export async function test_api_admin_force_cancel_override_seller_rejection(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin setup
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  // 2. Seller setup
  const sellerConnection: api.IConnection = { host: connection.host };
  const seller = await authorize_seller_join(sellerConnection, {});
  // 3. Admin approves the seller
  await api.functional.shoppingMall.admin.sellers.approve(adminConnection, {
    sellerId: seller.id,
  });
  // 4. Seller creates a product
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    {},
  );
  typia.assert(product);
  // 5. Seller creates a variant for the product
  const variant =
    await generate_random_shopping_mall_seller_products_variants_create(
      sellerConnection,
      { params: { productId: product.id } },
    );
  typia.assert(variant);
  // 6. Seller adds stock to the variant
  await generate_random_shopping_mall_seller_products_variants_inventory_records_create(
    sellerConnection,
    {
      params: { productId: product.id, variantId: variant.id },
      body: { quantity_change: 10, reason: "Initial stock" },
    },
  );
  // 7. Customer setup
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  // 8. Customer adds the variant to cart
  await generate_random_shopping_mall_customer_cart_items_create(
    customerConnection,
    {
      body: {
        productVariantId: variant.id,
        quantity: 1,
      },
    },
  );
  // 9. Customer places an order
  const order = await generate_random_shopping_mall_customer_orders_create(
    customerConnection,
    {
      body: {
        items: [{ variant_id: variant.id, quantity: 1 }],
      },
    },
  );
  typia.assert(order);
  const orderItem = order.items[0];
  typia.assert(orderItem);
  // 10. Customer submits a cancellation request
  const cancellationRequest =
    await generate_random_shopping_mall_customer_order_items_cancellation_requests_create(
      customerConnection,
      {
        params: { itemId: orderItem.id },
        body: { reason: "Changed my mind about this purchase" },
      },
    );
  typia.assert(cancellationRequest);
  // 11. Seller rejects the cancellation request
  const rejectedRequest =
    await api.functional.shoppingMall.seller.cancellation_requests.update(
      sellerConnection,
      {
        requestId: cancellationRequest.id,
        body: {
          status: "rejected",
        } satisfies IShoppingMallCancellationRequest.IUpdate,
      },
    );
  typia.assert(rejectedRequest);
  TestValidator.equals(
    "seller rejection sets status to rejected",
    rejectedRequest.status,
    "rejected",
  );
  // 12. Admin force-cancels the order item, overriding the seller's rejection
  const forceCancelReason =
    "Overriding seller rejection — customer complaint validated";
  const cancelledItem =
    await api.functional.shoppingMall.admin.order_items.force_cancel.forceCancel(
      adminConnection,
      {
        itemId: orderItem.id,
        body: {
          reason: forceCancelReason,
        } satisfies IShoppingMallOrderItem.IForceCancel,
      },
    );
  typia.assert(cancelledItem);
  // Validate: order item status is now "cancelled"
  TestValidator.equals(
    "force-cancelled item has status cancelled",
    cancelledItem.status,
    "cancelled",
  );
  // Validate: the cancellation request was updated from "rejected" to "approved"
  TestValidator.predicate(
    "cancellation request overridden to approved status",
    cancelledItem.cancellationRequests.some((req) => req.status === "approved"),
  );
}
