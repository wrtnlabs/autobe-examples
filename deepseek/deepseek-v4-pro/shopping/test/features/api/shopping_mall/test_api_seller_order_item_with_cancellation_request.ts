export async function test_api_seller_order_item_with_cancellation_request(
  connection: api.IConnection,
): Promise<void> {
  // -----------------------------------------------------------------------
  // 1. Seller registration and authentication
  // -----------------------------------------------------------------------
  const sellerEmail = typia.random<string & tags.Format<"email">>();
  const sellerPassword = RandomGenerator.alphaNumeric(16);
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {
    body: { email: sellerEmail, password: sellerPassword },
  });
  // -----------------------------------------------------------------------
  // 2. Seller creates a product
  // -----------------------------------------------------------------------
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    {},
  );
  typia.assert(product);
  // -----------------------------------------------------------------------
  // 3. Seller creates a variant with stock
  // -----------------------------------------------------------------------
  const variant =
    await generate_random_shopping_mall_seller_products_variants_create(
      sellerConnection,
      { params: { productId: product.id } },
    );
  typia.assert(variant);
  await generate_random_shopping_mall_seller_products_variants_inventory_records_create(
    sellerConnection,
    {
      params: { productId: product.id, variantId: variant.id },
      body: {
        quantity_change: 10 satisfies number as number,
        reason: "Initial stock",
      },
    },
  );
  // -----------------------------------------------------------------------
  // 4. Customer registration and authentication
  // -----------------------------------------------------------------------
  const customerEmail = typia.random<string & tags.Format<"email">>();
  const customerPassword = RandomGenerator.alphaNumeric(16);
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: { email: customerEmail, password: customerPassword },
  });
  // -----------------------------------------------------------------------
  // 5. Customer adds variant to cart
  // -----------------------------------------------------------------------
  await generate_random_shopping_mall_customer_cart_items_create(
    customerConnection,
    { body: { productVariantId: variant.id, quantity: 1 } },
  );
  // -----------------------------------------------------------------------
  // 6. Customer places order — order item created in "paid" status
  // -----------------------------------------------------------------------
  const order = await generate_random_shopping_mall_customer_orders_create(
    customerConnection,
    {
      body: {
        items: [{ variant_id: variant.id, quantity: 1 }],
      },
    },
  );
  typia.assert(order);
  const orderItem = order.items[0];
  // -----------------------------------------------------------------------
  // 7. Customer submits cancellation request for the order item
  // -----------------------------------------------------------------------
  const cancellationReason = "Changed mind about the purchase";
  await generate_random_shopping_mall_customer_order_items_cancellation_requests_create(
    customerConnection,
    {
      params: { itemId: orderItem.id },
      body: { reason: cancellationReason },
    },
  );
  // -----------------------------------------------------------------------
  // 8. Seller re-authenticates (fresh connection) and views order item detail
  // -----------------------------------------------------------------------
  const sellerViewConnection: api.IConnection = { host: connection.host };
  await authorize_seller_login(sellerViewConnection, {
    body: {
      email: sellerEmail,
      password: sellerPassword,
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  const orderItemDetail =
    await api.functional.shoppingMall.seller.order_items.at(
      sellerViewConnection,
      { itemId: orderItem.id },
    );
  typia.assert(orderItemDetail);
  // -----------------------------------------------------------------------
  // 9. Validations
  // -----------------------------------------------------------------------
  // Cancellation request appears with correct reason and "pending" status
  TestValidator.equals(
    "cancellation requests count",
    orderItemDetail.cancellationRequests.length,
    1,
  );
  TestValidator.equals(
    "cancellation request status",
    orderItemDetail.cancellationRequests[0].status,
    "pending",
  );
  TestValidator.equals(
    "cancellation request reason",
    orderItemDetail.cancellationRequests[0].reason,
    cancellationReason,
  );
  // Refund requests are empty
  TestValidator.equals(
    "refund requests count",
    orderItemDetail.refundRequests.length,
    0,
  );
  // Snapshots are present (captured at order placement time)
  TestValidator.predicate(
    "product snapshot exists",
    orderItemDetail.productSnapshot !== null,
  );
  TestValidator.predicate(
    "variant snapshot exists",
    orderItemDetail.variantSnapshot !== null,
  );
  TestValidator.predicate(
    "seller snapshot exists",
    orderItemDetail.sellerSnapshot !== null,
  );
}
