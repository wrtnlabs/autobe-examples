/**
 * Test that an administrator can force-refund a paid order item, bypassing the normal refund workflow.
 *
 * Validates that the force-refund operation directly transitions an order item from "paid" to "refunded" without requiring the item to be shipped, delivered, or have a customer refund request. This privileged admin operation bypasses the seller approval workflow and the 7-day post-delivery window entirely.
 *
 * The test also verifies that a refund request snapshot is created to record the force-refund action for audit purposes, and that the parent order's derived status is recalculated after the item's status change.
 *
 * 1. Administrator registers and creates a product category.
 * 2. Seller registers and is approved by the administrator.
 * 3. Seller creates a product under the category with a variant that has initial stock.
 * 4. Customer registers and places an order containing the variant, producing an order item in "paid" status.
 * 5. Administrator force-refunds the paid order item via the privileged endpoint.
 * 6. Validates the item status changes directly to "refunded" and a refund request snapshot is created.
 */
export async function test_api_force_refund_paid_item_bypasses_workflow(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin setup
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  // 2. Seller setup
  const sellerConnection: api.IConnection = { host: connection.host };
  const seller = await authorize_seller_join(sellerConnection, {});
  // 3. Admin approves seller
  const approvedSeller =
    await api.functional.shoppingMall.admin.sellers.approve(adminConnection, {
      sellerId: seller.id,
    });
  typia.assert(approvedSeller);
  TestValidator.equals(
    "seller is approved",
    approvedSeller.approval_status,
    "approved",
  );
  // 4. Admin creates category
  const category = await generate_random_shopping_mall_admin_categories_create(
    adminConnection,
    {},
  );
  typia.assert(category);
  // 5. Seller creates product under the category
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        shopping_mall_category_id: category.id,
      },
    },
  );
  typia.assert(product);
  // 6. Seller creates variant with initial stock
  const variant =
    await generate_random_shopping_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
        body: {
          initialStockQuantity: 10,
        },
      },
    );
  typia.assert(variant);
  // 7. Customer setup
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  // 8. Customer places order with the variant
  const order = await generate_random_shopping_mall_customer_orders_create(
    customerConnection,
    {
      body: {
        items: [
          {
            variant_id: variant.id,
            quantity: 1,
          },
        ],
      },
    },
  );
  typia.assert(order);
  const orderItem = order.items[0];
  TestValidator.equals("initial item status is paid", orderItem.status, "paid");
  // 9. Admin force-refunds the paid order item, bypassing the normal workflow
  const refundedItem =
    await api.functional.shoppingMall.admin.order_items.force_refund.forceRefund(
      adminConnection,
      {
        itemId: orderItem.id,
      },
    );
  typia.assert(refundedItem);
  // 10. Validate force-refund results
  TestValidator.equals(
    "item status changed directly from paid to refunded",
    refundedItem.status,
    "refunded",
  );
  TestValidator.predicate(
    "refund request snapshot created for force-refund audit trail",
    refundedItem.refundRequests.length > 0,
  );
}
