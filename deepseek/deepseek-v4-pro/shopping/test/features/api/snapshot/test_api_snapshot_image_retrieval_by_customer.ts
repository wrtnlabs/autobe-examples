/**
 * Test that a customer retrieves a specific product snapshot image from their own order.
 *
 * Validates the complete purchase-to-snapshot flow: an administrator creates a category,
 * a seller registers and creates a product with a variant and inventory stock, then
 * the customer places an order. The order placement atomically captures product, variant,
 * and seller snapshots including all product images at purchase time.
 *
 * The customer then retrieves a specific snapshot image by its ID scoped within the
 * order item's product snapshot. The response must include the frozen image URL and
 * display order, confirming the immutable snapshot data matches exactly what was
 * captured at purchase time and remains accurate even if original images change later.
 *
 * 1. Administrator registers via authorize_admin_join and creates a category.
 * 2. Seller registers via authorize_seller_join, creates a product under the category.
 * 3. Seller creates a variant with option values and adds inventory stock.
 * 4. Customer registers via authorize_customer_join and places an order for the variant.
 * 5. Customer extracts the first snapshot image from the order item's product snapshot.
 * 6. Customer retrieves the snapshot image via the at endpoint with itemId and imageId.
 * 7. Validates the retrieved imageUrl and displayOrder match the snapshot data.
 */
export async function test_api_snapshot_image_retrieval_by_customer(
  connection: api.IConnection,
): Promise<void> {
  // 1. Administrator registers and creates category
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  const category = await generate_random_shopping_mall_admin_categories_create(
    adminConnection,
    {},
  );
  typia.assert(category);
  // 2. Seller registers
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {});
  // 3. Seller creates product
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        shopping_mall_category_id: category.id,
      },
    },
  );
  typia.assert(product);
  // 4. Seller creates variant
  const variant =
    await generate_random_shopping_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
      },
    );
  typia.assert(variant);
  // 5. Seller adds inventory
  await generate_random_shopping_mall_seller_products_variants_inventory_records_create(
    sellerConnection,
    {
      params: { productId: product.id, variantId: variant.id },
    },
  );
  // 6. Customer registers
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  // 7. Customer places order
  const order = await generate_random_shopping_mall_customer_orders_create(
    customerConnection,
    {
      body: {
        items: [
          {
            variant_id: variant.id,
            quantity: 1,
          } satisfies IShoppingMallOrderItem.ICreate,
        ],
      },
    },
  );
  typia.assert(order);
  // 8. Extract order item and its product snapshot images
  const orderItem = order.items[0];
  typia.assert(orderItem);
  const productSnapshot = typia.assert(orderItem.productSnapshot!);
  const snapshotImages = productSnapshot.productSnapshotImages;
  TestValidator.predicate(
    "snapshot images should not be empty",
    snapshotImages.length > 0,
  );
  // 9. Retrieve the first snapshot image via the API
  const expectedImage = snapshotImages[0];
  const retrievedImage =
    await api.functional.shoppingMall.customer.order_items.product_snapshot.images.at(
      customerConnection,
      {
        itemId: orderItem.id,
        imageId: expectedImage.id,
      },
    );
  typia.assert(retrievedImage);
  // 10. Validate frozen snapshot image data
  TestValidator.equals(
    "snapshot image URL matches frozen value",
    retrievedImage.imageUrl,
    expectedImage.imageUrl,
  );
  TestValidator.equals(
    "snapshot image display order matches frozen value",
    retrievedImage.displayOrder,
    expectedImage.displayOrder,
  );
}
