/**
 * Test that a customer cannot remove a cart item belonging to a different customer.
 *
 * Validates strict cart item ownership enforcement: Customer A adds a product
 * variant to their cart creating a cart item, then Customer B (a separate
 * authenticated customer) attempts to delete Customer A's cart item. The system
 * must reject the unauthorized deletion attempt with a 403 Forbidden error,
 * confirming that the cart item's customer ID must match the authenticated
 * customer's ID for the delete operation.
 *
 * Cross-customer cart item manipulation is properly blocked at the authorization
 * layer, preventing Customer B from interfering with Customer A's shopping cart
 * contents.
 *
 * 1. Administrator creates a product category for product organization.
 * 2. Seller registers, creates a product, adds a variant with inventory stock.
 * 3. Customer A registers and adds the variant to their cart.
 * 4. Customer B registers separately.
 * 5. Customer B attempts to delete Customer A's cart item — rejected with 403.
 */
export async function test_api_cart_item_remove_other_customer_forbidden(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin setup
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  const category = await generate_random_shopping_mall_admin_categories_create(
    adminConnection,
    {},
  );
  typia.assert(category);
  // 2. Seller setup
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {});
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    { body: { shopping_mall_category_id: category.id } },
  );
  typia.assert(product);
  const variant =
    await generate_random_shopping_mall_seller_products_variants_create(
      sellerConnection,
      { params: { productId: product.id } },
    );
  typia.assert(variant);
  await generate_random_shopping_mall_seller_products_variants_inventory_records_create(
    sellerConnection,
    { params: { productId: product.id, variantId: variant.id } },
  );
  // 3. Customer A adds variant to cart
  const customerAConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerAConnection, {});
  const cartItem =
    await generate_random_shopping_mall_customer_cart_items_create(
      customerAConnection,
      { body: { productVariantId: variant.id } },
    );
  typia.assert(cartItem);
  // 4. Customer B registers separately
  const customerBConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerBConnection, {});
  // 5. Customer B attempts to delete Customer A's cart item — must be rejected
  await TestValidator.error(
    "Customer B cannot delete another customer's cart item",
    async () => {
      await api.functional.shoppingMall.customer.cart_items.erase(
        customerBConnection,
        { cartItemId: cartItem.id },
      );
    },
  );
}
