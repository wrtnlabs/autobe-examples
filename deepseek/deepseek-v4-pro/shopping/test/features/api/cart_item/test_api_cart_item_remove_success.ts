/**
 * Test successful cart item removal by an authenticated customer.
 *
 * Verifies that a customer can permanently delete their own cart item from the shopping cart. The DELETE endpoint returns 204 No Content on success with no response body, confirming the item is removed from the database.
 *
 * After deletion, the same product variant can be re-added to the cart as a fresh entry, confirming that the unique constraint on (customer_id, product_variant_id) only prevents duplicate active entries and does not block re-addition after deletion.
 *
 * 1. Administrator registers and creates a product category.
 * 2. Seller registers, creates a product under the category, adds a variant with SKU code, and restocks inventory.
 * 3. Customer registers and adds the product variant to their shopping cart.
 * 4. Customer deletes the cart item — deletion succeeds without error.
 * 5. Customer re-adds the same product variant to the cart — addition succeeds, proving the unique constraint does not block re-addition after deletion.
 */
export async function test_api_cart_item_remove_success(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin setup
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  const category = await generate_random_shopping_mall_admin_categories_create(
    adminConnection,
    {},
  );
  typia.assert(category);
  // 2. Seller setup
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {});
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    { body: { shopping_mall_category_id: category.id } },
  );
  typia.assert(product);
  const variant =
    await generate_random_shopping_mall_seller_products_variants_create(
      sellerConnection,
      { params: { productId: product.id } },
    );
  typia.assert(variant);
  const inventoryRecord =
    await generate_random_shopping_mall_seller_products_variants_inventory_records_create(
      sellerConnection,
      { params: { productId: product.id, variantId: variant.id } },
    );
  typia.assert(inventoryRecord);
  // 3. Customer setup
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  const cartItem =
    await generate_random_shopping_mall_customer_cart_items_create(
      customerConnection,
      { body: { productVariantId: variant.id } },
    );
  typia.assert(cartItem);
  // 4. Delete cart item — permanent removal with 204 No Content
  await api.functional.shoppingMall.customer.cart_items.erase(
    customerConnection,
    { cartItemId: cartItem.id },
  );
  // 5. Re-add same variant after deletion — proves unique constraint does not block re-addition
  const newCartItem =
    await generate_random_shopping_mall_customer_cart_items_create(
      customerConnection,
      { body: { productVariantId: variant.id } },
    );
  typia.assert(newCartItem);
}
