/**
 * Verify that a customer cannot modify another customer's cart item quantity.
 *
 * Cart items are strictly scoped to the owning customer. This test validates
 * that when Customer B attempts to update a cart item created by Customer A,
 * the server rejects the request with HTTP 403 Forbidden because the cart
 * item's owning customer ID does not match Customer B's authenticated identity.
 *
 * 1. Administrator creates a product category.
 * 2. Seller registers, creates a product, variant, and records inventory stock.
 * 3. Customer A joins and adds the variant to their cart.
 * 4. Customer B joins (different customer).
 * 5. Customer B attempts to update Customer A's cart item quantity.
 * 6. Validates the server returns HTTP 403 Forbidden.
 */
export async function test_api_cart_item_quantity_update_other_customer_forbidden(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin setup - create category
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  const category = await generate_random_shopping_mall_admin_categories_create(
    adminConnection,
    { body: {} },
  );
  typia.assert(category);
  // 2. Seller setup - create product, variant, and stock
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {});
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    { body: { shopping_mall_category_id: category.id } },
  );
  typia.assert(product);
  const variant =
    await generate_random_shopping_mall_seller_products_variants_create(
      sellerConnection,
      { params: { productId: product.id } },
    );
  typia.assert(variant);
  const quantityChange = 100 satisfies number as number;
  await generate_random_shopping_mall_seller_products_variants_inventory_records_create(
    sellerConnection,
    {
      params: { productId: product.id, variantId: variant.id },
      body: { quantity_change: quantityChange },
    },
  );
  // 3. Customer A setup - add variant to cart
  const customerAConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerAConnection, {});
  const cartItem =
    await generate_random_shopping_mall_customer_cart_items_create(
      customerAConnection,
      {
        body: {
          productVariantId: variant.id,
          quantity: 1 satisfies number as number,
        },
      },
    );
  typia.assert(cartItem);
  // 4. Customer B setup - different customer
  const customerBConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerBConnection, {});
  // 5. Customer B attempts to update Customer A's cart item → 403 Forbidden
  await TestValidator.httpError(
    "other customer's cart item update forbidden",
    403,
    async () => {
      await api.functional.shoppingMall.customer.cart_items.update(
        customerBConnection,
        {
          cartItemId: cartItem.id,
          body: { quantity: 5 } satisfies IShoppingMallCartItem.IUpdate,
        },
      );
    },
  );
}
