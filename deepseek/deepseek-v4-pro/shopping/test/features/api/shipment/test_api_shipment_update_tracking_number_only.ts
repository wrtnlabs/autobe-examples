/**
 * Test updating only the tracking number of an existing shipment while leaving the carrier name unchanged.
 *
 * Validates that carrier_name and tracking_number can be updated independently — at least one of the two fields must be provided when calling the shipment update endpoint. The test establishes a full e-commerce dependency chain: administrator creates a category, a seller registers and receives approval, the seller creates a product with a stock-holding variant, a customer places an order for that variant, and the seller creates a shipment for the paid order items.
 *
 * The critical validation occurs when the seller submits an update containing only a new tracking_number without providing a carrier_name. The response must show the updated tracking_number while the original carrier_name remains unchanged, confirming independent field update support.
 *
 * 1. Administrator joins, creates a product category.
 * 2. Seller joins and receives administrator approval.
 * 3. Seller creates a product under the category and a variant with initial stock.
 * 4. Customer joins and places an order for the variant.
 * 5. Seller creates a shipment for the paid order items.
 * 6. Seller updates the shipment with only a new tracking_number, omitting carrier_name.
 * 7. Validates the tracking_number changed to the new value and carrier_name remained as originally set.
 */
export async function test_api_shipment_update_tracking_number_only(
  connection: api.IConnection,
): Promise<void> {
  // 1. Administrator setup
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  // 2. Create category
  const category = await generate_random_shopping_mall_admin_categories_create(
    adminConnection,
    {},
  );
  typia.assert(category);
  // 3. Seller registration and approval
  const sellerConnection: api.IConnection = { host: connection.host };
  const seller = await authorize_seller_join(sellerConnection, {});
  await api.functional.shoppingMall.admin.sellers.approve(adminConnection, {
    sellerId: seller.id,
  });
  // 4. Seller creates product
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    {
      body: { shopping_mall_category_id: category.id },
    },
  );
  typia.assert(product);
  // 5. Seller creates variant with stock
  const variant =
    await generate_random_shopping_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
        body: {
          initialStockQuantity: typia.random<
            number & tags.Type<"int32"> & tags.Minimum<1> & tags.Maximum<100>
          >(),
        },
      },
    );
  typia.assert(variant);
  // 6. Customer registration
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  // 7. Customer places order
  const order = await generate_random_shopping_mall_customer_orders_create(
    customerConnection,
    {
      body: {
        items: [
          {
            variant_id: variant.id,
            quantity: 1,
          },
        ],
      },
    },
  );
  typia.assert(order);
  // 8. Seller creates shipment for the paid order items
  const sellerOrderItem = order.items[0];
  const shipment =
    await generate_random_shopping_mall_seller_orders_shipments_create(
      sellerConnection,
      {
        params: { orderId: order.id },
        body: { orderItemIds: [sellerOrderItem.id] },
      },
    );
  typia.assert(shipment);
  // Capture original values before update
  const originalCarrierName = shipment.carrier_name;
  // 9. Seller updates only the tracking number
  const newTrackingNumber = RandomGenerator.alphaNumeric(16);
  const updatedShipment =
    await api.functional.shoppingMall.seller.shipments.update(
      sellerConnection,
      {
        shipmentId: shipment.id,
        body: {
          tracking_number: newTrackingNumber,
        } satisfies IShoppingMallShipment.IUpdate,
      },
    );
  typia.assert(updatedShipment);
  // 10. Validate independent field update
  TestValidator.equals(
    "tracking number updated to new value",
    updatedShipment.tracking_number,
    newTrackingNumber,
  );
  TestValidator.equals(
    "carrier name unchanged after tracking-only update",
    updatedShipment.carrier_name,
    originalCarrierName,
  );
}
