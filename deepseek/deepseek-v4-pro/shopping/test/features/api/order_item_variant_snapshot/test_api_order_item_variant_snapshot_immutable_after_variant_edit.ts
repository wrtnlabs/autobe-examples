/**
 * Test that variant snapshot remains immutable after seller edits the variant price.
 *
 * Validates the core immutability principle of order item variant snapshots: the snapshot captures the variant's price at the moment of order placement and survives independently of later modifications. The seller creates a variant with an original price, a customer places an order containing it, then the seller edits the variant to a new price. The test verifies that the snapshot's price matches the original price, not the edited price.
 *
 * 1. Seller registers, creates a product, and adds a variant with a specific original price.
 * 2. Seller adds inventory stock to make the variant purchasable.
 * 3. Customer registers, adds the variant to cart, and places an order.
 * 4. Seller edits the variant price to a new, different value.
 * 5. Seller retrieves the variant snapshot for the order item via the dedicated endpoint.
 * 6. Validates snapshot price equals the original purchase-time price and differs from the edited price.
 */
export async function test_api_order_item_variant_snapshot_immutable_after_variant_edit(
  connection: api.IConnection,
): Promise<void> {
  // 1. Seller setup
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {});
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    { body: {} },
  );
  typia.assert(product);
  const originalPrice = typia.random<
    number & tags.Type<"uint32"> & tags.Minimum<1000>
  >();
  const variant =
    await generate_random_shopping_mall_seller_products_variants_create(
      sellerConnection,
      {
        body: { price: originalPrice },
        params: { productId: product.id },
      },
    );
  typia.assert(variant);
  await generate_random_shopping_mall_seller_products_variants_inventory_records_create(
    sellerConnection,
    {
      params: { productId: product.id, variantId: variant.id },
    },
  );
  // 2. Customer purchase
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  await generate_random_shopping_mall_customer_cart_items_create(
    customerConnection,
    { body: { productVariantId: variant.id, quantity: 1 } },
  );
  const order = await generate_random_shopping_mall_customer_orders_create(
    customerConnection,
    {
      body: {
        items: [{ variant_id: variant.id, quantity: 1 }],
      },
    },
  );
  typia.assert(order);
  const orderItem = order.items[0];
  // 3. Seller edits variant price
  const newPrice = (originalPrice + 5000) satisfies number as number;
  await api.functional.shoppingMall.seller.products.variants.update(
    sellerConnection,
    {
      productId: product.id,
      variantId: variant.id,
      body: { price: newPrice },
    },
  );
  // 4. Retrieve variant snapshot via dedicated endpoint
  const snapshot =
    await api.functional.shoppingMall.seller.order_items.variant_snapshot.at(
      sellerConnection,
      { itemId: orderItem.id },
    );
  typia.assert(snapshot);
  // 5. Validate snapshot immutability
  TestValidator.equals(
    "snapshot price equals original purchase-time price",
    snapshot.price,
    originalPrice,
  );
  TestValidator.notEquals(
    "snapshot price differs from edited current price",
    snapshot.price,
    newPrice,
  );
}
