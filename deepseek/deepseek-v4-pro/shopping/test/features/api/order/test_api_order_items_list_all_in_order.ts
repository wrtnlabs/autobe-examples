/**
 * Test listing all order items in an order without status filtering.
 *
 * Verifies that a customer can retrieve all order items within their own order after successful checkout. The test places an order with a single item, then calls the order items listing endpoint without any status filter to retrieve all items.
 *
 * Validates that the pagination metadata correctly reflects a single page with all items, and that each returned item has its status set to "paid", the order reference correctly points back to the parent order, and the frozen price and quantity are non-negative.
 *
 * 1. Administrator creates a product category.
 * 2. Seller joins, creates a product with a variant, and adds inventory stock.
 * 3. Customer joins and places an order with the variant.
 * 4. Customer lists all order items in the order without a status filter.
 * 5. Validates pagination metadata and item-level business properties.
 */
export async function test_api_order_items_list_all_in_order(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin setup
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  const category = await generate_random_shopping_mall_admin_categories_create(
    adminConnection,
    {},
  );
  typia.assert(category);
  // 2. Seller setup
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {});
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        shopping_mall_category_id: category.id,
      },
    },
  );
  typia.assert(product);
  const variant =
    await generate_random_shopping_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
      },
    );
  typia.assert(variant);
  await generate_random_shopping_mall_seller_products_variants_inventory_records_create(
    sellerConnection,
    {
      params: { productId: product.id, variantId: variant.id },
    },
  );
  // 3. Customer setup
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  // 4. Place order
  const order = await generate_random_shopping_mall_customer_orders_create(
    customerConnection,
    {
      body: {
        items: [
          {
            variant_id: variant.id,
            quantity: 1,
          },
        ],
      },
    },
  );
  typia.assert(order);
  // 5. List all order items without status filter
  const page = await api.functional.shoppingMall.customer.orders.items.index(
    customerConnection,
    {
      orderId: order.id,
      body: {} satisfies IShoppingMallOrderItem.IRequest,
    },
  );
  typia.assert(page);
  // 6. Validate pagination
  TestValidator.equals("current page is 1", page.pagination.current, 1);
  TestValidator.equals(
    "records count matches items",
    page.pagination.records,
    order.items.length,
  );
  TestValidator.equals("pages is 1", page.pagination.pages, 1);
  TestValidator.equals(
    "data length equals records",
    page.data.length,
    order.items.length,
  );
  // 7. Validate each item
  for (const item of page.data) {
    TestValidator.equals("status is paid", item.status, "paid");
    TestValidator.equals("order ref matches", item.order.id, order.id);
    TestValidator.predicate("has non-negative price", item.price >= 0);
    TestValidator.predicate("has positive quantity", item.quantity >= 1);
  }
}
