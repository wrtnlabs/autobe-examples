/**
 * Verify that querying a non-existent order code returns a 404 Not Found error.
 *
 * Tests the seller order detail endpoint's error handling when an authenticated
 * seller requests an order that does not exist in the system. The seller first
 * registers and authenticates, then queries with a randomly generated,
 * non-existent order code.
 *
 * The test confirms that the API properly rejects the request with an error
 * rather than returning an empty response or succeeding unexpectedly. This
 * ensures that sellers receive clear feedback when attempting to access
 * orders that have never been created.
 *
 * 1. Seller registers and authenticates via authorize_seller_join.
 * 2. A random non-existent order code is generated.
 * 3. The seller queries the order detail endpoint with the invalid code.
 * 4. The API throws an error, confirming proper 404 handling.
 */
export async function test_api_seller_order_not_found(
  connection: api.IConnection,
): Promise<void> {
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {});
  const nonExistentOrderCode = typia.random<string>();
  await TestValidator.error("non-existent order code returns 404", async () => {
    await api.functional.shoppingMall.seller.orders.at(sellerConnection, {
      orderCode: nonExistentOrderCode,
    });
  });
}
