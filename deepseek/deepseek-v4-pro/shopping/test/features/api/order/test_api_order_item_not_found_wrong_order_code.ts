/**
 * Test that an order item cannot be retrieved using a different order's code.
 *
 * Validates cross-order item isolation: an order item belonging to one order must not
 * be accessible through another order's identifier. This ensures the item-to-order
 * relationship is strictly enforced at the API level.
 *
 * 1. Administrator creates a product category.
 * 2. Seller joins, creates a product under the category, adds a variant with SKU code,
 *    and restocks sufficient inventory for two separate orders.
 * 3. Customer registers and places two separate orders (Order A and Order B), each
 *    purchasing a quantity of the same variant.
 * 4. Customer attempts to retrieve an item belonging to Order A using Order B's
 *    orderCode — the system rejects the request with an error because the item is not
 *    associated with the provided order code.
 */
export async function test_api_order_item_not_found_wrong_order_code(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin setup — create category
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  const category = await generate_random_shopping_mall_admin_categories_create(
    adminConnection,
    {},
  );
  typia.assert(category);
  // 2. Seller setup — join, create product, variant, add inventory
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {});
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        shopping_mall_category_id: category.id,
      },
    },
  );
  typia.assert(product);
  const variant =
    await generate_random_shopping_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
      },
    );
  typia.assert(variant);
  await generate_random_shopping_mall_seller_products_variants_inventory_records_create(
    sellerConnection,
    {
      params: { productId: product.id, variantId: variant.id },
      body: { quantity_change: 10, reason: "Initial stock for test orders" },
    },
  );
  // 3. Customer setup — register and place two orders
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  const orderA = await generate_random_shopping_mall_customer_orders_create(
    customerConnection,
    {
      body: {
        items: [{ variant_id: variant.id, quantity: 2 }],
      },
    },
  );
  typia.assert(orderA);
  const orderB = await generate_random_shopping_mall_customer_orders_create(
    customerConnection,
    {
      body: {
        items: [{ variant_id: variant.id, quantity: 3 }],
      },
    },
  );
  typia.assert(orderB);
  // 4. Attempt cross-order access — item from Order A using Order B's code
  const itemA = orderA.items[0];
  typia.assertGuard(itemA);
  await TestValidator.error(
    "item from Order A not found when using Order B's orderCode",
    async () => {
      await api.functional.shoppingMall.customer.orders.items.at(
        customerConnection,
        {
          orderCode: orderB.code,
          itemId: itemA.id,
        },
      );
    },
  );
}
