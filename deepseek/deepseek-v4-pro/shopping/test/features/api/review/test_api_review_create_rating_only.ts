/**
 * Test that a customer can create a review with only a star rating and no text content.
 *
 * Validates the business rule that the content field is optional when writing a review — a rating-only review with a 3-star rating and no written feedback is created successfully. The test traces the complete purchase-to-delivery lifecycle to establish the prerequisite delivered order item before creating the review.
 *
 * Special attention is given to verifying that the content field is null in the response, the snapshots array is empty for a newly created review, and deleted_at remains null. All nested relation fields — customer with display name, product summary, order summary, and order item summary — are populated.
 *
 * 1. Administrator registers and creates a product category.
 * 2. Seller registers, is approved by the administrator, creates a product under the category, adds a variant with a unique SKU, and records initial inventory stock.
 * 3. Customer registers and places an order containing the variant with a shipping address.
 * 4. Seller creates a shipment for the paid order item with carrier and tracking information.
 * 5. Customer confirms delivery of the shipment, transitioning the order item to delivered status.
 * 6. Customer creates a review with rating 3 and no content field.
 * 7. Validates review content is null, snapshots is empty, and deleted_at is null.
 */
export async function test_api_review_create_rating_only(
  connection: api.IConnection,
): Promise<void> {
  // 1. Administrator creates a category
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  const category = await generate_random_shopping_mall_admin_categories_create(
    adminConnection,
    {},
  );
  typia.assert(category);
  // 2. Seller registers and is approved
  const sellerConnection: api.IConnection = { host: connection.host };
  const seller = await authorize_seller_join(sellerConnection, {});
  await api.functional.shoppingMall.admin.sellers.approve(adminConnection, {
    sellerId: seller.id,
  });
  // 3. Seller creates product
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        shopping_mall_category_id: category.id,
      },
    },
  );
  typia.assert(product);
  // 4. Seller creates variant
  const variant =
    await generate_random_shopping_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
      },
    );
  typia.assert(variant);
  // 5. Seller adds inventory stock
  const inventoryRecord =
    await generate_random_shopping_mall_seller_products_variants_inventory_records_create(
      sellerConnection,
      {
        params: { productId: product.id, variantId: variant.id },
        body: {
          quantity_change: 10,
          reason: "Initial stock for review test",
        },
      },
    );
  typia.assert(inventoryRecord);
  // 6. Customer registers and places an order
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  const order = await generate_random_shopping_mall_customer_orders_create(
    customerConnection,
    {
      body: {
        items: [
          {
            variant_id: variant.id,
            quantity: 1,
          },
        ],
      },
    },
  );
  typia.assert(order);
  const orderItem = order.items[0];
  // 7. Seller creates shipment
  const shipment =
    await generate_random_shopping_mall_seller_orders_shipments_create(
      sellerConnection,
      {
        params: { orderId: order.id },
        body: {
          orderItemIds: [orderItem.id],
        },
      },
    );
  typia.assert(shipment);
  // 8. Customer confirms delivery
  await api.functional.shoppingMall.customer.shipments.confirm_delivery.confirmDelivery(
    customerConnection,
    {
      shipmentId: shipment.id,
    },
  );
  // 9. Customer creates rating-only review (no content)
  const review = await generate_random_shopping_mall_customer_reviews_create(
    customerConnection,
    {
      body: {
        shopping_mall_product_id: product.id,
        shopping_mall_order_id: order.id,
        shopping_mall_order_item_id: orderItem.id,
        rating: 3,
      },
    },
  );
  typia.assert(review);
  // 10. Validate review
  TestValidator.equals("rating matches input", review.rating, 3);
  TestValidator.equals("content is null when omitted", review.content, null);
  TestValidator.equals(
    "snapshots empty for new review",
    review.snapshots.length,
    0,
  );
  TestValidator.equals(
    "deleted_at is null for active review",
    review.deleted_at,
    null,
  );
}
