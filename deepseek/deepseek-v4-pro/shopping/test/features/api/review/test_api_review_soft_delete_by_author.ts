/**
 * Test that an authenticated customer can soft-delete their own review.
 *
 * Validates the review soft-deletion workflow: a customer writes a review for
 * a product they've purchased, then soft-deletes it. The deletion must succeed,
 * and subsequent deletion attempts must be rejected with 409 Conflict to
 * enforce idempotency.
 *
 * The review data — including rating, content, and creation timestamp — is
 * preserved server-side for audit purposes. All associated review snapshots
 * remain intact. The review is excluded from product detail page display and
 * from average rating calculations after soft deletion.
 *
 * 1. Administrator creates a product category for product listing.
 * 2. Seller registers, creates a product, adds a purchasable variant, and stocks inventory.
 * 3. Customer registers, places an order, and writes a review for the purchased product.
 * 4. Customer soft-deletes the review — the operation succeeds.
 * 5. Customer attempts to delete the same review again — 409 Conflict rejected.
 */
export async function test_api_review_soft_delete_by_author(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin setup — create category
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  const category = await generate_random_shopping_mall_admin_categories_create(
    adminConnection,
    {},
  );
  typia.assert(category);
  // 2. Seller setup — create product, variant, inventory
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {});
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    { body: { shopping_mall_category_id: category.id } },
  );
  typia.assert(product);
  const variant =
    await generate_random_shopping_mall_seller_products_variants_create(
      sellerConnection,
      { params: { productId: product.id } },
    );
  typia.assert(variant);
  await generate_random_shopping_mall_seller_products_variants_inventory_records_create(
    sellerConnection,
    { params: { productId: product.id, variantId: variant.id } },
  );
  // 3. Customer setup — place order, write review
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  const order = await generate_random_shopping_mall_customer_orders_create(
    customerConnection,
    {
      body: {
        items: [{ variant_id: variant.id, quantity: 1 }],
      },
    },
  );
  typia.assert(order);
  const review = await generate_random_shopping_mall_customer_reviews_create(
    customerConnection,
    {
      body: {
        shopping_mall_product_id: product.id,
        shopping_mall_order_id: order.id,
        shopping_mall_order_item_id: order.items[0].id,
        rating: 5,
      },
    },
  );
  typia.assert(review);
  // 4. Soft-delete the review
  await api.functional.shoppingMall.customer.reviews.erase(customerConnection, {
    reviewId: review.id,
  });
  // 5. Verify idempotency — already deleted review cannot be deleted again
  await TestValidator.httpError(
    "cannot delete an already soft-deleted review",
    409,
    async () => {
      await api.functional.shoppingMall.customer.reviews.erase(
        customerConnection,
        { reviewId: review.id },
      );
    },
  );
}
