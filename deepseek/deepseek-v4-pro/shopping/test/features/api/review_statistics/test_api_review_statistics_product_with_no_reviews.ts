/**
 * Verify that review statistics for a product with no reviews returns zero values.
 *
 * Confirms the endpoint correctly handles the empty-reviews case by returning
 * averageRating of 0 and totalCount of 0, distinguishing a product with no
 * reviews (200 with zero values) from a non-existent product (404).
 *
 * 1. Administrator creates a product category for the product to belong to.
 * 2. Seller registers and creates a product — newly created products have no
 *    reviews, so the review statistics should reflect this.
 * 3. Customer registers and queries the review-statistics endpoint for the
 *    product using the authenticated customer connection.
 * 4. Validates that both averageRating and totalCount are exactly 0, confirming
 *    the endpoint's empty-reviews behavior.
 */
export async function test_api_review_statistics_product_with_no_reviews(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin setup - create category
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  const category = await generate_random_shopping_mall_admin_categories_create(
    adminConnection,
    {},
  );
  typia.assert(category);
  // 2. Seller setup - create product with no reviews
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {});
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        shopping_mall_category_id: category.id,
      },
    },
  );
  typia.assert(product);
  // 3. Customer authenticates
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  // 4. Query review statistics
  const statistics =
    await api.functional.shoppingMall.customer.products.review_statistics.at(
      customerConnection,
      {
        productId: product.id,
      },
    );
  typia.assert(statistics);
  // 5. Validate zero values for product with no reviews
  TestValidator.equals("average rating", statistics.averageRating, 0);
  TestValidator.equals("total count", statistics.totalCount, 0);
}
