/**
 * Test that a seller can soft-delete their own product variant.
 *
 * Validates the complete variant deletion workflow: an administrator creates a category, a seller joins and creates a product under that category, the seller adds a variant with stock, then soft-deletes the variant. The test confirms the deletion succeeds by verifying the erase call returns void without throwing, indicating the variant was marked as soft-deleted with its inventory records hard-deleted.
 *
 * 1. Administrator registers and creates a product category.
 * 2. Seller registers, creates a product under the category.
 * 3. Seller creates a variant with SKU code, option values, and initial stock.
 * 4. Seller deletes the variant and verifies the operation succeeds.
 */
export async function test_api_variant_deletion_by_owning_seller(
  connection: api.IConnection,
) {
  // 1. Admin setup — create a category
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  const category = await generate_random_shopping_mall_admin_categories_create(
    adminConnection,
    {},
  );
  typia.assert(category);
  // 2. Seller setup — join and create a product
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {});
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        shopping_mall_category_id: category.id,
      },
    },
  );
  typia.assert(product);
  // 3. Create variant with initial stock
  const variant =
    await generate_random_shopping_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
        body: {
          initialStockQuantity: 100,
        },
      },
    );
  typia.assert(variant);
  // 4. Delete the variant
  await api.functional.shoppingMall.seller.products.variants.erase(
    sellerConnection,
    {
      productId: product.id,
      variantId: variant.id,
    },
  );
}
