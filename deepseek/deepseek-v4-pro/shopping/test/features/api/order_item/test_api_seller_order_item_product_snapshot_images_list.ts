export async function test_api_seller_order_item_product_snapshot_images_list(
  connection: api.IConnection,
): Promise<void> {
  // 1. Administrator setup
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  // 2. Seller registration
  const sellerConnection: api.IConnection = { host: connection.host };
  const seller = await authorize_seller_join(sellerConnection, {});
  // 3. Administrator approves the pending seller
  await api.functional.shoppingMall.admin.sellers.approve(adminConnection, {
    sellerId: seller.id,
  });
  // 4. Seller creates a product
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    {},
  );
  typia.assert(product);
  // 5. Seller uploads multiple product images
  const imageCount = 3;
  for (let i = 0; i < imageCount; i++) {
    const img =
      await generate_random_shopping_mall_seller_products_images_create(
        sellerConnection,
        { params: { productId: product.id } },
      );
    typia.assert(img);
  }
  // 6. Seller creates a variant
  const variant =
    await generate_random_shopping_mall_seller_products_variants_create(
      sellerConnection,
      { params: { productId: product.id } },
    );
  typia.assert(variant);
  // 7. Seller adds inventory stock
  await generate_random_shopping_mall_seller_products_variants_inventory_records_create(
    sellerConnection,
    {
      params: { productId: product.id, variantId: variant.id },
      body: { quantity_change: 100, reason: "Initial stock" },
    },
  );
  // 8. Customer registration
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  // 9. Customer adds variant to cart
  await generate_random_shopping_mall_customer_cart_items_create(
    customerConnection,
    { body: { productVariantId: variant.id, quantity: 1 } },
  );
  // 10. Customer places an order — triggers product snapshot creation
  const order = await generate_random_shopping_mall_customer_orders_create(
    customerConnection,
    {
      body: {
        items: [{ variant_id: variant.id, quantity: 1 }],
      },
    },
  );
  typia.assert(order);
  const orderItem = order.items[0];
  // 11. Seller lists product snapshot images
  const result =
    await api.functional.shoppingMall.seller.order_items.product_snapshot.images.index(
      sellerConnection,
      {
        itemId: orderItem.id,
        body: {},
      },
    );
  typia.assert(result);
  // 12. Validate pagination metadata
  TestValidator.equals("current page", result.pagination.current, 1);
  TestValidator.predicate("limit positive", result.pagination.limit > 0);
  TestValidator.equals("total records", result.pagination.records, imageCount);
  TestValidator.predicate("total pages positive", result.pagination.pages > 0);
  // 13. Validate data array
  TestValidator.equals("data length", result.data.length, imageCount);
  // 14. Validate each snapshot image has required fields
  for (const img of result.data) {
    TestValidator.predicate("image id is non-empty", img.id.length > 0);
    TestValidator.predicate("image url is non-empty", img.image_url.length > 0);
    TestValidator.predicate(
      "display_order is non-negative",
      img.display_order >= 0,
    );
  }
  // 15. Validate images sorted by display_order ascending
  for (let i = 1; i < result.data.length; i++) {
    TestValidator.predicate(
      "display_order ascending",
      result.data[i].display_order > result.data[i - 1].display_order,
    );
  }
}
