export async function test_api_product_snapshot_retrieve_after_product_deletion(
  connection: api.IConnection,
): Promise<void> {
  // 1. Administrator creates a category
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  const category = await generate_random_shopping_mall_admin_categories_create(
    adminConnection,
    {},
  );
  typia.assert(category);
  // 2. Seller registers and creates a product
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {});
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        shopping_mall_category_id: category.id,
      },
    },
  );
  typia.assert(product);
  // 3. Edit product to trigger snapshot creation (snapshot captures pre-edit state)
  const updatedProduct =
    await api.functional.shoppingMall.seller.products.update(sellerConnection, {
      productId: product.id,
      body: {
        name: RandomGenerator.paragraph({ sentences: 2 }),
        description: RandomGenerator.content({ paragraphs: 2 }),
        shopping_mall_category_id: category.id,
        base_price: typia.random<number & tags.Minimum<1>>(),
      } satisfies IShoppingMallProduct.IUpdate,
    });
  typia.assert(updatedProduct);
  // 4. Soft-delete the product
  await api.functional.shoppingMall.seller.products.erase(sellerConnection, {
    productId: product.id,
  });
  // 5. Retrieve the snapshot after product deletion
  const snapshotId = typia.random<string & tags.Format<"uuid">>();
  const snapshot =
    await api.functional.shoppingMall.seller.products.snapshots.at(
      sellerConnection,
      {
        productId: product.id,
        snapshotId,
      },
    );
  typia.assert(snapshot);
  // 6. Validate snapshot integrity — data must match original product (pre-edit state)
  TestValidator.equals("snapshot product_id", snapshot.product_id, product.id);
  TestValidator.equals("snapshot name preserved", snapshot.name, product.name);
  TestValidator.equals(
    "snapshot description preserved",
    snapshot.description,
    product.description,
  );
  TestValidator.equals(
    "snapshot base_price preserved",
    snapshot.base_price,
    product.base_price,
  );
  TestValidator.predicate(
    "snapshot has valid created_at timestamp",
    snapshot.created_at.length > 0,
  );
}
