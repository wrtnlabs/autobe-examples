/**
 * Test cross-customer cart item retrieval authorization.
 *
 * Validates that cart items are strictly scoped to the owning customer by
 * having Customer B attempt to retrieve Customer A's cart item. The system
 * must reject the request with 403 Forbidden, confirming that no customer
 * may view another customer's cart contents even when possessing a valid
 * cart item identifier.
 *
 * 1. Administrator joins and creates a product category.
 * 2. Seller registers, gets approved by admin, creates a product with a
 *    variant, and adds inventory stock.
 * 3. Customer A joins and adds the variant to their cart, creating a cart
 *    item whose ID is captured.
 * 4. Customer B joins with separate credentials.
 * 5. Customer B attempts to retrieve Customer A's cart item by ID.
 * 6. The system returns 403 Forbidden, confirming the authorization
 *    boundary that protects customer cart privacy.
 */
export async function test_api_cart_item_retrieve_cross_customer_forbidden(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin setup
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  const category = await generate_random_shopping_mall_admin_categories_create(
    adminConnection,
    {},
  );
  typia.assert(category);
  // 2. Seller setup
  const sellerConnection: api.IConnection = { host: connection.host };
  const seller = await authorize_seller_join(sellerConnection, {});
  await api.functional.shoppingMall.admin.sellers.approve(adminConnection, {
    sellerId: seller.id,
  });
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    {
      body: { shopping_mall_category_id: category.id },
    },
  );
  typia.assert(product);
  const variant =
    await generate_random_shopping_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
      },
    );
  typia.assert(variant);
  await generate_random_shopping_mall_seller_products_variants_inventory_records_create(
    sellerConnection,
    {
      params: { productId: product.id, variantId: variant.id },
    },
  );
  // 3. Customer A creates a cart item
  const customerAConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerAConnection, {});
  const cartItem =
    await generate_random_shopping_mall_customer_cart_items_create(
      customerAConnection,
      {
        body: { productVariantId: variant.id },
      },
    );
  typia.assert(cartItem);
  // 4. Customer B joins
  const customerBConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerBConnection, {});
  // 5. Customer B attempts to access Customer A's cart item
  await TestValidator.httpError(
    "customer B cannot access customer A's cart item",
    403,
    async () => {
      await api.functional.shoppingMall.customer.cart_items.at(
        customerBConnection,
        { cartItemId: cartItem.id },
      );
    },
  );
}
