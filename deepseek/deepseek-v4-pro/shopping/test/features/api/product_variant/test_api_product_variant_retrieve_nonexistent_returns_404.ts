/**
 * Test that a customer receives a 404 error when requesting a non-existent variant.
 *
 * Validates the specification rule that the API returns HTTP 404 when the variant does not exist or the productId does not match the variant's product ID. The test sets up a complete product with a valid variant through administrative and seller workflows, then attempts to retrieve a variant using the valid product ID but a randomly generated, non-existent variant ID.
 *
 * The test covers the edge case where a customer has access to a valid product identifier but attempts to guess or brute-force variant identifiers. The system must properly distinguish between existing and non-existing variants and return appropriate errors rather than leaking information or crashing.
 *
 * 1. Administrator registers and creates a top-level category for product classification.
 * 2. Seller registers, creates a product under the category, then creates a variant with SKU and option values.
 * 3. Customer registers and calls the variant retrieval endpoint with a valid productId but a random variantId.
 * 4. TestValidator.error confirms the call throws, validating the 404 business rule.
 */
export async function test_api_product_variant_retrieve_nonexistent_returns_404(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin setup - create category
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  const category = await generate_random_shopping_mall_admin_categories_create(
    adminConnection,
    {},
  );
  typia.assert(category);
  // 2. Seller setup - create product and variant
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {});
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        shopping_mall_category_id: category.id,
      },
    },
  );
  typia.assert(product);
  const variant =
    await generate_random_shopping_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
      },
    );
  typia.assert(variant);
  // 3. Customer setup
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  // 4. Attempt to retrieve variant with valid productId but nonexistent variantId
  const nonexistentVariantId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.error("nonexistent variant returns 404", async () => {
    await api.functional.shoppingMall.customer.products.variants.at(
      customerConnection,
      {
        productId: product.id,
        variantId: nonexistentVariantId,
      },
    );
  });
}
