export async function test_api_product_variant_retrieve_active_with_price_override(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin setup - create category
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  const category = await generate_random_shopping_mall_admin_categories_create(
    adminConnection,
    {},
  );
  typia.assert(category);
  // 2. Seller setup - create product
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {});
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    {
      body: { shopping_mall_category_id: category.id },
    },
  );
  typia.assert(product);
  // 3. Seller creates variant with price override
  const priceOverride = 29900;
  const variant =
    await generate_random_shopping_mall_seller_products_variants_create(
      sellerConnection,
      {
        body: { price: priceOverride },
        params: { productId: product.id },
      },
    );
  typia.assert(variant);
  // 4. Seller adds inventory restock
  await generate_random_shopping_mall_seller_products_variants_inventory_records_create(
    sellerConnection,
    {
      body: {
        quantity_change: 100,
      },
      params: {
        productId: product.id,
        variantId: variant.id,
      },
    },
  );
  // 5. Customer retrieves the variant
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  const retrieved =
    await api.functional.shoppingMall.customer.products.variants.at(
      customerConnection,
      {
        productId: product.id,
        variantId: variant.id,
      },
    );
  typia.assert(retrieved);
  // 6. Validate response
  TestValidator.equals("variant id matches", retrieved.id, variant.id);
  TestValidator.equals("variant code matches", retrieved.code, variant.code);
  TestValidator.predicate(
    "optionValues is non-empty",
    retrieved.optionValues.length > 0,
  );
  TestValidator.equals(
    "variant price override",
    retrieved.price,
    priceOverride,
  );
  TestValidator.equals(
    "base price from parent",
    retrieved.base_price,
    product.base_price,
  );
  TestValidator.predicate(
    "stock quantity is positive",
    retrieved.stock_quantity > 0,
  );
  TestValidator.equals("deleted_at is null", retrieved.deleted_at, null);
}
