/**
 * Test that a customer receives a 404 error when retrieving a soft-deleted product variant.
 *
 * Validates the business rule that customers can only see active (non-deleted) variants — soft-deleted variants must be hidden from customer view. The role-based soft-delete filtering ensures customers cannot access deleted variants even when they know the variant ID.
 *
 * 1. Administrator registers and creates a top-level category.
 * 2. Seller registers, creates a product under the category, creates a variant, then soft-deletes the variant via the seller endpoint.
 * 3. Customer registers and attempts to GET the deleted variant, expecting an error to be thrown (404 Not Found).
 */
export async function test_api_product_variant_retrieve_soft_deleted_returns_404(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin setup — create a category
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  const category = await generate_random_shopping_mall_admin_categories_create(
    adminConnection,
    {},
  );
  typia.assert(category);
  // 2. Seller setup — create product, variant, then soft-delete the variant
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {});
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    { body: { shopping_mall_category_id: category.id } },
  );
  typia.assert(product);
  const variant =
    await generate_random_shopping_mall_seller_products_variants_create(
      sellerConnection,
      { params: { productId: product.id } },
    );
  typia.assert(variant);
  await api.functional.shoppingMall.seller.products.variants.erase(
    sellerConnection,
    { productId: product.id, variantId: variant.id },
  );
  // 3. Customer attempts to retrieve the soft-deleted variant — expect failure
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  await TestValidator.error(
    "soft-deleted variant hidden from customer",
    async () => {
      await api.functional.shoppingMall.customer.products.variants.at(
        customerConnection,
        { productId: product.id, variantId: variant.id },
      );
    },
  );
}
