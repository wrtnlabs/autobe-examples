/**
 * Test seller retrieval of an approved cancellation request with snapshots.
 *
 * Validates that after a seller approves a customer's cancellation request, the seller
 * can retrieve the request and the response includes the automatically created snapshot
 * capturing the reason and status at the moment of approval. The test covers the full
 * lifecycle from product creation through order placement, cancellation submission,
 * seller approval, and final retrieval with snapshot verification.
 *
 * 1. Seller registers and creates a product with a variant and inventory stock.
 * 2. Customer registers, adds the variant to their cart, and places an order.
 * 3. Customer submits a cancellation request for the paid order item.
 * 4. Seller approves the cancellation request, triggering automatic snapshot creation.
 * 5. Seller retrieves the cancellation request and validates status, snapshots, and references.
 */
export async function test_api_cancellation_request_seller_retrieves_after_approval_with_snapshots(
  connection: api.IConnection,
): Promise<void> {
  // 1. Seller setup: register and create product/variant/inventory
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {});
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    {},
  );
  const variant =
    await generate_random_shopping_mall_seller_products_variants_create(
      sellerConnection,
      { params: { productId: product.id } },
    );
  await generate_random_shopping_mall_seller_products_variants_inventory_records_create(
    sellerConnection,
    { params: { productId: product.id, variantId: variant.id } },
  );
  // 2. Customer setup: register, add to cart, place order
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  await generate_random_shopping_mall_customer_cart_items_create(
    customerConnection,
    { body: { productVariantId: variant.id, quantity: 1 } },
  );
  const order = await generate_random_shopping_mall_customer_orders_create(
    customerConnection,
    {
      body: {
        items: [{ variant_id: variant.id, quantity: 1 }],
      },
    },
  );
  typia.assert(order);
  const orderItem = order.items[0];
  // 3. Customer submits cancellation request
  const cancellationRequest =
    await generate_random_shopping_mall_customer_order_items_cancellation_requests_create(
      customerConnection,
      { params: { itemId: orderItem.id } },
    );
  typia.assert(cancellationRequest);
  // 4. Seller approves the cancellation request
  const approvedRequest =
    await api.functional.shoppingMall.seller.cancellation_requests.update(
      sellerConnection,
      {
        requestId: cancellationRequest.id,
        body: {
          status: "approved",
        } satisfies IShoppingMallCancellationRequest.IUpdate,
      },
    );
  typia.assert(approvedRequest);
  // 5. Seller retrieves the cancellation request after approval
  const retrievedRequest =
    await api.functional.shoppingMall.seller.cancellation_requests.at(
      sellerConnection,
      { requestId: cancellationRequest.id },
    );
  typia.assert(retrievedRequest);
  // 6. Validate
  TestValidator.equals(
    "status is approved",
    retrievedRequest.status,
    "approved",
  );
  TestValidator.predicate(
    "snapshots array is non-empty",
    retrievedRequest.snapshots.length > 0,
  );
  const snapshot = retrievedRequest.snapshots[0];
  TestValidator.equals(
    "snapshot status is approved",
    snapshot.status,
    "approved",
  );
  TestValidator.equals(
    "snapshot reason matches original",
    snapshot.reason,
    cancellationRequest.reason,
  );
  TestValidator.equals(
    "snapshot references parent cancellation request",
    snapshot.cancellationRequest.id,
    retrievedRequest.id,
  );
  TestValidator.equals(
    "orderItem details remain accessible",
    retrievedRequest.orderItem.id,
    orderItem.id,
  );
}
