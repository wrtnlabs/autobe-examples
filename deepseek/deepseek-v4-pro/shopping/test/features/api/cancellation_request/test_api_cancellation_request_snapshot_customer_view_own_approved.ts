export async function test_api_cancellation_request_snapshot_customer_view_own_approved(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin setup: join and create category
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  const category = await generate_random_shopping_mall_admin_categories_create(
    adminConnection,
    {},
  );
  typia.assert(category);
  // 2. Seller setup: join, create product, variant, and add inventory
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {});
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    { body: { shopping_mall_category_id: category.id } },
  );
  typia.assert(product);
  const variant =
    await generate_random_shopping_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
        body: { initialStockQuantity: 100 },
      },
    );
  typia.assert(variant);
  // 3. Customer setup: join and place order for the variant
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  const order = await generate_random_shopping_mall_customer_orders_create(
    customerConnection,
    {
      body: {
        items: [{ variant_id: variant.id, quantity: 1 }],
      },
    },
  );
  typia.assert(order);
  const orderItem = order.items[0];
  // 4. Customer submits cancellation request with a specific reason
  const cancellationReason = RandomGenerator.paragraph({ sentences: 3 });
  const cancellationRequest =
    await generate_random_shopping_mall_customer_order_items_cancellation_requests_create(
      customerConnection,
      {
        params: { itemId: orderItem.id },
        body: { reason: cancellationReason },
      },
    );
  typia.assert(cancellationRequest);
  // 5. Seller approves cancellation request — system creates immutable snapshot
  const updatedRequest =
    await api.functional.shoppingMall.seller.cancellation_requests.update(
      sellerConnection,
      {
        requestId: cancellationRequest.id,
        body: {
          status: "approved",
        } satisfies IShoppingMallCancellationRequest.IUpdate,
      },
    );
  typia.assert(updatedRequest);
  // 6. Customer retrieves cancellation request snapshots
  const snapshotPage =
    await api.functional.shoppingMall.cancellation_requests.snapshots.index(
      customerConnection,
      {
        requestId: cancellationRequest.id,
        body: {} satisfies IShoppingMallCancellationRequestSnapshot.IRequest,
      },
    );
  typia.assert(snapshotPage);
  // 7. Validate snapshot content and pagination
  TestValidator.equals("snapshot count", snapshotPage.data.length, 1);
  const snapshot = snapshotPage.data[0];
  TestValidator.equals(
    "snapshot preserves reason",
    snapshot.reason,
    cancellationReason,
  );
  TestValidator.equals(
    "snapshot status is approved",
    snapshot.status,
    "approved",
  );
  TestValidator.predicate("snapshot has valid id", snapshot.id.length > 0);
  TestValidator.predicate(
    "snapshot has created_at timestamp",
    snapshot.created_at.length > 0,
  );
  // 8. Validate pagination metadata
  TestValidator.equals(
    "pagination current page",
    snapshotPage.pagination.current,
    1,
  );
  TestValidator.equals(
    "pagination total records",
    snapshotPage.pagination.records,
    1,
  );
  TestValidator.equals(
    "pagination total pages",
    snapshotPage.pagination.pages,
    1,
  );
  TestValidator.equals("pagination limit", snapshotPage.pagination.limit, 20);
}
