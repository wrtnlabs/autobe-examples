export async function test_api_cancellation_request_view_by_non_owner(
  connection: api.IConnection,
): Promise<void> {
  // 1. Seller setup — register and create product with variant and inventory
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {});
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    {},
  );
  typia.assert(product);
  const variant =
    await generate_random_shopping_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
      },
    );
  typia.assert(variant);
  await generate_random_shopping_mall_seller_products_variants_inventory_records_create(
    sellerConnection,
    {
      params: {
        productId: product.id,
        variantId: variant.id,
      },
      body: {
        quantity_change: 10 satisfies number as number,
        reason: "Initial stock for test",
      },
    },
  );
  // 2. Customer A — register, add to cart, place order, create cancellation request
  const customerAConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerAConnection, {});
  await generate_random_shopping_mall_customer_cart_items_create(
    customerAConnection,
    {
      body: {
        productVariantId: variant.id,
        quantity: 1 satisfies number as number,
      },
    },
  );
  const order = await generate_random_shopping_mall_customer_orders_create(
    customerAConnection,
    {
      body: {
        items: [
          {
            variant_id: variant.id,
            quantity: 1 satisfies number as number,
          },
        ],
      },
    },
  );
  typia.assert(order);
  const orderItem = order.items[0];
  typia.assertGuard(orderItem);
  const cancellationRequest =
    await generate_random_shopping_mall_customer_order_items_cancellation_requests_create(
      customerAConnection,
      {
        params: { itemId: orderItem.id },
      },
    );
  typia.assert(cancellationRequest);
  // 3. Customer B — register as a different customer with no ownership
  const customerBConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerBConnection, {});
  // 4. Customer B attempts to view Customer A's cancellation request — must be denied
  await TestValidator.httpError(
    "non-owner customer cannot view another customer's cancellation request",
    403,
    async () => {
      await api.functional.shoppingMall.customer.cancellation_requests.at(
        customerBConnection,
        {
          requestId: cancellationRequest.id,
        },
      );
    },
  );
}
