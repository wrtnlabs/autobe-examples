/**
 * Test that snapshot listing returns an empty paginated result when a seller has not yet responded to a cancellation request.
 *
 * Validates that the cancellation request snapshot listing endpoint returns HTTP 200 with zero snapshots — not 404 — when the cancellation request exists but no snapshot has been created because the seller has not yet approved or rejected it. Snapshots are only generated at the moment of seller response, so a pending cancellation request legitimately has an empty snapshot history.
 *
 * The pagination metadata must also reflect the emptiness: current page 1, total records 0, and total pages 0. The response must include a valid IPageIShoppingMallCancellationRequestSnapshot.ISummary structure — an empty data array rather than a missing or null field — confirming the endpoint handles the no-snapshots case gracefully.
 *
 * 1. Administrator registers, creates a product category, and approves the seller.
 * 2. Seller registers, creates a product with a variant and inventory stock.
 * 3. Customer registers, places an order for the variant, and submits a cancellation request.
 * 4. Customer lists snapshots of the pending cancellation request with default pagination.
 * 5. Validates the response contains zero snapshots with correct pagination metadata.
 */
export async function test_api_cancellation_request_snapshot_empty_before_seller_response(
  connection: api.IConnection,
): Promise<void> {
  // 1. Administrator setup
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  const category = await generate_random_shopping_mall_admin_categories_create(
    adminConnection,
    {},
  );
  typia.assert(category);
  // 2. Seller setup
  const sellerConnection: api.IConnection = { host: connection.host };
  const seller = await authorize_seller_join(sellerConnection, {});
  await api.functional.shoppingMall.admin.sellers.approve(adminConnection, {
    sellerId: seller.id,
  });
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        shopping_mall_category_id: category.id,
      },
    },
  );
  typia.assert(product);
  const variant =
    await generate_random_shopping_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
      },
    );
  typia.assert(variant);
  await generate_random_shopping_mall_seller_products_variants_inventory_records_create(
    sellerConnection,
    {
      params: {
        productId: product.id,
        variantId: variant.id,
      },
    },
  );
  // 3. Customer setup
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  const order = await generate_random_shopping_mall_customer_orders_create(
    customerConnection,
    {
      body: {
        items: [
          {
            variant_id: variant.id,
            quantity: 1,
          },
        ],
      },
    },
  );
  typia.assert(order);
  const orderItem = order.items[0];
  // 4. Customer submits cancellation request
  const cancellationRequest =
    await generate_random_shopping_mall_customer_order_items_cancellation_requests_create(
      customerConnection,
      {
        params: { itemId: orderItem.id },
      },
    );
  typia.assert(cancellationRequest);
  // 5. List snapshots before seller responds
  const result =
    await api.functional.shoppingMall.customer.cancellation_requests.snapshots.index(
      customerConnection,
      {
        requestId: cancellationRequest.id,
        body: {},
      },
    );
  typia.assert(result);
  // 6. Validate empty paginated result
  TestValidator.equals("snapshot data array is empty", result.data.length, 0);
  TestValidator.equals("current page is 1", result.pagination.current, 1);
  TestValidator.equals("total records is 0", result.pagination.records, 0);
  TestValidator.equals("total pages is 0", result.pagination.pages, 0);
}
