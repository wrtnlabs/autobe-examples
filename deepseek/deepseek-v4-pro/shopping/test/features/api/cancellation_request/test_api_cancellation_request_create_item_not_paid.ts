/**
 * Test that cancellation requests are rejected for order items not in "paid" status.
 *
 * Validates the business rule that cancellation is only available while an order item remains in "paid" status. Once a seller creates a shipment and the item transitions to "shipped", the cancellation endpoint must respond with 422 Unprocessable Entity.
 *
 * The test follows the complete purchase lifecycle through shipment creation to ensure the item is in a well-defined non-cancellable state before the customer's cancellation attempt.
 *
 * 1. Administrator registers, creates a top-level product category.
 * 2. Seller registers, gets approved by the administrator.
 * 3. Seller creates a product under the category with a variant and initial stock.
 * 4. Customer registers and places an order for the variant — the order item enters "paid" status.
 * 5. Seller creates a shipment containing the order item, transitioning it to "shipped".
 * 6. Customer attempts to submit a cancellation request for the shipped item — expects 422 rejection with no side effects on the order item's state.
 */
export async function test_api_cancellation_request_create_item_not_paid(
  connection: api.IConnection,
): Promise<void> {
  // 1. Administrator setup
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  const category = await generate_random_shopping_mall_admin_categories_create(
    adminConnection,
    {},
  );
  typia.assert(category);
  // 2. Seller setup
  const sellerConnection: api.IConnection = { host: connection.host };
  const seller = await authorize_seller_join(sellerConnection, {});
  await api.functional.shoppingMall.admin.sellers.approve(adminConnection, {
    sellerId: seller.id,
  });
  // 3. Seller creates product with variant and stock
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        shopping_mall_category_id: category.id,
      },
    },
  );
  typia.assert(product);
  const variant =
    await generate_random_shopping_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
        body: {
          initialStockQuantity: 100,
        },
      },
    );
  typia.assert(variant);
  // 4. Customer setup and order placement
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  const order = await generate_random_shopping_mall_customer_orders_create(
    customerConnection,
    {
      body: {
        items: [
          {
            variant_id: variant.id,
            quantity: 1,
          } satisfies IShoppingMallOrderItem.ICreate,
        ],
      },
    },
  );
  typia.assert(order);
  const orderItem = order.items[0];
  TestValidator.equals("order item is paid", orderItem.status, "paid");
  // 5. Seller creates shipment → item transitions to "shipped"
  const shipment =
    await generate_random_shopping_mall_seller_orders_shipments_create(
      sellerConnection,
      {
        params: { orderId: order.id },
        body: {
          orderItemIds: [orderItem.id],
        },
      },
    );
  typia.assert(shipment);
  // 6. Customer attempts cancellation on shipped item → expects 422
  await TestValidator.httpError(
    "cancellation unavailable for shipped item",
    422,
    async () => {
      await api.functional.shoppingMall.customer.order_items.cancellation_requests.create(
        customerConnection,
        {
          itemId: orderItem.id,
          body: {
            reason: "I want to cancel this order",
          } satisfies IShoppingMallCancellationRequest.ICreate,
        },
      );
    },
  );
}
