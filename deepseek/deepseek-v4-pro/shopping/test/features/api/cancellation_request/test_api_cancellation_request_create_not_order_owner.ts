/**
 * Test ownership enforcement for cancellation request creation.
 *
 * Verifies that a customer cannot submit a cancellation request for an order item
 * belonging to a different customer. The system must trace from order item to order
 * to the owning customer and reject mismatches with a 403 Forbidden response.
 *
 * The test follows a complete purchase flow:
 * 1. An administrator creates a category and approves a seller registration.
 * 2. The approved seller creates a product, a variant with stock.
 * 3. Customer A places an order for the variant, becoming the legitimate owner.
 * 4. Customer B, an unrelated customer, attempts to cancel Customer A's order item.
 * 5. The system rejects Customer B's attempt with 403 Forbidden, preserving Customer A's
 *    order item state and not revealing order details to the unauthorized customer.
 */
export async function test_api_cancellation_request_create_not_order_owner(
  connection: api.IConnection,
): Promise<void> {
  // 1. Administrator setup
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  const category = await generate_random_shopping_mall_admin_categories_create(
    adminConnection,
    {},
  );
  typia.assert(category);
  // 2. Seller registration and approval
  const sellerConnection: api.IConnection = { host: connection.host };
  const seller = await authorize_seller_join(sellerConnection, {});
  await api.functional.shoppingMall.admin.sellers.approve(adminConnection, {
    sellerId: seller.id,
  });
  // 3. Product and variant with stock
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    { body: { shopping_mall_category_id: category.id } },
  );
  typia.assert(product);
  const variant =
    await generate_random_shopping_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
        body: { initialStockQuantity: 10 },
      },
    );
  typia.assert(variant);
  // 4. Customer A registration and order placement
  const customerAConnection: api.IConnection = { host: connection.host };
  const customerA = await authorize_customer_join(customerAConnection, {});
  const order = await generate_random_shopping_mall_customer_orders_create(
    customerAConnection,
    {
      body: {
        items: [{ variant_id: variant.id, quantity: 1 }],
      },
    },
  );
  typia.assert(order);
  const orderItem = order.items[0];
  TestValidator.equals("order item status", orderItem.status, "paid");
  // 5. Customer B registration
  const customerBConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerBConnection, {});
  // 6. Customer B attempts to cancel Customer A's order item — must fail with 403
  await TestValidator.httpError(
    "non-owner cancellation denied",
    403,
    async () => {
      await api.functional.shoppingMall.customer.order_items.cancellation_requests.create(
        customerBConnection,
        {
          itemId: orderItem.id,
          body: {
            reason: "Unauthorized cancellation attempt by non-owner",
          } satisfies IShoppingMallCancellationRequest.ICreate,
        },
      );
    },
  );
}
