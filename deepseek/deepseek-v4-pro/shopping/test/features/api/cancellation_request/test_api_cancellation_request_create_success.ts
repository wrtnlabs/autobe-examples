export async function test_api_cancellation_request_create_success(
  connection: api.IConnection,
): Promise<void> {
  // 1. Administrator setup
  const adminConnection: api.IConnection = { host: connection.host };
  const admin = await authorize_admin_join(adminConnection, {});
  typia.assert(admin);
  const category = await generate_random_shopping_mall_admin_categories_create(
    adminConnection,
    {},
  );
  typia.assert(category);
  // 2. Seller registration and approval
  const sellerConnection: api.IConnection = { host: connection.host };
  const seller = await authorize_seller_join(sellerConnection, {});
  typia.assert(seller);
  const approvedSeller =
    await api.functional.shoppingMall.admin.sellers.approve(adminConnection, {
      sellerId: seller.id,
    });
  typia.assert(approvedSeller);
  // 3. Seller creates product and variant
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    { body: { shopping_mall_category_id: category.id } },
  );
  typia.assert(product);
  const variant =
    await generate_random_shopping_mall_seller_products_variants_create(
      sellerConnection,
      { params: { productId: product.id } },
    );
  typia.assert(variant);
  // 4. Seller adds inventory stock
  const stockQuantity = typia.random<
    number & tags.Type<"uint32"> & tags.Minimum<10> & tags.Maximum<100>
  >();
  const inventoryRecord =
    await generate_random_shopping_mall_seller_products_variants_inventory_records_create(
      sellerConnection,
      {
        params: { productId: product.id, variantId: variant.id },
        body: {
          quantity_change: stockQuantity satisfies number as number,
          reason: "Initial stock for testing",
        },
      },
    );
  typia.assert(inventoryRecord);
  // 5. Customer registers and places an order
  const customerConnection: api.IConnection = { host: connection.host };
  const customer = await authorize_customer_join(customerConnection, {});
  typia.assert(customer);
  const order = await generate_random_shopping_mall_customer_orders_create(
    customerConnection,
    {
      body: {
        items: [
          {
            variant_id: variant.id,
            quantity: 1,
          },
        ],
      },
    },
  );
  typia.assert(order);
  const orderItem = order.items[0];
  TestValidator.equals("order item status is paid", orderItem.status, "paid");
  // 6. Customer submits cancellation request
  const cancellationReason = "No longer need this item";
  const cancellationRequest =
    await generate_random_shopping_mall_customer_order_items_cancellation_requests_create(
      customerConnection,
      {
        body: { reason: cancellationReason },
        params: { itemId: orderItem.id },
      },
    );
  typia.assert(cancellationRequest);
  // 7. Validate cancellation request response
  TestValidator.equals(
    "status is pending",
    cancellationRequest.status,
    "pending",
  );
  TestValidator.equals(
    "reason matches submitted text",
    cancellationRequest.reason,
    cancellationReason,
  );
  TestValidator.equals(
    "order item reference is correct",
    cancellationRequest.orderItem.id,
    orderItem.id,
  );
  TestValidator.equals(
    "order item status remains paid",
    cancellationRequest.orderItem.status,
    "paid",
  );
  TestValidator.equals(
    "deleted_at is null",
    cancellationRequest.deleted_at,
    null,
  );
  TestValidator.equals(
    "created_at equals updated_at",
    cancellationRequest.created_at,
    cancellationRequest.updated_at,
  );
}
