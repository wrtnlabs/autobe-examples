export async function test_api_variant_snapshot_history_wrong_product(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin setup — register and create a category
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  const category = await generate_random_shopping_mall_admin_categories_create(
    adminConnection,
    {},
  );
  typia.assert(category);
  // 2. Seller setup — register
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {});
  // 3. Create Product A under the category
  const productA = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        shopping_mall_category_id: category.id,
      },
    },
  );
  typia.assert(productA);
  // 4. Create a variant under Product A with a globally unique SKU code
  const variant =
    await generate_random_shopping_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: productA.id },
      },
    );
  typia.assert(variant);
  // 5. Create Product B under the same category (different product, same seller)
  const productB = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        shopping_mall_category_id: category.id,
      },
    },
  );
  typia.assert(productB);
  // 6. Attempt to retrieve variant snapshot history using Product B's ID
  //    but the variant's SKU code (which belongs to Product A).
  //    The system must resolve the variant by variantCode, verify it belongs
  //    to the product identified by productId, and return 404 on mismatch.
  await TestValidator.httpError(
    "variant code belonging to Product A should not be accessible via Product B's productId",
    404,
    async () =>
      await api.functional.shoppingMall.seller.products.variants.snapshots.patchByProductidAndVariantcode(
        sellerConnection,
        {
          productId: productB.id,
          variantCode: variant.code,
          body: {} satisfies IShoppingMallProductVariantSnapshot.IRequest,
        },
      ),
  );
}
