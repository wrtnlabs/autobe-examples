/**
 * Test customer retrieval of a refund request after seller rejection.
 *
 * Validates the end-to-end flow where a customer submits a refund request for a delivered order item, the seller rejects it, and the customer retrieves the request to confirm the rejected state. This ensures customers can track the outcome of their refund requests after seller rejection — a business scenario distinct from approval.
 *
 * The test constructs the full prerequisite chain: administrator creates a category and approves a seller; the seller creates a product, adds a variant, and stocks inventory; a customer registers, places an order, and the item progresses through the paid → shipped → delivered lifecycle; the customer submits a refund request which the seller rejects; finally the customer retrieves the request to verify the rejected state.
 *
 * 1. Administrator joins and creates a product category.
 * 2. Seller registers, then the administrator approves the seller.
 * 3. Seller creates a product under the category.
 * 4. Seller creates a variant with a SKU code for the product.
 * 5. Seller adds positive inventory stock to make the variant purchasable.
 * 6. Customer registers and places an order containing the variant.
 * 7. Seller creates a shipment for the order item, transitioning it to "shipped".
 * 8. Customer confirms delivery, transitioning the order item to "delivered".
 * 9. Customer submits a refund request for the delivered order item.
 * 10. Seller rejects the refund request via the seller update endpoint.
 * 11. Customer retrieves the refund request and validates the rejected state: status is "rejected", responded_at is populated, reason is unchanged from submission, orderItem reference is correct, and created_at predates responded_at.
 */
export async function test_api_refund_request_retrieve_after_seller_rejection(
  connection: api.IConnection,
): Promise<void> {
  // 1. Administrator setup
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  const category = await generate_random_shopping_mall_admin_categories_create(
    adminConnection,
    {},
  );
  typia.assert(category);
  // 2. Seller registration
  const sellerConnection: api.IConnection = { host: connection.host };
  const seller = await authorize_seller_join(sellerConnection, {});
  typia.assert(seller);
  // 3. Administrator approves seller
  await api.functional.shoppingMall.admin.sellers.approve(adminConnection, {
    sellerId: seller.id,
  });
  // 4. Seller creates product
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        shopping_mall_category_id: category.id,
      },
    },
  );
  typia.assert(product);
  // 5. Seller creates variant
  const variant =
    await generate_random_shopping_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
      },
    );
  typia.assert(variant);
  // 6. Seller adds stock
  await generate_random_shopping_mall_seller_products_variants_inventory_records_create(
    sellerConnection,
    {
      params: { productId: product.id, variantId: variant.id },
      body: {
        quantity_change: 100,
      },
    },
  );
  // 7. Customer registration
  const customerConnection: api.IConnection = { host: connection.host };
  const customer = await authorize_customer_join(customerConnection, {});
  typia.assert(customer);
  // 8. Customer places order
  const order = await generate_random_shopping_mall_customer_orders_create(
    customerConnection,
    {
      body: {
        items: [
          {
            variant_id: variant.id,
            quantity: 1,
          },
        ],
      },
    },
  );
  typia.assert(order);
  const orderItem = order.items[0];
  typia.assert(orderItem);
  // 9. Seller creates shipment
  const shipment =
    await generate_random_shopping_mall_seller_orders_shipments_create(
      sellerConnection,
      {
        params: { orderId: order.id },
        body: {
          orderItemIds: [orderItem.id],
        },
      },
    );
  typia.assert(shipment);
  // 10. Customer confirms delivery
  await api.functional.shoppingMall.customer.shipments.confirm_delivery.confirmDelivery(
    customerConnection,
    { shipmentId: shipment.id },
  );
  // 11. Customer submits refund request
  const refundRequest =
    await generate_random_shopping_mall_customer_order_items_refund_requests_create(
      customerConnection,
      {
        params: { itemId: orderItem.id },
      },
    );
  typia.assert(refundRequest);
  // 12. Seller rejects the refund request
  await api.functional.shoppingMall.seller.refund_requests.update(
    sellerConnection,
    {
      requestId: refundRequest.id,
      body: {
        status: "rejected",
      } satisfies IShoppingMallRefundRequest.IUpdate,
    },
  );
  // 13. TARGET: Customer retrieves the refund request after seller rejection
  const retrieved =
    await api.functional.shoppingMall.customer.refund_requests.at(
      customerConnection,
      { requestId: refundRequest.id },
    );
  typia.assert(retrieved);
  // 14. Validate rejected state
  TestValidator.equals("status is rejected", retrieved.status, "rejected");
  TestValidator.predicate(
    "responded_at is populated after seller response",
    retrieved.responded_at !== null,
  );
  TestValidator.equals(
    "reason unchanged from submission",
    retrieved.reason,
    refundRequest.reason,
  );
  TestValidator.equals(
    "orderItem id matches",
    retrieved.orderItem.id,
    orderItem.id,
  );
  TestValidator.predicate(
    "created_at predates responded_at",
    new Date(retrieved.created_at).getTime() <
      new Date(retrieved.responded_at!).getTime(),
  );
}
