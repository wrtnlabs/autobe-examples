/**
 * Test that a seller can view cancellation request snapshots after rejecting a customer's cancellation request.
 *
 * Validates the complete flow from product creation through order placement, cancellation request submission, seller rejection, and snapshot listing. The seller who owns the product involved in the cancellation can view snapshots for cancellation requests on their products through the product → variant → order item → cancellation request chain.
 *
 * 1. Administrator creates a product category for the seller's product.
 * 2. Seller joins, creates a product under the category, adds a variant with a unique SKU, and records positive inventory.
 * 3. Customer joins and places an order for the variant with quantity 1.
 * 4. Customer submits a cancellation request with a specific reason text.
 * 5. Seller rejects the cancellation request, triggering system creation of an immutable snapshot with "rejected" status preserving the reason.
 * 6. Seller lists the cancellation request's snapshots and verifies exactly one snapshot exists with "rejected" status and the preserved reason text.
 */
export async function test_api_cancellation_request_snapshot_seller_view_product_rejected(
  connection: api.IConnection,
): Promise<void> {
  // 1. Administrator creates category
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  const category = await generate_random_shopping_mall_admin_categories_create(
    adminConnection,
    {},
  );
  typia.assert(category);
  // 2. Seller joins, creates product, variant, and adds inventory
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {});
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        shopping_mall_category_id: category.id,
      },
    },
  );
  typia.assert(product);
  const variant =
    await generate_random_shopping_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
      },
    );
  typia.assert(variant);
  const inventoryRecord =
    await generate_random_shopping_mall_seller_products_variants_inventory_records_create(
      sellerConnection,
      {
        params: { productId: product.id, variantId: variant.id },
      },
    );
  typia.assert(inventoryRecord);
  // 3. Customer joins and places order
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  const order = await generate_random_shopping_mall_customer_orders_create(
    customerConnection,
    {
      body: {
        items: [
          {
            variant_id: variant.id,
            quantity: 1,
          },
        ],
      },
    },
  );
  typia.assert(order);
  // 4. Customer submits cancellation request
  const cancellationReason = "Changed my mind about the purchase";
  const cancellationRequest =
    await generate_random_shopping_mall_customer_order_items_cancellation_requests_create(
      customerConnection,
      {
        params: { itemId: order.items[0].id },
        body: { reason: cancellationReason },
      },
    );
  typia.assert(cancellationRequest);
  // 5. Seller rejects cancellation request — system creates immutable snapshot
  const updatedRequest =
    await api.functional.shoppingMall.seller.cancellation_requests.update(
      sellerConnection,
      {
        requestId: cancellationRequest.id,
        body: {
          status: "rejected",
        } satisfies IShoppingMallCancellationRequest.IUpdate,
      },
    );
  typia.assert(updatedRequest);
  // 6. Seller lists snapshots
  const snapshots =
    await api.functional.shoppingMall.cancellation_requests.snapshots.index(
      sellerConnection,
      {
        requestId: cancellationRequest.id,
        body: {},
      },
    );
  typia.assert(snapshots);
  // 7. Validate snapshot
  TestValidator.equals("snapshot count", snapshots.data.length, 1);
  TestValidator.equals("snapshot status", snapshots.data[0].status, "rejected");
  TestValidator.equals(
    "snapshot reason preserved",
    snapshots.data[0].reason,
    cancellationReason,
  );
}
