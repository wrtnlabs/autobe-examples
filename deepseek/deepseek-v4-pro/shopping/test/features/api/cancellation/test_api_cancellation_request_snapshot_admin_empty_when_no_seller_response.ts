/**
 * Verify that an administrator receives an empty paginated result when viewing snapshots for a cancellation request where the seller has not yet responded.
 *
 * Validates the edge case where cancellation request snapshots have not been generated yet because the cancellation request remains in "pending" status — the seller has not approved or rejected it. The endpoint must gracefully return an empty paginated result with zero records and zero pages rather than erroring out, confirming the endpoint correctly distinguishes between "no snapshots exist" and "cancellation request not found."
 *
 * 1. Administrator registers and authenticates.
 * 2. Seller registers, administrator approves the seller.
 * 3. Administrator creates a product category.
 * 4. Seller creates a product with a variant that has initial stock.
 * 5. Customer registers, places an order for the variant.
 * 6. Customer submits a cancellation request for the order item (status remains "pending" — seller does not respond).
 * 7. Administrator retrieves snapshots for the cancellation request with an empty body.
 * 8. Validates the response data array is empty and pagination metadata shows records=0 and pages=0.
 */
export async function test_api_cancellation_request_snapshot_admin_empty_when_no_seller_response(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin setup
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  // 2. Seller setup
  const sellerConnection: api.IConnection = { host: connection.host };
  const seller = await authorize_seller_join(sellerConnection, {});
  // 3. Admin approves seller
  await api.functional.shoppingMall.admin.sellers.approve(adminConnection, {
    sellerId: seller.id,
  });
  // 4. Admin creates category
  const category = await generate_random_shopping_mall_admin_categories_create(
    adminConnection,
    {},
  );
  // 5. Seller creates product
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    { body: { shopping_mall_category_id: category.id } },
  );
  // 6. Seller creates variant with stock
  const variant =
    await generate_random_shopping_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
        body: { initialStockQuantity: 10 },
      },
    );
  // 7. Customer setup
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  // 8. Customer places order
  const order = await generate_random_shopping_mall_customer_orders_create(
    customerConnection,
    {
      body: {
        items: [{ variant_id: variant.id, quantity: 1 }],
      },
    },
  );
  // 9. Customer submits cancellation request (seller does NOT respond)
  const cancellationRequest =
    await generate_random_shopping_mall_customer_order_items_cancellation_requests_create(
      customerConnection,
      { params: { itemId: order.items[0].id } },
    );
  // 10. Admin views snapshots — should be empty since seller hasn't responded
  const snapshots =
    await api.functional.shoppingMall.admin.cancellation_requests.snapshots.index(
      adminConnection,
      {
        requestId: cancellationRequest.id,
        body: {},
      },
    );
  typia.assert(snapshots);
  // 11. Validate empty result
  TestValidator.equals("data is empty", snapshots.data.length, 0);
  TestValidator.equals(
    "pagination records is zero",
    snapshots.pagination.records,
    0,
  );
  TestValidator.equals(
    "pagination pages is zero",
    snapshots.pagination.pages,
    0,
  );
}
