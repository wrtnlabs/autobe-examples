/**
 * Test inventory record restock creation by an authenticated product-owning seller.
 *
 * Validates the complete inventory restock workflow where a seller who owns a product
 * creates a positive inventory record to increase variant stock. The test covers the full
 * dependency chain: administrator category setup, seller registration and authentication,
 * product creation, variant creation, and finally the inventory record creation.
 *
 * Special attention is given to verifying that the returned inventory record contains all
 * server-generated fields (id, created_at), correctly preserves the input values
 * (quantity_change, reason), and accurately references the target variant.
 *
 * 1. Administrator registers and creates a product category.
 * 2. Seller registers and authenticates on the platform.
 * 3. Seller creates a product under the category.
 * 4. Seller creates a variant with SKU code and option values.
 * 5. Seller creates a restock inventory record with positive quantity.
 * 6. Validates the inventory record response matches input and variant identity.
 */
export async function test_api_inventory_record_restock_by_seller(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin setup
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  const category = await generate_random_shopping_mall_admin_categories_create(
    adminConnection,
    { body: {} },
  );
  typia.assert(category);
  // 2. Seller setup
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {});
  // 3. Seller creates product
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        shopping_mall_category_id: category.id,
      },
    },
  );
  typia.assert(product);
  // 4. Seller creates variant
  const variant =
    await generate_random_shopping_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
      },
    );
  typia.assert(variant);
  // 5. Seller creates inventory record (restock)
  const restockQuantity = typia.random<
    number & tags.Type<"int32"> & tags.Minimum<1>
  >();
  const inventoryRecord =
    await generate_random_shopping_mall_seller_products_variants_inventory_records_create(
      sellerConnection,
      {
        params: {
          productId: product.id,
          variantId: variant.id,
        },
        body: {
          quantity_change: restockQuantity,
          reason: "Quarterly restock",
        },
      },
    );
  typia.assert(inventoryRecord);
  // 6. Validate response
  TestValidator.equals(
    "quantity_change matches input",
    inventoryRecord.quantity_change,
    restockQuantity,
  );
  TestValidator.equals(
    "reason matches input",
    inventoryRecord.reason,
    "Quarterly restock",
  );
  TestValidator.equals(
    "variant id matches",
    inventoryRecord.variant.id,
    variant.id,
  );
  TestValidator.predicate(
    "variant stock_quantity reflects restock",
    inventoryRecord.variant.stock_quantity >= restockQuantity,
  );
}
