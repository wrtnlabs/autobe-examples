export async function test_api_wishlist_item_removal_by_other_customer(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin setup: create admin and category
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  const category = await generate_random_shopping_mall_admin_categories_create(
    adminConnection,
    {},
  );
  typia.assert(category);
  // 2. Seller setup: create seller and product
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {});
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        shopping_mall_category_id: category.id,
      },
    },
  );
  typia.assert(product);
  // 3. Customer A: join and add product to wishlist
  const customerAConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerAConnection, {});
  const wishlistItem =
    await generate_random_shopping_mall_customer_wishlist_items_create(
      customerAConnection,
      {
        body: {
          product_id: product.id,
        },
      },
    );
  typia.assert(wishlistItem);
  // 4. Customer B: join and attempt cross-owner deletion
  const customerBConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerBConnection, {});
  // 5. Customer B attempts to delete Customer A's wishlist item — must be rejected
  await TestValidator.error(
    "Customer B cannot delete Customer A's wishlist item",
    async () => {
      await api.functional.shoppingMall.customer.wishlist_items.erase(
        customerBConnection,
        {
          wishlistItemId: wishlistItem.id,
        },
      );
    },
  );
}
