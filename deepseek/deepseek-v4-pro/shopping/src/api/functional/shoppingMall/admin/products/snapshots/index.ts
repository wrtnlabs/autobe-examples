/**
 * Retrieves the paginated snapshot history of a specific product, showing the complete state of the product at each point in its edit history.
 *
 * Each snapshot represents a frozen record of the product as it existed just before an edit was applied. Snapshots capture the product's name, description, category, base price, all images with their display order, and the full state of every variant — including SKU codes, option values, prices, and stock quantities — at that exact moment in time.
 *
 * Snapshots are created automatically by the system whenever a seller modifies any field of their product. They are permanently immutable and cannot be modified or deleted by any actor, ensuring a trustworthy audit trail for dispute resolution and historical reference. Snapshots are preserved even after the product itself is deleted.
 *
 * Authorization: Sellers can view the snapshot history of only their own products. Administrators can view the snapshot history of any product on the platform.
 *
 * @param props.connection
 * @param props.productId UUID of the product whose snapshot history is being retrieved.
 * @param props.body Search and pagination parameters including optional date-range filtering for narrowing snapshots to a specific time window.
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor admin
 * @x-autobe-specification Query the shopping_mall_product_snapshots table
 *   filtered by shopping_mall_product_id = {productId}. Order results by
 *   created_at descending (newest first) to show the edit chronology from most
 *   recent to oldest.
 *
 * Authorization:
 * - Seller: verify the product's shopping_mall_seller_id matches the authenticated seller's ID before returning results. Reject with 403 if the product does not belong to the seller.
 * - Admin: allow access to any product's snapshots without ownership check.
 * - Guest/Customer: reject with 403 — snapshot history is not exposed to these actors.
 *
 * Support standard pagination via cursor or offset-based pagination passed in the IShoppingMallProductSnapshot.IRequest body. Optional date-range filtering allows narrowing results to snapshots created within a specific time window.
 *
 * Include related data:
 * - Join shopping_mall_product_snapshot_images for the image gallery captured at snapshot time.
 * - Include shopping_mall_product_variant_snapshots linked to each snapshot record, preserving each variant's SKU code, option values, price, and stock quantity at that moment.
 * - The shopping_mall_category_id may be null if the category was deleted after the snapshot was taken — handle this gracefully in the join.
 *
 * Edge cases:
 * - If the product has been soft-deleted (deleted_at IS NOT NULL), snapshots are still accessible — do not filter out based on product deletion status.
 * - If no snapshots exist for the product, return an empty paginated result, not a 404.
 * - If productId does not correspond to any existing product, return 404.
 *
 * Snapshot immutability: this is a read-only operation. No create, update, or delete mutations are permitted on snapshot records.
 * @path /shoppingMall/admin/products/:productId/snapshots
 * @accessor api.functional.shoppingMall.admin.products.snapshots.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
