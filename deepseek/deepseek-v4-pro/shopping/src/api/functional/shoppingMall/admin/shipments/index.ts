/**
 * Search and list shipments with filtering and pagination.
 *
 * Returns a paginated list of shipments scoped to the authenticated user's role. Sellers see only their own shipments with the ability to filter by delivery status or order. Customers see shipments for their orders with tracking information including carrier name and tracking number. Administrators can view all shipments across the platform.
 *
 * Each shipment includes the carrier name, tracking number, shipping date, delivery confirmation status, and a summary of the order items contained in the shipment.
 *
 * **Delivery Status Filtering:**
 * Filter shipments by whether delivery has been confirmed. Shipments with a null delivery timestamp are in transit ("pending"); shipments with a confirmed delivery timestamp are delivered. Auto-confirmation occurs 14 days after shipping via a background job independently of API queries.
 *
 * @param props.connection
 * @param props.body Search criteria including optional delivery status filter (pending/delivered), order ID filter, seller ID filter (administrator only), shipping date range (createdFrom, createdTo), and pagination parameters (pageSize, cursor). All filters are optional — an empty request body returns all scoped shipments sorted newest first.
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor admin
 * @x-autobe-specification Query the shopping_mall_shipments table with optional
 *   filters and cursor-based pagination.
 *
 * **Authorization & Scoping:**
 * - Seller: automatically scope to shipments where shopping_mall_seller_id equals the authenticated seller's ID. Sellers cannot view shipments from other sellers.
 * - Customer: automatically scope to shipments belonging to orders where shopping_mall_customer_id equals the authenticated customer's ID. Customers only see shipments for their own orders.
 * - Administrator: no automatic scoping — can view all shipments across the platform.
 *
 * **Filtering:**
 * - deliveryStatus: filter by delivery state. "pending" matches shipments where delivered_at IS NULL (in transit). "delivered" matches shipments where delivered_at IS NOT NULL.
 * - orderId: exact match on shopping_mall_order_id. Sellers can filter to see shipments for a specific order. Customers are already scoped to their orders.
 * - sellerId: exact match on shopping_mall_seller_id. Only available for administrators — rejected with 403 for other roles.
 * - createdFrom / createdTo: date range filter on created_at for shipping date filtering. Both optional, can be used independently or together.
 *
 * All filters are optional and combinable. An empty request body returns all scoped shipments.
 *
 * **Sorting & Pagination:**
 * Default sort: created_at DESC (newest shipments first). Use cursor-based pagination with pageSize (default 20, max 100) and cursor parameters.
 *
 * **Response Construction:**
 * For each shipment in the result set, include:
 * - id, carrier_name, tracking_number, created_at (shipping date), delivered_at (null if not yet delivered)
 * - deliveryStatus: derived from delivered_at — null → "pending", non-null → "delivered"
 * - order: object with id and code for cross-reference
 * - seller: object with id for identification
 * - orderItemsSummary: array of contained order items, each with id, quantity, price, and status
 *
 * **Delivery Auto-Confirmation Note:**
 * Shipments with null delivered_at and created_at older than 14 days still appear as "pending" in search results. The auto-confirmation scheduled job runs independently — the API reflects actual database state at query time.
 * @path /shoppingMall/admin/shipments
 * @accessor api.functional.shoppingMall.admin.shipments.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
