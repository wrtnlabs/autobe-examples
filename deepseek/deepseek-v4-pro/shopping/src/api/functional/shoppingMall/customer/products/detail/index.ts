/**
 * Retrieves the complete product detail page data for a single product.
 *
 * The response includes the product's name, description, and base price; its category and owning seller's shop name and logo; all gallery images in display order; all available variants with their option values, prices, and current stock status; and all published reviews sorted newest first along with the product's computed average rating and total review count.
 *
 * Products that have been soft-deleted by their seller or an administrator return a 404 error and are not accessible through this endpoint. Products with no non-deleted variants are shown as unavailable for purchase but remain visible. Variants with zero or negative stock are marked as out of stock. Reviews from customers who have deleted their accounts are preserved with the author shown as "deleted user".
 *
 * @param props.connection
 * @param props.productId Unique identifier of the product to retrieve detail for (global scope).
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor customer
 * @x-autobe-specification Query the shopping_mall_products table by productId
 *   UUID. If the product is soft-deleted (deleted_at is not null), return a 404
 *   error.
 *
 * Join with shopping_mall_seller_profiles via shopping_mall_seller_id to include the seller's shop_name and logo_image_uri.
 *
 * Join with shopping_mall_categories via shopping_mall_category_id to include the category's id and name.
 *
 * Load all shopping_mall_product_images for the product, ordered by display_order ASC. Each image provides its image_url and display_order.
 *
 * Load all non-deleted shopping_mall_product_variants (deleted_at IS NULL) for the product, each with its child shopping_mall_product_variant_option_values. For each variant, compute current stock by summing all shopping_mall_inventory_records.quantity for that variant. A variant with stock <= 0 is marked as out-of-stock. If the product has no non-deleted variants, mark it as unavailable for purchase.
 *
 * Load all non-deleted shopping_mall_review_reviews (deleted_at IS NULL) for the product, ordered by created_at DESC (newest first). Include each review's rating, content, created_at, and the reviewer's display name from shopping_mall_customers joined via shopping_mall_customer_id. If the customer account is deleted (soft-deleted), display the author as "deleted user".
 *
 * Compute average_rating as the arithmetic mean of all non-deleted review ratings (rounded to one decimal place). If there are no non-deleted reviews, average_rating is null. Compute review_count as the count of all non-deleted reviews.
 *
 * Return all data in a single aggregated response. This operation is read-only and does not modify any data.
 * @path /shoppingMall/customer/products/:productId/detail
 * @accessor api.functional.shoppingMall.customer.products.detail.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique identifier of the product to retrieve detail for (global scope).
     */
    productId: string & tags.Format<"uuid">;
  };
  export type Response = IShoppingMallProduct.IDetail;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/customer/products/:productId/detail",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/customer/products/${encodeURIComponent(props.productId ?? "null")}/detail`;
  export const random = (): IShoppingMallProduct.IDetail =>
    typia.random<IShoppingMallProduct.IDetail>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("productId")(() => typia.assert(props.productId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
