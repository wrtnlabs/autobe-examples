/**
 * Confirms delivery of a shipment, transitioning all contained order items to "delivered" status.
 *
 * When a customer receives a physical package, they confirm delivery through this endpoint. The confirmation applies to the entire shipment — all order items within that shipment are marked as delivered simultaneously, and the shipment's delivery timestamp is recorded.
 *
 * If the customer does not manually confirm delivery, the system automatically confirms it 14 calendar days after the shipment was created (the shipping date). Once delivery is confirmed, it cannot be undone or reconfirmed — attempting to confirm an already-delivered shipment results in a conflict error.
 *
 * Only the customer who owns the order that this shipment belongs to may confirm delivery. Sellers and administrators cannot confirm delivery on behalf of the customer.
 *
 * @param props.connection
 * @param props.shipmentId The unique identifier of the shipment to confirm delivery for.
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor customer
 * @x-autobe-specification Confirm delivery of a shipment by the authenticated
 *   customer.
 *
 * Look up the shipment by shipmentId. Return 404 if no active (deleted_at IS NULL) shipment exists with the given id.
 *
 * Verify ownership: the shipment's shopping_mall_order_id must reference an order whose customer matches the authenticated customer. To do this, join shopping_mall_shipments → shopping_mall_orders and verify the order's customer id equals the authenticated customer's id. Return 403 Forbidden if the customer does not own this order.
 *
 * Verify the shipment has not already been confirmed: delivered_at must be null. Return 409 Conflict with message "Delivery has already been confirmed for this shipment" if delivered_at is not null.
 *
 * Verify that the shipment is associated with order items whose status is "shipped". Query shopping_mall_order_items where shopping_mall_shipment_id equals this shipment's id, checking that at least one item exists and all associated items have status = "shipped". Return 422 Unprocessable Entity if no order items reference this shipment or if any associated item is not in "shipped" status (e.g., still "paid" or already "delivered"/"cancelled"/"refunded").
 *
 * Within a database transaction:
 * 1. Set the shipment's delivered_at to the current timestamp (NOW()).
 * 2. Update the shipment's updated_at to NOW().
 * 3. Update all shopping_mall_order_items where shopping_mall_shipment_id equals this shipment's id: set status from "shipped" to "delivered", and set updated_at to NOW().
 *
 * Return the updated shipment record including: id, shopping_mall_order_id, shopping_mall_seller_id, carrier_name, tracking_number, delivered_at (now set), created_at, updated_at.
 *
 * Edge case — auto-delivery: if a customer has not called this endpoint within 14 calendar days of the shipment's created_at, a scheduled job or background process shall perform the same delivery confirmation logic automatically. The auto-delivery mechanism is not part of this endpoint but is noted for completeness.
 * @path /shoppingMall/customer/shipments/:shipmentId/confirm-delivery
 * @accessor api.functional.shoppingMall.customer.shipments.confirm_delivery.confirmDelivery
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function confirmDelivery(
  connection: IConnection,
  props: confirmDelivery.Props,
): Promise<confirmDelivery.Response> {
  return true === connection.simulate
    ? confirmDelivery.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...confirmDelivery.METADATA,
          path: confirmDelivery.path(props),
          status: null,
        },
      );
}
