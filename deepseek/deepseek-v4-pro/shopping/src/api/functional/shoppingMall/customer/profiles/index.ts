import { IShoppingMallSellerProfile } from "../../../../structures/IShoppingMallSellerProfile";

/**
 * Retrieve a seller's public profile by its unique identifier.
 *
 * Returns the seller's storefront identity including the shop name displayed on product pages, the shop description shown on the full profile page, and the logo image URI. This endpoint powers the seller profile view accessible to customers when clicking a seller's shop name link on product detail pages, search results, and order history.
 *
 * Profile visibility: seller profiles are publicly accessible to all authenticated customers. When a seller account is suspended, the profile remains visible — only the seller's products are hidden from search and category listings. Administrators can view any seller profile for review purposes but cannot modify profile fields.
 *
 * This endpoint returns the current state of the profile only. Historical profile snapshots created during edits are not included in this response.
 *
 * @param props.connection
 * @param props.profileId Unique identifier of the seller profile to retrieve.
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor customer
 * @x-autobe-specification Query the shopping_mall_seller_profiles table by
 *   primary key id matching the profileId path parameter.
 *
 * Join with shopping_mall_sellers to verify the seller account exists — return 404 if no profile is found for the given ID.
 *
 * Return the current profile state: shop_name, shop_description, logo_image_uri, created_at, updated_at, and the associated seller ID. Do not include snapshot history in this response; snapshots are accessible through a separate endpoint.
 *
 * This is a read-only operation. No data mutation occurs.
 *
 * Authorization: customers can view any seller's profile. Administrators can view any seller's profile. The owning seller can view their own profile. Unauthenticated guests should be denied access.
 * @path /shoppingMall/customer/profiles/:profileId
 * @accessor api.functional.shoppingMall.customer.profiles.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique identifier of the seller profile to retrieve.
     */
    profileId: string & tags.Format<"uuid">;
  };
  export type Response = IShoppingMallSellerProfile;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/customer/profiles/:profileId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/customer/profiles/${encodeURIComponent(props.profileId ?? "null")}`;
  export const random = (): IShoppingMallSellerProfile =>
    typia.random<IShoppingMallSellerProfile>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("profileId")(() => typia.assert(props.profileId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
