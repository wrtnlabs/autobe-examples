/**
 * Retrieves aggregated review statistics for a specific product.
 *
 * Returns the average star rating and total review count computed from all non-deleted reviews for the specified product. The average rating is rounded to one decimal place and ranges from 0.0 to 5.0.
 *
 * When the product has no reviews, both the average rating and total count are returned as zero. Soft-deleted reviews are excluded from both calculations, ensuring that only currently visible reviews contribute to the displayed statistics.
 *
 * @param props.connection
 * @param props.productId Unique identifier of the product whose review statistics are being retrieved.
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor customer
 * @x-autobe-specification Query the shopping_mall_review_reviews table for all
 *   reviews belonging to the product identified by {productId} where deleted_at
 *   IS NULL.
 *
 * Compute the average rating by summing all rating values and dividing by the count of non-deleted reviews. Round the result to one decimal place. If there are no non-deleted reviews, return an average rating of 0 and a total count of 0.
 *
 * Compute the total review count as the number of non-deleted reviews for this product.
 *
 * No pagination is needed — this endpoint returns only the two aggregate values.
 *
 * Verify that the product exists in shopping_mall_products before querying reviews. If the product does not exist or has been soft-deleted (deleted_at IS NOT NULL), return a 404 error.
 * @path /shoppingMall/customer/products/:productId/review-statistics
 * @accessor api.functional.shoppingMall.customer.products.review_statistics.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique identifier of the product whose review statistics are being retrieved.
     */
    productId: string & tags.Format<"uuid">;
  };
  export type Response = IShoppingMallReviewStatistic;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/customer/products/:productId/review-statistics",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/customer/products/${encodeURIComponent(props.productId ?? "null")}/review-statistics`;
  export const random = (): IShoppingMallReviewStatistic =>
    typia.random<IShoppingMallReviewStatistic>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("productId")(() => typia.assert(props.productId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
