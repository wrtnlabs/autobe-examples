/**
 * Register a new customer account on the platform.
 *
 * Creates a customer record with the provided email, password, and display name. The email serves as the unique login identifier across all customer accounts and must not already be registered. The display name is set at registration and will be publicly visible on reviews and profile pages.
 *
 * Upon successful registration, an access token and refresh token pair is issued, establishing an authenticated session immediately. A verification email is also sent to the provided email address containing a unique, time-limited token link that must be confirmed to complete the registration process.
 *
 * The password is stored as a cryptographic hash using a secure one-way algorithm; the plain-text password is never persisted. If the email is already associated with an active customer account, the registration is rejected with a conflict error.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Customer registration request containing email, password, and display name.
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor customer
 * @x-autobe-specification Create a new customer account with email, password,
 *   and display_name. Hash the password using bcrypt or argon2 before storage.
 *   Generate a unique UUID for the customer id. Set created_at and updated_at
 *   to the current timestamp. Check that the email is not already in use by an
 *   existing non-deleted customer (shopping_mall_customers.email unique
 *   constraint, where deleted_at IS NULL). If the email is already taken by an
 *   active account, return 409 Conflict. If the email belongs to a soft-deleted
 *   account, treat as available (the old account is no longer active). After
 *   successful account creation, generate a JWT access token (short-lived,
 *   e.g., 15 minutes) and refresh token (longer-lived, e.g., 7 days). Create a
 *   session record in shopping_mall_customer_sessions with the customer id,
 *   client IP address, href (originating page URL), referrer, created_at (now),
 *   and expired_at (7 days from now). Generate an email verification token
 *   (cryptographically random), store it in
 *   shopping_mall_customer_email_verifications with the customer id, token,
 *   expired_at (24 hours from now), and created_at (now). Send the verification
 *   email. Return the access token, refresh token, and session information in
 *   the IAuthorized response structure. Apply rate limiting: max 5 registration
 *   attempts per IP per hour to prevent abuse.
 * @path /shoppingMall/auth/customer/join
 * @accessor api.functional.shoppingMall.auth.customer.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
