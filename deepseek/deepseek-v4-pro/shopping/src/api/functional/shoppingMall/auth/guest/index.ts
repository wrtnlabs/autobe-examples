/**
 * Register or identify a guest visitor using a device fingerprint and obtain JWT session tokens.
 *
 * This endpoint serves as the entry point for all unauthenticated visitors to the platform. Guests identify themselves via a unique device fingerprint — a string generated from client-side device characteristics (browser, OS, screen resolution, etc.). The platform uses this fingerprint to associate session tokens and maintain continuity across page visits before the guest registers or logs in as a customer, seller, or administrator.
 *
 * The operation is idempotent: if a guest with the same device fingerprint already exists (and has not been cleaned up), a new session is created for the existing guest record rather than creating a duplicate. The `shopping_mall_guests` table enforces uniqueness on `device_fingerprint` via the `@@unique` constraint.
 *
 * On success, the response includes an access token (short-lived, for API authorization) and a refresh token (longer-lived, for obtaining new access tokens without re-identifying). The access token embeds the guest ID and session ID for downstream authorization checks.
 *
 * Guest sessions have an explicit expiration timestamp (`expired_at` in `shopping_mall_guest_sessions`). Once expired, the guest must re-establish identity through this endpoint — expired sessions cannot be refreshed.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Guest registration payload containing the device fingerprint for identification and session context information (IP address, current page URL, and referrer).
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor guest
 * @x-autobe-specification ## join — Guest Registration via Device Fingerprint
 *
 * ### Purpose
 * Create or identify a guest visitor by device fingerprint and issue JWT session tokens.
 *
 * ### Business Logic
 * 1. Extract `device_fingerprint`, `ip`, `href`, and `referrer` from the request body.
 * 2. Validate `device_fingerprint` is present and non-empty — return 400 if missing or empty.
 * 3. Query `shopping_mall_guests` by `device_fingerprint` (unique constraint, excluding soft-deleted):
 *    - **Found with deleted_at IS NULL**: Use the existing guest record. Skip creation.
 *    - **Found with deleted_at IS NOT NULL**: Treat as not found — create a new guest record.
 *    - **Not found**: Insert a new row into `shopping_mall_guests` with a new UUID `id`, the provided `device_fingerprint`, `created_at = now()`, `updated_at = now()`, `deleted_at = null`.
 * 4. Create a new session in `shopping_mall_guest_sessions`:
 *    - Generate a new UUID `id`.
 *    - Set `shopping_mall_guest_id` to the guest's `id`.
 *    - Set `ip`, `href`, and `referrer` from the request body.
 *    - Set `created_at = now()`.
 *    - Set `expired_at = now() + session_ttl` (e.g., 24 hours for guest sessions).
 * 5. Generate a JWT access token embedding `{ sub: guest.id, session_id: session.id }` with short TTL (e.g., 15 minutes).
 * 6. Generate a JWT refresh token embedding `{ sub: guest.id, session_id: session.id }` with longer TTL (e.g., 24 hours).
 * 7. Return `IShoppingMallGuest.IAuthorized` containing `access_token`, `refresh_token`, `guest_id`, and `expires_at` (the access token expiration timestamp).
 *
 * ### Edge Cases
 * - **Missing device_fingerprint**: Return 400 Bad Request.
 * - **Empty device_fingerprint**: Return 400 Bad Request.
 * - **Guest previously soft-deleted**: Treated as new — create a fresh guest record.
 *
 * ### Database Operations
 * - SELECT from `shopping_mall_guests` WHERE `device_fingerprint = $1` AND `deleted_at IS NULL`
 * - INSERT into `shopping_mall_guests` (if not found)
 * - INSERT into `shopping_mall_guest_sessions`
 *
 * ### Security
 * - JWT tokens signed with server private key.
 * - Access token TTL: 15 minutes.
 * - Refresh token TTL: 24 hours.
 * - IP address logged for audit purposes.
 * @path /shoppingMall/auth/guest/join
 * @accessor api.functional.shoppingMall.auth.guest.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
