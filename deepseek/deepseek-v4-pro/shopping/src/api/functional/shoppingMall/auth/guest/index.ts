/**
 * Refresh an expired guest access token using a valid refresh token and obtain a new JWT token pair.
 *
 * Guest sessions have explicit expiration boundaries (`expired_at` in `shopping_mall_guest_sessions`). When an access token expires, the guest can use this endpoint with their refresh token to obtain a new access token without re-identifying via device fingerprint. This provides session continuity for guests navigating between login and registration pages.
 *
 * Each successful refresh creates a new session record in `shopping_mall_guest_sessions` — sessions follow an append-only audit trail pattern. The new session carries forward the guest identity but with fresh `ip`, `href`, and `referrer` values from the current request context. The old session remains preserved for audit purposes.
 *
 * Refresh tokens are single-use in practice: each refresh issues a new refresh token, and clients should discard the old one. If a refresh token has expired or the associated session has passed its `expired_at`, the guest must re-establish identity through the join endpoint (`/auth/guest/join`).
 *
 * This endpoint requires no prior authentication — the refresh token itself serves as the credential.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Token refresh payload containing the current refresh token to be exchanged for a new token pair, along with updated session context (IP address, current page URL, and referrer).
 * @x-autobe-authorization-type refresh
 * @x-autobe-authorization-actor guest
 * @x-autobe-specification ## refresh — Guest Session Token Renewal
 *
 * ### Purpose
 * Validate an existing guest refresh token and issue a new JWT token pair with a new session.
 *
 * ### Business Logic
 * 1. Extract `refresh_token` from the request body. Return 400 if missing.
 * 2. Decode and validate the JWT refresh token:
 *    - Verify signature using the server's public key.
 *    - Verify the token has not expired (check `exp` claim).
 *    - Extract `sub` (guest_id) and `session_id` claims.
 *    - If any step fails: return 401 Unauthorized.
 * 3. Query `shopping_mall_guest_sessions` by `id = session_id`:
 *    - Verify the session exists and belongs to the guest (`shopping_mall_guest_id = guest_id`).
 *    - Verify the session has not expired (`expired_at > now()`).
 *    - If any check fails: return 401 Unauthorized.
 * 4. Query `shopping_mall_guests` by `id = guest_id`:
 *    - Verify the guest exists and `deleted_at IS NULL`.
 *    - If not found: return 401 Unauthorized.
 * 5. Create a **new** session in `shopping_mall_guest_sessions` (append-only pattern):
 *    - Generate a new UUID `id`.
 *    - Set `shopping_mall_guest_id` to the guest's `id`.
 *    - Set `ip`, `href`, and `referrer` from the request body.
 *    - Set `created_at = now()`.
 *    - Set `expired_at = now() + session_ttl`.
 * 6. Generate a new JWT access token embedding `{ sub: guest.id, session_id: new_session.id }`.
 * 7. Generate a new JWT refresh token embedding `{ sub: guest.id, session_id: new_session.id }`.
 * 8. Return `IShoppingMallGuest.IAuthorized` with the new token pair.
 *
 * ### Token Rotation
 * Each refresh creates a new session and issues new tokens. The old session remains in the database as an audit record. Clients should discard old tokens upon receiving new ones.
 *
 * ### Edge Cases
 * - **Expired refresh token**: Return 401 Unauthorized — re-identify via `/auth/guest/join`.
 * - **Tampered token**: Return 401 Unauthorized.
 * - **Session expired in DB**: Return 401 Unauthorized even if JWT is technically valid.
 * - **Deleted guest**: Return 401 Unauthorized.
 * - **Missing refresh_token**: Return 400 Bad Request.
 *
 * ### Database Operations
 * - SELECT from `shopping_mall_guest_sessions` WHERE `id = $1`
 * - SELECT from `shopping_mall_guests` WHERE `id = $1` AND `deleted_at IS NULL`
 * - INSERT into `shopping_mall_guest_sessions`
 *
 * ### Security
 * - Refresh tokens have finite TTL; guests must re-identify after expiration.
 * - Each refresh creates a new session — old sessions never mutated, preserving audit trail.
 * - IP address logged in each new session for security analysis.
 * @path /shoppingMall/auth/guest/refresh
 * @accessor api.functional.shoppingMall.auth.guest.refresh
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
