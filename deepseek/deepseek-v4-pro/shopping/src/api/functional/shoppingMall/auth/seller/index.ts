/**
 * Register a new seller account on the platform.
 *
 * Creates a seller account with the provided email and password. The new seller starts in "pending" approval status and must be approved by an administrator before gaining access to product management, order processing, and the seller dashboard.
 *
 * Upon successful registration, the seller is automatically authenticated — an access token and refresh token pair are issued. The session is recorded in shopping_mall_seller_sessions with the client's IP address, the page URL (href), and the HTTP referrer for security auditing.
 *
 * The access token is short-lived and used to authenticate subsequent API requests. The refresh token is longer-lived and can be used to obtain new access tokens without re-entering credentials.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Seller registration credentials containing email and password.
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor seller
 * @x-autobe-specification Register a new seller account with email and
 *   password.
 *
 * Implementation:
 * 1. Validate email format and uniqueness (shopping_mall_sellers has @@unique on email)
 * 2. Validate password meets minimum strength requirements (minimum 8 characters)
 * 3. Hash password using bcrypt, store in password_hash column
 * 4. Insert into shopping_mall_sellers with approval_status = 'pending'
 * 5. Create session in shopping_mall_seller_sessions: seller_id, ip, href, referrer, created_at (now), expired_at (refresh token lifetime)
 * 6. Generate JWT access token and refresh token bound to the session id
 * 7. Return both tokens with expiration timestamps
 *
 * Edge cases:
 * - Email already registered: 409 Conflict
 * - Invalid email format: 400 Bad Request
 * - Password too short/weak: 400 Bad Request
 * @path /shoppingMall/auth/seller/join
 * @accessor api.functional.shoppingMall.auth.seller.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
