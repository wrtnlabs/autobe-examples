/**
 * Register a new administrator account on the platform.
 *
 * Creates a new administrator account with the provided email and password. The account is assigned the 'regular' grade by default. Upon successful registration, an authenticated session is created immediately and JWT tokens are returned — no separate login step is required.
 *
 * Email must be unique across all active administrator accounts. The password must meet minimum security requirements (length and complexity). The password is stored using a one-way cryptographic hash and is never logged or returned in responses.
 *
 * After registration, the administrator can immediately access admin-protected endpoints using the returned access token. The refresh token can be used to obtain new tokens before the current ones expire.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Administrator registration payload containing the email and password for the new admin account.
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor admin
 * @x-autobe-specification Create a new administrator account. Validate that the
 *   email is unique across shopping_mall_admins (excluding soft-deleted records
 *   where deleted_at IS NOT NULL). Hash the password using a cryptographically
 *   secure algorithm (bcrypt or argon2). The grade defaults to 'regular'.
 *   Insert into shopping_mall_admins with created_at and updated_at set to now.
 *   Create an initial session in shopping_mall_admin_sessions with the admin's
 *   IP, href, and referrer from the request context. Generate access and
 *   refresh JWT tokens. Set expired_at for the session based on the access
 *   token expiry. Return IShoppingMallAdmin.IAuthorized containing the access
 *   token, refresh token, and expiration timestamps. If the email already
 *   exists on an active (non-deleted) admin, return 409 Conflict.
 * @path /shoppingMall/auth/admin/join
 * @accessor api.functional.shoppingMall.auth.admin.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
