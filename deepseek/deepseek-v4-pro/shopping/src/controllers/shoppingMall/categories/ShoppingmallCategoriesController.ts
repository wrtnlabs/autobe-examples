import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallCategory } from "../../../api/structures/IPageIShoppingMallCategory";
import { IShoppingMallCategory } from "../../../api/structures/IShoppingMallCategory";
import { getShoppingMallCategoriesCategoryId } from "../../../providers/getShoppingMallCategoriesCategoryId";
import { patchShoppingMallCategories } from "../../../providers/patchShoppingMallCategories";

@Controller("/shoppingMall/categories")
export class ShoppingmallCategoriesController {
  /**
   * Browse the platform's category catalog with search and filtering capabilities.
   *
   * Returns a paginated list of active product categories. Categories form a two-tier hierarchy: top-level parent categories and their immediate subcategories. This endpoint supports browsing all categories at once or filtering to a specific view — for example, listing only top-level categories to build a navigation menu, or listing subcategories belonging to a particular parent.
   *
   * Name search uses fuzzy text matching, allowing customers and administrators to find categories by partial name input. Filtering by parent ID enables hierarchical browsing patterns common in e-commerce navigation.
   *
   * The response includes subcategory counts for each category, so consumers can determine which categories have children without making additional API calls. Soft-deleted categories are excluded from results — once an administrator removes a category, it disappears from all listings while preserving referential integrity for existing product assignments.
   *
   * @param connection
   * @param body Search and filter criteria for browsing categories. Supports searching by name (partial match via trigram), filtering by parent category to view top-level or specific subcategories, and pagination controls.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor null
     * @x-autobe-specification Query the shopping_mall_categories table with
     *   pagination and optional filters.
   *
   * Only return categories where deleted_at IS NULL (active categories). Apply the following optional filters from the request body:
   * - name: partial text search using trigram similarity (leverages the gin_trgm_ops index on the name column)
   * - parentId: filter by parent category — when provided, return only subcategories belonging to that parent; when explicitly null, return only top-level categories (parent_id IS NULL); when omitted, return all categories regardless of nesting level
   *
   * Support pagination via cursor-based or offset-based pagination parameters. Return results as IPageIShoppingMallCategory.ISummary, where each summary record includes the category's id, name, description, parentId (if any), and timestamps.
   *
   * Include subcategory count in each summary record if the category has children. This helps consumers know which categories can be expanded to view subcategories.
   *
   * Sort results by created_at in descending order (newest first) by default, or by the requested sort parameter.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IShoppingMallCategory.IRequest,
  ): Promise<IPageIShoppingMallCategory.ISummary> {
    try {
      return await patchShoppingMallCategories({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves a single category by its unique identifier.
   *
   * The response includes the category's name, description, creation and update timestamps, as well as its parent category (if it is a subcategory) and its immediate child subcategories (if it is a parent category). This enables clients to render the category's position within the two-level hierarchy.
   *
   * Soft-deleted categories are treated as nonexistent and will return a 404 response.
   *
   * @param connection
   * @param categoryId Unique identifier of the category to retrieve.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor null
     * @x-autobe-specification Query the `shopping_mall_categories` table by
     *   primary key `id` matching the `categoryId` path parameter.
   *
   * Exclude soft-deleted records: if `deleted_at` is not null, return a 404 Not Found response as if the category does not exist.
   *
   * Include the recursive `parent` relation to provide the parent category (if any) for hierarchy context. Include the recursive `children` relation to provide immediate subcategories for nesting display.
   *
   * Return 404 if no matching active category is found.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":categoryId")
  public async at(
    @TypedParam("categoryId")
    categoryId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallCategory> {
    try {
      return await getShoppingMallCategoriesCategoryId({
        categoryId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
