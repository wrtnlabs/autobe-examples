import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallGuest } from "../../../../api/structures/IPageIShoppingMallGuest";
import { IShoppingMallGuest } from "../../../../api/structures/IShoppingMallGuest";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminGuestsGuestId } from "../../../../providers/getShoppingMallAdminGuestsGuestId";
import { patchShoppingMallAdminGuests } from "../../../../providers/patchShoppingMallAdminGuests";

@Controller("/shoppingMall/admin/guests")
export class ShoppingmallAdminGuestsController {
  /**
   * Searches and lists guest visitor records with pagination and filtering.
   *
   * Guests are unauthenticated visitors to the platform identified by device fingerprint. This endpoint allows administrators to browse guest records for security auditing, traffic analysis, and monitoring of unauthenticated access patterns.
   *
   * Search filters support matching by device fingerprint, filtering by creation and last-activity date ranges, and toggling between active and cleaned-up guests. Results are paginated and sorted by most recent first by default.
   *
   * @param connection
   * @param body Search criteria for filtering and paginating guest records. Supports device fingerprint matching, date range filters on creation and last activity timestamps, active/inactive filtering, and pagination controls.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification Query the shopping_mall_guests table with
     *   pagination and filtering.
   *
   * Apply search filters:
   * - device_fingerprint: partial or exact match on the device fingerprint string
   * - created_at range: filter by guest creation (first visit) date range
   * - updated_at range: filter by last activity date range
   * - active_only: when true, exclude guests where deleted_at IS NOT NULL (cleaned up guests)
   *
   * Return cursor-based or offset-based pagination for potentially large result sets. Default sort by created_at descending (newest first). Support sort direction control.
   *
   * Exclude sensitive internal fields from the summary response. Each summary record should include id, device_fingerprint (optionally masked), created_at, updated_at, and whether the guest is active (deleted_at IS NULL).
   *
   * Do NOT expose session tokens or internal session data through this endpoint.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallGuest.IRequest,
  ): Promise<IPageIShoppingMallGuest.ISummary> {
    try {
      return await patchShoppingMallAdminGuests({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves a single guest record by its unique identifier.
   *
   * A guest is a temporary account created for each unauthenticated visitor to the platform. Each guest is identified by a device fingerprint and tracked from their first visit until they register, log in, or the account expires. This endpoint returns the full guest record including the device fingerprint, creation timestamp, last update timestamp, and soft-delete status.
   *
   * This operation is designed for administrative inspection of visitor records. Guests themselves are unauthenticated — they are limited to the login and registration pages only and cannot access this or any other authenticated endpoint.
   *
   * @param connection
   * @param guestId The unique identifier of the guest record to retrieve (UUID format).
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification Query the shopping_mall_guests table by primary
     *   key matching the given guestId.
   *
   * Return the full guest record including all columns: id, device_fingerprint, created_at, updated_at, and deleted_at. If no record exists with the given guestId, return a 404 Not Found error.
   *
   * Do not filter by deleted_at — return the record regardless of soft-delete status so that administrators can inspect all guest records, including those that have been cleaned up during periodic maintenance.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":guestId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("guestId")
    guestId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallGuest> {
    try {
      return await getShoppingMallAdminGuestsGuestId({
        admin,
        guestId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
