import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallAdminSession } from "../../../../../api/structures/IPageIShoppingMallAdminSession";
import { IShoppingMallAdminSession } from "../../../../../api/structures/IShoppingMallAdminSession";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminAdminsAdminIdSessionsSessionId } from "../../../../../providers/getShoppingMallAdminAdminsAdminIdSessionsSessionId";
import { patchShoppingMallAdminAdminsAdminIdSessions } from "../../../../../providers/patchShoppingMallAdminAdminsAdminIdSessions";

@Controller("/shoppingMall/admin/admins/:adminId/sessions")
export class ShoppingmallAdminAdminsSessionsController {
  /**
   * Lists administrator session records for security auditing and access pattern review.
   *
   * Each session represents an authenticated login by an administrator, capturing the IP address, page URL at session creation, referral source, and the session's valid time window (from creation to expiration). This data enables security teams to audit administrator access patterns, detect anomalies such as geographically implausible logins, and review the timeline of administrative activity.
   *
   * Sessions are managed automatically by the authentication system — created on successful login and invalidated on logout or expiration. They cannot be created, modified, or deleted through this API. The listing is strictly read-only.
   *
   * Results are paginated and sorted with the most recent sessions first. Use the request body to filter by date range, expiration status, or IP address for targeted security investigations.
   *
   * @param connection
   * @param adminId Unique identifier of the administrator whose sessions are being listed. (global scope — each administrator has a single account identified by UUID)
   * @param body Search criteria for filtering administrator sessions, including date range filters (created_at, expired_at), expiration status filter, IP address search, and pagination parameters.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification Query the shopping_mall_admin_sessions table
     *   filtered by shopping_mall_admin_id matching the {adminId} path
     *   parameter.
   *
   * Use the composite index @@index([shopping_mall_admin_id, created_at]) for efficient ordering and cursor-based pagination. Sessions are append-only audit records — never create, update, or delete them through this API.
   *
   * Search/filter support:
   * - Date range: filter by created_at (session start time) and expired_at (session end time) ranges
   * - Expiration status: filter for active sessions (expired_at > now), expired sessions (expired_at <= now), or both
   * - IP address: partial match search on the ip field for security investigation
   *
   * Default sort: created_at descending (newest sessions first).
   *
   * Validate that {adminId} references an existing, non-deleted administrator (deleted_at IS NULL on shopping_mall_admins). Return 404 if the administrator is not found or has been soft-deleted.
   *
   * This is a security-sensitive endpoint. Limit access to authenticated administrators. Super administrators may view sessions of any administrator; regular administrators may only view their own sessions.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallAdminSession.IRequest,
  ): Promise<IPageIShoppingMallAdminSession.ISummary> {
    try {
      return await patchShoppingMallAdminAdminsAdminIdSessions({
        admin,
        adminId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves the full details of a single administrator session record.
   *
   * This endpoint returns the complete session information for security auditing purposes. Each session record captures the context in which an administrator logged in — the originating IP address, the page they were viewing at the time, and the referring source. The creation and expiration timestamps define the session's valid authentication window.
   *
   * Session records are immutable audit trail entries. They are created automatically upon successful administrator login and invalidated upon logout or expiration. This endpoint provides read-only access to these records; sessions cannot be created, modified, or deleted through direct API calls.
   *
   * @param connection
   * @param adminId Unique identifier of the administrator who owns the session. The session must belong to this administrator.
   * @param sessionId Unique identifier of the session record to retrieve.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification Retrieve the shopping_mall_admin_sessions record
     *   with the given sessionId, ensuring it belongs to the administrator
     *   identified by adminId (shopping_mall_admin_id must match).
   *
   * Query: SELECT * FROM shopping_mall_admin_sessions WHERE id = :sessionId AND shopping_mall_admin_id = :adminId.
   *
   * If the session does not exist or does not belong to the specified administrator, return 404 Not Found.
   *
   * The session includes the administrator's IP address at login time, the page URL (href) they were on, the referring URL (referrer), the creation timestamp (created_at), and the expiration timestamp (expired_at).
   *
   * If the session's expired_at has passed, the session is considered expired and invalid for authentication, but the record remains readable for audit purposes.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallAdminSession> {
    try {
      return await getShoppingMallAdminAdminsAdminIdSessionsSessionId({
        admin,
        adminId,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
