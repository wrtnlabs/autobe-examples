import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IPageIShoppingMallOrder } from "../../../../api/structures/IPageIShoppingMallOrder";
import { IShoppingMallOrder } from "../../../../api/structures/IShoppingMallOrder";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminOrdersOrderCode } from "../../../../providers/getShoppingMallAdminOrdersOrderCode";
import { patchShoppingMallAdminOrders } from "../../../../providers/patchShoppingMallAdminOrders";

@Controller("/shoppingMall/admin/orders")
export class ShoppingmallAdminOrdersController {
  /**
   * Retrieves a paginated, filterable list of orders with newest orders displayed first.
   *
   * This endpoint provides the primary order browsing interface used by customers to review their purchase history, sellers to locate orders containing their products for fulfillment processing, and administrators to oversee all platform transactions. Each result entry includes the order number, placement date, total transaction amount, and the derived overall order status — the essential fields needed for list-level browsing and decision-making.
   *
   * The endpoint supports optional filtering by order status, date range, and order code to narrow results. Customers are automatically scoped to only their own orders, while administrators can optionally filter by customer to investigate specific accounts. Sellers see only orders that contain at least one of their products, enabling them to identify items requiring shipment, cancellation response, or refund processing.
   *
   * Results are always sorted with the most recently placed orders first, ensuring the most relevant and actionable orders appear at the top of the list. Pagination controls allow efficient navigation through large order histories without overwhelming the client.
   *
   * @param connection
   * @param body Search and filter criteria for browsing orders, including optional status filter, date range constraints, order code search, and pagination parameters. Customer-scoped automatically for non-admin actors.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification Query the shopping_mall_orders table with
     *   pagination, filtering, and sorting.
   *
   * **Actor-Based Scoping:**
   * - Customer: results are automatically scoped to shopping_mall_customer_id matching the authenticated customer. No explicit customer filter is available.
   * - Seller: results are scoped to orders containing at least one order item belonging to the seller's products. Join through shopping_mall_order_items where the variant's parent product belongs to the seller.
   * - Administrator: full access to all orders. Can optionally filter by customer ID.
   *
   * **Filtering:**
   * Apply optional filters from the request body:
   * - orderCode: partial or exact match against the unique code field
   * - status: filter by order status (paid, shipped, delivered, cancelled, refunded, partially_completed)
   * - createdAfter / createdBefore: date range filter on created_at
   * - customerId: (admin only) filter by shopping_mall_customer_id
   *
   * **Sorting:**
   * Always sort by created_at in descending order (newest first). No alternative sort options.
   *
   * **Pagination:**
   * Use offset-based pagination with page and limit parameters. Default limit is 20 items per page. Return total count for pagination metadata.
   *
   * **Soft-Delete Exclusion:**
   * Exclude records where deleted_at is not null.
   *
   * **Status Derivation:**
   * The status field is derived from order item statuses at write time and stored. No runtime aggregation from order items is needed for list display.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallOrder.IRequest,
  ): Promise<IPageIShoppingMallOrder.ISummary> {
    try {
      return await patchShoppingMallAdminOrders({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves the complete details of a single order by its order number.
   *
   * The response includes the full order metadata — order number, placement date, total price, and the overall order status derived from its constituent items. The frozen shipping address (recipient name, phone number, street address, city, state/province, postal code, and country) is returned exactly as captured at checkout time.
   *
   * Each order item includes the product name, variant SKU code and option values, quantity purchased, and unit price — all frozen via snapshots taken at the moment of purchase to guarantee historical accuracy regardless of later product or pricing changes. The seller's shop name at the time of purchase is also preserved per item. Every item's current lifecycle status (paid, shipped, delivered, cancelled, refunded) is reported individually.
   *
   * All shipments associated with the order are listed with their carrier name, tracking number, shipping date, and delivery confirmation status. The relationship between shipments and the order items they contain is fully mapped, showing which items traveled together in each package.
   *
   * @param connection
   * @param orderCode The human-readable order number uniquely identifying the order (global scope).
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification Query shopping_mall_orders by the unique code
     *   field to retrieve a single order. Join shopping_mall_order_items for
     *   the list of purchased line items, and for each order item join
     *   shopping_mall_order_item_product_snapshots (for product name at
     *   purchase time), shopping_mall_order_item_variant_snapshots (for SKU
     *   code, option values, and price at purchase), and
     *   shopping_mall_order_item_seller_snapshots (for seller shop name at
     *   purchase).
   *
   * Join shopping_mall_shipments filtered by shopping_mall_order_id to retrieve all shipments for this order. For each shipment, include carrier_name, tracking_number, created_at (shipping date), and delivered_at (delivery confirmation timestamp). Map each order item to its shipment via shopping_mall_shipment_id.
   *
   * Return the denormalized shipping address fields directly from the order (recipient_name, phone_number, street_address, city, state_province, postal_code, country) — these are frozen at checkout and immutable.
   *
   * The order status field is derived from item statuses and stored on the order record, updated automatically when any item's status changes. Return it as-is.
   *
   * Error handling: return 404 if no order exists with the given code. Apply data access control — customers can only view their own orders; sellers can view orders containing their items; administrators can view any order.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":orderCode")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("orderCode")
    orderCode: string,
  ): Promise<IShoppingMallOrder> {
    try {
      return await getShoppingMallAdminOrdersOrderCode({
        admin,
        orderCode,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
