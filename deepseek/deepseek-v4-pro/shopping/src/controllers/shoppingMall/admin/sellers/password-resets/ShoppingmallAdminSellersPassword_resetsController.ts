import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallSellerPasswordReset } from "../../../../../api/structures/IPageIShoppingMallSellerPasswordReset";
import { IShoppingMallSellerPasswordReset } from "../../../../../api/structures/IShoppingMallSellerPasswordReset";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminSellersSellerIdPasswordResetsResetId } from "../../../../../providers/getShoppingMallAdminSellersSellerIdPasswordResetsResetId";
import { patchShoppingMallAdminSellersSellerIdPasswordResets } from "../../../../../providers/patchShoppingMallAdminSellersSellerIdPasswordResets";

@Controller("/shoppingMall/admin/sellers/:sellerId/password-resets")
export class ShoppingmallAdminSellersPassword_resetsController {
  /**
   * Retrieve a paginated list of password reset token records for a specific seller.
   *
   * This endpoint provides administrative visibility into the password reset history of a seller account. Each record indicates when a password reset was requested, whether the token has expired, and the token's creation timestamp. The actual reset tokens are never exposed in the response for security reasons.
   *
   * Results are sorted newest-first and support filtering by date range and expiry status. Pagination is provided for efficient browsing of large result sets.
   *
   * @param connection
   * @param sellerId Unique identifier of the seller whose password reset history to retrieve. (UUID format)
   * @param body Search and filter criteria including optional date range on created_at, expiry status filter (active, expired, or all), and pagination parameters.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification Query the shopping_mall_seller_password_resets
     *   table filtered by shopping_mall_seller_id matching {sellerId}.
   *
   * Apply optional filters from the request body:
   * - Date range filter on created_at (from/to)
   * - Expiry status filter: active (expired_at > now), expired (expired_at <= now), or all
   *
   * Sort results by created_at descending (newest first). Apply cursor-based or offset-based pagination.
   *
   * Return a paginated summary containing for each record: id, whether the token is expired, created_at, and expired_at. Do NOT expose the raw token value in summary responses — the token is a security credential. Provide only a masked indicator (e.g., whether a token exists and its expiry status).
   *
   * This operation does not modify any data. Only administrators should have access to this endpoint as part of seller account oversight.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallSellerPasswordReset.IRequest,
  ): Promise<IPageIShoppingMallSellerPasswordReset.ISummary> {
    try {
      return await patchShoppingMallAdminSellersSellerIdPasswordResets({
        admin,
        sellerId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves a single password reset token record for a specific seller.
   *
   * This endpoint returns the full details of a password reset request, including the cryptographically random token value, its expiration timestamp, and creation metadata. It is used during the password reset flow to allow the seller or an administrator to verify whether a reset token is still active and valid before authorizing a password change.
   *
   * Each password reset token is single-use and time-limited. After the expiration timestamp passes, the token can no longer be used to authorize a password change, and the seller must request a new password reset. The token is stored as a unique string to prevent accidental collisions.
   *
   * Access to this endpoint is restricted: a seller may only view their own password reset tokens, while administrators may view any seller's tokens for oversight and audit purposes.
   *
   * @param connection
   * @param sellerId Unique identifier of the seller who owns the password reset token. Must match the shopping_mall_seller_id on the password reset record.
   * @param resetId Unique identifier of the password reset token record to retrieve.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification Query the shopping_mall_seller_password_resets
     *   table by primary key id matching the {resetId} path parameter.
   *
   * Verify that the record's shopping_mall_seller_id matches the {sellerId} path parameter. If it does not match, return a 404 Not Found error to prevent cross-seller access to another seller's password reset tokens.
   *
   * If the record is not found by id, return a 404 Not Found error.
   *
   * Return the full password reset record including: id, token, expired_at, created_at, and updated_at. The token field is the cryptographically random value sent to the seller's email. It is returned in the response so the caller can verify which token they are inspecting and validate it against what was received via email.
   *
   * No soft-delete logic applies — password reset records follow their natural lifecycle and are not soft-deleted.
   *
   * Authorization: the authenticated seller can only access password reset tokens where shopping_mall_seller_id matches their own seller account id. Administrators may access any seller's password reset tokens for audit and oversight purposes.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":resetId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
    @TypedParam("resetId")
    resetId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallSellerPasswordReset> {
    try {
      return await getShoppingMallAdminSellersSellerIdPasswordResetsResetId({
        admin,
        sellerId,
        resetId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
