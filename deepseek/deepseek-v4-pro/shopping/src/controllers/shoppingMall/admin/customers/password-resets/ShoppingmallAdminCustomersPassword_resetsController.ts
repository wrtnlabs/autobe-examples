import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallCustomerPasswordReset } from "../../../../../api/structures/IPageIShoppingMallCustomerPasswordReset";
import { IShoppingMallCustomerPasswordReset } from "../../../../../api/structures/IShoppingMallCustomerPasswordReset";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminCustomersCustomerIdPasswordResetsResetId } from "../../../../../providers/getShoppingMallAdminCustomersCustomerIdPasswordResetsResetId";
