@Controller("/shoppingMall/admin/customers/:customerId/password-resets")
export class ShoppingmallAdminCustomersPassword_resetsController {
  /**
   * Retrieves a paginated list of password reset token records for a specific customer.
   *
   * Each record represents a password reset request initiated through the forgotten-password flow. Records include the token creation time, expiration time, and whether the token is still valid or has expired. Tokens are single-use and expire automatically after a fixed validity window.
   *
   * This endpoint supports filtering by token validity status and date range, with results sorted newest first. It is useful for customers reviewing their account security activity and for administrators auditing password reset patterns.
   *
   * @param connection
   * @param customerId Unique identifier of the customer whose password reset history is being retrieved.
   * @param body Search and filter criteria including optional token status filter (valid/expired), date range filters on creation timestamp, and pagination parameters.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification Query the shopping_mall_customer_password_resets
     *   table filtered by the customerId path parameter. This table is
     *   append-only — read only, never mutated through this endpoint.
   *
   * Apply optional filters from the request body:
   * - token status: filter by whether the token is still valid (expired_at > now) or expired (expired_at <= now)
   * - date range: filter by created_at range (start and end timestamps)
   *
   * Sort results by created_at descending (most recent first). Support cursor-based or offset pagination.
   *
   * Edge cases:
   * - If the customer does not exist, return 404
   * - If the customer has no reset history, return an empty page (not an error)
   * - Ensure only authorized actors can access this resource (customer viewing their own history, or administrators auditing any customer)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("customerId")
    customerId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallCustomerPasswordReset.IRequest,
  ): Promise<IPageIShoppingMallCustomerPasswordReset.ISummary> {
    try {
      return await patchShoppingMallAdminCustomersCustomerIdPasswordResets({
        admin,
        customerId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves a specific password reset token record for a customer.
   *
   * This endpoint returns the full details of a password reset record, including the cryptographic token string, its expiration timestamp, and creation time. The record is scoped to the specified customer — the resetId must belong to the given customerId, otherwise the request is rejected.
   *
   * Password reset tokens are generated when a customer initiates the "forgot password" flow. Each token is single-use, cryptographically random, and expires after a fixed validity window. Expired tokens are still returned by this endpoint for audit and support purposes.
   *
   * This operation is available to platform administrators for auditing password reset activities and assisting customers with account recovery inquiries.
   *
   * @param connection
   * @param customerId UUID of the customer account that owns the password reset record. The reset record must belong to this customer. (scoped to customer)
   * @param resetId UUID of the password reset record to retrieve.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification Query the shopping_mall_customer_password_resets
     *   table by the given resetId (UUID primary key). Verify that the record's
     *   shopping_mall_customer_id matches the provided customerId path
     *   parameter — if the record exists but belongs to a different customer,
     *   return a 404 error to prevent information leakage about other
     *   customers' reset tokens. If the record does not exist at all, return
     *   404. Return the full record including id, token, expired_at,
     *   created_at, and shopping_mall_customer_id. Expired tokens are still
     *   returned — expiration does not prevent retrieval for audit purposes. No
     *   updates or side effects are performed.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":resetId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("customerId")
    customerId: string & tags.Format<"uuid">,
    @TypedParam("resetId")
    resetId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallCustomerPasswordReset> {
    try {
      return await getShoppingMallAdminCustomersCustomerIdPasswordResetsResetId(
        {
          admin,
          customerId,
          resetId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
