import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallCustomerSession } from "../../../../../api/structures/IPageIShoppingMallCustomerSession";
import { IShoppingMallCustomerSession } from "../../../../../api/structures/IShoppingMallCustomerSession";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminCustomersCustomerIdSessionsSessionId } from "../../../../../providers/getShoppingMallAdminCustomersCustomerIdSessionsSessionId";
import { patchShoppingMallAdminCustomersCustomerIdSessions } from "../../../../../providers/patchShoppingMallAdminCustomersCustomerIdSessions";

@Controller("/shoppingMall/admin/customers/:customerId/sessions")
export class ShoppingmallAdminCustomersSessionsController {
  /**
   * Retrieves a paginated list of authentication sessions for a specific customer.
   *
   * Each session record represents a successful login event, capturing the client IP address, the page from which the customer initiated login, and the referring page. The session remains active until the customer explicitly logs out, the session expires naturally, or the system terminates it due to password change, account deletion, or ban.
   *
   * This endpoint supports filtering by IP address, session creation date range, and active/expired status, enabling administrators to audit login activity and identify unusual patterns. Sessions are returned in reverse chronological order with the most recent logins first.
   *
   * Access is restricted: administrators may view sessions for any customer, while customers may only view their own session history.
   *
   * @param connection
   * @param customerId Unique identifier of the customer whose sessions are being listed. Must be a valid UUID referencing an existing customer account.
   * @param body Search criteria and pagination parameters for listing customer sessions. Supports filtering by IP address, session creation date range, and active/expired status.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification Query the shopping_mall_customer_sessions table
     *   filtered by shopping_mall_customer_id matching the {customerId} path
     *   parameter.
   *
   * Apply pagination via cursor-based or offset-based pagination from the request body. Support filtering by:
   * - IP address (partial match)
   * - Date range on created_at (session start time)
   * - Expiration status: active (expired_at > now) vs. expired/terminated (expired_at <= now)
   * - Date range on expired_at (session end time)
   *
   * Sort by created_at descending by default (newest sessions first).
   *
   * Return a paginated summary including: session id, IP address, href (login origin page), referrer, created_at (session start), expired_at (session end/expiry), and an active flag derived from comparing expired_at to the current timestamp.
   *
   * Authorization: accessible by administrators (regular and super) for any customer; accessible by the customer themselves for their own sessions only.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("customerId")
    customerId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallCustomerSession.IRequest,
  ): Promise<IPageIShoppingMallCustomerSession.ISummary> {
    try {
      return await patchShoppingMallAdminCustomersCustomerIdSessions({
        admin,
        customerId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve the details of a specific customer authentication session.
   *
   * Returns the session record including the client IP address, originating page URL, HTTP referrer, creation timestamp, and expiration timestamp. This endpoint supports both customer self-service (viewing their own active and past sessions) and administrator security auditing (inspecting session history for any customer account).
   *
   * A session is considered active when the current time is before `expired_at`. Expired or terminated sessions (via logout, password change, account deletion, or ban) have `expired_at` set to the termination time and remain visible in history.
   *
   * @param connection
   * @param customerId Unique identifier of the customer account (global scope).
   * @param sessionId Unique identifier of the customer session (global scope).
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification Query the shopping_mall_customer_sessions table
     *   by session ID, ensuring the session belongs to the specified customer
     *   (shopping_mall_customer_id matches customerId).
   *
   * Authorization rules:
   * - A customer may only retrieve sessions belonging to their own account. Reject with 403 if the authenticated customer's ID does not match customerId.
   * - An administrator may retrieve sessions for any customer account.
   *
   * Return the full session record: id, ip, href, referrer, created_at, expired_at, and the associated customer ID (shopping_mall_customer_id).
   *
   * If no session exists with the given sessionId under the specified customerId, return 404.
   * If the customer account does not exist, return 404.
   *
   * No soft-delete filtering is needed on sessions — expired sessions remain queryable for audit purposes.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("customerId")
    customerId: string & tags.Format<"uuid">,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallCustomerSession> {
    try {
      return await getShoppingMallAdminCustomersCustomerIdSessionsSessionId({
        admin,
        customerId,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
