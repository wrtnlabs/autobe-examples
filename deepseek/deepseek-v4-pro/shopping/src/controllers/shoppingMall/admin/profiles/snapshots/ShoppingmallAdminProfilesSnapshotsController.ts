import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallSellerProfileSnapshot } from "../../../../../api/structures/IPageIShoppingMallSellerProfileSnapshot";
import { IShoppingMallSellerProfileSnapshot } from "../../../../../api/structures/IShoppingMallSellerProfileSnapshot";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminProfilesProfileIdSnapshotsSnapshotId } from "../../../../../providers/getShoppingMallAdminProfilesProfileIdSnapshotsSnapshotId";
import { patchShoppingMallAdminProfilesProfileIdSnapshots } from "../../../../../providers/patchShoppingMallAdminProfilesProfileIdSnapshots";

@Controller("/shoppingMall/admin/profiles/:profileId/snapshots")
export class ShoppingmallAdminProfilesSnapshotsController {
  /**
   * Retrieves a paginated list of immutable snapshot records for a seller profile.
   *
   * Each snapshot captures the complete state of the seller profile — shop name, shop description, and logo image — at the moment before an edit was applied. Snapshots are created automatically by the system whenever the seller modifies any profile field, providing a complete and permanent audit trail of all profile changes.
   *
   * Snapshots are read-only and are never deleted under any circumstance, even if the seller profile or seller account is later removed. This guarantees that historical seller information referenced by order records remains valid indefinitely for dispute resolution and historical accuracy.
   *
   * @param connection
   * @param profileId Unique identifier of the seller profile whose snapshot history is being requested.
   * @param body Search and filter criteria for browsing profile snapshots, including date range filters, sorting options, and pagination parameters.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification Query the shopping_mall_seller_profile_snapshots
     *   table filtered by the profile identified in the path.
   *
   * 1. Verify the profile exists by querying shopping_mall_seller_profiles by id. If not found, return 404.
   *
   * 2. Apply request body filters:
   *    - dateFrom / dateTo: Filter snapshots by created_at range (inclusive).
   *    - Sort by created_at (default: descending — newest first).
   *
   * 3. Apply cursor-based or offset pagination from the request body (page, limit).
   *
   * 4. Join with shopping_mall_seller_profiles if needed for context, but all snapshot fields (shop_name, shop_description, logo_image) are denormalized and self-contained.
   *
   * 5. Return paginated IShoppingMallSellerProfileSnapshot.ISummary records.
   *
   * Authorization:
   * - The seller who owns the profile can view their own snapshots.
   * - Administrators can view snapshots of any seller profile.
   * - Customers and guests have no access.
   *
   * Edge cases:
   * - Snapshots are immutable and never deleted. Even if the source profile or seller account is deleted, snapshots remain queryable.
   * - An empty result set is valid (profile exists but has never been edited, so no snapshots exist).
   * - The profile may have zero snapshots if it was created but never edited after initial creation.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("profileId")
    profileId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallSellerProfileSnapshot.IRequest,
  ): Promise<IPageIShoppingMallSellerProfileSnapshot.ISummary> {
    try {
      return await patchShoppingMallAdminProfilesProfileIdSnapshots({
        admin,
        profileId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves a single immutable seller profile snapshot.
   *
   * Seller profile snapshots are created automatically every time a seller edits their shop name, shop description, or logo image. Each snapshot preserves the complete state of the profile fields as they existed before the edit was applied, along with the timestamp of when the snapshot was captured.
   *
   * This endpoint returns the frozen historical data for a specific snapshot, including the shop name, shop description, and logo image at that point in time. The snapshot data is permanently immutable and cannot be modified or deleted by any actor.
   *
   * Sellers can view snapshots belonging to their own profile. Administrators can view any seller profile snapshot for oversight and dispute resolution purposes.
   *
   * @param connection
   * @param profileId Unique identifier of the seller profile whose snapshot is being retrieved (global scope).
   * @param snapshotId Unique identifier of the seller profile snapshot to retrieve (global scope).
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification Retrieve a single seller profile snapshot by its
     *   ID, scoped to the specified seller profile.
   *
   * Query the shopping_mall_seller_profile_snapshots table filtering by both id (snapshotId) and shopping_mall_seller_profile_id (profileId). If either the profile or the snapshot does not exist, return a 404 error.
   *
   * Authorization: sellers may only view snapshots belonging to their own profile (verify the authenticated seller's profile ID matches profileId). Administrators may view any seller profile snapshot. Unauthorized access returns a 403 error.
   *
   * Snapshots are immutable — no update or delete operations are supported. The returned data is a frozen historical record of the shop_name, shop_description, and logo_image as they existed at the moment the snapshot was captured (recorded in created_at).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":snapshotId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("profileId")
    profileId: string & tags.Format<"uuid">,
    @TypedParam("snapshotId")
    snapshotId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallSellerProfileSnapshot> {
    try {
      return await getShoppingMallAdminProfilesProfileIdSnapshotsSnapshotId({
        admin,
        profileId,
        snapshotId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
