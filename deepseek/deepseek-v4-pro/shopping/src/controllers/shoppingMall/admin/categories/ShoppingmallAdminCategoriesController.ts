  /**
   * Updates an existing product category's name, description, or parent relationship.
   *
   * This endpoint allows administrators to modify the category taxonomy by editing names and descriptions, reassigning parent categories, or promoting a subcategory to a top-level category. All edits take effect immediately and are visible across the platform.
   *
   * The operation enforces the platform's two-tier category hierarchy: a subcategory cannot become a parent to further subcategories, and no category may reference itself as its own parent either directly or indirectly through a chain. Category names must remain unique within their parent scope — two top-level categories cannot share the same name, and two subcategories under the same parent cannot share the same name.
   *
   * Only authenticated administrators may perform this operation. Attempts by guests, customers, or sellers are rejected. Soft-deleted categories cannot be edited and must be restored before modification.
   *
   * @param connection
   * @param categoryId Unique identifier of the category to update. This is a UUID primary key assigned at category creation time.
   * @param body The fields to update on the category. All fields are optional — only the provided fields are modified. Set `parentId` to `null` to promote the category to a top-level category, or to a valid top-level category ID to make it a subcategory under that parent. The `name` must be non-empty when provided and unique within the target parent scope.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification Update an existing category by its UUID primary
     *   key. This operation is restricted to administrators only.
   *
   * ## Authorization
   * - Require administrator authentication. Reject with 403 if the caller is a guest, customer, or seller.
   *
   * ## Validation
   * 1. **Category existence**: Query `shopping_mall_categories` where `id` = `categoryId` and `deleted_at IS NULL`. Return 404 if the category does not exist or has been soft-deleted.
   * 2. **Name validation**: If `name` is provided in the request body and is empty or consists only of whitespace, reject with 400.
   * 3. **Parent validation** (if `parentId` is provided and non-null):
   *    - Query `shopping_mall_categories` where `id` = `parentId` and `deleted_at IS NULL`. Return 404 if the parent category does not exist or is soft-deleted.
   *    - Verify the parent is a top-level category: `parent_id IS NULL`. If the parent is itself a subcategory, reject with 400 — the platform supports at most one level of nesting.
   *    - **Circular reference detection**: If `categoryId` equals `parentId`, reject with 400. If following the `parent_id` chain from the proposed parent reaches `categoryId` (forming a cycle), reject with 400.
   * 4. **Name uniqueness** (if `name` is provided and differs from the current category name):
   *    - For top-level scope (`parentId` is null): query for another category with the same `name` where `parent_id IS NULL` and `id != categoryId` and `deleted_at IS NULL`. If found, reject with 409.
   *    - For subcategory scope (`parentId` is non-null): query for another category with the same `name` where `parent_id` = `parentId` and `id != categoryId` and `deleted_at IS NULL`. If found, reject with 409.
   *
   * ## Update
   * - Apply only the fields that were provided in the request body (`name`, `description`, `parentId`). Do not overwrite unprovided fields with defaults.
   * - Set `updated_at` to the current timestamp.
   * - Persist the changes to the database.
   *
   * ## Response
   * - Return the updated category record as `IShoppingMallCategory` with all fields: `id`, `name`, `description`, `parentId`, `createdAt`, `updatedAt`, `deletedAt`.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
