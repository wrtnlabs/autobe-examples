  /**
   * Soft-deletes a category and automatically reorganizes the category hierarchy.
   *
   * When an administrator deletes a category, the platform handles subcategory promotion and product unlinking automatically within a single transaction. If the deleted category is a top-level parent, all its direct subcategories are promoted to become top-level categories, retaining their names, descriptions, and product assignments. If the deleted category is a depth-1 subcategory with its own depth-2 subcategories, those children are promoted one level up under the grandparent. If the deleted category is a leaf with no children, it is simply removed with no hierarchy changes.
   *
   * Products that were assigned to the deleted category become uncategorized — they are not deleted or modified in any other way, only their category assignment is removed. The deleted category is excluded from all future category listings and cannot receive new product assignments, but its record is preserved with a deletion timestamp for historical reference.
   *
   * This operation is restricted to administrators only. Requests from non-administrator actors are rejected with a 403 Forbidden error.
   *
   * @param connection
   * @param categoryId UUID of the category to delete (global scope).
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification Soft-delete a category by setting its deleted_at
     *   timestamp to the current time. Execute all changes within a single
     *   database transaction for atomicity — if any step fails, roll back the
     *   entire operation.
   *
   * **Authorization**: Require administrator authentication. Reject requests from non-administrator actors with 403 Forbidden.
   *
   * **Lookup**: Find the category by categoryId (UUID). If no matching record exists, or if the category is already soft-deleted (deleted_at IS NOT NULL), return 404 Not Found — treat soft-deleted categories as nonexistent for API purposes.
   *
   * **Hierarchy Reorganization** (execute BEFORE soft-deleting the target):
   *
   * 1. **Parent category deletion** (target has parent_id IS NULL):
   *    - Find all direct children: `SELECT * FROM shopping_mall_categories WHERE parent_id = target.id AND deleted_at IS NULL`.
   *    - For each child, set `parent_id = NULL` (promoted to top-level). These subcategories retain their names, descriptions, and existing product assignments unchanged.
   *
   * 2. **Depth-1 subcategory deletion** (target has parent_id IS NOT NULL):
   *    - Check for grandchildren: `SELECT * FROM shopping_mall_categories WHERE parent_id = target.id AND deleted_at IS NULL`.
   *    - If grandchildren exist: for each grandchild, set `parent_id = target.parent_id` (promoted one level up to depth 1 under the grandparent).
   *    - If no grandchildren exist: no hierarchy changes needed — this is a leaf deletion.
   *
   * 3. **Depth-2+ leaf deletion** (target has no non-deleted children):
   *    - Simply proceed to soft-delete with no hierarchy changes.
   *
   * **Product Unlinking**: Unlink all products from the target category:
   * `UPDATE shopping_mall_products SET category_id = NULL WHERE category_id = target.id`
   * Products themselves are neither modified nor deleted — only the category assignment is removed.
   *
   * **Soft-Delete**: Set `deleted_at = NOW()` and `updated_at = NOW()` on the target category record.
   *
   * **Edge Cases**:
   * - Category not found → 404 Not Found
   * - Category already soft-deleted → 404 Not Found (treat as nonexistent)
   * - Non-admin actor → 403 Forbidden
   * - Category with no children and no products → clean soft-delete, no side effects
   * - Multiple children requiring promotion → handle all within the transaction
   * - Transaction rollback on any failure to maintain data consistency
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":categoryId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("categoryId")
    categoryId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallAdminCategoriesCategoryId({
        admin,
        categoryId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
