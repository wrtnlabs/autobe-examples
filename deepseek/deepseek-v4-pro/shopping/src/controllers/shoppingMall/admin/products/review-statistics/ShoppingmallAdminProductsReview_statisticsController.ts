import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IShoppingMallReviewStatistic } from "../../../../../api/structures/IShoppingMallReviewStatistic";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminProductsProductIdReviewStatistics } from "../../../../../providers/getShoppingMallAdminProductsProductIdReviewStatistics";

@Controller("/shoppingMall/admin/products/:productId/review-statistics")
export class ShoppingmallAdminProductsReview_statisticsController {
  /**
   * Retrieves aggregated review statistics for a specific product.
   *
   * Returns the average star rating and total review count computed from all non-deleted reviews for the specified product. The average rating is rounded to one decimal place and ranges from 0.0 to 5.0.
   *
   * When the product has no reviews, both the average rating and total count are returned as zero. Soft-deleted reviews are excluded from both calculations, ensuring that only currently visible reviews contribute to the displayed statistics.
   *
   * @param connection
   * @param productId Unique identifier of the product whose review statistics are being retrieved.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification Query the shopping_mall_review_reviews table for
     *   all reviews belonging to the product identified by {productId} where
     *   deleted_at IS NULL.
   *
   * Compute the average rating by summing all rating values and dividing by the count of non-deleted reviews. Round the result to one decimal place. If there are no non-deleted reviews, return an average rating of 0 and a total count of 0.
   *
   * Compute the total review count as the number of non-deleted reviews for this product.
   *
   * No pagination is needed — this endpoint returns only the two aggregate values.
   *
   * Verify that the product exists in shopping_mall_products before querying reviews. If the product does not exist or has been soft-deleted (deleted_at IS NOT NULL), return a 404 error.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallReviewStatistic> {
    try {
      return await getShoppingMallAdminProductsProductIdReviewStatistics({
        admin,
        productId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
