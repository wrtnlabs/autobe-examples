import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallReviewReview } from "../../../../api/structures/IPageIShoppingMallReviewReview";
import { IShoppingMallReviewReview } from "../../../../api/structures/IShoppingMallReviewReview";
import { getShoppingMallProductsProductIdReviewsReviewId } from "../../../../providers/getShoppingMallProductsProductIdReviewsReviewId";
import { patchShoppingMallProductsProductIdReviews } from "../../../../providers/patchShoppingMallProductsProductIdReviews";

@Controller("/shoppingMall/products/:productId/reviews")
export class ShoppingmallProductsReviewsController {
  /**
   * Retrieves a paginated list of reviews for a specific product, ordered by newest first.
   *
   * This endpoint powers the review section on the product detail page. It returns all non-deleted reviews written by verified purchasers, including the star rating, optional text content, reviewer identity, and the date each review was written.
   *
   * Only active (non-deleted) reviews are returned. Reviews that have been soft-deleted by their authors are excluded from the results, from the average rating calculation, and from the total review count. When a customer who wrote a review later deletes their account, the review content and rating are preserved but the author is shown as a 'deleted user'.
   *
   * The response includes pagination metadata and the total count of non-deleted reviews, enabling clients to display the average rating and review count alongside the review list on the product detail page.
   *
   * @param connection
   * @param productId Unique identifier of the product whose reviews are being retrieved.
   * @param body Pagination parameters and an optional rating filter to narrow results to reviews with a specific star rating (1–5).
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor null
     * @x-autobe-specification Query the shopping_mall_review_reviews table
     *   filtered by shopping_mall_product_id matching the provided productId
     *   path parameter.
   *
   * Filtering rules:
   * - Exclude soft-deleted reviews: WHERE deleted_at IS NULL.
   * - If a rating filter is provided in the request body, additionally filter WHERE rating = [requested rating value].
   *
   * Sorting:
   * - Always sort by created_at DESC (newest first), matching the index on (shopping_mall_product_id, created_at) for optimal query performance.
   *
   * Pagination:
   * - Support cursor-based or offset-based pagination as specified in the IRequest DTO.
   * - Return total count of non-deleted reviews for the product to enable client-side average rating and review count display.
   *
   * Deletion handling:
   * - Reviews where deleted_at IS NOT NULL are excluded from results entirely.
   * - When the authoring customer has deleted their account, the review content and rating are preserved but the author attribution should be displayed as a 'deleted user' indicator in the ISummary response.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallReviewReview.IRequest,
  ): Promise<IPageIShoppingMallReviewReview.ISummary> {
    try {
      return await patchShoppingMallProductsProductIdReviews({
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves a single product review by its unique identifier.
   *
   * Returns the complete review details including the star rating (1-5), optional written content, author information, and creation/update timestamps. The review must belong to the specified product — if the review ID does not correspond to a review for that product, a 404 error is returned.
   *
   * Soft-deleted reviews are not visible through this endpoint. Customers who deleted their accounts will have their reviews preserved but shown as authored by a "deleted user". This endpoint supports both the product detail page (linking to individual reviews) and the review management flow where customers retrieve their own reviews before editing or deleting them.
   *
   * @param connection
   * @param productId Unique identifier of the product the review belongs to. Must match the shopping_mall_product_id of the target review.
   * @param reviewId Unique identifier of the review to retrieve. This is the primary key of the shopping_mall_review_reviews record.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor null
     * @x-autobe-specification Retrieve a single review from the
     *   shopping_mall_review_reviews table by its primary key (id = reviewId).
     *   Verify that the review's shopping_mall_product_id matches the productId
     *   path parameter — if it does not match, return a 404 Not Found error to
     *   maintain the RESTful resource hierarchy.
   *
   * For customer and guest actors, exclude soft-deleted reviews: if the review's deleted_at is not null, return 404 Not Found. Administrator actors may retrieve soft-deleted reviews for audit purposes.
   *
   * When the reviewing customer has deleted their account, the customer relationship (shopping_mall_customer_id) will no longer resolve to an active customer record. In this case, attribute the review to a "deleted user" designation in the response rather than omitting the author information.
   *
   * Join with shopping_mall_customers to resolve the reviewer's display name. If the customer record no longer exists (account deleted), show the author as "deleted user".
   *
   * Return 404 if no review exists with the given id, regardless of whether the id is valid UUID format.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":reviewId")
  public async at(
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallReviewReview> {
    try {
      return await getShoppingMallProductsProductIdReviewsReviewId({
        productId,
        reviewId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
