import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallShipment } from "../../../../api/structures/IPageIShoppingMallShipment";
import { IShoppingMallShipment } from "../../../../api/structures/IShoppingMallShipment";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { getShoppingMallSellerShipmentsShipmentId } from "../../../../providers/getShoppingMallSellerShipmentsShipmentId";
import { patchShoppingMallSellerShipments } from "../../../../providers/patchShoppingMallSellerShipments";
import { putShoppingMallSellerShipmentsShipmentId } from "../../../../providers/putShoppingMallSellerShipmentsShipmentId";

@Controller("/shoppingMall/seller/shipments")
export class ShoppingmallSellerShipmentsController {
  /**
   * Search and list shipments with filtering and pagination.
   *
   * Returns a paginated list of shipments scoped to the authenticated user's role. Sellers see only their own shipments with the ability to filter by delivery status or order. Customers see shipments for their orders with tracking information including carrier name and tracking number. Administrators can view all shipments across the platform.
   *
   * Each shipment includes the carrier name, tracking number, shipping date, delivery confirmation status, and a summary of the order items contained in the shipment.
   *
   * **Delivery Status Filtering:**
   * Filter shipments by whether delivery has been confirmed. Shipments with a null delivery timestamp are in transit ("pending"); shipments with a confirmed delivery timestamp are delivered. Auto-confirmation occurs 14 days after shipping via a background job independently of API queries.
   *
   * @param connection
   * @param body Search criteria including optional delivery status filter (pending/delivered), order ID filter, seller ID filter (administrator only), shipping date range (createdFrom, createdTo), and pagination parameters (pageSize, cursor). All filters are optional — an empty request body returns all scoped shipments sorted newest first.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Query the shopping_mall_shipments table with
     *   optional filters and cursor-based pagination.
   *
   * **Authorization & Scoping:**
   * - Seller: automatically scope to shipments where shopping_mall_seller_id equals the authenticated seller's ID. Sellers cannot view shipments from other sellers.
   * - Customer: automatically scope to shipments belonging to orders where shopping_mall_customer_id equals the authenticated customer's ID. Customers only see shipments for their own orders.
   * - Administrator: no automatic scoping — can view all shipments across the platform.
   *
   * **Filtering:**
   * - deliveryStatus: filter by delivery state. "pending" matches shipments where delivered_at IS NULL (in transit). "delivered" matches shipments where delivered_at IS NOT NULL.
   * - orderId: exact match on shopping_mall_order_id. Sellers can filter to see shipments for a specific order. Customers are already scoped to their orders.
   * - sellerId: exact match on shopping_mall_seller_id. Only available for administrators — rejected with 403 for other roles.
   * - createdFrom / createdTo: date range filter on created_at for shipping date filtering. Both optional, can be used independently or together.
   *
   * All filters are optional and combinable. An empty request body returns all scoped shipments.
   *
   * **Sorting & Pagination:**
   * Default sort: created_at DESC (newest shipments first). Use cursor-based pagination with pageSize (default 20, max 100) and cursor parameters.
   *
   * **Response Construction:**
   * For each shipment in the result set, include:
   * - id, carrier_name, tracking_number, created_at (shipping date), delivered_at (null if not yet delivered)
   * - deliveryStatus: derived from delivered_at — null → "pending", non-null → "delivered"
   * - order: object with id and code for cross-reference
   * - seller: object with id for identification
   * - orderItemsSummary: array of contained order items, each with id, quantity, price, and status
   *
   * **Delivery Auto-Confirmation Note:**
   * Shipments with null delivered_at and created_at older than 14 days still appear as "pending" in search results. The auto-confirmation scheduled job runs independently — the API reflects actual database state at query time.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IShoppingMallShipment.IRequest,
  ): Promise<IPageIShoppingMallShipment.ISummary> {
    try {
      return await patchShoppingMallSellerShipments({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves full details of a single shipment identified by its unique ID.
   *
   * Returns the carrier name, tracking number, shipping date (when the shipment was created), and delivery confirmation status. The response includes the complete list of order items contained in this shipment, each with its variant details, quantity, and price.
   *
   * Customers can only access shipments belonging to their own orders, enabling them to track package delivery progress. Sellers can access shipments they have created, allowing them to manage dispatched packages. Administrators have unrestricted access to all shipments on the platform.
   *
   * Delivery status is indicated by the `delivered_at` timestamp — a null value means the shipment is still in transit, while a non-null value confirms delivery has been completed either by customer confirmation or automatic confirmation 14 days after shipping.
   *
   * @param connection
   * @param shipmentId Unique identifier (UUID) of the shipment to retrieve.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Query the `shopping_mall_shipments` table by
     *   primary key `id` matching the `shipmentId` path parameter.
   *
   * Authorization scoping:
   * - If actor is a customer: verify the shipment's order (`shopping_mall_order_id`) belongs to the authenticated customer via `shopping_mall_orders.shopping_mall_customer_id`. Return 404 if not authorized.
   * - If actor is a seller: verify `shopping_mall_seller_id` matches the authenticated seller. Return 404 if not authorized.
   * - If actor is an admin: no restriction, return any shipment.
   *
   * Exclude soft-deleted records: filter `deleted_at IS NULL`.
   *
   * Eager-load related `shopping_mall_order_items` belonging to this shipment (where `shopping_mall_shipment_id` matches). For each order item, include its quantity, price, status, and reference to the product variant.
   *
   * Return 404 if no non-deleted shipment matches the given ID (or if the actor lacks authorization to view it).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":shipmentId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("shipmentId")
    shipmentId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallShipment> {
    try {
      return await getShoppingMallSellerShipmentsShipmentId({
        seller,
        shipmentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update the carrier name and tracking number for an existing shipment.
   *
   * A seller can correct or update the tracking information — carrier name and tracking number — of a shipment they created, as long as delivery has not yet been confirmed. This allows sellers to fix data entry errors or update tracking numbers when the carrier provides a revised tracking number after the initial shipment creation.
   *
   * Tracking information updates are only permitted before delivery confirmation. Once a customer confirms delivery — or the system automatically confirms delivery 14 days after the shipment was created — the tracking information becomes immutable. This ensures the historical accuracy of delivery records and prevents tampering with completed shipments.
   *
   * @param connection
   * @param shipmentId Unique identifier (UUID) of the shipment to update.
   * @param body Updated tracking information containing the carrier name and tracking number for the shipment. At least one of carrier_name or tracking_number must be provided.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Update the carrier_name and/or tracking_number on
     *   an existing shipment owned by the authenticated seller.
   *
   * Authorization: The authenticated seller must be the creator of the shipment (shopping_mall_seller_id matches the authenticated seller's ID).
   *
   * Preconditions:
   * - The shipment must exist and not be soft-deleted (deleted_at IS NULL). If not found, return 404.
   * - delivered_at must be null — shipments with confirmed delivery have immutable tracking information. If delivered_at IS NOT NULL, return 409 Conflict.
   *
   * Implementation:
   * 1. Query shopping_mall_shipments by id WHERE deleted_at IS NULL. If no record found, return 404.
   * 2. Verify shopping_mall_seller_id matches the authenticated seller. If not, return 403 Forbidden.
   * 3. Verify delivered_at IS NULL. If not, return 409 Conflict with message indicating tracking information is immutable after delivery confirmation.
   * 4. Update carrier_name and/or tracking_number with the provided values. Both fields can be updated independently — at least one must be provided.
   * 5. Set updated_at to the current timestamp.
   * 6. Return the full updated shipment record.
   *
   * Error codes:
   * - 404: Shipment not found (invalid id or soft-deleted record).
   * - 403: Authenticated seller does not own this shipment.
   * - 409: Delivery already confirmed — tracking information cannot be modified after delivery.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":shipmentId")
  public async update(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("shipmentId")
    shipmentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallShipment.IUpdate,
  ): Promise<IShoppingMallShipment> {
    try {
      return await putShoppingMallSellerShipmentsShipmentId({
        seller,
        shipmentId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
