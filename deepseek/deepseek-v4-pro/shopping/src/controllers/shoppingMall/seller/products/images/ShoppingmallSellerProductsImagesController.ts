import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IShoppingMallProductImage } from "../../../../../api/structures/IShoppingMallProductImage";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { deleteShoppingMallSellerProductsProductIdImagesImageId } from "../../../../../providers/deleteShoppingMallSellerProductsProductIdImagesImageId";
import { postShoppingMallSellerProductsProductIdImages } from "../../../../../providers/postShoppingMallSellerProductsProductIdImages";
import { putShoppingMallSellerProductsProductIdImagesImageId } from "../../../../../providers/putShoppingMallSellerProductsProductIdImagesImageId";

@Controller("/shoppingMall/seller/products/:productId/images")
export class ShoppingmallSellerProductsImagesController {
  /**
   * Upload one or more images to an existing product's gallery.
   *
   * Sellers can upload images to their own products so customers can visually evaluate the product before purchasing. Each uploaded image is assigned the next available display order position. The image with the lowest display order value serves as the main thumbnail — used in search results, category listings, and product cards.
   *
   * Only the seller who owns the product can upload images. Suspended sellers cannot modify product images even for products they own. Administrators may view product images as part of their oversight responsibilities but cannot upload on behalf of sellers.
   *
   * Every image upload operation creates a product snapshot capturing the complete visual state before the change, preserving all existing image references and their display ordering for audit and dispute resolution purposes.
   *
   * @param connection
   * @param productId Unique identifier of the product to upload images to.
   * @param body Image data for one or more images to add to the product gallery. Each entry includes the image URL locating the stored image file.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Upload one or more images to a product's gallery.
   *
   * **Authorization**: Only the seller who owns the product can upload images. If the requesting user is not the product's owner, reject the request. If the seller account is suspended, deny the upload even for owned products. Administrators cannot upload images on behalf of sellers.
   *
   * **Pre-conditions**:
   * - The product identified by productId must exist
   * - The product must not be soft-deleted (deleted_at IS NULL)
   * - The authenticated seller must own the product (shopping_mall_seller_id matches)
   * - The seller's account must not be suspended
   *
   * **Implementation**:
   * 1. Query the shopping_mall_products record by productId; verify it exists and deleted_at IS NULL
   * 2. Verify the authenticated seller is the product owner (shopping_mall_seller_id equals the seller's user ID)
   * 3. Verify the seller account is not suspended
   * 4. Query all existing shopping_mall_product_images for this product, ordered by display_order ascending, to determine the current maximum display_order value
   * 5. Create a product snapshot capturing the complete product state BEFORE the upload — include all variant states and all existing image URLs with their display_order positions (see shopping_mall_product_snapshots and shopping_mall_product_snapshot_images)
   * 6. For each image URL in the request:
   *    - Generate a new UUID for the image record
   *    - Set display_order starting from (maximum existing + 1) and incrementing for each subsequent image
   *    - Create the shopping_mall_product_images record with the image_url, display_order, and current timestamp for created_at and updated_at
   *    - If no images previously existed, the first uploaded image receives display_order 0 and becomes the main thumbnail
   * 7. Return all newly created shopping_mall_product_images records with their assigned IDs, display_order positions, image URLs, and timestamps
   *
   * **Edge Cases**:
   * - If the image upload fails for any reason, retain all existing product images unchanged — no partial uploads
   * - Uploading images to a product with existing images appends the new images after the current highest display_order
   * - The first image ever uploaded to a product automatically becomes the main thumbnail (display_order 0)
   * - Uploading multiple images in a single request assigns sequential display_order values to all of them
   * - If a combination of changes occurs in a single edit, create one snapshot reflecting the state before all changes
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallProductImage.ICreate,
  ): Promise<IShoppingMallProductImage> {
    try {
      return await postShoppingMallSellerProductsProductIdImages({
        seller,
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update a product image's display order or replace its image file.
   *
   * This operation allows the seller who owns the product to reposition an image within the product gallery or replace the image file with a new one. Both changes can be applied in a single request.
   *
   * **Reordering**: Changing the display order repositions the image within the gallery. Other images are automatically shifted to accommodate the new position, and display order values are normalized to maintain sequential ordering without gaps. If the updated image becomes the first in display order, it is immediately promoted to serve as the product's main thumbnail across search results, category listings, and product cards — no additional action or cache clearing is required.
   *
   * **Image Replacement**: The image URL can be updated to replace the current image file while preserving the image's position in the gallery and its identity within existing snapshots.
   *
   * **Snapshot**: Every change to a product image triggers a full product snapshot, capturing the complete gallery state (all image URLs and their display orders) as it existed before the change was applied. This ensures a complete audit trail for historical reference and dispute resolution. A single snapshot is created even when both image_url and display_order are changed in the same request.
   *
   * **Authorization**: Only the seller who owns the product can update its images. The seller must not be suspended. Administrators and other sellers cannot modify images on products they do not own.
   *
   * @param connection
   * @param productId Unique identifier of the product that owns the image.
   * @param imageId Unique identifier of the product image to update.
   * @param body Fields to update on the product image. Both display_order and image_url are optional — provide only the fields that need to change. When display_order is changed, other images are automatically shifted to maintain sequential ordering and the thumbnail may be reassigned. When image_url is changed, the image file is replaced while the image retains its position in the gallery.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Update an existing product image by its ID within
     *   the scope of the parent product.
   *
   * **Authorization & Validation**:
   * 1. Verify the requesting user is the seller who owns the product identified by {productId}. Reject with 403 if not the owner.
   * 2. Verify the seller account is not suspended. Reject with 403 if suspended (per business rule [505]: suspended sellers cannot modify images).
   * 3. Verify the product exists. Return 404 if not found.
   * 4. Verify the image identified by {imageId} exists and its shopping_mall_product_id matches {productId}. Return 404 if not found or mismatched.
   *
   * **Updating display_order — Reordering**:
   * - When display_order is provided and differs from the current value, reposition the image within the product's gallery.
   * - If the new display_order collides with an existing image's position, shift the colliding image and all subsequent images forward by one to make room. For example, moving image at position 3 to position 0 shifts images at positions 0, 1, 2 to positions 1, 2, 3 respectively.
   * - After repositioning, check whether this image now occupies the lowest display_order position (position 0). If so, this image becomes the new main thumbnail — displayed in search results, category listings, and product cards per [346].
   * - Normalize display_order values across all images of the product after the shift to ensure sequential ordering (0, 1, 2, …) with no gaps.
   *
   * **Updating image_url — Image Replacement**:
   * - When image_url is provided and differs from the current value, replace the stored URL with the new one.
   * - The image retains its current display_order position unless display_order is also being changed in the same request.
   *
   * **Snapshot Creation**:
   * - Before applying any changes (display_order or image_url), capture the complete pre-change state of all product images — every image's URL and display_order — into a new product snapshot via shopping_mall_product_snapshots and shopping_mall_product_snapshot_images per [342].
   * - This snapshot preserves the gallery state for historical reference and dispute resolution.
   * - A single snapshot suffices even if both display_order and image_url are changed in the same request.
   *
   * **Response**:
   * - Return the updated image record with all fields: id, shopping_mall_product_id, image_url, display_order, created_at, updated_at.
   * - The updated_at timestamp is set to the current time automatically by the database.
   *
   * **Edge Cases**:
   * - If neither display_order nor image_url is provided, or both match their current values, return 200 with the unchanged image. No snapshot is created since no actual change occurred.
   * - If display_order is set to a value greater than or equal to the total image count, clamp it to the last position (total count - 1).
   * - If the product has only one image and its display_order is changed, no shifting of other images is needed — simply set the new display_order (clamped to 0).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":imageId")
  public async update(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedParam("imageId")
    imageId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallProductImage.IUpdate,
  ): Promise<IShoppingMallProductImage> {
    try {
      return await putShoppingMallSellerProductsProductIdImagesImageId({
        seller,
        productId,
        imageId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Deletes a single image from a product's image gallery.
   *
   * Only the seller who owns the product can delete its images. Suspended sellers are blocked from performing this operation. Administrators cannot modify seller product images.
   *
   * After deletion, the remaining images are reordered to maintain a contiguous display sequence. If the deleted image was the main thumbnail (shown first in search results and category listings), the next image in sequence automatically becomes the new main thumbnail. If all images are deleted from the product, a placeholder image will be displayed in product listings.
   *
   * @param connection
   * @param productId UUID of the product that owns the image to be deleted.
   * @param imageId UUID of the product image to delete.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Delete a single product image by its ID, scoped
     *   to a specific product.
   *
   * 1. Look up the product by `productId`. If not found or soft-deleted, return 404.
   * 2. Look up the image by `imageId`. If not found, return 404.
   * 3. Verify the image's `shopping_mall_product_id` matches `productId`. If it does not, return 404 — the image does not belong to this product.
   * 4. Authorize: the requesting user must be the seller who owns the product (`shopping_mall_seller_id`). If not the owner, return 403.
   * 5. Verify the seller is not suspended (`suspended_at` is null). If suspended, return 403.
   * 6. Record the `display_order` of the image being deleted.
   * 7. Delete the image record from `shopping_mall_product_images`.
   * 8. For all remaining images of the product with `display_order` greater than the deleted image's `display_order`, decrement their `display_order` by 1 to maintain a contiguous, gap-free sequence starting from 0.
   * 9. If the deleted image had `display_order` = 0 (was the main thumbnail), the image now at `display_order` = 0 (previously at position 1) becomes the new main thumbnail automatically — no explicit promotion step is needed.
   * 10. Return 204 No Content on success.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":imageId")
  public async erase(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedParam("imageId")
    imageId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallSellerProductsProductIdImagesImageId({
        seller,
        productId,
        imageId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
