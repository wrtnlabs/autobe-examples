import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IShoppingMallProduct } from "../../../../api/structures/IShoppingMallProduct";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { deleteShoppingMallSellerProductsProductId } from "../../../../providers/deleteShoppingMallSellerProductsProductId";
import { postShoppingMallSellerProducts } from "../../../../providers/postShoppingMallSellerProducts";
import { putShoppingMallSellerProductsProductId } from "../../../../providers/putShoppingMallSellerProductsProductId";

@Controller("/shoppingMall/seller/products")
export class ShoppingmallSellerProductsController {
  /**
   * Creates a new product listing for the authenticated seller.
   *
   * Only approved sellers who are not suspended may create products. The product is created under the authenticated seller's ownership and assigned to the specified category. All input fields are required.
   *
   * A newly created product has no variants and will appear in search results and category listings, but will be displayed as unavailable for purchase. The seller must add at least one variant with stock to make the product purchasable.
   *
   * No snapshot is created at product creation time — snapshots are only generated when the product is edited.
   *
   * @param connection
   * @param body Product creation payload containing the product name, detailed description, category reference, and base price. All fields are required.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Create a new product record in the
     *   shopping_mall_products table.
   *
   * Authorization:
   * - The calling user must be an authenticated seller.
   * - The seller's approval status must be "approved" (verify via shopping_mall_sellers relationship).
   * - The seller must not be suspended. If suspended, reject with 403 Forbidden.
   *
   * Validation:
   * - name: required, non-empty string.
   * - description: required, non-empty string.
   * - shopping_mall_category_id: required, must reference an existing category in shopping_mall_categories. If the category does not exist, return 404 Not Found.
   * - base_price: required, must be a positive number greater than 0. If zero or negative, return 400 Bad Request.
   *
   * Implementation:
   * - Generate a new UUID for the product id.
   * - Set shopping_mall_seller_id from the authenticated seller's session.
   * - Set created_at and updated_at to the current timestamp.
   * - Insert the row into shopping_mall_products and return the full record.
   * - Do NOT create a snapshot — snapshots are only created during product edits (per Section 217).
   * - deleted_at remains null for newly created products.
   *
   * Edge cases:
   * - If the seller is not approved, return 403 Forbidden.
   * - If the seller is suspended, return 403 Forbidden.
   * - If the category does not exist, return 404 Not Found.
   * - If any required field is missing or base_price is not positive, return 400 Bad Request with details.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IShoppingMallProduct.ICreate,
  ): Promise<IShoppingMallProduct> {
    try {
      return await postShoppingMallSellerProducts({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update a product's name, description, category, or base price.
   *
   * This operation allows the seller who owns the product to modify its core attributes. Every successful update creates an immutable snapshot recording the product's previous state — including name, description, category, and base price — along with the complete state of all images and variants at that moment. This snapshot-based audit trail ensures full historical traceability of product changes for both the seller and platform administrators.
   *
   * Only the seller who created the product can update it. The seller's account must be approved and not suspended. Administrators cannot update products on behalf of sellers, though they can delete products for policy violations.
   *
   * When the category is changed, the target category must exist and must not be soft-deleted. Products can be assigned to either a top-level category or a subcategory.
   *
   * @param connection
   * @param productId UUID of the product to update.
   * @param body Fields to update on the product. All fields are required — this is a full replacement update (PUT semantics). The name and description identify the product in listings and detail pages. The shopping_mall_category_id must reference an existing, non-deleted category. The base_price is the default price used when variants have no price override.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Find the product by productId UUID. Verify the
     *   product exists and is not soft-deleted (deleted_at IS NULL). Verify the
     *   requesting seller owns the product (shopping_mall_seller_id matches the
     *   authenticated seller). Verify the seller is approved (approval_status =
     *   'approved') and not suspended (suspended_at IS NULL).
   *
   * Validate the request body:
   * - name: required, non-empty string
   * - description: required, non-empty string
   * - shopping_mall_category_id: required, must reference an existing category that is not soft-deleted (deleted_at IS NULL). The category may be a top-level or subcategory.
   * - base_price: required, positive number (greater than 0)
   *
   * Before applying changes, create a shopping_mall_product_snapshots record capturing the current state:
   * - shopping_mall_product_id: product's id
   * - shopping_mall_category_id: product's current shopping_mall_category_id
   * - name: product's current name
   * - description: product's current description
   * - base_price: product's current base_price
   * - created_at: now()
   *
   * Also create shopping_mall_product_snapshot_images records for all current product images, preserving each image_url and display_order.
   *
   * Also create shopping_mall_product_variant_snapshots records for all current variants, capturing each variant's code, option values, and price at the moment of snapshot.
   *
   * Apply the updates to the product record: set name, description, shopping_mall_category_id, base_price, and updated_at to now().
   *
   * Execute the entire operation — snapshot creation (product snapshot, snapshot images, variant snapshots) and product update — within a single database transaction to ensure atomicity. If any part fails, the entire operation rolls back.
   *
   * Return the full updated product record with all fields.
   *
   * Error conditions:
   * - 404: Product not found or is soft-deleted (deleted_at IS NOT NULL)
   * - 403: Authenticated seller does not own this product, or seller approval_status is not 'approved', or seller is suspended (suspended_at IS NOT NULL)
   * - 404: Referenced category not found or is soft-deleted (deleted_at IS NOT NULL)
   * - 400: Validation failure — missing required fields, empty strings, or base_price is zero or negative
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":productId")
  public async update(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallProduct.IUpdate,
  ): Promise<IShoppingMallProduct> {
    try {
      return await putShoppingMallSellerProductsProductId({
        seller,
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Soft-deletes a product, removing it from search results, category listings, and all customer wishlists.
   *
   * This operation permanently removes the product from active listings while preserving all historical snapshots for audit and order history accuracy. The deletion cascades to all product variants, inventory records, and product images.
   *
   * **Seller Restrictions**
   *
   * A seller may only delete their own products. The deletion is blocked when any variant of the product has order items in "paid" or "shipped" status, pending cancellation requests, or pending refund requests. This ensures active transactions are not disrupted.
   *
   * **Administrator Override**
   *
   * Administrators may delete any product on the platform. Administrator-initiated deletions bypass all pending-item checks and proceed immediately — this is intended for policy violation enforcement.
   *
   * **Cascading Effects**
   *
   * Upon successful deletion, all variants belonging to the product are soft-deleted, all inventory records and product images are permanently removed, and the product is automatically removed from every customer's wishlist. Historical snapshots of the product, its variants, and its images are preserved for order history integrity.
   *
   * @param connection
   * @param productId Unique identifier (UUID) of the product to delete. Must reference an existing, non-deleted product.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Soft-delete a product by setting its deleted_at
     *   timestamp.
   *
   * **Authorization**
   * - Seller: must own the product (shopping_mall_seller_id matches authenticated seller).
   * - Administrator: may delete any product without ownership check.
   *
   * **Pre-Deletion Validation (Seller Path Only)**
   * Before soft-deleting, query all variants of the product and check:
   * 1. Join shopping_mall_product_variants → shopping_mall_order_items WHERE order_items.status IN ('paid', 'shipped'). If any rows exist, reject with error indicating pending order items.
   * 2. Join shopping_mall_product_variants → shopping_mall_order_items → shopping_mall_cancellation_requests WHERE cancellation_requests.status = 'pending' AND cancellation_requests.deleted_at IS NULL. If any rows exist, reject with error indicating pending cancellation requests.
   * 3. Join shopping_mall_product_variants → shopping_mall_order_items → shopping_mall_refund_requests WHERE refund_requests.status = 'pending' AND refund_requests.deleted_at IS NULL. If any rows exist, reject with error indicating pending refund requests.
   *
   * **Administrator Path**
   * Skip all pending-item checks — process deletion immediately regardless of order state (section 221).
   *
   * **Deletion Steps (Transactional)**
   * 1. Verify product exists and deleted_at IS NULL. If already deleted, return 404.
   * 2. Set product.deleted_at = NOW().
   * 3. For all product variants: set variant.deleted_at = NOW() WHERE variant.deleted_at IS NULL.
   * 4. Delete all inventory records (shopping_mall_inventory_records) for all variants — hard delete, not soft delete.
   * 5. Delete all product images (shopping_mall_product_images) for the product — hard delete. After deletion, if any snapshot references these images, those snapshot records are preserved (referential integrity handled by snapshot tables).
   * 6. Delete all wishlist items (shopping_mall_wishlist_items) referencing this product — hard delete across all customers.
   * 7. Product snapshots (shopping_mall_product_snapshots), variant snapshots (shopping_mall_product_variant_snapshots), and product snapshot images (shopping_mall_product_snapshot_images) are preserved — do not delete any snapshot data.
   * 8. Return the updated product entity with deleted_at populated.
   *
   * **Error Conditions**
   * - Product not found or already deleted: return 404.
   * - Seller does not own the product: return 403.
   * - Pending order items / cancellation requests / refund requests exist (seller path): return 409 Conflict with descriptive message.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":productId")
  public async erase(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallSellerProductsProductId({
        seller,
        productId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
