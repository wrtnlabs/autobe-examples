  /**
   * Retrieves a single immutable variant snapshot by its unique identifier.
   *
   * Variant snapshots are created automatically whenever a product variant is edited, preserving the variant's complete state — SKU code, option values, price, and stock quantity — at the moment before the change took effect. Snapshots are also created as children of product snapshots when the parent product is edited, ensuring the full product-variant configuration can be reconstructed at any historical point.
   *
   * Each snapshot records exactly what the variant looked like: its SKU code, option values (e.g., "color: Red, size: Large"), variant-specific price (or null when no price override existed), and the net stock quantity summed from all inventory records at that moment. The optional parent product snapshot reference indicates whether this variant snapshot was created standalone (variant-only edit) or as part of a broader product edit.
   *
   * Snapshots are append-only and never deleted. They remain accessible even after the variant or product itself is deleted, providing an immutable audit trail for seller record-keeping and administrator dispute resolution. This endpoint is accessible to the product's owning seller and to platform administrators.
   *
   * @param connection
   * @param productId UUID of the product to which the variant belongs (global scope). Used for ownership verification — the requesting seller must own this product, or the requester must be an administrator.
   * @param variantCode Globally unique SKU code of the variant whose snapshot is being retrieved (global scope). Must belong to the product specified by productId.
   * @param snapshotId UUID of the variant snapshot to retrieve. Must belong to the variant identified by variantCode.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Retrieve a single variant snapshot by its UUID,
     *   scoped under a specific product and variant identified by SKU code.
   *
   * 1. Look up the product by productId (UUID). The product may be active or soft-deleted — snapshots are preserved after deletion. If the product is not found, return 404.
   * 2. Look up the variant by variantCode (globally unique SKU code) within the product identified in step 1. Verify that shopping_mall_product_id matches the product UUID from step 1. If the variant does not belong to this product or does not exist, return 404.
   * 3. Authorization: verify that the requesting actor is either (a) the seller who owns the product (match shopping_mall_seller_id on the product), or (b) an administrator. Return 403 Forbidden otherwise.
   * 4. Query shopping_mall_product_variant_snapshots by id = snapshotId and shopping_mall_product_variant_id = the variant's UUID from step 2. If no matching snapshot exists, return 404.
   * 5. Return the full snapshot record: id, shopping_mall_product_variant_id, shopping_mall_product_snapshot_id (nullable — null for standalone variant-only snapshots; non-null when created as a child of a product-level snapshot), sku_code, option_values, price (nullable — null means the variant used the product base price at snapshot time), stock_quantity, and created_at.
   * 6. Snapshots are immutable — no update or delete operations exist for them. This endpoint is strictly read-only.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
