@Controller("/shoppingMall/seller/cancellation-requests/:requestId/snapshots")
export class ShoppingmallSellerCancellation_requestsSnapshotsController {
  /**
   * Retrieves paginated audit trail of snapshots created when a seller responded to a specific cancellation request.
   *
   * Each snapshot captures the exact state of the cancellation request at the moment of the seller's decision — preserving the customer's reason text and the resulting status (approved or rejected) as a permanent, immutable record. These snapshots serve as an auditable history for dispute resolution and seller accountability.
   *
   * Snapshots are system-generated and cannot be created, modified, or deleted through any API. A new snapshot is automatically created each time the seller responds to the cancellation request. This endpoint provides the only read access to this historical record.
   *
   * Results are paginated and sorted with the most recent snapshot first, reflecting the chronological order of seller responses to the cancellation request.
   *
   * @param connection
   * @param requestId The unique identifier (UUID) of the cancellation request whose snapshots are being retrieved.
   * @param body Search and pagination criteria for browsing cancellation request snapshots. Supports optional filtering by snapshot status (approved or rejected) and by the snapshot creation date range.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Query the
     *   shopping_mall_cancellation_request_snapshots table filtered by the
     *   cancellation request ID from the path parameter.
   *
   * Implementation:
   * - Verify the cancellation request exists in shopping_mall_cancellation_requests by id = {requestId}. If not found, return 404.
   * - Filter snapshots WHERE shopping_mall_cancellation_request_id = {requestId}.
   * - Default sort by created_at descending (newest snapshot first), matching the composite index on [shopping_mall_cancellation_request_id, created_at].
   * - Support pagination via request body (cursor-based or offset-based).
   * - Support optional filtering by status ("approved" / "rejected") and created_at date range.
   * - Each snapshot record includes: id, reason, status, and created_at.
   *
   * Access control:
   * - Customer: only snapshots of requests they submitted (traverse snapshot → cancellation_request → order_item → order → user).
   * - Seller: only snapshots of requests on order items for their own products (traverse snapshot → cancellation_request → order_item → product_variant → product → seller_profile → user).
   * - Admin: all snapshots for dispute resolution.
   *
   * Edge cases:
   * - If the cancellation request has no snapshots (seller has not yet responded), return an empty paginated result.
   * - Snapshots are accessible even when the parent cancellation request is soft-deleted (deleted_at is not null) — do not filter by the parent's deletion state.
   * - Snapshots are permanently immutable — no write operations exist for this resource.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("requestId")
    requestId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallCancellationRequestSnapshot.IRequest,
  ): Promise<IPageIShoppingMallCancellationRequestSnapshot.ISummary> {
    try {
      return await patchShoppingMallSellerCancellationRequestsRequestIdSnapshots(
        {
          seller,
          requestId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single cancellation request snapshot by its unique identifier.
   *
   * A cancellation request snapshot is an immutable historical record captured at the exact moment a seller responds to a customer's cancellation request — either approving or rejecting it. The snapshot preserves the cancellation reason text and the status transition, providing a permanent auditable trail for dispute resolution and accountability.
   *
   * Snapshots cannot be modified or deleted by any actor or system process. They survive independently of their source entities: even if the original cancellation request, order item, order, or user accounts are deleted, the snapshot remains preserved and accessible to authorized viewers.
   *
   * Access is restricted by role:
   * - Customers may view snapshots of cancellation requests they themselves submitted.
   * - Sellers may view snapshots of cancellation requests related to their own products.
   * - Administrators may view any cancellation request snapshot on the platform for dispute resolution purposes.
   * - All other users are denied access.
   *
   * @param connection
   * @param requestId Unique identifier of the cancellation request that owns this snapshot (global scope).
   * @param snapshotId Unique identifier of the cancellation request snapshot to retrieve (global scope).
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Query the
     *   shopping_mall_cancellation_request_snapshots table by primary key `id`
     *   matching `snapshotId`, ensuring the snapshot belongs to the
     *   cancellation request identified by `requestId` via the
     *   `shopping_mall_cancellation_request_id` foreign key.
   *
   * Authorization:
   * - Customers: verify the snapshot's cancellation request belongs to an order item within an order owned by the authenticated customer. Traverse: snapshot → cancellation_request → order_item → order → customer.
   * - Sellers: verify the snapshot's cancellation request belongs to an order item whose product variant belongs to a product owned by the authenticated seller. Traverse: snapshot → cancellation_request → order_item → product_variant → product → seller.
   * - Administrators: unrestricted access to all cancellation request snapshots.
   * - If the authenticated user is none of the above, return 403 Forbidden.
   *
   * Return the full snapshot record including id, reason, status, created_at, and the parent cancellation request ID. The snapshot is immutable — no write operations are permitted on this resource.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":snapshotId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("requestId")
    requestId: string & tags.Format<"uuid">,
    @TypedParam("snapshotId")
    snapshotId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallCancellationRequestSnapshot> {
    try {
      return await getShoppingMallSellerCancellationRequestsRequestIdSnapshotsSnapshotId(
        {
          seller,
          requestId,
          snapshotId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
