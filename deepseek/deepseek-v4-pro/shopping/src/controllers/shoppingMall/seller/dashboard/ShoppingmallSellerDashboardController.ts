import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallSellerDashboard } from "../../../../api/structures/IShoppingMallSellerDashboard";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { getShoppingMallSellerDashboard } from "../../../../providers/getShoppingMallSellerDashboard";

@Controller("/shoppingMall/seller/dashboard")
export class ShoppingmallSellerDashboardController {
  /**
   * Retrieves the seller dashboard summary for the currently authenticated seller.
   *
   * The dashboard provides a high-level overview of the seller's shop activity, aggregating key metrics across products, orders, and pending customer requests. This endpoint is accessible only to sellers whose accounts have been approved by an administrator.
   *
   * The response includes four aggregated counts: the total number of active products in the seller's shop, the total number of order items sold across all products, the number of pending cancellation requests awaiting the seller's response, and the number of pending refund requests awaiting the seller's response. Products that have been soft-deleted are excluded from all counts.
   *
   * @param connection
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Retrieve aggregated shop statistics for the
     *   currently authenticated seller.
   *
   * 1. Extract the seller ID from the authenticated session. Reject with 401 if no valid seller session exists.
   * 2. Verify the seller is in "approved" status — rejected or pending sellers cannot access the dashboard. Return 403 if the seller is not approved.
   * 3. Count the seller's total products: query shopping_mall_products WHERE shopping_mall_seller_id = sellerId AND deleted_at IS NULL.
   * 4. Count total order items for the seller's products: find all product variants belonging to the seller's products (shopping_mall_product_variants WHERE shopping_mall_product_id IN seller's product IDs), then count shopping_mall_order_items WHERE shopping_mall_product_variant_id IN those variant IDs.
   * 5. Count pending cancellation requests: count shopping_mall_cancellation_requests WHERE status = 'pending' AND shopping_mall_order_item_id IN (order item IDs from step 4) AND deleted_at IS NULL.
   * 6. Count pending refund requests: count shopping_mall_refund_requests WHERE status = 'pending' AND shopping_mall_order_item_id IN (order item IDs from step 4) AND deleted_at IS NULL.
   * 7. Return all four counts in a single response object.
   *
   * Edge cases:
   * - If the seller has no products, all counts return 0.
   * - Soft-deleted products are excluded from all counts.
   * - Soft-deleted cancellation/refund requests are excluded.
   * - This is a pure read operation — no side effects, no mutations.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @SellerAuth()
    seller: SellerPayload,
  ): Promise<IShoppingMallSellerDashboard> {
    try {
      return await getShoppingMallSellerDashboard({
        seller,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
