import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallSeller } from "../../../../api/structures/IShoppingMallSeller";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { postShoppingMallSellerResubmission } from "../../../../providers/postShoppingMallSellerResubmission";

@Controller("/shoppingMall/seller/resubmission")
export class ShoppingmallSellerResubmissionController {
  /**
   * Resubmit a rejected seller registration for administrator review.
   *
   * Allows a seller whose registration was previously rejected to submit a new registration request. When a seller resubmits, their approval status resets to "pending" and a new administrator must review the registration independently of the previous decision. This ensures sellers who address the issues that led to rejection have a path to eventually sell on the platform.
   *
   * This operation is only available to sellers whose current approval status is "rejected". Sellers who are already pending or approved cannot use this endpoint. Banned sellers are also denied access — they must be unbanned by an administrator before resubmitting.
   *
   * The previous rejection reason is cleared from the current record upon resubmission, as it no longer represents the seller's current standing. The resubmission starts a fresh review cycle with no carryover from the prior rejection.
   *
   * @param connection
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Retrieve the authenticated seller's ID from the
     *   session token. Query the shopping_mall_sellers table by primary key ID.
   *
   * Preconditions (reject with appropriate error if any fail):
   * - Seller must be authenticated as a seller.
   * - Seller must NOT be banned: if banned_at is not null, reject with 403 Forbidden — banned sellers cannot resubmit.
   * - Seller's approval_status must be "rejected". If "pending", reject with 409 Conflict indicating the registration is already awaiting review. If "approved", reject with 409 Conflict indicating the seller is already approved.
   *
   * Update operation:
   * - Set approval_status to "pending".
   * - Set rejection_reason to null — the previous rejection reason is conceptually retained in history but no longer represents the seller's current standing.
   * - Set updated_at to the current timestamp.
   *
   * Return the updated seller record. Use a database transaction to ensure atomicity.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async resubmit(
    @SellerAuth()
    seller: SellerPayload,
  ): Promise<IShoppingMallSeller> {
    try {
      return await postShoppingMallSellerResubmission({
        seller,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
