import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallCustomer } from "../../../../api/structures/IShoppingMallCustomer";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { getShoppingMallSellerProfile } from "../../../../providers/getShoppingMallSellerProfile";

@Controller("/shoppingMall/seller/profile")
export class ShoppingmallSellerProfileController {
  /**
   * Retrieve the authenticated customer's own profile information.
   *
   * Returns the customer's profile data including email address, display name, phone number, account creation date, and ban status if applicable. This endpoint is scoped exclusively to the authenticated customer — each customer can only view their own profile and cannot access another customer's information.
   *
   * This operation requires an active customer session. Guest users, sellers, and administrators cannot access this endpoint. The profile data is read directly from the customer account record and reflects the most current state.
   *
   * @param connection
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Retrieve the authenticated customer's own profile
     *   from the shopping_mall_customers table.
   *
   * Extract the customer ID from the validated session token — this is NOT a path-parameter operation; the identity is session-scoped.
   *
   * Query: SELECT id, email, display_name, phone_number, banned_at, created_at, updated_at FROM shopping_mall_customers WHERE id = {authenticated customer ID} AND deleted_at IS NULL.
   *
   * If no record is found (account deleted or ID mismatch), return a 404 error.
   *
   * NEVER include password_hash in the response under any circumstances.
   *
   * This operation requires an authenticated customer session. Guest, seller, and admin sessions should be rejected with a 401 or 403 error — this endpoint is exclusively for the customer actor viewing their own profile. The session-scoped query inherently prevents access to other customers' data.
   *
   * No database writes occur. This is a read-only operation.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @SellerAuth()
    seller: SellerPayload,
  ): Promise<IShoppingMallCustomer> {
    try {
      return await getShoppingMallSellerProfile({
        seller,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
