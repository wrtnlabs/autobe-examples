  /**
   * Lists all product images captured in the product snapshot of a specific order item.
   *
   * When an order is placed, a product snapshot is created for each order item, freezing the product's state — including all images and their display order — at the moment of purchase. This endpoint retrieves those frozen images, providing an authoritative historical record of what the product listing looked like when the customer placed the order.
   *
   * Each image includes its URL and display order position as it existed at purchase time. Images are sorted by their original display order by default, replicating the gallery arrangement the customer saw.
   *
   * The product snapshot images are immutable — they are created once at order time and never modified. Even if the seller later deletes or replaces product images, these snapshot references remain intact for audit and dispute resolution purposes.
   *
   * @param connection
   * @param itemId UUID of the order item whose product snapshot images are to be listed.
   * @param body Pagination and sorting parameters for listing snapshot images.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification List images belonging to the product snapshot of
     *   a given order item.
   *
   * **Database Query**:
   * 1. Resolve the order item by {itemId} from shopping_mall_order_items.
   * 2. Resolve the product snapshot via the unique constraint on shopping_mall_order_item_id — there is exactly one product snapshot per order item.
   * 3. Query shopping_mall_order_item_product_snapshot_images filtered by the resolved snapshot ID.
   *
   * **Pagination**: Cursor-based pagination using created_at as the cursor. Default page size: 20. Maximum: 100.
   *
   * **Sorting**: Results sorted by display_order ascending by default (replicates the gallery order as seen at purchase time). Alternative sort by created_at descending is supported.
   *
   * **Authorization**:
   * - Customers: can only access images for order items belonging to their own orders.
   * - Sellers: can only access images for order items where the product belongs to them.
   * - Administrators: can access images for any order item.
   *
   * **Response**: Returns IPageIShoppingMallOrderItemProductSnapshotImage.ISummary with image ID, URL, display order, and creation timestamp.
   *
   * **Error Handling**:
   * - 404 if the order item does not exist.
   * - 404 if no product snapshot exists for the order item (should not occur in normal operation — snapshots are created atomically at order time).
   * - 403 if the requester lacks authorization to view this order item.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
