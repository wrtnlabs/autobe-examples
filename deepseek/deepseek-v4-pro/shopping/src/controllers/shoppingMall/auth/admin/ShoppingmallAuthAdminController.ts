import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallAdmin } from "../../../../api/structures/IShoppingMallAdmin";
import { postShoppingMallAuthAdminJoin } from "../../../../providers/postShoppingMallAuthAdminJoin";
import { postShoppingMallAuthAdminLogin } from "../../../../providers/postShoppingMallAuthAdminLogin";
import { postShoppingMallAuthAdminRefresh } from "../../../../providers/postShoppingMallAuthAdminRefresh";

@Controller("/shoppingMall/auth/admin")
export class ShoppingmallAuthAdminController {
  /**
   * Register a new administrator account on the platform.
   *
   * Creates a new administrator account with the provided email and password. The account is assigned the 'regular' grade by default. Upon successful registration, an authenticated session is created immediately and JWT tokens are returned — no separate login step is required.
   *
   * Email must be unique across all active administrator accounts. The password must meet minimum security requirements (length and complexity). The password is stored using a one-way cryptographic hash and is never logged or returned in responses.
   *
   * After registration, the administrator can immediately access admin-protected endpoints using the returned access token. The refresh token can be used to obtain new tokens before the current ones expire.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Administrator registration payload containing the email and password for the new admin account.
     * @x-autobe-authorization-type join
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification Create a new administrator account. Validate that
     *   the email is unique across shopping_mall_admins (excluding soft-deleted
     *   records where deleted_at IS NOT NULL). Hash the password using a
     *   cryptographically secure algorithm (bcrypt or argon2). The grade
     *   defaults to 'regular'. Insert into shopping_mall_admins with created_at
     *   and updated_at set to now. Create an initial session in
     *   shopping_mall_admin_sessions with the admin's IP, href, and referrer
     *   from the request context. Generate access and refresh JWT tokens. Set
     *   expired_at for the session based on the access token expiry. Return
     *   IShoppingMallAdmin.IAuthorized containing the access token, refresh
     *   token, and expiration timestamps. If the email already exists on an
     *   active (non-deleted) admin, return 409 Conflict.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallAdmin.IJoin,
  ): Promise<IShoppingMallAdmin.IAuthorized> {
    try {
      return await postShoppingMallAuthAdminJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate an administrator using their email and password credentials.
   *
   * Validates the provided credentials against stored administrator accounts. On successful authentication, a new session is created and JWT access and refresh tokens are returned. The access token is used for subsequent authenticated requests, while the refresh token can be used to obtain a new token pair when the access token expires.
   *
   * For security, the response does not distinguish between non-existent accounts and incorrect passwords — both return a generic authentication failure. Soft-deleted administrator accounts cannot authenticate.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Administrator login credentials containing the registered email and password.
     * @x-autobe-authorization-type login
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification Authenticate an administrator by email and
     *   password. Query shopping_mall_admins WHERE email = input AND deleted_at
     *   IS NULL. If no record found, return 401 Unauthorized with a generic
     *   'invalid credentials' message (do not reveal whether the email exists).
     *   Compare the provided password against the stored password_hash using
     *   the same hashing algorithm used during registration. If the hash
     *   comparison fails, return 401 Unauthorized. On success, create a new
     *   session in shopping_mall_admin_sessions with the admin's IP, href, and
     *   referrer. Generate access and refresh JWT tokens. Set expired_at based
     *   on the access token's expiration. Return IShoppingMallAdmin.IAuthorized
     *   with tokens. If the account is soft-deleted (deleted_at IS NOT NULL),
     *   treat as non-existent — return 401.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallAdmin.ILogin,
  ): Promise<IShoppingMallAdmin.IAuthorized> {
    try {
      return await postShoppingMallAuthAdminLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh an administrator's authentication session using a valid refresh token.
   *
   * Exchanges a valid refresh token for a new pair of access and refresh tokens. This allows administrators to maintain an authenticated session without re-entering credentials, as long as the refresh token has not expired.
   *
   * The existing session is extended rather than duplicated — the session's expiration timestamp is updated to reflect the new token lifetime. If the refresh token is expired or belongs to a deactivated administrator account, the request is rejected.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Token refresh payload containing the current refresh token to be exchanged for new tokens.
     * @x-autobe-authorization-type refresh
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification Refresh an expiring or expired administrator
     *   session. Accept the refresh token from the request body. Validate the
     *   refresh token's signature and check that it has not expired. Look up
     *   the associated session in shopping_mall_admin_sessions by the token's
     *   session identifier. Verify the session exists and belongs to an active
     *   (non-deleted) admin — JOIN with shopping_mall_admins WHERE deleted_at
     *   IS NULL. If the session's expired_at has passed, return 401
     *   Unauthorized (token cannot be refreshed beyond its absolute
     *   expiration). On success, generate a new access and refresh token pair.
     *   Update the session's expired_at to reflect the new expiration window.
     *   Do NOT create a new session — update the existing one. Return
     *   IShoppingMallAdmin.IAuthorized with the new tokens. If the admin
     *   account has been soft-deleted since the session was created, return
     *   401.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IShoppingMallAdmin.IRefresh,
  ): Promise<IShoppingMallAdmin.IAuthorized> {
    try {
      return await postShoppingMallAuthAdminRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
