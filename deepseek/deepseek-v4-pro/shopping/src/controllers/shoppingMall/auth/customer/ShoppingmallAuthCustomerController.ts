import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallCustomer } from "../../../../api/structures/IShoppingMallCustomer";
import { postShoppingMallAuthCustomerJoin } from "../../../../providers/postShoppingMallAuthCustomerJoin";
import { postShoppingMallAuthCustomerLogin } from "../../../../providers/postShoppingMallAuthCustomerLogin";
import { postShoppingMallAuthCustomerRefresh } from "../../../../providers/postShoppingMallAuthCustomerRefresh";

@Controller("/shoppingMall/auth/customer")
export class ShoppingmallAuthCustomerController {
  /**
   * Register a new customer account on the platform.
   *
   * Creates a customer record with the provided email, password, and display name. The email serves as the unique login identifier across all customer accounts and must not already be registered. The display name is set at registration and will be publicly visible on reviews and profile pages.
   *
   * Upon successful registration, an access token and refresh token pair is issued, establishing an authenticated session immediately. A verification email is also sent to the provided email address containing a unique, time-limited token link that must be confirmed to complete the registration process.
   *
   * The password is stored as a cryptographic hash using a secure one-way algorithm; the plain-text password is never persisted. If the email is already associated with an active customer account, the registration is rejected with a conflict error.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Customer registration request containing email, password, and display name.
     * @x-autobe-authorization-type join
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification Create a new customer account with email,
     *   password, and display_name. Hash the password using bcrypt or argon2
     *   before storage. Generate a unique UUID for the customer id. Set
     *   created_at and updated_at to the current timestamp. Check that the
     *   email is not already in use by an existing non-deleted customer
     *   (shopping_mall_customers.email unique constraint, where deleted_at IS
     *   NULL). If the email is already taken by an active account, return 409
     *   Conflict. If the email belongs to a soft-deleted account, treat as
     *   available (the old account is no longer active). After successful
     *   account creation, generate a JWT access token (short-lived, e.g., 15
     *   minutes) and refresh token (longer-lived, e.g., 7 days). Create a
     *   session record in shopping_mall_customer_sessions with the customer id,
     *   client IP address, href (originating page URL), referrer, created_at
     *   (now), and expired_at (7 days from now). Generate an email verification
     *   token (cryptographically random), store it in
     *   shopping_mall_customer_email_verifications with the customer id, token,
     *   expired_at (24 hours from now), and created_at (now). Send the
     *   verification email. Return the access token, refresh token, and session
     *   information in the IAuthorized response structure. Apply rate limiting:
     *   max 5 registration attempts per IP per hour to prevent abuse.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallCustomer.IJoin,
  ): Promise<IShoppingMallCustomer.IAuthorized> {
    try {
      return await postShoppingMallAuthCustomerJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate a customer using email and password credentials.
   *
   * Validates the provided credentials against registered customer accounts. Upon successful authentication, an access token and refresh token pair is issued, establishing a new session. The session records the client IP address, originating page URL, and HTTP referrer for security auditing and anomaly detection.
   *
   * If the account has been banned by an administrator, authentication is denied even with correct credentials. Accounts that have been soft-deleted cannot be authenticated. For security, the system returns identical error responses for invalid email addresses and incorrect passwords to prevent email enumeration attacks.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Customer login credentials containing email and password.
     * @x-autobe-authorization-type login
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification Authenticate a customer using email and password.
     *   Look up the customer by email in shopping_mall_customers where
     *   deleted_at IS NULL. If no matching customer is found, return 401
     *   Unauthorized with a generic message (do not reveal whether the email
     *   exists — prevent email enumeration). If a matching customer is found
     *   but banned_at IS NOT NULL, return 403 Forbidden indicating the account
     *   has been banned by an administrator. Compare the provided password
     *   against the stored password_hash using the secure hashing algorithm
     *   (bcrypt/argon2). If the password does not match, return 401
     *   Unauthorized. On successful authentication, create a new session in
     *   shopping_mall_customer_sessions with the customer id, client IP
     *   address, href (originating page URL), referrer, created_at (now), and
     *   expired_at (7 days from now). Generate a JWT access token (short-lived,
     *   e.g., 15 minutes) and refresh token (longer-lived, matching session
     *   expiry). Return the token pair and session info in the IAuthorized
     *   response. Apply rate limiting: max 5 failed attempts per email per
     *   minute, max 10 failed attempts per IP per minute, with exponential
     *   backoff on repeated failures to prevent brute-force attacks.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallCustomer.ILogin,
  ): Promise<IShoppingMallCustomer.IAuthorized> {
    try {
      return await postShoppingMallAuthCustomerLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh an expiring or expired access token using a valid refresh token.
   *
   * Exchanges a valid refresh token for a new access token and refresh token pair through secure token rotation. This allows the customer to maintain an authenticated session indefinitely without re-entering credentials, as long as the refresh token remains valid and unexpired.
   *
   * The original refresh token is invalidated upon use, preventing token replay attacks. Each successful refresh extends the session expiry. If the associated customer account has been banned or deleted since the session was originally created, the refresh is denied and the session is forcibly terminated.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Token refresh request containing the current refresh token.
     * @x-autobe-authorization-type refresh
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification Refresh an expiring access token using a valid
     *   refresh token. Extract the refresh token from the request body. Look up
     *   the associated session in shopping_mall_customer_sessions where the
     *   session is still active (expired_at > now). If no matching active
     *   session is found or the session has already expired, return 401
     *   Unauthorized. Verify the associated customer account status: look up
     *   the customer from shopping_mall_customers and verify deleted_at IS NULL
     *   and banned_at IS NULL. If the account has been deleted or banned since
     *   the session was created, terminate the session by setting expired_at to
     *   now and return 403 Forbidden (banned) or 401 Unauthorized (deleted). On
     *   success, generate a new JWT access token (15 minutes) and a new refresh
     *   token (7 days). Update the session's expired_at to extend it (7 days
     *   from now). Invalidate the old refresh token through token rotation —
     *   the new refresh token replaces the old one. The old access token may
     *   continue to work until its natural expiration. Return the new token
     *   pair in the IAuthorized response.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IShoppingMallCustomer.IRefresh,
  ): Promise<IShoppingMallCustomer.IAuthorized> {
    try {
      return await postShoppingMallAuthCustomerRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
