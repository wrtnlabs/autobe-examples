import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallCancellationRequestSnapshot } from "../../../../api/structures/IPageIShoppingMallCancellationRequestSnapshot";
import { IShoppingMallCancellationRequestSnapshot } from "../../../../api/structures/IShoppingMallCancellationRequestSnapshot";
import { patchShoppingMallCancellationRequestsRequestIdSnapshots } from "../../../../providers/patchShoppingMallCancellationRequestsRequestIdSnapshots";

@Controller("/shoppingMall/cancellation-requests/:requestId/snapshots")
export class ShoppingmallCancellation_requestsSnapshotsController {
  /**
   * Retrieves all snapshots belonging to a specific cancellation request.
   *
   * Cancellation request snapshots are immutable audit records created automatically by the system when a seller responds to a cancellation request. Each snapshot preserves the reason text and status of the cancellation request at the exact moment of the seller's decision, providing a permanent and unalterable record for dispute resolution and accountability.
   *
   * Snapshots cannot be created, edited, or deleted through any API — they are exclusively system-generated. This endpoint is strictly read-only, returning snapshots sorted by creation time (newest first) with pagination support.
   *
   * Access to these snapshots is restricted to the customer who submitted the cancellation request, the seller whose product is involved, and platform administrators. Unauthorized access attempts are rejected with a 403 Forbidden response.
   *
   * @param connection
   * @param requestId UUID of the cancellation request whose snapshots are being retrieved. (global scope)
   * @param body Pagination and sorting parameters for listing snapshots. Supports page number, items per page, and sort direction by creation timestamp.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor null
     * @x-autobe-specification Query the
     *   shopping_mall_cancellation_request_snapshots table filtered by
     *   shopping_mall_cancellation_request_id matching the {requestId} path
     *   parameter.
   *
   * Access control — verify the authenticated actor is one of:
   * - The customer who submitted the cancellation request. Resolve by joining: shopping_mall_cancellation_requests → shopping_mall_order_items → shopping_mall_orders (check shopping_mall_customer_id against the authenticated customer's ID).
   * - The seller who owns the product being cancelled. Resolve by joining: shopping_mall_cancellation_requests → shopping_mall_order_items → shopping_mall_product_variants → shopping_mall_products → shopping_mall_seller_profiles → shopping_mall_sellers (check the seller's authenticated ID).
   * - An administrator (any grade). Bypass all ownership checks.
   *
   * Reject with 403 Forbidden if the authenticated actor is none of the above.
   *
   * Snapshots are immutable per business rules (sections 448, 571) — no create, update, or delete logic applies. This endpoint is strictly read-only.
   *
   * Return 404 Not Found if the cancellation request referenced by {requestId} does not exist or has been soft-deleted (deleted_at IS NOT NULL).
   *
   * Apply pagination from the request body (page number, items per page with a sensible default and maximum). Support sorting by created_at (newest first by default, allow ascending option via sort direction parameter). Each snapshot record includes its id, reason, status, and created_at fields.
   *
   * The result set for a single cancellation request typically contains one snapshot (representing the seller's single response), but pagination is included for consistency with platform conventions.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedParam("requestId")
    requestId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallCancellationRequestSnapshot.IRequest,
  ): Promise<IPageIShoppingMallCancellationRequestSnapshot.ISummary> {
    try {
      return await patchShoppingMallCancellationRequestsRequestIdSnapshots({
        requestId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
