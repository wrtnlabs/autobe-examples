  /**
   * Retrieves a single option value of a product variant.
   *
   * Each product variant is defined by a specific combination of option values — key-value pairs that describe what makes the variant distinct from others of the same product. For example, a clothing variant might have option values for "color" set to "Red" and "size" set to "Large".
   *
   * This endpoint returns the full details of one option value record, including the dimension name (the key, such as "color" or "size"), its specific value, and creation/modification timestamps. The option value is identified by its unique ID and is scoped within the variant and product hierarchy. The system validates that the option value actually belongs to the specified variant and that the variant belongs to the specified product before returning data.
   *
   * @param connection
   * @param productId The unique identifier of the product that owns the variant (UUID).
   * @param variantId The unique identifier of the variant that owns this option value (UUID).
   * @param optionId The unique identifier of the option value to retrieve (UUID).
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification Query the
     *   shopping_mall_product_variant_option_values table by the given
     *   optionId.
   *
   * Validate the entity hierarchy chain:
   * 1. Look up the option value by id = optionId. If not found, return 404 Not Found.
   * 2. Confirm the option value's shopping_mall_product_variant_id matches variantId. If it does not match, return 404 Not Found (the option value exists but does not belong to this variant).
   * 3. Look up the variant and confirm its shopping_mall_product_id matches productId. If it does not match, return 404 Not Found.
   *
   * Check the parent product's soft-delete state (deleted_at). If the product is soft-deleted, return 404 Not Found since deleted products are hidden from all listings and their details are inaccessible to customers.
   *
   * For the variant's soft-delete state: if the variant has deleted_at set, the option values are still preserved in the database for historical integrity. The option value data may be returned, but the response should indicate the variant is no longer active so consumers can display appropriate UI cues.
   *
   * Return the full option value record: id (UUID), key (the option dimension name, e.g., "color"), value (the specific dimension value, e.g., "Red"), created_at, and updated_at.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":optionId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedParam("variantId")
    variantId: string & tags.Format<"uuid">,
    @TypedParam("optionId")
    optionId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallProductVariantOptionValue> {
    try {
      return await getShoppingMallCustomerProductsProductIdVariantsVariantIdOptionsOptionId(
        {
          customer,
          productId,
          variantId,
          optionId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
