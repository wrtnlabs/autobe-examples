import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallProductImage } from "../../../../../api/structures/IPageIShoppingMallProductImage";
import { IShoppingMallProductImage } from "../../../../../api/structures/IShoppingMallProductImage";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { getShoppingMallCustomerProductsProductIdImagesImageId } from "../../../../../providers/getShoppingMallCustomerProductsProductIdImagesImageId";
import { patchShoppingMallCustomerProductsProductIdImages } from "../../../../../providers/patchShoppingMallCustomerProductsProductIdImages";

@Controller("/shoppingMall/customer/products/:productId/images")
export class ShoppingmallCustomerProductsImagesController {
  /**
   * Retrieves the list of images belonging to a specific product, with optional filtering and pagination.
   *
   * Product images form the visual gallery displayed on the product detail page, in search results, and in category listings. Each image has a display order that determines its position — the image with the lowest display order serves as the main thumbnail. This endpoint returns images in their configured display order by default.
   *
   * Filtering and Sorting
   *
   * The request body supports filtering images by display order range and searching by image URL pattern. Results can be sorted by display order (default, ascending) or by creation date. Pagination is supported for products with large image sets.
   *
   * Access Control
   *
   * Customers can view images for any available product. Sellers can view images only for products they own, which supports their image management workflows (upload, reorder, delete). Administrators can view images for any product as part of platform oversight.
   *
   * @param connection
   * @param productId Unique identifier of the product whose images are being listed (global scope).
   * @param body Search and filter criteria including optional display order range, image URL pattern search, sorting preferences, and pagination parameters.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification Query the shopping_mall_product_images table
     *   filtered by the shopping_mall_product_id matching the {productId} path
     *   parameter.
   *
   * Validation:
   * - Verify the product exists in shopping_mall_products (including soft-deleted products, since snapshots may reference their images). If the product does not exist, return 404.
   *
   * Filtering (from IShoppingMallProductImage.IRequest):
   * - display_order range: apply min/max display_order filters if provided
   * - image_url search: apply partial text match on image_url if provided
   *
   * Sorting:
   * - Default sort: display_order ascending (images in gallery order)
   * - Allow sorting by created_at (newest/oldest first) when specified in request
   *
   * Pagination:
   * - Support cursor-based or offset-based pagination
   * - Include total count for page calculation
   *
   * Authorization:
   * - Customers: can view images of any non-deleted product (public product gallery)
   * - Sellers: can view images of their own products only (for management)
   * - Administrators: can view images of any product (for oversight)
   * - Guests: cannot access this endpoint (must be authenticated)
   *
   * The response IShoppingMallProductImage.ISummary includes id, image_url, display_order, and created_at — sufficient for gallery rendering without the full product relation.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallProductImage.IRequest,
  ): Promise<IPageIShoppingMallProductImage.ISummary> {
    try {
      return await patchShoppingMallCustomerProductsProductIdImages({
        customer,
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves a single product image by its unique identifier within the context of a specific product.
   *
   * Returns the full image record including the image URL, its display order position within the product's image gallery, and creation/modification timestamps. The display order determines the visual arrangement of images — the image with the lowest display order value serves as the main thumbnail used in search results and category listings.
   *
   * This endpoint is accessible to all authenticated users who can view the product. No special permissions are required for reading image data.
   *
   * @param connection
   * @param productId Unique identifier of the product that owns this image.
   * @param imageId Unique identifier of the product image to retrieve (scoped to the specified product).
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification Query the shopping_mall_product_images table by
     *   the given imageId, ensuring the image's shopping_mall_product_id
     *   matches the productId path parameter. Return the full image record
     *   including id, image_url, display_order, created_at, and updated_at. If
     *   no image matches the composite condition (imageId + productId), return
     *   a 404 not found error. This is a read-only operation — no side effects.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":imageId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedParam("imageId")
    imageId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallProductImage> {
    try {
      return await getShoppingMallCustomerProductsProductIdImagesImageId({
        customer,
        productId,
        imageId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
