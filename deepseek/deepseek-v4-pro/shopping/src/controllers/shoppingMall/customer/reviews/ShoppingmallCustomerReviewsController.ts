  /**
   * Edits an existing review written by the authenticated customer.
   *
   * This endpoint allows a customer to update the star rating, the written feedback, or both on a review they previously authored. The review must belong to the authenticated customer and must not have been previously deleted.
   *
   * When a review is edited, the system automatically preserves the previous state by creating an immutable snapshot that records the rating and text content as they were before the change. This ensures a complete and auditable history of all modifications to every review.
   *
   * The review's original creation date is never altered. This means the review retains its position in the newest-first display order on the product detail page regardless of how many times it is edited. The product's average rating is recalculated after the update to reflect the new rating value.
   *
   * @param connection
   * @param reviewId Unique identifier of the review to update. Must be a valid UUID referencing an existing, non-deleted review owned by the authenticated customer.
   * @param body The updated review data containing the new star rating (integer from 1 to 5) and optional text content. Content may be null to indicate a rating-only review.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification Update a review owned by the authenticated
     *   customer. The implementation must:
   *
   * 1. Authenticate: Verify the requester is a customer. Reject with 401 if unauthenticated or not a customer.
   *
   * 2. Retrieve the review: Query shopping_mall_review_reviews by reviewId. Reject with 404 if the review does not exist or if deleted_at is not null (soft-deleted reviews cannot be edited).
   *
   * 3. Ownership check: Verify that shopping_mall_customer_id matches the authenticated customer's ID. Reject with 403 if the review belongs to a different customer.
   *
   * 4. Validate input: Ensure rating is an integer between 1 and 5 inclusive. Reject with 400 if rating is missing, out of range, or non-integer. Content is optional — null is accepted and means the review has no text.
   *
   * 5. Create snapshot (before update): Insert a row into shopping_mall_review_review_snapshots with shopping_mall_review_review_id set to reviewId, rating set to the current (pre-edit) rating value, content set to the current (pre-edit) content value, and created_at set to the current timestamp. This preserves the audit trail.
   *
   * 6. Apply update: Set rating to the new value, content to the new value (may be null), and updated_at to the current timestamp. Do NOT modify created_at, id, shopping_mall_customer_id, shopping_mall_product_id, shopping_mall_order_id, shopping_mall_order_item_id, or deleted_at.
   *
   * 7. Return the fully updated review entity including all fields.
   *
   * Edge cases:
   * - If the new rating and content are identical to the existing values, the snapshot is still created and updated_at is still refreshed — this maintains audit consistency and signals that an edit action was performed even if values didn't change.
   * - The review's position in product detail page listings (sorted by created_at descending per the @@index([shopping_mall_product_id, created_at])) does not change after edit.
   * - The product's average rating must be recalculated from all non-deleted reviews after the rating change.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
