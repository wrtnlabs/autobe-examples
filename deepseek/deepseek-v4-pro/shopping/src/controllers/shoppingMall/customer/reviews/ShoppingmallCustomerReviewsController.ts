  /**
   * Soft-deletes a review written by the authenticated customer.
   *
   * When a review is deleted, it is immediately hidden from the product detail page. Its star rating is excluded from the product's average rating calculation, and the total review count displayed on the product page is decremented accordingly. Other customers will no longer see this review when browsing the product.
   *
   * The review data — including the star rating, text content, and creation timestamp — is preserved in the database for audit and dispute resolution. All snapshots associated with the review (created during previous edits via `shopping_mall_review_review_snapshots`) remain available for historical record-keeping even after the review itself is deleted.
   *
   * Only the review author may delete their own review. If the authenticated customer is not the original author, the operation is rejected with a 403 Forbidden response. An already-deleted review cannot be deleted again — attempting to do so returns a 409 Conflict.
   *
   * @param connection
   * @param reviewId The unique identifier of the review to delete, in UUID format. This corresponds to the primary key of the `shopping_mall_review_reviews` table.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification Soft-delete a review by setting its `deleted_at`
     *   timestamp to NOW(). The `updated_at` field is also refreshed to NOW().
   *
   * **Authorization**:
   * Compare the authenticated customer ID against the review's `shopping_mall_customer_id`. Reject with 403 Forbidden if the authenticated customer is not the review author.
   *
   * **Database Operations**:
   * 1. Query `shopping_mall_review_reviews` by `id` matching the `{reviewId}` path parameter. Return 404 Not Found if no matching record exists.
   * 2. Compare the authenticated customer ID against `shopping_mall_customer_id`. Return 403 Forbidden on mismatch.
   * 3. Check `deleted_at`: if already non-null, return 409 Conflict — the review has already been deleted (idempotency guard).
   * 4. Update the record: SET `deleted_at = NOW()`, `updated_at = NOW()`.
   * 5. Return the updated review entity including the new `deleted_at` timestamp.
   *
   * **Side Effects**:
   * - The review is excluded from product detail page display.
   * - The review's rating is excluded from the product's average rating calculation.
   * - The review is excluded from the total review count.
   * - All associated `shopping_mall_review_review_snapshots` records are preserved unchanged.
   *
   * **Edge Cases**:
   * - Idempotency: attempting to delete an already-deleted review returns 409 Conflict rather than silently succeeding.
   * - Deleted user scenario: If the customer account that authored the review has been deleted, the review displays as authored by "deleted user" and this deletion operation is no longer possible since the customer account no longer exists.
   * - Soft-delete does NOT cascade: references to product, order, and order-item remain intact.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":reviewId")
  public async erase(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallCustomerReviewsReviewId({
        customer,
        reviewId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
