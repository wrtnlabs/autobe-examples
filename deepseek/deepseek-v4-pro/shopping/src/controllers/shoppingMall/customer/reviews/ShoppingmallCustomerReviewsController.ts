  /**
   * Create a new product review.
   *
   * Allows an authenticated customer to write a review for a product they have purchased and received. The customer must have an order containing the product, and the corresponding order item must be in delivered status before a review can be written. Only one review per product per order is permitted — if the customer purchases the same product across multiple orders, a separate review may be written for each order.
   *
   * The review requires a star rating from 1 to 5 and supports optional text content for written feedback. Once created, the review appears on the product detail page sorted by newest first and contributes to the product's average rating calculation.
   *
   * Customers can later edit or delete their own reviews. Edits create immutable snapshots preserving the review history, and deleted reviews are excluded from public display and average rating calculations while their data is preserved for audit purposes.
   *
   * @param connection
   * @param body Review creation payload containing the product and order references, star rating, and optional text content. The customer identity is derived from the authenticated session.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification Create a new product review for the authenticated
     *   customer.
   *
   * **Authentication**: Requires a valid customer session. The customer ID is extracted from the session token.
   *
   * **Eligibility Validation** (execute in order, return 422 with descriptive message on failure):
   * 1. Verify the order (shopping_mall_order_id) belongs to the authenticated customer.
   * 2. Verify the order item (shopping_mall_order_item_id) belongs to the order and references the product (shopping_mall_product_id).
   * 3. Verify the order item status is 'delivered' — reviews can only be written after the item has been delivered.
   * 4. Check the unique constraint: query shopping_mall_review_reviews for an existing non-deleted review with the same (customer_id, product_id, order_id). If found, return 409 Conflict.
   *
   * **Creation**:
   * - Insert a new row into shopping_mall_review_reviews with: id (generated UUID), shopping_mall_customer_id (from session), shopping_mall_product_id, shopping_mall_order_id, shopping_mall_order_item_id, rating (1-5), content (nullable string), created_at (now), updated_at (now), deleted_at (null).
   *
   * **Response**: Return the created review as IShoppingMallReviewReview with all fields populated. Join with customer to include display_name for the reviewer identity.
   *
   * **Error cases**:
   * - 401 Unauthorized: No valid customer session.
   * - 422 Unprocessable Entity: Invalid eligibility (wrong customer, wrong product-order_item association, item not delivered).
   * - 409 Conflict: Review already exists for this customer-product-order combination.
   * - 400 Bad Request: Rating outside 1-5 range or missing required fields.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
