import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallGuestSession } from "../../../../api/structures/IPageIShoppingMallGuestSession";
import { IShoppingMallCustomerSession } from "../../../../api/structures/IShoppingMallCustomerSession";
import { IShoppingMallGuestSession } from "../../../../api/structures/IShoppingMallGuestSession";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { getShoppingMallCustomerSessionsSessionId } from "../../../../providers/getShoppingMallCustomerSessionsSessionId";
import { patchShoppingMallCustomerSessions } from "../../../../providers/patchShoppingMallCustomerSessions";

@Controller("/shoppingMall/customer/sessions")
export class ShoppingmallCustomerSessionsController {
  /**
   * Search and browse authentication sessions across the platform.
   *
   * This endpoint provides administrators with a unified view of all active and expired sessions — customer, seller, administrator, and guest — for security auditing and access pattern analysis. Each session record captures the originating IP address, the page URL at login, the referring page, and the session's creation and expiration timestamps.
   *
   * Sessions are append-only audit records. They are created automatically on successful authentication and terminated on logout, expiration, password change, account deletion, or ban. No actor — including super administrators — can modify or delete session records after creation.
   *
   * Search results support filtering by actor type to narrow results to a specific user category, by IP address to trace access patterns or detect credential compromise across geographically distant origins, by date range to review session activity within a specific time window, and by active status to identify currently logged-in users.
   *
   * @param connection
   * @param body Search criteria for session records including actor type filter, IP address filter, actor identifier, creation and expiration date ranges, active status filter, and pagination parameters.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification Query across all four session tables —
     *   shopping_mall_customer_sessions, shopping_mall_seller_sessions,
     *   shopping_mall_admin_sessions, shopping_mall_guest_sessions — using
     *   UNION ALL with per-table actor type tagging (discriminator values:
     *   "customer", "seller", "admin", "guest").
   *
   * Apply filters:
   * - actorType: filter to specific session table(s) only — omit to search all four tables
   * - ip: partial or exact IP address substring match for security auditing and anomaly detection
   * - actorId: filter sessions belonging to a specific actor (customer ID, seller ID, admin ID, or guest ID)
   * - createdFrom/createdTo: session creation timestamp range (inclusive lower, exclusive upper)
   * - expiredFrom/expiredTo: session expiration timestamp range (inclusive lower, exclusive upper)
   * - isActive: when true, filter to sessions where expired_at > NOW(); when false, filter to expired_at <= NOW(); omit to include both
   *
   * Apply pagination (cursor-based, default 20 per page, max 100). Sort by created_at descending (newest sessions first).
   *
   * Each response summary record must include an `actorType` discriminator field ("customer" | "seller" | "admin" | "guest") so consumers can distinguish the session owner type. Additionally include: session id, actor id, ip, href, referrer, created_at, expired_at, and isActive (computed boolean).
   *
   * Security: restricted to admin actors only. Super admins see all sessions including other admin sessions. Regular admins see all sessions except sessions belonging to other admins (filter out shopping_mall_admin_sessions rows where the actor is not the requesting admin). Sessions are append-only — no write, update, or delete operations are permitted on any session table.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallGuestSession.IRequest,
  ): Promise<IPageIShoppingMallGuestSession.ISummary> {
    try {
      return await patchShoppingMallCustomerSessions({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific customer authentication session by its unique identifier.
   *
   * The session record provides complete context about a customer's login event, including the originating IP address for security auditing, the page URL (href) the customer was viewing at login for redirect flows, and the referring page (referrer) for understanding navigation patterns. The created_at and expired_at timestamps define the session's valid time window.
   *
   * This endpoint is used for session inspection, security auditing of login patterns, and verifying whether a given session identifier is still valid. Expired sessions are still returned — callers should check expired_at against the current time to determine session validity.
   *
   * @param connection
   * @param sessionId Unique identifier of the customer session to retrieve (UUID format).
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification Query the shopping_mall_customer_sessions table
     *   by primary key id = sessionId.
   *
   * Return the full session record including all fields: id, shopping_mall_customer_id, ip, href, referrer, created_at, and expired_at.
   *
   * If no session exists with the given sessionId, return a 404 Not Found error.
   *
   * If the session exists but expired_at is in the past, still return the record — expiration status is informational and callers determine validity themselves.
   *
   * This operation is read-only and never modifies data.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallCustomerSession> {
    try {
      return await getShoppingMallCustomerSessionsSessionId({
        customer,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
