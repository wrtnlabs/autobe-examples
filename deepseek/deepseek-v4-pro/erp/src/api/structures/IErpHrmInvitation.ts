/**
 * An employee invitation record for joining an organization.
 *
 * Represents an invitation sent to an email address, inviting that person to join the current organization as an employee. The invitation carries an assigned role that determines the invitee's permissions upon joining.
 *
 * **Status Lifecycle**: The invitation starts as pending when sent. It transitions to resolved when the recipient signs up with the matching email address, at which point they automatically become an employee with the assigned role.
 *
 * **Multi-organization**: The same email address can have pending invitations in different organizations simultaneously. Each invitation is scoped to a single organization.
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type IErpHrmInvitation = {
  /**
   * Unique identifier for the invitation.
   *
   * A system-generated UUID assigned when the invitation record is created. Used to reference the invitation in subsequent operations such as revocation or status checks.
   *
     * @x-autobe-specification System-generated UUID v4 assigned at invitation
     *   creation time. Not derived from any database column.
   */
  id: string & tags.Format<"uuid">;

  /**
   * The email address of the invited person.
   *
   * The invitation is delivered to this email address. The recipient must sign up using the same email for the invitation to be automatically resolved. Only one pending invitation per email address can exist within an organization at any time.
   *
     * @x-autobe-specification The email address the invitation was sent to.
     *   Must be unique among pending invitations within the same organization.
     *   Validated as a properly formatted email address. Used for matching when
     *   the recipient signs up.
   */
  email: string & tags.Format<"email">;

  /**
   * Current status of the invitation.
   *
   * **pending**: The invitation has been sent but the recipient has not yet signed up with the matching email address. The invitation remains in this state indefinitely until fulfilled, revoked, or the organization is deleted.
   *
   * **resolved**: The recipient has signed up with the matching email and has been automatically added as an employee of the organization with the assigned role.
   *
     * @x-autobe-specification Enum discriminator with two possible values:
     *   'pending' or 'resolved'. Set to 'pending' at invitation creation time.
     *   Transitions to 'resolved' when the recipient successfully signs up with
     *   the matching email address. No other valid transitions exist.
   */
  status: "pending" | "resolved";

  /**
   * The role assigned to the invitee upon joining the organization.
   *
   * Determines the complete set of permissions the new employee will have once the invitation is resolved. The role is selected at invitation creation time and cannot be changed after the invitation is sent. Use the employee role change operation if a different role is needed after the employee joins.
   *
     * @x-autobe-specification Resolved from the stored role_id by joining to
     *   erp_hrm_roles. Returns the ISummary of the role the invitee will
     *   receive upon joining. Includes id, name, is_builtin, description,
     *   permissions_count, created_at, and updated_at.
   */
  role: IErpHrmRole.ISummary;

  /**
   * Timestamp when the invitation was sent.
   *
   * Represents the exact moment the invitation record was created and the invitation email was dispatched to the recipient. This timestamp is immutable and provides an audit trail of when the invitation process began.
   *
     * @x-autobe-specification Timestamp recorded at the moment the invitation
     *   is created and the email is dispatched. Captured as server time at
     *   record creation. Immutable after creation.
   */
  created_at: string & tags.Format<"date-time">;

  /**
   * Timestamp when the invitation was resolved.
   *
   * Null when the invitation is still in pending status. Set to the exact moment the recipient successfully signs up with the matching email address, at which point the invitation is fulfilled and the user is automatically added as an employee of the organization with the assigned role.
   *
     * @x-autobe-specification Null when the invitation status is 'pending'. Set
     *   to the server timestamp at the moment the recipient signs up with the
     *   matching email address and the invitation transitions to 'resolved'.
     *   Immutable once set.
   */
  resolved_at: (string & tags.Format<"date-time">) | null;
};
