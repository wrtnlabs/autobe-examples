/**
 * Verify a member's email address by consuming a one-time verification token delivered during sign-up.
 *
 * This endpoint confirms email ownership and completes the registration verification step. The verification token is embedded in the link sent to the user's email address after sign-up. Tokens have a limited lifespan — expired tokens are rejected and the user must request a new verification email.
 *
 * **Invitation Fulfillment**: Upon successful verification, the system automatically checks for any pending organization invitations sent to the verified email address. Matching invitations are fulfilled and the user is enrolled as an employee in those organizations, gaining immediate access upon their next login.
 *
 * **Security**: Each token can only be used once. Attempting to verify an already-consumed token returns a conflict error. The token is cryptographically secure and globally unique, preventing enumeration attacks.
 *
 * @param props.connection
 * @param props.verificationId The cryptographically secure verification token sent to the user's email address during sign-up. This is the unique token string, not the UUID primary key of the verification record.
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor guest
 * @x-autobe-specification Verify a member's email address by consuming a
 *   one-time verification token.
 *
 * Look up the erp_hrm_member_email_verifications record where token equals the {verificationId} path parameter. The lookup uses the unique token index — do not use the UUID primary key for lookup.
 *
 * Reject the request if:
 * - No verification record exists with the given token (return 404 not-found)
 * - The token has already been consumed (verified_at is not null) — return a conflict error indicating the email was already verified
 * - The token has expired (expires_at is before the current timestamp) — return a gone/expired error
 *
 * On success, update the record:
 * - Set verified_at to the current timestamp
 * - Set updated_at to the current timestamp
 *
 * After successful verification, automatically fulfill pending invitations:
 * - Query erp_hrm_invitations where email equals the verified email address and status is 'pending'
 * - For each matching invitation, update its status to 'fulfilled' and create an erp_hrm_employees record linking the member to the inviting organization with the role specified in the invitation
 *
 * Return the updated verification record including the email, verified_at timestamp, and status.
 * @path /erpHrm/guest/email-verifications/:verificationId/verification
 * @accessor api.functional.erpHrm.guest.email_verifications.verification.verify
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function verify(
  connection: IConnection,
  props: verify.Props,
): Promise<verify.Response> {
  return true === connection.simulate
    ? verify.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...verify.METADATA,
          path: verify.path(props),
          status: null,
        },
      );
}
