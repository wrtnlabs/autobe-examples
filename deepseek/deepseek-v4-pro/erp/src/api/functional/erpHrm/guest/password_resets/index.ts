/**
 * Initiates the password reset flow by requesting a reset token for the specified email address.
 *
 * A password reset token is a time-limited, cryptographically secure string sent to the member's registered email. The token serves as proof of email ownership and is required to complete the password change operation. Tokens are single-use and expire after a configurable duration.
 *
 * This endpoint is accessible to both guests and authenticated members. For authenticated members who are already logged in and know their current password, the change-password flow (which requires the current password) is the preferred path.
 *
 * For privacy and security, the response does not indicate whether the provided email address exists in the system. This prevents attackers from enumerating registered email addresses. The system always returns a successful response after processing, regardless of the email lookup result.
 *
 * @param props.connection
 * @param props.body The email address associated with the member account for which a password reset is requested.
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor guest
 * @x-autobe-specification Accept the member's email address in the request
 *   body. Look up the member in erp_hrm_members by email, excluding records
 *   where deleted_at IS NOT NULL. If the email is invalid or no active member
 *   is found, return a 204 No Content response without creating any record — do
 *   not reveal whether the email exists. For a matching member, delete any
 *   existing unused password reset tokens for that member to prevent token
 *   accumulation. Generate a new cryptographically secure random token string
 *   that is globally unique (enforced by @@unique([token])). Set created_at and
 *   updated_at to the current timestamp. Set expired_at to a point after which
 *   the token becomes invalid. Store the record in
 *   erp_hrm_member_password_resets with the member's UUID as erp_hrm_member_id.
 *   Send the token to the member's email address via email service. Return 204
 *   No Content regardless of outcome to prevent email enumeration. Handle edge
 *   cases: rate-limit requests per IP and per email to prevent abuse; reject
 *   malformed email formats with 400 Bad Request before any lookup.
 * @path /erpHrm/guest/password-resets
 * @accessor api.functional.erpHrm.guest.password_resets.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function create(
  connection: IConnection,
  props: create.Props,
): Promise<void> {
  return true === connection.simulate
    ? create.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...create.METADATA,
          path: create.path(),
          status: null,
        },
        props.body,
      );
}
