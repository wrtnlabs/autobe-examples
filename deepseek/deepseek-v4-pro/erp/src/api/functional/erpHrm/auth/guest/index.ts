/**
 * Register a new member account with email, password, and display name, immediately authenticating the guest.
 *
 * Creates a user profile in the system and issues JWT access and refresh tokens so the guest transitions directly to an authenticated member without a separate login step. The email address must not already be registered — if it is, the caller should use the login endpoint instead.
 *
 * If a pending organization invitation exists for the registered email address, the new member is automatically enrolled into the inviting organization with the role specified in the invitation. This allows invitation recipients to seamlessly join organizations upon sign-up without additional steps.
 *
 * Security: Passwords are hashed using a one-way algorithm before storage and are never logged, returned in responses, or transmitted in plaintext after the initial request. The access token is short-lived for security; use the refresh token to obtain new access tokens. The refresh token has a longer lifespan with an explicit expiration.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Account registration credentials for creating a new member account. Email must be unique across the entire platform — an existing email indicates the user already has an account and should log in. Password must be at least 8 characters with at least one letter and one digit. Display name is the member's visible identity shown across all organizations they belong to.
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor guest
 * @x-autobe-specification Create a new member account and authenticate the
 *   guest in a single atomic operation.
 *
 * 1. Validate that email is not already registered by checking erp_hrm_members.email uniqueness constraint. If a matching email exists, return 409 Conflict with message indicating the email is already registered and the guest should log in instead.
 *
 * 2. Validate password strength: minimum 8 characters, at least one letter and one digit. Return 422 Unprocessable Entity if password does not meet requirements.
 *
 * 3. Validate that display_name is non-empty. Return 422 Unprocessable Entity if missing or blank.
 *
 * 4. Hash the password using a secure one-way algorithm (bcrypt or argon2id). Never store or log plaintext passwords.
 *
 * 5. Create an erp_hrm_members record with email, password_hash, and display_name. Set created_at and updated_at to current timestamp. Leave avatar_image and phone_number as null (populated later via member profile operations).
 *
 * 6. Create an erp_hrm_member_sessions record: generate a cryptographically signed JWT access_token (short-lived, e.g., 15 minutes) and a JWT refresh_token (longer-lived, e.g., 7 days). Capture the client's IP address, page URL (href), and HTTP Referer from the request context. Set created_at to now and expired_at based on the refresh token lifespan. Leave erp_hrm_organization_id as null — the member selects an organization context after authentication.
 *
 * 7. Check for pending erp_hrm_invitations where invitation.email matches the new member's email and invitation.status allows resolution. If any exist, automatically create erp_hrm_employees records linking the member to the inviting organizations with the role specified in each invitation, and mark the invitations as resolved.
 *
 * 8. Return the access_token and refresh_token in the response body. The guest is now authenticated as a member.
 *
 * Edge cases:
 * - Email already registered → 409 Conflict with guidance to log in
 * - Weak password → 422 Unprocessable Entity with specific strength requirements
 * - Missing or empty display_name → 422 Unprocessable Entity
 * - Invitation matching failure (e.g., expired invitation) is non-fatal — account creation succeeds regardless; the member can accept invitations later
 * - Concurrent registration race with same email → database unique constraint handles it, return 409 Conflict
 * @path /erpHrm/auth/guest/join
 * @accessor api.functional.erpHrm.auth.guest.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
