/**
 * Obtain a new JWT access token using a valid refresh token, extending the authenticated session without requiring the user to authenticate again.
 *
 * Presents a previously issued refresh token to receive a fresh access token and a rotated refresh token. This allows long-lived sessions while maintaining security through short-lived access tokens and single-use refresh tokens.
 *
 * Token rotation is enforced: each refresh operation invalidates the previous refresh token and issues a new one. If a refresh token that has already been used is presented again, the system rejects it and may invalidate the entire session as a security measure against token theft.
 *
 * Session expiration is strictly enforced: if the session's expiration timestamp has passed, the refresh is denied and the user must authenticate again via join or login.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body The refresh token previously issued during join or a prior refresh operation. This token identifies the member session to be extended. Each refresh token is single-use — after a successful refresh, the presented token becomes invalid.
 * @x-autobe-authorization-type refresh
 * @x-autobe-authorization-actor guest
 * @x-autobe-specification Refresh an expiring or expired JWT access token by
 *   presenting a valid refresh token, issuing a new token pair.
 *
 * 1. Look up the erp_hrm_member_sessions record matching the provided refresh_token (via the unique index on access_token is for access tokens; search by refresh_token column). If no session is found, return 401 Unauthorized with message indicating the refresh token is invalid or has already been rotated.
 *
 * 2. Check that the session's expired_at timestamp has not passed. If the session is expired, return 401 Unauthorized with message indicating the session has expired and the guest must join or the member must log in again.
 *
 * 3. Validate that the member account associated with the session has not been soft-deleted (erp_hrm_members.deleted_at IS NULL). If the account is deleted, return 401 Unauthorized — deleted accounts cannot refresh sessions.
 *
 * 4. Generate a new JWT access_token with the same member identity claims (member id, email). Rotate the refresh_token: generate a new refresh_token, update the erp_hrm_member_sessions record with both new tokens, and extend expired_at to maintain the session's remaining lifespan or grant a fresh expiration window based on security policy.
 *
 * 5. The old refresh_token is now invalid. Any subsequent attempt to use the old refresh_token must fail (detectable replay attack).
 *
 * 6. Return the new access_token and new refresh_token in the response body.
 *
 * Token rotation rationale: Each refresh consumes the previous refresh token and issues a new one. This prevents replay attacks — if a stolen refresh token is used after the legitimate user has already refreshed, the system detects the reuse and can invalidate all tokens for that session, forcing re-authentication.
 *
 * Edge cases:
 * - Invalid, malformed, or previously-rotated refresh token → 401 Unauthorized
 * - Expired session (expired_at has passed) → 401 Unauthorized
 * - Deleted member account (deleted_at IS NOT NULL) → 401 Unauthorized
 * - Token reuse after rotation → 401 Unauthorized (potential token theft; invalidate entire session)
 * @path /erpHrm/auth/guest/refresh
 * @accessor api.functional.erpHrm.auth.guest.refresh
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
