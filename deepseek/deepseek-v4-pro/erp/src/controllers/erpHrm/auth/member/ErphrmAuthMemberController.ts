import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IErpHrmMember } from "../../../../api/structures/IErpHrmMember";
import { postErpHrmAuthMemberJoin } from "../../../../providers/postErpHrmAuthMemberJoin";
import { postErpHrmAuthMemberLogin } from "../../../../providers/postErpHrmAuthMemberLogin";
import { postErpHrmAuthMemberRefresh } from "../../../../providers/postErpHrmAuthMemberRefresh";

@Controller("/erpHrm/auth/member")
export class ErphrmAuthMemberController {
  /**
   * Register a new member account with email and password credentials.
   *
   * Creates a member record in erp_hrm_members with the provided display name, email address, and a securely hashed password. Email must be unique across all non-deleted accounts — if the email is already registered, the request is rejected with a 409 Conflict response directing the user to log in instead.
   *
   * Upon successful registration, the system automatically authenticates the new member by issuing a JWT access token and refresh token pair stored in erp_hrm_member_sessions. No separate login step is required after sign-up. An email verification token is generated and stored in erp_hrm_member_email_verifications to confirm email ownership. Once the email is verified, the system automatically matches any pending organization invitations sent to that email address.
   *
   * The access token is short-lived and must be presented as a Bearer token on all authenticated requests. The refresh token is used to obtain a new access token when the current one expires, without re-entering credentials.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Registration payload containing the new member's email, password, and display name.
     * @x-autobe-authorization-type join
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Create a new member account in erp_hrm_members
     *   with the provided email and password. Hash the password with a secure
     *   algorithm (bcrypt or argon2) and store the hash in password_hash. Set
     *   display_name from the request. Set created_at and updated_at to the
     *   current timestamp. Enforce email uniqueness via the @@unique([email])
     *   index — if the email already exists in a non-deleted account
     *   (deleted_at IS NULL), return 409 Conflict. If the email matches a
     *   previously soft-deleted account, treat it as a new registration and
     *   clear deleted_at.
   *
   * After creating the member record, generate a cryptographically secure email verification token and insert it into erp_hrm_member_email_verifications with the member's ID, the email address, an expiration timestamp (e.g., 24 hours from now), and created_at. This token enables email ownership confirmation and triggers automatic matching of any pending invitations to the verified email.
   *
   * Create a member session in erp_hrm_member_sessions: generate JWT access_token (short-lived, e.g., 15 minutes) and refresh_token (longer-lived, e.g., 7 days). Store both tokens, the member ID, IP address from the request context, href, referrer, created_at (now), and expired_at (matching refresh token lifespan). Set erp_hrm_organization_id to null initially — the member selects an organization after login or is automatically assigned if they belong to exactly one. The @@unique([access_token]) index enforces access token uniqueness.
   *
   * Return the access_token, refresh_token, session expiration, and basic member information (id, email, display_name).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IErpHrmMember.IJoin,
  ): Promise<IErpHrmMember.IAuthorized> {
    try {
      return await postErpHrmAuthMemberJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate an existing member using email and password credentials.
   *
   * Validates the member's email and password against the erp_hrm_members table. The account must exist and must not be soft-deleted (deleted_at IS NULL). If credentials are valid, the system issues a JWT access token and refresh token pair stored in erp_hrm_member_sessions, establishing an authenticated session.
   *
   * The response includes the member's global profile information (id, email, display_name, avatar_image, phone_number) and a list of organizations the member belongs to through employee records. If the member belongs to multiple organizations, the client should present an organization selection interface. The selected organization context is set via a separate operation and scopes all subsequent API requests for data isolation.
   *
   * Members whose email has not yet been verified can still log in. The verification status is indicated in the response, allowing the client to prompt for email verification if needed.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Login credentials containing the member's registered email address and password.
     * @x-autobe-authorization-type login
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Validate the provided email and password against
     *   the erp_hrm_members table. Look up the member by email where deleted_at
     *   IS NULL (account must not be soft-deleted). If no such member exists or
     *   the password does not match the stored password_hash, return 401
     *   Unauthorized with a generic message to avoid user enumeration.
   *
   * On successful authentication, create a new session in erp_hrm_member_sessions: generate a JWT access_token (short-lived) and a refresh_token (longer-lived). Store both tokens along with the member ID, the client's IP address, href, referrer, created_at (current timestamp), and expired_at (matching refresh token lifespan). The @@unique([access_token]) index ensures each access token is globally unique.
   *
   * Set erp_hrm_organization_id to null initially. After issuing tokens, query erp_hrm_employees to find all organizations the member belongs to (via employee records linking to this member). Include the list of organizations in the response so the client can present an organization selection screen.
   *
   * Return the access_token, refresh_token, session expiration, member profile (id, email, display_name, avatar_image, phone_number), and list of organizations the member belongs to.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IErpHrmMember.ILogin,
  ): Promise<IErpHrmMember.IAuthorized> {
    try {
      return await postErpHrmAuthMemberLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Obtain a new JWT access token using a valid refresh token, without requiring the member to re-enter credentials.
   *
   * Looks up the provided refresh token in erp_hrm_member_sessions. The session must exist, must not have expired (expired_at in the future), and the associated member account must not be soft-deleted. On success, the system performs token rotation: both the access token and refresh token are replaced with newly generated values, and the session expiration is extended.
   *
   * The old refresh token is invalidated immediately upon rotation. This prevents token replay attacks and ensures each refresh token can only be used once. The new tokens carry the same organization context as the previous session. The response includes the updated member profile and organization list, allowing the client to refresh its cached state.
   *
   * If the refresh token is expired, invalid, or the member account has been deleted, the request is rejected with 401 Unauthorized and the client must redirect the user to the login flow.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Token refresh payload containing the current refresh token to exchange for a new token pair.
     * @x-autobe-authorization-type refresh
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Validate the provided refresh_token against
     *   erp_hrm_member_sessions. Look up the session by the refresh_token
     *   value. Ensure the session has not expired (expired_at > now) and the
     *   associated member account is not soft-deleted (join to erp_hrm_members,
     *   check deleted_at IS NULL). If the session is expired, the member is
     *   soft-deleted, or the token is not found, return 401 Unauthorized.
   *
   * On successful validation, perform token rotation: generate a new JWT access_token and a new refresh_token. Update the session record with both new tokens, reset expired_at to a new future timestamp (maintaining the same lifespan policy), and update the IP address to the current request's IP. The old refresh_token is invalidated by this replacement. The @@unique([access_token]) index on the new access_token ensures no collisions.
   *
   * If the session's erp_hrm_organization_id is set, carry that organization context forward in the new tokens. If null, the member will need to select an organization.
   *
   * Return the new access_token, refresh_token, updated session expiration, and the member's current profile and organization membership list.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IErpHrmMember.IRefresh,
  ): Promise<IErpHrmMember.IAuthorized> {
    try {
      return await postErpHrmAuthMemberRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
