import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IErpHrmMemberPasswordReset } from "../../../../../api/structures/IErpHrmMemberPasswordReset";
import { GuestAuth } from "../../../../../decorators/GuestAuth";
import { GuestPayload } from "../../../../../decorators/payload/GuestPayload";
import { postErpHrmGuestPasswordResetsResetIdCompletion } from "../../../../../providers/postErpHrmGuestPasswordResetsResetIdCompletion";

@Controller("/erpHrm/guest/password-resets/:resetId/completion")
export class ErphrmGuestPassword_resetsCompletionController {
  /**
   * Completes a password reset by verifying the reset token and setting a new password.
   *
   * This endpoint is the final step in the password recovery flow. After requesting a password reset, the member receives an email containing a link back to the application. The link carries the unique reset request identifier. The member enters a new password, and the client submits both the reset identifier and the cryptographic token (extracted from the email link) to this endpoint.
   *
   * The system validates that the reset request exists, has not expired, and that the provided token matches the one sent to the member's email. Upon successful verification, the member's password is updated and the reset token is consumed and deleted. The member can then log in with the new password.
   *
   * This endpoint is accessible without authentication — the member is in the process of recovering access and does not have an active session.
   *
   * @param connection
   * @param resetId The unique identifier of the password reset request, provided in the password reset email link.
   * @param body The password reset completion payload containing the cryptographic token from the email and the new password to set.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor guest
     * @x-autobe-specification Complete a password reset by verifying the token
     *   and updating the member's password.
   *
   * 1. Look up the erp_hrm_member_password_resets record by the provided resetId (UUID primary key). If no record is found, return a 404 error.
   *
   * 2. Check the expired_at timestamp against the current time. If expired_at is in the past, the token has expired. Return a 400 error indicating the reset request has expired and a new one must be requested.
   *
   * 3. Compare the token provided in the request body against the token stored in the password reset record. If they do not match, return a 400 error indicating an invalid token.
   *
   * 4. Locate the erp_hrm_members record referenced by erp_hrm_member_id on the reset record. Update the member's password with the new password from the request body. Apply password validation: the new password must meet minimum length requirements (at least 8 characters), must not be the same as the current password, and must not be a commonly compromised password.
   *
   * 5. After successfully updating the password, delete the erp_hrm_member_password_resets record to prevent token reuse. This is a hard delete, not a soft delete.
   *
   * 6. Return a 200 OK with no response body on success.
   *
   * Edge cases:
   * - Concurrent completion attempts for the same resetId: the second attempt will find the record already deleted (step 5 from the first attempt) and return 404.
   * - Token expiration is evaluated at the moment of validation, so a request that arrives exactly at expired_at is rejected.
   * - This endpoint is accessible to guests (unauthenticated users). No organization context or role check is applied.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async complete(
    @GuestAuth()
    guest: GuestPayload,
    @TypedParam("resetId")
    resetId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IErpHrmMemberPasswordReset.ICompletion,
  ): Promise<void> {
    try {
      return await postErpHrmGuestPasswordResetsResetIdCompletion({
        guest,
        resetId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
