import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IErpHrmPermission } from "../../../api/structures/IErpHrmPermission";
import { IPageIErpHrmPermission } from "../../../api/structures/IPageIErpHrmPermission";
import { getErpHrmPermissionsPermissionId } from "../../../providers/getErpHrmPermissionsPermissionId";
import { patchErpHrmPermissions } from "../../../providers/patchErpHrmPermissions";

@Controller("/erpHrm/permissions")
export class ErphrmPermissionsController {
  /**
   * Lists all available permissions that can be assigned to roles within the organization.
   *
   * Permissions are a fixed catalog of nine system-defined access rights, each identified by a unique dot-notation key (e.g., "org:manage", "time:approve"). These permissions determine what actions role holders can perform across the platform, covering organization management, employee management, project operations, time tracking, approval workflows, and reporting.
   *
   * This endpoint returns the complete permission catalog with optional text-based search on permission keys and descriptions. Results are paginated for consistency with other list endpoints. Each entry includes the permission's unique identifier, its dot-notation key, and a human-readable description of the access it grants.
   *
   * Permissions are read-only system constants. They are never created, modified, or deleted at runtime, and this endpoint supports no mutation operations.
   *
   * @param connection
   * @param body Optional search criteria for filtering permissions by key or description text. When omitted, all nine permissions are returned.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor null
     * @x-autobe-specification Query the erp_hrm_permissions table, which is a
     *   fixed catalog of nine immutable permissions seeded into the system.
   *
   * Apply optional text search filters from the request body on the key and description columns using case-insensitive matching. If no search filters are provided, return all nine permissions.
   *
   * Apply cursor-based pagination from the request body (limit and cursor parameters). Since the total result set is always exactly nine items, pagination is straightforward but maintained for API consistency.
   *
   * No organization scoping is required — permissions are global system constants shared across all organizations. No write operations (create, update, delete) are supported through any API; the permission catalog is immutable at runtime.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IErpHrmPermission.IRequest,
  ): Promise<IPageIErpHrmPermission.ISummary> {
    try {
      return await patchErpHrmPermissions({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single permission from the system's fixed permission catalog.
   *
   * Permissions are the granular access rights that can be granted to roles within an organization. The system supports exactly nine predefined permissions — org:manage, employee:manage, employee:view, project:manage, project:view, time:manage, time:approve, time:view_all, and report:view — each identified by a unique dot-notation key.
   *
   * This endpoint returns the full permission record including its key, human-readable description explaining what access the permission grants, and creation/update timestamps. Permissions are immutable system constants seeded at initialization and never change at runtime.
   *
   * All authenticated members can access this endpoint. No organization context is required since permissions are global system definitions, not scoped to any single organization.
   *
   * @param connection
   * @param permissionId UUID of the permission to retrieve.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor null
     * @x-autobe-specification Query the erp_hrm_permissions table by primary
     *   key id matching the {permissionId} parameter. Return the full
     *   permission record including id, key, description, created_at, and
     *   updated_at. Since permissions are immutable system constants, no
     *   organization scoping or authorization beyond basic authentication is
     *   required — any authenticated member can view the permission catalog.
     *   Return 404 if no permission with the given UUID exists.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":permissionId")
  public async at(
    @TypedParam("permissionId")
    permissionId: string & tags.Format<"uuid">,
  ): Promise<IErpHrmPermission> {
    try {
      return await getErpHrmPermissionsPermissionId({
        permissionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
