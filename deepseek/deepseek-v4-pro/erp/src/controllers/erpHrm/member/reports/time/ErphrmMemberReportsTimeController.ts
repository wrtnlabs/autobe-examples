import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IErpHrmTimeReport } from "../../../../../api/structures/IErpHrmTimeReport";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { getErpHrmMemberReportsTime } from "../../../../../providers/getErpHrmMemberReportsTime";

@Controller("/erpHrm/member/reports/time")
export class ErphrmMemberReportsTimeController {
  /**
   * Generates an aggregated time report summarizing logged hours across the organization for a specified date range.
   *
   * This report queries all timelogs within the current organization context and aggregates total work hours by the chosen grouping dimension — employee, project, or task. Results include separate tallies for billable and non-billable hours, along with entry counts, enabling managers and owners to analyze workforce utilization, project effort distribution, and billing summaries.
   *
   * **Access Control**: Only users holding the `report:view` permission may access this report. Filtering by a specific employee additionally requires the `time:view_all` or `time:manage` permission, ensuring that individual time data is only exposed to authorized personnel.
   *
   * **Data Privacy**: The report returns aggregated summary statistics only — total hours and entry counts per group. Individual timelog descriptions and personal notes are never exposed through this endpoint, in accordance with organizational privacy boundaries.
   *
   * **Grouping Behavior**: When grouped by employee, results include the employee's display name alongside aggregated hours. When grouped by project, project names are included. When grouped by task, task titles appear — timelogs not associated with any task are consolidated under an "Unassigned" category. Omitting the groupBy parameter returns a single organization-wide grand total for the period.
   *
   * @param connection
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query the erp_hrm_timelogs table scoped to the
     *   current organization context (derived from the member's active
     *   organization in the session).
   *
   * **Query Parameters** (all optional):
   * - `dateFrom` (ISO date): Inclusive start of the reporting period. When omitted, defaults to the earliest timelog date in the organization.
   * - `dateTo` (ISO date): Inclusive end of the reporting period. When omitted, defaults to the current date.
   * - `groupBy` (enum: `employee`, `project`, `task`): Determines the aggregation dimension. When omitted, returns a single grand total for the organization. When `employee`, groups by employee_id joined with erp_hrm_employees for display name. When `project`, groups by project_id joined with erp_hrm_projects for project name. When `task`, groups by task_id joined with erp_hrm_tasks for task title — null task_id timelogs are grouped under an "unassigned" category.
   * - `employeeId` (UUID): Filter results to a specific employee. Only valid when the requesting user has time:view_all or time:manage permission.
   * - `projectId` (UUID): Filter results to a specific project.
   * - `billable` (boolean): Filter by billable status. When `true`, only billable timelogs; when `false`, only non-billable. When omitted, both are included.
   *
   * **Aggregation Logic**:
   * - SUM(duration_minutes) for each group, converted to hours (divide by 60).
   * - COUNT(timelogs) for each group as the entry count.
   * - Separate totals for billable and non-billable hours within each group.
   * - Total hours = billable_hours + non_billable_hours.
   *
   * **Authorization**:
   * - Requires `report:view` permission. Reject with 403 if the requesting user lacks this permission.
   * - When employeeId is specified without time:view_all or time:manage permission, reject with 403.
   *
   * **Privacy Compliance**:
   * - Do NOT expose individual timelog descriptions or personal notes.
   * - Report output contains only aggregated numerical data (total hours, entry counts) and group identifiers (employee name, project name, task title).
   *
   * **Edge Cases**:
   * - If no timelogs match the criteria, return an empty results array with zero totals rather than a 404.
   * - When groupBy is `task`, timelogs with null task_id are grouped under a synthetic entry with taskId null and title "Unassigned".
   * - dateFrom must not be after dateTo; if violated, return 400 with an appropriate error message.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async report(
    @MemberAuth()
    member: MemberPayload,
  ): Promise<IErpHrmTimeReport> {
    try {
      return await getErpHrmMemberReportsTime({
        member,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
