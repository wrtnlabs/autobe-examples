@Controller("/erpHrm/member/reports/project-budget")
export class ErphrmMemberReportsProject_budgetController {
  /**
   * Retrieves the project budget report comparing planned budget hours against actual logged hours across projects.
   *
   * This report provides organization-level visibility into how project time budgets are being utilized. Each project with a defined budget is listed alongside the total hours actually logged against it, with a computed utilization percentage.
   *
   * The report includes all projects that have budget hours set, regardless of their status (active, archived, or completed). Projects without budget hours are excluded. Projects with no timelogs are included with zero actual hours.
   *
   * An optional project filter allows narrowing the report to a single project for detailed budget analysis.
   *
   * Access to this report requires the report:view permission. The report presents aggregate data only — individual timelog descriptions and employee-level details are not exposed.
   *
   * @param connection
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query erp_hrm_projects where organization_id
     *   matches the authenticated user's current organization context,
     *   deleted_at IS NULL, and budget_hours IS NOT NULL.
   *
   * For each qualifying project, aggregate actual hours from erp_hrm_timelogs: SUM(duration_minutes) / 60 WHERE project_id = project.id AND deleted_at IS NULL. Include both billable and non-billable timelogs in the total.
   *
   * If an optional project_id query parameter is provided, filter results to only that project. Validate the project belongs to the same organization.
   *
   * Compute utilization percentage as (actual_hours / budget_hours) * 100 for each project.
   *
   * Return a response containing the list of project budget items, each with: project_id, project_name, budget_hours (estimated), actual_hours (logged), utilization_percentage, and project status. Also include summary totals: total budget hours, total actual hours, and overall utilization across all included projects.
   *
   * Projects without any timelogs still appear in the report with actual_hours = 0 and utilization_percentage = 0.
   *
   * Authorization: Require report:view permission. Verify the authenticated user's organization context and scope all queries accordingly.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @MemberAuth()
    member: MemberPayload,
  ): Promise<IErpHrmProjectBudgetReport> {
    try {
      return await getErpHrmMemberReportsProjectBudget({
        member,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
