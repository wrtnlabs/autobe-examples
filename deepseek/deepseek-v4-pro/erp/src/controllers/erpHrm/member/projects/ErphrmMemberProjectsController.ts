  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IErpHrmProject.ICreate,
  ): Promise<IErpHrmProject> {
    try {
      return await postErpHrmMemberProjects({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

