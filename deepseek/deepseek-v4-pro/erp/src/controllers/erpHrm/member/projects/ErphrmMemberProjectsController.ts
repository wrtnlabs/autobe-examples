  /**
   * Permanently removes a project and all its associated child data.
   *
   * Before deletion proceeds, the system verifies that no timelogs are associated with the project — if any exist, the request is rejected with a conflict error regardless of the timelogs' timesheet status. When the precondition is met, all project memberships, tasks, and task history entries are permanently and irreversibly removed from the database. The project record itself is preserved with a deletion timestamp for referential integrity.
   *
   * Requires `project:manage` permission within the user's currently selected organization. The operation is scoped to the user's active organization context — only projects belonging to that organization can be deleted. Upon successful deletion, a real-time event is dispatched to all project members confirming the permanent removal.
   *
   * @param connection
   * @param projectId Unique identifier of the project to delete (UUID format). Scoped to the user's currently selected organization context.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Delete a project by its unique identifier using
     *   soft-delete for the project and permanent removal for all child data.
   *
   * Authorization:
   * - Require `project:manage` permission within the current organization context.
   * - Reject with 403 Forbidden if the calling user lacks this permission.
   *
   * Precondition — No Timelogs:
   * - Query the `erp_hrm_timelogs` table scoped to the target project's organization to check for any timelog rows where `project_id` equals the target project ID.
   * - If ANY timelogs exist (regardless of their timesheet status — draft, submitted, or approved), reject the request with a 409 Conflict error indicating that all timelogs must be removed before the project can be deleted.
   *
   * Organization Scoping:
   * - Look up the project by `id` AND `organization_id` matching the user's active organization context.
   * - Return 404 Not Found if no matching project exists or if the project's `deleted_at` is already set (project was already soft-deleted).
   *
   * Cascading Permanent Removal:
   * - Execute within a single database transaction.
   * - Permanently DELETE all rows from `erp_hrm_project_members` where `project_id` equals the target project ID.
   * - Permanently DELETE all rows from `erp_hrm_task_histories` whose `task_id` belongs to any task of the target project (join through `erp_hrm_tasks`).
   * - Permanently DELETE all rows from `erp_hrm_tasks` where `project_id` equals the target project ID.
   * - Soft-delete the project itself: SET `deleted_at = NOW()` and `updated_at = NOW()` on the `erp_hrm_projects` row. Do NOT hard-delete the project record — the `deleted_at` column preserves referential integrity for historical references.
   *
   * Real-time Event:
   * - After successful deletion, emit a `project.deleted` real-time event.
   * - Event payload: `{ projectId: string, organizationId: string }`.
   * - Target subscribers: all project members (query `erp_hrm_project_members` before the cascading deletion to build the subscriber list) and any WebSocket channel subscribers within the organization.
   *
   * Response:
   * - Return the soft-deleted project entity with `deleted_at` populated so the caller can confirm the deletion timestamp.
   * - HTTP 200 OK on success.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":projectId")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("projectId")
    projectId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteErpHrmMemberProjectsProjectId({
        member,
        projectId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
