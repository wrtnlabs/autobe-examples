  /**
   * Creates a new project within the currently selected organization. The project becomes available immediately for time tracking and task management.
   *
   * A project requires a display name and a color code for visual identification in the user interface. The name appears in project lists, timelog entry forms, timesheet summaries, and reports. The color code should be a hex color value such as `#FF5733`.
   *
   * Optional fields provide additional context: a description explaining the project's purpose or scope, budget hours for comparing planned effort against actual logged time in budget reports, and start and end dates to define the project timeline.
   *
   * The project is automatically created in active status, meaning it accepts new timelogs from the moment it is created. Archived and completed statuses can be set later through the update operation.
   *
   * Only users holding the project management permission within the organization can create projects.
   *
   * @param connection
   * @param body Project creation payload containing the required display name and color code, plus optional description, budget hours, and timeline dates.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Insert a new row into erp_hrm_projects with the
     *   following rules:
   *
   * **Authorization**: Only users with `project:manage` permission can create projects. Extract the organization_id from the authenticated session's currently selected organization context.
   *
   * **Required Fields**:
   * - `name` (string): Must not be empty. Project display name used in lists, forms, summaries, and reports.
   * - `color_code` (string): Must not be empty. Hex color value (e.g., `#FF5733`) for visual distinction in the UI. Validate format is a valid hex color.
   *
   * **Optional Fields**:
   * - `description` (string | null): Additional context about the project's purpose or scope.
   * - `budget_hours` (number | null): Total estimated hours. Must be a positive number (> 0) when provided. Projects without a budget are excluded from budget utilization reports.
   * - `start_date` (datetime | null): Project timeline start.
   * - `end_date` (datetime | null): Project timeline end. When both start_date and end_date are provided, end_date must not be earlier than start_date.
   *
   * **Auto-Set Fields**:
   * - `id`: Server-generated UUID.
   * - `organization_id`: From session context.
   * - `status`: Always `"active"` for new projects.
   * - `created_at`: Current timestamp.
   * - `updated_at`: Current timestamp.
   * - `deleted_at`: null.
   *
   * **Edge Cases**:
   * - Return 400 if name is empty or missing.
   * - Return 400 if color_code is empty, missing, or not a valid hex color.
   * - Return 400 if budget_hours is provided but is zero or negative.
   * - Return 400 if both start_date and end_date are provided and end_date < start_date.
   * - Return 403 if the user lacks project:manage permission.
   *
   * **Post-Creation**: Emit a project creation real-time event so subscribed clients are notified of the new project.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
