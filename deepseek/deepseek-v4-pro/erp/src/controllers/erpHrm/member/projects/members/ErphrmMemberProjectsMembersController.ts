  /**
   * Update the role of an existing project member.
   *
   * Changes the assigned role for a member who is already part of the project. The role can be switched between "member" (regular participant with time tracking and view access) and "project-lead" (elevated authority with task management permissions within the project).
   *
   * The specific membership is identified by the combination of the project ID in the path and the employee ID provided in the request body. Only one membership record exists per employee-project pair.
   *
   * This operation updates the membership's role without affecting the original join date. It does not create new project assignments — employees must already be members of the project.
   *
   * @param connection
   * @param projectId UUID of the project whose member role is being updated (scoped to the current organization).
   * @param body Identifies the employee whose membership role should be updated and the new role to assign. The role must be either "member" or "project-lead".
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Update an existing project member's assigned
     *   role.
   *
   * 1. Validate the project exists within the current organization context and is not soft-deleted.
   * 2. Look up the erp_hrm_project_members record matching projectId (from path) and the employeeId (from request body).
   * 3. Reject with 404 if no active (deleted_at IS NULL) membership record exists for this employee-project pair.
   * 4. Validate the requested role is either "member" or "project-lead".
   * 5. Update the role column and set updated_at to now.
   * 6. Do NOT modify joined_at — it remains the original assignment timestamp.
   * 7. Return the updated project member record.
   *
   * Edge cases:
   * - If the new role is the same as the current role, the update is idempotent — still succeeds and returns the record.
   * - The employee must belong to the same organization as the project.
   * - This operation does not create new memberships; use POST for assignment.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
