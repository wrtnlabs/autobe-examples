  /**
   * Assign an employee to a project with a specified membership role.
   *
   * This endpoint creates a project membership, linking an active employee to a project within the current organization. The membership carries a role of either "member" for regular project participants or "project-lead" for those with elevated task management authority within the project.
   *
   * **Authorization**: Requires the `project:manage` permission. Users without this permission will receive a 403 Forbidden response.
   *
   * **Project Status Restriction**: Only projects with an `active` status accept new members. Attempting to assign a member to an archived or completed project results in a 422 Unprocessable Entity error.
   *
   * **Employee Validation**: The employee must be active within the organization and belong to the same organization as the target project. Deactivated employees and employees from different organizations are rejected.
   *
   * **Duplicate Prevention**: An employee cannot be assigned to the same project more than once. Attempting a duplicate assignment returns a 409 Conflict error.
   *
   * **Role Default**: If no role is specified in the request, the membership defaults to "member".
   *
   * @param connection
   * @param projectId UUID of the project to which the employee will be assigned.
   * @param body Employee identification and the membership role to assign. The role must be either "member" or "project-lead". If omitted, the role defaults to "member".
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Create a project membership record that links an
     *   employee to a project with an assigned role.
   *
   * **Validation Sequence**:
   * 1. Verify the requesting user holds the `project:manage` permission within the current organization context.
   * 2. Look up the project by `projectId` — reject with 404 if not found or if `deleted_at` is set. Verify the project belongs to the current organization.
   * 3. Reject with 422 if the project status is `archived` or `completed` — new members cannot join non-active projects.
   * 4. Look up the employee by `employeeId` from the request body — reject with 404 if not found or if `deleted_at` is set.
   * 5. Reject with 422 if the employee's `status` is `deactivated`.
   * 6. Reject with 422 if the employee's `erp_hrm_organization_id` does not match the project's `organization_id`.
   * 7. Check the unique constraint `[erp_hrm_employee_id, erp_hrm_project_id]` — reject with 409 if a membership already exists (even if soft-deleted, reactivate the existing record or reject).
   *
   * **Creation**:
   * - Set `erp_hrm_employee_id` from the request body.
   * - Set `erp_hrm_project_id` from the path parameter.
   * - Set `role` from the request body; if not provided, default to `"member"`. Validate the value is either `"member"` or `"project-lead"`.
   * - Set `joined_at` to the current timestamp (immutable — never updated).
   * - Set `created_at` and `updated_at` to the current timestamp.
   *
   * **Response**: Return the newly created project membership record with all fields populated.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
