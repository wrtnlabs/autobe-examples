import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IErpHrmActivityLog } from "../../../../api/structures/IErpHrmActivityLog";
import { IPageIErpHrmActivityLog } from "../../../../api/structures/IPageIErpHrmActivityLog";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getErpHrmMemberActivityLogsActivityLogId } from "../../../../providers/getErpHrmMemberActivityLogsActivityLogId";
import { patchErpHrmMemberActivityLogs } from "../../../../providers/patchErpHrmMemberActivityLogs";

@Controller("/erpHrm/member/activity-logs")
export class ErphrmMemberActivity_logsController {
  /**
   * Lists activity log entries for the current organization with pagination and filtering.
   *
   * Activity logs provide an immutable, append-only audit trail of significant actions across the organization. Each entry records who performed what action, on which entity, at what time — enabling accountability and operational transparency.
   *
   * **Filtering**: Results can be narrowed by action type (e.g., employee_invited, task_status_changed, timesheet_approved), by the user who performed the action, or by a date range. Multiple filters can be combined to pinpoint specific activity.
   *
   * **Pagination**: Results are paginated and sorted in reverse chronological order (most recent first). Use pagination parameters to navigate large result sets.
   *
   * **Immutability**: Activity log entries are created automatically by the system when significant actions occur. They cannot be created, edited, or deleted through any API.
   *
   * @param connection
   * @param body Search criteria for filtering activity log entries, including action type, user ID, date range, and pagination parameters.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query the erp_hrm_activity_logs table scoped to
     *   the authenticated user's current organization (organization_id from
     *   session context).
   *
   * Apply optional filters from the request body:
   * - action_type: exact match against the action_type column (e.g., 'employee_invited', 'task_status_changed', 'timesheet_approved')
   * - user_id: exact match against the user_id column to filter actions performed by a specific user
   * - date_from / date_to: range filter on the created_at column, inclusive on both ends
   *
   * Return results paginated (cursor-based or offset-based) sorted by created_at descending (newest first) by default. Include total count for pagination metadata.
   *
   * Edge cases:
   * - When no filters are provided, return all activity logs for the organization in descending chronological order
   * - When filter combination yields no results, return an empty page with zero total count
   * - The details field (JSON string) should be returned as-is; consumers should parse the JSON on the client side
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IErpHrmActivityLog.IRequest,
  ): Promise<IPageIErpHrmActivityLog.ISummary> {
    try {
      return await patchErpHrmMemberActivityLogs({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves a single activity log entry by its unique identifier.
   *
   * Activity log entries form the organization's permanent, immutable audit trail. Every significant business action — from employee invitations, role assignments, and contract changes to project archival, task status transitions, and timesheet reviews — is automatically recorded. Each entry captures who performed the action, what type of action occurred, which entity was affected, and when it happened.
   *
   * This endpoint returns the full detail of a specific entry, including:
   * - The polymorphic target reference (`target_entity` and `target_id`) that identifies the exact business object affected by the action
   * - The `details` field containing action-type-specific contextual information stored as JSON (e.g., old and new status values for task status changes, rejection reasons for timesheet rejections, or modified contract terms)
   * - The performing user's identifier and the exact timestamp of the action
   *
   * Access is restricted to users who hold the organization management permission. The entry must belong to the currently selected organization context — cross-organization access is not permitted. Activity log entries are append-only and are never modified or deleted through any user-facing operation.
   *
   * @param connection
   * @param activityLogId The unique identifier of the activity log entry to retrieve (UUID format).
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Retrieve a single activity log entry from the
     *   `erp_hrm_activity_logs` table by its primary key `id`.
   *
   * **Authorization**: Only users holding the organization management permission within the currently selected organization may access this endpoint. Reject with 403 Forbidden for managers, regular employees, and guests.
   *
   * **Organization Scoping**: Always scope the query to the authenticated user's currently selected organization (`organization_id`). Even if a valid UUID is provided, the entry must belong to the current organization context. Return 404 Not Found if no matching record exists — do not distinguish between "not found" and "wrong organization" in the response to prevent information leakage about other organizations' data.
   *
   * **Query**: Perform a single-row lookup filtering by `id` (matching the `activityLogId` path parameter) AND `organization_id` (matching the authenticated user's selected organization). A standard SELECT with WHERE clause on both columns is sufficient — no joins are required since the response returns the raw log data.
   *
   * **Response**: Return all columns from the record: `id`, `user_id`, `organization_id`, `action_type`, `target_entity`, `target_id`, `details` (nullable JSON string — return null when no additional context exists), and `created_at`. The `details` field contains action-type-specific contextual JSON that varies by action type:
   * - Task status changes: `{"old_status": "...", "new_status": "..."}`
   * - Timesheet rejections: `{"reason": "..."}`
   * - Contract edits: `{"changed_fields": ["..."], ...}`
   * Return the `details` value as-is without parsing or transforming the JSON.
   *
   * **Immutability**: Activity log entries are append-only records. They are never modified or deleted through any user-facing operation. This endpoint is strictly read-only. Entries are only removed via cascading deletion when the owning organization is permanently deleted.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":activityLogId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("activityLogId")
    activityLogId: string & tags.Format<"uuid">,
  ): Promise<IErpHrmActivityLog> {
    try {
      return await getErpHrmMemberActivityLogsActivityLogId({
        member,
        activityLogId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
