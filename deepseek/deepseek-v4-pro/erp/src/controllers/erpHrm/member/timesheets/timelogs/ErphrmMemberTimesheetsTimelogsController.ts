@Controller("/erpHrm/member/timesheets/:timesheetId/timelogs")
export class ErphrmMemberTimesheetsTimelogsController {
  /**
   * Add a new timelog entry to a draft timesheet.
   *
   * This operation creates a time entry and immediately associates it with the specified timesheet. Only draft timesheets accept new timelogs — once a timesheet has been submitted, its timelog set is frozen. The timelog must fall within the timesheet's calendar week (Monday through Sunday) and belong to the same employee who owns the timesheet.
   *
   * Employees without the time:manage permission can only log time for themselves — the timelog's employee is automatically set to their own employee record. Managers and owners with the time:manage permission may create timelogs for any employee, but the timelog's employee must still match the timesheet's owning employee.
   *
   * Deactivated employees are prevented from logging time entirely. The project must be active and the employee must be a project member. When the timelog is successfully created, the timesheet's total hours are recalculated to reflect the new entry.
   *
   * @param connection
   * @param timesheetId Unique identifier of the draft timesheet to add the timelog to. The timesheet must be in draft status and owned by the same employee who will own the new timelog.
   * @param body Timelog creation data including project, optional task, date, duration in minutes, optional description, and billable flag. The employee and timesheet are derived from authentication context and the path parameter respectively.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Create a new timelog and associate it with the
     *   timesheet specified by {timesheetId}.
   *
   * Validate the timesheet exists within the current organization context and is in "draft" status. Reject if the timesheet is in submitted, approved, or rejected status — timelogs can only be added to draft timesheets.
   *
   * Resolve the employee for whom the timelog is created:
   * - If the authenticated user lacks the time:manage permission, automatically set the timelog's employee_id to the authenticated user's own employee record. Reject any attempt to specify a different employee.
   * - If the authenticated user has the time:manage permission, set the timelog's employee_id to the timesheet's employee_id. The timelog's employee must match the timesheet's employee.
   *
   * Validate the employee is active (not deactivated). A deactivated employee cannot create timelogs.
   *
   * Validate the project exists, belongs to the same organization, and has an active status (not archived or completed). The employee must be a member of the project (has an erp_hrm_project_members record).
   *
   * If task_id is provided, validate the task exists, belongs to the same project as specified by project_id, and has not been deleted.
   *
   * Validate the timelog's date falls within the timesheet's week range: week_start_date <= date <= week_end_date.
   *
   * Validate duration_minutes is a positive integer.
   *
   * Set timesheet_id to the {timesheetId} from the path. Set created_at and updated_at to the current timestamp. Set billable to the provided value or default to true if not specified.
   *
   * After successful insertion, recalculate the timesheet's total hours by summing duration_minutes of all timelogs associated with the timesheet.
   *
   * Return the created timelog with all fields populated.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("timesheetId")
    timesheetId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IErpHrmTimelog.ICreate,
  ): Promise<IErpHrmTimelog> {
    try {
      return await postErpHrmMemberTimesheetsTimesheetIdTimelogs({
        member,
        timesheetId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Erase a timelog entry within a timesheet.
   *
   * Permanently soft-deletes a timelog that belongs to a specific timesheet. The timelog record is preserved in the database for audit integrity but excluded from all normal queries, reports, and timesheet calculations.
   *
   * **Access Control**: Employees may delete only their own timelogs. Users holding the time:manage permission may delete any employee's timelogs within the organization, subject to the timesheet status restrictions described below.
   *
   * **Timesheet Status Restrictions**:
   * - **Approved timesheet**: Deletion is unconditionally blocked for all users, including those with time:manage permission. The approved-timesheet lock is absolute — no timelog in an approved timesheet can ever be removed.
   * - **Submitted timesheet**: Only users with time:manage permission may delete timelogs. The owning employee is blocked once the timesheet has been submitted for review.
   * - **Draft timesheet**: Deletion is permitted for the owning employee and for users with time:manage permission.
   *
   * **Effect**: The timelog's deleted_at timestamp is set, and its association with the timesheet is cleared (timesheet_id is set to null) so the timesheet's total hours and timelog counts remain accurate.
   *
   * @param connection
   * @param timesheetId UUID of the timesheet containing the timelog to be deleted (global scope).
   * @param timelogId UUID of the timelog entry to be deleted (global scope). Must belong to the timesheet identified by timesheetId.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Soft-delete a timelog entry that is scoped to a
     *   specific timesheet.
   *
   * **Validation Steps**:
   * 1. Look up the timesheet by {timesheetId}. Verify it exists and belongs to the current organization (via timesheet → employee → organization). If not found or out of scope, return 404.
   * 2. Look up the timelog by {timelogId}. Verify it exists, belongs to the current organization scope (via timelog → employee → organization), and its timesheet_id matches {timesheetId}. If the timelog does not belong to this timesheet, return 404 with a message indicating the timelog is not associated with the specified timesheet.
   * 3. If the timelog's deleted_at is already set, return 404 (already deleted).
   *
   * **Authorization and Timesheet Status Checks**:
   * 4. Determine the requesting user's permissions:
   *    - Identify the current employee record for the requesting user in the active organization.
   *    - Check whether the user holds the `time:manage` permission.
   *
   * 5. Branch on the timesheet's status:
   *    - **status = 'approved'**: Reject unconditionally with 409 Conflict. Message: "This timelog is locked by an approved timesheet and cannot be deleted." This lock applies to ALL users including those with time:manage permission (sections 165, 273, 279).
   *    - **status = 'submitted'**: If the requesting user is the timelog's owning employee AND does NOT hold time:manage, return 403 Forbidden: "You cannot delete a timelog that is part of a submitted timesheet." If the user holds time:manage, allow deletion.
   *    - **status = 'draft'**: If the requesting user is the timelog's owning employee OR holds time:manage, allow deletion. Otherwise, return 403 Forbidden.
   *    - **status = 'rejected'**: Treat the same as 'draft' (rejected timesheets return to draft status).
   *    - **Any other status**: Return 400 Bad Request indicating an unrecognized timesheet status.
   *
   * **Deletion Execution**:
   * 6. Perform the soft delete in a transaction:
   *    - Set timelog.deleted_at to the current timestamp.
   *    - Set timelog.timesheet_id to null (removing the timelog from the timesheet so the timesheet's computed totals remain accurate).
   *    - Set timelog.updated_at to the current timestamp.
   *
   * 7. Record the deletion in the activity log (action type: timelog.deleted) with the actor's user ID, affected timelog ID, and organization context.
   *
   * **Edge Cases**:
   * - If the timelog's employee has been deactivated, deletion still proceeds based on the same permission and status rules — historical data ownership is preserved.
   * - Concurrent deletion attempts: the transaction isolation level should handle the race; the second request will find deleted_at already set and return 404.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":timelogId")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("timesheetId")
    timesheetId: string & tags.Format<"uuid">,
    @TypedParam("timelogId")
    timelogId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteErpHrmMemberTimesheetsTimesheetIdTimelogsTimelogId({
        member,
        timesheetId,
        timelogId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
