  /**
   * Soft-deletes a timesheet, marking it as removed while preserving the record for audit purposes.
   *
   * When a timesheet is deleted, all timelogs previously associated with it are unlinked — they remain in the system as independent time entries and can be included in a future timesheet. The timesheet itself is soft-deleted (its deleted_at timestamp is set) and will no longer appear in listing or retrieval operations.
   *
   * Only timesheets in draft or rejected status can be deleted. Submitted timesheets are pending review and must be approved or rejected before they can be removed. Approved timesheets are permanently locked to protect the integrity of approved time data and cannot be deleted.
   *
   * @param connection
   * @param timesheetId UUID of the timesheet to delete (scoped to the current organization).
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Soft-delete a timesheet by setting its deleted_at
     *   timestamp to the current time.
   *
   * **Authorization**: The requesting user must either be the employee who owns the timesheet, or hold a role with timesheet management permission. The operation is scoped to the user's currently selected organization.
   *
   * **Status Validation**:
   * - Timesheets in "draft" status: deletion permitted.
   * - Timesheets in "rejected" status: deletion permitted (they have been returned to the employee for revision and can be discarded).
   * - Timesheets in "submitted" status: deletion rejected. The timesheet is pending review and must be either approved or rejected first.
   * - Timesheets in "approved" status: deletion rejected. Approved timesheets lock all contained timelogs and must be preserved for audit integrity.
   *
   * **Implementation Steps**:
   * 1. Query the erp_hrm_timesheets table for the given timesheetId within the current organization scope, ensuring deleted_at IS NULL (only active timesheets).
   * 2. Verify the requesting user's permission: either the timesheet's employee_id matches the current user's employee record, or the user holds a role with timesheet management permission.
   * 3. Validate the timesheet status — reject if status is "submitted" or "approved".
   * 4. Unlink all associated timelogs: update erp_hrm_timelogs records where timesheet_id equals this timesheet's ID, setting timesheet_id to NULL. This preserves the timelog data independently of the deleted timesheet.
   * 5. Set deleted_at = NOW() on the timesheet record.
   * 6. Return the updated timesheet entity with the deleted_at timestamp set.
   *
   * **Edge Cases**:
   * - Timesheet not found: return 404.
   * - Timesheet already soft-deleted (deleted_at IS NOT NULL): return 404 or 410 Gone.
   * - User lacks permission: return 403.
   * - Status is submitted or approved: return 409 Conflict with descriptive message.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
