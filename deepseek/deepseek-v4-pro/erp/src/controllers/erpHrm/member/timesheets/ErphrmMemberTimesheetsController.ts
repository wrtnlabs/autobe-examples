  /**
   * Approves a submitted timesheet, finalizing the review process.
   *
   * This endpoint transitions a timesheet from submitted to approved status. Approval is a terminal state — once approved, a timesheet cannot be modified, rejected, or returned to any other status. All timelogs contained within the approved timesheet become permanently locked against editing or deletion, regardless of the caller's permission level.
   *
   * Only users who hold the time:approve permission within the current organization may perform this action. The reviewer's identity and the approval timestamp are automatically recorded from the authenticated session.
   *
   * Upon successful approval, the system emits a real-time event notifying both the timesheet owner and all other approvers in the organization that the timesheet has been approved and its timelogs are now locked.
   *
   * @param connection
   * @param timesheetId The unique identifier of the timesheet to approve. Must reference a timesheet in submitted status that belongs to the currently selected organization.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Approve a submitted timesheet, transitioning it
     *   from submitted to approved status and locking all contained timelogs.
   *
   * **Authorization**: Require the authenticated user to hold the `time:approve` permission within the current organization context. Return 403 Forbidden if the user lacks this permission.
   *
   * **Lookup**: Query the `erp_hrm_timesheets` table by `id` matching `timesheetId`. The timesheet must belong to the currently selected organization — join through `erp_hrm_employees.organization_id` using the timesheet's `employee_id`. Return 404 Not Found if no matching timesheet exists or if it belongs to a different organization.
   *
   * **Status Validation**: Verify the timesheet's `status` field value:
   * - If `"approved"`: return 409 Conflict with a message indicating the timesheet has already been approved (approved is a terminal state and no further transitions are permitted).
   * - If `"draft"`: return 422 Unprocessable Entity indicating the timesheet must be submitted before it can be approved.
   * - If `"rejected"`: return 422 Unprocessable Entity indicating the timesheet must be resubmitted by the employee before approval.
   * - If `"submitted"`: proceed with approval.
   *
   * **Update (in a single transaction)**:
   * - Set `status` to `"approved"`
   * - Set `reviewed_by_user_id` to the current authenticated user's ID (from `erp_hrm_members`)
   * - Set `reviewed_at` to the current timestamp
   * - Set `updated_at` to the current timestamp
   *
   * **Timelog Locking**: All records in `erp_hrm_timelogs` where `timesheet_id` equals this timesheet's `id` become locked. This lock is enforced at the service layer — subsequent attempts to edit or delete these timelogs must be rejected regardless of the caller's permissions, including the `time:manage` permission. The lock is permanent; no unlock mechanism exists.
   *
   * **Event Emission**: Emit a timesheet approval event containing the timesheet ID, the reviewer's identity (user ID), and the review timestamp. Deliver this event to:
   * - The timesheet owner (the employee identified by `employee_id`)
   * - All users who hold the `time:approve` permission within the organization
   * Event delivery must be scoped to the current organization context.
   *
   * **Response**: Return the fully updated timesheet record including the new status, reviewer information (`reviewed_by_user_id`), and review timestamp (`reviewed_at`).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
