import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IErpHrmMember } from "../../../../../api/structures/IErpHrmMember";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { postErpHrmMemberPasswordsChange } from "../../../../../providers/postErpHrmMemberPasswordsChange";

@Controller("/erpHrm/member/passwords/change")
export class ErphrmMemberPasswordsController {
  /**
   * Change the authenticated member's password.
   *
   * Verifies the member's current password, then replaces it with a new password that takes effect immediately for all subsequent login attempts. The member remains authenticated after the change and does not need to re-authenticate.
   *
   * This operation targets the member's global authentication identity and is independent of organization context. The member's profile, role assignments, and organization memberships are unaffected by a password change.
   *
   * @param connection
   * @param body Password change payload containing the member's current password for verification and the new password to set.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Retrieve the authenticated member from the
     *   current session context. Verify that the provided currentPassword
     *   matches the member's stored password hash. If it does not match, return
     *   a 403 Forbidden with an appropriate error message indicating
     *   authentication failure.
   *
   * Validate that the newPassword differs from the currentPassword. If identical, return a 422 Unprocessable Entity indicating the new password must differ from the current password to enforce a meaningful update.
   *
   * Apply standard password strength validation rules (minimum length, complexity requirements) to the newPassword. If validation fails, return a 422 Unprocessable Entity with specific validation error details.
   *
   * Hash the newPassword using the same hashing algorithm used for password storage and update the member's password hash in the erp_hrm_members table. The change takes effect immediately — all subsequent login attempts must use the new password.
   *
   * Do not invalidate the current session. The member remains authenticated after the password change and does not need to re-authenticate.
   *
   * This operation does not require organization context — it operates on the member's global authentication identity. Skip the organization context middleware for this endpoint.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async change(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IErpHrmMember.IChangePassword,
  ): Promise<void> {
    try {
      return await postErpHrmMemberPasswordsChange({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
