  /**
   * Update an existing timelog entry.
   *
   * Allows the owner of a timelog or a user with the time:manage permission to modify the details of a previously logged time entry. This operation supports correcting dates, adjusting durations, reassigning work to different projects or tasks, updating descriptions, and toggling the billable flag.
   *
   * **Lock enforcement:** Timelogs that are part of an approved timesheet are immutable — no fields can be changed regardless of the user's permissions. Timelogs assigned to draft or submitted timesheets remain editable by their owner or a time:manage holder.
   *
   * **Project membership:** The employee who owns the timelog must be an active member of the target project. Only projects with active status accept timelog updates; archived and completed projects reject modifications.
   *
   * **Task integrity:** When a task is specified, it must belong to the selected project. This constraint maintains referential integrity across the project-task-timelog relationship chain.
   *
   * **Soft-deleted exclusion:** Soft-deleted timelogs cannot be updated. Any attempt to update a soft-deleted timelog results in a 404 response.
   *
   * @param connection
   * @param timelogId Unique identifier of the timelog to update. UUID v4 format.
   * @param body Complete set of updatable fields for the timelog. All required fields (date, duration_minutes, project_id, billable) must be provided. Optional fields (task_id, description) may be omitted or set to null to clear their value. Employee ownership and timesheet assignment are managed through separate workflows and cannot be changed via this endpoint.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Update an existing timelog identified by
     *   timelogId.
   *
   * **Authorization:**
   * - The requesting employee must either own the timelog (employee_id matches the requesting user's employee record) OR hold the time:manage permission.
   * - When the employee owns the timelog but lacks time:manage, only their own timelogs can be updated.
   * - When the user holds time:manage, they may update any employee's timelog within the organization.
   *
   * **Preconditions — reject with appropriate status if violated:**
   * - The timelog must exist and not be soft-deleted (deleted_at IS NULL). Return 404 if not found or soft-deleted.
   * - The timelog must not belong to an approved timesheet. If the timelog's timesheet_id references an erp_hrm_timesheets record with status 'approved', reject with 409 Conflict (Section 279 — approved-timesheet lock).
   *
   * **Validation rules:**
   * 1. date (required): The calendar date the work was performed. Must be a valid date.
   * 2. duration_minutes (required): A positive integer representing the work session length in minutes. Must be greater than zero.
   * 3. project_id (required): Must reference an erp_hrm_projects record in the same organization. The project must have status 'active' (Sections 45, 110). The timelog owner (employee_id) must be an active member of the project (exists in erp_hrm_project_members with matching employee_id and project_id).
   * 4. task_id (optional): If provided, must reference an erp_hrm_tasks record whose project_id matches the supplied project_id. If task_id is provided but does not belong to the selected project, reject with 422 Unprocessable Entity.
   * 5. description (optional): Free-text description of the work performed. May be set to null to clear the description.
   * 6. billable (required): Boolean indicating whether the time entry is billable.
   *
   * **Execution:**
   * - Locate the timelog by id (UUID). Return 404 if not found or soft-deleted.
   * - Verify the requesting user's organization context matches the timelog owner's organization.
   * - Verify authorization: ownership check (timelog.employee_id equals the requesting user's employee ID) OR permission check (time:manage).
   * - Verify approved-timesheet lock: if timesheet_id is set, load the referenced timesheet and check its status is not 'approved'.
   * - Validate all input fields against the rules above.
   * - Update the timelog record: set date, duration_minutes, project_id, task_id, description, billable. The updated_at field is set to the current timestamp automatically.
   * - Return the updated timelog with all fields populated, including its related employee, project, task, and timesheet references.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
