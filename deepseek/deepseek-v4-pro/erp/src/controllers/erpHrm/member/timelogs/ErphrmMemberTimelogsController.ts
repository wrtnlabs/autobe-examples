  /**
   * Delete a timelog entry.
   *
   * Removes a single timelog entry via soft deletion, preserving the record for audit purposes while making it unavailable for further operations. The deletion is subject to strict access control and timesheet workflow constraints.
   *
   * Employees may only delete their own timelogs, and only when those timelogs are not currently under review (not part of a submitted or approved timesheet). Users with the time management permission (time:manage) have broader authority and may delete any employee's timelog, including those within submitted timesheets awaiting approval.
   *
   * There is one absolute constraint that applies to all users: once a timesheet containing a timelog has been approved, that timelog becomes permanently locked and cannot be deleted by anyone, regardless of their permission level. This ensures the integrity of approved time records.
   *
   * @param connection
   * @param timelogId Unique identifier (UUID) of the timelog to delete.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Soft-delete a single timelog entry identified by
     *   timelogId.
   *
   * **Authorization Rules**
   *
   * 1. **Owner deletion**: The owning employee can delete their own timelog ONLY when the timelog is NOT part of a submitted or approved timesheet. If the timelog's timesheet has status 'submitted' or 'approved', the employee-level deletion is blocked.
   *
   * 2. **Manager deletion (time:manage permission)**: Users with the time:manage permission can delete any employee's timelog, including timelogs that are part of a submitted (but not yet approved) timesheet. However, the approved-timesheet lock is absolute — no user can delete a timelog belonging to an approved timesheet.
   *
   * **Implementation Steps**
   *
   * 1. Look up the timelog by timelogId. If not found or already soft-deleted (deleted_at IS NOT NULL), return 404.
   *
   * 2. Verify organization context: the timelog's employee must belong to the current session's organization. If not, return 403.
   *
   * 3. Determine the caller's authorization:
   *    - If caller's employee ID matches timelog.employee_id → they are the owner.
   *    - If caller holds the time:manage permission → they are a manager.
   *    - Otherwise → return 403.
   *
   * 4. If the timelog has a timesheet_id (IS NOT NULL):
   *    - Query the related erp_hrm_timesheets record for its status.
   *    - If timesheet.status is 'approved' → return 409/422 indicating the timelog is locked by an approved timesheet. This applies to ALL users, including those with time:manage permission.
   *    - If timesheet.status is 'submitted' AND the caller is the owner (no time:manage permission) → return 409/422 indicating the timelog cannot be deleted while under review.
   *    - If timesheet.status is 'submitted' AND the caller has time:manage permission → allow the deletion.
   *    - If timesheet.status is 'draft' or 'rejected' → allow the deletion (owner only; managers can always delete in these statuses).
   *
   * 5. If the timelog has no timesheet_id (IS NULL), the owner can delete freely; managers can also delete freely.
   *
   * 6. Perform soft delete: SET deleted_at = NOW() WHERE id = timelogId.
   *
   * 7. Return 204 No Content on success.
   *
   * **Edge Cases**
   * - The timelog must belong to an active employee (deactivated employees' historical timelogs can still be deleted by managers).
   * - Cascade considerations: deleting a timelog does not cascade. The timesheet's total hours will need recalculation if the timelog was part of a draft timesheet.
   * - The timelog's description GIN index entry should be considered for cleanup if the database engine supports it.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":timelogId")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("timelogId")
    timelogId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteErpHrmMemberTimelogsTimelogId({
        member,
        timelogId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
