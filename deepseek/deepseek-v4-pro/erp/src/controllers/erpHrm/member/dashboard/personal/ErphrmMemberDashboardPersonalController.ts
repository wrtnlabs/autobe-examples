import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IErpHrmPersonalDashboard } from "../../../../../api/structures/IErpHrmPersonalDashboard";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { getErpHrmMemberDashboardPersonal } from "../../../../../providers/getErpHrmMemberDashboardPersonal";

@Controller("/erpHrm/member/dashboard/personal")
export class ErphrmMemberDashboardPersonalController {
  /**
   * Returns the authenticated employee's personal dashboard with an at-a-glance summary of their current work status.
   *
   * The dashboard aggregates data from time tracking, live timer, timesheet workflow, and task assignment domains into a single unified view. It is designed for rendering a personal home screen where the employee can immediately see their progress for the day and week, manage their active timer, review recent work entries, monitor timesheet submission status, and triage assigned tasks.
   *
   * All data is strictly scoped to the authenticated employee within the currently selected organization. The employee must be active to access this endpoint. Each section of the dashboard is independently computed — if any section has no data, its fields gracefully default to zero, empty, or null rather than causing the entire request to fail.
   *
   * The endpoint is optimized for low latency by executing queries against indexed columns (employee_id + date for timelogs, employee_id unique for timers, employee_id + week_start_date for timesheets, assigned_employee_id + status for tasks). Real-time timer updates are delivered via WebSocket events (see Timer Event Subscription Scope); this endpoint provides the initial snapshot for dashboard rendering.
   *
   * @param connection
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query the authenticated member's personal
     *   dashboard by aggregating data from multiple tables scoped to the
     *   current organization context.
   *
   * 1. Resolve the authenticated user from the session and locate their employee record (erp_hrm_employees) in the current organization. The employee must be active; return 403 if deactivated.
   *
   * 2. Hours Today: SUM duration_minutes from erp_hrm_timelogs WHERE employee_id = current employee AND date = today's date (in the organization's timezone). Return as both minutes and decimal hours.
   *
   * 3. Hours This Week: SUM duration_minutes from erp_hrm_timelogs WHERE employee_id = current employee AND date BETWEEN Monday 00:00 and Sunday 23:59 of the current calendar week (determined from the organization's timezone). Return as both minutes and decimal hours.
   *
   * 4. Active Timer: Query erp_hrm_timers WHERE erp_hrm_employee_id = current employee. At most one record due to @@unique constraint. If found, include id, start_timestamp, calculated elapsed seconds (now - start_timestamp), project id/name, task id/title, and description. If no timer exists, return null for the timer field.
   *
   * 5. Recent Timelogs: SELECT 5 most recent erp_hrm_timelogs WHERE employee_id = current employee ORDER BY created_at DESC. Include id, date, duration_minutes, project id/name, task id/title, description, billable, and timesheet status if linked.
   *
   * 6. Pending Timesheet: Query erp_hrm_timesheets WHERE employee_id = current employee AND week_start_date = Monday of current week. This week's timesheet may be draft, submitted, approved, or rejected — return its id, status, week_start_date, week_end_date. If rejected, include rejection_reason. If no timesheet exists for the current week, return null.
   *
   * 7. Assigned Tasks: Query erp_hrm_tasks WHERE erp_hrm_assigned_employee_id = current employee AND status IN ('open', 'in-progress') AND deleted_at IS NULL. Join with erp_hrm_projects to include project name. Order by priority (urgent first, then high, medium, low) and due_date ASC. Include id, title, status, priority, due_date, project id/name, and estimated_hours.
   *
   * 8. All queries must respect soft-delete (deleted_at IS NULL) on timelogs, timesheets, tasks, and projects. Archived/completed projects that have active tasks assigned to the employee should still appear in the tasks list.
   *
   * 9. Return all fields in a single response object. Handle the case where the employee has no data yet (all numeric fields return 0, arrays return empty, nullable fields return null).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @MemberAuth()
    member: MemberPayload,
  ): Promise<IErpHrmPersonalDashboard> {
    try {
      return await getErpHrmMemberDashboardPersonal({
        member,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
