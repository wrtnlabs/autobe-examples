import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IErpHrmMemberSession } from "../../../../../api/structures/IErpHrmMemberSession";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { putErpHrmMemberSessionsOrganizations } from "../../../../../providers/putErpHrmMemberSessionsOrganizations";

@Controller("/erpHrm/member/sessions/organizations")
export class ErphrmMemberSessionsOrganizationsController {
  /**
   * Switch the active organization context for the current session.
   *
   * A member who belongs to multiple organizations can switch their active context at any time without logging out. This endpoint updates the session to scope all subsequent API requests to the specified organization.
   *
   * After a successful switch, the member's effective permissions reflect the role they hold in the newly selected organization. Data from the previous organization becomes inaccessible until the member switches back. The session itself remains intact — switching organizations does not create a new session or affect authentication state.
   *
   * No real-time event is emitted for organization context switches, as this is a client-side operation that does not affect other users.
   *
   * @param connection
   * @param body The target organization to switch the session context to. Must be an organization the authenticated member belongs to with an active employee record.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Update the current session's organization context
     *   to the specified target organization.
   *
   * 1. Extract the current session from the JWT bearer token (the `access_token` claim identifies the `erp_hrm_member_sessions` record).
   * 2. Read the target organization ID from the request body.
   * 3. Validate that the authenticated member has an active employee record (`erp_hrm_employees`) in the target organization — the member must belong to the organization they are switching into. If no active employee record exists, return a 403 Forbidden error.
   * 4. Update the session's `erp_hrm_organization_id` field to the target organization ID.
   * 5. Do NOT emit a broadcast event (per business rule: organization context switches are client-side only).
   * 6. Return 200 OK with no response body — the client confirms the switch by observing that subsequent API calls are scoped to the new organization.
   *
   * Edge cases:
   * - If the target organization is the same as the current one, treat as a no-op and return 200 OK.
   * - If the session has expired, return 401 Unauthorized (re-authentication required).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async switchOrganization(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IErpHrmMemberSession.ISwitchOrganization,
  ): Promise<void> {
    try {
      return await putErpHrmMemberSessionsOrganizations({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
