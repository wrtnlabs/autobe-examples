import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IErpHrmMemberEmailVerification } from "../../../../api/structures/IErpHrmMemberEmailVerification";
import { IPageIErpHrmMemberEmailVerification } from "../../../../api/structures/IPageIErpHrmMemberEmailVerification";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getErpHrmMemberEmailVerificationsVerificationId } from "../../../../providers/getErpHrmMemberEmailVerificationsVerificationId";
import { patchErpHrmMemberEmailVerifications } from "../../../../providers/patchErpHrmMemberEmailVerifications";
import { postErpHrmMemberEmailVerifications } from "../../../../providers/postErpHrmMemberEmailVerifications";

@Controller("/erpHrm/member/email-verifications")
export class ErphrmMemberEmail_verificationsController {
  /**
   * Verify an email address by consuming a one-time verification token sent during the sign-up process.
   *
   * When a guest completes sign-up, the system creates a member account and dispatches a verification email containing a unique, time-limited token. This endpoint accepts that token and confirms that the email address belongs to the user who created the account.
   *
   * Upon successful verification, the system automatically matches any pending organization invitations targeting the verified email address. The user is enrolled into each inviting organization as an employee with the role specified in the invitation, and those invitations are marked as fulfilled. This automatic enrollment operates regardless of whether the user is authenticated at the time of verification.
   *
   * Tokens are single-use and expire after a system-defined duration. An expired token is rejected with an appropriate error. Verification is idempotent — submitting an already-verified token returns a success response confirming the email has already been verified, rather than producing an error.
   *
   * @param connection
   * @param body The verification token string received via email. This is a cryptographically secure, globally unique token generated during the sign-up process and delivered to the user's email address.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Receive a verification token from the request
     *   body and verify the associated email address.
   *
   * Look up the `erp_hrm_member_email_verifications` record by the unique `token` value provided in the request body. If no matching record exists, reject with a generic error message — do not reveal whether the token corresponds to an existing account.
   *
   * Validate the token has not expired: compare `expires_at` against the current server timestamp. If `expires_at` is in the past, reject the verification with an expired-token error. The expired record is preserved for audit purposes.
   *
   * Check that the token has not already been consumed: `verified_at` must be null. If `verified_at` is already populated, return a success response with the existing record — do not reject, as verification is idempotent.
   *
   * Upon passing all validations, set `verified_at` to the current timestamp and `updated_at` to the current timestamp. Persist the update in a transaction.
   *
   * After successful verification, within the same transaction or as a post-commit action, automatically match any pending invitations in the `erp_hrm_invitations` table where `email` equals the verified email address and `status` is `pending`. For each matched invitation:
   * - Update the invitation `status` to `fulfilled`.
   * - Create the corresponding `erp_hrm_employees` record linking the member (`erp_hrm_member_id`) to the inviting organization with the role specified in the invitation.
   *
   * Return the updated verification record including the `verified_at` timestamp.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async verify(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IErpHrmMemberEmailVerification.ICreate,
  ): Promise<IErpHrmMemberEmailVerification> {
    try {
      return await postErpHrmMemberEmailVerifications({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a paginated list of email verification records for members within the current organization.
   *
   * Email verification tokens are issued automatically when a user signs up. Each token represents a pending, completed, or expired email verification attempt. This endpoint allows organization administrators and managers to audit the verification status of their members' email addresses.
   *
   * Results are scoped to the currently selected organization — only verification records belonging to members who are employees of the active organization are included. The response includes the member reference, email address, token issuance date, expiration date, and verification completion timestamp where applicable.
   *
   * @param connection
   * @param body Search criteria for filtering email verification records. Supports filters by member ID, email address (partial match), verification status (pending, verified, or expired), and creation date range. Includes pagination parameters for cursor-based navigation.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query the erp_hrm_member_email_verifications
     *   table with pagination and filtering.
   *
   * Data Isolation: Join through erp_hrm_member_id → erp_hrm_members → erp_hrm_employees to scope results to the currently selected organization context. Only return verification records belonging to members who have an employee record in the active organization.
   *
   * Search Filters: Support filtering by member ID, email address (partial match), verification status (pending: verified_at IS NULL AND expires_at > NOW(), verified: verified_at IS NOT NULL, expired: verified_at IS NULL AND expires_at <= NOW()), and date range on created_at.
   *
   * Sorting: Default sort by created_at descending. Support optional sorting by email, expires_at, or verified_at.
   *
   * Pagination: Cursor-based pagination on created_at with configurable page size. Return next cursor for sequential loading.
   *
   * Edge Cases: Exclude verification records where the member has been deleted (cascade deletion may have removed them, but verify referential integrity). Handle members with multiple verification tokens (re-issued) by returning all records.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IErpHrmMemberEmailVerification.IRequest,
  ): Promise<IPageIErpHrmMemberEmailVerification.ISummary> {
    try {
      return await patchErpHrmMemberEmailVerifications({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves a single email verification token record by its unique identifier.
   *
   * Email verification tokens are generated during the sign-up process when a guest registers a new account. Each token is delivered to the user's email address and must be confirmed to verify email ownership. Upon successful verification, the system automatically matches any pending organization invitations associated with the verified email address.
   *
   * This endpoint returns the full verification record, including the token value, the target email address, expiration timestamp, and verification status. The verified_at field indicates whether the token has been consumed — null means the token is still pending or expired, while a populated timestamp confirms successful verification.
   *
   * @param connection
   * @param verificationId Unique identifier of the email verification record (UUID primary key).
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query the erp_hrm_member_email_verifications
     *   table by primary key id matching the verificationId path parameter.
   *
   * Return the full record including: id, erp_hrm_member_id (reference to the member account), token, email, expires_at, verified_at (null if unverified), created_at, and updated_at.
   *
   * If no record exists with the given id, return a 404 Not Found response.
   *
   * No authentication is required for reading email verification records — this endpoint may be accessed during the verification flow before the user is fully authenticated.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":verificationId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("verificationId")
    verificationId: string & tags.Format<"uuid">,
  ): Promise<IErpHrmMemberEmailVerification> {
    try {
      return await getErpHrmMemberEmailVerificationsVerificationId({
        member,
        verificationId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
