import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IErpHrmContract } from "../../../../../api/structures/IErpHrmContract";
import { IPageIErpHrmContract } from "../../../../../api/structures/IPageIErpHrmContract";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { patchErpHrmMemberEmployeesEmployeeIdContracts } from "../../../../../providers/patchErpHrmMemberEmployeesEmployeeIdContracts";
import { postErpHrmMemberEmployeesEmployeeIdContracts } from "../../../../../providers/postErpHrmMemberEmployeesEmployeeIdContracts";

@Controller("/erpHrm/member/employees/:employeeId/contracts")
export class ErphrmMemberEmployeesContractsController {
  /**
   * Create a new employment contract for a specific employee.
   *
   * This endpoint adds a new contract to the employee's compensation history with a specified pay rate, pay period, working hours per week, and effective date range. When a new contract is created, the system automatically closes the employee's previous active contract by setting its end date to the day before the new contract's start date. This ensures only one contract is active at any given time while preserving all past contracts as immutable historical records.
   *
   * Contracts serve as the authoritative record of an employee's compensation terms throughout their tenure. Each contract captures the pay rate, pay period (hourly, daily, weekly, or monthly), expected working hours per week, and optional notes for additional context such as bonus structures or special terms. The contract history provides a complete auditable trail for compliance, reporting, and reference purposes.
   *
   * Access to this endpoint requires the `employee:manage` permission. Users without this permission will receive an access denied response. The employee must belong to the current organization context — contracts cannot be created for employees outside the organization.
   *
   * @param connection
   * @param employeeId The unique identifier of the employee for whom the contract is being created. Must belong to the current organization context.
   * @param body The contract details including start date, pay rate, pay period, working hours per week, and optional end date and notes. The employee reference is derived from the path parameter and must not be included in the request body.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Create a new employment contract for the employee
     *   identified by {employeeId}.
   *
   * **Authorization**: Requires `employee:manage` permission within the current organization context.
   *
   * **Pre-validation**:
   * 1. Verify the employee exists in the current organization. If not found, reject with 404 not-found.
   * 2. Validate that `pay_rate` > 0. If zero or negative, reject with 422 validation error.
   * 3. Validate that `working_hours_per_week` > 0. If zero or negative, reject with 422 validation error.
   * 4. If `end_date` is provided, validate that `start_date` < `end_date`. If start_date is after or equal to end_date, reject with 422 validation error.
   * 5. Validate that `pay_period` is one of: `hourly`, `daily`, `weekly`, `monthly`. If not, reject with 422 validation error.
   *
   * **Auto-closure of previous active contract**:
   * Query for the employee's current active contract (the contract with the most recent start_date on or before the current date whose end_date is either null or not yet passed). If an active contract exists, set its `end_date` to the day before the new contract's `start_date` and update its `updated_at` timestamp. This ensures only one contract is active at any time for the employee.
   *
   * **Creation**:
   * Insert a new row into `erp_hrm_contracts` with:
   * - `id`: auto-generated UUID
   * - `erp_hrm_employee_id`: from the {employeeId} path parameter
   * - `start_date`, `end_date`, `pay_rate`, `pay_period`, `working_hours_per_week`, `notes`: from the request body
   * - `created_at`, `updated_at`: set to current timestamp
   * - `deleted_at`: null
   *
   * **Response**: Return the newly created contract record with all fields including the server-generated id and timestamps.
   *
   * **Activity Log**: Record a contract creation event in the activity log with the employee and contract identifiers.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("employeeId")
    employeeId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IErpHrmContract.ICreate,
  ): Promise<IErpHrmContract> {
    try {
      return await postErpHrmMemberEmployeesEmployeeIdContracts({
        member,
        employeeId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves a paginated list of employment contracts for a specific employee.
   *
   * Each employee can have multiple contracts over their tenure, forming a complete historical record of compensation arrangements — pay rate, pay period, and working hours commitment. Only one contract is active at any given time; past contracts are preserved as immutable historical records for auditing and reference purposes.
   *
   * **Filtering and Search**
   *
   * Contracts can be filtered by start date range, end date range, pay period (hourly, daily, weekly, monthly), and contract status (active vs. past). The active contract is determined at query time as the one with the most recent start date on or before the current date whose end date is either absent or not yet passed.
   *
   * **Access Control**
   *
   * Users with the `employee:view` permission can view any employee's contracts within the organization. Employees without this permission can only view their own contracts. Contract creation and editing require the separate `employee:manage` permission and are handled by dedicated endpoints.
   *
   * @param connection
   * @param employeeId Unique identifier of the employee whose contracts are being retrieved (scoped to the current organization).
   * @param body Search and filter criteria including date ranges, pay period filter, contract status (active/past), and pagination parameters.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query the `erp_hrm_contracts` table filtered by
     *   the specified employee, with pagination and optional search filters.
   *
   * **Prerequisites**:
   * - Verify the employee exists within the current organization context by looking up `erp_hrm_employees` where `id = {employeeId}` AND `erp_hrm_organization_id = current_organization_id` AND `deleted_at IS NULL`. If not found, reject with a 404 not-found error.
   * - Enforce permission: users with `employee:view` permission can view any employee's contracts; employees without `employee:view` can only view their own contracts (where `erp_hrm_member_id = current_user_member_id`). Reject with 403 if unauthorized.
   *
   * **Query Execution**:
   * - Base filter: `erp_hrm_employee_id = {employeeId}` AND `deleted_at IS NULL`.
   * - Apply optional filters from the request body:
   *   - `start_date_from` / `start_date_to`: filter by contract start date range.
   *   - `end_date_from` / `end_date_to`: filter by contract end date range.
   *   - `pay_period`: filter by pay period value (hourly, daily, weekly, monthly).
   *   - `status`: filter by contract status — `active` returns the current active contract (most recent start_date ≤ now and end_date IS NULL or end_date ≥ now), `past` returns superseded or expired contracts, absent returns all.
   * - Apply cursor-based or offset pagination from the request body.
   * - Order results by `start_date DESC` so the most recent contract appears first.
   *
   * **Response Construction**:
   * - Return paginated summary records. Each summary includes: `id`, `start_date`, `end_date`, `pay_rate`, `pay_period`, `working_hours_per_week`, `created_at`.
   * - Include pagination metadata (total count, next cursor).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("employeeId")
    employeeId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IErpHrmContract.IRequest,
  ): Promise<IPageIErpHrmContract.ISummary> {
    try {
      return await patchErpHrmMemberEmployeesEmployeeIdContracts({
        member,
        employeeId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
