import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { postErpHrmMemberLogout } from "../../../../providers/postErpHrmMemberLogout";

@Controller("/erpHrm/member/logout")
export class ErphrmMemberController {
  /**
   * Terminates the current authenticated session and returns the user to an unauthenticated (guest) state.
   *
   * Logging out invalidates the current JWT access and refresh tokens. Once the session is terminated, the tokens can no longer be used to access any protected resources. The user must complete a new login with their email and password to re-establish an authenticated session.
   *
   * This operation does not require an active organization context. A member can log out regardless of which organization is currently selected, and the logout applies to the session as a whole — not to a specific organization context.
   *
   * After a successful logout, all subsequent requests to organization-scoped endpoints will be rejected until the user authenticates again.
   *
   * @param connection
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Invalidate the current member session identified
     *   by the JWT access token from the request.
   *
   * 1. Extract the session identifier from the authenticated request context (the JWT access token).
   * 2. Delete or invalidate the corresponding session record in erp_hrm_member_sessions, including both the access token and the refresh token.
   * 3. The member is now in an unauthenticated (guest) state.
   * 4. Any subsequent requests with the revoked token must be rejected by the auth middleware.
   * 5. After logout, the member must complete a full login flow (email + password) to establish a new session.
   *
   * Edge cases:
   * - If no valid session exists (already expired or already logged out), treat the operation as idempotent and return success (204 No Content).
   * - Logout does not require an active organization context — it operates at the member level regardless of which organization is currently selected.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async logout(
    @MemberAuth()
    member: MemberPayload,
  ): Promise<void> {
    try {
      return await postErpHrmMemberLogout({
        member,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
