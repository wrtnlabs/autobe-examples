import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IErpHrmInvitation } from "../../../../api/structures/IErpHrmInvitation";
import { IPageIErpHrmInvitation } from "../../../../api/structures/IPageIErpHrmInvitation";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { deleteErpHrmMemberInvitationsInvitationId } from "../../../../providers/deleteErpHrmMemberInvitationsInvitationId";
import { patchErpHrmMemberInvitations } from "../../../../providers/patchErpHrmMemberInvitations";
import { postErpHrmMemberInvitations } from "../../../../providers/postErpHrmMemberInvitations";

@Controller("/erpHrm/member/invitations")
export class ErphrmMemberInvitationsController {
  /**
   * Send an employee invitation to join the current organization by email.
   *
   * Creates a pending invitation record and delivers an invitation email to the specified address. The invitation remains in pending status indefinitely until the recipient signs up with the matching email address, at which point it is automatically fulfilled and the user is added as an employee.
   *
   * This operation requires the employee:manage permission. Only one pending invitation per email address can exist within an organization at a time.
   *
   * If the invited email address corresponds to an existing user who has not yet joined this organization, the invitation is fulfilled immediately upon signup with email matching.
   *
   * @param connection
   * @param body The email address to send the invitation to.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Create a new pending invitation in the current
     *   organization context.
   *
   * Implementation steps:
   * 1. Verify the authenticated user has employee:manage permission in the current organization (reject with 403 if not).
   * 2. Validate the invited email address format.
   * 3. Check for duplicate pending invitation: if a pending invitation already exists for the same email in the current organization, reject with a conflict error (409).
   * 4. Create the invitation record with status='pending', recording the current timestamp as the sent time.
   * 5. Deliver the invitation email to the recipient (fire-and-forget; email delivery failure does not roll back the invitation creation).
   * 6. Return the created invitation with all fields.
   *
   * Edge cases:
   * - If the invited email already belongs to an active employee in the organization, reject with 409 (already a member).
   * - Multi-org: the same email can have pending invitations in different organizations simultaneously.
   * - The invitation has no expiration and remains pending indefinitely until fulfilled, revoked, or the organization is deleted.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IErpHrmInvitation.ICreate,
  ): Promise<IErpHrmInvitation> {
    try {
      return await postErpHrmMemberInvitations({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves a paginated list of invitations sent from the current organization.
   *
   * This endpoint allows users with the employee:manage permission to browse all invitations associated with their organization. Each invitation record includes the invited email address, the invitation's current status (pending, fulfilled, or revoked), the timestamp when the invitation was sent, and identifying information about the user who sent the invitation.
   *
   * The list supports filtering by invitation status — managers can narrow results to pending invitations awaiting acceptance, fulfilled invitations already accepted, or revoked invitations that were cancelled. Users can also search by the invited email address using partial matching to locate a specific invitation.
   *
   * Results are paginated and returned sorted with the most recently sent invitations first. Only invitations belonging to the caller's currently selected organization context are returned.
   *
   * @param connection
   * @param body Search and filter criteria for browsing invitations. Includes an optional status filter (one of: pending, fulfilled, revoked), an optional email search string for case-insensitive partial matching against the invited email address, and pagination parameters.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query all invitation records belonging to the
     *   current session's selected organization.
   *
   * Enforce permission check: the caller's assigned role within the current organization must include the employee:manage permission. Return 403 Forbidden if the caller lacks this permission.
   *
   * Apply request body filters as AND conditions:
   * - status: when provided, filter by the invitation's status field. Valid values are 'pending', 'fulfilled', and 'revoked'. When omitted, return invitations regardless of status.
   * - email: when provided, perform a case-insensitive partial substring match (e.g., SQL ILIKE '%value%' or equivalent) against the invited email address field. When omitted, no email filter is applied.
   * - Apply standard pagination parameters (page size, cursor or offset) as defined in IErpHrmInvitation.IRequest.
   *
   * The inviter's identifying information (such as name and email from the associated user record) should be included in each result row via a join with the user/employee tables through the invitation's sender reference.
   *
   * Sort results by the invitation creation timestamp in descending order so the most recently sent invitations appear first.
   *
   * Restrict all results to invitations belonging to the caller's currently selected organization — never return invitations from other organizations.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IErpHrmInvitation.IRequest,
  ): Promise<IPageIErpHrmInvitation.ISummary> {
    try {
      return await patchErpHrmMemberInvitations({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Revoke a pending invitation.
   *
   * Cancels a pending invitation so it can no longer be fulfilled. The invitation transitions from "pending" to "revoked" status and the invited email address will not automatically receive organization membership upon signup.
   *
   * This operation requires the employee:manage permission. It is scoped to the current organization context — only invitations belonging to the user's active organization can be revoked.
   *
   * Once revoked, the invitation is permanently finalized in that state. It cannot be reactivated or returned to pending status. The revoked invitation record remains in the system for audit purposes and is only removed if the entire organization is deleted.
   *
   * Only invitations in "pending" status are eligible for revocation. Attempting to revoke an invitation that has already been fulfilled (the user signed up and joined the organization) or was previously revoked will result in a conflict error.
   *
   * @param connection
   * @param invitationId Unique identifier of the invitation to revoke, scoped to the current organization.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Transition the invitation status from "pending"
     *   to "revoked".
   *
   * Implementation steps:
   * 1. Validate that the authenticated user has the employee:manage permission in their current organization context. Reject with 403 Forbidden if not.
   * 2. Look up the invitation by invitationId, scoped to the user's current organization (erp_hrm_organization_id).
   * 3. If no invitation matches, return 404 Not Found.
   * 4. Check the invitation's current status:
   *    - If "pending": proceed with revocation.
   *    - If "fulfilled": return 409 Conflict — fulfilled invitations cannot be revoked.
   *    - If "revoked": return 409 Conflict — already revoked.
   * 5. Update the invitation record: set status to "revoked", record the revocation timestamp, and record the revoking user for accountability.
   * 6. Log the revocation action to the activity log (action type: invitation_revoked).
   * 7. Return the updated invitation record with all fields including the new status and revocation timestamp.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":invitationId")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("invitationId")
    invitationId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteErpHrmMemberInvitationsInvitationId({
        member,
        invitationId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
