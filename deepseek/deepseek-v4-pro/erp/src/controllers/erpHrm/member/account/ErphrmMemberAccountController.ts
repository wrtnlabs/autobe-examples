import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { deleteErpHrmMemberAccount } from "../../../../providers/deleteErpHrmMemberAccount";

@Controller("/erpHrm/member/account")
export class ErphrmMemberAccountController {
  /**
   * Permanently delete the authenticated member's own account.
   *
   * This endpoint initiates full account deletion. Before deletion proceeds, the system verifies that the member is not the sole owner of any active organization. If the member is the sole owner anywhere, the request is rejected and the member must first transfer ownership to another active employee in that organization or delete the organization entirely.
   *
   * When deletion is allowed, all of the member's employee records in other organizations are deactivated rather than removed. This preserves historical data — including timelogs, timesheets, activity log entries, and contracts — ensuring organizational records remain intact. The member's global profile information is permanently removed, and the member can no longer authenticate or access any organization.
   *
   * Account deletion events are emitted to all affected organizations so that owners and managers can take appropriate action regarding the deactivated employee's projects, tasks, and pending timesheets.
   *
   * @param connection
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Identify the authenticated member from the
     *   current session context.
   *
   * **Sole Owner Check**: Before proceeding, query all organizations where the member holds the built-in Owner role. For each such organization, count the total number of active employees assigned the Owner role. If any organization has exactly one active Owner (the requesting member), reject the deletion with an error indicating ownership must be transferred or the organization must be deleted first.
   *
   * **Employee Deactivation**: For all other organizations where the member is an active employee but NOT a sole owner, update the corresponding `erp_hrm_employees` records: set `status` to `deactivated` and set `updated_at` to the current timestamp. Do NOT delete these employee records — historical timelogs, timesheets, contracts, and activity logs must remain intact.
   *
   * **Member Soft Delete**: Set `deleted_at` to the current timestamp on the `erp_hrm_members` record. The member's authentication credentials become invalid immediately — subsequent login attempts with this email must be rejected.
   *
   * **Event Emission**: Emit an account deletion event to each organization where the member held an active employee record. The event payload must include the deleted member ID, the deletion timestamp, and a notification that the corresponding employee record has been deactivated.
   *
   * **Transaction**: Wrap the employee deactivation updates and member soft-delete in a database transaction to ensure atomicity.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @MemberAuth()
    member: MemberPayload,
  ): Promise<void> {
    try {
      return await deleteErpHrmMemberAccount({
        member,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
