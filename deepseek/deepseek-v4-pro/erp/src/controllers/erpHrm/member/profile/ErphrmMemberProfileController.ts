import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IErpHrmMember } from "../../../../api/structures/IErpHrmMember";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { putErpHrmMemberProfile } from "../../../../providers/putErpHrmMemberProfile";

@Controller("/erpHrm/member/profile")
export class ErphrmMemberProfileController {
  /**
   * Update the authenticated member's global profile.
   *
   * The global profile consists of three fields shared across all organizations the member belongs to: display name, avatar image, and phone number. This endpoint allows the member to modify any or all of these fields.
   *
   * **Partial Update**: Only the fields included in the request body are updated. Omitted fields retain their current values. To clear an optional field (avatar image or phone number), send null for that field.
   *
   * **Cross-Organization Consistency**: Because the profile is global, any change takes effect immediately in every organization where the member holds an active employee membership. Coworkers in all organizations see the updated profile information in real time through WebSocket events, without needing to refresh.
   *
   * **Validation**: The display name must not be empty when provided. The avatar image must be a valid URI if specified. The phone number is free-form to accommodate international formats.
   *
   * @param connection
   * @param body Profile fields to update. Only include fields that should be changed — omitted fields retain their current values. Set avatar_image or phone_number to null to clear them.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Update the authenticated member's global profile
     *   by modifying the erp_hrm_members record identified by the current
     *   session's member ID.
   *
   * Fields that can be updated:
   * - display_name: Required string. Must not be empty or whitespace-only. Update if provided.
   * - avatar_image: Optional string. Must be a valid URI if provided, or null to remove the existing avatar. Update if key is present in the request.
   * - phone_number: Optional string. Free-text for international number formats, or null to remove. Update if key is present in the request.
   *
   * Partial update semantics: only fields present in the request body are modified. Fields omitted from the request retain their existing values.
   *
   * After successfully updating the database record, emit a real-time event with the user's identifier, the list of changed fields and their new values, and the timestamp. Broadcast this event to all active members of every organization where the member holds an active employee record (erp_hrm_employees with status 'active'). This enables coworkers to see updated display names and avatars without refreshing.
   *
   * Return the updated member record excluding sensitive fields (password_hash must not be returned).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IErpHrmMember.IUpdate,
  ): Promise<IErpHrmMember> {
    try {
      return await putErpHrmMemberProfile({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
