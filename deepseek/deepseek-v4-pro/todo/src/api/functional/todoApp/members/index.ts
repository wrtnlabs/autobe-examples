/**
 * Retrieve the authenticated member's own profile information.
 *
 * This endpoint returns the profile details of the currently authenticated member. Because the application enforces complete profile isolation between users, each member can only access their own profile — no member can view another member's profile under any circumstance.
 *
 * The response is paginated for API consistency, though it will always contain at most one record: the authenticated member's own profile. The request body supports optional search filters that are applied against the member's own data.
 *
 * @param props.connection
 * @param props.body Search criteria for filtering the authenticated member's profile. Supports optional filtering by email and display name pattern. All filters are constrained to the authenticated member's own record.
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor null
 * @x-autobe-specification Query the todo_app_members table scoped exclusively
 *   to the authenticated member's own record. The member's identity is
 *   extracted from the active session — never from request parameters. Apply
 *   any search filters provided in the request body (email, display_name)
 *   against the authenticated member's record only. Return a cursor-based
 *   paginated response containing at most one result. Reject with 401 if no
 *   authenticated session exists.
 * @path /todoApp/members
 * @accessor api.functional.todoApp.members.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
