import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { ITodoAppMember } from "../../../../api/structures/ITodoAppMember";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { putTodoAppMemberProfile } from "../../../../providers/putTodoAppMemberProfile";

@Controller("/todoApp/member/profile")
export class TodoappMemberProfileController {
  /**
   * Update the authenticated member's profile display name.
   *
   * The display name is a personal label visible only to the owning member within their own workspace. It serves as a friendly identifier within the application but has no uniqueness constraint across members.
   *
   * This operation is scoped exclusively to the authenticated user's own profile. Profile data is completely isolated between users — there is no mechanism to view or modify another user's profile.
   *
   * @param connection
   * @param body Profile update payload containing the new display name. The display name must be a non-empty value — empty strings or whitespace-only values are rejected.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Update the authenticated member's profile display
     *   name.
   *
   * Retrieve the authenticated member's ID from the session context. Query the todo_app_members table for the record matching the authenticated member's ID. Validate that the member exists and is not soft-deleted (deleted_at IS NULL).
   *
   * Validate the incoming display_name: it must be present, non-empty after trimming whitespace, and must not consist solely of whitespace characters. If validation fails, return a 400 Bad Request error.
   *
   * If validation passes, update the display_name field on the member's record and set updated_at to the current timestamp. Return the full updated member record.
   *
   * This operation is scoped exclusively to the authenticated member's own profile. No other user's profile can be accessed or modified.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: ITodoAppMember.IUpdate,
  ): Promise<ITodoAppMember> {
    try {
      return await putTodoAppMemberProfile({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
