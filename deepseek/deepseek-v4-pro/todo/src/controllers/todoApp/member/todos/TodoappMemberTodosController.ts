@Controller("/todoApp/member/todos")
export class TodoappMemberTodosController {
  /**
   * Create a new todo item for the authenticated member.
   *
   * A todo represents an individual task owned by the member. The title is mandatory and must not be empty. The description, start date, and due date are optional and may be omitted or set to null.
   *
   * When both a start date and due date are provided, the due date must not precede the start date. If this constraint is violated, the request is rejected.
   *
   * Newly created todos are incomplete by default and appear in the member's active todo list. They do not appear in the trash view. Each creation is scoped to the authenticated member — the todo is invisible to all other members.
   *
   * @param connection
   * @param body The todo creation payload. Only user-supplied fields are accepted — system-managed fields such as member ID, completion status, and timestamps are derived automatically.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Insert a new row into the todo_app_todos table
     *   with the following rules:
   *
   * 1. Authenticate the request — extract the member ID from the current session. If no session exists, reject with 401.
   * 2. Validate that title is non-empty and not whitespace-only. Reject with 400 if empty or missing.
   * 3. Set member_id to the authenticated member's ID (derived from session, not from request body).
   * 4. Set completed_at to NULL (new todos are incomplete by default).
   * 5. Set deleted_at to NULL (new todos are active, not in trash).
   * 6. Generate a new UUID for the id field.
   * 7. Set created_at and updated_at to the current timestamp.
   * 8. If both start_date and due_date are provided, validate that due_date is not earlier than start_date. Reject with 400 if violated.
   * 9. Insert the row and return the full todo record including all generated fields.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: ITodoAppTodo.ICreate,
  ): Promise<ITodoAppTodo> {
    try {
      return await postTodoAppMemberTodos({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves a paginated, filtered, and sorted list of the authenticated member's active todos.
   *
   * This endpoint returns only active (non-trashed) todos belonging to the authenticated member. Each todo in the list includes its title, completion status, optional start date, optional due date, and creation date for at-a-glance task management.
   *
   * Filtering supports three completion status modes: all todos, only completed todos, or only incomplete todos. Sorting is available by creation date, start date, or due date — when sorting by start or due date, todos without those dates are placed at the end of the list for consistent browsing.
   *
   * All results are strictly private. The operation is scoped to the authenticated member's own todos with no cross-user visibility.
   *
   * @param connection
   * @param body Search, filter, sorting, and pagination parameters for the todo list. Includes completion status filter (all, complete, incomplete), sort field and direction, and pagination controls.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query the todo_app_todos table with the following
     *   constraints and logic:
   *
   * **Scope**: Filter by member_id = authenticated member's ID. All results are strictly scoped to the current user — never expose other members' todos.
   *
   * **Active Filter**: Always filter by deleted_at IS NULL. Trashed todos are excluded from this list; they appear only in the dedicated trash view.
   *
   * **Completion Status Filter** (request body):
   * - "all": No additional filter on completed_at.
   * - "complete": Filter by completed_at IS NOT NULL.
   * - "incomplete": Filter by completed_at IS NULL.
   *
   * **Sorting** (request body):
   * - Sort by created_at: newest first (DESC) or oldest first (ASC).
   * - Sort by start_date: earliest first (ASC) or latest first (DESC). Todos with start_date IS NULL appear at the end regardless of sort direction (use NULLS LAST).
   * - Sort by due_date: earliest first (ASC) or latest first (DESC). Todos with due_date IS NULL appear at the end regardless of sort direction (use NULLS LAST).
   * - Default sort: created_at DESC (newest first).
   *
   * **Pagination**: Cursor-based or offset-based pagination as specified in the request body. Return the requested page of results with metadata (total count, current page, page size).
   *
   * **Returned Fields per Todo** (summary): id, title, completed_at (for completion status), start_date, due_date, created_at.
   *
   * **Error Handling**:
   * - If the authenticated user is not a member, deny access.
   * - Cross-user access is impossible by design — the query is always scoped to the authenticated member's ID.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: ITodoAppTodo.IRequest,
  ): Promise<IPageITodoAppTodo.ISummary> {
    try {
      return await patchTodoAppMemberTodos({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves a single todo with all its details including title, description, start date, due date, completion status, and timestamps.
   *
   * This endpoint returns the full representation of a todo owned by the authenticated member. The response includes all fields: the unique identifier, title, optional description, optional start and due dates, completion status (via the completed_at timestamp), and creation/update timestamps.
   *
   * Access is strictly scoped to the owning member. Todos belonging to other members are treated as not found. Soft-deleted todos currently in the trash are also excluded from this endpoint — the trash has its own dedicated browsing interface for viewing deleted items.
   *
   * @param connection
   * @param todoId Unique identifier of the todo to retrieve. A UUID v4 value assigned at creation time.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query the todo_app_todos table by primary key
     *   `id` matching the `{todoId}` path parameter.
   *
   * Apply the following access control and business rules:
   * 1. Verify that the `member_id` on the todo matches the authenticated member's ID. If it does not match, return a not-found response — never reveal the existence of another member's todos.
   * 2. Filter out soft-deleted records by requiring `deleted_at IS NULL`. If the todo has a non-null `deleted_at`, return a not-found response. Trashed todos are only accessible through the dedicated trash listing view.
   * 3. If no matching todo is found (doesn't exist, belongs to another member, or is soft-deleted), return a not-found error.
   *
   * Return all columns from the todo_app_todos row: id, title, description, start_date, due_date, completed_at, created_at, updated_at. Do not include member_id in the response — the owning member is implicit from the authenticated context.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":todoId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppTodo> {
    try {
      return await getTodoAppMemberTodosTodoId({
        member,
        todoId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing todo's title, description, start date, and/or due date.
   *
   * Each successful edit records the changed fields in the todo's edit history — unchanged fields are not recorded. The operation returns the full updated todo including the new modification timestamp.
   *
   * **Access Control**: Only the todo's owner can update it. Attempting to update another member's todo returns a not-found response.
   *
   * **State Restrictions**: Todos that are in the trash (soft-deleted) cannot be edited. Restore the todo from trash first before making modifications.
   *
   * **Validation Rules**:
   * - The title must not be empty.
   * - When both start date and due date are set, the due date must not be earlier than the start date.
   *
   * @param connection
   * @param todoId UUID of the todo to update.
   * @param body Fields to update on the todo. Only title, description, start_date, and due_date are editable. Omitted fields remain unchanged.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Update the todo identified by {todoId} with the
     *   provided field values.
   *
   * **Ownership Verification**: Query the todo by id, verifying it belongs to the authenticated member (member_id match). If the todo belongs to another member or does not exist, return a not-found response to avoid leaking existence information.
   *
   * **Soft-Delete Check**: If the todo's deleted_at is not null (i.e., the todo is in the trash), reject the update with an error indicating the todo is not available for modification.
   *
   * **Field Validation**:
   * - title: Required. Reject with a validation error if empty or whitespace-only.
   * - description: Optional. Accept null or empty string to clear.
   * - start_date: Optional. Accept null to clear.
   * - due_date: Optional. Accept null to clear.
   * - If both start_date and due_date are provided (non-null), enforce that due_date is not earlier than start_date. Reject with a validation error if violated.
   *
   * **Edit History Recording**: Compare each incoming field (title, description, start_date, due_date) against the current database values. For each field that differs, create a todo_app_edit_histories entry recording the new value and the timestamp of the change. Fields that remain unchanged are not recorded.
   *
   * **Response**: After persisting the update, return the full todo entity with all fields including the updated_at timestamp reflecting the modification time.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":todoId")
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoAppTodo.IUpdate,
  ): Promise<ITodoAppTodo> {
    try {
      return await putTodoAppMemberTodosTodoId({
        member,
        todoId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Soft-delete a todo, moving it to the trash.
   *
   * This operation marks the todo as deleted by setting its deletion timestamp, which hides it from the normal active todo list. The todo is not permanently removed — it remains recoverable and visible in the dedicated trash view.
   *
   * **Ownership**: Only the member who owns the todo can soft-delete it. Attempting to delete another member's todo results in an access-denied error.
   *
   * **Idempotency**: This operation is not idempotent. A todo can only be soft-deleted once while it is active. Attempting to soft-delete a todo that is already in the trash is rejected with a conflict error — the todo must first be restored from the trash before it can be soft-deleted again.
   *
   * **Recovery**: Soft-deleted todos can be restored from the trash via the restore endpoint, which clears the deletion timestamp. Permanent deletion, which irreversibly removes the todo and all its edit history, is a separate operation available from the trash view.
   *
   * @param connection
   * @param todoId UUID of the todo to soft-delete (scoped to the authenticated member).
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Soft-delete the todo identified by `todoId`,
     *   moving it to the trash.
   *
   * **Ownership Verification**: Query the `todo_app_todos` table by `id = todoId`. If no row is found, return a 404 not-found response. If a row is found but `member_id` does not match the authenticated member's ID, return a 403 access-denied response — members can only soft-delete their own todos (section 70).
   *
   * **Duplicate Soft-Delete Rejection**: Before executing the soft-delete, inspect the `deleted_at` column. If it is already non-NULL (the todo is already in the trash), reject the request with a 409 Conflict response. A todo can only be soft-deleted once; attempting to soft-delete an already-trashed todo must be declined (section 73).
   *
   * **Soft-Delete Execution**: If the todo is active (`deleted_at IS NULL`), perform an UPDATE on the row:
   * - Set `deleted_at = NOW()` — marks the todo as soft-deleted, hiding it from the active todo list.
   * - Set `updated_at = NOW()` — records when this soft-delete occurred.
   *
   * No other columns are modified. The `completed_at`, title, description, start_date, and due_date remain unchanged. All associated `todo_app_edit_histories` records are preserved — they are only removed when the todo is permanently deleted from the trash.
   *
   * **Response**: Return the full updated todo entity with all columns including the newly set `deleted_at` timestamp.
   *
   * **Edge Cases**:
   * - Todo does not exist → 404 Not Found.
   * - Todo belongs to another member → 403 Forbidden (access denied).
   * - Todo is already in the trash → 409 Conflict (duplicate soft-delete).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":todoId")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoAppMemberTodosTodoId({
        member,
        todoId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Toggle the completion status of a todo between complete and incomplete.
   *
   * A member can flip the completion state of any of their own todos at any time. Marking an incomplete todo as complete sets the completion timestamp to the current time; marking a complete todo as incomplete clears the timestamp. The toggle has no restrictions — a todo may transition back and forth any number of times.
   *
   * Only the todo owner can perform this action. Soft-deleted todos currently in the trash cannot be toggled; they must be restored from the trash first before their completion status can be changed.
   *
   * @param connection
   * @param todoId Unique identifier of the todo to toggle (UUID). The todo must belong to the authenticated member and must not be in the trash.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Toggle the completion status of a todo owned by
     *   the authenticated member.
   *
   * **Query**: Look up the todo in `todo_app_todos` by its `id` matching `todoId`. If no row is found, or if `deleted_at` IS NOT NULL (the todo is in the trash), respond with 404 Not Found. Verify the todo's `member_id` equals the authenticated member's ID — if not, respond with 403 Forbidden.
   *
   * **Toggle Logic**:
   * - If `completed_at` IS NULL (currently incomplete): set `completed_at` to the current timestamp. The todo is now complete.
   * - If `completed_at` IS NOT NULL (currently complete): set `completed_at` to NULL. The todo is now incomplete.
   *
   * Update `updated_at` to the current timestamp. Persist the change and return the full updated todo row.
   *
   * **Error Conditions**:
   * - Todo does not exist or is soft-deleted (`deleted_at` IS NOT NULL) → 404 Not Found
   * - Todo belongs to another member (`member_id` mismatch) → 403 Forbidden
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post(":todoId/toggle")
  public async toggle(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppTodo> {
    try {
      return await postTodoAppMemberTodosTodoIdToggle({
        member,
        todoId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
