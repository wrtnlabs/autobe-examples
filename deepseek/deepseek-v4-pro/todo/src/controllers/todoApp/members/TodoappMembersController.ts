import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageITodoAppMember } from "../../../api/structures/IPageITodoAppMember";
import { ITodoAppMember } from "../../../api/structures/ITodoAppMember";
import { getTodoAppMembersMemberId } from "../../../providers/getTodoAppMembersMemberId";
import { patchTodoAppMembers } from "../../../providers/patchTodoAppMembers";

@Controller("/todoApp/members")
export class TodoappMembersController {
  /**
   * Retrieve the authenticated member's own profile information.
   *
   * This endpoint returns the profile details of the currently authenticated member. Because the application enforces complete profile isolation between users, each member can only access their own profile — no member can view another member's profile under any circumstance.
   *
   * The response is paginated for API consistency, though it will always contain at most one record: the authenticated member's own profile. The request body supports optional search filters that are applied against the member's own data.
   *
   * @param connection
   * @param body Search criteria for filtering the authenticated member's profile. Supports optional filtering by email and display name pattern. All filters are constrained to the authenticated member's own record.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor null
     * @x-autobe-specification Query the todo_app_members table scoped
     *   exclusively to the authenticated member's own record. The member's
     *   identity is extracted from the active session — never from request
     *   parameters. Apply any search filters provided in the request body
     *   (email, display_name) against the authenticated member's record only.
     *   Return a cursor-based paginated response containing at most one result.
     *   Reject with 401 if no authenticated session exists.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: ITodoAppMember.IRequest,
  ): Promise<IPageITodoAppMember.ISummary> {
    try {
      return await patchTodoAppMembers({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve the authenticated member's own profile.
   *
   * Returns the member's identity and profile information including email address, display name, and account timestamps. This endpoint is strictly scoped to the authenticated member — each member can only retrieve their own profile.
   *
   * @param connection
   * @param memberId UUID of the member whose profile to retrieve. Must match the authenticated member's own ID — cross-user access is denied.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor null
     * @x-autobe-specification Query the todo_app_members table by the provided
     *   memberId (UUID primary key).
   *
   * Verify that the authenticated member's ID exactly matches the memberId path parameter — cross-user profile access is prohibited. If the IDs do not match, deny the request.
   *
   * Exclude deleted members (deleted_at IS NOT NULL) from results. Return the member's profile fields: id, email, display_name, created_at, updated_at. Never expose the password_hash in any response.
   *
   * If no matching member is found or the member has been deleted, return an appropriate not-found error.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":memberId")
  public async at(
    @TypedParam("memberId")
    memberId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppMember> {
    try {
      return await getTodoAppMembersMemberId({
        memberId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
