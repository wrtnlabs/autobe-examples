import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { ITodoAppGuest } from "../../../../api/structures/ITodoAppGuest";
import { postTodoAppAuthGuestJoin } from "../../../../providers/postTodoAppAuthGuestJoin";
import { postTodoAppAuthGuestRefresh } from "../../../../providers/postTodoAppAuthGuestRefresh";

@Controller("/todoApp/auth/guest")
export class TodoappAuthGuestController {
  /**
   * Register or identify a guest visitor by device fingerprint and create a temporary session.
   *
   * This endpoint serves as the entry point for unauthenticated visitors. It creates or retrieves a guest identity based on the device fingerprint hash, then establishes a new guest session with contextual metadata (current page URL and referrer) for security auditing purposes. The guest's IP address is captured server-side from the incoming request.
   *
   * Upon success, the endpoint returns a JWT access token and refresh token pair. The access token grants temporary authenticated access as a guest to permitted endpoints, while the refresh token allows the session to be extended without re-submitting the fingerprint.
   *
   * **Session Lifecycle**: Each call to this endpoint creates a new session record in `todo_app_guest_sessions`. Previous sessions remain in the database until they expire naturally based on `expired_at`. The guest identity in `todo_app_guests` persists across sessions and is matched by the unique `fingerprint` field.
   *
   * **Role Transition**: To transition from guest to member, the visitor must call the member registration endpoint (`/auth/member/join`) or login endpoint (`/auth/member/login`). The guest identity and sessions are independent from member identities and are superseded upon successful member authentication.
   *
   * **Related Operations**: After join, call `refresh` to renew tokens before they expire. Guest tokens cannot access member-only resources such as todos, trash, edit history, or user profiles.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Guest join request containing the device fingerprint hash and optional session context metadata.
   *
   *             The fingerprint is a hashed representation of device characteristics used to uniquely identify returning unauthenticated visitors across visits. Optional href and referrer fields capture the page context where the guest initiated the join flow, stored in the session record for security auditing.
     * @x-autobe-authorization-type join
     * @x-autobe-authorization-actor guest
     * @x-autobe-specification Create or retrieve a guest identity by device
     *   fingerprint, then create a new guest session with the provided context
     *   and issue JWT tokens.
   *
   * **Implementation Steps**:
   * 1. Validate `fingerprint` is a non-empty string.
   * 2. Look up existing `todo_app_guests` record by `fingerprint` (unique index).
   *    - If found: update `updated_at` to now().
   *    - If not found: insert new record with UUID, fingerprint, `created_at = now()`, `updated_at = now()`.
   * 3. Create a new `todo_app_guest_sessions` record:
   *    - `id`: new UUID
   *    - `todo_app_guest_id`: guest record ID from step 2
   *    - `ip`: extracted from request context (X-Forwarded-For header or remote address)
   *    - `href`: from request body if provided, otherwise empty string
   *    - `referrer`: from request body if provided, otherwise empty string
   *    - `created_at`: now()
   *    - `expired_at`: now() + configured guest session TTL (e.g., 24 hours)
   * 4. Generate JWT access token (short-lived, e.g., 15 minutes) with claims:
   *    - `sub`: guest ID
   *    - `session_id`: session ID from step 3
   *    - `kind`: "guest"
   * 5. Generate JWT refresh token (long-lived, e.g., 7 days) with claims:
   *    - `sub`: guest ID
   *    - `session_id`: session ID from step 3
   *    - `kind`: "guest"
   *    - `type`: "refresh"
   * 6. Return `ITodoAppGuest.IAuthorized` containing both token strings.
   *
   * **Error Handling**:
   * - 400: `fingerprint` is missing or empty
   * - 500: Database write failure or token generation failure
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoAppGuest.IJoin,
  ): Promise<ITodoAppGuest.IAuthorized> {
    try {
      return await postTodoAppAuthGuestJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh an existing guest session by exchanging a valid refresh token for a new JWT token pair.
   *
   * This endpoint allows guest sessions to be extended without requiring the guest to re-submit their device fingerprint. The provided refresh token is cryptographically verified, its embedded claims are validated against the database, and upon success a new guest session record is created along with a fresh access token and refresh token pair.
   *
   * **Token Rotation**: Each refresh call creates a new session record in `todo_app_guest_sessions` with a new refresh token. The previous refresh token remains valid until its natural expiration, but the new token pair should be used for all subsequent requests. The old session record persists for audit purposes but is not extended.
   *
   * **Session Expiry**: If the session referenced by the refresh token has passed its `expired_at` timestamp, the refresh is denied and the guest must call `join` again to establish a new identity and session. Refresh tokens have a longer lifetime than access tokens but are still finite.
   *
   * **Related Operations**: This endpoint is called after `join` to maintain session continuity without fingerprint re-submission. It does not upgrade the guest to a member — that transition requires calling member-specific authentication endpoints (`/auth/member/join` or `/auth/member/login`).
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token request containing the current refresh token to exchange for a new token pair.
   *
   *             The refresh token was issued during a previous `join` or `refresh` call. It contains embedded JWT claims identifying the guest identity and session, which are extracted and validated server-side.
     * @x-autobe-authorization-type refresh
     * @x-autobe-authorization-actor guest
     * @x-autobe-specification Validate the provided refresh token and issue a
     *   new JWT token pair with a new guest session.
   *
   * **Implementation Steps**:
   * 1. Decode and verify the refresh token's signature and expiration.
   * 2. Extract claims: `sub` (guest ID), `session_id` (session ID), `kind` (must be "guest"), `type` (must be "refresh").
   * 3. Verify the guest record exists in `todo_app_guests` by the extracted guest ID. If not found → 401.
   * 4. Verify the session record exists in `todo_app_guest_sessions` by the extracted session ID and that `todo_app_guest_id` matches the guest ID. If not found or mismatch → 401.
   * 5. Check session `expired_at` > now(). If expired → 401 with message indicating re-join is required.
   * 6. Create a new `todo_app_guest_sessions` record with the same guest ID:
   *    - `id`: new UUID
   *    - `todo_app_guest_id`: extracted guest ID
   *    - `ip`: extracted from current request context
   *    - `href`: empty string (no href context from refresh request body)
   *    - `referrer`: empty string
   *    - `created_at`: now()
   *    - `expired_at`: now() + configured guest session TTL
   * 7. Generate new JWT access token with claims: `sub` = guest ID, `session_id` = new session ID, `kind` = "guest".
   * 8. Generate new JWT refresh token with claims: `sub` = guest ID, `session_id` = new session ID, `kind` = "guest", `type` = "refresh".
   * 9. Return `ITodoAppGuest.IAuthorized` with both new tokens.
   *
   * **Error Handling**:
   * - 400: `refreshToken` is missing or empty
   * - 401: Token is invalid, expired, malformed, or references a non-existent guest or session
   * - 401: Session referenced by token has expired — guest must re-join
   * - 500: Token generation failure
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: ITodoAppGuest.IRefresh,
  ): Promise<ITodoAppGuest.IAuthorized> {
    try {
      return await postTodoAppAuthGuestRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
