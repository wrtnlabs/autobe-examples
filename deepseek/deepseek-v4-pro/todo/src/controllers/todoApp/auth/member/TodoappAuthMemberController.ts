import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { ITodoAppMember } from "../../../../api/structures/ITodoAppMember";
import { postTodoAppAuthMemberJoin } from "../../../../providers/postTodoAppAuthMemberJoin";
import { postTodoAppAuthMemberLogin } from "../../../../providers/postTodoAppAuthMemberLogin";
import { postTodoAppAuthMemberRefresh } from "../../../../providers/postTodoAppAuthMemberRefresh";

@Controller("/todoApp/auth/member")
export class TodoappAuthMemberController {
  /**
   * Register a new member account and authenticate in a single flow.
   *
   * The join operation creates a new member record in todo_app_members with the provided email, password, and display name. Upon successful creation, a session is established in todo_app_member_sessions and JWT access and refresh tokens are issued.
   *
   * **Validation**: Email must be a valid email format and must not already exist in the system. Password must meet minimum strength requirements. Display name is required and must be non-empty.
   *
   * **Session**: A new session record is created capturing the client's IP address and request context. The session's expired_at timestamp defines the access token's validity window.
   *
   * **Response**: Returns an IAuthorized object containing both an access token (short-lived, for API authentication) and a refresh token (long-lived, for obtaining new access tokens without re-login).
   *
   * **Errors**: 409 Conflict if the email is already registered. 400 Bad Request for invalid input.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Registration payload containing the new member's email, password, and display name.
     * @x-autobe-authorization-type join
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Create a new member account and establish an
     *   authenticated session.
   *
   * 1. Validate request body: email must be valid email format, password must meet strength requirements (minimum length, complexity), display_name must be non-empty.
   * 2. Check email uniqueness against todo_app_members table — if email already exists and the account is not deleted (deleted_at IS NULL), return 409 Conflict.
   * 3. If email belongs to a soft-deleted account (deleted_at IS NOT NULL), reject with 409 Conflict — re-registration with same email is not allowed.
   * 4. Hash the password using bcrypt or argon2 with appropriate cost factor.
   * 5. Insert new row into todo_app_members: generate UUID for id, set email, password_hash, display_name, created_at = now(), updated_at = now().
   * 6. Create a session in todo_app_member_sessions: generate UUID for id, set todo_app_member_id to new member id, capture client IP and href from request context, set created_at = now(), expired_at = now() + access token TTL.
   * 7. Generate JWT access token (short-lived) and JWT refresh token (long-lived) bound to the session id and member id.
   * 8. Return both tokens in the response body.
   * 9. On any database error, return 500 Internal Server Error.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoAppMember.IJoin,
  ): Promise<ITodoAppMember.IAuthorized> {
    try {
      return await postTodoAppAuthMemberJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate an existing member using email and password.
   *
   * Verifies the member's credentials against the stored password_hash in todo_app_members. Upon successful authentication, a new session is created in todo_app_member_sessions and JWT access and refresh tokens are issued.
   *
   * **Security**: Failed login attempts return a generic 401 Unauthorized response regardless of whether the email exists, preventing user enumeration attacks. Password comparison uses constant-time verification.
   *
   * **Session**: Each successful login creates a new session record with the client's IP address, request path, and referrer for audit trail purposes. Previous sessions remain valid until their individual expiration.
   *
   * **Response**: Returns an IAuthorized object with access and refresh tokens for subsequent authenticated requests.
   *
   * **Errors**: 401 Unauthorized for invalid credentials or non-existent account. 400 Bad Request for missing email or password.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Login credentials containing the member's email and password.
     * @x-autobe-authorization-type login
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Authenticate an existing member with email and
     *   password credentials.
   *
   * 1. Validate request body: email must be present and valid format, password must be present.
   * 2. Query todo_app_members by email where deleted_at IS NULL — if no record found, return 401 Unauthorized with generic message (do not reveal whether email exists).
   * 3. Compare the provided password against the stored password_hash using the appropriate verification function (bcrypt/argon2).
   * 4. If password does not match, return 401 Unauthorized with generic message.
   * 5. Create a new session in todo_app_member_sessions: generate UUID for id, set todo_app_member_id to the member's id, capture client IP, href, and referrer from request context, set created_at = now(), expired_at = now() + access token TTL.
   * 6. Generate JWT access token (short-lived) and JWT refresh token (long-lived) bound to the session id and member id.
   * 7. Return both tokens in the response body.
   * 8. On any database error, return 500 Internal Server Error.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoAppMember.ILogin,
  ): Promise<ITodoAppMember.IAuthorized> {
    try {
      return await postTodoAppAuthMemberLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Obtain a new access token and refresh token using a valid refresh token.
   *
   * This operation implements refresh token rotation. When a valid refresh token is presented, the existing session in todo_app_member_sessions is extended and new tokens are issued. The previous refresh token is invalidated.
   *
   * **Token Rotation**: Each refresh operation returns a new refresh token and invalidates the one used. This limits the window of vulnerability if a refresh token is compromised.
   *
   * **Session Validation**: The refresh token must correspond to an active, non-expired session in todo_app_member_sessions. The linked member account in todo_app_members must not be deleted (deleted_at IS NULL).
   *
   * **Response**: Returns an IAuthorized object containing the new access token and new refresh token for continued authenticated access.
   *
   * **Errors**: 401 Unauthorized for expired, invalid, or revoked refresh tokens. 401 Unauthorized if the associated member account has been deleted.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token payload containing the current refresh token to be exchanged.
     * @x-autobe-authorization-type refresh
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Refresh an access token using a valid refresh
     *   token.
   *
   * 1. Validate request body: refreshToken must be present and non-empty.
   * 2. Decode and verify the refresh token's JWT signature and expiration.
   * 3. If the refresh token is expired or invalid, return 401 Unauthorized.
   * 4. Extract the session id from the refresh token payload.
   * 5. Query todo_app_member_sessions by id — if session not found or expired_at < now(), return 401 Unauthorized.
   * 6. Verify the linked todo_app_member still exists and deleted_at IS NULL — if deleted, return 401 Unauthorized.
   * 7. Update the existing session: set expired_at = now() + new access token TTL (extend the session window).
   * 8. Generate a new JWT access token (short-lived) and a new JWT refresh token (long-lived), both bound to the same session id and member id.
   * 9. The old refresh token becomes invalid (rotation — the new refresh token replaces it).
   * 10. Return both new tokens in the response body.
   * 11. On any database error, return 500 Internal Server Error.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: ITodoAppMember.IRefresh,
  ): Promise<ITodoAppMember.IAuthorized> {
    try {
      return await postTodoAppAuthMemberRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
