export async function test_api_email_template_retrieve_by_administrator(
  connection: api.IConnection,
): Promise<void> {
  // Create administrator connection
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_administrator_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
    },
  });
  // Generate random template ID
  const templateId = typia.random<string & tags.Format<"uuid">>();
  // Retrieve email template
  const template =
    await api.functional.ecommerce.administrator.email_templates.at(
      adminConnection,
      { templateId },
    );
  typia.assert(template);
}
