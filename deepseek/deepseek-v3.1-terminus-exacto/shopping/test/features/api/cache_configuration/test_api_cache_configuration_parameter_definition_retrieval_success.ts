export async function test_api_cache_configuration_parameter_definition_retrieval_success(
  connection: api.IConnection,
): Promise<void> {
  // Create super administrator connection
  const superAdminConnection: api.IConnection = { host: connection.host };
  // Authenticate as super administrator
  const authResult = await authorize_super_administrator_join(
    superAdminConnection,
    {
      body: {
        email: typia.random<string & tags.Format<"email">>(),
        password: RandomGenerator.alphaNumeric(16),
        href: typia.random<string & tags.Format<"uri">>(),
        referrer: typia.random<string & tags.Format<"uri">>(),
        ip: typia.random<string & tags.Format<"ipv4">>(),
      } satisfies IEcommerceSuperAdministrator.IJoin,
    },
  );
  typia.assert(authResult);
  // Retrieve cache configuration parameter definition
  const parameterDefinition =
    await api.functional.ecommerce.superAdministrator.cache_configurations.parameter_definitions.at(
      superAdminConnection,
      {
        definitionId: typia.random<string & tags.Format<"uuid">>(),
      },
    );
  typia.assert(parameterDefinition);
  // Validate business logic - ensure the response contains expected category operation audit data
  TestValidator.predicate("definition ID is valid UUID", () =>
    /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i.test(
      parameterDefinition.id,
    ),
  );
  TestValidator.predicate("administrator has valid email format", () =>
    /^[a-z0-9!#$%&'*+/=?^_`{|}~-]+(?:\.[a-z0-9!#$%&'*+/=?^_`{|}~-]+)*@(?:[a-z0-9](?:[a-z0-9-]*[a-z0-9])?\.)+[a-z0-9](?:[a-z0-9-]*[a-z0-9])?$/i.test(
      parameterDefinition.administrator.email,
    ),
  );
  TestValidator.predicate("category has valid UUID format", () =>
    /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i.test(
      parameterDefinition.category.id,
    ),
  );
}
