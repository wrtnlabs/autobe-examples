export async function test_api_cache_configuration_parameter_nonexistent_config(
  connection: api.IConnection,
): Promise<void> {
  // Create administrator connection and authenticate
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_administrator_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IEcommerceAdministrator.IJoin,
  });
  // Generate random UUIDs that don't correspond to existing configurations
  const configId = typia.random<string & tags.Format<"uuid">>();
  const parameterId = typia.random<string & tags.Format<"uuid">>();
  // Attempt to retrieve parameter from non-existent cache configuration
  // This should throw an HTTP error with status code 404
  await TestValidator.httpError(
    "non-existent cache configuration parameter retrieval",
    404,
    async () =>
      await api.functional.ecommerce.administrator.cache_configurations.parameters.at(
        adminConnection,
        {
          configId,
          parameterId,
        },
      ),
  );
}
