export async function test_api_cache_parameter_definition_delete_not_found(
  connection: api.IConnection,
): Promise<void> {
  // Create super administrator connection
  const superAdminConnection: api.IConnection = { host: connection.host };
  // Authenticate as super administrator using utility function
  await authorize_super_administrator_join(superAdminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    },
  });
  // Generate a random but valid UUID that doesn't exist in the system
  const nonExistentDefinitionId = typia.random<string & tags.Format<"uuid">>();
  // Attempt to delete the non-existent cache parameter definition
  // This should return a 404 error indicating the definition was not found
  await TestValidator.httpError(
    "delete non-existent cache parameter definition",
    404,
    async () => {
      await api.functional.ecommerce.superAdministrator.cache_configurations.parameter_definitions.erase(
        superAdminConnection,
        {
          definitionId: nonExistentDefinitionId,
        },
      );
    },
  );
}
