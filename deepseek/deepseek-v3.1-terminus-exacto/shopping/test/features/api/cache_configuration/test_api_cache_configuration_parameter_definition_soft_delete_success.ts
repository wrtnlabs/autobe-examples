export async function test_api_cache_configuration_parameter_definition_soft_delete_success(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create administrator account and connection
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_administrator_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IEcommerceAdministrator.IJoin,
  });
  // 2. Create a parameter definition ID for deletion
  const definitionId = typia.random<string & tags.Format<"uuid">>();
  // 3. Execute soft deletion
  await api.functional.ecommerce.administrator.cache_configurations.parameter_definitions.erase(
    adminConnection,
    { definitionId },
  );
  // 4. Response is void type (204 No Content) - no validation needed
  // Soft deletion successful - the definition is marked as deleted
}
