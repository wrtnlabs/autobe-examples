export async function test_api_cancellation_request_paid_order_item_success(
  connection: api.IConnection,
): Promise<void> {
  // 1. Customer authentication using utility function
  const customerConnection: api.IConnection = { host: connection.host };
  const customer = await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      phone_number: RandomGenerator.mobile(),
    },
  });
  typia.assert(customer);
  // 2. Create cancellation request using generation utility function
  // This utility function internally handles order item validation and creation
  const cancellationRequest: IEcommerceCancellationRequest =
    await generate_random_ecommerce_customer_cancellation_requests_create(
      customerConnection,
      {
        body: {
          reason:
            RandomGenerator.paragraph({ sentences: 3 })
              .substring(0, 200)
              .trim() +
            " additional details to ensure minimum length requirement is met.",
        },
      },
    );
  typia.assert(cancellationRequest);
  // 3. Validate cancellation request structure
  TestValidator.equals(
    "cancellation request customer matches authenticated customer",
    cancellationRequest.customer.id,
    customer.id,
  );
  // 4. Validate order item exists in response
  TestValidator.predicate(
    "cancellation request includes order item",
    cancellationRequest.orderItem !== null,
  );
  // 5. Validate seller exists in response
  TestValidator.predicate(
    "cancellation request includes seller",
    cancellationRequest.seller !== null,
  );
  // 6. Validate cancellation reason length meets requirements (10-500 characters)
  TestValidator.predicate(
    "cancellation reason length valid",
    cancellationRequest.reason.length >= 10 &&
      cancellationRequest.reason.length <= 500,
  );
  // 7. Verify timestamps are present
  TestValidator.predicate(
    "created_at timestamp present",
    cancellationRequest.created_at !== null,
  );
  TestValidator.predicate(
    "updated_at timestamp present",
    cancellationRequest.updated_at !== null,
  );
  // 8. Validate the response is a complete cancellation request object
  // typia.assert already performed complete validation
}
