/**
 * Test seller cancellation request retrieval for owned requests.
 *
 * This test verifies that a seller can successfully retrieve cancellation requests
 * that belong to their products. It follows the complete workflow from account
 * creation to cancellation request retrieval, ensuring proper authentication
 * and authorization checks.
 */
export async function test_api_seller_cancellation_request_retrieve_owned_by_seller(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create seller account and authenticate
  const sellerConnection: api.IConnection = { host: connection.host };
  const seller = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "password123",
      shop_name: RandomGenerator.name(),
      shop_description: RandomGenerator.paragraph({ sentences: 2 }),
      logo_image_url: typia.random<string & tags.Format<"uri">>(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    },
  });
  typia.assert(seller);
  // 2. Create customer account and authenticate
  const customerConnection: api.IConnection = { host: connection.host };
  const customer = await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "password123",
      display_name: RandomGenerator.name(),
      phone_number: RandomGenerator.mobile(),
    },
  });
  typia.assert(customer);
  // 3. Seller creates a product
  const product = await generate_random_ecommerce_seller_products_create(
    sellerConnection,
    {
      body: {
        name: RandomGenerator.paragraph({
          sentences: 1,
          wordMin: 2,
          wordMax: 4,
        }),
        description: RandomGenerator.paragraph({ sentences: 3 }),
        base_price: typia.random<
          number & tags.Type<"uint32"> & tags.Minimum<1000>
        >(),
        category_id: typia.random<string & tags.Format<"uuid">>(),
      },
    },
  );
  typia.assert(product);
  // 4. Seller creates a product variant
  const variant =
    await generate_random_ecommerce_seller_products_variants_create(
      sellerConnection,
      {
        body: {
          sku: RandomGenerator.alphaNumeric(10),
          option_values: JSON.stringify({ color: "red", size: "M" }),
          price_override: null,
          quantity: typia.random<
            number & tags.Type<"int32"> & tags.Minimum<100>
          >(),
        },
        params: { productId: product.id },
      },
    );
  typia.assert(variant);
  // Note: Actual order creation and cancellation request creation workflow
  // would require additional API endpoints not available in the current SDK.
  // For this test, we'll simulate the cancellation request retrieval scenario
  // by creating a mock cancellation request reference.
  // 5. Create a cancellation request directly (simulating the workflow)
  const cancellationRequest =
    await generate_random_ecommerce_customer_cancellation_requests_create(
      customerConnection,
      {
        body: {
          ecommerce_order_item_id: typia.random<string & tags.Format<"uuid">>(),
          reason: RandomGenerator.paragraph({ sentences: 2 }),
        },
      },
    );
  typia.assert(cancellationRequest);
  // 6. Seller retrieves the cancellation request
  const retrievedRequest =
    await api.functional.ecommerce.seller.cancellation_requests.at(
      sellerConnection,
      {
        cancellationRequestId: cancellationRequest.id,
      },
    );
  typia.assert(retrievedRequest);
  // 7. Validate response structure and data integrity
  TestValidator.equals(
    "cancellation request ID",
    retrievedRequest.id,
    cancellationRequest.id,
  );
  TestValidator.equals(
    "cancellation reason",
    retrievedRequest.reason,
    cancellationRequest.reason,
  );
  TestValidator.predicate(
    "has valid timestamps",
    retrievedRequest.created_at !== null &&
      retrievedRequest.updated_at !== null,
  );
  TestValidator.predicate(
    "customer information present",
    retrievedRequest.customer !== null &&
      retrievedRequest.customer.email === customer.email,
  );
  TestValidator.predicate(
    "seller information present",
    retrievedRequest.seller !== null &&
      retrievedRequest.seller.email === seller.email,
  );
  TestValidator.predicate(
    "order item information present",
    retrievedRequest.orderItem !== null &&
      retrievedRequest.orderItem.id !== null,
  );
}
