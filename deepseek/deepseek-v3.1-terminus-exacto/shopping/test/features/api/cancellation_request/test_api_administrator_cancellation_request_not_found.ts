export async function test_api_administrator_cancellation_request_not_found(
  connection: api.IConnection,
): Promise<void> {
  // Create admin connection and authenticate
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_administrator_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IEcommerceAdministrator.IJoin,
  });
  // Attempt to retrieve a non-existent cancellation request
  await TestValidator.httpError(
    "should return 404 for non-existent cancellation request",
    404,
    async () =>
      await api.functional.ecommerce.administrator.cancellation_requests.at(
        adminConnection,
        {
          cancellationRequestId: typia.random<string & tags.Format<"uuid">>(),
        },
      ),
  );
}
