export async function test_api_customer_orders_hide_other_users(
  connection: api.IConnection,
): Promise<void> {
  // Create first customer (Customer A)
  const customerAConnection: api.IConnection = { host: connection.host };
  const customerA = await authorize_customer_join(customerAConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      phone_number: RandomGenerator.mobile(),
    },
  });
  typia.assert(customerA);
  // Create second customer (Customer B)
  const customerBConnection: api.IConnection = { host: connection.host };
  const customerB = await authorize_customer_join(customerBConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      phone_number: RandomGenerator.mobile(),
    },
  });
  typia.assert(customerB);
  // Create seller account (must be approved to create products)
  const sellerConnection: api.IConnection = { host: connection.host };
  const seller = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      shop_name: RandomGenerator.name(),
      shop_description: RandomGenerator.paragraph({ sentences: 2 }),
      logo_image_url: typia.random<string & tags.Format<"uri">>(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    },
  });
  typia.assert(seller);
  // Seller creates product
  const product = await generate_random_ecommerce_seller_products_create(
    sellerConnection,
    {
      body: {
        name: RandomGenerator.paragraph({
          sentences: 2,
          wordMin: 3,
          wordMax: 7,
        }),
        description: RandomGenerator.content({
          paragraphs: 1,
          sentenceMin: 3,
          sentenceMax: 5,
        }),
        base_price: typia.random<
          number & tags.Type<"uint32"> & tags.Minimum<1000>
        >(),
        category_id: typia.random<string & tags.Format<"uuid">>(),
      },
    },
  );
  typia.assert(product);
  // Seller adds variant to product
  const variant =
    await generate_random_ecommerce_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
        body: {
          sku: RandomGenerator.alphaNumeric(10),
          option_values: JSON.stringify({ color: "red", size: "M" }),
          price_override: null,
          quantity: typia.random<
            number & tags.Type<"int32"> & tags.Minimum<10>
          >(),
        },
      },
    );
  typia.assert(variant);
  // Customer B creates cart (using cart index endpoint)
  const cartResponse = await api.functional.ecommerce.customer.carts.index(
    customerBConnection,
    {
      body: {
        customer_id: customerB.id,
        page: 1,
        limit: 10,
      },
    },
  );
  typia.assert(cartResponse);
  // Find or create cart for Customer B (simplified - assume first cart)
  const cartId =
    cartResponse.data[0]?.id ?? typia.random<string & tags.Format<"uuid">>();
  // Customer B adds item to cart
  const cartItem = await generate_random_ecommerce_customer_carts_items_create(
    customerBConnection,
    {
      params: { cartId },
      body: {
        product_variant_id: variant.id,
        quantity: typia.random<
          number & tags.Type<"int32"> & tags.Minimum<1> & tags.Maximum<3>
        >(),
      },
    },
  );
  typia.assert(cartItem);
  // Customer B creates order via checkout
  const order = await api.functional.ecommerce.customer.checkout.create(
    customerBConnection,
    {
      body: {
        page: 1,
        limit: 10,
      },
    },
  );
  typia.assert(order);
  // Capture order ID from Customer B's order
  // FIX: Use proper type assertion to extract the order ID
  const orderId = (order as any).id satisfies string as string;
  // Customer A attempts to access Customer B's order - should fail
  await TestValidator.error(
    "Customer A cannot access Customer B's order",
    async () => {
      await api.functional.ecommerce.customer.orders.at(customerAConnection, {
        orderId,
      });
    },
  );
  // Optional: Verify Customer B can access their own order
  const ownOrder = await api.functional.ecommerce.customer.orders.at(
    customerBConnection,
    {
      orderId,
    },
  );
  typia.assert(ownOrder);
  TestValidator.equals("Order ID matches", (ownOrder as any).id, orderId);
}