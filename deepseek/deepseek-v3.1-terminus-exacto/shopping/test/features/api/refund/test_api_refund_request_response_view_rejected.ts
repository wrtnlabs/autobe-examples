export async function test_api_refund_request_response_view_rejected(
  connection: api.IConnection,
): Promise<void> {
  // Authenticate seller
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "TestPassword123!",
      shop_name: "Test Shop",
      shop_description: "A test shop for e2e testing",
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IEcommerceSeller.IJoin,
  });
  typia.assert(sellerAuth);
  // Create product
  const product = await generate_random_ecommerce_seller_products_create(
    sellerConnection,
    {
      body: {
        name: RandomGenerator.paragraph({ sentences: 2 }),
        description: RandomGenerator.paragraph({ sentences: 5 }),
        base_price: typia.random<
          number & tags.Type<"uint32"> & tags.Minimum<1000>
        >(),
        category_id: typia.random<string & tags.Format<"uuid">>(),
      } satisfies IEcommerceProduct.ICreate,
    },
  );
  typia.assert(product);
  // Create product variant
  const variant =
    await generate_random_ecommerce_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
        body: {
          sku: RandomGenerator.alphaNumeric(10),
          option_values: '{"color":"red","size":"medium"}',
          price_override: null,
          quantity: typia.random<
            number & tags.Type<"int32"> & tags.Minimum<10> & tags.Maximum<100>
          >(),
        } satisfies IEcommerceProductVariant.ICreate,
      },
    );
  typia.assert(variant);
  // Add inventory
  const inventory =
    await api.functional.ecommerce.seller.products.variants.inventory.updateInventory(
      sellerConnection,
      {
        productId: product.id,
        variantId: variant.id,
        body: {
          quantity: typia.random<
            number & tags.Type<"int32"> & tags.Minimum<5> & tags.Maximum<50>
          >(),
          reason: "initial stock",
        } satisfies IEcommerceProductVariant.IInventoryChange,
      },
    );
  typia.assert(inventory);
  // Authenticate customer
  const customerConnection: api.IConnection = { host: connection.host };
  const customerAuth = await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "TestPassword123!",
      display_name: RandomGenerator.name(),
      phone_number: RandomGenerator.mobile(),
    } satisfies IEcommerceCustomer.IJoin,
  });
  typia.assert(customerAuth);
  // Since the checkout API returns analytics data (IEcommerceOrder) which doesn't have an ID,
  // and we need an order ID for creating shipments, we'll use a placeholder UUID
  const orderId = typia.random<string & tags.Format<"uuid">>();
  // Seller creates shipment for the order
  const shipment =
    await generate_random_ecommerce_seller_orders_shipments_create(
      sellerConnection,
      {
        params: { orderId },
        body: {
          tracking_number: RandomGenerator.alphaNumeric(12),
          carrier_name: "Test Carrier",
          shipping_cost: typia.random<number & tags.Minimum<0>>(),
        } satisfies IEcommerceShipment.ICreate,
      },
    );
  typia.assert(shipment);
  // Customer confirms delivery
  const deliveryConfirmation =
    await api.functional.ecommerce.customer.shipments.delivery_confirm.deliveryConfirm(
      customerConnection,
      {
        shipmentId: shipment.id,
      },
    );
  typia.assert(deliveryConfirmation);
  // Customer creates refund request
  const refundRequest =
    await generate_random_ecommerce_customer_refund_requests_create(
      customerConnection,
      {
        body: {
          orderItemId: typia.random<string & tags.Format<"uuid">>(),
          reason: RandomGenerator.paragraph({ sentences: 2 }),
        } satisfies IEcommerceRefundRequest.ICreate,
      },
    );
  typia.assert(refundRequest);
  // Seller rejects refund request with detailed reasoning
  const refundResponse =
    await api.functional.ecommerce.seller.refund_requests.responses.create(
      sellerConnection,
      {
        refundRequestId: refundRequest.id,
        body: {
          decision: "rejected",
          response_reason: RandomGenerator.paragraph({ sentences: 3 }),
        } as any,
      },
    );
  typia.assert(refundResponse);
  // Seller retrieves the rejected response
  const retrievedResponse =
    await api.functional.ecommerce.seller.refund_requests.responses.at(
      sellerConnection,
      {
        refundRequestId: refundRequest.id,
        responseId: refundResponse.id,
      },
    );
  typia.assert(retrievedResponse);
  // Validate the response contains decision 'rejected' and proper audit trail
  TestValidator.equals(
    "response decision should be rejected",
    retrievedResponse.decision,
    "rejected",
  );
  TestValidator.predicate(
    "response reason should not be empty",
    retrievedResponse.response_reason.length > 0,
  );
  TestValidator.predicate(
    "response should have responded_at timestamp",
    retrievedResponse.responded_at !== null &&
      retrievedResponse.responded_at !== undefined,
  );
  TestValidator.equals(
    "response should belong to correct refund request",
    retrievedResponse.refundRequest.id,
    refundRequest.id,
  );
}
