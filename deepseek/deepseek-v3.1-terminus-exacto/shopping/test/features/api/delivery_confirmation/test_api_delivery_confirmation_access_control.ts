export async function test_api_delivery_confirmation_access_control(
  connection: api.IConnection,
): Promise<void> {
  // Create seller connection and authenticate
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "password123",
      shop_name: RandomGenerator.name(),
      shop_description: RandomGenerator.paragraph({ sentences: 2 }),
      logo_image_url: typia.random<string & tags.Format<"uri">>(),
      href: "https://example.com",
      referrer: "https://example.com",
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IEcommerceSeller.IJoin,
  });
  // Create product and variant for customer1's order
  const product = await generate_random_ecommerce_seller_products_create(
    sellerConnection,
    {
      body: {
        name: RandomGenerator.paragraph({ sentences: 2 }),
        description: RandomGenerator.paragraph({ sentences: 5 }),
        base_price: typia.random<
          number & tags.Type<"uint32"> & tags.Minimum<1000>
        >(),
        category_id: typia.random<string & tags.Format<"uuid">>(),
      } satisfies IEcommerceProduct.ICreate,
    },
  );
  typia.assert(product);
  const variant =
    await generate_random_ecommerce_seller_products_variants_create(
      sellerConnection,
      {
        body: {
          sku: RandomGenerator.alphaNumeric(10),
          option_values: '{"color": "red", "size": "M"}',
          price_override: null,
          quantity: typia.random<
            number & tags.Type<"int32"> & tags.Minimum<10>
          >(),
        } satisfies IEcommerceProductVariant.ICreate,
        params: { productId: product.id },
      },
    );
  typia.assert(variant);
  // Create first customer (customer1) and setup order flow
  const customer1Connection: api.IConnection = { host: connection.host };
  const customer1 = await authorize_customer_join(customer1Connection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "password123",
      display_name: RandomGenerator.name(),
      phone_number: RandomGenerator.mobile(),
    } satisfies IEcommerceCustomer.IJoin,
  });
  typia.assert(customer1);
  // Create cart items for customer1
  const cartItem = await generate_random_ecommerce_customer_carts_items_create(
    customer1Connection,
    {
      body: {
        product_variant_id: variant.id,
        quantity: typia.random<
          number & tags.Type<"int32"> & tags.Minimum<1> & tags.Maximum<5>
        >(),
      } satisfies IEcommerceCartItem.ICreate,
      params: { cartId: typia.random<string & tags.Format<"uuid">>() },
    },
  );
  typia.assert(cartItem);
  // Create order through checkout
  const order = await api.functional.ecommerce.customer.checkout.create(
    customer1Connection,
    {
      body: {
        page: 1,
        limit: 10,
        customer_id: customer1.id,
        created_after: new Date().toISOString(),
        created_before: null,
      } satisfies IEcommerceOrder.IRequest,
    },
  );
  typia.assert(order);
  // Create shipment for the order
  const shipment =
    await generate_random_ecommerce_seller_orders_shipments_create(
      sellerConnection,
      {
        body: {
          tracking_number: RandomGenerator.alphaNumeric(15),
          carrier_name: "Test Carrier",
          shipping_cost: typia.random<number & tags.Minimum<0>>(),
        } satisfies IEcommerceShipment.ICreate,
        params: { orderId: typia.random<string & tags.Format<"uuid">>() },
      },
    );
  typia.assert(shipment);
  // Create delivery confirmation for customer1
  const deliveryConfirmation =
    await api.functional.ecommerce.customer.shipments.delivery_confirmations.create(
      customer1Connection,
      {
        shipmentId: shipment.id,
      },
    );
  typia.assert(deliveryConfirmation);
  // Create second customer (customer2) who will attempt unauthorized access
  const customer2Connection: api.IConnection = { host: connection.host };
  const customer2 = await authorize_customer_join(customer2Connection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "password123",
      display_name: RandomGenerator.name(),
      phone_number: RandomGenerator.mobile(),
    } satisfies IEcommerceCustomer.IJoin,
  });
  typia.assert(customer2);
  // Attempt unauthorized access - customer2 trying to access customer1's delivery confirmation
  await TestValidator.error(
    "customer2 unauthorized access to customer1's delivery confirmation",
    async () => {
      await api.functional.ecommerce.customer.shipments.delivery_confirmations.at(
        customer2Connection,
        {
          shipmentId: shipment.id,
          confirmationId: deliveryConfirmation.id,
        },
      );
    },
  );
  // Verify customer1 can access their own delivery confirmation
  const accessibleConfirmation =
    await api.functional.ecommerce.customer.shipments.delivery_confirmations.at(
      customer1Connection,
      {
        shipmentId: shipment.id,
        confirmationId: deliveryConfirmation.id,
      },
    );
  typia.assert(accessibleConfirmation);
  TestValidator.equals(
    "delivery confirmation matches",
    accessibleConfirmation.id,
    deliveryConfirmation.id,
  );
}
