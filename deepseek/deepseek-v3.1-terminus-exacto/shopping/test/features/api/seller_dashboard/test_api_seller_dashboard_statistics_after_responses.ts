export async function test_api_seller_dashboard_statistics_after_responses(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create and authenticate seller
  const sellerConnection: api.IConnection = { host: connection.host };
  const seller = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      shop_name: RandomGenerator.name(),
      shop_description: RandomGenerator.paragraph({ sentences: 2 }),
      logo_image_url: typia.random<string & tags.Format<"uri">>(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IEcommerceSeller.IJoin,
  });
  typia.assert(seller);
  // 2. Create product for seller
  const product = await generate_random_ecommerce_seller_products_create(
    sellerConnection,
    {
      body: {
        name: RandomGenerator.paragraph({ sentences: 2 }),
        description: RandomGenerator.content({
          paragraphs: 1,
          sentenceMin: 3,
          sentenceMax: 5,
        }),
        base_price: typia.random<
          number & tags.Type<"uint32"> & tags.Minimum<1000>
        >(),
        category_id: typia.random<string & tags.Format<"uuid">>(),
      } satisfies IEcommerceProduct.ICreate,
    },
  );
  typia.assert(product);
  // 3. Create and authenticate customer
  const customerConnection: api.IConnection = { host: connection.host };
  const customer = await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name().substring(0, 50),
      phone_number: RandomGenerator.mobile(),
    } satisfies IEcommerceCustomer.IJoin,
  });
  typia.assert(customer);
  // 4. Customer creates pending cancellation request
  const cancellationRequest =
    await generate_random_ecommerce_customer_cancellation_requests_create(
      customerConnection,
      {
        body: {
          ecommerce_order_item_id: typia.random<string & tags.Format<"uuid">>(),
          reason: RandomGenerator.content({
            paragraphs: 1,
            sentenceMin: 1,
            sentenceMax: 2,
          }),
        } satisfies IEcommerceCancellationRequest.ICreate,
      },
    );
  typia.assert(cancellationRequest);
  // 5. Customer creates pending refund request
  const refundRequest =
    await generate_random_ecommerce_customer_refund_requests_create(
      customerConnection,
      {
        body: {
          orderItemId: typia.random<string & tags.Format<"uuid">>(),
          reason: RandomGenerator.content({
            paragraphs: 1,
            sentenceMin: 1,
            sentenceMax: 2,
          }),
        } satisfies IEcommerceRefundRequest.ICreate,
      },
    );
  typia.assert(refundRequest);
  // 6. Initial dashboard check
  const initialDashboard =
    await api.functional.ecommerce.seller.dashboard(sellerConnection);
  typia.assert(initialDashboard);
  // 7. Seller responds to cancellation request
  const cancellationResponse =
    await api.functional.ecommerce.seller.cancellation_requests.responses.create(
      sellerConnection,
      {
        cancellationRequestId: cancellationRequest.id,
        body: {
          decision: "approved",
          response_reason: RandomGenerator.content({
            paragraphs: 1,
            sentenceMin: 1,
            sentenceMax: 2,
          }),
        } satisfies IEcommerceCancellationResponseRecord.ICreate,
      },
    );
  typia.assert(cancellationResponse);
  // 8. Seller responds to refund request - FIXED: Use correct type
  // Looking at the API definition, refund response creation expects IEcommerceRefundRequest.IResponse
  // But the properties should be appropriate for creating a response
  const refundResponse =
    await api.functional.ecommerce.seller.refund_requests.responses.create(
      sellerConnection,
      {
        refundRequestId: refundRequest.id,
        body: {
          // Using minimal required properties for response creation
          id: refundRequest.id,
          reason: "Seller approved refund request",
          requested_at: refundRequest.requested_at,
          refund_window_expires_at: refundRequest.refund_window_expires_at,
          customer: refundRequest.customer,
          seller: refundRequest.seller,
          order_item: refundRequest.orderItem,
          created_at: new Date().toISOString(),
          updated_at: new Date().toISOString(),
        } satisfies IEcommerceRefundRequest.IResponse,
      },
    );
  typia.assert(refundResponse);
  // 9. Final dashboard check
  const finalDashboard =
    await api.functional.ecommerce.seller.dashboard(sellerConnection);
  typia.assert(finalDashboard);
  // 10. Basic validation
  TestValidator.predicate(
    "dashboard statistics should be available after responses",
    true,
  );
}
