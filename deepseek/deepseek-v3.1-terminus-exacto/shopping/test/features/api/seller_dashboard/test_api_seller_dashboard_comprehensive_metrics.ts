/**
 * Test comprehensive seller dashboard metrics including product count, active order items,
 * pending cancellation requests, and pending refund requests with data isolation.
 */
export async function test_api_seller_dashboard_comprehensive_metrics(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create and authenticate seller
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "password123",
      shop_name: RandomGenerator.name(),
      shop_description: RandomGenerator.paragraph({ sentences: 2 }),
      logo_image_url: typia.random<string & tags.Format<"uri">>(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IEcommerceSeller.IJoin,
  });
  typia.assert(sellerAuth);
  // 2. Create multiple products for the seller
  const product1 = await generate_random_ecommerce_seller_products_create(
    sellerConnection,
    {
      body: {
        name: RandomGenerator.paragraph({
          sentences: 2,
          wordMin: 2,
          wordMax: 4,
        }),
        description: RandomGenerator.content({
          paragraphs: 1,
          sentenceMin: 3,
          sentenceMax: 5,
        }),
        base_price: typia.random<
          number & tags.Minimum<1000> & tags.Maximum<50000>
        >(),
        category_id: typia.random<string & tags.Format<"uuid">>(),
      } satisfies IEcommerceProduct.ICreate,
    },
  );
  typia.assert(product1);
  const product2 = await generate_random_ecommerce_seller_products_create(
    sellerConnection,
    {
      body: {
        name: RandomGenerator.paragraph({
          sentences: 2,
          wordMin: 2,
          wordMax: 4,
        }),
        description: RandomGenerator.content({
          paragraphs: 1,
          sentenceMin: 3,
          sentenceMax: 5,
        }),
        base_price: typia.random<
          number & tags.Minimum<1000> & tags.Maximum<50000>
        >(),
        category_id: typia.random<string & tags.Format<"uuid">>(),
      } satisfies IEcommerceProduct.ICreate,
    },
  );
  typia.assert(product2);
  // 3. Create and authenticate customer
  const customerConnection: api.IConnection = { host: connection.host };
  const customerAuth = await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "password123",
      display_name: RandomGenerator.name(),
      phone_number: RandomGenerator.mobile(),
    } satisfies IEcommerceCustomer.IJoin,
  });
  typia.assert(customerAuth);
  // 4. Create dashboard metrics (wait for actual dashboard endpoint implementation)
  // Note: Currently dashboard endpoint returns IEcommerceSeller instead of metrics
  // This will be updated when proper dashboard DTO is implemented
  const dashboard =
    await api.functional.ecommerce.seller.dashboard(sellerConnection);
  typia.assert(dashboard);
  // 5. Validate seller identity (basic data isolation test)
  TestValidator.equals(
    "seller should access their own dashboard",
    dashboard.id,
    sellerAuth.id,
  );
  // Note: Additional validation will be added when dashboard metrics are properly implemented
  // Currently, the dashboard endpoint returns seller profile instead of metrics
}
