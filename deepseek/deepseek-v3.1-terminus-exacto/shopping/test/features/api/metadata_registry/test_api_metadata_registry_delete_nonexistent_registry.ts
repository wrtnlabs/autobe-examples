export async function test_api_metadata_registry_delete_nonexistent_registry(
  connection: api.IConnection,
): Promise<void> {
  // Create administrator connection
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_administrator_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IEcommerceAdministrator.IJoin,
  });
  // Generate random UUID that doesn't exist
  const nonexistentRegistryId = typia.random<string & tags.Format<"uuid">>();
  // Attempt to delete non-existent registry and verify specific 404 NotFound error
  await TestValidator.httpError(
    "delete non-existent registry",
    404,
    async () => {
      await api.functional.ecommerce.administrator.metadata_registries.erase(
        adminConnection,
        {
          registryId: nonexistentRegistryId,
        },
      );
    },
  );
}
