export async function test_api_metadata_registry_deletion_success(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create super administrator connection
  const superAdminConnection: api.IConnection = { host: connection.host };
  await authorize_super_administrator_join(superAdminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IEcommerceSuperAdministrator.IJoin,
  });
  // 2. Create metadata registry entry to delete
  const registry =
    await generate_random_ecommerce_super_administrator_metadata_registries_create(
      superAdminConnection,
      {
        body: {
          schema_name: RandomGenerator.paragraph({ sentences: 1 }),
          schema_version: "1.0.0",
          description: RandomGenerator.paragraph({ sentences: 2 }),
          is_active: true,
        } satisfies IEcommerceMetadataRegistry.ICreate,
      },
    );
  typia.assert(registry);
  // 3. Execute deletion operation and validate success
  await TestValidator.predicate(
    "deletion should succeed without error",
    async () => {
      await api.functional.ecommerce.superAdministrator.metadata_registries.erase(
        superAdminConnection,
        {
          registryId: registry.id,
        },
      );
      return true; // If no error thrown, deletion succeeded
    },
  );
  // 4. Verify deletion by attempting to delete again (should fail with 404)
  await TestValidator.error(
    "registry should not exist after deletion",
    async () => {
      await api.functional.ecommerce.superAdministrator.metadata_registries.erase(
        superAdminConnection,
        {
          registryId: registry.id,
        },
      );
    },
  );
}
