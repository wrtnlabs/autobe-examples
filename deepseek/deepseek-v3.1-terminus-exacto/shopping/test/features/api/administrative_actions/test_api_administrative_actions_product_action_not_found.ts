export async function test_api_administrative_actions_product_action_not_found(
  connection: api.IConnection,
): Promise<void> {
  // 1. Administrator authentication
  const adminConnection: api.IConnection = { host: connection.host };
  const adminAuth = await authorize_administrator_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "TempPass123!",
    },
  });
  typia.assert(adminAuth);
  // 2. Create parent administrative action
  const adminAction =
    await generate_random_ecommerce_administrator_administrative_actions_create(
      adminConnection,
      {},
    );
  typia.assert(adminAction);
  // 3. Generate random product action ID that does not exist
  const nonExistentProductActionId = typia.random<
    string & tags.Format<"uuid">
  >();
  // 4. Attempt to retrieve non-existent product action
  await TestValidator.httpError(
    "product action not found",
    404,
    async () =>
      await api.functional.ecommerce.administrator.administrative_actions.product_actions.at(
        adminConnection,
        {
          administrativeActionId: adminAction.id,
          productActionId: nonExistentProductActionId,
        },
      ),
  );
}
