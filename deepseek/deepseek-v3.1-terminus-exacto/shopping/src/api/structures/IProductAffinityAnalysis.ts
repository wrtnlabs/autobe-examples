import { tags } from "typia";

import { ITimePeriod } from "./ITimePeriod";
import { IShoppingMallProductCategory } from "./IShoppingMallProductCategory";
import { IShoppingMallProductBundleSummary } from "./IShoppingMallProductBundleSummary";
import { IShoppingMallCrossSellRecommendationSummary } from "./IShoppingMallCrossSellRecommendationSummary";
import { IShoppingMallProductAffinityScoreSummary } from "./IShoppingMallProductAffinityScoreSummary";

/**
 * Product preference patterns and cross-selling opportunities identified
 * through customer behavior.
 *
 * This schema analyzes how customers interact with products, including their
 * preferences, browsing patterns, and purchase combinations. Product affinity
 * analysis helps identify relationships between products and customer
 * preferences.
 *
 * The analysis supports personalized recommendations, product bundling
 * strategies, and inventory optimization based on customer behavior patterns
 * and product relationships.
 *
 * Used for analytics dashboards, marketing campaign planning, and product
 * recommendation engines. Provides insights into customer purchasing behavior
 * and product relationship patterns across different customer segments and time
 * periods.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type IProductAffinityAnalysis = {
  /**
   * Unique identifier for this specific affinity analysis instance. Generated
   * automatically when the analysis is created and used for tracking and
   * referencing specific analysis runs.
   */
  analysisId: string & tags.Format<"uuid">;

  /**
   * Time period covered by this affinity analysis. Defines the date range for
   * which customer behavior data was analyzed to generate these insights.
   */
  period: ITimePeriod;

  /**
   * Specific customer segment targeted by this analysis. Can be based on
   * demographics, purchasing behavior, or other segmentation criteria
   * relevant to the shopping mall platform.
   */
  customerSegment: string;

  /**
   * Most popular product categories based on customer preferences within the
   * analyzed period. Categories are ranked by customer engagement metrics
   * including views, cart additions, and purchases.
   */
  topProductCategories: IShoppingMallProductCategory[];

  /**
   * Identified opportunities for product bundling based on purchase patterns.
   * Bundles are suggested when products are frequently purchased together by
   * the same customers.
   */
  productBundleOpportunities: IShoppingMallProductBundleSummary[];

  /**
   * Recommended cross-selling opportunities between products. These
   * recommendations identify products that customers who bought item A are
   * likely to also purchase item B.
   */
  crossSellRecommendations: IShoppingMallCrossSellRecommendationSummary[];

  /**
   * Affinity scores between different product categories and items. Scores
   * range from 0 to 1, with higher values indicating stronger relationships
   * between products based on customer behavior patterns.
   */
  affinityScores: IShoppingMallProductAffinityScoreSummary[];
};
