/**
 * Key indicator that predicts potential customer churn based on behavioral,
 * demographic, engagement, or purchase patterns.
 *
 * Churn indicators are statistical models that identify customers at risk of
 * leaving the platform based on specific metrics and thresholds. These
 * indicators enable proactive retention efforts by flagging customers who
 * exhibit behaviors correlated with churn.
 *
 * Each indicator includes the specific metric type, threshold values that
 * signal risk, and the predictive strength calculated through statistical
 * analysis. Indicators are used in customer analytics dashboards and automated
 * retention workflows.
 *
 * The schema supports multiple metric types including behavioral patterns,
 * demographic characteristics, engagement levels, and purchase history to
 * provide comprehensive churn prediction capabilities.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type IChurnIndicator = {
  /**
   * Unique name identifying the churn prediction indicator for reference and
   * tracking purposes. Must be descriptive enough to convey the specific
   * metric being measured, such as 'login_frequency_decline' or
   * 'purchase_value_drop'.
   *
   * Used in analytics dashboards and reporting systems to identify which
   * specific indicators are triggering churn alerts.
   */
  indicator_name: string;

  /**
   * Categorical classification of the metric type used for churn prediction,
   * determining how the indicator data is collected and analyzed.
   *
   * Each metric type requires different data sources and analysis methods,
   * with behavioral metrics focusing on usage patterns and demographic
   * metrics leveraging customer profile information.
   */
  metric_type: "behavioral" | "demographic" | "engagement" | "purchase";

  /**
   * Numerical threshold value that indicates elevated churn risk when
   * exceeded or unmet, depending on the indicator direction.
   *
   * For example, a login frequency indicator might trigger at less than 2
   * logins per week, while a purchase value indicator might trigger at
   * spending below $50 per month.
   *
   * Threshold values are calibrated through historical data analysis to
   * balance detection sensitivity with false positive rates.
   */
  risk_threshold: number;

  /**
   * Statistical measure indicating how strongly this indicator correlates
   * with actual churn events, typically expressed as a value between 0 and
   * 1.
   *
   * Values closer to 1 indicate stronger predictive power, while values near
   * 0 suggest weak correlation. This metric helps prioritize which indicators
   * to focus on for retention efforts.
   *
   * Calculated through regression analysis or machine learning models using
   * historical customer data.
   */
  predictive_strength: number;
};
