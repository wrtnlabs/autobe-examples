import { IValueRange } from "./IValueRange";

/**
 * Customer segmentation criterion defining rules for grouping customers based
 * on specific attributes and behaviors.
 *
 * This schema represents a single segmentation rule used in customer analytics
 * and marketing campaigns. Each criterion specifies which customer attribute to
 * evaluate, what comparison operator to apply, and the target value or range
 * for segmentation.
 *
 * Segmentation criteria enable sophisticated customer grouping for targeted
 * marketing, personalized experiences, and behavioral analysis. Multiple
 * criteria can be combined using AND/OR logic to create complex customer
 * segments that reflect real-world purchasing patterns and preferences.
 *
 * Common use cases include segmenting customers by demographic attributes (age,
 * location), purchasing behavior (frequency, average spend), loyalty status,
 * product preferences, and engagement levels. The system validates that
 * operators are compatible with attribute types (e.g., numeric operators for
 * quantitative attributes).
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type ISegmentationCriterion = {
  /**
   * Customer attribute used for segmentation. Determines which customer
   * characteristic will be evaluated for grouping purposes.
   */
  attribute:
    | "age_range"
    | "purchase_frequency"
    | "average_order_value"
    | "customer_status"
    | "preferred_category";

  /**
   * Comparison operator defining how the attribute value will be evaluated
   * against the target criteria.
   */
  operator: "equals" | "greater_than" | "less_than" | "between" | "in";

  /**
   * Target value for segmentation comparison. The specific value that
   * customer attributes will be evaluated against using the defined
   * operator.
   *
   * For numeric operators (greater_than, less_than), the value should be a
   * numeric string. For categorical operators (equals, in), the value should
   * match valid category values. For the 'between' operator, this field may
   * be ignored in favor of the value_range property.
   */
  value: string;

  /**
   * Numeric range specification used exclusively with the 'between' operator.
   * Defines the inclusive minimum and maximum values for range-based
   * segmentation.
   *
   * Required when operator is 'between', optional for all other operators.
   * The range defines the boundaries within which customer attribute values
   * must fall to satisfy the segmentation criterion.
   */
  value_range?: IValueRange | undefined;
};
