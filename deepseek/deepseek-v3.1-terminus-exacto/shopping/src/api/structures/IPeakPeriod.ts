import { tags } from "typia";

/**
 * Detailed analysis of identified peak ordering periods with comprehensive
 * volume metrics.
 *
 * Represents specific timeframes when order activity significantly exceeds
 * average levels, providing insights into high-demand periods for business
 * optimization.
 *
 * Peak periods are identified through statistical analysis of historical order
 * data and help businesses prepare for increased demand through proper
 * inventory management, staffing adjustments, and targeted marketing
 * campaigns.
 *
 * Each peak period analysis includes timing information, volume multipliers,
 * and contextual data that supports operational planning and strategic
 * decision-making.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type IPeakPeriod = {
  /**
   * Start date of the identified peak period.
   *
   * Indicates when the elevated order activity begins, allowing businesses to
   * prepare resources and inventory in advance of the peak demand period.
   */
  period_start: string & tags.Format<"date">;

  /**
   * End date of the identified peak period.
   *
   * Marks the conclusion of the elevated order activity, helping businesses
   * transition back to normal operations and analyze post-peak performance.
   */
  period_end: string & tags.Format<"date">;

  /**
   * Multiplier indicating how much higher order volume is compared to the
   * baseline average.
   *
   * For example, a factor of 2.5 indicates order volume is 2.5 times higher
   * than the typical average during this period. This metric helps quantify
   * the intensity of the peak period.
   *
   * Used for capacity planning and resource allocation to ensure adequate
   * support during high-demand periods.
   */
  order_volume_factor: number;

  /**
   * Categorical classification of peak intensity based on volume factor and
   * duration.
   *
   * Provides a quick reference for understanding the significance of the peak
   * period without requiring detailed numerical analysis.
   *
   * - Low: Minor increase (1.5-2x average)
   * - Medium: Moderate increase (2-3x average)
   * - High: Significant increase (3-5x average)
   * - Extreme: Major spike (5x+ average)
   */
  peak_intensity: "low" | "medium" | "high" | "extreme";

  /**
   * Indicates whether this peak period follows a recurring pattern.
   *
   * True if the peak occurs regularly (e.g., annual holiday season, monthly
   * promotions). False for one-time or irregular peaks.
   *
   * Helps businesses anticipate and prepare for predictable high-demand
   * periods through historical pattern recognition.
   */
  recurring_pattern: boolean;
};
