import { tags } from "typia";

/**
 * Detailed statistical breakdown for specific time periods enabling
 * comprehensive trend analysis and period-to-period performance comparisons.
 *
 * This schema provides the foundational structure for temporal analysis of
 * shopping mall order data, allowing administrators to track performance across
 * different time dimensions from daily operational metrics to annual strategic
 * indicators.
 *
 * The time period specification ensures consistent data aggregation and enables
 * meaningful comparisons between equivalent periods (e.g., month-over-month,
 * year-over-year). This temporal framework is essential for identifying
 * seasonal patterns, growth trends, and the impact of time-specific events or
 * promotions.
 *
 * Used in reporting dashboards, analytics tools, and business intelligence
 * systems to support data-driven decision making. The period-based approach
 * facilitates performance benchmarking, goal tracking, and the identification
 * of opportunities for improvement based on temporal performance patterns.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type IOrderStatisticsTimePeriod = {
  /**
   * Inclusive start date of the statistical reporting period in ISO 8601
   * format (YYYY-MM-DD). Defines the beginning boundary for data aggregation
   * and metric calculation.
   *
   * Must be a valid calendar date that aligns with the period_type
   * granularity. For daily periods, represents the specific day; for weekly
   * periods, the Monday of the week; for monthly periods, the first day of
   * the month.
   */
  period_start: string & tags.Format<"date">;

  /**
   * Inclusive end date of the statistical reporting period in ISO 8601 format
   * (YYYY-MM-DD). Marks the termination boundary for data aggregation within
   * the specified timeframe.
   *
   * Ensures consistent period definitions for comparative analysis. The
   * period spans from period_start through period_end inclusively, covering
   * the entire duration specified by the period_type.
   */
  period_end: string & tags.Format<"date">;

  /**
   * Temporal grouping dimension that determines the aggregation level and
   * reporting granularity for statistical analysis.
   *
   * Defines how order data is grouped and summarized for trend analysis.
   * Different period types serve distinct analytical purposes from daily
   * operational monitoring to annual strategic planning.
   *
   * The selection impacts data granularity, with shorter periods providing
   * more detailed insights into daily fluctuations while longer periods
   * smooth out noise for trend identification.
   */
  period_type: "day" | "week" | "month" | "quarter" | "year";

  /**
   * Total number of orders successfully processed within the specific time
   * period. Provides the volume metric for the defined aggregation window.
   *
   * Enables period-to-period comparison and trend analysis. Combined with
   * period_type, helps identify seasonal patterns, promotional effectiveness,
   * and business cycle fluctuations.
   */
  order_count: number & tags.Type<"int32">;

  /**
   * Cumulative revenue generated from all orders within the period.
   * Represents the financial performance metric for the specific timeframe.
   *
   * Critical for revenue trend analysis, growth rate calculation, and
   * period-specific financial performance assessment. Used to measure the
   * effectiveness of time-bound marketing campaigns or seasonal promotions.
   */
  total_revenue: number;

  /**
   * Mean order value calculated specifically for the period by dividing
   * period revenue by period order count. Provides period-specific spending
   * pattern insights.
   *
   * Helps identify whether order values fluctuate by time of week, season, or
   * specific events. Higher values during certain periods may indicate
   * successful premium product promotions or seasonal buying patterns.
   */
  average_order_value: number;
};
