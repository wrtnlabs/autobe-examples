import { tags } from "typia";

import { IDeviceUsage } from "./IDeviceUsage";

/**
 * Comprehensive customer engagement metrics tracking platform interaction
 * patterns and conversion behaviors.
 *
 * This schema captures detailed analytics on how customers engage with the
 * shopping platform, including browsing duration, page navigation patterns,
 * cart management behaviors, and purchase conversion rates. Engagement metrics
 * provide crucial insights into customer interest levels, platform usability
 * effectiveness, and opportunities for optimizing the user experience journey.
 *
 * The metrics analyze customer journey effectiveness from initial product
 * discovery through final purchase conversion, helping identify friction points
 * and optimization opportunities. Platform navigation patterns reveal how
 * customers explore product categories and interact with search and filtering
 * features.
 *
 * Used primarily in analytics reporting and dashboard displays to monitor
 * platform performance and customer engagement trends over time. These metrics
 * help inform UX improvements, feature prioritization, and conversion rate
 * optimization strategies.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type IEngagementMetrics = {
  /**
   * Average duration of customer sessions measured in minutes. Higher values
   * indicate stronger engagement and platform stickiness. This metric helps
   * identify content quality and user experience effectiveness.
   *
   * Sessions are tracked from initial platform access until user inactivity
   * timeout. Values typically range from 2-15 minutes depending on platform
   * complexity and customer engagement levels.
   */
  average_session_duration: number & tags.Minimum<0>;

  /**
   * Average number of distinct pages viewed during customer sessions. Higher
   * values indicate effective content discovery and navigation patterns.
   *
   * This metric reflects how well customers explore the platform and discover
   * relevant products. Values help optimize information architecture and
   * navigation flow design.
   */
  pages_per_session: number & tags.Minimum<0>;

  /**
   * Percentage of shopping carts created that are abandoned before completing
   * purchase. Lower values indicate better conversion funnel effectiveness.
   *
   * Cart abandonment analysis helps identify friction points in the checkout
   * process, pricing concerns, or shipping issues that prevent final
   * conversion.
   */
  cart_abandonment_rate: number & tags.Minimum<0> & tags.Maximum<100>;

  /**
   * Conversion rate measuring the percentage of product views that result in
   * purchases. This metric evaluates product presentation effectiveness and
   * customer decision-making patterns.
   *
   * Higher conversion rates indicate compelling product information,
   * effective pricing strategies, and smooth purchase pathways. Values help
   * optimize product pages and recommendation algorithms.
   */
  product_view_to_purchase_rate: number & tags.Minimum<0> & tags.Maximum<100>;

  /**
   * Percentage of customers who return to the platform after their initial
   * visit. This metric measures platform stickiness and customer loyalty
   * development.
   *
   * Higher return rates indicate successful customer retention strategies,
   * valuable content, and positive user experiences that encourage repeat
   * engagement.
   */
  return_visitor_rate: number & tags.Minimum<0> & tags.Maximum<100>;

  /**
   * Detailed breakdown of platform access patterns across different device
   * types. This analysis helps optimize user experience for specific device
   * categories and prioritize development efforts.
   *
   * Understanding device preferences enables targeted optimization for mobile
   * responsiveness, desktop feature richness, and tablet interface
   * compatibility.
   */
  mobile_vs_desktop_usage?: IDeviceUsage | undefined;
};
