import { tags } from "typia";

/**
 * Time period specification for analytics reporting and data filtering.
 *
 * This schema defines the time range for analytics reports, supporting various
 * period types including fixed ranges, relative periods, and custom date
 * ranges. The time period specification ensures consistent time-based analysis
 * across different reports.
 *
 * The schema supports both predefined periods (like last 30 days, last quarter)
 * and custom date ranges for flexible analytics generation based on specific
 * business needs.
 *
 * Validation rules ensure that custom periods have valid date ranges and that
 * start dates precede end dates. Predefined periods automatically calculate the
 * appropriate date ranges based on the current date.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type ITimePeriod = {
  /**
   * Type of time period for analysis. Determines how the date range is
   * calculated and whether custom dates are required.
   */
  periodType:
    | "custom"
    | "last_7_days"
    | "last_30_days"
    | "last_quarter"
    | "last_year";

  /**
   * Start date for custom period analysis. Required when periodType is
   * 'custom'. Must be a valid date in ISO 8601 format (YYYY-MM-DD).
   */
  startDate?: (string & tags.Format<"date">) | undefined;

  /**
   * End date for custom period analysis. Required when periodType is
   * 'custom'. Must be a valid date in ISO 8601 format (YYYY-MM-DD) and must
   * be equal to or after the start date.
   */
  endDate?: (string & tags.Format<"date">) | undefined;
};
