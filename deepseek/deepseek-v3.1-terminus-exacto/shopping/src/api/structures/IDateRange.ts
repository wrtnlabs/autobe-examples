import { tags } from "typia";

/**
 * Date range specification for filtering search results and analytics data by
 * time periods.
 *
 * Defines flexible start and end dates for filtering entities based on creation
 * timestamps, modification dates, or transaction timestamps. Both start and end
 * dates are optional, allowing for various time-based query scenarios including
 * recent data analysis, historical comparisons, and specific period
 * evaluations.
 *
 * When both start and end dates are specified, the filter matches entities with
 * dates falling within the inclusive range [start, end]. When only start is
 * specified, matches entities with dates after or equal to start (no upper
 * bound). When only end is specified, matches entities with dates before or
 * equal to end (no lower bound). When neither is specified, all available data
 * is included in the analysis.
 *
 * The date range functionality supports various business use cases including
 * monthly performance reviews, seasonal trend analysis, year-over-year
 * comparisons, and custom period evaluations. The flexible design accommodates
 * different reporting requirements and analytical needs across the shopping
 * mall platform.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type IDateRange = {
  /**
   * Start date for the range filter in ISO 8601 format.
   *
   * Optional parameter that defines the beginning of the time period for
   * analysis. When specified, only entities with dates on or after this
   * timestamp are included in the results.
   *
   * Use cases include analyzing data from a specific launch date, evaluating
   * performance since a marketing campaign began, or focusing on recent
   * periods by setting a start date without an end date.
   */
  start?: (string & tags.Format<"date-time">) | undefined;

  /**
   * End date for the range filter in ISO 8601 format.
   *
   * Optional parameter that defines the conclusion of the time period for
   * analysis. When specified, only entities with dates on or before this
   * timestamp are included in the results.
   *
   * Use cases include analyzing historical data up to a specific point,
   * evaluating performance before a system change, or focusing on past
   * periods by setting an end date without a start date.
   */
  end?: (string & tags.Format<"date-time">) | undefined;
};
