/**
 * Registration endpoint for creating new super administrator accounts with email and password authentication.
 *
 * This operation allows system administrators to create new super administrator accounts with the highest level of platform privileges. The endpoint validates the email address format and ensures uniqueness across all super administrator accounts. Password strength requirements are enforced according to platform security policies.
 *
 * Upon successful registration, the system automatically creates an initial authentication session and returns JWT tokens for immediate platform access. The operation follows secure password hashing practices and maintains audit trails for account creation events.
 *
 * Super administrator accounts require email verification and maintain the highest security standards for platform administration. This endpoint is typically used during initial platform setup or when expanding administrative team members.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Registration credentials for new super administrator account
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor superAdministrator
 * @x-autobe-specification The join operation creates a new super administrator account with email and password. It validates email uniqueness, hashes the password securely, creates the account record, and returns authentication tokens. This operation should include email format validation, password strength requirements, and automatic session creation upon successful registration.
 * @path /ecommerce/auth/superAdministrator/join
 * @accessor api.functional.ecommerce.auth.superAdministrator.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
