/**
 * This endpoint allows registration of new administrator accounts on the e-commerce platform. Administrators require elevated privileges for platform management and oversight capabilities.
 *
 * When an administrator registers, the system validates the email format and ensures uniqueness across all administrator accounts. The password undergoes complexity validation before being securely hashed using industry-standard algorithms. Upon successful registration, the system creates the administrator record with timestamps and returns JWT tokens for immediate authentication.
 *
 * Administrator accounts are distinct from customer and seller accounts in the multi-actor ecosystem, requiring separate authentication flows and session management. This endpoint provides the foundation for administrative access to platform management features.
 *
 * The implementation includes comprehensive error handling for duplicate emails, invalid password formats, and system-level failures. Successful registration enables immediate access to administrative dashboard features and system configuration tools.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Registration information for new administrator account
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor administrator
 * @x-autobe-specification The join operation creates a new administrator account with email and password validation. It checks email uniqueness against existing administrators, validates password strength requirements, securely hashes the password, creates the administrator record, and returns authentication tokens. The implementation must ensure email format validation and enforce password complexity rules before account creation.
 * @path /ecommerce/auth/administrator/join
 * @accessor api.functional.ecommerce.auth.administrator.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
