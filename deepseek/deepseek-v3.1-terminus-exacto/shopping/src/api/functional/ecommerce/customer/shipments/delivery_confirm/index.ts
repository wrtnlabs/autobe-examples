import { HttpError, IConnection } from "@nestia/fetcher";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";

import { IEcommerceDeliveryConfirmation } from "../../../../../structures/IEcommerceDeliveryConfirmation";

/**
 * Customer delivery confirmation endpoint that marks a shipment and all its contained order items as delivered.
 *
 * This operation allows customers to manually confirm receipt of shipment packages containing their purchased items. When a customer confirms delivery, the system creates an immutable delivery confirmation record, updates the shipment status to 'delivered', and changes the status of all order items within that shipment to 'delivered'. This confirmation triggers order fulfillment completion and makes the purchased products eligible for customer reviews.
 *
 * Delivery confirmations serve as audit trail evidence for dispute resolution and provide legal verification that customers received their purchased items. The system also automatically confirms deliveries after 14 days if customers don't manually confirm, but manual confirmation allows for immediate status updates.
 *
 * Customers can only confirm delivery of shipments that contain their order items. The operation validates shipment ownership before processing the confirmation to prevent unauthorized access to other customers' shipment data.
 *
 * @param props.connection
 * @param props.shipmentId UUID of the shipment to confirm delivery for
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor customer
 * @x-autobe-specification First validate that the authenticated customer has permission to confirm this shipment by checking if any of their order items are included in this shipment. Then create a delivery confirmation record linking the shipment to the customer with current timestamp. Update the shipment status to 'delivered' and set delivered_at timestamp. Update all order items within this shipment to 'delivered' status. Return the created delivery confirmation record with populated relationship data.
 * @path /ecommerce/customer/shipments/:shipmentId/delivery-confirm
 * @accessor api.functional.ecommerce.customer.shipments.delivery_confirm.deliveryConfirm
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function deliveryConfirm(
  connection: IConnection,
  props: deliveryConfirm.Props,
): Promise<deliveryConfirm.Response> {
  return true === connection.simulate
    ? deliveryConfirm.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...deliveryConfirm.METADATA,
          path: deliveryConfirm.path(props),
          status: null,
        },
      );
}
export namespace deliveryConfirm {
  export type Props = {
    /**
     * UUID of the shipment to confirm delivery for
     */
    shipmentId: string & tags.Format<"uuid">;
  };
  export type Response = IEcommerceDeliveryConfirmation;

  export const METADATA = {
    method: "POST",
    path: "/ecommerce/customer/shipments/:shipmentId/delivery-confirm",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/ecommerce/customer/shipments/${encodeURIComponent(props.shipmentId ?? "null")}/delivery-confirm`;
  export const random = (): IEcommerceDeliveryConfirmation =>
    typia.random<IEcommerceDeliveryConfirmation>();
  export const simulate = (
    connection: IConnection,
    props: deliveryConfirm.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: deliveryConfirm.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("shipmentId")(() => typia.assert(props.shipmentId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
