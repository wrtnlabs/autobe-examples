/**
 * Permanently delete a specific shipment associated with an order from the
 * shopping mall platform.
 *
 * This operation removes a shipment record completely from the database,
 * including all tracking information, carrier details, and delivery status. The
 * deletion is permanent and irreversible, removing the shipment from both the
 * Orders table relationship and the Shipments table itself.
 *
 * The operation validates that the specified shipment belongs to the specified
 * order before proceeding with deletion. This ensures referential integrity and
 * prevents accidental deletion of unrelated shipments. The system performs a
 * hard delete operation, completely removing the record rather than marking it
 * as deleted.
 *
 * Security considerations include verifying that the requesting user has
 * appropriate permissions to manage shipments for the specified order. The
 * operation should only be accessible to users with administrative privileges
 * or order management capabilities. Rate limiting applies to prevent abuse of
 * the deletion functionality.
 *
 * Related operations: View shipment details (GET
 * /orders/{orderId}/shipments/{shipmentId}), List shipments for order (PATCH
 * /orders/{orderId}/shipments).
 *
 * @param props.connection
 * @param props.orderId Unique identifier of the target order containing the
 *   shipment
 * @param props.shipmentId Unique identifier of the target shipment to be
 *   deleted
 * @path /shoppingMall/orders/:orderId/shipments/:shipmentId
 * @accessor api.functional.shoppingMall.orders.shipments.erase
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function erase(
  connection: IConnection,
  props: erase.Props,
): Promise<void> {
  return true === connection.simulate
    ? erase.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...erase.METADATA,
          path: erase.path(props),
          status: null,
        },
      );
}
