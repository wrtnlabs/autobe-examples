/**
 * Retrieve a filtered and paginated list of shopping mall channels from the
 * system. This operation operates on the shopping_mall_channels table from the
 * Prisma schema and provides advanced search capabilities for finding channels
 * based on multiple criteria including channel code, name, status, and creation
 * date ranges.
 *
 * The operation supports comprehensive pagination with configurable page sizes
 * and sorting options. Channels can be sorted by creation date, update date,
 * channel name, or status in ascending or descending order. The search
 * functionality allows filtering by channel status (active, inactive,
 * maintenance, planned) and partial matching on channel names and
 * descriptions.
 *
 * Security considerations include appropriate filtering based on the requesting
 * user's authorization level. Channel visibility may be restricted based on
 * platform configuration and user permissions. The operation integrates with
 * the shopping_mall_channels table as defined in the Prisma schema,
 * incorporating all available channel fields and relationships.
 *
 * The response includes channel summary information optimized for list
 * displays, with options to include additional details based on authorization
 * level. This endpoint is essential for platform administrators managing
 * channel configurations and for customers browsing available shopping
 * channels.
 *
 * @param props.connection
 * @param props.body Search criteria and pagination parameters for channel
 *   filtering
 * @path /shoppingMall/channels
 * @accessor api.functional.shoppingMall.channels.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /** Search criteria and pagination parameters for channel filtering */
    body: IShoppingMallChannel.IRequest;
  };
  export type Body = IShoppingMallChannel.IRequest;
  export type Response = IPageIShoppingMallChannel.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/channels",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/shoppingMall/channels";
  export const random = (): IPageIShoppingMallChannel.ISummary =>
    typia.random<IPageIShoppingMallChannel.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

