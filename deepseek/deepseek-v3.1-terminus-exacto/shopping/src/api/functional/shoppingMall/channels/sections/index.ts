import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallSection } from "../../../../structures/IShoppingMallSection";

/**
 * Retrieve detailed information about a specific shopping mall section within a
 * designated channel.
 *
 * This operation returns the complete configuration and metadata for a shopping
 * mall section, including its display properties, organizational hierarchy, and
 * operational status. The section is uniquely identified by the combination of
 * channel code and section code, ensuring precise targeting within the
 * hierarchical structure of the shopping mall platform.
 *
 * Security considerations include validating that the requesting user has
 * appropriate permissions to view the section details based on their role and
 * the section's visibility settings. The operation performs validation checks
 * to ensure both the channel and section exist and are accessible before
 * returning the detailed information.
 *
 * This endpoint integrates with the shopping_mall_sections table from the
 * Prisma schema, providing access to all section attributes including
 * hierarchical relationships, display ordering, and configuration settings. The
 * response includes comprehensive section data for use in administrative
 * interfaces and customer-facing applications.
 *
 * @param props.connection
 * @param props.channelCode Unique business identifier code of the target
 *   shopping channel (global scope)
 * @param props.sectionCode Unique business identifier code of the target
 *   section within the channel (scoped to channel)
 * @path /shoppingMall/channels/:channelCode/sections/:sectionCode
 * @accessor api.functional.shoppingMall.channels.sections.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique business identifier code of the target shopping channel
     * (global scope)
     */
    channelCode: string;

    /**
     * Unique business identifier code of the target section within the
     * channel (scoped to channel)
     */
    sectionCode: string;
  };
  export type Response = IShoppingMallSection;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/channels/:channelCode/sections/:sectionCode",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/channels/${encodeURIComponent(props.channelCode ?? "null")}/sections/${encodeURIComponent(props.sectionCode ?? "null")}`;
  export const random = (): IShoppingMallSection =>
    typia.random<IShoppingMallSection>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("channelCode")(() => typia.assert(props.channelCode));
      assert.param("sectionCode")(() => typia.assert(props.sectionCode));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
