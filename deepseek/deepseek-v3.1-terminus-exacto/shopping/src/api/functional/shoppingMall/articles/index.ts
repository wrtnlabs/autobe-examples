/**
 * Retrieve a filtered and paginated list of shopping mall articles with
 * advanced search capabilities. This operation operates on the
 * shopping_mall_articles table from the Prisma schema and provides
 * comprehensive filtering options including title search, content matching,
 * status filtering, publication date ranges, and engagement metrics.
 *
 * The operation supports full-text search capabilities using PostgreSQL GIN
 * indexes on title and content fields, allowing for efficient keyword matching
 * and relevance ranking. Users can filter by publication status (draft,
 * pending_review, published, archived), business workflow status, featured
 * articles, and comment permissions. The system also supports sorting by view
 * count, like count, publication date, or creation date.
 *
 * Security considerations include appropriate access controls based on article
 * status - published articles are generally accessible while draft and pending
 * articles may require specific permissions. The operation integrates with the
 * shopping mall channel and section hierarchy for organizational filtering.
 * Response includes article summary information optimized for list displays
 * with pagination metadata.
 *
 * This operation leverages the GIN indexes on title and content fields for
 * optimal search performance and supports complex boolean search queries when
 * needed. The response is designed for efficient client-side rendering of
 * article lists with essential metadata.
 *
 * @param props.connection
 * @param props.body Search criteria and pagination parameters for article
 *   filtering
 * @path /shoppingMall/articles
 * @accessor api.functional.shoppingMall.articles.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /** Search criteria and pagination parameters for article filtering */
    body: IShoppingMallArticle.IRequest;
  };
  export type Body = IShoppingMallArticle.IRequest;
  export type Response = IPageIShoppingMallArticle.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/articles",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/shoppingMall/articles";
  export const random = (): IPageIShoppingMallArticle.ISummary =>
    typia.random<IPageIShoppingMallArticle.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

