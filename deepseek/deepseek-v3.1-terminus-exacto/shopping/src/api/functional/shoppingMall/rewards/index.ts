import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallReward } from "../../../structures/IShoppingMallReward";
import { IPageIShoppingMallReward } from "../../../structures/IPageIShoppingMallReward";

/**
 * Search and retrieve a filtered list of reward programs from the shopping mall
 * platform.
 *
 * This operation provides advanced search capabilities for finding reward
 * programs based on multiple criteria including reward type, program status,
 * validity dates, and program name matching. The operation supports
 * comprehensive pagination with configurable page sizes and sorting options.
 * Users can sort by creation date, validity period, or program name in
 * ascending or descending order.
 *
 * Security considerations include appropriate filtering of reward program
 * information based on the requesting user's authorization level. Only active
 * reward programs are returned by default, with optional filters to include
 * inactive or expired programs for administrative purposes. Rate limiting
 * applies to prevent excessive search operations.
 *
 * This operation integrates with the shopping_mall_rewards table as defined in
 * the Prisma schema, incorporating all available reward program fields
 * including name, description, reward_type, earning_rules, redemption_rules,
 * coin_value, and program validity periods. The response includes reward
 * program summary information optimized for list displays.
 *
 * @param props.connection
 * @param props.body Search criteria and pagination parameters for reward
 *   program filtering
 * @path /shoppingMall/rewards
 * @accessor api.functional.shoppingMall.rewards.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Search criteria and pagination parameters for reward program
     * filtering
     */
    body: IShoppingMallReward.IRequest;
  };
  export type Body = IShoppingMallReward.IRequest;
  export type Response = IPageIShoppingMallReward.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/rewards",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/shoppingMall/rewards";
  export const random = (): IPageIShoppingMallReward.ISummary =>
    typia.random<IPageIShoppingMallReward.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
