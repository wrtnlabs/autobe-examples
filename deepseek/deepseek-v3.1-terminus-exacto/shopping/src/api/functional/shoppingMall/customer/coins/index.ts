import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallCoin } from "../../../../structures/IShoppingMallCoin";

/**
 * Retrieve detailed information about a specific coin account from the shopping
 * mall platform.
 *
 * This operation returns the complete coin account details for a specific coin
 * ID, including current balance, total earned/spent metrics, coin type, and
 * actor ownership information. The operation accesses the shopping_mall_coins
 * table from the Prisma schema and provides comprehensive coin account
 * information for authenticated users.
 *
 * Security considerations include ensuring that users can only access their own
 * coin accounts or accounts they have permission to view. The operation
 * validates that the coin ID exists and that the requesting user has
 * appropriate access rights. Rate limiting applies to prevent excessive API
 * calls for coin balance checking.
 *
 * This operation integrates with the shopping_mall_coins table as defined in
 * the Prisma schema, incorporating all available coin account fields including
 * actor_type, balance, total_earned, total_spent, coin_type, and timestamps.
 * The response includes detailed coin account information optimized for display
 * in user interfaces and administrative dashboards.
 *
 * @param props.connection
 * @param props.coinId Unique identifier of the target coin account
 * @path /shoppingMall/customer/coins/:coinId
 * @accessor api.functional.shoppingMall.customer.coins.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique identifier of the target coin account */
    coinId: string & tags.Format<"uuid">;
  };
  export type Response = IShoppingMallCoin;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/customer/coins/:coinId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/customer/coins/${encodeURIComponent(props.coinId ?? "null")}`;
  export const random = (): IShoppingMallCoin =>
    typia.random<IShoppingMallCoin>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("coinId")(() => typia.assert(props.coinId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
