import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallSale } from "../../../../structures/IShoppingMallSale";

/**
 * Retrieve detailed information about a specific sale transaction in the
 * shopping mall system.
 *
 * This operation fetches comprehensive sale details from the
 * shopping_mall_sales table, including transaction amounts, item counts, status
 * information, commission rates, and related customer and seller information.
 * Each sale represents a completed purchase transaction that has been
 * successfully processed and paid.
 *
 * The operation validates that the requested sale exists and that the
 * requesting user has appropriate permissions to view the sale details. Sales
 * data includes financial information such as sale amount, commission rate, and
 * net payout amount, making this operation suitable for both customer order
 * history and seller sales reporting.
 *
 * Security considerations include ensuring that customers can only view their
 * own sales, while sellers can view sales they have received. Administrative
 * users may have broader access to all sales data for analytics and business
 * intelligence purposes. The operation returns the complete sale record with
 * all associated metadata.
 *
 * @param props.connection
 * @param props.saleId Unique identifier of the target sale transaction
 * @path /shoppingMall/customer/sales/:saleId
 * @accessor api.functional.shoppingMall.customer.sales.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique identifier of the target sale transaction */
    saleId: string & tags.Format<"uuid">;
  };
  export type Response = IShoppingMallSale;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/customer/sales/:saleId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/customer/sales/${encodeURIComponent(props.saleId ?? "null")}`;
  export const random = (): IShoppingMallSale =>
    typia.random<IShoppingMallSale>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("saleId")(() => typia.assert(props.saleId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
