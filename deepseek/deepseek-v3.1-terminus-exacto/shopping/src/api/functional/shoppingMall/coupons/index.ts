/**
 * Search and retrieve a filtered list of shopping mall coupons with advanced
 * filtering, sorting, and pagination capabilities.
 *
 * This operation provides comprehensive search functionality for the coupon
 * catalog, allowing administrators to find coupons based on various criteria
 * including coupon code, name, discount type, validity period, active status,
 * and usage statistics. The search supports complex filtering logic with
 * multiple conditions combined using AND/OR operators.
 *
 * Pagination is fully supported with configurable page sizes and cursor-based
 * navigation. Results can be sorted by creation date, validity period, discount
 * value, or usage count in ascending or descending order. The operation returns
 * coupon summary information optimized for list displays, including essential
 * details without sensitive administrative data.
 *
 * Security considerations include rate limiting for search operations and
 * appropriate access controls to ensure only authorized administrators can
 * search the coupon catalog. The operation integrates with the Coupons table
 * from the Prisma schema, incorporating all available coupon fields and
 * relationships.
 *
 * Related operations: Create coupon (POST /coupons), View coupon details (GET
 * /coupons/{couponId}), Update coupon (PUT /coupons/{couponId}).
 *
 * @param props.connection
 * @param props.body Search criteria and pagination parameters for coupon
 *   filtering
 * @path /shoppingMall/coupons
 * @accessor api.functional.shoppingMall.coupons.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /** Search criteria and pagination parameters for coupon filtering */
    body: IShoppingMallCoupon.IRequest;
  };
  export type Body = IShoppingMallCoupon.IRequest;
  export type Response = IPageIShoppingMallCoupon.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/coupons",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/shoppingMall/coupons";
  export const random = (): IPageIShoppingMallCoupon.ISummary =>
    typia.random<IPageIShoppingMallCoupon.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

