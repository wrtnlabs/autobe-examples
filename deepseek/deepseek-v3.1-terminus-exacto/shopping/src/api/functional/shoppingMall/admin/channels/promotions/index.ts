import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallPromotion } from "../../../../../structures/IShoppingMallPromotion";

/**
 * Permanently delete a marketing promotion from the shopping mall platform.
 *
 * This operation removes a specific promotion identified by its unique name
 * within a specific channel from the promotions table. The deletion respects
 * the composite unique constraint that requires channel context for promotion
 * identification. The operation performs a soft delete by setting the
 * deleted_at timestamp, preserving the promotion record for audit purposes
 * while excluding it from normal queries.
 *
 * The operation validates that the promotion exists within the specified
 * channel and that the requesting administrator has appropriate permissions to
 * delete promotions. It also checks that the promotion is not currently active
 * or scheduled for future activation to prevent disruption of active marketing
 * campaigns.
 *
 * Security considerations include verifying administrator permissions and
 * ensuring that only authorized users can delete promotions. The operation logs
 * the deletion event for audit purposes and updates related entities that may
 * reference the promotion.
 *
 * This operation integrates with the shopping_mall_promotions table as defined
 * in the Prisma schema, handling all promotion fields and relationships. The
 * soft delete pattern uses the deleted_at field to mark promotions as deleted
 * while preserving historical data. Related operations include creating
 * promotions (POST /promotions), updating promotions (PUT
 * /promotions/{promotionName}), and searching promotions (PATCH /promotions).
 *
 * @param props.connection
 * @param props.channelCode Unique business identifier code of the target
 *   channel where the promotion exists (global scope)
 * @param props.promotionName Unique name identifier of the target promotion
 *   within the specified channel (scoped to channel)
 * @path /shoppingMall/admin/channels/:channelCode/promotions/:promotionName
 * @accessor api.functional.shoppingMall.admin.channels.promotions.erase
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function erase(
  connection: IConnection,
  props: erase.Props,
): Promise<erase.Response> {
  return true === connection.simulate
    ? erase.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...erase.METADATA,
          path: erase.path(props),
          status: null,
        },
      );
}
export namespace erase {
  export type Props = {
    /**
     * Unique business identifier code of the target channel where the
     * promotion exists (global scope)
     */
    channelCode: string;

    /**
     * Unique name identifier of the target promotion within the specified
     * channel (scoped to channel)
     */
    promotionName: string;
  };
  export type Response = IShoppingMallPromotion;

  export const METADATA = {
    method: "DELETE",
    path: "/shoppingMall/admin/channels/:channelCode/promotions/:promotionName",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/admin/channels/${encodeURIComponent(props.channelCode ?? "null")}/promotions/${encodeURIComponent(props.promotionName ?? "null")}`;
  export const random = (): IShoppingMallPromotion =>
    typia.random<IShoppingMallPromotion>();
  export const simulate = (
    connection: IConnection,
    props: erase.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: erase.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("channelCode")(() => typia.assert(props.channelCode));
      assert.param("promotionName")(() => typia.assert(props.promotionName));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
