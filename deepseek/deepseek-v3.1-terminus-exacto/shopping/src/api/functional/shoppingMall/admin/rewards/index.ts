/**
 * Retrieve detailed information about a specific reward program from the
 * shopping mall platform.
 *
 * This operation fetches a single reward program entity by its unique
 * identifier, providing comprehensive details about the program's
 * configuration, earning rules, redemption rules, and validity periods. The
 * reward program represents a structured incentive system where customers can
 * earn coins based on specific conditions defined in the earning_rules JSON
 * configuration.
 *
 * Security considerations include ensuring that only authorized users can
 * access reward program details, particularly for programs that may contain
 * sensitive business logic or targeted customer segments. The operation
 * validates that the requested reward program exists and is accessible based on
 * the current user's permissions and program visibility settings.
 *
 * This operation integrates directly with the shopping_mall_rewards table in
 * the Prisma schema, returning all fields including the program name,
 * description, reward type, coin value, minimum purchase requirements, maximum
 * coin limits, and program validity dates. The response includes both active
 * and inactive programs, allowing for comprehensive program management and
 * historical tracking.
 *
 * @param props.connection
 * @param props.rewardId Unique identifier of the target reward program
 * @path /shoppingMall/admin/rewards/:rewardId
 * @accessor api.functional.shoppingMall.admin.rewards.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
