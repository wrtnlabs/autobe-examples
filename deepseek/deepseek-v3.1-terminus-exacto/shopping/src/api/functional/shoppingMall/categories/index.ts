import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallCategory } from "../../../structures/IShoppingMallCategory";
import { IPageIShoppingMallCategory } from "../../../structures/IPageIShoppingMallCategory";

/**
 * Search and retrieve a paginated list of product categories from the shopping
 * mall catalog.
 *
 * This operation allows users to search through the hierarchical category
 * system with advanced filtering capabilities. Users can filter by category
 * name, parent category relationships, active status, and display order. The
 * operation supports comprehensive pagination with configurable page sizes and
 * sorting options, allowing sorting by display order, creation date, or
 * alphabetical order.
 *
 * The search functionality implements partial matching on category names and
 * descriptions, making it easy to find relevant categories. The response
 * includes category summary information optimized for list displays, including
 * hierarchical relationships for proper navigation context.
 *
 * Security considerations include appropriate filtering of soft-deleted
 * categories and access control based on user permissions. Only active
 * categories are returned by default, with administrators having the ability to
 * include inactive categories in search results.
 *
 * @param props.connection
 * @param props.body Search criteria and pagination parameters for category
 *   filtering
 * @path /shoppingMall/categories
 * @accessor api.functional.shoppingMall.categories.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /** Search criteria and pagination parameters for category filtering */
    body: IShoppingMallCategory.IRequest;
  };
  export type Body = IShoppingMallCategory.IRequest;
  export type Response = IPageIShoppingMallCategory.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/categories",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/shoppingMall/categories";
  export const random = (): IPageIShoppingMallCategory.ISummary =>
    typia.random<IPageIShoppingMallCategory.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

/**
 * Retrieve detailed information for a specific product category in the shopping
 * mall catalog.
 *
 * This operation provides comprehensive details about a single category,
 * including its hierarchical relationships, metadata, and current status. The
 * response includes the category's parent relationship information for proper
 * navigation context within the category hierarchy.
 *
 * Detailed information includes the category name, description, display order,
 * active status, creation and modification timestamps. The operation validates
 * that the requested category exists and is accessible before returning the
 * detailed information.
 *
 * Security considerations ensure that soft-deleted categories are not
 * accessible through this endpoint unless the user has appropriate
 * administrative permissions. The operation provides proper error handling for
 * non-existent categories or access violations.
 *
 * @param props.connection
 * @param props.categoryId Unique identifier of the target category
 * @path /shoppingMall/categories/:categoryId
 * @accessor api.functional.shoppingMall.categories.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
