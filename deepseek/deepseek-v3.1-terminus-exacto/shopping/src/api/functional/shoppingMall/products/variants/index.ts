import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallProductVariant } from "../../../../structures/IShoppingMallProductVariant";

/**
 * Retrieve detailed information about a specific product variant from the
 * shopping mall product catalog.
 *
 * This operation fetches comprehensive details for a single product variant
 * identified by its unique identifier. The variant belongs to a specific
 * product and contains variant-specific information such as pricing, inventory,
 * attributes, and availability status.
 *
 * Product variants represent different configurations of the same base product,
 * such as size variations, color options, or style differences. Each variant
 * can have unique pricing, stock levels, and attribute combinations while
 * sharing the same core product information.
 *
 * Security considerations include proper access control to ensure only
 * authorized users can view product variant details. The operation validates
 * that both the parent product and variant exist and are accessible before
 * returning the detailed information.
 *
 * This operation integrates with the Product Variants table from the Prisma
 * schema, providing access to all variant-specific fields including pricing
 * overrides, inventory tracking, and attribute configurations stored as JSON
 * data.
 *
 * @param props.connection
 * @param props.productId Unique identifier of the parent product that contains
 *   the target variant
 * @param props.variantId Unique identifier of the specific product variant to
 *   retrieve
 * @path /shoppingMall/products/:productId/variants/:variantId
 * @accessor api.functional.shoppingMall.products.variants.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique identifier of the parent product that contains the target
     * variant
     */
    productId: string & tags.Format<"uuid">;

    /** Unique identifier of the specific product variant to retrieve */
    variantId: string & tags.Format<"uuid">;
  };
  export type Response = IShoppingMallProductVariant;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/products/:productId/variants/:variantId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/products/${encodeURIComponent(props.productId ?? "null")}/variants/${encodeURIComponent(props.variantId ?? "null")}`;
  export const random = (): IShoppingMallProductVariant =>
    typia.random<IShoppingMallProductVariant>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("productId")(() => typia.assert(props.productId));
      assert.param("variantId")(() => typia.assert(props.variantId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
