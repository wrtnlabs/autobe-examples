/**
 * Search and retrieve a paginated list of shopping mall reviews with advanced
 * filtering and sorting capabilities.
 *
 * This operation provides comprehensive search functionality for shopping mall
 * reviews, allowing users to filter by product ID, seller ID, actor type,
 * review status, rating range, and other criteria. The operation supports
 * pagination with configurable page sizes and sorting options based on creation
 * date, rating, helpful count, and other review attributes.
 *
 * Security considerations include appropriate access controls based on the
 * requesting user's role. Public users may view approved reviews, while
 * authenticated users can see their own reviews regardless of status.
 * Administrative users have access to all reviews including pending and
 * rejected ones for moderation purposes.
 *
 * This operation integrates with the shopping_mall_reviews table from the
 * Prisma schema, incorporating all available review fields and relationships.
 * The response includes review summary information optimized for list displays,
 * with pagination metadata for efficient navigation through large result sets.
 *
 * The search functionality supports complex queries including text search on
 * review titles and content, range filtering on ratings and dates, and
 * multi-criteria combinations. Users can specify sorting preferences to
 * prioritize recent reviews, highest-rated content, or most helpful
 * evaluations.
 *
 * Related operations include retrieving a specific review detail (GET
 * /reviews/{reviewId}) and creating new reviews (POST /reviews). This search
 * operation serves as the primary entry point for discovering and browsing
 * review content across the shopping mall platform.
 *
 * @param props.connection
 * @param props.body Search criteria and pagination parameters for review
 *   filtering
 * @path /shoppingMall/reviews
 * @accessor api.functional.shoppingMall.reviews.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /** Search criteria and pagination parameters for review filtering */
    body: IShoppingMallReview.IRequest;
  };
  export type Body = IShoppingMallReview.IRequest;
  export type Response = IPageIShoppingMallReview.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/reviews",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/shoppingMall/reviews";
  export const random = (): IPageIShoppingMallReview.ISummary =>
    typia.random<IPageIShoppingMallReview.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

