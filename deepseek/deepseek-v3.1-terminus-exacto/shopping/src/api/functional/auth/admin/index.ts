/**
 * Registration endpoint for creating new administrator accounts in the shopping
 * mall platform. This operation allows authorized personnel to create
 * administrator accounts with proper role-based permissions and authentication
 * credentials.
 *
 * The endpoint validates administrator registration data including email format
 * uniqueness, password strength requirements, and role assignment validation.
 * Upon successful registration, the system creates a new administrator record
 * with hashed password storage and initial account status set to
 * pending_activation.
 *
 * Administrator accounts require elevated security measures including strong
 * password policies and role-based access control. The registration process
 * ensures proper accountability by recording first_name and last_name for
 * identification purposes. Role assignment follows predefined permission sets
 * for super_admin, support_admin, and security_admin roles.
 *
 * Security considerations include proper password hashing using bcrypt
 * algorithm, email validation to prevent duplicate accounts, and role-based
 * permission assignment. Related operations include administrator login for
 * authentication and account status management for activation workflows.
 *
 * @param props.connection
 * @param props.body Administrator registration information including
 *   authentication credentials and role assignment
 * @setHeader token.access Authorization
 *
 * @path /auth/admin/join
 * @accessor api.functional.auth.admin.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
