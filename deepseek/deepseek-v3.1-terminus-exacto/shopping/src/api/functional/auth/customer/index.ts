/**
 * Customer registration endpoint that creates new customer accounts in the
 * shopping mall platform. This operation handles the initial account creation
 * process for customers who want to shop on the platform.
 *
 * The endpoint validates customer-provided information including email
 * uniqueness, password strength requirements, and personal details. It creates
 * a new customer record in the shopping_mall_customers table with the provided
 * email, hashed password, first name, last name, and optional phone number. The
 * customer account is initialized with 'pending_verification' status to ensure
 * proper verification workflows.
 *
 * Security considerations include password hashing using bcrypt algorithm
 * before storage, email uniqueness validation to prevent duplicate accounts,
 * and initial account status management. The operation returns authentication
 * tokens upon successful registration, allowing immediate access to the
 * platform while verification processes run in the background.
 *
 * Related operations include customer login for existing accounts and email
 * verification workflows that transition accounts from 'pending_verification'
 * to 'active' status. This endpoint serves as the entry point for new customers
 * joining the shopping mall ecosystem.
 *
 * @param props.connection
 * @param props.body Customer registration information including authentication
 *   credentials and personal details
 * @setHeader token.access Authorization
 *
 * @path /auth/customer/join
 * @accessor api.functional.auth.customer.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
