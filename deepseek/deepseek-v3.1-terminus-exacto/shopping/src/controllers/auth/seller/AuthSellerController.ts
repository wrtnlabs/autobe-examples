import { Controller, Ip } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthSellerJoin } from "../../../providers/postAuthSellerJoin";
import { postAuthSellerLogin } from "../../../providers/postAuthSellerLogin";
import { postAuthSellerRefresh } from "../../../providers/postAuthSellerRefresh";
import { SellerAuth } from "../../../decorators/SellerAuth";
import { SellerPayload } from "../../../decorators/payload/SellerPayload";

import { IShoppingMallSeller } from "../../../api/structures/IShoppingMallSeller";

@Controller("/auth/seller")
export class AuthSellerController {
  /**
   * Seller registration endpoint that creates a new seller account in the
   * shopping mall platform. This operation registers business entities that
   * will list products and manage inventory on the platform.
   *
   * The registration process captures essential business information including
   * legal business name, contact details, and authentication credentials. Upon
   * successful registration, sellers receive initial JWT tokens for immediate
   * access to their seller dashboard.
   *
   * Seller accounts undergo verification before becoming fully active, with
   * status transitioning from 'pending_approval' to 'verified' after business
   * validation. The operation validates email uniqueness and business name
   * availability to prevent duplicate registrations.
   *
   * Security measures include password hashing using bcrypt algorithm and email
   * verification workflows. Registered sellers can immediately begin setting up
   * their storefront while awaiting full business verification.
   *
   * @param connection
   * @param body Seller registration information including business details and
   *   authentication credentials
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallSeller.ICreate,
  ): Promise<IShoppingMallSeller.IAuthorized> {
    try {
      return await postAuthSellerJoin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Seller authentication endpoint that validates seller credentials and
   * provides access tokens for seller dashboard access. This operation
   * authenticates registered sellers using their email and password
   * combination.
   *
   * The authentication process verifies the seller's email exists in the system
   * and matches the provided password hash using bcrypt comparison. Successful
   * authentication grants access to seller-specific features including product
   * management, order processing, and sales analytics.
   *
   * Security features include rate limiting to prevent brute force attacks and
   * session management through refresh tokens. The operation validates seller
   * account status, allowing login only for 'active' or 'verified' accounts
   * while blocking 'suspended' or 'pending_approval' accounts.
   *
   * Upon successful authentication, sellers receive JWT access tokens with
   * seller-specific permissions and refresh tokens for session continuity.
   *
   * @param connection
   * @param body Seller login credentials for authentication
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallSeller.ILogin,
  ): Promise<IShoppingMallSeller.IAuthorized> {
    try {
      return await postAuthSellerLogin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Token refresh endpoint that renews seller authentication tokens without
   * requiring re-authentication. This operation extends seller session validity
   * by generating new access tokens using valid refresh tokens.
   *
   * The refresh mechanism maintains seller dashboard continuity while enhancing
   * security by rotating tokens periodically. The operation validates the
   * refresh token's authenticity and checks that the associated seller account
   * remains in good standing.
   *
   * Security measures include refresh token expiration policies and automatic
   * session termination for suspended accounts. The operation supports seamless
   * seller experience by minimizing authentication interruptions during
   * extended management sessions.
   *
   * Successful token refresh provides sellers with new access tokens while
   * maintaining their current session context and permissions.
   *
   * @param connection
   * @param body Refresh token for authentication token renewal
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IShoppingMallSeller.IRefresh,
  ): Promise<IShoppingMallSeller.IAuthorized> {
    try {
      return await postAuthSellerRefresh({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
