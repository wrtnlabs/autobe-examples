import { Controller, Ip } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthCustomerJoin } from "../../../providers/postAuthCustomerJoin";
import { postAuthCustomerLogin } from "../../../providers/postAuthCustomerLogin";
import { postAuthCustomerRefresh } from "../../../providers/postAuthCustomerRefresh";

import { IShoppingMallCustomer } from "../../../api/structures/IShoppingMallCustomer";

@Controller("/auth/customer")
export class AuthCustomerController {
  /**
   * Customer registration endpoint that creates new customer accounts in the
   * shopping mall platform. This operation handles the initial account creation
   * process for customers who want to shop on the platform.
   *
   * The endpoint validates customer-provided information including email
   * uniqueness, password strength requirements, and personal details. It
   * creates a new customer record in the shopping_mall_customers table with the
   * provided email, hashed password, first name, last name, and optional phone
   * number. The customer account is initialized with 'pending_verification'
   * status to ensure proper verification workflows.
   *
   * Security considerations include password hashing using bcrypt algorithm
   * before storage, email uniqueness validation to prevent duplicate accounts,
   * and initial account status management. The operation returns authentication
   * tokens upon successful registration, allowing immediate access to the
   * platform while verification processes run in the background.
   *
   * Related operations include customer login for existing accounts and email
   * verification workflows that transition accounts from 'pending_verification'
   * to 'active' status. This endpoint serves as the entry point for new
   * customers joining the shopping mall ecosystem.
   *
   * @param connection
   * @param body Customer registration information including authentication
   *   credentials and personal details
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallCustomer.ICreate,
  ): Promise<IShoppingMallCustomer.IAuthorized> {
    try {
      return await postAuthCustomerJoin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Customer authentication endpoint that validates credentials and establishes
   * secure sessions for existing customer accounts. This operation
   * authenticates customers using their registered email and password
   * combination.
   *
   * The endpoint verifies the provided email exists in the
   * shopping_mall_customers table and validates the password against the stored
   * password_hash using bcrypt comparison. Upon successful authentication, it
   * creates a new session record in shopping_mall_customer_sessions with
   * connection details including IP address, URL, and referrer information for
   * security monitoring.
   *
   * Security features include session tracking for audit purposes, connection
   * context recording for security analysis, and proper token expiration
   * management. The operation handles various authentication scenarios
   * including invalid credentials, suspended accounts, and verification
   * requirements. It returns JWT tokens that grant access to customer-specific
   * resources and functionalities.
   *
   * Related operations include customer registration for new accounts and token
   * refresh for session maintenance. This endpoint is essential for returning
   * customers to access their shopping carts, order history, and personalized
   * shopping experiences.
   *
   * @param connection
   * @param body Customer login credentials including email and password
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallCustomer.ILogin,
  ): Promise<IShoppingMallCustomer.IAuthorized> {
    try {
      return await postAuthCustomerLogin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Token refresh endpoint that renews authentication tokens for active
   * customer sessions. This operation extends the validity of existing sessions
   * without requiring re-authentication, providing seamless user experience.
   *
   * The endpoint validates the provided refresh token against active sessions
   * in the shopping_mall_customer_sessions table, ensuring the session has not
   * expired and belongs to a valid customer account. It generates new access
   * and refresh tokens while maintaining the session context and connection
   * information for continuity.
   *
   * Security considerations include refresh token validation, session
   * expiration checks, and proper token rotation to prevent token reuse. The
   * operation updates the session expiration timestamp to extend the session
   * duration while maintaining audit trails of customer activity. It handles
   * scenarios where refresh tokens are invalid, expired, or associated with
   * terminated sessions.
   *
   * Related operations include customer login for initial authentication and
   * session management for tracking customer activity. This endpoint supports
   * long-term customer engagement by maintaining secure access without frequent
   * re-login requirements.
   *
   * @param connection
   * @param body Refresh token for renewing authentication session
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IShoppingMallCustomer.IRefresh,
  ): Promise<IShoppingMallCustomer.IAuthorized> {
    try {
      return await postAuthCustomerRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
