import { Controller, Ip } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthAdminJoin } from "../../../providers/postAuthAdminJoin";
import { postAuthAdminLogin } from "../../../providers/postAuthAdminLogin";
import { postAuthAdminRefresh } from "../../../providers/postAuthAdminRefresh";

import { IShoppingMallAdministrator } from "../../../api/structures/IShoppingMallAdministrator";

@Controller("/auth/admin")
export class AuthAdminController {
  /**
   * Registration endpoint for creating new administrator accounts in the
   * shopping mall platform. This operation allows authorized personnel to
   * create administrator accounts with proper role-based permissions and
   * authentication credentials.
   *
   * The endpoint validates administrator registration data including email
   * format uniqueness, password strength requirements, and role assignment
   * validation. Upon successful registration, the system creates a new
   * administrator record with hashed password storage and initial account
   * status set to pending_activation.
   *
   * Administrator accounts require elevated security measures including strong
   * password policies and role-based access control. The registration process
   * ensures proper accountability by recording first_name and last_name for
   * identification purposes. Role assignment follows predefined permission sets
   * for super_admin, support_admin, and security_admin roles.
   *
   * Security considerations include proper password hashing using bcrypt
   * algorithm, email validation to prevent duplicate accounts, and role-based
   * permission assignment. Related operations include administrator login for
   * authentication and account status management for activation workflows.
   *
   * @param connection
   * @param body Administrator registration information including authentication
   *   credentials and role assignment
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallAdministrator.ICreate,
  ): Promise<IShoppingMallAdministrator.IAuthorized> {
    try {
      return await postAuthAdminJoin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authentication endpoint for administrator access to the shopping mall
   * platform. This operation validates administrator credentials against stored
   * email and password_hash fields in the shopping_mall_administrators table.
   *
   * The endpoint performs secure authentication by comparing provided password
   * against the bcrypt-hashed password_hash stored in the database. It
   * validates account status to ensure only active administrators can
   * authenticate, rejecting suspended or pending accounts.
   *
   * Authentication success generates JWT tokens for secure access to
   * administrative functions. The system records login activity and validates
   * role-based permissions for subsequent API operations. Security measures
   * include rate limiting, credential validation, and session management.
   *
   * Implementation details include proper password verification using bcrypt
   * comparison, account status validation against active status, and JWT token
   * generation with appropriate expiration times. Related operations include
   * token refresh for session continuation and account management for status
   * updates.
   *
   * @param connection
   * @param body Administrator login credentials for authentication
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallAdministrator.ILogin,
  ): Promise<IShoppingMallAdministrator.IAuthorized> {
    try {
      return await postAuthAdminLogin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Token refresh endpoint for maintaining administrator session continuity.
   * This operation validates refresh tokens and issues new access tokens
   * without requiring re-authentication.
   *
   * The endpoint validates the refresh token against stored session information
   * and administrator account status. It ensures the administrator account
   * remains active and has not been suspended since the original
   * authentication. Successful refresh generates new access tokens with updated
   * expiration times.
   *
   * Security considerations include refresh token validation, session integrity
   * checks, and proper token expiration management. The operation supports
   * continuous administrative access while maintaining security through
   * periodic revalidation of account status and permissions.
   *
   * Implementation details include refresh token verification, access token
   * regeneration with appropriate expiration, and session activity tracking.
   * Related operations include administrator login for initial authentication
   * and account management for status monitoring during session refresh
   * cycles.
   *
   * @param connection
   * @param body Refresh token for generating new access tokens
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IShoppingMallAdministrator.IRefresh,
  ): Promise<IShoppingMallAdministrator.IAuthorized> {
    try {
      return await postAuthAdminRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
