import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallArticlesArticleIdComments } from "../../../../providers/patchShoppingMallArticlesArticleIdComments";
import { getShoppingMallArticlesArticleIdCommentsCommentId } from "../../../../providers/getShoppingMallArticlesArticleIdCommentsCommentId";

import { IPageIShoppingMallArticleComment } from "../../../../api/structures/IPageIShoppingMallArticleComment";
import { IShoppingMallArticleComment } from "../../../../api/structures/IShoppingMallArticleComment";

@Controller("/shoppingMall/articles/:articleId/comments")
export class ShoppingmallArticlesCommentsController {
  /**
   * Search and retrieve comments associated with a specific shopping mall
   * article. This operation provides advanced filtering, pagination, and
   * sorting capabilities for browsing article comments with comprehensive
   * search functionality.
   *
   * This operation targets the shopping_mall_article_comments table in the
   * Prisma schema, which stores user comments on articles with support for
   * threaded discussions and moderation workflows. The search functionality
   * allows filtering by comment status, actor type, creation date ranges, and
   * content keywords using full-text search capabilities.
   *
   * The response includes paginated results with metadata about the total
   * number of comments matching the search criteria. Users can sort comments by
   * creation date, like count, or depth level for threaded discussions. The
   * system supports complex query parameters for advanced comment management
   * and moderation workflows.
   *
   * Security considerations include appropriate access controls based on
   * comment visibility and moderation status. Public users may only see
   * approved comments, while moderators can view all comment statuses. Rate
   * limiting applies to prevent excessive search requests that could impact
   * system performance.
   *
   * Related operations include creating comments (POST
   * /articles/{articleId}/comments), retrieving a specific comment (GET
   * /articles/{articleId}/comments/{commentId}), and updating comments (PUT
   * /articles/{articleId}/comments/{commentId}).
   *
   * @param connection
   * @param articleId Unique identifier of the target article whose comments are
   *   being searched
   * @param body Search criteria and pagination parameters for comment filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallArticleComment.IRequest,
  ): Promise<IPageIShoppingMallArticleComment.ISummary> {
    try {
      return await patchShoppingMallArticlesArticleIdComments({
        articleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific comment on a shopping mall article by its unique
   * identifier. This operation accesses the shopping_mall_article_comments
   * table from the Prisma schema and returns detailed comment information
   * including content, engagement metrics, and moderation status.
   *
   * The operation validates that both the article and comment exist and are
   * accessible. It supports threaded comment retrieval by including parent
   * comment relationships when applicable. The response includes comprehensive
   * comment details with proper actor attribution and engagement metrics.
   *
   * Security considerations include appropriate access controls based on
   * comment status and article visibility. Comments with sensitive moderation
   * status may require additional authorization checks. The operation
   * integrates with the article's comment threading system to provide
   * context-aware comment retrieval.
   *
   * This operation serves as the foundation for comment display functionality
   * in the shopping mall platform, supporting both standalone comment viewing
   * and threaded discussion navigation. Related operations include listing all
   * comments for an article and creating new comments.
   *
   * @param connection
   * @param articleId Unique identifier of the target article
   * @param commentId Unique identifier of the target comment
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":commentId")
  public async at(
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallArticleComment> {
    try {
      return await getShoppingMallArticlesArticleIdCommentsCommentId({
        articleId,
        commentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
