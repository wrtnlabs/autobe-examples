import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallArticles } from "../../../providers/patchShoppingMallArticles";
import { getShoppingMallArticlesArticleId } from "../../../providers/getShoppingMallArticlesArticleId";

import { IPageIShoppingMallArticle } from "../../../api/structures/IPageIShoppingMallArticle";
import { IShoppingMallArticle } from "../../../api/structures/IShoppingMallArticle";

@Controller("/shoppingMall/articles")
export class ShoppingmallArticlesController {
  /**
   * Retrieve a filtered and paginated list of shopping mall articles with
   * advanced search capabilities. This operation operates on the
   * shopping_mall_articles table from the Prisma schema and provides
   * comprehensive filtering options including title search, content matching,
   * status filtering, publication date ranges, and engagement metrics.
   *
   * The operation supports full-text search capabilities using PostgreSQL GIN
   * indexes on title and content fields, allowing for efficient keyword
   * matching and relevance ranking. Users can filter by publication status
   * (draft, pending_review, published, archived), business workflow status,
   * featured articles, and comment permissions. The system also supports
   * sorting by view count, like count, publication date, or creation date.
   *
   * Security considerations include appropriate access controls based on
   * article status - published articles are generally accessible while draft
   * and pending articles may require specific permissions. The operation
   * integrates with the shopping mall channel and section hierarchy for
   * organizational filtering. Response includes article summary information
   * optimized for list displays with pagination metadata.
   *
   * This operation leverages the GIN indexes on title and content fields for
   * optimal search performance and supports complex boolean search queries when
   * needed. The response is designed for efficient client-side rendering of
   * article lists with essential metadata.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for article filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IShoppingMallArticle.IRequest,
  ): Promise<IPageIShoppingMallArticle.ISummary> {
    try {
      return await patchShoppingMallArticles({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information for a specific shopping mall article by its
   * unique identifier. This operation provides comprehensive article data
   * including full content, metadata, engagement metrics, and publication
   * status from the shopping_mall_articles table.
   *
   * The response includes the complete article content with rich text
   * formatting, publication timeline information (created_at, updated_at,
   * published_at), and engagement statistics (view_count, like_count,
   * share_count). The operation also resolves channel and section relationships
   * to provide organizational context for the article's placement within the
   * shopping mall content hierarchy.
   *
   * Security considerations ensure that access to draft or pending review
   * articles is restricted based on user permissions and ownership. Published
   * articles are generally accessible to all users while draft articles may
   * only be visible to their creators or administrators. The operation
   * validates that the requested article exists and is accessible based on its
   * current status.
   *
   * This operation serves as the primary method for displaying individual
   * article pages and supports content preview functionality for editors. The
   * detailed response includes all necessary information for rendering complete
   * article views with proper attribution and metadata display.
   *
   * @param connection
   * @param articleId Unique identifier of the target article
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":articleId")
  public async at(
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallArticle> {
    try {
      return await getShoppingMallArticlesArticleId({
        articleId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
