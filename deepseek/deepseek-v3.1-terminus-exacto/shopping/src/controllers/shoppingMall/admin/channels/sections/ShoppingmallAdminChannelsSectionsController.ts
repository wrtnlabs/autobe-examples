import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia from "typia";
import { postShoppingMallAdminChannelsChannelCodeSections } from "../../../../../providers/postShoppingMallAdminChannelsChannelCodeSections";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { patchShoppingMallAdminChannelsChannelCodeSections } from "../../../../../providers/patchShoppingMallAdminChannelsChannelCodeSections";
import { putShoppingMallAdminChannelsChannelCodeSectionsSectionCode } from "../../../../../providers/putShoppingMallAdminChannelsChannelCodeSectionsSectionCode";
import { deleteShoppingMallAdminChannelsChannelCodeSectionsSectionCode } from "../../../../../providers/deleteShoppingMallAdminChannelsChannelCodeSectionsSectionCode";

import { IShoppingMallSection } from "../../../../../api/structures/IShoppingMallSection";
import { IPageIShoppingMallSection } from "../../../../../api/structures/IPageIShoppingMallSection";

@Controller("/shoppingMall/admin/channels/:channelCode/sections")
export class ShoppingmallAdminChannelsSectionsController {
  /**
   * Create a new shopping mall section within a specified channel to organize
   * products and categories.
   *
   * This operation allows platform administrators to establish new
   * organizational sections within existing shopping channels. Sections provide
   * hierarchical grouping capabilities for products, enabling better
   * merchandising, navigation, and customer experience management. The
   * operation validates that the parent channel exists and is active before
   * creating the new section.
   *
   * Business rules enforced during creation include validation of section code
   * uniqueness within the channel, verification of hierarchical parent
   * relationships, and enforcement of display ordering constraints. The
   * operation automatically sets creation timestamps and applies default
   * configuration settings based on channel policies.
   *
   * This endpoint creates records in the shopping_mall_sections table from the
   * Prisma schema, establishing the necessary relationships with parent
   * channels and maintaining referential integrity. The created section becomes
   * immediately available for product assignment and customer navigation based
   * on its status configuration.
   *
   * @param connection
   * @param channelCode Unique business identifier code of the target shopping
   *   channel where the section will be created (global scope)
   * @param body Section creation data including organizational details and
   *   configuration settings
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("channelCode")
    channelCode: string,
    @TypedBody()
    body: IShoppingMallSection.ICreate,
  ): Promise<IShoppingMallSection> {
    try {
      return await postShoppingMallAdminChannelsChannelCodeSections({
        admin,
        channelCode,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a paginated and filtered list of sections within a specific
   * shopping channel. This operation provides advanced search capabilities for
   * finding sections based on multiple criteria including name matching, status
   * filtering, display order ranges, and hierarchical relationships.
   *
   * This operation targets the shopping_mall_sections table in the Prisma
   * schema and returns sections that belong to the specified channel. The
   * operation supports comprehensive pagination with configurable page sizes
   * and sorting options. Sections can be sorted by display order, creation
   * date, name, or other relevant fields in ascending or descending order.
   *
   * The search functionality allows filtering by section status, parent section
   * relationships, and creation date ranges. Complex queries can combine
   * multiple criteria to find specific section groupings or organizational
   * structures within the channel. The operation validates that the target
   * channel exists and is accessible before performing the section search.
   *
   * Security considerations include appropriate access controls based on
   * channel visibility settings. The response includes section summary
   * information optimized for list displays, with options to include additional
   * hierarchical relationship data based on authorization level. This operation
   * is essential for channel management interfaces and section navigation
   * systems.
   *
   * @param connection
   * @param channelCode Unique channel code identifier of the target channel
   *   containing the sections
   * @param body Search criteria and pagination parameters for section filtering
   *   within the channel
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("channelCode")
    channelCode: string,
    @TypedBody()
    body: IShoppingMallSection.IRequest,
  ): Promise<IPageIShoppingMallSection.ISummary> {
    try {
      return await patchShoppingMallAdminChannelsChannelCodeSections({
        admin,
        channelCode,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing section within a specific shopping channel.
   *
   * This operation allows administrators to modify the configuration and
   * properties of a shopping mall section that belongs to a specific channel.
   * The section is identified by its unique code within the parent channel
   * context, ensuring proper scoping and access control.
   *
   * The operation validates that both the channel and section exist and are
   * accessible. It updates section properties including display name,
   * description, display order, status, and configuration settings. All updates
   * are validated against business rules and channel-specific constraints.
   *
   * Security considerations include authorization checks to ensure only users
   * with appropriate permissions can modify section configurations. The
   * operation maintains data integrity by preserving relationships and ensuring
   * consistent hierarchical structures.
   *
   * This operation integrates with the shopping_mall_sections table as defined
   * in the Prisma schema, incorporating all available section fields and
   * maintaining referential integrity with the parent channel.
   *
   * @param connection
   * @param channelCode Unique business identifier code of the target shopping
   *   channel (global scope)
   * @param sectionCode Unique business identifier code of the target section
   *   within the channel (scoped to channel)
   * @param body Section update data with modified properties
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":sectionCode")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("channelCode")
    channelCode: string,
    @TypedParam("sectionCode")
    sectionCode: string,
    @TypedBody()
    body: IShoppingMallSection.IUpdate,
  ): Promise<IShoppingMallSection> {
    try {
      return await putShoppingMallAdminChannelsChannelCodeSectionsSectionCode({
        admin,
        channelCode,
        sectionCode,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a section from a specific shopping channel.
   *
   * This operation performs a hard deletion of a shopping mall section,
   * completely removing it from the database along with all associated data.
   * The section is identified by its unique code within the parent channel
   * context, ensuring proper scoping and preventing accidental deletion of
   * sections from other channels.
   *
   * The operation validates that both the channel and section exist before
   * proceeding with deletion. It performs comprehensive integrity checks to
   * ensure no active products or sub-sections depend on the target section. If
   * dependencies exist, the operation will fail with appropriate error
   * messages.
   *
   * Security considerations include authorization verification to ensure only
   * users with administrative privileges can delete sections. The operation
   * maintains audit trails through system logging but does not preserve the
   * deleted section data for recovery purposes.
   *
   * This operation integrates with the shopping_mall_sections table as defined
   * in the Prisma schema, ensuring complete removal of the section record and
   * maintaining database consistency.
   *
   * @param connection
   * @param channelCode Unique business identifier code of the target shopping
   *   channel (global scope)
   * @param sectionCode Unique business identifier code of the target section
   *   within the channel (scoped to channel)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":sectionCode")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("channelCode")
    channelCode: string,
    @TypedParam("sectionCode")
    sectionCode: string,
  ): Promise<void> {
    try {
      return await deleteShoppingMallAdminChannelsChannelCodeSectionsSectionCode(
        {
          admin,
          channelCode,
          sectionCode,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
