import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";

import { IShoppingMallPromotion } from "../../../../../api/structures/IShoppingMallPromotion";

@Controller(
  "/shoppingMall/admin/channels/:channelCode/promotions/:promotionName",
)
export class ShoppingmallAdminChannelsPromotionsController {
  /**
   * Permanently delete a marketing promotion from the shopping mall platform.
   *
   * This operation removes a specific promotion identified by its unique name
   * within a specific channel from the promotions table. The deletion respects
   * the composite unique constraint that requires channel context for promotion
   * identification. The operation performs a soft delete by setting the
   * deleted_at timestamp, preserving the promotion record for audit purposes
   * while excluding it from normal queries.
   *
   * The operation validates that the promotion exists within the specified
   * channel and that the requesting administrator has appropriate permissions
   * to delete promotions. It also checks that the promotion is not currently
   * active or scheduled for future activation to prevent disruption of active
   * marketing campaigns.
   *
   * Security considerations include verifying administrator permissions and
   * ensuring that only authorized users can delete promotions. The operation
   * logs the deletion event for audit purposes and updates related entities
   * that may reference the promotion.
   *
   * This operation integrates with the shopping_mall_promotions table as
   * defined in the Prisma schema, handling all promotion fields and
   * relationships. The soft delete pattern uses the deleted_at field to mark
   * promotions as deleted while preserving historical data. Related operations
   * include creating promotions (POST /promotions), updating promotions (PUT
   * /promotions/{promotionName}), and searching promotions (PATCH
   * /promotions).
   *
   * @param connection
   * @param channelCode Unique business identifier code of the target channel
   *   where the promotion exists (global scope)
   * @param promotionName Unique name identifier of the target promotion within
   *   the specified channel (scoped to channel)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("channelCode")
    channelCode: string,
    @TypedParam("promotionName")
    promotionName: string,
  ): Promise<IShoppingMallPromotion> {
    try {
      return await deleteShoppingMallAdminChannelsChannelCodePromotionsPromotionName(
        {
          admin,
          channelCode,
          promotionName,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
