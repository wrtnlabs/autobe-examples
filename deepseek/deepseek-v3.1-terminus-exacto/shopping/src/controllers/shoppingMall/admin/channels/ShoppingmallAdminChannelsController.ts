import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia from "typia";
import { postShoppingMallAdminChannels } from "../../../../providers/postShoppingMallAdminChannels";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { putShoppingMallAdminChannelsChannelCode } from "../../../../providers/putShoppingMallAdminChannelsChannelCode";
import { deleteShoppingMallAdminChannelsChannelCode } from "../../../../providers/deleteShoppingMallAdminChannelsChannelCode";

import { IShoppingMallChannel } from "../../../../api/structures/IShoppingMallChannel";

@Controller("/shoppingMall/admin/channels")
export class ShoppingmallAdminChannelsController {
  /**
   * Create a new shopping mall sales channel to categorize different shopping
   * experiences or market segments within the platform.
   *
   * This operation allows platform administrators to create distinct shopping
   * environments or marketplaces such as general retail, outlet stores,
   * specialty markets, or regional marketplaces. Each channel represents a
   * logical grouping that serves different customer segments or business models
   * with its own configuration settings, pricing strategies, and seller
   * eligibility requirements.
   *
   * The channel creation process validates the unique channel code identifier
   * to ensure no duplicates exist across the platform. The operation
   * automatically sets creation timestamps and initializes the channel with
   * default configuration settings based on the platform's systematic
   * configurations for consistent behavior across the marketplace ecosystem.
   *
   * Security considerations require that only authenticated administrators can
   * create new channels. The operation includes validation of all required
   * fields and ensures the channel status is set to an appropriate initial
   * state (typically 'planned' or 'active').
   *
   * @param connection
   * @param body Creation data for a new shopping mall sales channel
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallChannel.ICreate,
  ): Promise<IShoppingMallChannel> {
    try {
      return await postShoppingMallAdminChannels({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing shopping mall sales channel configuration and
   * properties.
   *
   * This operation allows platform administrators to modify channel settings,
   * including display name, description, operational status, and configuration
   * parameters. Channel updates can be performed to reflect changes in business
   * strategy, target market adjustments, or operational requirements.
   *
   * The operation validates that the target channel exists and ensures that
   * critical properties like the unique channel code cannot be modified once
   * created. Configuration updates are validated against the platform's
   * systematic configuration schema to maintain consistency across the
   * marketplace ecosystem.
   *
   * Security considerations require that only authenticated administrators can
   * modify channel properties. The operation automatically updates the
   * modification timestamp to track changes for version control and audit
   * purposes. Channel status transitions are validated to ensure proper
   * workflow adherence.
   *
   * Related operations include retrieving channel details (GET
   * /channels/{channelCode}) and listing all channels (PATCH /channels) for
   * comprehensive channel management.
   *
   * @param connection
   * @param channelCode Unique business identifier code of the target shopping
   *   mall channel (global scope)
   * @param body Update data for modifying shopping mall channel properties
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":channelCode")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("channelCode")
    channelCode: string,
    @TypedBody()
    body: IShoppingMallChannel.IUpdate,
  ): Promise<IShoppingMallChannel> {
    try {
      return await putShoppingMallAdminChannelsChannelCode({
        admin,
        channelCode,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a shopping channel from the platform. This operation
   * removes the channel and all associated sections, products, and
   * configurations from the system.
   *
   * This operation targets the shopping_mall_channels table in the Prisma
   * schema and performs a hard deletion of the channel record. The channel is
   * identified by its unique code identifier rather than UUID, providing a more
   * user-friendly API interface. The operation validates that the channel
   * exists and is not currently active before allowing deletion to prevent
   * disruption to ongoing operations.
   *
   * Security considerations require that only authorized administrators can
   * perform channel deletion operations. The operation includes comprehensive
   * validation to ensure referential integrity and prevent orphaned data. All
   * associated sections within the channel will be automatically deleted or
   * archived according to system configuration settings.
   *
   * The operation returns no response body upon successful completion,
   * following RESTful deletion patterns. Error responses provide detailed
   * information about deletion failures, including active dependencies or
   * permission issues that prevent the operation from completing.
   *
   * @param connection
   * @param channelCode Unique channel code identifier of the target channel to
   *   be deleted
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":channelCode")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("channelCode")
    channelCode: string,
  ): Promise<void> {
    try {
      return await deleteShoppingMallAdminChannelsChannelCode({
        admin,
        channelCode,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
