import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { patchShoppingMallAdminAnalyticsCustomerBehavior } from "../../../../../providers/patchShoppingMallAdminAnalyticsCustomerBehavior";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";

import { IShoppingMallCustomerAnalytics } from "../../../../../api/structures/IShoppingMallCustomerAnalytics";

@Controller("/shoppingMall/admin/analytics/customer-behavior")
export class ShoppingmallAdminAnalyticsCustomer_behaviorController {
  /**
   * Analyze customer behavior patterns and shopping trends across the shopping
   * mall platform.
   *
   * This operation provides detailed analytics about customer shopping
   * behaviors, including purchase patterns, product preferences, browsing
   * history, and engagement metrics. The analytics are computed by analyzing
   * data from multiple tables including Customers, Orders, Carts, and Product
   * views.
   *
   * The operation supports segmentation by customer demographics, purchase
   * frequency, average order value, and other behavioral characteristics. It
   * returns insights such as customer lifetime value, retention rates, product
   * affinity patterns, and shopping cart abandonment trends.
   *
   * Security and privacy considerations are paramount, as this operation
   * analyzes sensitive customer data. The results are aggregated and anonymized
   * to protect individual privacy while still providing valuable business
   * intelligence. Access is restricted to authorized administrators only.
   *
   * The analytics help platform administrators understand customer preferences,
   * optimize product offerings, improve user experience, and develop targeted
   * marketing strategies based on actual shopping behavior patterns observed
   * across the platform.
   *
   * @param connection
   * @param body Analytics parameters and customer segmentation criteria
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallCustomerAnalytics.IRequest,
  ): Promise<IShoppingMallCustomerAnalytics> {
    try {
      return await patchShoppingMallAdminAnalyticsCustomerBehavior({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
