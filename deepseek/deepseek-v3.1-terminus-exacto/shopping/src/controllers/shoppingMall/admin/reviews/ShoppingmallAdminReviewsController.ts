import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { deleteShoppingMallAdminReviewsReviewId } from "../../../../providers/deleteShoppingMallAdminReviewsReviewId";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";

@Controller("/shoppingMall/admin/reviews/:reviewId")
export class ShoppingmallAdminReviewsController {
  /**
   * Permanently delete a specific review from the shopping mall platform.
   *
   * This operation removes a review entity from the shopping_mall_reviews table
   * in the database. The review is identified by its unique UUID identifier and
   * is permanently deleted along with any associated rating data or metadata.
   * This operation should only be used when a review violates platform policies
   * or when the reviewer requests removal.
   *
   * Security considerations include verifying that the requesting user has
   * appropriate permissions to delete the review. Typically, only
   * administrators or the original reviewer should be able to delete reviews.
   * The operation validates that the review exists before attempting deletion
   * and returns appropriate error responses for invalid review IDs.
   *
   * This operation integrates with the shopping_mall_reviews table as defined
   * in the Prisma schema, ensuring all database constraints and relationships
   * are properly handled during deletion. The operation performs a hard delete,
   * completely removing the record from the database without soft deletion
   * functionality.
   *
   * Related operations include viewing reviews (GET /reviews/{reviewId}),
   * updating reviews (PUT /reviews/{reviewId}), and searching reviews (PATCH
   * /reviews).
   *
   * @param connection
   * @param reviewId Unique identifier of the target review to be deleted
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallAdminReviewsReviewId({
        admin,
        reviewId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
