import { Controller } from "@nestjs/common";
import { TypedRoute } from "@nestia/core";
import typia from "typia";
import { getShoppingMallAdminDashboardOverview } from "../../../../../providers/getShoppingMallAdminDashboardOverview";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";

import { IShoppingMallDashboardOverview } from "../../../../../api/structures/IShoppingMallDashboardOverview";

@Controller("/shoppingMall/admin/dashboard/overview")
export class ShoppingmallAdminDashboardController {
  /**
   * Retrieve comprehensive dashboard overview statistics for the shopping mall
   * platform.
   *
   * This operation provides aggregated business metrics and system statistics
   * for administrative oversight and business intelligence. The dashboard
   * overview includes key performance indicators across sales, customer
   * engagement, product inventory, and platform activity.
   *
   * The operation aggregates data from multiple Prisma schema tables including
   * shopping_mall_sales, shopping_mall_customers, shopping_mall_products, and
   * shopping_mall_orders to provide a holistic view of platform performance.
   * Metrics include total sales revenue, customer growth trends, product
   * inventory status, and order processing statistics.
   *
   * Security considerations ensure that only authorized administrators can
   * access this comprehensive business intelligence data. The operation
   * performs real-time aggregation of business metrics without storing
   * pre-computed values, ensuring data freshness and accuracy for
   * decision-making purposes.
   *
   * @param connection
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async overview(
    @AdminAuth()
    admin: AdminPayload,
  ): Promise<IShoppingMallDashboardOverview> {
    try {
      return await getShoppingMallAdminDashboardOverview({
        admin,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
