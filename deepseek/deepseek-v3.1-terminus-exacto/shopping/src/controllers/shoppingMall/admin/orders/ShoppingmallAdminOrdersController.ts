import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { putShoppingMallAdminOrdersOrderId } from "../../../../providers/putShoppingMallAdminOrdersOrderId";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { deleteShoppingMallAdminOrdersOrderId } from "../../../../providers/deleteShoppingMallAdminOrdersOrderId";

import { IShoppingMallOrder } from "../../../../api/structures/IShoppingMallOrder";

@Controller("/shoppingMall/admin/orders/:orderId")
export class ShoppingmallAdminOrdersController {
  /**
   * Update an existing shopping mall order with new information.
   *
   * This operation allows authorized users to modify an existing order in the
   * shopping mall system. The operation updates the order details including
   * status, shipping information, billing address, and other order attributes.
   * Only users with appropriate permissions can modify orders, typically
   * administrators or the original customer who placed the order.
   *
   * The operation validates that the order exists and that the requesting user
   * has permission to modify it. Updates are applied atomically and trigger
   * appropriate business logic such as status change notifications or inventory
   * adjustments. The operation maintains data integrity by ensuring all updates
   * comply with business rules and validation constraints.
   *
   * Security considerations include proper authorization checks to prevent
   * unauthorized order modifications. Rate limiting may apply to prevent abuse
   * of the update functionality. The operation integrates with the
   * shopping_mall_orders table as defined in the Prisma schema, ensuring all
   * field validations and constraints are respected.
   *
   * @param connection
   * @param orderId Unique identifier of the target order to update
   * @param body Updated order information with fields to modify
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallOrder.IUpdate,
  ): Promise<IShoppingMallOrder> {
    try {
      return await putShoppingMallAdminOrdersOrderId({
        admin,
        orderId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a shopping mall order from the system.
   *
   * This operation performs a hard deletion of an order record from the
   * shopping mall database. The operation is intended for administrative
   * purposes where complete removal of order data is required, such as for
   * compliance with data deletion requests or system cleanup operations. The
   * deletion is irreversible and removes all associated order data
   * permanently.
   *
   * Security is critical for this operation as it involves permanent data
   * removal. Only users with administrative privileges can execute order
   * deletions. The operation validates that the order exists and that no active
   * dependencies prevent its deletion. Appropriate audit logging is performed
   * to track deletion activities for compliance and security purposes.
   *
   * The operation integrates with the shopping_mall_orders table as defined in
   * the Prisma schema. Since this is a hard delete operation, it bypasses any
   * soft delete mechanisms and removes the record completely from the database.
   * Related entities such as order items and payment records may also be
   * removed through cascading deletion or separate cleanup processes.
   *
   * @param connection
   * @param orderId Unique identifier of the target order to delete
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallAdminOrdersOrderId({
        admin,
        orderId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
