import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallAdminOrdersOrderIdShipments } from "../../../../../providers/postShoppingMallAdminOrdersOrderIdShipments";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { putShoppingMallAdminOrdersOrderIdShipmentsShipmentId } from "../../../../../providers/putShoppingMallAdminOrdersOrderIdShipmentsShipmentId";
import { deleteShoppingMallAdminOrdersOrderIdShipmentsShipmentId } from "../../../../../providers/deleteShoppingMallAdminOrdersOrderIdShipmentsShipmentId";

import { IShoppingMallShipment } from "../../../../../api/structures/IShoppingMallShipment";

@Controller("/shoppingMall/admin/orders/:orderId/shipments")
export class ShoppingmallAdminOrdersShipmentsController {
  /**
   * Create a new shipment for a specific order in the shopping mall platform.
   *
   * This operation allows authorized users to create shipping records for
   * customer orders, tracking the complete delivery lifecycle from label
   * creation through final delivery. Each shipment represents a physical
   * package associated with an order and includes carrier selection, tracking
   * information, and delivery timelines.
   *
   * The operation validates that the target order exists and is in a shippable
   * state before creating the shipment record. It ensures proper carrier
   * integration by validating carrier codes and shipping methods against
   * supported options. The shipment creation process includes automatic
   * generation of tracking numbers and integration with carrier APIs for
   * real-time tracking capabilities.
   *
   * Security considerations require that only authorized users with shipment
   * management permissions can create shipments. Each shipment maintains a
   * complete audit trail and integrates with the order fulfillment workflow to
   * provide customers with delivery progress visibility.
   *
   * @param connection
   * @param orderId Unique identifier of the target order for shipment creation
   * @param body Shipment creation information including carrier details and
   *   shipping method
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallShipment.ICreate,
  ): Promise<IShoppingMallShipment> {
    try {
      return await postShoppingMallAdminOrdersOrderIdShipments({
        admin,
        orderId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing shipment record for a specific order with new carrier
   * information or delivery status.
   *
   * This operation allows authorized users to modify shipment details such as
   * carrier information, tracking numbers, shipping methods, and delivery
   * status updates. It supports scenarios like carrier changes, tracking number
   * updates, delivery confirmation, and shipping cost adjustments.
   *
   * The operation validates that both the target order and shipment exist and
   * maintains referential integrity throughout the update process. It ensures
   * that shipment status transitions follow valid workflow patterns (e.g.,
   * cannot revert from delivered to in_transit) and that critical fields like
   * tracking numbers maintain their uniqueness constraints.
   *
   * Security requires proper authorization for shipment management, with
   * additional validation to ensure users can only update shipments associated
   * with orders they have permission to manage. The operation provides
   * comprehensive error handling for invalid status transitions, duplicate
   * tracking numbers, and unauthorized access attempts.
   *
   * @param connection
   * @param orderId Unique identifier of the target order containing the
   *   shipment
   * @param shipmentId Unique identifier of the target shipment to be updated
   * @param body Updated shipment information including carrier details,
   *   tracking, and status
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":shipmentId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedParam("shipmentId")
    shipmentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallShipment.IUpdate,
  ): Promise<IShoppingMallShipment> {
    try {
      return await putShoppingMallAdminOrdersOrderIdShipmentsShipmentId({
        admin,
        orderId,
        shipmentId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a specific shipment associated with an order from the
   * shopping mall platform.
   *
   * This operation removes a shipment record completely from the database,
   * including all tracking information, carrier details, and delivery status.
   * The deletion is permanent and irreversible, removing the shipment from both
   * the Orders table relationship and the Shipments table itself.
   *
   * The operation validates that the specified shipment belongs to the
   * specified order before proceeding with deletion. This ensures referential
   * integrity and prevents accidental deletion of unrelated shipments. The
   * system performs a hard delete operation, completely removing the record
   * rather than marking it as deleted.
   *
   * Security considerations include verifying that the requesting user has
   * appropriate permissions to manage shipments for the specified order. The
   * operation should only be accessible to users with administrative privileges
   * or order management capabilities. Rate limiting applies to prevent abuse of
   * the deletion functionality.
   *
   * Related operations: View shipment details (GET
   * /orders/{orderId}/shipments/{shipmentId}), List shipments for order (PATCH
   * /orders/{orderId}/shipments).
   *
   * @param connection
   * @param orderId Unique identifier of the target order containing the
   *   shipment
   * @param shipmentId Unique identifier of the target shipment to be deleted
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":shipmentId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedParam("shipmentId")
    shipmentId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallAdminOrdersOrderIdShipmentsShipmentId({
        admin,
        orderId,
        shipmentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
