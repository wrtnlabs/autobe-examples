import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { patchShoppingMallAdminSearchGlobal } from "../../../../../providers/patchShoppingMallAdminSearchGlobal";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";

import { IPageIShoppingMallGlobalSearchResult } from "../../../../../api/structures/IPageIShoppingMallGlobalSearchResult";
import { IShoppingMallGlobalSearch } from "../../../../../api/structures/IShoppingMallGlobalSearch";

@Controller("/shoppingMall/admin/search/global")
export class ShoppingmallAdminSearchGlobalController {
  /**
   * Perform global search across multiple entities in the shopping mall
   * platform.
   *
   * This operation enables comprehensive search functionality that spans across
   * products, categories, customers, and other relevant entities within the
   * shopping mall ecosystem. Users can search for products by name or
   * description, categories by name, customers by name or email, and other
   * searchable content.
   *
   * The search operation supports advanced filtering, pagination, and sorting
   * capabilities to efficiently locate relevant information across the
   * platform. Results are categorized by entity type and include relevant
   * metadata to help users quickly identify the most relevant matches.
   *
   * Security considerations include appropriate access controls based on the
   * user's authorization level. Public users may see limited product and
   * category information, while authenticated users can access more detailed
   * results. Administrative users have access to comprehensive search results
   * including customer and order information.
   *
   * @param connection
   * @param body Global search criteria including search query, filters, and
   *   pagination parameters
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async search(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallGlobalSearch.IRequest,
  ): Promise<IPageIShoppingMallGlobalSearchResult> {
    try {
      return await patchShoppingMallAdminSearchGlobal({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
