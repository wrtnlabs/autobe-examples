import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia from "typia";
import { postShoppingMallAdminPromotions } from "../../../../providers/postShoppingMallAdminPromotions";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { patchShoppingMallAdminPromotions } from "../../../../providers/patchShoppingMallAdminPromotions";
import { getShoppingMallAdminPromotionsPromotionName } from "../../../../providers/getShoppingMallAdminPromotionsPromotionName";
import { putShoppingMallAdminPromotionsPromotionName } from "../../../../providers/putShoppingMallAdminPromotionsPromotionName";
import { deleteShoppingMallAdminPromotionsPromotionName } from "../../../../providers/deleteShoppingMallAdminPromotionsPromotionName";

import { IShoppingMallPromotion } from "../../../../api/structures/IShoppingMallPromotion";
import { IPageIShoppingMallPromotion } from "../../../../api/structures/IPageIShoppingMallPromotion";

@Controller("/shoppingMall/admin/promotions")
export class ShoppingmallAdminPromotionsController {
  /**
   * Create a new marketing promotion campaign in the shopping mall platform.
   *
   * This operation allows platform administrators to create new promotional
   * campaigns with specific start and end dates, target audiences, and discount
   * structures. The promotion can be associated with specific shopping
   * channels, products, or categories through promotion rules. The operation
   * validates that the promotion name is unique and ensures proper scheduling
   * constraints.
   *
   * Security considerations require that only authenticated administrators can
   * create promotions. The creator's identity is automatically tracked through
   * the administrator session context. The system validates that the promotion
   * dates are logical (start date before end date) and that the promotion type
   * is valid.
   *
   * This operation creates records in the shopping_mall_promotions table and
   * can optionally create associated promotion rules in the
   * shopping_mall_promotion_rules table. The created promotion becomes
   * immediately available for evaluation during customer checkout processes.
   *
   * Related operations: Update promotion (PUT /promotions/{promotionName}),
   * List promotions (PATCH /promotions), View promotion details (GET
   * /promotions/{promotionName}).
   *
   * @param connection
   * @param body Creation data for the new marketing promotion
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallPromotion.ICreate,
  ): Promise<IShoppingMallPromotion> {
    try {
      return await postShoppingMallAdminPromotions({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve a paginated list of shopping mall promotions with
   * advanced filtering capabilities.
   *
   * This operation allows platform administrators to search through all
   * marketing promotions and campaign definitions in the shopping mall system.
   * It supports complex filtering based on promotion type, active status, date
   * ranges, priority levels, and channel associations. The operation integrates
   * with the shopping_mall_promotions table from the Prisma schema and provides
   * comprehensive search functionality for campaign management.
   *
   * Administrators can filter promotions by their current status
   * (active/inactive), promotion type (sale, clearance, loyalty, seasonal,
   * etc.), date ranges (start_date and end_date), priority levels, and
   * associated shopping channels. The operation supports pagination with
   * configurable page sizes and sorting options based on creation date,
   * priority, or promotion name.
   *
   * Security considerations include restricting access to authorized
   * administrators only, as promotions contain sensitive marketing campaign
   * data. The operation validates all search parameters and ensures proper
   * authorization checks are performed before returning results. Related
   * operations include creating new promotions (POST /promotions) and viewing
   * individual promotion details (GET /promotions/{promotionName}).
   *
   * @param connection
   * @param body Search criteria and pagination parameters for promotion
   *   filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallPromotion.IRequest,
  ): Promise<IPageIShoppingMallPromotion.ISummary> {
    try {
      return await patchShoppingMallAdminPromotions({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information for a specific shopping mall promotion by its
   * unique name identifier.
   *
   * This operation allows platform administrators to view comprehensive details
   * of a specific marketing promotion campaign. It returns the complete
   * promotion record including name, description, promotion type, active
   * status, date ranges, priority level, and associated channel information.
   * The operation integrates with the shopping_mall_promotions table from the
   * Prisma schema and provides full promotion details for campaign management
   * and analysis.
   *
   * Administrators can access detailed promotion information including the
   * promotion's terms and benefits description, current active status, start
   * and end dates, priority level for conflict resolution, and any
   * channel-specific targeting. The operation also includes creator information
   * and creation timestamps for audit purposes.
   *
   * Security considerations require administrator-level access since promotions
   * contain sensitive marketing campaign data. The operation validates that the
   * promotion exists and that the requesting administrator has appropriate
   * permissions to view the promotion details. Related operations include
   * searching promotions (PATCH /promotions) and updating promotion information
   * (PUT /promotions/{promotionName}).
   *
   * @param connection
   * @param promotionName Unique name identifier of the target promotion (global
   *   scope)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":promotionName")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("promotionName")
    promotionName: string,
  ): Promise<IShoppingMallPromotion> {
    try {
      return await getShoppingMallAdminPromotionsPromotionName({
        admin,
        promotionName,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing marketing promotion campaign in the shopping mall
   * platform.
   *
   * This operation allows platform administrators to modify promotion details
   * including name, description, promotion type, scheduling dates, and active
   * status. The operation validates that the updated promotion name remains
   * unique (if changed) and ensures scheduling constraints are maintained.
   *
   * Security considerations require that only authenticated administrators can
   * update promotions. The operation tracks the updating administrator through
   * session context. The system validates that promotion dates remain logical
   * and that any changes to promotion rules maintain consistency.
   *
   * This operation updates records in the shopping_mall_promotions table based
   * on the unique promotion name identifier. Promotion rules associated with
   * the promotion can also be updated through separate operations.
   *
   * Related operations: Create promotion (POST /promotions), List promotions
   * (PATCH /promotions), View promotion details (GET
   * /promotions/{promotionName}).
   *
   * @param connection
   * @param promotionName Unique name identifier of the target promotion
   * @param body Update data for the existing marketing promotion
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":promotionName")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("promotionName")
    promotionName: string,
    @TypedBody()
    body: IShoppingMallPromotion.IUpdate,
  ): Promise<IShoppingMallPromotion> {
    try {
      return await putShoppingMallAdminPromotionsPromotionName({
        admin,
        promotionName,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a marketing promotion from the shopping mall platform.
   *
   * This operation removes a specific promotion identified by its unique name
   * from the promotions table. The deletion is permanent and cannot be
   * recovered, as promotions are critical marketing assets that should be
   * properly managed through their lifecycle.
   *
   * The operation validates that the promotion exists and that the requesting
   * administrator has appropriate permissions to delete promotions. It also
   * checks that the promotion is not currently active or scheduled for future
   * activation to prevent disruption of active marketing campaigns.
   *
   * Security considerations include verifying administrator permissions and
   * ensuring that only authorized users can delete promotions. The operation
   * logs the deletion event for audit purposes and updates related entities
   * that may reference the promotion.
   *
   * This operation integrates with the shopping_mall_promotions table as
   * defined in the Prisma schema, handling all promotion fields and
   * relationships. Related operations include creating promotions (POST
   * /promotions), updating promotions (PUT /promotions/{promotionName}), and
   * searching promotions (PATCH /promotions).
   *
   * @param connection
   * @param promotionName Unique name identifier of the target promotion to be
   *   deleted
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":promotionName")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("promotionName")
    promotionName: string,
  ): Promise<void> {
    try {
      return await deleteShoppingMallAdminPromotionsPromotionName({
        admin,
        promotionName,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
