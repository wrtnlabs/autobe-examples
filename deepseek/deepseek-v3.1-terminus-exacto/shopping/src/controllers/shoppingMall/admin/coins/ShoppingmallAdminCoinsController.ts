import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { patchShoppingMallAdminCoins } from "../../../../providers/patchShoppingMallAdminCoins";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";

import { IPageIShoppingMallCoin } from "../../../../api/structures/IPageIShoppingMallCoin";
import { IShoppingMallCoin } from "../../../../api/structures/IShoppingMallCoin";

@Controller("/shoppingMall/admin/coins")
export class ShoppingmallAdminCoinsController {
  /**
   * Search and filter coin account records across the shopping mall platform
   * with advanced query capabilities.
   *
   * This operation provides comprehensive search functionality for coin
   * accounts, allowing administrators to filter by actor type, coin type,
   * balance ranges, and account status. It supports pagination, sorting by
   * various fields, and complex query conditions to efficiently manage the
   * platform's digital currency system.
   *
   * The search respects the composite unique constraint @@unique([actor_type,
   * coin_type]) by requiring filtering parameters for proper scoping. Results
   * include current balance, total earned/spent metrics, and account
   * creation/update timestamps for comprehensive reporting.
   *
   * Security considerations include restricting access to authorized
   * administrators only, as coin account data contains sensitive financial
   * information. The operation supports performance optimization through
   * indexed queries on actor_type, coin_type, and balance fields.
   *
   * This operation integrates with the shopping_mall_coins table as defined in
   * the Prisma schema, providing access to all coin account fields and
   * supporting complex filtering scenarios. The request body includes filtering
   * parameters for actor_type and coin_type to ensure proper scoping of
   * results. Related operations include viewing individual coin accounts (GET
   * /coins/{accountId}) and managing coin transactions (POST /transactions).
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering coin
   *   accounts, including required actor_type and coin_type filters
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallCoin.IRequest,
  ): Promise<IPageIShoppingMallCoin.ISummary> {
    try {
      return await patchShoppingMallAdminCoins({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
