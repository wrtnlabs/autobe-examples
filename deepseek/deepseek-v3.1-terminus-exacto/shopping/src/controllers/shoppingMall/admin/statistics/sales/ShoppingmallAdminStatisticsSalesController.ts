import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { patchShoppingMallAdminStatisticsSales } from "../../../../../providers/patchShoppingMallAdminStatisticsSales";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";

import { IPageIShoppingMallSaleStatistics } from "../../../../../api/structures/IPageIShoppingMallSaleStatistics";
import { IShoppingMallSaleStatistics } from "../../../../../api/structures/IShoppingMallSaleStatistics";

@Controller("/shoppingMall/admin/statistics/sales")
export class ShoppingmallAdminStatisticsSalesController {
  /**
   * Retrieve comprehensive sales statistics and analytics data from the
   * shopping mall platform.
   *
   * This operation provides aggregated sales statistics by analyzing data from
   * the shopping_mall_sales table. It supports complex filtering, grouping, and
   * aggregation capabilities for business intelligence and reporting purposes.
   * Statistics include sales volume, revenue trends, commission calculations,
   * and performance metrics across different time periods and dimensions.
   *
   * The operation allows filtering by date ranges, sale status, customer
   * segments, seller performance, and product categories. It supports grouping
   * by various dimensions including daily, weekly, monthly, or custom time
   * periods, as well as by seller, customer, category, or product attributes.
   * The response includes aggregated metrics such as total sales amount,
   * average sale value, commission earnings, and performance indicators.
   *
   * Security considerations include appropriate data access controls based on
   * user roles. Administrators can access system-wide statistics, while sellers
   * can only view their own sales data. The operation integrates with the
   * shopping_mall_sales table and leverages relationships with customers,
   * sellers, and orders for comprehensive analytics.
   *
   * @param connection
   * @param body Sales statistics query parameters including filters, grouping
   *   options, and date ranges
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallSaleStatistics.IRequest,
  ): Promise<IPageIShoppingMallSaleStatistics> {
    try {
      return await patchShoppingMallAdminStatisticsSales({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
