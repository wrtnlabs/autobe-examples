import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { patchShoppingMallAdminStatisticsProducts } from "../../../../../providers/patchShoppingMallAdminStatisticsProducts";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";

import { IPageIShoppingMallProductStatistics } from "../../../../../api/structures/IPageIShoppingMallProductStatistics";
import { IShoppingMallProductStatistics } from "../../../../../api/structures/IShoppingMallProductStatistics";

@Controller("/shoppingMall/admin/statistics/products")
export class ShoppingmallAdminStatisticsProductsController {
  /**
   * Retrieve comprehensive product performance statistics and analytics data
   * from the shopping mall platform.
   *
   * This operation provides aggregated product statistics by analyzing data
   * from the shopping_mall_products table and related sales data. It supports
   * performance analysis, inventory insights, and product trend reporting for
   * business intelligence purposes. Statistics include sales performance,
   * inventory levels, pricing analysis, and customer engagement metrics across
   * the product catalog.
   *
   * The operation allows filtering by product categories, seller performance,
   * inventory status, pricing ranges, and sales performance metrics. It
   * supports grouping by various dimensions including product categories,
   * sellers, price segments, or custom attributes. The response includes
   * aggregated metrics such as total sales volume, revenue performance,
   * inventory turnover rates, and product popularity indicators.
   *
   * Security considerations include appropriate data access controls based on
   * user roles. Administrators can access system-wide product statistics, while
   * sellers can only view statistics for their own products. The operation
   * integrates with the shopping_mall_products table and leverages
   * relationships with categories, sellers, and sales data for comprehensive
   * product analytics.
   *
   * @param connection
   * @param body Product statistics query parameters including filters, grouping
   *   options, and performance metrics
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallProductStatistics.IRequest,
  ): Promise<IPageIShoppingMallProductStatistics> {
    try {
      return await patchShoppingMallAdminStatisticsProducts({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
