import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { patchShoppingMallAdminStatisticsOrders } from "../../../../../providers/patchShoppingMallAdminStatisticsOrders";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";

import { IShoppingMallOrderStatistics } from "../../../../../api/structures/IShoppingMallOrderStatistics";

@Controller("/shoppingMall/admin/statistics/orders")
export class ShoppingmallAdminStatisticsOrdersController {
  /**
   * Retrieve comprehensive order statistics and analytics for the shopping mall
   * platform.
   *
   * This operation provides aggregated statistical data about orders across the
   * platform, enabling administrators and sellers to analyze sales performance,
   * order patterns, and business trends. The statistics are computed by
   * analyzing data from the Orders table and related entities in the shopping
   * mall database.
   *
   * The operation supports filtering by date ranges, order status, customer
   * segments, and seller performance metrics. It returns aggregated data
   * including order counts, revenue totals, average order values, and
   * conversion rates over specified time periods.
   *
   * Security considerations include restricting access to authorized users
   * only, as order statistics contain sensitive business information. The
   * operation implements rate limiting to prevent excessive data requests and
   * maintains data privacy by aggregating results to protect individual
   * customer information.
   *
   * The statistics are computed in real-time from the Orders table and provide
   * insights into platform performance, helping stakeholders make data-driven
   * decisions about inventory management, marketing strategies, and operational
   * improvements.
   *
   * @param connection
   * @param body Search criteria and date range parameters for order statistics
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallOrderStatistics.IRequest,
  ): Promise<IShoppingMallOrderStatistics> {
    try {
      return await patchShoppingMallAdminStatisticsOrders({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
