import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia from "typia";
import { postShoppingMallAdminCoupons } from "../../../../providers/postShoppingMallAdminCoupons";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { patchShoppingMallAdminCoupons } from "../../../../providers/patchShoppingMallAdminCoupons";
import { putShoppingMallAdminCouponsCouponCode } from "../../../../providers/putShoppingMallAdminCouponsCouponCode";
import { deleteShoppingMallAdminCouponsCouponCode } from "../../../../providers/deleteShoppingMallAdminCouponsCouponCode";

import { IShoppingMallCoupon } from "../../../../api/structures/IShoppingMallCoupon";
import { IPageIShoppingMallCoupon } from "../../../../api/structures/IPageIShoppingMallCoupon";

@Controller("/shoppingMall/admin/coupons")
export class ShoppingmallAdminCouponsController {
  /**
   * Create a new coupon in the shopping mall platform with comprehensive
   * configuration options.
   *
   * This operation creates a new coupon entity in the shopping_mall_coupons
   * table with all necessary configuration parameters. It supports various
   * discount types including percentage-based discounts, fixed amount
   * reductions, and free shipping offers. The operation validates coupon
   * parameters including discount value ranges, validity periods, and usage
   * limits.
   *
   * Administrative security is enforced through required authentication and
   * authorization checks. Only platform administrators can create coupons, and
   * the operation automatically records the creating administrator and their
   * session for audit trail purposes. The system generates a unique uppercase
   * alphanumeric coupon code and ensures it doesn't conflict with existing
   * codes.
   *
   * Business logic includes validation of minimum order amounts, maximum
   * discount caps for percentage-based coupons, and proper configuration of
   * customer-specific and overall usage limits. The operation sets default
   * values for tracking fields like used_count and ensures proper timestamp
   * recording for created_at and updated_at fields.
   *
   * @param connection
   * @param body Coupon creation parameters including discount configuration,
   *   validity period, and usage limits
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallCoupon.ICreate,
  ): Promise<IShoppingMallCoupon> {
    try {
      return await postShoppingMallAdminCoupons({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve a filtered list of shopping mall coupons with advanced
   * filtering, sorting, and pagination capabilities.
   *
   * This operation provides comprehensive search functionality for the coupon
   * catalog, allowing administrators to find coupons based on various criteria
   * including coupon code, name, discount type, validity period, active status,
   * and usage statistics. The search supports complex filtering logic with
   * multiple conditions combined using AND/OR operators.
   *
   * Pagination is fully supported with configurable page sizes and cursor-based
   * navigation. Results can be sorted by creation date, validity period,
   * discount value, or usage count in ascending or descending order. The
   * operation returns coupon summary information optimized for list displays,
   * including essential details without sensitive administrative data.
   *
   * Security considerations include rate limiting for search operations and
   * appropriate access controls to ensure only authorized administrators can
   * search the coupon catalog. The operation integrates with the Coupons table
   * from the Prisma schema, incorporating all available coupon fields and
   * relationships.
   *
   * Related operations: Create coupon (POST /coupons), View coupon details (GET
   * /coupons/{couponId}), Update coupon (PUT /coupons/{couponId}).
   *
   * @param connection
   * @param body Search criteria and pagination parameters for coupon filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallCoupon.IRequest,
  ): Promise<IPageIShoppingMallCoupon.ISummary> {
    try {
      return await patchShoppingMallAdminCoupons({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing coupon's configuration and settings.
   *
   * This operation allows platform administrators to modify coupon properties
   * including discount values, validity periods, usage limits, and activation
   * status. The coupon is identified by its unique alphanumeric code rather
   * than UUID, making it easier for administrators to reference specific
   * coupons.
   *
   * When updating a coupon, administrators can modify the discount type
   * (percentage, fixed_amount, free_shipping), adjust discount values, change
   * validity periods, update usage limits, and toggle activation status. The
   * system validates that the new configuration doesn't conflict with existing
   * coupon usage and maintains data integrity.
   *
   * Security considerations require that only authenticated administrators with
   * appropriate permissions can modify coupons. The operation includes
   * validation checks to ensure coupon updates don't violate business rules or
   * create inconsistencies with existing coupon applications.
   *
   * The operation interacts with the shopping_mall_coupons table in the Prisma
   * schema, updating fields such as name, description, discount_type,
   * discount_value, validity periods, and usage limits while maintaining audit
   * trails through updated_at timestamps.
   *
   * @param connection
   * @param couponCode Unique business identifier code of the target coupon
   *   (global scope)
   * @param body Updated coupon configuration data with modified properties
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":couponCode")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("couponCode")
    couponCode: string,
    @TypedBody()
    body: IShoppingMallCoupon.IUpdate,
  ): Promise<IShoppingMallCoupon> {
    try {
      return await putShoppingMallAdminCouponsCouponCode({
        admin,
        couponCode,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently remove a coupon from the platform using soft deletion.
   *
   * This operation allows platform administrators to delete coupon definitions
   * from the shopping mall system. The deletion is performed using soft
   * deletion by setting the deleted_at timestamp, which preserves the coupon
   * record for audit purposes while removing it from active use.
   *
   * When a coupon is deleted, it becomes immediately unavailable for new
   * customer orders. However, the coupon record remains in the database with
   * its historical usage data intact. This approach maintains referential
   * integrity for existing orders that used the coupon while preventing future
   * coupon applications.
   *
   * Security considerations require that only authenticated administrators with
   * appropriate permissions can delete coupons. The operation includes
   * validation checks to ensure the coupon isn't currently in use by active
   * orders and that deletion doesn't violate business rules.
   *
   * The operation interacts with the shopping_mall_coupons table in the Prisma
   * schema, setting the deleted_at timestamp to mark the coupon as deleted
   * while preserving all other coupon data for historical reference and
   * reporting purposes.
   *
   * @param connection
   * @param couponCode Unique business identifier code of the target coupon
   *   (global scope)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":couponCode")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("couponCode")
    couponCode: string,
  ): Promise<void> {
    try {
      return await deleteShoppingMallAdminCouponsCouponCode({
        admin,
        couponCode,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
