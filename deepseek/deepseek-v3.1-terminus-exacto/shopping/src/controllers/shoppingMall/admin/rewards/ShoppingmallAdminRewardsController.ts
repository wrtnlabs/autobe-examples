import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { getShoppingMallAdminRewardsRewardId } from "../../../../providers/getShoppingMallAdminRewardsRewardId";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { putShoppingMallAdminRewardsRewardId } from "../../../../providers/putShoppingMallAdminRewardsRewardId";
import { deleteShoppingMallAdminRewardsRewardId } from "../../../../providers/deleteShoppingMallAdminRewardsRewardId";
import { postShoppingMallAdminRewards } from "../../../../providers/postShoppingMallAdminRewards";

import { IShoppingMallReward } from "../../../../api/structures/IShoppingMallReward";

@Controller("/shoppingMall/admin/rewards")
export class ShoppingmallAdminRewardsController {
  /**
   * Retrieve detailed information about a specific reward program from the
   * shopping mall platform.
   *
   * This operation fetches a single reward program entity by its unique
   * identifier, providing comprehensive details about the program's
   * configuration, earning rules, redemption rules, and validity periods. The
   * reward program represents a structured incentive system where customers can
   * earn coins based on specific conditions defined in the earning_rules JSON
   * configuration.
   *
   * Security considerations include ensuring that only authorized users can
   * access reward program details, particularly for programs that may contain
   * sensitive business logic or targeted customer segments. The operation
   * validates that the requested reward program exists and is accessible based
   * on the current user's permissions and program visibility settings.
   *
   * This operation integrates directly with the shopping_mall_rewards table in
   * the Prisma schema, returning all fields including the program name,
   * description, reward type, coin value, minimum purchase requirements,
   * maximum coin limits, and program validity dates. The response includes both
   * active and inactive programs, allowing for comprehensive program management
   * and historical tracking.
   *
   * @param connection
   * @param rewardId Unique identifier of the target reward program
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":rewardId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("rewardId")
    rewardId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallReward> {
    try {
      return await getShoppingMallAdminRewardsRewardId({
        admin,
        rewardId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing reward program definition with new configuration and
   * rules.
   *
   * This operation allows administrators to modify the properties of an
   * existing reward program in the shopping mall platform. The operation
   * updates the reward program's name, description, earning rules, redemption
   * rules, coin value, and validity periods based on the provided request body.
   * All updates are validated against business rules to ensure program
   * integrity.
   *
   * The operation performs comprehensive validation checks including ensuring
   * the reward program exists, validating the new configuration format,
   * checking for conflicts with existing programs, and verifying that the
   * updated program maintains consistency with active customer reward balances.
   * The updated reward program is immediately reflected in the system and
   * affects all future reward calculations.
   *
   * Security considerations include strict authorization checks to ensure only
   * authorized administrators can modify reward programs. The operation
   * maintains audit trails of all changes and ensures that existing customer
   * reward balances are not negatively impacted by the updates.
   *
   * @param connection
   * @param rewardId Unique identifier of the target reward program to update
   * @param body Updated reward program configuration and rules
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":rewardId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("rewardId")
    rewardId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallReward.IUpdate,
  ): Promise<IShoppingMallReward> {
    try {
      return await putShoppingMallAdminRewardsRewardId({
        admin,
        rewardId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Soft delete a reward program by setting the deletion timestamp while
   * preserving the record for audit purposes.
   *
   * This operation performs a soft deletion of the specified reward program by
   * setting the deleted_at timestamp to the current time. The program record is
   * preserved in the database but excluded from normal queries and operations.
   * This approach maintains audit trails and allows for potential restoration
   * if needed.
   *
   * Before deletion, the operation checks if the reward program is currently
   * active and whether any customers have earned coins through this program. If
   * the program is active or has customer associations, the deletion will fail
   * with appropriate error messages. Only inactive programs with no customer
   * associations can be soft deleted.
   *
   * Security measures ensure that only authorized administrators can perform
   * deletion operations. The operation maintains comprehensive audit trails for
   * compliance purposes and provides clear feedback on the deletion outcome.
   * Soft deletion allows for data recovery while ensuring the program is no
   * longer active in the system.
   *
   * @param connection
   * @param rewardId Unique identifier of the target reward program to delete
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":rewardId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("rewardId")
    rewardId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallAdminRewardsRewardId({
        admin,
        rewardId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Create a new reward program in the shopping mall platform with
   * comprehensive configuration settings.
   *
   * This operation allows administrators to define new reward programs that
   * customers can participate in to earn coins. Each reward program requires
   * detailed configuration including the program name, description, reward
   * type, earning rules, redemption rules, coin value, and validity periods.
   * The earning_rules and redemption_rules fields accept JSON configurations
   * that define the specific conditions and logic for coin earning and
   * redemption.
   *
   * Validation includes ensuring that the program name is unique across all
   * reward programs, that required fields are properly populated, and that the
   * validity period (valid_from and valid_until) follows logical chronological
   * ordering. The operation automatically sets creation timestamps and
   * initializes the program as active unless specified otherwise.
   *
   * Security considerations require that only administrators with appropriate
   * permissions can create reward programs, as these programs directly impact
   * the platform's incentive structure and customer engagement strategies. The
   * operation integrates with the shopping_mall_rewards table and ensures all
   * business rules for reward program creation are enforced.
   *
   * @param connection
   * @param body Configuration data for creating a new reward program
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallReward.ICreate,
  ): Promise<IShoppingMallReward> {
    try {
      return await postShoppingMallAdminRewards({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
