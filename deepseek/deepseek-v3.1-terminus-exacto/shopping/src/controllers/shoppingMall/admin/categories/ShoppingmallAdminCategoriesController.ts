import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallAdminCategories } from "../../../../providers/postShoppingMallAdminCategories";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { putShoppingMallAdminCategoriesCategoryId } from "../../../../providers/putShoppingMallAdminCategoriesCategoryId";
import { deleteShoppingMallAdminCategoriesCategoryId } from "../../../../providers/deleteShoppingMallAdminCategoriesCategoryId";

import { IShoppingMallCategory } from "../../../../api/structures/IShoppingMallCategory";

@Controller("/shoppingMall/admin/categories")
export class ShoppingmallAdminCategoriesController {
  /**
   * Create a new product category in the shopping mall's hierarchical category
   * system.
   *
   * This operation allows administrators to create new product categories that
   * can be used to organize products within the shopping mall platform.
   * Categories support hierarchical organization through parent-child
   * relationships, enabling multi-level product categorization for improved
   * navigation and discovery.
   *
   * The operation validates that the category name is unique across the system
   * and ensures proper hierarchical structure when a parent category is
   * specified. Category display order must be explicitly specified as the
   * display_order field is a required field in the database schema.
   *
   * Security considerations include restricting this operation to
   * administrative users only, as category management requires platform-level
   * permissions. The operation automatically sets creation timestamps and
   * ensures proper referential integrity for parent category relationships.
   *
   * Related operations include updating existing categories (PUT
   * /categories/{categoryId}) and retrieving category lists (PATCH
   * /categories).
   *
   * @param connection
   * @param body Category creation data including name, description, parent
   *   reference, and display properties
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallCategory.ICreate,
  ): Promise<IShoppingMallCategory> {
    try {
      return await postShoppingMallAdminCategories({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing product category in the shopping mall's hierarchical
   * category system.
   *
   * This operation allows administrators to modify category properties
   * including name, description, display order, active status, and parent-child
   * relationships. Category updates maintain referential integrity and ensure
   * that hierarchical structures remain valid after modifications.
   *
   * The operation validates that category name uniqueness is preserved across
   * updates and prevents circular references in parent-child relationships.
   * When updating parent references, the system ensures that the new parent
   * category exists and is not a descendant of the current category.
   *
   * Security considerations restrict this operation to administrative users
   * with category management permissions. The operation automatically updates
   * the modification timestamp and maintains audit trails of category changes
   * for administrative oversight.
   *
   * Related operations include creating new categories (POST /categories) and
   * retrieving category details (GET /categories/{categoryId}).
   *
   * @param connection
   * @param categoryId Unique identifier of the target category to update
   * @param body Category update data including modified properties and
   *   hierarchical relationships
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":categoryId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("categoryId")
    categoryId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallCategory.IUpdate,
  ): Promise<IShoppingMallCategory> {
    try {
      return await putShoppingMallAdminCategoriesCategoryId({
        admin,
        categoryId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a product category from the shopping mall catalog. This
   * operation removes the category record from the database and cannot be
   * undone.
   *
   * This operation targets the shopping_mall_categories table in the Prisma
   * schema, which stores hierarchical product category information. The
   * category must exist and be accessible for deletion to succeed. The
   * operation performs a hard delete, completely removing the category record
   * from the database.
   *
   * Security considerations include verifying that the requesting user has
   * appropriate administrative permissions to delete categories. The operation
   * validates that the category exists and is not currently referenced by any
   * products before allowing deletion. If the category has child categories or
   * associated products, the deletion will fail to maintain referential
   * integrity.
   *
   * Related operations include creating categories (POST /categories), updating
   * categories (PUT /categories/{categoryId}), and listing categories (PATCH
   * /categories). This operation should be used cautiously as it permanently
   * removes category data from the system.
   *
   * @param connection
   * @param categoryId Unique identifier of the target category to be deleted
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":categoryId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("categoryId")
    categoryId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallAdminCategoriesCategoryId({
        admin,
        categoryId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
