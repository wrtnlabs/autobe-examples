import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { patchShoppingMallAdminCarts } from "../../../../providers/patchShoppingMallAdminCarts";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";

import { IPageIShoppingMallCart } from "../../../../api/structures/IPageIShoppingMallCart";
import { IShoppingMallCart } from "../../../../api/structures/IShoppingMallCart";

@Controller("/shoppingMall/admin/carts")
export class ShoppingmallAdminCartsController {
  /**
   * Search and retrieve shopping cart sessions with advanced filtering and
   * pagination capabilities.
   *
   * This operation provides comprehensive search functionality for shopping
   * cart sessions stored in the shopping_mall_carts table. It supports
   * filtering by cart status (active, abandoned, converted, expired), customer
   * session associations, date ranges, and applied coupon codes. The operation
   * is designed for administrative oversight and customer service scenarios
   * where cart analytics and session management are required.
   *
   * Search capabilities include filtering by creation date ranges, status
   * changes, expiration timelines, and shipping method selections. Pagination
   * parameters allow for efficient browsing of large cart datasets while
   * maintaining performance. The operation returns summarized cart information
   * optimized for list displays, including key metadata like status, expiration
   * dates, and session context.
   *
   * Security considerations ensure that customers can only search their own
   * cart sessions, while administrative users may access broader cart data for
   * system analytics and abandoned cart recovery initiatives. The operation
   * supports complex query structures while maintaining data privacy and access
   * control boundaries.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for cart filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallCart.IRequest,
  ): Promise<IPageIShoppingMallCart.ISummary> {
    try {
      return await patchShoppingMallAdminCarts({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
