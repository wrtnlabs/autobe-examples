import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { patchShoppingMallRewards } from "../../../providers/patchShoppingMallRewards";

import { IPageIShoppingMallReward } from "../../../api/structures/IPageIShoppingMallReward";
import { IShoppingMallReward } from "../../../api/structures/IShoppingMallReward";

@Controller("/shoppingMall/rewards")
export class ShoppingmallRewardsController {
  /**
   * Search and retrieve a filtered list of reward programs from the shopping
   * mall platform.
   *
   * This operation provides advanced search capabilities for finding reward
   * programs based on multiple criteria including reward type, program status,
   * validity dates, and program name matching. The operation supports
   * comprehensive pagination with configurable page sizes and sorting options.
   * Users can sort by creation date, validity period, or program name in
   * ascending or descending order.
   *
   * Security considerations include appropriate filtering of reward program
   * information based on the requesting user's authorization level. Only active
   * reward programs are returned by default, with optional filters to include
   * inactive or expired programs for administrative purposes. Rate limiting
   * applies to prevent excessive search operations.
   *
   * This operation integrates with the shopping_mall_rewards table as defined
   * in the Prisma schema, incorporating all available reward program fields
   * including name, description, reward_type, earning_rules, redemption_rules,
   * coin_value, and program validity periods. The response includes reward
   * program summary information optimized for list displays.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for reward program
   *   filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IShoppingMallReward.IRequest,
  ): Promise<IPageIShoppingMallReward.ISummary> {
    try {
      return await patchShoppingMallRewards({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
