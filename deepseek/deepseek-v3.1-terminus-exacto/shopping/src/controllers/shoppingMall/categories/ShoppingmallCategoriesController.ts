import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallCategories } from "../../../providers/patchShoppingMallCategories";
import { getShoppingMallCategoriesCategoryId } from "../../../providers/getShoppingMallCategoriesCategoryId";

import { IPageIShoppingMallCategory } from "../../../api/structures/IPageIShoppingMallCategory";
import { IShoppingMallCategory } from "../../../api/structures/IShoppingMallCategory";

@Controller("/shoppingMall/categories")
export class ShoppingmallCategoriesController {
  /**
   * Search and retrieve a paginated list of product categories from the
   * shopping mall catalog.
   *
   * This operation allows users to search through the hierarchical category
   * system with advanced filtering capabilities. Users can filter by category
   * name, parent category relationships, active status, and display order. The
   * operation supports comprehensive pagination with configurable page sizes
   * and sorting options, allowing sorting by display order, creation date, or
   * alphabetical order.
   *
   * The search functionality implements partial matching on category names and
   * descriptions, making it easy to find relevant categories. The response
   * includes category summary information optimized for list displays,
   * including hierarchical relationships for proper navigation context.
   *
   * Security considerations include appropriate filtering of soft-deleted
   * categories and access control based on user permissions. Only active
   * categories are returned by default, with administrators having the ability
   * to include inactive categories in search results.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for category
   *   filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IShoppingMallCategory.IRequest,
  ): Promise<IPageIShoppingMallCategory.ISummary> {
    try {
      return await patchShoppingMallCategories({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information for a specific product category in the
   * shopping mall catalog.
   *
   * This operation provides comprehensive details about a single category,
   * including its hierarchical relationships, metadata, and current status. The
   * response includes the category's parent relationship information for proper
   * navigation context within the category hierarchy.
   *
   * Detailed information includes the category name, description, display
   * order, active status, creation and modification timestamps. The operation
   * validates that the requested category exists and is accessible before
   * returning the detailed information.
   *
   * Security considerations ensure that soft-deleted categories are not
   * accessible through this endpoint unless the user has appropriate
   * administrative permissions. The operation provides proper error handling
   * for non-existent categories or access violations.
   *
   * @param connection
   * @param categoryId Unique identifier of the target category
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":categoryId")
  public async at(
    @TypedParam("categoryId")
    categoryId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallCategory> {
    try {
      return await getShoppingMallCategoriesCategoryId({
        categoryId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
