import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia from "typia";
import { patchShoppingMallCoupons } from "../../../providers/patchShoppingMallCoupons";
import { AdminAuth } from "../../../decorators/AdminAuth";
import { AdminPayload } from "../../../decorators/payload/AdminPayload";
import { getShoppingMallCouponsCouponCode } from "../../../providers/getShoppingMallCouponsCouponCode";

import { IPageIShoppingMallCoupon } from "../../../api/structures/IPageIShoppingMallCoupon";
import { IShoppingMallCoupon } from "../../../api/structures/IShoppingMallCoupon";

@Controller("/shoppingMall/coupons")
export class ShoppingmallCouponsController {
  /**
   * Search and retrieve a filtered list of shopping mall coupons with advanced
   * filtering, sorting, and pagination capabilities.
   *
   * This operation provides comprehensive search functionality for the coupon
   * catalog, allowing administrators to find coupons based on various criteria
   * including coupon code, name, discount type, validity period, active status,
   * and usage statistics. The search supports complex filtering logic with
   * multiple conditions combined using AND/OR operators.
   *
   * Pagination is fully supported with configurable page sizes and cursor-based
   * navigation. Results can be sorted by creation date, validity period,
   * discount value, or usage count in ascending or descending order. The
   * operation returns coupon summary information optimized for list displays,
   * including essential details without sensitive administrative data.
   *
   * Security considerations include rate limiting for search operations and
   * appropriate access controls to ensure only authorized administrators can
   * search the coupon catalog. The operation integrates with the Coupons table
   * from the Prisma schema, incorporating all available coupon fields and
   * relationships.
   *
   * Related operations: Create coupon (POST /coupons), View coupon details (GET
   * /coupons/{couponId}), Update coupon (PUT /coupons/{couponId}).
   *
   * @param connection
   * @param body Search criteria and pagination parameters for coupon filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallCoupon.IRequest,
  ): Promise<IPageIShoppingMallCoupon.ISummary> {
    try {
      return await patchShoppingMallCoupons({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific coupon using its unique
   * coupon code.
   *
   * This operation fetches complete coupon information from the
   * shopping_mall_coupons table in the Prisma schema. It returns all coupon
   * details including discount type, value, validity period, usage limits, and
   * configuration settings. The coupon is identified by its unique uppercase
   * alphanumeric code that customers enter during checkout.
   *
   * Security considerations include validating that the coupon is currently
   * active and within its validity period. The operation checks the coupon's
   * is_active flag and ensures the current datetime falls between valid_from
   * and valid_until dates. Only active and valid coupons are returned to
   * prevent displaying expired or inactive coupons to users.
   *
   * This operation integrates with the shopping_mall_coupons table as defined
   * in the Prisma schema, incorporating all available coupon fields including
   * relationships to channels and administrators. The response includes the
   * complete coupon object with all configuration details needed for proper
   * coupon application during checkout processes.
   *
   * @param connection
   * @param couponCode Unique uppercase alphanumeric coupon code that identifies
   *   the target coupon (global scope)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":couponCode")
  public async at(
    @TypedParam("couponCode")
    couponCode: string,
  ): Promise<IShoppingMallCoupon> {
    try {
      return await getShoppingMallCouponsCouponCode({
        couponCode,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
