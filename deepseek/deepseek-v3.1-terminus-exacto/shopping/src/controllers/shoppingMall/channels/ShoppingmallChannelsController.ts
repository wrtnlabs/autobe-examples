import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia from "typia";
import { patchShoppingMallChannels } from "../../../providers/patchShoppingMallChannels";
import { getShoppingMallChannelsChannelCode } from "../../../providers/getShoppingMallChannelsChannelCode";

import { IPageIShoppingMallChannel } from "../../../api/structures/IPageIShoppingMallChannel";
import { IShoppingMallChannel } from "../../../api/structures/IShoppingMallChannel";

@Controller("/shoppingMall/channels")
export class ShoppingmallChannelsController {
  /**
   * Retrieve a filtered and paginated list of shopping mall channels from the
   * system. This operation operates on the shopping_mall_channels table from
   * the Prisma schema and provides advanced search capabilities for finding
   * channels based on multiple criteria including channel code, name, status,
   * and creation date ranges.
   *
   * The operation supports comprehensive pagination with configurable page
   * sizes and sorting options. Channels can be sorted by creation date, update
   * date, channel name, or status in ascending or descending order. The search
   * functionality allows filtering by channel status (active, inactive,
   * maintenance, planned) and partial matching on channel names and
   * descriptions.
   *
   * Security considerations include appropriate filtering based on the
   * requesting user's authorization level. Channel visibility may be restricted
   * based on platform configuration and user permissions. The operation
   * integrates with the shopping_mall_channels table as defined in the Prisma
   * schema, incorporating all available channel fields and relationships.
   *
   * The response includes channel summary information optimized for list
   * displays, with options to include additional details based on authorization
   * level. This endpoint is essential for platform administrators managing
   * channel configurations and for customers browsing available shopping
   * channels.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for channel filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IShoppingMallChannel.IRequest,
  ): Promise<IPageIShoppingMallChannel.ISummary> {
    try {
      return await patchShoppingMallChannels({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information for a specific shopping mall channel
   * identified by its unique channel code. This operation accesses the
   * shopping_mall_channels table from the Prisma schema and returns
   * comprehensive channel details including configuration settings, operational
   * status, and metadata.
   *
   * The channel code parameter must match an existing channel's unique
   * identifier code. The operation validates that the channel exists and is
   * accessible based on the requesting user's permissions. Channel status
   * determines whether the channel information is returned - inactive or
   * maintenance channels may have restricted visibility depending on platform
   * configuration.
   *
   * This endpoint provides complete channel information including the JSON
   * configuration object that stores channel-specific settings, policies, and
   * operational parameters. The response includes timestamps for creation,
   * updates, and any deletion status for audit purposes.
   *
   * Security considerations ensure that sensitive channel configuration details
   * are only accessible to authorized users with appropriate permissions. The
   * operation serves both administrative functions for channel management and
   * customer-facing features for channel discovery and selection.
   *
   * @param connection
   * @param channelCode Unique business identifier code of the target shopping
   *   channel (global scope)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":channelCode")
  public async at(
    @TypedParam("channelCode")
    channelCode: string,
  ): Promise<IShoppingMallChannel> {
    try {
      return await getShoppingMallChannelsChannelCode({
        channelCode,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
