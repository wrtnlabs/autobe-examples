import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia from "typia";
import { getShoppingMallChannelsChannelCodeSectionsSectionCode } from "../../../../providers/getShoppingMallChannelsChannelCodeSectionsSectionCode";

import { IShoppingMallSection } from "../../../../api/structures/IShoppingMallSection";

@Controller("/shoppingMall/channels/:channelCode/sections/:sectionCode")
export class ShoppingmallChannelsSectionsController {
  /**
   * Retrieve detailed information about a specific shopping mall section within
   * a designated channel.
   *
   * This operation returns the complete configuration and metadata for a
   * shopping mall section, including its display properties, organizational
   * hierarchy, and operational status. The section is uniquely identified by
   * the combination of channel code and section code, ensuring precise
   * targeting within the hierarchical structure of the shopping mall platform.
   *
   * Security considerations include validating that the requesting user has
   * appropriate permissions to view the section details based on their role and
   * the section's visibility settings. The operation performs validation checks
   * to ensure both the channel and section exist and are accessible before
   * returning the detailed information.
   *
   * This endpoint integrates with the shopping_mall_sections table from the
   * Prisma schema, providing access to all section attributes including
   * hierarchical relationships, display ordering, and configuration settings.
   * The response includes comprehensive section data for use in administrative
   * interfaces and customer-facing applications.
   *
   * @param connection
   * @param channelCode Unique business identifier code of the target shopping
   *   channel (global scope)
   * @param sectionCode Unique business identifier code of the target section
   *   within the channel (scoped to channel)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @TypedParam("channelCode")
    channelCode: string,
    @TypedParam("sectionCode")
    sectionCode: string,
  ): Promise<IShoppingMallSection> {
    try {
      return await getShoppingMallChannelsChannelCodeSectionsSectionCode({
        channelCode,
        sectionCode,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
