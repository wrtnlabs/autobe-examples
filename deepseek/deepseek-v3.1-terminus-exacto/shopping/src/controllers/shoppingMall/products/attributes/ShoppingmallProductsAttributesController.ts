import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallProductsProductIdAttributes } from "../../../../providers/patchShoppingMallProductsProductIdAttributes";
import { getShoppingMallProductsProductIdAttributesAttributeId } from "../../../../providers/getShoppingMallProductsProductIdAttributesAttributeId";

import { IPageIShoppingMallProductAttribute } from "../../../../api/structures/IPageIShoppingMallProductAttribute";
import { IShoppingMallProductAttribute } from "../../../../api/structures/IShoppingMallProductAttribute";

@Controller("/shoppingMall/products/:productId/attributes")
export class ShoppingmallProductsAttributesController {
  /**
   * Search and retrieve product attributes associated with a specific product
   * in the shopping mall catalog.
   *
   * This operation allows users to search through the attributes of a specific
   * product using advanced filtering, sorting, and pagination capabilities. The
   * attributes are retrieved from the shopping_mall_product_attributes table,
   * which stores detailed product specifications and characteristics.
   *
   * The operation supports filtering by attribute name, attribute value, and
   * display order. Users can search for specific attribute patterns using
   * partial matching and can sort results by display order or attribute name.
   * Pagination ensures efficient retrieval of large attribute sets.
   *
   * Security considerations include product visibility checks to ensure users
   * can only access attributes of products that are publicly available or
   * accessible based on their permissions. The operation validates that the
   * specified product exists and is accessible before retrieving its
   * attributes.
   *
   * This operation integrates with the shopping_mall_product_attributes table
   * as defined in the Prisma schema, incorporating all available attribute
   * fields including attribute_name, attribute_value, display_order, and
   * timestamps. The response includes attribute summary information optimized
   * for list displays.
   *
   * @param connection
   * @param productId Unique identifier of the target product
   * @param body Search criteria and pagination parameters for product attribute
   *   filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallProductAttribute.IRequest,
  ): Promise<IPageIShoppingMallProductAttribute.ISummary> {
    try {
      return await patchShoppingMallProductsProductIdAttributes({
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific product attribute in the
   * shopping mall catalog.
   *
   * This operation returns complete details for a specific attribute associated
   * with a product, including the attribute name, value, display order, and
   * creation timestamps. The attribute is retrieved from the
   * shopping_mall_product_attributes table based on the provided product and
   * attribute identifiers.
   *
   * The operation validates that both the product and attribute exist and are
   * accessible to the requesting user. It ensures that the attribute belongs to
   * the specified product and performs necessary permission checks based on
   * product visibility settings.
   *
   * This detailed view is useful for product management interfaces, attribute
   * editing workflows, and displaying comprehensive product specifications to
   * customers. The operation provides the complete attribute record as stored
   * in the database.
   *
   * Security considerations include proper access control to ensure users can
   * only view attributes of products they are authorized to access. The
   * operation integrates with the shopping_mall_product_attributes table as
   * defined in the Prisma schema, returning all attribute fields including
   * technical specifications and metadata.
   *
   * @param connection
   * @param productId Unique identifier of the target product
   * @param attributeId Unique identifier of the target product attribute
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":attributeId")
  public async at(
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedParam("attributeId")
    attributeId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallProductAttribute> {
    try {
      return await getShoppingMallProductsProductIdAttributesAttributeId({
        productId,
        attributeId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
