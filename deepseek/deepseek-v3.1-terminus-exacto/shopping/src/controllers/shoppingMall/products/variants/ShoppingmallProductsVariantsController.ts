import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { getShoppingMallProductsProductIdVariantsVariantId } from "../../../../providers/getShoppingMallProductsProductIdVariantsVariantId";

import { IShoppingMallProductVariant } from "../../../../api/structures/IShoppingMallProductVariant";

@Controller("/shoppingMall/products/:productId/variants/:variantId")
export class ShoppingmallProductsVariantsController {
  /**
   * Retrieve detailed information about a specific product variant from the
   * shopping mall product catalog.
   *
   * This operation fetches comprehensive details for a single product variant
   * identified by its unique identifier. The variant belongs to a specific
   * product and contains variant-specific information such as pricing,
   * inventory, attributes, and availability status.
   *
   * Product variants represent different configurations of the same base
   * product, such as size variations, color options, or style differences. Each
   * variant can have unique pricing, stock levels, and attribute combinations
   * while sharing the same core product information.
   *
   * Security considerations include proper access control to ensure only
   * authorized users can view product variant details. The operation validates
   * that both the parent product and variant exist and are accessible before
   * returning the detailed information.
   *
   * This operation integrates with the Product Variants table from the Prisma
   * schema, providing access to all variant-specific fields including pricing
   * overrides, inventory tracking, and attribute configurations stored as JSON
   * data.
   *
   * @param connection
   * @param productId Unique identifier of the parent product that contains the
   *   target variant
   * @param variantId Unique identifier of the specific product variant to
   *   retrieve
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedParam("variantId")
    variantId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallProductVariant> {
    try {
      return await getShoppingMallProductsProductIdVariantsVariantId({
        productId,
        variantId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
