import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallProducts } from "../../../providers/patchShoppingMallProducts";
import { getShoppingMallProductsProductId } from "../../../providers/getShoppingMallProductsProductId";

import { IPageIShoppingMallProduct } from "../../../api/structures/IPageIShoppingMallProduct";
import { IShoppingMallProduct } from "../../../api/structures/IShoppingMallProduct";

@Controller("/shoppingMall/products")
export class ShoppingmallProductsController {
  /**
   * Search and retrieve a paginated list of products from the shopping mall
   * catalog with advanced filtering and sorting capabilities. This operation
   * provides comprehensive product search functionality across the entire
   * product catalog.
   *
   * This operation targets the shopping_mall_products table in the Prisma
   * schema, which contains detailed product information including pricing,
   * inventory, categorization, and seller details. The search supports
   * filtering by multiple criteria such as category, price range, stock
   * availability, product status, seller information, and text search across
   * product names and descriptions.
   *
   * The operation includes robust pagination with configurable page sizes and
   * sorting options. Users can sort products by price, creation date,
   * popularity, or other relevant metrics. Advanced search capabilities include
   * full-text search using PostgreSQL's GIN indexes on product names and
   * descriptions for optimal performance.
   *
   * Security considerations ensure that only active and approved products are
   * returned in search results. The operation respects product visibility
   * settings and seller status to provide accurate, filtered results. Related
   * operations include retrieving individual product details (GET
   * /products/{productId}) and creating new products (POST /products).
   *
   * @param connection
   * @param body Search criteria and pagination parameters for product filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IShoppingMallProduct.IRequest,
  ): Promise<IPageIShoppingMallProduct.ISummary> {
    try {
      return await patchShoppingMallProducts({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific product from the shopping
   * mall catalog.
   *
   * This operation fetches comprehensive product details including pricing,
   * inventory status, seller information, and product specifications. The
   * product is identified by its unique UUID identifier which must exist in the
   * shopping_mall_products table.
   *
   * Security considerations include public access to product information for
   * browsing purposes. No authentication is required to view product details as
   * this supports customer shopping experiences. The operation validates that
   * the product exists and is in an active status before returning data.
   *
   * This operation integrates with the shopping_mall_products table as defined
   * in the Prisma schema, returning all available product fields including
   * name, description, pricing, inventory status, and related category and
   * seller information through foreign key relationships.
   *
   * @param connection
   * @param productId Unique identifier of the target product
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":productId")
  public async at(
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallProduct> {
    try {
      return await getShoppingMallProductsProductId({
        productId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
