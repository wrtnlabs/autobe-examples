import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallProductsProductIdImages } from "../../../../providers/patchShoppingMallProductsProductIdImages";
import { getShoppingMallProductsProductIdImagesImageId } from "../../../../providers/getShoppingMallProductsProductIdImagesImageId";

import { IPageIShoppingMallProductImage } from "../../../../api/structures/IPageIShoppingMallProductImage";
import { IShoppingMallProductImage } from "../../../../api/structures/IShoppingMallProductImage";

@Controller("/shoppingMall/products/:productId/images")
export class ShoppingmallProductsImagesController {
  /**
   * Search and retrieve product images associated with a specific product in
   * the shopping mall catalog.
   *
   * This operation allows users to search, filter, and paginate through the
   * image gallery of a specific product. The operation accesses the
   * shopping_mall_product_images table from the Prisma schema, which stores
   * multiple images for each product with display ordering and primary image
   * designation.
   *
   * Users can search images by various criteria including image type (primary
   * vs gallery), display order, and upload date ranges. The operation supports
   * comprehensive pagination with configurable page sizes and sorting options
   * based on display order, creation date, or image priority.
   *
   * Security considerations include proper product ownership validation to
   * ensure users can only access images for products they are authorized to
   * view. The operation integrates with the ProductImages table as defined in
   * the Prisma schema, incorporating all available image fields and
   * relationships.
   *
   * This operation is essential for product detail pages, image galleries, and
   * product management interfaces where multiple images need to be displayed in
   * a structured manner with proper sequencing and priority handling.
   *
   * @param connection
   * @param productId Unique identifier of the target product
   * @param body Search criteria and pagination parameters for product image
   *   filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallProductImage.IRequest,
  ): Promise<IPageIShoppingMallProductImage.ISummary> {
    try {
      return await patchShoppingMallProductsProductIdImages({
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information for a specific product image from the
   * shopping mall catalog.
   *
   * This operation provides comprehensive details about a single product image,
   * including its URL, alt text, display properties, and metadata. The
   * operation accesses the shopping_mall_product_images table from the Prisma
   * schema, which manages product visuals with proper sequencing and priority
   * handling.
   *
   * The response includes the complete image information such as the image URL
   * for display, accessibility alt text, whether it's designated as the primary
   * product image, display order for gallery sequencing, and
   * creation/modification timestamps. This detailed view is essential for image
   * management interfaces, product detail pages, and any functionality
   * requiring individual image manipulation.
   *
   * Security considerations ensure that users can only access images for
   * products they are authorized to view. The operation validates that the
   * specified product image exists and belongs to the referenced product before
   * returning the detailed information.
   *
   * This operation integrates with the ProductImages table as defined in the
   * Prisma schema, providing a complete view of individual product images with
   * all their associated metadata and display properties.
   *
   * @param connection
   * @param productId Unique identifier of the target product
   * @param imageId Unique identifier of the target product image
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":imageId")
  public async at(
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedParam("imageId")
    imageId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallProductImage> {
    try {
      return await getShoppingMallProductsProductIdImagesImageId({
        productId,
        imageId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
