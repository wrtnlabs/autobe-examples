import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallCustomerArticlesArticleIdComments } from "../../../../../providers/postShoppingMallCustomerArticlesArticleIdComments";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { putShoppingMallCustomerArticlesArticleIdCommentsCommentId } from "../../../../../providers/putShoppingMallCustomerArticlesArticleIdCommentsCommentId";
import { deleteShoppingMallCustomerArticlesArticleIdCommentsCommentId } from "../../../../../providers/deleteShoppingMallCustomerArticlesArticleIdCommentsCommentId";

import { IShoppingMallArticleComment } from "../../../../../api/structures/IShoppingMallArticleComment";

@Controller("/shoppingMall/customer/articles/:articleId/comments")
export class ShoppingmallCustomerArticlesCommentsController {
  /**
   * Create a new comment on a shopping mall article for community engagement.
   * This operation creates a record in the shopping_mall_article_comments table
   * with proper validation and moderation workflows.
   *
   * The operation validates that the target article exists and accepts comments
   * based on its allow_comments setting. It supports threaded commenting by
   * accepting an optional parent comment ID for reply functionality. The system
   * automatically sets appropriate default values for engagement metrics and
   * moderation status.
   *
   * Security considerations include authentication requirements for comment
   * creation and content moderation workflows. The operation integrates with
   * the platform's moderation system to flag comments for review based on
   * content analysis. Actor attribution is preserved through the actor_type
   * field for proper ownership tracking.
   *
   * This operation enables user engagement with shopping mall content through
   * threaded discussions. It supports the platform's community features by
   * allowing customers, sellers, and administrators to participate in article
   * discussions. Related operations include retrieving comments and managing
   * comment moderation.
   *
   * @param connection
   * @param articleId Unique identifier of the target article
   * @param body Comment creation data including content and optional parent
   *   comment reference
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallArticleComment.ICreate,
  ): Promise<IShoppingMallArticleComment> {
    try {
      return await postShoppingMallCustomerArticlesArticleIdComments({
        customer,
        articleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing comment on a shopping mall article with new content and
   * status.
   *
   * This operation allows authenticated users to modify their own comments on
   * articles within the shopping mall platform. The comment content can be
   * updated, and the comment status can be changed if the user has appropriate
   * permissions. The operation validates that both the article and comment
   * exist and that the comment belongs to the specified article.
   *
   * Security considerations include ensuring that users can only update their
   * own comments unless they have administrative privileges. The system
   * performs ownership verification based on the authenticated user's identity
   * and the comment's actor type association. Rate limiting applies to prevent
   * spam updates.
   *
   * The operation updates the shopping_mall_article_comments table in the
   * Prisma schema, modifying the content field and potentially the status field
   * if the user has moderation privileges. The updated_at timestamp is
   * automatically refreshed to track modification history.
   *
   * Related operations include creating new comments (POST
   * /articles/{articleId}/comments) and retrieving comment details (GET
   * /articles/{articleId}/comments/{commentId}). This operation is part of the
   * comprehensive comment management system that supports community engagement
   * features.
   *
   * @param connection
   * @param articleId Unique identifier of the target article containing the
   *   comment
   * @param commentId Unique identifier of the target comment to be updated
   * @param body Updated comment content and optional status modification
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":commentId")
  public async update(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallArticleComment.IUpdate,
  ): Promise<IShoppingMallArticleComment> {
    try {
      return await putShoppingMallCustomerArticlesArticleIdCommentsCommentId({
        customer,
        articleId,
        commentId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently remove a comment from a shopping mall article.
   *
   * This operation allows authenticated users to delete their own comments or
   * administrators to remove comments for moderation purposes. The comment is
   * permanently deleted from the shopping_mall_article_comments table in the
   * Prisma schema, with no soft-delete mechanism implemented for this
   * operation.
   *
   * Security validation ensures that users can only delete their own comments
   * unless they have administrative privileges. The system verifies comment
   * ownership through the actor_type field and associated user context. The
   * operation checks that both the article and comment exist and that the
   * comment belongs to the specified article before proceeding with deletion.
   *
   * Deletion operations are logged for audit purposes, and related comment
   * threads may be affected if this comment has child comments. The system
   * handles cascading effects appropriately based on the comment hierarchy.
   *
   * Related operations include creating comments (POST
   * /articles/{articleId}/comments) and updating comments (PUT
   * /articles/{articleId}/comments/{commentId}). This operation supports
   * content moderation and user self-management of their contributions to the
   * shopping mall platform.
   *
   * @param connection
   * @param articleId Unique identifier of the target article containing the
   *   comment
   * @param commentId Unique identifier of the target comment to be deleted
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":commentId")
  public async erase(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallArticleComment> {
    try {
      return await deleteShoppingMallCustomerArticlesArticleIdCommentsCommentId(
        {
          customer,
          articleId,
          commentId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
