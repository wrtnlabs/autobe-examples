import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallCustomerFavorites } from "../../../../providers/postShoppingMallCustomerFavorites";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { patchShoppingMallCustomerFavorites } from "../../../../providers/patchShoppingMallCustomerFavorites";
import { getShoppingMallCustomerFavoritesFavoriteId } from "../../../../providers/getShoppingMallCustomerFavoritesFavoriteId";
import { putShoppingMallCustomerFavoritesFavoriteId } from "../../../../providers/putShoppingMallCustomerFavoritesFavoriteId";
import { deleteShoppingMallCustomerFavoritesFavoriteId } from "../../../../providers/deleteShoppingMallCustomerFavoritesFavoriteId";

import { IShoppingMallFavorite } from "../../../../api/structures/IShoppingMallFavorite";
import { IPageIShoppingMallFavorite } from "../../../../api/structures/IPageIShoppingMallFavorite";

@Controller("/shoppingMall/customer/favorites")
export class ShoppingmallCustomerFavoritesController {
  /**
   * Create a new favorite product entry for a customer.
   *
   * This operation allows authenticated customers to mark products as favorites
   * for quick access and personalized recommendations. The operation creates a
   * new entry in the shopping_mall_favorites table, linking a customer to a
   * specific product.
   *
   * The system validates that the customer exists and has permission to create
   * favorites, and that the product exists and is available for favoriting. The
   * operation automatically sets the favorited_at timestamp and initializes the
   * updated_at timestamp.
   *
   * Security considerations include ensuring that customers can only create
   * favorites for their own account and that product availability is verified
   * before creating the favorite entry. Rate limiting may apply to prevent spam
   * favorite creation.
   *
   * Related operations: Update favorite (PUT /favorites/{favoriteId}), Remove
   * favorite (DELETE /favorites/{favoriteId}), List favorites (PATCH
   * /favorites).
   *
   * @param connection
   * @param body Favorite creation information including customer and product
   *   references
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallFavorite.ICreate,
  ): Promise<IShoppingMallFavorite> {
    try {
      return await postShoppingMallCustomerFavorites({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve a paginated list of customer favorite products from the
   * shopping mall platform.
   *
   * This operation allows customers to search through their favorited products
   * using various filtering criteria including product categories, favorite
   * dates, and product attributes. The operation supports comprehensive
   * pagination with configurable page sizes and sorting options. Customers can
   * sort by favorite date, product name, or other relevant fields in ascending
   * or descending order.
   *
   * Security considerations include ensuring that customers can only access
   * their own favorite entries. The operation automatically filters results
   * based on the authenticated customer's identity extracted from the JWT
   * token. Rate limiting applies to prevent excessive search operations.
   *
   * This operation integrates with the shopping_mall_favorites table as defined
   * in the Prisma schema, incorporating all available favorite fields and
   * relationships. The response includes favorite summary information optimized
   * for list displays, with product details and favorite metadata.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for favorite product
   *   filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallFavorite.IRequest,
  ): Promise<IPageIShoppingMallFavorite.ISummary> {
    try {
      return await patchShoppingMallCustomerFavorites({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific favorite product entry from
   * the shopping mall platform.
   *
   * This operation allows customers to view complete details of a single
   * favorited product, including the full product information, favorite
   * metadata, and customer-specific context. The operation validates that the
   * authenticated customer owns the favorite entry before returning the data.
   *
   * Security considerations include ownership verification to ensure customers
   * can only access their own favorite entries. The operation performs proper
   * authorization checks to prevent unauthorized access to favorite data.
   *
   * This operation integrates with the shopping_mall_favorites table as defined
   * in the Prisma schema, providing complete favorite details along with
   * related product information. The response includes the full favorite record
   * with embedded product data for comprehensive display.
   *
   * @param connection
   * @param favoriteId Unique identifier of the target favorite entry
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":favoriteId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("favoriteId")
    favoriteId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallFavorite> {
    try {
      return await getShoppingMallCustomerFavoritesFavoriteId({
        customer,
        favoriteId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing favorite product entry.
   *
   * This operation allows authenticated customers to modify their favorite
   * entries. While favorites typically don't require frequent updates, this
   * endpoint supports updating metadata or additional favorite-related
   * information that may be added in the future.
   *
   * The system validates that the customer owns the favorite entry being
   * updated and has permission to modify it. The operation automatically
   * updates the updated_at timestamp to reflect the modification time.
   *
   * Security considerations include ensuring that customers can only update
   * their own favorite entries. The operation performs ownership verification
   * before allowing any modifications to prevent unauthorized access to other
   * customers' favorites.
   *
   * Related operations: Create favorite (POST /favorites), Remove favorite
   * (DELETE /favorites/{favoriteId}), List favorites (PATCH /favorites).
   *
   * @param connection
   * @param favoriteId Unique identifier of the favorite entry to update
   * @param body Favorite update information with fields to modify
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":favoriteId")
  public async update(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("favoriteId")
    favoriteId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallFavorite.IUpdate,
  ): Promise<IShoppingMallFavorite> {
    try {
      return await putShoppingMallCustomerFavoritesFavoriteId({
        customer,
        favoriteId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Soft delete a product favorite entry from the customer's favorites list by
   * setting the deleted_at timestamp.
   *
   * This operation performs a soft delete of the favorite entry, marking it as
   * deleted by setting the deleted_at timestamp while preserving the record in
   * the database for potential recovery or audit purposes. The operation
   * validates that the specified favorite exists and belongs to the
   * authenticated customer before proceeding with the soft deletion.
   *
   * Security considerations include verifying that customers can only delete
   * their own favorites. The operation extracts the customer identity from the
   * JWT authentication token and ensures the favorite being deleted belongs to
   * that customer. Rate limiting applies to prevent abuse of the deletion
   * functionality.
   *
   * This operation interacts with the shopping_mall_favorites table in the
   * Prisma schema, which tracks individual products marked as favorites by
   * customers and includes soft delete capability through the deleted_at field.
   * The soft deletion process preserves the favorite entry for potential future
   * restoration while excluding it from normal queries. Related operations
   * include listing favorites (GET /favorites) and adding favorites (POST
   * /favorites).
   *
   * @param connection
   * @param favoriteId Unique identifier of the target favorite entry to be soft
   *   deleted
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":favoriteId")
  public async erase(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("favoriteId")
    favoriteId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallCustomerFavoritesFavoriteId({
        customer,
        favoriteId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
