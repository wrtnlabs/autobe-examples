import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallCustomerWishlists } from "../../../../providers/postShoppingMallCustomerWishlists";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { patchShoppingMallCustomerWishlists } from "../../../../providers/patchShoppingMallCustomerWishlists";
import { getShoppingMallCustomerWishlistsWishlistId } from "../../../../providers/getShoppingMallCustomerWishlistsWishlistId";
import { putShoppingMallCustomerWishlistsWishlistId } from "../../../../providers/putShoppingMallCustomerWishlistsWishlistId";
import { deleteShoppingMallCustomerWishlistsWishlistId } from "../../../../providers/deleteShoppingMallCustomerWishlistsWishlistId";

import { IShoppingMallWishlist } from "../../../../api/structures/IShoppingMallWishlist";
import { IPageIShoppingMallWishlist } from "../../../../api/structures/IPageIShoppingMallWishlist";

@Controller("/shoppingMall/customer/wishlists")
export class ShoppingmallCustomerWishlistsController {
  /**
   * Create a new wishlist for the authenticated customer.
   *
   * This operation allows customers to create personalized wishlists for
   * organizing products they want to save for future purchase consideration.
   * The operation validates input data, ensures the wishlist name is unique
   * within the customer's account, and creates the wishlist with appropriate
   * default settings.
   *
   * Security considerations include ensuring customers can only create
   * wishlists for their own account. The customer_id field is automatically
   * populated from the JWT authentication token. The operation validates that
   * the wishlist name is not already used by the customer for another active
   * wishlist.
   *
   * The operation integrates with the shopping_mall_wishlists table from the
   * Prisma schema, creating records with all specified fields including name,
   * description, public status, priority level, and creation timestamps.
   * Default values are applied for optional fields when not provided in the
   * request.
   *
   * Related operations: Retrieve wishlist (GET /wishlists/{wishlistId}), Update
   * wishlist (PUT /wishlists/{wishlistId}), Delete wishlist (DELETE
   * /wishlists/{wishlistId}), Search wishlists (PATCH /wishlists).
   *
   * @param connection
   * @param body Wishlist creation data including name, description, and
   *   settings
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallWishlist.ICreate,
  ): Promise<IShoppingMallWishlist> {
    try {
      return await postShoppingMallCustomerWishlists({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve a paginated list of wishlists from the shopping mall
   * platform with advanced filtering capabilities.
   *
   * This operation queries the shopping_mall_wishlists table to return
   * wishlists matching specified search criteria. It supports comprehensive
   * filtering by wishlist name, description, privacy status, priority level,
   * and customer ownership. The operation provides pagination with configurable
   * page sizes and sorting options for efficient data retrieval.
   *
   * Search capabilities include partial text matching for wishlist names and
   * descriptions, exact matching for status and privacy settings, and range
   * filtering for priority levels. The operation can filter wishlists by
   * specific customers or return public wishlists for discovery purposes.
   *
   * Security considerations ensure that users can only access wishlists they
   * own or public wishlists. Private wishlists belonging to other users are
   * automatically filtered out of search results. The operation includes rate
   * limiting to prevent abuse of search functionality.
   *
   * This operation integrates with the shopping_mall_wishlists table as defined
   * in the Prisma schema, leveraging database indexes for optimal performance
   * on large datasets. The response includes wishlist summary information
   * optimized for list displays.
   *
   * Related operations include creating wishlists (POST /wishlists), viewing
   * specific wishlists (GET /wishlists/{wishlistId}), and updating wishlists
   * (PUT /wishlists/{wishlistId}).
   *
   * @param connection
   * @param body Search criteria and pagination parameters for wishlist
   *   filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallWishlist.IRequest,
  ): Promise<IPageIShoppingMallWishlist.ISummary> {
    try {
      return await patchShoppingMallCustomerWishlists({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific customer wishlist.
   *
   * This operation allows authenticated customers to retrieve complete details
   * of a wishlist they own, including all wishlist items with product
   * information. The operation validates that the requesting customer has
   * permission to access the specified wishlist and returns comprehensive data
   * including wishlist metadata, items, and associated product details.
   *
   * Security considerations include ensuring customers can only access their
   * own wishlists. The operation performs ownership validation by comparing the
   * authenticated customer's ID with the wishlist's customer_id field. Rate
   * limiting applies to prevent excessive API calls.
   *
   * The operation integrates with the shopping_mall_wishlists table from the
   * Prisma schema, returning all wishlist fields including name, description,
   * public status, priority level, and creation timestamps. Related wishlist
   * items are included with their product references, quantities, priorities,
   * and customer notes.
   *
   * Related operations: Create wishlist (POST /wishlists), Update wishlist (PUT
   * /wishlists/{wishlistId}), Delete wishlist (DELETE /wishlists/{wishlistId}),
   * Search wishlists (PATCH /wishlists).
   *
   * @param connection
   * @param wishlistId Unique identifier of the target wishlist
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":wishlistId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("wishlistId")
    wishlistId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallWishlist> {
    try {
      return await getShoppingMallCustomerWishlistsWishlistId({
        customer,
        wishlistId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing shopping mall wishlist with new information.
   *
   * This operation allows authenticated customers to modify the properties of
   * their existing wishlists. Customers can update the wishlist name,
   * description, visibility settings, priority level, and status. The operation
   * validates that the wishlist belongs to the authenticated customer before
   * allowing modifications.
   *
   * Security considerations include ensuring that customers can only update
   * their own wishlists. The system automatically validates ownership based on
   * the authenticated customer's ID extracted from the JWT token. Rate limiting
   * applies to prevent abuse of the update functionality.
   *
   * The operation integrates with the shopping_mall_wishlists table as defined
   * in the Prisma schema, updating fields including name, description,
   * is_public, priority, and status. The updated_at timestamp is automatically
   * refreshed to track modification history.
   *
   * Related operations: Create wishlist (POST /wishlists), View wishlist (GET
   * /wishlists/{wishlistId}), Search wishlists (PATCH /wishlists).
   *
   * @param connection
   * @param wishlistId Unique identifier of the target wishlist to be updated
   * @param body Wishlist update information with modified properties
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":wishlistId")
  public async update(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("wishlistId")
    wishlistId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallWishlist.IUpdate,
  ): Promise<IShoppingMallWishlist> {
    try {
      return await putShoppingMallCustomerWishlistsWishlistId({
        customer,
        wishlistId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently remove a shopping mall wishlist from the system.
   *
   * This operation performs a hard delete of the specified wishlist, completely
   * removing it from the database along with all associated wishlist items. The
   * deletion is irreversible and cannot be recovered, making it suitable for
   * customers who want to completely eliminate unwanted wishlists.
   *
   * Security validation ensures that customers can only delete their own
   * wishlists. The system verifies ownership by comparing the authenticated
   * customer's ID with the wishlist's shopping_mall_customer_id field.
   * Administrative oversight may be required for bulk deletion operations.
   *
   * The operation integrates with the shopping_mall_wishlists table as defined
   * in the Prisma schema. Since this is a hard delete operation, all related
   * wishlist items in the shopping_mall_wishlist_items table are also removed
   * to maintain referential integrity.
   *
   * Related operations: Create wishlist (POST /wishlists), Update wishlist (PUT
   * /wishlists/{wishlistId}), View wishlist (GET /wishlists/{wishlistId}).
   *
   * @param connection
   * @param wishlistId Unique identifier of the target wishlist to be
   *   permanently deleted
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":wishlistId")
  public async erase(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("wishlistId")
    wishlistId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallCustomerWishlistsWishlistId({
        customer,
        wishlistId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
