import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { getShoppingMallCustomerCoinsCoinId } from "../../../../providers/getShoppingMallCustomerCoinsCoinId";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";

import { IShoppingMallCoin } from "../../../../api/structures/IShoppingMallCoin";

@Controller("/shoppingMall/customer/coins/:coinId")
export class ShoppingmallCustomerCoinsController {
  /**
   * Retrieve detailed information about a specific coin account from the
   * shopping mall platform.
   *
   * This operation returns the complete coin account details for a specific
   * coin ID, including current balance, total earned/spent metrics, coin type,
   * and actor ownership information. The operation accesses the
   * shopping_mall_coins table from the Prisma schema and provides comprehensive
   * coin account information for authenticated users.
   *
   * Security considerations include ensuring that users can only access their
   * own coin accounts or accounts they have permission to view. The operation
   * validates that the coin ID exists and that the requesting user has
   * appropriate access rights. Rate limiting applies to prevent excessive API
   * calls for coin balance checking.
   *
   * This operation integrates with the shopping_mall_coins table as defined in
   * the Prisma schema, incorporating all available coin account fields
   * including actor_type, balance, total_earned, total_spent, coin_type, and
   * timestamps. The response includes detailed coin account information
   * optimized for display in user interfaces and administrative dashboards.
   *
   * @param connection
   * @param coinId Unique identifier of the target coin account
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("coinId")
    coinId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallCoin> {
    try {
      return await getShoppingMallCustomerCoinsCoinId({
        customer,
        coinId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
