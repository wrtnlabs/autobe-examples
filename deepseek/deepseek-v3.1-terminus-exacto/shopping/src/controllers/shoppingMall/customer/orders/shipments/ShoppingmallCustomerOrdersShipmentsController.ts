import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallCustomerOrdersOrderIdShipments } from "../../../../../providers/patchShoppingMallCustomerOrdersOrderIdShipments";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { getShoppingMallCustomerOrdersOrderIdShipmentsShipmentId } from "../../../../../providers/getShoppingMallCustomerOrdersOrderIdShipmentsShipmentId";

import { IPageIShoppingMallShipment } from "../../../../../api/structures/IPageIShoppingMallShipment";
import { IShoppingMallShipment } from "../../../../../api/structures/IShoppingMallShipment";

@Controller("/shoppingMall/customer/orders/:orderId/shipments")
export class ShoppingmallCustomerOrdersShipmentsController {
  /**
   * Search and retrieve shipments associated with a specific order with
   * advanced filtering and pagination capabilities.
   *
   * This operation allows users to search through shipments belonging to a
   * particular order using comprehensive filtering options. The operation
   * supports filtering by carrier, shipment status, tracking number patterns,
   * and delivery date ranges. Users can also sort results by creation date,
   * estimated delivery date, or shipping cost.
   *
   * The operation integrates with the shopping_mall_shipments table from the
   * Prisma schema, which tracks shipping and delivery information for order
   * fulfillment. Each shipment represents a physical delivery package
   * associated with an order, supporting scenarios like split shipments and
   * multiple package deliveries.
   *
   * Security considerations include ensuring that users can only access
   * shipments for orders they are authorized to view. The operation validates
   * that the order exists and that the requesting user has appropriate
   * permissions to view its shipments. Rate limiting applies to prevent
   * excessive search requests.
   *
   * Related operations include retrieving a specific shipment detail (GET
   * /orders/{orderId}/shipments/{shipmentId}) and creating new shipments for
   * orders.
   *
   * @param connection
   * @param orderId Unique identifier of the target order
   * @param body Search criteria and pagination parameters for shipment
   *   filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallShipment.IRequest,
  ): Promise<IPageIShoppingMallShipment.ISummary> {
    try {
      return await patchShoppingMallCustomerOrdersOrderIdShipments({
        customer,
        orderId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific shipment associated with an
   * order.
   *
   * This operation returns comprehensive details for a single shipment,
   * including carrier information, tracking details, shipping costs, and
   * delivery status. The response includes the complete shipment record with
   * all tracking timelines and carrier-specific data.
   *
   * The operation integrates with the shopping_mall_shipments table from the
   * Prisma schema, which maintains shipping and delivery information for order
   * fulfillment. Each shipment tracks the complete shipping lifecycle including
   * carrier selection, label generation, tracking, and delivery confirmation.
   *
   * Security validation ensures that users can only access shipments for orders
   * they are authorized to view. The operation verifies that both the order and
   * shipment exist and that the requesting user has appropriate permissions.
   * The response includes real-time tracking information when available from
   * carrier APIs.
   *
   * Related operations include searching for multiple shipments (PATCH
   * /orders/{orderId}/shipments) and updating shipment status information.
   *
   * @param connection
   * @param orderId Unique identifier of the target order
   * @param shipmentId Unique identifier of the target shipment
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":shipmentId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedParam("shipmentId")
    shipmentId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallShipment> {
    try {
      return await getShoppingMallCustomerOrdersOrderIdShipmentsShipmentId({
        customer,
        orderId,
        shipmentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
