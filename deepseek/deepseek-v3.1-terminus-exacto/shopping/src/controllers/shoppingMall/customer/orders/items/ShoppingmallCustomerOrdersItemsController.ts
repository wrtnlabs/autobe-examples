import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallCustomerOrdersOrderIdItems } from "../../../../../providers/postShoppingMallCustomerOrdersOrderIdItems";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { patchShoppingMallCustomerOrdersOrderIdItems } from "../../../../../providers/patchShoppingMallCustomerOrdersOrderIdItems";
import { getShoppingMallCustomerOrdersOrderIdItemsItemId } from "../../../../../providers/getShoppingMallCustomerOrdersOrderIdItemsItemId";
import { putShoppingMallCustomerOrdersOrderIdItemsItemId } from "../../../../../providers/putShoppingMallCustomerOrdersOrderIdItemsItemId";
import { deleteShoppingMallCustomerOrdersOrderIdItemsItemId } from "../../../../../providers/deleteShoppingMallCustomerOrdersOrderIdItemsItemId";

import { IShoppingMallOrderItem } from "../../../../../api/structures/IShoppingMallOrderItem";
import { IPageIShoppingMallOrderItem } from "../../../../../api/structures/IPageIShoppingMallOrderItem";

@Controller("/shoppingMall/customer/orders/:orderId/items")
export class ShoppingmallCustomerOrdersItemsController {
  /**
   * Create a new order item within an existing shopping mall order.
   *
   * This operation allows authenticated customers to add individual product
   * items to an existing order. Each order item represents a specific product
   * variant with quantity, pricing, and seller information. The operation
   * validates that the referenced order exists and is in a state that allows
   * item additions.
   *
   * Security considerations include verifying that the authenticated customer
   * has appropriate permissions to modify the target order. The operation
   * ensures pricing consistency by capturing the current product variant price
   * at the time of addition. Each item maintains its own pricing information
   * separate from the product catalog to preserve historical accuracy.
   *
   * The created order item becomes part of the order's total calculation and is
   * subject to the same validation rules as the parent order. Related
   * operations include updating existing order items and viewing the complete
   * order with all items.
   *
   * @param connection
   * @param orderId Unique identifier of the target order
   * @param body Order item creation data including product variant, quantity,
   *   and pricing
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallOrderItem.ICreate,
  ): Promise<IShoppingMallOrderItem> {
    try {
      return await postShoppingMallCustomerOrdersOrderIdItems({
        customer,
        orderId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve order items within a specific order with advanced
   * filtering, sorting, and pagination capabilities.
   *
   * This operation allows users to search through order items belonging to a
   * specific order, providing comprehensive filtering options based on product
   * details, quantities, pricing, and seller information. The operation
   * supports complex search queries with multiple criteria, sorting by various
   * fields, and pagination for efficient data retrieval.
   *
   * Security considerations include ensuring that users can only access order
   * items belonging to orders they are authorized to view. The operation
   * validates that the specified order exists and that the requesting user has
   * appropriate permissions to access its items. Rate limiting applies to
   * prevent excessive search requests.
   *
   * The operation integrates with the Order Items table from the Prisma schema,
   * incorporating all available fields for filtering and sorting. The response
   * includes paginated summary information optimized for list displays, with
   * options to include additional details based on authorization level.
   *
   * Related operations: Get specific order item (GET
   * /orders/{orderId}/items/{itemId}), Update order item (PUT
   * /orders/{orderId}/items/{itemId}).
   *
   * @param connection
   * @param orderId Unique identifier of the target order
   * @param body Search criteria and pagination parameters for order item
   *   filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallOrderItem.IRequest,
  ): Promise<IPageIShoppingMallOrderItem.ISummary> {
    try {
      return await patchShoppingMallCustomerOrdersOrderIdItems({
        customer,
        orderId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific order item within an order.
   *
   * This operation returns comprehensive details about a single order item,
   * including product information, pricing at the time of order, quantity, and
   * seller details. The operation validates that both the specified order and
   * order item exist and that the requesting user has appropriate permissions
   * to access this information.
   *
   * Security considerations include ensuring that users can only access order
   * items belonging to orders they are authorized to view. The operation
   * performs authorization checks to verify that the user has access rights to
   * the parent order before returning the item details.
   *
   * The operation integrates with the Order Items table from the Prisma schema,
   * providing complete information about the product variant ordered, including
   * preserved product name and attributes from the time of purchase. This
   * ensures historical accuracy for order records.
   *
   * Related operations: Search order items (PATCH /orders/{orderId}/items),
   * Update order item (PUT /orders/{orderId}/items/{itemId}).
   *
   * @param connection
   * @param orderId Unique identifier of the target order
   * @param itemId Unique identifier of the target order item within the order
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":itemId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedParam("itemId")
    itemId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallOrderItem> {
    try {
      return await getShoppingMallCustomerOrdersOrderIdItemsItemId({
        customer,
        orderId,
        itemId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing order item within a shopping mall order.
   *
   * This operation allows authenticated customers to modify the quantity,
   * pricing, or other attributes of an existing order item. Common use cases
   * include correcting quantity errors, updating pricing due to promotions, or
   * adjusting item details after customer requests.
   *
   * The operation validates that both the target order and order item exist and
   * are in a modifiable state. Security checks ensure the authenticated
   * customer has appropriate permissions to modify the specific order. The
   * update maintains audit integrity by preserving the original item state
   * while applying the requested changes.
   *
   * When updating quantities or pricing, the operation recalculates the order's
   * total amount to maintain financial accuracy. The updated order item
   * reflects the changes while preserving the historical context of the
   * original purchase.
   *
   * @param connection
   * @param orderId Unique identifier of the target order
   * @param itemId Unique identifier of the target order item
   * @param body Order item update data including modified quantity, pricing, or
   *   attributes
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":itemId")
  public async update(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedParam("itemId")
    itemId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallOrderItem.IUpdate,
  ): Promise<IShoppingMallOrderItem> {
    try {
      return await putShoppingMallCustomerOrdersOrderIdItemsItemId({
        customer,
        orderId,
        itemId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently remove a specific order item from an order.
   *
   * This operation permanently deletes an individual order item from an
   * existing order. The operation requires both the order identifier and the
   * specific item identifier to ensure precise targeting of the item to be
   * removed. This is typically used when customers need to remove items from
   * their orders before the order is processed or shipped.
   *
   * Security considerations include verifying that the requesting user has
   * appropriate permissions to modify the order. The operation validates that
   * both the order and the specific item exist before proceeding with deletion.
   * Rate limiting may apply to prevent abuse of the deletion functionality.
   *
   * This operation affects the shopping_mall_order_items table in the Prisma
   * schema, removing the specified record permanently from the database.
   * Related operations include updating order items (PUT
   * /orders/{orderId}/items/{itemId}) and viewing order details (GET
   * /orders/{orderId}).
   *
   * @param connection
   * @param orderId Unique identifier of the target order
   * @param itemId Unique identifier of the specific order item to remove
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":itemId")
  public async erase(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedParam("itemId")
    itemId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallCustomerOrdersOrderIdItemsItemId({
        customer,
        orderId,
        itemId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
