import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallCustomerOrders } from "../../../../providers/postShoppingMallCustomerOrders";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { patchShoppingMallCustomerOrders } from "../../../../providers/patchShoppingMallCustomerOrders";
import { getShoppingMallCustomerOrdersOrderId } from "../../../../providers/getShoppingMallCustomerOrdersOrderId";

import { IShoppingMallOrder } from "../../../../api/structures/IShoppingMallOrder";
import { IPageIShoppingMallOrder } from "../../../../api/structures/IPageIShoppingMallOrder";

@Controller("/shoppingMall/customer/orders")
export class ShoppingmallCustomerOrdersController {
  /**
   * Create a new shopping mall order from customer shopping cart or direct
   * purchase.
   *
   * This operation initiates the order creation process, converting temporary
   * shopping cart items into a committed financial transaction. The operation
   * validates product availability, calculates pricing including taxes and
   * shipping, and establishes the order record in the shopping_mall_orders
   * table.
   *
   * Business logic includes inventory validation, price verification, customer
   * authentication, and payment authorization pre-processing. The operation
   * creates the order record with initial status and prepares for subsequent
   * payment processing and fulfillment workflows.
   *
   * Security considerations require customer authentication and validation of
   * ownership for the shopping cart or purchase items. The operation ensures
   * data integrity and financial accuracy before committing the order to the
   * database.
   *
   * Related operations include order retrieval, status updates, and
   * cancellation workflows. Successful order creation triggers notification
   * systems and inventory updates.
   *
   * @param connection
   * @param body Order creation data including items, customer information, and
   *   shipping details
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallOrder.ICreate,
  ): Promise<IShoppingMallOrder> {
    try {
      return await postShoppingMallCustomerOrders({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve a paginated list of customer orders with advanced
   * filtering capabilities.
   *
   * This operation provides comprehensive order search functionality operating
   * on the shopping_mall_orders table. Customers can search their order history
   * using multiple criteria including order status, date ranges, order numbers,
   * and total amount ranges. The operation supports complex pagination with
   * configurable page sizes and sorting options.
   *
   * Security considerations ensure that customers can only access their own
   * orders, with appropriate filtering based on the authenticated customer
   * session. The operation includes rate limiting to prevent excessive search
   * requests and maintains performance through efficient database indexing.
   *
   * The search functionality supports partial matching on order numbers, exact
   * status filtering, and date-based range queries. Results include order
   * summaries with essential information for quick review, with detailed order
   * information available through the individual order retrieval endpoint.
   *
   * Related operations: Get specific order (GET /orders/{orderId}), Create new
   * order (POST /orders), Update order status (PUT /orders/{orderId}).
   *
   * @param connection
   * @param body Search criteria and pagination parameters for order filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallOrder.IRequest,
  ): Promise<IPageIShoppingMallOrder.ISummary> {
    try {
      return await patchShoppingMallCustomerOrders({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information for a specific shopping mall order by its
   * unique identifier.
   *
   * This operation fetches complete order details including customer
   * information, order items, pricing breakdown, and current status from the
   * shopping_mall_orders table. The operation provides comprehensive order
   * visibility for customers, sellers, and administrators based on their
   * authorization level.
   *
   * Security considerations include proper access control to ensure users can
   * only view their own orders unless they have administrative privileges. The
   * operation validates that the order exists and that the requesting user has
   * appropriate permissions to access the order details.
   *
   * Related operations include listing multiple orders via the index operation
   * and creating new orders via the create operation. This detailed view is
   * essential for order tracking, customer support, and fulfillment management
   * workflows.
   *
   * @param connection
   * @param orderId Unique identifier of the target order
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":orderId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallOrder> {
    try {
      return await getShoppingMallCustomerOrdersOrderId({
        customer,
        orderId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
