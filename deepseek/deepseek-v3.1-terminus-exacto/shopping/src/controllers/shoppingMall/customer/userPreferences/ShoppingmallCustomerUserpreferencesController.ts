import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallCustomerUserPreferences } from "../../../../providers/postShoppingMallCustomerUserPreferences";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { patchShoppingMallCustomerUserPreferences } from "../../../../providers/patchShoppingMallCustomerUserPreferences";
import { getShoppingMallCustomerUserPreferencesPreferenceId } from "../../../../providers/getShoppingMallCustomerUserPreferencesPreferenceId";
import { putShoppingMallCustomerUserPreferencesPreferenceId } from "../../../../providers/putShoppingMallCustomerUserPreferencesPreferenceId";
import { deleteShoppingMallCustomerUserPreferencesPreferenceId } from "../../../../providers/deleteShoppingMallCustomerUserPreferencesPreferenceId";
import { getShoppingMallCustomerCustomerIdUserPreferencesPreferenceId } from "../../../../providers/getShoppingMallCustomerCustomerIdUserPreferencesPreferenceId";
import { postShoppingMallCustomerCustomerIdUserPreferences } from "../../../../providers/postShoppingMallCustomerCustomerIdUserPreferences";

import { IShoppingMallUserPreference } from "../../../../api/structures/IShoppingMallUserPreference";
import { IPageIShoppingMallUserPreference } from "../../../../api/structures/IPageIShoppingMallUserPreference";

@Controller("/shoppingMall/customer")
export class ShoppingmallCustomerUserpreferencesController {
  /**
   * Create a new customer preference setting for personalized user experience.
   *
   * This operation allows authenticated customers to create new preference
   * records in the shopping_mall_user_preferences table. Customers can set
   * various types of preferences including notification settings, display
   * preferences, privacy controls, and other personalization options that
   * affect their shopping mall experience.
   *
   * The operation validates the preference data against allowed preference
   * types and values, ensuring compliance with platform constraints. It
   * automatically associates the preference with the authenticated customer's
   * account and sets appropriate timestamps for creation and modification.
   *
   * Security measures include verifying that the customer has permission to
   * create preferences and ensuring that preference values adhere to platform
   * guidelines. The system supports GDPR compliance by allowing customers to
   * control their data and experience preferences through this interface.
   *
   * Created preferences become immediately active and affect the customer's
   * user experience according to the specified settings. The operation returns
   * the complete preference record including system-generated identifiers and
   * timestamps.
   *
   * @param connection
   * @param body Customer preference creation data
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("userPreferences")
  public async post(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallUserPreference.ICreate,
  ): Promise<IShoppingMallUserPreference> {
    try {
      return await postShoppingMallCustomerUserPreferences({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve customer preference settings with advanced filtering
   * and pagination capabilities.
   *
   * This operation allows customers to search through their preference settings
   * using various criteria including preference type, category, active status,
   * and creation date ranges. The operation supports comprehensive pagination
   * with configurable page sizes and sorting options. Customers can sort
   * preferences by creation date, update date, or preference type in ascending
   * or descending order.
   *
   * The operation interacts with the shopping_mall_user_preferences table in
   * the Prisma schema, which stores various user settings and preferences for
   * personalization and user experience customization. Security considerations
   * include ensuring that customers can only access their own preferences. The
   * customer identity is automatically extracted from the JWT authentication
   * token and used to filter results.
   *
   * This operation supports GDPR compliance by allowing customers to review and
   * manage their data and experience preferences. Related operations include
   * creating preferences (POST /userPreferences), updating preferences (PUT
   * /userPreferences/{preferenceId}), and deleting preferences (DELETE
   * /userPreferences/{preferenceId}).
   *
   * @param connection
   * @param body Search criteria and pagination parameters for preference
   *   filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch("userPreferences")
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallUserPreference.IRequest,
  ): Promise<IPageIShoppingMallUserPreference.ISummary> {
    try {
      return await patchShoppingMallCustomerUserPreferences({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific customer preference setting by its unique identifier.
   *
   * This operation fetches detailed information about a single customer
   * preference record from the shopping_mall_user_preferences table. The
   * preference is identified by its UUID primary key and includes all
   * preference details such as type, key, value, category, and activation
   * status.
   *
   * Security considerations include ensuring that only authenticated customers
   * can access their own preference data. The operation validates that the
   * requesting customer has permission to view the specified preference record
   * based on ownership.
   *
   * The response includes comprehensive preference information including the
   * preference type (notification, display, privacy, etc.), specific preference
   * key, current value, category grouping, activation status, and timestamps
   * for creation, modification, and potential deletion.
   *
   * This operation is essential for customer profile management and
   * personalization features, allowing customers to review and manage their
   * individual preference settings within the shopping mall platform.
   *
   * @param connection
   * @param preferenceId Unique identifier of the target customer preference
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get("userPreferences/:preferenceId")
  public async getByPreferenceid(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("preferenceId")
    preferenceId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallUserPreference> {
    try {
      return await getShoppingMallCustomerUserPreferencesPreferenceId({
        customer,
        preferenceId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing customer preference setting in the shopping mall
   * platform.
   *
   * This operation allows authenticated customers to modify their personal
   * preference settings, such as notification preferences, display options,
   * privacy settings, and other user experience customizations. The operation
   * updates the preference_value field while preserving the preference_type and
   * preference_key structure.
   *
   * Security considerations include verifying that the requesting customer owns
   * the preference being modified. The system validates that the preference
   * exists and belongs to the authenticated customer before allowing the
   * update. Rate limiting applies to prevent abuse of preference modification
   * capabilities.
   *
   * The operation supports GDPR compliance by allowing customers to control
   * their data preferences. All preference updates are logged for audit
   * purposes. Related operations include creating new preferences (POST
   * /userPreferences) and viewing existing preferences (PATCH
   * /userPreferences).
   *
   * @param connection
   * @param preferenceId Unique identifier of the target preference to update
   * @param body Updated preference value and settings
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put("userPreferences/:preferenceId")
  public async update(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("preferenceId")
    preferenceId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallUserPreference.IUpdate,
  ): Promise<IShoppingMallUserPreference> {
    try {
      return await putShoppingMallCustomerUserPreferencesPreferenceId({
        customer,
        preferenceId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Remove a customer preference setting from the shopping mall platform.
   *
   * This operation performs a soft deletion of customer preference records by
   * setting the deleted_at timestamp. The preference record is preserved in the
   * database for audit and compliance purposes but is no longer active in the
   * system. Customers can remove preferences they no longer wish to use, such
   * as notification settings or display preferences.
   *
   * Security validation ensures that only the customer who owns the preference
   * can delete it. The system verifies ownership before proceeding with the
   * soft deletion. This operation supports GDPR compliance by allowing
   * customers to remove their personal data preferences.
   *
   * Soft deletion preserves historical preference data while making the
   * preference inactive. Related operations include creating preferences (POST
   * /userPreferences) and updating preferences (PUT
   * /userPreferences/{preferenceId}).
   *
   * @param connection
   * @param preferenceId Unique identifier of the target preference to delete
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete("userPreferences/:preferenceId")
  public async erase(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("preferenceId")
    preferenceId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallCustomerUserPreferencesPreferenceId({
        customer,
        preferenceId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific customer preference setting by its unique identifier
   * within the customer's scope.
   *
   * This operation fetches detailed information about a single customer
   * preference record from the shopping_mall_user_preferences table. The
   * preference is identified by its UUID primary key and includes all
   * preference details such as type, key, value, category, and activation
   * status. The operation requires both the customer identifier and preference
   * identifier to ensure proper scoping according to the composite unique
   * constraint @@unique([shopping_mall_customer_id, preference_type,
   * preference_key]) in the Prisma schema.
   *
   * Security considerations include ensuring that only authenticated customers
   * can access their own preference data. The operation validates that the
   * requesting customer has permission to view the specified preference record
   * based on ownership matching the customerId path parameter.
   *
   * The response includes comprehensive preference information including the
   * preference type (notification, display, privacy, etc.), specific preference
   * key, current value, category grouping, activation status, and timestamps
   * for creation, modification, and potential deletion.
   *
   * This operation is essential for customer profile management and
   * personalization features, allowing customers to review and manage their
   * individual preference settings within the shopping mall platform while
   * maintaining proper data isolation between customers.
   *
   * @param connection
   * @param customerId Unique identifier of the target customer (global scope)
   * @param preferenceId Unique identifier of the target preference within the
   *   customer's scope (scoped to customer)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":customerId/userPreferences/:preferenceId")
  public async getByCustomeridAndPreferenceid(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("customerId")
    customerId: string & tags.Format<"uuid">,
    @TypedParam("preferenceId")
    preferenceId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallUserPreference> {
    try {
      return await getShoppingMallCustomerCustomerIdUserPreferencesPreferenceId(
        {
          customer,
          customerId,
          preferenceId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Create a new customer preference setting for personalized user experience
   * within the customer's account.
   *
   * This operation allows authenticated customers to create new preference
   * records in the shopping_mall_user_preferences table. Customers can set
   * various types of preferences including notification settings, display
   * preferences, privacy controls, and other personalization options that
   * affect their shopping mall experience. The operation requires the
   * customerId path parameter to properly scope the preference creation
   * according to the composite unique constraint
   *
   * @param connection
   * @param customerId Unique identifier of the target customer (global scope)
   * @param body Customer preference creation data
   * @@unique([shopping_mall_customer_id, preference_type, preference_key]) in
   * the Prisma schema.
   *
   * The operation validates the preference data against allowed preference
   * types and values, ensuring compliance with platform constraints. It
   * automatically associates the preference with the specified customer's
   * account (validating that the authenticated customer matches the
   * customerId) and sets appropriate timestamps for creation and
   * modification.
   *
   * Security measures include verifying that the customer has permission to
   * create preferences for their own account and ensuring that preference
   * values adhere to platform guidelines. The system supports GDPR compliance
   * by allowing customers to control their data and experience preferences
   * through this interface.
   *
   * Created preferences become immediately active and affect the customer's
   * user experience according to the specified settings. The operation
   * returns the complete preference record including system-generated
   * identifiers and timestamps.
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post(":customerId/userPreferences")
  public async postByCustomerid(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("customerId")
    customerId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallUserPreference.ICreate,
  ): Promise<IShoppingMallUserPreference> {
    try {
      return await postShoppingMallCustomerCustomerIdUserPreferences({
        customer,
        customerId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
