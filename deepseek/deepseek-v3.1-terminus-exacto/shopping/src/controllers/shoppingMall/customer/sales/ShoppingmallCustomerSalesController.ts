import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { getShoppingMallCustomerSalesSaleId } from "../../../../providers/getShoppingMallCustomerSalesSaleId";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";

import { IShoppingMallSale } from "../../../../api/structures/IShoppingMallSale";

@Controller("/shoppingMall/customer/sales/:saleId")
export class ShoppingmallCustomerSalesController {
  /**
   * Retrieve detailed information about a specific sale transaction in the
   * shopping mall system.
   *
   * This operation fetches comprehensive sale details from the
   * shopping_mall_sales table, including transaction amounts, item counts,
   * status information, commission rates, and related customer and seller
   * information. Each sale represents a completed purchase transaction that has
   * been successfully processed and paid.
   *
   * The operation validates that the requested sale exists and that the
   * requesting user has appropriate permissions to view the sale details. Sales
   * data includes financial information such as sale amount, commission rate,
   * and net payout amount, making this operation suitable for both customer
   * order history and seller sales reporting.
   *
   * Security considerations include ensuring that customers can only view their
   * own sales, while sellers can view sales they have received. Administrative
   * users may have broader access to all sales data for analytics and business
   * intelligence purposes. The operation returns the complete sale record with
   * all associated metadata.
   *
   * @param connection
   * @param saleId Unique identifier of the target sale transaction
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("saleId")
    saleId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallSale> {
    try {
      return await getShoppingMallCustomerSalesSaleId({
        customer,
        saleId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
