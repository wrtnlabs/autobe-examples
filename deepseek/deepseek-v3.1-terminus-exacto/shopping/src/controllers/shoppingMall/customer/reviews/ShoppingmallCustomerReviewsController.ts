import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallCustomerReviews } from "../../../../providers/postShoppingMallCustomerReviews";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { putShoppingMallCustomerReviewsReviewId } from "../../../../providers/putShoppingMallCustomerReviewsReviewId";

import { IShoppingMallReview } from "../../../../api/structures/IShoppingMallReview";

@Controller("/shoppingMall/customer/reviews")
export class ShoppingmallCustomerReviewsController {
  /**
   * Create a new review entity in the shopping mall system. This operation
   * allows authenticated users to submit reviews for products or sellers,
   * supporting the polymorphic ownership pattern where reviews can be created
   * by different actor types (customers or sellers).
   *
   * The operation validates that the review content meets platform standards
   * and ensures proper rating constraints (1.0 to 5.0). The system
   * automatically handles review status transitions and maintains integrity
   * with the underlying shopping_mall_reviews table structure.
   *
   * Security considerations include rate limiting to prevent spam reviews and
   * validation of actor permissions. The operation integrates with the
   * shopping_mall_reviews Prisma schema, incorporating all available review
   * fields including title, content, overall_rating, and actor-specific
   * relationships.
   *
   * @param connection
   * @param body Review creation data including content, ratings, and actor
   *   context
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallReview.ICreate,
  ): Promise<IShoppingMallReview> {
    try {
      return await postShoppingMallCustomerReviews({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing review entity in the shopping mall system. This
   * operation allows authenticated users to modify their own reviews,
   * supporting updates to content, ratings, and other review attributes while
   * maintaining data integrity.
   *
   * The operation validates ownership permissions to ensure users can only
   * update their own reviews. It handles the polymorphic ownership pattern by
   * verifying the actor_type matches the authenticated user's role. The system
   * preserves audit trails by updating the updated_at timestamp while
   * maintaining the original created_at value.
   *
   * Security considerations include ownership verification and content
   * moderation workflows. The operation integrates with the
   * shopping_mall_reviews Prisma schema, allowing updates to fields like title,
   * content, overall_rating, and status while protecting system-managed
   * fields.
   *
   * @param connection
   * @param reviewId Unique identifier of the target review
   * @param body Review update data including modified content and ratings
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":reviewId")
  public async update(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallReview.IUpdate,
  ): Promise<IShoppingMallReview> {
    try {
      return await putShoppingMallCustomerReviewsReviewId({
        customer,
        reviewId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
