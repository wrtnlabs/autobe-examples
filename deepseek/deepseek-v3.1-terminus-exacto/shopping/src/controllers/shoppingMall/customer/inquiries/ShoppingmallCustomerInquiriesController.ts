import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallCustomerInquiries } from "../../../../providers/postShoppingMallCustomerInquiries";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { putShoppingMallCustomerInquiriesInquiryId } from "../../../../providers/putShoppingMallCustomerInquiriesInquiryId";

import { IShoppingMallInquiry } from "../../../../api/structures/IShoppingMallInquiry";

@Controller("/shoppingMall/customer/inquiries")
export class ShoppingmallCustomerInquiriesController {
  /**
   * Create a new customer support inquiry in the shopping mall platform.
   *
   * This operation allows customers to submit inquiries for support assistance
   * with various platform issues including product questions, order problems,
   * account issues, technical support, and general feedback. The inquiry
   * captures essential information such as title, detailed description, inquiry
   * type, priority level, and initial status.
   *
   * The system automatically assigns timestamps for creation and updates, and
   * the inquiry is immediately available for support staff review. Each inquiry
   * follows a workflow lifecycle from submission through resolution, with
   * status tracking and priority-based routing.
   *
   * Security considerations include rate limiting to prevent spam submissions
   * and validation of inquiry content to ensure appropriate content standards.
   * The operation integrates with the shopping_mall_inquiries table from the
   * Prisma schema, creating a new record with the provided customer input.
   *
   * **CRITICAL IMPLEMENTATION NOTE**: This operation must create corresponding
   * records in the shopping_mall_inquiry_of_customers subtype table to properly
   * attribute the inquiry to the creating customer through polymorphic
   * ownership.
   *
   * Related operations include viewing inquiry details (GET
   * /inquiries/{inquiryId}), updating inquiry information (PUT
   * /inquiries/{inquiryId}), and searching inquiries (PATCH /inquiries).
   *
   * @param connection
   * @param body Creation data for a new customer support inquiry including
   *   required fields: title, body, inquiry_type, priority, and status
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallInquiry.ICreate,
  ): Promise<IShoppingMallInquiry> {
    try {
      return await postShoppingMallCustomerInquiries({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing customer support inquiry with new information or status
   * changes.
   *
   * This operation allows customers or support staff to modify inquiry details
   * such as title, description, priority level, or inquiry type. It also
   * supports status transitions through the inquiry workflow lifecycle (open →
   * in_progress → awaiting_response → resolved → closed).
   *
   * The operation validates that the target inquiry exists and is accessible to
   * the requesting user. For customers, this typically allows updates only to
   * their own inquiries, while support staff may have broader update
   * permissions based on their authorization level.
   *
   * Security considerations include ownership verification to prevent
   * unauthorized modifications and validation of status transitions to maintain
   * proper workflow integrity. The operation updates the
   * shopping_mall_inquiries table record with the provided changes while
   * preserving audit trail information.
   *
   * Related operations include creating inquiries (POST /inquiries), viewing
   * inquiry details (GET /inquiries/{inquiryId}), and searching inquiries
   * (PATCH /inquiries).
   *
   * @param connection
   * @param inquiryId Unique identifier of the target inquiry to update
   * @param body Updated inquiry information including modified fields
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":inquiryId")
  public async update(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("inquiryId")
    inquiryId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallInquiry.IUpdate,
  ): Promise<IShoppingMallInquiry> {
    try {
      return await putShoppingMallCustomerInquiriesInquiryId({
        customer,
        inquiryId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
