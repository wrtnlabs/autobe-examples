import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallCustomerCarts } from "../../../../providers/postShoppingMallCustomerCarts";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { getShoppingMallCustomerCartsCartId } from "../../../../providers/getShoppingMallCustomerCartsCartId";
import { putShoppingMallCustomerCartsCartId } from "../../../../providers/putShoppingMallCustomerCartsCartId";
import { deleteShoppingMallCustomerCartsCartId } from "../../../../providers/deleteShoppingMallCustomerCartsCartId";

import { IShoppingMallCart } from "../../../../api/structures/IShoppingMallCart";

@Controller("/shoppingMall/customer/carts")
export class ShoppingmallCustomerCartsController {
  /**
   * Create a new shopping cart session for customer product selections.
   *
   * This operation creates a new shopping cart session that temporarily holds
   * customer product selections before order conversion. Each cart represents a
   * unique shopping session associated with a customer's active session and
   * maintains temporary product selections that customers may later convert to
   * actual orders or abandon.
   *
   * The cart creation process automatically sets initial status to 'active' and
   * establishes an expiration timestamp based on system configuration. The
   * operation validates that the referenced customer session exists and is
   * valid before creating the cart.
   *
   * Security considerations include ensuring that carts are only created for
   * authenticated customer sessions and that cart data is properly isolated
   * between different customers. The system tracks cart creation timestamps for
   * analytics and cart lifecycle management.
   *
   * Related operations include adding items to carts (POST
   * /carts/{cartId}/items), converting carts to orders (POST /orders), and
   * retrieving cart details (GET /carts/{cartId}).
   *
   * @param connection
   * @param body Shopping cart creation data including customer session
   *   reference and initial configuration
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallCart.ICreate,
  ): Promise<IShoppingMallCart> {
    try {
      return await postShoppingMallCustomerCarts({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific shopping cart session.
   *
   * This operation returns complete details of a shopping cart session
   * including its current status, expiration timestamp, applied coupon codes,
   * shipping preferences, and associated cart items. The cart information
   * provides customers with a comprehensive view of their current shopping
   * selections.
   *
   * The operation validates that the cart exists and that the requesting user
   * has appropriate permissions to access the cart details. For security, carts
   * are only accessible to the customer session that owns them or to
   * administrative users with appropriate permissions.
   *
   * The response includes real-time calculated fields such as total cart value
   * and item count, which are computed dynamically based on the current cart
   * contents and pricing. Cart expiration status is checked and updated if
   * necessary during retrieval.
   *
   * Related operations include creating carts (POST /carts), updating cart
   * items (PUT /carts/{cartId}/items/{itemId}), and converting carts to orders
   * (POST /orders).
   *
   * @param connection
   * @param cartId Unique identifier of the target shopping cart
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":cartId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("cartId")
    cartId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallCart> {
    try {
      return await getShoppingMallCustomerCartsCartId({
        customer,
        cartId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing shopping cart session with modified product selections,
   * shipping preferences, or coupon applications.
   *
   * This operation allows customers to modify their active shopping cart by
   * updating product quantities, changing shipping methods, applying or
   * removing coupons, or adjusting other cart preferences. The cart must be in
   * an active status and belong to the authenticated customer's session to be
   * eligible for updates.
   *
   * The operation validates that the cart exists, is still active, and belongs
   * to the requesting customer before applying updates. It recalculates cart
   * totals including any applied discounts from coupons and updates shipping
   * cost estimates based on the selected shipping method. The cart's updated_at
   * timestamp is automatically refreshed to track the most recent activity.
   *
   * Security considerations include ensuring customers can only modify their
   * own carts and that cart modifications respect inventory availability and
   * business rules. The operation performs comprehensive validation of coupon
   * codes, shipping method availability, and product stock levels before
   * applying changes.
   *
   * Related operations: Create cart (POST /carts), View cart (GET
   * /carts/{cartId}), Delete cart (DELETE /carts/{cartId}), Convert cart to
   * order (POST /carts/{cartId}/orders).
   *
   * @param connection
   * @param cartId Unique identifier of the target shopping cart
   * @param body Cart update information including product selections, shipping
   *   preferences, and coupon applications
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":cartId")
  public async update(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("cartId")
    cartId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallCart.IUpdate,
  ): Promise<IShoppingMallCart> {
    try {
      return await putShoppingMallCustomerCartsCartId({
        customer,
        cartId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Soft delete a shopping cart session by setting the deleted_at timestamp.
   *
   * This operation performs a soft deletion of the specified shopping cart by
   * setting the deleted_at field to the current timestamp, preserving the cart
   * data for analytics and reporting purposes while removing it from active
   * use. The cart record remains in the database but is excluded from normal
   * queries and operations.
   *
   * The operation validates that the cart exists and belongs to the
   * authenticated customer before proceeding with soft deletion. It is
   * typically used when customers explicitly want to abandon their shopping
   * session or when carts need to be archived for system maintenance.
   *
   * Security considerations include ensuring customers can only soft delete
   * their own carts. The system maintains cart data for audit purposes and
   * analytics, allowing for recovery of abandoned cart information if needed.
   * Soft-deleted carts are automatically cleaned up after configurable
   * retention periods.
   *
   * Note: This is a soft delete operation that preserves cart records. For
   * complete removal of cart data, administrative hard delete operations are
   * available separately.
   *
   * Related operations: Update cart (PUT /carts/{cartId}), View cart (GET
   * /carts/{cartId}), Create cart (POST /carts).
   *
   * @param connection
   * @param cartId Unique identifier of the target shopping cart to be
   *   soft-deleted
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":cartId")
  public async erase(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("cartId")
    cartId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallCustomerCartsCartId({
        customer,
        cartId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
