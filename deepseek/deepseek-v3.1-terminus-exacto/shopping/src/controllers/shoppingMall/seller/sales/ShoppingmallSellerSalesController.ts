import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { patchShoppingMallSellerSales } from "../../../../providers/patchShoppingMallSellerSales";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";

import { IPageIShoppingMallSale } from "../../../../api/structures/IPageIShoppingMallSale";
import { IShoppingMallSale } from "../../../../api/structures/IShoppingMallSale";

@Controller("/shoppingMall/seller/sales")
export class ShoppingmallSellerSalesController {
  /**
   * Search and retrieve a paginated list of sales transactions from the
   * shopping mall platform.
   *
   * This operation provides comprehensive search capabilities for sales records
   * stored in the shopping_mall_sales table. It supports complex filtering,
   * sorting, and pagination to help users find specific sales transactions
   * based on multiple criteria including sale amount, date ranges, customer
   * information, seller details, and sale status.
   *
   * The operation allows filtering by sale status (completed, refunded,
   * disputed), date ranges, customer IDs, seller IDs, and amount thresholds.
   * Sorting options include sale date, sale amount, and item count in ascending
   * or descending order. Pagination parameters control the number of results
   * per page and navigation through large result sets.
   *
   * Security considerations include appropriate data access controls based on
   * user roles. Sellers should only see their own sales, while administrators
   * can view all sales across the platform. The operation includes rate
   * limiting to prevent excessive resource usage and ensures that sensitive
   * financial information is properly protected based on authorization levels.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for sales filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IShoppingMallSale.IRequest,
  ): Promise<IPageIShoppingMallSale.ISummary> {
    try {
      return await patchShoppingMallSellerSales({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
