import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallSellerProductsProductIdImages } from "../../../../../providers/postShoppingMallSellerProductsProductIdImages";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { putShoppingMallSellerProductsProductIdImagesImageId } from "../../../../../providers/putShoppingMallSellerProductsProductIdImagesImageId";
import { deleteShoppingMallSellerProductsProductIdImagesImageId } from "../../../../../providers/deleteShoppingMallSellerProductsProductIdImagesImageId";

import { IShoppingMallProductImage } from "../../../../../api/structures/IShoppingMallProductImage";

@Controller("/shoppingMall/seller/products/:productId/images")
export class ShoppingmallSellerProductsImagesController {
  /**
   * Create a new product image entry for a specific product in the shopping
   * mall catalog.
   *
   * This operation allows sellers to upload and associate images with their
   * products, enhancing the product presentation with visual content. The image
   * is linked to the specified product and can be configured as the primary
   * image or positioned in the display order sequence.
   *
   * When creating a product image, the system validates that the product exists
   * and belongs to the authenticated seller. The image URL must point to a
   * valid image resource, and the display order ensures proper sequencing in
   * product galleries. If the image is marked as primary, it becomes the main
   * image displayed in product listings and search results.
   *
   * Security considerations include verifying that the authenticated seller
   * owns the target product before allowing image uploads. Rate limiting
   * applies to prevent abuse of the image upload functionality. The operation
   * integrates with the ProductImages table from the Prisma schema, ensuring
   * all image metadata is properly stored and managed.
   *
   * Related operations include updating product images (PUT
   * /products/{productId}/images/{imageId}) and managing the product image
   * gallery through search and retrieval endpoints.
   *
   * @param connection
   * @param productId Unique identifier of the target product for image
   *   association
   * @param body Product image creation data including URL, alt text, and
   *   display configuration
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallProductImage.ICreate,
  ): Promise<IShoppingMallProductImage> {
    try {
      return await postShoppingMallSellerProductsProductIdImages({
        seller,
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing product image with new metadata or configuration
   * changes.
   *
   * This operation allows sellers to modify product image properties such as
   * the image URL, alternative text, primary image status, or display order.
   * The update ensures that product galleries remain properly organized and
   * visually appealing.
   *
   * When updating a product image, the system validates that both the product
   * and image exist and belong to the authenticated seller. Changes to the
   * primary image status automatically update the previous primary image if one
   * exists. Display order adjustments may require reordering other images in
   * the gallery to maintain proper sequencing.
   *
   * Security considerations include ownership verification to prevent
   * unauthorized modifications to product images. The operation supports
   * partial updates where only specified fields are modified, leaving other
   * properties unchanged. Integration with the ProductImages table ensures data
   * consistency and proper audit trail maintenance.
   *
   * Related operations include creating new product images (POST
   * /products/{productId}/images) and retrieving product image information
   * through search and detail endpoints.
   *
   * @param connection
   * @param productId Unique identifier of the target product containing the
   *   image
   * @param imageId Unique identifier of the specific product image to update
   * @param body Product image update data with modified properties
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":imageId")
  public async update(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedParam("imageId")
    imageId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallProductImage.IUpdate,
  ): Promise<IShoppingMallProductImage> {
    try {
      return await putShoppingMallSellerProductsProductIdImagesImageId({
        seller,
        productId,
        imageId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a specific product image from the shopping mall product
   * gallery.
   *
   * This operation removes a product image record from the
   * shopping_mall_product_images table in the database. The image is identified
   * by both the product ID and image ID to ensure precise targeting. This
   * operation performs a hard deletion, completely removing the image record
   * from the system.
   *
   * Security considerations include verifying that the requesting user has
   * appropriate permissions to manage product images. Typically, this operation
   * should be restricted to product owners (sellers) or administrative users.
   * The operation validates that both the product and image exist and belong to
   * the same entity before proceeding with deletion.
   *
   * Related operations include creating product images (POST
   * /products/{productId}/images) and updating image properties (PUT
   * /products/{productId}/images/{imageId}). This operation is part of the
   * comprehensive product image management workflow in the shopping mall
   * platform.
   *
   * @param connection
   * @param productId Unique identifier of the target product
   * @param imageId Unique identifier of the target product image
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":imageId")
  public async erase(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedParam("imageId")
    imageId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallSellerProductsProductIdImagesImageId({
        seller,
        productId,
        imageId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
