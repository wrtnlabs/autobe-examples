import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallSellerProductsProductIdVariants } from "../../../../../providers/postShoppingMallSellerProductsProductIdVariants";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { patchShoppingMallSellerProductsProductIdVariants } from "../../../../../providers/patchShoppingMallSellerProductsProductIdVariants";
import { putShoppingMallSellerProductsProductIdVariantsVariantId } from "../../../../../providers/putShoppingMallSellerProductsProductIdVariantsVariantId";
import { deleteShoppingMallSellerProductsProductIdVariantsVariantId } from "../../../../../providers/deleteShoppingMallSellerProductsProductIdVariantsVariantId";

import { IShoppingMallProductVariant } from "../../../../../api/structures/IShoppingMallProductVariant";
import { IPageIShoppingMallProductVariant } from "../../../../../api/structures/IPageIShoppingMallProductVariant";

@Controller("/shoppingMall/seller/products/:productId/variants")
export class ShoppingmallSellerProductsVariantsController {
  /**
   * Create a new product variant for an existing product in the shopping mall
   * catalog.
   *
   * This operation allows sellers to add new variant options to their existing
   * products. Variants enable products to have multiple configurations such as
   * different sizes, colors, materials, or other attributes while maintaining
   * the same core product identity.
   *
   * Each variant can have unique pricing, inventory levels, SKU identifiers,
   * and attribute combinations. The operation validates that the parent product
   * exists and belongs to the requesting seller before creating the new
   * variant. It also ensures that the variant SKU is unique within the
   * product's variant collection.
   *
   * Product variants support complex attribute configurations stored as JSON
   * data, allowing for flexible product option management. The created variant
   * becomes immediately available for purchase unless explicitly set to
   * inactive status.
   *
   * This operation integrates with the Product Variants table from the Prisma
   * schema, creating new records with proper relationships to the parent
   * product and maintaining data consistency across the product catalog.
   *
   * @param connection
   * @param productId Unique identifier of the parent product that will contain
   *   the new variant
   * @param body Creation data for the new product variant including attributes,
   *   pricing, and inventory
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallProductVariant.ICreate,
  ): Promise<IShoppingMallProductVariant> {
    try {
      return await postShoppingMallSellerProductsProductIdVariants({
        seller,
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a filtered and paginated list of product variants for a specific
   * product in the shopping mall catalog.
   *
   * This operation searches and filters product variants associated with a
   * particular product, providing advanced search capabilities for finding
   * variants based on multiple criteria including variant name matching, SKU
   * filtering, active status, and inventory levels. The operation operates on
   * the ProductVariants table from the Prisma schema and supports comprehensive
   * pagination with configurable page sizes and sorting options.
   *
   * Product variants can be sorted by creation date, variant name, price, or
   * stock quantity in ascending or descending order. The search functionality
   * supports complex queries including partial name matching, SKU pattern
   * matching, and inventory threshold filtering. Only variants belonging to the
   * specified product are included in the results.
   *
   * Security considerations include appropriate access controls to ensure that
   * only authorized users can view product variant information. The operation
   * validates that the requesting user has permission to access the product and
   * its variants, typically requiring seller ownership or administrative
   * privileges.
   *
   * This operation integrates with the ProductVariants table as defined in the
   * Prisma schema, which manages product variations with different attributes
   * like size, color, or style options. The response includes variant summary
   * information optimized for list displays.
   *
   * @param connection
   * @param productId Unique identifier of the target product
   * @param body Search criteria and pagination parameters for product variant
   *   filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallProductVariant.IRequest,
  ): Promise<IPageIShoppingMallProductVariant.ISummary> {
    try {
      return await patchShoppingMallSellerProductsProductIdVariants({
        seller,
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing product variant with new attribute values, pricing, and
   * inventory information.
   *
   * This operation allows sellers to modify product variant details such as
   * variant name, pricing, stock quantity, and attribute combinations. The
   * operation updates the shopping_mall_product_variants table in the database
   * and ensures that variant-specific information remains synchronized with the
   * parent product.
   *
   * Security considerations include verifying that the authenticated seller
   * owns both the product and variant being modified. The operation validates
   * that the SKU remains unique within the product context and ensures that
   * pricing and inventory updates comply with business rules.
   *
   * The updated variant information is immediately reflected in product
   * listings and shopping cart calculations. Related operations include
   * creating variants (POST /products/{productId}/variants) and retrieving
   * variant details (GET /products/{productId}/variants/{variantId}).
   *
   * @param connection
   * @param productId Unique identifier of the parent product that contains the
   *   target variant
   * @param variantId Unique identifier of the product variant to be updated
   * @param body Updated product variant information including pricing,
   *   inventory, and attributes
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":variantId")
  public async update(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedParam("variantId")
    variantId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallProductVariant.IUpdate,
  ): Promise<IShoppingMallProductVariant> {
    try {
      return await putShoppingMallSellerProductsProductIdVariantsVariantId({
        seller,
        productId,
        variantId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently remove a product variant from the shopping mall catalog.
   *
   * This operation performs a hard deletion of the product variant record from
   * the shopping_mall_product_variants table. The deletion is irreversible and
   * removes all variant-specific pricing, inventory, and attribute information.
   * The operation should be used cautiously as it affects product availability
   * and existing customer orders.
   *
   * Security validation ensures that only the seller who owns the parent
   * product can delete its variants. The operation checks for dependencies such
   * as active cart items or order line items referencing the variant before
   * proceeding with deletion.
   *
   * After successful deletion, the variant is immediately removed from product
   * listings and becomes unavailable for new purchases. Related operations
   * include updating variants (PUT /products/{productId}/variants/{variantId})
   * and creating new variants (POST /products/{productId}/variants).
   *
   * @param connection
   * @param productId Unique identifier of the parent product that contains the
   *   target variant
   * @param variantId Unique identifier of the product variant to be deleted
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":variantId")
  public async erase(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedParam("variantId")
    variantId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallSellerProductsProductIdVariantsVariantId({
        seller,
        productId,
        variantId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
