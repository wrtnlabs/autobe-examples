import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallSellerProductsProductIdAttributes } from "../../../../../providers/postShoppingMallSellerProductsProductIdAttributes";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { putShoppingMallSellerProductsProductIdAttributesAttributeId } from "../../../../../providers/putShoppingMallSellerProductsProductIdAttributesAttributeId";
import { deleteShoppingMallSellerProductsProductIdAttributesAttributeId } from "../../../../../providers/deleteShoppingMallSellerProductsProductIdAttributesAttributeId";

import { IShoppingMallProductAttribute } from "../../../../../api/structures/IShoppingMallProductAttribute";

@Controller("/shoppingMall/seller/products/:productId/attributes")
export class ShoppingmallSellerProductsAttributesController {
  /**
   * Create a new product attribute for a specific product in the shopping mall
   * catalog.
   *
   * This operation allows sellers to add custom attributes and specifications
   * to their products, enabling detailed product descriptions and enhanced
   * search capabilities. Attributes are key-value pairs that define product
   * characteristics such as size, color, material, or technical
   * specifications.
   *
   * The operation validates that the target product exists and belongs to the
   * authenticated seller before allowing attribute creation. Each attribute
   * name must be unique per product to prevent duplicate specifications. The
   * display order parameter controls how attributes are presented on product
   * detail pages.
   *
   * Security considerations include verifying that the seller owns the product
   * being modified. The system automatically tracks creation timestamps and
   * maintains attribute history for audit purposes. Related operations include
   * updating existing attributes (PUT
   * /products/{productId}/attributes/{attributeId}) and viewing product
   * attributes (GET /products/{productId}/attributes).
   *
   * @param connection
   * @param productId Unique identifier of the target product
   * @param body Attribute creation data including name, value, and display
   *   order
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallProductAttribute.ICreate,
  ): Promise<IShoppingMallProductAttribute> {
    try {
      return await postShoppingMallSellerProductsProductIdAttributes({
        seller,
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing product attribute for a specific product in the shopping
   * mall catalog.
   *
   * This operation allows sellers to modify attribute values, names, or display
   * order for their products. The system validates that both the product and
   * attribute exist and belong to the authenticated seller before processing
   * the update.
   *
   * Attribute updates maintain data consistency by preserving the unique
   * constraint per product. The operation supports partial updates where
   * sellers can modify individual attribute properties without affecting
   * others. Timestamp tracking ensures accurate audit trails of attribute
   * modifications.
   *
   * Security enforcement includes ownership verification for both the product
   * and attribute. The system prevents unauthorized modifications by validating
   * seller permissions at both entity levels. Related operations include
   * creating new attributes (POST /products/{productId}/attributes) and
   * deleting attributes (DELETE
   * /products/{productId}/attributes/{attributeId}).
   *
   * @param connection
   * @param productId Unique identifier of the target product
   * @param attributeId Unique identifier of the target attribute
   * @param body Attribute update data including modified name, value, or
   *   display order
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":attributeId")
  public async update(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedParam("attributeId")
    attributeId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallProductAttribute.IUpdate,
  ): Promise<IShoppingMallProductAttribute> {
    try {
      return await putShoppingMallSellerProductsProductIdAttributesAttributeId({
        seller,
        productId,
        attributeId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently remove a specific product attribute from the shopping mall
   * product catalog.
   *
   * This operation permanently deletes a product attribute associated with a
   * specific product in the shopping mall. The operation targets the
   * ProductAttributes table from the Prisma schema and removes the attribute
   * record completely from the database. This is a hard delete operation that
   * cannot be reversed, as the attribute is permanently removed rather than
   * soft deleted.
   *
   * Security considerations include verifying that the requesting user has
   * appropriate permissions to modify product attributes. Typically, only the
   * product owner (seller) or administrative users should be able to delete
   * product attributes. The operation validates that both the product and
   * attribute exist and are properly associated before proceeding with
   * deletion.
   *
   * This operation integrates with the ProductAttributes table as defined in
   * the Prisma schema, which stores product-specific attributes and
   * specifications for detailed product information. The deletion ensures
   * referential integrity by removing the attribute record and any dependent
   * data structures.
   *
   * Related operations include creating product attributes (POST
   * /products/{productId}/attributes) and updating product attributes (PUT
   * /products/{productId}/attributes/{attributeId}).
   *
   * @param connection
   * @param productId Unique identifier of the target product
   * @param attributeId Unique identifier of the target product attribute
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":attributeId")
  public async erase(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedParam("attributeId")
    attributeId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallSellerProductsProductIdAttributesAttributeId(
        {
          seller,
          productId,
          attributeId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
