import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallSellerProducts } from "../../../../providers/postShoppingMallSellerProducts";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { putShoppingMallSellerProductsProductId } from "../../../../providers/putShoppingMallSellerProductsProductId";
import { deleteShoppingMallSellerProductsProductId } from "../../../../providers/deleteShoppingMallSellerProductsProductId";

import { IShoppingMallProduct } from "../../../../api/structures/IShoppingMallProduct";

@Controller("/shoppingMall/seller/products")
export class ShoppingmallSellerProductsController {
  /**
   * Create a new product listing in the shopping mall catalog.
   *
   * This operation allows authenticated sellers to create new product listings
   * with comprehensive product information including name, description,
   * pricing, inventory quantities, and product specifications. The operation
   * validates that the seller has permission to create products and ensures all
   * required fields are provided.
   *
   * Business rules include validation of SKU uniqueness per seller, ensuring
   * pricing consistency, and setting appropriate default status values. The
   * operation automatically sets creation timestamps and initializes inventory
   * tracking for new products.
   *
   * Security considerations require seller authentication to prevent
   * unauthorized product creation. The operation integrates with the
   * shopping_mall_products table and validates relationships with categories
   * and sellers through foreign key constraints.
   *
   * @param connection
   * @param body Product creation information including all required fields
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IShoppingMallProduct.ICreate,
  ): Promise<IShoppingMallProduct> {
    try {
      return await postShoppingMallSellerProducts({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing product in the shopping mall catalog.
   *
   * This operation allows authenticated sellers to modify product information
   * including name, description, pricing, inventory, and categorization
   * details. The operation operates on the shopping_mall_products table from
   * the Prisma schema and requires ownership verification to ensure sellers can
   * only update their own products.
   *
   * The request body includes comprehensive product update fields that allow
   * sellers to modify all editable aspects of their product listings. The
   * operation validates that the referenced category exists and belongs to an
   * accessible section of the shopping mall. Pricing updates are validated to
   * ensure logical relationships between price, compare price, and cost price.
   *
   * Security considerations include seller authentication and ownership
   * verification. The seller's identity is extracted from the JWT
   * authentication token and matched against the product's seller_id field.
   * Products can only be updated if they are in an editable status (draft or
   * active).
   *
   * Related operations: Create product (POST /products), Delete product (DELETE
   * /products/{productId}), View product (GET /products/{productId}).
   *
   * @param connection
   * @param productId Unique identifier of the target product
   * @param body Product update information including modified fields
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":productId")
  public async update(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallProduct.IUpdate,
  ): Promise<IShoppingMallProduct> {
    try {
      return await putShoppingMallSellerProductsProductId({
        seller,
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Remove a product from the shopping mall catalog using soft deletion.
   *
   * This operation performs a soft delete on the product record by setting the
   * deleted_at timestamp, effectively removing the product from public
   * visibility while preserving the data for reporting and reactivation
   * purposes. The operation operates on the shopping_mall_products table from
   * the Prisma schema and requires seller authentication with ownership
   * verification.
   *
   * Soft deletion ensures that product data remains available for historical
   * reporting, order fulfillment, and potential reactivation. Products marked
   * as deleted are excluded from search results and public product listings but
   * remain accessible to sellers and administrators for management purposes.
   *
   * Security considerations include seller authentication and ownership
   * verification. The operation validates that the requesting seller owns the
   * product being deleted. Products with active orders or pending transactions
   * may require additional validation before deletion can proceed.
   *
   * Related operations: Create product (POST /products), Update product (PUT
   * /products/{productId}), View product (GET /products/{productId}).
   *
   * @param connection
   * @param productId Unique identifier of the target product
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":productId")
  public async erase(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallProduct> {
    try {
      return await deleteShoppingMallSellerProductsProductId({
        seller,
        productId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
