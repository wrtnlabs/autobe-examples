import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceCategory } from "../../../api/structures/IEcommerceCategory";
import { IPageIEcommerceCategory } from "../../../api/structures/IPageIEcommerceCategory";
import { getEcommerceCategoriesCategoryId } from "../../../providers/getEcommerceCategoriesCategoryId";
import { patchEcommerceCategories } from "../../../providers/patchEcommerceCategories";

@Controller("/ecommerce/categories")
export class EcommerceCategoriesController {
  /**
   * Retrieve a paginated and filtered list of product categories with hierarchical organization.
   *
   * This operation provides comprehensive category browsing capabilities for customers exploring the product catalog and administrators managing category structures. Supports filtering by category name, description content, and parent-child relationships to help users find relevant product categories efficiently.
   *
   * The response includes category summaries organized hierarchically, allowing customers to understand the category tree structure with one level of nesting. Pagination controls enable browsing large category catalogs while maintaining performance.
   *
   * Access control ensures that only authorized administrators can view soft-deleted categories while customers see only active categories. The system maintains data integrity by preserving category relationships during filtering operations.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for category filtering
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query the ecommerce_categories table with support for filtering by name (partial match), description (text search), parent category status (top-level vs subcategories), and pagination. Return categories in a hierarchical structure by including parent category relationships. Use Prisma's full-text search capabilities for description field with gin_trgm_ops index. Implement cursor-based pagination for large result sets. Include both active and soft-deleted categories in results to support administrative use cases. Ensure proper authorization - this endpoint should be accessible to all users but may return different data based on authentication status.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IEcommerceCategory.IRequest,
  ): Promise<IPageIEcommerceCategory.ISummary> {
    try {
      return await patchEcommerceCategories({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information for a specific product category.
   *
   * This operation provides complete category details including the category name, description, parent category relationship (if applicable), and creation/modification timestamps. Customers can use this endpoint to browse category information while administrators can access it for management purposes.
   *
   * The category system supports hierarchical organization with one level of nesting. Top-level categories have no parent category reference, while subcategories reference their parent category. This structure enables intuitive product organization and navigation throughout the e-commerce platform.
   *
   * Related operations include GET /categories for browsing all categories and GET /categories/{categoryId}/products for viewing products within a specific category. Administrative operations for category management are available through separate endpoints requiring appropriate permissions.
   *
   * @param connection
   * @param categoryId Unique identifier of the category to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query the ecommerce_categories table by ID to retrieve a single category. Include parent category relationship if available. Return 404 if category not found or soft-deleted. Validate that the category exists and is accessible.
   *
   * Implementation steps:
   * 1. Validate categoryId is a valid UUID
   * 2. Query ecommerce_categories table where id = categoryId and deleted_at is null
   * 3. Include parent category relationship for hierarchical display
   * 4. Return complete category information including name, description, parent_id, created_at, updated_at
   * 5. Handle not found errors with appropriate HTTP status
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":categoryId")
  public async at(
    @TypedParam("categoryId")
    categoryId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceCategory> {
    try {
      return await getEcommerceCategoriesCategoryId({
        categoryId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
