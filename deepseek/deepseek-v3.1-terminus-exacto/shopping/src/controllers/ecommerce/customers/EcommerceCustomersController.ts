import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceCustomer } from "../../../api/structures/IEcommerceCustomer";
import { IPageIEcommerceCustomer } from "../../../api/structures/IPageIEcommerceCustomer";
import { getEcommerceCustomersCustomerId } from "../../../providers/getEcommerceCustomersCustomerId";
import { patchEcommerceCustomers } from "../../../providers/patchEcommerceCustomers";

@Controller("/ecommerce/customers")
export class EcommerceCustomersController {
  /**
   * Search and retrieve a paginated list of customer accounts with advanced filtering capabilities.
   *
   * This operation provides administrators with comprehensive search functionality across customer accounts, including exact email matching, partial name matching using trigram similarity search, and creation date range filtering. The response includes customer summary information optimized for administrative overview displays.
   *
   * The ecommerce_customers table supports soft deletion using the deleted_at field, and by default this operation excludes soft-deleted records unless explicitly included through filter parameters. This ensures compliance with data retention policies while maintaining operational data for administrators.
   *
   * Administrators can use this endpoint to monitor customer registration patterns, search for specific accounts, and perform customer management tasks. The operation supports configurable pagination with page size limits and sorting options to handle large customer databases efficiently.
   *
   * Security considerations require that only authenticated administrators can access this operation to protect customer privacy. All search operations are logged for audit trail compliance.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for customer accounts
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query the ecommerce_customers table with pagination and filtering capabilities. Apply search filters on email (exact match), display_name (partial match using trigram similarity), and creation date ranges. Use cursor-based pagination for efficient large result sets. Exclude deleted customers unless explicitly requested. Return customer summaries without sensitive password_hash field. Validate that only administrators can access this operation for security.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IEcommerceCustomer.IRequest,
  ): Promise<IPageIEcommerceCustomer.ISummary> {
    try {
      return await patchEcommerceCustomers({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information for a specific customer account.
   *
   * This operation returns the complete customer profile including email address, display name, phone number, and account timestamps based on the ecommerce_customers table schema. The response includes all profile fields (id, email, display_name, phone_number, created_at, updated_at, deleted_at) while excluding the password_hash field for security.
   *
   * Customer profiles serve as the canonical identity record throughout the platform for personalization, order management, and communication. Profiles are editable through the profile update API and are referenced by orders, reviews, wishlists, and address management systems.
   *
   * If the customer account has been soft-deleted (deleted_at is not null), the retrieved profile will include the deletion timestamp while maintaining account visibility for order history preservation. Access is restricted to authorized users only, typically the customer themselves or platform administrators for support purposes.
   *
   * @param connection
   * @param customerId Unique identifier of the customer to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query the ecommerce_customers table by ID to retrieve customer details. Exclude the password_hash field from the response for security. Validate that the customer exists and return appropriate error if not found. Include all profile fields: id, email, display_name, phone_number, created_at, updated_at, deleted_at.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":customerId")
  public async at(
    @TypedParam("customerId")
    customerId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceCustomer> {
    try {
      return await getEcommerceCustomersCustomerId({
        customerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
