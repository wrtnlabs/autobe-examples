import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceShipment } from "../../../../../api/structures/IEcommerceShipment";
import { IPageIEcommerceShipment } from "../../../../../api/structures/IPageIEcommerceShipment";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { getEcommerceSellerOrdersOrderIdShipmentsShipmentId } from "../../../../../providers/getEcommerceSellerOrdersOrderIdShipmentsShipmentId";
import { patchEcommerceSellerOrdersOrderIdShipments } from "../../../../../providers/patchEcommerceSellerOrdersOrderIdShipments";
import { postEcommerceSellerOrdersOrderIdShipments } from "../../../../../providers/postEcommerceSellerOrdersOrderIdShipments";
import { putEcommerceSellerOrdersOrderIdShipmentsShipmentId } from "../../../../../providers/putEcommerceSellerOrdersOrderIdShipmentsShipmentId";

@Controller("/ecommerce/seller/orders/:orderId/shipments")
export class EcommerceSellerOrdersShipmentsController {
  /**
   * Create a new shipment package for order fulfillment with tracking information.
   *
   * This operation allows sellers to create shipment records for orders containing their products. Sellers can bundle multiple order items from the same order into a single shipment package, providing carrier details and tracking information for customer delivery tracking. The operation validates that all selected items belong to the seller making the request and are in 'paid' status ready for shipment.
   *
   * Shipment creation triggers status updates for all included order items, transitioning them from 'paid' to 'shipped' status. Customers receive notifications with tracking information and can monitor delivery progress through integrated carrier tracking systems. The system supports multiple shipment creation per order when items require separate packaging or staggered shipping.
   *
   * Security validation ensures sellers can only create shipments for their own order items, maintaining proper fulfillment accountability. Tracking numbers must be unique across all shipments to prevent conflicts in delivery tracking systems. Orders with soft deletion (deleted_at field) are preserved for audit purposes but may have restricted visibility.
   *
   * @param connection
   * @param orderId UUID of the target order for which to create shipment
   * @param body Shipment creation details including carrier information, tracking number, and order item selections
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Validate that the order exists and belongs to an order with items from the authenticating seller. Ensure all selected order items belong to the same seller (the authenticated seller) and have status 'paid' (ready for shipment). Create shipment record with provided carrier name, tracking number, and default status 'created'. Associate selected order items with the shipment through ecommerce_shipment_items junction table. Update all selected order items status to 'shipped'. Set shipped_at timestamp to current time. Return complete shipment details with included items. Validate tracking number uniqueness across all shipments.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceShipment.ICreate,
  ): Promise<IEcommerceShipment> {
    try {
      return await postEcommerceSellerOrdersOrderIdShipments({
        seller,
        orderId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a paginated and filtered list of shipments associated with a specific order.
   *
   * This operation allows customers to track all shipments related to their order, providing visibility into the shipping progress across potentially multiple sellers. Each shipment represents a package sent by a seller containing one or more order items from the same seller. Customers can monitor tracking information, carrier details, and delivery status for each shipment associated with their order.
   *
   * The response includes shipment summaries with essential information such as carrier name, tracking number, shipment status, creation timestamp, and delivery confirmation details. This enables customers to track their order fulfillment progress and anticipate delivery timelines.
   *
   * Shipments are automatically created by sellers when they prepare order fulfillment packages. Different sellers always ship separately, so an order containing items from multiple sellers will have multiple shipments. Customers confirm delivery per shipment rather than per individual item, and automatic delivery confirmation occurs after 14 days if not manually confirmed.
   *
   * This operation supports comprehensive filtering capabilities including shipment status filtering (created, shipped, delivered), date range filtering for shipment creation, and carrier-specific filtering. The pagination system ensures efficient handling of orders with numerous shipments while maintaining optimal performance for large result sets.
   *
   * @param connection
   * @param orderId Unique identifier of the order to retrieve shipments for
   * @param body Search criteria and pagination parameters for filtering shipments
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query the ecommerce_shipments table filtered by the specified order ID through the ecommerce_shipment_items association table. Join with ecommerce_shipment_items to find shipments containing order items from the specified order. Apply filtering based on request criteria including shipment status, carrier name, date ranges, and delivery status. Implement pagination with configurable page sizes and sorting options. Return shipment summaries optimized for list displays with essential tracking and status information. Validate that the requesting user has permission to access the specified order's shipments.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceShipment.IRequest,
  ): Promise<IPageIEcommerceShipment.ISummary> {
    try {
      return await patchEcommerceSellerOrdersOrderIdShipments({
        seller,
        orderId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific shipment within an order.
   *
   * This operation provides comprehensive shipment tracking information including carrier details, tracking number, shipment status, and delivery timestamps. Customers can use this endpoint to monitor the progress of their order shipments and track delivery status.
   *
   * The response includes all order items contained within this specific shipment, allowing customers to see exactly which products are included in this shipment package. Shipment status progression follows the defined workflow: created → shipped → delivered, with automatic delivery confirmation occurring after 14 days if not manually confirmed.
   *
   * Security validation ensures that only the customer who placed the order can access shipment details for their own orders. The operation maintains data integrity by preserving the relationship between shipments, order items, and the parent order.
   *
   * @param connection
   * @param orderId Unique identifier of the parent order
   * @param shipmentId Unique identifier of the specific shipment
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query the ecommerce_shipments table by shipment ID and verify it belongs to the specified order ID through the shipment_items -> order_items -> orders relationship chain. Include shipment details, carrier information, tracking number, and join with shipment_items to retrieve the associated order items with their product variant details. Validate that the requesting customer has permission to view this shipment (must be the customer who placed the order).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":shipmentId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedParam("shipmentId")
    shipmentId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceShipment> {
    try {
      return await getEcommerceSellerOrdersOrderIdShipmentsShipmentId({
        seller,
        orderId,
        shipmentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update shipment details for a specific shipment within an order.
   *
   * This operation allows sellers to modify shipment information after creation, such as updating carrier details, tracking numbers, or correcting shipment status. The update is scoped to a specific order to ensure data integrity and proper authorization.
   *
   * Only sellers who own the shipment can perform updates. The system validates that the shipment belongs to the specified order before applying changes. Supported fields for update include carrier name, tracking number, and shipment status transitions following the platform's shipment lifecycle rules.
   *
   * Shipment updates trigger notifications to customers when tracking information changes or status progresses to shipped/delivered. The operation preserves the original creation timestamp while updating the modification timestamp for audit purposes.
   *
   * @param connection
   * @param orderId Unique identifier of the parent order containing the shipment
   * @param shipmentId Unique identifier of the shipment to be updated
   * @param body Shipment update information including carrier details and tracking updates
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Update an existing shipment record with new carrier information, tracking details, or status changes. Validate that the shipment belongs to the specified order before proceeding. Only allow updates to fields that sellers can modify after shipment creation (carrier_name, tracking_number, shipment_status updates). Ensure the shipment exists and belongs to the correct seller making the request. Update the shipment record and return the complete updated entity.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":shipmentId")
  public async update(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedParam("shipmentId")
    shipmentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceShipment.IUpdate,
  ): Promise<IEcommerceShipment> {
    try {
      return await putEcommerceSellerOrdersOrderIdShipmentsShipmentId({
        seller,
        orderId,
        shipmentId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
