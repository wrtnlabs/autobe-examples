import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceSellerProfileSnapshot } from "../../../../../api/structures/IEcommerceSellerProfileSnapshot";
import { IPageIEcommerceSellerProfileSnapshot } from "../../../../../api/structures/IPageIEcommerceSellerProfileSnapshot";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { getEcommerceSellerProfileSnapshotsSnapshotId } from "../../../../../providers/getEcommerceSellerProfileSnapshotsSnapshotId";
import { patchEcommerceSellerProfileSnapshots } from "../../../../../providers/patchEcommerceSellerProfileSnapshots";

@Controller("/ecommerce/seller/profile/snapshots")
export class EcommerceSellerProfileSnapshotsController {
  /**
   * Retrieve a paginated list of seller profile snapshots with filtering capabilities.
   *
   * This operation allows sellers to view their historical profile changes, which are automatically created whenever they update their shop information. Each snapshot captures the complete state of the seller's profile at a specific point in time, including shop name, description, and logo URL.
   *
   * The operation supports filtering by date ranges to help sellers locate specific profile changes. Pagination ensures efficient handling of large numbers of snapshots while maintaining performance. Sellers can use this endpoint to track their profile evolution over time and review past shop information.
   *
   * Security is enforced by ensuring sellers can only access their own profile snapshots. The authentication context determines which seller's snapshots are retrieved, preventing unauthorized access to other sellers' historical data.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering profile snapshots
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query the ecommerce_seller_profile_snapshots table filtered by the authenticated seller's ID. Apply date range filtering on created_at field if specified in the request. Support pagination with cursor-based or offset-based approach. Return snapshot summaries including shop name, description, logo URL, and creation timestamp. Ensure the response is properly paginated with metadata.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IEcommerceSellerProfileSnapshot.IRequest,
  ): Promise<IPageIEcommerceSellerProfileSnapshot.ISummary> {
    try {
      return await patchEcommerceSellerProfileSnapshots({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific seller profile snapshot by its unique identifier.
   *
   * This operation provides access to historical seller profile snapshots that are automatically created whenever a seller updates their shop profile. Each snapshot captures the complete state of the seller's profile at the time of modification, including shop name, description, and logo information.
   *
   * The snapshot system ensures data integrity and provides an audit trail for seller profile changes. Sellers can use this endpoint to review their profile history and understand how their shop information has evolved over time. The snapshots are immutable and preserved indefinitely for reference purposes.
   *
   * This operation requires authentication and authorization to ensure that sellers can only access their own profile snapshots. The response includes all the snapshot details captured at the time of creation, allowing sellers to see exactly what their profile looked like at any point in their shop's history.
   *
   * The snapshot is retrieved from the ecommerce_seller_profile_snapshots table which maintains historical records of all seller profile modifications. This operation returns the complete snapshot data including shop name, description, logo URL, and creation timestamp, providing sellers with visibility into their profile evolution.
   *
   * Note that this operation only returns snapshots belonging to the authenticated seller, and access to other sellers' snapshots is restricted through ownership validation.
   *
   * @param connection
   * @param snapshotId Unique identifier of the seller profile snapshot to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query the ecommerce_seller_profile_snapshots table by the provided snapshot ID. Validate that the authenticated seller owns the snapshot by checking the ecommerce_seller_id field against the current user's seller ID. Return the complete snapshot data including shop name, description, logo URL, and creation timestamp. Ensure proper authorization checks to prevent unauthorized access to other sellers' snapshots.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":snapshotId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("snapshotId")
    snapshotId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceSellerProfileSnapshot> {
    try {
      return await getEcommerceSellerProfileSnapshotsSnapshotId({
        seller,
        snapshotId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
