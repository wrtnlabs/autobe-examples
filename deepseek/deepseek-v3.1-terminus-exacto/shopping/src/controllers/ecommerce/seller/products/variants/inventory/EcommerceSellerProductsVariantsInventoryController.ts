import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceInventoryRecord } from "../../../../../../api/structures/IEcommerceInventoryRecord";
import { IEcommerceProductVariant } from "../../../../../../api/structures/IEcommerceProductVariant";
import { IPageIEcommerceInventoryRecord } from "../../../../../../api/structures/IPageIEcommerceInventoryRecord";
import { SellerAuth } from "../../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../../decorators/payload/SellerPayload";
import { getEcommerceSellerProductsProductIdVariantsVariantIdInventory } from "../../../../../../providers/getEcommerceSellerProductsProductIdVariantsVariantIdInventory";
import { postEcommerceSellerProductsProductIdVariantsVariantIdInventory } from "../../../../../../providers/postEcommerceSellerProductsProductIdVariantsVariantIdInventory";

@Controller(
  "/ecommerce/seller/products/:productId/variants/:variantId/inventory",
)
export class EcommerceSellerProductsVariantsInventoryController {
  /**
   * Retrieve the complete inventory history for a specific product variant.
   *
   * This operation provides a detailed audit trail of all stock movements associated with the specified variant, including restocking operations, order placements, cancellations, refunds, and manual adjustments. Each inventory record contains the quantity change amount, reason for the change, and timestamp.
   *
   * The response shows the chronological sequence of inventory transactions in reverse order (newest first). Positive quantity values indicate stock additions (restocking), while negative values represent stock reductions (orders, adjustments, losses). This comprehensive history supports business intelligence, stock reconciliation, and dispute resolution.
   *
   * Inventory records are automatically created by the system for order-related activities and can be manually created by sellers for restocking and adjustments. The current stock level for the variant is calculated as the sum of all historical inventory record quantities.
   *
   * Related operations include adding inventory (POST /sellers/variants/{variantId}/inventory/add) and subtracting inventory (POST /sellers/variants/{variantId}/inventory/subtract) for manual stock management.
   *
   * @param connection
   * @param productId The unique identifier of the parent product
   * @param variantId The unique identifier of the specific product variant
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query the ecommerce_inventory_records table filtered by the specific variant ID. Join with product variants and sellers tables to include relevant context. Apply chronological sorting (newest first) to show the most recent inventory changes first. Return all inventory records for the variant without pagination since this represents the complete history of a specific resource.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedParam("variantId")
    variantId: string & tags.Format<"uuid">,
  ): Promise<IPageIEcommerceInventoryRecord> {
    try {
      return await getEcommerceSellerProductsProductIdVariantsVariantIdInventory(
        {
          seller,
          productId,
          variantId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Add or subtract inventory for a specific product variant owned by the seller.
   *
   * This operation allows sellers to manage inventory levels through restocking (positive quantities) or adjustments/losses (negative quantities). Each inventory change creates an immutable history record with a specified reason, providing a complete audit trail for inventory management.
   *
   * The operation validates that the seller owns the product variant being modified and ensures that negative adjustments don't result in negative stock quantities. Inventory changes immediately update the variant's availability status for customers.
   *
   * For inventory restocking, use positive quantities to increase available stock. For inventory adjustments or losses (damaged goods, theft, etc.), use negative quantities to decrease stock levels.
   *
   * @param connection
   * @param productId UUID identifier of the product containing the target variant
   * @param variantId UUID identifier of the specific variant to modify inventory
   * @param body Inventory change details including quantity and reason
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Validate that the authenticated seller owns the product variant. Create an inventory record with the specified quantity (positive for restocking, negative for adjustments) and reason. Calculate the new current stock by summing all inventory records for this variant. If the variant stock becomes positive after the operation, mark it as available if it was previously out of stock. Return the updated inventory status including the new current stock and operation details.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async updateInventory(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedParam("variantId")
    variantId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceProductVariant.IInventoryChange,
  ): Promise<IEcommerceInventoryRecord.IInventoryStatus> {
    try {
      return await postEcommerceSellerProductsProductIdVariantsVariantIdInventory(
        {
          seller,
          productId,
          variantId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
