import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceProductVariant } from "../../../../../api/structures/IEcommerceProductVariant";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { deleteEcommerceSellerProductsProductIdVariantsVariantId } from "../../../../../providers/deleteEcommerceSellerProductsProductIdVariantsVariantId";
import { postEcommerceSellerProductsProductIdVariants } from "../../../../../providers/postEcommerceSellerProductsProductIdVariants";
import { putEcommerceSellerProductsProductIdVariantsVariantId } from "../../../../../providers/putEcommerceSellerProductsProductIdVariantsVariantId";

@Controller("/ecommerce/seller/products/:productId/variants")
export class EcommerceSellerProductsVariantsController {
  /**
   * Create a new product variant with specific SKU configuration and inventory settings.
   *
   * This operation allows approved sellers to add new variants to their existing products, enabling different option combinations (e.g., color, size, material) with individual pricing and stock management. Each variant requires a unique SKU code that serves as an inventory identifier across the entire platform.
   *
   * Important: Variant operations create snapshots preserving all changes for audit trails. However, variant deletion is constrained - variants can only be removed if no pending orders exist for the specific variant and no active cancellation/refund requests are associated. Products without variants remain visible but are marked as "unavailable" for purchase.
   *
   * The system validates product ownership to ensure sellers can only modify their own products and maintains strict SKU uniqueness across the platform. This operation enables sellers to diversify product offerings while maintaining inventory integrity and transactional consistency.
   *
   * @param connection
   * @param productId UUID of the target product to add the variant to
   * @param body Variant creation parameters including unique SKU, option values, pricing, and inventory settings
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Validate that the authenticated seller owns the target product identified by {productId}. Check SKU uniqueness across the platform to prevent duplicates. Create the variant record with the provided option values, price override (if specified), and initial quantity. Set created_at and updated_at timestamps to current time. Return the complete created variant object including the generated UUID and system-assigned timestamps. Ensure the variant is properly linked to its parent product through the ecommerce_product_id foreign key.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceProductVariant.ICreate,
  ): Promise<IEcommerceProductVariant> {
    try {
      return await postEcommerceSellerProductsProductIdVariants({
        seller,
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing product variant with modified properties including SKU code, option values, pricing override, and stock quantity.
   *
   * This operation allows sellers to modify the specific variant configurations for their products. All changes are validated against platform requirements including SKU uniqueness checks and proper option value formatting. The operation automatically creates an immutable snapshot before applying changes to preserve the previous state for audit trail purposes.
   *
   * When variants are deleted, they are soft-deleted using the deleted_at timestamp field, preserving the record for historical reference while removing it from active product listings. The request body accepts partial updates - only fields that need modification should be included. The system performs appropriate validation for each provided field and preserves existing values for omitted fields.
   *
   * Response includes the complete updated variant information for confirmation of changes. This endpoint requires seller authentication and ownership validation to ensure sellers can only modify variants belonging to their own products.
   *
   * @param connection
   * @param productId The unique identifier of the parent product that owns the variant
   * @param variantId The unique identifier of the specific variant to be updated
   * @param body Variant update properties including SKU, option values, price override, and quantity
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Validate that seller owns both the product and variant. Check SKU uniqueness across all variants when SKU is being modified. Update variant fields with validation: SKU (3-50 chars unique), option_values (JSON), price_override (positive decimal), quantity (non-negative integer). Create variant snapshot before changes capturing previous state. Update modified fields and set updated_at timestamp. Return complete variant information including all fields for confirmation.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":variantId")
  public async update(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedParam("variantId")
    variantId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceProductVariant.IUpdate,
  ): Promise<IEcommerceProductVariant> {
    try {
      return await putEcommerceSellerProductsProductIdVariantsVariantId({
        seller,
        productId,
        variantId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a specific product variant from the e-commerce platform.
   *
   * This operation allows sellers to remove a product variant from their product catalog. The deletion is subject to strict business constraints to maintain platform integrity. Before deletion, the system validates that no pending orders exist for the variant and no active cancellation or refund requests are associated with it.
   *
   * When a variant is deleted, the system performs a permanent deletion of the variant record from the database. The operation returns the complete variant information that was deleted for confirmation purposes before removal.
   *
   * Sellers can only delete variants belonging to their own products. The system maintains comprehensive audit trails through the snapshot system to track all variant modifications and deletions for dispute resolution and data integrity purposes.
   *
   * This operation must be preceeded by GET /ecommerce/seller/products/{productId}/variants/{variantId} to verify variant details before deletion.
   *
   * @param connection
   * @param productId Unique identifier of the parent product
   * @param variantId Unique identifier of the variant to delete
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Validate that the variant can be deleted by checking business constraints:
   * 1. Verify no pending order items exist with 'paid' or 'shipped' status for this specific variant
   * 2. Verify no pending cancellation or refund requests exist for this variant
   * 3. Check that the authenticated seller owns the parent product
   * 4. Perform soft deletion by setting deleted_at timestamp
   * 5. Return the deleted variant information for confirmation
   *
   * If constraints are violated, return appropriate error response indicating the specific constraint failure.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":variantId")
  public async erase(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedParam("variantId")
    variantId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteEcommerceSellerProductsProductIdVariantsVariantId({
        seller,
        productId,
        variantId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
