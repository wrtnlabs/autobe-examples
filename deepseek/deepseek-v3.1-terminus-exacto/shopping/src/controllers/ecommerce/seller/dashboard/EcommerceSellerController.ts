import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceSeller } from "../../../../api/structures/IEcommerceSeller";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { getEcommerceSellerDashboard } from "../../../../providers/getEcommerceSellerDashboard";

@Controller("/ecommerce/seller/dashboard")
export class EcommerceSellerController {
  /**
   * Retrieve comprehensive dashboard statistics for sellers to monitor their shop performance and pending actions.
   *
   * This endpoint provides sellers with an overview of their business metrics including total product listings, active order items requiring attention, and pending customer requests that need responses. The dashboard statistics help sellers prioritize their daily operations and respond promptly to customer needs.
   *
   * Security considerations ensure that each seller only sees their own data through proper authentication and authorization checks. The aggregated counts are calculated in real-time to provide the most current view of the seller's business status.
   *
   * Related API operations include order management endpoints for processing individual orders and request management endpoints for handling cancellation and refund requests displayed in the dashboard statistics.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query the database to aggregate statistics for the authenticated seller's dashboard. Count products where seller_id matches the authenticated seller and deleted_at is null. Count order items where seller_id matches and status is active. Count pending cancellation requests where ecommerce_seller_id matches and no response has been recorded yet. Count pending refund requests where ecommerce_seller_id matches and no response has been recorded yet. Return all counts in a single response object with proper labeling for the frontend dashboard display.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async dashboard(
    @SellerAuth()
    seller: SellerPayload,
  ): Promise<IEcommerceSeller> {
    try {
      return await getEcommerceSellerDashboard({
        seller,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
