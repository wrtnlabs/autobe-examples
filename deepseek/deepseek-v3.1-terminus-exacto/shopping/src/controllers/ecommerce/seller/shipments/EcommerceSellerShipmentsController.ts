import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceShipment } from "../../../../api/structures/IEcommerceShipment";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { postEcommerceSellerShipments } from "../../../../providers/postEcommerceSellerShipments";

@Controller("/ecommerce/seller/shipments")
export class EcommerceSellerShipmentsController {
  /**
   * Create a new shipment package containing order items from the seller's inventory.
   *
   * This API endpoint allows sellers to create shipments for fulfilling customer orders. When a seller receives orders containing their products, they can use this endpoint to create shipment records that bundle multiple order items into a single package for efficient shipping. The shipment creation process requires providing carrier information with tracking number and selecting which order items to include in the shipment package.
   *
   * Upon successful creation, the system automatically updates the status of all included order items to 'shipped' to reflect their progression in the order fulfillment workflow. This status change triggers customer notifications and enables delivery tracking through the provided carrier information. The shipment record preserves the complete shipping context including carrier details, tracking number, and item associations for audit and customer service purposes.
   *
   * This operation implements the business requirement that different sellers must always ship separately, while allowing sellers flexibility in how they bundle their own order items. The shipment creation process supports the platform's multi-seller fulfillment model where each seller manages their own shipping independently.
   *
   * @param connection
   * @param body Shipment creation details including carrier information and order items to include
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Validate that the authenticated user is a seller with active account status. Verify that all provided order item IDs belong to the seller and are in 'paid' status. Check that the tracking number is unique across all shipments. Create the shipment record with seller association and tracking information. For each included order item, create shipment item associations and update the order item status to 'shipped'. Update the shipment status to 'created' and set the shipment creation timestamp. Return the complete shipment record with all associated items and tracking information.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IEcommerceShipment.ICreate,
  ): Promise<IEcommerceShipment> {
    try {
      return await postEcommerceSellerShipments({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
