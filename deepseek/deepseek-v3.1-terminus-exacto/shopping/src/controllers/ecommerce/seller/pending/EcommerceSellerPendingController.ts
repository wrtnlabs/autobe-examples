import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceSeller } from "../../../../api/structures/IEcommerceSeller";
import { IPageIEcommerceSeller } from "../../../../api/structures/IPageIEcommerceSeller";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { patchEcommerceSellerPending } from "../../../../providers/patchEcommerceSellerPending";

@Controller("/ecommerce/seller/pending")
export class EcommerceSellerPendingController {
  /**
   * Retrieve a paginated list of sellers with pending approval status for administrative review workflows.
   *
   * This operation provides administrators with comprehensive visibility into seller registration requests that require attention. The response includes seller registration details, submission timestamps, and approval workflow status to support efficient review processes.
   *
   * Administrators can use this endpoint to monitor the seller approval pipeline, prioritize review activities based on registration timelines, and ensure compliance with platform onboarding policies. The paginated results support scalable administration of growing seller registration volumes.
   *
   * The operation integrates with the complete seller lifecycle management system, supporting proper audit trails and workflow tracking as specified in the administrative system requirements.
   *
   * @param connection
   * @param body Pagination and filtering parameters for sellers with pending approval status
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query ecommerce_seller_approval_queues table filtering by status='pending'. Apply pagination with configurable page size and sorting by submission_date descending. Join with ecommerce_sellers table to include seller registration details. Return summary information optimized for administrative review interface.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IEcommerceSeller.IRequest,
  ): Promise<IPageIEcommerceSeller.ISummary> {
    try {
      return await patchEcommerceSellerPending({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
