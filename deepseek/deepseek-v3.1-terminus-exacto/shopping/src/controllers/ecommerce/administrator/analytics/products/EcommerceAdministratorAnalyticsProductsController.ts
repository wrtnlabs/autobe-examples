import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceProductSnapshot } from "../../../../../api/structures/IEcommerceProductSnapshot";
import { IPageIEcommerceProductSnapshot } from "../../../../../api/structures/IPageIEcommerceProductSnapshot";
import { AdministratorAuth } from "../../../../../decorators/AdministratorAuth";
import { AdministratorPayload } from "../../../../../decorators/payload/AdministratorPayload";
import { patchEcommerceAdministratorAnalyticsProducts } from "../../../../../providers/patchEcommerceAdministratorAnalyticsProducts";

@Controller("/ecommerce/administrator/analytics/products")
export class EcommerceAdministratorAnalyticsProductsController {
  /**
   * Retrieve comprehensive product analytics data with advanced filtering capabilities.
   *
   * This operation provides business intelligence insights into product performance across the platform. It aggregates data from multiple sources including sales transactions, customer reviews, and inventory levels to deliver actionable analytics for sellers and administrators.
   *
   * The analytics include key performance indicators such as total revenue generated, number of orders placed, average customer rating, review count, and current inventory status. Results can be filtered by date ranges, specific sellers, product categories, rating thresholds, and sales performance metrics.
   *
   * This endpoint is essential for sellers to monitor their product performance and for administrators to analyze platform-wide product trends. The paginated response structure ensures efficient handling of large datasets while maintaining comprehensive analytics coverage.
   *
   * Security considerations require appropriate authorization based on user role - sellers can only view analytics for their own products, while administrators have access to all platform products.
   *
   * @param connection
   * @param body Analytics search criteria including filters, date ranges, and performance metrics
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Query product analytics data by joining multiple tables: ecommerce_products, ecommerce_product_variants, ecommerce_order_items, ecommerce_reviews, and ecommerce_sellers. Apply filters based on the request criteria including date ranges, seller IDs, category IDs, rating thresholds, and sales performance metrics. Calculate aggregate statistics for each product including total sales revenue, order count, average rating, and inventory status. Support pagination with configurable page sizes and sorting options for large result sets. Join with seller information to include shop details in the analytics response.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedBody()
    body: IEcommerceProductSnapshot.IRequest,
  ): Promise<IPageIEcommerceProductSnapshot.ISummary> {
    try {
      return await patchEcommerceAdministratorAnalyticsProducts({
        administrator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
