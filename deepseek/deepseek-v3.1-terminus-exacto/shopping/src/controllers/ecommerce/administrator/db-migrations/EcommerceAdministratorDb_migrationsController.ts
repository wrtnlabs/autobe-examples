import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceDbMigration } from "../../../../api/structures/IEcommerceDbMigration";
import { IPageIEcommerceDbMigration } from "../../../../api/structures/IPageIEcommerceDbMigration";
import { AdministratorAuth } from "../../../../decorators/AdministratorAuth";
import { AdministratorPayload } from "../../../../decorators/payload/AdministratorPayload";
import { getEcommerceAdministratorDbMigrationsMigrationId } from "../../../../providers/getEcommerceAdministratorDbMigrationsMigrationId";
import { patchEcommerceAdministratorDbMigrations } from "../../../../providers/patchEcommerceAdministratorDbMigrations";

@Controller("/ecommerce/administrator/db-migrations")
export class EcommerceAdministratorDb_migrationsController {
  /**
   * Retrieve a filtered and paginated list of database migration execution records from the ecommerce_db_migrations table.
   *
   * This operation provides comprehensive search capabilities for database migration history, allowing administrators to monitor migration execution status, track rollback capabilities, and analyze migration performance. Filters include migration name matching, version filtering, execution status selection, date range queries, and rollback capability filtering. The operation includes automatic filtering by deleted_at IS NULL to prevent exposure of soft-deleted migration records, as implemented by the database schema's soft delete capability through the deleted_at field.
   *
   * Supports advanced pagination with configurable page sizes, sorting options, and comprehensive result metadata. The response includes migration summary information suitable for administrative dashboards and monitoring interfaces, with fields mapped directly from the ecommerce_db_migrations table columns while excluding sensitive data like error_message and checksum fields for security.
   *
   * Security considerations: Only administrators should have access to this endpoint due to the sensitive nature of database migration information. The ecommerce_db_migrations table tracks all schema changes with execution status, rollback capability, and dependency information - making this a critical administrative oversight tool. Error messages and detailed migration content are excluded from summary responses for security purposes.
   *
   * Related operations: This search endpoint complements administrative oversight capabilities and should be used in conjunction with system monitoring tools. The migration execution_status field supports filtering by pending, executing, completed, failed, or rolled_back statuses as defined in the database schema.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for migration records
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Query ecommerce_db_migrations table with advanced filtering capabilities. Support search by migration name (partial match), version (exact match), execution status, date ranges (executed_at, created_at), and rollback capability. Apply pagination with configurable page sizes and sorting options. Return summary information optimized for list displays, excluding detailed error messages and checksums for security.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedBody()
    body: IEcommerceDbMigration.IRequest,
  ): Promise<IPageIEcommerceDbMigration.ISummary> {
    try {
      return await patchEcommerceAdministratorDbMigrations({
        administrator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific database migration execution.
   *
   * This operation provides comprehensive access to migration tracking data including execution status, timing information, rollback capabilities, and any error messages captured during migration execution. Administrators can use this endpoint to monitor migration health, verify execution details, and prepare for rollback operations if needed.
   *
   * The response includes complete migration metadata such as version information, execution duration, dependency tracking, and checksum validation data. This information is essential for database administrators managing schema evolution and ensuring migration integrity across deployment environments.
   *
   * Access to migration records is restricted to authorized administrative users who need visibility into database schema changes and migration execution history for operational oversight and troubleshooting purposes. The operation respects soft deletion by excluding migration records that have been marked as deleted.
   *
   * @param connection
   * @param migrationId Unique identifier of the database migration record
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Query the ecommerce_db_migrations table by primary key (id) to retrieve a single migration record. Include all fields from the migration table to provide complete execution details. Validate that the migrationId parameter is a valid UUID format before querying. Return 404 if no migration exists with the given ID.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":migrationId")
  public async at(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("migrationId")
    migrationId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceDbMigration> {
    try {
      return await getEcommerceAdministratorDbMigrationsMigrationId({
        administrator,
        migrationId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
