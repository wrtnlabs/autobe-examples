import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceCategory } from "../../../../api/structures/IEcommerceCategory";
import { AdministratorAuth } from "../../../../decorators/AdministratorAuth";
import { AdministratorPayload } from "../../../../decorators/payload/AdministratorPayload";
import { deleteEcommerceAdministratorCategoriesCategoryId } from "../../../../providers/deleteEcommerceAdministratorCategoriesCategoryId";
import { postEcommerceAdministratorCategories } from "../../../../providers/postEcommerceAdministratorCategories";
import { putEcommerceAdministratorCategoriesCategoryId } from "../../../../providers/putEcommerceAdministratorCategoriesCategoryId";

@Controller("/ecommerce/administrator/categories")
export class EcommerceAdministratorCategoriesController {
  /**
   * Create a new category in the e-commerce platform's hierarchical category system.
   *
   * This operation allows administrators to create new product categories with optional parent-child relationships supporting one level of nesting. Categories serve as the primary organizational structure for products, enabling efficient customer browsing and product discovery.
   *
   * When creating a category, the system validates that the category name is unique across all categories and ensures proper hierarchical relationships. Categories can be created as top-level categories (no parent) or as subcategories of existing categories. The operation preserves category integrity by preventing circular references and maintaining the one-level nesting constraint.
   *
   * Administrators can create categories with descriptive names and detailed descriptions to help customers understand the category scope and purpose. Created categories become immediately available for product assignment and customer browsing.
   *
   * The operation includes comprehensive validation to ensure data integrity, including unique name enforcement, parent category existence validation, and hierarchical depth constraints. Successful creation returns the complete category object with system-generated identifiers and timestamps.
   *
   * Related operations include GET /categories for browsing categories, PUT /categories/{categoryId} for category updates, and DELETE /categories/{categoryId} for category removal with product reassignment.
   *
   * @param connection
   * @param body Category creation data including name, description, and optional parent category reference
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Validate request body contains required name field and valid optional parentCategoryId. Check that category name is unique across all categories using @@unique([name]) constraint. If parentCategoryId is provided, verify the parent category exists and is not itself a subcategory (maintain one-level nesting). Create new category record with provided data, setting created_at and updated_at timestamps. Return complete category object including system-generated id and timestamps. Ensure proper authorization for administrator access only.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedBody()
    body: IEcommerceCategory.ICreate,
  ): Promise<IEcommerceCategory> {
    try {
      return await postEcommerceAdministratorCategories({
        administrator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing product category with new information.
   *
   * This operation allows administrators to modify category details including the category name, description, and parent category relationships. All changes are validated to ensure data integrity, including uniqueness constraints for category names within the same hierarchy level. The operation handles soft-deleted categories appropriately, requiring restoration of deleted categories before modification.
   *
   * Category updates preserve historical information through snapshot mechanisms, ensuring that previous versions of category data are retained for audit and reference purposes. The operation automatically updates the modification timestamp to track when changes were made. Circular reference prevention ensures that category hierarchies maintain valid tree structures without infinite loops.
   *
   * Administrators must have appropriate permissions to perform category updates. The system validates that parent category relationships do not create circular references by traversing the hierarchy and that the updated category structure maintains the platform's one-level nesting constraint. Category names must remain unique within their respective parent contexts to avoid ambiguity in product organization.
   *
   * Category updates are atomic operations that either succeed completely or fail with appropriate error messages. Failed updates leave the category data unchanged and preserve the existing category state for subsequent modification attempts.
   *
   * @param connection
   * @param categoryId UUID identifier of the category to update
   * @param body Updated category information
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Update an existing category in the ecommerce_categories table. Validate that the category name is unique within the same parent category level. Handle parent category relationships to prevent circular references. Update the updated_at timestamp automatically. Preserve the existing category information in data snapshots before making changes. Return the complete updated category object with all fields.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":categoryId")
  public async update(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("categoryId")
    categoryId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceCategory.IUpdate,
  ): Promise<IEcommerceCategory> {
    try {
      return await putEcommerceAdministratorCategoriesCategoryId({
        administrator,
        categoryId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Administrative endpoint for soft deleting a category from the e-commerce platform.
   *
   * This operation performs a logical deletion by setting the deleted_at timestamp, which preserves the category information for historical audit trails while removing it from active use. Only administrators with appropriate privileges can execute this operation.
   *
   * When a category is deleted, all products currently assigned to that category are automatically reassigned to have null category_id (uncategorized status) to maintain data integrity. This preserves the relationships in product snapshots while allowing products to be recategorized by administrators as needed.
   *
   * The category hierarchy structure is maintained through the parent_category_id relationships, and deletion requires validation that no active subcategories exist to prevent orphaned hierarchies. The operation creates appropriate audit trail records for administrative oversight.
   *
   * Related operations include GET /categories for browsing categories, POST /admin/categories for category creation, and PUT /admin/categories/{categoryId} for category updates. Administrator privileges are required for all category management operations.
   *
   * @param connection
   * @param categoryId UUID identifier of the category to be deleted
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Perform soft deletion of the specified category by setting the deleted_at timestamp to the current time. Validate that the category exists and is not already deleted. Update all products currently assigned to this category to set their category_id to null (uncategorized status). Create an audit log entry for the deletion action. Return 204 No Content on successful deletion.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":categoryId")
  public async erase(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("categoryId")
    categoryId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteEcommerceAdministratorCategoriesCategoryId({
        administrator,
        categoryId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
