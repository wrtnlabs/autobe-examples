import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceSeller } from "../../../api/structures/IEcommerceSeller";
import { IPageIEcommerceSeller } from "../../../api/structures/IPageIEcommerceSeller";
import { getEcommerceSellersSellerId } from "../../../providers/getEcommerceSellersSellerId";
import { patchEcommerceSellers } from "../../../providers/patchEcommerceSellers";

@Controller("/ecommerce/sellers")
export class EcommerceSellersController {
  /**
   * Search and filter seller accounts with comprehensive search criteria for administrative oversight.
   *
   * This operation provides administrators with advanced search capabilities to monitor and manage seller accounts across the platform. Supports filtering by account status (pending approval, approved, rejected, suspended, active), partial shop name matching, email address lookup, and account creation date ranges.
   *
   * Includes pagination with configurable page sizes and sorting options. The response provides summary information optimized for administrative dashboards and account management interfaces. Only accessible to platform administrators for oversight purposes.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for seller accounts
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query ecommerce_sellers table with comprehensive filtering and search capabilities. Implement full-text search on shop_name using trigram index for partial matching. Filter by account_status to show specific account states (pending_approval, approved, rejected, suspended, active). Support date range filtering on created_at for account creation timeframe. Return paginated results with appropriate sorting options (newest first by default). Include current stock calculation from inventory history for seller variants. Validate that only administrators can access this endpoint for platform oversight.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IEcommerceSeller.IRequest,
  ): Promise<IPageIEcommerceSeller.ISummary> {
    try {
      return await patchEcommerceSellers({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific seller account, honoring soft deletion semantics.
   *
   * This operation provides complete seller profile data including shop information, account status, and authentication details. The response includes the seller's shop name, description, logo image URL, current account status, and timestamps for account creation and updates. Soft-deleted seller accounts (those with a `deleted_at` timestamp) are automatically excluded from the results.
   *
   * Seller accounts go through an approval process and can have various statuses including 'pending_approval', 'approved', 'rejected', 'suspended', or 'active'. This operation returns the current status along with any approval reason provided by administrators.
   *
   * Access to seller information is restricted based on user roles and permissions. Administrators can view all seller accounts including soft-deleted ones, while regular users typically only see active accounts.
   *
   * @param connection
   * @param sellerId Unique identifier of the seller account to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query the ecommerce_sellers table by the provided sellerId parameter to retrieve the complete seller record. Validate that the seller exists and return the full entity including shop name, description, logo URL, account status, and timestamps. Handle cases where the seller ID is invalid or the seller doesn't exist by returning appropriate error responses.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sellerId")
  public async at(
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceSeller> {
    try {
      return await getEcommerceSellersSellerId({
        sellerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
