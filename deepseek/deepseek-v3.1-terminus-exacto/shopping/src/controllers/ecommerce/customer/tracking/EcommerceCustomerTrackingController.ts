import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceShipment } from "../../../../api/structures/IEcommerceShipment";
import { IPageIEcommerceShipment } from "../../../../api/structures/IPageIEcommerceShipment";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { patchEcommerceCustomerTracking } from "../../../../providers/patchEcommerceCustomerTracking";

@Controller("/ecommerce/customer/tracking")
export class EcommerceCustomerTrackingController {
  /**
   * Search and filter shipment tracking information for authenticated customers.
   *
   * This operation provides comprehensive tracking search capabilities allowing customers to find specific shipments by status, date ranges, tracking numbers, carrier information, and other criteria. Customers can only access shipments containing their own order items, ensuring proper data isolation and privacy.
   *
   * The response includes essential tracking information such as carrier details, tracking numbers, shipment status, estimated delivery dates, and creation timestamps. Pagination support enables efficient browsing of large shipment histories while maintaining performance.
   *
   * Security is enforced through customer authentication and ownership validation, preventing unauthorized access to shipment data. The operation integrates with the platform's order fulfillment workflow, providing customers with real-time visibility into their package delivery status.
   *
   * This operation requires successful execution of authentication check to validate customer identity before accessing shipment tracking data. All shipment data is filtered to include only order items belonging to the authenticated customer through the complex relationship chain: shipments → shipment_items → order_items → orders → customers.
   *
   * @param connection
   * @param body Search criteria for filtering shipment tracking information
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query shipment tracking information with customer authorization. Join shipments with order items and orders to verify customer ownership. Apply filters for shipment status, date ranges, tracking numbers, and carrier information. Support pagination with cursor-based approach for large result sets. Return summarized shipment information optimized for tracking display.
   *
   * Implementation steps:
   * 1. Validate customer authentication and extract customer ID
   * 2. Build query joining shipments → shipment_items → order_items → orders → customers
   * 3. Apply search filters from request body (status, date ranges, tracking, carrier)
   * 4. Implement pagination with proper ordering by creation date
   * 5. Return summarized shipment data with tracking information
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IEcommerceShipment.IRequest,
  ): Promise<IPageIEcommerceShipment.ISummary> {
    try {
      return await patchEcommerceCustomerTracking({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
