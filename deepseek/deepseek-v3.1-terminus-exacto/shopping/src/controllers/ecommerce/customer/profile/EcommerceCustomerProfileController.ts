import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceCustomer } from "../../../../api/structures/IEcommerceCustomer";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { getEcommerceCustomerProfile } from "../../../../providers/getEcommerceCustomerProfile";
import { putEcommerceCustomerProfile } from "../../../../providers/putEcommerceCustomerProfile";

@Controller("/ecommerce/customer/profile")
export class EcommerceCustomerProfileController {
  /**
   * Retrieve the authenticated customer's profile information from the ecommerce_customers database table.
   *
   * This operation returns the complete profile details of the currently authenticated customer, accessed through their session token. The customer must be logged in with a valid JWT token to access this endpoint, which provides all customer profile fields for viewing and verification purposes.
   *
   * The response includes essential customer information such as display name, email address, phone number, and timestamps, but excludes sensitive security fields like password_hash. This operation supports customer profile management and enables customers to review their account details before making updates via the profile update API.
   *
   * Security considerations require that customers can only access their own profile information. The authentication system ensures that each customer can only retrieve their own data through proper session validation and authorization checks. Access to other customer accounts is prevented by the system's authorization layer.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query the ecommerce_customers table using the authenticated customer's ID from the JWT token. Return all profile fields including id, email, display_name, phone_number, created_at, and updated_at. Exclude sensitive fields like password_hash and deleted_at from the response. Validate that the customer exists and is not soft-deleted before returning the profile data.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
  ): Promise<IEcommerceCustomer> {
    try {
      return await getEcommerceCustomerProfile({
        customer,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update customer profile information including display name and phone number.
   *
   * This operation allows authenticated customers to modify their personal profile information. Only the display name and phone number fields are editable through this endpoint. When a customer updates their profile, the changes take effect immediately across the platform and are reflected in all subsequent API calls.
   *
   * The operation validates input formats according to business rules: display name must be 1-50 characters and phone number must follow valid international format. Profile updates are logged for audit purposes but do not require administrator approval. Customers can only update their own profiles through this authenticated endpoint.
   *
   * Profile editing functionality is disabled for deleted or deactivated customer accounts. This endpoint works in conjunction with GET /profile for retrieving current profile information and supports the complete customer profile management workflow for the e-commerce platform.
   *
   * @param connection
   * @param body Profile update information with display name and phone number
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Update the authenticated customer's profile information. Validate the display name length (1-50 characters) and phone number format. Update only the provided fields in the ecommerce_customers table. Return the complete updated customer profile. Ensure the customer is authenticated and can only update their own profile.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IEcommerceCustomer.IUpdate,
  ): Promise<IEcommerceCustomer> {
    try {
      return await putEcommerceCustomerProfile({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
