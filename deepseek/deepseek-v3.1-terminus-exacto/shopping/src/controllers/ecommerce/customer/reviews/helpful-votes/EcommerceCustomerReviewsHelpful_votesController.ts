import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceReviewVote } from "../../../../../api/structures/IEcommerceReviewVote";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { deleteEcommerceCustomerReviewsReviewIdHelpfulVotes } from "../../../../../providers/deleteEcommerceCustomerReviewsReviewIdHelpfulVotes";
import { postEcommerceCustomerReviewsReviewIdHelpfulVotes } from "../../../../../providers/postEcommerceCustomerReviewsReviewIdHelpfulVotes";

@Controller("/ecommerce/customer/reviews/:reviewId/helpful-votes")
export class EcommerceCustomerReviewsHelpful_votesController {
  /**
   * Allows authenticated customers to cast a helpful vote on product reviews to surface quality content.
   *
   * This operation creates a vote record indicating whether a specific review was helpful or not helpful. Each customer can only vote once per review, enforced by database constraints defined in the `ecommerce_review_votes` schema. The system uses these votes to calculate helpfulness scores and prioritize reviews that provide the most value to shoppers.
   *
   * Votes reference the customer's current session for audit purposes and include comprehensive timestamp tracking. The helpful boolean field allows customers to indicate both positive and negative feedback on review quality.
   *
   * This voting system helps maintain review quality standards and ensures the most useful customer feedback receives appropriate visibility on product detail pages. The operation validates review existence and prevents duplicate voting through unique constraints on customer_id and review_id combinations.
   *
   * @param connection
   * @param reviewId UUID of the review being voted on
   * @param body Helpful vote decision with boolean indicator
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Validate that the review exists and is not deleted. Check that the customer hasn't already voted on this specific review (unique constraint on customer_id + review_id). Create vote record with the helpful boolean value, customer ID from authentication context, customer session ID, and target review ID. Return the complete vote record including timestamps. Handle constraint violation errors if customer tries to vote multiple times on same review.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceReviewVote.ICreate,
  ): Promise<IEcommerceReviewVote> {
    try {
      return await postEcommerceCustomerReviewsReviewIdHelpfulVotes({
        customer,
        reviewId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Removes a customer's helpful vote from a specific product review.
   *
   * This operation allows customers to retract their helpful vote on a review they previously marked as helpful. The system enforces that customers can only remove their own votes, preventing unauthorized deletion of other customers' votes. The deletion is performed using soft delete principles, preserving the vote record with a deletion timestamp for audit trail purposes while removing it from active helpfulness calculations.
   *
   * Customer authorization is enforced through the database schema's foreign key relationship between ecommerce_review_helpful_votes.customer_id and ecommerce_customers.id. Votes can only be removed by the customer who originally cast them, ensuring data integrity and preventing unauthorized access.
   *
   * The operation validates that the specified review exists and that the customer has previously cast a helpful vote for it. If no vote exists or the vote doesn't belong to the current customer, the operation returns an appropriate error response. After successful deletion, the review's helpfulness score is automatically recalculated to reflect the removal of the vote.
   *
   * This functionality supports the platform's commitment to transparent and reversible customer feedback, allowing users to change their mind about review helpfulness while maintaining data integrity through the soft delete mechanism.
   *
   * @param connection
   * @param reviewId Unique identifier of the review from which to remove the helpful vote
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Delete the customer's helpful vote for the specified review. Look up the existing vote record using the review ID from the path parameter and the authenticated customer's ID. Use soft delete by setting the deleted_at timestamp rather than hard deletion. Verify the vote exists and belongs to the current customer before proceeding. Log the deletion for audit purposes.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteEcommerceCustomerReviewsReviewIdHelpfulVotes({
        customer,
        reviewId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
