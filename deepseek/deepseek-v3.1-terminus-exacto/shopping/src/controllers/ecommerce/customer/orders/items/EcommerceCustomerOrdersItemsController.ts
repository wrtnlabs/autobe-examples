import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceOrderItem } from "../../../../../api/structures/IEcommerceOrderItem";
import { IPageIEcommerceOrderItem } from "../../../../../api/structures/IPageIEcommerceOrderItem";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { getEcommerceCustomerOrdersOrderIdItemsItemId } from "../../../../../providers/getEcommerceCustomerOrdersOrderIdItemsItemId";
import { patchEcommerceCustomerOrdersOrderIdItems } from "../../../../../providers/patchEcommerceCustomerOrdersOrderIdItems";

@Controller("/ecommerce/customer/orders/:orderId/items")
export class EcommerceCustomerOrdersItemsController {
  /**
   * Search and filter order items within a specific order with comprehensive filtering capabilities.
   *
   * This operation provides advanced search functionality for order items, allowing administrators, sellers with appropriate permissions, or customers (for their own orders) to retrieve specific order items based on various criteria. The operation supports filtering by item status, seller information, product variant details, quantity ranges, price parameters, and date ranges. It returns paginated results for efficient data handling of potentially large order item collections.
   *
   * The search functionality integrates with the ecommerce_order_items database table and maintains referential integrity through joins with related entities including ecommerce_sellers for seller information and ecommerce_product_variants for product details. The operation respects user permissions and data access restrictions based on the authenticated user's role and ownership relationships.
   *
   * For comprehensive order management, this operation complements other order-related APIs such as GET /orders/{orderId} for full order details and PATCH /orders for searching across multiple orders. Administrators can use this operation for oversight and analytics, while sellers can track their specific items across customer orders.
   *
   * @param connection
   * @param orderId Unique identifier of the parent order
   * @param body Search criteria and pagination parameters for filtering order items
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query ecommerce_order_items table filtered by order_id parameter matching the path orderId. Apply additional filters from request body including status values, seller_id matching, product_variant_id matching, quantity range filters, unit_price and total_price range filters. Join with ecommerce_sellers for seller name and profile information. Join with ecommerce_product_variants for product variant details and inventory tracking. Implement cursor-based pagination with configurable page sizes and sorting options. Validate that the authenticated user has appropriate permissions to access the specified order and its items. Return summarized order item information optimized for list displays with essential fields from related entities.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceOrderItem.IRequest,
  ): Promise<IPageIEcommerceOrderItem.ISummary> {
    try {
      return await patchEcommerceCustomerOrdersOrderIdItems({
        customer,
        orderId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific order item within a customer's order.
   *
   * This operation provides comprehensive details about an individual purchased item, including the product variant information at the time of purchase, seller details, quantity, pricing, and current status. Customers can use this endpoint to view specific items within their orders for tracking purposes or when managing cancellations and refunds.
   *
   * The response includes immutable purchase-time information that preserves the transaction details regardless of subsequent product or price changes. Each order item maintains independent status tracking, allowing customers to monitor the fulfillment progress of individual items within multi-seller orders.
   *
   * Access to this operation is restricted to the customer who placed the order. The system validates ownership by checking that the authenticated customer matches the customer_id of the parent order before returning any order item data.
   *
   * This endpoint references the ecommerce_order_items table which captures individual purchased items representing specific product variants within orders, with seller attribution for fulfillment management.
   *
   * @param connection
   * @param orderId Unique identifier of the parent order
   * @param itemId Unique identifier of the specific order item
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query the ecommerce_order_items table by the provided itemId, ensuring it belongs to the specified orderId. Join with related tables (ecommerce_orders, ecommerce_sellers, ecommerce_product_variants) to retrieve complete order item information including seller details and product variant information. Validate that the authenticated customer owns the parent order before returning the data. Return 404 if the order item doesn't exist or doesn't belong to the specified order.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":itemId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedParam("itemId")
    itemId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceOrderItem> {
    try {
      return await getEcommerceCustomerOrdersOrderIdItemsItemId({
        customer,
        orderId,
        itemId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
