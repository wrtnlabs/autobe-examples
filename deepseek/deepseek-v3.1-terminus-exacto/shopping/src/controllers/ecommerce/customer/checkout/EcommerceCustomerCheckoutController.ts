import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceOrder } from "../../../../api/structures/IEcommerceOrder";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { postEcommerceCustomerCheckout } from "../../../../providers/postEcommerceCustomerCheckout";

@Controller("/ecommerce/customer/checkout")
export class EcommerceCustomerCheckoutController {
  /**
   * Process customer checkout by converting shopping cart items into a completed order with payment processing.
   *
   * This operation validates the customer's shopping cart contents, requires selection of a shipping address, processes payment through external gateways, and creates a complete order record. The checkout process ensures all cart items are available and in stock before proceeding with order creation. Upon successful payment processing, shopping cart items are converted to permanent order items and the cart is cleared.
   *
   * The operation performs comprehensive validation including cart item availability, shipping address verification, and payment method validation. Customers must have at least one valid shipping address configured before checkout can proceed. The payment processing integrates with external payment gateways and creates transaction records for audit purposes.
   *
   * Successful checkout results in the creation of an order with all items from the shopping cart, deduction of inventory quantities, and generation of payment transaction records. The shopping cart is automatically cleared after successful order creation to prevent duplicate purchases.
   *
   * @param connection
   * @param body Checkout request parameters including shipping address selection and payment information
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Validate customer shopping cart contents and process checkout to create a new order.
   *
   * First, retrieve the customer's active shopping cart and validate all cart items:
   * - Ensure cart exists and belongs to the authenticated customer
   * - Verify all cart items are available (product variants exist and are in stock)
   * - Check that quantities do not exceed available inventory
   * - Remove any invalid items and notify customer
   *
   * Validate shipping address:
   * - Customer must select a valid shipping address from their address book
   * - Verify address has all required fields (recipient, phone, street, city, state, postal code, country)
   * - Use default address if customer doesn't specify one
   *
   * Process payment through external gateway:
   * - Integrate with payment gateway using customer's payment method
   * - Handle authorization, processing, and reconciliation
   * - Create payment transaction record with status tracking
   * - Support retry logic for failed payments
   *
   * Create order and order items:
   * - Generate new order record linked to customer
   * - Convert each valid cart item to order item with purchase-time pricing
   * - Set initial order item status to 'paid'
   * - Calculate total order amount from all items
   *
   * Update inventory and clear cart:
   * - Deduct purchased quantities from product variant inventory
   * - Mark shopping cart as deleted (soft delete)
   * - Preserve cart items for audit trail
   *
   * Handle edge cases:
   * - Stock changes during checkout process
   * - Payment gateway failures
   * - Invalid shipping addresses
   * - Concurrent checkout attempts
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IEcommerceOrder.IRequest,
  ): Promise<IEcommerceOrder> {
    try {
      return await postEcommerceCustomerCheckout({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
