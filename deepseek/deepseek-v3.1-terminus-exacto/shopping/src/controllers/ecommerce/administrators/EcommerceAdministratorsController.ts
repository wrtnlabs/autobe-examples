  @TypedRoute.Get(":administratorId")
  public async at(
    @TypedParam("administratorId")
    administratorId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceAdministrator> {
    try {
      return await getEcommerceAdministratorsAdministratorId({
        administratorId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
