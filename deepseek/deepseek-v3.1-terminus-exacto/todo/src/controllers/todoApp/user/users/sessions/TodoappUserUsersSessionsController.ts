import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchTodoAppUserUsersUserIdSessions } from "../../../../../providers/patchTodoAppUserUsersUserIdSessions";
import { UserAuth } from "../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../decorators/payload/UserPayload";
import { getTodoAppUserUsersUserIdSessionsSessionId } from "../../../../../providers/getTodoAppUserUsersUserIdSessionsSessionId";
import { deleteTodoAppUserUsersUserIdSessionsSessionId } from "../../../../../providers/deleteTodoAppUserUsersUserIdSessionsSessionId";

import { IPageITodoAppUserSession } from "../../../../../api/structures/IPageITodoAppUserSession";
import { ITodoAppUserSession } from "../../../../../api/structures/ITodoAppUserSession";

@Controller("/todoApp/user/users/:userId/sessions")
export class TodoappUserUsersSessionsController {
  /**
   * Search and retrieve a filtered, paginated list of user sessions for a
   * specific user.
   *
   * Retrieve a filtered and paginated list of user sessions associated with a
   * specific user account. This operation provides advanced search capabilities
   * for finding sessions based on multiple criteria including session status
   * (active vs expired), creation date ranges, IP address patterns, and
   * connection context information.
   *
   * The operation supports comprehensive pagination with configurable page
   * sizes and sorting options. Sessions can be sorted by creation date,
   * expiration date, or other relevant fields in ascending or descending order.
   * Filtering options include searching for active sessions only, expired
   * sessions only, or all sessions regardless of status.
   *
   * Security considerations include ensuring that users can only access their
   * own session data. The operation validates that the requesting user has
   * permission to view the sessions for the specified user ID. Rate limiting
   * applies to prevent excessive session listing requests.
   *
   * This operation integrates with the todo_app_user_sessions table as defined
   * in the Prisma schema, incorporating all available session fields including
   * IP address, connection URL, referrer information, and timestamps. The
   * response includes session summary information optimized for administrative
   * and user-facing displays.
   *
   * @param connection
   * @param userId Unique identifier of the target user
   * @param body Search criteria and pagination parameters for session filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoAppUserSession.IRequest,
  ): Promise<IPageITodoAppUserSession.ISummary> {
    try {
      return await patchTodoAppUserUsersUserIdSessions({
        user,
        userId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific user session.
   *
   * Retrieve comprehensive details about a specific user session identified by
   * its unique session ID. This operation provides complete session information
   * including connection context (IP address, URL, referrer), creation
   * timestamp, expiration status, and the associated user information.
   *
   * The operation validates that the session belongs to the specified user and
   * that the requesting user has appropriate permissions to view the session
   * details. Session data includes security-relevant information that may be
   * used for audit purposes or user activity monitoring.
   *
   * Security considerations include ensuring that users can only access their
   * own session data. The operation performs ownership verification to prevent
   * unauthorized access to session information. Session details may be used for
   * security auditing, troubleshooting connection issues, or monitoring user
   * activity patterns.
   *
   * This operation integrates with the todo_app_user_sessions table as defined
   * in the Prisma schema, returning all available session fields. The response
   * includes the complete session object with relationship information to the
   * associated user account.
   *
   * @param connection
   * @param userId Unique identifier of the target user
   * @param sessionId Unique identifier of the target session
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppUserSession> {
    try {
      return await getTodoAppUserUsersUserIdSessionsSessionId({
        user,
        userId,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a specific user session.
   *
   * This operation permanently removes a user session record from the database.
   * The session is identified by both the user ID and session ID to ensure
   * proper scoping and authorization.
   *
   * User sessions are created automatically during authentication and track
   * user login activity across different devices. This delete operation allows
   * administrators to forcibly terminate sessions for security reasons, such as
   * when a device is lost or compromised, or when suspicious activity is
   * detected.
   *
   * The operation requires both the user ID and session ID to ensure that only
   * authorized administrators can delete sessions. This prevents accidental or
   * malicious deletion of sessions belonging to other users. The deletion is
   * permanent and cannot be undone, so it should be used with caution.
   *
   * Security considerations include proper authorization checks to ensure only
   * administrators can perform this operation. The system should log all
   * session deletion events for audit purposes. Rate limiting may be applied to
   * prevent abuse of this endpoint.
   *
   * This operation integrates with the todo_app_user_sessions table as defined
   * in the Prisma schema, permanently removing the session record and all
   * associated data.
   *
   * @param connection
   * @param userId Unique identifier of the user who owns the target session
   * @param sessionId Unique identifier of the target session to be deleted
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":sessionId")
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoAppUserUsersUserIdSessionsSessionId({
        user,
        userId,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
