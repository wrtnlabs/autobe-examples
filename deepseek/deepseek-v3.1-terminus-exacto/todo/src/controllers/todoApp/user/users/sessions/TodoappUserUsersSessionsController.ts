import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchTodoAppUserUsersUserIdSessions } from "../../../../../providers/patchTodoAppUserUsersUserIdSessions";
import { UserAuth } from "../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../decorators/payload/UserPayload";
import { getTodoAppUserUsersUserIdSessionsSessionId } from "../../../../../providers/getTodoAppUserUsersUserIdSessionsSessionId";
import { deleteTodoAppUserUsersUserIdSessionsSessionId } from "../../../../../providers/deleteTodoAppUserUsersUserIdSessionsSessionId";

import { IPageITodoAppUserSession } from "../../../../../api/structures/IPageITodoAppUserSession";
import { ITodoAppUserSession } from "../../../../../api/structures/ITodoAppUserSession";

@Controller("/todoApp/user/users/:userId/sessions")
export class TodoappUserUsersSessionsController {
  /**
   * Search and retrieve a filtered, paginated list of user sessions.
   *
   * Retrieve a filtered and paginated list of user sessions from the system.
   * This operation provides advanced search capabilities for finding sessions
   * based on multiple criteria including IP address patterns, creation date
   * ranges, expiration status, and referrer information.
   *
   * The operation supports comprehensive pagination with configurable page
   * sizes and sorting options. Users can sort by creation date, expiration
   * date, or other relevant fields in ascending or descending order. The search
   * functionality allows filtering for active sessions, expired sessions, or
   * sessions within specific date ranges.
   *
   * Security considerations include ensuring that users can only access their
   * own session data. The system validates that the authenticated user matches
   * the userId parameter before returning any session information. Session data
   * may contain sensitive information such as IP addresses and referrer URLs.
   *
   * This operation integrates with the todo_app_user_sessions table as defined
   * in the Prisma schema, which tracks user authentication sessions with
   * detailed connection information. The response includes session summary
   * information optimized for administrative review.
   *
   * @param connection
   * @param userId Unique identifier of the target user whose sessions to
   *   retrieve
   * @param body Search criteria and pagination parameters for session filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoAppUserSession.IRequest,
  ): Promise<IPageITodoAppUserSession.ISummary> {
    try {
      return await patchTodoAppUserUsersUserIdSessions({
        user,
        userId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific user session by ID.
   *
   * This operation retrieves detailed information about a specific user session
   * identified by the session ID. The session must belong to the authenticated
   * user specified in the path parameter.
   *
   * User sessions represent active login instances and contain metadata such as
   * IP address, connection URL, referrer information, and timestamps. This
   * operation is primarily used for session management and audit purposes.
   *
   * Security considerations include verifying that the requesting user has
   * permission to access the specified session. The system validates that the
   * session belongs to the authenticated user before returning session
   * details.
   *
   * This operation integrates with the todo_app_user_sessions table as defined
   * in the Prisma schema, returning complete session information including
   * creation time, expiration status, and connection details.
   *
   * @param connection
   * @param userId Unique identifier of the target user (global scope)
   * @param sessionId Unique identifier of the target session within the user
   *   (scoped to user)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppUserSession> {
    try {
      return await getTodoAppUserUsersUserIdSessionsSessionId({
        user,
        userId,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Terminate a specific user session by ID.
   *
   * This operation terminates a user session by marking it as expired. The
   * operation performs a soft delete by setting the expired_at timestamp in the
   * todo_app_user_sessions table, allowing for session audit trails while
   * effectively ending the session.
   *
   * Session termination is useful for security purposes, such as when a user
   * wants to log out from a specific device or when suspicious activity is
   * detected. The system validates that the session belongs to the
   * authenticated user before allowing termination.
   *
   * Security considerations include preventing users from terminating sessions
   * that do not belong to them. The operation ensures proper authorization
   * checks are performed before modifying session records.
   *
   * This operation integrates with the todo_app_user_sessions table as defined
   * in the Prisma schema, updating the expired_at field to effectively
   * terminate the session while preserving audit information.
   *
   * @param connection
   * @param userId Unique identifier of the target user (global scope)
   * @param sessionId Unique identifier of the target session within the user
   *   (scoped to user)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":sessionId")
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppUserSession> {
    try {
      return await deleteTodoAppUserUsersUserIdSessionsSessionId({
        user,
        userId,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
