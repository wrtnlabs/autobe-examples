import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchTodoAppUserUsersUserEmailSessions } from "../../../../../providers/patchTodoAppUserUsersUserEmailSessions";
import { UserAuth } from "../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../decorators/payload/UserPayload";
import { getTodoAppUserUsersUserEmailSessionsSessionId } from "../../../../../providers/getTodoAppUserUsersUserEmailSessionsSessionId";
import { deleteTodoAppUserUsersUserEmailSessionsSessionId } from "../../../../../providers/deleteTodoAppUserUsersUserEmailSessionsSessionId";
import { deleteTodoAppUserUsersUserIdSessionsSessionId } from "../../../../../providers/deleteTodoAppUserUsersUserIdSessionsSessionId";

import { IPageITodoAppUserSession } from "../../../../../api/structures/IPageITodoAppUserSession";
import { ITodoAppUserSession } from "../../../../../api/structures/ITodoAppUserSession";

@Controller("/todoApp/user/users")
export class TodoappUserUsersSessionsController {
  /**
   * Search and retrieve user sessions filtered by user email.
   *
   * This operation provides comprehensive search capabilities for retrieving
   * user session records associated with a specific user identified by their
   * email address. The search functionality supports filtering by session
   * status, creation date ranges, and activity patterns, along with full
   * pagination support for large result sets.
   *
   * Security considerations include validating that the requesting user has
   * appropriate permissions to view session information. The operation ensures
   * data isolation by restricting results to sessions belonging to the
   * specified user email. Session records include connection details such as IP
   * address, user agent, and activity timestamps for security auditing
   * purposes.
   *
   * The operation integrates with the todo_app_user_sessions table as defined
   * in the Prisma schema, incorporating all available session fields and
   * relationships. The response includes session summary information optimized
   * for administrative review and security monitoring workflows.
   *
   * @param connection
   * @param userEmail Email address of the target user whose sessions are being
   *   retrieved
   * @param body Search criteria and pagination parameters for session filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch(":userEmail/sessions")
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userEmail")
    userEmail: string & tags.Format<"email">,
    @TypedBody()
    body: ITodoAppUserSession.IRequest,
  ): Promise<IPageITodoAppUserSession.ISummary> {
    try {
      return await patchTodoAppUserUsersUserEmailSessions({
        user,
        userEmail,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information for a specific user session.
   *
   * This operation provides detailed session information for security auditing
   * and administrative review purposes. It retrieves comprehensive data about a
   * specific user session including connection details, authentication context,
   * and activity patterns.
   *
   * The operation validates that both the user email and session ID exist and
   * are properly associated. Security measures ensure that only authorized
   * users can access detailed session information, with appropriate permission
   * checks based on the requesting user's role and relationship to the target
   * session.
   *
   * Detailed session information includes IP address, user agent, referrer
   * data, creation timestamp, last activity timestamp, and expiration status.
   * This comprehensive view supports security investigations, user support
   * scenarios, and compliance auditing requirements.
   *
   * @param connection
   * @param userEmail Email address of the target user who owns the session
   * @param sessionId Unique identifier of the target user session
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":userEmail/sessions/:sessionId")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userEmail")
    userEmail: string & tags.Format<"email">,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppUserSession> {
    try {
      return await getTodoAppUserUsersUserEmailSessionsSessionId({
        user,
        userEmail,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a specific user session by session ID.
   *
   * This operation permanently removes a user session from the system,
   * invalidating the associated authentication token. The operation requires
   * both the user's email address and the specific session ID to ensure precise
   * targeting of the session to be deleted.
   *
   * Security considerations include verifying that the requesting user has
   * permission to delete the specified session. The operation validates that
   * the session belongs to the specified user before proceeding with deletion.
   * Session deletion is an irreversible action that immediately terminates the
   * user's access through that session.
   *
   * This operation integrates with the todo_app_user_sessions table as defined
   * in the Prisma schema, ensuring proper cleanup of session records and
   * maintaining referential integrity with the associated user account. The
   * operation is designed for administrative and user self-service session
   * management scenarios.
   *
   * @param connection
   * @param userEmail Email address of the user who owns the target session
   * @param sessionId Unique identifier of the target session to be deleted
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":userEmail/sessions/:sessionId")
  public async eraseByUseremailAndSessionid(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userEmail")
    userEmail: string & tags.Format<"email">,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoAppUserUsersUserEmailSessionsSessionId({
        user,
        userEmail,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a specific user session by session ID.
   *
   * This operation permanently removes a user session from the system,
   * invalidating the associated authentication token. The operation requires
   * both the user's ID (UUID) and the specific session ID to ensure precise
   * targeting of the session to be deleted.
   *
   * Security considerations include verifying that the requesting user has
   * permission to delete the specified session. The operation validates that
   * the session belongs to the specified user before proceeding with deletion.
   * Session deletion is an irreversible action that immediately terminates the
   * user's access through that session.
   *
   * This operation integrates with the todo_app_user_sessions table as defined
   * in the Prisma schema, ensuring proper cleanup of session records and
   * maintaining referential integrity with the associated user account. The
   * operation is designed for administrative and user self-service session
   * management scenarios.
   *
   * @param connection
   * @param userId Unique identifier (UUID) of the user who owns the target
   *   session
   * @param sessionId Unique identifier of the target session to be deleted
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":userId/sessions/:sessionId")
  public async eraseByUseridAndSessionid(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoAppUserUsersUserIdSessionsSessionId({
        user,
        userId,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
