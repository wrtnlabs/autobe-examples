import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { getTodoAppUserUsersUserId } from "../../../../providers/getTodoAppUserUsersUserId";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { putTodoAppUserUsersUserId } from "../../../../providers/putTodoAppUserUsersUserId";
import { deleteTodoAppUserUsersUserId } from "../../../../providers/deleteTodoAppUserUsersUserId";

import { ITodoAppUser } from "../../../../api/structures/ITodoAppUser";

@Controller("/todoApp/user/users/:userId")
export class TodoappUserUsersController {
  /**
   * Retrieve a specific user account by ID.
   *
   * This API operation retrieves detailed information for a specific user
   * account identified by the unique user ID. The operation accesses the
   * todo_app_users table in the database and returns comprehensive user data
   * including email address, account status, creation timestamp, and last
   * update timestamp.
   *
   * Security considerations require that authenticated users can only access
   * their own user account information. The system validates that the
   * requesting user's authentication token matches the user ID specified in the
   * path parameter to prevent unauthorized access to other users' data.
   *
   * The operation integrates with the User table as defined in the Prisma
   * schema, incorporating all available user fields and relationships. The
   * response includes complete user information suitable for account management
   * and profile display purposes.
   *
   * @param connection
   * @param userId Unique identifier of the target user
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppUser> {
    try {
      return await getTodoAppUserUsersUserId({
        user,
        userId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing user account.
   *
   * This operation allows authenticated users to update their account
   * information including email address, password, and account status. The
   * system validates all input data to ensure data integrity and security.
   *
   * When processing update requests, the system performs comprehensive
   * validation including email format verification, password complexity checks,
   * and email uniqueness validation across all user accounts. The operation
   * maintains audit trails by updating the timestamp of the last modification.
   *
   * Security considerations include proper authentication verification and
   * authorization checks to ensure users can only modify their own accounts.
   * The system logs all update operations for security monitoring and audit
   * purposes.
   *
   * This operation integrates with the todo_app_users table as defined in the
   * Prisma schema, incorporating all available user fields and relationships.
   * The response includes the complete updated user information reflecting the
   * changes made.
   *
   * @param connection
   * @param userId Unique identifier of the target user account
   * @param body User account update data including email, password, and status
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoAppUser.IUpdate,
  ): Promise<ITodoAppUser> {
    try {
      return await putTodoAppUserUsersUserId({
        user,
        userId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a user account.
   *
   * This operation performs a permanent deletion of a user account from the
   * Todo application. When a user account is deleted, all associated data
   * including todo items and session records are also removed through cascade
   * deletion to maintain data integrity.
   *
   * The deletion process is irreversible and removes all user data from the
   * system. Users should be properly informed about the consequences of account
   * deletion before proceeding with this operation.
   *
   * Security considerations include strict authentication verification to
   * ensure that users can only delete their own accounts. The system implements
   * proper authorization checks and logs all deletion operations for security
   * monitoring and audit purposes.
   *
   * This operation integrates with the todo_app_users table as defined in the
   * Prisma schema, and through cascade relationships, also affects
   * todo_app_todos and todo_app_user_sessions tables. The operation returns the
   * deleted user information as confirmation of the deletion.
   *
   * @param connection
   * @param userId Unique identifier of the target user account to be deleted
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppUser> {
    try {
      return await deleteTodoAppUserUsersUserId({
        user,
        userId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
