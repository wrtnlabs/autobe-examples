import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { getTodoAppUserTodosTodoIdLifecycle } from "../../../../../providers/getTodoAppUserTodosTodoIdLifecycle";
import { UserAuth } from "../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../decorators/payload/UserPayload";
import { putTodoAppUserTodosTodoIdLifecycle } from "../../../../../providers/putTodoAppUserTodosTodoIdLifecycle";

import { ITodoAppTodoLifecycle } from "../../../../../api/structures/ITodoAppTodoLifecycle";

@Controller("/todoApp/user/todos/:todoId/lifecycle")
export class TodoappUserTodosLifecycleController {
  /**
   * Retrieve the current lifecycle state of a specific todo item.
   *
   * This operation returns the complete lifecycle state information for a
   * specific todo item, including current status, priority level, and
   * completion tracking details. The lifecycle state represents the present
   * mutable state of the todo while the main todo table contains immutable
   * attributes.
   *
   * The response includes the todo's current status from the reference table,
   * priority level, completion percentage if applicable, and a reference to the
   * current snapshot that represents this state. This provides a comprehensive
   * view of the todo's current operational state without requiring historical
   * data queries.
   *
   * Security considerations include verifying that the requesting user has
   * appropriate permissions to view the todo's lifecycle state. The operation
   * validates that the todo exists and is accessible to the authenticated user
   * before returning lifecycle information.
   *
   * This operation integrates with the todo_app_todo_lifecycles table as
   * defined in the Prisma schema, providing efficient access to current todo
   * states for real-time management and tracking purposes.
   *
   * @param connection
   * @param todoId Unique identifier of the target todo
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppTodoLifecycle> {
    try {
      return await getTodoAppUserTodosTodoIdLifecycle({
        user,
        todoId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update the lifecycle state of a specific todo item.
   *
   * This operation allows authorized users to modify the current lifecycle
   * state of a todo item, including status changes, priority adjustments, and
   * completion tracking updates. When updating the lifecycle state, the system
   * automatically creates a new snapshot to preserve the historical record
   * while updating the current state.
   *
   * The operation validates that the requested status and priority values are
   * valid according to the reference tables. It ensures that completion
   * percentages are within acceptable ranges and that status transitions follow
   * business rules (e.g., completed todos cannot be reopened without proper
   * authorization).
   *
   * Security considerations include verifying that the requesting user has
   * ownership or appropriate permissions to modify the todo's lifecycle state.
   * The operation checks that the todo exists and is accessible before applying
   * updates.
   *
   * This operation integrates with the todo_app_todo_lifecycles table as
   * defined in the Prisma schema, maintaining data consistency between the
   * current state and historical snapshots while supporting real-time todo
   * management workflows.
   *
   * @param connection
   * @param todoId Unique identifier of the target todo
   * @param body Updated lifecycle state information for the todo
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoAppTodoLifecycle.IUpdate,
  ): Promise<ITodoAppTodoLifecycle> {
    try {
      return await putTodoAppUserTodosTodoIdLifecycle({
        user,
        todoId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
