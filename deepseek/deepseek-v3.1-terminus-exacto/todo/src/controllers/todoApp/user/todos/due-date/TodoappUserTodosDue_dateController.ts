import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { ITodoAppTodoDueDateField } from "../../../../../api/structures/ITodoAppTodoDueDateField";
import { UserAuth } from "../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../decorators/payload/UserPayload";
import { getTodoAppUserTodosTodoIdDueDate } from "../../../../../providers/getTodoAppUserTodosTodoIdDueDate";

@Controller("/todoApp/user/todos/:todoId/due-date")
export class TodoappUserTodosDue_dateController {
  /**
   * Retrieve the due date information for a specific todo.
   *
   * This operation returns the due date details associated with a particular todo identified by the todoId path parameter. The response includes the due date value if it has been set for the todo, or null if no due date has been configured.
   *
   * Access to this operation is restricted to the owner of the todo. The system verifies that the authenticated user owns the specified todo before returning the due date information. This ensures complete data isolation between users as required by the privacy-first design.
   *
   * The due date field is stored separately from the main todo entity to handle optional fields properly and support cross-validation with start dates when both are provided. This design allows for flexible date management while maintaining data integrity.
   *
   * @param connection
   * @param todoId The unique identifier of the todo whose due date information is being retrieved
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Query the todo_app_todo_due_date_fields table using the todoId from the path parameter. Join with the parent todo_app_todos table to verify ownership and access permissions. Return the due date field information if it exists, or null if no due date is set for this todo.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppTodoDueDateField> {
    try {
      return await getTodoAppUserTodosTodoIdDueDate({
        user,
        todoId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
