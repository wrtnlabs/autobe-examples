import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia from "typia";
import { patchTodoAppUserTodosStatuses } from "../../../../../providers/patchTodoAppUserTodosStatuses";
import { UserAuth } from "../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../decorators/payload/UserPayload";
import { getTodoAppUserTodosStatusesStatusCode } from "../../../../../providers/getTodoAppUserTodosStatusesStatusCode";

import { IPageITodoAppTodoStatus } from "../../../../../api/structures/IPageITodoAppTodoStatus";
import { ITodoAppTodoStatus } from "../../../../../api/structures/ITodoAppTodoStatus";

@Controller("/todoApp/user/todos/statuses")
export class TodoappUserTodosStatusesController {
  /**
   * Search and retrieve a filtered, paginated list of todo statuses.
   *
   * This operation provides comprehensive search and filtering capabilities for
   * todo status reference data. Administrators can use this endpoint to view
   * all available status options, filter by active/inactive status, and
   * paginate through large result sets.
   *
   * The operation supports advanced filtering including status code matching,
   * name searching, and active status filtering. Pagination parameters allow
   * for efficient browsing of status lists with configurable page sizes and
   * sorting options.
   *
   * Security considerations include restricting access to authorized
   * administrators only, as status management is a system-level function. The
   * operation integrates with the todo_app_todo_statuses table as defined in
   * the Prisma schema, ensuring data consistency across the application.
   *
   * Related operations include retrieving specific status details and managing
   * status configurations for the todo management system.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for status filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoAppTodoStatus.IRequest,
  ): Promise<IPageITodoAppTodoStatus.ISummary> {
    try {
      return await patchTodoAppUserTodosStatuses({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information for a specific todo status.
   *
   * This operation provides detailed information about a specific todo status
   * identified by its unique code. The status code serves as the primary
   * identifier for status reference data throughout the todo application.
   *
   * The operation returns comprehensive status information including the unique
   * code identifier, descriptive name, detailed explanation of the status
   * meaning, and whether the status is currently active for use in the system.
   * This information is essential for administrative interfaces and system
   * configuration management.
   *
   * Security considerations include restricting access to authorized
   * administrators only, as status reference data represents system-level
   * configuration. The operation validates that the requested status code
   * exists and returns appropriate error responses for invalid codes.
   *
   * This operation complements the status list search functionality by
   * providing detailed information for individual status records when needed
   * for administrative purposes.
   *
   * @param connection
   * @param statusCode Unique status code identifier of the target todo status
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":statusCode")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("statusCode")
    statusCode: string,
  ): Promise<ITodoAppTodoStatus> {
    try {
      return await getTodoAppUserTodosStatusesStatusCode({
        user,
        statusCode,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
