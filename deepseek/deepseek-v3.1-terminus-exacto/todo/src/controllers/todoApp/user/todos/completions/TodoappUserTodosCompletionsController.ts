import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { ITodoAppTodo } from "../../../../../api/structures/ITodoAppTodo";
import { ITodoAppTodoCompletion } from "../../../../../api/structures/ITodoAppTodoCompletion";
import { UserAuth } from "../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../decorators/payload/UserPayload";
import { getTodoAppUserTodosTodoIdCompletionsCompletionId } from "../../../../../providers/getTodoAppUserTodosTodoIdCompletionsCompletionId";
import { patchTodoAppUserTodosTodoIdCompletions } from "../../../../../providers/patchTodoAppUserTodosTodoIdCompletions";

@Controller("/todoApp/user/todos/:todoId/completions")
export class TodoappUserTodosCompletionsController {
  /**
   * Update the completion status of a specific todo by creating a new completion tracking record.
   *
   * This operation allows authenticated users to mark their todos as complete or incomplete. Each completion status change is recorded as a separate event in the completion tracking system, creating an audit trail of when todos were marked complete or incomplete.
   *
   * When a user marks a todo as complete, the system creates a new record in the completion tracking table with the current timestamp and the new completion status. This supports comprehensive edit history functionality and provides chronological tracking of completion status modifications.
   *
   * The operation validates that the target todo exists and belongs to the authenticated user before allowing the completion status update. The response includes the updated todo information along with its completion history for immediate feedback.
   *
   * This operation integrates with the broader todo lifecycle management system, supporting undo functionality through the ability to toggle completion status multiple times while maintaining a complete audit trail of all status changes.
   *
   * @param connection
   * @param todoId Unique identifier of the target todo
   * @param body Completion status update request
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Validate that the authenticated user owns the target todo before proceeding with completion status update. Create a new record in the todo_app_todo_completions table with the provided completion status and current timestamp. Update the todo's updated_at timestamp to reflect the modification. Return the updated todo information including its completion history for immediate user feedback. Ensure proper transaction handling to maintain data consistency between the todo and completion tracking tables.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async updateCompletion(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoAppTodo.ICompletionUpdate,
  ): Promise<ITodoAppTodo> {
    try {
      return await patchTodoAppUserTodosTodoIdCompletions({
        user,
        todoId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific completion status change record for a todo.
   *
   * This operation provides access to individual completion events in the audit trail of a todo's lifecycle. Each completion record represents a specific moment when the todo's completion status was changed, including the timestamp and the new status value (complete or incomplete).
   *
   * Users can use this endpoint to examine specific completion events for audit purposes or to understand the history of their todo's completion status changes. The operation ensures data privacy by verifying that the authenticated user owns both the todo and the completion record being accessed.
   *
   * The response includes the complete completion record details, allowing users to see exactly when a status change occurred and what the new status was set to. This supports transparency in todo management and provides valuable audit trail information for users tracking their task completion patterns.
   *
   * Security considerations: This operation requires authentication and ensures that users can only access completion records for their own todos. The system validates ownership through database joins before returning any data.
   *
   * Related operations: Use PATCH /todoApp/user/todos to search for todos, GET /todoApp/user/todos/{todoId} to retrieve todo details, and PATCH /todoApp/user/todos/{todoId}/completions to search completion history.
   *
   * @param connection
   * @param todoId Unique identifier of the parent todo
   * @param completionId Unique identifier of the completion record
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Retrieve a specific completion record by its ID, ensuring it belongs to the specified todo. Validate that both the todo and completion exist and that the authenticated user owns the todo. Return the complete completion record including the completion status, timestamp, and relationship information.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":completionId")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
    @TypedParam("completionId")
    completionId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppTodoCompletion> {
    try {
      return await getTodoAppUserTodosTodoIdCompletionsCompletionId({
        user,
        todoId,
        completionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
