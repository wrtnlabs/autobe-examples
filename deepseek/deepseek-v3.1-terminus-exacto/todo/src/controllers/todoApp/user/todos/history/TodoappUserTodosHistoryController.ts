import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageITodoAppTodoHistory } from "../../../../../api/structures/IPageITodoAppTodoHistory";
import { ITodoAppTodoHistory } from "../../../../../api/structures/ITodoAppTodoHistory";
import { UserAuth } from "../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../decorators/payload/UserPayload";
import { getTodoAppUserTodosTodoIdHistoryHistoryId } from "../../../../../providers/getTodoAppUserTodosTodoIdHistoryHistoryId";
import { patchTodoAppUserTodosTodoIdHistory } from "../../../../../providers/patchTodoAppUserTodosTodoIdHistory";

@Controller("/todoApp/user/todos/:todoId/history")
export class TodoappUserTodosHistoryController {
  /**
   * Retrieve a paginated list of edit history entries for a specific todo item.
   *
   * This operation provides comprehensive audit trail access for todo modifications, allowing users to view the complete history of changes made to their todos. Each history entry includes timestamp information and detailed field-level change tracking showing what specific fields were modified and when.
   *
   * The response includes pagination metadata for efficient navigation through potentially large history datasets. Users can track the evolution of their todos over time, including title changes, description updates, and date modifications.
   *
   * Security measures ensure that users can only access history for todos they own, maintaining strict data isolation between users. The system validates ownership before returning any history data.
   *
   * History entries are returned in reverse chronological order (newest first) to provide immediate access to recent changes while supporting backward navigation through older edits.
   *
   * @param connection
   * @param todoId UUID identifier of the target todo for which to retrieve history
   * @param body Pagination and filtering parameters for history retrieval
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Query todo_app_todo_histories table filtered by todo_app_todo_id parameter. Join with todo_app_todo_history_changes to include field-level change details. Apply pagination using cursor-based or offset-based approach. Validate that the requesting user owns the target todo to enforce data isolation. Return history entries sorted by created_at descending (newest first) with field change details included.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoAppTodoHistory.IRequest,
  ): Promise<IPageITodoAppTodoHistory.ISummary> {
    try {
      return await patchTodoAppUserTodosTodoIdHistory({
        user,
        todoId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific todo edit history entry from the `todo_app_todo_histories` table.
   *
   * This operation provides comprehensive audit trail access for individual edit operations performed on todos, as recorded in the `todo_app_todo_histories` table. Each history entry represents a distinct modification event with timestamp information, user attribution, and granular field-level change tracking captured in the `todo_app_todo_history_changes` table.
   *
   * The response includes the complete history record from `todo_app_todo_histories` along with all associated field changes from `todo_app_todo_history_changes` captured during the edit operation. This enables users to review specific modifications made to todo fields such as title, description, start date, or due date, providing full transparency into the edit history.
   *
   * Access to history entries is strictly scoped to the authenticated user's own todos, ensuring complete data privacy and isolation between users. The operation validates ownership through the todo-user relationship before returning any history data.
   *
   * Related operations include retrieving paginated history lists for todos and viewing todo details with current field values.
   *
   * @param connection
   * @param todoId Unique identifier of the target todo (UUID format)
   * @param historyId Unique identifier of the specific history entry to retrieve (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Query the todo_app_todo_histories table by the provided historyId, ensuring it belongs to the specified todoId and that the todo belongs to the authenticated user. Join with todo_app_todo_history_changes to include all field-level modifications. Validate that both the todo and history entry exist and are accessible to the current user. Return 404 if either resource is not found or inaccessible.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":historyId")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
    @TypedParam("historyId")
    historyId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppTodoHistory> {
    try {
      return await getTodoAppUserTodosTodoIdHistoryHistoryId({
        user,
        todoId,
        historyId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
