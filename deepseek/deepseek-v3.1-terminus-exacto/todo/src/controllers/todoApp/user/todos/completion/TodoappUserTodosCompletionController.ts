import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { ITodoAppTodo } from "../../../../../api/structures/ITodoAppTodo";
import { UserAuth } from "../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../decorators/payload/UserPayload";
import { putTodoAppUserTodosTodoIdCompletion } from "../../../../../providers/putTodoAppUserTodosTodoIdCompletion";

@Controller("/todoApp/user/todos/:todoId/completion")
export class TodoappUserTodosCompletionController {
  /**
   * Update the completion status of a specific todo, toggling between complete and incomplete states.
   *
   * This operation allows users to mark their todos as complete or incomplete based on the current status. When a todo is marked complete, the system records the completion timestamp and creates a history entry for audit trail purposes. When toggled back to incomplete, the completion timestamp is cleared while maintaining the historical record of the status change.
   *
   * The operation validates that the authenticated user owns the specified todo before allowing any modifications. It ensures data integrity by creating comprehensive audit trail entries in the todo_app_todo_histories table and tracking completion status changes in the todo_app_todo_completions table.
   *
   * This endpoint integrates with the broader todo management system, allowing users to efficiently track their task progress while maintaining complete edit history for compliance and user insight into their workflow patterns.
   *
   * @param connection
   * @param todoId UUID identifier of the todo to update completion status
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Validate user authentication and extract user ID from JWT token. Query todo_app_todos table to verify the todo exists and belongs to the authenticated user. If todo not found or access denied, return appropriate error. Check current completion status by querying todo_app_todo_completions for the most recent status. Toggle the completion status: if currently incomplete, mark as complete; if complete, mark as incomplete. Create new entry in todo_app_todo_completions table with the new status and timestamp. Update the todo's updated_at timestamp in todo_app_todos. Create comprehensive history entry in todo_app_todo_histories recording the status change. Return the updated todo entity with current completion status for immediate UI updates.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async updateCompletion(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppTodo> {
    try {
      return await putTodoAppUserTodosTodoIdCompletion({
        user,
        todoId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
