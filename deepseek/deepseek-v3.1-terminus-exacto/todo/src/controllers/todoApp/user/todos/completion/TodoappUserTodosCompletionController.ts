import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { ITodoAppTodoCompletion } from "../../../../../api/structures/ITodoAppTodoCompletion";
import { UserAuth } from "../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../decorators/payload/UserPayload";
import { getTodoAppUserTodosTodoIdCompletion } from "../../../../../providers/getTodoAppUserTodosTodoIdCompletion";

@Controller("/todoApp/user/todos/:todoId/completion")
export class TodoappUserTodosCompletionController {
  /**
   * Retrieve completion status information for a specific todo item.
   *
   * This operation returns the current completion status of a todo based on the most recent completion status change event recorded in the todo_app_todo_completions table. The system supports completion status tracking through a comprehensive audit system that records every status change event, allowing users to toggle between complete and incomplete states as specified in the business requirements.
   *
   * When a user marks a todo as complete, the system creates a new completion record with status 'true' and records the completion timestamp. When marked incomplete, a new record with status 'false' is created. This operation returns only the most recent completion status for efficiency, while separate history endpoints provide access to the complete audit trail.
   *
   * The operation supports the filtering capabilities specified in the requirements, where users can filter todos by completion status (All, Complete Only, Incomplete Only). Security ensures that users can only access completion information for their own todos, maintaining complete data isolation between user accounts.
   *
   * @param connection
   * @param todoId Unique identifier of the todo item to retrieve completion status for
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Retrieve the latest completion status for a specific todo by querying the most recent record from todo_app_todo_completions where todo_app_todo_id equals the provided {todoId}. If no completion record exists, assume incomplete status (default state). Include timestamp information from the most recent completion status change for audit purposes. Ensure the user can only access their own todos by verifying todo ownership through the todo_app_user_id relationship.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async current(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppTodoCompletion> {
    try {
      return await getTodoAppUserTodosTodoIdCompletion({
        user,
        todoId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
