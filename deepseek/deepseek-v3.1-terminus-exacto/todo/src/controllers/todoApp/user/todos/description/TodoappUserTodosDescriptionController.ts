import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { ITOdoAppTodoDescriptionField } from "../../../../../api/structures/ITOdoAppTodoDescriptionField";
import { UserAuth } from "../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../decorators/payload/UserPayload";
import { getTodoAppUserTodosTodoIdDescription } from "../../../../../providers/getTodoAppUserTodosTodoIdDescription";

@Controller("/todoApp/user/todos/:todoId/description")
export class TodoappUserTodosDescriptionController {
  /**
   * Retrieve the optional description field for a specific todo owned by the requesting user.
   *
   * This operation provides access to the description text associated with a todo, which is stored separately from the main todo entity to handle optional content efficiently. The description field supports rich text content and can be left empty if no description was provided during todo creation.
   *
   * Access to this description is restricted to the todo owner only, ensuring complete data isolation between users. If the todo exists but has no description field record, the operation returns an empty or null response indicating the absence of a description.
   *
   * This endpoint complements the main todo retrieval operations by providing focused access to specific optional fields, allowing clients to efficiently load description content without retrieving the entire todo entity when not needed. Proper authentication and authorization validation are critical security requirements.
   *
   * @param connection
   * @param todoId Unique identifier of the todo whose description is being retrieved
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Query the todo_app_todo_description_fields table using the provided todoId parameter. Join with todo_app_todos to verify ownership and existence. Return the description field record if it exists, otherwise return null or empty response. Ensure the requesting user owns the todo before returning the description.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
  ): Promise<ITOdoAppTodoDescriptionField> {
    try {
      return await getTodoAppUserTodosTodoIdDescription({
        user,
        todoId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
