import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchTodoAppUserTodosTodoIdSnapshots } from "../../../../../providers/patchTodoAppUserTodosTodoIdSnapshots";
import { UserAuth } from "../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../decorators/payload/UserPayload";
import { getTodoAppUserTodosTodoIdSnapshotsSnapshotId } from "../../../../../providers/getTodoAppUserTodosTodoIdSnapshotsSnapshotId";

import { IPageITodoAppTodoSnapshot } from "../../../../../api/structures/IPageITodoAppTodoSnapshot";
import { ITodoAppTodoSnapshot } from "../../../../../api/structures/ITodoAppTodoSnapshot";

@Controller("/todoApp/user/todos/:todoId/snapshots")
export class TodoappUserTodosSnapshotsController {
  /**
   * Search and retrieve a filtered, paginated list of todo snapshots.
   *
   * Retrieve a filtered and paginated list of historical snapshots for a
   * specific todo item. This operation provides advanced search capabilities
   * for finding snapshots based on multiple criteria including status,
   * priority, completion status, and creation date ranges.
   *
   * The operation supports comprehensive pagination with configurable page
   * sizes and sorting options. Users can sort by snapshot creation date,
   * completion date, or other relevant fields in ascending or descending
   * order.
   *
   * Security considerations include ensuring that users can only access
   * snapshots for todos they own or have appropriate permissions to view. The
   * operation validates that the referenced todo exists and belongs to an
   * accessible user before returning snapshot data.
   *
   * This operation integrates with the todo_app_todo_snapshots table as defined
   * in the Prisma schema, incorporating all available snapshot fields and
   * relationships. The response includes snapshot summary information optimized
   * for list displays, with options to include additional details based on
   * authorization level.
   *
   * @param connection
   * @param todoId Unique identifier of the target todo item
   * @param body Search criteria and pagination parameters for snapshot
   *   filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoAppTodoSnapshot.IRequest,
  ): Promise<IPageITodoAppTodoSnapshot.ISummary> {
    try {
      return await patchTodoAppUserTodosTodoIdSnapshots({
        user,
        todoId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information for a specific todo snapshot.
   *
   * Retrieve detailed information for a specific historical snapshot of a todo
   * item. This operation returns the complete snapshot record including all
   * captured state information at the time the snapshot was created.
   *
   * The snapshot includes the todo's status, priority level, completion
   * timestamp (if applicable), and the exact creation time of the snapshot.
   * This detailed view provides comprehensive insight into the todo's state at
   * a specific moment in its lifecycle.
   *
   * Security considerations include ensuring that users can only access
   * snapshots for todos they own or have appropriate permissions to view. The
   * operation validates that both the referenced todo and snapshot exist and
   * belong to accessible entities before returning the data.
   *
   * This operation integrates with the todo_app_todo_snapshots table as defined
   * in the Prisma schema, providing access to the complete snapshot record with
   * all its relationships and captured state information.
   *
   * @param connection
   * @param todoId Unique identifier of the target todo item
   * @param snapshotId Unique identifier of the target snapshot
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":snapshotId")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
    @TypedParam("snapshotId")
    snapshotId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppTodoSnapshot> {
    try {
      return await getTodoAppUserTodosTodoIdSnapshotsSnapshotId({
        user,
        todoId,
        snapshotId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
