import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { ITodoAppTodo } from "../../../../../api/structures/ITodoAppTodo";
import { UserAuth } from "../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../decorators/payload/UserPayload";
import { putTodoAppUserTrashTrashItemIdRestore } from "../../../../../providers/putTodoAppUserTrashTrashItemIdRestore";

@Controller("/todoApp/user/trash/:trashItemId/restore")
export class TodoappUserTrashRestoreController {
  /**
   * Restore a previously deleted todo from the trash collection back to active status.
   *
   * This operation allows users to recover todos that were accidentally deleted or removed from their active list. When a todo is restored, it is moved from the trash collection back to the user's active todo list with all its original data intact, including title, description, dates, and completion status.
   *
   * The restoration process preserves the todo's complete edit history and maintains all relationships. The operation creates an audit trail by recording the restoration event in the system logs. Users can only restore their own deleted todos, ensuring data privacy and security.
   *
   * After successful restoration, the todo becomes immediately available in the user's active todo list and can be managed normally. The trash item record remains in the system for audit purposes but is marked as restored to prevent duplicate restoration attempts.
   *
   * This operation is part of the comprehensive trash management system that provides users with a safety net against accidental data loss while maintaining clean data management practices.
   *
   * @param connection
   * @param trashItemId Unique identifier of the trash item to restore
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Restore a soft-deleted todo from trash back to active status.
   *
   * Query the todo_app_trash_items table to find the trash item by ID and verify it belongs to the authenticated user. Check that the item hasn't already been restored or permanently deleted. Update the restored_at timestamp to mark the restoration event. Remove the soft-delete flag from the associated todo by setting deleted_at to null. Create a restoration record in todo_app_trash_restorations for audit purposes. Return the restored todo information to confirm successful operation.
   *
   * Validation:
   * - Verify trash item exists and belongs to current user
   * - Check trash item is not already restored (restored_at is null)
   * - Check trash item is not permanently deleted (permanently_deleted_at is null)
   * - Ensure associated todo still exists
   *
   * Error handling:
   * - Return 404 if trash item not found or doesn't belong to user
   * - Return 400 if trash item already restored or permanently deleted
   * - Return 500 if database transaction fails
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async putByTrashitemid(
    @UserAuth()
    user: UserPayload,
    @TypedParam("trashItemId")
    trashItemId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppTodo> {
    try {
      return await putTodoAppUserTrashTrashItemIdRestore({
        user,
        trashItemId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
