import { Controller } from "@nestjs/common";
import { TypedRoute } from "@nestia/core";
import typia from "typia";
import { getTodoAppUserDashboardTodoOverview } from "../../../../../providers/getTodoAppUserDashboardTodoOverview";
import { UserAuth } from "../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../decorators/payload/UserPayload";

import { ITodoAppTodoDashboard } from "../../../../../api/structures/ITodoAppTodoDashboard";

@Controller("/todoApp/user/dashboard/todo-overview")
export class TodoappUserDashboardTodo_overviewController {
  /**
   * Retrieve comprehensive dashboard overview of todo statistics and metrics.
   *
   * This operation provides a high-level dashboard view of the user's todo
   * management system, aggregating data from multiple database tables to
   * present key metrics and statistics.
   *
   * The dashboard includes total todo counts broken down by status (pending,
   * in-progress, completed), priority distribution across all active todos,
   * recent completion trends, and upcoming due dates. This information helps
   * users quickly assess their productivity and task management status.
   *
   * Security considerations ensure that users can only view their own todo
   * data. The operation automatically filters results based on the
   * authenticated user's identity extracted from the JWT token. No sensitive
   * user information is exposed to unauthorized parties.
   *
   * The operation integrates with the todo_app_todos table for basic todo
   * information, todo_app_todo_lifecycles for current state tracking,
   * todo_app_todo_statuses for status definitions, and todo_app_todo_priorities
   * for priority classification. This multi-table approach ensures accurate and
   * comprehensive dashboard metrics.
   *
   * Performance optimizations include efficient aggregation queries and caching
   * strategies to ensure responsive dashboard loading even with large todo
   * datasets.
   *
   * @param connection
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async dashboard(
    @UserAuth()
    user: UserPayload,
  ): Promise<ITodoAppTodoDashboard> {
    try {
      return await getTodoAppUserDashboardTodoOverview({
        user,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
