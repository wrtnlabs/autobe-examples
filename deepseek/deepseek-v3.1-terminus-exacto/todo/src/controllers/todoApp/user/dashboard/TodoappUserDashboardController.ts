import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { ITodoAppSystemConfiguration } from "../../../../api/structures/ITodoAppSystemConfiguration";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { getTodoAppUserDashboard } from "../../../../providers/getTodoAppUserDashboard";

@Controller("/todoApp/user/dashboard")
export class TodoappUserDashboardController {
  /**
   * Retrieve a comprehensive dashboard overview of the user's todo management system.
   *
   * This endpoint provides aggregated statistics and metrics about the user's todo activities, including completion rates, recent changes, and overall progress. The dashboard data is calculated in real-time from the user's todo records, completion history, and edit tracking.
   *
   * The response includes counts of todos by status (total, completed, incomplete), completion percentage, recent activity timeline, and trash management statistics. All data is scoped to the authenticated user's account, ensuring complete privacy and data isolation as required by the system's privacy-first design.
   *
   * This operation supports the user's ability to monitor their productivity and track progress across their todo management workflow. The dashboard metrics help users understand their work patterns and identify areas for improvement in their task management approach.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Query the todo_app_todos table to count todos by completion status for the authenticated user. Calculate statistics including total todos, completed todos, incomplete todos, and completion percentage. Retrieve recent activity from todo_app_todo_histories and todo_app_todo_completions tables. Aggregate data from todo_app_trash_items for deleted todo counts. Ensure all queries are scoped to the current user's data for privacy compliance. Return a comprehensive dashboard object with all aggregated metrics.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @UserAuth()
    user: UserPayload,
  ): Promise<ITodoAppSystemConfiguration> {
    try {
      return await getTodoAppUserDashboard({
        user,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
