import { Controller } from "@nestjs/common";
import { TypedRoute } from "@nestia/core";
import typia from "typia";
import { postTodoAppUserAuthLogout } from "../../../../../providers/postTodoAppUserAuthLogout";
import { UserAuth } from "../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../decorators/payload/UserPayload";

@Controller("/todoApp/user/auth/logout")
export class TodoappUserAuthController {
  /**
   * Terminate user session and invalidate authentication tokens.
   *
   * This endpoint securely terminates an active user session by invalidating
   * the current JWT tokens and marking the session record as expired in the
   * todo_app_user_sessions table. The operation requires valid authentication
   * to ensure only authenticated users can log out.
   *
   * The system updates the expired_at timestamp in the session record to
   * prevent token reuse and maintains audit trails for security monitoring. All
   * client-side tokens should be cleared upon successful logout to ensure
   * complete session termination.
   *
   * Security considerations include proper token invalidation, prevention of
   * session hijacking, and maintaining audit logs for security compliance. The
   * operation handles both normal logout scenarios and forced session
   * termination for security incidents.
   *
   * @param connection
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async logout(
    @UserAuth()
    user: UserPayload,
  ): Promise<void> {
    try {
      return await postTodoAppUserAuthLogout({
        user,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
