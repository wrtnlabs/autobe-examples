import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia from "typia";
import { patchTodoAppTodosPriorities } from "../../../../providers/patchTodoAppTodosPriorities";
import { getTodoAppTodosPrioritiesPriorityCode } from "../../../../providers/getTodoAppTodosPrioritiesPriorityCode";

import { IPageITodoAppTodoPriority } from "../../../../api/structures/IPageITodoAppTodoPriority";
import { ITodoAppTodoPriority } from "../../../../api/structures/ITodoAppTodoPriority";

@Controller("/todoApp/todos/priorities")
export class TodoappTodosPrioritiesController {
  /**
   * Search and retrieve filtered list of todo priority levels.
   *
   * This operation enables administrators to search and filter through the
   * available todo priority levels defined in the system. It provides
   * comprehensive search capabilities for managing the priority classification
   * system used across all todo items.
   *
   * The operation supports multiple filtering options including priority code
   * matching, active status filtering, and weight-based sorting. Administrators
   * can use this endpoint to review existing priorities, check which ones are
   * currently active, and prepare for priority system updates or extensions.
   *
   * Security considerations include restricting access to administrative users
   * only, as priority management affects the entire application's todo
   * classification system. The operation integrates with the
   * todo_app_todo_priorities table and returns paginated results optimized for
   * administrative interfaces.
   *
   * Related operations include creating new priorities (POST /todos/priorities)
   * and updating existing priority definitions (PUT
   * /todos/priorities/{priorityCode}).
   *
   * @param connection
   * @param body Search criteria and pagination parameters for priority
   *   filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: ITodoAppTodoPriority.IRequest,
  ): Promise<IPageITodoAppTodoPriority.ISummary> {
    try {
      return await patchTodoAppTodosPriorities({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information for a specific todo priority level.
   *
   * This operation allows administrators to retrieve complete details about a
   * specific todo priority level using its unique code identifier. The priority
   * code serves as the business key for identifying priority levels within the
   * system.
   *
   * The returned information includes the priority's display name, detailed
   * description, numerical weight for sorting purposes, and active status
   * indicator. This detailed view is essential for administrators who need to
   * review or modify priority definitions that affect todo classification
   * throughout the application.
   *
   * Security is enforced through administrative access controls, ensuring that
   * only authorized users can view and manage the priority classification
   * system. The operation validates that the requested priority code exists and
   * returns appropriate error responses for invalid or non-existent codes.
   *
   * This operation complements the priority search functionality by providing
   * detailed access to individual priority definitions for administrative
   * review and potential modification through update operations.
   *
   * @param connection
   * @param priorityCode Unique business identifier code of the target todo
   *   priority (global scope)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":priorityCode")
  public async at(
    @TypedParam("priorityCode")
    priorityCode: string,
  ): Promise<ITodoAppTodoPriority> {
    try {
      return await getTodoAppTodosPrioritiesPriorityCode({
        priorityCode,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
