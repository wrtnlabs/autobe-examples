import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia from "typia";
import { postTodoAppConfigurations } from "../../../providers/postTodoAppConfigurations";
import { putTodoAppConfigurationsConfigKey } from "../../../providers/putTodoAppConfigurationsConfigKey";

import { ITodoAppConfiguration } from "../../../api/structures/ITodoAppConfiguration";

@Controller("/todoApp/configurations")
export class TodoappConfigurationsController {
  /**
   * Create a new system configuration setting.
   *
   * Create a new configuration setting for the Todo application system. This
   * operation allows administrators to define new key-value pairs that control
   * various aspects of application behavior.
   *
   * The configuration system supports different data types including 'string',
   * 'boolean', 'number', and 'json' formats, ensuring proper validation and
   * parsing of configuration values. Each configuration setting requires a
   * unique key identifier and a clear description of its purpose.
   *
   * Security considerations include restricting this operation to authorized
   * administrative users only, as configuration changes can significantly
   * impact application behavior. The system validates all input parameters
   * before creating the configuration record to ensure data integrity.
   *
   * This operation integrates with the todo_app_configurations table as defined
   * in the Prisma schema, incorporating all available configuration fields
   * including data type validation, status tracking, and audit timestamps.
   *
   * @param connection
   * @param body Configuration creation data including key, value, data type,
   *   description, and status
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @TypedBody()
    body: ITodoAppConfiguration.ICreate,
  ): Promise<ITodoAppConfiguration> {
    try {
      return await postTodoAppConfigurations({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing system configuration setting.
   *
   * Update an existing configuration setting identified by its unique
   * configuration key. This operation allows administrators to modify
   * configuration values, change data types, update descriptions, or alter the
   * status of existing configuration settings.
   *
   * The system validates that the configuration key exists before applying
   * updates and ensures that the new configuration value matches the specified
   * data type requirements. Configuration updates are tracked with timestamp
   * changes for audit purposes.
   *
   * Security considerations require that only authorized administrative users
   * can modify configuration settings, as changes can affect application
   * behavior and system stability. The operation includes validation to prevent
   * invalid data type assignments or configuration key modifications.
   *
   * This operation integrates with the todo_app_configurations table as defined
   * in the Prisma schema, maintaining data integrity through proper validation
   * and audit trail tracking of all configuration changes.
   *
   * @param connection
   * @param configKey Unique configuration key identifier of the target
   *   configuration setting (global scope)
   * @param body Configuration update data including value, data type,
   *   description, and status
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":configKey")
  public async update(
    @TypedParam("configKey")
    configKey: string,
    @TypedBody()
    body: ITodoAppConfiguration.IUpdate,
  ): Promise<ITodoAppConfiguration> {
    try {
      return await putTodoAppConfigurationsConfigKey({
        configKey,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
