import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia from "typia";
import { getTodoAppConfigurationsConfigKeyValuesEnvironment } from "../../../../providers/getTodoAppConfigurationsConfigKeyValuesEnvironment";

import { IMvTodoAppActiveConfiguration } from "../../../../api/structures/IMvTodoAppActiveConfiguration";

@Controller("/todoApp/configurations/:configKey/values/:environment")
export class TodoappConfigurationsValuesController {
  /**
   * This operation retrieves the currently active configuration value for a
   * specified deployment environment by querying the materialized view
   * mv_todo_app_active_configurations. The view combines configuration
   * definitions with their active environment-specific values, providing
   * optimized performance for configuration lookups.
   *
   * The operation uses the composite unique constraint on config_key and
   * environment to efficiently retrieve the effective configuration value. If
   * an environment-specific value exists and is active, it returns that value;
   * otherwise, it falls back to the default value from the configuration
   * definition. The response includes metadata about the value source
   * (environment-specific or default) and data type information for proper
   * client-side handling.
   *
   * Security considerations include public access for configuration values that
   * are not marked as sensitive. Sensitive configurations may require
   * authentication or administrative privileges. The operation supports caching
   * headers for performance optimization since configuration values change
   * infrequently.
   *
   * @param connection
   * @param configKey Unique configuration key identifier following naming
   *   convention: 'category.subcategory.setting'
   * @param environment Deployment environment for the configuration value
   *   (e.g., 'development', 'staging', 'production')
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @TypedParam("configKey")
    configKey: string,
    @TypedParam("environment")
    environment: string,
  ): Promise<IMvTodoAppActiveConfiguration> {
    try {
      return await getTodoAppConfigurationsConfigKeyValuesEnvironment({
        configKey,
        environment,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
