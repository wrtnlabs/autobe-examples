import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postTodoAppAuthLogin } from "../../../../providers/postTodoAppAuthLogin";

import { ITodoAppUser } from "../../../../api/structures/ITodoAppUser";

@Controller("/todoApp/auth/login")
export class TodoappAuthController {
  /**
   * Authenticate user and establish secure session.
   *
   * This endpoint validates user credentials and creates an authenticated
   * session. It checks the provided email and password against the stored
   * credentials in the todo_app_users table, ensuring the user account is
   * active and not deleted.
   *
   * Upon successful authentication, the system generates JWT access and refresh
   * tokens for secure session management. The operation also creates a session
   * record in the todo_app_user_sessions table, capturing the user's IP
   * address, connection URL, and referrer information for audit and security
   * monitoring.
   *
   * Security considerations include rate limiting to prevent brute force
   * attacks, secure password validation using bcrypt hashing, and proper
   * session expiration management. Failed authentication attempts are logged
   * for security monitoring without revealing specific validation details to
   * prevent information disclosure.
   *
   * @param connection
   * @param body User authentication credentials including email and password
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async login(
    @TypedBody()
    body: ITodoAppUser.ILogin,
  ): Promise<ITodoAppUser.IAuthResponse> {
    try {
      return await postTodoAppAuthLogin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
