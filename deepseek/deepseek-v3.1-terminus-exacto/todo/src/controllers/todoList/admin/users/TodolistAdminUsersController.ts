import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchTodoListAdminUsers } from "../../../../providers/patchTodoListAdminUsers";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { deleteTodoListAdminUsersUserId } from "../../../../providers/deleteTodoListAdminUsersUserId";

import { IPageITodoListUser } from "../../../../api/structures/IPageITodoListUser";
import { ITodoListUser } from "../../../../api/structures/ITodoListUser";

@Controller("/todoList/admin/users")
export class TodolistAdminUsersController {
  /**
   * Retrieve and search a paginated administrative list of users
   * (todo_list_users).
   *
   * Retrieve a paginated and filtered list of users for administrative
   * oversight or reporting purposes.
   *
   * The search criteria allow filtering by email, lock status, creation dates,
   * and account deletion status. Pagination parameters enable scalable access
   * to large user bases, with optional sorting based on registration or account
   * change history. This endpoint is restricted to administrative users only,
   * as exposed user data includes sensitive credentials and moderation
   * indicators.
   *
   * Associated entity fields are derived from the TODO_LIST_USERS table, taking
   * into account that deleted_at marks soft-deleted accounts and locked
   * determines account suspension at the infrastructure level. The search
   * operation is designed for bulk auditing, compliance checks, and system
   * management duties requiring detailed user account visibility.
   *
   * @param connection
   * @param body Search filters and pagination requests for admin to list users.
   *   Follows ITodoListUser.IRequest format.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: ITodoListUser.IRequest,
  ): Promise<IPageITodoListUser.ISummary> {
    try {
      return await patchTodoListAdminUsers({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Erase a user account (todo_list_users) by administrator action using user
   * ID.
   *
   * Permanently remove a user account by administrator action, ensuring full
   * compliance with business policy and audit trails.
   *
   * This operation accepts a unique identifier for a user account and marks the
   * targeted user as deleted by setting the deleted_at field on the
   * todo_list_users table. The deletion is soft—while the record persists for
   * audit purposes, all user access is immediately revoked and the account is
   * excluded from all user-facing queries and authentication checks. Only
   * administrators may invoke this endpoint; attempts by regular users are
   * forcibly rejected and strictly logged. No personal task (todo) data is
   * deleted by this operation, unless separately orchestrated per business
   * rules.
   *
   * All deletion actions are strictly logged for audit and compliance. The
   * endpoint enforces consistent error handling: not found errors if the user
   * does not exist, and permission errors for unauthorized requests. Other
   * endpoints for self-service deletion by users may have different flows and
   * are not covered by this endpoint.
   *
   * @param connection
   * @param userId Unique identifier of the target user to be deleted (UUID
   *   format).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":userId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoListAdminUsersUserId({
        admin,
        userId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
