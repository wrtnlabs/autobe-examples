import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchTodoListAdminUsersUserIdSessions } from "../../../../../providers/patchTodoListAdminUsersUserIdSessions";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getTodoListAdminUsersUserIdSessionsSessionId } from "../../../../../providers/getTodoListAdminUsersUserIdSessionsSessionId";
import { deleteTodoListAdminUsersUserIdSessionsSessionId } from "../../../../../providers/deleteTodoListAdminUsersUserIdSessionsSessionId";

import { IPageITodoListUserSession } from "../../../../../api/structures/IPageITodoListUserSession";
import { ITodoListUserSession } from "../../../../../api/structures/ITodoListUserSession";

@Controller("/todoList/admin/users/:userId/sessions")
export class TodolistAdminUsersSessionsController {
  /**
   * Retrieve paginated list of all sessions (todo_list_user_sessions) for a
   * given user by ID (admin only).
   *
   * Fetch all authentication sessions (active and expired) for a designated
   * user by administrator request, returning exhaustive session details for
   * audit, security review, or support.
   *
   * The operation takes the user ID as a path parameter and exposes session
   * records as defined by the todo_list_user_sessions Prisma model, including
   * full connection context (IP, href, referrer), created and expired
   * timestamps, and session linkage. This enables compliance-maintaining
   * inspection and security review of all access sessions ever held by a
   * particular user. The endpoint requires admin-level permissions and responds
   * with a paginated structure suitable for long-term audit trails.
   *
   * Usage is limited to administrative actors; users cannot view their own or
   * others' sessions from this route. Error responses cover not found and
   * forbidden scenarios for non-existent users or unauthorized access attempts.
   * Pagination and filtering are supported through the request body,
   * facilitating scalable audit on large user bases.
   *
   * @param connection
   * @param userId Unique identifier of the user account whose sessions are
   *   being queried (UUID format).
   * @param body Paging and filtering options for session record search and
   *   listing.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoListUserSession.IRequest,
  ): Promise<IPageITodoListUserSession> {
    try {
      return await patchTodoListAdminUsersUserIdSessions({
        admin,
        userId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information of a specific user session from
   * todo_list_user_sessions Prisma table.
   *
   * Retrieve all session details for a particular user session. This endpoint
   * is used exclusively for system administration, providing granular
   * auditability into user session context, including connection IP, client
   * origin, referrer, session start, and expiration timestamps.
   *
   * Because sessions may represent sensitive authentication contexts, security
   * is paramount: only administrators may access this endpoint. No confidential
   * authentication tokens or password hashes are exposed; only session
   * lifecycle metadata is returned. Administrators use this operation primarily
   * for security incident investigation, compliance audits, and session
   * management.
   *
   * This operation relates to audit requirements by enabling session
   * traceability and correlating each session to its owning user account via
   * the userId path parameter. If either the user or session does not exist, a
   * not found error is triggered. Related endpoints include session deletion
   * and search for all sessions by a user.
   *
   * @param connection
   * @param userId Unique identifier of the target user account who owns the
   *   session.
   * @param sessionId Unique identifier of the target user session for audit
   *   inspection.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<ITodoListUserSession> {
    try {
      return await getTodoListAdminUsersUserIdSessionsSessionId({
        admin,
        userId,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Erase a specific user session (hard delete) from todo_list_user_sessions
   * Prisma table.
   *
   * Erase an individual user session for policy enforcement, fraud mitigation,
   * or privacy compliance. This capability is exclusively reserved for system
   * administrators to remove session state, typically in response to suspicious
   * activity, regulatory requests, or obsolete sessions.
   *
   * This operation relates to audit requirements by enabling controlled erasure
   * of session records. Successful execution invalidates any ongoing session
   * and leaves a trace in the system's audit logs. The actual
   * authentication/session lifecycle should be managed by specialized
   * authentication services; this operation removes only the session tracking
   * record for administrative oversight.
   *
   * Attempting to erase a non-existent session or user will result in a not
   * found error. Only admin actors are permitted to perform this erasure;
   * regular users are never able to invoke session deletion directly. Related
   * operations include session lookup, audit log review, and compliance
   * management.
   *
   * @param connection
   * @param userId Unique identifier of the target user account who owns the
   *   session.
   * @param sessionId Unique identifier of the target user session to erase.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":sessionId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoListAdminUsersUserIdSessionsSessionId({
        admin,
        userId,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
