import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchTodoListAdminAdmins } from "../../../../providers/patchTodoListAdminAdmins";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getTodoListAdminAdminsAdminId } from "../../../../providers/getTodoListAdminAdminsAdminId";
import { putTodoListAdminAdminsAdminId } from "../../../../providers/putTodoListAdminAdminsAdminId";
import { deleteTodoListAdminAdminsAdminId } from "../../../../providers/deleteTodoListAdminAdminsAdminId";

import { IPageITodoListAdmin } from "../../../../api/structures/IPageITodoListAdmin";
import { ITodoListAdmin } from "../../../../api/structures/ITodoListAdmin";

@Controller("/todoList/admin/admins")
export class TodolistAdminAdminsController {
  /**
   * Paginate and search todo list administrator accounts.
   *
   * Search and retrieve a list of admin users using advanced filtering and
   * pagination.
   *
   * This endpoint is intended for oversight and management of accounts with
   * administrative privileges. Search parameters can include admin name, email,
   * creation date, and status. Returned results are paginated for scalability
   * and include summary details for each admin account, based on the fields of
   * the todo_list_admins schema.
   *
   * Sensitive information (such as password hashes) is never included in
   * results. Only administrators may access this endpoint, and permissions are
   * strictly enforced. This endpoint is fundamental for monitoring and managing
   * privileged access to the todo list service.
   *
   * @param connection
   * @param body Search and filter criteria for listing administrators,
   *   including pagination and sorting options.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: ITodoListAdmin.IRequest,
  ): Promise<IPageITodoListAdmin.ISummary> {
    try {
      return await patchTodoListAdminAdmins({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Fetch detailed information for a specific todo list admin account.
   *
   * Retrieve the complete record of a single administrator user for inspection
   * and management purposes.
   *
   * This endpoint returns all available detail fields for an admin user, using
   * the adminId as a required path parameter to specify the record to retrieve.
   * Typical use cases include administrative audits, account validation, and
   * monitoring privileged user actions. Access to this endpoint is tightly
   * controlled and limited to admin actors, ensuring that sensitive admin data
   * is not exposed inappropriately.
   *
   * The response fields are strictly determined by the todo_list_admins schema.
   * Error handling ensures that attempts to access non-existent or unauthorized
   * records are properly reported.
   *
   * @param connection
   * @param adminId Unique identifier of the target admin account, as defined in
   *   the todo_list_admins schema.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":adminId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
  ): Promise<ITodoListAdmin> {
    try {
      return await getTodoListAdminAdminsAdminId({
        admin,
        adminId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing todo_list_admins administrator account by ID.
   *
   * Update an administrator's account information, including core profile
   * fields, credentials, and role classification.
   *
   * This endpoint supports modification of sensitive admin attributes,
   * requiring full administrative authorization. All updates are processed via
   * a single PUT and replace only mutable, non-protected fields; immutable
   * fields such as creation timestamp are preserved. The operation enforces
   * email uniqueness as defined in the Prisma schema, validates password hash
   * format, and ensures only recognized role values are saved. Soft deletion
   * can be reverted by setting deleted_at to null but cannot be set directly.
   * Account status (locked/unlocked) and administrative privileges (role) can
   * be updated as required for personnel changes or compliance. Security
   * measures demand audit logging of all changes and require privileged context
   * validation. Only senior admin users or superadmins may call this endpoint
   * per business policy.
   *
   * This operation is strictly limited to the todo_list_admins table and is
   * governed by the unique email constraint and stateful business rules defined
   * in system requirements. Related endpoints include the administrator
   * creation (not exposed here), deletion, and detail retrieval.
   *
   * @param connection
   * @param adminId Unique identifier of the administrator to update.
   * @param body Fields for updating an existing administrator account. All
   *   non-nullable attributes must be provided; email must remain globally
   *   unique.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":adminId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoListAdmin.IUpdate,
  ): Promise<ITodoListAdmin> {
    try {
      return await putTodoListAdminAdminsAdminId({
        admin,
        adminId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete an admin entry from todo_list_admins by ID (hard erase).
   *
   * Permanently remove an administrator account from the system by its unique
   * identifier.
   *
   * This DELETE endpoint performs a hard erase operation on the
   * todo_list_admins table, physically expunging the admin account and all
   * associated metadata, in contrast to setting the deleted_at field for soft
   * deletion. The operation is only accessible to privileged administrative
   * actors as per system policy, and attempts to delete non-existent or already
   * deleted accounts will be met with clear error responses.
   *
   * Due to the critical nature of this action, every invocation is fully logged
   * for regulatory and traceability purposes. This operation must be used
   * judiciously and only when business policy permits, such as in cases of
   * fraud, policy breach, or lifecycle fulfillment. A successful response will
   * indicate completion, and related operations include account update, detail
   * retrieval, and audit record listing.
   *
   * @param connection
   * @param adminId Unique identifier of the administrator account to remove.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":adminId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoListAdminAdminsAdminId({
        admin,
        adminId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
