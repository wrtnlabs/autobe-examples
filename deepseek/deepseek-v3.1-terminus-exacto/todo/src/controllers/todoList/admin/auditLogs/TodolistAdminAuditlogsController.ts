import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchTodoListAdminAuditLogs } from "../../../../providers/patchTodoListAdminAuditLogs";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getTodoListAdminAuditLogsAuditLogId } from "../../../../providers/getTodoListAdminAuditLogsAuditLogId";

import { IPageITodoListAuditLog } from "../../../../api/structures/IPageITodoListAuditLog";
import { ITodoListAuditLog } from "../../../../api/structures/ITodoListAuditLog";

@Controller("/todoList/admin/auditLogs")
export class TodolistAdminAuditlogsController {
  /**
   * Search and retrieve filtered, paginated admin audit logs from
   * todo_list_audit_logs table.
   *
   * Search, filter, and paginate through security- and compliance-critical
   * business audit logs. This endpoint exposes advanced analytical capabilities
   * to privileged administrators, supporting temporal, entity, and event-based
   * queries across the todo_list_audit_logs.
   *
   * Audit logs may be filtered by action type (such as 'todo_create',
   * 'permission_denied'), outcome status, actor roles (users/admins/sessions),
   * affected entity (such as specific todo items), and time window. The
   * operation supports robust pagination and sorting for efficient access to
   * large log volumes. Results are delivered as summaries suitable for
   * compliance dashboards or investigative analysis.
   *
   * Due to the sensitive nature of audit information, this operation is
   * restricted exclusively to high-privilege administration personnel. No write
   * or destructive actions are supported: this endpoint is strictly for viewing
   * and investigation only, as required by security policy and the schema's
   * restrictions.
   *
   * @param connection
   * @param body Audit log search and filter request parameters supporting event
   *   action, status, actor roles, target entity, time range, sorting, and
   *   pagination.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: ITodoListAuditLog.IRequest,
  ): Promise<IPageITodoListAuditLog.ISummary> {
    try {
      return await patchTodoListAdminAuditLogs({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Fetch a single audit log entry from the todo_list_audit_logs table by ID.
   *
   * Retrieve a specific audit log entry from the system's immutable audit log,
   * providing details for compliance and security analysis.
   *
   * This operation allows authorized reviewers or system administrators to view
   * the full content of a single audit log entry, including acting identity
   * (user or admin), associated session, event type, result status, event
   * context, and all available metadata as defined in the schema.
   *
   * The operation is designed to support internal oversight, forensics, legal
   * investigations, and operational monitoring, referencing all audit log
   * schema documentation. Since audit logs are never modified or deleted, this
   * endpoint will always return the original record if the identifier is valid.
   * Errors are returned if the audit log does not exist or if the requester
   * lacks suitable permission.
   *
   * @param connection
   * @param auditLogId Globally unique identifier of the target audit log entry
   *   (generated at insertion; immutable primary key).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":auditLogId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("auditLogId")
    auditLogId: string & tags.Format<"uuid">,
  ): Promise<ITodoListAuditLog> {
    try {
      return await getTodoListAdminAuditLogsAuditLogId({
        admin,
        auditLogId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
