  public async create(
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoListUserSession.ICreate,
  ): Promise<ITodoListUserSession> {
    try {
      return await postTodoListUsersUserIdSessions({
        userId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

