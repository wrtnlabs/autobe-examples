import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { getTodoListUserUsersUserId } from "../../../../providers/getTodoListUserUsersUserId";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { putTodoListUserUsersUserId } from "../../../../providers/putTodoListUserUsersUserId";

import { ITodoListUser } from "../../../../api/structures/ITodoListUser";

@Controller("/todoList/user/users/:userId")
export class TodolistUserUsersController {
  /**
   * Retrieve a Todo List user's account details using a UUID as defined in
   * todo_list_users.
   *
   * Fetch a specific user's detailed information from the Todo List service by
   * their unique user ID.
   *
   * This operation provides the complete set of profile details, account
   * creation/update timestamps, whether the account is locked, and other core
   * account metadata. The password hash is present in the schema for
   * authentication validation but is excluded from user-facing responses for
   * security reasons.
   *
   * Access to this endpoint must enforce authentication and user authorization.
   * End users may typically view only their own account; administrators may be
   * permitted to view any user's account information for audit and moderation
   * purposes. Soft-deleted user accounts (where deleted_at is not null) are not
   * returned to ensure data privacy and security compliance as required by
   * business rules.
   *
   * @param connection
   * @param userId Unique identifier (UUID) of the Todo List user.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
  ): Promise<ITodoListUser> {
    try {
      return await getTodoListUserUsersUserId({
        user,
        userId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update a Todo List user's profile or account status in the todo_list_users
   * table by UUID.
   *
   * Update an existing Todo List user's profile details and account status by
   * unique user ID.
   *
   * This operation allows changing the user's email address, updating the
   * credential hash, or modifying the lock status in accordance with business
   * validation. Soft-deleted users are excluded from any modification,
   * enforcing data integrity and auditability as set by system requirements.
   *
   * Authorization is strictly enforced: end users may update their own account
   * fields, while administrative actors may update any user's information as
   * needed for moderation or support. Each change is logged for compliance and
   * traceability, referencing the audit requirements detailed in the system's
   * documentation.
   *
   * @param connection
   * @param userId Unique identifier (UUID) of the Todo List user to update.
   * @param body Fields to modify on the user's profile or account including
   *   email, password, or lock status.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoListUser.IUpdate,
  ): Promise<ITodoListUser> {
    try {
      return await putTodoListUserUsersUserId({
        user,
        userId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
