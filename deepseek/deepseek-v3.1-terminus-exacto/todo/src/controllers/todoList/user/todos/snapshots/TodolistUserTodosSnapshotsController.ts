import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchTodoListUserTodosTodoIdSnapshots } from "../../../../../providers/patchTodoListUserTodosTodoIdSnapshots";
import { UserAuth } from "../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../decorators/payload/UserPayload";
import { getTodoListUserTodosTodoIdSnapshotsSnapshotId } from "../../../../../providers/getTodoListUserTodosTodoIdSnapshotsSnapshotId";

import { IPageITodoListTodoSnapshot } from "../../../../../api/structures/IPageITodoListTodoSnapshot";
import { ITodoListTodoSnapshot } from "../../../../../api/structures/ITodoListTodoSnapshot";

@Controller("/todoList/user/todos/:todoId/snapshots")
export class TodolistUserTodosSnapshotsController {
  /**
   * Search and retrieve historical snapshots of a specific todo item.
   *
   * This operation provides access to the complete audit trail and version
   * history of a todo item by retrieving paginated snapshots. Each snapshot
   * represents a point-in-time capture of the todo's state whenever significant
   * changes occurred (title, description, or status modifications).
   *
   * The operation supports comprehensive pagination with configurable page
   * sizes and sorting options. Users can sort snapshots by creation date to
   * view the chronological evolution of the todo item. The system automatically
   * creates snapshots when todo items are modified, providing an append-only
   * record for compliance and recovery purposes.
   *
   * Security considerations include ensuring that users can only access
   * snapshots for todo items they own. The operation validates that the
   * referenced todo exists and belongs to the authenticated user before
   * returning snapshot data. Rate limiting applies to prevent excessive
   * historical data queries.
   *
   * This operation integrates with the todo_list_todo_snapshots table as
   * defined in the Prisma schema, incorporating all available snapshot fields
   * including title, description, status, and creation timestamp. The response
   * includes snapshot summary information optimized for historical browsing.
   *
   * @param connection
   * @param todoId Unique identifier of the target todo item
   * @param body Search criteria and pagination parameters for snapshot
   *   filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoListTodoSnapshot.IRequest,
  ): Promise<IPageITodoListTodoSnapshot.ISummary> {
    try {
      return await patchTodoListUserTodosTodoIdSnapshots({
        user,
        todoId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information for a specific todo snapshot.
   *
   * This operation provides access to a specific historical snapshot of a todo
   * item, returning the complete state information that was captured at the
   * time of snapshot creation. Each snapshot preserves the title, description,
   * and status of the todo item at a specific moment, enabling detailed
   * historical analysis and audit trail verification.
   *
   * The operation validates that both the todo item and snapshot exist and
   * belong to the authenticated user before returning the detailed snapshot
   * data. Security measures ensure that users can only access snapshots for
   * todo items they own, maintaining proper data isolation between users.
   *
   * This operation is particularly useful for compliance auditing, version
   * comparison, and recovery scenarios where users need to examine specific
   * historical states of their todo items. The snapshot data provides a
   * complete record of what the todo item contained at the time of capture,
   * including any descriptions and status information.
   *
   * This operation integrates with the todo_list_todo_snapshots table as
   * defined in the Prisma schema, returning all available snapshot fields with
   * their historical values. The response includes the complete snapshot data
   * for detailed examination.
   *
   * @param connection
   * @param todoId Unique identifier of the target todo item
   * @param snapshotId Unique identifier of the target snapshot
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":snapshotId")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
    @TypedParam("snapshotId")
    snapshotId: string & tags.Format<"uuid">,
  ): Promise<ITodoListTodoSnapshot> {
    try {
      return await getTodoListUserTodosTodoIdSnapshotsSnapshotId({
        user,
        todoId,
        snapshotId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
