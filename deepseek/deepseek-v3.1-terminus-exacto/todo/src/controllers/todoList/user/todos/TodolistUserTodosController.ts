import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postTodoListUserTodos } from "../../../../providers/postTodoListUserTodos";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { patchTodoListUserTodos } from "../../../../providers/patchTodoListUserTodos";
import { getTodoListUserTodosTodoId } from "../../../../providers/getTodoListUserTodosTodoId";
import { putTodoListUserTodosTodoId } from "../../../../providers/putTodoListUserTodosTodoId";
import { deleteTodoListUserTodosTodoId } from "../../../../providers/deleteTodoListUserTodosTodoId";

import { ITodoListTodo } from "../../../../api/structures/ITodoListTodo";
import { IPageITodoListTodo } from "../../../../api/structures/IPageITodoListTodo";

@Controller("/todoList/user/todos")
export class TodolistUserTodosController {
  /**
   * Create a new todo item (todo_list_todos) for the authenticated user.
   *
   * Create an individual todo item belonging to a single end-user, tracked in
   * the todo_list_todos table.
   *
   * This endpoint enforces strict validation for the title, requiring it to be
   * 1 to 100 characters with non-whitespace content. The status field is
   * required and must be one of 'pending', 'completed', or 'archived' at
   * creation. The description is optional and can be omitted or set to null,
   * with a maximum of 1000 characters. The due_date, if provided, must be a
   * valid ISO 8601 datetime and cannot be set in the past.
   *
   * Timestamps for creation and update are automatically generated by the
   * system and cannot be set by the client. The owning user is determined by
   * the authenticated context and cannot be supplied by the client directly.
   * All business logic, as well as state transition rules, are enforced
   * server-side to ensure data integrity and compliance. Upon success, the full
   * todo item is returned including all persistent, derived, and system-managed
   * fields.
   *
   * Associated access and change auditability are maintained via external
   * tables. The operation is public for authenticated users only, with no
   * collaborative creation supported. Related operations include updating (PUT
   * /todos/{todoId}) and batch listing (not included here).
   *
   * @param connection
   * @param body Information for creating a single todo item, including required
   *   title, status, and optional description and due_date. Ownership is
   *   implicit from authentication context. Timestamps are handled by the
   *   system.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoListTodo.ICreate,
  ): Promise<ITodoListTodo> {
    try {
      return await postTodoListUserTodos({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve a paginated, filtered list of todos (todo_list_todos
   * table).
   *
   * Retrieve a filtered and paginated list of the current user's todo items,
   * supporting advanced searching, filtering, and sorting according to the
   * requirements and schema rules.
   *
   * Each todo in the response corresponds to one actionable task that the user
   * owns; ownership is guaranteed by the todo_list_user_id foreign key
   * constraint in the Prisma schema. The search supports filters for status
   * (pending, completed, archived), text search in title and description, date
   * range filtering for due dates or creation dates, and flexible pagination
   * and ordering.
   *
   * Security and privacy are ensured by always scoping the search to the
   * currently authenticated user, preventing access to todos from other
   * accounts. Rate limiting and validation rules on titles, states, and other
   * fields are enforced as per the schema comments. The response intentionally
   * uses the summary DTO for efficient list rendering and batch interactions.
   *
   * This operation is related to the detailed retrieval (GET /todos/{todoId})
   * for viewing or editing full item details. All access and modifications must
   * comply with user-action traceability and audit requirements.
   *
   * @param connection
   * @param body Search, filter, and pagination parameters for the todo item
   *   list.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoListTodo.IRequest,
  ): Promise<IPageITodoListTodo.ISummary> {
    try {
      return await patchTodoListUserTodos({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve full detail for a single todo item (todo_list_todos table).
   *
   * Retrieve the detailed information for a specific user's todo item by its
   * unique identifier. This operation returns all attributes for the todo,
   * including title, description, status, due date, timestamps for creation and
   * updates, and all fields defined in the todo_list_todos Prisma schema.
   *
   * Access is strictly limited to the authenticated user's own todos as
   * enforced by a foreign key relationship. Attempting to access a todo
   * belonging to another user will result in a not-found or forbidden error.
   * This endpoint is essential for viewing, editing, or auditing an individual
   * todo item's complete lifecycle and current state.
   *
   * Field-level validation and constraints from the schema, such as title
   * length, status value, and state transition compliance, are reflected in the
   * output and error cases. This operation relates to the search operation
   * (PATCH /todos) for listing and filtering todos, and both operations
   * together implement the user's main todo management workflow.
   *
   * @param connection
   * @param todoId Universally unique identifier (UUID) of the target todo item
   *   belonging to the authenticated user.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":todoId")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
  ): Promise<ITodoListTodo> {
    try {
      return await getTodoListUserTodosTodoId({
        user,
        todoId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing todo item (todo_list_todos) by UUID for the
   * authenticated user.
   *
   * Update an individual todo item in the todo_list_todos table, identified by
   * a UUID path parameter (todoId). The operation allows updates to the title,
   * description, status, and due_date. Title, if updated, must pass all
   * business rules: 1–100 characters, non-whitespace. Description is optional
   * with a maximum of 1000 characters and can be set to null. Status updates
   * must conform to valid lifecycle transitions between 'pending', 'completed',
   * and 'archived'.
   *
   * The due_date, if provided, must be a valid ISO 8601 datetime not in the
   * past. Modification metadata (updated_at) is handled automatically;
   * completed_at is set only when the status becomes 'completed'. The owning
   * user cannot be changed and is always tied to the authenticated session.
   * Attempts to update another user's todo will result in a permission error.
   * On success, the API returns the updated todo item including all persistent
   * and computed fields.
   *
   * This operation supports accountability and compliance requirements for data
   * history and audit. Ownership is immutable and privacy is enforced at the
   * data access layer. Creation and deletion operations are available via other
   * endpoints.
   *
   * @param connection
   * @param todoId Unique identifier (UUID) of the target todo item
   * @param body Fields to update on the existing todo item, supporting title,
   *   description, status, and due_date modifications. Validation rules are
   *   strictly enforced per business logic.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":todoId")
  public async update(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoListTodo.IUpdate,
  ): Promise<ITodoListTodo> {
    try {
      return await putTodoListUserTodosTodoId({
        user,
        todoId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a todo item from todo_list_todos by ID.
   *
   * Permanently delete a single todo item belonging to the requesting user.
   *
   * This operation ensures that only the owner of the todo can perform the
   * deletion. It checks the existence and ownership of the todo using the
   * todo_list_user_id foreign key relationship, as described in the Prisma
   * schema. Upon successful authorization and validation, the todo is
   * immediately removed from the database, with no possibility for recovery.
   * All business constraints enforced on the todo (including state,
   * title/content validation, and timestamps) are resolved before deletion, and
   * related per-user query indexes are updated accordingly.
   *
   * The operation is strictly scoped to user-owned data and never exposes or
   * removes account or system-wide entities. Administrative deletion, auditing,
   * or compliance logging are managed by external tables and are outside the
   * scope of this API operation. Attempting to delete a todo not owned by the
   * user results in a not-found or forbidden error, consistent with
   * security/compliance standards.
   *
   * @param connection
   * @param todoId Unique identifier of the todo item to be deleted (UUID, as
   *   per todo_list_todos.id field).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":todoId")
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoListUserTodosTodoId({
        user,
        todoId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
