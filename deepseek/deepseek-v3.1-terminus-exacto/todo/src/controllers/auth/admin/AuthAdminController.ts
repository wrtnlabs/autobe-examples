import { Controller, Ip } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthAdminJoin } from "../../../providers/postAuthAdminJoin";
import { postAuthAdminLogin } from "../../../providers/postAuthAdminLogin";
import { postAuthAdminRefresh } from "../../../providers/postAuthAdminRefresh";

import { ITodoListAdmin } from "../../../api/structures/ITodoListAdmin";

@Controller("/auth/admin")
export class AuthAdminController {
  /**
   * Register a new admin in the todo_list_admins table and issue JWT tokens.
   *
   * This endpoint registers a new admin by creating a record in
   * todo_list_admins. The required fields include a unique email address
   * (enforced by the unique index on email) and a password, which is stored
   * securely as a hashed value in the password_hash field, never in plain text.
   * Upon registration, the admin's account lock status is set as appropriate,
   * and a creation timestamp is recorded in created_at.
   *
   * Password security is enforced at both the API and database layers;
   * passwords are subjected to policy validation and then securely hashed
   * before being persisted. Email uniqueness is validated against the unique
   * index, and the API returns an error if a duplicate is detected.
   *
   * Admins have the highest system privileges, and their registration triggers
   * audit logging in down-stream flows (not in this operation directly). This
   * operation does not allow setting the admin's role field or locked status
   * directly; these are handled by system rules or subsequent administrative
   * operations.
   *
   * The response for a successful operation includes newly issued
   * authentication tokens (access and refresh) as documented by
   * ITodoListAdmin.IAuthorized, aligning with JWT-based onboarding procedures.
   * On error or conflict, a suitable response is provided.
   *
   * Related operations include /auth/admin/login for subsequent authentication
   * and /auth/admin/refresh for token renewal. Audit and logging are
   * recommended by the business rules but are not performed in this operation.
   *
   * @param connection
   * @param body Registration details for new admin, including email and
   *   password.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoListAdmin.IJoin,
  ): Promise<ITodoListAdmin.IAuthorized> {
    try {
      return await postAuthAdminJoin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate a todo_list_admin and issue JWT tokens if successful.
   *
   * This endpoint authenticates a registered administrator based on their email
   * (unique index in todo_list_admins) and password (hashed, compared
   * securely). If credentials match (verified against password_hash), and the
   * account is not locked (locked is false) or deleted (deleted_at is null), an
   * access and refresh token pair are returned (ITodoListAdmin.IAuthorized
   * DTO). Lock status is checked, and the operation is denied if locked is
   * true, enforcing compliance and incident handling measures.
   *
   * Authentication failures (bad credentials, locked accounts, or soft-deleted
   * admins) are securely handled and return generic authentication errors to
   * avoid leaking sensitive information. The operation does not permit login
   * for any admin that has been soft-deleted (deleted_at is not null) or is
   * currently locked.
   *
   * Detailed audit logging is assumed for all login attempts (not implemented
   * in this endpoint directly), supporting system-level traceability of
   * privileged access.
   *
   * Security is reinforced by requiring password_hash validation and not
   * storing/revealing actual passwords, as per schema best practices. Related
   * operations include /auth/admin/join for onboarding new admins and
   * /auth/admin/refresh for token renewal.
   *
   * Error handling ensures that locked or deleted accounts are not accessible,
   * and the endpoint returns only minimal error messages for failed logins.
   *
   * @param connection
   * @param body Admin login credentials: email and password.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoListAdmin.ILogin,
  ): Promise<ITodoListAdmin.IAuthorized> {
    try {
      return await postAuthAdminLogin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Renew JWT tokens for an authenticated admin account in todo_list_admins.
   *
   * This endpoint refreshes authentication tokens for an admin. Token renewal
   * is performed if the refresh token is valid, the associated admin record is
   * still active (deleted_at is null), and the account is not locked (locked is
   * false). Underlying logic ensures that admins who have since been locked or
   * soft-deleted cannot use this operation.
   *
   * The refresh token is securely validated, potentially against a session
   * store, but always checked to confirm the admin's existence and current
   * status in todo_list_admins. Business logic re-issues access and refresh
   * tokens only if conditions are met; otherwise, appropriate errors are
   * returned. No authentication is performed via password; only the provided
   * refresh token is checked per ITodoListAdmin.IRefresh DTO contracts.
   *
   * This strengthens session management by ensuring token renewal cannot bypass
   * admin-level restrictions (locked/deleted). The operation does not support
   * role elevation or privilege changes—tokens are renewed at the existing
   * privilege level.
   *
   * Related admin operations include /auth/admin/login for initial
   * authentication and /auth/admin/join for new registrations. Audit logging is
   * recommended for token refresh attempts but is outside this endpoint's
   * direct scope.
   *
   * Security concerns are addressed by denying renewal for locked or deleted
   * admins, with detailed error reporting suppressed to prevent information
   * leaks.
   *
   * @param connection
   * @param body Admin refresh token for session renewal.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: ITodoListAdmin.IRefresh,
  ): Promise<ITodoListAdmin.IAuthorized> {
    try {
      return await postAuthAdminRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
