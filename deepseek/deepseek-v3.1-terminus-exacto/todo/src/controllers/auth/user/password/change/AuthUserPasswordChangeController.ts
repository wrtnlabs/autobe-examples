import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthUserPasswordChange } from "../../../../../providers/postAuthUserPasswordChange";
import { UserAuth } from "../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../decorators/payload/UserPayload";

import { ITodoAppUser } from "../../../../../api/structures/ITodoAppUser";

@Controller("/auth/user/password/change")
export class AuthUserPasswordChangeController {
  /**
   * Change user password with current password verification.
   *
   * This endpoint enables authenticated users to change their password while
   * maintaining an active session. The operation requires the user to provide
   * their current password for verification against the stored password_hash in
   * the todo_app_users table, ensuring security before allowing the change.
   *
   * Upon successful verification of the current password, the system updates
   * the password_hash field with the new securely hashed password. The
   * operation validates that the new password meets the same complexity
   * requirements as during registration. The updated_at timestamp is
   * automatically updated to reflect the password change time.
   *
   * Security measures include requiring current password verification to
   * prevent unauthorized changes, enforcing password complexity standards, and
   * invalidating all existing sessions after a successful password change to
   * ensure account security. This operation provides users with control over
   * their account security while maintaining high authentication standards.
   *
   * @param connection
   * @param body Current and new password information for verification and
   *   update
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async changePassword(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoAppUser.IChangePassword,
  ): Promise<ITodoAppUser.IChangePasswordResponse> {
    try {
      return await postAuthUserPasswordChange({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
