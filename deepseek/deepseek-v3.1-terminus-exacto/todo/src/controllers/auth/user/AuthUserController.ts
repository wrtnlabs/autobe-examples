import { Controller, Ip } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthUserJoin } from "../../../providers/postAuthUserJoin";
import { postAuthUserLogin } from "../../../providers/postAuthUserLogin";
import { postAuthUserRefresh } from "../../../providers/postAuthUserRefresh";

import { ITodoAppUser } from "../../../api/structures/ITodoAppUser";

@Controller("/auth/user")
export class AuthUserController {
  /**
   * This API operation creates a new user account in the todo_app_users table,
   * enabling users to register for the Todo application. The operation
   * validates the provided email address for uniqueness against existing
   * accounts and securely hashes the password using industry-standard
   * algorithms before storage.
   *
   * The registration process sets the initial account status to
   * 'pending_verification' to support email verification workflows, requiring
   * users to complete verification before full account activation. The
   * operation generates and returns JWT tokens (access and refresh tokens)
   * immediately after successful registration, allowing users to authenticate
   * and begin using the application while verification is pending.
   *
   * Security considerations include preventing duplicate email registrations,
   * enforcing password strength requirements, and implementing proper token
   * management. The operation integrates with the user authentication system to
   * ensure seamless transition from registration to authenticated session
   * management.
   *
   * Related operations include the login endpoint for existing users and email
   * verification endpoints for completing the account activation process. This
   * operation establishes the foundation for user identity management within
   * the Todo application ecosystem.
   *
   * @param connection
   * @param body User registration information including email, password, and
   *   display name.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoAppUser.ICreate,
  ): Promise<ITodoAppUser.IAuthorized> {
    try {
      return await postAuthUserJoin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This API operation authenticates users by validating their email and
   * password credentials against the todo_app_users table. The operation
   * performs secure password comparison using the stored password_hash field
   * and updates the last_login_at timestamp upon successful authentication.
   *
   * The authentication process includes comprehensive account status
   * validation, ensuring that only accounts with appropriate status values
   * ('active' or 'verified') can authenticate successfully. Accounts with
   * statuses like 'suspended', 'locked', or 'pending_verification' are rejected
   * with appropriate error messages guiding users through the account recovery
   * or verification process.
   *
   * Security implementation includes rate limiting to prevent brute force
   * attacks, proper error messaging to avoid information leakage, and secure
   * token generation with appropriate expiration times. The operation updates
   * user activity tracking through the last_login_at field for monitoring and
   * security purposes.
   *
   * Successful authentication returns both access and refresh JWT tokens,
   * enabling seamless session management and token refresh capabilities. This
   * operation works in conjunction with the registration endpoint for new users
   * and the token refresh endpoint for maintaining active sessions.
   *
   * @param connection
   * @param body User login credentials including email and password.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoAppUser.ILogin,
  ): Promise<ITodoAppUser.IAuthorized> {
    try {
      return await postAuthUserLogin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This API operation refreshes user authentication tokens by validating
   * existing refresh tokens and issuing new access tokens. The refresh
   * mechanism allows users to maintain active sessions without repeatedly
   * providing credentials, enhancing user experience while maintaining security
   * through token rotation.
   *
   * The operation validates the refresh token's integrity and expiration,
   * ensuring that only valid, non-expired tokens can be used to obtain new
   * access tokens. Successful token refresh updates the user's session
   * continuity while maintaining the security principle of short-lived access
   * tokens and longer-lived refresh tokens.
   *
   * Security considerations include proper token validation, prevention of
   * token reuse, and implementation of refresh token expiration policies. The
   * operation supports secure session management by allowing periodic access
   * token rotation while minimizing disruption to the user experience.
   *
   * This endpoint works in conjunction with the login and registration
   * operations to provide comprehensive authentication lifecycle management. It
   * enables applications to maintain secure, long-lived user sessions while
   * adhering to security best practices for token management and session
   * continuity.
   *
   * @param connection
   * @param body Refresh token for obtaining new access tokens.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: ITodoAppUser.IRefresh,
  ): Promise<ITodoAppUser.IAuthorized> {
    try {
      return await postAuthUserRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
