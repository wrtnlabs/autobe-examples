import { Controller, Ip } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthUserJoin } from "../../../providers/postAuthUserJoin";
import { postAuthUserLogin } from "../../../providers/postAuthUserLogin";
import { postAuthUserRefresh } from "../../../providers/postAuthUserRefresh";

import { ITodoAppUser } from "../../../api/structures/ITodoAppUser";

@Controller("/auth/user")
export class AuthUserController {
  /**
   * Register a new user account for the Todo application.
   *
   * This endpoint allows new users to register for the Todo application by
   * creating a user account with email and password credentials. The operation
   * validates that the email format is correct and that the email is not
   * already registered in the system. It enforces password complexity
   * requirements including minimum length and character diversity. Upon
   * successful registration, the system creates a new user record in the
   * todo_app_users table with initial status set to 'active' and generates
   * authentication tokens for immediate access.
   *
   * The operation uses the email field for unique identification and stores the
   * password securely using bcrypt hashing in the password_hash field. The
   * created_at timestamp is automatically set to record the registration time.
   * This endpoint is publicly accessible and does not require authentication,
   * serving as the entry point for new users to join the Todo application.
   *
   * Security considerations include preventing duplicate email registrations
   * and ensuring proper password hashing before storage. The operation
   * integrates with the authentication system to provide seamless transition
   * from registration to authenticated session. Related operations include
   * login for existing users and password reset functionality for account
   * recovery.
   *
   * @param connection
   * @param body User registration information including email and password
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoAppUser.ICreate,
  ): Promise<ITodoAppUser.IAuthorized> {
    try {
      return await postAuthUserJoin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate an existing user and establish a secure session.
   *
   * This endpoint authenticates existing users by validating their email and
   * password credentials against the stored records in the todo_app_users
   * table. The operation checks the email existence and verifies the provided
   * password against the stored password_hash using bcrypt comparison. Upon
   * successful authentication, it creates a new session record in
   * todo_app_user_sessions with the user's IP address, connection URL, and
   * referrer information.
   *
   * The operation validates that the user account has an 'active' status in the
   * status field before allowing login. It generates JWT access and refresh
   * tokens with appropriate expiration times for secure session management. The
   * created_at timestamp in the session record captures the login time, while
   * the expired_at field remains null until session termination.
   *
   * Security measures include rate limiting to prevent brute force attacks and
   * proper error handling that doesn't reveal whether the email or password was
   * incorrect. The operation integrates with the token refresh system to
   * maintain continuous session management. Users who successfully authenticate
   * gain access to their personal todo management functionality.
   *
   * @param connection
   * @param body User login credentials including email and password
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoAppUser.ILogin,
  ): Promise<ITodoAppUser.IAuthorized> {
    try {
      return await postAuthUserLogin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh authentication tokens to extend user session.
   *
   * This endpoint allows authenticated users to refresh their access tokens
   * using a valid refresh token, extending their session without requiring full
   * re-authentication. The operation validates the refresh token against the
   * user's active session records in the todo_app_user_sessions table, ensuring
   * it hasn't expired based on the expired_at field.
   *
   * Upon successful validation, the system issues a new access token with
   * updated expiration while maintaining the same user context. This operation
   * helps maintain seamless user experience by preventing frequent login
   * interruptions. The session record's created_at timestamp is used to track
   * session duration for security monitoring.
   *
   * Security considerations include proper token validation, prevention of
   * token reuse, and session expiration enforcement. The operation supports the
   * JWT-based authentication system by providing continuous access while
   * maintaining security standards. It requires a valid refresh token from a
   * previous successful authentication operation.
   *
   * @param connection
   * @param body Refresh token for authentication renewal
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: ITodoAppUser.IRefresh,
  ): Promise<ITodoAppUser.IAuthorized> {
    try {
      return await postAuthUserRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
