import { Controller, Ip } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthUserJoin } from "../../../providers/postAuthUserJoin";
import { postAuthUserLogin } from "../../../providers/postAuthUserLogin";
import { postAuthUserRefresh } from "../../../providers/postAuthUserRefresh";

import { ITodoListUser } from "../../../api/structures/ITodoListUser";

@Controller("/auth/user")
export class AuthUserController {
  /**
   * User registration for todo_list_users table. Public operation to create a
   * regular user account.
   *
   * Registers a new user in the system by creating a todo_list_users record and
   * enforcing authentication fields as required by the schema. Enforces unique
   * and required field constraints from the todo_list_users schema.
   * Registration is public, does not confer admin or privileged access, and is
   * a necessary prerequisite for login and all user authorization flows. All
   * onboarding and field validation rules are strictly enforced as described in
   * the table definition.
   *
   * @param connection
   * @param body Registration payload for new users.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoListUser.ICreate,
  ): Promise<ITodoListUser.IAuthorized> {
    try {
      return await postAuthUserJoin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * User login against todo_list_users table, providing JWT tokens for
   * authenticated sessions.
   *
   * Authenticates user credentials (per todo_list_users schema), returning JWT
   * tokens in the format required for user session management. Only normal
   * todo_list_users accounts are supported—admins must use their own login
   * endpoint. Security and credential validation correspond to the
   * todo_list_users schema and defined business rules. Operation supports only
   * those fields and policies present in the schema.
   *
   * @param connection
   * @param body User login credentials as per authentication requirements.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoListUser.ILogin,
  ): Promise<ITodoListUser.IAuthorized> {
    try {
      return await postAuthUserLogin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * User JWT refresh token operation for todo_list_users table.
   *
   * Issues new JWT tokens for a regular user by validating a supplied refresh
   * token, per the todo_list_users security policy. Only valid, untampered
   * tokens are accepted, following all refresh lifecycle constraints. The
   * operation supports only user-level refresh—no admin or cross-account tokens
   * are accepted.
   *
   * @param connection
   * @param body Refresh token container for user session.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: ITodoListUser.IRefresh,
  ): Promise<ITodoListUser.IAuthorized> {
    try {
      return await postAuthUserRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
