import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IMultiUserTodoMember } from "../../../../api/structures/IMultiUserTodoMember";
import { postMultiUserTodoAuthMemberJoin } from "../../../../providers/postMultiUserTodoAuthMemberJoin";
import { postMultiUserTodoAuthMemberLogin } from "../../../../providers/postMultiUserTodoAuthMemberLogin";
import { postMultiUserTodoAuthMemberRefresh } from "../../../../providers/postMultiUserTodoAuthMemberRefresh";

@Controller("/multiUserTodo/auth/member")
export class MultiusertodoAuthMemberController {
  /**
   * The join operation allows new users to register for the multi-user todo application by creating a member account with email and password credentials. This operation validates the email address for uniqueness against the multi_user_todo_members.email field and securely hashes the password before storage in the multi_user_todo_members.password_hash field. Upon successful registration, the system automatically creates an authentication session with access and refresh tokens, providing immediate access to the application.
   *
   * The login operation authenticates existing members by validating their email and password credentials against the stored records in the multi_user_todo_members table. Successful authentication creates a new session entry in the multi_user_todo_member_sessions table, tracking connection details such as IP address, current URL, and referrer information. This operation supports the JWT-based authentication workflow described in the session management requirements.
   *
   * The refresh operation renews authentication tokens for active sessions, allowing members to maintain continuous access without re-entering credentials. This operation validates the existing refresh token against the multi_user_todo_member_sessions.refresh_token field and generates new access and refresh tokens with updated expiration timestamps. The operation ensures session security by regularly rotating tokens while maintaining user convenience.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Registration information for creating a new member account
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor member
   * @x-autobe-specification The join operation creates a new member account by validating the email uniqueness and hashing the password before storage. It generates initial session tokens and returns them in the response. Email validation ensures no duplicate accounts exist, and password hashing follows security best practices. The operation creates records in both the members table and sessions table for immediate authentication.
   *
   * The login operation validates member credentials by comparing the provided password hash against the stored hash. If successful, it creates a new session record with access and refresh tokens, tracking connection metadata like IP address and referrer. Failed login attempts are handled with appropriate error responses.
   *
   * The refresh operation validates an existing refresh token, generates new access and refresh tokens, and updates the session record. This maintains continuous authentication while rotating tokens for security. Expired or invalid tokens result in authentication errors requiring re-login.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IMultiUserTodoMember.IJoin,
  ): Promise<IMultiUserTodoMember.IAuthorized> {
    try {
      return await postMultiUserTodoAuthMemberJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * The login operation provides authentication for registered members to access the multi-user todo application. This operation validates the provided email and password against the credentials stored in the multi_user_todo_members table, specifically checking the email uniqueness constraint and verifying the password hash stored in the password_hash field.
   *
   * Upon successful authentication, the operation creates a new session record in the multi_user_todo_member_sessions table, generating both access and refresh tokens with appropriate expiration timestamps. The session record captures connection context including the member's IP address, current URL (href), and referrer information for security monitoring purposes. This operation implements the authentication flow described in the session and token policy requirements, supporting the JWT-based security model.
   *
   * Failed authentication attempts return appropriate error responses without disclosing whether the email exists or the password was incorrect, maintaining security best practices. The operation only allows login for active member accounts that haven't been soft-deleted (deleted_at is null), ensuring proper account lifecycle management.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Authentication credentials for member login
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor member
   * @x-autobe-specification The login operation validates member credentials by querying the multi_user_todo_members table for the provided email and comparing the password hash. If authentication succeeds, it creates a new session record with generated tokens and connection metadata. Failed attempts return appropriate authentication errors without revealing specific failure reasons for security.
   *
   * The operation uses secure password comparison techniques to prevent timing attacks and ensures that only active (non-deleted) member accounts can authenticate. Session creation includes proper expiration handling based on the system's token policy requirements.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IMultiUserTodoMember.ILogin,
  ): Promise<IMultiUserTodoMember.IAuthorized> {
    try {
      return await postMultiUserTodoAuthMemberLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * The refresh operation enables members to renew their authentication tokens without requiring full re-authentication, supporting continuous access to the multi-user todo application. This operation validates the provided refresh token against the multi_user_todo_member_sessions.refresh_token field and checks that the session hasn't expired based on the expired_at timestamp.
   *
   * Upon successful validation, the operation generates new access and refresh tokens with updated expiration timestamps, replacing the existing tokens in the session record. This token rotation enhances security by regularly refreshing authentication credentials while maintaining user convenience. The operation implements the token refresh mechanism specified in the session and token policy requirements, supporting the JWT-based authentication system.
   *
   * Invalid or expired refresh tokens result in authentication failure responses, requiring members to complete the full login process again. This operation only processes refresh requests for active sessions that haven't reached their expiration threshold, ensuring proper session lifecycle management and security compliance.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token for renewing authentication session
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor member
   * @x-autobe-specification The refresh operation validates an existing refresh token by querying the multi_user_todo_member_sessions table and checking expiration. If valid, it generates new access and refresh tokens, updates the session record with the new tokens and extended expiration, and returns the updated authentication information. Invalid or expired tokens result in authentication errors requiring re-login.
   *
   * This operation supports the token refresh mechanism described in the session management requirements, allowing continuous authentication while maintaining security through regular token rotation. The operation ensures that only active sessions can be refreshed and properly handles token expiration according to the system's security policies.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IMultiUserTodoMember.IRefresh,
  ): Promise<IMultiUserTodoMember.IAuthorized> {
    try {
      return await postMultiUserTodoAuthMemberRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
