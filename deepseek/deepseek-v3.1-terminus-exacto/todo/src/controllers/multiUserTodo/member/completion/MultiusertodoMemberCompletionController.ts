@Controller("/multiUserTodo/member/completion")
export class MultiusertodoMemberCompletionController {
  /**
   * Toggle the completion status of a todo between complete and incomplete states.
   *
   * This operation provides a simple toggle mechanism for users to mark their todos as complete or incomplete. When a todo is marked complete, it is recorded as finished and appears in completed todo filters. When marked incomplete, it returns to active status and appears in incomplete todo lists.
   *
   * The operation automatically records each status change event in the completion status history table, providing a complete audit trail of when todos were completed and potentially reactivated. This ensures users can track their productivity patterns and completion history over time.
   *
   * Authentication is required and users can only toggle completion status on their own todos. The operation follows atomic completion status change requirements to prevent race conditions and ensure consistent state management across concurrent operations.
   *
   * After the status change, the operation returns the complete todo information including the updated completion status, allowing clients to immediately reflect the new state in their user interfaces.
   *
   * @param connection
   * @param body Completion status toggle criteria including the target todo identifier
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Handle todo completion status toggling with atomic operations to prevent race conditions as specified in race condition prevention requirements. Update the multi_user_todo_todo_completion_statuses table to record the status change event with timestamp. Verify the todo exists and belongs to the authenticated user before allowing status changes. Update the is_completed field in the main todos table to reflect the current state. Ensure edit history is created for the completion status change as specified in business rules. Return the updated todo information including the new completion status.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async status(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IMultiUserTodoTodoCompletionStatus.IRequest,
  ): Promise<IMultiUserTodoTodo> {
    try {
      return await patchMultiUserTodoMemberCompletion({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
