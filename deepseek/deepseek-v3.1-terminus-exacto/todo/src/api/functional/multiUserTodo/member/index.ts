/**
 * Restore a soft-deleted todo from the trash system back to active status.
 *
 * This operation allows users to recover todos that were previously deleted but not permanently removed from the system. When a todo is restored, it returns to the user's main todo list with all its original properties intact, including title, description, dates, and completion status.
 *
 * The restoration process preserves the todo's edit history and maintains all associated data. The operation validates that the todo exists in the trash and belongs to the requesting user before performing the restoration.
 *
 * After successful restoration, the todo becomes available for normal operations including viewing, editing, completion status changes, and can be deleted again if needed. The operation provides immediate feedback on the restoration status and returns the restored todo for confirmation.
 *
 * @param props.connection
 * @param props.body Identification of the todo to restore from trash
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor member
 * @x-autobe-specification Handle todo restoration from trash by updating the trash entry and todo records.
 *
 * 1. Validate that the todo exists in the trash_entries table and belongs to the authenticated user
 * 2. Update the trash entry's restored_at timestamp to the current time
 * 3. Clear the deleted_at field on the corresponding todo record
 * 4. Return the restored todo with all its properties
 * 5. Ensure the operation is atomic to prevent partial updates
 * 6. Validate that the todo hasn't already been restored or permanently deleted
 * 7. Create an audit log entry for the restoration operation
 * @path /multiUserTodo/member/restore
 * @accessor api.functional.multiUserTodo.member.restore
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function restore(
  connection: IConnection,
  props: restore.Props,
): Promise<restore.Response> {
  return true === connection.simulate
    ? restore.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...restore.METADATA,
          path: restore.path(),
          status: null,
        },
        props.body,
      );
}
export namespace restore {
  export type Props = {
    /**
     * Identification of the todo to restore from trash
     */
    body: IMultiUserTodoTodoTrashEntry.IRequest;
  };
  export type Body = IMultiUserTodoTodoTrashEntry.IRequest;
  export type Response = IMultiUserTodoTodo;

  export const METADATA = {
    method: "PATCH",
    path: "/multiUserTodo/member/restore",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/multiUserTodo/member/restore";
  export const random = (): IMultiUserTodoTodo =>
    typia.random<IMultiUserTodoTodo>();
  export const simulate = (
    connection: IConnection,
    props: restore.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: restore.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
