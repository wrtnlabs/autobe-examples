import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ITodoAppUser } from "../../../../../structures/ITodoAppUser";

/**
 * Change user password with current password verification.
 *
 * This endpoint enables authenticated users to change their password while
 * maintaining an active session. The operation requires the user to provide
 * their current password for verification against the stored password_hash in
 * the todo_app_users table, ensuring security before allowing the change.
 *
 * Upon successful verification of the current password, the system updates the
 * password_hash field with the new securely hashed password. The operation
 * validates that the new password meets the same complexity requirements as
 * during registration. The updated_at timestamp is automatically updated to
 * reflect the password change time.
 *
 * Security measures include requiring current password verification to prevent
 * unauthorized changes, enforcing password complexity standards, and
 * invalidating all existing sessions after a successful password change to
 * ensure account security. This operation provides users with control over
 * their account security while maintaining high authentication standards.
 *
 * @param props.connection
 * @param props.body Current and new password information for verification and
 *   update
 * @path /auth/user/password/change
 * @accessor api.functional.auth.user.password.change.changePassword
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function changePassword(
  connection: IConnection,
  props: changePassword.Props,
): Promise<changePassword.Response> {
  return true === connection.simulate
    ? changePassword.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...changePassword.METADATA,
          path: changePassword.path(),
          status: null,
        },
        props.body,
      );
}
export namespace changePassword {
  export type Props = {
    /** Current and new password information for verification and update */
    body: ITodoAppUser.IChangePassword;
  };
  export type Body = ITodoAppUser.IChangePassword;
  export type Response = ITodoAppUser.IChangePasswordResponse;

  export const METADATA = {
    method: "POST",
    path: "/auth/user/password/change",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/user/password/change";
  export const random = (): ITodoAppUser.IChangePasswordResponse =>
    typia.random<ITodoAppUser.IChangePasswordResponse>();
  export const simulate = (
    connection: IConnection,
    props: changePassword.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: changePassword.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
