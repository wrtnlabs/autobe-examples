import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ITodoAppUser } from "../../../../../structures/ITodoAppUser";

/**
 * Initiate password reset process for user account recovery.
 *
 * This endpoint allows users to initiate the password reset process by
 * providing their registered email address. The operation validates that the
 * email exists in the todo_app_users table and that the user account has an
 * 'active' status. It generates a secure, time-limited reset token and sends it
 * to the user's email address for verification.
 *
 * The operation ensures that only active user accounts can request password
 * resets and implements rate limiting to prevent abuse. It records the reset
 * request for security auditing purposes but doesn't immediately change the
 * password. The user must complete the verification process through the
 * received email link to actually reset their password.
 *
 * Security considerations include preventing email enumeration by providing
 * generic success messages regardless of email existence, implementing secure
 * token generation, and enforcing time limits on reset tokens. This operation
 * is part of the comprehensive account recovery system for the Todo
 * application.
 *
 * @param props.connection
 * @param props.body Email address for password reset request
 * @path /auth/user/password/reset
 * @accessor api.functional.auth.user.password.reset.requestPasswordReset
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function requestPasswordReset(
  connection: IConnection,
  props: requestPasswordReset.Props,
): Promise<requestPasswordReset.Response> {
  return true === connection.simulate
    ? requestPasswordReset.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...requestPasswordReset.METADATA,
          path: requestPasswordReset.path(),
          status: null,
        },
        props.body,
      );
}
export namespace requestPasswordReset {
  export type Props = {
    /** Email address for password reset request */
    body: ITodoAppUser.IResetPasswordRequest;
  };
  export type Body = ITodoAppUser.IResetPasswordRequest;
  export type Response = ITodoAppUser.IResetPasswordResponse;

  export const METADATA = {
    method: "POST",
    path: "/auth/user/password/reset",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/user/password/reset";
  export const random = (): ITodoAppUser.IResetPasswordResponse =>
    typia.random<ITodoAppUser.IResetPasswordResponse>();
  export const simulate = (
    connection: IConnection,
    props: requestPasswordReset.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: requestPasswordReset.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
