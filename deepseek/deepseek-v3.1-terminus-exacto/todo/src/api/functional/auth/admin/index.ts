/**
 * Register a new admin in the todo_list_admins table and issue JWT tokens.
 *
 * This endpoint registers a new admin by creating a record in todo_list_admins.
 * The required fields include a unique email address (enforced by the unique
 * index on email) and a password, which is stored securely as a hashed value in
 * the password_hash field, never in plain text. Upon registration, the admin's
 * account lock status is set as appropriate, and a creation timestamp is
 * recorded in created_at.
 *
 * Password security is enforced at both the API and database layers; passwords
 * are subjected to policy validation and then securely hashed before being
 * persisted. Email uniqueness is validated against the unique index, and the
 * API returns an error if a duplicate is detected.
 *
 * Admins have the highest system privileges, and their registration triggers
 * audit logging in down-stream flows (not in this operation directly). This
 * operation does not allow setting the admin's role field or locked status
 * directly; these are handled by system rules or subsequent administrative
 * operations.
 *
 * The response for a successful operation includes newly issued authentication
 * tokens (access and refresh) as documented by ITodoListAdmin.IAuthorized,
 * aligning with JWT-based onboarding procedures. On error or conflict, a
 * suitable response is provided.
 *
 * Related operations include /auth/admin/login for subsequent authentication
 * and /auth/admin/refresh for token renewal. Audit and logging are recommended
 * by the business rules but are not performed in this operation.
 *
 * @param props.connection
 * @param props.body Registration details for new admin, including email and
 *   password.
 * @setHeader token.access Authorization
 *
 * @path /auth/admin/join
 * @accessor api.functional.auth.admin.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
