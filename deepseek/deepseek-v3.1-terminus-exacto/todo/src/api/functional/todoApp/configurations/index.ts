import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ITodoAppConfiguration } from "../../../structures/ITodoAppConfiguration";
import { IPageITodoAppConfiguration } from "../../../structures/IPageITodoAppConfiguration";

/**
 * Search and retrieve a filtered, paginated list of system configuration
 * settings.
 *
 * This operation provides comprehensive search capabilities for system
 * configuration settings stored in the todo_app_configurations table. Users can
 * filter configurations by category, data type, key patterns, and date ranges
 * to find specific settings.
 *
 * Configuration settings are system-wide and control application behavior,
 * feature flags, and system parameters. These settings are not user-specific
 * but apply to the entire application instance.
 *
 * The search functionality supports pagination with configurable page sizes,
 * sorting options by creation date or category, and advanced filtering
 * capabilities. Configuration settings are organized by category for easy
 * navigation and management.
 *
 * Security considerations include appropriate access controls for configuration
 * management. Authorized users can view system configurations to understand
 * application behavior and settings.
 *
 * The operation returns configuration summary information optimized for list
 * displays, including key, value, category, and data type details. This enables
 * efficient configuration management and system administration workflows.
 *
 * @param props.connection
 * @param props.body Search criteria and pagination parameters for configuration
 *   filtering
 * @path /todoApp/configurations
 * @accessor api.functional.todoApp.configurations.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /** Search criteria and pagination parameters for configuration filtering */
    body: ITodoAppConfiguration.IRequest;
  };
  export type Body = ITodoAppConfiguration.IRequest;
  export type Response = IPageITodoAppConfiguration.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/todoApp/configurations",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/todoApp/configurations";
  export const random = (): IPageITodoAppConfiguration.ISummary =>
    typia.random<IPageITodoAppConfiguration.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

/**
 * Retrieve detailed information for a specific configuration setting.
 *
 * This operation retrieves a single configuration setting from the
 * todo_app_configurations table using its unique key identifier. The
 * configuration key serves as the primary lookup mechanism for system
 * settings.
 *
 * The operation returns comprehensive configuration details including the
 * current value, data type specification, category classification, and
 * descriptive information. Configuration settings are system-wide and control
 * various aspects of the Todo application behavior.
 *
 * Configuration settings include feature flags, performance parameters, default
 * settings, and business rules. Each configuration has a specific data type
 * that determines how the value should be parsed and validated by the
 * application.
 *
 * Access to configuration details requires appropriate permissions, as these
 * settings can impact system functionality. The operation provides the complete
 * configuration record for inspection and system administration purposes.
 *
 * @param props.connection
 * @param props.configurationKey Unique configuration key identifier of the
 *   target configuration setting
 * @path /todoApp/configurations/:configurationKey
 * @accessor api.functional.todoApp.configurations.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique configuration key identifier of the target configuration
     * setting
     */
    configurationKey: string;
  };
  export type Response = ITodoAppConfiguration;

  export const METADATA = {
    method: "GET",
    path: "/todoApp/configurations/:configurationKey",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/todoApp/configurations/${encodeURIComponent(props.configurationKey ?? "null")}`;
  export const random = (): ITodoAppConfiguration =>
    typia.random<ITodoAppConfiguration>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("configurationKey")(() =>
        typia.assert(props.configurationKey),
      );
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
