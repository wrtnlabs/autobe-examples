import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IMvTodoAppActiveConfiguration } from "../../../../structures/IMvTodoAppActiveConfiguration";

/**
 * This operation retrieves the currently active configuration value for a
 * specified deployment environment by querying the materialized view
 * mv_todo_app_active_configurations. The view combines configuration
 * definitions with their active environment-specific values, providing
 * optimized performance for configuration lookups.
 *
 * The operation uses the composite unique constraint on config_key and
 * environment to efficiently retrieve the effective configuration value. If an
 * environment-specific value exists and is active, it returns that value;
 * otherwise, it falls back to the default value from the configuration
 * definition. The response includes metadata about the value source
 * (environment-specific or default) and data type information for proper
 * client-side handling.
 *
 * Security considerations include public access for configuration values that
 * are not marked as sensitive. Sensitive configurations may require
 * authentication or administrative privileges. The operation supports caching
 * headers for performance optimization since configuration values change
 * infrequently.
 *
 * @param props.connection
 * @param props.configKey Unique configuration key identifier following naming
 *   convention: 'category.subcategory.setting'
 * @param props.environment Deployment environment for the configuration value
 *   (e.g., 'development', 'staging', 'production')
 * @path /todoApp/configurations/:configKey/values/:environment
 * @accessor api.functional.todoApp.configurations.values.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique configuration key identifier following naming convention:
     * 'category.subcategory.setting'
     */
    configKey: string;

    /**
     * Deployment environment for the configuration value (e.g.,
     * 'development', 'staging', 'production')
     */
    environment: string;
  };
  export type Response = IMvTodoAppActiveConfiguration;

  export const METADATA = {
    method: "GET",
    path: "/todoApp/configurations/:configKey/values/:environment",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/todoApp/configurations/${encodeURIComponent(props.configKey ?? "null")}/values/${encodeURIComponent(props.environment ?? "null")}`;
  export const random = (): IMvTodoAppActiveConfiguration =>
    typia.random<IMvTodoAppActiveConfiguration>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("configKey")(() => typia.assert(props.configKey));
      assert.param("environment")(() => typia.assert(props.environment));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
