import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ITodoAppUser } from "../../../structures/ITodoAppUser";
export * as register from "./register/index";

/**
 * Authenticate user and establish secure session.
 *
 * This endpoint validates user credentials and creates an authenticated
 * session. It checks the provided email and password against the stored
 * credentials in the todo_app_users table, ensuring the user account is active
 * and not deleted.
 *
 * Upon successful authentication, the system generates JWT access and refresh
 * tokens for secure session management. The operation also creates a session
 * record in the todo_app_user_sessions table, capturing the user's IP address,
 * connection URL, and referrer information for audit and security monitoring.
 *
 * Security considerations include rate limiting to prevent brute force attacks,
 * secure password validation using bcrypt hashing, and proper session
 * expiration management. Failed authentication attempts are logged for security
 * monitoring without revealing specific validation details to prevent
 * information disclosure.
 *
 * @param props.connection
 * @param props.body User authentication credentials including email and
 *   password
 * @path /todoApp/auth/login
 * @accessor api.functional.todoApp.auth.login
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function login(
  connection: IConnection,
  props: login.Props,
): Promise<login.Response> {
  return true === connection.simulate
    ? login.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...login.METADATA,
          path: login.path(),
          status: null,
        },
        props.body,
      );
}
export namespace login {
  export type Props = {
    /** User authentication credentials including email and password */
    body: ITodoAppUser.ILogin;
  };
  export type Body = ITodoAppUser.ILogin;
  export type Response = ITodoAppUser.IAuthResponse;

  export const METADATA = {
    method: "POST",
    path: "/todoApp/auth/login",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/todoApp/auth/login";
  export const random = (): ITodoAppUser.IAuthResponse =>
    typia.random<ITodoAppUser.IAuthResponse>();
  export const simulate = (
    connection: IConnection,
    props: login.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: login.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
