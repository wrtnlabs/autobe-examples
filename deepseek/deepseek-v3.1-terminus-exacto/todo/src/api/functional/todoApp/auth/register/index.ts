import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ITodoAppUser } from "../../../../structures/ITodoAppUser";

/**
 * Register a new user account for the Todo application.
 *
 * This endpoint allows new users to create an account for accessing the Todo
 * application. The registration process validates the email format, ensures
 * email uniqueness across all users, and enforces password complexity
 * requirements.
 *
 * Upon successful registration, the system creates a user account record in the
 * todo_app_users table with the provided email and securely hashed password.
 * The user account is initially set to 'active' status, and the creation
 * timestamp is recorded for audit purposes.
 *
 * Security considerations include password hashing using industry-standard
 * algorithms, email verification before full account activation, and protection
 * against duplicate account creation. The system validates that the email
 * follows proper format requirements and that the password meets minimum
 * security standards.
 *
 * @param props.connection
 * @param props.body User registration information including email and password
 * @path /todoApp/auth/register
 * @accessor api.functional.todoApp.auth.register.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function create(
  connection: IConnection,
  props: create.Props,
): Promise<create.Response> {
  return true === connection.simulate
    ? create.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...create.METADATA,
          path: create.path(),
          status: null,
        },
        props.body,
      );
}
export namespace create {
  export type Props = {
    /** User registration information including email and password */
    body: ITodoAppUser.ICreate;
  };
  export type Body = ITodoAppUser.ICreate;
  export type Response = ITodoAppUser;

  export const METADATA = {
    method: "POST",
    path: "/todoApp/auth/register",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/todoApp/auth/register";
  export const random = (): ITodoAppUser => typia.random<ITodoAppUser>();
  export const simulate = (
    connection: IConnection,
    props: create.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: create.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
