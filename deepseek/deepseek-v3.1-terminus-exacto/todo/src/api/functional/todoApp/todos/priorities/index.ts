/**
 * Search and retrieve filtered list of todo priority levels.
 *
 * This operation enables administrators to search and filter through the
 * available todo priority levels defined in the system. It provides
 * comprehensive search capabilities for managing the priority classification
 * system used across all todo items.
 *
 * The operation supports multiple filtering options including priority code
 * matching, active status filtering, and weight-based sorting. Administrators
 * can use this endpoint to review existing priorities, check which ones are
 * currently active, and prepare for priority system updates or extensions.
 *
 * Security considerations include restricting access to administrative users
 * only, as priority management affects the entire application's todo
 * classification system. The operation integrates with the
 * todo_app_todo_priorities table and returns paginated results optimized for
 * administrative interfaces.
 *
 * Related operations include creating new priorities (POST /todos/priorities)
 * and updating existing priority definitions (PUT
 * /todos/priorities/{priorityCode}).
 *
 * @param props.connection
 * @param props.body Search criteria and pagination parameters for priority
 *   filtering
 * @path /todoApp/todos/priorities
 * @accessor api.functional.todoApp.todos.priorities.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /** Search criteria and pagination parameters for priority filtering */
    body: ITodoAppTodoPriority.IRequest;
  };
  export type Body = ITodoAppTodoPriority.IRequest;
  export type Response = IPageITodoAppTodoPriority.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/todoApp/todos/priorities",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/todoApp/todos/priorities";
  export const random = (): IPageITodoAppTodoPriority.ISummary =>
    typia.random<IPageITodoAppTodoPriority.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

