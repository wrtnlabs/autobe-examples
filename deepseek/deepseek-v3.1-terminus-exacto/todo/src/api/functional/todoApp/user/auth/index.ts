import { IConnection } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";

/**
 * Terminate user session and invalidate authentication tokens.
 *
 * This endpoint securely terminates an active user session by invalidating the
 * current JWT tokens and marking the session record as expired in the
 * todo_app_user_sessions table. The operation requires valid authentication to
 * ensure only authenticated users can log out.
 *
 * The system updates the expired_at timestamp in the session record to prevent
 * token reuse and maintains audit trails for security monitoring. All
 * client-side tokens should be cleared upon successful logout to ensure
 * complete session termination.
 *
 * Security considerations include proper token invalidation, prevention of
 * session hijacking, and maintaining audit logs for security compliance. The
 * operation handles both normal logout scenarios and forced session termination
 * for security incidents.
 *
 * @param props.connection
 * @path /todoApp/user/auth/logout
 * @accessor api.functional.todoApp.user.auth.logout
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function logout(connection: IConnection): Promise<void> {
  return true === connection.simulate
    ? logout.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...logout.METADATA,
          path: logout.path(),
          status: null,
        },
      );
}
export namespace logout {
  export const METADATA = {
    method: "POST",
    path: "/todoApp/user/auth/logout",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/todoApp/user/auth/logout";
  export const random = (): void => typia.random<void>();
  export const simulate = (_connection: IConnection): void => {
    return random();
  };
}
