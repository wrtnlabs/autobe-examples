import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ITodoAppTodo } from "../../../../../structures/ITodoAppTodo";
import { IPageITodoAppTodo } from "../../../../../structures/IPageITodoAppTodo";

/**
 * Search and retrieve a filtered, paginated list of todo items.
 *
 * This operation provides comprehensive search capabilities for todo items
 * within the authenticated user's personal todo list. Users can search by
 * keyword matching in todo titles and descriptions, filter by status (pending,
 * in-progress, completed), priority levels (low, medium, high), due date
 * ranges, and creation date ranges.
 *
 * The search functionality supports partial matching for text searches and
 * exact matching for categorical filters like status and priority. Results are
 * returned in a paginated format with configurable page sizes and sorting
 * options. Users can sort by creation date, due date, priority weight, or title
 * in ascending or descending order.
 *
 * Security considerations include strict user isolation - each user can only
 * search their own todo items. The operation validates that all referenced
 * status and priority codes exist in their respective reference tables before
 * executing the search. Performance optimizations include efficient indexing on
 * user_id, creation_date, and due_date fields to ensure responsive search
 * results even with large todo collections.
 *
 * The operation integrates with the normalized database structure by joining
 * the main todo table with status and priority reference tables to provide
 * meaningful status names and priority levels in the search results. This
 * ensures that users see human-readable status and priority information rather
 * than internal codes.
 *
 * @param props.connection
 * @param props.body Search criteria and pagination parameters for todo
 *   filtering
 * @path /todoApp/user/search/todos
 * @accessor api.functional.todoApp.user.search.todos.search
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function search(
  connection: IConnection,
  props: search.Props,
): Promise<search.Response> {
  return true === connection.simulate
    ? search.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...search.METADATA,
          path: search.path(),
          status: null,
        },
        props.body,
      );
}
export namespace search {
  export type Props = {
    /** Search criteria and pagination parameters for todo filtering */
    body: ITodoAppTodo.IRequest;
  };
  export type Body = ITodoAppTodo.IRequest;
  export type Response = IPageITodoAppTodo.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/todoApp/user/search/todos",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/todoApp/user/search/todos";
  export const random = (): IPageITodoAppTodo.ISummary =>
    typia.random<IPageITodoAppTodo.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: search.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: search.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
