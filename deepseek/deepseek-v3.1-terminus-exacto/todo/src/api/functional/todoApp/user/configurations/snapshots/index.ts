/**
 * Retrieve detailed information for a specific configuration snapshot
 * identified by its unique snapshot ID. This operation provides complete access
 * to the historical configuration state captured at the moment the snapshot was
 * created.
 *
 * The response includes all snapshot details such as the configuration
 * definition, validation rules, default values, and metadata that were active
 * at the time of snapshot creation. This detailed view is essential for
 * understanding configuration changes over time and for rollback operations.
 *
 * Security considerations include appropriate access controls for configuration
 * management. Only users with configuration management permissions should be
 * able to access detailed snapshot information. The operation integrates with
 * the todo_app_configuration_snapshots table as defined in the Prisma schema,
 * providing comprehensive snapshot details.
 *
 * This operation is crucial for configuration auditing, troubleshooting
 * configuration-related issues, and understanding the historical evolution of
 * application settings. It enables administrators to examine specific
 * configuration states from the past for compliance and analysis purposes.
 *
 * @param props.connection
 * @param props.configKey Unique configuration key identifier for context
 *   verification
 * @param props.snapshotId Unique identifier of the target configuration
 *   snapshot
 * @path /todoApp/user/configurations/:configKey/snapshots/:snapshotId
 * @accessor api.functional.todoApp.user.configurations.snapshots.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique configuration key identifier for context verification */
    configKey: string;

    /** Unique identifier of the target configuration snapshot */
    snapshotId: string & tags.Format<"uuid">;
  };
  export type Response = ITodoAppConfigurationSnapshot;

  export const METADATA = {
    method: "GET",
    path: "/todoApp/user/configurations/:configKey/snapshots/:snapshotId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/todoApp/user/configurations/${encodeURIComponent(props.configKey ?? "null")}/snapshots/${encodeURIComponent(props.snapshotId ?? "null")}`;
  export const random = (): ITodoAppConfigurationSnapshot =>
    typia.random<ITodoAppConfigurationSnapshot>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("configKey")(() => typia.assert(props.configKey));
      assert.param("snapshotId")(() => typia.assert(props.snapshotId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

