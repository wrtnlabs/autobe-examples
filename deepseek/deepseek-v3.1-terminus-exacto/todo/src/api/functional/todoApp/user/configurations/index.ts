/**
 * Search and retrieve a filtered, paginated list of Todo application
 * configuration settings.
 *
 * Retrieve a filtered and paginated list of Todo application configuration
 * settings from the system. This operation provides advanced search
 * capabilities for finding configuration settings based on multiple criteria
 * including partial key matching, data type filtering, status filtering, and
 * creation date ranges.
 *
 * The operation supports comprehensive pagination with configurable page sizes
 * and sorting options. Configuration settings can be sorted by creation date,
 * update date, config_key, or other relevant fields in ascending or descending
 * order.
 *
 * Security considerations include that configuration settings may contain
 * sensitive application parameters, so access should be restricted to
 * authorized users only. The operation integrates with the
 * todo_app_configurations table as defined in the Prisma schema, incorporating
 * all available configuration fields including config_key, config_value,
 * data_type, description, status, created_at, and updated_at.
 *
 * This operation serves system administrators who need to manage application
 * settings and monitor configuration changes across the Todo application
 * ecosystem.
 *
 * @param props.connection
 * @param props.body Search criteria and pagination parameters for configuration
 *   settings filtering
 * @path /todoApp/user/configurations
 * @accessor api.functional.todoApp.user.configurations.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Search criteria and pagination parameters for configuration settings
     * filtering
     */
    body: ITodoAppConfiguration.IRequest;
  };
  export type Body = ITodoAppConfiguration.IRequest;
  export type Response = IPageITodoAppConfiguration.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/todoApp/user/configurations",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/todoApp/user/configurations";
  export const random = (): IPageITodoAppConfiguration.ISummary =>
    typia.random<IPageITodoAppConfiguration.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

