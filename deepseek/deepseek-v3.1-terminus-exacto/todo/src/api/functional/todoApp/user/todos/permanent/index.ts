import { HttpError, IConnection } from "@nestia/fetcher";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";

/**
 * Permanently delete a todo from the system.
 *
 * This operation performs irreversible deletion of a todo that has been previously deleted and moved to trash. Once executed, the todo and all its associated data including edit history, completion records, and metadata are permanently removed from the system with no recovery options.
 *
 * The operation requires that the todo exists and belongs to the authenticated user. The system performs comprehensive validation to ensure proper authorization before proceeding with permanent deletion.
 *
 * This is a destructive operation intended for final cleanup when users are certain they want to remove todos completely from their account. The system logs all permanent deletion events for audit and monitoring purposes.
 *
 * Related operations include initial deletion (DELETE /todos/{todoId}), trash viewing (GET /trash), and restoration (POST /trash/{todoId}/restore).
 *
 * @param props.connection
 * @param props.todoId The unique identifier of the todo to permanently delete
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor user
 * @x-autobe-specification Permanently delete a todo and all associated data from the system.
 *
 * Implementation steps:
 * 1. Validate user authentication and session
 * 2. Verify todo ownership - user can only delete their own todos
 * 3. Check that the todo exists and is in trash (deleted_at is not null)
 * 4. Perform cascading deletion of all related data:
 *    - Delete from todo_app_todos table
 *    - Delete associated edit history from todo_app_todo_histories
 *    - Delete completion status records from todo_app_todo_completions
 *    - Delete description fields from todo_app_todo_description_fields
 *    - Delete date fields from todo_app_todo_start_date_fields and todo_app_todo_due_date_fields
 * 5. Log the permanent deletion event for audit purposes
 * 6. Return success response with no data
 *
 * Security considerations:
 * - Strict ownership validation required
 * - Permanent deletion is irreversible
 * - Must confirm todo is in trash before permanent deletion
 * - No recovery mechanism after this operation
 * @path /todoApp/user/todos/:todoId/permanent
 * @accessor api.functional.todoApp.user.todos.permanent.erase
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function erase(
  connection: IConnection,
  props: erase.Props,
): Promise<void> {
  return true === connection.simulate
    ? erase.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...erase.METADATA,
          path: erase.path(props),
          status: null,
        },
      );
}
export namespace erase {
  export type Props = {
    /**
     * The unique identifier of the todo to permanently delete
     */
    todoId: string & tags.Format<"uuid">;
  };

  export const METADATA = {
    method: "DELETE",
    path: "/todoApp/user/todos/:todoId/permanent",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/todoApp/user/todos/${encodeURIComponent(props.todoId ?? "null")}/permanent`;
  export const random = (): void => typia.random<void>();
  export const simulate = (
    connection: IConnection,
    props: erase.Props,
  ): void => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: erase.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("todoId")(() => typia.assert(props.todoId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
