/**
 * Search and analyze todo completion patterns with advanced filtering.
 *
 * This operation provides comprehensive analytics capabilities for analyzing
 * todo completion patterns and productivity trends over time. It enables users
 * to gain insights into their task management effectiveness through detailed
 * statistical analysis.
 *
 * The analytics include completion rate calculations, average
 * time-to-completion metrics, priority-based performance analysis, and trend
 * identification across different time periods. Users can filter results by
 * date ranges, specific status transitions, priority levels, and completion
 * patterns to focus on specific aspects of their productivity.
 *
 * Security is maintained through user-based data isolation, ensuring that
 * analytics only reflect the authenticated user's own todo data. The operation
 * automatically applies user-based filtering to prevent cross-user data
 * access.
 *
 * The operation leverages the todo_app_todo_snapshots table for historical
 * state tracking and todo_app_todo_lifecycles for current state information.
 * This historical data enables trend analysis and pattern recognition over
 * extended time periods.
 *
 * Advanced filtering capabilities support complex analytical queries including
 * date range filtering, status-based segmentation, priority-level analysis, and
 * completion pattern identification. The operation returns paginated results
 * with comprehensive statistical summaries.
 *
 * @param props.connection
 * @param props.body Analytics search criteria including date ranges, filters,
 *   and pagination parameters
 * @path /todoApp/user/analytics/todo-completion
 * @accessor api.functional.todoApp.user.analytics.todo_completion.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
