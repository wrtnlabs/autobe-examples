/**
 * Retrieve a specific user account by ID.
 *
 * This API operation retrieves detailed information for a specific user account
 * identified by the unique user ID. The operation accesses the todo_app_users
 * table in the database and returns comprehensive user data including email
 * address, account status, creation timestamp, and last update timestamp.
 *
 * Security considerations require that authenticated users can only access
 * their own user account information. The system validates that the requesting
 * user's authentication token matches the user ID specified in the path
 * parameter to prevent unauthorized access to other users' data.
 *
 * The operation integrates with the User table as defined in the Prisma schema,
 * incorporating all available user fields and relationships. The response
 * includes complete user information suitable for account management and
 * profile display purposes.
 *
 * @param props.connection
 * @param props.userId Unique identifier of the target user
 * @path /todoApp/user/users/:userId
 * @accessor api.functional.todoApp.user.users.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique identifier of the target user */
    userId: string & tags.Format<"uuid">;
  };
  export type Response = ITodoAppUser;

  export const METADATA = {
    method: "GET",
    path: "/todoApp/user/users/:userId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/todoApp/user/users/${encodeURIComponent(props.userId ?? "null")}`;
  export const random = (): ITodoAppUser => typia.random<ITodoAppUser>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("userId")(() => typia.assert(props.userId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

