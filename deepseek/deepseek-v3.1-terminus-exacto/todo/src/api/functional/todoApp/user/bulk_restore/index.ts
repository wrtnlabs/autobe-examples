/**
 * Restore multiple soft-deleted todos from trash back to active status in a single bulk operation.
 *
 * This API operation enables users to efficiently restore multiple previously deleted todos from the trash system. When a todo is restored, it is removed from the trash and returned to the user's active todo list with all original data preserved including creation date, modification history, and completion status. The operation performs validation to ensure all specified todos exist in the current user's trash and have not been permanently deleted.
 *
 * The bulk restoration process maintains data integrity by ensuring atomic transaction handling - either all specified todos are successfully restored or none are, preventing partial restoration states. Each restoration event is recorded in the todo_app_trash_restorations table for audit trail purposes, capturing the timestamp and user context of the restoration operation.
 *
 * Security and privacy are maintained through strict user-scoping - users can only restore todos that they originally deleted and have appropriate access to. The operation validates ownership and existence checks before proceeding with any restoration actions.
 *
 * Related operations include GET /trash for viewing deleted todos, DELETE /trash/{id} for permanent deletion, and GET /todos for viewing restored active todos. This bulk operation provides significant efficiency improvements over individual restoration operations when users need to recover multiple accidentally deleted todos.
 *
 * @param props.connection
 * @param props.body List of todo IDs to restore from trash
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor user
 * @x-autobe-specification Validate that all todo IDs in the request belong to the current user and exist in the trash system. Check that none of the specified todos have been permanently deleted (permanently_deleted_at is null). For each valid todo, update the todo_app_todos.deleted_at field to null to mark as active, create a restoration record in todo_app_trash_restorations, and update the todo_app_trash_items.restored_at timestamp. Use database transactions to ensure atomicity - if any restoration fails, rollback all changes. Return a paginated summary of the restored todos with basic information for confirmation. Handle validation errors gracefully with appropriate error messages.
 * @path /todoApp/user/bulk-restore
 * @accessor api.functional.todoApp.user.bulk_restore.bulkRestore
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function bulkRestore(
  connection: IConnection,
  props: bulkRestore.Props,
): Promise<bulkRestore.Response> {
  return true === connection.simulate
    ? bulkRestore.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...bulkRestore.METADATA,
          path: bulkRestore.path(),
          status: null,
        },
        props.body,
      );
}
