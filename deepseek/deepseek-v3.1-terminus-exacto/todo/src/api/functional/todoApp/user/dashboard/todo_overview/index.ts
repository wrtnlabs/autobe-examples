/**
 * Retrieve comprehensive dashboard overview of todo statistics and metrics.
 *
 * This operation provides a high-level dashboard view of the user's todo
 * management system, aggregating data from multiple database tables to present
 * key metrics and statistics.
 *
 * The dashboard includes total todo counts broken down by status (pending,
 * in-progress, completed), priority distribution across all active todos,
 * recent completion trends, and upcoming due dates. This information helps
 * users quickly assess their productivity and task management status.
 *
 * Security considerations ensure that users can only view their own todo data.
 * The operation automatically filters results based on the authenticated user's
 * identity extracted from the JWT token. No sensitive user information is
 * exposed to unauthorized parties.
 *
 * The operation integrates with the todo_app_todos table for basic todo
 * information, todo_app_todo_lifecycles for current state tracking,
 * todo_app_todo_statuses for status definitions, and todo_app_todo_priorities
 * for priority classification. This multi-table approach ensures accurate and
 * comprehensive dashboard metrics.
 *
 * Performance optimizations include efficient aggregation queries and caching
 * strategies to ensure responsive dashboard loading even with large todo
 * datasets.
 *
 * @param props.connection
 * @path /todoApp/user/dashboard/todo-overview
 * @accessor api.functional.todoApp.user.dashboard.todo_overview.dashboard
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function dashboard(
  connection: IConnection,
): Promise<dashboard.Response> {
  return true === connection.simulate
    ? dashboard.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...dashboard.METADATA,
          path: dashboard.path(),
          status: null,
        },
      );
}
export namespace dashboard {
  export type Response = ITodoAppTodoDashboard;

  export const METADATA = {
    method: "GET",
    path: "/todoApp/user/dashboard/todo-overview",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/todoApp/user/dashboard/todo-overview";
  export const random = (): ITodoAppTodoDashboard =>
    typia.random<ITodoAppTodoDashboard>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}
