import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ITodoAppTodo } from "../../structures/ITodoAppTodo";
import { IPageITodoAppTodo } from "../../structures/IPageITodoAppTodo";

/**
 * Retrieve a specific todo item by its unique identifier.
 *
 * This operation fetches a single todo item from the system using its unique
 * identifier. The todo is retrieved from the todo_app_todos table which stores
 * core todo items with immutable attributes and ownership information.
 *
 * The operation performs authorization checks to ensure the requesting user has
 * permission to access the specific todo item. If the todo does not exist or
 * the user lacks appropriate permissions, an appropriate error response is
 * returned.
 *
 * The response includes all todo details including the title, description,
 * optional due date, creation timestamps, and ownership information linking to
 * the user who created the todo and the session that created it for audit
 * tracing purposes.
 *
 * This endpoint is essential for displaying individual todo details in user
 * interfaces and for retrieving specific todo information for editing or
 * viewing purposes.
 *
 * @param props.connection
 * @param props.todoId Unique identifier of the target todo item
 * @path /todos/:todoId
 * @accessor api.functional.todos.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique identifier of the target todo item */
    todoId: string & tags.Format<"uuid">;
  };
  export type Response = ITodoAppTodo;

  export const METADATA = {
    method: "GET",
    path: "/todos/:todoId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/todos/${encodeURIComponent(props.todoId ?? "null")}`;
  export const random = (): ITodoAppTodo => typia.random<ITodoAppTodo>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("todoId")(() => typia.assert(props.todoId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

