import { ITodoListUser } from "../../../../structures/ITodoListUser";

/**
 * Retrieve a Todo List user's account details using a UUID as defined in
 * todo_list_users.
 *
 * Fetch a specific user's detailed information from the Todo List service by
 * their unique user ID.
 *
 * This operation provides the complete set of profile details, account
 * creation/update timestamps, whether the account is locked, and other core
 * account metadata. The password hash is present in the schema for
 * authentication validation but is excluded from user-facing responses for
 * security reasons.
 *
 * Access to this endpoint must enforce authentication and user authorization.
 * End users may typically view only their own account; administrators may be
 * permitted to view any user's account information for audit and moderation
 * purposes. Soft-deleted user accounts (where deleted_at is not null) are not
 * returned to ensure data privacy and security compliance as required by
 * business rules.
 *
 * @param props.connection
 * @param props.userId Unique identifier (UUID) of the Todo List user.
 * @path /todoList/user/users/:userId
 * @accessor api.functional.todoList.user.users.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique identifier (UUID) of the Todo List user. */
    userId: string & tags.Format<"uuid">;
  };
  export type Response = ITodoListUser;

  export const METADATA = {
    method: "GET",
    path: "/todoList/user/users/:userId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/todoList/user/users/${encodeURIComponent(props.userId ?? "null")}`;
  export const random = (): ITodoListUser => typia.random<ITodoListUser>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("userId")(() => typia.assert(props.userId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

