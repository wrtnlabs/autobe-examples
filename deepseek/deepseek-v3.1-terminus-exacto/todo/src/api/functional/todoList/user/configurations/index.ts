import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ITodoListConfiguration } from "../../../../structures/ITodoListConfiguration";

/**
 * Create a new system configuration setting.
 *
 * This operation allows authorized administrators to create new configuration
 * entries that control various aspects of the Todo List application behavior.
 * Each configuration consists of a unique key identifier and a corresponding
 * value that can represent different data types (boolean, number, text) as
 * needed by the application logic.
 *
 * The configuration system supports categorization for better organization,
 * allowing related settings to be grouped together (e.g., 'ui', 'performance',
 * 'security', 'features'). Each configuration entry includes a human-readable
 * description to help administrators understand the purpose and usage of the
 * setting.
 *
 * Security considerations include requiring administrative privileges to modify
 * system-level configurations. The operation validates that the configuration
 * key is unique across all existing entries and ensures proper data formatting
 * for the value field. Created configurations become immediately available for
 * the application to use.
 *
 * Related operations: Update configuration (PUT
 * /configurations/{configurationKey}), List configurations (PATCH
 * /configurations).
 *
 * @param props.connection
 * @param props.body Configuration creation data including key, value,
 *   description, and category
 * @path /todolist/user/configurations
 * @accessor api.functional.todolist.user.configurations.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function create(
  connection: IConnection,
  props: create.Props,
): Promise<create.Response> {
  return true === connection.simulate
    ? create.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...create.METADATA,
          path: create.path(),
          status: null,
        },
        props.body,
      );
}
export namespace create {
  export type Props = {
    /**
     * Configuration creation data including key, value, description, and
     * category
     */
    body: ITodoListConfiguration.ICreate;
  };
  export type Body = ITodoListConfiguration.ICreate;
  export type Response = ITodoListConfiguration;

  export const METADATA = {
    method: "POST",
    path: "/todolist/user/configurations",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/todolist/user/configurations";
  export const random = (): ITodoListConfiguration =>
    typia.random<ITodoListConfiguration>();
  export const simulate = (
    connection: IConnection,
    props: create.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: create.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

/**
 * Update an existing system configuration setting.
 *
 * This operation enables authorized administrators to modify existing
 * configuration entries that control application behavior. The configuration is
 * identified by its unique key, which serves as the primary identifier for
 * system settings. Administrators can update the configuration value,
 * description, or category as needed.
 *
 * The update operation supports partial modification, meaning only the fields
 * provided in the request body will be updated while other fields remain
 * unchanged. This allows for flexible configuration management without
 * requiring complete re-specification of all configuration properties.
 *
 * Security considerations include requiring administrative privileges to modify
 * system-level configurations. The operation validates that the configuration
 * key exists and ensures the updated value maintains proper data formatting.
 * The updated_at timestamp is automatically refreshed to track when the
 * configuration was last modified.
 *
 * Related operations: Create configuration (POST /configurations), Get
 * configuration (GET /configurations/{configurationKey}).
 *
 * @param props.connection
 * @param props.configurationKey Unique configuration key identifier of the
 *   target configuration setting (global scope)
 * @param props.body Configuration update data including value, description, and
 *   category
 * @path /todolist/user/configurations/:configurationKey
 * @accessor api.functional.todolist.user.configurations.update
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function update(
  connection: IConnection,
  props: update.Props,
): Promise<update.Response> {
  return true === connection.simulate
    ? update.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...update.METADATA,
          path: update.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace update {
  export type Props = {
    /**
     * Unique configuration key identifier of the target configuration
     * setting (global scope)
     */
    configurationKey: string;

    /** Configuration update data including value, description, and category */
    body: ITodoListConfiguration.IUpdate;
  };
  export type Body = ITodoListConfiguration.IUpdate;
  export type Response = ITodoListConfiguration;

  export const METADATA = {
    method: "PUT",
    path: "/todolist/user/configurations/:configurationKey",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/todolist/user/configurations/${encodeURIComponent(props.configurationKey ?? "null")}`;
  export const random = (): ITodoListConfiguration =>
    typia.random<ITodoListConfiguration>();
  export const simulate = (
    connection: IConnection,
    props: update.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: update.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("configurationKey")(() =>
        typia.assert(props.configurationKey),
      );
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
