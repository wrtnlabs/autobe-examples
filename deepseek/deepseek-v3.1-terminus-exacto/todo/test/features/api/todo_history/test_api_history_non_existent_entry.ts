export async function test_api_history_non_existent_entry(
  connection: api.IConnection,
): Promise<void> {
  // Create user connection and authenticate
  const userConnection: api.IConnection = { host: connection.host };
  const user = await authorize_user_join(userConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies ITodoAppUser.IJoin,
  });
  typia.assert(user);
  // Create a todo for history testing
  const todo = await generate_random_todo_app_user_todos_create(
    userConnection,
    {
      body: {
        title: RandomGenerator.paragraph({ sentences: 2 }),
      } satisfies ITodoAppTodo.ICreate,
    },
  );
  typia.assert(todo);
  // Attempt to retrieve a non-existent history entry
  await TestValidator.httpError(
    "should return 404 for non-existent history entry",
    404,
    async () => {
      await api.functional.todoApp.user.todos.histories.at(userConnection, {
        todoId: todo.id,
        historyId: typia.random<string & tags.Format<"uuid">>(),
      });
    },
  );
}
