export async function test_api_todo_edit_history_access_another_users_todo(
  connection: api.IConnection,
): Promise<void> {
  // Step 1: Create first member account
  const firstMemberConnection: api.IConnection = { host: connection.host };
  const firstMember = await authorize_member_join(firstMemberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IMultiUserTodoMember.IJoin,
  });
  typia.assert(firstMember);
  // Step 2: Create a todo with the first member
  const todo = await generate_random_multi_user_todo_member_todos_create(
    firstMemberConnection,
    {
      body: {
        title: RandomGenerator.paragraph({ sentences: 2 }),
        description: RandomGenerator.paragraph({ sentences: 3 }),
      } satisfies IMultiUserTodoTodo.ICreate,
    },
  );
  typia.assert(todo);
  // Step 3: Create second member account
  const secondMemberConnection: api.IConnection = { host: connection.host };
  const secondMember = await authorize_member_join(secondMemberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IMultiUserTodoMember.IJoin,
  });
  typia.assert(secondMember);
  // Step 4: Attempt to access first member's todo edit history with second member
  // Use a valid UUID format but with non-existent ID to test ownership validation
  const nonExistentHistoryId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.httpError(
    "should return 404 when accessing another user's todo edit history",
    404,
    async () => {
      await api.functional.multiUserTodo.member.todos.edit_histories.at(
        secondMemberConnection,
        {
          todoId: todo.id,
          historyId: nonExistentHistoryId,
        },
      );
    },
  );
}
