export async function test_api_todo_deletion_nonexistent_id(
  connection: api.IConnection,
): Promise<void> {
  // Create user connection and authenticate
  const userConnection: api.IConnection = { host: connection.host };
  await authorize_user_join(userConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  // Attempt to delete a non-existent todo ID
  const nonExistentId = typia.random<string & tags.Format<"uuid">>();
  // Verify the deletion fails with appropriate error
  await TestValidator.httpError(
    "deletion should fail for non-existent todo",
    404,
    async () => {
      await api.functional.todoApp.user.todos.erase(userConnection, {
        todoId: nonExistentId,
      });
    },
  );
}
