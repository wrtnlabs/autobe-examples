export async function test_api_todo_completion_mark_incomplete_as_complete(
  connection: api.IConnection,
): Promise<void> {
  // Create user connection and authenticate
  const userConnection: api.IConnection = { host: connection.host };
  const authorizedUser = await authorize_user_join(userConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
    } satisfies ITodoAppUser.IJoin,
  });
  typia.assert(authorizedUser);
  // Note: The create endpoint returns void, so we cannot create a todo through the regular API
  // and then mark it as complete. This test scenario needs to be rethought since we cannot
  // get a todo object to work with from the create operation.
  // Since the scenario is impossible with the current API structure, we need to acknowledge
  // that this test cannot be implemented as originally planned
  throw new Error(
    "Test scenario cannot be implemented: todo creation endpoint returns void, making it impossible to get a todo ID for completion update",
  );
}
