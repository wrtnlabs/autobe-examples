import { authorize_user_join } from "../../../authorize/authorize_user_join";
import { authorize_user_login } from "../../../authorize/authorize_user_login";
import { authorize_user_refresh } from "../../../authorize/authorize_user_refresh";

export async function test_api_todo_create_with_complete_fields(
  connection: api.IConnection,
): Promise<void> {
  // Create user connection and authenticate
  const userConnection: api.IConnection = { host: connection.host };
  await authorize_user_join(userConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
    } satisfies ITodoAppUser.IJoin,
  });
  // Create todo - the API returns void and accepts no parameters
  await api.functional.todoApp.user.todos.create(userConnection);
  // Since the API returns void and accepts no parameters for optional fields,
  // we can only validate that the call completes without errors
  TestValidator.predicate("todo creation completed successfully", true);
}
