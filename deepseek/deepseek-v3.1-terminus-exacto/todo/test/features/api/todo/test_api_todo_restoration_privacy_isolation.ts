export async function test_api_todo_restoration_privacy_isolation(
  connection: api.IConnection,
): Promise<void> {
  // First user setup
  const firstUserConnection: api.IConnection = { host: connection.host };
  const firstUser = await authorize_user_join(firstUserConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies ITodoAppUser.IJoin,
  });
  typia.assert(firstUser);
  // First user creates a todo
  const todo = await api.functional.todoApp.user.todos.create(
    firstUserConnection,
    {
      body: {
        title: RandomGenerator.paragraph({ sentences: 2 }),
      } satisfies ITodoAppTodo.ICreate,
    },
  );
  typia.assert(todo);
  // First user soft-deletes the todo
  await api.functional.todoApp.user.todos.erase(firstUserConnection, {
    todoId: todo.id,
  });
  // Second user setup
  const secondUserConnection: api.IConnection = { host: connection.host };
  const secondUser = await authorize_user_join(secondUserConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies ITodoAppUser.IJoin,
  });
  typia.assert(secondUser);
  // Second user attempts to restore first user's todo - should fail
  await TestValidator.error("restoration unauthorized", async () => {
    await api.functional.todoApp.user.todos.restore(secondUserConnection, {
      todoId: todo.id,
    });
  });
}
