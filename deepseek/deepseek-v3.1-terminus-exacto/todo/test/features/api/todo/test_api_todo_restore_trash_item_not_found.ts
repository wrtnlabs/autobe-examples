export async function test_api_todo_restore_trash_item_not_found(
  connection: api.IConnection,
): Promise<void> {
  // Create user connection and register
  const userConnection: api.IConnection = { host: connection.host };
  const joinResponse = await authorize_user_join(userConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies ITodoAppUser.IJoin,
  });
  typia.assert(joinResponse);
  // Attempt to restore a non-existent trash item with invalid UUID
  await TestValidator.httpError(
    "restore non-existent trash item should return 404",
    404,
    async () => {
      await api.functional.todoApp.user.todos.trash.restore(userConnection, {
        trashItemId: typia.random<string & tags.Format<"uuid">>(),
      });
    },
  );
}
