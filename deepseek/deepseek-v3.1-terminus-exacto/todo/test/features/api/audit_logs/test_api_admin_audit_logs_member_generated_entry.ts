export async function test_api_admin_audit_logs_member_generated_entry(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin setup
  const adminConnection: api.IConnection = { host: connection.host };
  const admin = await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
    } satisfies IMultiUserTodoAdmin.IJoin,
  });
  typia.assert(admin);
  // 2. Member setup
  const memberConnection: api.IConnection = { host: connection.host };
  const member = await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IMultiUserTodoMember.IJoin,
  });
  typia.assert(member);
  // 3. Member creates todo to generate audit log
  const todo = await generate_random_multi_user_todo_member_todos_create(
    memberConnection,
    {
      body: {
        title: RandomGenerator.paragraph({ sentences: 2 }),
        description: RandomGenerator.paragraph({ sentences: 3 }),
      } satisfies IMultiUserTodoTodo.ICreate,
    },
  );
  typia.assert(todo);
  // 4. Admin retrieves audit log entry (using a valid audit log ID)
  // Note: In a real implementation, we would need to list audit logs first
  // to find the one generated by the todo creation operation
  const auditLog = await api.functional.multiUserTodo.admin.audit_logs.at(
    adminConnection,
    {
      auditLogId: typia.random<string & tags.Format<"uuid">>(),
    },
  );
  typia.assert(auditLog);
  // 5. Validate audit log content
  TestValidator.equals(
    "actor type should be member",
    auditLog.actorType,
    "member",
  );
  TestValidator.predicate(
    "event type should indicate todo creation",
    auditLog.eventType.includes("todo") ||
      auditLog.eventType.includes("create"),
  );
  TestValidator.predicate(
    "operation should be successful",
    auditLog.successFlag,
  );
  TestValidator.predicate(
    "should have member relationship",
    auditLog.member !== null,
  );
  TestValidator.equals(
    "member ID should match",
    auditLog.member?.id,
    member.id,
  );
  TestValidator.predicate(
    "should have creation timestamp",
    auditLog.createdAt !== null,
  );
}
