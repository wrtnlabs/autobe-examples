import typia, { tags } from "typia";

import { authorize_member_join } from "../../../authorize/authorize_member_join";
import { authorize_member_login } from "../../../authorize/authorize_member_login";
import { authorize_member_refresh } from "../../../authorize/authorize_member_refresh";

export async function test_api_member_login_incorrect_password(
  connection: api.IConnection,
): Promise<void> {
  // Create member account
  const memberConnection: api.IConnection = { host: connection.host };
  const member = await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "correct_password_123",
      display_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  typia.assert(member);
  // Attempt login with incorrect password using fresh connection
  const loginConnection: api.IConnection = { host: connection.host };
  await TestValidator.error(
    "login should fail with incorrect password",
    async () => {
      await authorize_member_login(loginConnection, {
        body: {
          email: member.email,
          password: "incorrect_password_456",
        } satisfies IMultiUserTodoMember.ILogin,
      });
    },
  );
}
