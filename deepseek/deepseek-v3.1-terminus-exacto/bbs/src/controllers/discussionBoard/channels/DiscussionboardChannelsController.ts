import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia from "typia";
import { patchDiscussionBoardChannels } from "../../../providers/patchDiscussionBoardChannels";
import { getDiscussionBoardChannelsChannelName } from "../../../providers/getDiscussionBoardChannelsChannelName";

import { IPageIDiscussionBoardChannel } from "../../../api/structures/IPageIDiscussionBoardChannel";
import { IDiscussionBoardChannel } from "../../../api/structures/IDiscussionBoardChannel";

@Controller("/discussionBoard/channels")
export class DiscussionboardChannelsController {
  /**
   * Retrieve a filtered and paginated list of discussion board channels from
   * the system. This operation provides advanced search capabilities for
   * finding channels based on multiple criteria including partial name
   * matching, status filtering, creation date ranges, and description content
   * search.
   *
   * The operation supports comprehensive pagination with configurable page
   * sizes and sorting options. Channels can be sorted by creation date, update
   * date, name, or status in ascending or descending order.
   *
   * Security considerations include appropriate filtering of channel
   * information based on the requesting user's authorization level. Only users
   * with appropriate permissions can access channel management features, while
   * basic channel lists may be available to authenticated users.
   *
   * This operation integrates with the discussion_board_channels table as
   * defined in the Prisma schema, incorporating all available channel fields
   * and relationships. The response includes channel summary information
   * optimized for list displays, with options to include additional details
   * based on authorization level.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for channel filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IDiscussionBoardChannel.IRequest,
  ): Promise<IPageIDiscussionBoardChannel.ISummary> {
    try {
      return await patchDiscussionBoardChannels({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information for a specific discussion board channel
   * identified by its unique name. This operation provides comprehensive
   * channel details including the channel name, detailed description, current
   * status, creation timestamp, last update timestamp, and soft deletion status
   * if applicable.
   *
   * The operation validates that the requested channel exists and is accessible
   * to the user. If the channel has been soft deleted, the operation may return
   * appropriate status information based on user permissions.
   *
   * Security considerations ensure that users can only access channels they are
   * authorized to view. The operation integrates with the
   * discussion_board_channels table as defined in the Prisma schema, providing
   * accurate and up-to-date channel information.
   *
   * This endpoint is essential for channel management interfaces and content
   * discovery workflows, allowing users to access detailed information about
   * specific discussion categories.
   *
   * @param connection
   * @param channelName Unique name identifier of the target discussion board
   *   channel
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":channelName")
  public async at(
    @TypedParam("channelName")
    channelName: string,
  ): Promise<IDiscussionBoardChannel> {
    try {
      return await getDiscussionBoardChannelsChannelName({
        channelName,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
