import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia from "typia";
import { patchDiscussionBoardChannelsChannelNamePosts } from "../../../../providers/patchDiscussionBoardChannelsChannelNamePosts";

import { IPageIDiscussionBoardPost } from "../../../../api/structures/IPageIDiscussionBoardPost";
import { IDiscussionBoardPost } from "../../../../api/structures/IDiscussionBoardPost";

@Controller("/discussionBoard/channels/:channelName/posts")
export class DiscussionboardChannelsPostsController {
  /**
   * This operation provides advanced search capabilities for finding discussion
   * board posts within a specific channel. Users can filter posts by various
   * criteria including title keywords, content search, post status (draft,
   * published, archived), creation date ranges, and sorting options.
   *
   * The operation leverages the discussion_board_posts table structure and its
   * relationships to channels and sections. It supports comprehensive
   * pagination with configurable page sizes and multiple sorting options
   * including creation date, update date, title, and pin status.
   *
   * Security considerations include channel-based access control where users
   * can only search posts within channels they have permission to access. The
   * operation validates that the specified channel exists and is active before
   * returning results.
   *
   * This operation integrates with the discussion_board_posts table as defined
   * in the Prisma schema, incorporating all available post fields and
   * relationships. The response includes post summary information optimized for
   * list displays, with options to include additional details based on
   * authorization level.
   *
   * @param connection
   * @param channelName Unique name identifier of the target discussion board
   *   channel (global scope)
   * @param body Search criteria and pagination parameters for post filtering
   *   within the specified channel
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedParam("channelName")
    channelName: string,
    @TypedBody()
    body: IDiscussionBoardPost.IRequest,
  ): Promise<IPageIDiscussionBoardPost.ISummary> {
    try {
      return await patchDiscussionBoardChannelsChannelNamePosts({
        channelName,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
