import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia from "typia";
import { patchDiscussionBoardChannelsChannelNameSections } from "../../../../providers/patchDiscussionBoardChannelsChannelNameSections";
import { getDiscussionBoardChannelsChannelNameSectionsSectionName } from "../../../../providers/getDiscussionBoardChannelsChannelNameSectionsSectionName";

import { IPageIDiscussionBoardSection } from "../../../../api/structures/IPageIDiscussionBoardSection";
import { IDiscussionBoardSection } from "../../../../api/structures/IDiscussionBoardSection";

@Controller("/discussionBoard/channels/:channelName/sections")
export class DiscussionboardChannelsSectionsController {
  /**
   * Search and retrieve filtered sections within a specific discussion board
   * channel.
   *
   * This operation provides comprehensive search capabilities for retrieving
   * discussion board sections organized within a specific channel. Users can
   * filter sections by various criteria including status, creation date ranges,
   * and search terms within section names and descriptions.
   *
   * The operation supports pagination with configurable page sizes and multiple
   * sorting options. Sections can be sorted by creation date, update date,
   * name, or status in ascending or descending order. The response includes
   * section summary information optimized for list displays.
   *
   * Security considerations include appropriate access controls based on
   * channel visibility settings. Public channels may allow anonymous access,
   * while restricted channels require authentication. The operation respects
   * channel-specific permissions and section visibility settings.
   *
   * This operation integrates with the discussion_board_sections table as
   * defined in the Prisma schema, incorporating all available section fields
   * and relationships with the parent channel.
   *
   * @param connection
   * @param channelName Unique name identifier of the parent discussion board
   *   channel (global scope)
   * @param body Search criteria and pagination parameters for section filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedParam("channelName")
    channelName: string,
    @TypedBody()
    body: IDiscussionBoardSection.IRequest,
  ): Promise<IPageIDiscussionBoardSection.ISummary> {
    try {
      return await patchDiscussionBoardChannelsChannelNameSections({
        channelName,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific discussion board section within a channel.
   *
   * This GET operation allows users to retrieve detailed information about a
   * specific discussion board section within a channel. The operation uses the
   * channel name and section name as path parameters to uniquely identify the
   * target section.
   *
   * The operation validates that both the channel and section exist and are
   * accessible. It returns the complete section object including its name,
   * description, status, creation timestamp, and relationship to the parent
   * channel. This endpoint is useful for displaying section details when users
   * navigate to specific discussion topics.
   *
   * Security considerations include ensuring that the requested section belongs
   * to an active channel and that the user has appropriate permissions to view
   * the content. The operation performs necessary validation to prevent access
   * to deleted or inactive sections unless the user has administrative
   * privileges.
   *
   * @param connection
   * @param channelName Unique name identifier of the parent discussion board
   *   channel (global scope)
   * @param sectionName Unique name identifier of the target section within the
   *   channel (scoped to channel)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sectionName")
  public async at(
    @TypedParam("channelName")
    channelName: string,
    @TypedParam("sectionName")
    sectionName: string,
  ): Promise<IDiscussionBoardSection> {
    try {
      return await getDiscussionBoardChannelsChannelNameSectionsSectionName({
        channelName,
        sectionName,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
