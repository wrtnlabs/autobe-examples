import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { getDiscussionBoardPostsPostIdCommentsCommentId } from "../../../../providers/getDiscussionBoardPostsPostIdCommentsCommentId";

import { IDiscussionBoardComment } from "../../../../api/structures/IDiscussionBoardComment";

@Controller("/discussionBoard/posts/:postId/comments/:commentId")
export class DiscussionboardPostsCommentsController {
  /**
   * Retrieve a specific comment from a discussion board post by its unique
   * identifier.
   *
   * This operation retrieves detailed information about a specific comment
   * within a discussion board post. The operation requires both the post
   * identifier and comment identifier to ensure the comment belongs to the
   * correct post context.
   *
   * Comments are hierarchical and support threaded discussions up to 3 levels
   * deep as specified in the requirements. Each comment includes content with
   * Markdown formatting support, author information, threading level, status,
   * and timestamps for creation and modification.
   *
   * The operation performs validation to ensure the comment exists and belongs
   * to the specified post. It returns the complete comment object including all
   * fields from the discussion_board_comments table. This operation is
   * essential for displaying individual comments in discussion threads and
   * supporting comment management features.
   *
   * Security considerations include proper authorization checks to ensure users
   * can only access comments they are permitted to view. The operation respects
   * comment status (draft, published, deleted) and returns appropriate
   * responses based on the comment's current state.
   *
   * @param connection
   * @param postId Unique identifier of the parent post containing the target
   *   comment
   * @param commentId Unique identifier of the target comment within the
   *   specified post
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @TypedParam("postId")
    postId: string & tags.Format<"uuid">,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardComment> {
    try {
      return await getDiscussionBoardPostsPostIdCommentsCommentId({
        postId,
        commentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
