import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IDiscussionBoardBanAppeal } from "../../../../api/structures/IDiscussionBoardBanAppeal";
import { postDiscussionBoardBansBanIdAppeals } from "../../../../providers/postDiscussionBoardBansBanIdAppeals";

@Controller("/discussionBoard/bans/:banId/appeals")
export class DiscussionboardBansAppealsController {
  /**
   * Submit an appeal against a ban decision to request reconsideration.
   *
   * This operation allows users who have been banned to formally appeal the decision by providing a reason for reconsideration. The appeal creates a structured workflow for administrators to review ban decisions and ensures transparency in moderation actions.
   *
   * When an appeal is submitted, it enters the 'pending' status and awaits administrator review. Users can only appeal active bans that reference their own user account. The appeal process supports the platform's commitment to fair moderation practices.
   *
   * Appeals are linked to specific ban records through the discussion_board_ban_record_id field and include detailed appeal reasons in the appeal_reason field. The system maintains a complete audit trail with timestamps for appealed_at, created_at, and updated_at fields.
   *
   * Related operations include viewing appeal status through GET operations, updating appeal decisions through administrative interfaces, and managing the appeal review workflow.
   *
   * @param connection
   * @param banId Unique identifier of the ban record being appealed
   * @param body Appeal submission details including the reason for appealing
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Create a new ban appeal record in the discussion_board_ban_appeals table.
   *
   * Validate that the ban record exists and is currently active.
   * Ensure the user is not already banned from submitting appeals.
   * Set initial appeal status to 'pending'.
   * Record appeal timestamp and user information.
   * Validate appeal reason meets minimum length requirements.
   * Return the complete appeal record with generated ID and timestamps.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @TypedParam("banId")
    banId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardBanAppeal.ICreate,
  ): Promise<IDiscussionBoardBanAppeal> {
    try {
      return await postDiscussionBoardBansBanIdAppeals({
        banId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
