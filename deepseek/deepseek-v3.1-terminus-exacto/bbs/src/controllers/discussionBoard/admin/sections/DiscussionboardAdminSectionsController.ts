import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IDiscussionBoardSection } from "../../../../api/structures/IDiscussionBoardSection";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { deleteDiscussionBoardAdminSectionsSectionId } from "../../../../providers/deleteDiscussionBoardAdminSectionsSectionId";
import { postDiscussionBoardAdminSections } from "../../../../providers/postDiscussionBoardAdminSections";
import { putDiscussionBoardAdminSectionsSectionId } from "../../../../providers/putDiscussionBoardAdminSectionsSectionId";

@Controller("/discussionBoard/admin/sections")
export class DiscussionboardAdminSectionsController {
  /**
   * Create a new discussion board section for organizing articles by topic.
   *
   * This operation allows administrators to create new sections that serve as organizational categories for the discussion board platform. Each section represents a distinct topic area such as Politics, Economy, or Current Affairs, providing users with structured content browsing.
   *
   * The operation validates that the requesting user has administrator privileges and ensures section name uniqueness across the platform (enforcing the @@unique([name]) database constraint). Upon successful creation, the section becomes immediately available for article posting and user browsing. The system automatically sets the section status to 'active' and records the creation timestamp and administrator identity for audit purposes.
   *
   * Required fields from the database schema include name, description, display_order, and created_by_admin_id. The operation validates these requirements before creating the section record.
   *
   * Related operations include PATCH /sections for listing sections, GET /sections/{sectionId} for retrieving specific section details, and PUT /sections/{sectionId} for updating section information.
   *
   * @param connection
   * @param body Section creation information including name, description, and display order
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Validate administrator permissions before allowing section creation. Check for unique section name constraint. Set default status as 'active' and generate UUID for id. Record creation timestamp and administrator identity. Return complete section entity with all fields populated.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IDiscussionBoardSection.ICreate,
  ): Promise<IDiscussionBoardSection> {
    try {
      return await postDiscussionBoardAdminSections({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing discussion board section with new information.
   *
   * This operation allows administrators to modify section properties including the section name, description, status, and display order. The section ID is specified in the URL path, and all updatable fields are provided in the request body.
   *
   * Administrators must have appropriate permissions to modify sections. The operation validates that the section name remains unique across all active sections (excluding the current section being updated). Section status changes are tracked for audit purposes.
   *
   * The database schema supports soft deletion through the deleted_at field. When a section status is changed to 'archived', the operation will mark it as soft-deleted rather than permanently removing it from the database.
   *
   * After successful update, the complete section entity is returned with the new values and updated timestamp. This operation supports the section management functionality required for maintaining the discussion board's organizational structure.
   *
   * Related operations include creating new sections (POST /sections), retrieving section details (GET /sections/{sectionId}), and listing all sections (PATCH /sections).
   *
   * @param connection
   * @param sectionId Unique identifier of the section to update
   * @param body Section update information including name, description, status, and display order
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Update an existing section by ID. Validate that the authenticated user has administrator privileges. Check if the section exists and is not deleted. Validate the request body fields: name must be unique (excluding current section), description must be non-empty, status must be one of 'active', 'inactive', 'archived', display_order must be positive integer. Update the section fields and set updated_at timestamp. Return the updated section entity.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":sectionId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("sectionId")
    sectionId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardSection.IUpdate,
  ): Promise<IDiscussionBoardSection> {
    try {
      return await putDiscussionBoardAdminSectionsSectionId({
        admin,
        sectionId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a discussion board section by performing a soft deletion operation.
   *
   * This operation allows administrators to remove sections from the discussion board platform while preserving historical data. The deletion is implemented as a soft delete, meaning the section record remains in the database with a deleted_at timestamp rather than being permanently removed. This approach maintains data integrity and allows for potential restoration if needed.
   *
   * Only users with administrator privileges can perform this operation. The system validates that the section exists and has not already been deleted before proceeding with the deletion. After successful deletion, the section will no longer appear in section lists or be available for new article creation, but existing articles within the section may be handled according to platform configuration (either preserved with section reference or reassigned to a default section).
   *
   * The response includes the complete section information at the time of deletion, providing confirmation of the operation's success and a record of the deleted section's state. This information can be used for audit purposes or potential restoration workflows.
   *
   * Related operations include creating sections (POST /sections), updating sections (PUT /sections/{sectionId}), and browsing sections (PATCH /sections). Administrators should also have access to view deleted sections through specialized administrative interfaces if restoration capabilities are implemented.
   *
   * @param connection
   * @param sectionId Unique identifier of the section to be deleted
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Perform soft deletion of a discussion board section by setting the deleted_at timestamp. First verify that the requesting user has administrator privileges. Check if the section exists and is not already deleted. Update the deleted_at field with the current timestamp and return the deleted section information. Ensure referential integrity by handling any dependent articles or comments according to business rules (either cascade delete or reassign to default section).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":sectionId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("sectionId")
    sectionId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardSection> {
    try {
      return await deleteDiscussionBoardAdminSectionsSectionId({
        admin,
        sectionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
