import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IDiscussionBoardBanAppeal } from "../../../../api/structures/IDiscussionBoardBanAppeal";
import { IPageIDiscussionBoardBanAppeal } from "../../../../api/structures/IPageIDiscussionBoardBanAppeal";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { patchDiscussionBoardAdminAppeals } from "../../../../providers/patchDiscussionBoardAdminAppeals";
import { postDiscussionBoardAdminAppealsAppealIdReview } from "../../../../providers/postDiscussionBoardAdminAppealsAppealIdReview";

@Controller("/discussionBoard/admin/appeals")
export class DiscussionboardAdminAppealsController {
  /**
   * Search and filter ban appeal records with advanced criteria for administrator review workflows.
   *
   * This operation provides comprehensive search capabilities for ban appeals, allowing administrators to filter by appeal status (pending, under_review, approved, rejected), date ranges for appeal submission and review, ban reason content matching, and user-specific appeals. The response includes paginated results with appeal summaries containing essential information for review decisions.
   *
   * Administrators can use this endpoint to manage the appeal workflow, prioritize pending appeals, track review statuses, and maintain transparency in moderation actions. The search functionality supports both broad overviews of all appeals and targeted searches for specific cases requiring attention.
   *
   * The operation respects the soft delete capability of the discussion_board_ban_appeals table, filtering out soft-deleted records while maintaining comprehensive appeal history for audit purposes.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for ban appeal filtering
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query discussion_board_ban_appeals table with advanced filtering capabilities including status filtering, date range searches, and appeal reason text matching. Join with discussion_board_ban_records to filter by ban reason content and discussion_board_users for user information. Implement pagination with configurable page sizes and sorting options. Apply GIN index optimizations for text search on appeal_reason and decision_reason fields. Return comprehensive appeal summary information for administrator review workflows.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IDiscussionBoardBanAppeal.IRequest,
  ): Promise<IPageIDiscussionBoardBanAppeal.ISummary> {
    try {
      return await patchDiscussionBoardAdminAppeals({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Submit a review decision for a ban appeal.
   *
   * This operation allows administrators to review user appeals against ban decisions recorded in the `discussion_board_ban_appeals` table. Administrators can approve appeals to overturn bans or reject appeals to uphold bans, providing detailed reasons for their decisions in the `decision_reason` field.
   *
   * The review process requires careful consideration of the ban circumstances and the user's appeal reason stored in the `appeal_reason` field. Approved appeals result in the ban being overturned by updating the appeal `status` to 'approved', while rejected appeals maintain the ban status by setting the `status` to 'rejected'. All review decisions are permanently recorded with the `discussion_board_admin_id`, `decision_reason`, and `reviewed_at` timestamp for audit purposes.
   *
   * Administrators must have appropriate moderation privileges to perform appeal reviews. The system validates that appeals are in a reviewable status ('pending' or 'under_review') and that the reviewing administrator has the necessary permissions. The operation updates the `discussion_board_ban_appeals` record with the review decision and related metadata.
   *
   * The response includes the complete updated appeal record from the `discussion_board_ban_appeals` table with review details, ban information via the `banRecord` relation, and related user data via the `user` relation for comprehensive audit trail maintenance.
   *
   * @param connection
   * @param appealId Unique identifier of the ban appeal to review
   * @param body Review decision details including status and reason
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Update the ban appeal record with the administrator's review decision. Validate that the appeal exists and is in a reviewable status (pending or under_review). Check that the reviewing administrator has appropriate permissions. Update the appeal status, decision reason, reviewer ID, and review timestamp. Ensure the decision reason meets minimum length requirements if provided. Return the complete updated appeal record including all related ban information.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post(":appealId/review")
  public async review(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("appealId")
    appealId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardBanAppeal.IReview,
  ): Promise<IDiscussionBoardBanAppeal> {
    try {
      return await postDiscussionBoardAdminAppealsAppealIdReview({
        admin,
        appealId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
