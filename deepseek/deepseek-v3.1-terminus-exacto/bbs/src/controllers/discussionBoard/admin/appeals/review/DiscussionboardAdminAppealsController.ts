import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IDiscussionBoardBanAppeal } from "../../../../../api/structures/IDiscussionBoardBanAppeal";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { patchDiscussionBoardAdminBanIdAppealsAppealIdReview } from "../../../../../providers/patchDiscussionBoardAdminBanIdAppealsAppealIdReview";

@Controller("/discussionBoard/admin/:banId/appeals/:appealId/review")
export class DiscussionboardAdminAppealsController {
  /**
   * Review a ban appeal by updating its status and providing a decision reason.
   *
   * This operation allows administrators to process ban appeals submitted by users. The appeal review workflow involves evaluating the user's appeal reason against the original ban decision and making a determination to either approve (overturn the ban) or reject (uphold the ban) the appeal. The operation references the discussion_board_ban_appeals table structure including the status workflow, decision_reason field, and soft deletion tracking via deleted_at.
   *
   * Administrators must have appropriate moderation privileges to perform this action. The appeal must be in a reviewable state (pending or under_review status with deleted_at null) to be eligible for review. Once reviewed, the appeal status becomes final and cannot be changed again, though the record may be soft deleted if needed.
   *
   * The operation validates that the specified ban record and appeal exist and are properly linked. It ensures the reviewing administrator is authorized and records the decision timestamp for audit trail purposes. The appeal workflow supports status transitions between pending, under_review, approved, and rejected states as defined in the database schema.
   *
   * Related operations include viewing ban appeals lists and accessing individual ban records for context during the review process.
   *
   * @param connection
   * @param banId UUID of the ban record containing the appeal
   * @param appealId UUID of the specific appeal being reviewed
   * @param body Review decision details including new status and decision reason
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Update the ban appeal record with review decision. Validate that the appeal exists and belongs to the specified ban record. Check that the administrator has permission to review appeals. Update the status field to the new value and set the decision_reason if provided. Set the reviewed_at timestamp to current time and link the reviewing administrator. Ensure the appeal is in a reviewable state (not already reviewed). Return the updated appeal record with all current field values.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async review(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("banId")
    banId: string & tags.Format<"uuid">,
    @TypedParam("appealId")
    appealId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardBanAppeal.IUpdate,
  ): Promise<IDiscussionBoardBanAppeal> {
    try {
      return await patchDiscussionBoardAdminBanIdAppealsAppealIdReview({
        admin,
        banId,
        appealId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
