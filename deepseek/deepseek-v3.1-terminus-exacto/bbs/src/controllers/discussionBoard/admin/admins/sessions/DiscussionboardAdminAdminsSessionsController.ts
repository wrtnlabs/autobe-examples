import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IDiscussionBoardAdminSession } from "../../../../../api/structures/IDiscussionBoardAdminSession";
import { IPageIDiscussionBoardAdminSession } from "../../../../../api/structures/IPageIDiscussionBoardAdminSession";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getDiscussionBoardAdminAdminsSessionsSessionId } from "../../../../../providers/getDiscussionBoardAdminAdminsSessionsSessionId";
import { patchDiscussionBoardAdminAdminsSessions } from "../../../../../providers/patchDiscussionBoardAdminAdminsSessions";

@Controller("/discussionBoard/admin/admins/sessions")
export class DiscussionboardAdminAdminsSessionsController {
  /**
   * Search and retrieve a paginated list of administrator sessions with comprehensive filtering options.
   *
   * This operation provides administrators with the ability to monitor and audit session activity across the platform. Super administrators can view sessions for all administrators, while regular administrators are limited to viewing their own sessions only. The search functionality supports filtering by administrator ID, session status (active vs expired based on expired_at timestamp), IP address patterns, user agent information, and temporal ranges for security auditing purposes.
   *
   * Sessions include detailed connection metadata such as IP address, user agent, and referrer information for security monitoring. The response provides session summaries optimized for administrative review and security auditing workflows. This operation is essential for maintaining platform security and monitoring administrator access patterns.
   *
   * Related operations include individual session retrieval (GET /admins/sessions/{sessionId}) for detailed inspection and session termination (DELETE /admins/sessions/{sessionId}) for security management.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for administrator sessions
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query discussion_board_admin_sessions table with advanced filtering capabilities. Support filtering by administrator ID, session status (active vs expired based on expired_at), IP address patterns, creation date ranges, and last access time. Join with discussion_board_admins table to include administrator information in summaries. Implement cursor-based pagination for efficient large result sets. Validate that only super administrators can access sessions across all administrators, while regular administrators can only access their own sessions.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IDiscussionBoardAdminSession.IRequest,
  ): Promise<IPageIDiscussionBoardAdminSession.ISummary> {
    try {
      return await patchDiscussionBoardAdminAdminsSessions({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific administrator session for security auditing and monitoring purposes.
   *
   * This operation provides comprehensive session metadata including authentication tokens, connection context (IP address, user agent, referrer), and timing information (creation, expiration, last access). Session data is essential for security monitoring, auditing administrator access patterns, and troubleshooting authentication issues.
   *
   * Only authorized administrators with appropriate permissions should be able to access session information. The operation supports security auditing workflows by providing detailed visibility into active and historical administrator sessions across the platform.
   *
   * @param connection
   * @param sessionId Unique identifier of the administrator session to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query the discussion_board_admin_sessions table by the provided sessionId parameter to retrieve the complete session record. Include all fields from the table including access_token, refresh_token, ip, user_agent, referrer, created_at, expired_at, and last_accessed_at. Validate that the sessionId exists in the database and return appropriate error responses for invalid or expired sessions. Ensure proper authorization checks to prevent unauthorized access to session information.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardAdminSession> {
    try {
      return await getDiscussionBoardAdminAdminsSessionsSessionId({
        admin,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
