import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IDiscussionBoardAttachmentDownload } from "../../../../../api/structures/IDiscussionBoardAttachmentDownload";
import { IPageIDiscussionBoardAttachmentDownload } from "../../../../../api/structures/IPageIDiscussionBoardAttachmentDownload";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { patchDiscussionBoardAdminAnalyticsDownloads } from "../../../../../providers/patchDiscussionBoardAdminAnalyticsDownloads";

@Controller("/discussionBoard/admin/analytics/downloads")
export class DiscussionboardAdminAnalyticsDownloadsController {
  /**
   * Retrieve filtered and paginated analytics data for attachment downloads across the discussion board platform.
   *
   * This operation provides comprehensive download analytics for administrative oversight, allowing administrators to analyze download patterns, track file access trends, and monitor system usage. The analytics include detailed information about who downloaded what files, when downloads occurred, and from which locations.
   *
   * Administrators can filter results by date ranges, actor types (guest, member, admin, super_admin), attachment file types, IP address patterns, and specific articles or sections. The response includes both individual download records and aggregated statistics for trend analysis.
   *
   * Security considerations require that only authenticated administrators can access this sensitive download data. The operation enforces proper access controls to prevent unauthorized viewing of download analytics.
   *
   * Related operations include viewing individual attachment details and accessing article-level download statistics for more granular analysis of file access patterns.
   *
   * @param connection
   * @param body Search criteria and filtering parameters for download analytics
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query the discussion_board_attachment_downloads table with complex filtering capabilities for download analytics. Join with subtype tables (discussion_board_attachment_download_members, discussion_board_attachment_download_admins, etc.) to resolve actor identities based on actor_type field. Apply date range filters, actor type filters, attachment type filters, and IP address pattern matching. Support pagination with configurable page sizes and sorting options. Return aggregated statistics alongside individual download records for comprehensive analytics. Validate that the requesting user has administrator privileges before returning sensitive download data.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IDiscussionBoardAttachmentDownload.IRequest,
  ): Promise<IPageIDiscussionBoardAttachmentDownload.ISummary> {
    try {
      return await patchDiscussionBoardAdminAnalyticsDownloads({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
