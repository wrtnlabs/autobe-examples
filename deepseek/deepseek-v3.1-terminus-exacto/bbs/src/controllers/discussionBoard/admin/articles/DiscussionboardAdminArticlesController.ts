import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IDiscussionBoardArticle } from "../../../../api/structures/IDiscussionBoardArticle";
import { IPageIDiscussionBoardArticle } from "../../../../api/structures/IPageIDiscussionBoardArticle";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { deleteDiscussionBoardAdminArticlesArticleId } from "../../../../providers/deleteDiscussionBoardAdminArticlesArticleId";
import { patchDiscussionBoardAdminArticles } from "../../../../providers/patchDiscussionBoardAdminArticles";

@Controller("/discussionBoard/admin/articles")
export class DiscussionboardAdminArticlesController {
  /**
   * Search and retrieve a paginated list of articles with advanced filtering capabilities.
   *
   * This operation provides comprehensive search functionality for articles across the discussion board platform. It supports full-text search on article titles and content, allowing users to find relevant discussions based on keywords and phrases. The search leverages PostgreSQL's trigram indexing for efficient partial matching and relevance ranking.
   *
   * Users can filter results by specific sections to focus on particular topics like Politics, Economy, or Current Affairs. Additional filtering options include author selection, publication status (draft, published, archived), and creation date ranges. The tag filtering system enables users to find articles with specific categorization labels that authors have assigned.
   *
   * The response provides article summaries optimized for list displays, including essential information like title, author details, creation timestamp, and tag information. Pagination ensures efficient loading of large result sets with configurable page sizes. Sorting options allow users to prioritize newest content or explore historical discussions.
   *
   * This operation integrates with the discussion_board_articles table structure and respects the platform's content organization principles. It supports the business requirement for effective content discovery while maintaining performance standards for large-scale article databases.
   *
   * @param connection
   * @param body Search criteria and filtering parameters for article retrieval
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query the discussion_board_articles table with complex filtering and search capabilities. Implement full-text search on title and content fields using PostgreSQL's trigram indexes. Support filtering by section ID, author ID, status, creation date ranges, and tags. Join with related tables to include author information and tag counts. Apply pagination with cursor-based or offset-based approach. Sort results by creation date (newest/oldest first) as specified in requirements. Validate that all filter parameters correspond to actual database fields.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IDiscussionBoardArticle.IRequest,
  ): Promise<IPageIDiscussionBoardArticle.ISummary> {
    try {
      return await patchDiscussionBoardAdminArticles({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Perform soft deletion of a specific article from the discussion board platform.
   *
   * This operation marks an article as deleted by setting the deleted_at field to the current timestamp, implementing a soft deletion approach that preserves the article record for audit and recovery purposes. The deletion process cascades to related entities including comments, file attachments, image attachments, tags, and favorite associations, which are similarly soft-deleted.
   *
   * Authorization is required for this operation. Regular users can only delete their own articles, while administrators can delete any article regardless of ownership. The system validates article existence and user permissions before proceeding with deletion.
   *
   * After successful soft deletion, the complete article details are returned in the response, confirming the deletion while maintaining the record relationship integrity. The response includes the article ID, title, content, section information, author details, and timestamps for comprehensive audit trail.
   *
   * Related operations include GET /articles/{articleId} for retrieving article details before deletion and PATCH /articles for searching articles that might need deletion. Administrators should use this operation responsibly as it affects user content visibility while preserving discussion integrity.
   *
   * Note: This operation performs soft deletion, not permanent removal of data from the database. The deleted_at timestamp facilitates potential recovery and maintains referential integrity across the platform.
   *
   * @param connection
   * @param articleId Unique identifier of the article to delete
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Implement soft deletion by setting the deleted_at field to current timestamp. Validate that the requesting user either owns the article or has administrator privileges. Cascade deletion to related entities: set deleted_at for comments, files, and tags; remove article favorites. Return the deleted article details for confirmation. Handle authorization checks and return appropriate error responses for unauthorized access or non-existent articles.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":articleId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardArticle> {
    try {
      return await deleteDiscussionBoardAdminArticlesArticleId({
        admin,
        articleId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
