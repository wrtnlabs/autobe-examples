import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IDiscussionBoardAttachment } from "../../../../../api/structures/IDiscussionBoardAttachment";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { deleteDiscussionBoardAdminArticlesArticleIdAttachmentsAttachmentId } from "../../../../../providers/deleteDiscussionBoardAdminArticlesArticleIdAttachmentsAttachmentId";
import { postDiscussionBoardAdminArticlesArticleIdAttachments } from "../../../../../providers/postDiscussionBoardAdminArticlesArticleIdAttachments";
import { putDiscussionBoardAdminArticlesArticleIdAttachmentsAttachmentId } from "../../../../../providers/putDiscussionBoardAdminArticlesArticleIdAttachmentsAttachmentId";

@Controller("/discussionBoard/admin/articles/:articleId/attachments")
export class DiscussionboardAdminArticlesAttachmentsController {
  /**
   * Create new file attachments for an existing article.
   *
   * This operation allows authorized users to upload and attach files to articles they have permission to edit. Each attachment includes metadata such as filename, file type, MIME type, and file size. The system validates all attachments against configured limits and file type restrictions before creating the database records.
   *
   * Only article authors and administrators with edit permissions can add attachments to articles. The operation supports multiple file uploads in a single request, with individual validation for each attachment. Failed uploads for one file do not affect other valid attachments in the same request.
   *
   * After successful creation, the attachment records are immediately available for download and display within the article. The response includes the complete attachment metadata with system-generated IDs and timestamps for reference.
   *
   * @param connection
   * @param articleId Unique identifier of the target article
   * @param body Attachment creation data including file metadata
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Validate that the target article exists and the authenticated user has edit permissions (either as article owner or administrator). For each attachment in the request, validate file metadata including filename, filetype, mime_type, and size_bytes against system limits. Generate unique storage paths for each file. Create attachment records in the database with the provided metadata and link them to the parent article. Handle concurrent attachment uploads for the same article with proper transaction management. Return the created attachment records with their assigned IDs and timestamps.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardAttachment.ICreate,
  ): Promise<IDiscussionBoardAttachment> {
    try {
      return await postDiscussionBoardAdminArticlesArticleIdAttachments({
        admin,
        articleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update the metadata of a specific file attachment associated with an article.
   *
   * This operation allows article authors and administrators to modify attachment information such as the display filename, file type classification, and MIME type. The operation preserves system-managed fields including storage location and file size while updating user-facing metadata.
   *
   * Authorization requires that the user either owns the parent article or has administrative privileges. The operation validates that the attachment exists and belongs to the specified article before proceeding with the update. Filename uniqueness is enforced per article to prevent conflicts.
   *
   * After successful update, the modified attachment metadata is returned with updated timestamps reflecting the modification time. The actual file content remains unchanged - this operation only affects metadata fields that control how the attachment is presented to users.
   *
   * @param connection
   * @param articleId Identifier of the parent article that contains the attachment
   * @param attachmentId Identifier of the specific attachment to update
   * @param body Attachment metadata update information
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Update attachment metadata for a specific attachment belonging to an article. Verify that both the article and attachment exist and that the attachment belongs to the specified article. Validate that the user has edit permissions for the article (either as the article author or as an administrator). Update only the allowed fields: filename, filetype, mime_type. Preserve the storage_path and size_bytes as these are system-managed. Return the updated attachment metadata with current timestamps. Handle validation errors for filename uniqueness within the article and proper MIME type formatting.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":attachmentId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedParam("attachmentId")
    attachmentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardAttachment.IUpdate,
  ): Promise<IDiscussionBoardAttachment> {
    try {
      return await putDiscussionBoardAdminArticlesArticleIdAttachmentsAttachmentId(
        {
          admin,
          articleId,
          attachmentId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently removes a specific file attachment from an article.
   *
   * This operation deletes both the physical file from storage and the attachment metadata record from the database. Only the article author or administrators with appropriate privileges can perform this operation. The deletion is irreversible and removes all traces of the attachment from the system.
   *
   * When an attachment is deleted, the file is immediately removed from storage and the attachment record is marked as deleted. This operation follows the cascade deletion pattern defined in the database schema where attachments are dependent on their parent articles. Users should exercise caution when deleting attachments as this action cannot be undone.
   *
   * The operation requires valid article and attachment identifiers and proper authorization. If the user lacks permission or the resources cannot be found, appropriate error responses will be returned. Administrators can delete attachments from any article regardless of ownership, while regular users can only delete attachments from articles they authored.
   *
   * @param connection
   * @param articleId Unique identifier of the parent article containing the attachment
   * @param attachmentId Unique identifier of the specific attachment to be deleted
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Verify the requesting user has permission to delete the attachment (must be article author or administrator). Check that both the article and attachment exist and are accessible. Perform the deletion in a transaction: first delete the physical file from storage using the storage_path, then delete the attachment metadata record from discussion_board_attachments table. Handle errors for missing files, storage failures, and permission violations. Log the deletion action for audit purposes if performed by an administrator.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":attachmentId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedParam("attachmentId")
    attachmentId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteDiscussionBoardAdminArticlesArticleIdAttachmentsAttachmentId(
        {
          admin,
          articleId,
          attachmentId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
