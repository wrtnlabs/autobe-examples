import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IDiscussionBoardCommentActivityMetadatum } from "../../../../../../../api/structures/IDiscussionBoardCommentActivityMetadatum";
import { IPageIDiscussionBoardCommentActivityMetadatum } from "../../../../../../../api/structures/IPageIDiscussionBoardCommentActivityMetadatum";
import { AdminAuth } from "../../../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../../../decorators/payload/AdminPayload";
