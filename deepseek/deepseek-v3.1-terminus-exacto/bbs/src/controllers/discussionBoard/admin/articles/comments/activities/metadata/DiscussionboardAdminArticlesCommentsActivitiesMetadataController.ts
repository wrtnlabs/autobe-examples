@Controller(
  "/discussionBoard/admin/articles/:articleId/comments/:commentId/activities/:activityId/metadata",
)
export class DiscussionboardAdminArticlesCommentsActivitiesMetadataController {
  /**
   * Search and retrieve metadata entries associated with a specific comment activity for audit trail purposes.
   *
   * This operation provides access to the detailed audit trail metadata stored for comment activities in the discussion_board_comment_activity_metadata table. The metadata is stored as key-value pairs that maintain First Normal Form compliance, enabling structured querying of audit information that would otherwise be stored as unstructured JSON.
   *
   * Users can filter metadata entries by key identifiers (such as 'old_content', 'changed_fields', 'deletion_reason', 'moderation_details'), value patterns, and creation date ranges. The operation returns paginated results to handle large audit trails efficiently. Each metadata entry provides context about specific actions taken on comments, such as old content before edits, changed fields, deletion reasons, or moderation details.
   *
   * Access to this operation requires proper authorization to view the underlying article, comment, and activity. The hierarchical validation ensures that users can only access metadata for activities they have permission to view. The operation validates that the activity belongs to the specified comment, and the comment belongs to the specified article before returning any metadata.
   *
   * @param connection
   * @param articleId UUID of the parent article
   * @param commentId UUID of the parent comment
   * @param activityId UUID of the parent comment activity
   * @param body Search criteria for filtering metadata entries
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Validate the hierarchical relationship: check that the activity belongs to the comment, and the comment belongs to the article. Query the discussion_board_comment_activity_metadata table filtered by discussion_board_comment_activity_id equal to the activityId parameter. Apply search filters from the request body on key, value, and creation date range. Implement pagination with configurable page sizes. Return metadata entries sorted by creation timestamp descending for reverse chronological audit trail viewing. Handle cases where the activity has no metadata entries by returning empty paginated results.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
    @TypedParam("activityId")
    activityId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardCommentActivityMetadatum.IRequest,
  ): Promise<IPageIDiscussionBoardCommentActivityMetadatum> {
    try {
      return await patchDiscussionBoardAdminArticlesArticleIdCommentsCommentIdActivitiesActivityIdMetadata(
        {
          admin,
          articleId,
          commentId,
          activityId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve specific metadata record for a comment activity audit trail.
   *
   * This operation provides access to detailed audit metadata associated with comment activities such as edits, deletions, or moderation actions. The metadata contains key-value pairs that store structured information about the activity, including old content before edits, specific fields changed, deletion reasons, or moderation details.
   *
   * Each metadata record is uniquely identified within the context of its parent activity. The operation validates the activity exists and belongs to the authenticated administrator's scope before returning the metadata to ensure data integrity.
   *
   * This endpoint is primarily used for administrative auditing and debugging purposes, providing detailed insight into comment lifecycle management and user actions within the discussion platform. Access requires administrator privileges and proper authorization validation.
   *
   * Security considerations: Only authenticated administrators with appropriate privileges can access audit metadata. The system validates both the activity existence and the administrator's authorization level before returning sensitive audit information.
   *
   * @param connection
   * @param articleId Target article's unique identifier
   * @param commentId Target comment's unique identifier within the article
   * @param activityId Comment activity's unique identifier
   * @param metadataId Metadata record's unique identifier
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query the discussion_board_comment_activity_metadata table by metadata ID while verifying the activity belongs to the specified comment, which belongs to the specified article. Validate all relationships exist before returning metadata. Ensure the metadata record belongs to the correct activity chain. Return 404 if any relationship in the chain is broken.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":metadataId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
    @TypedParam("activityId")
    activityId: string & tags.Format<"uuid">,
    @TypedParam("metadataId")
    metadataId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardCommentActivityMetadatum> {
    try {
      return await getDiscussionBoardAdminArticlesArticleIdCommentsCommentIdActivitiesActivityIdMetadataMetadataId(
        {
          admin,
          articleId,
          commentId,
          activityId,
          metadataId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
