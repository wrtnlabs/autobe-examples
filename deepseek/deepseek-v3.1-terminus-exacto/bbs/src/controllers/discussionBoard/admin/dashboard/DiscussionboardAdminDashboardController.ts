import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IDiscussionBoardSystemConfiguration } from "../../../../api/structures/IDiscussionBoardSystemConfiguration";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getDiscussionBoardAdminDashboard } from "../../../../providers/getDiscussionBoardAdminDashboard";

@Controller("/discussionBoard/admin/dashboard")
export class DiscussionboardAdminDashboardController {
  /**
   * Retrieve comprehensive system dashboard overview with aggregated statistics and performance metrics.
   *
   * This operation provides administrators with a high-level view of the discussion board platform's health and activity. The dashboard includes user engagement metrics, content statistics, section analytics, and system performance indicators.
   *
   * The response includes total user counts, article creation rates, comment activity levels, and section engagement metrics. Administrators can use this data to monitor platform growth, identify popular content areas, and track moderation activity.
   *
   * Security considerations: This operation should be restricted to administrators and super administrators only, as it contains sensitive system statistics and user activity data.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query multiple database tables to aggregate dashboard statistics:
   * - Count total users from discussion_board_users
   * - Count total articles from discussion_board_articles
   * - Count total comments from discussion_board_comments
   * - Get section statistics from discussion_board_section_statistics
   * - Get recent system activities from discussion_board_system_activities
   * - Get moderation statistics from discussion_board_moderation_logs
   * - Get article view statistics from discussion_board_article_view_stats
   *
   * Aggregate the data into a comprehensive dashboard response with performance metrics, content statistics, and system health indicators.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @AdminAuth()
    admin: AdminPayload,
  ): Promise<IDiscussionBoardSystemConfiguration> {
    try {
      return await getDiscussionBoardAdminDashboard({
        admin,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
