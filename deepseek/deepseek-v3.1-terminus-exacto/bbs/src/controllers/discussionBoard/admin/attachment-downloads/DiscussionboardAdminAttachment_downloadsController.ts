import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IDiscussionBoardAttachmentDownload } from "../../../../api/structures/IDiscussionBoardAttachmentDownload";
import { IPageIDiscussionBoardAttachmentDownload } from "../../../../api/structures/IPageIDiscussionBoardAttachmentDownload";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getDiscussionBoardAdminAttachmentDownloadsDownloadId } from "../../../../providers/getDiscussionBoardAdminAttachmentDownloadsDownloadId";
import { patchDiscussionBoardAdminAttachmentDownloads } from "../../../../providers/patchDiscussionBoardAdminAttachmentDownloads";

@Controller("/discussionBoard/admin/attachment-downloads")
export class DiscussionboardAdminAttachment_downloadsController {
  /**
   * Search and retrieve attachment download records with comprehensive filtering capabilities.
   *
   * This operation provides administrative access to file download analytics and audit trails. Administrators can filter downloads by specific attachments, actor types (guest, member, admin, super_admin), date ranges, IP addresses, and user agent patterns. The response includes paginated results with download metadata suitable for security monitoring and usage analytics.
   *
   * Security considerations require administrator privileges to access download records due to privacy implications. The operation excludes soft-deleted download records and provides comprehensive filtering to support various administrative use cases including security investigations, usage analytics, and compliance reporting.
   *
   * @param connection
   * @param body Search criteria for filtering attachment download records
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query discussion_board_attachment_downloads table with filtering capabilities including attachment ID, actor type, date ranges, IP address patterns, and user agent filtering. Apply soft delete filtering to exclude deleted records. Join with discussion_board_attachments for attachment metadata. Support pagination with cursor-based or offset-based approaches. Return download summary information optimized for administrative review.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IDiscussionBoardAttachmentDownload.IRequest,
  ): Promise<IPageIDiscussionBoardAttachmentDownload.ISummary> {
    try {
      return await patchDiscussionBoardAdminAttachmentDownloads({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific attachment download event.
   *
   * This operation returns comprehensive metadata for a single file download activity, including who performed the download, when it occurred, and technical details about the request. The response includes the original filename, file type, and download statistics for the associated attachment.
   *
   * Download records are tracked for audit and analytics purposes, providing visibility into file access patterns across the platform. The response structure varies based on the actor type (guest, member, admin, or super admin) to provide appropriate context for each download event.
   *
   * This endpoint is primarily used by administrators for security monitoring, usage analytics, and understanding content popularity trends. Each download record provides a permanent audit trail of file access activities within the discussion board system.
   *
   * Access to this operation is restricted to administrators only, ensuring proper security controls for sensitive download activity data.
   *
   * @param connection
   * @param downloadId Unique identifier of the download record to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Retrieve a specific attachment download record by its UUID identifier.
   *
   * Query the discussion_board_attachment_downloads table using the provided downloadId. Include the associated attachment information via the belongs-to relation. Based on the actor_type field, join with the appropriate subtype table (discussion_board_attachment_download_admins, discussion_board_attachment_download_members, etc.) to retrieve actor-specific details.
   *
   * Return 404 error if the download record does not exist or has been soft-deleted. Validate that the downloadId is a valid UUID format before querying the database. Include all download metadata such as IP address, user agent, referrer, and timestamps in the response.
   *
   * For security and privacy, ensure proper access controls are in place - users should only be able to view download records they have permission to access (typically administrators for audit purposes).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":downloadId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("downloadId")
    downloadId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardAttachmentDownload.IAttachment> {
    try {
      return await getDiscussionBoardAdminAttachmentDownloadsDownloadId({
        admin,
        downloadId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
