import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IDiscussionBoardContentModerationQueueAssignment } from "../../../../api/structures/IDiscussionBoardContentModerationQueueAssignment";
import { IDiscussionBoardContentModerationQueueEscalation } from "../../../../api/structures/IDiscussionBoardContentModerationQueueEscalation";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getDiscussionBoardAdminQueuesAnalytics } from "../../../../providers/getDiscussionBoardAdminQueuesAnalytics";
import { postDiscussionBoardAdminQueuesQueueIdEscalate } from "../../../../providers/postDiscussionBoardAdminQueuesQueueIdEscalate";

@Controller("/discussionBoard/admin/queues")
export class DiscussionboardAdminQueuesController {
  /**
   * Retrieve comprehensive analytics and performance metrics for the content moderation queue system.
   *
   * This operation provides administrators with detailed insights into moderation workflow efficiency, queue processing statistics, and administrator performance metrics. The analytics include queue size breakdown by moderation status (pending, under_review, resolved, dismissed), average processing times (measured from assignment to completion), assignment distribution across administrators, escalation frequency analysis, and priority level distribution (low, medium, high, critical).
   *
   * The data is sourced from the content moderation queues, queue assignment history, and escalation records to provide a complete picture of moderation system performance. Administrators can use this information to identify bottlenecks, optimize workflow assignments, and monitor overall system health.
   *
   * Response includes both quantitative metrics and calculated efficiency indicators that support data-driven decision making for moderation team management and resource allocation. This read-only operation respects the system-generated nature of moderation audit data.
   *
   * Usage requires administrator privileges and provides aggregated statistics suitable for dashboard displays and performance monitoring tools.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query multiple tables to aggregate moderation queue analytics data. Calculate queue statistics by moderation status (pending, under_review, resolved, dismissed) with counts and percentages. Compute average processing times by measuring time from assignment to completion. Analyze assignment efficiency with administrator workload distribution metrics. Track escalation patterns including escalation frequency and reasons. Return all analytics data in a comprehensive structured response optimized for dashboard visualization.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get("analytics")
  public async analytics(
    @AdminAuth()
    admin: AdminPayload,
  ): Promise<IDiscussionBoardContentModerationQueueAssignment> {
    try {
      return await getDiscussionBoardAdminQueuesAnalytics({
        admin,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Escalate a content moderation queue entry to higher priority or reassign to different administrators.
   *
   * This operation allows administrators to escalate moderation tasks that require urgent attention, specialized handling, or reassignment to different administrators. The escalation process creates a comprehensive audit trail documenting priority changes, assignment transfers, and workflow state transitions.
   *
   * Administrators can escalate queue entries for various reasons including urgent content requiring immediate review, content requiring specialized expertise, or workload redistribution among moderation team members. Each escalation includes detailed reason documentation for transparency and accountability.
   *
   * The escalation system supports priority level adjustments from low to medium, high, or critical priority, as well as reassignment transfers between administrators with different expertise levels. All escalation actions are tracked for workflow analysis and performance monitoring.
   *
   * Security considerations require that only authenticated administrators with appropriate permissions can perform escalation actions. The operation validates that the requesting administrator has authority to escalate the specific queue entry based on their role and assignment status.
   *
   * @param connection
   * @param queueId Unique identifier of the moderation queue entry to escalate
   * @param body Escalation details including type, priority changes, assignment changes, and reason
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Create a new escalation record for a content moderation queue entry. Validate that the queue entry exists and is in a modifiable state. Check administrator permissions for escalation actions. Update the parent queue entry's priority and assignment status based on escalation parameters. Create the escalation audit trail record with all relevant details including previous and new states.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post(":queueId/escalate")
  public async escalate(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("queueId")
    queueId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardContentModerationQueueEscalation.ICreate,
  ): Promise<IDiscussionBoardContentModerationQueueEscalation> {
    try {
      return await postDiscussionBoardAdminQueuesQueueIdEscalate({
        admin,
        queueId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
