import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IDiscussionBoardComment } from "../../../../api/structures/IDiscussionBoardComment";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { deleteDiscussionBoardAdminCommentsCommentId } from "../../../../providers/deleteDiscussionBoardAdminCommentsCommentId";
import { putDiscussionBoardAdminCommentsCommentId } from "../../../../providers/putDiscussionBoardAdminCommentsCommentId";

@Controller("/discussionBoard/admin/comments/:commentId")
export class DiscussionboardAdminCommentsController {
  /**
   * Update the content of an existing comment.
   *
   * This operation allows authenticated users to modify their own comments by providing new content. The system maintains an audit trail of all edits through the comment edit history system, ensuring transparency and compliance with content modification policies.
   *
   * When a comment is updated, the system automatically creates an edit history record that captures both the original content and the edited version. This supports the platform's requirement for users to be able to edit their own comments while maintaining accountability through edit tracking.
   *
   * The operation validates that the requesting user owns the comment being modified and that the new content meets platform requirements (1-1000 characters). If the comment has been deleted or does not exist, appropriate error responses are returned.
   *
   * Related operations include viewing comment edit history through the comment edit history endpoints and deleting comments through the DELETE /comments/{commentId} operation.
   *
   * @param connection
   * @param commentId Unique identifier of the comment to update
   * @param body New content for the comment
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Update an existing comment by replacing its content with the provided value.
   *
   * First validate that the authenticated user owns the comment being updated. Check that the comment exists and is not deleted.
   *
   * Validate the new content meets requirements (1-1000 characters). Create an edit history record before updating the comment content to track the change.
   *
   * Update the comment's content field and set updated_at timestamp. Return the complete updated comment with author and article information.
   *
   * Handle authorization: only the comment author can update their own comments. Administrators cannot edit comments on behalf of users.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardComment.IUpdate,
  ): Promise<IDiscussionBoardComment> {
    try {
      return await putDiscussionBoardAdminCommentsCommentId({
        admin,
        commentId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a specific comment from the discussion board.
   *
   * This operation permanently removes a comment from the platform. When a user calls this endpoint, the system performs a soft delete by setting the deleted_at timestamp on the comment record. This preserves the comment data for audit purposes while removing it from public view.
   *
   * Users can only delete their own comments, while administrators have permission to delete any comment on the platform. The operation validates that the requesting user has appropriate permissions before proceeding with the deletion.
   *
   * After successful deletion, the complete comment information is returned in the response body, allowing the client to confirm the deletion and potentially display a confirmation message to the user. The response includes all comment details including content, author information, timestamps, and the deletion timestamp.
   *
   * This operation integrates with the comment moderation system, ensuring that deletion actions are properly logged for administrative review and compliance purposes. Related entities such as comment edit histories and moderation records remain accessible for audit trails even after the comment is marked as deleted.
   *
   * @param connection
   * @param commentId UUID identifier of the comment to be deleted
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Implement soft delete by setting deleted_at timestamp to current time. Validate that the authenticated user is either the comment author or an administrator. Return the complete comment object including the newly set deleted_at timestamp. Ensure proper authorization checks before allowing deletion. Log the deletion action for audit purposes if performed by an administrator.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteDiscussionBoardAdminCommentsCommentId({
        admin,
        commentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
