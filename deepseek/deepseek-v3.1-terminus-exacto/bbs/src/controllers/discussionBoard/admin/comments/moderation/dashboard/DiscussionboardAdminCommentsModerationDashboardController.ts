import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IDiscussionBoardCommentModeration } from "../../../../../../api/structures/IDiscussionBoardCommentModeration";
import { AdminAuth } from "../../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../../decorators/payload/AdminPayload";
import { getDiscussionBoardAdminCommentsModerationDashboard } from "../../../../../../providers/getDiscussionBoardAdminCommentsModerationDashboard";

@Controller("/discussionBoard/admin/comments/moderation/dashboard")
export class DiscussionboardAdminCommentsModerationDashboardController {
  /**
   * Provides administrators with a comprehensive overview of comment moderation activities across the platform.
   *
   * This dashboard displays key moderation metrics including pending flag counts, recent moderation actions, and moderation statistics. Administrators can quickly assess the current moderation workload and identify trends in comment moderation activities.
   *
   * The dashboard aggregates data from multiple moderation-related tables including comment flags, moderation logs, and user reports. It provides actionable insights for efficient moderation workflow management and helps administrators prioritize their moderation efforts based on current platform activity levels.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query multiple tables to build comprehensive moderation dashboard:
   * - Count pending comment flags from discussion_board_comment_flags where status = 'pending'
   * - Count pending comment reports from discussion_board_comment_reports where status = 'pending'
   * - Retrieve recent moderation actions from discussion_board_comment_moderations ordered by created_at desc
   * - Calculate moderation statistics by action type and timeframe
   * - Join with administrator and user tables for display names
   * - Aggregate data for efficient dashboard loading
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @AdminAuth()
    admin: AdminPayload,
  ): Promise<IDiscussionBoardCommentModeration> {
    try {
      return await getDiscussionBoardAdminCommentsModerationDashboard({
        admin,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
