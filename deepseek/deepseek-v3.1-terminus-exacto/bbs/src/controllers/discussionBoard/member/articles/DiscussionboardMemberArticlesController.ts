import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IDiscussionBoardArticle } from "../../../../api/structures/IDiscussionBoardArticle";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { deleteDiscussionBoardMemberArticles } from "../../../../providers/deleteDiscussionBoardMemberArticles";
import { postDiscussionBoardMemberArticles } from "../../../../providers/postDiscussionBoardMemberArticles";

@Controller("/discussionBoard/member/articles")
export class DiscussionboardMemberArticlesController {
  /**
   * Create a new article in the discussion board system.
   *
   * This operation allows authenticated members to create new articles within specified sections. The article must include a title and content body, and be assigned to an existing section for proper categorization. The system validates that the requesting user has permission to create articles and that the target section is active and accessible.
   *
   * Articles serve as the primary discussion starters in the forum and support rich text content with optional attachments. Upon successful creation, the article becomes immediately visible to other users according to their access permissions. The operation ensures data integrity by enforcing section validity and maintaining proper author attribution.
   *
   * Related operations include PATCH /articles for searching articles, GET /articles/{articleId} for retrieving individual articles, and PUT /articles/{articleId} for updating existing articles. Each article created through this operation can receive comments and attachments through their respective APIs.
   *
   * @param connection
   * @param body Article creation data including title, content, and section assignment
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Validate user authentication and ensure the requesting member has active status. Verify the specified section exists and is active. Validate title and content meet minimum length requirements and content guidelines. Create the article record with the member's ID as author and specified section ID. Set initial status to 'published' and timestamps. Handle potential conflicts with unique constraint on member_id, section_id, and title. Return the complete article record with all fields populated from the database.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IDiscussionBoardArticle.ICreate,
  ): Promise<IDiscussionBoardArticle> {
    try {
      return await postDiscussionBoardMemberArticles({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Administrative bulk deletion operation for discussion board articles.
   *
   * This operation allows administrators to delete multiple articles simultaneously based on filtering criteria such as article status, author, section, creation date range, or specific tags. The deletion process follows cascade rules as defined in the system requirements, automatically removing all comments and file attachments associated with the targeted articles.
   *
   * Administrators can use this operation for content moderation, cleanup of outdated content, or removal of articles that violate platform guidelines. The operation provides comprehensive audit trails and maintains referential integrity throughout the deletion process.
   *
   * Security considerations require administrator-level authorization for this operation. Regular members can only delete their own individual articles through the single-article deletion endpoint.
   *
   * @param connection
   * @param body Criteria for identifying articles to be deleted
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Execute bulk deletion of discussion board articles based on filtering criteria. Query the discussion_board_articles table with the provided filters to identify articles for deletion. For each article to be deleted, perform cascade deletion of all associated comments from discussion_board_comments table and all associated attachments from discussion_board_attachments table. Validate that the requesting user has administrator privileges. Return the count of deleted articles and related records for audit purposes. Handle transaction rollback if any deletion fails to maintain data integrity.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IDiscussionBoardArticle.IDeleteRequest,
  ): Promise<void> {
    try {
      return await deleteDiscussionBoardMemberArticles({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
