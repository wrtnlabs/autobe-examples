import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IDiscussionBoardComment } from "../../../../../api/structures/IDiscussionBoardComment";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { deleteDiscussionBoardMemberArticlesArticleIdCommentsCommentId } from "../../../../../providers/deleteDiscussionBoardMemberArticlesArticleIdCommentsCommentId";
import { postDiscussionBoardMemberArticlesArticleIdComments } from "../../../../../providers/postDiscussionBoardMemberArticlesArticleIdComments";
import { putDiscussionBoardMemberArticlesArticleIdCommentsCommentId } from "../../../../../providers/putDiscussionBoardMemberArticlesArticleIdCommentsCommentId";

@Controller("/discussionBoard/member/articles/:articleId/comments")
export class DiscussionboardMemberArticlesCommentsController {
  /**
   * Create a new comment on a specific article.
   *
   * This operation allows authenticated users to post comments on articles within the discussion board. Each comment is associated with both the authoring user and the target article, creating a direct response to the article content.
   *
   * Comments support Markdown formatting and are displayed in chronological order on article pages. Users can only create comments on articles they have permission to view. The system validates comment content against community guidelines before publishing, ensuring substantive contributions that advance discussion.
   *
   * This operation requires authentication and will fail if the user is banned or the target article does not exist or is inaccessible. Successful creation returns the complete comment object including author details and timestamps.
   *
   * The operation creates records in the discussion_board_comments table, which maintains foreign key relationships to discussion_board_members (author) and discussion_board_articles (parent article). Comment validation includes checking for meaningful content contributions as defined in the business requirements.
   *
   * @param connection
   * @param articleId Target article's unique identifier
   * @param body Comment creation data including content
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Validate that the authenticated user exists and is not banned. Verify the target article exists and is accessible (not deleted). Create a new comment record with the provided content, associating it with the article and author. Update the article's comment count if needed. Return the created comment with author information.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardComment.ICreate,
  ): Promise<IDiscussionBoardComment> {
    try {
      return await postDiscussionBoardMemberArticlesArticleIdComments({
        member,
        articleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update the content of a specific comment on an article.
   *
   * This operation allows authenticated member users to modify their own comments. The system validates that the requesting user is the author of the target comment before processing the update, referencing the discussion_board_member_id field in the discussion_board_comments table. If the user does not own the comment, the operation returns an authorization error.
   *
   * After successful update, the comment's updated_at timestamp is automatically set to the current time while preserving the original created_at timestamp. The operation returns the complete updated comment object including content, author information, and timestamps.
   *
   * Administrators have special privileges to edit any comment regardless of authorship, supporting content moderation workflows. The operation enforces meaningful contribution validation rules requiring substantive content edits that maintain the comment's original context and discussion position.
   *
   * Comment edits must preserve chronological ordering and cannot fundamentally alter the original meaning in ways that disrupt conversation flow, as specified in the business requirements for edit context preservation.
   *
   * @param connection
   * @param articleId Unique identifier of the parent article containing the comment
   * @param commentId Unique identifier of the comment to be updated
   * @param body Updated comment content with validation for meaningful contributions
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Update a specific comment on an article. Validate that the authenticated user is the author of the comment before allowing the update. Update the comment content and set the updated_at timestamp to the current time. Return the updated comment with all fields including the new content and updated timestamp.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":commentId")
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardComment.IUpdate,
  ): Promise<IDiscussionBoardComment> {
    try {
      return await putDiscussionBoardMemberArticlesArticleIdCommentsCommentId({
        member,
        articleId,
        commentId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a specific comment from an article.
   *
   * This operation allows authorized users to remove comments from articles following the discussion board platform's deletion workflow. Comment authors can delete their own comments, while administrators have broader deletion privileges. The operation enforces strict authorization by verifying the authenticated user either owns the comment via discussion_board_comments.discussion_board_member_id or possesses administrative privileges.
   *
   * When a comment is deleted, the system creates an audit trail record in the discussion_board_comment_deletions table with actor_type 'member' for member-initiated deletions. For member actors, a corresponding record is created in discussion_board_comment_deletion_of_members linking to the member's account and session. The parent comment in discussion_board_comments receives a deleted_at timestamp, removing it from public view while preserving the record for audit purposes.
   *
   * This operation integrates with the platform's comment management system, working alongside comment creation and editing operations. Users should first retrieve comments using article comment listing operations to identify specific comments for deletion. Deletion records provide accountability and enable restoration capabilities for administrators while maintaining referential integrity throughout the comment lifecycle.
   *
   * Response includes the deleted comment information from discussion_board_comments for confirmation, allowing users to verify successful deletion. The operation maintains data consistency across related tables including comment activities, snapshots, and article statistics.
   *
   * @param connection
   * @param articleId Unique identifier of the parent article containing the comment
   * @param commentId Unique identifier of the comment to be deleted
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Verify user authorization before deletion. Check if the current user is the comment author or has administrator privileges. If authorized, perform soft deletion by setting deleted_at timestamp. Maintain referential integrity by updating article comment counts if needed. Return the deleted comment information for confirmation. Handle concurrent deletion attempts with proper locking.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":commentId")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteDiscussionBoardMemberArticlesArticleIdCommentsCommentId(
        {
          member,
          articleId,
          commentId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
