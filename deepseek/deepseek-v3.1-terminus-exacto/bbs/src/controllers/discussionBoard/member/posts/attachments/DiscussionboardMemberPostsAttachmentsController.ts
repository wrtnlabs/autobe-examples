import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { postDiscussionBoardMemberPostsPostIdAttachments } from "../../../../../providers/postDiscussionBoardMemberPostsPostIdAttachments";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { patchDiscussionBoardMemberPostsPostIdAttachments } from "../../../../../providers/patchDiscussionBoardMemberPostsPostIdAttachments";
import { getDiscussionBoardMemberPostsPostIdAttachmentsAttachmentId } from "../../../../../providers/getDiscussionBoardMemberPostsPostIdAttachmentsAttachmentId";
import { putDiscussionBoardMemberPostsPostIdAttachmentsAttachmentId } from "../../../../../providers/putDiscussionBoardMemberPostsPostIdAttachmentsAttachmentId";
import { deleteDiscussionBoardMemberPostsPostIdAttachmentsAttachmentId } from "../../../../../providers/deleteDiscussionBoardMemberPostsPostIdAttachmentsAttachmentId";

import { IDiscussionBoardPostAttachment } from "../../../../../api/structures/IDiscussionBoardPostAttachment";
import { IPageIDiscussionBoardPostAttachment } from "../../../../../api/structures/IPageIDiscussionBoardPostAttachment";

@Controller("/discussionBoard/member/posts/:postId/attachments")
export class DiscussionboardMemberPostsAttachmentsController {
  /**
   * Create a new file attachment for a discussion board post.
   *
   * Upload and associate a new file attachment with an existing discussion
   * board post. This operation allows authenticated users to add supporting
   * materials such as images, documents, or research files to their posts.
   *
   * The operation validates the uploaded file metadata including file name,
   * type, size, and storage path. It associates the attachment with the
   * specified post and initiates security scanning to ensure file safety. The
   * attachment undergoes processing before being made available for download.
   *
   * Security considerations include validating that the user has permission to
   * modify the target post and ensuring uploaded files meet size and type
   * restrictions. The operation tracks upload status and provides appropriate
   * error handling for invalid file uploads or permission violations.
   *
   * @param connection
   * @param postId Unique identifier of the target discussion board post
   * @param body File attachment creation data including metadata and upload
   *   information
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("postId")
    postId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardPostAttachment.ICreate,
  ): Promise<IDiscussionBoardPostAttachment> {
    try {
      return await postDiscussionBoardMemberPostsPostIdAttachments({
        member,
        postId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve a filtered, paginated list of attachments for a
   * specific discussion board post.
   *
   * This operation provides advanced search capabilities for finding file
   * attachments associated with a specific discussion board post. Users can
   * filter attachments by file type, upload status, security scan result, and
   * other criteria to efficiently manage post-related files.
   *
   * The operation supports comprehensive pagination with configurable page
   * sizes and sorting options. Attachments can be sorted by creation date, file
   * size, download count, or other relevant fields in ascending or descending
   * order. The search functionality includes partial matching on file names and
   * descriptions to help users locate specific attachments quickly.
   *
   * Security considerations include validating that the requesting user has
   * appropriate permissions to view attachments for the specified post. The
   * operation automatically filters out attachments that have been soft-deleted
   * or are in failed upload status, ensuring only valid and accessible files
   * are returned.
   *
   * This operation integrates with the discussion_board_post_attachments table
   * as defined in the Prisma schema, incorporating all available attachment
   * fields and relationships. The response includes attachment summary
   * information optimized for list displays, with options to include additional
   * details based on authorization level.
   *
   * @param connection
   * @param postId Unique identifier of the target discussion board post
   * @param body Search criteria and pagination parameters for attachment
   *   filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("postId")
    postId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardPostAttachment.IRequest,
  ): Promise<IPageIDiscussionBoardPostAttachment.ISummary> {
    try {
      return await patchDiscussionBoardMemberPostsPostIdAttachments({
        member,
        postId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific file attachment for a
   * discussion board post.
   *
   * This operation provides complete metadata and information about a specific
   * file attachment linked to a discussion board post. It returns detailed
   * information including the original file name, MIME type, file size, storage
   * path, upload status, security scan results, and download statistics.
   *
   * The operation performs validation checks to ensure both the specified post
   * and attachment exist and are accessible. It verifies that the attachment
   * belongs to the specified post and that the requesting user has appropriate
   * permissions to view the attachment details. Security measures include
   * checking the attachment's upload status and security scan results to
   * prevent access to potentially harmful files.
   *
   * For attachments that are still processing or have failed uploads, the
   * operation returns appropriate status information to inform the user about
   * the current state. Successful attachments include download URLs and access
   * information that can be used to retrieve the actual file content through
   * separate download endpoints.
   *
   * This operation integrates with the discussion_board_post_attachments table
   * as defined in the Prisma schema, returning all available attachment
   * metadata. The detailed response is optimized for attachment management
   * interfaces and provides comprehensive information for both administrative
   * and user-facing applications.
   *
   * @param connection
   * @param postId Unique identifier of the target discussion board post
   * @param attachmentId Unique identifier of the target file attachment
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":attachmentId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("postId")
    postId: string & tags.Format<"uuid">,
    @TypedParam("attachmentId")
    attachmentId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardPostAttachment> {
    try {
      return await getDiscussionBoardMemberPostsPostIdAttachmentsAttachmentId({
        member,
        postId,
        attachmentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing file attachment for a discussion board post.
   *
   * Modify metadata and properties of an existing file attachment associated
   * with a discussion board post. This operation allows users to update
   * attachment descriptions, file information, or other metadata while
   * maintaining the attachment's association with the original post.
   *
   * The operation validates that both the post and attachment exist and that
   * the attachment belongs to the specified post. It ensures the requesting
   * user has appropriate permissions to modify the attachment, typically
   * requiring ownership or administrative privileges.
   *
   * Security considerations include verifying attachment ownership and
   * preventing unauthorized modifications to file metadata. The operation
   * maintains audit trails of attachment updates and preserves the original
   * file content while allowing metadata changes.
   *
   * @param connection
   * @param postId Unique identifier of the target discussion board post
   * @param attachmentId Unique identifier of the target attachment to update
   * @param body Attachment update data including modified metadata and
   *   properties
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":attachmentId")
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("postId")
    postId: string & tags.Format<"uuid">,
    @TypedParam("attachmentId")
    attachmentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardPostAttachment.IUpdate,
  ): Promise<IDiscussionBoardPostAttachment> {
    try {
      return await putDiscussionBoardMemberPostsPostIdAttachmentsAttachmentId({
        member,
        postId,
        attachmentId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a specific attachment from a discussion board post.
   *
   * This operation permanently removes a file attachment from a discussion
   * board post. The attachment is identified by its unique identifier within
   * the context of a specific post.
   *
   * The operation validates that both the post and attachment exist and that
   * the requesting user has appropriate permissions to delete the attachment.
   * This typically requires that the user is either the original uploader of
   * the attachment or has moderator privileges.
   *
   * Security considerations include verifying ownership or authorization before
   * allowing deletion. The operation performs a hard delete, completely
   * removing the attachment record from the database. This action cannot be
   * undone, so appropriate confirmation should be implemented at the client
   * level.
   *
   * Related operations include viewing attachments (GET
   * /posts/{postId}/attachments) and uploading new attachments (POST
   * /posts/{postId}/attachments).
   *
   * @param connection
   * @param postId Unique identifier of the target discussion board post
   * @param attachmentId Unique identifier of the target attachment within the
   *   post
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":attachmentId")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("postId")
    postId: string & tags.Format<"uuid">,
    @TypedParam("attachmentId")
    attachmentId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteDiscussionBoardMemberPostsPostIdAttachmentsAttachmentId(
        {
          member,
          postId,
          attachmentId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
