import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { postDiscussionBoardMemberPostsPostIdComments } from "../../../../../providers/postDiscussionBoardMemberPostsPostIdComments";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { patchDiscussionBoardMemberPostsPostIdComments } from "../../../../../providers/patchDiscussionBoardMemberPostsPostIdComments";
import { putDiscussionBoardMemberPostsPostIdCommentsCommentId } from "../../../../../providers/putDiscussionBoardMemberPostsPostIdCommentsCommentId";
import { deleteDiscussionBoardMemberPostsPostIdCommentsCommentId } from "../../../../../providers/deleteDiscussionBoardMemberPostsPostIdCommentsCommentId";

import { IDiscussionBoardComment } from "../../../../../api/structures/IDiscussionBoardComment";
import { IPageIDiscussionBoardComment } from "../../../../../api/structures/IPageIDiscussionBoardComment";

@Controller("/discussionBoard/member/posts/:postId/comments")
export class DiscussionboardMemberPostsCommentsController {
  /**
   * Create a new comment on a discussion board post.
   *
   * This operation allows authenticated users to create new comments on
   * discussion board posts. The operation requires a valid post identifier and
   * comment creation data including content and optional parent comment
   * reference for threaded replies.
   *
   * Comments support hierarchical threading with a maximum depth of 3 levels as
   * specified in the requirements. When creating a reply comment, the operation
   * automatically calculates the appropriate thread level based on the parent
   * comment's nesting depth. The system validates that the maximum thread depth
   * is not exceeded.
   *
   * The operation performs comprehensive validation including content length
   * checks (1-2000 characters), parent post existence verification, and parent
   * comment validation for threaded replies. Comments are initially created
   * with 'published' status and include timestamps for creation and
   * modification tracking.
   *
   * Security considerations require user authentication to track comment
   * authorship and prevent anonymous posting. The operation integrates with the
   * discussion board's moderation system and supports attachment uploads
   * through separate attachment management endpoints.
   *
   * @param connection
   * @param postId Unique identifier of the parent post where the comment will
   *   be created
   * @param body Comment creation data including content and optional parent
   *   comment reference
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("postId")
    postId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardComment.ICreate,
  ): Promise<IDiscussionBoardComment> {
    try {
      return await postDiscussionBoardMemberPostsPostIdComments({
        member,
        postId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve comments for a specific discussion board post.
   *
   * This operation provides advanced search and filtering capabilities for
   * comments associated with a specific discussion board post. It allows users
   * to retrieve comments with various filtering options, pagination controls,
   * and sorting preferences.
   *
   * The operation supports comprehensive search functionality including text
   * matching within comment content, filtering by comment status (published,
   * draft, deleted), and filtering by author. Users can specify pagination
   * parameters such as page number and page size to control the volume of
   * results returned.
   *
   * Sorting options include creation date, update date, thread level, and other
   * relevant fields. The operation automatically handles threaded comment
   * hierarchies, maintaining proper parent-child relationships in the response
   * data.
   *
   * Security is enforced through access controls that verify the requesting
   * user has appropriate permissions to view the parent post and its comments.
   * The operation respects the post's locked status and other visibility
   * restrictions. Comments that have been soft-deleted are filtered out unless
   * explicitly requested by users with appropriate permissions.
   *
   * @param connection
   * @param postId Unique identifier of the target post whose comments are being
   *   retrieved
   * @param body Search criteria and pagination parameters for comment filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("postId")
    postId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardComment.IRequest,
  ): Promise<IPageIDiscussionBoardComment.ISummary> {
    try {
      return await patchDiscussionBoardMemberPostsPostIdComments({
        member,
        postId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing comment on a discussion board post.
   *
   * This operation allows authenticated members to update the content of their
   * comments on discussion board posts. The system validates that the comment
   * exists, belongs to the specified post, and that the requesting member is
   * the original author of the comment.
   *
   * Comment updates are subject to time-based restrictions as specified in the
   * requirements - members can only edit their comments within a limited
   * timeframe after creation. The operation preserves the comment's thread
   * level and parent relationships while updating the content and tracking the
   * modification timestamp.
   *
   * Security considerations include ensuring that only the comment author can
   * modify their content, and that the comment belongs to the specified post.
   * The system validates the comment's current status and prevents
   * modifications to deleted or archived comments. The updated_at timestamp is
   * automatically refreshed to track the modification history.
   *
   * This operation integrates with the discussion_board_comments table as
   * defined in the Prisma schema, updating the content field while preserving
   * all other comment attributes and relationships.
   *
   * @param connection
   * @param postId Unique identifier of the parent post containing the comment
   * @param commentId Unique identifier of the comment to be updated
   * @param body Updated comment content and metadata
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":commentId")
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("postId")
    postId: string & tags.Format<"uuid">,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardComment.IUpdate,
  ): Promise<IDiscussionBoardComment> {
    try {
      return await putDiscussionBoardMemberPostsPostIdCommentsCommentId({
        member,
        postId,
        commentId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a comment from a discussion board post.
   *
   * This operation performs a soft deletion of a comment on a discussion board
   * post by setting the deleted_at timestamp. The comment remains in the
   * database but is marked as deleted and hidden from normal view. Only the
   * comment author or authorized moderators can delete comments.
   *
   * The system validates that the comment exists and belongs to the specified
   * post before proceeding with deletion. If the comment has child comments
   * (replies), the operation may handle them according to the business rules
   *
   * - Either cascading the deletion or preserving the thread structure.
   *
   * Security considerations include ensuring proper authorization checks -
   * members can only delete their own comments, while moderators may have
   * broader deletion privileges. The operation maintains data integrity by
   * preserving the comment record for audit purposes while making it invisible
   * to regular users.
   *
   * This operation integrates with the discussion_board_comments table as
   * defined in the Prisma schema, updating the status and deleted_at fields to
   * reflect the deletion while maintaining the comment's historical context and
   * relationships.
   *
   * @param connection
   * @param postId Unique identifier of the parent post containing the comment
   * @param commentId Unique identifier of the comment to be deleted
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":commentId")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("postId")
    postId: string & tags.Format<"uuid">,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardComment> {
    try {
      return await deleteDiscussionBoardMemberPostsPostIdCommentsCommentId({
        member,
        postId,
        commentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
