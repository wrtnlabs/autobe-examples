import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { postDiscussionBoardMemberPostsPostIdLikes } from "../../../../../providers/postDiscussionBoardMemberPostsPostIdLikes";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { deleteDiscussionBoardMemberPostsPostIdLikesLikeId } from "../../../../../providers/deleteDiscussionBoardMemberPostsPostIdLikesLikeId";

import { IDiscussionBoardPostLike } from "../../../../../api/structures/IDiscussionBoardPostLike";

@Controller("/discussionBoard/member/posts/:postId/likes")
export class DiscussionboardMemberPostsLikesController {
  /**
   * This operation allows authenticated members to create a like record for a
   * specific discussion board post, indicating their appreciation for the
   * content. The system validates that the member has not already liked the
   * same post to prevent duplicate engagements.
   *
   * The operation requires the authenticated member's identity to be extracted
   * from the JWT token and automatically associates the like with the current
   * user. The post ID is validated to ensure it exists and is accessible before
   * creating the like record.
   *
   * Security considerations include verifying that the member has permission to
   * view and engage with the target post. The operation implements rate
   * limiting to prevent spam-like behavior and ensures that likes can only be
   * created for posts that are currently published and accessible.
   *
   * This operation integrates with the discussion_board_post_likes table as
   * defined in the Prisma schema, maintaining the unique constraint that
   * prevents multiple likes per member per post. The response returns the
   * complete like record with timestamps for tracking engagement metrics.
   *
   * @param connection
   * @param postId Unique identifier of the target discussion board post
   * @param body Empty request body for post like creation
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("postId")
    postId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardPostLike.ICreate,
  ): Promise<IDiscussionBoardPostLike> {
    try {
      return await postDiscussionBoardMemberPostsPostIdLikes({
        member,
        postId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This operation allows authenticated members to permanently delete their
   * like record from a specific discussion board post, effectively retracting
   * their appreciation for the content. The operation performs a hard delete
   * that completely removes the engagement record from the database.
   *
   * The system validates that the authenticated member owns the like record
   * being deleted, preventing unauthorized removal of other users' likes. Both
   * the post ID and like ID are validated to ensure they exist and belong to
   * the authenticated member before proceeding with deletion.
   *
   * Security considerations include strict ownership verification to ensure
   * members can only delete their own like records. The operation does not
   * support soft deletion as likes represent transient engagement metrics
   * rather than permanent content records.
   *
   * This operation integrates with the discussion_board_post_likes table as
   * defined in the Prisma schema, permanently removing the engagement record
   * and updating post like counts accordingly. The response confirms successful
   * deletion without returning any data.
   *
   * @param connection
   * @param postId Unique identifier of the target discussion board post
   * @param likeId Unique identifier of the like record to be deleted
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":likeId")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("postId")
    postId: string & tags.Format<"uuid">,
    @TypedParam("likeId")
    likeId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteDiscussionBoardMemberPostsPostIdLikesLikeId({
        member,
        postId,
        likeId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
