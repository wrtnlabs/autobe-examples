import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postDiscussionBoardMemberContentReports } from "../../../../providers/postDiscussionBoardMemberContentReports";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { putDiscussionBoardMemberContentReportsReportId } from "../../../../providers/putDiscussionBoardMemberContentReportsReportId";

import { IDiscussionBoardContentReport } from "../../../../api/structures/IDiscussionBoardContentReport";

@Controller("/discussionBoard/member/contentReports")
export class DiscussionboardMemberContentreportsController {
  /**
   * This operation allows authenticated members to submit content reports for
   * moderation on the discussion board platform. Members can report various
   * types of content including posts, comments, and member profiles by
   * providing the report reason category and detailed explanation.
   *
   * The operation automatically sets the actor_type field to 'member' to
   * properly categorize the report source. It validates the report reason
   * against predefined categories such as spam, harassment, inappropriate
   * content, misinformation, copyright violations, and other issues. The system
   * automatically assigns appropriate priority levels based on the report
   * severity and initializes the report status as 'pending' for moderation
   * workflow processing.
   *
   * Security considerations include rate limiting to prevent report spam and
   * verification that the reporting member has appropriate permissions to
   * submit reports. The operation ensures that all required fields are properly
   * validated and that the report is routed to the appropriate moderation queue
   * based on the content type and severity level.
   *
   * This operation integrates with the discussion_board_content_reports table
   * as defined in the Prisma schema, incorporating all available report fields
   * and relationships. The response includes the complete report information
   * with system-generated fields such as report ID, timestamps, and initial
   * status.
   *
   * @param connection
   * @param body Content report creation data including reason, details, and
   *   target information
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IDiscussionBoardContentReport.ICreate,
  ): Promise<IDiscussionBoardContentReport> {
    try {
      return await postDiscussionBoardMemberContentReports({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This operation allows authorized members to update existing content reports
   * during the moderation workflow. Only the original report creator can modify
   * report details and additional information, with proper ownership validation
   * performed before allowing any updates.
   *
   * The operation validates that members have appropriate permissions to update
   * the specific report, ensuring that only the original reporter can make
   * changes to their submitted reports. Status transitions follow predefined
   * workflow rules, preventing invalid state changes such as moving from
   * 'resolved' back to 'pending' without proper escalation procedures. The
   * system automatically updates the updated_at timestamp to track modification
   * history.
   *
   * Security considerations include verification of member ownership for each
   * report update attempt and audit logging of all modifications to maintain
   * transparency in the moderation process. The operation ensures data
   * integrity by validating all field updates against business rules and
   * maintaining consistent timestamps for audit purposes.
   *
   * This operation integrates with the discussion_board_content_reports table
   * as defined in the Prisma schema, supporting updates to report details,
   * status, priority, and other modifiable fields while preserving
   * system-generated information and audit trails.
   *
   * @param connection
   * @param reportId Unique identifier of the target content report
   * @param body Content report update data including modified fields and status
   *   changes
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":reportId")
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("reportId")
    reportId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardContentReport.IUpdate,
  ): Promise<IDiscussionBoardContentReport> {
    try {
      return await putDiscussionBoardMemberContentReportsReportId({
        member,
        reportId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
