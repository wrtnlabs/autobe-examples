import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { postDiscussionBoardMemberCommentsCommentIdLikes } from "../../../../../providers/postDiscussionBoardMemberCommentsCommentIdLikes";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { patchDiscussionBoardMemberCommentsCommentIdLikes } from "../../../../../providers/patchDiscussionBoardMemberCommentsCommentIdLikes";
import { deleteDiscussionBoardMemberCommentsCommentIdLikesLikeId } from "../../../../../providers/deleteDiscussionBoardMemberCommentsCommentIdLikesLikeId";

import { IDiscussionBoardCommentLike } from "../../../../../api/structures/IDiscussionBoardCommentLike";
import { IPageIDiscussionBoardCommentLike } from "../../../../../api/structures/IPageIDiscussionBoardCommentLike";

@Controller("/discussionBoard/member/comments/:commentId/likes")
export class DiscussionboardMemberCommentsLikesController {
  /**
   * This operation allows authenticated members to express appreciation for
   * discussion board comments by creating a like record. The system validates
   * that the target comment exists and is accessible before creating the like
   * association.
   *
   * The operation enforces business rules including the unique constraint that
   * prevents duplicate likes from the same user on the same comment. It
   * automatically records the creation timestamp and associates the like with
   * the authenticated member's identity.
   *
   * Security measures ensure that users can only like comments they have
   * permission to access. The system validates comment status and accessibility
   * before allowing the like operation to proceed, maintaining data integrity
   * throughout the process.
   *
   * @param connection
   * @param commentId Unique identifier of the target comment to like
   * @param body Creation data for the new comment like record
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardCommentLike.ICreate,
  ): Promise<IDiscussionBoardCommentLike> {
    try {
      return await postDiscussionBoardMemberCommentsCommentIdLikes({
        member,
        commentId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This operation provides comprehensive search capabilities for retrieving
   * likes associated with a specific comment on the discussion board. Users can
   * filter likes by creation date ranges, sort by various criteria, and
   * paginate through results efficiently.
   *
   * The operation validates that the target comment exists and is accessible
   * before retrieving its likes. It supports complex query parameters including
   * date ranges, sorting options, and pagination controls to manage large
   * datasets effectively.
   *
   * Security considerations ensure that users can only view likes for comments
   * they have permission to access. The system maintains data integrity by
   * validating comment existence and enforcing access controls throughout the
   * search process.
   *
   * @param connection
   * @param commentId Unique identifier of the target comment
   * @param body Search criteria and pagination parameters for filtering comment
   *   likes
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardCommentLike.IRequest,
  ): Promise<IPageIDiscussionBoardCommentLike> {
    try {
      return await patchDiscussionBoardMemberCommentsCommentIdLikes({
        member,
        commentId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This operation permanently removes a comment like record from the
   * discussion board system. The operation requires authentication and
   * authorization to ensure only the user who created the like can delete it.
   *
   * The operation validates that the specified comment like exists and belongs
   * to the authenticated user before proceeding with deletion. This ensures
   * data integrity and prevents unauthorized deletion of other users'
   * engagement data.
   *
   * Security considerations include proper authentication verification and
   * ownership validation. The system maintains audit trails through separate
   * logging mechanisms, but the actual like record is permanently removed from
   * the database. Related operations include creating likes (POST
   * /comments/{commentId}/likes) and viewing likes (GET
   * /comments/{commentId}/likes).
   *
   * @param connection
   * @param commentId Unique identifier of the target comment
   * @param likeId Unique identifier of the target like record
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":likeId")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
    @TypedParam("likeId")
    likeId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteDiscussionBoardMemberCommentsCommentIdLikesLikeId({
        member,
        commentId,
        likeId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
