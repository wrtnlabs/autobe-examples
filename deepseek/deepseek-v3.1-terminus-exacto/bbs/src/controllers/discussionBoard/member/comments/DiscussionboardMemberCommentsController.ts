import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchDiscussionBoardMemberComments } from "../../../../providers/patchDiscussionBoardMemberComments";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getDiscussionBoardMemberCommentsCommentId } from "../../../../providers/getDiscussionBoardMemberCommentsCommentId";
import { putDiscussionBoardMemberCommentsCommentId } from "../../../../providers/putDiscussionBoardMemberCommentsCommentId";
import { deleteDiscussionBoardMemberCommentsCommentId } from "../../../../providers/deleteDiscussionBoardMemberCommentsCommentId";

import { IPageIDiscussionBoardComment } from "../../../../api/structures/IPageIDiscussionBoardComment";
import { IDiscussionBoardComment } from "../../../../api/structures/IDiscussionBoardComment";

@Controller("/discussionBoard/member/comments")
export class DiscussionboardMemberCommentsController {
  /**
   * This operation provides comprehensive search capabilities for discussion
   * board comments with support for pagination, filtering, and sorting. Users
   * can search comments based on content text, author information, parent post
   * references, comment status, and date ranges.
   *
   * The operation supports advanced text search within comment content using
   * full-text indexing capabilities. Filtering options include comment status
   * (published, draft, deleted), author identification, parent post filtering,
   * and thread level restrictions. Sorting options include creation date,
   * update date, and relevance scoring for text searches.
   *
   * Security considerations ensure that users can only access comments they are
   * authorized to view based on their permissions and the visibility settings
   * of the comments. The operation integrates with the
   * discussion_board_comments table as defined in the Prisma schema,
   * incorporating all available comment fields and relationships.
   *
   * Related operations include creating new comments (POST /comments) and
   * retrieving specific comments (GET /comments/{commentId}).
   *
   * @param connection
   * @param body Search criteria and pagination parameters for comment filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IDiscussionBoardComment.IRequest,
  ): Promise<IPageIDiscussionBoardComment.ISummary> {
    try {
      return await patchDiscussionBoardMemberComments({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This operation fetches a single comment from the discussion board comments
   * table using its unique identifier. The comment is retrieved with all its
   * details including the content text, current status, thread nesting level,
   * creation and modification timestamps, and soft deletion status if
   * applicable.
   *
   * The operation validates that the requested comment exists in the database
   * and that the requesting user has appropriate permissions to view it.
   * Comments with 'published' status are accessible to all authenticated users,
   * while 'draft' comments may have additional access restrictions based on the
   * author relationship.
   *
   * The response includes the complete comment object with references to its
   * parent post, author information, and parent comment for threaded
   * discussions. This operation is essential for displaying individual comments
   * in discussion threads and supporting comment management workflows.
   *
   * @param connection
   * @param commentId Unique identifier of the target comment
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":commentId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardComment> {
    try {
      return await getDiscussionBoardMemberCommentsCommentId({
        member,
        commentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This operation enables authenticated users to modify the content of an
   * existing comment while maintaining the comment's structural relationships
   * and metadata. The operation performs comprehensive validation to ensure the
   * comment exists, the requesting user has appropriate edit permissions, and
   * the updated content meets the system's validation requirements.
   *
   * Only the comment author or users with moderation privileges can update
   * comments. The operation preserves the comment's relationships to its parent
   * post, author, and parent comment while updating the content field. The
   * thread level, status, and creation timestamp remain unchanged, while the
   * updated_at timestamp is automatically refreshed.
   *
   * The system validates that the updated content meets the length requirements
   * (1-2000 characters) and applies any content moderation rules. If the
   * comment has been soft deleted, the operation may be restricted based on
   * system policies. This operation supports the editing workflow for comment
   * authors and moderation actions for administrators.
   *
   * @param connection
   * @param commentId Unique identifier of the target comment to update
   * @param body Updated comment content and optional metadata
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":commentId")
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardComment.IUpdate,
  ): Promise<IDiscussionBoardComment> {
    try {
      return await putDiscussionBoardMemberCommentsCommentId({
        member,
        commentId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This operation permanently removes a discussion board comment from the
   * system, including all associated file attachments. The deletion is
   * irreversible and cannot be recovered.
   *
   * Before deletion, the system validates that the comment exists and that the
   * requesting user has appropriate permissions to perform this action. The
   * operation checks the comment's current status and ensures it can be deleted
   * based on business rules.
   *
   * When a comment is deleted, all associated attachments in the
   * discussion_board_comment_attachments table are also permanently removed.
   * This includes file metadata records and any stored file content. The
   * operation maintains referential integrity by cascading the deletion to
   * related attachment records.
   *
   * Security considerations include authentication verification and
   * authorization checks to prevent unauthorized deletion. The operation logs
   * the deletion event for audit purposes and ensures proper cleanup of
   * associated resources.
   *
   * @param connection
   * @param commentId Unique identifier of the target comment to delete
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":commentId")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardComment> {
    try {
      return await deleteDiscussionBoardMemberCommentsCommentId({
        member,
        commentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
