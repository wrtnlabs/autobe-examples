import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { postDiscussionBoardMemberCommentsCommentIdAttachments } from "../../../../../providers/postDiscussionBoardMemberCommentsCommentIdAttachments";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { patchDiscussionBoardMemberCommentsCommentIdAttachments } from "../../../../../providers/patchDiscussionBoardMemberCommentsCommentIdAttachments";
import { getDiscussionBoardMemberCommentsCommentIdAttachmentsAttachmentId } from "../../../../../providers/getDiscussionBoardMemberCommentsCommentIdAttachmentsAttachmentId";
import { putDiscussionBoardMemberCommentsCommentIdAttachmentsAttachmentId } from "../../../../../providers/putDiscussionBoardMemberCommentsCommentIdAttachmentsAttachmentId";
import { deleteDiscussionBoardMemberCommentsCommentIdAttachmentsAttachmentId } from "../../../../../providers/deleteDiscussionBoardMemberCommentsCommentIdAttachmentsAttachmentId";

import { IDiscussionBoardCommentAttachment } from "../../../../../api/structures/IDiscussionBoardCommentAttachment";
import { IPageIDiscussionBoardCommentAttachment } from "../../../../../api/structures/IPageIDiscussionBoardCommentAttachment";

@Controller("/discussionBoard/member/comments/:commentId/attachments")
export class DiscussionboardMemberCommentsAttachmentsController {
  /**
   * Upload a new file attachment for a comment.
   *
   * This operation allows authenticated members to upload file attachments to
   * support their discussion board comments. The attachment is associated with
   * a specific comment and undergoes a multi-stage processing workflow
   * including security scanning and validation.
   *
   * The upload process begins by creating an attachment record with pending
   * status. The system then validates file properties against platform
   * restrictions, including size limits and allowed file types. Once basic
   * validation passes, security scanning is initiated to ensure the file is
   * safe for distribution.
   *
   * Members can upload various file types including images (JPG, PNG, GIF) and
   * documents (PDF, DOC, DOCX) to enhance their comment content. Each
   * attachment maintains its own lifecycle independent from the comment text,
   * allowing for separate management and moderation.
   *
   * The operation requires active member authentication and validates that the
   * user has permission to attach files to the specified comment. Upload limits
   * and rate limiting apply to prevent abuse of the attachment system.
   *
   * @param connection
   * @param commentId Unique identifier of the parent comment that will receive
   *   the attachment
   * @param body File attachment metadata and upload information
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardCommentAttachment.ICreate,
  ): Promise<IDiscussionBoardCommentAttachment> {
    try {
      return await postDiscussionBoardMemberCommentsCommentIdAttachments({
        member,
        commentId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve attachments for a specific comment.
   *
   * This operation provides comprehensive search capabilities for attachments
   * associated with a specific discussion board comment. It supports advanced
   * filtering options including file type categorization, upload status
   * tracking, security scan results, and date-based filtering.
   *
   * The search functionality includes pagination support with configurable page
   * sizes and sorting options. Users can sort attachments by creation date,
   * file size, download count, or file name. The operation returns summary
   * information optimized for attachment management interfaces.
   *
   * Security validation ensures that users can only access attachments
   * belonging to comments they have permission to view. The system checks
   * comment visibility and user authorization before returning any attachment
   * data.
   *
   * The operation integrates with the discussion_board_comment_attachments
   * table as defined in the Prisma schema, incorporating all available
   * attachment fields and relationships. Response data includes essential
   * attachment metadata while excluding sensitive storage path information.
   *
   * @param connection
   * @param commentId Unique identifier of the target comment whose attachments
   *   to search
   * @param body Search criteria and pagination parameters for attachment
   *   filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardCommentAttachment.IRequest,
  ): Promise<IPageIDiscussionBoardCommentAttachment.ISummary> {
    try {
      return await patchDiscussionBoardMemberCommentsCommentIdAttachments({
        member,
        commentId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve metadata for a specific comment attachment.
   *
   * This operation returns detailed information about a specific file
   * attachment associated with a discussion board comment. The attachment must
   * belong to the specified comment and be in a completed upload status to be
   * accessible.
   *
   * Each attachment undergoes security scanning before being made available for
   * download. The system tracks download counts and maintains audit trails for
   * all attachment access. Users can only access attachments for comments they
   * have permission to view based on the discussion board's access controls.
   *
   * The response includes comprehensive metadata such as file name, type, size,
   * upload status, security scan results, and download statistics. This
   * information helps users understand the attachment's properties before
   * deciding to download the actual file.
   *
   * Security considerations include validating the comment-attachment
   * relationship, checking user permissions for the parent comment, and
   * ensuring attachments have passed security scanning. Rate limiting applies
   * to prevent abuse of the attachment retrieval functionality.
   *
   * @param connection
   * @param commentId Unique identifier of the parent comment that contains the
   *   attachment
   * @param attachmentId Unique identifier of the specific attachment to
   *   retrieve
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":attachmentId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
    @TypedParam("attachmentId")
    attachmentId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardCommentAttachment> {
    try {
      return await getDiscussionBoardMemberCommentsCommentIdAttachmentsAttachmentId(
        {
          member,
          commentId,
          attachmentId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update metadata for a specific comment attachment.
   *
   * This operation allows authenticated members to update metadata for a file
   * attachment associated with a discussion board comment. Members can modify
   * the attachment description, update upload status, or adjust other metadata
   * fields while maintaining the core file properties.
   *
   * The operation validates that the attachment exists and belongs to the
   * specified comment before allowing updates. Security checks ensure that only
   * the original uploader or authorized moderators can modify attachment
   * metadata. The system maintains audit trails of attachment modifications for
   * moderation and compliance purposes.
   *
   * Attachment updates follow business rules including validation of file type
   * compatibility and size constraints. The operation supports partial updates
   * through the IUpdate DTO pattern, allowing selective field modification
   * without requiring complete re-submission of all attachment data. Related
   * operations include creating new attachments (POST
   * /comments/{commentId}/attachments) and retrieving attachment details (GET
   * /comments/{commentId}/attachments/{attachmentId}).
   *
   * @param connection
   * @param commentId Unique identifier of the parent comment that contains the
   *   target attachment
   * @param attachmentId Unique identifier of the specific attachment to be
   *   updated
   * @param body Update data for the comment attachment metadata
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":attachmentId")
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
    @TypedParam("attachmentId")
    attachmentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardCommentAttachment.IUpdate,
  ): Promise<IDiscussionBoardCommentAttachment> {
    try {
      return await putDiscussionBoardMemberCommentsCommentIdAttachmentsAttachmentId(
        {
          member,
          commentId,
          attachmentId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a comment attachment.
   *
   * This operation permanently removes a file attachment from a discussion
   * board comment, including deletion of the database record and associated
   * storage resources. The operation performs hard deletion rather than soft
   * deletion to ensure complete removal of attachment data from the system.
   *
   * Security validation ensures that only the original attachment uploader or
   * authorized moderators can delete attachments. The operation checks that the
   * attachment belongs to the specified comment and that the requesting user
   * has appropriate deletion permissions. System administrators may override
   * deletion restrictions for moderation purposes.
   *
   * File storage cleanup occurs asynchronously after the database record
   * deletion to ensure efficient operation completion. The operation maintains
   * audit logs of attachment deletions for compliance and moderation tracking.
   * Related operations include viewing attachment details (GET
   * /comments/{commentId}/attachments/{attachmentId}) and updating attachment
   * metadata (PUT /comments/{commentId}/attachments/{attachmentId}).
   *
   * @param connection
   * @param commentId Unique identifier of the parent comment that contains the
   *   target attachment
   * @param attachmentId Unique identifier of the specific attachment to be
   *   deleted
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":attachmentId")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
    @TypedParam("attachmentId")
    attachmentId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteDiscussionBoardMemberCommentsCommentIdAttachmentsAttachmentId(
        {
          member,
          commentId,
          attachmentId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
