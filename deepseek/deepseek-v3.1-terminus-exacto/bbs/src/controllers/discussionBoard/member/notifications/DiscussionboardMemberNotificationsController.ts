import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchDiscussionBoardMemberNotifications } from "../../../../providers/patchDiscussionBoardMemberNotifications";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getDiscussionBoardMemberNotificationsNotificationId } from "../../../../providers/getDiscussionBoardMemberNotificationsNotificationId";
import { putDiscussionBoardMemberNotificationsNotificationId } from "../../../../providers/putDiscussionBoardMemberNotificationsNotificationId";
import { deleteDiscussionBoardMemberNotificationsNotificationId } from "../../../../providers/deleteDiscussionBoardMemberNotificationsNotificationId";

import { IPageIDiscussionBoardUserNotification } from "../../../../api/structures/IPageIDiscussionBoardUserNotification";
import { IDiscussionBoardUserNotification } from "../../../../api/structures/IDiscussionBoardUserNotification";

@Controller("/discussionBoard/member/notifications")
export class DiscussionboardMemberNotificationsController {
  /**
   * Search and retrieve a filtered, paginated list of user notifications.
   *
   * This operation provides comprehensive search functionality for user
   * notifications with support for filtering by type, status, delivery method,
   * and text content. Users can search through their notification history using
   * various criteria to find specific notifications.
   *
   * The operation supports advanced pagination with configurable page sizes and
   * sorting options. Users can sort notifications by creation date, update
   * date, or notification type in ascending or descending order. Text search
   * capabilities allow users to find notifications containing specific keywords
   * in titles or messages.
   *
   * Security considerations include ensuring that users can only access their
   * own notifications. The operation automatically filters results based on the
   * authenticated user's identity to maintain data privacy. Rate limiting
   * applies to prevent excessive search requests that could impact system
   * performance.
   *
   * This operation integrates with the discussion_board_user_notifications
   * table as defined in the Prisma schema, incorporating all available
   * notification fields and relationships. The response includes notification
   * summary information optimized for list displays, with options to include
   * additional details based on authorization level.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for notification
   *   filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IDiscussionBoardUserNotification.IRequest,
  ): Promise<IPageIDiscussionBoardUserNotification.ISummary> {
    try {
      return await patchDiscussionBoardMemberNotifications({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information for a specific user notification.
   *
   * This operation allows authenticated users to retrieve complete details for
   * a specific notification identified by its unique ID. The operation returns
   * the full notification record including title, message, type, status,
   * delivery method, and related entity information.
   *
   * Security measures ensure that users can only access notifications that
   * belong to them. The operation validates that the requested notification ID
   * corresponds to a notification owned by the authenticated user, preventing
   * unauthorized access to other users' notifications.
   *
   * The operation provides comprehensive notification details suitable for
   * displaying individual notification views. Users can see the complete
   * notification content, delivery status, creation and update timestamps, and
   * any related entity information for contextual navigation.
   *
   * This operation integrates with the discussion_board_user_notifications
   * table as defined in the Prisma schema, returning all available notification
   * fields. The response includes the complete notification object with
   * detailed information for user reference and interaction.
   *
   * @param connection
   * @param notificationId Unique identifier of the target notification
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":notificationId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("notificationId")
    notificationId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardUserNotification> {
    try {
      return await getDiscussionBoardMemberNotificationsNotificationId({
        member,
        notificationId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing user notification with new status or preferences.
   *
   * This PUT operation allows authenticated users to update their notification
   * settings and status. Users can mark notifications as read, dismiss them, or
   * update delivery preferences.
   *
   * The operation validates that the notification exists and belongs to the
   * requesting user before allowing any modifications. Only specific fields are
   * updatable based on user permissions - core notification content and
   * creation metadata cannot be modified.
   *
   * Security considerations include ensuring users can only update their own
   * notifications and preventing modification of critical system-generated
   * fields. The operation returns the updated notification object with current
   * status and timestamps.
   *
   * This operation integrates with the discussion_board_user_notifications
   * table as defined in the Prisma schema, allowing updates to status,
   * delivery_method, and other user-configurable fields while preserving
   * system-generated data integrity.
   *
   * @param connection
   * @param notificationId Unique identifier of the target notification
   * @param body Updated notification data including status changes and
   *   preferences
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":notificationId")
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("notificationId")
    notificationId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardUserNotification.IUpdate,
  ): Promise<IDiscussionBoardUserNotification> {
    try {
      return await putDiscussionBoardMemberNotificationsNotificationId({
        member,
        notificationId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a user notification from the system.
   *
   * This DELETE operation performs a hard deletion of user notifications from
   * the discussion_board_user_notifications table. Unlike soft-delete
   * operations that mark records as deleted, this operation permanently removes
   * the notification data from the database.
   *
   * The operation validates that the notification exists and belongs to the
   * requesting user before proceeding with deletion. This prevents unauthorized
   * users from deleting notifications that do not belong to them.
   *
   * Security considerations include proper authorization checks and audit
   * logging of deletion actions. The operation does not return any response
   * body upon successful deletion, providing only an HTTP status code to
   * indicate success.
   *
   * This operation integrates with the discussion_board_user_notifications
   * table as defined in the Prisma schema, performing complete removal of
   * notification records that users wish to permanently erase from their
   * notification history.
   *
   * @param connection
   * @param notificationId Unique identifier of the target notification
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":notificationId")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("notificationId")
    notificationId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteDiscussionBoardMemberNotificationsNotificationId({
        member,
        notificationId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
