import typia, { tags } from "typia";

import { IDiscussionBoardArticleFavorite } from "../../../../api/structures/IDiscussionBoardArticleFavorite";
import { IPageIDiscussionBoardArticleFavorite } from "../../../../api/structures/IPageIDiscussionBoardArticleFavorite";
