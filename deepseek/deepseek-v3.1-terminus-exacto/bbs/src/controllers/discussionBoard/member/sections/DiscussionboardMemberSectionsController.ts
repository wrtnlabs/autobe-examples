import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IDiscussionBoardSection } from "../../../../api/structures/IDiscussionBoardSection";
import { IPageIDiscussionBoardSection } from "../../../../api/structures/IPageIDiscussionBoardSection";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getDiscussionBoardMemberSections } from "../../../../providers/getDiscussionBoardMemberSections";
import { patchDiscussionBoardMemberSections } from "../../../../providers/patchDiscussionBoardMemberSections";

@Controller("/discussionBoard/member/sections")
export class DiscussionboardMemberSectionsController {
  /**
   * Retrieve the complete list of available discussion board sections for content navigation.
   *
   * This operation provides access to all thematic content categories that organize articles within the discussion platform. Each section represents a high-level content grouping such as Politics, Economy, or Current Affairs that administrators create and manage. Sections serve as the primary categorization backbone for content discovery and navigation.
   *
   * Users can browse sections to find relevant articles organized by thematic category. The response includes section names and descriptions to help users understand the content focus of each category. This operation supports the platform's content discovery workflow by enabling users to explore articles within specific thematic areas.
   *
   * All user types including guests, members, administrators, and super administrators can access section listings. The operation returns active sections only, excluding any sections that have been soft-deleted by administrators while preserving existing article associations.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query the discussion_board_sections table to retrieve all active sections (where deleted_at is null). Sort sections alphabetically by name for consistent browsing experience. Return basic section information including name, description, and creation timestamp. This operation should be accessible to all user types without authentication requirements.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @MemberAuth()
    member: MemberPayload,
  ): Promise<IDiscussionBoardSection.ISummary> {
    try {
      return await getDiscussionBoardMemberSections({
        member,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a paginated list of all available discussion board sections.
   *
   * This operation returns all active thematic content categories within the discussion platform. Sections represent high-level groupings such as Politics, Economy, or Current Affairs that administrators create and manage for organizing articles.
   *
   * Supports comprehensive pagination with configurable page sizes. The operation respects soft deletion policies by excluding sections marked as deleted while preserving existing article associations. All sections are returned in alphabetical order by name for consistent browsing.
   *
   * Users can browse available content categories to find relevant articles. This operation is available to all users regardless of authentication status.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query discussion_board_sections table with pagination and filtering.
   * Apply search filters on name and description using partial matching.
   * Support sorting by created_at (newest/oldest) and updated_at.
   * Implement cursor-based pagination for large result sets.
   * Exclude soft-deleted sections (deleted_at IS NULL).
   * Return section summaries optimized for list displays.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
  ): Promise<IPageIDiscussionBoardSection.ISummary> {
    try {
      return await patchDiscussionBoardMemberSections({
        member,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
