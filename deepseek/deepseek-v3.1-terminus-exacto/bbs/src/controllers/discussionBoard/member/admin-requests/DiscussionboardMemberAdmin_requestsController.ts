import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IDiscussionBoardAdminRequest } from "../../../../api/structures/IDiscussionBoardAdminRequest";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { deleteDiscussionBoardMemberAdminRequestsRequestId } from "../../../../providers/deleteDiscussionBoardMemberAdminRequestsRequestId";
import { getDiscussionBoardMemberAdminRequestsRequestId } from "../../../../providers/getDiscussionBoardMemberAdminRequestsRequestId";
import { postDiscussionBoardMemberAdminRequests } from "../../../../providers/postDiscussionBoardMemberAdminRequests";
import { putDiscussionBoardMemberAdminRequestsRequestId } from "../../../../providers/putDiscussionBoardMemberAdminRequestsRequestId";

@Controller("/discussionBoard/member/admin-requests")
export class DiscussionboardMemberAdmin_requestsController {
  /**
   * Submit a new administrator privilege request.
   *
   * This operation allows authenticated member users to apply for administrator privileges by submitting a formal request. The request requires a detailed reason explaining the user's qualifications, motivations, and how they plan to contribute to platform governance. The reason field corresponds to the 'reason' column in the discussion_board_admin_requests table which records the member's justification for seeking administrative role. Upon submission, the request enters a pending status (stored in the 'status' column) awaiting review by super administrators.
   *
   * The system validates that the user does not have any existing pending requests and ensures the request reason meets content guidelines including non-whitespace validation. Additionally, the system confirms the member is not currently banned and validates the reason text contains meaningful content. The 'created_at' timestamp is automatically generated upon successful submission. Once submitted, the request becomes visible to super administrators for review and cannot be modified by the requesting user. This operation supports the community governance framework by providing a formal pathway for user progression to administrative roles.
   *
   * Security considerations include rate limiting to prevent abuse and logging all submission activities for audit purposes. Users must be in good standing (not banned) to submit requests, and duplicate pending requests from the same user are automatically rejected. The operation creates records in the discussion_board_admin_requests table with fields: id (primary UUID), discussion_board_member_id (foreign key to member), reason, status, created_at, updated_at, and deleted_at (for soft deletion).
   *
   * @param connection
   * @param body Administrator request submission details
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Authenticate the user from the session token. Validate that the user does not have any existing pending admin requests. Create a new record in discussion_board_admin_requests table with the provided reason, set status to 'pending', associate with the authenticated user ID, and generate timestamps. Return the complete created record with ID, status, reason, and timestamps.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IDiscussionBoardAdminRequest.ICreate,
  ): Promise<IDiscussionBoardAdminRequest> {
    try {
      return await postDiscussionBoardMemberAdminRequests({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific administrator request for review by super administrators.
   *
   * This operation provides comprehensive details about an individual admin request including the request reason, current status, submission timestamp, and member profile information. Super administrators use this endpoint during the review process to evaluate requests for administrator promotion.
   *
   * The response includes the requesting member's display name and bio to provide context for the evaluation. Only super administrators should have access to this operation as it contains sensitive administrative information.
   *
   * This endpoint works in conjunction with the list operation (PATCH /admin-requests) to provide a complete admin request management workflow for platform governance.
   *
   * @param connection
   * @param requestId Unique identifier of the admin request to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Retrieve a single admin request by its unique ID from the discussion_board_admin_requests table. Include the member information (display name, bio) for super administrator review. Validate that the request exists and return appropriate error if not found. This operation is intended for super administrators reviewing pending admin requests.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":requestId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("requestId")
    requestId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardAdminRequest> {
    try {
      return await getDiscussionBoardMemberAdminRequestsRequestId({
        member,
        requestId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an administrator request with approval or rejection decision.
   *
   * This operation allows super administrators to review and decide on pending administrator requests. The decision must be either 'approved' or 'rejected', with an optional rejection reason required for rejection decisions. Approved requests grant regular administrator privileges to the requesting member, while rejected requests maintain the member's current status.
   *
   * Super administrators must have valid authentication and authorization to perform this operation. The system validates that the request exists, is in pending status, and that no previous decision has been recorded. All decisions are logged for audit trail and governance transparency.
   *
   * @param connection
   * @param requestId Unique identifier of the admin request to update
   * @param body Decision and optional rejection reason for the admin request
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Update an admin request with approval/rejection decision. Verify the requesting user is a super administrator. Validate the request exists and is in pending status. Create a decision record in discussion_board_admin_request_decisions table. Update the admin request status to approved/rejected. Return the complete admin request with decision details.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":requestId")
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("requestId")
    requestId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardAdminRequest.IUpdate,
  ): Promise<IDiscussionBoardAdminRequest> {
    try {
      return await putDiscussionBoardMemberAdminRequestsRequestId({
        member,
        requestId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently remove an administrator privilege request from the system by marking it as soft-deleted.
   *
   * This operation enables authorized users to delete administrator request records from the discussion board platform. Members who initiated requests can withdraw their own administrator privilege applications when they no longer wish to pursue administrative responsibilities. Additionally, platform administrators can clean up any admin request as part of system maintenance, regardless of ownership.
   *
   * The deletion process follows the soft-delete pattern configured in the `discussion_board_admin_requests` database table, setting the `deleted_at` timestamp field without physically removing the record. This preserves audit trail integrity while removing the request from active consideration. Before deletion, the system validates that the request exists and has not already been deleted.
   *
   * Authorization is strictly enforced: members can only delete their own requests, verified through ownership checks against the `discussion_board_member_id` field. Administrators have broader privilege to delete any admin request for system maintenance purposes. The operation returns null response as the deletion is considered complete once the `deleted_at` field is set.
   *
   * @param connection
   * @param requestId Unique identifier of the admin request to delete
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Handle admin request deletion with proper authorization checks. If the requesting user is the request owner (member), allow deletion for withdrawal. If the requesting user is an administrator, allow deletion for cleanup. Perform soft deletion by setting deleted_at timestamp. Return the deleted request for confirmation. Validate that the request exists and is not already deleted.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":requestId")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("requestId")
    requestId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteDiscussionBoardMemberAdminRequestsRequestId({
        member,
        requestId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
