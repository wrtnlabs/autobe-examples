  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("preferenceId")
    preferenceId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardNotificationPreference> {
    try {
      return await getDiscussionBoardMemberNotificationPreferencesPreferenceId({
        member,
        preferenceId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update notification preferences configuration for a discussion board
   * member.
   *
   * Update an existing notification preference configuration with new settings
   * for delivery methods and notification categories. This operation allows
   * users to customize how they receive notifications from the discussion
   * platform.
   *
   * The operation validates that the preference ID belongs to the authenticated
   * user before allowing modifications. Users can enable or disable specific
   * notification types including email notifications, in-app notifications,
   * post interactions, comment replies, moderation updates, and system
   * announcements. The frequency setting allows users to choose between
   * immediate notifications, daily digests, or weekly digests.
   *
   * Security considerations include ensuring that users can only update their
   * own notification preferences. The system automatically updates the
   * updated_at timestamp to track when preferences were last modified. This
   * operation integrates with the discussion_board_notification_preferences
   * table as defined in the Prisma schema, incorporating all available
   * preference fields and validation rules.
   *
   * Related operations include viewing notification preferences (GET
   * /notificationPreferences/{preferenceId}) and creating initial preferences
   * (POST /notificationPreferences). The updated preferences take effect
   * immediately for all future notifications generated by the platform.
   *
   * @param connection
   * @param preferenceId Unique identifier of the notification preference
   *   configuration to update
   * @param body Updated notification preference settings including delivery
   *   methods and notification categories
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
