import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { putDiscussionBoardMemberMembersUsernameSessionsSessionId } from "../../../../../providers/putDiscussionBoardMemberMembersUsernameSessionsSessionId";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { deleteDiscussionBoardMemberMembersUsernameSessionsSessionId } from "../../../../../providers/deleteDiscussionBoardMemberMembersUsernameSessionsSessionId";

import { IDiscussionBoardMemberSession } from "../../../../../api/structures/IDiscussionBoardMemberSession";

@Controller("/discussionBoard/member/members/:username/sessions/:sessionId")
export class DiscussionboardMemberMembersSessionsController {
  /**
   * Update an existing member session with new connection details.
   *
   * This operation allows updating the details of an existing member session,
   * including connection information such as IP address, access URL, and
   * referrer. The session must belong to the specified member and must be
   * active (not expired or deleted).
   *
   * Security considerations require that only authenticated members can update
   * their own sessions. The operation validates that the session belongs to the
   * member identified by the username parameter. Session updates are typically
   * used for tracking connection changes or extending session validity.
   *
   * This operation integrates with the discussion_board_member_sessions table
   * as defined in the Prisma schema, updating fields like IP address,
   * connection URL, referrer, and expiration timestamp. The updated_at field is
   * automatically refreshed to track modification time.
   *
   * @param connection
   * @param username Unique username of the member who owns the target session
   * @param sessionId Unique identifier of the target member session
   * @param body Updated session information including connection details
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("username")
    username: string,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardMemberSession.IUpdate,
  ): Promise<IDiscussionBoardMemberSession> {
    try {
      return await putDiscussionBoardMemberMembersUsernameSessionsSessionId({
        member,
        username,
        sessionId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a member session from the system.
   *
   * This operation permanently removes a member session record from the
   * database. The deletion is irreversible and cannot be recovered. The
   * operation validates that the session belongs to the specified member before
   * proceeding with deletion.
   *
   * Security considerations require that only authenticated members can delete
   * their own sessions. This operation is typically used when members want to
   * explicitly terminate a session for security reasons or when sessions need
   * to be cleaned up after logout events.
   *
   * This operation integrates with the discussion_board_member_sessions table
   * as defined in the Prisma schema. The operation performs a hard delete,
   * completely removing the session record rather than using soft deletion.
   * This ensures that terminated sessions are not retained in the system.
   *
   * @param connection
   * @param username Unique username of the member who owns the target session
   * @param sessionId Unique identifier of the target member session
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("username")
    username: string,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteDiscussionBoardMemberMembersUsernameSessionsSessionId({
        member,
        username,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
