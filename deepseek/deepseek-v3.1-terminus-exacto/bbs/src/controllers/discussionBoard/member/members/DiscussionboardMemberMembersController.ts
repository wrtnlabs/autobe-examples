import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia from "typia";
import { putDiscussionBoardMemberMembersUsername } from "../../../../providers/putDiscussionBoardMemberMembersUsername";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { deleteDiscussionBoardMemberMembersUsername } from "../../../../providers/deleteDiscussionBoardMemberMembersUsername";

import { IDiscussionBoardMember } from "../../../../api/structures/IDiscussionBoardMember";

@Controller("/discussionBoard/member/members/:username")
export class DiscussionboardMemberMembersController {
  /**
   * Update an existing member's profile information using their unique username
   * identifier. This operation allows authenticated members to modify their
   * personal details such as display name, biography, and other profile
   * attributes.
   *
   * The operation validates that the target username exists in the system and
   * ensures that the requesting user has appropriate permissions to update the
   * specified member profile. Only the member themselves or users with
   * administrative privileges can modify member profiles.
   *
   * Security considerations include authentication verification and
   * authorization checks to prevent unauthorized profile modifications. The
   * operation performs validation on all input fields to ensure data integrity
   * and consistency with the database schema constraints.
   *
   * This operation integrates with the discussion_board_members table as
   * defined in the Prisma schema, incorporating all updatable member fields
   * while respecting unique constraints on email and username fields. The
   * response returns the updated member profile with all current information.
   *
   * @param connection
   * @param username Unique username identifier of the target member to update
   * @param body Member profile update data including fields to modify
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("username")
    username: string,
    @TypedBody()
    body: IDiscussionBoardMember.IUpdate,
  ): Promise<IDiscussionBoardMember> {
    try {
      return await putDiscussionBoardMemberMembersUsername({
        member,
        username,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Perform a soft deletion of a member account using their unique username
   * identifier. This operation marks the member account as deleted by setting
   * the deleted_at timestamp while preserving all account data for potential
   * future restoration or audit purposes.
   *
   * The operation validates that the target username exists in the system and
   * ensures that the requesting user has appropriate permissions to delete the
   * specified member account. Only the member themselves or users with
   * administrative privileges can delete member accounts.
   *
   * Security considerations include authentication verification and
   * authorization checks to prevent unauthorized account deletions. The soft
   * deletion approach preserves data integrity and allows for account recovery
   * if needed, while removing the member from active participation in the
   * discussion board.
   *
   * This operation integrates with the discussion_board_members table as
   * defined in the Prisma schema, utilizing the soft delete mechanism through
   * the deleted_at field. The operation returns the deleted member profile
   * information as confirmation of the deletion action.
   *
   * @param connection
   * @param username Unique username identifier of the target member to delete
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("username")
    username: string,
  ): Promise<IDiscussionBoardMember> {
    try {
      return await deleteDiscussionBoardMemberMembersUsername({
        member,
        username,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
