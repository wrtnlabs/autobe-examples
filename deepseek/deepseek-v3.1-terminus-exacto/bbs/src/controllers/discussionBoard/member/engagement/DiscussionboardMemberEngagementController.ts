import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IDiscussionBoardArticle } from "../../../../api/structures/IDiscussionBoardArticle";
import { IPageIDiscussionBoardArticle } from "../../../../api/structures/IPageIDiscussionBoardArticle";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { patchDiscussionBoardMemberEngagement } from "../../../../providers/patchDiscussionBoardMemberEngagement";

@Controller("/discussionBoard/member/engagement")
export class DiscussionboardMemberEngagementController {
  /**
   * Retrieve articles filtered by engagement metrics and activity levels.
   *
   * This operation provides advanced search capabilities for discovering popular and trending content based on user engagement patterns. Users can find articles with high reaction counts, extensive comment discussions, or significant view statistics.
   *
   * The response includes article summaries enriched with engagement metrics such as total reaction counts, comment statistics, and view analytics. This enables users to identify trending topics and high-engagement content within the discussion community.
   *
   * Supports filtering by engagement thresholds, time periods, and content categories. Results are paginated for efficient browsing of large result sets.
   *
   * @param connection
   * @param body Engagement search criteria and filtering parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query engagement metrics across articles with filtering capabilities.
   *
   * Search for articles based on engagement criteria including:
   * - Reaction counts (like, helpful, insightful)
   * - View statistics and popularity
   * - Comment activity levels
   * - Time-based engagement trends
   *
   * Join with discussion_board_articles, discussion_board_article_reactions, discussion_board_article_view_stats, and discussion_board_mv_article_comments for comprehensive metrics.
   * Apply pagination and sorting by engagement metrics (most viewed, most commented, highest reactions).
   * Return article summaries with embedded engagement statistics for efficient listing.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IDiscussionBoardArticle.IRequest,
  ): Promise<IPageIDiscussionBoardArticle.ISummary> {
    try {
      return await patchDiscussionBoardMemberEngagement({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
