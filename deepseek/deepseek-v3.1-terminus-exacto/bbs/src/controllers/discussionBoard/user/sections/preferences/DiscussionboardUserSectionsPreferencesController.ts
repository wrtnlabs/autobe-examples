  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("sectionId")
    sectionId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardSectionPreference> {
    try {
      return await getDiscussionBoardUserSectionsSectionIdPreferences({
        user,
        sectionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

