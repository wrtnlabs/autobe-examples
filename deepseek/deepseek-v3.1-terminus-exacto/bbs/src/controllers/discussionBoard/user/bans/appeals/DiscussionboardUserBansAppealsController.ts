import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IDiscussionBoardBanAppeal } from "../../../../../api/structures/IDiscussionBoardBanAppeal";
import { UserAuth } from "../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../decorators/payload/UserPayload";
import { getDiscussionBoardUserBansBanIdAppealsAppealId } from "../../../../../providers/getDiscussionBoardUserBansBanIdAppealsAppealId";
import { postDiscussionBoardUserBansBanIdAppeals } from "../../../../../providers/postDiscussionBoardUserBansBanIdAppeals";

@Controller("/discussionBoard/user/bans/:banId/appeals")
export class DiscussionboardUserBansAppealsController {
  /**
   * Retrieve detailed information about a specific ban appeal for administrative review.
   *
   * This operation provides administrators with comprehensive details about an individual ban appeal, including the user's appeal reason, current status, review timeline, and any administrator decisions. The response includes all relevant timestamps and workflow status information needed for proper appeal evaluation.
   *
   * Administrators can use this operation to review appeal details before making decisions, track appeal progress, and maintain transparency in the moderation process. The operation ensures that appeal information is accessible only to authorized administrators with appropriate permissions.
   *
   * Related operations include listing all appeals for a ban record and updating appeal status during the review process.
   *
   * @param connection
   * @param banId Unique identifier of the ban record containing the appeal
   * @param appealId Unique identifier of the specific ban appeal to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Query the discussion_board_ban_appeals table by ID to retrieve a specific ban appeal. Include related ban record information and reviewer details if available. Validate that the appeal belongs to the specified ban record. Return complete appeal details with timestamps and status information.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":appealId")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("banId")
    banId: string & tags.Format<"uuid">,
    @TypedParam("appealId")
    appealId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardBanAppeal> {
    try {
      return await getDiscussionBoardUserBansBanIdAppealsAppealId({
        user,
        banId,
        appealId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Create a new appeal against an existing ban decision.
   *
   * This operation allows users to contest ban decisions by submitting an appeal with a detailed reason explaining why they believe the ban should be overturned. The appeal initiates a formal review process where administrators will evaluate the merits of the appeal against the original ban reason.
   *
   * Appeals must include a comprehensive explanation of at least 10 characters detailing why the ban decision should be reconsidered. The appeal enters a workflow with status tracking from initial submission through administrator review and final decision. Users can only submit one appeal per ban record and cannot appeal bans that have already been overturned or expired.
   *
   * The response includes the complete appeal record with system-generated timestamps and initial status, allowing users to verify their appeal was properly submitted and track its progress through the moderation workflow.
   *
   * @param connection
   * @param banId Unique identifier of the ban record being appealed
   * @param body Appeal information including the user's reason for contesting the ban
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Validate that the banId exists in discussion_board_ban_records before processing appeal. Verify that the current user has permission to appeal this ban (typically the banned user themselves). Ensure appeal_reason meets minimum 10 character requirement as per business rules. Set initial status to 'pending' and record appeal timestamp. Prevent duplicate appeals for the same ban record by the same user. Implement proper transaction handling to maintain data integrity.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @UserAuth()
    user: UserPayload,
    @TypedParam("banId")
    banId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardBanAppeal.ICreate,
  ): Promise<IDiscussionBoardBanAppeal> {
    try {
      return await postDiscussionBoardUserBansBanIdAppeals({
        user,
        banId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
