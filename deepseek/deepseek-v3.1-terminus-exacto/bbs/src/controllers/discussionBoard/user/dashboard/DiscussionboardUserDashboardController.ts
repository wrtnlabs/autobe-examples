import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IDiscussionBoardSuperAdmin } from "../../../../api/structures/IDiscussionBoardSuperAdmin";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { getDiscussionBoardUserDashboard } from "../../../../providers/getDiscussionBoardUserDashboard";

@Controller("/discussionBoard/user/dashboard")
export class DiscussionboardUserDashboardController {
  /**
   * Retrieve comprehensive dashboard statistics and system overview for the discussion board platform.
   *
   * This operation provides administrators with a complete overview of platform health, user engagement, content activity, and system performance. The dashboard includes key metrics such as total user count, article publication rates, comment activity levels, and section-specific statistics.
   *
   * Administrators can use this dashboard to monitor platform growth, identify trending sections, track user engagement patterns, and assess overall system performance. The data supports decision-making for content moderation, feature prioritization, and resource allocation.
   *
   * The response includes section-by-section breakdowns showing article distribution and engagement metrics, allowing administrators to identify popular topics and areas needing attention. Recent system activities provide insight into current platform usage patterns.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Query multiple database tables to aggregate dashboard statistics:
   * - Count total users from discussion_board_users (excluding deleted)
   * - Count total articles from discussion_board_articles (excluding deleted)
   * - Count total comments from discussion_board_comments (excluding deleted)
   * - Get section statistics with article counts from discussion_board_section_statistics
   * - Get recent system activities for activity feed from discussion_board_system_activities
   * - Calculate platform-wide engagement metrics
   * - Return aggregated data optimized for dashboard display
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @UserAuth()
    user: UserPayload,
  ): Promise<IDiscussionBoardSuperAdmin> {
    try {
      return await getDiscussionBoardUserDashboard({
        user,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
