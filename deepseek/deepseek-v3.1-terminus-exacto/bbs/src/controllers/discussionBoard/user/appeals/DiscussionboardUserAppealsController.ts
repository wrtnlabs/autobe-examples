import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IDiscussionBoardBanAppeal } from "../../../../api/structures/IDiscussionBoardBanAppeal";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { postDiscussionBoardUserAppeals } from "../../../../providers/postDiscussionBoardUserAppeals";

@Controller("/discussionBoard/user/appeals")
export class DiscussionboardUserAppealsController {
  /**
   * Submit a new ban appeal to contest a ban decision.
   *
   * This operation allows users who have been banned to formally appeal their ban by providing a detailed explanation of why they believe the ban should be overturned. The appeal is submitted to the moderation system for administrator review.
   *
   * When an appeal is created, it enters the 'pending' status and awaits review by an administrator. The appeal includes the user's justification for why the ban decision was incorrect or unfair. Administrators will review the appeal along with the original ban context to make a fair decision.
   *
   * Users can only appeal bans that are currently active and assigned to them. Each ban record can have only one active appeal at a time. The appeal process provides transparency and due process for users who believe they were banned unfairly.
   *
   * Related operations include viewing appeal status updates and administrator review workflows for processing appeals. The appeal system ensures that ban decisions can be contested through a structured review process.
   *
   * Security considerations: Only authenticated users who are currently banned can access this operation. The system validates that the ban record exists and belongs to the requesting user before allowing appeal submission.
   *
   * @param connection
   * @param body Ban appeal creation information including the appeal reason
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Create a new ban appeal record in the discussion_board_ban_appeals table.
   *
   * Validate that the ban record exists and belongs to the authenticated user.
   * Set initial status to 'pending' and timestamp the appeal submission.
   * Link the appeal to the user's ID from authentication context.
   * Ensure the ban record is currently active and not already appealed.
   * Return the complete appeal record with all fields populated.
   *
   * Business rules:
   * - Only banned users can submit appeals
   * - One appeal per ban record maximum
   * - Appeal reason must meet minimum content requirements
   * - Status transitions follow predefined workflow
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: IDiscussionBoardBanAppeal.ICreate,
  ): Promise<IDiscussionBoardBanAppeal> {
    try {
      return await postDiscussionBoardUserAppeals({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
