import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IDiscussionBoardArticle } from "../../../../../../api/structures/IDiscussionBoardArticle";
import { IPageIDiscussionBoardArticle } from "../../../../../../api/structures/IPageIDiscussionBoardArticle";
import { UserAuth } from "../../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../../decorators/payload/UserPayload";
import { patchDiscussionBoardUserArticlesSearchTags } from "../../../../../../providers/patchDiscussionBoardUserArticlesSearchTags";

@Controller("/discussionBoard/user/articles/search/tags")
export class DiscussionboardUserArticlesSearchTagsController {
  /**
   * Search for articles by tag filtering with advanced search capabilities.
   *
   * This operation allows users to find articles based on specific tags assigned to them. The search supports multiple tag selection with flexible filtering options including exact tag matching and tag combination logic.
   *
   * The system searches across the discussion_board_article_tags junction table to identify articles that match the specified tag criteria. Results include article summaries optimized for list displays with essential metadata.
   *
   * Security considerations ensure that only published articles are returned in search results, respecting article status and user permissions. The operation integrates with the discussion board's comprehensive tagging system for efficient content discovery.
   *
   * Related operations include general article search, section-based article browsing, and individual article retrieval for detailed content viewing.
   *
   * @param connection
   * @param body Tag search criteria and pagination parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Query discussion_board_articles table joined with discussion_board_article_tags for tag filtering. Support multiple tag filtering with AND/OR logic. Apply pagination and sorting options. Return article summaries with basic information including title, author, tags, comment count, and timestamp.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async search(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: IDiscussionBoardArticle.IRequest,
  ): Promise<IPageIDiscussionBoardArticle.ISummary> {
    try {
      return await patchDiscussionBoardUserArticlesSearchTags({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
