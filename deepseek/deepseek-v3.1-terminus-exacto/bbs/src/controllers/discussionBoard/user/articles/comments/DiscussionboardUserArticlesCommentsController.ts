import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IDiscussionBoardComment } from "../../../../../api/structures/IDiscussionBoardComment";
import { UserAuth } from "../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../decorators/payload/UserPayload";
import { deleteDiscussionBoardUserArticlesArticleIdCommentsCommentId } from "../../../../../providers/deleteDiscussionBoardUserArticlesArticleIdCommentsCommentId";
import { postDiscussionBoardUserArticlesArticleIdComments } from "../../../../../providers/postDiscussionBoardUserArticlesArticleIdComments";
import { putDiscussionBoardUserArticlesArticleIdCommentsCommentId } from "../../../../../providers/putDiscussionBoardUserArticlesArticleIdCommentsCommentId";

@Controller("/discussionBoard/user/articles/:articleId/comments")
export class DiscussionboardUserArticlesCommentsController {
  /**
   * Create a new comment on an existing discussion board article.
   *
   * This operation allows authenticated users to participate in discussions by adding comments to articles. The comment is associated with the specified article and the authenticated user's account. The system validates that the article exists and is accessible before creating the comment.
   *
   * Comments are single-level only as specified in requirements, with no nested reply functionality. Each comment contains the user's text content and is automatically timestamped for creation and modification tracking. The operation enforces content validation rules including minimum length requirements.
   *
   * After successful creation, the complete comment object is returned including the generated UUID identifier, content, author information, article association, and timestamps. This allows the client to immediately display the new comment without additional API calls.
   *
   * @param connection
   * @param articleId UUID of the article to comment on
   * @param body Comment creation data including content
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Create a new comment on the specified article. Validate that the article exists and is accessible. Ensure the authenticated user has permission to comment (not banned). Store the comment content with author and article associations. Return the created comment with all fields populated including timestamps.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @UserAuth()
    user: UserPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardComment.ICreate,
  ): Promise<IDiscussionBoardComment> {
    try {
      return await postDiscussionBoardUserArticlesArticleIdComments({
        user,
        articleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update the content of a specific comment on an article.
   *
   * This operation allows authenticated users to modify their own comments on articles. Users can update the comment text content while maintaining the original article association and authorship. The operation validates that the requesting user owns the comment and that the comment exists within the specified article.
   *
   * The system enforces content validation rules including minimum character requirements to maintain discussion quality. Only the comment content field can be modified through this operation - the author, article association, and creation timestamp remain unchanged.
   *
   * Users must have appropriate permissions to update comments. Regular users can only update their own comments, while administrators have broader editing capabilities as defined by their privilege level.
   *
   * @param connection
   * @param articleId UUID of the article containing the comment
   * @param commentId UUID of the comment to update
   * @param body Updated comment content
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Validate that the authenticated user owns the comment before allowing update. Check that the comment exists and belongs to the specified article. Validate the new content meets minimum length requirements. Update the comment content and updated_at timestamp. Return the updated comment with author information.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":commentId")
  public async update(
    @UserAuth()
    user: UserPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardComment.IUpdate,
  ): Promise<IDiscussionBoardComment> {
    try {
      return await putDiscussionBoardUserArticlesArticleIdCommentsCommentId({
        user,
        articleId,
        commentId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a specific comment from an article.
   *
   * This operation allows authenticated users to delete their own comments from articles. Administrators have the additional capability to delete any comment regardless of ownership. The deletion uses a soft-delete approach, marking the comment as deleted by setting the deleted_at timestamp while preserving the comment record for audit purposes.
   *
   * Authorization is enforced based on user roles. Regular users can only delete comments they authored, while administrators can delete any comment. The system validates that the specified comment exists and belongs to the referenced article before proceeding with deletion. The operation references the deleted_at column in the discussion_board_comments table which stores the soft deletion status.
   *
   * Successful deletion returns no content (204 status). If the comment doesn't exist, doesn't belong to the specified article, or the user lacks permission, appropriate error responses are returned. This operation integrates with the discussion_board_comments table which stores comment content, author information, and deletion status.
   *
   * Related operations include creating comments (POST /articles/{articleId}/comments), editing comments (PUT /articles/{articleId}/comments/{commentId}), and viewing comments (GET /articles/{articleId}/comments).
   *
   * @param connection
   * @param articleId UUID of the article containing the comment
   * @param commentId UUID of the comment to delete
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Delete a specific comment by setting its deleted_at timestamp. First validate that the comment exists and belongs to the specified article. Check authorization: users can only delete their own comments unless they have administrator privileges. Use a transaction to ensure atomicity. Return 404 if comment doesn't exist or doesn't belong to the article, 403 if user lacks permission, and 204 on successful deletion.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":commentId")
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteDiscussionBoardUserArticlesArticleIdCommentsCommentId({
        user,
        articleId,
        commentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
