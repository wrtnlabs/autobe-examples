@Controller("/discussionBoard/user/search/articles")
export class DiscussionboardUserSearchArticlesController {
  /**
   * Search for articles across the discussion board platform with advanced filtering capabilities.
   *
   * This operation provides comprehensive search functionality allowing users to find articles based on text matching in titles and content, combined with tag-based filtering. The search supports partial matching, relevance ranking, and paginated results for efficient browsing.
   *
   * Search results include essential article information optimized for list displays, including article title, author display name, associated tags, comment count, and publication timestamp. The system supports complex search criteria including boolean operators and phrase matching as specified in the requirements documentation.
   *
   * Security considerations ensure that only published articles are returned in search results, with appropriate access controls based on user permissions and section visibility settings.
   *
   * @param connection
   * @param body Search criteria including text query, tag filters, and pagination parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Query discussion_board_articles table with full-text search on title and content fields using PostgreSQL trigram matching. Support tag filtering by joining with discussion_board_article_tags table. Apply pagination with configurable page sizes and cursor-based navigation. Return articles sorted by relevance or timestamp as specified in search criteria. Include article summary information: title, author display name, tags, comment count (from related comments table), and timestamps.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async search(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: IDiscussionBoardArticle.IRequest,
  ): Promise<IPageIDiscussionBoardArticle.ISummary> {
    try {
      return await patchDiscussionBoardUserSearchArticles({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
