import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IDiscussionBoardSection } from "../../../../api/structures/IDiscussionBoardSection";
import { IPageIDiscussionBoardSection } from "../../../../api/structures/IPageIDiscussionBoardSection";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { patchDiscussionBoardUserBrowse } from "../../../../providers/patchDiscussionBoardUserBrowse";

@Controller("/discussionBoard/user/browse")
export class DiscussionboardUserBrowseController {
  /**
   * Search and retrieve a paginated list of active discussion board sections with filtering capabilities.
   *
   * This operation provides advanced browsing functionality for sections, allowing users to search by name, filter by status, and sort results alphabetically or by activity level. The operation queries the discussion_board_sections table and joins with discussion_board_section_statistics to include comprehensive metrics.
   *
   * Each section summary includes the section name, description, current status, article count from discussion_board_section_statistics, and last activity timestamp. Users can filter sections by status ('active', 'inactive', 'archived') and search within section names and descriptions using text matching.
   *
   * The response provides paginated results with metadata for efficient navigation through large result sets. This operation forms the core of the section browsing experience on the discussion board platform, enabling users to discover relevant content areas.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for section browsing
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Query the discussion_board_sections table filtering by status, name search, and other criteria. Join with discussion_board_section_statistics to include article counts. Apply pagination with configurable page size and sorting options. Support search functionality for section names and descriptions. Return summary information including section name, description, article count, and other relevant metrics.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: IDiscussionBoardSection.IRequest,
  ): Promise<IPageIDiscussionBoardSection.ISummary> {
    try {
      return await patchDiscussionBoardUserBrowse({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
