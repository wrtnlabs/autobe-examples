import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IDiscussionBoardBanAppeal } from "../../../../../api/structures/IDiscussionBoardBanAppeal";
import { IPageIDiscussionBoardBanAppeal } from "../../../../../api/structures/IPageIDiscussionBoardBanAppeal";
import { UserAuth } from "../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../decorators/payload/UserPayload";
import { getDiscussionBoardUserBanRecordsBanRecordIdAppeals } from "../../../../../providers/getDiscussionBoardUserBanRecordsBanRecordIdAppeals";
import { postDiscussionBoardUserBanRecordsBanRecordIdAppeals } from "../../../../../providers/postDiscussionBoardUserBanRecordsBanRecordIdAppeals";

@Controller("/discussionBoard/user/ban-records/:banRecordId/appeals")
export class DiscussionboardUserBan_recordsAppealsController {
  /**
   * Retrieve all ban appeals submitted against a specific ban record.
   *
   * This operation provides administrators with access to the complete appeal history for a particular ban decision. Each appeal record includes the user's appeal reason, current appeal status, submission timestamp, and review information if the appeal has been processed.
   *
   * The response includes paginated results showing appeal summaries with essential information for review purposes. Administrators can use this operation to monitor appeal workflows, track appeal processing times, and ensure timely review of user appeals against ban decisions.
   *
   * Appeal records are linked to the specific ban record through the discussion_board_ban_record_id foreign key relationship, ensuring accurate tracking of which ban decision each appeal contests. The operation supports the platform's commitment to transparent moderation practices by providing clear audit trails for ban-related actions.
   *
   * @param connection
   * @param banRecordId Unique identifier of the ban record for which to retrieve appeals
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Query the discussion_board_ban_appeals table filtering by discussion_board_ban_record_id equal to the path parameter. Join with discussion_board_users to get user display names and discussion_board_admins to get reviewer information if available. Apply pagination using cursor-based or offset-based approach. Sort by appealed_at descending to show newest appeals first. Return summary information including appeal status, appeal reason, user display name, and timestamps.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedParam("banRecordId")
    banRecordId: string & tags.Format<"uuid">,
  ): Promise<IPageIDiscussionBoardBanAppeal.ISummary> {
    try {
      return await getDiscussionBoardUserBanRecordsBanRecordIdAppeals({
        user,
        banRecordId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Submit an appeal against a ban decision.
   *
   * This operation allows users to formally contest a ban decision by providing an appeal reason. The appeal is created with 'pending' status and awaits administrator review. Users can only appeal bans that affect their own account.
   *
   * The appeal process provides transparency and due process for moderation actions, allowing users to present their case for reconsideration. Administrators will review the appeal and make a final decision based on the provided reason and ban context.
   *
   * Appeals are linked to specific ban records and include timestamps for tracking the appeal workflow. Users can only submit one appeal per ban record.
   *
   * @param connection
   * @param banRecordId The unique identifier of the ban record being appealed
   * @param body Ban appeal submission details
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Create a new ban appeal record in the discussion_board_ban_appeals table. Validate that the ban record exists and is active. Set initial status to 'pending'. Store the appeal reason and link it to the ban record and appealing user. Ensure the user has permission to appeal this ban (typically the banned user themselves).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @UserAuth()
    user: UserPayload,
    @TypedParam("banRecordId")
    banRecordId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardBanAppeal.ICreate,
  ): Promise<IDiscussionBoardBanAppeal> {
    try {
      return await postDiscussionBoardUserBanRecordsBanRecordIdAppeals({
        user,
        banRecordId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
