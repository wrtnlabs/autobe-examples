import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IDiscussionBoardUser } from "../../../api/structures/IDiscussionBoardUser";
import { IPageIDiscussionBoardUser } from "../../../api/structures/IPageIDiscussionBoardUser";
import { getDiscussionBoardUsersUserId } from "../../../providers/getDiscussionBoardUsersUserId";
import { patchDiscussionBoardUsers } from "../../../providers/patchDiscussionBoardUsers";

@Controller("/discussionBoard/users")
export class DiscussionboardUsersController {
  /**
   * Search and retrieve a paginated list of user accounts with filtering capabilities.
   *
   * This operation provides advanced search functionality for user accounts across the discussion board platform. It supports filtering by display name (with partial matching), email address (exact or domain-based filtering), and account status. The response includes user summary information suitable for list displays and user browsing interfaces.
   *
   * Supports comprehensive pagination with configurable page sizes and sorting options. Users can search for specific individuals or browse user profiles based on various criteria. The operation respects user privacy by excluding sensitive authentication data from the response.
   *
   * This endpoint is particularly useful for administrators managing user accounts, community members looking for specific contributors, or system administrators performing user account maintenance tasks.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for user filtering
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query discussion_board_users table with pagination and filtering capabilities. Apply search filters on display_name (partial matching), email (exact or domain matching), and account status (active/deleted). Support cursor-based pagination for efficient large result sets. Return user summaries optimized for list displays without sensitive information like password_hash.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IDiscussionBoardUser.IRequest,
  ): Promise<IPageIDiscussionBoardUser.ISummary> {
    try {
      return await patchDiscussionBoardUsers({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a user's public profile information.
   *
   * This operation returns the public-facing profile data for a specific user, including their display name, biography text, and account creation/update timestamps. The response provides essential profile information suitable for display to other users on the platform.
   *
   * User profiles serve as public identities within the discussion board community, allowing users to learn about each other's backgrounds and interests. The profile data is designed to balance transparency with privacy by excluding sensitive information like email addresses.
   *
   * This operation integrates with the article and comment systems to provide comprehensive user activity tracking, though the actual article and comment lists are retrieved through separate API endpoints for performance optimization.
   *
   * @param connection
   * @param userId Unique identifier of the user whose profile is being retrieved
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query the discussion_board_users table by userId parameter. Return the user's display_name, bio, created_at, and updated_at fields. Exclude sensitive fields like email and password_hash. Validate that the user exists and account is active (not deleted).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":userId")
  public async at(
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardUser.ISummary> {
    try {
      return await getDiscussionBoardUsersUserId({
        userId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
