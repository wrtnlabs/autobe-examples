import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { patchDiscussionBoardSearchPosts } from "../../../../providers/patchDiscussionBoardSearchPosts";

import { IPageIDiscussionBoardPost } from "../../../../api/structures/IPageIDiscussionBoardPost";
import { IDiscussionBoardPost } from "../../../../api/structures/IDiscussionBoardPost";

@Controller("/discussionBoard/search/posts")
export class DiscussionboardSearchPostsController {
  /**
   * Search and retrieve filtered discussion board posts with pagination.
   *
   * This operation enables users to search through discussion board posts using
   * advanced filtering criteria and pagination controls. It supports searching
   * by post title, content text, channel categorization, section organization,
   * post status, pinning status, and creation date ranges.
   *
   * The search functionality leverages full-text indexing on title and content
   * fields to provide efficient text-based searching. Users can filter results
   * by specific channels or sections to narrow down discussions to particular
   * topics. The operation also supports filtering by post status (draft,
   * published, archived) and pinning status to focus on active or featured
   * content.
   *
   * Pagination is implemented with configurable page sizes and sorting options,
   * allowing users to browse large result sets efficiently. Results can be
   * sorted by creation date, update date, publication date, or relevance score
   * when using text search. The operation integrates with the
   * discussion_board_posts table and maintains proper relationship references
   * to channels and sections.
   *
   * Security considerations include appropriate access controls based on post
   * status and user permissions. Published posts are generally accessible to
   * all users, while draft posts are restricted to authors and moderators. The
   * operation implements rate limiting to prevent abuse and ensures efficient
   * database query performance through proper indexing.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for post filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async search(
    @TypedBody()
    body: IDiscussionBoardPost.IRequest,
  ): Promise<IPageIDiscussionBoardPost.ISummary> {
    try {
      return await patchDiscussionBoardSearchPosts({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
