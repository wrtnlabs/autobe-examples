import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IDiscussionBoardArticle } from "../../../../api/structures/IDiscussionBoardArticle";
import { IPageIDiscussionBoardArticle } from "../../../../api/structures/IPageIDiscussionBoardArticle";
import { SuperadminAuth } from "../../../../decorators/SuperadminAuth";
import { SuperadminPayload } from "../../../../decorators/payload/SuperadminPayload";
import { patchDiscussionBoardSuperAdminEngagement } from "../../../../providers/patchDiscussionBoardSuperAdminEngagement";

@Controller("/discussionBoard/superAdmin/engagement")
export class DiscussionboardSuperadminEngagementController {
  /**
   * Retrieve articles filtered by engagement metrics and activity levels for administrative oversight.
   *
   * This operation provides super administrators with advanced analytics capabilities for monitoring content engagement patterns across the platform. It enables identification of trending articles, high-engagement discussions, and community activity hotspots based on comprehensive metrics including reaction counts, view statistics, and comment activity.
   *
   * The response includes article summaries enriched with detailed engagement analytics such as total reaction breakdowns, comment volume trends, and viewership patterns. This supports administrative oversight by highlighting content that drives community participation and requires moderation attention.
   *
   * Supports filtering by engagement thresholds, time periods, and content categories specifically for administrative reporting purposes. Results are paginated for efficient analysis of platform-wide engagement patterns.
   *
   * @param connection
   * @param body Engagement search criteria and filtering parameters for administrative analytics
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification Query engagement metrics across articles with filtering capabilities.
   *
   * Search for articles based on engagement criteria including:
   * - Reaction counts (like, helpful, insightful)
   * - View statistics and popularity
   * - Comment activity levels
   * - Time-based engagement trends
   *
   * Join with discussion_board_articles, discussion_board_article_reactions, discussion_board_article_view_stats, and discussion_board_mv_article_comments for comprehensive metrics.
   * Apply pagination and sorting by engagement metrics (most viewed, most commented, highest reactions).
   * Return article summaries with embedded engagement statistics for efficient listing.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SuperadminAuth()
    superAdmin: SuperadminPayload,
    @TypedBody()
    body: IDiscussionBoardArticle.IRequest,
  ): Promise<IPageIDiscussionBoardArticle.ISummary> {
    try {
      return await patchDiscussionBoardSuperAdminEngagement({
        superAdmin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
