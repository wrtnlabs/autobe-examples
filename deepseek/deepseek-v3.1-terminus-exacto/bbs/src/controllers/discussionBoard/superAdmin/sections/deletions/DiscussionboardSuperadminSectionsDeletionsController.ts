import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IDiscussionBoardSectionDeletion } from "../../../../../api/structures/IDiscussionBoardSectionDeletion";
import { IPageIDiscussionBoardSectionDeletion } from "../../../../../api/structures/IPageIDiscussionBoardSectionDeletion";
import { SuperadminAuth } from "../../../../../decorators/SuperadminAuth";
import { SuperadminPayload } from "../../../../../decorators/payload/SuperadminPayload";
import { getDiscussionBoardSuperAdminSectionsSectionIdDeletions } from "../../../../../providers/getDiscussionBoardSuperAdminSectionsSectionIdDeletions";
import { patchDiscussionBoardSuperAdminSectionsDeletions } from "../../../../../providers/patchDiscussionBoardSuperAdminSectionsDeletions";

@Controller("/discussionBoard/superAdmin/sections")
export class DiscussionboardSuperadminSectionsDeletionsController {
  /**
   * Retrieve the deletion record for a specific discussion board section.
   *
   * This operation allows super administrators to view the audit trail of section deletions, including who performed the deletion, when it occurred, and the reason provided. The response includes complete deletion metadata that maintains referential integrity while preserving section deletion history.
   *
   * Super administrators can use this endpoint to review section management actions and understand the context behind section removals. The deletion record maintains links to the original section and the administrator who performed the deletion action.
   *
   * This operation complements section management workflows by providing visibility into deletion history without requiring direct database access. It supports administrative oversight and compliance requirements for section lifecycle management.
   *
   * @param connection
   * @param sectionId Unique identifier of the section for which to retrieve deletion records
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification Query the discussion_board_section_deletions table filtered by discussion_board_section_id matching the provided sectionId parameter. Join with discussion_board_members to include administrator information who performed the deletion. Return the deletion record with full context including deletion reason and timestamps. Validate that the section exists and has a deletion record before returning data.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sectionId/deletions")
  public async invert(
    @SuperadminAuth()
    superAdmin: SuperadminPayload,
    @TypedParam("sectionId")
    sectionId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardSectionDeletion> {
    try {
      return await getDiscussionBoardSuperAdminSectionsSectionIdDeletions({
        superAdmin,
        sectionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve a paginated list of section deletion records with filtering capabilities.
   *
   * This operation provides administrators with comprehensive audit trail access for section deletion activities. It enables searching through deletion records based on various criteria including the administrator who performed the deletion, date ranges, and section information. The response includes paginated results with summary information suitable for administrative dashboards and audit reports.
   *
   * Administrators can use this operation to monitor section management activities, track deletion patterns, and review administrative actions. The search functionality supports complex filtering to help identify specific deletion events or patterns across the platform.
   *
   * The operation maintains referential integrity by joining with related tables to provide complete context for each deletion record, including section details and administrator information.
   *
   * @param connection
   * @param body Search criteria including deletion actor, date ranges, and section information with pagination for section deletion records
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification Query discussion_board_section_deletions table with pagination and filtering capabilities. Join with discussion_board_sections to include section name and description. Join with discussion_board_members to include member information for the deletion actor. Support filtering by deleted_by_member_id, creation date ranges, and section name patterns. Return paginated results with summary information optimized for administrative review.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch("deletions")
  public async index(
    @SuperadminAuth()
    superAdmin: SuperadminPayload,
    @TypedBody()
    body: IDiscussionBoardSectionDeletion.IRequest,
  ): Promise<IPageIDiscussionBoardSectionDeletion.ISummary> {
    try {
      return await patchDiscussionBoardSuperAdminSectionsDeletions({
        superAdmin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
