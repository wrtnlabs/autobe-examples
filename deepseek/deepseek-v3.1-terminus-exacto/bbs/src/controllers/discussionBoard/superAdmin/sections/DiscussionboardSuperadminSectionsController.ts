import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IDiscussionBoardSection } from "../../../../api/structures/IDiscussionBoardSection";
import { SuperadminAuth } from "../../../../decorators/SuperadminAuth";
import { SuperadminPayload } from "../../../../decorators/payload/SuperadminPayload";
import { deleteDiscussionBoardSuperAdminSectionsSectionId } from "../../../../providers/deleteDiscussionBoardSuperAdminSectionsSectionId";
import { postDiscussionBoardSuperAdminSections } from "../../../../providers/postDiscussionBoardSuperAdminSections";
import { putDiscussionBoardSuperAdminSectionsSectionId } from "../../../../providers/putDiscussionBoardSuperAdminSectionsSectionId";

@Controller("/discussionBoard/superAdmin/sections")
export class DiscussionboardSuperadminSectionsController {
  /**
   * Create a new discussion board section for organizing articles by topic.
   *
   * This operation allows administrators to create new sections that serve as organizational categories for the discussion board platform. Each section represents a distinct topic area such as Politics, Economy, or Current Affairs, providing users with structured content browsing.
   *
   * The operation validates that the requesting user has administrator privileges (either regular admin or super admin) and ensures section name uniqueness across the platform. Upon successful creation, the section becomes immediately available for article posting and user browsing.
   *
   * Administrators can manage the section's display order to control how sections appear in the user interface. The system automatically sets the section status to 'active' and records the creation timestamp and administrator identity for audit purposes.
   *
   * Related operations include PATCH /sections for listing sections, GET /sections/{sectionId} for retrieving specific section details, and PUT /sections/{sectionId} for updating section information.
   *
   * @param connection
   * @param body Section creation information including name, description, and display order
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification Validate administrator permissions before allowing section creation. Check for unique section name constraint. Set default status as 'active' and generate UUID for id. Record creation timestamp and administrator identity. Return complete section entity with all fields populated.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SuperadminAuth()
    superAdmin: SuperadminPayload,
    @TypedBody()
    body: IDiscussionBoardSection.ICreate,
  ): Promise<IDiscussionBoardSection> {
    try {
      return await postDiscussionBoardSuperAdminSections({
        superAdmin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing discussion board section with new information.
   *
   * This operation allows administrators to modify section properties including the section name, description, status, and display order. The section ID is specified in the URL path, and all updatable fields are provided in the request body.
   *
   * Administrators must have appropriate permissions to modify sections. The operation validates that the section name remains unique across all active sections (excluding the current section being updated), as defined by the @@unique([name]) constraint in the discussion_board_sections table. Section status changes are tracked for audit purposes through the status field.
   *
   * The request body corresponds to the IDiscussionBoardSection.IUpdate type, which maps to the updatable fields in the discussion_board_sections table: name (unique section identifier), description (detailed content scope), status (active/inactive/archived), and display_order (UI sorting position).
   *
   * After successful update, the complete section entity is returned with the new values and updated timestamp. This operation supports the section management functionality required for maintaining the discussion board's organizational structure.
   *
   * Related operations include creating new sections (POST /sections), retrieving section details (GET /sections/{sectionId}), and listing all sections (PATCH /sections).
   *
   * @param connection
   * @param sectionId Unique identifier of the section to update
   * @param body Section update information including name, description, status, and display order
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification Update an existing section by ID. Validate that the authenticated user has administrator privileges. Check if the section exists and is not deleted. Validate the request body fields: name must be unique (excluding current section), description must be non-empty, status must be one of 'active', 'inactive', 'archived', display_order must be positive integer. Update the section fields and set updated_at timestamp. Return the updated section entity.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":sectionId")
  public async update(
    @SuperadminAuth()
    superAdmin: SuperadminPayload,
    @TypedParam("sectionId")
    sectionId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardSection.IUpdate,
  ): Promise<IDiscussionBoardSection> {
    try {
      return await putDiscussionBoardSuperAdminSectionsSectionId({
        superAdmin,
        sectionId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a discussion board section from the platform.
   *
   * This operation allows super administrators to remove sections from the discussion board platform. The deletion is permanent and irreversible, completely removing the section record from the database. This action should be performed with caution as it cannot be undone.
   *
   * Only users with super administrator privileges can perform this operation. The system validates that the section exists and has no dependent articles or comments before proceeding with deletion. If the section contains articles or comments, they must be handled according to platform configuration (either deleted along with the section or reassigned to a default section).
   *
   * The response includes the complete section information that was deleted, providing confirmation of the operation's success. This information can be used for audit purposes but cannot be used for restoration since the deletion is permanent.
   *
   * Related operations include creating sections (POST /sections), updating sections (PUT /sections/{sectionId}), and browsing sections (PATCH /sections). Super administrators should ensure proper backup procedures are in place before performing permanent deletions.
   *
   * @param connection
   * @param sectionId Unique identifier of the section to be deleted
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification Perform soft deletion of a discussion board section by setting the deleted_at timestamp. First verify that the requesting user has administrator privileges. Check if the section exists and is not already deleted. Update the deleted_at field with the current timestamp and return the deleted section information. Ensure referential integrity by handling any dependent articles or comments according to business rules (either cascade delete or reassign to default section).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":sectionId")
  public async erase(
    @SuperadminAuth()
    superAdmin: SuperadminPayload,
    @TypedParam("sectionId")
    sectionId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardSection> {
    try {
      return await deleteDiscussionBoardSuperAdminSectionsSectionId({
        superAdmin,
        sectionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
