import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IDiscussionBoardArticleSnapshot } from "../../../../../api/structures/IDiscussionBoardArticleSnapshot";
import { IPageIDiscussionBoardArticleSnapshot } from "../../../../../api/structures/IPageIDiscussionBoardArticleSnapshot";
import { SuperAdminAuth } from "../../../../../decorators/SuperAdminAuth";
import { SuperAdminPayload } from "../../../../../decorators/payload/SuperAdminPayload";
import { getDiscussionBoardSuperAdminArticlesArticleIdSnapshotsSnapshotId } from "../../../../../providers/getDiscussionBoardSuperAdminArticlesArticleIdSnapshotsSnapshotId";
import { patchDiscussionBoardSuperAdminArticlesArticleIdSnapshots } from "../../../../../providers/patchDiscussionBoardSuperAdminArticlesArticleIdSnapshots";

@Controller("/discussionBoard/superAdmin/articles/:articleId/snapshots")
export class DiscussionboardSuperadminArticlesSnapshotsController {
  /**
   * Retrieve a paginated list of article snapshots showing the edit history and version changes for a specific article.
   *
   * This operation provides access to the complete audit trail of article modifications, allowing users to track how content has evolved over time. Each snapshot represents a point-in-time state of the article, capturing title, content, section assignment, and author information at the moment of modification.
   *
   * The response includes snapshot summaries with creation timestamps and basic information, enabling users to compare versions and understand the article's editing history. Pagination ensures efficient loading even for articles with extensive edit histories.
   *
   * Administrators and article authors typically use this endpoint for content moderation, compliance tracking, and understanding the evolution of discussion board content. The snapshots support rollback capabilities and provide transparency about content changes.
   *
   * @param connection
   * @param articleId UUID identifier of the target article
   * @param body Pagination and filtering criteria for article snapshots
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification Query discussion_board_article_snapshots table filtered by article ID with pagination support. Apply date range filtering if specified in request criteria. Return snapshots ordered by created_at descending to show most recent edits first. Include basic snapshot information in summary format without full content for list view. Validate that the article exists and user has permission to view its snapshots.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SuperAdminAuth()
    superAdmin: SuperAdminPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardArticleSnapshot.IRequest,
  ): Promise<IPageIDiscussionBoardArticleSnapshot.ISummary> {
    try {
      return await patchDiscussionBoardSuperAdminArticlesArticleIdSnapshots({
        superAdmin,
        articleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific article snapshot by its unique identifier within the context of a parent article.
   *
   * This operation provides access to historical versions of articles through the snapshot system. Each snapshot represents a point-in-time capture of an article's state, including its title, content, section assignment, and author information at the moment the snapshot was created. The snapshot system supports audit trails, content moderation tracking, and version comparison capabilities.
   *
   * Security considerations require that users have appropriate permissions to access both the parent article and the specific snapshot. The operation validates that the snapshot belongs to the specified article before returning the data. Snapshots are read-only records that cannot be modified, providing an immutable audit trail of article changes.
   *
   * Related operations include retrieving the current version of an article through GET /articles/{articleId} and listing all snapshots for an article through GET /articles/{articleId}/snapshots. This operation is particularly useful for content moderation, auditing, and version comparison workflows.
   *
   * @param connection
   * @param articleId Unique identifier of the parent article
   * @param snapshotId Unique identifier of the article snapshot
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification Query the discussion_board_article_snapshots table to retrieve the specified snapshot. Validate that the snapshot belongs to the parent article by checking the discussion_board_article_id foreign key relationship. Return the complete snapshot data including title, content, section assignment, author information, and creation timestamp. Ensure that the operation returns a 404 error if either the article or snapshot does not exist, or if the snapshot does not belong to the specified article.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":snapshotId")
  public async at(
    @SuperAdminAuth()
    superAdmin: SuperAdminPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedParam("snapshotId")
    snapshotId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardArticleSnapshot> {
    try {
      return await getDiscussionBoardSuperAdminArticlesArticleIdSnapshotsSnapshotId(
        {
          superAdmin,
          articleId,
          snapshotId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
