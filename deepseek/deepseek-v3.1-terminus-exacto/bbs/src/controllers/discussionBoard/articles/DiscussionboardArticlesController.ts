import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IDiscussionBoardArticle } from "../../../api/structures/IDiscussionBoardArticle";
import { IPageIDiscussionBoardArticle } from "../../../api/structures/IPageIDiscussionBoardArticle";
import { getDiscussionBoardArticlesArticleId } from "../../../providers/getDiscussionBoardArticlesArticleId";
import { patchDiscussionBoardArticles } from "../../../providers/patchDiscussionBoardArticles";

@Controller("/discussionBoard/articles")
export class DiscussionboardArticlesController {
  /**
   * Retrieve a paginated and filtered list of article content from the discussion board platform.
   *
   * This operation queries the main article content table (discussion_board_articles) which stores all user-generated posts including title, body content, author reference, and section categorization. The response includes article summaries optimized for list displays, showing essential information like title, author display name, publication time, and comment count without exposing full article content.
   *
   * Search capabilities leverage PostgreSQL trigram indexes on title and body fields for efficient text matching. Filtering options include section categorization (discussion_board_section_id), article author (discussion_board_member_id), and current lifecycle status (published, edited, deleted). The operation supports comprehensive pagination with configurable page sizes to manage performance for large result sets.
   *
   * Authorization considerations: Regular users can only access published articles where deleted_at IS NULL. Administrators have access to additional status filtering for moderation purposes. Article summaries include author information from the discussion_board_members table, specifically the display_name field for user identification.
   *
   * Related operations include viewing individual articles (GET /articles/{id}) for detailed content and creating new articles (POST /articles). This search operation serves as the primary discovery mechanism for finding relevant discussions across all thematic sections in the platform.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering articles
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query discussion_board_articles table with pagination, filtering, and search capabilities.
   *
   * Implement pagination using cursor-based or offset-based approach with configurable page sizes.
   * Apply filters for section ID, author ID, status, and tag matching.
   * Support full-text search on title and body fields using PostgreSQL trigram indexes.
   * Implement sorting by creation date (newest/oldest first).
   * Join with discussion_board_members for author display names.
   * Count comments per article for the summary view.
   * Ensure proper authorization checks based on article status and user permissions.
   * Optimize queries using existing indexes on section_id, member_id, status, and created_at.
   * Handle concurrent access with appropriate transaction isolation levels.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IDiscussionBoardArticle.IRequest,
  ): Promise<IPageIDiscussionBoardArticle.ISummary> {
    try {
      return await patchDiscussionBoardArticles({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information for a specific article including full content, author details, section information, and associated comments.
   *
   * This operation provides complete article viewing capabilities for both authenticated and unauthenticated users. The response includes the article title, body content, creation timestamps, author profile information, section categorization, and all comments posted on the article. The operation queries the discussion_board_articles table by UUID identifier and joins with discussion_board_members for author details and discussion_board_sections for section information.
   *
   * Article content is returned in its full format with support for markdown or rich text rendering. Comments are returned in chronological order (oldest first) as specified in the business requirements. The operation performs necessary permission checks to ensure content visibility based on user authorization levels.
   *
   * Related operations include PATCH /articles for searching and filtering articles, GET /sections for browsing available sections, and POST /comments for adding new comments to articles.
   *
   * @param connection
   * @param articleId Unique identifier of the article to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query the discussion_board_articles table by primary key ID. Include author information from discussion_board_members via the discussion_board_member_id foreign key. Include section information from discussion_board_sections via the discussion_board_section_id foreign key. Load associated comments from discussion_board_comments ordered by creation timestamp. Validate that the article exists and is not deleted (deleted_at IS NULL). Return 404 if article not found or deleted.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":articleId")
  public async at(
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardArticle> {
    try {
      return await getDiscussionBoardArticlesArticleId({
        articleId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
