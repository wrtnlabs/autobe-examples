@Controller(
  "/discussionBoard/articles/:articleId/comments/:commentId/edit-histories",
)
export class DiscussionboardArticlesCommentsEdit_historiesController {
  /**
   * Search and filter comment edit history records for a specific comment within an article.
   *
   * This operation provides comprehensive search capabilities for tracking comment modification history. Users can filter by edit sequence numbers, search within original or edited content, and filter by date ranges.
   *
   * The response includes paginated summary information showing edit sequence, timestamps, and content comparison. This supports transparency and audit requirements for comment modification tracking across the discussion board platform.
   *
   * Note: This operation searches edit history records but does not provide editor attribution since the database schema does not include editor reference fields.
   *
   * @param connection
   * @param articleId ID of the article containing the target comment
   * @param commentId ID of the comment whose edit history is being searched
   * @param body Search criteria and pagination parameters for comment edit histories
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query discussion_board_comment_edit_histories table filtered by discussion_board_comment_id matching the commentId parameter. Apply search filters from request body including edit sequence ranges, content keyword search, date ranges, and editor type filtering. Join with subtype tables (users, admins, super_admins) to determine editor information if requested. Return paginated results sorted by edit sequence or creation date.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardCommentEditHistory.IRequest,
  ): Promise<IPageIDiscussionBoardCommentEditHistory.ISummary> {
    try {
      return await patchDiscussionBoardArticlesArticleIdCommentsCommentIdEditHistories(
        {
          articleId,
          commentId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific comment edit history entry for detailed audit and transparency purposes.
   *
   * This operation provides access to the complete edit history record of a comment, allowing users to see the evolution of comment content over time. The response includes both the original content before the edit and the edited content after the modification, along with the edit sequence number indicating the order of edits.
   *
   * Each edit history entry contains comprehensive metadata including the timestamp when the edit was recorded, the sequential edit number, and any edit reason provided by the editor. This supports transparency in content modification and helps users understand how comments have evolved.
   *
   * The operation requires valid article, comment, and edit history identifiers to ensure proper resource access. Users can only view edit history for comments they have permission to access, maintaining appropriate security boundaries.
   *
   * This API operation is particularly useful for moderation workflows, content audit trails, and user transparency features where understanding comment modification history is important for maintaining trust in the discussion platform.
   *
   * @param connection
   * @param articleId UUID identifier of the article containing the comment
   * @param commentId UUID identifier of the comment containing the edit history
   * @param editHistoryId UUID identifier of the specific edit history entry to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query the discussion_board_comment_edit_histories table using the provided editHistoryId parameter. Validate that the edit history record exists and belongs to the specified comment. Verify that the comment belongs to the specified article through the discussion_board_comments table relationship. Return the complete edit history record including original_content, edited_content, edit_sequence, edit_reason, and created_at fields. Include proper error handling for invalid IDs or permission violations.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":editHistoryId")
  public async at(
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
    @TypedParam("editHistoryId")
    editHistoryId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardCommentEditHistory> {
    try {
      return await getDiscussionBoardArticlesArticleIdCommentsCommentIdEditHistoriesEditHistoryId(
        {
          articleId,
          commentId,
          editHistoryId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
