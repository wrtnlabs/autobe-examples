import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IDiscussionBoardCommentMention } from "../../../../../api/structures/IDiscussionBoardCommentMention";
import { IPageIDiscussionBoardCommentMention } from "../../../../../api/structures/IPageIDiscussionBoardCommentMention";
import { getDiscussionBoardArticlesArticleIdCommentsCommentIdMentionsMentionId } from "../../../../../providers/getDiscussionBoardArticlesArticleIdCommentsCommentIdMentionsMentionId";
import { patchDiscussionBoardArticlesArticleIdCommentsCommentIdMentions } from "../../../../../providers/patchDiscussionBoardArticlesArticleIdCommentsCommentIdMentions";

@Controller("/discussionBoard/articles/:articleId/comments/:commentId/mentions")
export class DiscussionboardArticlesCommentsMentionsController {
  /**
   * Search and retrieve paginated list of user mentions within a specific comment.
   *
   * This operation provides advanced filtering capabilities for comment mentions, allowing administrators and users to find specific mentions based on mentioned users, position within the comment text, and creation time ranges. The search results include mention summary information with user references and position data.
   *
   * The operation requires comment scope validation and supports comprehensive pagination with configurable page sizes and sorting options. Response includes mention summary information optimized for list displays and moderation workflows. Note that mentions are scoped to individual comments only, not requiring article-level parameters for query filtering.
   *
   * @param connection
   * @param articleId Target article's ID containing the comment
   * @param commentId Target comment's ID containing the mentions
   * @param body Search criteria and pagination parameters for comment mentions
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query the discussion_board_comment_mentions table filtered by discussion_board_comment_id matching the path parameter. Apply search filters on mentioned user IDs, position ranges, and creation date ranges. Join with discussion_board_users to include mention target user information. Return paginated results with cursor-based pagination for large result sets.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardCommentMention.IRequest,
  ): Promise<IPageIDiscussionBoardCommentMention.ISummary> {
    try {
      return await patchDiscussionBoardArticlesArticleIdCommentsCommentIdMentions(
        {
          articleId,
          commentId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific user mention within a comment on an article.
   *
   * This operation returns the complete mention record including the character position range where the mention appears within the comment text, the mentioned user information, and creation timestamp. The mention must belong to the specified comment, which in turn must belong to the specified article.
   *
   * This endpoint is useful for notification systems where users need to see the context of mentions, or for moderation tools that track user interactions within the discussion platform. Only authenticated users can access this endpoint, and the system validates that the mention exists and belongs to the specified comment-article hierarchy before returning the data.
   *
   * The response includes all metadata needed to display the mention in context and link to the mentioned user's profile, supporting features like mention highlighting and user reference tracking within the discussion platform.
   *
   * @param connection
   * @param articleId Unique identifier of the article containing the comment
   * @param commentId Unique identifier of the comment containing the mention
   * @param mentionId Unique identifier of the specific mention record
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Retrieve a specific mention record by its ID, ensuring it belongs to the specified comment and article. Validate that all path parameters correspond to existing records with proper relationships. Return the complete mention details including position information and timestamps. Handle cases where the mention doesn't exist or doesn't belong to the specified comment/article hierarchy.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":mentionId")
  public async at(
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
    @TypedParam("mentionId")
    mentionId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardCommentMention> {
    try {
      return await getDiscussionBoardArticlesArticleIdCommentsCommentIdMentionsMentionId(
        {
          articleId,
          commentId,
          mentionId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
