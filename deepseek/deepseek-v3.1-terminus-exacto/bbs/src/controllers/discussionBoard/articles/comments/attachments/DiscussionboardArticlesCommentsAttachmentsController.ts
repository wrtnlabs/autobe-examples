import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IDiscussionBoardCommentAttachment } from "../../../../../api/structures/IDiscussionBoardCommentAttachment";
import { IPageIDiscussionBoardCommentAttachment } from "../../../../../api/structures/IPageIDiscussionBoardCommentAttachment";
import { getDiscussionBoardArticlesArticleIdCommentsCommentIdAttachmentsAttachmentId } from "../../../../../providers/getDiscussionBoardArticlesArticleIdCommentsCommentIdAttachmentsAttachmentId";
import { patchDiscussionBoardArticlesArticleIdCommentsCommentIdAttachments } from "../../../../../providers/patchDiscussionBoardArticlesArticleIdCommentsCommentIdAttachments";

@Controller(
  "/discussionBoard/articles/:articleId/comments/:commentId/attachments",
)
export class DiscussionboardArticlesCommentsAttachmentsController {
  /**
   * Search and retrieve a paginated list of file attachments for a specific comment within an article.
   *
   * This operation allows administrators and comment authors to search through file attachments associated with a particular comment. The search functionality supports filtering by file name patterns, file types, and creation date ranges. Results are returned in a paginated format optimized for efficient browsing of attachment lists.
   *
   * Users can search for specific file attachments using partial name matching, filter by MIME types or file extensions, and specify date ranges for attachment creation. The operation ensures that only attachments belonging to the specified comment within the given article are returned, maintaining proper access control and data scoping.
   *
   * The response includes essential file metadata such as filename, file type, size in bytes, and creation timestamp, providing a comprehensive overview of comment attachments without requiring individual file downloads for basic information retrieval.
   *
   * @param connection
   * @param articleId The unique identifier of the article containing the comment
   * @param commentId The unique identifier of the comment whose attachments are being searched
   * @param body Search criteria and pagination parameters for comment attachments
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query the discussion_board_comment_attachments table filtered by discussion_board_comment_id matching the commentId parameter. Join with discussion_board_article_files to get file metadata. Apply search filters on file names, types, and creation dates. Return paginated results with file summary information including name, type, size, and creation timestamp.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardCommentAttachment.IRequest,
  ): Promise<IPageIDiscussionBoardCommentAttachment.ISummary> {
    try {
      return await patchDiscussionBoardArticlesArticleIdCommentsCommentIdAttachments(
        {
          articleId,
          commentId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific file attachment associated with a comment.
   *
   * This operation provides access to the metadata and file information for a comment attachment, including the original filename, file type, size, storage path, and download statistics. The attachment must belong to the specified comment, which in turn must belong to the specified article.
   *
   * The response includes comprehensive file metadata that enables clients to properly handle file downloads and display attachment information. Users can only access attachments for comments they have permission to view, ensuring proper content security and access control.
   *
   * This operation is part of the comment attachment management system, working in conjunction with the file storage infrastructure to provide seamless file access for discussion board users.
   *
   * @param connection
   * @param articleId ID of the article containing the comment
   * @param commentId ID of the comment containing the attachment
   * @param attachmentId ID of the specific attachment to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Retrieve a specific comment attachment by its ID. First validate that the article exists and the comment belongs to the specified article. Then verify that the attachment exists and is linked to the specified comment. Return the complete attachment metadata including file information, storage path, and download statistics. Ensure proper authorization checks so users can only access attachments for comments they have permission to view.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":attachmentId")
  public async at(
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
    @TypedParam("attachmentId")
    attachmentId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardCommentAttachment> {
    try {
      return await getDiscussionBoardArticlesArticleIdCommentsCommentIdAttachmentsAttachmentId(
        {
          articleId,
          commentId,
          attachmentId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
