import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IDiscussionBoardCommentVote } from "../../../../../api/structures/IDiscussionBoardCommentVote";
import { getDiscussionBoardArticlesArticleIdCommentsCommentIdVotesVoteId } from "../../../../../providers/getDiscussionBoardArticlesArticleIdCommentsCommentIdVotesVoteId";
import { patchDiscussionBoardArticlesArticleIdCommentsCommentIdVotes } from "../../../../../providers/patchDiscussionBoardArticlesArticleIdCommentsCommentIdVotes";

@Controller("/discussionBoard/articles/:articleId/comments/:commentId/votes")
export class DiscussionboardArticlesCommentsVotesController {
  /**
   * Update or cast a vote on a specific comment within an article.
   *
   * This operation allows authenticated users to express their assessment of comment quality by casting upvotes or downvotes. Each user can only have one active vote per comment, and this operation will either create a new vote record or update an existing one.
   *
   * The system validates that both the article and comment exist and are properly associated before processing the vote. Vote types are restricted to 'upvote' for positive assessment and 'downvote' for negative assessment, ensuring consistent voting behavior across the platform.
   *
   * This voting mechanism supports community-driven content quality assessment and helps surface high-quality comments through ranking algorithms. Users can change their vote at any time, and the system maintains audit trails of vote creation and modification timestamps.
   *
   * @param connection
   * @param articleId UUID of the article containing the comment
   * @param commentId UUID of the comment being voted on
   * @param body Vote information including vote type
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Update or create a user vote on a comment. First validate that the article exists and the comment exists and belongs to the article. Then check if the user already has a vote on this comment. If exists, update the vote_type; if not exists, create new vote record. Validate vote_type is either 'upvote' or 'downvote'. Return the complete vote record after operation.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async update(
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardCommentVote.IUpdate,
  ): Promise<IDiscussionBoardCommentVote> {
    try {
      return await patchDiscussionBoardArticlesArticleIdCommentsCommentIdVotes({
        articleId,
        commentId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific vote on a comment within an article.
   *
   * This operation allows users to view the complete details of a vote cast on a comment, including the vote type (upvote or downvote), the voter's information, and the vote timestamps. The endpoint follows the hierarchical structure of the discussion board where votes belong to comments, which in turn belong to articles.
   *
   * Authorization checks ensure that users can only access votes on comments within articles they have permission to view. The operation validates the existence of the vote and its proper relationship to the specified comment and article before returning the vote details.
   *
   * This API is particularly useful for moderation purposes, analytics, or when displaying detailed vote information in administrative interfaces.
   *
   * @param connection
   * @param articleId UUID identifier of the article containing the comment
   * @param commentId UUID identifier of the comment containing the vote
   * @param voteId UUID identifier of the specific vote to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query the discussion_board_comment_votes table using the provided voteId parameter. Validate that the vote exists and belongs to the specified comment and article through the comment's article_id relationship. Return the complete vote record including vote_type, voter information, and timestamps. Ensure proper authorization checks so users can only access votes on comments they have permission to view.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":voteId")
  public async at(
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
    @TypedParam("voteId")
    voteId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardCommentVote> {
    try {
      return await getDiscussionBoardArticlesArticleIdCommentsCommentIdVotesVoteId(
        {
          articleId,
          commentId,
          voteId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
