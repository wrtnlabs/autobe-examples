import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IDiscussionBoardArticle } from "../../../../api/structures/IDiscussionBoardArticle";
import { IPageIDiscussionBoardArticle } from "../../../../api/structures/IPageIDiscussionBoardArticle";
import { GuestAuth } from "../../../../decorators/GuestAuth";
import { GuestPayload } from "../../../../decorators/payload/GuestPayload";
import { patchDiscussionBoardGuestSearch } from "../../../../providers/patchDiscussionBoardGuestSearch";

@Controller("/discussionBoard/guest/search")
export class DiscussionboardGuestSearchController {
  /**
   * Perform a comprehensive search across all articles in the discussion board platform.
   *
   * This operation enables users to search articles by title and content text using advanced full-text search capabilities. The search supports partial matching and relevance ranking to help users find the most relevant discussions. Users can filter results by specific tags to narrow down search results to particular topics or categories.
   *
   * The search results are paginated for performance and usability, with each page displaying article summaries including the title, author information, associated tags, comment count, and publication timestamp. This provides users with sufficient context to evaluate search results without needing to view full article content.
   *
   * Search functionality is available to all authenticated users and follows the platform's search query validation rules to ensure security and performance. The system enforces query length limits and sanitizes input to prevent search injection attempts while maintaining search accuracy.
   *
   * When no articles match the search criteria, the system returns an empty result set with appropriate pagination metadata. The search operation maintains consistency with section-based browsing while providing cross-sectional discovery capabilities.
   *
   * @param connection
   * @param body Search criteria including text query, tag filters, and pagination parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification Query discussion_board_articles table with full-text search on title and body fields using PostgreSQL trigram similarity (gin_trgm_ops). Join with discussion_board_article_tags for tag filtering when tags are specified. Apply pagination with cursor-based or offset-based approach. Include relevance scoring for search results ranking. Support filtering by multiple tags (AND logic). Return article summaries with title, author info, tags, comment count, and creation time.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @GuestAuth()
    guest: GuestPayload,
    @TypedBody()
    body: IDiscussionBoardArticle.IRequest,
  ): Promise<IPageIDiscussionBoardArticle.ISummary> {
    try {
      return await patchDiscussionBoardGuestSearch({
        guest,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
