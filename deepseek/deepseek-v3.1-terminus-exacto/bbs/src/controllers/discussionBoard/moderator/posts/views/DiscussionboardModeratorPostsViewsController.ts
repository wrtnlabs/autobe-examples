import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchDiscussionBoardModeratorPostsPostIdViews } from "../../../../../providers/patchDiscussionBoardModeratorPostsPostIdViews";
import { ModeratorAuth } from "../../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../../decorators/payload/ModeratorPayload";

import { IPageIDiscussionBoardPostView } from "../../../../../api/structures/IPageIDiscussionBoardPostView";
import { IDiscussionBoardPostView } from "../../../../../api/structures/IDiscussionBoardPostView";

@Controller("/discussionBoard/moderator/posts/:postId/views")
export class DiscussionboardModeratorPostsViewsController {
  /**
   * Search and retrieve paginated view records for a specific discussion board
   * post.
   *
   * This operation provides comprehensive search capabilities for viewing post
   * engagement analytics. It allows filtering view records by member, date
   * ranges, and other criteria to analyze post popularity and user engagement
   * patterns.
   *
   * The operation supports advanced pagination with configurable page sizes and
   * sorting options. Views can be sorted by creation date, member, or other
   * relevant fields in ascending or descending order. This data is essential
   * for content analytics and helps identify trending discussions and user
   * behavior patterns.
   *
   * Security considerations include restricting access to authorized moderators
   * only, as view data contains user engagement information. The operation
   * integrates with the discussion_board_post_views table as defined in the
   * Prisma schema, incorporating all available view tracking fields and
   * relationships.
   *
   * @param connection
   * @param postId Unique identifier of the target discussion board post
   * @param body Search criteria and pagination parameters for filtering view
   *   records
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("postId")
    postId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardPostView.IRequest,
  ): Promise<IPageIDiscussionBoardPostView.ISummary> {
    try {
      return await patchDiscussionBoardModeratorPostsPostIdViews({
        moderator,
        postId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
