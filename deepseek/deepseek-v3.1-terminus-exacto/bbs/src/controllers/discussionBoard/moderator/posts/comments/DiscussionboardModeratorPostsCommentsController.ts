import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchDiscussionBoardModeratorPostsPostIdComments } from "../../../../../providers/patchDiscussionBoardModeratorPostsPostIdComments";
import { ModeratorAuth } from "../../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../../decorators/payload/ModeratorPayload";

import { IPageIDiscussionBoardComment } from "../../../../../api/structures/IPageIDiscussionBoardComment";
import { IDiscussionBoardComment } from "../../../../../api/structures/IDiscussionBoardComment";

@Controller("/discussionBoard/moderator/posts/:postId/comments")
export class DiscussionboardModeratorPostsCommentsController {
  /**
   * This operation provides advanced search and filtering capabilities for
   * comments associated with a specific discussion board post. It allows users
   * to retrieve comments with various filtering options, pagination controls,
   * and sorting preferences.
   *
   * The operation supports comprehensive search functionality including text
   * matching within comment content, filtering by comment status (published,
   * draft, deleted), and filtering by author. Users can specify pagination
   * parameters such as page number and page size to control the volume of
   * results returned.
   *
   * Sorting options include creation date, update date, thread level, and other
   * relevant fields. The operation automatically handles threaded comment
   * hierarchies, maintaining proper parent-child relationships in the response
   * data.
   *
   * Security is enforced through access controls that verify the requesting
   * user has appropriate permissions to view the parent post and its comments.
   * The operation respects the post's locked status and other visibility
   * restrictions. Comments that have been soft-deleted are filtered out unless
   * explicitly requested by users with appropriate permissions.
   *
   * @param connection
   * @param postId Unique identifier of the target post whose comments are being
   *   retrieved
   * @param body Search criteria and pagination parameters for comment filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("postId")
    postId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardComment.IRequest,
  ): Promise<IPageIDiscussionBoardComment.ISummary> {
    try {
      return await patchDiscussionBoardModeratorPostsPostIdComments({
        moderator,
        postId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
