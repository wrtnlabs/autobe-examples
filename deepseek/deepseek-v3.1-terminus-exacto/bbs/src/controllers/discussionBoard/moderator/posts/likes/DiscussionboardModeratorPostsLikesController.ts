import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchDiscussionBoardModeratorPostsPostIdLikes } from "../../../../../providers/patchDiscussionBoardModeratorPostsPostIdLikes";
import { ModeratorAuth } from "../../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../../decorators/payload/ModeratorPayload";

import { IPageIDiscussionBoardPostLike } from "../../../../../api/structures/IPageIDiscussionBoardPostLike";
import { IDiscussionBoardPostLike } from "../../../../../api/structures/IDiscussionBoardPostLike";

@Controller("/discussionBoard/moderator/posts/:postId/likes")
export class DiscussionboardModeratorPostsLikesController {
  /**
   * This operation provides comprehensive search capabilities for analyzing
   * post appreciation metrics. It allows filtering like records by member, date
   * ranges, and other criteria to measure content popularity and user
   * engagement through likes.
   *
   * The operation supports advanced pagination with configurable page sizes and
   * sorting options. Likes can be sorted by creation date, member, or other
   * relevant fields in ascending or descending order. This data helps identify
   * highly appreciated content and user preferences within the discussion board
   * community.
   *
   * Security considerations include restricting access to authorized moderators
   * only, as like data contains user engagement information. The operation
   * integrates with the discussion_board_post_likes table as defined in the
   * Prisma schema, incorporating all available like tracking fields and
   * relationships.
   *
   * @param connection
   * @param postId Unique identifier of the target discussion board post
   * @param body Search criteria and pagination parameters for filtering like
   *   records
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("postId")
    postId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardPostLike.IRequest,
  ): Promise<IPageIDiscussionBoardPostLike.ISummary> {
    try {
      return await patchDiscussionBoardModeratorPostsPostIdLikes({
        moderator,
        postId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
