import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { patchDiscussionBoardModeratorAnalyticsPosts } from "../../../../../providers/patchDiscussionBoardModeratorAnalyticsPosts";
import { ModeratorAuth } from "../../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../../decorators/payload/ModeratorPayload";

import { IPageIDiscussionBoardPost } from "../../../../../api/structures/IPageIDiscussionBoardPost";
import { IDiscussionBoardPost } from "../../../../../api/structures/IDiscussionBoardPost";

@Controller("/discussionBoard/moderator/analytics/posts")
export class DiscussionboardModeratorAnalyticsPostsController {
  /**
   * This operation provides detailed analytics for discussion board posts by
   * aggregating data from multiple tables including posts, views, and likes. It
   * computes key performance indicators such as total views, like counts,
   * engagement rates, and content popularity metrics.
   *
   * The analytics operation supports advanced filtering capabilities including
   * date ranges, channel selection, section categorization, and post status
   * filtering. Users can analyze post performance across different time periods
   * and categories to identify trends and optimize content strategy.
   *
   * Security considerations include appropriate access controls for analytics
   * data, with different authorization levels for members and moderators. The
   * operation implements efficient aggregation queries to handle large datasets
   * while maintaining responsive performance.
   *
   * This operation integrates with the discussion_board_posts table as defined
   * in the Prisma schema, incorporating all available post fields and
   * relationships with views and likes data for comprehensive analytics
   * reporting.
   *
   * @param connection
   * @param body Analytics query parameters including filters, date ranges, and
   *   aggregation options
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async search(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedBody()
    body: IDiscussionBoardPost.IRequest,
  ): Promise<IPageIDiscussionBoardPost.ISummary> {
    try {
      return await patchDiscussionBoardModeratorAnalyticsPosts({
        moderator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
