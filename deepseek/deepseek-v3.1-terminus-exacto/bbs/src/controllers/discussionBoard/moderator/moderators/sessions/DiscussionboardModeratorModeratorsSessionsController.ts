import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchDiscussionBoardModeratorModeratorsUsernameSessions } from "../../../../../providers/patchDiscussionBoardModeratorModeratorsUsernameSessions";
import { ModeratorAuth } from "../../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../../decorators/payload/ModeratorPayload";
import { getDiscussionBoardModeratorModeratorsUsernameSessionsSessionId } from "../../../../../providers/getDiscussionBoardModeratorModeratorsUsernameSessionsSessionId";
import { putDiscussionBoardModeratorModeratorsUsernameSessionsSessionId } from "../../../../../providers/putDiscussionBoardModeratorModeratorsUsernameSessionsSessionId";
import { deleteDiscussionBoardModeratorModeratorsUsernameSessionsSessionId } from "../../../../../providers/deleteDiscussionBoardModeratorModeratorsUsernameSessionsSessionId";

import { IPageIDiscussionBoardModeratorSession } from "../../../../../api/structures/IPageIDiscussionBoardModeratorSession";
import { IDiscussionBoardModeratorSession } from "../../../../../api/structures/IDiscussionBoardModeratorSession";

@Controller("/discussionBoard/moderator/moderators/:username/sessions")
export class DiscussionboardModeratorModeratorsSessionsController {
  /**
   * Retrieve a filtered and paginated list of moderator authentication sessions
   * from the system. This operation provides advanced search capabilities for
   * finding moderator sessions based on multiple criteria including IP address
   * filtering, connection URL patterns, session creation date ranges, and
   * expiration status.
   *
   * The operation supports comprehensive pagination with configurable page
   * sizes and sorting options. Sessions can be sorted by creation date, last
   * update time, expiration status, or other relevant fields in ascending or
   * descending order.
   *
   * Security considerations include requiring moderator authentication and
   * appropriate filtering of session information based on the requesting
   * moderator's authorization level. Only authenticated moderators can access
   * session information, with session data being filtered to show only sessions
   * belonging to the specified moderator.
   *
   * This operation integrates with the discussion_board_moderator_sessions
   * table as defined in the Prisma schema, incorporating all available session
   * fields and relationships. The response includes session summary information
   * optimized for audit displays, with options to include additional details
   * based on authorization level.
   *
   * @param connection
   * @param username Unique username identifier of the target moderator
   * @param body Search criteria and pagination parameters for session filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("username")
    username: string,
    @TypedBody()
    body: IDiscussionBoardModeratorSession.IRequest,
  ): Promise<IPageIDiscussionBoardModeratorSession.ISummary> {
    try {
      return await patchDiscussionBoardModeratorModeratorsUsernameSessions({
        moderator,
        username,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific moderator authentication
   * session identified by its unique session ID. This operation provides
   * complete session details including connection context such as IP address,
   * access URL, referrer information, and comprehensive timestamp tracking.
   *
   * The operation validates that the requesting moderator has appropriate
   * permissions to access the session information. Session details are only
   * accessible to authorized moderators for security auditing and monitoring
   * purposes. The operation ensures that session information is properly
   * secured and only accessible to users with the correct authorization level.
   *
   * This operation integrates with the discussion_board_moderator_sessions
   * table as defined in the Prisma schema, returning all available session
   * fields including creation time, last update, expiration status, and
   * deletion status. The response provides a comprehensive view of the
   * session's lifecycle and connection context for security analysis.
   *
   * Security measures include validation of moderator permissions and ensuring
   * that session information is only accessible to authorized users. The
   * operation supports security auditing workflows by providing detailed
   * session information for investigation and monitoring purposes.
   *
   * @param connection
   * @param username Unique username identifier of the target moderator
   * @param sessionId Unique identifier of the target moderator session
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("username")
    username: string,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardModeratorSession> {
    try {
      return await getDiscussionBoardModeratorModeratorsUsernameSessionsSessionId(
        {
          moderator,
          username,
          sessionId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This operation allows administrators to update properties of a moderator
   * session identified by the moderator's username and session ID. The session
   * must belong to the specified moderator and can be modified to change
   * expiration time or other session attributes.
   *
   * Moderator sessions track authentication state and connection context for
   * administrative users. Each session is associated with a specific moderator
   * account and maintains audit trail information including IP address, access
   * URLs, and connection timestamps.
   *
   * Security considerations require that only administrators can modify
   * moderator sessions. The operation validates that the session exists and
   * belongs to the specified moderator before allowing updates. Session
   * modifications are logged for audit purposes.
   *
   * This operation integrates with the discussion_board_moderator_sessions
   * table as defined in the Prisma schema, incorporating all available session
   * fields and relationships. The response includes the updated session
   * information with current connection context.
   *
   * @param connection
   * @param username Unique username of the target moderator
   * @param sessionId Unique identifier of the target session
   * @param body Session update data including expiration time and connection
   *   context
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":sessionId")
  public async update(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("username")
    username: string,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardModeratorSession.IUpdate,
  ): Promise<IDiscussionBoardModeratorSession> {
    try {
      return await putDiscussionBoardModeratorModeratorsUsernameSessionsSessionId(
        {
          moderator,
          username,
          sessionId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This operation allows administrators to permanently remove a moderator
   * session identified by the moderator's username and session ID. The session
   * record is completely deleted from the database and cannot be recovered.
   *
   * Moderator sessions contain authentication and connection context
   * information for administrative users. Deleting a session terminates the
   * moderator's access and removes all session tracking data. This operation is
   * typically used for security purposes when a session needs to be forcibly
   * terminated.
   *
   * Security considerations require that only administrators can delete
   * moderator sessions. The operation validates that the session exists and
   * belongs to the specified moderator before performing deletion. Session
   * deletion is logged for audit purposes.
   *
   * This operation integrates with the discussion_board_moderator_sessions
   * table as defined in the Prisma schema. Records are completely removed from
   * the database and cannot be recovered through standard means.
   *
   * @param connection
   * @param username Unique username of the target moderator
   * @param sessionId Unique identifier of the target session
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":sessionId")
  public async erase(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("username")
    username: string,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardModeratorSession> {
    try {
      return await deleteDiscussionBoardModeratorModeratorsUsernameSessionsSessionId(
        {
          moderator,
          username,
          sessionId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
