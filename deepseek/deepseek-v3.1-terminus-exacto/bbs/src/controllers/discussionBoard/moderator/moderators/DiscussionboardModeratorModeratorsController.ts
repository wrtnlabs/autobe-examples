import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia from "typia";
import { patchDiscussionBoardModeratorModerators } from "../../../../providers/patchDiscussionBoardModeratorModerators";
import { ModeratorAuth } from "../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../decorators/payload/ModeratorPayload";
import { getDiscussionBoardModeratorModeratorsUsername } from "../../../../providers/getDiscussionBoardModeratorModeratorsUsername";
import { putDiscussionBoardModeratorModeratorsUsername } from "../../../../providers/putDiscussionBoardModeratorModeratorsUsername";
import { deleteDiscussionBoardModeratorModeratorsUsername } from "../../../../providers/deleteDiscussionBoardModeratorModeratorsUsername";

import { IPageIDiscussionBoardModerator } from "../../../../api/structures/IPageIDiscussionBoardModerator";
import { IDiscussionBoardModerator } from "../../../../api/structures/IDiscussionBoardModerator";

@Controller("/discussionBoard/moderator/moderators")
export class DiscussionboardModeratorModeratorsController {
  /**
   * This operation provides comprehensive search functionality for discussion
   * board moderators with advanced filtering options and pagination support.
   * Users can search moderators by username pattern matching, email domain
   * filtering, moderation level selection, and account status filtering.
   *
   * The operation supports multiple sorting options including sorting by
   * username, email, moderation level, creation date, and last update
   * timestamp. Pagination is fully configurable with customizable page sizes
   * and navigation controls. The search results include summary information
   * optimized for list displays while excluding sensitive authentication data.
   *
   * Security considerations include appropriate access controls based on
   * moderator privilege levels. The operation validates search parameters to
   * prevent excessive resource consumption and implements rate limiting for
   * search operations. The response includes pagination metadata for efficient
   * client-side navigation through large result sets.
   *
   * This operation integrates with the discussion_board_moderators table as
   * defined in the Prisma schema, incorporating all available moderator fields
   * and relationships while maintaining data security and privacy standards.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for moderator
   *   filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedBody()
    body: IDiscussionBoardModerator.IRequest,
  ): Promise<IPageIDiscussionBoardModerator.ISummary> {
    try {
      return await patchDiscussionBoardModeratorModerators({
        moderator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This operation retrieves comprehensive profile information for a specific
   * discussion board moderator identified by their unique username. The
   * operation validates that the requested moderator exists and returns
   * detailed information including contact details, moderation level, account
   * creation timestamp, and profile metadata.
   *
   * The response includes complete moderator profile data while maintaining
   * appropriate security measures. Sensitive authentication information such as
   * password hashes is excluded from the response for security reasons. The
   * operation provides real-time moderator status information including account
   * activity and moderation capabilities.
   *
   * Security considerations include access control verification to ensure only
   * authorized users can retrieve moderator information. The operation
   * validates the username parameter format and existence before processing the
   * request. Error handling includes appropriate responses for non-existent
   * moderators and invalid username formats.
   *
   * This operation integrates with the discussion_board_moderators table as
   * defined in the Prisma schema, providing complete moderator information
   * while maintaining data security and privacy standards.
   *
   * @param connection
   * @param username Unique username identifier of the target moderator
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":username")
  public async at(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("username")
    username: string,
  ): Promise<IDiscussionBoardModerator.ISummary> {
    try {
      return await getDiscussionBoardModeratorModeratorsUsername({
        moderator,
        username,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This operation allows authorized moderators to modify the profile details
   * of an existing moderator in the discussion board system. The operation
   * requires the moderator's unique username as a path parameter and accepts a
   * complete moderator profile update request.
   *
   * When updating a moderator profile, all required fields must be provided
   * even if only specific attributes are being modified. The system validates
   * that the updated email and username values remain unique across all
   * moderator accounts to prevent conflicts.
   *
   * Security considerations include authentication verification to ensure only
   * authorized moderators can perform moderator updates. The operation checks
   * that the target moderator exists and is active before applying changes.
   * Profile updates may include changes to display name, biography, moderation
   * level, and authentication credentials if needed.
   *
   * The updated moderator record is returned with all current profile
   * information reflecting the applied changes. Related operations include
   * creating new moderators (POST /moderators) and retrieving moderator details
   * (GET /moderators/{username}).
   *
   * @param connection
   * @param username Unique username identifier of the target moderator to
   *   update
   * @param body Complete moderator profile update data including all required
   *   fields
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":username")
  public async update(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("username")
    username: string,
    @TypedBody()
    body: IDiscussionBoardModerator.IUpdate,
  ): Promise<IDiscussionBoardModerator> {
    try {
      return await putDiscussionBoardModeratorModeratorsUsername({
        moderator,
        username,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This operation allows authorized moderators to permanently remove a
   * moderator account from the discussion board system. The operation requires
   * the moderator's unique username as a path parameter and performs a hard
   * deletion of the moderator record.
   *
   * Before deletion, the system validates that the target moderator exists and
   * checks for any active moderation assignments or pending content reports
   * associated with the moderator. If the moderator is currently assigned to
   * active moderation tasks, the deletion may be blocked or require
   * reassignment of those tasks.
   *
   * Security considerations include strict authentication verification to
   * ensure only authorized moderators can perform moderator deletions. The
   * operation implements additional safeguards to prevent accidental deletion
   * of critical moderator accounts, particularly those with administrative
   * privileges.
   *
   * Unlike soft deletion operations that mark records as deleted while
   * preserving them in the database, this operation performs a complete removal
   * of the moderator record. All associated moderator sessions and moderation
   * history are also removed to maintain database integrity.
   *
   * After successful deletion, the operation returns the deleted moderator
   * information for confirmation. The moderator's username and email address
   * become available for registration of new moderator accounts. Related
   * operations include creating moderators (POST /moderators) and updating
   * moderator profiles (PUT /moderators/{username}).
   *
   * @param connection
   * @param username Unique username identifier of the target moderator to
   *   delete
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":username")
  public async erase(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("username")
    username: string,
  ): Promise<IDiscussionBoardModerator> {
    try {
      return await deleteDiscussionBoardModeratorModeratorsUsername({
        moderator,
        username,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
