import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia from "typia";
import { postDiscussionBoardModeratorChannels } from "../../../../providers/postDiscussionBoardModeratorChannels";
import { ModeratorAuth } from "../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../decorators/payload/ModeratorPayload";
import { putDiscussionBoardModeratorChannelsChannelName } from "../../../../providers/putDiscussionBoardModeratorChannelsChannelName";
import { deleteDiscussionBoardModeratorChannelsChannelName } from "../../../../providers/deleteDiscussionBoardModeratorChannelsChannelName";

import { IDiscussionBoardChannel } from "../../../../api/structures/IDiscussionBoardChannel";

@Controller("/discussionBoard/moderator/channels")
export class DiscussionboardModeratorChannelsController {
  /**
   * Create a new discussion board channel.
   *
   * This operation allows authorized administrators to create new discussion
   * board channels that serve as major content categories for organizing
   * discussions.
   *
   * Each channel represents a broad topic area such as Economics, Politics, or
   * Technology, and provides the primary organizational structure for the
   * discussion board platform. The operation validates that the channel name is
   * unique across all existing channels to prevent duplication and maintain
   * clear content categorization.
   *
   * Security considerations include authentication requirements for
   * administrative users and validation of input parameters to ensure data
   * integrity. The created channel becomes immediately available for content
   * organization and can be configured with specific moderation policies and
   * display settings.
   *
   * This operation integrates with the discussion_board_channels table as
   * defined in the Prisma schema, incorporating all available channel fields
   * including name, description, status, and timestamps. The response includes
   * the complete channel information with system-generated identifiers and
   * timestamps.
   *
   * @param connection
   * @param body Creation data for the new discussion board channel
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedBody()
    body: IDiscussionBoardChannel.ICreate,
  ): Promise<IDiscussionBoardChannel> {
    try {
      return await postDiscussionBoardModeratorChannels({
        moderator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing discussion board channel.
   *
   * This operation enables authorized administrators to modify the properties
   * of an existing discussion board channel identified by its unique name.
   * Channel updates may include changes to the description, status
   * (active/inactive/archived), or other configuration settings that affect how
   * the channel is displayed and managed.
   *
   * The operation performs comprehensive validation to ensure the target
   * channel exists and that the requested changes maintain data integrity.
   * Updates to channel names are restricted to prevent breaking existing
   * content relationships, as the channel name serves as a stable identifier
   * throughout the system.
   *
   * Security measures include authentication verification for administrative
   * users and authorization checks to ensure only authorized personnel can
   * modify channel configurations. The operation preserves audit trails by
   * updating the last modified timestamp and maintains referential integrity
   * with related content and sections.
   *
   * This operation integrates with the discussion_board_channels table as
   * defined in the Prisma schema, handling all updateable fields while
   * protecting system-generated identifiers and creation timestamps from
   * modification.
   *
   * @param connection
   * @param channelName Unique name identifier of the target discussion board
   *   channel (global scope)
   * @param body Update data for the discussion board channel
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":channelName")
  public async update(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("channelName")
    channelName: string,
    @TypedBody()
    body: IDiscussionBoardChannel.IUpdate,
  ): Promise<IDiscussionBoardChannel> {
    try {
      return await putDiscussionBoardModeratorChannelsChannelName({
        moderator,
        channelName,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a discussion board channel by its unique name.
   *
   * This operation permanently removes a discussion board channel from the
   * system using the channel's unique name identifier. The deletion process
   * includes validation checks to ensure the channel exists and is not
   * currently in use by active discussions.
   *
   * The operation performs a hard delete that completely removes the channel
   * record from the database. This action cannot be undone, so appropriate
   * authorization and confirmation mechanisms should be implemented at the
   * application level before calling this endpoint.
   *
   * Security considerations require that only authorized moderators can perform
   * channel deletion operations. The system validates that no active posts or
   * sections are associated with the channel before allowing deletion to
   * maintain data integrity.
   *
   * @param connection
   * @param channelName Unique name identifier of the target discussion board
   *   channel
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":channelName")
  public async erase(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("channelName")
    channelName: string,
  ): Promise<void> {
    try {
      return await deleteDiscussionBoardModeratorChannelsChannelName({
        moderator,
        channelName,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
