import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia from "typia";
import { postDiscussionBoardModeratorChannelsChannelNameSections } from "../../../../../providers/postDiscussionBoardModeratorChannelsChannelNameSections";
import { ModeratorAuth } from "../../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../../decorators/payload/ModeratorPayload";
import { putDiscussionBoardModeratorChannelsChannelNameSectionsSectionName } from "../../../../../providers/putDiscussionBoardModeratorChannelsChannelNameSectionsSectionName";
import { deleteDiscussionBoardModeratorChannelsChannelNameSectionsSectionName } from "../../../../../providers/deleteDiscussionBoardModeratorChannelsChannelNameSectionsSectionName";

import { IDiscussionBoardSection } from "../../../../../api/structures/IDiscussionBoardSection";

@Controller("/discussionBoard/moderator/channels/:channelName/sections")
export class DiscussionboardModeratorChannelsSectionsController {
  /**
   * Create a new discussion board section within a channel.
   *
   * This POST operation allows administrators to create new discussion board
   * sections within existing channels. The operation requires the parent
   * channel name as a path parameter and section creation data in the request
   * body.
   *
   * The operation validates that the specified channel exists and is active
   * before creating the section. It ensures that the section name is unique
   * within the parent channel to prevent duplicate sections. Upon successful
   * creation, the operation returns the complete section object with all
   * generated fields including the unique identifier and timestamps.
   *
   * Security considerations include restricting this operation to authorized
   * administrators only, as section creation affects the organizational
   * structure of the discussion board. The operation performs comprehensive
   * validation to maintain data integrity and prevent conflicts with existing
   * sections.
   *
   * @param connection
   * @param channelName Unique name identifier of the parent discussion board
   *   channel (global scope)
   * @param body Section creation data including name, description, and initial
   *   status
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("channelName")
    channelName: string,
    @TypedBody()
    body: IDiscussionBoardSection.ICreate,
  ): Promise<IDiscussionBoardSection> {
    try {
      return await postDiscussionBoardModeratorChannelsChannelNameSections({
        moderator,
        channelName,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing discussion board section within a specific channel.
   *
   * This PUT operation allows administrators to modify the properties of an
   * existing discussion board section within a specific channel. The operation
   * requires both the channel name and section name to uniquely identify the
   * target section, as sections are scoped to their parent channels.
   *
   * The operation validates that the specified channel exists and contains the
   * target section before applying updates. Administrators can modify section
   * properties such as the name, description, and status while maintaining the
   * section's relationship to its parent channel.
   *
   * Security considerations include requiring moderator privileges to modify
   * section properties. The operation ensures data integrity by preserving the
   * section's relationship to its parent channel and maintaining referential
   * constraints throughout the update process.
   *
   * @param connection
   * @param channelName Unique name identifier of the parent discussion board
   *   channel (global scope)
   * @param sectionName Unique name identifier of the target section within the
   *   channel (scoped to channel)
   * @param body Updated properties for the discussion board section
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":sectionName")
  public async update(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("channelName")
    channelName: string,
    @TypedParam("sectionName")
    sectionName: string,
    @TypedBody()
    body: IDiscussionBoardSection.IUpdate,
  ): Promise<IDiscussionBoardSection> {
    try {
      return await putDiscussionBoardModeratorChannelsChannelNameSectionsSectionName(
        {
          moderator,
          channelName,
          sectionName,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a discussion board section from a specific channel.
   *
   * This DELETE operation allows administrators to permanently remove a
   * discussion board section from a specific channel. The operation requires
   * both the channel name and section name to uniquely identify the target
   * section, ensuring precise deletion within the correct channel context.
   *
   * The operation performs a hard deletion, completely removing the section
   * record from the database. This action is irreversible and should be used
   * with caution. Before deletion, the operation validates that the specified
   * channel exists and contains the target section.
   *
   * Security considerations include requiring moderator privileges to perform
   * deletion operations. The operation ensures that only authorized users can
   * remove sections and maintains referential integrity by validating the
   * section's existence within the specified channel before proceeding with
   * deletion.
   *
   * @param connection
   * @param channelName Unique name identifier of the parent discussion board
   *   channel (global scope)
   * @param sectionName Unique name identifier of the target section within the
   *   channel (scoped to channel)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":sectionName")
  public async erase(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("channelName")
    channelName: string,
    @TypedParam("sectionName")
    sectionName: string,
  ): Promise<void> {
    try {
      return await deleteDiscussionBoardModeratorChannelsChannelNameSectionsSectionName(
        {
          moderator,
          channelName,
          sectionName,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
