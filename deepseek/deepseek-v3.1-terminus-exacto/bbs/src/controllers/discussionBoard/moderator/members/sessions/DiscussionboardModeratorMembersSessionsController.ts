import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchDiscussionBoardModeratorMembersUsernameSessions } from "../../../../../providers/patchDiscussionBoardModeratorMembersUsernameSessions";
import { ModeratorAuth } from "../../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../../decorators/payload/ModeratorPayload";
import { getDiscussionBoardModeratorMembersUsernameSessionsSessionId } from "../../../../../providers/getDiscussionBoardModeratorMembersUsernameSessionsSessionId";

import { IPageIDiscussionBoardMemberSession } from "../../../../../api/structures/IPageIDiscussionBoardMemberSession";
import { IDiscussionBoardMemberSession } from "../../../../../api/structures/IDiscussionBoardMemberSession";

@Controller("/discussionBoard/moderator/members/:username/sessions")
export class DiscussionboardModeratorMembersSessionsController {
  /**
   * Retrieve a filtered and paginated list of authentication sessions for a
   * specific member user identified by their username. This operation provides
   * advanced search capabilities for finding session records based on multiple
   * criteria including IP address filtering, creation date ranges, session
   * status (active/expired), and connection context.
   *
   * The operation supports comprehensive pagination with configurable page
   * sizes and sorting options. Sessions can be sorted by creation date, last
   * update time, or expiration date in ascending or descending order. Filtering
   * options include IP address patterns, connection URL matching, and session
   * status indicators.
   *
   * Security considerations include ensuring that only authorized users can
   * access session information. The operation validates that the requesting
   * user has appropriate permissions to view the target member's session
   * history. Session data includes connection context information but excludes
   * sensitive authentication details.
   *
   * This operation integrates with the discussion_board_member_sessions table
   * as defined in the Prisma schema, incorporating all available session fields
   * and relationships. The response includes session summary information
   * optimized for administrative review and audit purposes.
   *
   * @param connection
   * @param username Unique username identifier of the target member
   * @param body Search criteria and pagination parameters for session filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("username")
    username: string,
    @TypedBody()
    body: IDiscussionBoardMemberSession.IRequest,
  ): Promise<IPageIDiscussionBoardMemberSession.ISummary> {
    try {
      return await patchDiscussionBoardModeratorMembersUsernameSessions({
        moderator,
        username,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve comprehensive details about a specific authentication session for
   * a member user. This operation provides complete session information
   * including connection context, IP address, access URLs, session timestamps,
   * and relationship to the member account.
   *
   * The session details include creation and update timestamps, expiration
   * status, and connection metadata such as IP address and referrer
   * information. This information is valuable for security auditing,
   * troubleshooting connection issues, and monitoring member activity
   * patterns.
   *
   * Security considerations require that only authorized administrators can
   * access detailed session information. The operation validates permissions to
   * ensure sensitive session data is protected while providing necessary
   * information for administrative purposes.
   *
   * This operation integrates with the discussion_board_member_sessions table
   * as defined in the Prisma schema, returning all available session fields in
   * a detailed view. The response includes the complete session object with
   * relationship information to the parent member account.
   *
   * @param connection
   * @param username Unique username identifier of the target member
   * @param sessionId Unique identifier of the target session
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("username")
    username: string,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardMemberSession> {
    try {
      return await getDiscussionBoardModeratorMembersUsernameSessionsSessionId({
        moderator,
        username,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
