import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia from "typia";
import { patchDiscussionBoardModeratorMembers } from "../../../../providers/patchDiscussionBoardModeratorMembers";
import { ModeratorAuth } from "../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../decorators/payload/ModeratorPayload";
import { getDiscussionBoardModeratorMembersUsername } from "../../../../providers/getDiscussionBoardModeratorMembersUsername";

import { IPageIDiscussionBoardMember } from "../../../../api/structures/IPageIDiscussionBoardMember";
import { IDiscussionBoardMember } from "../../../../api/structures/IDiscussionBoardMember";

@Controller("/discussionBoard/moderator/members")
export class DiscussionboardModeratorMembersController {
  /**
   * This operation provides advanced search capabilities for finding discussion
   * board members based on multiple criteria including partial username
   * matching, email domain filtering, registration date ranges, and account
   * status.
   *
   * The operation supports comprehensive pagination with configurable page
   * sizes and sorting options. Members can sort by registration date, last
   * update timestamp, username, or other relevant fields in ascending or
   * descending order.
   *
   * Security considerations include appropriate filtering of sensitive member
   * information based on the requesting user's authorization level. Only users
   * with appropriate permissions can access detailed member information, while
   * basic member lists may be available to authenticated users.
   *
   * This operation integrates with the discussion_board_members table as
   * defined in the Prisma schema, incorporating all available member fields and
   * relationships. The response includes member summary information optimized
   * for list displays, with options to include additional details based on
   * authorization level.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for member filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedBody()
    body: IDiscussionBoardMember.IRequest,
  ): Promise<IPageIDiscussionBoardMember.ISummary> {
    try {
      return await patchDiscussionBoardModeratorMembers({
        moderator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This operation retrieves complete profile information for a specific
   * discussion board member identified by their unique username. The operation
   * validates that the requested member exists and that the requesting user has
   * appropriate permissions to access the member's information.
   *
   * The response includes comprehensive member data such as email address,
   * display name, biography, account creation date, and account status.
   * Sensitive information like password hashes is excluded from the response
   * for security reasons.
   *
   * Security considerations include authorization checks to ensure only
   * authorized users can access member details. Administrative users may have
   * access to all member information, while regular users may only access their
   * own profile data or public member information.
   *
   * This operation integrates with the discussion_board_members table as
   * defined in the Prisma schema, ensuring all returned data accurately
   * reflects the current member state in the database.
   *
   * @param connection
   * @param username Unique username identifier of the target member
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":username")
  public async at(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("username")
    username: string,
  ): Promise<IDiscussionBoardMember.ISummary> {
    try {
      return await getDiscussionBoardModeratorMembersUsername({
        moderator,
        username,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
