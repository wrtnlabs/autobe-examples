import { Controller } from "@nestjs/common";
import { TypedRoute } from "@nestia/core";
import typia from "typia";
import { getDiscussionBoardModeratorStatisticsPostsByStatus } from "../../../../../providers/getDiscussionBoardModeratorStatisticsPostsByStatus";
