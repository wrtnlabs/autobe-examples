import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchDiscussionBoardModeratorContentReports } from "../../../../providers/patchDiscussionBoardModeratorContentReports";
import { ModeratorAuth } from "../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../decorators/payload/ModeratorPayload";
import { getDiscussionBoardModeratorContentReportsReportId } from "../../../../providers/getDiscussionBoardModeratorContentReportsReportId";
import { deleteDiscussionBoardModeratorContentReportsReportId } from "../../../../providers/deleteDiscussionBoardModeratorContentReportsReportId";

import { IPageIDiscussionBoardContentReport } from "../../../../api/structures/IPageIDiscussionBoardContentReport";
import { IDiscussionBoardContentReport } from "../../../../api/structures/IDiscussionBoardContentReport";

@Controller("/discussionBoard/moderator/contentReports")
export class DiscussionboardModeratorContentreportsController {
  /**
   * This operation provides comprehensive search capabilities for content
   * reports submitted on the discussion board platform. It enables moderators
   * and administrators to filter reports based on various criteria including
   * report status, priority level, actor type (member or moderator), and
   * creation date ranges.
   *
   * The search functionality supports complex query parameters that allow for
   * precise filtering of the moderation queue. Moderators can search for
   * reports by specific reason categories such as spam, harassment,
   * inappropriate content, misinformation, copyright violations, or other
   * custom reasons. The operation also supports text search within report
   * details for finding specific content issues.
   *
   * Pagination is built into the response structure, allowing moderators to
   * efficiently navigate through large volumes of reports. The operation
   * returns summary information optimized for list displays, including
   * essential report metadata without overwhelming detail. This design supports
   * the moderation workflow by providing quick access to report overviews while
   * maintaining performance.
   *
   * Security considerations include appropriate access controls based on user
   * roles. Only authorized moderators and administrators should have access to
   * this endpoint, with filtering applied based on the requesting user's
   * permissions and scope of responsibility within the discussion board
   * system.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for content report
   *   filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedBody()
    body: IDiscussionBoardContentReport.IRequest,
  ): Promise<IPageIDiscussionBoardContentReport.ISummary> {
    try {
      return await patchDiscussionBoardModeratorContentReports({
        moderator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This operation provides complete details for a single content report
   * identified by its unique report ID. It returns all relevant information
   * from the main content report table along with actor-specific details from
   * the appropriate subsidiary table based on the report's actor type.
   *
   * The response includes the full report metadata such as report reason,
   * detailed explanation, current status, priority level, and timestamps.
   * Additionally, it provides actor-specific context including the reporter's
   * identity (member or moderator), session information, and the specific
   * content being reported (post, comment, or member profile).
   *
   * This detailed view is essential for moderators conducting thorough
   * investigations of reported content. It provides the complete context needed
   * to make informed moderation decisions, including understanding who reported
   * the content, when it was reported, and the specific concerns raised by the
   * reporter.
   *
   * Access to this operation is restricted to authorized moderators and
   * administrators who need to review report details as part of the content
   * moderation process. The operation ensures that sensitive reporter
   * information is protected while providing sufficient context for effective
   * moderation decisions.
   *
   * @param connection
   * @param reportId Unique identifier of the target content report
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":reportId")
  public async at(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("reportId")
    reportId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardContentReport> {
    try {
      return await getDiscussionBoardModeratorContentReportsReportId({
        moderator,
        reportId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This operation removes a content report record from the discussion board
   * system using a hard delete approach. The report is identified by its unique
   * UUID identifier and is permanently removed from the database.
   *
   * The operation validates that the specified report exists before attempting
   * deletion. If the report is found, it performs a complete removal of the
   * record from the discussion_board_content_reports table. This operation is
   * typically used by administrators or moderators for cleaning up resolved or
   * invalid reports.
   *
   * Security considerations include proper authorization checks to ensure only
   * authorized users can delete content reports. The operation maintains audit
   * integrity by ensuring that deletion actions are properly logged and
   * tracked. Related operations include viewing reports (GET
   * /contentReports/{reportId}) and listing reports (PATCH /contentReports).
   *
   * @param connection
   * @param reportId Unique identifier of the target content report to be
   *   deleted
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":reportId")
  public async erase(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("reportId")
    reportId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteDiscussionBoardModeratorContentReportsReportId({
        moderator,
        reportId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
