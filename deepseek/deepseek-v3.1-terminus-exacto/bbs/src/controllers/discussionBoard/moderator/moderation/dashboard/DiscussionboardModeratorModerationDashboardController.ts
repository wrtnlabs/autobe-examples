import { Controller } from "@nestjs/common";
import { TypedRoute } from "@nestia/core";
import typia from "typia";
import { getDiscussionBoardModeratorModerationDashboard } from "../../../../../providers/getDiscussionBoardModeratorModerationDashboard";
import { ModeratorAuth } from "../../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../../decorators/payload/ModeratorPayload";

import { IDiscussionBoardModerationDashboard } from "../../../../../api/structures/IDiscussionBoardModerationDashboard";

@Controller("/discussionBoard/moderator/moderation/dashboard")
export class DiscussionboardModeratorModerationDashboardController {
  /**
   * This operation delivers a complete moderation dashboard containing key
   * metrics and statistics essential for effective content moderation
   * management. It aggregates data from multiple sources including content
   * reports, moderation actions, and queue management systems.
   *
   * The dashboard provides real-time insights into moderation workflow
   * efficiency, including pending report counts, average resolution times,
   * moderator workload distribution, and content violation trends. Metrics are
   * computed through complex JOIN operations across the moderation-related
   * tables to provide a holistic view of platform moderation health.
   *
   * Security is critical for this operation as it exposes sensitive moderation
   * metrics. Access is restricted to authorized moderation personnel only. The
   * dashboard data is computed on-demand to ensure accuracy and timeliness
   * without relying on cached statistics.
   *
   * This operation serves the business need for moderation team oversight and
   * platform governance. It enables moderators to identify bottlenecks, track
   * performance metrics, and make data-driven decisions about resource
   * allocation and workflow optimization.
   *
   * @param connection
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async index(
    @ModeratorAuth()
    moderator: ModeratorPayload,
  ): Promise<IDiscussionBoardModerationDashboard> {
    try {
      return await getDiscussionBoardModeratorModerationDashboard({
        moderator,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
