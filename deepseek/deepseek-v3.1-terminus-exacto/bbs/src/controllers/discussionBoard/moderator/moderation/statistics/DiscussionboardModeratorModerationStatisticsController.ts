import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { patchDiscussionBoardModeratorModerationStatistics } from "../../../../../providers/patchDiscussionBoardModeratorModerationStatistics";
import { ModeratorAuth } from "../../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../../decorators/payload/ModeratorPayload";

import { IDiscussionBoardModerationStatistics } from "../../../../../api/structures/IDiscussionBoardModerationStatistics";

@Controller("/discussionBoard/moderator/moderation/statistics")
export class DiscussionboardModeratorModerationStatisticsController {
  /**
   * Retrieve aggregated moderation statistics and analytics for moderation
   * oversight.
   *
   * This operation provides comprehensive moderation statistics by aggregating
   * data from the moderation workflow tables. It generates key performance
   * indicators that help moderators monitor moderation effectiveness, identify
   * trends, and optimize moderation workflows.
   *
   * The statistics include report volume metrics showing daily, weekly, and
   * monthly trends in content reporting activity. This helps identify peak
   * reporting periods and potential spam or coordinated reporting patterns. The
   * operation also computes moderation efficiency metrics such as average
   * response time, resolution rates, and moderator workload distribution across
   * different queue types.
   *
   * Queue performance statistics provide insights into moderation workflow
   * efficiency, including average queue wait times, assignment completion
   * rates, and timeout incidents. These metrics help moderators balance
   * workloads and identify bottlenecks in the moderation pipeline. The
   * statistics are calculated based on actual moderation activities recorded in
   * the discussion_board_content_reports, discussion_board_moderation_actions,
   * and discussion_board_moderation_queues tables.
   *
   * Security considerations ensure that only authorized moderators can access
   * these sensitive moderation statistics. The operation includes appropriate
   * rate limiting to prevent excessive computational load from frequent
   * statistical queries. The response provides both summary statistics and
   * detailed breakdowns by report type, priority level, and time periods for
   * comprehensive moderation oversight.
   *
   * @param connection
   * @param body Search criteria and date range parameters for moderation
   *   statistics filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedBody()
    body: IDiscussionBoardModerationStatistics.IRequest,
  ): Promise<IDiscussionBoardModerationStatistics> {
    try {
      return await patchDiscussionBoardModeratorModerationStatistics({
        moderator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
