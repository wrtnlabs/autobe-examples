import { Controller } from "@nestjs/common";
import { TypedRoute } from "@nestia/core";
import typia from "typia";
import { getDiscussionBoardModeratorDashboardPostsOverview } from "../../../../../providers/getDiscussionBoardModeratorDashboardPostsOverview";
import { ModeratorAuth } from "../../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../../decorators/payload/ModeratorPayload";

import { IPageIDiscussionBoardPost } from "../../../../../api/structures/IPageIDiscussionBoardPost";

@Controller("/discussionBoard/moderator/dashboard/postsOverview")
export class DiscussionboardModeratorDashboardPostsoverviewController {
  /**
   * This operation provides a comprehensive dashboard overview of discussion
   * board posts, displaying key metrics and summary information for content
   * management. The dashboard includes total post counts by status, recent
   * activity statistics, popular content indicators, and moderation workflow
   * insights.
   *
   * The overview dashboard is optimized for quick content management decisions,
   * providing administrators and moderators with immediate visibility into
   * discussion board health and activity levels. It aggregates data from
   * multiple sources to present a holistic view of content performance and
   * community engagement.
   *
   * Security considerations ensure that only authorized moderators and
   * administrators can access the dashboard overview, which may contain
   * sensitive content statistics and moderation information. The operation
   * implements efficient data aggregation to provide responsive dashboard
   * performance.
   *
   * This operation integrates with the discussion_board_posts table as defined
   * in the Prisma schema, incorporating status tracking, creation timestamps,
   * and relationship data to provide comprehensive dashboard insights.
   *
   * @param connection
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async overview(
    @ModeratorAuth()
    moderator: ModeratorPayload,
  ): Promise<IPageIDiscussionBoardPost.ISummary> {
    try {
      return await getDiscussionBoardModeratorDashboardPostsOverview({
        moderator,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
