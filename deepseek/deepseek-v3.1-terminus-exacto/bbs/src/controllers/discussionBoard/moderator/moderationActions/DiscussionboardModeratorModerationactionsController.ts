import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postDiscussionBoardModeratorModerationActions } from "../../../../providers/postDiscussionBoardModeratorModerationActions";
import { ModeratorAuth } from "../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../decorators/payload/ModeratorPayload";
import { patchDiscussionBoardModeratorModerationActions } from "../../../../providers/patchDiscussionBoardModeratorModerationActions";
import { getDiscussionBoardModeratorModerationActionsActionId } from "../../../../providers/getDiscussionBoardModeratorModerationActionsActionId";
import { putDiscussionBoardModeratorModerationActionsActionId } from "../../../../providers/putDiscussionBoardModeratorModerationActionsActionId";
import { deleteDiscussionBoardModeratorModerationActionsActionId } from "../../../../providers/deleteDiscussionBoardModeratorModerationActionsActionId";

import { IDiscussionBoardModerationAction } from "../../../../api/structures/IDiscussionBoardModerationAction";
import { IPageIDiscussionBoardModerationAction } from "../../../../api/structures/IPageIDiscussionBoardModerationAction";

@Controller("/discussionBoard/moderator/moderationActions")
export class DiscussionboardModeratorModerationactionsController {
  /**
   * Create a new moderation action record.
   *
   * This operation allows authorized moderators to create new moderation action
   * records in the discussion board system. Each moderation action represents
   * an official decision made by a moderator regarding reported content,
   * including actions such as content removal, user warnings, temporary
   * suspensions, permanent bans, content approvals, or report dismissals.
   *
   * The operation validates all input parameters including the action type,
   * escalation level, and required references to content reports and moderator
   * sessions. It ensures that the moderation action is properly linked to the
   * triggering content report and records the moderator responsible for the
   * decision.
   *
   * Security considerations include strict access control to ensure only
   * authorized moderators can create moderation actions. The operation
   * validates moderator permissions and ensures proper session context is
   * recorded for audit purposes. Created moderation actions become immediately
   * available in the moderation audit trail and can be referenced in subsequent
   * moderation workflows.
   *
   * @param connection
   * @param body Creation data for the new moderation action
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedBody()
    body: IDiscussionBoardModerationAction.ICreate,
  ): Promise<IDiscussionBoardModerationAction> {
    try {
      return await postDiscussionBoardModeratorModerationActions({
        moderator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve a filtered, paginated list of moderation actions.
   *
   * This operation provides comprehensive search functionality for moderation
   * actions recorded in the discussion board system. It supports advanced
   * filtering options including action type (content_removal, user_warning,
   * temporary_suspension, etc.), escalation level (standard, escalated,
   * critical), moderator identification, and date-based filtering.
   *
   * The operation implements full pagination support with configurable page
   * sizes and multiple sorting options. Users can sort results by creation
   * date, action type, escalation level, or moderator information. The search
   * functionality includes text-based filtering on action details and supports
   * complex boolean combinations of multiple criteria.
   *
   * Security considerations ensure that only authorized administrators and
   * moderators can access moderation action records. The operation integrates
   * with the discussion_board_moderation_actions table as defined in the Prisma
   * schema, incorporating all available fields and relationships. The response
   * includes moderation action summary information optimized for administrative
   * review and audit purposes.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for moderation action
   *   filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedBody()
    body: IDiscussionBoardModerationAction.IRequest,
  ): Promise<IPageIDiscussionBoardModerationAction.ISummary> {
    try {
      return await patchDiscussionBoardModeratorModerationActions({
        moderator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific moderation action by its unique identifier.
   *
   * This operation fetches a detailed moderation action record from the
   * discussion board moderation system. It provides comprehensive information
   * about a specific moderation action including the action type, detailed
   * explanation, escalation level, duration (if applicable), and timestamps.
   *
   * The operation validates that the requested moderation action exists and is
   * accessible. It returns the complete moderation action record with all
   * associated fields from the discussion_board_moderation_actions table. This
   * includes references to the content report that triggered the action, the
   * moderator who performed it, and the session context.
   *
   * Security considerations include ensuring that only authorized users can
   * access moderation action records. The operation performs proper access
   * control checks to prevent unauthorized viewing of sensitive moderation
   * data. Related operations include creating new moderation actions (POST
   * /moderationActions) and searching moderation actions (PATCH
   * /moderationActions).
   *
   * @param connection
   * @param actionId Unique identifier of the target moderation action
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":actionId")
  public async at(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("actionId")
    actionId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardModerationAction> {
    try {
      return await getDiscussionBoardModeratorModerationActionsActionId({
        moderator,
        actionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing moderation action record.
   *
   * This operation allows authorized moderators to update moderation action
   * records after they have been created. Moderation actions can be modified to
   * adjust details, escalation levels, or durations based on new information or
   * appeals.
   *
   * The operation validates that the target moderation action exists and that
   * the requesting user has appropriate moderator permissions. Only certain
   * fields can be updated after creation, such as action details, escalation
   * level, and duration days. Core identifying information like action type and
   * relationships to content reports cannot be modified.
   *
   * Security considerations include verifying that the requesting moderator has
   * authority to modify the specific action record. The operation maintains
   * audit integrity by preserving original creation timestamps while updating
   * the modification timestamp. All updates are logged for accountability and
   * transparency purposes.
   *
   * @param connection
   * @param actionId Unique identifier of the moderation action to update
   * @param body Updated moderation action information
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":actionId")
  public async update(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("actionId")
    actionId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardModerationAction.IUpdate,
  ): Promise<IDiscussionBoardModerationAction> {
    try {
      return await putDiscussionBoardModeratorModerationActionsActionId({
        moderator,
        actionId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a moderation action record.
   *
   * This operation performs a hard deletion of moderation action records,
   * permanently removing them from the database. This operation is intended for
   * administrative cleanup purposes only and should be used sparingly.
   *
   * Hard deletion is necessary when moderation actions were created in error,
   * contain sensitive information that must be completely removed for
   * compliance reasons, or when complete record elimination is required for
   * legal or regulatory purposes. The operation validates that the target
   * action exists and that the requesting user has administrative-level
   * permissions.
   *
   * Security considerations include strict access control to prevent
   * unauthorized deletion of moderation audit trails. The operation maintains
   * database integrity by ensuring all foreign key relationships are properly
   * handled before deletion. Once deleted, moderation action records cannot be
   * recovered, so this operation should only be used when absolute removal is
   * necessary.
   *
   * @param connection
   * @param actionId Unique identifier of the moderation action to delete
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":actionId")
  public async erase(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("actionId")
    actionId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteDiscussionBoardModeratorModerationActionsActionId({
        moderator,
        actionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
