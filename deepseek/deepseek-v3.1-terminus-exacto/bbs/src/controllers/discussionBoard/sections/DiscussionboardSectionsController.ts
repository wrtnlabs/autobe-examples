import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IDiscussionBoardSection } from "../../../api/structures/IDiscussionBoardSection";
import { getDiscussionBoardSectionsSectionId } from "../../../providers/getDiscussionBoardSectionsSectionId";

@Controller("/discussionBoard/sections/:sectionId")
export class DiscussionboardSectionsController {
  /**
   * Retrieve detailed information about a specific discussion board section.
   *
   * This operation provides access to section metadata including the section name, description, creation timestamp, and last update timestamp. Sections serve as thematic content categories that organize articles for better navigation and discovery.
   *
   * All users including guests, members, administrators, and super administrators can access section details through this endpoint. The section ID must be a valid UUID that corresponds to an existing, active section in the system. Soft-deleted sections (those with deleted_at timestamp set) are not accessible through this endpoint.
   *
   * Section information is essential for content browsing as it provides context about the thematic focus and purpose of each content category. Users typically access section details when exploring articles within specific categories or when administrators need to review section configurations. This operation follows the discussion_board database schema for IDiscussionBoardSection entities.
   *
   * @param connection
   * @param sectionId Unique identifier of the section to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query the discussion_board_sections table by ID to retrieve a single section. Validate that the section exists and is accessible (not soft-deleted). Return the complete section entity with all fields including name, description, and timestamps. Handle cases where the section ID doesn't exist by returning appropriate error responses.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @TypedParam("sectionId")
    sectionId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardSection> {
    try {
      return await getDiscussionBoardSectionsSectionId({
        sectionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
