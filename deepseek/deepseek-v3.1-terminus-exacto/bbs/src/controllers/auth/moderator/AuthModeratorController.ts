import { Controller, Ip } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthModeratorJoin } from "../../../providers/postAuthModeratorJoin";
import { postAuthModeratorLogin } from "../../../providers/postAuthModeratorLogin";
import { postAuthModeratorRefresh } from "../../../providers/postAuthModeratorRefresh";

import { IDiscussionBoardModerator } from "../../../api/structures/IDiscussionBoardModerator";

@Controller("/auth/moderator")
export class AuthModeratorController {
  /**
   * This POST endpoint handles moderator account registration by creating a new
   * moderator record in the discussion_board_moderators table. The operation
   * validates the provided email and username against the unique constraints
   * defined in the Prisma schema to ensure no duplicate accounts exist.
   *
   * The registration process requires essential authentication information
   * including email address, username, and password. The password is securely
   * hashed before storage in the password_hash field. Optional profile
   * information such as display_name and bio can be provided during
   * registration for moderator profile customization.
   *
   * Security considerations include validating email format, enforcing password
   * strength requirements, and ensuring username uniqueness across all
   * moderators. The operation automatically sets the moderation_level field and
   * generates timestamps for created_at and updated_at fields.
   *
   * Successful registration returns JWT tokens for immediate authentication,
   * allowing the new moderator to access the system without requiring a
   * separate login step. The response includes both access and refresh tokens
   * following the standard authentication pattern.
   *
   * This operation is essential for onboarding new moderators and establishing
   * their authentication credentials within the discussion board platform's
   * administrative system.
   *
   * @param connection
   * @param body Moderator registration information including authentication
   *   credentials
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IDiscussionBoardModerator.ICreate,
  ): Promise<IDiscussionBoardModerator.IAuthorized> {
    try {
      return await postAuthModeratorJoin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This POST endpoint handles moderator authentication by validating provided
   * credentials against the stored information in the
   * discussion_board_moderators table. The operation supports authentication
   * using either email address or username, providing flexibility for moderator
   * login preferences.
   *
   * The authentication process involves comparing the provided password with
   * the stored password_hash using secure hashing algorithms. Successful
   * authentication requires matching credentials and an active moderator
   * account (not soft-deleted). The operation checks the deleted_at field to
   * ensure the account is active.
   *
   * Security features include rate limiting to prevent brute force attacks,
   * proper error handling to avoid information leakage about which credential
   * is invalid, and immediate token issuance upon successful authentication.
   * The operation updates the updated_at timestamp to reflect the last login
   * activity.
   *
   * Upon successful authentication, the operation generates and returns both
   * access and refresh JWT tokens. The access token provides immediate
   * authorization for moderator operations, while the refresh token enables
   * session renewal without requiring re-authentication.
   *
   * This operation is critical for moderator access to administrative functions
   * and ensures secure authentication for content management and moderation
   * activities within the discussion board platform.
   *
   * @param connection
   * @param body Moderator authentication credentials (email/username and
   *   password)
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IDiscussionBoardModerator.ILogin,
  ): Promise<IDiscussionBoardModerator.IAuthorized> {
    try {
      return await postAuthModeratorLogin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This POST endpoint handles token refresh for moderator sessions by
   * validating an existing refresh token and issuing new access and refresh
   * tokens. The operation maintains session continuity while enhancing security
   * through regular token rotation.
   *
   * The refresh process validates the provided refresh token for authenticity
   * and expiration status. Valid tokens are used to identify the moderator and
   * generate new tokens with updated expiration times. This mechanism allows
   * moderators to maintain extended sessions without repeatedly entering
   * credentials.
   *
   * Security considerations include token validation against potential
   * revocation lists, proper expiration handling, and prevention of token
   * reuse. The operation ensures that refresh tokens can only be used once for
   * security purposes, requiring the moderator to re-authenticate if the
   * refresh token is compromised.
   *
   * The refreshed tokens maintain the same moderator permissions and access
   * levels as the original tokens. This operation is essential for providing
   * seamless moderator experience while maintaining high security standards for
   * administrative access to the discussion board platform.
   *
   * Successful token refresh returns new JWT tokens with updated expiration
   * times, allowing moderators to continue their administrative tasks without
   * interruption. The operation supports the overall authentication flow by
   * enabling sustainable session management for moderator activities.
   *
   * @param connection
   * @param body Valid refresh token for token renewal
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IDiscussionBoardModerator.IRefresh,
  ): Promise<IDiscussionBoardModerator.IAuthorized> {
    try {
      return await postAuthModeratorRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
