/**
 * Retrieve a filtered and paginated list of discussion board channels from the
 * system. This operation provides advanced search capabilities for finding
 * channels based on multiple criteria including partial name matching, status
 * filtering, creation date ranges, and description content search.
 *
 * The operation supports comprehensive pagination with configurable page sizes
 * and sorting options. Channels can be sorted by creation date, update date,
 * name, or status in ascending or descending order.
 *
 * Security considerations include appropriate filtering of channel information
 * based on the requesting user's authorization level. Only users with
 * appropriate permissions can access channel management features, while basic
 * channel lists may be available to authenticated users.
 *
 * This operation integrates with the discussion_board_channels table as defined
 * in the Prisma schema, incorporating all available channel fields and
 * relationships. The response includes channel summary information optimized
 * for list displays, with options to include additional details based on
 * authorization level.
 *
 * @param props.connection
 * @param props.body Search criteria and pagination parameters for channel
 *   filtering
 * @path /discussionBoard/channels
 * @accessor api.functional.discussionBoard.channels.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /** Search criteria and pagination parameters for channel filtering */
    body: IDiscussionBoardChannel.IRequest;
  };
  export type Body = IDiscussionBoardChannel.IRequest;
  export type Response = IPageIDiscussionBoardChannel.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/discussionBoard/channels",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/discussionBoard/channels";
  export const random = (): IPageIDiscussionBoardChannel.ISummary =>
    typia.random<IPageIDiscussionBoardChannel.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

