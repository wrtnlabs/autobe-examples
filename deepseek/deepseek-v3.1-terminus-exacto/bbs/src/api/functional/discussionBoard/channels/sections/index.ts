/**
 * Search and retrieve filtered sections within a specific discussion board
 * channel.
 *
 * This operation provides comprehensive search capabilities for retrieving
 * discussion board sections organized within a specific channel. Users can
 * filter sections by various criteria including status, creation date ranges,
 * and search terms within section names and descriptions.
 *
 * The operation supports pagination with configurable page sizes and multiple
 * sorting options. Sections can be sorted by creation date, update date, name,
 * or status in ascending or descending order. The response includes section
 * summary information optimized for list displays.
 *
 * Security considerations include appropriate access controls based on channel
 * visibility settings. Public channels may allow anonymous access, while
 * restricted channels require authentication. The operation respects
 * channel-specific permissions and section visibility settings.
 *
 * This operation integrates with the discussion_board_sections table as defined
 * in the Prisma schema, incorporating all available section fields and
 * relationships with the parent channel.
 *
 * @param props.connection
 * @param props.channelName Unique name identifier of the parent discussion
 *   board channel (global scope)
 * @param props.body Search criteria and pagination parameters for section
 *   filtering
 * @path /discussionBoard/channels/:channelName/sections
 * @accessor api.functional.discussionBoard.channels.sections.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
