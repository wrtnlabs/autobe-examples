import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardPost } from "../../../../structures/IDiscussionBoardPost";
import { IPageIDiscussionBoardPost } from "../../../../structures/IPageIDiscussionBoardPost";

/**
 * This operation provides advanced search capabilities for finding discussion
 * board posts within a specific channel. Users can filter posts by various
 * criteria including title keywords, content search, post status (draft,
 * published, archived), creation date ranges, and sorting options.
 *
 * The operation leverages the discussion_board_posts table structure and its
 * relationships to channels and sections. It supports comprehensive pagination
 * with configurable page sizes and multiple sorting options including creation
 * date, update date, title, and pin status.
 *
 * Security considerations include channel-based access control where users can
 * only search posts within channels they have permission to access. The
 * operation validates that the specified channel exists and is active before
 * returning results.
 *
 * This operation integrates with the discussion_board_posts table as defined in
 * the Prisma schema, incorporating all available post fields and relationships.
 * The response includes post summary information optimized for list displays,
 * with options to include additional details based on authorization level.
 *
 * @param props.connection
 * @param props.channelName Unique name identifier of the target discussion
 *   board channel (global scope)
 * @param props.body Search criteria and pagination parameters for post
 *   filtering within the specified channel
 * @path /discussionBoard/channels/:channelName/posts
 * @accessor api.functional.discussionBoard.channels.posts.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Unique name identifier of the target discussion board channel (global
     * scope)
     */
    channelName: string;

    /**
     * Search criteria and pagination parameters for post filtering within
     * the specified channel
     */
    body: IDiscussionBoardPost.IRequest;
  };
  export type Body = IDiscussionBoardPost.IRequest;
  export type Response = IPageIDiscussionBoardPost.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/discussionBoard/channels/:channelName/posts",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/discussionBoard/channels/${encodeURIComponent(props.channelName ?? "null")}/posts`;
  export const random = (): IPageIDiscussionBoardPost.ISummary =>
    typia.random<IPageIDiscussionBoardPost.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("channelName")(() => typia.assert(props.channelName));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
