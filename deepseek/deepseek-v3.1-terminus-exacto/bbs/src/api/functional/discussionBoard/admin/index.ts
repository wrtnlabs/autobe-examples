/**
 * Revoke an active user ban before its expiration date.
 *
 * This operation allows administrators to manually revoke active bans, restoring user access to the platform. When a ban is revoked, the system records the revocation reason, timestamp, and administrator who performed the action, maintaining a complete audit trail of ban management.
 *
 * Only active bans can be revoked - attempts to revoke already expired or previously revoked bans will result in validation errors. The operation requires administrators to provide a detailed reason explaining why the ban is being revoked, ensuring accountability and documentation of moderation decisions.
 *
 * The revocation process immediately restores the user's ability to log in and participate in discussions while preserving the original ban record for historical reference and compliance purposes.
 *
 * @param props.connection
 * @param props.banId UUID identifier of the ban record to be revoked
 * @param props.body Revocation details including the reason for revoking the ban
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor admin
 * @x-autobe-specification Update ban status to 'revoked' in discussion_board_ban_records table. Validate that the ban exists and is currently active (status: 'active'). Set revoked_at to current timestamp, store revocation_reason from request body, and record the administrator ID who performed the revocation. Ensure the banId parameter matches a valid UUID format and check that only active bans can be revoked (cannot revoke already expired or revoked bans). Return the updated ban record with revocation details.
 * @path /discussionBoard/admin/:banId/revoke
 * @accessor api.functional.discussionBoard.admin.revoke
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function revoke(
  connection: IConnection,
  props: revoke.Props,
): Promise<revoke.Response> {
  return true === connection.simulate
    ? revoke.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...revoke.METADATA,
          path: revoke.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace revoke {
  export type Props = {
    /**
     * UUID identifier of the ban record to be revoked
     */
    banId: string & tags.Format<"uuid">;

    /**
     * Revocation details including the reason for revoking the ban
     */
    body: IDiscussionBoardBanRecord.IRevoke;
  };
  export type Body = IDiscussionBoardBanRecord.IRevoke;
  export type Response = IDiscussionBoardBanRecord;

  export const METADATA = {
    method: "PATCH",
    path: "/discussionBoard/admin/:banId/revoke",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/discussionBoard/admin/${encodeURIComponent(props.banId ?? "null")}/revoke`;
  export const random = (): IDiscussionBoardBanRecord =>
    typia.random<IDiscussionBoardBanRecord>();
  export const simulate = (
    connection: IConnection,
    props: revoke.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: revoke.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("banId")(() => typia.assert(props.banId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
