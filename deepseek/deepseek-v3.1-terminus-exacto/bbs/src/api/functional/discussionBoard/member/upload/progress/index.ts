import { HttpError, IConnection } from "@nestia/fetcher";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";

import { IDiscussionBoardAttachment } from "../../../../../structures/IDiscussionBoardAttachment";

/**
 * Retrieve real-time upload progress information for file attachment operations.
 *
 * This endpoint provides detailed progress tracking for ongoing file uploads to articles, allowing users to monitor upload status during bulk attachment operations. The response includes comprehensive metrics such as total file count, completed files, bytes transferred, and individual file status.
 *
 * Upload progress is tracked per session and includes error handling for failed uploads. The system maintains upload state until completion or timeout, providing accurate progress indicators for large file batches.
 *
 * This operation supports the attachment management workflow by enabling users to monitor upload progress during article creation and editing, ensuring transparent feedback for multi-file upload operations.
 *
 * @param props.connection
 * @param props.uploadId Unique identifier for the upload session (global scope)
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor member
 * @x-autobe-specification Retrieve upload progress status for a specific upload session identified by uploadId.
 *
 * Query the upload tracking system to get current progress metrics including:
 * - Total file count and completed file count
 * - Bytes transferred vs total bytes
 * - Individual file upload statuses
 * - Estimated time remaining
 * - Any upload errors or warnings
 *
 * Return real-time progress data for display in the UI. Handle expired or non-existent upload sessions gracefully.
 * @path /discussionBoard/member/upload/progress/:uploadId
 * @accessor api.functional.discussionBoard.member.upload.progress.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique identifier for the upload session (global scope)
     */
    uploadId: string & tags.Format<"uuid">;
  };
  export type Response = IDiscussionBoardAttachment.IProgress;

  export const METADATA = {
    method: "GET",
    path: "/discussionBoard/member/upload/progress/:uploadId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/member/upload/progress/${encodeURIComponent(props.uploadId ?? "null")}`;
  export const random = (): IDiscussionBoardAttachment.IProgress =>
    typia.random<IDiscussionBoardAttachment.IProgress>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("uploadId")(() => typia.assert(props.uploadId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
