import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardConfiguration } from "../../../structures/IDiscussionBoardConfiguration";

/**
 * Retrieve a specific configuration setting by its unique key.
 *
 * This operation allows clients to retrieve individual configuration settings
 * from the discussion board platform. Each configuration is identified by a
 * unique config_key that corresponds to a specific system setting such as
 * attachment size limits, moderation policies, or content guidelines.
 *
 * The operation validates that the requested configuration key exists in the
 * system and returns the corresponding configuration value along with metadata
 * about the setting. If the configuration key does not exist, the operation
 * returns an appropriate error response.
 *
 * Configuration settings are stored as key-value pairs with type information,
 * allowing the system to interpret values correctly based on the config_type
 * field. This design enables flexible system customization without requiring
 * code changes for each configuration modification.
 *
 * Security considerations include rate limiting for configuration queries and
 * appropriate access controls to prevent unauthorized viewing of sensitive
 * system settings. Configuration retrieval is typically available to
 * authenticated users with appropriate permissions.
 *
 * @param props.connection
 * @param props.configKey Unique identifier key of the configuration setting to
 *   retrieve
 * @path /discussionBoard/configurations/:configKey
 * @accessor api.functional.discussionBoard.configurations.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique identifier key of the configuration setting to retrieve */
    configKey: string;
  };
  export type Response = IDiscussionBoardConfiguration;

  export const METADATA = {
    method: "GET",
    path: "/discussionBoard/configurations/:configKey",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/configurations/${encodeURIComponent(props.configKey ?? "null")}`;
  export const random = (): IDiscussionBoardConfiguration =>
    typia.random<IDiscussionBoardConfiguration>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("configKey")(() => typia.assert(props.configKey));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
