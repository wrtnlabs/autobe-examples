import { IConnection } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";

import { IDiscussionBoardBackupRecord } from "../../../../structures/IDiscussionBoardBackupRecord";

/**
 * Retrieve comprehensive data export packages from the discussion board platform.
 *
 * This operation provides system administrators with the ability to export platform data for compliance, backup, and analysis purposes. The export includes user profiles, articles, comments, sections, and administrative records in structured JSON format.
 *
 * The export operation generates a complete snapshot of the platform data at the time of request. The data is organized into logical sections corresponding to the main entities in the system, making it easy to parse and analyze.
 *
 * Each export package includes comprehensive metadata such as the export timestamp, data scope, and integrity verification information. This ensures that exported data can be reliably used for compliance reporting, system migrations, or archival purposes.
 *
 * Related operations include user profile management for individual data access and administrative functions for platform-wide data management. The export functionality supports data protection regulations by providing users and administrators with transparent access to platform data.
 *
 * @param props.connection
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor user
 * @x-autobe-specification Generate comprehensive data export packages for the discussion board platform. The operation should export user profiles, articles, comments, sections, and administrative data in structured formats. The export includes metadata about the export scope, timestamp, and data integrity checksums.
 * @path /discussionBoard/user/export
 * @accessor api.functional.discussionBoard.user._export.generateExport
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function generateExport(
  connection: IConnection,
): Promise<generateExport.Response> {
  return true === connection.simulate
    ? generateExport.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...generateExport.METADATA,
          path: generateExport.path(),
          status: null,
        },
      );
}
export namespace generateExport {
  export type Response = IDiscussionBoardBackupRecord;

  export const METADATA = {
    method: "GET",
    path: "/discussionBoard/user/export",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/discussionBoard/user/export";
  export const random = (): IDiscussionBoardBackupRecord =>
    typia.random<IDiscussionBoardBackupRecord>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}
