/**
 * Retrieve paginated list of articles sorted by recent comment activity.
 *
 * This endpoint provides specialized sorting functionality that prioritizes articles based on their most recent comment activity, rather than just publication date. The operation analyzes comment timestamps across all articles to identify the most recently active discussions, making it ideal for users who want to participate in ongoing conversations.
 *
 * The system queries both the discussion_board_articles table and the discussion_board_comments table to determine activity patterns. Articles without comments are ranked by their original publication date. The response provides summary information optimized for list displays, including basic article metadata and comment count indicators.
 *
 * Security considerations ensure that only published articles are included in results, respecting content workflow states. The operation supports comprehensive pagination with configurable page sizes and cursor-based navigation for efficient browsing of large result sets.
 *
 * This endpoint complements standard chronological sorting by providing activity-based ranking, enhancing user engagement with the most current discussions on the platform.
 *
 * @param props.connection
 * @param props.body Pagination and filtering parameters for recently active articles
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor user
 * @x-autobe-specification Query the discussion_board_articles table joined with discussion_board_comments to determine recent activity.
 *
 * Implementation steps:
 * 1. Join articles with comments on discussion_board_article_id
 * 2. Group by article and select max(comments.created_at) as last_activity
 * 3. For articles without comments, use articles.created_at as last_activity
 * 4. Sort by last_activity descending
 * 5. Apply pagination parameters from request body
 * 6. Filter to only include articles with status = 'published'
 * 7. Return paginated results with summary information
 *
 * Include article title, author info, section info, comment count, and last_activity timestamp in response. Handle edge cases where articles have no comments or are in draft/archived status.
 *
 * Performance considerations:
 * - Use composite indexes on (discussion_board_article_id, created_at) in comments table
 * - Cache frequently accessed results for performance
 * - Implement efficient cursor-based pagination
 * @path /discussionBoard/user/recently-active
 * @accessor api.functional.discussionBoard.user.recently_active.recentlyActive
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function recentlyActive(
  connection: IConnection,
  props: recentlyActive.Props,
): Promise<recentlyActive.Response> {
  return true === connection.simulate
    ? recentlyActive.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...recentlyActive.METADATA,
          path: recentlyActive.path(),
          status: null,
        },
        props.body,
      );
}
