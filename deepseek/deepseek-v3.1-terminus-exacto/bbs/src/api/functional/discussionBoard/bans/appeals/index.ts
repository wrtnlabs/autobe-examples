/**
 * Submit an appeal against a ban decision to request reconsideration.
 *
 * This operation allows users who have been banned to formally appeal the decision by providing a reason for reconsideration. The appeal creates a structured workflow for administrators to review ban decisions and ensures transparency in moderation actions.
 *
 * When an appeal is submitted, it enters the 'pending' status and awaits administrator review. Users can only appeal active bans that reference their own user account. The appeal process supports the platform's commitment to fair moderation practices.
 *
 * Appeals are linked to specific ban records through the discussion_board_ban_record_id field and include detailed appeal reasons in the appeal_reason field. The system maintains a complete audit trail with timestamps for appealed_at, created_at, and updated_at fields.
 *
 * Related operations include viewing appeal status through GET operations, updating appeal decisions through administrative interfaces, and managing the appeal review workflow.
 *
 * @param props.connection
 * @param props.banId Unique identifier of the ban record being appealed
 * @param props.body Appeal submission details including the reason for appealing
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor null
 * @x-autobe-specification Create a new ban appeal record in the discussion_board_ban_appeals table.
 *
 * Validate that the ban record exists and is currently active.
 * Ensure the user is not already banned from submitting appeals.
 * Set initial appeal status to 'pending'.
 * Record appeal timestamp and user information.
 * Validate appeal reason meets minimum length requirements.
 * Return the complete appeal record with generated ID and timestamps.
 * @path /discussionBoard/bans/:banId/appeals
 * @accessor api.functional.discussionBoard.bans.appeals.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function create(
  connection: IConnection,
  props: create.Props,
): Promise<create.Response> {
  return true === connection.simulate
    ? create.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...create.METADATA,
          path: create.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace create {
  export type Props = {
    /**
     * Unique identifier of the ban record being appealed
     */
    banId: string & tags.Format<"uuid">;

    /**
     * Appeal submission details including the reason for appealing
     */
    body: IDiscussionBoardBanAppeal.ICreate;
  };
  export type Body = IDiscussionBoardBanAppeal.ICreate;
  export type Response = IDiscussionBoardBanAppeal;

  export const METADATA = {
    method: "POST",
    path: "/discussionBoard/bans/:banId/appeals",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/discussionBoard/bans/${encodeURIComponent(props.banId ?? "null")}/appeals`;
  export const random = (): IDiscussionBoardBanAppeal =>
    typia.random<IDiscussionBoardBanAppeal>();
  export const simulate = (
    connection: IConnection,
    props: create.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: create.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("banId")(() => typia.assert(props.banId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
