import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardPost } from "../../../../structures/IDiscussionBoardPost";
import { IPageIDiscussionBoardPost } from "../../../../structures/IPageIDiscussionBoardPost";

/**
 * This operation enables users to search through discussion board posts using
 * advanced filtering criteria and pagination controls. It supports searching by
 * post title, content text, channel categorization, section organization, post
 * status, pinning status, and creation date ranges.
 *
 * The search functionality leverages full-text indexing on title and content
 * fields to provide efficient text-based searching. Users can filter results by
 * specific channels or sections to narrow down discussions to particular
 * topics. The operation also supports filtering by post status (draft,
 * published, archived) and pinning status to focus on active or featured
 * content.
 *
 * Pagination is implemented with configurable page sizes and sorting options,
 * allowing users to browse large result sets efficiently. Results can be sorted
 * by creation date, update date, publication date, or relevance score when
 * using text search. The operation integrates with the discussion_board_posts
 * table and maintains proper relationship references to channels and sections.
 *
 * Security considerations include appropriate access controls based on post
 * status and user permissions. Published posts are generally accessible to all
 * users, while draft posts are restricted to authors and moderators. The
 * operation implements rate limiting to prevent abuse and ensures efficient
 * database query performance through proper indexing.
 *
 * @param props.connection
 * @param props.body Search criteria and pagination parameters for post
 *   filtering
 * @path /discussionBoard/search/posts
 * @accessor api.functional.discussionBoard.search.posts.search
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function search(
  connection: IConnection,
  props: search.Props,
): Promise<search.Response> {
  return true === connection.simulate
    ? search.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...search.METADATA,
          path: search.path(),
          status: null,
        },
        props.body,
      );
}
export namespace search {
  export type Props = {
    /** Search criteria and pagination parameters for post filtering */
    body: IDiscussionBoardPost.IRequest;
  };
  export type Body = IDiscussionBoardPost.IRequest;
  export type Response = IPageIDiscussionBoardPost.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/discussionBoard/search/posts",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/discussionBoard/search/posts";
  export const random = (): IPageIDiscussionBoardPost.ISummary =>
    typia.random<IPageIDiscussionBoardPost.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: search.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: search.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
