/**
 * This operation provides comprehensive search capabilities for viewing post
 * engagement analytics. It allows filtering view records by member, date
 * ranges, and other criteria to analyze post popularity and user engagement
 * patterns.
 *
 * The operation supports advanced pagination with configurable page sizes and
 * sorting options. Views can be sorted by creation date, member, or other
 * relevant fields in ascending or descending order. This data is essential for
 * content analytics and helps identify trending discussions and user behavior
 * patterns.
 *
 * Security considerations include restricting access to authorized moderators
 * only, as view data contains user engagement information. The operation
 * integrates with the discussion_board_post_views table as defined in the
 * Prisma schema, incorporating all available view tracking fields and
 * relationships.
 *
 * @param props.connection
 * @param props.postId Unique identifier of the target discussion board post
 * @param props.body Search criteria and pagination parameters for filtering
 *   view records
 * @path /discussionBoard/moderator/posts/:postId/views
 * @accessor api.functional.discussionBoard.moderator.posts.views.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /** Unique identifier of the target discussion board post */
    postId: string & tags.Format<"uuid">;

    /** Search criteria and pagination parameters for filtering view records */
    body: IDiscussionBoardPostView.IRequest;
  };
  export type Body = IDiscussionBoardPostView.IRequest;
  export type Response = IPageIDiscussionBoardPostView.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/discussionBoard/moderator/posts/:postId/views",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/discussionBoard/moderator/posts/${encodeURIComponent(props.postId ?? "null")}/views`;
  export const random = (): IPageIDiscussionBoardPostView.ISummary =>
    typia.random<IPageIDiscussionBoardPostView.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("postId")(() => typia.assert(props.postId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
