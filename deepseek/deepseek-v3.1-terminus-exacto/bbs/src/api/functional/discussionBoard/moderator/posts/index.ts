/**
 * This operation permanently removes a discussion board post from the system.
 * When a post is deleted, all associated comments, attachments, and related
 * data are also removed to maintain database integrity.
 *
 * The operation performs validation checks to ensure the requesting user has
 * appropriate permissions to delete the post. For member-created posts,
 * deletion is restricted to the original author or users with administrative
 * privileges. For moderator-created posts, appropriate moderator-level
 * permissions are required.
 *
 * Deletion is irreversible and cannot be undone. Once a post is deleted, it is
 * completely removed from the database along with all its associated content.
 * Users should exercise caution when using this operation as there is no
 * recovery mechanism for deleted posts.
 *
 * The operation returns the deleted post information as confirmation of
 * successful deletion. This allows the client to verify that the intended post
 * was removed and provides a record of what was deleted for audit purposes.
 *
 * @param props.connection
 * @param props.postId Unique identifier of the target post to be deleted
 * @path /discussionBoard/moderator/posts/:postId
 * @accessor api.functional.discussionBoard.moderator.posts.erase
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function erase(
  connection: IConnection,
  props: erase.Props,
): Promise<erase.Response> {
  return true === connection.simulate
    ? erase.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...erase.METADATA,
          path: erase.path(props),
          status: null,
        },
      );
}
export namespace erase {
  export type Props = {
    /** Unique identifier of the target post to be deleted */
    postId: string & tags.Format<"uuid">;
  };
  export type Response = IDiscussionBoardPost;

  export const METADATA = {
    method: "DELETE",
    path: "/discussionBoard/moderator/posts/:postId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/moderator/posts/${encodeURIComponent(props.postId ?? "null")}`;
  export const random = (): IDiscussionBoardPost =>
    typia.random<IDiscussionBoardPost>();
  export const simulate = (
    connection: IConnection,
    props: erase.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: erase.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("postId")(() => typia.assert(props.postId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
