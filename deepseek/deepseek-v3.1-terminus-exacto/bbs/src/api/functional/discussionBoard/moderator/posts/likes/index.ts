import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardPostLike } from "../../../../../structures/IDiscussionBoardPostLike";
import { IPageIDiscussionBoardPostLike } from "../../../../../structures/IPageIDiscussionBoardPostLike";

/**
 * Search and retrieve paginated like records for a specific discussion board
 * post.
 *
 * This operation provides comprehensive search capabilities for analyzing post
 * appreciation metrics. It allows filtering like records by member, date
 * ranges, and other criteria to measure content popularity and user engagement
 * through likes.
 *
 * The operation supports advanced pagination with configurable page sizes and
 * sorting options. Likes can be sorted by creation date, member, or other
 * relevant fields in ascending or descending order. This data helps identify
 * highly appreciated content and user preferences within the discussion board
 * community.
 *
 * Security considerations include restricting access to authorized moderators
 * only, as like data contains user engagement information. The operation
 * integrates with the discussion_board_post_likes table as defined in the
 * Prisma schema, incorporating all available like tracking fields and
 * relationships.
 *
 * @param props.connection
 * @param props.postId Unique identifier of the target discussion board post
 * @param props.body Search criteria and pagination parameters for filtering
 *   like records
 * @path /discussionBoard/moderator/posts/:postId/likes
 * @accessor api.functional.discussionBoard.moderator.posts.likes.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /** Unique identifier of the target discussion board post */
    postId: string & tags.Format<"uuid">;

    /** Search criteria and pagination parameters for filtering like records */
    body: IDiscussionBoardPostLike.IRequest;
  };
  export type Body = IDiscussionBoardPostLike.IRequest;
  export type Response = IPageIDiscussionBoardPostLike.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/discussionBoard/moderator/posts/:postId/likes",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/discussionBoard/moderator/posts/${encodeURIComponent(props.postId ?? "null")}/likes`;
  export const random = (): IPageIDiscussionBoardPostLike.ISummary =>
    typia.random<IPageIDiscussionBoardPostLike.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("postId")(() => typia.assert(props.postId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
