/**
 * This operation provides comprehensive moderation statistics by aggregating
 * data from the moderation workflow tables. It generates key performance
 * indicators that help moderators monitor moderation effectiveness, identify
 * trends, and optimize moderation workflows.
 *
 * The statistics include report volume metrics showing daily, weekly, and
 * monthly trends in content reporting activity. This helps identify peak
 * reporting periods and potential spam or coordinated reporting patterns. The
 * operation also computes moderation efficiency metrics such as average
 * response time, resolution rates, and moderator workload distribution across
 * different queue types.
 *
 * Queue performance statistics provide insights into moderation workflow
 * efficiency, including average queue wait times, assignment completion rates,
 * and timeout incidents. These metrics help moderators balance workloads and
 * identify bottlenecks in the moderation pipeline. The statistics are
 * calculated based on actual moderation activities recorded in the
 * discussion_board_content_reports, discussion_board_moderation_actions, and
 * discussion_board_moderation_queues tables.
 *
 * Security considerations ensure that only authorized moderators can access
 * these sensitive moderation statistics. The operation includes appropriate
 * rate limiting to prevent excessive computational load from frequent
 * statistical queries. The response provides both summary statistics and
 * detailed breakdowns by report type, priority level, and time periods for
 * comprehensive moderation oversight.
 *
 * @param props.connection
 * @param props.body Search criteria and date range parameters for moderation
 *   statistics filtering
 * @path /discussionBoard/moderator/moderation/statistics
 * @accessor api.functional.discussionBoard.moderator.moderation.statistics.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Search criteria and date range parameters for moderation statistics
     * filtering
     */
    body: IDiscussionBoardModerationStatistics.IRequest;
  };
  export type Body = IDiscussionBoardModerationStatistics.IRequest;
  export type Response = IDiscussionBoardModerationStatistics;

  export const METADATA = {
    method: "PATCH",
    path: "/discussionBoard/moderator/moderation/statistics",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/discussionBoard/moderator/moderation/statistics";
  export const random = (): IDiscussionBoardModerationStatistics =>
    typia.random<IDiscussionBoardModerationStatistics>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
