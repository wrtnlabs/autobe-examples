/**
 * This operation provides advanced search and filtering capabilities for
 * comments associated with a specific discussion board post. It allows users to
 * retrieve comments with various filtering options, pagination controls, and
 * sorting preferences.
 *
 * The operation supports comprehensive search functionality including text
 * matching within comment content, filtering by comment status (published,
 * draft, deleted), and filtering by author. Users can specify pagination
 * parameters such as page number and page size to control the volume of results
 * returned.
 *
 * Sorting options include creation date, update date, thread level, and other
 * relevant fields. The operation automatically handles threaded comment
 * hierarchies, maintaining proper parent-child relationships in the response
 * data.
 *
 * Security is enforced through access controls that verify the requesting user
 * has appropriate permissions to view the parent post and its comments. The
 * operation respects the post's locked status and other visibility
 * restrictions. Comments that have been soft-deleted are filtered out unless
 * explicitly requested by users with appropriate permissions.
 *
 * @param props.connection
 * @param props.postId Unique identifier of the target post whose comments are
 *   being retrieved
 * @param props.body Search criteria and pagination parameters for comment
 *   filtering
 * @path /discussionBoard/moderator/posts/:postId/comments
 * @accessor api.functional.discussionBoard.moderator.posts.comments.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Unique identifier of the target post whose comments are being
     * retrieved
     */
    postId: string & tags.Format<"uuid">;

    /** Search criteria and pagination parameters for comment filtering */
    body: IDiscussionBoardComment.IRequest;
  };
  export type Body = IDiscussionBoardComment.IRequest;
  export type Response = IPageIDiscussionBoardComment.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/discussionBoard/moderator/posts/:postId/comments",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/discussionBoard/moderator/posts/${encodeURIComponent(props.postId ?? "null")}/comments`;
  export const random = (): IPageIDiscussionBoardComment.ISummary =>
    typia.random<IPageIDiscussionBoardComment.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("postId")(() => typia.assert(props.postId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
