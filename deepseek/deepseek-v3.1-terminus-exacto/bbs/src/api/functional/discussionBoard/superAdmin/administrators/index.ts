/**
 * Promote a regular administrator to super administrator status.
 *
 * This operation allows super administrators to elevate regular administrators to super administrator privileges, granting them expanded platform governance capabilities including the ability to promote/demote other administrators and perform advanced administrative functions.
 *
 * Authorization requires the requesting user to hold super administrator status. The target administrator must be a regular administrator (not already a super administrator) and the operation cannot be performed on the requesting user's own account. The system maintains audit trails of all privilege changes through the administrator assignment history table.
 *
 * Upon successful promotion, the target administrator gains all super administrator capabilities while retaining their existing regular administrator functions. Administrative hierarchy is maintained with at least one super administrator required to ensure platform governance stability.
 *
 * @param props.connection
 * @param props.administratorId Target administrator's unique identifier to be promoted
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor superAdmin
 * @x-autobe-specification Validate the current user has super administrator privileges by checking their admin_grade field. Verify the target administrator exists and has admin_grade 'regular' (not already super admin). Update the target administrator's admin_grade from 'regular' to 'super'. Record the promotion in the assignment history table for audit trail. Return the updated administrator details with the new grade. Enforce business rules: cannot promote self, cannot promote if target is already super admin, must have at least one super admin remaining.
 * @path /discussionBoard/superAdmin/administrators/:administratorId/promote
 * @accessor api.functional.discussionBoard.superAdmin.administrators.promote
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function promote(
  connection: IConnection,
  props: promote.Props,
): Promise<promote.Response> {
  return true === connection.simulate
    ? promote.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...promote.METADATA,
          path: promote.path(props),
          status: null,
        },
      );
}
export namespace promote {
  export type Props = {
    /**
     * Target administrator's unique identifier to be promoted
     */
    administratorId: string & tags.Format<"uuid">;
  };
  export type Response = IDiscussionBoardAdmin;

  export const METADATA = {
    method: "PATCH",
    path: "/discussionBoard/superAdmin/administrators/:administratorId/promote",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/superAdmin/administrators/${encodeURIComponent(props.administratorId ?? "null")}/promote`;
  export const random = (): IDiscussionBoardAdmin =>
    typia.random<IDiscussionBoardAdmin>();
  export const simulate = (
    connection: IConnection,
    props: promote.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: promote.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("administratorId")(() =>
        typia.assert(props.administratorId),
      );
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
