/**
 * Retrieve detailed information for a specific discussion board article.
 *
 * This operation provides complete article details including the full content, author information, section assignment, publication status, and timestamps. The response includes all article metadata required for displaying a complete article view in the discussion board interface.
 *
 * Article content includes the main text body, title, and publication status which determines visibility and editing permissions. Author information links to the user profile system for attribution and user engagement tracking. Section assignment categorizes the article within the discussion board's organizational structure.
 *
 * Security considerations require that only published articles are visible to regular users, while administrators may access draft and archived articles for moderation purposes. The operation validates article existence and user permissions before returning sensitive content.
 *
 * Related operations include PATCH /articles for searching and listing articles, POST /articles for creating new articles, and PUT /articles/{articleId} for updating existing articles. This operation serves as the primary endpoint for individual article viewing and content consumption.
 *
 * @param props.connection
 * @param props.articleId Unique identifier of the article to retrieve
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor null
 * @x-autobe-specification Query the discussion_board_articles table by primary key to retrieve the specific article.
 * Join with discussion_board_users table to get author display name and profile information.
 * Join with discussion_board_sections table to get section name and description.
 * Include related attachments and tags through additional queries to discussion_board_article_files and discussion_board_article_tags tables.
 * Validate that the article exists and handle 404 responses appropriately.
 * Implement permission checks: regular users can only access published articles, administrators can access all statuses.
 * Return complete article data including content, metadata, and related information in a single response.
 * Handle soft-deleted articles by filtering out articles where deleted_at is not null unless user has administrative privileges.
 * @path /discussionBoard/articles/:articleId
 * @accessor api.functional.discussionBoard.articles.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique identifier of the article to retrieve
     */
    articleId: string & tags.Format<"uuid">;
  };
  export type Response = IDiscussionBoardArticle;

  export const METADATA = {
    method: "GET",
    path: "/discussionBoard/articles/:articleId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/articles/${encodeURIComponent(props.articleId ?? "null")}`;
  export const random = (): IDiscussionBoardArticle =>
    typia.random<IDiscussionBoardArticle>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("articleId")(() => typia.assert(props.articleId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
