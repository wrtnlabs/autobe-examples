import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardComment } from "../../../../structures/IDiscussionBoardComment";

/**
 * This operation retrieves detailed information about a specific comment within
 * a discussion board post. The operation requires both the post identifier and
 * comment identifier to ensure the comment belongs to the correct post
 * context.
 *
 * Comments are hierarchical and support threaded discussions up to 3 levels
 * deep as specified in the requirements. Each comment includes content with
 * Markdown formatting support, author information, threading level, status, and
 * timestamps for creation and modification.
 *
 * The operation performs validation to ensure the comment exists and belongs to
 * the specified post. It returns the complete comment object including all
 * fields from the discussion_board_comments table. This operation is essential
 * for displaying individual comments in discussion threads and supporting
 * comment management features.
 *
 * Security considerations include proper authorization checks to ensure users
 * can only access comments they are permitted to view. The operation respects
 * comment status (draft, published, deleted) and returns appropriate responses
 * based on the comment's current state.
 *
 * @param props.connection
 * @param props.postId Unique identifier of the parent post containing the
 *   target comment
 * @param props.commentId Unique identifier of the target comment within the
 *   specified post
 * @path /discussionBoard/posts/:postId/comments/:commentId
 * @accessor api.functional.discussionBoard.posts.comments.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique identifier of the parent post containing the target comment */
    postId: string & tags.Format<"uuid">;

    /** Unique identifier of the target comment within the specified post */
    commentId: string & tags.Format<"uuid">;
  };
  export type Response = IDiscussionBoardComment;

  export const METADATA = {
    method: "GET",
    path: "/discussionBoard/posts/:postId/comments/:commentId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/posts/${encodeURIComponent(props.postId ?? "null")}/comments/${encodeURIComponent(props.commentId ?? "null")}`;
  export const random = (): IDiscussionBoardComment =>
    typia.random<IDiscussionBoardComment>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("postId")(() => typia.assert(props.postId));
      assert.param("commentId")(() => typia.assert(props.commentId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
