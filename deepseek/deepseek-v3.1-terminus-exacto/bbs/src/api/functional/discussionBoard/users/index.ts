/**
 * Search and retrieve a paginated list of user accounts with filtering capabilities.
 *
 * This operation provides advanced search functionality for user accounts across the discussion board platform. It supports filtering by display name (with partial matching), email address (exact or domain-based filtering), and account status. The response includes user summary information suitable for list displays and user browsing interfaces.
 *
 * Supports comprehensive pagination with configurable page sizes and sorting options. Users can search for specific individuals or browse user profiles based on various criteria. The operation respects user privacy by excluding sensitive authentication data from the response.
 *
 * This endpoint is particularly useful for administrators managing user accounts, community members looking for specific contributors, or system administrators performing user account maintenance tasks.
 *
 * @param props.connection
 * @param props.body Search criteria and pagination parameters for user filtering
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor null
 * @x-autobe-specification Query discussion_board_users table with pagination and filtering capabilities. Apply search filters on display_name (partial matching), email (exact or domain matching), and account status (active/deleted). Support cursor-based pagination for efficient large result sets. Return user summaries optimized for list displays without sensitive information like password_hash.
 * @path /discussionBoard/users
 * @accessor api.functional.discussionBoard.users.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Search criteria and pagination parameters for user filtering
     */
    body: IDiscussionBoardUser.IRequest;
  };
  export type Body = IDiscussionBoardUser.IRequest;
  export type Response = IPageIDiscussionBoardUser.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/discussionBoard/users",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/discussionBoard/users";
  export const random = (): IPageIDiscussionBoardUser.ISummary =>
    typia.random<IPageIDiscussionBoardUser.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

