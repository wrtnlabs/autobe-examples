import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardPost } from "../../structures/IDiscussionBoardPost";
import { IPageIDiscussionBoardPost } from "../../structures/IPageIDiscussionBoardPost";

/**
 * This operation provides advanced search capabilities for finding discussion
 * board posts across the entire platform. Users can filter posts by various
 * criteria including title keywords, content search, post status (draft,
 * published, archived), creation date ranges, channel association, and sorting
 * options.
 *
 * The operation leverages the discussion_board_posts table structure and its
 * relationships to channels and sections. It supports comprehensive pagination
 * with configurable page sizes and multiple sorting options including creation
 * date, update date, title, and pin status.
 *
 * Security considerations include appropriate access control based on channel
 * permissions. The operation validates user permissions for specific channels
 * when filtering by channel_id. Public users can search published posts, while
 * authenticated users may have additional access based on their roles.
 *
 * This operation integrates with the discussion_board_posts table as defined in
 * the Prisma schema, incorporating all available post fields and relationships.
 * The response includes post summary information optimized for list displays,
 * with options to include additional details based on authorization level.
 *
 * @param props.connection
 * @param props.body Search criteria and pagination parameters for post
 *   filtering, including optional channel filtering
 * @path /posts
 * @accessor api.functional.posts.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Search criteria and pagination parameters for post filtering,
     * including optional channel filtering
     */
    body: IDiscussionBoardPost.IRequest;
  };
  export type Body = IDiscussionBoardPost.IRequest;
  export type Response = IPageIDiscussionBoardPost.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/posts",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/posts";
  export const random = (): IPageIDiscussionBoardPost.ISummary =>
    typia.random<IPageIDiscussionBoardPost.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
