/**
 * Create a temporary guest account for anonymous browsing of discussion board
 * content.
 *
 * This API operation handles guest registration for the discussion board
 * platform, creating temporary anonymous accounts that allow users to browse
 * public content without full authentication. The operation generates a unique
 * guest_token using UUID v4 format and stores it in the discussion_board_guests
 * table along with creation timestamps.
 *
 * Guest accounts serve as temporary identifiers for users exploring the
 * platform before committing to registration. Unlike members and moderators,
 * guests do not require traditional authentication credentials until they
 * complete the registration process. The guest_token field provides anonymous
 * tracking capability while maintaining user privacy.
 *
 * The operation follows the platform's guest management workflow where
 * temporary accounts can be upgraded to full member accounts. Guest records may
 * be converted to member accounts upon successful registration, maintaining
 * continuity of user identity while transitioning from anonymous to
 * authenticated status.
 *
 * Security considerations include generating cryptographically secure guest
 * tokens and ensuring proper token validation for subsequent API calls. The
 * system tracks guest interactions through the guest_token field while
 * respecting user privacy and anonymity requirements.
 *
 * Related operations include guest token refresh for extending session validity
 * and member registration for converting guest accounts to full member status
 * with enhanced privileges.
 *
 * @param props.connection
 * @setHeader token.access Authorization
 *
 * @path /auth/guest/join
 * @accessor api.functional.auth.guest.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(connection: IConnection): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
export namespace join {
  export type Response = IDiscussionBoardGuest.IAuthorized;

  export const METADATA = {
    method: "POST",
    path: "/auth/guest/join",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/guest/join";
  export const random = (): IDiscussionBoardGuest.IAuthorized =>
    typia.random<IDiscussionBoardGuest.IAuthorized>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}

