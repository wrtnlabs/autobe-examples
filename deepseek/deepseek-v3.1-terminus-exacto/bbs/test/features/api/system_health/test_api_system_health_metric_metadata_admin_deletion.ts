export async function test_api_system_health_metric_metadata_admin_deletion(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as administrator
  const adminConnection: api.IConnection = { host: connection.host };
  const admin = await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IDiscussionBoardAdmin.IJoin,
  });
  typia.assert(admin);
  // 2. Generate valid UUIDs for metric and metadata
  const metricId = typia.random<string & tags.Format<"uuid">>();
  const metadataId = typia.random<string & tags.Format<"uuid">>();
  // 3. Call the DELETE endpoint with valid parameters
  await api.functional.discussionBoard.admin.system_health_metrics.metadata.erase(
    adminConnection,
    {
      metricId,
      metadataId,
    },
  );
  // The erase function returns void on successful deletion
  // No additional validation needed as the function would throw on error
}
