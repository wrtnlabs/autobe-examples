export async function test_api_system_health_mixed_status_aggregation(
  connection: api.IConnection,
): Promise<void> {
  // Create super administrator connection using utility function
  const superAdminConnection: api.IConnection = { host: connection.host };
  const authResult = await authorize_super_admin_join(superAdminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IDiscussionBoardSuperAdmin.IJoin,
  });
  typia.assert(authResult);
  // Call the health endpoint
  const healthResponse =
    await api.functional.discussionBoard.superAdmin.health.at(
      superAdminConnection,
    );
  typia.assert(healthResponse);
  // Validate status is one of the expected values without redundant checks
  const validStatuses = ["healthy", "warning", "critical"] as const;
  TestValidator.predicate(
    "status is valid",
    validStatuses.includes(
      healthResponse.status as (typeof validStatuses)[number],
    ),
  );
}
