export async function test_api_moderation_action_type_retrieval_by_super_admin(
  connection: api.IConnection,
): Promise<void> {
  // Create super admin connection
  const superAdminConnection: api.IConnection = { host: connection.host };
  await authorize_super_admin_join(superAdminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      privilege_level: "super_admin",
    } satisfies IDiscussionBoardSuperAdmin.IJoin,
  });
  // Retrieve moderation action type
  const moderationActionType =
    await api.functional.discussionBoard.superAdmin.moderation_action_types.at(
      superAdminConnection,
      {
        actionTypeId: typia.random<string & tags.Format<"uuid">>(),
      },
    );
  // Validate response structure - typia.assert performs complete validation
  typia.assert(moderationActionType);
}
