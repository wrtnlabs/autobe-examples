/**
 * Test comment moderation validation when attempting to moderate a comment through
 * the wrong article path. This ensures relational integrity between articles and
 * their comments in the moderation system.
 */
export async function test_api_comment_moderation_wrong_article_validation(
  connection: api.IConnection,
): Promise<void> {
  // Create super admin connection
  const superAdminConnection: api.IConnection = { host: connection.host };
  await authorize_super_admin_join(superAdminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      privilege_level: "super_admin",
    } satisfies IDiscussionBoardSuperAdmin.IJoin,
  });
  // Create user connection
  const userConnection: api.IConnection = { host: connection.host };
  await authorize_user_join(userConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      bio: RandomGenerator.paragraph({ sentences: 2 }),
    } satisfies IDiscussionBoardUser.IJoin,
  });
  // Note: In a real implementation, we would need to create sections first
  // Since section creation is not available in the provided API functions,
  // we'll use the existing approach but acknowledge the limitation
  // Create first article
  const articleA = await generate_random_discussion_board_user_articles_create(
    userConnection,
    {
      body: {
        title: RandomGenerator.paragraph({ sentences: 2 }),
        content: RandomGenerator.content({ paragraphs: 1 }),
        section_id: typia.random<string & tags.Format<"uuid">>(),
        status: "published" as const,
      } satisfies IDiscussionBoardArticle.ICreate,
    },
  );
  typia.assert(articleA);
  // Create second article
  const articleB = await generate_random_discussion_board_user_articles_create(
    userConnection,
    {
      body: {
        title: RandomGenerator.paragraph({ sentences: 2 }),
        content: RandomGenerator.content({ paragraphs: 1 }),
        section_id: typia.random<string & tags.Format<"uuid">>(),
        status: "published" as const,
      } satisfies IDiscussionBoardArticle.ICreate,
    },
  );
  typia.assert(articleB);
  // Create comment on article A
  const comment =
    await generate_random_discussion_board_user_articles_comments_create(
      userConnection,
      {
        body: {
          content: RandomGenerator.paragraph({ sentences: 3 }),
        } satisfies IDiscussionBoardComment.ICreate,
        params: {
          articleId: articleA.id,
        },
      },
    );
  typia.assert(comment);
  // Attempt to moderate comment through wrong article B path
  await TestValidator.error(
    "should reject moderation when comment belongs to different article",
    async () => {
      await api.functional.discussionBoard.superAdmin.articles.comments.moderations.create(
        superAdminConnection,
        {
          articleId: articleB.id,
          commentId: comment.id,
          body: {
            action_type: "delete" as const,
            reason: RandomGenerator.paragraph({ sentences: 2 }),
          } satisfies IDiscussionBoardCommentModeration.ICreate,
        },
      );
    },
  );
  // The test successfully validates that the system rejects the moderation request
  // when the comment doesn't belong to the specified article, ensuring relational
  // integrity is maintained in the moderation workflow
}
