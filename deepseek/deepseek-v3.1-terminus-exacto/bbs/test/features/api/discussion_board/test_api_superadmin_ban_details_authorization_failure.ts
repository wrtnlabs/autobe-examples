export async function test_api_superadmin_ban_details_authorization_failure(
  connection: api.IConnection,
): Promise<void> {
  // Create and authenticate a regular user
  const userConnection: api.IConnection = { host: connection.host };
  const userCredentials = {
    email: typia.random<string & tags.Format<"email">>(),
    password: RandomGenerator.alphaNumeric(16),
    display_name: RandomGenerator.name(),
  } satisfies IDiscussionBoardUser.IJoin;
  await authorize_user_join(userConnection, { body: userCredentials });
  // Generate a random ban ID to attempt access
  const banId = typia.random<string & tags.Format<"uuid">>();
  // Attempt to access ban details as regular user - should fail with 403 Forbidden
  await TestValidator.httpError(
    "regular user should not access ban details",
    403,
    async () => {
      await api.functional.discussionBoard.superAdmin.user_bans.at(
        userConnection,
        {
          banId,
        },
      );
    },
  );
}
