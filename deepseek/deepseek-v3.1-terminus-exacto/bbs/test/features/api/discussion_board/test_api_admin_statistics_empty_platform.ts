export async function test_api_admin_statistics_empty_platform(
  connection: api.IConnection,
): Promise<void> {
  // Create admin connection
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IDiscussionBoardAdmin.IJoin,
  });
  // Retrieve platform statistics
  const statistics =
    await api.functional.discussionBoard.admin.statistics.at(adminConnection);
  typia.assert(statistics);
  // Validate that statistics structure is properly formed for an empty platform
  // The response should contain valid performance metric data
  TestValidator.predicate(
    "statistics contains valid performance metric data",
    statistics.metric_type.length > 0 && statistics.source_component.length > 0,
  );
}
