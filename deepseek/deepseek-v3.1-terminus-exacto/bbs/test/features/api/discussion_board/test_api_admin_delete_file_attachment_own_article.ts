export async function test_api_admin_delete_file_attachment_own_article(
  connection: api.IConnection,
): Promise<void> {
  // Create admin connection
  const adminConnection: api.IConnection = { host: connection.host };
  // Authenticate as administrator
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IDiscussionBoardAdmin.IJoin,
  });
  // Create an article
  const article = await generate_random_discussion_board_admin_articles_create(
    adminConnection,
    {
      body: {
        title: RandomGenerator.paragraph({ sentences: 2 }),
        content: RandomGenerator.content({ paragraphs: 3 }),
        discussion_board_section_id: typia.random<
          string & tags.Format<"uuid">
        >(),
      } satisfies IDiscussionBoardArticle.ICreate,
    },
  );
  typia.assert(article);
  // Test file deletion with a non-existent file ID
  // This tests the deletion endpoint structure and error handling
  await TestValidator.error(
    "delete non-existent file should handle gracefully",
    async () => {
      await api.functional.discussionBoard.admin.articles.files.erase(
        adminConnection,
        {
          articleId: article.id,
          fileId: typia.random<string & tags.Format<"uuid">>(),
        },
      );
    },
  );
  // Validate article remains intact after deletion attempt
  TestValidator.predicate(
    "article should remain valid after file deletion attempt",
    article.id !== undefined && article.title !== undefined,
  );
}
