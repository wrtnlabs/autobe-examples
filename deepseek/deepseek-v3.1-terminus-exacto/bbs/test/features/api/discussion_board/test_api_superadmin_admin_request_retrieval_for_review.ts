export async function test_api_superadmin_admin_request_retrieval_for_review(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create super administrator account
  const superAdminConnection: api.IConnection = { host: connection.host };
  const superAdmin = await authorize_super_admin_join(superAdminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IDiscussionBoardSuperAdmin.IJoin,
  });
  typia.assert(superAdmin);
  // 2. Create regular member account
  const memberConnection: api.IConnection = { host: connection.host };
  const member = await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      bio: RandomGenerator.paragraph({ sentences: 2 }),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IDiscussionBoardMember.IJoin,
  });
  typia.assert(member);
  // 3. Member submits administrator request using utility function
  const adminRequest =
    await generate_random_discussion_board_member_admin_requests_create(
      memberConnection,
      {
        body: {
          reason: RandomGenerator.paragraph({ sentences: 3 }),
        } satisfies IDiscussionBoardAdminRequest.ICreate,
      },
    );
  typia.assert(adminRequest);
  // 4. Super admin retrieves the specific request for review
  const retrievedRequest =
    await api.functional.discussionBoard.superAdmin.admin_requests.at(
      superAdminConnection,
      {
        requestId: adminRequest.id,
      },
    );
  typia.assert(retrievedRequest);
  // 5. Validate the retrieved request matches expectations
  TestValidator.equals(
    "request ID matches",
    retrievedRequest.id,
    adminRequest.id,
  );
  TestValidator.equals(
    "status should be pending",
    retrievedRequest.status,
    "pending",
  );
  TestValidator.equals(
    "reason text matches",
    retrievedRequest.reason,
    adminRequest.reason,
  );
  TestValidator.equals(
    "member ID matches",
    retrievedRequest.member.id,
    member.id,
  );
  TestValidator.equals(
    "member display name matches",
    retrievedRequest.member.display_name,
    member.display_name,
  );
  TestValidator.equals(
    "member bio matches",
    retrievedRequest.member.bio,
    member.bio,
  );
  TestValidator.predicate(
    "created_at timestamp exists",
    retrievedRequest.created_at.length > 0,
  );
  TestValidator.predicate(
    "updated_at timestamp exists",
    retrievedRequest.updated_at.length > 0,
  );
}
