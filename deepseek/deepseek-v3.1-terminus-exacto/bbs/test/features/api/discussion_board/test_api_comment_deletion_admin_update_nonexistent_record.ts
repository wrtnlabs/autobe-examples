/**
 * Test the error response when attempting to update a deletion record that does not exist.
 * Authenticate as an admin user, create an article and comment, but do not delete the comment.
 * Attempt to update a non-existent deletion record and validate that the system returns
 * an appropriate error indicating the deletion record cannot be found.
 */
export async function test_api_comment_deletion_admin_update_nonexistent_record(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin registration and authentication
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IDiscussionBoardAdmin.IJoin,
  });
  // 2. Member registration and authentication
  const memberConnection: api.IConnection = { host: connection.host };
  const member = await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      bio: RandomGenerator.paragraph({ sentences: 2 }),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IDiscussionBoardMember.IJoin,
  });
  // 3. Create article as member
  const article = await generate_random_discussion_board_member_articles_create(
    memberConnection,
    {
      body: {
        title: RandomGenerator.paragraph({ sentences: 1 }),
        body: RandomGenerator.content({ paragraphs: 2 }),
        discussion_board_section_id: typia.random<
          string & tags.Format<"uuid">
        >(),
      } satisfies IDiscussionBoardArticle.ICreate,
    },
  );
  typia.assert(article);
  // 4. Add comment to article as member
  const comment =
    await generate_random_discussion_board_member_articles_comments_create(
      memberConnection,
      {
        body: {
          content: RandomGenerator.paragraph({ sentences: 3 }),
        } satisfies IDiscussionBoardComment.ICreate,
        params: {
          articleId: article.id,
        },
      },
    );
  typia.assert(comment);
  // 5. Attempt to update non-existent deletion record as admin
  await TestValidator.httpError(
    "should return 404 error when updating non-existent deletion record",
    404,
    async () => {
      await api.functional.discussionBoard.admin.articles.comments.deletions.update(
        adminConnection,
        {
          articleId: article.id,
          commentId: comment.id,
          body: {
            reason: RandomGenerator.paragraph({ sentences: 1 }),
          } satisfies IDiscussionBoardCommentDeletion.IUpdate,
        },
      );
    },
  );
}
