import { authorize_super_admin_join } from "../../../authorize/authorize_super_admin_join";
import { authorize_super_admin_login } from "../../../authorize/authorize_super_admin_login";
import { authorize_super_admin_refresh } from "../../../authorize/authorize_super_admin_refresh";
import { generate_random_discussion_board_super_admin_sections_create } from "../../../generate/generate_random_discussion_board_super_admin_sections_create";
import { prepare_random_discussion_board_section } from "../../../prepare/prepare_random_discussion_board_section";

export async function test_api_section_deletion_empty_section(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create super administrator account
  const superAdminConnection: api.IConnection = { host: connection.host };
  const superAdmin = await authorize_super_admin_join(superAdminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      privilege_level: "super_admin",
    } satisfies IDiscussionBoardSuperAdmin.IJoin,
  });
  typia.assert(superAdmin);
  // 2. Create an empty section for deletion testing
  const section =
    await generate_random_discussion_board_super_admin_sections_create(
      superAdminConnection,
      {
        body: {
          name: RandomGenerator.paragraph({ sentences: 2 }),
          description: RandomGenerator.paragraph({ sentences: 3 }),
          display_order: typia.random<
            number & tags.Type<"int32"> & tags.Minimum<1>
          >(),
        } satisfies IDiscussionBoardSection.ICreate,
      },
    );
  typia.assert(section);
  // 3. Perform deletion operation
  const deletedSection =
    await api.functional.discussionBoard.superAdmin.sections.erase(
      superAdminConnection,
      {
        sectionId: section.id,
      },
    );
  typia.assert(deletedSection);
  // 4. Validate deletion response
  TestValidator.equals(
    "deleted section ID matches original",
    deletedSection.id,
    section.id,
  );
  TestValidator.equals(
    "deleted section name matches original",
    deletedSection.name,
    section.name,
  );
  // 5. Verify section is permanently removed by attempting to access it
  await TestValidator.error(
    "accessing deleted section should fail",
    async () => {
      await api.functional.discussionBoard.superAdmin.sections.erase(
        superAdminConnection,
        {
          sectionId: section.id,
        },
      );
    },
  );
}
