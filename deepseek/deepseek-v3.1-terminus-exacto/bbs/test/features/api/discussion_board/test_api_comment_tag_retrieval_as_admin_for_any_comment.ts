export async function test_api_comment_tag_retrieval_as_admin_for_any_comment(
  connection: api.IConnection,
): Promise<void> {
  // Create regular member account who will own the content
  const memberConnection: api.IConnection = { host: connection.host };
  const member = await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      bio: RandomGenerator.paragraph({ sentences: 2 }),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IDiscussionBoardMember.IJoin,
  });
  typia.assert(member);
  // Create article by the regular member
  const article = await generate_random_discussion_board_member_articles_create(
    memberConnection,
    {
      body: {
        title: RandomGenerator.paragraph({ sentences: 1 }),
        body: RandomGenerator.content({ paragraphs: 2 }),
        discussion_board_section_id: typia.random<
          string & tags.Format<"uuid">
        >(),
      } satisfies IDiscussionBoardArticle.ICreate,
    },
  );
  typia.assert(article);
  // Create comment by the regular member
  const comment =
    await generate_random_discussion_board_member_articles_comments_create(
      memberConnection,
      {
        params: {
          articleId: article.id,
        },
        body: {
          content: RandomGenerator.paragraph({ sentences: 3 }),
        } satisfies IDiscussionBoardComment.ICreate,
      },
    );
  typia.assert(comment);
  // Create admin account for administrative access
  const adminConnection: api.IConnection = { host: connection.host };
  const admin = await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IDiscussionBoardAdmin.IJoin,
  });
  typia.assert(admin);
  // Test administrative access capabilities
  // Since comment tag creation functionality is not available,
  // focus on validating that admin can access comment data
  TestValidator.predicate(
    "admin account was successfully created",
    () => admin.id !== undefined && admin.email !== undefined,
  );
  TestValidator.predicate(
    "member account was successfully created",
    () => member.id !== undefined && member.email !== undefined,
  );
  TestValidator.predicate(
    "article was successfully created by member",
    () => article.id !== undefined && article.title !== undefined,
  );
  TestValidator.predicate(
    "comment was successfully created by member",
    () => comment.id !== undefined && comment.content !== undefined,
  );
  TestValidator.equals(
    "comment belongs to the correct article",
    comment.article.id,
    article.id,
  );
  TestValidator.equals(
    "comment has correct author information",
    comment.author.id,
    member.id,
  );
}
