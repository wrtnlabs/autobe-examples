export async function test_api_super_admin_system_overview_empty_tables(
  connection: api.IConnection,
): Promise<void> {
  // Create super admin connection
  const superAdminConnection: api.IConnection = { host: connection.host };
  await authorize_super_admin_join(superAdminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IDiscussionBoardSuperAdmin.IJoin,
  });
  // Test system overview with empty tables
  const overview =
    await api.functional.discussionBoard.superAdmin.system.overview.at(
      superAdminConnection,
    );
  typia.assert(overview);
  // The system overview endpoint returns a system configuration entity
  // This represents the platform configuration rather than statistical counts
  // The test validates that the endpoint works correctly with minimal data
  TestValidator.predicate(
    "system overview returns valid configuration",
    overview.config_key.length > 0 && overview.description.length > 0,
  );
  TestValidator.predicate(
    "configuration has valid data type",
    ["string", "integer", "boolean", "number", "json"].includes(
      overview.data_type,
    ),
  );
}
