export async function test_api_admin_request_decision_deletion_nonexistent(
  connection: api.IConnection,
): Promise<void> {
  // Create super administrator connection
  const superAdminConnection: api.IConnection = { host: connection.host };
  await authorize_super_admin_join(superAdminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IDiscussionBoardSuperAdmin.IJoin,
  });
  // Generate a random UUID that doesn't exist in the system
  const nonExistentDecisionId = typia.random<string & tags.Format<"uuid">>();
  // Attempt to delete non-existent decision and validate 404 error
  await TestValidator.httpError(
    "delete non-existent decision",
    404,
    async () => {
      await api.functional.discussionBoard.superAdmin.admin_request_decisions.erase(
        superAdminConnection,
        {
          decisionId: nonExistentDecisionId,
        },
      );
    },
  );
}
