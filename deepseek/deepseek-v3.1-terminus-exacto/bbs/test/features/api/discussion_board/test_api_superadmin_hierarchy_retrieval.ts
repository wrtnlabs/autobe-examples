export async function test_api_superadmin_hierarchy_retrieval(
  connection: api.IConnection,
): Promise<void> {
  // Create super administrator connection
  const superAdminConnection: api.IConnection = { host: connection.host };
  await authorize_super_admin_join(superAdminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IDiscussionBoardSuperAdmin.IJoin,
  });
  // Retrieve administrator hierarchy
  const hierarchy =
    await api.functional.discussionBoard.superAdmin.hierarchy.at(
      superAdminConnection,
    );
  typia.assert(hierarchy);
  // Validate business logic: pagination consistency
  TestValidator.predicate(
    "pagination records match data length",
    hierarchy.pagination.records === hierarchy.data.length,
  );
  TestValidator.predicate(
    "pages calculation is correct",
    hierarchy.pagination.pages ===
      Math.ceil(hierarchy.pagination.records / hierarchy.pagination.limit),
  );
}
