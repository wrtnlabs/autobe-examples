export async function test_api_article_draft_deletion_nonexistent(
  connection: api.IConnection,
): Promise<void> {
  // Create authenticated user connection
  const userConnection: api.IConnection = { host: connection.host };
  await authorize_user_join(userConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      bio: RandomGenerator.paragraph({ sentences: 2 }),
    } satisfies IDiscussionBoardUser.IJoin,
  });
  // Generate random UUID that doesn't exist
  const nonExistentDraftId = typia.random<string & tags.Format<"uuid">>();
  // Attempt to delete non-existent draft
  await TestValidator.error("delete non-existent draft", async () => {
    await api.functional.discussionBoard.user.article_drafts.erase(
      userConnection,
      {
        draftId: nonExistentDraftId,
      },
    );
  });
}
