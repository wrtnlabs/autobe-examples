import { authorize_member_refresh } from "../../../authorize/authorize_member_refresh";

export async function test_api_sections_browsing_member_registered(
  connection: api.IConnection,
): Promise<void> {
  // Register a new member using utility function
  const memberConnection: api.IConnection = { host: connection.host };
  const authorizedMember = await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      bio: RandomGenerator.paragraph({ sentences: 2 }),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IDiscussionBoardMember.IJoin,
  });
  typia.assert(authorizedMember);
  // Browse sections using the authenticated member connection
  const sections =
    await api.functional.discussionBoard.member.sections.at(memberConnection);
  typia.assert(sections);
  // Validate that we received a valid section object with expected properties
  TestValidator.predicate(
    "section should have required properties",
    sections.id !== undefined &&
      sections.name !== undefined &&
      sections.created_at !== undefined,
  );
}
