export async function test_api_admin_dashboard_comprehensive_statistics(
  connection: api.IConnection,
): Promise<void> {
  // Create administrator connection
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IDiscussionBoardAdmin.IJoin,
  });
  // Retrieve dashboard statistics
  const dashboard =
    await api.functional.discussionBoard.admin.administrators.dashboard.index(
      adminConnection,
      {
        body: {} satisfies IDiscussionBoardAdministratorPromotionApproval.IRequest,
      },
    );
  typia.assert(dashboard);
  // Validate that the dashboard returns a valid response structure
  // The typia.assert() call above already validates all type constraints
  // We only need to ensure the basic response structure is present
  TestValidator.predicate(
    "dashboard response has pagination",
    dashboard.pagination !== undefined,
  );
  TestValidator.predicate(
    "dashboard response has data array",
    Array.isArray(dashboard.data),
  );
}
