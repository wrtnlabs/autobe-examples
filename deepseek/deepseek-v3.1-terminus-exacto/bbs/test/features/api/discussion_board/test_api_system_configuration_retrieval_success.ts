import { authorize_admin_join } from "../../../authorize/authorize_admin_join";
import { authorize_admin_login } from "../../../authorize/authorize_admin_login";
import { authorize_admin_refresh } from "../../../authorize/authorize_admin_refresh";

export async function test_api_system_configuration_retrieval_success(
  connection: api.IConnection,
): Promise<void> {
  // Create administrator connection
  const adminConnection: api.IConnection = { host: connection.host };
  // Register and authenticate as administrator
  const admin = await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IDiscussionBoardAdmin.IJoin,
  });
  typia.assert(admin);
  // Retrieve system configuration
  const configurationId = typia.random<string & tags.Format<"uuid">>();
  const configuration =
    await api.functional.discussionBoard.admin.system_configurations.at(
      adminConnection,
      {
        configurationId,
      },
    );
  typia.assert(configuration);
  // Validate configuration ID matches the requested ID
  TestValidator.equals(
    "configuration ID matches",
    configuration.id,
    configurationId,
  );
}
