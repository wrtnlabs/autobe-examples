export async function test_api_comment_creation_on_deleted_article(
  connection: api.IConnection,
): Promise<void> {
  // Since article creation endpoint is not available in the provided API functions,
  // we cannot properly simulate creating an article and then deleting it.
  // However, we can test that the comment creation endpoint properly validates
  // article existence and returns an appropriate error for non-existent articles.
  // 1. Member setup - create and authenticate comment author
  const memberConnection: api.IConnection = { host: connection.host };
  await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      bio: RandomGenerator.paragraph({ sentences: 2 }),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IDiscussionBoardMember.IJoin,
  });
  // 2. Use a random UUID to simulate a deleted/non-existent article
  // This tests that the comment creation endpoint properly validates article existence
  const deletedArticleId = typia.random<string & tags.Format<"uuid">>();
  // 3. Attempt to create comment on non-existent/deleted article
  await TestValidator.error(
    "comment creation should fail on non-existent article",
    async () => {
      await api.functional.discussionBoard.member.articles.comments.create(
        memberConnection,
        {
          articleId: deletedArticleId,
          body: {
            content: RandomGenerator.paragraph({ sentences: 3 }),
          } satisfies IDiscussionBoardComment.ICreate,
        },
      );
    },
  );
}
