/**
 * Test the super admin dashboard retrieval functionality.
 * Validate that the dashboard endpoint returns paginated statistics data
 * with proper structure and formatting.
 */
export async function test_api_superadmin_dashboard_section_filter(
  connection: api.IConnection,
): Promise<void> {
  // Create super admin connection
  const superAdminConnection: api.IConnection = { host: connection.host };
  await authorize_super_admin_join(superAdminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      privilege_level: "super_admin",
    } satisfies IDiscussionBoardSuperAdmin.IJoin,
  });
  // Call dashboard endpoint with empty request body (as per current DTO definition)
  const dashboardResponse =
    await api.functional.discussionBoard.superAdmin.administrators.dashboard.index(
      superAdminConnection,
      {
        body: {} satisfies IDiscussionBoardAdministratorPromotionApproval.IRequest,
      },
    );
  // Validate response structure - typia.assert performs complete validation
  typia.assert(dashboardResponse);
}
