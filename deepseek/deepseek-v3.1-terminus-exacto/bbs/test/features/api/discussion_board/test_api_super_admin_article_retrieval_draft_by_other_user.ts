/**
 * Test that super administrators can retrieve draft articles created by other users,
 * overriding normal draft visibility restrictions.
 */
export async function test_api_super_admin_article_retrieval_draft_by_other_user(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create and authenticate regular user (article author)
  const userConnection: api.IConnection = { host: connection.host };
  const userAuth = await authorize_user_join(userConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
    } satisfies IDiscussionBoardUser.IJoin,
  });
  typia.assert(userAuth);
  // 2. Create and authenticate admin for section creation
  const adminConnection: api.IConnection = { host: connection.host };
  const adminAuth = await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      href: "http://localhost:3000",
      referrer: "http://localhost:3000",
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IDiscussionBoardAdmin.IJoin,
  });
  typia.assert(adminAuth);
  // 3. Create a section for the article
  const section = await generate_random_discussion_board_admin_sections_create(
    adminConnection,
    {
      body: {
        name: RandomGenerator.paragraph({ sentences: 2 }),
        description: RandomGenerator.paragraph({ sentences: 3 }),
        status: "active",
        display_order: typia.random<
          number & tags.Type<"int32"> & tags.Minimum<1> & tags.Maximum<100>
        >(),
      } satisfies IDiscussionBoardSection.ICreate,
    },
  );
  typia.assert(section);
  // 4. Create draft article by regular user
  const article = await generate_random_discussion_board_user_articles_create(
    userConnection,
    {
      body: {
        title: RandomGenerator.paragraph({ sentences: 2 }) satisfies string &
          tags.MinLength<5> &
          tags.MaxLength<200>,
        content: RandomGenerator.paragraph({ sentences: 5 }) satisfies string &
          tags.MinLength<50>,
        discussion_board_section_id: section.id,
      } satisfies IDiscussionBoardArticle.ICreate,
    },
  );
  typia.assert(article);
  // 5. Create and authenticate super admin
  const superAdminConnection: api.IConnection = { host: connection.host };
  const superAdminAuth = await authorize_super_admin_join(
    superAdminConnection,
    {
      body: {
        email: typia.random<string & tags.Format<"email">>(),
        password: RandomGenerator.alphaNumeric(16),
        href: "http://localhost:3000",
        referrer: "http://localhost:3000",
        ip: typia.random<string & tags.Format<"ipv4">>(),
      } satisfies IDiscussionBoardSuperAdmin.IJoin,
    },
  );
  typia.assert(superAdminAuth);
  // 6. Super admin retrieves the draft article created by regular user
  // Note: No utility function exists for this endpoint, using SDK directly
  const retrievedArticle =
    await api.functional.discussionBoard.superAdmin.articles.at(
      superAdminConnection,
      {
        articleId: article.id,
      },
    );
  typia.assert(retrievedArticle);
  // 7. Validate that super admin can view the draft article
  TestValidator.equals("article ID matches", retrievedArticle.id, article.id);
  TestValidator.equals(
    "article title matches",
    retrievedArticle.title,
    article.title,
  );
  TestValidator.equals(
    "article content matches",
    retrievedArticle.content,
    article.content,
  );
  TestValidator.equals(
    "article author ID matches",
    retrievedArticle.author.id,
    userAuth.id,
  );
  TestValidator.equals(
    "article section ID matches",
    retrievedArticle.section.id,
    section.id,
  );
  TestValidator.predicate(
    "article has valid creation timestamp",
    retrievedArticle.created_at.length > 0,
  );
  TestValidator.predicate(
    "article has status field",
    retrievedArticle.status.length > 0,
  );
}
