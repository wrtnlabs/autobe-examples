/**
 * Test the basic platform statistics retrieval for a newly registered user.
 *
 * This test verifies that after user registration, the statistics endpoint
 * returns valid platform metrics with all required fields populated.
 * The test ensures the response structure matches the expected schema
 * and contains reasonable values for a newly initialized platform.
 */
export async function test_api_user_statistics_basic_platform_overview(
  connection: api.IConnection,
): Promise<void> {
  // Create user-specific connection and register new user
  const userConnection: api.IConnection = { host: connection.host };
  await authorize_user_join(userConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      bio: RandomGenerator.paragraph({ sentences: 2 }),
    } satisfies IDiscussionBoardUser.IJoin,
  });
  // Access the statistics endpoint with authenticated user
  const statistics =
    await api.functional.discussionBoard.user.statistics.at(userConnection);
  typia.assert(statistics);
}
