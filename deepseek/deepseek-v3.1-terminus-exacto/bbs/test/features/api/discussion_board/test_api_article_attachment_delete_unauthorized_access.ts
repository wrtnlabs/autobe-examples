export async function test_api_article_attachment_delete_unauthorized_access(
  connection: api.IConnection,
): Promise<void> {
  // Create Member A (article author)
  const memberAConnection: api.IConnection = { host: connection.host };
  const memberA = await authorize_member_join(memberAConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      bio: RandomGenerator.paragraph({ sentences: 2 }),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IDiscussionBoardMember.IJoin,
  });
  typia.assert(memberA);
  // Create Member B (unauthorized user)
  const memberBConnection: api.IConnection = { host: connection.host };
  const memberB = await authorize_member_join(memberBConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      bio: RandomGenerator.paragraph({ sentences: 2 }),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IDiscussionBoardMember.IJoin,
  });
  typia.assert(memberB);
  // Member A creates an article
  const article = await generate_random_discussion_board_member_articles_create(
    memberAConnection,
    {
      body: {
        title: RandomGenerator.paragraph({ sentences: 1 }),
        body: RandomGenerator.content({ paragraphs: 2 }),
        discussion_board_section_id: typia.random<
          string & tags.Format<"uuid">
        >(),
      } satisfies IDiscussionBoardArticle.ICreate,
    },
  );
  typia.assert(article);
  // Member A adds attachment to the article
  const attachment =
    await generate_random_discussion_board_member_articles_attachments_create(
      memberAConnection,
      {
        body: {
          filename: `${RandomGenerator.alphabets(8)}.txt`,
          filetype: "txt",
          mime_type: "text/plain",
          size_bytes: typia.random<
            number & tags.Type<"int32"> & tags.Minimum<1>
          >(),
        } satisfies IDiscussionBoardAttachment.ICreate,
        params: { articleId: article.id },
      },
    );
  typia.assert(attachment);
  // Member B attempts to delete Member A's attachment (should fail)
  await TestValidator.error("unauthorized attachment deletion", async () => {
    await api.functional.discussionBoard.member.articles.attachments.erase(
      memberBConnection,
      {
        articleId: article.id,
        attachmentId: attachment.id,
      },
    );
  });
  // Verify attachment still exists by attempting to create another attachment with same filename
  // This validates the attachment record wasn't deleted and the article still accepts attachments
  const validationAttachment =
    await generate_random_discussion_board_member_articles_attachments_create(
      memberAConnection,
      {
        body: {
          filename: `${RandomGenerator.alphabets(8)}.pdf`,
          filetype: "pdf",
          mime_type: "application/pdf",
          size_bytes: typia.random<
            number & tags.Type<"int32"> & tags.Minimum<1>
          >(),
        } satisfies IDiscussionBoardAttachment.ICreate,
        params: { articleId: article.id },
      },
    );
  typia.assert(validationAttachment);
}
