export async function test_api_attachment_deletion_by_admin_from_owned_article(
  connection: api.IConnection,
): Promise<void> {
  // First, we need to create a valid section for the article
  // Since section creation is admin-only, we'll create an admin account first
  const adminConnection: api.IConnection = { host: connection.host };
  const adminAuth = await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IDiscussionBoardAdmin.IJoin,
  });
  typia.assert(adminAuth);
  // Create a member account
  const memberConnection: api.IConnection = { host: connection.host };
  const memberAuth = await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      bio: RandomGenerator.paragraph({ sentences: 2 }),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IDiscussionBoardMember.IJoin,
  });
  typia.assert(memberAuth);
  // For the section ID, we need to use a valid UUID that exists in the system
  // Since we don't have section creation endpoints available, we'll use a random UUID
  // and hope it exists, or the test will need to be adjusted based on available sections
  const sectionId = typia.random<string & tags.Format<"uuid">>();
  // Create article as member
  const article = await generate_random_discussion_board_member_articles_create(
    memberConnection,
    {
      body: {
        title: RandomGenerator.paragraph({ sentences: 1 }),
        body: RandomGenerator.content({ paragraphs: 2 }),
        discussion_board_section_id: sectionId,
      } satisfies IDiscussionBoardArticle.ICreate,
    },
  );
  typia.assert(article);
  // Create attachment on the article as administrator
  const attachment =
    await generate_random_discussion_board_admin_articles_attachments_create(
      adminConnection,
      {
        body: {
          filename: `${RandomGenerator.alphabets(8)}.txt`,
          filetype: "txt",
          mime_type: "text/plain",
          size_bytes: typia.random<
            number & tags.Type<"int32"> & tags.Minimum<1>
          >(),
        } satisfies IDiscussionBoardAttachment.ICreate,
        params: {
          articleId: article.id,
        },
      },
    );
  typia.assert(attachment);
  // Delete the attachment as administrator
  await api.functional.discussionBoard.admin.articles.attachments.erase(
    adminConnection,
    {
      articleId: article.id,
      attachmentId: attachment.id,
    },
  );
  // The erase endpoint returns void on success, indicating successful deletion
  // If any error occurs during deletion, it will throw an exception
}
