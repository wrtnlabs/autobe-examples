export async function test_api_administrator_promotion_self_promotion_prevention(
  connection: api.IConnection,
): Promise<void> {
  // Create super administrator connection
  const superAdminConnection: api.IConnection = { host: connection.host };
  // Register and authenticate as super administrator using the utility function
  const superAdmin = await authorize_super_admin_join(superAdminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IDiscussionBoardSuperAdmin.IJoin,
  });
  typia.assert(superAdmin);
  // Attempt to promote self (should fail)
  await TestValidator.error(
    "super administrator cannot promote themselves",
    async () => {
      await api.functional.discussionBoard.superAdmin.administrators.promote(
        superAdminConnection,
        {
          administratorId: superAdmin.id,
        },
      );
    },
  );
}
