export async function test_api_super_admin_sections_filter_deleted(
  connection: api.IConnection,
): Promise<void> {
  // Create super admin connection
  const superAdminConnection: api.IConnection = { host: connection.host };
  await authorize_super_admin_join(superAdminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IDiscussionBoardSuperAdmin.IJoin,
  });
  // Test the sections endpoint
  const sections =
    await api.functional.discussionBoard.superAdmin.sections.at(
      superAdminConnection,
    );
  typia.assert(sections);
  // Validate basic response structure
  TestValidator.predicate(
    "section should have required properties",
    sections.id !== undefined &&
      sections.name !== undefined &&
      sections.created_at !== undefined,
  );
  // Note: The scenario requires testing soft-delete filtering, but section creation/deletion
  // functionality is not available via the provided APIs. This test validates that the
  // endpoint returns valid data structure as per the current available capabilities.
}
