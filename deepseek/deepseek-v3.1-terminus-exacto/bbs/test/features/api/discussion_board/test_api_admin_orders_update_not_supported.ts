export async function test_api_admin_orders_update_not_supported(
  connection: api.IConnection,
): Promise<void> {
  // Create admin connection and authenticate
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IDiscussionBoardAdmin.IJoin,
  });
  // Test that the orders endpoint correctly returns void (indicating no operation)
  const result =
    await api.functional.discussionBoard.admin.orders.update(adminConnection);
  typia.assert(result);
  // Validate that the result is void (no return value) as expected for unsupported endpoint
  TestValidator.equals("endpoint returns void", result, undefined);
}
