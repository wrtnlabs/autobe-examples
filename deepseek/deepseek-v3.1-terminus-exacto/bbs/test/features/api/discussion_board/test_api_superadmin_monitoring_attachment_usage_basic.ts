export async function test_api_superadmin_monitoring_attachment_usage_basic(
  connection: api.IConnection,
): Promise<void> {
  // Create super administrator connection
  const superAdminConnection: api.IConnection = { host: connection.host };
  await authorize_super_admin_join(superAdminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IDiscussionBoardSuperAdmin.IJoin,
  });
  // Retrieve attachment usage statistics
  const usageStats =
    await api.functional.discussionBoard.superAdmin.monitoring.attachment_usage.at(
      superAdminConnection,
    );
  typia.assert(usageStats);
  // Validate that the response contains essential governance data
  TestValidator.predicate(
    "response contains valid attachment reference",
    usageStats.attachment.id !== undefined &&
      usageStats.attachment.filename !== undefined,
  );
  TestValidator.predicate(
    "response contains download context information",
    usageStats.actor_type !== undefined && usageStats.ip !== undefined,
  );
}
