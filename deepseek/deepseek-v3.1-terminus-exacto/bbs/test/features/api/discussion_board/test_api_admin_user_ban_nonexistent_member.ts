export async function test_api_admin_user_ban_nonexistent_member(
  connection: api.IConnection,
): Promise<void> {
  // Create admin connection
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IDiscussionBoardAdmin.IJoin,
  });
  // Generate a random UUID that doesn't correspond to any existing member
  const nonExistentMemberId = typia.random<string & tags.Format<"uuid">>();
  // Attempt to ban non-existent member and expect error
  await TestValidator.error("ban non-existent member should fail", async () => {
    await generate_random_discussion_board_admin_user_bans_create(
      adminConnection,
      {
        body: {
          member_id: nonExistentMemberId,
          reason: RandomGenerator.paragraph({ sentences: 2 }),
          expires_at: null,
        } satisfies IDiscussionBoardUserBan.ICreate,
      },
    );
  });
}
