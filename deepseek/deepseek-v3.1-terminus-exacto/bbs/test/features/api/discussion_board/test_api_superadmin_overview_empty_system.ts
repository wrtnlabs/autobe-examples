export async function test_api_superadmin_overview_empty_system(
  connection: api.IConnection,
): Promise<void> {
  // Create super admin connection
  const superAdminConnection: api.IConnection = { host: connection.host };
  // Authenticate as super admin using join (since system is empty)
  const authorized = await authorize_super_admin_join(superAdminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IDiscussionBoardSuperAdmin.IJoin,
  });
  typia.assert(authorized);
  // Call the overview endpoint
  const overview =
    await api.functional.discussionBoard.superAdmin.overview.at(
      superAdminConnection,
    );
  typia.assert(overview);
  // The typia.assert() above performs complete validation of all properties
  // including type checks, format validations, and constraint validations
  // No additional validation is needed or allowed after typia.assert()
}
