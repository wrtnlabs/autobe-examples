export async function test_api_section_deletion_success(
  connection: api.IConnection,
): Promise<void> {
  // Create super admin connection and authenticate
  const superAdminConnection: api.IConnection = { host: connection.host };
  const superAdmin = await authorize_super_admin_join(superAdminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IDiscussionBoardSuperAdmin.IJoin,
  });
  typia.assert(superAdmin);
  // Create a new section to be deleted
  const section =
    await generate_random_discussion_board_super_admin_sections_create(
      superAdminConnection,
      {
        body: {
          name: RandomGenerator.paragraph({ sentences: 2 }),
          description: RandomGenerator.paragraph({ sentences: 3 }),
        } satisfies IDiscussionBoardSection.ICreate,
      },
    );
  typia.assert(section);
  // Delete the section - this should succeed without throwing an error
  await api.functional.discussionBoard.superAdmin.sections.erase(
    superAdminConnection,
    {
      sectionId: section.id,
    },
  );
  // The deletion API call itself validates success - if it returns without error, deletion was successful
  // For soft deletion scenarios, we rely on the API to properly handle the deletion logic
}
