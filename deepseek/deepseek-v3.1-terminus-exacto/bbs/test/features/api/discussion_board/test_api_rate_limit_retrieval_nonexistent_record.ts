export async function test_api_rate_limit_retrieval_nonexistent_record(
  connection: api.IConnection,
): Promise<void> {
  // Create administrator connection and authenticate
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IDiscussionBoardAdmin.IJoin,
  });
  // Generate a random UUID that does not correspond to any existing rate limit record
  const nonExistentRateLimitId = typia.random<string & tags.Format<"uuid">>();
  // Attempt to retrieve the non-existent rate limit record
  await TestValidator.error(
    "should return 404 for non-existent rate limit ID",
    async () => {
      await api.functional.discussionBoard.admin.comment_rate_limits.at(
        adminConnection,
        {
          rateLimitId: nonExistentRateLimitId,
        },
      );
    },
  );
}
