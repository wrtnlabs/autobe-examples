export async function test_api_section_image_deletion_nonexistent_image(
  connection: api.IConnection,
): Promise<void> {
  // Create super admin connection and authenticate
  const superAdminConnection: api.IConnection = { host: connection.host };
  const authResult = await authorize_super_admin_join(superAdminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      privilege_level: "super_admin",
    } satisfies IDiscussionBoardSuperAdmin.IJoin,
  });
  typia.assert(authResult);
  // Create a valid section for testing
  const section =
    await generate_random_discussion_board_super_admin_sections_create(
      superAdminConnection,
      {
        body: {
          name: RandomGenerator.paragraph({ sentences: 2 }),
          description: RandomGenerator.paragraph({ sentences: 5 }),
          display_order: typia.random<
            number & tags.Type<"int32"> & tags.Minimum<1>
          >(),
        } satisfies IDiscussionBoardSection.ICreate,
      },
    );
  typia.assert(section);
  // Attempt to delete a non-existent image
  const nonExistentImageId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.error(
    "delete non-existent image should fail",
    async () => {
      await api.functional.discussionBoard.superAdmin.sections.images.erase(
        superAdminConnection,
        {
          sectionId: section.id,
          imageId: nonExistentImageId,
        },
      );
    },
  );
}
