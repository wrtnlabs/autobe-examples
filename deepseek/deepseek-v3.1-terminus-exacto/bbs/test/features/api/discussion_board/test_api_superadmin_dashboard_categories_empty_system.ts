import { authorize_super_admin_join } from "../../../authorize/authorize_super_admin_join";
import { authorize_super_admin_login } from "../../../authorize/authorize_super_admin_login";
import { authorize_super_admin_refresh } from "../../../authorize/authorize_super_admin_refresh";

export async function test_api_superadmin_dashboard_categories_empty_system(
  connection: api.IConnection,
): Promise<void> {
  // Create super administrator connection
  const superAdminConnection: api.IConnection = { host: connection.host };
  // Authenticate as super administrator
  await authorize_super_admin_join(superAdminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IDiscussionBoardSuperAdmin.IJoin,
  });
  // Retrieve dashboard categories (sections)
  const section =
    await api.functional.discussionBoard.superAdmin.dashboard.categories.at(
      superAdminConnection,
    );
  // Validate response structure
  typia.assert(section);
  // The endpoint returns a single section summary object
  // Even in an empty system, it should return a valid section structure
  // with appropriate null/default values
  TestValidator.predicate(
    "section should have valid structure even in empty system",
    () => typeof section.id === "string" && typeof section.name === "string",
  );
}
