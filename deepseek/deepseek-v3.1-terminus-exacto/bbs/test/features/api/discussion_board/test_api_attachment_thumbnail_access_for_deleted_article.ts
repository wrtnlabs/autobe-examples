export async function test_api_attachment_thumbnail_access_for_deleted_article(
  connection: api.IConnection,
): Promise<void> {
  // Create member-specific connection
  const memberConnection: api.IConnection = { host: connection.host };
  // 1. Create member account
  const member = await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      bio: RandomGenerator.paragraph({ sentences: 2 }),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IDiscussionBoardMember.IJoin,
  });
  typia.assert(member);
  // 2. Create article with a valid section ID
  const article = await generate_random_discussion_board_member_articles_create(
    memberConnection,
    {
      body: {
        title: RandomGenerator.paragraph({ sentences: 1 }),
        body: RandomGenerator.content({ paragraphs: 2 }),
        discussion_board_section_id: typia.random<
          string & tags.Format<"uuid">
        >(),
      } satisfies IDiscussionBoardArticle.ICreate,
    },
  );
  typia.assert(article);
  // 3. Add image attachment
  const attachment =
    await generate_random_discussion_board_member_articles_attachments_create(
      memberConnection,
      {
        params: { articleId: article.id },
        body: {
          filename: `image_${RandomGenerator.alphabets(8)}.jpg`,
          filetype: "jpg",
          mime_type: "image/jpeg",
          size_bytes: typia.random<
            number & tags.Type<"int32"> & tags.Minimum<1>
          >(),
        } satisfies IDiscussionBoardAttachment.ICreate,
      },
    );
  typia.assert(attachment);
  // 4. Delete the parent article
  await api.functional.discussionBoard.member.articles.erase(memberConnection, {
    body: {
      author_id: member.id,
      section_id: article.section.id,
    } satisfies IDiscussionBoardArticle.IDeleteRequest,
  });
  // 5. Attempt to retrieve thumbnail metadata (should fail)
  await TestValidator.error(
    "thumbnail access should fail for deleted article",
    async () => {
      // Use a valid thumbnail ID format
      const thumbnailId = typia.random<string & tags.Format<"uuid">>();
      await api.functional.discussionBoard.articles.attachments.thumbnails.at(
        memberConnection,
        {
          articleId: article.id,
          attachmentId: attachment.id,
          thumbnailId: thumbnailId,
        },
      );
    },
  );
}
