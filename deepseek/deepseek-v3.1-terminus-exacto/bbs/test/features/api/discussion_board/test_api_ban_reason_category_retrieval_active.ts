export async function test_api_ban_reason_category_retrieval_active(
  connection: api.IConnection,
): Promise<void> {
  // Create super admin connection
  const superAdminConnection: api.IConnection = { host: connection.host };
  // Authenticate as super admin using join operation
  const superAdmin = await authorize_super_admin_join(superAdminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      privilege_level: "super_admin",
    } satisfies IDiscussionBoardSuperAdmin.IJoin,
  });
  typia.assert(superAdmin);
  // Retrieve ban reason category
  const category =
    await api.functional.discussionBoard.superAdmin.ban_reason_categories.at(
      superAdminConnection,
      {
        categoryId: typia.random<string & tags.Format<"uuid">>(),
      },
    );
  typia.assert(category);
  // Validate business logic - category is active
  TestValidator.predicate("category is active", category.is_active === true);
}
