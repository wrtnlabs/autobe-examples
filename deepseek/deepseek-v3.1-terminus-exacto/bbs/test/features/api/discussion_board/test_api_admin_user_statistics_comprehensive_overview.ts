export async function test_api_admin_user_statistics_comprehensive_overview(
  connection: api.IConnection,
): Promise<void> {
  // Create administrator connection
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IDiscussionBoardAdmin.IJoin,
  });
  // Retrieve user statistics with default parameters
  const statistics =
    await api.functional.discussionBoard.admin.users.statistics.index(
      adminConnection,
      {
        body: {} satisfies IDiscussionBoardUser.IRequest,
      },
    );
  typia.assert(statistics);
  // Validate pagination structure
  TestValidator.equals(
    "pagination has current page",
    statistics.pagination.current,
    1,
  );
  TestValidator.predicate(
    "pagination has valid limit",
    statistics.pagination.limit > 0,
  );
  TestValidator.predicate(
    "pagination has non-negative records",
    statistics.pagination.records >= 0,
  );
  TestValidator.predicate(
    "pagination has non-negative pages",
    statistics.pagination.pages >= 0,
  );
}
