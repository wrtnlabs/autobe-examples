export async function test_api_section_deletion_empty_section_by_admin(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create admin account and authenticate
  const adminConnection: api.IConnection = { host: connection.host };
  const admin = await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IDiscussionBoardAdmin.IJoin,
  });
  typia.assert(admin);
  // 2. Create an empty section
  const section = await generate_random_discussion_board_admin_sections_create(
    adminConnection,
    {
      body: {
        name: RandomGenerator.paragraph({ sentences: 2 }),
        description: RandomGenerator.paragraph({ sentences: 3 }),
      } satisfies IDiscussionBoardSection.ICreate,
    },
  );
  typia.assert(section);
  // 3. Delete the empty section
  await api.functional.discussionBoard.admin.sections.erase(adminConnection, {
    sectionId: section.id,
  });
  // 4. Validate that the section deletion was successful
  // Since the erase function returns void on success, we can validate
  // by ensuring no error was thrown during the deletion operation
  TestValidator.predicate("section deletion should succeed", true);
  // 5. Verify that the section is soft-deleted by attempting to delete it again
  // This should fail since the section is already deleted
  await TestValidator.error(
    "deleting already deleted section should fail",
    async () => {
      await api.functional.discussionBoard.admin.sections.erase(
        adminConnection,
        {
          sectionId: section.id,
        },
      );
    },
  );
}
