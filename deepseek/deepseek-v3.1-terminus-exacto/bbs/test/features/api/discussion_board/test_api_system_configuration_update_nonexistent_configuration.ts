import { authorize_super_admin_refresh } from "../../../authorize/authorize_super_admin_refresh";

export async function test_api_system_configuration_update_nonexistent_configuration(
  connection: api.IConnection,
): Promise<void> {
  // Create super admin connection
  const superAdminConnection: api.IConnection = { host: connection.host };
  // Authenticate as super administrator
  await authorize_super_admin_join(superAdminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      privilege_level: "super_admin",
    } satisfies IDiscussionBoardSuperAdmin.IJoin,
  });
  // Attempt to update a non-existent configuration
  await TestValidator.httpError(
    "update non-existent configuration",
    404,
    async () => {
      await api.functional.discussionBoard.superAdmin.system_configurations.update(
        superAdminConnection,
        {
          configurationId: typia.random<string & tags.Format<"uuid">>(),
          body: {
            config_value: RandomGenerator.paragraph({ sentences: 2 }),
            description: RandomGenerator.paragraph({ sentences: 3 }),
            category: RandomGenerator.name(1),
            is_sensitive: typia.random<boolean>(),
          } satisfies IDiscussionBoardSystemConfiguration.IUpdate,
        },
      );
    },
  );
}
