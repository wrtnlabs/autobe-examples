export async function test_api_section_files_search_empty_results(
  connection: api.IConnection,
): Promise<void> {
  // Create admin connection and authenticate
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IDiscussionBoardAdmin.IJoin,
  });
  // Create a section
  const section = await generate_random_discussion_board_admin_sections_create(
    adminConnection,
    {
      body: {
        name: RandomGenerator.paragraph({ sentences: 2 }),
        description: RandomGenerator.content({ paragraphs: 1 }),
        display_order: typia.random<
          number & tags.Type<"int32"> & tags.Minimum<1>
        >(),
      } satisfies IDiscussionBoardSection.ICreate,
    },
  );
  typia.assert(section);
  // Search for files with criteria that should return no results
  const searchResponse =
    await api.functional.discussionBoard.admin.sections.files.index(
      adminConnection,
      {
        sectionId: section.id,
        body: {
          file_type: "application/non-existent-type",
          description: "This description definitely does not exist in any file",
        } satisfies IDiscussionBoardSectionFile.IRequest,
      },
    );
  typia.assert(searchResponse);
  // Validate empty results with proper pagination expectations
  TestValidator.equals(
    "data array should be empty",
    searchResponse.data.length,
    0,
  );
  TestValidator.equals(
    "total records should be 0",
    searchResponse.pagination.records,
    0,
  );
  TestValidator.predicate(
    "pagination should have valid structure",
    searchResponse.pagination.current >= 0 &&
      searchResponse.pagination.limit >= 0,
  );
}
