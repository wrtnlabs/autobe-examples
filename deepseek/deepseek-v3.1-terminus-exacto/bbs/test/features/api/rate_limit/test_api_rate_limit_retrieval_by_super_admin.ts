export async function test_api_rate_limit_retrieval_by_super_admin(
  connection: api.IConnection,
): Promise<void> {
  // Create super admin connection
  const superAdminConnection: api.IConnection = { host: connection.host };
  await authorize_super_admin_join(superAdminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      privilege_level: "super_admin",
    } satisfies IDiscussionBoardSuperAdmin.IJoin,
  });
  // Retrieve rate limit configuration
  const rateLimitId = typia.random<string & tags.Format<"uuid">>();
  const rateLimit =
    await api.functional.discussionBoard.superAdmin.api_rate_limits.at(
      superAdminConnection,
      { rateLimitId },
    );
  // Validate response structure - typia.assert performs complete validation
  typia.assert(rateLimit);
  // Validate business logic - the rate limit ID should match the requested ID
  TestValidator.equals("rate limit id matches", rateLimit.id, rateLimitId);
}
