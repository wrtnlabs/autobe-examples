export async function test_api_error_log_admin_retrieval_success(
  connection: api.IConnection,
): Promise<void> {
  // Create admin connection
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IDiscussionBoardAdmin.IJoin,
  });
  // Generate random UUID for error log ID
  const errorLogId = typia.random<string & tags.Format<"uuid">>();
  // Retrieve error log details
  const errorLog = await api.functional.discussionBoard.admin.error_logs.at(
    adminConnection,
    { errorLogId },
  );
  // Validate response structure - typia.assert performs complete validation
  typia.assert(errorLog);
  // Validate ID matches the requested error log
  TestValidator.equals("error log ID matches", errorLog.id, errorLogId);
}
