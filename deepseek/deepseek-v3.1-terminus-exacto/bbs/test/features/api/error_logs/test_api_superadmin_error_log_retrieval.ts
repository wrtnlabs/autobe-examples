export async function test_api_superadmin_error_log_retrieval(
  connection: api.IConnection,
): Promise<void> {
  // Create super admin connection
  const superAdminConnection: api.IConnection = { host: connection.host };
  // Authenticate as super administrator
  await authorize_super_admin_join(superAdminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IDiscussionBoardSuperAdmin.IJoin,
  });
  // Since we cannot create error logs via API, we'll test the retrieval endpoint
  // with a valid UUID format. The API should either return a valid error log
  // or handle the non-existent case appropriately
  const errorLogId = typia.random<string & tags.Format<"uuid">>();
  const errorLog =
    await api.functional.discussionBoard.superAdmin.error_logs.at(
      superAdminConnection,
      { errorLogId },
    );
  // Validate the response structure - typia.assert will validate all fields
  typia.assert(errorLog);
}
