export async function test_api_article_view_statistics_no_view_data(
  connection: api.IConnection,
): Promise<void> {
  // Create admin account and authenticate
  const adminConnection: api.IConnection = { host: connection.host };
  const admin = await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IDiscussionBoardAdmin.IJoin,
  });
  typia.assert(admin);
  // Create article using admin connection
  const article = await generate_random_discussion_board_admin_articles_create(
    adminConnection,
    {
      body: {
        title: RandomGenerator.paragraph({ sentences: 2 }),
        content: RandomGenerator.content({ paragraphs: 3 }),
        discussion_board_section_id: typia.random<
          string & tags.Format<"uuid">
        >(),
      } satisfies IDiscussionBoardArticle.ICreate,
    },
  );
  typia.assert(article);
  // Retrieve view statistics immediately (no views recorded yet)
  const stats =
    await api.functional.discussionBoard.admin.articles.view_stats.at(
      adminConnection,
      {
        articleId: article.id,
      },
    );
  typia.assert(stats);
  // Validate empty statistics
  TestValidator.equals(
    "total_view_count should be 0",
    stats.total_view_count,
    0,
  );
  TestValidator.equals(
    "unique_viewer_count should be 0",
    stats.unique_viewer_count,
    0,
  );
  TestValidator.equals(
    "last_viewed_at should be null",
    stats.last_viewed_at,
    null,
  );
  TestValidator.equals(
    "average_time_spent_seconds should be null",
    stats.average_time_spent_seconds,
    null,
  );
  TestValidator.predicate(
    "total_time_spent_seconds should be 0",
    stats.total_time_spent_seconds === 0,
  );
}
