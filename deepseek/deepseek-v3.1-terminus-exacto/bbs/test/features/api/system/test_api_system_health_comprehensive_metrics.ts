export async function test_api_system_health_comprehensive_metrics(
  connection: api.IConnection,
): Promise<void> {
  // Create super administrator connection
  const superAdminConnection: api.IConnection = { host: connection.host };
  // Authenticate as super administrator using join endpoint
  await authorize_super_admin_join(superAdminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      privilege_level: "super_admin",
    } satisfies IDiscussionBoardSuperAdmin.IJoin,
  });
  // Retrieve system health metrics
  const healthMetrics =
    await api.functional.discussionBoard.superAdmin.system.health.at(
      superAdminConnection,
    );
  // Validate the response structure - typia.assert performs complete validation
  typia.assert(healthMetrics);
  // Verify metric value is within reasonable bounds for performance metrics
  // This is business logic validation, not type validation
  TestValidator.predicate(
    "metric value is non-negative",
    healthMetrics.metric_value >= 0,
  );
}
