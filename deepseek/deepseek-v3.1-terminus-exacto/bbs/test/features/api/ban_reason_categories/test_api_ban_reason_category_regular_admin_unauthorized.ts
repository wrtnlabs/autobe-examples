export async function test_api_ban_reason_category_regular_admin_unauthorized(
  connection: api.IConnection,
): Promise<void> {
  // Create separate connection for regular admin
  const regularAdminConnection: api.IConnection = { host: connection.host };
  // Authenticate as regular administrator using utility function
  await authorize_admin_join(regularAdminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IDiscussionBoardAdmin.IJoin,
  });
  // Attempt to delete ban reason category - regular admin should not have permission
  await TestValidator.error(
    "regular admin cannot delete ban reason categories",
    async () => {
      await api.functional.discussionBoard.superAdmin.ban_reason_categories.erase(
        regularAdminConnection,
        {
          categoryId: typia.random<string & tags.Format<"uuid">>(),
        },
      );
    },
  );
}
