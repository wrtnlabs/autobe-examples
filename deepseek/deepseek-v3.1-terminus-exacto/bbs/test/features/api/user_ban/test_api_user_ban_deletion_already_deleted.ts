export async function test_api_user_ban_deletion_already_deleted(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin setup
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_login(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IDiscussionBoardAdmin.ILogin,
  });
  // 2. User setup - use join to create a new user
  const userConnection: api.IConnection = { host: connection.host };
  const user = await authorize_user_join(userConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
    } satisfies IDiscussionBoardUser.IJoin,
  });
  typia.assert(user);
  // 3. Create ban record using admin connection
  const ban = await generate_random_discussion_board_admin_user_bans_create(
    adminConnection,
    {
      body: {
        bannedUserId: user.id,
        banReason: RandomGenerator.paragraph({ sentences: 3 }),
        banDurationType: "permanent",
      } satisfies IDiscussionBoardBanRecord.ICreate,
    },
  );
  typia.assert(ban);
  // 4. First deletion (should succeed)
  await api.functional.discussionBoard.admin.user_bans.erase(adminConnection, {
    banId: ban.id,
  });
  // 5. Second deletion attempt (should handle appropriately)
  await TestValidator.error(
    "deleting already deleted ban",
    async () =>
      await api.functional.discussionBoard.admin.user_bans.erase(
        adminConnection,
        {
          banId: ban.id,
        },
      ),
  );
}
