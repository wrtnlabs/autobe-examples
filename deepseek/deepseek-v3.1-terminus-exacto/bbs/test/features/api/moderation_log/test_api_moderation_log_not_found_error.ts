export async function test_api_moderation_log_not_found_error(
  connection: api.IConnection,
): Promise<void> {
  // Create and authenticate an administrator
  const adminConnection: api.IConnection = { host: connection.host };
  const authResponse = await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IDiscussionBoardAdmin.IJoin,
  });
  typia.assert(authResponse);
  // Attempt to retrieve a non-existent moderation log
  const nonExistentModerationLogId = typia.random<
    string & tags.Format<"uuid">
  >();
  await TestValidator.httpError("moderation log not found", 404, async () => {
    await api.functional.discussionBoard.admin.moderation_logs.at(
      adminConnection,
      {
        moderationLogId: nonExistentModerationLogId,
      },
    );
  });
}
