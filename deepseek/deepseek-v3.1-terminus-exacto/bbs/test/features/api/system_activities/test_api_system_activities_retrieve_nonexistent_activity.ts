export async function test_api_system_activities_retrieve_nonexistent_activity(
  connection: api.IConnection,
): Promise<void> {
  // Create administrator connection
  const adminConnection: api.IConnection = { host: connection.host };
  // Create an administrator account for authentication
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IDiscussionBoardAdmin.IJoin,
  });
  // Attempt to retrieve a non-existent system activity
  await TestValidator.error("retrieve non-existent activity", async () => {
    await api.functional.discussionBoard.admin.system_activities.at(
      adminConnection,
      {
        activityId: typia.random<string & tags.Format<"uuid">>(),
      },
    );
  });
}
