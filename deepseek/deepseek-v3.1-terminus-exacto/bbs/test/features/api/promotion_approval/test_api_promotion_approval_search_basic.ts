export async function test_api_promotion_approval_search_basic(
  connection: api.IConnection,
): Promise<void> {
  // Create administrator connection
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IDiscussionBoardAdmin.IJoin,
  });
  // Search promotion approvals with empty request (no filters)
  const response =
    await api.functional.discussionBoard.admin.promotion_approvals.index(
      adminConnection,
      {
        body: {} satisfies IDiscussionBoardAdministratorPromotionApproval.IRequest,
      },
    );
  typia.assert(response);
  // Validate pagination business logic
  TestValidator.predicate(
    "current page is non-negative",
    response.pagination.current >= 0,
  );
  TestValidator.predicate(
    "limit is non-negative",
    response.pagination.limit >= 0,
  );
  TestValidator.predicate(
    "total records is non-negative",
    response.pagination.records >= 0,
  );
  TestValidator.predicate(
    "total pages is non-negative",
    response.pagination.pages >= 0,
  );
  // Validate data array consistency with pagination
  if (response.pagination.records === 0) {
    TestValidator.equals("empty data when no records", response.data.length, 0);
    TestValidator.equals(
      "pages should be 0 when no records",
      response.pagination.pages,
      0,
    );
  } else {
    TestValidator.predicate(
      "data length matches limit",
      response.data.length <= response.pagination.limit,
    );
    TestValidator.predicate(
      "current page calculation",
      response.pagination.current >= 1,
    );
  }
}
