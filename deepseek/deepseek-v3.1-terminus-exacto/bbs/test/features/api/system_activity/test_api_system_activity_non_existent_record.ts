export async function test_api_system_activity_non_existent_record(
  connection: api.IConnection,
): Promise<void> {
  // Create super admin connection
  const superAdminConnection: api.IConnection = { host: connection.host };
  // Authenticate as super administrator and get authorization token
  const authorized = await authorize_super_admin_join(superAdminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IDiscussionBoardSuperAdmin.IJoin,
  });
  // Update connection headers with authorization token
  superAdminConnection.headers = {
    ...superAdminConnection.headers,
    Authorization: authorized.token.access,
  };
  // Generate a valid UUID that does not exist in the database
  const nonExistentActivityId = typia.random<string & tags.Format<"uuid">>();
  // Attempt to retrieve non-existent system activity record and validate 404 error
  await TestValidator.httpError(
    "should return 404 for non-existent activity",
    404,
    async () => {
      await api.functional.discussionBoard.superAdmin.system_activities.at(
        superAdminConnection,
        {
          activityId: nonExistentActivityId,
        },
      );
    },
  );
}
