/**
 * Test authentication attempt with valid email format but no corresponding account in the system.
 * Create an administrator account via join, but use a different email (not previously registered)
 * for login attempt. Verify the system returns an appropriate authentication error.
 */
export async function test_api_admin_login_nonexistent_account(
  connection: api.IConnection,
): Promise<void> {
  // Create an administrator account to establish system context
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IDiscussionBoardAdmin.IJoin,
  });
  // Attempt login with a different email that doesn't exist in the system
  const loginConnection: api.IConnection = { host: connection.host };
  await TestValidator.error("login with nonexistent account", async () => {
    await api.functional.discussionBoard.auth.admin.login(loginConnection, {
      body: {
        email: typia.random<string & tags.Format<"email">>(), // Different email
        password: RandomGenerator.alphaNumeric(16),
        href: typia.random<string & tags.Format<"uri">>(),
        referrer: typia.random<string & tags.Format<"uri">>(),
        ip: typia.random<string & tags.Format<"ipv4">>(),
      } satisfies IDiscussionBoardAdmin.ILogin,
    });
  });
}
