/**
 * Test the system overview endpoint to validate comprehensive platform statistics for an administrator.
 * 1. Authenticate as an admin using the authorize_admin_join utility function
 * 2. Call the overview endpoint and verify the response structure
 * 3. Validate response contains system configuration data
 */
export async function test_api_admin_system_overview_comprehensive_statistics(
  connection: api.IConnection,
): Promise<void> {
  // Create admin-specific connection
  const adminConnection: api.IConnection = { host: connection.host };
  // Authenticate as admin using the utility function
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IDiscussionBoardAdmin.IJoin,
  });
  // Call the system overview endpoint
  const systemConfig =
    await api.functional.discussionBoard.admin.system.overview.at(
      adminConnection,
    );
  // Validate the response structure - typia.assert performs complete validation
  typia.assert(systemConfig);
  // Test unauthorized access should fail
  await TestValidator.error("unauthorized access should fail", async () => {
    await api.functional.discussionBoard.admin.system.overview.at(connection);
  });
}
