import { authorize_admin_join } from "../../../authorize/authorize_admin_join";
import { authorize_admin_login } from "../../../authorize/authorize_admin_login";
import { authorize_admin_refresh } from "../../../authorize/authorize_admin_refresh";

export async function test_api_admin_join_existing_email_prevention(
  connection: api.IConnection,
): Promise<void> {
  // Create initial admin account
  const adminConnection: api.IConnection = { host: connection.host };
  const firstAdmin = await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IDiscussionBoardAdmin.IJoin,
  });
  typia.assert(firstAdmin);
  // Attempt to create second admin with same email
  await TestValidator.error(
    "duplicate email registration prevention",
    async () => {
      await api.functional.discussionBoard.auth.admin.join(adminConnection, {
        body: {
          email: firstAdmin.email,
          password: RandomGenerator.alphaNumeric(16),
          display_name: RandomGenerator.name(),
          href: typia.random<string & tags.Format<"uri">>(),
          referrer: typia.random<string & tags.Format<"uri">>(),
          ip: typia.random<string & tags.Format<"ipv4">>(),
        } satisfies IDiscussionBoardAdmin.IJoin,
      });
    },
  );
}
