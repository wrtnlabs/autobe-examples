import api from "@ORGANIZATION/PROJECT-api";
import type { IAuthorizationToken } from "@ORGANIZATION/PROJECT-api/lib/structures/IAuthorizationToken";
import type { IDiscussionBoardAdmin } from "@ORGANIZATION/PROJECT-api/lib/structures/IDiscussionBoardAdmin";
import type { IDiscussionBoardCommentRateLimit } from "@ORGANIZATION/PROJECT-api/lib/structures/IDiscussionBoardCommentRateLimit";
import type { IDiscussionBoardUser } from "@ORGANIZATION/PROJECT-api/lib/structures/IDiscussionBoardUser";
import { IEntity } from "@ORGANIZATION/PROJECT-api/lib/structures/IEntity";
import type { IPage } from "@ORGANIZATION/PROJECT-api/lib/structures/IPage";
import type { IPageIDiscussionBoardCommentRateLimit } from "@ORGANIZATION/PROJECT-api/lib/structures/IPageIDiscussionBoardCommentRateLimit";
import { DeepPartial } from "@ORGANIZATION/PROJECT-api/lib/typings/DeepPartial";
import { ArrayUtil, RandomGenerator, TestValidator } from "@nestia/e2e";
import { IConnection } from "@nestia/fetcher";
import { randint } from "tstl";
import typia, { tags } from "typia";

import { authorize_admin_join } from "../../../authorize/authorize_admin_join";
import { authorize_admin_login } from "../../../authorize/authorize_admin_login";
import { authorize_admin_refresh } from "../../../authorize/authorize_admin_refresh";
import { authorize_user_join } from "../../../authorize/authorize_user_join";
import { authorize_user_login } from "../../../authorize/authorize_user_login";
import { authorize_user_refresh } from "../../../authorize/authorize_user_refresh";

export async function test_api_comment_rate_limit_filter_by_user(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create and authenticate as administrator
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IDiscussionBoardAdmin.IJoin,
  });
  // 2. Create multiple test users
  const user1Connection: api.IConnection = { host: connection.host };
  const user1 = await authorize_user_join(user1Connection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
    } satisfies IDiscussionBoardUser.IJoin,
  });
  typia.assert(user1);
  const user2Connection: api.IConnection = { host: connection.host };
  const user2 = await authorize_user_join(user2Connection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
    } satisfies IDiscussionBoardUser.IJoin,
  });
  typia.assert(user2);
  // Note: The comment rate limiting records are automatically generated by the system
  // when users submit comments. Since we don't have access to comment submission APIs
  // in the provided SDK functions, we'll test the filtering functionality with whatever
  // records exist in the system.
  // 3. Test filtering by specific user ID
  const filteredByUser1 =
    await api.functional.discussionBoard.admin.comment_rate_limits.index(
      adminConnection,
      {
        body: {
          discussion_board_user_id: user1.id,
        } satisfies IDiscussionBoardCommentRateLimit.IRequest,
      },
    );
  typia.assert(filteredByUser1);
  // Verify all returned records belong to user1 (if any records exist)
  for (const record of filteredByUser1.data) {
    TestValidator.equals("user ID matches filter", record.user.id, user1.id);
  }
  // 4. Test filtering by different user ID
  const filteredByUser2 =
    await api.functional.discussionBoard.admin.comment_rate_limits.index(
      adminConnection,
      {
        body: {
          discussion_board_user_id: user2.id,
        } satisfies IDiscussionBoardCommentRateLimit.IRequest,
      },
    );
  typia.assert(filteredByUser2);
  // Verify all returned records belong to user2 (if any records exist)
  for (const record of filteredByUser2.data) {
    TestValidator.equals("user ID matches filter", record.user.id, user2.id);
  }
  // 5. Test null user ID filter (should return all users' records)
  const allUsersRecords =
    await api.functional.discussionBoard.admin.comment_rate_limits.index(
      adminConnection,
      {
        body: {
          discussion_board_user_id: null,
        } satisfies IDiscussionBoardCommentRateLimit.IRequest,
      },
    );
  typia.assert(allUsersRecords);
  // Validate that null filter returns a superset of individual user filters
  if (filteredByUser1.data.length > 0 && filteredByUser2.data.length > 0) {
    TestValidator.predicate(
      "null filter returns more records than individual filters",
      allUsersRecords.data.length >=
        filteredByUser1.data.length + filteredByUser2.data.length,
    );
  }
  // 6. Test combined filtering with date range
  const combinedFilter =
    await api.functional.discussionBoard.admin.comment_rate_limits.index(
      adminConnection,
      {
        body: {
          discussion_board_user_id: user1.id,
          submitted_at_start: new Date(
            Date.now() - 24 * 60 * 60 * 1000,
          ).toISOString(),
          submitted_at_end: new Date().toISOString(),
        } satisfies IDiscussionBoardCommentRateLimit.IRequest,
      },
    );
  typia.assert(combinedFilter);
  // Verify combined filter results are subset of user1 filter results
  if (filteredByUser1.data.length > 0 && combinedFilter.data.length > 0) {
    TestValidator.predicate(
      "combined filter returns subset of user1 results",
      combinedFilter.data.length <= filteredByUser1.data.length,
    );
  }
  // 7. Test pagination with user filter
  const paginatedResults =
    await api.functional.discussionBoard.admin.comment_rate_limits.index(
      adminConnection,
      {
        body: {
          discussion_board_user_id: user1.id,
          page: 1,
          limit: 10,
        } satisfies IDiscussionBoardCommentRateLimit.IRequest,
      },
    );
  typia.assert(paginatedResults);
  TestValidator.predicate(
    "pagination metadata present",
    paginatedResults.pagination !== undefined,
  );
  TestValidator.predicate(
    "data array present",
    Array.isArray(paginatedResults.data),
  );
  // Validate pagination structure
  if (paginatedResults.pagination) {
    TestValidator.predicate(
      "current page is valid",
      paginatedResults.pagination.current >= 0,
    );
    TestValidator.predicate(
      "limit is valid",
      paginatedResults.pagination.limit >= 0,
    );
    TestValidator.predicate(
      "records count is valid",
      paginatedResults.pagination.records >= 0,
    );
    TestValidator.predicate(
      "pages count is valid",
      paginatedResults.pagination.pages >= 0,
    );
  }
}
