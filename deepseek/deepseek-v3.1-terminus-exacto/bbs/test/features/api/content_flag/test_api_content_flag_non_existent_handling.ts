export async function test_api_content_flag_non_existent_handling(
  connection: api.IConnection,
): Promise<void> {
  // Step 1: Create user account and get authenticated connection
  const userConnection: api.IConnection = { host: connection.host };
  await authorize_user_join(userConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
    },
  });
  // Step 2: Attempt to retrieve a non-existent content flag
  const nonExistentFlagId = typia.random<string & tags.Format<"uuid">>();
  // Step 3: Verify 404 Not Found error
  await TestValidator.httpError(
    "Retrieving non-existent flag should return 404",
    404,
    async () => {
      await api.functional.discussionBoard.user.content_flags.at(
        userConnection,
        {
          flagId: nonExistentFlagId,
        },
      );
    },
  );
}
