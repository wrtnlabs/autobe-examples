/**
 * Test the successful retrieval of a content flag by an administrator.
 * Validates that an authenticated administrator can retrieve detailed information
 * about a specific content flag, including reporter details, flagged content,
 * moderation status, and resolution information.
 */
export async function test_api_content_flag_retrieval_by_admin(
  connection: api.IConnection,
): Promise<void> {
  // Create and authenticate as administrator
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IDiscussionBoardAdmin.IJoin,
  });
  // Generate a random content flag ID to retrieve
  const flagId = typia.random<string & tags.Format<"uuid">>();
  // Retrieve the content flag using the admin endpoint
  const contentFlag =
    await api.functional.discussionBoard.admin.content_flags.at(
      adminConnection,
      { flagId },
    );
  // Validate the response structure - typia.assert performs complete validation
  typia.assert(contentFlag);
  // Verify the flag ID matches the requested ID
  TestValidator.equals("flag ID matches", contentFlag.id, flagId);
}
