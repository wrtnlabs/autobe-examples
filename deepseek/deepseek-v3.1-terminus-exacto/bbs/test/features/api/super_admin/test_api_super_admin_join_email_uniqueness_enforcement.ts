/**
 * Test super administrator registration fails when attempting to use an email address
 * that has already been registered for another super administrator account.
 */
export async function test_api_super_admin_join_email_uniqueness_enforcement(
  connection: api.IConnection,
): Promise<void> {
  // Create first super admin connection and account
  const firstConnection: api.IConnection = { host: connection.host };
  const firstSuperAdmin = await authorize_super_admin_join(firstConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IDiscussionBoardSuperAdmin.IJoin,
  });
  typia.assert(firstSuperAdmin);
  // Attempt to register second super admin with same email
  const secondConnection: api.IConnection = { host: connection.host };
  await TestValidator.error(
    "duplicate super admin email should fail",
    async () =>
      await authorize_super_admin_join(secondConnection, {
        body: {
          email: firstSuperAdmin.email,
          password: RandomGenerator.alphaNumeric(16),
          href: typia.random<string & tags.Format<"uri">>(),
          referrer: typia.random<string & tags.Format<"uri">>(),
          ip: typia.random<string & tags.Format<"ipv4">>(),
        } satisfies IDiscussionBoardSuperAdmin.IJoin,
      }),
  );
}
