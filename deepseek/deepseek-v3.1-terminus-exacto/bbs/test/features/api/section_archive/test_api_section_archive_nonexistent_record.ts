export async function test_api_section_archive_nonexistent_record(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin authentication
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      display_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IDiscussionBoardAdmin.IJoin,
  });
  // 2. Generate a non-existent archive ID
  const nonExistentArchiveId = typia.random<string & tags.Format<"uuid">>();
  // 3. Attempt to retrieve non-existent archive record
  await TestValidator.httpError(
    "retrieve non-existent archive should return 404",
    404,
    async () => {
      await api.functional.discussionBoard.admin.sections.archives.at(
        adminConnection,
        {
          archiveId: nonExistentArchiveId,
        } satisfies api.functional.discussionBoard.admin.sections.archives.at.Props,
      );
    },
  );
}
