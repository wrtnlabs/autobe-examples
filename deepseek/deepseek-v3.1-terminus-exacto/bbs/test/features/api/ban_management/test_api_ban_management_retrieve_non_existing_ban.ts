export async function test_api_ban_management_retrieve_non_existing_ban(
  connection: api.IConnection,
): Promise<void> {
  // Create admin connection and authenticate
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: undefined,
  });
  // Generate a valid but non-existent UUID
  const nonExistentBanId = typia.random<string & tags.Format<"uuid">>();
  // Attempt to retrieve non-existent ban record and validate 404 error
  await TestValidator.httpError(
    "retrieve non-existent ban returns 404",
    404,
    async () =>
      await api.functional.discussionBoard.admin.bans.at(adminConnection, {
        banId: nonExistentBanId,
      }),
  );
}
