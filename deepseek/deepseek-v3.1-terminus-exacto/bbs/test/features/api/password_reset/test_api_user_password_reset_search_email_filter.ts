export async function test_api_user_password_reset_search_email_filter(
  connection: api.IConnection,
): Promise<void> {
  // Create authenticated user sessions for testing
  const userConnection: api.IConnection = { host: connection.host };
  // Create multiple users with different email patterns
  const user1 = await authorize_user_join(userConnection, {
    body: {
      email: "test.user1@example.com" satisfies string & tags.Format<"email">,
      password: "password123",
      display_name: RandomGenerator.name(),
    } satisfies IDiscussionBoardUser.IJoin,
  });
  typia.assert(user1);
  const user2 = await authorize_user_join(userConnection, {
    body: {
      email: "another.user2@test.org" satisfies string & tags.Format<"email">,
      password: "password123",
      display_name: RandomGenerator.name(),
    } satisfies IDiscussionBoardUser.IJoin,
  });
  typia.assert(user2);
  const user3 = await authorize_user_join(userConnection, {
    body: {
      email: "different.user3@demo.net" satisfies string & tags.Format<"email">,
      password: "password123",
      display_name: RandomGenerator.name(),
    } satisfies IDiscussionBoardUser.IJoin,
  });
  typia.assert(user3);
  // Note: Password reset requests would typically be generated by the system
  // when users request password resets. For testing purposes, we assume
  // reset requests exist for these users due to previous reset attempts.
  // Test exact email matching for user1
  const exactSearch =
    await api.functional.discussionBoard.user.users.password_resets.index(
      userConnection,
      {
        body: {
          email: user1.email,
        } satisfies IDiscussionBoardUserPasswordReset.IRequest,
      },
    );
  typia.assert(exactSearch);
  // Validate exact match results
  TestValidator.predicate(
    "exact email search should return paginated response",
    typeof exactSearch.pagination === "object" &&
      exactSearch.pagination !== null,
  );
  // Verify response structure contains expected fields
  if (exactSearch.data.length > 0) {
    const record = exactSearch.data[0];
    TestValidator.predicate(
      "record should have valid id",
      typeof record.id === "string" && record.id.length > 0,
    );
    TestValidator.predicate(
      "record should have expiration timestamp",
      typeof record.expired_at === "string" && record.expired_at.length > 0,
    );
    TestValidator.predicate(
      "record should have creation timestamp",
      typeof record.created_at === "string" && record.created_at.length > 0,
    );
    TestValidator.predicate(
      "record should have user summary",
      typeof record.user === "object" && record.user !== null,
    );
    // Validate user summary structure
    TestValidator.predicate(
      "user summary should have id",
      typeof record.user.id === "string" && record.user.id.length > 0,
    );
    TestValidator.predicate(
      "user summary should have display name",
      typeof record.user.display_name === "string" &&
        record.user.display_name.length > 0,
    );
    TestValidator.predicate(
      "user summary should have creation timestamp",
      typeof record.user.created_at === "string" &&
        record.user.created_at.length > 0,
    );
  }
  // Test search with non-existent email
  const nonExistentEmail = "nonexistent.user@example.com" satisfies string &
    tags.Format<"email">;
  const noResultsSearch =
    await api.functional.discussionBoard.user.users.password_resets.index(
      userConnection,
      {
        body: {
          email: nonExistentEmail,
        } satisfies IDiscussionBoardUserPasswordReset.IRequest,
      },
    );
  typia.assert(noResultsSearch);
  TestValidator.predicate(
    "non-existent email search should return valid pagination",
    typeof noResultsSearch.pagination === "object" &&
      noResultsSearch.pagination !== null,
  );
  // Test empty search (no email filter) to get all records
  const allRecordsSearch =
    await api.functional.discussionBoard.user.users.password_resets.index(
      userConnection,
      {
        body: {
          // No email filter - should return all records
        } satisfies IDiscussionBoardUserPasswordReset.IRequest,
      },
    );
  typia.assert(allRecordsSearch);
  TestValidator.predicate(
    "empty search should return valid response structure",
    typeof allRecordsSearch.pagination === "object" &&
      allRecordsSearch.pagination !== null &&
      Array.isArray(allRecordsSearch.data),
  );
  // Validate pagination structure exists and has required fields
  if (
    allRecordsSearch.pagination &&
    typeof allRecordsSearch.pagination === "object"
  ) {
    const pagination = allRecordsSearch.pagination as any;
    TestValidator.predicate(
      "pagination should have current page",
      typeof pagination.current === "number" && pagination.current >= 0,
    );
    TestValidator.predicate(
      "pagination should have limit",
      typeof pagination.limit === "number" && pagination.limit >= 0,
    );
    TestValidator.predicate(
      "pagination should have records count",
      typeof pagination.records === "number" && pagination.records >= 0,
    );
    TestValidator.predicate(
      "pagination should have pages count",
      typeof pagination.pages === "number" && pagination.pages >= 0,
    );
  }
}
