export async function test_api_backup_record_retrieval_not_found(
  connection: api.IConnection,
): Promise<void> {
  // Create admin connection and authenticate
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IDiscussionBoardAdmin.IJoin,
  });
  // Generate a valid but non-existent UUID
  const nonExistentRecordId = typia.random<string & tags.Format<"uuid">>();
  // Attempt to retrieve non-existent backup record and validate 404 error
  await TestValidator.httpError(
    "retrieve non-existent backup record",
    404,
    async () => {
      await api.functional.discussionBoard.admin.backup_records.at(
        adminConnection,
        {
          recordId: nonExistentRecordId,
        },
      );
    },
  );
}
