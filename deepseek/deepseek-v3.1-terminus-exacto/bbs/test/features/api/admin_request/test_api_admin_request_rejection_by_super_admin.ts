export async function test_api_admin_request_rejection_by_super_admin(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create and authenticate super administrator
  const superAdminConnection: api.IConnection = { host: connection.host };
  await authorize_super_admin_join(superAdminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IDiscussionBoardSuperAdmin.IJoin,
  });
  // 2. Create and authenticate regular member
  const memberConnection: api.IConnection = { host: connection.host };
  await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      bio: RandomGenerator.paragraph({ sentences: 2 }),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IDiscussionBoardMember.IJoin,
  });
  // 3. Member submits admin request
  const adminRequest =
    await generate_random_discussion_board_member_admin_requests_create(
      memberConnection,
      {
        body: {
          reason: RandomGenerator.paragraph({ sentences: 3 }),
        } satisfies IDiscussionBoardAdminRequest.ICreate,
      },
    );
  typia.assert(adminRequest);
  TestValidator.equals(
    "initial status should be pending",
    adminRequest.status,
    "pending",
  );
  // 4. Super administrator rejects the request
  const rejectedRequest =
    await api.functional.discussionBoard.member.admin_requests.update(
      superAdminConnection,
      {
        requestId: adminRequest.id,
        body: {
          status: "rejected",
        } satisfies IDiscussionBoardAdminRequest.IUpdate,
      },
    );
  typia.assert(rejectedRequest);
  // 5. Validate the rejection
  TestValidator.equals(
    "status should be rejected",
    rejectedRequest.status,
    "rejected",
  );
  TestValidator.equals(
    "request ID should match",
    rejectedRequest.id,
    adminRequest.id,
  );
  TestValidator.equals(
    "reason should remain unchanged",
    rejectedRequest.reason,
    adminRequest.reason,
  );
  TestValidator.equals(
    "member should remain the same",
    rejectedRequest.member.id,
    adminRequest.member.id,
  );
  TestValidator.predicate(
    "updated_at should be later than created_at",
    new Date(rejectedRequest.updated_at) > new Date(adminRequest.created_at),
  );
}
