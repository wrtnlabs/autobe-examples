export async function test_api_attachment_image_metadata_creation_for_new_attachment(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create and authenticate superAdmin
  const superAdminConnection: api.IConnection = { host: connection.host };
  await authorize_super_admin_join(superAdminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IDiscussionBoardSuperAdmin.IJoin,
  });
  // 2. Create and authenticate member (article author)
  const memberConnection: api.IConnection = { host: connection.host };
  await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      bio: RandomGenerator.paragraph({ sentences: 2 }),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IDiscussionBoardMember.IJoin,
  });
  // 3. Create an article using member account
  const article = await generate_random_discussion_board_member_articles_create(
    memberConnection,
    {
      body: {
        title: RandomGenerator.paragraph({ sentences: 2 }),
        body: RandomGenerator.content({ paragraphs: 3 }),
        discussion_board_section_id: typia.random<
          string & tags.Format<"uuid">
        >(),
      } satisfies IDiscussionBoardArticle.ICreate,
    },
  );
  typia.assert(article);
  // 4. Create an attachment for the article using superAdmin
  const attachment =
    await generate_random_discussion_board_super_admin_articles_attachments_create(
      superAdminConnection,
      {
        params: {
          articleId: article.id,
        },
        body: {
          filename: `${RandomGenerator.alphabets(8)}.jpg`,
          filetype: "jpg",
          mime_type: "image/jpeg",
          size_bytes: typia.random<
            number & tags.Type<"int32"> & tags.Minimum<1>
          >(),
        } satisfies IDiscussionBoardAttachment.ICreate,
      },
    );
  typia.assert(attachment);
  // 5. Create image metadata for the attachment
  const imageMetadata =
    await api.functional.discussionBoard.superAdmin.articles.attachments.image_metadata.update(
      superAdminConnection,
      {
        articleId: article.id,
        attachmentId: attachment.id,
        body: {
          width: typia.random<number & tags.Type<"int32"> & tags.Minimum<1>>(),
          height: typia.random<number & tags.Type<"int32"> & tags.Minimum<1>>(),
          altText: RandomGenerator.paragraph({ sentences: 1 }),
        } satisfies IDiscussionBoardImageAttachment.IUpdate,
      },
    );
  typia.assert(imageMetadata);
  // 6. Validate the created image metadata links correctly
  TestValidator.equals(
    "metadata linked to correct attachment",
    imageMetadata.discussion_board_attachment_id,
    attachment.id,
  );
}
