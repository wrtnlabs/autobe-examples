export async function test_api_attachment_download_public_access(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create member account for article creation
  const memberConnection: api.IConnection = { host: connection.host };
  const member = await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      bio: RandomGenerator.paragraph({ sentences: 2 }),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IDiscussionBoardMember.IJoin,
  });
  typia.assert(member);
  // 2. Create article using member connection
  // Note: We assume default sections exist and allow public access
  const article = await generate_random_discussion_board_member_articles_create(
    memberConnection,
    {
      body: {
        title: RandomGenerator.paragraph({ sentences: 2 }),
        body: RandomGenerator.content({ paragraphs: 3 }),
        discussion_board_section_id: typia.random<
          string & tags.Format<"uuid">
        >(),
      } satisfies IDiscussionBoardArticle.ICreate,
    },
  );
  typia.assert(article);
  // 3. Upload attachment to the article
  const attachment =
    await generate_random_discussion_board_member_articles_attachments_create(
      memberConnection,
      {
        params: {
          articleId: article.id,
        },
        body: {
          filename: RandomGenerator.name() + ".txt",
          filetype: "txt",
          mime_type: "text/plain",
          size_bytes: typia.random<
            number & tags.Type<"int32"> & tags.Minimum<1>
          >(),
        } satisfies IDiscussionBoardAttachment.ICreate,
      },
    );
  typia.assert(attachment);
  // 4. Attempt to download attachment using base connection (unauthenticated guest)
  // This validates that public access to attachments works correctly
  await TestValidator.predicate(
    "guest should be able to download attachment",
    async () => {
      await api.functional.discussionBoard.articles.attachments.download(
        connection,
        {
          articleId: article.id,
          attachmentId: attachment.id,
        },
      );
      return true; // If no error thrown, download succeeded
    },
  );
}
