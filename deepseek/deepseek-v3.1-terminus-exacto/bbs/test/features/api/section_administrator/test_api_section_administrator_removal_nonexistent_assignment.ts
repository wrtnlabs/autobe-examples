export async function test_api_section_administrator_removal_nonexistent_assignment(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as super administrator
  const superAdminConnection: api.IConnection = { host: connection.host };
  const superAdminAuth = await authorize_super_admin_join(
    superAdminConnection,
    {
      body: {
        email: typia.random<string & tags.Format<"email">>(),
        password: RandomGenerator.alphaNumeric(16),
        href: typia.random<string & tags.Format<"uri">>(),
        referrer: typia.random<string & tags.Format<"uri">>(),
        ip: typia.random<string & tags.Format<"ipv4">>(),
      } satisfies IDiscussionBoardSuperAdmin.IJoin,
    },
  );
  typia.assert(superAdminAuth);
  // 2. Create a section to test against
  const section =
    await generate_random_discussion_board_super_admin_sections_create(
      superAdminConnection,
      {
        body: {
          name: RandomGenerator.paragraph({ sentences: 2 }),
          description: RandomGenerator.paragraph({ sentences: 3 }),
          status: "active",
          display_order: typia.random<number & tags.Type<"int32">>(),
        } satisfies IDiscussionBoardSection.ICreate,
      },
    );
  typia.assert(section);
  // 3. Generate a non-existent assignment ID (valid UUID but not assigned)
  const nonExistentAssignmentId = typia.random<string & tags.Format<"uuid">>();
  // 4. Attempt to remove non-existent assignment and validate error response
  await TestValidator.error(
    "should reject non-existent assignment removal",
    async () => {
      await api.functional.discussionBoard.superAdmin.sections.administrators.erase(
        superAdminConnection,
        {
          sectionId: section.id,
          assignmentId: nonExistentAssignmentId,
        },
      );
    },
  );
}
