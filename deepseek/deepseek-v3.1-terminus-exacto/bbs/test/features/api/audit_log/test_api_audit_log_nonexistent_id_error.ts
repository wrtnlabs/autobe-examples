export async function test_api_audit_log_nonexistent_id_error(
  connection: api.IConnection,
): Promise<void> {
  // Create super admin connection
  const superAdminConnection: api.IConnection = { host: connection.host };
  await authorize_super_admin_join(superAdminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IDiscussionBoardSuperAdmin.IJoin,
  });
  // Generate a random UUID that doesn't exist
  const nonExistentLogId: string & tags.Format<"uuid"> = typia.random<
    string & tags.Format<"uuid">
  >();
  // Attempt to retrieve non-existent audit log and validate 404 error
  await TestValidator.httpError(
    "non-existent audit log should return 404",
    404,
    async () => {
      await api.functional.discussionBoard.superAdmin.audit_logs.at(
        superAdminConnection,
        {
          logId: nonExistentLogId,
        },
      );
    },
  );
}
