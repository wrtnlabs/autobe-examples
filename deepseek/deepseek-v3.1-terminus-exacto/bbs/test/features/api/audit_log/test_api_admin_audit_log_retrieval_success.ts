export async function test_api_admin_audit_log_retrieval_success(
  connection: api.IConnection,
): Promise<void> {
  // Create admin connection and authenticate
  const adminConnection: api.IConnection = { host: connection.host };
  const adminAuth = await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IDiscussionBoardAdmin.IJoin,
  });
  typia.assert(adminAuth);
  // Retrieve audit log
  const auditLogId = typia.random<string & tags.Format<"uuid">>();
  const auditLog = await api.functional.discussionBoard.admin.audit_logs.at(
    adminConnection,
    { auditLogId },
  );
  typia.assert(auditLog);
  // Validate business logic relationships
  TestValidator.equals(
    "audit log id should match requested id",
    auditLog.id,
    auditLogId,
  );
  TestValidator.predicate(
    "audit log should have valid structure",
    auditLog.description.length > 0 &&
      auditLog.created_at <= auditLog.updated_at,
  );
}
