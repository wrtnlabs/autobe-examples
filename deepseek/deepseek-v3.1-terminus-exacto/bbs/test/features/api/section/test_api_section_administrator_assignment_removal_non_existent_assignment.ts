export async function test_api_section_administrator_assignment_removal_non_existent_assignment(
  connection: api.IConnection,
): Promise<void> {
  // Create administrator connection
  const adminConnection: api.IConnection = { host: connection.host };
  const admin = await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IDiscussionBoardAdmin.IJoin,
  });
  typia.assert(admin);
  // Create a section using the utility function
  const section = await generate_random_discussion_board_admin_sections_create(
    adminConnection,
    {},
  );
  typia.assert(section);
  // Generate a random UUID for non-existent assignment
  const nonExistentAssignmentId = typia.random<string & tags.Format<"uuid">>();
  // Attempt to delete non-existent assignment and validate 404 error
  await TestValidator.httpError(
    "delete non-existent assignment should return 404",
    404,
    async () => {
      await api.functional.discussionBoard.admin.sections.administrators.erase(
        adminConnection,
        {
          sectionId: section.id,
          assignmentId: nonExistentAssignmentId,
        },
      );
    },
  );
}
