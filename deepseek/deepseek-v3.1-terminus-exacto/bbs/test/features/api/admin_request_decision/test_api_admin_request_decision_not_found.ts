export async function test_api_admin_request_decision_not_found(
  connection: api.IConnection,
): Promise<void> {
  // Create super administrator connection
  const superAdminConnection: api.IConnection = { host: connection.host };
  await authorize_super_admin_join(superAdminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IDiscussionBoardSuperAdmin.IJoin,
  });
  // Generate a random UUID that does not exist
  const nonExistentDecisionId = typia.random<string & tags.Format<"uuid">>();
  // Attempt to retrieve non-existent decision and validate error
  await TestValidator.error("retrieve non-existent decision", async () => {
    await api.functional.discussionBoard.superAdmin.admin_request_decisions.at(
      superAdminConnection,
      {
        decisionId: nonExistentDecisionId,
      },
    );
  });
}
