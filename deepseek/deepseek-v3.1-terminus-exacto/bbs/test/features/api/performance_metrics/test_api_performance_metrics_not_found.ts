export async function test_api_performance_metrics_not_found(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as superAdmin using utility function
  const superAdminConnection: api.IConnection = { host: connection.host };
  await authorize_super_admin_join(superAdminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    },
  });
  // 2. Generate a non-existent UUID
  const nonExistentMetricId = typia.random<string & tags.Format<"uuid">>();
  // 3. Call endpoint with non-existent ID and validate 404 Not Found error
  await TestValidator.httpError(
    "performance metric not found returns 404",
    404,
    async () => {
      await api.functional.discussionBoard.superAdmin.performance_metrics.at(
        superAdminConnection,
        { metricId: nonExistentMetricId },
      );
    },
  );
}
