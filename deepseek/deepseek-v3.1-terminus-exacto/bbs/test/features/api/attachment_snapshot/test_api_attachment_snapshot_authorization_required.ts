export async function test_api_attachment_snapshot_authorization_required(
  connection: api.IConnection,
): Promise<void> {
  // Create member account
  const memberConnection: api.IConnection = { host: connection.host };
  await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      bio: RandomGenerator.paragraph({ sentences: 2 }),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IDiscussionBoardMember.IJoin,
  });
  // Create regular admin account
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IDiscussionBoardAdmin.IJoin,
  });
  // Create superAdmin account
  const superAdminConnection: api.IConnection = { host: connection.host };
  await authorize_super_admin_join(superAdminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IDiscussionBoardSuperAdmin.IJoin,
  });
  // Generate a valid snapshot ID for testing
  const snapshotId = typia.random<string & tags.Format<"uuid">>();
  // Test member access - should fail
  await TestValidator.error(
    "member should not access superAdmin endpoint",
    async () => {
      await api.functional.discussionBoard.superAdmin.attachment_snapshots.at(
        memberConnection,
        { snapshotId },
      );
    },
  );
  // Test regular admin access - should fail
  await TestValidator.error(
    "regular admin should not access superAdmin endpoint",
    async () => {
      await api.functional.discussionBoard.superAdmin.attachment_snapshots.at(
        adminConnection,
        { snapshotId },
      );
    },
  );
  // Test superAdmin access - should succeed
  const snapshot =
    await api.functional.discussionBoard.superAdmin.attachment_snapshots.at(
      superAdminConnection,
      { snapshotId },
    );
  typia.assert(snapshot);
}
