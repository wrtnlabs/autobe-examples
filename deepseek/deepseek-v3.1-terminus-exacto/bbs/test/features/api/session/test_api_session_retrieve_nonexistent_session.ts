export async function test_api_session_retrieve_nonexistent_session(
  connection: api.IConnection,
): Promise<void> {
  // Create user account through registration using utility function
  const userConnection: api.IConnection = { host: connection.host };
  const user = await authorize_user_join(userConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
    },
  });
  typia.assert(user);
  // Attempt to retrieve non-existent session with random UUID
  const nonExistentSessionId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.httpError(
    "non-existent session retrieval",
    404,
    async () => {
      await api.functional.discussionBoard.user.users.sessions.at(
        userConnection,
        {
          sessionId: nonExistentSessionId,
        },
      );
    },
  );
}
