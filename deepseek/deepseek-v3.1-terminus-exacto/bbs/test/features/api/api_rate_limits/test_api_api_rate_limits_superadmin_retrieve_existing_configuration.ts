export async function test_api_api_rate_limits_superadmin_retrieve_existing_configuration(
  connection: api.IConnection,
): Promise<void> {
  const superAdminConnection: api.IConnection = { host: connection.host };
  const superAdmin = await api.functional.discussionBoard.auth.superAdmin.join(
    superAdminConnection,
    {
      body: {
        email: typia.random<string & tags.Format<"email">>(),
        password: RandomGenerator.alphaNumeric(16),
        href: typia.random<string & tags.Format<"uri">>(),
        referrer: typia.random<string & tags.Format<"uri">>(),
        ip: typia.random<string & tags.Format<"ipv4">>(),
      } satisfies IDiscussionBoardSuperAdmin.IJoin,
    },
  );
  typia.assert(superAdmin);
  const rateLimitConfig =
    await api.functional.discussionBoard.superAdmin.api_rate_limits.at(
      superAdminConnection,
      { rateLimitId: typia.random<string & tags.Format<"uuid">>() },
    );
  typia.assert(rateLimitConfig);
  TestValidator.equals(
    "configuration retrieved successfully",
    typeof rateLimitConfig.id,
    "string",
  );
  TestValidator.predicate(
    "configuration has enforcement count tracking",
    rateLimitConfig.enforcement_count >= 0,
  );
  TestValidator.predicate(
    "configuration has valid timestamps",
    new Date(rateLimitConfig.created_at).getTime() <= new Date().getTime(),
  );
}
