export async function test_api_data_retention_policy_data_type_mapping_not_found(
  connection: api.IConnection,
): Promise<void> {
  // Create superAdmin connection and authenticate using available utility function
  const superAdminConnection: api.IConnection = { host: connection.host };
  await authorize_super_admin_join(superAdminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IDiscussionBoardSuperAdmin.IJoin,
  });
  // Generate a random UUID that does not exist in the system
  const nonExistentMappingId = typia.random<string & tags.Format<"uuid">>();
  // Attempt to delete non-existent mapping and validate 404 error
  await TestValidator.error(
    "delete non-existent mapping should return 404",
    async () => {
      await api.functional.discussionBoard.superAdmin.data_retention_policy_data_type_mappings.erase(
        superAdminConnection,
        {
          mappingId: nonExistentMappingId,
        },
      );
    },
  );
}
