export async function test_api_article_snapshots_empty_history(
  connection: api.IConnection,
): Promise<void> {
  // Create actor-specific connection for super admin
  const superAdminConnection: api.IConnection = { host: connection.host };
  // Authenticate as super administrator
  const auth = await authorize_super_admin_join(superAdminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IDiscussionBoardSuperAdmin.IJoin,
  });
  typia.assert(auth);
  // Create a new article without any subsequent edits
  const article =
    await generate_random_discussion_board_super_admin_articles_create(
      superAdminConnection,
      {
        body: {
          title: RandomGenerator.paragraph({ sentences: 2 }),
          content: RandomGenerator.content({ paragraphs: 3 }),
          discussion_board_section_id: typia.random<
            string & tags.Format<"uuid">
          >(),
        } satisfies IDiscussionBoardArticle.ICreate,
      },
    );
  typia.assert(article);
  // Attempt to retrieve snapshots for the newly created article
  const snapshots =
    await api.functional.discussionBoard.superAdmin.articles.snapshots.index(
      superAdminConnection,
      {
        articleId: article.id,
        body: {
          page: typia.random<number & tags.Type<"int32"> & tags.Minimum<1>>(),
          limit: typia.random<
            number & tags.Type<"int32"> & tags.Minimum<1> & tags.Maximum<100>
          >(),
        } satisfies IDiscussionBoardArticleSnapshot.IRequest,
      },
    );
  typia.assert(snapshots);
  // Access the actual pagination properties through the nested structure
  const actualPagination =
    snapshots.pagination.pagination.pagination.pagination;
  // Verify empty snapshot data array
  TestValidator.equals("empty snapshot data", snapshots.data.length, 0);
  // Verify pagination records match empty snapshot count
  TestValidator.equals(
    "pagination records match data length",
    actualPagination.records,
    0,
  );
  TestValidator.equals(
    "pagination pages should be 0 for empty records",
    actualPagination.pages,
    0,
  );
  TestValidator.predicate(
    "pagination current page should be valid",
    actualPagination.current >= 1,
  );
  TestValidator.predicate(
    "pagination limit should be valid",
    actualPagination.limit >= 1 && actualPagination.limit <= 100,
  );
}
