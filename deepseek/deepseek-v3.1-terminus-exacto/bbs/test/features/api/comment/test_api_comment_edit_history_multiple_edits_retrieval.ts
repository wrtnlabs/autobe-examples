export async function test_api_comment_edit_history_multiple_edits_retrieval(
  connection: api.IConnection,
): Promise<void> {
  // Create user connection and authenticate
  const userConnection: api.IConnection = { host: connection.host };
  await authorize_user_join(userConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      bio: RandomGenerator.paragraph({ sentences: 2 }),
    } satisfies IDiscussionBoardUser.IJoin,
  });
  // Create an article for comment placement
  const article = await generate_random_discussion_board_user_articles_create(
    userConnection,
    {
      body: {
        title: RandomGenerator.paragraph({
          sentences: 2,
          wordMin: 5,
          wordMax: 8,
        }),
        content: RandomGenerator.content({
          paragraphs: 3,
          sentenceMin: 5,
          sentenceMax: 8,
        }),
        section_id: typia.random<string & tags.Format<"uuid">>(),
        status: "published" as const,
      } satisfies IDiscussionBoardArticle.ICreate,
    },
  );
  typia.assert(article);
  // Add initial comment
  const comment =
    await generate_random_discussion_board_user_articles_comments_create(
      userConnection,
      {
        body: {
          content: RandomGenerator.paragraph({ sentences: 3 }),
        } satisfies IDiscussionBoardComment.ICreate,
        params: {
          articleId: article.id,
        },
      },
    );
  typia.assert(comment);
  // Since no edit comment API is available, we can only test the retrieval of edit history
  // This tests that the endpoint exists and returns valid data structure
  const editHistory =
    await api.functional.discussionBoard.articles.comments.edit_histories.at(
      userConnection,
      {
        articleId: article.id,
        commentId: comment.id,
        editHistoryId: typia.random<string & tags.Format<"uuid">>(),
      },
    );
  typia.assert(editHistory);
  // Validate basic structure of edit history response
  TestValidator.predicate(
    "should have edit sequence",
    typeof editHistory.edit_sequence === "number",
  );
  TestValidator.predicate(
    "should have original content",
    typeof editHistory.original_content === "string",
  );
  TestValidator.predicate(
    "should have edited content",
    typeof editHistory.edited_content === "string",
  );
  TestValidator.predicate(
    "should have valid creation timestamp",
    new Date(editHistory.created_at).getTime() > 0,
  );
}
