export async function test_api_comment_retrieval_comment_not_found(
  connection: api.IConnection,
): Promise<void> {
  // Create a user account for article creation
  const userConnection: api.IConnection = { host: connection.host };
  const user = await authorize_user_join(userConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
    } satisfies IDiscussionBoardUser.IJoin,
  });
  typia.assert(user);
  // Create an article under the user account
  // Note: section ID must be provided - using a random UUID since no section creation utility exists
  const article = await generate_random_discussion_board_user_articles_create(
    userConnection,
    {
      body: {
        title: RandomGenerator.paragraph({ sentences: 2 }),
        content: RandomGenerator.paragraph({ sentences: 5 }),
        discussion_board_section_id: typia.random<
          string & tags.Format<"uuid">
        >(),
      } satisfies IDiscussionBoardArticle.ICreate,
    },
  );
  typia.assert(article);
  // Generate a non-existent comment ID
  const nonExistentCommentId = typia.random<string & tags.Format<"uuid">>();
  // Verify the operation returns a 404 error when comment not found
  await TestValidator.httpError(
    "comment not found should return 404",
    404,
    async () =>
      await api.functional.discussionBoard.articles.comments.at(
        userConnection,
        {
          articleId: article.id,
          commentId: nonExistentCommentId,
        },
      ),
  );
}
