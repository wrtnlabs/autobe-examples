/**
 * Test the deletion impact analysis for an eligible comment that can be safely deleted.
 * Creates a comment through normal member workflow, then authenticates as admin and
 * analyzes deletion impact. Verifies the response indicates the comment exists,
 * is eligible for deletion, has no restrictions, and zero dependencies.
 */
export async function test_api_comment_deletion_impact_eligible(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create and authenticate as member
  const memberConnection: api.IConnection = { host: connection.host };
  await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      bio: RandomGenerator.paragraph({ sentences: 2 }),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IDiscussionBoardMember.IJoin,
  });
  // 2. Create an article for the comment
  const article = await generate_random_discussion_board_member_articles_create(
    memberConnection,
    {
      body: {
        title: RandomGenerator.paragraph({ sentences: 2 }),
        body: RandomGenerator.content({ paragraphs: 3 }),
        discussion_board_section_id: typia.random<
          string & tags.Format<"uuid">
        >(),
      } satisfies IDiscussionBoardArticle.ICreate,
    },
  );
  typia.assert(article);
  // 3. Create a comment on the article
  const comment =
    await generate_random_discussion_board_member_articles_comments_create(
      memberConnection,
      {
        body: {
          content: RandomGenerator.paragraph({ sentences: 3 }),
        } satisfies IDiscussionBoardComment.ICreate,
        params: {
          articleId: article.id,
        },
      },
    );
  typia.assert(comment);
  // 4. Authenticate as administrator
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IDiscussionBoardAdmin.IJoin,
  });
  // 5. Analyze deletion impact for the created comment
  const impact =
    await api.functional.discussionBoard.admin.comments.deletion_impact.deletionImpact(
      adminConnection,
      {
        commentId: comment.id,
      },
    );
  typia.assert(impact);
  // 6. Validate the impact analysis indicates eligibility for deletion
  TestValidator.equals("comment exists", impact.exists, true);
  TestValidator.equals("comment eligible for deletion", impact.eligible, true);
  TestValidator.equals("no restrictions", impact.restrictions.length, 0);
  TestValidator.equals("zero dependencies", impact.dependencyCount, 0);
}
