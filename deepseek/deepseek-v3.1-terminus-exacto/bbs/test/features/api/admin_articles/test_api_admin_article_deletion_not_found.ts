export async function test_api_admin_article_deletion_not_found(
  connection: api.IConnection,
): Promise<void> {
  // Create admin connection and authenticate
  const adminConnection: api.IConnection = { host: connection.host };
  const admin = await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "password123",
      display_name: RandomGenerator.name(),
      href: "http://localhost:3000",
      referrer: "http://localhost:3000",
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IDiscussionBoardAdmin.IJoin,
  });
  typia.assert(admin);
  // Attempt to delete a non-existent article with a random UUID
  await TestValidator.error(
    "should fail when deleting non-existent article",
    async () => {
      await api.functional.discussionBoard.admin.articles.erase(
        adminConnection,
        {
          articleId: typia.random<string & tags.Format<"uuid">>(),
        },
      );
    },
  );
}
