export async function test_api_system_audit_log_parameter_not_found(
  connection: api.IConnection,
): Promise<void> {
  // Create admin connection and authenticate
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IDiscussionBoardAdmin.IJoin,
  });
  // Generate valid UUIDs for non-existent audit log and parameter
  const auditLogId = typia.random<string & tags.Format<"uuid">>();
  const parameterId = typia.random<string & tags.Format<"uuid">>();
  // Test that retrieving non-existent parameter returns 404 error
  await TestValidator.httpError(
    "non-existent audit log parameter should return 404",
    404,
    async () => {
      await api.functional.discussionBoard.admin.system_audit_logs.parameters.at(
        adminConnection,
        {
          auditLogId,
          parameterId,
        },
      );
    },
  );
}
