export async function test_api_super_admin_session_retrieval_success(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create super admin connection and authenticate via join
  const superAdminConnection: api.IConnection = { host: connection.host };
  const authorized = await authorize_super_admin_join(superAdminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IDiscussionBoardSuperAdmin.IJoin,
  });
  typia.assert(authorized);
  // The join function already updated superAdminConnection.headers.Authorization
  // 2. Retrieve a session using a random session ID (simulation will succeed)
  const sessionId = typia.random<string & tags.Format<"uuid">>();
  const session =
    await api.functional.discussionBoard.superAdmin.super_admins.sessions.at(
      superAdminConnection,
      { sessionId },
    );
  typia.assert(session);
  // 3. Validate session id matches request (business logic)
  TestValidator.equals("session id matches", session.id, sessionId);
}
