export async function test_api_content_moderation_queue_assignment_update(
  connection: api.IConnection,
): Promise<void> {
  // Create super administrator connection and authenticate
  const superAdminConnection: api.IConnection = { host: connection.host };
  await authorize_super_admin_join(superAdminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      privilege_level: "super_admin",
    } satisfies IDiscussionBoardSuperAdmin.IJoin,
  });
  // Create user connection and authenticate
  const userConnection: api.IConnection = { host: connection.host };
  await authorize_user_join(userConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      bio: RandomGenerator.paragraph({ sentences: 2 }),
    } satisfies IDiscussionBoardUser.IJoin,
  });
  // Create a content flag to generate moderation queue entry
  const contentFlag =
    await generate_random_discussion_board_user_content_flags_create(
      userConnection,
      {
        body: {
          flag_reason: RandomGenerator.paragraph({ sentences: 1 }),
        } satisfies IDiscussionBoardContentFlag.ICreate,
      },
    );
  typia.assert(contentFlag);
  // Since moderation queue creation endpoint is not available, test the update endpoint
  // with a random queueId to verify super admin permissions and endpoint functionality
  const randomQueueId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.error(
    "super admin should have permission but queue may not exist",
    async () => {
      await api.functional.discussionBoard.superAdmin.content_flags.moderation_queues.putByContentflagidAndQueueid(
        superAdminConnection,
        {
          contentFlagId: contentFlag.id,
          queueId: randomQueueId,
          body: {
            assigned_admin_id: typia.random<string & tags.Format<"uuid">>(),
          } satisfies IDiscussionBoardContentModerationQueue.IUpdate,
        },
      );
    },
  );
}
