import { authorize_super_admin_join } from "../../../authorize/authorize_super_admin_join";
import { authorize_super_admin_login } from "../../../authorize/authorize_super_admin_login";
import { authorize_super_admin_refresh } from "../../../authorize/authorize_super_admin_refresh";

export async function test_api_administrator_assignment_deletion_non_existent(
  connection: api.IConnection,
): Promise<void> {
  // Create super administrator connection
  const superAdminConnection: api.IConnection = { host: connection.host };
  // Authenticate as super administrator using the join utility function
  const authResult = await authorize_super_admin_join(superAdminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IDiscussionBoardSuperAdmin.IJoin,
  });
  typia.assert(authResult);
  // Generate a random UUID that doesn't exist
  const nonExistentAssignmentId = typia.random<string & tags.Format<"uuid">>();
  // Attempt to delete non-existent assignment and verify error
  await TestValidator.error(
    "should reject non-existent assignment deletion",
    async () => {
      await api.functional.discussionBoard.superAdmin.administrator_assignments.erase(
        superAdminConnection,
        {
          assignmentId: nonExistentAssignmentId,
        },
      );
    },
  );
}
