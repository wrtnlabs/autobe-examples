export async function test_api_article_draft_retrieval_superadmin_success(
  connection: api.IConnection,
): Promise<void> {
  // Authenticate as super administrator
  const superAdminConnection: api.IConnection = { host: connection.host };
  const authResult = await authorize_super_admin_join(superAdminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IDiscussionBoardSuperAdmin.IJoin,
  });
  typia.assert(authResult);
  // Create a draft ID by generating a random UUID
  const draftId = typia.random<string & tags.Format<"uuid">>();
  // Retrieve the article draft using the authenticated super admin connection
  const draft =
    await api.functional.discussionBoard.superAdmin.articles_drafts.at(
      superAdminConnection,
      { draftId },
    );
  typia.assert(draft);
  // Validate business logic: retrieved draft ID matches requested ID
  TestValidator.equals(
    "retrieved draft ID matches requested ID",
    draft.id,
    draftId,
  );
}
