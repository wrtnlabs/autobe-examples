export async function test_api_system_notification_deletion_by_admin(
  connection: api.IConnection,
): Promise<void> {
  // Create admin connection and authenticate
  const adminConnection: api.IConnection = { host: connection.host };
  const adminAuth = await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IDiscussionBoardAdmin.IJoin,
  });
  typia.assert(adminAuth);
  // Create a system notification to be deleted
  const notification =
    await generate_random_discussion_board_admin_system_notifications_create(
      adminConnection,
      {
        body: {
          title: RandomGenerator.paragraph({ sentences: 2 }),
          content: RandomGenerator.content({ paragraphs: 1 }),
          notification_type: "announcement",
          status: "pending",
          priority: "normal",
        } satisfies IDiscussionBoardSystemNotification.ICreate,
      },
    );
  typia.assert(notification);
  // Execute deletion operation - this should complete successfully
  await api.functional.discussionBoard.admin.system_notifications.erase(
    adminConnection,
    {
      notificationId: notification.id,
    },
  );
  // Note: Without a GET endpoint to verify deletion, we rely on the successful
  // execution of the deletion operation as validation that the workflow functions correctly.
  // The scenario's requirement to verify the notification no longer exists and
  // cascading deletion cannot be implemented with the available API endpoints.
}
