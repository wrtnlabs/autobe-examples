export async function test_api_system_configuration_retrieval_not_found(
  connection: api.IConnection,
): Promise<void> {
  // Create super admin connection
  const superAdminConnection: api.IConnection = { host: connection.host };
  await authorize_super_admin_join(superAdminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IDiscussionBoardSuperAdmin.IJoin,
  });
  // Attempt to retrieve non-existent system configuration
  const nonExistentConfigId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.error("retrieve non-existent configuration", async () => {
    await api.functional.discussionBoard.superAdmin.system_configurations.at(
      superAdminConnection,
      {
        configId: nonExistentConfigId,
      },
    );
  });
}
