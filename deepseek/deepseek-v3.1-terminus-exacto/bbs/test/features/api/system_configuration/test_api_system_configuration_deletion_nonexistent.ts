export async function test_api_system_configuration_deletion_nonexistent(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as super administrator
  const superAdminConnection: api.IConnection = { host: connection.host };
  await authorize_super_admin_join(superAdminConnection, {});
  // 2. Attempt to delete a non-existent configuration
  const nonExistentId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.httpError(
    "should return not found error for non-existent configuration",
    404,
    async () => {
      await api.functional.discussionBoard.superAdmin.system_configurations.erase(
        superAdminConnection,
        { configurationId: nonExistentId },
      );
    },
  );
}
