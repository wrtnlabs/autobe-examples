/**
 * Test the successful creation of a moderation queue assignment by a super administrator.
 * Validates that a new assignment can be created linking an existing moderation queue entry
 * with an active administrator, including proper timestamps and relationship data.
 */
export async function test_api_moderation_queue_assignment_creation(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create and authenticate as a user
  const userConnection: api.IConnection = { host: connection.host };
  const userAuth = await authorize_user_join(userConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      bio: RandomGenerator.paragraph({ sentences: 2 }),
    } satisfies IDiscussionBoardUser.IJoin,
  });
  typia.assert(userAuth);
  // 2. Create a content flag to generate a moderation queue entry
  const contentFlag =
    await generate_random_discussion_board_user_content_flags_create(
      userConnection,
      {
        body: {
          flag_reason: RandomGenerator.paragraph({ sentences: 3 }),
        } satisfies IDiscussionBoardContentFlag.ICreate,
      },
    );
  typia.assert(contentFlag);
  // 3. Create and authenticate as an administrator
  const adminConnection: api.IConnection = { host: connection.host };
  const adminAuth = await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IDiscussionBoardAdmin.IJoin,
  });
  typia.assert(adminAuth);
  // 4. Authenticate as super administrator
  const superAdminConnection: api.IConnection = { host: connection.host };
  const superAdminAuth = await authorize_super_admin_join(
    superAdminConnection,
    {
      body: {
        email: typia.random<string & tags.Format<"email">>(),
        password: typia.random<string & tags.Format<"password">>(),
        privilege_level: "super_admin",
      } satisfies IDiscussionBoardSuperAdmin.IJoin,
    },
  );
  typia.assert(superAdminAuth);
  // 5. Create the moderation queue assignment
  const assignment =
    await generate_random_discussion_board_super_admin_moderation_queues_assignments_create(
      superAdminConnection,
      {
        body: {
          discussion_board_content_moderation_queue_id: contentFlag.id,
          assigned_admin_id: adminAuth.id,
        } satisfies IDiscussionBoardContentModerationQueueAssignment.ICreate,
      },
    );
  typia.assert(assignment);
  // 6. Validate assignment properties
  TestValidator.predicate(
    "assignment has valid UUID format",
    /^[0-9a-f-]{36}$/i.test(assignment.id),
  );
  TestValidator.predicate(
    "assigned_at is set to current time",
    assignment.assigned_at !== null,
  );
  TestValidator.equals(
    "completed_at is null for new assignment",
    assignment.completed_at,
    null,
  );
  TestValidator.equals(
    "content flag ID matches",
    assignment.contentModerationQueue.content_flag_id,
    contentFlag.id,
  );
  TestValidator.equals(
    "admin ID matches",
    assignment.assignedAdmin.id,
    adminAuth.id,
  );
  TestValidator.predicate(
    "created_at timestamp is valid",
    assignment.created_at !== null,
  );
  TestValidator.predicate(
    "updated_at timestamp is valid",
    assignment.updated_at !== null,
  );
}
