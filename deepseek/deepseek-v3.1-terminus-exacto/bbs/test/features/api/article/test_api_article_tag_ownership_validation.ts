export async function test_api_article_tag_ownership_validation(
  connection: api.IConnection,
): Promise<void> {
  // Create member A connection and register
  const memberAConnection: api.IConnection = { host: connection.host };
  const memberA = await authorize_member_join(memberAConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      bio: RandomGenerator.paragraph({ sentences: 2 }),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IDiscussionBoardMember.IJoin,
  });
  typia.assert(memberA);
  // Create member B connection and register
  const memberBConnection: api.IConnection = { host: connection.host };
  const memberB = await authorize_member_join(memberBConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      bio: RandomGenerator.paragraph({ sentences: 2 }),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IDiscussionBoardMember.IJoin,
  });
  typia.assert(memberB);
  // Member A creates an article
  const article = await generate_random_discussion_board_member_articles_create(
    memberAConnection,
    {
      body: {
        title: RandomGenerator.paragraph({ sentences: 1 }),
        body: RandomGenerator.content({ paragraphs: 2 }),
        discussion_board_section_id: typia.random<
          string & tags.Format<"uuid">
        >(),
      } satisfies IDiscussionBoardArticle.ICreate,
    },
  );
  typia.assert(article);
  // Member B attempts to tag member A's article - should fail
  await TestValidator.error(
    "member B cannot tag member A's article",
    async () => {
      await generate_random_discussion_board_member_articles_tags_create(
        memberBConnection,
        {
          body: {
            discussion_board_article_id: article.id,
          } satisfies IDiscussionBoardArticleTag.ICreate,
        },
      );
    },
  );
  // Member A tags their own article - should succeed
  const tag =
    await generate_random_discussion_board_member_articles_tags_create(
      memberAConnection,
      {
        body: {
          discussion_board_article_id: article.id,
        } satisfies IDiscussionBoardArticleTag.ICreate,
      },
    );
  typia.assert(tag);
  // Validate tag association
  TestValidator.equals(
    "tag belongs to correct article",
    tag.article.id,
    article.id,
  );
}
