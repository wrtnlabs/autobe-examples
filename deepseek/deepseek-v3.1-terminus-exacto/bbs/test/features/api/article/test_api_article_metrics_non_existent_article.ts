export async function test_api_article_metrics_non_existent_article(
  connection: api.IConnection,
): Promise<void> {
  // Create admin connection and authenticate
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IDiscussionBoardAdmin.IJoin,
  });
  // Generate a valid UUID that doesn't correspond to any existing article
  const nonExistentArticleId = typia.random<string & tags.Format<"uuid">>();
  // Attempt to retrieve metrics for non-existent article and validate 404 error
  await TestValidator.httpError(
    "metrics for non-existent article should return 404",
    404,
    async () => {
      await api.functional.discussionBoard.admin.articles.metrics.at(
        adminConnection,
        {
          articleId: nonExistentArticleId,
        },
      );
    },
  );
}
