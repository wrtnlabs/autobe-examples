export async function test_api_article_file_download_unauthorized_user(
  connection: api.IConnection,
): Promise<void> {
  // Create first user account
  const firstUserConnection: api.IConnection = { host: connection.host };
  const firstUser = await authorize_user_join(firstUserConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
    } satisfies IDiscussionBoardUser.IJoin,
  });
  typia.assert(firstUser);
  // Create article with first user
  const article = await generate_random_discussion_board_user_articles_create(
    firstUserConnection,
    {},
  );
  typia.assert(article);
  // Create second user account
  const secondUserConnection: api.IConnection = { host: connection.host };
  const secondUser = await authorize_user_join(secondUserConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
    } satisfies IDiscussionBoardUser.IJoin,
  });
  typia.assert(secondUser);
  // Attempt to download file with second user (should fail authorization)
  const fileId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.error("unauthorized file download", async () => {
    await api.functional.discussionBoard.user.articles.files.at(
      secondUserConnection,
      {
        articleId: article.id,
        fileId: fileId,
      },
    );
  });
}
