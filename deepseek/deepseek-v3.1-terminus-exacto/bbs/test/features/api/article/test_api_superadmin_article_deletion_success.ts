export async function test_api_superadmin_article_deletion_success(
  connection: api.IConnection,
): Promise<void> {
  // Create super admin connection and authenticate
  const superAdminConnection: api.IConnection = { host: connection.host };
  const superAdmin = await authorize_super_admin_join(superAdminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "superadmin_password123",
      href: "http://localhost:3000",
      referrer: "http://localhost:3000",
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IDiscussionBoardSuperAdmin.IJoin,
  });
  typia.assert(superAdmin);
  // Create an article as the super admin
  const article =
    await api.functional.discussionBoard.superAdmin.articles.create(
      superAdminConnection,
      {
        body: {
          title: RandomGenerator.paragraph({ sentences: 2 }),
          content: RandomGenerator.content({ paragraphs: 1 }),
          discussion_board_section_id: typia.random<
            string & tags.Format<"uuid">
          >(),
        } satisfies IDiscussionBoardArticle.ICreate,
      },
    );
  typia.assert(article);
  // Delete the article
  await api.functional.discussionBoard.superAdmin.articles.erase(
    superAdminConnection,
    {
      articleId: article.id,
    },
  );
  // Verify deletion by attempting to access the deleted article
  await TestValidator.error(
    "deleted article should not be accessible",
    async () => {
      await api.functional.discussionBoard.superAdmin.articles.erase(
        superAdminConnection,
        {
          articleId: article.id,
        },
      );
    },
  );
}
