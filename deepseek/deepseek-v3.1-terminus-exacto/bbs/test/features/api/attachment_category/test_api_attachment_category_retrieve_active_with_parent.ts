export async function test_api_attachment_category_retrieve_active_with_parent(
  connection: api.IConnection,
): Promise<void> {
  // Create super admin connection
  const superAdminConnection: api.IConnection = { host: connection.host };
  // Authenticate as super admin using join endpoint
  const authResult = await authorize_super_admin_join(superAdminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IDiscussionBoardSuperAdmin.IJoin,
  });
  typia.assert(authResult);
  // Retrieve attachment category details
  const categoryId = typia.random<string & tags.Format<"uuid">>();
  const category =
    await api.functional.discussionBoard.superAdmin.attachment_categories.at(
      superAdminConnection,
      { categoryId },
    );
  typia.assert(category);
  // Validate business logic: category is active
  TestValidator.predicate("category is active", category.isActive);
  // Validate hierarchical structure if parent exists
  if (category.parent !== null && category.parent !== undefined) {
    TestValidator.predicate("parent category exists", category.parent !== null);
    // Additional business logic validation can be added here if needed
  }
}
