export async function test_api_api_rate_limit_deletion_nonexistent(
  connection: api.IConnection,
): Promise<void> {
  // Create super administrator connection
  const superAdminConnection: api.IConnection = { host: connection.host };
  // Authenticate as super administrator
  await authorize_super_admin_join(superAdminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      privilege_level: "super_admin",
    } satisfies IDiscussionBoardSuperAdmin.IJoin,
  });
  // Generate a valid UUID that doesn't correspond to any existing rate limit
  const nonExistentRateLimitId = typia.random<string & tags.Format<"uuid">>();
  // Attempt to delete non-existent rate limit and expect error
  await TestValidator.error("delete non-existent rate limit", async () => {
    await api.functional.discussionBoard.superAdmin.api_rate_limits.erase(
      superAdminConnection,
      {
        rateLimitId: nonExistentRateLimitId,
      },
    );
  });
}
