export async function test_api_system_metadata_deletion_authorization_failure(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin setup - create admin account using SDK since no utility function exists
  const adminConnection: api.IConnection = { host: connection.host };
  const adminCredentials = {
    email: typia.random<string & tags.Format<"email">>(),
    password: RandomGenerator.alphaNumeric(16),
  } satisfies IDiscussionBoardAdmin.IJoin;
  await api.functional.discussionBoard.auth.admin.join(adminConnection, {
    body: adminCredentials,
  });
  // 2. Member setup - create regular member account using available utility function
  const memberConnection: api.IConnection = { host: connection.host };
  await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      bio: RandomGenerator.paragraph({ sentences: 2 }),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    },
  });
  // 3. Attempt to delete system metadata using non-admin (member) credentials
  // This should fail with 403 Forbidden authorization error
  await TestValidator.httpError(
    "non-admin cannot delete system metadata",
    403,
    async () => {
      await api.functional.discussionBoard.admin.system_metadata.erase(
        memberConnection,
        {
          metadataId: typia.random<string & tags.Format<"uuid">>(),
        },
      );
    },
  );
}
