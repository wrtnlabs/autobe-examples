export async function test_api_user_dashboard_empty_platform(
  connection: api.IConnection,
): Promise<void> {
  // Create user connection and register a new user
  const userConnection: api.IConnection = { host: connection.host };
  await authorize_user_join(userConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      bio: RandomGenerator.paragraph({ sentences: 2 }),
    } satisfies IDiscussionBoardUser.IJoin,
  });
  // Access the dashboard endpoint
  const dashboard =
    await api.functional.discussionBoard.user.dashboard.at(userConnection);
  typia.assert(dashboard);
  // The dashboard response uses IDiscussionBoardSuperAdmin type which represents
  // super admin account information, not platform statistics. Based on the response
  // type definition, we validate the basic account structure exists properly.
  TestValidator.predicate(
    "dashboard provides valid super admin account information",
    dashboard.id.length > 0 && dashboard.email.length > 0,
  );
}
