export async function test_api_promotion_request_deletion_unauthorized(
  connection: api.IConnection,
): Promise<void> {
  // Create super admin connection and authenticate
  const superAdminConnection: api.IConnection = { host: connection.host };
  await authorize_super_admin_join(superAdminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: "http://localhost:3000",
      referrer: "http://localhost:3000",
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IDiscussionBoardSuperAdmin.IJoin,
  });
  // Create first regular user that will submit promotion request
  const userConnection1: api.IConnection = { host: connection.host };
  const user1 = await authorize_user_join(userConnection1, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
    } satisfies IDiscussionBoardUser.IJoin,
  });
  // Submit promotion request as first user
  const promotionRequest =
    await generate_random_discussion_board_user_promotion_requests_create(
      userConnection1,
      {
        body: {
          reason: RandomGenerator.paragraph({ sentences: 3 }),
        } satisfies IDiscussionBoardAdministratorPromotionApproval.ICreate,
      },
    );
  typia.assert(promotionRequest);
  // Create second regular user that will attempt unauthorized deletion
  const userConnection2: api.IConnection = { host: connection.host };
  const user2 = await authorize_user_join(userConnection2, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
    } satisfies IDiscussionBoardUser.IJoin,
  });
  // Attempt unauthorized deletion as second user
  await TestValidator.error(
    "regular user cannot delete promotion request",
    async () => {
      await api.functional.discussionBoard.superAdmin.promotion_requests.erase(
        userConnection2,
        {
          requestId: promotionRequest.id,
        },
      );
    },
  );
}
