export async function test_api_promotion_request_deletion_success(
  connection: api.IConnection,
): Promise<void> {
  // Create a user who will submit the promotion request
  const userConnection: api.IConnection = { host: connection.host };
  const user = await authorize_user_join(userConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
    },
  });
  typia.assert(user);
  // User submits promotion request using utility function
  const promotionRequest =
    await generate_random_discussion_board_user_promotion_requests_create(
      userConnection,
      {
        body: {
          reason: RandomGenerator.paragraph({
            sentences: 3,
            wordMin: 20,
            wordMax: 30,
          }),
        },
      },
    );
  typia.assert(promotionRequest);
  // Create and authenticate as super administrator
  const superAdminConnection: api.IConnection = { host: connection.host };
  const superAdmin = await authorize_super_admin_join(superAdminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: "http://localhost:3000",
      referrer: "http://localhost:3000/admin",
      ip: "127.0.0.1",
    },
  });
  typia.assert(superAdmin);
  // Super admin deletes the promotion request
  await api.functional.discussionBoard.superAdmin.promotion_requests.erase(
    superAdminConnection,
    {
      requestId: promotionRequest.id,
    },
  );
  // The deletion should complete successfully (void return indicates success)
  // No additional validation needed as the erase endpoint returns void on success
}
