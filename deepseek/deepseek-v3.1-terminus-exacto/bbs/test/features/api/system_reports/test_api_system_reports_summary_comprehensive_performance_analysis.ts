export async function test_api_system_reports_summary_comprehensive_performance_analysis(
  connection: api.IConnection,
): Promise<void> {
  // Create admin connection and authenticate
  const adminConnection: api.IConnection = { host: connection.host };
  const authorizedAdmin = await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IDiscussionBoardAdmin.IJoin,
  });
  // Update admin connection with authorization token
  adminConnection.headers = {
    Authorization: authorizedAdmin.token.access,
  };
  // Call system reports summary endpoint without filters to get comprehensive data
  const summary =
    await api.functional.discussionBoard.admin.system.reports.summary.search(
      adminConnection,
      {
        body: {} satisfies IDiscussionBoardAuditLog.IRequest,
      },
    );
  typia.assert(summary);
  // Validate the audit log response contains comprehensive system performance data
  TestValidator.predicate(
    "has valid audit log structure",
    summary.id !== undefined &&
      summary.action_type !== undefined &&
      summary.description !== undefined &&
      summary.created_at !== undefined &&
      summary.updated_at !== undefined,
  );
}
