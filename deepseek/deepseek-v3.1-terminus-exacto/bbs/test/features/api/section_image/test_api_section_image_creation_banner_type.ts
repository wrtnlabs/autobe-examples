export async function test_api_section_image_creation_banner_type(
  connection: api.IConnection,
): Promise<void> {
  // Create admin connection and authenticate
  const adminConnection: api.IConnection = { host: connection.host };
  const admin = await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IDiscussionBoardAdmin.IJoin,
  });
  typia.assert(admin);
  // Create a section first
  const section = await generate_random_discussion_board_admin_sections_create(
    adminConnection,
    {
      body: {
        name: RandomGenerator.paragraph({ sentences: 2 }),
        description: RandomGenerator.paragraph({ sentences: 3 }),
        status: "active",
        display_order: typia.random<
          number & tags.Type<"int32"> & tags.Minimum<1>
        >(),
      } satisfies IDiscussionBoardSection.ICreate,
    },
  );
  typia.assert(section);
  // Create banner image for the section
  const image =
    await generate_random_discussion_board_admin_sections_images_create(
      adminConnection,
      {
        params: { sectionId: section.id },
        body: {
          filename: "banner-image.jpg",
          mime_type: "image/jpeg",
          file_size: typia.random<
            number &
              tags.Type<"int32"> &
              tags.Minimum<1000> &
              tags.Maximum<5000000>
          >(),
          width: typia.random<
            number & tags.Type<"int32"> & tags.Minimum<800> & tags.Maximum<1920>
          >(),
          height: typia.random<
            number & tags.Type<"int32"> & tags.Minimum<200> & tags.Maximum<600>
          >(),
          image_type: "banner",
          storage_path: "/images/sections/" + section.id + "/banner.jpg",
          alt_text: "Section banner image for " + section.name,
        } satisfies IDiscussionBoardSectionImage.ICreate,
      },
    );
  typia.assert(image);
  // Validate business logic (not type validation after typia.assert)
  TestValidator.equals("image type is banner", image.image_type, "banner");
  TestValidator.equals(
    "mime type is image/jpeg",
    image.mime_type,
    "image/jpeg",
  );
  TestValidator.predicate("filename is provided", image.filename.length > 0);
  TestValidator.predicate(
    "storage path is valid",
    image.storage_path.length > 0,
  );
}
