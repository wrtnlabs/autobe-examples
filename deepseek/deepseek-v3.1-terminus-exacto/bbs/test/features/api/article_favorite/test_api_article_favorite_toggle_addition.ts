/**
 * Test that an administrator can successfully add an article to their favorites
 * by toggling favorite status from false to true. Authenticate as admin, create
 * a test article to serve as the target for favorite operations, then call the
 * favorite toggle endpoint. Verify that the response indicates favorite status
 * is now true (favorited=true). Test should confirm proper state transition and
 * relationship creation in the discussion_board_article_favorites table.
 */
export async function test_api_article_favorite_toggle_addition(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin setup and authentication
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IDiscussionBoardAdmin.IJoin,
  });
  // 2. Create a test article for favorite operations
  const article = await generate_random_discussion_board_admin_articles_create(
    adminConnection,
    {
      body: {
        title: RandomGenerator.paragraph({ sentences: 2 }),
        content: RandomGenerator.paragraph({ sentences: 3 }),
        discussion_board_section_id: typia.random<
          string & tags.Format<"uuid">
        >(),
      } satisfies IDiscussionBoardArticle.ICreate,
    },
  );
  typia.assert(article);
  // 3. Toggle favorite status (first call should add to favorites)
  const favoriteStatus =
    await api.functional.discussionBoard.admin.articles.favorites.toggle(
      adminConnection,
      {
        articleId: article.id,
      },
    );
  typia.assert(favoriteStatus);
  // 4. Validate that the article is now favorited
  TestValidator.equals(
    "article should be added to favorites",
    favoriteStatus.favorited,
    true,
  );
}
