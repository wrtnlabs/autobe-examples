export async function test_api_section_administration_super_admin_assignment(
  connection: api.IConnection,
): Promise<void> {
  // Create admin account and authenticate
  const adminConnection: api.IConnection = { host: connection.host };
  const adminAuth = await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IDiscussionBoardAdmin.IJoin,
  });
  typia.assert(adminAuth);
  // Create section using admin account
  const section = await api.functional.discussionBoard.admin.sections.create(
    adminConnection,
    {
      body: {
        name: RandomGenerator.paragraph({ sentences: 2 }),
        description: RandomGenerator.paragraph({ sentences: 3 }),
        status: "active",
        display_order: typia.random<
          number & tags.Type<"int32"> & tags.Minimum<1> & tags.Maximum<100>
        >(),
      } satisfies IDiscussionBoardSection.ICreate,
    },
  );
  typia.assert(section);
  // Create super admin account and authenticate
  const superAdminConnection: api.IConnection = { host: connection.host };
  const superAdminAuth = await authorize_super_admin_join(
    superAdminConnection,
    {
      body: {
        email: typia.random<string & tags.Format<"email">>(),
        password: RandomGenerator.alphaNumeric(16),
        href: typia.random<string & tags.Format<"uri">>(),
        referrer: typia.random<string & tags.Format<"uri">>(),
        ip: typia.random<string & tags.Format<"ipv4">>(),
      } satisfies IDiscussionBoardSuperAdmin.IJoin,
    },
  );
  typia.assert(superAdminAuth);
  // Assign super admin to the section
  const assignment =
    await api.functional.discussionBoard.admin.sections.administrators.create(
      superAdminConnection,
      {
        sectionId: section.id,
        body: {
          permission_level: "super_admin",
          admin_id: null,
          super_admin_id: superAdminAuth.id,
        } satisfies IDiscussionBoardSuperAdmin.ICreate,
      },
    );
  typia.assert(assignment);
  // Validate assignment properties
  TestValidator.equals(
    "assignment ID should be UUID",
    typeof assignment.id,
    "string",
  );
  TestValidator.equals(
    "permission level",
    assignment.permission_level,
    "super_admin",
  );
  TestValidator.equals(
    "admin should be null for super admin assignment",
    assignment.admin,
    null,
  );
  TestValidator.notEquals(
    "super admin should not be null",
    assignment.superAdmin,
    null,
  );
  TestValidator.equals(
    "section ID should match",
    assignment.section.id,
    section.id,
  );
  TestValidator.predicate(
    "assignment date should be valid",
    () => new Date(assignment.assignment_date).getTime() > 0,
  );
  if (assignment.superAdmin !== null) {
    TestValidator.equals(
      "super admin ID matches",
      assignment.superAdmin.id,
      superAdminAuth.id,
    );
  }
}
