export async function test_api_administrator_demote_self_prevention(
  connection: api.IConnection,
): Promise<void> {
  // Create super administrator connection and authenticate
  const superAdminConnection: api.IConnection = { host: connection.host };
  const authorizedSuperAdmin = await authorize_super_admin_join(
    superAdminConnection,
    {
      body: {
        email: typia.random<string & tags.Format<"email">>(),
        password: RandomGenerator.alphaNumeric(16),
        href: typia.random<string & tags.Format<"uri">>(),
        referrer: typia.random<string & tags.Format<"uri">>(),
        ip: typia.random<string & tags.Format<"ipv4">>(),
      } satisfies IDiscussionBoardSuperAdmin.IJoin,
    },
  );
  typia.assert(authorizedSuperAdmin);
  // Attempt to demote self - this should fail with appropriate HTTP error
  await TestValidator.httpError(
    "super admin cannot demote self",
    [400, 403],
    async () => {
      await api.functional.discussionBoard.superAdmin.administrators.demote(
        superAdminConnection,
        {
          administratorId: authorizedSuperAdmin.id,
          body: {
            reason: RandomGenerator.paragraph({ sentences: 2 }),
          } satisfies IDiscussionBoardAdministratorGradeChange.ICreate,
        },
      );
    },
  );
}
