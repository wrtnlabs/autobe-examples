export async function test_api_administrator_deletion_nonexistent(
  connection: api.IConnection,
): Promise<void> {
  // Create superAdmin connection
  const superAdminConnection: api.IConnection = { host: connection.host };
  // Authenticate as superAdmin
  const authResult = await authorize_super_admin_join(superAdminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IDiscussionBoardSuperAdmin.IJoin,
  });
  typia.assert(authResult);
  // Generate non-existent administrator ID
  const nonExistentAdministratorId = typia.random<
    string & tags.Format<"uuid">
  >();
  // Attempt to delete non-existent administrator
  await TestValidator.error("delete non-existent administrator", async () => {
    await api.functional.discussionBoard.superAdmin.administrators.erase(
      superAdminConnection,
      {
        administratorId: nonExistentAdministratorId,
      },
    );
  });
}
