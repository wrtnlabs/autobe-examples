/**
 * Test unauthorized administrator promotion attempt.
 *
 * Validates that regular administrators cannot promote other administrators,
 * as this privilege is reserved exclusively for super administrators.
 * The test creates a super administrator to establish the system state,
 * then creates two regular administrators where one attempts to promote
 * the other, which should fail with proper authorization error.
 */
export async function test_api_administrator_promotion_unauthorized(
  connection: api.IConnection,
): Promise<void> {
  // Setup super administrator account
  const superAdminConnection: api.IConnection = { host: connection.host };
  await authorize_super_admin_join(superAdminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      privilege_level: "super_admin",
    } satisfies IDiscussionBoardSuperAdmin.IJoin,
  });
  // Create first regular administrator
  const regularAdmin1Connection: api.IConnection = { host: connection.host };
  const regularAdmin1 = await authorize_admin_join(regularAdmin1Connection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IDiscussionBoardAdmin.IJoin,
  });
  // Create second regular administrator (will be promotion target)
  const regularAdmin2Connection: api.IConnection = { host: connection.host };
  const regularAdmin2 = await authorize_admin_join(regularAdmin2Connection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IDiscussionBoardAdmin.IJoin,
  });
  // Attempt unauthorized promotion - regular admin trying to promote another regular admin
  await TestValidator.error(
    "regular admin cannot promote administrator",
    async () => {
      await api.functional.discussionBoard.superAdmin.promote(
        regularAdmin1Connection,
        {
          administratorId: regularAdmin2.id,
        },
      );
    },
  );
}
