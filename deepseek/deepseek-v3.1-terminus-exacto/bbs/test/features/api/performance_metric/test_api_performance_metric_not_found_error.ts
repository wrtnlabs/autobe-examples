export async function test_api_performance_metric_not_found_error(
  connection: api.IConnection,
): Promise<void> {
  // Create super administrator connection
  const superAdminConnection: api.IConnection = { host: connection.host };
  // Authenticate as super administrator using utility function
  await authorize_super_admin_join(superAdminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      privilege_level: "super_admin",
    } satisfies IDiscussionBoardSuperAdmin.IJoin,
  });
  // Generate a random UUID that does not exist in the system
  const nonExistentMetricId = typia.random<string & tags.Format<"uuid">>();
  // Attempt to retrieve non-existent performance metric and expect 404 error
  await TestValidator.httpError(
    "performance metric not found",
    404,
    async () => {
      await api.functional.discussionBoard.superAdmin.performance_metrics.at(
        superAdminConnection,
        {
          metricId: nonExistentMetricId,
        },
      );
    },
  );
}
