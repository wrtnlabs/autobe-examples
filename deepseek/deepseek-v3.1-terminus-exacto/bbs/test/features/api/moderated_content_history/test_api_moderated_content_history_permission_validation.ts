export async function test_api_moderated_content_history_permission_validation(
  connection: api.IConnection,
): Promise<void> {
  // Create a super administrator connection
  const superAdminConnection: api.IConnection = { host: connection.host };
  // Authenticate as super administrator using the authorize utility function
  await authorize_super_admin_join(superAdminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IDiscussionBoardSuperAdmin.IJoin,
  });
  // Attempt to delete a moderated content history record
  // The API specification states this should return an audit integrity error
  const historyId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.error(
    "audit integrity error on deletion attempt",
    async () => {
      await api.functional.discussionBoard.superAdmin.moderated_content_histories.erase(
        superAdminConnection,
        { historyId },
      );
    },
  );
}
