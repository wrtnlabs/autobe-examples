export async function test_api_project_task_deletion_by_project_lead(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register and authenticate a member
  const memberConnection: api.IConnection = { host: connection.host };
  await authorize_member_join(memberConnection, {});
  // 2. Create a project (member is implicitly the project lead/owner)
  const project =
    await generate_random_hrm_time_tracking_member_projects_create(
      memberConnection,
      {},
    );
  typia.assert(project);
  // 3. Create a task within the project
  const task =
    await generate_random_hrm_time_tracking_member_projects_tasks_create(
      memberConnection,
      {
        params: {
          projectId: project.id,
        },
      },
    );
  typia.assert(task);
  // 4. Delete the task (soft-delete) as project lead
  await api.functional.hrmTimeTracking.member.projects.tasks.erase(
    memberConnection,
    {
      projectId: project.id,
      taskId: task.id,
    },
  );
}
