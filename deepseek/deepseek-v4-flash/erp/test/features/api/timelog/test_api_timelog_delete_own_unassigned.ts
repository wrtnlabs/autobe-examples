export async function test_api_timelog_delete_own_unassigned(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register a new member
  const memberConnection: api.IConnection = { host: connection.host };
  await authorize_member_join(memberConnection, {});
  // 2. Create an organization
  const organization =
    await generate_random_hrm_time_tracking_member_organizations_create(
      memberConnection,
      {},
    );
  typia.assert(organization);
  // 3. Create a project within the organization
  const project =
    await generate_random_hrm_time_tracking_member_projects_create(
      memberConnection,
      {},
    );
  typia.assert(project);
  // 4. Add the authenticated employee as a project member with role 'member'
  const projectMember =
    await generate_random_hrm_time_tracking_member_projects_members_create(
      memberConnection,
      {
        params: {
          projectId: project.id,
        },
      },
    );
  typia.assert(projectMember);
  // 5. Create a timelog against the project (unassigned to any timesheet)
  const timelog =
    await generate_random_hrm_time_tracking_member_timelogs_create(
      memberConnection,
      {
        body: {
          project_id: project.id,
          billable: true,
        } satisfies DeepPartial<IHrmTimeTrackingTimelog.ICreate>,
      },
    );
  typia.assert(timelog);
  // 6. Delete the timelog (soft-delete)
  await api.functional.hrmTimeTracking.member.timelogs.erase(memberConnection, {
    timelogId: timelog.id,
  });
}
