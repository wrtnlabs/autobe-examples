export async function test_api_department_list_empty_organization(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register and authenticate a new member
  const memberConnection: api.IConnection = { host: connection.host };
  await authorize_member_join(memberConnection, {
    body: {
      password: RandomGenerator.alphaNumeric(16),
    } satisfies DeepPartial<IHrmTimeTrackingMember.IJoin>,
  });
  // 2. Create a new organization without any departments
  const organization =
    await generate_random_hrm_time_tracking_member_organizations_create(
      memberConnection,
      {},
    );
  typia.assert(organization);
  // 3. List departments with default pagination
  const departmentList: IPageIHrmTimeTrackingDepartment.ISummary =
    await api.functional.hrmTimeTracking.member.departments.index(
      memberConnection,
      {
        body: {
          page: 1 satisfies number & tags.Type<"int32"> & tags.Minimum<1>,
          limit: 10 satisfies number &
            tags.Type<"int32"> &
            tags.Minimum<1> &
            tags.Maximum<100>,
        } satisfies IHrmTimeTrackingDepartment.IRequest,
      },
    );
  typia.assert(departmentList);
  // 4. Validate empty paginated response
  TestValidator.equals("data array is empty", departmentList.data, []);
  TestValidator.equals(
    "records count is 0",
    departmentList.pagination.records,
    0,
  );
  TestValidator.equals("pages count is 0", departmentList.pagination.pages, 0);
  TestValidator.equals(
    "current page is 1",
    departmentList.pagination.current,
    1,
  );
  TestValidator.equals("limit matches", departmentList.pagination.limit, 10);
}
