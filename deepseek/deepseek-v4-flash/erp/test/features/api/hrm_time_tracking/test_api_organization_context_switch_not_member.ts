export async function test_api_organization_context_switch_not_member(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register Member A
  const memberAConnection: api.IConnection = { host: connection.host };
  const memberA = await authorize_member_join(memberAConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  typia.assert(memberA);
  // 2. Register Member B
  const memberBConnection: api.IConnection = { host: connection.host };
  const memberB = await authorize_member_join(memberBConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  typia.assert(memberB);
  // 3. As Member B: Create organization "Delta Group"
  const organization =
    await generate_random_hrm_time_tracking_member_organizations_create(
      memberBConnection,
      {
        body: {
          name: "Delta Group",
          currency: "JPY",
          timezone: "Asia/Tokyo",
          fiscal_start_month: 4,
        },
      },
    );
  typia.assert(organization);
  // 4. As Member A: Attempt to switch to Member B's organization — expect 403 Forbidden
  await TestValidator.httpError(
    "switch to organization where member has no active employee record",
    403,
    async () => {
      await api.functional.hrmTimeTracking.member.switch_organization.switchOrganization(
        memberAConnection,
        { organizationId: organization.id },
      );
    },
  );
}
