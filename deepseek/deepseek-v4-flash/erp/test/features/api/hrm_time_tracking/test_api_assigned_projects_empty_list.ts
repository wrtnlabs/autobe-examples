/**
 * Test that a member with no project memberships receives an empty paginated list.
 *
 * This test validates the edge case where the authenticated employee has not been assigned to any projects within the organization. The API must gracefully return an empty page with zero records and zero pages instead of throwing an error.
 *
 * 1. Register a new member account and obtain JWT authentication token.
 * 2. Create an organization owned by the authenticated member.
 * 3. Create one project within the organization, but deliberately do NOT assign the employee as a project member.
 * 4. Call the assigned projects endpoint with an empty request body (default pagination).
 * 5. Validate that pagination shows records: 0, pages: 0, and the data array is empty.
 */
export async function test_api_assigned_projects_empty_list(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register a new member and authenticate
  const memberConnection: api.IConnection = { host: connection.host };
  const authorized = await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    },
  });
  typia.assert(authorized);
  // 2. Create an organization
  const organization =
    await generate_random_hrm_time_tracking_member_organizations_create(
      memberConnection,
      {},
    );
  typia.assert(organization);
  // 3. Create a project - deliberately NOT assigning any employee as a project member
  const project =
    await generate_random_hrm_time_tracking_member_projects_create(
      memberConnection,
      {},
    );
  typia.assert(project);
  // 4. Call the assigned projects endpoint with empty request body
  const page =
    await api.functional.hrmTimeTracking.member.projects.assigned.index(
      memberConnection,
      {
        body: {},
      },
    );
  typia.assert(page);
  // 5. Validate empty pagination
  TestValidator.equals("records count", page.pagination.records, 0);
  TestValidator.equals("pages count", page.pagination.pages, 0);
  TestValidator.equals("data array length", page.data.length, 0);
}
