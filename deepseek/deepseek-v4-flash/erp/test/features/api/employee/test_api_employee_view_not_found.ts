export async function test_api_employee_view_not_found(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register a new member (creates authenticated session)
  const memberConnection: api.IConnection = { host: connection.host };
  const authorized = await authorize_member_join(memberConnection, {});
  typia.assert(authorized);
  // 2. Create a new organization owned by the member
  const organization =
    await generate_random_hrm_time_tracking_member_organizations_create(
      memberConnection,
      {},
    );
  typia.assert(organization);
  // 3. Switch to the organization context for scoped access
  const switched =
    await api.functional.hrmTimeTracking.member.switch_organization.switchOrganization(
      memberConnection,
      {
        organizationId: organization.id,
      },
    );
  typia.assert(switched);
  // 4. Attempt to fetch a non-existent employee by random UUID
  const nonExistentEmployeeId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.httpError(
    "should return 404 for non-existent employee UUID",
    404,
    async () => {
      await api.functional.hrmTimeTracking.employees.at(memberConnection, {
        employeeId: nonExistentEmployeeId,
      });
    },
  );
}
