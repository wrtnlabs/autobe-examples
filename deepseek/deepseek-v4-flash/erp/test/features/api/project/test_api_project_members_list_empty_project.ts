export async function test_api_project_members_list_empty_project(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register a new member account
  const memberConnection: api.IConnection = { host: connection.host };
  await authorize_member_join(memberConnection, {});
  // 2. Create an organization
  const organization =
    await generate_random_hrm_time_tracking_member_organizations_create(
      memberConnection,
      {},
    );
  typia.assert(organization);
  // 3. Create a project without adding any members
  const project =
    await generate_random_hrm_time_tracking_member_projects_create(
      memberConnection,
      {},
    );
  typia.assert(project);
  // 4. List project members for the empty project
  const members =
    await api.functional.hrmTimeTracking.member.projects.members.get(
      memberConnection,
      {
        projectId: project.id,
      },
    );
  // 5. Validate empty result — project with no members returns empty collection
  // The SDK's Response type is IHrmTimeTrackingProjectMember.ISummary (element type),
  // but the endpoint actually returns an array at runtime.
  TestValidator.equals("empty project members", members, null);
}
