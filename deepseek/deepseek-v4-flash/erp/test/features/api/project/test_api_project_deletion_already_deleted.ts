/**
 * Test that attempting to delete an already soft-deleted project returns a 404 HTTP error.
 *
 * Verifies the business rule that a project whose {@link deleted_at} timestamp has already been set cannot be deleted again. The first deletion succeeds silently, while the second attempt must be rejected with a 404 status code, indicating the resource is no longer available for modification.
 *
 * The test follows a complete workflow: member registration, organization creation, project creation, first deletion (succeeds), and second deletion (fails with 404).
 *
 * 1. Register a new member via {@link authorize_member_join}.
 * 2. Create an organization via {@link generate_random_hrm_time_tracking_member_organizations_create}.
 * 3. Create a project via {@link generate_random_hrm_time_tracking_member_projects_create}.
 * 4. Delete the project — first deletion succeeds (soft-delete).
 * 5. Attempt to delete the same project again — expects HTTP 404 error.
 */
export async function test_api_project_deletion_already_deleted(
  connection: api.IConnection,
): Promise<void> {
  // 1. Member authentication
  const memberConnection: api.IConnection = { host: connection.host };
  await authorize_member_join(memberConnection, {});
  // 2. Create organization
  const organization =
    await generate_random_hrm_time_tracking_member_organizations_create(
      memberConnection,
      {},
    );
  typia.assert(organization);
  // 3. Create project
  const project =
    await generate_random_hrm_time_tracking_member_projects_create(
      memberConnection,
      {},
    );
  typia.assert(project);
  // 4. First deletion — should succeed
  await api.functional.hrmTimeTracking.member.projects.erase(memberConnection, {
    projectId: project.id,
  });
  // 5. Second deletion — should fail with 404 (already soft-deleted)
  await TestValidator.httpError(
    "delete already deleted project",
    404,
    async () => {
      await api.functional.hrmTimeTracking.member.projects.erase(
        memberConnection,
        {
          projectId: project.id,
        },
      );
    },
  );
}
