/**
 * Test successful soft-deletion of a project that has no timelogs.
 *
 * Validates the complete workflow for deleting a project without associated time entries. An authenticated member creates an organization (becoming the Owner with project:manage permission), creates a project, and then deletes it. The deletion is soft, setting the deleted_at timestamp while preserving the project record for audit purposes.
 *
 * 1. Register a new member account via the member join endpoint.
 * 2. Create a new organization where the member becomes the Owner.
 * 3. Create a new project within the organization.
 * 4. Soft-delete the project via the erase endpoint.
 * 5. Confirm the deletion completed successfully (no error thrown).
 */
export async function test_api_project_deletion_without_timelogs(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register a new member
  const memberConnection: api.IConnection = { host: connection.host };
  const authorized = await authorize_member_join(memberConnection, {});
  typia.assert(authorized);
  // 2. Create an organization (member becomes Owner with project:manage permission)
  const organization =
    await generate_random_hrm_time_tracking_member_organizations_create(
      memberConnection,
      {},
    );
  typia.assert(organization);
  // 3. Create a project within the organization
  const project =
    await generate_random_hrm_time_tracking_member_projects_create(
      memberConnection,
      {},
    );
  typia.assert(project);
  // 4. Soft-delete the project (no timelogs exist, so deletion is permitted)
  await api.functional.hrmTimeTracking.member.projects.erase(memberConnection, {
    projectId: project.id,
  });
  // 5. Deletion completed successfully - no error thrown confirms the operation
}
