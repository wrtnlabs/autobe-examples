export async function test_api_timer_retrieve_not_found(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register a new member account
  const memberConnection: api.IConnection = { host: connection.host };
  await authorize_member_join(memberConnection, {});
  // 2. Create a new organization
  const organization: IHrmTimeTrackingOrganization =
    await generate_random_hrm_time_tracking_member_organizations_create(
      memberConnection,
      {},
    );
  typia.assert(organization);
  // 3. Switch to the organization context
  const switched: IHrmTimeTrackingOrganization =
    await api.functional.hrmTimeTracking.member._switch.organizations.change(
      memberConnection,
      {
        organizationId: organization.id,
      },
    );
  typia.assert(switched);
  // 4. Attempt to retrieve a non-existent timer
  await TestValidator.httpError(
    "404 on non-existent timer",
    404,
    async () =>
      await api.functional.hrmTimeTracking.member.timers.at(memberConnection, {
        timerId: typia.random<string & tags.Format<"uuid">>(),
      }),
  );
}
