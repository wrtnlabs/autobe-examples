export async function test_api_invitation_cancel_non_existent(
  connection: api.IConnection,
): Promise<void> {
  // Create actor-specific connection for the member
  const memberConnection: api.IConnection = { host: connection.host };
  // 1. Authenticate as a member via join
  const authorized = await authorize_member_join(memberConnection, {});
  typia.assert(authorized);
  // 2. Create an organization to establish organization context
  const organization =
    await generate_random_hrm_time_tracking_member_organizations_create(
      memberConnection,
      {},
    );
  typia.assert(organization);
  // 3. Attempt to cancel a non-existent invitation using a random UUID
  const nonExistentInvitationId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.httpError(
    "cancel non-existent invitation",
    404,
    async () => {
      await api.functional.hrmTimeTracking.member.invitations.erase(
        memberConnection,
        {
          invitationId: nonExistentInvitationId,
        },
      );
    },
  );
}
