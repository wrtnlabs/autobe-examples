export async function test_api_project_members_list_nonexistent_project(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register a new member account
  const memberConnection: api.IConnection = { host: connection.host };
  await authorize_member_join(memberConnection, {});
  // 2. Create an organization to establish the organizational context
  await generate_random_hrm_time_tracking_member_organizations_create(
    memberConnection,
    {},
  );
  // 3. Attempt to list members for a non-existent project — expect 404
  await TestValidator.httpError(
    "list members for non-existent project",
    404,
    async () => {
      await api.functional.hrmTimeTracking.member.projects.members.get(
        memberConnection,
        {
          projectId: typia.random<string & tags.Format<"uuid">>(),
        },
      );
    },
  );
}
