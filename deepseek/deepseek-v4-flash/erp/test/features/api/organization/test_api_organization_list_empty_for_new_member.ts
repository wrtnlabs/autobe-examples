export async function test_api_organization_list_empty_for_new_member(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register a new member account
  const memberConnection: api.IConnection = { host: connection.host };
  const authorized = await authorize_member_join(memberConnection, {});
  typia.assert(authorized);
  // 2. Query organizations with default parameters
  // The member has not created or joined any organization yet
  const page = await api.functional.hrmTimeTracking.member.organizations.index(
    memberConnection,
    {
      body: {},
    },
  );
  typia.assert(page);
  // 3. Verify empty paginated result
  TestValidator.equals("records count", page.pagination.records, 0);
  TestValidator.equals("pages count", page.pagination.pages, 0);
  TestValidator.equals("current page", page.pagination.current, 1);
  TestValidator.equals("page limit", page.pagination.limit, 20);
  TestValidator.equals("data array", page.data, []);
}
