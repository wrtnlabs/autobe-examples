export async function test_api_organization_file_deletion_by_owner(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register a new member
  const memberConnection: api.IConnection = { host: connection.host };
  const authorized = await authorize_member_join(memberConnection, {});
  typia.assert(authorized);
  // 2. Create an organization — the authenticated member becomes the owner
  const organization =
    await generate_random_hrm_time_tracking_member_organizations_create(
      memberConnection,
      {},
    );
  typia.assert(organization);
  // 3. Upload a non-logo file of type 'report_attachment'
  const file =
    await generate_random_hrm_time_tracking_member_organizations_files_create(
      memberConnection,
      {
        params: { organizationId: organization.id },
        body: { type: "report_attachment" },
      },
    );
  typia.assert(file);
  // 4. Delete the file via erase endpoint (the owner has full permission)
  await api.functional.hrmTimeTracking.member.organizations.files.erase(
    memberConnection,
    {
      organizationId: organization.id,
      fileId: file.id,
    },
  );
}
