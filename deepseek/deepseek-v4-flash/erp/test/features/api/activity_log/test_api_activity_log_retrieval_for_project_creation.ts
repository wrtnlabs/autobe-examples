/**
 * Test that a member with org:manage permission (Owner role) can retrieve a specific activity log entry that was automatically generated by a system action.
 *
 * Validates the full audit trail functionality — activity logs are auto-generated for significant actions and retrievable by authorized members. The test follows a natural workflow: member joins, creates an organization (becoming Owner), creates a project (triggering a 'project.created' activity log), locates the entry via filtered listing, and retrieves it by UUID.
 *
 * Special attention is given to verifying that the retrieved activity log correctly references the created organization and project, that the actor member identity matches, and that the action type code is precisely 'project.created'.
 *
 * 1. Join as a new member to obtain authentication tokens.
 * 2. Create an organization — the creating member becomes Owner with the built-in org:manage permission required for activity log access.
 * 3. Create a project within the organization — this system action automatically generates a 'project.created' activity log entry, recording the actor member, target entity (project with ID and name), and contextual details about the creation.
 * 4. List activity logs via PATCH /member/activity-logs with filtering by action type code 'project.created' to locate the auto-generated entry and capture its UUID.
 * 5. Retrieve the full activity log via GET /member/activity-logs/{activityLogId}.
 * 6. Validate the response structure: organization reference (id, name) matches the created organization, actor member reference (id, display_name, email) matches the authenticated member, activityLogType contains code='project.created' with name and category, targetEntityType='Project', targetEntityId equals the created project's UUID, targetEntityName equals the created project's display name, details is a non-null string describing the creation, createdAt is a valid ISO 8601 timestamp.
 */
export async function test_api_activity_log_retrieval_for_project_creation(
  connection: api.IConnection,
): Promise<void> {
  // 1. Join as a new member
  const memberConnection: api.IConnection = { host: connection.host };
  const authorized = await authorize_member_join(memberConnection, {});
  typia.assert(authorized);
  // 2. Create an organization (member becomes Owner with org:manage permission)
  const organization =
    await generate_random_hrm_time_tracking_member_organizations_create(
      memberConnection,
      {},
    );
  typia.assert(organization);
  // 3. Create a project within the organization
  const project =
    await generate_random_hrm_time_tracking_member_projects_create(
      memberConnection,
      {},
    );
  typia.assert(project);
  // 4. List activity logs filtered by action type code 'project.created'
  const logPage =
    await api.functional.hrmTimeTracking.member.activity_logs.index(
      memberConnection,
      {
        body: {
          activity_log_type_code: "project.created",
          page: 1,
          limit: 10,
        } satisfies IHrmTimeTrackingActivityLog.IRequest,
      },
    );
  typia.assert(logPage);
  // Find the activity log entry that matches our project
  const foundLog = logPage.data.find(
    (entry) => entry.targetEntityId === project.id,
  );
  if (foundLog === undefined) {
    throw new Error(
      "Could not find project.created activity log for the created project",
    );
  }
  // 5. Retrieve the full activity log by its UUID
  const activityLog =
    await api.functional.hrmTimeTracking.member.activity_logs.at(
      memberConnection,
      {
        activityLogId: foundLog.id,
      },
    );
  typia.assert(activityLog);
  // 6. Validate the response structure
  // Organization reference
  TestValidator.equals(
    "organization id",
    activityLog.organization.id,
    organization.id,
  );
  TestValidator.equals(
    "organization name",
    activityLog.organization.name,
    organization.name,
  );
  // Actor member reference
  TestValidator.equals("actor member id", activityLog.member.id, authorized.id);
  TestValidator.equals(
    "actor display name",
    activityLog.member.display_name,
    authorized.display_name,
  );
  TestValidator.equals(
    "actor email",
    activityLog.member.email,
    authorized.email,
  );
  // Activity log type
  TestValidator.equals(
    "action type code",
    activityLog.activityLogType.code,
    "project.created",
  );
  // Target entity
  TestValidator.equals(
    "target entity type",
    activityLog.targetEntityType,
    "Project",
  );
  TestValidator.equals(
    "target entity ID",
    activityLog.targetEntityId,
    project.id,
  );
  TestValidator.equals(
    "target entity name",
    activityLog.targetEntityName,
    project.name,
  );
  // Details should be a non-null string describing the creation
  TestValidator.predicate(
    "details is non-null string",
    () =>
      activityLog.details !== null &&
      typeof activityLog.details === "string" &&
      activityLog.details!.length > 0,
  );
  // CreatedAt timestamp must be valid ISO 8601
  TestValidator.predicate(
    "createdAt is valid ISO 8601 timestamp",
    () => !isNaN(Date.parse(activityLog.createdAt)),
  );
}
