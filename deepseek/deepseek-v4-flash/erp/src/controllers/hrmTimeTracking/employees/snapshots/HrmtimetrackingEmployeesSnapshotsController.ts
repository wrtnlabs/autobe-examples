import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmTimeTrackingEmployeeSnapshot } from "../../../../api/structures/IHrmTimeTrackingEmployeeSnapshot";
import { IPageIHrmTimeTrackingEmployeeSnapshot } from "../../../../api/structures/IPageIHrmTimeTrackingEmployeeSnapshot";
import { getHrmTimeTrackingEmployeesEmployeeIdSnapshotsSnapshotId } from "../../../../providers/getHrmTimeTrackingEmployeesEmployeeIdSnapshotsSnapshotId";
import { patchHrmTimeTrackingEmployeesEmployeeIdSnapshots } from "../../../../providers/patchHrmTimeTrackingEmployeesEmployeeIdSnapshots";
import { postHrmTimeTrackingEmployeesEmployeeIdSnapshots } from "../../../../providers/postHrmTimeTrackingEmployeesEmployeeIdSnapshots";

@Controller("/hrmTimeTracking/employees/:employeeId/snapshots")
export class HrmtimetrackingEmployeesSnapshotsController {
  /**
   * Creates a manual point-in-time snapshot of an employee's current record state.
   *
   * This operation allows authorized users to record a checkpoint capturing the employee's current status, employment type, position, role, and department assignments at a specific moment. The user provides metadata describing what changed (changed field and optional before/after values), while the system automatically captures the employee's full current state.
   *
   * Use cases include documenting a notable change, creating an audit checkpoint before a modification, or recording compliance-related observations. The snapshot preserves the employee's state at the time of creation, providing an immutable record for historical review.
   *
   * Requires `employee:manage` permission. The requesting user is recorded as the actor who created the snapshot.
   *
   * @param connection
   * @param employeeId Unique identifier (UUID) of the employee to create a snapshot for. The snapshot captures this employee's current record state at the time of creation.
   * @param body Change metadata describing the reason for this manual checkpoint snapshot. The user provides which field changed and optional before/after values. The employee's current state (status, employment_type, position, role, department) is captured automatically by the system.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification 1. Verify the authenticated user has `employee:manage` permission within the current organization context.
   * 2. Verify the employee identified by {employeeId} exists, belongs to the current organization, and is not deleted.
   * 3. Read the employee's current state: status, employment_type, position, hrm_time_tracking_role_id (current role), hrm_time_tracking_department_id (current department, may be null).
   * 4. Validate the request body: changed_field is required (string), old_value is optional (string|null), new_value is optional (string|null).
   * 5. Create the snapshot record with:
   *    - hrm_time_tracking_employee_id = employeeId (from path)
   *    - hrm_time_tracking_member_id = authenticated user's member ID
   *    - hrm_time_tracking_role_id = employee's current role ID
   *    - hrm_time_tracking_department_id = employee's current department ID (null if unassigned)
   *    - status = employee's current status
   *    - employment_type = employee's current employment type
   *    - position = employee's current position (null if unset)
   *    - changed_field = provided value
   *    - old_value = provided value (may be null)
   *    - new_value = provided value (may be null)
   * 6. Return the created snapshot with all fields populated.
   * 7. On validation failure (employee not found, no permission), return appropriate 404 or 403 errors.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @TypedParam("employeeId")
    employeeId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IHrmTimeTrackingEmployeeSnapshot.ICreate,
  ): Promise<IHrmTimeTrackingEmployeeSnapshot> {
    try {
      return await postHrmTimeTrackingEmployeesEmployeeIdSnapshots({
        employeeId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a paginated, filterable list of historical snapshots for a specific employee.
   *
   * Employee snapshots are immutable point-in-time records automatically generated by the system whenever significant changes are made to an employee record. Each snapshot captures the employee's full state at the moment of change, including the field that was modified and the before/after values. Snapshots are created automatically on events such as status transitions (active ↔ deactivated), role reassignments, employment type changes, position updates, and department reassignments.
   *
   * Results can be filtered by the type of field that was changed (changed_field) and by a date range on the snapshot creation timestamp (created_at). Results are sorted by creation date in descending order by default, showing the most recent changes first. This endpoint requires the employee:view permission.
   *
   * @param connection
   * @param employeeId The UUID of the employee whose historical snapshots to retrieve. (global scope)
   * @param body Search criteria for filtering employee snapshots. Supports filtering by changed_field, date range on created_at, and pagination parameters.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query the hrm_time_tracking_employee_snapshots table filtered by hrm_time_tracking_employee_id matching the {employeeId} path parameter. Apply permission checks: verify the requesting member belongs to the same organization as the employee identified by {employeeId}. Require employee:view permission. Support filtering by changed_field (exact match on string enum values: status, role_id, employment_type, department_id, position). Support date range filtering on created_at with from and to timestamps. Support pagination with page/limit/sort parameters. Default sort by created_at descending (most recent first). Join with hrm_time_tracking_members table to include the actor's display name in each snapshot record. Join with hrm_time_tracking_roles and hrm_time_tracking_departments tables to include denormalized role and department names from the snapshot's foreign keys.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedParam("employeeId")
    employeeId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IHrmTimeTrackingEmployeeSnapshot.IRequest,
  ): Promise<IPageIHrmTimeTrackingEmployeeSnapshot.ISummary> {
    try {
      return await patchHrmTimeTrackingEmployeesEmployeeIdSnapshots({
        employeeId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific employee snapshot record from the audit trail.
   *
   * Employee snapshots capture point-in-time states of employee records whenever significant changes occur — status transitions (active ↔ deactivated), role re-assignments, department changes, employment type updates, or position modifications. Each snapshot includes the full employee state at the moment of change (status, employment type, position) along with foreign key references to the role and department assignments at that time, plus change metadata identifying what was modified and the before/after values.
   *
   * This operation requires the `employee:view` permission within the organization context to access snapshot history.
   *
   * @param connection
   * @param employeeId UUID of the employee whose snapshot record to retrieve.
   * @param snapshotId UUID of the specific employee snapshot to retrieve.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query the hrm_time_tracking_employee_snapshots table filtering by both hrm_time_tracking_employee_id (matching employeeId parameter) and id (matching snapshotId parameter).
   *
   * Join with hrm_time_tracking_members to include the actor's display name who performed the change.
   * Join with hrm_time_tracking_roles to include the role name at the time of snapshot.
   * Optionally join with hrm_time_tracking_departments for the department name (may be null).
   *
   * Verify the requesting user has access to the organization of the employee. If the user does not have the employee:view permission, deny access. If the snapshot or employee is not found, return 404 Not Found. If the snapshot does not belong to the specified employee (hrm_time_tracking_employee_id mismatch), return 404 Not Found.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":snapshotId")
  public async at(
    @TypedParam("employeeId")
    employeeId: string & tags.Format<"uuid">,
    @TypedParam("snapshotId")
    snapshotId: string & tags.Format<"uuid">,
  ): Promise<IHrmTimeTrackingEmployeeSnapshot> {
    try {
      return await getHrmTimeTrackingEmployeesEmployeeIdSnapshotsSnapshotId({
        employeeId,
        snapshotId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
