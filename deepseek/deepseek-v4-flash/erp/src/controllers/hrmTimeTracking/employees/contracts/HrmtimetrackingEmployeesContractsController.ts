  /**
   * Creates a new employment contract for the specified employee.
   *
   * This operation records a new contract documenting the employee's compensation terms, including pay rate, pay period, working hours per week, contract duration, and optional notes. The contract becomes effective on the specified start date.
   *
   * When a new contract is created and the employee already has an active contract (end_date IS NULL), the system automatically ends the previous active contract by setting its end_date to one day before the new contract's start_date, ensuring a gapless compensation history. Only one active contract per employee is permitted at any time.
   *
   * Active contracts (end_date IS NULL) remain editable. Past contracts (end_date IS NOT NULL) become immutable historical records.
   *
   * Access control: This operation requires the employee:manage permission within the organization.
   *
   * @param connection
   * @param employeeId The UUID of the employee for whom the contract is being created. This employee must belong to the requester's organization and must not be deactivated.
   * @param body Contract creation payload containing compensation terms including pay rate, pay period type (hourly, daily, weekly, monthly), working hours per week, start date, optional end date for fixed-term contracts, and optional notes.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Create a new contract record in hrm_time_tracking_employee_contracts for the employee identified by {employeeId}.
   *
   * 1. Validate that the employee exists and is not soft-deleted (deleted_at IS NULL).
   * 2. Verify the requesting user has employee:manage permission within the employee's organization.
   * 3. Check that no existing contract has the same (hrm_time_tracking_employee_id, start_date) combination (enforced by @@unique constraint).
   * 4. If the employee has an active contract (end_date IS NULL), automatically set its end_date to one day before the new contract's start_date (start_date - 1 day). Update the previous contract's updated_at timestamp.
   * 5. Create the new contract with:
   *    - hrm_time_tracking_employee_id = {employeeId}
   *    - start_date from request body
   *    - end_date from request body (nullable)
   *    - pay_rate from request body
   *    - pay_period from request body (validate against enum: hourly, daily, weekly, monthly)
   *    - working_hours_per_week from request body
   *    - notes from request body (nullable)
   *    - id = auto-generated UUID
   *    - created_at = current timestamp
   *    - updated_at = current timestamp
   *    - deleted_at = null
   * 6. Return the created contract with all fields.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @TypedParam("employeeId")
    employeeId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IHrmTimeTrackingEmployeeContract.ICreate,
  ): Promise<IHrmTimeTrackingEmployeeContract> {
    try {
      return await postHrmTimeTrackingEmployeesEmployeeIdContracts({
        employeeId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a paginated list of employment contracts for a specific employee.
   *
   * This endpoint returns the employee's compensation history, including current and past contracts. Each contract record displays the pay rate, pay period type, working hours per week, start and end dates, and any notes. The list is ordered by start date descending by default, showing the most recent contract first.
   *
   * Access control: The employee can view their own contracts. Users with the employee:view permission within the same organization can view any employee's contracts. Requests from unauthorized users are rejected.
   *
   * Filtering is available by contract status (active contracts where end_date is null, or past contracts with a set end date), pay period type, and date ranges. Results are paginated with configurable page size and sorting options.
   *
   * @param connection
   * @param employeeId UUID of the employee whose contracts are being listed. Must reference an existing employee record within the organization. (scoped to organization)
   * @param body Search criteria for filtering employee contracts, including optional status filter (active/past), pay period filter, date range filters, and pagination parameters.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query hrm_time_tracking_employee_contracts joined with hrm_time_tracking_employees (for organization scope and authorization).
   *
   * Authorization: Verify the authenticated member's employee record exists in the same organization as the target employee. Allow access if the authenticated member is the same as the target employee OR has the employee:view permission.
   *
   * Default filtering: Exclude soft-deleted contracts (deleted_at IS NULL).
   *
   * Request body fields for filtering:
   * - status: 'active' (end_date IS NULL) or 'past' (end_date IS NOT NULL)
   * - pay_period: filter by pay period type (hourly, daily, weekly, monthly)
   * - start_date_range: filter contracts starting within a date range
   * - end_date_range: filter contracts ending within a date range
   *
   * Sort by start_date descending (most recent first) by default. Support cursor or offset-based pagination.
   *
   * Return paginated results with contract summary fields: id, start_date, end_date, pay_rate, pay_period, working_hours_per_week, notes, created_at.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
