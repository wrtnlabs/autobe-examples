import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IHrmTimeTrackingMember } from "../../../../api/structures/IHrmTimeTrackingMember";
import { postHrmTimeTrackingAuthMemberJoin } from "../../../../providers/postHrmTimeTrackingAuthMemberJoin";
import { postHrmTimeTrackingAuthMemberLogin } from "../../../../providers/postHrmTimeTrackingAuthMemberLogin";
import { postHrmTimeTrackingAuthMemberRefresh } from "../../../../providers/postHrmTimeTrackingAuthMemberRefresh";

@Controller("/hrmTimeTracking/auth/member")
export class HrmtimetrackingAuthMemberController {
  /**
   * Register a new user account on the platform.
   *
   * Creates a new member account using the provided email address and password. The email address serves as the unique identifier across the entire platform — no two accounts can share the same email address. The display name is part of the global profile shared across all organizations the user later joins.
   *
   * Upon successful registration, the system creates an authentication session recording the client's IP address, current page URL, and HTTP referrer for audit purposes, and issues JWT access and refresh tokens. The member is then authenticated and can proceed to select or create an organization context.
   *
   * Security considerations: The password is hashed using bcrypt and never stored in plaintext. Email uniqueness is enforced at the database level via a unique constraint. Duplicate email registration attempts return a conflict error.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Credentials and profile information required for new member registration.
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Create a new member account. Validate email is not empty and contains '@'. Validate password is not empty (minimum 8 characters recommended). Check email uniqueness in hrm_time_tracking_members table — if email already exists (including soft-deleted), return 409 Conflict. Hash the password using bcrypt. Insert a new hrm_time_tracking_members record with provided email, password_hash, and display_name. Create a hrm_time_tracking_member_sessions record storing IP, href, referrer from request context. Generate JWT access token (short-lived) and refresh token (long-lived). Return tokens and member identity in the response body.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IHrmTimeTrackingMember.IJoin,
  ): Promise<IHrmTimeTrackingMember.IAuthorized> {
    try {
      return await postHrmTimeTrackingAuthMemberJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate a member using email and password credentials.
   *
   * Validates the provided email and password against stored credentials for an existing member account. On successful authentication, creates a new session recording the client IP address, current page URL, and HTTP referrer for security auditing, and returns JWT authentication tokens.
   *
   * The system returns a generic 'Invalid email or password' error for both non-existent email and incorrect password to prevent account enumeration attacks. Soft-deleted accounts (deleted_at is set) cannot log in.
   *
   * Upon successful authentication, the member receives tokens that must be included in the Authorization header of subsequent API requests to access protected features within their organization context.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Member credentials — email address and password for authentication.
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Authenticate a member using email and password. Look up member by email in hrm_time_tracking_members (exclude soft-deleted records where deleted_at IS NOT NULL). If not found, return 401 with generic 'Invalid email or password'. Compare provided password against stored password_hash using bcrypt.compare(). If mismatch, return 401 with same generic message (prevent account enumeration). Create hrm_time_tracking_member_sessions record with IP, href, referrer from request context. Generate JWT access token and refresh token. Return tokens with member identity.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IHrmTimeTrackingMember.ILogin,
  ): Promise<IHrmTimeTrackingMember.IAuthorized> {
    try {
      return await postHrmTimeTrackingAuthMemberLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh authentication tokens using a valid refresh token.
   *
   * Issues a new access token when the current one expires, using a valid refresh token obtained during a previous login or registration. This enables long-lived sessions without requiring the member to re-enter credentials periodically.
   *
   * The refresh token is validated against the stored session record — the session must not be expired (expired_at must be in the future) and the associated member account must be active (not soft-deleted).
   *
   * This operation is essential for maintaining continuous authenticated access while keeping access tokens short-lived for security. The new access token should be used for subsequent API requests until it expires.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body The refresh token previously issued during authentication, used to obtain a new access token.
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Refresh an expired or soon-to-expire access token using a valid refresh token. Extract refresh token from request body. Verify the JWT refresh token signature and check expiration. Decode the token to extract the session ID and member ID. Look up the associated hrm_time_tracking_member_sessions record. If session not found, expired (expired_at < now), or invalid, return 401. Verify the hrm_time_tracking_members record exists and is not soft-deleted (deleted_at IS NULL). Issue a new JWT access token. Optionally rotate the refresh token. Return new tokens.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IHrmTimeTrackingMember.IRefresh,
  ): Promise<IHrmTimeTrackingMember.IAuthorized> {
    try {
      return await postHrmTimeTrackingAuthMemberRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
