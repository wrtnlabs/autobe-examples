import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IHrmTimeTrackingGuest } from "../../../../api/structures/IHrmTimeTrackingGuest";
import { postHrmTimeTrackingAuthGuestJoin } from "../../../../providers/postHrmTimeTrackingAuthGuestJoin";
import { postHrmTimeTrackingAuthGuestRefresh } from "../../../../providers/postHrmTimeTrackingAuthGuestRefresh";

@Controller("/hrmTimeTracking/auth/guest")
export class HrmtimetrackingAuthGuestController {
  /**
   * Register a new user account and transition from anonymous guest to authenticated member.
   *
   * The guest submits their email address and password to create a platform account. The email serves as the unique identifier across the entire system, as enforced by the unique constraint on the hrm_time_tracking_members table. The system validates the email format (must contain an '@' symbol), ensures no duplicate account exists with the same email, and confirms the password meets minimum requirements before hashing and storing it securely using a one-way hashing algorithm.
   *
   * Upon successful validation, a permanent member record is created in hrm_time_tracking_members with the provided email and hashed password. A member session is established in hrm_time_tracking_member_sessions capturing the HTTP context at registration time — the client IP address, the current page URL (href), and the HTTP referrer (referrer) — for basic security auditing. The system issues a short-lived JWT access token (15 minutes) for authenticated API requests and a long-lived refresh token (30 days) for obtaining new access tokens without re-authentication.
   *
   * This operation is the entry point for all new users. The guest actor's anonymous device fingerprint record in hrm_time_tracking_guests is preserved for audit, while the new member identity becomes the primary actor for all subsequent interactions. Error handling follows the sign-up error specification: missing email, invalid email format, missing password, and duplicate email each produce appropriate error responses — the guest remains unauthenticated until successful registration completes.
   *
   * Security considerations: passwords are never stored in plaintext; session expiry is enforced via the non-nullable expired_at timestamp; the email serves as a platform-wide unique identifier preventing account duplication; and token signatures prevent forgery of authentication credentials.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Registration credentials containing the guest's email address and desired password for creating a new member account.
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification 1) Validate request body: email must be non-empty and contain '@' symbol; password must be non-empty. 2) Check hrm_time_tracking_members for duplicate email via unique constraint — if a member with the same email exists, return 409 Conflict with message 'This email is already registered'. 3) Hash the password using a secure one-way hashing algorithm (bcrypt, cost factor 10+). 4) Create hrm_time_tracking_member record: id (new UUID), email (trimmed/lowercased), password_hash (hashed output), display_name (default from email prefix before '@'), avatar as null, phone_number as null, created_at (now), updated_at (now), deleted_at as null. 5) Capture HTTP context: read client IP from request, current page href, and HTTP Referer header (may be null). 6) Create hrm_time_tracking_member_session record: id (new UUID), hrm_time_tracking_member_id (the new member's id), ip, href, referrer (may be empty string if null), created_at (now), expired_at (now + 30 days). 7) Generate JWT access token (15-minute expiry) containing member_id and session_id claims, and a refresh token (30-day expiry, containing session_id claim). 8) Return IHrmTimeTrackingGuest.IAuthorized with both tokens. Edge cases: empty email/email missing '@' → 400 Bad Request; empty password → 400 Bad Request; duplicate email → 409 Conflict.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IHrmTimeTrackingGuest.IJoin,
  ): Promise<IHrmTimeTrackingGuest.IAuthorized> {
    try {
      return await postHrmTimeTrackingAuthGuestJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh authentication tokens using a valid refresh token to obtain new access credentials without re-authentication.
   *
   * Users who have previously registered through the join operation can use this endpoint to obtain a fresh access token by providing their refresh token. The refresh token was originally issued during the join operation and encodes the member session identifier (session_id) within its JWT payload.
   *
   * The system validates the refresh token's cryptographic signature, confirms the referenced session record in hrm_time_tracking_member_sessions exists and has not yet expired (the expired_at timestamp must be in the future), and verifies the associated member account in hrm_time_tracking_members is still active (deleted_at is null). Upon successful validation, a new short-lived JWT access token (15 minutes) is issued, and the refresh token may be rotated for enhanced security.
   *
   * This operation supports the two-token authentication pattern: the access token (short-lived) is used for everyday API calls, while the refresh token (long-lived, 30 days) is stored securely by the client and used only to request new access tokens when the current one expires. If the refresh token itself expires or the session is revoked, the user must re-authenticate through the join flow.
   *
   * Security considerations: token signature verification prevents forgery; server-side session expiry enforcement via the expired_at column provides an additional security layer beyond token lifetime; soft-deleted member accounts cannot obtain fresh tokens; and expired sessions are rejected regardless of token validity to prevent indefinite token reuse.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body The refresh token obtained from a previous join or refresh response, used to request a new access token without re-entering credentials.
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification 1) Extract and decode the refresh token from the request body. 2) Verify the JWT signature using the server's secret key — if invalid or malformed, return 400 Bad Request with 'Invalid refresh token'. 3) Extract the session_id claim from the JWT payload. 4) Look up the corresponding hrm_time_tracking_member_session record by id. 5) If session not found, return 401 Unauthorized with 'Session not found'. 6) If session.expired_at < current timestamp, return 401 Unauthorized with 'Session expired'. 7) Extract the member_id from the JWT or from the session record, verify the corresponding hrm_time_tracking_members record exists and is not soft-deleted (deleted_at IS NULL). 8) Generate a new JWT access token (15-minute expiry) with member_id and session_id claims. 9) Optionally rotate the refresh token — issue a new refresh token (30-day expiry), updating the session's expired_at to now + 30 days. 10) Return IHrmTimeTrackingGuest.IAuthorized with new tokens. Edge cases: malformed token → 400 Bad Request; expired or invalid session → 401 Unauthorized; deleted member account → 401 Unauthorized.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IHrmTimeTrackingGuest.IRefresh,
  ): Promise<IHrmTimeTrackingGuest.IAuthorized> {
    try {
      return await postHrmTimeTrackingAuthGuestRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
