import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmTimeTrackingMemberSession } from "../../../../api/structures/IHrmTimeTrackingMemberSession";
import { IPageIHrmTimeTrackingMemberSession } from "../../../../api/structures/IPageIHrmTimeTrackingMemberSession";
import { GuestAuth } from "../../../../decorators/GuestAuth";
import { GuestPayload } from "../../../../decorators/payload/GuestPayload";
import { getHrmTimeTrackingGuestSessionsSessionId } from "../../../../providers/getHrmTimeTrackingGuestSessionsSessionId";
import { patchHrmTimeTrackingGuestSessions } from "../../../../providers/patchHrmTimeTrackingGuestSessions";

@Controller("/hrmTimeTracking/guest/sessions")
export class HrmtimetrackingGuestSessionsController {
  /**
   * List the current member's active sessions.
   *
   * Returns a paginated list of the authenticated member's active session records. Sessions represent authenticated browser/device sessions created when the member logs in. This operation enables members to review their active sessions, see which devices and browsers are connected, and monitor session metadata including IP address and creation timestamps.
   *
   * Session records are append-only — each login creates a new session entry. Expired sessions (past their expired_at timestamp) are filtered out from results. Sessions are scoped to the authenticated member automatically; cross-tenant access is prevented by design.
   *
   * @param connection
   * @param body Search criteria for filtering member sessions, including optional IP address search, date range filter on creation timestamp, sorting preferences, and pagination parameters.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor guest
     * @x-autobe-specification Query hrm_time_tracking_member_sessions table
     *   filtered by the authenticated member's ID (from JWT token).
   *
   * Filter out expired sessions where expired_at < current timestamp to show only active sessions.
   *
   * Support pagination with cursor-based or offset pagination in the IRequest body. Support sorting by created_at (default descending, newest first) and expired_at.
   *
   * Apply search filters if provided: date range filter on created_at (from, to), ip address substring search, and href/referrer substring search.
   *
   * Return IPageIHrmTimeTrackingMemberSession.ISummary with session id, ip address, href, referrer, created_at, and expired_at fields.
   *
   * No JOINs needed — this is a single-table query on the sessions table. Respect data isolation: always scope to the authenticated member's ID from the JWT token context.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @GuestAuth()
    guest: GuestPayload,
    @TypedBody()
    body: IHrmTimeTrackingMemberSession.IRequest,
  ): Promise<IPageIHrmTimeTrackingMemberSession.ISummary> {
    try {
      return await patchHrmTimeTrackingGuestSessions({
        guest,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves a single member authentication session by its unique identifier.
   *
   * Provides detailed session metadata including the client IP address at session creation, the page URL where authentication occurred, the HTTP referrer indicating the navigation source, and the session validity window defined by creation and expiration timestamps. This enables security auditing, access pattern analysis, and session lifecycle monitoring.
   *
   * Session records follow an append-only lifecycle — once created, they are never modified. Expired sessions remain in the database but are filtered out during authentication validation. Each session belongs to exactly one authenticated member, and a single member may have multiple concurrent sessions across different devices or browsers.
   *
   * Only available to authenticated members with appropriate administrative permissions.
   *
   * @param connection
   * @param sessionId Unique identifier of the member session to retrieve, in UUID format (global scope).
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor guest
     * @x-autobe-specification Query hrm_time_tracking_member_sessions table by
     *   primary key (id) with the provided sessionId UUID. Return 404 Not Found
     *   if no session exists with the given ID. The session is returned
     *   regardless of its expiration status — expired sessions can still be
     *   retrieved for audit purposes. No joins needed unless caller requires
     *   the associated member details.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @GuestAuth()
    guest: GuestPayload,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<IHrmTimeTrackingMemberSession> {
    try {
      return await getHrmTimeTrackingGuestSessionsSessionId({
        guest,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
