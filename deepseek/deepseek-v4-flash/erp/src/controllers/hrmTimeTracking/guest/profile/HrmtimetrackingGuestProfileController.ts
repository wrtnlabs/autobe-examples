import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IHrmTimeTrackingMember } from "../../../../api/structures/IHrmTimeTrackingMember";
import { GuestAuth } from "../../../../decorators/GuestAuth";
import { GuestPayload } from "../../../../decorators/payload/GuestPayload";
import { putHrmTimeTrackingGuestProfile } from "../../../../providers/putHrmTimeTrackingGuestProfile";

@Controller("/hrmTimeTracking/guest/profile")
export class HrmtimetrackingGuestProfileController {
  /**
   * Update the authenticated member's global profile.
   *
   * The global profile consists of the display name, avatar image, and phone number. These fields are shared across all organizations the member belongs to — updating a field here immediately reflects the change in every organization context.
   *
   * Only the authenticated member's own profile can be updated via this endpoint. System-managed fields (email, password, timestamps) cannot be modified through this operation.
   *
   * When the update succeeds, a user-profile-updated event is delivered to all organizations where the member has an active employee record, including back to the member themselves as confirmation.
   *
   * @param connection
   * @param body Updated global profile fields for the authenticated member. Only the fields to be changed need to be provided. display_name is required.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor guest
     * @x-autobe-specification Update the authenticated member's global profile
     *   in the hrm_time_tracking_members table.
   *
   * 1. Retrieve the authenticated member's ID from the JWT session token.
   * 2. Validate the request body:
   *    - display_name: required, must be a non-empty string. Reject with clear error if empty.
   *    - avatar: optional (nullable string), URL of the avatar image.
   *    - phone_number: optional (nullable string).
   * 3. Update the member record: set display_name, avatar, phone_number, and updated_at to current timestamp.
   * 4. Do NOT update: id, email, password_hash, created_at, deleted_at — these are system-managed.
   * 5. Return the full updated member record (IHrmTimeTrackingMember) as confirmation.
   * 6. After successful update, trigger a user-profile-updated real-time event to all organizations where the member has an active employee record. The event payload includes the member ID and the updated profile fields.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @GuestAuth()
    guest: GuestPayload,
    @TypedBody()
    body: IHrmTimeTrackingMember.IUpdate,
  ): Promise<IHrmTimeTrackingMember> {
    try {
      return await putHrmTimeTrackingGuestProfile({
        guest,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
