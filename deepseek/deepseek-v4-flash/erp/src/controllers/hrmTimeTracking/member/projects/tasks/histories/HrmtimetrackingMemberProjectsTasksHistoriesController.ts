import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmTimeTrackingTaskHistory } from "../../../../../../api/structures/IHrmTimeTrackingTaskHistory";
import { IPageIHrmTimeTrackingTaskHistory } from "../../../../../../api/structures/IPageIHrmTimeTrackingTaskHistory";
import { MemberAuth } from "../../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../../decorators/payload/MemberPayload";
import { getHrmTimeTrackingMemberProjectsProjectIdTasksTaskIdHistoriesHistoryId } from "../../../../../../providers/getHrmTimeTrackingMemberProjectsProjectIdTasksTaskIdHistoriesHistoryId";
import { patchHrmTimeTrackingMemberProjectsProjectIdTasksTaskIdHistories } from "../../../../../../providers/patchHrmTimeTrackingMemberProjectsProjectIdTasksTaskIdHistories";

@Controller(
  "/hrmTimeTracking/member/projects/:projectId/tasks/:taskId/histories",
)
export class HrmtimetrackingMemberProjectsTasksHistoriesController {
  /**
   * Retrieve a paginated, filterable list of task history entries for a specific task within a project.
   *
   * Task history entries are immutable audit trail records automatically created by the system each time a task's status changes. Each entry captures the previous status, the new status, the timestamp of the change, and the employee who performed the change. This provides a complete, chronological record of all status transitions throughout the task's lifecycle.
   *
   * This endpoint supports searching by employee who performed the change, filtering by previous and new status values, date range filtering on the change timestamp, and sorting by creation date. Results are returned in chronological order by default (most recent first).
   *
   * Only users with task viewing access to the parent project can view task history entries. The data is organization-scoped via the project's owning organization, enforcing multi-tenant data isolation.
   *
   * @param connection
   * @param projectId The UUID of the project that contains the task whose history is being queried. (global scope)
   * @param taskId The UUID of the task whose status change history entries should be retrieved. (scoped to project)
   * @param body Search criteria for filtering task history entries, including optional employee ID filter, previous/new status filters, date range on creation timestamp, sorting options, and pagination parameters.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query `hrm_time_tracking_task_histories` filtered
     *   by `hrm_time_tracking_task_id = taskId`.
   *
   * Verify accessibility:
   * - Join through `hrm_time_tracking_tasks` on `hrm_time_tracking_task_id` to confirm the task belongs to the specified project (`hrm_time_tracking_project_id = projectId`)
   * - Then join through `hrm_time_tracking_projects` on `hrm_time_tracking_project_id` to scope results to the authenticated user's current organization
   * - Enforce task visibility rules: users with project:view permission can see all tasks; project members can only see tasks in projects they are assigned to
   *
   * Apply filters from request body:
   * - `hrm_time_tracking_employee_id` (optional): filter by the employee who performed the status change
   * - `previous_status` (optional): filter by the source status of the transition
   * - `new_status` (optional): filter by the destination status of the transition
   * - `created_at` date range (optional): filter by when the status change occurred
   *
   * Apply sorting:
   * - Default sort by `created_at` descending (most recent first)
   * - Support ascending sort on `created_at` for chronological timeline view
   *
   * Apply pagination using IPage cursor-based or offset pagination pattern.
   *
   * Return summary records containing: id, created_at, previous_status, new_status, and employee information (id, display name). The summary should not include full entity data.
   *
   * No write operations are permitted — task history is immutable (append-only audit trail).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("projectId")
    projectId: string & tags.Format<"uuid">,
    @TypedParam("taskId")
    taskId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IHrmTimeTrackingTaskHistory.IRequest,
  ): Promise<IPageIHrmTimeTrackingTaskHistory.ISummary> {
    try {
      return await patchHrmTimeTrackingMemberProjectsProjectIdTasksTaskIdHistories(
        {
          member,
          projectId,
          taskId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single task history entry recording a status change in a task's lifecycle.
   *
   * Task history entries are immutable audit trail records that capture every task status transition within a project. Each entry records the previous status, new status, the employee who performed the change, and the exact timestamp. This endpoint returns a complete history record scoped within the specified task and project, providing full visibility into task lifecycle changes for accountability and auditing purposes.
   *
   * The response includes all fields of the task history record: the associated task and employee identifiers, the status transition details (previous and new status values), and creation timestamp. Since task history entries are immutable append-only records, the returned data represents a permanent historical fact that cannot be modified or deleted.
   *
   * Access is restricted to employees who are members of the parent project, or users with organization-level project:view permission.
   *
   * @param connection
   * @param projectId UUID of the project that owns the task. Scopes the lookup to the correct project context for authorization.
   * @param taskId UUID of the task whose history entry is being retrieved. The task must belong to the specified project.
   * @param historyId UUID of the task history entry to retrieve. Identifies a specific immutable status change record within the task's audit trail.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query the hrm_time_tracking_task_histories table
     *   with authorization scoping through the project hierarchy.
   *
   * 1. Verify the project exists within the user's organization context: query hrm_time_tracking_projects with id = projectId AND hrm_time_tracking_organization_id = <current_org_id> AND deleted_at IS NULL. Return 404 if not found.
   * 2. Verify the task exists within the project: query hrm_time_tracking_tasks with id = taskId AND hrm_time_tracking_project_id = projectId AND deleted_at IS NULL. Return 404 if not found.
   * 3. Verify the requesting employee has access to the project: check hrm_time_tracking_project_members for the employee's record OR check if the user has organization-level project:view permission. Return 403 if unauthorized.
   * 4. Query hrm_time_tracking_task_histories with id = historyId AND hrm_time_tracking_task_id = taskId AND deleted_at IS NULL. Return 404 if not found.
   * 5. Return the full history record including: id, hrm_time_tracking_task_id, hrm_time_tracking_employee_id, previous_status, new_status, created_at, updated_at. The deleted_at field should be null for valid records.
   * 6. No joins are required — this is a simple single-record lookup.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":historyId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("projectId")
    projectId: string & tags.Format<"uuid">,
    @TypedParam("taskId")
    taskId: string & tags.Format<"uuid">,
    @TypedParam("historyId")
    historyId: string & tags.Format<"uuid">,
  ): Promise<IHrmTimeTrackingTaskHistory> {
    try {
      return await getHrmTimeTrackingMemberProjectsProjectIdTasksTaskIdHistoriesHistoryId(
        {
          member,
          projectId,
          taskId,
          historyId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
