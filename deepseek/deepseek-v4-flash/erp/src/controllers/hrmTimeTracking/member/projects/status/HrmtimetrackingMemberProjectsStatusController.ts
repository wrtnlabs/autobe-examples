import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmTimeTrackingProject } from "../../../../../api/structures/IHrmTimeTrackingProject";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { postHrmTimeTrackingMemberProjectsProjectIdStatus } from "../../../../../providers/postHrmTimeTrackingMemberProjectsProjectIdStatus";

@Controller("/hrmTimeTracking/member/projects/:projectId/status")
export class HrmtimetrackingMemberProjectsStatusController {
  /**
   * Change the lifecycle status of a project.
   *
   * This operation allows users with `project:manage` permission to transition a project from its current status to a new status. Only active projects can have their status changed, and the valid transitions are from "active" to "archived" (project set aside but data preserved) or from "active" to "completed" (project finished).
   *
   * Archived and completed projects cannot receive new timelogs, but all existing timelogs, tasks, and project member data are preserved. Status changes are recorded in the organization's activity log for audit purposes.
   *
   * @param connection
   * @param projectId The unique identifier (UUID) of the project whose status is to be changed.
   * @param body The new status value for the project. Valid values are "archived" (move project to inactive state with data preserved) or "completed" (mark project as finished). Only active projects can transition to a new status.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Validate that the requesting user has
     *   `project:manage` permission for the organization owning the project.
   *
   * 1. Look up the project by projectId (UUID) within the user's organization context.
   * 2. Verify the project exists and is not soft-deleted (deleted_at is null).
   * 3. Validate that the project's current status is "active" — only active projects can transition.
   * 4. Validate the requested new status in the request body: must be "archived" or "completed".
   * 5. Update the project's status field and updated_at timestamp.
   * 6. Create an activity log entry recording the status change (project ID, old status, new status, actor).
   * 7. Return the updated project record.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("projectId")
    projectId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IHrmTimeTrackingProject.IUpdate,
  ): Promise<IHrmTimeTrackingProject> {
    try {
      return await postHrmTimeTrackingMemberProjectsProjectIdStatus({
        member,
        projectId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
