import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmTimeTrackingDepartmentSnapshot } from "../../../../../api/structures/IHrmTimeTrackingDepartmentSnapshot";
import { IPageIHrmTimeTrackingDepartmentSnapshot } from "../../../../../api/structures/IPageIHrmTimeTrackingDepartmentSnapshot";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { getHrmTimeTrackingMemberDepartmentsDepartmentIdSnapshotsSnapshotId } from "../../../../../providers/getHrmTimeTrackingMemberDepartmentsDepartmentIdSnapshotsSnapshotId";
import { patchHrmTimeTrackingMemberDepartmentsDepartmentIdSnapshots } from "../../../../../providers/patchHrmTimeTrackingMemberDepartmentsDepartmentIdSnapshots";

@Controller("/hrmTimeTracking/member/departments/:departmentId/snapshots")
export class HrmtimetrackingMemberDepartmentsSnapshotsController {
  /**
   * Retrieve a paginated, filterable history of department snapshots for a specific department.
   *
   * Each department snapshot is an immutable point-in-time record that captures the complete state of a department (its name, description, and parent department relationship) at the moment a change occurred. Snapshots are automatically generated by the system whenever a department is created, updated, or soft-deleted, providing a comprehensive audit trail of all department modifications over time.
   *
   * This endpoint supports filtering by the type of change that triggered the snapshot (creation, modification, or deletion), by date range to narrow results to a specific period, and by the actor who performed the change. Results are sorted by timestamp with the most recent changes first by default, and support cursor-based pagination for efficient browsing of large histories.
   *
   * Department snapshots are read-only records and cannot be created, modified, or deleted through the API. Access is available to all employees within the organization that owns the department.
   *
   * @param connection
   * @param departmentId The unique identifier (UUID) of the department whose snapshot history is being retrieved. All returned snapshots will belong to this department.
   * @param body Search, filter, and pagination criteria for browsing department snapshot history. Supports filtering by change type (created, updated, deleted), date range on the snapshot creation timestamp, and the actor who performed the change. Includes pagination parameters (page, limit) and sorting options.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query hrm_time_tracking_department_snapshots
     *   filtered by hrm_time_tracking_department_id matching the {departmentId}
     *   path parameter. Support pagination with page number and limit. Support
     *   filtering by: change_type (enum: 'created', 'updated', 'deleted'), date
     *   range on created_at (from/to), actor_member_id. Support sorting by
     *   created_at ascending or descending (default descending, most recent
     *   first). Join with hrm_time_tracking_members to resolve actor_member_id
     *   to member name/email for display purposes. Return paginated results
     *   with total count metadata. Consider that snapshots can be numerous for
     *   frequently-modified departments, so cursor-based pagination may be
     *   beneficial for large datasets. No write operations allowed — this is a
     *   read-only endpoint.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("departmentId")
    departmentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IHrmTimeTrackingDepartmentSnapshot.IRequest,
  ): Promise<IPageIHrmTimeTrackingDepartmentSnapshot.ISummary> {
    try {
      return await patchHrmTimeTrackingMemberDepartmentsDepartmentIdSnapshots({
        member,
        departmentId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific department snapshot by its ID.
   *
   * A department snapshot is an immutable point-in-time record that captures the complete state of a department (name, description, parent department) at the moment a create, update, or delete event occurred. Snapshots preserve historical department data even after the department is subsequently modified or removed, providing a full audit trail of all department changes.
   *
   * The response includes the department snapshot fields such as name, description, parent department ID, change type (created/updated/deleted), and the timestamp when the snapshot was recorded. Use this endpoint to inspect historical department states or to audit organizational changes.
   *
   * @param connection
   * @param departmentId The UUID of the department whose snapshot is being retrieved (scoped to organization).
   * @param snapshotId The UUID of the snapshot record to retrieve (global scope).
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query hrm_time_tracking_department_snapshots
     *   table by the snapshotId (id field). Verify that the snapshot belongs to
     *   the specified department by checking that
     *   hrm_time_tracking_department_id matches the departmentId path
     *   parameter. Ensure organization-scoped access by verifying the
     *   snapshot's hrm_time_tracking_organization_id is within the
     *   authenticated member's organization. Return 404 Not Found if no
     *   snapshot matches both parameters or if the snapshot belongs to a
     *   different organization. The snapshot record is immutable — no update
     *   logic required.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":snapshotId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("departmentId")
    departmentId: string & tags.Format<"uuid">,
    @TypedParam("snapshotId")
    snapshotId: string & tags.Format<"uuid">,
  ): Promise<IHrmTimeTrackingDepartmentSnapshot> {
    try {
      return await getHrmTimeTrackingMemberDepartmentsDepartmentIdSnapshotsSnapshotId(
        {
          member,
          departmentId,
          snapshotId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
