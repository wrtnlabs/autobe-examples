import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmTimeTrackingOrganization } from "../../../../../api/structures/IHrmTimeTrackingOrganization";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { getHrmTimeTrackingMemberOrganizationsOrganizationIdDeletionRequirements } from "../../../../../providers/getHrmTimeTrackingMemberOrganizationsOrganizationIdDeletionRequirements";

@Controller(
  "/hrmTimeTracking/member/organizations/:organizationId/deletion-requirements",
)
export class HrmtimetrackingMemberOrganizationsDeletion_requirementsController {
  /**
   * Retrieves the current status of all prerequisites required to delete an organization.
   *
   * An organization can only be deleted when all pending timesheets within the organization have been resolved (approved or rejected) and there are no active employee contracts (contracts with no end date). This endpoint evaluates both conditions and returns detailed status information so the organization owner can determine what actions remain before deletion can proceed.
   *
   * The response includes individual boolean flags for each requirement along with detail counts to help the owner understand the scope of pending items. Only the organization owner has access to this information.
   *
   * @param connection
   * @param organizationId UUID of the organization whose deletion prerequisites are being checked. Only the organization owner can view this information.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Retrieve the organization by organizationId.
     *   Verify the authenticated caller is the organization owner by comparing
     *   hrm_time_tracking_member_id against the authenticated member's ID. If
     *   the organization does not exist, return 404. If the caller is not the
     *   owner, return 403.
   *
   * Requirement 1 — Pending timesheets resolved:
   * Query hrm_time_tracking_timesheets joined to hrm_time_tracking_employees (filtered by hrm_time_tracking_organization_id = organizationId) where status is 'draft' or 'submitted' (unresolved states) and deleted_at IS NULL. Count results. The condition is met (true) when count is 0.
   *
   * Requirement 2 — No active contracts:
   * Query hrm_time_tracking_employee_contracts joined to hrm_time_tracking_employees (filtered by hrm_time_tracking_organization_id = organizationId) where end_date IS NULL AND deleted_at IS NULL. Count results. The condition is met (true) when count is 0.
   *
   * Return both boolean flags, detail counts for each requirement, and a combined allRequirementsMet boolean (true only when both flags are true).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("organizationId")
    organizationId: string & tags.Format<"uuid">,
  ): Promise<IHrmTimeTrackingOrganization.IDeletionRequirement> {
    try {
      return await getHrmTimeTrackingMemberOrganizationsOrganizationIdDeletionRequirements(
        {
          member,
          organizationId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
