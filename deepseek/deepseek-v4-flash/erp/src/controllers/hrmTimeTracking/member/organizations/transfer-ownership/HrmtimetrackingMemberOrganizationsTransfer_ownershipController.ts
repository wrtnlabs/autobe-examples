  /**
   * Transfers ownership of an organization from the current owner to another active employee within the same organization.
   *
   * This operation changes the organization's owner to the specified employee. The target employee must have an active employee record in the organization and will be assigned the Owner role upon successful transfer. The current owner's role is modified accordingly — they retain access as an Employee (or another role) in the organization unless they are deactivated.
   *
   * This operation is idempotent: if the target employee is already the owner, the request succeeds without changes.
   *
   * Authorization: Only the current organization owner can perform this operation. Requires the org:manage permission implicitly through ownership.
   *
   * @param connection
   * @param organizationId The unique identifier (UUID) of the organization whose ownership will be transferred.
   * @param body Specifies the target employee who will receive ownership of the organization. The employee must have an active record within the same organization.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Verify the requesting user is the current
     *   organization owner (checked via
     *   hrm_time_tracking_organizations.hrm_time_tracking_member_id matching
     *   the authenticated member).
   *
   * Look up the target employee by their UUID (hrm_time_tracking_employees.id). Verify the target employee belongs to the same organization (hrm_time_tracking_employees.hrm_time_tracking_organization_id matches the path parameter). Verify the target employee has status='active' and deleted_at IS NULL.
   *
   * Use a Prisma transaction to:
   * 1. Update the target employee's role to the 'Owner' built-in role for this organization (find hrm_time_tracking_roles where name='Owner' AND hrm_time_tracking_organization_id = organizationId AND type='built_in')
   * 2. Update the current owner's employee role to 'Manager' (or a configurable fallback role)
   * 3. Update hrm_time_tracking_organizations.hrm_time_tracking_member_id to reference the target employee's member ID
   * 4. Create an activity log entry recording the ownership transfer
   *
   * If the target employee is the current owner (self-transfer), return success without changes.
   *
   * Error cases:
   * - 403: Requesting user is not the current owner
   * - 404: Organization not found, or target employee not found in this organization
   * - 409: Target employee is deactivated
   * - 422: Target employee does not have an active employee record
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
