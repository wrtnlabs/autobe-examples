  /**
   * Replaces the entire permission set assigned to a role within an organization.
   *
   * This endpoint performs a full, atomic replacement of the role's permission set. The caller provides an array of permission codes, and the system deletes all existing role-permission mappings for the role, then inserts new mappings for each provided code. The operation is idempotent — invoking it multiple times with the same input yields the same result.
   *
   * Built-in roles (Owner, Manager, Employee) have fixed, immutable permission sets that are seeded at organization creation. Any attempt to modify a built-in role's permissions is rejected with a 403 Forbidden response. Only custom roles support configurable permission sets.
   *
   * The 9 available system permission codes are: org:manage, employee:manage, employee:view, project:manage, project:view, time:manage, time:approve, time:view_all, report:view. An empty array is permitted, creating a role with zero functional permissions — this is an explicit business requirement.
   *
   * Each organization maintains its own independent set of roles and permissions. Roles and permissions from one organization are neither visible nor applicable to any other organization.
   *
   * **Authorization** — Requires the org:manage permission within the target organization. Only the organization owner or users with org:manage permission can modify role permissions.
   *
   * @param connection
   * @param organizationId The unique identifier (UUID) of the organization that owns the role.
   * @param roleId The unique identifier (UUID) of the role whose permissions are being updated.
   * @param body The complete set of permission codes to assign to the role. Replaces all existing permissions. Each code must be one of the 9 fixed system permissions: org:manage, employee:manage, employee:view, project:manage, project:view, time:manage, time:approve, time:view_all, report:view. An empty array clears all permissions from the role, which is explicitly allowed by the system.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Replace all role-permission mappings for the given role within a single database transaction:
   *
   * 1. **Validate organization existence** — Look up the organization by organizationId. Return 404 if not found or if status is 'deleted'.
   *
   * 2. **Validate role existence and ownership** — Look up the role by roleId, verify it belongs to the specified organization (hrm_time_tracking_organization_id matches organizationId). Return 404 if not found or if deleted_at is not null (soft-deleted roles are considered deleted).
   *
   * 3. **Validate role type** — If role.type === 'built_in', return 403 Forbidden. Built-in roles (Owner, Manager, Employee) have fixed, non-modifiable permission sets.
   *
   * 4. **Validate permission codes** — Each code in the request body must be one of the 9 fixed values. Reject invalid codes with 400 Bad Request and a descriptive message identifying the invalid code.
   *
   * 5. **Deduplicate and replace atomically** — Remove duplicate codes from the input. Within a Prisma transaction: (a) Delete all existing hrm_time_tracking_role_permissions rows where hrm_time_tracking_role_id = roleId. (b) Insert new rows for each unique permission code. Each row gets a new UUID id, current timestamp for created_at and updated_at, and null for deleted_at. Allow empty array (role with zero permissions).
   *
   * 6. **Return updated role** — Return the role entity with its current set of permission codes. Fetch the role by ID, joining hrm_time_tracking_role_permissions where deleted_at IS NULL, and return the role with id, name, type, and the array of permission codes.
   *
   * 7. **Edge case — soft-deleted role** — If role.deleted_at is not null, treat as 404 (soft-deleted roles cannot be modified).
   *
   * 8. **Edge case — multiple calls** — The operation is idempotent; calling it twice with the same codes produces identical results.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
