@Controller("/hrmTimeTracking/member/organizations/:organizationId/snapshots")
export class HrmtimetrackingMemberOrganizationsSnapshotsController {
  /**
   * Creates a manual point-in-time snapshot of the organization's current state, preserving all configuration attributes and ownership information for historical reference.
   *
   * When an organization owner needs to capture the current configuration before making significant changes — such as updating settings, transferring ownership, or restructuring — this operation creates a complete archival record. The snapshot stores a denormalized copy of all organization attributes (name, description, logo, currency, timezone, fiscal start month), the owner's identity and display name, and the current status, along with the acting user and optional contextual notes.
   *
   * This supplements the system's automatic snapshots created during lifecycle events (creation, settings updates, ownership transfers, deletion), providing on-demand capture flexibility for audit and governance purposes. Snapshots are immutable once created and provide a reliable historical record for organizational accountability.
   *
   * @param connection
   * @param organizationId The target organization's unique identifier (UUID). The snapshot will capture this organization's current attributes, owner information, and status at the time of creation.
   * @param body Optional contextual details to annotate the snapshot. The remaining snapshot fields (organization attributes, owner info, status) are automatically populated from the current organization state, and the actor is resolved from the authenticated user.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification 1. Validate organization exists and is 'active' —
     *   reject with 404 if not found or status is 'deleted'. 2. Verify
     *   authorization: only the organization owner
     *   (organization.hrm_time_tracking_member_id matches authenticated user)
     *   may create manual snapshots. 3. Enforce organization data isolation —
     *   ensure the organization belongs to the authenticated user's context. 4.
     *   Read the full current state from hrm_time_tracking_organizations for
     *   the given organizationId. 5. Resolve the actor's display name from
     *   hrm_time_tracking_members (owner_display_name). 6. Construct the
     *   snapshot record: - hrm_time_tracking_organization_id: organizationId -
     *   hrm_time_tracking_member_id: authenticated user's member ID - name,
     *   description, logo_uri, currency, timezone, fiscal_start_month: from
     *   current organization - owner_member_id: from organization.owner -
     *   owner_display_name: resolved from owner's member record - status:
     *   current organization status - event_type: 'snapshot' - event_details:
     *   from request body (optional) 7. Create the snapshot record
     *   (append-only). 8. Return the created snapshot with 201 status.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("organizationId")
    organizationId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IHrmTimeTrackingOrganizationSnapshot.ICreate,
  ): Promise<IHrmTimeTrackingOrganizationSnapshot> {
    try {
      return await postHrmTimeTrackingMemberOrganizationsOrganizationIdSnapshots(
        {
          member,
          organizationId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a paginated, filterable list of organization snapshot audit trail records.
   *
   * Organization snapshots are immutable point-in-time records that capture the complete state of an organization whenever a significant lifecycle event occurs — such as creation, settings updates, ownership transfers, or deletion. Each snapshot preserves the organization's name, description, logo, currency, timezone, fiscal start month, owner identity, and status at the moment of the event, along with the actor member who triggered it and the event type classification. This table is append-only — entries are never modified or deleted, ensuring a reliable audit trail for organizational governance.
   *
   * This endpoint allows organization administrators to browse the full audit trail of changes. Results can be filtered by event type (e.g., "created", "settings_updated", "ownership_transferred", "deleted"), by date range of when snapshots were created, and by the member who performed the action. Results are sorted by creation timestamp in descending order by default, showing the most recent changes first.
   *
   * All operations are strictly scoped to the organization identified by the path parameter — data isolation is enforced across tenants, and only snapshots belonging to the specified organization are accessible.
   *
   * @param connection
   * @param organizationId The UUID of the organization whose snapshot audit trail is being queried (scoped to this organization).
   * @param body Search criteria for filtering the organization snapshot audit trail. Supports filtering by event type (e.g., 'created', 'settings_updated', 'ownership_transferred', 'deleted'), date range (created_at from/to timestamps), actor member ID, free-text search on event details, and pagination parameters (page, limit) with sorting options.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query the
     *   hrm_time_tracking_organization_snapshots table with strict organization
     *   scoping.
   *
   * 1. **Data isolation**: WHERE hrm_time_tracking_organization_id = {organizationId}. Never allow cross-organization access.
   *
   * 2. **Filters** (all optional, from requestBody):
   *    - `event_type`: exact match filter — one of 'created', 'settings_updated', 'ownership_transferred', 'deleted'
   *    - `created_at`: date range filter (from/to timestamps)
   *    - `hrm_time_tracking_member_id`: exact match against the actor member who triggered the event
   *    - Free-text search on `event_details` (LIKE/contains pattern)
   *
   * 3. **Sorting**: Default sort by created_at DESC (newest first). Support sort field and direction from request body.
   *
   * 4. **Pagination**: Support page/limit parameters from request body for cursor-based pagination.
   *
   * 5. **Response**: Return IPageIHrmTimeTrackingOrganizationSnapshot.ISummary with total count, pagination metadata, and snapshot summary records.
   *
   * 6. **Edge cases**: Append-only table — no write operations applicable. Return empty page if no snapshots exist for the organization.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("organizationId")
    organizationId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IHrmTimeTrackingOrganizationSnapshot.IRequest,
  ): Promise<IPageIHrmTimeTrackingOrganizationSnapshot.ISummary> {
    try {
      return await patchHrmTimeTrackingMemberOrganizationsOrganizationIdSnapshots(
        {
          member,
          organizationId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single organization lifecycle snapshot by its unique identifier.
   *
   * Organization snapshots are immutable point-in-time records that capture the complete organizational state at the moment a significant lifecycle event occurred. These events include organization creation, settings changes (name, description, currency, timezone, fiscal start month), ownership transfers, and organization deletion. Each snapshot preserves a full copy of all organization attributes as they were at that moment, along with the identity of the user who triggered the event and contextual details about what changed.
   *
   * The snapshot includes the organization's name, description, logo URI, currency setting, timezone, fiscal start month, the owner's member ID and display name at that time, the organization status at that moment, the event type classification, and any additional event details. This endpoint is restricted to organization members with appropriate access rights within the active organization context.
   *
   * @param connection
   * @param organizationId UUID of the organization that owns the snapshot (scoped to active organization context).
   * @param snapshotId UUID of the organization snapshot to retrieve.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query the
     *   hrm_time_tracking_organization_snapshots table filtering by the
     *   composite of organization ID and snapshot ID.
   *
   * Implementation steps:
   * 1. Validate that the requesting user belongs to the organization identified by {organizationId} (via their employee record).
   * 2. Query: SELECT * FROM hrm_time_tracking_organization_snapshots WHERE id = {snapshotId} AND hrm_time_tracking_organization_id = {organizationId}.
   * 3. If no record found, return 404 Not Found — the snapshot either does not exist or does not belong to the specified organization.
   * 4. Return the full snapshot record as the response body.
   *
   * Edge cases:
   * - The organization may be in 'deleted' status — snapshots are still accessible for audit purposes.
   * - The requesting user's employee record may be deactivated — consider whether to allow access based on business rules.
   * - The snapshot is immutable and append-only; no record locking or version conflict handling needed.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":snapshotId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("organizationId")
    organizationId: string & tags.Format<"uuid">,
    @TypedParam("snapshotId")
    snapshotId: string & tags.Format<"uuid">,
  ): Promise<IHrmTimeTrackingOrganizationSnapshot> {
    try {
      return await getHrmTimeTrackingMemberOrganizationsOrganizationIdSnapshotsSnapshotId(
        {
          member,
          organizationId,
          snapshotId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
