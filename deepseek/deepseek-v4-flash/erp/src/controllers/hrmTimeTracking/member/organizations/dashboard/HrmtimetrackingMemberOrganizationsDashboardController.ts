import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmTimeTrackingOrganizationDashboard } from "../../../../../api/structures/IHrmTimeTrackingOrganizationDashboard";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { getHrmTimeTrackingMemberOrganizationsOrganizationIdDashboard } from "../../../../../providers/getHrmTimeTrackingMemberOrganizationsOrganizationIdDashboard";

@Controller("/hrmTimeTracking/member/organizations/:organizationId/dashboard")
export class HrmtimetrackingMemberOrganizationsDashboardController {
  /**
   * Retrieve the organization dashboard overview for authorized users.
   *
   * The organization dashboard provides a high-level summary of key metrics and performance indicators for users with the `report:view` permission within the organization. This endpoint aggregates cross-entity data to give managers and administrators a quick at-a-glance view of organizational health.
   *
   * **Dashboard metrics include:**
   * - **Active employee count**: Total number of employees currently in active status within the organization.
   * - **Weekly hours logged**: Aggregate hours logged by all employees during the current work week (Monday through Sunday), calculated using the organization's configured timezone.
   * - **Pending timesheets**: Count of submitted timesheets awaiting manager approval.
   * - **Budget alerts**: Projects where actual logged hours have exceeded 80% of the budgeted hours, enabling proactive budget management.
   * - **Top performers**: The top 5 employees ranked by hours logged during the current week.
   *
   * All metrics are computed in real-time from the underlying data and are scoped strictly to the requested organization. Cross-tenant data is never included.
   *
   * @param connection
   * @param organizationId Target organization UUID. All dashboard metrics are scoped to this organization's multi-tenant boundary.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Fetch organization dashboard data scoped to the
     *   organization context.
   *
   * 1. **Active employees count**: Query `hrm_time_tracking_employees` WHERE `hrm_time_tracking_organization_id` = organizationId AND `status` = 'active' AND `deleted_at` IS NULL. Return COUNT(*).
   *
   * 2. **Total hours this week**: Calculate the current week's Monday–Sunday boundaries using the organization's `timezone` setting. Query `hrm_time_tracking_timelogs` JOIN `hrm_time_tracking_employees` WHERE employee's `hrm_time_tracking_organization_id` = organizationId AND timelog.`date` BETWEEN week_start AND week_end AND timelog.`deleted_at` IS NULL. Return SUM(`duration_minutes`) / 60.0 as total_hours.
   *
   * 3. **Pending timesheets count**: Query `hrm_time_tracking_timesheets` JOIN `hrm_time_tracking_employees` WHERE employee's `hrm_time_tracking_organization_id` = organizationId AND timesheet.`status` = 'submitted' AND timesheet.`deleted_at` IS NULL. Return COUNT(*).
   *
   * 4. **Budget alerts (projects >80% utilization)**: Query `hrm_time_tracking_projects` WHERE `hrm_time_tracking_organization_id` = organizationId AND `status` = 'active' AND `deleted_at` IS NULL AND `budget_hours` IS NOT NULL. For each project, calculate total logged hours from `hrm_time_tracking_timelogs` (deleted_at IS NULL). Compute utilization_pct = total_logged / budget_hours * 100. Filter where utilization_pct > 80. Return the list of projects exceeding threshold.
   *
   * 5. **Top 5 employees by hours logged this week**: Using the same week boundaries from step 2, query timelogs grouped by employee_id, SUM(duration_minutes). Join with employees table to get employee name. Order by SUM(duration_minutes) DESC LIMIT 5. Return employee name and total hours.
   *
   * **Authorization**: Verify the requesting user has the `report:view` permission within the organization before returning data. Users without this permission should receive a 403 Forbidden error.
   *
   * **Data isolation**: All queries MUST filter by `hrm_time_tracking_organization_id` to enforce multi-tenant data boundaries.
   *
   * **Edge cases**:
   * - Organization not found → 404
   * - No timelogs for the current week → return 0 for total hours, empty list for top employees
   * - No projects with budget → return empty list for budget alerts
   * - No pending timesheets → return 0
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async overview(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("organizationId")
    organizationId: string & tags.Format<"uuid">,
  ): Promise<IHrmTimeTrackingOrganizationDashboard> {
    try {
      return await getHrmTimeTrackingMemberOrganizationsOrganizationIdDashboard(
        {
          member,
          organizationId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
