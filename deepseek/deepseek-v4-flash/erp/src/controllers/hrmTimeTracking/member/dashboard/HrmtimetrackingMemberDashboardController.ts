import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IHrmTimeTrackingDashboard } from "../../../../api/structures/IHrmTimeTrackingDashboard";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getHrmTimeTrackingMemberDashboard } from "../../../../providers/getHrmTimeTrackingMemberDashboard";

@Controller("/hrmTimeTracking/member/dashboard")
export class HrmtimetrackingMemberDashboardController {
  /**
   * Retrieve the current user's dashboard providing a comprehensive work status overview.
   *
   * The dashboard combines personal work tracking data with organization-wide metrics for authorized users. The personal section shows hours logged today and this week, active timer status with running duration, the five most recent timelog entries, the current week's timesheet status, and tasks assigned to the employee that are still open or in-progress. When the authenticated employee's role includes the report:view permission, the response additionally includes organization-level metrics: total active employee count, total hours logged across all employees this week, number of pending timesheets awaiting approval, projects approaching or exceeding 80% budget utilization, and the top 5 employees by hours logged this week.
   *
   * This endpoint requires an active authenticated session with a selected organization context. All date calculations respect the organization's configured timezone. Data access is scoped to the current organization only — no cross-organization data is exposed.
   *
   * @param connection
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Authenticate the member and identify the current
     *   organization context. Find the employee record for this member in the
     *   organization (join hrm_time_tracking_employees by member_id and
     *   organization_id). If not found, return 404.
   *
   * Personal Dashboard:
   * 1. Hours logged today: SUM(duration_minutes) FROM hrm_time_tracking_timelogs WHERE employee_id = {employeeId} AND date = TODAY (org timezone) AND deleted_at IS NULL. Convert to hours (divide by 60).
   * 2. Hours logged this week: Same query but date BETWEEN week_start AND week_end (Monday to Sunday in org timezone).
   * 3. Active timer: SELECT FROM hrm_time_tracking_timers WHERE employee_id = {employeeId} AND status = 'running'. Include project name, task name, started_at for elapsed duration calculation.
   * 4. Recent timelogs: Last 5 timelogs for the employee (ORDER BY created_at DESC LIMIT 5), include project name, task name, date, duration_minutes, description, billable.
   * 5. Pending timesheet: SELECT FROM hrm_time_tracking_timesheets WHERE employee_id = {employeeId} AND week_start_date = CURRENT_WEEK_MONDAY (org timezone). Return status (or null if none), total_hours.
   * 6. Assigned tasks: SELECT FROM hrm_time_tracking_tasks WHERE hrm_time_tracking_employee_id = {employeeId} AND status IN ('open', 'in-progress') AND deleted_at IS NULL. Include title, status, priority, due_date, project name.
   *
   * Organization Dashboard (only if employee's role has 'report:view' permission):
   * 1. Total active employees: COUNT FROM hrm_time_tracking_employees WHERE organization_id = {orgId} AND status = 'active' AND deleted_at IS NULL.
   * 2. Total hours logged this week: SUM(duration_minutes) FROM hrm_time_tracking_timelogs JOIN hrm_time_tracking_employees ON employee_id = employees.id WHERE organization_id = {orgId} AND date BETWEEN week_start AND week_end AND deleted_at IS NULL. Convert to hours.
   * 3. Pending timesheets: COUNT FROM hrm_time_tracking_timesheets WHERE status = 'submitted' AND employee is in current organization (JOIN through employees).
   * 4. Budget alerts: Projects WHERE organization_id = {orgId} AND status = 'active' AND budget_hours IS NOT NULL AND (SUM of timelog durations / (budget_hours * 60)) > 0.8. Include name, budget_hours, actual hours, utilization percentage.
   * 5. Top 5 employees by hours: GROUP BY employee_id, SUM(duration_minutes) WHERE date BETWEEN week_start AND week_end, JOIN employees for display_name, ORDER BY SUM DESC LIMIT 5.
   *
   * Use the organization's configured timezone for date boundaries (today, week start/end). All duration values returned in hours (decimal).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @MemberAuth()
    member: MemberPayload,
  ): Promise<IHrmTimeTrackingDashboard> {
    try {
      return await getHrmTimeTrackingMemberDashboard({
        member,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
