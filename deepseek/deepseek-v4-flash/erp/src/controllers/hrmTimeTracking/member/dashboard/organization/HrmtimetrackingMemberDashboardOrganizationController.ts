import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IHrmTimeTrackingOrganizationDashboard } from "../../../../../api/structures/IHrmTimeTrackingOrganizationDashboard";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { getHrmTimeTrackingMemberDashboardOrganization } from "../../../../../providers/getHrmTimeTrackingMemberDashboardOrganization";

@Controller("/hrmTimeTracking/member/dashboard/organization")
export class HrmtimetrackingMemberDashboardOrganizationController {
  /**
   * Retrieves the organization dashboard providing a high-level overview of team productivity and operational status.
   *
   * The dashboard aggregates real-time data across all active employees, projects, timelogs, and timesheets within the currently active organization. It is intended for users with the `report:view` permission — typically organization owners and managers.
   *
   * The response includes: total active employee count, total hours logged across all employees for the current week, the number of pending timesheets awaiting approval, projects whose budget utilization exceeds 80%, and the top 5 employees by hours logged this week.
   *
   * All data is strictly scoped to the organization context selected by the authenticated user. Cross-organization data is never included.
   *
   * Requires `report:view` permission.
   *
   * @param connection
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query across multiple tables within the current
     *   organization context:
   *
   * 1. Active employees count: COUNT of hrm_time_tracking_employees WHERE organization_id = current AND status = 'active' AND deleted_at IS NULL.
   *
   * 2. Total hours this week: SUM of duration_minutes / 60 from hrm_time_tracking_timelogs JOIN hrm_time_tracking_employees WHERE employee.organization_id = current AND timelog.deleted_at IS NULL AND timelog.date is within the current Monday-to-Sunday week (use the organization's timezone setting to determine week boundaries).
   *
   * 3. Pending timesheets count: COUNT of hrm_time_tracking_timesheets WHERE employee.organization_id = current AND status = 'submitted' AND deleted_at IS NULL.
   *
   * 4. Projects with budget utilization > 80%: SELECT from hrm_time_tracking_projects WHERE organization_id = current AND status = 'active' AND budget_hours IS NOT NULL AND deleted_at IS NULL. For each project, calculate SUM of timelog duration_minutes / 60 and compare against budget_hours. Return projects where SUM/budget_hours > 0.8 along with utilization percentage.
   *
   * 5. Top 5 employees by hours this week: GROUP BY employee_id on timelogs within current week, SUM(duration_minutes), ORDER BY SUM DESC, LIMIT 5. JOIN with employees table to include employee name/id.
   *
   * All queries MUST enforce organization data isolation — only data belonging to the authenticated user's current organization context. Apply soft-delete filtering (deleted_at IS NULL) on all tables that support it.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @MemberAuth()
    member: MemberPayload,
  ): Promise<IHrmTimeTrackingOrganizationDashboard> {
    try {
      return await getHrmTimeTrackingMemberDashboardOrganization({
        member,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
