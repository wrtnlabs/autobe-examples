@Controller("/hrmTimeTracking/member/timers")
export class HrmtimetrackingMemberTimersController {
  /**
   * Starts a new timer session for the authenticated employee to track work time in real-time.
   *
   * The employee must select a project they are currently assigned to. Optionally, a specific task within that project and a description of the work can be provided. The system automatically records the start timestamp and sets the timer status to "running".
   *
   * An employee can have at most one active timer at any time — if a timer is already running, the request is rejected and the employee must stop or discard the existing timer first. Deactivated employees cannot start timers. Timers cannot be started on archived or completed projects.
   *
   * Once started, the timer runs indefinitely until the employee manually stops it (which creates a timelog with the calculated duration) or discards it (which abandons the session without recording time).
   *
   * @param connection
   * @param body Parameters for starting a timer: the project to track time against (required), an optional task within that project, and an optional description of the work being performed.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Start a timer for the authenticated employee.
   *
   * Validate:
   * 1. The authenticated employee exists and has status 'active' — reject with error if deactivated.
   * 2. The employee has no existing timer with status 'running' — query hrm_time_tracking_timers where employee_id = {employee.id} AND status = 'running'. If found, reject with error (multiple active timers blocked).
   * 3. The referenced project exists, belongs to the employee's organization, and the employee is a project member — query hrm_time_tracking_projects and hrm_time_tracking_project_members. Project status must NOT be 'archived' or 'completed' — reject if so.
   * 4. If taskId is provided, verify the task exists and belongs to the specified project — query hrm_time_tracking_tasks.
   *
   * On success:
   * - Create a new hrm_time_tracking_timers record with:
   *   - id: auto-generated UUID
   *   - hrm_time_tracking_employee_id: from authenticated employee
   *   - hrm_time_tracking_project_id: from request
   *   - hrm_time_tracking_task_id: from request (optional, null if not provided)
   *   - description: from request (optional, null if not provided)
   *   - started_at: current timestamp
   *   - stopped_at: null
   *   - status: 'running'
   *   - created_at: current timestamp
   *   - updated_at: current timestamp
   * - Fire timer-started event to the timer owner and users with time:view_all permission.
   * - Return the created timer entity.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async start(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmTimeTrackingTimer.ICreate,
  ): Promise<IHrmTimeTrackingTimer> {
    try {
      return await postHrmTimeTrackingMemberTimers({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and list timer records with powerful filtering, pagination, and sorting capabilities.
   *
   * This endpoint allows organization members to browse timer sessions recorded within their organization. A timer represents a live time tracking session that an employee uses to record work duration in real-time — each timer captures the project being worked on, an optional task, an optional description, and tracks the elapsed duration from its start timestamp.
   *
   * Users with the `time:view_all` permission can view timer records across all employees in the organization, making it useful for managers and administrators who need to monitor time tracking activity and see who is currently running timers. Users without this permission can only view their own timer records — the system automatically restricts the result set.
   *
   * Results can be filtered by timer status (running, stopped, or discarded), associated project, optional task assignment, and date ranges for when the timer started or stopped. This enables workflows such as reviewing all running timers across the organization, inspecting completed timer sessions for a specific project, or auditing timer activity within a date range. The response is cursor-paginated with configurable sorting to support efficient browsing of large timer histories.
   *
   * @param connection
   * @param body Search criteria for filtering timer records. Supports filtering by employee ID (for users with time:view_all), timer status (running, stopped, discarded), associated project, optional task, and date range for started_at or stopped_at timestamps. Includes pagination parameters (sort, limit, cursor) for browsing large result sets.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query hrm_time_tracking_timers table with
     *   pagination and filtering.
   *
   * **Data Access & Organization Isolation:**
   * - Join through hrm_time_tracking_employees to the requesting user's current organization context
   * - The requesting user's organization is resolved from their Employee record (hrm_time_tracking_employee_id on the member session)
   * - Only return timers belonging to employees whose organization_id matches the requesting user's organization
   * - NEVER allow cross-organization data leaks — this is strictly enforced
   *
   * **Permission-Based Access:**
   * - Check if the requesting user has `time:view_all` permission via their role
   * - If user HAS `time:view_all`: return timers for ALL employees in the organization (filterable by employeeId)
   * - If user does NOT have `time:view_all`: only return timers owned by the requesting user themselves (ignore any employeeId filter)
   *
   * **Filtering Criteria (in request body):**
   * - `employeeId`: Filter by timer owner (ignored if user lacks time:view_all)
   * - `status`: Filter by timer status — "running", "stopped", "discarded"
   * - `projectId`: Filter by associated project
   * - `taskId`: Filter by optional task (null task filter returns timers without task)
   * - `startedAt.from` / `startedAt.to`: Date range filter on started_at timestamp
   * - `stoppedAt.from` / `stoppedAt.to`: Date range filter on stopped_at timestamp
   *
   * **Pagination & Sorting:**
   * - Use cursor-based pagination with sort and limit fields in request body
   * - Default sort: started_at descending (newest first)
   * - Supported sort fields: started_at, stopped_at, status
   * - Include next cursor in response for pagination continuation
   * - Return empty array (not error) when no results match
   *
   * **Edge Cases:**
   * - Employee with no timers → empty result set
   * - Invalid employee ID (within org but doesn't exist) → empty result set
   * - Stopped timers have stopped_at populated and status "stopped"
   * - Discarded timers have stopped_at populated and status "discarded"
   * - Running timers have stopped_at = null and status "running"
   * - An employee can have at most one running timer
   * - Filtering by "running" status should return at most one per employee
   * - Archived/completed project filters: existing timer records for archived projects are still visible (the filter restriction applies only to creating new timers, not viewing historical ones)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmTimeTrackingTimer.IRequest,
  ): Promise<IPageIHrmTimeTrackingTimer.ISummary> {
    try {
      return await patchHrmTimeTrackingMemberTimers({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific timer session by its unique identifier.
   *
   * Each timer belongs to an employee and tracks a real-time work session with a project (and optionally a task). The response includes the timer's current status (running, stopped, or discarded), the start timestamp, the optional stopped timestamp, and the associated project and task references. If the timer is currently running, the stopped_at field is null.
   *
   * This endpoint enforces organization-level data isolation: the requesting employee must belong to the same organization as the timer's owning employee. A 404 response is returned if the timer does not exist or is not accessible within the current organization context.
   *
   * @param connection
   * @param timerId The unique identifier (UUID) of the timer session to retrieve.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query hrm_time_tracking_timers by id = {timerId}.
     *   Join with hrm_time_tracking_employees to enforce multi-tenant
     *   isolation: verify the timer's employee belongs to the same organization
     *   as the requesting employee (via hrm_time_tracking_organization_id). If
     *   no matching record is found or the organization does not match, return
     *   404 Not Found. The response should return the full timer entity data
     *   including id, hrm_time_tracking_employee_id,
     *   hrm_time_tracking_project_id, hrm_time_tracking_task_id, description,
     *   started_at, stopped_at, status, created_at, and updated_at. No
     *   pagination or filtering is needed — this is a single record retrieval.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":timerId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("timerId")
    timerId: string & tags.Format<"uuid">,
  ): Promise<IHrmTimeTrackingTimer> {
    try {
      return await getHrmTimeTrackingMemberTimersTimerId({
        member,
        timerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update a running timer's details including the associated project, task, and description.
   *
   * This operation allows an employee to modify the project, task assignment, and description of their currently active (running) timer. The timer must belong to the requesting employee and be in the 'running' status to accept updates.
   *
   * **Modifiable fields**: The project (required), task (optional, must belong to the selected project), and description (optional) can all be changed while the timer is running. When the timer is later stopped, the timelog inherits the final values of these fields.
   *
   * **Project validation**: The selected project must be in 'active' status. Archived or completed projects are not accepting new time entries and cannot be assigned to a running timer.
   *
   * **Task validation**: If a task is specified, it must belong to the selected project.
   *
   * **Authorization**: Only the employee who owns the timer (the employee who started it) can update their own timer.
   *
   * @param connection
   * @param timerId The UUID of the timer session to update. The timer must belong to the authenticated employee and be in 'running' status.
   * @param body Fields to update on a running timer: the project, optional task within that project, and optional description. The timer must be in 'running' status.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query the hrm_time_tracking_timers table by
     *   timerId. Verify the timer exists and the requesting employee is the
     *   owner (hrm_time_tracking_employee_id matches the authenticated
     *   employee).
   *
   * **Status check**: Verify timer.status === 'running'. Reject with 422 if status is 'stopped' or 'discarded' — stopped/discarded timers are final and cannot be modified.
   *
   * **Project validation**: Verify the new project exists, belongs to the same organization as the timer's employee, and has status === 'active'. Reject with 422 if status is 'archived' or 'completed'.
   *
   * **Task validation**: If taskId is provided, verify the task exists, belongs to the selected project (hrm_time_tracking_project_id matches), and is not soft-deleted. Reject with 422 if the task does not match the project.
   *
   * **Update**: Update only the provided fields (hrm_time_tracking_project_id, hrm_time_tracking_task_id, description) and set updated_at to current timestamp. Return the full updated timer record.
   *
   * **Edge cases**: If the timer is stopped/discarded, reject with appropriate error message. If the employee is deactivated (status !== 'active'), reject per employee status rules.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":timerId")
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("timerId")
    timerId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IHrmTimeTrackingTimer.IUpdate,
  ): Promise<IHrmTimeTrackingTimer> {
    try {
      return await putHrmTimeTrackingMemberTimersTimerId({
        member,
        timerId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Discard a running timer without creating a timelog.
   *
   * When an employee discards a timer, the timer session is terminated without generating a time entry. This operation is the counterpart to stopping a timer — while stopping creates a timelog with the elapsed duration, discarding abandons the session entirely. The discarded timer record is preserved with status set to 'discarded' and stopped_at populated for audit trail purposes.
   *
   * Only the timer owner (the employee who started the timer) can discard their own running timer. Users with the time:manage permission may discard any employee's running timer. Timers that are already in 'stopped' or 'discarded' status cannot be discarded — the timer must be currently running.
   *
   * After discarding, the employee is free to start a new timer. No timelog is created, and the elapsed time is not recorded. The response returns the updated timer object reflecting the new status and stopped_at timestamp.
   *
   * @param connection
   * @param timerId The unique identifier (UUID) of the running timer to discard.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query the hrm_time_tracking_timers table by id
     *   (timerId). If not found, return 404 Not Found.
   *
   * Validate timer state: the timer must be in 'running' status (status = 'running', stopped_at is null). If the timer is already 'stopped' or 'discarded', return 409 Conflict with a message indicating only running timers can be discarded.
   *
   * Authorization check: the authenticated employee must own the timer (hrm_time_tracking_employee_id matches the current employee's employee id), OR the authenticated user must hold the time:manage permission. If neither condition is met, return 403 Forbidden.
   *
   * Update the timer record: set stopped_at to the current UTC timestamp, status to 'discarded', and updated_at to the current UTC timestamp. Do NOT create a timelog — this is the critical difference from the stop operation.
   *
   * Emit a timer-discarded real-time event. Deliver the event to the timer owner (the employee who owns the timer). For users with time:view_all permission, remove the timer from the visible active-timer list.
   *
   * Return the updated timer record (IHrmTimeTrackingTimer) with the new status and stopped_at values.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":timerId")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("timerId")
    timerId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteHrmTimeTrackingMemberTimersTimerId({
        member,
        timerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
