/**
 * Register a new user account on the platform.
 *
 * Creates a new member account using the provided email address and password. The email address serves as the unique identifier across the entire platform — no two accounts can share the same email address. The display name is part of the global profile shared across all organizations the user later joins.
 *
 * Upon successful registration, the system creates an authentication session recording the client's IP address, current page URL, and HTTP referrer for audit purposes, and issues JWT access and refresh tokens. The member is then authenticated and can proceed to select or create an organization context.
 *
 * Security considerations: The password is hashed using bcrypt and never stored in plaintext. Email uniqueness is enforced at the database level via a unique constraint. Duplicate email registration attempts return a conflict error.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Credentials and profile information required for new member registration.
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor member
 * @x-autobe-specification Create a new member account. Validate email is not
 *   empty and contains '@'. Validate password is not empty (minimum 8
 *   characters recommended). Check email uniqueness in
 *   hrm_time_tracking_members table — if email already exists (including
 *   soft-deleted), return 409 Conflict. Hash the password using bcrypt. Insert
 *   a new hrm_time_tracking_members record with provided email, password_hash,
 *   and display_name. Create a hrm_time_tracking_member_sessions record storing
 *   IP, href, referrer from request context. Generate JWT access token
 *   (short-lived) and refresh token (long-lived). Return tokens and member
 *   identity in the response body.
 * @path /hrmTimeTracking/auth/member/join
 * @accessor api.functional.hrmTimeTracking.auth.member.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
