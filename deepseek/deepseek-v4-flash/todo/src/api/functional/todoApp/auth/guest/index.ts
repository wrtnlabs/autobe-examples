import typia from "typia";

import { ITodoAppGuest } from "../../../../structures/ITodoAppGuest";

/**
 * Create a new anonymous guest identity and session.
 *
 * Guests are unauthenticated visitors who have not yet signed up or logged into the application. This operation creates a lightweight guest record in the `todo_app_guests` table along with an associated session in `todo_app_guest_sessions`. The session tracks the guest's IP address, entry page URL (`href`), and referring page URL (`referrer`) for basic analytics and security auditing.
 *
 * Upon successful creation, the guest receives an authorized response containing an access token (JWT) and a refresh token. The refresh token corresponds to the session identifier and can be used to obtain new access tokens when the current one expires. Guests must provide this refresh token to extend their anonymous session.
 *
 * This is the only entry point for unauthenticated visitors to obtain guest-level access. Once a guest transitions to a member via sign-up or login, the guest record is discarded.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Guest registration payload containing session context information (IP address, entry URL, referrer) needed to establish the anonymous session.
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor guest
 * @x-autobe-specification Create a new guest record in todo_app_guests with a
 *   generated UUID id and current timestamps for created_at and updated_at.
 *   Then create a corresponding guest session record in todo_app_guest_sessions
 *   with: generated UUID id, the guest's id as todo_app_guest_id,
 *   ip/href/referrer extracted from the request body, created_at set to now,
 *   expired_at set to now + session duration (e.g., 24 hours). Generate a JWT
 *   access token containing the guest id as a claim, and use the session id as
 *   the refresh token. Return both tokens in the response.
 * @path /todoApp/auth/guest/join
 * @accessor api.functional.todoApp.auth.guest.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
