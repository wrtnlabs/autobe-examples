/**
 * Creates a new anonymous guest session for an unauthenticated visitor.
 *
 * When an unauthenticated user first accesses the application, the system initializes a guest record and creates an anonymous session for tracking purposes. The guest provides their current page URL (href) and the referring page URL (referrer) as context for the session.
 *
 * The session is time-limited and expires after a predefined duration. Once expired, the guest must obtain a new session. Guest sessions are ephemeral and carry no persistent user data — all session state is discarded upon expiration or when the guest transitions to a member through sign-up or login.
 *
 * This is the only operation available to guests before authentication, alongside the sign-up and login endpoints.
 *
 * @param props.connection
 * @param props.body Session initialization data including the current page URL the guest is accessing and the HTTP referrer.
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor null
 * @x-autobe-specification Create a new guest record in todo_app_guests table
 *   with generated UUID and current timestamp.
 *
 * Then create a new guest session in todo_app_guest_sessions table:
 * - Generate a new UUID for the session ID
 * - Set todo_app_guest_id to the newly created guest's ID
 * - Capture client IP from request headers (X-Forwarded-For or connection remote address)
 * - Set href and referrer from the request body
 * - Set created_at to current timestamp
 * - Set expired_at to current timestamp + session duration (e.g., 30 minutes)
 *
 * Return the created guest record with its session token and expiration time.
 *
 * Edge cases:
 * - If href or referrer are empty strings, store them as provided
 * - IP should be extracted from trusted proxy headers if behind a reverse proxy
 * @path /todoApp/guests
 * @accessor api.functional.todoApp.guests.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function create(
  connection: IConnection,
  props: create.Props,
): Promise<create.Response> {
  return true === connection.simulate
    ? create.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...create.METADATA,
          path: create.path(),
          status: null,
        },
        props.body,
      );
}
export namespace create {
  export type Props = {
    /**
     * Session initialization data including the current page URL the guest is accessing and the HTTP referrer.
     */
    body: ITodoAppGuest.ICreate;
  };
  export type Body = ITodoAppGuest.ICreate;
  export type Response = ITodoAppGuest;

  export const METADATA = {
    method: "POST",
    path: "/todoApp/guests",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/todoApp/guests";
  export const random = (): ITodoAppGuest => typia.random<ITodoAppGuest>();
  export const simulate = (
    connection: IConnection,
    props: create.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: create.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

/**
 * Retrieve a guest record by its unique identifier.
 *
 * Guests are anonymous, unauthenticated visitors who have not yet signed up or logged into the application. Each guest record serves as a lightweight identifier tracking the visitor's anonymous presence. The record contains only basic metadata (creation and update timestamps); session-level details such as IP address, page URLs, and expiration are stored separately in related session records.
 *
 * This operation returns the guest record for the specified identifier. If no guest exists with the given ID, a 404 Not Found response is returned.
 *
 * @param props.connection
 * @param props.guestId The unique identifier (UUID) of the guest record to retrieve. (global scope)
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor null
 * @x-autobe-specification Query todo_app_guests table by primary key id. Return
 *   the full guest record if found. If no record matches the given guestId,
 *   return 404 Not Found. No joins needed as this returns only the guest record
 *   itself. Guest records are never soft-deleted — they are hard-deleted when
 *   the guest transitions to a member or when sessions expire.
 * @path /todoApp/guests/:guestId
 * @accessor api.functional.todoApp.guests.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
