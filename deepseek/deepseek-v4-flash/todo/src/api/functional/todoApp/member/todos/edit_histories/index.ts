/**
 * Retrieve the paginated edit history for a specific todo.
 *
 * Every time a todo is edited, a history entry is automatically created recording which fields were changed and what their new values are. This endpoint returns those entries in reverse chronological order so you can see the most recent edits first.
 *
 * Each history entry contains a timestamp and the new values for any fields that changed during that edit. Fields that remained unchanged are omitted (null). Clearing an optional field (description, start date, due date) records the field as cleared.
 *
 * History is read-only — entries are immutable once created and cannot be modified or deleted except when the parent todo is permanently removed. Access is restricted to the member who owns the todo.
 *
 * @param props.connection
 * @param props.todoId The UUID of the todo whose edit history is being retrieved. (UUID format)
 * @param props.body Pagination and sorting parameters for browsing the edit history. Supports page number, page size, and sort direction by creation timestamp.
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor member
 * @x-autobe-specification Query todo_app_edit_histories filtered by
 *   todo_app_todo_id = {todoId}. Verify the todo exists and belongs to the
 *   authenticated member (todo_app_member_id = current member ID) before
 *   returning results — if the todo doesn't exist or belongs to another user,
 *   return 404 Not Found (don't distinguish between non-existent and
 *   inaccessible).
 *
 * Apply pagination (page, limit) with cursor-based or offset pagination. Sort by created_at DESC (most recent first) by default. Support optional sort direction override via request body.
 *
 * The response items show changed-only fields: for each entry, include created_at, and include title/description/start_date/due_date only when they are non-null (the field was changed in that edit).
 * @path /todoApp/member/todos/:todoId/edit-histories
 * @accessor api.functional.todoApp.member.todos.edit_histories.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
