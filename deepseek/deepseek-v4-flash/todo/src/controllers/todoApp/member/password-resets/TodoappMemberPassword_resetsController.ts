import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageITodoAppMemberPasswordReset } from "../../../../api/structures/IPageITodoAppMemberPasswordReset";
import { ITodoAppMemberPasswordReset } from "../../../../api/structures/ITodoAppMemberPasswordReset";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getTodoAppMemberPasswordResetsResetId } from "../../../../providers/getTodoAppMemberPasswordResetsResetId";
import { patchTodoAppMemberPasswordResets } from "../../../../providers/patchTodoAppMemberPasswordResets";

@Controller("/todoApp/member/password-resets")
export class TodoappMemberPassword_resetsController {
  /**
   * Retrieve a paginated list of password reset requests for the authenticated member.
   *
   * Each password reset record represents a request to reset the member's password. The list shows the reset code, creation timestamp, expiration timestamp, and consumption status (soft-delete timestamp). Results are paginated and can be filtered by date range or consumption status.
   *
   * This operation requires authentication. Only the authenticated member's own password reset records are returned — no other member's data is accessible.
   *
   * @param connection
   * @param body Pagination parameters and optional filters for searching password reset records. Includes page number, page size, and optional date range or consumption status filters.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query todo_app_member_password_resets table filtered by the authenticated member's ID (todo_app_member_id). Apply pagination with page and limit parameters from the request body. Support optional filtering by date range on created_at. Support optional filtering by consumption status (deleted_at IS NULL vs deleted_at IS NOT NULL). Sort by created_at descending by default. Return paginated summary records. The code field should be masked or partially shown in the summary view for security.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: ITodoAppMemberPasswordReset.IRequest,
  ): Promise<IPageITodoAppMemberPasswordReset.ISummary> {
    try {
      return await patchTodoAppMemberPasswordResets({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a password reset record by its unique identifier to verify its validity for password recovery.
   *
   * The response includes the reset record's status information, allowing the caller to determine whether the reset token is still valid (not expired and not yet consumed). This endpoint is used during the password reset flow after the user provides their reset code, enabling the frontend to verify the token's validity before proceeding with setting a new password.
   *
   * Accessible only to guests and members who possess the reset identifier. The endpoint does not expose the sensitive reset code value in its response to maintain security.
   *
   * @param connection
   * @param resetId The unique identifier (UUID) of the password reset record to retrieve.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query the todo_app_member_password_resets table by primary key (id). Return the password reset record including its expiration status (expired_at compared against current time) and consumption status (deleted_at being null or non-null). If the record is not found, return a 404 Not Found error. The reset code itself should be excluded from the response for security — the caller already possesses the code.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":resetId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("resetId")
    resetId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppMemberPasswordReset> {
    try {
      return await getTodoAppMemberPasswordResetsResetId({
        member,
        resetId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
