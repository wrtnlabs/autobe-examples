import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IPageITodoAppTodo } from "../../../../api/structures/IPageITodoAppTodo";
import { ITodoAppTodo } from "../../../../api/structures/ITodoAppTodo";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { patchTodoAppMemberTrash } from "../../../../providers/patchTodoAppMemberTrash";

@Controller("/todoApp/member/trash")
export class TodoappMemberTrashController {
  /**
   * Retrieves a paginated list of trashed (soft-deleted) todos belonging to the authenticated member.
   *
   * Todos that have been deleted from the normal todo list appear here in the trash, preserving all their data including completion status and edit history. Each item in the list displays the title, completion status, start date (if set), due date (if set), creation date, and deletion timestamp.
   *
   * The list supports pagination with customizable page size, sorting by creation date, start date, or due date in either ascending or descending order, and filtering by completion status. Todos without a start date or due date appear at the end when sorting by those fields.
   *
   * Only the authenticated member can view their own trash. Other members' trash data is never accessible.
   *
   * @param connection
   * @param body Pagination, sorting, and filtering parameters for the trash list view. Supports page number, page size, sort field (createdAt, startDate, dueDate), sort direction (asc, desc), and completion status filter (all, complete, incomplete).
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query todo_app_todos table filtering by: todo_app_member_id = {authenticated member's ID} AND deleted_at IS NOT NULL. Apply pagination (page, limit) from request body. Support sorting by: created_at (asc/desc for oldest first/newest first), start_date (asc/desc, nulls last), due_date (asc/desc, nulls last). Default sort: created_at DESC (newest first). Filter by completion status: all (no filter), complete (completed_at IS NOT NULL), incomplete (completed_at IS NULL). Reset to page 1 when sort or filter changes. Return only summary fields: id, title, completed_at, start_date, due_date, created_at, deleted_at. Return empty list if no matching records.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: ITodoAppTodo.IRequest,
  ): Promise<IPageITodoAppTodo.ISummary> {
    try {
      return await patchTodoAppMemberTrash({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
