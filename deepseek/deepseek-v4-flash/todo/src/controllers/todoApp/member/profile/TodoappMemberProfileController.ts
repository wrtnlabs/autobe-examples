import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { ITodoAppProfile } from "../../../../api/structures/ITodoAppProfile";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getTodoAppMemberProfile } from "../../../../providers/getTodoAppMemberProfile";
import { putTodoAppMemberProfile } from "../../../../providers/putTodoAppMemberProfile";

@Controller("/todoApp/member/profile")
export class TodoappMemberProfileController {
  /**
   * Retrieves the authenticated member's own profile information.
   *
   * This endpoint returns the display name and metadata for the currently authenticated member's profile. Each member has exactly one profile created at registration. The profile is private — only the authenticated member can view their own profile. There is no mechanism to view another user's profile.
   *
   * The display name is optional and can be updated through the profile update endpoint. If not set, display_name returns null.
   *
   * @param connection
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query todo_app_profiles where todo_app_member_id
     *   matches the authenticated member's ID (resolved from JWT token). Return
     *   the profile record if found. Since a profile is created atomically with
     *   member registration (via cascade), a missing profile indicates a data
     *   integrity issue — return 404 Not Found. No joins needed. Return only
     *   fields: id, todo_app_member_id, display_name, created_at, updated_at.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @MemberAuth()
    member: MemberPayload,
  ): Promise<ITodoAppProfile> {
    try {
      return await getTodoAppMemberProfile({
        member,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update the authenticated member's profile information.
   *
   * Only the display name can be modified through this endpoint. The display name is optional — it can be set, changed, or cleared. The update takes effect immediately and is reflected in subsequent profile retrievals.
   *
   * This is a private profile accessible only to the owning member. No other user can view or modify this profile.
   *
   * Authentication is required. The profile is identified by the authenticated member's identity from the JWT token, not from a path parameter.
   *
   * @param connection
   * @param body Profile update payload containing the new display name value. Set to null or omit to clear the display name.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Fetch the profile record belonging to the
     *   authenticated member using their member ID (extracted from JWT token).
     *   The profile is linked to the member via the todo_app_member_id foreign
     *   key.
   *
   * Update the display_name field if provided in the request body. If display_name is null, clear the existing value. If display_name is absent from the request body, treat it as clearing the value.
   *
   * Update the updated_at timestamp to the current time.
   *
   * Return the updated profile record including all fields (id, todo_app_member_id, display_name, created_at, updated_at).
   *
   * Edge cases:
   * - If the member has no profile yet (should not occur since profiles are created at registration), return a 404 Not Found error.
   * - The profile is identified by the authenticated member, so no authorization check beyond authentication is needed — the member can only access their own profile.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: ITodoAppProfile.IUpdate,
  ): Promise<ITodoAppProfile> {
    try {
      return await putTodoAppMemberProfile({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
