import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { ITodoAppGuest } from "../../../../api/structures/ITodoAppGuest";
import { postTodoAppAuthGuestJoin } from "../../../../providers/postTodoAppAuthGuestJoin";
import { postTodoAppAuthGuestRefresh } from "../../../../providers/postTodoAppAuthGuestRefresh";

@Controller("/todoApp/auth/guest")
export class TodoappAuthGuestController {
  /**
   * Create a new anonymous guest identity and session.
   *
   * Guests are unauthenticated visitors who have not yet signed up or logged into the application. This operation creates a lightweight guest record in the `todo_app_guests` table along with an associated session in `todo_app_guest_sessions`. The session tracks the guest's IP address, entry page URL (`href`), and referring page URL (`referrer`) for basic analytics and security auditing.
   *
   * Upon successful creation, the guest receives an authorized response containing an access token (JWT) and a refresh token. The refresh token corresponds to the session identifier and can be used to obtain new access tokens when the current one expires. Guests must provide this refresh token to extend their anonymous session.
   *
   * This is the only entry point for unauthenticated visitors to obtain guest-level access. Once a guest transitions to a member via sign-up or login, the guest record is discarded.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Guest registration payload containing session context information (IP address, entry URL, referrer) needed to establish the anonymous session.
     * @x-autobe-authorization-type join
     * @x-autobe-authorization-actor guest
     * @x-autobe-specification Create a new guest record in todo_app_guests with
     *   a generated UUID id and current timestamps for created_at and
     *   updated_at. Then create a corresponding guest session record in
     *   todo_app_guest_sessions with: generated UUID id, the guest's id as
     *   todo_app_guest_id, ip/href/referrer extracted from the request body,
     *   created_at set to now, expired_at set to now + session duration (e.g.,
     *   24 hours). Generate a JWT access token containing the guest id as a
     *   claim, and use the session id as the refresh token. Return both tokens
     *   in the response.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoAppGuest.IJoin,
  ): Promise<ITodoAppGuest.IAuthorized> {
    try {
      return await postTodoAppAuthGuestJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh an existing guest session and obtain new authorization tokens.
   *
   * Guests can extend their anonymous session by providing a valid refresh token obtained from a previous `join` or `refresh` operation. The system validates the token by looking up the corresponding session record in the `todo_app_guest_sessions` table and verifying that the session has not expired and that the associated guest record still exists in `todo_app_guests`.
   *
   * On success, a new access token is issued for continued anonymous access. This operation does not create a new guest record or session — it only refreshes the existing session's authorization. The refresh token corresponds to the session ID created during the initial `join` operation or the most recent `refresh`.
   *
   * If the refresh token is invalid, expired, or the guest record has been deleted (e.g., because the guest signed up as a member), the request is rejected with an authentication error. The guest must then create a new session via the `join` operation.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token payload containing the session's refresh token to validate and exchange for new authorization tokens.
     * @x-autobe-authorization-type refresh
     * @x-autobe-authorization-actor guest
     * @x-autobe-specification Validate the incoming refresh token from the
     *   request body. Look up the corresponding session in
     *   todo_app_guest_sessions where id matches the refresh token value.
     *   Verify the session has not expired (expired_at > now). If valid, check
     *   that the session's guest (todo_app_guest_id) still exists in
     *   todo_app_guests. Generate a new JWT access token containing the guest
     *   id claim. Optionally extend the session's expired_at. Return new
     *   tokens. If the refresh token is invalid, expired, or the guest no
     *   longer exists, return 401 Unauthorized.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: ITodoAppGuest.IRefresh,
  ): Promise<ITodoAppGuest.IAuthorized> {
    try {
      return await postTodoAppAuthGuestRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
