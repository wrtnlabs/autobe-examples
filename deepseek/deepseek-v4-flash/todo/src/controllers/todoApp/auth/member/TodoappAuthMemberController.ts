import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { ITodoAppMember } from "../../../../api/structures/ITodoAppMember";
import { postTodoAppAuthMemberJoin } from "../../../../providers/postTodoAppAuthMemberJoin";
import { postTodoAppAuthMemberLogin } from "../../../../providers/postTodoAppAuthMemberLogin";
import { postTodoAppAuthMemberRefresh } from "../../../../providers/postTodoAppAuthMemberRefresh";

@Controller("/todoApp/auth/member")
export class TodoappAuthMemberController {
  /**
   * Create a new member account and establish an authenticated session.
   *
   * This endpoint registers a new member using an email address and password. The email serves as the member's unique login identifier and cannot be changed later. The password is securely hashed before storage. An optional display name can be provided for the member's profile.
   *
   * Upon successful registration, the member is immediately authenticated: a session is created, and JWT access and refresh tokens are returned. The member can then access all features within their private workspace.
   *
   * If the email address is already registered, the endpoint returns a conflict error. Email addresses are case-sensitive and must be unique across all members.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Registration credentials including email, password, and optional display name.
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Register a new member account. Validate that email is unique (check todo_app_members.email unique constraint). Hash the provided password using bcrypt. Create a new todo_app_members record. Create a todo_app_profiles record with the optional display_name. Create a todo_app_member_sessions record with IP/href/referrer from request context. Generate JWT access+refresh tokens. Return the tokens in IAuthorized response. On duplicate email, return 409 Conflict.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoAppMember.IJoin,
  ): Promise<ITodoAppMember.IAuthorized> {
    try {
      return await postTodoAppAuthMemberJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate an existing member and establish an authenticated session.
   *
   * This endpoint verifies the member's identity by confirming that the provided password matches the registered email address. The email must already exist in the system (the member must have registered first).
   *
   * Upon successful authentication, a new session is created in the member_sessions table, and JWT access and refresh tokens are returned. The session captures the client IP address and page URL for audit purposes. The member can then access all features within their private workspace until the session expires or they log out.
   *
   * If the email is not found or the password does not match, the endpoint returns an unauthorized error.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Authentication credentials with email and password.
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Authenticate an existing member. Look up the member by email in todo_app_members. Verify the provided password against password_hash using bcrypt.compare(). On success, create a new todo_app_member_sessions record with IP/href/referrer. Generate new JWT access+refresh tokens. On invalid credentials, return 401 Unauthorized.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoAppMember.ILogin,
  ): Promise<ITodoAppMember.IAuthorized> {
    try {
      return await postTodoAppAuthMemberLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Renew JWT access and refresh tokens using a valid refresh token.
   *
   * This endpoint allows a member to obtain new tokens without re-entering their credentials. The refresh token from the previous authentication is validated for signature and expiration. If valid, a new session is created, and fresh access and refresh tokens are issued.
   *
   * This is useful for maintaining long-lived sessions. The old refresh token is not invalidated (standard JWT stateless pattern). Tokens expire naturally based on their expiration claims.
   *
   * If the refresh token is invalid, expired, or malformed, the endpoint returns an unauthorized error.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body The refresh token to validate and exchange for new tokens.
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Validate the refresh token from the request body. Verify JWT signature and expiration. Look up the associated member in todo_app_members (check member exists). Create a new todo_app_member_sessions record. Issue new JWT access+refresh tokens. On invalid or expired refresh token, return 401 Unauthorized.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: ITodoAppMember.IRefresh,
  ): Promise<ITodoAppMember.IAuthorized> {
    try {
      return await postTodoAppAuthMemberRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
