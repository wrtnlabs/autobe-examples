export async function test_api_password_reset_retrieve_valid_pending(
  connection: api.IConnection,
): Promise<void> {
  // 1. Join a member to obtain an authenticated session
  const memberConnection: api.IConnection = { host: connection.host };
  const authorized = await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      display_name: RandomGenerator.name(),
    } satisfies ITodoAppMember.IJoin,
  });
  typia.assert(authorized);
  // 2. Retrieve a password reset record by its unique identifier
  const resetRecord: ITodoAppMemberPasswordReset =
    await api.functional.todoApp.member.password_resets.at(memberConnection, {
      resetId: typia.random<string & tags.Format<"uuid">>(),
    });
  typia.assert(resetRecord);
}
