export async function test_api_member_password_reset_records_list_empty(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create authenticated member connection
  const memberConnection: api.IConnection = { host: connection.host };
  await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies ITodoAppMember.IJoin,
  });
  // 2. Retrieve password reset records with default pagination
  const page = await api.functional.todoApp.member.password_resets.index(
    memberConnection,
    {
      body: {} satisfies ITodoAppMemberPasswordReset.IRequest,
    },
  );
  typia.assert(page);
  // 3. Verify pagination metadata for empty result set
  TestValidator.equals("current page", page.pagination.current, 1);
  TestValidator.equals("records count", page.pagination.records, 0);
  TestValidator.equals("total pages", page.pagination.pages, 0);
  TestValidator.equals("data array empty", page.data.length, 0);
  TestValidator.predicate(
    "limit is positive integer",
    page.pagination.limit > 0,
  );
}
