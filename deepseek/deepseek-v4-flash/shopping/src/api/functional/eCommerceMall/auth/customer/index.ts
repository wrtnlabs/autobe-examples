/**
 * Register a new customer account on the platform.
 *
 * Customers sign up with a unique email address and a password. The email address serves as the unique identifier for the customer account, enforced by the unique constraint on e_commerce_mall_customers.email. If the email address is already associated with an existing customer account, the registration request is rejected with a conflict error.
 *
 * Upon successful registration, the customer account is created with the provided email and password (stored as a bcrypt hash in password_hash). A corresponding customer profile record is created in e_commerce_mall_customer_profiles with empty display_name and phone_number defaults. The customer is immediately able to log in and access platform features.
 *
 * An active session is established at registration time. The session metadata (IP address, page URL, HTTP referrer) is captured in e_commerce_mall_customer_sessions for audit purposes. Access and refresh tokens are returned to authenticate subsequent API calls.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Customer registration credentials including email address and password. The email must not already be associated with an existing customer account.
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor customer
 * @x-autobe-specification POST endpoint for customer registration. Validates email uniqueness via unique index on e_commerce_mall_customers.email. Bcrypt-hashes the password and stores in password_hash. Creates row in e_commerce_mall_customers with id (UUID), email, password_hash, created_at, updated_at. Creates corresponding e_commerce_mall_customer_profiles row (1:1 with empty display_name and phone_number). Generates JWT access+refresh tokens, creates session record in e_commerce_mall_customer_sessions (ip, href, referrer from request metadata, expired_at=now+config duration). Returns IECommerceMallCustomer.IAuthorized with tokens. If email already exists, reject 409 Conflict.
 * @path /eCommerceMall/auth/customer/join
 * @accessor api.functional.eCommerceMall.auth.customer.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
