/**
 * Register a new guest account on the e-commerce platform using a unique device or browser fingerprint identifier.
 *
 * Guest accounts provide temporary, unauthenticated access identified by a device_identifier collected client-side via fingerprinting techniques. Upon successful registration, the system creates or reuses a guest record and an associated session, then returns JWT authentication tokens (access and refresh) for subsequent API calls within the authentication boundary (login and registration pages only).
 *
 * The device_identifier uniquely identifies a device or browser across visits. If a guest record already exists for the given device_identifier, the existing guest is reused with a new session rather than creating a duplicate. This ensures each device maintains a consistent guest identity for session continuity, rate limiting, and CSRF protection.
 *
 * The guest's IP address is automatically captured server-side from the HTTP request context. The href (current page URL) and referrer (previous page URL) parameters track navigation context. Session expiration (expired_at) is set at creation time; expired sessions require the refresh endpoint to obtain a new session.
 *
 * Security considerations: Rate limiting per device fingerprint prevents registration abuse. Guest sessions are automatically invalidated upon transition to a registered actor (customer, seller, administrator) via login or registration. Soft-delete support allows guest data retention for analytics and security auditing before permanent cleanup.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Device identifier and page context for guest registration.
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor guest
 * @x-autobe-specification Register a new guest account using a device
 *   fingerprint. Steps: 1) Extract device_identifier, href, referrer from the
 *   request body. 2) Query e_commerce_mall_guests by device_identifier where
 *   deleted_at IS NULL. 3) If found, reuse the existing guest record (if
 *   soft-deleted, reactivate by setting deleted_at to NULL). 4) If not found,
 *   INSERT a new guest record with the device_identifier and current
 *   timestamps. 5) Capture the client IP from the HTTP request context. 6)
 *   INSERT a new guest_session record: id (UUID), e_commerce_mall_guest_id
 *   (guest.id), ip (from request), href, referrer, created_at (now), expired_at
 *   (now + session TTL, e.g. 24 hours). 7) Generate JWT access token
 *   (short-lived, e.g. 15 minutes) and JWT refresh token (long-lived, matching
 *   session expiration). 8) Return IECommerceMallGuest.IAuthorized containing
 *   tokens and session metadata. Error cases: Rate limiting per
 *   device_identifier to prevent abuse.
 * @path /eCommerceMall/auth/guest/join
 * @accessor api.functional.eCommerceMall.auth.guest.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
