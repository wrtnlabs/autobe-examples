/**
 * Register a new seller account on the platform.
 *
 * A prospective seller registers by providing their email address and password, along with shop profile information (shop name, shop description, and optional logo image). The email address serves as the unique login identifier for the seller account. If the email is already associated with an existing seller account, the registration request is rejected with a 409 Conflict response.
 *
 * Upon successful registration, the seller account is created with an approval status of 'pending'. The seller cannot list products or use selling features until an administrator approves the account. A JWT access token and refresh token are issued in the response for authenticating subsequent API requests.
 *
 * The shop profile is established during registration and can be updated later by the seller via the profile management endpoints. Each seller account has exactly one shop profile record.
 *
 * This endpoint is public and does not require prior authentication.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Seller registration credentials including email, password, and shop profile information (shop name, description, and optional logo image URI).
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor seller
 * @x-autobe-specification Create a new seller account with email and password.
 *   Validate email uniqueness (unique constraint on sellers.email). Hash
 *   password using bcrypt. Set approval_status to 'pending'. Create associated
 *   seller_profile record with shop_name, shop_description, logo_image from
 *   request. Create session in e_commerce_mall_seller_sessions capturing ip,
 *   href, referrer, expired_at. Generate JWT access token and refresh token.
 *   Return IECommerceMallSeller.IAuthorized with tokens. On email collision,
 *   return 409 Conflict.
 * @path /eCommerceMall/auth/seller/join
 * @accessor api.functional.eCommerceMall.auth.seller.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
