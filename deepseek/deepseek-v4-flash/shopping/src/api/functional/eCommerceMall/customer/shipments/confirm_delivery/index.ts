/**
 * Confirm delivery of a received shipment package.
 *
 * When a customer receives a shipment, they confirm delivery through this endpoint. Upon confirmation, the shipment's `delivered_at` timestamp is set to the current time, and all order items grouped within this shipment transition to "delivered" status simultaneously. A status log entry with reason "customer_delivery_confirmation" is created for each affected order item.
 *
 * This operation is scoped to the authenticated customer — the shipment must belong to an order owned by the requesting customer. If the shipment has already been delivered (delivered_at is already set), the request is rejected. If the shipment has not been shipped yet (shipped_at is null), the request is also rejected.
 *
 * After delivery confirmation, customers may submit refund requests for delivered items within the 7-day refund window. The shipment record itself is immutable after confirmation except for the delivered_at timestamp.
 *
 * @param props.connection
 * @param props.shipmentId UUID of the shipment to confirm delivery for. The shipment must belong to an order owned by the authenticated customer and must be in 'shipped' state (not yet delivered).
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor customer
 * @x-autobe-specification Find the shipment by `shipmentId` where `deleted_at`
 *   is null. Verify the shipment exists — if not found, return 404 Not Found.
 *
 * Verify customer ownership by traversing: shipment → shipmentItems → orderItems → order → customer. The order's `e_commerce_mall_customer_id` must match the authenticated customer ID. If not authorized, return 403 Forbidden.
 *
 * Validate shipment state:
 * - If `shipped_at` is null, reject with error explaining the shipment has not been dispatched yet
 * - If `delivered_at` is already set, reject with error explaining delivery has already been confirmed
 *
 * If validation passes, execute in a transaction:
 * 1. Update `e_commerce_mall_shipments`:
 *    - Set `delivered_at` to current timestamp
 *    - Update `updated_at` to current timestamp
 * 2. Find all order items linked via `e_commerce_mall_shipment_items` with `shipment_id = {shipmentId}`
 * 3. For each order item:
 *    - Verify its current `status` is "shipped" (defensive check — should always be true)
 *    - Update `status` to "delivered"
 *    - Update `updated_at` to current timestamp
 *    - Create an `e_commerce_mall_order_item_status_logs` entry:
 *      - `from_status`: "shipped"
 *      - `to_status`: "delivered"
 *      - `reason`: "customer_delivery_confirmation"
 *      - `created_at`: current timestamp
 *      - `updated_at`: current timestamp
 *
 * Return the updated shipment record (excluding deleted_at). On any failure within the transaction, roll back all changes.
 * @path /eCommerceMall/customer/shipments/:shipmentId/confirm-delivery
 * @accessor api.functional.eCommerceMall.customer.shipments.confirm_delivery.confirmDelivery
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function confirmDelivery(
  connection: IConnection,
  props: confirmDelivery.Props,
): Promise<confirmDelivery.Response> {
  return true === connection.simulate
    ? confirmDelivery.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...confirmDelivery.METADATA,
          path: confirmDelivery.path(props),
          status: null,
        },
      );
}
