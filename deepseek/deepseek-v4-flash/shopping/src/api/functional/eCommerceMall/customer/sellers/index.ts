/**
 * Retrieve a seller's account and public merchant profile by their unique identifier.
 *
 * The endpoint returns the seller's current approval status (pending, approved, or rejected) alongside their public-facing merchant profile — shop name, shop description, and logo image. The profile information is what customers see when viewing a seller's public profile page before making a purchase, providing transparency about the merchant they are buying from.
 *
 * The response combines data from the seller's authentication record and their shop profile through a one-to-one relationship. Sensitive information such as the password hash is excluded from the response for security purposes.
 *
 * Returns a 404 error if the seller ID does not match any active seller account or if the seller account has been soft-deleted.
 *
 * @param props.connection
 * @param props.sellerId Unique identifier (UUID) of the seller account to retrieve.
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor customer
 * @x-autobe-specification Query e_commerce_mall_sellers by id (UUID), joining
 *   with e_commerce_mall_seller_profiles via the one-to-one relationship on
 *   e_commerce_mall_seller_id.
 *
 * Exclude soft-deleted sellers (deleted_at IS NOT NULL) — return 404 if the seller is not found or has been soft-deleted.
 *
 * Include the seller's approval_status and all profile fields (shop_name, shop_description, logo_image). Use a LEFT JOIN on the profile since a seller might not have a profile created yet (e.g., during pending approval before profile setup).
 *
 * Do NOT expose the password_hash field in the response.
 *
 * Edge cases: If sellerId is not a valid UUID format, return 400 Bad Request. If the UUID is valid but no active seller matches, return 404 Not Found.
 * @path /eCommerceMall/customer/sellers/:sellerId
 * @accessor api.functional.eCommerceMall.customer.sellers.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique identifier (UUID) of the seller account to retrieve.
     */
    sellerId: string & tags.Format<"uuid">;
  };
  export type Response = IECommerceMallSeller;

  export const METADATA = {
    method: "GET",
    path: "/eCommerceMall/customer/sellers/:sellerId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/eCommerceMall/customer/sellers/${encodeURIComponent(props.sellerId ?? "null")}`;
  export const random = (): IECommerceMallSeller =>
    typia.random<IECommerceMallSeller>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("sellerId")(() => typia.assert(props.sellerId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
