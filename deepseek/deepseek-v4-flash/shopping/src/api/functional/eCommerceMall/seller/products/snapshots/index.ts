/**
 * Retrieves a paginated list of product snapshots for a specific product, ordered by creation timestamp descending (newest first).
 *
 * Product snapshots are immutable historical records automatically created whenever a seller edits a product. Each snapshot preserves the complete product state at the time of the edit, including the product name, description, base price, category assignment, all variant configurations, and all product images.
 *
 * Sellers can view snapshots of their own products only. Administrators can view snapshots of any product on the platform for oversight and dispute resolution purposes. Snapshots are preserved even after the product is deleted, ensuring a permanent audit trail.
 *
 * Each snapshot in the list includes the timestamp of capture and summary information about the preserved product state.
 *
 * @param props.connection
 * @param props.productId UUID identifier of the product whose snapshots are being retrieved (global scope).
 * @param props.body Search criteria for filtering product snapshots. Supports optional date-range filtering by creation timestamp and standard pagination parameters for controlling result set size and cursor position.
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor seller
 * @x-autobe-specification Query e_commerce_mall_product_snapshots filtered by
 *   e_commerce_mall_product_id = productId (UUID). Apply optional date-range
 *   filters on created_at. Order by created_at descending (newest first). Join
 *   with e_commerce_mall_product_snapshot_variants for variant count and
 *   e_commerce_mall_product_snapshot_images for image count. Return
 *   cursor-based pagination. Authorization: only the seller who owns the
 *   product (via e_commerce_mall_products.seller_id matching authenticated
 *   seller) or any administrator is allowed to view snapshots. Snapshots are
 *   immutable — always return active records (deleted_at is always null for
 *   snapshots but verify).
 * @path /eCommerceMall/seller/products/:productId/snapshots
 * @accessor api.functional.eCommerceMall.seller.products.snapshots.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
