import {
  HttpError,
  IConnection,
  NestiaSimulator,
  PlainFetcher,
} from "@nestia/fetcher";
import typia, { tags } from "typia";

import { IECommerceMallProduct } from "../../../../../structures/IECommerceMallProduct";

/**
 * Retrieve the aggregated rating summary for a specific product.
 *
 * The rating summary provides the average star rating (calculated from all non-deleted reviews) and the total count of reviews for the product. The average rating is rounded to one decimal place. This endpoint is used to display rating information on product listing pages, category browsing pages, search result pages, and the product detail page.
 *
 * When a product has no non-deleted reviews, the average rating returns 0 and the review count returns 0.
 *
 * @param props.connection
 * @param props.productId The unique identifier of the product to retrieve ratings for.
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor seller
 * @x-autobe-specification Query the e_commerce_mall_reviews table filtered by product_id and where deleted_at IS NULL.
 *
 * Calculate average rating: SELECT AVG(rating) FROM e_commerce_mall_reviews WHERE e_commerce_mall_product_id = {productId} AND deleted_at IS NULL.
 *
 * Calculate total review count: SELECT COUNT(*) FROM e_commerce_mall_reviews WHERE e_commerce_mall_product_id = {productId} AND deleted_at IS NULL.
 *
 * Round the average to one decimal place. If no non-deleted reviews exist, return average_rating = 0 and total_count = 0.
 *
 * Validate that the product exists (query e_commerce_mall_products by id). If product not found, return 404.
 * @path /eCommerceMall/seller/products/:productId/ratings
 * @accessor api.functional.eCommerceMall.seller.products.ratings.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * The unique identifier of the product to retrieve ratings for.
     */
    productId: string & tags.Format<"uuid">;
  };
  export type Response = IECommerceMallProduct.IRating;

  export const METADATA = {
    method: "GET",
    path: "/eCommerceMall/seller/products/:productId/ratings",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/eCommerceMall/seller/products/${encodeURIComponent(props.productId ?? "null")}/ratings`;
  export const random = (): IECommerceMallProduct.IRating =>
    typia.random<IECommerceMallProduct.IRating>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("productId")(() => typia.assert(props.productId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
