export async function getECommerceMallCustomerRefundRequestsRefundRequestId(props: {
  customer: CustomerPayload;
  refundRequestId: string & tags.Format<"uuid">;
}): Promise<IECommerceMallRefundRequest> {
  const record =
    await MyGlobal.prisma.e_commerce_mall_refund_requests.findFirstOrThrow({
      where: {
        id: props.refundRequestId,
        e_commerce_mall_customer_id: props.customer.id,
        deleted_at: null,
      },
      ...ECommerceMallRefundRequestTransformer.select(),
    });
  return await ECommerceMallRefundRequestTransformer.transform(record);
}


