export async function getECommerceMallAdministratorReviewsReviewId(props: {
  administrator: AdministratorPayload;
  reviewId: string & tags.Format<"uuid">;
}): Promise<IECommerceMallReview> {
  const record = await MyGlobal.prisma.e_commerce_mall_reviews.findFirstOrThrow(
    {
      where: {
        id: props.reviewId,
        deleted_at: null,
      },
      ...ECommerceMallReviewTransformer.select(),
    },
  );
  return await ECommerceMallReviewTransformer.transform(record);
}


