import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IECommerceMallSellerProfile } from "../../../../../api/structures/IECommerceMallSellerProfile";
import { SuperadministratorAuth } from "../../../../../decorators/SuperadministratorAuth";
import { SuperadministratorPayload } from "../../../../../decorators/payload/SuperadministratorPayload";
import { getECommerceMallSuperAdministratorSellersSellerIdProfile } from "../../../../../providers/getECommerceMallSuperAdministratorSellersSellerIdProfile";

@Controller("/eCommerceMall/superAdministrator/sellers/:sellerId/profile")
export class EcommercemallSuperadministratorSellersProfileController {
  /**
   * Retrieve the public profile of a seller.
   *
   * Returns the seller's shop name, shop description, and logo image for display on the seller's public profile page. This endpoint is accessible to customers browsing products or viewing seller information from product detail pages, category listings, and search results.
   *
   * The seller profile is publicly viewable — customers use this profile to learn about a merchant before making a purchase. The shop name displayed here also appears alongside products in search results and category listings.
   *
   * If the seller account has been deleted (soft-deleted), this endpoint returns a 404 Not Found response as the profile is no longer publicly accessible. If the seller account does not exist, a 404 Not Found is returned as well.
   *
   * @param connection
   * @param sellerId Unique identifier (UUID) of the seller whose public profile is to be retrieved.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor superAdministrator
   * @x-autobe-specification Query the e_commerce_mall_seller_profiles table joined with e_commerce_mall_sellers to find the profile for the given sellerId.
   *
   * 1. Resolve the seller: Look up e_commerce_mall_sellers by id = sellerId. If not found, return 404.
   * 2. Check seller deleted_at: If the seller has a non-null deleted_at, return 404 (account deleted).
   * 3. Fetch profile: Query e_commerce_mall_seller_profiles where e_commerce_mall_seller_id = sellerId. Since this is a 1:1 unique relationship, there is at most one profile.
   * 4. If profile has non-null deleted_at, return 404 (profile soft-deleted alongside seller deletion).
   * 5. Return the profile entity: shop_name, shop_description, logo_image, created_at, updated_at.
   * 6. No authorization check needed — seller profiles are publicly viewable per Access Control policy (section 534).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @SuperadministratorAuth()
    superAdministrator: SuperadministratorPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
  ): Promise<IECommerceMallSellerProfile> {
    try {
      return await getECommerceMallSuperAdministratorSellersSellerIdProfile({
        superAdministrator,
        sellerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
