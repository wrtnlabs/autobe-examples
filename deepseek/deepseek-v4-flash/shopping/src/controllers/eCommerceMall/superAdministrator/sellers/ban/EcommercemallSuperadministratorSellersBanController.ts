import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IECommerceMallSeller } from "../../../../../api/structures/IECommerceMallSeller";
import { SuperadministratorAuth } from "../../../../../decorators/SuperadministratorAuth";
import { SuperadministratorPayload } from "../../../../../decorators/payload/SuperadministratorPayload";
import { postECommerceMallSuperAdministratorSellersSellerIdBan } from "../../../../../providers/postECommerceMallSuperAdministratorSellersSellerIdBan";

@Controller("/eCommerceMall/superAdministrator/sellers/:sellerId/ban")
export class EcommercemallSuperadministratorSellersBanController {
  /**
   * Ban a seller account, revoking their login access while preserving existing orders and associated data.
   *
   * Administrators use this endpoint to ban a seller account for policy violations. When a seller is banned, they can no longer log into their account. Their existing orders remain unaffected — order items already paid or shipped continue processing normally, and the seller's order history is preserved. All products belonging to the banned seller are hidden from search results and category listings and cannot be purchased.
   *
   * The request must include a reason for the ban, which is recorded in the administrative audit trail for transparency and accountability. A seller who is already banned cannot be banned again — the endpoint returns a conflict error.
   *
   * @param connection
   * @param sellerId UUID of the seller account to ban (global scope).
   * @param body Ban request containing the mandatory reason explaining why the seller is being banned. The reason is recorded in the administrator audit trail for accountability.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor superAdministrator
   * @x-autobe-specification Validate that the requesting actor is an administrator or super administrator. Verify the seller exists and is not already banned (banned_at is null). Set the seller's banned_at field to the current timestamp. Record the action in e_commerce_mall_administrator_audit_logs (or e_commerce_mall_super_administrator_audit_logs) with action_type 'ban_seller', target_type 'seller', target_id as the seller's UUID, and the reason from the request body. Return the updated seller record. If the seller is already banned, return a conflict error. If the seller account is soft-deleted (deleted_at is set), return a not-found error.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SuperadministratorAuth()
    superAdministrator: SuperadministratorPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IECommerceMallSeller.IBan,
  ): Promise<IECommerceMallSeller> {
    try {
      return await postECommerceMallSuperAdministratorSellersSellerIdBan({
        superAdministrator,
        sellerId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
