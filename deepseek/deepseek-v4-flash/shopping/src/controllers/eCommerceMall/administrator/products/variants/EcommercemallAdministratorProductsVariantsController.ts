import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IECommerceMallProductVariant } from "../../../../../api/structures/IECommerceMallProductVariant";
import { IPageIECommerceMallProductVariant } from "../../../../../api/structures/IPageIECommerceMallProductVariant";
import { AdministratorAuth } from "../../../../../decorators/AdministratorAuth";
import { AdministratorPayload } from "../../../../../decorators/payload/AdministratorPayload";
import { getECommerceMallAdministratorProductsProductIdVariantsVariantId } from "../../../../../providers/getECommerceMallAdministratorProductsProductIdVariantsVariantId";
import { patchECommerceMallAdministratorProductsProductIdVariants } from "../../../../../providers/patchECommerceMallAdministratorProductsProductIdVariants";

@Controller("/eCommerceMall/administrator/products/:productId/variants")
export class EcommercemallAdministratorProductsVariantsController {
  /**
   * Retrieve a paginated, searchable list of product variants belonging to a specific product.
   *
   * This endpoint powers seller-side variant management — sellers view SKU codes, prices, current stock quantities, and option configurations (e.g., color, size) for all variants of a given product. It also serves the customer-facing product detail page's variant selector, showing purchasable configurations with prices and stock availability.
   *
   * Results are scoped to the product identified by `productId`. By default, only active (non-deleted) variants are returned. Each variant summary includes its option values as key-value pairs, the current stock quantity (derived as the sum of all inventory record quantity changes), and the effective price (variant price override, or the parent product's base price if no override is set).
   *
   * Search criteria support partial SKU code matching, stock status filtering (in stock vs. out of stock), and sorting by creation date or price. Standard pagination applies.
   *
   * If the specified product does not exist, a 404 Not Found error is returned. If the product has no variants, an empty page is returned (not an error).
   *
   * @param connection
   * @param productId Unique identifier (UUID) of the parent product whose variants are being listed. This scopes the search to variants belonging to a specific product.
   * @param body Search and pagination criteria for filtering product variants. Supports searching by SKU code (partial match), filtering by stock status (in stock / out of stock), and sorting by creation date or effective price. Includes standard pagination parameters (page, limit).
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Query the e_commerce_mall_product_variants table filtered by e_commerce_mall_product_id = productId and deleted_at IS NULL.
   *
   * Perform a LEFT JOIN with e_commerce_mall_product_variant_options to collect option values as an array of key-value objects for each variant.
   *
   * Derive current stock quantity by summing all e_commerce_mall_inventory_records.quantity_change values for the variant (SUM aggregation on all non-deleted inventory records). If no inventory records exist, stock = 0.
   *
   * Resolve effective price: if variant.price is not null, use it; otherwise fall back to the parent product's base_price (look up e_commerce_mall_products by id = productId).
   *
   * Search/filter support:
   * - Partial SKU code match using case-insensitive LIKE/ILIKE on sku_code.
   * - Stock status filter: 'in_stock' (derived stock > 0) vs 'out_of_stock' (derived stock = 0).
   *
   * Sorting support:
   * - Sort by created_at ascending/descending.
   * - Sort by effective price ascending/descending (requires joining product base price if variant.price is null).
   *
   * Paginate using standard page/limit parameters with offset-based pagination. Return total count for page metadata.
   *
   * Edge cases:
   * - productId not found → 404 Not Found.
   * - Product has no variants → empty page result (HTTP 200 with empty items array).
   * - Product is deleted or suspended → still return variant list (snapshot/historical access) or 404 depending on business context. Default: 404 for deleted products.
   * - Deleted variants (deleted_at IS NOT NULL) are excluded by default.
   * - A variant with no option records → return empty options array, not an error.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IECommerceMallProductVariant.IRequest,
  ): Promise<IPageIECommerceMallProductVariant.ISummary> {
    try {
      return await patchECommerceMallAdministratorProductsProductIdVariants({
        administrator,
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves the full details of a specific product variant by its unique identifier, scoped to the parent product.
   *
   * This endpoint returns comprehensive variant information including the SKU code, price override (if set), option values (such as color and size), and the current available stock quantity computed from inventory records. Use this endpoint on the product detail page to display variant selection options with prices and availability status to customers.
   *
   * The request requires both the parent product ID and the variant ID to ensure the variant belongs to the specified product. If the variant does not exist or does not belong to the specified product, a 404 Not Found response is returned.
   *
   * @param connection
   * @param productId The UUID identifier of the parent product that owns this variant (scope parameter).
   * @param variantId The UUID identifier of the product variant to retrieve.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Query e_commerce_mall_product_variants by variantId, filtering by e_commerce_mall_product_id = productId (to ensure the variant belongs to the specified product). Verify the variant exists and belongs to the given product. Return 404 if not found. Include the variant's option values from e_commerce_mall_product_variant_options (where deleted_at IS NULL). Compute current stock by summing quantity changes from e_commerce_mall_inventory_records. Exclude soft-deleted variants (deleted_at IS NULL) from response unless querying as seller/administrator who may view deleted variants. The response includes the variant's SKU code, price (or null if inheriting base price), option values as an array of key-value pairs, and the computed stock quantity.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":variantId")
  public async at(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedParam("variantId")
    variantId: string & tags.Format<"uuid">,
  ): Promise<IECommerceMallProductVariant> {
    try {
      return await getECommerceMallAdministratorProductsProductIdVariantsVariantId(
        {
          administrator,
          productId,
          variantId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
