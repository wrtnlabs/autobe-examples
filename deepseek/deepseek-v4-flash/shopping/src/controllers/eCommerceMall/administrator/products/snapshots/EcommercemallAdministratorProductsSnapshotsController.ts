import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IECommerceMallProductSnapshot } from "../../../../../api/structures/IECommerceMallProductSnapshot";
import { IPageIECommerceMallProductSnapshot } from "../../../../../api/structures/IPageIECommerceMallProductSnapshot";
import { AdministratorAuth } from "../../../../../decorators/AdministratorAuth";
import { AdministratorPayload } from "../../../../../decorators/payload/AdministratorPayload";
import { getECommerceMallAdministratorProductsProductIdSnapshotsSnapshotId } from "../../../../../providers/getECommerceMallAdministratorProductsProductIdSnapshotsSnapshotId";
import { patchECommerceMallAdministratorProductsProductIdSnapshots } from "../../../../../providers/patchECommerceMallAdministratorProductsProductIdSnapshots";

@Controller("/eCommerceMall/administrator/products/:productId/snapshots")
export class EcommercemallAdministratorProductsSnapshotsController {
  /**
   * Retrieves a paginated list of product snapshots for a specific product, ordered by creation timestamp descending (newest first).
   *
   * Product snapshots are immutable historical records automatically created whenever a seller edits a product. Each snapshot preserves the complete product state at the time of the edit, including the product name, description, base price, category assignment, all variant configurations, and all product images.
   *
   * Sellers can view snapshots of their own products only. Administrators can view snapshots of any product on the platform for oversight and dispute resolution purposes. Snapshots are preserved even after the product is deleted, ensuring a permanent audit trail.
   *
   * Each snapshot in the list includes the timestamp of capture and summary information about the preserved product state.
   *
   * @param connection
   * @param productId UUID identifier of the product whose snapshots are being retrieved (global scope).
   * @param body Search criteria for filtering product snapshots. Supports optional date-range filtering by creation timestamp and standard pagination parameters for controlling result set size and cursor position.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Query e_commerce_mall_product_snapshots filtered by e_commerce_mall_product_id = productId (UUID). Apply optional date-range filters on created_at. Order by created_at descending (newest first). Join with e_commerce_mall_product_snapshot_variants for variant count and e_commerce_mall_product_snapshot_images for image count. Return cursor-based pagination. Authorization: only the seller who owns the product (via e_commerce_mall_products.seller_id matching authenticated seller) or any administrator is allowed to view snapshots. Snapshots are immutable — always return active records (deleted_at is always null for snapshots but verify).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IECommerceMallProductSnapshot.IRequest,
  ): Promise<IPageIECommerceMallProductSnapshot.ISummary> {
    try {
      return await patchECommerceMallAdministratorProductsProductIdSnapshots({
        administrator,
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves a single product snapshot by its unique identifier for the specified product.
   *
   * Product snapshots are immutable historical records preserving the complete product state — name, description, base price, category — along with all variants and images at the moment of an edit. Snapshots are created automatically whenever a seller edits their product. They survive product deletion and provide an authoritative audit trail for dispute resolution and historical reference.
   *
   * Sellers can only view snapshots of their own products. Administrators can view snapshots of any product on the platform. Snapshots are displayed with their full reconstructed state including variant configurations (SKU codes, option values, prices) and image URLs with display order.
   *
   * @param connection
   * @param productId Unique identifier (UUID) of the product whose snapshot is being retrieved.
   * @param snapshotId Unique identifier (UUID) of the product snapshot to retrieve.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Query e_commerce_mall_product_snapshots by snapshotId and verify it belongs to the given productId. Include the related seller ownership check: the authenticated seller must own the parent product, unless the actor is an administrator.
   *
   * Include eager loading of:
   * - variantSnapshots (e_commerce_mall_product_snapshot_variants) — sku, name, price
   * - snapshotImages (e_commerce_mall_product_snapshot_images) — url, sort_order, ordered ascending by sort_order
   *
   * Even if the parent product is deleted (visibility='deleted'), the snapshot must still be accessible to the original seller and administrators.
   *
   * Return 404 if:
   * - The snapshot does not exist
   * - The snapshot does not belong to the specified product
   * - The requesting seller does not own the parent product
   *
   * Return 403 if a customer or guest attempts to access this endpoint. Snapshots are only viewable by the owning seller or administrators.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":snapshotId")
  public async at(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedParam("snapshotId")
    snapshotId: string & tags.Format<"uuid">,
  ): Promise<IECommerceMallProductSnapshot> {
    try {
      return await getECommerceMallAdministratorProductsProductIdSnapshotsSnapshotId(
        {
          administrator,
          productId,
          snapshotId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
