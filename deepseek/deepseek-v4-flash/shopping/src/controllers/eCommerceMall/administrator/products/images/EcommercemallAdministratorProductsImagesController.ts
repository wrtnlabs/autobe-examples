import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IECommerceMallProductImage } from "../../../../../api/structures/IECommerceMallProductImage";
import { AdministratorAuth } from "../../../../../decorators/AdministratorAuth";
import { AdministratorPayload } from "../../../../../decorators/payload/AdministratorPayload";
import { getECommerceMallAdministratorProductsProductIdImagesImageId } from "../../../../../providers/getECommerceMallAdministratorProductsProductIdImagesImageId";
import { patchECommerceMallAdministratorProductsProductIdImages } from "../../../../../providers/patchECommerceMallAdministratorProductsProductIdImages";

@Controller("/eCommerceMall/administrator/products/:productId/images")
export class EcommercemallAdministratorProductsImagesController {
  /**
   * Reorder the images of a product to set a new display sequence and thumbnail image.
   *
   * When a seller reorders images, they submit an ordered list of image IDs belonging to their product. The system assigns ascending sort_order values based on the array index: the first image ID receives sort_order 0 and becomes the product's thumbnail image displayed in search results, category listings, and wishlist views. All images appear on the product detail page in ascending sort_order order.
   *
   * Only the seller who owns the product can reorder its images — cross-seller image operations are rejected. After successful reordering, a product snapshot is created to preserve the updated image ordering state for historical reference and audit purposes.
   *
   * The reorder operation affects only the sort positions of existing images. Image URLs and identities remain unchanged. If a product has no images, the operation succeeds with an empty result.
   *
   * @param connection
   * @param productId UUID of the product whose images are being reordered (global scope).
   * @param body Ordered array of image IDs specifying the new display sequence. The first element receives sort_order 0 (thumbnail position), the second receives sort_order 1, and so on. All image IDs must belong to the specified product.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification 1. Authenticate the seller; extract seller_id from session.
   * 2. Fetch the product by productId; return 404 if not found.
   * 3. Verify the product's seller_id matches the authenticated seller; return 403 if mismatch (cross-seller denial per [311]).
   * 4. Validate all image IDs in the request belong to the specified product. Query e_commerce_mall_product_images WHERE id IN (...) AND e_commerce_mall_product_id = productId. If any image ID is missing or belongs to a different product, return 400.
   * 5. Begin a database transaction.
   * 6. Update each image's sort_order based on its index in the provided array: first element → sort_order 0, second → 1, etc.
   * 7. The unique constraint (e_commerce_mall_product_id, sort_order) requires that old sort_orders be cleared before new ones are assigned, OR update atomically by setting sort_order = (index * -1) first then flipping to positive. Use a two-phase update: first set all to negative offsets, then set to final positive values.
   * 8. Commit the transaction.
   * 9. After reorder, create a product snapshot to preserve the new image ordering (per [65] Snapshot Preservation).
   * 10. Return the updated image records sorted by the new sort_order.
   * 11. Edge case: if the request array is empty, all images remain unchanged (no-op).
   * 12. Edge case: if the product has no images, return an empty array immediately.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async reorder(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IECommerceMallProductImage.IReorder,
  ): Promise<IECommerceMallProductImage> {
    try {
      return await patchECommerceMallAdministratorProductsProductIdImages({
        administrator,
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves a single product image by its unique identifier, scoped to the parent product.
   *
   * This endpoint returns the full details of a specific product image including its file storage URL and sort position within the product's image set. The image is scoped to its parent product for access control, ensuring that only images belonging to the specified product are accessible.
   *
   * The response includes the image URL used for rendering across the platform (product detail page, search results, category listings, wishlist) and the sort_order value that determines the display sequence. The image with the lowest sort_order (typically 0) serves as the main thumbnail image. All images for a product are displayed on the product detail page in ascending sort order.
   *
   * **Access Control**: Authorization (seller ownership verification, customer visibility rules) is handled by the auth middleware layer. This endpoint returns the image record regardless of product visibility state when the caller has appropriate access rights.
   *
   * @param connection
   * @param productId UUID of the product that owns the image (global scope).
   * @param imageId UUID of the product image to retrieve (scoped to the specified product).
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Query e_commerce_mall_product_images table filtering by both id (imageId parameter) and e_commerce_mall_product_id (productId parameter).
   *
   * **Validation**:
   * 1. Verify the product exists in e_commerce_mall_products — return 404 if not found.
   * 2. Verify the image exists with the given id belonging to the specified product — return 404 if not found.
   * 3. Return 404 for both failure cases (missing product, missing image, or image not belonging to product) to avoid information leakage about which parameter is invalid.
   *
   * **Response**: Return the full image record: id, url, sort_order, created_at, updated_at. The image URL should be a fully resolvable URI for rendering.
   *
   * **Edge Cases**:
   * - Soft-deleted products (visibility='deleted'): the image record still exists in the database. Authorization middleware determines who can access deleted product images.
   * - Cross-resource access: if the imageId exists but belongs to a different product than productId, return 404.
   * - Single-record retrieval — no pagination needed.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":imageId")
  public async at(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedParam("imageId")
    imageId: string & tags.Format<"uuid">,
  ): Promise<IECommerceMallProductImage> {
    try {
      return await getECommerceMallAdministratorProductsProductIdImagesImageId({
        administrator,
        productId,
        imageId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
