import { postECommerceMallAdministratorSellersSellerIdUnsuspend } from "../../../../providers/postECommerceMallAdministratorSellersSellerIdUnsuspend";

@Controller("/eCommerceMall/administrator/sellers")
export class EcommercemallAdministratorSellersController {
  /**
   * Search and list seller accounts with filtering and pagination.
   *
   * This endpoint provides a paginated, filterable list of seller accounts on the platform. Each result includes the seller's email, current approval status (pending, approved, or rejected), and associated shop profile information such as shop name and logo. Administrators use this endpoint to browse and manage seller registrations, while sellers can also retrieve their own account details.
   *
   * Supports filtering by approval status, email address, and registration date range. Results are sorted by newest registration first by default, with configurable sort order. When a seller account has been soft-deleted (account deleted by the seller), the record is excluded from results unless explicitly requested.
   *
   * @param connection
   * @param body Search and filter criteria for seller account listing. Supports filtering by approval status, email partial match, registration date range, and pagination parameters.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Query the e_commerce_mall_sellers table with LEFT JOIN to e_commerce_mall_seller_profiles to include shop name and logo. Apply filters from request body: approval_status (enum: pending/approved/rejected), email (partial match), created_at range (start/end). Exclude soft-deleted records (deleted_at IS NULL) by default. Support pagination with page and limit parameters. Sort by created_at descending by default, with optional sort field and direction. Return paginated results using IPageIECommerceMallSeller.ISummary with seller id, email, approval_status, profile shop_name and logo, created_at, and soft-deleted status.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedBody()
    body: IECommerceMallSeller.IRequest,
  ): Promise<IPageIECommerceMallSeller.ISummary> {
    try {
      return await patchECommerceMallAdministratorSellers({
        administrator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a seller's account and public merchant profile by their unique identifier.
   *
   * The endpoint returns the seller's current approval status (pending, approved, or rejected) alongside their public-facing merchant profile — shop name, shop description, and logo image. The profile information is what customers see when viewing a seller's public profile page before making a purchase, providing transparency about the merchant they are buying from.
   *
   * The response combines data from the seller's authentication record and their shop profile through a one-to-one relationship. Sensitive information such as the password hash is excluded from the response for security purposes.
   *
   * Returns a 404 error if the seller ID does not match any active seller account or if the seller account has been soft-deleted.
   *
   * @param connection
   * @param sellerId Unique identifier (UUID) of the seller account to retrieve.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Query e_commerce_mall_sellers by id (UUID), joining with e_commerce_mall_seller_profiles via the one-to-one relationship on e_commerce_mall_seller_id.
   *
   * Exclude soft-deleted sellers (deleted_at IS NOT NULL) — return 404 if the seller is not found or has been soft-deleted.
   *
   * Include the seller's approval_status and all profile fields (shop_name, shop_description, logo_image). Use a LEFT JOIN on the profile since a seller might not have a profile created yet (e.g., during pending approval before profile setup).
   *
   * Do NOT expose the password_hash field in the response.
   *
   * Edge cases: If sellerId is not a valid UUID format, return 400 Bad Request. If the UUID is valid but no active seller matches, return 404 Not Found.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sellerId")
  public async at(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
  ): Promise<IECommerceMallSeller> {
    try {
      return await getECommerceMallAdministratorSellersSellerId({
        administrator,
        sellerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Suspend a seller account, immediately restricting their selling capabilities on the platform.
   *
   * When a seller is suspended, their products are hidden from search results and category listings, cannot be purchased by customers, and the seller loses the ability to create new products or edit existing ones. The seller retains limited access to process existing orders — including creating shipments, responding to pending cancellation requests, and responding to pending refund requests.
   *
   * An optional reason may be provided to document the rationale for the suspension. The action is recorded in an immutable audit log for governance and dispute resolution purposes.
   *
   * @param connection
   * @param sellerId The unique identifier of the seller account to suspend (UUID, global scope).
   * @param body The reason for suspending the seller account, if any. Provides documentation for the administrative action.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Validate that the requester is an administrator or super administrator. Validate that the target seller exists and is not already suspended (check suspension logs for most recent action — if the latest log entry for this seller has action 'suspend' and no subsequent 'unsuspend', reject). Insert a record into e_commerce_mall_seller_suspension_logs with action='suspend', the provided reason (if any), and actor_type='administrator' or 'superAdministrator' depending on the requester's role. Create the corresponding subtype record in e_commerce_mall_seller_suspension_log_of_administrators or e_commerce_mall_seller_suspension_log_of_super_administrators to link the log to the specific actor. Return the seller entity.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post(":sellerId/suspend")
  public async suspend(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IECommerceMallSeller.ISuspend,
  ): Promise<IECommerceMallSeller> {
    try {
      return await postECommerceMallAdministratorSellersSellerIdSuspend({
        administrator,
        sellerId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Unsuspend a seller account to restore full selling privileges.
   *
   * Administrators can reinstate a previously suspended seller account. When a seller is unsuspended, their products become visible in search results and category listings, and they regain the ability to create new products and edit existing ones. The unsuspension action is recorded in the immutable audit log for governance and dispute resolution.
   *
   * The acting administrator may optionally provide a reason for the unsuspension, which will be stored in the audit trail for future reference.
   *
   * @param connection
   * @param sellerId The unique identifier (UUID) of the seller account to unsuspend.
   * @param body Optional free-text reason for unsuspending the seller account. This reason is recorded in the audit log for governance and dispute resolution purposes.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Verify the acting user is an authenticated administrator or super administrator.
   * Verify the seller with the given sellerId exists and is not soft-deleted.
   * Verify the seller account is currently in a suspended state.
   * Update the seller's approval_status to "approved" to restore selling privileges.
   * Create an entry in e_commerce_mall_seller_suspension_logs with action="unsuspend", the provided reason (if any), and actor_type set to "administrator" or "super_administrator" based on the acting user's role.
   * Insert the corresponding subtype record in e_commerce_mall_seller_suspension_log_of_administrators or e_commerce_mall_seller_suspension_log_of_super_administrators.
   * All database operations must be wrapped in a transaction.
   * Return the updated seller entity with restored status.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post(":sellerId/unsuspend")
  public async unsuspend(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IECommerceMallSeller.IUnsuspend,
  ): Promise<IECommerceMallSeller> {
    try {
      return await postECommerceMallAdministratorSellersSellerIdUnsuspend({
        administrator,
        sellerId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Unban a seller account, restoring the seller's ability to log into the platform.
   *
   * This operation is performed by an administrator or super administrator to reverse a previous seller ban. When a seller is unbanned, they regain access to their account using their existing email and password credentials.
   *
   * All existing orders, products, order history, and data associated with the seller remain unaffected by the unban action. The seller's products remain visible or hidden according to their current account status (e.g., suspension state is independent of ban state).
   *
   * Note that unbanning follows the administrator grade hierarchy: if the seller was banned by a super administrator, only a super administrator can perform the unban; regular administrators cannot unban sellers banned by super administrators.
   *
   * @param connection
   * @param sellerId Unique identifier (UUID) of the seller account to unban. This references the seller whose login ability will be restored.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Unban a seller account by clearing the seller's ban status.
   *
   * 1. Validate that the requesting actor is an administrator (or super administrator) with appropriate authorization.
   * 2. Verify the seller exists and is currently banned (not already unbanned).
   * 3. Clear the seller's ban status (set banned_at to null) to restore login ability.
   * 4. Preserve all existing orders, products, order history, and snapshots — unbanning does not modify any of these.
   * 5. After unban, the seller can log in normally using their existing email and password.
   * 6. If the seller was previously suspended (not banned), this operation should not proceed — only handle ban reversal.
   * 7. Return the updated seller record reflecting the unbanned state.
   *
   * Error handling:
   * - Return 404 if the seller does not exist
   * - Return 409 if the seller is not currently banned
   * - Return 403 if the requesting actor lacks permission (e.g., regular admin trying to unban a super-admin-banned seller)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post(":sellerId/unban")
  public async unban(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
  ): Promise<IECommerceMallSeller> {
    try {
      return await postECommerceMallAdministratorSellersSellerIdUnban({
        administrator,
        sellerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
