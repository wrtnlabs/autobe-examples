import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IECommerceMallCustomerAddress } from "../../../../../api/structures/IECommerceMallCustomerAddress";
import { IPageIECommerceMallCustomerAddress } from "../../../../../api/structures/IPageIECommerceMallCustomerAddress";
import { AdministratorAuth } from "../../../../../decorators/AdministratorAuth";
import { AdministratorPayload } from "../../../../../decorators/payload/AdministratorPayload";
import { getECommerceMallAdministratorCustomersCustomerIdAddressesAddressId } from "../../../../../providers/getECommerceMallAdministratorCustomersCustomerIdAddressesAddressId";
import { patchECommerceMallAdministratorCustomersCustomerIdAddresses } from "../../../../../providers/patchECommerceMallAdministratorCustomersCustomerIdAddresses";

@Controller("/eCommerceMall/administrator/customers/:customerId/addresses")
export class EcommercemallAdministratorCustomersAddressesController {
  /**
   * Retrieve a paginated list of active shipping addresses for the specified customer.
   *
   * The response includes all non-deleted addresses belonging to the customer, with each address showing the full recipient and location details — recipient name, phone number, street address, city, state/province, postal code, and country. The default shipping address is clearly indicated via the `isDefault` field, allowing the UI to pre-select or highlight it when the customer proceeds to checkout.
   *
   * Results are sorted by creation date (newest first) by default. Optional filtering by the `isDefault` flag is supported to find only the default address, and a text search across recipient name, street address, city, state/province, postal code, and country fields enables quick address lookup for customers with many saved addresses.
   *
   * Soft-deleted addresses are excluded from results. Addresses that were used in completed historical orders but were deleted from the customer's active address list will not appear here — those remain accessible only via the historical order records that captured them as snapshots.
   *
   * @param connection
   * @param customerId Unique identifier (UUID) of the customer whose shipping addresses are being retrieved. This scopes the query to addresses owned exclusively by that customer.
   * @param body Search and pagination criteria for listing active shipping addresses. Supports optional text search across recipient name, street address, city, state/province, postal code, and country fields; optional filtering by default address status (isDefault flag); and standard pagination parameters (page, limit) for result set control.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Query the e_commerce_mall_customer_addresses table filtered by e_commerce_mall_customer_id matching the customerId path parameter (UUID). Exclude soft-deleted records with WHERE deleted_at IS NULL. Support pagination using page and limit fields from the request body. Default sort order by created_at DESC (newest first).
   *
   * Filtering support in the request body:
   * - search: optional string — case-insensitive text search across recipient_name, street_address, city, state_province, postal_code, and country fields using LIKE patterns, combined with OR logic.
   * - isDefault: optional boolean — when provided, filter by is_default = true/false.
   *
   * Response fields for ISummary should include: id, recipientName, phoneNumber, streetAddress, city, stateProvince, postalCode, country, isDefault, createdAt. Exclude deleted_at, updated_at from the summary.
   *
   * Edge cases:
   * - If the customer (e_commerce_mall_customer_id) does not exist, return 404 Not Found.
   * - If the customer exists but has no addresses, return an empty paginated response (page with empty data array, total = 0).
   * - The isDefault flag filtering is straightforward since only one address per customer can be default (enforced at application layer).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("customerId")
    customerId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IECommerceMallCustomerAddress.IRequest,
  ): Promise<IPageIECommerceMallCustomerAddress.ISummary> {
    try {
      return await patchECommerceMallAdministratorCustomersCustomerIdAddresses({
        administrator,
        customerId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves a single shipping address by ID for the specified customer.
   *
   * This operation allows a customer to view the full details of one of their saved shipping addresses, including recipient information, location fields, and the default address flag. The address must belong to the authenticated customer — customers cannot access addresses owned by other users.
   *
   * If the address has been soft-deleted (e.g., removed from the active address list but still referenced by historical orders), this operation returns a 404 Not Found error since deleted addresses are not accessible through active retrieval endpoints. For deleted addresses, the customer should use the order detail endpoint which preserves the address snapshot captured at checkout time.
   *
   * @param connection
   * @param customerId UUID of the customer who owns the address (global scope).
   * @param addressId UUID of the address to retrieve, scoped to the specified customer.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Query the e_commerce_mall_customer_addresses table by id and e_commerce_mall_customer_id, filtering out soft-deleted records (deleted_at IS NULL).
   *
   * Use the authenticated customer's ID to enforce the e_commerce_mall_customer_id match — ensure the requesting customer owns this address. Return 404 Not Found if no matching active address is found.
   *
   * Return all columns: id, e_commerce_mall_customer_id, recipient_name, phone_number, street_address, city, state_province, postal_code, country, is_default, created_at, updated_at. Do NOT include deleted_at in the response.
   *
   * Edge case: If the address exists but belongs to a different customer (customerId mismatch), return 404 Not Found (not 403 Forbidden) to avoid leaking information about other customers' addresses.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":addressId")
  public async at(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("customerId")
    customerId: string & tags.Format<"uuid">,
    @TypedParam("addressId")
    addressId: string & tags.Format<"uuid">,
  ): Promise<IECommerceMallCustomerAddress> {
    try {
      return await getECommerceMallAdministratorCustomersCustomerIdAddressesAddressId(
        {
          administrator,
          customerId,
          addressId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
