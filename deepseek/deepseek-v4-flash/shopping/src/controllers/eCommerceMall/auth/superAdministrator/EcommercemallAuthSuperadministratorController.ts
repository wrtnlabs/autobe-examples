import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IECommerceMallSuperAdministrator } from "../../../../api/structures/IECommerceMallSuperAdministrator";
import { postECommerceMallAuthSuperAdministratorJoin } from "../../../../providers/postECommerceMallAuthSuperAdministratorJoin";
import { postECommerceMallAuthSuperAdministratorLogin } from "../../../../providers/postECommerceMallAuthSuperAdministratorLogin";
import { postECommerceMallAuthSuperAdministratorRefresh } from "../../../../providers/postECommerceMallAuthSuperAdministratorRefresh";

@Controller("/eCommerceMall/auth/superAdministrator")
export class EcommercemallAuthSuperadministratorController {
  /**
   * Creates a new super administrator account by promoting an existing regular administrator to super administrator status.
   *
   * This operation is performed exclusively by an existing super administrator. The promoting super administrator specifies the target regular administrator account to be elevated. A new super administrator record is created with a 1:1 link to the existing administrator's record via the `e_commerce_mall_administrator_id` foreign key.
   *
   * Upon successful promotion, the operation returns JWT access and refresh tokens for the newly created super administrator, establishing their first authenticated session. The session records the client IP address, request URL, and referrer for audit trail purposes, with a defined expiration time.
   *
   * This is a privileged operation restricted to existing super administrators, enforcing the platform's governance model where only super administrators can expand the super administrator roster.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Request payload for super administrator account creation through promotion. Contains the target administrator ID, the desired super administrator email, and password credential.
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor superAdministrator
   * @x-autobe-specification Create a new superAdministrator record by linking to an existing administrator record. The requesting superAdministrator provides the target administrator's ID, email, and password. Validate that the administrator exists, is not already a superAdministrator, and that the email is unique. Hash the password with bcrypt. Create both the superAdministrator record and a session record (with ip, href, referrer from request), then return JWT access+refresh tokens with session expiration.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IECommerceMallSuperAdministrator.IJoin,
  ): Promise<IECommerceMallSuperAdministrator.IAuthorized> {
    try {
      return await postECommerceMallAuthSuperAdministratorJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticates a super administrator using email and password credentials.
   *
   * The super administrator provides their registered email address and password. The system verifies the credentials against the stored `password_hash` in the `e_commerce_mall_super_administrators` table using secure hash comparison.
   *
   * Upon successful authentication, a new session is created in `e_commerce_mall_super_administrator_sessions` recording the client IP address, request URL, and HTTP referrer for security auditing. The session has a mandatory expiration time. JWT access and refresh tokens are returned to authorize subsequent API requests.
   *
   * If the account has been soft-deleted (`deleted_at` is set), authentication is denied regardless of credential validity.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Login credentials containing the super administrator's email address and password for authentication.
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor superAdministrator
   * @x-autobe-specification Validate the email and password_hash combination against the e_commerce_mall_super_administrators table. Use bcrypt.compare for password verification. On success, create a session record in e_commerce_mall_super_administrator_sessions with ip, href, referrer, created_at, and expired_at. Generate JWT access token and refresh token. On failure, return 401 Unauthorized.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IECommerceMallSuperAdministrator.ILogin,
  ): Promise<IECommerceMallSuperAdministrator.IAuthorized> {
    try {
      return await postECommerceMallAuthSuperAdministratorLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Obtains new JWT access and refresh tokens using a valid refresh token.
   *
   * The super administrator provides their current refresh token. The system validates the token against the stored session records and checks that the session has not expired (`expired_at` has not passed).
   *
   * On successful validation, new JWT access and refresh tokens are issued, extending the authenticated session. This allows the super administrator to maintain continuous authenticated access without re-entering credentials.
   *
   * Invalid, expired, or revoked refresh tokens result in authentication failure, requiring the super administrator to log in again.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token payload containing the existing refresh token to be exchanged for new authentication tokens.
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor superAdministrator
   * @x-autobe-specification Validate the provided refresh token. Find the associated superAdministrator session. Verify the session is not expired (expired_at > now). Invalid or expired tokens return 401. On success, generate new JWT access token and a new refresh token. Update the session's expiration.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IECommerceMallSuperAdministrator.IRefresh,
  ): Promise<IECommerceMallSuperAdministrator.IAuthorized> {
    try {
      return await postECommerceMallAuthSuperAdministratorRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
