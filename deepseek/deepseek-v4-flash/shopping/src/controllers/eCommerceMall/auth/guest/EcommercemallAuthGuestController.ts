import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IECommerceMallGuest } from "../../../../api/structures/IECommerceMallGuest";
import { postECommerceMallAuthGuestJoin } from "../../../../providers/postECommerceMallAuthGuestJoin";
import { postECommerceMallAuthGuestRefresh } from "../../../../providers/postECommerceMallAuthGuestRefresh";

@Controller("/eCommerceMall/auth/guest")
export class EcommercemallAuthGuestController {
  /**
   * Register a new guest account on the e-commerce platform using a unique device or browser fingerprint identifier.
   *
   * Guest accounts provide temporary, unauthenticated access identified by a device_identifier collected client-side via fingerprinting techniques. Upon successful registration, the system creates or reuses a guest record and an associated session, then returns JWT authentication tokens (access and refresh) for subsequent API calls within the authentication boundary (login and registration pages only).
   *
   * The device_identifier uniquely identifies a device or browser across visits. If a guest record already exists for the given device_identifier, the existing guest is reused with a new session rather than creating a duplicate. This ensures each device maintains a consistent guest identity for session continuity, rate limiting, and CSRF protection.
   *
   * The guest's IP address is automatically captured server-side from the HTTP request context. The href (current page URL) and referrer (previous page URL) parameters track navigation context. Session expiration (expired_at) is set at creation time; expired sessions require the refresh endpoint to obtain a new session.
   *
   * Security considerations: Rate limiting per device fingerprint prevents registration abuse. Guest sessions are automatically invalidated upon transition to a registered actor (customer, seller, administrator) via login or registration. Soft-delete support allows guest data retention for analytics and security auditing before permanent cleanup.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Device identifier and page context for guest registration.
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification Register a new guest account using a device fingerprint. Steps: 1) Extract device_identifier, href, referrer from the request body. 2) Query e_commerce_mall_guests by device_identifier where deleted_at IS NULL. 3) If found, reuse the existing guest record (if soft-deleted, reactivate by setting deleted_at to NULL). 4) If not found, INSERT a new guest record with the device_identifier and current timestamps. 5) Capture the client IP from the HTTP request context. 6) INSERT a new guest_session record: id (UUID), e_commerce_mall_guest_id (guest.id), ip (from request), href, referrer, created_at (now), expired_at (now + session TTL, e.g. 24 hours). 7) Generate JWT access token (short-lived, e.g. 15 minutes) and JWT refresh token (long-lived, matching session expiration). 8) Return IECommerceMallGuest.IAuthorized containing tokens and session metadata. Error cases: Rate limiting per device_identifier to prevent abuse.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IECommerceMallGuest.IJoin,
  ): Promise<IECommerceMallGuest.IAuthorized> {
    try {
      return await postECommerceMallAuthGuestJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh an existing guest session by exchanging a valid refresh token for a new set of authentication tokens with an extended session lifetime.
   *
   * Guest sessions have a limited lifetime defined by the expired_at timestamp. When a session expires or approaches expiration, the guest can use their refresh token to obtain a new session with updated tokens without re-registering. The old session is invalidated upon successful refresh, and a new session is created with a fresh expiration timestamp.
   *
   * The refresh token is a long-lived JWT issued during guest registration (join). Each refresh operation follows token rotation — the old refresh token is consumed and a new one is issued. The request body includes the current href and referrer for accurate session context tracking.
   *
   * The guest's current IP address is captured server-side. Expired, invalid, or already-consumed refresh tokens return a 401 Unauthorized error, requiring the guest to re-register via the join endpoint.
   *
   * Security considerations: Token rotation mitigates the risk of stolen refresh tokens. If a previously rotated refresh token is presented (reuse detection), all active sessions for that guest should be invalidated as a precaution against token theft. Rate limiting per guest identity or IP address prevents brute-force refresh attempts.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token and page context for session renewal.
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification Refresh a guest session by exchanging a valid refresh token. Steps: 1) Extract refreshToken, href, and referrer from the request body. 2) Validate the refresh token JWT (verify signature, check expiration). 3) Look up the associated guest_session by matching the refresh token's jti or stored token reference. 4) Verify the session's expired_at is still in the future; if expired return 401. 5) Invalidate the old session (update expired_at to now() or soft-delete). 6) Capture the client's current IP from the request context. 7) INSERT a new guest_session with updated ip, href, referrer, and new expiration. 8) Generate new JWT access token (short-lived) and new refresh token (long-lived). 9) Return IECommerceMallGuest.IAuthorized with new tokens. Error cases: invalid/expired refresh token → 401. Token reuse detection: if a previously rotated refresh token is presented, invalidate ALL sessions for that guest as a precaution against token theft.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IECommerceMallGuest.IRefresh,
  ): Promise<IECommerceMallGuest.IAuthorized> {
    try {
      return await postECommerceMallAuthGuestRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
