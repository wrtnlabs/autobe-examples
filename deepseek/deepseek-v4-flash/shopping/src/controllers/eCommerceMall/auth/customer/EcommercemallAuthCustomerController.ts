import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IECommerceMallCustomer } from "../../../../api/structures/IECommerceMallCustomer";
import { postECommerceMallAuthCustomerJoin } from "../../../../providers/postECommerceMallAuthCustomerJoin";
import { postECommerceMallAuthCustomerLogin } from "../../../../providers/postECommerceMallAuthCustomerLogin";
import { postECommerceMallAuthCustomerRefresh } from "../../../../providers/postECommerceMallAuthCustomerRefresh";

@Controller("/eCommerceMall/auth/customer")
export class EcommercemallAuthCustomerController {
  /**
   * Register a new customer account on the platform.
   *
   * Customers sign up with a unique email address and a password. The email address serves as the unique identifier for the customer account, enforced by the unique constraint on e_commerce_mall_customers.email. If the email address is already associated with an existing customer account, the registration request is rejected with a conflict error.
   *
   * Upon successful registration, the customer account is created with the provided email and password (stored as a bcrypt hash in password_hash). A corresponding customer profile record is created in e_commerce_mall_customer_profiles with empty display_name and phone_number defaults. The customer is immediately able to log in and access platform features.
   *
   * An active session is established at registration time. The session metadata (IP address, page URL, HTTP referrer) is captured in e_commerce_mall_customer_sessions for audit purposes. Access and refresh tokens are returned to authenticate subsequent API calls.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Customer registration credentials including email address and password. The email must not already be associated with an existing customer account.
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification POST endpoint for customer registration. Validates email uniqueness via unique index on e_commerce_mall_customers.email. Bcrypt-hashes the password and stores in password_hash. Creates row in e_commerce_mall_customers with id (UUID), email, password_hash, created_at, updated_at. Creates corresponding e_commerce_mall_customer_profiles row (1:1 with empty display_name and phone_number). Generates JWT access+refresh tokens, creates session record in e_commerce_mall_customer_sessions (ip, href, referrer from request metadata, expired_at=now+config duration). Returns IECommerceMallCustomer.IAuthorized with tokens. If email already exists, reject 409 Conflict.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IECommerceMallCustomer.IJoin,
  ): Promise<IECommerceMallCustomer.IAuthorized> {
    try {
      return await postECommerceMallAuthCustomerJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate a customer using their email and password credentials.
   *
   * The system queries e_commerce_mall_customers by the provided email address. If no matching account is found, the login request is rejected with an unauthorized error — this prevents disclosing whether a particular email is registered.
   *
   * If the account exists but the password (verified against the bcrypt hash in password_hash) is incorrect, the request is rejected. If the customer account has been banned by an administrator (banned_at is set), the customer cannot log in. If the account has been soft-deleted (deleted_at is set), the customer cannot log in.
   *
   * After successful authentication, the customer is granted access to their profile, addresses, wishlist, cart, orders, and other customer features. An active session is established with its metadata captured in e_commerce_mall_customer_sessions. Access and refresh tokens are returned for subsequent authenticated API calls.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Customer login credentials including email address and password for authentication against the e_commerce_mall_customers table.
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification POST endpoint for customer login. Queries e_commerce_mall_customers by email. If not found, reject 401 Unauthorized. If found, check banned_at — if non-null, reject (banned customers cannot log in per section 36). Check deleted_at — if non-null, reject (deleted account). Verify password_hash against provided password using bcrypt.compare. On success, generate JWT access+refresh tokens, create session in e_commerce_mall_customer_sessions with ip, href, referrer, expired_at. Return IECommerceMallCustomer.IAuthorized.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IECommerceMallCustomer.ILogin,
  ): Promise<IECommerceMallCustomer.IAuthorized> {
    try {
      return await postECommerceMallAuthCustomerLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh authentication tokens for an existing customer session.
   *
   * Issues a new access token and refresh token when a valid refresh token is provided. This extends the customer's authenticated session without requiring re-authentication via email and password, providing a seamless user experience.
   *
   * The refresh token is validated against the existing session record in e_commerce_mall_customer_sessions. If the session has expired (expired_at timestamp is in the past), the refresh request is rejected and the customer must log in again with their credentials.
   *
   * Token refresh maintains security through mandatory session expiration while allowing customers to remain authenticated across page loads and browser sessions. The previous refresh token is invalidated upon successful refresh.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token obtained from a previous authentication response. Used to obtain a new access token without requiring the customer to re-enter their email and password credentials.
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification POST endpoint for token refresh. Validates the provided refresh token against e_commerce_mall_customer_sessions. Checks the session is not expired (expired_at > now). Generates new access token and refresh token with extended expiry. Updates session record with new expired_at or creates new session. Returns IECommerceMallCustomer.IAuthorized with new tokens. If session expired or token invalid, reject 401 Unauthorized.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IECommerceMallCustomer.IRefresh,
  ): Promise<IECommerceMallCustomer.IAuthorized> {
    try {
      return await postECommerceMallAuthCustomerRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
