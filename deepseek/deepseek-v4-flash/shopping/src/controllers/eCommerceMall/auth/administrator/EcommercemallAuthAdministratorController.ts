import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IECommerceMallAdministrator } from "../../../../api/structures/IECommerceMallAdministrator";
import { postECommerceMallAuthAdministratorJoin } from "../../../../providers/postECommerceMallAuthAdministratorJoin";
import { postECommerceMallAuthAdministratorLogin } from "../../../../providers/postECommerceMallAuthAdministratorLogin";
import { postECommerceMallAuthAdministratorRefresh } from "../../../../providers/postECommerceMallAuthAdministratorRefresh";

@Controller("/eCommerceMall/auth/administrator")
export class EcommercemallAuthAdministratorController {
  /**
   * Register a new administrator account on the platform.\n\nCreates an administrator account using the provided email and password credentials. The email must be unique across all administrators — attempting to register with an already-registered email results in a conflict error. The password is securely hashed before storage.\n\nUpon successful registration, the administrator is automatically authenticated: a JWT access token and refresh token are issued and returned in the response body. A session record is created in the e_commerce_mall_administrator_sessions table tracking the client IP address and request URL for audit purposes.\n\nThis endpoint is accessible to administrator actor context and allows initial account creation. After registration, the administrator can use the returned tokens for subsequent authenticated API requests.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Credentials for creating a new administrator account — email address and password.
     * @x-autobe-authorization-type join
     * @x-autobe-authorization-actor administrator
     * @x-autobe-specification Create a new administrator account with the
     *   provided email and password. Validate that the email is not already in
     *   use (unique constraint on e_commerce_mall_administrators.email). Hash
     *   the password using a strong algorithm (bcrypt). Create a session record
     *   in e_commerce_mall_administrator_sessions capturing the client IP and
     *   request URL. Generate and return a JWT access token and refresh token.
     *   Return 409 Conflict if email already exists. Return 400 Bad Request for
     *   invalid email format or weak password.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IECommerceMallAdministrator.IJoin,
  ): Promise<IECommerceMallAdministrator.IAuthorized> {
    try {
      return await postECommerceMallAuthAdministratorJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate an existing administrator using email and password credentials.\n\nValidates the provided email against the e_commerce_mall_administrators table and verifies the password against the stored password_hash. Only active (non-deleted) administrator accounts can log in — soft-deleted accounts are rejected.\n\nUpon successful authentication, a new session is created in the e_commerce_mall_administrator_sessions table recording the client IP and request URL for security auditing. A JWT access token and refresh token are issued and returned, providing authenticated access to all administrator endpoints.\n\nThis endpoint is accessible to administrator actor context.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Administrator login credentials — registered email address and corresponding password.
     * @x-autobe-authorization-type login
     * @x-autobe-authorization-actor administrator
     * @x-autobe-specification Authenticate an administrator using email and
     *   password. Look up the administrator by email in
     *   e_commerce_mall_administrators (checking deleted_at is null — account
     *   not soft-deleted). Compare the provided password against password_hash
     *   using bcrypt. On success, create a session record in
     *   e_commerce_mall_administrator_sessions with client IP and request URL.
     *   Generate and return new JWT access and refresh tokens. Return 404 Not
     *   Found if email does not exist. Return 401 Unauthorized if password is
     *   incorrect.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IECommerceMallAdministrator.ILogin,
  ): Promise<IECommerceMallAdministrator.IAuthorized> {
    try {
      return await postECommerceMallAuthAdministratorLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Issue a new JWT access token using a valid refresh token from a previous authentication.\n\nValidates the provided refresh token against the e_commerce_mall_administrator_sessions table, checking that the session exists, has not yet expired (expired_at is in the future), and is associated with an active, non-deleted administrator account.\n\nOn successful validation, a new JWT access token is issued and returned alongside the existing or rotated refresh token. This allows administrators to maintain authenticated sessions without re-entering credentials, improving the user experience for long-running administrative tasks.\n\nThis endpoint is accessible to administrator actor context.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token obtained from a previous authentication (join or login) to request new access tokens.
     * @x-autobe-authorization-type refresh
     * @x-autobe-authorization-actor administrator
     * @x-autobe-specification Issue a new JWT access token using a valid
     *   refresh token. Validate the refresh token from the request body against
     *   the e_commerce_mall_administrator_sessions table — check that the
     *   session exists, has not expired (expired_at in the future), and belongs
     *   to an active administrator account. Generate a new access token and
     *   optionally rotate the refresh token. Return 401 Unauthorized if the
     *   refresh token is invalid, expired, or the associated account is
     *   deleted.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IECommerceMallAdministrator.IRefresh,
  ): Promise<IECommerceMallAdministrator.IAuthorized> {
    try {
      return await postECommerceMallAuthAdministratorRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
