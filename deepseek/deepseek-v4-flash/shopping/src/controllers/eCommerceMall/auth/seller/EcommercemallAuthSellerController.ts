import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IECommerceMallSeller } from "../../../../api/structures/IECommerceMallSeller";
import { postECommerceMallAuthSellerJoin } from "../../../../providers/postECommerceMallAuthSellerJoin";
import { postECommerceMallAuthSellerLogin } from "../../../../providers/postECommerceMallAuthSellerLogin";
import { postECommerceMallAuthSellerRefresh } from "../../../../providers/postECommerceMallAuthSellerRefresh";

@Controller("/eCommerceMall/auth/seller")
export class EcommercemallAuthSellerController {
  /**
   * Register a new seller account on the platform.
   *
   * A prospective seller registers by providing their email address and password, along with shop profile information (shop name, shop description, and optional logo image). The email address serves as the unique login identifier for the seller account. If the email is already associated with an existing seller account, the registration request is rejected with a 409 Conflict response.
   *
   * Upon successful registration, the seller account is created with an approval status of 'pending'. The seller cannot list products or use selling features until an administrator approves the account. A JWT access token and refresh token are issued in the response for authenticating subsequent API requests.
   *
   * The shop profile is established during registration and can be updated later by the seller via the profile management endpoints. Each seller account has exactly one shop profile record.
   *
   * This endpoint is public and does not require prior authentication.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Seller registration credentials including email, password, and shop profile information (shop name, description, and optional logo image URI).
     * @x-autobe-authorization-type join
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Create a new seller account with email and
     *   password. Validate email uniqueness (unique constraint on
     *   sellers.email). Hash password using bcrypt. Set approval_status to
     *   'pending'. Create associated seller_profile record with shop_name,
     *   shop_description, logo_image from request. Create session in
     *   e_commerce_mall_seller_sessions capturing ip, href, referrer,
     *   expired_at. Generate JWT access token and refresh token. Return
     *   IECommerceMallSeller.IAuthorized with tokens. On email collision,
     *   return 409 Conflict.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IECommerceMallSeller.IJoin,
  ): Promise<IECommerceMallSeller.IAuthorized> {
    try {
      return await postECommerceMallAuthSellerJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate a seller using their registered email address and password.
   *
   * Sellers authenticate by providing their email and password combination. The system verifies the credentials against the stored seller record. If the email does not match any seller account, or if the password is incorrect, the login request is rejected with a 401 Unauthorized response.
   *
   * Upon successful authentication, a JWT access token and refresh token are issued. The access token is sent with subsequent API requests for authorization, while the refresh token is used to obtain a new access token when the current one expires.
   *
   * Deleted (soft-deleted) seller accounts cannot log in. Suspended sellers can still log in with restricted access appropriate to their suspension status, as suspension does not revoke authentication capability per platform requirements.
   *
   * This endpoint is public and does not require prior authentication.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Seller login credentials including the registered email address and password.
     * @x-autobe-authorization-type login
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Authenticate seller by email and password. Look
     *   up seller by email in e_commerce_mall_sellers. Verify password_hash
     *   matches using bcrypt. Check deleted_at is null (account not deleted).
     *   Per requirements, suspended sellers can still log in (suspension
     *   doesn't invalidate sessions or prevent login), so no suspension check
     *   needed. Create session in e_commerce_mall_seller_sessions. Generate JWT
     *   access and refresh tokens. Return IECommerceMallSeller.IAuthorized. On
     *   invalid credentials, return 401 Unauthorized.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IECommerceMallSeller.ILogin,
  ): Promise<IECommerceMallSeller.IAuthorized> {
    try {
      return await postECommerceMallAuthSellerLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Obtain a new JWT access token using a valid refresh token.
   *
   * When a seller's access token expires, they can present their valid refresh token to obtain a new access token without re-entering their credentials. The refresh token is validated against the seller's active session records.
   *
   * Upon successful validation, a new JWT access token and a new refresh token are issued. The old refresh token is invalidated (refresh token rotation) to prevent token reuse and enhance security. If the refresh token is expired, invalid, or the seller account has been deleted, the request is rejected with a 401 Unauthorized response.
   *
   * This mechanism allows sellers to maintain continuous authenticated access to the platform without repeated logins, while enforcing session expiration for security.
   *
   * This endpoint requires a valid refresh token in the request body — it does not require prior authentication via access token.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body The valid refresh token used to obtain a new JWT access token and refresh token pair.
     * @x-autobe-authorization-type refresh
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Issue a new JWT access token using a valid
     *   refresh token. Validate the refresh token against the seller's session
     *   records. Verify the session is not expired (expired_at > now). Look up
     *   the associated seller from the session. Verify seller is not deleted
     *   (deleted_at is null). Generate a new access token and rotate the
     *   refresh token (create new session, invalidate old one). Return
     *   IECommerceMallSeller.IAuthorized with new tokens. On invalid/expired
     *   token, return 401 Unauthorized.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IECommerceMallSeller.IRefresh,
  ): Promise<IECommerceMallSeller.IAuthorized> {
    try {
      return await postECommerceMallAuthSellerRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
