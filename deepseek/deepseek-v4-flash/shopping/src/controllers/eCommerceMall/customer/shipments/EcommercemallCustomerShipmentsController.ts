import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IECommerceMallShipment } from "../../../../api/structures/IECommerceMallShipment";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { getECommerceMallCustomerShipmentsShipmentId } from "../../../../providers/getECommerceMallCustomerShipmentsShipmentId";
import { putECommerceMallCustomerShipmentsShipmentId } from "../../../../providers/putECommerceMallCustomerShipmentsShipmentId";

@Controller("/eCommerceMall/customer/shipments/:shipmentId")
export class EcommercemallCustomerShipmentsController {
  /**
   * Retrieve a single shipment by its unique identifier.
   *
   * Returns the complete shipment record including carrier name, tracking number, shipping timestamp, and delivery confirmation timestamp. The response also includes all order items contained within this shipment, each with its product variant reference, quantity, unit price at the time of purchase, and current fulfillment status (paid, shipped, delivered, cancelled, or refunded).
   *
   * This endpoint serves multiple actors: sellers use it to view tracking details of their dispatched packages, customers use it to track delivery progress of their orders (accessible through order detail pages), and administrators use it for platform order oversight. The shipment's seller association and the related order information are accessible through the respective reference fields in the response.
   *
   * @param connection
   * @param shipmentId Unique UUID identifier of the shipment to retrieve.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query e_commerce_mall_shipments table by id with deleted_at IS NULL filter to exclude soft-deleted records. Join with e_commerce_mall_shipment_items (1-to-many) to include all order items in the shipment. Further join with e_commerce_mall_order_items to retrieve item details (quantity, unit_price, status) and with e_commerce_mall_product_variants for product variant identification. Also join with e_commerce_mall_orders for the parent order reference. If no active shipment found with the given id, return 404 Not Found. The response should structure shipment-level fields at the top level and include a nested array of order items with their details.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("shipmentId")
    shipmentId: string & tags.Format<"uuid">,
  ): Promise<IECommerceMallShipment> {
    try {
      return await getECommerceMallCustomerShipmentsShipmentId({
        customer,
        shipmentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Confirm delivery of a shipment package, marking all contained order items as delivered.
   *
   * When a customer receives a physical package from the shipping carrier, they confirm delivery through this endpoint. Upon successful confirmation, the system records the delivery timestamp on the shipment record and simultaneously transitions every order item grouped in that shipment to the 'delivered' status. This bulk status change affects all order items in the shipment together — individual item confirmation is not supported.
   *
   * Only shipments that have been dispatched by the seller (shipped_at is set) and are not yet delivered (delivered_at is null) can be confirmed. If delivery was already confirmed or the shipment has not been shipped, the operation is rejected with an appropriate error.
   *
   * Each status transition is recorded in the order item status change log with reason 'customer_delivery_confirmation', providing a complete audit trail. If the customer does not manually confirm delivery within 14 days of the shipment's shipped_at timestamp, an automatic batch process transitions the shipment to delivered state instead.
   *
   * Accessible to: authenticated customers who own the order that contains this shipment.
   *
   * @param connection
   * @param shipmentId Unique identifier (UUID) of the shipment whose delivery is being confirmed. The shipment must belong to one of the authenticated customer's orders and must be in transit (shipped but not yet delivered).
   * @param body Delivery confirmation of a shipment. The customer acknowledges receipt of the physical package. The IUpdate type serves as a marker — sending the request constitutes confirmation. No specific fields are required from the customer as the confirmation action is implicit in the API call.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Validate the shipment exists by shipmentId. Verify the shipment belongs to the authenticated customer by joining: e_commerce_mall_shipment_items → e_commerce_mall_order_items → e_commerce_mall_orders → e_commerce_mall_customer_id. Compare customer_id against the authenticated customer's identity.
   *
   * Pre-condition checks (return appropriate HTTP errors):
   * - Shipment not found → 404 Not Found
   * - Shipment belongs to a different customer's orders → 403 Forbidden
   * - Shipment not yet dispatched (shipped_at is null) → 422 Unprocessable Entity
   * - Shipment already delivered (delivered_at is not null) → 409 Conflict
   *
   * Transactional execution:
   * 1. Begin database transaction with row-level lock on the shipment record (SELECT ... FOR UPDATE) to prevent double-confirmation race conditions
   * 2. Update e_commerce_mall_shipments: SET delivered_at = NOW(), updated_at = NOW()
   * 3. Query all e_commerce_mall_shipment_items WHERE shipment_id = {shipmentId}
   * 4. For each linked e_commerce_mall_order_item:
   *    a. Update status to 'delivered'
   *    b. Insert status log: from_status='shipped', to_status='delivered', reason='customer_delivery_confirmation'
   * 5. Commit transaction
   * 6. Return the updated shipment record with all relations for confirmation display
   *
   * Edge cases:
   * - Order items already in 'cancelled' or 'refunded' status within the shipment → skip those items (they reached terminal states before shipment)
   * - Order items already 'delivered' → skip (idempotent within the batch)
   * - Empty shipment_items (no items linked) → reject with 422 Unprocessable Entity
   * - Auto-delivery timeout (14 days) is handled by a separate scheduled job, not this endpoint
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("shipmentId")
    shipmentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IECommerceMallShipment.IUpdate,
  ): Promise<IECommerceMallShipment> {
    try {
      return await putECommerceMallCustomerShipmentsShipmentId({
        customer,
        shipmentId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
