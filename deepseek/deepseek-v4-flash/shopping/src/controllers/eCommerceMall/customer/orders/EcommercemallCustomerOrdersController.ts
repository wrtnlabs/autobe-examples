import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IECommerceMallOrder } from "../../../../api/structures/IECommerceMallOrder";
import { IPageIECommerceMallOrder } from "../../../../api/structures/IPageIECommerceMallOrder";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { getECommerceMallCustomerOrdersOrderCode } from "../../../../providers/getECommerceMallCustomerOrdersOrderCode";
import { patchECommerceMallCustomerOrders } from "../../../../providers/patchECommerceMallCustomerOrders";
import { postECommerceMallCustomerOrders } from "../../../../providers/postECommerceMallCustomerOrders";

@Controller("/eCommerceMall/customer/orders")
export class EcommercemallCustomerOrdersController {
  /**
   * Place an order by checking out the current cart items.
   *
   * The customer selects a shipping address from their saved addresses and confirms the purchase. The system validates all cart items for availability and stock sufficiency, processes payment through an external payment gateway, and upon successful payment creates the order with all checked-out items as individual order items. Each order item receives status 'paid' and purchase-time snapshots are automatically captured to preserve the product details, variant configuration, and seller profile information as they existed at the moment of purchase for historical accuracy.
   *
   * Stock quantities are decreased for each purchased variant, and purchased items are removed from the cart. If payment processing fails, no order is created and the customer can retry without losing their order summary selections. The overall order status is derived from the individual order item statuses after creation.
   *
   * @param connection
   * @param body Selection of the shipping address to use for this order. The customer picks one of their saved addresses by its ID. All cart items belonging to this customer are implicitly included as the items to purchase.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification Authenticate the customer from the session. Fetch
     *   the customer's current cart items with their product variants. Validate
     *   each cart item: variant must not be deleted (deleted_at is null) and
     *   must have sufficient stock (sum of inventory_records quantity_change >=
     *   cart item quantity). Fetch the selected shipping address by addressId
     *   from request body — verify it belongs to this customer and is not
     *   soft-deleted. Calculate total price by summing (cartItem.quantity *
     *   variant.price or product.base_price) across all valid cart items.
     *   Process payment via external payment gateway integration — if payment
     *   fails, return an error (HTTP 402 or similar) without creating any
     *   records. If payment succeeds: create the order with a unique
     *   auto-generated order code, total price, and address snapshot fields
     *   copied from the customer's address. For each distinct variant in the
     *   cart (combining quantities since multiple cart items for same variant
     *   are already combined by the unique constraint), create an order item
     *   with quantity, unit_price (from variant), and status 'paid'. Create
     *   three snapshots per order item: (1) product snapshot capturing current
     *   product name, description, base_price, category assignment, and all
     *   variant snapshots; (2) order item snapshot capturing product_name,
     *   product_description, product_base_price, variant_sku, variant_options
     *   (formatted string), variant_price; (3) seller profile snapshot
     *   capturing shop_name and shop_logo. Create negative inventory records
     *   for each variant with quantity_change = -(orderItem.quantity) and
     *   reason = 'order placed - Order #{code}'. Remove all checked-out cart
     *   items (set deleted_at). Return the created order with all items,
     *   snapshots, and calculated overall order status. Edge cases: empty cart
     *   → reject (HTTP 422); no shipping address provided → reject; cart
     *   contains unavailable items → reject with details of which items are
     *   unavailable; payment gateway timeout → return server error.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IECommerceMallOrder.ICreate,
  ): Promise<IECommerceMallOrder> {
    try {
      return await postECommerceMallCustomerOrders({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a paginated list of the authenticated customer's orders, sorted by newest first.
   *
   * Each order summary includes the order number, creation date, total price, and the overall order status derived from the statuses of all constituent order items. The overall status is computed as: 'paid' (all items paid), 'shipped' (at least one shipped, none delivered), 'delivered' (all delivered), 'cancelled' (all cancelled), 'refunded' (all refunded), or 'partially_completed' (mixed terminal states).
   *
   * Filtering is supported by order status to narrow down the results. Pagination controls (page number, page size) are included in the request body. This endpoint is accessible only to authenticated customers.
   *
   * @param connection
   * @param body Search criteria for filtering the order history, including optional order status filter, date range (start and end), and pagination parameters (page, limit).
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification Query e_commerce_mall_orders table filtered by
     *   the authenticated customer's ID (e_commerce_mall_customer_id). Apply
     *   optional status filter by computing the derived order status from order
     *   items at query time - join with e_commerce_mall_order_items and
     *   aggregate statuses per order. Apply sorting by created_at descending
     *   (newest first). Implement cursor-based or offset pagination as
     *   configured. Return paginated summary records with order code,
     *   created_at, total_price, and the computed overall status. Edge case: if
     *   status filter is provided, pre-filter orders by checking order item
     *   statuses before pagination.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IECommerceMallOrder.IRequest,
  ): Promise<IPageIECommerceMallOrder.ISummary> {
    try {
      return await patchECommerceMallCustomerOrders({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve full order details by order number.
   *
   * This endpoint returns the complete order record including all purchased items, snapshots preserved at the time of purchase, shipping address, and shipment tracking information. Each order item includes the product name, variant options (e.g., "Color: Red, Size: Large"), quantity, unit price, and its independent fulfillment status (paid, shipped, delivered, cancelled, or refunded). The product-variant snapshot and seller profile snapshot captured at purchase time are also included for historical accuracy. Shipment entries provide carrier name, tracking number, shipped timestamp, and delivery confirmation status.
   *
   * Customers can view their own orders only. If the requested order does not belong to the requesting customer, the request is rejected. Administrators can view any order on the platform for oversight and dispute resolution purposes.
   *
   * @param connection
   * @param orderCode Unique order number assigned at order creation for customer reference and communication purposes. (global scope)
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification Query the `e_commerce_mall_orders` table by the
     *   unique `code` field (string equality lookup). Join with the following
     *   relations to build the full response: - `orderItems`: List of purchased
     *   order items with quantity, unit_price, status -
     *   `orderItems.productVariantSnapshot`
     *   (e_commerce_mall_order_item_snapshots): Immutable product name,
     *   description, base price, variant SKU, variant options, variant price -
     *   `orderItems.sellerSnapshot`
     *   (e_commerce_mall_order_item_seller_snapshots): Immutable shop name and
     *   logo - `orderItems.shipmentItem.shipment`
     *   (e_commerce_mall_shipment_items → e_commerce_mall_shipments): Carrier
     *   name, tracking number, shipped_at, delivered_at
   *
   * Authorization logic (handled at controller layer):
   * - Customer actor: Verify `order.e_commerce_mall_customer_id` matches the authenticated customer's ID. Reject with 404 (not 403) if mismatch to avoid leaking order existence.
   * - Administrator actor: Allow access regardless of customer_id.
   *
   * Return 404 if no order matches the given orderCode.
   *
   * Do NOT include deleted/soft-deleted records where `deleted_at` is non-null for shipments. Order items and orders themselves are preserved permanently even after customer account deletion.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":orderCode")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderCode")
    orderCode: string,
  ): Promise<IECommerceMallOrder> {
    try {
      return await getECommerceMallCustomerOrdersOrderCode({
        customer,
        orderCode,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
