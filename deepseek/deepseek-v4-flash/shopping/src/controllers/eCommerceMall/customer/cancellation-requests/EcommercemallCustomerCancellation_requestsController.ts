import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IECommerceMallCancellationRequest } from "../../../../api/structures/IECommerceMallCancellationRequest";
import { IPageIECommerceMallCancellationRequest } from "../../../../api/structures/IPageIECommerceMallCancellationRequest";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { getECommerceMallCustomerCancellationRequestsCancellationRequestId } from "../../../../providers/getECommerceMallCustomerCancellationRequestsCancellationRequestId";
import { patchECommerceMallCustomerCancellationRequests } from "../../../../providers/patchECommerceMallCustomerCancellationRequests";
import { postECommerceMallCustomerCancellationRequests } from "../../../../providers/postECommerceMallCustomerCancellationRequests";

@Controller("/eCommerceMall/customer/cancellation-requests")
export class EcommercemallCustomerCancellation_requestsController {
  /**
   * Submit a cancellation request for a specific order item.
   *
   * Customers can request cancellation of individual order items that are in the paid status (payment completed, not yet shipped). Each cancellation request targets exactly one order item. The request includes a free-form reason explaining why the customer wishes to cancel.
   *
   * Upon submission, the request enters pending status and awaits review by the seller who owns the product variant in the target order item. The customer's identity and session are automatically associated with the request for audit purposes.
   *
   * A cancellation request can only be created when the order item is in the paid status. Items that are shipped, delivered, cancelled, or refunded are not eligible for cancellation. An order item must not already have an active pending cancellation request.
   *
   * @param connection
   * @param body The order item to cancel and the reason for cancellation. The customer's identity and session are determined from the authentication context.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Create a new e_commerce_mall_cancellation_requests record.
   *
   * 1. Validate the target order item exists via e_commerce_mall_order_item_id.
   * 2. Verify the order item belongs to the authenticated customer (check e_commerce_mall_orders → e_commerce_mall_customer_id matches the authenticated customer).
   * 3. Verify the order item's status is "paid" — only paid items can be cancelled. Reject with error if status is shipped, delivered, cancelled, or refunded.
   * 4. Check that no existing cancellation request for the same order item has status "pending" — prevent duplicate pending requests.
   * 5. Set e_commerce_mall_customer_id from the authenticated customer's identity.
   * 6. Set e_commerce_mall_customer_session_id from the authenticated session.
   * 7. Set reason from the request body.
   * 8. Set status to "pending".
   * 9. Set created_at and updated_at to current timestamp.
   * 10. Return the created IECommerceMallCancellationRequest record.
   *
   * Edge cases:
   * - If the order item does not exist, return 404 Not Found.
   * - If the order item does not belong to the authenticated customer, return 403 Forbidden.
   * - If the order item is not in paid status, return 422 Unprocessable Entity with a message indicating the item is not eligible for cancellation.
   * - If a pending cancellation request already exists for this order item, return 409 Conflict.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IECommerceMallCancellationRequest.ICreate,
  ): Promise<IECommerceMallCancellationRequest> {
    try {
      return await postECommerceMallCustomerCancellationRequests({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and list cancellation requests with filtering and pagination support.
   *
   * This endpoint allows authenticated users to search through cancellation requests based on various filter criteria. The results depend on the caller's role: customers see only their own cancellation requests, sellers see requests for order items containing their products, and administrators see all requests across the platform.
   *
   * Filtering capabilities include status (pending, approved, rejected), creation date range, and association filters. Results are paginated and sorted by creation date in descending order by default.
   *
   * Each cancellation request summary in the list includes the request status, reason, timestamps, and references to the associated order item and customer.
   *
   * @param connection
   * @param body Search and filter criteria for cancellation requests including status filters, date range, pagination parameters, and sorting options. The available filters may be scoped by the caller's role automatically.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query the e_commerce_mall_cancellation_requests table with pagination and filtering.
   *
   * Apply search filters from request body:
   * - status filter (single or multiple): pending, approved, rejected
   * - created_at date range (from/to)
   * - customer_id filter (administrators and sellers scoping)
   * - seller_id filter (administrators scoping)
   * - order_item_id filter (for specific item lookup)
   *
   * Authorization:
   * - Customers: scope results to e_commerce_mall_customer_id = authenticated customer ID
   * - Sellers: scope results via join with e_commerce_mall_order_items → e_commerce_mall_product_variants → e_commerce_mall_products where seller_id = authenticated seller ID
   * - Administrators: view all cancellation requests
   * - Super administrators: view all cancellation requests
   *
   * Join with e_commerce_mall_order_items for order item details and with e_commerce_mall_customers, e_commerce_mall_sellers for actor display names.
   *
   * Pagination: Use cursor-based or offset-based pagination with page/limit parameters from request body.
   * Sorting: Default sort by created_at descending. Support sort by created_at, status.
   *
   * Return paginated list of cancellation request summaries with computed fields for display.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IECommerceMallCancellationRequest.IRequest,
  ): Promise<IPageIECommerceMallCancellationRequest.ISummary> {
    try {
      return await patchECommerceMallCustomerCancellationRequests({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single cancellation request by its unique identifier.
   *
   * Cancellation requests are customer-initiated requests to cancel a paid order item before it has been shipped. Each request is associated with exactly one order item and includes the customer's reason for cancellation, the current status (pending, approved, or rejected), and seller response details if the seller has responded.
   *
   * This operation returns the full cancellation request record including the customer's original reason, the current lifecycle status, seller response fields (responded timestamp, rejection reason, seller identity), and creation/update timestamps. It does not include the associated snapshots or related order item details — those are available through separate endpoints.
   *
   * Use this endpoint to view the current state of a specific cancellation request for customer support, order management, or status tracking purposes.
   *
   * @param connection
   * @param cancellationRequestId Unique identifier of the cancellation request to retrieve (UUID).
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query the e_commerce_mall_cancellation_requests table by primary key (id) using the provided cancellationRequestId path parameter.
   *
   * Return the full cancellation request entity. Do not include soft-deleted records (deleted_at IS NULL) to respect data retention policies.
   *
   * Validate that the cancellationRequestId is a valid UUID format before querying. If the record is not found (no matching id with deleted_at IS NULL), return a 404 Not Found error.
   *
   * Authorization rules (to be enforced at the middleware layer):
   * - Customers can only access their own cancellation requests (where e_commerce_mall_customer_id matches their customer account)
   * - Sellers can only access cancellation requests for order items containing their products (where e_commerce_mall_seller_id matches or the order item's variant belongs to them)
   * - Administrators and super administrators can access any cancellation request
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":cancellationRequestId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("cancellationRequestId")
    cancellationRequestId: string & tags.Format<"uuid">,
  ): Promise<IECommerceMallCancellationRequest> {
    try {
      return await getECommerceMallCustomerCancellationRequestsCancellationRequestId(
        {
          customer,
          cancellationRequestId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
