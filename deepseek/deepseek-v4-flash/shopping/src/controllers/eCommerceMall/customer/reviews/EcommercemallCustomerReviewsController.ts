import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IECommerceMallReview } from "../../../../api/structures/IECommerceMallReview";
import { IPageIECommerceMallReview } from "../../../../api/structures/IPageIECommerceMallReview";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { deleteECommerceMallCustomerReviewsReviewId } from "../../../../providers/deleteECommerceMallCustomerReviewsReviewId";
import { getECommerceMallCustomerReviewsReviewId } from "../../../../providers/getECommerceMallCustomerReviewsReviewId";
import { patchECommerceMallCustomerReviews } from "../../../../providers/patchECommerceMallCustomerReviews";
import { postECommerceMallCustomerReviews } from "../../../../providers/postECommerceMallCustomerReviews";
import { putECommerceMallCustomerReviewsReviewId } from "../../../../providers/putECommerceMallCustomerReviewsReviewId";

@Controller("/eCommerceMall/customer/reviews")
export class EcommercemallCustomerReviewsController {
  /**
   * Write a product review after receiving a delivered order item.
   *
   * Customers can submit a review for a product they have purchased once the corresponding order item reaches the 'delivered' status. The review must include a star rating between 1 and 5 (required) and may include optional text content describing the customer's experience.
   *
   * Each order item may have at most one review, and a customer may write at most one review per product per order. Duplicate review submissions for the same product within the same order are rejected.
   *
   * Upon successful creation, the system automatically captures an initial snapshot of the review state for audit and dispute resolution purposes. The review is associated with the authenticated customer, the product, and the specific order item.
   *
   * @param connection
   * @param body Review creation payload containing the order item identifier, a required star rating between 1 and 5, and optional text content.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification Authenticate the customer from the session
     *   context. Retrieve the order item by the provided order_item_id and
     *   verify it belongs to the authenticated customer. Check that the order
     *   item status is 'delivered' — reject with 422 if not. Verify no existing
     *   review exists for the same customer+product+order combination using the
     *   composite unique constraint — reject with 422 if a review already
     *   exists. Derive product_id and order_id from the order item. Create the
     *   review record with rating and optional content. Create an initial
     *   snapshot with changed_fields='created', preserving the initial rating
     *   and text values. Return the created review with all fields.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IECommerceMallReview.ICreate,
  ): Promise<IECommerceMallReview> {
    try {
      return await postECommerceMallCustomerReviews({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and list product reviews with comprehensive filtering and pagination.
   *
   * This endpoint retrieves customer reviews for products on the e-commerce platform. Reviews are displayed on product detail pages (sorted newest first by default) and can be filtered by product, customer, rating range, or text content for administrative oversight.
   *
   * Non-deleted reviews are returned exclusively — soft-deleted reviews (where the customer chose to delete their review) are automatically excluded from all results. The customer display name is anonymized to "deleted user" if the review author has deleted their account, while the review content remains visible.
   *
   * Supports full-text search on review content using the database's trigram index. Results are paginated for efficient browsing of large review collections.
   *
   * @param connection
   * @param body Search criteria for filtering reviews. Supports filtering by product (productId), customer (customerId), rating range (minRating, maxRating), text content search (keyword), sort parameters, and pagination.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification Query e_commerce_mall_reviews table with the
     *   following implementation:
   *
   * 1. Filtering:
   *    - Filter by productId (e_commerce_mall_product_id) when provided — primary use case for product detail page
   *    - Filter by customerId (e_commerce_mall_customer_id) when provided — for customer review history
   *    - Filter by rating range (minRating, maxRating) to allow filtering by satisfaction level
   *    - Text search on content field using GIN trigram index (content ops: gin_trgm_ops) for keyword search
   *    - EXCLUDE soft-deleted reviews: WHERE deleted_at IS NULL
   *
   * 2. Sorting:
   *    - Default: created_at DESC (newest first) as required by business rules (Section 378)
   *    - Support optional sort field and direction parameters
   *
   * 3. Pagination:
   *    - Use cursor or offset-based pagination
   *    - Return total count for UI display
   *
   * 4. Data composition:
   *    - Join with e_commerce_mall_customers to get customer display name
   *    - If customer is deleted (account anonymized), display name = 'deleted user'
   *    - Join with e_commerce_mall_products to get product name (for admin view)
   *
   * 5. Response:
   *    - Return paginated list of review summaries with customer display name anonymization
   *    - Include total count for the filtered result set
   *
   * 6. Error handling:
   *    - Return empty page (not 404) when no results match
   *    - Validate pagination parameters (page, limit)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IECommerceMallReview.IRequest,
  ): Promise<IPageIECommerceMallReview.ISummary> {
    try {
      return await patchECommerceMallCustomerReviews({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single product review by its unique identifier.
   *
   * Returns the complete review details including the star rating (1-5), optional text content, creation and update timestamps, the customer's display name, and the reviewed product's information. The customer display name is automatically anonymized to 'deleted user' if the author's account has been deleted, maintaining privacy while preserving review content.
   *
   * Soft-deleted reviews are not accessible through this endpoint and return a 404 Not Found response. Review snapshots created during edits are accessible via the review snapshots endpoint.
   *
   * @param connection
   * @param reviewId The unique identifier (UUID) of the review to retrieve.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification Query e_commerce_mall_reviews by id with the
     *   given reviewId UUID parameter. Join with
     *   e_commerce_mall_customer_profiles on customer_id to retrieve the
     *   display_name. If the customer has a deleted_at timestamp (account
     *   deleted), anonymize display_name to 'deleted user'. Join with
     *   e_commerce_mall_products to include product name. If the review has a
     *   non-null deleted_at, return 404 Not Found (soft-deleted reviews are
     *   excluded from public access). Return the full review with rating,
     *   content, created_at, updated_at, customer display name (or 'deleted
     *   user'), product id and name.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":reviewId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
  ): Promise<IECommerceMallReview> {
    try {
      return await getECommerceMallCustomerReviewsReviewId({
        customer,
        reviewId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing review's rating and/or text content.
   *
   * The authenticated customer updates their own review by providing a new rating (1-5 stars, required) and/or new text content (optional). Before applying the update, the system creates an immutable snapshot of the current review state to preserve the edit history. The snapshot records which fields were changed ('rating', 'text', or 'rating_and_text') for audit purposes.
   *
   * The review's `created_at` timestamp remains unchanged to preserve sort position in newest-first ordering on the product detail page. Only the `updated_at` timestamp is refreshed. Soft-deleted reviews cannot be edited.
   *
   * Returns the full updated review entity on success.
   *
   * @param connection
   * @param reviewId The UUID of the review to update. Must reference an existing, non-deleted review owned by the requesting customer.
   * @param body Updated review data. Rating (1-5 stars integer) is required. Text content is optional — set to null to clear existing text, or provide a string to update it.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification Query the e_commerce_mall_reviews table by
     *   {reviewId}. Verify the review exists and deleted_at IS NULL — reject
     *   with 404 if not found or deleted.
   *
   * Verify the requesting customer's ID matches e_commerce_mall_customer_id — reject with 403 if unauthorized.
   *
   * Before updating, create a snapshot in e_commerce_mall_review_snapshots:
   * - id: new UUID
   * - e_commerce_mall_review_id: the review's id
   * - rating: current rating value (before update)
   * - text: current content value (before update)
   * - changed_fields: determine based on which fields are being changed — 'rating' if only rating differs, 'text' if only text differs, 'rating_and_text' if both differ
   * - created_at: current timestamp
   *
   * Then update the review:
   * - Set rating to the new value
   * - Set content to the new text value (can be null to clear text)
   * - Set updated_at to current timestamp
   * - Do NOT modify created_at (preserves sort order)
   *
   * Rating must be an integer between 1 and 5 — reject with 400 if invalid.
   *
   * Return the updated IECommerceMallReview entity.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":reviewId")
  public async update(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IECommerceMallReview.IUpdate,
  ): Promise<IECommerceMallReview> {
    try {
      return await putECommerceMallCustomerReviewsReviewId({
        customer,
        reviewId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Deletes the customer's own review for a purchased product.
   *
   * The review is soft-deleted, meaning it is marked as deleted rather than permanently removed from the database. Once deleted, the review no longer appears on the product detail page and is excluded from the product's average rating calculation. All review snapshots created during prior edits are preserved and remain accessible to administrators for audit and dispute resolution purposes.
   *
   * The requesting customer must be the author of the review. Attempting to delete a review that is already deleted will result in an error.
   *
   * @param connection
   * @param reviewId The unique identifier (UUID) of the review to delete.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification Look up the review by {reviewId} UUID. Verify the
     *   authenticated customer owns the review by checking
     *   e_commerce_mall_customer_id matches the current customer's ID. If
     *   review not found, return 404 Not Found. If review does not belong to
     *   the customer, return 403 Forbidden. If review is already deleted
     *   (deleted_at is not null), return 410 Gone.
   *
   * Perform soft delete: set deleted_at to the current timestamp. Do NOT delete the row — review snapshots use onDelete: Cascade, so removing the row would cascade-delete all snapshots. After deletion, the product's average rating must be recalculated dynamically (deleted reviews are excluded from average rating calculations). All snapshots created during prior edits are preserved and remain accessible to administrators.
   *
   * No response body is returned. Return 204 No Content on success.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":reviewId")
  public async erase(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteECommerceMallCustomerReviewsReviewId({
        customer,
        reviewId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
