import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IECommerceMallCustomerProfile } from "../../../../api/structures/IECommerceMallCustomerProfile";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { getECommerceMallCustomerProfile } from "../../../../providers/getECommerceMallCustomerProfile";
import { putECommerceMallCustomerProfile } from "../../../../providers/putECommerceMallCustomerProfile";

@Controller("/eCommerceMall/customer/profile")
export class EcommercemallCustomerProfileController {
  /**
   * Retrieves the authenticated customer's own profile information.
   *
   * Each customer has a profile containing two editable attributes. The display name is the customer's publicly visible name that appears on product reviews, allowing customers to be recognized by other users without revealing their email address. The phone number is an optional contact number stored for order-related communication such as delivery coordination by shipping carriers.
   *
   * The profile is automatically determined from the authenticated customer's session — no identifiers need to be provided in the request. The response includes the current display name, phone number, and timestamps for creation and last update.
   *
   * Returns a 404 Not Found error if no profile exists for the authenticated customer.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query the e_commerce_mall_customer_profiles table joined with e_commerce_mall_customers via the authenticated customer's ID extracted from the JWT session token. Return the customer's profile fields: id, display_name, phone_number, created_at, updated_at. Exclude soft-deleted profiles by filtering WHERE deleted_at IS NULL. If the authenticated actor is not a customer actor type, return 403 Forbidden. Return 404 NotFound if no profile record exists for this customer.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
  ): Promise<IECommerceMallCustomerProfile> {
    try {
      return await getECommerceMallCustomerProfile({
        customer,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update the authenticated customer's profile information.
   *
   * The customer can update their display name — the publicly visible name shown on product reviews and other public-facing areas — and their phone number used for order-related communication such as delivery coordination. Both fields are optional in the request, allowing partial updates. Only the fields provided in the request body will be updated; omitted fields retain their existing values.
   *
   * The customer is identified from the authenticated session, so no customer identifier is required in the path.
   *
   * @param connection
   * @param body Customer profile update payload. Only the fields to be updated need to be provided. display_name is the name shown publicly on reviews; phone_number is the contact number for order communication.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query e_commerce_mall_customer_profiles joined with the authenticated customer's session to find the profile record. Update only the fields provided in the request body. Set updated_at to the current timestamp. Return the full updated profile record. If the customer has no profile yet (should not happen under normal registration flow), return a 404 error.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IECommerceMallCustomerProfile.IUpdate,
  ): Promise<IECommerceMallCustomerProfile> {
    try {
      return await putECommerceMallCustomerProfile({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
