import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IECommerceMallProduct } from "../../../../api/structures/IECommerceMallProduct";
import { IPageIECommerceMallProduct } from "../../../../api/structures/IPageIECommerceMallProduct";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { getECommerceMallCustomerProductsProductId } from "../../../../providers/getECommerceMallCustomerProductsProductId";
import { patchECommerceMallCustomerProducts } from "../../../../providers/patchECommerceMallCustomerProducts";

@Controller("/eCommerceMall/customer/products")
export class EcommercemallCustomerProductsController {
  /**
   * Search and browse products available for purchase on the platform.
   *
   * This endpoint provides the primary product discovery experience for customers. It supports full-text search by product name with fuzzy matching capabilities, allowing customers to find products quickly. Results are filtered to show only products with 'visible' visibility status — products that are deleted, suspended (due to seller suspension), or have no purchasable variants are excluded from results.
   *
   * Advanced filtering capabilities include category-based filtering to narrow results to specific product categories, price range filtering with minimum and maximum price boundaries, and an in-stock only toggle that filters to products with available inventory. Results can be sorted by newest listings first, or by price in ascending or descending order.
   *
   * Results are paginated using cursor-based pagination for efficient browsing of large product catalogs. Each product summary in the result set displays the main thumbnail image, product name, price or price range, seller's shop name, and calculated average rating from customer reviews.
   *
   * @param connection
   * @param body Search and filtering criteria for browsing products. Supports full-text search by product name, filtering by category, price range (min/max), and in-stock only toggle. Includes sort options (newest, price ascending, price descending) and cursor-based pagination parameters.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification Query e_commerce_mall_products table filtering by
     *   visibility = 'visible' (exclude deleted, suspended, and
     *   unavailable_but_visible products). Apply full-text search (ILIKE) on
     *   product name if search keyword provided. Filter by category_id for
     *   category filtering. Apply price range filter on base_price (consider
     *   variant price overrides for accurate price range). For in-stock filter,
     *   join with variants and inventory records to check stock > 0. Support
     *   sort options: newest (created_at DESC), price ascending (base_price
     *   ASC), price descending (base_price DESC). Paginate using cursor-based
     *   pagination on created_at. Join with e_commerce_mall_sellers for shop
     *   name. Left join with e_commerce_mall_reviews (non-deleted) for average
     *   rating calculation (AVG(rating)). Join with
     *   e_commerce_mall_product_images for main thumbnail (sort_order = 0).
     *   Join with e_commerce_mall_product_variants for price range calculation
     *   (min/max price including variant overrides). Exclude products belonging
     *   to suspended sellers.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IECommerceMallProduct.IRequest,
  ): Promise<IPageIECommerceMallProduct.ISummary> {
    try {
      return await patchECommerceMallCustomerProducts({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a product's full details by its unique identifier.
   *
   * This endpoint returns comprehensive product information for the product detail page. The response includes the product's name, description, base price, and current visibility state. All uploaded product images are returned sorted by their display order (the first image serves as the thumbnail). All active (non-deleted) variants are included with their SKU codes, option key-value pairs, price overrides, and calculated current stock quantities derived from the sum of all inventory records. When a category is assigned, the category name and description are provided. The seller's shop name is included from their public profile. The endpoint also returns the average rating calculated from all non-deleted reviews, the total review count, and the full list of non-deleted reviews sorted by newest first, each with the reviewer's display name and review timestamps.
   *
   * Products with visibility set to 'deleted' or 'suspended' return a 404 response. Products with visibility 'unavailable_but_visible' (no variants) return successfully with variant data empty but the product details still shown as unavailable for purchase.
   *
   * @param connection
   * @param productId Unique identifier (UUID) of the product to retrieve. Must reference an existing product whose visibility is not 'deleted' or 'suspended'.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification Query e_commerce_mall_products by id with UUID
     *   equality filter. If product does not exist or visibility is 'deleted'
     *   or 'suspended', return 404 Not Found. Join
     *   e_commerce_mall_seller_profiles to retrieve shop_name. Left join
     *   e_commerce_mall_categories to retrieve category name and description
     *   (nullable if category was deleted). Include
     *   e_commerce_mall_product_images where deleted_at IS NULL, ordered by
     *   sort_order ascending — the first image (lowest sort_order) is the
     *   thumbnail. Include e_commerce_mall_product_variants where deleted_at IS
     *   NULL, ordered by created_at ascending. For each variant, include
     *   e_commerce_mall_product_variant_options where deleted_at IS NULL
     *   (key-value option pairs). For each variant, calculate current stock by
     *   summing quantity_change from all e_commerce_mall_inventory_records for
     *   that variant. If visibility is 'unavailable_but_visible' (no variants
     *   exist), mark purchasable flag as false. Include e_commerce_mall_reviews
     *   where deleted_at IS NULL, ordered by created_at DESC. For each review,
     *   join e_commerce_mall_customer_profiles to get the customer's display
     *   name (if customer deleted their account, use 'deleted user'). Calculate
     *   average rating by averaging rating from all non-deleted reviews.
     *   Calculate total review count by counting non-deleted reviews.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":productId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
  ): Promise<IECommerceMallProduct> {
    try {
      return await getECommerceMallCustomerProductsProductId({
        customer,
        productId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
