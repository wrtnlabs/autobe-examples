import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IECommerceMallCartOverview } from "../../../../../api/structures/IECommerceMallCartOverview";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { getECommerceMallCustomerCartOverview } from "../../../../../providers/getECommerceMallCustomerCartOverview";

@Controller("/eCommerceMall/customer/cart/overview")
export class EcommercemallCustomerCartController {
  /**
   * Retrieve the authenticated customer's shopping cart with detailed item-level information.
   *
   * Returns a comprehensive overview of the customer's cart including each cart item's product name, selected variant options (e.g., color, size), unit price, quantity, subtotal, and availability status. The total price of all available items is computed and displayed. Cart items are sorted by the order in which they were added, with the most recently added item appearing last.
   *
   * Unavailable items — where the product variant has been deleted by the seller or is out of stock (stock quantity reaches zero) — are clearly marked with an unavailable status and are excluded from the total price calculation. If the cart is empty, an empty items list with a total price of zero is returned.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query the authenticated customer's active cart items from e_commerce_mall_cart_items filtered by customer_id and where deleted_at IS NULL. Join with e_commerce_mall_product_variants (for price override and deleted_at status) and e_commerce_mall_products (for name, base_price, visibility). Join with e_commerce_mall_product_variant_options to retrieve option key-value pairs grouped by variant ID. Determine item availability: an item is unavailable if the variant's deleted_at IS NOT NULL, or if the current stock quantity (calculated by summing e_commerce_mall_inventory_records.quantity_change for that variant) is 0 or less. Calculate unit price as COALESCE(variant.price, product.base_price). Calculate subtotal as unit_price multiplied by cart_item.quantity. Compute total_price as the sum of subtotals for available items only, excluding unavailable items. Sort cart items by created_at in ascending order (oldest first, most recent last). When cart has no active items, return an empty items array with total_price of 0.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async overview(
    @CustomerAuth()
    customer: CustomerPayload,
  ): Promise<IECommerceMallCartOverview> {
    try {
      return await getECommerceMallCustomerCartOverview({
        customer,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
