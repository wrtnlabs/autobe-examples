import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IECommerceMallRefundRequest } from "../../../../api/structures/IECommerceMallRefundRequest";
import { IPageIECommerceMallRefundRequest } from "../../../../api/structures/IPageIECommerceMallRefundRequest";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { getECommerceMallCustomerRefundRequestsRefundRequestId } from "../../../../providers/getECommerceMallCustomerRefundRequestsRefundRequestId";
import { patchECommerceMallCustomerRefundRequests } from "../../../../providers/patchECommerceMallCustomerRefundRequests";
import { postECommerceMallCustomerRefundRequests } from "../../../../providers/postECommerceMallCustomerRefundRequests";

@Controller("/eCommerceMall/customer/refund-requests")
export class EcommercemallCustomerRefund_requestsController {
  /**
   * Create a new refund request for a specific delivered order item.
   *
   * A refund request allows a customer to seek a refund for an individual order item that has been delivered. Each refund request targets exactly one order item and requires a textual reason explaining why the refund is being requested. Only order items with status "delivered" are eligible, and the request must be submitted within 7 calendar days of the delivery date. A customer may submit at most one refund request per order item — duplicate pending requests are prevented.
   *
   * When created, the refund request enters "pending" status and awaits the seller's decision. The seller may either approve (triggering payment reversal and stock restoration) or reject the request. A snapshot of the request state is created at the time of seller response for audit and dispute resolution purposes.
   *
   * **Security**: The authenticated customer making the request must be the owner of the order item. The seller identity is automatically derived from the order item's product variant ownership chain.
   *
   * @param connection
   * @param body The order item identifier and the refund reason required to create a refund request. The customer identity is automatically determined from the authenticated user.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Validate that the authenticated customer matches the customer who owns the order item identified by `orderItemId`. Query `e_commerce_mall_order_items` by ID and verify `e_commerce_mall_customer_id` matches the authenticated user.
   *
   * Verify eligibility: the order item's `status` must equal "delivered".
   *
   * Verify the 7-day refund window: calculate the time elapsed from the delivery timestamp (use `e_commerce_mall_order_item_status_logs` to find when status changed to "delivered", or use `updated_at` of the order item as proxy) to the current timestamp. Reject if more than 7 calendar days have elapsed.
   *
   * Enforce the unique constraint: query `e_commerce_mall_refund_requests` where `e_commerce_mall_order_item_id` matches. If a record already exists with status "pending", reject the duplicate request.
   *
   * Derive `e_commerce_mall_seller_id` from the order item's variant→product→seller chain: `orderItem.productVariant.product.seller.id`.
   *
   * Create the refund request with: `e_commerce_mall_order_item_id` from input, `e_commerce_mall_customer_id` from authenticated customer, `e_commerce_mall_seller_id` derived from variant, `reason` from input, `status` = "pending", `response_timestamp` = null.
   *
   * Return the full created refund request record. On validation failure, return appropriate error messages indicating which condition was not met (not delivered, outside 7-day window, duplicate request, not the item owner).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IECommerceMallRefundRequest.ICreate,
  ): Promise<IECommerceMallRefundRequest> {
    try {
      return await postECommerceMallCustomerRefundRequests({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and list refund requests with filtering, sorting, and pagination.
   *
   * This endpoint provides a comprehensive search interface for refund requests across the platform. It serves three distinct actor types with appropriate data scoping: customers view their own submitted refund requests, sellers view refund requests targeting their products (enabling them to approve or reject), and administrators gain full visibility into all refund requests for platform oversight.
   *
   * Results are paginated and sorted by newest first by default. The response includes summary information such as the refund reason, current status, response timestamp (if the seller has responded), and related order item and customer/seller identifiers. Use the optional filter parameters to narrow results by status, date range, or specific customers and sellers.
   *
   * Soft-deleted refund requests are excluded from results by default.
   *
   * @param connection
   * @param body Search criteria for filtering refund requests. Supports filtering by status, creation date range, customer, seller, and order item. Includes pagination and sorting parameters.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query e_commerce_mall_refund_returns table with pagination, filtering, and sorting.
   *
   * ## Authentication & Data Isolation
   * - **Customers**: Automatically scope query by `e_commerce_mall_customer_id = current customer id`. Customers can only see their own refund requests.
   * - **Sellers**: Automatically scope query by `e_commerce_mall_seller_id = current seller id`. Sellers can only see refund requests for their own products.
   * - **Administrators**: No automatic scoping. Can search across all refund requests. Can filter by `customerId` and `sellerId` parameters.
   *
   * ## Filtering
   * Apply the following optional filters from the request body:
   * - `status`: Filter by refund request status (pending, approved, rejected). Single value or array.
   * - `fromCreatedAt` / `toCreatedAt`: Date range filter on `created_at` column.
   * - `customerId`: (Admin only) Filter by specific customer.
   * - `sellerId`: (Admin only) Filter by specific seller.
   * - `orderItemId`: Filter by specific order item.
   * - `search`: Text search on the `reason` field (partial match).
   *
   * ## Sorting
   * Default sort: `created_at` descending (newest first). Support sort by other fields: `created_at`, `status`, `response_timestamp`.
   *
   * ## Pagination
   * Use cursor-based or offset pagination with `page` and `limit` parameters. Return total count for UI pagination display.
   *
   * ## Joins & Enrichment
   * Join with `e_commerce_mall_order_items` to display product/variant info. Join with `e_commerce_mall_customers` for customer name/email. Join with `e_commerce_mall_sellers` for seller shop name. Join with `e_commerce_mall_refund_request_snapshots` to indicate if a snapshot exists.
   *
   * ## Edge Cases
   * - Include soft-deleted refund requests (`deleted_at IS NULL` filter) unless admin explicitly requests to see deleted records.
   * - If the authenticated actor has neither customer, seller, nor admin role, reject with 403 Forbidden.
   * - Return empty page array (not error) when no refund requests match criteria.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IECommerceMallRefundRequest.IRequest,
  ): Promise<IPageIECommerceMallRefundRequest.ISummary> {
    try {
      return await patchECommerceMallCustomerRefundRequests({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific refund request by its unique identifier.
   *
   * Returns the full details of a refund request including the customer's stated reason for seeking a refund, the current processing status, and the seller's response timestamp if a decision has already been made. The refund request references a single delivered order item for which the customer is requesting a refund within the statutory 7-day refund window.
   *
   * Each refund request is associated with three key actors: the customer who submitted it, the seller who must respond, and the order item being contested. The status field indicates where the request is in its lifecycle — pending (awaiting seller response), approved (refund granted), or rejected (refund denied). When the seller responds, an immutable snapshot of the request state is automatically created for audit trail purposes.
   *
   * @param connection
   * @param refundRequestId The unique identifier (UUID) of the refund request to retrieve.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query e_commerce_mall_refund_requests table by id matching the refundRequestId path parameter. If no active record is found (matching id and deleted_at IS NULL), return 404 Not Found.
   *
   * Include the following columns in the response: id, e_commerce_mall_order_item_id, e_commerce_mall_customer_id, e_commerce_mall_seller_id, reason, status, response_timestamp, created_at, updated_at. The deleted_at column is excluded — only active (non-deleted) records are returned.
   *
   * Authorization at the middleware layer should enforce that:
   * - Customers can only view their own refund requests (where e_commerce_mall_customer_id matches the authenticated customer's id)
   * - Sellers can only view refund requests for their own products (where e_commerce_mall_seller_id matches the authenticated seller's id)
   * - Administrators and super administrators can view any refund request
   *
   * Edge cases: If the refund request references an order item that was soft-deleted (deleted_at not null), the request itself is still accessible as long as the refund request record is active.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":refundRequestId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("refundRequestId")
    refundRequestId: string & tags.Format<"uuid">,
  ): Promise<IECommerceMallRefundRequest> {
    try {
      return await getECommerceMallCustomerRefundRequestsRefundRequestId({
        customer,
        refundRequestId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
