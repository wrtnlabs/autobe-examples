import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IECommerceMallSession } from "../../../../api/structures/IECommerceMallSession";
import { IPageIECommerceMallSession } from "../../../../api/structures/IPageIECommerceMallSession";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { getECommerceMallCustomerSessionsSessionId } from "../../../../providers/getECommerceMallCustomerSessionsSessionId";
import { patchECommerceMallCustomerSessions } from "../../../../providers/patchECommerceMallCustomerSessions";

@Controller("/eCommerceMall/customer/sessions")
export class EcommercemallCustomerSessionsController {
  /**
   * List all active login sessions for the currently authenticated user.
   *
   * This endpoint provides visibility into where the user is currently logged in across different devices and browsers. Each session record includes the IP address, referring page, creation timestamp, and expiration time — enabling users to monitor their account access points and identify any unrecognized sessions.
   *
   * Sessions are created upon successful authentication and persist until explicit logout, account deletion, or ban. Expired sessions are excluded by default to keep the list focused on active sessions. Results are sorted by creation date in descending order (newest first).
   *
   * @param connection
   * @param body Search criteria for filtering active sessions, including IP address matching, creation date range filtering, and standard pagination parameters.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification Query the appropriate session table based on the
     *   authenticated user's actor type: - Customer →
     *   e_commerce_mall_customer_sessions - Seller →
     *   e_commerce_mall_seller_sessions - Administrator →
     *   e_commerce_mall_administrator_sessions - Super Administrator →
     *   e_commerce_mall_super_administrator_sessions
   *
   * Filter sessions by the authenticated actor's ID (not a parameter — derived from auth context). Apply search filters on ip (partial match), created_at range (from/to), and expired_at range. Support pagination with page and limit parameters. Sort by created_at descending (newest first). Mark the current session (matching the session token's ID) with a flag in the response. Exclude expired sessions from results (expired_at < now) unless explicitly requested via a filter parameter. Return cursor-based or offset-based pagination.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IECommerceMallSession.IRequest,
  ): Promise<IPageIECommerceMallSession.ISummary> {
    try {
      return await patchECommerceMallCustomerSessions({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a session record by its unique identifier.
   *
   * Administrators can look up session details for security monitoring and audit purposes. The response includes metadata about the session such as the IP address of the client device, the page URL at the time of creation, the HTTP referrer, the creation timestamp, and the expiration timestamp. The response also identifies which actor type (administrator, customer, seller, or guest) owns the session.
   *
   * If no session exists with the provided identifier, a 404 Not Found error is returned. Expired sessions are still returned — the `expiredAt` field indicates whether the session is still valid.
   *
   * @param connection
   * @param sessionId The unique identifier (UUID) of the session to retrieve. Sessions are checked across administrator, customer, seller, and guest session tables.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification Query across all four session tables
     *   (e_commerce_mall_administrator_sessions,
     *   e_commerce_mall_customer_sessions, e_commerce_mall_seller_sessions,
     *   e_commerce_mall_guest_sessions) by the provided sessionId UUID. Return
     *   the matching session along with the actor type discriminator and the
     *   actor's ID. If no match is found in any table, return 404 Not Found.
   *
   * Response includes: id, actorType (string enum: 'administrator'|'customer'|'seller'|'guest'), actorId (UUID of the owning actor), ip, href, referrer, createdAt, expiredAt. Do not expose the session token itself.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<IECommerceMallSession> {
    try {
      return await getECommerceMallCustomerSessionsSessionId({
        customer,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
