  /**
   * Update an existing product variant's SKU code, price, and option values.
   *
   * The authenticated seller must be the owner of the parent product and have an 'approved' approval status. The variant must not be soft-deleted (deleted_at must be null).
   *
   * SKU code uniqueness is enforced globally across all variants on the platform. Option value combinations must remain unique within the parent product — no two variants of the same product can share identical option key-value pairs.
   *
   * Changing the SKU code triggers uniqueness validation against all other variants. Updating option values may affect how customers distinguish this variant from others of the same product.
   *
   * Returns the full variant record with updated fields and refreshed updated_at timestamp.
   *
   * @param connection
   * @param productId The UUID of the parent product that owns the variant. Used to verify the variant belongs to the correct product and for ownership validation.
   * @param variantId The UUID of the variant to update. Must reference an existing, non-deleted variant belonging to the specified product.
   * @param body Updated variant data including the SKU code, optional price override, and option values (key-value pairs). The sku_code must be globally unique across all variants. The options array defines distinguishing attributes such as color, size, or material.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification 1. Authenticate the requesting seller.
   * 2. Load the variant by variantId, ensuring it exists and belongs to the specified productId. Join with product to verify ownership (seller_id matches the authenticated seller's ID).
   * 3. Reject if variant.deleted_at is not null (variant is soft-deleted).
   * 4. Reject if the seller's approval status is not 'approved' — unapproved sellers cannot edit variants.
   * 5. If sku_code is being changed (different from current value), validate uniqueness: query e_commerce_mall_product_variants to ensure no other variant has the same sku_code (excluding the current variant's ID). Reject with conflict if duplicate.
   * 6. If option values are being updated, validate that the new combination is unique among the product's existing variants (excluding the current variant). Option values must not be empty and must have both key and value set.
   * 7. Update the variant record: set sku_code, price (or null), updated_at to current timestamp.
   * 8. Update options: delete removed option records, create/update new ones. Each option must have a unique (variant_id, key) pair.
   * 9. Trigger product snapshot creation to preserve the previous state (as per business rules: every variant edit creates a snapshot). The snapshot captures all product-level data and all variant states before the edit.
   * 10. Return the updated variant including its options in the response.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
