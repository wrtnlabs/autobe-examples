  /**
   * Update an existing product's attributes.
   *
   * Sellers can edit the name, description, category assignment, and base price of their own products. Each edit automatically creates a product snapshot preserving the complete previous state (including all variants and images) for historical audit and dispute resolution.
   *
   * Only sellers with an 'approved' approval status may update products. The product must belong to the authenticated seller — cross-seller updates are rejected. If the product has no pending order items (paid or shipped status) and no pending cancellation or refund requests, all editable fields may be changed.
   *
   * @param connection
   * @param productId The unique identifier (UUID) of the product to update.
   * @param body Updated product attributes including name, description, category ID, and base price. All fields are required.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Validate that the authenticated seller has 'approved' approval status. Verify that the product with the given productId exists and belongs to the authenticated seller (seller_id matches). Reject with appropriate error if not found or not owned.
   *
   * Before applying updates, create a product snapshot: insert a record into e_commerce_mall_product_snapshots capturing the current product name, description, base_price, and category_id. Also capture all existing variants into e_commerce_mall_product_snapshot_variants (sku, name, price) and all existing images into e_commerce_mall_product_snapshot_images (url, sort_order).
   *
   * After snapshot creation, apply the update: update the product record's name, description, category_id, and base_price fields. Set updated_at to current timestamp.
   *
   * Edge cases:
   * - If the product does not exist: return 404 Not Found
   * - If the product belongs to a different seller: return 403 Forbidden
   * - If the seller's approval status is not 'approved': return 403 Forbidden with message indicating admin approval required
   * - If category_id references a deleted (soft-deleted) category: reject with validation error
   * - Category must exist and not be soft-deleted
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
