  /**
   * Responds to a pending refund request by either approving or rejecting it.
   *
   * This operation allows a seller to review and respond to a refund request submitted by a customer for a delivered order item. The seller provides their decision by specifying a new status of either "approved" or "rejected".
   *
   * When the seller approves the refund request, the system automatically processes the refund: the order item's status transitions to "refunded", the associated product variant's stock is restored by a positive inventory record matching the purchased quantity (with reason "refund"), and a snapshot of the refund request state is preserved for audit purposes.
   *
   * When the seller rejects the refund request, the request status is set to "rejected", a snapshot is created, and the order item remains in its "delivered" state without any stock or financial changes.
   *
   * Only the seller who owns the product variant in the refunded order item can respond to the refund request. Only refund requests in "pending" status are eligible for a response.
   *
   * @param connection
   * @param refundRequestId Unique identifier of the refund request (UUID, global scope).
   * @param body Seller's decision on the refund request containing the new status value. Allowed values: "approved" to approve the refund (triggers stock restoration and status change), or "rejected" to deny the refund.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Validate the refund request exists and is owned by the seller (e_commerce_mall_refund_requests.seller_id matches authenticated seller).
   *
   * Validate the current status is 'pending' — only pending requests can be responded to.
   *
   * Validate the request body contains a valid decision: status must be 'approved' or 'rejected'.
   *
   * When status is 'approved':
   * - Update refund_request status to 'approved' and set response_timestamp to current time.
   * - Create a refund_request_snapshot with the customer's reason, decision, and response timestamp.
   * - Restore stock: create a positive inventory_record on the associated product_variant with quantity matching the order_item.quantity, reason = 'refund'.
   * - Update the order_item status to 'refunded'.
   *
   * When status is 'rejected':
   * - Update refund_request status to 'rejected' and set response_timestamp to current time.
   * - Create a refund_request_snapshot with the customer's reason, decision, and response timestamp.
   * - The order_item remains in 'delivered' status; no stock restoration occurs.
   *
   * Use a database transaction to ensure atomicity of the status update, snapshot creation, inventory record, and order item status change.
   *
   * Edge cases:
   * - If the refund request is not in 'pending' status, reject the operation with a conflict error.
   * - If the refund request does not exist, reject with a not-found error.
   * - If the authenticated seller does not own the refund request, reject with a forbidden error.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
