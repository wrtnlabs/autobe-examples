import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IECommerceMallSellerApprovalRequest } from "../../../../api/structures/IECommerceMallSellerApprovalRequest";
import { IPageIECommerceMallSellerApprovalRequest } from "../../../../api/structures/IPageIECommerceMallSellerApprovalRequest";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { getECommerceMallSellerApprovalRequestsRequestId } from "../../../../providers/getECommerceMallSellerApprovalRequestsRequestId";
import { patchECommerceMallSellerApprovalRequests } from "../../../../providers/patchECommerceMallSellerApprovalRequests";
import { postECommerceMallSellerApprovalRequests } from "../../../../providers/postECommerceMallSellerApprovalRequests";

@Controller("/eCommerceMall/seller/approval-requests")
export class EcommercemallSellerApproval_requestsController {
  /**
   * Submit a new seller registration approval request for administrator review.
   *
   * The authenticated seller, whose previous registration was rejected, submits a new approval request to be reconsidered for seller privileges. The system creates a new approval request record with 'pending' status, which administrators can then review and either approve or reject.
   *
   * This operation is only available to sellers whose current approval status is 'rejected'. Sellers with 'pending' status already have an active request under review and do not need to submit another. Sellers with 'approved' status already have full selling privileges.
   *
   * @param connection
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Validate that the authenticated seller exists and
     *   has approval_status 'rejected'. If the seller does not exist or
     *   approval_status is not 'rejected', reject the operation with an
     *   appropriate error. Create a new
     *   e_commerce_mall_seller_approval_requests record with: seller_id set to
     *   the authenticated seller's ID from the auth context, status 'pending',
     *   created_at and updated_at set to the current timestamp. reviewer_id,
     *   rejection_reason, and reviewed_at remain null. Return the newly created
     *   approval request record including the generated id and timestamps.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SellerAuth()
    seller: SellerPayload,
  ): Promise<IECommerceMallSellerApprovalRequest> {
    try {
      return await postECommerceMallSellerApprovalRequests({
        seller,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and list seller registration approval requests with filtering and pagination.
   *
   * Administrators use this endpoint to browse seller approval requests, filter by status (pending, approved, rejected), search by seller email, filter by reviewer, and restrict results by submission or review date range. Results are paginated and sorted by newest first by default.
   *
   * Each approval request summary includes the seller's email, the current status, the rejection reason if applicable, the reviewer's identity, and key timestamps. This enables administrators to efficiently manage the seller registration pipeline, prioritize pending reviews requiring attention, and audit historical approval decisions for compliance and transparency.
   *
   * @param connection
   * @param body Search criteria for filtering seller registration approval requests, supporting status filter, seller email keyword search, reviewer email search, submission and review date range filters, and pagination parameters.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Query the
     *   e_commerce_mall_seller_approval_requests table joined with
     *   e_commerce_mall_sellers (for seller email) and
     *   e_commerce_mall_administrators (for reviewer info). Exclude
     *   soft-deleted records (deleted_at IS NULL).
   *
   * Apply search filters:
   * - status: filter by "pending", "approved", or "rejected" (all statuses if omitted)
   * - seller email search: join e_commerce_mall_sellers and search by email with LIKE/ILIKE partial match
   * - reviewer email search: join e_commerce_mall_administrators and search by email
   * - date range: filter by created_at (submission date) and/or reviewed_at (review completion date)
   *
   * Default sort by created_at descending (newest first). Support pagination with page number and page size parameters in the request body. Use offset-based pagination with skip and take/limit. Return total count for frontend pagination display.
   *
   * Include related seller email from e_commerce_mall_sellers. Include reviewer email from e_commerce_mall_administrators (null for pending requests). Map status values exactly as stored: "pending", "approved", "rejected".
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IECommerceMallSellerApprovalRequest.IRequest,
  ): Promise<IPageIECommerceMallSellerApprovalRequest.ISummary> {
    try {
      return await patchECommerceMallSellerApprovalRequests({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single seller registration approval request by its unique identifier.
   *
   * The approval request contains the full details of a seller's registration submission, including the current approval status (pending awaiting administrator review, approved with selling privileges granted, or rejected with an administrator-provided reason). Both the submitting seller and administrators can access this information — sellers to verify their registration status and view any rejection reason, and administrators to review pending requests before making an approval or rejection decision. The response includes the seller's identity, the reviewing administrator's details when applicable, and timestamps for submission and review completion.
   *
   * Authorization is enforced such that sellers can only view their own approval requests, while administrators can view any request regardless of the submitting seller.
   *
   * @param connection
   * @param requestId Unique identifier (UUID) of the seller approval request to retrieve.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Query e_commerce_mall_seller_approval_requests
     *   table by primary key id matching the requestId path parameter. Exclude
     *   soft-deleted records by filtering WHERE deleted_at IS NULL. Join with
     *   e_commerce_mall_sellers (seller_id) to include seller email and current
     *   approval_status. Join with e_commerce_mall_administrators (reviewer_id)
     *   to include reviewer details when the request has been reviewed.
   *
   * Authorization: Sellers can only view their own approval requests — filter by seller_id matching the authenticated seller's ID. Administrators can view any approval request regardless of seller. Return 404 Not Found if the record does not exist, is soft-deleted, or the requesting user is not authorized to view it. Return the full approval request record including seller and reviewer relationship data.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":requestId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("requestId")
    requestId: string & tags.Format<"uuid">,
  ): Promise<IECommerceMallSellerApprovalRequest> {
    try {
      return await getECommerceMallSellerApprovalRequestsRequestId({
        seller,
        requestId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
