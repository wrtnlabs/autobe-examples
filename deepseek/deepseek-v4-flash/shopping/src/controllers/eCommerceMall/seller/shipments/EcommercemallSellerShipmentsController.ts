import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IECommerceMallShipment } from "../../../../api/structures/IECommerceMallShipment";
import { IPageIECommerceMallShipment } from "../../../../api/structures/IPageIECommerceMallShipment";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { getECommerceMallSellerShipmentsShipmentId } from "../../../../providers/getECommerceMallSellerShipmentsShipmentId";
import { patchECommerceMallSellerShipments } from "../../../../providers/patchECommerceMallSellerShipments";
import { postECommerceMallSellerShipments } from "../../../../providers/postECommerceMallSellerShipments";

@Controller("/eCommerceMall/seller/shipments")
export class EcommercemallSellerShipmentsController {
  /**
   * Create a new shipment containing one or more order items from the seller's own products.
   *
   * When a seller creates a shipment, they select the paid order items they wish to include, enter the carrier name and tracking number for the package. Upon successful creation, all included order items automatically transition from 'paid' to 'shipped' status. Multiple order items from the same seller can be bundled into a single shipment, or each item can be shipped individually in separate shipments.
   *
   * Only sellers with 'approved' approval status can create shipments. Only order items belonging to the creating seller with 'paid' status can be selected. Each order item can be assigned to at most one shipment at a time.
   *
   * @param connection
   * @param body Shipment creation details including the list of order item IDs to include, carrier name, and tracking number for the package.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Create a shipment for the authenticated seller.
   *
   * 1. Verify the authenticated seller's `approval_status` is 'approved' — reject with appropriate error if pending or rejected.
   * 2. For each `orderItemId` in the request:
   *    a. Load the `e_commerce_mall_order_items` record.
   *    b. Verify the order item's `e_commerce_mall_product_variant_id` belongs to a product owned by this seller (check via `e_commerce_mall_products.seller_id`).
   *    c. Verify the order item's `status` is 'paid' — reject if any other status.
   *    d. Verify there is no existing `e_commerce_mall_shipment_items` record for this order item — reject if already in another shipment.
   * 3. Validate at least one order item was provided — reject empty list.
   * 4. Create the `e_commerce_mall_shipments` record with the seller_id, carrier_name, tracking_number, and shipped_at set to current timestamp.
   * 5. Create `e_commerce_mall_shipment_items` records linking each selected order item to the new shipment.
   * 6. Update all included order items' status to 'shipped' and record status changes in `e_commerce_mall_order_item_status_logs`.
   * 7. Return the created shipment with its associated items.
   *
   * Edge cases: If any validation fails (wrong seller, wrong status, already shipped, empty list), reject the entire operation — no partial shipment creation.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IECommerceMallShipment.ICreate,
  ): Promise<IECommerceMallShipment> {
    try {
      return await postECommerceMallSellerShipments({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and list shipments with filtering and pagination.
   *
   * This endpoint allows sellers to view their dispatched shipments, customers to view shipments associated with their orders for tracking purposes, and administrators to view all shipments across the platform for oversight. Each shipment represents a physical package containing one or more order items from the same seller, with shared carrier name, tracking number, and shipment/delivery timestamps.
   *
   * Results are paginated and sorted by shipment creation date (newest first by default). Optional filters narrow results by carrier name, tracking number, shipment date range, delivery status (shipped or delivered), and delivery date range. Access is automatically scoped by actor type through authentication — sellers see only their own shipments, customers see shipments tied to their orders, and administrators see all shipments.
   *
   * Soft-deleted shipments are excluded from results unless explicitly requested by administrators.
   *
   * @param connection
   * @param body Search criteria for filtering shipments, including carrier name, tracking number, shipment and delivery date ranges, delivery status filter, and standard pagination parameters (page, limit, sort).
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query the e_commerce_mall_shipments table with pagination and optional search filters.
   *
   * Apply actor-based authorization scoping:
   * - Seller: filter by seller_id matching the authenticated seller's ID
   * - Customer: join through e_commerce_mall_shipment_items → e_commerce_mall_order_items → e_commerce_mall_orders, filter by e_commerce_mall_orders.e_commerce_mall_customer_id matching the authenticated customer
   * - Administrator: no seller/customer filter — view all shipments across the platform
   *
   * Search filters (all optional, applied via AND logic):
   * - carrierName: partial/fuzzy match on carrier_name field
   * - trackingNumber: partial/fuzzy match on tracking_number field
   * - shippedAtFrom/shippedAtTo: date range filter on shipped_at timestamp
   * - deliveredAtFrom/deliveredAtTo: date range filter on delivered_at timestamp
   * - deliveryStatus: enum filter — 'shipped' (delivered_at IS NULL) or 'delivered' (delivered_at IS NOT NULL)
   *
   * Soft-delete handling: exclude records where deleted_at IS NOT NULL by default. Administrators may optionally include soft-deleted records.
   *
   * Include standard pagination parameters: page (1-based index), limit (items per page), and sort (field and direction). Default sort is by created_at descending.
   *
   * Return summary fields for each shipment: id, carrier_name, tracking_number, shipped_at, delivered_at, and the count of associated order items (aggregated from e_commerce_mall_shipment_items).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IECommerceMallShipment.IRequest,
  ): Promise<IPageIECommerceMallShipment.ISummary> {
    try {
      return await patchECommerceMallSellerShipments({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single shipment by its unique identifier.
   *
   * Returns the complete shipment record including carrier name, tracking number, shipping timestamp, and delivery confirmation timestamp. The response also includes all order items contained within this shipment, each with its product variant reference, quantity, unit price at the time of purchase, and current fulfillment status (paid, shipped, delivered, cancelled, or refunded).
   *
   * This endpoint serves multiple actors: sellers use it to view tracking details of their dispatched packages, customers use it to track delivery progress of their orders (accessible through order detail pages), and administrators use it for platform order oversight. The shipment's seller association and the related order information are accessible through the respective reference fields in the response.
   *
   * @param connection
   * @param shipmentId Unique UUID identifier of the shipment to retrieve.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query e_commerce_mall_shipments table by id with deleted_at IS NULL filter to exclude soft-deleted records. Join with e_commerce_mall_shipment_items (1-to-many) to include all order items in the shipment. Further join with e_commerce_mall_order_items to retrieve item details (quantity, unit_price, status) and with e_commerce_mall_product_variants for product variant identification. Also join with e_commerce_mall_orders for the parent order reference. If no active shipment found with the given id, return 404 Not Found. The response should structure shipment-level fields at the top level and include a nested array of order items with their details.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":shipmentId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("shipmentId")
    shipmentId: string & tags.Format<"uuid">,
  ): Promise<IECommerceMallShipment> {
    try {
      return await getECommerceMallSellerShipmentsShipmentId({
        seller,
        shipmentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
