export async function test_api_cancellation_request_approved_snapshot_view_by_administrator(
  connection: api.IConnection,
): Promise<void> {
  //-----
  // Setup: Create and authenticate an administrator
  //-----
  const adminConnection: api.IConnection = { host: connection.host };
  const adminAuthorized = await authorize_administrator_join(adminConnection, {
    body: typia.random<IECommerceMallAdministrator.IJoin>(),
  });
  typia.assert(adminAuthorized);
  //-----
  // Execute: Retrieve a cancellation request snapshot
  //-----
  const snapshot: IECommerceMallCancellationRequestSnapshot =
    await api.functional.eCommerceMall.administrator.cancellation_requests.snapshots.at(
      adminConnection,
      {
        cancellationRequestId: typia.random<string & tags.Format<"uuid">>(),
        snapshotId: typia.random<string & tags.Format<"uuid">>(),
      },
    );
  typia.assert(snapshot);
}
