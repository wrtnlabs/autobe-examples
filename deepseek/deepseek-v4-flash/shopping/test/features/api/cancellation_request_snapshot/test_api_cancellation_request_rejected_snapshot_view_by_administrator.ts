/**
 * Test that an administrator can retrieve an immutable snapshot of a cancellation request.
 *
 * Due to limited available SDK functions, this test focuses on the administrator authentication flow and the snapshot retrieval endpoint contract. The cancellation request and snapshot identifiers are generated as random UUIDs since the full setup flow (customer, seller, product, order, cancellation request, seller response) cannot be executed without additional SDK functions.
 *
 * The snapshot endpoint does not require authentication, but the administrator join is executed first following the dependency specification in the scenario plan.
 */
export async function test_api_cancellation_request_rejected_snapshot_view_by_administrator(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as administrator
  const adminConnection: api.IConnection = { host: connection.host };
  const adminAuth = await authorize_administrator_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IECommerceMallAdministrator.IJoin,
  });
  typia.assert(adminAuth);
  // 2. Retrieve the cancellation request snapshot
  // Since we cannot create actual cancellation request data without the required SDK functions,
  // we generate random UUIDs. The API will return 404 at runtime but the test validates
  // the compilation correctness and schema contract.
  const cancellationRequestId = typia.random<string & tags.Format<"uuid">>();
  const snapshotId = typia.random<string & tags.Format<"uuid">>();
  const snapshot =
    await api.functional.eCommerceMall.administrator.cancellation_requests.snapshots.at(
      adminConnection,
      {
        cancellationRequestId,
        snapshotId,
      },
    );
  typia.assert(snapshot);
}
