export async function test_api_inventory_rejected_when_seller_suspended(
  connection: api.IConnection,
): Promise<void> {
  //----
  // 1. Seller Setup
  //----
  // 1.1. Seller A joins
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerEmail = typia.random<string & tags.Format<"email">>();
  const sellerPassword = "1234";
  const seller = await authorize_seller_join(sellerConnection, {
    body: {
      email: sellerEmail,
      password: sellerPassword,
      shop_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IECommerceMallSeller.IJoin,
  });
  typia.assert(seller);
  // 1.2. Seller A creates a product
  const product = await generate_random_e_commerce_mall_seller_products_create(
    sellerConnection,
    {},
  );
  typia.assert(product);
  // 1.3. Seller A creates a variant under that product
  const variant =
    await generate_random_e_commerce_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: {
          productId: product.id,
        },
      },
    );
  typia.assert(variant);
  //----
  // 2. Administrator Suspends Seller
  //----
  // 2.1. Administrator joins
  const adminConnection: api.IConnection = { host: connection.host };
  const admin = await authorize_administrator_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "1234",
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IECommerceMallAdministrator.IJoin,
  });
  typia.assert(admin);
  // 2.2. Administrator suspends Seller A
  await api.functional.eCommerceMall.administrator.sellers.suspend(
    adminConnection,
    {
      sellerId: seller.id,
      body: {
        reason: "Violation of platform policies",
      } satisfies IECommerceMallSeller.ISuspend,
    },
  );
  //----
  // 3. Attempt Inventory Creation - Should Be Rejected
  //----
  await TestValidator.httpError(
    "inventory creation should be rejected when seller suspended",
    403,
    async () => {
      await api.functional.eCommerceMall.seller.products.variants.inventory.create(
        sellerConnection,
        {
          productId: product.id,
          variantId: variant.id,
          body: {
            quantity_change: typia.random<
              number & tags.Type<"int32"> & tags.Minimum<1>
            >(),
            reason: "Restock attempt while suspended",
          } satisfies IECommerceMallInventoryRecord.ICreate,
        },
      );
    },
  );
}
