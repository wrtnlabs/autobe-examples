export async function test_api_administrator_product_browse_excludes_suspended_seller_products(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as administrator
  const adminConnection: api.IConnection = { host: connection.host };
  const authorized = await authorize_administrator_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IECommerceMallAdministrator.IJoin,
  });
  typia.assert(authorized);
  // 2. Browse all products as administrator
  const page = await api.functional.eCommerceMall.administrator.products.index(
    adminConnection,
    {
      body: {} satisfies IECommerceMallProduct.IRequest,
    },
  );
  typia.assert(page);
  // 3. Validate that no product has "suspended" visibility
  for (const product of page.data) {
    TestValidator.predicate(
      `product ${product.id} should not be from a suspended seller`,
      () => product.visibility !== "suspended",
    );
  }
}
