export async function test_api_super_administrator_force_refund_paid_order_item(
  connection: api.IConnection,
): Promise<void> {
  // 1. Seller setup: join → create product → create variant → restock
  const sellerConnection: api.IConnection = { host: connection.host };
  const seller = await authorize_seller_join(sellerConnection, {});
  typia.assert(seller);
  const product = await generate_random_e_commerce_mall_seller_products_create(
    sellerConnection,
    { body: { category_id: null } },
  );
  typia.assert(product);
  const variant =
    await generate_random_e_commerce_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
      },
    );
  typia.assert(variant);
  const inventoryRecord =
    await generate_random_e_commerce_mall_seller_products_variants_inventory_create(
      sellerConnection,
      {
        params: { productId: product.id, variantId: variant.id },
        body: {
          quantity_change: 100,
          reason: "seller restock",
        },
      },
    );
  typia.assert(inventoryRecord);
  // 2. Customer setup: join → create address → add to cart → place order
  const customerConnection: api.IConnection = { host: connection.host };
  const customer = await authorize_customer_join(customerConnection, {});
  typia.assert(customer);
  const address =
    await generate_random_e_commerce_mall_customer_addresses_create(
      customerConnection,
      {},
    );
  typia.assert(address);
  const cartItem =
    await generate_random_e_commerce_mall_customer_cart_items_create(
      customerConnection,
      {
        body: {
          product_variant_id: variant.id,
          quantity: 2,
        },
      },
    );
  typia.assert(cartItem);
  const order = await generate_random_e_commerce_mall_customer_orders_create(
    customerConnection,
    {
      body: {
        addressId: address.id,
      },
    },
  );
  typia.assert(order);
  const orderItem = order.orderItems[0];
  TestValidator.equals("order item status is paid", orderItem.status, "paid");
  // 3. Super administrator setup
  const superAdminConnection: api.IConnection = { host: connection.host };
  const superAdmin = await authorize_super_administrator_join(
    superAdminConnection,
    {},
  );
  typia.assert(superAdmin);
  // 4. Force-refund the paid order item
  const refundedItem =
    await api.functional.eCommerceMall.superAdministrator.order_items.force_refund.create(
      superAdminConnection,
      { itemId: orderItem.id },
    );
  typia.assert(refundedItem);
  // 5. Validations
  TestValidator.equals(
    "status changed to refunded",
    refundedItem.status,
    "refunded",
  );
  TestValidator.notEquals(
    "updated_at changed",
    orderItem.updated_at,
    refundedItem.updated_at,
  );
  const forceRefundLog = refundedItem.statusLogs.find(
    (log) => log.reason === "administrator_force_refund",
  );
  TestValidator.predicate(
    "force refund status log exists",
    () => forceRefundLog !== undefined,
  );
  TestValidator.equals(
    "from status is paid",
    forceRefundLog!.from_status,
    "paid",
  );
  TestValidator.equals(
    "to status is refunded",
    forceRefundLog!.to_status,
    "refunded",
  );
}
