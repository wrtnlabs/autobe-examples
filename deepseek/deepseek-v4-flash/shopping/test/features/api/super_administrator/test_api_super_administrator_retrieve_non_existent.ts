export async function test_api_super_administrator_retrieve_non_existent(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create a regular administrator account
  const adminConnection: api.IConnection = { host: connection.host };
  const admin = await authorize_administrator_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IECommerceMallAdministrator.IJoin,
  });
  typia.assert(admin);
  // 2. Promote the regular administrator to super administrator
  const superAdminConnection: api.IConnection = { host: connection.host };
  const superAdmin = await authorize_super_administrator_join(
    superAdminConnection,
    {
      body: {
        administrator_id: admin.id,
        email: typia.random<string & tags.Format<"email">>(),
        password: RandomGenerator.alphaNumeric(16),
        href: typia.random<string & tags.Format<"uri">>(),
        referrer: typia.random<string & tags.Format<"uri">>(),
        ip: typia.random<string & tags.Format<"ipv4">>(),
      },
    },
  );
  typia.assert(superAdmin);
  // 3. Generate a UUID that does not correspond to any existing super administrator
  const nonExistentId = typia.random<string & tags.Format<"uuid">>();
  // 4. Attempt to retrieve the non-existent super administrator — must return 404
  await TestValidator.httpError(
    "retrieve non-existent super administrator returns 404",
    404,
    async () => {
      await api.functional.eCommerceMall.superAdministrator.super_administrators.at(
        superAdminConnection,
        {
          superAdministratorId: nonExistentId,
        },
      );
    },
  );
}
