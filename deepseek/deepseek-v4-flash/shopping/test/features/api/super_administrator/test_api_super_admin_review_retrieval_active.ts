export async function test_api_super_admin_review_retrieval_active(
  connection: api.IConnection,
): Promise<void> {
  // 1. Super administrator setup
  const superAdminConnection: api.IConnection = { host: connection.host };
  const superAdmin = await authorize_super_administrator_join(
    superAdminConnection,
    {},
  );
  typia.assert(superAdmin);
  // 2. Customer setup
  const customerConnection: api.IConnection = { host: connection.host };
  const customer = await authorize_customer_join(customerConnection, {});
  typia.assert(customer);
  // 3. Customer creates a shipping address
  const address =
    await generate_random_e_commerce_mall_customer_addresses_create(
      customerConnection,
      {},
    );
  typia.assert(address);
  // 4. Seller setup
  const sellerConnection: api.IConnection = { host: connection.host };
  const seller = await authorize_seller_join(sellerConnection, {});
  typia.assert(seller);
  // 5. Seller creates a product
  const product = await generate_random_e_commerce_mall_seller_products_create(
    sellerConnection,
    {},
  );
  typia.assert(product);
  // 6. Seller creates a variant under the product
  const variant =
    await generate_random_e_commerce_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
      },
    );
  typia.assert(variant);
  // 7. Customer adds the variant to cart
  const cartItem =
    await generate_random_e_commerce_mall_customer_cart_items_create(
      customerConnection,
      {
        body: {
          product_variant_id: variant.id,
          quantity: 1,
        },
      },
    );
  typia.assert(cartItem);
  // 8. Customer places an order using the saved address
  const order = await generate_random_e_commerce_mall_customer_orders_create(
    customerConnection,
    {
      body: {
        addressId: address.id,
      },
    },
  );
  typia.assert(order);
  const orderItem = order.orderItems[0];
  typia.assert(orderItem);
  // 9. Seller creates a shipment for the order item
  const shipment =
    await generate_random_e_commerce_mall_seller_shipments_create(
      sellerConnection,
      {
        body: {
          orderItemIds: [orderItem.id],
        },
      },
    );
  typia.assert(shipment);
  // 10. Customer confirms delivery
  const confirmedShipment =
    await api.functional.eCommerceMall.customer.shipments.confirm_delivery.confirmDelivery(
      customerConnection,
      {
        shipmentId: shipment.id,
      },
    );
  typia.assert(confirmedShipment);
  // 11. Customer writes a review for the delivered order item
  const rating = typia.random<
    number & tags.Type<"int32"> & tags.Minimum<1> & tags.Maximum<5>
  >();
  const reviewContent = RandomGenerator.paragraph({ sentences: 2 });
  const review = await generate_random_e_commerce_mall_customer_reviews_create(
    customerConnection,
    {
      body: {
        order_item_id: orderItem.id,
        rating,
        content: reviewContent,
      },
    },
  );
  typia.assert(review);
  // 12. Super administrator retrieves the review by ID
  const retrieved =
    await api.functional.eCommerceMall.superAdministrator.reviews.at(
      superAdminConnection,
      {
        reviewId: review.id,
      },
    );
  typia.assert(retrieved);
  // 13. Validate review details
  TestValidator.equals(
    "rating matches submitted value",
    retrieved.rating,
    rating,
  );
  TestValidator.equals(
    "content matches submitted value",
    retrieved.content,
    reviewContent,
  );
  TestValidator.equals(
    "customer display name matches",
    retrieved.customer.profile?.display_name,
    customer.profile.display_name,
  );
  TestValidator.equals("product id matches", retrieved.product.id, product.id);
  TestValidator.equals(
    "product name matches",
    retrieved.product.name,
    product.name,
  );
  TestValidator.equals(
    "order item id matches",
    retrieved.orderItem.id,
    orderItem.id,
  );
  TestValidator.equals("order id matches", retrieved.order.id, order.id);
  TestValidator.predicate(
    "created_at timestamp is present",
    () => !!retrieved.created_at,
  );
  TestValidator.predicate(
    "updated_at timestamp is present",
    () => !!retrieved.updated_at,
  );
  TestValidator.equals(
    "deleted_at is null for active review",
    retrieved.deleted_at,
    null,
  );
}
