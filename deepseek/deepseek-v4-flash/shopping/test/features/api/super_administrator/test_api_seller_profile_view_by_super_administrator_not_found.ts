export async function test_api_seller_profile_view_by_super_administrator_not_found(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create an administrator account
  const adminConnection: api.IConnection = { host: connection.host };
  const admin = await authorize_administrator_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IECommerceMallAdministrator.IJoin,
  });
  typia.assert(admin);
  // 2. Promote the administrator to super administrator status
  const superAdmin = await authorize_super_administrator_join(adminConnection, {
    body: {
      administrator_id: admin.id,
    },
  });
  typia.assert(superAdmin);
  // adminConnection now has super administrator authorization header
  // 3. Attempt to retrieve a seller using a non-existent UUID
  const nonExistentSellerId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.httpError(
    "non-existent seller returns 404",
    404,
    async () => {
      await api.functional.eCommerceMall.superAdministrator.sellers.at(
        adminConnection,
        {
          sellerId: nonExistentSellerId,
        },
      );
    },
  );
}
