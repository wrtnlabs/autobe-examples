export async function test_api_super_administrator_force_refund_entire_order(
  connection: api.IConnection,
): Promise<void> {
  //----
  // 1. Create administrator and promote to super administrator
  //----
  const adminConnection: api.IConnection = { host: connection.host };
  const adminAuthorized = await authorize_administrator_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IECommerceMallAdministrator.IJoin,
  });
  typia.assert(adminAuthorized);
  const superAdminConnection: api.IConnection = { host: connection.host };
  const superAdminAuthorized = await authorize_super_administrator_join(
    superAdminConnection,
    {
      body: {
        administrator_id: adminAuthorized.id,
      },
    },
  );
  typia.assert(superAdminAuthorized);
  //----
  // 2. Create seller, product, and variant
  //----
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuthorized = await authorize_seller_join(sellerConnection, {});
  typia.assert(sellerAuthorized);
  const product = await generate_random_e_commerce_mall_seller_products_create(
    sellerConnection,
    {},
  );
  typia.assert(product);
  const variant =
    await generate_random_e_commerce_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: {
          productId: product.id,
        },
      },
    );
  typia.assert(variant);
  //----
  // 3. Create customer, address, and place order
  //----
  const customerConnection: api.IConnection = { host: connection.host };
  const customerAuthorized = await authorize_customer_join(
    customerConnection,
    {},
  );
  typia.assert(customerAuthorized);
  const address =
    await generate_random_e_commerce_mall_customer_addresses_create(
      customerConnection,
      {},
    );
  typia.assert(address);
  const cartItem =
    await generate_random_e_commerce_mall_customer_cart_items_create(
      customerConnection,
      {
        body: {
          product_variant_id: variant.id,
          quantity: 1,
        },
      },
    );
  typia.assert(cartItem);
  const order = await generate_random_e_commerce_mall_customer_orders_create(
    customerConnection,
    {
      body: {
        addressId: address.id,
      },
    },
  );
  typia.assert(order);
  //----
  // 4. Force-refund the entire order via super administrator
  //----
  const forceRefundResponse =
    await api.functional.eCommerceMall.superAdministrator.orders.force_refund.forceRefund(
      superAdminConnection,
      {
        orderCode: order.code,
        body: {},
      },
    );
  typia.assert(forceRefundResponse);
  // All order items should be in refundedItems
  TestValidator.equals(
    "number of refunded items matches order items",
    forceRefundResponse.refundedItems.length,
    order.orderItems.length,
  );
  // Skipped items should be empty (all items were refunded)
  TestValidator.equals(
    "skipped items are empty",
    forceRefundResponse.skippedItems.length,
    0,
  );
  // Each refunded item should have status 'refunded'
  for (const item of forceRefundResponse.refundedItems) {
    TestValidator.equals(
      `item ${item.id} status is refunded`,
      item.status,
      "refunded",
    );
  }
}
