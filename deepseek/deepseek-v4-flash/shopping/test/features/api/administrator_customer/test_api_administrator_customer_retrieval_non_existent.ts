export async function test_api_administrator_customer_retrieval_non_existent(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create administrator connection
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_administrator_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IECommerceMallAdministrator.IJoin,
  });
  // 2. Generate a random non-existent customer UUID
  const nonExistentCustomerId: string & tags.Format<"uuid"> = typia.random<
    string & tags.Format<"uuid">
  >();
  // 3. Attempt to retrieve a non-existent customer - expect 404
  await TestValidator.httpError(
    "customer not found",
    404,
    async () =>
      await api.functional.eCommerceMall.administrator.customers.at(
        adminConnection,
        {
          customerId: nonExistentCustomerId,
        },
      ),
  );
}
