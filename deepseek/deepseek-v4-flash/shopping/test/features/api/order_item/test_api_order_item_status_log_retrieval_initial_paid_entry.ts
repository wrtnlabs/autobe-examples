export async function test_api_order_item_status_log_retrieval_initial_paid_entry(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate seller
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {});
  // 2. Authenticate customer
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  // 3. Seller creates a product
  const product = await generate_random_e_commerce_mall_seller_products_create(
    sellerConnection,
    {},
  );
  // 4. Seller creates a variant
  const variant =
    await generate_random_e_commerce_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: {
          productId: product.id,
        },
      },
    );
  // 5. Seller restocks inventory
  const inventoryRecord: IECommerceMallInventoryRecord =
    await generate_random_e_commerce_mall_seller_products_variants_inventory_create(
      sellerConnection,
      {
        params: {
          productId: product.id,
          variantId: variant.id,
        },
      },
    );
  // 6. Customer creates a shipping address
  const address =
    await generate_random_e_commerce_mall_customer_addresses_create(
      customerConnection,
      {},
    );
  // 7. Customer adds the variant to the cart
  await generate_random_e_commerce_mall_customer_cart_items_create(
    customerConnection,
    {
      body: {
        product_variant_id: variant.id,
      },
    },
  );
  // 8. Customer places the order
  const order: IECommerceMallOrder =
    await generate_random_e_commerce_mall_customer_orders_create(
      customerConnection,
      {
        body: {
          addressId: address.id,
        },
      },
    );
  typia.assert(order);
  // 9. Extract the order item and its first status log
  const orderItem = order.orderItems[0];
  typia.assert(orderItem);
  const statusLogs = orderItem.statusLogs;
  typia.assert(statusLogs);
  // 10. Seller retrieves the status log via the dedicated endpoint
  const logId = statusLogs[0].id;
  const retrieved: IECommerceMallOrderItemStatusLog =
    await api.functional.eCommerceMall.seller.order_items.status_logs.at(
      sellerConnection,
      {
        itemId: orderItem.id,
        logId: logId,
      },
    );
  typia.assert(retrieved);
  // 11. Validate the initial status log properties
  TestValidator.equals(
    "from_status is null for initial status log",
    retrieved.from_status,
    null,
  );
  TestValidator.equals(
    "to_status is 'paid' for initial status log",
    retrieved.to_status,
    "paid",
  );
  TestValidator.equals(
    "reason is null for initial status log",
    retrieved.reason,
    null,
  );
}