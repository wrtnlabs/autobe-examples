/**
 * Test that the system returns 404 when an administrator attempts to retrieve a shipment item association that does not exist.
 *
 * Validates the edge case where both the shipment ID and item ID path parameters reference non-existent records in the e_commerce_mall_shipment_items junction table. The administrator must be authenticated first — the 404 is triggered by the missing junction record, not by authorization failure.
 *
 * 1. Register and authenticate as an administrator using randomized credentials.
 * 2. Attempt to retrieve a shipment item with non-existent UUIDs for both shipmentId and itemId.
 * 3. Validate that a 404 Not Found HTTP error is thrown.
 */
export async function test_api_shipment_item_not_found(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register and authenticate as an administrator
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_administrator_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IECommerceMallAdministrator.IJoin,
  });
  // 2. Attempt to retrieve a non-existent shipment item → expect 404
  await TestValidator.httpError("shipment item not found", 404, () =>
    api.functional.eCommerceMall.administrator.shipments.items.at(
      adminConnection,
      {
        shipmentId: typia.random<string & tags.Format<"uuid">>(),
        itemId: typia.random<string & tags.Format<"uuid">>(),
      },
    ),
  );
}
