export async function test_api_shipment_item_admin_retrieval(
  connection: api.IConnection,
): Promise<void> {
  // 1. Administrator setup
  const adminConnection: api.IConnection = { host: connection.host };
  const adminAuth = await authorize_administrator_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IECommerceMallAdministrator.IJoin,
  });
  typia.assert(adminAuth);
  // 2. Customer setup
  const customerConnection: api.IConnection = { host: connection.host };
  const customerAuth = await authorize_customer_join(customerConnection, {
    body: {},
  });
  typia.assert(customerAuth);
  // 3. Create shipping address for customer
  const address =
    await generate_random_e_commerce_mall_customer_addresses_create(
      customerConnection,
      { body: {} },
    );
  typia.assert(address);
  // 4. Seller setup
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {
    body: {},
  });
  typia.assert(sellerAuth);
  // 5. Create a product as the seller
  const product = await generate_random_e_commerce_mall_seller_products_create(
    sellerConnection,
    { body: {} },
  );
  typia.assert(product);
  // 6. Create a variant for the product
  const variant =
    await generate_random_e_commerce_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
        body: {},
      },
    );
  typia.assert(variant);
  // 7. Add stock to the variant
  const inventoryRecord =
    await generate_random_e_commerce_mall_seller_products_variants_inventory_create(
      sellerConnection,
      {
        params: {
          productId: product.id,
          variantId: variant.id,
        },
        body: {
          quantity_change: 100,
          reason: "initial restock",
        },
      },
    );
  typia.assert(inventoryRecord);
  // 8. Add the variant to customer's cart
  const cartItem =
    await generate_random_e_commerce_mall_customer_cart_items_create(
      customerConnection,
      {
        body: {
          product_variant_id: variant.id,
          quantity: 1,
        },
      },
    );
  typia.assert(cartItem);
  // 9. Place an order as customer
  const order = await generate_random_e_commerce_mall_customer_orders_create(
    customerConnection,
    {
      body: {
        addressId: address.id,
      },
    },
  );
  typia.assert(order);
  // 10. List paid order items as seller to find the order item ID
  const page = await api.functional.eCommerceMall.seller.order_items.index(
    sellerConnection,
    {
      body: {
        status: ["paid"],
        page: 1,
        limit: 10,
      } satisfies IECommerceMallOrderItem.IRequest,
    },
  );
  typia.assert(page);
  const orderItemId = page.data[0].id;
  // 11. Create a shipment containing the order item
  const carrierName = RandomGenerator.name();
  const trackingNumber = RandomGenerator.alphaNumeric(16);
  const shipment =
    await generate_random_e_commerce_mall_seller_shipments_create(
      sellerConnection,
      {
        body: {
          carrierName,
          trackingNumber,
          orderItemIds: [orderItemId],
        } satisfies DeepPartial<IECommerceMallShipment.ICreate>,
      },
    );
  typia.assert(shipment);
  // 12. Administrator retrieves the shipment item
  const result: IECommerceMallShipmentItem =
    await api.functional.eCommerceMall.administrator.shipments.items.at(
      adminConnection,
      {
        shipmentId: shipment.id,
        itemId: orderItemId,
      },
    );
  typia.assert(result);
  // Validate the response structure
  TestValidator.equals("shipment id matches", result.shipment.id, shipment.id);
  TestValidator.equals(
    "carrier name",
    result.shipment.carrier_name,
    carrierName,
  );
  TestValidator.equals(
    "tracking number",
    result.shipment.tracking_number,
    trackingNumber,
  );
  TestValidator.predicate(
    "shipped_at exists",
    result.shipment.shipped_at !== null,
  );
  TestValidator.equals(
    "order item id matches",
    result.orderItem.id,
    orderItemId,
  );
  TestValidator.equals("order item status", result.orderItem.status, "shipped");
  TestValidator.equals(
    "snapshot product name exists",
    typeof result.snapshot.productName,
    "string",
  );
  TestValidator.equals(
    "seller snapshot shop name exists",
    typeof result.sellerSnapshot.shop_name,
    "string",
  );
  TestValidator.predicate("created_at exists", result.created_at !== null);
}
