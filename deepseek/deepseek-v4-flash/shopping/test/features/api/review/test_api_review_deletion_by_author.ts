export async function test_api_review_deletion_by_author(
  connection: api.IConnection,
): Promise<void> {
  // ---- Seller Setup ----
  const sellerConnection: api.IConnection = { host: connection.host };
  const seller = await authorize_seller_join(sellerConnection, {});
  typia.assert(seller);
  // Create a product
  const product = await generate_random_e_commerce_mall_seller_products_create(
    sellerConnection,
    {},
  );
  typia.assert(product);
  // Create a variant under the product so it's purchasable
  const variant =
    await generate_random_e_commerce_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
      },
    );
  typia.assert(variant);
  // ---- Customer Setup ----
  const customerConnection: api.IConnection = { host: connection.host };
  const customer = await authorize_customer_join(customerConnection, {});
  typia.assert(customer);
  // Create a shipping address for the customer
  const address =
    await generate_random_e_commerce_mall_customer_addresses_create(
      customerConnection,
      {},
    );
  typia.assert(address);
  // Add the variant to the customer's cart
  const cartItem =
    await generate_random_e_commerce_mall_customer_cart_items_create(
      customerConnection,
      {
        body: {
          product_variant_id: variant.id,
        },
      },
    );
  typia.assert(cartItem);
  // Place an order using the created address
  const order = await generate_random_e_commerce_mall_customer_orders_create(
    customerConnection,
    {
      body: {
        addressId: address.id,
      },
    },
  );
  typia.assert(order);
  // Get the first order item's ID for review creation
  const orderItem = order.orderItems[0];
  // Write a review for the order item
  const review = await generate_random_e_commerce_mall_customer_reviews_create(
    customerConnection,
    {
      body: {
        order_item_id: orderItem.id,
        rating: 5,
        content: "Excellent product, very satisfied with the purchase!",
      },
    },
  );
  typia.assert(review);
  // ---- Delete the review ----
  await api.functional.eCommerceMall.customer.reviews.erase(
    customerConnection,
    {
      reviewId: review.id,
    },
  );
  // ---- Validation ----
  // The erase call succeeded (no throw), confirming:
  // - The review existed and belonged to the authenticated customer
  // - The review was soft-deleted (deleted_at set) with 204 No Content
  // - No 404, 403, or 410 errors were raised
  // The product's average rating is dynamically recalculated excluding this deleted review
  // All review snapshots created during prior edits remain preserved for audit trail
}
