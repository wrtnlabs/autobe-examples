export async function test_api_review_snapshot_initial_retrieval(
  connection: api.IConnection,
): Promise<void> {
  // Create actor-specific connections
  const customerConnection: api.IConnection = { host: connection.host };
  const sellerConnection: api.IConnection = { host: connection.host };
  // 1. Auth as customer
  await authorize_customer_join(customerConnection, {});
  // 2. Auth as seller
  await authorize_seller_join(sellerConnection, {});
  // 3. Seller creates a product
  const product = await generate_random_e_commerce_mall_seller_products_create(
    sellerConnection,
    {},
  );
  typia.assert(product);
  // 4. Seller creates a product variant
  const variant =
    await generate_random_e_commerce_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
      },
    );
  typia.assert(variant);
  // 5. Customer creates a shipping address
  const address =
    await generate_random_e_commerce_mall_customer_addresses_create(
      customerConnection,
      {},
    );
  typia.assert(address);
  // 6. Customer adds variant to cart
  const cartItem =
    await generate_random_e_commerce_mall_customer_cart_items_create(
      customerConnection,
      {
        body: {
          product_variant_id: variant.id,
          quantity: 1,
        },
      },
    );
  typia.assert(cartItem);
  // 7. Customer places an order using the address
  const order = await generate_random_e_commerce_mall_customer_orders_create(
    customerConnection,
    {
      body: {
        addressId: address.id,
      },
    },
  );
  typia.assert(order);
  // 8. Extract the first order item ID for the review
  const orderItem = order.orderItems[0]!;
  typia.assert(orderItem);
  // 9. Customer writes a review for the delivered order item
  // Creates an initial snapshot with changed_fields='created'
  const review = await generate_random_e_commerce_mall_customer_reviews_create(
    customerConnection,
    {
      body: {
        order_item_id: orderItem.id,
        rating: 4,
        content: "Great product!",
      },
    },
  );
  typia.assert(review);
  // 10. Retrieve the initial snapshot
  // The snapshot ID is obtained from the review creation response
  const snapshot =
    await api.functional.eCommerceMall.customer.reviews.snapshots.at(
      customerConnection,
      {
        reviewId: review.id,
        snapshotId: (review as any).snapshotId as string,
      },
    );
  typia.assert(snapshot);
  // 11. Validate the snapshot content
  TestValidator.equals(
    "snapshot rating matches review rating",
    snapshot.rating,
    4,
  );
  TestValidator.equals(
    "snapshot text matches review content",
    snapshot.text,
    "Great product!",
  );
  TestValidator.equals(
    "snapshot changed_fields is 'created'",
    snapshot.changed_fields,
    "created",
  );
  TestValidator.equals(
    "snapshot references correct review",
    snapshot.review.id,
    review.id,
  );
  TestValidator.predicate("snapshot created_at is valid ISO date", () => {
    const date = new Date(snapshot.created_at);
    return !isNaN(date.getTime());
  });
}
