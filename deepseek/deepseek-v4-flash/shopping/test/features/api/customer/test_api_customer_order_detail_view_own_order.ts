export async function test_api_customer_order_detail_view_own_order(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register a customer account
  const customerConnection: api.IConnection = { host: connection.host };
  const authorized = await authorize_customer_join(customerConnection, {});
  typia.assert(authorized);
  // 2. Attempt to retrieve an order by code
  // Since full setup (seller product, cart, checkout) is not available,
  // verify that looking up a non-existent order returns a 404 error.
  await TestValidator.httpError(
    "non-existent order returns 404",
    404,
    async () => {
      await api.functional.eCommerceMall.customer.orders.at(
        customerConnection,
        {
          orderCode: typia.random<string>(),
        },
      );
    },
  );
}
