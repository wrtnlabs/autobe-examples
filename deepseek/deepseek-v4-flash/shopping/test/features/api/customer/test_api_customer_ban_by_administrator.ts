import { authorize_administrator_join } from "../../../authorize/authorize_administrator_join";
import { authorize_administrator_login } from "../../../authorize/authorize_administrator_login";
import { authorize_administrator_refresh } from "../../../authorize/authorize_administrator_refresh";
import { authorize_customer_join } from "../../../authorize/authorize_customer_join";
import { authorize_customer_login } from "../../../authorize/authorize_customer_login";
import { authorize_customer_refresh } from "../../../authorize/authorize_customer_refresh";

export async function test_api_customer_ban_by_administrator(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create administrator account
  const adminConnection: api.IConnection = { host: connection.host };
  const admin = await authorize_administrator_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IECommerceMallAdministrator.IJoin,
  });
  typia.assert(admin);
  // 2. Create customer account
  const customerConnection: api.IConnection = { host: connection.host };
  const customer = await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: null,
    } satisfies IECommerceMallCustomer.IJoin,
  });
  typia.assert(customer);
  // 3. Ban the customer using the admin connection
  const banned: IECommerceMallCustomer =
    await api.functional.eCommerceMall.administrator.customers.ban(
      adminConnection,
      {
        customerId: customer.id,
      },
    );
  typia.assert(banned);
  // 4. Validate ban was applied
  TestValidator.predicate("customer is banned", banned.banned_at !== null);
  // 5. Validate customer data is preserved
  TestValidator.equals(
    "customer email preserved",
    banned.email,
    customer.email,
  );
  TestValidator.equals(
    "customer display name preserved",
    banned.profile.display_name,
    customer.profile.display_name,
  );
}
