export async function test_api_customer_unban_not_found(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create a regular administrator account
  const adminConnection: api.IConnection = { host: connection.host };
  const admin = await authorize_administrator_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IECommerceMallAdministrator.IJoin,
  });
  typia.assert(admin);
  // 2. Promote the administrator to super administrator status
  const superAdminConnection: api.IConnection = { host: connection.host };
  const superAdmin = await authorize_super_administrator_join(
    superAdminConnection,
    {
      body: {
        administrator_id: admin.id,
      },
    },
  );
  typia.assert(superAdmin);
  // 3. Attempt to unban a non-existent customer — expect 404
  const nonExistentCustomerId =
    "00000000-0000-4000-8000-000000000000" as string & tags.Format<"uuid">;
  await TestValidator.httpError(
    "unban non-existent customer returns 404",
    404,
    async () => {
      await api.functional.eCommerceMall.superAdministrator.customers.unban(
        superAdminConnection,
        {
          customerId: nonExistentCustomerId,
        },
      );
    },
  );
}
