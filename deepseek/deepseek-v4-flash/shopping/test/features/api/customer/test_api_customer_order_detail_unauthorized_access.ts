export async function test_api_customer_order_detail_unauthorized_access(
  connection: api.IConnection,
): Promise<void> {
  // Register Customer A
  const customerAConnection: api.IConnection = { host: connection.host };
  const customerA = await authorize_customer_join(customerAConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  typia.assert(customerA);
  // Register Customer B (different customer)
  const customerBConnection: api.IConnection = { host: connection.host };
  const customerB = await authorize_customer_join(customerBConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  typia.assert(customerB);
  // Both customers should be different
  TestValidator.notEquals("customers are distinct", customerA.id, customerB.id);
  // Customer B tries to access a non-existent order code
  // The endpoint returns 404 for orders that don't exist OR belong to another customer
  // (to prevent leaking order existence)
  const nonExistentOrderCode = typia.random<string>();
  await TestValidator.httpError(
    "Customer B cannot access another customer's order (404)",
    404,
    async () => {
      await api.functional.eCommerceMall.customer.orders.at(
        customerBConnection,
        { orderCode: nonExistentOrderCode },
      );
    },
  );
  // Customer A also cannot access a non-existent order
  await TestValidator.httpError(
    "Customer A also cannot access a non-existent order (404)",
    404,
    async () => {
      await api.functional.eCommerceMall.customer.orders.at(
        customerAConnection,
        { orderCode: nonExistentOrderCode },
      );
    },
  );
}
