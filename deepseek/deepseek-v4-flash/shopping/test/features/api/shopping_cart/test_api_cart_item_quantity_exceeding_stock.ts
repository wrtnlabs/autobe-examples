export async function test_api_cart_item_quantity_exceeding_stock(
  connection: api.IConnection,
): Promise<void> {
  // Create actor-specific connections
  const customerConnection: api.IConnection = { host: connection.host };
  const sellerConnection: api.IConnection = { host: connection.host };
  // 1. Register a customer
  await authorize_customer_join(customerConnection, {});
  // 2. Register a seller
  await authorize_seller_join(sellerConnection, {});
  // 3. Seller creates a product
  const product = await generate_random_e_commerce_mall_seller_products_create(
    sellerConnection,
    {},
  );
  typia.assert(product);
  // 4. Seller creates a variant under the product (stock starts at 0)
  const variant =
    await generate_random_e_commerce_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
      },
    );
  typia.assert(variant);
  // 5. Customer adds the variant to cart with quantity=1
  const cartItem =
    await generate_random_e_commerce_mall_customer_cart_items_create(
      customerConnection,
      {
        body: {
          product_variant_id: variant.id,
          quantity: 1,
        },
      },
    );
  typia.assert(cartItem);
  // Capture the unit price for later validation
  const unitPrice = cartItem.unit_price;
  // 6. Update cart item quantity to 10 (exceeding available stock of 0)
  const updated = await api.functional.eCommerceMall.customer.cart_items.update(
    customerConnection,
    {
      cartItemId: cartItem.id,
      body: { quantity: 10 } satisfies IECommerceMallCartItem.IUpdate,
    },
  );
  typia.assert(updated);
  // 7. Validate
  TestValidator.equals("quantity should be 10", updated.quantity, 10);
  TestValidator.equals("is_available should be false", updated.is_available, false);
  TestValidator.equals("unit_price unchanged", updated.unit_price, unitPrice);
  TestValidator.equals("subtotal correct", updated.subtotal, unitPrice * 10);
}
