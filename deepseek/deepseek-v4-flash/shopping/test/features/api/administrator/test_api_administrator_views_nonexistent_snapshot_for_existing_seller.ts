export async function test_api_administrator_views_nonexistent_snapshot_for_existing_seller(
  connection: api.IConnection,
): Promise<void> {
  // Step 1: Administrator joins
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_administrator_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IECommerceMallAdministrator.IJoin,
  });
  // Step 2: Seller joins
  const sellerConnection: api.IConnection = { host: connection.host };
  const seller = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      shop_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IECommerceMallSeller.IJoin,
  });
  // Step 3: Administrator retrieves a nonexistent snapshot for the existing seller
  await TestValidator.httpError(
    "nonexistent snapshot for existing seller",
    404,
    async () => {
      await api.functional.eCommerceMall.administrator.sellers.profile.snapshots.at(
        adminConnection,
        {
          sellerId: seller.id,
          snapshotId: typia.random<string & tags.Format<"uuid">>(),
        },
      );
    },
  );
}
