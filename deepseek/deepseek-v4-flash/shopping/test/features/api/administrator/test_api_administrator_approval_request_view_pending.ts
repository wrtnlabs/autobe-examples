export async function test_api_administrator_approval_request_view_pending(
  connection: api.IConnection,
): Promise<void> {
  // 1. Administrator joins and authenticates
  const adminConnection: api.IConnection = { host: connection.host };
  const admin = await authorize_administrator_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IECommerceMallAdministrator.IJoin,
  });
  typia.assert(admin);
  // 2. Seller joins (creates seller with pending status and implicitly an approval request)
  const sellerConnection: api.IConnection = { host: connection.host };
  const seller = await authorize_seller_join(sellerConnection, {});
  typia.assert(seller);
  // 3. Administrator retrieves the pending approval request
  const approvalRequest =
    await api.functional.eCommerceMall.administrator.approval_requests.at(
      adminConnection,
      {
        requestId: seller.id,
      },
    );
  typia.assert(approvalRequest);
  // 4. Business logic validation
  TestValidator.equals(
    "approval request status is pending",
    approvalRequest.status,
    "pending",
  );
}
