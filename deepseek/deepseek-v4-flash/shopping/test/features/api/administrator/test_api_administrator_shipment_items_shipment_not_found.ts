export async function test_api_administrator_shipment_items_shipment_not_found(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as administrator
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_administrator_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IECommerceMallAdministrator.IJoin,
  });
  // 2. Query shipment items with non-existent shipment UUID
  const nonExistentShipmentId: string = typia.random<
    string & tags.Format<"uuid">
  >();
  await TestValidator.httpError("shipment not found", 404, () =>
    api.functional.eCommerceMall.administrator.shipments.items.index(
      adminConnection,
      {
        shipmentId: nonExistentShipmentId,
        body: {} satisfies IECommerceMallShipmentItem.IRequest,
      },
    ),
  );
}
