export async function test_api_administrator_shipment_view_not_found(
  connection: api.IConnection,
): Promise<void> {
  // 1. Join as administrator to get a valid auth token
  const adminConnection: api.IConnection = { host: connection.host };
  const authorized = await authorize_administrator_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IECommerceMallAdministrator.IJoin,
  });
  typia.assert(authorized);
  // 2. Generate a non-existent shipment UUID
  const nonExistentShipmentId = typia.random<string & tags.Format<"uuid">>();
  // 3. Attempt to retrieve the non-existent shipment, expect 404
  await TestValidator.httpError("shipment not found", 404, () =>
    api.functional.eCommerceMall.administrator.shipments.at(adminConnection, {
      shipmentId: nonExistentShipmentId,
    }),
  );
}
