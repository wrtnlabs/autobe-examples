export async function test_api_administrator_force_refund_entire_order(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create and authenticate seller
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {});
  // 2. Create a product
  const product = await api.functional.eCommerceMall.seller.products.create(
    sellerConnection,
    {
      body: {
        name: RandomGenerator.paragraph({ sentences: 2 }),
        description: RandomGenerator.content({ paragraphs: 2 }),
        category_id: null,
        base_price: typia.random<
          number & tags.Minimum<1000> & tags.Maximum<100000>
        >(),
      } satisfies IECommerceMallProduct.ICreate,
    },
  );
  typia.assert(product);
  // 3. Create a variant with unique SKU and options
  const variant =
    await api.functional.eCommerceMall.seller.products.variants.create(
      sellerConnection,
      {
        productId: product.id,
        body: {
          sku_code: typia.random<
            string & tags.MinLength<8> & tags.MaxLength<20>
          >(),
          options: [
            {
              key: "color",
              value: RandomGenerator.pick(["Red", "Blue", "Green", "Black"]),
            },
          ] satisfies IECommerceMallProductVariant.IOption[],
        } satisfies IECommerceMallProductVariant.ICreate,
      },
    );
  typia.assert(variant);
  // 4. Create and authenticate customer
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  // 5. Create a shipping address
  const address = await api.functional.eCommerceMall.customer.addresses.create(
    customerConnection,
    {
      body: {
        recipient_name: RandomGenerator.name(),
        phone_number: RandomGenerator.mobile(),
        street_address: RandomGenerator.paragraph({ sentences: 1 }),
        city: RandomGenerator.name(),
        state_province: RandomGenerator.name(),
        postal_code: RandomGenerator.alphaNumeric(5),
        country: "United States",
      } satisfies IECommerceMallCustomerAddress.ICreate,
    },
  );
  typia.assert(address);
  // 6. Add the variant to cart with quantity 2
  const cartItem =
    await api.functional.eCommerceMall.customer.cart_items.create(
      customerConnection,
      {
        body: {
          product_variant_id: variant.id,
          quantity: 2,
        } satisfies IECommerceMallCartItem.ICreate,
      },
    );
  typia.assert(cartItem);
  // 7. Place the order and capture the order code
  const order = await api.functional.eCommerceMall.customer.orders.create(
    customerConnection,
    {
      body: {
        addressId: address.id,
      } satisfies IECommerceMallOrder.ICreate,
    },
  );
  typia.assert(order);
  // 8. Create and authenticate administrator
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_administrator_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IECommerceMallAdministrator.IJoin,
  });
  // 9. Force refund the entire order (empty body = all eligible items)
  const forceRefundResponse =
    await api.functional.eCommerceMall.administrator.orders.force_refund.forceRefund(
      adminConnection,
      {
        orderCode: order.code,
        body: {} satisfies IECommerceMallOrder.IForceRefundRequest,
      },
    );
  typia.assert(forceRefundResponse);
  // 10. Assertions
  // Should have exactly one refunded item
  TestValidator.equals(
    "refunded items count",
    forceRefundResponse.refundedItems.length,
    1,
  );
  // Skipped items should be empty (no items were in terminal state)
  TestValidator.equals(
    "skipped items count",
    forceRefundResponse.skippedItems.length,
    0,
  );
  // Validate refunded item summary details
  const refundedItem = forceRefundResponse.refundedItems[0]!;
  TestValidator.equals("product name", refundedItem.product_name, product.name);
  TestValidator.equals(
    "variant sku",
    refundedItem.variant_sku,
    variant.sku_code,
  );
  TestValidator.equals("quantity", refundedItem.quantity, 2);
  TestValidator.equals("status", refundedItem.status, "refunded");
  TestValidator.predicate(
    "shop name exists",
    refundedItem.shop_name.length > 0,
  );
  TestValidator.predicate(
    "variant options exist",
    refundedItem.variant_options.length > 0,
  );
}
