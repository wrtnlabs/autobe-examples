export async function test_api_admin_force_refund_already_terminal_item_skipped(
  connection: api.IConnection,
): Promise<void> {
  // ---- Setup: Authenticate all actors ----
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_administrator_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    },
  });
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {});
  typia.assert(sellerAuth);
  const customerConnection: api.IConnection = { host: connection.host };
  const customerAuth = await authorize_customer_join(customerConnection, {});
  typia.assert(customerAuth);
  // ---- Setup: Seller creates product, variant, and stock ----
  const product = await generate_random_e_commerce_mall_seller_products_create(
    sellerConnection,
    {},
  );
  typia.assert(product);
  const variant =
    await generate_random_e_commerce_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
      },
    );
  typia.assert(variant);
  await generate_random_e_commerce_mall_seller_products_variants_inventory_create(
    sellerConnection,
    {
      body: {
        quantity_change: 10,
        reason: "seller restock",
      },
      params: {
        productId: product.id,
        variantId: variant.id,
      },
    },
  );
  // ---- Setup: Customer creates address, cart item, and places order ----
  const address =
    await generate_random_e_commerce_mall_customer_addresses_create(
      customerConnection,
      {},
    );
  typia.assert(address);
  await generate_random_e_commerce_mall_customer_cart_items_create(
    customerConnection,
    {
      body: {
        product_variant_id: variant.id,
        quantity: 1,
      },
    },
  );
  const order = await generate_random_e_commerce_mall_customer_orders_create(
    customerConnection,
    {
      body: {
        addressId: address.id,
      },
    },
  );
  typia.assert(order);
  // Extract the order item
  const orderItem = order.orderItems[0];
  typia.assert(orderItem);
  TestValidator.equals("order item status is paid", orderItem.status, "paid");
  const orderItemId = orderItem.id;
  // ---- Act: First force-refund (should succeed) ----
  const firstRefund =
    await api.functional.eCommerceMall.administrator.order_items.force_refund.create(
      adminConnection,
      { itemId: orderItemId },
    );
  typia.assert(firstRefund);
  TestValidator.equals(
    "first force-refund sets status to refunded",
    firstRefund.status,
    "refunded",
  );
  const stockAfterFirstRefund = firstRefund.productVariant.stock;
  // ---- Act: Second force-refund (should skip, not fail) ----
  const secondRefund =
    await api.functional.eCommerceMall.administrator.order_items.force_refund.create(
      adminConnection,
      { itemId: orderItemId },
    );
  typia.assert(secondRefund);
  TestValidator.equals(
    "status remains refunded after skip",
    secondRefund.status,
    "refunded",
  );
  TestValidator.equals(
    "stock unchanged after skipped refund",
    secondRefund.productVariant.stock,
    stockAfterFirstRefund,
  );
}
