export async function test_api_administrator_force_refund_skips_already_refunded_items(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create seller account
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {});
  // 2. Create a product
  const product = await generate_random_e_commerce_mall_seller_products_create(
    sellerConnection,
    {},
  );
  typia.assert(product);
  // 3. Create a variant for the product
  const variant =
    await generate_random_e_commerce_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
      },
    );
  typia.assert(variant);
  // 4. Create customer account
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  // 5. Create a shipping address for the customer
  const address =
    await generate_random_e_commerce_mall_customer_addresses_create(
      customerConnection,
      {},
    );
  typia.assert(address);
  // 6. Add variant to customer cart
  await generate_random_e_commerce_mall_customer_cart_items_create(
    customerConnection,
    {
      body: {
        product_variant_id: variant.id,
        quantity: 1,
      },
    },
  );
  // 7. Place an order with the address
  const order = await generate_random_e_commerce_mall_customer_orders_create(
    customerConnection,
    {
      body: {
        addressId: address.id,
      },
    },
  );
  typia.assert(order);
  // 8. Create administrator account
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_administrator_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  // Step A: First force-refund — should refund the item
  const firstRefund =
    await api.functional.eCommerceMall.administrator.orders.force_refund.forceRefund(
      adminConnection,
      {
        orderCode: order.code,
        body: {},
      },
    );
  typia.assert(firstRefund);
  TestValidator.equals(
    "first force-refund: refunded items count",
    firstRefund.refundedItems.length,
    1,
  );
  TestValidator.equals(
    "first force-refund: skipped items count",
    firstRefund.skippedItems.length,
    0,
  );
  TestValidator.equals(
    "first force-refund: item status is refunded",
    firstRefund.refundedItems[0].status,
    "refunded",
  );
  // Step B: Second force-refund on same order — should skip already refunded item
  const secondRefund =
    await api.functional.eCommerceMall.administrator.orders.force_refund.forceRefund(
      adminConnection,
      {
        orderCode: order.code,
        body: {},
      },
    );
  typia.assert(secondRefund);
  TestValidator.equals(
    "second force-refund: refunded items count",
    secondRefund.refundedItems.length,
    0,
  );
  TestValidator.equals(
    "second force-refund: skipped items count",
    secondRefund.skippedItems.length,
    1,
  );
  TestValidator.equals(
    "second force-refund: skip reason",
    secondRefund.skippedItems[0].reason,
    "already in terminal state",
  );
  TestValidator.equals(
    "second force-refund: skipped item status",
    secondRefund.skippedItems[0].item.status,
    "refunded",
  );
}
