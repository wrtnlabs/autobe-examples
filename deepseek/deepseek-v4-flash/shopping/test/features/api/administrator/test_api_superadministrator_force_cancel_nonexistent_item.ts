export async function test_api_superadministrator_force_cancel_nonexistent_item(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register a regular administrator
  const adminBody = {
    email: typia.random<string & tags.Format<"email">>(),
    password: RandomGenerator.alphaNumeric(16),
    href: typia.random<string & tags.Format<"uri">>(),
    referrer: typia.random<string & tags.Format<"uri">>(),
    ip: typia.random<string & tags.Format<"ipv4">>(),
  } satisfies IECommerceMallAdministrator.IJoin;
  const adminConnection: api.IConnection = { host: connection.host };
  const adminAuthorized = await authorize_administrator_join(adminConnection, {
    body: adminBody,
  });
  typia.assert(adminAuthorized);
  // 2. Promote to super administrator
  const superAdminBody = {
    administrator_id: adminAuthorized.id,
    email: typia.random<string & tags.Format<"email">>(),
    password: RandomGenerator.alphaNumeric(16),
    href: typia.random<string & tags.Format<"uri">>(),
    referrer: typia.random<string & tags.Format<"uri">>(),
    ip: typia.random<string & tags.Format<"ipv4">>(),
  } satisfies IECommerceMallSuperAdministrator.IJoin;
  const superAdminConnection: api.IConnection = { host: connection.host };
  const superAdminAuthorized = await authorize_super_administrator_join(
    superAdminConnection,
    {
      body: superAdminBody,
    },
  );
  typia.assert(superAdminAuthorized);
  // 3. Attempt to force-cancel a non-existent order item
  const nonExistentItemId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.httpError(
    "force-cancel non-existent order item",
    404,
    async () => {
      await api.functional.eCommerceMall.superAdministrator.order_items.force_cancel.forceCancel(
        superAdminConnection,
        {
          itemId: nonExistentItemId,
        },
      );
    },
  );
}
