/**
 * Test that a seller can retrieve refund request snapshots filtered by 'rejected' status.
 *
 * Validates the complete refund request rejection workflow: seller setup with product and variant, customer order placement, refund request creation, seller's rejection response, and filtered snapshot retrieval. Ensures that the snapshot listing with status='rejected' filter returns only rejected snapshots with the customer's original refund reason preserved and valid response timestamps.
 *
 * Special attention is given to verifying that the snapshot's status, reason, and response_timestamp fields are correctly populated from the rejection event.
 */
export async function test_api_refund_request_snapshots_filtered_by_rejected_status(
  connection: api.IConnection,
): Promise<void> {
  // 1. Seller setup: join, create product, create variant
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {});
  const product = await generate_random_e_commerce_mall_seller_products_create(
    sellerConnection,
    {},
  );
  typia.assert(product);
  const variant =
    await generate_random_e_commerce_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
      },
    );
  typia.assert(variant);
  // 2. Customer setup: join, create address, add variant to cart, place order
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  const address =
    await generate_random_e_commerce_mall_customer_addresses_create(
      customerConnection,
      {},
    );
  typia.assert(address);
  await generate_random_e_commerce_mall_customer_cart_items_create(
    customerConnection,
    {
      body: {
        product_variant_id: variant.id,
        quantity: 1,
      },
    },
  );
  const order = await generate_random_e_commerce_mall_customer_orders_create(
    customerConnection,
    {
      body: {
        addressId: address.id,
      },
    },
  );
  typia.assert(order);
  // 3. Customer creates refund request for the delivered order item
  const orderItemId: string = order.orderItems[0].id;
  const refundReason = "Product did not meet expectations";
  const refundRequest =
    await generate_random_e_commerce_mall_customer_refund_requests_create(
      customerConnection,
      {
        body: {
          orderItemId: orderItemId,
          reason: refundReason,
        },
      },
    );
  typia.assert(refundRequest);
  // 4. Seller rejects the refund request (creates a 'rejected' snapshot)
  const rejectedRefundRequest =
    await api.functional.eCommerceMall.seller.refund_requests.update(
      sellerConnection,
      {
        refundRequestId: refundRequest.id,
        body: {
          status: "rejected",
        } satisfies IECommerceMallRefundRequest.IUpdate,
      },
    );
  typia.assert(rejectedRefundRequest);
  // 5. Seller lists snapshots filtered by 'rejected' status
  const snapshotPage =
    await api.functional.eCommerceMall.seller.refund_requests.snapshots.index(
      sellerConnection,
      {
        refundRequestId: refundRequest.id,
        body: {
          status: "rejected",
        } satisfies IECommerceMallRefundRequestSnapshot.IRequest,
      },
    );
  typia.assert(snapshotPage);
  // 6. Validate the filtered snapshots
  TestValidator.equals("snapshots count", snapshotPage.data.length, 1);
  const snapshot = snapshotPage.data[0]!;
  TestValidator.equals(
    "snapshot status is rejected",
    snapshot.status,
    "rejected",
  );
  TestValidator.equals(
    "snapshot reason preserved",
    snapshot.reason,
    refundReason,
  );
  TestValidator.predicate(
    "response_timestamp is valid date-time",
    () => !isNaN(new Date(snapshot.response_timestamp).getTime()),
  );
  TestValidator.predicate(
    "created_at is valid date-time",
    () => !isNaN(new Date(snapshot.created_at).getTime()),
  );
}
