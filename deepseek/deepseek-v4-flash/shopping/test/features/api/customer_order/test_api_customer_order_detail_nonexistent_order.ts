export async function test_api_customer_order_detail_nonexistent_order(
  connection: api.IConnection,
): Promise<void> {
  // Register a customer account to get authenticated access
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  // Attempt to retrieve a non-existent order by a made-up order code
  const nonexistentOrderCode = "NONEXISTENT-ORDER-12345";
  await TestValidator.httpError(
    "should return 404 for non-existent order code",
    404,
    async () => {
      await api.functional.eCommerceMall.customer.orders.at(
        customerConnection,
        {
          orderCode: nonexistentOrderCode,
        },
      );
    },
  );
}
