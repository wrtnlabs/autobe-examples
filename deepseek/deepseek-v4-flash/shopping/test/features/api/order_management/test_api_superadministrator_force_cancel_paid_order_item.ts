/**
 * Test that a super administrator can force-cancel a paid order item.
 *
 * Validates the complete administrative force-cancel workflow including admin registration, promotion to super administrator, product setup by a seller, customer ordering, and the force-cancel operation.
 *
 * This test verifies that the order item status transitions to 'cancelled' and the status log records the reason as 'administrator_force_cancel'.
 *
 * 1. Register a regular administrator and promote to super administrator.
 * 2. Register a seller, create a product with variant, and restock inventory.
 * 3. Register a customer, add a shipping address, add the variant to cart, and place an order.
 * 4. Super administrator force-cancels the paid order item.
 * 5. Validates item status is 'cancelled' and status log contains force-cancel entry.
 */
export async function test_api_superadministrator_force_cancel_paid_order_item(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register a regular administrator
  const adminConnection: api.IConnection = { host: connection.host };
  const admin = await authorize_administrator_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IECommerceMallAdministrator.IJoin,
  });
  typia.assert(admin);
  // 2. Promote the administrator to super administrator
  const superAdminConnection: api.IConnection = { host: connection.host };
  const superAdmin = await authorize_super_administrator_join(
    superAdminConnection,
    {
      body: {
        administrator_id: admin.id,
        email: typia.random<string & tags.Format<"email">>(),
        password: RandomGenerator.alphaNumeric(16),
        href: typia.random<string & tags.Format<"uri">>(),
        referrer: typia.random<string & tags.Format<"uri">>(),
      },
    },
  );
  typia.assert(superAdmin);
  // 3. Register a seller
  const sellerConnection: api.IConnection = { host: connection.host };
  const seller = await authorize_seller_join(sellerConnection, {});
  typia.assert(seller);
  // 4. Seller creates a product (no category assignment)
  const product = await generate_random_e_commerce_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        category_id: null,
      },
    },
  );
  typia.assert(product);
  // 5. Seller creates a product variant
  const variant =
    await generate_random_e_commerce_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: {
          productId: product.id,
        },
      },
    );
  typia.assert(variant);
  // 6. Seller restocks inventory for the variant
  const inventoryRecord =
    await generate_random_e_commerce_mall_seller_products_variants_inventory_create(
      sellerConnection,
      {
        body: {
          quantity_change: 10,
          reason: "initial restock for test",
        },
        params: {
          productId: product.id,
          variantId: variant.id,
        },
      },
    );
  typia.assert(inventoryRecord);
  // 7. Register a customer
  const customerConnection: api.IConnection = { host: connection.host };
  const customer = await authorize_customer_join(customerConnection, {});
  typia.assert(customer);
  // 8. Customer adds a shipping address
  const address =
    await generate_random_e_commerce_mall_customer_addresses_create(
      customerConnection,
      {},
    );
  typia.assert(address);
  // 9. Customer adds the variant to cart
  const cartItem =
    await generate_random_e_commerce_mall_customer_cart_items_create(
      customerConnection,
      {
        body: {
          product_variant_id: variant.id,
          quantity: 1,
        },
      },
    );
  typia.assert(cartItem);
  // 10. Customer places the order (checkout)
  const order = await generate_random_e_commerce_mall_customer_orders_create(
    customerConnection,
    {
      body: {
        addressId: address.id,
      },
    },
  );
  typia.assert(order);
  // 11. Extract the paid order item
  const paidOrderItem = order.orderItems[0];
  typia.assert(paidOrderItem);
  TestValidator.equals(
    "order item status is paid",
    paidOrderItem.status,
    "paid",
  );
  // 12. Super administrator force-cancels the paid order item
  const cancelledItem =
    await api.functional.eCommerceMall.superAdministrator.order_items.force_cancel.forceCancel(
      superAdminConnection,
      {
        itemId: paidOrderItem.id,
      },
    );
  typia.assert(cancelledItem);
  // 13. Validate the force-cancel result
  TestValidator.equals(
    "item status is cancelled",
    cancelledItem.status,
    "cancelled",
  );
  const hasForceCancelLog = cancelledItem.statusLogs.some(
    (log) =>
      log.reason === "administrator_force_cancel" &&
      log.to_status === "cancelled",
  );
  TestValidator.predicate(
    "status log contains force-cancel entry",
    hasForceCancelLog,
  );
}
