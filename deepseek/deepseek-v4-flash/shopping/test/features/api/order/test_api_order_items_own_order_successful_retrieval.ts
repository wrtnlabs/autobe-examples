export async function test_api_order_items_own_order_successful_retrieval(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register customer
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  // 2. Register seller
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {});
  // 3. Seller creates product
  const product = await generate_random_e_commerce_mall_seller_products_create(
    sellerConnection,
    {},
  );
  typia.assert(product);
  // 4. Seller creates variant
  const variant =
    await generate_random_e_commerce_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
      },
    );
  typia.assert(variant);
  // 5. Seller adds inventory (restock with 100 units)
  const inventory =
    await generate_random_e_commerce_mall_seller_products_variants_inventory_create(
      sellerConnection,
      {
        params: {
          productId: product.id,
          variantId: variant.id,
        },
        body: {
          quantity_change: 100,
          reason: "initial restock",
        },
      },
    );
  typia.assert(inventory);
  // 6. Customer creates a shipping address
  const address =
    await generate_random_e_commerce_mall_customer_addresses_create(
      customerConnection,
      {},
    );
  typia.assert(address);
  // 7. Customer adds variant to cart with quantity 3
  const cartItem =
    await generate_random_e_commerce_mall_customer_cart_items_create(
      customerConnection,
      {
        body: {
          product_variant_id: variant.id,
          quantity: 3,
        },
      },
    );
  typia.assert(cartItem);
  // 8. Customer places the order using the shipping address
  const order = await generate_random_e_commerce_mall_customer_orders_create(
    customerConnection,
    {
      body: {
        addressId: address.id,
      },
    },
  );
  typia.assert(order);
  // 9. Customer retrieves order items from the created order (no filters)
  const page = await api.functional.eCommerceMall.customer.orders.items.index(
    customerConnection,
    {
      orderCode: order.code,
      body: {},
    },
  );
  typia.assert(page);
  // 10. Validate pagination metadata
  TestValidator.equals("pagination current", page.pagination.current, 1);
  TestValidator.equals("pagination records", page.pagination.records, 1);
  TestValidator.equals("pagination pages", page.pagination.pages, 1);
  TestValidator.equals("data length", page.data.length, 1);
  // 11. Validate the single order item
  const item = page.data[0]!;
  TestValidator.equals("quantity matches ordered quantity", item.quantity, 3);
  TestValidator.equals("status is paid", item.status, "paid");
  TestValidator.predicate(
    "subtotal equals quantity * unit_price",
    item.subtotal === item.quantity * item.unit_price,
  );
  TestValidator.predicate(
    "has valid order item id",
    typeof item.id === "string",
  );
  TestValidator.predicate(
    "has product_name",
    typeof item.product_name === "string",
  );
  TestValidator.predicate(
    "has variant_sku",
    typeof item.variant_sku === "string",
  );
  TestValidator.predicate(
    "has variant_options",
    typeof item.variant_options === "string",
  );
  TestValidator.predicate("has shop_name", typeof item.shop_name === "string");
  TestValidator.predicate(
    "has order reference",
    typeof item.order.id === "string",
  );
  TestValidator.predicate(
    "has productVariant reference",
    typeof item.productVariant.id === "string",
  );
  TestValidator.predicate(
    "has created_at",
    typeof item.created_at === "string",
  );
}
