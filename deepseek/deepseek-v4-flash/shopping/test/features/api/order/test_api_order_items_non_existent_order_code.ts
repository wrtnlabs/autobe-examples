export async function test_api_order_items_non_existent_order_code(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register a customer for authentication
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: null,
    } satisfies IECommerceMallCustomer.IJoin,
  });
  // 2. Attempt to fetch order items with a non-existent order code
  //    Expect HTTP 404 as per specification: "If no order with the given code exists, return 404 Not Found."
  await TestValidator.httpError(
    "non-existent order code returns 404",
    404,
    async () =>
      await api.functional.eCommerceMall.customer.orders.items.index(
        customerConnection,
        {
          orderCode: "NONEXISTENT-ORDER-99999",
          body: {},
        } satisfies api.functional.eCommerceMall.customer.orders.items.index.Props,
      ),
  );
}
