export async function test_api_order_items_status_filter_empty_result(
  connection: api.IConnection,
): Promise<void> {
  // 1. Customer setup
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  // 2. Seller setup
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {});
  // 3. Seller creates a product
  const product = await generate_random_e_commerce_mall_seller_products_create(
    sellerConnection,
    {},
  );
  typia.assert(product);
  // 4. Seller creates a variant under the product
  const variant =
    await generate_random_e_commerce_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: {
          productId: product.id,
        },
      },
    );
  typia.assert(variant);
  // 5. Seller adds inventory to the variant (restock)
  await generate_random_e_commerce_mall_seller_products_variants_inventory_create(
    sellerConnection,
    {
      params: {
        productId: product.id,
        variantId: variant.id,
      },
    },
  );
  // 6. Customer creates a shipping address
  const address =
    await generate_random_e_commerce_mall_customer_addresses_create(
      customerConnection,
      {},
    );
  typia.assert(address);
  // 7. Customer adds the variant to cart
  await generate_random_e_commerce_mall_customer_cart_items_create(
    customerConnection,
    {
      body: {
        product_variant_id: variant.id,
      },
    },
  );
  // 8. Customer places the order
  const order = await generate_random_e_commerce_mall_customer_orders_create(
    customerConnection,
    {
      body: {
        addressId: address.id,
      },
    },
  );
  typia.assert(order);
  // 9. Query order items with status 'shipped' — expect empty result
  const shippedPage =
    await api.functional.eCommerceMall.customer.orders.items.index(
      customerConnection,
      {
        orderCode: order.code,
        body: {
          status: ["shipped"],
        },
      },
    );
  typia.assert(shippedPage);
  TestValidator.equals(
    "shipped filter records",
    shippedPage.pagination.records,
    0,
  );
  TestValidator.equals("shipped filter data", shippedPage.data.length, 0);
  TestValidator.equals("shipped filter pages", shippedPage.pagination.pages, 0);
  // 10. Query order items with status 'paid' — expect 1 result
  const paidPage =
    await api.functional.eCommerceMall.customer.orders.items.index(
      customerConnection,
      {
        orderCode: order.code,
        body: {
          status: ["paid"],
        },
      },
    );
  typia.assert(paidPage);
  TestValidator.equals("paid filter records", paidPage.pagination.records, 1);
  TestValidator.equals("paid filter data", paidPage.data.length, 1);
  TestValidator.equals("paid filter pages", paidPage.pagination.pages, 1);
}
