export async function test_api_seller_product_creation_by_rejected_seller(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register a seller account via authorize_seller_join
  //    The seller starts with approval_status='pending' and cannot create products
  const sellerConnection: api.IConnection = { host: connection.host };
  const seller = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      shop_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IECommerceMallSeller.IJoin,
  });
  typia.assert(seller);
  // 2. Attempt to create a product as the pending seller
  //    Since the seller has approval_status='pending' (not 'approved'),
  //    the API should reject the request with an HTTP error
  await TestValidator.httpError(
    "rejected seller cannot create product",
    [400, 403, 422],
    async () => {
      await api.functional.eCommerceMall.seller.products.create(
        sellerConnection,
        {
          body: {
            name: RandomGenerator.paragraph({ sentences: 2 }),
            description: RandomGenerator.paragraph({ sentences: 4 }),
            base_price: 49.99,
          } satisfies IECommerceMallProduct.ICreate,
        },
      );
    },
  );
}
