export async function test_api_seller_ban_already_banned_conflict(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register an administrator account
  const adminConnection: api.IConnection = { host: connection.host };
  const admin = await authorize_administrator_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IECommerceMallAdministrator.IJoin,
  });
  typia.assert(admin);
  // 2. Promote the administrator to super administrator
  const superAdminConnection: api.IConnection = { host: connection.host };
  const superAdmin = await authorize_super_administrator_join(
    superAdminConnection,
    {
      body: {
        administrator_id: admin.id,
        email: typia.random<string & tags.Format<"email">>(),
        password: RandomGenerator.alphaNumeric(16),
        href: typia.random<string & tags.Format<"uri">>(),
        referrer: typia.random<string & tags.Format<"uri">>(),
      },
    },
  );
  typia.assert(superAdmin);
  // 3. Register a seller account
  const sellerConnection: api.IConnection = { host: connection.host };
  const seller = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      shop_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  typia.assert(seller);
  // 4. First ban — should succeed
  const firstBan =
    await api.functional.eCommerceMall.superAdministrator.sellers.ban.create(
      superAdminConnection,
      {
        sellerId: seller.id,
        body: {
          reason: "First ban — multiple policy violations",
        } satisfies IECommerceMallSeller.IBan,
      },
    );
  typia.assert(firstBan);
  // 5. Second ban attempt — should fail with 409 Conflict
  await TestValidator.httpError("ban already banned seller", 409, async () => {
    await api.functional.eCommerceMall.superAdministrator.sellers.ban.create(
      superAdminConnection,
      {
        sellerId: seller.id,
        body: {
          reason: "Second ban attempt — repeat violation",
        } satisfies IECommerceMallSeller.IBan,
      },
    );
  });
}
