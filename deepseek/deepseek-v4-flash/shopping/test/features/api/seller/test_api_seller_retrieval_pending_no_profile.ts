export async function test_api_seller_retrieval_pending_no_profile(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create administrator account for authenticated access
  const adminConnection: api.IConnection = { host: connection.host };
  const admin = await authorize_administrator_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IECommerceMallAdministrator.IJoin,
  });
  typia.assert(admin);
  // 2. Create seller account — seller is created with 'pending' approval status
  const sellerEmail = typia.random<string & tags.Format<"email">>();
  const sellerPassword = RandomGenerator.alphaNumeric(16);
  const sellerConnection: api.IConnection = { host: connection.host };
  const seller = await authorize_seller_join(sellerConnection, {
    body: {
      email: sellerEmail,
      password: sellerPassword,
      shop_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IECommerceMallSeller.IJoin,
  });
  typia.assert(seller);
  // 3. Authenticated admin retrieves the pending seller by ID
  const retrieved = await api.functional.eCommerceMall.administrator.sellers.at(
    adminConnection,
    { sellerId: seller.id },
  );
  typia.assert(retrieved);
  // 4. Validate response fields
  TestValidator.equals("seller ID matches", retrieved.id, seller.id);
  TestValidator.equals("seller email matches", retrieved.email, sellerEmail);
  TestValidator.equals(
    "approval status is pending",
    retrieved.approval_status,
    "pending",
  );
  TestValidator.predicate("deleted_at is null", retrieved.deleted_at === null);
  TestValidator.predicate(
    "created_at is present",
    typeof retrieved.created_at === "string",
  );
}
