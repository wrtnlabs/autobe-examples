export async function test_api_seller_cancellation_requests_empty_list(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register a new seller
  const sellerConnection: api.IConnection = { host: connection.host };
  const authorized = await authorize_seller_join(sellerConnection, {});
  typia.assert(authorized);
  // 2. Call cancellation requests with default pagination
  const page =
    await api.functional.eCommerceMall.seller.cancellation_requests.index(
      sellerConnection,
      {
        body: {
          page: 1,
          limit: 10,
        } satisfies IECommerceMallCancellationRequest.IRequest,
      },
    );
  typia.assert(page);
  // 3. Validate empty paginated result
  TestValidator.equals("pagination current", page.pagination.current, 1);
  TestValidator.equals("pagination records", page.pagination.records, 0);
  TestValidator.equals("pagination pages", page.pagination.pages, 0);
  TestValidator.equals("data array empty", page.data.length, 0);
}
