export async function test_api_seller_order_items_snapshot_integrity(
  connection: api.IConnection,
): Promise<void> {
  // Register seller
  const sellerConnection: api.IConnection = { host: connection.host };
  const seller = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      shop_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  typia.assert(seller);
  // Query order items as seller
  const orderItemsPage =
    await api.functional.eCommerceMall.seller.order_items.index(
      sellerConnection,
      {
        body: {
          page: 1,
          limit: 10,
        } satisfies IECommerceMallOrderItem.IRequest,
      },
    );
  typia.assert(orderItemsPage);
  // Validate pagination values match request
  TestValidator.equals("current page", 1, orderItemsPage.pagination.current);
  TestValidator.equals("page limit", 10, orderItemsPage.pagination.limit);
}
