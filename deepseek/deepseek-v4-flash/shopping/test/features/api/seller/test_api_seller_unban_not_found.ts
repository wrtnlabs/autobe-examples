export async function test_api_seller_unban_not_found(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register administrator
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_administrator_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IECommerceMallAdministrator.IJoin,
  });
  // 2. Attempt to unban a non-existent seller
  const nonExistentSellerId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.httpError(
    "unban non-existent seller",
    404,
    async () =>
      await api.functional.eCommerceMall.administrator.sellers.unban(
        adminConnection,
        {
          sellerId: nonExistentSellerId,
        },
      ),
  );
}
