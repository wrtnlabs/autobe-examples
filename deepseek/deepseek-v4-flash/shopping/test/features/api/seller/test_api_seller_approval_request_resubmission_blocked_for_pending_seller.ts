export async function test_api_seller_approval_request_resubmission_blocked_for_pending_seller(
  connection: api.IConnection,
): Promise<void> {
  // 1. Join as a new seller
  // The seller account is created with approval_status='pending' and an
  // auto-generated initial approval request is submitted.
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      shop_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  // 2-3. Attempt to submit another approval request while status is 'pending'
  // This should fail with 422 because the seller already has a pending
  // request under administrator review.
  await TestValidator.httpError(
    "seller with pending status cannot submit new approval request",
    422,
    async () => {
      await api.functional.eCommerceMall.seller.approval_requests.create(
        sellerConnection,
      );
    },
  );
}
