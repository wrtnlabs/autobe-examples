export async function test_api_seller_refund_request_not_found(
  connection: api.IConnection,
): Promise<void> {
  // Setup: Register as a seller to obtain authentication
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {});
  // Execute: Attempt to retrieve a non-existent refund request
  const nonExistentId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.httpError(
    "refund request not found",
    404,
    async () => {
      await api.functional.eCommerceMall.seller.refund_requests.at(
        sellerConnection,
        {
          refundRequestId: nonExistentId,
        },
      );
    },
  );
}
