export async function test_api_seller_retrieval_not_found(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create admin connection
  const adminConnection: api.IConnection = { host: connection.host };
  // 2. Register and authenticate administrator
  await authorize_administrator_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IECommerceMallAdministrator.IJoin,
  });
  // 3. Attempt to retrieve a non-existent seller and expect 404
  await TestValidator.httpError(
    "non-existent seller returns 404",
    404,
    async () => {
      await api.functional.eCommerceMall.administrator.sellers.at(
        adminConnection,
        {
          sellerId: typia.random<string & tags.Format<"uuid">>(),
        },
      );
    },
  );
}
