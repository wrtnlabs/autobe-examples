export async function test_api_seller_snapshot_without_logo(
  connection: api.IConnection,
): Promise<void> {
  //----
  // Seller setup (without logo_image)
  //----
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {
    body: {
      shop_name: "Local Crafts",
    },
  });
  typia.assert(sellerAuth);
  //----
  // Administrator setup
  //----
  const adminConnection: api.IConnection = { host: connection.host };
  const adminAuth = await authorize_administrator_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IECommerceMallAdministrator.IJoin,
  });
  typia.assert(adminAuth);
  //----
  // Seller approval flow
  //----
  const approvalRequest =
    await api.functional.eCommerceMall.seller.approval_requests.create(
      sellerConnection,
    );
  typia.assert(approvalRequest);
  const approved =
    await api.functional.eCommerceMall.administrator.approval_requests.update(
      adminConnection,
      {
        requestId: approvalRequest.id,
        body: {
          status: "approved",
        } satisfies IECommerceMallSellerApprovalRequest.IUpdate,
      },
    );
  typia.assert(approved);
  //----
  // Seller creates product with variant and inventory
  //----
  const product = await generate_random_e_commerce_mall_seller_products_create(
    sellerConnection,
    {},
  );
  typia.assert(product);
  const variant =
    await generate_random_e_commerce_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
      },
    );
  typia.assert(variant);
  await generate_random_e_commerce_mall_seller_products_variants_inventory_create(
    sellerConnection,
    {
      params: {
        productId: product.id,
        variantId: variant.id,
      },
    },
  );
  //----
  // Customer setup
  //----
  const customerConnection: api.IConnection = { host: connection.host };
  const customerAuth = await authorize_customer_join(customerConnection, {});
  typia.assert(customerAuth);
  const address =
    await generate_random_e_commerce_mall_customer_addresses_create(
      customerConnection,
      {},
    );
  typia.assert(address);
  //----
  // Customer adds to cart and places order
  //----
  await generate_random_e_commerce_mall_customer_cart_items_create(
    customerConnection,
    {
      body: { product_variant_id: variant.id, quantity: 1 },
    },
  );
  const order = await generate_random_e_commerce_mall_customer_orders_create(
    customerConnection,
    {
      body: { addressId: address.id },
    },
  );
  typia.assert(order);
  const orderItemId = order.orderItems[0].id;
  //----
  // Retrieve seller snapshot and validate
  //----
  const snapshot =
    await api.functional.eCommerceMall.seller.order_items.seller_snapshot.at(
      sellerConnection,
      {
        itemId: orderItemId,
      },
    );
  typia.assert(snapshot);
  TestValidator.equals(
    "shop_name should be 'Local Crafts'",
    snapshot.shop_name,
    "Local Crafts",
  );
  TestValidator.equals(
    "shop_logo should be null (never set)",
    snapshot.shop_logo,
    null,
  );
  TestValidator.predicate(
    "created_at should be a valid ISO 8601 timestamp",
    () => !isNaN(Date.parse(snapshot.created_at)),
  );
  TestValidator.predicate("id should be a valid UUID", () =>
    /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i.test(
      snapshot.id,
    ),
  );
}
