export async function test_api_seller_snapshot_with_logo(
  connection: api.IConnection,
): Promise<void> {
  // Setup actor-specific connections
  const sellerConnection: api.IConnection = { host: connection.host };
  const adminConnection: api.IConnection = { host: connection.host };
  const customerConnection: api.IConnection = { host: connection.host };
  // 1. Seller joins with a specific logo image
  const shopLogo = typia.random<string & tags.Format<"uri">>();
  await authorize_seller_join(sellerConnection, {
    body: {
      shop_name: "TechStore Pro",
      logo_image: shopLogo,
    },
  });
  // 2. Administrator joins
  await authorize_administrator_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  // 3. Seller submits approval request
  const approvalRequest =
    await api.functional.eCommerceMall.seller.approval_requests.create(
      sellerConnection,
    );
  typia.assert(approvalRequest);
  // 4. Administrator approves the seller
  const updatedApproval =
    await api.functional.eCommerceMall.administrator.approval_requests.update(
      adminConnection,
      {
        requestId: approvalRequest.id,
        body: { status: "approved" },
      },
    );
  typia.assert(updatedApproval);
  // 5. Seller creates a product
  const product = await generate_random_e_commerce_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        name: "Wireless Headphones",
        category_id: null,
      },
    },
  );
  typia.assert(product);
  // 6. Seller creates a variant
  const variant =
    await generate_random_e_commerce_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
        body: {
          sku_code: "WH-001",
          options: [
            {
              key: "color",
              value: "Black",
            } satisfies IECommerceMallProductVariant.IOption,
            {
              key: "size",
              value: "Standard",
            } satisfies IECommerceMallProductVariant.IOption,
          ],
        },
      },
    );
  typia.assert(variant);
  // 7. Seller adds inventory
  const inventoryRecord =
    await generate_random_e_commerce_mall_seller_products_variants_inventory_create(
      sellerConnection,
      {
        params: {
          productId: product.id,
          variantId: variant.id,
        },
        body: {
          quantity_change: 100,
          reason: "Initial restock",
        },
      },
    );
  typia.assert(inventoryRecord);
  // 8. Customer joins
  await authorize_customer_join(customerConnection, {});
  // 9. Customer creates a default shipping address
  const address =
    await generate_random_e_commerce_mall_customer_addresses_create(
      customerConnection,
      {
        body: { is_default: true },
      },
    );
  typia.assert(address);
  // 10. Customer adds variant to cart
  const cartItem =
    await generate_random_e_commerce_mall_customer_cart_items_create(
      customerConnection,
      {
        body: {
          product_variant_id: variant.id,
          quantity: 2,
        },
      },
    );
  typia.assert(cartItem);
  // 11. Customer places the order — triggers seller snapshot creation
  const order = await generate_random_e_commerce_mall_customer_orders_create(
    customerConnection,
    {
      body: { addressId: address.id },
    },
  );
  typia.assert(order);
  // 12. Extract an order item ID from the order
  const orderItemId = order.orderItems[0].id;
  // 13. Retrieve the seller snapshot as the seller
  const snapshot =
    await api.functional.eCommerceMall.seller.order_items.seller_snapshot.at(
      sellerConnection,
      {
        itemId: orderItemId,
      },
    );
  typia.assert(snapshot);
  // 14. Validate snapshot business values
  TestValidator.equals("shop name", snapshot.shop_name, "TechStore Pro");
  TestValidator.equals("shop logo", snapshot.shop_logo, shopLogo);
}
