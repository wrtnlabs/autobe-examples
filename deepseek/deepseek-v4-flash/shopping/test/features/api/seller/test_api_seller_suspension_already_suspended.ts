export async function test_api_seller_suspension_already_suspended(
  connection: api.IConnection,
): Promise<void> {
  // Step 1: Register and authenticate an administrator
  const adminConnection: api.IConnection = { host: connection.host };
  const admin = await authorize_administrator_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IECommerceMallAdministrator.IJoin,
  });
  typia.assert(admin);
  // Step 2: Register and authenticate a seller
  const sellerConnection: api.IConnection = { host: connection.host };
  const seller = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      shop_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IECommerceMallSeller.IJoin,
  });
  typia.assert(seller);
  // Step 3: First suspend (should succeed)
  const firstSuspend =
    await api.functional.eCommerceMall.administrator.sellers.suspend(
      adminConnection,
      {
        sellerId: seller.id,
        body: {
          reason: "First suspension",
        } satisfies IECommerceMallSeller.ISuspend,
      },
    );
  typia.assert(firstSuspend);
  // Step 4: Second suspend (should fail — already suspended)
  await TestValidator.httpError("already suspended seller", 409, async () => {
    await api.functional.eCommerceMall.administrator.sellers.suspend(
      adminConnection,
      {
        sellerId: seller.id,
        body: {
          reason: "Second attempt",
        } satisfies IECommerceMallSeller.ISuspend,
      },
    );
  });
}
