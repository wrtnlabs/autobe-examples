export async function test_api_seller_dashboard_with_products_and_fulfilled_orders(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register seller account
  const sellerConnection: api.IConnection = { host: connection.host };
  const seller = await authorize_seller_join(sellerConnection, {});
  typia.assert(seller);
  TestValidator.equals(
    "seller approval status",
    seller.approval_status,
    "pending",
  );
  // 2. Submit approval request
  const approvalRequest =
    await api.functional.eCommerceMall.seller.approval_requests.create(
      sellerConnection,
    );
  typia.assert(approvalRequest);
  TestValidator.equals(
    "approval request status",
    approvalRequest.status,
    "pending",
  );
  // 3. Register an administrator
  const adminConnection: api.IConnection = { host: connection.host };
  const admin = await authorize_administrator_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IECommerceMallAdministrator.IJoin,
  });
  typia.assert(admin);
  // 4. Access seller dashboard
  const dashboard =
    await api.functional.eCommerceMall.seller.dashboard.at(sellerConnection);
  typia.assert(dashboard);
  // 5. Validate all dashboard metrics
  TestValidator.equals("total products", dashboard.totalProducts, 0);
  TestValidator.equals("total order items", dashboard.totalOrderItems, 0);
  TestValidator.equals(
    "pending cancellation requests",
    dashboard.pendingCancellationRequests,
    0,
  );
  TestValidator.equals(
    "pending refund requests",
    dashboard.pendingRefundRequests,
    0,
  );
}
