export async function test_api_customer_addresses_admin_empty_list(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register and authenticate an administrator
  const adminConnection: api.IConnection = { host: connection.host };
  const adminAuth = await authorize_administrator_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IECommerceMallAdministrator.IJoin,
  });
  typia.assert(adminAuth);
  // 2. Register a customer (without creating any addresses)
  const customerConnection: api.IConnection = { host: connection.host };
  const customerAuth = await authorize_customer_join(customerConnection, {});
  typia.assert(customerAuth);
  // 3. As the administrator, query the customer's address list
  const result =
    await api.functional.eCommerceMall.administrator.customers.addresses.index(
      adminConnection,
      {
        customerId: customerAuth.id,
        body: {
          page: 1,
          limit: 20,
        } satisfies IECommerceMallCustomerAddress.IRequest,
      },
    );
  typia.assert(result);
  // 4. Verify empty paginated response
  TestValidator.equals("records count", result.pagination.records, 0);
  TestValidator.equals("pages count", result.pagination.pages, 0);
  TestValidator.equals("data array length", result.data.length, 0);
}
