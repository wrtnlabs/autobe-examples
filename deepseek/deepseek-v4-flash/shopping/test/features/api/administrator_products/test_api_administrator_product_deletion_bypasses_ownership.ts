/**
 * Test that an administrator can delete any seller's product, bypassing seller
 * ownership restrictions.
 *
 * Administrators have elevated privileges that allow them to delete products
 * without meeting the seller-specific prerequisites (no pending order items,
 * no cancellation/refund requests). This test verifies the administrator-level
 * bypass by creating a product as a seller, then deleting it as an
 * administrator.
 *
 * 1. Register and authenticate as a seller using `authorize_seller_join`.
 * 2. Create a product as the seller.
 * 3. Register and authenticate as an administrator using
 *    `authorize_administrator_join`.
 * 4. Call the administrator product delete endpoint with the seller's product
 *    UUID.
 * 5. The operation succeeds without error, demonstrating that the
 *    administrator bypasses the seller ownership check.
 */
export async function test_api_administrator_product_deletion_bypasses_ownership(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register and authenticate as a seller
  const sellerConnection: api.IConnection = { host: connection.host };
  const seller = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      shop_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  typia.assert(seller);
  // 2. Create a product as the seller
  const product = await api.functional.eCommerceMall.seller.products.create(
    sellerConnection,
    {
      body: {
        name: RandomGenerator.paragraph({ sentences: 2 }),
        description: RandomGenerator.content({ paragraphs: 2 }),
        category_id: null,
        base_price: typia.random<
          number & tags.Minimum<1000> & tags.Maximum<100000>
        >(),
      } satisfies IECommerceMallProduct.ICreate,
    },
  );
  typia.assert(product);
  // 3. Register and authenticate as an administrator
  const adminConnection: api.IConnection = { host: connection.host };
  const admin = await authorize_administrator_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  typia.assert(admin);
  // 4. Delete the seller's product as the administrator
  //    The administrator bypasses ownership checks, so this should succeed
  //    even though the admin did not create the product.
  await api.functional.eCommerceMall.administrator.products.erase(
    adminConnection,
    {
      productId: product.id,
    },
  );
}
