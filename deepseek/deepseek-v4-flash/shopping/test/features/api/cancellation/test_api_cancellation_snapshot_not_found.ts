export async function test_api_cancellation_snapshot_not_found(
  connection: api.IConnection,
): Promise<void> {
  // 1. Seller setup
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {});
  typia.assert(sellerAuth);
  // 2. Seller creates a product
  const product = await generate_random_e_commerce_mall_seller_products_create(
    sellerConnection,
    {},
  );
  typia.assert(product);
  // 3. Seller adds a variant
  const variant =
    await generate_random_e_commerce_mall_seller_products_variants_create(
      sellerConnection,
      { params: { productId: product.id } },
    );
  typia.assert(variant);
  // 4. Seller restocks the variant
  const inventoryRecord =
    await generate_random_e_commerce_mall_seller_products_variants_inventory_create(
      sellerConnection,
      {
        params: {
          productId: product.id,
          variantId: variant.id,
        },
      },
    );
  typia.assert(inventoryRecord);
  // 5. Customer setup
  const customerConnection: api.IConnection = { host: connection.host };
  const customerAuth = await authorize_customer_join(customerConnection, {});
  typia.assert(customerAuth);
  // 6. Customer creates a shipping address
  const address =
    await generate_random_e_commerce_mall_customer_addresses_create(
      customerConnection,
      {},
    );
  typia.assert(address);
  // 7. Customer adds the variant to cart
  const cartItem =
    await generate_random_e_commerce_mall_customer_cart_items_create(
      customerConnection,
      {
        body: {
          product_variant_id: variant.id,
          quantity: 1,
        } satisfies DeepPartial<IECommerceMallCartItem.ICreate>,
      },
    );
  typia.assert(cartItem);
  // 8. Customer places an order
  const order = await generate_random_e_commerce_mall_customer_orders_create(
    customerConnection,
    {
      body: {
        addressId: address.id,
      } satisfies DeepPartial<IECommerceMallOrder.ICreate>,
    },
  );
  typia.assert(order);
  // 9. Get the first order item
  const orderItem = order.orderItems[0];
  typia.assert(orderItem);
  // 10. Customer creates a cancellation request for the paid order item
  const cancellationRequest =
    await generate_random_e_commerce_mall_customer_cancellation_requests_create(
      customerConnection,
      {
        body: {
          order_item_id: orderItem.id,
          reason: "Changed my mind, no longer need this item",
        } satisfies DeepPartial<IECommerceMallCancellationRequest.ICreate>,
      },
    );
  typia.assert(cancellationRequest);
  // 11. Seller responds to the cancellation request (approve) — creates at least one valid snapshot
  const updatedCancellation =
    await api.functional.eCommerceMall.seller.cancellation_requests.update(
      sellerConnection,
      {
        cancellationRequestId: cancellationRequest.id,
        body: {
          status: "approved",
        } satisfies IECommerceMallCancellationRequest.IUpdate,
      },
    );
  typia.assert(updatedCancellation);
  // The cancellation request now has at least one snapshot
  const validSnapshotId = updatedCancellation.snapshots[0].id;
  typia.assert(validSnapshotId);
  // 12. Attempt to retrieve a snapshot with a non-existent UUID — expect 404
  const fakeSnapshotId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.httpError(
    "snapshot not found for non-existent snapshotId",
    404,
    async () => {
      await api.functional.eCommerceMall.seller.cancellation_requests.snapshots.at(
        sellerConnection,
        {
          cancellationRequestId: cancellationRequest.id,
          snapshotId: fakeSnapshotId,
        },
      );
    },
  );
  // 13. Verify that a valid snapshot IS retrievable — the endpoint doesn't globally fail
  const retrievedSnapshot =
    await api.functional.eCommerceMall.seller.cancellation_requests.snapshots.at(
      sellerConnection,
      {
        cancellationRequestId: cancellationRequest.id,
        snapshotId: validSnapshotId,
      },
    );
  typia.assert(retrievedSnapshot);
}
