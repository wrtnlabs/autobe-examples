export async function test_api_cancellation_request_duplicate_pending_rejected(
  connection: api.IConnection,
): Promise<void> {
  // 1. Seller setup: register seller, create product with variant
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {});
  typia.assert(sellerAuth);
  const product = await generate_random_e_commerce_mall_seller_products_create(
    sellerConnection,
    {},
  );
  typia.assert(product);
  const variant =
    await generate_random_e_commerce_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
      },
    );
  typia.assert(variant);
  // 2. Customer setup: register customer, create address, add to cart, place order
  const customerConnection: api.IConnection = { host: connection.host };
  const customerAuth = await authorize_customer_join(customerConnection, {});
  typia.assert(customerAuth);
  const address =
    await generate_random_e_commerce_mall_customer_addresses_create(
      customerConnection,
      {},
    );
  typia.assert(address);
  const cartItem =
    await generate_random_e_commerce_mall_customer_cart_items_create(
      customerConnection,
      {
        body: {
          product_variant_id: variant.id,
          quantity: 1,
        },
      },
    );
  typia.assert(cartItem);
  const order = await generate_random_e_commerce_mall_customer_orders_create(
    customerConnection,
    {
      body: {
        addressId: address.id,
      },
    },
  );
  typia.assert(order);
  const firstOrderItem = order.orderItems[0]!;
  typia.assert(firstOrderItem);
  // 3. First cancellation request — should succeed with status 'pending'
  const firstCancellation =
    await generate_random_e_commerce_mall_customer_cancellation_requests_create(
      customerConnection,
      {
        body: {
          order_item_id: firstOrderItem.id,
          reason: "I changed my mind and no longer need this item",
        },
      },
    );
  typia.assert(firstCancellation);
  TestValidator.equals(
    "first cancellation status",
    firstCancellation.status,
    "pending",
  );
  // 4. Second cancellation request for the same order item — should be rejected with 409
  await TestValidator.httpError(
    "duplicate pending cancellation request is rejected",
    409,
    async () => {
      await generate_random_e_commerce_mall_customer_cancellation_requests_create(
        customerConnection,
        {
          body: {
            order_item_id: firstOrderItem.id,
            reason: "Found a better price from another seller",
          },
        },
      );
    },
  );
  // 5. Verify first cancellation request remains unaffected
  TestValidator.equals(
    "first cancellation still pending",
    firstCancellation.status,
    "pending",
  );
}
