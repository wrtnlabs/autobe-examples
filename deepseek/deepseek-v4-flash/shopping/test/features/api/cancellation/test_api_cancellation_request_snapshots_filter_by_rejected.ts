export async function test_api_cancellation_request_snapshots_filter_by_rejected(
  connection: api.IConnection,
): Promise<void> {
  // ---- Step 1: Seller setup ----
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {});
  // Create product
  const product = await generate_random_e_commerce_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        name: RandomGenerator.name(),
        description: RandomGenerator.content({ paragraphs: 2 }),
        base_price: typia.random<
          number & tags.Minimum<1000> & tags.Maximum<100000>
        >(),
      },
    },
  );
  typia.assert(product);
  // Create variant (SKU)
  const variant =
    await generate_random_e_commerce_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
        body: {
          sku_code: RandomGenerator.alphaNumeric(10),
          options: [
            {
              key: "color",
              value: RandomGenerator.alphabets(5),
            },
          ],
          price: null,
        },
      },
    );
  typia.assert(variant);
  // ---- Step 2: Customer setup ----
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  // Create address
  const address =
    await generate_random_e_commerce_mall_customer_addresses_create(
      customerConnection,
      {},
    );
  typia.assert(address);
  // Add variant to cart
  await generate_random_e_commerce_mall_customer_cart_items_create(
    customerConnection,
    {
      body: {
        product_variant_id: variant.id,
        quantity: 1,
      },
    },
  );
  // Place order
  const order = await generate_random_e_commerce_mall_customer_orders_create(
    customerConnection,
    {
      body: {
        addressId: address.id,
      },
    },
  );
  typia.assert(order);
  const orderItem = order.orderItems[0];
  // ---- Step 3: Customer creates cancellation request ----
  const cancellationReason = RandomGenerator.paragraph({ sentences: 2 });
  const cancellationRequest =
    await generate_random_e_commerce_mall_customer_cancellation_requests_create(
      customerConnection,
      {
        body: {
          order_item_id: orderItem.id,
          reason: cancellationReason,
        },
      },
    );
  typia.assert(cancellationRequest);
  // ---- Step 4: Seller responds with rejection ----
  const updatedCancellation =
    await api.functional.eCommerceMall.seller.cancellation_requests.update(
      sellerConnection,
      {
        cancellationRequestId: cancellationRequest.id,
        body: {
          status: "rejected",
          rejection_reason: "Cannot cancel - item is already in preparation",
        } satisfies IECommerceMallCancellationRequest.IUpdate,
      },
    );
  typia.assert(updatedCancellation);
  TestValidator.equals(
    "seller responded with rejected",
    updatedCancellation.status,
    "rejected",
  );
  // ---- Step 5: Customer retrieves snapshots filtered by 'rejected' ----
  const snapshotPage =
    await api.functional.eCommerceMall.customer.cancellation_requests.snapshots.index(
      customerConnection,
      {
        cancellationRequestId: cancellationRequest.id,
        body: {
          status: "rejected",
        } satisfies IECommerceMallCancellationRequestSnapshot.IRequest,
      },
    );
  typia.assert(snapshotPage);
  // ---- Step 6: Validate ----
  TestValidator.equals(
    "exactly one rejected snapshot",
    snapshotPage.data.length,
    1,
  );
  const snapshot = snapshotPage.data[0];
  TestValidator.equals(
    "snapshot status is rejected",
    snapshot.status,
    "rejected",
  );
  TestValidator.equals(
    "snapshot preserves customer reason",
    snapshot.reason,
    cancellationReason,
  );
}
