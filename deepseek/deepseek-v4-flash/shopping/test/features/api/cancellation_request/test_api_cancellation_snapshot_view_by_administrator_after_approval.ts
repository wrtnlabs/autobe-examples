export async function test_api_cancellation_snapshot_view_by_administrator_after_approval(
  connection: api.IConnection,
): Promise<void> {
  // 1. Auth as administrator
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_administrator_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IECommerceMallAdministrator.IJoin,
  });
  // 2. Auth as seller
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      shop_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IECommerceMallSeller.IJoin,
  });
  // 3. Auth as customer
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IECommerceMallCustomer.IJoin,
  });
  // 4. Seller creates a product
  const product = await generate_random_e_commerce_mall_seller_products_create(
    sellerConnection,
    {},
  );
  typia.assert(product);
  // 5. Seller creates a variant with options
  const variant =
    await generate_random_e_commerce_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
        body: {
          sku_code: RandomGenerator.alphaNumeric(8),
          options: [
            {
              key: "color",
              value: "Red",
            } satisfies IECommerceMallProductVariant.IOption,
            {
              key: "size",
              value: "Large",
            } satisfies IECommerceMallProductVariant.IOption,
          ],
        } satisfies IECommerceMallProductVariant.ICreate,
      },
    );
  typia.assert(variant);
  // 6. Seller adds inventory to the variant
  const inventory =
    await generate_random_e_commerce_mall_seller_products_variants_inventory_create(
      sellerConnection,
      {
        params: {
          productId: product.id,
          variantId: variant.id,
        },
        body: {
          quantity_change: 100,
          reason: "initial restock",
        } satisfies IECommerceMallInventoryRecord.ICreate,
      },
    );
  typia.assert(inventory);
  // 7. Customer creates a shipping address
  const address =
    await generate_random_e_commerce_mall_customer_addresses_create(
      customerConnection,
      {
        body: {
          recipient_name: RandomGenerator.name(),
          phone_number: RandomGenerator.mobile(),
          street_address: "123 Main Street",
          city: "Seoul",
          state_province: "Seoul",
          postal_code: "12345",
          country: "South Korea",
          is_default: true,
        } satisfies IECommerceMallCustomerAddress.ICreate,
      },
    );
  typia.assert(address);
  // 8. Customer adds variant to cart
  const cartItem =
    await generate_random_e_commerce_mall_customer_cart_items_create(
      customerConnection,
      {
        body: {
          product_variant_id: variant.id,
          quantity: 1,
        } satisfies IECommerceMallCartItem.ICreate,
      },
    );
  typia.assert(cartItem);
  // 9. Customer places order
  const order = await generate_random_e_commerce_mall_customer_orders_create(
    customerConnection,
    {
      body: {
        addressId: address.id,
      } satisfies IECommerceMallOrder.ICreate,
    },
  );
  typia.assert(order);
  const orderItemId: string = order.orderItems[0].id;
  // 10. Customer creates a cancellation request
  const cancellationRequest =
    await generate_random_e_commerce_mall_customer_cancellation_requests_create(
      customerConnection,
      {
        body: {
          order_item_id: orderItemId,
          reason: "Changed my mind - no longer need this item",
        } satisfies IECommerceMallCancellationRequest.ICreate,
      },
    );
  typia.assert(cancellationRequest);
  // 11. Seller approves the cancellation request
  const updatedCancellationRequest =
    await api.functional.eCommerceMall.seller.cancellation_requests.update(
      sellerConnection,
      {
        cancellationRequestId: cancellationRequest.id,
        body: {
          status: "approved",
        } satisfies IECommerceMallCancellationRequest.IUpdate,
      },
    );
  typia.assert(updatedCancellationRequest);
  // 12. Administrator views cancellation request snapshots
  const page =
    await api.functional.eCommerceMall.administrator.cancellation_requests.snapshots.index(
      adminConnection,
      {
        cancellationRequestId: cancellationRequest.id,
        body: {},
      },
    );
  typia.assert(page);
  // 13. Validate pagination metadata
  TestValidator.equals("pagination current", page.pagination.current, 1);
  TestValidator.equals("pagination limit", page.pagination.limit, 100);
  TestValidator.predicate(
    "has at least one record",
    () => page.pagination.records >= 1,
  );
  TestValidator.predicate(
    "data has at least one snapshot",
    () => page.data.length >= 1,
  );
  // 14. Validate each snapshot's business data
  for (const snapshot of page.data) {
    TestValidator.equals(
      "snapshot reason",
      snapshot.reason,
      "Changed my mind - no longer need this item",
    );
    TestValidator.equals("snapshot status", snapshot.status, "approved");
    TestValidator.equals(
      "snapshot cancellation request id",
      snapshot.cancellationRequest.id,
      cancellationRequest.id,
    );
    TestValidator.predicate(
      "snapshot has created_at",
      () => snapshot.created_at !== null,
    );
  }
}
