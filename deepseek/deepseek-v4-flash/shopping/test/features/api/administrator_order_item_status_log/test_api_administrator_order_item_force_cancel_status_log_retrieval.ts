export async function test_api_administrator_order_item_force_cancel_status_log_retrieval(
  connection: api.IConnection,
): Promise<void> {
  // 1. Administrator setup
  const adminConnection: api.IConnection = { host: connection.host };
  const adminAuthorized = await authorize_administrator_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IECommerceMallAdministrator.IJoin,
  });
  typia.assert(adminAuthorized);
  // 2. Seller setup
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuthorized = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      shop_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IECommerceMallSeller.IJoin,
  });
  typia.assert(sellerAuthorized);
  // 3. Seller creates a product
  const product = await generate_random_e_commerce_mall_seller_products_create(
    sellerConnection,
    {},
  );
  typia.assert(product);
  // 4. Seller creates a variant
  const variant =
    await generate_random_e_commerce_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
      },
    );
  typia.assert(variant);
  // 5. Seller restocks the variant
  const inventory =
    await generate_random_e_commerce_mall_seller_products_variants_inventory_create(
      sellerConnection,
      {
        params: { productId: product.id, variantId: variant.id },
      },
    );
  typia.assert(inventory);
  // 6. Customer setup
  const customerConnection: api.IConnection = { host: connection.host };
  const customerAuthorized = await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IECommerceMallCustomer.IJoin,
  });
  typia.assert(customerAuthorized);
  // 7. Customer creates a shipping address
  const address =
    await generate_random_e_commerce_mall_customer_addresses_create(
      customerConnection,
      {},
    );
  typia.assert(address);
  // 8. Customer adds the variant to cart
  const cartItem =
    await generate_random_e_commerce_mall_customer_cart_items_create(
      customerConnection,
      {
        body: {
          product_variant_id: variant.id,
          quantity: typia.random<
            number & tags.Type<"int32"> & tags.Minimum<1> & tags.Maximum<3>
          >(),
        },
      },
    );
  typia.assert(cartItem);
  // 9. Customer places the order
  const order = await generate_random_e_commerce_mall_customer_orders_create(
    customerConnection,
    {
      body: {
        addressId: address.id,
      },
    },
  );
  typia.assert(order);
  TestValidator.equals(
    "order has at least one order item",
    order.orderItems.length > 0,
    true,
  );
  const orderItem = order.orderItems[0]!;
  typia.assert(orderItem);
  TestValidator.equals("order item status is paid", orderItem.status, "paid");
  // 10. Administrator force-cancels the order item
  const forceCancelledItem =
    await api.functional.eCommerceMall.administrator.order_items.force_cancel.forceCancel(
      adminConnection,
      {
        itemId: orderItem.id,
      },
    );
  typia.assert(forceCancelledItem);
  TestValidator.equals(
    "force-cancelled item status is cancelled",
    forceCancelledItem.status,
    "cancelled",
  );
  // Find the force-cancel status log
  const forceCancelLog = forceCancelledItem.statusLogs.find(
    (log) => log.reason === "administrator_force_cancel",
  );
  if (forceCancelLog === undefined) {
    throw new Error("Force-cancel status log not found");
  }
  // 11. Retrieve the status log via GET endpoint
  const retrievedLog =
    await api.functional.eCommerceMall.administrator.order_items.status_logs.at(
      adminConnection,
      {
        itemId: orderItem.id,
        logId: forceCancelLog.id,
      },
    );
  typia.assert(retrievedLog);
  // 12. Validate status log fields
  TestValidator.equals("from_status is paid", retrievedLog.from_status, "paid");
  TestValidator.equals(
    "to_status is cancelled",
    retrievedLog.to_status,
    "cancelled",
  );
  TestValidator.equals(
    "reason is administrator_force_cancel",
    retrievedLog.reason,
    "administrator_force_cancel",
  );
  TestValidator.equals(
    "orderItem.status is cancelled",
    retrievedLog.orderItem.status,
    "cancelled",
  );
  // 13. Test data isolation: wrong itemId with same logId should return 404
  const wrongItemId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.httpError(
    "data isolation returns 404 for wrong itemId",
    404,
    async () => {
      await api.functional.eCommerceMall.administrator.order_items.status_logs.at(
        adminConnection,
        {
          itemId: wrongItemId,
          logId: forceCancelLog.id,
        },
      );
    },
  );
}
