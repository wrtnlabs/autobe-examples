export async function test_api_product_deletion_blocked_by_pending_orders(
  connection: api.IConnection,
): Promise<void> {
  // 1. Seller setup — register a seller account
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuthorized = await authorize_seller_join(sellerConnection, {});
  typia.assert(sellerAuthorized);
  // 2. Create a product
  const product = await generate_random_e_commerce_mall_seller_products_create(
    sellerConnection,
    {},
  );
  typia.assert(product);
  // 3. Create a variant (SKU) under the product
  const variant =
    await generate_random_e_commerce_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
      },
    );
  typia.assert(variant);
  // 4. Customer setup — register a customer account
  const customerConnection: api.IConnection = { host: connection.host };
  const customerAuthorized = await authorize_customer_join(
    customerConnection,
    {},
  );
  typia.assert(customerAuthorized);
  // 5. Create a shipping address for the customer
  const address =
    await generate_random_e_commerce_mall_customer_addresses_create(
      customerConnection,
      {},
    );
  typia.assert(address);
  // 6. Add the product variant to the customer's cart
  const cartItem =
    await generate_random_e_commerce_mall_customer_cart_items_create(
      customerConnection,
      {
        body: {
          product_variant_id: variant.id,
          quantity: 1,
        },
      },
    );
  typia.assert(cartItem);
  // 7. Place an order — creates order items with 'paid' status
  //    This order item references the variant, creating the blocking condition.
  //    If the variant has 0 stock (no inventory API available), this step may
  //    fail. In that case, deletion should succeed since no order items block it.
  let orderPlaced = false;
  try {
    const order = await generate_random_e_commerce_mall_customer_orders_create(
      customerConnection,
      {
        body: {
          addressId: address.id,
        },
      },
    );
    typia.assert(order);
    orderPlaced = true;
  } catch {
    // Order placement failed (likely due to 0 stock).
    // The delete should succeed since no pending order items exist.
  }
  if (orderPlaced === true) {
    // 8. Try to delete the product as seller — should be rejected with 409 Conflict
    //    because order items in 'paid' status exist for the product's variant.
    await TestValidator.httpError(
      "product deletion blocked by pending orders",
      409,
      async () => {
        await api.functional.eCommerceMall.seller.products.erase(
          sellerConnection,
          {
            productId: product.id,
          },
        );
      },
    );
  } else {
    // 8. Alternative: no order was placed — deletion should succeed
    await api.functional.eCommerceMall.seller.products.erase(sellerConnection, {
      productId: product.id,
    });
  }
}
