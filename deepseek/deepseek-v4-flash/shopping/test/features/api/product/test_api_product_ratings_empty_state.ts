export async function test_api_product_ratings_empty_state(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create seller account
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {});
  // 2. Create product
  const product = await generate_random_e_commerce_mall_seller_products_create(
    sellerConnection,
    {},
  );
  typia.assert(product);
  // 3. Create a variant under the product
  const variant =
    await generate_random_e_commerce_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: {
          productId: product.id,
        },
      },
    );
  typia.assert(variant);
  // 4. Create customer account
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  // 5. Fetch ratings for the product (which has no reviews)
  const rating =
    await api.functional.eCommerceMall.customer.products.ratings.at(
      customerConnection,
      {
        productId: product.id,
      },
    );
  typia.assert(rating);
  // 6. Validate empty state: averageRating = 0, totalCount = 0
  TestValidator.equals(
    "average rating is 0 for product with no reviews",
    rating.averageRating,
    0,
  );
  TestValidator.equals(
    "total review count is 0 for product with no reviews",
    rating.totalCount,
    0,
  );
}
