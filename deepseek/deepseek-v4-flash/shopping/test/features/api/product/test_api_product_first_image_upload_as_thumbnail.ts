/**
 * Test that when a seller uploads the first image for their product, the system correctly assigns sort_order 0 and designates it as the thumbnail.
 *
 * Validates the complete image upload flow including seller registration, product creation, and initial image upload. Ensures that the first image uploaded receives sort_order 0 and becomes the product's thumbnail.
 *
 * Special attention is given to verifying that the product summary's thumbnail URL correctly references the uploaded image after the first image is associated.
 *
 * 1. Seller registers with email, password, and shop profile.
 * 2. Seller creates a product with name, description, and base price.
 * 3. Seller uploads the first product image, which automatically receives sort_order 0.
 * 4. Validates the image record has sort_order 0 and the product thumbnail matches the uploaded image URL.
 */
export async function test_api_product_first_image_upload_as_thumbnail(
  connection: api.IConnection,
): Promise<void> {
  // 1. Seller setup
  const sellerConnection: api.IConnection = { host: connection.host };
  const seller = await authorize_seller_join(sellerConnection, {});
  typia.assert(seller);
  // 2. Create a product
  const product = await generate_random_e_commerce_mall_seller_products_create(
    sellerConnection,
    {},
  );
  typia.assert(product);
  // 3. Upload the first image
  const image =
    await generate_random_e_commerce_mall_seller_products_images_create(
      sellerConnection,
      {
        params: {
          productId: product.id,
        },
      },
    );
  typia.assert(image);
  // 4. Validate first image is the thumbnail (sort_order = 0)
  TestValidator.equals("sort_order is 0 (thumbnail)", image.sort_order, 0);
  // 5. Validate product thumbnail matches the uploaded image URL
  TestValidator.predicate("product thumbnail matches image URL", () => {
    return image.product.thumbnail === image.url;
  });
}
