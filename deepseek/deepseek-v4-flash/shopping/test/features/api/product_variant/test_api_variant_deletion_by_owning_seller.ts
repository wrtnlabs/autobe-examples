/**
 * Test variant deletion by its owning seller when other variants remain.
 *
 * Validates the successful deletion of a product variant by the authenticated seller who owns the product. Ensures that a seller can remove a specific variant from their product while other variants remain unaffected.
 *
 * The deletion is a soft-delete operation: the variant record's `deleted_at` timestamp is set to hide it from active listings while preserving the record for historical order references and audit purposes.
 *
 * 1. Authenticate as a seller via authorization utility.
 * 2. Create a new product with two distinct variants (different SKU codes and option combinations).
 * 3. Delete the first variant using the seller connection.
 * 4. Verify the deletion completes without errors.
 */
export async function test_api_variant_deletion_by_owning_seller(
  connection: api.IConnection,
): Promise<void> {
  // 1. Seller authentication
  const sellerConnection: api.IConnection = { host: connection.host };
  const authorized = await authorize_seller_join(sellerConnection, {
    body: {
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  typia.assert(authorized);
  // 2. Create a product
  const product = await generate_random_e_commerce_mall_seller_products_create(
    sellerConnection,
    {},
  );
  typia.assert(product);
  // 3. Create two distinct variants
  const variant1 =
    await generate_random_e_commerce_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
      },
    );
  typia.assert(variant1);
  const variant2 =
    await generate_random_e_commerce_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
      },
    );
  typia.assert(variant2);
  // 4. Delete the first variant (owning seller)
  await api.functional.eCommerceMall.seller.products.variants.erase(
    sellerConnection,
    {
      productId: product.id,
      variantId: variant1.id,
    },
  );
  // 5. Verify deletion succeeded by absence of error
  // The erase endpoint returns void; successful completion confirms
  // the variant was soft-deleted without issues.
}
