export async function test_api_product_variant_sku_code_change(
  connection: api.IConnection,
): Promise<void> {
  // 1. Seller joins
  const sellerConnection: api.IConnection = { host: connection.host };
  const seller = await authorize_seller_join(sellerConnection, {});
  typia.assert(seller);
  // 2. Seller creates a product
  const product = await generate_random_e_commerce_mall_seller_products_create(
    sellerConnection,
    {},
  );
  typia.assert(product);
  // 3. Seller creates a variant with old SKU code
  const oldSkuCode = "OLD-SKU-001";
  const variant =
    await generate_random_e_commerce_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
        body: { sku_code: oldSkuCode },
      },
    );
  typia.assert(variant);
  TestValidator.equals("initial sku code", variant.sku_code, oldSkuCode);
  const oldUpdatedAt = variant.updated_at;
  // 4. Seller updates the variant's sku_code to a new value
  const newSkuCode = "NEW-SKU-001";
  const updatedVariant =
    await api.functional.eCommerceMall.seller.products.variants.update(
      sellerConnection,
      {
        productId: product.id,
        variantId: variant.id,
        body: {
          sku_code: newSkuCode,
        } satisfies IECommerceMallProductVariant.IUpdate,
      },
    );
  typia.assert(updatedVariant);
  // 5. Validations
  TestValidator.equals("sku code changed", updatedVariant.sku_code, newSkuCode);
  TestValidator.equals("variant id unchanged", updatedVariant.id, variant.id);
  TestValidator.predicate(
    "updated_at refreshed",
    updatedVariant.updated_at !== oldUpdatedAt,
  );
}
