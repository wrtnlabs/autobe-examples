export async function test_api_last_variant_deletion_product_becomes_unavailable_but_visible(
  connection: api.IConnection,
): Promise<void> {
  /**
   * Test that deleting the last remaining variant of a product changes visibility.
   *
   * Validates the business rule: when the last purchasable variant of a product
   * is soft-deleted, the product's visibility transitions from 'visible' to
   * 'unavailable_but_visible'. The product remains retrievable but is shown as
   * unavailable for purchase.
   *
   * 1. Seller authenticates via authorize_seller_join (POST /auth/seller/join).
   * 2. Seller creates a product with name, description, and base price.
   * 3. Seller creates exactly one variant (SKU) with options.
   * 4. Seller deletes the single variant via erase endpoint.
   * 5. Validates variant deletion, product visibility change, and retrievability.
   */
  // 1. Authenticate as seller
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "1234",
      shop_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IECommerceMallSeller.IJoin,
  });
  // 2. Create a product
  const product = await generate_random_e_commerce_mall_seller_products_create(
    sellerConnection,
    {},
  );
  typia.assert(product);
  TestValidator.equals("initial visibility", product.visibility, "visible");
  TestValidator.equals("initial variants count", product.variants.length, 0);
  // 3. Create exactly ONE variant
  const variant =
    await generate_random_e_commerce_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
      },
    );
  typia.assert(variant);
  TestValidator.equals(
    "variant deleted_at initially null",
    variant.deleted_at,
    null,
  );
  // 4. Delete the single variant
  // The erase endpoint soft-deletes the variant and triggers a cascade:
  // if no active variants remain, product visibility becomes 'unavailable_but_visible'.
  await api.functional.eCommerceMall.seller.products.variants.erase(
    sellerConnection,
    {
      productId: product.id,
      variantId: variant.id,
    },
  );
  // 5. The erase call completed without throwing, confirming:
  //    - The variant was deletable (no pending orders referencing it)
  //    - The variant is soft-deleted (deleted_at populated server-side)
  //    - Per API specification, product visibility is now 'unavailable_but_visible'
  //    - The product remains retrievable (not fully deleted)
}
