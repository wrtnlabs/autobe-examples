export async function test_api_customer_refund_request_snapshots_list_after_approval(
  connection: api.IConnection,
): Promise<void> {
  // Setup actor-specific connections
  const customerConnection: api.IConnection = { host: connection.host };
  const sellerConnection: api.IConnection = { host: connection.host };
  // 1. Customer joins and authenticates
  const customer = await authorize_customer_join(customerConnection, {});
  typia.assert(customer);
  // 2. Seller joins and authenticates
  const seller = await authorize_seller_join(sellerConnection, {});
  typia.assert(seller);
  // 3. Seller creates a product
  const product = await generate_random_e_commerce_mall_seller_products_create(
    sellerConnection,
    {},
  );
  typia.assert(product);
  // 4. Seller creates a variant (SKU) with options
  const variant =
    await generate_random_e_commerce_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
      },
    );
  typia.assert(variant);
  // 5. Seller restocks inventory (positive quantity_change for sufficient stock)
  const inventory =
    await generate_random_e_commerce_mall_seller_products_variants_inventory_create(
      sellerConnection,
      {
        params: {
          productId: product.id,
          variantId: variant.id,
        },
        body: {
          quantity_change: 100,
          reason: "initial restock",
        },
      },
    );
  typia.assert(inventory);
  // 6. Customer creates a shipping address (set as default)
  const address =
    await generate_random_e_commerce_mall_customer_addresses_create(
      customerConnection,
      {
        body: {
          is_default: true,
        },
      },
    );
  typia.assert(address);
  // 7. Customer adds the variant to cart with quantity 1
  const cartItem =
    await generate_random_e_commerce_mall_customer_cart_items_create(
      customerConnection,
      {
        body: {
          product_variant_id: variant.id,
          quantity: 1,
        },
      },
    );
  typia.assert(cartItem);
  // 8. Customer places an order using the created address
  const order = await generate_random_e_commerce_mall_customer_orders_create(
    customerConnection,
    {
      body: {
        addressId: address.id,
      },
    },
  );
  typia.assert(order);
  // Extract the first (and only) order item
  const orderItem = order.orderItems[0]!;
  typia.assert(orderItem);
  // 9. Seller creates a shipment containing the order item
  const shipment =
    await generate_random_e_commerce_mall_seller_shipments_create(
      sellerConnection,
      {
        body: {
          orderItemIds: [orderItem.id],
        },
      },
    );
  typia.assert(shipment);
  // 10. Customer confirms delivery
  const updatedShipment =
    await api.functional.eCommerceMall.customer.shipments.update(
      customerConnection,
      {
        shipmentId: shipment.id,
        body: {},
      },
    );
  typia.assert(updatedShipment);
  // 11. Customer creates a refund request for the delivered order item
  const refundRequest =
    await generate_random_e_commerce_mall_customer_refund_requests_create(
      customerConnection,
      {
        body: {
          orderItemId: orderItem.id,
          reason: "Product arrived damaged",
        },
      },
    );
  typia.assert(refundRequest);
  // 12. Seller approves the refund request
  // This triggers creation of an immutable snapshot recording the customer's reason, decision='approved', and response timestamp.
  const approvedRefundRequest =
    await api.functional.eCommerceMall.seller.refund_requests.update(
      sellerConnection,
      {
        refundRequestId: refundRequest.id,
        body: {
          status: "approved",
        },
      },
    );
  typia.assert(approvedRefundRequest);
  // 13. Customer lists snapshots for the refund request with default pagination
  const snapshotPage =
    await api.functional.eCommerceMall.customer.refund_requests.snapshots.index(
      customerConnection,
      {
        refundRequestId: refundRequest.id,
        body: {},
      },
    );
  typia.assert(snapshotPage);
  // Validate pagination metadata
  TestValidator.equals("current page", snapshotPage.pagination.current, 1);
  TestValidator.predicate(
    "has at least one record",
    snapshotPage.pagination.records >= 1,
  );
  // Validate snapshot content
  const snapshot = snapshotPage.data[0]!;
  TestValidator.equals(
    "snapshot reason matches",
    snapshot.reason,
    "Product arrived damaged",
  );
  TestValidator.equals(
    "snapshot status is approved",
    snapshot.status,
    "approved",
  );
  TestValidator.predicate(
    "response timestamp exists",
    snapshot.response_timestamp !== null,
  );
  TestValidator.predicate("created at exists", snapshot.created_at !== null);
}
