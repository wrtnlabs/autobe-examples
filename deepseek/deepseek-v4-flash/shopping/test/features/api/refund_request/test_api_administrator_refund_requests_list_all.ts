export async function test_api_administrator_refund_requests_list_all(
  connection: api.IConnection,
): Promise<void> {
  // 1. Administrator setup
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_administrator_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IECommerceMallAdministrator.IJoin,
  });
  // 2. List all refund requests as administrator (no filters, first page)
  const page: IPageIECommerceMallRefundRequest.ISummary =
    await api.functional.eCommerceMall.administrator.refund_requests.index(
      adminConnection,
      {
        body: {
          page: 1,
          limit: 20,
        } satisfies IECommerceMallRefundRequest.IRequest,
      },
    );
  typia.assert(page);
  // 3. Validate pagination metadata
  TestValidator.equals("pagination current", page.pagination.current, 1);
  TestValidator.equals("pagination limit", page.pagination.limit, 20);
  TestValidator.equals("pagination records", page.pagination.records, 0);
  TestValidator.equals("pagination pages", page.pagination.pages, 0);
  // 4. Validate data array is empty (no refund requests in the system)
  TestValidator.equals("data array length", page.data.length, 0);
}
