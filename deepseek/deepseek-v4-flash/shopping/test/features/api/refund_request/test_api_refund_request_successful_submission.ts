export async function test_api_refund_request_successful_submission(
  connection: api.IConnection,
): Promise<void> {
  // 1. Join as customer
  const customerConnection: api.IConnection = { host: connection.host };
  const customerJoin = await authorize_customer_join(customerConnection, {});
  typia.assert(customerJoin);
  // 2. Join as seller
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerJoin = await authorize_seller_join(sellerConnection, {});
  typia.assert(sellerJoin);
  // 3. As seller: create a product
  const product = await generate_random_e_commerce_mall_seller_products_create(
    sellerConnection,
    {},
  );
  typia.assert(product);
  // 4. As seller: create a variant
  const variant =
    await generate_random_e_commerce_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
      },
    );
  typia.assert(variant);
  // 5. As customer: create a shipping address
  const address =
    await generate_random_e_commerce_mall_customer_addresses_create(
      customerConnection,
      {},
    );
  typia.assert(address);
  // 6. As customer: add the product variant to cart with quantity 1
  const cartItem =
    await generate_random_e_commerce_mall_customer_cart_items_create(
      customerConnection,
      {
        body: {
          product_variant_id: variant.id,
          quantity: 1,
        },
      },
    );
  typia.assert(cartItem);
  // 7. As customer: place an order using the created address ID
  const order = await generate_random_e_commerce_mall_customer_orders_create(
    customerConnection,
    {
      body: {
        addressId: address.id,
      },
    },
  );
  typia.assert(order);
  // Get the first order item
  const orderItem = order.orderItems[0];
  typia.assert(orderItem);
  // 8. As seller: create a shipment including the order item
  const shipment =
    await generate_random_e_commerce_mall_seller_shipments_create(
      sellerConnection,
      {
        body: {
          orderItemIds: [orderItem.id],
        },
      },
    );
  typia.assert(shipment);
  // 9. As customer: confirm delivery of the shipment
  const deliveredShipment =
    await api.functional.eCommerceMall.customer.shipments.update(
      customerConnection,
      {
        shipmentId: shipment.id,
        body: {},
      },
    );
  typia.assert(deliveredShipment);
  // 10. As customer: submit a refund request with reason
  const refundRequest =
    await generate_random_e_commerce_mall_customer_refund_requests_create(
      customerConnection,
      {
        body: {
          orderItemId: orderItem.id,
          reason: "Product arrived damaged",
        },
      },
    );
  typia.assert(refundRequest);
  // 11. Validate refund request properties
  TestValidator.equals("status is pending", refundRequest.status, "pending");
  TestValidator.equals(
    "response_timestamp is null",
    refundRequest.response_timestamp,
    null,
  );
  TestValidator.equals(
    "order item matches",
    refundRequest.orderItem.id,
    orderItem.id,
  );
  TestValidator.equals(
    "reason matches",
    refundRequest.reason,
    "Product arrived damaged",
  );
  TestValidator.predicate(
    "customer reference matches",
    () => refundRequest.customer.id === customerJoin.id,
  );
  TestValidator.predicate(
    "seller reference derived correctly",
    () => refundRequest.seller.id === sellerJoin.id,
  );
}
