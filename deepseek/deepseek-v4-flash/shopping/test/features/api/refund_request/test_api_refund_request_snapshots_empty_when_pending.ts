/**
 * Test that the refund request snapshot list is empty when the seller has not yet responded.
 *
 * Validates that snapshots are only created when the seller responds to a refund request. While the refund request is in 'pending' status, no snapshots should exist — the snapshot list returns an empty array with pagination metadata indicating zero records.
 *
 * 1. Seller joins, creates a product and a variant.
 * 2. Customer joins, creates a shipping address, adds the variant to cart, and places an order.
 * 3. Customer creates a refund request for a delivered order item — status becomes 'pending'.
 * 4. Seller does NOT respond to the refund request.
 * 5. Seller lists refund request snapshots via PATCH endpoint.
 * 6. Validates data array is empty and pagination reflects zero records.
 */
export async function test_api_refund_request_snapshots_empty_when_pending(
  connection: api.IConnection,
): Promise<void> {
  // 1. Seller setup
  const sellerConnection: api.IConnection = { host: connection.host };
  const seller = await authorize_seller_join(sellerConnection, {});
  typia.assert(seller);
  // 2. Seller creates a product
  const product = await generate_random_e_commerce_mall_seller_products_create(
    sellerConnection,
    {},
  );
  typia.assert(product);
  // 3. Seller creates a variant under the product
  const variant =
    await generate_random_e_commerce_mall_seller_products_variants_create(
      sellerConnection,
      { params: { productId: product.id } },
    );
  typia.assert(variant);
  // 4. Customer setup
  const customerConnection: api.IConnection = { host: connection.host };
  const customer = await authorize_customer_join(customerConnection, {});
  typia.assert(customer);
  // 5. Customer creates a shipping address
  const address =
    await generate_random_e_commerce_mall_customer_addresses_create(
      customerConnection,
      {},
    );
  typia.assert(address);
  // 6. Customer adds the variant to cart
  const cartItem =
    await generate_random_e_commerce_mall_customer_cart_items_create(
      customerConnection,
      {
        body: {
          product_variant_id: variant.id,
          quantity: 1,
        },
      },
    );
  typia.assert(cartItem);
  // 7. Customer places an order
  const order = await generate_random_e_commerce_mall_customer_orders_create(
    customerConnection,
    {
      body: {
        addressId: address.id,
      },
    },
  );
  typia.assert(order);
  // 8. Customer creates a refund request for the delivered order item
  const orderItem = order.orderItems[0];
  const refundRequest =
    await generate_random_e_commerce_mall_customer_refund_requests_create(
      customerConnection,
      {
        body: {
          orderItemId: orderItem.id,
        },
      },
    );
  typia.assert(refundRequest);
  // 9. Seller lists refund request snapshots (seller has NOT responded yet)
  const page =
    await api.functional.eCommerceMall.seller.refund_requests.snapshots.index(
      sellerConnection,
      {
        refundRequestId: refundRequest.id,
        body: {},
      },
    );
  typia.assert(page);
  // 10. Validate that snapshots are empty
  TestValidator.equals("snapshot data is empty", page.data.length, 0);
  TestValidator.equals("total records", page.pagination.records, 0);
  TestValidator.equals("total pages", page.pagination.pages, 0);
  TestValidator.equals(
    "current page defaults to 1",
    page.pagination.current,
    1,
  );
}
