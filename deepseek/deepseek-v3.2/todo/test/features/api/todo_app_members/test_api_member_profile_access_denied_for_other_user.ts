export async function test_api_member_profile_access_denied_for_other_user(
  connection: api.IConnection,
): Promise<void> {
  // Create first member account for authentication
  const firstMemberConnection: api.IConnection = { host: connection.host };
  const firstMember = await authorize_member_join(firstMemberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    },
  });
  typia.assert(firstMember);
  // Create second member account to attempt accessing their profile
  const secondMemberConnection: api.IConnection = { host: connection.host };
  const secondMember = await authorize_member_join(secondMemberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    },
  });
  typia.assert(secondMember);
  // Attempt to retrieve second member's profile using first member's connection (should fail)
  await TestValidator.httpError(
    "access denied when attempting to view another member's profile",
    403,
    async () =>
      await api.functional.todoApp.members.at(firstMemberConnection, {
        memberId: secondMember.id,
      }),
  );
}
