export async function test_api_todo_trash_permanent_deletion(
  connection: api.IConnection,
): Promise<void> {
  // Create authenticated member session
  const memberConnection: api.IConnection = { host: connection.host };
  await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies ITodoAppMember.IJoin,
  });
  // Create a todo
  const todo = await generate_random_todo_app_member_todos_create(
    memberConnection,
    {
      body: {
        title: RandomGenerator.paragraph({ sentences: 2 }),
        description: RandomGenerator.content({ paragraphs: 1 }),
        start_date: new Date().toISOString(),
        due_date: new Date(Date.now() + 86400000).toISOString(),
      } satisfies ITodoAppTodo.ICreate,
    },
  );
  typia.assert(todo);
  // Attempt to permanently delete the todo from trash
  // This will likely fail since the todo is not in trash,
  // but we test the endpoint call itself
  await api.functional.todoApp.member.todos.trash.erase(memberConnection, {
    todoId: todo.id,
  });
  // Note: We cannot verify the todo is actually deleted because:
  // 1. No GET endpoints provided to check if todo exists
  // 2. No trash listing endpoints provided
  // 3. The erase operation might fail if todo not in trash (business logic error)
  // The test demonstrates the API call pattern for permanent deletion
}
