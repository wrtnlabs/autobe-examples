import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IPageITodoAppMemberSession } from "../../../../api/structures/IPageITodoAppMemberSession";
import { ITodoAppMemberSession } from "../../../../api/structures/ITodoAppMemberSession";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getTodoAppMemberSessionsSessionId } from "../../../../providers/getTodoAppMemberSessionsSessionId";
import { patchTodoAppMemberSessions } from "../../../../providers/patchTodoAppMemberSessions";

@Controller("/todoApp/member/sessions")
export class TodoappMemberSessionsController {
  /**
   * Search and filter member authentication sessions with pagination and filtering options.
   *
   * This operation allows searching through member session records using various filter criteria including IP address, creation date range, expiration status, and session activity. The response provides paginated session summaries for administrative review or user self-inspection.
   *
   * Sessions contain authentication tokens (JWT access and refresh tokens) along with connection context information for security auditing. The operation respects data isolation boundaries where users can only access their own sessions, and administrators can access all sessions depending on implementation.
   *
   * Filter options include IP address matching, date range filtering for creation and expiration, and session status based on expiration timestamps. The operation supports comprehensive pagination with sorting by creation date, expiration date, or last update timestamp.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering sessions
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query the todo_app_member_sessions table with filtering based on request body criteria. Implement pagination using cursor-based or offset-based approach. Apply filters for IP address (partial match), creation date range (created_at from/to), expiration date range (expired_at from/to), and active/expired status. Join with todo_app_members table to get member information if needed for admin view. Ensure data isolation: if user is member, filter by todo_app_member_id equals current user ID; if admin, allow all sessions. Return session summaries with essential fields for listing. Handle large result sets with efficient database queries.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: ITodoAppMemberSession.IRequest,
  ): Promise<IPageITodoAppMemberSession.ISummary> {
    try {
      return await patchTodoAppMemberSessions({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific member authentication session.
   *
   * This operation returns complete session information including JWT tokens, connection context (IP, URL, referrer), and timing data. The session record provides auditing visibility into authentication events and session lifecycle management.
   *
   * Access to session information is strictly limited to the authenticated member who owns the session. Members can only retrieve their own sessions through authentication verification. This ensures session privacy and prevents unauthorized access to authentication tokens and connection metadata.
   *
   * The response includes all session attributes from the todo_app_member_sessions table, enabling comprehensive session management and audit capabilities. Session data is useful for security monitoring, device management, and understanding authentication patterns.
   *
   * @param connection
   * @param sessionId Unique identifier of the session record (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query the todo_app_member_sessions table by primary key ID.
   * First, verify that the authenticated user (from the request's authorization header) matches the todo_app_member_id in the session record.
   * If the session doesn't exist or belongs to a different user, return appropriate error responses (404 or 403).
   * Return the full session object including all fields: id, todo_app_member_id, access_token, refresh_token, ip, href, referrer, created_at, expired_at, updated_at.
   * The operation should be read-only with no side effects on the session data.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("sessionId")
    sessionId: string,
  ): Promise<ITodoAppMemberSession> {
    try {
      return await getTodoAppMemberSessionsSessionId({
        member,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
