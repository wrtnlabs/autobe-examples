import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { ITodoAppGuest } from "../../../../api/structures/ITodoAppGuest";
import { postTodoAppAuthGuestJoin } from "../../../../providers/postTodoAppAuthGuestJoin";
import { postTodoAppAuthGuestRefresh } from "../../../../providers/postTodoAppAuthGuestRefresh";

@Controller("/todoApp/auth/guest")
export class TodoappAuthGuestController {
  /**
   * This endpoint creates a temporary guest account for visitors who have not yet authenticated. It accepts a device fingerprint identifier and establishes a guest session with access and refresh tokens.
   *
   * Guests are unauthenticated users who need temporary access to the application's sign-up and login screens. The device fingerprint ensures unique guest identification across sessions while maintaining privacy. Upon successful creation, the guest receives JWT tokens that allow limited access to authentication interfaces.
   *
   * Guest accounts are automatically created with a unique UUID identifier and timestamps for creation and updates. The system tracks guest sessions separately in the todo_app_guest_sessions table, linking them to the guest account. These temporary accounts cannot access any todo data, user profiles, or application functionality beyond the entry points.
   *
   * Security considerations include validating device fingerprint format, preventing duplicate guest accounts from the same device, and implementing appropriate token expiration policies. Guest sessions should have shorter lifespans than member sessions to maintain security boundaries.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Device fingerprint information for guest account creation.
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification The join operation creates a temporary guest account for unauthenticated visitors. It accepts a device fingerprint string and creates a guest record in the todo_app_guests table. The operation generates a unique guest ID, stores the device fingerprint, and creates timestamps. It then generates JWT access and refresh tokens for the guest session. The access token should have a short expiration (e.g., 1 hour) for guest operations, while the refresh token should have a longer expiration (e.g., 7 days) for session maintenance. No email or password validation is required for guest accounts. The guest account can be automatically cleaned up after inactivity periods. The operation should check for existing guest accounts with the same device fingerprint to prevent duplicates.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoAppGuest.IJoin,
  ): Promise<ITodoAppGuest.IAuthorized> {
    try {
      return await postTodoAppAuthGuestJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This endpoint refreshes guest session tokens to extend temporary access to authentication interfaces. It accepts a valid refresh token and returns new access and refresh tokens for continued guest session management.
   *
   * Guest refresh tokens have longer expiration periods than access tokens, allowing visitors to maintain temporary identification across browser sessions. The refresh operation validates the provided refresh token against the guest account and session records, ensuring the guest account is still active and not deleted.
   *
   * Upon successful validation, the system generates new JWT tokens with updated expiration timestamps. The previous refresh token is invalidated to prevent token reuse. Guest accounts that have been marked for deletion (deleted_at not null) or have exceeded inactivity periods cannot refresh their sessions.
   *
   * Security considerations include proper JWT validation, token rotation to prevent replay attacks, and session state verification. The refresh mechanism supports the guest experience by allowing temporary access persistence while maintaining security boundaries between guest and member functionality.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token for guest session renewal.
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification The refresh operation renews guest session tokens using a valid refresh token. It validates the provided refresh token, checks if the associated guest account still exists and is not deleted, and generates new access and refresh tokens. The old refresh token should be invalidated after use. The operation should verify that the guest account has not been deleted (deleted_at is null) and that the session is still within allowed time boundaries. New tokens should have the same expiration policies as the join operation. This allows guests to maintain temporary access across browser sessions without requiring re-identification.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: ITodoAppGuest.IRefresh,
  ): Promise<ITodoAppGuest.IAuthorized> {
    try {
      return await postTodoAppAuthGuestRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
