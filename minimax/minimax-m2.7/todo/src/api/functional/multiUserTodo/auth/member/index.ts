/**
 * Creates a new member account for user registration.
 *
 * This endpoint allows unauthenticated users (guests) to create a new registered member account by providing their email address, password, and display name. The email must be unique across the system as enforced by the unique constraint on the email field in the multi_user_todo_members database table. Upon successful registration, the system creates a new member record with a bcrypt-hashed password, generates JWT access and refresh tokens, establishes a new session in the multi_user_todo_member_sessions table, and returns the authentication tokens along with basic member information.
 *
 * The registration process validates that the email address is not already associated with an existing account before creating the new member. The password is securely hashed using bcrypt before storage. A new session record is created linking the member to their initial authentication session with client metadata (IP address, request URL, and HTTP referrer).
 *
 * This operation transitions a guest to an authenticated member with full access to the todo management system. The returned access token should be used in the Authorization header for subsequent authenticated API requests.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Registration request containing email, password, and display name for new member account creation.
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor member
 * @x-autobe-specification 1. Validate the email field (must be valid email
 *   format, must be unique per the members table's @@unique([email])
 *   constraint). 2. Validate the password field (must meet system password
 *   requirements). 3. Hash the password using bcrypt with appropriate cost
 *   factor. 4. Generate a new UUID for the member's id field. 5. Insert a new
 *   record into the multi_user_todo_members table with email, password_hash,
 *   and display_name. 6. Generate JWT access_token and refresh_token for the
 *   new member. 7. Create a new session record in
 *   multi_user_todo_member_sessions with the tokens, client metadata (IP, href,
 *   referrer), and expiration timestamp. 8. Return the tokens and member
 *   information in the IAuthorized response format.
 * @path /multiUserTodo/auth/member/join
 * @accessor api.functional.multiUserTodo.auth.member.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
