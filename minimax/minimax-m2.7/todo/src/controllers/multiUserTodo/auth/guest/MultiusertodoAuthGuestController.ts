import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IMultiUserTodoGuest } from "../../../../api/structures/IMultiUserTodoGuest";
import { postMultiUserTodoAuthGuestJoin } from "../../../../providers/postMultiUserTodoAuthGuestJoin";
import { postMultiUserTodoAuthGuestRefresh } from "../../../../providers/postMultiUserTodoAuthGuestRefresh";

@Controller("/multiUserTodo/auth/guest")
export class MultiusertodoAuthGuestController {
  /**
   * Guest user registration endpoint that creates a new guest account or restores an existing one based on device identifier.
   *
   * This operation handles unauthenticated visitor registration using device_id as the primary identification mechanism. The device_id field from the multi_user_todo_guests table uniquely identifies the guest device, allowing the system to maintain session continuity for anonymous users before they register or log in.
   *
   * Security considerations include validating the device_id format, preventing duplicate registrations for the same device, and generating secure JWT tokens with appropriate expiration times. The session tracking captures client metadata (IP address, request URL, referrer) for analytics and security audit purposes.
   *
   * The multi_user_todo_guest_sessions table stores session information linked to the guest via multi_user_todo_guest_id foreign key. Sessions track connection metadata including IP address (ip field), requested URL path (href field), HTTP referrer header (referrer field), creation timestamp (created_at), and expiration timestamp (expired_at).
   *
   * Related operations include the refresh endpoint for renewing expired tokens using the refresh token flow.
   *
   * Request validation: device_id must be a non-empty string, properly formatted UUID or device identifier. Response includes access_token for API authentication and refresh_token for token renewal.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Request body containing guest registration information including device identifier for session tracking.
     * @x-autobe-authorization-type join
     * @x-autobe-authorization-actor guest
     * @x-autobe-specification 1. Extract device_id from request body 2.
     *   Validate device_id is not empty and is a valid UUID format 3. Check if
     *   guest with this device_id already exists (by device_id unique
     *   constraint) 4. If exists and not deleted, return existing guest record
     *   5. If exists and soft-deleted, restore the guest (clear deleted_at,
     *   update updated_at) 6. If not exists, create new guest record with
     *   generated UUID and current timestamps 7. Generate JWT access token with
     *   guest ID, expiry (typically 15-30 minutes) 8. Generate JWT refresh
     *   token with guest ID, expiry (typically 7-30 days) 9. Store refresh
     *   token in multi_user_todo_guest_sessions table with client metadata (ip,
     *   href, referrer, expired_at) 10. Return access token and refresh token
     *   in response
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IMultiUserTodoGuest.IJoin,
  ): Promise<IMultiUserTodoGuest.IAuthorized> {
    try {
      return await postMultiUserTodoAuthGuestJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Token refresh endpoint that renews expired or expiring access tokens using a valid refresh token.
   *
   * This operation allows guest users to maintain their authenticated session without re-registering. The refresh token workflow uses the multi_user_todo_guest_sessions table which stores session information with expiration timestamps (expired_at field). Sessions are linked to guests via the multi_user_todo_guest_id foreign key.
   *
   * Security considerations include validating token signatures, checking token expiration against the expired_at timestamp, ensuring the associated guest account is not soft-deleted (deleted_at must be null in multi_user_todo_guests table), and optionally implementing token rotation for enhanced security.
   *
   * The session tracking captures client metadata including IP address (ip), requested URL (href), and HTTP referrer (referrer) from the original session creation. This metadata remains associated with the refreshed session.
   *
   * Related operations include the join endpoint for initial guest registration that creates the refresh token.
   *
   * Request validation: refresh_token must be a valid JWT string. Response includes new access_token and optionally new refresh_token.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Request body containing the refresh token for token renewal.
     * @x-autobe-authorization-type refresh
     * @x-autobe-authorization-actor guest
     * @x-autobe-specification 1. Extract refresh_token from request body 2.
     *   Validate refresh_token format and signature (JWT validation) 3. Check
     *   if refresh_token exists in multi_user_todo_guest_sessions table and is
     *   not expired 4. Verify session's expired_at is greater than current
     *   timestamp 5. If session is valid, retrieve associated
     *   multi_user_todo_guest_id 6. Verify guest exists in
     *   multi_user_todo_guests table and is not soft-deleted (deleted_at is
     *   null) 7. Generate new JWT access token with guest ID and new expiry 8.
     *   Optionally generate new refresh token (token rotation) or reuse same
     *   refresh token 9. Update session record's expired_at timestamp if new
     *   refresh token is issued 10. Return new access token and optionally new
     *   refresh token in response
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IMultiUserTodoGuest.IRefresh,
  ): Promise<IMultiUserTodoGuest.IAuthorized> {
    try {
      return await postMultiUserTodoAuthGuestRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
