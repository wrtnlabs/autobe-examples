import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IMultiUserTodoMember } from "../../../../api/structures/IMultiUserTodoMember";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { putMultiUserTodoMemberProfile } from "../../../../providers/putMultiUserTodoMemberProfile";

@Controller("/multiUserTodo/member/profile")
export class MultiusertodoMemberProfileController {
  /**
   * Update the authenticated member's profile with a new display name.
   *
   * This endpoint allows an authenticated member to change their profile display name to any value they choose. The display name change takes effect immediately and is reflected across the application. Each member has exclusive access to their own profile and can update it at any time without affecting their account security or existing todos.
   *
   * The member is identified from the authenticated session, not from path parameters. The request body contains only the display_name field to be updated. If the display_name is omitted or identical to the current value, the operation succeeds with the current data.
   *
   * This operation corresponds to the multi_user_todo_members table where display_name is stored. The updated_at timestamp is automatically refreshed when this operation succeeds.
   *
   * @param connection
   * @param body Profile update data containing the new display name
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Validate that the authenticated session contains
     *   a valid member ID. Query the multi_user_todo_members table using the
     *   authenticated member ID from the session. Update the display_name field
     *   with the value provided in the request body. Set updated_at to the
     *   current timestamp. Return the complete member record including id,
     *   email, display_name, created_at, and updated_at. If the member does not
     *   exist (invalid session), return 401 Unauthorized.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IMultiUserTodoMember.IUpdate,
  ): Promise<IMultiUserTodoMember> {
    try {
      return await putMultiUserTodoMemberProfile({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
