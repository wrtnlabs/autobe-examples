import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IMultiUserTodoTodoEditHistory } from "../../../../../api/structures/IMultiUserTodoTodoEditHistory";
import { IPageIMultiUserTodoTodoEditHistory } from "../../../../../api/structures/IPageIMultiUserTodoTodoEditHistory";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { getMultiUserTodoMemberTodosTodoIdHistoryHistoryId } from "../../../../../providers/getMultiUserTodoMemberTodosTodoIdHistoryHistoryId";
import { patchMultiUserTodoMemberTodosTodoIdHistory } from "../../../../../providers/patchMultiUserTodoMemberTodosTodoIdHistory";

@Controller("/multiUserTodo/member/todos/:todoId/history")
export class MultiusertodoMemberTodosHistoryController {
  /**
   * Retrieve the edit history of a specific todo with pagination and optional filtering.
   *
   * This endpoint returns all edit history entries associated with the specified todo. Each history entry captures the changes made during a single edit operation, recording the old and new values for any fields that were modified (title, description, start date, due date).
   *
   * History entries are displayed in reverse chronological order with the most recent edits appearing first. This allows users to quickly see the latest modifications to their todos.
   *
   * Only active todos have accessible edit history. When a todo is moved to trash (soft-deleted), its history is not available for viewing. Once a todo is permanently deleted, all associated history entries are automatically removed as well.
   *
   * Users can only view the edit history of their own todos. The system enforces ownership verification to ensure privacy and data isolation between users.
   *
   * The response includes pagination metadata for navigating through large histories, along with summary information about each edit including the timestamp and the specific field changes that occurred.
   *
   * @param connection
   * @param todoId Unique identifier of the todo whose history to retrieve
   * @param body Pagination parameters for history retrieval
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query multi_user_todo_todo_edit_histories table
     *   filtered by multi_user_todo_todo_id matching the path parameter.
   *
   * 1. Ownership Verification:
   *    - First verify the todo exists in multi_user_todo_todos by todoId
   *    - Check that todo.multi_user_todo_member_id matches the authenticated user's member ID
   *    - Verify todo.deleted_at is null (active todo, not in trash)
   *    - If any check fails, return appropriate error response
   *
   * 2. History Query:
   *    - Query multi_user_todo_todo_edit_histories where multi_user_todo_todo_id = :todoId
   *    - Order by created_at DESC (newest first per requirements)
   *    - Apply pagination using page and limit parameters
   *    - Count total matching records for pagination metadata
   *
   * 3. Response Construction:
   *    - Map each history entry to ISummary format with:
   *      - id, created_at (timestamp of the edit)
   *      - old_title, new_title (null if not changed)
   *      - old_description, new_description (null if not changed)
   *      - old_start_date, new_start_date (null if not changed)
   *      - old_due_date, new_due_date (null if not changed)
   *    - Include pagination metadata: items, total, page, limit, totalPages
   *
   * 4. Error Handling:
   *    - 404 if todo not found
   *    - 403 if todo belongs to another user
   *    - 400 if todo is in trash (history not available for trashed todos)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IMultiUserTodoTodoEditHistory.IRequest,
  ): Promise<IPageIMultiUserTodoTodoEditHistory.ISummary> {
    try {
      return await patchMultiUserTodoMemberTodosTodoIdHistory({
        member,
        todoId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single edit history entry for a todo.
   *
   * This endpoint returns the details of a specific edit history entry associated with a todo. Each history entry records the changes made during a single edit operation, including the old and new values for any fields that were modified.
   *
   * The history entry contains the timestamp when the edit was made, along with old/new values for title, description, start_date, and due_date. Fields that were not changed during that edit will have null values for both old and new.
   *
   * **Security**: Only the owner of the todo can view its edit history. If the requesting user does not own the todo, the system returns a 404 error to maintain privacy.
   *
   * **Todo Status**: Edit history is only available for active todos. If the specified todo has been moved to trash (deleted_at is not null), the system returns a 404 error indicating that history is not available for trashed todos.
   *
   * **Relationship to Todo**: The history entry is linked to its parent todo through the multi_user_todo_todo_id field. This endpoint requires both the todo ID and history ID to ensure precise retrieval of the specific history entry.
   *
   * @param connection
   * @param todoId The unique identifier of the todo whose history entry is being retrieved
   * @param historyId The unique identifier of the specific history entry to retrieve
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification 1. Extract todoId and historyId from path
     *   parameters. 2. Query multi_user_todo_todos table to find the todo by
     *   todoId. 3. Verify the todo exists - return 404 if not found. 4. Verify
     *   the todo's multi_user_todo_member_id matches the authenticated user's
     *   member ID - return 404 if not authorized (do not reveal existence to
     *   unauthorized users). 5. Verify the todo's deleted_at is null - return
     *   404 if the todo is in trash (history not available for trashed todos).
     *   6. Query multi_user_todo_todo_edit_histories table to find the history
     *   entry by historyId. 7. Verify the history entry's
     *   multi_user_todo_todo_id matches the todoId - return 404 if not found.
     *   8. Return the history entry with all fields: id, todo_id, created_at,
     *   old_title, new_title, old_description, new_description, old_start_date,
     *   new_start_date, old_due_date, new_due_date. 9. The completion status of
     *   a todo is NOT tracked in the edit history.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":historyId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
    @TypedParam("historyId")
    historyId: string & tags.Format<"uuid">,
  ): Promise<IMultiUserTodoTodoEditHistory> {
    try {
      return await getMultiUserTodoMemberTodosTodoIdHistoryHistoryId({
        member,
        todoId,
        historyId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
