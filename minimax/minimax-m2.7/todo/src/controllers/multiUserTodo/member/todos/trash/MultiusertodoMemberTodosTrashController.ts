import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIMultiUserTodoTodo } from "../../../../../api/structures/IPageIMultiUserTodoTodo";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { deleteMultiUserTodoMemberTodosTrashTodoId } from "../../../../../providers/deleteMultiUserTodoMemberTodosTrashTodoId";
import { patchMultiUserTodoMemberTodosTrash } from "../../../../../providers/patchMultiUserTodoMemberTodosTrash";

@Controller("/multiUserTodo/member/todos/trash")
export class MultiusertodoMemberTodosTrashController {
  /**
   * Retrieve a paginated list of soft-deleted todos for the authenticated member.
   *
   * This endpoint returns all todos that have been moved to trash, allowing users to view their deleted items before deciding whether to restore or permanently delete them. The response is paginated with configurable page size and sorting options.
   *
   * Each returned todo includes its title, description, dates, and completion status at the time of deletion. The timestamps indicate when the todo was originally created and when it was moved to trash.
   *
   * Security: Only the authenticated member can access their own trash. Todos belonging to other users are not visible through this endpoint.
   *
   * Related Operations:
   * - POST /todos/{id}/restore - Restore a specific todo from trash
   * - DELETE /todos/{id} - Soft delete a todo (moves to trash)
   * - DELETE /trash/{id} - Permanently delete a specific todo from trash
   * - DELETE /trash - Empty trash (permanently delete all items)
   *
   * The trash list excludes active todos (those with null deleted_at). Users should first use GET /todos to view their active todo list.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query multi_user_todo_todos table filtering by multi_user_todo_member_id matching the authenticated session and deleted_at IS NOT NULL.
   *
   * Query Parameters:
   * - page: Page number (default: 1, minimum: 1)
   * - limit: Items per page (default: 20, minimum: 1, maximum: 100)
   * - sortBy: Sort field - 'created_at', 'start_date', or 'due_date' (default: 'created_at')
   * - sortOrder: Sort direction - 'asc' or 'desc' (default: 'desc')
   *
   * Business Rules:
   * - Only return todos where deleted_at is NOT NULL (soft-deleted items)
   * - Filter by multi_user_todo_member_id for privacy isolation
   * - Null handling for date sorting: todos without start_date/due_date appear at the end regardless of sort order
   * - No filtering by completion status (all deleted todos shown regardless of completion state)
   *
   * Pagination Response:
   * Return paginated results with pagination metadata:
   * - items: Array of IMultiUserTodoTodos.ISummary
   * - total: Total count of deleted todos for the member
   * - page: Current page number
   * - limit: Items per page
   * - totalPages: Calculated total pages
   *
   * Sort Order: ORDER BY {sortBy} {sortOrder}, NULLS LAST
   *
   * No request body. Query parameters passed via URL query string.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
  ): Promise<IPageIMultiUserTodoTodo.ISummary> {
    try {
      return await patchMultiUserTodoMemberTodosTrash({
        member,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a todo from the trash.
   *
   * This endpoint removes a todo that has been soft-deleted (moved to trash) and all its associated edit history entries from the system completely. The operation is irreversible and cannot be undone.
   *
   * **Prerequisites**: The todo must already be in trash (soft-deleted with deleted_at timestamp set). Attempting to permanently delete an active todo returns an error.
   *
   * **Scope**: The authenticated member can only permanently delete their own todos from trash. Accessing or deleting other users' todos is prohibited.
   *
   * **Cascade Behavior**: When a todo is permanently deleted, the system also deletes all associated edit history entries (multi_user_todo_todo_edit_histories) via cascade delete.
   *
   * **Response**: Returns 204 No Content on successful permanent deletion. Returns 404 Not Found if the todo does not exist or is not in trash.
   *
   * **Related Operations**:
   * - POST /todos/{todoId} (restore) - Restore a todo from trash back to active list
   * - DELETE /todos/{todoId} - Soft-delete a todo (move to trash)
   * - GET /trash - View all todos in trash
   *
   * @param connection
   * @param todoId Unique identifier of the todo to permanently delete from trash
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Service layer validates that the todo exists and belongs to the authenticated member. Verify deleted_at is not null to confirm todo is in trash. Begin transaction, delete all associated edit history entries (cascade), then delete the todo record. Return 204 No Content on success. Handle errors: 404 if todo not found or not in trash, 403 if todo belongs to another user.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":todoId")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteMultiUserTodoMemberTodosTrashTodoId({
        member,
        todoId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
