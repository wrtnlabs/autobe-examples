  /**
   * Create a new todo item for the authenticated member.
   *
   * This endpoint allows authenticated members to create a new todo task. The todo is automatically associated with the requesting member's account. Users must be authenticated via session token to create todos.
   *
   * The created todo includes the following properties:
   * - A unique identifier assigned by the system
   * - The member ID automatically derived from the authenticated session
   * - The title provided in the request body
   * - An optional description explaining the task details
   * - Optional start and due dates for scheduling
   * - Completion status automatically set to false on creation
   * - Creation and update timestamps automatically recorded
   * - Soft-delete timestamp initially null
   *
   * The system enforces ownership by associating the new todo with the authenticated user's member ID. Todos created through this endpoint are immediately visible in the user's todo list and are not marked as deleted.
   *
   * This operation relates to other todo endpoints:
   * - GET /todos - List todos including the newly created one
   * - GET /todos/:id - View details of the created todo
   * - PATCH /todos/:id - Update properties of the created todo
   *
   * @param connection
   * @param body Todo creation data including required title and optional description, startDate, and dueDate
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Create a new todo record in the multi_user_todo_todos table.
   *
   * 1. Extract multi_user_todo_member_id from the authenticated session (from Authorization header or session cookie).
   *
   * 2. Validate request body:
   *    - title: Required, non-empty string
   *    - description: Optional, defaults to empty string
   *    - startDate: Optional, ISO 8601 date-time format
   *    - dueDate: Optional, ISO 8601 date-time format
   *
   * 3. Validate business rules:
   *    - Title must not be empty after trimming whitespace
   *    - If both startDate and dueDate are provided, dueDate must be after startDate
   *
   * 4. Insert into multi_user_todo_todos:
   *    - id: Generate new UUID
   *    - multi_user_todo_member_id: From authenticated session
   *    - title: From request body
   *    - description: From request body or empty string
   *    - start_date: From request body or null
   *    - due_date: From request body or null
   *    - completed: false (default)
   *    - created_at: Current timestamp
   *    - updated_at: Current timestamp
   *    - deleted_at: null
   *
   * 5. Return the created todo record with all fields populated.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
