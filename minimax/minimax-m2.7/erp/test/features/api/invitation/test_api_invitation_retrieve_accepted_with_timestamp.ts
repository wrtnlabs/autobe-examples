export async function test_api_invitation_retrieve_accepted_with_timestamp(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create first member account
  const member1Connection: api.IConnection = { host: connection.host };
  const member1 = await authorize_member_join(member1Connection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      displayName: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  typia.assert(member1);
  // 2. Create second member account (with different email)
  const member2Connection: api.IConnection = { host: connection.host };
  const member2 = await authorize_member_join(member2Connection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      displayName: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  typia.assert(member2);
  // 3. Create invitation for the second member's email (auto-accepts because user exists)
  const invitation = await generate_random_erp_hrm_member_invitations_create(
    member1Connection,
    {
      body: {
        email: member2.email,
      },
    },
  );
  typia.assert(invitation);
  // 4. Retrieve the invitation
  const retrieved = await api.functional.erpHrm.member.invitations.at(
    member1Connection,
    {
      invitationId: invitation.id,
    },
  );
  typia.assert(retrieved);
  // 5. Validate the response
  TestValidator.equals("status is accepted", retrieved.status, "accepted");
  TestValidator.predicate(
    "accepted_at is not null",
    retrieved.accepted_at !== null,
  );
  TestValidator.equals("email matches", retrieved.email, member2.email);
}
