export async function test_api_invitation_retrieve_not_found(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as a member
  const memberConnection: api.IConnection = { host: connection.host };
  await authorize_member_join(memberConnection, {});
  // 2. Attempt to retrieve a non-existent invitation
  const nonExistentInvitationId = "00000000-0000-0000-0000-000000000000";
  // 3. Validate the response is HTTP 404
  await TestValidator.error("non-existent invitation returns 404", async () => {
    await api.functional.erpHrm.member.invitations.at(memberConnection, {
      invitationId: nonExistentInvitationId as string & tags.Format<"uuid">,
    });
  });
}
