export async function test_api_contract_creation_unauthorized_forbidden(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin creates organization context
  const adminConnection: api.IConnection = { host: connection.host };
  const adminAuth = await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  typia.assert(adminAuth);
  // 2. Create regular member without employee:manage permission
  const memberConnection: api.IConnection = { host: connection.host };
  const memberAuth = await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      displayName: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  typia.assert(memberAuth);
  // 3. Member attempts to create contract (should be forbidden)
  await TestValidator.httpError(
    "member without employee:manage permission cannot create contract",
    403,
    async () => {
      await api.functional.erpHrm.admin.employees.contracts.create(
        memberConnection,
        {
          employeeId: typia.random<string & tags.Format<"uuid">>(),
          body: {
            start_date: new Date().toISOString(),
            pay_rate: typia.random<
              number & tags.Type<"float"> & tags.Minimum<1000>
            >(),
            pay_period: "monthly",
            working_hours_per_week: 40,
          } satisfies IErpHrmContract.ICreate,
        },
      );
    },
  );
}
