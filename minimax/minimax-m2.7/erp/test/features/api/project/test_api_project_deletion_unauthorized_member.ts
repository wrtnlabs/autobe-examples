export async function test_api_project_deletion_unauthorized_member(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register admin account
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  // 2. Create a project as admin
  const project = await generate_random_erp_hrm_admin_projects_create(
    adminConnection,
    {},
  );
  typia.assert(project);
  // 3. Register a member without project:manage permission
  const memberConnection: api.IConnection = { host: connection.host };
  await authorize_member_join(memberConnection, {});
  // 4. Attempt to delete the project as member - should fail with 403
  await TestValidator.httpError(
    "member cannot delete project without permission",
    403,
    async () => {
      await api.functional.erpHrm.admin.projects.erase(memberConnection, {
        projectId: project.id,
      });
    },
  );
}
