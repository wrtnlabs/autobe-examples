export async function test_api_project_deletion_not_found(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as a member with project:manage permission
  const memberConnection: api.IConnection = { host: connection.host };
  await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      displayName: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IErpHrmMember.IJoin,
  });
  // 2. Attempt to delete a project using a UUID that does not exist
  const nonExistentProjectId = typia.random<string & tags.Format<"uuid">>();
  // 3. Verify the response is 404 Not Found
  await TestValidator.httpError(
    "delete non-existent project returns 404",
    404,
    async () =>
      await api.functional.erpHrm.member.projects.erase(memberConnection, {
        projectId: nonExistentProjectId,
      }),
  );
}
