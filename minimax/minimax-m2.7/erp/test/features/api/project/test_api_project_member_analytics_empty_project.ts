export async function test_api_project_member_analytics_empty_project(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register admin account
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      displayName: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  // 2. Create a project with no members
  const project = await generate_random_erp_hrm_admin_projects_create(
    adminConnection,
    {},
  );
  typia.assert(project);
  // 3. Call analytics endpoint for empty project
  const analytics =
    await api.functional.erpHrm.admin.projects.analytics.members.at(
      adminConnection,
      {
        projectId: project.items[0]!.projectId,
      },
    );
  typia.assert(analytics);
  // 4. Validate analytics for empty project
  TestValidator.equals("totalCount is 0", analytics.totalCount, 0);
  TestValidator.equals("memberCount is 0", analytics.memberCount, 0);
  TestValidator.equals("projectLeadCount is 0", analytics.projectLeadCount, 0);
  TestValidator.equals("members is empty array", analytics.members.length, 0);
}
