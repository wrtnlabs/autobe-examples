import { authorize_admin_join } from "../../../authorize/authorize_admin_join";
import { authorize_admin_login } from "../../../authorize/authorize_admin_login";
import { authorize_admin_refresh } from "../../../authorize/authorize_admin_refresh";

export async function test_api_role_validation_unique_name_available(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as admin
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      displayName: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IErpHrmAdmin.IJoin,
  });
  // 2. Call role validation with a unique role name
  const uniqueRoleName = `QA Lead ${RandomGenerator.alphaNumeric(6)}`;
  const validationResult = await api.functional.erpHrm.admin.roles.validate(
    adminConnection,
    {
      body: {
        name: uniqueRoleName,
      } satisfies IErpHrmRole.IValidationRequest,
    },
  );
  typia.assert(validationResult);
  // 3. Verify validation passes
  TestValidator.equals(
    "isValid should be true",
    validationResult.isValid,
    true,
  );
  TestValidator.equals("errors should be empty", validationResult.errors, []);
}
