export async function test_api_role_permission_bulk_update_builtin_role_protected(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as admin
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      displayName: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IErpHrmAdmin.IJoin,
  });
  // 2. Attempt to bulk update permissions for Manager built-in role
  // Note: Using a placeholder UUID since GET /erpHrm/member/roles endpoint is not available in SDK
  const managerRoleId = typia.random<string & tags.Format<"uuid">>();
  // 3. Expect 400 error - built-in roles cannot be modified
  await TestValidator.httpError(
    "built-in role permissions cannot be updated",
    400,
    async () =>
      await api.functional.erpHrm.admin.roles.permissions.bulk.bulkUpdate(
        adminConnection,
        {
          roleId: managerRoleId,
          body: {
            permissions: ["project:view"],
          } satisfies IErpHrmRolePermission.IBulkUpdate,
        },
      ),
  );
}
