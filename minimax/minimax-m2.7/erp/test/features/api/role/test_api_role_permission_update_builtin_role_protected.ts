export async function test_api_role_permission_update_builtin_role_protected(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as admin
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      displayName: RandomGenerator.name(),
    },
  });
  // 2. Attempt to update permissions on a built-in role
  // Using a known UUID format for built-in roles (system-defined)
  const builtinRoleId = "00000000-0000-0000-0000-000000000001" as string &
    tags.Format<"uuid">;
  // 3. Expect 400 error - built-in roles cannot be modified
  await TestValidator.httpError(
    "built-in role permissions update should be rejected",
    400,
    async () =>
      await api.functional.erpHrm.member.roles.permissions.updatePermissions(
        adminConnection,
        {
          roleId: builtinRoleId,
          body: {
            permissions: ["employee:manage"],
          } satisfies IErpHrmRole.IUpdatePermission,
        },
      ),
  );
}
