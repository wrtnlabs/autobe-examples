export async function test_api_organization_deletion_with_clean_state(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as admin
  const adminConnection: api.IConnection = { host: connection.host };
  const admin = await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      displayName: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  typia.assert(admin);
  // 2. Create a new organization (clean state - no employees, no timesheets)
  const organization = await generate_random_erp_hrm_admin_organizations_create(
    adminConnection,
    {},
  );
  typia.assert(organization);
  // 3. Delete the organization (should succeed in clean state)
  await api.functional.erpHrm.admin.organizations.erase(adminConnection, {
    organizationId: organization.id,
  });
  // 4. Validate deletion was successful (204 No Content)
  // The erase function returns void on success, so we verify by attempting to check
  // that no error was thrown during deletion
  TestValidator.predicate("organization deleted successfully", true);
}
