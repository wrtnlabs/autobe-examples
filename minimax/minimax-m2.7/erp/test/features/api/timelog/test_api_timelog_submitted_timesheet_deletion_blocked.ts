export async function test_api_timelog_submitted_timesheet_deletion_blocked(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create member session via join
  const memberConnection: api.IConnection = { host: connection.host };
  await authorize_member_join(memberConnection, {});
  // 2. Create a project
  const project = await generate_random_erp_hrm_member_projects_create(
    memberConnection,
    {
      body: {
        name: RandomGenerator.paragraph({ sentences: 2 }),
        color: "#FF5733",
        status: "active" as const,
      },
    },
  );
  typia.assert(project);
  // 3. Create a timelog
  const timelog = await generate_random_erp_hrm_member_timelogs_create(
    memberConnection,
    {
      body: {
        projectId: project.id,
        date: new Date().toISOString(),
        durationMinutes: 60,
      },
    },
  );
  typia.assert(timelog);
  // 4. Create a draft timesheet (timelog will be auto-included if within date range)
  const timesheet = await generate_random_erp_hrm_member_timesheets_create(
    memberConnection,
    {
      body: {
        week_start_date: new Date().toISOString(),
        week_end_date: new Date(
          Date.now() + 6 * 24 * 60 * 60 * 1000,
        ).toISOString(),
      },
    },
  );
  typia.assert(timesheet);
  // 5. Submit the timesheet for approval
  const submittedTimesheet =
    await api.functional.erpHrm.member.timesheets.submit(memberConnection, {
      timesheetId: timesheet.id,
    });
  typia.assert(submittedTimesheet);
  // 6. Attempt to delete the timelog - expected to fail with error
  await TestValidator.error(
    "timelog in submitted timesheet cannot be deleted",
    async () => {
      await api.functional.erpHrm.member.timelogs.erase(memberConnection, {
        timelogId: timelog.id,
      });
    },
  );
}
