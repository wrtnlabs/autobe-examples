export async function test_api_timelog_query_member_with_no_timelogs(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin authentication
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_login(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IErpHrmAdmin.ILogin,
  });
  // 2. Create organization
  const organization = await generate_random_erp_hrm_admin_organizations_create(
    adminConnection,
    {},
  );
  typia.assert(organization);
  // 3. Create member account
  const memberConnection: api.IConnection = { host: connection.host };
  const memberAuth = await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  typia.assert(memberAuth);
  // 4. Query timelogs for the member (who has no timelogs yet)
  // The endpoint queries by memberId and returns timelogs from employees associated with that member
  const timelogResponse =
    await api.functional.erpHrm.admin.members.timelogs.index(adminConnection, {
      memberId: memberAuth.id,
      body: {
        limit: 20,
        page: 1,
      } satisfies IErpHrmTimelog.IRequest,
    });
  typia.assert(timelogResponse);
  // 5. Validate response - should have empty data array with zero records
  TestValidator.equals("data array should be empty", timelogResponse.data, []);
  TestValidator.equals(
    "records should be zero",
    timelogResponse.pagination.records,
    0,
  );
  TestValidator.equals(
    "pages should be zero",
    timelogResponse.pagination.pages,
    0,
  );
  TestValidator.equals(
    "current page should be 1",
    timelogResponse.pagination.current,
    1,
  );
}
