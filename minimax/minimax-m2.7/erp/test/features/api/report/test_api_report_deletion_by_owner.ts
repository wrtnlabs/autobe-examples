export async function test_api_report_deletion_by_owner(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as admin using join
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  // 2. Generate a random organization ID for report creation
  const organizationId = typia.random<string & tags.Format<"uuid">>();
  // 3. Create a report to be deleted
  const report =
    await generate_random_erp_hrm_admin_organizations_reports_create(
      adminConnection,
      {
        params: {
          organizationId: organizationId,
        },
      },
    );
  // 4. Delete the report
  await api.functional.erpHrm.admin.organizations.reports.erase(
    adminConnection,
    {
      organizationId: report.organization.id,
      reportId: report.id,
    },
  );
}
