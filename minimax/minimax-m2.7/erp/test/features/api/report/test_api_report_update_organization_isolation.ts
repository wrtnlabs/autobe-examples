export async function test_api_report_update_organization_isolation(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as member using utility function
  const memberConnection: api.IConnection = { host: connection.host };
  const authorized = await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      displayName: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IErpHrmMember.IJoin,
  });
  typia.assert(authorized);
  // 2. Create a report in one organization (organization A)
  const organizationAId = typia.random<string & tags.Format<"uuid">>();
  const report =
    await generate_random_erp_hrm_member_organizations_reports_create(
      memberConnection,
      {
        params: { organizationId: organizationAId },
      },
    );
  typia.assert(report);
  // 3. Attempt to update the report using a different organization ID (organization B)
  const organizationBId = typia.random<string & tags.Format<"uuid">>();
  // 4. Verify the system returns 404 not found error
  // The report does not belong to organization B, so the system should reject the request
  await TestValidator.httpError(
    "cannot update report from different organization",
    404,
    async () =>
      await api.functional.erpHrm.member.organizations.reports.update(
        memberConnection,
        {
          organizationId: organizationBId,
          reportId: report.id,
          body: {
            name: RandomGenerator.paragraph({ sentences: 1 }),
          } satisfies IErpHrmReport.IUpdate,
        },
      ),
  );
}
