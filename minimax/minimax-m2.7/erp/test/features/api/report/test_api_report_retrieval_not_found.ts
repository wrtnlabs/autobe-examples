export async function test_api_report_retrieval_not_found(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as admin
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      displayName: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IErpHrmAdmin.IJoin,
  });
  // 2. Generate a random UUID that doesn't exist
  const nonExistentReportId = typia.random<string & tags.Format<"uuid">>();
  // 3. Attempt to retrieve non-existent report - should return 404
  await TestValidator.httpError(
    "report not found returns 404",
    404,
    async () => {
      await api.functional.erpHrm.admin.reports.at(adminConnection, {
        reportId: nonExistentReportId,
      });
    },
  );
}
