export async function test_api_timer_discard_by_non_owner(
  connection: api.IConnection,
): Promise<void> {
  // 1. Member A registers and authenticates
  const memberAConnection: api.IConnection = { host: connection.host };
  const memberAAuthorized = await authorize_member_join(memberAConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      displayName: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  // 2. Member B registers and authenticates (different session)
  const memberBConnection: api.IConnection = { host: connection.host };
  await authorize_member_join(memberBConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      displayName: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  // 3. Create a project for timer assignment
  const project = await generate_random_erp_hrm_member_projects_create(
    memberAConnection,
    {
      body: {
        name: RandomGenerator.name(),
        color: "#FF5733",
        status: "active",
      },
    },
  );
  // 4. Member A creates a timer (this timer belongs to Member A)
  const timer = await generate_random_erp_hrm_member_timers_create(
    memberAConnection,
    {
      body: {
        erp_hrm_project_id: project.id,
      },
    },
  );
  // 5. Member B attempts to discard Member A's timer (should fail with 403)
  await TestValidator.httpError(
    "non-owner cannot discard timer",
    403,
    async () => {
      await api.functional.erpHrm.member.timers.erase(memberBConnection, {
        timerId: timer.id,
      });
    },
  );
}
