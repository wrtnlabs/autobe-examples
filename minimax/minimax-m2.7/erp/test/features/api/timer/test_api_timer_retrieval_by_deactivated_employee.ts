export async function test_api_timer_retrieval_by_deactivated_employee(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create a member account via member join
  const memberConnection: api.IConnection = { host: connection.host };
  const authorized = await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  // 2. Create authorized connection with the token
  const memberAuthorizedConnection: api.IConnection = {
    host: connection.host,
    headers: {
      Authorization: `Bearer ${authorized.token.access}`,
    },
  };
  // 3. Attempt to retrieve timer as the member
  // A newly registered member without an active employee record (or with deactivated employee)
  // should be rejected when trying to access timer endpoints.
  // The system validates that the authenticated member has an active employee in the organization.
  await TestValidator.httpError(
    "deactivated employee cannot retrieve timer",
    403,
    async () =>
      await api.functional.erpHrm.member.timers.at(memberAuthorizedConnection),
  );
}
