export async function test_api_timer_retrieval_without_active_timer(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin setup - create organization and project
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  await authorize_admin_login(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IErpHrmAdmin.ILogin,
  });
  // 2. Create organization
  const organization = await generate_random_erp_hrm_admin_organizations_create(
    adminConnection,
    {},
  );
  typia.assert(organization);
  // 3. Create project
  const project = await generate_random_erp_hrm_admin_projects_create(
    adminConnection,
    {
      body: {
        name: RandomGenerator.paragraph({ sentences: 1 }),
        color: "#4A90E2",
        description: RandomGenerator.paragraph({ sentences: 2 }),
        status: "active",
      },
    },
  );
  typia.assert(project);
  // 4. Member setup - join and login
  const memberConnection: api.IConnection = { host: connection.host };
  const memberAuthorized = await authorize_member_join(memberConnection, {});
  const memberPassword = RandomGenerator.alphaNumeric(16);
  const memberLoginBody = {
    email: memberAuthorized.email,
    password: memberPassword,
    href: typia.random<string & tags.Format<"uri">>(),
    referrer: typia.random<string & tags.Format<"uri">>(),
  } satisfies IErpHrmMember.ILogin;
  await authorize_member_login(memberConnection, {
    body: memberLoginBody,
  });
  // 5. Retrieve timers without any active timer started
  const timerResponse = await api.functional.erpHrm.member.timers.index(
    memberConnection,
    {
      body: {} satisfies IErpHrmTimer.IRequest,
    },
  );
  typia.assert(timerResponse);
  // 6. Validate the response
  TestValidator.equals("data should be empty array", timerResponse.data, []);
  TestValidator.equals(
    "records should be 0",
    timerResponse.pagination.records,
    0,
  );
}
