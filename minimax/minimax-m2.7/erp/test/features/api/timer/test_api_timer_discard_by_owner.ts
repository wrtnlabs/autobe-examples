export async function test_api_timer_discard_by_owner(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin creates account
  const adminConnection: api.IConnection = { host: connection.host };
  const admin = await authorize_admin_join(adminConnection, {});
  // 2. Admin sets organization context
  const organization = await generate_random_erp_hrm_admin_organizations_create(
    adminConnection,
    {},
  );
  // 3. Admin creates a project
  const project = await generate_random_erp_hrm_admin_projects_create(
    adminConnection,
    {},
  );
  // 4. Member creates account
  const memberConnection: api.IConnection = { host: connection.host };
  const member = await authorize_member_join(memberConnection, {});
  // 5. Admin assigns member to project
  await generate_random_erp_hrm_admin_projects_members_create(adminConnection, {
    params: { projectId: project.items[0].projectId },
  });
  // 6. Member starts a timer
  const timer = await generate_random_erp_hrm_member_timers_create(
    memberConnection,
    {
      body: {
        erpHrmProjectId: project.items[0].projectId,
      },
    },
  );
  // 7. Member discards the timer
  await api.functional.erpHrm.member.timers.erase(memberConnection, {
    timerId: timer.id,
  });
}
