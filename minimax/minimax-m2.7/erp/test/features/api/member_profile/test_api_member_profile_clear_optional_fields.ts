export async function test_api_member_profile_clear_optional_fields(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register a new member account
  const memberConnection: api.IConnection = { host: connection.host };
  const authorized = await authorize_member_join(memberConnection, {});
  typia.assert(authorized);
  // 2. Update profile with avatar_uri and phone set to null to clear them
  const updatedProfile =
    await api.functional.erpHrm.member.profile.updateProfile(memberConnection, {
      body: {
        display_name: RandomGenerator.name(),
        avatar_uri: null,
        phone: null,
      } satisfies IErpHrmMember.IUpdate,
    });
  const safeProfile = typia.assert(updatedProfile) as IErpHrmMember.IAuthorized;
  // 3. Verify both optional fields are now null
  TestValidator.equals(
    "avatar_uri should be null",
    safeProfile.avatar_uri,
    null,
  );
  TestValidator.equals("phone should be null", safeProfile.phone, null);
}
