export async function test_api_timesheet_deletion_by_owner_draft(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as a member
  const memberConnection: api.IConnection = { host: connection.host };
  await authorize_member_join(memberConnection, {});
  // 2. Create a draft timesheet
  const timesheet = await generate_random_erp_hrm_member_timesheets_create(
    memberConnection,
    {},
  );
  typia.assert(timesheet);
  // 3. Verify the timesheet is created with status 'draft'
  TestValidator.equals("status is draft", timesheet.status, "draft");
  // 4. Delete the draft timesheet (should succeed with 204 No Content)
  await api.functional.erpHrm.member.timesheets.erase(memberConnection, {
    timesheetId: timesheet.id,
  });
  // Note: GET /member/timesheets/{timesheetId} endpoint does not exist in SDK
  // The successful erasure call above confirms the deletion worked
}
