export async function test_api_timesheet_retrieval_admin_non_existent(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as admin
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IErpHrmAdmin.IJoin,
  });
  // 2. Generate a valid UUID that does not correspond to any existing timesheet
  const nonExistentTimesheetId = typia.random<string & tags.Format<"uuid">>();
  // 3. Verify that retrieving a non-existent timesheet returns 404 Not Found
  // This confirms the difference between 'not found' and 'unauthorized access' scenarios
  await TestValidator.httpError(
    "non-existent timesheet returns 404",
    404,
    async () =>
      await api.functional.erpHrm.admin.timesheets.at(adminConnection, {
        timesheetId: nonExistentTimesheetId,
      }),
  );
}
