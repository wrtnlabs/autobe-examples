export async function test_api_timesheet_retrieval_not_found(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as admin
  const adminConnection: api.IConnection = { host: connection.host };
  const admin = await authorize_admin_join(adminConnection, {});
  // 2. Create organization
  const organization = await generate_random_erp_hrm_admin_organizations_create(
    adminConnection,
    {},
  );
  // 3. Authenticate as member
  const memberConnection: api.IConnection = { host: connection.host };
  const member = await authorize_member_join(memberConnection, {});
  // 4. Generate a non-existent timesheet UUID
  const nonExistentTimesheetId = typia.random<string & tags.Format<"uuid">>();
  // 5. Attempt to retrieve non-existent timesheet - should return 404
  await TestValidator.httpError(
    "non-existent timesheet returns 404",
    404,
    async () =>
      await api.functional.erpHrm.admin.members.timesheets.at(
        memberConnection,
        {
          memberId: member.id,
          timesheetId: nonExistentTimesheetId,
        },
      ),
  );
}
