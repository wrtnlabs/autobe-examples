export async function test_api_task_assignment_to_non_project_member_rejected(
  connection: api.IConnection,
): Promise<void> {
  // Step 1: Create first member (project owner)
  const member1Connection: api.IConnection = { host: connection.host };
  const member1 = await authorize_member_join(member1Connection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      displayName: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  typia.assert(member1);
  // Step 2: Create a project
  const project = await generate_random_erp_hrm_member_projects_create(
    member1Connection,
    {
      body: {
        name: RandomGenerator.name(),
        color: "#FF5733",
        status: "active",
      },
    },
  );
  typia.assert(project);
  // Step 3: Create second member who is NOT added to the project
  const member2Connection: api.IConnection = { host: connection.host };
  const member2 = await authorize_member_join(member2Connection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      displayName: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  typia.assert(member2);
  // Step 4: Attempt to create a task with the non-project-member as assignee
  // The second member is NOT a project member, so this should be rejected
  await TestValidator.httpError(
    "assigning non-project-member to task should be rejected",
    400,
    async () => {
      await api.functional.erpHrm.member.projects.tasks.create(
        member1Connection,
        {
          projectId: project.id,
          body: {
            title: RandomGenerator.paragraph({ sentences: 1 }),
            priority: RandomGenerator.pick([
              "low",
              "medium",
              "high",
              "urgent",
            ] as const),
            erp_hrm_employee_id: member2.id,
          } satisfies IErpHrmTask.ICreate,
        },
      );
    },
  );
}
