/**
 * Test that an admin receives 404 error when attempting to retrieve a non-existent member.
 *
 * This test validates:
 * 1. Admin authentication via join endpoint
 * 2. Member retrieval with non-existent UUID returns 404
 * 3. System properly handles requests for deleted or non-existent resources
 */
export async function test_api_member_retrieval_non_existent_member(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as admin
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  // 2. Generate a non-existent member UUID
  const nonExistentMemberId = typia.random<string & tags.Format<"uuid">>();
  // 3. Verify that retrieving non-existent member returns 404
  await TestValidator.httpError(
    "non-existent member should return 404",
    404,
    async () =>
      await api.functional.erpHrm.admin.members.at(adminConnection, {
        memberId: nonExistentMemberId,
      }),
  );
}
