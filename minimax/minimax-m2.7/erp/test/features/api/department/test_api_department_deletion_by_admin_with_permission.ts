export async function test_api_department_deletion_by_admin_with_permission(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as admin
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  // 2. Create a department to delete
  const department = await generate_random_erp_hrm_admin_departments_create(
    adminConnection,
    {
      body: {
        name: "Engineering",
      },
    },
  );
  typia.assert(department);
  // 3. Delete the department and verify 204 No Content
  await api.functional.erpHrm.admin.departments.erase(adminConnection, {
    departmentId: department.id,
  });
}
