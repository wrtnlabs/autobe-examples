export async function test_api_activity_log_access_denied_without_permission(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create admin account (owner role with org:manage permission)
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      displayName: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  // 2. Create member account (will have Employee role without org:manage permission)
  const memberConnection: api.IConnection = { host: connection.host };
  await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  // 3. Set organization context for the member
  // The member gets the default Employee role which lacks org:manage permission
  // Organization is provisioned automatically when admin joins
  await generate_random_erp_hrm_member_organization_context_select(
    memberConnection,
    {},
  );
  // 4. Attempt to retrieve activity log - should be denied (403 Forbidden)
  // Member with Employee role does not have org:manage permission required for this endpoint
  const fakeActivityLogId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.httpError(
    "access denied without org:manage permission",
    403,
    async () =>
      await api.functional.erpHrm.admin.activity_logs.at(memberConnection, {
        activityLogId: fakeActivityLogId,
      }),
  );
}
