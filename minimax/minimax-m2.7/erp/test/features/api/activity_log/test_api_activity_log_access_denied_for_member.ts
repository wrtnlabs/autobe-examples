export async function test_api_activity_log_access_denied_for_member(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create member account without org:manage permission
  const memberConnection: api.IConnection = { host: connection.host };
  await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      displayName: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  // 2. Member attempts to access activity log endpoint (requires org:manage permission)
  // Expected: HTTP 403 Forbidden - access denied for member without elevated privileges
  await TestValidator.httpError(
    "access denied for member without org:manage permission",
    403,
    async () =>
      await api.functional.erpHrm.admin.organizations.activity_logs.at(
        memberConnection,
        {
          organizationId: typia.random<string & tags.Format<"uuid">>(),
          activityLogId: typia.random<string & tags.Format<"uuid">>(),
        },
      ),
  );
}
