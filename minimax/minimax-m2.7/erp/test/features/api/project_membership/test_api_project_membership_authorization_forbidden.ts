export async function test_api_project_membership_authorization_forbidden(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create admin connection and authenticate
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  // 2. Authenticate as member A (project creator)
  const memberAConnection: api.IConnection = { host: connection.host };
  const memberAAuthorized = await authorize_member_join(memberAConnection, {});
  typia.assert(memberAAuthorized);
  // 3. Create a project using member A
  const project = await generate_random_erp_hrm_member_projects_create(
    memberAConnection,
    {},
  );
  typia.assert(project);
  // 4. Authenticate as member B who will be added to project
  const memberBConnection: api.IConnection = { host: connection.host };
  const memberBAuthorized = await authorize_member_join(memberBConnection, {});
  typia.assert(memberBAuthorized);
  // 5. Assign member B to project as member role
  const projectMembership =
    await generate_random_erp_hrm_member_projects_members_create(
      memberAConnection,
      {
        params: { projectId: project.id },
      },
    );
  typia.assert(projectMembership);
  // 6. Authenticate as member C who is NOT a member of the project
  const memberCConnection: api.IConnection = { host: connection.host };
  const memberCAuthorized = await authorize_member_join(memberCConnection, {});
  typia.assert(memberCAuthorized);
  // 7. Verify that member C cannot access project membership details (403 Forbidden)
  await TestValidator.httpError(
    "non-project member should receive 403 forbidden",
    403,
    async () => {
      await api.functional.erpHrm.member.projects.members.at(
        memberCConnection,
        {
          projectId: project.id,
          memberId: projectMembership.id,
        },
      );
    },
  );
}
