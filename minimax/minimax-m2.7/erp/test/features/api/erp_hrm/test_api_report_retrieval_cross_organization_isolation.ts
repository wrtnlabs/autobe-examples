export async function test_api_report_retrieval_cross_organization_isolation(
  connection: api.IConnection,
): Promise<void> {
  // Create a new connection for admin authentication
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      display_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  // Create a report in Organization A
  const organizationAId = typia.random<string & tags.Format<"uuid">>();
  const report =
    await generate_random_erp_hrm_admin_organizations_reports_create(
      adminConnection,
      {
        params: {
          organizationId: organizationAId,
        },
      },
    );
  typia.assert(report);
  // Attempt to retrieve the report using Organization B's organizationId
  const organizationBId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.httpError(
    "cross-organization report access denied",
    403,
    async () =>
      await api.functional.erpHrm.admin.organizations.reports.at(
        adminConnection,
        {
          organizationId: organizationBId,
          reportId: report.id,
        },
      ),
  );
}
