export async function test_api_token_refresh_with_expired_token(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create a member account via join to obtain credentials
  const authorized = await authorize_member_join(connection, {});
  typia.assert(authorized);
  // 2. Attempt to refresh using an invalid/expired refresh token value
  // The system should reject this and return an authentication error
  await TestValidator.error("expired refresh token rejected", async () => {
    await api.functional.erpHrm.auth.member.refresh(connection, {
      body: {
        refresh_token: "invalid_or_expired_refresh_token_abc123xyz789",
      } satisfies IErpHrmMember.IRefresh,
    });
  });
}
