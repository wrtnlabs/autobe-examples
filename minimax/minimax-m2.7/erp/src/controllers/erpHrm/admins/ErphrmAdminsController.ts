import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IErpHrmAdmin } from "../../../api/structures/IErpHrmAdmin";
import { IPageIErpHrmAdmin } from "../../../api/structures/IPageIErpHrmAdmin";
import { getErpHrmAdminsAdminId } from "../../../providers/getErpHrmAdminsAdminId";
import { patchErpHrmAdmins } from "../../../providers/patchErpHrmAdmins";

@Controller("/erpHrm/admins")
export class ErphrmAdminsController {
  /**
   * Retrieve a filtered and paginated list of system administrator accounts.
   *
   * This operation enables platform administrators to search and browse admin accounts across the system. Supports filtering by email address, display name, and other criteria. Results are returned in a paginated format with configurable page sizes.
   *
   * The response includes admin summary information optimized for list displays, showing key attributes such as display name, email, and avatar.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering admin accounts
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor null
     * @x-autobe-specification Query the erp_hrm_admins table with pagination
     *   and filtering.
   *
   * Apply search filters on email (partial match), display_name (partial match), and phone if provided.
   *
   * Implement cursor-based pagination for efficient large result set traversal.
   *
   * Return only non-sensitive data: id, email, display_name, avatar_uri, phone, created_at. Never return password_hash in any response.
   *
   * Sort results by created_at descending by default (newest first).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IErpHrmAdmin.IRequest,
  ): Promise<IPageIErpHrmAdmin.ISummary> {
    try {
      return await patchErpHrmAdmins({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single administrator account by its unique identifier.
   *
   * This operation fetches the complete details of an administrator account including their email address, display name, avatar, phone number, and account timestamps. The password hash is never exposed in API responses for security reasons.
   *
   * This endpoint is typically used for admin profile display, account management interfaces, or administrative oversight features. The response includes the admin's creation and last update timestamps for audit purposes.
   *
   * @param connection
   * @param adminId Unique identifier of the administrator account to retrieve (UUID format)
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor null
     * @x-autobe-specification Query the erp_hrm_admins table using the provided
     *   adminId as the primary key lookup.
   *
   * Return the matching admin record with all fields EXCEPT password_hash.
   *
   * If no admin exists with the given UUID, return a 404 Not Found error.
   *
   * The admin record is a system-level entity and does not require organization context filtering.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":adminId")
  public async at(
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
  ): Promise<IErpHrmAdmin> {
    try {
      return await getErpHrmAdminsAdminId({
        adminId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
