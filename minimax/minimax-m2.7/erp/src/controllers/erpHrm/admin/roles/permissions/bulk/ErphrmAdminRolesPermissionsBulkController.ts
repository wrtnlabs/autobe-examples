import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IErpHrmRole } from "../../../../../../api/structures/IErpHrmRole";
import { IErpHrmRolePermission } from "../../../../../../api/structures/IErpHrmRolePermission";
import { AdminAuth } from "../../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../../decorators/payload/AdminPayload";
import { putErpHrmAdminRolesRoleIdPermissionsBulk } from "../../../../../../providers/putErpHrmAdminRolesRoleIdPermissionsBulk";

@Controller("/erpHrm/admin/roles/:roleId/permissions/bulk")
export class ErphrmAdminRolesPermissionsBulkController {
  /**
   * Replace all permissions assigned to a role with a new set of permissions.
   *
   * This bulk update operation replaces the entire permission set of a custom role. The request body should contain the complete list of permission codes to assign. Permissions not included in the request are removed from the role.
   *
   * Built-in roles (Owner, Manager, Employee) cannot be modified. Attempting to update permissions for a built-in role returns a validation error. Only organization owners with org:manage permission can modify custom roles.
   *
   * The operation validates that all provided permission codes are valid system permissions. Duplicate permissions in the request are deduplicated before storage.
   *
   * @param connection
   * @param roleId Unique identifier of the role (UUID format)
   * @param body Array of permission codes to assign to the role
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification 1. Validate roleId exists and belongs to the
     *   current organization context 2. Retrieve the role from erp_hrm_roles
     *   table 3. Check role.is_builtin flag - if true, reject with 400 error 4.
     *   Validate all permission codes in request body against allowed
     *   permissions list: org:manage, employee:manage, employee:view,
     *   project:manage, project:view, time:manage, time:approve, time:view_all,
     *   report:view 5. Begin transaction: a. Delete all existing entries from
     *   erp_hrm_role_permissions where erp_hrm_role_id matches b. Insert new
     *   permission entries for each permission in request body c. Update
     *   role.updated_at timestamp 6. Commit transaction 7. Return the updated
     *   role with its new permission set
   *
   * Edge cases:
   * - Empty permissions array: clears all permissions (valid scenario for minimal access roles)
   * - Invalid permission code: reject with 400 error listing invalid codes
   * - Non-existent role: return 404 error
   * - Role from different organization: return 404 (not 403 to prevent enumeration)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async bulkUpdate(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("roleId")
    roleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IErpHrmRolePermission.IBulkUpdate,
  ): Promise<IErpHrmRole> {
    try {
      return await putErpHrmAdminRolesRoleIdPermissionsBulk({
        admin,
        roleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
