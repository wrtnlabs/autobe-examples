import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IErpHrmRole } from "../../../../api/structures/IErpHrmRole";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { deleteErpHrmAdminRolesRoleId } from "../../../../providers/deleteErpHrmAdminRolesRoleId";
import { postErpHrmAdminRoles } from "../../../../providers/postErpHrmAdminRoles";
import { postErpHrmAdminRolesValidate } from "../../../../providers/postErpHrmAdminRolesValidate";
import { putErpHrmAdminRolesRoleId } from "../../../../providers/putErpHrmAdminRolesRoleId";

@Controller("/erpHrm/admin/roles")
export class ErphrmAdminRolesController {
  /**
   * Create a custom role within the current organization.
   *
   * This operation allows organization owners and users with org:manage permission to create new custom roles. Custom roles define specific access levels for employees by combining a role name with one or more permissions.
   *
   * The role name must be unique within the organization. Available permissions include org:manage, employee:manage, employee:view, project:manage, project:view, time:manage, time:approve, time:view_all, and report:view.
   *
   * The created role is immediately available for assignment to employees within the same organization. Built-in roles (Owner, Manager, Employee) cannot be created through this endpoint.
   *
   * @param connection
   * @param body Custom role creation payload containing role name and permission codes
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification 1. Extract organization context from authenticated user session
   * 2. Validate user has org:manage permission in current organization
   * 3. Validate role name is provided and non-empty
   * 4. Validate permissions array is provided and contains at least one valid permission code
   * 5. Validate role name is unique within the organization (check erp_hrm_roles for existing name with same erp_hrm_organization_id and null deleted_at)
   * 6. Create role record in erp_hrm_roles with is_builtin=false
   * 7. Create role_permissions records in erp_hrm_role_permissions for each permission code
   * 8. Return the created role with its associated permissions
   * 9. Handle errors: duplicate name (409 Conflict), invalid permission code (400 Bad Request), missing permissions (400 Bad Request)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IErpHrmRole.ICreate,
  ): Promise<IErpHrmRole> {
    try {
      return await postErpHrmAdminRoles({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing custom role's name and permissions within the current organization.
   *
   * This operation allows organization owners to modify custom role details. The role name must be unique within the organization. Only custom roles (non-built-in) can be updated through this endpoint. Built-in roles (Owner, Manager, Employee) are protected from modification.
   *
   * The request must include the complete set of permissions to assign to the role. The previous permission set will be replaced entirely. Permissions are validated against the available permission codes before assignment.
   *
   * If the role has employees assigned to it, those assignments remain intact after the role is updated. The employee's permission scope will reflect the new role permissions on their next action.
   *
   * @param connection
   * @param roleId Unique identifier of the role to update (UUID format)
   * @param body Role update data including the new name and complete set of permission codes to assign
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Update the role identified by roleId with the provided details.
   *
   * 1. VALIDATION PHASE:
   *    - Verify roleId is a valid UUID format
   *    - Query erp_hrm_roles table to find role by id
   *    - Ensure the role belongs to the current organization context (from session)
   *    - Verify the role's is_builtin flag is FALSE — reject if true with error "Built-in roles cannot be modified"
   *    - Check role is not soft-deleted (deleted_at must be NULL)
   *    - Validate name uniqueness: no other role in the same organization can have the same name
   *    - Validate all permission codes in the request exist in the available permission set
   *
   * 2. UPDATE PHASE (within a database transaction):
   *    - Update the name field in erp_hrm_roles table
   *    - Update the updated_at timestamp
   *    - Delete all existing entries from erp_hrm_role_permissions for this role
   *    - Insert new entries into erp_hrm_role_permissions for each permission in the request
   *    - Set created_at and updated_at on new permission entries
   *
   * 3. RESPONSE PHASE:
   *    - Fetch the complete updated role with its rolePermissions relation
   *    - Return the full role object including all assigned permissions
   *
   * 4. ERROR HANDLING:
   *    - 404 Not Found: Role does not exist or does not belong to current organization
   *    - 400 Bad Request: Invalid name (empty, too long) or invalid permission codes
   *    - 403 Forbidden: Attempting to modify a built-in role
   *    - 409 Conflict: Role name already exists in organization
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":roleId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("roleId")
    roleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IErpHrmRole.IUpdate,
  ): Promise<IErpHrmRole> {
    try {
      return await putErpHrmAdminRolesRoleId({
        admin,
        roleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Archives a custom role within the organization by marking it as deleted.
   *
   * This operation soft deletes a custom role that was previously created within the organization. Only organization owners have permission to delete roles. The system enforces two critical restrictions: built-in roles (Owner, Manager, Employee) cannot be deleted under any circumstances, and roles with assigned active employees cannot be deleted until all employees are reassigned to other roles.
   *
   * Before deleting a role, the system verifies the role is not a built-in role and that no employees currently reference the role_id with an active status. If any employees are assigned to the role, the deletion request is rejected with a conflict error indicating employees must be reassigned first.
   *
   * Successful deletion sets the role's deleted_at timestamp, preserving the role record for historical reference and potential recovery. All associated role_permission records are preserved. Employee historical data and timesheets remain unaffected.
   *
   * @param connection
   * @param roleId Unique identifier of the role to delete
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification DELETE /roles/{roleId} - Erase a custom role from the organization
   *
   * 1. PATH PARAMETERS:
   *    - roleId (UUID): The unique identifier of the role to delete
   *
   * 2. VALIDATION RULES (in order):
   *    a) Retrieve role by roleId from erp_hrm_roles table
   *    b) If role not found → return 404 error
   *    c) If role.is_builtin === true → return 403 error with message 'Built-in roles cannot be deleted'
   *    d) Query erp_hrm_employees table for count where erp_hrm_role_id === roleId AND deleted_at IS NULL
   *    e) If employee count > 0 → return 409 conflict error with message 'Cannot delete role with assigned employees'
   *
   * 3. DELETE TRANSACTION:
   *    a) Begin database transaction
   *    b) Delete from erp_hrm_role_permissions where erp_hrm_role_id === roleId
   *    c) Delete from erp_hrm_roles where id === roleId
   *    d) Commit transaction
   *
   * 4. RESPONSE:
   *    - Success: 204 No Content (no response body)
   *    - Error cases return appropriate HTTP status codes with error messages
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":roleId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("roleId")
    roleId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteErpHrmAdminRolesRoleId({
        admin,
        roleId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Validate whether a role name is available for use in the current organization.
   *
   * This endpoint checks if a proposed role name meets all naming constraints before attempting creation. It validates that the name is unique within the organization and does not conflict with built-in role names. Built-in roles (Owner, Manager, Employee) are protected and cannot be duplicated.
   *
   * The validation checks include: name uniqueness within the organization scope, prevention of built-in role name conflicts, and proper character constraints. This operation is typically called before creating a custom role to provide immediate feedback to users.
   *
   * Errors returned indicate specific validation failures, allowing users to correct their input without attempting an invalid creation.
   *
   * @param connection
   * @param body Role name to validate for availability in the current organization
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query erp_hrm_roles table to check if a role with the given name already exists in the current organization context.
   *
   * Validate role name against the following rules:
   * 1. Check if role name matches any built-in role name (case-insensitive): 'owner', 'manager', 'employee'
   * 2. Check if role name already exists in the current organization (case-insensitive uniqueness)
   * 3. Return all validation errors found
   *
   * The validation should be case-insensitive when comparing names. Return a result object with isValid boolean and an array of error messages for any validation failures.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("validate")
  public async validate(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IErpHrmRole.IValidationRequest,
  ): Promise<IErpHrmRole.IValidationResult> {
    try {
      return await postErpHrmAdminRolesValidate({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
