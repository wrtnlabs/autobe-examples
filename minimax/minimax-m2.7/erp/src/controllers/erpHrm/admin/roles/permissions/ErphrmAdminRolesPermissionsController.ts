import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IErpHrmRole } from "../../../../../api/structures/IErpHrmRole";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { putErpHrmAdminRolesRoleIdPermissions } from "../../../../../providers/putErpHrmAdminRolesRoleIdPermissions";

@Controller("/erpHrm/admin/roles/:roleId/permissions")
export class ErphrmAdminRolesPermissionsController {
  /**
   * Replace all permissions assigned to a specific role with a new set of permissions.
   *
   * This endpoint allows organization owners with org:manage permission to modify the permission set of custom roles within their organization. The caller must have the org:manage permission to invoke this operation. The operation performs a complete replacement: all existing permissions are removed and the new permission array is assigned.
   *
   * The role must belong to the current organization context. Accessing a role from a different organization returns 404 (not 403) to prevent enumeration attacks. Built-in roles (Owner, Manager, Employee) cannot have their permissions modified regardless of user permissions - requests to modify built-in role permissions return 403 Forbidden.
   *
   * Permission codes must be valid values from the allowed set: org:manage, employee:manage, employee:view, project:manage, project:view, time:manage, time:approve, time:view_all, report:view. Invalid permission codes result in validation errors.
   *
   * The erp_hrm_roles table stores role definitions with is_builtin flag indicating system roles. The erp_hrm_role_permissions junction table links roles to their permission codes using the erp_hrm_role_id foreign key. Role names must be unique within an organization scope as enforced by the unique constraint on [erp_hrm_organization_id, name].
   *
   * @param connection
   * @param roleId Unique identifier of the role whose permissions to update
   * @param body Array of permission codes to assign to the role
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification 1. Extract organization context from authenticated session
   * 2. Validate roleId exists and belongs to current organization
   * 3. Check if role is_builtin = true; if so, return 403 Forbidden with message about built-in role protection
   * 4. Begin database transaction
   * 5. Delete all existing records from erp_hrm_role_permissions where erp_hrm_role_id = roleId
   * 6. Validate all permission codes in request body are valid permission strings
   * 7. Insert new records into erp_hrm_role_permissions for each permission code
   * 8. Commit transaction
   * 9. Query and return the updated role with its rolePermissions relation
   *
   * Edge cases:
   * - Role not found: return 404
   * - Role belongs to different organization: return 404 (not 403 to prevent enumeration)
   * - Empty permissions array: allowed (creates role with no permissions)
   * - Duplicate permission codes in request: deduplicate before insert
   * - Invalid permission code: return 400 with list of invalid codes
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("roleId")
    roleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IErpHrmRole.IPermissionUpdate,
  ): Promise<IErpHrmRole> {
    try {
      return await putErpHrmAdminRolesRoleIdPermissions({
        admin,
        roleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
