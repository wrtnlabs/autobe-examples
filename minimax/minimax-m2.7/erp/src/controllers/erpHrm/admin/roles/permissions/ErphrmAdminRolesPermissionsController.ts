import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IErpHrmRolePermission } from "../../../../../api/structures/IErpHrmRolePermission";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { deleteErpHrmAdminRolesRoleIdPermissionsPermissionId } from "../../../../../providers/deleteErpHrmAdminRolesRoleIdPermissionsPermissionId";
import { postErpHrmAdminRolesRoleIdPermissions } from "../../../../../providers/postErpHrmAdminRolesRoleIdPermissions";
import { putErpHrmAdminRolesRoleIdPermissionsPermissionId } from "../../../../../providers/putErpHrmAdminRolesRoleIdPermissionsPermissionId";

@Controller("/erpHrm/admin/roles/:roleId/permissions")
export class ErphrmAdminRolesPermissionsController {
  /**
   * Assign a permission to a role within an organization.
   *
   * This operation adds a new permission to an existing role. The permission code must be one of the available system permissions (org:manage, employee:manage, employee:view, project:manage, project:view, time:manage, time:approve, time:view_all, report:view). Once assigned, the permission takes effect immediately for all employees holding that role.
   *
   * Built-in roles (Owner, Manager, Employee) cannot have their permission sets modified through this endpoint. Custom roles created by organization owners can be assigned any combination of permissions.
   *
   * If the same permission is already assigned to the role, the system returns a conflict error.
   *
   * @param connection
   * @param roleId Unique identifier of the role to assign permission to (global scope)
   * @param body Permission assignment details including the permission code to assign
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification Verify the role exists and belongs to the current
     *   organization. Validate the permission code against the allowed
     *   permission list. Check if the permission is already assigned to this
     *   role (return conflict if duplicate). Create a new record in
     *   erp_hrm_role_permissions with the role ID and permission code. Return
     *   the created role-permission association.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async assignPermission(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("roleId")
    roleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IErpHrmRolePermission.ICreate,
  ): Promise<IErpHrmRolePermission> {
    try {
      return await postErpHrmAdminRolesRoleIdPermissions({
        admin,
        roleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Assign a permission to an existing role within an organization.
   *
   * This endpoint attaches a permission to a custom role, granting employees with that role the ability to perform actions associated with the permission. Permissions include org:manage, employee:manage, employee:view, project:manage, project:view, time:manage, time:approve, time:view_all, and report:view.
   *
   * Built-in roles (Owner, Manager, Employee) cannot have their permissions modified. Custom roles must have at least one permission at all times.
   *
   * This operation is idempotent - assigning a permission that is already attached returns success without creating duplicates, as enforced by the composite unique constraint on (role_id, permission).
   *
   * @param connection
   * @param roleId UUID of the role to assign the permission to
   * @param permissionId Permission code to assign (e.g., org:manage, employee:manage)
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification Assign a permission to a role by creating a
     *   record in erp_hrm_role_permissions table.
   *
   * 1. Validate roleId exists in erp_hrm_roles and belongs to the current organization context.
   * 2. Verify the role is not a built-in role (is_builtin must be false). If built-in, return 403 Forbidden with message 'Built-in roles cannot have permissions modified'.
   * 3. Validate permissionId is a valid permission code from the allowed set: org:manage, employee:manage, employee:view, project:manage, project:view, time:manage, time:approve, time:view_all, report:view. If invalid, return 400 Bad Request.
   * 4. Check if the permission is already assigned to the role. If already assigned, return 200 OK with the existing record (idempotent behavior).
   * 5. Create new record in erp_hrm_role_permissions with: id (UUID), erp_hrm_role_id (from path), permission (from path), created_at, updated_at.
   * 6. Return 201 Created with the created role permission record.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":permissionId")
  public async assign(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("roleId")
    roleId: string & tags.Format<"uuid">,
    @TypedParam("permissionId")
    permissionId: string,
  ): Promise<IErpHrmRolePermission> {
    try {
      return await putErpHrmAdminRolesRoleIdPermissionsPermissionId({
        admin,
        roleId,
        permissionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Remove a permission from a custom role within the organization.
   *
   * This endpoint allows organization owners to revoke a specific permission from a custom role. The operation deletes a record from the erp_hrm_role_permissions junction table, unlinking the specified permission from the role.
   *
   * The role must be a custom role (erp_hrm_roles.is_builtin = false). Built-in roles (Owner, Manager, Employee) cannot have their permissions modified or removed. Attempting to modify a built-in role results in rejection with an error indicating that built-in roles are protected.
   *
   * Permissions are referenced by their code string (e.g., 'org:manage', 'employee:manage', 'project:view'). Only permissions currently assigned to the role can be removed. Attempting to remove a permission that is not assigned to the role results in a not-found error.
   *
   * This operation affects the role's permission set immediately. Employees assigned to this role will lose access to operations governed by the removed permission.
   *
   * @param connection
   * @param roleId UUID of the role to remove the permission from
   * @param permissionId Permission code string to remove from the role (e.g., 'org:manage', 'employee:view', 'project:manage')
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification Extract roleId from path and permissionId from
     *   path (permission code string).
   *
   * Query erp_hrm_roles table to verify the role exists and belongs to the caller's organization. Return 404 if role not found or belongs to different organization.
   *
   * Check role.is_builtin field. If true, reject with 400 error indicating built-in roles cannot be modified.
   *
   * Query erp_hrm_role_permissions table to find the permission record where erp_hrm_role_id matches roleId AND permission matches permissionId. If not found, return 404 error indicating permission is not assigned to this role.
   *
   * Delete the found erp_hrm_role_permissions record from the database.
   *
   * Return 200 with the deleted permission information including the permission code.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":permissionId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("roleId")
    roleId: string & tags.Format<"uuid">,
    @TypedParam("permissionId")
    permissionId: string,
  ): Promise<void> {
    try {
      return await deleteErpHrmAdminRolesRoleIdPermissionsPermissionId({
        admin,
        roleId,
        permissionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
