import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IErpHrmBudgetAnalysis } from "../../../../../api/structures/IErpHrmBudgetAnalysis";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { patchErpHrmAdminAnalyticsBudget } from "../../../../../providers/patchErpHrmAdminAnalyticsBudget";

@Controller("/erpHrm/admin/analytics/budget")
export class ErphrmAdminAnalyticsBudgetController {
  /**
   * Retrieve budget utilization analytics across all projects with configured budget hours in the organization.
   *
   * This endpoint aggregates budget data by querying all projects with budget_hours defined and calculating actual hours logged against them. For each project, it returns the budget hours, actual hours consumed, and the utilization percentage. Projects without budget hours configured are automatically excluded from the results.
   *
   * The utilization percentage indicates budget consumption status: under 80% is considered within budget, 80-100% indicates approaching budget, and over 100% indicates the project has exceeded its allocated hours.
   *
   * This operation requires report:view permission and returns data scoped to the authenticated user's organization context.
   *
   * @param connection
   * @param body Optional filter criteria for budget analytics including specific project IDs to include
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification Query erp_hrm_projects table filtered to projects
     *   that belong to the authenticated user's organization and have
     *   budget_hours defined (not null and greater than 0).
   *
   * For each project, calculate actual hours by:
   * 1. Joining erp_hrm_timelogs on erp_hrm_project_id
   * 2. Summing duration_minutes and converting to hours (divide by 60)
   * 3. Grouping by project_id
   *
   * Calculate utilization percentage for each project:
   * - utilization = (actual_hours / budget_hours) * 100
   * - Round to one decimal place
   *
   * Determine budget status:
   * - 'within_budget' when utilization < 80
   * - 'approaching_budget' when 80 <= utilization <= 100
   * - 'over_budget' when utilization > 100
   *
   * If projectIds filter is provided in request body, further filter projects by those IDs.
   *
   * Return projects ordered by utilization percentage descending (projects closest to or exceeding budget first).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async search(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IErpHrmBudgetAnalysis.IRequest,
  ): Promise<IErpHrmBudgetAnalysis.IResult> {
    try {
      return await patchErpHrmAdminAnalyticsBudget({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
