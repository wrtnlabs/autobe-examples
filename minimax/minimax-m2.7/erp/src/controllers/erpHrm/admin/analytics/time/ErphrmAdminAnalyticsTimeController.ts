import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IErpHrmTimelog } from "../../../../../api/structures/IErpHrmTimelog";
import { IPageIErpHrmTimelog } from "../../../../../api/structures/IPageIErpHrmTimelog";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { patchErpHrmAdminAnalyticsTime } from "../../../../../providers/patchErpHrmAdminAnalyticsTime";

@Controller("/erpHrm/admin/analytics/time")
export class ErphrmAdminAnalyticsTimeController {
  /**
   * Generate a time analytics report with aggregated hours data.
   *
   * This endpoint provides comprehensive time tracking analytics for the organization. Users with report:view permission can generate reports showing total hours logged within a specified date range, with flexible grouping and filtering options.
   *
   * The report displays aggregated time data grouped by the selected dimension (employee, project, or task). Each grouping includes total hours, billable hours subtotal, and non-billable hours subtotal. When grouping by employee, the report also includes employee details such as department and position.
   *
   * Filtering capabilities allow narrowing results to specific employees, projects, or billable status. The response includes both detailed breakdowns and summary totals for quick overview.
   *
   * @param connection
   * @param body Time analytics search criteria including date range, filters, grouping, and pagination parameters.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query the erp_hrm_timelogs table with the provided date range filter.
   *
   * Join erp_hrm_timelogs with erp_hrm_employees to get employee details (name, department, position). Join with erp_hrm_projects to get project details (name, color). Join with erp_hrm_tasks optionally for task-based grouping.
   *
   * Apply date range filter: timelogs where date >= start_date AND date <= end_date.
   *
   * Apply optional filters:
   * - employee_id: filter by specific employee
   * - project_id: filter by specific project
   * - task_id: filter by specific task
   * - billable: true = billable only, false = non-billable only, null = all
   *
   * Group results by the specified group_by field:
   * - 'employee': group by erp_hrm_employee_id, include employee details
   * - 'project': group by erp_hrm_project_id, include project details
   * - 'task': group by erp_hrm_task_id, include task details
   *
   * For each group, calculate:
   * - total_minutes: SUM(duration_minutes)
   * - billable_minutes: SUM(duration_minutes) WHERE billable = true
   * - non_billable_minutes: SUM(duration_minutes) WHERE billable = false
   * - timelog_count: COUNT(*)
   *
   * Sort by total_hours descending within each group.
   *
   * Return paginated results with pagination parameters.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IErpHrmTimelog.IRequest,
  ): Promise<IPageIErpHrmTimelog.ISummary> {
    try {
      return await patchErpHrmAdminAnalyticsTime({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
