import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IErpHrmOrganization } from "../../../../api/structures/IErpHrmOrganization";
import { IPageIErpHrmOrganization } from "../../../../api/structures/IPageIErpHrmOrganization";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { deleteErpHrmAdminOrganizationsOrganizationId } from "../../../../providers/deleteErpHrmAdminOrganizationsOrganizationId";
import { getErpHrmAdminOrganizationsOrganizationId } from "../../../../providers/getErpHrmAdminOrganizationsOrganizationId";
import { patchErpHrmAdminOrganizations } from "../../../../providers/patchErpHrmAdminOrganizations";
import { postErpHrmAdminOrganizations } from "../../../../providers/postErpHrmAdminOrganizations";
import { putErpHrmAdminOrganizationsOrganizationId } from "../../../../providers/putErpHrmAdminOrganizationsOrganizationId";

@Controller("/erpHrm/admin/organizations")
export class ErphrmAdminOrganizationsController {
  /**
   * Create a new organization and register the authenticated user as its owner.
   *
   * This endpoint creates a new organization tenant within the platform. The authenticated user who creates the organization automatically becomes the organization owner with full administrative privileges, including the ability to manage organization settings, employees, projects, and roles.
   *
   * Upon successful creation, the system automatically initializes three built-in roles for the organization: Owner, Manager, and Employee. These roles provide the foundation for role-based access control within the newly created organization.
   *
   * The organization requires fundamental configuration including a display name, currency for billing and reporting purposes, and timezone settings for time tracking and scheduling. An optional description may be provided to explain the organization's purpose or industry.
   *
   * The organization name must be unique across the entire platform to ensure clear identification when users belong to multiple organizations. Logo URI, if provided, should be a valid URL pointing to an image file.
   *
   * This operation is typically called during the initial sign-up flow when a new user creates their first organization. Users may subsequently join additional organizations through invitations.
   *
   * @param connection
   * @param body Organization creation payload containing the organization name, configuration settings, and optional details.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Handle organization creation within a database transaction to ensure atomicity.
   *
   * 1. Validate incoming request body fields:
   *    - name: required, non-empty string, max 255 characters
   *    - currency: required, valid 3-letter ISO currency code (e.g., USD, EUR, KRW)
   *    - timezone: required, valid IANA timezone string (e.g., Asia/Seoul, America/New_York)
   *    - fiscal_start_month: required, integer 1-12 representing starting month of fiscal year
   *    - description: optional string, max 1000 characters
   *    - logo_uri: optional, must be valid URL format if provided
   *
   * 2. Verify organization name uniqueness across the entire platform. If a duplicate name exists, return a 409 Conflict error with appropriate message.
   *
   * 3. Retrieve the authenticated member ID from the session context.
   *
   * 4. Insert new organization record:
   *    - Generate UUID for id field
   *    - Set owner_id to authenticated member's ID
   *    - Set created_at and updated_at to current timestamp
   *    - Store all provided configuration fields
   *
   * 5. Create three built-in role records for the organization:
   *    - Owner role with all permissions
   *    - Manager role with management permissions (employee:manage, project:manage, time:approve, time:view_all, report:view)
   *    - Employee role with basic permissions (project:view, time:view_all for own data)
   *
   * 6. Create initial employee record linking the owner to the organization with the Owner role assigned.
   *
   * 7. Return the created organization entity with HTTP 201 status code.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IErpHrmOrganization.ICreate,
  ): Promise<IErpHrmOrganization> {
    try {
      return await postErpHrmAdminOrganizations({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a filtered and paginated list of organizations the authenticated user belongs to.
   *
   * This endpoint returns all organizations where the current user has an employee record, enabling them to view and switch between their organizational contexts. The list includes organization identity attributes such as name, description, and logo.
   *
   * Supports pagination with configurable page sizes. Users with membership in multiple organizations can filter by name to quickly find specific organizations. Results are scoped to the authenticated user based on their employee records.
   *
   * The organization context determines data isolation boundaries for all subsequent operations.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering organizations
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query erp_hrm_organizations table joined with erp_hrm_employees to find all organizations where the authenticated user has an active employee record.
   *
   * Apply search filters on organization name (partial match).
   * Return cursor-based pagination for large result sets.
   * Include organization identity attributes: id, name, description, logo_uri, currency, timezone.
   * Order results by created_at descending (most recent first).
   * Enforce that results only include organizations the user belongs to.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IErpHrmOrganization.IRequest,
  ): Promise<IPageIErpHrmOrganization.ISummary> {
    try {
      return await patchErpHrmAdminOrganizations({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single organization by its unique identifier.
   *
   * This endpoint returns the complete organization entity including its identity attributes (name, description, logo), regional and fiscal settings (currency, timezone, fiscal start month), and ownership information. The organization serves as the primary tenant container in the multi-tenant platform, providing strict data isolation boundaries.
   *
   * The response includes timestamps for creation and last modification, allowing consumers to understand the organization's lifecycle. Organization data is scoped to the currently selected organization context, ensuring users can only access organizations they belong to.
   *
   * @param connection
   * @param organizationId Unique identifier of the organization (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query erp_hrm_organizations table by the provided organizationId UUID. Return the full organization record including all columns: id, owner_id, name, description, logo_uri, currency, timezone, fiscal_start_month, created_at, updated_at. Join with erp_hrm_members table to include owner details (name, email) if needed. Enforce organization context isolation - reject if user does not belong to this organization.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":organizationId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("organizationId")
    organizationId: string & tags.Format<"uuid">,
  ): Promise<IErpHrmOrganization> {
    try {
      return await getErpHrmAdminOrganizationsOrganizationId({
        admin,
        organizationId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an organization's settings and configuration.
   *
   * This endpoint allows organization owners and users with org:manage permission to modify their organization's identity attributes and operational settings. Users can update the organization name, description, logo, currency, timezone, and fiscal year start month. Only the organization owner or users with org:manage permission have authorization to perform this operation.
   *
   * When updating currency or timezone, the system records the change in the activity log for audit purposes. The fiscal start month must be a valid month number between 1 and 12, determining when the organization's fiscal year begins for reporting purposes.
   *
   * The organization ID in the path must belong to an organization where the authenticated user is either the owner or has org:manage permission. Users cannot modify organizations they do not own or lack permission for.
   *
   * @param connection
   * @param organizationId Unique identifier of the organization to update.
   * @param body Organization update payload containing the fields to modify.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Handle PUT request to update organization settings.
   *
   * **Input Validation**:
   * - Validate organizationId is a valid UUID format
   * - Verify the authenticated user is the organization owner (owner_id matches current user)
   * - Validate name: required, non-empty string, max 255 characters
   * - Validate description: optional, max 1000 characters
   * - Validate logo_uri: optional, valid URL format, max 80000 characters
   * - Validate currency: required, valid ISO 4217 currency code (e.g., USD, EUR, KRW)
   * - Validate timezone: required, valid IANA timezone string (e.g., Asia/Seoul, America/New_York)
   * - Validate fiscal_start_month: required, integer between 1 and 12
   *
   * **Database Operation**:
   * - Query erp_hrm_organizations table where id equals organizationId
   * - Verify the returned organization exists (404 if not found)
   * - Verify the owner_id matches the authenticated user's member ID (403 if not owner)
   * - Update only the fields provided in the request body
   * - Set updated_at to current timestamp
   * - Return the updated organization record
   *
   * **Business Rules**:
   * - Organization name uniqueness is NOT enforced at the database level (application-level constraint)
   * - Logo URI can be cleared by passing null
   * - Currency changes affect future reports but not historical data
   * - Timezone changes apply immediately to time tracking display
   * - Fiscal start month change affects future period calculations
   *
   * **Error Handling**:
   * - 400: Invalid field values or validation failures
   * - 401: Not authenticated
   * - 403: Not the organization owner
   * - 404: Organization not found
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":organizationId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("organizationId")
    organizationId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IErpHrmOrganization.IUpdate,
  ): Promise<IErpHrmOrganization> {
    try {
      return await putErpHrmAdminOrganizationsOrganizationId({
        admin,
        organizationId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently deletes an organization and all its associated data.
   *
   * This operation can only be performed by the organization owner. Before deletion is permitted, the system verifies that all pending timesheets have been resolved (approved or rejected) and that no active employee contracts exist.
   *
   * When deletion succeeds, the system permanently removes all employees, projects, tasks, timelogs, timesheets, departments, roles, activity logs, and reports associated with the organization. The owner's user account remains intact and is preserved; the account is no longer associated with the deleted organization.
   *
   * If the deletion fails due to unresolved timesheets, the system returns an error indicating that all timesheets must be approved or rejected before deletion. If active contracts exist, the system returns an error indicating that all active employee contracts must be ended before deletion.
   *
   * Deletion is irreversible; there is no mechanism to recover deleted organization data.
   *
   * @param connection
   * @param organizationId Unique identifier of the organization to delete (UUID)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Validate that the requesting user is the owner of the organization by comparing the authenticated user ID with the owner_id field in erp_hrm_organizations table. If not the owner, return 403 Forbidden.
   *
   * Verify the organization exists by querying erp_hrm_organizations with the provided organizationId (UUID). If not found, return 404 Not Found.
   *
   * Check for pending timesheets: Query erp_hrm_timesheets for any records belonging to employees of this organization where status is 'submitted'. If any exist, return 400 Bad Request with error message indicating pending timesheets must be resolved first.
   *
   * Check for active contracts: Query erp_hrm_contracts joined with erp_hrm_employees where end_date is NULL and employee belongs to this organization. If any active contracts exist, return 400 Bad Request with error message indicating all contracts must be ended before deletion.
   *
   * If all preconditions pass, begin database transaction to:
   * 1. Delete all timelogs belonging to organization's employees (via erp_hrm_employees)
   * 2. Delete all timesheet-timelog associations
   * 3. Delete all timesheets belonging to organization's employees
   * 4. Delete all timers belonging to organization's employees
   * 5. Delete all task histories for tasks in organization's projects
   * 6. Delete all tasks belonging to organization's projects
   * 7. Delete all project members for organization's projects
   * 8. Delete all projects belonging to the organization
   * 9. Delete all invitations for the organization
   * 10. Delete all employee contracts belonging to organization's employees
   * 11. Delete all employees of the organization
   * 12. Delete all departments of the organization
   * 13. Delete all role permissions for organization's roles
   * 14. Delete all roles of the organization
   * 15. Delete all activity logs for the organization
   * 16. Delete all reports for the organization
   * 17. Delete the organization record
   *
   * On transaction success, return 204 No Content. On any failure, rollback transaction and return appropriate error response.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":organizationId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("organizationId")
    organizationId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteErpHrmAdminOrganizationsOrganizationId({
        admin,
        organizationId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
