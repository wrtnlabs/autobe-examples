import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IErpHrmReportParameter } from "../../../../../../api/structures/IErpHrmReportParameter";
import { AdminAuth } from "../../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../../decorators/payload/AdminPayload";
import { getErpHrmAdminOrganizationsOrganizationIdReportsReportIdParameters } from "../../../../../../providers/getErpHrmAdminOrganizationsOrganizationIdReportsReportIdParameters";
import { putErpHrmAdminOrganizationsOrganizationIdReportsReportIdParameters } from "../../../../../../providers/putErpHrmAdminOrganizationsOrganizationIdReportsReportIdParameters";

@Controller(
  "/erpHrm/admin/organizations/:organizationId/reports/:reportId/parameters",
)
export class ErphrmAdminOrganizationsReportsParametersController {
  /**
   * Retrieve the filter parameters for a specific report within an organization.
   *
   * This endpoint returns the detailed parameters used to generate a report, including the date range filter (start_date and end_date), optional filtering criteria for specific employees, projects, or tasks, the billable status filter, and the grouping preference (employee, project, or task).
   *
   * Each report in erp_hrm_reports has exactly one associated set of parameters in erp_hrm_report_parameters, stored in a 1:1 relationship. This endpoint retrieves that parameter set for the specified report.
   *
   * The report must belong to the specified organization, ensuring data isolation between organizations. Users must possess the report:view permission to access this endpoint. If the report does not exist or does not belong to the specified organization, the system returns a not found error.
   *
   * @param connection
   * @param organizationId The organization's unique identifier (global scope)
   * @param reportId The report's unique identifier
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification 1. Validate organizationId matches the user's current organization context (data isolation enforcement)
   * 2. Validate reportId corresponds to an existing report in erp_hrm_reports
   * 3. Verify the report's erp_hrm_organization_id matches the provided organizationId
   * 4. Query erp_hrm_report_parameters table with erp_hrm_report_id = reportId
   * 5. Return the parameter record including:
   *    - Date range: start_date, end_date
   *    - Optional filters: employee_id, project_id, task_id
   *    - Billable filter: billable (true/false/null)
   *    - Grouping preference: group_by ('employee', 'project', or 'task')
   *    - Timestamps: created_at, updated_at
   * 6. If no parameters exist for the report, return null or appropriate response
   * 7. Authorization check: user must have report:view permission in the organization
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("organizationId")
    organizationId: string & tags.Format<"uuid">,
    @TypedParam("reportId")
    reportId: string & tags.Format<"uuid">,
  ): Promise<IErpHrmReportParameter> {
    try {
      return await getErpHrmAdminOrganizationsOrganizationIdReportsReportIdParameters(
        {
          admin,
          organizationId,
          reportId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update the filter parameters for a specific report within an organization.
   *
   * This endpoint allows authorized users to modify the date range, employee/project/task filters, billable status, and grouping preferences for an existing report. The report must belong to the specified organization.
   *
   * The system enforces strict data isolation - users can only update report parameters for reports within their currently selected organization context. Users must possess the report:view permission to access reports.
   *
   * Report parameters define how the report data is filtered and grouped: start_date and end_date establish the reporting period, employee_id/project_id/task_id provide optional filtering to specific entities, billable filters time entries by billable status, and group_by determines how data is aggregated in the report output.
   *
   * If the associated report does not exist or belongs to a different organization, the request will be rejected with an appropriate error.
   *
   * @param connection
   * @param organizationId UUID of the organization that owns the report (global scope)
   * @param reportId UUID of the report whose parameters are being updated
   * @param body Updated filter parameters including date range, entity filters, and grouping preferences
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification 1. Validate organizationId matches the user's current organization context
   * 2. Validate the user has report:view permission
   * 3. Retrieve the report by reportId and verify it belongs to the organization
   * 4. Validate all provided parameter fields according to business rules:
   *    - start_date must be before end_date
   *    - employee_id, project_id, task_id must belong to the organization if provided
   *    - group_by must be one of: 'employee', 'project', 'task'
   *    - billable can be true, false, or null
   * 5. Update the associated erp_hrm_report_parameters record with provided fields
   * 6. Set updated_at timestamp to current time
   * 7. Return the updated parameter object with its full details
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("organizationId")
    organizationId: string & tags.Format<"uuid">,
    @TypedParam("reportId")
    reportId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IErpHrmReportParameter.IUpdate,
  ): Promise<IErpHrmReportParameter> {
    try {
      return await putErpHrmAdminOrganizationsOrganizationIdReportsReportIdParameters(
        {
          admin,
          organizationId,
          reportId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
