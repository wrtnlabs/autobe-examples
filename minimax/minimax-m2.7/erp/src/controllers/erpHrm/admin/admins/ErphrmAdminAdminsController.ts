import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IErpHrmAdmin } from "../../../../api/structures/IErpHrmAdmin";
import { IPageIErpHrmAdmin } from "../../../../api/structures/IPageIErpHrmAdmin";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getErpHrmAdminAdminsAdminId } from "../../../../providers/getErpHrmAdminAdminsAdminId";
import { patchErpHrmAdminAdmins } from "../../../../providers/patchErpHrmAdminAdmins";

@Controller("/erpHrm/admin/admins")
export class ErphrmAdminAdminsController {
  /**
   * Retrieve a filtered and paginated list of admin accounts with elevated privileges.
   *
   * This endpoint allows users with appropriate permissions to search and list admin accounts in the system. Admin accounts have elevated privileges for organization management, employee oversight, and system administration.
   *
   * The operation supports filtering by email (partial match using ILIKE pattern), display name (partial match), and phone number (exact match). Results are returned in a paginated format with configurable page size and cursor-based pagination using the id field.
   *
   * Security: Access is restricted to authenticated admin users with appropriate permissions. Regular member accounts cannot access this endpoint. All admin actions are recorded in the activity log.
   *
   * Relationship to database: Queries the erp_hrm_admins table containing administrator accounts with fields including email (unique identifier), display_name, avatar_uri, phone, and timestamps (created_at, updated_at). No soft delete or status fields exist in this table.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering admin accounts
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query the erp_hrm_admins table with the following implementation:
   *
   * 1. Filter by email using ILIKE pattern matching if email parameter is provided
   * 2. Filter by display_name using ILIKE pattern matching if displayName parameter is provided
   * 3. Filter by phone exact match if phone parameter is provided
   * 4. Apply cursor-based pagination using id field for efficient scrolling
   * 5. Return results ordered by created_at descending by default
   * 6. Include total count in response metadata
   * 7. Validate pagination parameters (page size between 1-100)
   * 8. Reject request if user does not have admin privileges
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IErpHrmAdmin.IRequest,
  ): Promise<IPageIErpHrmAdmin.ISummary> {
    try {
      return await patchErpHrmAdminAdmins({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific administrator account by its unique identifier.
   *
   * This endpoint retrieves detailed information for a single admin account within the system. Administrators have elevated privileges for organization management, including full access to organization settings, employee management, project oversight, and time tracking approvals.
   *
   * The response includes the admin's authentication email, display name, profile avatar, phone contact, and account timestamps. The password hash is intentionally excluded from the response for security reasons.
   *
   * This operation is typically used by system administrators to view admin account details, verify account information, or retrieve data for administrative dashboards. All admin accounts exist in a global namespace separate from regular member accounts.
   *
   * @param connection
   * @param adminId Unique identifier of the admin account to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query the erp_hrm_admins table using the provided adminId as the primary key lookup. Return the matching admin record with all fields except password_hash. If no admin exists with the given ID, return a 404 error response. Ensure the response does not expose the password_hash field under any circumstances.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":adminId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
  ): Promise<IErpHrmAdmin> {
    try {
      return await getErpHrmAdminAdminsAdminId({
        admin,
        adminId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
