import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IErpHrmProject } from "../../../../api/structures/IErpHrmProject";
import { IPageIErpHrmProject } from "../../../../api/structures/IPageIErpHrmProject";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { deleteErpHrmAdminProjectsProjectId } from "../../../../providers/deleteErpHrmAdminProjectsProjectId";
import { getErpHrmAdminProjectsProjectId } from "../../../../providers/getErpHrmAdminProjectsProjectId";
import { patchErpHrmAdminProjects } from "../../../../providers/patchErpHrmAdminProjects";
import { postErpHrmAdminProjects } from "../../../../providers/postErpHrmAdminProjects";
import { putErpHrmAdminProjectsProjectId } from "../../../../providers/putErpHrmAdminProjectsProjectId";

@Controller("/erpHrm/admin/projects")
export class ErphrmAdminProjectsController {
  /**
   * Create a new project within the current organization.
   *
   * This endpoint creates a project that serves as a work container for organizing time tracking and task management. Projects are scoped to the organization determined by the user's session context.
   *
   * The project name must be unique within the organization (case-insensitive comparison). If a project with the same name already exists in the organization, the creation will fail with a conflict error.
   *
   * By default, new projects are created with status 'active', allowing immediate time logging. Projects can be archived or completed later to prevent new timelogs while preserving existing data.
   *
   * The color code is required for UI visual differentiation across project lists and dashboards. Use a valid hex color format such as #FF5733 or #4A90E2.
   *
   * @param connection
   * @param body Project creation data including name, color code, optional description, status, budget hours, and date boundaries
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Create a new project in the database.
   *
   * 1. Extract organization context from authenticated session
   * 2. Validate request body:
   *    - name: required, non-empty string, max 255 characters
   *    - color: required, valid hex color format (#RRGGBB)
   *    - status: optional, defaults to 'active'
   *    - description: optional, max 1000 characters
   *    - budget_hours: optional, positive number if provided
   *    - start_date: optional, valid ISO datetime
   *    - end_date: optional, valid ISO datetime, must be >= start_date if both provided
   * 3. Check for name uniqueness within the organization (case-insensitive)
   * 4. Insert project record with:
   *    - erp_hrm_organization_id from session
   *    - Auto-generate UUID for id
   *    - Auto-set created_at and updated_at to current timestamp
   * 5. Return created project entity
   * 6. On duplicate name conflict: return 409 Conflict with message
   * 7. On validation failure: return 400 Bad Request with field-specific errors
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IErpHrmProject.ICreate,
  ): Promise<IErpHrmProject> {
    try {
      return await postErpHrmAdminProjects({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a filtered and paginated list of projects within the organization.
   *
   * This operation provides search capabilities including partial name matching and status filtering. Status filter supports exact matching for active, archived, or completed projects.
   *
   * Supports cursor-based pagination with configurable page sizes. Response includes project summary information optimized for list displays including name, color, status, and budget hours.
   *
   * Requires project:view permission to access project listings. All results are scoped to the authenticated user's organization context.
   *
   * @param connection
   * @param body Search criteria including optional name filter, status filter, and pagination parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query erp_hrm_projects table with organization context filtering.
   *
   * Apply optional name filter with partial match (case-insensitive) when name parameter is provided.
   * Apply optional status filter with exact match when status parameter is provided. When status is not provided, default to active status filter.
   * Supported status values: active, archived, completed.
   *
   * Return results ordered by created_at descending (newest first).
   * Apply cursor-based pagination using pageSize and pageCursor parameters.
   *
   * Join with organization data to verify project belongs to authenticated user's organization.
   *
   * Include computed fields: total_timelogs_count for budget utilization display.
   *
   * Validate all filter values against allowed enum values. Return empty list (not error) when no projects match filter criteria.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IErpHrmProject.IRequest,
  ): Promise<IPageIErpHrmProject.ISummary> {
    try {
      return await patchErpHrmAdminProjects({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific project by its unique identifier.
   *
   * This endpoint returns the complete project record including its name, description, color code for UI display, current status, budget hours, and planned date range. The response includes all metadata such as creation and update timestamps.
   *
   * Project data is strictly isolated within the requesting user's organization context. Users must have the project:view permission to access project information. The project status indicates whether it actively receives timelogs (active), has been frozen (archived), or has finished work (completed).
   *
   * @param connection
   * @param projectId Unique identifier of the project to retrieve (UUID format, scoped to organization)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query the erp_hrm_projects table filtering by the provided projectId.
   *
   * Validate that the project belongs to the user's current organization context (erp_hrm_organization_id match).
   *
   * If the project does not exist or belongs to a different organization, return a 404 error.
   *
   * Return all project fields: id, erp_hrm_organization_id, name, description, color, status, budget_hours, start_date, end_date, created_at, updated_at.
   *
   * No additional joins required for the base project retrieval.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":projectId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("projectId")
    projectId: string & tags.Format<"uuid">,
  ): Promise<IErpHrmProject> {
    try {
      return await getErpHrmAdminProjectsProjectId({
        admin,
        projectId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing project's attributes.
   *
   * This endpoint allows authorized users with project:manage permission to modify any project attribute within their organization. Users can update the project name, description, color code for UI display, status lifecycle state, budget hours for tracking, and optional start/end dates for planning.
   *
   * The project name must be unique within the organization. Status transitions follow specific rules: projects can move from active to archived or completed, but archived projects cannot receive new timelogs. Only projects without associated timelogs can be deleted through separate operations.
   *
   * All modifications are scoped to the organization context established during authentication. Attempting to update a project from another organization results in a permission denied error.
   *
   * @param connection
   * @param projectId Unique identifier of the project to update (UUID format, global scope)
   * @param body Project update payload containing the fields to modify.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification 1. Validate the projectId path parameter is a valid UUID format.
   * 2. Retrieve the current project record from erp_hrm_projects table by projectId.
   * 3. Verify the project belongs to the authenticated user's organization context.
   * 4. Validate authorization: user must have project:manage permission.
   * 5. If name is being updated, verify the new name is unique within the organization (excluding current project).
   * 6. Validate status transitions:
   *    - active -> archived, completed
   *    - archived -> active, completed
   *    - completed -> archived (cannot reactivate to active)
   * 7. Validate date consistency: if both start_date and end_date provided, end_date must be after start_date.
   * 8. Validate color is a valid hex color code format.
   * 9. Validate budget_hours is non-negative if provided.
   * 10. Update only the provided fields in the request body.
   * 11. Set updated_at to current timestamp.
   * 12. Return the complete updated project entity.
   * 13. Handle errors: 404 if project not found, 403 if unauthorized, 400 for validation failures.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":projectId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("projectId")
    projectId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IErpHrmProject.IUpdate,
  ): Promise<IErpHrmProject> {
    try {
      return await putErpHrmAdminProjectsProjectId({
        admin,
        projectId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently deletes a project from the organization.
   *
   * This operation removes the project and all its associated tasks and project member assignments. The operation is subject to strict deletion constraints: projects containing any timelogs cannot be deleted to preserve historical time tracking data. Users must have the project:manage permission to execute this operation.
   *
   * Before deletion, the system verifies that no timelogs are associated with the project. If timelogs exist, the deletion is rejected with an error message indicating the constraint violation. For projects that should no longer receive new entries but contain historical data, archiving is the recommended alternative.
   *
   * Successful deletion returns the deleted project object for confirmation. The operation does not affect timelogs recorded in other projects or the employee's overall membership in other projects.
   *
   * @param connection
   * @param projectId Unique identifier of the project to delete (global scope)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Execute project deletion with the following steps:
   *
   * 1. **Authorization**: Verify the requesting user has project:manage permission in the current organization context.
   *
   * 2. **Timelog Constraint Check**: Query the timelog table to check if any timelogs exist where the project_id matches the target project. If any timelogs are found, reject the deletion with HTTP 409 Conflict and error message: "Project cannot be deleted because it contains time entries. Consider archiving the project instead."
   *
   * 3. **Project Retrieval**: Fetch the project record by projectId to verify existence and get current data for response.
   *
   * 4. **Cascade Deletion**: Delete associated records in the following order:
   *    - Delete tasks belonging to the project (erp_hrm_tasks where erp_hrm_project_id = projectId)
   *    - Delete project members (erp_hrm_project_members where erp_hrm_project_id = projectId)
   *    - Delete the project itself (erp_hrm_projects where id = projectId)
   *
   * 5. **Response**: Return the deleted project object with HTTP 200 status.
   *
   * Error scenarios:
   * - 401 Unauthorized: User is not authenticated
   * - 403 Forbidden: User lacks project:manage permission
   * - 404 Not Found: Project does not exist in the organization
   * - 409 Conflict: Project has associated timelogs
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":projectId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("projectId")
    projectId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteErpHrmAdminProjectsProjectId({
        admin,
        projectId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
