import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IErpHrmTaskHistory } from "../../../../../../api/structures/IErpHrmTaskHistory";
import { IPageIErpHrmTaskHistory } from "../../../../../../api/structures/IPageIErpHrmTaskHistory";
import { AdminAuth } from "../../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../../decorators/payload/AdminPayload";
import { getErpHrmAdminProjectsProjectIdTasksTaskIdHistoriesHistoryId } from "../../../../../../providers/getErpHrmAdminProjectsProjectIdTasksTaskIdHistoriesHistoryId";
import { patchErpHrmAdminProjectsProjectIdTasksTaskIdHistories } from "../../../../../../providers/patchErpHrmAdminProjectsProjectIdTasksTaskIdHistories";

@Controller("/erpHrm/admin/projects/:projectId/tasks/:taskId/histories")
export class ErphrmAdminProjectsTasksHistoriesController {
  /**
   * Retrieve the complete status change history for a specific task within a project.
   *
   * This endpoint provides access to the immutable audit trail of all status transitions for a task. Each history entry records the previous status, new status, who made the change, and when it occurred. The history is displayed in chronological order from oldest to newest, allowing users to trace the complete lifecycle progression of a task from creation through all status changes to its current state.
   *
   * Users must have appropriate permissions to access task history. Users with project view permission or task-related permissions can access history for tasks within projects they are authorized to view. Task history remains accessible even for archived projects, preserving the complete audit trail. This endpoint is useful for tracking task progress, identifying who made specific status changes, and understanding the workflow history of work items.
   *
   * The response includes summary information for each history entry optimized for list display, including status transition details and the member who initiated each change.
   *
   * @param connection
   * @param projectId Unique identifier of the project containing the task (global scope)
   * @param taskId Unique identifier of the task to retrieve history for (scoped to project)
   * @param body Search criteria and pagination parameters for filtering task histories
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query erp_hrm_task_histories table filtered by the specified task ID from path parameter.
   *
   * Join with erp_hrm_members table to retrieve member identity information (display name, avatar) for the member who made each status change. Join with erp_hrm_tasks to verify the task exists and belongs to the specified project.
   *
   * Apply pagination with configurable page size and cursor-based navigation. Order results by created_at ascending (oldest first) to show chronological progression.
   *
   * Optional filters in request body:
   * - Filter by erp_hrm_member_id to show only changes made by a specific member
   * - Filter by date range using created_at for changes within a specific time period
   *
   * Validate that the requesting user has permission to view task history (project view permission or project manage permission). Return empty list if no history entries exist rather than an error.
   *
   * Return paginated response with IPageIErpHrmTaskHistory.ISummary containing summary fields: id, previousStatus, newStatus, createdAt, and nested member summary (id, displayName, avatar).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("projectId")
    projectId: string & tags.Format<"uuid">,
    @TypedParam("taskId")
    taskId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IErpHrmTaskHistory.IRequest,
  ): Promise<IPageIErpHrmTaskHistory.ISummary> {
    try {
      return await patchErpHrmAdminProjectsProjectIdTasksTaskIdHistories({
        admin,
        projectId,
        taskId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific task history entry by its unique identifier.
   *
   * This endpoint returns the complete details of a single task history record, including the previous and new status values, the timestamp when the status change occurred, and the identity of the member who initiated the change. The history entry documents a single status transition in the task's lifecycle.
   *
   * The endpoint requires the project and task context in the URL path. Users must have appropriate permissions to view tasks within the project. Task history remains accessible even for archived projects, preserving the complete audit trail of status changes.
   *
   * The returned history entry is immutable once created - no modifications or deletions are permitted through this API.
   *
   * @param connection
   * @param projectId Unique identifier of the project containing the task (global scope)
   * @param taskId Unique identifier of the task whose history entry is being retrieved (scoped to project)
   * @param historyId Unique identifier of the specific task history entry to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Retrieve the task history entry from erp_hrm_task_histories table using the provided historyId.
   *
   * Verify the history entry belongs to the specified taskId by checking erp_hrm_task_id foreign key relationship.
   *
   * Verify the task belongs to the specified projectId by checking erp_hrm_projects relationship through erp_hrm_tasks.
   *
   * Authorization check: The requesting user must have project view permission for the organization containing the project, or be a member of the project. Return 403 Forbidden if unauthorized.
   *
   * Return 404 Not Found if historyId does not exist, if the history entry does not belong to the specified taskId, or if the task does not belong to the specified projectId.
   *
   * Join with erp_hrm_members table to include the member's display name or email in the response for identifying who made the status change.
   *
   * Return the complete TaskHistory record including all fields: id, erp_hrm_task_id, erp_hrm_member_id, previous_status, new_status, created_at.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":historyId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("projectId")
    projectId: string & tags.Format<"uuid">,
    @TypedParam("taskId")
    taskId: string & tags.Format<"uuid">,
    @TypedParam("historyId")
    historyId: string & tags.Format<"uuid">,
  ): Promise<IErpHrmTaskHistory> {
    try {
      return await getErpHrmAdminProjectsProjectIdTasksTaskIdHistoriesHistoryId(
        {
          admin,
          projectId,
          taskId,
          historyId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
