import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IErpHrmReport } from "../../../../../api/structures/IErpHrmReport";
import { IErpHrmReportParameter } from "../../../../../api/structures/IErpHrmReportParameter";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getErpHrmAdminReportsReportIdParametersParameterId } from "../../../../../providers/getErpHrmAdminReportsReportIdParametersParameterId";
import { patchErpHrmAdminReportsReportIdParameters } from "../../../../../providers/patchErpHrmAdminReportsReportIdParameters";
import { postErpHrmAdminReportsReportIdParameters } from "../../../../../providers/postErpHrmAdminReportsReportIdParameters";

@Controller("/erpHrm/admin/reports/:reportId/parameters")
export class ErphrmAdminReportsParametersController {
  /**
   * Create filter parameters for a specific report.
   *
   * This operation sets the filtering, grouping, and date range criteria for a report. Each report can have exactly one set of parameters defining how the report should be generated and what data it should include.
   *
   * The operation requires the user to have report:view permission within the organization. The report must belong to the user's current organization context. Parameters define the date range, optional employee/project/task filters, billable status filtering, and data grouping preference.
   *
   * If the specified report already has parameters defined, the system returns a conflict error since each report can only have one parameter configuration.
   *
   * @param connection
   * @param reportId Unique identifier of the report to create parameters for (global scope)
   * @param body Report parameter configuration including date range, optional filters, and grouping preference
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification 1. Validate user has report:view permission in the current organization context
   * 2. Validate reportId is a valid UUID format
   * 3. Verify the report exists and belongs to the current organization
   * 4. Verify the report does not already have parameters (1:1 relationship with unique constraint)
   * 5. Validate date range: start_date must not be after end_date
   * 6. Validate group_by is one of: 'employee', 'project', 'task'
   * 7. If employee_id is provided, verify employee exists and belongs to current organization
   * 8. If project_id is provided, verify project exists and belongs to current organization
   * 9. If task_id is provided, verify task exists and belongs to current organization
   * 10. Validate billable filter: true, false, or null (include all)
   * 11. Create erp_hrm_report_parameters record with erp_hrm_report_id linking to the report
   * 12. Set created_at and updated_at to current timestamp
   * 13. Return the created parameter record with full details
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("reportId")
    reportId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IErpHrmReportParameter.ICreate,
  ): Promise<IErpHrmReportParameter> {
    try {
      return await postErpHrmAdminReportsReportIdParameters({
        admin,
        reportId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update the filter parameters for an existing report within the organization.
   *
   * This endpoint allows authorized users with report:view permission to modify the filter criteria used to generate or refine a report. The parameters include date range boundaries, optional employee/project/task filters, billable status filtering, and data grouping preference.
   *
   * The report must belong to the user's current organization. If the report does not exist or belongs to a different organization, the system returns a not found error.
   *
   * Report parameters follow a 1:1 relationship with reports — each report has exactly one set of parameters. If parameters do not already exist for the report, PATCH creates them.
   *
   * Valid grouping options are strictly enforced: 'employee', 'project', or 'task'. Invalid group_by values result in a validation error. Date range must have start_date on or before end_date.
   *
   * @param connection
   * @param reportId Unique identifier of the report whose parameters to update (global scope)
   * @param body Updated filter parameters for the report including date range, filters, and grouping preference
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Validate that the report exists and belongs to the user's current organization context.
   *
   * If report_parameters record does not exist for this report, create a new one with the provided values.
   *
   * If report_parameters record already exists, apply partial updates using the provided fields.
   *
   * Validate date range: start_date must be on or before end_date. Return validation error if invalid.
   *
   * Validate group_by field: must be one of 'employee', 'project', or 'task'. Return validation error with valid options if invalid.
   *
   * Billable field accepts boolean values (true, false) or null (meaning include all).
   *
   * Store updated_at timestamp on both the report and its parameters.
   *
   * Return the full report object with updated parameters in the response.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("reportId")
    reportId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IErpHrmReportParameter.IUpdate,
  ): Promise<IErpHrmReport> {
    try {
      return await patchErpHrmAdminReportsReportIdParameters({
        admin,
        reportId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific report parameter with its associated report details.
   *
   * This endpoint returns the report parameter identified by the parameterId path parameter, along with its parent report information. The response uses an inverted composition pattern where the parameter includes the complete report object for full context without requiring additional API calls.
   *
   * The operation requires the user to have report:view permission within the organization. The report parameter and report must both belong to the same organization, and data isolation is enforced by the organization context from the authenticated session.
   *
   * If the specified parameter or report does not exist, or if they do not belong to the user's current organization, the system returns a not found error.
   *
   * @param connection
   * @param reportId Unique identifier of the report (UUID format)
   * @param parameterId Unique identifier of the report parameter (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query erp_hrm_report_parameters table filtering by id = parameterId.
   * Join with erp_hrm_reports table to get parent report data.
   * Verify the report's erp_hrm_organization_id matches the user's current organization context.
   * Verify reportId in path matches the parameter's erp_hrm_report_id.
   * Return 404 if parameter not found, report not found, or organization mismatch.
   * Construct response using inverted pattern: IErpHrmReportParameter.IInvert containing the report object without nested children arrays.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":parameterId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("reportId")
    reportId: string & tags.Format<"uuid">,
    @TypedParam("parameterId")
    parameterId: string & tags.Format<"uuid">,
  ): Promise<IErpHrmReportParameter.IInvert> {
    try {
      return await getErpHrmAdminReportsReportIdParametersParameterId({
        admin,
        reportId,
        parameterId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
