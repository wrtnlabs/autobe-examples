import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IErpHrmReport } from "../../../../api/structures/IErpHrmReport";
import { IPageIErpHrmReport } from "../../../../api/structures/IPageIErpHrmReport";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { deleteErpHrmAdminReportsReportId } from "../../../../providers/deleteErpHrmAdminReportsReportId";
import { getErpHrmAdminReportsReportId } from "../../../../providers/getErpHrmAdminReportsReportId";
import { patchErpHrmAdminReports } from "../../../../providers/patchErpHrmAdminReports";
import { postErpHrmAdminReports } from "../../../../providers/postErpHrmAdminReports";
import { putErpHrmAdminReportsReportId } from "../../../../providers/putErpHrmAdminReportsReportId";

@Controller("/erpHrm/admin/reports")
export class ErphrmAdminReportsController {
  /**
   * Generate a new organization report with specified parameters.
   *
   * This endpoint creates a report for the current organization based on the provided filter criteria. The report captures time tracking data, project budget information, or weekly summaries depending on the report type.
   *
   * Report Types:
   * - time_report: Shows hours logged with breakdown by billable status, grouped by employee, project, or task
   * - project_budget_report: Compares estimated budget hours against actual logged hours per project
   * - weekly_summary_report: Provides week-by-week metrics including total hours, timelog counts, and active employee counts
   *
   * The user must have report:view permission to generate reports. All report data is scoped to the current organization context.
   *
   * @param connection
   * @param body Report type and filter parameters for generating the report
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Create a new report record in erp_hrm_reports with the generated_by_erp_hrm_member_id set to the current authenticated user. Validate that the user has report:view permission within the organization.
   *
   * Store report parameters in erp_hrm_report_parameters table with a 1:1 relationship to the report (erp_hrm_report_id). Validate:
   * - report_type must be one of: 'time_report', 'project_budget_report', 'weekly_summary_report'
   * - start_date and end_date are required, end_date must be after start_date
   * - group_by for time_report must be one of: 'employee', 'project', 'task'
   * - billable filter: true for billable only, false for non-billable only, null for all
   * - employee_id, project_id, task_id must reference valid records within the organization
   *
   * Return the created report with its parameters included.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IErpHrmReport.ICreate,
  ): Promise<IErpHrmReport> {
    try {
      return await postErpHrmAdminReports({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a filtered and paginated list of reports within the organization.
   *
   * This operation allows authorized users to search and browse organization reports. Reports are scoped to the currently selected organization, ensuring strict data isolation. The search supports filtering by report type (time report, project budget report, weekly summary report), date range of report generation, and the user who generated the report.
   *
   * Users must possess the report:view permission to access this endpoint. Results are returned in descending order by creation date (newest first), enabling quick access to the most recently generated reports. Each report includes its parameters (date range, filters, grouping preferences) that were used during generation.
   *
   * @param connection
   * @param body Search criteria including report type filter, date range filter, generator filter, and pagination parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query erp_hrm_reports table filtered by erp_hrm_organization_id from session context.
   *
   * Apply search filters:
   * - Filter by report_type when specified (time_report, project_budget_report, weekly_summary_report)
   * - Filter by created_at date range when startDate/endDate provided
   * - Filter by generated_by_erp_hrm_member_id when specific generator specified
   *
   * Join with erp_hrm_report_parameters to include parameter details in response.
   *
   * Order by created_at descending (newest first).
   *
   * Apply cursor-based or offset pagination with configurable page size.
   *
   * Verify user has report:view permission in current organization context before returning results.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IErpHrmReport.IRequest,
  ): Promise<IPageIErpHrmReport.ISummary> {
    try {
      return await patchErpHrmAdminReports({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single stored report by its unique identifier.
   *
   * This endpoint returns the complete report entity including its associated parameters (date range, filters, grouping preferences) used to generate the report. The report is scoped to the currently selected organization context.
   *
   * The response includes the report metadata (type, name, generation timestamp) along with all filtering parameters that were applied when the report was generated. This allows consumers to understand what criteria produced the report data.
   *
   * Authorization requires the report:view permission. Users can only access reports belonging to their current organization. Reports from other organizations are not accessible even if the user belongs to multiple organizations.
   *
   * @param connection
   * @param reportId Unique identifier of the report (UUID)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query the erp_hrm_reports table using the provided reportId. Verify the report belongs to the currently authenticated user's organization context. If the report does not exist or belongs to a different organization, return 404 error.
   *
   * Join with erp_hrm_report_parameters table to retrieve the associated parameters (1:1 relationship via erp_hrm_report_id). Return the full report entity including:
   * - Report metadata: id, report_type, name, created_at, updated_at
   * - Generator info: generated_by_erp_hrm_member_id
   * - Parameters: start_date, end_date, employee_id, project_id, task_id, billable, group_by
   *
   * Validate that the user has report:view permission for the organization. Return 403 error if permission is denied.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":reportId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("reportId")
    reportId: string & tags.Format<"uuid">,
  ): Promise<IErpHrmReport> {
    try {
      return await getErpHrmAdminReportsReportId({
        admin,
        reportId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing report's configuration including display name and filter parameters.
   *
   * This operation allows authorized users to modify an existing report's parameters for generating updated analysis results. Users can update the display name for easier identification and change the filter parameters to generate the report with different criteria.
   *
   * The report must belong to the user's current organization context. Users must have report:view permission to access this endpoint. The system preserves the original generated_by tracking and report_type.
   *
   * Supported parameter updates include changing the date range (start_date, end_date), applying employee/project/task filters, modifying billable status filtering, and adjusting grouping preferences (employee/project/task). When parameters are updated, the report can be re-queried to retrieve the newly computed analysis results based on the updated filters.
   *
   * This operation updates the erp_hrm_reports and erp_hrm_report_parameters tables to store the new configuration.
   *
   * @param connection
   * @param reportId Unique identifier of the report to update (global scope)
   * @param body Updated report configuration including display name and filter parameters for the report.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Validate the report exists and belongs to the user's organization context.
   *
   * Verify user has report:view permission for the organization.
   *
   * Update the report's name field if provided in the request.
   *
   * Update or create the associated erp_hrm_report_parameters record:
   * - Set start_date and end_date for the date range
   * - Set employee_id filter if specified (null to include all)
   * - Set project_id filter if specified (null to include all)
   * - Set task_id filter if specified (null to include all)
   * - Set billable boolean filter (true/false for specific status, null for all)
   * - Set group_by preference (employee/project/task)
   *
   * Regenerate the report data based on new parameters:
   * - Query timelogs within date range filtered by employee/project/task
   * - Apply billable status filter if specified
   * - Group results according to group_by preference
   * - Calculate totals: total hours, billable hours, non-billable hours
   * - Store regenerated results in the report
   *
   * Update the updated_at timestamp on both report and parameters.
   *
   * Return the complete updated report with its parameters.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":reportId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("reportId")
    reportId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IErpHrmReport.IUpdate,
  ): Promise<IErpHrmReport> {
    try {
      return await putErpHrmAdminReportsReportId({
        admin,
        reportId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently removes a stored report from the organization.
   *
   * This operation deletes a specific report that was previously generated and stored. The report must belong to the current organization context to be deleted. Attempting to delete a report from another organization returns an access denied error.
   *
   * Only users with report:view permission can access report functionality. Deleted reports cannot be recovered as there is no soft-delete mechanism.
   *
   * @param connection
   * @param reportId Unique identifier of the report to delete
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification 1. Validate the reportId is a valid UUID format
   * 2. Retrieve the report by ID from erp_hrm_reports table
   * 3. Verify the report's erp_hrm_organization_id matches the current organization context
   * 4. If organization mismatch, return access denied error
   * 5. If report not found, return not found error
   * 6. Delete the report record from erp_hrm_reports table
   * 7. Return 204 No Content on success
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":reportId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("reportId")
    reportId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteErpHrmAdminReportsReportId({
        admin,
        reportId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
