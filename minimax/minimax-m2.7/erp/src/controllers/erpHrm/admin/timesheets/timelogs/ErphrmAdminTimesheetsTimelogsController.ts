import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IErpHrmTimesheet } from "../../../../../api/structures/IErpHrmTimesheet";
import { IErpHrmTimesheetTimelog } from "../../../../../api/structures/IErpHrmTimesheetTimelog";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getErpHrmAdminTimesheetsTimesheetIdTimelogsTimesheetTimelogId } from "../../../../../providers/getErpHrmAdminTimesheetsTimesheetIdTimelogsTimesheetTimelogId";
import { patchErpHrmAdminTimesheetsTimesheetIdTimelogs } from "../../../../../providers/patchErpHrmAdminTimesheetsTimesheetIdTimelogs";

@Controller("/erpHrm/admin/timesheets/:timesheetId/timelogs")
export class ErphrmAdminTimesheetsTimelogsController {
  /**
   * Manage the timelogs associated with a draft timesheet by adding or removing individual time entries.
   *
   * This endpoint allows employees to modify the contents of their draft timesheet before submission by adding or removing timelog entries. The operation works with the `erp_hrm_timesheet_timelogs` junction table to maintain associations between timesheets and timelogs.
   *
   * **Schema Relationships**: Each timesheet (`erp_hrm_timesheets`) represents a work week belonging to one employee (`erp_hrm_employee_id`). Timelogs (`erp_hrm_timelogs`) record individual time entries with date, duration, and project/task associations. The junction table tracks which timelogs belong to which timesheets.
   *
   * **Validation Rules**: Timelogs can only be added if they satisfy three conditions: (1) the timelog's employee matches the timesheet owner, (2) the timelog date falls within the timesheet week boundaries (`week_start_date` Monday through `week_end_date` Sunday), and (3) the timelog is not already associated with this timesheet. Removing timelogs preserves the original timelog record while deleting only the association.
   *
   * **Status Constraints**: Only timesheets with `status = 'draft'` can be modified. Submitted, approved, or rejected timesheets are locked and will return validation errors. The `total_hours` field on the timesheet is recalculated automatically based on the sum of `duration_minutes` from all associated timelogs.
   *
   * **Authorization**: Only the employee who owns the timesheet can modify it through their authenticated session. Users with `time:manage` permission can modify any employee's draft timesheet regardless of ownership.
   *
   * **Related Operations**: `POST /erpHrm/employees/{employeeId}/timesheets` to create a draft timesheet. `POST /erpHrm/employees/{employeeId}/timesheets/{timesheetId}/submit` to submit for approval. `PATCH /erpHrm/employees/{employeeId}/timesheets/{timesheetId}/approve` and `PATCH /erpHrm/employees/{employeeId}/timesheets/{timesheetId}/reject` for approval workflow.
   *
   * @param connection
   * @param timesheetId Unique identifier of the timesheet to modify
   * @param body Contains arrays of timelog IDs to add to or remove from the draft timesheet. Only one operation (add or remove) should be used per request.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification 1. Validate timesheetId is a valid UUID format
   * 2. Query erp_hrm_timesheets table to find the timesheet
   * 3. Verify the timesheet exists and is in 'draft' status
   * 4. Verify the requesting user has permission (employee owns timesheet or has time:manage permission)
   * 5. Validate all timelog IDs in addTimelogIds exist in erp_hrm_timelogs table
   * 6. Validate all timelog IDs in removeTimelogIds exist in erp_hrm_timelogs table
   * 7. For each timelog in addTimelogIds:
   *    - Verify timelog.erp_hrm_employee_id matches the timesheet's erp_hrm_employee_id
   *    - Verify timelog.date falls within timesheet's week_start_date and week_end_date
   *    - Verify timelog not already associated with this timesheet (check erp_hrm_timesheet_timelogs)
   *    - Insert new record into erp_hrm_timesheet_timelogs
   * 8. For each timelog in removeTimelogIds:
   *    - Verify timelog is currently associated with this timesheet
   *    - Delete record from erp_hrm_timesheet_timelogs
   * 9. Recalculate total_hours from all timelogs currently in timesheet
   * 10. Update timesheet's updated_at timestamp
   * 11. Return updated timesheet with associated timelogs and employee information
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("timesheetId")
    timesheetId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IErpHrmTimesheetTimelog.IUpdate,
  ): Promise<IErpHrmTimesheet> {
    try {
      return await patchErpHrmAdminTimesheetsTimesheetIdTimelogs({
        admin,
        timesheetId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific timelog association from a timesheet.
   *
   * This endpoint retrieves a single record from the erp_hrm_timesheet_timelogs junction table, which links individual time entries (erp_hrm_timelogs) to their parent weekly timesheet container (erp_hrm_timesheets). Each junction record contains the erp_hrm_timelog_id reference, the erp_hrm_timesheet_id association, and the added_at timestamp indicating when the timelog was added to the timesheet.
   *
   * The response returns an inverted view (IErpHrmTimesheetTimelog.IInvert) that includes the complete timelog details (date, duration_minutes, description, billable flag) along with project and task information. The timesheet itself is excluded from the response to prevent circular reference issues during JSON serialization.
   *
   * Security: Requires time:view_all permission to access any employee's timesheet associations, or the user must be the owner of the parent timesheet. Unauthorized access returns 403 Forbidden.
   *
   * Error scenarios: Returns 404 Not Found when the timesheetId does not exist or when the timesheetTimelogId junction record does not belong to the specified timesheet. Returns 403 when the requesting user lacks permission to view the timesheet.
   *
   *
   * @param connection
   * @param timesheetId Unique identifier of the parent timesheet
   * @param timesheetTimelogId Unique identifier of the timesheet-timelog junction record
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query the erp_hrm_timesheet_timelogs junction table filtering by id equals timesheetTimelogId and erp_hrm_timesheet_id equals timesheetId.
   *
   * Join with erp_hrm_timesheets to verify timesheet exists and user has access permission.
   *
   * Join with erp_hrm_timelogs to include complete timelog details in response.
   *
   * Join with erp_hrm_projects to include project name in timelog details.
   *
   * Join with erp_hrm_tasks to include task title if task_id is not null.
   *
   * Return 404 if junction record not found or belongs to different timesheet.
   *
   * Return 403 if user lacks time:view_all permission and is not the timesheet owner.
   *
   * Construct IErpHrmTimesheetTimelog.IInvert response with junction record details and embedded timelog with project/task info.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":timesheetTimelogId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("timesheetId")
    timesheetId: string & tags.Format<"uuid">,
    @TypedParam("timesheetTimelogId")
    timesheetTimelogId: string & tags.Format<"uuid">,
  ): Promise<IErpHrmTimesheetTimelog.IInvert> {
    try {
      return await getErpHrmAdminTimesheetsTimesheetIdTimelogsTimesheetTimelogId(
        {
          admin,
          timesheetId,
          timesheetTimelogId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
