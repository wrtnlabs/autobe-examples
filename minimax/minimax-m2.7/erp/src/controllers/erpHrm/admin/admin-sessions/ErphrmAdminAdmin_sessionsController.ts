import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IErpHrmAdminSession } from "../../../../api/structures/IErpHrmAdminSession";
import { IPageIErpHrmAdminSession } from "../../../../api/structures/IPageIErpHrmAdminSession";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getErpHrmAdminAdminSessionsSessionId } from "../../../../providers/getErpHrmAdminAdminSessionsSessionId";
import { patchErpHrmAdminAdminSessions } from "../../../../providers/patchErpHrmAdminAdminSessions";

@Controller("/erpHrm/admin/admin-sessions")
export class ErphrmAdminAdmin_sessionsController {
  /**
   * Retrieve a filtered and paginated list of administrator sessions.
   *
   * This operation allows administrators to search and filter admin sessions based on various criteria including the admin account, session creation date range, and expiration status. The results are returned in a paginated format with configurable page sizes.
   *
   * Security context: This endpoint is accessible only to admin actors who have authenticated via the admin session system. All queries are scoped to the current organization context. The session information includes IP address and navigation tracking for audit purposes.
   *
   * Filtering behavior: When filtering by date ranges, sessions created within the specified range are returned. When filtering by admin ID, only sessions belonging to that specific admin are returned. Multiple filters can be combined, and all conditions must be satisfied simultaneously.
   *
   * Pagination: Results are returned with cursor-based pagination for efficient traversal of large result sets. The response includes summary information optimized for list displays.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering admin sessions
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query erp_hrm_admin_sessions table with pagination and filtering.
   *
   * Apply search filters:
   * - Filter by erp_hrm_admin_id to get sessions for a specific admin
   * - Filter by created_at date range (from/to) for sessions created within period
   * - Filter by expired_at date range to identify active vs expired sessions
   * - Filter by ip address for sessions from specific IP
   *
   * Join with erp_hrm_admins table to include admin email/name in results if needed.
   *
   * Return cursor-based pagination with configurable page sizes (default 20, max 100).
   *
   * Sort by created_at descending by default (newest first).
   *
   * Include session status indicator (active/expired) based on expired_at comparison with current time.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IErpHrmAdminSession.IRequest,
  ): Promise<IPageIErpHrmAdminSession.ISummary> {
    try {
      return await patchErpHrmAdminAdminSessions({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific administrator session by its unique identifier.
   *
   * This endpoint returns the complete details of a single administrator session including the associated administrator reference, client IP address, current request URL path, HTTP referrer header, creation timestamp, and session expiration timestamp.
   *
   * The session must belong to an authenticated administrator. Only administrators can access this endpoint. The session identifier must be a valid UUID format.
   *
   * If the specified session does not exist, the endpoint returns a not found error. If the session has expired, the endpoint still returns the session data but the client should recognize it as invalid based on the expired_at timestamp.
   *
   * @param connection
   * @param sessionId Unique identifier of the admin session to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query the erp_hrm_admin_sessions table using the provided sessionId as the primary key lookup.
   *
   * 1. Validate sessionId is a valid UUID format
   * 2. Query the database for the session record matching the given id
   * 3. Verify the session has not been deleted
   * 4. Return the complete session entity including:
   *    - id (UUID)
   *    - erp_hrm_admin_id (UUID reference to admin)
   *    - ip (client IP address)
   *    - href (current request URL path)
   *    - referrer (HTTP referrer header)
   *    - created_at (timestamp)
   *    - expired_at (timestamp)
   *
   * If the session is not found, return 404 error.
   *
   * Note: This endpoint returns session metadata but does not validate session validity. The client should check the expired_at timestamp to determine if the session is still active.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<IErpHrmAdminSession> {
    try {
      return await getErpHrmAdminAdminSessionsSessionId({
        admin,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
