  /**
   * Retrieve a paginated list of timelogs for a specific member.
   *
   * This endpoint returns all timelogs belonging to the employees of the specified member. The member is identified by the memberId path parameter.
   *
   * Timelogs can be filtered by date range, project, task, and billable status. The response includes paginated timelog summaries with project and task information when available.
   *
   * Note: Only timelogs from employees belonging to the specified member are returned. The response does not include timelogs from employees in other organizations or members.
   *
   * @param connection
   * @param memberId Unique identifier of the member whose timelogs to retrieve (global scope)
   * @param body Search criteria and pagination parameters for filtering timelogs
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query timelogs for a specific member through their employee associations.
   *
   * 1. Validate that the memberId exists in erp_hrm_members table (not soft-deleted).
   * 2. Look up all employee records in erp_hrm_employees where erp_hrm_member_id matches the memberId.
   * 3. Collect all erp_hrm_employee_id values from these employee records.
   * 4. Query erp_hrm_timelogs where erp_hrm_employee_id is in the collected employee IDs.
   * 5. Join with erp_hrm_projects to get project name and status (filter by status='active' if specified in criteria).
   * 6. Optionally join with erp_hrm_tasks to get task title when erp_hrm_task_id is present.
   * 7. Apply search criteria filters from request body:
   *    - date_from and date_to: filter by date field
   *    - project_id: filter by erp_hrm_project_id
   *    - task_id: filter by erp_hrm_task_id
   *    - billable: filter by billable boolean field
   * 8. Apply pagination using cursor-based or offset pagination from request.
   * 9. Order results by date descending, then by created_at descending.
   * 10. Return paginated response with timelog summaries including: id, date, duration_minutes, description, billable, project name, task title, created_at.
   *
   * Edge cases:
   * - If member has no employees, return empty paginated result.
   * - If no timelogs match filters, return empty paginated result.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
