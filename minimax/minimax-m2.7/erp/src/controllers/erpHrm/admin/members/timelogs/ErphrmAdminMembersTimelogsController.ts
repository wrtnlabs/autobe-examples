  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("memberId")
    memberId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IErpHrmTimelog.IRequest,
  ): Promise<IPageIErpHrmTimelog.ISummary> {
    try {
      return await patchErpHrmAdminMembersMemberIdTimelogs({
        admin,
        memberId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

