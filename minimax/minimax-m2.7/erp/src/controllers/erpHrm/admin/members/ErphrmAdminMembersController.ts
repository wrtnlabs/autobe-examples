import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IErpHrmMember } from "../../../../api/structures/IErpHrmMember";
import { IPageIErpHrmMember } from "../../../../api/structures/IPageIErpHrmMember";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getErpHrmAdminMembersMemberId } from "../../../../providers/getErpHrmAdminMembersMemberId";
import { patchErpHrmAdminMembers } from "../../../../providers/patchErpHrmAdminMembers";

@Controller("/erpHrm/admin/members")
export class ErphrmAdminMembersController {
  /**
   * Retrieve a filtered and paginated list of member accounts in the system.
   *
   * This operation provides comprehensive search capabilities for member accounts, allowing clients to filter by email address, display name patterns, account status, and registration date ranges. The endpoint returns paginated results optimized for list displays with summary information for each member.
   *
   * Security and access control: This operation is accessible to authenticated members and admins. Data returned is scoped to the caller's organization context where applicable. Email addresses are included in responses for administrative purposes.
   *
   * The search supports partial matching on display names using configurable match modes (exact, contains, startsWith, endsWith). Account status filtering allows retrieving only active accounts, only deleted (soft-deleted) accounts, or all accounts regardless of status.
   *
   * Pagination follows cursor-based or offset-based patterns with configurable page sizes. Results can be sorted by display name, email, or creation date in ascending or descending order.
   *
   * Related operations: Individual member details can be retrieved using `GET /members/{memberId}`. Member creation is handled through registration flows, not this endpoint.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering members
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query erp_hrm_members table with pagination and filtering.
   *
   * 1. Parse request body for search criteria:
   *    - email: filter by exact email match (case-insensitive)
   *    - displayName: partial match search with configurable match mode
   *    - status: filter by 'active' (deleted_at IS NULL) or 'deleted' (deleted_at IS NOT NULL)
   *    - createdAtFrom/createdAtTo: date range filter for account creation
   *    - updatedAtFrom/updatedAtTo: date range filter for last update
   *
   * 2. Apply sorting:
   *    - Default sort: created_at DESC (newest first)
   *    - Configurable sort field and direction
   *
   * 3. Implement pagination:
   *    - Offset-based pagination with page and limit parameters
   *    - Default page size: 20, maximum: 100
   *    - Return total count for UI pagination controls
   *
   * 4. Response construction:
   *    - Map database rows to IErpHrmMember.ISummary format
   *    - Include: id, email, displayName, avatarUri, phone, createdAt
   *    - Exclude sensitive fields: passwordHash
   *    - Exclude deleted_at field from response
   *
   * 5. Authorization:
   *    - Verify caller has valid session
   *    - Return only members visible to caller's organization context
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IErpHrmMember.IRequest,
  ): Promise<IPageIErpHrmMember.ISummary> {
    try {
      return await patchErpHrmAdminMembers({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single member account by their unique identifier.
   *
   * This endpoint returns the profile information for a specific member based on their UUID identifier. The response includes the member's email address used for authentication, display name shown across organizations, avatar image URI, phone number, and account timestamps.
   *
   * The password hash field is intentionally excluded from the response for security reasons. Authentication credentials must never be exposed through the API.
   *
   * The member account is the canonical identity record for authenticated users in the system. Members can belong to multiple organizations through separate Employee records, but their core profile data is shared globally.
   *
   * This operation requires admin authorization. Administrators with appropriate permissions can view any member's profile information within their organization.
   *
   * @param connection
   * @param memberId Unique identifier of the member account (UUID)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query the erp_hrm_members table by the provided memberId (UUID primary key). Verify the member exists and is not soft-deleted (deleted_at is null). If the member is not found or is deleted, return a 404 error response. Build the response object including all member profile fields: id, email, display_name, avatar_uri, phone, created_at, updated_at. Exclude password_hash from the response for security. Return 200 OK with the member object on success.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":memberId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("memberId")
    memberId: string & tags.Format<"uuid">,
  ): Promise<IErpHrmMember> {
    try {
      return await getErpHrmAdminMembersMemberId({
        admin,
        memberId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
