import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IErpHrmRolePermission } from "../../../../api/structures/IErpHrmRolePermission";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getErpHrmAdminPermissions } from "../../../../providers/getErpHrmAdminPermissions";

@Controller("/erpHrm/admin/permissions")
export class ErphrmAdminPermissionsController {
  /**
   * Retrieve the complete list of available permissions that can be assigned to roles within an organization.
   *
   * This endpoint returns all predefined permission codes that define what actions users can perform. Permissions include organization management, employee management, project operations, time tracking controls, and report access. Organization owners and users with appropriate permissions can view this list to understand available capabilities when creating or editing custom roles.
   *
   * The response includes permission codes along with basic metadata such as creation timestamps. This endpoint does not filter by organization since permissions are system-wide definitions.
   *
   * @param connection
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification Query the erp_hrm_role_permissions table to
     *   retrieve all distinct permission codes available in the system.
   *
   * 1. Execute a SELECT DISTINCT query on the permission column from erp_hrm_role_permissions to get all unique permission codes.
   *
   * 2. Join with erp_hrm_roles to include role context (role ID, role name) for each permission.
   *
   * 3. Order results alphabetically by permission code for consistent output.
   *
   * 4. Return the permission codes along with associated role information (role_id, role_name).
   *
   * 5. No pagination required as the set of permissions is fixed and small.
   *
   * 6. No organization filtering needed since permissions are system-wide definitions.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async list(
    @AdminAuth()
    admin: AdminPayload,
  ): Promise<IErpHrmRolePermission.IList> {
    try {
      return await getErpHrmAdminPermissions({
        admin,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
