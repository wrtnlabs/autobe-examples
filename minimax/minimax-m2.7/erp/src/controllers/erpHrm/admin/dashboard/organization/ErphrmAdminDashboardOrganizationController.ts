import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IErpHrmOrganizationDashboard } from "../../../../../api/structures/IErpHrmOrganizationDashboard";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getErpHrmAdminDashboardOrganization } from "../../../../../providers/getErpHrmAdminDashboardOrganization";

@Controller("/erpHrm/admin/dashboard/organization")
export class ErphrmAdminDashboardOrganizationController {
  /**
   * Retrieve the organization dashboard with aggregate metrics for the current organization.
   *
   * This endpoint provides a comprehensive overview of the organization's current state, including employee count, weekly time tracking summaries, pending approval items, and budget utilization alerts. The dashboard is scoped to the currently selected organization context.
   *
   * The response includes total active employee count, total hours logged across all employees for the current week, the count of timesheets awaiting approval, a list of projects where budget utilization exceeds 80 percent, and the top performers by logged hours for the week.
   *
   * Requires report:view or org:manage permission to access.
   *
   * @param connection
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification Query the currently selected organization context
     *   from the session. Verify the requesting user has report:view or
     *   org:manage permission.
   *
   * 1. Count active employees: SELECT COUNT(*) FROM erp_hrm_employees WHERE erp_hrm_organization_id = :orgId AND status = 'active'
   *
   * 2. Calculate total hours this week: Join erp_hrm_timelogs with erp_hrm_employees, filter by current week (Monday to Sunday based on org timezone), sum duration_minutes and convert to hours.
   *
   * 3. Count pending timesheets: SELECT COUNT(*) FROM erp_hrm_timesheets WHERE erp_hrm_employee_id IN (employee IDs for org) AND status = 'submitted'
   *
   * 4. Find projects with budget over 80%: Join erp_hrm_projects with timelog aggregates, calculate (actual_hours / budget_hours * 100), filter where percentage > 80 AND budget_hours IS NOT NULL AND status = 'active'.
   *
   * 5. Get top 5 employees by hours: Aggregate timelogs per employee for current week, order by total hours DESC, limit 5. Include employee name and total hours.
   *
   * Return all metrics in a single response object. If no data exists for a category, return empty array or zero as appropriate.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @AdminAuth()
    admin: AdminPayload,
  ): Promise<IErpHrmOrganizationDashboard> {
    try {
      return await getErpHrmAdminDashboardOrganization({
        admin,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
