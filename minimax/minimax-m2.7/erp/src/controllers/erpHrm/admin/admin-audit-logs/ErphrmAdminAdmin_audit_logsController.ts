import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IErpHrmAdminAuditLog } from "../../../../api/structures/IErpHrmAdminAuditLog";
import { IPageIErpHrmAdminAuditLog } from "../../../../api/structures/IPageIErpHrmAdminAuditLog";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getErpHrmAdminAdminAuditLogsAuditLogId } from "../../../../providers/getErpHrmAdminAdminAuditLogsAuditLogId";
import { patchErpHrmAdminAdminAuditLogs } from "../../../../providers/patchErpHrmAdminAdminAuditLogs";

@Controller("/erpHrm/admin/admin-audit-logs")
export class ErphrmAdminAdmin_audit_logsController {
  /**
   * Retrieve a filtered and paginated list of administrative audit log entries.
   *
   * This operation provides search capabilities for reviewing administrative actions performed within the system. Administrators can filter audit logs by action type, target entity, administrator who performed the action, date range, and IP address.
   *
   * The audit log serves as an immutable record for security compliance and accountability. Each entry captures the administrator who performed the action, the action type (such as employee_invited, contract_created, project_archived, timesheet_approved), the target entity that was affected, and additional metadata in JSON format.
   *
   * Only users with appropriate administrative permissions can access this endpoint. The response is paginated with configurable page sizes and sorting by creation timestamp in descending order by default.
   *
   * Related operations: Use GET /admin-audit-logs/{id} to retrieve a single audit log entry by its unique identifier.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering admin audit logs
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query erp_hrm_admin_audit_logs table with pagination and filtering.
   *
   * Apply search filters:
   * - Filter by action_type (exact match, supports multiple values)
   * - Filter by target_entity (exact match, supports multiple values)
   * - Filter by target_id (exact match)
   * - Filter by erp_hrm_admin_id (exact match)
   * - Filter by ip_address (exact match)
   * - Filter by created_at date range (from/to)
   *
   * Always filter by the current organization context.
   *
   * Join with erp_hrm_admins to include administrator information (name, email) in results.
   *
   * Return cursor-based pagination with configurable page sizes (default 20, max 100).
   *
   * Sort by created_at descending (newest first) by default.
   *
   * Return IPageIErpHrmAdminAuditLog.ISummary with essential fields for list display:
   * - id, action_type, target_entity, target_id, ip_address, created_at
   * - Include admin summary (name, email)
   * - Include metadata preview if present
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IErpHrmAdminAuditLog.IRequest,
  ): Promise<IPageIErpHrmAdminAuditLog.ISummary> {
    try {
      return await patchErpHrmAdminAdminAuditLogs({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single admin audit log record by its unique identifier.
   *
   * This endpoint retrieves detailed information about a specific administrative action recorded in the system audit trail. Admin audit logs are immutable records that capture every significant action performed by administrators, including employee management operations, contract modifications, project lifecycle changes, task status updates, timesheet approvals/rejections, and role assignments.
   *
   * Each audit log entry contains the identity of the administrator who performed the action, the type of action taken, the target entity type and ID that was affected, optional JSON metadata with additional context such as old/new values or rejection reasons, the IP address from which the action was performed, and the timestamp when the action occurred.
   *
   * This operation is restricted to authenticated administrators only. Regular members cannot access admin audit logs as these records contain sensitive administrative activity information. The retrieved record is read-only - audit logs cannot be modified or deleted after creation to maintain compliance and accountability.
   *
   * Related Operations:
   * - PATCH /admin-audit-logs - List/search admin audit logs with filtering
   * - These logs are automatically created by the system when administrators perform privileged actions, so no creation endpoint is provided
   *
   * @param connection
   * @param auditLogId The unique identifier (UUID) of the admin audit log record to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query the erp_hrm_admin_audit_logs table using the provided auditLogId as the primary key lookup.
   *
   * 1. Extract auditLogId from path parameters and validate it as a valid UUID format.
   *
   * 2. Query the database for a single record where erp_hrm_admin_audit_logs.id equals the auditLogId.
   *
   * 3. If no record is found, return a 404 response with appropriate error message.
   *
   * 4. If found, return the complete audit log record including:
   *    - id: The unique identifier of the audit log entry
   *    - erpHrmAdminId: Reference to the admin who performed the action
   *    - actionType: The type of action (e.g., employee_invited, project_archived, timesheet_approved)
   *    - targetEntity: Type of entity affected (e.g., employee, contract, project, task, timesheet)
   *    - targetId: UUID of the affected entity
   *    - metadata: Optional JSON string with additional context (old values, new values, rejection reason, etc.)
   *    - ipAddress: IP address from which the action was performed
   *    - createdAt: Timestamp of when the action was performed
   *
   * 5. Join with erp_hrm_admins table to include admin information in the response if needed.
   *
   * 6. No permission checks beyond admin authentication are required - all authenticated admins can view any audit log.
   *
   * 7. No caching should be applied to audit log retrieval as these records must reflect the most current state.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":auditLogId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("auditLogId")
    auditLogId: string & tags.Format<"uuid">,
  ): Promise<IErpHrmAdminAuditLog> {
    try {
      return await getErpHrmAdminAdminAuditLogsAuditLogId({
        admin,
        auditLogId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
