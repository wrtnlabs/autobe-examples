import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IErpHrmMember } from "../../../../api/structures/IErpHrmMember";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { putErpHrmAdminProfile } from "../../../../providers/putErpHrmAdminProfile";

@Controller("/erpHrm/admin/profile")
export class ErphrmAdminProfileController {
  /**
   * Update the authenticated user's profile information.
   *
   * This operation allows members to modify their shared profile attributes including display name, avatar image, and phone number. Changes to the profile are immediately reflected across all organizations the user belongs to, ensuring consistent identity representation throughout the platform.
   *
   * The display name is shown in employee records, timesheets, activity logs, and other areas where user identity is displayed. The avatar appears next to the user's name in lists and reports. The phone number enables work-related communications within organizations.
   *
   * This endpoint requires an active authenticated session. Users can only update their own profile; cross-user profile modifications are not permitted.
   *
   * @param connection
   * @param body Profile update fields - display name, avatar URI, and phone number.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Retrieve the authenticated user from the session context. Validate that display_name is provided and meets length requirements (1-255 characters). If avatar_uri is provided, validate it as a valid URI format. If phone is provided, validate format. Update only the fields present in the request body: display_name, avatar_uri, phone. Set updated_at to current timestamp. Return the updated member profile including all fields except password_hash.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IErpHrmMember.IUpdate,
  ): Promise<IErpHrmMember> {
    try {
      return await putErpHrmAdminProfile({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
