import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IErpHrmStatistic } from "../../../../api/structures/IErpHrmStatistic";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getErpHrmAdminStatistics } from "../../../../providers/getErpHrmAdminStatistics";

@Controller("/erpHrm/admin/statistics")
export class ErphrmAdminStatisticsController {
  /**
   * Retrieve aggregated statistics for the current organization dashboard.
   *
   * This endpoint provides real-time organizational metrics including the total count of active employees, total hours logged this week across all employees, the number of timesheets awaiting approval, and a list of projects where budget utilization has exceeded 80 percent.
   *
   * Additionally, the response includes the top five employees ranked by hours logged during the current week, showing each employee's name, department, and total hours. This endpoint requires the report:view permission and all statistics are scoped to the currently selected organization context.
   *
   * @param connection
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification Query the current organization context from the
     *   session. Verify the requesting user has report:view permission in their
     *   role.
   *
   * Calculate active employee count from erp_hrm_employees where organization_id matches and status equals active.
   *
   * Calculate total hours logged this week from erp_hrm_timelogs where log_date falls within Monday to Sunday of current week and employee belongs to current organization.
   *
   * Count pending timesheets from erp_hrm_timesheets where status equals submitted and employee belongs to current organization.
   *
   * Query projects with budget_hours > 0 from erp_hrm_projects where (actual_hours / budget_hours) * 100 >= 80, sorted by utilization percentage descending, limit to 10.
   *
   * Find top 5 employees this week from timelogs aggregation, join with erp_hrm_employees for name and department, sort by total hours descending.
   *
   * Return all statistics in a single response object with clear category groupings.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async overview(
    @AdminAuth()
    admin: AdminPayload,
  ): Promise<IErpHrmStatistic> {
    try {
      return await getErpHrmAdminStatistics({
        admin,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
