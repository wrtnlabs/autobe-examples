import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IErpHrmMember } from "../../../api/structures/IErpHrmMember";
import { IPageIErpHrmMember } from "../../../api/structures/IPageIErpHrmMember";
import { getErpHrmMembersMemberId } from "../../../providers/getErpHrmMembersMemberId";
import { patchErpHrmMembers } from "../../../providers/patchErpHrmMembers";

@Controller("/erpHrm/members")
export class ErphrmMembersController {
  /**
   * Retrieve a filtered and paginated list of member accounts within the current organization context.
   *
   * This operation searches registered user accounts (members) who are associated with the currently selected organization through employee records. The search supports partial name matching using trigram similarity, exact email filtering, and soft-delete status toggling. Results are sorted by creation date descending by default.
   *
   * The operation enforces organization-level data isolation, ensuring only members with an active employee record in the current organization are returned. Deactivated members (soft-deleted accounts with non-null deleted_at) are excluded by default but can be included via the deleted filter parameter.
   *
   * Use cases include: admin user management interfaces, employee lookup for task assignment, and organization member directory views.
   *
   * @param connection
   * @param body Search criteria including name partial match, email filter, soft-delete status, date range, and pagination controls
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor null
     * @x-autobe-specification Query the erp_hrm_members table with the
     *   following implementation steps:
   *
   * 1. Base Query: Start with SELECT on erp_hrm_members JOIN erp_hrm_employees to filter by organization context (current session's organization_id).
   *
   * 2. Soft-Delete Filtering: Exclude members where deleted_at IS NOT NULL by default. Allow inclusion when deleted parameter is true.
   *
   * 3. Search Criteria (apply if provided):
   *    - displayName: Use ILIKE with %wildcards% for partial matching (GIN trigram index available)
   *    - email: Use exact match (email is unique)
   *    - createdAt: Filter by date range using created_at column
   *    - deleted: Boolean filter for soft-delete status
   *
   * 4. Sorting: Order by created_at DESC by default. Support sortBy and sortOrder parameters.
   *
   * 5. Pagination: Apply cursor-based or offset pagination with configurable page size (default 20, max 100).
   *
   * 6. Response Construction: Map results to IErpHrmMember.ISummary containing id, email, displayName, avatarUri, phone, createdAt.
   *
   * 7. Edge Cases:
   *    - Empty result set: Return empty page with total 0
   *    - Invalid organization context: Return 403 Forbidden
   *    - No members in organization: Return empty page
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IErpHrmMember.IRequest,
  ): Promise<IPageIErpHrmMember.ISummary> {
    try {
      return await patchErpHrmMembers({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific member's account details by their unique identifier.
   *
   * This endpoint returns the complete profile information for a registered member account, including their display name, avatar, email, and phone number. The operation performs soft-delete filtering to ensure only active accounts are returned.
   *
   * Access is scoped to the requesting user's organization context. The system verifies that the member has an active employee record within the current organization before returning their profile. This prevents unauthorized access to member information outside the organization.
   *
   * Deleted accounts (where deleted_at is set) are not returned; requesting such accounts results in a 404 error.
   *
   * @param connection
   * @param memberId Unique identifier of the member account (UUID format)
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor null
     * @x-autobe-specification Query the erp_hrm_members table by id with
     *   soft-delete filtering (WHERE deleted_at IS NULL). Verify the member has
     *   at least one active employee record (erp_hrm_employees) linked to the
     *   current organization context. Return all member fields EXCEPT
     *   password_hash. If the member is not found or soft-deleted, return 404
     *   error. If the member has no employee record in the current
     *   organization, return 403 forbidden error.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":memberId")
  public async at(
    @TypedParam("memberId")
    memberId: string & tags.Format<"uuid">,
  ): Promise<IErpHrmMember> {
    try {
      return await getErpHrmMembersMemberId({
        memberId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
