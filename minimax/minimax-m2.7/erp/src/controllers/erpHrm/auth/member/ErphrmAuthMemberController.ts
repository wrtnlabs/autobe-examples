import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IErpHrmMember } from "../../../../api/structures/IErpHrmMember";
import { postErpHrmAuthMemberJoin } from "../../../../providers/postErpHrmAuthMemberJoin";
import { postErpHrmAuthMemberLogin } from "../../../../providers/postErpHrmAuthMemberLogin";
import { postErpHrmAuthMemberRefresh } from "../../../../providers/postErpHrmAuthMemberRefresh";

@Controller("/erpHrm/auth/member")
export class ErphrmAuthMemberController {
  /**
   * Creates a new member account and establishes an authenticated session. This operation allows unauthenticated users (guests) to register as members by providing valid email address, password, and display name. The email must be unique across the erp_hrm_members table (enforced by unique constraint on email field). Password is securely hashed using bcrypt before storage in password_hash field. Upon successful registration, the system generates JWT access and refresh tokens stored in erp_hrm_member_sessions table, linking to the new member via erp_hrm_member_id. The access token has a configurable expiration time stored in token_expired_at field. This endpoint is accessible without authentication (authorizationActor: null) to allow guest-to-member transition. Related operations include login for existing members and refresh for token renewal.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Member registration credentials including email, password, and display name
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor member
   * @x-autobe-specification 1. Validate email format and uniqueness in erp_hrm_members table
   * 2. Validate password strength requirements
   * 3. Hash password using bcrypt
   * 4. Create new member record with email, password_hash, display_name
   * 5. Generate JWT access and refresh tokens
   * 6. Create session record in erp_hrm_member_sessions with token_expired_at and expired_at
   * 7. Return access_token, refresh_token, and member information
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IErpHrmMember.IJoin,
  ): Promise<IErpHrmMember.IAuthorized> {
    try {
      return await postErpHrmAuthMemberJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticates an existing member with email and password credentials. This login operation validates the provided email and password against the erp_hrm_members table records. The system verifies the password hash using bcrypt comparison. On successful authentication, new JWT access and refresh tokens are generated and stored in erp_hrm_member_sessions table with client metadata (ip address, href, referrer). Failed login attempts return generic error messages without revealing whether the email exists, protecting against enumeration attacks. Multiple failed attempts may trigger rate limiting. Session tokens have expiration timestamps stored in token_expired_at and expired_at fields. This endpoint is accessible without prior authentication.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Member login credentials with email and password
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor member
   * @x-autobe-specification 1. Validate email format
   * 2. Look up member by email in erp_hrm_members table
   * 3. Verify password against stored password_hash using bcrypt
   * 4. On success, generate new JWT access and refresh tokens
   * 5. Create new session record in erp_hrm_member_sessions
   * 6. Store client metadata (ip, href, referrer) in session record
   * 7. Set appropriate expiration times for tokens
   * 8. Return tokens and member information
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IErpHrmMember.ILogin,
  ): Promise<IErpHrmMember.IAuthorized> {
    try {
      return await postErpHrmAuthMemberLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Renews authentication tokens using a valid refresh token. This refresh operation allows members to obtain new access tokens without re-entering credentials. The operation validates the provided refresh_token against erp_hrm_member_sessions table records. Sessions track validity through token_expired_at (access token expiration) and expired_at (session expiration) timestamps. Both must be valid for successful refresh. Upon validation, new JWT tokens are generated and the session record is updated with fresh tokens and expiration times. This mechanism supports long-lived sessions while maintaining security through token rotation. The operation requires the member to be authenticated (authorizationActor: 'member').
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token for obtaining new access token
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor member
   * @x-autobe-specification 1. Validate refresh token format and existence
   * 2. Look up session by refresh_token in erp_hrm_member_sessions table
   * 3. Verify session has not expired (check expired_at timestamp)
   * 4. Verify refresh token has not expired (check token_expired_at)
   * 5. Generate new access token and optionally new refresh token
   * 6. Update session record with new tokens and expiration times
   * 7. Return new access token, optional new refresh token, and member information
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IErpHrmMember.IRefresh,
  ): Promise<IErpHrmMember.IAuthorized> {
    try {
      return await postErpHrmAuthMemberRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
