import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IErpHrmAdmin } from "../../../../api/structures/IErpHrmAdmin";
import { postErpHrmAuthAdminJoin } from "../../../../providers/postErpHrmAuthAdminJoin";
import { postErpHrmAuthAdminLogin } from "../../../../providers/postErpHrmAuthAdminLogin";
import { postErpHrmAuthAdminRefresh } from "../../../../providers/postErpHrmAuthAdminRefresh";

@Controller("/erpHrm/auth/admin")
export class ErphrmAuthAdminController {
  /**
   * Creates a new administrator account in the erp_hrm system. This endpoint accepts the new admin's email address, display name, and secure password to establish an authenticated admin session. The email field must be unique across all administrator accounts in the system as defined by the erp_hrm_admins table's @@unique([email]) constraint. Upon successful registration, the system returns JWT access and refresh tokens that can be used for subsequent authenticated API calls. The password is stored as a bcrypt hash in the password_hash field, ensuring secure credential storage. This operation corresponds to the join authorization type and creates a new erp_hrm_admins record in the database.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Request body containing new administrator registration information including email, display name, and password.
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Service layer validates the registration data, hashes the password using bcrypt, creates a new erp_hrm_admins record with the provided email, display_name, and optional phone/avatar_uri. JWT access and refresh tokens are generated and returned in the IErpHrmAdmin.IAuthorized response.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IErpHrmAdmin.IJoin,
  ): Promise<IErpHrmAdmin.IAuthorized> {
    try {
      return await postErpHrmAuthAdminJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticates an existing administrator using email and password credentials. This endpoint validates the provided credentials against the stored password_hash in the erp_hrm_admins table, where passwords are stored using bcrypt hashing for security. Upon successful authentication, the system creates a new erp_hrm_admin_sessions record that tracks the session context including client IP address, current request URL path, HTTP referrer header, creation timestamp, and expiration time. The endpoint returns JWT access and refresh tokens that enable the admin to make authenticated API requests. This login operation corresponds to the login authorization type and is restricted to administrator accounts only, providing elevated access privileges for organization management.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Request body containing administrator login credentials (email and password).
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Service layer validates the provided email and password against the stored bcrypt hash in erp_hrm_admins. On success, creates an erp_hrm_admin_sessions record with client IP and navigation context, then generates and returns JWT access and refresh tokens.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IErpHrmAdmin.ILogin,
  ): Promise<IErpHrmAdmin.IAuthorized> {
    try {
      return await postErpHrmAuthAdminLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refreshes the administrator's authentication tokens using a valid refresh token. This endpoint accepts a refresh token that was previously issued during login or registration and validates it against the erp_hrm_admin_sessions table records. The system checks the token's expiration timestamp stored in the expired_at field and verifies the token has not been used or revoked. Upon successful validation, new JWT access and refresh token pairs are generated and returned, extending the admin's authenticated session. The erp_hrm_admin_sessions table tracks all active sessions with their creation timestamps and expiration times for security auditing. This refresh operation corresponds to the refresh authorization type and maintains the admin's elevated access privileges for continued organization management operations.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Request body containing the refresh token to renew admin authentication.
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Service layer validates the provided refresh token, checks its expiration against the erp_hrm_admin_sessions.expired_at field, and issues new JWT access and refresh tokens. Invalid or expired refresh tokens result in authentication errors.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IErpHrmAdmin.IRefresh,
  ): Promise<IErpHrmAdmin.IAuthorized> {
    try {
      return await postErpHrmAuthAdminRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
