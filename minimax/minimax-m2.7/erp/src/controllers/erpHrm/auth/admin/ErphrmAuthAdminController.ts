import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IErpHrmAdmin } from "../../../../api/structures/IErpHrmAdmin";
import { postErpHrmAuthAdminJoin } from "../../../../providers/postErpHrmAuthAdminJoin";
import { postErpHrmAuthAdminLogin } from "../../../../providers/postErpHrmAuthAdminLogin";
import { postErpHrmAuthAdminRefresh } from "../../../../providers/postErpHrmAuthAdminRefresh";

@Controller("/erpHrm/auth/admin")
export class ErphrmAuthAdminController {
  /**
   * Creates a new administrator account for organization management. Accepts email (used as unique identifier), password (bcrypt hashed), and display name. Optional fields include phone number and avatar URI. Upon successful registration, returns JWT access and refresh tokens for immediate authentication. The admin account provides full access to organization settings, employee management, project oversight, and time tracking approvals.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Registration data for new admin account including email, password, and display name
     * @x-autobe-authorization-type join
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification 1. Receive IErpHrmAdmin.IJoin request body with
     *   email, password, displayName, phone (optional), avatarUri (optional) 2.
     *   Validate email format and uniqueness in erp_hrm_admins table 3.
     *   Validate password strength (min 8 chars, complexity requirements) 4.
     *   Hash password using bcrypt 5. Create new erp_hrm_admins record with
     *   provided data 6. Generate JWT access and refresh tokens with admin ID
     *   in payload 7. Create erp_hrm_admin_sessions record with IP, user agent,
     *   expiration (24 hours for access token) 8. Return
     *   IErpHrmAdmin.IAuthorized with tokens, admin details
   *
   * Edge cases:
   * - Duplicate email: return 409 Conflict
   * - Weak password: return 400 Bad Request with validation details
   * - Server error: return 500 with generic error message
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IErpHrmAdmin.IJoin,
  ): Promise<IErpHrmAdmin.IAuthorized> {
    try {
      return await postErpHrmAuthAdminJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticates an administrator using email and password credentials. Validates the provided password against the stored bcrypt hash in the erp_hrm_admins table. On successful authentication, creates a new session record in erp_hrm_admin_sessions tracking IP address and navigation context. Returns JWT access token for API authorization and refresh token for token renewal. Sessions expire according to configured access token lifetime.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Login credentials containing email and password for admin authentication
     * @x-autobe-authorization-type login
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification 1. Receive IErpHrmAdmin.ILogin request body with
     *   email and password 2. Query erp_hrm_admins table by email 3. Verify
     *   password against stored password_hash using bcrypt 4. If valid,
     *   generate JWT access token (1 hour expiry) and refresh token (7 days
     *   expiry) 5. Create erp_hrm_admin_sessions record with client IP, current
     *   URL, referrer, and expiration 6. Return IErpHrmAdmin.IAuthorized with
     *   tokens and admin profile
   *
   * Edge cases:
   * - Admin not found: return 401 Unauthorized with generic message
   * - Invalid password: return 401 Unauthorized with generic message
   * - Account issues: return appropriate error
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IErpHrmAdmin.ILogin,
  ): Promise<IErpHrmAdmin.IAuthorized> {
    try {
      return await postErpHrmAuthAdminLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Renews expired or expiring JWT access tokens using a valid refresh token. The refresh token is validated against stored sessions in erp_hrm_admin_sessions table to ensure it has not been revoked or expired. Implements optional token rotation for enhanced security. Returns new access token with extended validity period along with the admin profile data. Refresh tokens allow maintaining authenticated sessions without requiring re-login.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token for obtaining new access token without re-authentication
     * @x-autobe-authorization-type refresh
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification 1. Receive IErpHrmAdmin.IRefresh request body
     *   with refreshToken 2. Validate refresh token signature and expiration 3.
     *   Extract admin ID from token payload 4. Query erp_hrm_admin_sessions to
     *   verify session exists and not expired 5. Generate new access token and
     *   optionally new refresh token (token rotation) 6. Update session record
     *   with new expiration 7. Return IErpHrmAdmin.IAuthorized with new tokens
   *
   * Edge cases:
   * - Expired refresh token: return 401 Unauthorized
   * - Invalid token format: return 401 Unauthorized
   * - Session not found: return 401 Unauthorized
   * - Token already used (if implementing rotation): return 401 Unauthorized
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IErpHrmAdmin.IRefresh,
  ): Promise<IErpHrmAdmin.IAuthorized> {
    try {
      return await postErpHrmAuthAdminRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
