import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IErpHrmGuest } from "../../../../api/structures/IErpHrmGuest";
import { postErpHrmAuthGuestJoin } from "../../../../providers/postErpHrmAuthGuestJoin";
import { postErpHrmAuthGuestRefresh } from "../../../../providers/postErpHrmAuthGuestRefresh";

@Controller("/erpHrm/auth/guest")
export class ErphrmAuthGuestController {
  /**
   * Creates a new guest session for unauthenticated users who want temporary access to the system.
   *
   * This endpoint allows users to create a guest account identified by their device_id. The guest account provides temporary access with an expiration period (7 days by default). The device_id field uniquely identifies the guest device, while the temporary_email field can optionally store a contact email for the session. Upon successful registration, the system generates both an access_token for immediate API authentication and a refresh_token for token renewal when the access_token expires.
   *
   * The guest session is stored in the erp_hrm_guest_sessions table with references to the guest record. The access_token and refresh_token are JWT tokens that enable stateless authentication. When the guest eventually registers as a member or logs in, the guest session can be used to preserve context or migrate data.
   *
   * Security considerations: Device ID must be validated as UUID format. Guest accounts automatically expire after the configured expiration period. Temporary email is optional and validated for email format when provided.
   *
   * Related operations: POST /auth/guest/refresh - Token renewal endpoint for guests with valid refresh_token
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Guest join request containing device_id for device identification and optional temporary_email for contact purposes.
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification 1. Validate guest data from request body (device_id must be present and valid UUID format)
   * 2. Check if guest already exists for this device_id
   * 3. If exists and not expired, return existing guest session
   * 4. If not exists or expired, create new guest record with generated UUID and expiration (7 days from creation)
   * 5. Generate JWT access_token and refresh_token
   * 6. Create erp_hrm_guest_sessions record with tokens
   * 7. Return IErpHrmGuest.IAuthorized response with tokens and guest info
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IErpHrmGuest.IJoin,
  ): Promise<IErpHrmGuest.IAuthorized> {
    try {
      return await postErpHrmAuthGuestJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refreshes an expired or expiring access_token using a valid refresh_token for guest sessions.
   *
   * This endpoint allows guest users to obtain a new access_token without re-authenticating, extending their session duration. The refresh_token must be a valid, non-revoked token associated with an existing guest session. Upon successful refresh, the old refresh_token is revoked and a new token pair is issued for security purposes.
   *
   * The refresh operation validates against the erp_hrm_guest_sessions table, checking that the refresh_token matches and has not been revoked. The guest record in erp_hrm_guests table must still be within its expiration period. Token versioning ensures that compromised refresh tokens cannot be reused after a refresh operation.
   *
   * Security considerations: Each refresh operation invalidates the previous refresh_token (one-time use). Expired guest accounts cannot refresh their tokens. Token_version field prevents replay attacks with old refresh tokens. The revoked_at timestamp permanently invalidates compromised tokens.
   *
   * Related operations: POST /auth/guest/join - Initial guest registration endpoint
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Guest refresh request containing the refresh_token to obtain new access credentials.
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification 1. Extract refresh_token from request body
   * 2. Validate refresh_token format and signature
   * 3. Look up guest session by refresh_token in erp_hrm_guest_sessions table
   * 4. Verify session has not been revoked (revoked_at is null)
   * 5. Check guest record is not expired (expires_at > current_time)
   * 6. Generate new access_token and refresh_token pair
   * 7. Update guest_sessions record with new tokens and increment token_version
   * 8. Revoke old refresh_token by updating revoked_at timestamp
   * 9. Return new IErpHrmGuest.IAuthorized response with fresh tokens
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IErpHrmGuest.IRefresh,
  ): Promise<IErpHrmGuest.IAuthorized> {
    try {
      return await postErpHrmAuthGuestRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
