import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IErpHrmGuest } from "../../../../api/structures/IErpHrmGuest";
import { postErpHrmAuthGuestJoin } from "../../../../providers/postErpHrmAuthGuestJoin";
import { postErpHrmAuthGuestRefresh } from "../../../../providers/postErpHrmAuthGuestRefresh";

@Controller("/erpHrm/auth/guest")
export class ErphrmAuthGuestController {
  /**
   * Creates a new guest account and establishes an authenticated session. This endpoint handles user registration by accepting email, password, and organization details. The email field must be a valid unique email address not already registered in erp_hrm_members table. The password field must meet minimum security requirements (minimum 8 characters). The password_confirmation field must exactly match the password field. The organization_name field is required and sets up the user's initial organization. The currency field defaults to USD if not provided. The timezone field defaults to UTC if not provided. Upon successful registration, the system creates the member account in erp_hrm_members, the organization in erp_hrm_organizations, and the employee record in erp_hrm_employees with owner role. The response contains JWT access_token and refresh_token for authenticated sessions.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Registration request containing user credentials and organization details.
     * @x-autobe-authorization-type join
     * @x-autobe-authorization-actor guest
     * @x-autobe-specification Validate request body contains required fields
     *   (email, password, password_confirmation, organization_name). Check
     *   email format and uniqueness. Validate password strength. Verify
     *   password_confirmation matches password. Create new erp_hrm_members
     *   record with hashed password. Create new erp_hrm_organizations record
     *   with provided details (name, description, currency, timezone,
     *   fiscal_start_month). Create erp_hrm_employees record linking user to
     *   organization with owner role. Generate access_token and refresh_token
     *   JWTs. Return tokens and user/organization info.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IErpHrmGuest.IJoin,
  ): Promise<IErpHrmGuest.IAuthorized> {
    try {
      return await postErpHrmAuthGuestJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refreshes an authenticated session by issuing new JWT tokens. This endpoint accepts a valid refresh_token from a previous authentication (join) and issues new access_token and refresh_token pairs. The refresh_token field must contain a valid, non-expired JWT that was previously issued by the system. The system validates the token signature and expiration against the erp_hrm_guest_sessions table to ensure the session is still active. Upon successful validation, the system generates new tokens with fresh expiration times. The old refresh_token may be invalidated for security (token rotation) or allowed for stateless refresh. The response contains the new access_token for API authentication and a new refresh_token for subsequent refresh requests.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Token refresh request containing the current refresh token.
     * @x-autobe-authorization-type refresh
     * @x-autobe-authorization-actor guest
     * @x-autobe-specification Extract refresh_token from request body. Validate
     *   refresh_token is not expired. Decode token to get guest session info.
     *   Check erp_hrm_guest_sessions table to verify session exists and not
     *   expired. Optionally extend session expiration. Generate new
     *   access_token with updated expiration. Optionally generate new
     *   refresh_token (token rotation). Return new tokens. If refresh_token is
     *   invalid or expired, return 401 error.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IErpHrmGuest.IRefresh,
  ): Promise<IErpHrmGuest.IAuthorized> {
    try {
      return await postErpHrmAuthGuestRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
