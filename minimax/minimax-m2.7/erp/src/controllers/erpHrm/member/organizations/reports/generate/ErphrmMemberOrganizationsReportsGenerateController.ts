import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IErpHrmReport } from "../../../../../../api/structures/IErpHrmReport";
import { MemberAuth } from "../../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../../decorators/payload/MemberPayload";
import { postErpHrmMemberOrganizationsOrganizationIdReportsGenerate } from "../../../../../../providers/postErpHrmMemberOrganizationsOrganizationIdReportsGenerate";

@Controller("/erpHrm/member/organizations/:organizationId/reports/generate")
export class ErphrmMemberOrganizationsReportsGenerateController {
  /**
   * Generate a new report within the organization.
   *
   * This endpoint creates a new report by accepting report generation parameters including date range, filtering criteria, and grouping preferences. The report is scoped exclusively to the current organization context as defined by the organizationId path parameter.
   *
   * **Report Types**: The system supports three report types as defined in the erp_hrm_reports model: time_report, project_budget_report, and weekly_summary_report. Each type determines the analysis format and data aggregation.
   *
   * **Date Range Filtering**: The start_date and end_date parameters specify the report period. For time reports, the relevant date is the timelog date. For weekly summary reports, the date determines which week the timelog belongs to.
   *
   * **Optional Filters**: The request can include optional filters for specific employee_id, project_id, task_id, and billable status. When these are null, the report includes all relevant data.
   *
   * **Grouping Options**: The group_by parameter accepts 'employee', 'project', or 'task' to organize the report data accordingly.
   *
   * **Authorization**: Only users with the report:view permission can generate reports. Users without this permission receive an access denied response.
   *
   * **Data Isolation**: Reports are generated exclusively from data within the user's current organization. Cross-organization data access is prevented.
   *
   * **Response**: Returns the created report entity with its associated parameters including the generated report ID, report type, name, and timestamps.
   *
   * @param connection
   * @param organizationId The organization's unique identifier (UUID). The report will be generated within this organization scope.
   * @param body Report generation parameters including type, date range, and optional filters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Generate a report for the organization identified by organizationId.
   *
   * 1. Validate that the user has report:view permission within the organization
   * 2. Validate the organizationId matches the user's current organization context
   * 3. Validate required fields: report_type must be one of ['time_report', 'project_budget_report', 'weekly_summary_report']
   * 4. Validate start_date and end_date are valid date ranges (start_date must be before or equal to end_date)
   * 5. Validate group_by is one of ['employee', 'project', 'task'] if provided
   * 6. Validate optional filters reference valid entities within the same organization
   * 7. Create a new erp_hrm_reports record with:
   *    - erp_hrm_organization_id from path parameter
   *    - generated_by_erp_hrm_member_id from session
   *    - report_type from request
   *    - name from request (optional)
   *    - created_at and updated_at as current timestamp
   * 8. Create a new erp_hrm_report_parameters record with:
   *    - erp_hrm_report_id referencing the created report
   *    - All filter parameters from request
   *    - created_at and updated_at as current timestamp
   * 9. Return the complete report with embedded parameters
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("organizationId")
    organizationId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IErpHrmReport.ICreate,
  ): Promise<IErpHrmReport> {
    try {
      return await postErpHrmMemberOrganizationsOrganizationIdReportsGenerate({
        member,
        organizationId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
