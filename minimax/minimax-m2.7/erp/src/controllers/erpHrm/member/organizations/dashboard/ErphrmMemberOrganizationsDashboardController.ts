import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IErpHrmOrganization } from "../../../../../api/structures/IErpHrmOrganization";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { getErpHrmMemberOrganizationsOrganizationIdDashboard } from "../../../../../providers/getErpHrmMemberOrganizationsOrganizationIdDashboard";

@Controller("/erpHrm/member/organizations/:organizationId/dashboard")
export class ErphrmMemberOrganizationsDashboardController {
  /**
   * Retrieve the organization dashboard with aggregate metrics and overview data.
   *
   * This endpoint provides a comprehensive view of an organization's current state, including employee statistics, project summaries, task breakdowns, and time tracking aggregates. The dashboard is designed for organization administrators and managers who need quick insights into organizational performance.
   *
   * The response includes:
   *
   * - **Organization Summary**: Basic organization information including name, employee count, and status
   * - **Employee Statistics**: Breakdown of employees by status (active, deactivated) and employment type
   * - **Project Overview**: Distribution of projects by status (active, archived, completed) and budget utilization
   * - **Task Metrics**: Summary of tasks by status and priority levels
   * - **Time Tracking Data**: Aggregated time logged including billable vs non-billable hours
   * - **Recent Activity**: Latest significant actions within the organization
   *
   * Security: Requires valid member session with organization context. Users must belong to the organization to view its dashboard. The report:view permission is required for accessing detailed metrics.
   *
   * Data Isolation: All metrics are strictly scoped to the specified organization. Cross-organization data access is denied.
   *
   * @param connection
   * @param organizationId Unique identifier of the organization (UUID format, global scope)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification 1. Validate the organizationId from path parameter exists in erp_hrm_organizations table
   * 2. Verify the authenticated user belongs to the organization (via erp_hrm_members and erp_hrm_employees)
   * 3. Enforce organization context isolation - reject if user does not belong to the organization
   * 4. Query employee statistics:
   *    - Count total employees by status (active/deactivated)
   *    - Group by employment_type
   * 5. Query project statistics:
   *    - Count projects by status (active/archived/completed)
   *    - Calculate budget utilization for projects with budget_hours set
   *    - Sum actual hours logged against budget
   * 6. Query task metrics:
   *    - Count tasks by status (open/in-progress/completed/closed)
   *    - Group by priority (low/medium/high/urgent)
   *    - Calculate completion rate
   * 7. Query time tracking aggregates:
   *    - Total hours logged this week/month
   *    - Billable vs non-billable hours breakdown
   *    - Average daily hours
   * 8. Query recent activity from erp_hrm_activity_logs (last 10 entries)
   * 9. Return comprehensive dashboard response with all aggregates
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("organizationId")
    organizationId: string & tags.Format<"uuid">,
  ): Promise<IErpHrmOrganization> {
    try {
      return await getErpHrmMemberOrganizationsOrganizationIdDashboard({
        member,
        organizationId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
