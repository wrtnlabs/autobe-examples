import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IErpHrmReport } from "../../../../../api/structures/IErpHrmReport";
import { IPageIErpHrmReport } from "../../../../../api/structures/IPageIErpHrmReport";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { getErpHrmMemberOrganizationsOrganizationIdReportsReportId } from "../../../../../providers/getErpHrmMemberOrganizationsOrganizationIdReportsReportId";
import { patchErpHrmMemberOrganizationsOrganizationIdReports } from "../../../../../providers/patchErpHrmMemberOrganizationsOrganizationIdReports";
import { postErpHrmMemberOrganizationsOrganizationIdReports } from "../../../../../providers/postErpHrmMemberOrganizationsOrganizationIdReports";
import { putErpHrmMemberOrganizationsOrganizationIdReportsReportId } from "../../../../../providers/putErpHrmMemberOrganizationsOrganizationIdReportsReportId";

@Controller("/erpHrm/member/organizations/:organizationId/reports")
export class ErphrmMemberOrganizationsReportsController {
  /**
   * Create a new report within the specified organization.
   *
   * This endpoint generates a new report based on the provided parameters and stores it for later reference. The report is scoped to the organization specified in the path, ensuring strict data isolation between organizations.
   *
   * The authenticated user must have the report:view permission within the organization to generate reports. The organizationId in the path determines the scope of data included in the report - only data from that organization will be included in the generated analysis.
   *
   * Three report types are supported: time reports showing hours logged with billable breakdown, project budget reports comparing estimated versus actual hours, and weekly summary reports providing rolling week-by-week metrics.
   *
   * The report parameters include a date range (start_date and end_date), optional filters for specific employees, projects, or tasks, a billable status filter, and a grouping preference to organize the report data.
   *
   * The generated_by field is automatically set to the authenticated user from the current session. The created_at timestamp records when the report was generated.
   *
   * To retrieve a previously generated report, use the GET /organizations/{organizationId}/reports/{reportId} endpoint. To list all reports in an organization, use the PATCH /organizations/{organizationId}/reports endpoint with search filters.
   *
   * @param connection
   * @param organizationId The unique identifier of the organization to create the report in
   * @param body Report creation data including type, optional name, and filter parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Create a new report record with its associated parameters.
   *
   * 1. Validate that the authenticated user has report:view permission in the organization.
   * 2. Validate that organizationId from path exists and user has access to it.
   * 3. Validate required fields: report_type must be one of 'time_report', 'project_budget_report', 'weekly_summary_report'; start_date and end_date are required; group_by must be 'employee', 'project', or 'task'.
   * 4. Validate date range: start_date must be before or equal to end_date.
   * 5. If employee_id is provided, validate it belongs to the same organization.
   * 6. If project_id is provided, validate it belongs to the same organization.
   * 7. If task_id is provided, validate it belongs to a project in the same organization.
   * 8. Create the erp_hrm_reports record with: id (UUID), erp_hrm_organization_id, generated_by_erp_hrm_member_id (from session), report_type, name (if provided), created_at, updated_at.
   * 9. Create the erp_hrm_report_parameters record linked to the new report with all filter parameters.
   * 10. Return the complete report including its parameters in the response.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("organizationId")
    organizationId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IErpHrmReport.ICreate,
  ): Promise<IErpHrmReport> {
    try {
      return await postErpHrmMemberOrganizationsOrganizationIdReports({
        member,
        organizationId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a filtered and paginated list of reports within an organization.
   *
   * This operation lists all reports generated in the organization, with support for filtering by report type, date range, and the member who generated the report. Results are paginated and sorted by creation date in descending order by default.
   *
   * Each report is scoped to the organization specified in the path parameter. The system enforces strict data isolation - reports from one organization are never visible to users of another organization, even if the user belongs to multiple organizations. The user's currently selected organization context determines which organization's reports are accessible.
   *
   * This operation requires the user to have the report:view permission within the organization. Users without this permission will receive an access denied error.
   *
   * The response includes report metadata such as the report type, name, creation timestamp, and the member who generated it. Detailed report parameters (date range, filters, grouping preferences) are accessible through a separate endpoint using the report ID.
   *
   * Related operations: GET /organizations/{organizationId}/reports/{reportId} for retrieving a single report, GET /organizations/{organizationId}/reports/{reportId}/parameters for report parameters.
   *
   * @param connection
   * @param organizationId Unique identifier of the organization (global scope)
   * @param body Search criteria and pagination parameters for filtering reports
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query erp_hrm_reports table filtering by erp_hrm_organization_id matching the path parameter.
   *
   * Apply the following search filters from the request body:
   * - report_type: Filter by report type (time_report, project_budget_report, weekly_summary_report)
   * - name: Partial match on optional report name
   * - start_date / end_date: Filter reports created within the date range
   * - generated_by_member_id: Filter by the member who generated the report
   *
   * Always filter by erp_hrm_organization_id to enforce data isolation.
   *
   * Join with erp_hrm_members table to include generated_by_member information in response.
   *
   * Apply cursor-based pagination using page and limit parameters.
   *
   * Sort by created_at descending (newest first).
   *
   * Return paginated results with pagination metadata (total count, page info).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("organizationId")
    organizationId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IErpHrmReport.IRequest,
  ): Promise<IPageIErpHrmReport.ISummary> {
    try {
      return await patchErpHrmMemberOrganizationsOrganizationIdReports({
        member,
        organizationId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific report by its unique identifier within an organization.
   *
   * This endpoint returns detailed information about a stored report including the report type, display name, generation timestamp, and metadata about who created it. The report must belong to the specified organization in the path.
   *
   * Security: This operation requires the report:view permission. Users without this permission will receive an access denied response. The system enforces strict data isolation - reports from one organization cannot be accessed by users from another organization, even if the user belongs to multiple organizations.
   *
   * Data Isolation: The system validates that the specified organizationId in the path matches the erp_hrm_organization_id of the report. If the report belongs to a different organization, the request is rejected with an access denied error.
   *
   * Relationship to Database: This operation queries the erp_hrm_reports table using the reportId as the primary key. The response includes the generatedByMember relation for displaying who created the report.
   *
   * Related Operations: Use the report list endpoint (PATCH /organizations/{organizationId}/reports) to search and filter available reports. Use the report generation endpoint to create new reports with specific parameters.
   *
   * @param connection
   * @param organizationId The unique identifier of the organization (tenant scope)
   * @param reportId The unique identifier of the report to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification 1. Extract organizationId and reportId from path parameters.
   * 2. Verify user has active organization context and the selected organization matches organizationId.
   * 3. Verify user possesses report:view permission in the current organization context.
   * 4. Query erp_hrm_reports table filtering by id = reportId AND erp_hrm_organization_id = organizationId.
   * 5. If no report found or report belongs to different organization, return 403 Forbidden.
   * 6. Load the generatedByMember relation to include creator information.
   * 7. Return the report entity with all fields including report_type, name, created_at, updated_at.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":reportId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("organizationId")
    organizationId: string & tags.Format<"uuid">,
    @TypedParam("reportId")
    reportId: string & tags.Format<"uuid">,
  ): Promise<IErpHrmReport> {
    try {
      return await getErpHrmMemberOrganizationsOrganizationIdReportsReportId({
        member,
        organizationId,
        reportId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing report within the organization.
   *
   * This operation modifies the metadata of a stored report, including its optional display name. The report parameters (date range, filtering criteria, grouping preferences) can also be updated through this endpoint. All updates are scoped to the user's currently selected organization context, ensuring strict data isolation between organizations.
   *
   * Security: Users must have the report:view permission to access and modify reports. The system enforces that reports cannot be accessed or modified across organization boundaries. When updating report parameters, all filter criteria (date range, employee, project, task, billable status, grouping) can be modified.
   *
   * The report must belong to the specified organization. If the report does not exist or belongs to a different organization, the system returns a not found error.
   *
   * Related Operations:
   * - POST /organizations/{organizationId}/reports: Create a new report
   * - GET /organizations/{organizationId}/reports/{reportId}: Retrieve report details
   * - GET /organizations/{organizationId}/reports: List reports in the organization
   *
   * @param connection
   * @param organizationId The unique identifier of the organization (global scope)
   * @param reportId The unique identifier of the report to update
   * @param body Report update data including optional name and parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Update an existing report in the erp_hrm_reports table.
   *
   * 1. Validate user has report:view permission in the current organization context
   * 2. Verify organization context matches the organizationId parameter
   * 3. Query erp_hrm_reports table for the report by reportId where erp_hrm_organization_id matches the current organization
   * 4. If report not found, return 404 error
   * 5. Update allowed fields: name (optional), updated_at timestamp
   * 6. If request includes parameters, update erp_hrm_report_parameters table:
   *    - Validate date range (start_date <= end_date)
   *    - Validate group_by is one of: employee, project, task
   *    - Validate billable filter value (true, false, or null)
   *    - Validate employee_id, project_id, task_id if provided exist in organization
   * 7. Set updated_at to current timestamp
   * 8. Return the updated report with its parameters
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":reportId")
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("organizationId")
    organizationId: string & tags.Format<"uuid">,
    @TypedParam("reportId")
    reportId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IErpHrmReport.IUpdate,
  ): Promise<IErpHrmReport> {
    try {
      return await putErpHrmMemberOrganizationsOrganizationIdReportsReportId({
        member,
        organizationId,
        reportId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
