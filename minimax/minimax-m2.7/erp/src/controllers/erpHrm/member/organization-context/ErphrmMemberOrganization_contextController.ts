import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IErpHrmOrganizationContext } from "../../../../api/structures/IErpHrmOrganizationContext";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { postErpHrmMemberOrganizationContext } from "../../../../providers/postErpHrmMemberOrganizationContext";

@Controller("/erpHrm/member/organization-context")
export class ErphrmMemberOrganization_contextController {
  /**
   * Set the active organization context for the current session.
   *
   * This endpoint allows users who belong to multiple organizations to switch between them. When a user selects an organization, all subsequent API operations are scoped to that organization until the context is changed again.
   *
   * The user must be a member of the target organization to successfully switch context. Only organizations where the user has an active employee record are available for selection.
   *
   * This operation updates the session state to reflect the newly selected organization. The response includes organization details and the user's permissions within that organization context.
   *
   * @param connection
   * @param body The organization identifier to switch to
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Validate the user making the request is authenticated.
   * Extract the user ID from the current session.
   * Verify the user has an active employee record in the target organization.
   * Retrieve the employee record for the user within the target organization, including their role.
   * Retrieve all permissions assigned to the employee's role.
   * Update the session to set the new organization context.
   * Return the organization details, employee information, and role permissions.
   *
   * Edge cases:
   * - If the user is not a member of the target organization, return 403 Forbidden.
   * - If the employee record is deactivated, return 403 Forbidden.
   * - If the target organization does not exist, return 404 Not Found.
   * - If no organization is specified in the request, return 400 Bad Request.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async select(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IErpHrmOrganizationContext.ICreate,
  ): Promise<IErpHrmOrganizationContext> {
    try {
      return await postErpHrmMemberOrganizationContext({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
