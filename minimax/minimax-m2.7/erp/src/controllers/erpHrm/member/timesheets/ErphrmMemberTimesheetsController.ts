import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IErpHrmTimesheet } from "../../../../api/structures/IErpHrmTimesheet";
import { IPageIErpHrmTimesheet } from "../../../../api/structures/IPageIErpHrmTimesheet";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { deleteErpHrmMemberTimesheetsTimesheetId } from "../../../../providers/deleteErpHrmMemberTimesheetsTimesheetId";
import { getErpHrmMemberTimesheetsTimesheetId } from "../../../../providers/getErpHrmMemberTimesheetsTimesheetId";
import { patchErpHrmMemberTimesheets } from "../../../../providers/patchErpHrmMemberTimesheets";
import { postErpHrmMemberTimesheets } from "../../../../providers/postErpHrmMemberTimesheets";
import { postErpHrmMemberTimesheetsTimesheetIdSubmit } from "../../../../providers/postErpHrmMemberTimesheetsTimesheetIdSubmit";
import { putErpHrmMemberTimesheetsTimesheetId } from "../../../../providers/putErpHrmMemberTimesheetsTimesheetId";

@Controller("/erpHrm/member/timesheets")
export class ErphrmMemberTimesheetsController {
  /**
   * Create a new draft timesheet for the authenticated employee.
   *
   * This endpoint creates a draft timesheet covering a specific work week (Monday to Sunday). The week start date provided by the employee determines both the start and end dates of the timesheet. All timelogs belonging to the employee that fall within the Monday through Sunday date range are automatically associated with the new draft timesheet.
   *
   * The created timesheet remains in draft status until the employee submits it for approval. While in draft status, the employee can add or remove timelogs and modify the timesheet as needed. Each employee can have only one timesheet (draft, submitted, or approved) per week.
   *
   * The response returns the complete created timesheet including the auto-calculated week end date, the initial total hours from included timelogs, and timestamps for creation.
   *
   * @param connection
   * @param body Week start date (Monday) for the timesheet to be created
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Validate the authenticated employee exists and
     *   has an active status in the current organization context. Validate that
     *   week_start_date is a Monday. Calculate week_end_date as the following
     *   Sunday (week_start_date + 6 days). Verify no existing timesheet (any
     *   status) exists for this employee with the same week_start_date. Query
     *   all timelogs belonging to the employee where timelog date falls within
     *   [week_start_date, week_end_date]. Calculate total_hours by summing all
     *   found timelogs. Create the timesheet with status 'draft', include all
     *   found timelogs via the erp_hrm_timesheet_timelogs junction table.
     *   Return the created timesheet with associated timelogs and employee
     *   information.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IErpHrmTimesheet.ICreate,
  ): Promise<IErpHrmTimesheet> {
    try {
      return await postErpHrmMemberTimesheets({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a filtered and paginated list of timesheets.
   *
   * This operation provides search capabilities for timesheets within the current organization context. Employees can only view their own timesheets, while users with time:approve permission can view all employees' timesheets for approval workflow management.
   *
   * Supports filtering by timesheet status (draft, submitted, approved, rejected) and date range (week_start_date boundaries). The response includes timesheet summaries optimized for list displays with key information such as status, total hours, and submission dates.
   *
   * When an employee views their timesheets, the results are automatically scoped to that employee. When a user with time:approve permission views timesheets, results include all employees' timesheets within the organization.
   *
   * @param connection
   * @param body Search criteria including optional filters for status, date range, employee, and pagination parameters
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query erp_hrm_timesheets table with
     *   organization-scoped filtering.
   *
   * 1. Extract organization context from the authenticated session.
   * 2. If the current user has time:approve permission:
   *    - Apply optional status filter (draft, submitted, approved, rejected)
   *    - Apply optional employee_id filter to scope results to specific employee
   *    - Apply optional week_start_date range filters (gte/lte for date boundaries)
   * 3. If the current user does NOT have time:approve permission:
   *    - Automatically scope results to the current user's employee record
   *    - Apply same optional filters as above (except employee_id, which is fixed)
   * 4. Apply pagination with configurable page size (default 20, max 100) and cursor-based pagination using created_at for consistent ordering.
   * 5. Join with erp_hrm_employees table to include employee name in summary (for approvers viewing all employees' timesheets).
   * 6. Order by created_at descending (newest first).
   * 7. Calculate total_hours from the timesheet's included timelogs.
   * 8. Return paginated results with IPageIErpHrmTimesheet.ISummary format.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IErpHrmTimesheet.IRequest,
  ): Promise<IPageIErpHrmTimesheet.ISummary> {
    try {
      return await patchErpHrmMemberTimesheets({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific timesheet by its unique identifier.
   *
   * This endpoint returns detailed information about a single timesheet including its status, date range, total hours, included timelogs, and review information. The response includes the owning employee details and reviewer information when the timesheet has been reviewed.
   *
   * The owning employee can view their own timesheets in any status. Users with time:view_all permission can view all employees' timesheets. Users with time:approve permission can view submitted, approved, or rejected timesheets for approval workflow purposes.
   *
   * When the timesheet status is rejected, the response includes the rejection_reason field populated by the reviewing user. Approved timesheets have all their included timelogs locked from editing.
   *
   * @param connection
   * @param timesheetId Unique identifier of the timesheet to retrieve.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query erp_hrm_timesheets table by id (UUID
     *   primary key).
   *
   * Join with erp_hrm_employees to include employee details (id, position, employment_type, status).
   *
   * Join with erp_hrm_employees (reviewer) when reviewer_employee_id is not null to include reviewer details.
   *
   * Join with erp_hrm_timesheet_timelogs and erp_hrm_timelogs to include all associated timelog entries.
   *
   * For each included timelog, include: id, date, duration_minutes, description, billable, project_id, task_id, created_at.
   *
   * Authorization:
   * - If requester is the owning employee: allow access to their own timesheet
   * - If requester has time:view_all permission: allow access to any timesheet in the organization
   * - If requester has time:approve permission: allow access to timesheets in submitted/approved/rejected status
   * - Otherwise: return 403 Forbidden
   *
   * Return 404 Not Found if timesheet does not exist or belongs to a different organization.
   *
   * Soft-deleted timesheets (deleted_at is not null) should return 404.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":timesheetId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("timesheetId")
    timesheetId: string & tags.Format<"uuid">,
  ): Promise<IErpHrmTimesheet> {
    try {
      return await getErpHrmMemberTimesheetsTimesheetId({
        member,
        timesheetId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing timesheet owned by the authenticated employee.
   *
   * This endpoint allows employees to modify their draft timesheets before submission or after rejection. Timesheets with status 'submitted' or 'approved' cannot be modified through this endpoint.
   *
   * When a timesheet is rejected by a reviewer, it automatically returns to draft status, allowing the employee to make corrections and resubmit. The rejection reason provided by the reviewer is visible on the timesheet and should be addressed before resubmission.
   *
   * Only the employee who owns the timesheet can update it. If the timesheet is rejected, updating it does not automatically resubmit - the employee must explicitly submit again after making corrections.
   *
   * The week_start_date and week_end_date cannot be changed once the timesheet has been submitted, as these define the immutable billing period.
   *
   * @param connection
   * @param timesheetId Unique identifier of the timesheet to update
   * @param body Fields to update on the timesheet. Only draft timesheets (including rejected timesheets) can be updated. Status can be changed to 'submitted' for submission workflow.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification 1. Retrieve the timesheet by timesheetId from
     *   erp_hrm_timesheets table. 2. Verify the authenticated employee owns
     *   this timesheet (erp_hrm_employee_id matches current user session
     *   employee). 3. If timesheet status is not 'draft', return 403 Forbidden
     *   with message indicating only draft timesheets can be updated. 4.
     *   Validate request body fields according to IErpHrmTimesheet.IUpdate
     *   schema. 5. Update only the provided fields: status transition to
     *   'submitted', rejection_reason, week_start_date, week_end_date. 6. If
     *   status is changed to 'submitted', validate: timesheet contains at least
     *   one timelog, no duplicate submitted/approved timesheet exists for same
     *   employee and week. 7. If status is changed to 'submitted', set
     *   submitted_at to current timestamp. 8. Recalculate total_hours from
     *   associated timelogs in erp_hrm_timesheet_timelogs junction table. 9.
     *   Update updated_at timestamp. 10. Return the updated IErpHrmTimesheet
     *   entity.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":timesheetId")
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("timesheetId")
    timesheetId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IErpHrmTimesheet.IUpdate,
  ): Promise<IErpHrmTimesheet> {
    try {
      return await putErpHrmMemberTimesheetsTimesheetId({
        member,
        timesheetId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a draft or rejected timesheet and remove all its associations with timelogs.
   *
   * This operation permanently removes the timesheet and its link records from the database. The timelogs themselves are preserved and remain accessible outside any timesheet context. Only timesheets in draft or rejected status can be deleted; submitted or approved timesheets cannot be removed.
   *
   * The requesting user must be either the timesheet owner or possess the time:manage permission. The system validates ownership and permission before proceeding with deletion. Once deleted, the timesheet cannot be recovered and any rejection reason is lost.
   *
   * @param connection
   * @param timesheetId Unique identifier of the timesheet to delete
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Validate the timesheet exists and belongs to the
     *   current organization context. Verify the requesting user is either the
     *   timesheet owner (erp_hrm_employee_id matches authenticated employee) or
     *   has time:manage permission.
   *
   * Check timesheet status: if status is 'submitted' or 'approved', reject the deletion request with error 'TIMESHEET_NOT_DRAFT'. Only status 'draft' or 'rejected' can be deleted.
   *
   * Delete the timesheet record from erp_hrm_timesheets table. The Cascade onDelete for erp_hrm_timesheet_timelogs will automatically remove association records.
   *
   * Timelogs linked to this timesheet remain unchanged in erp_hrm_timelogs table.
   *
   * Return 204 No Content on success. Return 404 Not Found if timesheetId does not exist in organization. Return 403 Forbidden if user lacks permission or timesheet belongs to another employee without time:manage. Return 400 Bad Request if timesheet status is not draft or rejected.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":timesheetId")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("timesheetId")
    timesheetId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteErpHrmMemberTimesheetsTimesheetId({
        member,
        timesheetId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Submit a draft timesheet for manager approval.
   *
   * This operation transitions a timesheet from draft status to submitted status, entering the approval workflow. Only timesheets in draft status can be submitted. The system validates that the timesheet contains at least one timelog and that no other timesheet for the same employee and week already exists with submitted or approved status.
   *
   * Upon successful submission, the timesheet is locked from further modifications by the employee until it has been reviewed. The submitting employee must be the owner of the timesheet. Managers with time:approve permission review submitted timesheets.
   *
   * The response returns the updated timesheet with submitted_at timestamp recorded.
   *
   * @param connection
   * @param timesheetId Unique identifier of the timesheet to submit (UUID format)
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Execute timesheet submission workflow for draft
     *   timesheets.
   *
   * 1. Validate the timesheet exists in erp_hrm_timesheets with the given timesheetId.
   * 2. Verify the authenticated employee is the owner of the timesheet (erp_hrm_employee_id matches session employee).
   * 3. Verify the timesheet status equals 'draft'. Reject if status is 'submitted', 'approved', or 'rejected'.
   * 4. Query erp_hrm_timesheet_timelogs to verify the timesheet contains at least one timelog. Reject submission if no timelogs are associated.
   * 5. Check for duplicate submission: query erp_hrm_timesheets to ensure no other timesheet exists for the same erp_hrm_employee_id and week_start_date with status 'submitted' or 'approved'. Reject if duplicate found.
   * 6. Calculate total_hours by summing duration_minutes from all associated timelogs in erp_hrm_timesheet_timelogs joined with erp_hrm_timelogs.
   * 7. Update the timesheet: set status to 'submitted', set submitted_at to current timestamp, update total_hours, update updated_at to current timestamp.
   * 8. Return the updated timesheet with all fields including reviewer_employee relation (null) and timesheetTimelogs relation.
   *
   * Edge cases:
   * - Timesheet not found: return 404
   * - Unauthorized (not owner): return 403
   * - Already submitted/approved/rejected: return 400 with appropriate message
   * - Empty timesheet (no timelogs): return 400 indicating timesheet must contain timelogs
   * - Duplicate week conflict: return 409 with message about existing submission
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post(":timesheetId/submit")
  public async submit(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("timesheetId")
    timesheetId: string & tags.Format<"uuid">,
  ): Promise<IErpHrmTimesheet> {
    try {
      return await postErpHrmMemberTimesheetsTimesheetIdSubmit({
        member,
        timesheetId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
