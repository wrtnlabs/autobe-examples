import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IErpHrmTimelog } from "../../../../api/structures/IErpHrmTimelog";
import { IErpHrmTimer } from "../../../../api/structures/IErpHrmTimer";
import { IPageIErpHrmTimer } from "../../../../api/structures/IPageIErpHrmTimer";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { deleteErpHrmMemberTimersTimerId } from "../../../../providers/deleteErpHrmMemberTimersTimerId";
import { getErpHrmMemberTimers } from "../../../../providers/getErpHrmMemberTimers";
import { patchErpHrmMemberTimers } from "../../../../providers/patchErpHrmMemberTimers";
import { postErpHrmMemberTimers } from "../../../../providers/postErpHrmMemberTimers";
import { postErpHrmMemberTimersStop } from "../../../../providers/postErpHrmMemberTimersStop";
import { putErpHrmMemberTimers } from "../../../../providers/putErpHrmMemberTimers";

@Controller("/erpHrm/member/timers")
export class ErphrmMemberTimersController {
  /**
   * Retrieve the currently running timer for the authenticated employee.
   *
   * This endpoint returns the active timer owned by the authenticated employee. Each employee can have at most one timer running at any given time.
   *
   * The response includes the timer's complete details: the associated project and optional task, the description of work being tracked, the start timestamp, and the elapsed time calculated from the start timestamp to the current time.
   *
   * If the authenticated employee has no running timer, the response returns null with a 200 status code.
   *
   * This operation respects timer privacy — employees cannot view other employees' active timers. The existence of another employee's timer is never exposed through any API endpoint.
   *
   * @param connection
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query the erp_hrm_timers table filtering by
     *   erp_hrm_employee_id matching the authenticated employee from session
     *   context. Enforce @@unique constraint ensures at most one timer per
     *   employee. Join with erp_hrm_projects to include project details (name,
     *   color) and with erp_hrm_tasks to include task details (title) when
     *   task_id is present. Calculate elapsed time as current_time minus
     *   started_at. Return null if no active timer found. If timer exists,
     *   return complete timer details including nested project and task
     *   objects. Handle deactivated employee by rejecting request with
     *   appropriate error.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @MemberAuth()
    member: MemberPayload,
  ): Promise<IErpHrmTimer.IInvert> {
    try {
      return await getErpHrmMemberTimers({
        member,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Start a new live timer session for real-time time tracking.
   *
   * This endpoint initiates a timer that tracks time in real-time against a selected project. The timer records the start timestamp immediately and continues running until the employee stops or discards it.
   *
   * Business rules:
   * - An employee can have at most one active timer at any given time
   * - The selected project must be one the employee is assigned to as a project member
   * - The optional task must belong to the selected project
   * - Only employees with active status can start timers
   * - Deactivated employees cannot start new timers
   *
   * When stopped, the timer creates a timelog entry with the calculated duration. When discarded, no record is created.
   *
   * @param connection
   * @param body Timer creation payload with project and optional task selection
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification 1. Extract the authenticated employee from the
     *   request context (via session token) 2. Validate employee status is
     *   'active' - reject if deactivated 3. Check if employee already has an
     *   active timer in erp_hrm_timers table - Query: SELECT id FROM
     *   erp_hrm_timers WHERE erp_hrm_employee_id = {employeeId} - If exists,
     *   return 409 Conflict error with message 'An active timer already exists'
     *   4. Validate erp_hrm_project_id exists in request body 5. Verify
     *   employee is assigned to the project via erp_hrm_project_members -
     *   Query: SELECT 1 FROM erp_hrm_project_members WHERE erp_hrm_employee_id
     *   = {employeeId} AND erp_hrm_project_id = {projectId} - If not found,
     *   return 400 Bad Request error 6. If erp_hrm_task_id is provided: -
     *   Verify task exists and belongs to the selected project - Query: SELECT
     *   1 FROM erp_hrm_tasks WHERE id = {taskId} AND erp_hrm_project_id =
     *   {projectId} - If not found, return 400 Bad Request error 7. Create
     *   timer record: - id: generate UUID - erp_hrm_employee_id: from
     *   authenticated context - erp_hrm_project_id: from request body -
     *   erp_hrm_task_id: from request body (nullable) - started_at: current
     *   timestamp (UTC) - description: from request body (nullable) -
     *   created_at: current timestamp (UTC) - updated_at: current timestamp
     *   (UTC) 8. Return the created timer with 201 Created status
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IErpHrmTimer.ICreate,
  ): Promise<IErpHrmTimer> {
    try {
      return await postErpHrmMemberTimers({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update the currently running timer for the authenticated employee.
   *
   * This operation allows employees to modify the properties of their active timer while it is running. The update can change the description, selected project, and/or task being tracked. The original start timestamp is preserved regardless of any edits made.
   *
   * The project can be changed to any project the employee is assigned to as a project member. When changing the project, any previously selected task is cleared if it does not belong to the new project. Task can only be changed to tasks within the currently selected project.
   *
   * This endpoint only operates on the employee's own active timer. Other employees' timers are not accessible through this operation.
   *
   * @param connection
   * @param body Fields to update on the running timer - all fields are optional
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Update the running timer associated with the
     *   authenticated employee.
   *
   * Implementation steps:
   * 1. Extract employee_id from authenticated session context
   * 2. Query erp_hrm_timers table to find the active timer for this employee (using the unique constraint on erp_hrm_employee_id)
   * 3. If no active timer exists, return error indicating no running timer to update
   * 4. Validate the request body:
   *    - If project_id is provided, verify employee is assigned to that project (check erp_hrm_project_members)
   *    - If task_id is provided, verify task belongs to the selected project (check erp_hrm_tasks)
   * 5. Update only the fields provided in the request body:
   *    - description: optional string
   *    - project_id: optional UUID, must be assigned project membership
   *    - task_id: optional UUID, must belong to selected project
   * 6. When updating project_id, clear task_id if the previous task does not belong to new project
   * 7. Update updated_at timestamp
   * 8. Return the complete updated timer entity with all fields including the original started_at
   *
   * Edge cases:
   * - Employee has no active timer: return 404 with message
   * - Project not assigned to employee: return 400 with validation error
   * - Task does not belong to project: return 400 with validation error
   * - Deactivated employee: return 403 error
   * - Only include fields that are explicitly provided in request
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IErpHrmTimer.IUpdate,
  ): Promise<IErpHrmTimer> {
    try {
      return await putErpHrmMemberTimers({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve the authenticated employee's timer records with optional filtering.
   *
   * This endpoint allows employees to view their running timer status and search through their timer history. Each employee can have at most one active timer at a time, enforced by the database unique constraint on employee_id.
   *
   * Timer records are private to the employee who created them. Other employees, including managers and project leads, cannot view another employee's timers. Only the employee who owns the timer and organization administrators with system-level access can retrieve timer information.
   *
   * The response includes the timer details along with associated project and task information. If no active timer exists, an empty result is returned.
   *
   * @param connection
   * @param body Optional search filters for timer queries including project filter
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query the erp_hrm_timers table filtering by the
     *   authenticated employee's ID from the session context.
   *
   * Apply optional filters from the request body:
   * - Filter by erp_hrm_project_id if project filter is provided
   * - Filter by timer status if specified (active/running only)
   *
   * Join with erp_hrm_projects table to include project details (name, color_code) in the response.
   * Join with erp_hrm_tasks table to include task details (title) if a task is associated.
   *
   * Return timer records sorted by started_at descending (most recent first).
   * Apply pagination with configurable page size.
   *
   * If no timer exists for the employee, return empty array.
   *
   * Ensure data isolation: only return timers belonging to the authenticated employee.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IErpHrmTimer.IRequest,
  ): Promise<IPageIErpHrmTimer.ISummary> {
    try {
      return await patchErpHrmMemberTimers({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Discard the employee's currently active timer.
   *
   * This operation immediately terminates the specified timer without creating a timelog entry. The timer must belong to the authenticated employee making the request. Once discarded, the timer is permanently removed and cannot be recovered.
   *
   * The employee must have an active timer to discard. If the timer does not exist or belongs to another employee, the system returns a not found error. This operation does not generate any activity log entry since discarded timers do not create historical records.
   *
   * @param connection
   * @param timerId Unique identifier of the timer to discard
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Validate that the timer exists in the database.
     *   Verify the timer belongs to the authenticated employee by matching
     *   erp_hrm_employee_id with the current session's employee record. If the
     *   timer does not exist, return 404 not found error. If the timer belongs
     *   to another employee, return 404 not found error (do not reveal
     *   existence of other employees' timers for privacy). Permanently delete
     *   the timer record from erp_hrm_timers table using cascade delete. Do not
     *   create any timelog entry. Do not create any activity log entry. Return
     *   204 No Content on success.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":timerId")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("timerId")
    timerId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteErpHrmMemberTimersTimerId({
        member,
        timerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Stop the authenticated employee's active timer and optionally create a timelog entry.
   *
   * When an employee requests to stop their running timer, the system calculates the duration from the start timestamp to the current time, rounds it to the nearest minute, and creates a corresponding timelog entry. The timer is then removed from the system.
   *
   * If the discard option is specified, the timer is stopped without creating any timelog entry. This allows employees to abandon time tracking without generating records.
   *
   * The resulting timelog includes the project, optional task, calculated duration, and description from the timer. The billable flag is set to true by default. The timelog date is set to the current date.
   *
   * Only employees with active status can stop timers. Deactivated employees cannot perform this operation.
   *
   * @param connection
   * @param body Optional flag to discard timer without creating timelog. Defaults to false.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Stop timer operation flow:
   *
   * 1. Retrieve authenticated employee from session context
   * 2. Query erp_hrm_timers table for timer with erp_hrm_employee_id matching authenticated employee
   * 3. Verify timer exists - return 404 if no active timer found
   * 4. Verify employee status is active - return 403 if deactivated
   * 5. Calculate duration: current_time - timer.started_at in minutes
   * 6. Round duration: if seconds < 30, round down to 0; if seconds >= 30, round up to next minute
   * 7. If request body discard flag is true:
   *    - Delete timer from erp_hrm_timers table
   *    - Return empty response with 204 status
   * 8. If discard flag is false (default):
   *    - Create new erp_hrm_timelogs entry with:
   *      * erp_hrm_employee_id: from timer
   *      * erp_hrm_project_id: from timer
   *      * erp_hrm_task_id: from timer (nullable)
   *      * date: current date at midnight (date-only, ignore time)
   *      * duration_minutes: calculated rounded duration
   *      * description: from timer description
   *      * billable: true (default)
   *    - Delete timer from erp_hrm_timers table
   *    - Return created timelog with 201 status
   *
   * Edge cases:
   * - Timer with no description: proceed with null description
   * - Timer with no task: proceed with null erp_hrm_task_id
   * - Concurrent stop requests: use database transaction to ensure atomicity
   * - Very long running timer: no time limit, calculate as-is
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("stop")
  public async stop(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IErpHrmTimer.IStop,
  ): Promise<IErpHrmTimelog> {
    try {
      return await postErpHrmMemberTimersStop({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
