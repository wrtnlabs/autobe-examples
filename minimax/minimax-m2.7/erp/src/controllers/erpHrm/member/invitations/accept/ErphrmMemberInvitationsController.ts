import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IErpHrmInvitation } from "../../../../../api/structures/IErpHrmInvitation";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { postErpHrmMemberInvitationsTokenAccept } from "../../../../../providers/postErpHrmMemberInvitationsTokenAccept";

@Controller("/erpHrm/member/invitations/:token/accept")
export class ErphrmMemberInvitationsController {
  /**
   * Accept an organization invitation using a secure invitation token.
   *
   * This endpoint allows authenticated users to accept invitations sent by organizations. When called, the system validates the invitation token, verifies the invitation is still pending and not expired, and creates an employee record linking the user to the inviting organization.
   *
   * The authenticated user must match the email address specified in the invitation. Upon successful acceptance, the user gains access to the organization's data and can begin participating as an employee.
   *
   * The invitation status transitions from 'pending' to 'accepted', and the accepted_at timestamp is recorded. If the invitation has already been accepted or has expired, the request fails with an appropriate error.
   *
   * @param connection
   * @param token Secure token from the invitation link used to verify and accept the invitation
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification 1. Extract token from path parameter 2. Query
     *   erp_hrm_invitations table to find invitation by token 3. Validate
     *   invitation exists and is not soft-deleted (deleted_at is null) 4.
     *   Validate invitation status is 'pending' - reject if already 'accepted'
     *   or 'expired' 5. Validate invitation has not expired - check expires_at
     *   is null or in the future 6. Validate authenticated user's email matches
     *   the invitation's email address 7. Create employee record in
     *   erp_hrm_employees with: - erp_hrm_user_id: authenticated user's ID -
     *   erp_hrm_organization_id: from invitation - erp_hrm_role_id: from
     *   invitation (use default role if null) - erp_hrm_department_id: from
     *   invitation (optional) - position: from invitation's position field
     *   (optional) - employment_type: default to 'full-time' - status: 'active'
     *   8. Update invitation record: - status: 'accepted' - accepted_at:
     *   current timestamp 9. Record activity in erp_hrm_activity_logs 10.
     *   Return the accepted invitation with IErpHrmInvitation type
   *
   * Error handling:
   * - 404: Invitation not found or invalid token
   * - 400: Invitation already accepted or expired
   * - 403: User email does not match invitation email
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async accept(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("token")
    token: string,
  ): Promise<IErpHrmInvitation> {
    try {
      return await postErpHrmMemberInvitationsTokenAccept({
        member,
        token,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
