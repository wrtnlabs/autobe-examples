import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IErpHrmMember } from "../../../../api/structures/IErpHrmMember";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getErpHrmMemberProfile } from "../../../../providers/getErpHrmMemberProfile";
import { patchErpHrmMemberProfile } from "../../../../providers/patchErpHrmMemberProfile";

@Controller("/erpHrm/member/profile")
export class ErphrmMemberProfileController {
  /**
   * Retrieve the authenticated user's global profile information.
   *
   * This endpoint returns the profile data of the currently authenticated member. The profile is shared across all organizations the user belongs to, including display name, avatar image, and phone number.
   *
   * The returned profile includes the user's display name shown in employee records, activity logs, and timesheets. The avatar URI provides a link to the user's profile picture, or null if no avatar has been uploaded. The phone number field is optional for work-related contact purposes.
   *
   * This operation is scoped to the authenticated session and does not require any path parameters.
   *
   * @param connection
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query the erp_hrm_members table using the
     *   authenticated member's ID from the session token.
   *
   * Return the member's profile including: id, email, display_name, avatar_uri, phone, created_at, updated_at.
   *
   * Do NOT return the password_hash field for security reasons.
   *
   * If the member record has been soft-deleted (deleted_at is not null), return 404 Not Found.
   *
   * Join with any related data only if explicitly required for the profile display.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @MemberAuth()
    member: MemberPayload,
  ): Promise<IErpHrmMember> {
    try {
      return await getErpHrmMemberProfile({
        member,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update the authenticated user's profile information.
   *
   * This endpoint allows authenticated members to modify their personal profile data including display name, avatar image, phone number, and password. Changes are immediately reflected across all organizations the user belongs to since the profile is globally shared.
   *
   * The user can update any subset of fields in a single request. Email address cannot be changed through this endpoint for security reasons.
   *
   * This operation requires an active session with valid member authentication.
   *
   * @param connection
   * @param body Partial update fields for the authenticated user's profile
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Validate the request body contains at least one
     *   updatable field. For display_name: ensure non-empty string, max 255
     *   characters. For avatar_uri: validate it is a valid URI format if
     *   provided. For phone: validate format if provided. For password:
     *   validate minimum 8 characters, must include at least one letter and one
     *   number.
   *
   * Apply updates to the erp_hrm_members record using the authenticated user's ID from the session token. Update the updated_at timestamp to current time.
   *
   * Return the full updated member record excluding the password_hash field for security.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IErpHrmMember.IUpdate,
  ): Promise<IErpHrmMember> {
    try {
      return await patchErpHrmMemberProfile({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
