import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IErpHrmMember } from "../../../../api/structures/IErpHrmMember";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { putErpHrmMemberProfile } from "../../../../providers/putErpHrmMemberProfile";

@Controller("/erpHrm/member/profile")
export class ErphrmMemberProfileController {
  /**
   * Update the authenticated user's profile information.
   *
   * This endpoint allows authenticated members to modify their own profile data including display name, avatar image, and phone number. The profile information is shared across all organizations the user belongs to, so changes made here are immediately reflected in all organization contexts.
   *
   * Security: Only the authenticated user can update their own profile. Users cannot modify other users' profiles or any authentication credentials (email/password) through this endpoint. Email changes require a separate account management process, and password changes must go through the password change flow with current password verification.
   *
   * The display name appears in employee records, timesheets, activity logs, and other areas where user identity needs to be shown. The avatar image provides visual representation in the platform. The phone number enables work-related communications between organization members.
   *
   * Related Operations:
   * - GET /profile retrieves the current user's profile
   * - Password changes require separate authentication endpoints
   * - Account deletion is handled through account management operations
   *
   * @param connection
   * @param body Profile update data including display name, avatar URI, and phone number
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Implementation Steps:
   *
   * 1. Authentication Verification:
   *    - Extract and verify the authenticated member from the session/token
   *    - Ensure the user is logged in (member actor)
   *    - Return 401 Unauthorized if not authenticated
   *
   * 2. Input Validation:
   *    - Validate display_name: required, non-empty string, max 255 characters
   *    - Validate avatar_uri: optional, must be valid URI format if provided, max 80000 characters
   *    - Validate phone: optional, valid phone format if provided
   *    - Return 400 Bad Request with validation errors for invalid inputs
   *
   * 3. Database Update:
   *    - Update erp_hrm_members record where id = authenticated_user_id
   *    - Set display_name, avatar_uri (if provided, null to remove), phone (if provided)
   *    - Update updated_at timestamp to current time
   *    - Use transaction to ensure atomic update
   *
   * 4. Response:
   *    - Return 200 OK with the complete updated IErpHrmMember object
   *    - Include all fields except password_hash for security
   *    - Verify updated_at reflects the change
   *
   * Edge Cases:
   * - Empty string for avatar_uri should remove the avatar (set to null)
   * - Null phone should clear the phone number
   * - Concurrent updates: last write wins (standard behavior)
   * - User with deleted_at set: return 403 Forbidden (account deactivated)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async updateProfile(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IErpHrmMember.IUpdate,
  ): Promise<IErpHrmMember> {
    try {
      return await putErpHrmMemberProfile({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
