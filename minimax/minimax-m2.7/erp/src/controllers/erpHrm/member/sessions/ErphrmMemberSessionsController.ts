import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IErpHrmMemberSession } from "../../../../api/structures/IErpHrmMemberSession";
import { IPageIErpHrmMemberSession } from "../../../../api/structures/IPageIErpHrmMemberSession";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getErpHrmMemberSessionsSessionId } from "../../../../providers/getErpHrmMemberSessionsSessionId";
import { patchErpHrmMemberSessions } from "../../../../providers/patchErpHrmMemberSessions";

@Controller("/erpHrm/member/sessions")
export class ErphrmMemberSessionsController {
  /**
   * Retrieve a filtered and paginated list of the authenticated member's active sessions.
   *
   * This operation returns all sessions associated with the currently authenticated user, with support for filtering by session status (active, expired), creation date range, client metadata (IP address, referrer), and token expiration state. The organization context is automatically enforced based on the authenticated session, ensuring sessions are isolated to the user's current organization membership.
   *
   * Each session record includes client metadata recorded at login time (IP address, HTTP referrer, request URL), token validity information (expiration timestamps for both access and refresh tokens), and session lifecycle timestamps (creation time, overall expiration time). This endpoint is useful for security monitoring, allowing users to review where and when their account was accessed.
   *
   * Sessions are ordered by creation date in descending order by default, showing most recent sessions first. Expired sessions remain visible for review purposes but are clearly marked with their expiration status. The response includes pagination metadata for traversing large result sets of historical sessions.
   *
   * @param connection
   * @param body Search and filter criteria for sessions
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query the erp_hrm_member_sessions table filtering by the authenticated member's ID (extracted from the current session context).
   *
   * Apply optional filters from the request body:
   * - Filter by session status: active sessions (token_expired_at > current_time) or expired sessions
   * - Filter by created_at date range for temporal queries
   * - Filter by IP address or referrer for client identification
   * - Filter by token expiration state
   *
   * Join with erp_hrm_members table to verify session ownership (member must match authenticated user).
   *
   * Order results by created_at DESC to show most recent sessions first.
   *
   * Implement cursor-based or offset pagination with configurable page sizes.
   *
   * Return session summaries excluding sensitive token data (access_token and refresh_token are never exposed in list responses).
   *
   * Enforce organization context: only return sessions belonging to the user's current organization context.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IErpHrmMemberSession.IRequest,
  ): Promise<IPageIErpHrmMemberSession.ISummary> {
    try {
      return await patchErpHrmMemberSessions({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific session by its unique identifier.
   *
   * This endpoint fetches detailed information about a single session record from the system. The response includes the session's unique identifier, associated user type (member or admin), client metadata such as IP address and request URL, creation timestamp, and expiration timestamp. For member sessions, additional token-related information is included such as the access token, refresh token, and token expiration time.
   *
   * The session retrieval operation is essential for validating session validity, retrieving session context, and maintaining authenticated state within the application. Clients typically use this endpoint to verify their current session status or to retrieve session details after authentication.
   *
   * Security considerations: Only the owner of the session or administrators can retrieve session details. The access token and refresh token fields are only returned for member sessions and should be handled securely by the client.
   *
   * @param connection
   * @param sessionId Unique identifier of the session to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Implement session retrieval with the following logic:
   *
   * 1. Extract sessionId from path parameters
   * 2. Query erp_hrm_member_sessions table by sessionId
   * 3. If not found in member_sessions, query erp_hrm_admin_sessions table
   * 4. If not found in admin_sessions, query erp_hrm_guest_sessions table
   * 5. Return 404 if session not found in any table
   * 6. Validate session has not expired (check expired_at > current timestamp)
   * 7. Return session entity with all fields
   *
   * For member sessions, include access_token, refresh_token, and token_expired_at fields in response.
   *
   * Return 401 Unauthorized if session is expired or invalid.
   *
   * Join with erp_hrm_members table to include member basic info (email) if available.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<IErpHrmMemberSession> {
    try {
      return await getErpHrmMemberSessionsSessionId({
        member,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
