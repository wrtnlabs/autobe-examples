import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IErpHrmMemberSession } from "../../../../api/structures/IErpHrmMemberSession";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getErpHrmMemberSessionsSessionId } from "../../../../providers/getErpHrmMemberSessionsSessionId";

@Controller("/erpHrm/member/sessions/:sessionId")
export class ErphrmMemberSessionsController {
  /**
   * Retrieve a single authenticated session by its unique identifier.
   *
   * This endpoint returns the complete session details including the associated member reference, client metadata (IP address, requested URL, referrer), token information with expiration timestamps, and session lifecycle timestamps.
   *
   * The session must belong to the currently authenticated user's organization context. Access to session data is restricted to administrators with appropriate permissions. Session tokens are not included in the response for security purposes.
   *
   * If the requested session does not exist or belongs to a different organization, the API returns a 404 Not Found error.
   *
   * @param connection
   * @param sessionId Unique identifier of the session to retrieve (UUID format)
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query the erp_hrm_member_sessions table using the
     *   provided sessionId as the primary key. Join with erp_hrm_members table
     *   to verify the session belongs to an active employee within the current
     *   organization context. Return the session object with member reference
     *   but exclude access_token and refresh_token fields for security.
     *   Validate that the session has not expired (check expired_at against
     *   current timestamp). If the session is expired, return it but mark it
     *   appropriately or return 404. Enforce organization-level data isolation
     *   - sessions from other organizations must not be accessible.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<IErpHrmMemberSession> {
    try {
      return await getErpHrmMemberSessionsSessionId({
        member,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
