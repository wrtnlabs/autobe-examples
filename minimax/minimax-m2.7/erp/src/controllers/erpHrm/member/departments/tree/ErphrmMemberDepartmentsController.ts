import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IErpHrmDepartment } from "../../../../../api/structures/IErpHrmDepartment";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { getErpHrmMemberDepartmentsTree } from "../../../../../providers/getErpHrmMemberDepartmentsTree";

@Controller("/erpHrm/member/departments/tree")
export class ErphrmMemberDepartmentsController {
  /**
   * Retrieve the department hierarchy as a tree structure for the current organization.
   *
   * This endpoint returns all departments organized hierarchically, showing the parent-child relationships between departments within the organization. The response is structured as an array of root-level departments, each containing a nested array of their direct child departments.
   *
   * Root departments (those without a parent) appear at the top level of the response, while child departments are nested within their parent's children array. This structure allows API consumers to easily render organizational charts or navigation trees.
   *
   * The department hierarchy follows the one-level nesting rule enforced by the system, where a department may optionally have a parent, but that parent cannot have its own parent. All employees within the organization can access this endpoint regardless of their role.
   *
   * Departments are included regardless of their active status, allowing visibility into both current and inactive organizational units. The tree structure is useful for displaying the complete organizational structure in hierarchical views.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query erp_hrm_departments table for the current organization context.
   *
   * 1. Authentication: Validate the member session and extract organization context
   * 2. Query Strategy:
   *    - Fetch all departments belonging to the organization
   *    - Build tree structure by identifying root departments (parent_id IS NULL)
   *    - Recursively attach child departments to their parents
   * 3. Sorting: Order departments alphabetically by name at each level
   * 4. Response Construction: Create nested IErpHrmDepartment.ITree objects with children arrays
   * 5. Return the array of root department trees with their complete nested children
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async tree(
    @MemberAuth()
    member: MemberPayload,
  ): Promise<IErpHrmDepartment.ITree> {
    try {
      return await getErpHrmMemberDepartmentsTree({
        member,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
