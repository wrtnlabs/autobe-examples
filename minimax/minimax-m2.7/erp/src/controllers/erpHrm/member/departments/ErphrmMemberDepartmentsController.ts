import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IErpHrmDepartment } from "../../../../api/structures/IErpHrmDepartment";
import { IPageIErpHrmDepartment } from "../../../../api/structures/IPageIErpHrmDepartment";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getErpHrmMemberDepartmentsDepartmentId } from "../../../../providers/getErpHrmMemberDepartmentsDepartmentId";
import { getErpHrmMemberDepartmentsHierarchy } from "../../../../providers/getErpHrmMemberDepartmentsHierarchy";
import { patchErpHrmMemberDepartments } from "../../../../providers/patchErpHrmMemberDepartments";

@Controller("/erpHrm/member/departments")
export class ErphrmMemberDepartmentsController {
  /**
   * Retrieve a filtered and paginated list of departments within the current organization.
   *
   * This operation allows organization members to browse and search departments for organizational structure visibility. The response includes department summaries with name, description, and parent department relationships.
   *
   * All employees can access this endpoint regardless of their role. The list includes both active and inactive departments. Results are sorted alphabetically by department name by default.
   *
   * Filtering options include searching by department name and optionally filtering by parent department for hierarchical views.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering departments.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query erp_hrm_departments table with
     *   organization-scoped filtering from session context.
   *
   * Apply search filters:
   * - Filter by name substring match (case-insensitive)
   * - Filter by parent department ID if specified
   * - Filter by organization ID from session context
   *
   * Always include soft-deleted departments (deleted_at IS NOT NULL) alongside active ones since the business requirements state inactive departments are visible.
   *
   * Join with parent department table to include parent department name in results if requested.
   *
   * Apply default sorting by name ascending (alphabetical order).
   *
   * Return paginated results with configurable page size (default 20, max 100).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IErpHrmDepartment.IRequest,
  ): Promise<IPageIErpHrmDepartment.ISummary> {
    try {
      return await patchErpHrmMemberDepartments({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific department by its unique identifier within the current organization context.
   *
   * This endpoint returns the complete department details including its name, description, and parent department relationship if applicable. The operation enforces organization-level data isolation, ensuring employees can only access departments belonging to their current organization.
   *
   * The returned department object includes the parent department reference when a hierarchy exists, enabling the construction of organizational structure views and reporting line visualizations.
   *
   * @param connection
   * @param departmentId Unique identifier of the department to retrieve (global scope).
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query erp_hrm_departments table using the
     *   provided departmentId as the primary key lookup.
   *
   * Verify the department belongs to the authenticated user's current organization context (erp_hrm_organization_id match). Return 404 error if department does not exist or does not belong to the organization.
   *
   * Include the parent department relation (erp_hrm_departments.parent) to provide complete hierarchy information. The parent department details should be nested without its own children array to prevent circular references.
   *
   * Return the full department entity with all fields: id, name, description, parent_id, parent (with id, name, description), created_at, updated_at.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":departmentId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("departmentId")
    departmentId: string & tags.Format<"uuid">,
  ): Promise<IErpHrmDepartment> {
    try {
      return await getErpHrmMemberDepartmentsDepartmentId({
        member,
        departmentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve the complete department hierarchy for the current organization as a tree structure.
   *
   * This endpoint returns all departments organized by their parent-child relationships, enabling hierarchical displays in UI components such as tree views and organizational charts. Each department node includes its direct children, allowing recursive rendering.
   *
   * The hierarchy respects the one-level nesting constraint: departments may have a parent, but that parent cannot have its own parent. Root-level departments (those without parents) appear at the top level of the response, with their child departments nested within.
   *
   * Departments are scoped to the currently selected organization, ensuring data isolation between organizations. Both active and inactive departments are included in the hierarchy.
   *
   * @param connection
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query the erp_hrm_departments table filtering by
     *   the current organization context.
   *
   * Build the hierarchy tree structure server-side:
   * 1. Fetch all departments belonging to the organization where deleted_at IS NULL or deleted_at IS NOT NULL (include both active and inactive)
   * 2. Group departments by their parent_id
   * 3. Identify root-level departments (where parent_id is null)
   * 4. For each root department, recursively nest its children (one level deep only, since schema enforces this)
   * 5. Sort departments alphabetically by name within each level
   *
   * Return the tree structure with each node containing:
   * - Full department details (id, name, description)
   * - Parent reference for context
   * - Children array (may be empty)
   *
   * Handle edge cases:
   * - Empty organization: return empty children array
   * - Departments with deleted parents: include them as root-level in hierarchy
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get("hierarchy")
  public async hierarchy(
    @MemberAuth()
    member: MemberPayload,
  ): Promise<IErpHrmDepartment.IHierarchy> {
    try {
      return await getErpHrmMemberDepartmentsHierarchy({
        member,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
