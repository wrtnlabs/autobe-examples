import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IErpHrmRole } from "../../../../api/structures/IErpHrmRole";
import { IPageIErpHrmRole } from "../../../../api/structures/IPageIErpHrmRole";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getErpHrmMemberRolesRoleId } from "../../../../providers/getErpHrmMemberRolesRoleId";
import { patchErpHrmMemberRoles } from "../../../../providers/patchErpHrmMemberRoles";

@Controller("/erpHrm/member/roles")
export class ErphrmMemberRolesController {
  /**
   * Retrieve a filtered and paginated list of roles within the current organization.
   *
   * This operation returns all roles available in the authenticated user's organization, including the three built-in roles (Owner, Manager, Employee) and any custom roles created by organization owners. Results can be filtered by role name and built-in status.
   *
   * The response includes role summaries with permission counts, suitable for role management interfaces. Organization context is automatically applied based on the authenticated user's current session, ensuring strict data isolation between organizations.
   *
   * Built-in roles are always present and cannot be deleted, while custom roles can be identified and managed by users with appropriate permissions.
   *
   * @param connection
   * @param body Search criteria including optional name filter and pagination parameters
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query erp_hrm_roles table filtered by the current
     *   organization context from the authenticated session.
   *
   * Apply the following search filters when provided:
   * - Filter by role name using case-insensitive partial matching (LIKE %name%)
   * - Filter by is_builtin status (true/false) to separate built-in from custom roles
   *
   * Return results ordered by is_builtin DESC (built-in first), then by created_at ASC.
   *
   * Join with erp_hrm_role_permissions to include permission count in the response summary.
   *
   * Implement cursor-based pagination using the role's created_at timestamp and id as cursor. Default page size is 20, maximum 100.
   *
   * Return empty array if no roles exist for the organization.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IErpHrmRole.IRequest,
  ): Promise<IPageIErpHrmRole.ISummary> {
    try {
      return await patchErpHrmMemberRoles({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve details of a specific role by its unique identifier.
   *
   * This endpoint returns the complete role information including its name, whether it is a built-in role, creation and update timestamps, and all permissions assigned to the role. The response includes the role scoped within the current organization context.
   *
   * Built-in roles (Owner, Manager, Employee) are protected from deletion but can be retrieved normally. Custom roles created by organization owners can be fully managed.
   *
   * The role must belong to the current organization; attempting to retrieve a role from another organization returns an error.
   *
   * @param connection
   * @param roleId Unique identifier of the role to retrieve (UUID format)
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query the erp_hrm_roles table using the provided
     *   roleId as the primary key. Verify the role belongs to the current
     *   organization from session context. If the role has been soft-deleted
     *   (deleted_at is not null), return a 404 error. Join with
     *   erp_hrm_role_permissions to include the complete list of permission
     *   codes assigned to the role. Return the role entity with its permissions
     *   array. Handle case where role does not exist or does not belong to the
     *   organization with appropriate error response.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":roleId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("roleId")
    roleId: string & tags.Format<"uuid">,
  ): Promise<IErpHrmRole.IInvert> {
    try {
      return await getErpHrmMemberRolesRoleId({
        member,
        roleId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
