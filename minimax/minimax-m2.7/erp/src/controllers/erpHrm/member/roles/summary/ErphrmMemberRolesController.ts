import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IErpHrmRole } from "../../../../../api/structures/IErpHrmRole";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { getErpHrmMemberRolesSummary } from "../../../../../providers/getErpHrmMemberRolesSummary";

@Controller("/erpHrm/member/roles/summary")
export class ErphrmMemberRolesController {
  /**
   * Retrieve a list of role summaries available within the authenticated user's organization scope.
   *
   * This endpoint returns all active roles in the user's organization, including the three built-in roles (Owner, Manager, Employee) and any custom roles created by organization administrators. The response is optimized as a summary list containing essential role information without full permission details.
   *
   * Roles are scoped to the organization identified from the authenticated session. Only non-deleted roles are included in the response. Built-in roles cannot be modified or deleted, while custom roles can be managed by users with org:manage permission.
   *
   * Related operations: GET /roles/{roleId} retrieves detailed role information including full permission set.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query erp_hrm_roles table filtering by:
   * - erp_hrm_organization_id matching authenticated user's organization
   * - deleted_at IS NULL (exclude soft-deleted roles)
   *
   * Join with erp_hrm_organizations to verify organization exists.
   *
   * Return role summaries ordered by is_builtin DESC (built-in first), then by name ASC.
   *
   * No pagination required as role count per organization is bounded (typically <20).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async summary(
    @MemberAuth()
    member: MemberPayload,
  ): Promise<IErpHrmRole.ISummary> {
    try {
      return await getErpHrmMemberRolesSummary({
        member,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
