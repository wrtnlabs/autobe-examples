import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IErpHrmRole } from "../../../../../api/structures/IErpHrmRole";
import { IErpHrmRolePermission } from "../../../../../api/structures/IErpHrmRolePermission";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { getErpHrmMemberRolesRoleIdPermissionsPermissionId } from "../../../../../providers/getErpHrmMemberRolesRoleIdPermissionsPermissionId";
import { patchErpHrmMemberRolesRoleIdPermissions } from "../../../../../providers/patchErpHrmMemberRolesRoleIdPermissions";

@Controller("/erpHrm/member/roles/:roleId/permissions")
export class ErphrmMemberRolesPermissionsController {
  /**
   * Update the permission set for an organization role.
   *
   * This operation replaces all existing permissions of the specified role with a new set of permissions provided in the request. The system validates that the role exists within the current organization context and that the role is not a built-in role (Owner, Manager, Employee) which cannot have their permissions modified.
   *
   * Permission changes take effect immediately for all employees assigned to this role. Employees will gain or lose access rights based on the updated permission set.
   *
   * The request body contains an array of permission codes to assign to the role. Existing role permissions are removed and replaced entirely with the provided set. Each permission code must be one of the valid system permissions: org:manage, employee:manage, employee:view, project:manage, project:view, time:manage, time:approve, time:view_all, or report:view.
   *
   * Role permissions are scoped to the current organization. Attempting to modify permissions for a role in a different organization returns a not found error.
   *
   * @param connection
   * @param roleId Unique identifier of the role to update permissions for (global scope)
   * @param body New set of permission codes to assign to the role
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Implementation steps:
   *
   * 1. Extract roleId from path parameter and validate UUID format
   * 2. Retrieve the role from erp_hrm_roles table using roleId
   * 3. Verify role exists and belongs to the current organization context
   * 4. Validate that the role is NOT a built-in role (is_builtin = false)
   *    - If is_builtin is true, return 400 error: "Cannot modify permissions of built-in roles"
   * 5. Validate that the role is not soft-deleted (deleted_at is null)
   * 6. Validate all permission codes in the request body are valid system permissions
   *    - Valid permissions: org:manage, employee:manage, employee:view, project:manage, project:view, time:manage, time:approve, time:view_all, report:view
   *    - If any invalid permission code found, return 400 error with list of invalid codes
   * 7. Begin database transaction
   * 8. Delete all existing entries from erp_hrm_role_permissions where erp_hrm_role_id matches the role
   * 9. Insert new entries for each permission code in the request body
   * 10. Update updated_at timestamp on the role record
   * 11. Commit transaction
   * 12. Return 200 with the updated list of role permissions
   *
   * Edge cases:
   * - Empty permissions array: Allowed (creates a role with no permissions)
   * - Duplicate permission codes in request: De-duplicate before insert
   * - Role not found: Return 404 error
   * - Role in different organization: Return 404 error (for security, don't reveal existence)
   * - Invalid permission code: Return 400 with validation details
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async updatePermissions(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("roleId")
    roleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IErpHrmRole.IUpdatePermission,
  ): Promise<IErpHrmRolePermission.IUpdateResult> {
    try {
      return await patchErpHrmMemberRolesRoleIdPermissions({
        member,
        roleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific permission assignment from a role by its unique identifier.
   *
   * This endpoint fetches the details of a single permission that has been assigned to a role. The permission assignment links a role to a specific permission code that determines what actions employees with that role can perform.
   *
   * The response includes the permission code string (e.g., 'org:manage', 'employee:view', 'project:manage') and timestamps. Permission codes are immutable once assigned to a role.
   *
   * This operation requires the user to have appropriate organization context and permission to view role configurations.
   *
   * @param connection
   * @param roleId Unique identifier of the role that contains this permission assignment (UUID)
   * @param permissionId Unique identifier of the role permission assignment record (UUID)
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query erp_hrm_role_permissions table using the
     *   provided permissionId as the primary key. Verify the erp_hrm_role_id
     *   matches the provided roleId parameter. Join with erp_hrm_roles to
     *   confirm the role exists and is not soft-deleted. Return the full role
     *   permission record including: id, permission code, role_id, created_at,
     *   and updated_at. If the role permission record does not exist or the
     *   role is deleted, return 404 error. Enforce organization-level data
     *   isolation by verifying the role belongs to the current organization
     *   context.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":permissionId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("roleId")
    roleId: string & tags.Format<"uuid">,
    @TypedParam("permissionId")
    permissionId: string & tags.Format<"uuid">,
  ): Promise<IErpHrmRolePermission> {
    try {
      return await getErpHrmMemberRolesRoleIdPermissionsPermissionId({
        member,
        roleId,
        permissionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
