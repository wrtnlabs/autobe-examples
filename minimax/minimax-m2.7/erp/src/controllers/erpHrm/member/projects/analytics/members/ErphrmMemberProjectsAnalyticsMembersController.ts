import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IErpHrmProjectMember } from "../../../../../../api/structures/IErpHrmProjectMember";
import { MemberAuth } from "../../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../../decorators/payload/MemberPayload";
import { getErpHrmMemberProjectsProjectIdAnalyticsMembers } from "../../../../../../providers/getErpHrmMemberProjectsProjectIdAnalyticsMembers";

@Controller("/erpHrm/member/projects/:projectId/analytics/members")
export class ErphrmMemberProjectsAnalyticsMembersController {
  /**
   * Retrieve aggregated analytics and statistics about members assigned to a specific project.
   *
   * This endpoint returns project member analytics including total member count, breakdown by assigned role (member vs project_lead), and a list of current project members with their role assignments and join dates. The analytics are scoped to the specified project within the user's current organization context.
   *
   * The response includes summary statistics for quick overview and detailed member list for further analysis. Project membership authorization applies - users must have project view permissions to access this endpoint.
   *
   * @param connection
   * @param projectId Unique identifier of the project to retrieve member analytics for
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query erp_hrm_projects table to validate projectId exists and belongs to the user's organization.
   * Join erp_hrm_project_members with erp_hrm_employees to get member details.
   * Aggregate member count by assigned_role (member, project_lead).
   * Calculate total member count.
   * Return summary statistics and member details ordered by created_at.
   *
   * Validate that the project belongs to the user's current organization context.
   * Return empty analytics (not error) if project has no members.
   *
   * Error handling:
   * - 404 if projectId does not exist or belongs to different organization
   * - 403 if user lacks project view permission
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("projectId")
    projectId: string & tags.Format<"uuid">,
  ): Promise<IErpHrmProjectMember.IAnalytic> {
    try {
      return await getErpHrmMemberProjectsProjectIdAnalyticsMembers({
        member,
        projectId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
