import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IErpHrmTaskHistory } from "../../../../../../api/structures/IErpHrmTaskHistory";
import { IPageIErpHrmTaskHistory } from "../../../../../../api/structures/IPageIErpHrmTaskHistory";
import { MemberAuth } from "../../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../../decorators/payload/MemberPayload";
import { getErpHrmMemberProjectsProjectIdTasksTaskIdHistoriesHistoryId } from "../../../../../../providers/getErpHrmMemberProjectsProjectIdTasksTaskIdHistoriesHistoryId";
import { patchErpHrmMemberProjectsProjectIdTasksTaskIdHistories } from "../../../../../../providers/patchErpHrmMemberProjectsProjectIdTasksTaskIdHistories";

@Controller("/erpHrm/member/projects/:projectId/tasks/:taskId/histories")
export class ErphrmMemberProjectsTasksHistoriesController {
  /**
   * Retrieve a paginated list of task history entries for a specific task within a project.
   *
   * This endpoint provides read-only access to the immutable audit trail that records each status transition made to a task throughout its lifecycle. Every time a task changes from one status to another, a new history entry is automatically created documenting who made the change, when it occurred, and what the status changed from and to.
   *
   * The history entries are returned in chronological order from oldest to newest, allowing users to trace the complete progression of a task from creation through all subsequent status changes. This enables users to understand task workflow, identify when specific transitions occurred, and determine responsibility for each change.
   *
   * Users MUST have appropriate permissions to access task history. Users with project view permission can access task history for tasks within projects they can view. Users without project view or task-related permissions will be denied access to task history.
   *
   * When the parent project is archived, task history remains fully accessible with all entries preserved and chronological ordering unchanged.
   *
   * This operation is automatically generated by the system when task status changes occur, serving as an immutable audit trail. No write operations (create, update, delete) are exposed for task histories.
   *
   * @param connection
   * @param projectId UUID of the project containing the task (global scope)
   * @param taskId UUID of the task whose history to retrieve
   * @param body Pagination parameters for retrieving task history entries
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query the erp_hrm_task_histories table filtering by erp_hrm_task_id matching the taskId path parameter.
   *
   * Join erp_hrm_task_histories with erp_hrm_members to include member information (name, email) for the user who made each status change.
   *
   * Verify the task exists and belongs to the specified project by checking erp_hrm_tasks table.
   *
   * Authorization: User must have project view permission for the project OR task-related permissions that grant access to the task. Organization context is required from the authenticated session.
   *
   * Apply cursor-based pagination ordered by created_at ascending (chronological order, oldest first).
   *
   * Return history entries with: id, erp_hrm_task_id, erp_hrm_member_id, previous_status, new_status, created_at, and nested member summary.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("projectId")
    projectId: string & tags.Format<"uuid">,
    @TypedParam("taskId")
    taskId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IErpHrmTaskHistory.IRequest,
  ): Promise<IPageIErpHrmTaskHistory> {
    try {
      return await patchErpHrmMemberProjectsProjectIdTasksTaskIdHistories({
        member,
        projectId,
        taskId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific task history entry by its unique identifier.
   *
   * This endpoint returns detailed information about a single status change event recorded for a task. The task history entry includes the status values before and after the change, the employee who initiated the change, and the timestamp when the change occurred.
   *
   * Access to task history requires appropriate permissions. Users must have project view permission or task-related permissions to access history entries. The requesting user must be able to view the project containing the task, and the history entry must belong to the specified task within that project.
   *
   * The returned task history entry is immutable - it cannot be modified or deleted through this endpoint. This endpoint only retrieves existing history records.
   *
   * For listing all history entries for a task, use the task history index endpoint with appropriate filters. For retrieving the current status of a task, use the task detail endpoint.
   *
   * @param connection
   * @param projectId The unique identifier of the project containing the task (global scope)
   * @param taskId The unique identifier of the task whose history entry is being retrieved (scoped to project)
   * @param historyId The unique identifier of the task history entry to retrieve (scoped to task)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Retrieve a single task history entry from the erp_hrm_task_histories table.
   *
   * 1. Extract path parameters: projectId (UUID), taskId (UUID), historyId (UUID)
   * 2. Validate that projectId, taskId, and historyId are valid UUIDs
   * 3. Verify the task exists and belongs to the specified project by querying erp_hrm_tasks
   * 4. Verify the history entry exists and belongs to the specified task by querying erp_hrm_task_histories with erp_hrm_task_id = taskId
   * 5. Check authorization: user must have project view permission OR task-related permissions for the project
   * 6. Load the complete history entry with related data (member who made the change)
   * 7. Return the history entry as IErpHrmTaskHistory
   *
   * Edge cases:
   * - Invalid UUID format -> 400 Bad Request
   * - Project not found -> 404 Not Found
   * - Task not found or not in project -> 404 Not Found
   * - History entry not found or not belonging to task -> 404 Not Found
   * - No permission -> 403 Forbidden
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":historyId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("projectId")
    projectId: string & tags.Format<"uuid">,
    @TypedParam("taskId")
    taskId: string & tags.Format<"uuid">,
    @TypedParam("historyId")
    historyId: string & tags.Format<"uuid">,
  ): Promise<IErpHrmTaskHistory> {
    try {
      return await getErpHrmMemberProjectsProjectIdTasksTaskIdHistoriesHistoryId(
        {
          member,
          projectId,
          taskId,
          historyId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
