import {
  HttpError,
  IConnection,
  NestiaSimulator,
  PlainFetcher,
} from "@nestia/fetcher";
import typia, { tags } from "typia";

import { IErpHrmMemberSession } from "../../../../structures/IErpHrmMemberSession";

/**
 * Retrieve a single authenticated session by its unique identifier.
 *
 * This endpoint returns the complete session details including the associated member reference, client metadata (IP address, requested URL, referrer), token information with expiration timestamps, and session lifecycle timestamps.
 *
 * The session must belong to the currently authenticated user's organization context. Access to session data is restricted to administrators with appropriate permissions. Session tokens are not included in the response for security purposes.
 *
 * If the requested session does not exist or belongs to a different organization, the API returns a 404 Not Found error.
 *
 * @param props.connection
 * @param props.sessionId Unique identifier of the session to retrieve (UUID format)
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor member
 * @x-autobe-specification Query the erp_hrm_member_sessions table using the
 *   provided sessionId as the primary key. Join with erp_hrm_members table to
 *   verify the session belongs to an active employee within the current
 *   organization context. Return the session object with member reference but
 *   exclude access_token and refresh_token fields for security. Validate that
 *   the session has not expired (check expired_at against current timestamp).
 *   If the session is expired, return it but mark it appropriately or return
 *   404. Enforce organization-level data isolation - sessions from other
 *   organizations must not be accessible.
 * @path /erpHrm/member/sessions/:sessionId
 * @accessor api.functional.erpHrm.member.sessions.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique identifier of the session to retrieve (UUID format)
     */
    sessionId: string & tags.Format<"uuid">;
  };
  export type Response = IErpHrmMemberSession;

  export const METADATA = {
    method: "GET",
    path: "/erpHrm/member/sessions/:sessionId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/erpHrm/member/sessions/${encodeURIComponent(props.sessionId ?? "null")}`;
  export const random = (): IErpHrmMemberSession =>
    typia.random<IErpHrmMemberSession>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("sessionId")(() => typia.assert(props.sessionId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
