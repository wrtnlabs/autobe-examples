/**
 * Retrieve a filtered and paginated list of reports within the organization.
 *
 * This operation allows authorized users to search and browse organization reports. Reports are scoped to the currently selected organization, ensuring strict data isolation. The search supports filtering by report type (time report, project budget report, weekly summary report), date range of report generation, and the user who generated the report.
 *
 * Users must possess the report:view permission to access this endpoint. Results are returned in descending order by creation date (newest first), enabling quick access to the most recently generated reports. Each report includes its parameters (date range, filters, grouping preferences) that were used during generation.
 *
 * @param props.connection
 * @param props.body Search criteria including report type filter, date range filter, generator filter, and pagination parameters
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor member
 * @x-autobe-specification Query erp_hrm_reports table filtered by
 *   erp_hrm_organization_id from session context.
 *
 * Apply search filters:
 * - Filter by report_type when specified (time_report, project_budget_report, weekly_summary_report)
 * - Filter by created_at date range when startDate/endDate provided
 * - Filter by generated_by_erp_hrm_member_id when specific generator specified
 *
 * Join with erp_hrm_report_parameters to include parameter details in response.
 *
 * Order by created_at descending (newest first).
 *
 * Apply cursor-based or offset pagination with configurable page size.
 *
 * Verify user has report:view permission in current organization context before returning results.
 * @path /erpHrm/member/reports
 * @accessor api.functional.erpHrm.member.reports.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
