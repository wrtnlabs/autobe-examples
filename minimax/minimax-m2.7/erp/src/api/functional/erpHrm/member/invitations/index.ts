import {
  HttpError,
  IConnection,
  NestiaSimulator,
  PlainFetcher,
} from "@nestia/fetcher";
import typia from "typia";

import { IErpHrmInvitation } from "../../../../structures/IErpHrmInvitation";

/**
 * Accept an organization invitation using a secure invitation token.
 *
 * This endpoint allows authenticated users to accept invitations sent by organizations. When called, the system validates the invitation token, verifies the invitation is still pending and not expired, and creates an employee record linking the user to the inviting organization.
 *
 * The authenticated user must match the email address specified in the invitation. Upon successful acceptance, the user gains access to the organization's data and can begin participating as an employee.
 *
 * The invitation status transitions from 'pending' to 'accepted', and the accepted_at timestamp is recorded. If the invitation has already been accepted or has expired, the request fails with an appropriate error.
 *
 * @param props.connection
 * @param props.token Secure token from the invitation link used to verify and accept the invitation
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor member
 * @x-autobe-specification 1. Extract token from path parameter 2. Query
 *   erp_hrm_invitations table to find invitation by token 3. Validate
 *   invitation exists and is not soft-deleted (deleted_at is null) 4. Validate
 *   invitation status is 'pending' - reject if already 'accepted' or 'expired'
 *   5. Validate invitation has not expired - check expires_at is null or in the
 *   future 6. Validate authenticated user's email matches the invitation's
 *   email address 7. Create employee record in erp_hrm_employees with: -
 *   erp_hrm_user_id: authenticated user's ID - erp_hrm_organization_id: from
 *   invitation - erp_hrm_role_id: from invitation (use default role if null) -
 *   erp_hrm_department_id: from invitation (optional) - position: from
 *   invitation's position field (optional) - employment_type: default to
 *   'full-time' - status: 'active' 8. Update invitation record: - status:
 *   'accepted' - accepted_at: current timestamp 9. Record activity in
 *   erp_hrm_activity_logs 10. Return the accepted invitation with
 *   IErpHrmInvitation type
 *
 * Error handling:
 * - 404: Invitation not found or invalid token
 * - 400: Invitation already accepted or expired
 * - 403: User email does not match invitation email
 * @path /erpHrm/member/invitations/:token/accept
 * @accessor api.functional.erpHrm.member.invitations.accept
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function accept(
  connection: IConnection,
  props: accept.Props,
): Promise<accept.Response> {
  return true === connection.simulate
    ? accept.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...accept.METADATA,
          path: accept.path(props),
          status: null,
        },
      );
}
export namespace accept {
  export type Props = {
    /**
     * Secure token from the invitation link used to verify and accept the invitation
     */
    token: string;
  };
  export type Response = IErpHrmInvitation;

  export const METADATA = {
    method: "POST",
    path: "/erpHrm/member/invitations/:token/accept",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/erpHrm/member/invitations/${encodeURIComponent(props.token ?? "null")}/accept`;
  export const random = (): IErpHrmInvitation =>
    typia.random<IErpHrmInvitation>();
  export const simulate = (
    connection: IConnection,
    props: accept.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: accept.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("token")(() => typia.assert(props.token));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
