export async function summary(
  connection: IConnection,
): Promise<summary.Response> {
  return true === connection.simulate
    ? summary.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...summary.METADATA,
          path: summary.path(),
          status: null,
        },
      );
}
export namespace summary {
  export type Response = IErpHrmRole.ISummary;

  export const METADATA = {
    method: "GET",
    path: "/erpHrm/member/roles/summary",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/erpHrm/member/roles/summary";
  export const random = (): IErpHrmRole.ISummary =>
    typia.random<IErpHrmRole.ISummary>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}
