import {
  HttpError,
  IConnection,
  NestiaSimulator,
  PlainFetcher,
} from "@nestia/fetcher";
import typia from "typia";

import { IErpHrmMember } from "../../../../structures/IErpHrmMember";

/**
 * Retrieve the authenticated user's global profile information.
 *
 * This endpoint returns the profile data of the currently authenticated member. The profile is shared across all organizations the user belongs to, including display name, avatar image, and phone number.
 *
 * The returned profile includes the user's display name shown in employee records, activity logs, and timesheets. The avatar URI provides a link to the user's profile picture, or null if no avatar has been uploaded. The phone number field is optional for work-related contact purposes.
 *
 * This operation is scoped to the authenticated session and does not require any path parameters.
 *
 * @param props.connection
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor member
 * @x-autobe-specification Query the erp_hrm_members table using the authenticated member's ID from the session token.
 *
 * Return the member's profile including: id, email, display_name, avatar_uri, phone, created_at, updated_at.
 *
 * Do NOT return the password_hash field for security reasons.
 *
 * If the member record has been soft-deleted (deleted_at is not null), return 404 Not Found.
 *
 * Join with any related data only if explicitly required for the profile display.
 * @path /erpHrm/member/profile
 * @accessor api.functional.erpHrm.member.profile.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(connection: IConnection): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(),
          status: null,
        },
      );
}
export namespace at {
  export type Response = IErpHrmMember;

  export const METADATA = {
    method: "GET",
    path: "/erpHrm/member/profile",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/erpHrm/member/profile";
  export const random = (): IErpHrmMember => typia.random<IErpHrmMember>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}

/**
 * Update the authenticated user's profile information.
 *
 * This endpoint allows authenticated members to modify their personal profile data including display name, avatar image, phone number, and password. Changes are immediately reflected across all organizations the user belongs to since the profile is globally shared.
 *
 * The user can update any subset of fields in a single request. Email address cannot be changed through this endpoint for security reasons.
 *
 * This operation requires an active session with valid member authentication.
 *
 * @param props.connection
 * @param props.body Partial update fields for the authenticated user's profile
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor member
 * @x-autobe-specification Validate the request body contains at least one updatable field. For display_name: ensure non-empty string, max 255 characters. For avatar_uri: validate it is a valid URI format if provided. For phone: validate format if provided. For password: validate minimum 8 characters, must include at least one letter and one number.
 *
 * Apply updates to the erp_hrm_members record using the authenticated user's ID from the session token. Update the updated_at timestamp to current time.
 *
 * Return the full updated member record excluding the password_hash field for security.
 * @path /erpHrm/member/profile
 * @accessor api.functional.erpHrm.member.profile.update
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function update(
  connection: IConnection,
  props: update.Props,
): Promise<update.Response> {
  return true === connection.simulate
    ? update.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...update.METADATA,
          path: update.path(),
          status: null,
        },
        props.body,
      );
}
export namespace update {
  export type Props = {
    /**
     * Partial update fields for the authenticated user's profile
     */
    body: IErpHrmMember.IUpdate;
  };
  export type Body = IErpHrmMember.IUpdate;
  export type Response = IErpHrmMember;

  export const METADATA = {
    method: "PATCH",
    path: "/erpHrm/member/profile",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/erpHrm/member/profile";
  export const random = (): IErpHrmMember => typia.random<IErpHrmMember>();
  export const simulate = (
    connection: IConnection,
    props: update.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: update.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
