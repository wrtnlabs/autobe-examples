/**
 * Update the filter parameters for an existing report within the organization.
 *
 * This endpoint allows authorized users with report:view permission to modify the filter criteria used to generate or refine a report. The parameters include date range boundaries, optional employee/project/task filters, billable status filtering, and data grouping preference.
 *
 * The report must belong to the user's current organization. If the report does not exist or belongs to a different organization, the system returns a not found error.
 *
 * Report parameters follow a 1:1 relationship with reports — each report has exactly one set of parameters. If parameters do not already exist for the report, PATCH creates them.
 *
 * Valid grouping options are strictly enforced: 'employee', 'project', or 'task'. Invalid group_by values result in a validation error. Date range must have start_date on or before end_date.
 *
 * @param props.connection
 * @param props.reportId Unique identifier of the report whose parameters to update (global scope)
 * @param props.body Updated filter parameters for the report including date range, filters, and grouping preference
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor member
 * @x-autobe-specification Validate that the report exists and belongs to the
 *   user's current organization context.
 *
 * If report_parameters record does not exist for this report, create a new one with the provided values.
 *
 * If report_parameters record already exists, apply partial updates using the provided fields.
 *
 * Validate date range: start_date must be on or before end_date. Return validation error if invalid.
 *
 * Validate group_by field: must be one of 'employee', 'project', or 'task'. Return validation error with valid options if invalid.
 *
 * Billable field accepts boolean values (true, false) or null (meaning include all).
 *
 * Store updated_at timestamp on both the report and its parameters.
 *
 * Return the full report object with updated parameters in the response.
 * @path /erpHrm/member/reports/:reportId/parameters
 * @accessor api.functional.erpHrm.member.reports.parameters.update
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function update(
  connection: IConnection,
  props: update.Props,
): Promise<update.Response> {
  return true === connection.simulate
    ? update.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...update.METADATA,
          path: update.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace update {
  export type Props = {
    /**
     * Unique identifier of the report whose parameters to update (global scope)
     */
    reportId: string & tags.Format<"uuid">;

    /**
     * Updated filter parameters for the report including date range, filters, and grouping preference
     */
    body: IErpHrmReportParameter.IUpdate;
  };
  export type Body = IErpHrmReportParameter.IUpdate;
  export type Response = IErpHrmReport;

  export const METADATA = {
    method: "PATCH",
    path: "/erpHrm/member/reports/:reportId/parameters",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/erpHrm/member/reports/${encodeURIComponent(props.reportId ?? "null")}/parameters`;
  export const random = (): IErpHrmReport => typia.random<IErpHrmReport>();
  export const simulate = (
    connection: IConnection,
    props: update.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: update.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("reportId")(() => typia.assert(props.reportId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

