/**
 * Retrieve a specific timesheet by its ID for a given member.
 *
 * This endpoint returns a single timesheet belonging to the specified member. The timesheet includes all associated metadata such as status, total hours, submission and review timestamps, and the reviewer information.
 *
 * Access control: Employees can view their own timesheets. Users with time:approve or time:view_all permission can view any timesheet within their organization.
 *
 * The returned timesheet contains the full details including:
 * - Week start and end dates defining the timesheet period
 * - Current workflow status (draft, submitted, approved, rejected)
 * - Total hours calculated from included timelogs
 * - Submission and review timestamps
 * - Rejection reason if the timesheet was rejected
 *
 * If the timesheet does not exist or the requesting user lacks permission to view it, the system returns an access denied response.
 *
 * @param props.connection
 * @param props.memberId The unique identifier of the member (user) who owns the timesheet
 * @param props.timesheetId The unique identifier of the timesheet to retrieve
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor admin
 * @x-autobe-specification Query erp_hrm_timesheets table by id, joining with
 *   erp_hrm_employees to verify erp_hrm_user_id matches memberId.
 *
 * Authorization rules:
 * 1. If requesting user is the owner of the timesheet (their user record matches the employee.user), allow access.
 * 2. If requesting user has time:approve or time:view_all permission in the organization, allow access.
 * 3. Otherwise, deny access with 403 Forbidden.
 *
 * If timesheet is not found, return 404 Not Found.
 *
 * Join with erp_hrm_employees to verify the member relationship and include employee details in response.
 *
 * Join with erp_hrm_timesheet_timelogs to include the associated timelogs in the response.
 *
 * Return the complete timesheet entity including all included timelogs and reviewer information.
 * @path /erpHrm/admin/members/:memberId/timesheets/:timesheetId
 * @accessor api.functional.erpHrm.admin.members.timesheets.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * The unique identifier of the member (user) who owns the timesheet
     */
    memberId: string & tags.Format<"uuid">;

    /**
     * The unique identifier of the timesheet to retrieve
     */
    timesheetId: string & tags.Format<"uuid">;
  };
  export type Response = IErpHrmTimesheet;

  export const METADATA = {
    method: "GET",
    path: "/erpHrm/admin/members/:memberId/timesheets/:timesheetId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/erpHrm/admin/members/${encodeURIComponent(props.memberId ?? "null")}/timesheets/${encodeURIComponent(props.timesheetId ?? "null")}`;
  export const random = (): IErpHrmTimesheet =>
    typia.random<IErpHrmTimesheet>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("memberId")(() => typia.assert(props.memberId));
      assert.param("timesheetId")(() => typia.assert(props.timesheetId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
