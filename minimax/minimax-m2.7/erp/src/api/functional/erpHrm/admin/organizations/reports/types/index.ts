import {
  HttpError,
  IConnection,
  NestiaSimulator,
  PlainFetcher,
} from "@nestia/fetcher";
import typia, { tags } from "typia";

import { IErpHrmReport } from "../../../../../../structures/IErpHrmReport";

/**
 * Retrieve available report types for an organization.
 *
 * This endpoint returns the list of report types that can be generated within the specified organization. The response includes metadata about each report type such as its identifier and description, enabling clients to present options to users before generating specific reports.
 *
 * Report types are defined organization-wide and include: Time Report for analyzing hours logged per employee with breakdowns by project or task and billable status filtering; Project Budget Report for viewing budget consumption across projects comparing estimated versus actual hours; and Weekly Summary Report for viewing week-by-week productivity statistics and trends.
 *
 * This operation requires the report:view permission to access. The system enforces strict data isolation between organizations - only report types from the user's currently selected organization context are accessible. Users belonging to multiple organizations will only see report types available in their current organization context.
 *
 * The response is a list of available report type objects containing the type identifier and descriptive information. This endpoint does not return actual report data or generated reports - for accessing generated reports, use the report index operation.
 *
 * @param props.connection
 * @param props.organizationId Unique identifier of the organization (global scope)
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor admin
 * @x-autobe-specification Query the erp_hrm_reports table to retrieve distinct report_type values available within the specified organization.
 *
 * Verify the organization exists and belongs to the user's current organization context for data isolation.
 *
 * Return a list of report type objects with the following structure:
 * - report_type: string identifier (time_report, project_budget_report, weekly_summary_report)
 * - description: human-readable description of what the report type contains
 *
 * Hardcoded report type metadata:
 * 1. time_report: Hours logged per employee for any date range, with breakdowns by employee, project, or task, and filtering by billable status
 * 2. project_budget_report: Budget consumption across projects showing estimated vs actual hours
 * 3. weekly_summary_report: Week-by-week statistics showing productivity trends
 *
 * The implementation should not query timelogs, projects, or other data tables - this is a metadata endpoint returning available report type options.
 * @path /erpHrm/admin/organizations/:organizationId/reports/types
 * @accessor api.functional.erpHrm.admin.organizations.reports.types.listTypes
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function listTypes(
  connection: IConnection,
  props: listTypes.Props,
): Promise<listTypes.Response> {
  return true === connection.simulate
    ? listTypes.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...listTypes.METADATA,
          path: listTypes.path(props),
          status: null,
        },
      );
}
export namespace listTypes {
  export type Props = {
    /**
     * Unique identifier of the organization (global scope)
     */
    organizationId: string & tags.Format<"uuid">;
  };
  export type Response = IErpHrmReport.IReportType;

  export const METADATA = {
    method: "GET",
    path: "/erpHrm/admin/organizations/:organizationId/reports/types",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/erpHrm/admin/organizations/${encodeURIComponent(props.organizationId ?? "null")}/reports/types`;
  export const random = (): IErpHrmReport.IReportType =>
    typia.random<IErpHrmReport.IReportType>();
  export const simulate = (
    connection: IConnection,
    props: listTypes.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: listTypes.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("organizationId")(() => typia.assert(props.organizationId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
