import {
  HttpError,
  IConnection,
  NestiaSimulator,
  PlainFetcher,
} from "@nestia/fetcher";
import typia, { tags } from "typia";

import { IErpHrmProjectMember } from "../../../../../../structures/IErpHrmProjectMember";

/**
 * Retrieve aggregated analytics and statistics about members assigned to a specific project.
 *
 * This endpoint returns project member analytics including total member count, breakdown by assigned role (member vs project_lead), and a list of current project members with their role assignments and join dates. The analytics are scoped to the specified project within the user's current organization context.
 *
 * Authorization requires one of the following permissions within the organization: project:read to view project membership, project:manage for full project control, time:view_all to see all member data, or report:view to access aggregate reports and metrics.
 *
 * The response includes summary statistics for quick overview and detailed member list for further analysis. Project membership data is sourced from erp_hrm_project_members table joined with erp_hrm_employees for member details.
 *
 * Error handling:
 * - 404 Not Found: Project does not exist or does not belong to the user's organization
 * - 403 Forbidden: User lacks required permissions to view project analytics
 *
 * @param props.connection
 * @param props.projectId Unique identifier of the project to retrieve member analytics for
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor admin
 * @x-autobe-specification Query erp_hrm_projects table to validate projectId exists and belongs to the user's organization.
 * Join erp_hrm_project_members with erp_hrm_employees to get member details.
 * Aggregate member count by assigned_role (member, project_lead).
 * Calculate total member count.
 * Return summary statistics and member details ordered by created_at.
 *
 * Validate that the project belongs to the user's current organization context.
 * Return empty analytics (not error) if project has no members.
 *
 * Error handling:
 * - 404 if projectId does not exist or belongs to different organization
 * - 403 if user lacks project view permission
 * @path /erpHrm/admin/projects/:projectId/analytics/members
 * @accessor api.functional.erpHrm.admin.projects.analytics.members.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique identifier of the project to retrieve member analytics for
     */
    projectId: string & tags.Format<"uuid">;
  };
  export type Response = IErpHrmProjectMember.ISummary;

  export const METADATA = {
    method: "GET",
    path: "/erpHrm/admin/projects/:projectId/analytics/members",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/erpHrm/admin/projects/${encodeURIComponent(props.projectId ?? "null")}/analytics/members`;
  export const random = (): IErpHrmProjectMember.ISummary =>
    typia.random<IErpHrmProjectMember.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("projectId")(() => typia.assert(props.projectId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
