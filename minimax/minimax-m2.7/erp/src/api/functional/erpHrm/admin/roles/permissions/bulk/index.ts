/**
 * Replace all permissions assigned to a role with a new set of permissions.
 *
 * This bulk update operation replaces the entire permission set of a custom role. The request body should contain the complete list of permission codes to assign. Permissions not included in the request are removed from the role.
 *
 * Built-in roles (Owner, Manager, Employee) cannot be modified. Attempting to update permissions for a built-in role returns a validation error. Only organization owners with org:manage permission can modify custom roles.
 *
 * The operation validates that all provided permission codes are valid system permissions. Duplicate permissions in the request are deduplicated before storage.
 *
 * @param props.connection
 * @param props.roleId Unique identifier of the role (UUID format)
 * @param props.body Array of permission codes to assign to the role
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor admin
 * @x-autobe-specification 1. Validate roleId exists and belongs to the current
 *   organization context 2. Retrieve the role from erp_hrm_roles table 3. Check
 *   role.is_builtin flag - if true, reject with 400 error 4. Validate all
 *   permission codes in request body against allowed permissions list:
 *   org:manage, employee:manage, employee:view, project:manage, project:view,
 *   time:manage, time:approve, time:view_all, report:view 5. Begin transaction:
 *   a. Delete all existing entries from erp_hrm_role_permissions where
 *   erp_hrm_role_id matches b. Insert new permission entries for each
 *   permission in request body c. Update role.updated_at timestamp 6. Commit
 *   transaction 7. Return the updated role with its new permission set
 *
 * Edge cases:
 * - Empty permissions array: clears all permissions (valid scenario for minimal access roles)
 * - Invalid permission code: reject with 400 error listing invalid codes
 * - Non-existent role: return 404 error
 * - Role from different organization: return 404 (not 403 to prevent enumeration)
 * @path /erpHrm/admin/roles/:roleId/permissions/bulk
 * @accessor api.functional.erpHrm.admin.roles.permissions.bulk.bulkUpdate
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function bulkUpdate(
  connection: IConnection,
  props: bulkUpdate.Props,
): Promise<bulkUpdate.Response> {
  return true === connection.simulate
    ? bulkUpdate.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...bulkUpdate.METADATA,
          path: bulkUpdate.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace bulkUpdate {
  export type Props = {
    /**
     * Unique identifier of the role (UUID format)
     */
    roleId: string & tags.Format<"uuid">;

    /**
     * Array of permission codes to assign to the role
     */
    body: IErpHrmRolePermission.IBulkUpdate;
  };
  export type Body = IErpHrmRolePermission.IBulkUpdate;
  export type Response = IErpHrmRole;

  export const METADATA = {
    method: "PUT",
    path: "/erpHrm/admin/roles/:roleId/permissions/bulk",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/erpHrm/admin/roles/${encodeURIComponent(props.roleId ?? "null")}/permissions/bulk`;
  export const random = (): IErpHrmRole => typia.random<IErpHrmRole>();
  export const simulate = (
    connection: IConnection,
    props: bulkUpdate.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: bulkUpdate.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("roleId")(() => typia.assert(props.roleId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
