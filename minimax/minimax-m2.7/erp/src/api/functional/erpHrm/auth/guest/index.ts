/**
 * Creates a new guest session for unauthenticated users who want temporary access to the system.
 *
 * This endpoint allows users to create a guest account identified by their device_id. The guest account provides temporary access with an expiration period (7 days by default). The device_id field uniquely identifies the guest device, while the temporary_email field can optionally store a contact email for the session. Upon successful registration, the system generates both an access_token for immediate API authentication and a refresh_token for token renewal when the access_token expires.
 *
 * The guest session is stored in the erp_hrm_guest_sessions table with references to the guest record. The access_token and refresh_token are JWT tokens that enable stateless authentication. When the guest eventually registers as a member or logs in, the guest session can be used to preserve context or migrate data.
 *
 * Security considerations: Device ID must be validated as UUID format. Guest accounts automatically expire after the configured expiration period. Temporary email is optional and validated for email format when provided.
 *
 * Related operations: POST /auth/guest/refresh - Token renewal endpoint for guests with valid refresh_token
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Guest join request containing device_id for device identification and optional temporary_email for contact purposes.
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor guest
 * @x-autobe-specification 1. Validate guest data from request body (device_id must be present and valid UUID format)
 * 2. Check if guest already exists for this device_id
 * 3. If exists and not expired, return existing guest session
 * 4. If not exists or expired, create new guest record with generated UUID and expiration (7 days from creation)
 * 5. Generate JWT access_token and refresh_token
 * 6. Create erp_hrm_guest_sessions record with tokens
 * 7. Return IErpHrmGuest.IAuthorized response with tokens and guest info
 * @path /erpHrm/auth/guest/join
 * @accessor api.functional.erpHrm.auth.guest.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
