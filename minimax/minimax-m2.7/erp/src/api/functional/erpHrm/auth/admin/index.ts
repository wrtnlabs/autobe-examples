/**
 * Creates a new administrator account for organization management. Accepts email (used as unique identifier), password (bcrypt hashed), and display name. Optional fields include phone number and avatar URI. Upon successful registration, returns JWT access and refresh tokens for immediate authentication. The admin account provides full access to organization settings, employee management, project oversight, and time tracking approvals.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Registration data for new admin account including email, password, and display name
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor admin
 * @x-autobe-specification 1. Receive IErpHrmAdmin.IJoin request body with email, password, displayName, phone (optional), avatarUri (optional)
 * 2. Validate email format and uniqueness in erp_hrm_admins table
 * 3. Validate password strength (min 8 chars, complexity requirements)
 * 4. Hash password using bcrypt
 * 5. Create new erp_hrm_admins record with provided data
 * 6. Generate JWT access and refresh tokens with admin ID in payload
 * 7. Create erp_hrm_admin_sessions record with IP, user agent, expiration (24 hours for access token)
 * 8. Return IErpHrmAdmin.IAuthorized with tokens, admin details
 *
 * Edge cases:
 * - Duplicate email: return 409 Conflict
 * - Weak password: return 400 Bad Request with validation details
 * - Server error: return 500 with generic error message
 * @path /erpHrm/auth/admin/join
 * @accessor api.functional.erpHrm.auth.admin.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
