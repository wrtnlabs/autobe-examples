import {
  HttpError,
  IConnection,
  NestiaSimulator,
  PlainFetcher,
} from "@nestia/fetcher";
import typia from "typia";

import { IErpHrmInvitation } from "../../../../structures/IErpHrmInvitation";

/**
 * Verify an invitation token and retrieve invitation details.
 *
 * This endpoint validates an invitation token received via email and returns the associated invitation information if valid. It is designed for prospective employees who have received an invitation link.
 *
 * The verification checks whether the token exists, the invitation has not expired, and the invitation status is still pending. If valid, the response includes the inviting organization name, the invited email address, the pre-assigned role and department (if any), and the expiration timestamp.
 *
 * This operation does not require authentication and can be called by unauthenticated users (guests) to verify invitation validity before creating an account or logging in.
 *
 * @param props.connection
 * @param props.token Secure token from the invitation link
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor guest
 * @x-autobe-specification Query the erp_hrm_invitations table using the
 *   provided token parameter.
 *
 * Validate the token exists and is not null. Reject verification if token is missing or null.
 *
 * Check invitation status is 'pending'. Reject verification for accepted or expired invitations.
 *
 * Check expiration timestamp if present. If expires_at is set and current time exceeds it, mark as expired and reject.
 *
 * Return invitation details including: id, email, status, organization name, role name (if pre-assigned), department name (if pre-assigned), position (if specified), note (if present), expires_at (if set), and created_at.
 *
 * Return 404 error with appropriate message if token does not exist or invitation is not found.
 *
 * Return 410 Gone status if invitation is expired with message indicating expiration.
 * @path /erpHrm/guest/invitations/verify/:token
 * @accessor api.functional.erpHrm.guest.invitations.verify
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function verify(
  connection: IConnection,
  props: verify.Props,
): Promise<verify.Response> {
  return true === connection.simulate
    ? verify.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...verify.METADATA,
          path: verify.path(props),
          status: null,
        },
      );
}
export namespace verify {
  export type Props = {
    /**
     * Secure token from the invitation link
     */
    token: string;
  };
  export type Response = IErpHrmInvitation.IVerifyResponse;

  export const METADATA = {
    method: "GET",
    path: "/erpHrm/guest/invitations/verify/:token",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/erpHrm/guest/invitations/verify/${encodeURIComponent(props.token ?? "null")}`;
  export const random = (): IErpHrmInvitation.IVerifyResponse =>
    typia.random<IErpHrmInvitation.IVerifyResponse>();
  export const simulate = (
    connection: IConnection,
    props: verify.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: verify.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("token")(() => typia.assert(props.token));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
