import { tags } from "typia";

import { IAuthorizationToken } from "./IAuthorizationToken";

export namespace IErpHrmGuest {
  /**
   * Request body for refreshing guest session tokens. Contains the refresh token issued during guest authentication to obtain new JWT access and refresh tokens.
   */
  export type IRefresh = {
    /**
     * The refresh token issued during guest authentication. Must be a valid, non-expired JWT.
     *
     * @x-autobe-specification JWT refresh token string from client. Server validates against erp_hrm_guest_sessions table to verify session is active and not expired. Token contains guest_id claim for session lookup.
     */
    refresh_token: string;
  };

  /**
   * Authorization response containing guest ID and JWT tokens for authenticated session. Returned after successful guest join or token refresh operations.
   */
  export type IAuthorized = {
    /**
     * Unique identifier of the authenticated guest.
     *
     * @x-autobe-specification UUID identifier generated by the server when creating a guest record in erp_hrm_guests table. Maps directly to the guest's primary key for subsequent API requests.
     */
    id: string & tags.Format<"uuid">;

    /**
     * Authorization token.
     *
     * @x-autobe-specification Authorization token comes from the session table.
     */
    token: IAuthorizationToken;
  };

  /**
   * Request body for guest user registration. Creates a new member account with email and password, and establishes their initial organization with name, currency, and timezone settings.
   */
  export type IJoin = {
    /**
     * Organization's primary currency code for financial settings (e.g., USD, EUR, KRW). Defaults to USD if not provided.
     *
     * @x-autobe-specification Maps to erp_hrm_organizations.currency. Direct column mapping, optional field that defaults to USD if not provided.
     */
    currency?: string | undefined;

    /**
     * Unique email address for the new account. Must be a valid email format and not already registered in the system.
     *
     * @x-autobe-specification Maps to erp_hrm_members.email. Must be unique, validated for email format.
     */
    email: string & tags.Format<"email">;

    /**
     * Current page URL for session tracking and security purposes. Used to track the origin of the registration request.
     *
     * @x-autobe-specification Session context: captured for session tracking and security audit. Stored in erp_hrm_guest_sessions.href. Not a column in actor tables.
     */
    href: string & tags.Format<"uri">;

    /**
     * Client IP address for server-side rendering scenarios. Optional field that is auto-detected by the server when not provided.
     *
     * @x-autobe-specification Session context: client IP address for security and audit logging. Stored in erp_hrm_guest_sessions.ip. Optional in IJoin because in SSR scenarios the client cannot reliably know its own IP - server captures it as fallback.
     */
    ip?: (string & tags.Format<"ipv4">) | undefined;

    /**
     * Display name for the new organization being created. This name will be shown in the organization context and dashboard.
     *
     * @x-autobe-specification Maps to erp_hrm_organizations.name. Also used to derive display_name in erp_hrm_members.
     */
    organizationName: string;

    /**
     * Password for the new account. Must be at least 8 characters. Stored securely as a hashed value.
     *
     * @x-autobe-specification Plain text password mapped to erp_hrm_members.password_hash via bcrypt hashing. Client sends plain text; server transforms before storage. Minimum 8 characters.
     */
    password: string & tags.MinLength<8>;

    /**
     * Password confirmation. Must exactly match the password field to confirm the password was entered correctly.
     *
     * @x-autobe-specification Validation field for password confirmation. Not stored in database. Must exactly match the password field for registration to succeed.
     */
    passwordConfirmation: string;

    /**
     * Referrer URL for session tracking and analytics. Indicates the previous page that linked to the registration page.
     *
     * @x-autobe-specification Session context: referrer URL for session tracking and analytics. Stored in erp_hrm_guest_sessions.referrer. Not a column in actor tables.
     */
    referrer: string & tags.Format<"uri">;

    /**
     * Organization's timezone for time tracking calculations (e.g., Asia/Seoul, America/New_York). Defaults to UTC if not provided.
     *
     * @x-autobe-specification Maps to erp_hrm_organizations.timezone. Direct column mapping, optional field that defaults to UTC if not provided.
     */
    timezone?: string | undefined;
  };
}
