/**
 * Test retrieving wishlist when customer has no saved items.
 *
 * Validates that a newly registered customer with an empty wishlist receives
 * the correct response structure. Verifies that the endpoint gracefully handles
 * the empty state by returning a valid paginated response with zero records.
 *
 * This test ensures the wishlist API correctly handles edge cases where customers
 * haven't bookmarked any products yet, returning an empty data array and proper
 * pagination metadata indicating no items exist.
 *
 * 1. Register a new customer account with randomized credentials.
 * 2. Create authenticated connection with the customer's JWT token.
 * 3. Call PATCH /ecommerceMall/customer/wishlist with default pagination.
 * 4. Validate response returns empty data array with correct pagination showing total=0, pages=0.
 */
export async function test_api_wishlist_empty_collection(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create new customer with empty wishlist
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  // 2. Get wishlist with default pagination
  const response = await api.functional.ecommerceMall.customer.wishlist.index(
    customerConnection,
    {
      body: {},
    },
  );
  typia.assert(response);
  // 3. Validate empty wishlist response
  TestValidator.equals("data array is empty", response.data.length, 0);
  TestValidator.equals("pagination total is 0", response.pagination.records, 0);
  TestValidator.equals("pagination pages is 0", response.pagination.pages, 0);
  TestValidator.equals(
    "pagination current is 0",
    response.pagination.current,
    0,
  );
  TestValidator.equals("pagination limit is 20", response.pagination.limit, 20);
}
