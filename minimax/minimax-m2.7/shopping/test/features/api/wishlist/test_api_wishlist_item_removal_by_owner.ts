export async function test_api_wishlist_item_removal_by_owner(
  connection: api.IConnection,
): Promise<void> {
  // Create and authenticate a customer
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  // Add a product to the customer's wishlist
  const wishlistItem =
    await generate_random_ecommerce_mall_customer_customers_wishlist_create(
      customerConnection,
      {},
    );
  typia.assert(wishlistItem);
  // Delete the wishlist item by its ID
  await api.functional.ecommerceMall.customer.wishlist.erase(
    customerConnection,
    {
      wishlistItemId: wishlistItem.id,
    },
  );
}
