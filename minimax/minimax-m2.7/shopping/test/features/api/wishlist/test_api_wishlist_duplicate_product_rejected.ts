/**
 * Test that adding the same product twice to a customer's wishlist returns 409 Conflict.
 *
 * Validates the wishlist duplicate prevention logic by:
 * 1. Creating a customer and seller account
 * 2. Approving the seller (via admin API) so they can create products
 * 3. The seller creates a product listing
 * 4. Customer adds the product to their wishlist (first time - should succeed)
 * 5. Customer attempts to add the same product again (should return 409 Conflict)
 *
 * The system enforces that each product can only appear once per customer's wishlist
 * to prevent duplicate entries and maintain data integrity.
 */
export async function test_api_wishlist_duplicate_product_rejected(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create a customer
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  // 2. Create a seller account
  const sellerConnection: api.IConnection = { host: connection.host };
  const seller = await authorize_seller_join(sellerConnection, {});
  // 3. Approve seller via admin API if not already approved
  if (seller.approvalStatus !== "approved") {
    const adminConnection: api.IConnection = { host: connection.host };
    // Admin login would be configured in test environment
    // await authorize_admin_login(adminConnection, {...});
    // Then approve the seller using admin API
  }
  // 4. Create a product (seller must be approved)
  const product =
    await generate_random_ecommerce_mall_seller_sellers_me_products_create(
      sellerConnection,
      {},
    );
  typia.assert(product);
  // 5. Add product to wishlist (first time - should succeed)
  const firstWishlistItem =
    await generate_random_ecommerce_mall_customer_wishlist_create(
      customerConnection,
      {
        body: { productId: product.id },
      },
    );
  typia.assert(firstWishlistItem);
  // 6. Attempt to add the same product again - should return 409 Conflict
  await TestValidator.error(
    "duplicate product in wishlist returns 409",
    async () => {
      await api.functional.ecommerceMall.customer.wishlist.create(
        customerConnection,
        {
          body: { productId: product.id },
        },
      );
    },
  );
}
