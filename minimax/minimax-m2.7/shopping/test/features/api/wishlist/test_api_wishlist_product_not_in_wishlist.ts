export async function test_api_wishlist_product_not_in_wishlist(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register a customer account
  const customerConnection: api.IConnection = { host: connection.host };
  const customer = await authorize_customer_join(customerConnection, {});
  // 2. Register a seller and create a product
  const sellerConnection: api.IConnection = { host: connection.host };
  const seller = await authorize_seller_join(sellerConnection, {});
  // Create a product (use utility function)
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerConnection,
    {},
  );
  // 3. Attempt to remove the product from wishlist WITHOUT adding it first
  // This should return 404 Not Found since the product is not in the customer's wishlist
  await TestValidator.error(
    "remove non-existent wishlist item returns 404",
    async () => {
      await api.functional.ecommerceMall.customer.wishlist.erase(
        customerConnection,
        {
          productId: product.id,
        },
      );
    },
  );
}
