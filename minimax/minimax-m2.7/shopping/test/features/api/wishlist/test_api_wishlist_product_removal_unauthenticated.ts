/**
 * Test that unauthenticated requests are rejected when removing a product from wishlist.
 *
 * Validates that the DELETE /ecommerceMall/customer/customers/me/wishlist/{productId}
 * endpoint properly enforces authentication requirements. An unauthenticated request
 * to remove a product from the wishlist must be rejected with HTTP 401 Unauthorized,
 * confirming that customers can only modify their own wishlist.
 *
 * This test ensures proper security enforcement where wishlist operations require
 * valid customer authentication. Without proper authorization, the system prevents
 * unauthorized modification of customer wishlists.
 *
 * 1. Attempt to call the wishlist deletion endpoint without authentication.
 * 2. Assert that HTTP 401 Unauthorized error is returned.
 */
export async function test_api_wishlist_product_removal_unauthenticated(
  connection: api.IConnection,
): Promise<void> {
  // Generate a random product ID for the test
  const productId = typia.random<string & tags.Format<"uuid">>();
  // Attempt to remove product from wishlist without authentication
  await TestValidator.httpError(
    "unauthenticated wishlist removal rejected",
    401,
    async () =>
      await api.functional.ecommerceMall.customer.customers.me.wishlist.erase(
        connection,
        { productId },
      ),
  );
}
