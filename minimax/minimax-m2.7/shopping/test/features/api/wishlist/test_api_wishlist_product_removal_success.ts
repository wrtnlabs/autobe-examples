export async function test_api_wishlist_product_removal_success(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register seller and create product
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: "https://example.com/seller/register",
      referrer: "https://example.com/",
    } satisfies IEcommerceMallSeller.IJoin,
  });
  await authorize_seller_login(sellerConnection, {
    body: {
      email: sellerAuth.email,
      password: "",
    } satisfies IEcommerceMallSeller.ILogin,
  });
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerConnection,
    {},
  );
  // 2. Register customer
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: "https://example.com/register",
      referrer: "https://example.com/",
    },
  });
  // 3. Add product to wishlist
  const wishlistItem =
    await generate_random_ecommerce_mall_customer_wishlist_create(
      customerConnection,
      {
        body: {
          productId: product.id,
        } satisfies IEcommerceMallWishlistItem.ICreate,
      },
    );
  typia.assert(wishlistItem);
  // 4. Remove product from wishlist - should succeed with 204 No Content
  await api.functional.ecommerceMall.customer.wishlist.erase(
    customerConnection,
    {
      productId: product.id,
    },
  );
  // 5. Verify product is no longer in wishlist - attempt to remove again should fail
  await TestValidator.error("product removed from wishlist", async () => {
    await api.functional.ecommerceMall.customer.wishlist.erase(
      customerConnection,
      {
        productId: product.id,
      },
    );
  });
}
