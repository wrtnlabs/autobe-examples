export async function test_api_wishlist_product_not_found(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register a new customer account
  const customer: IEcommerceMallCustomer.IAuthorized =
    await authorize_customer_join(connection, {});
  // 2. Create actor-specific connection with customer auth token
  const customerConnection: api.IConnection = { host: connection.host };
  customerConnection.headers ??= {};
  customerConnection.headers.Authorization = customer.token.access;
  // 3. Generate a random non-existent product UUID
  const nonExistentProductId = typia.random<string & tags.Format<"uuid">>();
  // 4. Attempt to add non-existent product to wishlist and expect 404 error
  await TestValidator.error("product not found returns 404", async () => {
    await api.functional.ecommerceMall.customer.wishlist.create(
      customerConnection,
      {
        body: {
          productId: nonExistentProductId,
        } satisfies IEcommerceMallWishlistItem.ICreate,
      },
    );
  });
}
