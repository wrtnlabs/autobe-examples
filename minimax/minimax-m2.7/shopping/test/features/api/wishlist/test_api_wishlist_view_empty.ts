/**
 * Test retrieving the authenticated customer's wishlist when it contains no items.
 *
 * Validates that a newly registered customer can view their empty wishlist. This test confirms the business rule that every customer has exactly one wishlist created automatically at registration time. The endpoint returns pagination metadata even for empty wishlists, with records and pages both set to 0.
 *
 * Steps:
 * 1. Register a new customer account using POST /auth/customer/join
 *    - This automatically creates an empty wishlist for the customer
 * 2. Retrieve the customer's wishlist using GET /customer/customers/me/wishlist
 * 3. Validate response structure and pagination metadata
 *
 * Validations:
 * - HTTP 200 OK response
 * - Pagination metadata shows records = 0 and pages = 0
 * - Data array is empty
 */
export async function test_api_wishlist_view_empty(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register a new customer account (wishlist is auto-created on registration)
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  // 2. Retrieve the customer's empty wishlist
  const wishlist =
    await api.functional.ecommerceMall.customer.customers.me.wishlist.at(
      customerConnection,
    );
  typia.assert(wishlist);
  // 3. Validate response
  TestValidator.equals("records is 0", wishlist.pagination.records, 0);
  TestValidator.equals("pages is 0", wishlist.pagination.pages, 0);
  TestValidator.equals("data is empty", wishlist.data.length, 0);
}
