export async function test_api_wishlist_empty_state_retrieval(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register a new customer (which creates an empty wishlist automatically)
  const customerConnection: api.IConnection = { host: connection.host };
  const authorized = await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "Password123!",
      href: "https://example.com/register",
      referrer: "https://example.com",
    },
  });
  typia.assert(authorized);
  // 2. Create authenticated connection with the customer's token
  const authenticatedConnection: api.IConnection = {
    host: connection.host,
    headers: {
      Authorization: `Bearer ${authorized.token.access}`,
    },
  };
  // 3. Retrieve empty wishlist for the newly registered customer
  const wishlistResponse =
    await api.functional.ecommerceMall.customer.wishlist.index(
      authenticatedConnection,
      {
        body: {},
      },
    );
  typia.assert(wishlistResponse);
  // 4. Validate empty wishlist response
  TestValidator.equals(
    "data array should be empty",
    wishlistResponse.data.length,
    0,
  );
}