export async function test_api_wishlist_item_removal_cross_customer(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register first customer and create wishlist item
  const firstCustomerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(firstCustomerConnection, {});
  const wishlistItem =
    await generate_random_ecommerce_mall_customer_customers_wishlist_create(
      firstCustomerConnection,
      {},
    );
  const wishlistItemId = wishlistItem.id;
  // 2. Register second customer
  const secondCustomerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(secondCustomerConnection, {});
  // 3. Second customer attempts to delete first customer's wishlist item
  // 4. Verify response returns 404 (ownership verification prevents info leakage)
  await TestValidator.httpError(
    "cross-customer wishlist deletion must return 404",
    404,
    async () => {
      await api.functional.ecommerceMall.customer.wishlist.erase(
        secondCustomerConnection,
        { wishlistItemId },
      );
    },
  );
}
