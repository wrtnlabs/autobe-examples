export async function test_api_wishlist_add_product_success(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register and login as seller
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {});
  typia.assert(sellerAuth);
  // 2. Login as seller (seller might need approval first, use existing credentials)
  const sellerLoginConnection: api.IConnection = { host: connection.host };
  const sellerLoginAuth = await authorize_seller_login(sellerLoginConnection, {
    body: {
      email: sellerAuth.email,
      password:
        sellerAuth.rejection_reason !== undefined ? "Test@1234" : "password",
      href: "https://example.com",
      referrer: "https://example.com",
    } satisfies IEcommerceMallSeller.ILogin,
  });
  typia.assert(sellerLoginAuth);
  // 3. Create a product
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerLoginConnection,
    {},
  );
  typia.assert(product);
  // 4. Register as customer
  const customerConnection: api.IConnection = { host: connection.host };
  const customerAuth = await authorize_customer_join(customerConnection, {});
  typia.assert(customerAuth);
  // 5. Add product to wishlist
  const wishlistItem =
    await generate_random_ecommerce_mall_customer_customers_wishlist_create(
      customerConnection,
      {
        body: {
          product_id: product.id,
        } satisfies IEcommerceMallWishlistItem.ICreate,
      },
    );
  typia.assert(wishlistItem);
  // 6. Validate wishlist item response
  TestValidator.equals(
    "wishlist item has valid id",
    wishlistItem.id.length > 0,
    true,
  );
  TestValidator.equals("product matches", wishlistItem.product.id, product.id);
  TestValidator.equals(
    "product name matches",
    wishlistItem.product.name,
    product.name,
  );
  TestValidator.predicate(
    "created_at is recent",
    new Date(wishlistItem.created_at).getTime() > Date.now() - 60000,
  );
}
