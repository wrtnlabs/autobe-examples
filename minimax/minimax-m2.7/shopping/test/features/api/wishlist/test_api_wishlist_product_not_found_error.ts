/**
 * Test that removing a product not in the customer's wishlist returns 404 error.
 *
 * Validates the system's handling of wishlist item removal when the product has not been added to the customer's wishlist. The test ensures that attempting to remove a non-existent wishlist item correctly returns a 404 Not Found response, protecting against accidental or malicious removal requests for items that don't exist in the wishlist.
 *
 * Setup creates the necessary infrastructure: an admin creates a product category, a seller creates a product listing, and a customer account is registered. The product is intentionally NOT added to the customer's wishlist.
 *
 * 1. Administrator registers and creates a product category.
 * 2. Seller registers, logs in, and creates a product.
 * 3. Customer registers and logs in.
 * 4. Customer attempts to remove the product from wishlist (without adding it first).
 * 5. System returns 404 Not Found error indicating wishlist item not found.
 */
export async function test_api_wishlist_product_not_found_error(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin setup - Create category for product
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  const category =
    await generate_random_ecommerce_mall_admin_admin_categories_create(
      adminConnection,
      {},
    );
  // 2. Seller setup - Register and create product
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {});
  const product =
    await generate_random_ecommerce_mall_seller_sellers_me_products_create(
      sellerConnection,
      {
        body: {
          categoryId: category.id,
          name: RandomGenerator.paragraph({ sentences: 2 }),
          description: RandomGenerator.content({ paragraphs: 3 }),
          basePrice: typia.random<
            number & tags.Type<"uint32"> & tags.Minimum<1000>
          >(),
        },
      },
    );
  // 3. Customer setup - Register and login
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  // 4. Attempt to remove product that is NOT in wishlist - should return 404
  await TestValidator.httpError(
    "product not in wishlist returns 404",
    404,
    async () =>
      await api.functional.ecommerceMall.customer.wishlist.erase(
        customerConnection,
        {
          productId: product.id,
        },
      ),
  );
}
