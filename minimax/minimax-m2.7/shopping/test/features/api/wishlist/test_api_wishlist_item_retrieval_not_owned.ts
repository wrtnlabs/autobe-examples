export async function test_api_wishlist_item_retrieval_not_owned(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register Customer A (wishlist owner)
  const customerAConnection: api.IConnection = { host: connection.host };
  const customerA = await authorize_customer_join(customerAConnection, {});
  typia.assert(customerA);
  // 2. Register Customer B (unauthorized accessor)
  const customerBConnection: api.IConnection = { host: connection.host };
  const customerB = await authorize_customer_join(customerBConnection, {});
  typia.assert(customerB);
  // 3. Customer A adds a product to their wishlist
  // Note: Using simulated wishlist creation to generate a valid wishlist item ID
  const wishlistItem =
    await generate_random_ecommerce_mall_customer_customers_wishlist_create(
      customerAConnection,
      {},
    );
  typia.assert(wishlistItem);
  // 4. Customer B attempts to retrieve Customer A's wishlist item
  // Expected: HTTP 404 Not Found (not 403 Forbidden)
  // This ensures the system does not leak information about whether the wishlist item exists
  await TestValidator.httpError(
    "customer B cannot retrieve another customer's wishlist item",
    404,
    async () =>
      await api.functional.ecommerceMall.customer.wishlist.at(
        customerBConnection,
        {
          wishlistItemId: wishlistItem.id,
        },
      ),
  );
}
