export async function test_api_seller_admin_request_duplicate_pending(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as seller
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {});
  // 2. Submit first admin request (should succeed)
  const firstRequest =
    await generate_random_ecommerce_mall_seller_admin_requests_create(
      sellerConnection,
      {
        body: {
          reason: RandomGenerator.paragraph({ sentences: 2 }),
        },
      },
    );
  typia.assert(firstRequest);
  TestValidator.equals("status is pending", firstRequest.status, "pending");
  // 3. Submit second admin request (should fail with PENDING_REQUEST_EXISTS)
  await TestValidator.error(
    "duplicate pending request should fail",
    async () => {
      await generate_random_ecommerce_mall_seller_admin_requests_create(
        sellerConnection,
        {
          body: {
            reason: RandomGenerator.paragraph({ sentences: 3 }),
          },
        },
      );
    },
  );
}
