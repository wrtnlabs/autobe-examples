/**
 * Test that deleting a non-existent address returns 404 Not Found.
 *
 * Validates the business rule that when a customer attempts to delete a shipping
 * address that no longer exists or has never existed, the system properly rejects
 * the request with a 404 Not Found status code. This ensures that the API
 * gracefully handles requests for non-existent resources without exposing
 * internal implementation details.
 *
 * 1. Register a new customer account via customer join endpoint.
 * 2. Generate a random UUID that does not correspond to any existing address.
 * 3. Attempt to delete the non-existent address via DELETE endpoint.
 * 4. Validate that the response is HTTP 404 Not Found.
 */
export async function test_api_address_deletion_non_existent_returns_404(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register a new customer account
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  // 2. Generate a UUID that does not exist
  const nonExistentAddressId = typia.random<string & tags.Format<"uuid">>();
  // 3. Attempt to delete the non-existent address
  // 4. Verify 404 Not Found is returned
  await TestValidator.httpError(
    "deleting non-existent address returns 404",
    404,
    async () =>
      await api.functional.ecommerceMall.customer.customers.me.addresses.erase(
        customerConnection,
        {
          addressId: nonExistentAddressId,
        },
      ),
  );
}
