export async function test_api_admin_request_duplicate_prevention(
  connection: api.IConnection,
): Promise<void> {
  // Step 1: Register a new customer to obtain valid authentication
  const customerConnection: api.IConnection = { host: connection.host };
  const registered = await authorize_customer_join(customerConnection, {});
  typia.assert(registered);
  // Step 2: Submit first admin request with valid reason
  const firstRequest =
    await generate_random_ecommerce_mall_customer_admin_requests_create(
      customerConnection,
      {
        body: {
          reason:
            "I want to help manage the platform content and ensure quality.",
        },
      },
    );
  typia.assert(firstRequest);
  // Step 3: Verify first request succeeds with pending status
  TestValidator.equals("first request status", firstRequest.status, "pending");
  // Step 4: Submit second admin request with different reason while first is pending
  // This should fail with PENDING_REQUEST_EXISTS error
  await TestValidator.error("duplicate admin request should fail", async () => {
    await api.functional.ecommerceMall.customer.admin.requests.create(
      customerConnection,
      {
        body: {
          reason: "I am interested in platform administration privileges.",
        } satisfies IEcommerceMallAdminRequest.ICreate,
      },
    );
  });
  // Step 5: Verify original pending request remains unchanged
  TestValidator.equals(
    "original status still pending",
    firstRequest.status,
    "pending",
  );
}
