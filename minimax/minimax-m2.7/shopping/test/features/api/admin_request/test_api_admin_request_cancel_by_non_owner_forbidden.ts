export async function test_api_admin_request_cancel_by_non_owner_forbidden(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register first seller account
  const seller1Connection: api.IConnection = { host: connection.host };
  const seller1Auth = await authorize_seller_join(seller1Connection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  // 2. Submit admin request as first seller
  const adminRequest =
    await api.functional.ecommerceMall.auth.admin.request.join(
      seller1Connection,
      {
        body: {
          actorType: "seller",
          requestedGrade: "admin",
          reason: RandomGenerator.paragraph({ sentences: 5 }),
          href: typia.random<string & tags.Format<"uri">>(),
          referrer: typia.random<string & tags.Format<"uri">>(),
        } satisfies IEcommerceMallAdmin.IJoin,
      },
    );
  typia.assert(adminRequest);
  // 3. Register second seller account
  const seller2Connection: api.IConnection = { host: connection.host };
  const seller2Auth = await authorize_seller_join(seller2Connection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  // 4. Attempt to cancel first seller's request as second seller
  // This should fail with 403 Forbidden
  await TestValidator.httpError(
    "non-owner cannot cancel admin request",
    403,
    async () =>
      await api.functional.ecommerceMall.seller.admin.requests.cancel(
        seller2Connection,
        {
          requestId: adminRequest.id,
        },
      ),
  );
}
