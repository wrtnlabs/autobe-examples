export async function test_api_customer_address_default_unauthorized(
  connection: api.IConnection,
): Promise<void> {
  // ==========================================================
  // SCENARIO: Setting default address fails for unauthorized access
  //
  // Test that a customer cannot set another customer's address as
  // default, and that non-existent addresses return 404.
  // ==========================================================
  // Step 1: Register Customer A and create an address
  const customerAConnection: api.IConnection = { host: connection.host };
  const customerA = await authorize_customer_join(customerAConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "Password123!",
      href: "https://example.com/register",
      referrer: "https://example.com",
    },
  });
  const addressA =
    await generate_random_ecommerce_mall_customer_customers_addresses_create(
      customerAConnection,
      {},
    );
  typia.assert(addressA);
  // Step 2: Register Customer B (different customer)
  const customerBConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerBConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "Password456!",
      href: "https://example.com/register",
      referrer: "https://example.com",
    },
  });
  // Step 3: Attempt to set Customer A's address as default using Customer B's session
  // This should fail with 404 because the address belongs to Customer A
  await TestValidator.error(
    "cannot set another customer's address as default",
    async () => {
      await api.functional.ecommerceMall.customer.addresses.setDefault(
        customerBConnection,
        {
          addressId: addressA.id,
        },
      );
    },
  );
  // Step 4: Attempt to set a non-existent address as default
  // This should fail with 404
  const nonExistentAddressId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.error(
    "cannot set non-existent address as default",
    async () => {
      await api.functional.ecommerceMall.customer.addresses.setDefault(
        customerAConnection,
        {
          addressId: nonExistentAddressId,
        },
      );
    },
  );
}
