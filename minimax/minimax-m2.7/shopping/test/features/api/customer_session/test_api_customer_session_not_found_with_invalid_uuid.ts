/**
 * Test that retrieving a non-existent session returns HTTP 404 Not Found.
 *
 * Validates the customer session retrieval error handling when an invalid session ID is provided. First, registers a new customer account to obtain valid authentication context. Then, attempts to retrieve a session using a random UUID that does not exist in the system. Verifies the API returns HTTP 404 status code indicating the session was not found.
 *
 * This test ensures proper error handling for session lookups with non-existent identifiers, protecting against invalid session access while providing appropriate feedback.
 *
 * 1. Register a new customer account to obtain valid authentication context.
 * 2. Generate a random UUID that does not exist in the system.
 * 3. Attempt to retrieve the session using the invalid UUID.
 * 4. Verify the API returns HTTP 404 Not Found status code.
 */
export async function test_api_customer_session_not_found_with_invalid_uuid(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register a new customer to get authenticated context
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  // 2. Generate a random UUID that doesn't exist in the system
  const invalidSessionId = typia.random<string & tags.Format<"uuid">>();
  // 3. Attempt to retrieve the session with invalid UUID
  // 4. Verify API returns 404 Not Found
  await TestValidator.httpError(
    "session not found returns 404",
    404,
    async () => {
      await api.functional.ecommerceMall.customer.customer.sessions.at(
        customerConnection,
        {
          sessionId: invalidSessionId,
        },
      );
    },
  );
}
