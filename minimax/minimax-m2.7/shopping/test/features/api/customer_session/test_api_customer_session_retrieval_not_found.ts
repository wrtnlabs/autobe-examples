/**
 * Test that requesting a non-existent session ID returns appropriate 404 error response.
 *
 * Steps:
 * 1. Register and login as a customer to establish valid authentication context
 * 2. Generate a random UUID that does not exist in the system
 * 3. Call GET /ecommerceMall/customer/sessions/{sessionId} with the non-existent session ID
 *
 * Expected Results:
 * - Response returns 404 Not Found status
 * - Response body indicates session was not found
 * - No sensitive session information is leaked
 */
export async function test_api_customer_session_retrieval_not_found(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register and login as a customer to establish valid authentication context
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  // 2. Generate a random UUID that does not exist in the system
  const nonExistentSessionId = typia.random<string & tags.Format<"uuid">>();
  // 3. Test that retrieving non-existent session returns 404 error
  await TestValidator.httpError(
    "non-existent session returns 404",
    404,
    async () => {
      await api.functional.ecommerceMall.customer.sessions.at(
        customerConnection,
        {
          sessionId: nonExistentSessionId,
        },
      );
    },
  );
}
