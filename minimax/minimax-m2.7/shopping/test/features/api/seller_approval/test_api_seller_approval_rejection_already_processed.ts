export async function test_api_seller_approval_rejection_already_processed(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register a seller account (creates pending approval)
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  // 2. Authenticate as administrator
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_login(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  // 3. First rejection should succeed
  const approval =
    await api.functional.ecommerceMall.admin.admin.seller_approvals.reject(
      adminConnection,
      {
        approvalId: sellerAuth.id,
        body: {
          rejectionReason: "Incomplete documentation",
        } satisfies IEcommerceMallSellerApproval.IReject,
      },
    );
  typia.assert(approval);
  // 4. Second rejection - should fail with 409 Conflict
  await TestValidator.httpError("already rejected approval", 409, async () => {
    await api.functional.ecommerceMall.admin.admin.seller_approvals.reject(
      adminConnection,
      {
        approvalId: sellerAuth.id,
        body: {
          rejectionReason: "Already rejected",
        } satisfies IEcommerceMallSellerApproval.IReject,
      },
    );
  });
}
