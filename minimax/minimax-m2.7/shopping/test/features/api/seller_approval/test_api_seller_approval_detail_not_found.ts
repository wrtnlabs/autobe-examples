export async function test_api_seller_approval_detail_not_found(
  connection: api.IConnection,
): Promise<void> {
  // Create admin connection for authentication
  const adminConnection: api.IConnection = { host: connection.host };
  // Authenticate as admin
  await authorize_admin_login(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IEcommerceMallAdmin.ILogin,
  });
  // Attempt to retrieve non-existent seller approval and expect 404
  await TestValidator.httpError(
    "non-existent approval returns 404",
    404,
    async () => {
      await api.functional.ecommerceMall.admin.admin.seller_approvals.at(
        adminConnection,
        {
          approvalId: typia.random<string & tags.Format<"uuid">>(),
        },
      );
    },
  );
}
