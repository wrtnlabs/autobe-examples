export async function test_api_checkout_prepare_with_deleted_variant_blocked(
  connection: api.IConnection,
): Promise<void> {
  // Step 1: Create and authenticate seller
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {});
  // Step 2: Create a product with a variant (seller must be approved to create products)
  // Note: This test assumes seller approval is handled externally or seller is pre-approved
  const product = await api.functional.ecommerceMall.seller.products.create(
    sellerConnection,
    {
      body: {
        name: RandomGenerator.paragraph({ sentences: 2 }),
        description: RandomGenerator.content({ paragraphs: 2 }),
        category_id: typia.random<string & tags.Format<"uuid">>(),
        base_price: typia.random<number & tags.Minimum<0>>(),
      } satisfies IEcommerceMallProduct.ICreate,
    },
  );
  typia.assert(product);
  // Step 3: Create and authenticate customer
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  // Step 4: Add product variant to cart
  // Note: In a real test, we'd need to create a variant first, but for this test
  // we'll use the generate function which handles variant creation
  const cartItem =
    await api.functional.ecommerceMall.customer.cart.items.create(
      customerConnection,
      {
        body: {
          variant_id: typia.random<string & tags.Format<"uuid">>(),
          quantity: typia.random<
            number & tags.Type<"int32"> & tags.Minimum<1>
          >(),
        } satisfies IEcommerceMallCartItem.ICreate,
      },
    );
  typia.assert(cartItem);
  // Step 5: Delete the product variant (simulate variant deletion after cart addition)
  await api.functional.ecommerceMall.seller.products.variants.erase(
    sellerConnection,
    {
      productId: product.id,
      variantId: cartItem.product_variant.id,
    },
  );
  // Step 6: Prepare checkout and verify deleted variant is marked as unavailable
  const checkoutPrepare =
    await api.functional.ecommerceMall.customer.checkout.prepare(
      customerConnection,
    );
  typia.assert(checkoutPrepare);
  // Step 7: Validate checkout response
  // The deleted variant should be marked as 'unavailable' in validatedItems
  const deletedVariantItem = checkoutPrepare.validatedItems.find(
    (item) => item.variant.id === cartItem.product_variant.id,
  );
  TestValidator.equals(
    "deleted variant should be unavailable",
    deletedVariantItem?.status,
    "unavailable",
  );
  // unavailableItemsCount should reflect the deleted item
  TestValidator.predicate(
    "unavailableItemsCount should be at least 1",
    checkoutPrepare.unavailableItemsCount >= 1,
  );
}
