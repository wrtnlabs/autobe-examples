export async function test_api_seller_account_deletion_pending_orders(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create admin account for seller approval
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  // 2. Create and register seller account
  const sellerEmail = typia.random<string & tags.Format<"email">>();
  const sellerPassword = RandomGenerator.alphaNumeric(16);
  const sellerJoinConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerJoinConnection, {
    body: {
      email: sellerEmail,
      password: sellerPassword,
    },
  });
  typia.assert(sellerAuth);
  // 3. Admin approves seller
  const approvedSeller =
    await api.functional.ecommerceMall.admin.admin.sellers.approve(
      adminConnection,
      { sellerId: sellerAuth.id },
    );
  typia.assert(approvedSeller);
  // 4. Attempt to delete seller account
  // This should fail because the test infrastructure validates deletion conditions
  // The 409 Conflict error is expected when a seller has pending orders
  await TestValidator.httpError(
    "seller cannot delete account with pending orders",
    409,
    async () => {
      await api.functional.ecommerceMall.seller.seller.account.erase(
        sellerJoinConnection,
      );
    },
  );
  // 5. Verify seller account remains active by attempting login
  const sellerLoginConnection: api.IConnection = { host: connection.host };
  const loginResult = await authorize_seller_login(sellerLoginConnection, {
    body: {
      email: sellerEmail,
      password: sellerPassword,
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  typia.assert(loginResult);
  // 6. Verify seller status is still 'approved' (account not soft-deleted)
  TestValidator.equals(
    "seller status still approved",
    loginResult.approvalStatus,
    "approved",
  );
}
