export async function test_api_seller_product_rating_statistics_not_found(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as seller
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {});
  // 2. Attempt to retrieve rating statistics for non-existent product
  await TestValidator.httpError(
    "rating statistics for non-existent product should return 404",
    404,
    async () =>
      await api.functional.ecommerceMall.seller.products.rating_statistics.ratingStatistics(
        sellerConnection,
        {
          productId: typia.random<string & tags.Format<"uuid">>(),
        },
      ),
  );
}
