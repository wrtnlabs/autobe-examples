export async function test_api_product_creation_blocked_for_pending_seller(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin authentication setup
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      actorType: "seller",
      requestedGrade: "admin",
      reason: "Test admin for product creation blocking test",
    },
  });
  // 2. Admin creates a category for product assignment
  const category = await generate_random_ecommerce_mall_admin_categories_create(
    adminConnection,
    {},
  );
  // 3. Seller joins with pending status (not yet approved)
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  // Validate seller has pending status
  TestValidator.equals(
    "seller approval status is pending",
    sellerAuth.approvalStatus,
    "pending",
  );
  // 4. Attempt to create product as pending seller - should be blocked
  await TestValidator.httpError(
    "product creation blocked for pending seller",
    403,
    async () => {
      await api.functional.ecommerceMall.seller.products.create(
        sellerConnection,
        {
          body: {
            name: RandomGenerator.paragraph({ sentences: 2 }),
            description: RandomGenerator.paragraph({ sentences: 5 }),
            categoryId: category.id,
            basePrice: typia.random<
              number & tags.Type<"uint32"> & tags.Minimum<1000>
            >(),
          },
        },
      );
    },
  );
}
