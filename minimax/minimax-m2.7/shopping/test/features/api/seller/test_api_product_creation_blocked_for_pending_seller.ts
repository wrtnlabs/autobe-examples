export async function test_api_product_creation_blocked_for_pending_seller(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register a new seller account with pending approval status
  const sellerConnection: api.IConnection = { host: connection.host };
  const authorized = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IEcommerceMallSeller.IJoin,
  });
  // 2. Verify the seller has pending approval status
  TestValidator.equals(
    "seller approval status is pending",
    authorized.approval_status,
    "pending",
  );
  // 3. Attempt to create a product as pending seller (should fail)
  await TestValidator.error(
    "product creation blocked for pending seller",
    async () => {
      await api.functional.ecommerceMall.seller.products.create(
        sellerConnection,
        {
          body: {
            name: RandomGenerator.paragraph({ sentences: 2 }),
            description: RandomGenerator.paragraph({ sentences: 5 }),
            category_id: typia.random<string & tags.Format<"uuid">>(),
            base_price: typia.random<
              number & tags.Type<"uint32"> & tags.Minimum<100>
            >(),
          } satisfies IEcommerceMallProduct.ICreate,
        },
      );
    },
  );
}
