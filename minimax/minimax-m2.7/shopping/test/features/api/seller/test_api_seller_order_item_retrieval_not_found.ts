export async function test_api_seller_order_item_retrieval_not_found(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register seller using utility function
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {});
  // 2. Generate non-existent order item UUID
  const nonExistentOrderItemId = typia.random<string & tags.Format<"uuid">>();
  // 3. Attempt to retrieve non-existent order item - should return 404
  await TestValidator.httpError(
    "404 for non-existent order item",
    404,
    async () =>
      await api.functional.ecommerceMall.seller.order_items.at(
        sellerConnection,
        {
          orderItemId: nonExistentOrderItemId,
        },
      ),
  );
}
