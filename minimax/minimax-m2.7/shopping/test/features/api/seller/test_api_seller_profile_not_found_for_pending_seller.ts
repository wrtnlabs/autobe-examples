/**
 * Test retrieving a seller profile when the seller has pending approval status.
 *
 * Validates that customers cannot view seller profiles for sellers whose registration
 * is still pending administrator approval. According to business rules, sellers must be
 * approved by administrators before becoming publicly visible on the platform. This test
 * ensures that attempting to access a pending seller's profile returns HTTP 404 Not Found.
 *
 * The test flow:
 * 1. Customer authenticates with the platform
 * 2. Test attempts to retrieve seller profile for a seller with pending status
 * 3. System should reject with 404 since only approved sellers are publicly visible
 *
 * This validates the seller approval visibility enforcement in the customer-facing API.
 */
export async function test_api_seller_profile_not_found_for_pending_seller(
  connection: api.IConnection,
): Promise<void> {
  // 1. Customer authenticates
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  // 2. Attempt to access seller profile - should fail with 404 for pending seller
  // Using a UUID that would represent a pending seller (in real scenario, this
  // would be obtained from a seller who registered but hasn't been approved yet)
  const pendingSellerId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.httpError(
    "pending seller profile not found",
    404,
    async () =>
      await api.functional.ecommerceMall.customer.sellers.at(
        customerConnection,
        {
          sellerId: pendingSellerId,
        },
      ),
  );
}
