export async function test_api_seller_product_snapshots_unauthorized_access(
  connection: api.IConnection,
): Promise<void> {
  // Setup: Register first seller and create a product
  const firstSellerConnection: api.IConnection = { host: connection.host };
  const firstSellerAuth = await authorize_seller_join(
    firstSellerConnection,
    {},
  );
  const firstProduct =
    await generate_random_ecommerce_mall_seller_products_create(
      firstSellerConnection,
      {},
    );
  // Setup: Register second seller as a different authenticated context
  const secondSellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(secondSellerConnection, {});
  // Test: Second seller attempts to access first seller's product snapshots
  // This should be rejected with 403 Forbidden as sellers can only access their own product snapshots
  await TestValidator.httpError(
    "Second seller cannot access first seller's product snapshots",
    403,
    async () =>
      await api.functional.ecommerceMall.seller.products.snapshots.index(
        secondSellerConnection,
        {
          productId: firstProduct.id,
          body: {},
        },
      ),
  );
}
