export async function test_api_seller_inventory_history_access_denied_other_seller(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin creates category for products
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  const category =
    await generate_random_ecommerce_mall_admin_admin_categories_create(
      adminConnection,
      {},
    );
  typia.assert(category);
  // 2. First seller joins and creates product
  const firstSellerConnection: api.IConnection = { host: connection.host };
  const firstSeller = await authorize_seller_join(firstSellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "TestPass123!",
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  // Create product for first seller
  const product =
    await generate_random_ecommerce_mall_seller_sellers_me_products_create(
      firstSellerConnection,
      {
        body: {
          categoryId: category.id,
          description: RandomGenerator.paragraph({ sentences: 3 }),
          name: RandomGenerator.name(),
          basePrice: typia.random<
            number & tags.Type<"uint32"> & tags.Minimum<1000>
          >(),
        },
      },
    );
  typia.assert(product);
  // Create variant for first seller's product
  const variant =
    await generate_random_ecommerce_mall_seller_sellers_me_products_variants_create(
      firstSellerConnection,
      {
        params: { productId: product.id },
        body: {
          optionValues: [{ key: "Size", value: "Large" }],
          price: typia.random<
            number & tags.Type<"uint32"> & tags.Minimum<1000>
          >(),
          skuCode: RandomGenerator.alphaNumeric(12),
        },
      },
    );
  typia.assert(variant);
  // 3. Second seller joins with different account
  const secondSellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(secondSellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "TestPass123!",
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  // 4. Second seller attempts to access first seller's variant inventory
  // Should return 403 Forbidden due to ownership verification
  await TestValidator.httpError(
    "access denied for other seller's variant inventory",
    403,
    async () =>
      await api.functional.ecommerceMall.seller.sellers.me.variants.inventory(
        secondSellerConnection,
        { variantId: variant.id },
      ),
  );
}
