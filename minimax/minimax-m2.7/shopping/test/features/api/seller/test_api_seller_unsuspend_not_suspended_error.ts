export async function test_api_seller_unsuspend_not_suspended_error(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as admin
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  // 2. Register a new seller (seller starts with pending status, not suspended)
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {});
  typia.assert(sellerAuth);
  // 3. Attempt to unsuspend the seller who is NOT suspended
  // Should return 400 error indicating seller is not currently suspended
  await TestValidator.httpError(
    "unsuspend non-suspended seller should return 400",
    400,
    async () => {
      await api.functional.ecommerceMall.admin.admin.sellers.unsuspend(
        adminConnection,
        {
          sellerId: sellerAuth.id,
          body: {} satisfies IEcommerceMallSeller.IUnsuspend,
        },
      );
    },
  );
}
