export async function test_api_product_creation_blocked_for_suspended_seller(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create admin connection for approval and suspension operations
  const adminConnection: api.IConnection = { host: connection.host };
  const adminAuth = await authorize_admin_join(adminConnection, {});
  // 2. Create seller connection for registration
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerEmail = typia.random<string & tags.Format<"email">>();
  const sellerPassword = RandomGenerator.alphaNumeric(16) as string &
    tags.Format<"password">;
  const sellerAuth = await authorize_seller_join(sellerConnection, {
    body: {
      email: sellerEmail,
      password: sellerPassword,
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  // 3. Verify seller is pending approval
  TestValidator.equals(
    "seller approval status is pending",
    sellerAuth.approval_status,
    "pending",
  );
  // 4. Admin approves the seller
  await generate_random_ecommerce_mall_admin_seller_approvals_create(
    adminConnection,
    {
      body: {
        sellerId: sellerAuth.id,
        status: "approved" as const,
      },
    },
  );
  // 5. Admin suspends the approved seller
  await generate_random_ecommerce_mall_admin_seller_suspensions_create(
    adminConnection,
    {
      body: {
        seller_id: sellerAuth.id,
        reason:
          "Policy violation test - suspended seller cannot create products",
      },
    },
  );
  // 6. Attempt to create product as suspended seller - should fail
  await TestValidator.error(
    "suspended seller cannot create products",
    async () => {
      await api.functional.ecommerceMall.seller.products.create(
        sellerConnection,
        {
          body: {
            name: RandomGenerator.name(2),
            description: RandomGenerator.paragraph({ sentences: 3 }),
            category_id: typia.random<string & tags.Format<"uuid">>(),
            base_price: typia.random<
              number & tags.Type<"uint32"> & tags.Minimum<1000>
            >(),
          } satisfies IEcommerceMallProduct.ICreate,
        },
      );
    },
  );
}
