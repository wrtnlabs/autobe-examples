export async function test_api_shipping_address_switch_default_address(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as customer
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  // 2. Create first address with is_default=true (becomes initial default)
  const firstAddress =
    await generate_random_ecommerce_mall_customer_customers_me_addresses_create(
      customerConnection,
      {
        body: {
          is_default: true,
        },
      },
    );
  typia.assert(firstAddress);
  // 3. Create second address with is_default=false
  const secondAddress =
    await generate_random_ecommerce_mall_customer_customers_me_addresses_create(
      customerConnection,
      {
        body: {
          is_default: false,
        },
      },
    );
  typia.assert(secondAddress);
  // 4. Verify first address is currently the default
  TestValidator.equals(
    "first address has is_default=true",
    firstAddress.isDefault,
    true,
  );
  TestValidator.equals(
    "second address has is_default=false",
    secondAddress.isDefault,
    false,
  );
  // 5. Call set-default endpoint with second address ID
  const updatedSecondAddress =
    await api.functional.ecommerceMall.customer.customers.me.addresses.set_default.setDefault(
      customerConnection,
      {
        addressId: secondAddress.id,
      },
    );
  typia.assert(updatedSecondAddress);
  // 6. Validate second address is now the default
  TestValidator.equals(
    "updated second address has is_default=true",
    updatedSecondAddress.isDefault,
    true,
  );
  TestValidator.equals(
    "second address ID preserved",
    updatedSecondAddress.id,
    secondAddress.id,
  );
}
