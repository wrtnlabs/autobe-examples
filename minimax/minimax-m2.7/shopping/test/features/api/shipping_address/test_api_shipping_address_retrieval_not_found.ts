export async function test_api_shipping_address_retrieval_not_found(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as a customer
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  // 2. Create a shipping address
  const address =
    await generate_random_ecommerce_mall_customer_customers_me_addresses_create(
      customerConnection,
      {},
    );
  typia.assert(address);
  // 3. Delete the address (soft delete)
  await api.functional.ecommerceMall.customer.customers.me.addresses.erase(
    customerConnection,
    {
      addressId: address.id,
    },
  );
  // 4. Attempt to retrieve the soft-deleted address - should return 404
  await TestValidator.httpError(
    "retrieve deleted address returns 404",
    404,
    async () =>
      await api.functional.ecommerceMall.customer.customers.me.addresses.getByAddressid(
        customerConnection,
        {
          addressId: address.id,
        },
      ),
  );
  // 5. Test with a completely non-existent UUID - should also return 404
  const nonExistentId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.httpError(
    "retrieve non-existent address returns 404",
    404,
    async () =>
      await api.functional.ecommerceMall.customer.customers.me.addresses.getByAddressid(
        customerConnection,
        {
          addressId: nonExistentId,
        },
      ),
  );
}
