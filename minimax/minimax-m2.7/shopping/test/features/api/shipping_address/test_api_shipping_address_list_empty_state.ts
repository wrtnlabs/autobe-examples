/**
 * Test retrieving shipping addresses for a newly registered customer who has not added any addresses yet.
 *
 * Validates that the system gracefully handles the empty state when a customer has no shipping addresses.
 * After customer registration, the addresses list should return an empty data array with correct pagination
 * metadata indicating zero records. This test ensures the API correctly processes and returns an empty
 * result set without errors, which is a fundamental requirement for any list endpoint.
 *
 * 1. Register a new customer account with valid credentials.
 * 2. Call GET /customers/me/addresses to retrieve addresses.
 * 3. Validate response contains empty data array and zero pagination records.
 */
export async function test_api_shipping_address_list_empty_state(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register a new customer
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  // 2. Get addresses (should be empty for new customer)
  const response =
    await api.functional.ecommerceMall.customer.customers.me.addresses.get(
      customerConnection,
    );
  typia.assert(response);
  // 3. Validate empty state
  TestValidator.equals("data array should be empty", response.data.length, 0);
  TestValidator.equals(
    "pagination records should be zero",
    response.pagination.records,
    0,
  );
  TestValidator.equals(
    "pagination pages should be zero",
    response.pagination.pages,
    0,
  );
}
