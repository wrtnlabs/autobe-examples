/**
 * Test that attempting to set a non-existent address as default returns 404 error.
 *
 * Validates the error handling when a customer tries to set an address ID that
 * doesn't exist as their default shipping address. The system should return a
 * 404 NOT_FOUND response when the specified address ID is not found in the
 * customer's address list or has been soft-deleted.
 *
 * **Prerequisites:**
 * 1. Authenticate as a customer using POST /auth/customer/join
 *
 * **Test Steps:**
 * 1. Generate a valid UUID that does not correspond to any existing address
 * 2. Call POST /customer/customers/me/addresses/{nonExistentId}/set-default
 * 3. Verify HTTP 404 response is returned
 * 4. Verify error message indicates address not found
 *
 * **Validation Points:**
 * - System returns 404 NOT_FOUND when address doesn't exist
 * - Error message is user-friendly
 * - No partial state changes occur
 */
export async function test_api_shipping_address_set_default_not_found(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as a customer
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  // 2. Generate a random UUID that doesn't exist
  const nonExistentAddressId = typia.random<string & tags.Format<"uuid">>();
  // 3. Attempt to set non-existent address as default and expect 404 error
  await TestValidator.httpError(
    "should return 404 when address not found",
    404,
    async () =>
      await api.functional.ecommerceMall.customer.customers.me.addresses.set_default.setDefault(
        customerConnection,
        {
          addressId: nonExistentAddressId,
        },
      ),
  );
}
