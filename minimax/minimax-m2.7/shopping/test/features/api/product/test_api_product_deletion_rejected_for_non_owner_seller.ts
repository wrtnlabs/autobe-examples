export async function test_api_product_deletion_rejected_for_non_owner_seller(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin creates a category
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  const category =
    await generate_random_ecommerce_mall_admin_admin_categories_create(
      adminConnection,
      {},
    );
  // 2. Seller A registers and joins (pending approval)
  const sellerAEmail = typia.random<string & tags.Format<"email">>();
  const sellerAConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerAConnection, {
    body: {
      email: sellerAEmail,
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  // 3. Seller A creates a product
  const product =
    await generate_random_ecommerce_mall_seller_sellers_me_products_create(
      sellerAConnection,
      {
        body: {
          categoryId: category.id,
          name: RandomGenerator.paragraph({ sentences: 2 }),
          description: RandomGenerator.paragraph({ sentences: 5 }),
          basePrice: typia.random<
            number & tags.Type<"uint32"> & tags.Minimum<1000>
          >(),
        },
      },
    );
  // 4. Seller B registers and joins
  const sellerBEmail = typia.random<string & tags.Format<"email">>();
  const sellerBConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerBConnection, {
    body: {
      email: sellerBEmail,
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  // 5. Seller B attempts to delete Seller A's product
  // This should fail with 403 Forbidden because Seller B does not own the product
  await TestValidator.httpError(
    "Seller B cannot delete Seller A's product - ownership verification enforced",
    403,
    async () =>
      await api.functional.ecommerceMall.seller.sellers.me.products.erase(
        sellerBConnection,
        {
          productId: product.id,
        },
      ),
  );
}
