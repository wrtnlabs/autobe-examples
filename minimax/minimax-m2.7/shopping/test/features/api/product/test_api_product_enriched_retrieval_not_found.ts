/**
 * Test retrieving product information for a product that does not exist.
 *
 * Validates the GET /ecommerceMall/customer/products/{productId}/enriched endpoint
 * when requesting a product with a UUID that does not correspond to any existing
 * product. The endpoint should return HTTP 404 Not Found status code with an
 * appropriate error message indicating the product was not found.
 *
 * This test verifies that:
 * 1. A random non-existent UUID returns 404 status code
 * 2. The response body indicates product not found error
 * 3. The system does not leak information about whether the product
 *    existed but was deleted vs never existed (security consideration)
 *
 * 1. Register a new customer account using authorize_customer_join.
 * 2. Generate a random UUID that does not correspond to any existing product.
 * 3. Call the enriched product endpoint with the non-existent UUID.
 * 4. Validate that the response returns 404 status code.
 * 5. Verify error handling is consistent (no distinction between deleted and non-existent).
 */
export async function test_api_product_enriched_retrieval_not_found(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register a new customer account for authentication
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  // 2. Generate a random UUID that does not correspond to any existing product
  const nonExistentProductId = typia.random<string & tags.Format<"uuid">>();
  // 3. Call the enriched product endpoint with non-existent UUID
  // Expect this to throw HttpError with 404 status
  await TestValidator.error("non-existent product returns 404", async () => {
    await api.functional.ecommerceMall.customer.products.enriched.at(
      customerConnection,
      {
        productId: nonExistentProductId,
      },
    );
  });
}
