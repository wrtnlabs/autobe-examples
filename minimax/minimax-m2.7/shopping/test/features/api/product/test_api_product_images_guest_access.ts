export async function test_api_product_images_guest_access(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as seller
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {});
  // 2. Create a product
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerConnection,
    {},
  );
  typia.assert(product);
  // 3. Upload images to the product
  const image1 =
    await generate_random_ecommerce_mall_seller_products_images_create(
      sellerConnection,
      {
        params: { productId: product.id },
      },
    );
  typia.assert(image1);
  const image2 =
    await generate_random_ecommerce_mall_seller_products_images_create(
      sellerConnection,
      {
        params: { productId: product.id },
      },
    );
  typia.assert(image2);
  // 4. Create guest connection (no authentication)
  const guestConnection: api.IConnection = { host: connection.host };
  // Ensure no Authorization header is set
  // 5. Access product images as guest
  const imagesResponse =
    await api.functional.ecommerceMall.products.images.list(guestConnection, {
      productId: product.id,
    });
  typia.assert(imagesResponse);
  // 6. Validate response structure
  TestValidator.equals(
    "has pagination",
    imagesResponse.pagination !== null,
    true,
  );
  TestValidator.predicate("has data array", imagesResponse.data.length >= 2);
  // 7. Validate images match what was uploaded
  const uploadedUrls = [image1.image_url, image2.image_url];
  const returnedUrls = imagesResponse.data.map((img) => img.image_url);
  TestValidator.predicate(
    "contains first uploaded image",
    returnedUrls.some((url) => url === uploadedUrls[0]),
  );
  TestValidator.predicate(
    "contains second uploaded image",
    returnedUrls.some((url) => url === uploadedUrls[1]),
  );
}
