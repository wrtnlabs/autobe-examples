export async function test_api_product_deletion_blocked_by_pending_cancellation(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin creates category
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_login(adminConnection, {
    body: {
      email: "admin@example.com",
      password: "Admin1234!",
      href: "http://localhost:3000",
      referrer: "http://localhost:3000",
    },
  });
  const category = await generate_random_ecommerce_mall_admin_categories_create(
    adminConnection,
    {},
  );
  typia.assert(category);
  // 2. Seller registers
  const sellerEmail = typia.random<string & tags.Format<"email">>();
  const sellerPassword = "Seller1234!";
  const sellerJoinConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerJoinConnection, {
    body: {
      email: sellerEmail,
      password: sellerPassword,
      href: "http://localhost:3000",
      referrer: "http://localhost:3000",
    },
  });
  // 3. Login as approved seller
  const approvedSellerConnection: api.IConnection = { host: connection.host };
  const seller = await authorize_seller_login(approvedSellerConnection, {
    body: {
      email: sellerEmail,
      password: sellerPassword,
    },
  });
  typia.assert(seller);
  // 4. Seller creates product
  const product = await generate_random_ecommerce_mall_seller_products_create(
    approvedSellerConnection,
    {
      body: {
        name: RandomGenerator.paragraph({ sentences: 2 }),
        description: RandomGenerator.paragraph({ sentences: 5 }),
        categoryId: category.id,
        basePrice: typia.random<
          number & tags.Type<"uint32"> & tags.Minimum<1000>
        >(),
      },
    },
  );
  typia.assert(product);
  // 5. Customer registers
  const customerEmail = typia.random<string & tags.Format<"email">>();
  const customerPassword = "Customer1234!";
  const customerJoinConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerJoinConnection, {
    body: {
      email: customerEmail,
      password: customerPassword,
      href: "http://localhost:3000",
      referrer: "http://localhost:3000",
    },
  });
  // 6. Login as customer
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_login(customerConnection, {
    body: {
      email: customerEmail,
      password: customerPassword,
      href: "http://localhost:3000",
      referrer: "http://localhost:3000",
    },
  });
  // 7. Customer creates shipping address
  const address =
    await generate_random_ecommerce_mall_customer_customers_addresses_create(
      customerConnection,
      {
        body: {
          recipientName: RandomGenerator.name(),
          phone: RandomGenerator.mobile(),
          streetAddress: "123 Test Street",
          city: "Test City",
          state: "Test State",
          postalCode: "12345",
          country: "Test Country",
          isDefault: true,
        },
      },
    );
  typia.assert(address);
  // 8. Customer checks out (uses existing cart - cart must be pre-populated)
  const order =
    await generate_random_ecommerce_mall_customer_customers_checkout_create(
      customerConnection,
      {
        body: {
          shippingAddressId: address.id,
        },
      },
    );
  typia.assert(order);
  // 9. Get the order item ID for cancellation
  const orderItemId = order.orderItems[0]!.id;
  // 10. Customer submits cancellation request for the paid order item
  const cancellationRequest =
    await generate_random_ecommerce_mall_customer_cancellation_requests_create(
      customerConnection,
      {
        body: {
          orderItemId: orderItemId,
          reason: "Changed mind about the purchase",
        },
      },
    );
  typia.assert(cancellationRequest);
  // 11. Verify cancellation request has pending status
  TestValidator.equals(
    "cancellation status is pending",
    cancellationRequest.status,
    "pending",
  );
  // 12. Seller attempts to delete the product - should be blocked
  await TestValidator.error(
    "product deletion blocked by pending cancellation",
    async () => {
      await api.functional.ecommerceMall.seller.products.erase(
        approvedSellerConnection,
        {
          productId: product.id,
        },
      );
    },
  );
}
