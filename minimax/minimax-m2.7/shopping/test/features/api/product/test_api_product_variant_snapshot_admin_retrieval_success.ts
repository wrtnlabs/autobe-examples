export async function test_api_product_variant_snapshot_admin_retrieval_success(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as admin
  const adminConnection: api.IConnection = { host: connection.host };
  const admin = await authorize_admin_join(adminConnection, {});
  // 2. Authenticate as seller
  const sellerConnection: api.IConnection = { host: connection.host };
  const seller = await authorize_seller_join(sellerConnection, {});
  // 3. Create a product
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerConnection,
    {},
  );
  typia.assert(product);
  // 4. Create a product variant with initial option values
  const variant =
    await generate_random_ecommerce_mall_seller_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
        body: {
          sku_code: `SKU-${Date.now().toString(36)}-${randint(1000, 9999)}`,
          option_values: [
            { key: "color", value: "Blue" },
            { key: "size", value: "Medium" },
          ] satisfies IEcommerceMallProductVariantOptionValue.ICreate[],
        } satisfies IEcommerceMallProductVariant.ICreate,
      },
    );
  typia.assert(variant);
  // 5. Update the variant to create a snapshot (snapshot preserves original state)
  const updatedVariant =
    await api.functional.ecommerceMall.seller.products.variants.update(
      sellerConnection,
      {
        productId: product.id,
        variantId: variant.id,
        body: {
          optionValues: [
            { value: "Red" },
            { value: "Large" },
          ] satisfies IEcommerceMallProductVariantOptionValue.IUpdate[],
        } satisfies IEcommerceMallProductVariant.IUpdate,
      },
    );
  typia.assert(updatedVariant);
  // 6. Create another update to have multiple snapshots, then retrieve the first one
  const secondUpdate =
    await api.functional.ecommerceMall.seller.products.variants.update(
      sellerConnection,
      {
        productId: product.id,
        variantId: variant.id,
        body: {
          optionValues: [
            { value: "Green" },
            { value: "Small" },
          ] satisfies IEcommerceMallProductVariantOptionValue.IUpdate[],
        } satisfies IEcommerceMallProductVariant.IUpdate,
      },
    );
  typia.assert(secondUpdate);
}