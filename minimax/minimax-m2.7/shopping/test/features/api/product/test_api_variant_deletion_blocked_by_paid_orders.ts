export async function test_api_variant_deletion_blocked_by_paid_orders(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin creates a category
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  const category =
    await generate_random_ecommerce_mall_admin_admin_categories_create(
      adminConnection,
      {},
    );
  typia.assert(category);
  // 2. Seller joins (starts with pending status)
  const sellerEmail = typia.random<string & tags.Format<"email">>();
  const sellerPassword = RandomGenerator.alphaNumeric(16);
  const sellerJoinConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerJoinConnection, {
    body: {
      email: sellerEmail,
      password: sellerPassword,
    },
  });
  // Admin approves seller (login first)
  const adminLoginConnection: api.IConnection = { host: connection.host };
  const adminAuth = await authorize_admin_login(adminLoginConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: "http://localhost:3000",
      referrer: "http://localhost:3000",
    },
  });
  // Login as approved seller to create products
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_login(sellerConnection, {
    body: {
      email: sellerEmail,
      password: sellerPassword,
      href: "http://localhost:3000",
      referrer: "http://localhost:3000",
    },
  });
  const product =
    await generate_random_ecommerce_mall_seller_sellers_me_products_create(
      sellerConnection,
      {
        body: {
          name: RandomGenerator.paragraph({ sentences: 2 }),
          description: RandomGenerator.paragraph({ sentences: 5 }),
          basePrice: typia.random<
            number & tags.Type<"uint32"> & tags.Minimum<1000>
          >(),
          categoryId: category.id,
        },
      },
    );
  typia.assert(product);
  const variant =
    await generate_random_ecommerce_mall_seller_sellers_me_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
        body: {
          skuCode: RandomGenerator.alphaNumeric(10),
          optionValues: [
            { key: "Size", value: "Large" },
            { key: "Color", value: "Blue" },
          ],
        },
      },
    );
  typia.assert(variant);
  // 3. Seller adds inventory to the variant
  const inventoryRecord =
    await generate_random_ecommerce_mall_seller_sellers_me_variants_inventory_add(
      sellerConnection,
      {
        params: { variantId: variant.id },
        body: {
          quantityChange: typia.random<
            number & tags.Type<"int32"> & tags.Minimum<10>
          >(),
          reason: "Initial stock for testing",
        },
      },
    );
  typia.assert(inventoryRecord);
  // 4. Customer joins and adds variant to cart
  const customerConnection: api.IConnection = { host: connection.host };
  const customerAuth = await authorize_customer_join(customerConnection, {});
  const cartQuantity = typia.random<
    number & tags.Type<"int32"> & tags.Minimum<1> & tags.Maximum<5>
  >();
  await generate_random_ecommerce_mall_customer_customers_me_cart_create(
    customerConnection,
    {
      body: {
        variantId: variant.id,
        quantity: cartQuantity,
      },
    },
  );
  // 5. Customer places order with payment (creates order items with "paid" status)
  const order =
    await generate_random_ecommerce_mall_customer_customers_me_orders_create(
      customerConnection,
      {
        body: {
          shippingAddressId: customerAuth.shippingAddresses[0]!.id,
        },
      },
    );
  typia.assert(order);
  // Verify order was created successfully with paid status
  TestValidator.equals("order status is paid", order.status, "paid");
  TestValidator.predicate("order has items", order.orderItems.length > 0);
  // 6. Seller attempts to delete the variant - should be blocked with HTTP 409
  await TestValidator.httpError(
    "variant deletion blocked by paid orders",
    409,
    async () => {
      await api.functional.ecommerceMall.seller.sellers.me.products.variants.erase(
        sellerConnection,
        {
          productId: product.id,
          variantId: variant.id,
        },
      );
    },
  );
  // 7. Verify variant remains active (deleted_at is null)
  // The variant should still be in the product's variant list
  TestValidator.predicate(
    "variant still exists in product",
    product.variants.some((v) => v.id === variant.id && v.deletedAt === null),
  );
  // Verify inventory was decremented by the order
  TestValidator.predicate(
    "inventory was decreased by order",
    inventoryRecord.quantityChange > 0,
  );
  // Verify order item references the variant
  const orderItem = order.orderItems[0];
  TestValidator.equals(
    "order item references correct variant",
    orderItem.productVariant.id,
    variant.id,
  );
  TestValidator.equals("order item status is paid", orderItem.status, "paid");
}
