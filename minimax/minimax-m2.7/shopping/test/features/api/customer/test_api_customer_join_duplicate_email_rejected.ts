/**
 * Test customer registration rejection when email already exists.
 *
 * Validates that the system prevents duplicate customer emails during registration.
 * First registers a customer with a specific email, then attempts to register
 * another customer with the same email address. Verifies the second registration
 * is rejected with appropriate error response.
 *
 * The test flow:
 * 1. Register first customer with a unique email address.
 * 2. Attempt to register second customer using the identical email.
 * 3. Verify the second registration attempt fails with duplicate email error.
 *
 * This ensures email uniqueness constraint is enforced for customer accounts
 * while validating the system properly rejects duplicate registration attempts.
 */
export async function test_api_customer_join_duplicate_email_rejected(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register first customer with unique email
  const duplicateEmail = typia.random<string & tags.Format<"email">>();
  const firstCustomerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(firstCustomerConnection, {
    body: {
      email: duplicateEmail,
      password: RandomGenerator.alphaNumeric(16),
      name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IEcommerceMallCustomer.IJoin,
  });
  // 2. Attempt to register second customer with duplicate email
  // 3. Verify error is thrown indicating email already exists
  await TestValidator.error(
    "duplicate email registration should be rejected",
    async () => {
      const secondCustomerConnection: api.IConnection = {
        host: connection.host,
      };
      await authorize_customer_join(secondCustomerConnection, {
        body: {
          email: duplicateEmail,
          password: RandomGenerator.alphaNumeric(16),
          name: RandomGenerator.name(),
          href: typia.random<string & tags.Format<"uri">>(),
          referrer: typia.random<string & tags.Format<"uri">>(),
        } satisfies IEcommerceMallCustomer.IJoin,
      });
    },
  );
}
