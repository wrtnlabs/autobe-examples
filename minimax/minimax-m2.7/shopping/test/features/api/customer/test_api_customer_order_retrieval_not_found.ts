/**
 * Test retrieving order details for a non-existent order ID.
 *
 * Validates error handling when the customer attempts to retrieve an order that
 * does not exist in the system or has been soft-deleted. Ensures the API returns
 * proper HTTP 404 Not Found status with appropriate error messaging.
 *
 * This test verifies the complete error handling flow:
 * 1. Customer registration is completed successfully
 * 2. A random UUID is generated that does not correspond to any existing order
 * 3. The order retrieval endpoint is called with the non-existent order ID
 * 4. The API returns HTTP 404 with appropriate error message
 *
 * The test also implicitly validates that soft-deleted orders are treated as
 * non-existent (deleted_at IS NOT NULL records return 404).
 */
export async function test_api_customer_order_retrieval_not_found(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register customer for authentication
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  // 2. Generate a random UUID that does not exist in the system
  const nonExistentOrderId = typia.random<string & tags.Format<"uuid">>();
  // 3. Attempt to retrieve non-existent order and validate 404 response
  await TestValidator.httpError(
    "non-existent order returns 404",
    404,
    async () =>
      await api.functional.ecommerceMall.customer.orders.at(
        customerConnection,
        {
          orderId: nonExistentOrderId,
        },
      ),
  );
}
