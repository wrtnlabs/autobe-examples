export async function test_api_customer_order_delete_already_deleted(
  connection: api.IConnection,
): Promise<void> {
  // 1. Customer registers and authenticates
  const customerConnection: api.IConnection = { host: connection.host };
  const customer = await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  typia.assert(customer);
  // 2. Customer creates and confirms an order via checkout
  const order =
    await api.functional.ecommerceMall.customer.checkout.confirm.create(
      customerConnection,
      {
        body: {
          payment_token: "test_payment_token",
        } satisfies IEcommerceMallCheckoutConfirm.IRequest,
      },
    );
  typia.assert(order);
  // 3. Customer deletes the order successfully
  await api.functional.ecommerceMall.customer.orders.erase(customerConnection, {
    orderId: order.id,
  });
  // 4. Customer attempts to delete the same order again
  // 5. Validate: Returns HTTP 409 Conflict because the order is already soft-deleted
  await TestValidator.httpError(
    "cannot delete already deleted order",
    409,
    () =>
      api.functional.ecommerceMall.customer.orders.erase(customerConnection, {
        orderId: order.id,
      }),
  );
}
