export async function test_api_customer_addresses_list_empty_state(
  connection: api.IConnection,
): Promise<void> {
  // Create a new customer account with no addresses
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  // Retrieve addresses - should return empty array for new customer
  const addresses =
    await api.functional.ecommerceMall.customer.addresses.list(
      customerConnection,
    );
  // Validate response is an empty array (not null)
  typia.assert(addresses);
  TestValidator.predicate(
    "addresses should be an empty array",
    Array.isArray(addresses) && addresses.length === 0,
  );
}
