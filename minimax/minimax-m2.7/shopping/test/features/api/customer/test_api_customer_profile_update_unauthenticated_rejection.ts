/**
 * Test seller profile update without authentication token.
 *
 * Validates that the PUT /ecommerceMall/customer/profile endpoint properly rejects
 * unauthenticated requests by returning HTTP 401 or 403 error. This ensures that
 * seller profile data is protected from unauthorized modifications.
 *
 * The test creates a connection without Authorization headers and attempts to
 * update the seller profile. The endpoint should reject the request immediately
 * without processing the request body, as no valid authentication credentials
 * are present.
 *
 * Security Validation:
 * - Unauthenticated requests must be rejected before processing business logic
 * - Error response should indicate authentication/authorization failure
 * - No profile data should be modified without proper authentication
 */
export async function test_api_customer_profile_update_unauthenticated_rejection(
  connection: api.IConnection,
): Promise<void> {
  // Create connection without authentication headers
  const unauthenticatedConnection: api.IConnection = {
    host: connection.host,
  };
  // Attempt to update profile without authentication
  await TestValidator.httpError(
    "unauthenticated profile update should be rejected",
    [401, 403],
    async () =>
      await api.functional.ecommerceMall.customer.profile.update(
        unauthenticatedConnection,
        {
          body: {
            name: "Test Shop",
            description: "Test Description",
          } satisfies IEcommerceMallSellerProfile.IUpdate,
        },
      ),
  );
}
