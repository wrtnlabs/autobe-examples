/**
 * Test customer attempting to view shipments for non-existent or unauthorized order.
 *
 * Validates the error handling when a customer tries to retrieve shipment tracking
 * information for an order that either does not exist or does not belong to them.
 * This ensures proper access control and data isolation between customers.
 *
 * The test verifies that:
 * - A customer cannot access shipments for non-existent orders
 * - A customer cannot access shipments for other customers' orders
 * - The API returns appropriate 404 error with meaningful message
 * - Order ownership is properly validated before returning shipment data
 *
 * 1. Authenticate as a new customer via join endpoint
 * 2. Generate a random UUID that doesn't exist in the system
 * 3. Attempt to retrieve shipments for the non-existent order
 * 4. Validate 404 error response indicating order not found or access denied
 */
export async function test_api_customer_shipment_tracking_order_not_found(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as customer
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  // 2. Attempt to get shipments for non-existent order ID
  const nonExistentOrderId = typia.random<string & tags.Format<"uuid">>();
  // 3. Validate error response - should return 404 for non-existent order
  await TestValidator.httpError(
    "should return 404 for non-existent order",
    404,
    async () =>
      await api.functional.ecommerceMall.customer.customers.me.orders.shipments.getByOrderid(
        customerConnection,
        {
          orderId: nonExistentOrderId,
        },
      ),
  );
}
