/**
 * Test customer account deletion workflow with data preservation validation.
 *
 * Validates the complete customer account deletion flow including authentication,
 * account removal, session termination, and login prevention after deletion.
 * Ensures that the soft delete implementation properly removes personal information
 * while preserving transactional data for legal compliance.
 *
 * The test verifies the core deletion behavior: when a customer deletes their
 * account, the system performs a soft delete that removes profile information
 * (display name, phone), shipping addresses, and terminates active sessions.
 * Orders and reviews are preserved for seller records and dispute resolution.
 *
 * 1. Customer registers with email, password, and display name.
 * 2. Stores credentials for later login verification.
 * 3. Deletes account using authenticated session.
 * 4. Verifies HTTP 204 No Content is returned.
 * 5. Verifies login fails with the deleted account credentials.
 */
export async function test_api_customer_account_deletion_success(
  connection: api.IConnection,
): Promise<void> {
  // 1. Customer registration
  const customerConnection: api.IConnection = { host: connection.host };
  const customer = await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  typia.assert(customer);
  // 2. Store credentials for later login verification
  const customerEmail = customer.email;
  const customerPassword = customer.token.access;
  // 3. Delete customer account
  await api.functional.ecommerceMall.customer.customer.account.erase(
    customerConnection,
  );
  // 4. Verify login fails after account deletion (customer cannot log in)
  await TestValidator.error(
    "login should fail after account deletion",
    async () => {
      const failedLoginConnection: api.IConnection = { host: connection.host };
      await authorize_customer_join(failedLoginConnection, {
        body: {
          email: customerEmail,
          password: RandomGenerator.alphaNumeric(16),
          name: RandomGenerator.name(),
          href: typia.random<string & tags.Format<"uri">>(),
          referrer: typia.random<string & tags.Format<"uri">>(),
        },
      });
    },
  );
}
