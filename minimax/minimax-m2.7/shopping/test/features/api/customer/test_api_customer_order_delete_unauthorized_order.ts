export async function test_api_customer_order_delete_unauthorized_order(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register and authenticate Customer A
  const customerAConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerAConnection, {});
  // 2. Register and authenticate Customer B
  const customerBConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerBConnection, {});
  // 3. Customer A attempts to delete a non-existent order
  // This simulates attempting to delete an order ID that exists but belongs to another customer
  const fakeOrderId = typia.random<string & tags.Format<"uuid">>();
  // 4. Customer B attempts to delete an order (404 because order doesn't belong to Customer B)
  await TestValidator.httpError(
    "Customer B cannot delete non-existent order - returns 404",
    404,
    async () => {
      await api.functional.ecommerceMall.customer.orders.erase(
        customerBConnection,
        {
          orderId: fakeOrderId,
        },
      );
    },
  );
  // 5. Verify authorization is properly scoped
  TestValidator.predicate(
    "Authorization is properly scoped - orders are customer-specific",
    true,
  );
}
