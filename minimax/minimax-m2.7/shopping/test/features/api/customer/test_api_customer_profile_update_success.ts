export async function test_api_customer_profile_update_success(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register a new customer account to obtain JWT tokens
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  // 2. Update profile with display_name and phone
  const body = {
    display_name: "John Doe",
    phone: "1234567890",
  } satisfies IEcommerceMallCustomerProfile.IUpdate;
  const profile = await api.functional.ecommerceMall.customer.profile.update(
    customerConnection,
    { body },
  );
  typia.assert(profile);
  // 3. Verify updated profile contains the new display_name and phone values
  TestValidator.equals(
    "display_name updated correctly",
    profile.display_name,
    "John Doe",
  );
  TestValidator.equals("phone updated correctly", profile.phone, "1234567890");
  // 4. Verify response includes customer object, id, created_at, and updated_at fields
  TestValidator.predicate("has customer object", profile.customer !== null);
  TestValidator.predicate("has id", !!profile.id);
  TestValidator.predicate("has created_at", !!profile.created_at);
  TestValidator.predicate("has updated_at", !!profile.updated_at);
}
