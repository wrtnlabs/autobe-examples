export async function test_api_customer_profile_display_name_update(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register a new customer
  const customerConnection: api.IConnection = { host: connection.host };
  const authorized = await authorize_customer_join(customerConnection, {});
  typia.assert(authorized);
  // 2. Capture initial profile values
  const initialDisplayName = authorized.profile.display_name;
  const initialPhone = authorized.profile.phone;
  const initialUpdatedAt = authorized.profile.updated_at;
  // 3. Generate a new display name for the update
  const newDisplayName = RandomGenerator.name();
  // 4. Update only the display_name (phone remains unchanged)
  const updatedProfile =
    await api.functional.ecommerceMall.customer.customers.me.update(
      customerConnection,
      {
        body: {
          display_name: newDisplayName,
          phone: initialPhone,
        } satisfies IEcommerceMallCustomerProfile.IUpdate,
      },
    );
  typia.assert(updatedProfile);
  // 5. Verify display_name is updated
  TestValidator.equals(
    "display_name updated",
    updatedProfile.display_name,
    newDisplayName,
  );
  // 6. Verify display_name differs from initial
  TestValidator.notEquals(
    "display_name changed",
    updatedProfile.display_name,
    initialDisplayName,
  );
  // 7. Verify phone remains unchanged
  TestValidator.equals("phone unchanged", updatedProfile.phone, initialPhone);
  // 8. Verify updated_at timestamp reflects the change
  TestValidator.predicate(
    "updated_at exists",
    updatedProfile.updated_at !== null &&
      updatedProfile.updated_at !== undefined,
  );
  // 9. Verify updated_at is later than or equal to original
  TestValidator.predicate(
    "updated_at reflects change",
    new Date(updatedProfile.updated_at).getTime() >=
      new Date(initialUpdatedAt).getTime(),
  );
}
