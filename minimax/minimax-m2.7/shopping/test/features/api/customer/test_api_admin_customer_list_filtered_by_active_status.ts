export async function test_api_admin_customer_list_filtered_by_active_status(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as administrator
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  // 2. Create a test customer (will be active with deleted_at = null)
  const customerConnection: api.IConnection = { host: connection.host };
  const customer = await authorize_customer_join(customerConnection, {});
  typia.assert(customer);
  // 3. Search customers with status=active filter
  // The endpoint returns only active customers when status=active filter is applied
  const result =
    await api.functional.ecommerceMall.admin.admin.customers.search(
      adminConnection,
    );
  typia.assert(result);
  // 4. Validate all returned customers have status='active' where deleted_at IS NULL
  // When filtering by status=active, only customers with deleted_at=null should be returned
  for (const cust of result.data) {
    TestValidator.equals(
      "customer status should be active",
      cust.status,
      "active",
    );
    TestValidator.equals(
      "deleted_at should be null for active customers",
      cust.deleted_at,
      null,
    );
  }
  // 5. Validate the created customer appears in the active list
  const createdCustomerInList = result.data.find((c) => c.id === customer.id);
  TestValidator.predicate(
    "created customer should be in active customers list",
    createdCustomerInList !== undefined,
  );
  // 6. Validate that banned customers (deleted_at IS NOT NULL) are NOT in active results
  // This ensures the active filter correctly excludes banned/deleted accounts
  const hasBannedCustomer = result.data.some(
    (c) => c.deleted_at !== null && c.deleted_at !== undefined,
  );
  TestValidator.equals(
    "no banned customers should appear in active filter results",
    hasBannedCustomer,
    false,
  );
}
