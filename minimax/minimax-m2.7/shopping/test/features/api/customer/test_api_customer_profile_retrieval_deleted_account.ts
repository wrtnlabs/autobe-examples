export async function test_api_customer_profile_retrieval_deleted_account(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register a new customer
  const customerConnection: api.IConnection = { host: connection.host };
  const authorized = await authorize_customer_join(customerConnection, {});
  typia.assert(authorized);
  // 2. Verify customer can access their own profile (deleted_at is null)
  const profile =
    await api.functional.ecommerceMall.customer.customers.me.at(
      customerConnection,
    );
  typia.assert(profile);
  TestValidator.equals(
    "deleted_at should be null before deletion",
    profile.deleted_at,
    null,
  );
  // 3. Delete the customer account
  await api.functional.ecommerceMall.customer.customer.account.erase(
    customerConnection,
  );
  // 4. Attempt to call GET /customer/customers/me with the existing token
  // Expected: HTTP 401 Unauthorized because the account is soft-deleted
  await TestValidator.httpError(
    "should return 401 after account deletion",
    401,
    async () => {
      await api.functional.ecommerceMall.customer.customers.me.at(
        customerConnection,
      );
    },
  );
}
