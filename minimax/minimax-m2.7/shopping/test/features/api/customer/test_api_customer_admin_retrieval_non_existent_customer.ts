/**
 * Test that an administrator receives 404 Not Found when attempting to retrieve
 * a customer account that does not exist in the system.
 *
 * Validates proper error handling when an administrator attempts to look up
 * a non-existent customer by ID. This test ensures that the admin endpoint
 * correctly returns HTTP 404 status with an appropriate error message when
 * the specified customer ID does not exist in the system.
 *
 * 1. Administrator authenticates using admin join/login credentials.
 * 2. Generate a random UUID that is guaranteed not to exist in the database.
 * 3. Call GET /admin/customers/{nonExistentUuid} with the random UUID.
 * 4. Verify the response returns 404 Not Found status.
 * 5. Verify the response body contains an error message indicating customer not found.
 * 6. Verify the response does not contain any customer data fields.
 */
export async function test_api_customer_admin_retrieval_non_existent_customer(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as an administrator
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  // 2. Generate a random UUID that does not correspond to any existing customer
  const nonExistentCustomerId = typia.random<string & tags.Format<"uuid">>();
  // 3. Call GET /admin/customers/{nonExistentUuid} with the non-existent customer ID
  // 4-6. Validate: Response status should be 404, error message should indicate customer not found,
  //         and response must NOT contain any customer data fields
  await TestValidator.httpError(
    "non-existent customer returns 404",
    404,
    async () =>
      await api.functional.ecommerceMall.admin.customers.at(adminConnection, {
        customerId: nonExistentCustomerId,
      }),
  );
}
