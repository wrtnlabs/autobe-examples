export async function test_api_customer_order_item_access_denied_other_customer(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create and authenticate as Customer A
  const customerAConnection: api.IConnection = { host: connection.host };
  const customerA = await authorize_customer_join(customerAConnection, {});
  // 2. Create admin and approve seller
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  const sellerConnection: api.IConnection = { host: connection.host };
  const seller = await authorize_seller_join(sellerConnection, {});
  // 3. Approve seller
  await api.functional.ecommerceMall.admin.admin.sellers.approve(
    adminConnection,
    {
      sellerId: seller.id,
    },
  );
  // 4. Create product with inventory
  const product =
    await api.functional.ecommerceMall.seller.sellers.me.products.create(
      sellerConnection,
      {
        body: {
          name: RandomGenerator.paragraph({ sentences: 2 }),
          description: RandomGenerator.paragraph({ sentences: 3 }),
          basePrice: typia.random<
            number & tags.Type<"uint32"> & tags.Minimum<1000>
          >(),
          categoryId: typia.random<string & tags.Format<"uuid">>(),
        } satisfies IEcommerceMallProduct.ICreate,
      },
    );
  typia.assert(product);
  // 5. Add inventory to the product variant
  const variantId = product.variants[0]!.id;
  await api.functional.ecommerceMall.seller.variants.inventory.create(
    sellerConnection,
    {
      variantId: variantId,
      body: {
        quantityChange: typia.random<
          number & tags.Type<"int32"> & tags.Minimum<1>
        >(),
        reason: "initial stock",
      } satisfies IEcommerceMallInventoryRecord.ICreate,
    },
  );
  // 6. Customer A adds product to cart
  await api.functional.ecommerceMall.customer.customers.me.cart.create(
    customerAConnection,
    {
      body: {
        variantId: variantId,
        quantity: typia.random<
          number & tags.Type<"int32"> & tags.Minimum<1> & tags.Maximum<3>
        >(),
      } satisfies IEcommerceMallCart.ICreate,
    },
  );
  // 7. Customer A places order
  const order =
    await api.functional.ecommerceMall.customer.customers.me.orders.create(
      customerAConnection,
      {
        body: {
          shippingAddressId: customerA.shippingAddresses[0]!.id,
        } satisfies IEcommerceMallOrder.ICreate,
      },
    );
  typia.assert(order);
  const orderId = order.id;
  const itemId = order.orderItems[0]!.id;
  // 8. Register and authenticate as Customer B
  const customerBConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerBConnection, {});
  // 9. Customer B attempts to access Customer A\'s order item
  // This should return 403 Forbidden
  await TestValidator.httpError(
    "access denied for other customer\'s order item",
    403,
    () =>
      api.functional.ecommerceMall.customer.orders.items.getByOrderidAndItemid(
        customerBConnection,
        {
          orderId: orderId,
          itemId: itemId,
        },
      ),
  );
}
