export async function test_api_order_items_empty_filter_results(
  connection: api.IConnection,
): Promise<void> {
  // 1. Customer registers and authenticates
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  // 2. Customer adds shipping address
  await generate_random_ecommerce_mall_customer_customers_addresses_create(
    customerConnection,
    {},
  );
  // 3. Customer creates order with items (checkout handles seller/product/cart internally)
  const order =
    await generate_random_ecommerce_mall_customer_customers_checkout_create(
      customerConnection,
      {},
    );
  typia.assert(order);
  // 4. Extract orderId
  const orderId = order.id;
  // 5. Call PATCH /ecommerceMall/orders/{orderId}/items with status filter 'delivered'
  // Items are 'paid' status, so filtering by 'delivered' should return empty results
  const orderItemsPage = await api.functional.ecommerceMall.orders.items.index(
    customerConnection,
    {
      orderId: orderId,
      body: {
        status: "delivered",
      } satisfies IEcommerceMallOrderItem.IRequest,
    },
  );
  typia.assert(orderItemsPage);
  // 6. Verify empty results gracefully returned
  TestValidator.equals(
    "data array should be empty",
    orderItemsPage.data.length,
    0,
  );
  TestValidator.equals(
    "records should be 0",
    orderItemsPage.pagination.pagination.records,
    0,
  );
}
