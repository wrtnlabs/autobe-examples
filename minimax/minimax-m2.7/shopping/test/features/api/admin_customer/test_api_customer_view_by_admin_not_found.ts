export async function test_api_customer_view_by_admin_not_found(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as administrator
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  await authorize_admin_login(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "1234",
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IEcommerceMallAdmin.ILogin,
  });
  // 2. Generate a non-existent customer UUID
  const nonExistentCustomerId = typia.random<string & tags.Format<"uuid">>();
  // 3. Call admin customer detail endpoint with non-existent customer ID
  // Expect 404 error
  await TestValidator.httpError(
    "admin view non-existent customer returns 404",
    404,
    async () =>
      await api.functional.ecommerceMall.admin.customers.at(adminConnection, {
        customerId: nonExistentCustomerId,
      }),
  );
}
