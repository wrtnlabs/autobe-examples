export async function test_api_product_variant_unauthorized_access_rejection(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin creates a category
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_login(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IEcommerceMallAdmin.ILogin,
  });
  const category = await generate_random_ecommerce_mall_admin_categories_create(
    adminConnection,
    {},
  );
  typia.assert(category);
  // 2. Seller A registers and creates Product A
  const sellerAConnection: api.IConnection = { host: connection.host };
  const sellerAAuthorized = await authorize_seller_join(sellerAConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  const sellerAProductConnection: api.IConnection = { host: connection.host };
  sellerAProductConnection.headers = {
    Authorization: sellerAAuthorized.token.access,
  };
  const productA = await generate_random_ecommerce_mall_seller_products_create(
    sellerAProductConnection,
    {
      body: {
        categoryId: category.id,
      },
    },
  );
  typia.assert(productA);
  // 3. Seller B registers
  const sellerBConnection: api.IConnection = { host: connection.host };
  const sellerBAuthorized = await authorize_seller_join(sellerBConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  const sellerBProductConnection: api.IConnection = { host: connection.host };
  sellerBProductConnection.headers = {
    Authorization: sellerBAuthorized.token.access,
  };
  // 4. Seller B attempts to add variant to Seller A's product (should get 403 Forbidden)
  await TestValidator.httpError(
    "Seller B cannot add variant to Seller A's product",
    403,
    async () =>
      await api.functional.ecommerceMall.seller.products.variants.create(
        sellerBProductConnection,
        {
          productId: productA.id,
          body: {
            skuCode: "SKU-UNAUTHORIZED-001",
            optionValues: [
              {
                key: "color",
                value: "green",
              } satisfies IEcommerceMallProductVariantOptionValue.ICreate,
            ],
            quantity: 25,
          } satisfies IEcommerceMallProductVariant.ICreate,
        },
      ),
  );
}
