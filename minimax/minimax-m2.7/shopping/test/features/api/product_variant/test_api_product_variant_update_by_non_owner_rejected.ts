export async function test_api_product_variant_update_by_non_owner_rejected(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register and authenticate as Seller A
  const sellerAConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerAConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  // 2. Seller A creates a product
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerAConnection,
    {},
  );
  // 3. Seller A creates a variant for the product
  const variant =
    await generate_random_ecommerce_mall_seller_seller_products_variants_create(
      sellerAConnection,
      {
        params: { productId: product.id },
        body: {
          sku_code: `SKU-${RandomGenerator.alphaNumeric(10)}`,
          option_values: [
            { key: "color", value: "Red" },
            { key: "size", value: "Large" },
          ],
        },
      },
    );
  // 4. Register and authenticate as Seller B
  const sellerBConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerBConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  // 5. Seller B attempts to update Seller A's product variant
  // This should be rejected with 403 Forbidden or 404 Not Found
  await TestValidator.error(
    "non-owner cannot update product variant",
    async () => {
      await api.functional.ecommerceMall.seller.products.variants.update(
        sellerBConnection,
        {
          productId: product.id,
          variantId: variant.id,
          body: {
            optionValues: [{ value: "Blue" }],
          } satisfies IEcommerceMallProductVariant.IUpdate,
        },
      );
    },
  );
}
