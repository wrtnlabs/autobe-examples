export async function test_api_product_variant_cross_seller_rejection(
  connection: api.IConnection,
): Promise<void> {
  // Create Seller A connection and authenticate
  const sellerAConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerAConnection, {});
  // Seller A creates a product
  const sellerAProduct =
    await generate_random_ecommerce_mall_seller_products_create(
      sellerAConnection,
      {},
    );
  typia.assert(sellerAProduct);
  // Create Seller B connection and authenticate
  const sellerBConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerBConnection, {});
  // Seller B attempts to create a variant for Seller A's product
  // This should fail with 404 because product ownership verification rejects the access
  await TestValidator.httpError(
    "seller B cannot create variant for seller A's product",
    404,
    async () =>
      await generate_random_ecommerce_mall_seller_seller_products_variants_create(
        sellerBConnection,
        {
          params: {
            productId: sellerAProduct.id,
          },
        },
      ),
  );
}
