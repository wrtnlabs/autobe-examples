export async function test_api_product_variant_option_value_deletion_forbidden_for_non_owner(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin creates a category (required for product creation)
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      actorType: "seller",
      requestedGrade: "admin",
      reason: "Need admin access for testing purposes",
      href: "http://localhost:3000",
      referrer: "http://localhost:3000",
    },
  });
  const category = await generate_random_ecommerce_mall_admin_categories_create(
    adminConnection,
    {},
  );
  typia.assert(category);
  // 2. First seller (owner) creates product with variant and option value
  const firstSellerConnection: api.IConnection = { host: connection.host };
  const firstSeller = await authorize_seller_join(firstSellerConnection, {});
  typia.assert(firstSeller);
  const product = await generate_random_ecommerce_mall_seller_products_create(
    firstSellerConnection,
    {
      body: {
        categoryId: category.id,
      },
    },
  );
  typia.assert(product);
  const variant =
    await generate_random_ecommerce_mall_seller_products_variants_create(
      firstSellerConnection,
      {
        params: { productId: product.id },
      },
    );
  typia.assert(variant);
  const optionValue =
    await generate_random_ecommerce_mall_seller_products_variants_option_values_create(
      firstSellerConnection,
      {
        params: { productId: product.id, variantId: variant.id },
      },
    );
  typia.assert(optionValue);
  // 3. Second seller (non-owner) attempts to delete the option value
  const secondSellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(secondSellerConnection, {});
  // Note: Second seller's JWT token is now in secondSellerConnection.headers
  // Validate that deletion is forbidden (403 Forbidden)
  await TestValidator.httpError(
    "seller cannot delete option value from another seller's product variant",
    403,
    async () => {
      await api.functional.ecommerceMall.seller.products.variants.option_values.erase(
        secondSellerConnection,
        {
          productId: product.id,
          variantId: variant.id,
          optionValueId: optionValue.id,
        },
      );
    },
  );
}
