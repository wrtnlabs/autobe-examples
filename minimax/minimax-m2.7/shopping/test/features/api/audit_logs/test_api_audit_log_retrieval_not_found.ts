export async function test_api_audit_log_retrieval_not_found(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as super administrator
  const superAdminConnection: api.IConnection = { host: connection.host };
  await authorize_super_admin_join(superAdminConnection, {});
  // 2. Generate a non-existent UUID for audit log retrieval
  const nonExistentAuditLogId = typia.random<string & tags.Format<"uuid">>();
  // 3. Verify 404 error when retrieving non-existent audit log
  await TestValidator.httpError(
    "should return 404 for non-existent audit log",
    404,
    async () =>
      await api.functional.ecommerceMall.superAdmin.admin.audit_logs.at(
        superAdminConnection,
        {
          auditLogId: nonExistentAuditLogId,
        },
      ),
  );
}
