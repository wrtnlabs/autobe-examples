export async function test_api_variant_snapshots_empty_result(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as seller
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {});
  // 2. Create product
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerConnection,
    {},
  );
  // 3. Create variant (no edits, so no snapshots exist)
  const variant =
    await generate_random_ecommerce_mall_seller_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
      },
    );
  // 4. Query variant snapshots without any filters
  const snapshots =
    await api.functional.ecommerceMall.seller.products.variants.snapshots.index(
      sellerConnection,
      {
        productId: product.id,
        variantId: variant.id,
        body: {},
      },
    );
  // 5. Validate response structure
  typia.assert(snapshots);
  // 6. Validate empty result
  TestValidator.equals("data array should be empty", snapshots.data, []);
  TestValidator.equals("records should be 0", snapshots.pagination.records, 0);
  TestValidator.equals("pages should be 0", snapshots.pagination.pages, 0);
}
