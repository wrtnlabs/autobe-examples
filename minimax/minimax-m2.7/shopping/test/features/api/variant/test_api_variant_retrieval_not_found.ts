export async function test_api_variant_retrieval_not_found(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register and login as a seller
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {});
  // 2. Create a product
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerConnection,
    {},
  );
  typia.assert(product);
  // 3. Create at least one variant (to prove the product is valid)
  const variant =
    await generate_random_ecommerce_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
      },
    );
  typia.assert(variant);
  // 4. Generate a random UUID that doesn't exist
  const nonExistentVariantId = typia.random<string & tags.Format<"uuid">>();
  // 5. Call GET with valid product ID but non-existent variant UUID
  // 6. Validate response returns 404 Not Found
  await TestValidator.httpError(
    "non-existent variant returns 404",
    404,
    async () =>
      await api.functional.ecommerceMall.seller.products.variants.at(
        sellerConnection,
        {
          productId: product.id,
          variantId: nonExistentVariantId,
        },
      ),
  );
}
