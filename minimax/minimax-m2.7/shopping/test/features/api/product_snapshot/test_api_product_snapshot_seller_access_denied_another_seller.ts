export async function test_api_product_snapshot_seller_access_denied_another_seller(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create admin connection for category creation
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_login(adminConnection, {
    body: {
      email: "admin@test.com",
      password: "1234",
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IEcommerceMallAdmin.ILogin,
  });
  // 2. Create category for product
  const category = await generate_random_ecommerce_mall_admin_categories_create(
    adminConnection,
    {},
  );
  typia.assert(category);
  // 3. Register and login as first seller
  const firstSellerConnection: api.IConnection = { host: connection.host };
  const firstSeller = await authorize_seller_join(firstSellerConnection, {});
  typia.assert(firstSeller);
  // 4. Create product as first seller
  const product = await generate_random_ecommerce_mall_seller_products_create(
    firstSellerConnection,
    {
      body: {
        name: RandomGenerator.paragraph({ sentences: 1 }),
        description: RandomGenerator.paragraph({ sentences: 3 }),
        categoryId: category.id,
        basePrice: typia.random<
          number & tags.Type<"uint32"> & tags.Minimum<1000>
        >(),
      } satisfies IEcommerceMallProduct.ICreate,
    },
  );
  typia.assert(product);
  // 5. Register second seller
  const secondSellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(secondSellerConnection, {});
  // 6. Attempt to access first seller's product snapshots as second seller
  // This should return 403 Forbidden
  await TestValidator.httpError(
    "Second seller cannot access first seller's product snapshots",
    403,
    async () => {
      await api.functional.ecommerceMall.seller.products.snapshots.index(
        secondSellerConnection,
        {
          productId: product.id,
          body: typia.random<IEcommerceMallProductSnapshot.IRequest>(),
        },
      );
    },
  );
}
