export async function test_api_seller_login_invalid_password(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register a new seller
  const sellerEmail = typia.random<string & tags.Format<"email">>();
  const sellerPassword = RandomGenerator.alphaNumeric(16);
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {
    body: {
      email: sellerEmail,
      password: sellerPassword,
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  typia.assert(sellerAuth);
  // 2. Create admin account and login
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      actorType: "seller",
      requestedGrade: "admin",
      reason: RandomGenerator.paragraph({ sentences: 2 }),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  const adminEmail = typia.random<string & tags.Format<"email">>();
  const adminPassword = RandomGenerator.alphaNumeric(16);
  await authorize_admin_login(adminConnection, {
    body: {
      email: adminEmail,
      password: adminPassword,
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  // 3. Attempt login with correct email but wrong password
  // Login with invalid password should fail regardless of approval status
  const invalidLoginConnection: api.IConnection = { host: connection.host };
  const wrongPassword = RandomGenerator.alphaNumeric(16) + "_WRONG";
  await TestValidator.error(
    "login with invalid password should fail",
    async () => {
      await api.functional.ecommerceMall.auth.seller.login(
        invalidLoginConnection,
        {
          body: {
            email: sellerEmail,
            password: wrongPassword,
          } satisfies IEcommerceMallSeller.ILogin,
        },
      );
    },
  );
}
