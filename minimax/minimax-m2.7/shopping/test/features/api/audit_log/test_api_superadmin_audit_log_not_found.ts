export async function test_api_superadmin_audit_log_not_found(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as super admin using utility function
  const superAdminConnection: api.IConnection = { host: connection.host };
  await authorize_super_admin_join(superAdminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    },
  });
  // 2. Attempt to retrieve a non-existent audit log and expect 404 error
  await TestValidator.httpError(
    "non-existent audit log returns 404",
    404,
    async () => {
      await api.functional.ecommerceMall.superAdmin.super_admin.audit_logs.at(
        superAdminConnection,
        {
          logId: typia.random<string & tags.Format<"uuid">>(),
        },
      );
    },
  );
}
