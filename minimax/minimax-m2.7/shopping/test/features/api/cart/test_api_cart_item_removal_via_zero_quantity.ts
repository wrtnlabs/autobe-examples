export async function test_api_cart_item_removal_via_zero_quantity(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin creates a category
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  const category =
    await generate_random_ecommerce_mall_admin_admin_categories_create(
      adminConnection,
      {},
    );
  typia.assert(category);
  // 2. Seller registers with specific credentials and logs in
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerPassword = RandomGenerator.alphaNumeric(16);
  const sellerAuth = await authorize_seller_join(sellerConnection, {
    body: {
      password: sellerPassword,
    },
  });
  await authorize_seller_login(sellerConnection, {
    body: {
      email: sellerAuth.email,
      password: sellerPassword,
      href: "https://example.com/seller",
      referrer: "https://example.com",
    } satisfies IEcommerceMallSeller.ILogin,
  });
  // 3. Seller creates a product
  const product =
    await generate_random_ecommerce_mall_seller_sellers_me_products_create(
      sellerConnection,
      {
        body: {
          categoryId: category.id,
        },
      },
    );
  typia.assert(product);
  // 4. Seller creates a product variant
  const variant =
    await generate_random_ecommerce_mall_seller_sellers_me_products_variants_create(
      sellerConnection,
      {
        body: {
          optionValues: [{ key: "Size", value: "Large" }],
          price: 10000,
          skuCode: `SKU-${RandomGenerator.alphaNumeric(8)}`,
        } satisfies IEcommerceMallProductVariant.ICreate,
        params: { productId: product.id },
      },
    );
  typia.assert(variant);
  // 5. Customer registers, logs in, and adds item to cart
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  const cartItem =
    await generate_random_ecommerce_mall_customer_customers_me_cart_create(
      customerConnection,
      {
        body: {
          quantity: 2,
          variantId: variant.id,
        } satisfies IEcommerceMallCart.ICreate,
      },
    );
  typia.assert(cartItem);
  TestValidator.equals("initial quantity is 2", cartItem.quantity, 2);
  // 6. Update cart item quantity to 0 (effectively removing it)
  const updatedCartItem =
    await api.functional.ecommerceMall.customer.customers.me.cart.update(
      customerConnection,
      {
        cartItemId: cartItem.id,
        body: {
          quantity: 0,
        } satisfies IEcommerceMallCartItem.IUpdate,
      },
    );
  typia.assert(updatedCartItem);
  TestValidator.equals("quantity is now 0", updatedCartItem.quantity, 0);
  // 7. Validate the cart reflects the removal (cart subtotal should be 0)
  TestValidator.equals("cart subtotal is 0", updatedCartItem.subtotal, 0);
}