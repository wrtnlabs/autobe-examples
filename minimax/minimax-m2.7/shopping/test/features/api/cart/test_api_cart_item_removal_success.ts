export async function test_api_cart_item_removal_success(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as seller and create product with variant
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {});
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerConnection,
    {},
  );
  const variant =
    await generate_random_ecommerce_mall_seller_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
      },
    );
  // 2. Authenticate as customer and add item to cart
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  const quantity = typia.random<
    number & tags.Type<"int32"> & tags.Minimum<1>
  >();
  const cartItem =
    await generate_random_ecommerce_mall_customer_cart_items_create(
      customerConnection,
      {
        body: {
          variant_id: variant.id,
          quantity: quantity,
        },
      },
    );
  typia.assert(cartItem);
  // 3. Verify cart item exists and has correct data
  TestValidator.equals(
    "cart item has correct variant",
    cartItem.product_variant.id,
    variant.id,
  );
  TestValidator.equals(
    "cart item has correct quantity",
    cartItem.quantity,
    quantity,
  );
  // 4. Remove the cart item via DELETE endpoint (204 No Content expected)
  await api.functional.ecommerceMall.customer.customers.cart.items.erase(
    customerConnection,
    { itemId: cartItem.id },
  );
  // 5. Verify item removal by adding a different item to cart
  // If deletion succeeded, the new item will have a different ID
  const newQuantity = typia.random<
    number & tags.Type<"int32"> & tags.Minimum<1>
  >();
  const newCartItem =
    await generate_random_ecommerce_mall_customer_cart_items_create(
      customerConnection,
      {
        body: {
          variant_id: variant.id,
          quantity: newQuantity,
        },
      },
    );
  typia.assert(newCartItem);
  // Verify the new item ID is different from the deleted item ID
  TestValidator.notEquals(
    "new item has different ID from deleted item",
    newCartItem.id,
    cartItem.id,
  );
  TestValidator.equals(
    "new item has correct variant",
    newCartItem.product_variant.id,
    variant.id,
  );
  TestValidator.equals(
    "new item has correct quantity",
    newCartItem.quantity,
    newQuantity,
  );
}
