export async function test_api_cart_item_removal_other_customer(
  connection: api.IConnection,
): Promise<void> {
  // Test security boundary where customer attempts to remove a cart item belonging to another customer.
  // 1. First customer authenticates and adds item to cart
  // 2. Second customer authenticates separately
  // 3. Second customer attempts to delete first customer's cart item
  // 4. Verify 404 Not Found response (not unauthorized, to prevent information leakage)
  // Step 1: Seller setup - Create product with variant for cart item
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {});
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerConnection,
    {},
  );
  const variant =
    await generate_random_ecommerce_mall_seller_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
      },
    );
  // Step 2: First customer joins and adds item to cart
  const firstCustomerConnection: api.IConnection = { host: connection.host };
  const firstCustomerAuth = await authorize_customer_join(
    firstCustomerConnection,
    {},
  );
  const firstCustomerCartItem =
    await generate_random_ecommerce_mall_customer_cart_items_create(
      firstCustomerConnection,
      {
        body: {
          variant_id: variant.id,
          quantity: typia.random<
            number & tags.Type<"int32"> & tags.Minimum<1>
          >(),
        },
      },
    );
  // Step 3: Second customer authenticates separately
  const secondCustomerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(secondCustomerConnection, {});
  // Step 4: Second customer attempts to remove first customer's cart item
  // Should return 404 Not Found (security: returns not-found, not unauthorized)
  await TestValidator.httpError(
    "second customer cannot remove first customer's cart item (404 expected)",
    404,
    async () =>
      await api.functional.ecommerceMall.customer.customers.cart.items.erase(
        secondCustomerConnection,
        { itemId: firstCustomerCartItem.id },
      ),
  );
}
