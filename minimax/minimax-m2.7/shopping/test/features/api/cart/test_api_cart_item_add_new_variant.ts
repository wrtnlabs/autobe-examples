export async function test_api_cart_item_add_new_variant(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as a customer
  const customerConnection: api.IConnection = { host: connection.host };
  const authorized = await authorize_customer_join(customerConnection, {});
  typia.assert(authorized);
  // 2. Add a new variant to the cart with quantity 1
  const cartItem =
    await generate_random_ecommerce_mall_customer_me_cart_items_create(
      customerConnection,
      {
        body: {
          quantity: 1,
        },
      },
    );
  typia.assert(cartItem);
  // 3. Validate response structure
  TestValidator.equals("quantity is 1", cartItem.quantity, 1);
  TestValidator.predicate("variant exists", cartItem.variant !== null);
  TestValidator.predicate("product exists", cartItem.product !== null);
  TestValidator.predicate("subtotal is positive", cartItem.subtotal > 0);
  TestValidator.predicate(
    "has valid timestamps",
    cartItem.createdAt !== undefined && cartItem.updatedAt !== undefined,
  );
}
