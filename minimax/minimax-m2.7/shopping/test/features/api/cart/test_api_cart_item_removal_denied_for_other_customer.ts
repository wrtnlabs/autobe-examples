export async function test_api_cart_item_removal_denied_for_other_customer(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register Customer A who owns the cart item
  const customerAConnection: api.IConnection = { host: connection.host };
  const customerA = await authorize_customer_join(customerAConnection, {});
  // 2. Register Customer B who will attempt unauthorized removal
  const customerBConnection: api.IConnection = { host: connection.host };
  const customerB = await authorize_customer_join(customerBConnection, {});
  // 3. Customer A adds item to cart and note the itemId
  const cartItem =
    await generate_random_ecommerce_mall_customer_cart_items_create(
      customerAConnection,
      {},
    );
  typia.assert(cartItem);
  const itemId = cartItem.id;
  // 4. Customer B attempts to remove Customer A's cart item
  // 5. Validate response returns 404 Not Found error
  await TestValidator.httpError(
    "customer B cannot remove customer A's cart item",
    404,
    async () => {
      await api.functional.ecommerceMall.customer.cart.items.erase(
        customerBConnection,
        {
          itemId: itemId,
        },
      );
    },
  );
}
