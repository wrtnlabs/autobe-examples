export async function test_api_cart_quantity_update_to_zero_removes_item(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create admin connection and authenticate
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  // 2. Create category for product
  const category =
    await generate_random_ecommerce_mall_admin_admin_categories_create(
      adminConnection,
      {},
    );
  typia.assert(category);
  // 3. Seller registers
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {});
  // 4. Seller creates product with category
  const product =
    await generate_random_ecommerce_mall_seller_sellers_me_products_create(
      sellerConnection,
      {
        body: {
          categoryId: category.id,
        },
      },
    );
  typia.assert(product);
  // 5. Seller creates variant with stock
  const variant =
    await generate_random_ecommerce_mall_seller_sellers_me_products_variants_create(
      sellerConnection,
      {
        body: {
          optionValues: [
            { key: "Size", value: "Large" },
            { key: "Color", value: "Blue" },
          ],
        },
        params: {
          productId: product.id,
        },
      },
    );
  typia.assert(variant);
  // 6. Customer registers and adds item to cart
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  const cartItem =
    await generate_random_ecommerce_mall_customer_me_cart_items_create(
      customerConnection,
      {
        body: {
          productVariantId: variant.id,
          quantity: 2,
        },
      },
    );
  typia.assert(cartItem);
  // Store the cart item ID and price for validation
  const cartItemId = cartItem.id;
  const unitPrice = cartItem.variant.price ?? product.basePrice;
  const expectedSubtotal = 2 * unitPrice;
  // Verify item was added to cart by checking the cart response
  TestValidator.predicate("cart item has valid id", cartItemId !== undefined);
  TestValidator.equals("cart item quantity matches", cartItem.quantity, 2);
  TestValidator.equals(
    "cart item subtotal calculated",
    cartItem.subtotal,
    expectedSubtotal,
  );
  // 7. Update cart item quantity to 0 (should remove the item)
  const updatedCart =
    await api.functional.ecommerceMall.customer.me.cart.items.patch(
      customerConnection,
      {
        body: {
          quantity: 0,
        } satisfies IEcommerceMallCartItem.IUpdate,
      },
    );
  typia.assert(updatedCart);
  // 8. Validate item is removed from cart
  TestValidator.equals(
    "removed item not in cart items",
    updatedCart.items.find((item) => item.id === cartItemId),
    undefined,
  );
  // 9. Validate cart total is 0 after item removal
  TestValidator.equals("cart total is 0 after removal", updatedCart.total, 0);
  // 10. Validate cart has no items after removal
  TestValidator.predicate(
    "cart has no items after removal",
    updatedCart.items.length === 0,
  );
}
