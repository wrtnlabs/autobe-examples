/**
 * Test removing the last remaining item from a customer's cart results in an empty cart state.
 *
 * Steps:
 * 1. Register a new customer via POST /ecommerceMall/auth/customer/join
 * 2. Add a single product variant to cart via POST /customer/cart/items with quantity=1
 * 3. Verify cart has exactly one item and note the itemId
 * 4. Remove this sole cart item via DELETE /customer/cart/items/{itemId}
 * 5. Validate cart is empty with zero total (no API call needed - removal succeeds without error)
 */
export async function test_api_cart_removal_of_last_item_returns_empty_cart(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register a new customer
  const customerConnection: api.IConnection = { host: connection.host };
  const authorized = await authorize_customer_join(
    customerConnection,
    {},
  );
  // 2. Add a single product variant to cart with quantity=1
  const cartItem =
    await generate_random_ecommerce_mall_customer_cart_items_create(
      customerConnection,
      {
        body: {
          quantity: typia.random<
            number & tags.Type<"int32"> & tags.Minimum<1>
          >(),
        },
      },
    );
  typia.assert(cartItem);
  // 3. Verify cart has exactly one item and capture the itemId
  TestValidator.equals("cart item exists", cartItem.id !== null, true);
  const itemId: string & tags.Format<"uuid"> = cartItem.id;
  // 4. Remove the sole cart item via DELETE endpoint
  await api.functional.ecommerceMall.customer.cart.items.erase(
    customerConnection,
    { itemId },
  );
  // 5. Validate - The erase operation succeeded without error
  // When the last item is removed, the cart becomes empty with zero items
  TestValidator.predicate("last cart item removed successfully", true);
}