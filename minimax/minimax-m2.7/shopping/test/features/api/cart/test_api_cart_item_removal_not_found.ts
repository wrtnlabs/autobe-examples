/**
 * Test removing a cart item when the item does not exist or doesn't belong to the customer.
 *
 * Validates the cart item deletion behavior for non-existent items. When attempting to delete a cart item that either doesn't exist in the system or doesn't belong to the authenticated customer, the API must return a 404 Not Found error. This ensures proper data isolation and prevents unauthorized access to other customers' cart items.
 *
 * 1. Customer registers with valid credentials via join.
 * 2. Customer authenticates and receives JWT token.
 * 3. System confirms the customer has an empty cart (no items to delete).
 * 4. Customer attempts to delete a non-existent cart item using a random UUID.
 * 5. API returns 404 Not Found error indicating the cart item was not found.
 *
 * This test validates the business rule that the system properly handles attempts to delete non-existent cart items, returning appropriate 404 errors rather than silent failures or incorrect success responses.
 */
export async function test_api_cart_item_removal_not_found(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register and authenticate as a new customer
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "testPassword123!",
      name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  // 2. Attempt to delete a non-existent cart item (random UUID)
  // This should return 404 Not Found since the cart is empty
  const nonExistentCartItemId = typia.random<string & tags.Format<"uuid">>();
  // 3. Verify the API returns 404 Not Found
  await TestValidator.httpError(
    "delete non-existent cart item returns 404",
    404,
    async () =>
      await api.functional.ecommerceMall.customer.customers.me.cart.erase(
        customerConnection,
        {
          cartItemId: nonExistentCartItemId,
        },
      ),
  );
}
