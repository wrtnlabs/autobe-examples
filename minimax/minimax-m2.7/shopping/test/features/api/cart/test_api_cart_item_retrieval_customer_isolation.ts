export async function test_api_cart_item_retrieval_customer_isolation(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create seller and product with variant
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {});
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerConnection,
    {},
  );
  const variant =
    await generate_random_ecommerce_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
        body: { quantity: 100 },
      },
    );
  typia.assert(variant);
  // 2. Register Customer A and add product to cart
  const customerAConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerAConnection, {});
  const cartA =
    await generate_random_ecommerce_mall_customer_customers_cart_items_create(
      customerAConnection,
      {
        body: {
          productVariantId: variant.id,
          quantity: 1,
        },
      },
    );
  typia.assert(cartA);
  const customerAItemId = cartA.items[0].id;
  // 3. Register Customer B
  const customerBConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerBConnection, {});
  // 4. Customer B attempts to retrieve Customer A's cart item - should get 404
  await TestValidator.httpError(
    "Customer B cannot retrieve Customer A's cart item",
    404,
    async () =>
      await api.functional.ecommerceMall.customer.cart.items.at(
        customerBConnection,
        {
          itemId: customerAItemId,
        },
      ),
  );
  // 5. Customer B can retrieve their own cart (empty cart)
  const cartB =
    await generate_random_ecommerce_mall_customer_customers_cart_items_create(
      customerBConnection,
      {
        body: {
          productVariantId: variant.id,
          quantity: 1,
        },
      },
    );
  typia.assert(cartB);
  TestValidator.predicate(
    "Customer B's cart has items after adding",
    cartB.items.length > 0,
  );
}
