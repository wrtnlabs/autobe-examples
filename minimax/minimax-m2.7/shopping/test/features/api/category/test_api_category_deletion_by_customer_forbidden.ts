export async function test_api_category_deletion_by_customer_forbidden(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create and authenticate as a customer
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  // 2. Create and authenticate as an administrator, then create a category
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  const category =
    await generate_random_ecommerce_mall_admin_admin_categories_create(
      adminConnection,
      {},
    );
  // 3. Attempt to delete the category as a customer (should fail with 403 or 401)
  await TestValidator.error("customer cannot delete category", async () => {
    await api.functional.ecommerceMall.admin.categories.erase(
      customerConnection,
      {
        categoryId: category.id,
      },
    );
  });
}
