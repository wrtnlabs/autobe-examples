export async function test_api_category_update_forbidden_for_non_admin(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create admin connection and authenticate
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      actorType: "customer",
      requestedGrade: "admin",
      reason: "Admin request for testing category authorization",
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  // 2. Create a category as admin
  const category = await api.functional.ecommerceMall.admin.categories.create(
    adminConnection,
    {
      body: {
        name: RandomGenerator.paragraph({ sentences: 1 }),
        description: "Test category for authorization testing",
      },
    },
  );
  typia.assert(category);
  // 3. Create customer connection and authenticate
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  // 4. Customer attempts to update category - should be forbidden
  await TestValidator.error("customer cannot update category", async () => {
    await api.functional.ecommerceMall.admin.categories.update(
      customerConnection,
      {
        categoryId: category.id,
        body: {
          name: "Unauthorized Update Attempt",
        },
      },
    );
  });
}
