/**
 * Test retrieving the category tree focusing on terminal parent categories.
 *
 * Validates the category tree endpoint by ensuring that parent categories without
 * subcategories (terminal nodes) correctly return an empty children array. Each
 * category node is validated for proper structure including UUID-formatted id,
 * non-empty name, and properly typed description field.
 *
 * The test authenticates as a customer, retrieves the complete category tree,
 * and verifies the tree structure meets the expected format for terminal nodes.
 *
 * 1. Customer authentication via join endpoint.
 * 2. Category tree retrieval via GET /ecommerceMall/customer/categories/tree.
 * 3. Validation of required fields: id (UUID), name (non-empty string).
 * 4. Validation that terminal parent categories have empty children arrays.
 * 5. Validation of optional description field (null or string).
 */
export async function test_api_category_tree_terminal_parent_categories(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as customer
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  // 2. Get category tree
  const tree =
    await api.functional.ecommerceMall.customer.categories.tree(
      customerConnection,
    );
  typia.assert(tree);
  // 3. Validate each category node
  for (const category of tree.children) {
    // Validate required fields exist and have correct types
    TestValidator.predicate(
      "category id is UUID format",
      /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i.test(
        category.id,
      ),
    );
    TestValidator.predicate(
      "category name is non-empty string",
      category.name.length > 0,
    );
    TestValidator.equals(
      "category children is array",
      Array.isArray(category.children),
      true,
    );
    // Validate terminal parent categories have empty children array
    const isTerminalNode = category.children.length === 0;
    if (isTerminalNode) {
      TestValidator.equals(
        "terminal node has empty children array",
        category.children.length,
        0,
      );
    }
    // Validate description field type (can be null or string)
    TestValidator.predicate(
      "description is null or string",
      category.description === null || typeof category.description === "string",
    );
  }
}