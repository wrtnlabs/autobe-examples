/**
 * Test retrieving the category tree when no categories exist on the platform.
 *
 * Validates the category tree endpoint handles the empty state gracefully. When the platform has no categories created yet, the endpoint should return an empty array without errors. This ensures the API correctly handles edge cases where no data exists.
 *
 * The test flow:
 * 1. Authenticate as a customer to access the category tree endpoint
 * 2. Call the category tree endpoint
 * 3. Validate that the response returns an empty array when no categories exist
 */
export async function test_api_category_tree_empty_when_no_categories(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as a customer
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  // 2. Call the category tree endpoint
  const categoryTree =
    await api.functional.ecommerceMall.customer.categories.tree(
      customerConnection,
    );
  // 3. Validate the response
  typia.assert(categoryTree);
  // When no categories exist, the response should be an empty array
  // (represented as a tree node with empty children)
  TestValidator.equals(
    "category tree should have empty children when no categories exist",
    categoryTree.children,
    [],
  );
}
