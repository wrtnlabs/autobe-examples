export async function test_api_refund_request_creation_for_delivered_item(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin setup - Create admin connection and authenticate
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_login(adminConnection, {
    body: {
      email: "admin@test.com",
      password: "1234",
      href: "http://localhost:3000/admin",
      referrer: "http://localhost:3000",
    },
  });
  // 2. Create product category using generation function
  const category = await generate_random_ecommerce_mall_admin_categories_create(
    adminConnection,
    {},
  );
  typia.assert(category);
  // 3. Seller setup - Create seller connection and register
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "TestPassword123!",
      href: "http://localhost:3000/seller",
      referrer: "http://localhost:3000",
    },
  });
  // Login as seller
  const sellerLogin = await api.functional.ecommerceMall.auth.seller.login(
    sellerConnection,
    {
      body: {
        email: sellerAuth.email,
        password: "TestPassword123!",
      },
    },
  );
  typia.assert(sellerLogin);
  // 4. Create product with category using generation function
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        categoryId: category.id,
      },
    },
  );
  typia.assert(product);
  // 5. Customer setup - Create customer connection and register
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "TestPassword123!",
      href: "http://localhost:3000",
      referrer: "http://localhost:3000",
    },
  });
  // 6. Add shipping address using generation function
  const address =
    await generate_random_ecommerce_mall_customer_customers_addresses_create(
      customerConnection,
      {},
    );
  typia.assert(address);
  // 7. Add product to cart - get variant from product
  const variant = product.variants[0];
  typia.assert(variant);
  const cart =
    await api.functional.ecommerceMall.customer.customers.cart.items.create(
      customerConnection,
      {
        body: {
          productVariantId: variant.id,
          quantity: 1,
        },
      },
    );
  typia.assert(cart);
  // 8. Checkout to create order
  const order =
    await api.functional.ecommerceMall.customer.customers.checkout.create(
      customerConnection,
      {
        body: {
          shippingAddressId: address.id,
        },
      },
    );
  typia.assert(order);
  // 9. Get order item for refund request
  const orderItem = order.orderItems[0];
  typia.assert(orderItem);
  // 10. Test refund request creation for delivered item
  // Note: In a complete test environment, order item status would be 'delivered'
  // after seller creates shipment and customer confirms delivery
  const refundRequest =
    await api.functional.ecommerceMall.customer.refund_requests.create(
      customerConnection,
      {
        body: {
          orderItemId: orderItem.id,
          sellerId: sellerLogin.id,
          reason: "Product received was damaged and does not work as expected",
        },
      },
    );
  typia.assert(refundRequest);
  // Validate refund request response
  TestValidator.equals(
    "refund request status is pending",
    refundRequest.snapshotStatus,
    "pending",
  );
  TestValidator.equals(
    "refund request reason matches",
    refundRequest.snapshotReason,
    "Product received was damaged and does not work as expected",
  );
  TestValidator.predicate(
    "customer info exists",
    refundRequest.customer !== null && refundRequest.customer !== undefined,
  );
  TestValidator.predicate(
    "seller info exists",
    refundRequest.seller !== null && refundRequest.seller !== undefined,
  );
  TestValidator.predicate(
    "createdAt timestamp exists",
    refundRequest.createdAt !== null && refundRequest.createdAt !== undefined,
  );
  TestValidator.predicate(
    "updatedAt timestamp exists",
    refundRequest.updatedAt !== null && refundRequest.updatedAt !== undefined,
  );
}
