/**
 * Test retrieving a specific refund request snapshot by its unique identifier.
 *
 * This test validates the customer refund request snapshot retrieval endpoint
 * by:
 * 1. Authenticating as a customer using the authorize_customer_join utility
 * 2. Attempting to retrieve a refund request snapshot by UUID
 * 3. Validating the response structure includes all expected snapshot fields
 *
 * Note: The refund request snapshot must already exist in the system from a
 * previous refund request flow (customer requests refund -> seller responds).
 * This test validates the snapshot retrieval functionality for the authenticated
 * customer.
 */
export async function test_api_customer_refund_request_snapshot_retrieval(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as a customer using the utility function
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  // 2. Generate a valid UUID for the snapshot ID to retrieve
  const snapshotId = typia.random<string & tags.Format<"uuid">>();
  // 3. Retrieve the refund request snapshot by its unique identifier
  const snapshot =
    await api.functional.ecommerceMall.customer.refund_request_snapshots.at(
      customerConnection,
      {
        snapshotId: snapshotId,
      },
    );
  // 4. Validate the response with typia.assert for complete runtime type validation
  typia.assert(snapshot);
}
