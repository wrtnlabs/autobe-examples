export async function test_api_seller_product_rating_statistics_no_reviews(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as a seller
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {});
  // 2. Create a product
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerConnection,
    {},
  );
  typia.assert(product);
  // 3. Create a product variant
  const variant =
    await generate_random_ecommerce_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
      },
    );
  typia.assert(variant);
  // 4. Add inventory to the variant
  await generate_random_ecommerce_mall_seller_products_variants_inventory_create(
    sellerConnection,
    {
      params: { productId: product.id, variantId: variant.id },
    },
  );
  // 5. Get rating statistics (no reviews yet)
  const statistics =
    await api.functional.ecommerceMall.seller.products.rating_statistics.ratingStatistics(
      sellerConnection,
      {
        productId: product.id,
      },
    );
  typia.assert(statistics);
  // 6. Validate rating statistics for product with no reviews
  TestValidator.equals(
    "averageRating should be 0",
    statistics.averageRating,
    0,
  );
  TestValidator.equals("totalReviews should be 0", statistics.totalReviews, 0);
  TestValidator.equals(
    "distribution 1-star should be 0",
    statistics.distribution["1"],
    0,
  );
  TestValidator.equals(
    "distribution 2-star should be 0",
    statistics.distribution["2"],
    0,
  );
  TestValidator.equals(
    "distribution 3-star should be 0",
    statistics.distribution["3"],
    0,
  );
  TestValidator.equals(
    "distribution 4-star should be 0",
    statistics.distribution["4"],
    0,
  );
  TestValidator.equals(
    "distribution 5-star should be 0",
    statistics.distribution["5"],
    0,
  );
}
