export async function test_api_seller_product_retrieval_after_deletion(
  connection: api.IConnection,
): Promise<void> {
  // Create seller connection for authentication
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {});
  typia.assert(sellerAuth);
  // Create a product that will be deleted
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerConnection,
    {},
  );
  typia.assert(product);
  // Delete the product (soft delete sets deleted_at timestamp)
  await api.functional.ecommerceMall.seller.products.erase(sellerConnection, {
    productId: product.id,
  });
  // Attempt to retrieve the deleted product - should return 404
  await TestValidator.httpError(
    "deleted product should not be retrievable",
    404,
    async () =>
      await api.functional.ecommerceMall.seller.products.at(sellerConnection, {
        productId: product.id,
      }),
  );
}
