export async function test_api_admin_audit_log_unauthorized_access(
  connection: api.IConnection,
): Promise<void> {
  // 1. Setup: Create admin account and get a valid audit log ID
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  // Generate a valid UUID format for the audit log ID to test access denial
  const validAuditLogId = typia.random<string & tags.Format<"uuid">>();
  // 2. Test with customer authentication - should receive 403 Forbidden
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  await TestValidator.httpError(
    "customer should not access admin audit logs (403)",
    403,
    async () =>
      await api.functional.ecommerceMall.admin.admin.audit_logs.getByAuditlogid(
        customerConnection,
        { auditLogId: validAuditLogId },
      ),
  );
  // 3. Test with seller authentication - should receive 403 Forbidden
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {});
  await TestValidator.httpError(
    "seller should not access admin audit logs (403)",
    403,
    async () =>
      await api.functional.ecommerceMall.admin.admin.audit_logs.getByAuditlogid(
        sellerConnection,
        { auditLogId: validAuditLogId },
      ),
  );
  // 4. Test unauthenticated access - should receive 401 Unauthorized
  const unauthenticatedConnection: api.IConnection = { host: connection.host };
  await TestValidator.httpError(
    "unauthenticated request should not access admin audit logs (401)",
    401,
    async () =>
      await api.functional.ecommerceMall.admin.admin.audit_logs.getByAuditlogid(
        unauthenticatedConnection,
        { auditLogId: validAuditLogId },
      ),
  );
}
