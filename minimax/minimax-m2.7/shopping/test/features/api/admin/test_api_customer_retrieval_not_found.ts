export async function test_api_customer_retrieval_not_found(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as administrator
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  // 2. Generate a valid UUID format that does not correspond to any existing customer
  const nonExistentCustomerId = typia.random<string & tags.Format<"uuid">>();
  // 3. Attempt to retrieve non-existent customer and validate 404 error
  await TestValidator.httpError("customer not found returns 404", 404, () =>
    api.functional.ecommerceMall.admin.customers.at(adminConnection, {
      customerId: nonExistentCustomerId,
    }),
  );
}
