/**
 * Test that banning an already banned customer returns a 400 error.
 *
 * Validates the administrative ban operation by first banning a customer account and then attempting to ban the same customer again. The system should reject duplicate ban attempts by returning a 400 Bad Request error, preventing administrators from re-banning customers who are already banned.
 *
 * This test ensures idempotency in the ban operation at the API level. While the first ban successfully soft-deletes the customer account, subsequent attempts to ban the same customer should be rejected with clear error messaging.
 *
 * 1. Administrator registers and authenticates to perform ban operations.
 * 2. Customer registers as the target account to be banned.
 * 3. Administrator bans the customer (first attempt) - expects success.
 * 4. Administrator attempts to ban the same customer again - expects 400 error.
 * 5. Validates that the error indicates the customer is already banned.
 */
export async function test_api_customer_ban_already_banned(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register administrator
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  // 2. Register customer
  const customerConnection: api.IConnection = { host: connection.host };
  const customer = await authorize_customer_join(customerConnection, {});
  typia.assert(customer);
  // 3. First ban attempt - should succeed
  const firstBan = await api.functional.ecommerceMall.admin.admin.customers.ban(
    adminConnection,
    { customerId: customer.id },
  );
  typia.assert(firstBan);
  // Verify customer is banned (deletedAt is not null)
  TestValidator.equals("customer is banned", firstBan.deletedAt !== null, true);
  // 4. Second ban attempt - should fail with 400 error
  await TestValidator.error("cannot ban already banned customer", async () => {
    await api.functional.ecommerceMall.admin.admin.customers.ban(
      adminConnection,
      {
        customerId: customer.id,
      },
    );
  });
}
