/**
 * Test admin force-cancel on a non-existent order.
 *
 * Validates that attempting to force-cancel an order with a non-existent order ID
 * properly returns an HTTP 404 error. This test verifies:
 *
 * 1. Authentication works correctly for admin endpoints
 * 2. The force-cancel endpoint correctly validates order existence
 * 3. Appropriate 404 error is returned when order does not exist
 * 4. No side effects occur (inventory, refunds) when operation fails
 *
 * The test uses a clearly invalid order ID format to ensure the error handling
 * correctly identifies non-existent orders vs other types of errors.
 */
export async function test_api_admin_force_cancel_nonexistent_order(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as administrator
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  // 2. Attempt to force-cancel a non-existent order
  const nonexistentOrderId = "ORD-NONEXISTENT-12345";
  // 3. Validate 404 error is returned
  await TestValidator.httpError(
    "force-cancel non-existent order returns 404",
    404,
    async () =>
      await api.functional.ecommerceMall.admin.admin.orders.force_cancel.forceCancel(
        adminConnection,
        { orderId: nonexistentOrderId },
      ),
  );
}
