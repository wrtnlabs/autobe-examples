/**
 * Test that customer cannot access admin-only fulfillment metrics endpoint.
 *
 * Validates the authorization boundary between customer and admin roles by ensuring
 * that non-admin users receive 403 Forbidden when attempting to access admin-only
 * endpoints. The fulfillment metrics endpoint contains sensitive platform-wide statistics
 * that should only be accessible to administrators.
 *
 * This test creates a customer account, authenticates as that customer, and attempts
 * to access the admin fulfillment metrics endpoint. The expected behavior is that
 * the server rejects the request with 403 Forbidden status, confirming that the
 * endpoint is properly protected against unauthorized access.
 *
 * 1. Register and authenticate as a customer with valid credentials.
 * 2. Call GET /ecommerceMall/admin/admin/fulfillment/metrics with customer authorization.
 * 3. Validate response returns 403 Forbidden status code.
 */
export async function test_api_fulfillment_metrics_customer_access_forbidden(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register and authenticate as a customer
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  // 2. Attempt to access admin-only fulfillment metrics endpoint
  // 3. Validate 403 Forbidden response
  await TestValidator.httpError(
    "customer cannot access admin fulfillment metrics",
    403,
    async () =>
      await api.functional.ecommerceMall.admin.admin.fulfillment.metrics(
        customerConnection,
      ),
  );
}
