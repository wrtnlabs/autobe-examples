/**
 * Test that a customer cannot access another customer's order details.
 *
 * Validates the privacy boundary that customers can only view their own order history. This test ensures that when customer B attempts to access an order that belongs to customer A, the system correctly denies access with HTTP 403 Forbidden.
 *
 * Prerequisites setup involves creating two separate customers: customer A who owns an order, and customer B who will attempt unauthorized access. The test verifies that the authorization layer properly enforces ownership constraints.
 *
 * 1. Register and authenticate as seller to create a product.
 * 2. Create product with inventory.
 * 3. Register and authenticate as customer A.
 * 4. Add shipping address for customer A.
 * 5. Add product to customer A's cart.
 * 6. Create order for customer A and capture order ID.
 * 7. Register and authenticate as customer B.
 * 8. Attempt to access customer A's order using customer B's session.
 * 9. Validate HTTP 403 Forbidden response.
 */
export async function test_api_order_detail_access_denied_for_other_customer(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register seller for product setup
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {});
  // 2. Create product for order
  const product =
    await api.functional.ecommerceMall.seller.sellers.me.products.create(
      sellerConnection,
      {
        body: {
          name: RandomGenerator.paragraph({ sentences: 2 }),
          description: RandomGenerator.paragraph({ sentences: 5 }),
          basePrice: typia.random<
            number & tags.Type<"uint32"> & tags.Minimum<1000>
          >(),
          categoryId: typia.random<string & tags.Format<"uuid">>(),
        } satisfies IEcommerceMallProduct.ICreate,
      },
    );
  typia.assert(product);
  // Get the product's first variant ID for cart creation
  const variantId = product.variants[0]?.id;
  if (!variantId) {
    throw new Error("Product has no variants");
  }
  // 3. Register and authenticate as customer A
  const customerAConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerAConnection, {});
  // 4. Create shipping address for customer A
  const address =
    await api.functional.ecommerceMall.customer.customers.me.addresses.create(
      customerAConnection,
      {
        body: {
          recipient_name: RandomGenerator.name(),
          phone: RandomGenerator.mobile(),
          street_address: "123 Test Street",
          city: "Test City",
          state: "Test State",
          postal_code: "12345",
          country: "Test Country",
          is_default: true,
        } satisfies IEcommerceMallShippingAddress.ICreate,
      },
    );
  typia.assert(address);
  // 5. Add product to customer A's cart
  const cartItem =
    await api.functional.ecommerceMall.customer.customers.me.cart.create(
      customerAConnection,
      {
        body: {
          variantId: variantId,
          quantity: typia.random<
            number & tags.Type<"int32"> & tags.Minimum<1>
          >(),
        } satisfies IEcommerceMallCart.ICreate,
      },
    );
  typia.assert(cartItem);
  // 6. Create order for customer A and capture order ID
  const order =
    await api.functional.ecommerceMall.customer.customers.me.orders.create(
      customerAConnection,
      {
        body: {
          shippingAddressId: address.id,
        } satisfies IEcommerceMallOrder.ICreate,
      },
    );
  typia.assert(order);
  const customerAOrderId = order.id;
  // 7. Register and authenticate as customer B
  const customerBConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerBConnection, {});
  // 8. Attempt to access customer A's order using customer B's session
  // This should return HTTP 403 Forbidden
  await TestValidator.httpError(
    "access denied for other customer's order",
    403,
    async () => {
      await api.functional.ecommerceMall.customer.customers.me.orders.at(
        customerBConnection,
        {
          orderId: customerAOrderId,
        },
      );
    },
  );
}
