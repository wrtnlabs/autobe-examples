export async function test_api_order_shipment_listing_empty(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create and authenticate customer
  const customerConnection: api.IConnection = { host: connection.host };
  const customerAuth = await authorize_customer_join(customerConnection, {});
  // 2. Create and authenticate seller (auto-approved)
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {});
  // 3. Seller creates product
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerConnection,
    {},
  );
  typia.assert(product);
  // Get variant ID from the created product
  const variantId = product.variants[0]!.id;
  // 4. Customer adds item to cart
  await generate_random_ecommerce_mall_customer_customers_cart_items_create(
    customerConnection,
    {
      body: {
        productVariantId: variantId,
        quantity: typia.random<number & tags.Type<"int32"> & tags.Minimum<1>>(),
      },
    },
  );
  // 5. Customer checks out to create order (without shipments)
  const order =
    await generate_random_ecommerce_mall_customer_customers_checkout_create(
      customerConnection,
      {},
    );
  typia.assert(order);
  // 6. List shipments for the order (should be empty)
  const shipmentsResponse =
    await api.functional.ecommerceMall.orders.shipments.index(
      customerConnection,
      {
        orderId: order.id,
        body: {
          page: 1,
          limit: 10,
        },
      },
    );
  typia.assert(shipmentsResponse);
  // 7. Validate empty shipments response
  TestValidator.equals(
    "data array should be empty",
    shipmentsResponse.data,
    [],
  );
}
