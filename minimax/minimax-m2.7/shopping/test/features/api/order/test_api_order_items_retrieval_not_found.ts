/**
 * Test retrieving order items for a non-existent order.
 *
 * Validates that attempting to retrieve order items for an order that does not exist returns a proper 404 error response. This test verifies the API's order ownership validation and ensures no sensitive data is exposed for non-existent orders.
 *
 * **Test Flow**:
 * 1. Register and authenticate as a new customer via POST /ecommerceMall/auth/customer/join
 * 2. Generate a random UUID that does not correspond to any existing order
 * 3. Attempt to retrieve order items via GET /ecommerceMall/customer/orders/{nonExistentOrderId}/items
 * 4. Validate that the API returns 404 Not Found
 * 5. Verify proper error handling without data exposure
 *
 * **Business Rules Verified**:
 * - Order existence validation: API must verify the order exists before returning items
 * - Ownership validation: API must ensure the order belongs to the authenticated customer
 * - Security: Non-existent or unauthorized orders must return 404, not 403 (to avoid information disclosure)
 * - Error handling: Proper error response format without exposing internal details
 */
export async function test_api_order_items_retrieval_not_found(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register and authenticate as a new customer
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  // 2. Generate a random UUID that does not correspond to any existing order
  const nonExistentOrderId = typia.random<string & tags.Format<"uuid">>();
  // 3. Attempt to retrieve order items for non-existent order
  // 4. Validate that the API returns 404 Not Found
  await TestValidator.httpError(
    "should return 404 for non-existent order",
    404,
    async () =>
      await api.functional.ecommerceMall.customer.orders.items.getByOrderid(
        customerConnection,
        { orderId: nonExistentOrderId },
      ),
  );
}
