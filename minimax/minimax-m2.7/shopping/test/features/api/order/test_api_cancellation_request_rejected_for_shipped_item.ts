export async function test_api_cancellation_request_rejected_for_shipped_item(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin creates a product category
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  const category =
    await generate_random_ecommerce_mall_admin_admin_categories_create(
      adminConnection,
      {},
    );
  typia.assert(category);
  // 2. Seller registers and creates a product with a variant
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerEmail = typia.random<string & tags.Format<"email">>();
  await authorize_seller_join(sellerConnection, {
    body: {
      email: sellerEmail,
      password: "password123",
    },
  });
  const product =
    await generate_random_ecommerce_mall_seller_sellers_me_products_create(
      sellerConnection,
      {
        body: {
          name: RandomGenerator.paragraph({ sentences: 2 }),
          description: RandomGenerator.content({ paragraphs: 2 }),
          basePrice: typia.random<
            number & tags.Type<"uint32"> & tags.Minimum<1000>
          >(),
          categoryId: category.id,
        },
      },
    );
  typia.assert(product);
  // Verify product has at least one variant
  const variantId = product.variants[0]?.id;
  if (!variantId) {
    throw new Error("Product has no variants");
  }
  // 3. Customer registers
  const customerConnection: api.IConnection = { host: connection.host };
  const customerEmail = typia.random<string & tags.Format<"email">>();
  await authorize_customer_join(customerConnection, {
    body: {
      email: customerEmail,
      password: "password123",
      name: RandomGenerator.name(),
      href: "http://localhost:3000",
      referrer: "http://localhost:3000",
    },
  });
  // Create shipping address
  const address =
    await generate_random_ecommerce_mall_customer_customers_me_addresses_create(
      customerConnection,
      {},
    );
  typia.assert(address);
  // 4. Customer places order
  const order =
    await generate_random_ecommerce_mall_customer_customers_me_orders_create(
      customerConnection,
      {
        body: {
          shippingAddressId: address.id,
        },
      },
    );
  typia.assert(order);
  const orderItem = order.orderItems[0];
  if (!orderItem) {
    throw new Error("Order has no items");
  }
  // 5. Seller ships the order item
  await generate_random_ecommerce_mall_seller_sellers_me_orders_items_ship_create(
    sellerConnection,
    {
      params: {
        itemId: orderItem.id,
      },
      body: {
        carrier: "FastShip",
        trackingNumber: "TRACK123456789",
        itemIds: [orderItem.id],
      },
    },
  );
  // 6. Customer attempts to cancel shipped item - should be rejected with error
  await TestValidator.error(
    "cancellation rejected for shipped item",
    async () => {
      await api.functional.ecommerceMall.customer.customers.me.orders.items.cancel.create(
        customerConnection,
        {
          itemId: orderItem.id,
          body: {
            reason: "Changed my mind",
          },
        },
      );
    },
  );
}
