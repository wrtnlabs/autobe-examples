/**
 * Test that a customer receives 404 when accessing a non-existent order.
 *
 * Validates the system's handling of requests for non-existent order resources. When a customer attempts to retrieve an order using an order ID that does not exist in the system, the API should return HTTP 404 Not Found status code. This test ensures proper resource access control and error handling for the order detail endpoint.
 *
 * **Test Flow:**
 * 1. Register and authenticate a new customer
 * 2. Generate a random UUID that does not exist in the system
 * 3. Attempt to retrieve the non-existent order using the customer's authenticated session
 * 4. Assert that the server responds with HTTP 404 status
 *
 * **Business Rules Validated:**
 * - Customers cannot access orders that don't exist
 * - Soft-deleted orders also return 404 (not accessible)
 * - The system properly distinguishes between "not found" and other error conditions
 */
export async function test_api_order_detail_not_found_for_nonexistent_order(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register and authenticate a customer
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  // 2. Generate a random UUID that does not exist in the system
  const nonExistentOrderId = typia.random<string & tags.Format<"uuid">>();
  // 3. Attempt to retrieve the non-existent order
  // 4. Validate HTTP 404 response
  await TestValidator.httpError(
    "should return 404 for non-existent order",
    404,
    async () =>
      await api.functional.ecommerceMall.customer.customers.me.orders.at(
        customerConnection,
        { orderId: nonExistentOrderId },
      ),
  );
}
