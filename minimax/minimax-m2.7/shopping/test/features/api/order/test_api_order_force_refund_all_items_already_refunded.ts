export async function test_api_order_force_refund_all_items_already_refunded(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin authentication
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  // 2. Attempt force-refund on a non-existent order (returns 404)
  const nonExistentOrderId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.httpError(
    "force-refund non-existent order returns 404",
    404,
    async () => {
      await api.functional.ecommerceMall.admin.admin.orders.force_refund.forceRefund(
        adminConnection,
        {
          orderId: nonExistentOrderId,
          body: {
            reason: "Test force refund",
          } satisfies IEcommerceMallOrder.IForceRefund,
        },
      );
    },
  );
}