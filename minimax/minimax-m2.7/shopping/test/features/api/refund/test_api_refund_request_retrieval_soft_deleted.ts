export async function test_api_refund_request_retrieval_soft_deleted(
  connection: api.IConnection,
): Promise<void> {
  // Create admin connection for authentication
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "Admin1234!" as string & tags.Format<"password">,
      name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  // Test retrieving a soft-deleted refund request
  // Soft-deleted records (with deleted_at timestamp set) should return 404 Not Found
  // This validates that soft-deleted refund request records are not accessible through the API
  const softDeletedRequestId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.httpError(
    "soft-deleted refund request returns 404",
    404,
    async () =>
      await api.functional.ecommerceMall.admin.refund_requests.at(
        adminConnection,
        {
          requestId: softDeletedRequestId,
        },
      ),
  );
}
