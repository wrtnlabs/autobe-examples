export async function test_api_refund_snapshot_empty_before_seller_response(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin creates category
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      actorType: "customer",
      requestedGrade: "admin",
      reason: "Need admin access for testing purposes",
      href: "https://test.example.com",
      referrer: "https://test.example.com",
    },
  });
  const category = await generate_random_ecommerce_mall_admin_categories_create(
    adminConnection,
    {},
  );
  typia.assert(category);
  // 2. Seller joins (automatically handles authentication)
  const sellerConnection: api.IConnection = { host: connection.host };
  const seller = await authorize_seller_join(sellerConnection, {});
  typia.assert(seller);
  // 3. Customer joins (automatically handles authentication)
  const customerConnection: api.IConnection = { host: connection.host };
  const customer = await authorize_customer_join(customerConnection, {});
  typia.assert(customer);
  // 4. Seller creates product
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        categoryId: category.id,
        name: "Test Product for Refund",
        description: "Product to test refund snapshot behavior",
        basePrice: 10000,
      },
    },
  );
  typia.assert(product);
  // Get variant from product
  const variant = product.variants[0];
  if (!variant) {
    throw new Error("Product has no variants");
  }
  // 5. Customer adds shipping address
  const address =
    await generate_random_ecommerce_mall_customer_customers_addresses_create(
      customerConnection,
      {
        body: {
          recipientName: "Test Customer",
          phone: "010-1234-5678",
          streetAddress: "123 Test Street",
          city: "Test City",
          state: "Test State",
          postalCode: "12345",
          country: "Test Country",
          isDefault: true,
        },
      },
    );
  typia.assert(address);
  // 6. Customer adds to cart
  const cart =
    await generate_random_ecommerce_mall_customer_customers_cart_items_create(
      customerConnection,
      {
        body: {
          productVariantId: variant.id,
          quantity: 1,
        },
      },
    );
  typia.assert(cart);
  // 7. Customer checks out
  const order =
    await generate_random_ecommerce_mall_customer_customers_checkout_create(
      customerConnection,
      {
        body: {
          shippingAddressId: address.id,
        },
      },
    );
  typia.assert(order);
  // Get the order item
  const orderItem = order.orderItems[0];
  if (!orderItem) {
    throw new Error("Order has no items");
  }
  // 8. Seller ships the order (marking as shipped)
  const shipment =
    await generate_random_ecommerce_mall_seller_orders_shipments_create(
      sellerConnection,
      {
        params: {
          orderId: order.id,
        },
        body: {
          orderItemIds: [orderItem.id],
          carrier: "Test Courier",
          trackingNumber: "TRACK123456",
        },
      },
    );
  typia.assert(shipment);
  // Note: In real scenario, customer would confirm delivery or auto-delivery occurs after 14 days
  // For this test, we proceed assuming delivery is confirmed
  // 9. Customer creates refund request
  const refundRequest =
    await generate_random_ecommerce_mall_customer_refund_requests_create(
      customerConnection,
      {
        body: {
          orderItemId: orderItem.id,
          sellerId: seller.id,
          reason: "Item not as described",
        },
      },
    );
  typia.assert(refundRequest);
  // Test: Get refund request snapshots BEFORE seller responds
  const snapshots =
    await api.functional.ecommerceMall.customer.refund_requests.snapshots.list(
      customerConnection,
      {
        requestId: refundRequest.id,
      },
    );
  typia.assert(snapshots);
  // Validate: snapshots should be empty before seller response
  TestValidator.equals("data array should be empty", snapshots.data.length, 0);
  TestValidator.predicate(
    "pagination should be returned",
    snapshots.pagination !== undefined,
  );
  TestValidator.equals(
    "pagination records should be 0",
    snapshots.pagination.records,
    0,
  );
  TestValidator.equals(
    "pagination pages should be 0",
    snapshots.pagination.pages,
    0,
  );
}
