/**
 * Test validation error when confirming delivery for a shipment whose items are not in 'shipped' status.
 *
 * Validates that customers cannot confirm delivery for order items that have not yet been shipped.
 * The test verifies the system correctly rejects delivery confirmation attempts when:
 * - The shipment does not exist (no shipment was created after order payment)
 * - Order items remain in 'paid' status awaiting seller shipment creation
 *
 * This test ensures the business rule that delivery can only be confirmed for items
 * that have been shipped by the seller. Items in 'paid' status must go through
 * the shipment creation flow before delivery can be confirmed.
 *
 * **Setup Flow:**
 * 1. Register and approve a seller account
 * 2. Register a customer account
 * 3. Seller creates product with inventory
 * 4. Customer creates order (items in 'paid' status, no shipment created)
 *
 * **Test Execution:**
 * 5. Customer attempts to confirm delivery on non-existent shipment
 *
 * **Expected Behavior:**
 * - Returns 400 or 404 error
 * - Items remain in 'paid' status
 */
export async function test_api_shipment_delivery_confirmation_invalid_status(
  connection: api.IConnection,
): Promise<void> {
  // 1. Setup: Register and approve seller
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {});
  typia.assert(sellerAuth);
  // 2. Register customer
  const customerConnection: api.IConnection = { host: connection.host };
  const customerAuth = await authorize_customer_join(customerConnection, {});
  typia.assert(customerAuth);
  // 3. Seller creates product with inventory
  const product =
    await generate_random_ecommerce_mall_seller_sellers_me_products_create(
      sellerConnection,
      {},
    );
  typia.assert(product);
  // Get variant from the created product
  const variant = product.variants[0];
  TestValidator.equals("variant exists", variant !== undefined, true);
  // 4. Add inventory to the variant
  await generate_random_ecommerce_mall_seller_variants_inventory_create(
    sellerConnection,
    {
      params: { variantId: variant.id },
    },
  );
  // 5. Customer adds product to cart and creates order
  await generate_random_ecommerce_mall_customer_customers_me_cart_create(
    customerConnection,
    {
      body: { variantId: variant.id, quantity: 1 },
    },
  );
  const order =
    await generate_random_ecommerce_mall_customer_customers_me_orders_create(
      customerConnection,
      {},
    );
  typia.assert(order);
  // 6. Test: Attempt to confirm delivery on non-existent shipment
  // Items are in 'paid' status but no shipment exists
  await TestValidator.error(
    "confirm delivery fails when shipment does not exist (items not shipped)",
    async () => {
      await api.functional.ecommerceMall.customer.orders.shipments.confirm_delivery.create(
        customerConnection,
        {
          orderId: order.id,
          shipmentId: typia.random<string & tags.Format<"uuid">>(),
        },
      );
    },
  );
}
