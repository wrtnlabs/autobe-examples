/**
 * Test that a seller cannot update tracking information for another seller's shipment.
 *
 * Validates the authorization rule that sellers can only update their own shipments.
 * When Seller B attempts to update a shipment created by Seller A, the system returns
 * a 403 Forbidden error. This ensures proper isolation of seller data and prevents
 * unauthorized access to other sellers' shipment information.
 *
 * The test flow:
 * 1. Customer registers and authenticates
 * 2. Customer creates a shipping address for order delivery
 * 3. Seller A registers and authenticates
 * 4. Seller B registers and authenticates (different seller account)
 * 5. Seller B attempts to update a shipment that belongs to Seller A
 * 6. System returns 403 Forbidden error
 *
 * This test ensures that the shipment ownership validation works correctly and prevents
 * cross-seller unauthorized modifications to shipment tracking information.
 */
export async function test_api_shipment_tracking_update_forbidden_for_non_owner(
  connection: api.IConnection,
): Promise<void> {
  // 1. Customer registration and authentication
  const customerConnection: api.IConnection = { host: connection.host };
  const customer = await authorize_customer_join(customerConnection, {});
  typia.assert(customer);
  // 2. Customer creates shipping address
  const shippingAddress =
    await api.functional.ecommerceMall.customer.customers.me.addresses.create(
      customerConnection,
      {
        body: {
          recipient_name: RandomGenerator.name(),
          phone: RandomGenerator.mobile(),
          street_address: "123 Test Street",
          city: "Test City",
          state: "Test State",
          postal_code: "12345",
          country: "Test Country",
          is_default: true,
        } satisfies IEcommerceMallShippingAddress.ICreate,
      },
    );
  typia.assert(shippingAddress);
  // 3. Seller A registration and authentication
  const sellerAConnection: api.IConnection = { host: connection.host };
  const sellerA = await authorize_seller_join(sellerAConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "TestPassword123!",
    },
  });
  typia.assert(sellerA);
  // 4. Seller B registration and authentication (different seller)
  const sellerBConnection: api.IConnection = { host: connection.host };
  const sellerB = await authorize_seller_join(sellerBConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "TestPassword123!",
    },
  });
  typia.assert(sellerB);
  // 5. Seller B attempts to update a shipment that doesn't belong to them
  // We use a random UUID to represent Seller A's shipment
  const unauthorizedShipmentId = typia.random<string & tags.Format<"uuid">>();
  // Seller B tries to update the shipment (should fail with 403 Forbidden)
  await TestValidator.httpError(
    "Seller B cannot update Seller A's shipment - unauthorized access",
    403,
    async () =>
      await api.functional.ecommerceMall.seller.sellers.me.shipments.update(
        sellerBConnection,
        {
          shipmentId: unauthorizedShipmentId,
          body: {
            carrier: "DHL Express",
            trackingNumber: "1234567890",
          } satisfies IEcommerceMallShipment.IUpdate,
        },
      ),
  );
}
