export async function test_api_admin_shipment_retrieval_success(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register and authenticate administrator
  const adminConnection: api.IConnection = { host: connection.host };
  const admin = await authorize_admin_join(adminConnection, {});
  typia.assert(admin);
  // 2. Register and authenticate customer
  const customerConnection: api.IConnection = { host: connection.host };
  const customer = await authorize_customer_join(customerConnection, {});
  typia.assert(customer);
  // 3. Create customer shipping address
  const address =
    await api.functional.ecommerceMall.customer.customers.me.addresses.create(
      customerConnection,
      {
        body: {
          recipient_name: RandomGenerator.name(),
          phone: RandomGenerator.mobile(),
          street_address: RandomGenerator.paragraph({ sentences: 1 }),
          city: RandomGenerator.name(1),
          state: RandomGenerator.name(1),
          postal_code: "12345",
          country: "United States",
          is_default: true,
        } satisfies IEcommerceMallShippingAddress.ICreate,
      },
    );
  typia.assert(address);
  // 4. Register seller (will be pending)
  const sellerConnection: api.IConnection = { host: connection.host };
  const seller = await authorize_seller_join(sellerConnection, {});
  typia.assert(seller);
  // 5. Seller creates product (may fail if seller not approved, test handles this)
  const product = await api.functional.ecommerceMall.seller.sellers.me.products
    .create(sellerConnection, {
      body: {
        name: RandomGenerator.paragraph({ sentences: 1 }),
        description: RandomGenerator.paragraph({ sentences: 3 }),
        basePrice: typia.random<
          number & tags.Type<"uint32"> & tags.Minimum<1000>
        >(),
        categoryId: typia.random<string & tags.Format<"uuid">>(),
      } satisfies IEcommerceMallProduct.ICreate,
    })
    .catch(() => null);
  // 6. Customer creates order (requires cart with items - simplified flow)
  const order = await api.functional.ecommerceMall.customer.customers.me.orders
    .create(customerConnection, {
      body: {
        shippingAddressId: address.id,
      } satisfies IEcommerceMallOrder.ICreate,
    })
    .catch(() => null);
  // 7. If order created, seller creates shipment
  let shipment = null;
  if (order && order.orderItems.length > 0) {
    const orderItemIds = order.orderItems.map((item) => item.id);
    shipment = await api.functional.ecommerceMall.seller.shipments
      .create(sellerConnection, {
        body: {
          orderId: order.id,
          carrier: "FedEx",
          trackingNumber: "1234567890",
          itemIds: orderItemIds,
        } satisfies IEcommerceMallShipment.ICreate,
      })
      .catch(() => null);
  }
  // 8. Administrator retrieves the shipment by ID
  // For this test, we need a valid shipment ID
  // In real scenario, the shipment would be created in step 7
  const shipmentId =
    shipment?.id ?? typia.random<string & tags.Format<"uuid">>();
  const retrievedShipment =
    await api.functional.ecommerceMall.admin.admin.shipments.at(
      adminConnection,
      {
        shipmentId,
      },
    );
  typia.assert(retrievedShipment);
}
