export async function test_api_customer_shipment_tracking_with_seller_shipments(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create customer connection
  const customerConnection: api.IConnection = { host: connection.host };
  const customerAuth = await authorize_customer_join(customerConnection, {});
  typia.assert(customerAuth);
  // 2. Create shipping address
  const address =
    await api.functional.ecommerceMall.customer.customers.me.addresses.create(
      customerConnection,
      {
        body: {
          recipient_name: RandomGenerator.name(),
          phone: RandomGenerator.mobile(),
          street_address: `${RandomGenerator.alphabets(5)} Street`,
          city: "Test City",
          state: "Test State",
          postal_code: "12345",
          country: "Test Country",
          is_default: true,
        } satisfies IEcommerceMallShippingAddress.ICreate,
      },
    );
  typia.assert(address);
  // 3. Create order with items that will have shipments
  const order =
    await api.functional.ecommerceMall.customer.customers.me.orders.create(
      customerConnection,
      {
        body: {
          shippingAddressId: address.id,
        } satisfies IEcommerceMallOrder.ICreate,
      },
    );
  typia.assert(order);
  // 4. Authenticate as seller
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {});
  typia.assert(sellerAuth);
  // 5. Create shipment for the order item
  const orderItem = order.orderItems[0];
  TestValidator.equals("has order items", order.orderItems.length > 0, true);
  const shipment =
    await api.functional.ecommerceMall.seller.sellers.me.orders.items.ship.create(
      sellerConnection,
      {
        itemId: orderItem.id,
        body: {
          carrier: "DHL",
          trackingNumber: "1234567890",
          itemIds: [orderItem.id],
        } satisfies IEcommerceMallShipment.ICreate,
      },
    );
  typia.assert(shipment);
  // 6. Get shipments for the order via customer endpoint
  const shipmentInvert =
    await api.functional.ecommerceMall.customer.customers.me.orders.shipments.getByOrderid(
      customerConnection,
      {
        orderId: order.id,
      },
    );
  typia.assert(shipmentInvert);
  // Validations for single shipment response (IInvert)
  TestValidator.equals("has id", !!shipmentInvert.id, true);
  TestValidator.equals("has carrier", !!shipmentInvert.carrier, true);
  TestValidator.equals(
    "has tracking number",
    !!shipmentInvert.tracking_number,
    true,
  );
  TestValidator.equals("has created_at", !!shipmentInvert.created_at, true);
  TestValidator.equals(
    "has shipment items",
    shipmentInvert.shipmentItems.length > 0,
    true,
  );
  TestValidator.equals("has order info", !!shipmentInvert.order, true);
  TestValidator.equals("has seller info", !!shipmentInvert.seller, true);
  // Validate shipment item details
  const shipmentItem = shipmentInvert.shipmentItems[0];
  TestValidator.equals("shipment item has id", !!shipmentItem.id, true);
  TestValidator.equals(
    "shipment item has quantity",
    !!shipmentItem.quantity,
    true,
  );
  TestValidator.equals(
    "shipment item has unit price",
    !!shipmentItem.unitPrice,
    true,
  );
  TestValidator.equals("shipment item has status", !!shipmentItem.status, true);
  TestValidator.equals(
    "shipment item has product snapshot",
    !!shipmentItem.productSnapshot,
    true,
  );
}
