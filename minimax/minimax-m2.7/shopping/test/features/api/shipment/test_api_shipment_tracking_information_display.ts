/**
 * Test shipment tracking information retrieval and display.
 *
 * Validates that retrieving a shipment by ID returns accurate tracking information
 * for customer delivery monitoring. Ensures that carrier name, tracking number, and
 * shipment details are correctly returned when a seller fetches their shipment records.
 *
 * The test flow involves:
 * 1. Creating and authenticating a seller account
 * 2. Creating and authenticating a customer account
 * 3. Creating a shipping address for the customer
 * 4. Creating an order with paid items (via generation utility)
 * 5. Creating a shipment with specific carrier and tracking number
 * 6. Retrieving the shipment by ID and validating tracking information
 *
 * This test verifies the shipment endpoint returns complete tracking details including
 * carrier name, tracking number, timestamps, and bundled order items for delivery monitoring.
 */
export async function test_api_shipment_tracking_information_display(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create and authenticate seller
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {});
  typia.assert(sellerAuth);
  // 2. Create and authenticate customer
  const customerConnection: api.IConnection = { host: connection.host };
  const customerAuth = await authorize_customer_join(customerConnection, {});
  typia.assert(customerAuth);
  // 3. Create shipping address for customer
  const address =
    await generate_random_ecommerce_mall_customer_customers_me_addresses_create(
      customerConnection,
      {},
    );
  typia.assert(address);
  // 4. Create order with paid items
  const order =
    await generate_random_ecommerce_mall_customer_customers_me_orders_create(
      customerConnection,
      {
        body: {
          shippingAddressId: address.id,
        } satisfies IEcommerceMallOrder.ICreate,
      },
    );
  typia.assert(order);
  // 5. Get order item IDs for shipment creation
  const orderItemIds = order.orderItems.map((item) => item.id);
  // 6. Create shipment with specific carrier and tracking number
  const carrierName = "FedEx";
  const trackingNumber = "1234567890";
  const shipment = await generate_random_ecommerce_mall_seller_shipments_create(
    sellerConnection,
    {
      body: {
        orderId: order.id,
        carrier: carrierName,
        trackingNumber: trackingNumber,
        itemIds: orderItemIds,
      } satisfies IEcommerceMallShipment.ICreate,
    },
  );
  typia.assert(shipment);
  // 7. Retrieve shipment by ID using the SDK function
  const retrievedShipment =
    await api.functional.ecommerceMall.seller.shipments.at(sellerConnection, {
      shipmentId: shipment.id,
    });
  typia.assert(retrievedShipment);
  // 8. Validate tracking information
  TestValidator.equals(
    "carrier matches",
    retrievedShipment.carrier,
    carrierName,
  );
  TestValidator.equals(
    "tracking number matches",
    retrievedShipment.trackingNumber,
    trackingNumber,
  );
  TestValidator.predicate(
    "has createdAt timestamp",
    retrievedShipment.createdAt !== undefined &&
      retrievedShipment.createdAt.length > 0,
  );
  TestValidator.predicate(
    "has updatedAt timestamp",
    retrievedShipment.updatedAt !== undefined &&
      retrievedShipment.updatedAt.length > 0,
  );
  TestValidator.equals(
    "item count matches order items",
    retrievedShipment.shipmentItems.length,
    orderItemIds.length,
  );
}
