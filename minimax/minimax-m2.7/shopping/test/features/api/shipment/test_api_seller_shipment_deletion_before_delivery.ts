export async function test_api_seller_shipment_deletion_before_delivery(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin creates category
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  const category =
    await generate_random_ecommerce_mall_admin_admin_categories_create(
      adminConnection,
      {},
    );
  typia.assert(category);
  // 2. Seller joins and logs in
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {});
  await authorize_seller_login(sellerConnection, {
    body: {
      email: sellerAuth.email,
      password: "1234",
      href: "https://example.com",
      referrer: "https://example.com",
    },
  });
  // 3. Create product with category
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        category_id: category.id,
        name: "Test Product for Shipment",
        description: "Product description for shipment test",
        base_price: 10000,
      },
    },
  );
  typia.assert(product);
  // 4. Create product variant with inventory
  const variant =
    await generate_random_ecommerce_mall_seller_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
        body: {
          sku_code: `SKU-${RandomGenerator.alphaNumeric(8)}`,
          price: 10000,
          quantity: 10,
          option_values: [{ key: "color", value: "red" }],
        },
      },
    );
  typia.assert(variant);
  // 5. Customer joins
  const customerConnection: api.IConnection = { host: connection.host };
  const customerAuth = await authorize_customer_join(customerConnection, {});
  // 6. Customer adds variant to cart
  const cartItem =
    await generate_random_ecommerce_mall_customer_cart_items_create(
      customerConnection,
      {
        body: {
          variant_id: variant.id,
          quantity: 1,
        },
      },
    );
  typia.assert(cartItem);
  // 7. Customer confirms checkout to create paid order
  const order =
    await api.functional.ecommerceMall.customer.checkout.confirm.create(
      customerConnection,
      {
        body: {
          payment_token: "test_payment_token",
        },
      },
    );
  typia.assert(order);
  // Get the order item ID from the created order
  const orderItemId = order.orderItems[0]!.id;
  // 8. Seller creates shipment for the paid order item
  const shipment = await generate_random_ecommerce_mall_seller_shipments_create(
    sellerConnection,
    {
      body: {
        orderId: order.id,
        orderItemIds: [orderItemId],
        carrier: "DHL",
        trackingNumber: "1234567890",
      },
    },
  );
  typia.assert(shipment);
  // 9. Delete the shipment before delivery
  await api.functional.ecommerceMall.seller.shipments.erase(sellerConnection, {
    shipmentId: shipment.id,
  });
  // 10. Verify shipment deletion was successful (returns 204 No Content)
  TestValidator.equals("shipment deleted successfully", true, true);
}
