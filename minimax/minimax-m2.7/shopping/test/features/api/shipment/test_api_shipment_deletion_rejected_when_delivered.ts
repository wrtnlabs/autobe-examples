export async function test_api_shipment_deletion_rejected_when_delivered(
  connection: api.IConnection,
): Promise<void> {
  // 1. Customer registration and authentication
  const customerConnection: api.IConnection = { host: connection.host };
  const customerAuth = await authorize_customer_join(customerConnection, {});
  typia.assert(customerAuth);
  // Create shipping address for customer
  const address =
    await api.functional.ecommerceMall.customer.customers.me.addresses.create(
      customerConnection,
      {
        body: {
          recipient_name: RandomGenerator.name(),
          phone: RandomGenerator.mobile(),
          street_address: RandomGenerator.paragraph({ sentences: 1 }),
          city: "Test City",
          state: "Test State",
          postal_code: "12345",
          country: "Test Country",
          is_default: true,
        } satisfies IEcommerceMallShippingAddress.ICreate,
      },
    );
  typia.assert(address);
  // 2. Create order with paid items (using generation function handles cart + product setup)
  const order =
    await generate_random_ecommerce_mall_customer_customers_me_orders_create(
      customerConnection,
      {
        body: {
          shippingAddressId: address.id,
        },
      },
    );
  typia.assert(order);
  // Extract order item IDs from the order
  const orderItemIds = order.orderItems.map((item) => item.id);
  TestValidator.equals("order has items", orderItemIds.length > 0, true);
  // 3. Seller registration and authentication
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {});
  typia.assert(sellerAuth);
  // 4. Create shipment for order items
  const shipment = await api.functional.ecommerceMall.seller.shipments.create(
    sellerConnection,
    {
      body: {
        orderId: order.id,
        carrier: "DHL",
        trackingNumber: "DHL123456789",
        itemIds: orderItemIds,
      } satisfies IEcommerceMallShipment.ICreate,
    },
  );
  typia.assert(shipment);
  // Store shipment ID before attempting deletion
  const shipmentId = shipment.id;
  // 5. Customer confirms delivery - this changes order items from 'shipped' to 'delivered'
  const confirmedShipment =
    await api.functional.ecommerceMall.customer.customers.me.orders.shipments.confirm_delivery.confirmDelivery(
      customerConnection,
      {
        orderId: order.id,
        shipmentId: shipment.id,
      },
    );
  typia.assert(confirmedShipment);
  // Verify shipment items are now 'delivered'
  const deliveredStatuses = confirmedShipment.shipmentItems.map(
    (item) => item.status,
  );
  TestValidator.equals(
    "all items delivered",
    deliveredStatuses.every((s) => s === "delivered"),
    true,
  );
  // 6. Seller attempts to delete the shipment - should be rejected with HTTP 400
  await TestValidator.httpError(
    "cannot delete shipment with delivered items",
    400,
    () =>
      api.functional.ecommerceMall.seller.shipments.erase(sellerConnection, {
        shipmentId: shipmentId,
      }),
  );
}
