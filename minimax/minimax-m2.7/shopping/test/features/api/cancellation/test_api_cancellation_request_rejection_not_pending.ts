export async function test_api_cancellation_request_rejection_not_pending(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin setup - register and authenticate admin
  const adminConnection: api.IConnection = { host: connection.host };
  const adminEmail = typia.random<string & tags.Format<"email">>();
  const adminPassword = RandomGenerator.alphaNumeric(16);
  await authorize_admin_join(adminConnection, {
    body: {
      email: adminEmail,
      password: adminPassword,
      name: RandomGenerator.name(),
    },
  });
  await authorize_admin_login(adminConnection, {
    body: {
      email: adminEmail,
      password: adminPassword,
      href: "https://example.com/admin",
      referrer: "https://example.com",
    },
  });
  // 2. Admin creates category
  const category =
    await generate_random_ecommerce_mall_admin_admin_categories_create(
      adminConnection,
      {},
    );
  typia.assert(category);
  // 3. Seller setup - register and authenticate as approved seller
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerEmail = typia.random<string & tags.Format<"email">>();
  const sellerPassword = RandomGenerator.alphaNumeric(16);
  await authorize_seller_join(sellerConnection, {
    body: {
      email: sellerEmail,
      password: sellerPassword,
      href: "https://example.com/seller",
      referrer: "https://example.com",
    },
  });
  // Login as seller
  await authorize_seller_login(sellerConnection, {
    body: {
      email: sellerEmail,
      password: sellerPassword,
      href: "https://example.com/seller",
      referrer: "https://example.com",
    },
  });
  // 4. Seller creates product
  const product =
    await generate_random_ecommerce_mall_seller_sellers_me_products_create(
      sellerConnection,
      {
        body: {
          name: RandomGenerator.paragraph({ sentences: 2 }),
          description: RandomGenerator.content({ paragraphs: 2 }),
          basePrice: typia.random<
            number & tags.Type<"uint32"> & tags.Minimum<1000>
          >(),
          categoryId: category.id,
        },
      },
    );
  typia.assert(product);
  // 5. Customer setup - register (join already authenticates)
  const customerConnection: api.IConnection = { host: connection.host };
  const customerEmail = typia.random<string & tags.Format<"email">>();
  const customerPassword = RandomGenerator.alphaNumeric(16);
  const customerName = RandomGenerator.name();
  await authorize_customer_join(customerConnection, {
    body: {
      email: customerEmail,
      password: customerPassword,
      name: customerName,
      href: "https://example.com/customer",
      referrer: "https://example.com",
    },
  });
  // 6. Customer adds shipping address
  const address =
    await generate_random_ecommerce_mall_customer_customers_me_addresses_create(
      customerConnection,
      {
        body: {
          recipient_name: RandomGenerator.name(),
          phone: RandomGenerator.mobile(),
          street_address: RandomGenerator.paragraph({ sentences: 1 }),
          city: RandomGenerator.name(),
          state: RandomGenerator.name(),
          postal_code: "12345",
          country: "Test Country",
          is_default: true,
        },
      },
    );
  typia.assert(address);
  // 7. Create order (cart items should be added via prepare_random_ecommerce_mall_order)
  const order =
    await generate_random_ecommerce_mall_customer_customers_me_orders_create(
      customerConnection,
      {
        body: {
          shippingAddressId: address.id,
        },
      },
    );
  typia.assert(order);
  // Get order item ID for cancellation
  const orderItem = order.orderItems[0];
  typia.assert(orderItem);
  // 8. Customer submits cancellation request (status becomes 'pending')
  await generate_random_ecommerce_mall_customer_customers_me_orders_items_cancel_create(
    customerConnection,
    {
      params: {
        itemId: orderItem.id,
      },
      body: {
        reason: "Changed my mind about the product",
      },
    },
  );
  // 9. Seller approves the cancellation request (changes status from 'pending' to 'approved')
  // Use orderItem.id since IEcommerceMallCancellationRequest doesn't have id property
  await api.functional.ecommerceMall.seller.sellers.me.cancellation_requests.approve(
    sellerConnection,
    {
      requestId: orderItem.id,
    },
  );
  // 10. Test: Seller attempts to reject the already approved cancellation request
  // This should fail with HTTP 400 error
  await TestValidator.error(
    "rejecting non-pending cancellation request should fail",
    async () => {
      await api.functional.ecommerceMall.seller.sellers.me.cancellation_requests.reject(
        sellerConnection,
        {
          requestId: orderItem.id,
        },
      );
    },
  );
}