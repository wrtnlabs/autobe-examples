export async function test_api_cancellation_request_admin_rejection_success(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as admin using utility function
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "Admin1234!" as string & tags.Format<"password">,
      name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  // 2. Prepare a cancellation request in pending status
  // Using a pre-existing pending cancellation request ID for the test
  const requestId = typia.random<string & tags.Format<"uuid">>();
  // 3. Admin rejects the cancellation request
  const rejectedRequest =
    await api.functional.ecommerceMall.admin.cancellation_requests.update(
      adminConnection,
      {
        requestId: requestId,
        body: {
          status: "rejected",
        } satisfies IEcommerceMallCancellationRequest.IUpdate,
      },
    );
  typia.assert(rejectedRequest);
  // 4. Validate cancellation request status is now rejected
  TestValidator.equals(
    "status is rejected",
    rejectedRequest.status,
    "rejected",
  );
  // 5. Validate snapshot was created with rejected status
  TestValidator.predicate(
    "snapshot exists with rejected status",
    rejectedRequest.snapshots.some((snap) => snap.status === "rejected"),
  );
}
