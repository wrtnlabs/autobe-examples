/**
 * Test that a customer cannot retrieve snapshots for another customer's
 * cancellation request. This validates the authorization boundary ensuring
 * customers can only access their own cancellation request history.
 *
 * Steps:
 * 1. Register customer A
 * 2. Register customer B
 * 3. Customer A retrieves their cancellation request list
 * 4. If customer A has cancellation requests, customer B attempts to retrieve
 *    snapshots using customer A's request ID
 * 5. Validate the system returns 403 Forbidden error
 * 6. Validate the error indicates unauthorized access to another customer's data
 */
export async function test_api_cancellation_request_snapshot_authorization_boundary(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register customer A (owner of cancellation requests)
  const customerAConnection: api.IConnection = { host: connection.host };
  const customerA = await authorize_customer_join(customerAConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IEcommerceMallCustomer.IJoin,
  });
  typia.assert(customerA);
  // 2. Register customer B (unauthorized accessor)
  const customerBConnection: api.IConnection = { host: connection.host };
  const customerB = await authorize_customer_join(customerBConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IEcommerceMallCustomer.IJoin,
  });
  typia.assert(customerB);
  // 3. Customer A retrieves their cancellation request list
  const cancellationRequestsPage =
    await api.functional.ecommerceMall.customer.cancellation_requests.index(
      customerAConnection,
      {
        body: {
          customer_id: customerA.id,
        } satisfies IEcommerceMallCancellationRequest.IRequest,
      },
    );
  typia.assert(cancellationRequestsPage);
  // 4. If customer A has cancellation requests, test authorization boundary
  if (cancellationRequestsPage.data.length > 0) {
    const customerARequestId = cancellationRequestsPage.data[0].id;
    // Customer B attempts to retrieve snapshots for customer A's request
    await TestValidator.httpError(
      "unauthorized access to another customer's cancellation request snapshots",
      403,
      async () =>
        await api.functional.ecommerceMall.customer.cancellation_requests.snapshots.index(
          customerBConnection,
          {
            requestId: customerARequestId,
            body: {} satisfies IEcommerceMallCancellationRequestSnapshot.IRequest,
          },
        ),
    );
  }
}
