/**
 * Test admin retrieving a cancellation request snapshot that does not exist.
 *
 * Validates that when an admin attempts to retrieve a snapshot using a valid
 * cancellation request ID but an invalid/non-existent snapshot ID, the system
 * returns a 404 Not Found error. This ensures proper snapshot existence validation.
 *
 * The test flow:
 * 1. Admin creates a product category.
 * 2. Seller registers, creates a product with inventory.
 * 3. Customer registers, creates address, adds to cart, and places order.
 * 4. Customer submits cancellation request for the order item.
 * 5. Seller approves the cancellation → creates valid snapshot.
 * 6. Admin attempts to retrieve with valid requestId but invalid snapshotId.
 * 7. System returns 404 Not Found.
 *
 * Validation ensures proper error handling for non-existent snapshot resources.
 */
export async function test_api_cancellation_snapshot_not_found(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin creates category
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  const category =
    await generate_random_ecommerce_mall_admin_admin_categories_create(
      adminConnection,
      {},
    );
  typia.assert(category);
  // 2. Seller registers and creates product
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {});
  const product =
    await generate_random_ecommerce_mall_seller_sellers_me_products_create(
      sellerConnection,
      {
        body: {
          categoryId: category.id,
          name: RandomGenerator.name(),
          description: RandomGenerator.paragraph(),
          basePrice: randint(1000, 100000),
        } satisfies IEcommerceMallProduct.ICreate,
      },
    );
  typia.assert(product);
  // Get variant ID from product
  const variant = product.variants[0];
  const variantId = variant.id;
  // 3. Customer registers, creates address, adds to cart, places order
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  const address =
    await generate_random_ecommerce_mall_customer_customers_me_addresses_create(
      customerConnection,
      {},
    );
  typia.assert(address);
  const cartItem =
    await generate_random_ecommerce_mall_customer_me_cart_items_create(
      customerConnection,
      {
        body: {
          productVariantId: variantId,
          quantity: 1,
        } satisfies IEcommerceMallCartItem.ICreate,
      },
    );
  typia.assert(cartItem);
  const order =
    await generate_random_ecommerce_mall_customer_customers_me_orders_create(
      customerConnection,
      {
        body: {
          shippingAddressId: address.id,
        } satisfies IEcommerceMallOrder.ICreate,
      },
    );
  typia.assert(order);
  // Get order item ID
  const orderItem = order.orderItems[0];
  const orderItemId = orderItem.id;
  // 4. Customer submits cancellation request
  const cancellationResult =
    await generate_random_ecommerce_mall_customer_customers_me_orders_items_cancel_create(
      customerConnection,
      {
        body: {
          reason: "Changed my mind",
        } satisfies IEcommerceMallCancellationRequest.ICreate,
        params: {
          itemId: orderItemId,
        },
      },
    );
  // 5. Seller approves → creates valid snapshot
  const cancellationId = (cancellationResult as any).id as string;
  const approved =
    await api.functional.ecommerceMall.seller.sellers.me.cancellation_requests.approve(
      sellerConnection,
      {
        requestId: cancellationId,
      },
    );
  typia.assert(approved);
  // 6. Admin attempts to retrieve with valid requestId but invalid/non-existent snapshotId
  const nonExistentSnapshotId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.httpError(
    "snapshot not found returns 404",
    404,
    async () => {
      await api.functional.ecommerceMall.admin.cancellation_requests.snapshots.at(
        adminConnection,
        {
          requestId: cancellationId,
          snapshotId: nonExistentSnapshotId,
        },
      );
    },
  );
}
