export async function test_api_cancellation_request_duplicate_approval_idempotent(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin creates category
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  const category =
    await generate_random_ecommerce_mall_admin_admin_categories_create(
      adminConnection,
      {},
    );
  typia.assert(category);
  // 2. Seller registers and gets approved
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {});
  typia.assert(sellerAuth);
  const approvedSeller =
    await api.functional.ecommerceMall.admin.admin.sellers.approve(
      adminConnection,
      { sellerId: sellerAuth.id },
    );
  typia.assert(approvedSeller);
  // 3. Seller creates product
  const product =
    await generate_random_ecommerce_mall_seller_sellers_me_products_create(
      sellerConnection,
      {
        body: {
          categoryId: category.id,
        },
      },
    );
  typia.assert(product);
  // 4. Customer registers, creates address, adds to cart, and places order
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  const address =
    await generate_random_ecommerce_mall_customer_customers_me_addresses_create(
      customerConnection,
      {},
    );
  typia.assert(address);
  // Get product variant ID from the product
  const variantId = product.variants[0]?.id;
  if (!variantId) {
    throw new Error("Product has no variants");
  }
  // Add to cart
  const cart = await generate_random_ecommerce_mall_customer_me_cart_create(
    customerConnection,
    {
      body: {
        productVariantId: variantId,
        quantity: 1,
      },
    },
  );
  typia.assert(cart);
  // Place order
  const order =
    await generate_random_ecommerce_mall_customer_customers_me_orders_create(
      customerConnection,
      {
        body: {
          shippingAddressId: address.id,
        },
      },
    );
  typia.assert(order);
  // 5. Customer submits cancellation request
  const orderItem = order.orderItems[0];
  if (!orderItem) {
    throw new Error("Order has no items");
  }
  const cancellationRequest =
    await generate_random_ecommerce_mall_customer_customers_me_orders_items_cancel_create(
      customerConnection,
      {
        params: {
          itemId: orderItem.id,
        },
      },
    );
  typia.assert(cancellationRequest);
  // Get the cancellation request ID from the response
  // The API response contains id but the DTO type definition is incomplete
  const cancellationRequestId = (
    cancellationRequest as unknown as {
      id: string & tags.Format<"uuid">;
    }
  ).id;
  // 6. Seller approves cancellation request (first time)
  const firstApproval =
    await api.functional.ecommerceMall.seller.sellers.me.cancellation_requests.approve(
      sellerConnection,
      { requestId: cancellationRequestId },
    );
  typia.assert(firstApproval);
  // 7. Seller attempts to approve again (idempotent test)
  const secondApproval =
    await api.functional.ecommerceMall.seller.sellers.me.cancellation_requests.approve(
      sellerConnection,
      { requestId: cancellationRequestId },
    );
  typia.assert(secondApproval);
  // 8. Validate idempotent behavior - both approvals should succeed
  TestValidator.equals(
    "first approval returns cancellation request",
    firstApproval.reason,
    cancellationRequest.reason,
  );
  TestValidator.equals(
    "second approval returns cancellation request",
    secondApproval.reason,
    cancellationRequest.reason,
  );
}
