export async function test_api_cancellation_request_approval_invalid_status(
  connection: api.IConnection,
): Promise<void> {
  // 1. Setup seller and customer
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {});
  const customerConnection: api.IConnection = { host: connection.host };
  const customerAuth = await authorize_customer_join(customerConnection, {});
  // 2. Seller creates product with variant
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerConnection,
    {},
  );
  typia.assert(product);
  const variant =
    await generate_random_ecommerce_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
        body: { quantity: 10 },
      },
    );
  typia.assert(variant);
  // 3. Customer adds item to cart and checks out
  await api.functional.ecommerceMall.customer.ecommerceMall.cart.items.create(
    customerConnection,
    {
      body: {
        variantId: variant.id,
        quantity: 1,
      } satisfies IEcommerceMallCartItem.IRequest,
    },
  );
  const order =
    await generate_random_ecommerce_mall_customer_customers_checkout_create(
      customerConnection,
      {},
    );
  typia.assert(order);
  // 4. Customer submits cancellation request
  const orderItemId = order.orderItems[0].id;
  const cancellationRequest =
    await generate_random_ecommerce_mall_customer_cancellation_requests_create(
      customerConnection,
      {
        body: {
          orderItemId: orderItemId,
          reason: "Changed my mind",
        },
      },
    );
  typia.assert(cancellationRequest);
  // 5. Seller rejects the cancellation request first
  const rejectBody = {
    reason: "Order already being processed",
  } satisfies IEcommerceMallCancellationRequest.IReject;
  const rejected =
    await api.functional.ecommerceMall.seller.cancellation_requests.reject(
      sellerConnection,
      {
        requestId: cancellationRequest.id,
        body: rejectBody,
      },
    );
  typia.assert(rejected);
  // 6. Seller attempts to approve the already rejected cancellation request
  // This should fail with 400 Bad Request
  await TestValidator.httpError(
    "approve rejected cancellation fails with 400",
    400,
    async () => {
      await api.functional.ecommerceMall.seller.cancellation_requests.approve(
        sellerConnection,
        {
          requestId: cancellationRequest.id,
        },
      );
    },
  );
}
