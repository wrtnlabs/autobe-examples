export async function test_api_cancellation_request_retrieval_by_owner(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin setup - register admin
  const adminConnection: api.IConnection = { host: connection.host };
  const adminAuth = await authorize_admin_join(adminConnection, {});
  typia.assert(adminAuth);
  // 2. Create product category (admin)
  const category =
    await generate_random_ecommerce_mall_admin_admin_categories_create(
      adminConnection,
      {},
    );
  typia.assert(category);
  // 3. Seller setup - register and get approved
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {});
  typia.assert(sellerAuth);
  // 4. Create product (seller)
  const product =
    await generate_random_ecommerce_mall_seller_sellers_me_products_create(
      sellerConnection,
      {
        body: {
          categoryId: category.id,
        },
      },
    );
  typia.assert(product);
  // 5. Customer setup - register customer
  const customerConnection: api.IConnection = { host: connection.host };
  const customerAuth = await authorize_customer_join(customerConnection, {});
  typia.assert(customerAuth);
  // 6. Create shipping address (customer)
  const address =
    await generate_random_ecommerce_mall_customer_customers_me_addresses_create(
      customerConnection,
      {},
    );
  typia.assert(address);
  // 7. Create order (customer)
  const order =
    await generate_random_ecommerce_mall_customer_customers_me_orders_create(
      customerConnection,
      {
        body: {
          shippingAddressId: address.id,
        },
      },
    );
  typia.assert(order);
  // 8. Submit cancellation request for a paid order item
  const orderItem = order.orderItems[0];
  const cancellationReason = "Changed my mind about the product";
  // Create cancellation request using the endpoint directly
  const createResponse =
    await api.functional.ecommerceMall.customer.customers.me.orders.items.cancel.create(
      customerConnection,
      {
        itemId: orderItem.id,
        body: {
          reason: cancellationReason,
        } satisfies IEcommerceMallCancellationRequest.ICreate,
      },
    );
  typia.assert(createResponse);
  // 9. Retrieve the cancellation request by owner
  // Note: The cancellation request ID is returned in the create response
  // We need to access it - since DTO may not have id, we use type assertion
  const cancellationRequestId = (createResponse as any).id;
  const retrievedRequest =
    await api.functional.ecommerceMall.customer.customers.me.cancellation_requests.at(
      customerConnection,
      {
        requestId: cancellationRequestId,
      },
    );
  typia.assert(retrievedRequest);
  // 10. Validate retrieved cancellation request
  // The DTO IEcommerceMallCancellationRequest only has 'reason' property
  // We validate the reason matches what was submitted
  TestValidator.equals(
    "reason matches original input",
    retrievedRequest.reason,
    cancellationReason,
  );
  // Additional validation: verify the retrieved response is a valid object
  TestValidator.predicate(
    "retrieved request is valid object",
    retrievedRequest !== null && typeof retrievedRequest === "object",
  );
  TestValidator.predicate(
    "retrieved request has reason property",
    "reason" in retrievedRequest && typeof retrievedRequest.reason === "string",
  );
}
