export async function test_api_cancellation_request_access_denied_for_other_customer(
  connection: api.IConnection,
): Promise<void> {
  // Test scenario: Customer cannot view another customer's cancellation request.
  // This test validates access control on GET /ecommerceMall/customer/cancellation-requests/{requestId}
  // Expected: HTTP 403 Forbidden when one customer tries to access another's cancellation request.
  // Step 1: Register two customers
  const customerAConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerAConnection, { body: {} });
  const customerBConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerBConnection, { body: {} });
  // Step 2: Customer B attempts to access a cancellation request ID
  // This simulates trying to access another customer's cancellation request
  // The endpoint should return 403 Forbidden due to access control
  const fakeRequestId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.httpError(
    "access denied for other customer's cancellation request",
    403,
    async () =>
      api.functional.ecommerceMall.customer.cancellation_requests.at(
        customerBConnection,
        { requestId: fakeRequestId },
      ),
  );
}
