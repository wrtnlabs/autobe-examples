export async function test_api_cancellation_request_snapshots_pending_request_empty_list(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as seller
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {});
  // 2. Authenticate as customer
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  // 3. Create seller product with variant and inventory
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerConnection,
    {},
  );
  typia.assert(product);
  const variant =
    await generate_random_ecommerce_mall_seller_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
      },
    );
  typia.assert(variant);
  // Add inventory to the variant
  await generate_random_ecommerce_mall_seller_products_variants_inventory_create(
    sellerConnection,
    {
      params: { productId: product.id, variantId: variant.id },
      body: {
        operation: "restock" as const,
        quantity: 10,
        reason: "Initial stock",
      },
    },
  );
  // 4. Customer adds product to cart
  const cartItem =
    await generate_random_ecommerce_mall_customer_cart_items_create(
      customerConnection,
      {
        body: {
          variant_id: variant.id,
          quantity: 1,
        },
      },
    );
  typia.assert(cartItem);
  // 5. Customer places order
  const order =
    await api.functional.ecommerceMall.customer.checkout.confirm.create(
      customerConnection,
      {
        body: {
          payment_token: "test_payment_token_" + Date.now(),
        },
      },
    );
  typia.assert(order);
  // 6. Customer creates cancellation request (status remains 'pending')
  const cancellationRequests =
    await api.functional.ecommerceMall.customer.cancellation_requests.index(
      customerConnection,
      {
        body: {},
      },
    );
  typia.assert(cancellationRequests);
  const pendingRequest = cancellationRequests.data[0];
  typia.assert(pendingRequest);
  // 7. Seller retrieves snapshots for the pending cancellation request
  // Expected: Returns 200 OK with empty data array (no snapshots yet since pending)
  const snapshots =
    await api.functional.ecommerceMall.seller.cancellation_requests.snapshots.index(
      sellerConnection,
      {
        requestId: pendingRequest.id,
        body: {},
      },
    );
  typia.assert(snapshots);
  // Validate: Empty data array with records = 0
  TestValidator.equals("records should be 0", snapshots.pagination.records, 0);
  TestValidator.equals("data should be empty array", snapshots.data.length, 0);
  TestValidator.equals("pages should be 0", snapshots.pagination.pages, 0);
}
