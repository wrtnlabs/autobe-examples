export async function test_api_cancellation_request_snapshots_ownership_enforcement(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register Customer A (attacker/impersonator)
  const customerAConnection: api.IConnection = { host: connection.host };
  const customerA = await authorize_customer_join(customerAConnection, {});
  typia.assert(customerA);
  // 2. Register Customer B (victim - owns the cancellation request)
  const customerBConnection: api.IConnection = { host: connection.host };
  const customerB = await authorize_customer_join(customerBConnection, {});
  typia.assert(customerB);
  // 3. Register and approve Seller
  const sellerConnection: api.IConnection = { host: connection.host };
  const seller = await authorize_seller_join(sellerConnection, {});
  typia.assert(seller);
  // 4. Seller creates product
  const product =
    await generate_random_ecommerce_mall_seller_sellers_me_products_create(
      sellerConnection,
      {},
    );
  typia.assert(product);
  // 5. Customer B creates order
  const order =
    await generate_random_ecommerce_mall_customer_customers_me_orders_create(
      customerBConnection,
      {},
    );
  typia.assert(order);
  // 6. Get the order item ID for cancellation
  const orderItemId = order.orderItems[0]!.id;
  // 7. Customer B submits cancellation request
  // Cast to any to access the id property that exists on the server response
  // but isn't defined in the minimal DTO type
  const cancellationRequestRaw =
    (await generate_random_ecommerce_mall_customer_customers_me_orders_items_cancel_create(
      customerBConnection,
      {
        params: {
          itemId: orderItemId,
        },
      },
    )) as any;
  const cancellationRequestId = cancellationRequestRaw.id as string &
    tags.Format<"uuid">;
  // 8. Seller approves cancellation (creates snapshot)
  const approvedRequest =
    await api.functional.ecommerceMall.seller.sellers.me.cancellation_requests.approve(
      sellerConnection,
      {
        requestId: cancellationRequestId,
      },
    );
  typia.assert(approvedRequest);
  // 9. Customer A attempts to view Customer B's cancellation request snapshots
  // This should return 404 because ownership validation fails
  await TestValidator.httpError(
    "Customer A cannot access Customer B's cancellation request snapshots",
    404,
    async () =>
      await api.functional.ecommerceMall.customer.customers.me.cancellation_requests.snapshots.cancellationRequestSnapshot(
        customerAConnection,
        {
          requestId: cancellationRequestId,
        },
      ),
  );
}
