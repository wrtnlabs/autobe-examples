export async function test_api_cancellation_request_unauthorized_access(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin creates product category
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_login(adminConnection, {
    body: {
      email: "admin@test.com",
      password: "1234",
      href: "http://localhost:3000",
      referrer: "http://localhost:3000",
    },
  });
  const category =
    await generate_random_ecommerce_mall_admin_admin_categories_create(
      adminConnection,
      {},
    );
  typia.assert(category);
  // 2. Seller joins and creates product
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {});
  typia.assert(sellerAuth);
  const product =
    await generate_random_ecommerce_mall_seller_sellers_me_products_create(
      sellerConnection,
      {
        body: {
          categoryId: category.id,
        },
      },
    );
  typia.assert(product);
  // Get variant ID for cart creation
  const variantId = product.variants[0]?.id;
  if (!variantId) {
    throw new Error("Product has no variants");
  }
  // 3. Customer A registers and sets up order with cancellation request
  const customerAConnection: api.IConnection = { host: connection.host };
  const customerA = await authorize_customer_join(customerAConnection, {});
  typia.assert(customerA);
  // Customer A creates shipping address
  const address =
    await generate_random_ecommerce_mall_customer_customers_me_addresses_create(
      customerAConnection,
      {},
    );
  typia.assert(address);
  // Customer A adds to cart
  const cartItem =
    await generate_random_ecommerce_mall_customer_customers_me_cart_create(
      customerAConnection,
      {
        body: {
          variantId: variantId,
          quantity: 1,
        },
      },
    );
  typia.assert(cartItem);
  // Customer A creates order
  const order =
    await generate_random_ecommerce_mall_customer_customers_me_orders_create(
      customerAConnection,
      {
        body: {
          shippingAddressId: address.id,
        },
      },
    );
  typia.assert(order);
  // Customer A submits cancellation request
  const orderItemId = order.orderItems[0]?.id;
  if (!orderItemId) {
    throw new Error("Order has no items");
  }
  const cancellationRequest =
    await generate_random_ecommerce_mall_customer_customers_me_orders_items_cancel_create(
      customerAConnection,
      {
        params: {
          itemId: orderItemId,
        },
        body: {
          reason: "Changed my mind",
        },
      },
    );
  typia.assert(cancellationRequest);
  // 4. Customer B registers (different customer account)
  const customerBConnection: api.IConnection = { host: connection.host };
  const customerB = await authorize_customer_join(customerBConnection, {});
  typia.assert(customerB);
  // 5. Verify Customer A can retrieve their own cancellation request (positive case)
  const ownCancellationRequest =
    await api.functional.ecommerceMall.customer.customers.me.orders.items.cancellation.at(
      customerAConnection,
      {
        itemId: orderItemId,
      },
    );
  typia.assert(ownCancellationRequest);
  // 6. Verify Customer B receives 403 when trying to access Customer A's cancellation request
  await TestValidator.httpError(
    "Customer B cannot access Customer A's cancellation request",
    403,
    async () => {
      await api.functional.ecommerceMall.customer.customers.me.orders.items.cancellation.at(
        customerBConnection,
        {
          itemId: orderItemId,
        },
      );
    },
  );
}
