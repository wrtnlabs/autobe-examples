export async function test_api_inventory_history_empty_for_new_variant(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as seller
  const sellerConnection: api.IConnection = { host: connection.host };
  const seller = await authorize_seller_join(sellerConnection, {});
  // 2. Create a product
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerConnection,
    {},
  );
  // 3. Create a product variant with no inventory (quantity defaults to 0)
  const variant =
    await generate_random_ecommerce_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
        body: {
          skuCode: `SKU-${Date.now()}`,
          quantity: 0,
        },
      },
    );
  typia.assert(variant);
  // 4. Call GET /seller/variants/{variantId}/inventory/history
  const inventoryHistory =
    await api.functional.ecommerceMall.seller.variants.inventory.history.at(
      sellerConnection,
      {
        variantId: variant.id,
      },
    );
  typia.assert(inventoryHistory);
  // 5. Validate response - pagination exists and data array is empty
  TestValidator.equals(
    "pagination exists",
    inventoryHistory.pagination !== null,
    true,
  );
  TestValidator.equals("data array is empty", inventoryHistory.data.length, 0);
}