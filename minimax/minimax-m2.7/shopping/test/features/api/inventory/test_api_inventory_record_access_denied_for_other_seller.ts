export async function test_api_inventory_record_access_denied_for_other_seller(
  connection: api.IConnection,
): Promise<void> {
  // 1. First seller (owner) registers and logs in
  const seller1Connection: api.IConnection = { host: connection.host };
  await authorize_seller_join(seller1Connection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IEcommerceMallSeller.IJoin,
  });
  // 2. First seller creates a product
  const product = await generate_random_ecommerce_mall_seller_products_create(
    seller1Connection,
    {},
  );
  typia.assert(product);
  // 3. First seller creates a variant
  const variant =
    await generate_random_ecommerce_mall_seller_products_variants_create(
      seller1Connection,
      {
        params: {
          productId: product.id,
        },
      },
    );
  typia.assert(variant);
  // 4. First seller adds inventory to create a record
  const inventoryRecord =
    await generate_random_ecommerce_mall_seller_products_variants_inventory_create(
      seller1Connection,
      {
        params: {
          productId: product.id,
          variantId: variant.id,
        },
      },
    );
  typia.assert(inventoryRecord);
  // 5. Second seller registers and logs in (intruder)
  const seller2Connection: api.IConnection = { host: connection.host };
  await authorize_seller_join(seller2Connection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IEcommerceMallSeller.IJoin,
  });
  // 6. Second seller attempts to access first seller's variant's inventory
  // This should be denied with 403 Forbidden because seller2 doesn't own the variant
  await TestValidator.httpError(
    "Second seller cannot access first seller's variant inventory",
    403,
    async () =>
      await api.functional.ecommerceMall.seller.variants.inventory.at(
        seller2Connection,
        {
          variantId: variant.id,
          inventoryId: typia.random<string & tags.Format<"uuid">>(),
        },
      ),
  );
}
