export async function test_api_inventory_restock_minimum_quantity(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register seller
  const sellerConnection: api.IConnection = { host: connection.host };
  const seller = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  typia.assert(seller);
  // 2. Create product
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerConnection,
    {},
  );
  typia.assert(product);
  // 3. Create variant
  const variant =
    await generate_random_ecommerce_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
        body: {
          skuCode: RandomGenerator.alphabets(10),
          quantity: 0,
        },
      },
    );
  typia.assert(variant);
  // 4. Restock with minimum quantity of 1 unit
  const inventoryRecord =
    await api.functional.ecommerceMall.seller.productVariants.inventoryRecords.create(
      sellerConnection,
      {
        variantId: variant.id,
        body: {
          quantity: 1 as number & tags.Type<"int32"> & tags.Minimum<1>,
          operationType: "restock",
          reason: "initial stock",
        } satisfies IEcommerceMallInventoryRecord.ICreate,
      },
    );
  typia.assert(inventoryRecord);
  // 5. Validate inventory record creation with minimum quantity of 1
  TestValidator.predicate(
    "inventory record has positive stock quantity",
    inventoryRecord.totalStockQuantity >= 1,
  );
  TestValidator.predicate(
    "recent changes contains restock record with quantity 1",
    inventoryRecord.recentChanges.some(
      (change) =>
        change.quantityChange === 1 && change.reason === "initial stock",
    ),
  );
  TestValidator.predicate(
    "low stock variants count is correct",
    inventoryRecord.lowStockCount >= 0,
  );
}
