export async function test_api_inventory_records_variant_not_found(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as super administrator
  const superAdminConnection: api.IConnection = { host: connection.host };
  await authorize_super_admin_join(superAdminConnection, {});
  // 2. Generate a non-existent variant UUID
  const nonExistentVariantId = typia.random<string & tags.Format<"uuid">>();
  // 3. Attempt to get inventory records for non-existent variant
  await TestValidator.error("variant not found returns 404", async () => {
    await api.functional.ecommerceMall.superAdmin.productVariants.inventoryRecords.index(
      superAdminConnection,
      {
        variantId: nonExistentVariantId,
        body: {} satisfies IEcommerceMallInventoryRecord.IRequest,
      },
    );
  });
}
