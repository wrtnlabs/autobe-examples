export async function test_api_inventory_restock_variant_positive_quantity(
  connection: api.IConnection,
): Promise<void> {
  // 1. Administrator setup
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  await authorize_admin_login(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IEcommerceMallAdmin.ILogin,
  });
  // 2. Seller registration and authentication
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {});
  // 3. Create category (admin creates category for seller to use)
  const category =
    await generate_random_ecommerce_mall_admin_admin_categories_create(
      adminConnection,
      {},
    );
  typia.assert(category);
  // 4. Create product
  const product =
    await generate_random_ecommerce_mall_seller_sellers_me_products_create(
      sellerConnection,
      {
        body: {
          categoryId: category.id,
        },
      },
    );
  typia.assert(product);
  // 5. Create variant (starts at zero stock)
  const variant =
    await generate_random_ecommerce_mall_seller_sellers_me_products_variants_create(
      sellerConnection,
      {
        params: {
          productId: product.id,
        },
      },
    );
  typia.assert(variant);
  // Verify variant starts at zero stock
  TestValidator.equals("variant stock should be zero", variant.quantity, 0);
  // 6. Restock with positive quantity
  const restockQuantity = 100;
  const restockReason = "restock from supplier";
  const inventoryRecord =
    await api.functional.ecommerceMall.seller.sellers.me.variants._inventory.add(
      sellerConnection,
      {
        variantId: variant.id,
        body: {
          quantityChange: restockQuantity,
          reason: restockReason,
        } satisfies IEcommerceMallInventoryRecord.ICreate,
      },
    );
  typia.assert(inventoryRecord);
  // 7. Validate inventory record response
  TestValidator.predicate(
    "inventory record should have valid UUID ID",
    /^[0-9a-f-]{36}$/i.test(inventoryRecord.id),
  );
  TestValidator.equals(
    "quantity change should match restock amount",
    inventoryRecord.quantityChange,
    restockQuantity,
  );
  TestValidator.equals(
    "reason should match provided reason",
    inventoryRecord.reason,
    restockReason,
  );
  TestValidator.predicate(
    "should have valid server-generated timestamp",
    (inventoryRecord.createdAt?.length ?? 0) > 0,
  );
}
