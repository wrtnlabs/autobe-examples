export async function test_api_inventory_records_access_denied_for_other_seller(
  connection: api.IConnection,
): Promise<void> {
  // 1. Seller A registers
  const sellerAConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerAConnection, {});
  // 2. Seller A creates product with variant
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerAConnection,
    {},
  );
  const variant =
    await generate_random_ecommerce_mall_seller_products_variants_create(
      sellerAConnection,
      {
        params: { productId: product.id },
        body: {},
      },
    );
  // 3. Seller B registers
  const sellerBConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerBConnection, {});
  // 4. Seller B attempts to access Seller A's variant inventory records
  await TestValidator.httpError(
    "Seller B cannot access Seller A's variant inventory - should return 403 Forbidden",
    403,
    async () =>
      await api.functional.ecommerceMall.seller.productVariants.inventoryRecords.index(
        sellerBConnection,
        {
          variantId: variant.id,
          body: {},
        },
      ),
  );
}
