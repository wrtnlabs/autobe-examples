export async function test_api_inventory_record_not_found(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register and login as a seller
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {});
  // 2. Create a product listing
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerConnection,
    {},
  );
  // 3. Create a product variant with SKU code
  const variant =
    await generate_random_ecommerce_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
      },
    );
  // 4. Generate a random UUID for non-existent inventory record
  const nonExistentInventoryId = typia.random<string & tags.Format<"uuid">>();
  // 5. Verify 404 when trying to retrieve non-existent inventory record
  await TestValidator.httpError(
    "inventory record not found returns 404",
    404,
    () =>
      api.functional.ecommerceMall.seller.variants.inventory.at(
        sellerConnection,
        {
          variantId: variant.id,
          inventoryId: nonExistentInventoryId,
        },
      ),
  );
}
