export async function test_api_inventory_record_retrieval_record_not_found(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as admin
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      actorType: "seller",
      requestedGrade: "admin",
      reason: "Testing admin inventory record access",
      href: "https://test.example.com/admin",
      referrer: "https://test.example.com",
    },
  });
  // 2. Create a category for product creation
  const category = await generate_random_ecommerce_mall_admin_categories_create(
    adminConnection,
    {},
  );
  // 3. Authenticate as seller
  const sellerConnection: api.IConnection = { host: connection.host };
  const seller = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: "https://test.example.com/seller",
      referrer: "https://test.example.com",
    },
  });
  // 4. Create a product with the category
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        name: RandomGenerator.name(),
        description: RandomGenerator.paragraph({ sentences: 3 }),
        categoryId: category.id,
        basePrice: typia.random<
          number & tags.Type<"uint32"> & tags.Minimum<1000>
        >(),
      },
    },
  );
  // 5. Create a product variant
  const variant =
    await generate_random_ecommerce_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
        body: {
          skuCode: `SKU-${RandomGenerator.alphaNumeric(8)}`,
          quantity: 100,
        },
      },
    );
  // 6. Create an inventory record
  const inventoryRecord =
    await generate_random_ecommerce_mall_seller_product_variants_inventory_records_create(
      sellerConnection,
      {
        params: { variantId: variant.id },
        body: {
          quantity: 50,
          operationType: "restock",
          reason: "Initial stock",
        },
      },
    );
  // 7. Generate a non-existent inventory record ID (valid UUID format but not in database)
  const nonExistentRecordId = typia.random<string & tags.Format<"uuid">>();
  // 8. Attempt to retrieve the non-existent inventory record - should return 404
  await TestValidator.error(
    "non-existent inventory record returns 404",
    async () => {
      await api.functional.ecommerceMall.admin.productVariants.inventoryRecords.at(
        adminConnection,
        {
          variantId: variant.id,
          inventoryRecordId: nonExistentRecordId,
        },
      );
    },
  );
}
