export async function test_api_cancellation_request_listing_as_customer(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as customer
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  // 2. Retrieve cancellation requests (should be empty for new customer)
  const cancellationRequests =
    await api.functional.ecommerceMall.customer.cancellation_requests.index(
      customerConnection,
      {
        body: {} satisfies IEcommerceMallCancellationRequest.IRequest,
      },
    );
  typia.assert(cancellationRequests);
  // 3. Validate pagination metadata structure
  TestValidator.equals(
    "pagination.current is valid",
    cancellationRequests.pagination.current,
    1 satisfies number,
  );
  TestValidator.equals(
    "pagination.limit is valid",
    cancellationRequests.pagination.limit,
    10 satisfies number,
  );
  TestValidator.equals(
    "pagination.records is 0 for new customer",
    cancellationRequests.pagination.records,
    0,
  );
  TestValidator.equals(
    "pagination.pages is 0 for empty data",
    cancellationRequests.pagination.pages,
    0,
  );
  // 4. Validate data array is empty for new customer
  TestValidator.equals(
    "data array is empty",
    cancellationRequests.data.length,
    0,
  );
}
