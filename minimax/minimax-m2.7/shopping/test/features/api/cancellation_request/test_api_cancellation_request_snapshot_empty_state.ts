export async function test_api_cancellation_request_snapshot_empty_state(
  connection: api.IConnection,
): Promise<void> {
  // 1. Customer registers and authenticates (new customer with no snapshots)
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  // 2. Customer sends PATCH request with empty/optional body to query snapshots
  // Since the customer has no cancellation requests, no snapshots exist
  const response =
    await api.functional.ecommerceMall.customer.cancellation_request_snapshots.index(
      customerConnection,
      {
        body: {}, // Empty body - all filters are optional
      },
    );
  typia.assert(response);
  // 3. Validate response structure and empty state
  TestValidator.equals("data array should be empty", response.data, []);
  TestValidator.equals("records should be 0", response.pagination.records, 0);
  TestValidator.equals("pages should be 0", response.pagination.pages, 0);
  TestValidator.equals(
    "current page should be 1",
    response.pagination.current,
    1,
  );
  TestValidator.equals(
    "limit should be default 20",
    response.pagination.limit,
    20,
  );
}
