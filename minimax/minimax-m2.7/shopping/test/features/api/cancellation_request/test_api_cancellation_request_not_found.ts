/**
 * Test retrieving a non-existent cancellation request returns 404.
 *
 * Scenario:
 * 1. Register a customer account via POST /ecommerceMall/auth/customer/join
 * 2. Authenticate as the registered customer
 * 3. Call GET /ecommerceMall/customer/cancellation-requests/{requestId} with a random UUID
 * 4. Expected response: HTTP 404 Not Found
 *
 * Validations:
 * - Response status code is 404
 * - No sensitive data leaked in error message
 */
export async function test_api_cancellation_request_not_found(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register a customer account
  const customerConnection: api.IConnection = { host: connection.host };
  const customer = await authorize_customer_join(customerConnection, {});
  typia.assert(customer);
  // 2. Generate a random UUID that doesn't exist
  const nonExistentRequestId = typia.random<string & tags.Format<"uuid">>();
  // 3. Attempt to retrieve non-existent cancellation request
  // 4. Validate 404 error response
  await TestValidator.httpError(
    "non-existent cancellation request returns 404",
    404,
    async () =>
      await api.functional.ecommerceMall.customer.cancellation_requests.at(
        customerConnection,
        {
          requestId: nonExistentRequestId,
        },
      ),
  );
}
