/**
 * Test retrieving a cancellation request that does not exist.
 *
 * Validates the system's 404 handling when a customer attempts to view a cancellation request with an invalid UUID. Ensures the endpoint properly rejects requests for non-existent cancellation requests and returns an appropriate HTTP 404 error without leaking information about other resources.
 *
 * **Test Flow**:
 * 1. Customer registers and authenticates with valid credentials
 * 2. Attempt to retrieve a cancellation request using a non-existent UUID
 * 3. Verify HTTP 404 error is returned
 *
 * **Security Considerations**:
 * - The endpoint should not reveal whether cancellation requests exist for other orders
 * - Error messages should be generic and not expose internal implementation details
 * - The 404 response prevents enumeration attacks on cancellation request IDs
 */
export async function test_api_cancellation_request_retrieval_not_found(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register and authenticate a customer
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  // 2. Attempt to retrieve a non-existent cancellation request
  // Using a UUID that definitely does not exist in the system
  const nonExistentRequestId = "00000000-0000-0000-0000-000000000000";
  // 3. Verify 404 error is returned for non-existent cancellation request
  await TestValidator.httpError(
    "non-existent cancellation request returns 404",
    404,
    async () =>
      await api.functional.ecommerceMall.customer.customers.me.cancellation_requests.at(
        customerConnection,
        {
          requestId: nonExistentRequestId as string & tags.Format<"uuid">,
        },
      ),
  );
}
