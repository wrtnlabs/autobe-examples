export async function test_api_snapshot_retrieval_not_found(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as super administrator
  const superAdminConnection: api.IConnection = { host: connection.host };
  await authorize_super_admin_join(superAdminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16) as any,
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  // 2. Create a category using admin endpoint
  const category = await generate_random_ecommerce_mall_admin_categories_create(
    superAdminConnection,
    {
      body: {
        name: RandomGenerator.name(),
        description: RandomGenerator.paragraph({ sentences: 2 }),
      },
    },
  );
  typia.assert(category);
  // 3. Authenticate as seller
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16) as any,
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  // 4. Create a product (automatically creates initial snapshot)
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        name: RandomGenerator.name(),
        description: RandomGenerator.paragraph({ sentences: 3 }),
        categoryId: category.id,
        basePrice: typia.random<
          number & tags.Type<"uint32"> & tags.Minimum<1000>
        >(),
      },
    },
  );
  typia.assert(product);
  // 5. Attempt to retrieve non-existent snapshot (UUID with all zeros)
  const nonExistentSnapshotId =
    "00000000-0000-0000-0000-000000000000" as string & tags.Format<"uuid">;
  // Validate that 404 Not Found is returned
  await TestValidator.httpError(
    "snapshot not found returns 404",
    404,
    async () =>
      await api.functional.ecommerceMall.superAdmin.products.snapshots.at(
        superAdminConnection,
        {
          productId: product.id,
          snapshotId: nonExistentSnapshotId,
        },
      ),
  );
}
