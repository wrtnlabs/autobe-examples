export async function test_api_seller_product_reviews_retrieval_empty_state(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin creates a category
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_login(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IEcommerceMallAdmin.ILogin,
  });
  const category = await generate_random_ecommerce_mall_admin_categories_create(
    adminConnection,
    {},
  );
  typia.assert(category);
  // 2. Seller registers
  const sellerPassword = RandomGenerator.alphaNumeric(16);
  const sellerEmail = typia.random<string & tags.Format<"email">>();
  const sellerAuthResult = await authorize_seller_join(connection, {
    body: {
      email: sellerEmail,
      password: sellerPassword,
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  // 3. Seller logs in
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_login(sellerConnection, {
    body: {
      email: sellerEmail,
      password: sellerPassword,
    } satisfies IEcommerceMallSeller.ILogin,
  });
  // 4. Seller creates a product (no reviews)
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        categoryId: category.id,
      },
    },
  );
  typia.assert(product);
  // 5. Retrieve reviews for the product (empty state)
  const reviewsPage =
    await api.functional.ecommerceMall.seller.products.reviews.at(
      sellerConnection,
      {
        productId: product.id,
      },
    );
  typia.assert(reviewsPage);
  // 6. Validate empty state response
  TestValidator.equals(
    "data array should be empty",
    reviewsPage.data.length,
    0,
  );
  TestValidator.equals(
    "pagination records should be 0",
    reviewsPage.pagination.records,
    0,
  );
  TestValidator.equals(
    "pagination pages should be 0",
    reviewsPage.pagination.pages,
    0,
  );
  TestValidator.equals(
    "pagination current should be 1",
    reviewsPage.pagination.current,
    1,
  );
}
