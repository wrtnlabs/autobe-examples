export async function test_api_review_snapshot_forbidden_for_non_owner(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create customerA and authenticate
  const customerAConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerAConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IEcommerceMallCustomer.IJoin,
  });
  // 2. Create review as customerA using generation utility
  const review =
    await generate_random_ecommerce_mall_customer_customers_orders_items_review_create(
      customerAConnection,
      {
        params: {
          orderId: typia.random<string & tags.Format<"uuid">>(),
          itemId: typia.random<string & tags.Format<"uuid">>(),
        },
        body: {
          rating: typia.random<
            number & tags.Type<"int32"> & tags.Minimum<1> & tags.Maximum<5>
          >(),
          content: RandomGenerator.paragraph({ sentences: 2 }),
        },
      },
    );
  typia.assert(review);
  // 3. Create customerB (different customer)
  const customerBConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerBConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IEcommerceMallCustomer.IJoin,
  });
  // 4. Attempt to retrieve snapshots for customerA's review as customerB
  // Should return 403 Forbidden
  await TestValidator.httpError(
    "customerB cannot access customerA's review snapshots",
    403,
    async () =>
      await api.functional.ecommerceMall.customer.reviews.snapshots.index(
        customerBConnection,
        {
          reviewId: review.id,
          body: {} satisfies IEcommerceMallReviewSnapshot.IRequest,
        },
      ),
  );
}
