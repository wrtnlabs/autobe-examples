export async function test_api_customer_review_list_filtered_by_date_and_deleted(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as customer
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  // 2. Define date range for filtering
  const dateFrom = "2024-01-01T00:00:00.000Z";
  const dateTo = "2024-12-31T23:59:59.999Z";
  // 3. Call reviews endpoint with date range filter and include deleted reviews
  const reviewListResponse =
    await api.functional.ecommerceMall.customer.customers.me.reviews.index(
      customerConnection,
      {
        body: {
          createdAtFrom: dateFrom,
          createdAtTo: dateTo,
          deleted: true,
        } satisfies IEcommerceMallReview.IRequest,
      },
    );
  typia.assert(reviewListResponse);
  // 4. Validate response structure
  TestValidator.equals(
    "response has pagination",
    reviewListResponse.pagination !== null,
    true,
  );
  TestValidator.equals(
    "response has data array",
    Array.isArray(reviewListResponse.data),
    true,
  );
  // 5. Validate date range filtering if reviews exist
  for (const review of reviewListResponse.data) {
    const reviewDate = new Date(review.createdAt).getTime();
    const fromTime = new Date(dateFrom).getTime();
    const toTime = new Date(dateTo).getTime();
    TestValidator.predicate(
      `Review ${review.id} createdAt should be within date range`,
      reviewDate >= fromTime && reviewDate <= toTime,
    );
  }
  // 6. Validate pagination metadata
  TestValidator.predicate(
    "pagination current page is valid",
    reviewListResponse.pagination.current >= 0,
  );
  TestValidator.predicate(
    "pagination limit is valid",
    reviewListResponse.pagination.limit > 0,
  );
  TestValidator.predicate(
    "pagination records count is valid",
    reviewListResponse.pagination.records >= 0,
  );
  TestValidator.predicate(
    "pagination pages count is valid",
    reviewListResponse.pagination.pages >= 0,
  );
}
