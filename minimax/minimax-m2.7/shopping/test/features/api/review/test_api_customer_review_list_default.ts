/**
 * Test retrieving all reviews written by the authenticated customer with default filtering.
 *
 * Validates the customer review list endpoint by authenticating as a customer and
 * retrieving all reviews with default settings. Since the customer has no reviews yet,
 * the test expects an empty paginated response.
 *
 * Key validations:
 * - HTTP 200 response with valid pagination metadata
 * - Empty data array when customer has no reviews
 * - Pagination fields (current, limit, records, pages) are properly populated
 * - Default filtering excludes deleted reviews
 *
 * @param connection Base API connection for the test
 */
export async function test_api_customer_review_list_default(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as customer
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  // 2. Get customer reviews with default settings (empty request body)
  const reviewList =
    await api.functional.ecommerceMall.customer.customers.me.reviews.index(
      customerConnection,
      {
        body: {},
      },
    );
  typia.assert(reviewList);
  // 3. Validate response structure
  TestValidator.equals(
    "has pagination metadata",
    reviewList.pagination !== undefined,
    true,
  );
  TestValidator.equals("has data array", reviewList.data !== undefined, true);
  // 4. Validate pagination metadata
  const pagination = reviewList.pagination;
  TestValidator.equals("current page is 1", pagination.current, 1);
  TestValidator.predicate("limit is positive", pagination.limit > 0);
  TestValidator.equals(
    "records count is 0 (no reviews)",
    pagination.records,
    0,
  );
  TestValidator.equals("pages count is 0", pagination.pages, 0);
  // 5. Validate data array is empty (new customer has no reviews)
  TestValidator.equals("data array is empty", reviewList.data.length, 0);
}
