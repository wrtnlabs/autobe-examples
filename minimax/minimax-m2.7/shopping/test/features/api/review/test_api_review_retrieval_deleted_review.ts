export async function test_api_review_retrieval_deleted_review(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register a customer account
  const customerConnection: api.IConnection = { host: connection.host };
  const customerAuth = await authorize_customer_join(customerConnection, {});
  typia.assert(customerAuth);
  // 2. Register a seller account (pending status)
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {});
  typia.assert(sellerAuth);
  // 3. Admin authenticates and approves the seller
  const adminConnection: api.IConnection = { host: connection.host };
  const adminAuth = await authorize_admin_join(adminConnection, {});
  typia.assert(adminAuth);
  // Approve seller
  const approvedSeller =
    await api.functional.ecommerceMall.admin.admin.sellers.approve(
      adminConnection,
      { sellerId: sellerAuth.id },
    );
  typia.assert(approvedSeller);
  // 4. Admin creates a product category
  const category =
    await generate_random_ecommerce_mall_admin_admin_categories_create(
      adminConnection,
      {},
    );
  typia.assert(category);
  // 5. Seller creates a product
  const product =
    await generate_random_ecommerce_mall_seller_sellers_me_products_create(
      sellerConnection,
      {
        body: {
          categoryId: category.id,
        },
      },
    );
  typia.assert(product);
  // 6. Customer adds product to cart and places an order
  // First, get the product with variants
  const variant = product.variants[0];
  if (!variant) {
    throw new Error("Product has no variants");
  }
  // Add to cart
  const cartItem =
    await generate_random_ecommerce_mall_customer_customers_me_cart_create(
      customerConnection,
      {
        body: {
          variantId: variant.id,
          quantity: 1,
        },
      },
    );
  typia.assert(cartItem);
  // Place order
  const order =
    await generate_random_ecommerce_mall_customer_customers_me_orders_create(
      customerConnection,
      {},
    );
  typia.assert(order);
  const orderItem = order.orderItems[0];
  if (!orderItem) {
    throw new Error("Order has no items");
  }
  // 7. Seller ships order items
  const shipment =
    await generate_random_ecommerce_mall_seller_sellers_me_orders_items_ship_create(
      sellerConnection,
      {
        params: { itemId: orderItem.id },
        body: {
          itemIds: [orderItem.id],
          carrier: "Test Carrier",
          trackingNumber: "TEST123456",
        },
      },
    );
  typia.assert(shipment);
  // 8. Customer confirms delivery
  const confirmedShipment =
    await api.functional.ecommerceMall.customer.customers.me.orders.shipments.confirm_delivery.confirmDelivery(
      customerConnection,
      {
        orderId: order.id,
        shipmentId: shipment.id,
      },
    );
  typia.assert(confirmedShipment);
  // 9. Customer creates a review for the delivered order item
  const review =
    await generate_random_ecommerce_mall_customer_customers_me_orders_items_review_create(
      customerConnection,
      {
        params: { itemId: orderItem.id },
        body: {
          rating: 5,
          content: "Great product!",
        },
      },
    );
  typia.assert(review);
  // 10. Customer deletes their own review (soft delete)
  await api.functional.ecommerceMall.customer.customers.me.reviews.erase(
    customerConnection,
    {
      reviewId: review.id,
    },
  );
  // 11. Test: Any user (guest) calls GET /ecommerceMall/products/{productId}/reviews/{reviewId}
  // This should return 404 Not Found
  const guestConnection: api.IConnection = { host: connection.host };
  await TestValidator.error("deleted review returns 404", async () => {
    await api.functional.ecommerceMall.products.reviews.getByProductidAndReviewid(
      guestConnection,
      {
        productId: product.id,
        reviewId: review.id,
      },
    );
  });
}
