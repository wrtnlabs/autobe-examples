/**
 * Test retrieving reviews when the customer has not written any reviews.
 *
 * Validates the empty state of a customer's review list. When a newly registered customer who has not yet written any reviews calls the GET /ecommerceMall/customer/customers/me/reviews endpoint, the system should return HTTP 200 with an empty data array and pagination metadata showing zero total count.
 *
 * This test ensures that:
 * - The endpoint returns HTTP 200 even when no reviews exist
 * - The response data array is empty
 * - Pagination metadata correctly reflects zero records
 * - The response structure is valid with complete pagination fields
 *
 * 1. Register a new customer account.
 * 2. Call GET /ecommerceMall/customer/customers/me/reviews without any reviews.
 * 3. Validate response returns empty data array with pagination showing total count of 0.
 */
export async function test_api_review_customer_list_reviews_empty(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register a new customer account
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  // 2. Call GET /ecommerceMall/customer/customers/me/reviews
  const reviewsResponse =
    await api.functional.ecommerceMall.customer.customers.me.reviews.search(
      customerConnection,
    );
  typia.assert(reviewsResponse);
  // 3. Validate response is valid with empty data array
  TestValidator.equals("data array should be empty", reviewsResponse.data, []);
  TestValidator.equals(
    "pagination total should be 0",
    reviewsResponse.pagination.records,
    0,
  );
  TestValidator.equals(
    "pagination pages should be 0",
    reviewsResponse.pagination.pages,
    0,
  );
}
