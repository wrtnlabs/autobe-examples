export async function test_api_admin_audit_log_retrieval_with_valid_id(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register and authenticate as administrator
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  // 2. Perform an admin action using simulation mode to get mock audit log data
  // since there is no list endpoint to retrieve actual audit log IDs
  const simulateConnection: api.IConnection = {
    host: connection.host,
    simulate: true,
  };
  const auditLogId = typia.random<string & tags.Format<"uuid">>();
  const auditLog =
    await api.functional.ecommerceMall.admin.admin.audit_logs.getByLogid(
      simulateConnection,
      {
        logId: auditLogId,
      },
    );
  typia.assert(auditLog);
}
