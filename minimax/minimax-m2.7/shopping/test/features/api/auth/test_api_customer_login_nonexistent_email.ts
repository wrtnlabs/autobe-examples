export async function test_api_customer_login_nonexistent_email(
  connection: api.IConnection,
): Promise<void> {
  // Test customer login with non-existent email.
  // Attempt to log in using an email address 'nonexistent_customer@example.com'
  // that has not been registered in the system.
  // Validate that the response returns a generic error message without revealing
  // whether the email exists. Verify that no JWT tokens are returned and no
  // session is created.
  // This validates the security requirement that the system must not reveal
  // whether an email address exists when login fails.
  // Attempt to login with non-existent email - should fail with generic error
  await TestValidator.error(
    "non-existent email login should fail",
    async () => {
      await api.functional.ecommerceMall.auth.customer.login(connection, {
        body: {
          email: "nonexistent_customer@example.com",
          password: "anypassword123",
          href: "https://example.com/login",
          referrer: "https://example.com",
        } satisfies IEcommerceMallCustomer.ILogin,
      });
    },
  );
  // Verify that no authorization token was set on the connection
  TestValidator.equals(
    "no authorization token after failed login",
    connection.headers?.Authorization,
    undefined,
  );
}
