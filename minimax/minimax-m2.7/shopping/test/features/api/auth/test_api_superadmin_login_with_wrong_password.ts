/**
 * Test the super administrator login failure when attempting to log in with an incorrect password.
 *
 * Validates the system's authentication security by ensuring that login attempts with incorrect passwords are rejected with generic error messages. This prevents account enumeration attacks where attackers could determine valid email addresses based on different error messages for "user not found" vs "wrong password".
 *
 * The test flow:
 * 1. Registers a new super administrator account with valid credentials
 * 2. Attempts to log in using the correct email but with a wrong password
 * 3. Verifies the login is rejected with a generic authentication error
 * 4. Confirms no tokens or sessions are returned
 *
 * This ensures the system treats both authentication failure scenarios identically for security purposes.
 */
export async function test_api_superadmin_login_with_wrong_password(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register a super administrator account to establish valid credentials
  const superAdminConnection: api.IConnection = { host: connection.host };
  const registered = await authorize_super_admin_join(superAdminConnection, {});
  typia.assert(registered);
  // Store the valid email from registration
  const validEmail = registered.email;
  // Generate a wrong password that is different from the registered password
  // The registered password was generated by the utility function
  const wrongPassword = `${RandomGenerator.alphaNumeric(12)}Wrong!`;
  // 2. Attempt to log in with correct email but wrong password
  const loginConnection: api.IConnection = { host: connection.host };
  // 3. Verify that login fails with authentication error (not successful)
  await TestValidator.error(
    "login with wrong password should fail",
    async () => {
      await api.functional.ecommerceMall.auth.superAdmin.login(
        loginConnection,
        {
          body: {
            email: validEmail,
            password: wrongPassword,
            href: typia.random<string & tags.Format<"uri">>(),
            referrer: typia.random<string & tags.Format<"uri">>(),
          } satisfies IEcommerceMallSuperAdmin.ILogin,
        },
      );
    },
  );
  // 4. Verify no Authorization header was set (no session created)
  TestValidator.equals(
    "no authorization token should be set after failed login",
    loginConnection.headers?.["Authorization"],
    undefined,
  );
}
