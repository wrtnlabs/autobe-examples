export async function test_api_customer_token_refresh_expired(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register a new customer to obtain valid tokens
  const customerConnection: api.IConnection = { host: connection.host };
  const authorized = await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  typia.assert(authorized);
  // 2. Attempt to refresh using an invalid/expired refresh token
  // Using a fake token that doesn't exist in the system
  await TestValidator.error(
    "expired refresh token should be rejected",
    async () => {
      const expiredConnection: api.IConnection = { host: connection.host };
      await api.functional.ecommerceMall.auth.customer.refresh(
        expiredConnection,
        {
          body: {
            refresh: "expired.invalid.token.format",
          } satisfies IEcommerceMallCustomer.IRefresh,
        },
      );
    },
  );
}
