export async function test_api_customer_login_wrong_password(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register a new customer account
  const customerConnection: api.IConnection = { host: connection.host };
  const authorized = await authorize_customer_join(customerConnection, {});
  // 2. Attempt to login with WRONG password
  const wrongPassword = "wrong_password_12345";
  const loginConnection: api.IConnection = { host: connection.host };
  // 3. Validate HTTP 401 error is returned
  await TestValidator.httpError(
    "login with wrong password returns 401",
    401,
    async () =>
      await api.functional.ecommerceMall.auth.customer.login(loginConnection, {
        body: {
          email: authorized.email,
          password: wrongPassword,
          href: "http://localhost:3000/login",
          referrer: "http://localhost:3000/",
        },
      }),
  );
  // 4. Validate the response does NOT contain tokens or customer data
  // The connection should not have Authorization header set after failed login
  TestValidator.equals(
    "no Authorization token after failed login",
    loginConnection.headers?.Authorization,
    undefined,
  );
}
