export async function test_api_superadmin_audit_log_not_found(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as super administrator
  const superAdminConnection: api.IConnection = { host: connection.host };
  await authorize_super_admin_join(superAdminConnection, {});
  // 2. Call GET with non-existent audit log ID (00000000-0000-0000-0000-000000000000)
  await TestValidator.httpError(
    "non-existent audit log returns 404",
    404,
    async () =>
      await api.functional.ecommerceMall.superAdmin.superAdmin.audit_logs.at(
        superAdminConnection,
        {
          auditLogId: "00000000-0000-0000-0000-000000000000" as string &
            tags.Format<"uuid">,
        },
      ),
  );
}
