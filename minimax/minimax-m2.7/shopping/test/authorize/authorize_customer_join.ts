/**
 * Register and authenticate a new customer for E2E testing.
 *
 * Creates a customer account with randomized valid credentials, mutates the connection with the auth token for subsequent authenticated requests. The customer must verify their email before gaining full access to shopping features.
 *
 * Handles the complete customer registration flow including account creation and JWT token issuance. Use this function to authenticate as a customer in test scenarios requiring customer-level permissions.
 */
export async function authorize_customer_join(
  connection: api.IConnection,
  props: {
    body?: DeepPartial<IEcommerceMallCustomer.IJoin>;
  },
): Promise<IEcommerceMallCustomer.IAuthorized> {
  const joinInput = {
    email: props.body?.email ?? typia.random<string & tags.Format<"email">>(),
    password: props.body?.password ?? RandomGenerator.alphaNumeric(16),
    name: props.body?.name ?? RandomGenerator.name(),
    href: props.body?.href ?? typia.random<string & tags.Format<"uri">>(),
    referrer:
      props.body?.referrer ?? typia.random<string & tags.Format<"uri">>(),
    ip: props.body?.ip,
  } satisfies IEcommerceMallCustomer.IJoin;
  return await api.functional.ecommerceMall.auth.customer.join(connection, {
    body: joinInput,
  });
}
