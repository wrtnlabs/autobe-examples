/**
 * Register and authenticate a new seller for E2E testing.
 *
 * Creates a seller account with randomized credentials, mutates the connection with the auth token.
 * The seller account starts with 'pending' approval status and requires administrator approval
 * before the seller can list products or access seller-specific endpoints.
 *
 * **Note**: Email verification may be required after registration depending on server configuration.
 */
export async function authorize_seller_join(
  connection: api.IConnection,
  props: {
    body?: DeepPartial<IEcommerceMallSeller.IJoin>;
  },
): Promise<IEcommerceMallSeller.IAuthorized> {
  const joinInput = {
    email: props.body?.email ?? typia.random<string & tags.Format<"email">>(),
    password: props.body?.password ?? RandomGenerator.alphaNumeric(16),
    href: props.body?.href ?? typia.random<string & tags.Format<"uri">>(),
    referrer:
      props.body?.referrer ?? typia.random<string & tags.Format<"uri">>(),
    ip: props.body?.ip,
  } satisfies IEcommerceMallSeller.IJoin;
  return await api.functional.ecommerceMall.auth.seller.join(connection, {
    body: joinInput,
  });
}
