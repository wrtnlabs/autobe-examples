import { tags } from "typia";

import { IAuthorizationToken } from "./IAuthorizationToken";
import { IEcommerceMallSellerProfile } from "./IEcommerceMallSellerProfile";

export namespace IEcommerceMallSeller {
  /**
   * Seller registration request body containing email address, password credentials, and session context for new seller account creation. The email serves as the unique identifier for login authentication. The password is transmitted in plain text and securely hashed by the backend before storage. Session context fields (href and referrer) are required for proper session management and redirect handling during the registration flow.
   */
  export type IJoin = {
    /**
     * Unique email address for seller login and account identification.
     *
     * @x-autobe-database-schema-property email
     * @x-autobe-specification Direct mapping from ecommerce_mall_sellers.email. Must be unique across all sellers. Validated for email format.
     */
    email: string & tags.Format<"email">;

    /**
     * User's authentication password (plain text, hashed server-side before storage).
     *
     * @x-autobe-database-schema-property password_hash
     * @x-autobe-specification Plain text password from request body is hashed using bcrypt before storing in ecommerce_mall_sellers.password_hash. The hash includes salt automatically generated by bcrypt.
     */
    password: string & tags.Format<"password">;

    /**
     * Current page URL from which the registration request was initiated.
     *
     * @x-autobe-specification Session context field stored in ecommerce_mall_seller_sessions.href for security audit and redirect handling after login/registration. Not a column in sellers table.
     */
    href: string & tags.Format<"uri">;

    /**
     * URL of the page that referred the user to the registration page.
     *
     * @x-autobe-specification Session context field stored in ecommerce_mall_seller_sessions.referrer for security audit and tracking user navigation. Not a column in sellers table.
     */
    referrer: string & tags.Format<"uri">;
  };

  /**
   * Request body for refreshing seller authentication tokens. Contains the current refresh token to exchange for new access and refresh token pair.
   */
  export type IRefresh = {
    /**
     * The current refresh token to exchange for new authentication tokens.
     *
     * @x-autobe-specification Client-provided JWT refresh token. This is NOT a database column - it is validated against stored sessions in ecommerce_mall_seller_sessions table. The token contains embedded claims that allow server-side validation without direct DB lookup for initial verification. Downstream service: 1) Validates JWT signature and expiration, 2) Looks up session by token in database, 3) Verifies session belongs to active seller, 4) Issues new token pair on success.
     */
    refresh: string;
  };

  /**
   * Authorization response containing JWT access and refresh tokens along with authenticated seller account information. This DTO is returned by the seller login, registration, and token refresh endpoints to establish authenticated sessions.
   */
  export type IAuthorized = {
    /**
     * Authorization token.
     *
     * @x-autobe-specification Authorization token comes from the session table.
     */
    token: IAuthorizationToken;

    /**
     * Unique identifier for the seller account, used for API references.
     *
     * @x-autobe-database-schema-property id
     * @x-autobe-specification Direct mapping from ecommerce_mall_sellers.id. UUID format, primary key of the sellers table.
     */
    id: string & tags.Format<"uuid">;

    /**
     * Unique email address serving as the seller's login identifier and primary contact method.
     *
     * @x-autobe-database-schema-property email
     * @x-autobe-specification Direct mapping from ecommerce_mall_sellers.email. Unique constraint enforced. Format: valid email address.
     */
    email: string & tags.Format<"email">;

    /**
     * Current approval status of the seller account indicating registration state.
     *
     * @x-autobe-database-schema-property approval_status
     * @x-autobe-specification Direct mapping from ecommerce_mall_sellers.approval_status. Enum values: 'pending' (awaiting admin approval, limited access), 'approved' (full selling access), 'rejected' (can view reason and resubmit).
     */
    approval_status: string;

    /**
     * Explanation provided by administrators for rejecting the seller registration. Only populated when approval_status is 'rejected'.
     *
     * @x-autobe-database-schema-property rejection_reason
     * @x-autobe-specification Direct mapping from ecommerce_mall_sellers.rejection_reason. Nullable - only populated when approval_status equals 'rejected'. Contains the admin-provided reason for rejection.
     */
    rejection_reason?: null | string | undefined;

    /**
     * Timestamp when the seller registration was rejected by an administrator. Only populated when approval_status is 'rejected'.
     *
     * @x-autobe-database-schema-property rejected_at
     * @x-autobe-specification Direct mapping from ecommerce_mall_sellers.rejected_at. Nullable - only populated when approval_status equals 'rejected'. UTC timestamp in ISO 8601 format.
     */
    rejected_at?: null | (string & tags.Format<"date-time">) | undefined;

    /**
     * Timestamp when the seller account was originally created.
     *
     * @x-autobe-database-schema-property created_at
     * @x-autobe-specification Direct mapping from ecommerce_mall_sellers.created_at. UTC timestamp in ISO 8601 format.
     */
    created_at: string & tags.Format<"date-time">;

    /**
     * Timestamp of the most recent update to the seller account information.
     *
     * @x-autobe-database-schema-property updated_at
     * @x-autobe-specification Direct mapping from ecommerce_mall_sellers.updated_at. Updated automatically on any seller record modification. UTC timestamp in ISO 8601 format.
     */
    updated_at: string & tags.Format<"date-time">;

    /**
     * Soft deletion timestamp indicating the account has been deactivated. Null means the account is active.
     *
     * @x-autobe-database-schema-property deleted_at
     * @x-autobe-specification Direct mapping from ecommerce_mall_sellers.deleted_at. Nullable - null indicates active account, populated timestamp indicates soft-deleted account.
     */
    deleted_at?: null | (string & tags.Format<"date-time">) | undefined;
  };

  /**
   * Seller login credentials for authentication with session context tracking. Contains email and password for credential verification, plus HTTP context fields (href, referrer, ip) for session security and audit logging. The password is transmitted in plain text and hashed server-side before comparison.
   */
  export type ILogin = {
    /**
     * Seller's email address used for account identification and login credential verification.
     *
     * @x-autobe-specification Validated against ecommerce_mall_sellers.email via lookup. If not found, return generic 'invalid credentials' error (no account enumeration). Used to identify the seller account for authentication.
     */
    email: string & tags.Format<"email">;

    /**
     * Seller's password in plain text for authentication. Server will hash with bcrypt before comparing against stored password_hash.
     *
     * @x-autobe-specification Plain text password compared against ecommerce_mall_sellers.password_hash via bcrypt hash comparison. Server hashes input with bcrypt and compares with stored hash. Never log or store the plain text password.
     */
    password: string;

    /**
     * Current URL of the client browser or application initiating the login request.
     *
     * @x-autobe-specification Session context metadata for ecommerce_mall_seller_sessions.href. Captures the originating URL for security audit logging. Stored with the session record upon successful login.
     */
    href: string & tags.Format<"uri">;

    /**
     * Referrer URL indicating the previous page the client was on before navigating to the login page.
     *
     * @x-autobe-specification Session context metadata for ecommerce_mall_seller_sessions.referrer. Captures navigation context for security audit. Stored with the session record upon successful login.
     */
    referrer: string & tags.Format<"uri">;

    /**
     * IPv4 address of the client initiating the login request. Optional due to SSR limitations - server will use fallback IP if not provided.
     *
     * @x-autobe-specification Session context metadata for ecommerce_mall_seller_sessions.ip. Optional because in SSR (Server Side Rendering) the client cannot know its own IP; server captures it as fallback (body.ip ?? serverIp). Stored with the session record upon successful login.
     */
    ip?: (string & tags.Format<"ipv4">) | undefined;
  };

  /**
   * Request parameters for searching and filtering sellers on the platform.
   *
   * This type is used as the request body for the admin seller list endpoint, allowing administrators to filter sellers by various criteria including approval status, email search, seller profile name, and registration date ranges. All fields are optional to support flexible querying with partial filters.
   */
  export type IRequest = {
    /**
     * Partial email search to filter sellers by email address.
     *
     * @x-autobe-specification LIKE query pattern applied to sellers.email column. Use '%' wildcards for partial matching. Example: 'seller@' matches 'seller@example.com'.
     */
    search?: string | undefined;

    /**
     * Partial seller profile name search for filtering by shop name.
     *
     * @x-autobe-specification LIKE query on seller profile name via JOIN with ecommerce_mall_seller_profiles.name column. Filters sellers whose shop name contains the search term.
     */
    sellerName?: string | undefined;

    /**
     * Filter sellers by their approval status. Can be a single value or array for multiple statuses.
     *
     * @x-autobe-specification Exact match filter on sellers.approval_status column. Accepts single value or array of values (pending, approved, rejected).
     */
    approval_status?: string | string[] | undefined;

    /**
     * Filter sellers created on or after this date (inclusive).
     *
     * @x-autobe-specification Lower boundary for created_at date range filter. Sellers created on or after this datetime are included. Use ISO 8601 format.
     */
    created_at_from?: (string & tags.Format<"date-time">) | undefined;

    /**
     * Filter sellers created on or before this date (inclusive).
     *
     * @x-autobe-specification Upper boundary for created_at date range filter. Sellers created on or before this datetime are included. Use ISO 8601 format.
     */
    created_at_to?: (string & tags.Format<"date-time">) | undefined;

    /**
     * Page number for pagination (1-indexed).
     *
     * @x-autobe-specification 1-indexed page number for pagination. Default value is 1. Calculates offset as (page - 1) * limit for database query.
     */
    page?: (number & tags.Type<"int32"> & tags.Minimum<1>) | undefined;

    /**
     * Number of items per page. Default: 20, Maximum: 100.
     *
     * @x-autobe-specification Number of records per page. Default: 20, Maximum: 100. Used with page parameter to calculate OFFSET for database query.
     */
    limit?:
      | (number & tags.Type<"int32"> & tags.Minimum<1> & tags.Maximum<100>)
      | undefined;
  };

  /**
   * Lightweight seller entity for list displays. Contains essential seller information including approval status and public shop profile data. Optimized for admin seller listing operations with minimal payload size.
   */
  export type ISummary = {
    /**
     * @x-autobe-database-schema-property id
     */
    id: string & tags.Format<"uuid">;
    /**
     * @x-autobe-database-schema-property email
     */
    email: string & tags.Format<"email">;
    /**
     * @x-autobe-database-schema-property approval_status
     */
    approval_status: string;
    /**
     * @x-autobe-database-schema-property created_at
     */
    created_at: string & tags.Format<"date-time">;
    profile: IEcommerceMallSellerProfile;
  };

  /**
   * Seller entity with public shop profile information. Combines seller account attributes (id, created_at, approval_status) with shop profile data (name, description, logo_uri) for display on public seller pages and admin views.
   */
  export type IInvert = {
    /**
     * Unique identifier of the seller account.
     *
     * @x-autobe-database-schema-property id
     * @x-autobe-specification Direct mapping from ecommerce_mall_sellers.id. UUID primary key.
     */
    id: string & tags.Format<"uuid">;

    /**
     * Timestamp when the seller account was created.
     *
     * @x-autobe-database-schema-property created_at
     * @x-autobe-specification Direct mapping from ecommerce_mall_sellers.created_at. Timestamp when the seller registered.
     */
    created_at: string & tags.Format<"date-time">;

    /**
     * Current approval status of the seller's registration.
     *
     * @x-autobe-database-schema-property approval_status
     * @x-autobe-specification Direct mapping from ecommerce_mall_sellers.approval_status. Values: pending, approved, rejected.
     */
    approval_status: string;

    /**
     * Public shop profile information including shop name, description, and logo.
     *
     * @x-autobe-specification Join ecommerce_mall_seller_profiles on seller_id. Flattened fields: profile.name maps to shop_name, profile.description maps to ecommerce_mall_seller_profiles.description, profile.logo_uri maps to ecommerce_mall_seller_profiles.logo_uri (nullable).
     */
    profile: {
      name: string;
      description: string;
      logo_uri: string | null;
    };
  };
}
