/**
 * The join operation establishes a guest session for unauthenticated visitors. Guests are identified by their device fingerprint which is captured during session creation. The system creates a lightweight guest account linked to the device fingerprint and generates JWT tokens for session continuity.
 *
 * This operation is used when an unauthenticated visitor first accesses the platform. The fingerprint allows the system to track guest browsing activity across sessions without requiring registration. The returned access token is short-lived (15 minutes) and the refresh token enables session renewal.
 *
 * The guest account is stored in the ecommerce_mall_guests table with the fingerprint field serving as the unique device identifier. The session is tracked in ecommerce_mall_guest_sessions with IP address, current URL (href), and HTTP referrer for navigation context. Sessions expire after a configurable duration and are invalidated on explicit logout or expiration.
 *
 * Security considerations include validating fingerprint format, rate limiting session creation requests, and ensuring session tokens are transmitted over secure channels (HTTPS).
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Request body containing guest device fingerprint for session establishment. The fingerprint identifies the anonymous visitor device and enables session continuity without authentication.
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor guest
 * @x-autobe-specification Implementation steps:
 * 1. Validate fingerprint is provided and non-empty
 * 2. Generate UUID for new guest ID
 * 3. Capture IP address and user agent from request headers
 * 4. Create new guest record in ecommerce_mall_guests table with fingerprint, ip_address, user_agent
 * 5. Create new session record in ecommerce_mall_guest_sessions table linked to guest
 * 6. Generate JWT access token (short-lived, e.g., 15 minutes) and refresh token (long-lived, e.g., 7 days)
 * 7. Return access token and refresh token to client
 *
 * Edge cases:
 * - If fingerprint already exists for active guest, reuse existing guest ID
 * - Handle concurrent session creation gracefully
 * - Ensure expired_at is set correctly for refresh token expiry
 * @path /ecommerceMall/auth/guest/join
 * @accessor api.functional.ecommerceMall.auth.guest.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
