/**
 * Creates a new guest session for unauthenticated visitors.
 *
 * This endpoint establishes a guest account identified by device fingerprint. When an unauthenticated visitor accesses the platform, the system creates a guest record in the ecommerce_mall_guests table using the provided fingerprint string, capturing device information (IP address, user agent) for security tracking and analytics. A session token is generated and stored in ecommerce_mall_guest_sessions with configurable expiration duration.
 *
 * The response returns JWT access and refresh tokens that the client stores and includes in subsequent requests via Authorization header. The access token is short-lived (e.g., 1 hour) while the refresh token has longer validity (e.g., 7 days), allowing session continuity without re-authentication.
 *
 * Guest sessions track browsing context including current page URL (href) and referrer for understanding navigation patterns. The last_active_at timestamp on the guest record updates on each session interaction.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Request body containing device fingerprint for guest identification. The fingerprint is typically generated client-side using browser characteristics and used to recognize returning guests across sessions.
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor guest
 * @x-autobe-specification 1. Validate fingerprint from request body exists and
 *   is non-empty. 2. Extract IP address from request headers (x-forwarded-for
 *   or remote address) and user agent from headers. 3. Create new guest record
 *   in ecommerce_mall_guests table with fingerprint, ip_address, user_agent,
 *   created_at, updated_at. 4. Create new session in
 *   ecommerce_mall_guest_sessions table with generated UUID, guest_id
 *   reference, IP, href, referrer, current timestamp for created_at, and
 *   expiration timestamp (configurable, e.g., 24 hours). 5. Generate JWT access
 *   token containing guest_id, session_id, exp claim. 6. Generate refresh token
 *   with longer expiration (e.g., 7 days). 7. Return access token and refresh
 *   token in IEcommerceMallGuest.IAuthorized response.
 *
 * Error handling:
 * - 400 if fingerprint is missing or empty
 * - 500 on database errors
 * @path /ecommerceMall/auth/guest/join
 * @accessor api.functional.ecommerceMall.auth.guest.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
