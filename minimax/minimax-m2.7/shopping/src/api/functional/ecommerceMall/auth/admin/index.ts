/**
 * Authenticates an administrator using their email and password credentials. Validates the provided credentials against the stored password hash in the ecommerce_mall_admins table. Upon successful authentication, returns JWT access and refresh tokens along with token metadata. The session is recorded in ecommerce_mall_admin_sessions for security auditing, capturing the client IP address and current page URL.
 *
 * This operation requires the email and password fields from the admin account record. The password_hash uses bcrypt hashing for secure storage.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Request body containing administrator email address and password for credential validation.
 * @x-autobe-authorization-type login
 * @x-autobe-authorization-actor admin
 * @x-autobe-specification Login: Validate email exists in ecommerce_mall_admins table, verify password_hash matches using bcrypt, check deleted_at is null (account not soft-deleted). Generate JWT access token (short-lived) and refresh token (long-lived). Store session in ecommerce_mall_admin_sessions with IP and href. Return tokens to client.
 * @path /ecommerceMall/auth/admin/login
 * @accessor api.functional.ecommerceMall.auth.admin.login
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function login(
  connection: IConnection,
  props: login.Props,
): Promise<login.Response> {
  const output: login.Response =
    true === connection.simulate
      ? login.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...login.METADATA,
            path: login.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
export namespace login {
  export type Props = {
    /**
     * Request body containing administrator email address and password for credential validation.
     */
    body: IEcommerceMallAdmin.ILogin;
  };
  export type Body = IEcommerceMallAdmin.ILogin;
  export type Response = IEcommerceMallAdmin.IAuthorized;

  export const METADATA = {
    method: "POST",
    path: "/ecommerceMall/auth/admin/login",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/ecommerceMall/auth/admin/login";
  export const random = (): IEcommerceMallAdmin.IAuthorized =>
    typia.random<IEcommerceMallAdmin.IAuthorized>();
  export const simulate = (
    connection: IConnection,
    props: login.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: login.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

