/**
 * Creates a new administrator account for platform management.
 *
 * This endpoint handles the registration of new administrators within the ecommerce mall platform. The operation accepts email and password credentials which are validated for format compliance and uniqueness. Passwords are securely hashed using bcrypt before storage in the ecommerce_mall_admins table.
 *
 * Upon successful registration, the system generates JWT access and refresh tokens stored in the ecommerce_mall_admin_sessions table. The session record captures client context including IP address and HTTP referrer for security auditing purposes. The tokens enable subsequent authenticated requests to administrative endpoints.
 *
 * The registration process creates administrative accounts that can access platform management features including seller approvals, category management, product oversight, and user account administration as defined by the admin role permissions.
 *
 * Security considerations include email uniqueness enforcement, password complexity validation, secure hashing with bcrypt, and comprehensive session tracking for audit purposes. The soft delete support through deleted_at field allows account deactivation without permanent data loss.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Administrator registration credentials including email and password for new account creation
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor admin
 * @x-autobe-specification 1. Validate email format and password strength requirements
 * 2. Check if email already exists in ecommerce_mall_admins
 * 3. Generate bcrypt hash from password
 * 4. Create new admin record with hashed password
 * 5. Generate JWT access token and refresh token
 * 6. Create session record in ecommerce_mall_admin_sessions with IP and href
 * 7. Return authorized response with tokens
 * @path /ecommerceMall/auth/admin/join
 * @accessor api.functional.ecommerceMall.auth.admin.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
