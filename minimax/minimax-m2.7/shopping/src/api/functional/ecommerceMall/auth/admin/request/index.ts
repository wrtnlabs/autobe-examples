import { IEcommerceMallAdmin } from "../../../../../structures/IEcommerceMallAdmin";

/**
 * Submits a request to become an administrator on the platform. This operation allows existing customers or sellers to request administrative privileges by providing a reason for their request and specifying the requested privilege grade (admin or super_admin). The request is reviewed by super administrators. Upon successful submission, returns JWT access and refresh tokens for the requesting actor.
 *
 * Request body must include the actor_type discriminator ('customer' or 'seller') to identify the requester, the requested_grade indicating privilege level, and a text reason explaining why administrative access is needed.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Request body containing actor_type discriminator, requested_grade, and reason for admin privilege request.
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor admin
 * @x-autobe-specification Join (admin request submission): Validate email format, check actor_type is 'customer' or 'seller', validate requested_grade is 'admin' or 'super_admin', store request with status 'pending'. Generate email notification to super admins. Return authorized tokens for the requesting actor (customer or seller) to track their request status.
 * @path /ecommerceMall/auth/admin/request
 * @accessor api.functional.ecommerceMall.auth.admin.request.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
export namespace join {
  export type Props = {
    /**
     * Request body containing actor_type discriminator, requested_grade, and reason for admin privilege request.
     */
    body: IEcommerceMallAdmin.IJoin;
  };
  export type Body = IEcommerceMallAdmin.IJoin;
  export type Response = IEcommerceMallAdmin.IAuthorized;

  export const METADATA = {
    method: "POST",
    path: "/ecommerceMall/auth/admin/request",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/ecommerceMall/auth/admin/request";
  export const random = (): IEcommerceMallAdmin.IAuthorized =>
    typia.random<IEcommerceMallAdmin.IAuthorized>();
  export const simulate = (
    connection: IConnection,
    props: join.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: join.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
