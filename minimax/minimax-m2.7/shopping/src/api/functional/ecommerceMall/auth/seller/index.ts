/**
 * Seller registration endpoint for new sellers to create an account on the ecommerce mall platform.
 *
 * This operation creates a new seller account with email and password credentials. The seller record is inserted into the ecommerce_mall_sellers table with approval_status set to 'pending'. An email verification token is generated and stored in ecommerce_mall_seller_email_verifications for email confirmation. A new session is created in ecommerce_mall_seller_sessions with JWT access and refresh tokens for immediate authentication after registration.
 *
 * The seller must wait for administrator approval (approval_status = 'approved') before listing products or managing orders. If rejected, the rejection_reason and rejected_at fields in ecommerce_mall_sellers will be populated by an administrator.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Registration request containing seller email address and password for new account creation.
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor seller
 * @x-autobe-specification Implementation steps:
 * 1. Validate email format and uniqueness in ecommerce_mall_sellers.email
 * 2. Hash password using bcrypt with appropriate salt rounds
 * 3. Insert new seller record with approval_status = 'pending'
 * 4. Generate email verification token, store in ecommerce_mall_seller_email_verifications
 * 5. Create initial seller session with JWT access and refresh tokens
 * 6. Send verification email (external integration)
 * 7. Return IAuthorized response with tokens
 *
 * Error handling:
 * - Duplicate email: Return 409 Conflict
 * - Invalid email format: Return 400 Bad Request
 * - Weak password: Return 400 Bad Request with validation details
 * @path /ecommerceMall/auth/seller/join
 * @accessor api.functional.ecommerceMall.auth.seller.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
