/**
 * Registers a new seller account on the platform.
 *
 * This endpoint creates a new seller account with email and password credentials. The registration initiates a pending approval workflow where administrators must approve the seller before they can list products. An email verification token is generated and sent to the seller's email address for account confirmation.
 *
 * Implementation details:
 * The operation validates the email format, checks for email uniqueness against the ecommerce_mall_sellers.email field, hashes the password using bcrypt, and creates a new seller record with approval_status set to 'pending'. A verification token is stored in ecommerce_mall_seller_email_verifications with expiration time. The response returns authorized tokens as null since email verification is required before the account can be used for login.
 *
 * Business context:
 * New sellers cannot immediately list products or access seller-specific endpoints. They must wait for administrator approval. The rejection_reason field in ecommerce_mall_sellers will be populated if an administrator rejects the registration. Sellers can re-register using the reregister endpoint if initially rejected.
 *
 * Security considerations:
 * Passwords are never stored in plaintext; only bcrypt hashes are persisted. The verification token is cryptographically random and single-use. Tokens expire after a configurable duration.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Registration request containing seller email address and password.
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor seller
 * @x-autobe-specification Service logic:
 * 1. Validate email format and uniqueness (check ecommerce_mall_sellers.email uniqueness)
 * 2. Validate password strength (minimum 8 characters, hash with bcrypt)
 * 3. Create new seller record with approval_status = 'pending'
 * 4. Generate email verification token and store in ecommerce_mall_seller_email_verifications
 * 5. Return IAuthorized response with null tokens (email verification required before login)
 *
 * Edge cases:
 * - Duplicate email: return 409 Conflict
 * - Invalid email format: return 400 Bad Request
 * - Weak password: return 400 Bad Request
 * @path /ecommerceMall/auth/seller/join
 * @accessor api.functional.ecommerceMall.auth.seller.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
