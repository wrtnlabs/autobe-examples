import { IEcommerceMallPaymentWebhook } from "../../../../structures/IEcommerceMallPaymentWebhook";

/**
 * Receive payment status notifications from the external payment gateway.
 *
 * This endpoint receives asynchronous payment notifications from the integrated payment gateway. When a payment is processed, the gateway sends a webhook to this endpoint containing the payment result, transaction ID, and associated order reference. The system validates the webhook payload, verifies the signature, and processes the payment status update.
 *
 * Webhook notifications can indicate successful payments, failed payments, or refunds processed by the gateway. Valid payloads trigger appropriate internal actions including order status updates and inventory adjustments. The endpoint returns an acknowledgment response to confirm receipt.
 *
 * @param props.connection
 * @param props.body Payment gateway webhook payload containing transaction details and status
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor null
 * @x-autobe-specification Receive and process webhook notifications from the external payment gateway.
 *
 * 1. Extract the raw request body from the webhook POST request
 * 2. Retrieve the webhook signature from headers (gateway-specific header like X-Webhook-Signature)
 * 3. Validate webhook authenticity using the configured webhook secret and signature verification algorithm
 * 4. If validation fails, return 401 Unauthorized without processing
 * 5. Parse the validated webhook payload
 * 6. Extract: transaction_id, order_reference, status, amount, currency, timestamp
 * 7. Look up the order by the order_reference (order number)
 * 8. If order not found, return 404 Not Found
 * 9. Based on webhook status:
 *    - 'success'/'captured': Update order payment status to confirmed
 *    - 'failed'/'declined': Update order payment status to failed
 *    - 'refunded': Update order payment status to refunded, restore inventory
 * 10. Log the webhook event with complete context for audit purposes
 * 11. Return 200 OK with acknowledgment body
 *
 * Edge cases:
 * - Duplicate webhook (same transaction_id already processed): Return 200 OK (idempotent)
 * - Invalid payload structure: Return 400 Bad Request
 * - Order already in terminal state (completed/cancelled): Process but log warning
 * - Webhook for non-existent order: Log and return 404
 * @path /ecommerceMall/payments/webhook
 * @accessor api.functional.ecommerceMall.payments.webhook.receive
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function receive(
  connection: IConnection,
  props: receive.Props,
): Promise<void> {
  return true === connection.simulate
    ? receive.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...receive.METADATA,
          path: receive.path(),
          status: null,
        },
        props.body,
      );
}
export namespace receive {
  export type Props = {
    /**
     * Payment gateway webhook payload containing transaction details and status
     */
    body: IEcommerceMallPaymentWebhook.IRequest;
  };
  export type Body = IEcommerceMallPaymentWebhook.IRequest;

  export const METADATA = {
    method: "POST",
    path: "/ecommerceMall/payments/webhook",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/ecommerceMall/payments/webhook";
  export const random = (): void => typia.random<void>();
  export const simulate = (
    connection: IConnection,
    props: receive.Props,
  ): void => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: receive.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
