import {
  HttpError,
  IConnection,
  NestiaSimulator,
  PlainFetcher,
} from "@nestia/fetcher";
import typia, { tags } from "typia";

import { IEcommerceMallReview } from "../../../../structures/IEcommerceMallReview";

/**
 * Retrieves the average rating and review count for a specific product.
 *
 * This endpoint returns the calculated average rating value and total number of reviews for the product identified by the path parameter. Only non-deleted reviews are included in the calculation. If a product has no reviews, the average rating is 0 and the count is 0.
 *
 * **Rating Calculation**: The average rating is computed by summing all rating values from active (non-deleted) reviews and dividing by the count of those reviews. This ensures the displayed rating always reflects current genuine customer feedback.
 *
 * **Use Cases**: This endpoint is called by the product listing page to display rating stars and review counts, and by the product detail page to show aggregate customer satisfaction metrics.
 *
 * @param props.connection
 * @param props.productId Unique identifier of the product in UUID format.
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor null
 * @x-autobe-specification Query the ecommerce_mall_products table to verify the product exists. If the product does not exist, return a 404 error with message "Product not found".
 *
 * Query the ecommerce_mall_reviews table filtered by ecommerce_mall_product_id matching the path parameter and where deleted_at is NULL (only active reviews).
 *
 * Calculate the average rating: SUM(rating) / COUNT(*) for all matching non-deleted reviews.
 *
 * Count the total number of non-deleted reviews for the product.
 *
 * Return a response object containing:
 * - averageRating: The calculated average as a decimal number rounded to one decimal place (e.g., 4.5)
 * - reviewCount: The total count of non-deleted reviews as an integer
 *
 * If no reviews exist for the product, return { averageRating: 0, reviewCount: 0 }.
 * @path /ecommerceMall/products/:productId/rating
 * @accessor api.functional.ecommerceMall.products.rating.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique identifier of the product in UUID format.
     */
    productId: string & tags.Format<"uuid">;
  };
  export type Response = IEcommerceMallReview;

  export const METADATA = {
    method: "GET",
    path: "/ecommerceMall/products/:productId/rating",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/ecommerceMall/products/${encodeURIComponent(props.productId ?? "null")}/rating`;
  export const random = (): IEcommerceMallReview =>
    typia.random<IEcommerceMallReview>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("productId")(() => typia.assert(props.productId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
