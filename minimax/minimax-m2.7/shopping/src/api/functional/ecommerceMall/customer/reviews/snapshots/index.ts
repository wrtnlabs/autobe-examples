/**
 * Retrieve the modification history of a specific product review.
 *
 * This operation lists all historical snapshots for a review, showing how the rating and content changed over time. Each snapshot captures the previous state before an edit was made.
 *
 * Access is restricted to the customer who wrote the review or administrators for oversight purposes. The snapshots are displayed in chronological order from oldest to newest, allowing consumers to see the complete edit history.
 *
 * Review snapshots are immutable records preserved for dispute resolution, showing exactly what content existed at each point in time.
 *
 * @param props.connection
 * @param props.reviewId Unique identifier of the review whose snapshots to retrieve (global scope)
 * @param props.body Pagination parameters for retrieving review snapshots
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor customer
 * @x-autobe-specification Query ecommerce_mall_review_snapshots table filtering by reviewId.
 *
 * Join with ecommerce_mall_reviews to verify the review exists and belongs to the requesting customer.
 *
 * Apply authorization: only allow access if the requesting user is the review author (via review.customerId match) or has admin privileges.
 *
 * Order results by snapshot timestamp ascending (oldest first) to show chronological edit history.
 *
 * Include pagination with configurable page sizes.
 *
 * Return snapshot fields: previousRating, previousContent, newRating, newContent, createdAt.
 *
 * Handle case where review does not exist: return 404 error.
 *
 * Handle unauthorized access: return 403 error.
 * @path /ecommerceMall/customer/reviews/:reviewId/snapshots
 * @accessor api.functional.ecommerceMall.customer.reviews.snapshots.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
