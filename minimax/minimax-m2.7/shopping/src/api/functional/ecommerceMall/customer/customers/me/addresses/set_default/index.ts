/**
 * Designates a specific shipping address as the customer's default shipping address.
 *
 * When a customer selects a shipping address and marks it as their default, this endpoint updates the address record and automatically removes the default designation from any previously default address. The default address is pre-selected during checkout for faster order processing.
 *
 * **Operation Behavior:**
 * - Validates that the specified address belongs to the authenticated customer
 * - Validates that the address exists and is not soft-deleted
 * - Clears the `is_default` flag on the customer's current default address (if any)
 * - Sets `is_default` to `true` on the specified address
 * - Updates the `updated_at` timestamp on both affected addresses
 *
 * **Error Handling:**
 * - Returns 404 if the address does not exist or is soft-deleted
 * - Returns 403 if the address belongs to a different customer
 * - Returns 400 if the addressId format is invalid
 *
 * **Relationship:**
 * - Addresses belong to customers (ecommerce_mall_customer_id)
 * - Only one address can be default per customer at any time
 *
 * @param props.connection
 * @param props.addressId Unique identifier of the shipping address to set as default.
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor customer
 * @x-autobe-specification 1. Extract `addressId` from path parameter and
 *   `customerId` from authenticated session. 2. Query the database to verify
 *   the address exists, is not soft-deleted (deleted_at IS NULL), and belongs
 *   to the authenticated customer. 3. If address not found or soft-deleted:
 *   throw NOT_FOUND error. 4. If address belongs to different customer: throw
 *   FORBIDDEN error. 5. Begin database transaction: a. UPDATE
 *   ecommerce_mall_shipping_addresses SET is_default = false, updated_at =
 *   NOW() WHERE ecommerce_mall_customer_id = customerId AND is_default = true
 *   AND deleted_at IS NULL; b. UPDATE ecommerce_mall_shipping_addresses SET
 *   is_default = true, updated_at = NOW() WHERE id = addressId; 6. Commit
 *   transaction. 7. Fetch and return the updated address record.
 * @path /ecommerceMall/customer/customers/me/addresses/:addressId/set-default
 * @accessor api.functional.ecommerceMall.customer.customers.me.addresses.set_default.setDefault
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
