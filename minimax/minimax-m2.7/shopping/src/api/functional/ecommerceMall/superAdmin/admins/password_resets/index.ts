import { IEcommerceMallAdminPasswordReset } from "../../../../../structures/IEcommerceMallAdminPasswordReset";
import { IPageIEcommerceMallAdminPasswordReset } from "../../../../../structures/IPageIEcommerceMallAdminPasswordReset";

/**
 * Retrieve a filtered and paginated list of password reset records for a specific administrator account.
 *
 * This operation allows authorized administrators to view the password reset history for any admin account. The response includes details about each reset request such as token status (used/unused), expiration timestamp, usage timestamp, and creation time.
 *
 * Only accessible to authenticated administrators with appropriate permissions. Results are sorted by creation date in descending order (newest first) with pagination support.
 *
 * The adminId path parameter specifies which administrator's password reset records to retrieve.
 *
 * @param props.connection
 * @param props.adminId Unique identifier of the administrator whose password reset records to retrieve (global scope)
 * @param props.body Search criteria and pagination parameters for filtering password reset records
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor superAdmin
 * @x-autobe-specification Query the ecommerce_mall_admin_password_resets table filtered by the adminId path parameter.
 *
 * Apply search filters from request body:
 * - Filter by used_at status (null = unused, not null = used) if provided
 * - Filter by created_at date range if provided (from/to timestamps)
 *
 * Join with ecommerce_mall_admins table to validate adminId exists and get admin email for reference.
 *
 * Sort results by created_at descending (newest first).
 *
 * Return paginated results with configurable page size and cursor-based pagination.
 *
 * Include in response: reset id, token presence indicator (not the actual token hash for security), expires_at, used_at, created_at.
 *
 * Verify requesting admin has permission to view password reset records.
 * @path /ecommerceMall/superAdmin/admins/:adminId/password-resets
 * @accessor api.functional.ecommerceMall.superAdmin.admins.password_resets.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Unique identifier of the administrator whose password reset records to retrieve (global scope)
     */
    adminId: string & tags.Format<"uuid">;

    /**
     * Search criteria and pagination parameters for filtering password reset records
     */
    body: IEcommerceMallAdminPasswordReset.IRequest;
  };
  export type Body = IEcommerceMallAdminPasswordReset.IRequest;
  export type Response = IPageIEcommerceMallAdminPasswordReset;

  export const METADATA = {
    method: "PATCH",
    path: "/ecommerceMall/superAdmin/admins/:adminId/password-resets",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/ecommerceMall/superAdmin/admins/${encodeURIComponent(props.adminId ?? "null")}/password-resets`;
  export const random = (): IPageIEcommerceMallAdminPasswordReset =>
    typia.random<IPageIEcommerceMallAdminPasswordReset>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("adminId")(() => typia.assert(props.adminId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
