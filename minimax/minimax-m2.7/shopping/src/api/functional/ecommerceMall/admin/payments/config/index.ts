/**
 * Retrieve the payment gateway configuration for the platform.
 *
 * This endpoint returns the public-facing payment gateway settings required for clients to initiate payment processing. The configuration includes supported payment methods, currency codes, and integration parameters. This allows frontend applications to configure their payment interface appropriately and understand what payment options are available to customers.
 *
 * The returned configuration is read-only and applies platform-wide. All payment processing occurs through the external payment gateway with the platform acting as an intermediary.
 *
 * @param props.connection
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor admin
 * @x-autobe-specification Query the system configuration for payment gateway settings.
 *
 * Return the following configuration values:
 * - Supported payment method types (e.g., credit_card, debit_card, bank_transfer, e_wallet)
 * - Default currency code for transactions
 * - Supported currency codes list
 * - Payment gateway endpoint URL for initiating payment requests
 * - Maximum timeout threshold for payment requests (in seconds)
 * - Retry configuration for transient failures
 * - Webhook callback URL path for payment status notifications
 * - Platform merchant/tenant identifier
 *
 * Ensure NO sensitive credentials (API keys, secrets, private keys) are included in the response.
 *
 * Return 200 OK with the payment configuration object on success.
 * Return 503 Service Unavailable if payment gateway configuration is not initialized.
 * @path /ecommerceMall/admin/payments/config
 * @accessor api.functional.ecommerceMall.admin.payments.config.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(connection: IConnection): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(),
          status: null,
        },
      );
}
export namespace at {
  export type Response = IEcommerceMallPaymentConfig;

  export const METADATA = {
    method: "GET",
    path: "/ecommerceMall/admin/payments/config",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/ecommerceMall/admin/payments/config";
  export const random = (): IEcommerceMallPaymentConfig =>
    typia.random<IEcommerceMallPaymentConfig>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}

/**
 * Update the payment gateway integration configuration for the platform.
 *
 * This operation allows administrators to modify the external payment gateway settings including API endpoints, credentials, and operational parameters. Changes to integration settings are recorded in the system audit log for security and compliance purposes.
 *
 * Only super administrators with appropriate permissions can modify payment configuration. The configuration affects all payment processing across the platform, so changes should be validated before application.
 *
 * The payment gateway integration must be available and responsive for checkout operations to proceed. If the gateway becomes unavailable, the system follows degradation policies to maintain core functionality while preventing order creation.
 *
 * @param props.connection
 * @param props.body Payment gateway configuration update parameters
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor admin
 * @x-autobe-specification Retrieve current payment gateway configuration from secure configuration storage. Validate all incoming configuration fields against payment gateway API requirements. Verify payment gateway connectivity by performing a health check with the new configuration if credentials are being updated. Update the payment gateway configuration in secure storage. Log the configuration change in ecommerce_mall_admin_audit_logs with actor identification and timestamp. Return the updated configuration response. If configuration validation fails, return appropriate validation errors without applying changes. If payment gateway health check fails, reject the configuration update with clear error message.
 * @path /ecommerceMall/admin/payments/config
 * @accessor api.functional.ecommerceMall.admin.payments.config.update
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function update(
  connection: IConnection,
  props: update.Props,
): Promise<update.Response> {
  return true === connection.simulate
    ? update.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...update.METADATA,
          path: update.path(),
          status: null,
        },
        props.body,
      );
}
export namespace update {
  export type Props = {
    /**
     * Payment gateway configuration update parameters
     */
    body: IEcommerceMallPaymentConfig.IUpdate;
  };
  export type Body = IEcommerceMallPaymentConfig.IUpdate;
  export type Response = IEcommerceMallPaymentConfig.IConfig;

  export const METADATA = {
    method: "PATCH",
    path: "/ecommerceMall/admin/payments/config",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/ecommerceMall/admin/payments/config";
  export const random = (): IEcommerceMallPaymentConfig.IConfig =>
    typia.random<IEcommerceMallPaymentConfig.IConfig>();
  export const simulate = (
    connection: IConnection,
    props: update.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: update.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
