/**
 * Allows authenticated administrators to change their account password.
 *
 * Administrators must provide their current password for verification before setting a new password. The new password must meet the platform's security requirements. Upon successful password change, the administrator remains logged in with the updated credentials.
 *
 * **Request Validation**
 *
 * The current password must match the stored password hash exactly. If verification fails, the request is rejected with an authentication error. The new password is validated against platform security requirements before acceptance.
 *
 * **Response**
 *
 * On success, returns a confirmation message indicating the password was updated. No additional authentication is required after the change.
 *
 * @param props.connection
 * @param props.body Contains the current password for verification and the new password to set.
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor admin
 * @x-autobe-specification Validate the current password against the stored
 *   password_hash in ecommerce_mall_admins table for the authenticated admin.
 *
 * If current password verification fails, return 401 Unauthorized with message indicating incorrect current password.
 *
 * Validate the newPassword against platform security requirements (minimum length, complexity rules).
 *
 * Hash the newPassword using bcrypt and update the password_hash field in ecommerce_mall_admins table.
 *
 * Update the updated_at timestamp on successful password change.
 *
 * Return 200 OK with success confirmation on successful update.
 * @path /ecommerceMall/admin/admin/password
 * @accessor api.functional.ecommerceMall.admin.admin.password.update
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function update(
  connection: IConnection,
  props: update.Props,
): Promise<update.Response> {
  return true === connection.simulate
    ? update.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...update.METADATA,
          path: update.path(),
          status: null,
        },
        props.body,
      );
}
export namespace update {
  export type Props = {
    /**
     * Contains the current password for verification and the new password to set.
     */
    body: IEcommerceMallAdmin.IPasswordUpdate;
  };
  export type Body = IEcommerceMallAdmin.IPasswordUpdate;
  export type Response = IEcommerceMallAdmin.IPasswordChangeSuccess;

  export const METADATA = {
    method: "PUT",
    path: "/ecommerceMall/admin/admin/password",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/ecommerceMall/admin/admin/password";
  export const random = (): IEcommerceMallAdmin.IPasswordChangeSuccess =>
    typia.random<IEcommerceMallAdmin.IPasswordChangeSuccess>();
  export const simulate = (
    connection: IConnection,
    props: update.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: update.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
