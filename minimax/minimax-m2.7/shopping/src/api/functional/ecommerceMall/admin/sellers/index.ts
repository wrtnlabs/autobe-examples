/**
 * Retrieve a filtered and paginated list of sellers registered on the platform.
 *
 * This operation allows administrators to search and filter sellers by various criteria including approval status, shop name, email, and registration date. Results are paginated with configurable page sizes and sorting options.
 *
 * The search functionality supports partial matching on shop name and email address. Administrators can filter by approval status (pending, approved, rejected) to review seller registrations or manage existing sellers. Date range filtering allows finding sellers registered within specific time periods.
 *
 * Sellers with pending status have limited platform access and cannot list products. Approved sellers have full selling privileges. Rejected sellers may have provided a rejection reason and can resubmit registration.
 *
 * @param props.connection
 * @param props.body Search criteria, filters, and pagination parameters
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor admin
 * @x-autobe-specification Query ecommerce_mall_sellers table with optional JOIN to ecommerce_mall_seller_profiles for shop name search.
 *
 * Apply filters: approval_status (exact match), created_at range, and search term (ILIKE on email and shop name).
 *
 * Only return sellers where deleted_at IS NULL to exclude soft-deleted accounts.
 *
 * Pagination: limit default 20, max 100. Sort by created_at DESC by default.
 *
 * For seller role: return only their own record. For admin/superAdmin: return all matching records.
 *
 * Response includes seller summary without password_hash field. Join with seller_profiles to include shop name if available.
 * @path /ecommerceMall/admin/sellers
 * @accessor api.functional.ecommerceMall.admin.sellers.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
