/**
 * Retrieve a comprehensive inventory overview with stock statistics for the authenticated seller.
 *
 * This endpoint provides sellers with a dashboard view of their inventory status across all product variants. The response includes aggregated metrics such as total stock quantity, total stock value, out-of-stock variant count, low-stock variant count, and recent inventory changes.
 *
 * Low-stock variants are those with stock quantity below the configurable threshold (default: 10 units). This helps sellers quickly identify items that may need restocking.
 *
 * The endpoint aggregates inventory data from all product variants belonging to products owned by the authenticated seller. It calculates current stock by summing all inventory records for each variant.
 *
 * @param props.connection
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor admin
 * @x-autobe-specification Query all product variants belonging to products owned by the authenticated seller.
 * For each variant:
 * 1. Calculate current stock quantity by summing all ecommerce_mall_inventory_records where ecommerce_mall_product_variant_id matches the variant's id
 * 2. Determine variant status: 'in_stock' (quantity > 10), 'low_stock' (1-10), or 'out_of_stock' (0)
 * 3. Calculate stock value as quantity * COALESCE(variant.price, product.base_price)
 * 4. Get the most recent inventory record timestamp
 *
 * Aggregate results:
 * - Total variants count
 * - Total stock quantity across all variants
 * - Total stock value
 * - Out-of-stock variants count
 * - Low-stock variants count
 * - In-stock variants count
 *
 * For the low-stock variants list:
 * - Filter variants where calculated stock quantity is between 1 and 10
 * - Include variant id, SKU code, product name, current quantity, and price
 * - Limit to 20 variants ordered by quantity ascending
 *
 * For recent changes list:
 * - Get the 10 most recent inventory records from ecommerce_mall_inventory_records
 * - Include quantity change, reason, created_at, variant SKU, and product name
 * - Order by created_at descending
 *
 * Authorization: Seller authentication required. Only return data for variants owned by the authenticated seller (join through product_variants -> products -> seller_id matches authenticated seller).
 * @path /ecommerceMall/admin/inventory/overview
 * @accessor api.functional.ecommerceMall.admin.inventory.overview.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(connection: IConnection): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(),
          status: null,
        },
      );
}
export namespace at {
  export type Response = IEcommerceMallInventoryRecord;

  export const METADATA = {
    method: "GET",
    path: "/ecommerceMall/admin/inventory/overview",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/ecommerceMall/admin/inventory/overview";
  export const random = (): IEcommerceMallInventoryRecord =>
    typia.random<IEcommerceMallInventoryRecord>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}
