import {
  HttpError,
  IConnection,
  NestiaSimulator,
  PlainFetcher,
} from "@nestia/fetcher";
import typia from "typia";

import { IEcommerceMallOrder } from "../../../../../../structures/IEcommerceMallOrder";

/**
 * Force cancel all eligible items in an order.
 *
 * This endpoint allows administrators to cancel all order items with 'paid' status in an entire order. For each cancelled item, the system immediately processes a refund and restores the stock quantity by creating inventory records.
 *
 * **Cancellation Behavior:**
 * - Only items with 'paid' status are cancelled
 * - Items already shipped, delivered, cancelled, or refunded are skipped
 * - Each cancelled item triggers a refund and stock restoration
 * - Order status is updated to reflect the new state
 *
 * **Authorization:**
 * - Requires ADMIN or SUPER_ADMIN role
 *
 * **Error Handling:**
 * - Returns 404 if order not found
 * - Returns 400 if order has no eligible items to cancel
 *
 * @param props.connection
 * @param props.orderId Unique order number of the order to force cancel.
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor admin
 * @x-autobe-specification 1. Validate the order exists in ecommerce_mall_orders
 *   table using orderId as order_number 2. Query all order items from
 *   ecommerce_mall_order_items where ecommerce_mall_order_id matches orderId
 *   and status equals 'paid' 3. If no eligible items found, return 400 error 4.
 *   For each eligible order item: a. Update status to 'cancelled' in
 *   ecommerce_mall_order_items b. Process refund via payment gateway c. Create
 *   inventory record in ecommerce_mall_inventory_records with quantity_change =
 *   +quantity, reason = 'order_cancellation' 5. Update order status in
 *   ecommerce_mall_orders based on remaining items: - If all items cancelled →
 *   status = 'cancelled' - If mixed states → status = 'partially_completed' 6.
 *   Return the updated order with all order items included
 * @path /ecommerceMall/admin/admin/orders/:orderId/force-cancel
 * @accessor api.functional.ecommerceMall.admin.admin.orders.force_cancel.forceCancel
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function forceCancel(
  connection: IConnection,
  props: forceCancel.Props,
): Promise<forceCancel.Response> {
  return true === connection.simulate
    ? forceCancel.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...forceCancel.METADATA,
          path: forceCancel.path(props),
          status: null,
        },
      );
}
export namespace forceCancel {
  export type Props = {
    /**
     * Unique order number of the order to force cancel.
     */
    orderId: string;
  };
  export type Response = IEcommerceMallOrder;

  export const METADATA = {
    method: "POST",
    path: "/ecommerceMall/admin/admin/orders/:orderId/force-cancel",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/ecommerceMall/admin/admin/orders/${encodeURIComponent(props.orderId ?? "null")}/force-cancel`;
  export const random = (): IEcommerceMallOrder =>
    typia.random<IEcommerceMallOrder>();
  export const simulate = (
    connection: IConnection,
    props: forceCancel.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: forceCancel.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("orderId")(() => typia.assert(props.orderId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
