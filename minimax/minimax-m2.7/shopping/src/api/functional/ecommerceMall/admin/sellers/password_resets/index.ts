import {
  HttpError,
  IConnection,
  NestiaSimulator,
  PlainFetcher,
} from "@nestia/fetcher";
import typia, { tags } from "typia";

import { IEcommerceMallSeller } from "../../../../../structures/IEcommerceMallSeller";
import { IEcommerceMallSellerPasswordReset } from "../../../../../structures/IEcommerceMallSellerPasswordReset";

/**
 * Complete a password reset flow for a seller account using a valid reset token.
 *
 * This operation allows sellers who have forgotten their password to set a new one. The seller must have previously requested a password reset (which sends a secure token to their registered email address). The token, along with the new password, is submitted through this endpoint.
 *
 * The system validates the reset token against the seller ID, checks token expiration, verifies the token has not been previously used, and then updates the seller's password hash. Upon successful password reset, the seller can immediately log in with their new password.
 *
 * Security measures include one-time token usage (marked as used_at after successful reset), token expiration enforcement, and rejection of invalid or expired tokens.
 *
 * @param props.connection
 * @param props.sellerId Unique identifier of the seller account to reset password for (UUID format).
 * @param props.body Password reset request containing the secure token from email and the new password to set.
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor admin
 * @x-autobe-specification Implement password reset completion for sellers.
 *
 * 1. Extract sellerId from path parameter (UUID format)
 * 2. Validate request body contains required fields: token and newPassword
 * 3. Query ecommerce_mall_seller_password_resets table to find token record
 * 4. Validate token belongs to the specified seller (ecommerce_mall_seller_id matches)
 * 5. Validate token has not been used (used_at is null)
 * 6. Validate token has not expired (expires_at > current timestamp)
 * 7. Validate new password meets platform security requirements (minimum length, complexity)
 * 8. Hash new password using bcrypt
 * 9. Update ecommerce_mall_sellers record with new password_hash
 * 10. Update ecommerce_mall_seller_password_resets record: set used_at to current timestamp
 * 11. Return success response with seller information (excluding password_hash)
 *
 * Error handling:
 * - Token not found: Return 404 with error message
 * - Token expired: Return 400 with error message
 * - Token already used: Return 400 with error message
 * - Seller ID mismatch: Return 400 with error message
 * - Invalid password format: Return 400 with validation error
 * - Seller account deleted: Return 400 with error message
 *
 * Transaction: Wrap password update and token usage in a database transaction to ensure atomicity.
 * @path /ecommerceMall/admin/sellers/:sellerId/password-resets
 * @accessor api.functional.ecommerceMall.admin.sellers.password_resets.reset
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function reset(
  connection: IConnection,
  props: reset.Props,
): Promise<reset.Response> {
  return true === connection.simulate
    ? reset.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...reset.METADATA,
          path: reset.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace reset {
  export type Props = {
    /**
     * Unique identifier of the seller account to reset password for (UUID format).
     */
    sellerId: string & tags.Format<"uuid">;

    /**
     * Password reset request containing the secure token from email and the new password to set.
     */
    body: IEcommerceMallSellerPasswordReset.IReset;
  };
  export type Body = IEcommerceMallSellerPasswordReset.IReset;
  export type Response = IEcommerceMallSeller;

  export const METADATA = {
    method: "PATCH",
    path: "/ecommerceMall/admin/sellers/:sellerId/password-resets",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/ecommerceMall/admin/sellers/${encodeURIComponent(props.sellerId ?? "null")}/password-resets`;
  export const random = (): IEcommerceMallSeller =>
    typia.random<IEcommerceMallSeller>();
  export const simulate = (
    connection: IConnection,
    props: reset.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: reset.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("sellerId")(() => typia.assert(props.sellerId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
