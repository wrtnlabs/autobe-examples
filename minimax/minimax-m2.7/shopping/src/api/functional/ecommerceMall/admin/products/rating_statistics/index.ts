import {
  HttpError,
  IConnection,
  NestiaSimulator,
  PlainFetcher,
} from "@nestia/fetcher";
import typia, { tags } from "typia";

import { IEcommerceMallProductRatingStatistic } from "../../../../../structures/IEcommerceMallProductRatingStatistic";

/**
 * Retrieve aggregated rating statistics for a specific product.
 *
 * This endpoint returns comprehensive rating statistics including the average star rating, total number of reviews, and the distribution of ratings across each star level (1 through 5). Statistics are calculated only from non-deleted reviews to ensure accurate representation of current product quality as perceived by verified purchasers.
 *
 * The average rating is computed by summing all individual ratings and dividing by the count of non-deleted reviews. The rating distribution shows how many customers gave each star rating, providing insight into customer satisfaction patterns. This data helps prospective buyers make informed purchasing decisions and enables sellers to understand product reception.
 *
 * @param props.connection
 * @param props.productId Unique identifier of the product (UUID format)
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor admin
 * @x-autobe-specification Query the ecommerce_mall_products table to verify the product exists and belongs to an active seller.
 *
 * Query the ecommerce_mall_reviews table filtering by ecommerce_mall_product_id matching the path parameter and deleted_at IS NULL.
 *
 * Calculate the following statistics:
 * - averageRating: SUM(rating) / COUNT(*) from filtered reviews, rounded to 1 decimal place
 * - totalReviews: COUNT(*) from filtered reviews
 * - distribution: COUNT(*) grouped by rating value (1, 2, 3, 4, 5)
 *
 * If no reviews exist (count is 0), return averageRating as 0 and all distribution counts as 0.
 *
 * Return 404 Not Found if the product does not exist.
 * @path /ecommerceMall/admin/products/:productId/rating-statistics
 * @accessor api.functional.ecommerceMall.admin.products.rating_statistics.ratingStatistics
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function ratingStatistics(
  connection: IConnection,
  props: ratingStatistics.Props,
): Promise<ratingStatistics.Response> {
  return true === connection.simulate
    ? ratingStatistics.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...ratingStatistics.METADATA,
          path: ratingStatistics.path(props),
          status: null,
        },
      );
}
export namespace ratingStatistics {
  export type Props = {
    /**
     * Unique identifier of the product (UUID format)
     */
    productId: string & tags.Format<"uuid">;
  };
  export type Response = IEcommerceMallProductRatingStatistic;

  export const METADATA = {
    method: "GET",
    path: "/ecommerceMall/admin/products/:productId/rating-statistics",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/ecommerceMall/admin/products/${encodeURIComponent(props.productId ?? "null")}/rating-statistics`;
  export const random = (): IEcommerceMallProductRatingStatistic =>
    typia.random<IEcommerceMallProductRatingStatistic>();
  export const simulate = (
    connection: IConnection,
    props: ratingStatistics.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: ratingStatistics.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("productId")(() => typia.assert(props.productId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
