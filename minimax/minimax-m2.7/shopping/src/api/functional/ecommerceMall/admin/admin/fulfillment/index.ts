export async function metrics(
  connection: IConnection,
): Promise<metrics.Response> {
  return true === connection.simulate
    ? metrics.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...metrics.METADATA,
          path: metrics.path(),
          status: null,
        },
      );
}
