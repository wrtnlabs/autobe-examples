import {
  HttpError,
  IConnection,
  NestiaSimulator,
  PlainFetcher,
} from "@nestia/fetcher";
import typia, { tags } from "typia";

import { IEcommerceMallSellerSession } from "../../../../../structures/IEcommerceMallSellerSession";

/**
 * Retrieve details of a specific seller session by its unique identifier.
 *
 * This endpoint returns session metadata including client information (IP address, request URL, referrer), session creation and expiration timestamps, and the associated seller information.
 *
 * The actual JWT access and refresh tokens are not exposed in the response for security reasons. Sellers can use this endpoint to review their active sessions for security auditing purposes.
 *
 * If the session has expired, the response still includes the session record with its expiration timestamp. Expired sessions indicate that the seller needs to re-authenticate.
 *
 * This operation is scoped to the authenticated seller's own sessions only, ensuring session privacy between different seller accounts.
 *
 * @param props.connection
 * @param props.sessionId Unique identifier of the seller session (UUID format)
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor seller
 * @x-autobe-specification Query the ecommerce_mall_seller_sessions table using the provided sessionId (UUID) as the primary key.
 *
 * Join with ecommerce_mall_sellers table to include seller email and approval status in the response.
 *
 * Return the following session fields: id, ecommerce_mall_seller_id, ip, href, referrer, created_at, expired_at.
 *
 * Do NOT return access_token or refresh_token fields for security.
 *
 * Verify that the authenticated seller (from session context) owns the requested session. Return 403 Forbidden if the session belongs to a different seller.
 *
 * If session not found or soft-deleted, return 404 Not Found.
 * @path /ecommerceMall/seller/seller/sessions/:sessionId
 * @accessor api.functional.ecommerceMall.seller.seller.sessions.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique identifier of the seller session (UUID format)
     */
    sessionId: string & tags.Format<"uuid">;
  };
  export type Response = IEcommerceMallSellerSession;

  export const METADATA = {
    method: "GET",
    path: "/ecommerceMall/seller/seller/sessions/:sessionId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/ecommerceMall/seller/seller/sessions/${encodeURIComponent(props.sessionId ?? "null")}`;
  export const random = (): IEcommerceMallSellerSession =>
    typia.random<IEcommerceMallSellerSession>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("sessionId")(() => typia.assert(props.sessionId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
