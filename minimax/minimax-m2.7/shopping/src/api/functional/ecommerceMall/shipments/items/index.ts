/**
 * Add order items to an existing shipment for shipping preparation.
 *
 * This endpoint allows sellers to include additional order items in a shipment before adding tracking information. All items within a shipment must belong to the same seller and have 'paid' status. Items can only belong to one shipment at a time.
 *
 * The seller can only update shipments they own. Items can only be added while the shipment is in 'created' state (before tracking information is added). Once tracking is added and shipment transitions to 'in transit', no further items can be added.
 *
 * If any validation fails during the operation, all changes are rolled back to maintain data consistency. The seller receives detailed error information specifying which validation failed.
 *
 * @param props.connection
 * @param props.shipmentId Unique identifier of the shipment to update (global scope)
 * @param props.body Order item identifiers to add to the shipment
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor null
 * @x-autobe-specification Implement the following steps for adding items to a shipment:
 *
 * 1. **Validation Phase**:
 *    - Verify shipment exists and is not soft-deleted (deleted_at IS NULL)
 *    - Verify shipment is in 'created' state (tracking_number is NULL or empty)
 *    - Verify authenticated seller owns the shipment (ecommerce_mall_seller_id matches)
 *    - Validate all orderItemIds exist and belong to the same order as the shipment
 *    - Verify all order items have status = 'paid'
 *    - Verify no order item is already assigned to another shipment (ecommerce_mall_shipment_items)
 *    - Verify all order items belong to the same seller as the shipment
 *
 * 2. **Transaction Phase**:
 *    - Create ecommerce_mall_shipment_items records for each order item
 *    - Update ecommerce_mall_order_items status to 'shipped' for all included items
 *    - Record the shipped timestamp synchronized across all items
 *
 * 3. **Rollback Handling**:
 *    - If any item fails validation or update, rollback all previously created shipment_items
 *    - Do not create partial shipments - either all items succeed or none do
 *    - Return specific error message indicating which items failed
 *
 * 4. **Authorization**:
 *    - Seller can only update their own shipments
 *    - Verify seller has active (non-suspended) account status
 * @path /ecommerceMall/shipments/:shipmentId/items
 * @accessor api.functional.ecommerceMall.shipments.items.update
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function update(
  connection: IConnection,
  props: update.Props,
): Promise<update.Response> {
  return true === connection.simulate
    ? update.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...update.METADATA,
          path: update.path(props),
          status: null,
        },
        props.body,
      );
}
