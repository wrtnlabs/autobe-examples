import { IEcommerceMallGuestSession } from "../../../../structures/IEcommerceMallGuestSession";

/**
 * Retrieve a specific guest session by its unique identifier.
 *
 * This endpoint allows unauthenticated guests to retrieve their session data. The session contains browsing context including the current page URL, referrer, IP address, and session timing information. Sessions track the guest's navigation across the platform while maintaining anonymity.
 *
 * The session must belong to the requesting guest (validated via session token or device fingerprint in headers). Expired sessions return a 404 error as they are considered invalid. This endpoint is primarily used by the client application to maintain session state and navigation context during guest browsing.
 *
 * Related operations: POST /guest/sessions creates new sessions, and sessions are automatically invalidated upon expiration or logout.
 *
 * @param props.connection
 * @param props.sessionId Unique identifier of the guest session to retrieve (UUID format)
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor null
 * @x-autobe-specification Query the ecommerce_mall_guest_sessions table to retrieve the session by id. Join with ecommerce_mall_guests table to fetch associated guest information (fingerprint, user_agent, last_active_at). Verify the session has not expired by checking expired_at > current timestamp. If expired, return 404 error. Return the complete session record including guest details. Handle invalid UUID format with 400 error.
 * @path /ecommerceMall/guest/sessions/:sessionId
 * @accessor api.functional.ecommerceMall.guest.sessions.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique identifier of the guest session to retrieve (UUID format)
     */
    sessionId: string & tags.Format<"uuid">;
  };
  export type Response = IEcommerceMallGuestSession;

  export const METADATA = {
    method: "GET",
    path: "/ecommerceMall/guest/sessions/:sessionId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/ecommerceMall/guest/sessions/${encodeURIComponent(props.sessionId ?? "null")}`;
  export const random = (): IEcommerceMallGuestSession =>
    typia.random<IEcommerceMallGuestSession>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("sessionId")(() => typia.assert(props.sessionId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
