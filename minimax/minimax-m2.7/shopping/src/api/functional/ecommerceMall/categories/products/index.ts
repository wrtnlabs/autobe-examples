/**
 * Retrieve a paginated list of products within a specific category.
 *
 * This endpoint allows customers to browse products belonging to a particular category. The response includes product summaries optimized for list display, including basic pricing information and listing visibility.
 *
 * Supports filtering by search term to find products by name or description within the category. Results can be sorted by creation date (newest first by default) or by price. Soft-deleted products are automatically excluded from results.
 *
 * The category must exist and be active (not soft-deleted) for products to be retrieved. If the category has subcategories, only products directly belonging to this category are returned, not products from subcategories.
 *
 * @param props.connection
 * @param props.categoryId Unique identifier of the category (global scope)
 * @param props.body Search criteria, filtering options, and pagination parameters
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor null
 * @x-autobe-specification Query ecommerce_mall_products table filtering by the specified categoryId.
 *
 * Apply the following filters:
 * 1. ecommerce_mall_category_id must match the path parameter categoryId
 * 2. deleted_at must be NULL (exclude soft-deleted products)
 * 3. If name or description search term provided, apply partial match using case-insensitive LIKE on both fields combined
 * 4. If minPrice provided, filter products where base_price >= minPrice
 * 5. If maxPrice provided, filter products where base_price <= maxPrice
 *
 * Pagination:
 * - Default page: 1, default limit: 20, maximum limit: 100
 * - Calculate offset from page and limit
 * - Return total count for pagination metadata
 *
 * Sorting:
 * - Default: created_at DESC (newest first)
 * - price_asc: base_price ASC
 * - price_desc: base_price DESC
 * - newest: created_at DESC
 *
 * Join with ecommerce_mall_sellers table to include seller name in response if available.
 *
 * Return cursor-based pagination metadata with data array.
 * @path /ecommerceMall/categories/:categoryId/products
 * @accessor api.functional.ecommerceMall.categories.products.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Unique identifier of the category (global scope)
     */
    categoryId: string & tags.Format<"uuid">;

    /**
     * Search criteria, filtering options, and pagination parameters
     */
    body: IEcommerceMallProduct.IRequest;
  };
  export type Body = IEcommerceMallProduct.IRequest;
  export type Response = IPageIEcommerceMallProduct.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/ecommerceMall/categories/:categoryId/products",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/ecommerceMall/categories/${encodeURIComponent(props.categoryId ?? "null")}/products`;
  export const random = (): IPageIEcommerceMallProduct.ISummary =>
    typia.random<IPageIEcommerceMallProduct.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("categoryId")(() => typia.assert(props.categoryId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
