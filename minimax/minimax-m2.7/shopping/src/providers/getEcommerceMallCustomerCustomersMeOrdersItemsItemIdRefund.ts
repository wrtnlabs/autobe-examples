export async function getEcommerceMallCustomerCustomersMeOrdersItemsItemIdRefund(props: {
  customer: CustomerPayload;
  itemId: string & tags.Format<"uuid">;
}): Promise<IEcommerceMallRefundRequest> {
  // Verify order item exists and belongs to the authenticated customer
  // Security: Return 404 (not 403) to prevent enumeration attacks
  await MyGlobal.prisma.ecommerce_mall_order_items.findFirstOrThrow({
    where: {
      id: props.itemId,
      order: {
        ecommerce_mall_customer_id: props.customer.id,
      },
    },
    select: {
      id: true,
    },
  });
  // Find refund request for this order item, exclude soft-deleted records
  // If multiple exist, return the most recent one (highest created_at)
  const refundRequest =
    await MyGlobal.prisma.ecommerce_mall_refund_requests.findFirst({
      where: {
        ecommerce_mall_order_item_id: props.itemId,
        ecommerce_mall_customer_id: props.customer.id,
        deleted_at: null,
      },
      orderBy: {
        created_at: "desc",
      },
    });
  if (!refundRequest) {
    throw new HttpException("Refund request not found", 404);
  }
  // Use transformer for select and transform
  const record =
    await MyGlobal.prisma.ecommerce_mall_refund_requests.findFirstOrThrow({
      ...EcommerceMallRefundRequestTransformer.select(),
      where: {
        id: refundRequest.id,
      },
    });
  return await EcommerceMallRefundRequestTransformer.transform(record);
}


