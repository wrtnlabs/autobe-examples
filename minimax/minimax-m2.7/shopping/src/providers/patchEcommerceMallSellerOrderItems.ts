export async function patchEcommerceMallSellerOrderItems(props: {
  seller: SellerPayload;
  body: IEcommerceMallOrderItem.IRequest;
}): Promise<IPageIEcommerceMallOrderItem.ISummary> {
  const page = props.body.page ?? 1;
  const limit = props.body.limit ?? 20;
  const skip = (page - 1) * limit;
  const createdAtRange = {
    ...(props.body.createdAtFrom !== undefined && {
      gte: props.body.createdAtFrom,
    }),
    ...(props.body.createdAtTo !== undefined && {
      lte: props.body.createdAtTo,
    }),
  };
  const whereInput = {
    productSnapshot: {
      seller: {
        id: props.seller.id,
      },
    },
    ...(props.body.status !== undefined && {
      status: props.body.status,
    }),
    ...(props.body.orderId !== undefined && {
      ecommerce_mall_order_id: props.body.orderId,
    }),
    ...(Object.keys(createdAtRange).length > 0 && {
      created_at: createdAtRange,
    }),
  } satisfies Prisma.ecommerce_mall_order_itemsFindManyArgs["where"];
  const records = await MyGlobal.prisma.ecommerce_mall_order_items.findMany({
    ...EcommerceMallOrderItemAtSummaryTransformer.select(),
    where: whereInput,
    skip,
    take: limit,
    orderBy: { created_at: "desc" },
  });
  const total = await MyGlobal.prisma.ecommerce_mall_order_items.count({
    where: whereInput,
  });
  return {
    pagination: {
      pagination: {
        current: page,
        limit: limit,
        records: total,
        pages: Math.ceil(total / limit),
      },
      data: [],
    },
    data: await ArrayUtil.asyncMap(
      records,
      EcommerceMallOrderItemAtSummaryTransformer.transform,
    ),
  };
}


