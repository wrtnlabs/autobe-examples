export async function getEcommerceMallCustomerCustomersMeOrdersOrderId(props: {
  customer: CustomerPayload;
  orderId: string & tags.Format<"uuid">;
}): Promise<IEcommerceMallOrder.IAt> {
  // Query order with ownership check and soft-delete filter
  // findFirstOrThrow returns 404 if order doesn't exist or is soft-deleted
  const record = await MyGlobal.prisma.ecommerce_mall_orders.findFirstOrThrow({
    ...EcommerceMallOrderAtAtTransformer.select(),
    where: {
      id: props.orderId,
      ecommerce_mall_customer_id: props.customer.id,
      deleted_at: null,
    },
  });
  return await EcommerceMallOrderAtAtTransformer.transform(record);
}


