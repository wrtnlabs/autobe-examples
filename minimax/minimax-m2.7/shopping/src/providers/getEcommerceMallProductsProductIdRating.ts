export async function getEcommerceMallProductsProductIdRating(props: {
  productId: string & tags.Format<"uuid">;
}): Promise<{
  averageRating: number;
  reviewCount: number;
}> {
  // Verify product exists - returns 404 if not found
  await MyGlobal.prisma.ecommerce_mall_products.findUniqueOrThrow({
    where: { id: props.productId },
    select: { id: true },
  });
  // Calculate average rating and count from non-deleted reviews
  const aggregate = await MyGlobal.prisma.ecommerce_mall_reviews.aggregate({
    where: {
      ecommerce_mall_product_id: props.productId,
      deleted_at: null,
    },
    _avg: { rating: true },
    _count: { id: true },
  });
  // Round average to one decimal place
  const averageRating =
    aggregate._avg.rating !== null
      ? Math.round((aggregate._avg.rating ?? 0) * 10) / 10
      : 0;
  return {
    averageRating,
    reviewCount: aggregate._count.id,
  };
}


