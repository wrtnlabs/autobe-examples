export async function getEcommerceMallSellerSellersMeProductsProductIdSnapshotsSnapshotId(props: {
  seller: SellerPayload;
  productId: string & tags.Format<"uuid">;
  snapshotId: string & tags.Format<"uuid">;
}): Promise<IEcommerceMallProductSnapshot.IInvert> {
  const snapshot =
    await MyGlobal.prisma.ecommerce_mall_product_snapshots.findFirstOrThrow({
      ...EcommerceMallProductSnapshotAtInvertTransformer.select(),
      where: {
        id: props.snapshotId,
        ecommerce_mall_product_id: props.productId,
      },
    });
  if (snapshot.seller.id !== props.seller.id) {
    throw new HttpException("Forbidden", 403);
  }
  return await EcommerceMallProductSnapshotAtInvertTransformer.transform(
    snapshot,
  );
}


