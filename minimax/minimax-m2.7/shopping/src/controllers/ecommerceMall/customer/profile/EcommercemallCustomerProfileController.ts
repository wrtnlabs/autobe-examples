import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallSellerProfile } from "../../../../api/structures/IEcommerceMallSellerProfile";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { putEcommerceMallCustomerProfile } from "../../../../providers/putEcommerceMallCustomerProfile";

@Controller("/ecommerceMall/customer/profile")
export class EcommercemallCustomerProfileController {
  /**
   * Update the authenticated seller's shop profile information.
   *
   * This endpoint allows sellers to modify their public shop profile including the shop name displayed in product listings, business description shown to customers, and logo image for brand identification. All profile modifications are automatically captured as immutable snapshots in the seller_profile_snapshots table for historical tracking and dispute resolution.
   *
   * **Snapshot Creation**: The system automatically creates a seller profile snapshot before applying any changes. This snapshot captures the previous name, description, and logo_uri values along with a timestamp and seller reference.
   *
   * **Authentication**: Requires valid seller session JWT token in Authorization header with SELLER role.
   *
   * **Validation**: Returns 400 validation errors for empty or oversized fields. Returns 404 if no profile exists for the authenticated seller.
   *
   * @param connection
   * @param body Seller profile update fields. All fields are optional but at least one should be provided for meaningful update.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification 1. Extract authenticated seller from JWT token in Authorization header. Verify seller role.
   * 2. Validate request body contains valid seller profile update fields.
   * 3. Validate field constraints:
   *    - name: required if provided, non-empty string, max 200 characters, no whitespace-only values
   *    - description: optional, max 5000 characters
   *    - logo_uri: optional, valid URI format if provided, max 80000 characters
   * 4. Fetch current seller profile from ecommerce_mall_seller_profiles table using authenticated seller's ID.
   * 5. If no profile exists (null result), return HTTP 404 with error message indicating profile not found.
   * 6. Before updating, create a new record in ecommerce_mall_seller_profile_snapshots table containing:
   *    - seller_id: reference to the authenticated seller
   *    - previous_name: current name value from profile
   *    - previous_description: current description value from profile
   *    - previous_logo_uri: current logo_uri value from profile
   *    - created_at: current timestamp
   * 7. Apply updates to ecommerce_mall_seller_profiles:
   *    - Update name if provided in request
   *    - Update description if provided in request
   *    - Update logo_uri if provided in request
   *    - Set updated_at to current timestamp
   * 8. Return HTTP 200 with the complete updated seller profile record including all fields.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IEcommerceMallSellerProfile.IUpdate,
  ): Promise<IEcommerceMallSellerProfile> {
    try {
      return await putEcommerceMallCustomerProfile({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
