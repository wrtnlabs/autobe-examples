import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallCustomerProfile } from "../../../../api/structures/IEcommerceMallCustomerProfile";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { getEcommerceMallCustomerProfile } from "../../../../providers/getEcommerceMallCustomerProfile";
import { patchEcommerceMallCustomerProfile } from "../../../../providers/patchEcommerceMallCustomerProfile";

@Controller("/ecommerceMall/customer/profile")
export class EcommercemallCustomerProfileController {
  /**
   * Retrieve the authenticated customer's profile information.
   *
   * This endpoint returns the current customer's profile data including their display name and phone number. The profile is automatically created when a customer registers and is linked to their account throughout their lifetime on the platform.
   *
   * The operation requires the customer to be authenticated via valid session token. Unauthenticated requests will be rejected with an appropriate error response.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Retrieve the customer profile for the authenticated customer.
   *
   * 1. Extract customer ID from the authenticated session context (JWT token in Authorization header)
   * 2. Query ecommerce_mall_customer_profiles table using the customer_id
   * 3. Return the profile record including: id, display_name, phone, created_at, updated_at
   * 4. If no profile exists for the customer, return 404 error
   * 5. Include the related customer email from ecommerce_mall_customers table in the response if needed for display
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
  ): Promise<IEcommerceMallCustomerProfile> {
    try {
      return await getEcommerceMallCustomerProfile({
        customer,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Partially update the authenticated customer's profile with the provided fields.
   *
   * This endpoint allows customers to modify their display name and/or phone number without requiring a full profile replacement. Only the fields included in the request body will be updated; omitted fields retain their current values. The display name, when provided, must be between 1 and 100 characters. The phone number, when provided, must be between 10 and 20 characters.
   *
   * The update is atomic: if any validation fails, no changes are applied and the profile remains in its previous state. At least one field must be provided in the request. If both fields are omitted, the profile is returned unchanged. Concurrent updates from multiple sessions are handled using last-write-wins semantics, where the most recently received update takes precedence.
   *
   * @param connection
   * @param body Partial profile update with only the fields to be modified. At least one field must be provided.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Implement partial profile update for the authenticated customer session.
   *
   * 1. Extract customer ID from authenticated session JWT token
   * 2. Look up the customer profile by customer_id foreign key
   * 3. Validate request body fields:
   *    - displayName: if provided, must be non-empty string, max 100 characters
   *    - phone: if provided, must be non-empty string, 10-20 characters, valid phone format
   * 4. Apply only the provided fields to the existing profile (partial update)
   * 5. Validate that after update, at least displayName remains populated
   * 6. If both fields are omitted or all validations pass, save updated profile
   * 7. Update the updated_at timestamp automatically
   * 8. Return the complete updated profile in response
   *
   * Edge cases:
   * - Empty string for displayName or phone: reject with 400 error, preserve current values
   * - Both fields omitted: return current profile unchanged
   * - Profile not found for customer: return 404 error
   * - Phone with invalid characters or wrong length: reject with 400 error
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async update(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IEcommerceMallCustomerProfile.IUpdate,
  ): Promise<IEcommerceMallCustomerProfile> {
    try {
      return await patchEcommerceMallCustomerProfile({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
