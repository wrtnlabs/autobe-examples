import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallCategory } from "../../../../../api/structures/IEcommerceMallCategory";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { getEcommerceMallCustomerCategoriesTree } from "../../../../../providers/getEcommerceMallCustomerCategoriesTree";

@Controller("/ecommerceMall/customer/categories/tree")
export class EcommercemallCustomerCategoriesController {
  /**
   * Retrieves the complete category hierarchy as a nested tree structure.
   *
   * This endpoint returns all parent categories along with their direct subcategories in a hierarchical format. Customers use this to browse the full category structure when navigating the platform. Each parent category includes an array of its immediate child subcategories, providing a complete view of the category taxonomy.
   *
   * **Response Structure**
   *
   * The response contains an array of category tree nodes. Each node represents a parent category and includes its subcategories as nested children. The tree is always complete—no filtering, pagination, or query parameters are supported.
   *
   * **Usage Context**
   *
   * This endpoint is typically called on initial page load or when customers access the category navigation menu. It provides the complete taxonomy in a single request, enabling efficient client-side category browsing without multiple API calls.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query the ecommerce_mall_categories table to retrieve all categories.
   *
   * Group categories by their parent_id field. Categories with NULL parent_id are root/parent categories.
   *
   * Build the tree structure:
   * - For each parent category, create a tree node with: id, name, description
   * - Attach all subcategories (categories where parent_id matches parent category id) as children array
   * - Each subcategory node includes: id, name, description (with empty children array)
   * - Sort parent categories by name alphabetically
   * - Sort subcategories within each parent by name alphabetically
   *
   * Return the complete tree structure as an array of parent category nodes with nested subcategories. No filtering, no pagination—always return the full tree.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async tree(
    @CustomerAuth()
    customer: CustomerPayload,
  ): Promise<IEcommerceMallCategory.ITree> {
    try {
      return await getEcommerceMallCustomerCategoriesTree({
        customer,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
