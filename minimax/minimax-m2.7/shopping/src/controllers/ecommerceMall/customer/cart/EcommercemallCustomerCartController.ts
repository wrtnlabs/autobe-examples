import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallCart } from "../../../../api/structures/IEcommerceMallCart";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { getEcommerceMallCustomerCart } from "../../../../providers/getEcommerceMallCustomerCart";

@Controller("/ecommerceMall/customer/cart")
export class EcommercemallCustomerCartController {
  /**
   * Retrieve the current customer's shopping cart with complete item details.
   *
   * This endpoint returns the authenticated customer's shopping cart containing all selected product variants and quantities. The response includes inverted composition data—each cart item embeds its parent cart information along with full product details (name, description, images) and variant details (SKU, options, price).
   *
   * Cart items include real-time availability status based on variant stock levels. Items may appear as unavailable if the variant has been soft-deleted by the seller or if stock quantity is zero. The cart total is calculated by summing the subtotal of each item (quantity multiplied by variant price).
   *
   * The cart is automatically created upon customer registration and persists across sessions. Items from the same variant are combined into a single line item with aggregated quantity rather than appearing as separate entries.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query the ecommerce_mall_carts table to find the cart belonging to the authenticated customer (from JWT session). If no cart exists, return an empty cart structure.
   *
   * Join with ecommerce_mall_cart_items to fetch all cart line items. For each cart item:
   * 1. Join with ecommerce_mall_product_variants to get variant details (sku_code, price, quantity)
   * 2. Join with ecommerce_mall_products to get product information (name, description)
   * 3. Check variant availability: set availability_status to 'unavailable' if variant.deleted_at is not null or variant.quantity is 0
   * 4. Include related data: variant option values from ecommerce_mall_product_variant_option_values
   *
   * Calculate cart_total as the sum of all (cart_item.quantity * COALESCE(variant.price, product.base_price)).
   *
   * Return the cart with all items embedded using the IInvert pattern to prevent circular references.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
  ): Promise<IEcommerceMallCart.IInvert> {
    try {
      return await getEcommerceMallCustomerCart({
        customer,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
