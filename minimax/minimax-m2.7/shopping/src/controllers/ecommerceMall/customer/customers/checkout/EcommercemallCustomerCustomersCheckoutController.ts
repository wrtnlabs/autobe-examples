import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallOrder } from "../../../../../api/structures/IEcommerceMallOrder";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { postEcommerceMallCustomerCustomersCheckout } from "../../../../../providers/postEcommerceMallCustomerCustomersCheckout";

@Controller("/ecommerceMall/customer/customers/checkout")
export class EcommercemallCustomerCustomersCheckoutController {
  /**
   * Create a new order from the customer's shopping cart contents.
   *
   * This endpoint finalizes the purchase by converting all available cart items into an order. The customer must have at least one available cart item to proceed. The system validates stock availability for all items before order creation.
   *
   * At checkout, the system retrieves the specified or default shipping address, freezes current product prices and seller information into immutable snapshots for dispute resolution, and calculates the order total from cart item quantities multiplied by variant unit prices.
   *
   * Upon successful order creation, all cart items are automatically removed from the customer's cart, and inventory quantities are deducted for each purchased variant. The returned order includes the generated order number for customer reference and tracking.
   *
   * The customer cannot checkout if any cart item is marked as unavailable (out of stock or variant deleted). All items must be available for the checkout to succeed.
   *
   * @param connection
   * @param body Optional shipping address ID. If not provided, the customer's default address is used.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification 1. Retrieve the authenticated customer's cart with all cart items joined to product variants
   * 2. Validate that the cart contains at least one item
   * 3. Validate that all cart items have available status (not unavailable/out-of-stock)
   * 4. If no items available, return error: cannot checkout with unavailable items
   * 5. Retrieve shipping address:
   *    - If shippingAddressId provided in request body, use it
   *    - Otherwise, use the customer's default address (is_default = true)
   * 6. Validate the shipping address belongs to the customer and is not deleted
   * 7. For each cart item, retrieve current product variant price and create ProductSnapshot
   * 8. Create SellerProfileSnapshot for each unique seller in the order
   * 9. Calculate order subtotal: sum of (cart_item.quantity * product_variant.price) for all items
   * 10. Calculate shipping_cost: platform configurable (default 0 for this implementation)
   * 11. Calculate total_amount: subtotal + shipping_cost
   * 12. Generate unique order_number (format: ORD-{timestamp}-{random})
   * 13. Create order record with status 'paid'
   * 14. Create order_item records for each cart item with:
   *     - Frozen unit_price from product variant
   *     - Frozen product_snapshot_id
   *     - Frozen seller_profile_snapshot_id
   *     - status = 'paid'
   * 15. Create inventory deduction records for each variant
   * 16. Clear all cart items from customer's cart (do not delete cart)
   * 17. Return created order with order_number
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IEcommerceMallOrder.ICreate,
  ): Promise<IEcommerceMallOrder> {
    try {
      return await postEcommerceMallCustomerCustomersCheckout({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
