import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallCheckout } from "../../../../../../api/structures/IEcommerceMallCheckout";
import { CustomerAuth } from "../../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../../decorators/payload/CustomerPayload";
import { getEcommerceMallCustomerCustomersMeCheckout } from "../../../../../../providers/getEcommerceMallCustomerCustomersMeCheckout";

@Controller("/ecommerceMall/customer/customers/me/checkout")
export class EcommercemallCustomerCustomersMeCheckoutController {
  /**
   * Retrieves the checkout summary for the authenticated customer.
   *
   * This endpoint validates all items in the customer's shopping cart and prepares a comprehensive checkout summary. The system checks each cart item for variant availability, stock quantity, and price validity. It retrieves all available shipping addresses for the customer, pre-selecting the default address if one exists.
   *
   * The checkout summary includes an itemized list of all cart items with their individual statuses. Items that are unavailable (deleted variants or out-of-stock) are flagged but remain visible so customers can resolve them before proceeding. The response calculates subtotals per item, the total item count, and the grand total for all valid items.
   *
   * **Cart Validation Rules:**
   * - Each cart item is validated against its product variant
   * - Variants that have been soft-deleted are marked as unavailable
   * - Items exceeding available stock quantity are flagged with actual available quantity
   * - Soft-deleted cart items are automatically excluded from totals
   *
   * **Shipping Address:**
   * - All non-deleted shipping addresses for the customer are returned
   * - The default address is indicated via the isDefault field
   * - At least one address is required before completing checkout
   *
   * **Totals Calculation:**
   * - Subtotal is computed per item: quantity multiplied by variant price
   * - Grand total includes only valid (non-unavailable) items
   * - Unavailable items are listed separately for customer awareness
   *
   * @param connection
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification 1. Authenticate the customer via JWT token in
     *   Authorization header 2. Retrieve the customer's cart from
     *   ecommerce_mall_carts using the authenticated customer ID 3. Load all
     *   cart items from ecommerce_mall_cart_items with JOIN to
     *   ecommerce_mall_product_variants and ecommerce_mall_products 4. For each
     *   cart item, perform validation: - Check if the variant
     *   (ecommerce_mall_product_variants) exists and deleted_at is NULL - Check
     *   if the product (ecommerce_mall_products) exists and deleted_at is NULL
     *   - Compare requested quantity against variant.quantity (available stock)
     *   - Determine item status: AVAILABLE, OUT_OF_STOCK, UNAVAILABLE (variant
     *   deleted) 5. Load all shipping addresses from
     *   ecommerce_mall_shipping_addresses where deleted_at IS NULL 6. Identify
     *   which address is the default (is_default = true) 7. Calculate per-item
     *   subtotals: quantity * variant_price (use price override if not null,
     *   else use product.base_price) 8. Compute grand total from subtotals of
     *   valid items only 9. Return the checkout summary with: - items: array
     *   with id, quantity, status, availableQuantity, unitPrice, subtotal, and
     *   embedded variant/product snapshot - addresses: array of customer
     *   shipping addresses with isDefault flag - summary: grandTotal,
     *   totalItems, validItemsCount, unavailableItemsCount
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
  ): Promise<IEcommerceMallCheckout.ISummary> {
    try {
      return await getEcommerceMallCustomerCustomersMeCheckout({
        customer,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
