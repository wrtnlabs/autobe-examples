import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallCancellationRequest } from "../../../../../../../../api/structures/IEcommerceMallCancellationRequest";
import { CustomerAuth } from "../../../../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../../../../decorators/payload/CustomerPayload";
import { postEcommerceMallCustomerCustomersMeOrdersItemsItemIdCancel } from "../../../../../../../../providers/postEcommerceMallCustomerCustomersMeOrdersItemsItemIdCancel";

@Controller("/ecommerceMall/customer/customers/me/orders/items/:itemId/cancel")
export class EcommercemallCustomerCustomersMeOrdersItemsCancelController {
  /**
   * Submits a cancellation request for a specific order item.
   *
   * The customer must be the owner of the order containing the item. The order item must have a status of 'paid' (payment completed but not yet shipped). Items that have been shipped or delivered cannot be cancelled through this endpoint—customers should use the refund request endpoint instead.
   *
   * **Cancellation Eligibility:**
   * - Item status must be 'paid'
   * - Item must belong to an order owned by the authenticated customer
   * - Each order item can only have one active cancellation request
   *
   * **Workflow:**
   * 1. Customer submits cancellation request with reason
   * 2. Request enters 'pending' status
   * 3. Seller reviews and approves or rejects
   * 4. If approved, item status changes to 'cancelled' and refund is processed
   * 5. Inventory quantity for the variant is restored
   *
   * **Error Handling:**
   * - 404 if item not found or not owned by customer
   * - 400 if item status is not 'paid'
   * - 400 if cancellation request already exists for this item
   *
   * @param connection
   * @param itemId Unique identifier of the order item to cancel.
   * @param body Cancellation request details containing the reason for requesting cancellation.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification 1. Extract customer ID from authenticated
     *   session. 2. Validate itemId is a valid UUID. 3. Query
     *   ecommerce_mall_order_items table to find the order item by itemId. 4.
     *   Verify the order item belongs to an order owned by the authenticated
     *   customer by joining with ecommerce_mall_orders table. 5. Verify the
     *   order item status is 'paid'. If not, return 400 error with message
     *   'Item is not eligible for cancellation'. 6. Check if a cancellation
     *   request already exists for this order item (unique constraint). If
     *   exists, return 400 error with message 'Cancellation request already
     *   submitted for this item'. 7. Extract the seller_id from the order item
     *   (owner of the product). 8. Create new cancellation request with status
     *   'pending', storing: - ecommerce_mall_order_item_id: itemId -
     *   ecommerce_mall_customer_id: authenticated customer ID -
     *   ecommerce_mall_seller_id: seller ID from order item - reason: from
     *   request body - status: 'pending' 9. Return the created cancellation
     *   request.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("itemId")
    itemId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceMallCancellationRequest.ICreate,
  ): Promise<IEcommerceMallCancellationRequest> {
    try {
      return await postEcommerceMallCustomerCustomersMeOrdersItemsItemIdCancel({
        customer,
        itemId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
