import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallCart } from "../../../../../../../api/structures/IEcommerceMallCart";
import { CustomerAuth } from "../../../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../../../decorators/payload/CustomerPayload";
import { patchEcommerceMallCustomerCustomersMeCartStock } from "../../../../../../../providers/patchEcommerceMallCustomerCustomersMeCartStock";

@Controller("/ecommerceMall/customer/customers/me/cart/stock")
export class EcommercemallCustomerCustomersMeCartStockController {
  /**
   * Validates stock availability for items in the customer's shopping cart.
   *
   * This endpoint checks the current available stock for cart items and returns warnings for any items where the cart quantity exceeds available stock. Items with zero stock are marked as unavailable.
   *
   * **Stock Validation Rules**:
   * - Compares each cart item's quantity against the current stock of its product variant
   * - Returns a warning flag and available stock quantity when cart quantity exceeds stock
   * - Marks items as unavailable when stock is zero
   * - Returns real-time stock information reflecting all inventory changes
   *
   * **Response Details**:
   * The response includes stock status for each validated cart item with the current available quantity, warning indicators, and availability status.
   *
   * @param connection
   * @param body Cart item IDs to validate. If empty, validates all items in the cart. Maximum 50 item IDs per request.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query the authenticated customer's shopping cart using the session context.
   *
   * For each cart item ID provided in the request (or all cart items if array is empty):
   * 1. Fetch the cart item with its associated product variant
   * 2. Calculate current available stock from the product variant's quantity field
   * 3. Compare cart quantity against available stock
   * 4. Determine stock warning status (warning when cart quantity > available stock, but stock > 0)
   * 5. Determine availability status (unavailable when stock equals 0)
   *
   * Return an array of stock validation results containing:
   * - cartItemId: The cart item identifier
   * - variantId: The product variant identifier
   * - skuCode: The SKU code for reference
   * - cartQuantity: The quantity in the cart
   * - availableStock: The current available stock quantity
   * - hasWarning: Boolean indicating if cart quantity exceeds available stock
   * - isAvailable: Boolean indicating if item can be checked out (stock > 0)
   * - warningMessage: Human-readable message when hasWarning is true
   *
   * Handle edge cases:
   * - If cart item does not exist or belongs to different customer, skip with error indication
   * - If variant is deleted (deleted_at not null), mark as unavailable
   * - If variant has zero stock, mark as unavailable with appropriate message
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async validateStock(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IEcommerceMallCart.IRequest,
  ): Promise<IEcommerceMallCart.IResult> {
    try {
      return await patchEcommerceMallCustomerCustomersMeCartStock({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
