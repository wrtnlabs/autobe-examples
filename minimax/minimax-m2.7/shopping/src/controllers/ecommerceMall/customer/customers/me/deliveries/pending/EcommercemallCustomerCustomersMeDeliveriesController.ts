import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IPageIEcommerceMallShipment } from "../../../../../../../api/structures/IPageIEcommerceMallShipment";
import { CustomerAuth } from "../../../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../../../decorators/payload/CustomerPayload";
import { getEcommerceMallCustomerCustomersMeDeliveriesPending } from "../../../../../../../providers/getEcommerceMallCustomerCustomersMeDeliveriesPending";

@Controller("/ecommerceMall/customer/customers/me/deliveries/pending")
export class EcommercemallCustomerCustomersMeDeliveriesController {
  /**
   * Retrieves all pending deliveries for the authenticated customer.
   *
   * This endpoint returns a list of shipments that have been shipped by sellers but not yet delivered or confirmed by the customer. Each delivery includes tracking information, carrier details, and the associated order information.
   *
   * **Purpose**:
   * Customers use this endpoint to view all their incoming packages across different orders in one consolidated view. This helps them track what items are on the way.
   *
   * **Response Details**:
   * The response includes shipment tracking numbers, carrier names, item details from the associated order, and estimated delivery context. Deliveries are sorted by shipment creation date with newest first.
   *
   * **Relationship to Orders**:
   * Each pending delivery belongs to a specific order. Customers can view which order each delivery is from and access detailed order information through the provided references.
   *
   * @param connection
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification Query all shipments for the authenticated
     *   customer where the shipment's order items have status 'shipped' (not
     *   yet delivered or confirmed).
   *
   * Implementation steps:
   * 1. Extract authenticated customer ID from session/token
   * 2. Query ecommerce_mall_shipments table joining with:
   *    - ecommerce_mall_orders (via order_id) to verify customer ownership
   *    - ecommerce_mall_shipment_items to get associated order items
   *    - ecommerce_mall_order_items to filter by item status
   * 3. Filter: shipment items with order_item.status = 'shipped'
   * 4. Exclude soft-deleted shipments (deleted_at IS NULL)
   * 5. Exclude cancelled/delivered order items
   * 6. Join with ecommerce_mall_seller_profiles for seller/shop name
   * 7. Return shipment details with tracking info, carrier, and item summaries
   * 8. Order by shipments.created_at DESC
   * 9. Apply pagination via query string parameters 'page' and 'limit' (default: page=1, limit=20, max=100)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async pending(
    @CustomerAuth()
    customer: CustomerPayload,
  ): Promise<IPageIEcommerceMallShipment.IDelivery.ISummary> {
    try {
      return await getEcommerceMallCustomerCustomersMeDeliveriesPending({
        customer,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
