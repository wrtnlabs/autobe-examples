import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallCustomer } from "../../../../../api/structures/IEcommerceMallCustomer";
import { IEcommerceMallCustomerProfile } from "../../../../../api/structures/IEcommerceMallCustomerProfile";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { getEcommerceMallCustomerCustomersMe } from "../../../../../providers/getEcommerceMallCustomerCustomersMe";
import { patchEcommerceMallCustomerCustomersMe } from "../../../../../providers/patchEcommerceMallCustomerCustomersMe";

@Controller("/ecommerceMall/customer/customers/me")
export class EcommercemallCustomerCustomersMeController {
  /**
   * Retrieves the profile of the currently authenticated customer.
   *
   * This endpoint returns the customer's account information (email, registration date) along with their profile details (display name, phone number). The response includes the customer's unique identifier and account status.
   *
   * **Authentication**: Requires a valid customer JWT token in the Authorization header.
   *
   * **Profile Data**: The response includes the display name shown on the platform and the contact phone number for order notifications. Both fields are required for a complete customer profile.
   *
   * **Account Status**: The response indicates whether the account is active or has been soft-deleted via the deleted_at timestamp. Active accounts have a null deleted_at value.
   *
   * @param connection
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification Query the ecommerce_mall_customers table using
     *   the authenticated customer's ID from the JWT token.
   *
   * Join with the ecommerce_mall_customer_profiles table to retrieve the display_name and phone_number.
   *
   * Return the combined customer and profile data in the response body.
   *
   * Verify the customer's deleted_at is null; if not null, return 401 Unauthorized as the account is inactive.
   *
   * Handle cases where profile exists but display_name or phone is empty - return the data as-is since these are optional in the database.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
  ): Promise<IEcommerceMallCustomer.IInvert> {
    try {
      return await getEcommerceMallCustomerCustomersMe({
        customer,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Updates the authenticated customer's profile information.
   *
   * This endpoint allows customers to modify their display name and contact phone number. The display name appears publicly on the platform for identification purposes, while the phone number is used for order notifications and delivery coordination.
   *
   * All fields are validated before the update is accepted. If any validation fails, the entire operation is rejected and the profile remains unchanged. Successful updates return the complete updated profile for client confirmation.
   *
   * **Validation Rules**:
   * - Display name is required and must not exceed 100 characters
   * - Phone number is required and must be between 10 and 20 characters
   * - Both fields cannot be submitted as null or blank
   *
   * @param connection
   * @param body Profile update payload containing the new display name and phone number. Both fields are required.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification 1. Extract the authenticated customer ID from the
     *   JWT session token in the Authorization header. 2. Validate the request
     *   body: - display_name: Required, string, max length 100 characters.
     *   Return error if null, blank, or exceeds 100 chars. - phone: Required,
     *   string, length between 10 and 20 characters. Return error if null,
     *   blank, or invalid format. 3. If validation fails, return 400 error with
     *   descriptive message preserving current valid values. 4. Query the
     *   ecommerce_mall_customer_profiles table using the customer_id from the
     *   JWT. 5. Update the display_name and phone fields with new values. 6.
     *   Set updated_at to current timestamp. 7. Return the complete updated
     *   profile including id, display_name, phone, created_at, updated_at. 8.
     *   On database error, rollback transaction and return 500 generic error
     *   without exposing internal details.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async update(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IEcommerceMallCustomerProfile.IUpdate,
  ): Promise<IEcommerceMallCustomerProfile> {
    try {
      return await patchEcommerceMallCustomerCustomersMe({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
