import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallOrder } from "../../../../../../../api/structures/IEcommerceMallOrder";
import { CustomerAuth } from "../../../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../../../decorators/payload/CustomerPayload";
import { getEcommerceMallCustomerCustomersMeCheckoutValidate } from "../../../../../../../providers/getEcommerceMallCustomerCustomersMeCheckoutValidate";

@Controller("/ecommerceMall/customer/customers/me/checkout/validate")
export class EcommercemallCustomerCustomersMeCheckoutValidateController {
  /**
   * Validates the customer's shopping cart and checkout readiness.
   *
   * This endpoint checks whether the customer can proceed to checkout by verifying:
   *
   * - All items in the cart are still available (not deleted, in stock)
   * - Requested quantities do not exceed available stock
   * - A valid shipping address exists (selected or default)
   *
   * **Validation Results**
   *
   * The response indicates whether checkout can proceed and includes any blocking errors or non-blocking warnings. Errors prevent checkout; warnings inform the customer of issues that may affect their order but do not block it.
   *
   * **Cart Item Validation**
   *
   * Each cart item is validated against current product and variant state. Items may become unavailable due to seller deletion, product deactivation, or variant removal. Stock quantities are verified against current inventory levels.
   *
   * **Shipping Address**
   *
   * A valid shipping address must exist for checkout. The system checks for a pre-selected address or falls back to the customer's default address. If no address is available, validation fails with an appropriate error.
   *
   * **Response Structure**
   *
   * The response includes the overall validation status, detailed error messages for any blocking issues, warnings about non-blocking concerns, the resolved shipping address, and a summary of cart contents with current prices and availability.
   *
   * @param connection
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification 1. Retrieve the authenticated customer from the
     *   session token.
   *
   * 2. Load the customer's cart with all cart items using the customer ID from session.
   *
   * 3. For each cart item:
   *    a. Verify the product variant still exists and is not deleted.
   *    b. Verify the product is not soft-deleted.
   *    c. Check current stock quantity against requested quantity.
   *    d. If variant/product unavailable → add error with item details.
   *    e. If stock insufficient → add warning with available quantity.
   *
   * 4. Check shipping address:
   *    a. If customer has a selected address ID in session, load that address.
   *    b. If no selected address, check for default address.
   *    c. If no address exists → add error about missing shipping address.
   *
   * 5. Build validation response:
   *    a. isValid = true only if no errors exist.
   *    b. Include all errors that block checkout.
   *    c. Include all warnings (low stock, price changes, etc.).
   *    d. Include resolved shipping address details.
   *    e. Include cart summary with current prices.
   *
   * 6. Return the validation result with HTTP 200 regardless of validation outcome.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async validateCheckout(
    @CustomerAuth()
    customer: CustomerPayload,
  ): Promise<IEcommerceMallOrder> {
    try {
      return await getEcommerceMallCustomerCustomersMeCheckoutValidate({
        customer,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
