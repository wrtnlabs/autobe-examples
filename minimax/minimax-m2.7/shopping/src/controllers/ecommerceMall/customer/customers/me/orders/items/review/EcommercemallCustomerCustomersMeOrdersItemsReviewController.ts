import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallReview } from "../../../../../../../../api/structures/IEcommerceMallReview";
import { CustomerAuth } from "../../../../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../../../../decorators/payload/CustomerPayload";
import { postEcommerceMallCustomerCustomersMeOrdersItemsItemIdReview } from "../../../../../../../../providers/postEcommerceMallCustomerCustomersMeOrdersItemsItemIdReview";

@Controller("/ecommerceMall/customer/customers/me/orders/items/:itemId/review")
export class EcommercemallCustomerCustomersMeOrdersItemsReviewController {
  /**
   * Create a product review for a delivered order item.
   *
   * Customers can write reviews only for products they have purchased and received. The order item must have 'delivered' status to be eligible for review. Each customer can write one review per product per order (per order item).
   *
   * **Review Eligibility**:
   * - The order item must belong to the authenticated customer
   * - The order item status must be 'delivered'
   * - No existing review for the same customer + product + order_item combination
   *
   * **Review Content**:
   * - Rating is required (1-5 stars)
   * - Text content is optional
   *
   * **Review Display**:
   * Reviews appear on the product detail page sorted by most recent first. When a customer deletes their account, reviews are retained with an anonymous label.
   *
   * **Error Scenarios**:
   * - 404: Order item not found or does not belong to customer
   * - 400: Order item status is not 'delivered'
   * - 409: Review already exists for this product and order item
   * - 400: Invalid rating value (must be 1-5)
   *
   * @param connection
   * @param itemId Unique identifier of the order item to review. The order item must belong to the authenticated customer and have 'delivered' status.
   * @param body Review creation data including the required star rating (1-5) and optional text content for the product review.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification 1. Extract authenticated customer ID from JWT token
   * 2. Extract itemId from path parameter
   * 3. Verify the order item exists and belongs to the authenticated customer
   *    - Query ecommerce_mall_order_items table
   *    - Join with ecommerce_mall_orders to verify customer ownership
   * 4. Verify order item status is 'delivered'
   *    - If status is not 'delivered', return 400 error
   * 5. Verify no existing review for this customer + product + order_item combination
   *    - Query ecommerce_mall_reviews for existing review
   *    - If exists, return 409 Conflict error
   * 6. Validate rating in request body (1-5 integer required)
   * 7. Create new review in ecommerce_mall_reviews table
   *    - Set ecommerce_mall_customer_id from token
   *    - Set ecommerce_mall_product_id from order_item
   *    - Set ecommerce_mall_order_item_id from path
   *    - Set rating and content from request body
   *    - Set created_at and updated_at to current timestamp
   *    - deleted_at remains null
   * 8. Return created review with 201 status
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("itemId")
    itemId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceMallReview.ICreate,
  ): Promise<IEcommerceMallReview> {
    try {
      return await postEcommerceMallCustomerCustomersMeOrdersItemsItemIdReview({
        customer,
        itemId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
