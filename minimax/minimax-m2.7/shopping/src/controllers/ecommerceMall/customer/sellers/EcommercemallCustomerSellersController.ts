import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallSeller } from "../../../../api/structures/IEcommerceMallSeller";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { getEcommerceMallCustomerSellersSellerId } from "../../../../providers/getEcommerceMallCustomerSellersSellerId";

@Controller("/ecommerceMall/customer/sellers/:sellerId")
export class EcommercemallCustomerSellersController {
  /**
   * Retrieves the public profile of a seller including shop name, description, and logo.
   *
   * This endpoint provides public seller information for customers browsing the marketplace. The response includes the seller's approval status (visible only as 'approved' for public profiles), shop name displayed in product listings, business description, and optional logo image.
   *
   * **Public Access**: This endpoint is accessible to all users including guests without authentication. No authentication is required to view seller profiles.
   *
   * **Profile Visibility**: Only sellers with 'approved' status are publicly visible. Sellers with 'pending' or 'rejected' status will return 404 to maintain platform integrity.
   *
   * **Soft-Deleted Profiles**: If a seller's profile has been soft-deleted, the endpoint returns 404 to prevent access to deleted shop information.
   *
   * @param connection
   * @param sellerId Unique identifier of the seller (UUID format)
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification Retrieve seller by sellerId from
     *   ecommerce_mall_sellers table using UUID primary key.
   *
   * Join with ecommerce_mall_seller_profiles to fetch shop profile data (name, description, logo_uri).
   *
   * Apply the following filters:
   * 1. Verify approval_status equals 'approved' - reject with 404 if not approved
   * 2. Verify seller.deleted_at is NULL - reject with 404 if seller is soft-deleted
   * 3. Verify seller_profile.deleted_at is NULL - reject with 404 if profile is soft-deleted
   *
   * Return the seller record with nested seller_profile data. Do not include sensitive fields like email, password_hash, rejection_reason in the response.
   *
   * If seller is not found or does not meet visibility criteria, return HTTP 404.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallSeller.IInvert> {
    try {
      return await getEcommerceMallCustomerSellersSellerId({
        customer,
        sellerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
