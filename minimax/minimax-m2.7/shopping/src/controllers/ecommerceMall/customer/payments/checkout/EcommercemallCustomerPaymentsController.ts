import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallCheckout } from "../../../../../api/structures/IEcommerceMallCheckout";
import { IEcommerceMallOrder } from "../../../../../api/structures/IEcommerceMallOrder";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { postEcommerceMallCustomerPaymentsCheckout } from "../../../../../providers/postEcommerceMallCustomerPaymentsCheckout";

@Controller("/ecommerceMall/customer/payments/checkout")
export class EcommercemallCustomerPaymentsController {
  /**
   * Complete the checkout process by validating the cart, processing payment through the external payment gateway, and creating an order on successful payment.
   *
   * This endpoint is the final step in the purchase journey. The customer must have items in their cart, and all items must be available (in-stock, variant not deleted). The customer must select a valid shipping address from their saved addresses.
   *
   * When payment succeeds, the system atomically creates the order with all associated records: order items with product and seller profile snapshots, inventory deduction records, and cart clearance. If payment fails or times out, no order is created and the customer can retry.
   *
   * The response includes the complete order details with all items, enabling immediate order confirmation and tracking.
   *
   * @param connection
   * @param body Checkout request containing the selected shipping address for the order.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Implementation flow:
   * 1. Extract authenticated customer from request context
   * 2. Validate customer account is active (not banned/suspended)
   * 3. Retrieve customer's cart with all cart items and variant details
   * 4. Validate cart is not empty
   * 5. Validate all cart items are available:
   *    - Variant exists and not soft-deleted (deleted_at is null)
   *    - Variant quantity >= requested cart quantity
   *    - Product is not soft-deleted
   *    - Product has at least one non-deleted variant
   * 6. Retrieve shipping address by shippingAddressId
   * 7. Validate shipping address belongs to the authenticated customer and is not soft-deleted
   * 8. Calculate order totals:
   *    - subtotal: sum of (variant price override or product base price) * quantity for each item
   *    - shipping_cost: 0 for this implementation (can be extended)
   *    - total_amount: subtotal + shipping_cost
   * 9. Initiate payment with external gateway:
   *    - Send total_amount and order reference to payment gateway
   *    - Wait for success/failure response
   *    - Handle timeout as failure (30 second threshold per SLO)
   * 10. On payment failure:
   *     - Return error response with failure reason
   *     - Do NOT create any records
   *     - Do NOT modify inventory
   *     - Do NOT clear cart
   * 11. On payment success (atomic transaction):
   *     a. Generate unique order_number (retry if collision)
   *     b. Create ecommerce_mall_orders record with status 'paid'
   *     c. For each cart item:
   *        - Retrieve current product and variant state
   *        - Create product snapshot
   *        - Create seller profile snapshot
   *        - Create ecommerce_mall_order_items record with status 'paid'
   *        - Decrement variant quantity
   *        - Create negative inventory record for deduction
   *     d. Clear all cart items from ecommerce_mall_cart_items
   *     e. Commit transaction
   * 12. Return created order with all order items and snapshots
   *
   * Error handling:
   * - Cart empty: Return 400 with 'CART_EMPTY' code
   * - Unavailable item: Return 400 with 'ITEM_UNAVAILABLE' code and item details
   * - Invalid shipping address: Return 400 with 'INVALID_ADDRESS' code
   * - Payment declined: Return 402 with 'PAYMENT_FAILED' code
   * - Payment timeout: Return 504 with 'PAYMENT_TIMEOUT' code
   * - Stock insufficient: Rollback transaction, return 400 with 'INSUFFICIENT_STOCK' code
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async checkout(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IEcommerceMallCheckout.ICreate,
  ): Promise<IEcommerceMallOrder> {
    try {
      return await postEcommerceMallCustomerPaymentsCheckout({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
