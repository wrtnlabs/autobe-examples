import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallReview } from "../../../../../api/structures/IEcommerceMallReview";
import { IPageIEcommerceMallReview } from "../../../../../api/structures/IPageIEcommerceMallReview";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { getEcommerceMallCustomerReviewsReviewIdSnapshotsSnapshotId } from "../../../../../providers/getEcommerceMallCustomerReviewsReviewIdSnapshotsSnapshotId";
import { patchEcommerceMallCustomerReviewsReviewIdSnapshots } from "../../../../../providers/patchEcommerceMallCustomerReviewsReviewIdSnapshots";

@Controller("/ecommerceMall/customer/reviews/:reviewId/snapshots")
export class EcommercemallCustomerReviewsSnapshotsController {
  /**
   * Retrieve the modification history of a specific product review.
   *
   * This operation lists all historical snapshots for a review, showing how the rating and content changed over time. Each snapshot captures the previous state before an edit was made.
   *
   * Access is restricted to the customer who wrote the review or administrators for oversight purposes. The snapshots are displayed in chronological order from oldest to newest, allowing consumers to see the complete edit history.
   *
   * Review snapshots are immutable records preserved for dispute resolution, showing exactly what content existed at each point in time.
   *
   * @param connection
   * @param reviewId Unique identifier of the review whose snapshots to retrieve (global scope)
   * @param body Pagination parameters for retrieving review snapshots
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query ecommerce_mall_review_snapshots table filtering by reviewId.
   *
   * Join with ecommerce_mall_reviews to verify the review exists and belongs to the requesting customer.
   *
   * Apply authorization: only allow access if the requesting user is the review author (via review.customerId match) or has admin privileges.
   *
   * Order results by snapshot timestamp ascending (oldest first) to show chronological edit history.
   *
   * Include pagination with configurable page sizes.
   *
   * Return snapshot fields: previousRating, previousContent, newRating, newContent, createdAt.
   *
   * Handle case where review does not exist: return 404 error.
   *
   * Handle unauthorized access: return 403 error.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceMallReview.IRequest,
  ): Promise<IPageIEcommerceMallReview.ISummary> {
    try {
      return await patchEcommerceMallCustomerReviewsReviewIdSnapshots({
        customer,
        reviewId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific review snapshot by its ID.
   *
   * This endpoint returns the historical state of a review at the time a snapshot was created, including the rating value and text content before that edit was made.
   *
   * Customers can only retrieve snapshots of reviews they have written. The review must exist and belong to the authenticated customer. Administrators with elevated privileges can retrieve any review snapshot regardless of ownership.
   *
   * Review snapshots are immutable records that cannot be modified or deleted. They serve as an audit trail for dispute resolution when customers contest product conditions at time of purchase. Each snapshot includes the exact timestamp when that state was captured.
   *
   * The response includes the snapshot data (rating, body text, creation timestamp) along with an inverted representation of the parent review for context about which review this snapshot belongs to.
   *
   * @param connection
   * @param reviewId Unique identifier of the parent review this snapshot belongs to (global scope)
   * @param snapshotId Unique identifier of the review snapshot (global scope)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query ecommerce_mall_review_snapshots table using the provided snapshotId parameter. Verify the snapshot exists and join with ecommerce_mall_reviews table to get the review_id and verify ownership.
   *
   * Authorization check: If the authenticated user is a customer, verify that the review's ecommerce_mall_customer_id matches the authenticated customer ID. If the user is an administrator or super administrator, allow access to any snapshot.
   *
   * Return the snapshot record with rating, body, and created_at fields. Include the parent review summary (without snapshots array) via IInvert pattern for context.
   *
   * Handle cases: Snapshot not found (404), review not found (404), unauthorized access (403).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":snapshotId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
    @TypedParam("snapshotId")
    snapshotId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallReview.IInvert> {
    try {
      return await getEcommerceMallCustomerReviewsReviewIdSnapshotsSnapshotId({
        customer,
        reviewId,
        snapshotId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
