import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallShipment } from "../../../../../../api/structures/IEcommerceMallShipment";
import { CustomerAuth } from "../../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../../decorators/payload/CustomerPayload";
import { postEcommerceMallCustomerOrdersOrderIdShipmentsShipmentIdConfirmDelivery } from "../../../../../../providers/postEcommerceMallCustomerOrdersOrderIdShipmentsShipmentIdConfirmDelivery";

@Controller(
  "/ecommerceMall/customer/orders/:orderId/shipments/:shipmentId/confirm-delivery",
)
export class EcommercemallCustomerOrdersShipmentsConfirm_deliveryController {
  /**
   * Confirms delivery for a specific shipment belonging to an order.
   *
   * Allows customers to confirm that they have received the items in a shipment. When confirmed, all order items within that shipment transition their status from 'shipped' to 'delivered'.
   *
   * Only the shipment owner (customer who placed the order) can confirm delivery. The shipment must currently have 'shipped' status. If the customer does not confirm within 14 days of shipping, the system automatically transitions items to 'delivered'.
   *
   * **Authorization**: Customer must be the owner of the order containing this shipment.
   *
   * **Status Transition**: All order items in this shipment change from 'shipped' to 'delivered'.
   *
   * @param connection
   * @param orderId Unique identifier of the parent order containing this shipment (global scope).
   * @param shipmentId Unique identifier of the shipment to confirm delivery for (global scope).
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification 1. Extract orderId and shipmentId from path parameters.
   * 2. Validate shipmentId is a valid UUID format.
   * 3. Retrieve the shipment by shipmentId.
   * 4. Verify the shipment belongs to the specified orderId.
   * 5. Verify the authenticated customer owns the order (via session JWT).
   * 6. Verify the shipment exists and is not soft-deleted (deleted_at is null).
   * 7. Verify the shipment's order items have 'shipped' status.
   * 8. Begin database transaction:
   *    a. Update all order items linked via ecommerce_mall_shipment_items to 'delivered' status
   *    b. Record the delivery confirmation timestamp
   *    c. Update order item statuses accordingly
   * 9. Commit transaction.
   * 10. Return the updated shipment with its shipment_items and order_item details.
   *
   * **Edge Cases**:
   * - If shipment not found: Return 404.
   * - If shipment belongs to different order: Return 400.
   * - If customer does not own order: Return 403.
   * - If shipment already confirmed (items already 'delivered'): Allow re-confirmation, return success.
   * - If items have status other than 'shipped': Return 400 with validation error.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedParam("shipmentId")
    shipmentId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallShipment> {
    try {
      return await postEcommerceMallCustomerOrdersOrderIdShipmentsShipmentIdConfirmDelivery(
        {
          customer,
          orderId,
          shipmentId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
