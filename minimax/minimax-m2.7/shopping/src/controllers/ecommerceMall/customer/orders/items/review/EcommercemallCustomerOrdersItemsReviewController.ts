import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallReview } from "../../../../../../api/structures/IEcommerceMallReview";
import { CustomerAuth } from "../../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../../decorators/payload/CustomerPayload";
import { postEcommerceMallCustomerOrdersOrderIdItemsItemIdReview } from "../../../../../../providers/postEcommerceMallCustomerOrdersOrderIdItemsItemIdReview";

@Controller("/ecommerceMall/customer/orders/:orderId/items/:itemId/review")
export class EcommercemallCustomerOrdersItemsReviewController {
  /**
   * Create a product review for a delivered order item.
   *
   * This endpoint allows customers to submit reviews for products they have purchased and received. The order item must have a status of 'delivered' before a review can be created. Each customer can write one review per product per order.
   *
   * The review consists of a required star rating (1 to 5) and optional text content for detailed feedback. Upon creation, a review snapshot is automatically generated to preserve the rating and content history for audit purposes.
   *
   * If the associated product has been deleted by the seller, the review can still be created and will display the product name as it appeared at the time of the review. Reviews are displayed on the product detail page sorted by newest first.
   *
   * @param connection
   * @param orderId Unique identifier of the order containing the item being reviewed.
   * @param itemId Unique identifier of the order item (product) being reviewed. The order item must have 'delivered' status.
   * @param body Review content including star rating and optional text feedback.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification 1. Extract authenticated customer ID from session/token
   * 2. Validate orderId exists in ecommerce_mall_orders
   * 3. Validate order belongs to the authenticated customer
   * 4. Validate itemId exists in ecommerce_mall_order_items for the given order
   * 5. Verify order item status is 'delivered' - reject if status is 'paid', 'shipped', 'cancelled', or 'refunded'
   * 6. Check for existing review by this customer for the same order_item_id - reject duplicate reviews
   * 7. Validate rating is between 1 and 5 (inclusive)
   * 8. Validate content length if provided (max 5000 characters recommended)
   * 9. Insert review into ecommerce_mall_reviews table with current timestamp
   * 10. Return the created review record with product and customer information
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedParam("itemId")
    itemId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceMallReview.ICreate,
  ): Promise<IEcommerceMallReview> {
    try {
      return await postEcommerceMallCustomerOrdersOrderIdItemsItemIdReview({
        customer,
        orderId,
        itemId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
