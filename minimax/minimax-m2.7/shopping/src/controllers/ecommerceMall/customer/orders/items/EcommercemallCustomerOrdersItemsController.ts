import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallOrderItem } from "../../../../../api/structures/IEcommerceMallOrderItem";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { getEcommerceMallCustomerOrdersOrderIdItems } from "../../../../../providers/getEcommerceMallCustomerOrdersOrderIdItems";
import { getEcommerceMallCustomerOrdersOrderIdItemsItemId } from "../../../../../providers/getEcommerceMallCustomerOrdersOrderIdItemsItemId";

@Controller("/ecommerceMall/customer/orders/:orderId/items")
export class EcommercemallCustomerOrdersItemsController {
  /**
   * Retrieves all order items for a specific order.
   *
   * This endpoint returns a comprehensive list of all items within an order, including each item's product details as they existed at purchase time (via product snapshots), seller information (via seller profile snapshots), quantities, unit prices, and current item statuses.
   *
   * **Access Control**: Customers can only retrieve items from their own orders. The system enforces ownership verification before returning any data.
   *
   * **Order Item Details**: Each order item includes frozen product state (name, description, variant options, price at purchase time) and seller profile state (shop name, logo at purchase time) captured when the order was placed. This snapshot mechanism preserves what was actually purchased for dispute resolution.
   *
   * **Status Tracking**: Order items maintain individual statuses (paid, shipped, delivered, cancelled, refunded) that may differ from the parent order's overall status. Multiple sellers may be involved in a single order, with items shipped and fulfilled independently.
   *
   * **Error Handling**: Returns 404 if the order does not exist or does not belong to the authenticated customer. Returns 403 if the customer attempts to access another customer's orders.
   *
   * @param connection
   * @param orderId Unique identifier of the order (UUID format). Must belong to the authenticated customer.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query the ecommerce_mall_orders table to verify the order exists and belongs to the authenticated customer. If the order is not found or ownership check fails, return 404 or 403 error accordingly.
   *
   * Query the ecommerce_mall_order_items table with the validated order_id to retrieve all associated order items. Join with ecommerce_mall_product_snapshots to include product details (name, description, option key-value pairs) at purchase time. Join with ecommerce_mall_seller_profile_snapshots to include seller shop details (shop name, logo URL) at purchase time.
   *
   * Order the results by created_at ascending to maintain chronological item addition sequence.
   *
   * For each order item, compute the line_total as quantity multiplied by unit_price. Return the complete order item records with all snapshot data for dispute resolution purposes.
   *
   * If no order items exist for the order, return an empty array with 200 status.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async getByOrderid(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallOrderItem.IInvert> {
    try {
      return await getEcommerceMallCustomerOrdersOrderIdItems({
        customer,
        orderId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves the complete details of a specific order item including the frozen product and seller profile state at the time of purchase.
   *
   * This endpoint returns a single order item with all its associated snapshot data preserved at transaction time. The product snapshot contains the exact product name, description, base price, and category as they appeared when the customer placed the order. The seller profile snapshot shows the shop name, description, and logo that were displayed to the customer at purchase time.
   *
   * The order item status reflects its current fulfillment state: paid (awaiting shipment), shipped (in transit), delivered (received), cancelled (cancelled by seller), or refunded (refunded to customer). Customers can only access order items belonging to their own orders; attempting to access items from other customers' orders returns a not found error for security.
   *
   * The response includes the quantity purchased, unit price frozen at purchase time, and references to the product variant that was ordered. This historical data remains accurate even if the seller later edits the product or shop profile, making it essential for dispute resolution.
   *
   * @param connection
   * @param orderId Unique identifier of the parent order (UUID format). Must belong to the authenticated customer.
   * @param itemId Unique identifier of the order item to retrieve (UUID format). Must belong to the specified order.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query the ecommerce_mall_order_items table filtering by id equal to itemId and ecommerce_mall_order_id equal to orderId.
   *
   * Join with ecommerce_mall_product_snapshots to retrieve the product state at purchase time (name, description, base_price, category_name).
   *
   * Join with ecommerce_mall_seller_profile_snapshots to retrieve the seller shop profile state at purchase time (shop_name, shop_description, logo_url).
   *
   * Join with ecommerce_mall_order_items to verify ownership: the order must belong to the authenticated customer (ecommerce_mall_customer_id matches the session user).
   *
   * Join with ecommerce_mall_product_variants to retrieve variant details (sku, option key-value pairs) if needed for display.
   *
   * Return 404 Not Found if the order item does not exist or does not belong to the specified order.
   *
   * Return 403 Forbidden if the order belongs to a different customer.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":itemId")
  public async getByOrderidAndItemid(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedParam("itemId")
    itemId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallOrderItem> {
    try {
      return await getEcommerceMallCustomerOrdersOrderIdItemsItemId({
        customer,
        orderId,
        itemId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
