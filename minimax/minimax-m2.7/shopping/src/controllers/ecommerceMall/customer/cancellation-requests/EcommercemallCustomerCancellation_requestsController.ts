import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallCancellationRequest } from "../../../../api/structures/IEcommerceMallCancellationRequest";
import { IPageIEcommerceMallCancellationRequest } from "../../../../api/structures/IPageIEcommerceMallCancellationRequest";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { getEcommerceMallCustomerCancellationRequestsRequestId } from "../../../../providers/getEcommerceMallCustomerCancellationRequestsRequestId";
import { patchEcommerceMallCustomerCancellationRequests } from "../../../../providers/patchEcommerceMallCustomerCancellationRequests";
import { postEcommerceMallCustomerCancellationRequests } from "../../../../providers/postEcommerceMallCustomerCancellationRequests";

@Controller("/ecommerceMall/customer/cancellation-requests")
export class EcommercemallCustomerCancellation_requestsController {
  /**
   * Submit a cancellation request for an order item that has not yet shipped.
   *
   * Customers use this endpoint to formally request cancellation of an order item before it ships. The request must include a text reason explaining why cancellation is desired. Once submitted, the seller reviews the request and either approves or rejects it.
   *
   * The system automatically associates the request with the authenticated customer and the appropriate seller based on the order item. Only order items with 'paid' status can be cancelled. If a cancellation request already exists for the same order item, the request is rejected.
   *
   * When the seller approves the cancellation, the order item status changes to 'cancelled' and a refund is processed. If rejected, the cancellation request status becomes 'rejected' and the order item remains unchanged.
   *
   * @param connection
   * @param body Cancellation request details including the order item to cancel and the reason for cancellation.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Validate that the order item exists and belongs to an order owned by the authenticated customer.
   * Verify the order item status is 'paid' (not yet shipped). Return 400 error if order item is already shipped, delivered, cancelled, or refunded.
   * Check that no existing cancellation request exists for the same order item with status 'pending'. Return 409 conflict if a pending cancellation already exists.
   * Retrieve the seller ID from the order item's product relationship.
   * Create a new cancellation request record with status 'pending', current timestamp, and provided reason.
   * Create an immutable snapshot of the cancellation request state for audit trail.
   * Return the created cancellation request with all fields populated.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IEcommerceMallCancellationRequest.ICreate,
  ): Promise<IEcommerceMallCancellationRequest> {
    try {
      return await postEcommerceMallCustomerCancellationRequests({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a filtered and paginated list of cancellation requests from the platform.
   *
   * This operation provides comprehensive search capabilities for cancellation requests, allowing filtering by status (pending, approved, rejected), customer reference, seller reference, and date range. Results are sorted by creation date in descending order by default.
   *
   * Administrative users can view all cancellation requests across the platform. The response includes request summaries with customer and seller identifiers, current status, and timestamps for efficient list display and dashboard integration.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering cancellation requests
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query ecommerce_mall_cancellation_requests table with pagination and filtering.
   *
   * Apply search filters:
   * - status: Filter by cancellation request status (pending, approved, rejected)
   * - customerId: Filter by customer who submitted the request
   * - sellerId: Filter by seller who owns the order item
   * - createdAtFrom/createdAtTo: Filter by creation date range
   * - orderBy: Sort field (default: created_at DESC)
   * - page/limit: Pagination parameters
   *
   * Join with ecommerce_mall_order_items when additional order context needed for filtering.
   *
   * Return paginated results with total count, page info, and request summaries.
   *
   * Implement cursor-based pagination for large result sets.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IEcommerceMallCancellationRequest.IRequest,
  ): Promise<IPageIEcommerceMallCancellationRequest.ISummary> {
    try {
      return await patchEcommerceMallCustomerCancellationRequests({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single cancellation request by its unique identifier.
   *
   * This endpoint returns the complete cancellation request details including the reason text, current status (pending, approved, or rejected), timestamps, and references to the associated order item, customer, and seller.
   *
   * The cancellation request is immutable once created. When a seller responds to the request, a snapshot is automatically created preserving the request state at that moment for audit and dispute resolution purposes.
   *
   * Only the customer who created the request, the seller who owns the order item, or administrators can access this endpoint.
   *
   * @param connection
   * @param requestId Unique identifier of the cancellation request (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query ecommerce_mall_cancellation_requests table by the provided requestId (UUID).
   *
   * Verify the requestId exists in the database. If not found, return 404 error.
   *
   * Return the complete cancellation request entity including:
   * - id: UUID primary key
   * - ecommerce_mall_order_item_id: UUID reference to the order item
   * - ecommerce_mall_customer_id: UUID reference to the customer who created the request
   * - ecommerce_mall_seller_id: UUID reference to the seller who owns the order item
   * - reason: text describing why cancellation was requested
   * - status: current status (pending, approved, rejected)
   * - created_at: timestamp when request was created
   * - updated_at: timestamp when request was last updated
   *
   * Include related cancellation_request_snapshots ordered by created_at descending to show the state history.
   *
   * Authorization: Allow access if the authenticated user is the customer who created the request, the seller who owns the order item, or an administrator.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":requestId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("requestId")
    requestId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallCancellationRequest.IInvert> {
    try {
      return await getEcommerceMallCustomerCancellationRequestsRequestId({
        customer,
        requestId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
