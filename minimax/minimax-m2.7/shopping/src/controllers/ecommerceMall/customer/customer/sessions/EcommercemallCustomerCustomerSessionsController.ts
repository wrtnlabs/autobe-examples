import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallCustomerSession } from "../../../../../api/structures/IEcommerceMallCustomerSession";
import { IPageIEcommerceMallCustomerSession } from "../../../../../api/structures/IPageIEcommerceMallCustomerSession";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { getEcommerceMallCustomerCustomerSessionsSessionId } from "../../../../../providers/getEcommerceMallCustomerCustomerSessionsSessionId";
import { patchEcommerceMallCustomerCustomerSessions } from "../../../../../providers/patchEcommerceMallCustomerCustomerSessions";

@Controller("/ecommerceMall/customer/customer/sessions")
export class EcommercemallCustomerCustomerSessionsController {
  /**
   * Retrieve a paginated list of the authenticated customer's login sessions.
   *
   * This operation allows customers to view their active and recent sessions across all devices. Each session record includes the device IP address, pages visited, and session expiration timestamp. Customers can use this to review their login history and identify any suspicious activity on their account.
   *
   * Sessions are ordered by creation date (newest first) by default. The response includes a summary view optimized for list display with key session metadata.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering sessions
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query ecommerce_mall_customer_sessions table filtering by the authenticated customer ID.
   *
   * Apply the following filters if provided in the request body:
   * - status: filter for 'active' (expired_at > now()) or 'expired' (expired_at <= now()) sessions
   * - createdFrom/createdTo: filter sessions created within date range
   *
   * Join with ecommerce_mall_customers table to verify session ownership (customer must match authenticated user).
   *
   * Order by created_at descending (newest first) by default.
   *
   * Implement cursor-based or offset pagination with configurable page size (default 20, max 100).
   *
   * Return session summary information: id, ip, href, referrer, created_at, expired_at, isActive (computed field).
   *
   * If no sessions found, return empty array with pagination metadata showing total: 0.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IEcommerceMallCustomerSession.IRequest,
  ): Promise<IPageIEcommerceMallCustomerSession.ISummary> {
    try {
      return await patchEcommerceMallCustomerCustomerSessions({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve details of a specific customer session by its unique identifier.
   *
   * This endpoint returns comprehensive information about a customer session including the session's creation timestamp, last activity via the href field, client device information through IP address and referrer headers, and the session expiration time. The authenticated customer can only retrieve their own sessions; attempting to access another customer's session results in a not found error for security reasons.
   *
   * Session data is primarily used for security auditing and session management purposes. Applications typically display active sessions to customers so they can identify and understand their login activity across devices.
   *
   * @param connection
   * @param sessionId Unique identifier of the customer session to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query the ecommerce_mall_customer_sessions table using the provided sessionId as the primary key.
   *
   * Validate that the session belongs to the authenticated customer by comparing ecommerce_mall_customer_id in the session record with the authenticated customer's ID from the session context. Return 404 Not Found if the session does not exist or does not belong to the customer.
   *
   * Verify the session has not expired by checking if current time is before expired_at. Return 401 Unauthorized with appropriate message if the session is expired.
   *
   * Return the full session record including: id, ecommerce_mall_customer_id, ip, href, referrer, created_at, updated_at, and expired_at. Exclude access_token and refresh_token from the response for security.
   *
   * Include related customer information in the response if available from the customer relation.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallCustomerSession> {
    try {
      return await getEcommerceMallCustomerCustomerSessionsSessionId({
        customer,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
