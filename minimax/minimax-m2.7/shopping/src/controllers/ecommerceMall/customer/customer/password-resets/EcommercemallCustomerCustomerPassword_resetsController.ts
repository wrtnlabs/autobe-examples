import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallCustomerPasswordReset } from "../../../../../api/structures/IEcommerceMallCustomerPasswordReset";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { getEcommerceMallCustomerCustomerPasswordResetsResetId } from "../../../../../providers/getEcommerceMallCustomerCustomerPasswordResetsResetId";
import { patchEcommerceMallCustomerCustomerPasswordResets } from "../../../../../providers/patchEcommerceMallCustomerCustomerPasswordResets";

@Controller("/ecommerceMall/customer/customer/password-resets")
export class EcommercemallCustomerCustomerPassword_resetsController {
  /**
   * Reset customer password using a valid password reset token.
   *
   * This endpoint allows customers who have requested a password reset to set a new password. The token must be valid (not expired, not already used) and belongs to the customer making the request. Upon successful password reset, the token is marked as used and cannot be reused.
   *
   * The customer must provide the reset token received via email and a new password meeting security requirements. After successful reset, the customer can log in with the new password. All existing sessions are invalidated for security.
   *
   * This operation differs from the change-password endpoint which requires the current password. Password reset is used when the customer has forgotten their current password.
   *
   * @param connection
   * @param body Password reset request containing the token and new password
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Validate the provided password reset token against the ecommerce_mall_customer_password_resets table.
   *
   * 1. Token Validation:
   *    - Verify token exists in database
   *    - Verify token has not been used (used_at is null)
   *    - Verify token has not expired (expires_at > current timestamp)
   *    - Return 400 error if token is invalid, expired, or already used
   *
   * 2. Customer Identification:
   *    - Extract ecommerce_mall_customer_id from the valid token
   *    - Verify the customer account exists and is active (deleted_at is null)
   *    - Return 404 error if customer not found or deleted
   *
   * 3. New Password Validation:
   *    - Validate new password meets security requirements
   *    - Return 400 error with validation details if password is weak
   *
   * 4. Password Update:
   *    - Hash the new password securely
   *    - Update password_hash in ecommerce_mall_customers table
   *    - Set used_at timestamp on the password reset token
   *    - Perform both updates in a transaction
   *
   * 5. Session Invalidation:
   *    - Invalidate all existing customer sessions for security
   *    - Delete all records from ecommerce_mall_customer_sessions for this customer
   *
   * 6. Error Handling:
   *    - Return 400 for invalid/expired/used token or weak password
   *    - Return 404 for non-existent or deleted customer
   *    - Return 500 for database or system errors with generic message
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async resetPassword(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IEcommerceMallCustomerPasswordReset.IRequest,
  ): Promise<void> {
    try {
      return await patchEcommerceMallCustomerCustomerPasswordResets({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve details of a specific password reset request for the authenticated customer.
   *
   * This endpoint allows customers to view the status of their password reset request by providing the reset request ID. The response includes the expiration timestamp and whether the reset token has been used.
   *
   * The customer can only access their own password reset requests. Attempting to access another customer's password reset record will result in a not found error for security reasons.
   *
   * If the reset token has expired, the customer should request a new password reset. If the token has already been used, the password has been successfully changed.
   *
   * @param connection
   * @param resetId Unique identifier of the password reset request (UUID)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query ecommerce_mall_customer_password_resets table by the provided resetId (UUID). Verify the customer_id in the password reset record matches the authenticated customer's ID from the session token. If the record does not exist or belongs to a different customer, return a 404 error.
   *
   * Return the password reset details including id, expires_at timestamp, and used_at timestamp. Do NOT return the token field in the response for security reasons.
   *
   * If expires_at is in the past and used_at is null, the token is expired. If used_at is not null, the token has been used.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":resetId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("resetId")
    resetId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallCustomerPasswordReset> {
    try {
      return await getEcommerceMallCustomerCustomerPasswordResetsResetId({
        customer,
        resetId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
