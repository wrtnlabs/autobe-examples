import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallWishlistItem } from "../../../../api/structures/IEcommerceMallWishlistItem";
import { IPageIEcommerceMallWishlistItem } from "../../../../api/structures/IPageIEcommerceMallWishlistItem";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { deleteEcommerceMallCustomerWishlistProductId } from "../../../../providers/deleteEcommerceMallCustomerWishlistProductId";
import { patchEcommerceMallCustomerWishlist } from "../../../../providers/patchEcommerceMallCustomerWishlist";
import { postEcommerceMallCustomerWishlist } from "../../../../providers/postEcommerceMallCustomerWishlist";

@Controller("/ecommerceMall/customer/wishlist")
export class EcommercemallCustomerWishlistController {
  /**
   * Adds a product to the authenticated customer's wishlist.
   *
   * This endpoint allows customers to bookmark products for future purchase consideration. A product can only appear once in a customer's wishlist; attempting to add a duplicate returns an appropriate error. Products can be added regardless of their current stock status, as wishlist serves as a reference list rather than a commitment to purchase.
   *
   * **Request Validation**:
   * - Verifies the specified product exists in the system
   * - Verifies the product has not been deleted by the seller
   * - Enforces that each product appears only once per customer wishlist
   *
   * **Ownership**: The wishlist is automatically associated with the authenticated customer making the request.
   *
   * **Error Handling**:
   * - Returns 404 if the product does not exist or has been deleted
   * - Returns 409 Conflict if the product is already in the customer's wishlist
   * - Returns 401 if the customer is not authenticated
   *
   * @param connection
   * @param body Contains the product identifier to add to the customer's wishlist. Only the productId field is required.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification 1. Extract authenticated customer ID from request
     *   context (JWT token) 2. Get or validate that the customer has an
     *   existing wishlist (should exist from registration) 3. Extract productId
     *   from request body 4. Verify the product exists in
     *   ecommerce_mall_products and has not been deleted (status = 'ACTIVE') 5.
     *   Check if wishlist item already exists for this wishlist and product
     *   (prevent duplicates) 6. If duplicate found, return 409 Conflict with
     *   descriptive message 7. If product not found or deleted, return 404 Not
     *   Found 8. Create new wishlist item with: - ecommerce_mall_wishlist_id =
     *   customer's wishlist id - ecommerce_mall_product_id = provided productId
     *   - created_at = current timestamp 9. Return created wishlist item with
     *   product details included
   *
   * **Edge Cases**:
   * - Customer without a wishlist: Create one automatically
   * - Product deleted mid-request: Return appropriate error
   * - Race condition on duplicate: Database unique constraint handles this atomically
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IEcommerceMallWishlistItem.ICreate,
  ): Promise<IEcommerceMallWishlistItem> {
    try {
      return await postEcommerceMallCustomerWishlist({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Lists and searches a customer's wishlist items with pagination support.
   *
   * This endpoint retrieves the authenticated customer's wishlist, returning a paginated collection of wishlist items. Each item includes the associated product information. The operation supports filtering by product name and sorting by creation date.
   *
   * **Pagination**: Results are returned in pages with configurable page size and page number. The response includes pagination metadata for client-side navigation.
   *
   * **Filtering**: Clients can filter wishlist items by searching product names within the wishlist.
   *
   * **Sorting**: Items are sorted by creation date (newest first) by default.
   *
   * **Relationship**: Each wishlist item belongs to exactly one wishlist (the customer's wishlist). The response includes nested product details for each wishlist item.
   *
   * @param connection
   * @param body Search criteria including optional product name filter and pagination parameters.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification Query the ecommerce_mall_wishlists table to find
     *   the customer's wishlist using the authenticated customer ID from the
     *   JWT token.
   *
   * Query ecommerce_mall_wishlist_items table with JOIN to ecommerce_mall_products to retrieve wishlist items along with their product details.
   *
   * Apply the following filters from IRequest:
   * - Filter by product name if search query is provided (case-insensitive partial match on product name)
   * - Join with products table to access product fields for filtering
   *
   * Return paginated results ordered by wishlist item creation date (newest first by default).
   *
   * For each wishlist item, include:
   * - Wishlist item ID and creation timestamp
   * - Product ID, name, base price, and primary image
   * - Product availability status (check if product.deleted_at is null)
   *
   * Handle empty wishlist gracefully by returning empty data array with pagination showing zero total.
   *
   * Validate that the customer has an active wishlist. If no wishlist exists, return empty results.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IEcommerceMallWishlistItem.IRequest,
  ): Promise<IPageIEcommerceMallWishlistItem.ISummary> {
    try {
      return await patchEcommerceMallCustomerWishlist({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Removes a product from the authenticated customer's wishlist.
   *
   * WHEN a customer removes a product from their wishlist, THE system SHALL delete the wishlist entry for that product.
   *
   * This operation requires the customer to be authenticated via Bearer token. The product must exist in the customer's wishlist; attempting to remove a product not in the wishlist returns a 404 error. Customers can only remove items from their own wishlist, enforced by session validation.
   *
   * **Ownership Validation**: The system verifies the authenticated customer owns the wishlist containing the specified product. Customers cannot remove items from other customers' wishlists.
   *
   * **Product Existence**: The system validates that the referenced product still exists before processing removal. If the product has been deleted, the wishlist item would have been automatically removed during product deletion, so a 404 is returned.
   *
   * **Automatic Cleanup**: Wishlist items are automatically removed when sellers delete products. This operation handles manual customer-initiated removal.
   *
   * @param connection
   * @param productId UUID of the product to remove from wishlist
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification 1. Extract authenticated customer from JWT
     *   session token in Authorization header. 2. Retrieve the customer's
     *   wishlist ID from ecommerce_mall_wishlists using shopping_customer_id
     *   from session. 3. Query ecommerce_mall_wishlist_items to find entry
     *   where ecommerce_mall_wishlist_id equals customer's wishlist ID AND
     *   ecommerce_mall_product_id equals {productId}. 4. If no matching
     *   wishlist item found, return 404 error with message 'Wishlist item not
     *   found'. 5. If found, delete the wishlist item from
     *   ecommerce_mall_wishlist_items table. 6. Return 204 No Content on
     *   successful deletion.
   *
   * Edge cases:
   * - Invalid productId format (non-UUID): return 400 Bad Request
   * - Product not in customer's wishlist: return 404 Not Found
   * - Unauthenticated request: return 401 Unauthorized
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":productId")
  public async erase(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteEcommerceMallCustomerWishlistProductId({
        customer,
        productId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
