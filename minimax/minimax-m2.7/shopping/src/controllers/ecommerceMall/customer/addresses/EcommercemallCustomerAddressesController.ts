import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallShippingAddress } from "../../../../api/structures/IEcommerceMallShippingAddress";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { getEcommerceMallCustomerAddressesAddressId } from "../../../../providers/getEcommerceMallCustomerAddressesAddressId";
import { putEcommerceMallCustomerAddressesAddressId } from "../../../../providers/putEcommerceMallCustomerAddressesAddressId";

@Controller("/ecommerceMall/customer/addresses/:addressId")
export class EcommercemallCustomerAddressesController {
  /**
   * Retrieves a specific shipping address by its unique identifier.
   *
   * This endpoint returns the complete details of a single shipping address belonging to the authenticated customer. The operation enforces data isolation — customers can only access their own addresses.
   *
   * **Ownership Verification**: The system verifies that the requested address belongs to the authenticated customer before returning any data. Attempts to access addresses belonging to other customers result in a not-found response for security reasons.
   *
   * **Soft-Deleted Addresses**: Addresses that have been deleted are not returned. If a customer attempts to retrieve a previously deleted address, the system returns a not-found response.
   *
   * **Related Operations**: To list all addresses, use `PATCH /addresses` (index). To modify an address, use `PATCH /addresses/{addressId}`. To delete an address, use `DELETE /addresses/{addressId}`.
   *
   * @param connection
   * @param addressId Unique identifier of the shipping address to retrieve. Must be a valid UUID.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query the ecommerce_mall_shipping_addresses table filtering by:
   * - id = :addressId (UUID primary key)
   * - ecommerce_mall_customer_id = :customerId (from authenticated session)
   * - deleted_at IS NULL (exclude soft-deleted addresses)
   *
   * If no matching record is found, return HTTP 404 Not Found with error message "Address not found".
   *
   * The customerId is extracted from the authenticated user's session/token, not from request parameters. This ensures customers can only view their own addresses.
   *
   * Return all fields from the matched record: id, ecommerce_mall_customer_id, recipient_name, phone, street_address, city, state, postal_code, country, is_default, created_at, updated_at.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("addressId")
    addressId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallShippingAddress> {
    try {
      return await getEcommerceMallCustomerAddressesAddressId({
        customer,
        addressId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Updates an existing shipping address for the authenticated customer.
   *
   * This operation allows customers to modify any field of their stored shipping address including recipient name, phone number, street address, city, state, postal code, and country. When editing, all fields are validated and required.
   *
   * **Ownership verification**: The system verifies that the address belongs to the authenticated customer making the request. Addresses belonging to other customers cannot be modified.
   *
   * **Default status preservation**: If the address being edited was the customer's default shipping address, its default status is preserved after the update. Customers can change their default address separately using the set-default endpoint.
   *
   * **Soft-delete handling**: Deleted addresses cannot be updated. The system returns 404 if the address exists but has been soft-deleted.
   *
   * **Response**: Returns the complete updated address object with all current values.
   *
   * @param connection
   * @param addressId Unique identifier of the shipping address to update (UUID format, scoped to the authenticated customer).
   * @param body Complete address update payload containing all address fields. All fields are required. System fields (id, customer_id, created_at, deleted_at) are not accepted and will be ignored.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Update the shipping address identified by {addressId} belonging to the authenticated customer.
   *
   * 1. **Authentication**: Verify customer is authenticated via JWT token. Extract customer_id from token.
   *
   * 2. **Input validation**:
   *    - addressId must be a valid UUID format
   *    - All address fields are required: recipient_name, phone, street_address, city, state, postal_code, country
   *    - recipient_name: non-empty string, reasonable length
   *    - phone: valid phone number format
   *    - street_address, city, state, postal_code, country: non-empty strings
   *
   * 3. **Ownership check**: Query ecommerce_mall_shipping_addresses where id = addressId AND ecommerce_mall_customer_id = customer_id AND deleted_at IS NULL. If not found, return 404.
   *
   * 4. **Update operation**: Update the record with provided fields. Set updated_at to current timestamp. Preserve is_default value.
   *
   * 5. **Response**: Return the full updated address record.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("addressId")
    addressId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceMallShippingAddress.IUpdate,
  ): Promise<IEcommerceMallShippingAddress> {
    try {
      return await putEcommerceMallCustomerAddressesAddressId({
        customer,
        addressId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
