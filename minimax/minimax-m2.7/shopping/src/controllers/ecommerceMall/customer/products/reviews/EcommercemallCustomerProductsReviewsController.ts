import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIEcommerceMallReview } from "../../../../../api/structures/IPageIEcommerceMallReview";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { getEcommerceMallCustomerProductsProductIdReviews } from "../../../../../providers/getEcommerceMallCustomerProductsProductIdReviews";

@Controller("/ecommerceMall/customer/products/:productId/reviews")
export class EcommercemallCustomerProductsReviewsController {
  /**
   * Retrieve a paginated list of reviews for a specific product to help customers make informed purchasing decisions.
   *
   * This endpoint returns all non-deleted reviews associated with the product, sorted by creation date with the newest reviews appearing first. Each review includes the customer rating (1-5 stars) and any text content provided by the reviewer.
   *
   * The response is paginated to handle products with many reviews efficiently. Empty pages indicate no reviews exist for the product. Reviews remain visible even after the product is deleted by the seller, preserving customer feedback history.
   *
   * @param connection
   * @param productId Unique identifier of the product to retrieve reviews for
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query ecommerce_mall_reviews table filtered by ecommerce_mall_product_id matching the path parameter. Exclude soft-deleted reviews where deleted_at IS NOT NULL. Order results by created_at in descending order (newest first).
   *
   * Implement offset-based pagination with page and limit parameters. Default page size is 20, maximum 100. Join with ecommerce_mall_customer_profiles to include reviewer display name in response.
   *
   * If no reviews exist for the product, return empty data array with pagination showing total: 0. Handle invalid productId by returning empty result (product may not exist but we still return valid pagination structure).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
  ): Promise<IPageIEcommerceMallReview.ISummary> {
    try {
      return await getEcommerceMallCustomerProductsProductIdReviews({
        customer,
        productId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
