import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallProduct } from "../../../../../api/structures/IEcommerceMallProduct";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { getEcommerceMallCustomerProductsProductIdEnriched } from "../../../../../providers/getEcommerceMallCustomerProductsProductIdEnriched";

@Controller("/ecommerceMall/customer/products/:productId/enriched")
export class EcommercemallCustomerProductsEnrichedController {
  /**
   * Retrieves comprehensive product information including all variants, images, reviews, seller profile, and category details. This enriched endpoint provides the complete data needed for a product detail page. Only active (non-deleted) products are returned. If the product is deleted, returns 404 Not Found.
   *
   * **Product Information**: Returns full product details including name, description, base price, creation date, and update timestamp.
   *
   * **Product Variants**: Includes all active variants with their SKU codes, option values (color, size, etc.), price overrides, and current stock quantities.
   *
   * **Product Images**: Returns all product images ordered by display order, with the first image being the main thumbnail.
   *
   * **Review Statistics**: Includes average rating and total review count for customer evaluation.
   *
   * **Seller Information**: Returns shop name and logo for the seller's profile, allowing customers to identify the seller.
   *
   * **Category Information**: Returns the assigned category details for product taxonomy display.
   *
   * @param connection
   * @param productId Unique identifier of the product to retrieve.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query ecommerce_mall_products table filtering by id = {productId} AND deleted_at IS NULL. If not found, return 404.
   *
   * Join and include related data:
   * 1. ecommerce_mall_product_images: Get all images for the product ordered by display_order ASC
   * 2. ecommerce_mall_product_variants: Get all variants where deleted_at IS NULL, including option values from ecommerce_mall_product_variant_option_values
   * 3. ecommerce_mall_reviews: Calculate AVG(rating) as averageRating and COUNT(*) as reviewCount for the product (excluding deleted reviews)
   * 4. ecommerce_mall_seller_profiles: Join to get shop name and logo_uri for the seller
   * 5. ecommerce_mall_categories: Join to get category name
   *
   * Construct the enriched response with all related data nested appropriately.
   *
   * Handle case where product has no variants (quantity = 0 for all) - still return product but mark as out of stock.
   *
   * Edge cases:
   * - Product not found → 404
   * - Product deleted → 404 (per Section 103: deleted products not visible)
   * - No variants → return product with empty variants array
   * - No images → return product with empty images array
   * - No reviews → return with averageRating = 0, reviewCount = 0
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallProduct.IEnriched> {
    try {
      return await getEcommerceMallCustomerProductsProductIdEnriched({
        customer,
        productId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
