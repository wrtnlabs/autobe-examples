import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallCustomerSession } from "../../../../api/structures/IEcommerceMallCustomerSession";
import { IPageIEcommerceMallCustomerSession } from "../../../../api/structures/IPageIEcommerceMallCustomerSession";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { getEcommerceMallCustomerSessionsSessionId } from "../../../../providers/getEcommerceMallCustomerSessionsSessionId";
import { patchEcommerceMallCustomerSessions } from "../../../../providers/patchEcommerceMallCustomerSessions";

@Controller("/ecommerceMall/customer/sessions")
export class EcommercemallCustomerSessionsController {
  /**
   * Retrieve a filtered and paginated list of user sessions across all actor types.
   *
   * This operation provides comprehensive session search capabilities for platform administrators to monitor and audit user authentication activity. Sessions represent authenticated user access to the platform and include security-relevant metadata such as IP addresses, navigation paths, and session timestamps.
   *
   * The endpoint supports filtering by actor type (customer, seller, admin, super_admin, guest) to narrow results to specific user categories. Date range filtering allows searching sessions within specific time windows for incident investigation or security audits. Session status filtering distinguishes between active and expired sessions.
   *
   * Each session record includes the associated user identifier, client IP address for security tracking, navigation context (current URL and referrer), creation timestamp, and expiration timestamp. This information supports security auditing, fraud detection, and session management workflows.
   *
   * The response is paginated with configurable page sizes and supports cursor-based pagination for efficient traversal of large result sets. Results are sorted by creation timestamp in descending order by default to show the most recent sessions first.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering sessions
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query session records from all actor-specific session tables (ecommerce_mall_customer_sessions, ecommerce_mall_seller_sessions, ecommerce_mall_admin_sessions, ecommerce_mall_super_admin_sessions, ecommerce_mall_guest_sessions).
   *
   * 1. If actorType filter is specified, query only the corresponding session table.
   * 2. If actorType filter is not specified, UNION results from all session tables with actor type indicator.
   * 3. Apply date range filters on created_at field.
   * 4. Apply IP address partial matching if provided.
   * 5. Filter by session status: 'active' (expired_at > current_time) or 'expired' (expired_at <= current_time).
   * 6. Return results ordered by created_at DESC with cursor-based pagination.
   * 7. Include associated user identifier and actor type in response for each session.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IEcommerceMallCustomerSession.IRequest,
  ): Promise<IPageIEcommerceMallCustomerSession.ISummary> {
    try {
      return await patchEcommerceMallCustomerSessions({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about the current authenticated customer's session by its unique identifier.
   *
   * This endpoint returns comprehensive session metadata including the session owner's customer reference ID, client IP address, current navigation context (href and referrer), creation timestamp, last update timestamp, and expiration timestamp. For customer sessions, it also includes access and refresh token information for token management purposes.
   *
   * The session data enables customers to view their active session details such as login location (IP address), device context (referrer), and session validity period including expiration time. This information helps customers verify their account security and session status.
   *
   * Session records serve as immutable audit trails - this endpoint provides read-only access to session metadata. Sessions cannot be modified or extended through this operation. Customers can only access their own sessions.
   *
   * @param connection
   * @param sessionId Unique identifier of the session to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query the appropriate session table based on session ID format or try each session type. Extract session ID from path parameter. Retrieve session record including: id, user reference ID, ip address, href, referrer, created_at, expired_at. For customer/seller sessions, also include access_token and refresh_token. Return session metadata with appropriate user type discriminator.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallCustomerSession> {
    try {
      return await getEcommerceMallCustomerSessionsSessionId({
        customer,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
