import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallProduct } from "../../../../../api/structures/IEcommerceMallProduct";
import { IPageIEcommerceMallProduct } from "../../../../../api/structures/IPageIEcommerceMallProduct";
import { GuestAuth } from "../../../../../decorators/GuestAuth";
import { GuestPayload } from "../../../../../decorators/payload/GuestPayload";
import { patchEcommerceMallGuestProductsSearch } from "../../../../../providers/patchEcommerceMallGuestProductsSearch";

@Controller("/ecommerceMall/guest/products/search")
export class EcommercemallGuestProductsSearchController {
  /**
   * Search for products in the marketplace using various filters and sorting options.
   *
   * This endpoint allows customers and guests to discover products through keyword search, category browsing, price filtering, and availability filtering. Search results return product summaries optimized for list display, including the main thumbnail image, product name, price range (when variants have different prices), the shop name of the selling seller, and the product's average rating from customer reviews.
   *
   * Products are searchable by their name and description using full-text search. Results can be filtered to show only products within a specific category, within a price range, or that are currently in stock. The sort parameter controls the order of results by newest first, lowest price first, or highest price first.
   *
   * Deleted products are not included in search results. Products without variants or with all variants out of stock appear in search but are marked as unavailable. Products without a category assignment (uncategorized) appear in search results when the query matches the product name.
   *
   * @param connection
   * @param body Search criteria including keyword query, category filter, price range filter, stock availability filter, sorting option, and pagination parameters.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification Implement product search with the following requirements:
   *
   * **Database Query Strategy**:
   * - Query ecommerce_mall_products table with filters on deleted_at IS NULL
   * - Apply GIN trigram index for name/description search (use ILIKE or trgm_similar for partial matching)
   * - Filter by ecommerce_mall_category_id if categoryId provided
   * - Filter by base_price range if minPrice/maxPrice provided
   * - Filter by stock availability: check ecommerce_mall_product_variants for quantity > 0
   * - Join with ecommerce_mall_sellers and ecommerce_mall_seller_profiles for shop name
   * - Join with ecommerce_mall_product_images to get first image (display_order = 0) as thumbnail
   * - Join with ecommerce_mall_reviews to calculate average rating
   *
   * **Filtering Logic**:
   * - `q` parameter: Search in product name and description (case-insensitive partial match)
   * - `categoryId`: Exact match on ecommerce_mall_category_id
   * - `minPrice`: base_price >= minPrice (apply to products without price override variants)
   * - `maxPrice`: base_price <= maxPrice
   * - `inStock`: When true, filter products that have at least one variant with quantity > 0
   *
   * **Sorting Options**:
   * - `newest`: ORDER BY created_at DESC
   * - `price_asc`: ORDER BY base_price ASC
   * - `price_desc`: ORDER BY base_price DESC
   *
   * **Response Construction**:
   * - Calculate price range from variants (MIN/MAX of COALESCE(variant.price, product.base_price))
   * - Get first product image (display_order = 0) as thumbnail_url
   * - Calculate average rating from reviews table (AVG(rating))
   * - Count total reviews for each product
   *
   * **Pagination**: Use page and limit parameters with OFFSET/LIMIT. Return total count for pagination metadata.
   *
   * **Price Range Display**: When min_variant_price differs from max_variant_price, return both values to display as a range.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @GuestAuth()
    guest: GuestPayload,
    @TypedBody()
    body: IEcommerceMallProduct.IRequest,
  ): Promise<IPageIEcommerceMallProduct.ISummary> {
    try {
      return await patchEcommerceMallGuestProductsSearch({
        guest,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
