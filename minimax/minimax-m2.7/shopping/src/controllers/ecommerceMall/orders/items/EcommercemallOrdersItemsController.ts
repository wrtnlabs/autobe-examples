import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallOrderItem } from "../../../../api/structures/IEcommerceMallOrderItem";
import { IPageIEcommerceMallOrderItem } from "../../../../api/structures/IPageIEcommerceMallOrderItem";
import { getEcommerceMallOrdersOrderIdItemsOrderItemId } from "../../../../providers/getEcommerceMallOrdersOrderIdItemsOrderItemId";
import { patchEcommerceMallOrdersOrderIdItems } from "../../../../providers/patchEcommerceMallOrdersOrderIdItems";

@Controller("/ecommerceMall/orders/:orderId/items")
export class EcommercemallOrdersItemsController {
  /**
   * Retrieve a filtered and paginated list of order items for a specific order.
   *
   * This endpoint allows customers and administrators to view order items within a specific order. Customers can only access their own orders, while administrators can access any order on the platform.
   *
   * The operation supports filtering by item status (paid, shipped, delivered, cancelled, refunded) and returns comprehensive item information including product snapshots, quantities, unit prices, and current status.
   *
   * Order items are immutable records that preserve the product state at the time of purchase through product snapshots. Each item shows the frozen price, quantity, and product information for dispute resolution.
   *
   * Paginated results are returned with configurable page sizes. The response includes summary information optimized for list displays showing item details, status indicators, and pricing.
   *
   * Soft Delete Handling: Items are only accessible for active orders. If the parent order has been soft-deleted (deleted_at timestamp is set), the system returns an empty result set rather than exposing items from cancelled or archived orders.
   *
   * @param connection
   * @param orderId Unique identifier (UUID) of the parent order
   * @param body Search filters and pagination parameters for order items
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query ecommerce_mall_order_items table filtering by orderId.
   *
   * Join with ecommerce_mall_product_snapshots to retrieve product name, description, and base price at purchase time.
   * Join with ecommerce_mall_product_snapshot_variants to get variant SKU and option values.
   * Join with ecommerce_mall_seller_profile_snapshots to get seller shop name.
   *
   * Apply status filter if provided in request body (allowed values: paid, shipped, delivered, cancelled, refunded).
   * Apply pagination using cursor or offset-based pagination with configurable page size.
   * Order results by created_at descending (newest first).
   *
   * Authorization check: If requester is customer, verify ecommerce_mall_order_id belongs to their customer account. If requester is admin, allow access to all orders.
   *
   * Return empty results (not error) if order exists but has no items matching filters.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceMallOrderItem.IRequest,
  ): Promise<IPageIEcommerceMallOrderItem.ISummary> {
    try {
      return await patchEcommerceMallOrdersOrderIdItems({
        orderId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific order item with its complete purchase-time context.
   *
   * This endpoint returns detailed information about a single order item including the frozen product state (name, description, price as purchased), variant details (SKU, options), and seller shop information at the time of purchase.
   *
   * The response includes the product snapshot capturing what the product looked like when the customer placed the order, preserving historical data even if the product has since been edited or deleted. Similarly, the seller profile snapshot preserves the shop name and logo shown to the customer at purchase time.
   *
   * This endpoint is accessible to customers viewing their own orders, sellers viewing order items for their products, and administrators performing platform oversight. Customers can only access items in their own orders, while sellers can only access items for products they own.
   *
   * @param connection
   * @param orderId Unique identifier of the parent order (UUID format)
   * @param orderItemId Unique identifier of the order item to retrieve (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query the ecommerce_mall_order_items table using the provided orderId and orderItemId path parameters.
   *
   * Validate that the order item belongs to the specified order by checking ecommerce_mall_order_id matches orderId.
   *
   * Authorization checks:
   * - For customers: Verify the order belongs to the authenticated customer (ecommerce_mall_customer_id matches session)
   * - For sellers: Verify the order item's product belongs to the authenticated seller
   * - For admins: Allow unrestricted access
   *
   * Join and load related data:
   * 1. Load ecommerce_mall_product_snapshots record via ecommerce_mall_product_snapshot_id
   * 2. Load ecommerce_mall_seller_profile_snapshots record via ecommerce_mall_seller_profile_snapshot_id
   * 3. Load ecommerce_mall_product_variants record via ecommerce_mall_product_variant_id
   * 4. Load the parent order via ecommerce_mall_order_id for order context
   *
   * For the product variant, also load its option values from ecommerce_mall_product_variant_option_values table to provide complete variant information.
   *
   * Return the complete order item with all nested snapshot data. If order item not found or unauthorized, return 404. If order not found or does not match orderId, return 400.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":orderItemId")
  public async at(
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedParam("orderItemId")
    orderItemId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallOrderItem> {
    try {
      return await getEcommerceMallOrdersOrderIdItemsOrderItemId({
        orderId,
        orderItemId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
