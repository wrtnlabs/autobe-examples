import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallShipment } from "../../../../api/structures/IEcommerceMallShipment";
import { IPageIEcommerceMallShipment } from "../../../../api/structures/IPageIEcommerceMallShipment";
import { getEcommerceMallOrdersOrderIdShipmentsShipmentId } from "../../../../providers/getEcommerceMallOrdersOrderIdShipmentsShipmentId";
import { patchEcommerceMallOrdersOrderIdShipments } from "../../../../providers/patchEcommerceMallOrdersOrderIdShipments";

@Controller("/ecommerceMall/orders/:orderId/shipments")
export class EcommercemallOrdersShipmentsController {
  /**
   * Retrieve a paginated list of shipments for a specific order.
   *
   * This endpoint allows customers to view all shipments associated with their order, including tracking information, carrier details, and shipment status. Each shipment is created by a seller and may contain one or more order items.
   *
   * The response includes shipment summaries with essential tracking information. For detailed shipment contents, use the order detail endpoint which includes full shipment item information. Shipments are returned in chronological order by creation date.
   *
   * This operation is primarily used after order placement to monitor shipment progress and track deliveries.
   *
   * @param connection
   * @param orderId Unique identifier of the order (UUID format)
   * @param body Pagination parameters including page number and page size
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query ecommerce_mall_shipments table filtered by the orderId path parameter. Include shipment_items join to get item count per shipment. Order results by created_at descending (newest first).
   *
   * Validate that the authenticated customer owns the order. Return 403 Forbidden if the order belongs to another customer.
   *
   * Apply pagination with configurable page size (default 10, max 50). Include total count and pagination metadata in response.
   *
   * Each shipment summary should include: id, carrier, tracking_number, created_at, and item_count from shipment_items join.
   *
   * If no shipments exist for the order, return empty array with pagination showing zero total.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceMallShipment.IRequest,
  ): Promise<IPageIEcommerceMallShipment.ISummary> {
    try {
      return await patchEcommerceMallOrdersOrderIdShipments({
        orderId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific shipment within an order.
   *
   * This endpoint returns the complete shipment details including carrier name, tracking number, creation timestamp, and all order items included in this shipment. The shipment must belong to the specified order.
   *
   * The response includes the shipment's items through the shipment_items relationship, allowing customers to see exactly which products are in each package. Sellers can verify shipment contents, and customers can track their deliveries.
   *
   * If the shipment does not belong to the specified order, a 404 error is returned.
   *
   * @param connection
   * @param orderId Unique identifier of the parent order (global scope)
   * @param shipmentId Unique identifier of the shipment to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query the ecommerce_mall_shipments table filtering by id equal to shipmentId AND order_id equal to orderId. Include related shipment_items with their order_item data through eager loading. Validate that both orderId and shipmentId exist and that the shipment belongs to the specified order. Return 404 if shipment not found or if shipment does not belong to the order. The shipment items should include order_item details such as product name, variant options, quantity, and unit price.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":shipmentId")
  public async at(
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedParam("shipmentId")
    shipmentId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallShipment> {
    try {
      return await getEcommerceMallOrdersOrderIdShipmentsShipmentId({
        orderId,
        shipmentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
