import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallGuestSession } from "../../../api/structures/IEcommerceMallGuestSession";
import { IPageIEcommerceMallGuestSession } from "../../../api/structures/IPageIEcommerceMallGuestSession";
import { getEcommerceMallGuestSessionsSessionId } from "../../../providers/getEcommerceMallGuestSessionsSessionId";
import { patchEcommerceMallGuestSessions } from "../../../providers/patchEcommerceMallGuestSessions";

@Controller("/ecommerceMall/guest-sessions")
export class EcommercemallGuest_sessionsController {
  /**
   * Retrieve a filtered and paginated list of guest sessions on the platform.
   *
   * This operation provides administrative access to view and search guest sessions for security monitoring, analytics, and troubleshooting purposes. Sessions track anonymous visitor navigation context including IP address, current page URL, and referrer information.
   *
   * Supports filtering by guest identifier, session expiration status, IP address patterns, and creation date ranges. Results are paginated with configurable page sizes and sorting options.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering guest sessions
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query the ecommerce_mall_guest_sessions table with pagination and filtering.
   *
   * Apply search filters based on provided criteria:
   * - Filter by ecommerce_mall_guest_id if provided
   * - Filter by ip address pattern matching
   * - Filter by href URL pattern if provided
   * - Filter by session expiration status (expired vs active)
   * - Filter by created_at date range (from/to)
   *
   * Join with ecommerce_mall_guests table to include guest fingerprint information when needed.
   *
   * Return cursor-based pagination for large result sets. Order by created_at descending by default.
   *
   * Validate all filter parameters before applying to query.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IEcommerceMallGuestSession.IRequest,
  ): Promise<IPageIEcommerceMallGuestSession.ISummary> {
    try {
      return await patchEcommerceMallGuestSessions({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific guest session by its unique identifier.
   *
   * This endpoint retrieves detailed information about a single guest session including the guest's browsing context (current page URL, HTTP referrer) and session timestamps (creation time, expiration time).
   *
   * The guest session tracks anonymous visitor activity across page visits. Each session is associated with a device fingerprint and contains navigation context for maintaining browsing continuity.
   *
   * If the session has expired, the response still returns the session data with the expiration timestamp. Clients should check the expired_at field to determine if the session is still valid.
   *
   * @param connection
   * @param sessionId Unique identifier of the guest session (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query the ecommerce_mall_guest_sessions table by sessionId (UUID).
   *
   * Join with ecommerce_mall_guests relation to include guest device information (fingerprint, user_agent).
   *
   * Validate that sessionId is a valid UUID format. Return 404 if session not found.
   *
   * Include all session fields: id, ecommerce_mall_guest_id, ip, href, referrer, created_at, expired_at.
   *
   * Include guest relation with fields: id, fingerprint, user_agent.
   *
   * The session is considered expired if current timestamp exceeds expired_at. Return the session data regardless of expiration status - the client determines validity.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallGuestSession> {
    try {
      return await getEcommerceMallGuestSessionsSessionId({
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
