import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallSellerProfile } from "../../../../api/structures/IEcommerceMallSellerProfile";
import { getEcommerceMallSellersSellerIdProfile } from "../../../../providers/getEcommerceMallSellersSellerIdProfile";

@Controller("/ecommerceMall/sellers/:sellerId/profile")
export class EcommercemallSellersProfileController {
  /**
   * Retrieves the public shop profile for a specific seller.
   *
   * This endpoint allows customers and guests to view a seller's public shop information. The profile displays the shop name shown on product listings, a business description explaining the shop's background and offerings, and a logo image for brand identification.
   *
   * **Profile Information**
   * The response includes the shop name that appears in product listings and order records, a detailed business description visible on the seller's profile page, and a logo image URI for brand display. This information helps customers make informed purchasing decisions by learning about the seller before buying.
   *
   * **Availability**
   * Profiles with a deleted_at timestamp are not returned. If the seller profile has been deleted, the endpoint returns a 404 error indicating the seller profile was not found.
   *
   * @param connection
   * @param sellerId Unique identifier of the seller whose profile to retrieve. Must be a valid UUID.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor null
     * @x-autobe-specification Query the ecommerce_mall_seller_profiles table to
     *   find a profile where seller_id matches the provided sellerId parameter.
   *
   * Verify the seller exists by checking the ecommerce_mall_sellers table - if the seller does not exist, return 404 with 'Seller not found'.
   *
   * Check the deleted_at field - if deleted_at is not null, return 404 with 'Seller profile not found'.
   *
   * Return the profile data including: id, name, description, logo_uri, created_at, updated_at.
   *
   * Join with ecommerce_mall_sellers to verify seller approval_status is 'approved' - if seller is not approved, return 404.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallSellerProfile> {
    try {
      return await getEcommerceMallSellersSellerIdProfile({
        sellerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
