import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallReviewSnapshot } from "../../../../api/structures/IEcommerceMallReviewSnapshot";
import { IPageIEcommerceMallReviewSnapshot } from "../../../../api/structures/IPageIEcommerceMallReviewSnapshot";
import { getEcommerceMallReviewsReviewIdSnapshotsSnapshotId } from "../../../../providers/getEcommerceMallReviewsReviewIdSnapshotsSnapshotId";
import { patchEcommerceMallReviewsReviewIdSnapshots } from "../../../../providers/patchEcommerceMallReviewsReviewIdSnapshots";

@Controller("/ecommerceMall/reviews/:reviewId/snapshots")
export class EcommercemallReviewsSnapshotsController {
  /**
   * Retrieves the modification history of a review as a paginated list of snapshots.
   *
   * Each snapshot captures the review state (rating and content) at the time of a previous edit, providing an immutable audit trail for dispute resolution. When a review is edited, a new snapshot is automatically created to preserve the previous state.
   *
   * Customers can view snapshots of their own reviews. Sellers can view snapshots of reviews on their products. Administrators can view any review snapshot.
   *
   * The results are ordered by creation timestamp in descending order (newest first) to show the most recent modifications at the top.
   *
   * @param connection
   * @param reviewId Unique identifier of the review whose snapshots to retrieve.
   * @param body Search criteria including pagination parameters (page number, page size) and optional sorting preferences.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query ecommerce_mall_review_snapshots table filtered by the reviewId path parameter.
   *
   * Apply pagination with page number and page size limits. Order results by created_at descending (newest first).
   *
   * Authorization checks:
   * - Customer: can only access if review belongs to their account
   * - Seller: can only access if review's product belongs to their shop
   * - Admin: can access any review snapshot
   *
   * Return paginated results with total count for pagination controls.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceMallReviewSnapshot.IRequest,
  ): Promise<IPageIEcommerceMallReviewSnapshot.ISummary> {
    try {
      return await patchEcommerceMallReviewsReviewIdSnapshots({
        reviewId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves a specific review snapshot capturing the review state before an edit.
   *
   * This endpoint returns a historical snapshot of a review edit, including the previous rating value and text content. Customers can access this endpoint to view the modification history of their own reviews. The snapshot provides the exact state of the review (rating and body) at the time the edit was made.
   *
   * **Access Control**: Only the customer who owns the review or an administrator can retrieve the snapshot.
   *
   * **Snapshot Data**: Each snapshot contains the rating value (1-5) and optional text content as they existed before the edit was applied.
   *
   * **Relationship to Review**: The snapshot is linked to its parent review via the reviewId parameter. If the parent review has been deleted, the snapshot is still accessible for audit purposes.
   *
   * **Use Cases**: This endpoint is primarily used for dispute resolution when customers contest product conditions, or to review the history of review modifications.
   *
   * @param connection
   * @param reviewId UUID of the parent review that this snapshot belongs to.
   * @param snapshotId UUID of the snapshot to retrieve.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Retrieve a single review snapshot by validating the snapshot exists and belongs to the specified review.
   *
   * Implementation steps:
   * 1. Validate both reviewId and snapshotId are valid UUIDs.
   * 2. Verify the snapshot exists in ecommerce_mall_review_snapshots table.
   * 3. Verify the snapshot's ecommerce_mall_review_id matches the provided reviewId.
   * 4. Verify the review exists in ecommerce_mall_reviews table.
   * 5. Check authorization: the requesting user must be either:
   *    - The customer who owns the review (ecommerce_mall_customer_id matches session), OR
   *    - An administrator with appropriate permissions.
   * 6. If the review is soft-deleted (deleted_at is not null), still return the snapshot as they are preserved for audit.
   * 7. Return the snapshot data including: id, ecommerce_mall_review_id, rating, body (nullable), created_at.
   *
   * Error handling:
   * - 404 Not Found: If snapshot or review does not exist.
   * - 403 Forbidden: If user is not authorized to view this snapshot.
   * - 400 Bad Request: If IDs are not valid UUIDs.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":snapshotId")
  public async at(
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
    @TypedParam("snapshotId")
    snapshotId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallReviewSnapshot> {
    try {
      return await getEcommerceMallReviewsReviewIdSnapshotsSnapshotId({
        reviewId,
        snapshotId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
