import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallCustomer } from "../../../../api/structures/IEcommerceMallCustomer";
import { postEcommerceMallAuthCustomerJoin } from "../../../../providers/postEcommerceMallAuthCustomerJoin";
import { postEcommerceMallAuthCustomerLogin } from "../../../../providers/postEcommerceMallAuthCustomerLogin";
import { postEcommerceMallAuthCustomerRefresh } from "../../../../providers/postEcommerceMallAuthCustomerRefresh";

@Controller("/ecommerceMall/auth/customer")
export class EcommercemallAuthCustomerController {
  /**
   * Register a new customer account on the ecommerce mall platform. This endpoint creates a new customer record in the ecommerce_mall_customers table with the provided email address and password hash. The email serves as the unique login identifier and cannot be changed after registration. Upon successful registration, the system creates an empty wishlist and shopping cart for the customer. A JWT access token and refresh token are returned for immediate authenticated access to protected endpoints.
   *
   * The registration flow requires email verification (handled separately) to fully activate the account for certain operations. Password comparison is case-insensitive during login. Soft-deleted accounts cannot register with the same email until the deletion is permanent.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Request body containing customer registration credentials including email address and password.
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification 1. Validate request body (email format, password not empty)
   * 2. Check email uniqueness (case-sensitive comparison against ecommerce_mall_customers.email)
   * 3. Hash password using bcrypt
   * 4. Create new customer record in ecommerce_mall_customers table
   * 5. Create empty wishlist and cart for the customer
   * 6. Generate JWT access_token and refresh_token
   * 7. Create session record in ecommerce_mall_customer_sessions
   * 8. Return authorized response with tokens
   *
   * Edge cases:
   * - Duplicate email: return 409 Conflict
   * - Invalid email format: return 400 Bad Request
   * - Password empty: return 400 Bad Request
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEcommerceMallCustomer.IJoin,
  ): Promise<IEcommerceMallCustomer.IAuthorized> {
    try {
      return await postEcommerceMallAuthCustomerJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate an existing customer account using email and password credentials. This endpoint validates the provided credentials against the stored password hash in the ecommerce_mall_customers table. Upon successful authentication, the system issues a new JWT access token and refresh token stored in the ecommerce_mall_customer_sessions table. The session tracks client information including IP address, current page URL, and HTTP referrer for security auditing purposes.
   *
   * Password comparison is not case-sensitive, while email comparison is case-sensitive. Soft-deleted accounts cannot log in. Each login creates a new session record, allowing multiple concurrent sessions.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Request body containing customer login credentials: email address and password.
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification 1. Validate request body (email and password present)
   * 2. Look up customer by email in ecommerce_mall_customers (case-sensitive)
   * 3. Verify password against stored hash (comparison not case-sensitive)
   * 4. Check customer is not soft-deleted (deleted_at is null)
   * 5. Generate new JWT access_token and refresh_token
   * 6. Create new session record in ecommerce_mall_customer_sessions with IP, href, referrer
   * 7. Return authorized response with tokens
   *
   * Edge cases:
   * - Email not found: return 401 Unauthorized
   * - Wrong password: return 401 Unauthorized
   * - Soft-deleted account: return 401 Unauthorized
   * - Empty credentials: return 400 Bad Request
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEcommerceMallCustomer.ILogin,
  ): Promise<IEcommerceMallCustomer.IAuthorized> {
    try {
      return await postEcommerceMallAuthCustomerLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Renew expired or expiring JWT tokens using a valid refresh token. This endpoint accepts a refresh token from the ecommerce_mall_customer_sessions table and issues a new access token and refresh token pair. The refresh token mechanism allows users to maintain their session without re-entering credentials. Sessions track token expiration through the expired_at field, and this endpoint handles token renewal before expiration.
   *
   * The refresh operation maintains session continuity for the customer, updating the existing session record with new token values. Multiple concurrent sessions each have their own token pairs, and refresh operates on the specific session corresponding to the provided refresh token.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Request body containing the refresh token to renew authentication credentials.
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification 1. Validate request body (refresh_token present)
   * 2. Verify refresh_token exists and is not expired in ecommerce_mall_customer_sessions
   * 3. Look up associated customer in ecommerce_mall_customers
   * 4. Verify customer is not soft-deleted (deleted_at is null)
   * 5. Generate new JWT access_token and refresh_token
   * 6. Update session record with new tokens
   * 7. Return authorized response with new tokens
   *
   * Edge cases:
   * - Invalid refresh token: return 401 Unauthorized
   * - Expired refresh token: return 401 Unauthorized
   * - Associated customer deleted: return 401 Unauthorized
   * - Empty refresh token: return 400 Bad Request
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IEcommerceMallCustomer.IRefresh,
  ): Promise<IEcommerceMallCustomer.IAuthorized> {
    try {
      return await postEcommerceMallAuthCustomerRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
