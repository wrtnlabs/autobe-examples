import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallCustomer } from "../../../../api/structures/IEcommerceMallCustomer";
import { postEcommerceMallAuthCustomerJoin } from "../../../../providers/postEcommerceMallAuthCustomerJoin";
import { postEcommerceMallAuthCustomerLogin } from "../../../../providers/postEcommerceMallAuthCustomerLogin";
import { postEcommerceMallAuthCustomerRefresh } from "../../../../providers/postEcommerceMallAuthCustomerRefresh";

@Controller("/ecommerceMall/auth/customer")
export class EcommercemallAuthCustomerController {
  /**
   * Register a new customer account with email and password. Creates the customer record and initiates email verification process. Upon successful registration, returns JWT access and refresh tokens for immediate authenticated requests.
   *
   * This operation creates a new customer in the ecommerce_mall_customers table using the provided email and password_hash. A unique verification token is generated and stored in ecommerce_mall_customer_email_verifications for email confirmation. The customer must verify their email before gaining full access to shopping features.
   *
   * After registration, the system creates an empty wishlist and empty shopping cart for the new customer. The email address serves as the unique login identifier and cannot be changed after registration. Password comparison is case-insensitive during login.
   *
   * Security considerations: Passwords are hashed before storage. Email verification tokens are cryptographically random and expire after a set duration. Duplicate email registration attempts are rejected with appropriate error messaging.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Registration credentials including email address and password for new customer account creation.
     * @x-autobe-authorization-type join
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification Handle new customer registration. Validate email
     *   format and check email uniqueness. Hash password securely. Create
     *   customer record with created_at and updated_at timestamps. Generate
     *   email verification token with expiration (e.g., 24 hours). Store
     *   verification token in ecommerce_mall_customer_email_verifications
     *   table. Return access and refresh JWT tokens in IAuthorized response. Do
     *   NOT auto-login - customer must verify email first.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEcommerceMallCustomer.IJoin,
  ): Promise<IEcommerceMallCustomer.IAuthorized> {
    try {
      return await postEcommerceMallAuthCustomerJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate a customer with email and password credentials. Validates the provided credentials against stored customer records and establishes an authenticated session. Returns JWT access and refresh tokens upon successful authentication.
   *
   * This operation verifies the customer's email and password against the ecommerce_mall_customers table. Password comparison is case-insensitive as per business rules. The system checks that the account exists and has not been soft-deleted (deleted_at is null).
   *
   * Upon successful authentication, a new session is created in ecommerce_mall_customer_sessions containing the customer's access and refresh tokens. The session records client metadata including IP address, current page URL, and HTTP referrer for security auditing purposes.
   *
   * Error handling: Returns appropriate errors for invalid credentials, non-existent accounts, or deactivated accounts. Does not reveal whether email exists vs password is wrong to prevent enumeration attacks.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Login credentials containing the customer's email address and password.
     * @x-autobe-authorization-type login
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification Authenticate existing customer. Validate provided
     *   email exists and password matches (case-insensitive comparison). Check
     *   customer.deleted_at is null (account not soft-deleted). Create new
     *   session record in ecommerce_mall_customer_sessions with JWT access and
     *   refresh tokens. Store IP address, current href, and referrer from
     *   request context. Set appropriate expiration for tokens (access:
     *   short-lived e.g. 15min, refresh: longer e.g. 7 days). Return tokens in
     *   IAuthorized response.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEcommerceMallCustomer.ILogin,
  ): Promise<IEcommerceMallCustomer.IAuthorized> {
    try {
      return await postEcommerceMallAuthCustomerLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Renew expired or expiring access tokens using a valid refresh token. Allows customers to maintain their authenticated session without re-entering credentials. Returns new JWT access and refresh tokens upon successful renewal.
   *
   * This operation accepts a valid refresh token from the ecommerce_mall_customer_sessions table. The refresh token must not be expired and must not have been previously used. Upon validation, the system issues a new access token and optionally rotates the refresh token for enhanced security.
   *
   * Token refresh is stateless after initial validation - the new tokens are signed JWTs containing the customer_id claim. The session record is updated to track token lifecycle and maintain security audit trail.
   *
   * Security considerations: Implements token rotation to prevent replay attacks. Expired refresh tokens are rejected. Used tokens are invalidated immediately after rotation. Rate limiting may apply to prevent token refresh abuse.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token request containing the current refresh token to exchange for new access and refresh tokens.
     * @x-autobe-authorization-type refresh
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification Renew expired access token using refresh token.
     *   Validate refresh token exists and has not expired (check expires_at
     *   against current time). Verify refresh token is not marked as used
     *   (used_at is null for single-use tokens). Extract customer_id from
     *   token. Generate new access token and optionally new refresh token.
     *   Update session record. Return new tokens in IAuthorized response.
     *   Handle token rotation for security (old refresh token invalidated, new
     *   one issued).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IEcommerceMallCustomer.IRefresh,
  ): Promise<IEcommerceMallCustomer.IAuthorized> {
    try {
      return await postEcommerceMallAuthCustomerRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
