import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallCustomer } from "../../../../api/structures/IEcommerceMallCustomer";
import { postEcommerceMallAuthCustomerJoin } from "../../../../providers/postEcommerceMallAuthCustomerJoin";
import { postEcommerceMallAuthCustomerLogin } from "../../../../providers/postEcommerceMallAuthCustomerLogin";
import { postEcommerceMallAuthCustomerRefresh } from "../../../../providers/postEcommerceMallAuthCustomerRefresh";

@Controller("/ecommerceMall/auth/customer")
export class EcommercemallAuthCustomerController {
  /**
   * Registers a new customer account on the ecommerce mall platform. This endpoint creates a new customer record in the ecommerce_mall_customers table with the provided email address and securely hashed password. Upon successful registration, the system creates an associated customer profile record in ecommerce_mall_customer_profiles table, initializes an empty wishlist for future product bookmarks, and sets up an empty shopping cart for the new customer. A unique email verification token is generated and stored in ecommerce_mall_customer_email_verifications table with an expiration timestamp. The response contains JWT access and refresh tokens that the client must store for subsequent authenticated requests. The customer must verify their email address before gaining full access to the platform's features.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Customer registration credentials including email address and password.
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Accept email and password, hash password securely, create customer record in ecommerce_mall_customers table, create associated profile in ecommerce_mall_customer_profiles, create empty wishlist and cart, generate email verification token, return JWT tokens. Email uniqueness validated against existing customers.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEcommerceMallCustomer.IJoin,
  ): Promise<IEcommerceMallCustomer.IAuthorized> {
    try {
      return await postEcommerceMallAuthCustomerJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticates an existing customer and establishes a new session on the platform. This endpoint validates the provided email and password against the customer records in the ecommerce_mall_customers table. The password_hash field is compared securely while the email comparison is case-sensitive. The system verifies that the customer account is active by checking that the deleted_at field is null - suspended or banned accounts will fail authentication. Upon successful validation, a new session record is created in ecommerce_mall_customer_sessions table capturing the client IP address, current page URL, and HTTP referrer for security auditing purposes. JWT access and refresh tokens are generated and returned to the client. These tokens must be included in subsequent API requests for authentication. Multiple concurrent sessions are supported - each login creates a new session record.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Customer login credentials including email and password.
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Validate email and password against ecommerce_mall_customers table, verify account is not soft-deleted (deleted_at is null), create new session record in ecommerce_mall_customer_sessions with IP, user agent, and referrer, generate JWT access and refresh tokens, return tokens to client.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEcommerceMallCustomer.ILogin,
  ): Promise<IEcommerceMallCustomer.IAuthorized> {
    try {
      return await postEcommerceMallAuthCustomerLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Renews customer authentication tokens using a valid refresh token. This endpoint accepts a refresh token from the ecommerce_mall_customer_sessions table and issues a new JWT access token to continue the authenticated session. The refresh token must be valid and the associated session must not have expired (checked against expired_at field). Upon successful validation, a new access token is generated with a fresh expiration timestamp. The session's updated_at field is updated to reflect the token refresh activity. This endpoint supports token rotation for enhanced security - optionally issuing a new refresh token while invalidating the old one. Customers use this endpoint when their access token is about to expire to seamlessly maintain their authenticated session without requiring re-login. The refresh endpoint is stateless regarding the access token but validates against the persistent session record.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Current refresh token for renewing authentication session.
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Extract customer ID from expired or expiring access token, validate refresh token against ecommerce_mall_customer_sessions table, verify session has not expired, generate new JWT access token, optionally rotate refresh token, update session updated_at timestamp, return new tokens.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IEcommerceMallCustomer.IRefresh,
  ): Promise<IEcommerceMallCustomer.IAuthorized> {
    try {
      return await postEcommerceMallAuthCustomerRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
