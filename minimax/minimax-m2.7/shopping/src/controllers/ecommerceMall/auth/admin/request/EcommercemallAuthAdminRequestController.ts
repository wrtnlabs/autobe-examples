import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallAdmin } from "../../../../../api/structures/IEcommerceMallAdmin";
import { postEcommerceMallAuthAdminRequest } from "../../../../../providers/postEcommerceMallAuthAdminRequest";

@Controller("/ecommerceMall/auth/admin/request")
export class EcommercemallAuthAdminRequestController {
  /**
   * Submits a request to become an administrator on the platform. This operation allows existing customers or sellers to request administrative privileges by providing a reason for their request and specifying the requested privilege grade (admin or super_admin). The request is reviewed by super administrators. Upon successful submission, returns JWT access and refresh tokens for the requesting actor.
   *
   * Request body must include the actor_type discriminator ('customer' or 'seller') to identify the requester, the requested_grade indicating privilege level, and a text reason explaining why administrative access is needed.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Request body containing actor_type discriminator, requested_grade, and reason for admin privilege request.
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Join (admin request submission): Validate email format, check actor_type is 'customer' or 'seller', validate requested_grade is 'admin' or 'super_admin', store request with status 'pending'. Generate email notification to super admins. Return authorized tokens for the requesting actor (customer or seller) to track their request status.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEcommerceMallAdmin.IJoin,
  ): Promise<IEcommerceMallAdmin.IAuthorized> {
    try {
      return await postEcommerceMallAuthAdminRequest({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
