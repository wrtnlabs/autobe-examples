import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallAdmin } from "../../../../api/structures/IEcommerceMallAdmin";
import { postEcommerceMallAuthAdminJoin } from "../../../../providers/postEcommerceMallAuthAdminJoin";
import { postEcommerceMallAuthAdminLogin } from "../../../../providers/postEcommerceMallAuthAdminLogin";
import { postEcommerceMallAuthAdminRefresh } from "../../../../providers/postEcommerceMallAuthAdminRefresh";

@Controller("/ecommerceMall/auth/admin")
export class EcommercemallAuthAdminController {
  /**
   * Register a new administrator account with email and password credentials.
   *
   * This operation creates a new administrator account in the ecommerce_mall_admins table. The email address must be unique across all administrators. Password is securely hashed using bcrypt before storage. Upon successful registration, the system generates JWT access and refresh tokens for immediate authentication.
   *
   * The request body contains the email address used for login and the initial password for the new administrator account.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Administrator registration credentials including unique email and secure password.
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification 1. Validate email format and password strength (min 8 chars).
   * 2. Check email uniqueness in ecommerce_mall_admins table.
   * 3. Hash password with bcrypt.
   * 4. Create new admin record with generated UUID.
   * 5. Generate access and refresh JWT tokens.
   * 6. Create session record in ecommerce_mall_admin_sessions.
   * 7. Return tokens and admin info.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEcommerceMallAdmin.IJoin,
  ): Promise<IEcommerceMallAdmin.IAuthorized> {
    try {
      return await postEcommerceMallAuthAdminJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate an administrator with email and password credentials.
   *
   * This operation validates administrator credentials against the ecommerce_mall_admins table. Upon successful authentication, the system generates new JWT access and refresh tokens. A new session record is created in ecommerce_mall_admin_sessions capturing the client IP address and HTTP referrer for security auditing purposes.
   *
   * The response contains the authenticated administrator's information along with tokens for API authorization.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Administrator login credentials with email and password.
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification 1. Validate email and password presence.
   * 2. Look up admin by email in ecommerce_mall_admins table.
   * 3. Verify password against stored bcrypt hash.
   * 4. Generate new JWT access and refresh tokens.
   * 5. Create new session in ecommerce_mall_admin_sessions with IP and user agent.
   * 6. Return tokens and admin profile.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEcommerceMallAdmin.ILogin,
  ): Promise<IEcommerceMallAdmin.IAuthorized> {
    try {
      return await postEcommerceMallAuthAdminLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Renew authentication tokens using a valid refresh token.
   *
   * This operation allows administrators to obtain new access and refresh tokens without re-entering credentials. The refresh token must be valid and not expired. Upon successful refresh, the old refresh token is invalidated and a new pair of tokens is issued. The session is updated in ecommerce_mall_admin_sessions with current timestamp.
   *
   * This operation is used to maintain continuous authentication sessions while rotating tokens for security.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Valid refresh token to obtain new authentication credentials.
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification 1. Extract refresh token from request body.
   * 2. Validate refresh token signature and expiration.
   * 3. Look up session by token in ecommerce_mall_admin_sessions.
   * 4. Verify admin exists and is not soft-deleted.
   * 5. Generate new access and refresh tokens.
   * 6. Invalidate old refresh token.
   * 7. Create new session record.
   * 8. Return new tokens and admin profile.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IEcommerceMallAdmin.IRefresh,
  ): Promise<IEcommerceMallAdmin.IAuthorized> {
    try {
      return await postEcommerceMallAuthAdminRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
