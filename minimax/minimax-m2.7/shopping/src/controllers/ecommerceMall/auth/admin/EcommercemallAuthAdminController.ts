import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallAdmin } from "../../../../api/structures/IEcommerceMallAdmin";
import { postEcommerceMallAuthAdminLogin } from "../../../../providers/postEcommerceMallAuthAdminLogin";
import { postEcommerceMallAuthAdminRefresh } from "../../../../providers/postEcommerceMallAuthAdminRefresh";

@Controller("/ecommerceMall/auth/admin")
export class EcommercemallAuthAdminController {
  /**
   * Authenticates an administrator using their email and password credentials. Validates the provided credentials against the stored password hash in the ecommerce_mall_admins table. Upon successful authentication, returns JWT access and refresh tokens along with token metadata. The session is recorded in ecommerce_mall_admin_sessions for security auditing, capturing the client IP address and current page URL.
   *
   * This operation requires the email and password fields from the admin account record. The password_hash uses bcrypt hashing for secure storage.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Request body containing administrator email address and password for credential validation.
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Login: Validate email exists in ecommerce_mall_admins table, verify password_hash matches using bcrypt, check deleted_at is null (account not soft-deleted). Generate JWT access token (short-lived) and refresh token (long-lived). Store session in ecommerce_mall_admin_sessions with IP and href. Return tokens to client.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEcommerceMallAdmin.ILogin,
  ): Promise<IEcommerceMallAdmin.IAuthorized> {
    try {
      return await postEcommerceMallAuthAdminLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Renews JWT authentication tokens using a valid refresh token. Accepts the refresh token previously issued during login or a prior refresh operation. Validates the token's integrity and expiration, then issues a new access token with fresh claims. The associated session in ecommerce_mall_admin_sessions is updated with a new expiration timestamp.
   *
   * This operation maintains the security of long-lived refresh tokens by optionally implementing token rotation, issuing a new refresh token while invalidating the used one.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Request body containing the refresh token for JWT token renewal.
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Refresh: Extract refresh token from request body, validate token signature and expiration, lookup associated admin session, verify admin account is not soft-deleted (deleted_at is null). Generate new access token and optionally new refresh token (token rotation). Update session expiration. Return new token set.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IEcommerceMallAdmin.IRefresh,
  ): Promise<IEcommerceMallAdmin.IAuthorized> {
    try {
      return await postEcommerceMallAuthAdminRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
