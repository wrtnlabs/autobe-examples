import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallSeller } from "../../../../api/structures/IEcommerceMallSeller";
import { postEcommerceMallAuthSellerJoin } from "../../../../providers/postEcommerceMallAuthSellerJoin";
import { postEcommerceMallAuthSellerLogin } from "../../../../providers/postEcommerceMallAuthSellerLogin";
import { postEcommerceMallAuthSellerRefresh } from "../../../../providers/postEcommerceMallAuthSellerRefresh";

@Controller("/ecommerceMall/auth/seller")
export class EcommercemallAuthSellerController {
  /**
   * Registers a new seller account on the platform.
   *
   * This endpoint creates a new seller account with email and password credentials. The registration initiates a pending approval workflow where administrators must approve the seller before they can list products. An email verification token is generated and sent to the seller's email address for account confirmation.
   *
   * Implementation details:
   * The operation validates the email format, checks for email uniqueness against the ecommerce_mall_sellers.email field, hashes the password using bcrypt, and creates a new seller record with approval_status set to 'pending'. A verification token is stored in ecommerce_mall_seller_email_verifications with expiration time. The response returns authorized tokens as null since email verification is required before the account can be used for login.
   *
   * Business context:
   * New sellers cannot immediately list products or access seller-specific endpoints. They must wait for administrator approval. The rejection_reason field in ecommerce_mall_sellers will be populated if an administrator rejects the registration. Sellers can re-register using the reregister endpoint if initially rejected.
   *
   * Security considerations:
   * Passwords are never stored in plaintext; only bcrypt hashes are persisted. The verification token is cryptographically random and single-use. Tokens expire after a configurable duration.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Registration request containing seller email address and password.
     * @x-autobe-authorization-type join
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Service logic: 1. Validate email format and
     *   uniqueness (check ecommerce_mall_sellers.email uniqueness) 2. Validate
     *   password strength (minimum 8 characters, hash with bcrypt) 3. Create
     *   new seller record with approval_status = 'pending' 4. Generate email
     *   verification token and store in
     *   ecommerce_mall_seller_email_verifications 5. Return IAuthorized
     *   response with null tokens (email verification required before login)
   *
   * Edge cases:
   * - Duplicate email: return 409 Conflict
   * - Invalid email format: return 400 Bad Request
   * - Weak password: return 400 Bad Request
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEcommerceMallSeller.IJoin,
  ): Promise<IEcommerceMallSeller.IAuthorized> {
    try {
      return await postEcommerceMallAuthSellerJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticates a seller with email and password credentials.
   *
   * This endpoint validates the seller's email and password against stored records and issues JWT tokens upon successful authentication. The seller must have an approved account status to obtain valid session tokens.
   *
   * Implementation details:
   * The operation validates credentials by verifying the password hash stored in ecommerce_mall_sellers.password_hash. It checks the approval_status field to ensure the account has been approved by an administrator. A new session is created in ecommerce_mall_seller_sessions capturing client metadata (IP address, request URL, referrer) for security tracking. JWT tokens are generated and stored in the session record.
   *
   * Business context:
   * Sellers with pending or rejected approval status cannot authenticate. Only approved sellers can access seller-specific endpoints like product management and order fulfillment. Sessions track login activity for audit purposes.
   *
   * Security considerations:
   * Failed login attempts are not rate-limited at this endpoint (should be handled by infrastructure-level rate limiting). Sessions can be invalidated by deleting the session record. Access tokens expire after a short duration; use the refresh endpoint to obtain new tokens.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Login credentials containing email and password.
     * @x-autobe-authorization-type login
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Service logic: 1. Validate email exists in
     *   ecommerce_mall_sellers 2. Verify password against password_hash 3.
     *   Check approval_status = 'approved' (rejected accounts cannot login) 4.
     *   Create session record in ecommerce_mall_seller_sessions with ip, href,
     *   referrer 5. Generate JWT access_token and refresh_token 6. Store tokens
     *   in session record 7. Return IAuthorized with both tokens
   *
   * Edge cases:
   * - Email not found: return 401 Unauthorized
   * - Wrong password: return 401 Unauthorized
   * - Not approved (pending): return 403 Forbidden with message to wait for approval
   * - Rejected: return 403 Forbidden with message to use reregister
   * - Soft deleted (deleted_at not null): return 403 Forbidden
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEcommerceMallSeller.ILogin,
  ): Promise<IEcommerceMallSeller.IAuthorized> {
    try {
      return await postEcommerceMallAuthSellerLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refreshes authentication tokens using a valid refresh token.
   *
   * This endpoint exchanges a valid refresh token for new access and refresh tokens, allowing sellers to maintain their authenticated session without re-entering credentials. The operation validates the refresh token's existence and expiration against the session record.
   *
   * Implementation details:
   * The operation looks up the session in ecommerce_mall_seller_sessions using the provided refresh_token. It verifies the session has not expired (expired_at field) and that the associated seller is still active with approved status and no deletion timestamp. New JWT tokens are generated, replacing the old ones in the session record. The expiration time is extended for the new tokens.
   *
   * Business context:
   * Access tokens have short lifespans for security. Refresh tokens allow prolonged authenticated sessions. When sellers change their password, old sessions may be invalidated (handled by the change-password operation which deletes all sessions).
   *
   * Security considerations:
   * Each refresh operation rotates the refresh token to limit token reuse exposure. Expired sessions cannot be refreshed and require re-authentication. Deleted or suspended sellers cannot refresh tokens.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh request containing the current refresh token.
     * @x-autobe-authorization-type refresh
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Service logic: 1. Extract refresh_token from
     *   request body 2. Find session in ecommerce_mall_seller_sessions by
     *   refresh_token 3. Verify session not expired (check expired_at > current
     *   time) 4. Verify seller still approved (check
     *   ecommerce_mall_sellers.approval_status = 'approved') 5. Verify seller
     *   not deleted (check ecommerce_mall_sellers.deleted_at is null) 6.
     *   Generate new access_token and refresh_token 7. Update session record
     *   with new tokens and new expiration 8. Return IAuthorized with new
     *   tokens
   *
   * Edge cases:
   * - Invalid/expired refresh_token: return 401 Unauthorized
   * - Seller account deleted: return 401 Unauthorized
   * - Seller not approved: return 401 Unauthorized
   * - Session not found: return 401 Unauthorized
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IEcommerceMallSeller.IRefresh,
  ): Promise<IEcommerceMallSeller.IAuthorized> {
    try {
      return await postEcommerceMallAuthSellerRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
