import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallSeller } from "../../../../api/structures/IEcommerceMallSeller";
import { postEcommerceMallAuthSellerJoin } from "../../../../providers/postEcommerceMallAuthSellerJoin";
import { postEcommerceMallAuthSellerLogin } from "../../../../providers/postEcommerceMallAuthSellerLogin";
import { postEcommerceMallAuthSellerRefresh } from "../../../../providers/postEcommerceMallAuthSellerRefresh";

@Controller("/ecommerceMall/auth/seller")
export class EcommercemallAuthSellerController {
  /**
   * Seller registration endpoint for new sellers to create an account on the ecommerce mall platform.
   *
   * This operation creates a new seller account with email and password credentials. The seller record is inserted into the ecommerce_mall_sellers table with approval_status set to 'pending'. An email verification token is generated and stored in ecommerce_mall_seller_email_verifications for email confirmation. A new session is created in ecommerce_mall_seller_sessions with JWT access and refresh tokens for immediate authentication after registration.
   *
   * The seller must wait for administrator approval (approval_status = 'approved') before listing products or managing orders. If rejected, the rejection_reason and rejected_at fields in ecommerce_mall_sellers will be populated by an administrator.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Registration request containing seller email address and password for new account creation.
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Implementation steps:
   * 1. Validate email format and uniqueness in ecommerce_mall_sellers.email
   * 2. Hash password using bcrypt with appropriate salt rounds
   * 3. Insert new seller record with approval_status = 'pending'
   * 4. Generate email verification token, store in ecommerce_mall_seller_email_verifications
   * 5. Create initial seller session with JWT access and refresh tokens
   * 6. Send verification email (external integration)
   * 7. Return IAuthorized response with tokens
   *
   * Error handling:
   * - Duplicate email: Return 409 Conflict
   * - Invalid email format: Return 400 Bad Request
   * - Weak password: Return 400 Bad Request with validation details
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEcommerceMallSeller.IJoin,
  ): Promise<IEcommerceMallSeller.IAuthorized> {
    try {
      return await postEcommerceMallAuthSellerJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Seller login endpoint for approved sellers to authenticate with email and password credentials.
   *
   * This operation validates seller credentials against the ecommerce_mall_sellers table. The email is looked up and password_hash is verified using bcrypt comparison. Only sellers with approval_status = 'approved' can successfully login - pending or rejected sellers receive error responses. The deleted_at field must be null for active accounts.
   *
   * Upon successful authentication, new JWT access and refresh tokens are generated. A session record is created in ecommerce_mall_seller_sessions storing client metadata (IP address, href, referrer) for security audit purposes. The session expiration time is set according to platform security policies.
   *
   * The returned tokens enable authenticated requests to seller operations such as product management, order fulfillment, and cancellation/refund response.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Login request containing seller email address and password for authentication.
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Implementation steps:
   * 1. Validate email exists in ecommerce_mall_sellers table
   * 2. Verify password against stored password_hash using bcrypt
   * 3. Check approval_status - only 'approved' sellers can login
   * 4. If not approved, return appropriate error (pending/approved/rejected status)
   * 5. Check deleted_at is null (account not soft-deleted)
   * 6. Generate new JWT access and refresh tokens
   * 7. Create session record in ecommerce_mall_seller_sessions with IP, href, referrer
   * 8. Return IAuthorized response with tokens
   *
   * Error handling:
   * - Invalid credentials: Return 401 Unauthorized
   * - Account not approved: Return 403 Forbidden with approval_status
   * - Account rejected: Return 403 with rejection reason
   * - Account deleted: Return 404 Not Found
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEcommerceMallSeller.ILogin,
  ): Promise<IEcommerceMallSeller.IAuthorized> {
    try {
      return await postEcommerceMallAuthSellerLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Token refresh endpoint for sellers to obtain new JWT access tokens using a valid refresh token.
   *
   * This operation extends the authenticated session without requiring the seller to re-enter credentials. The refresh token from the ecommerce_mall_seller_sessions table is validated. If valid and not expired, new JWT access and refresh tokens are generated to maintain continuous authentication.
   *
   * The operation ensures security by verifying the session belongs to an active seller account (deleted_at is null in ecommerce_mall_sellers). Old tokens are invalidated upon refresh, and the session record is updated with the new token values for audit tracking.
   *
   * This endpoint is essential for maintaining seamless user experience during extended sessions while enforcing token expiration for security.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh request containing the current refresh token to obtain new access and refresh tokens.
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Implementation steps:
   * 1. Extract seller_id from expired access token in request
   * 2. Validate refresh token from request body against ecommerce_mall_seller_sessions.refresh_token
   * 3. Check session not expired (expired_at > current time)
   * 4. Verify session belongs to valid seller (check ecommerce_mall_sellers deleted_at is null)
   * 5. Generate new access token with updated expiration
   * 6. Optionally generate new refresh token (token rotation)
   * 7. Update session record with new token values
   * 8. Return IAuthorized response with new tokens
   *
   * Error handling:
   * - Expired refresh token: Return 401 Unauthorized
   * - Invalid refresh token: Return 401 Unauthorized
   * - Session expired: Return 401 Unauthorized
   * - Seller account deleted: Return 401 Unauthorized
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IEcommerceMallSeller.IRefresh,
  ): Promise<IEcommerceMallSeller.IAuthorized> {
    try {
      return await postEcommerceMallAuthSellerRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
