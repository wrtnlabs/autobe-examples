import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallSuperAdmin } from "../../../../api/structures/IEcommerceMallSuperAdmin";
import { postEcommerceMallAuthSuperAdminJoin } from "../../../../providers/postEcommerceMallAuthSuperAdminJoin";
import { postEcommerceMallAuthSuperAdminLogin } from "../../../../providers/postEcommerceMallAuthSuperAdminLogin";
import { postEcommerceMallAuthSuperAdminRefresh } from "../../../../providers/postEcommerceMallAuthSuperAdminRefresh";

@Controller("/ecommerceMall/auth/superAdmin")
export class EcommercemallAuthSuperadminController {
  /**
   * Register a new super administrator account for platform management.
   *
   * Registers a new super admin with email and password credentials. The operation validates email uniqueness, enforces strong password requirements, and returns JWT access and refresh tokens for authentication. Super administrators have the highest privilege level including admin management capabilities.
   *
   * **Implementation Details:**
   * - Validates email format and uniqueness
   * - Enforces password strength requirements (minimum 8 characters with uppercase, lowercase, number, and special character)
   * - Hashes password using bcrypt before storage
   * - Creates session record with client metadata (IP, href, referrer)
   * - Returns access_token and refresh_token in IAuthorized response
   *
   * **Security Considerations:**
   * - Passwords are never stored in plain text
   * - Session tracking enables audit logging
   * - Soft delete support allows account deactivation without data loss
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Super admin registration request containing email and password credentials
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification 1. Validate email format and password strength (min 8 chars, require uppercase, lowercase, number, special char)
   * 2. Check email uniqueness in ecommerce_mall_super_admins table
   * 3. Hash password using bcrypt
   * 4. Create new superAdmin record with email and password_hash
   * 5. Generate access_token (JWT with superAdmin id, short expiry ~15min) and refresh_token (longer expiry ~7 days)
   * 6. Create session record in ecommerce_mall_super_admin_sessions with ip, href, referrer
   * 7. Return tokens and superAdmin info
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEcommerceMallSuperAdmin.IJoin,
  ): Promise<IEcommerceMallSuperAdmin.IAuthorized> {
    try {
      return await postEcommerceMallAuthSuperAdminJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate a super administrator with email and password credentials.
   *
   * Validates super admin credentials and returns JWT tokens for session management. Super administrators have exclusive privileges including admin management, super admin promotion/demotion, and full platform oversight.
   *
   * **Implementation Details:**
   * - Validates credentials against stored password_hash
   * - Checks account is not soft deleted (deleted_at is null)
   * - Creates session record for audit and security tracking
   * - Returns access_token (short-lived) and refresh_token (long-lived)
   *
   * **Security Considerations:**
   * - Failed login attempts should be rate limited
   * - Session metadata (IP, href, referrer) enables security audit
   * - Soft delete ensures revoked access is immediately effective
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Super admin login request with email and password credentials
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification 1. Validate email and password presence
   * 2. Look up superAdmin by email in ecommerce_mall_super_admins
   * 3. Verify password_hash matches provided password
   * 4. Check deleted_at is null (account not soft deleted)
   * 5. Generate new access_token and refresh_token
   * 6. Create session record in ecommerce_mall_super_admin_sessions
   * 7. Return tokens and superAdmin info
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEcommerceMallSuperAdmin.ILogin,
  ): Promise<IEcommerceMallSuperAdmin.IAuthorized> {
    try {
      return await postEcommerceMallAuthSuperAdminLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh authentication tokens using a valid refresh token.
   *
   * Extends an authenticated session by issuing new access and refresh tokens. Maintains security through short-lived access tokens while allowing persistent sessions via refresh tokens.
   *
   * **Implementation Details:**
   * - Validates refresh_token expiration
   * - Verifies superAdmin account is still active (not deleted)
   * - Issues new access_token with fresh expiry
   * - Optionally rotates refresh_token for enhanced security
   * - Updates session expiration timestamp
   *
   * **Security Considerations:**
   * - Token rotation reduces window of opportunity for token theft
   * - Session expiry tracking enables automatic invalidation
   * - Account deletion immediately invalidates all tokens
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Token refresh request containing the current refresh token
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification 1. Validate refresh_token presence and format
   * 2. Verify refresh_token is not expired
   * 3. Extract superAdmin id from refresh_token payload
   * 4. Look up superAdmin in ecommerce_mall_super_admins to verify still active
   * 5. Generate new access_token (and optionally new refresh_token)
   * 6. Update session record with new expiry
   * 7. Return new tokens and superAdmin info
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IEcommerceMallSuperAdmin.IRefresh,
  ): Promise<IEcommerceMallSuperAdmin.IAuthorized> {
    try {
      return await postEcommerceMallAuthSuperAdminRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
