import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallSuperAdmin } from "../../../../api/structures/IEcommerceMallSuperAdmin";
import { postEcommerceMallAuthSuperAdminJoin } from "../../../../providers/postEcommerceMallAuthSuperAdminJoin";
import { postEcommerceMallAuthSuperAdminLogin } from "../../../../providers/postEcommerceMallAuthSuperAdminLogin";
import { postEcommerceMallAuthSuperAdminRefresh } from "../../../../providers/postEcommerceMallAuthSuperAdminRefresh";

@Controller("/ecommerceMall/auth/superAdmin")
export class EcommercemallAuthSuperadminController {
  /**
   * Register a new super administrator account on the ecommerce mall platform. This operation creates a new super admin record in the ecommerce_mall_super_admins table with email and bcrypt-hashed password. Upon successful registration, the system issues a JWT access token and refresh token stored in the ecommerce_mall_super_admin_sessions table with session metadata including client IP, request path, and referrer. The access token contains superAdmin identity for subsequent API authentication. Super administrators have the highest authority level including managing other administrators, approving/rejecting admin requests, and platform-wide oversight.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Super admin registration request containing email address and password for new account creation.
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification 1. Validate request body (email, password fields)
   * 2. Hash password using bcrypt
   * 3. Create new super admin record in ecommerce_mall_super_admins table with email and password_hash
   * 4. Generate access token (JWT with superAdmin context) and refresh token
   * 5. Create session record in ecommerce_mall_super_admin_sessions table with ip, href, referrer metadata
   * 6. Return both tokens with authorized response
   *
   * Edge cases:
   * - Duplicate email: Return 409 Conflict
   * - Invalid email format: Return 400 Bad Request
   * - Password too short: Return 400 Bad Request
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEcommerceMallSuperAdmin.IJoin,
  ): Promise<IEcommerceMallSuperAdmin.IAuthorized> {
    try {
      return await postEcommerceMallAuthSuperAdminJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate an existing super administrator using email and password credentials. This operation validates the provided credentials against the ecommerce_mall_super_admins table, verifies the account is active (deleted_at is null), and issues new JWT tokens stored in the ecommerce_mall_super_admin_sessions table. Session metadata including client IP address, current page URL, and HTTP referrer are recorded for security audit purposes. The access token enables subsequent API calls requiring super admin authorization, while the refresh token allows token renewal without re-authentication.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Super admin login credentials containing email address and password for authentication.
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification 1. Validate request body (email, password fields)
   * 2. Query ecommerce_mall_super_admins table by email
   * 3. Verify password hash matches using bcrypt
   * 4. Check deleted_at is null (account not soft-deleted)
   * 5. Generate new access token and refresh token
   * 6. Create new session record in ecommerce_mall_super_admin_sessions with ip, href, referrer
   * 7. Return tokens with authorized response
   *
   * Edge cases:
   * - Email not found: Return 401 Unauthorized
   * - Wrong password: Return 401 Unauthorized
   * - Account deleted: Return 403 Forbidden
   * - Account suspended: Return 403 Forbidden
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEcommerceMallSuperAdmin.ILogin,
  ): Promise<IEcommerceMallSuperAdmin.IAuthorized> {
    try {
      return await postEcommerceMallAuthSuperAdminLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Renew authentication tokens using a valid refresh token. This operation accepts a previously issued refresh token from the ecommerce_mall_super_admin_sessions table, validates its authenticity and expiration, and issues a new pair of access and refresh tokens. The old session is replaced with a new session record to maintain session continuity while preventing token reuse attacks. This endpoint enables seamless session maintenance without requiring the super administrator to re-enter credentials. The refresh token mechanism supports the stateless JWT architecture where token expiration is handled client-side by proactively refreshing before the access token expires.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token request containing the current refresh token to obtain new authentication tokens.
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification 1. Validate request body (refresh token field)
   * 2. Verify refresh token is valid and not expired
   * 3. Extract super admin ID from refresh token payload
   * 4. Query ecommerce_mall_super_admin_sessions table to confirm session exists and not expired
   * 5. Generate new access token and refresh token
   * 6. Create new session record replacing the old one
   * 7. Optionally invalidate old session
   * 8. Return new tokens with authorized response
   *
   * Edge cases:
   * - Expired refresh token: Return 401 Unauthorized
   * - Invalid token format: Return 401 Unauthorized
   * - Session already expired: Return 401 Unauthorized
   * - Token reuse detected: Return 401 Unauthorized (security)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IEcommerceMallSuperAdmin.IRefresh,
  ): Promise<IEcommerceMallSuperAdmin.IAuthorized> {
    try {
      return await postEcommerceMallAuthSuperAdminRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
