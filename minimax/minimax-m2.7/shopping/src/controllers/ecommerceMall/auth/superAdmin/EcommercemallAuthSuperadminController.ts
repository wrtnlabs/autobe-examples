import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallSuperAdmin } from "../../../../api/structures/IEcommerceMallSuperAdmin";
import { postEcommerceMallAuthSuperAdminJoin } from "../../../../providers/postEcommerceMallAuthSuperAdminJoin";
import { postEcommerceMallAuthSuperAdminLogin } from "../../../../providers/postEcommerceMallAuthSuperAdminLogin";
import { postEcommerceMallAuthSuperAdminRefresh } from "../../../../providers/postEcommerceMallAuthSuperAdminRefresh";

@Controller("/ecommerceMall/auth/superAdmin")
export class EcommercemallAuthSuperadminController {
  /**
   * Register a new super administrator account with email and password credentials.
   *
   * This operation creates a new super administrator account in the ecommerce_mall_super_admins table, which stores senior administrators with highest platform privileges. The super admin email must be unique and is used for subsequent login authentication. The password is stored as a bcrypt hash, never in plaintext.
   *
   * Upon successful registration, the system issues JWT access and refresh tokens for immediate authentication. The access token is used for authorization on protected endpoints, while the refresh token enables token renewal without re-authentication.
   *
   * This endpoint is typically restricted during initial platform setup or requires existing super admin authorization for subsequent registrations to maintain platform security.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Registration credentials including unique email address and secure password for the new super administrator account.
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification Validate email format and uniqueness across super admin accounts. Hash password using bcrypt with appropriate cost factor. Create new super admin record with generated UUID primary key. Return access and refresh JWT tokens in IEcommerceMallSuperAdmin.IAuthorized response.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEcommerceMallSuperAdmin.IJoin,
  ): Promise<IEcommerceMallSuperAdmin.IAuthorized> {
    try {
      return await postEcommerceMallAuthSuperAdminJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate a super administrator using email and password credentials.
   *
   * This operation validates the super administrator's email and password against stored records in the ecommerce_mall_super_admins table. Successful authentication creates a new session record in ecommerce_mall_super_admin_sessions, capturing client metadata such as IP address, current page URL, and HTTP referrer for security audit purposes.
   *
   * The session expiration time is configurable and stored with each session record. Both access and refresh tokens are returned, enabling the super admin to access protected endpoints and renew sessions as needed.
   *
   * Failed authentication attempts should return appropriate error responses without revealing whether the email exists or the password is incorrect, preventing user enumeration attacks.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Authentication credentials consisting of email and password for super administrator login.
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification Validate provided email exists and password matches bcrypt hash. Generate new session record in ecommerce_mall_super_admin_sessions with client metadata (IP, href, referrer). Create access and refresh JWT tokens. Return tokens in IEcommerceMallSuperAdmin.IAuthorized response.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEcommerceMallSuperAdmin.ILogin,
  ): Promise<IEcommerceMallSuperAdmin.IAuthorized> {
    try {
      return await postEcommerceMallAuthSuperAdminLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Renew super administrator authentication using a valid refresh token.
   *
   * This operation accepts a valid refresh token and issues new access and refresh token pair without requiring the user to re-enter credentials. The refresh token must correspond to an active, non-expired session stored in ecommerce_mall_super_admin_sessions.
   *
   * The operation validates that the associated super administrator account (referenced by ecommerce_mall_super_admin_id) is still active and not soft-deleted. If the super admin was deleted, token refresh fails even if the token itself appears valid.
   *
   * Upon successful validation, new JWT tokens are generated and optionally a new session record is created to track the token renewal event. This enables security teams to audit session activity and detect potential token theft.
   *
   * This endpoint supports long-lived sessions and seamless user experience by allowing automatic token renewal before access token expiration.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token for renewing super administrator authentication session.
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification Validate refresh token from request body. Verify token is not expired and corresponds to a valid session in ecommerce_mall_super_admin_sessions. Check associated super admin account exists and is not soft-deleted. Generate new access and refresh token pair. Optionally create new session record or extend existing session. Return new tokens in IEcommerceMallSuperAdmin.IAuthorized response.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IEcommerceMallSuperAdmin.IRefresh,
  ): Promise<IEcommerceMallSuperAdmin.IAuthorized> {
    try {
      return await postEcommerceMallAuthSuperAdminRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
