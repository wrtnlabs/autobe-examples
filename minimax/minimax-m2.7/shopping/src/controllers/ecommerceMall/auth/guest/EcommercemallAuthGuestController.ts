import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallGuest } from "../../../../api/structures/IEcommerceMallGuest";
import { postEcommerceMallAuthGuestJoin } from "../../../../providers/postEcommerceMallAuthGuestJoin";
import { postEcommerceMallAuthGuestRefresh } from "../../../../providers/postEcommerceMallAuthGuestRefresh";

@Controller("/ecommerceMall/auth/guest")
export class EcommercemallAuthGuestController {
  /**
   * Creates a new guest identity for unauthenticated visitors to the ecommerce mall platform. This endpoint is the entry point for guests who want to establish a temporary session for browsing public content.
   *
   * The operation accepts a device fingerprint that uniquely identifies the visitor's device across sessions. The fingerprint is stored in the ecommerce_mall_guests table along with IP address and user agent for security tracking and analytics purposes.
   *
   * A new session is created in the ecommerce_mall_guest_sessions table with the guest's IP address, current page URL (href), and referrer header. The session has a configurable expiration time defined in the system settings.
   *
   * The response returns JWT access and refresh tokens that the client must include in subsequent requests to maintain the guest session. Access tokens are short-lived for security, while refresh tokens allow session renewal without re-authentication.
   *
   * This endpoint is public and does not require any authentication. It is the first step in the guest authentication flow before accessing any protected guest endpoints.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Guest join request containing device fingerprint for identity creation
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification Validate fingerprint presence and format. Create new guest record if not exists (check by fingerprint). Generate session token with expiration. Insert session into ecommerce_mall_guest_sessions table. Return access token and refresh token in response.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEcommerceMallGuest.IJoin,
  ): Promise<IEcommerceMallGuest.IAuthorized> {
    try {
      return await postEcommerceMallAuthGuestJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refreshes an existing guest session by exchanging a valid refresh token for new access and refresh tokens. This endpoint allows guests to maintain their browsing session without re-authenticating.
   *
   * The refresh token must be valid and not expired. The system looks up the associated guest session in the ecommerce_mall_guest_sessions table and verifies the guest record in ecommerce_mall_guests table exists and is not soft-deleted.
   *
   * On successful validation, new JWT tokens are generated. The session's expired_at timestamp may be updated depending on the refresh policy. The operation ensures session continuity by preserving the original guest identity and session context.
   *
   * This endpoint is public and does not require authentication. It is part of the token lifecycle management for guest sessions, ensuring smooth browsing experience without frequent re-authentication prompts.
   *
   * If the refresh token is invalid or expired, the client must call the join endpoint again to establish a new guest identity.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Guest refresh request containing the current refresh token
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification Validate refresh token from request body. Look up guest session by token. Verify session is not expired. Check guest record exists and is not soft-deleted. Generate new access token. Optionally generate new refresh token and update session. Return new access token and refresh token in response.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IEcommerceMallGuest.IRefresh,
  ): Promise<IEcommerceMallGuest.IAuthorized> {
    try {
      return await postEcommerceMallAuthGuestRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
