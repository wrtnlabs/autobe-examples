import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallGuest } from "../../../../api/structures/IEcommerceMallGuest";
import { postEcommerceMallAuthGuestJoin } from "../../../../providers/postEcommerceMallAuthGuestJoin";
import { postEcommerceMallAuthGuestRefresh } from "../../../../providers/postEcommerceMallAuthGuestRefresh";

@Controller("/ecommerceMall/auth/guest")
export class EcommercemallAuthGuestController {
  /**
   * Creates a new guest session for unauthenticated visitors.
   *
   * This endpoint establishes a guest account identified by device fingerprint. When an unauthenticated visitor accesses the platform, the system creates a guest record in the ecommerce_mall_guests table using the provided fingerprint string, capturing device information (IP address, user agent) for security tracking and analytics. A session token is generated and stored in ecommerce_mall_guest_sessions with configurable expiration duration.
   *
   * The response returns JWT access and refresh tokens that the client stores and includes in subsequent requests via Authorization header. The access token is short-lived (e.g., 1 hour) while the refresh token has longer validity (e.g., 7 days), allowing session continuity without re-authentication.
   *
   * Guest sessions track browsing context including current page URL (href) and referrer for understanding navigation patterns. The last_active_at timestamp on the guest record updates on each session interaction.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Request body containing device fingerprint for guest identification. The fingerprint is typically generated client-side using browser characteristics and used to recognize returning guests across sessions.
     * @x-autobe-authorization-type join
     * @x-autobe-authorization-actor guest
     * @x-autobe-specification 1. Validate fingerprint from request body exists
     *   and is non-empty. 2. Extract IP address from request headers
     *   (x-forwarded-for or remote address) and user agent from headers. 3.
     *   Create new guest record in ecommerce_mall_guests table with
     *   fingerprint, ip_address, user_agent, created_at, updated_at. 4. Create
     *   new session in ecommerce_mall_guest_sessions table with generated UUID,
     *   guest_id reference, IP, href, referrer, current timestamp for
     *   created_at, and expiration timestamp (configurable, e.g., 24 hours). 5.
     *   Generate JWT access token containing guest_id, session_id, exp claim.
     *   6. Generate refresh token with longer expiration (e.g., 7 days). 7.
     *   Return access token and refresh token in
     *   IEcommerceMallGuest.IAuthorized response.
   *
   * Error handling:
   * - 400 if fingerprint is missing or empty
   * - 500 on database errors
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEcommerceMallGuest.IJoin,
  ): Promise<IEcommerceMallGuest.IAuthorized> {
    try {
      return await postEcommerceMallAuthGuestJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refreshes an expired or expiring guest session token.
   *
   * This endpoint allows guest clients to obtain a new access token using a valid refresh token without requiring re-authentication. The guest presents the refresh token issued during the join operation, and if valid, receives a new access token with extended validity.
   *
   * Session validation checks the ecommerce_mall_guest_sessions table for the session_id embedded in the refresh token, verifying the session hasn't expired (expired_at) or been invalidated. The guest's last_active_at timestamp is updated to reflect continued engagement.
   *
   * For security, refresh tokens may be rotated on each use, invalidating the old token and issuing a new one to prevent token replay attacks. Clients must store the new refresh token from the response for subsequent refresh calls.
   *
   * The refresh token has a longer lifetime than the access token (e.g., 7 days vs 1 hour), enabling persistent guest sessions across browser sessions while maintaining security boundaries.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Request body containing the refresh token issued during guest join. The refresh token is used to obtain a new access token without re-authentication.
     * @x-autobe-authorization-type refresh
     * @x-autobe-authorization-actor guest
     * @x-autobe-specification 1. Extract refresh token from request body. 2.
     *   Validate refresh token signature and expiration. 3. Look up session by
     *   session_id from token claims. 4. Verify session hasn't been invalidated
     *   (check expiry, deleted status). 5. Update last_active_at on the guest
     *   record. 6. Optionally update session href/referrer if provided. 7.
     *   Generate new access token with updated expiration. 8. Optionally rotate
     *   refresh token (invalidate old, issue new) for security. 9. Return new
     *   access token and optionally new refresh token.
   *
   * Error handling:
   * - 401 if refresh token is invalid, expired, or revoked
   * - 404 if session not found
   * - 410 if guest account is deleted
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IEcommerceMallGuest.IRefresh,
  ): Promise<IEcommerceMallGuest.IAuthorized> {
    try {
      return await postEcommerceMallAuthGuestRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
