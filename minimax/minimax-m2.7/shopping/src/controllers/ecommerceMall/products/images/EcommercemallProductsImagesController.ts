import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIEcommerceMallProductImage } from "../../../../api/structures/IPageIEcommerceMallProductImage";
import { getEcommerceMallProductsProductIdImages } from "../../../../providers/getEcommerceMallProductsProductIdImages";

@Controller("/ecommerceMall/products/:productId/images")
export class EcommercemallProductsImagesController {
  /**
   * Retrieve all product images for a specific product.
   *
   * This endpoint returns the complete image gallery for a product, ordered by display position. The images form the visual gallery that accompanies the product's name, description, and price on the product detail page.
   *
   * The first image in the returned list (display_order = 0) serves as the main thumbnail image shown in search results and category listings. Subsequent images appear in order in the product's image carousel.
   *
   * If the product has no images, an empty array is returned. Clients should display a placeholder image in this case.
   *
   * Each image record includes the image URL pointing to the stored file, the display order for positioning in the gallery, and timestamps for when the image was added and last modified.
   *
   * This operation is accessible to all users including guests. No authentication is required.
   *
   * @param connection
   * @param productId UUID of the product to retrieve images for
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query the ecommerce_mall_product_images table filtering by the product_id matching the path parameter. Order results by display_order ascending to return images in gallery sequence. Return the image id, image_url, display_order, created_at, and updated_at fields for each image record. If no images exist, return an empty array.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async list(
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
  ): Promise<IPageIEcommerceMallProductImage.IProtocol> {
    try {
      return await getEcommerceMallProductsProductIdImages({
        productId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
