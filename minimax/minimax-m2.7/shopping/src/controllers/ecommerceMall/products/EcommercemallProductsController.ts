import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallProduct } from "../../../api/structures/IEcommerceMallProduct";
import { IPageIEcommerceMallProduct } from "../../../api/structures/IPageIEcommerceMallProduct";
import { getEcommerceMallProductsProductId } from "../../../providers/getEcommerceMallProductsProductId";
import { patchEcommerceMallProducts } from "../../../providers/patchEcommerceMallProducts";

@Controller("/ecommerceMall/products")
export class EcommercemallProductsController {
  /**
   * Search and list products with optional filters and sorting.
   *
   * This endpoint allows public users and customers to search products by name, filter by category, price range, and stock availability. Results are returned in a paginated format with configurable sorting options.
   *
   * **Filtering Criteria**: Users can filter by product name (partial match), category ID, minimum and maximum price, and stock availability. Multiple filters can be combined.
   *
   * **Sorting Options**: Results can be sorted by newest (creation date descending), price ascending, or price descending. Default sorting is by newest.
   *
   * **Pagination**: Results are paginated with page number and limit per page. Response includes total count and total pages for UI pagination.
   *
   * **Active Products Only**: Only products with null deleted_at are returned. Soft-deleted products are excluded from search results.
   *
   * @param connection
   * @param body Search criteria including optional filters for name query, category, price range, stock availability, sorting order, and pagination parameters.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor null
     * @x-autobe-specification Query the ecommerce_mall_products table applying
     *   the following filters:
   *
   * 1. **Name Search**: If 'query' is provided, perform case-insensitive partial match on name field using ILIKE pattern '%query%'.
   *
   * 2. **Category Filter**: If 'category' is provided, filter by ecommerce_mall_category_id matching the provided category UUID.
   *
   * 3. **Price Range**: If 'minPrice' is provided, filter base_price >= minPrice. If 'maxPrice' is provided, filter base_price <= maxPrice.
   *
   * 4. **Stock Availability**: If 'inStock' is true, filter to products that have at least one variant with quantity > 0. If 'inStock' is false, no stock filter applied.
   *
   * 5. **Exclude Deleted**: Always filter deleted_at IS NULL to exclude soft-deleted products.
   *
   * 6. **Sorting**:
   *    - 'newest': ORDER BY created_at DESC
   *    - 'price_asc': ORDER BY base_price ASC
   *    - 'price_desc': ORDER BY base_price DESC
   *    - Default: ORDER BY created_at DESC
   *
   * 7. **Pagination**: Apply OFFSET (page - 1) * limit and LIMIT limit.
   *
   * 8. **Response**: Return paginated results with IPageIEcommerceMallProduct.ISummary including total count and total pages in pagination metadata.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IEcommerceMallProduct.IRequest,
  ): Promise<IPageIEcommerceMallProduct.ISummary> {
    try {
      return await patchEcommerceMallProducts({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves detailed information about a specific product including all variants, images, seller information, and average rating.
   *
   * This endpoint provides the complete product view for customers browsing the marketplace. It returns the product name, description, base price, category information, all product images ordered by display order, all variants with their SKU codes and prices, the seller profile information including shop name and logo, and the calculated average rating from customer reviews.
   *
   * Only products that have not been deleted are accessible. Deleted products return a 404 error. Products without variants are shown as unavailable for purchase. The response includes the calculated price range when variants have different prices.
   *
   * @param connection
   * @param productId Unique identifier of the product in UUID format.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor null
     * @x-autobe-specification Query the ecommerce_mall_products table by id.
   *
   * Return 404 Not Found if product does not exist or has been deleted (deleted_at is not null).
   *
   * Join with ecommerce_mall_seller_profiles to get seller shop name and logo.
   * Join with ecommerce_mall_categories to get category name.
   * Join with ecommerce_mall_product_images ordered by display_order to get all images.
   * Join with ecommerce_mall_product_variants (where deleted_at is null) to get available variants with SKU codes, prices, and quantities.
   * Join with ecommerce_mall_reviews (where deleted_at is null) to calculate average rating and count.
   *
   * Calculate inStock boolean: true if any variant has quantity > 0.
   * Calculate priceRange: min and max price from variants or base_price if no variants.
   *
   * Return the complete product object with all nested data in a single response.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":productId")
  public async at(
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallProduct> {
    try {
      return await getEcommerceMallProductsProductId({
        productId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
