import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallCustomer } from "../../../../api/structures/IEcommerceMallCustomer";
import { IPageIEcommerceMallCustomer } from "../../../../api/structures/IPageIEcommerceMallCustomer";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getEcommerceMallAdminCustomersCustomerId } from "../../../../providers/getEcommerceMallAdminCustomersCustomerId";
import { patchEcommerceMallAdminCustomers } from "../../../../providers/patchEcommerceMallAdminCustomers";

@Controller("/ecommerceMall/admin/customers")
export class EcommercemallAdminCustomersController {
  /**
   * Lists all customers registered on the platform with pagination and filtering support.
   *
   * This endpoint is restricted to administrator accounts only. It allows administrators to browse the complete customer base with various filter criteria such as email search, registration date range, and account status. Results are returned in a paginated format optimized for administrative list displays.
   *
   * **Query Filters:**
   * Administrators can filter by email address (partial match supported), registration date range, and account status (active or deleted). Sorting options include newest first, oldest first, and email alphabetically.
   *
   * **Response Format:**
   * Each customer record includes basic identification information and profile data. The response omits sensitive data such as password hashes. Deleted accounts are included in results with their deletion timestamp for audit purposes.
   *
   * **Pagination:**
   * Standard cursor-based pagination using page number and limit parameters. Maximum 100 records per page.
   *
   * @param connection
   * @param body Search criteria including email filter, date range filters, account status filter, and pagination parameters.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification Query the ecommerce_mall_customers table with
     *   LEFT JOIN on ecommerce_mall_customer_profiles to include profile data.
   *
   * Apply search filters:
   * - Filter by email using ILIKE for partial matching
   * - Filter by created_at date range if provided
   * - Filter by deleted_at status: null = active, not null = deleted
   *
   * Apply sorting by created_at DESC (newest first) as default.
   *
   * Join with customer_profiles to retrieve display_name and phone.
   *
   * Implement pagination with page and limit parameters. Maximum limit is 100.
   *
   * Exclude password_hash from response for security.
   *
   * Return total count for pagination metadata.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IEcommerceMallCustomer.IRequest,
  ): Promise<IPageIEcommerceMallCustomer.ISummary> {
    try {
      return await patchEcommerceMallAdminCustomers({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves detailed information about a specific customer account by their unique identifier.
   *
   * This endpoint allows administrators to view customer account details including email address, account creation date, last modification timestamp, and account status. The account status is determined by the deleted_at field - a null value indicates an active account while a non-null timestamp indicates the account has been soft-deleted by the customer.
   *
   * **Account Status**: The deleted_at field indicates whether the account is active (null) or has been deleted (non-null timestamp). When deleted, profile information is removed but order history and reviews are preserved for legal compliance and seller records.
   *
   * **Related Data Access**: To retrieve associated data such as customer profile, shipping addresses, orders, or reviews, use the respective endpoints with the customer ID as a filter parameter.
   *
   * **Access Control**: This endpoint requires administrator privileges. Regular customers cannot view other customers' accounts.
   *
   * @param connection
   * @param customerId Unique identifier of the customer account to retrieve (UUID format).
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification Query the ecommerce_mall_customers table using
     *   the provided customerId path parameter as the primary key.
   *
   * Validate that customerId is a valid UUID format. Return 400 Bad Request with validation error if the format is invalid.
   *
   * Execute database query: SELECT id, email, created_at, updated_at, deleted_at FROM ecommerce_mall_customers WHERE id = $customerId.
   *
   * If no record is found, return 404 Not Found with error message indicating the customer does not exist.
   *
   * Return the customer object with all retrieved fields. The password_hash field must never be included in the response for security reasons.
   *
   * Note: Include the deleted_at field in the response to allow consumers to determine account status (active vs soft-deleted).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":customerId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("customerId")
    customerId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallCustomer> {
    try {
      return await getEcommerceMallAdminCustomersCustomerId({
        admin,
        customerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
