import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallSeller } from "../../../../api/structures/IEcommerceMallSeller";
import { IPageIEcommerceMallSeller } from "../../../../api/structures/IPageIEcommerceMallSeller";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getEcommerceMallAdminSellersSellerId } from "../../../../providers/getEcommerceMallAdminSellersSellerId";
import { patchEcommerceMallAdminSellers } from "../../../../providers/patchEcommerceMallAdminSellers";

@Controller("/ecommerceMall/admin/sellers")
export class EcommercemallAdminSellersController {
  /**
   * Retrieve a filtered and paginated list of sellers registered on the platform.
   *
   * This operation allows administrators to search and filter sellers by various criteria including approval status, shop name, email, and registration date. Results are paginated with configurable page sizes and sorting options.
   *
   * The search functionality supports partial matching on shop name and email address. Administrators can filter by approval status (pending, approved, rejected) to review seller registrations or manage existing sellers. Date range filtering allows finding sellers registered within specific time periods.
   *
   * Sellers with pending status have limited platform access and cannot list products. Approved sellers have full selling privileges. Rejected sellers may have provided a rejection reason and can resubmit registration.
   *
   * @param connection
   * @param body Search criteria, filters, and pagination parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query ecommerce_mall_sellers table with optional JOIN to ecommerce_mall_seller_profiles for shop name search.
   *
   * Apply filters: approval_status (exact match), created_at range, and search term (ILIKE on email and shop name).
   *
   * Only return sellers where deleted_at IS NULL to exclude soft-deleted accounts.
   *
   * Pagination: limit default 20, max 100. Sort by created_at DESC by default.
   *
   * For seller role: return only their own record. For admin/superAdmin: return all matching records.
   *
   * Response includes seller summary without password_hash field. Join with seller_profiles to include shop name if available.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IEcommerceMallSeller.IRequest,
  ): Promise<IPageIEcommerceMallSeller.ISummary> {
    try {
      return await patchEcommerceMallAdminSellers({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve the public profile information of a seller by their unique identifier.
   *
   * This endpoint returns the seller's public shop information including shop name, business description, and logo image. It is accessible to all users including guests and does not require authentication.
   *
   * The response includes the seller's basic account information (approval status, creation date) along with their complete shop profile. Only approved sellers with non-deleted profiles will return complete data. Sellers with pending or rejected status will return limited information.
   *
   * This operation is used when customers browse products and want to learn more about a seller, when viewing seller pages directly, or when customers need to identify which shop fulfilled their order.
   *
   * @param connection
   * @param sellerId Unique identifier of the seller (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query the ecommerce_mall_sellers table by the provided sellerId UUID.
   *
   * Verify the seller exists and is not soft-deleted (deleted_at IS NULL).
   *
   * If seller does not exist or is deleted, return 404 Not Found with error code SELLER_NOT_FOUND.
   *
   * Join with ecommerce_mall_seller_profiles table to retrieve shop profile data.
   *
   * If the seller has no profile or the profile is soft-deleted:
   * - Return 404 Not Found with error code SELLER_PROFILE_NOT_FOUND.
   *
   * Check approval_status:
   * - If 'approved': Return full profile data including name, description, logo_uri.
   * - If 'pending' or 'rejected': Return basic seller info only (id, approval_status, created_at) without profile details.
   *
   * Return response with:
   * - Seller: id, approval_status, created_at
   * - Profile (if approved): name, description, logo_uri, created_at, updated_at
   *
   * No authentication required - this is a public endpoint.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sellerId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallSeller.IInvert> {
    try {
      return await getEcommerceMallAdminSellersSellerId({
        admin,
        sellerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
