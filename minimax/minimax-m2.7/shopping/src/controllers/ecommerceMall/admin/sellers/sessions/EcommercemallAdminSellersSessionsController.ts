import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallSellerSession } from "../../../../../api/structures/IEcommerceMallSellerSession";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getEcommerceMallAdminSellersSellerIdSessionsSessionId } from "../../../../../providers/getEcommerceMallAdminSellersSellerIdSessionsSessionId";
import { patchEcommerceMallAdminSellersSellerIdSessions } from "../../../../../providers/patchEcommerceMallAdminSellersSellerIdSessions";

@Controller("/ecommerceMall/admin/sellers/:sellerId/sessions")
export class EcommercemallAdminSellersSessionsController {
  /**
   * Invalidate seller sessions to terminate authentication on other devices.
   *
   * This operation allows administrators or the system to terminate specific seller sessions for security purposes. When a seller changes their password, all sessions except the current one should be invalidated. Administrators can also manually terminate sessions for security monitoring.
   *
   * The operation supports selective invalidation by session ID or bulk invalidation of all sessions for a specific seller, except for a session that should remain active (such as the session where the password change occurred).
   *
   * Session termination removes the associated access and refresh tokens, making them invalid for subsequent API requests. The seller will need to log in again from the terminated session.
   *
   * @param connection
   * @param sellerId Unique identifier of the seller (UUID)
   * @param body Session invalidation criteria and options
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification This endpoint handles seller session invalidation for security purposes.
   *
   * Implementation:
   * 1. Validate sellerId exists in ecommerce_mall_sellers table
   * 2. Verify the seller is not banned or deleted (deleted_at is null)
   * 3. If sessionIds provided: terminate only those sessions by setting access_token and refresh_token to null
   * 4. If sessionIds not provided: terminate ALL sessions except the current session (if sessionId provided)
   * 5. Update the affected session records in ecommerce_mall_seller_sessions table
   * 6. Return count of invalidated sessions
   *
   * Security rules:
   * - Sellers can only invalidate their own sessions (or through admin)
   * - Cannot invalidate a session that is currently making the request
   * - All token-based authentication will fail for invalidated sessions
   *
   * Error handling:
   * - 404: Seller not found
   * - 403: Requester not authorized to invalidate sessions for this seller
   * - 400: Invalid request parameters
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async invalidate(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceMallSellerSession.IInvalidateRequest,
  ): Promise<IEcommerceMallSellerSession.IInvalidateResponse> {
    try {
      return await patchEcommerceMallAdminSellersSellerIdSessions({
        admin,
        sellerId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific seller session by its unique identifier.
   *
   * This endpoint returns detailed session information including the session ID, client metadata (IP address, browser referrer), JWT tokens status, creation timestamp, and expiration time. The sellerId parameter ensures the session belongs to the authenticated seller for authorization purposes.
   *
   * Sessions track authenticated seller activity across devices. Each session maintains its own access and refresh tokens. Sellers can view all their active sessions to monitor login activity or identify unauthorized access.
   *
   * The session is invalidated when expired or when the seller logs out.
   *
   * @param connection
   * @param sellerId Unique identifier of the seller (UUID)
   * @param sessionId Unique identifier of the session (UUID)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query ecommerce_mall_seller_sessions table filtering by id matching sessionId parameter. Join with ecommerce_mall_sellers table to verify the session belongs to the seller identified by sellerId. Return session record including: id, ecommerce_mall_seller_id, ip, href, referrer, access_token (if present), refresh_token (if present), created_at, expired_at. Return 404 if session not found or does not belong to seller. Return session details only, do not include sensitive token values.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallSellerSession> {
    try {
      return await getEcommerceMallAdminSellersSellerIdSessionsSessionId({
        admin,
        sellerId,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
