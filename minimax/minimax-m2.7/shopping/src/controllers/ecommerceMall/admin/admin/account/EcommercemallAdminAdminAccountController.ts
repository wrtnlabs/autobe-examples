import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { deleteEcommerceMallAdminAdminAccount } from "../../../../../providers/deleteEcommerceMallAdminAdminAccount";

@Controller("/ecommerceMall/admin/admin/account")
export class EcommercemallAdminAdminAccountController {
  /**
   * Allows an authenticated administrator to permanently delete their own administrator account from the platform.
   *
   * This endpoint performs a soft deletion by setting the deleted_at timestamp, which prevents future authentication while preserving the account record for audit trail purposes. Upon deletion, all active sessions for this administrator are immediately terminated and the administrator cannot log in.
   *
   * **Prerequisites**: The administrator must be authenticated with a valid session token.
   *
   * **Account Recovery**: Once deleted, the account cannot be recovered through API endpoints. A super administrator may manually restore the account by clearing the deleted_at field directly in the database if necessary.
   *
   * **Comparison with Other Account Deletions**: Unlike seller account deletion which has restrictions (no pending orders or refund requests), administrator account deletion has no such preconditions. This is because administrator accounts do not have direct transactional responsibilities.
   *
   * @param connection
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification 1. Retrieve the authenticated administrator's ID
     *   from the JWT session token in the Authorization header. 2. Validate
     *   that the admin session exists and is active by checking
     *   ecommerce_mall_admin_sessions table. 3. If session validation fails,
     *   return 401 Unauthorized error. 4. Set the deleted_at timestamp to
     *   current UTC time for the admin record in ecommerce_mall_admins table.
     *   5. Delete all active session records for this admin from
     *   ecommerce_mall_admin_sessions to terminate all login sessions. 6.
     *   Return 204 No Content response with no body.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
  ): Promise<void> {
    try {
      return await deleteEcommerceMallAdminAdminAccount({
        admin,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
