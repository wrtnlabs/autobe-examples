import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallAdminPasswordReset } from "../../../../../api/structures/IEcommerceMallAdminPasswordReset";
import { IPageIEcommerceMallAdminPasswordReset } from "../../../../../api/structures/IPageIEcommerceMallAdminPasswordReset";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getEcommerceMallAdminAdminPasswordResetsResetId } from "../../../../../providers/getEcommerceMallAdminAdminPasswordResetsResetId";
import { patchEcommerceMallAdminAdminPasswordResets } from "../../../../../providers/patchEcommerceMallAdminAdminPasswordResets";

@Controller("/ecommerceMall/admin/admin/password-resets")
export class EcommercemallAdminAdminPassword_resetsController {
  /**
   * Retrieve a filtered and paginated list of administrator password reset tokens.
   *
   * This operation provides administrative oversight capabilities for password reset activity on admin accounts. Administrators can search and filter reset tokens by admin account, token status (active, used, expired), and date ranges.
   *
   * Token status is determined by: active tokens have null used_at and future expires_at, used tokens have non-null used_at, expired tokens have past expires_at with null used_at.
   *
   * Supports cursor-based pagination with configurable page sizes for efficient browsing of large token histories.
   *
   * @param connection
   * @param body Search criteria including pagination, filtering by admin, status, and date ranges
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query ecommerce_mall_admin_password_resets table with pagination and filtering.
   *
   * Apply search filters:
   * - Filter by ecommerce_mall_admin_id to view resets for specific admin
   * - Filter by status: 'active' (unused and not expired), 'used', 'expired', or 'all'
   * - Filter by created_at date range (fromDate, toDate)
   * - Filter by expires_at date range
   *
   * Join with ecommerce_mall_admins to include admin email (optional based on request).
   *
   * Return cursor-based pagination for large result sets.
   *
   * Validate that requesting user is a super administrator.
   *
   * Order by created_at descending by default.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IEcommerceMallAdminPasswordReset.IRequest,
  ): Promise<IPageIEcommerceMallAdminPasswordReset> {
    try {
      return await patchEcommerceMallAdminAdminPasswordResets({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific admin password reset record by its unique identifier.
   *
   * This operation allows administrators and super administrators to view details of a password reset request including the token status (active, expired, or used), expiration timestamp, and whether the token has been consumed. Password reset records are created when administrators request account recovery and are automatically invalidated after use or expiration.
   *
   * The response includes the reset identifier, associated administrator reference, token metadata (hashed for security), and timestamps for creation, expiration, and usage. This operation supports audit and security review workflows for super administrators.
   *
   * @param connection
   * @param resetId Unique identifier of the password reset record (UUID)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query the ecommerce_mall_admin_password_resets table using the provided resetId as the primary key. Return the matching record including all fields: id, ecommerce_mall_admin_id, token hash, expires_at, used_at, created_at, updated_at. Join with ecommerce_mall_admins table to include administrator email for reference. Handle not found scenario by returning 404 error. This is a read-only operation with no side effects.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":resetId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("resetId")
    resetId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallAdminPasswordReset> {
    try {
      return await getEcommerceMallAdminAdminPasswordResetsResetId({
        admin,
        resetId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
