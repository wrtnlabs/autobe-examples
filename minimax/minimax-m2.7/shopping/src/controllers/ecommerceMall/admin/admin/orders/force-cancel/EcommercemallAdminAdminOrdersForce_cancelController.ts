import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallOrder } from "../../../../../../api/structures/IEcommerceMallOrder";
import { AdminAuth } from "../../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../../decorators/payload/AdminPayload";
import { postEcommerceMallAdminAdminOrdersOrderIdForceCancel } from "../../../../../../providers/postEcommerceMallAdminAdminOrdersOrderIdForceCancel";

@Controller("/ecommerceMall/admin/admin/orders/:orderId/force-cancel")
export class EcommercemallAdminAdminOrdersForce_cancelController {
  /**
   * Force cancel all eligible items in an order.
   *
   * This endpoint allows administrators to cancel all order items with 'paid' status in an entire order. For each cancelled item, the system immediately processes a refund and restores the stock quantity by creating inventory records.
   *
   * **Cancellation Behavior:**
   * - Only items with 'paid' status are cancelled
   * - Items already shipped, delivered, cancelled, or refunded are skipped
   * - Each cancelled item triggers a refund and stock restoration
   * - Order status is updated to reflect the new state
   *
   * **Authorization:**
   * - Requires ADMIN or SUPER_ADMIN role
   *
   * **Error Handling:**
   * - Returns 404 if order not found
   * - Returns 400 if order has no eligible items to cancel
   *
   * @param connection
   * @param orderId Unique order number of the order to force cancel.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification 1. Validate the order exists in ecommerce_mall_orders table using orderId as order_number
   * 2. Query all order items from ecommerce_mall_order_items where ecommerce_mall_order_id matches orderId and status equals 'paid'
   * 3. If no eligible items found, return 400 error
   * 4. For each eligible order item:
   *    a. Update status to 'cancelled' in ecommerce_mall_order_items
   *    b. Process refund via payment gateway
   *    c. Create inventory record in ecommerce_mall_inventory_records with quantity_change = +quantity, reason = 'order_cancellation'
   * 5. Update order status in ecommerce_mall_orders based on remaining items:
   *    - If all items cancelled → status = 'cancelled'
   *    - If mixed states → status = 'partially_completed'
   * 6. Return the updated order with all order items included
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async forceCancel(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("orderId")
    orderId: string,
  ): Promise<IEcommerceMallOrder> {
    try {
      return await postEcommerceMallAdminAdminOrdersOrderIdForceCancel({
        admin,
        orderId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
