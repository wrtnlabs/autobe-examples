import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallOrder } from "../../../../../api/structures/IEcommerceMallOrder";
import { IPageIEcommerceMallOrder } from "../../../../../api/structures/IPageIEcommerceMallOrder";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getEcommerceMallAdminAdminOrders } from "../../../../../providers/getEcommerceMallAdminAdminOrders";
import { getEcommerceMallAdminAdminOrdersOrderId } from "../../../../../providers/getEcommerceMallAdminAdminOrdersOrderId";
import { patchEcommerceMallAdminAdminOrders } from "../../../../../providers/patchEcommerceMallAdminAdminOrders";

@Controller("/ecommerceMall/admin/admin/orders")
export class EcommercemallAdminAdminOrdersController {
  /**
   * Lists all orders on the platform with pagination and optional filtering.
   *
   * This endpoint allows administrators to view and browse all orders placed by customers across the entire platform. The response includes paginated order summaries with key information for quick administrative reference.
   *
   * **Pagination**
   * Results are returned in pages. Use page and limit query parameters to navigate through results. Default page size is 20.
   *
   * **Filtering Options**
   * Administrators can filter orders using query parameters:
   * - Filter by status (paid, shipped, delivered, cancelled, refunded, partially_completed)
   * - Filter by customer ID to view specific customer's orders
   * - Filter by date range using startDate and endDate
   *
   * **Order Information**
   * Each order in the list displays the order number for reference, total order amount, current order status, and creation timestamp. The full order details can be retrieved using the individual order retrieval endpoint.
   *
   * **Access Control**
   * This endpoint is restricted to administrators and super administrators only. Regular customers cannot access this endpoint. Sellers cannot access other sellers' order information.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query ecommerce_mall_orders table with pagination.
   *
   * Apply optional filtering based on query parameters:
   * - Filter by status if provided (matching order status field)
   * - Filter by customer if customerId query param provided
   * - Filter by date range if startDate/endDate provided
   *
   * Join with ecommerce_mall_customers table to include customer email or name in response.
   *
   * Order results by created_at descending (newest first).
   *
   * Return pagination metadata including total count, current page, page size, and total pages.
   *
   * Exclude soft-deleted orders (where deleted_at is not null).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async list(
    @AdminAuth()
    admin: AdminPayload,
  ): Promise<IPageIEcommerceMallOrder.ISummary> {
    try {
      return await getEcommerceMallAdminAdminOrders({
        admin,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Lists all orders on the platform for administrative oversight.
   *
   * Administrators can filter orders by status, customer, date range, and amount range to find specific orders for review or action. The results are paginated with configurable page size.
   *
   * **Filtering Options**: Order status (paid, shipped, delivered, cancelled, refunded, partially_completed), customer ID, creation date range, total amount range.
   *
   * **Sorting**: Default sorting by creation date descending (newest first).
   *
   * **Access Control**: Requires administrator or super administrator authentication.
   *
   * @param connection
   * @param body Search criteria including order status filter, customer ID filter, date range filters (createdAtFrom, createdAtTo), amount range filters (minTotal, maxTotal), and pagination parameters (page, limit).
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query ecommerce_mall_orders table with JOIN on ecommerce_mall_customers for customer email display when customer filter is applied.
   *
   * Apply search filters:
   * - Filter by order status (exact match on status field)
   * - Filter by customer ID (exact match on ecommerce_mall_customer_id)
   * - Filter by date range (created_at >= fromDate AND created_at <= toDate)
   * - Filter by amount range (total_amount >= minAmount AND total_amount <= maxAmount)
   *
   * Support cursor-based or offset-based pagination with configurable page size.
   *
   * Order results by created_at DESC by default.
   *
   * Join with order_items to include item count in summary if requested.
   *
   * Return paginated results with total count for pagination metadata.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IEcommerceMallOrder.IRequest,
  ): Promise<IPageIEcommerceMallOrder.ISummary> {
    try {
      return await patchEcommerceMallAdminAdminOrders({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves complete details of a specific order for administrative oversight.
   *
   * This endpoint provides administrators with full visibility into any order on the platform, including customer information, shipping address, all order items with frozen product and seller snapshots, and shipment tracking details. Administrators use this endpoint for customer service support, dispute resolution, and order oversight.
   *
   * **Order Details**: Returns order number, totals (subtotal, shipping cost, total amount), current status, and timestamps.
   *
   * **Customer Information**: Includes customer email and name for contact purposes.
   *
   * **Shipping Address**: Full delivery address including recipient name, phone, street address, city, state, postal code, and country.
   *
   * **Order Items**: Each item includes purchased product snapshot (name, description, base price, category), seller profile snapshot (shop name, logo), quantity, unit price, and item status (paid, shipped, delivered, cancelled, refunded).
   *
   * **Shipments**: Lists all shipments for the order with carrier name, tracking number, and creation timestamp.
   *
   * Only super administrators and regular administrators have access to this endpoint.
   *
   * @param connection
   * @param orderId Unique identifier of the order to retrieve.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query ecommerce_mall_orders table using the provided orderId.
   *
   * Validate that the order exists; return 404 if not found.
   *
   * Join and load related data:
   * - Customer details from ecommerce_mall_customers (email)
   * - Shipping address from ecommerce_mall_shipping_addresses
   * - All order items from ecommerce_mall_order_items
   * - For each order item, load:
   *   - Product snapshot from ecommerce_mall_product_snapshots (name, description, base_price, category_name)
   *   - Seller profile snapshot from ecommerce_mall_seller_profile_snapshots (shop_name, shop_description, logo_url)
   *   - Shipment items from ecommerce_mall_shipment_items linking to shipments
   * - All shipments from ecommerce_mall_shipments with tracking information
   *
   * Construct the response object with all loaded data organized hierarchically.
   *
   * Handle soft-deleted orders: Return the order data even if deleted_at is set, as historical records must be accessible for administrative purposes.
   *
   * Return 403 if the authenticated user does not have ADMIN or SUPER_ADMIN role.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":orderId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallOrder> {
    try {
      return await getEcommerceMallAdminAdminOrdersOrderId({
        admin,
        orderId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
