import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallShipmentMetric } from "../../../../../../api/structures/IEcommerceMallShipmentMetric";
import { AdminAuth } from "../../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../../decorators/payload/AdminPayload";
import { getEcommerceMallAdminAdminFulfillmentMetrics } from "../../../../../../providers/getEcommerceMallAdminAdminFulfillmentMetrics";

@Controller("/ecommerceMall/admin/admin/fulfillment/metrics")
export class EcommercemallAdminAdminFulfillmentController {
  /**
   * Retrieves fulfillment performance metrics and statistics for the entire platform.
   *
   * This endpoint provides administrators and super administrators with aggregated data about order fulfillment across all sellers and customers. Metrics include order volumes by status, shipment statistics, and fulfillment performance indicators.
   *
   * **Metrics Categories:**
   *
   * **Order Statistics:**
   * - Total number of orders
   * - Breakdown by status: paid, shipped, delivered, cancelled, refunded, partially_completed
   *
   * **Order Item Statistics:**
   * - Total number of items ordered
   * - Breakdown by item status: paid, shipped, delivered, cancelled, refunded
   *
   * **Shipment Statistics:**
   * - Total shipments created
   * - Total items shipped
   * - Average items per shipment
   *
   * **Fulfillment Performance:**
   * - Average fulfillment time (paid to shipped)
   * - Delivery completion rate
   *
   * **Authorization:**
   * Only authenticated administrators and super administrators can access this endpoint. Regular customers and sellers receive a 403 Forbidden response.
   *
   * @param connection
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification Query ecommerce_mall_orders,
     *   ecommerce_mall_order_items, and ecommerce_mall_shipments tables to
     *   compute fulfillment metrics.
   *
   * Implementation steps:
   *
   * 1. Query order statistics:
   *    - Count total active orders (where deleted_at IS NULL)
   *    - Group orders by status: paid, shipped, delivered, cancelled, refunded, partially_completed
   *    - Calculate total revenue from completed orders (delivered + refunded)
   *
   * 2. Query order item statistics:
   *    - Count total order items
   *    - Group items by status: paid, shipped, delivered, cancelled, refunded
   *    - Calculate average order item quantity
   *
   * 3. Query shipment statistics:
   *    - Count total shipments (where deleted_at IS NULL)
   *    - Sum total shipment items via ecommerce_mall_shipment_items
   *    - Calculate average items per shipment
   *
   * 4. Calculate fulfillment performance metrics:
   *    - Average time from paid to shipped status (for shipped items)
   *    - Calculate delivery rate: (delivered + refunded) / total items
   *    - Calculate cancellation rate: cancelled / total items
   *
   * 5. Return IEcommerceMallFulfillmentMetrics object with all computed statistics
   *
   * Edge cases:
   * - No orders exist: Return zeros for all counts with null for averages
   * - Soft-deleted orders and shipments are excluded from calculations
   * - All timestamps use created_at from respective tables
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async metrics(
    @AdminAuth()
    admin: AdminPayload,
  ): Promise<IEcommerceMallShipmentMetric> {
    try {
      return await getEcommerceMallAdminAdminFulfillmentMetrics({
        admin,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
