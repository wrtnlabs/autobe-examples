import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallSellerSuspension } from "../../../../../api/structures/IEcommerceMallSellerSuspension";
import { IPageIEcommerceMallSellerSuspension } from "../../../../../api/structures/IPageIEcommerceMallSellerSuspension";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getEcommerceMallAdminAdminSellerSuspensionsSuspensionId } from "../../../../../providers/getEcommerceMallAdminAdminSellerSuspensionsSuspensionId";
import { patchEcommerceMallAdminAdminSellerSuspensions } from "../../../../../providers/patchEcommerceMallAdminAdminSellerSuspensions";

@Controller("/ecommerceMall/admin/admin/seller-suspensions")
export class EcommercemallAdminAdminSeller_suspensionsController {
  /**
   * Lists seller suspension records for administrative oversight and audit purposes.
   *
   * This endpoint allows administrators to search and filter suspension records including active suspensions (restored_at IS NULL) and historical suspensions. Search supports filtering by seller, suspension period, and administrative actor who performed the action.
   *
   * **Search Criteria**:
   * - Filter by specific seller using sellerId
   * - Filter by suspension status: active (still suspended) or resolved (restored)
   * - Filter by suspension date range (suspended_at)
   * - Filter by restoration date range (restored_at)
   * - Filter by administrator who performed suspension or restoration
   * - Pagination with cursor or offset-based navigation
   *
   * **Response**: Returns paginated suspension records sorted by suspended_at descending by default.
   *
   * @param connection
   * @param body Search criteria including seller ID, suspension status, date ranges, and pagination parameters.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query the ecommerce_mall_seller_suspensions table with pagination and filtering.
   *
   * Apply search filters:
   * - sellerId filter: match ecommerce_mall_seller_id exactly
   * - status filter: 'active' returns records where restored_at IS NULL; 'resolved' returns records where restored_at IS NOT NULL
   * - suspendedAtFrom/suspendedAtTo: filter by suspended_at timestamp range
   * - restoredAtFrom/restoredAtTo: filter by restored_at timestamp range (for resolved suspensions)
   * - suspendedById filter: match suspended_by_id
   * - restoredById filter: match restored_by_id (supports null filter for active suspensions)
   *
   * Join with ecommerce_mall_sellers table to include seller email in response if requested.
   * Join with ecommerce_mall_admins table twice for suspended_by and restored_by information.
   *
   * Return cursor-based pagination using suspended_at as cursor for consistent results with new suspensions.
   * Default page size: 20, maximum: 100.
   *
   * Order by suspended_at DESC by default.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IEcommerceMallSellerSuspension.IRequest,
  ): Promise<IPageIEcommerceMallSellerSuspension.ISummary> {
    try {
      return await patchEcommerceMallAdminAdminSellerSuspensions({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves a specific seller suspension record by its unique identifier.
   *
   * This endpoint returns detailed information about a seller suspension including the suspended seller details, the administrator who performed the suspension, and optionally the administrator who restored the account. The suspension record contains the reason for suspension, timestamps, and restoration details if the seller has been unsuspended.
   *
   * **Access Control**: Only administrators and super administrators can access this endpoint.
   *
   * **Resource Relationships**: The returned suspension record includes the full seller profile (email, shop name, status) and the administrators involved in the suspension and potential restoration actions.
   *
   * @param connection
   * @param suspensionId Unique identifier (UUID) of the seller suspension record to retrieve.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query the ecommerce_mall_seller_suspensions table by the provided suspensionId UUID.
   *
   * Join with ecommerce_mall_sellers table to include seller details (email, approval_status, suspension_status).
   * Join with ecommerce_mall_admins table twice: once for suspended_by_id and once for restored_by_id to include administrator names.
   *
   * Return the complete suspension record including:
   * - Suspension ID and timestamps (created_at, updated_at, suspended_at, restored_at)
   * - Suspension reason and optional restoration reason
   * - Suspended seller details (via seller relation)
   * - Suspending administrator details (via suspendedBy relation)
   * - Restoring administrator details if applicable (via restoredBy relation)
   *
   * If no suspension record exists with the given ID, return 404 Not Found error.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":suspensionId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("suspensionId")
    suspensionId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallSellerSuspension.IInvert> {
    try {
      return await getEcommerceMallAdminAdminSellerSuspensionsSuspensionId({
        admin,
        suspensionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
