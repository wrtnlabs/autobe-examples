import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallAdmin } from "../../../../../api/structures/IEcommerceMallAdmin";
import { IPageIEcommerceMallAdmin } from "../../../../../api/structures/IPageIEcommerceMallAdmin";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getEcommerceMallAdminAdminAdminsAdminId } from "../../../../../providers/getEcommerceMallAdminAdminAdminsAdminId";
import { patchEcommerceMallAdminAdminAdmins } from "../../../../../providers/patchEcommerceMallAdminAdminAdmins";

@Controller("/ecommerceMall/admin/admin/admins")
export class EcommercemallAdminAdminAdminsController {
  /**
   * Retrieves a paginated list of administrator accounts matching the specified search criteria.
   *
   * Super administrators can use this endpoint to search and filter all administrator accounts on the platform. Search filters include email pattern matching, name search, creation date ranges, and status filtering (active or deleted administrators).
   *
   * **Pagination**: Results are returned in pages with configurable size. Default page size is 20 with maximum 100 per page.
   *
   * **Sorting**: Results are sorted by creation date in descending order by default, showing newest administrators first.
   *
   * @param connection
   * @param body Search criteria including email filter, name filter, date range filters, status filter, and pagination parameters.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query ecommerce_mall_admins table with the following search criteria:
   * - Filter by email: partial match (LIKE %email%) if email filter provided
   * - Filter by name: partial match (LIKE %name%) if name filter provided
   * - Filter by createdAt range: created_after and created_before datetime filters
   * - Filter by status: 'active' returns only where deleted_at IS NULL, 'deleted' returns only where deleted_at IS NOT NULL, null/omitted returns all
   *
   * Apply pagination with page number and limit (default 20, max 100).
   * Sort by created_at descending (newest first) by default.
   *
   * Join with ecommerce_mall_admin_sessions for session status if requested.
   *
   * Return cursor-based pagination with total count for large result sets.
   *
   * Validate that the requesting user is a super administrator before allowing access.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IEcommerceMallAdmin.IRequest,
  ): Promise<IPageIEcommerceMallAdmin.ISummary> {
    try {
      return await patchEcommerceMallAdminAdminAdmins({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves detailed information for a specific administrator account by their unique identifier.
   *
   * This endpoint allows super administrators to view the complete profile of any administrator on the platform. The returned information includes the administrator's name, email address, account creation timestamp, and current status. This operation is essential for super administrator oversight of platform administrative staff.
   *
   * **Access Control**: Only super administrators can access this endpoint. Regular administrators are denied access to prevent unauthorized enumeration of administrative accounts.
   *
   * **Use Cases**: Super administrators may use this endpoint when reviewing administrative accounts, investigating administrative actions, or managing administrator privileges.
   *
   * @param connection
   * @param adminId Unique identifier of the administrator account to retrieve (UUID format).
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query the ecommerce_mall_admins table using the provided adminId parameter.
   *
   * Validate that the requesting user is a super administrator. If not, return 403 Forbidden.
   *
   * Fetch the admin record where id equals the provided adminId and deleted_at is NULL (active accounts only).
   *
   * If the admin record does not exist, return 404 Not Found.
   *
   * Return the admin entity with the following fields: id, email, name, created_at, updated_at.
   *
   * Do NOT include password_hash in the response for security reasons.
   *
   * Join with ecommerce_mall_admin_sessions if session information is needed, though this is typically not required for view operations.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":adminId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallAdmin> {
    try {
      return await getEcommerceMallAdminAdminAdminsAdminId({
        admin,
        adminId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
