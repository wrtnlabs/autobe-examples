import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallProduct } from "../../../../../api/structures/IEcommerceMallProduct";
import { IPageIEcommerceMallProduct } from "../../../../../api/structures/IPageIEcommerceMallProduct";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { deleteEcommerceMallAdminAdminProductsProductId } from "../../../../../providers/deleteEcommerceMallAdminAdminProductsProductId";
import { getEcommerceMallAdminAdminProducts } from "../../../../../providers/getEcommerceMallAdminAdminProducts";
import { getEcommerceMallAdminAdminProductsProductId } from "../../../../../providers/getEcommerceMallAdminAdminProductsProductId";
import { patchEcommerceMallAdminAdminProducts } from "../../../../../providers/patchEcommerceMallAdminAdminProducts";

@Controller("/ecommerceMall/admin/admin/products")
export class EcommercemallAdminAdminProductsController {
  /**
   * Retrieves a paginated list of all products on the platform for administrative oversight.
   *
   * This endpoint is restricted to administrators with platform management privileges. It returns product summaries including product name, base price, category information, seller information, status, and timestamps. Administrators can use this endpoint to review the complete product catalog and monitor seller activities.
   *
   * **Pagination:**
   * Results are returned in paginated format with configurable page number and page size. The response includes pagination metadata for building navigation controls.
   *
   * **Soft Delete Handling:**
   * By default, only active products are returned. Deleted products (those with deleted_at timestamp set) are excluded from the results to show only currently available listings.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query ecommerce_mall_products table with the following logic:
   *
   * 1. **Soft Delete Filter**: Apply `WHERE deleted_at IS NULL` to return only active products.
   *
   * 2. **Pagination**: Apply page and limit parameters with sensible defaults (page=1, limit=20).
   *
   * 3. **Joins**: Join with ecommerce_mall_sellers table to include seller name in results. Join with ecommerce_mall_categories table to include category name.
   *
   * 4. **Sorting**: Default sort by created_at DESC (newest first).
   *
   * 5. **Response Construction**: Return paginated summary array with pagination metadata including total count, current page, page size, and total pages.
   *
   * 6. **Authorization**: Verify authenticated user has ADMIN or SUPER_ADMIN role from JWT token.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async list(
    @AdminAuth()
    admin: AdminPayload,
  ): Promise<IPageIEcommerceMallProduct.ISummary> {
    try {
      return await getEcommerceMallAdminAdminProducts({
        admin,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and list all products on the platform with optional filters.
   *
   * Administrators can search products by name, filter by category, seller, price range, and stock availability. Results are returned in a paginated format sorted by creation date in descending order by default.
   *
   * **Filtering Options:**
   * - Name search: Match product names using case-insensitive partial matching
   * - Category filter: Filter by specific category ID
   * - Seller filter: Filter by specific seller ID
   * - Price range: Filter products within minimum and maximum price bounds
   * - Stock filter: Show only products with available stock or all products
   *
   * **Sorting:**
   * Results can be sorted by creation date (newest first) or price (ascending/descending).
   *
   * **Pagination:**
   * Use page number and items per page to navigate through large result sets. Response includes total count and total page count for navigation.
   *
   * @param connection
   * @param body Search criteria including optional filters for name query, category, seller, price range, stock availability, and pagination/sorting parameters.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query ecommerce_mall_products table with JOINs to ecommerce_mall_categories and ecommerce_mall_sellers for filter resolution.
   *
   * Apply soft-delete filter: only return products where deleted_at IS NULL.
   *
   * Filter logic:
   * - If nameQuery is provided: match against product name using ILIKE '%{name}%'
   * - If categoryId is provided: match against ecommerce_mall_category_id
   * - If sellerId is provided: match against ecommerce_mall_seller_id
   * - If minPrice is provided: match where base_price >= minPrice
   * - If maxPrice is provided: match where base_price <= maxPrice
   * - If inStock is true: match where product has at least one variant with quantity > 0
   * - If inStock is false: no additional filter (show all)
   *
   * Sorting:
   * - sortBy 'newest' (default): ORDER BY created_at DESC
   * - sortBy 'price_asc': ORDER BY base_price ASC
   * - sortBy 'price_desc': ORDER BY base_price DESC
   *
   * Return paginated results with total count. Include related category name and seller shop name in response if available.
   *
   * Authorization: Verify authenticated user has admin or super_admin role.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IEcommerceMallProduct.IRequest,
  ): Promise<IPageIEcommerceMallProduct.ISummary> {
    try {
      return await patchEcommerceMallAdminAdminProducts({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves complete details of any product on the platform.
   *
   * This endpoint allows administrators to view all product information including the owning seller, assigned category, product images with display order, and all product variants with their SKU codes, prices, and stock quantities.
   *
   * **Seller Information**: Returns the seller's ID and email for identification purposes.
   *
   * **Category Information**: Returns the category's ID and name where the product is listed.
   *
   * **Product Images**: Returns all images ordered by display_order (ascending), with the first image being the main thumbnail.
   *
   * **Product Variants**: Returns all active variants with their SKU codes, optional price overrides, current quantities, and option key-value pairs.
   *
   * This endpoint is restricted to authenticated administrators only.
   *
   * @param connection
   * @param productId UUID identifier of the product to retrieve.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query the ecommerce_mall_products table by id (UUID). Join with ecommerce_mall_sellers table to retrieve seller information (id, email). Join with ecommerce_mall_categories table to retrieve category information (id, name). Join with ecommerce_mall_product_images table to retrieve all images ordered by display_order. Join with ecommerce_mall_product_variants table to retrieve all non-deleted variants with their option values from ecommerce_mall_product_variant_option_values table.
   *
   * If the product does not exist or is soft-deleted (deleted_at is not null), return a 404 error.
   *
   * Return the complete product record including all related data in a single response object.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":productId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallProduct> {
    try {
      return await getEcommerceMallAdminAdminProductsProductId({
        admin,
        productId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Deletes a product from the platform for policy violation.
   *
   * This endpoint allows administrators to permanently remove products that violate platform guidelines. The operation performs a soft delete by setting the deleted_at timestamp, which removes the product from search results and category listings while preserving order history.
   *
   * **Cascade Effects**: When a product is deleted, all associated variants are soft-deleted, their inventory records are removed, cart items referencing those variants are deleted, and wishlist entries are automatically cleaned up.
   *
   * **Preserved Data**: Product snapshots and order item references remain intact for dispute resolution and historical records.
   *
   * **Authorization**: Requires ADMIN or SUPER_ADMIN authentication.
   *
   * @param connection
   * @param productId Unique identifier of the product to delete.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query the ecommerce_mall_products table to locate the product by productId.
   *
   * Verify the product exists and is not already deleted (deleted_at must be null). If the product does not exist or is already deleted, return appropriate error response.
   *
   * Retrieve all product variants from ecommerce_mall_product_variants where ecommerce_mall_product_id matches.
   *
   * **Cascade Deletion Sequence**:
   * 1. Set deleted_at = NOW() on the product record (soft delete)
   * 2. For each variant:
   *    a. Delete all inventory_records where ecommerce_mall_product_variant_id matches variant.id
   *    b. Delete all cart_items where ecommerce_mall_product_variant_id matches variant.id
   *    c. Set deleted_at = NOW() on each variant record
   * 3. Delete all wishlist_items where ecommerce_mall_product_id matches productId
   * 4. Commit all changes in a single transaction
   *
   * Return the deleted product entity with all fields including the new deleted_at timestamp.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":productId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteEcommerceMallAdminAdminProductsProductId({
        admin,
        productId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
