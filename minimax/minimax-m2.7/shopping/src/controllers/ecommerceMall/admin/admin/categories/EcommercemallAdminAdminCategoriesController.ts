import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallCategory } from "../../../../../api/structures/IEcommerceMallCategory";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { deleteEcommerceMallAdminAdminCategoriesCategoryId } from "../../../../../providers/deleteEcommerceMallAdminAdminCategoriesCategoryId";
import { postEcommerceMallAdminAdminCategories } from "../../../../../providers/postEcommerceMallAdminAdminCategories";
import { putEcommerceMallAdminAdminCategoriesCategoryId } from "../../../../../providers/putEcommerceMallAdminAdminCategoriesCategoryId";

@Controller("/ecommerceMall/admin/admin/categories")
export class EcommercemallAdminAdminCategoriesController {
  /**
   * Create a new product category on the platform.
   *
   * This endpoint allows administrators to create top-level categories or subcategories with optional parent relationships. Only administrators with appropriate permissions can access this operation.
   *
   * When creating a top-level category, the parent_id field should be omitted or set to null. For subcategories, specify the parent category's ID in the parent_id field. The system enforces a maximum nesting depth of one level - subcategories cannot have their own subcategories.
   *
   * The category name must be unique across all categories at the same hierarchy level. If a name conflict occurs, the request will be rejected with an appropriate error message.
   *
   * Upon successful creation, the system records the creation timestamp and returns the complete category entity including the generated identifier.
   *
   * This operation is part of the administrator-only category management workflow alongside category editing and deletion operations.
   *
   * @param connection
   * @param body Category creation payload containing name, optional description, and optional parent category reference for subcategory creation
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Execute the following steps:
   *
   * 1. Validate admin authentication and authorization
   * 2. Validate request body fields:
   *    - name: required, non-empty string, max length 255 characters
   *    - description: optional string, max length 1000 characters
   *    - parent_id: optional UUID string, must reference existing active category if provided
   * 3. If parent_id is provided:
   *    - Verify parent category exists and is not deleted
   *    - Verify parent category has no parent_id set (cannot nest under subcategory)
   *    - Return error if nesting limit would be exceeded
   * 4. Validate name uniqueness:
   *    - If parent_id is null, check no active category with same name at root level
   *    - If parent_id is set, check no active category with same name under same parent
   * 5. Create category record with:
   *    - Generated UUID for id
   *    - parent_id from request or null
   *    - name from request
   *    - description from request or null
   *    - created_at: current timestamp
   *    - updated_at: current timestamp
   *    - deleted_at: null
   * 6. Return created category entity with all fields
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IEcommerceMallCategory.ICreate,
  ): Promise<IEcommerceMallCategory> {
    try {
      return await postEcommerceMallAdminAdminCategories({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing product category on the platform.
   *
   * This endpoint allows administrators to modify the properties of an existing category including its name, description, and parent category assignment. Only administrators have permission to access this endpoint.
   *
   * The category name must remain unique within the same parent scope. If changing the parent category, the system validates that the new parent is not a descendant of the category being updated to prevent circular references in the hierarchy. Categories can only have one level of nesting (subcategories cannot have children), so a subcategory cannot be reassigned to have a parent that is itself a subcategory.
   *
   * When a category is updated, its subcategories remain attached to it. The updated_at timestamp is automatically refreshed. Soft-deleted categories cannot be updated.
   *
   * This operation is part of the category management workflow where administrators maintain the platform's product taxonomy structure.
   *
   * @param connection
   * @param categoryId Unique identifier of the category to update
   * @param body Category update information including name, description, and parent reassignment
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Retrieve the category by categoryId from ecommerce_mall_categories table. Validate that the category exists and deleted_at is null. If category not found or soft-deleted, return 404 error.
   *
   * Validate the request body: name must not be empty if provided, must be unique within the same parent scope (check @@unique([parent_id, name]) constraint excluding current record). Description can be null or empty string to clear.
   *
   * If parentId is provided in request: Validate parent category exists and is not soft-deleted. Verify parent category is not a descendant of the current category (to prevent circular references). Verify parent is not a subcategory itself (enforce one-level nesting limit).
   *
   * Update the category record with provided fields (name, description, parent_id, updated_at). Use database transaction to ensure atomicity.
   *
   * Return the updated category with all related data (subcategories count, product count if available).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":categoryId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("categoryId")
    categoryId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceMallCategory.IUpdate,
  ): Promise<IEcommerceMallCategory> {
    try {
      return await putEcommerceMallAdminAdminCategoriesCategoryId({
        admin,
        categoryId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently removes a category from the platform.
   *
   * This endpoint is exclusively accessible to administrators and super administrators. When a category is deleted, the system performs a soft delete by setting the deleted_at timestamp, which hides the category from customer-facing listings while preserving the data for audit purposes.
   *
   * Cascade Behavior: Subcategories assigned to the deleted category are also removed via database cascade. Products that were assigned to the deleted category become uncategorized, meaning their ecommerce_mall_category_id reference is set to null. These uncategorized products remain visible in search results but no longer appear under any category in category browsing views.
   *
   * The category name must be unique within the same parent scope as defined in the database constraint @@unique([parent_id, name]). Deleting a top-level category does not affect other top-level categories with the same name.
   *
   * Administrators should ensure no active operations depend on the category before deletion. This operation cannot be undone through the API; data recovery would require database administrator intervention.
   *
   * Related Operations: Use GET /categories to browse available categories before deletion. Use POST /admin/categories to create replacement categories after deletion.
   *
   * @param connection
   * @param categoryId Unique identifier of the category to delete
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification 1. Validate that the authenticated actor has admin or superAdmin role. Return 403 Forbidden if unauthorized.
   *
   * 2. Verify the category exists and is not already deleted (deleted_at IS NULL). Return 404 Not Found if category does not exist or is already deleted.
   *
   * 3. Within a database transaction:
   *    a. Find all subcategories of the target category (parent_id = categoryId)
   *    b. Set products.ecommerce_mall_category_id to NULL for all products in the target category and its subcategories
   *    c. Set subcategories.deleted_at to current timestamp (cascade soft delete)
   *    d. Set the target category.deleted_at to current timestamp (soft delete)
   *    e. Commit transaction
   *
   * 4. Return 204 No Content on successful deletion.
   *
   * Edge Cases:
   * - If the category has products, proceed with uncategorizing products (no error)
   * - If the category has subcategories, they are cascade deleted automatically by database constraint
   * - Concurrent deletion attempts should be handled gracefully (idempotent - return 204 if already deleted)
   * - Invalid UUID format should return 400 Bad Request
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":categoryId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("categoryId")
    categoryId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteEcommerceMallAdminAdminCategoriesCategoryId({
        admin,
        categoryId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
