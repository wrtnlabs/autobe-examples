  /**
   * Rejects a pending seller registration application.
   *
   * Rejects a seller registration that is currently in pending approval status. The rejecting administrator must provide a mandatory reason explaining why the application was denied. Once rejected, the seller can view the rejection reason and may submit a new registration request at a later time.
   *
   * **Authorization**: Requires administrator privileges.
   *
   * **Status Transitions**: Only sellers with 'pending' approval_status can be rejected. Sellers with 'approved' or already 'rejected' status cannot be rejected again through this endpoint.
   *
   * **Error Handling**: Returns 404 if seller not found, 400 if seller is not in pending status, and 403 if the administrator does not have permission to reject sellers.
   *
   * @param connection
   * @param sellerId Unique identifier of the seller to reject (UUID format).
   * @param body Rejection details containing the mandatory reason for rejecting the seller registration application.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification Reject a seller registration application by
     *   updating the seller record.
   *
   * 1. Validate the sellerId parameter is a valid UUID format.
   *
   * 2. Look up the seller by sellerId in ecommerce_mall_sellers table.
   *
   * 3. Verify the seller exists and is not soft-deleted (deleted_at IS NULL).
   *
   * 4. Verify the seller's approval_status is 'pending'. Return 400 error if status is not 'pending'.
   *
   * 5. Update the seller record:
   *    - Set approval_status to 'rejected'
   *    - Set rejection_reason to the reason provided in request body
   *    - Set rejected_at to current timestamp
   *
   * 6. Create a corresponding record in ecommerce_mall_seller_approvals table to track the review history:
   *    - Link to the seller via ecommerce_mall_seller_id
   *    - Set reviewed_by_admin_id to the current administrator
   *    - Set status to 'rejected'
   *    - Set rejection_reason to the provided reason
   *
   * 7. Return the updated seller record including email, approval_status, rejection_reason, and rejected_at.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
