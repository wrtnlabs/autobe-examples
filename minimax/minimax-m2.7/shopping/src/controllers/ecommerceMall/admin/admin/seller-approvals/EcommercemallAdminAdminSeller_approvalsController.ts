import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallSellerApproval } from "../../../../../api/structures/IEcommerceMallSellerApproval";
import { IPageIEcommerceMallSellerApproval } from "../../../../../api/structures/IPageIEcommerceMallSellerApproval";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getEcommerceMallAdminAdminSellerApprovalsApprovalId } from "../../../../../providers/getEcommerceMallAdminAdminSellerApprovalsApprovalId";
import { patchEcommerceMallAdminAdminSellerApprovals } from "../../../../../providers/patchEcommerceMallAdminAdminSellerApprovals";
import { postEcommerceMallAdminAdminSellerApprovalsApprovalIdApprove } from "../../../../../providers/postEcommerceMallAdminAdminSellerApprovalsApprovalIdApprove";
import { postEcommerceMallAdminAdminSellerApprovalsApprovalIdReject } from "../../../../../providers/postEcommerceMallAdminAdminSellerApprovalsApprovalIdReject";

@Controller("/ecommerceMall/admin/admin/seller-approvals")
export class EcommercemallAdminAdminSeller_approvalsController {
  /**
   * Retrieve a filtered and paginated list of seller approval requests for administrative review.
   *
   * This operation allows administrators to browse all seller registration applications with filtering capabilities by approval status. Each record includes the seller's email address and the current approval status. Pending applications are shown for review, while approved/rejected applications provide audit history.
   *
   * Supports filtering by status (pending, approved, rejected) and pagination with configurable page sizes. Results are ordered by creation date (newest first) for efficient review workflows.
   *
   * @param connection
   * @param body Search criteria and pagination parameters including optional status filter
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query ecommerce_mall_seller_approvals table with pagination and filtering.
   *
   * Apply search filters:
   * - Filter by status if provided (pending, approved, rejected)
   * - Default to showing all statuses unless filtered
   *
   * Join with ecommerce_mall_sellers table to include seller email address (seller.email).
   *
   * Order results by created_at descending (newest first).
   *
   * Return cursor-based pagination with configurable page sizes (default 20, max 100).
   *
   * Include seller email and approval status in each summary record.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IEcommerceMallSellerApproval.IRequest,
  ): Promise<IPageIEcommerceMallSellerApproval.ISummary> {
    try {
      return await patchEcommerceMallAdminAdminSellerApprovals({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve details of a specific seller approval request by its unique identifier.
   *
   * This endpoint allows administrators to view the complete details of a seller registration approval, including the seller's registration information, the current approval status, the reviewing administrator (if any), and the rejection reason if the request was rejected.
   *
   * The response includes all relevant information about the approval workflow, enabling administrators to review individual approval records during their oversight activities. Related seller and administrator information is included to provide full context.
   *
   * @param connection
   * @param approvalId Unique identifier of the seller approval record (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query the ecommerce_mall_seller_approvals table using the provided approvalId as the primary key. Return the complete approval record including the associated seller details and the reviewing administrator information if the request has been reviewed. Handle cases where reviewed_by_admin_id is null (pending status). Return 404 if no approval record exists with the given ID.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":approvalId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("approvalId")
    approvalId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallSellerApproval> {
    try {
      return await getEcommerceMallAdminAdminSellerApprovalsApprovalId({
        admin,
        approvalId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Approve a pending seller registration request.
   *
   * This endpoint allows administrators to approve seller registration applications that are in pending status. When approved, the seller's account status changes from pending to approved, enabling them to create products, manage inventory, and process orders on the platform.
   *
   * The approving administrator's ID is recorded in the approval record for audit purposes. Only pending approval requests can be approved; already approved or rejected requests return an error.
   *
   * Administrators cannot approve their own seller account. This operation only applies to pending approval requests from the ecommerce_mall_seller_approvals table.
   *
   * @param connection
   * @param approvalId Unique identifier of the seller approval request to approve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification 1. Validate approvalId exists in ecommerce_mall_seller_approvals table
   * 2. Verify the approval record has status = 'pending' (return error if already approved/rejected/cancelled)
   * 3. Retrieve the associated seller from ecommerce_mall_sellers via ecommerce_mall_seller_id
   * 4. Verify the approving admin is not the owner of the seller account being approved (self-approval prevention)
   * 5. Verify the seller is not already approved (concurrent modification check)
   * 6. Begin transaction:
   *    a. Update ecommerce_mall_seller_approvals: set status = 'approved', reviewed_by_admin_id = current admin ID, updated_at = now()
   *    b. Update ecommerce_mall_sellers: set approval_status = 'approved', rejection_reason = null, rejected_at = null, updated_at = now()
   * 7. Commit transaction
   * 8. Return the updated approval record with seller information
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post(":approvalId/approve")
  public async approve(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("approvalId")
    approvalId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallSellerApproval> {
    try {
      return await postEcommerceMallAdminAdminSellerApprovalsApprovalIdApprove({
        admin,
        approvalId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Reject a pending seller registration application.
   *
   * This endpoint allows administrators to reject a seller application that is awaiting approval. When rejected, the seller receives the rejection reason and may submit a new registration request at a later time.
   *
   * The rejection updates the seller approval record with status 'rejected' and stores the administrator-provided rejection reason. The corresponding seller account's approval_status is also updated.
   *
   * Only pending seller approvals can be rejected.
   *
   * @param connection
   * @param approvalId Unique identifier of the seller approval record to reject
   * @param body Rejection reason provided by the administrator (required, 1-1000 characters)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Handle seller approval rejection workflow.
   *
   * 1. Validate the approvalId is a valid UUID format
   * 2. Query ecommerce_mall_seller_approvals table to find the approval record by ID
   * 3. Verify the approval exists and has status 'pending' - return 404 if not found or 409 if not pending
   * 4. Verify the current user is an authenticated administrator (from session/JWT)
   * 5. Validate rejectionReason is present in request body and between 1-1000 characters
   * 6. Update seller_approval record: set status='rejected', rejection_reason=requestBody.rejectionReason, reviewed_by_admin_id=currentAdmin.id, updated_at=current_timestamp
   * 7. Update ecommerce_mall_sellers: set approval_status='rejected', rejection_reason=requestBody.rejectionReason, rejected_at=current_timestamp
   * 8. Return the updated seller_approval record with seller details
   *
   * Error handling:
   * - 400: Invalid approvalId format or rejection reason validation failure
   * - 401: Unauthorized - not authenticated
   * - 403: Forbidden - not an administrator
   * - 404: Seller approval not found
   * - 409: Approval is not in pending status (already processed)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post(":approvalId/reject")
  public async reject(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("approvalId")
    approvalId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceMallSellerApproval.IReject,
  ): Promise<IEcommerceMallSellerApproval> {
    try {
      return await postEcommerceMallAdminAdminSellerApprovalsApprovalIdReject({
        admin,
        approvalId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
