import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallAdminDashboardMetric } from "../../../../../../api/structures/IEcommerceMallAdminDashboardMetric";
import { AdminAuth } from "../../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../../decorators/payload/AdminPayload";
import { getEcommerceMallAdminAdminDashboardMetrics } from "../../../../../../providers/getEcommerceMallAdminAdminDashboardMetrics";

@Controller("/ecommerceMall/admin/admin/dashboard/metrics")
export class EcommercemallAdminAdminDashboardMetricsController {
  /**
   * Retrieve comprehensive platform-wide metrics and statistics for super administrator dashboard overview.
   *
   * This endpoint provides aggregated statistics across the entire ecommerce platform, enabling super administrators to monitor platform health, user activity, and pending administrative workloads at a glance.
   *
   * The response includes total counts for major entities (customers, sellers, products, orders), breakdown of order statuses, pending approval counts for sellers and admin requests, and recent activity indicators. These metrics support data-driven governance decisions and help super administrators identify areas requiring attention.
   *
   * Security: Only super administrators can access this endpoint. Regular administrators do not have platform-wide oversight capabilities per administrative boundaries defined in section 38. Authentication via super_admin session token is required.
   *
   * Related Operations:
   * - GET /admin/sellers/pending - View pending seller approval requests
   * - GET /admin/customers - List customer accounts
   * - GET /admin/orders - View all orders
   * - GET /admin/products - View all products
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query the following database tables and aggregate statistics:
   *
   * 1. Customer Metrics:
   *    - Count all active customers from ecommerce_mall_customers where deleted_at IS NULL
   *    - Count customers registered in the last 30 days
   *
   * 2. Seller Metrics:
   *    - Count all sellers from ecommerce_mall_sellers
   *    - Breakdown by approval_status: pending, approved, rejected
   *    - Count sellers with deleted_at NOT NULL (suspended/banned)
   *
   * 3. Product Metrics:
   *    - Count all products from ecommerce_mall_products where deleted_at IS NULL
   *    - Count products created in the last 30 days
   *
   * 4. Order Metrics:
   *    - Count all orders from ecommerce_mall_orders where deleted_at IS NULL
   *    - Breakdown by status: paid, shipped, delivered, cancelled, refunded, partially_completed
   *    - Calculate total GMV (sum of total_amount) for completed orders (delivered status)
   *    - Count orders created in the last 30 days
   *
   * 5. Pending Request Metrics:
   *    - Count pending seller approvals from ecommerce_mall_seller_approvals where status = 'pending'
   *    - Count pending admin requests from ecommerce_mall_admin_requests where status = 'pending'
   *
   * 6. Dispute Metrics:
   *    - Count pending cancellation requests from ecommerce_mall_cancellation_requests where status = 'pending'
   *    - Count pending refund requests from ecommerce_mall_refund_requests where status = 'pending'
   *
   * Return all counts as integer values. Calculate percentages where appropriate (e.g., approval rate). Sort by relevance for dashboard display.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @AdminAuth()
    admin: AdminPayload,
  ): Promise<IEcommerceMallAdminDashboardMetric> {
    try {
      return await getEcommerceMallAdminAdminDashboardMetrics({
        admin,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
