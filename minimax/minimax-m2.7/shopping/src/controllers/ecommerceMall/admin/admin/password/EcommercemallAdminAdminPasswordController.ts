import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallAdmin } from "../../../../../api/structures/IEcommerceMallAdmin";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { putEcommerceMallAdminAdminPassword } from "../../../../../providers/putEcommerceMallAdminAdminPassword";

@Controller("/ecommerceMall/admin/admin/password")
export class EcommercemallAdminAdminPasswordController {
  /**
   * Allows authenticated administrators to change their account password.
   *
   * Administrators must provide their current password for verification before setting a new password. The new password must meet the platform's security requirements. Upon successful password change, the administrator remains logged in with the updated credentials.
   *
   * **Request Validation**
   *
   * The current password must match the stored password hash exactly. If verification fails, the request is rejected with an authentication error. The new password is validated against platform security requirements before acceptance.
   *
   * **Response**
   *
   * On success, returns a confirmation message indicating the password was updated. No additional authentication is required after the change.
   *
   * @param connection
   * @param body Contains the current password for verification and the new password to set.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification Validate the current password against the stored
     *   password_hash in ecommerce_mall_admins table for the authenticated
     *   admin.
   *
   * If current password verification fails, return 401 Unauthorized with message indicating incorrect current password.
   *
   * Validate the newPassword against platform security requirements (minimum length, complexity rules).
   *
   * Hash the newPassword using bcrypt and update the password_hash field in ecommerce_mall_admins table.
   *
   * Update the updated_at timestamp on successful password change.
   *
   * Return 200 OK with success confirmation on successful update.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IEcommerceMallAdmin.IPasswordUpdate,
  ): Promise<IEcommerceMallAdmin.IPasswordChangeSuccess> {
    try {
      return await putEcommerceMallAdminAdminPassword({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
