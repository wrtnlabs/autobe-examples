import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallAdmin } from "../../../../../api/structures/IEcommerceMallAdmin";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { putEcommerceMallAdminAdminProfile } from "../../../../../providers/putEcommerceMallAdminAdminProfile";

@Controller("/ecommerceMall/admin/admin/profile")
export class EcommercemallAdminAdminProfileController {
  /**
   * Update the authenticated administrator's own profile information.
   *
   * This endpoint allows administrators to modify their display name that appears throughout the admin dashboard, audit logs, and administrative records. The email address used for authentication cannot be changed via this endpoint.
   *
   * Authentication is required. Only the currently authenticated administrator can update their own profile. The system validates the input and returns the updated profile data upon successful modification.
   *
   * For password changes, use the dedicated password change endpoint instead.
   *
   * @param connection
   * @param body The profile update data containing the new display name.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Implement the admin profile update operation with the following steps:
   *
   * 1. Authentication: Verify the request includes valid admin session JWT token. Extract admin ID from authenticated session.
   *
   * 2. Input Validation:
   *    - Validate name field: required, max 100 characters, cannot be empty or whitespace only
   *    - Reject any attempt to modify email or system-managed fields
   *
   * 3. Database Update:
   *    - Query ecommerce_mall_admins table by admin ID from session
   *    - Verify admin account exists and is not soft-deleted (deleted_at is null)
   *    - Update only the name field
   *    - Set updated_at timestamp to current time
   *
   * 4. Error Handling:
   *    - If admin not found or deleted: return 404 error
   *    - If validation fails: return 400 with specific field errors
   *    - If database error: return 500 with generic error message
   *
   * 5. Response:
   *    - Return full updated admin profile including id, email, name, created_at, updated_at
   *    - Exclude password_hash from response
   *    - HTTP 200 with updated profile object
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IEcommerceMallAdmin.IUpdate,
  ): Promise<IEcommerceMallAdmin> {
    try {
      return await putEcommerceMallAdminAdminProfile({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
