import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallOrder } from "../../../../../../api/structures/IEcommerceMallOrder";
import { AdminAuth } from "../../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../../decorators/payload/AdminPayload";
import { postEcommerceMallAdminAdminOrdersOrderIdForceRefund } from "../../../../../../providers/postEcommerceMallAdminAdminOrdersOrderIdForceRefund";

@Controller("/ecommerceMall/admin/admin/orders/:orderId/force-refund")
export class EcommercemallAdminAdminOrdersForce_refundController {
  /**
   * Force refund all items in an entire order.
   *
   * This endpoint allows super administrators to process refunds for all items in a specific order, restoring inventory quantities for each product variant. The operation is immediate and does not require seller approval.
   *
   * **Authorization**: Only super administrators can access this endpoint.
   *
   * **Business Logic**:
   * - All order items with status 'paid', 'shipped', or 'delivered' are eligible for force refund
   * - Each eligible item's status is updated to 'refunded'
   * - Inventory is restored for each product variant via inventory records with reason 'refund'
   * - Order status is updated based on remaining items
   *
   * **Error Handling**:
   * - Returns 404 if order is not found
   * - Returns 400 if all items are already cancelled or refunded
   * - Returns 403 if caller is not a super administrator
   *
   * @param connection
   * @param orderId Unique identifier of the order to force-refund. Must be a valid UUID.
   * @param body Optional reason for the force refund. If not provided, a default reason will be used for audit records.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification 1. Extract orderId from path parameter (UUID
     *   format) 2. Validate caller has super administrator privileges 3.
     *   Retrieve the order from ecommerce_mall_orders table by orderId 4. If
     *   order not found, return 404 error 5. Retrieve all order items from
     *   ecommerce_mall_order_items table where ecommerce_mall_order_id matches
     *   6. Filter items eligible for refund: status IN ('paid', 'shipped',
     *   'delivered') 7. If no items eligible for refund, return 400 error with
     *   message indicating no items can be refunded 8. Begin database
     *   transaction: a. For each eligible order item: - Update status to
     *   'refunded' in ecommerce_mall_order_items - Create inventory record in
     *   ecommerce_mall_inventory_records with: - quantity_change =
     *   order_item.quantity (positive to restore stock) - reason = 'refund' -
     *   ecommerce_mall_product_variant_id from order item b. Update order
     *   status in ecommerce_mall_orders: - If all items now refunded -> status
     *   = 'refunded' - Else -> status = 'partially_completed' 9. Commit
     *   transaction 10. Return the updated order with all order items
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async forceRefund(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceMallOrder.IForceRefund,
  ): Promise<IEcommerceMallOrder> {
    try {
      return await postEcommerceMallAdminAdminOrdersOrderIdForceRefund({
        admin,
        orderId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
