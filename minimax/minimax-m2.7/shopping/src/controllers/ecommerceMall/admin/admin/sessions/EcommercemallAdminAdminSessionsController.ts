import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallAdminSession } from "../../../../../api/structures/IEcommerceMallAdminSession";
import { IPageIEcommerceMallAdminSession } from "../../../../../api/structures/IPageIEcommerceMallAdminSession";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getEcommerceMallAdminAdminSessionsSessionId } from "../../../../../providers/getEcommerceMallAdminAdminSessionsSessionId";
import { patchEcommerceMallAdminAdminSessions } from "../../../../../providers/patchEcommerceMallAdminAdminSessions";

@Controller("/ecommerceMall/admin/admin/sessions")
export class EcommercemallAdminAdminSessionsController {
  /**
   * Retrieve a filtered and paginated list of administrator sessions.
   *
   * This operation allows super administrators to view and search all admin sessions across the platform. Sessions can be filtered by administrator, expiration status, IP address, and creation date range.
   *
   * Supports cursor-based pagination with configurable page sizes and sorting options. Each session record includes the associated administrator name, session metadata (IP address, accessed URL), and timing information.
   *
   * This endpoint is restricted to super administrators only for security audit purposes.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering sessions
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query ecommerce_mall_admin_sessions table with pagination and filtering.
   *
   * Apply search filters:
   * - Filter by ecommerce_mall_admin_id if provided (sessions for specific admin)
   * - Filter by expiration status (expired vs active sessions)
   * - Filter by created_at date range if provided
   * - Filter by IP address pattern if provided
   *
   * Join with ecommerce_mall_admins table to include admin name in results.
   *
   * Return results sorted by created_at descending (newest first) by default.
   *
   * Implement cursor-based pagination for efficient traversal of large result sets.
   *
   * Security: Verify requesting user has super admin privileges before returning data.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IEcommerceMallAdminSession.IRequest,
  ): Promise<IPageIEcommerceMallAdminSession.ISummary> {
    try {
      return await patchEcommerceMallAdminAdminSessions({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific administrator session by its unique identifier.
   *
   * This operation returns the complete session details including the authenticated administrator reference, client connection information (IP address, current URL, HTTP referrer), and session timing (creation and expiration timestamps).
   *
   * The session must exist and not be expired. This endpoint is used for session auditing and monitoring by administrators. If the session has expired, the system returns a 404 error indicating the session is no longer valid. Session details are immutable and cannot be modified through this endpoint.
   *
   * @param connection
   * @param sessionId Unique identifier of the administrator session to retrieve (UUID format).
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query the ecommerce_mall_admin_sessions table using the sessionId as the primary key lookup. Return the session record with all fields: id, ecommerce_mall_admin_id, ip, href, referrer, created_at, and expired_at. Include the related admin entity for context if needed. Validate that the session exists before returning. If the session does not exist, return a 404 error with appropriate message. The session data is read-only and should never be modified through retrieval operations.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallAdminSession> {
    try {
      return await getEcommerceMallAdminAdminSessionsSessionId({
        admin,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
