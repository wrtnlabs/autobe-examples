import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallAdminSession } from "../../../../../api/structures/IEcommerceMallAdminSession";
import { IPageIEcommerceMallAdminSession } from "../../../../../api/structures/IPageIEcommerceMallAdminSession";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getEcommerceMallAdminAdminSessionsSessionId } from "../../../../../providers/getEcommerceMallAdminAdminSessionsSessionId";
import { patchEcommerceMallAdminAdminSessions } from "../../../../../providers/patchEcommerceMallAdminAdminSessions";

@Controller("/ecommerceMall/admin/admin/sessions")
export class EcommercemallAdminAdminSessionsController {
  /**
   * List and search admin sessions with filtering criteria.
   *
   * Retrieves a paginated list of administrator sessions for security auditing purposes. Only super administrators can access this endpoint. Sessions can be filtered by administrator, IP address, date range, and status (active or expired).
   *
   * **Filtering Options:**
   * Administrators can filter sessions by admin ID to view all sessions belonging to a specific administrator. IP address filtering allows identifying sessions from specific network locations. Date range filters enable auditing sessions within specific time periods.
   *
   * **Session Status:**
   * Active sessions have not yet reached their expiration time. Expired sessions have passed their expiration timestamp but remain in the database for audit purposes until cleaned up according to retention policies.
   *
   * **Security Context:**
   * Each session record captures the IP address, href (current page), and referrer from the time of session creation. This information is valuable for security investigations and access pattern analysis.
   *
   * @param connection
   * @param body Search criteria including administrator ID filter, IP address filter, date range filters for session creation time, and pagination parameters.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification Query ecommerce_mall_admin_sessions table with
     *   pagination and optional filtering.
   *
   * Implement cursor-based or offset pagination with configurable page size (default 20, max 100).
   *
   * **Filter Implementation:**
   * - Filter by ecommerce_mall_admin_id when provided to list sessions for a specific administrator
   * - Filter by ip address prefix or exact match when provided
   * - Filter by created_at range (from and/or to) when date range is specified
   * - Filter by expired_at comparison to determine active vs expired sessions:
   *   - If expired_at > NOW() then session is active
   *   - If expired_at <= NOW() then session is expired
   *
   * **Join:**
   * Join with ecommerce_mall_admins table to include admin email or name in results for identification purposes.
   *
   * **Sorting:**
   * Default sort by created_at descending (newest first). Allow sorting by created_at, expired_at if needed.
   *
   * **Response:**
   * Return paginated results with session details including admin identifier, IP address, access context (href, referrer), creation timestamp, and expiration timestamp.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IEcommerceMallAdminSession.IRequest,
  ): Promise<IPageIEcommerceMallAdminSession.ISummary> {
    try {
      return await patchEcommerceMallAdminAdminSessions({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves detailed information about a specific administrator session by its unique identifier.
   *
   * This endpoint allows super administrators to view session details including the associated administrator account, session token status, creation timestamp, and expiration information. Session details are useful for security auditing, access control reviews, and identifying active sessions across the platform.
   *
   * **Session Details**
   *
   * The response includes the complete session record with the authenticated administrator's basic information (id, email, role), session metadata including creation and expiration timestamps, and the session's current status indicating whether it is active, expired, or revoked.
   *
   * **Authorization**
   *
   * Only super administrators can access this endpoint. Regular administrators are restricted from viewing session information for security reasons. Requests from non-administrative accounts are rejected with a 403 Forbidden response.
   *
   * **Error Handling**
   *
   * If the session does not exist or has been deleted, the system returns a 404 Not Found response indicating the session identifier is invalid. If the requesting user lacks super administrator privileges, a 403 Forbidden response is returned.
   *
   * @param connection
   * @param sessionId Unique identifier of the administrator session to retrieve (UUID format).
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification Query the ecommerce_mall_admin_sessions table
     *   using the provided sessionId parameter. Join with ecommerce_mall_admins
     *   table to retrieve associated administrator details (id, email, role).
   *
   * Validate that the session record exists. If not found, return 404 with appropriate error message.
   *
   * Return the complete session record including: session identifier, administrator id and basic info, token fingerprint, creation timestamp, expiration timestamp, last activity timestamp, and session status (active/expired/revoked).
   *
   * No request body processing required for GET operation. Authentication via Bearer token required.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallAdminSession> {
    try {
      return await getEcommerceMallAdminAdminSessionsSessionId({
        admin,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
