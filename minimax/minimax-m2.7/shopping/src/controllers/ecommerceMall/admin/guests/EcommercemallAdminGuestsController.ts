import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallGuest } from "../../../../api/structures/IEcommerceMallGuest";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getEcommerceMallAdminGuestsGuestId } from "../../../../providers/getEcommerceMallAdminGuestsGuestId";
import { patchEcommerceMallAdminGuests } from "../../../../providers/patchEcommerceMallAdminGuests";

@Controller("/ecommerceMall/admin/guests")
export class EcommercemallAdminGuestsController {
  /**
   * Identifies or creates a guest visitor and updates their browsing context.
   *
   * This endpoint is called by the client to establish or resume a guest session. The client provides a device fingerprint to uniquely identify the visitor. If a guest with that fingerprint exists, their record is updated with the latest browsing context (IP address, user agent, current page). If no matching guest exists, a new guest record is created.
   *
   * **Identification**: Guests are identified by the device fingerprint provided in the request body, not by authentication tokens. The fingerprint should be generated client-side using available device information.
   *
   * **Session Tracking**: Each call updates the guest's last activity timestamp, allowing the system to track active browsing sessions and maintain continuity for anonymous visitors.
   *
   * **No Authentication Required**: This endpoint is publicly accessible and does not require any authentication headers.
   *
   * @param connection
   * @param body Identification and browsing context data. The fingerprint is required to identify the guest. Other fields update the guest's browsing context and are optional.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification Query the ecommerce_mall_guests table by
     *   fingerprint.
   *
   * If a guest record exists:
   * - Update ip_address with the provided value (if given)
   * - Update user_agent with the provided value (if given)
   * - Update last_active_at to the current timestamp
   * - Return the updated guest record
   *
   * If no guest record exists:
   * - Create a new guest record with the provided fingerprint
   * - Set ip_address, user_agent if provided
   * - Set created_at and updated_at to current timestamp
   * - Set last_active_at to current timestamp
   * - Return the newly created guest record
   *
   * Do NOT expose the deleted_at field in the response. If the existing guest has a non-null deleted_at, treat the record as non-existent and create a new one.
   *
   * Handle concurrent requests for the same fingerprint by using database-level constraints or optimistic locking.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async upsert(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IEcommerceMallGuest.IUpsert,
  ): Promise<IEcommerceMallGuest> {
    try {
      return await patchEcommerceMallAdminGuests({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves detailed information about a specific guest account by its unique identifier.
   *
   * This endpoint allows administrators to view guest account details including device information, last activity timestamp, and account creation date. Guest accounts are lightweight records that track unauthenticated visitors across sessions using device fingerprinting.
   *
   * **Retrieval Details**
   *
   * The operation returns the complete guest account record including the device fingerprint used for identification, IP address if available, user agent string, last activity timestamp, and account lifecycle timestamps (created_at, updated_at). Soft-deleted guests (those with deleted_at set) will return a 404 error as they are considered inactive.
   *
   * **Use Cases**
   *
   * This endpoint supports administrative functions such as customer support inquiries, fraud investigation, and platform analytics. It may be called when investigating suspicious activity traced to a specific device fingerprint or when correlating guest browsing behavior with authenticated user actions during the same session.
   *
   * **Error Handling**
   *
   * If the guest account does not exist or has been soft-deleted, the endpoint returns a 404 Not Found error. If the guestId format is invalid, a 400 Bad Request error is returned.
   *
   * @param connection
   * @param guestId Unique identifier of the guest account (UUID format).
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification Query the ecommerce_mall_guests table using the
     *   provided guestId as the primary key lookup.
   *
   * 1. Validate the guestId format - must be a valid UUID
   * 2. Query database: SELECT * FROM ecommerce_mall_guests WHERE id = :guestId AND deleted_at IS NULL
   * 3. If no record found, return 404 Not Found
   * 4. Return the guest record with all fields: id, fingerprint, ip_address, user_agent, last_active_at, created_at, updated_at
   *
   * Note: Do not expose the fingerprint field in the response as it may contain sensitive device identification data. Return only: id, ip_address, user_agent, last_active_at, created_at, updated_at.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":guestId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("guestId")
    guestId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallGuest> {
    try {
      return await getEcommerceMallAdminGuestsGuestId({
        admin,
        guestId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
