import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallAdmin } from "../../../../../api/structures/IEcommerceMallAdmin";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getEcommerceMallAdminAdminsMe } from "../../../../../providers/getEcommerceMallAdminAdminsMe";
import { patchEcommerceMallAdminAdminsMe } from "../../../../../providers/patchEcommerceMallAdminAdminsMe";

@Controller("/ecommerceMall/admin/admins/me")
export class EcommercemallAdminAdminsMeController {
  /**
   * Retrieves the profile of the currently authenticated administrator.
   *
   * This endpoint returns the administrator's account information including their unique identifier, email address, display name, and timestamps. The response excludes sensitive data such as the password hash for security purposes.
   *
   * **Authentication**: Requires a valid administrator JWT token in the Authorization header.
   *
   * **Response Contents**: Returns the admin's id, email, name, created_at, updated_at, and deleted_at (if soft-deleted). The password_hash field is never included in the response.
   *
   * **Error Handling**: If the session is invalid or expired, returns a 401 Unauthorized error. If the admin account has been soft-deleted, returns the profile with deleted_at timestamp set.
   *
   * @param connection
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification Query the ecommerce_mall_admins table using the
     *   authenticated admin's ID extracted from the JWT token in the
     *   Authorization header. Retrieve fields: id, email, name, created_at,
     *   updated_at, deleted_at. The password_hash field must NEVER be selected
     *   or returned. If the admin record is not found, return 401 Unauthorized.
     *   If the admin's session is invalid or expired, return 401 Unauthorized
     *   with appropriate message.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @AdminAuth()
    admin: AdminPayload,
  ): Promise<IEcommerceMallAdmin> {
    try {
      return await getEcommerceMallAdminAdminsMe({
        admin,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update the authenticated administrator's own profile information.
   *
   * This endpoint allows administrators to modify their display name shown throughout the admin dashboard and audit logs.
   *
   * **Authentication**: Requires valid admin session token. Only the authenticated admin can update their own profile.
   *
   * **Editable Fields**: The `name` field (display name) can be updated. Email address cannot be changed through this endpoint as it serves as the unique account identifier.
   *
   * **Validation**: The name field is required and must not be empty. If the update fails due to validation errors or system issues, appropriate error responses are returned.
   *
   * **Snapshot Behavior**: Profile updates do not create snapshots as admin profiles are not snapshot-eligible data types.
   *
   * **Related Operations**: Password changes are handled through a separate authentication endpoint.
   *
   * @param connection
   * @param body Update payload containing the new display name for the administrator.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification 1. Extract authenticated admin ID from session
     *   token. 2. Validate the request body contains at least one updatable
     *   field. 3. Validate the 'name' field is not empty if provided. 4. Update
     *   the admin record in ecommerce_mall_admins table. 5. Update the
     *   'updated_at' timestamp automatically. 6. Return the updated admin
     *   object without sensitive fields (exclude password_hash). 7. Handle
     *   validation errors with appropriate error responses. 8. Handle database
     *   errors with generic error message to prevent information leakage.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IEcommerceMallAdmin.IUpdate,
  ): Promise<IEcommerceMallAdmin> {
    try {
      return await patchEcommerceMallAdminAdminsMe({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
