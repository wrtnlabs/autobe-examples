import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallAdmin } from "../../../../api/structures/IEcommerceMallAdmin";
import { IPageIEcommerceMallAdmin } from "../../../../api/structures/IPageIEcommerceMallAdmin";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { patchEcommerceMallAdminAdmins } from "../../../../providers/patchEcommerceMallAdminAdmins";

@Controller("/ecommerceMall/admin/admins")
export class EcommercemallAdminAdminsController {
  /**
   * Retrieve a filtered and paginated list of administrator accounts on the platform.
   *
   * This operation provides administrative oversight capabilities for viewing all administrator accounts. It supports filtering by email address pattern matching, display name search, and account status (active or soft-deleted). The response is paginated to handle large numbers of administrators efficiently.
   *
   * Security considerations: Only super administrators or other authorized administrators can access this endpoint. The response excludes sensitive information such as password hashes. Soft-deleted administrators are included when status filter includes deleted accounts.
   *
   * The underlying ecommerce_mall_admins table stores administrator credentials with email/password authentication for elevated platform management privileges. This operation is part of the administrator management system alongside admin request review, promotion, and demotion operations.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for admin list
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query ecommerce_mall_admins table with cursor-based pagination and filtering.
   *
   * Apply search filters:
   * - email: partial match filter using ILIKE pattern
   * - name: partial match filter using ILIKE pattern
   * - status: filter by 'active' (deleted_at IS NULL) or 'deleted' (deleted_at IS NOT NULL), defaults to 'active'
   *
   * Join with ecommerce_mall_super_admin_audit_logs for created_at tracking if needed.
   *
   * Return results ordered by created_at DESC for consistent pagination.
   *
   * Exclude password_hash field from all results for security.
   *
   * Support pagination with cursor-based navigation using page and limit parameters.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IEcommerceMallAdmin.IRequest,
  ): Promise<IPageIEcommerceMallAdmin.ISummary> {
    try {
      return await patchEcommerceMallAdminAdmins({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
