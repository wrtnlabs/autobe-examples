  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IEcommerceMallSellerApproval.ICreate,
  ): Promise<IEcommerceMallSellerApproval> {
    try {
      return await postEcommerceMallAdminSellerApprovals({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

