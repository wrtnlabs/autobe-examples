import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallOrder } from "../../../../api/structures/IEcommerceMallOrder";
import { IPageIEcommerceMallOrder } from "../../../../api/structures/IPageIEcommerceMallOrder";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getEcommerceMallAdminOrdersOrderId } from "../../../../providers/getEcommerceMallAdminOrdersOrderId";
import { patchEcommerceMallAdminOrders } from "../../../../providers/patchEcommerceMallAdminOrders";

@Controller("/ecommerceMall/admin/orders")
export class EcommercemallAdminOrdersController {
  /**
   * Retrieve a filtered and paginated list of all orders on the platform.
   *
   * This operation provides administrators with full oversight of customer orders. Administrators can search and filter orders across the entire platform using various criteria including order number search, status filtering, and date range queries.
   *
   * The response includes comprehensive order summaries containing order number, customer reference, total amount, status, and creation timestamp. Unlike customer-facing order history, this admin operation provides access to all orders regardless of which customer placed them.
   *
   * Supports pagination with configurable page sizes and sorting options with newest orders appearing first by default. Administrators can also filter by specific customer to narrow results when investigating particular accounts.
   *
   * @param connection
   * @param body Search criteria including order number filter, status filter, date range, optional customer filter, and pagination parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query ecommerce_mall_orders table filtering by customer_id from authenticated session context.
   *
   * Apply search filters:
   * - order_number: partial string match for order number search
   * - status: exact match or array of statuses (paid, shipped, delivered, cancelled, refunded, partially_completed)
   * - created_at_from and created_at_to: date range filters
   *
   * Sort results by created_at descending (newest first) as default sort order.
   *
   * Return paginated results using cursor-based pagination with configurable limit (default 20, max 100).
   *
   * Include only non-deleted orders (deleted_at IS NULL).
   *
   * Join with ecommerce_mall_shipping_addresses if address information is needed in response.
   *
   * Calculate derived fields: item_count from order_items table for summary display.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IEcommerceMallOrder.IRequest,
  ): Promise<IPageIEcommerceMallOrder.ISummary> {
    try {
      return await patchEcommerceMallAdminOrders({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific order including all order items, shipping address, and shipment tracking details.
   *
   * This endpoint allows customers to view the complete details of their own orders, including the products purchased (via product snapshots), seller information (via seller profile snapshots), shipping address used, and any shipment tracking information. The order items preserve the exact product and pricing information as they appeared at the time of purchase for dispute resolution.
   *
   * Customers can only retrieve orders that belong to their own account. Administrators have elevated access to view any order on the platform for support and oversight purposes.
   *
   * The response includes the order's computed status based on item statuses, individual item statuses (paid, shipped, delivered, cancelled, refunded), and shipment tracking information when items have been shipped.
   *
   * @param connection
   * @param orderId Unique identifier of the order to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Retrieve order by id from ecommerce_mall_orders table.
   *
   * Validate that the authenticated user (customer or admin) has permission to view this order:
   * - If user is a customer: verify ecommerce_mall_customer_id matches the authenticated customer's id
   * - If user is an admin: allow access to any order
   * - Otherwise, return 403 Forbidden
   *
   * Join and include in response:
   * - Order items from ecommerce_mall_order_items (quantity, unit_price, status)
   * - Product snapshots from ecommerce_mall_product_snapshots (name, description, base_price)
   * - Seller profile snapshots from ecommerce_mall_seller_profile_snapshots (shop_name, logo_url)
   * - Shipping address from ecommerce_mall_shipping_addresses
   * - Shipments from ecommerce_mall_shipments (carrier, tracking_number)
   *
   * Compute order status based on item statuses:
   * - All items 'paid' → status 'paid'
   * - Any item 'shipped' with no items 'delivered' → status 'shipped'
   * - All items 'delivered' → status 'delivered'
   * - All items 'cancelled' → status 'cancelled'
   * - All items 'refunded' → status 'refunded'
   * - Mixed states → status 'partially_completed'
   *
   * Return 404 if order not found or soft-deleted (deleted_at is not null).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":orderId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallOrder.IInvert> {
    try {
      return await getEcommerceMallAdminOrdersOrderId({
        admin,
        orderId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
