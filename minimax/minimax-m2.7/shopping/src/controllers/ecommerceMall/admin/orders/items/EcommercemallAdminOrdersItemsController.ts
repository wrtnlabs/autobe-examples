import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallOrderItem } from "../../../../../api/structures/IEcommerceMallOrderItem";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { putEcommerceMallAdminOrdersOrderIdItemsItemId } from "../../../../../providers/putEcommerceMallAdminOrdersOrderIdItemsItemId";

@Controller("/ecommerceMall/admin/orders/:orderId/items/:itemId")
export class EcommercemallAdminOrdersItemsController {
  /**
   * Update the status of an individual order item within an existing order.
   *
   * This endpoint allows administrators to modify order item status according to authorized admin actions. The system preserves the original product and seller information via frozen snapshots (product_snapshot_id, seller_profile_snapshot_id) that cannot be modified.
   *
   * **Admin Force Actions:**
   * - Force-cancel: Immediately cancel an order item, process refund, and restore stock quantity
   * - Force-refund: Process refund for a delivered item and restore stock quantity
   *
   * **Status Transition Rules:**
   * - paid → shipped (via shipment creation by seller)
   * - paid → cancelled (via cancellation request approved by seller OR force-cancelled by admin)
   * - shipped → delivered (via delivery confirmation by customer)
   * - delivered → refunded (via refund request approved by seller OR force-refunded by admin)
   * - cancelled/refunded are terminal states
   *
   * **Data Constraints:**
   * - unit_price: Frozen at purchase time, cannot be modified
   * - quantity: Fixed at purchase time, cannot be modified
   * - Product/seller snapshots: Immutable historical records, cannot be modified
   *
   * **Related Operations:**
   * - GET /orders/{orderId}/items/{itemId} - Retrieve single order item
   * - POST /orders/{orderId}/shipments - Create shipment (changes status to shipped)
   * - POST /orders/{orderId}/items/{itemId}/cancellation - Cancellation request
   * - POST /orders/{orderId}/items/{itemId}/refund - Refund request
   *
   * @param connection
   * @param orderId Unique identifier of the parent order (UUID format)
   * @param itemId Unique identifier of the order item to update (UUID format)
   * @param body Status update for the order item (e.g., force-cancelled, force-refunded)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification 1. Validate the order exists and is not soft-deleted (deleted_at is null)
   * 2. Validate the order item exists and belongs to the specified order
   * 3. Verify the requester has permission to update the item (customer owns order, seller owns product, or admin)
   * 4. Validate the update fields according to business rules:
   *    - Status transitions must be valid (e.g., cannot change shipped item quantity)
   *    - Quantity must be positive integer if provided
   *    - Unit price changes may require special authorization
   * 5. Apply updates to the order item record
   * 6. Update the parent order's updated_at timestamp
   * 7. Recalculate order totals if quantity or price changes affect subtotal
   * 8. Return the updated order item with all related data
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedParam("itemId")
    itemId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceMallOrderItem.IUpdate,
  ): Promise<IEcommerceMallOrderItem> {
    try {
      return await putEcommerceMallAdminOrdersOrderIdItemsItemId({
        admin,
        orderId,
        itemId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
