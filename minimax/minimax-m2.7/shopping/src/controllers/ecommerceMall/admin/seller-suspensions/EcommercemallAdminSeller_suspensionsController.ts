import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallSellerSuspension } from "../../../../api/structures/IEcommerceMallSellerSuspension";
import { IPageIEcommerceMallSellerSuspension } from "../../../../api/structures/IPageIEcommerceMallSellerSuspension";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getEcommerceMallAdminSellerSuspensionsSuspensionId } from "../../../../providers/getEcommerceMallAdminSellerSuspensionsSuspensionId";
import { patchEcommerceMallAdminSellerSuspensions } from "../../../../providers/patchEcommerceMallAdminSellerSuspensions";
import { postEcommerceMallAdminSellerSuspensions } from "../../../../providers/postEcommerceMallAdminSellerSuspensions";
import { putEcommerceMallAdminSellerSuspensionsSuspensionId } from "../../../../providers/putEcommerceMallAdminSellerSuspensionsSuspensionId";

@Controller("/ecommerceMall/admin/seller-suspensions")
export class EcommercemallAdminSeller_suspensionsController {
  /**
   * Suspend a seller account by creating a suspension audit record.
   *
   * This operation creates an immutable suspension record in the ecommerce_mall_seller_suspensions table, which serves as an audit trail of all seller account suspensions and restorations. When an administrator suspends a seller, this record captures the suspended seller identifier, the suspending administrator, the reason for suspension, and the timestamp of suspension.
   *
   * The suspended seller's products will be hidden from search results and category listings, preventing customers from purchasing while the suspension is active. However, the suspended seller can still process existing orders, ship items, and respond to cancellation or refund requests.
   *
   * This operation requires administrator authentication. The suspending administrator's ID is automatically extracted from the authenticated session and recorded in the suspension record.
   *
   * The ecommerce_mall_seller_suspensions table stores the suspension reason, timestamps for suspension and optional restoration, and references to both the suspended seller and the administrators involved in suspension and potential restoration actions.
   *
   * @param connection
   * @param body Suspension request containing seller ID to suspend and reason for suspension
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Service Layer Logic:
   * 1. Validate that the authenticated user has admin role (reject if not admin)
   * 2. Validate ecommerce_mall_seller_id exists in ecommerce_mall_sellers table and is not already deleted
   * 3. Check that seller is not already in suspended status (query ecommerce_mall_seller_suspensions for active suspension with NULL restored_at)
   * 4. Validate reason field is not empty (minimum 1 character)
   * 5. Extract suspended_by_id from authenticated admin session
   * 6. Create new record in ecommerce_mall_seller_suspensions with:
   *    - id: generate UUID
   *    - ecommerce_mall_seller_id: from request body
   *    - suspended_by_id: from session
   *    - reason: from request body
   *    - suspended_at: current timestamp
   *    - restored_at: NULL (indicates active suspension)
   *    - created_at: current timestamp
   *    - updated_at: current timestamp
   * 7. Return the created suspension record
   *
   * Transaction: Single INSERT operation with validation checks
   *
   * Error Handling:
   * - 400 Bad Request: Missing required fields (seller ID, reason)
   * - 403 Forbidden: User is not an administrator
   * - 404 Not Found: Seller does not exist or is deleted
   * - 409 Conflict: Seller is already suspended
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IEcommerceMallSellerSuspension.ICreate,
  ): Promise<IEcommerceMallSellerSuspension> {
    try {
      return await postEcommerceMallAdminSellerSuspensions({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a filtered and paginated list of seller account suspension records.
   *
   * This operation provides administrative access to the complete suspension audit trail for seller accounts. Administrators can search suspensions by seller identity, filter by suspension status (currently suspended vs restored), query by date ranges, and identify which administrators performed the actions.
   *
   * The suspension records serve as an immutable audit log capturing the reason for suspension, the administrator who performed the action, and the timestamp. When a suspension is lifted, the restoration details including the restoring administrator and optional reason are recorded.
   *
   * This endpoint is exclusively accessible to administrators and super administrators. Regular sellers and customers cannot access suspension records. The operation supports cursor-based pagination for efficient traversal of large result sets.
   *
   * Related administrative operations include the suspend and unsuspend seller endpoints which create these audit records.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering suspension records
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query ecommerce_mall_seller_suspensions table with comprehensive filtering and pagination.
   *
   * Implement the following search criteria logic:
   * - Filter by ecommerce_mall_seller_id when seller identification is provided
   * - Filter by suspended_by_id to find suspensions made by a specific administrator
   * - Filter by restored_by_id for restorations performed by a specific administrator
   * - Filter by suspended_at date range using provided start and end timestamps
   * - Filter by restored_at to isolate currently suspended (NULL restored_at) vs restored suspensions
   *
   * Join relationships:
   * - Join with ecommerce_mall_sellers to access seller email for identification
   * - Join with ecommerce_mall_admins for suspended_by and restored_by administrator details
   *
   * Return results ordered by suspended_at descending (newest first). Apply configurable page size with offset-based pagination.
   *
   * Business rules:
   * - Only administrators and super administrators can access this endpoint
   * - Return complete audit trail including reason, timestamps, and restoration details
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IEcommerceMallSellerSuspension.IRequest,
  ): Promise<IPageIEcommerceMallSellerSuspension.ISummary> {
    try {
      return await patchEcommerceMallAdminSellerSuspensions({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific seller account suspension record.
   *
   * This endpoint returns complete suspension details including the suspended seller account, the administrator who performed the suspension, the reason for suspension, and timestamps. If the suspension has been lifted, it also includes restoration details.
   *
   * The operation provides audit trail visibility for administrative accountability. The response includes the suspension identifier, associated seller information (email from the ecommerce_mall_sellers table), the suspending administrator's details, suspension reason text, and timestamps for when the suspension occurred and when it was restored (if applicable).
   *
   * This endpoint is primarily used by administrators for reviewing suspension history and by sellers to view their own suspension status. The returned data includes relationship information linking to the seller account and the administrators who suspended and restored (if restored) the account.
   *
   * @param connection
   * @param suspensionId Unique identifier of the seller suspension record to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query the ecommerce_mall_seller_suspensions table using the provided suspensionId as the primary key. Join with ecommerce_mall_sellers table to retrieve seller email and current status. Join with ecommerce_mall_admins table twice (once for suspended_by_id, once for restored_by_id if not null) to include administrator details. Return the complete suspension record including all fields: id, ecommerce_mall_seller_id, suspended_by_id, restored_by_id, reason, restored_reason, suspended_at, restored_at, created_at, updated_at. If the suspensionId does not exist in the database, return a 404 error with message 'Seller suspension record not found'.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":suspensionId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("suspensionId")
    suspensionId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallSellerSuspension> {
    try {
      return await getEcommerceMallAdminSellerSuspensionsSuspensionId({
        admin,
        suspensionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Restore a suspended seller account to active status.
   *
   * This endpoint allows administrators to lift a seller suspension and restore their account to full operational status. When a suspension is restored, the suspension record is updated with the restoration timestamp, the admin who performed the restoration, and optionally a reason for the restoration.
   *
   * Restoring a seller immediately:
   * - Makes their products visible again in search results and category listings
   * - Allows customers to purchase from the seller
   * - Enables the seller to create new products and edit existing ones
   * - Does not affect any existing orders or their processing status
   *
   * The suspension record remains in the database for audit purposes, but the restored_at timestamp indicates the suspension has been lifted. The relationship to ecommerce_mall_sellers table identifies which seller account is being restored.
   *
   * Administrators must provide their authentication credentials. The restored_by_id field automatically captures which administrator performed the restoration for accountability.
   *
   * @param connection
   * @param suspensionId Unique identifier of the suspension record to restore
   * @param body Optional restoration details
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Implement the seller suspension restoration logic:
   *
   * 1. Authentication: Verify the request comes from an authenticated admin or superAdmin session.
   *
   * 2. Input Validation:
   *    - Validate suspensionId is a valid UUID format
   *    - Query the database to find the suspension record by ID
   *    - Verify the suspension record exists
   *    - Verify the suspension has not already been restored (restored_at must be NULL)
   *    - If already restored, return error indicating suspension was previously lifted
   *
   * 3. Seller Status Check:
   *    - Retrieve the associated seller record using ecommerce_mall_seller_id
   *    - Verify the seller account exists and is not banned
   *    - Verify the seller account is not deleted (deleted_at is NULL)
   *
   * 4. Database Update:
   *    - Set restored_at to current timestamp
   *    - Set restored_by_id to the authenticated admin's ID
   *    - If restored_reason is provided in request body, set it
   *    - Update the updated_at timestamp on the suspension record
   *
   * 5. Seller Account Restoration:
   *    - The seller account status remains unchanged
   *    - The seller can now list and edit products
   *    - Their products become visible in search and category listings
   *
   * 6. Response:
   *    - Return the updated suspension record including:
   *      - id, ecommerce_mall_seller_id, suspended_by_id, restored_by_id
   *      - reason, restored_reason, suspended_at, restored_at, created_at, updated_at
   *
   * 7. Error Handling:
   *    - If suspension not found: 404 Not Found
   *    - If already restored: 409 Conflict
   *    - If seller banned: 403 Forbidden
   *    - If seller deleted: 404 Not Found
   *    - If unauthorized: 401 Unauthorized
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":suspensionId")
  public async restore(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("suspensionId")
    suspensionId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceMallSellerSuspension.IUpdate,
  ): Promise<IEcommerceMallSellerSuspension> {
    try {
      return await putEcommerceMallAdminSellerSuspensionsSuspensionId({
        admin,
        suspensionId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
