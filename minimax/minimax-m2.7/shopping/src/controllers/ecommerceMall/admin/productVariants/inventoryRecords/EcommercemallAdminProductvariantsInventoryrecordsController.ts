import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallInventoryRecord } from "../../../../../api/structures/IEcommerceMallInventoryRecord";
import { IPageIEcommerceMallInventoryRecord } from "../../../../../api/structures/IPageIEcommerceMallInventoryRecord";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getEcommerceMallAdminProductVariantsVariantIdInventoryRecordsInventoryRecordId } from "../../../../../providers/getEcommerceMallAdminProductVariantsVariantIdInventoryRecordsInventoryRecordId";
import { patchEcommerceMallAdminProductVariantsVariantIdInventoryRecords } from "../../../../../providers/patchEcommerceMallAdminProductVariantsVariantIdInventoryRecords";

@Controller("/ecommerceMall/admin/productVariants/:variantId/inventoryRecords")
export class EcommercemallAdminProductvariantsInventoryrecordsController {
  /**
   * Retrieve a paginated list of inventory records for a specific product variant.
   *
   * This operation allows administrators to view the complete history of stock changes for product variants across the platform. Each inventory record captures a quantity change (positive for restocking/refunds, negative for order deductions/adjustments), the business reason for the change, and the timestamp when the change occurred.
   *
   * The inventory history helps administrators audit stock movements, investigate inventory discrepancies, and reconcile stock levels across sellers. Records are sorted by timestamp in descending order, showing the most recent changes first.
   *
   * Filters can be applied to narrow results by date range. Only inventory records for variants belonging to products on the platform are accessible.
   *
   * @param connection
   * @param variantId Unique identifier of the product variant (UUID format)
   * @param body Optional date range filters for narrowing inventory record results
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query ecommerce_mall_inventory_records table filtered by ecommerce_mall_product_variant_id.
   *
   * First, verify the product variant exists by querying ecommerce_mall_product_variants table and retrieving its ecommerce_mall_product_id. Then verify the owning product belongs to the authenticated seller by checking ecommerce_mall_products table.
   *
   * If the variant does not exist, return 404 error with message 'Product variant not found'.
   *
   * If the seller does not own the product containing the variant, return 403 error with message 'You do not have permission to view this variant inventory'.
   *
   * Apply optional filters:
   * - createdAtFrom: Filter records with created_at >= this timestamp (ISO 8601 format)
   * - createdAtTo: Filter records with created_at <= this timestamp (ISO 8601 format)
   *
   * Order results by created_at descending (most recent first).
   *
   * Return paginated results with pagination metadata including page, limit, total, and totalPages. Each record should include id, quantityChange, reason, and createdAt from the inventory record.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("variantId")
    variantId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceMallInventoryRecord.IRequest,
  ): Promise<IPageIEcommerceMallInventoryRecord.ISummary> {
    try {
      return await patchEcommerceMallAdminProductVariantsVariantIdInventoryRecords(
        {
          admin,
          variantId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single inventory record by its unique identifier.
   *
   * This endpoint returns detailed information about a specific inventory change record, including the quantity change amount, the business reason for the change, and the timestamp when the change occurred. The inventory record is immutable once created, preserving a complete audit trail of all stock changes for dispute resolution and historical tracking purposes.
   *
   * Sellers can only access inventory records belonging to variants of their own products. Platform administrators have unrestricted access to all inventory records across the platform.
   *
   * Inventory records are viewable by the seller who owns the variant and by platform administrators, serving as an audit trail for dispute resolution and financial reconciliation.
   *
   * @param connection
   * @param variantId Unique identifier of the product variant (UUID format)
   * @param inventoryRecordId Unique identifier of the inventory record (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification 1. Extract variantId and inventoryRecordId from path parameters.
   * 2. Validate that both IDs are valid UUIDs.
   * 3. Verify the product variant exists and is not soft-deleted (deleted_at IS NULL).
   * 4. Verify the inventory record exists and belongs to the specified variant.
   * 5. For seller requests: Verify the parent product belongs to the requesting seller. Return 403 Forbidden if ownership check fails.
   * 6. For admin requests: Allow unrestricted access to any inventory record.
   * 7. Calculate current stock by summing all quantity_change values for the variant.
   * 8. Return the inventory record with calculated current_stock included.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":inventoryRecordId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("variantId")
    variantId: string & tags.Format<"uuid">,
    @TypedParam("inventoryRecordId")
    inventoryRecordId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallInventoryRecord> {
    try {
      return await getEcommerceMallAdminProductVariantsVariantIdInventoryRecordsInventoryRecordId(
        {
          admin,
          variantId,
          inventoryRecordId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
