import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallAdmin } from "../../../../../api/structures/IEcommerceMallAdmin";
import { IEcommerceMallAdminPromotion } from "../../../../../api/structures/IEcommerceMallAdminPromotion";
import { IPageIEcommerceMallAdmin } from "../../../../../api/structures/IPageIEcommerceMallAdmin";
import { SuperadminAuth } from "../../../../../decorators/SuperadminAuth";
import { SuperadminPayload } from "../../../../../decorators/payload/SuperadminPayload";
import { getEcommerceMallSuperAdminSuperAdminAdminsAdminId } from "../../../../../providers/getEcommerceMallSuperAdminSuperAdminAdminsAdminId";
import { patchEcommerceMallSuperAdminSuperAdminAdmins } from "../../../../../providers/patchEcommerceMallSuperAdminSuperAdminAdmins";
import { postEcommerceMallSuperAdminSuperAdminAdminsAdminIdDemote } from "../../../../../providers/postEcommerceMallSuperAdminSuperAdminAdminsAdminIdDemote";
import { postEcommerceMallSuperAdminSuperAdminAdminsAdminIdPromote } from "../../../../../providers/postEcommerceMallSuperAdminSuperAdminAdminsAdminIdPromote";

@Controller("/ecommerceMall/superAdmin/superAdmin/admins")
export class EcommercemallSuperadminSuperadminAdminsController {
  /**
   * Retrieve a filtered and paginated list of administrator accounts on the platform.
   *
   * This operation allows super administrators to search and browse all administrator accounts. Supports filtering by email pattern matching, name search, creation date ranges, and account status (active/suspended).
   *
   * Provides comprehensive pagination with configurable page sizes and sorting options. Results include administrator summary information optimized for list displays with essential account details.
   *
   * Only accessible by super administrators with full platform governance privileges.
   *
   * @param connection
   * @param body Search criteria, filters, and pagination parameters for listing administrators
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification Query ecommerce_mall_admins table with pagination and filtering.
   *
   * Apply search filters on email (partial match), name (partial match), and created_at date range.
   * Filter by status: active accounts (deleted_at is null) vs suspended accounts (deleted_at is set).
   * Sort by created_at descending by default, or by name if specified.
   * Return cursor-based pagination for large result sets.
   * Exclude password_hash from all query results.
   * Validate that requesting user has super admin privileges before returning data.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SuperadminAuth()
    superAdmin: SuperadminPayload,
    @TypedBody()
    body: IEcommerceMallAdmin.IRequest,
  ): Promise<IPageIEcommerceMallAdmin.ISummary> {
    try {
      return await patchEcommerceMallSuperAdminSuperAdminAdmins({
        superAdmin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information for a specific administrator account by its unique identifier.
   *
   * This endpoint allows super administrators to view complete details of any administrator account on the platform. The response includes the admin's basic account information such as email, display name, and account creation timestamp.
   *
   * Only active administrator accounts (not soft-deleted) can be retrieved. Attempting to access a deleted administrator account will return a not found response. This operation supports platform oversight by enabling super administrators to review admin accounts before performing administrative actions such as promotion or demotion.
   *
   * The retrieved admin details can be used to verify account status, review account history, or prepare for role management operations.
   *
   * @param connection
   * @param adminId Unique identifier of the administrator account to retrieve (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification Query the ecommerce_mall_admins table filtering by id equal to the provided adminId path parameter. Apply WHERE deleted_at IS NULL to exclude soft-deleted administrator accounts. Return all columns: id, email, name, created_at, updated_at, deleted_at.
   *
   * If no matching active admin is found, return HTTP 404 with error code ADMIN_NOT_FOUND. This operation requires the authenticated user to be a super administrator (validated via JWT session in ecommerce_mall_admin_sessions).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":adminId")
  public async at(
    @SuperadminAuth()
    superAdmin: SuperadminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallAdmin> {
    try {
      return await getEcommerceMallSuperAdminSuperAdminAdminsAdminId({
        superAdmin,
        adminId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Promote a regular administrator to super administrator status.
   *
   * This operation can only be executed by super administrators. Upon promotion, the target administrator gains all super administrator privileges including the ability to approve administrator requests, promote other administrators, and demote other super administrators.
   *
   * The operation creates an immutable audit record documenting the promotion action, who performed it, and any associated reason. The promoted administrator immediately receives elevated access without requiring re-login.
   *
   * Super administrators cannot promote other super administrators. This restriction ensures that super admin status can only be granted by existing super administrators, maintaining proper governance controls.
   *
   * This operation does not affect the promoted administrator's account credentials, email, or basic profile information.
   *
   * @param connection
   * @param adminId The unique identifier of the administrator to promote to super administrator
   * @param body Optional reason for the promotion action, typically used for audit purposes
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification Validate that the authenticated user is a super administrator with valid session. Extract super admin ID from authenticated session.
   *
   * Retrieve the target administrator by adminId from ecommerce_mall_admins table. Verify the administrator exists and is not soft-deleted (deleted_at is null). Verify the administrator is not already a super administrator (check grade field). Return error if target is already super admin.
   *
   * Verify that the authenticated super admin is not promoting themselves. Return error if adminId matches the authenticated super admin's ID.
   *
   * Create a new record in ecommerce_mall_admin_promotions table with:
   * - id: UUID v4
   * - admin_id: target administrator's UUID
   * - performed_by_super_admin_id: authenticated super admin's UUID
   * - action: 'promotion'
   * - reason: optional reason from request body (nullable)
   * - created_at: current timestamp
   *
   * Update the administrator's grade field to 'super' in ecommerce_mall_admins table.
   *
   * Return the created promotion record including admin details, performer details, action type, reason, and timestamp.
   *
   * Handle edge cases:
   * - Admin not found: return 404 with appropriate error message
   * - Admin already super admin: return 400 with error message
   * - Self-promotion attempt: return 400 with error message
   * - Database transaction failure: rollback and return 500 error
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post(":adminId/promote")
  public async promote(
    @SuperadminAuth()
    superAdmin: SuperadminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceMallAdminPromotion.ICreate,
  ): Promise<IEcommerceMallAdminPromotion> {
    try {
      return await postEcommerceMallSuperAdminSuperAdminAdminsAdminIdPromote({
        superAdmin,
        adminId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Demote a super administrator to regular administrator status.
   *
   * This endpoint allows a super administrator to reduce another administrator's privilege level from super administrator to regular administrator. The operation immediately revokes super administrator privileges including admin request management capabilities.
   *
   * Self-demotion prevention is strictly enforced. A super administrator cannot demote their own account regardless of any additional context provided in the request.
   *
   * The operation creates an immutable audit record documenting the demotion action, including the target administrator, the performing super administrator, the action type, and any optional reason provided.
   *
   * @param connection
   * @param adminId Unique identifier of the administrator to demote (UUID format).
   * @param body Optional demotion reason provided by the super administrator.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification 1. Authenticate the requesting user as a super administrator via session token validation.
   * 2. Extract adminId from path parameter (UUID format).
   * 3. Validate adminId corresponds to an existing admin account.
   * 4. Retrieve the authenticated super admin's ID from session.
   * 5. REJECT if adminId equals the authenticated super admin's ID (self-demotion prevention).
   * 6. Verify target admin has super administrator privileges.
   * 7. Create a new record in ecommerce_mall_admin_promotions table with:
   *    - id: new UUID
   *    - admin_id: target admin's UUID
   *    - performed_by_super_admin_id: authenticated super admin's UUID
   *    - action: 'demotion'
   *    - reason: from request body (nullable)
   *    - created_at: current timestamp
   * 8. Return the created promotion record.
   * 9. Handle errors: NOT_FOUND if admin doesn't exist, FORBIDDEN if not super admin or self-demotion attempt.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post(":adminId/demote")
  public async demote(
    @SuperadminAuth()
    superAdmin: SuperadminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceMallAdminPromotion.IDemote,
  ): Promise<IEcommerceMallAdminPromotion> {
    try {
      return await postEcommerceMallSuperAdminSuperAdminAdminsAdminIdDemote({
        superAdmin,
        adminId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
