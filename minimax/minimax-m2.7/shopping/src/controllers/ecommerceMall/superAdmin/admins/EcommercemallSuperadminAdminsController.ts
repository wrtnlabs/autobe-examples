import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallAdmin } from "../../../../api/structures/IEcommerceMallAdmin";
import { IPageIEcommerceMallAdmin } from "../../../../api/structures/IPageIEcommerceMallAdmin";
import { SuperadminAuth } from "../../../../decorators/SuperadminAuth";
import { SuperadminPayload } from "../../../../decorators/payload/SuperadminPayload";
import { getEcommerceMallSuperAdminAdminsAdminId } from "../../../../providers/getEcommerceMallSuperAdminAdminsAdminId";
import { patchEcommerceMallSuperAdminAdmins } from "../../../../providers/patchEcommerceMallSuperAdminAdmins";

@Controller("/ecommerceMall/superAdmin/admins")
export class EcommercemallSuperadminAdminsController {
  /**
   * Retrieve a filtered and paginated list of administrator accounts on the platform.
   *
   * This operation provides advanced search capabilities for platform administrators. Super administrators can filter by name, email, account status (active/deleted), and role level (super admin or regular admin). The results are paginated with configurable page sizes.
   *
   * Supports comprehensive pagination with cursor-based navigation for large result sets. Response includes administrator summary information optimized for list displays, excluding sensitive fields like password hashes.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering administrators
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification Query ecommerce_mall_admins table with pagination and filtering.
   * Apply search filters on name (partial match), email (partial match), role level filter (super_admin boolean flag), and account status filter (active/deleted).
   * Order by created_at descending by default.
   * Return cursor-based pagination for large result sets.
   * Join with ecommerce_mall_super_admins to determine super admin status.
   * Exclude password_hash field from results.
   * Filter out soft-deleted admins by default unless explicitly requested.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SuperadminAuth()
    superAdmin: SuperadminPayload,
    @TypedBody()
    body: IEcommerceMallAdmin.IRequest,
  ): Promise<IPageIEcommerceMallAdmin.ISummary> {
    try {
      return await patchEcommerceMallSuperAdminAdmins({
        superAdmin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve administrator account details by unique identifier.
   *
   * This endpoint allows super administrators to fetch detailed information about a specific administrator account on the platform. The response includes the administrator's basic profile information such as name, email, and timestamps.
   *
   * Sensitive information such as password hashes are never exposed in the response.
   *
   * If the administrator has been soft-deleted (deleted_at is not null), the account is considered inactive and should not be accessible.
   *
   * Use cases include administrative oversight, verification of administrative actions, and platform governance activities performed by super administrators.
   *
   * @param connection
   * @param adminId Unique identifier of the administrator account (global scope)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification Query the ecommerce_mall_admins table using the provided adminId as the primary key. Verify the requesting user has permission to view the target admin: if the requester is a regular admin, they can only access their own record; if the requester is a super admin, they can access any admin record.
   *
   * Select all columns EXCEPT password_hash for security reasons. Include related data if beneficial: role classification, status, created_at timestamp.
   *
   * If the adminId does not correspond to an existing administrator, return a 404 error with message indicating admin not found.
   *
   * If the requesting user is a regular admin attempting to view another admin's profile, return a 403 forbidden error.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":adminId")
  public async at(
    @SuperadminAuth()
    superAdmin: SuperadminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallAdmin> {
    try {
      return await getEcommerceMallSuperAdminAdminsAdminId({
        superAdmin,
        adminId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
