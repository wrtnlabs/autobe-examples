import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallAdminSession } from "../../../../../api/structures/IEcommerceMallAdminSession";
import { IPageIEcommerceMallAdminSession } from "../../../../../api/structures/IPageIEcommerceMallAdminSession";
import { SuperadminAuth } from "../../../../../decorators/SuperadminAuth";
import { SuperadminPayload } from "../../../../../decorators/payload/SuperadminPayload";
import { getEcommerceMallSuperAdminAdminsAdminIdSessionsSessionId } from "../../../../../providers/getEcommerceMallSuperAdminAdminsAdminIdSessionsSessionId";
import { patchEcommerceMallSuperAdminAdminsAdminIdSessions } from "../../../../../providers/patchEcommerceMallSuperAdminAdminsAdminIdSessions";

@Controller("/ecommerceMall/superAdmin/admins/:adminId/sessions")
export class EcommercemallSuperadminAdminsSessionsController {
  /**
   * Retrieve a paginated list of administrator sessions filtered by specified criteria.
   *
   * This endpoint returns sessions belonging to the specified administrator with support for filtering by IP address, URL path, HTTP referrer, creation date range, and expiration status. Results are returned in reverse chronological order by default.
   *
   * Sessions contain security-relevant information including client IP address, accessed URLs, and referrer headers for audit and security monitoring purposes. Only sessions that have not been soft-deleted are included in results.
   *
   * Use this endpoint to audit administrator activity, investigate suspicious login patterns, or review session history for security compliance.
   *
   * @param connection
   * @param adminId Unique identifier of the administrator whose sessions to retrieve
   * @param body Search criteria and pagination parameters for filtering sessions
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification Query the ecommerce_mall_admin_sessions table filtering by ecommerce_mall_admin_id equal to the path parameter adminId.
   *
   * Apply the following optional filters from request body:
   * - Filter by IP address (exact or partial match)
   * - Filter by href URL path (exact or prefix match)
   * - Filter by referrer header
   * - Filter by created_at date range (after/before)
   * - Filter by expired_at date range (expired/not expired/specific range)
   *
   * Exclude sessions where the corresponding admin's deleted_at is not null (use JOIN with ecommerce_mall_admins).
   *
   * Implement pagination with cursor-based navigation using created_at as cursor, or offset-based with page/limit parameters.
   *
   * Order results by created_at descending (newest first) by default.
   *
   * Return total count for pagination metadata.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SuperadminAuth()
    superAdmin: SuperadminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceMallAdminSession.IRequest,
  ): Promise<IPageIEcommerceMallAdminSession.ISummary> {
    try {
      return await patchEcommerceMallSuperAdminAdminsAdminIdSessions({
        superAdmin,
        adminId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific administrator session by its unique identifier.
   *
   * This operation returns detailed session information including the client's IP address, current URL path, HTTP referrer, and session timestamps. Session metadata is valuable for security auditing and allows administrators to review login activity from specific devices or locations.
   *
   * The session must belong to the specified admin. If the session does not exist or belongs to a different admin, the operation returns a not found error. Expired sessions are still retrievable for audit purposes.
   *
   * This endpoint requires super administrator authentication. Only super administrators can view admin session details.
   *
   * @param connection
   * @param adminId Unique identifier of the administrator who owns the session (global scope)
   * @param sessionId Unique identifier of the session to retrieve (scoped to admin)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification Query ecommerce_mall_admin_sessions table using the sessionId parameter as the primary key.
   *
   * Verify that the session's ecommerce_mall_admin_id matches the adminId path parameter. If the session belongs to a different admin, return a 404 not found response.
   *
   * Return the full session entity including: id, ecommerce_mall_admin_id, ip address, href, referrer, created_at, and expired_at.
   *
   * Handle the case where the session record does not exist by returning an appropriate 404 error.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @SuperadminAuth()
    superAdmin: SuperadminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallAdminSession> {
    try {
      return await getEcommerceMallSuperAdminAdminsAdminIdSessionsSessionId({
        superAdmin,
        adminId,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
