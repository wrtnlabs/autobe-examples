import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallAdminRequest } from "../../../../../api/structures/IEcommerceMallAdminRequest";
import { IPageIEcommerceMallAdminRequest } from "../../../../../api/structures/IPageIEcommerceMallAdminRequest";
import { SuperadminAuth } from "../../../../../decorators/SuperadminAuth";
import { SuperadminPayload } from "../../../../../decorators/payload/SuperadminPayload";
import { getEcommerceMallSuperAdminAdminRequestsRequestId } from "../../../../../providers/getEcommerceMallSuperAdminAdminRequestsRequestId";
import { patchEcommerceMallSuperAdminAdminRequests } from "../../../../../providers/patchEcommerceMallSuperAdminAdminRequests";
import { putEcommerceMallSuperAdminAdminRequestsRequestId } from "../../../../../providers/putEcommerceMallSuperAdminAdminRequestsRequestId";

@Controller("/ecommerceMall/superAdmin/admin/requests")
export class EcommercemallSuperadminAdminRequestsController {
  /**
   * Retrieve a filtered and paginated list of administrator requests on the platform.
   *
   * This operation allows super administrators to search and browse all admin requests across the platform with various filters. The endpoint supports filtering by request status (pending, approved, rejected), actor type (customer or seller), requested privilege grade (admin or super_admin), and submission date range.
   *
   * The response is paginated with configurable page sizes and sorting options. Each result includes the request ID, actor type, requested grade, reason text, current status, submission timestamp, and reviewer information if the request has been processed.
   *
   * Super administrators use this endpoint for complete administrative oversight including reviewing pending requests before approval decisions, auditing historical requests, and monitoring platform administrative activity patterns. The search supports partial reason matching via text search on the reason field.
   *
   * This endpoint provides access to the ecommerce_mall_admin_requests table with polymorphic ownership tracking (actor_type discriminator) and complete review workflow status (status field) for platform governance.
   *
   * @param connection
   * @param body Search criteria and pagination parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification Query the ecommerce_mall_admin_requests table with pagination and filtering.
   *
   * Apply search filters:
   * - status: Filter by request status (pending, approved, rejected)
   * - actor_type: Filter by requesting actor type (customer, seller)
   * - requested_grade: Filter by requested privilege grade (admin, super_admin)
   * - created_at_from and created_at_to: Filter by submission date range
   * - reason: Partial text match on reason field
   *
   * Join with ecommerce_mall_super_admins table to include reviewer information when available (reviewed_by_id -> ecommerce_mall_super_admins join).
   *
   * Apply cursor-based or offset pagination with configurable page sizes (default 20, max 100).
   *
   * Sort by created_at descending (newest first) by default.
   *
   * Exclude soft-deleted records (WHERE deleted_at IS NULL).
   *
   * Return total count for pagination metadata.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SuperadminAuth()
    superAdmin: SuperadminPayload,
    @TypedBody()
    body: IEcommerceMallAdminRequest.IRequest,
  ): Promise<IPageIEcommerceMallAdminRequest.ISummary> {
    try {
      return await patchEcommerceMallSuperAdminAdminRequests({
        superAdmin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific administrator request on the platform.
   *
   * This endpoint returns the complete details of an admin request including the requesting user's type (customer or seller), the requested privilege grade, the reason provided by the requester, current status, and any review information if the request has been processed by a super administrator.
   *
   * The admin request tracks a polymorphic relationship where the requesting user can be either a customer or a seller. The actor_type discriminator field indicates which type of actor submitted the request.
   *
   * Super administrators use this endpoint to review individual requests before taking approval or rejection actions. The response includes timestamps for submission and last modification, allowing super admins to track the request lifecycle.
   *
   * If the request has been reviewed, the response includes the reviewing super administrator's ID and any rejection reason they provided.
   *
   * @param connection
   * @param requestId Unique identifier of the admin request to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification Query the ecommerce_mall_admin_requests table filtering by the requestId UUID parameter. Return the matching record including all fields: id, actor_type, requested_grade, reason, status, reviewed_by_id, reviewed_reason, created_at, updated_at, deleted_at.
   *
   * Validate that the authenticated user is a super administrator. Return 403 Forbidden if the user lacks super admin privileges.
   *
   * Handle soft-deleted records: if deleted_at is not null, return 404 Not Found.
   *
   * Join with ecommerce_mall_super_admins table to include reviewer information if available.
   *
   * Return 404 Not Found if no matching record exists.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":requestId")
  public async at(
    @SuperadminAuth()
    superAdmin: SuperadminPayload,
    @TypedParam("requestId")
    requestId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallAdminRequest> {
    try {
      return await getEcommerceMallSuperAdminAdminRequestsRequestId({
        superAdmin,
        requestId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an admin request by approving or rejecting it.
   *
   * This endpoint allows super administrators to review and act on administrator privilege requests submitted by platform users (customers or sellers). When a super administrator approves a request, the requesting user immediately gains administrator privileges on the platform. When rejecting, an optional rejection reason should be provided to help the user understand the decision.
   *
   * The admin request must be in pending status to be updated. Once approved or rejected, the status cannot be changed. Only super administrators have authority to perform this action - regular administrators cannot approve or reject admin requests.
   *
   * The operation validates that the request exists and is in pending status before processing. The reviewing super administrator's ID is recorded automatically from the authenticated session.
   *
   * @param connection
   * @param requestId Unique identifier of the admin request to update
   * @param body Update information containing the new status and optional review reason
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification 1. Extract requestId from path parameter and validate as UUID format.
   * 2. Extract the authenticated super administrator from the session context.
   * 3. Validate the admin request exists and is in pending status.
   * 4. Validate the status field in request body is either 'approved' or 'rejected'.
   * 5. If status is 'rejected', reviewed_reason should be captured but is optional.
   * 6. Update the admin_request record:
   *    - Set status to the new value
   *    - Set reviewed_by_id to the authenticated super admin's ID
   *    - Set reviewed_reason if provided
   * 7. If status becomes 'approved', the requesting user gains administrator privileges.
   * 8. Return the complete updated admin_request record including:
   *    - The original request details (reason, requested_grade)
   *    - The review information (status, reviewed_by_id, reviewed_reason)
   *    - Timestamps (created_at, updated_at)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":requestId")
  public async update(
    @SuperadminAuth()
    superAdmin: SuperadminPayload,
    @TypedParam("requestId")
    requestId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceMallAdminRequest.IUpdate,
  ): Promise<IEcommerceMallAdminRequest> {
    try {
      return await putEcommerceMallSuperAdminAdminRequestsRequestId({
        superAdmin,
        requestId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
