import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallAdmin } from "../../../../api/structures/IEcommerceMallAdmin";
import { IEcommerceMallAdminPromotion } from "../../../../api/structures/IEcommerceMallAdminPromotion";
import { SuperadminAuth } from "../../../../decorators/SuperadminAuth";
import { SuperadminPayload } from "../../../../decorators/payload/SuperadminPayload";
import { postEcommerceMallSuperAdminAdminDemoteUserId } from "../../../../providers/postEcommerceMallSuperAdminAdminDemoteUserId";
import { postEcommerceMallSuperAdminAdminPromoteUserId } from "../../../../providers/postEcommerceMallSuperAdminAdminPromoteUserId";

@Controller("/ecommerceMall/superAdmin/admin")
export class EcommercemallSuperadminAdminController {
  /**
   * Promotes a regular administrator to super administrator status.
   *
   * This endpoint allows super administrators to elevate regular administrators to super administrator privileges. Upon successful promotion, the target administrator gains all super administrator capabilities including the ability to approve admin requests, promote other regular administrators, and demote other super administrators.
   *
   * **Authorization**: Only authenticated super administrators can invoke this operation.
   *
   * **Audit Trail**: Every promotion creates an immutable record in the admin promotions audit log capturing who was promoted, who performed the action, and any associated reason.
   *
   * **Constraints**: Cannot promote users who are not regular administrators. Cannot promote super administrators. Cannot self-promote.
   *
   * @param connection
   * @param userId Unique identifier of the administrator to promote to super administrator.
   * @param body Optional reason for the promotion, such as performance review outcome or trust decision rationale.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification 1. Validate the authenticated user is a super administrator (authorization check).
   * 2. Retrieve the target admin from ecommerce_mall_admins by userId parameter.
   * 3. Verify the target admin exists and is not soft-deleted (deleted_at is null).
   * 4. Verify the target admin is currently a regular administrator (not already super).
   * 5. Verify the authenticated super admin is not promoting themselves.
   * 6. Create a new record in ecommerce_mall_admin_promotions with:
   *    - id: UUID generated
   *    - admin_id: target admin's UUID
   *    - performed_by_super_admin_id: authenticated super admin's UUID
   *    - action: 'promotion'
   *    - reason: from request body (optional)
   *    - created_at: current timestamp
   * 7. Return the created promotion record.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("promote/:userId")
  public async promote(
    @SuperadminAuth()
    superAdmin: SuperadminPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceMallAdminPromotion.ICreate,
  ): Promise<IEcommerceMallAdminPromotion> {
    try {
      return await postEcommerceMallSuperAdminAdminPromoteUserId({
        superAdmin,
        userId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Demotes a super administrator to regular administrator status.
   *
   * This endpoint allows super administrators to reduce another super administrator's privileges to regular administrator level. The demoted administrator immediately loses all super admin capabilities including the ability to promote or demote other administrators, manage admin requests, and access super admin-exclusive features.
   *
   * Authorization: Only authenticated super administrators can access this endpoint. Regular administrators, customers, sellers, and unauthenticated users cannot perform this action.
   *
   * Self-Demotion Prevention: The system prevents a super administrator from demoting their own account. This constraint ensures at least one super administrator always retains full platform authority.
   *
   * Audit Trail: Every demotion action is recorded in the audit log with the acting super administrator's identity, target identity, timestamp, IP address, and user agent for security accountability.
   *
   * Error Handling: Returns appropriate error responses if the target user does not exist, is not a super administrator, if the authenticated user attempts self-demotion, or if authorization fails.
   *
   * @param connection
   * @param userId Unique identifier of the administrator account to demote to regular administrator status.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification 1. Extract the authenticated super administrator from the request context (from JWT session token).
   * 2. Retrieve the target userId from the path parameter.
   * 3. Validate that the target userId is a valid UUID format - return 400 if invalid.
   * 4. Query ecommerce_mall_admins table to find the target admin - return 404 if not found.
   * 5. Validate that the target admin currently has super administrator privileges (check if they exist in ecommerce_mall_super_admins table or have super_admin grade) - return 400 if already a regular admin.
   * 6. Validate that the authenticated super administrator is NOT demoting themselves by comparing userId with authenticated user's id - return 400 with error message if self-demotion attempted.
   * 7. Within a database transaction: update the target's grade from super_admin to regular_admin, remove their super admin privileges.
   * 8. Create an audit log entry in ecommerce_mall_super_admin_audit_logs with: ecommerce_mall_super_admin_id (acting user), action 'demote_to_admin', target_type 'admin', target_id (demoted admin's id), ip address from request, user agent string, and current timestamp.
   * 9. Commit the transaction.
   * 10. Return the updated admin entity with all fields except password_hash (id, email, name, created_at, updated_at, deleted_at).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("demote/:userId")
  public async demote(
    @SuperadminAuth()
    superAdmin: SuperadminPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallAdmin> {
    try {
      return await postEcommerceMallSuperAdminAdminDemoteUserId({
        superAdmin,
        userId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
