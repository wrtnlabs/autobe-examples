import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallShipmentItem } from "../../../../../api/structures/IEcommerceMallShipmentItem";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { getEcommerceMallSellerShipmentsShipmentIdItems } from "../../../../../providers/getEcommerceMallSellerShipmentsShipmentIdItems";
import { getEcommerceMallSellerShipmentsShipmentIdItemsItemId } from "../../../../../providers/getEcommerceMallSellerShipmentsShipmentIdItemsItemId";

@Controller("/ecommerceMall/seller/shipments/:shipmentId/items")
export class EcommercemallSellerShipmentsItemsController {
  /**
   * Retrieves all order items included in a specific shipment.
   *
   * This endpoint returns the list of shipment items bundled together in a shipment, along with their complete order item details including product information, variant options, quantities, and prices captured at purchase time.
   *
   * **Path Parameters**
   * - `shipmentId`: Unique identifier of the shipment
   *
   * **Response Details**
   * The response includes an array of shipment items, where each item contains:
   * - Shipment item metadata (ID, creation timestamp)
   * - Complete order item details (product name, description, quantity, unit price, status)
   * - Product snapshot information (captured product state at purchase time)
   * - Product variant details (SKU, option key-value pairs)
   *
   * **Error Scenarios**
   * - 404 Not Found: Shipment does not exist or has been deleted
   * - 403 Forbidden: User does not have permission to view this shipment
   *
   * @param connection
   * @param shipmentId Unique identifier of the shipment whose items to retrieve.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Query the ecommerce_mall_shipment_items table
     *   filtering by ecommerce_mall_shipment_id matching the path parameter.
   *
   * Join ecommerce_mall_shipment_items with ecommerce_mall_order_items to retrieve order item details.
   * Further join with:
   * - ecommerce_mall_product_snapshots for product information captured at purchase time
   * - ecommerce_mall_product_snapshot_variants for variant details
   * - ecommerce_mall_product_snapshot_variant_option_values for option key-value pairs
   *
   * Filter out any records where the parent shipment has deleted_at not null (soft-deleted shipments return 404).
   *
   * Return items ordered by ecommerce_mall_shipment_items.created_at ascending.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async getByShipmentid(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("shipmentId")
    shipmentId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallShipmentItem.IInvert> {
    try {
      return await getEcommerceMallSellerShipmentsShipmentIdItems({
        seller,
        shipmentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves a specific shipment item with its associated order item details.
   *
   * This endpoint allows customers to view detailed information about a particular item within a shipment, including the product name, variant details, quantity, unit price, and current status. The response includes the shipment tracking information alongside the order item specifics for comprehensive visibility into the shipped product.
   *
   * **Authorization**: Customers can only view shipment items belonging to their own orders. Sellers can view shipment items for their own shipped products. The system validates ownership before returning data.
   *
   * **Error Handling**: Returns 404 if the shipment or item is not found, or 403 if the requester does not have permission to view the item.
   *
   * @param connection
   * @param shipmentId Unique identifier of the shipment (UUID format)
   * @param itemId Unique identifier of the shipment item (UUID format)
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Retrieve a single shipment item by its ID within
     *   a specific shipment.
   *
   * 1. Validate the shipmentId and itemId are valid UUIDs
   * 2. Query ecommerce_mall_shipment_items table filtering by id = itemId AND ecommerce_mall_shipment_id = shipmentId
   * 3. If not found, throw NOT_FOUND error
   * 4. Join with ecommerce_mall_order_items to get order item details (product info, quantity, unit_price, status)
   * 5. Verify authorization:
   *    - If customer: verify the order belongs to the authenticated customer
   *    - If seller: verify the shipment belongs to the authenticated seller
   *    - If admin/superAdmin: allow access
   * 6. If authorization fails, throw FORBIDDEN error
   * 7. Return the shipment item with nested order item details
   *
   * Include in response:
   * - Shipment item ID, created_at
   * - Order item ID, quantity, unit_price, status
   * - Product snapshot details (name, description)
   * - Product variant options if applicable
   * - Seller profile snapshot (shop name)
   * - Shipment tracking info (carrier, tracking_number) from parent shipment
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":itemId")
  public async getByShipmentidAndItemid(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("shipmentId")
    shipmentId: string & tags.Format<"uuid">,
    @TypedParam("itemId")
    itemId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallShipmentItem> {
    try {
      return await getEcommerceMallSellerShipmentsShipmentIdItemsItemId({
        seller,
        shipmentId,
        itemId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
