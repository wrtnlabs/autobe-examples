import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallShipment } from "../../../../../api/structures/IEcommerceMallShipment";
import { IEcommerceMallShipmentItem } from "../../../../../api/structures/IEcommerceMallShipmentItem";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { getEcommerceMallSellerShipmentsShipmentIdItemsItemId } from "../../../../../providers/getEcommerceMallSellerShipmentsShipmentIdItemsItemId";
import { patchEcommerceMallSellerShipmentsShipmentIdItems } from "../../../../../providers/patchEcommerceMallSellerShipmentsShipmentIdItems";

@Controller("/ecommerceMall/seller/shipments/:shipmentId/items")
export class EcommercemallSellerShipmentsItemsController {
  /**
   * Add order items to an existing shipment.
   *
   * This endpoint allows sellers to add more order items to a shipment that has already been created. When a seller selects additional paid order items to include in a shipment, this operation adds those items and updates their status to shipped.
   *
   * All order items being added must belong to the same seller as the shipment owner and must be associated with the same order as the shipment. Each order item can only belong to one shipment, so items that are already in another shipment cannot be added.
   *
   * When items are successfully added to a shipment, their status changes from 'paid' to 'shipped'. The status change is atomic - if any item fails validation, no items are added and the shipment remains unchanged.
   *
   * The seller can only add items to their own shipments. Attempts to add items to another seller's shipment result in an authorization error.
   *
   * This operation is typically used when a seller wants to add more items to an existing shipment package after initially creating it with some items.
   *
   * @param connection
   * @param shipmentId Unique identifier of the shipment to add items to
   * @param body Array of order item IDs to add to the shipment
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification 1. Extract shipmentId from path parameter
   * 2. Validate the shipment exists and belongs to the authenticated seller
   * 3. For each orderItemId in the request body:
   *    a. Validate the order item exists
   *    b. Validate the order item belongs to the same order as the shipment
   *    c. Validate the order item belongs to the same seller as the shipment
   *    d. Validate the order item status is 'paid'
   *    e. Validate the order item is not already in another shipment
   * 4. Use a database transaction to:
   *    a. Create shipment_item records for each order item
   *    b. Update order item status to 'shipped'
   *    c. Set shipped_at timestamp on order items
   * 5. If any validation fails, rollback the transaction and return error
   * 6. Return the updated shipment with all included items
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async update(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("shipmentId")
    shipmentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceMallShipmentItem.IAdd,
  ): Promise<IEcommerceMallShipment> {
    try {
      return await patchEcommerceMallSellerShipmentsShipmentIdItems({
        seller,
        shipmentId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific shipment item.
   *
   * This endpoint returns the complete details of a shipment item including the associated order item information, product details captured at purchase time via product snapshots, and seller profile information. The response provides comprehensive context for customers to verify their shipment contents and track delivery status.
   *
   * The shipment item is identified by its composite key combining the shipment ID and the individual item ID. Each shipment bundles one or more order items from the same seller, and this endpoint provides the detailed view of each item within that bundle.
   *
   * Security: This operation requires customer authentication to access their own shipment items. The system validates that the requesting customer owns the parent order and shipment before returning the item details.
   *
   * Related Operations: Use GET /shipments/{shipmentId} to view all items in a shipment, or GET /orders/{orderId} to view the complete order with all shipments and items.
   *
   * @param connection
   * @param shipmentId Unique identifier of the parent shipment (UUID format)
   * @param itemId Unique identifier of the shipment item (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Retrieve a shipment item by its composite identifier (shipmentId + itemId).
   *
   * Implementation Steps:
   * 1. Extract shipmentId and itemId from path parameters
   * 2. Query ecommerce_mall_shipment_items table to find the item with matching shipment and item IDs
   * 3. Verify the shipment belongs to an order owned by the authenticated customer
   * 4. Join with ecommerce_mall_shipment_items -> ecommerce_mall_order_items to get order item details
   * 5. Join with ecommerce_mall_product_snapshots to get frozen product information (name, description)
   * 6. Join with ecommerce_mall_seller_profile_snapshots to get seller information at purchase time
   * 7. Join with ecommerce_mall_product_variant_option_values to get variant option details
   * 8. Return the complete shipment item with all nested information
   *
   * Error Handling:
   * - 404 Not Found: If shipment item does not exist
   * - 403 Forbidden: If the customer does not own the parent order
   * - 400 Bad Request: If path parameters are invalid UUIDs
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":itemId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("shipmentId")
    shipmentId: string & tags.Format<"uuid">,
    @TypedParam("itemId")
    itemId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallShipmentItem> {
    try {
      return await getEcommerceMallSellerShipmentsShipmentIdItemsItemId({
        seller,
        shipmentId,
        itemId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
