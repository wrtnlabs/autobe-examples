import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallOrderItem } from "../../../../../api/structures/IEcommerceMallOrderItem";
import { IPageIEcommerceMallOrderItem } from "../../../../../api/structures/IPageIEcommerceMallOrderItem";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { patchEcommerceMallSellerDashboardOrderItems } from "../../../../../providers/patchEcommerceMallSellerDashboardOrderItems";

@Controller("/ecommerceMall/seller/dashboard/order-items")
export class EcommercemallSellerDashboardOrder_itemsController {
  /**
   * Retrieve a paginated and filtered list of order items for the authenticated seller's products.
   *
   * This endpoint allows sellers to view all order items across orders that contain their products. Sellers can filter by item status to find items awaiting shipment, in transit, delivered, cancelled, or refunded.
   *
   * The response includes essential order item information: the order number, product name and variant details, quantity purchased, unit price at time of sale, current status, and the order date. This data enables sellers to efficiently manage their order fulfillment workflow.
   *
   * Only order items belonging to products owned by the authenticated seller are returned. The seller cannot see order items from other sellers' products.
   *
   * Status values for filtering:
   * - paid: Payment completed, awaiting shipment
   * - shipped: Item has been shipped
   * - delivered: Item delivered to customer
   * - cancelled: Item cancelled by seller
   * - refunded: Item refunded to customer
   *
   * Related operations:
   * - POST /seller/orders/items/:itemId/ship - Ship paid order items
   * - GET /seller/cancellations - View pending cancellation requests
   * - GET /seller/refunds - View pending refund requests
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering order items
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query ecommerce_mall_order_items table with JOIN to ecommerce_mall_products to filter by authenticated seller's product ownership.
   *
   * Join with ecommerce_mall_orders to get order_number and order date.
   * Join with ecommerce_mall_product_snapshots to get product name.
   * Join with ecommerce_mall_product_variant_option_values to get variant option display.
   *
   * Apply filters from request body:
   * - Filter by status if provided (exact match)
   * - Filter by date range if provided (created_at between start and end)
   * - Filter only items where product belongs to authenticated seller
   *
   * Return paginated results sorted by created_at descending (newest first).
   *
   * Calculate pagination metadata: total count, page, limit, total pages.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IEcommerceMallOrderItem.IRequest,
  ): Promise<IPageIEcommerceMallOrderItem.ISummary> {
    try {
      return await patchEcommerceMallSellerDashboardOrderItems({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
