import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallInventoryRecord } from "../../../../api/structures/IEcommerceMallInventoryRecord";
import { IPageIEcommerceMallInventoryRecord } from "../../../../api/structures/IPageIEcommerceMallInventoryRecord";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { patchEcommerceMallSellerInventories } from "../../../../providers/patchEcommerceMallSellerInventories";

@Controller("/ecommerceMall/seller/inventories")
export class EcommercemallSellerInventoriesController {
  /**
   * Retrieve a paginated list of inventory records with optional filtering.
   *
   * This endpoint provides access to the complete audit trail of inventory changes for product variants. Each record captures a quantity change event with its business reason and timestamp.
   *
   * Supports filtering by product variant, reason type, and date range. Results are sorted by timestamp in descending order (most recent first) to show latest changes first. Pagination ensures efficient retrieval of large datasets.
   *
   * Inventory records are immutable once created - the system never updates or deletes them to maintain complete audit integrity. Current stock quantity for any variant is derived by summing all inventory records for that variant.
   *
   * Use cases: Seller viewing inventory history for specific variants, administrators auditing stock changes, customer service representatives investigating stock-related disputes.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering inventory records
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query ecommerce_mall_inventory_records table with pagination and filtering.
   *
   * Filter criteria:
   * - ecommerce_mall_product_variant_id: UUID of the product variant to filter records
   * - reason: Business reason for inventory change (restock, order_placement, order_cancellation, refund, adjustment)
   * - from_date / to_date: Date range filter on created_at timestamp
   *
   * Sorting:
   * - Default: created_at descending (most recent first)
   *
   * Pagination:
   * - Standard cursor-based or offset pagination with page/limit parameters
   * - Default page size: 20 records
   * - Maximum page size: 100 records
   *
   * Join handling:
   * - Join with ecommerce_mall_product_variants to get variant details (sku_code, product_id)
   * - Join with ecommerce_mall_products to get product details (name, seller_id) for access control
   *
   * Access control:
   * - Sellers can only view inventory records for variants belonging to their products
   * - Admins can view all inventory records
   * - Guests cannot access this endpoint
   *
   * Response construction:
   * - For each record, include: id, variant_id, sku_code, product_id, product_name, quantity_change, reason, created_at
   * - Calculate current_stock by summing all records for the variant (include in variant summary if requested)
   *
   * Edge cases:
   * - If variant_id does not exist, return empty list
   * - If date range is invalid (from_date > to_date), return validation error
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IEcommerceMallInventoryRecord.IRequest,
  ): Promise<IPageIEcommerceMallInventoryRecord> {
    try {
      return await patchEcommerceMallSellerInventories({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
