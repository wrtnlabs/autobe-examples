import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallSeller } from "../../../../../api/structures/IEcommerceMallSeller";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { getEcommerceMallSellerSellerRejectionReason } from "../../../../../providers/getEcommerceMallSellerSellerRejectionReason";

@Controller("/ecommerceMall/seller/seller/rejection-reason")
export class EcommercemallSellerSellerRejection_reasonController {
  /**
   * Retrieves the rejection reason for the authenticated seller whose registration was rejected.
   *
   * When a seller's registration request is rejected by an administrator, this endpoint provides access to the rejection reason that explains why the request was denied. The response includes the rejection reason text and the timestamp when the rejection occurred.
   *
   * Sellers whose registration is pending or approved receive a response indicating no rejection reason is available. This endpoint helps rejected sellers understand what corrections or improvements are needed before submitting a new registration request.
   *
   * **Error Handling**: Returns 401 if the seller is not authenticated. Returns 404 if the seller account is not found.
   *
   * @param connection
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Retrieve the rejection reason for the
     *   authenticated seller from the ecommerce_mall_sellers table.
   *
   * 1. Extract seller ID from the authenticated session/JWT token.
   * 2. Query the ecommerce_mall_sellers table to find the seller by ID.
   * 3. Verify the seller's approval_status is 'rejected'.
   * 4. Return the rejection_reason and rejected_at fields.
   * 5. If approval_status is not 'rejected' (pending or approved), return null values for both fields.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async rejectionReason(
    @SellerAuth()
    seller: SellerPayload,
  ): Promise<IEcommerceMallSeller.IRejectionReason> {
    try {
      return await getEcommerceMallSellerSellerRejectionReason({
        seller,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
