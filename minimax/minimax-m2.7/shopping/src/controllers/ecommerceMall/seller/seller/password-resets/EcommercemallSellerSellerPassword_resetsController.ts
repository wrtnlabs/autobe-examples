import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallSellerPasswordReset } from "../../../../../api/structures/IEcommerceMallSellerPasswordReset";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { getEcommerceMallSellerSellerPasswordResetsResetId } from "../../../../../providers/getEcommerceMallSellerSellerPasswordResetsResetId";
import { patchEcommerceMallSellerSellerPasswordResets } from "../../../../../providers/patchEcommerceMallSellerSellerPasswordResets";

@Controller("/ecommerceMall/seller/seller/password-resets")
export class EcommercemallSellerSellerPassword_resetsController {
  /**
   * Reset seller password using a valid reset token.
   *
   * This endpoint allows sellers who have forgotten their password to set a new password by providing a valid reset token that was previously sent to their registered email address. The token must not be expired and must not have been previously used.
   *
   * The operation validates the token's expiration time and usage status before allowing the password change. Upon successful validation, the new password is set and the token is marked as used to prevent reuse. Sellers remain logged out after this operation and must log in with their new credentials.
   *
   * This differs from the change-password endpoint which requires the current password for verification.
   *
   * @param connection
   * @param body Password reset token received via email and new password
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Validate the reset token from request body against ecommerce_mall_seller_password_resets table.
   *
   * Verify token exists, has not been used (used_at is null), and has not expired (expires_at > current timestamp).
   *
   * If token is invalid, expired, or already used, reject the request with appropriate error.
   *
   * If token is valid, retrieve the associated seller (ecommerce_mall_seller_id) and update the seller's password in ecommerce_mall_sellers table with the hashed new password.
   *
   * Mark the reset token as used by setting used_at to current timestamp.
   *
   * Return success response. Do not return the new password or any token details in the response.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async invert(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IEcommerceMallSellerPasswordReset.IRequest,
  ): Promise<IEcommerceMallSellerPasswordReset.IResponse> {
    try {
      return await patchEcommerceMallSellerSellerPasswordResets({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve password reset record details by ID.
   *
   * This endpoint returns the details of a specific password reset request initiated by the seller. The response includes the reset token identifier, associated seller, expiration timestamp, and usage status.
   *
   * Sellers can only view password reset records that belong to their own account. The response indicates whether the token has expired and whether it has already been used. This information helps sellers track their password reset requests and identify issues with the reset flow.
   *
   * The reset token expires after a configurable time window (typically 24 hours). Sellers should initiate a new password reset if their token has expired.
   *
   * @param connection
   * @param resetId Unique identifier of the password reset record
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query the ecommerce_mall_seller_password_resets table using the provided resetId as the primary key.
   *
   * Verify that the authenticated seller owns the password reset record by comparing the ecommerce_mall_seller_id field with the authenticated seller ID. Reject with 403 Forbidden if the seller does not own the reset.
   *
   * Return the password reset record including: id, sellerId, token (for status display), expiresAt, usedAt, createdAt.
   *
   * Calculate derived status field: if used_at is not null, status is 'used'; if expires_at is before current time, status is 'expired'; otherwise status is 'pending'.
   *
   * Return 404 Not Found if the resetId does not exist in the database.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":resetId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("resetId")
    resetId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallSellerPasswordReset> {
    try {
      return await getEcommerceMallSellerSellerPasswordResetsResetId({
        seller,
        resetId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
