import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallSellerEmailVerification } from "../../../../../api/structures/IEcommerceMallSellerEmailVerification";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { getEcommerceMallSellerSellerEmailVerificationsVerificationId } from "../../../../../providers/getEcommerceMallSellerSellerEmailVerificationsVerificationId";
import { patchEcommerceMallSellerSellerEmailVerifications } from "../../../../../providers/patchEcommerceMallSellerSellerEmailVerifications";

@Controller("/ecommerceMall/seller/seller/email-verifications")
export class EcommercemallSellerSellerEmail_verificationsController {
  /**
   * Verify a seller email verification token.
   *
   * This endpoint verifies the email address for a seller account by confirming the verification token. Upon successful verification, the system marks the token as verified and links it to the seller's account.
   *
   * The verification token is sent to the seller's email address during registration. Tokens have an expiration time defined by expires_at, after which they become invalid.
   *
   * After successful verification, the seller's email verification status is updated, enabling the seller to proceed with account activation.
   *
   * This operation is used during the seller registration workflow where email verification is required before account activation.
   *
   * @param connection
   * @param body Email verification request containing the verification token
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query the ecommerce_mall_seller_email_verifications table to find a record matching the provided token.
   *
   * Validate that:
   * 1. The token exists in the database
   * 2. The token has not expired (current time < expires_at)
   * 3. The token has not already been verified (verified_at is null)
   *
   * If validation fails, return appropriate error:
   * - 404 if token not found
   * - 400 if token expired
   * - 400 if token already verified
   *
   * If validation passes:
   * 1. Update verified_at to current timestamp
   * 2. Return the updated verification record including id, email, verified_at, and expires_at
   *
   * The operation links to the ecommerce_mall_sellers table via ecommerce_mall_seller_id to associate the verification with the correct seller account.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async verify(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IEcommerceMallSellerEmailVerification.IRequest,
  ): Promise<IEcommerceMallSellerEmailVerification> {
    try {
      return await patchEcommerceMallSellerSellerEmailVerifications({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve email verification details for a seller account.
   *
   * This endpoint returns the verification status and details for a specific email verification token. Sellers receive a verification email after registering, and this endpoint allows checking whether the verification has been completed.
   *
   * The response includes the verification token status (pending/verified), associated seller information, and timestamps for when the verification was created and completed.
   *
   * @param connection
   * @param verificationId Unique identifier of the email verification token
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query ecommerce_mall_seller_email_verifications table using the provided verificationId. Return the verification record including status, associated seller reference, created_at timestamp, and verified_at timestamp if completed. Handle case where verification record does not exist - return 404 error. Verify the verificationId is a valid UUID format.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":verificationId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("verificationId")
    verificationId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallSellerEmailVerification> {
    try {
      return await getEcommerceMallSellerSellerEmailVerificationsVerificationId(
        {
          seller,
          verificationId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
