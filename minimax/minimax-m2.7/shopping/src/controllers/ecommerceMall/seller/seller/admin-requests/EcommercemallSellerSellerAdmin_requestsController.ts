import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallSellerAdminRequest } from "../../../../../api/structures/IEcommerceMallSellerAdminRequest";
import { IPageIEcommerceMallSellerAdminRequest } from "../../../../../api/structures/IPageIEcommerceMallSellerAdminRequest";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { getEcommerceMallSellerSellerAdminRequestsRequestId } from "../../../../../providers/getEcommerceMallSellerSellerAdminRequestsRequestId";
import { patchEcommerceMallSellerSellerAdminRequests } from "../../../../../providers/patchEcommerceMallSellerSellerAdminRequests";
import { postEcommerceMallSellerSellerAdminRequests } from "../../../../../providers/postEcommerceMallSellerSellerAdminRequests";

@Controller("/ecommerceMall/seller/seller/admin-requests")
export class EcommercemallSellerSellerAdmin_requestsController {
  /**
   * Submit a request to become an administrator on the platform.
   *
   * This endpoint allows sellers to request administrative privileges by providing a reason explaining why they need admin access. The request is submitted with a 'pending' status and becomes available for review by super administrators.
   *
   * The seller making this request must be authenticated as a seller actor. The seller ID is automatically extracted from the authenticated session and associated with this request. Sellers can only have one active admin request at a time (enforced by unique constraint on seller_id).
   *
   * Super administrators can view all pending requests and approve or reject them with reasons. When approved, the seller's admin request status changes to 'approved'. When rejected, a rejection reason must be provided by the super administrator.
   *
   * Related operations:
   * - GET /seller/admin-requests - List own admin requests and their statuses
   * - Super admin endpoints for approval/rejection workflow
   *
   * @param connection
   * @param body Reason for requesting administrative privileges
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Implement the following steps:
   *
   * 1. Extract seller ID from authenticated session token (seller context)
   * 2. Validate that seller does not have an existing pending admin request (check for active request with same seller_id and status='pending')
   * 3. If pending request exists, return conflict error
   * 4. Validate request body: reason field must be non-empty string with minimum length
   * 5. Create new record in ecommerce_mall_seller_admin_requests table:
   *    - id: auto-generated UUID
   *    - ecommerce_mall_seller_id: extracted from session
   *    - reason: from request body
   *    - status: 'pending'
   *    - reviewed_by_super_admin_id: null
   *    - rejection_reason: null
   *    - created_at: current timestamp
   *    - updated_at: current timestamp
   *    - deleted_at: null
   * 6. Return the created admin request record with all fields
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IEcommerceMallSellerAdminRequest.ICreate,
  ): Promise<IEcommerceMallSellerAdminRequest> {
    try {
      return await postEcommerceMallSellerSellerAdminRequests({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a paginated list of admin privilege requests submitted by the authenticated seller.
   *
   * This endpoint allows sellers to view their own history of admin privilege requests. Each request includes the submission date, current status (pending, approved, or rejected), the requested privilege grade, and any rejection reason if applicable.
   *
   * The seller can filter results by status to focus on pending requests awaiting review or previously rejected requests. Results are sorted by creation date with newest first by default.
   *
   * Only the authenticated seller's own requests are accessible. Sellers cannot view requests submitted by other sellers. The response includes summary information optimized for list displays, showing request status, grade requested, and submission timestamp.
   *
   * Related operations:
   * - POST /auth/admin/request: Submit a new admin privilege request
   * - GET /auth/admin/approval-status: Get current approval status
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering admin requests
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query ecommerce_mall_seller_admin_requests table filtering by the authenticated seller's ID.
   *
   * 1. Extract seller ID from authenticated session
   * 2. Apply optional status filter from request body (pending, approved, rejected)
   * 3. Apply pagination parameters (page, limit)
   * 4. Order by created_at descending (newest first)
   * 5. Return paginated results with request summary: id, requested_grade, status, reason, created_at, rejection_reason (if any)
   * 6. Exclude soft-deleted records (where deleted_at is not null)
   * 7. Return IPageIEcommerceMallSellerAdminRequest.ISummary format
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IEcommerceMallSellerAdminRequest.IRequest,
  ): Promise<IPageIEcommerceMallSellerAdminRequest.ISummary> {
    try {
      return await patchEcommerceMallSellerSellerAdminRequests({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific seller admin privilege request by its unique identifier.
   *
   * This endpoint allows authenticated sellers to view the details of an admin privilege request they submitted. The response includes the request status (pending, approved, or rejected), the reason provided during submission, and any rejection reason if the request was denied by a super administrator.
   *
   * The seller can only access their own admin requests. If the request does not belong to the authenticated seller, the system returns a not found error for security reasons (preventing enumeration of other users' requests).
   *
   * Timestamps for submission and last modification are included for reference. Soft-deleted requests are not accessible through this endpoint.
   *
   * @param connection
   * @param requestId Unique identifier of the admin request
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query the ecommerce_mall_seller_admin_requests table using the provided requestId as the primary key. Verify the request belongs to the authenticated seller via session. If not found or belongs to another seller, return 404. Return all fields including reason, status, rejection_reason, created_at, and updated_at. Exclude soft-deleted requests where deleted_at is not null.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":requestId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("requestId")
    requestId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallSellerAdminRequest> {
    try {
      return await getEcommerceMallSellerSellerAdminRequestsRequestId({
        seller,
        requestId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
