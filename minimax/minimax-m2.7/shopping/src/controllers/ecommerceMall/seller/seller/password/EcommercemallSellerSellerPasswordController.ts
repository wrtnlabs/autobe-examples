import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallSeller } from "../../../../../api/structures/IEcommerceMallSeller";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { putEcommerceMallSellerSellerPassword } from "../../../../../providers/putEcommerceMallSellerSellerPassword";

@Controller("/ecommerceMall/seller/seller/password")
export class EcommercemallSellerSellerPasswordController {
  /**
   * Allows authenticated sellers to change their account password.
   *
   * Sellers can update their password at any time through this endpoint. The operation requires verification of the current password before accepting the new password. Upon successful password change, the seller remains logged in and can continue using the platform with the updated credentials.
   *
   * **Request Validation**: The current password must match the stored password hash. If verification fails, the request is rejected with an authentication error. The new password must meet the platform's minimum security requirements for password strength.
   *
   * **Security**: Passwords are hashed using bcrypt before storage. The system never stores or returns plaintext passwords.
   *
   * @param connection
   * @param body Password change request containing the current password for verification and the new password to set.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification 1. Extract authenticated seller from request
     *   context (JWT token validated by auth middleware) 2. Validate request
     *   body contains 'currentPassword' and 'newPassword' fields 3. Retrieve
     *   seller record from ecommerce_mall_sellers table by authenticated seller
     *   ID 4. Verify currentPassword matches stored password_hash using bcrypt
     *   comparison 5. If verification fails, return 401 Unauthorized with error
     *   message 6. Validate newPassword meets platform requirements (minimum
     *   length, complexity rules) 7. If validation fails, return 400 Bad
     *   Request with validation errors 8. Hash newPassword using bcrypt with
     *   appropriate cost factor 9. Update password_hash field in
     *   ecommerce_mall_sellers table 10. Update updated_at timestamp 11. Return
     *   204 No Content on success (seller stays logged in)
   *
   * Edge cases:
   * - Seller account is suspended: return 403 Forbidden
   * - Seller account is soft-deleted (deleted_at not null): return 403 Forbidden
   * - Concurrent password change attempts: use database transaction with row-level locking
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IEcommerceMallSeller.IPasswordChange,
  ): Promise<void> {
    try {
      return await putEcommerceMallSellerSellerPassword({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
