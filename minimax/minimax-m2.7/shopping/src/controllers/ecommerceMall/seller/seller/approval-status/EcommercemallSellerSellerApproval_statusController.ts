import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallSellerApproval } from "../../../../../api/structures/IEcommerceMallSellerApproval";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { getEcommerceMallSellerSellerApprovalStatus } from "../../../../../providers/getEcommerceMallSellerSellerApprovalStatus";

@Controller("/ecommerceMall/seller/seller/approval-status")
export class EcommercemallSellerSellerApproval_statusController {
  /**
   * Retrieves the current approval status of the authenticated seller account.
   *
   * The status indicates whether the seller registration is pending administrator review, approved for selling, or rejected with a reason. Sellers can check this endpoint at any time to monitor their registration application status.
   *
   * **Status Values:**
   * - `pending`: Registration is awaiting administrator review
   * - `approved`: Seller can list products and process orders
   * - `rejected`: Registration was denied; `rejectionReason` contains the reason
   *
   * **Error Handling:**
   * - 401 Unauthorized: Invalid or missing authentication token
   * - 404 Not Found: Seller account not found
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification 1. Extract authenticated seller ID from JWT token in Authorization header
   * 2. Query the ecommerce_mall_sellers table using the seller ID
   * 3. Validate seller exists and is not deleted (deleted_at IS NULL)
   * 4. Return the approval_status field along with rejection_reason and rejected_at if status is 'rejected'
   * 5. Include recent approval history from ecommerce_mall_seller_approvals table showing status progression
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @SellerAuth()
    seller: SellerPayload,
  ): Promise<IEcommerceMallSellerApproval> {
    try {
      return await getEcommerceMallSellerSellerApprovalStatus({
        seller,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
