import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallSellerSession } from "../../../../../api/structures/IEcommerceMallSellerSession";
import { IPageIEcommerceMallSellerSession } from "../../../../../api/structures/IPageIEcommerceMallSellerSession";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { getEcommerceMallSellerSellerSessionsSessionId } from "../../../../../providers/getEcommerceMallSellerSellerSessionsSessionId";
import { patchEcommerceMallSellerSellerSessions } from "../../../../../providers/patchEcommerceMallSellerSellerSessions";

@Controller("/ecommerceMall/seller/seller/sessions")
export class EcommercemallSellerSellerSessionsController {
  /**
   * Retrieves a paginated list of the authenticated seller's active sessions.
   *
   * This endpoint allows sellers to view and manage their login sessions across multiple devices or browsers. Each session record includes client metadata such as IP address, browser referrer, and session creation/expiration timestamps.
   *
   * **Session Information Displayed:**
   * - Session identifier and creation timestamp
   * - Client IP address and browser referrer information
   * - Session expiration status and remaining validity period
   * - Access and refresh token status (active/expired)
   *
   * **Use Cases:**
   * - Review login history across devices
   * - Identify suspicious or unknown sessions
   * - Monitor active session count for security awareness
   * - Track session activity patterns
   *
   * **Filtering Options:**
   * - Filter by session status (active/expired)
   * - Filter by IP address or IP range
   * - Filter by creation date range
   * - Filter by expiration status
   *
   * **Security Considerations:**
   * - Only the authenticated seller's own sessions are accessible
   * - Session tokens are masked in responses
   * - Expired sessions are clearly marked
   *
   * @param connection
   * @param body Search criteria for filtering seller sessions including optional filters for IP address, session status, creation date range, and pagination parameters.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query ecommerce_mall_seller_sessions table filtering by the authenticated seller's ID (from session context).
   *
   * 1. Extract seller ID from the authenticated session JWT token.
   * 2. Query seller_sessions table with seller_id as primary filter.
   * 3. Apply optional filters from request body: ip address, href path, referrer, created_at range, expired_at status.
   * 4. Return paginated results sorted by created_at descending (newest first).
   * 5. Include session metadata: id, ip, href, referrer, created_at, expired_at.
   * 6. Mask or omit sensitive token information in responses.
   * 7. Calculate and include session status (active/expired) based on expired_at comparison with current time.
   * 8. Return cursor-based pagination for efficient browsing of large session histories.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IEcommerceMallSellerSession.IRequest,
  ): Promise<IPageIEcommerceMallSellerSession.ISummary> {
    try {
      return await patchEcommerceMallSellerSellerSessions({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves a specific seller session by its unique identifier.
   *
   * This endpoint returns detailed information about a seller session including the client metadata (IP address, request URL, referrer), token status (access token presence), and session lifecycle timestamps.
   *
   * The session must belong to the authenticated seller making the request, unless accessed by an administrator. The response includes all session metadata useful for security monitoring and session management.
   *
   * **Session Details**: The response includes the session creation time, expiration time, client IP address, request URL, and HTTP referrer header. Token fields indicate whether the session has active access or refresh tokens.
   *
   * **Error Handling**: Returns 404 if the session is not found. Returns 403 if the session does not belong to the authenticated user. Returns 401 for invalid or expired authentication.
   *
   * @param connection
   * @param sessionId Unique identifier of the seller session to retrieve.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query the ecommerce_mall_seller_sessions table using the provided sessionId as the primary key.
   *
   * Validate that the session exists and retrieve all associated fields: id, ecommerce_mall_seller_id, ip, href, referrer, access_token, refresh_token, created_at, expired_at.
   *
   * Join with ecommerce_mall_sellers table to verify session ownership if the requester is a seller (not an admin).
   *
   * If the session has expired (expired_at < current time), return appropriate status indicating expired session.
   *
   * Return the complete session entity with all metadata. Mask or exclude sensitive token values in the response if required by security policy.
   *
   * Handle errors: NOT_FOUND for invalid sessionId, FORBIDDEN for unauthorized access, UNAUTHORIZED for invalid tokens.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallSellerSession> {
    try {
      return await getEcommerceMallSellerSellerSessionsSessionId({
        seller,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
