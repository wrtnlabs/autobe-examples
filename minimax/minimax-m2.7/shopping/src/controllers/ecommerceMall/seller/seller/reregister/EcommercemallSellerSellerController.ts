import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallSeller } from "../../../../../api/structures/IEcommerceMallSeller";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { postEcommerceMallSellerSellerReregister } from "../../../../../providers/postEcommerceMallSellerSellerReregister";

@Controller("/ecommerceMall/seller/seller/reregister")
export class EcommercemallSellerSellerController {
  /**
   * Allows sellers whose registration was previously rejected to submit a new registration request.
   *
   * This endpoint is used when a seller wants to reapply after their initial registration was denied by an administrator. The seller must provide their credentials (email and password) to authenticate and initiate a fresh approval workflow.
   *
   * **Authentication Flow**:
   * 1. Validate the provided email and password against the seller's stored credentials
   * 2. Verify the seller account exists and is in 'rejected' status
   * 3. Reset the seller's approval_status to 'pending'
   * 4. Create a new seller approval record to start the review workflow
   * 5. Generate new JWT tokens for the authenticated session
   *
   * **Business Rules**:
   * - Only sellers with 'rejected' status can use this endpoint
   * - Sellers with 'pending' or 'approved' status receive an error
   * - A new approval record is created each time a seller resubmits
   * - The rejection_reason from the previous rejection is preserved in history
   *
   * **Error Handling**:
   * - Invalid credentials return 401 Unauthorized
   * - Seller not in 'rejected' status returns 400 Bad Request
   * - Seller account deleted returns 404 Not Found
   *
   * @param connection
   * @param body Seller credentials for authentication and registration resubmission. Email must match an existing rejected seller account.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Validate the seller's email and password using bcrypt comparison against the stored password_hash in ecommerce_mall_sellers table.
   *
   * Verify the seller exists by email lookup. Return 404 if no seller found.
   *
   * Check the approval_status field in ecommerce_mall_sellers:
   * - If status is 'rejected': Proceed with reregistration
   * - If status is 'pending': Return 400 with message 'Registration already pending'
   * - If status is 'approved': Return 400 with message 'Registration already approved'
   *
   * For rejected sellers:
   * 1. Update the seller's approval_status to 'pending' in ecommerce_mall_sellers
   * 2. Clear the rejected_at timestamp and rejection_reason from the seller record
   * 3. Create a new record in ecommerce_mall_seller_approvals table with:
   *    - status: 'pending'
   *    - reviewed_by_admin_id: null
   *    - rejection_reason: null
   *    - created_at: current timestamp
   *    - updated_at: current timestamp
   * 4. Generate JWT access token and refresh token for the seller session
   * 5. Store session in ecommerce_mall_seller_sessions table
   *
   * Return the seller information including:
   * - id, email, approval_status
   * - New JWT access token and refresh token
   * - Timestamp of the new registration submission
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async reregister(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IEcommerceMallSeller.ICreate,
  ): Promise<IEcommerceMallSeller.IReregisterResponse> {
    try {
      return await postEcommerceMallSellerSellerReregister({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
