  /**
   * Retrieves a specific product snapshot for sellers to view the complete product state at a historical point in time.
   *
   * Sellers can view snapshots of their own products to track modification history and resolve disputes with customers. The response includes all product fields, variant information with option values, and image URLs as they existed when the snapshot was created.
   *
   * **Access Control**: Only the seller who owns the product can view its snapshots. The system validates that the requesting seller matches the snapshot's ecommerce_mall_seller_id.
   *
   * **Response Contents**: Returns the complete snapshot data including name, description, base price, category name, creation timestamp, all product variants with their SKU codes, price overrides, stock quantities, and option key-value pairs, as well as all product images with their URLs and display order.
   *
   * **Error Handling**: Returns 403 if the seller does not own the product. Returns 404 if the product or snapshot does not exist.
   *
   * @param connection
   * @param productId UUID of the product whose snapshot is being retrieved (global scope).
   * @param snapshotId UUID of the product snapshot to retrieve (global scope).
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Query the ecommerce_mall_product_snapshots table
     *   filtering by id equal to snapshotId and ecommerce_mall_product_id equal
     *   to productId. Validate that the snapshot's ecommerce_mall_seller_id
     *   matches the authenticated seller's ID. If validation fails, return 403
     *   Forbidden.
   *
   * Join with ecommerce_mall_product_snapshot_variants using snapshot ID to retrieve all variants. For each variant, join with ecommerce_mall_product_snapshot_variant_option_values to retrieve option key-value pairs. Join with ecommerce_mall_product_snapshot_images to retrieve all images ordered by display_order.
   *
   * Return the complete snapshot with nested variants array (each containing optionValues array) and images array. Order variants by created_at for consistency.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
