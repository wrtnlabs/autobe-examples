import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallSellerApproval } from "../../../../../../api/structures/IEcommerceMallSellerApproval";
import { IPageIEcommerceMallSellerApproval } from "../../../../../../api/structures/IPageIEcommerceMallSellerApproval";
import { SellerAuth } from "../../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../../decorators/payload/SellerPayload";
import { getEcommerceMallSellerSellersMeApprovalsApprovalId } from "../../../../../../providers/getEcommerceMallSellerSellersMeApprovalsApprovalId";
import { patchEcommerceMallSellerSellersMeApprovals } from "../../../../../../providers/patchEcommerceMallSellerSellersMeApprovals";

@Controller("/ecommerceMall/seller/sellers/me/approvals")
export class EcommercemallSellerSellersMeApprovalsController {
  /**
   * Retrieves the list of approval records for the authenticated seller.
   *
   * This endpoint allows sellers to view their complete approval history, including initial submissions and any resubmissions after rejection. Each approval record shows the status, review timestamp, and rejection reason if applicable.
   *
   * Sellers can filter by status (pending, approved, rejected) and date range to find specific records. Results are paginated with newest records appearing first by default.
   *
   * **Authentication**: Requires valid seller session token.
   *
   * **Error Handling**: Returns 401 if not authenticated as a seller.
   *
   * @param connection
   * @param body Search criteria including optional status filter, date range filters, and pagination parameters.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Query ecommerce_mall_seller_approvals table
     *   filtering by the authenticated seller's ID from session context.
   *
   * Apply search filters from request body:
   * - Filter by status: pending, approved, or rejected
   * - Filter by date range using created_at boundaries
   *
   * Sort results by created_at descending (newest first).
   *
   * Implement pagination with page, limit parameters. Default page 1, limit 20.
   *
   * Join with ecommerce_mall_admins table to include reviewer information (admin email) when available.
   *
   * Return paginated results with total count and page metadata.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IEcommerceMallSellerApproval.IRequest,
  ): Promise<IPageIEcommerceMallSellerApproval.ISummary> {
    try {
      return await patchEcommerceMallSellerSellersMeApprovals({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves a specific seller approval record by its unique identifier.
   *
   * This endpoint allows authenticated sellers to view details of their own approval records. Each approval record contains the current approval status (pending, approved, or rejected), the reviewing administrator reference if reviewed, any rejection reason if the status is rejected, and timestamps for creation and last update.
   *
   * **Status Values**
   * - pending: The approval request is awaiting administrator review
   * - approved: The registration has been approved by an administrator
   * - rejected: The registration was denied with a provided rejection reason
   *
   * **Response Details**
   * The response includes the full approval record including the status, rejection reason if applicable, and administrator who reviewed the request.
   *
   * **Error Handling**
   * Returns 404 if the approval record does not exist or does not belong to the authenticated seller.
   *
   * @param connection
   * @param approvalId Unique identifier of the seller approval record (global scope)
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Query the ecommerce_mall_seller_approvals table
     *   using the provided approvalId.
   *
   * Verify that the approval record belongs to the authenticated seller by comparing ecommerce_mall_seller_id with the seller's ID from the session.
   *
   * Return the full approval record including: id, ecommerce_mall_seller_id, reviewed_by_admin_id, status, rejection_reason, created_at, updated_at.
   *
   * If the approval record is not found or does not belong to the seller, return 404 error.
   *
   * Include related seller information and reviewedByAdmin details in the response if available.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":approvalId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("approvalId")
    approvalId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallSellerApproval> {
    try {
      return await getEcommerceMallSellerSellersMeApprovalsApprovalId({
        seller,
        approvalId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
