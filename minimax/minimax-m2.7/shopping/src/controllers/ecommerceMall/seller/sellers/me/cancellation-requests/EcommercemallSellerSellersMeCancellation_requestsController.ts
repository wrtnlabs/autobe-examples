  /**
   * Approves a pending cancellation request from a customer for an order item with 'paid' status.
   *
   * When a seller approves a cancellation request, the system creates an immutable snapshot of the request state (reason and status) for audit purposes, updates the cancellation request status to 'approved', and changes the order item status to 'cancelled'. The seller can only approve cancellation requests for order items they own that currently have a 'paid' status. Items that have already shipped or been delivered cannot be cancelled through this endpoint - customers must use the refund process for those cases.
   *
   * This operation is idempotent: approving an already-approved request returns the current state without error. However, attempting to approve a rejected request will result in an error.
   *
   * @param connection
   * @param requestId Unique identifier of the cancellation request to approve.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Implement the seller cancellation request
     *   approval flow:
   *
   * 1. Extract `requestId` from path parameter
   * 2. Query `ecommerce_mall_cancellation_requests` table to find the cancellation request by id
   * 3. Validate the cancellation request exists - return 404 if not found
   * 4. Validate the cancellation request status is 'pending' - return 400 if already approved or rejected
   * 5. Verify the authenticated seller owns this cancellation request (match seller_id) - return 403 if not authorized
   * 6. Query `ecommerce_mall_order_items` table to get the associated order item and validate its status is 'paid' - return 400 if order item status is 'shipped', 'delivered', 'cancelled', or 'refunded'
   * 7. Begin database transaction:
   *    a. Update `ecommerce_mall_cancellation_requests` status to 'approved' and updated_at to current timestamp
   *    b. Create new record in `ecommerce_mall_cancellation_request_snapshots` with id (UUID), ecommerce_mall_cancellation_request_id, reason (copy from request), status ('approved'), created_at (current timestamp)
   *    c. Update `ecommerce_mall_order_items` status to 'cancelled' and updated_at to current timestamp
   * 8. Commit transaction
   * 9. Return the updated cancellation request object with all fields including the snapshot relationship
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post(":requestId/approve")
  public async approve(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("requestId")
    requestId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallCancellationRequest> {
    try {
      return await postEcommerceMallSellerSellersMeCancellationRequestsRequestIdApprove(
        {
          seller,
          requestId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Rejects a pending cancellation request from a customer.
   *
   * The seller reviews the cancellation request details including the reason provided by the customer and decides whether to approve or reject the cancellation. When rejected, the cancellation request status changes to 'rejected' and a snapshot is automatically created preserving the current state of the request for audit purposes.
   *
   * **Workflow Effects:**
   * - Cancellation request status changes from 'pending' to 'rejected'
   * - A snapshot record is created with the reason and status at rejection time
   * - The associated order item remains in 'paid' status and continues processing
   * - The customer receives notification of the rejection
   *
   * **Error Handling:**
   * - Returns 404 if the cancellation request does not exist
   * - Returns 403 if the seller does not own this cancellation request
   * - Returns 400 if the cancellation request is not in 'pending' status
   * - Returns 400 if the associated order item is not in 'paid' status
   *
   * @param connection
   * @param requestId Unique identifier of the cancellation request to reject.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Retrieve the cancellation request by requestId
     *   from ecommerce_mall_cancellation_requests table. Validate that the
     *   authenticated seller owns this request (ecommerce_mall_seller_id
     *   matches authenticated seller). Validate that status is 'pending'.
     *   Validate that the associated order item (via
     *   ecommerce_mall_order_item_id) has status 'paid'.
   *
   * If all validations pass:
   * 1. Update status to 'rejected' and update updated_at timestamp
   * 2. Create a new record in ecommerce_mall_cancellation_request_snapshots with:
   *    - id: generate new UUID
   *    - ecommerce_mall_cancellation_request_id: the request's id
   *    - reason: copy from cancellation request
   *    - status: 'rejected'
   *    - created_at: current timestamp
   * 3. Return the updated cancellation request with its associated snapshots
   *
   * If any validation fails, return appropriate error response.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post(":requestId/reject")
  public async reject(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("requestId")
    requestId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallCancellationRequest> {
    try {
      return await postEcommerceMallSellerSellersMeCancellationRequestsRequestIdReject(
        {
          seller,
          requestId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
