  /**
   * Deletes a product owned by the authenticated seller.
   *
   * This operation performs a soft delete, removing the product from search results and category listings while preserving order history through snapshots. The deletion is only allowed when there are no pending order items (with 'paid' or 'shipped' status) associated with the product.
   *
   * **Ownership Verification**: Only the seller who created the product can delete it. Requests for products not owned by the authenticated seller are rejected.
   *
   * **Deletion Conditions**: The product cannot be deleted if any order item for this product has a status of 'paid' or 'shipped'. Sellers must wait until all such order items reach 'delivered', 'cancelled', or 'refunded' status.
   *
   * **Soft Delete Behavior**: Upon successful deletion, the product's deleted_at timestamp is set, hiding it from search results and category listings. All product snapshots remain accessible for historical reference and dispute resolution.
   *
   * @param connection
   * @param productId Unique identifier of the product to delete (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification 1. Extract productId from path parameter
   * 2. Retrieve the authenticated seller ID from the session/token
   * 3. Query ecommerce_mall_products table to verify the product exists and belongs to the authenticated seller
   *    - If product not found: throw 404 error
   *    - If product does not belong to seller: throw 403 forbidden error
   * 4. Query ecommerce_mall_order_items table to check for any order items with status 'paid' or 'shipped' for this product
   *    - Join with ecommerce_mall_products to filter by the product being deleted
   *    - If any pending order items found: throw 409 conflict error with message indicating pending orders block deletion
   * 5. If no pending orders:
   *    - Set deleted_at to current timestamp on the product record
   *    - Do NOT physically delete the record (soft delete)
   *    - Product will no longer appear in search results or category listings
   * 6. Return success response (204 No Content)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
