@Controller("/ecommerceMall/seller/sellers/me/products/:productId/images")
export class EcommercemallSellerSellersMeProductsImagesController {
  /**
   * Upload a new image to a product.
   *
   * Sellers can add images to showcase different views, angles, and details of their products. Each product supports up to 10 images. The first uploaded image automatically becomes the main thumbnail, appearing first in the product gallery and search results.
   *
   * **Image Upload Process**
   * The seller provides an image URL pointing to a pre-uploaded file. The system validates the URL format and associates the image with the specified product. A new display order is automatically assigned based on the current image count, placing new uploads at the end of the gallery.
   *
   * **Thumbnail Management**
   * When uploading to a product with no existing images, the uploaded image becomes the main thumbnail (display_order = 0). Subsequent uploads are appended to the gallery in chronological order.
   *
   * **Validation Rules**
   * - Maximum 10 images per product (returns 400 if limit exceeded)
   * - Product must exist and belong to the authenticated seller
   * - Image URL must be a valid URI format
   * - Seller cannot upload images to another seller's product
   *
   * @param connection
   * @param productId Unique identifier of the product to upload the image to.
   * @param body The image URL and optional metadata for the new product image.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification 1. Extract authenticated seller from JWT token.
   * 2. Validate productId is a valid UUID format.
   * 3. Query ecommerce_mall_products to verify product exists and ecommerce_mall_seller_id matches authenticated seller. Return 404 if product not found, 403 if product belongs to another seller.
   * 4. Query existing images in ecommerce_mall_product_images for the product to check count. Return 400 if count >= 10.
   * 5. Validate imageUrl from request body is a non-empty valid URI string.
   * 6. Determine display_order: if no existing images, set to 0 (main thumbnail); otherwise, set to max(existing display_order) + 1.
   * 7. Insert new record into ecommerce_mall_product_images with:
   *    - id: generate UUID
   *    - product_id: from path parameter
   *    - image_url: from request body
   *    - display_order: calculated above
   *    - created_at: current timestamp
   *    - updated_at: current timestamp
   * 8. Return the created image record with 201 status.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceMallProductImage.ICreate,
  ): Promise<IEcommerceMallProductImage> {
    try {
      return await postEcommerceMallSellerSellersMeProductsProductIdImages({
        seller,
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Reorder product images to change their display sequence.
   *
   * Sellers can change the display order of images for their products by providing an ordered array of image IDs. The first image in the array becomes the new main thumbnail. Display order updates are immediate and affect product listings, search results thumbnails, and the product detail page gallery.
   *
   * **Image Reordering**: The request body contains the complete list of image IDs in the desired display order. The system recalculates display_order values for all affected images based on their position in the array.
   *
   * **Validation**: All image IDs must belong to the specified product. Sellers can only reorder images for their own products. The product must exist and belong to the authenticated seller.
   *
   * **Error Handling**: Returns 404 if the product does not exist. Returns 403 if the seller does not own the product. Returns 400 if any image ID does not belong to the product.
   *
   * @param connection
   * @param productId Unique identifier of the product whose images are being reordered.
   * @param body Array of image IDs in desired display order. First ID becomes the main thumbnail (display_order=0).
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query the ecommerce_mall_product_images table filtered by product_id matching {productId} and verify ownership through ecommerce_mall_products table (join on product_id, check ecommerce_mall_seller_id matches authenticated seller).
   *
   * Parse the imageIds array from request body, which contains image IDs in desired display order (index 0 = first position).
   *
   * Validate that all imageIds exist and belong to the specified product. If validation fails, throw error with appropriate status code.
   *
   * Within a database transaction, update display_order for each image: for each image ID at index i in the array, set display_order = i.
   *
   * Return all product images ordered by display_order ascending.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async update(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceMallProductImage.IReorderRequest,
  ): Promise<IEcommerceMallProductImage> {
    try {
      return await patchEcommerceMallSellerSellersMeProductsProductIdImages({
        seller,
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Deletes a product image from the seller's product.
   *
   * This endpoint permanently removes a single image from a product's image gallery. Only the seller who owns the product can delete its images. When the main thumbnail image (display_order=0) is deleted, the system automatically promotes the next image in sequence to become the new main thumbnail. If all images are deleted, the product will display a placeholder image.
   *
   * **Ownership Enforcement**: The seller must own the product. If the product belongs to another seller, the operation returns 403 Forbidden.
   *
   * **Main Thumbnail Promotion**: When deleting the first image, the system reorders remaining images so the previously second image becomes the new first image.
   *
   * **Admin Override**: Administrators can delete any product image without ownership check.
   *
   * **Permanent Action**: Image deletion cannot be undone. Deleted images are immediately removed from product listings.
   *
   * @param connection
   * @param productId Unique identifier of the product containing the image.
   * @param imageId Unique identifier of the image to delete.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification 1. Extract seller ID from authenticated session JWT token.
   * 2. Extract productId and imageId from path parameters.
   * 3. Verify the image exists and belongs to the specified product by querying ecommerce_mall_product_images table.
   * 4. Verify the product belongs to the authenticated seller by checking ecommerce_mall_products.ecommerce_mall_seller_id matches the session seller.
   * 5. If seller does not own the product, return 403 Forbidden with message "You do not have permission to delete images from this product".
   * 6. Check if this image is the main thumbnail (display_order=0).
   * 7. Delete the image record from ecommerce_mall_product_images table.
   * 8. If deleted image was the main thumbnail (display_order=0) and other images exist for this product:
   *    - Find the image with the lowest display_order greater than 0
   *    - Update its display_order to 0
   *    - Reorder any remaining images to close the gap
   * 9. Return null response body with 204 No Content status.
   *
   * Edge Cases:
   * - If image does not exist, return 404 Not Found.
   * - If product does not exist, return 404 Not Found.
   * - If deleting the last image, product will have zero images (placeholder shown).
   * - Transaction should ensure atomic deletion and reordering.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":imageId")
  public async erase(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedParam("imageId")
    imageId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteEcommerceMallSellerSellersMeProductsProductIdImagesImageId(
        {
          seller,
          productId,
          imageId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Reorders product images by assigning new display positions to selected images.
   *
   * Sellers can change which image appears as the main thumbnail by moving it to position one. When reordering occurs, the system automatically reassigns display order values to maintain sequential numbering without gaps.
   *
   * **Ownership Restriction**: Only the seller who owns the product can reorder its images. The system validates that the authenticated seller is the product owner before processing the reorder request.
   *
   * **Main Thumbnail Logic**: The image moved to display order 1 automatically becomes the main thumbnail, which appears in product listings and search results.
   *
   * **Validation Rules**: The system validates that all image IDs belong to the specified product and that the new display order values are positive integers without duplicates.
   *
   * @param connection
   * @param productId Unique identifier of the product whose images will be reordered
   * @param body Array of image IDs with their new display order positions. The system will renumber all product images sequentially based on these assignments.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Implement image reordering for seller products:
   *
   * 1. **Authentication**: Extract seller ID from authenticated session (JWT token validation)
   *
   * 2. **Ownership Validation**: Query ecommerce_mall_products table to verify the product exists and belongs to the authenticated seller. If product not found or seller mismatch, return 404 or 403 error.
   *
   * 3. **Request Validation**:
   *    - Validate productId is a valid UUID format
   *    - Validate reorderItems array is not empty
   *    - Each item must have valid imageId (UUID) and newDisplayOrder (positive integer)
   *    - All imageIds must exist and belong to the specified product
   *
   * 4. **Conflict Detection**: Before applying changes, check that the new display order values would not create duplicates among the product's images.
   *
   * 5. **Atomic Reordering**: Use a database transaction to:
   *    - First, shift existing images to temporary positions (e.g., add 10000 to all) to avoid unique constraint conflicts
   *    - Then, assign the new display order values to each image
   *    - Commit all changes atomically
   *
   * 6. **Automatic Rebalancing**: After assigning new positions, renumber all images for the product sequentially starting from 1 to maintain gapless ordering.
   *
   * 7. **Main Thumbnail Update**: If any image is moved to position 1, it automatically becomes the main thumbnail displayed in listings.
   *
   * 8. **Response**: Return 204 No Content on success with no response body.
   *
   * **Edge Cases**:
   * - Empty reorderItems array: Return 400 Bad Request
   * - Invalid imageId: Return 404 Not Found
   * - Duplicate display order values: Return 409 Conflict
   * - Negative or zero display order: Return 400 Bad Request
   * - Product with no images: Return 400 Bad Request
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch("reorder")
  public async reorder(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceMallProductImage.IReorder,
  ): Promise<void> {
    try {
      return await patchEcommerceMallSellerSellersMeProductsProductIdImagesReorder(
        {
          seller,
          productId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
