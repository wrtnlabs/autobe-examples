import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallSellerDashboard } from "../../../../../../api/structures/IEcommerceMallSellerDashboard";
import { SellerAuth } from "../../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../../decorators/payload/SellerPayload";
import { getEcommerceMallSellerSellersMeDashboard } from "../../../../../../providers/getEcommerceMallSellerSellersMeDashboard";

@Controller("/ecommerceMall/seller/sellers/me/dashboard")
export class EcommercemallSellerSellersMeDashboardController {
  /**
   * Retrieves a summary dashboard of the authenticated seller's shop performance.
   *
   * The dashboard provides an at-a-glance view of key metrics including the total number of products listed, the total count of order items across all orders containing the seller's products, the number of cancellation requests awaiting seller response, and the number of refund requests awaiting seller response.
   *
   * **Authentication**: Requires valid seller session JWT token. Suspended sellers cannot access the dashboard.
   *
   * **Response Data**:
   * - `totalProducts`: Count of active products listed by the seller
   * - `totalOrderItems`: Count of all order items containing the seller's products across all orders
   * - `pendingCancellationRequests`: Count of cancellation requests with 'pending' status requiring seller action
   * - `pendingRefundRequests`: Count of refund requests with 'pending' status requiring seller action
   *
   * @param connection
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Query the authenticated seller's session to
     *   obtain the seller ID from the JWT token.
   *
   * Aggregate statistics:
   * 1. Count products where ecommerce_mall_seller_id matches the authenticated seller ID and deleted_at IS NULL
   * 2. Count order items by joining ecommerce_mall_order_items -> ecommerce_mall_products -> ecommerce_mall_sellers WHERE seller_id matches authenticated seller
   * 3. Count cancellation requests with status = 'pending' AND ecommerce_mall_seller_id = authenticated seller ID
   * 4. Count refund requests with status = 'pending' AND ecommerce_mall_seller_id = authenticated seller ID
   *
   * Return all counts in a single dashboard summary object.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @SellerAuth()
    seller: SellerPayload,
  ): Promise<IEcommerceMallSellerDashboard.IResult> {
    try {
      return await getEcommerceMallSellerSellersMeDashboard({
        seller,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
