import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallSellerAdminRequest } from "../../../../../../api/structures/IEcommerceMallSellerAdminRequest";
import { IPageIEcommerceMallSellerAdminRequest } from "../../../../../../api/structures/IPageIEcommerceMallSellerAdminRequest";
import { SellerAuth } from "../../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../../decorators/payload/SellerPayload";
import { getEcommerceMallSellerSellersMeAdminRequestsRequestId } from "../../../../../../providers/getEcommerceMallSellerSellersMeAdminRequestsRequestId";
import { patchEcommerceMallSellerSellersMeAdminRequests } from "../../../../../../providers/patchEcommerceMallSellerSellersMeAdminRequests";
import { postEcommerceMallSellerSellersMeAdminRequests } from "../../../../../../providers/postEcommerceMallSellerSellersMeAdminRequests";

@Controller("/ecommerceMall/seller/sellers/me/admin-requests")
export class EcommercemallSellerSellersMeAdmin_requestsController {
  /**
   * Submit an administrative privilege request to become an administrator on the platform.
   *
   * Sellers can use this endpoint to request elevated administrative privileges by providing a detailed reason explaining why they need admin access. The request is then reviewed by super administrators who can approve or reject it.
   *
   * **Request Processing**
   * Upon submission, the system validates that the seller account exists and is in good standing. If the seller already has a pending admin request, the system returns a conflict error. The request status is set to 'pending' upon creation and awaits super administrator review.
   *
   * **Response Details**
   * The response returns the complete admin request record including the generated request ID, the submitted reason, current status of 'pending', and timestamps for creation and updates. The rejection_reason field is null initially and only populated if a super administrator rejects the request.
   *
   * **Error Handling**
   * If the seller already has a pending or approved admin request, the system returns a 409 Conflict error. If the seller account is suspended or banned, the system returns a 403 Forbidden error.
   *
   * @param connection
   * @param body Contains the reason text explaining why the seller is requesting administrative privileges.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Create a new admin request for the authenticated seller.
   *
   * 1. Extract authenticated seller from request context (seller session/token)
   * 2. Validate seller account exists and is active (not suspended/banned)
   * 3. Check for existing pending or approved admin requests for this seller - if exists, return 409 Conflict
   * 4. Insert new record into ecommerce_mall_seller_admin_requests:
   *    - id: generate UUID
   *    - ecommerce_mall_seller_id: from authenticated seller
   *    - reviewed_by_super_admin_id: null (not yet reviewed)
   *    - reason: from request body
   *    - status: 'pending'
   *    - rejection_reason: null
   *    - created_at: current timestamp
   *    - updated_at: current timestamp
   *    - deleted_at: null
   * 5. Return the created admin request record
   *
   * Note: The unique index on ecommerce_mall_seller_id enforces that each seller can only have one non-deleted admin request at a time. Deleted requests are soft-deleted (deleted_at set), allowing re-submission after deletion.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IEcommerceMallSellerAdminRequest.ICreate,
  ): Promise<IEcommerceMallSellerAdminRequest> {
    try {
      return await postEcommerceMallSellerSellersMeAdminRequests({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * List the authenticated seller's admin privilege requests with optional filtering.
   *
   * This endpoint allows sellers to view their submitted admin privilege requests. Sellers can filter by request status (pending, approved, rejected) and date range to find specific requests.
   *
   * **Filtering Options:**
   * - Filter by status: pending, approved, or rejected requests
   * - Filter by date range: requests created within a specific period
   * - Pagination: control page number and items per page
   *
   * **Response Format:**
   * Returns a paginated list sorted by creation date (newest first). Each item includes the request ID, status, reason, creation timestamp, and review information if applicable.
   *
   * **Error Handling:**
   * - 401 Unauthorized: Missing or invalid authentication token
   * - The system automatically filters results to only show requests belonging to the authenticated seller
   *
   * @param connection
   * @param body Search criteria including optional status filter, date range filters, and pagination parameters for listing the seller's admin requests.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query ecommerce_mall_seller_admin_requests table filtering by the authenticated seller's ID.
   *
   * Implementation steps:
   * 1. Extract seller ID from authenticated session (JWT token)
   * 2. Build query with filters from request body: status, createdAtFrom, createdAtTo
   * 3. Apply pagination: page, limit with default limit of 20
   * 4. Order by created_at descending (newest first)
   * 5. Include reviewed_by_super_admin_id and rejection_reason in response when available
   * 6. Return paginated results with summary fields only
   *
   * Edge cases:
   * - If no requests found for seller, return empty page with total: 0
   * - If status filter is invalid, reject with validation error
   * - Ensure soft-deleted requests are excluded (deleted_at IS NULL)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IEcommerceMallSellerAdminRequest.IRequest,
  ): Promise<IPageIEcommerceMallSellerAdminRequest.ISummary> {
    try {
      return await patchEcommerceMallSellerSellersMeAdminRequests({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves a specific admin privilege request submitted by the authenticated seller.
   *
   * This endpoint allows sellers to view the details of their own admin privilege requests. The response includes the request status (pending, approved, or rejected), the reason provided when submitting the request, and the rejection reason if the request was rejected by a super administrator.
   *
   * **Request Context**: Requires seller authentication via JWT token in Authorization header.
   *
   * **Ownership Verification**: The system verifies that the requested admin request belongs to the authenticated seller making the request. Sellers cannot view admin requests belonging to other sellers.
   *
   * **Error Handling**: Returns 404 if the admin request is not found. Returns 403 if the request belongs to another seller.
   *
   * @param connection
   * @param requestId Unique identifier (UUID) of the admin request to retrieve. Must belong to the authenticated seller.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query the ecommerce_mall_seller_admin_requests table to retrieve the specific admin request by its UUID identifier.
   *
   * 1. Extract seller ID from authenticated seller session (JWT token).
   * 2. Query database: SELECT * FROM ecommerce_mall_seller_admin_requests WHERE id = requestId AND ecommerce_mall_seller_id = authenticatedSellerId AND deleted_at IS NULL.
   * 3. Verify the admin request exists and belongs to the authenticated seller.
   * 4. If not found, throw NOT_FOUND error.
   * 5. Return the admin request record with all fields.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":requestId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("requestId")
    requestId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallSellerAdminRequest> {
    try {
      return await getEcommerceMallSellerSellersMeAdminRequestsRequestId({
        seller,
        requestId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
