import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallSellerProfile } from "../../../../../api/structures/IEcommerceMallSellerProfile";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { putEcommerceMallSellerSellersProfile } from "../../../../../providers/putEcommerceMallSellerSellersProfile";

@Controller("/ecommerceMall/seller/sellers/profile")
export class EcommercemallSellerSellersProfileController {
  /**
   * Update the authenticated seller's shop profile information.
   *
   * This endpoint allows sellers to modify their public-facing shop profile including the shop name, business description, and logo image. The shop name appears on product listings, order records, and throughout the platform wherever the seller is referenced.
   *
   * When the profile is updated, the system automatically creates an immutable snapshot of the previous state before applying the changes. This snapshot preserves the historical profile data for audit and dispute resolution purposes. If multiple fields are updated in a single request, one snapshot captures the complete state before the edit.
   *
   * Suspended sellers can still edit their shop profile - profile edits do not change the suspended status of the seller account. However, suspended sellers cannot create or edit products.
   *
   * The shop name must be provided when updating. The description and logo URI are optional in updates, allowing partial updates to specific fields.
   *
   * @param connection
   * @param body Fields to update in the seller profile. At minimum, shop name is required.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Update the seller profile for the authenticated seller.
   *
   * 1. Authentication: Extract seller_id from the authenticated session token.
   *
   * 2. Validate that the seller profile exists. If not found, return 404 error.
   *
   * 3. Validate input:
   *    - name: Required, non-empty string
   *    - description: Optional string
   *    - logo_uri: Optional string (valid URI format, max 80000 chars)
   *
   * 4. Before updating, create a snapshot of the current profile state:
   *    - Capture current name, description, logo_uri values
   *    - Include timestamp of the snapshot creation
   *    - Associate with the seller who made the change
   *    - Store in ecommerce_mall_seller_profile_snapshots table
   *
   * 5. Apply the updates to the profile:
   *    - Update only the fields provided in the request
   *    - Update the updated_at timestamp
   *
   * 6. Return the complete updated profile.
   *
   * Edge cases:
   * - If seller is suspended, still allow profile update but do not change suspension status
   * - If profile was previously deleted (soft-deleted), check business rules for recovery
   * - Validate logo_uri format if provided (must be valid URI)
   * - Ensure shop name uniqueness per seller (one profile per seller)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IEcommerceMallSellerProfile.IUpdate,
  ): Promise<IEcommerceMallSellerProfile> {
    try {
      return await putEcommerceMallSellerSellersProfile({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
