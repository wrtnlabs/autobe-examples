import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallSellerProfile } from "../../../../../../api/structures/IEcommerceMallSellerProfile";
import { SellerAuth } from "../../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../../decorators/payload/SellerPayload";
import { getEcommerceMallSellerSellersMeProfile } from "../../../../../../providers/getEcommerceMallSellerSellersMeProfile";
import { patchEcommerceMallSellerSellersMeProfile } from "../../../../../../providers/patchEcommerceMallSellerSellersMeProfile";
import { putEcommerceMallSellerSellersMeProfile } from "../../../../../../providers/putEcommerceMallSellerSellersMeProfile";

@Controller("/ecommerceMall/seller/sellers/me/profile")
export class EcommercemallSellerSellersMeProfileController {
  /**
   * Retrieves the authenticated seller's own shop profile.
   *
   * This endpoint allows sellers to view their complete shop profile including shop name, business description, and logo image. The profile information is visible to customers browsing products and viewing order records.
   *
   * **Authentication**: Requires valid seller session token.
   *
   * **Profile Visibility**: The shop profile is publicly visible to all customers and guests browsing the platform. This information helps customers learn about sellers before making purchase decisions.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query the ecommerce_mall_seller_profiles table using the seller_id from the authenticated session context.
   *
   * Return all profile fields: id, shop_name, description, logo_image, created_at, updated_at.
   *
   * If no profile exists for the seller, return a 404 error with message indicating profile not found.
   *
   * No authorization beyond seller authentication required as the endpoint only returns the authenticated seller's own profile.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @SellerAuth()
    seller: SellerPayload,
  ): Promise<IEcommerceMallSellerProfile> {
    try {
      return await getEcommerceMallSellerSellersMeProfile({
        seller,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Updates the authenticated seller's shop profile information.
   *
   * The shop profile contains the seller's public-facing shop name, business description, and logo image displayed to customers browsing products and seller pages. When any profile field is updated, the system automatically creates an immutable snapshot preserving the previous state for historical tracking and dispute resolution.
   *
   * **Profile Information**: The shop name appears on product listings and order records. The description provides business background visible on seller profile pages. The logo_uri references the shop logo image stored in file storage.
   *
   * **Automatic Snapshots**: Per business rules, every profile edit automatically creates a snapshot before applying changes. If multiple fields are updated in a single request, one snapshot captures the complete state before the edit. Sellers can view their profile change history through the snapshot history endpoint.
   *
   * **Validation**: Shop name is required and must not be empty. Description is required. Logo_uri is optional and can be null to remove the logo.
   *
   * @param connection
   * @param body Update payload containing the shop profile fields to modify. All fields are optional but at least one must be provided.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Update the authenticated seller's shop profile in ecommerce_mall_seller_profiles table.
   *
   * Implementation steps:
   * 1. Extract authenticated seller from request context
   * 2. Query current profile state from ecommerce_mall_seller_profiles by seller_id
   * 3. Validate profile exists and is not soft-deleted
   * 4. Validate request body: name (required, non-empty), description (required), logo_uri (optional)
   * 5. Before applying updates, create a snapshot in ecommerce_mall_seller_profile_snapshots capturing:
   *    - snapshot_type: 'profile_edit'
   *    - seller_profile_id: current profile id
   *    - seller_id: authenticated seller id
   *    - name: current name value
   *    - description: current description value
   *    - logo_uri: current logo_uri value
   *    - captured_at: current timestamp
   * 6. Apply updates to seller profile: name, description, logo_uri, updated_at
   * 7. Return the updated seller profile
   *
   * Error handling:
   * - 404 if profile not found or soft-deleted
   * - 400 for validation failures
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async put(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IEcommerceMallSellerProfile.IUpdate,
  ): Promise<IEcommerceMallSellerProfile> {
    try {
      return await putEcommerceMallSellerSellersMeProfile({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update the authenticated seller's shop profile including shop name, description, and logo.
   *
   * This endpoint allows sellers to modify their public-facing shop information. Every update automatically creates an immutable snapshot of the previous profile state for historical tracking.
   *
   * **Profile Updates**
   * The seller can update any combination of fields: shop name, description, and logo image. All fields are optional; only provided fields will be updated.
   *
   * **Automatic Snapshot Creation**
   * Before applying any changes, the system automatically creates a seller profile snapshot capturing the current profile state. This snapshot preserves the shop name, description, logo URL, and timestamp for audit and history purposes.
   *
   * **Suspended Seller Access**
   * Suspended sellers are permitted to edit their shop profile. Profile edits do not affect the suspended status of the account.
   *
   * **Validation**
   * The shop name must be provided and cannot exceed 200 characters. If updating the logo, the provided URI must be a valid format.
   *
   * @param connection
   * @param body Fields to update. All fields are optional - only provided fields will be modified. Shop name is required if any update is intended.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification 1. Extract authenticated seller from request context (seller session/JWT).
   * 2. Query the ecommerce_mall_seller_profiles table using seller_id from the authenticated seller.
   * 3. Validate that the seller profile exists (return 404 if not found).
   * 4. Validate input fields:
   *    - If name is provided, verify length <= 200 characters.
   *    - If description is provided, verify length <= 10000 characters.
   *    - If logo_uri is provided, verify it is a valid URI format.
   * 5. Create a snapshot BEFORE applying changes:
   *    - Insert into ecommerce_mall_seller_profile_snapshots with:
   *      - ecommerce_mall_seller_profile_id = current profile id
   *      - shop_name = current name
   *      - shop_description = current description
   *      - logo_url = current logo_uri
   *      - created_at = current timestamp
   * 6. Apply updates to ecommerce_mall_seller_profiles:
   *    - Update only the fields that were provided in the request.
   *    - Set updated_at = current timestamp.
   * 7. Return the updated seller profile.
   *
   * **Error Handling**:
   * - If seller profile not found: Return 404 with message "Seller profile not found".
   * - If validation fails: Return 400 with field-specific error messages.
   * - If snapshot creation fails: Log error but continue with profile update (snapshot is for audit, not blocking).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async patch(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IEcommerceMallSellerProfile.IUpdate,
  ): Promise<IEcommerceMallSellerProfile> {
    try {
      return await patchEcommerceMallSellerSellersMeProfile({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
