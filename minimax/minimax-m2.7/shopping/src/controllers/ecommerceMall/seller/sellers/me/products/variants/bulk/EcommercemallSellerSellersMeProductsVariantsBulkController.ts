import { postEcommerceMallSellerSellersMeProductsProductIdVariantsBulk } from "../../../../../../../../providers/postEcommerceMallSellerSellersMeProductsProductIdVariantsBulk";

@Controller(
  "/ecommerceMall/seller/sellers/me/products/:productId/variants/bulk",
)
export class EcommercemallSellerSellersMeProductsVariantsBulkController {
  /**
   * Creates multiple product variants in a single operation.
   *
   * This endpoint allows sellers to add multiple variants to their product at once, such as creating all size/color combinations in one request. Each variant must have a unique SKU code across the entire platform.
   *
   * **Variant Configuration**
   *
   * Each variant in the request specifies a unique combination of selectable options (e.g., color and size), an optional price override from the product's base price, and an initial stock quantity.
   *
   * **SKU Uniqueness**
   *
   * All SKU codes must be globally unique across the platform. Duplicate SKU codes cause the entire bulk operation to fail with validation errors indicating which SKUs are duplicated.
   *
   * **Option Values**
   *
   * Each variant requires one or more option key-value pairs defining its configuration. For example, a variant might specify color=Red and size=Large. These options are stored as separate records linked to the variant.
   *
   * **Ownership Verification**
   *
   * The system verifies that the requesting seller owns the specified product before allowing variant creation. Sellers cannot add variants to other sellers' products.
   *
   * **Response**
   *
   * On success, returns an array of all created variants with their assigned IDs, SKU codes, option values, prices, and quantities. If any validation fails, no variants are created.
   *
   * @param connection
   * @param productId Unique identifier of the product to which variants will be added.
   * @param body Bulk creation request containing an array of variant data. Each variant specifies a unique SKU code, option values defining the configuration (e.g., color and size), optional price override, and initial stock quantity.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification 1. Extract seller from authenticated session.
   * 2. Validate productId is a valid UUID.
   * 3. Verify the product belongs to the requesting seller by querying ecommerce_mall_products table with id = productId AND ecommerce_mall_seller_id = seller.id.
   * 4. If product not found or not owned by seller, throw 403 Forbidden.
   * 5. Validate request body contains an array of variant data (minimum 1, maximum 100 variants per request).
   * 6. For each variant in the array:
   *    - Validate sku_code is non-empty string (max 100 characters)
   *    - Validate option_values is non-empty array of objects with 'key' and 'value' properties
   *    - Validate quantity is non-negative integer (defaults to 0)
   *    - Validate price is optional positive number if provided
   * 7. Collect all SKU codes from request.
   * 8. Query ecommerce_mall_product_variants to check for existing SKU codes matching any in the request.
   * 9. If any SKU codes already exist, return 409 Conflict with list of duplicate SKUs.
   * 10. Begin database transaction.
   * 11. For each variant in request:
   *     - Create record in ecommerce_mall_product_variants with:
   *       - id: generated UUID
   *       - ecommerce_mall_product_id: productId
   *       - sku_code: variant.sku_code
   *       - price: variant.price (nullable)
   *       - quantity: variant.quantity or 0
   *       - created_at: current timestamp
   *       - updated_at: current timestamp
   *       - deleted_at: null
   *     - Create records in ecommerce_mall_product_variant_option_values for each option:
   *       - id: generated UUID
   *       - ecommerce_mall_product_variant_id: variant.id
   *       - key: option.key
   *       - value: option.value
   *       - created_at: current timestamp
   *       - updated_at: current timestamp
   * 12. Commit transaction.
   * 13. Query created variants with their option values to return in response.
   * 14. Return 201 Created with array of created variant objects including option_values.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceMallProductVariant.ICreateBulk,
  ): Promise<IEcommerceMallProductVariant.IBulk> {
    try {
      return await postEcommerceMallSellerSellersMeProductsProductIdVariantsBulk(
        {
          seller,
          productId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
