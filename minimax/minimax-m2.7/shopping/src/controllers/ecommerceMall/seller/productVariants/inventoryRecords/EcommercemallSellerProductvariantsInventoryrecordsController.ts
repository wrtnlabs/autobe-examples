import { getEcommerceMallSellerProductVariantsVariantIdInventoryRecordsInventoryRecordId } from "../../../../../providers/getEcommerceMallSellerProductVariantsVariantIdInventoryRecordsInventoryRecordId";
import { patchEcommerceMallSellerProductVariantsVariantIdInventoryRecords } from "../../../../../providers/patchEcommerceMallSellerProductVariantsVariantIdInventoryRecords";
import { postEcommerceMallSellerProductVariantsVariantIdInventoryRecords } from "../../../../../providers/postEcommerceMallSellerProductVariantsVariantIdInventoryRecords";

@Controller("/ecommerceMall/seller/productVariants/:variantId/inventoryRecords")
export class EcommercemallSellerProductvariantsInventoryrecordsController {
  /**
   * Create an inventory record for a product variant to add stock quantity.
   *
   * This endpoint allows sellers to restock their product variants by recording positive inventory changes. Each inventory record captures the quantity added and the business reason for the change.
   *
   * The seller must own the product containing the specified variant. The quantity change must be positive (greater than zero) and a reason must be provided explaining why the inventory is being added.
   *
   * The system automatically updates the variant's current stock quantity by adding the specified quantity. Created inventory records are immutable and form part of the complete audit trail for inventory changes.
   *
   * This operation is commonly used for restocking from suppliers, returning items to inventory, or correcting previous inventory counts.
   *
   * @param connection
   * @param variantId Unique identifier of the product variant to add inventory to
   * @param body Inventory addition details including quantity to add and business reason
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Validate that the variant exists and belongs to a product owned by the authenticated seller.
   *
   * Retrieve the variant's current stock quantity from the ecommerce_mall_product_variants table.
   *
   * Validate the request body:
   * - quantity_change: MUST be a positive integer greater than zero
   * - reason: MUST be a non-empty string between 1 and 500 characters
   *
   * Verify that quantity_change is positive. Reject with error if zero or negative.
   *
   * Create a new inventory record in ecommerce_mall_inventory_records table with:
   * - id: generated UUID
   * - ecommerce_mall_product_variant_id: from path parameter
   * - quantity_change: from request body (positive value)
   * - reason: from request body
   * - created_at: current timestamp
   *
   * Update the variant's quantity in ecommerce_mall_product_variants by adding the quantity_change to the current quantity.
   *
   * Return the created inventory record with all its fields including the generated ID and timestamp.
   *
   * Handle errors:
   * - Variant not found: return 404 with 'product variant not found'
   * - Variant belongs to another seller: return 403 with 'permission denied'
   * - quantity_change is zero or negative: return 400 with validation error
   * - reason is empty or exceeds 500 characters: return 400 with validation error
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("variantId")
    variantId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceMallInventoryRecord.ICreate,
  ): Promise<IEcommerceMallInventoryRecord> {
    try {
      return await postEcommerceMallSellerProductVariantsVariantIdInventoryRecords(
        {
          seller,
          variantId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a paginated list of inventory records for a specific product variant.
   *
   * This operation allows sellers to view the complete history of stock changes for their product variants. Each inventory record captures a quantity change (positive for restocking/refunds, negative for order deductions/adjustments), the business reason for the change, and the timestamp when the change occurred.
   *
   * The inventory history helps sellers track stock movements, audit inventory changes, and reconcile their stock levels. Records are sorted by timestamp in descending order, showing the most recent changes first.
   *
   * Filters can be applied to narrow results by date range. Only inventory records belonging to variants owned by the authenticated seller are accessible.
   *
   * @param connection
   * @param variantId Unique identifier of the product variant (UUID format)
   * @param body Optional date range filters for narrowing inventory record results
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query ecommerce_mall_inventory_records table filtered by ecommerce_mall_product_variant_id.
   *
   * First, verify the product variant exists by querying ecommerce_mall_product_variants table and retrieving its ecommerce_mall_product_id. Then verify the owning product belongs to the authenticated seller by checking ecommerce_mall_products table.
   *
   * If the variant does not exist, return 404 error with message 'Product variant not found'.
   *
   * If the seller does not own the product containing the variant, return 403 error with message 'You do not have permission to view this variant inventory'.
   *
   * Apply optional filters:
   * - createdAtFrom: Filter records with created_at >= this timestamp (ISO 8601 format)
   * - createdAtTo: Filter records with created_at <= this timestamp (ISO 8601 format)
   *
   * Order results by created_at descending (most recent first).
   *
   * Return paginated results with pagination metadata including page, limit, total, and totalPages. Each record should include id, quantityChange, reason, and createdAt from the inventory record.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("variantId")
    variantId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceMallInventoryRecord.IRequest,
  ): Promise<IPageIEcommerceMallInventoryRecord.ISummary> {
    try {
      return await patchEcommerceMallSellerProductVariantsVariantIdInventoryRecords(
        {
          seller,
          variantId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single inventory record by its unique identifier.
   *
   * This endpoint returns detailed information about a specific inventory change record, including the quantity change amount, the business reason for the change, and the timestamp when the change occurred. The current stock quantity shown is calculated by summing all inventory records for the variant up to and including this record.
   *
   * Sellers can only access inventory records belonging to variants of their own products. Attempting to access records for variants owned by other sellers will result in a permission denied error.
   *
   * The inventory record is immutable once created, preserving a complete audit trail of all stock changes for dispute resolution and historical tracking purposes.
   *
   * @param connection
   * @param variantId Unique identifier of the product variant (UUID format)
   * @param inventoryRecordId Unique identifier of the inventory record (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification 1. Extract variantId and inventoryRecordId from path parameters.
   * 2. Validate that both IDs are valid UUIDs.
   * 3. Verify the product variant exists and is not soft-deleted (deleted_at IS NULL).
   * 4. Verify the inventory record exists and belongs to the specified variant.
   * 5. For seller requests: Verify the parent product belongs to the requesting seller. Return 403 Forbidden if ownership check fails.
   * 6. For admin requests: Allow unrestricted access to any inventory record.
   * 7. Calculate current stock by summing all quantity_change values for the variant.
   * 8. Return the inventory record with calculated current_stock included.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":inventoryRecordId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("variantId")
    variantId: string & tags.Format<"uuid">,
    @TypedParam("inventoryRecordId")
    inventoryRecordId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallInventoryRecord> {
    try {
      return await getEcommerceMallSellerProductVariantsVariantIdInventoryRecordsInventoryRecordId(
        {
          seller,
          variantId,
          inventoryRecordId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
