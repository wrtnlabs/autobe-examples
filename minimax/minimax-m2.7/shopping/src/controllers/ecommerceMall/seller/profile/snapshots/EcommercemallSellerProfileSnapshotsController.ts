import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallSellerProfileSnapshot } from "../../../../../api/structures/IEcommerceMallSellerProfileSnapshot";
import { IPageIEcommerceMallSellerProfileSnapshot } from "../../../../../api/structures/IPageIEcommerceMallSellerProfileSnapshot";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { getEcommerceMallSellerProfileSnapshotsSnapshotId } from "../../../../../providers/getEcommerceMallSellerProfileSnapshotsSnapshotId";
import { patchEcommerceMallSellerProfileSnapshots } from "../../../../../providers/patchEcommerceMallSellerProfileSnapshots";

@Controller("/ecommerceMall/seller/profile/snapshots")
export class EcommercemallSellerProfileSnapshotsController {
  /**
   * Retrieve a paginated list of seller profile snapshots for the authenticated seller.
   *
   * This operation returns the history of all profile changes made by the seller, including shop name updates, description changes, and logo modifications. Each snapshot preserves the complete state of the profile at the moment before the change was applied.
   *
   * The snapshots are immutable records ordered by creation timestamp (newest first by default). This endpoint supports filtering by date range and pagination for efficient browsing of the snapshot history.
   *
   * Snapshots are created automatically by the system when the seller updates their shop profile through the profile update endpoint.
   *
   * @param connection
   * @param body Search criteria including optional date range filters and pagination parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query ecommerce_mall_seller_profile_snapshots table filtering by the authenticated seller's profile ID.
   *
   * Implement pagination with configurable page size and cursor or offset-based navigation. Support filtering by created_at date range (from_date, to_date).
   *
   * Order results by created_at descending (newest first) by default.
   *
   * Join with ecommerce_mall_seller_profiles table to verify the seller belongs to the authenticated user.
   *
   * Return snapshot summary data including id, shop_name, shop_description, logo_url, and created_at.
   *
   * Handle empty results gracefully with an empty data array and pagination metadata showing zero total.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IEcommerceMallSellerProfileSnapshot.IRequest,
  ): Promise<IPageIEcommerceMallSellerProfileSnapshot> {
    try {
      return await patchEcommerceMallSellerProfileSnapshots({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific seller profile snapshot by its unique identifier.
   *
   * This operation returns the immutable snapshot data including the shop name, description, logo URL, and creation timestamp that were captured at the time the snapshot was created. Access is restricted based on user role: sellers can retrieve snapshots of their own profile history, and administrators can access any snapshot on the platform for oversight purposes.
   *
   * The snapshot provides a point-in-time view of how the seller's shop profile appeared at a specific moment, useful for tracking profile changes over time or resolving disputes about shop information.
   *
   * @param connection
   * @param snapshotId Unique identifier of the seller profile snapshot to retrieve (global scope)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query the ecommerce_mall_seller_profile_snapshots table using the provided snapshotId as the primary key.
   *
   * Verify the requesting user has permission to view this snapshot:
   * - Sellers: can only view snapshots where their seller_profile_id matches their associated profile
   * - Administrators: can view any snapshot regardless of seller
   * - Customers: can view snapshots only if they are attached to order items in their order history
   *
   * If the snapshot exists but the associated seller profile has been deleted, still return the snapshot data as it represents historical record.
   *
   * Return the snapshot fields: id, ecommerce_mall_seller_profile_id, shop_name, shop_description, logo_url, created_at.
   *
   * Handle error cases:
   * - If snapshotId does not exist, return 404 error
   * - If user lacks permission to view this snapshot, return 403 forbidden error
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":snapshotId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("snapshotId")
    snapshotId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallSellerProfileSnapshot> {
    try {
      return await getEcommerceMallSellerProfileSnapshotsSnapshotId({
        seller,
        snapshotId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
