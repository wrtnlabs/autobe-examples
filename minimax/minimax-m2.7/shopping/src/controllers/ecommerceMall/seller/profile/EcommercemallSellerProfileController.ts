import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallCustomerProfile } from "../../../../api/structures/IEcommerceMallCustomerProfile";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { getEcommerceMallSellerProfile } from "../../../../providers/getEcommerceMallSellerProfile";

@Controller("/ecommerceMall/seller/profile")
export class EcommercemallSellerProfileController {
  /**
   * Retrieve the current authenticated customer's profile information.
   *
   * This endpoint returns the profile data for the currently logged-in customer, including their display name and contact phone number. The profile is automatically created during customer registration and can be updated through the profile update endpoint.
   *
   * The operation requires a valid customer authentication token in the request headers. The response contains the customer's public-facing profile information used for identification within the platform. Display names appear in order histories, reviews, and other customer-visible interactions.
   *
   * If the customer has not yet updated their profile after registration, the returned profile will contain default values as set during account creation.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query the authenticated customer's session to retrieve their customer ID. Use the customer ID to query the ecommerce_mall_customer_profiles table and fetch the associated profile record. Return the profile data including display_name, phone, created_at, and updated_at fields. If no profile exists for the authenticated customer, return an error indicating profile not found.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @SellerAuth()
    seller: SellerPayload,
  ): Promise<IEcommerceMallCustomerProfile> {
    try {
      return await getEcommerceMallSellerProfile({
        seller,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
