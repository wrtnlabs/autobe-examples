import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallOrderItem } from "../../../../api/structures/IEcommerceMallOrderItem";
import { IPageIEcommerceMallOrderItem } from "../../../../api/structures/IPageIEcommerceMallOrderItem";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { getEcommerceMallSellerOrderItemsOrderItemId } from "../../../../providers/getEcommerceMallSellerOrderItemsOrderItemId";
import { patchEcommerceMallSellerOrderItems } from "../../../../providers/patchEcommerceMallSellerOrderItems";

@Controller("/ecommerceMall/seller/order-items")
export class EcommercemallSellerOrder_itemsController {
  /**
   * Retrieve a filtered and paginated list of order items belonging to the authenticated seller.
   *
   * This operation enables sellers to query their order items across all orders with flexible filtering capabilities. Sellers can filter by order item status (paid, shipped, delivered, cancelled, refunded) and optionally scope results to specific orders. Results are sorted by creation date in descending order, showing most recent order items first.
   *
   * The response includes paginated order item summaries with key details such as associated order reference, product information from the frozen snapshot, variant details, quantity, unit price, and current status. This operation is essential for sellers to track order fulfillment progress, manage shipments, and respond to cancellation or refund requests.
   *
   * Only order items belonging to products sold by the authenticated seller are returned. Unauthorized access to other sellers' order items is prevented at the service layer.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering order items.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Implement a list/search operation for seller order items using PATCH method.
   *
   * Authentication: Require seller authentication via Bearer token in Authorization header. Extract seller ID from session.
   *
   * Query Logic:
   * 1. Start with a base query on ecommerce_mall_order_items table
   * 2. Join with ecommerce_mall_orders to get order reference information
   * 3. Join with ecommerce_mall_product_snapshots to include product name in results
   * 4. Filter: Only return order items where the associated product belongs to the authenticated seller (check ecommerce_mall_products table with seller_id = authenticated seller)
   * 5. Apply optional filters from request body:
   *    - status: Filter by ecommerce_mall_order_items.status (paid, shipped, delivered, cancelled, refunded)
   *    - orderId: Filter by ecommerce_mall_order_id to scope results to a specific order
   *    - createdAtFrom/createdAtTo: Filter by date range
   * 6. Apply pagination: Use page and limit from request body, default page=1, limit=20, max limit=100
   * 7. Order by created_at DESC (most recent first)
   *
   * Response Construction:
   * - Return paginated results with data array and pagination metadata
   * - Include pagination: { page, limit, total, totalPages }
   * - Each summary item should include: id, orderId, productSnapshot (name), variantInfo (sku, options), quantity, unitPrice, status, createdAt
   *
   * Edge Cases:
   * - If no order items found for seller: Return empty data array with total=0
   * - If seller has no products: Return empty data array
   * - If status filter has invalid value: Return validation error
   * - If pagination page exceeds total pages: Return empty data array
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IEcommerceMallOrderItem.IRequest,
  ): Promise<IPageIEcommerceMallOrderItem.ISummary> {
    try {
      return await patchEcommerceMallSellerOrderItems({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific order item by its unique identifier.
   *
   * This endpoint provides complete details of an individual order item including the frozen product state (name, description, variant options, price) and seller profile state (shop name, logo) as they existed at the time of purchase. The order item status indicates its current fulfillment state: paid, shipped, delivered, cancelled, or refunded.
   *
   * Sellers can retrieve order items containing their products to track fulfillment and respond to customer requests. Administrators have full access to view any order item for oversight purposes.
   *
   * The response includes the product snapshot for dispute resolution (showing exactly what the customer purchased) and the seller profile snapshot (showing the shop information at purchase time).
   *
   * @param connection
   * @param orderItemId Unique identifier of the order item to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query the ecommerce_mall_order_items table by the provided orderItemId (UUID). Join with ecommerce_mall_product_snapshots to include frozen product details (name, description, option key-value pairs, price). Join with ecommerce_mall_seller_profile_snapshots to include frozen seller details (shop name, logo).
   *
   * Authorization check: Verify the requesting user has permission to view this order item - either they are the customer who placed the order, or they are the seller whose product is in the order item, or they are an administrator.
   *
   * Return 404 if order item not found. Return 403 if user lacks permission to view this order item.
   *
   * Map the database status field to appropriate status enum values. Include timestamps for created_at and updated_at.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":orderItemId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("orderItemId")
    orderItemId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallOrderItem> {
    try {
      return await getEcommerceMallSellerOrderItemsOrderItemId({
        seller,
        orderItemId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
