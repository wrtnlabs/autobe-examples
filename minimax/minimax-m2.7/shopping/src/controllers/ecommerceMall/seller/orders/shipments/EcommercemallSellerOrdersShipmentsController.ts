import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallShipment } from "../../../../../api/structures/IEcommerceMallShipment";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { deleteEcommerceMallSellerOrdersOrderIdShipmentsShipmentId } from "../../../../../providers/deleteEcommerceMallSellerOrdersOrderIdShipmentsShipmentId";
import { postEcommerceMallSellerOrdersOrderIdShipments } from "../../../../../providers/postEcommerceMallSellerOrdersOrderIdShipments";
import { putEcommerceMallSellerOrdersOrderIdShipmentsShipmentId } from "../../../../../providers/putEcommerceMallSellerOrdersOrderIdShipmentsShipmentId";

@Controller("/ecommerceMall/seller/orders/:orderId/shipments")
export class EcommercemallSellerOrdersShipmentsController {
  /**
   * Create a new shipment for an order containing the seller's order items.
   *
   * This endpoint allows sellers to ship their order items that have been paid. Sellers can bundle multiple order items from the same order into a single shipment by providing the carrier name and tracking number. Only order items belonging to the authenticated seller can be included in the shipment.
   *
   * The shipment creation process validates that all included order items are in 'paid' status and belong to the same seller. Upon successful creation, all included order items automatically change their status from 'paid' to 'shipped', and the shipment becomes visible to the customer for tracking purposes.
   *
   * Each order can have multiple shipments from different sellers, but a single shipment can only contain items from one seller.
   *
   * @param connection
   * @param orderId Unique identifier of the parent order containing the items to ship
   * @param body Shipment creation data including order item IDs to include and tracking information
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Implementation steps:
   *
   * 1. Validate authenticated seller session and extract seller identity
   * 2. Query ecommerce_mall_orders table to verify order exists and belongs to a valid customer
   * 3. Query ecommerce_mall_order_items table to retrieve items with status 'paid' belonging to the authenticated seller
   * 4. Validate all provided orderItemIds exist, belong to the specified order, have 'paid' status, and belong to the authenticated seller
   * 5. Validate all order items belong to the same seller (single-seller rule)
   * 6. Validate all order items belong to the same order (enforced by path parameter)
   * 7. Validate carrier name is non-empty string
   * 8. Validate tracking number is non-empty string
   * 9. Create shipment record in ecommerce_mall_shipments with:
   *    - ecommerce_mall_order_id: from path parameter
   *    - ecommerce_mall_seller_id: from authenticated seller
   *    - carrier: from request body
   *    - tracking_number: from request body
   *    - created_at: current timestamp
   * 10. Create shipment item records in ecommerce_mall_shipment_items for each order item
   * 11. Update status of all included order items from 'paid' to 'shipped' in ecommerce_mall_order_items
   * 12. Return created shipment with shipment items and order item details
   *
   * Error handling:
   * - 400: Invalid carrier/tracking number, order item not in 'paid' status
   * - 403: Order item belongs to different seller
   * - 404: Order not found, order item not found
   * - 409: Order item already shipped (already in a shipment)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceMallShipment.ICreate,
  ): Promise<IEcommerceMallShipment> {
    try {
      return await postEcommerceMallSellerOrdersOrderIdShipments({
        seller,
        orderId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update shipment tracking information for a specific shipment within an order.
   *
   * This endpoint allows sellers to modify the carrier name and tracking number of an existing shipment. Sellers can only update shipments they created. The update is useful for correcting tracking information or updating with final tracking details after initial shipment creation.
   *
   * The shipment must belong to the specified order. Only the carrier and tracking number can be modified through this endpoint. Status changes occur through separate delivery confirmation operations.
   *
   * This operation affects only the tracking details of the shipment. Order item status changes are managed through shipment creation and delivery confirmation endpoints.
   *
   * @param connection
   * @param orderId Unique identifier of the order this shipment belongs to (global scope).
   * @param shipmentId Unique identifier of the shipment to update (global scope).
   * @param body Updated shipment tracking information including carrier name and tracking number.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Update the carrier and tracking number for an existing shipment.
   *
   * 1. Validate that the shipment exists and belongs to the specified order.
   * 2. Verify the authenticated seller owns this shipment (seller must have created the shipment).
   * 3. Validate the new carrier name is not empty and tracking number is provided.
   * 4. Update the carrier and tracking_number fields in the database.
   * 5. Update the updated_at timestamp.
   * 6. Return the updated shipment with related order and seller information.
   *
   * Error handling:
   * - If shipment not found: return 404.
   * - If shipment belongs to different order: return 400.
   * - If seller does not own the shipment: return 403.
   * - If carrier or tracking_number is empty: return 400 with validation error.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":shipmentId")
  public async update(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedParam("shipmentId")
    shipmentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceMallShipment.IUpdate,
  ): Promise<IEcommerceMallShipment.IInvert> {
    try {
      return await putEcommerceMallSellerOrdersOrderIdShipmentsShipmentId({
        seller,
        orderId,
        shipmentId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a shipment created by the authenticated seller.
   *
   * This endpoint allows sellers to remove shipments they have created for their order items. The operation performs a soft delete, setting the deleted_at timestamp rather than permanently removing the record, which preserves the shipment history for audit and dispute resolution purposes.
   *
   * When a shipment is deleted, all associated shipment item records (linking the shipment to specific order items) are also removed. The original order items remain intact and can be shipped again in a new shipment if needed.
   *
   * Sellers can only delete their own shipments. The shipment must belong to the authenticated seller. This operation is typically used when a shipment was created in error or needs to be cancelled before the items are picked up by the carrier.
   *
   * Once items have been marked as delivered (via customer confirmation or automatic delivery confirmation), the associated shipment cannot be deleted as the delivery has been completed.
   *
   * @param connection
   * @param orderId UUID of the parent order containing the shipment
   * @param shipmentId UUID of the shipment to delete
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification 1. Extract orderId and shipmentId from path parameters.
   * 2. Validate that the authenticated user is a seller.
   * 3. Verify the shipment exists and belongs to the specified order.
   * 4. Verify the shipment belongs to the authenticated seller (ownership check).
   * 5. Verify the shipment has not been deleted already (deleted_at is null).
   * 6. Check if any associated order items have status 'delivered'. If any are delivered, reject deletion with appropriate error.
   * 7. Perform soft delete: SET deleted_at = CURRENT_TIMESTAMP on the shipment record.
   * 8. Delete all related shipment_items junction records (CASCADE).
   * 9. Return 204 No Content on success.
   *
   * Edge cases:
   * - If order does not exist: return 404 Not Found
   * - If shipment does not exist: return 404 Not Found
   * - If shipment belongs to different seller: return 403 Forbidden
   * - If shipment already deleted: return 404 Not Found
   * - If any order item is delivered: return 409 Conflict with message indicating items already delivered
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":shipmentId")
  public async erase(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedParam("shipmentId")
    shipmentId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteEcommerceMallSellerOrdersOrderIdShipmentsShipmentId({
        seller,
        orderId,
        shipmentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
