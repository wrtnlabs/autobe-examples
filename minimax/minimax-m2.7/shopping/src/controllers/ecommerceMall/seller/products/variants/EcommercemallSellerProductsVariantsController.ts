  /**
   * Update an existing product variant with new details.
   *
   * This endpoint allows sellers to modify their product variant information including the SKU code, price override, stock quantity, and option values. The variant must belong to a product owned by the authenticated seller.
   *
   * When updating option values, the system replaces all existing options with the new set provided. Each option consists of a key (such as 'color' or 'size') and its corresponding value (such as 'Red' or 'Large').
   *
   * Every successful update creates an immutable snapshot of the variant's previous state in the product_snapshot_variants table, preserving the SKU code, option values, price, and quantity for audit and dispute resolution purposes.
   *
   * The seller must own the parent product containing this variant. If the product does not belong to the seller, the request is rejected with a 403 Forbidden status.
   *
   * This operation does not directly modify inventory records. Stock quantity changes from updates are reflected in the variant's quantity field, and separate inventory management endpoints should be used for detailed inventory tracking.
   *
   * If updating the SKU code, the system validates that the new code is unique across all variants in the platform. Duplicate SKU codes result in a 400 Bad Request response.
   *
   * @param connection
   * @param productId Unique identifier of the parent product containing the variant
   * @param variantId Unique identifier of the variant to update
   * @param body Update payload containing variant details and option values
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification 1. Extract productId and variantId from path parameters.
   * 2. Retrieve the variant by variantId and verify it exists and is not soft-deleted (deleted_at is null).
   * 3. Verify the variant's parent product exists and is not soft-deleted.
   * 4. Extract the authenticated seller from the request context.
   * 5. Verify the product's ecommerce_mall_seller_id matches the authenticated seller's ID. Return 403 if ownership check fails.
   * 6. Validate the request body:
   *    - If sku_code is provided, verify uniqueness across all variants (excluding current variant). Return 400 if duplicate.
   *    - If price is provided, ensure it is non-negative.
   *    - If quantity is provided, ensure it is non-negative integer.
   *    - If optionValues is provided, validate each entry has non-empty key and value strings.
   * 7. Begin database transaction:
   *    a. Update the variant record with provided fields (sku_code, price, quantity).
   *    b. Delete existing option values for this variant from ecommerce_mall_product_variant_option_values.
   *    c. Insert new option values for each key-value pair in the request.
   *    d. Create a product_snapshot_variants record capturing the previous state before update.
   *    e. Commit transaction.
   * 8. Return the updated variant with its option values.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
