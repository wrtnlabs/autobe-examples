import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IEconPoliticalDiscussionContentModerator } from "../../../../structures/IEconPoliticalDiscussionContentModerator";

/**
 * Refreshes expired JWT access tokens for authenticated content moderators
 * using valid refresh tokens. This endpoint enables seamless session renewal
 * without requiring re-authentication, maintaining moderator workflow
 * continuity during content management activities. The refresh mechanism
 * validates the provided refresh token against stored session data and
 * regenerates access tokens with extended expiration periods. Security
 * protocols ensure refresh tokens are single-use with automatic rotation upon
 * successful renewal. Invalid or compromised refresh tokens trigger mandatory
 * re-authentication flows for security maintenance. The token refresh process
 * maintains moderator permissions and role context while extending session
 * lifetime for continued platform access. This operation is essential for
 * maintaining active moderator sessions during extended content management and
 * community oversight activities.
 *
 * @param props.connection
 * @param props.body Refresh token for session renewal
 * @setHeader token.access Authorization
 *
 * @path /auth/contentModerator/refresh
 * @accessor api.functional.auth.contentModerator.refresh.renewSession
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function renewSession(
  connection: IConnection,
  props: renewSession.Props,
): Promise<renewSession.Response> {
  const output: renewSession.Response =
    true === connection.simulate
      ? renewSession.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...renewSession.METADATA,
            path: renewSession.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
export namespace renewSession {
  export type Props = {
    /** Refresh token for session renewal */
    body: IEconPoliticalDiscussionContentModerator.IRefresh;
  };
  export type Body = IEconPoliticalDiscussionContentModerator.IRefresh;
  export type Response = IEconPoliticalDiscussionContentModerator.IAuthorized;

  export const METADATA = {
    method: "POST",
    path: "/auth/contentModerator/refresh",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/contentModerator/refresh";
  export const random =
    (): IEconPoliticalDiscussionContentModerator.IAuthorized =>
      typia.random<IEconPoliticalDiscussionContentModerator.IAuthorized>();
  export const simulate = (
    connection: IConnection,
    props: renewSession.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: renewSession.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
