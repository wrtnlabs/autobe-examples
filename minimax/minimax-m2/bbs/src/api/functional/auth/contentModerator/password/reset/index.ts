import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IEconPoliticalDiscussionContentModerator } from "../../../../../structures/IEconPoliticalDiscussionContentModerator";

/**
 * Enables content moderators to reset their account password through secure
 * email verification. This operation supports password recovery for moderator
 * accounts when access is forgotten or compromised. The reset process generates
 * time-limited tokens sent via email to the registered moderator address,
 * ensuring secure password restoration. Password reset tokens expire after 24
 * hours for security, requiring new token generation for expired requests. The
 * operation validates email existence in the econ_political_discussion_users
 * table and generates secure reset tokens with cryptographic randomness. Upon
 * token validation, moderators can set new passwords meeting platform
 * complexity requirements (8+ characters, mixed case, numbers, special
 * characters). This security function maintains moderator account integrity
 * while providing essential account recovery capabilities for platform
 * administrators.
 *
 * @param props.connection
 * @param props.body Password reset request with email address
 * @path /auth/contentModerator/password/reset
 * @accessor api.functional.auth.contentModerator.password.reset.resetPassword
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function resetPassword(
  connection: IConnection,
  props: resetPassword.Props,
): Promise<resetPassword.Response> {
  return true === connection.simulate
    ? resetPassword.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...resetPassword.METADATA,
          path: resetPassword.path(),
          status: null,
        },
        props.body,
      );
}
export namespace resetPassword {
  export type Props = {
    /** Password reset request with email address */
    body: IEconPoliticalDiscussionContentModerator.IResetPassword;
  };
  export type Body = IEconPoliticalDiscussionContentModerator.IResetPassword;
  export type Response =
    IEconPoliticalDiscussionContentModerator.IPasswordResetResponse;

  export const METADATA = {
    method: "POST",
    path: "/auth/contentModerator/password/reset",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/contentModerator/password/reset";
  export const random =
    (): IEconPoliticalDiscussionContentModerator.IPasswordResetResponse =>
      typia.random<IEconPoliticalDiscussionContentModerator.IPasswordResetResponse>();
  export const simulate = (
    connection: IConnection,
    props: resetPassword.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: resetPassword.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
