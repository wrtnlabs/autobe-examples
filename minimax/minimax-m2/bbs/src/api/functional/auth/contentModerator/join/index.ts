import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IEconPoliticalDiscussionContentModerator } from "../../../../structures/IEconPoliticalDiscussionContentModerator";

/**
 * Creates a new content moderator account for the economic and political
 * discussion board platform. This endpoint establishes a new moderator with
 * elevated permissions for content oversight, community management, and user
 * interaction moderation. The operation requires email verification before full
 * account activation, ensuring secure moderator onboarding. New moderator
 * accounts are created with the appropriate role permissions for managing
 * discussions, handling user reports, and enforcing community guidelines. The
 * registration process includes password complexity requirements, terms
 * acceptance, and community guidelines acknowledgment to ensure moderator
 * understanding of platform responsibilities. Upon successful registration, the
 * system generates initial JWT tokens for immediate platform access while
 * maintaining security protocols for sensitive moderator functions.
 *
 * @param props.connection
 * @param props.body New content moderator registration information including
 *   email, password, and display name
 * @setHeader token.access Authorization
 *
 * @path /auth/contentModerator/join
 * @accessor api.functional.auth.contentModerator.join.register
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function register(
  connection: IConnection,
  props: register.Props,
): Promise<register.Response> {
  const output: register.Response =
    true === connection.simulate
      ? register.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...register.METADATA,
            path: register.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
export namespace register {
  export type Props = {
    /**
     * New content moderator registration information including email,
     * password, and display name
     */
    body: IEconPoliticalDiscussionContentModerator.ICreate;
  };
  export type Body = IEconPoliticalDiscussionContentModerator.ICreate;
  export type Response = IEconPoliticalDiscussionContentModerator.IAuthorized;

  export const METADATA = {
    method: "POST",
    path: "/auth/contentModerator/join",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/contentModerator/join";
  export const random =
    (): IEconPoliticalDiscussionContentModerator.IAuthorized =>
      typia.random<IEconPoliticalDiscussionContentModerator.IAuthorized>();
  export const simulate = (
    connection: IConnection,
    props: register.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: register.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
