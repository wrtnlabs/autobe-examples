import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IEconPoliticalDiscussionContentModerator } from "../../../../structures/IEconPoliticalDiscussionContentModerator";

/**
 * Authenticates content moderator credentials and establishes secure session
 * with JWT token generation. This endpoint validates the moderator's email and
 * password against the stored account information in the
 * econ_political_discussion_users table. Upon successful authentication, the
 * system generates access and refresh tokens with appropriate expiration times
 * for security-sensitive moderator functions. Failed authentication attempts
 * are tracked and rate-limited to prevent unauthorized access attempts. The
 * login process maintains session security while enabling immediate access to
 * moderator dashboard and content management tools. Token generation includes
 * moderator-specific permissions and role identification for proper
 * authorization throughout the platform. Session creation supports multi-device
 * access while maintaining security protocols for moderator account access.
 *
 * @param props.connection
 * @param props.body Content moderator login credentials (email and password)
 * @setHeader token.access Authorization
 *
 * @path /auth/contentModerator/login
 * @accessor api.functional.auth.contentModerator.login.authenticate
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function authenticate(
  connection: IConnection,
  props: authenticate.Props,
): Promise<authenticate.Response> {
  const output: authenticate.Response =
    true === connection.simulate
      ? authenticate.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...authenticate.METADATA,
            path: authenticate.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
export namespace authenticate {
  export type Props = {
    /** Content moderator login credentials (email and password) */
    body: IEconPoliticalDiscussionContentModerator.ILogin;
  };
  export type Body = IEconPoliticalDiscussionContentModerator.ILogin;
  export type Response = IEconPoliticalDiscussionContentModerator.IAuthorized;

  export const METADATA = {
    method: "POST",
    path: "/auth/contentModerator/login",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/contentModerator/login";
  export const random =
    (): IEconPoliticalDiscussionContentModerator.IAuthorized =>
      typia.random<IEconPoliticalDiscussionContentModerator.IAuthorized>();
  export const simulate = (
    connection: IConnection,
    props: authenticate.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: authenticate.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
