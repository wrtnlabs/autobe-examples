import { IEconPoliticalDiscussionSystemAdministrator } from "../../../../structures/IEconPoliticalDiscussionSystemAdministrator";

/**
 * Refresh system administrator access tokens using a valid refresh token.
 *
 * This operation renews the access token for an authenticated system
 * administrator without requiring re-authentication. The endpoint validates the
 * provided refresh token against the server's token store and generates new JWT
 * access and refresh token pairs.
 *
 * System administrators use this operation to maintain their session without
 * logging in again, which is essential for:
 *
 * - Long administrative sessions
 * - Background system monitoring
 * - Automated administrative processes
 * - Maintaining security while avoiding frequent re-authentication
 *
 * Token refresh process:
 *
 * - Validates the refresh token against stored tokens
 * - Verifies the associated user account is still active
 * - Checks token expiration and revocation status
 * - Generates new access and refresh token pair
 * - Invalidates the old refresh token for security
 *
 * Upon successful token refresh, the system returns:
 *
 * - New access token with renewed admin privileges
 * - New refresh token for subsequent renewals
 * - Updated session expiration timestamps
 * - Current admin user profile information
 *
 * This operation requires a valid refresh token in the authorization header and
 * returns new tokens that extend the administrator's session. The old refresh
 * token is invalidated to prevent replay attacks and ensure security best
 * practices.
 *
 * This is a protected endpoint that requires the refresh token to be present
 * and valid. The response maintains all administrative privileges and access
 * levels that the previous session had.
 *
 * @param props.connection
 * @setHeader token.access Authorization
 *
 * @path /auth/systemAdministrator/refresh
 * @accessor api.functional.auth.systemAdministrator.refresh.renew
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function renew(connection: IConnection): Promise<renew.Response> {
  const output: renew.Response =
    true === connection.simulate
      ? renew.simulate(connection)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...renew.METADATA,
            path: renew.path(),
            status: null,
          },
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
export namespace renew {
  export type Response =
    IEconPoliticalDiscussionSystemAdministrator.IAuthorized;

  export const METADATA = {
    method: "POST",
    path: "/auth/systemAdministrator/refresh",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/systemAdministrator/refresh";
  export const random =
    (): IEconPoliticalDiscussionSystemAdministrator.IAuthorized =>
      typia.random<IEconPoliticalDiscussionSystemAdministrator.IAuthorized>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}
