import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IEconPoliticalDiscussionUser } from "../../../../structures/IEconPoliticalDiscussionUser";
import { IEconPoliticalDiscussionSystemAdministrator } from "../../../../structures/IEconPoliticalDiscussionSystemAdministrator";

/**
 * Authenticate an existing system administrator and issue access tokens.
 *
 * This operation validates the provided email and password credentials against
 * the econ_political_discussion_users table. Upon successful authentication,
 * the system generates JWT access and refresh tokens that authorize the admin
 * user to access all system functions.
 *
 * System administrators authenticated through this endpoint gain full
 * privileges including:
 *
 * - User management and account administration
 * - System configuration and settings management
 * - Content moderation and platform oversight
 * - Platform analytics and reporting access
 *
 * The authentication process:
 *
 * - Verifies the provided email exists in the user table
 * - Validates account status (must be 'active' for admin access)
 * - Checks authentication credentials
 * - Generates secure JWT tokens with appropriate expiration
 * - Logs authentication events for security audit
 *
 * Upon successful login, the system returns:
 *
 * - Access token with admin-level permissions
 * - Refresh token for token renewal
 * - Complete admin user profile
 * - Session metadata including expiration timestamps
 *
 * This is a public endpoint that enables existing administrators to access
 * their accounts. The response tokens provide immediate access to all
 * administrative API endpoints and dashboard functions.
 *
 * Failed authentication attempts are logged for security monitoring, and
 * appropriate HTTP status codes are returned to indicate authentication success
 * or failure.
 *
 * @param props.connection
 * @param props.body Admin login credentials including email
 * @setHeader token.access Authorization
 *
 * @path /auth/systemAdministrator/login
 * @accessor api.functional.auth.systemAdministrator.login.signIn
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function signIn(
  connection: IConnection,
  props: signIn.Props,
): Promise<signIn.Response> {
  const output: signIn.Response =
    true === connection.simulate
      ? signIn.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...signIn.METADATA,
            path: signIn.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
export namespace signIn {
  export type Props = {
    /** Admin login credentials including email */
    body: IEconPoliticalDiscussionUser.ILogin;
  };
  export type Body = IEconPoliticalDiscussionUser.ILogin;
  export type Response =
    IEconPoliticalDiscussionSystemAdministrator.IAuthorized;

  export const METADATA = {
    method: "POST",
    path: "/auth/systemAdministrator/login",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/systemAdministrator/login";
  export const random =
    (): IEconPoliticalDiscussionSystemAdministrator.IAuthorized =>
      typia.random<IEconPoliticalDiscussionSystemAdministrator.IAuthorized>();
  export const simulate = (
    connection: IConnection,
    props: signIn.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: signIn.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
