/**
 * Create a new system administrator account with full access privileges.
 *
 * This operation registers a new system administrator in the
 * econ_political_discussion_users table with the display_name and email
 * provided in the request body. The new admin account will be created with an
 * active status and initial authentication tokens will be issued.
 *
 * System administrators have full control over user management, system
 * settings, content moderation, and platform operations. This endpoint is
 * typically used during initial system setup or when adding new administrative
 * personnel.
 *
 * The operation creates a user record with:
 *
 * - Display_name: User's name for article authorship and community identification
 * - Email: User email address for account management and notifications
 * - Status: Set to 'active' for immediate admin access
 * - Created_at: Timestamp when the account was created
 * - Updated_at: Timestamp when the record was last modified
 *
 * Upon successful registration, the system returns:
 *
 * - Access token for immediate authentication
 * - Refresh token for obtaining new access tokens
 * - Admin user profile information
 * - Session expiration details
 *
 * This is a public endpoint that does not require prior authentication, making
 * it accessible for initial admin setup. The response includes JWT tokens that
 * provide immediate access to all administrative functions.
 *
 * @param props.connection
 * @param props.body Admin account creation information including display name
 *   and email
 * @setHeader token.access Authorization
 *
 * @path /auth/systemAdministrator/join
 * @accessor api.functional.auth.systemAdministrator.join.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function create(
  connection: IConnection,
  props: create.Props,
): Promise<create.Response> {
  const output: create.Response =
    true === connection.simulate
      ? create.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...create.METADATA,
            path: create.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
export namespace create {
  export type Props = {
    /** Admin account creation information including display name and email */
    body: IEconPoliticalDiscussionUser.ICreate;
  };
  export type Body = IEconPoliticalDiscussionUser.ICreate;
  export type Response =
    IEconPoliticalDiscussionSystemAdministrator.IAuthorized;

  export const METADATA = {
    method: "POST",
    path: "/auth/systemAdministrator/join",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/systemAdministrator/join";
  export const random =
    (): IEconPoliticalDiscussionSystemAdministrator.IAuthorized =>
      typia.random<IEconPoliticalDiscussionSystemAdministrator.IAuthorized>();
  export const simulate = (
    connection: IConnection,
    props: create.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: create.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
