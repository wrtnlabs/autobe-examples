import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IEconPoliticalDiscussionGuestUser } from "../../../structures/IEconPoliticalDiscussionGuestUser";
export * as refresh from "./refresh/index";

/**
 * Create a new guest user account for the economic and political discussion
 * board. This endpoint allows anonymous visitors to register and gain limited
 * access to participate in discussions.
 *
 * The operation validates the provided display_name and email against the
 * econ_political_discussion_users table constraints, ensuring email uniqueness
 * and proper display name formatting. Upon successful registration, the system
 * creates a new user record with active status and issues temporary JWT tokens
 * for initial access.
 *
 * The registration process incorporates the user table's required fields
 * including display_name for community identification, email for account
 * management, and optional bio and avatar_url for profile enhancement. The
 * system sets status to 'active' by default and applies soft delete support via
 * deleted_at field.
 *
 * This guest registration enables new users to create articles, participate in
 * discussions, and build their community presence. The operation establishes
 * the foundation for user engagement within the discussion board platform while
 * maintaining proper data integrity through database constraints.
 *
 * Related operations include token refresh for session maintenance and article
 * creation endpoints that utilize the authenticated user context provided by
 * successful registration.
 *
 * @param props.connection
 * @param props.body Guest user registration data containing display name and
 *   email information required for account creation.
 * @setHeader token.access Authorization
 *
 * @path /auth/guestUser/join
 * @accessor api.functional.auth.guestUser.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
export namespace join {
  export type Props = {
    /**
     * Guest user registration data containing display name and email
     * information required for account creation.
     */
    body: IEconPoliticalDiscussionGuestUser.ICreate;
  };
  export type Body = IEconPoliticalDiscussionGuestUser.ICreate;
  export type Response = IEconPoliticalDiscussionGuestUser.IAuthorized;

  export const METADATA = {
    method: "POST",
    path: "/auth/guestUser/join",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/guestUser/join";
  export const random = (): IEconPoliticalDiscussionGuestUser.IAuthorized =>
    typia.random<IEconPoliticalDiscussionGuestUser.IAuthorized>();
  export const simulate = (
    connection: IConnection,
    props: join.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: join.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
