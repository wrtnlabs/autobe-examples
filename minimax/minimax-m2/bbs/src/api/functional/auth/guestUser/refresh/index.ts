import { IConnection } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";

import { IEconPoliticalDiscussionGuestUser } from "../../../../structures/IEconPoliticalDiscussionGuestUser";

/**
 * Refresh temporary access tokens for authenticated guest users in the economic
 * and political discussion board. This endpoint extends the user session
 * without requiring credential revalidation.
 *
 * The operation validates the provided refresh token against the user's active
 * session state, ensuring the token corresponds to a valid, non-expired user
 * account in the econ_political_discussion_users table. Upon successful
 * validation, the system generates new access and refresh tokens while
 * maintaining the user's authenticated context.
 *
 * The refresh mechanism respects the user table's status field, allowing token
 * refresh only for accounts with 'active' status. It also considers soft delete
 * functionality through the deleted_at field, preventing token refresh for
 * deactivated accounts.
 *
 * This operation is essential for maintaining persistent user sessions during
 * extended discussion participation. It supports the guest user's continued
 * access to article creation, comment participation, and other authenticated
 * features without requiring repeated login.
 *
 * The refresh process integrates seamlessly with the initial authentication
 * flow established during guest registration, providing a complete session
 * management solution for discussion board participants.
 *
 * @param props.connection
 * @setHeader token.access Authorization
 *
 * @path /auth/guestUser/refresh
 * @accessor api.functional.auth.guestUser.refresh.refreshToken
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function refreshToken(
  connection: IConnection,
): Promise<refreshToken.Response> {
  const output: refreshToken.Response =
    true === connection.simulate
      ? refreshToken.simulate(connection)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...refreshToken.METADATA,
            path: refreshToken.path(),
            status: null,
          },
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
export namespace refreshToken {
  export type Response = IEconPoliticalDiscussionGuestUser.IAuthorized;

  export const METADATA = {
    method: "POST",
    path: "/auth/guestUser/refresh",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/guestUser/refresh";
  export const random = (): IEconPoliticalDiscussionGuestUser.IAuthorized =>
    typia.random<IEconPoliticalDiscussionGuestUser.IAuthorized>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}
