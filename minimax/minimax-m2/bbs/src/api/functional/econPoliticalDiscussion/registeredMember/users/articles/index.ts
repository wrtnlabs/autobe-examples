/**
 * Retrieve a filtered and paginated list of economic and political discussion
 * articles written by a specific user. This operation operates on the
 * econ_political_discussion_articles table and provides comprehensive search
 * capabilities for finding articles by author with advanced filtering, sorting,
 * and pagination options.
 *
 * The operation supports filtering articles by multiple criteria including
 * category (Economic Policy, Political Analysis, Market Discussion),
 * publication status (published, draft, etc.), and temporal ranges. Users can
 * sort articles by creation date, modification date, or relevance with
 * configurable ascending or descending order.
 *
 * Security considerations include proper author verification and access
 * control. Only registered members can access this endpoint to view articles
 * they have permission to see. Rate limiting applies to prevent abuse of the
 * search functionality.
 *
 * This operation integrates with the econ_political_discussion_articles table
 * as defined in the Prisma schema, incorporating all available article fields
 * and relationships including author information and associated attachments.
 * The response includes article summary information optimized for list
 * displays, with the ability to include additional metadata based on user
 * permissions and request parameters.
 *
 * @param props.connection
 * @param props.userId Unique identifier of the target user whose articles are
 *   being retrieved
 * @param props.body Search criteria, filtering options, pagination parameters,
 *   and sorting preferences for retrieving user's discussion articles
 * @path /econPoliticalDiscussion/registeredMember/users/:userId/articles
 * @accessor api.functional.econPoliticalDiscussion.registeredMember.users.articles.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Unique identifier of the target user whose articles are being
     * retrieved
     */
    userId: string & tags.Format<"uuid">;

    /**
     * Search criteria, filtering options, pagination parameters, and
     * sorting preferences for retrieving user's discussion articles
     */
    body: IEconPoliticalDiscussionArticle.IRequest;
  };
  export type Body = IEconPoliticalDiscussionArticle.IRequest;
  export type Response = IPageIEconPoliticalDiscussionArticle.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/econPoliticalDiscussion/registeredMember/users/:userId/articles",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/econPoliticalDiscussion/registeredMember/users/${encodeURIComponent(props.userId ?? "null")}/articles`;
  export const random = (): IPageIEconPoliticalDiscussionArticle.ISummary =>
    typia.random<IPageIEconPoliticalDiscussionArticle.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("userId")(() => typia.assert(props.userId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
