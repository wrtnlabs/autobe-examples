/**
 * Retrieve complete user profile information for economic and political
 * discussion board participants. This operation provides comprehensive user
 * details including display name, contact information, biographical content,
 * and community participation status. The information supports user
 * identification, community building, and discussion attribution.
 *
 * The operation validates that the target user exists and is accessible based
 * on account status and privacy settings. The response includes all profile
 * information from the econ_political_discussion_users table including display
 * name, email, optional bio, avatar URL, account status, and creation metadata.
 * Sensitive information is appropriately filtered based on requesting user
 * permissions and privacy configurations.
 *
 * Security considerations include privacy controls, account status
 * verification, and appropriate information disclosure based on user
 * relationships and community settings. The operation supports user discovery,
 * contact information sharing within community context, and profile management
 * workflows. Related operations include profile updates, account management,
 * and user discovery features. This operation enables community interaction and
 * user identification essential for meaningful economic and political
 * discourse.
 *
 * @param props.connection
 * @param props.userId Unique identifier of the target user to retrieve profile
 *   information for
 * @path /econPoliticalDiscussion/users/:userId
 * @accessor api.functional.econPoliticalDiscussion.users.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique identifier of the target user to retrieve profile information
     * for
     */
    userId: string & tags.Format<"uuid">;
  };
  export type Response = IEconPoliticalDiscussionUser;

  export const METADATA = {
    method: "GET",
    path: "/econPoliticalDiscussion/users/:userId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/econPoliticalDiscussion/users/${encodeURIComponent(props.userId ?? "null")}`;
  export const random = (): IEconPoliticalDiscussionUser =>
    typia.random<IEconPoliticalDiscussionUser>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("userId")(() => typia.assert(props.userId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

