import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IEconPoliticalDiscussionAttachment } from "../../../structures/IEconPoliticalDiscussionAttachment";

/**
 * Remove a specific file attachment from the economic and political discussion
 * system. This operation performs targeted attachment deletion while preserving
 * article content and other associated files. The system permanently removes
 * the file from storage and cleans up associated metadata.
 *
 * The operation validates that the target attachment exists and that the
 * requesting user has appropriate deletion permissions (attachment uploader,
 * article author, or administrator). The deletion process includes removal from
 * cloud storage, cascade cleanup of related metadata, and audit logging for
 * content management purposes. Associated article content remains intact with
 * other attachments unaffected.
 *
 * Security considerations include permission verification, audit logging, and
 * appropriate notification mechanisms for attachment removal. The operation
 * supports content moderation workflows and user-generated content management.
 * Related operations include file upload, attachment viewing, and article
 * management. This operation enables precise attachment management while
 * maintaining discussion thread integrity and content continuity.
 *
 * @param props.connection
 * @param props.attachmentId Unique identifier of the target attachment to
 *   delete
 * @path /econPoliticalDiscussion/attachments/:attachmentId
 * @accessor api.functional.econPoliticalDiscussion.attachments.erase
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function erase(
  connection: IConnection,
  props: erase.Props,
): Promise<erase.Response> {
  return true === connection.simulate
    ? erase.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...erase.METADATA,
          path: erase.path(props),
          status: null,
        },
      );
}
export namespace erase {
  export type Props = {
    /** Unique identifier of the target attachment to delete */
    attachmentId: string & tags.Format<"uuid">;
  };
  export type Response = IEconPoliticalDiscussionAttachment;

  export const METADATA = {
    method: "DELETE",
    path: "/econPoliticalDiscussion/attachments/:attachmentId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/econPoliticalDiscussion/attachments/${encodeURIComponent(props.attachmentId ?? "null")}`;
  export const random = (): IEconPoliticalDiscussionAttachment =>
    typia.random<IEconPoliticalDiscussionAttachment>();
  export const simulate = (
    connection: IConnection,
    props: erase.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: erase.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("attachmentId")(() => typia.assert(props.attachmentId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
