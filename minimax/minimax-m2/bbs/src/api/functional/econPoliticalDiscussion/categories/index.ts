/**
 * Retrieve a filtered list of available topic categories for economic and
 * political discussions.
 *
 * This operation provides search and filtering capabilities for the category
 * classification system used in the discussion board. It extracts unique
 * category values from the econ_political_discussion_articles table and
 * supports category-based content discovery.
 *
 * The operation works by querying all articles to collect distinct category
 * values, then applying filtering and sorting logic. Categories can be filtered
 * by availability status (used/unused categories) and sorted alphabetically or
 * by usage frequency based on article counts.
 *
 * Security considerations ensure that category information is publicly
 * accessible to facilitate content discovery and navigation. The operation
 * applies rate limiting to prevent abuse and ensure system performance.
 *
 * The response includes category metadata such as usage statistics, article
 * counts per category, and availability status. This data helps users
 * understand category popularity and choose appropriate classifications for
 * their discussions.
 *
 * This operation serves as a precursor to article creation, allowing users to
 * see available category options before posting new content. Related operations
 * include Create article (POST /articles) where category is required, and List
 * articles by category (GET /articles?category={category}).
 *
 * @param props.connection
 * @param props.body Search criteria and pagination parameters for category
 *   filtering and discovery
 * @path /econPoliticalDiscussion/categories
 * @accessor api.functional.econPoliticalDiscussion.categories.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
