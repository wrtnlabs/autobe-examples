import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { getUsersEmailEmail } from "../../../providers/getUsersEmailEmail";
import { SystemadministratorAuth } from "../../../decorators/SystemadministratorAuth";
import { SystemadministratorPayload } from "../../../decorators/payload/SystemadministratorPayload";

import { IEconPoliticalDiscussionUser } from "../../../api/structures/IEconPoliticalDiscussionUser";

@Controller("/users/email/:email")
export class UsersEmailController {
  /**
   * Retrieve detailed information about a specific user account by their email
   * address. This operation operates on the econ_political_discussion_users
   * table and provides comprehensive user profile information including display
   * name, biography, avatar, and account status.
   *
   * The operation validates the requested email address format and searches for
   * the corresponding user account in the database. If the user exists and the
   * requesting user has appropriate permissions, the complete user profile
   * information is returned including all public fields from the
   * econ_political_discussion_users table.
   *
   * Security considerations include proper access control verification. The
   * operation checks if the requesting user has system administrator privileges
   * to view user account information. Sensitive fields like deleted_at
   * timestamps are appropriately handled based on the user's access level.
   *
   * This operation integrates with the econ_political_discussion_users table as
   * defined in the Prisma schema, incorporating all available user fields and
   * maintaining proper temporal tracking (created_at, updated_at, deleted_at).
   * The response includes comprehensive user profile information optimized for
   * display and user management purposes.
   *
   * @param connection
   * @param email Email address of the target user account to retrieve
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @SystemadministratorAuth()
    systemAdministrator: SystemadministratorPayload,
    @TypedParam("email")
    email: string & tags.Format<"email">,
  ): Promise<IEconPoliticalDiscussionUser> {
    try {
      return await getUsersEmailEmail({
        systemAdministrator,
        email,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
