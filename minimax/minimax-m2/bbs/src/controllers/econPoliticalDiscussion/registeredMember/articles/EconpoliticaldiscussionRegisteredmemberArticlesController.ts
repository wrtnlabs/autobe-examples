import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postEconPoliticalDiscussionRegisteredMemberArticles } from "../../../../providers/postEconPoliticalDiscussionRegisteredMemberArticles";
import { RegisteredmemberAuth } from "../../../../decorators/RegisteredmemberAuth";
import { RegisteredmemberPayload } from "../../../../decorators/payload/RegisteredmemberPayload";
import { putEconPoliticalDiscussionRegisteredMemberArticlesArticleId } from "../../../../providers/putEconPoliticalDiscussionRegisteredMemberArticlesArticleId";
import { deleteEconPoliticalDiscussionRegisteredMemberArticlesArticleId } from "../../../../providers/deleteEconPoliticalDiscussionRegisteredMemberArticlesArticleId";

import { IEconPoliticalDiscussionArticle } from "../../../../api/structures/IEconPoliticalDiscussionArticle";

@Controller("/econPoliticalDiscussion/registeredMember/articles")
export class EconpoliticaldiscussionRegisteredmemberArticlesController {
  /**
   * Create a new economic and political discussion article in the discussion
   * board system.
   *
   * This operation allows users to create new discussion posts focused on
   * economic policies, political developments, market analysis, and related
   * topics. Each article becomes a primary discussion thread that other users
   * can engage with through comments and replies.
   *
   * The article creation process requires a title, detailed content, and
   * categorization for proper topic organization. The author field must be
   * provided to link the article to a user profile. The system automatically
   * sets the creation timestamp and establishes the default 'published' status
   * for immediate availability.
   *
   * Validation ensures that all required fields are provided with appropriate
   * content length and format. The category field allows classification of
   * discussions (e.g., 'Economic Policy', 'Political Analysis', 'Market
   * Discussion') for improved organization and search capabilities.
   *
   * Upon successful creation, the system returns the complete article object
   * including the generated UUID, author information, and all metadata. The
   * article becomes immediately available for viewing and attachment uploads
   * through the established relationships.
   *
   * This operation integrates with the econ_political_discussion_articles table
   * from the Prisma schema, incorporating all available article fields and the
   * foreign key relationship to the author user profile. The creation process
   * supports the complete article lifecycle management within the discussion
   * board platform.
   *
   * @param connection
   * @param body Data for creating a new economic and political discussion
   *   article
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @RegisteredmemberAuth()
    registeredMember: RegisteredmemberPayload,
    @TypedBody()
    body: IEconPoliticalDiscussionArticle.ICreate,
  ): Promise<IEconPoliticalDiscussionArticle> {
    try {
      return await postEconPoliticalDiscussionRegisteredMemberArticles({
        registeredMember,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing economic and political discussion article with complete
   * content modification.
   *
   * This operation enables authenticated users to modify their previously
   * created articles, allowing content updates, topic refinement, and status
   * changes. Users can update the article title, content body, category
   * classification, and publication status while maintaining the original
   * creation context and author attribution.
   *
   * The system validates that the requesting user has proper ownership rights
   * to modify the specified article, ensuring content integrity and preventing
   * unauthorized modifications. Only the article owner or users with
   * appropriate administrative permissions can execute updates.
   *
   * All article fields can be modified including the title for better topic
   * clarity, content for expanded discussion points, category for improved
   * topic organization, and status for publication management. The system
   * automatically updates the 'updated_at' timestamp to maintain accurate
   * modification history.
   *
   * Content validation ensures that updated articles meet the same quality
   * standards as newly created articles, including proper formatting,
   * appropriate content length, and valid categorization. The system preserves
   * the original creation date and author information while updating the
   * modification tracking.
   *
   * Upon successful update, the system returns the complete updated article
   * object with all current data including the preserved original creation
   * information and the new modification timestamp. The updated article
   * maintains all existing relationships including attachments and engagement
   * data.
   *
   * This operation interfaces with the econ_political_discussion_articles table
   * from the Prisma schema, maintaining all existing relationships and metadata
   * while updating the specified article fields. The update process ensures
   * data consistency and preserves the integrity of the discussion thread
   * within the economic and political discourse platform.
   *
   * @param connection
   * @param articleId Unique identifier of the target article to update
   * @param body Updated data for the existing economic and political discussion
   *   article
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":articleId")
  public async update(
    @RegisteredmemberAuth()
    registeredMember: RegisteredmemberPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEconPoliticalDiscussionArticle.IUpdate,
  ): Promise<IEconPoliticalDiscussionArticle> {
    try {
      return await putEconPoliticalDiscussionRegisteredMemberArticlesArticleId({
        registeredMember,
        articleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Soft delete a discussion article and all associated attachments from the
   * system.
   *
   * This operation performs a soft deletion of the specified article by setting
   * the deleted_at timestamp, which preserves historical data while marking the
   * content as removed for display purposes. It operates on the
   * econ_political_discussion_articles table from the Prisma schema.
   *
   * The soft deletion approach maintains referential integrity and allows for
   * potential content restoration in administrative contexts. All associated
   * econ_political_discussion_attachments records remain in the database but
   * are excluded from normal queries through the deleted_at filter.
   *
   * Security considerations include ownership verification where users can only
   * delete their own articles, unless they have administrative privileges. The
   * operation validates that the article exists and is not already marked as
   * deleted before proceeding with the removal.
   *
   * Upon successful deletion, the article and all attachments become
   * inaccessible through normal API endpoints, and the content is removed from
   * public view. The operation returns a confirmation response without exposing
   * sensitive article content.
   *
   * Related operations: Create article (POST /articles), Update article (PUT
   * /articles/{id}), View attachments (GET /articles/{id}/attachments).
   *
   * @param connection
   * @param articleId Unique identifier of the target discussion article to be
   *   deleted
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":articleId")
  public async erase(
    @RegisteredmemberAuth()
    registeredMember: RegisteredmemberPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteEconPoliticalDiscussionRegisteredMemberArticlesArticleId(
        {
          registeredMember,
          articleId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
