import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchEconPoliticalDiscussionCategories } from "../../../providers/patchEconPoliticalDiscussionCategories";
import { getEconPoliticalDiscussionCategoriesCategoryId } from "../../../providers/getEconPoliticalDiscussionCategoriesCategoryId";

import { IPageIEconPoliticalDiscussionCategorySummary } from "../../../api/structures/IPageIEconPoliticalDiscussionCategorySummary";
import { IEconPoliticalDiscussionCategory } from "../../../api/structures/IEconPoliticalDiscussionCategory";

@Controller("/econPoliticalDiscussion/categories")
export class EconpoliticaldiscussionCategoriesController {
  /**
   * Retrieve a filtered list of available topic categories for economic and
   * political discussions.
   *
   * This operation provides search and filtering capabilities for the category
   * classification system used in the discussion board. It extracts unique
   * category values from the econ_political_discussion_articles table and
   * supports category-based content discovery.
   *
   * The operation works by querying all articles to collect distinct category
   * values, then applying filtering and sorting logic. Categories can be
   * filtered by availability status (used/unused categories) and sorted
   * alphabetically or by usage frequency based on article counts.
   *
   * Security considerations ensure that category information is publicly
   * accessible to facilitate content discovery and navigation. The operation
   * applies rate limiting to prevent abuse and ensure system performance.
   *
   * The response includes category metadata such as usage statistics, article
   * counts per category, and availability status. This data helps users
   * understand category popularity and choose appropriate classifications for
   * their discussions.
   *
   * This operation serves as a precursor to article creation, allowing users to
   * see available category options before posting new content. Related
   * operations include Create article (POST /articles) where category is
   * required, and List articles by category (GET
   * /articles?category={category}).
   *
   * @param connection
   * @param body Search criteria and pagination parameters for category
   *   filtering and discovery
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IEconPoliticalDiscussionCategory.IRequest,
  ): Promise<IPageIEconPoliticalDiscussionCategorySummary> {
    try {
      return await patchEconPoliticalDiscussionCategories({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific discussion category.
   *
   * This operation provides comprehensive category information including name,
   * description, creation timestamp, and related statistics such as the number
   * of articles assigned to this category. Categories serve as the primary
   * classification system for organizing economic and political discussions on
   * the platform.
   *
   * The operation supports public access for content discovery and
   * categorization purposes, allowing users to understand available topic areas
   * and browse content by specific economic or political themes. This enhances
   * the user experience by enabling focused exploration of discussions.
   *
   * Category information includes temporal data showing when the category was
   * established and any updates to category metadata. The response also
   * provides article count statistics to help users understand content volume
   * within each category.
   *
   * This operation integrates with the article management system, allowing
   * users to view which articles are classified under this category and
   * facilitating content discovery based on topic interest. The category system
   * supports the platform's goal of organizing economic and political discourse
   * into meaningful topic areas.
   *
   * @param connection
   * @param categoryId Unique identifier of the target category for information
   *   retrieval
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":categoryId")
  public async at(
    @TypedParam("categoryId")
    categoryId: string & tags.Format<"uuid">,
  ): Promise<IEconPoliticalDiscussionCategory> {
    try {
      return await getEconPoliticalDiscussionCategoriesCategoryId({
        categoryId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
