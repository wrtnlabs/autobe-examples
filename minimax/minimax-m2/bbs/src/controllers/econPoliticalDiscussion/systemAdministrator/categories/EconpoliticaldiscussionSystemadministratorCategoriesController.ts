  /**
   * Update an existing discussion category in the economic and political
   * discussion board. This operation allows authorized users to modify category
   * information including the category name, description, and display order.
   * Categories are used to classify discussion articles by topic area such as
   * 'Economic Policy', 'Political Analysis', 'Market Discussion', and
   * 'Legislation Updates'.
   *
   * The operation validates that the category exists and has not been deleted,
   * then applies updates while maintaining referential integrity with existing
   * articles. Only authorized system administrators can update categories to
   * prevent unauthorized modifications that could disrupt the article
   * classification system.
   *
   * When updating a category, the system updates the category field in all
   * associated articles that reference the old category name. This ensures
   * consistency across the discussion board and prevents orphaned article
   * classifications. The operation maintains audit trails of category changes
   * for transparency and rollback purposes.
   *
   * The update process validates the new category name against existing
   * categories to prevent duplicates, and ensures the category follows naming
   * conventions for economic and political topics. If the category is being
   * renamed, all existing articles automatically migrate to the new category
   * name while preserving their publication status and engagement metrics.
   *
   * Related operations include listing categories (GET /categories), creating
   * new categories (POST /categories), and retrieving articles by category (GET
   * /articles?category={categoryId}). This operation integrates with the
   * article management system to maintain proper content organization and
   * discovery.
   *
   * @param connection
   * @param categoryId Unique identifier of the category to be updated (global
   *   scope)
   * @param body Category update information including new name, description,
   *   and display properties
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
