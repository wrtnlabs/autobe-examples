import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthRegisteredMemberJoin } from "../../../providers/postAuthRegisteredMemberJoin";
import { RegisteredmemberAuth } from "../../../decorators/RegisteredmemberAuth";
import { RegisteredmemberPayload } from "../../../decorators/payload/RegisteredmemberPayload";
import { postAuthRegisteredMemberLogin } from "../../../providers/postAuthRegisteredMemberLogin";
import { postAuthRegisteredMemberRefresh } from "../../../providers/postAuthRegisteredMemberRefresh";

import { IEconPoliticalDiscussionRegisteredMember } from "../../../api/structures/IEconPoliticalDiscussionRegisteredMember";

@Controller("/auth/registeredMember")
export class AuthRegisteredmemberController {
  /**
   * User registration operation for economic and political discussion board
   * participants.
   *
   * This endpoint creates a new user account in the
   * econ_political_discussion_users table with essential profile information.
   * The registration process requires basic user identification fields
   * including display name for article authorship and email address for account
   * management.
   *
   * The registration validates that the provided email address is unique across
   * all users and establishes initial account status as active. Users provide
   * their display name for community identification in discussions and can
   * optionally include biography information for community context.
   *
   * Upon successful registration, the system creates temporal tracking entries
   * (created_at, updated_at) and sets initial account status. The operation
   * supports the discussion board's author identification system where
   * registered users can create articles and participate in community
   * discussions.
   *
   * Registration is required for users who wish to create content, upload
   * attachments, and engage with the economic and political discussion
   * community. This endpoint establishes the foundational user identity used
   * throughout the discussion board platform.
   *
   * @param connection
   * @param body User registration data including display name for community
   *   identification and email address for account management
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @RegisteredmemberAuth()
    registeredMember: RegisteredmemberPayload,
    @TypedBody()
    body: IEconPoliticalDiscussionRegisteredMember.ICreate,
  ): Promise<IEconPoliticalDiscussionRegisteredMember.IAuthorized> {
    try {
      return await postAuthRegisteredMemberJoin({
        registeredMember,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * User authentication operation for economic and political discussion board
   * participants.
   *
   * This endpoint validates user credentials and establishes authenticated
   * sessions for registered members of the discussion board. The login process
   * verifies the provided email address against the
   * econ_political_discussion_users table and validates account status to
   * ensure the user is active and not suspended.
   *
   * Authentication success enables access to member-only features including
   * article creation, attachment uploads, profile management, and community
   * participation. The system maintains user session state through the
   * registered user identity established during account creation.
   *
   * The login operation updates temporal tracking (updated_at field) to reflect
   * the most recent user activity and maintains user status information from
   * the user's profile record. Successful authentication provides access tokens
   * that authorize the user's participation in discussion board activities.
   *
   * This authentication endpoint supports the discussion board's member-only
   * functionality where authenticated users can create economic and political
   * content, engage in community discussions, and manage their discussion
   * profiles.
   *
   * @param connection
   * @param body User authentication credentials including email address for
   *   account verification
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @RegisteredmemberAuth()
    registeredMember: RegisteredmemberPayload,
    @TypedBody()
    body: IEconPoliticalDiscussionRegisteredMember.ILogin,
  ): Promise<IEconPoliticalDiscussionRegisteredMember.IAuthorized> {
    try {
      return await postAuthRegisteredMemberLogin({
        registeredMember,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Token refresh operation for maintaining authenticated sessions for
   * registered discussion board members.
   *
   * This endpoint renews user access tokens for registered members while
   * maintaining their authenticated session state in the economic and political
   * discussion board. The refresh operation validates the provided refresh
   * token against the user's active session and updates temporal tracking to
   * reflect continued platform engagement.
   *
   * Token refresh ensures seamless user experience by extending session
   * lifetimes without requiring repeated authentication, while maintaining
   * security through refresh token validation. The operation preserves the
   * user's profile status and community identity established during
   * registration.
   *
   * The refresh mechanism updates user activity timestamps and maintains
   * session continuity for ongoing discussion board participation. This allows
   * users to continue creating articles, uploading attachments, and engaging in
   * economic and political discussions without authentication interruption.
   *
   * This endpoint is essential for maintaining long-term user sessions in the
   * discussion board platform, supporting continuous community participation
   * and content creation activities for authenticated members.
   *
   * @param connection
   * @param body Valid refresh token for extending user session lifetime
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @RegisteredmemberAuth()
    registeredMember: RegisteredmemberPayload,
    @TypedBody()
    body: IEconPoliticalDiscussionRegisteredMember.IRefresh,
  ): Promise<IEconPoliticalDiscussionRegisteredMember.IAuthorized> {
    try {
      return await postAuthRegisteredMemberRefresh({
        registeredMember,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
