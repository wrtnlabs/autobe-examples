import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthContentModeratorPasswordReset } from "../../../../../providers/postAuthContentModeratorPasswordReset";
import { ContentmoderatorAuth } from "../../../../../decorators/ContentmoderatorAuth";
import { ContentmoderatorPayload } from "../../../../../decorators/payload/ContentmoderatorPayload";

import { IEconPoliticalDiscussionContentModerator } from "../../../../../api/structures/IEconPoliticalDiscussionContentModerator";

@Controller("/auth/contentModerator/password/reset")
export class AuthContentmoderatorPasswordResetController {
  /**
   * Enables content moderators to reset their account password through secure
   * email verification. This operation supports password recovery for moderator
   * accounts when access is forgotten or compromised. The reset process
   * generates time-limited tokens sent via email to the registered moderator
   * address, ensuring secure password restoration. Password reset tokens expire
   * after 24 hours for security, requiring new token generation for expired
   * requests. The operation validates email existence in the
   * econ_political_discussion_users table and generates secure reset tokens
   * with cryptographic randomness. Upon token validation, moderators can set
   * new passwords meeting platform complexity requirements (8+ characters,
   * mixed case, numbers, special characters). This security function maintains
   * moderator account integrity while providing essential account recovery
   * capabilities for platform administrators.
   *
   * @param connection
   * @param body Password reset request with email address
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async resetPassword(
    @ContentmoderatorAuth()
    contentModerator: ContentmoderatorPayload,
    @TypedBody()
    body: IEconPoliticalDiscussionContentModerator.IResetPassword,
  ): Promise<IEconPoliticalDiscussionContentModerator.IPasswordResetResponse> {
    try {
      return await postAuthContentModeratorPasswordReset({
        contentModerator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
