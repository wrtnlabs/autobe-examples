import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthContentModeratorJoin } from "../../../../providers/postAuthContentModeratorJoin";
import { ContentmoderatorAuth } from "../../../../decorators/ContentmoderatorAuth";
import { ContentmoderatorPayload } from "../../../../decorators/payload/ContentmoderatorPayload";

import { IEconPoliticalDiscussionContentModerator } from "../../../../api/structures/IEconPoliticalDiscussionContentModerator";

@Controller("/auth/contentModerator/join")
export class AuthContentmoderatorJoinController {
  /**
   * Creates a new content moderator account for the economic and political
   * discussion board platform. This endpoint establishes a new moderator with
   * elevated permissions for content oversight, community management, and user
   * interaction moderation. The operation requires email verification before
   * full account activation, ensuring secure moderator onboarding. New
   * moderator accounts are created with the appropriate role permissions for
   * managing discussions, handling user reports, and enforcing community
   * guidelines. The registration process includes password complexity
   * requirements, terms acceptance, and community guidelines acknowledgment to
   * ensure moderator understanding of platform responsibilities. Upon
   * successful registration, the system generates initial JWT tokens for
   * immediate platform access while maintaining security protocols for
   * sensitive moderator functions.
   *
   * @param connection
   * @param body New content moderator registration information including email,
   *   password, and display name
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async register(
    @ContentmoderatorAuth()
    contentModerator: ContentmoderatorPayload,
    @TypedBody()
    body: IEconPoliticalDiscussionContentModerator.ICreate,
  ): Promise<IEconPoliticalDiscussionContentModerator.IAuthorized> {
    try {
      return await postAuthContentModeratorJoin({
        contentModerator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
