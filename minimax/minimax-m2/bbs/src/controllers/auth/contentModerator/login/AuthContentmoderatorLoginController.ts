import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthContentModeratorLogin } from "../../../../providers/postAuthContentModeratorLogin";
import { ContentmoderatorAuth } from "../../../../decorators/ContentmoderatorAuth";
import { ContentmoderatorPayload } from "../../../../decorators/payload/ContentmoderatorPayload";

import { IEconPoliticalDiscussionContentModerator } from "../../../../api/structures/IEconPoliticalDiscussionContentModerator";

@Controller("/auth/contentModerator/login")
export class AuthContentmoderatorLoginController {
  /**
   * Authenticates content moderator credentials and establishes secure session
   * with JWT token generation. This endpoint validates the moderator's email
   * and password against the stored account information in the
   * econ_political_discussion_users table. Upon successful authentication, the
   * system generates access and refresh tokens with appropriate expiration
   * times for security-sensitive moderator functions. Failed authentication
   * attempts are tracked and rate-limited to prevent unauthorized access
   * attempts. The login process maintains session security while enabling
   * immediate access to moderator dashboard and content management tools. Token
   * generation includes moderator-specific permissions and role identification
   * for proper authorization throughout the platform. Session creation supports
   * multi-device access while maintaining security protocols for moderator
   * account access.
   *
   * @param connection
   * @param body Content moderator login credentials (email and password)
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async authenticate(
    @ContentmoderatorAuth()
    contentModerator: ContentmoderatorPayload,
    @TypedBody()
    body: IEconPoliticalDiscussionContentModerator.ILogin,
  ): Promise<IEconPoliticalDiscussionContentModerator.IAuthorized> {
    try {
      return await postAuthContentModeratorLogin({
        contentModerator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
