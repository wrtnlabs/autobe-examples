import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthContentModeratorRefresh } from "../../../../providers/postAuthContentModeratorRefresh";
import { ContentmoderatorAuth } from "../../../../decorators/ContentmoderatorAuth";
import { ContentmoderatorPayload } from "../../../../decorators/payload/ContentmoderatorPayload";

import { IEconPoliticalDiscussionContentModerator } from "../../../../api/structures/IEconPoliticalDiscussionContentModerator";

@Controller("/auth/contentModerator/refresh")
export class AuthContentmoderatorRefreshController {
  /**
   * Refreshes expired JWT access tokens for authenticated content moderators
   * using valid refresh tokens. This endpoint enables seamless session renewal
   * without requiring re-authentication, maintaining moderator workflow
   * continuity during content management activities. The refresh mechanism
   * validates the provided refresh token against stored session data and
   * regenerates access tokens with extended expiration periods. Security
   * protocols ensure refresh tokens are single-use with automatic rotation upon
   * successful renewal. Invalid or compromised refresh tokens trigger mandatory
   * re-authentication flows for security maintenance. The token refresh process
   * maintains moderator permissions and role context while extending session
   * lifetime for continued platform access. This operation is essential for
   * maintaining active moderator sessions during extended content management
   * and community oversight activities.
   *
   * @param connection
   * @param body Refresh token for session renewal
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async renewSession(
    @ContentmoderatorAuth()
    contentModerator: ContentmoderatorPayload,
    @TypedBody()
    body: IEconPoliticalDiscussionContentModerator.IRefresh,
  ): Promise<IEconPoliticalDiscussionContentModerator.IAuthorized> {
    try {
      return await postAuthContentModeratorRefresh({
        contentModerator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
