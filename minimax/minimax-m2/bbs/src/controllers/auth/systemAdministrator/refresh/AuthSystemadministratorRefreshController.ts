import { Controller } from "@nestjs/common";
import { TypedRoute } from "@nestia/core";
import typia from "typia";
import { postAuthSystemAdministratorRefresh } from "../../../../providers/postAuthSystemAdministratorRefresh";
import { SystemadministratorAuth } from "../../../../decorators/SystemadministratorAuth";
import { SystemadministratorPayload } from "../../../../decorators/payload/SystemadministratorPayload";

import { IEconPoliticalDiscussionSystemAdministrator } from "../../../../api/structures/IEconPoliticalDiscussionSystemAdministrator";

@Controller("/auth/systemAdministrator/refresh")
export class AuthSystemadministratorRefreshController {
  /**
   * Refresh system administrator access tokens using a valid refresh token.
   *
   * This operation renews the access token for an authenticated system
   * administrator without requiring re-authentication. The endpoint validates
   * the provided refresh token against the server's token store and generates
   * new JWT access and refresh token pairs.
   *
   * System administrators use this operation to maintain their session without
   * logging in again, which is essential for:
   *
   * - Long administrative sessions
   * - Background system monitoring
   * - Automated administrative processes
   * - Maintaining security while avoiding frequent re-authentication
   *
   * Token refresh process:
   *
   * - Validates the refresh token against stored tokens
   * - Verifies the associated user account is still active
   * - Checks token expiration and revocation status
   * - Generates new access and refresh token pair
   * - Invalidates the old refresh token for security
   *
   * Upon successful token refresh, the system returns:
   *
   * - New access token with renewed admin privileges
   * - New refresh token for subsequent renewals
   * - Updated session expiration timestamps
   * - Current admin user profile information
   *
   * This operation requires a valid refresh token in the authorization header
   * and returns new tokens that extend the administrator's session. The old
   * refresh token is invalidated to prevent replay attacks and ensure security
   * best practices.
   *
   * This is a protected endpoint that requires the refresh token to be present
   * and valid. The response maintains all administrative privileges and access
   * levels that the previous session had.
   *
   * @param connection
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async renew(
    @SystemadministratorAuth()
    systemAdministrator: SystemadministratorPayload,
  ): Promise<IEconPoliticalDiscussionSystemAdministrator.IAuthorized> {
    try {
      return await postAuthSystemAdministratorRefresh({
        systemAdministrator,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
