import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthSystemAdministratorJoin } from "../../../../providers/postAuthSystemAdministratorJoin";
import { SystemadministratorAuth } from "../../../../decorators/SystemadministratorAuth";
import { SystemadministratorPayload } from "../../../../decorators/payload/SystemadministratorPayload";

import { IEconPoliticalDiscussionSystemAdministrator } from "../../../../api/structures/IEconPoliticalDiscussionSystemAdministrator";
import { IEconPoliticalDiscussionUser } from "../../../../api/structures/IEconPoliticalDiscussionUser";

@Controller("/auth/systemAdministrator/join")
export class AuthSystemadministratorJoinController {
  /**
   * Create a new system administrator account with full access privileges.
   *
   * This operation registers a new system administrator in the
   * econ_political_discussion_users table with the display_name and email
   * provided in the request body. The new admin account will be created with an
   * active status and initial authentication tokens will be issued.
   *
   * System administrators have full control over user management, system
   * settings, content moderation, and platform operations. This endpoint is
   * typically used during initial system setup or when adding new
   * administrative personnel.
   *
   * The operation creates a user record with:
   *
   * - Display_name: User's name for article authorship and community
   *   identification
   * - Email: User email address for account management and notifications
   * - Status: Set to 'active' for immediate admin access
   * - Created_at: Timestamp when the account was created
   * - Updated_at: Timestamp when the record was last modified
   *
   * Upon successful registration, the system returns:
   *
   * - Access token for immediate authentication
   * - Refresh token for obtaining new access tokens
   * - Admin user profile information
   * - Session expiration details
   *
   * This is a public endpoint that does not require prior authentication,
   * making it accessible for initial admin setup. The response includes JWT
   * tokens that provide immediate access to all administrative functions.
   *
   * @param connection
   * @param body Admin account creation information including display name and
   *   email
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SystemadministratorAuth()
    systemAdministrator: SystemadministratorPayload,
    @TypedBody()
    body: IEconPoliticalDiscussionUser.ICreate,
  ): Promise<IEconPoliticalDiscussionSystemAdministrator.IAuthorized> {
    try {
      return await postAuthSystemAdministratorJoin({
        systemAdministrator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
