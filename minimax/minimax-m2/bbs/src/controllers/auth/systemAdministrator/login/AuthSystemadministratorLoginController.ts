import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthSystemAdministratorLogin } from "../../../../providers/postAuthSystemAdministratorLogin";
import { SystemadministratorAuth } from "../../../../decorators/SystemadministratorAuth";
import { SystemadministratorPayload } from "../../../../decorators/payload/SystemadministratorPayload";

import { IEconPoliticalDiscussionSystemAdministrator } from "../../../../api/structures/IEconPoliticalDiscussionSystemAdministrator";
import { IEconPoliticalDiscussionUser } from "../../../../api/structures/IEconPoliticalDiscussionUser";

@Controller("/auth/systemAdministrator/login")
export class AuthSystemadministratorLoginController {
  /**
   * Authenticate an existing system administrator and issue access tokens.
   *
   * This operation validates the provided email and password credentials
   * against the econ_political_discussion_users table. Upon successful
   * authentication, the system generates JWT access and refresh tokens that
   * authorize the admin user to access all system functions.
   *
   * System administrators authenticated through this endpoint gain full
   * privileges including:
   *
   * - User management and account administration
   * - System configuration and settings management
   * - Content moderation and platform oversight
   * - Platform analytics and reporting access
   *
   * The authentication process:
   *
   * - Verifies the provided email exists in the user table
   * - Validates account status (must be 'active' for admin access)
   * - Checks authentication credentials
   * - Generates secure JWT tokens with appropriate expiration
   * - Logs authentication events for security audit
   *
   * Upon successful login, the system returns:
   *
   * - Access token with admin-level permissions
   * - Refresh token for token renewal
   * - Complete admin user profile
   * - Session metadata including expiration timestamps
   *
   * This is a public endpoint that enables existing administrators to access
   * their accounts. The response tokens provide immediate access to all
   * administrative API endpoints and dashboard functions.
   *
   * Failed authentication attempts are logged for security monitoring, and
   * appropriate HTTP status codes are returned to indicate authentication
   * success or failure.
   *
   * @param connection
   * @param body Admin login credentials including email
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async signIn(
    @SystemadministratorAuth()
    systemAdministrator: SystemadministratorPayload,
    @TypedBody()
    body: IEconPoliticalDiscussionUser.ILogin,
  ): Promise<IEconPoliticalDiscussionSystemAdministrator.IAuthorized> {
    try {
      return await postAuthSystemAdministratorLogin({
        systemAdministrator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
