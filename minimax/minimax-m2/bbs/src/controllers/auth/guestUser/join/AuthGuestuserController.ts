import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthGuestUserJoin } from "../../../../providers/postAuthGuestUserJoin";
import { GuestuserAuth } from "../../../../decorators/GuestuserAuth";
import { GuestuserPayload } from "../../../../decorators/payload/GuestuserPayload";

import { IEconPoliticalDiscussionGuestUser } from "../../../../api/structures/IEconPoliticalDiscussionGuestUser";

@Controller("/auth/guestUser/join")
export class AuthGuestuserController {
  /**
   * Create a new guest user account for the economic and political discussion
   * board. This endpoint allows anonymous visitors to register and gain limited
   * access to participate in discussions.
   *
   * The operation validates the provided display_name and email against the
   * econ_political_discussion_users table constraints, ensuring email
   * uniqueness and proper display name formatting. Upon successful
   * registration, the system creates a new user record with active status and
   * issues temporary JWT tokens for initial access.
   *
   * The registration process incorporates the user table's required fields
   * including display_name for community identification, email for account
   * management, and optional bio and avatar_url for profile enhancement. The
   * system sets status to 'active' by default and applies soft delete support
   * via deleted_at field.
   *
   * This guest registration enables new users to create articles, participate
   * in discussions, and build their community presence. The operation
   * establishes the foundation for user engagement within the discussion board
   * platform while maintaining proper data integrity through database
   * constraints.
   *
   * Related operations include token refresh for session maintenance and
   * article creation endpoints that utilize the authenticated user context
   * provided by successful registration.
   *
   * @param connection
   * @param body Guest user registration data containing display name and email
   *   information required for account creation.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async join(
    @GuestuserAuth()
    guestUser: GuestuserPayload,
    @TypedBody()
    body: IEconPoliticalDiscussionGuestUser.ICreate,
  ): Promise<IEconPoliticalDiscussionGuestUser.IAuthorized> {
    try {
      return await postAuthGuestUserJoin({
        guestUser,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
