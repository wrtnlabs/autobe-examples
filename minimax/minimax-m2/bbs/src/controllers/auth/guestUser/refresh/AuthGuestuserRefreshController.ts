import { Controller } from "@nestjs/common";
import { TypedRoute } from "@nestia/core";
import typia from "typia";
import { postAuthGuestUserRefresh } from "../../../../providers/postAuthGuestUserRefresh";
import { GuestuserAuth } from "../../../../decorators/GuestuserAuth";
import { GuestuserPayload } from "../../../../decorators/payload/GuestuserPayload";

import { IEconPoliticalDiscussionGuestUser } from "../../../../api/structures/IEconPoliticalDiscussionGuestUser";

@Controller("/auth/guestUser/refresh")
export class AuthGuestuserRefreshController {
  /**
   * Refresh temporary access tokens for authenticated guest users in the
   * economic and political discussion board. This endpoint extends the user
   * session without requiring credential revalidation.
   *
   * The operation validates the provided refresh token against the user's
   * active session state, ensuring the token corresponds to a valid,
   * non-expired user account in the econ_political_discussion_users table. Upon
   * successful validation, the system generates new access and refresh tokens
   * while maintaining the user's authenticated context.
   *
   * The refresh mechanism respects the user table's status field, allowing
   * token refresh only for accounts with 'active' status. It also considers
   * soft delete functionality through the deleted_at field, preventing token
   * refresh for deactivated accounts.
   *
   * This operation is essential for maintaining persistent user sessions during
   * extended discussion participation. It supports the guest user's continued
   * access to article creation, comment participation, and other authenticated
   * features without requiring repeated login.
   *
   * The refresh process integrates seamlessly with the initial authentication
   * flow established during guest registration, providing a complete session
   * management solution for discussion board participants.
   *
   * @param connection
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async refreshToken(
    @GuestuserAuth()
    guestUser: GuestuserPayload,
  ): Promise<IEconPoliticalDiscussionGuestUser.IAuthorized> {
    try {
      return await postAuthGuestUserRefresh({
        guestUser,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
