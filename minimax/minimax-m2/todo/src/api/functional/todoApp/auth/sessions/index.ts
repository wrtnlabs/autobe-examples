import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

/**
 * Terminate an active user session by deleting it from the database. This
 * operation performs a hard delete of the specified session record, removing
 * all session data including connection metadata, IP addresses, and
 * timestamps.
 *
 * The operation works with both member sessions (todo_app_member_sessions) and
 * administrator sessions (todo_app_administrator_sessions) to provide
 * consistent session termination capabilities across all user types. When a
 * session is deleted, the user must re-authenticate to access protected Todo
 * functionality.
 *
 * This operation ensures security by allowing users to manually terminate
 * sessions from potentially compromised devices or locations. The session
 * deletion is permanent and cannot be recovered, providing complete access
 * revocation.
 *
 * Session termination includes cleanup of all associated session metadata such
 * as IP addresses, connection URLs, referrer information, and timestamps. The
 * operation logs the deletion event for audit purposes while removing the
 * session data itself.
 *
 * Security Note: Only authenticated users can delete sessions, and users can
 * only terminate their own sessions. The system verifies session ownership
 * before allowing deletion to prevent unauthorized session termination
 * attacks.
 *
 * @param props.connection
 * @param props.sessionId Unique identifier of the target session to be
 *   terminated
 * @path /todoApp/auth/sessions/:sessionId
 * @accessor api.functional.todoApp.auth.sessions.erase
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function erase(
  connection: IConnection,
  props: erase.Props,
): Promise<void> {
  return true === connection.simulate
    ? erase.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...erase.METADATA,
          path: erase.path(props),
          status: null,
        },
      );
}
export namespace erase {
  export type Props = {
    /** Unique identifier of the target session to be terminated */
    sessionId: string & tags.Format<"uuid">;
  };

  export const METADATA = {
    method: "DELETE",
    path: "/todoApp/auth/sessions/:sessionId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/todoApp/auth/sessions/${encodeURIComponent(props.sessionId ?? "null")}`;
  export const random = (): void => typia.random<void>();
  export const simulate = (
    connection: IConnection,
    props: erase.Props,
  ): void => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: erase.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("sessionId")(() => typia.assert(props.sessionId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
