import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ITodoAppMember } from "../../../../../structures/ITodoAppMember";

/**
 * Retrieve a comprehensive member profile with complete todo management
 * information. This operation provides detailed member data including personal
 * information, account status, and todo summary statistics for effective member
 * management and todo system navigation.
 *
 * This endpoint operates on the Member table from the Prisma schema and returns
 * detailed member information optimized for profile management and user
 * experience. The member profile includes personal details like name, email,
 * and account status along with todo-related metadata for administrative
 * oversight.
 *
 * Security considerations include proper member identification through the
 * memberId parameter and appropriate data filtering to ensure members can only
 * access their own profile information. The response is designed to be
 * immediately usable in user interfaces without requiring additional API calls
 * for todo statistics.
 *
 * This operation integrates with both the Member table and associated Todo
 * records to provide a comprehensive view of the member's current todo
 * management status. The response structure includes todo count summaries and
 * status distributions for quick dashboard display and member progress
 * tracking.
 *
 * @param props.connection
 * @param props.memberId Unique identifier of the target member whose profile
 *   information is being retrieved
 * @path /todoApp/member/members/:memberId/profile
 * @accessor api.functional.todoApp.member.members.profile.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique identifier of the target member whose profile information is
     * being retrieved
     */
    memberId: string & tags.Format<"uuid">;
  };
  export type Response = ITodoAppMember.IInvert;

  export const METADATA = {
    method: "GET",
    path: "/todoApp/member/members/:memberId/profile",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/todoApp/member/members/${encodeURIComponent(props.memberId ?? "null")}/profile`;
  export const random = (): ITodoAppMember.IInvert =>
    typia.random<ITodoAppMember.IInvert>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("memberId")(() => typia.assert(props.memberId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
