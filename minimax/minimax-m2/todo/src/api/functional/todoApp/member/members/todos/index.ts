import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ITodoAppTodo } from "../../../../../structures/ITodoAppTodo";
import { IPageITodoAppTodo } from "../../../../../structures/IPageITodoAppTodo";

/**
 * Search and filter todo items belonging to a specific member with advanced
 * query capabilities. This operation provides comprehensive todo management
 * functionality allowing members to view, filter, and organize their personal
 * tasks efficiently.
 *
 * The operation supports multiple filtering criteria including todo status
 * (pending, in_progress, completed, cancelled), priority levels (low, medium,
 * high, urgent), categories, due date ranges, and completion timestamps.
 * Advanced sorting options enable users to organize todos by creation date,
 * priority, due date, or completion status.
 *
 * Security is enforced through member-specific access control where users can
 * only access todos that belong to their own member ID. The system prevents
 * unauthorized access to other members' todos and provides rate limiting to
 * ensure optimal performance during high-traffic usage.
 *
 * This operation returns paginated results optimized for list display with
 * optional inclusion of todo descriptions and detailed metadata. The response
 * format supports efficient client-side filtering and sorting while maintaining
 * data privacy boundaries between different members.
 *
 * Integration with the Todo table provides access to all todo fields including
 * title, description, status tracking, business workflow states, priority
 * management, categorization, and due date handling. The search capabilities
 * enable precise todo discovery for effective personal task management.
 *
 * @param props.connection
 * @param props.memberId Unique identifier of the member whose todo items are
 *   being searched and retrieved
 * @param props.body Search criteria and filtering parameters for member's todo
 *   items with pagination support
 * @path /todoApp/member/members/:memberId/todos
 * @accessor api.functional.todoApp.member.members.todos.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Unique identifier of the member whose todo items are being searched
     * and retrieved
     */
    memberId: string & tags.Format<"uuid">;

    /**
     * Search criteria and filtering parameters for member's todo items with
     * pagination support
     */
    body: ITodoAppTodo.IRequest;
  };
  export type Body = ITodoAppTodo.IRequest;
  export type Response = IPageITodoAppTodo.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/todoApp/member/members/:memberId/todos",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/todoApp/member/members/${encodeURIComponent(props.memberId ?? "null")}/todos`;
  export const random = (): IPageITodoAppTodo.ISummary =>
    typia.random<IPageITodoAppTodo.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("memberId")(() => typia.assert(props.memberId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
