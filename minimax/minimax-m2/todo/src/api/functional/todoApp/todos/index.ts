import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ITodoAppTodo } from "../../../structures/ITodoAppTodo";

/**
 * Retrieve a specific todo item by its unique identifier from the TodoApp
 * system.
 *
 * This operation retrieves detailed information about a single todo item based
 * on the provided todo ID. The todo item must exist in the database and not be
 * soft-deleted (deleted_at must be null). The response includes all todo item
 * details including title, description, status, priority, category, due date,
 * and timestamps.
 *
 * The todo item may belong to either a member or administrator user, as
 * indicated by the foreign key relationships. This operation is essential for
 * displaying detailed todo information in user interfaces and for performing
 * operations that require full todo context.
 *
 * Security: This operation requires authentication. Users must be logged in as
 * either a member or administrator to access todo items. The system will verify
 * that the authenticated user has appropriate permissions to view the requested
 * todo item.
 *
 * The operation references the todo_app_todos table from the Prisma schema,
 * which stores individual task items with comprehensive tracking information.
 * All fields from the database schema are included in the response, providing
 * complete visibility into the todo item's current state and metadata.
 *
 * This is a read-only operation that does not modify any data in the system.
 * The operation supports the core TodoApp functionality by enabling
 * authenticated users to view and manage their specific todo items with full
 * context.
 *
 * @param props.connection
 * @param props.todoId Unique identifier of the target todo item in UUID format
 * @path /todoApp/todos/:todoId
 * @accessor api.functional.todoApp.todos.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique identifier of the target todo item in UUID format */
    todoId: string & tags.Format<"uuid">;
  };
  export type Response = ITodoAppTodo;

  export const METADATA = {
    method: "GET",
    path: "/todoApp/todos/:todoId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/todoApp/todos/${encodeURIComponent(props.todoId ?? "null")}`;
  export const random = (): ITodoAppTodo => typia.random<ITodoAppTodo>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("todoId")(() => typia.assert(props.todoId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
