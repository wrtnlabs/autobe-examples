import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ITodoAppAdministrator } from "../../../../../structures/ITodoAppAdministrator";

/**
 * Retrieve comprehensive profile information for a specific administrator
 * account from the TodoApp system.
 *
 * This operation accesses the todo_app_administrators table from the Prisma
 * schema and returns detailed administrator profile data including personal
 * information, role level, and current account status. The operation supports
 * administrative profile viewing for system oversight and user management
 * purposes.
 *
 * The endpoint requires administrative authentication and returns administrator
 * profile information excluding sensitive authentication data like password
 * hashes. Profile data includes name information, role level for permission
 * verification, account status for access control, and creation/modification
 * timestamps for audit trail purposes.
 *
 * This operation integrates with the todo_app_administrators table as defined
 * in the Prisma schema, incorporating all available administrator profile
 * fields and providing a comprehensive view of the administrator account
 * details. The response includes profile summary information optimized for
 * administrative interface displays.
 *
 * Security considerations include proper access control ensuring only
 * authenticated administrators can access profile information, and appropriate
 * filtering of sensitive administrator details. The operation validates
 * administrator existence and provides detailed account status information for
 * administrative oversight functions.
 *
 * @param props.connection
 * @param props.administratorId Unique identifier of the target administrator
 *   account
 * @path /todoApp/admin/administrators/:administratorId/profile
 * @accessor api.functional.todoApp.admin.administrators.profile.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique identifier of the target administrator account */
    administratorId: string & tags.Format<"uuid">;
  };
  export type Response = ITodoAppAdministrator;

  export const METADATA = {
    method: "GET",
    path: "/todoApp/admin/administrators/:administratorId/profile",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/todoApp/admin/administrators/${encodeURIComponent(props.administratorId ?? "null")}/profile`;
  export const random = (): ITodoAppAdministrator =>
    typia.random<ITodoAppAdministrator>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("administratorId")(() =>
        typia.assert(props.administratorId),
      );
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
