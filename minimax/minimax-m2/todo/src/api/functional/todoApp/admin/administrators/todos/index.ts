import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ITodoAppTodo } from "../../../../../structures/ITodoAppTodo";
import { IPageITodoAppTodo } from "../../../../../structures/IPageITodoAppTodo";

/**
 * Search, filter, and retrieve todo items owned by a specific administrator
 * from the TodoApp system.
 *
 * This operation accesses the todo_app_todos table from the Prisma schema and
 * provides comprehensive search and filtering capabilities for finding todo
 * items based on multiple criteria including task status, priority level, due
 * date ranges, categories, and completion tracking. The operation is scoped to
 * todos owned by the specified administrator through the
 * todo_app_administrator_id foreign key relationship.
 *
 * The operation supports advanced pagination with configurable page sizes and
 * sorting options. Todo items can be filtered by status (pending, in_progress,
 * completed, cancelled), priority level (low, medium, high, urgent), business
 * workflow status (active, on_hold, archived), and due date ranges. Results can
 * be sorted by creation date, due date, priority, or completion status.
 *
 * This operation integrates with the todo_app_todos table as defined in the
 * Prisma schema, incorporating all available todo fields and relationships. The
 * response includes todo summary information optimized for list displays with
 * options to include additional details based on administrative needs.
 *
 * Security considerations include proper authorization ensuring only the
 * specified administrator or system admins can access todo information, with
 * appropriate filtering of personal task data. Rate limiting applies to search
 * operations to prevent excessive queries, and the operation validates
 * administrator ownership of returned todo items.
 *
 * The query functionality allows administrators to efficiently manage their
 * personal todo list with comprehensive search capabilities including text
 * search across title and description fields, status-based filtering, priority
 * organization, and deadline management through due date filtering.
 *
 * @param props.connection
 * @param props.body Search criteria and pagination parameters for todo item
 *   filtering and retrieval
 * @path /todoApp/admin/administrators/:administratorId/todos
 * @accessor api.functional.todoApp.admin.administrators.todos.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    administratorId: string;

    /**
     * Search criteria and pagination parameters for todo item filtering and
     * retrieval
     */
    body: ITodoAppTodo.IRequest;
  };
  export type Body = ITodoAppTodo.IRequest;
  export type Response = IPageITodoAppTodo.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/todoApp/admin/administrators/:administratorId/todos",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/todoApp/admin/administrators/${encodeURIComponent(props.administratorId ?? "null")}/todos`;
  export const random = (): IPageITodoAppTodo.ISummary =>
    typia.random<IPageITodoAppTodo.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("administratorId")(() =>
        typia.assert(props.administratorId),
      );
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
