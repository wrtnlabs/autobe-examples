import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ITodoAppMember } from "../../../../structures/ITodoAppMember";

/**
 * Creates a new member account in the TodoApp system and establishes the
 * initial authentication session.
 *
 * This endpoint allows new users to register for TodoApp access by providing
 * their email address and basic profile information. Upon successful
 * registration, the system creates a new todo_app_members record with the
 * provided email, first name, last name, and sets the account status to
 * 'active'. A corresponding todo_app_member_sessions record is also created to
 * track the registration session with connection metadata including IP address,
 * connection URL, and referrer information.
 *
 * The registration process generates initial JWT tokens for the new member,
 * enabling immediate access to Todo management functionality. The session is
 * tracked with detailed connection metadata for security monitoring and audit
 * purposes. Members can register with optional first and last names, but must
 * provide a unique email address that serves as their account identifier.
 *
 * This operation is essential for onboarding new users to the TodoApp system
 * and establishing their initial authenticated session. After registration,
 * members can immediately start creating and managing their personal Todo items
 * using other authenticated endpoints.
 *
 * @param props.connection
 * @param props.body Member registration information including email and
 *   optional profile details
 * @setHeader token.access Authorization
 *
 * @path /auth/member/join
 * @accessor api.functional.auth.member.join.registerMember
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function registerMember(
  connection: IConnection,
  props: registerMember.Props,
): Promise<registerMember.Response> {
  const output: registerMember.Response =
    true === connection.simulate
      ? registerMember.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...registerMember.METADATA,
            path: registerMember.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
export namespace registerMember {
  export type Props = {
    /**
     * Member registration information including email and optional profile
     * details
     */
    body: ITodoAppMember.ICreate;
  };
  export type Body = ITodoAppMember.ICreate;
  export type Response = ITodoAppMember.IAuthorized;

  export const METADATA = {
    method: "POST",
    path: "/auth/member/join",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/member/join";
  export const random = (): ITodoAppMember.IAuthorized =>
    typia.random<ITodoAppMember.IAuthorized>();
  export const simulate = (
    connection: IConnection,
    props: registerMember.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: registerMember.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
