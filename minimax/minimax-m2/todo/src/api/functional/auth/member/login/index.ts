import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ITodoAppMember } from "../../../../structures/ITodoAppMember";

/**
 * Authenticates an existing member user and establishes a new authenticated
 * session with comprehensive security tracking.
 *
 * This endpoint validates member credentials and creates a new
 * todo_app_member_sessions record for ongoing Todo management access. The
 * system verifies the member exists in the todo_app_members table and has an
 * 'active' status before creating the session. Upon successful authentication,
 * the member gains access to their personal Todo items and can perform all CRUD
 * operations on their own data.
 *
 * The login process creates a new session record with detailed connection
 * metadata including the member's IP address, connection URL, and referrer URL
 * for comprehensive security monitoring and audit trails. This enables the
 * system to track login patterns, detect suspicious activity, and provide
 * detailed session management capabilities for individual members.
 *
 * After successful authentication, JWT tokens are issued that enable the member
 * to access authenticated Todo management endpoints. The session tracking
 * ensures all Todo operations can be properly attributed to the authenticated
 * member and provides the foundation for comprehensive security monitoring and
 * user activity analysis.
 *
 * @param props.connection
 * @param props.body Member login credentials for authentication
 * @setHeader token.access Authorization
 *
 * @path /auth/member/login
 * @accessor api.functional.auth.member.login.authenticateMember
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function authenticateMember(
  connection: IConnection,
  props: authenticateMember.Props,
): Promise<authenticateMember.Response> {
  const output: authenticateMember.Response =
    true === connection.simulate
      ? authenticateMember.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...authenticateMember.METADATA,
            path: authenticateMember.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
export namespace authenticateMember {
  export type Props = {
    /** Member login credentials for authentication */
    body: ITodoAppMember.ILogin;
  };
  export type Body = ITodoAppMember.ILogin;
  export type Response = ITodoAppMember.IAuthorized;

  export const METADATA = {
    method: "POST",
    path: "/auth/member/login",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/member/login";
  export const random = (): ITodoAppMember.IAuthorized =>
    typia.random<ITodoAppMember.IAuthorized>();
  export const simulate = (
    connection: IConnection,
    props: authenticateMember.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: authenticateMember.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
