import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ITodoAppMember } from "../../../../structures/ITodoAppMember";

/**
 * Refreshes the authentication tokens for an existing member session, extending
 * access to Todo management functionality.
 *
 * This endpoint allows members to renew their JWT access tokens using a valid
 * refresh token without requiring re-authentication with their credentials. The
 * system validates the refresh token against existing todo_app_member_sessions
 * records to ensure the session is still active and hasn't expired. Members can
 * refresh their tokens as long as they have a valid session record in the
 * database.
 *
 * Token refresh is essential for maintaining seamless access to Todo management
 * features without interrupting the user's workflow. When a refresh is
 * successful, new JWT tokens are issued while maintaining the existing session
 * context and security tracking. The refresh operation updates the session
 * expiration time to extend the member's authenticated access period.
 *
 * This operation is crucial for user experience optimization, allowing members
 * to continue managing their Todo items without needing to repeatedly log in.
 * It supports the TodoApp's goal of providing efficient task management by
 * maintaining persistent, secure authentication sessions for active members.
 *
 * @param props.connection
 * @param props.body Member refresh token for extending authentication session
 * @setHeader token.access Authorization
 *
 * @path /auth/member/refresh
 * @accessor api.functional.auth.member.refresh.refreshMemberToken
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function refreshMemberToken(
  connection: IConnection,
  props: refreshMemberToken.Props,
): Promise<refreshMemberToken.Response> {
  const output: refreshMemberToken.Response =
    true === connection.simulate
      ? refreshMemberToken.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...refreshMemberToken.METADATA,
            path: refreshMemberToken.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
export namespace refreshMemberToken {
  export type Props = {
    /** Member refresh token for extending authentication session */
    body: ITodoAppMember.IRefresh;
  };
  export type Body = ITodoAppMember.IRefresh;
  export type Response = ITodoAppMember.IAuthorized;

  export const METADATA = {
    method: "POST",
    path: "/auth/member/refresh",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/member/refresh";
  export const random = (): ITodoAppMember.IAuthorized =>
    typia.random<ITodoAppMember.IAuthorized>();
  export const simulate = (
    connection: IConnection,
    props: refreshMemberToken.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: refreshMemberToken.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
