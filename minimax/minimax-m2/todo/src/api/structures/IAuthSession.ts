import { tags } from "typia";

import { ITodoAppMember } from "./ITodoAppMember";

/**
 * Represents authentication session information from either member or
 * administrator contexts. This unified session type supports cross-role session
 * management and administrative oversight, enabling security monitoring and
 * audit capabilities across different user types.
 *
 * The session captures essential connection metadata including IP address,
 * referrer information, and session lifecycle timing. Each session is
 * associated with a specific user type (member or administrator) and includes
 * comprehensive tracking for security investigations, user support activities,
 * and compliance auditing.
 *
 * Sessions maintain independent lifecycle management with creation timestamps
 * and optional expiration handling. The type supports unified session retrieval
 * across both todo_app_member_sessions and todo_app_administrator_sessions
 * tables while preserving role-specific context and security boundaries.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type IAuthSession = {
  /**
   * Unique identifier of the authentication session for tracking and
   * administrative reference
   */
  id: string & tags.Format<"uuid">;

  /**
   * Complete user account information for this session including profile
   * details and status. Provides full context for session ownership and user
   * association without requiring additional API calls.
   */
  user: ITodoAppMember.ISummary;

  /**
   * Type of user account associated with this session for role identification
   * and proper data access routing
   */
  user_type: "member" | "administrator";

  /**
   * User's IP address for connection tracking and security monitoring. Used
   * to identify session origin, detect suspicious login patterns, and support
   * geographic security analysis
   */
  ip: string;

  /**
   * Connection URL where the session was established. Records the originating
   * URL or endpoint for session audit, security analysis, and user experience
   * tracking
   */
  href: string & tags.Format<"uri">;

  /**
   * Referrer URL that led to the session creation. Provides context for how
   * the user accessed the system for security analysis, marketing
   * attribution, and user journey tracking
   */
  referrer: string & tags.Format<"uri">;

  /**
   * Session creation timestamp. Records when the user successfully
   * authenticated and established this session for audit trail and session
   * lifecycle management
   */
  created_at: string & tags.Format<"date-time">;
};
