import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { getTodoAppTodosTodoId } from "../../../providers/getTodoAppTodosTodoId";

import { ITodoAppTodo } from "../../../api/structures/ITodoAppTodo";

@Controller("/todoApp/todos/:todoId")
export class TodoappTodosController {
  /**
   * Retrieve a specific todo item by its unique identifier from the TodoApp
   * system.
   *
   * This operation retrieves detailed information about a single todo item
   * based on the provided todo ID. The todo item must exist in the database and
   * not be soft-deleted (deleted_at must be null). The response includes all
   * todo item details including title, description, status, priority, category,
   * due date, and timestamps.
   *
   * The todo item may belong to either a member or administrator user, as
   * indicated by the foreign key relationships. This operation is essential for
   * displaying detailed todo information in user interfaces and for performing
   * operations that require full todo context.
   *
   * Security: This operation requires authentication. Users must be logged in
   * as either a member or administrator to access todo items. The system will
   * verify that the authenticated user has appropriate permissions to view the
   * requested todo item.
   *
   * The operation references the todo_app_todos table from the Prisma schema,
   * which stores individual task items with comprehensive tracking information.
   * All fields from the database schema are included in the response, providing
   * complete visibility into the todo item's current state and metadata.
   *
   * This is a read-only operation that does not modify any data in the system.
   * The operation supports the core TodoApp functionality by enabling
   * authenticated users to view and manage their specific todo items with full
   * context.
   *
   * @param connection
   * @param todoId Unique identifier of the target todo item in UUID format
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppTodo> {
    try {
      return await getTodoAppTodosTodoId({
        todoId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
