import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { getTodoAppAdminAdministratorsAdministratorIdProfile } from "../../../../../providers/getTodoAppAdminAdministratorsAdministratorIdProfile";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";

import { ITodoAppAdministrator } from "../../../../../api/structures/ITodoAppAdministrator";

@Controller("/todoApp/admin/administrators/:administratorId/profile")
export class TodoappAdminAdministratorsProfileController {
  /**
   * Retrieve comprehensive profile information for a specific administrator
   * account from the TodoApp system.
   *
   * This operation accesses the todo_app_administrators table from the Prisma
   * schema and returns detailed administrator profile data including personal
   * information, role level, and current account status. The operation supports
   * administrative profile viewing for system oversight and user management
   * purposes.
   *
   * The endpoint requires administrative authentication and returns
   * administrator profile information excluding sensitive authentication data
   * like password hashes. Profile data includes name information, role level
   * for permission verification, account status for access control, and
   * creation/modification timestamps for audit trail purposes.
   *
   * This operation integrates with the todo_app_administrators table as defined
   * in the Prisma schema, incorporating all available administrator profile
   * fields and providing a comprehensive view of the administrator account
   * details. The response includes profile summary information optimized for
   * administrative interface displays.
   *
   * Security considerations include proper access control ensuring only
   * authenticated administrators can access profile information, and
   * appropriate filtering of sensitive administrator details. The operation
   * validates administrator existence and provides detailed account status
   * information for administrative oversight functions.
   *
   * @param connection
   * @param administratorId Unique identifier of the target administrator
   *   account
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("administratorId")
    administratorId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppAdministrator> {
    try {
      return await getTodoAppAdminAdministratorsAdministratorIdProfile({
        admin,
        administratorId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
