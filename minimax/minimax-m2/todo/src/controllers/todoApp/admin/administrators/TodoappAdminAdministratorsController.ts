import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { getTodoAppAdminAdministrators } from "../../../../providers/getTodoAppAdminAdministrators";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { patchTodoAppAdminAdministrators } from "../../../../providers/patchTodoAppAdminAdministrators";
import { putTodoAppAdminAdministratorsAdministratorId } from "../../../../providers/putTodoAppAdminAdministratorsAdministratorId";
import { deleteTodoAppAdminAdministratorsAdministratorId } from "../../../../providers/deleteTodoAppAdminAdministratorsAdministratorId";

import { IPageITodoAppAdministrator } from "../../../../api/structures/IPageITodoAppAdministrator";
import { ITodoAppAdministrator } from "../../../../api/structures/ITodoAppAdministrator";

@Controller("/todoApp/admin/administrators")
export class TodoappAdminAdministratorsController {
  /**
   * Retrieve a comprehensive list of system administrators from the
   * todo_app_administrators table with advanced filtering, sorting, and
   * pagination capabilities. This operation serves administrative oversight
   * purposes by providing system-wide visibility into all administrator
   * accounts, their roles, status, and activity patterns.
   *
   * The operation interfaces with the todo_app_administrators Prisma schema
   * which contains system-wide administrative accounts with elevated
   * permissions. Each administrator record includes email (unique), encrypted
   * password_hash, first_name, last_name, role_level (super_admin, admin,
   * moderator), status (active, suspended, deactivated), and audit timestamps
   * (created_at, updated_at, deleted_at for soft deletion).
   *
   * Security considerations include proper authorization checking to ensure
   * only authorized administrative users can access this endpoint. The response
   * provides summarized administrator information optimized for administrative
   * dashboards and user management interfaces, including role level indicators
   * and current account status for operational oversight.
   *
   * This endpoint supports comprehensive filtering by role_level, status,
   * creation date ranges, and name-based searches across first_name and
   * last_name fields. Pagination parameters enable efficient handling of large
   * administrative user bases while maintaining responsive performance. The
   * operation includes detailed audit trail information for compliance and
   * security monitoring purposes.
   *
   * @param connection
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @AdminAuth()
    admin: AdminPayload,
  ): Promise<IPageITodoAppAdministrator.ISummary> {
    try {
      return await getTodoAppAdminAdministrators({
        admin,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and filter system administrators through advanced query capabilities
   * on the todo_app_administrators table. This operation provides comprehensive
   * search functionality for administrative user management, enabling efficient
   * retrieval of specific administrator subsets based on multiple criteria
   * including role levels, account status, creation dates, and name-based
   * searches.
   *
   * The operation works with the todo_app_administrators Prisma schema which
   * maintains system administrators with unique email constraints, role-based
   * permissions (super_admin, admin, moderator), and account lifecycle
   * management (active, suspended, deactivated). The search functionality
   * supports complex queries across multiple fields including exact matches,
   * partial text searches in name fields, date range filtering, and
   * status-based filtering.
   *
   * Advanced filtering capabilities include role_level-based searches,
   * status-based queries for account management, creation timestamp ranges for
   * activity analysis, and text-based searches across first_name and last_name
   * fields for user identification. The operation supports sorting by multiple
   * fields including creation date, last updated time, role level hierarchy,
   * and alphabetical name ordering.
   *
   * This endpoint facilitates administrative user management workflows by
   * providing efficient search capabilities for system administrators, user
   * support teams, and compliance monitoring. The response includes paginated
   * results with comprehensive filtering metadata for operational analytics and
   * user management dashboards.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for administrator
   *   filtering including role level filters, status queries, date ranges, and
   *   text search capabilities
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: ITodoAppAdministrator.IRequest,
  ): Promise<IPageITodoAppAdministrator.ISummary> {
    try {
      return await patchTodoAppAdminAdministrators({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing administrator account with full information modification
   * capabilities. This operation operates on the todo_app_administrators table
   * and allows authorized administrators to modify administrative user details
   * including role levels, status, names, and other account properties.
   *
   * The operation validates that the target administrator exists and is not
   * soft-deleted before proceeding with updates. Security considerations
   * include role-based access control ensuring only administrators with
   * sufficient privileges can modify other administrative accounts. The
   * operation performs comprehensive validation on email uniqueness, role_level
   * validity, and status transitions.
   *
   * This update operation supports partial updates where only specified fields
   * are modified while preserving existing values for non-updated fields. The
   * operation includes automatic timestamp updates for the updated_at field to
   * maintain accurate modification tracking. Administrators can update their
   * own account details or other administrators' accounts based on their
   * role_level permissions.
   *
   * The operation integrates with the todo_app_administrators table as defined
   * in the Prisma schema, incorporating all available administrator fields and
   * relationship constraints. Updates to sensitive fields like password_hash
   * and role_level may require additional security validations. All
   * administrative account changes are logged for audit and compliance
   * purposes.
   *
   * @param connection
   * @param administratorId Unique identifier of the target administrator
   *   account to update
   * @param body Administrator update information containing fields to be
   *   modified including role level, status, names, and other administrative
   *   properties
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":administratorId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("administratorId")
    administratorId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoAppAdministrator.IUpdate,
  ): Promise<ITodoAppAdministrator> {
    try {
      return await putTodoAppAdminAdministratorsAdministratorId({
        admin,
        administratorId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Remove an existing administrator account from the system using soft
   * deletion methodology. This operation operates on the
   * todo_app_administrators table and marks the specified administrator account
   * as deleted by setting the deleted_at timestamp while preserving all record
   * data for audit and recovery purposes.
   *
   * The operation performs comprehensive validation ensuring the target
   * administrator exists and is currently active before proceeding with
   * deletion. Security considerations include role-based access control
   * ensuring only authorized administrators can delete other administrative
   * accounts. The operation validates that the administrator being deleted has
   * appropriate permissions and that their removal won't compromise system
   * security.
   *
   * This soft delete operation preserves all administrative data including
   * audit trails, session information, and historical records while preventing
   * the deleted administrator from accessing the system. The deletion includes
   * automatic logging of the administrative action for compliance and security
   * monitoring. Administrators can be restored from soft-deleted state through
   * administrative functions if needed.
   *
   * The operation integrates with the todo_app_administrators table as defined
   * in the Prisma schema, utilizing the deleted_at field for soft deletion
   * implementation. All deletion operations are subject to comprehensive audit
   * logging and security validation. The deleted_at timestamp is automatically
   * set to the current time to accurately track when the administrator account
   * was deactivated.
   *
   * @param connection
   * @param administratorId Unique identifier of the target administrator
   *   account to remove
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":administratorId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("administratorId")
    administratorId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoAppAdminAdministratorsAdministratorId({
        admin,
        administratorId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
