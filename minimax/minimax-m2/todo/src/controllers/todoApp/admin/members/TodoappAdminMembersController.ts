import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchTodoAppAdminMembers } from "../../../../providers/patchTodoAppAdminMembers";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { putTodoAppAdminMembersMemberId } from "../../../../providers/putTodoAppAdminMembersMemberId";
import { deleteTodoAppAdminMembersMemberId } from "../../../../providers/deleteTodoAppAdminMembersMemberId";

import { IPageITodoAppMember } from "../../../../api/structures/IPageITodoAppMember";
import { ITodoAppMember } from "../../../../api/structures/ITodoAppMember";

@Controller("/todoApp/admin/members")
export class TodoappAdminMembersController {
  /**
   * Retrieve a filtered and paginated list of member accounts from the TodoApp
   * system. This operation operates on the todo_app_members table and provides
   * comprehensive search capabilities for finding members based on multiple
   * criteria including partial name matching, email filtering, account status,
   * and registration date ranges.
   *
   * The operation supports advanced pagination with configurable page sizes and
   * sorting options. Members can be sorted by registration date, last update,
   * name, email, or account status in ascending or descending order. Search
   * functionality includes case-insensitive partial matching for first name,
   * last name, and email fields.
   *
   * Security considerations include appropriate filtering of member information
   * based on the requesting user's authorization level. Only users with
   * appropriate permissions can access detailed member information, while basic
   * member lists may be available to authenticated users with read-only
   * access.
   *
   * This operation integrates with the todo_app_members table as defined in the
   * Prisma schema, incorporating all available member fields and relationships.
   * The response includes member summary information optimized for list
   * displays, with filtering capabilities to exclude soft-deleted accounts by
   * default.
   *
   * The search operation respects the member status field, allowing filtering
   * by active, suspended, or deactivated accounts. Results are automatically
   * paginated with consistent ordering to support efficient browsing and
   * administrative oversight of the member base.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for member filtering
   *   and listing
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: ITodoAppMember.IRequest,
  ): Promise<IPageITodoAppMember.ISummary> {
    try {
      return await patchTodoAppAdminMembers({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing member's information in the TodoApp system. This
   * operation allows authorized users to modify member profile data including
   * display name, email, and other personal information fields. The memberId
   * path parameter identifies the specific member record to be updated.
   *
   * The operation performs comprehensive validation including duplicate email
   * checking, required field validation, and data format verification. The
   * updated member record maintains all existing relationships including
   * sessions, todos, and audit trail entries. Only the fields provided in the
   * request body are updated, leaving other existing data unchanged.
   *
   * Security considerations include proper authorization checks to ensure only
   * administrators can update member records. The operation prevents
   * unauthorized access to member information and ensures data privacy
   * compliance.
   *
   * This operation integrates with the todo_app_members table as defined in the
   * Prisma schema, incorporating all available member fields and maintaining
   * referential integrity with related entities.
   *
   * @param connection
   * @param memberId Unique identifier of the target member to be updated (UUID
   *   format)
   * @param body Member information to be updated including display name, email,
   *   and other modifiable fields
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":memberId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("memberId")
    memberId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoAppMember.IUpdate,
  ): Promise<ITodoAppMember> {
    try {
      return await putTodoAppAdminMembersMemberId({
        admin,
        memberId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Soft delete a member from the TodoApp system by setting the deleted_at
   * timestamp. This operation marks the member record as deleted while
   * preserving all associated data for audit trail and compliance purposes. The
   * memberId path parameter identifies the specific member to be removed.
   *
   * The soft deletion approach ensures that all related data including member
   * sessions, assigned todos, and audit log entries are preserved but the
   * member account is marked as inactive. This provides account recovery
   * capabilities and maintains data integrity while preventing the member from
   * accessing the system.
   *
   * Security and authorization controls ensure that only administrators can
   * perform member deletions. The operation includes safety checks to prevent
   * accidental deletions and provides proper audit logging of the deletion
   * event.
   *
   * This operation maintains data integrity by properly handling the
   * todo_app_members table's soft deletion capability as defined in the Prisma
   * schema, ensuring the deleted_at field is set appropriately while preserving
   * related data for audit purposes.
   *
   * @param connection
   * @param memberId Unique identifier of the target member to be soft deleted
   *   (UUID format)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":memberId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("memberId")
    memberId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppMember> {
    try {
      return await deleteTodoAppAdminMembersMemberId({
        admin,
        memberId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
