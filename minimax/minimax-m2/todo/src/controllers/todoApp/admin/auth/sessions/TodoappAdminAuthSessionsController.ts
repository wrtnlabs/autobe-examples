import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { getTodoAppAdminAuthSessions } from "../../../../../providers/getTodoAppAdminAuthSessions";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getTodoAppAdminAuthSessionsSessionId } from "../../../../../providers/getTodoAppAdminAuthSessionsSessionId";

import { IPageIAuthSession } from "../../../../../api/structures/IPageIAuthSession";
import { IAuthSession } from "../../../../../api/structures/IAuthSession";

@Controller("/todoApp/admin/auth/sessions")
export class TodoappAdminAuthSessionsController {
  /**
   * Retrieve a comprehensive list of authentication sessions across the TodoApp
   * system. This administrative operation displays all active and recently
   * expired sessions for both member and administrator accounts, providing
   * essential oversight for system security and user management.
   *
   * This operation serves the administrative need to monitor system-wide
   * session activity, detect suspicious login patterns, manage active user
   * sessions, and maintain system security compliance. Administrative users can
   * view session details including IP addresses, connection origins, referrer
   * information, and session duration to identify potential security issues or
   * unauthorized access attempts.
   *
   * The operation aggregates session data from both todo_app_member_sessions
   * and todo_app_administrators_sessions tables in the Prisma schema, providing
   * unified session management capabilities. Each session record includes
   * connection metadata (IP address, referrer URL, connection source) and
   * timing information (creation timestamp, expiration details) to support
   * comprehensive administrative oversight.
   *
   * Security considerations include strict authorization requirements ensuring
   * only administrators can access session data, comprehensive audit logging of
   * session access for compliance, and appropriate data protection for
   * sensitive session information. The operation supports filtering and
   * pagination to handle large session datasets efficiently while maintaining
   * system performance.
   *
   * Session data retrieved includes user identification through
   * member_id/administrator_id references, connection security information (IP
   * tracking for security monitoring), session establishment context (referrer
   * and connection URL for user journey analysis), and session lifecycle
   * management (creation timestamps and expiration tracking). This enables
   * administrators to maintain system security while providing necessary
   * oversight capabilities.
   *
   * @param connection
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
  ): Promise<IPageIAuthSession> {
    try {
      return await getTodoAppAdminAuthSessions({
        admin,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information for a specific authentication session
   * identified by its unique session identifier. This administrative operation
   * provides comprehensive session details to support security investigations,
   * user support activities, and system oversight requirements.
   *
   * The operation serves critical administrative functions including security
   * incident investigation (examining specific suspicious sessions), user
   * account support (assisting users with session-related issues), compliance
   * auditing (providing detailed session records for security reviews), and
   * system monitoring (tracking individual session activities for operational
   * oversight).
   *
   * This operation accesses session data from either todo_app_member_sessions
   * or todo_app_administrators_sessions tables based on the sessionId provided,
   * supporting unified session management across both user types. The session
   * details include complete connection metadata (IP address, referrer URL,
   * connection source), full timing information (creation timestamp, expiration
   * details, session duration), and user association data.
   *
   * The session lookup functionality ensures proper data access by validating
   * the sessionId exists and the requesting administrator has appropriate
   * permissions to view session details. Session data is retrieved with
   * comprehensive audit logging to maintain security compliance and provide
   * accountability for administrative session access.
   *
   * Security measures include strict authentication verification ensuring only
   * authorized administrators can access session details, comprehensive audit
   * trail logging of all session access attempts for compliance and security
   * monitoring, and appropriate data handling procedures for sensitive session
   * information. The operation provides complete session visibility to support
   * administrative security oversight while maintaining proper access
   * controls.
   *
   * Administrative use cases include investigating specific security incidents
   * by examining session details, providing user support by reviewing session
   * activity patterns, conducting compliance audits by accessing comprehensive
   * session records, and performing operational monitoring by tracking
   * individual session behaviors and patterns.
   *
   * @param connection
   * @param sessionId Unique identifier of the target authentication session for
   *   detailed retrieval and administrative oversight
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<IAuthSession> {
    try {
      return await getTodoAppAdminAuthSessionsSessionId({
        admin,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
