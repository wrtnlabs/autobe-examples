import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postTodoAppMemberMembers } from "../../../../providers/postTodoAppMemberMembers";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getTodoAppMemberMembersMemberId } from "../../../../providers/getTodoAppMemberMembersMemberId";
import { putTodoAppMemberMembersMemberId } from "../../../../providers/putTodoAppMemberMembersMemberId";
import { deleteTodoAppMemberMembersMemberId } from "../../../../providers/deleteTodoAppMemberMembersMemberId";

import { ITodoAppMember } from "../../../../api/structures/ITodoAppMember";

@Controller("/todoApp/member/members")
export class TodoappMemberMembersController {
  /**
   * Create a new member profile in the TodoApp system. This operation allows
   * users to register themselves by providing their essential profile
   * information including email address and optional personal details. The
   * member's status is automatically set to 'active' upon successful creation,
   * allowing immediate access to Todo list functionality.
   *
   * The operation validates that the provided email address is unique across
   * all members to prevent duplicate accounts. Profile creation follows proper
   * security practices with soft deletion support and comprehensive audit trail
   * through created_at and updated_at timestamps.
   *
   * Security considerations include email uniqueness validation, required
   * status field management, and proper handling of soft deletion timestamps.
   * The operation integrates with the todo_app_members table from the Prisma
   * schema, incorporating all available member fields and relationships for
   * complete profile creation.
   *
   * @param connection
   * @param body New member profile creation data including email and optional
   *   personal information
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: ITodoAppMember.ICreate,
  ): Promise<ITodoAppMember> {
    try {
      return await postTodoAppMemberMembers({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information for a specific member by their unique
   * identifier. This operation provides access to complete member profile data
   * including personal information, account status, and creation metadata. The
   * operation supports viewing member details for profile management, user
   * administration, and account verification purposes.
   *
   * The operation includes soft deletion awareness - active members return full
   * profile information while deleted members return appropriate status
   * indicators without exposing sensitive data. Security controls ensure only
   * authorized users can access member information based on their relationship
   * to the target member.
   *
   * This operation integrates with the todo_app_members table from the Prisma
   * schema, retrieving all member fields including email, personal names,
   * status, and timestamps. The response provides a comprehensive view of
   * member identity and account state for authorized access patterns.
   *
   * @param connection
   * @param memberId Unique identifier of the target member profile
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":memberId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("memberId")
    memberId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppMember> {
    try {
      return await getTodoAppMemberMembersMemberId({
        member,
        memberId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update the current member's own profile information in the TodoApp system.
   * This operation allows authorized members to modify their own profile data
   * including first name, last name, and other personal information fields. The
   * memberId path parameter identifies the specific member record to be
   * updated.
   *
   * The operation performs comprehensive validation including duplicate email
   * checking, required field validation, and data format verification. The
   * updated member record maintains all existing relationships including
   * sessions, todos, and audit trail entries. Only the fields provided in the
   * request body are updated, leaving other existing data unchanged.
   *
   * Security considerations include proper authorization checks to ensure
   * members can only update their own profiles. The operation prevents
   * unauthorized access to other members' information and ensures data privacy
   * compliance.
   *
   * This operation integrates with the todo_app_members table as defined in the
   * Prisma schema, incorporating all available member fields and maintaining
   * referential integrity with related entities.
   *
   * @param connection
   * @param memberId Unique identifier of the target member to be updated (UUID
   *   format)
   * @param body Member information to be updated including first name, last
   *   name, and other modifiable fields
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":memberId")
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("memberId")
    memberId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoAppMember.IUpdate,
  ): Promise<ITodoAppMember> {
    try {
      return await putTodoAppMemberMembersMemberId({
        member,
        memberId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Soft delete the current member's own account from the TodoApp system by
   * setting the deleted_at timestamp. This operation allows members to
   * voluntarily deactivate their accounts while preserving all associated data
   * for audit trail and compliance purposes. The memberId path parameter
   * identifies the specific member to be removed.
   *
   * The soft deletion approach ensures that all related data including member
   * sessions, assigned todos, and audit log entries are preserved but the
   * member account is marked as inactive. This provides account recovery
   * capabilities and maintains data integrity while preventing the member from
   * accessing the system.
   *
   * Security considerations ensure that members can only delete their own
   * accounts. The operation includes safety checks and confirmation processes
   * to prevent accidental deletions and provides proper audit logging of the
   * account deactivation.
   *
   * This operation maintains data integrity by properly handling the
   * todo_app_members table's soft deletion capability as defined in the Prisma
   * schema, ensuring the deleted_at field is set appropriately while preserving
   * related data for audit purposes.
   *
   * @param connection
   * @param memberId Unique identifier of the current member account to be soft
   *   deleted (UUID format)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":memberId")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("memberId")
    memberId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppMember> {
    try {
      return await deleteTodoAppMemberMembersMemberId({
        member,
        memberId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
