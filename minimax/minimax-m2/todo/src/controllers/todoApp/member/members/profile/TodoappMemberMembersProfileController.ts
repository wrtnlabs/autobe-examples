import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { getTodoAppMemberMembersMemberIdProfile } from "../../../../../providers/getTodoAppMemberMembersMemberIdProfile";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";

import { ITodoAppMember } from "../../../../../api/structures/ITodoAppMember";

@Controller("/todoApp/member/members/:memberId/profile")
export class TodoappMemberMembersProfileController {
  /**
   * Retrieve a comprehensive member profile with complete todo management
   * information. This operation provides detailed member data including
   * personal information, account status, and todo summary statistics for
   * effective member management and todo system navigation.
   *
   * This endpoint operates on the Member table from the Prisma schema and
   * returns detailed member information optimized for profile management and
   * user experience. The member profile includes personal details like name,
   * email, and account status along with todo-related metadata for
   * administrative oversight.
   *
   * Security considerations include proper member identification through the
   * memberId parameter and appropriate data filtering to ensure members can
   * only access their own profile information. The response is designed to be
   * immediately usable in user interfaces without requiring additional API
   * calls for todo statistics.
   *
   * This operation integrates with both the Member table and associated Todo
   * records to provide a comprehensive view of the member's current todo
   * management status. The response structure includes todo count summaries and
   * status distributions for quick dashboard display and member progress
   * tracking.
   *
   * @param connection
   * @param memberId Unique identifier of the target member whose profile
   *   information is being retrieved
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("memberId")
    memberId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppMember.IInvert> {
    try {
      return await getTodoAppMemberMembersMemberIdProfile({
        member,
        memberId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
