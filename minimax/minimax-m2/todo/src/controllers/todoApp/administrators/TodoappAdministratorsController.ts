import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postTodoAppAdministrators } from "../../../providers/postTodoAppAdministrators";
import { AdminAuth } from "../../../decorators/AdminAuth";
import { AdminPayload } from "../../../decorators/payload/AdminPayload";
import { getTodoAppAdministratorsAdministratorId } from "../../../providers/getTodoAppAdministratorsAdministratorId";

import { ITodoAppAdministrator } from "../../../api/structures/ITodoAppAdministrator";

@Controller("/todoApp/administrators")
export class TodoappAdministratorsController {
  /**
   * Create a new administrator account in the TodoApp system with secure
   * authentication and appropriate role assignment.
   *
   * This operation allows the creation of new administrative accounts that will
   * have elevated permissions to manage users, system operations, and provide
   * oversight of the entire TodoApp platform. Each administrator must be
   * assigned a role level (super_admin, admin, or moderator) that determines
   * their administrative privileges and access scope.
   *
   * Security considerations include proper password hashing, unique email
   * validation, and comprehensive audit logging of all administrative account
   * creation. The system enforces strong authentication requirements for all
   * administrative accounts to protect against unauthorized access to sensitive
   * system functions.
   *
   * CRITICAL: This operation requires administrator authorization to prevent
   * unauthorized privilege escalation. Only existing administrators can create
   * new administrative accounts.
   *
   * The created administrator account becomes immediately active unless
   * otherwise specified through the status field. New administrators can access
   * the system based on their assigned role level and will be subject to the
   * same session management and security protocols as existing administrative
   * accounts.
   *
   * This operation integrates with the todo_app_administrators table as defined
   * in the Prisma schema, incorporating all required fields for secure
   * administrative account management including role-based access control and
   * comprehensive audit trail capabilities.
   *
   * @param connection
   * @param body Administrator account creation data including authentication
   *   credentials, personal information, and role assignment. Role level must
   *   be one of: 'super_admin', 'admin', or 'moderator'.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: ITodoAppAdministrator.ICreate,
  ): Promise<ITodoAppAdministrator> {
    try {
      return await postTodoAppAdministrators({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific administrator account in the
   * TodoApp system.
   *
   * This operation provides comprehensive access to administrator account
   * details including personal identification information, role assignment,
   * current status, and account lifecycle timestamps. The system supports soft
   * deletion recovery through the deleted_at field, allowing administrators to
   * be restored from deactivated states when appropriate.
   *
   * CRITICAL: This operation requires administrator authorization to protect
   * sensitive administrative data. Only authenticated administrators can access
   * other administrator account information.
   *
   * Security note: Authentication credentials (password_hash) are intentionally
   * excluded from the response to prevent security vulnerabilities. The
   * returned data includes safe administrative information suitable for system
   * oversight and user management functions.
   *
   * Access to administrative account information follows strict security
   * protocols with comprehensive audit trail information showing when the
   * account was created, last updated, and if applicable, when it was
   * deactivated through soft deletion.
   *
   * This operation operates on the todo_app_administrators table from the
   * Prisma schema, ensuring that all returned data accurately reflects the
   * current database state while excluding sensitive authentication fields for
   * security protection.
   *
   * @param connection
   * @param administratorId Unique identifier of the target administrator
   *   account
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":administratorId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("administratorId")
    administratorId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppAdministrator.ISummary> {
    try {
      return await getTodoAppAdministratorsAdministratorId({
        admin,
        administratorId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
