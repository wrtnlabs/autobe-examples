import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthAdminJoin } from "../../../providers/postAuthAdminJoin";
import { AdminAuth } from "../../../decorators/AdminAuth";
import { AdminPayload } from "../../../decorators/payload/AdminPayload";
import { postAuthAdminLogin } from "../../../providers/postAuthAdminLogin";
import { postAuthAdminRefresh } from "../../../providers/postAuthAdminRefresh";

import { ITodoAppAdministrator } from "../../../api/structures/ITodoAppAdministrator";

@Controller("/auth/admin")
export class AuthAdminController {
  /**
   * Administrative account registration endpoint that creates new system
   * administrator accounts with elevated privileges and issues initial JWT
   * tokens for system-wide management access.
   *
   * This endpoint allows the creation of new administrative users who can
   * access all TodoApp system features, manage other users, and perform system
   * administration tasks. The operation creates a new record in the
   * todo_app_administrators table with secure password hashing, role level
   * assignment, and active status by default.
   *
   * The join process includes comprehensive validation of email uniqueness
   * across administrators, password strength requirements, role level
   * assignment (super_admin, admin, moderator), and proper audit trail
   * creation. New administrators receive initial JWT access tokens with
   * appropriate privileges for their role level.
   *
   * Security considerations include mandatory email uniqueness validation to
   * prevent duplicate administrator accounts, encrypted password storage using
   * industry-standard hashing algorithms, and comprehensive audit logging of
   * all administrative account creation events. The operation supports the
   * administrative account lifecycle with proper status tracking and soft
   * deletion capabilities for account recovery.
   *
   * Administrative account creation establishes the foundation for secure
   * system management with role-based access control, ensuring administrators
   * can perform their duties while maintaining strict security protocols and
   * compliance requirements.
   *
   * @param connection
   * @param body New administrator account creation data including email,
   *   password, name information, and role level specification for initial
   *   account setup
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: ITodoAppAdministrator.ICreate,
  ): Promise<ITodoAppAdministrator.IAuthorized> {
    try {
      return await postAuthAdminJoin({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Administrative authentication endpoint that validates administrator
   * credentials and issues JWT access tokens for system-wide management
   * operations and privileged access.
   *
   * This endpoint provides secure authentication for system administrators who
   * need access to all TodoApp features, user management capabilities, and
   * system administration functions. The login process validates the
   * administrator's email and password against the todo_app_administrators
   * table, verifies account status is active, and generates appropriate JWT
   * tokens based on the administrator's role level.
   *
   * The authentication system includes comprehensive security measures such as
   * account status validation, password verification using stored hash
   * comparisons, and audit logging of all administrative login attempts.
   * Successful authentication generates both access and refresh tokens with
   * appropriate expiration times and role-based privileges.
   *
   * Security considerations include mandatory email and password validation,
   * account status verification to ensure only active administrators can access
   * the system, and comprehensive audit trail creation for all administrative
   * access attempts. The operation supports secure session management with
   * proper token generation and validation mechanisms.
   *
   * Administrative login establishes authenticated session context for
   * privileged operations, ensuring system administrators can securely access
   * management functions while maintaining strict security protocols and
   * compliance requirements.
   *
   * @param connection
   * @param body Administrator login credentials including email address and
   *   password for secure authentication and access token generation
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: ITodoAppAdministrator.ILogin,
  ): Promise<ITodoAppAdministrator.IAuthorized> {
    try {
      return await postAuthAdminLogin({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Administrative token refresh endpoint that renews JWT access tokens for
   * authenticated administrators to maintain secure system management sessions
   * without re-authentication.
   *
   * This endpoint allows system administrators to refresh their access tokens
   * using valid refresh tokens, ensuring uninterrupted access to privileged
   * TodoApp management features. The refresh process validates the provided
   * refresh token against active administrative sessions in the
   * todo_app_administrator_sessions table, verifies the administrator account
   * status, and generates new JWT access tokens with appropriate role-based
   * privileges.
   *
   * The token refresh system includes comprehensive security measures such as
   * refresh token validation, session existence verification, account status
   * checks, and proper token expiration management. New access tokens are
   * generated with appropriate expiration times while maintaining security best
   * practices for administrative sessions.
   *
   * Security considerations include mandatory refresh token validation to
   * prevent unauthorized token usage, session existence verification to ensure
   * active administrative sessions, and audit logging of all token refresh
   * events. The operation supports seamless session management while
   * maintaining strict security protocols for privileged access.
   *
   * Administrative token refresh maintains secure authenticated context for
   * ongoing system management operations, ensuring administrators can perform
   * their duties efficiently while maintaining strict security protocols and
   * compliance requirements.
   *
   * @param connection
   * @param body Valid refresh token for renewing administrative access tokens
   *   and maintaining authenticated session for system management operations
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: ITodoAppAdministrator.IRefresh,
  ): Promise<ITodoAppAdministrator.IAuthorized> {
    try {
      return await postAuthAdminRefresh({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
