import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthMemberJoin } from "../../../../providers/postAuthMemberJoin";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";

import { ITodoAppMember } from "../../../../api/structures/ITodoAppMember";

@Controller("/auth/member/join")
export class AuthMemberJoinController {
  /**
   * Creates a new member account in the TodoApp system and establishes the
   * initial authentication session.
   *
   * This endpoint allows new users to register for TodoApp access by providing
   * their email address and basic profile information. Upon successful
   * registration, the system creates a new todo_app_members record with the
   * provided email, first name, last name, and sets the account status to
   * 'active'. A corresponding todo_app_member_sessions record is also created
   * to track the registration session with connection metadata including IP
   * address, connection URL, and referrer information.
   *
   * The registration process generates initial JWT tokens for the new member,
   * enabling immediate access to Todo management functionality. The session is
   * tracked with detailed connection metadata for security monitoring and audit
   * purposes. Members can register with optional first and last names, but must
   * provide a unique email address that serves as their account identifier.
   *
   * This operation is essential for onboarding new users to the TodoApp system
   * and establishing their initial authenticated session. After registration,
   * members can immediately start creating and managing their personal Todo
   * items using other authenticated endpoints.
   *
   * @param connection
   * @param body Member registration information including email and optional
   *   profile details
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async registerMember(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: ITodoAppMember.ICreate,
  ): Promise<ITodoAppMember.IAuthorized> {
    try {
      return await postAuthMemberJoin({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
