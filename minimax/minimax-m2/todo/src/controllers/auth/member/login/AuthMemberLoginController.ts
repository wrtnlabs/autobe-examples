import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthMemberLogin } from "../../../../providers/postAuthMemberLogin";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";

import { ITodoAppMember } from "../../../../api/structures/ITodoAppMember";

@Controller("/auth/member/login")
export class AuthMemberLoginController {
  /**
   * Authenticates an existing member user and establishes a new authenticated
   * session with comprehensive security tracking.
   *
   * This endpoint validates member credentials and creates a new
   * todo_app_member_sessions record for ongoing Todo management access. The
   * system verifies the member exists in the todo_app_members table and has an
   * 'active' status before creating the session. Upon successful
   * authentication, the member gains access to their personal Todo items and
   * can perform all CRUD operations on their own data.
   *
   * The login process creates a new session record with detailed connection
   * metadata including the member's IP address, connection URL, and referrer
   * URL for comprehensive security monitoring and audit trails. This enables
   * the system to track login patterns, detect suspicious activity, and provide
   * detailed session management capabilities for individual members.
   *
   * After successful authentication, JWT tokens are issued that enable the
   * member to access authenticated Todo management endpoints. The session
   * tracking ensures all Todo operations can be properly attributed to the
   * authenticated member and provides the foundation for comprehensive security
   * monitoring and user activity analysis.
   *
   * @param connection
   * @param body Member login credentials for authentication
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async authenticateMember(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: ITodoAppMember.ILogin,
  ): Promise<ITodoAppMember.IAuthorized> {
    try {
      return await postAuthMemberLogin({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
