import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthMemberRefresh } from "../../../../providers/postAuthMemberRefresh";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";

import { ITodoAppMember } from "../../../../api/structures/ITodoAppMember";

@Controller("/auth/member/refresh")
export class AuthMemberRefreshController {
  /**
   * Refreshes the authentication tokens for an existing member session,
   * extending access to Todo management functionality.
   *
   * This endpoint allows members to renew their JWT access tokens using a valid
   * refresh token without requiring re-authentication with their credentials.
   * The system validates the refresh token against existing
   * todo_app_member_sessions records to ensure the session is still active and
   * hasn't expired. Members can refresh their tokens as long as they have a
   * valid session record in the database.
   *
   * Token refresh is essential for maintaining seamless access to Todo
   * management features without interrupting the user's workflow. When a
   * refresh is successful, new JWT tokens are issued while maintaining the
   * existing session context and security tracking. The refresh operation
   * updates the session expiration time to extend the member's authenticated
   * access period.
   *
   * This operation is crucial for user experience optimization, allowing
   * members to continue managing their Todo items without needing to repeatedly
   * log in. It supports the TodoApp's goal of providing efficient task
   * management by maintaining persistent, secure authentication sessions for
   * active members.
   *
   * @param connection
   * @param body Member refresh token for extending authentication session
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async refreshMemberToken(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: ITodoAppMember.IRefresh,
  ): Promise<ITodoAppMember.IAuthorized> {
    try {
      return await postAuthMemberRefresh({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
