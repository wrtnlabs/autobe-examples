/**
 * This endpoint enables the registration of a new user by inserting a record
 * into the todo_list_users table. It collects the unique email address
 * (validated for correct structure and uniqueness), a plain-text password
 * (securely hashed and never stored directly), and an initial display_name
 * within 2–50 characters. The endpoint follows the business requirement that
 * registration rejects duplicate emails and sends a confirmation email upon
 * success. Accounts remain in a pending state until confirmed via email. The
 * system records created_at and updated_at timestamps at creation and ensures
 * deleted_at remains null for active users. Soft deletion is not applied at
 * registration.
 *
 * Role-based access ensures only unauthenticated individuals may register.
 * Security logic prevents access to this endpoint by logged-in users. Upon
 * success, the endpoint returns a JWT access token and refresh token for use in
 * subsequent requests, encoding the user's id, role, and permissions as
 * specified by requirements. This operation is not related to session
 * termination or authentication validation flows.
 *
 * Field-level validation is enforced: email must match RFC standards and
 * display_name must be 2–50 chars. The operation guarantees no side effects on
 * other system entities or resources. This API operation is required as a
 * system entry point for all standard users and is not used for any admin
 * accounts or privilege escalation workflows.
 *
 * Error handling addresses duplicate email, invalid data formats, and internal
 * processing issues, returning specific error messages for each scenario.
 * Related operations: login (for authentication), password reset (not
 * implemented here), and refresh (token renewal).
 *
 * @param props.connection
 * @param props.body User registration details: unique email, password, and
 *   display_name as required for initial account creation.
 * @setHeader token.access Authorization
 *
 * @path /auth/user/join
 * @accessor api.functional.auth.user.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
