import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ITodoListUserSession } from "../../../../../structures/ITodoListUserSession";
import { IPageITodoListUserSession } from "../../../../../structures/IPageITodoListUserSession";

/**
 * Retrieve a filtered and paginated list of authentication session records
 * associated with the specified user. Only the user themselves or an
 * administrative actor can access this information, and the result includes
 * both currently active and historical login sessions for auditing and security
 * review purposes.
 *
 * The operation uses advanced filtering and pagination, and exposes device,
 * browser, and IP metadata for each entry. Business logic ensures strict
 * correspondence to the requested user account and prevents access to session
 * records of others.
 *
 * Typical business use cases include reviewing login activity for suspicious
 * behavior, session journaling for regulatory compliance, and user-driven
 * account auditing.
 *
 * @param props.connection
 * @param props.userId Unique identifier of the target user associated with
 *   session records
 * @param props.body Search parameters for filtering user session records
 *   (pagination, device/browser filters, date range, etc.)
 * @path /todoList/user/users/:userId/sessions
 * @accessor api.functional.todoList.user.users.sessions.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /** Unique identifier of the target user associated with session records */
    userId: string & tags.Format<"uuid">;

    /**
     * Search parameters for filtering user session records (pagination,
     * device/browser filters, date range, etc.)
     */
    body: ITodoListUserSession.IRequest;
  };
  export type Body = ITodoListUserSession.IRequest;
  export type Response = IPageITodoListUserSession;

  export const METADATA = {
    method: "PATCH",
    path: "/todoList/user/users/:userId/sessions",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/todoList/user/users/${encodeURIComponent(props.userId ?? "null")}/sessions`;
  export const random = (): IPageITodoListUserSession =>
    typia.random<IPageITodoListUserSession>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("userId")(() => typia.assert(props.userId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
