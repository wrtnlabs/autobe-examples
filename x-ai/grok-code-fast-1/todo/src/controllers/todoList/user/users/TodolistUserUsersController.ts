import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { getTodoListUserUsersUserId } from "../../../../providers/getTodoListUserUsersUserId";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { putTodoListUserUsersUserId } from "../../../../providers/putTodoListUserUsersUserId";
import { deleteTodoListUserUsersUserId } from "../../../../providers/deleteTodoListUserUsersUserId";

import { ITodoListUser } from "../../../../api/structures/ITodoListUser";

@Controller("/todoList/user/users/:userId")
export class TodolistUserUsersController {
  /**
   * Retrieve full profile and status of a registered user account from
   * todo_list_users.
   *
   * Retrieve the full profile and status of a specific registered user account,
   * including core identifying fields and timestamp metadata.
   *
   * Only privileged actors or the account owner themselves may access this
   * information. All fields except the password hash are included in the
   * response. Sensitive fields are excluded from non-admin consumers.
   *
   * Strict data isolation policies are enforced according to the business
   * rules. All user-related actions and accesses are audited. The system
   * prevents unauthorized users from accessing another’s account details.
   *
   * @param connection
   * @param userId Unique identifier (UUID) of the target user account.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
  ): Promise<ITodoListUser> {
    try {
      return await getTodoListUserUsersUserId({
        user,
        userId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update editable profile fields for a registered user account in
   * todo_list_users.
   *
   * Update profile information for a specific registered user account.
   * Modifiable fields typically include display name and email. Any attempted
   * change to protected properties, such as password hash or deleted timestamp,
   * will be rejected except by specific internal flows.
   *
   * This operation allows a user to manage their own account. Profile update
   * requests are validated for conformance with field requirements as defined
   * in the schema: email must be unique and RFC-compliant, display name must
   * fit length constraints, and the account's status fields are managed by the
   * system. All update actions are audited and logged.
   *
   * Security checks enforce that only the account owner (authenticated user) or
   * privileged admin actors can perform updates. The endpoint excludes all
   * non-relevant or system-managed fields from the request body, which follows
   * a strict DTO contract.
   *
   * @param connection
   * @param userId Unique identifier (UUID) of the user account to update.
   * @param body Patchable user profile fields following DTO schema for update.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoListUser.IUpdate,
  ): Promise<ITodoListUser> {
    try {
      return await putTodoListUserUsersUserId({
        user,
        userId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Soft-deletes a user account in the todo_list_users table by userId.
   *
   * Soft delete an existing user by userId. This operation sets the user's
   * deleted_at field, making the account inaccessible to both the user and any
   * other actors in the system from that moment onward.
   *
   * Permission checks ensure that only the owner of the account or an
   * administrator can delete the user. Upon soft deletion, personal data is no
   * longer accessible through normal application queries, but retained for
   * audit and potential restoration purposes as defined in the business logic.
   * Security is maintained through enforcement of unique email constraints,
   * isolation of all user data, and consistent application of soft deletion
   * throughout the data model.
   *
   * @param connection
   * @param userId Unique identifier of the target user
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoListUserUsersUserId({
        user,
        userId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
