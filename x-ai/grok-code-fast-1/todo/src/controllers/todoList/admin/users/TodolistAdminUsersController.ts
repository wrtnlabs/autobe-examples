import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { deleteTodoListAdminUsersUserId } from "../../../../providers/deleteTodoListAdminUsersUserId";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";

@Controller("/todoList/admin/users/:userId")
export class TodolistAdminUsersController {
  /**
   * Soft-deletes a user account in the todo_list_users table by userId.
   *
   * Soft delete an existing user by userId. This operation sets the user's
   * deleted_at field, making the account inaccessible to both the user and any
   * other actors in the system from that moment onward.
   *
   * Permission checks ensure that only the owner of the account or an
   * administrator can delete the user. Upon soft deletion, personal data is no
   * longer accessible through normal application queries, but retained for
   * audit and potential restoration purposes as defined in the business logic.
   * Security is maintained through enforcement of unique email constraints,
   * isolation of all user data, and consistent application of soft deletion
   * throughout the data model.
   *
   * @param connection
   * @param userId Unique identifier of the target user
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoListAdminUsersUserId({
        admin,
        userId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
