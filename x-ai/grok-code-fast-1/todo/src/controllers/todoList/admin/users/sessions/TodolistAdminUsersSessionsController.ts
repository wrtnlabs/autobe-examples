import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchTodoListAdminUsersUserIdSessions } from "../../../../../providers/patchTodoListAdminUsersUserIdSessions";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getTodoListAdminUsersUserIdSessionsSessionId } from "../../../../../providers/getTodoListAdminUsersUserIdSessionsSessionId";
import { deleteTodoListAdminUsersUserIdSessionsSessionId } from "../../../../../providers/deleteTodoListAdminUsersUserIdSessionsSessionId";

import { IPageITodoListUserSession } from "../../../../../api/structures/IPageITodoListUserSession";
import { ITodoListUserSession } from "../../../../../api/structures/ITodoListUserSession";

@Controller("/todoList/admin/users/:userId/sessions")
export class TodolistAdminUsersSessionsController {
  /**
   * Searches and lists authentication sessions for a given user account in
   * todo_list_user_sessions.
   *
   * Retrieve a filtered and paginated list of authentication session records
   * associated with the specified user. Only the user themselves or an
   * administrative actor can access this information, and the result includes
   * both currently active and historical login sessions for auditing and
   * security review purposes.
   *
   * The operation uses advanced filtering and pagination, and exposes device,
   * browser, and IP metadata for each entry. Business logic ensures strict
   * correspondence to the requested user account and prevents access to session
   * records of others.
   *
   * Typical business use cases include reviewing login activity for suspicious
   * behavior, session journaling for regulatory compliance, and user-driven
   * account auditing.
   *
   * @param connection
   * @param userId Unique identifier of the target user associated with session
   *   records
   * @param body Search parameters for filtering user session records
   *   (pagination, device/browser filters, date range, etc.)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoListUserSession.IRequest,
  ): Promise<IPageITodoListUserSession> {
    try {
      return await patchTodoListAdminUsersUserIdSessions({
        admin,
        userId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve complete details for a specific user session from
   * todo_list_user_sessions table.
   *
   * Retrieve the detailed information for a specific authentication session
   * belonging to a user by specifying both the userId and sessionId in the URL
   * path.
   *
   * This API operation is restricted to privileged administrative actors for
   * audit, compliance, and security investigation scenarios. Sessions contain
   * raw connection metadata such as IP address, URL, and referrer, as well as
   * creation and expiration timestamps. The returned information is
   * comprehensive and corresponds to all fields defined in the
   * todo_list_user_sessions table, including the owning user's unique
   * identifier. No secrets or token data are ever revealed – only session
   * metadata is exposed.
   *
   * The session is treated as a subsidiary of the user: the path must include a
   * valid userId for cross-checking user ownership, ensuring strict isolation
   * and preventing candidate collisions. In case of invalid session, ownership
   * mismatch, or orphaned session, the API returns a not-found error as per
   * business logic. Other endpoints may be used in conjunction (such as session
   * erase) for end-to-end session management under admin supervision.
   *
   * @param connection
   * @param userId Unique identifier of the parent user account for whom the
   *   session was created.
   * @param sessionId Unique identifier of the authentication session being
   *   retrieved (must be associated to the userId).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<ITodoListUserSession> {
    try {
      return await getTodoListAdminUsersUserIdSessionsSessionId({
        admin,
        userId,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Erase a specific user session from todo_list_user_sessions for
   * administrative session management.
   *
   * Permanently delete the specified authentication session for a user,
   * ensuring both user ownership and strict session traceability. This endpoint
   * is designed exclusively for administrative session management – allowing
   * privileged actors to forcibly end or erase a session in case of suspicious
   * activity, account compromise, or regulatory requirements.
   *
   * For subsidiary session records, both the userId and sessionId must be
   * specified in the path. This guarantees that only sessions belonging to the
   * designated user account can be deleted, enforcing database referential
   * integrity and minimizing risk of orphaned records or data leakage. The
   * operation does not require a request body.
   *
   * Upon successful execution, the session is removed from the
   * todo_list_user_sessions table. Any open authentication context for that
   * session is immediately invalidated. If the session does not exist or does
   * not belong to the user, a not-found error is returned. Error handling and
   * audit log updates must comply rigorously with compliance regulations for
   * session destruction.
   *
   * @param connection
   * @param userId Unique identifier of the user account owning the session.
   * @param sessionId Unique identifier of the session to be deleted (must be
   *   linked to userId).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":sessionId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<ITodoListUserSession> {
    try {
      return await deleteTodoListAdminUsersUserIdSessionsSessionId({
        admin,
        userId,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
