import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { putTodoListAdminTodosTodoId } from "../../../../providers/putTodoListAdminTodosTodoId";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { deleteTodoListAdminTodosTodoId } from "../../../../providers/deleteTodoListAdminTodosTodoId";

import { ITodoListTodo } from "../../../../api/structures/ITodoListTodo";

@Controller("/todoList/admin/todos/:todoId")
export class TodolistAdminTodosController {
  /**
   * Update attributes of an existing todo item in the todo_list_todos table.
   *
   * Update an existing todo item, enforcing all business and field-level
   * validation rules.
   *
   * This operation permits the owner or an administrator to change the title,
   * optional description, and status of a todo item identified by its unique
   * todoId. The title must remain 1–100 visible UTF-8 characters and unique
   * (among active todos for that user), and the description, if present, must
   * be ≤1000 characters. The status property accepts only 'pending' or
   * 'completed'; status transitions correctly set or clear the completed_at
   * timestamp in accordance with the workflow logic.
   *
   * This operation checks permission: only the todo owner or an admin can
   * update. All input is validated, and system-managed fields (created_at,
   * updated_at, deleted_at) are internally set or protected from modification.
   * If update is performed by an admin, the action is logged for
   * audit/compliance. Any failure—whether due to validation, permission, or
   * missing todoId—results in an explicit, clear error message, as described in
   * the requirements documentation.
   *
   * @param connection
   * @param todoId Unique identifier of the target todo item to update.
   * @param body Updated fields for the todo. Title and description validated
   *   for length and uniqueness. Status change sets completion state;
   *   system-managed timestamps not accepted.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoListTodo.IUpdate,
  ): Promise<ITodoListTodo> {
    try {
      return await putTodoListAdminTodosTodoId({
        admin,
        todoId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a specific todo item by ID, using soft deletion logic in the
   * todo_list_todos table.
   *
   * Deletes a single todo item belonging to the authenticated user, or any user
   * if performed by an admin.
   *
   * If the operation is performed by a standard user, the system first verifies
   * that the todo with the supplied ID is owned by that user and is not already
   * deleted. Requests to delete a non-owned or already deleted todo result in a
   * permission or not found error, respectively.
   *
   * Upon successful permission check, the system handles the delete as a soft
   * deletion by populating the 'deleted_at' timestamp. This ensures the todo is
   * no longer included in active user lists, is hidden from all user-facing
   * views, but retained for compliance and undo workflows. Admin actions
   * trigger the creation of audit log entries to provide traceability for all
   * privileged deletions.
   *
   * The endpoint does not remove rows, preventing accidental loss of
   * information, and enabling robust retention and regulatory audit policies.
   * If an error occurs, the system provides clear error messages for permission
   * denials, not found resources, or conflicts due to concurrent modification.
   *
   * @param connection
   * @param todoId Unique identifier of the target todo item to delete.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoListAdminTodosTodoId({
        admin,
        todoId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
