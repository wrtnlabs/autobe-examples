import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { getTodoListAdminAdminsAdminId } from "../../../../providers/getTodoListAdminAdminsAdminId";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { putTodoListAdminAdminsAdminId } from "../../../../providers/putTodoListAdminAdminsAdminId";
import { deleteTodoListAdminAdminsAdminId } from "../../../../providers/deleteTodoListAdminAdminsAdminId";

import { ITodoListAdmin } from "../../../../api/structures/ITodoListAdmin";

@Controller("/todoList/admin/admins/:adminId")
export class TodolistAdminAdminsController {
  /**
   * Retrieve full administrator account information for a given admin in the
   * system. This endpoint is intended for privileged administrative access and
   * allows system operators to inspect the profile, permissions, and status of
   * an admin account for troubleshooting or compliance purposes.
   *
   * The adminId path parameter identifies the administrator to display. Only
   * users with administrative credentials may use this operation, and security
   * controls restrict exposure of sensitive data fields to authorized actors.
   * The response reflects the current state of the administrator account as
   * stored in the database.
   *
   * Proper error handling will be enforced for cases where the specified
   * adminId does not exist or the requester lacks sufficient permission to
   * access the data. This operation supports oversight and governance
   * requirements, enabling detailed review of all admin accounts by privileged
   * users.
   *
   * @param connection
   * @param adminId Unique identifier of the target administrator (UUID format)
   *   (global scope)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
  ): Promise<ITodoListAdmin> {
    try {
      return await getTodoListAdminAdminsAdminId({
        admin,
        adminId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update the information of an existing administrator account in the Todo
   * List platform. This endpoint is reserved for "admin" actors who have the
   * authority to change admin-related fields such as email address, display
   * name, role assignments, or account status.
   *
   * The adminId path parameter designates the administrator to update.
   * Middleware and access control checks ensure only authorized admin users are
   * able to perform this operation. Updates must be validated
   * rigorously—invalid or missing fields should trigger explanatory error
   * messages, and all changes are auditable for security compliance.
   *
   * Only the fields specified in the request body will be updated. The response
   * includes the latest version of the administrator account after modification
   * is complete.
   *
   * @param connection
   * @param adminId Unique identifier of the target administrator (UUID format)
   *   (global scope)
   * @param body Fields to update for the target administrator account.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoListAdmin.IUpdate,
  ): Promise<ITodoListAdmin> {
    try {
      return await putTodoListAdminAdminsAdminId({
        admin,
        adminId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Erase an administrative account by setting its deleted_at timestamp. This
   * action performs a soft deletion; the admin cannot access or operate the
   * system following revocation, though audit and compliance information is
   * retained.
   *
   * Only system operators with elevated privileges should perform this
   * operation. Typical reasons include breach response, voluntary exit, or
   * transition of roles. The endpoint implements strict identity validation and
   * logs initiating user and IP address for audit traceability.
   *
   * This operation is irreversible except through manual database recovery. It
   * ensures system integrity by preventing deleted admins from managing the
   * platform, enforcing strict adherence to security and compliance protocols.
   * Related operations include PATCH /admins to list or filter administrative
   * users and PATCH /admins/{adminId}/sessions to inspect session history.
   *
   * @param connection
   * @param adminId Unique identifier of the administrative account (UUID) to
   *   erase.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoListAdminAdminsAdminId({
        admin,
        adminId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
