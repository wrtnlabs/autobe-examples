import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchTodoListAdminAuditLogs } from "../../../../providers/patchTodoListAdminAuditLogs";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getTodoListAdminAuditLogsAuditLogId } from "../../../../providers/getTodoListAdminAuditLogsAuditLogId";

import { IPageITodoListAuditLog } from "../../../../api/structures/IPageITodoListAuditLog";
import { ITodoListAuditLog } from "../../../../api/structures/ITodoListAuditLog";

@Controller("/todoList/admin/auditLogs")
export class TodolistAdminAuditlogsController {
  /**
   * Search and retrieve paginated audit logs from the todo_list_audit_logs
   * table.
   *
   * Retrieves audit log entries with advanced filtering options for time range,
   * event type, administrator, and target user.
   *
   * This endpoint is restricted to admin users, enabling compliance officers
   * and system maintainers to review all privileged system activity. Requests
   * may filter by event_time range, specific event_type, the responsible
   * admin's ID, and optionally by the affected target user. Full-text searches
   * may be applied to the details field to support investigations of complex
   * events or workflows.
   *
   * Results are paginated with configurable page size and cursor/offset
   * support. Logs are presented in order of most recent first (descending by
   * event_time) unless specified otherwise. The response includes all available
   * metadata—actor, target, event_type, event_time, and narrative details. The
   * audit log is immutable and cannot be altered or deleted via this endpoint.
   * Errors will be clearly described in the response if invalid filters or
   * unauthorized access attempts are made.
   *
   * @param connection
   * @param body Filter criteria and pagination parameters for searching audit
   *   logs.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: ITodoListAuditLog.IRequest,
  ): Promise<IPageITodoListAuditLog.ISummary> {
    try {
      return await patchTodoListAdminAuditLogs({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single audit log entry from todo_list_audit_logs by unique ID.
   *
   * Retrieve a single audit log entry from the system's audit log by its unique
   * identifier, supporting administrative forensic review and compliance
   * investigations.
   *
   * This API operation is only accessible to users with administrative roles
   * due to the sensitive nature of audit data and access. Each audit log
   * includes full details as recorded in the todo_list_audit_logs schema: event
   * type, timestamp, acting administrator, possibly affected user, and a
   * detailed narrative. The response structure is drawn directly from the
   * ITodoListAuditLog type.
   *
   * Audit log entries are immutable and cannot be edited or deleted, ensuring
   * integrity for audits and investigations. Error handling will indicate if
   * the audit event does not exist or if access is denied. Related operations
   * include search (index/list) endpoints, which may also be restricted to
   * admins.
   *
   * @param connection
   * @param auditLogId Unique identifier of the audit log entry to retrieve.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":auditLogId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("auditLogId")
    auditLogId: string & tags.Format<"uuid">,
  ): Promise<ITodoListAuditLog> {
    try {
      return await getTodoListAdminAuditLogsAuditLogId({
        admin,
        auditLogId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
