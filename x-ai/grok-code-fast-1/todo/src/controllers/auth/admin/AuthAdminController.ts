import { Controller, Ip } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthAdminJoin } from "../../../providers/postAuthAdminJoin";
import { postAuthAdminLogin } from "../../../providers/postAuthAdminLogin";
import { postAuthAdminRefresh } from "../../../providers/postAuthAdminRefresh";

import { ITodoListAdmin } from "../../../api/structures/ITodoListAdmin";

@Controller("/auth/admin")
export class AuthAdminController {
  /**
   * Register a new admin account (todo_list_admins table) and issue initial JWT
   * tokens.
   *
   * The join endpoint provides a secure mechanism for registering new admin
   * users in the system. It interacts specifically with the todo_list_admins
   * table, ensuring that all required fields—such as email and password—are
   * present and valid.
   *
   * Upon successful registration, the API issues a JWT-based authorization
   * bundle, including both an access and a refresh token. The created admin
   * record is populated according to field definitions in the schema, following
   * all defined constraints and default values.
   *
   * This operation does not require prior authentication, thereby supporting
   * new admin onboarding workflows in accordance with business rules.
   * Validation logic ensures that data such as email addresses are unique and
   * that password fields meet any defined security policies.
   *
   * Returned data adheres to the standard ITodoListAdmin.IAuthorized structure,
   * including authentication and metadata information needed for immediate
   * admin sessions.
   *
   * This operation ties directly to login and refresh endpoints for further
   * credential lifecycle operations, maintaining system integrity and access
   * control for all admin-level functionality.
   *
   * @param connection
   * @param body Admin registration data according to todo_list_admins table
   *   requirements.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoListAdmin.ICreate,
  ): Promise<ITodoListAdmin.IAuthorized> {
    try {
      return await postAuthAdminJoin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate an admin (todo_list_admins table) and issue JWT tokens.
   *
   * This endpoint enables an admin to log in by providing their credentials as
   * defined in the todo_list_admins schema (e.g., email and password fields).
   * The authentication logic is schema-driven, verifying the credentials
   * against securely stored, hashed versions in the database.
   *
   * Upon successful authentication, the API issues a new authorization bundle
   * including JWT access and refresh tokens in the ITodoListAdmin.IAuthorized
   * format, based on admin account information and active session state.
   *
   * The login operation ensures failed attempts are handled with proper error
   * messaging and lockout policies as defined by business rules. It requires no
   * prior authentication but is strictly limited to admin actors.
   *
   * Security considerations focus on credential protection, prevention of
   * brute-force attacks, and compliance with any defined schema security
   * policies, such as encrypted password columns and unique admin identifiers.
   *
   * This endpoint is directly related to the join (admin registration) and
   * refresh endpoints, forming the primary credential management workflow for
   * administrative users.
   *
   * @param connection
   * @param body Admin login credentials as per todo_list_admins authentication
   *   fields.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoListAdmin.ILogin,
  ): Promise<ITodoListAdmin.IAuthorized> {
    try {
      return await postAuthAdminLogin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh JWT access/refresh tokens for admin sessions
   * (todo_list_admin_sessions, todo_list_admins).
   *
   * The refresh endpoint accepts a valid admin JWT refresh token and, after
   * verification, issues a new JWT access token and refresh token for the
   * associated administrator. It interacts with the todo_list_admin_sessions
   * and todo_list_admins tables to ensure secure and stateless session
   * renewal.
   *
   * Validation processes leverage schema-defined relationships and confirm the
   * admin's account remains valid, active, and authorized to continue. New
   * tokens are issued in ITodoListAdmin.IAuthorized response format, in line
   * with the admin authentication lifecycle.
   *
   * Security measures include token authenticity checks, session state
   * validation, and robust error handling for expired or compromised tokens,
   * according to defined project policies. This endpoint never exposes
   * sensitive credential information to the client.
   *
   * The refresh operation is used in conjunction with admin login and join
   * (registration) endpoints, supporting seamless and secure longevity for
   * admin sessions.
   *
   * The interface is reserved for admin account use and follows all security
   * best practices as defined by schema constraints and requirements.
   *
   * @param connection
   * @param body Admin refresh token DTO as per session schema.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: ITodoListAdmin.IRefresh,
  ): Promise<ITodoListAdmin.IAuthorized> {
    try {
      return await postAuthAdminRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
