export async function test_api_organization_deletion_by_owner_success(
  connection: api.IConnection,
): Promise<void> {
  // Step 1: Register a new member (becomes the organization owner)
  const ownerConnection: api.IConnection = { host: connection.host };
  await authorize_member_join(ownerConnection, {});
  // Step 2: Create a new organization — the authenticated member is auto-assigned as Owner
  const organization =
    await generate_random_erp_hrm_member_organizations_create(
      ownerConnection,
      {},
    );
  typia.assert(organization);
  // Step 3: Delete the organization using the owner's connection
  await api.functional.erpHrm.member.organizations.erase(ownerConnection, {
    organizationId: organization.id,
  });
  // Step 4: Post-deletion validation — deleting again should fail (404 Not Found)
  await TestValidator.error(
    "deleted organization should not be found",
    async () => {
      await api.functional.erpHrm.member.organizations.erase(ownerConnection, {
        organizationId: organization.id,
      });
    },
  );
}
