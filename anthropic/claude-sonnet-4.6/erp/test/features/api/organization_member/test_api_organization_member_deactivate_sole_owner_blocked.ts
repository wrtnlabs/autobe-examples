export async function test_api_organization_member_deactivate_sole_owner_blocked(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register the owner's member account
  const ownerConnection: api.IConnection = { host: connection.host };
  const ownerAuth = await authorize_member_join(ownerConnection, {});
  typia.assert(ownerAuth);
  // 2. Create an organization - the registering member automatically becomes the sole Owner
  const organization =
    await generate_random_erp_hrm_member_organizations_create(
      ownerConnection,
      {},
    );
  typia.assert(organization);
  // 3. Attempt to deactivate the sole owner - this must fail with a business error (422)
  // The owner's organization member UUID is available via organization.owner.id
  const ownerOrgMemberId = organization.owner.id;
  await TestValidator.error("sole owner cannot be deactivated", async () => {
    await api.functional.erpHrm.member.organizationMembers.deactivate(
      ownerConnection,
      {
        organizationMemberId: ownerOrgMemberId,
      },
    );
  });
  // 4. Validate that after the rejected attempt, the owner's status is still 'active'
  // (no state mutation should have occurred)
  TestValidator.equals(
    "owner organization member status remains active",
    organization.owner.status,
    "active",
  );
}
