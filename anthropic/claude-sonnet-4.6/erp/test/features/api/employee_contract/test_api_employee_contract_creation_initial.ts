export async function test_api_employee_contract_creation_initial(
  connection: api.IConnection,
): Promise<void> {
  // Step 1: Register the owner member and create an authenticated connection
  const ownerConnection: api.IConnection = { host: connection.host };
  const ownerAuth = await authorize_member_join(ownerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  typia.assert(ownerAuth);
  // Step 2: Create organization (owner becomes the organization Owner automatically)
  const organization =
    await generate_random_erp_hrm_member_organizations_create(ownerConnection, {
      body: {
        name: `TestOrg-${RandomGenerator.alphaNumeric(8)}`,
        currency: "USD",
        timezone: "Asia/Seoul",
        fiscal_start_month: 1,
      },
    });
  typia.assert(organization);
  // Step 3: Register a second member (the employee)
  const employeeAuthConnection: api.IConnection = { host: connection.host };
  const employeeAuth = await authorize_member_join(employeeAuthConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  typia.assert(employeeAuth);
  // Step 4: Add the second member to the organization (authenticated as Owner)
  // We provide the employee's platform memberId; roleId is generated by the prepare function
  const orgMember =
    await generate_random_erp_hrm_member_organization_members_create(
      ownerConnection,
      {
        body: {
          memberId: employeeAuth.member.id,
          employmentType: "full-time",
        },
      },
    );
  typia.assert(orgMember);
  // Step 5: Create the initial employment contract for the employee (as Owner)
  const startDate = new Date().toISOString();
  const notes = RandomGenerator.paragraph({ sentences: 2 });
  const contract =
    await generate_random_erp_hrm_member_organization_members_contracts_create(
      ownerConnection,
      {
        params: {
          organizationMemberId: orgMember.id,
        },
        body: {
          payRate: 5000,
          payPeriod: "monthly",
          workingHoursPerWeek: 40,
          startDate: startDate,
          endDate: null,
          notes: notes,
        },
      },
    );
  typia.assert(contract);
  // Assertions: Validate contract fields
  TestValidator.equals(
    "organizationMemberId matches",
    contract.organizationMemberId,
    orgMember.id,
  );
  TestValidator.equals("payRate matches", contract.payRate, 5000);
  TestValidator.equals("payPeriod is monthly", contract.payPeriod, "monthly");
  TestValidator.equals(
    "workingHoursPerWeek matches",
    contract.workingHoursPerWeek,
    40,
  );
  TestValidator.equals("startDate matches", contract.startDate, startDate);
  TestValidator.equals("endDate is null", contract.endDate, null);
  TestValidator.predicate("isActive is true", contract.isActive === true);
  TestValidator.equals("notes matches", contract.notes, notes);
}
