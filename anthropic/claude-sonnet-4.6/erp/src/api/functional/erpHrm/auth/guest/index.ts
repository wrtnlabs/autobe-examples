/**
 * Registers or retrieves an existing guest identity and issues a JWT-based session for the unauthenticated visitor.
 *
 * This endpoint serves as the entry point for unauthenticated visitors (guests) into the ERP HRM platform. A guest is represented in the database by an `erp_hrm_guests` record, which is uniquely identified by the client-provided `fingerprint` field — a device fingerprint or client-generated identifier used to correlate anonymous activity before account creation or login (as described in the erp_hrm_guests schema: "Device fingerprint or client-generated identifier used to uniquely identify the unauthenticated visitor across sessions").
 *
 * When a join request is received, the service checks whether a guest record with the given fingerprint already exists (using the unique index on the `fingerprint` column). If it does, that record is reused; if not, a new `erp_hrm_guests` record is created with the provided fingerprint and current timestamps (`created_at`, `updated_at`). A new `erp_hrm_guest_sessions` record is then created, capturing the client IP address (`ip`), the page URL (`href`), the HTTP referrer (`referrer`), and an expiry timestamp (`expired_at`) relative to the current time.
 *
 * Upon successful session creation, the server returns an `IErpHrmGuest.IAuthorized` response containing JWT access and refresh tokens. These tokens allow the guest to make subsequent API calls and refresh their session without re-joining. Guest sessions are append-only and are never modified after creation; they are invalidated naturally when they expire (per the erp_hrm_guest_sessions schema: "Sessions are append-only and are never updated after creation").
 *
 * This operation requires the `guest` actor context. It is the prerequisite for any token refresh operation performed by a guest actor. Once the guest completes registration or login as a member, their guest context is no longer used and they transition to an `erp_hrm_members` identity.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Guest join request payload containing the device fingerprint used to identify the unauthenticated visitor.
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor guest
 * @x-autobe-specification 1. Accept the POST request body as IErpHrmGuest.IJoin, which must contain the device fingerprint string.
 * 2. Query the erp_hrm_guests table for an existing record with the matching fingerprint (unique index exists on fingerprint column).
 * 3. If found, use the existing erp_hrm_guests record. If not found, INSERT a new erp_hrm_guests row with a new UUID id, the provided fingerprint, and current timestamps for created_at and updated_at.
 * 4. INSERT a new erp_hrm_guest_sessions row with: a new UUID id, the erp_hrm_guest_id referencing the guest record, the client IP address extracted from the request, href and referrer from the request body or headers, created_at = now(), expired_at = now() + configured session TTL (e.g., 7 days).
 * 5. Generate a JWT access token (short-lived, e.g., 1 hour) and a refresh token (longer-lived, tied to the session record id) for the guest.
 * 6. Return IErpHrmGuest.IAuthorized containing the tokens and the guest identity (id, fingerprint, created_at).
 * 7. Edge cases: If fingerprint is empty or invalid, return 400. No rate limiting specific to this endpoint beyond global limits.
 * @path /erpHrm/auth/guest/join
 * @accessor api.functional.erpHrm.auth.guest.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
