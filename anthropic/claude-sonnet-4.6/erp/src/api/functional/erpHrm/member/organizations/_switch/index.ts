import { IErpHrmOrganizationMember } from "../../../../../structures/IErpHrmOrganizationMember";

/**
 * Switch the authenticated member's active organization context to the specified organization.
 *
 * This operation enables a member who belongs to multiple organizations to change their active working context. All subsequent API calls made after a successful switch are scoped exclusively to the newly selected organization — including employees, projects, tasks, timelogs, timesheets, departments, and all other organizational data. Data from the previous organization context is no longer visible until the member switches back.
 *
 * The system validates that the requesting member is currently an active member of the target organization (i.e., a record exists in `erp_hrm_organization_members` with the combination of the caller's member ID and the specified `organizationId`). If the member is not a member of the target organization, or if the target organization has been deleted, the switch is denied and the current organization context remains unchanged (see section 191 of the functional requirements: Switching to an Unjoined Organization Denied).
 *
 * Upon a successful switch, the server updates the session's active organization context to the target organization. The member's role and permission set are immediately replaced with those defined for their membership record in the newly selected organization. A member holding an Owner role in one organization and an Employee role in another will have full owner-level access in the first context and restricted employee-level access in the second — the switch is instant and complete.
 *
 * The response returns the caller's `erp_hrm_organization_members` record within the newly selected organization, confirming the new identity, role assignment, employment classification, status, position, and department placement that will govern all subsequent actions in this session.
 *
 * This endpoint is related to the organization listing endpoint (e.g., GET /organizations) which must be called first to retrieve the list of organizations the member belongs to and to obtain the target `organizationId` to pass here.
 *
 * @param props.connection
 * @param props.organizationId The UUID of the target organization to switch into. Must be an organization the authenticated member currently belongs to.
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor member
 * @x-autobe-specification 1. Authenticate the requesting member from the
 *   session token. 2. Verify that the target organization (identified by
 *   `organizationId`) exists and is not deleted (deleted_at IS NULL) in
 *   `erp_hrm_organizations`. 3. Query `erp_hrm_organization_members` for a
 *   record matching (organization_id = organizationId AND member_id =
 *   callerMemberId AND deleted_at IS NULL). If no such record exists, return
 *   403 Forbidden — the member is not a member of the target organization. 4.
 *   Verify the found OrganizationMember has status = 'active'. If
 *   'deactivated', return 403 Forbidden. 5. Update the session's active
 *   organization context to the target organizationId. This may be stored in
 *   the JWT, a session store, or a session table (erp_hrm_member_sessions is
 *   append-only, so a new session token or an in-memory context store approach
 *   is appropriate depending on implementation). 6. Load the full
 *   OrganizationMember record including its related role (with permissions),
 *   department (if any), and member profile. 7. Return the
 *   IErpHrmOrganizationMember response DTO representing the caller's membership
 *   in the newly selected organization. 8. Edge cases: If organizationId equals
 *   the currently active organization, the switch is a no-op but still returns
 *   the current OrganizationMember record with 200 OK.
 * @path /erpHrm/member/organizations/:organizationId/switch
 * @accessor api.functional.erpHrm.member.organizations._switch.switchContext
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function switchContext(
  connection: IConnection,
  props: switchContext.Props,
): Promise<switchContext.Response> {
  return true === connection.simulate
    ? switchContext.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...switchContext.METADATA,
          path: switchContext.path(props),
          status: null,
        },
      );
}
export namespace switchContext {
  export type Props = {
    /**
     * The UUID of the target organization to switch into. Must be an organization the authenticated member currently belongs to.
     */
    organizationId: string & tags.Format<"uuid">;
  };
  export type Response = IErpHrmOrganizationMember;

  export const METADATA = {
    method: "POST",
    path: "/erpHrm/member/organizations/:organizationId/switch",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/erpHrm/member/organizations/${encodeURIComponent(props.organizationId ?? "null")}/switch`;
  export const random = (): IErpHrmOrganizationMember =>
    typia.random<IErpHrmOrganizationMember>();
  export const simulate = (
    connection: IConnection,
    props: switchContext.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: switchContext.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("organizationId")(() => typia.assert(props.organizationId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
