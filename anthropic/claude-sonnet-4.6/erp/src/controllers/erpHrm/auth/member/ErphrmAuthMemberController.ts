import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IErpHrmMember } from "../../../../api/structures/IErpHrmMember";
import { postErpHrmAuthMemberJoin } from "../../../../providers/postErpHrmAuthMemberJoin";
import { postErpHrmAuthMemberLogin } from "../../../../providers/postErpHrmAuthMemberLogin";
import { postErpHrmAuthMemberRefresh } from "../../../../providers/postErpHrmAuthMemberRefresh";

@Controller("/erpHrm/auth/member")
export class ErphrmAuthMemberController {
  /**
   * Registers a new member account on the ERP HRM platform by creating a record in the `erp_hrm_members` table with a unique email address and a securely hashed password.
   *
   * This endpoint serves as the primary entry point for unauthenticated guests who wish to create a permanent account. As defined in the `erp_hrm_members` schema, each member is uniquely identified by their `email` field (enforced by a unique index) and authenticates using the `password_hash` column which stores a bcrypt-hashed credential — never a plaintext password.
   *
   * Upon successful registration, the system automatically resolves any pending invitations associated with the provided email address. If any organizations have outstanding invitation records for this email (as stored in the invitations subsystem), the newly created member is immediately linked to those organizations as an employee, eliminating the need for manual acceptance after sign-up.
   *
   * A new `erp_hrm_member_sessions` record is created to track the session context (IP address, href, referrer, and expiry timestamp), and a JWT access token plus refresh token pair are issued and returned in the `IErpHrmMember.IAuthorized` response body.
   *
   * If the provided email is already registered (unique constraint on `erp_hrm_members.email`), the operation returns a conflict error. Password strength validation is applied server-side. The `created_at` and `updated_at` timestamps on the new member record are set to the current server time.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Member registration payload containing email address and password for new account creation.
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor member
   * @x-autobe-specification 1. Validate the request body: email must be a valid email format; password must meet minimum strength requirements. 2. Check uniqueness of email against erp_hrm_members.email — if exists, return 409 Conflict. 3. Hash the password using bcrypt and store in password_hash. 4. INSERT into erp_hrm_members with a new UUID id, the provided email, hashed password, and current timestamps for created_at and updated_at. deleted_at is null. 5. Resolve pending invitations: query the invitations table for any pending invitations matching this email address, and for each, create the corresponding erp_hrm_organization_members record linking the new member to the organization. Mark the invitations as accepted. 6. Create a new erp_hrm_member_sessions record capturing the session context (ip, href, referrer) from request headers, with an appropriate expired_at timestamp (e.g., 30 days for refresh token lifetime). 7. Issue a short-lived JWT access token (e.g., 1 hour) and a long-lived refresh token (e.g., 30 days), embedding the member id and session id as claims. 8. Return IErpHrmMember.IAuthorized containing the member information and both tokens.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IErpHrmMember.IJoin,
  ): Promise<IErpHrmMember.IAuthorized> {
    try {
      return await postErpHrmAuthMemberJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticates an existing member by validating their email and password credentials against the `erp_hrm_members` table and returns a JWT token pair upon success.
   *
   * This endpoint is the primary authentication entry point for registered members. The `erp_hrm_members` table stores each member's unique `email` (used as login identifier) and their `password_hash` (a bcrypt hash). This operation looks up the member by email, verifies the provided plaintext password against the stored hash, and confirms the account is not deactivated (i.e., `deleted_at` is null).
   *
   * Upon successful authentication, a new `erp_hrm_member_sessions` record is inserted to capture the login event context — including the client's IP address, the current page href, and the HTTP referrer header. The session record also stores the `expired_at` timestamp which determines the validity window for the refresh token. This append-only design (per the `erp_hrm_member_sessions` schema comment) means sessions are never deleted but evaluated by their expiry timestamp.
   *
   * A short-lived JWT access token and a long-lived refresh token are issued and returned in the `IErpHrmMember.IAuthorized` response. The access token embeds the member's id and session id as claims, enabling stateless authorization for subsequent requests.
   *
   * If the email does not exist, if the password does not match the stored hash, or if the account has a non-null `deleted_at`, the operation returns a 401 Unauthorized error without distinguishing between the failure reasons to prevent user enumeration attacks.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Member login payload containing the registered email address and plaintext password for credential validation.
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor member
   * @x-autobe-specification 1. Validate request body: email must be non-empty valid email format, password must be non-empty. 2. Query erp_hrm_members WHERE email = provided email AND deleted_at IS NULL. If not found, return 401 Unauthorized. 3. Compare the provided password against password_hash using bcrypt verify. If mismatch, return 401 Unauthorized (same error message as not found to prevent enumeration). 4. INSERT a new erp_hrm_member_sessions record with a new UUID, the member's id, ip from request, href from request, referrer from request headers, current created_at, and expired_at set to now + refresh token lifetime (e.g., 30 days). 5. Issue a short-lived JWT access token (e.g., 1 hour expiry) and a refresh token (e.g., 30 days expiry), both embedding the member id and session id. 6. Return IErpHrmMember.IAuthorized with member info and both tokens.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IErpHrmMember.ILogin,
  ): Promise<IErpHrmMember.IAuthorized> {
    try {
      return await postErpHrmAuthMemberLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Exchanges a valid, unexpired refresh token for a new JWT access token and refresh token pair, extending the authenticated member's session without requiring re-entry of credentials.
   *
   * This operation implements the token refresh flow for members. It validates the provided refresh token by verifying its signature, decoding the embedded session id, and confirming that the corresponding `erp_hrm_member_sessions` record's `expired_at` timestamp has not passed. The referenced session must exist and belong to a member whose `erp_hrm_members.deleted_at` is null (i.e., an active account).
   *
   * The `erp_hrm_member_sessions` table, as described in the schema, is append-only — sessions are never deleted but expired via the `expired_at` column. This design allows full audit history of all login events and supports multi-device session tracking. Upon a successful refresh, the old session's `expired_at` is updated (or a new session record may be created) to reflect the renewed validity window.
   *
   * A new short-lived access token and a new refresh token are issued and returned in the `IErpHrmMember.IAuthorized` response body. Clients should replace their stored tokens with the newly issued pair.
   *
   * If the refresh token signature is invalid, has expired (its session's `expired_at` is in the past), or the associated member account is deactivated (`deleted_at` is not null), the operation returns a 401 Unauthorized response. Clients must re-authenticate via the login endpoint in this case.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Token refresh payload containing the valid refresh token to be exchanged for a new access and refresh token pair.
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor member
   * @x-autobe-specification 1. Validate the provided refresh token: verify JWT signature and extract claims (member id, session id). 2. Query erp_hrm_member_sessions WHERE id = session id from token. If not found, return 401. 3. Check expired_at > current time. If expired, return 401. 4. Load the associated erp_hrm_members record. Verify deleted_at IS NULL. If deleted, return 401. 5. Invalidate the old session by updating its expired_at to now (consumed), or leave as audit record and create a new session. 6. Insert a new erp_hrm_member_sessions record with updated context (ip, href, referrer from request), new expired_at = now + refresh token lifetime. 7. Issue a new short-lived access token and a new refresh token with the member id and new session id as claims. 8. Return IErpHrmMember.IAuthorized with member info and the new token pair.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IErpHrmMember.IRefresh,
  ): Promise<IErpHrmMember.IAuthorized> {
    try {
      return await postErpHrmAuthMemberRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
