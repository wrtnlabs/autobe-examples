import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IErpHrmMemberSession } from "../../../../api/structures/IErpHrmMemberSession";
import { IPageIErpHrmMemberSession } from "../../../../api/structures/IPageIErpHrmMemberSession";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getErpHrmMemberSessionsSessionId } from "../../../../providers/getErpHrmMemberSessionsSessionId";
import { patchErpHrmMemberSessions } from "../../../../providers/patchErpHrmMemberSessions";

@Controller("/erpHrm/member/sessions")
export class ErphrmMemberSessionsController {
  /**
   * Retrieve a paginated and filtered list of member session records.
   *
   * This operation returns session records from the `erp_hrm_member_sessions` table, which tracks JWT-based login sessions for authenticated members. Each session record captures the connection context at the time of login — including the client IP address, the originating page URL (`href`), and the HTTP referrer header — alongside creation and expiry timestamps.
   *
   * The authenticated member can use this endpoint to review their own active and historical login sessions across all devices and browsers. This supports account security awareness, allowing members to identify unfamiliar login origins and take action if needed. Members with appropriate administrative permissions may also browse sessions of other members within their organization context.
   *
   * Search criteria support filtering by session status (active vs. expired), IP address substring match, and a date range on `created_at` to narrow results to a specific login period. Pagination is provided to handle members with extensive session histories. Results are ordered by `created_at` descending by default, showing the most recent login events first.
   *
   * This endpoint depends on valid authentication. The caller must be a logged-in member. The server derives the member identity from the authenticated session token and scopes the default query to that member's own sessions unless an administrative override is in effect.
   *
   * Related operations: use `POST /login` to create a new session, and `DELETE /sessions/{sessionId}` to invalidate a specific session. Session invalidation is also triggered automatically upon account deletion as per the user-deleted event flow.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering member session records
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification 1. Authenticate the caller using the session
     *   token from the request header. Resolve the calling member's ID from
     *   erp_hrm_members. 2. Accept the IErpHrmMemberSession.IRequest body
     *   containing optional filters: ip (partial string match), isActive
     *   (boolean: true = expired_at > now, false = expired_at <= now),
     *   createdAtFrom / createdAtTo (date-time range on created_at), and
     *   pagination fields (page, limit, sort direction). 3. Query
     *   erp_hrm_member_sessions WHERE erp_hrm_member_id = authenticated
     *   member's ID (default scope). Apply additional filters as provided: - If
     *   ip is provided: WHERE ip ILIKE '%{ip}%' - If isActive = true: WHERE
     *   expired_at > NOW() - If isActive = false: WHERE expired_at <= NOW() -
     *   If createdAtFrom is provided: WHERE created_at >= createdAtFrom - If
     *   createdAtTo is provided: WHERE created_at <= createdAtTo 4. Order
     *   results by created_at DESC (default). Allow optional sort by
     *   expired_at. 5. Apply limit/offset pagination. Return total count for
     *   pagination metadata. 6. Map each row to IErpHrmMemberSession.ISummary,
     *   projecting: id, ip, href, referrer, created_at, expired_at, and a
     *   derived isActive boolean (expired_at > now). 7. Return
     *   IPageIErpHrmMemberSession.ISummary with pagination metadata (total,
     *   page, limit). 8. Edge cases: - If no sessions exist, return empty data
     *   array with total=0. - Validate date range: createdAtFrom must not be
     *   after createdAtTo. - Large limit values should be capped (e.g., max 100
     *   per page).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IErpHrmMemberSession.IRequest,
  ): Promise<IPageIErpHrmMemberSession.ISummary> {
    try {
      return await patchErpHrmMemberSessions({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific member session record by its unique identifier.
   *
   * This operation returns the full details of a single session stored in the `erp_hrm_member_sessions` table. Each session row represents one login event for an authenticated member (`erp_hrm_members`), capturing the client's IP address, the page URL (`href`) from which the login originated, the HTTP Referrer header value at login time, the session creation timestamp (`created_at`), and the session expiry or invalidation timestamp (`expired_at`).
   *
   * Sessions in this system are append-only audit records — they are never deleted during logout or expiry. Instead, validity is determined by comparing the current time against the `expired_at` field. This allows full audit history of login events to be preserved and queried even after a session has been invalidated.
   *
   * Access to session details is restricted to the authenticated member who owns the session. The caller must be logged in as the member referenced by `erp_hrm_member_id` on the target session record. Attempts to access another member's session will be rejected with an authorization error.
   *
   * This endpoint is typically used alongside the session list operation to allow a member to inspect the details of a particular historical login event — for example, to investigate an unfamiliar login from an unexpected IP address. It can also be used by security-aware clients to confirm whether a given session token is still valid by checking the returned `expired_at` value.
   *
   * @param connection
   * @param sessionId The UUID of the target session record to retrieve.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification 1. Validate that the caller is an authenticated
     *   member (active session, not deleted account). 2. Query the
     *   erp_hrm_member_sessions table WHERE id = :sessionId. 3. If no record is
     *   found, return 404 Not Found. 4. Verify that the found session's
     *   erp_hrm_member_id matches the authenticated caller's member ID. If not,
     *   return 403 Forbidden. 5. Return the full session record, mapping all
     *   columns: id, erp_hrm_member_id, ip, href, referrer, created_at,
     *   expired_at. 6. Include the related member reference (erp_hrm_members)
     *   if the DTO requires it for context. 7. Do not delete or mutate any data
     *   — this is a read-only operation.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<IErpHrmMemberSession> {
    try {
      return await getErpHrmMemberSessionsSessionId({
        member,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
