import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IErpHrmInvitation } from "../../../../../api/structures/IErpHrmInvitation";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { postErpHrmMemberInvitationsInvitationIdAccept } from "../../../../../providers/postErpHrmMemberInvitationsInvitationIdAccept";

@Controller("/erpHrm/member/invitations/:invitationId/accept")
export class ErphrmMemberInvitationsController {
  /**
   * Accept a specific pending invitation within the organization, transitioning it from 'pending' to 'accepted' status and adding the invitee as an active organization member.
   *
   * This operation allows users with the `employee:manage` permission to manually accept a pending invitation on behalf of the organization. When accepted, the system locates the invitation record in `erp_hrm_invitations` by the given `invitationId`, verifies it is in `pending` status, resolves or confirms the linked `erp_hrm_members` account for the invited email address, and creates or confirms an `erp_hrm_organization_members` record to formally add the invitee to the organization. The invitation's `status` field is then updated from `pending` to `accepted` and the `erp_hrm_member_id` is populated with the matching member account.
   *
   * Access control is strictly enforced: only authenticated members holding the `employee:manage` permission within the organization that owns this invitation may perform this action. Any attempt by an unauthorized actor is rejected. The invitation must belong to the same organization context as the acting member.
   *
   * The `erp_hrm_invitations` table tracks the full lifecycle of each invitation. The `status` field transitions follow the allowed lifecycle: `pending` → `accepted`. If the invitation is already in a terminal state (`accepted`, `rejected`, `expired`, or `cancelled`), this operation will fail with an appropriate error. Similarly, if no registered `erp_hrm_members` account exists for the invited email address at the time of this call, the operation cannot complete successfully.
   *
   * Related operations: `POST /organizations/{organizationId}/invitations` to send an initial invitation, `PATCH /invitations` to list and monitor all invitations for an organization, and `GET /invitations/{invitationId}` to retrieve a specific invitation's current status and details.
   *
   * @param connection
   * @param invitationId The unique UUID identifier of the pending invitation to be accepted.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification 1. Authenticate the acting member and verify they
     *   hold the `employee:manage` permission within the organization context.
     *   2. Query `erp_hrm_invitations` by the provided `invitationId` (UUID
     *   primary key). If not found, return 404. 3. Validate that the
     *   invitation's `erp_hrm_organization_id` matches the acting member's
     *   current organization context. If not, return 403. 4. Check the
     *   invitation's `status` field: if it is not `pending`, return a 422 or
     *   409 error indicating the invitation is not in a state that can be
     *   accepted. 5. Look up `erp_hrm_members` by the invitation's `email`
     *   field. If no active member account exists for that email (i.e., the
     *   invitee has not yet registered), return a 422 error — the invitee must
     *   register first before this manual acceptance can be applied. 6. In a
     *   database transaction: a. Update the `erp_hrm_invitations` record: set
     *   `status = 'accepted'`, `erp_hrm_member_id = <matched member's id>`, and
     *   `updated_at = NOW()`. b. Check if an `erp_hrm_organization_members`
     *   record already exists for `(organization_id, member_id)`. If not,
     *   create a new `erp_hrm_organization_members` record using the
     *   organization's default role (e.g., the Employee built-in role) and
     *   `employment_type` and `status = 'active'`. 7. Commit the transaction.
     *   8. Return the updated `erp_hrm_invitations` record as
     *   `IErpHrmInvitation`, including the linked member and organization
     *   details. 9. Emit a real-time invitation accepted event and a
     *   member-added event to relevant subscribers per the real-time monitoring
     *   requirements.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async accept(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("invitationId")
    invitationId: string & tags.Format<"uuid">,
  ): Promise<IErpHrmInvitation> {
    try {
      return await postErpHrmMemberInvitationsInvitationIdAccept({
        member,
        invitationId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
