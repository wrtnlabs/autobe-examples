  /**
   * Permanently discard an employee's active timer session without creating a timelog record.
   *
   * This operation terminates and permanently removes the specified timer from the system. Unlike stopping a timer — which converts the elapsed session into a persisted timelog entry — discarding a timer destroys the tracking session entirely. No work record is created, and the elapsed time is lost.
   *
   * The discard action is fully irreversible. Once a timer is discarded, neither the timer record nor the elapsed duration can be recovered by any means. The system provides no undo or recovery mechanism after the confirmation of a discard.
   *
   * Access control follows a two-tier model. The timer's owner (the organization member whose `organization_member_id` matches the timer record) may always discard their own active timer. Additionally, users holding the time management permission (`time:manage`) within the organization are permitted to discard any employee's active timer — including timers not belonging to themselves. Employees who do not own the timer and do not hold the time management permission will receive a 403 Forbidden response.
   *
   * The underlying `erp_hrm_timers` table stores transient timer records with no `deleted_at` column, confirming that timer records are physically deleted (not logically marked) when this operation is executed. The record is identified by its UUID primary key (`timerId` path parameter).
   *
   * If no active timer with the provided `timerId` exists, the operation returns a 404 Not Found response. If the caller neither owns the referenced timer nor holds the time management permission, a 403 Forbidden response is returned. No partial state is left behind in any failure scenario.
   *
   * @param connection
   * @param timerId The UUID of the active timer to be discarded.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification 1. Authenticate the current member session and resolve their organization context.
   * 2. Look up the erp_hrm_timers record by the provided timerId (UUID primary key).
   * 3. Verify the record exists; if not, return 404.
   * 4. Verify that erp_hrm_timers.organization_member_id matches the authenticated member's organization_member id for this organization context; if not, return 403 (even if the caller has time:manage permission).
   * 5. Permanently delete the erp_hrm_timers record using a hard DELETE SQL statement (no soft-delete column exists on this table).
   * 6. Return HTTP 204 No Content on success.
   * 7. No timelog record is created at any point during this operation.
   * 8. Wrap the delete in a transaction to ensure atomicity; any failure rolls back and the timer record is preserved intact.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":timerId")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("timerId")
    timerId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteErpHrmMemberTimersTimerId({
        member,
        timerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Stop an active timer and automatically create a timelog from the elapsed session.
   *
   * This operation terminates the authenticated member's active timer session identified by `timerId`. Upon invocation, the system calculates the total elapsed duration from the timer's `started_at` timestamp to the moment the stop action is taken. The duration is rounded to the nearest whole minute (e.g., 7 minutes 29 seconds → 7 minutes; 7 minutes 30 seconds → 8 minutes), consistent with the rounding rules defined for the `duration_minutes` field in `erp_hrm_timelogs`.
   *
   * If the rounded duration is greater than zero, the system automatically creates a new `erp_hrm_timelogs` record on behalf of the member. The newly created timelog inherits the `project_id`, `task_id`, and `description` from the timer at the moment of stopping. The `work_date` is set to the calendar date of the stop action, and `billable` defaults to `true`. The timer record in `erp_hrm_timers` is then permanently removed since timers are transient records that exist only to facilitate real-time tracking.
   *
   * If the elapsed time rounds to zero minutes (i.e., the timer was stopped almost immediately after starting), the system does not create a timelog. The operation is rejected or treated as equivalent to discarding the timer, and the caller is informed that the elapsed time was insufficient to record.
   *
   * Access control is enforced at the service layer: only the owner of the timer (the `organization_member_id` associated with the timer) may call this endpoint. Members holding the time management permission may stop any employee's active timer on their behalf.
   *
   * This operation depends on the existence of an active timer. To verify or retrieve the current state of the active timer before stopping it, use `GET /timers/{timerId}`. After the timelog is created, it follows its own independent lifecycle and may be submitted as part of a weekly timesheet via the Timesheet endpoints.
   *
   * @param connection
   * @param timerId The UUID of the active timer to stop. Must be an existing active timer record in erp_hrm_timers.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification 1. Authenticate the calling member and resolve their organization_member_id from the session.
   * 2. Look up the timer record in erp_hrm_timers by the given timerId (UUID). If not found, return 404.
   * 3. Authorization check: verify that either (a) the timer's organization_member_id matches the calling member's organization_member_id, or (b) the calling member holds the time management permission within the same organization. If neither condition is met, return 403.
   * 4. Compute elapsed duration: subtract started_at from the current UTC timestamp to get total seconds. Convert to minutes using standard rounding (round half up): Math.round(totalSeconds / 60). Store as duration_minutes.
   * 5. If duration_minutes === 0: do NOT create a timelog. Return an error response (e.g., 422 Unprocessable Entity) indicating the elapsed time was too short to record. Do not delete the timer in this case — or treat it as a discard (implementation decision based on UX requirements; typically reject without deleting).
   * 6. If duration_minutes > 0:
   *    a. Begin a database transaction.
   *    b. Insert a new row into erp_hrm_timelogs with:
   *       - id: new UUID
   *       - organization_member_id: from the timer
   *       - project_id: from the timer
   *       - task_id: from the timer (nullable)
   *       - timesheet_id: null (not yet assigned to any timesheet)
   *       - work_date: current UTC date (midnight UTC of the stop timestamp)
   *       - duration_minutes: calculated value
   *       - billable: true (default)
   *       - description: from the timer (nullable)
   *       - created_at: current UTC timestamp
   *       - updated_at: current UTC timestamp
   *    c. Delete the timer record from erp_hrm_timers by timerId.
   *    d. Commit the transaction.
   * 7. Return the newly created erp_hrm_timelogs record as IErpHrmTimelog.
   * 8. Edge cases:
   *    - If the timer is not active (already stopped/deleted concurrently), return 404 or 409.
   *    - Wrap the insert + delete in a transaction to ensure atomicity; if either step fails, roll back and return 500.
   *    - Do not allow this endpoint to be called for a timer belonging to a different organization than the calling member's active organization context.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post(":timerId/stop")
  public async stop(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("timerId")
    timerId: string & tags.Format<"uuid">,
  ): Promise<IErpHrmTimelog> {
    try {
      return await postErpHrmMemberTimersTimerIdStop({
        member,
        timerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
