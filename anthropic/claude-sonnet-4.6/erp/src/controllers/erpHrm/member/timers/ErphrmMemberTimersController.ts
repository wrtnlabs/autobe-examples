  /**
   * Update the editable fields of an active running timer.
   *
   * This operation allows the authenticated organization member to modify their currently active timer while it continues to run uninterrupted. The timer being updated is identified by its unique UUID (`timerId`) and must belong to the currently authenticated member — an employee can only edit their own active timer.
   *
   * The following fields may be updated: the free-text `description` describing the work being performed, the `project` against which the session is being tracked, and the optional `task` within the selected project. All edits take effect immediately without resetting, pausing, or interrupting the timer's elapsed duration.
   *
   * If the `project_id` is changed to a different project, any previously associated task is automatically cleared, because the prior task no longer belongs to the newly selected project. The caller may then optionally provide a new `task_id` that belongs to the newly selected project. If a `task_id` is submitted without a project change (or alongside a project change), the task must belong to the currently effective project; otherwise the request is rejected.
   *
   * The replacement project must be one that the authenticated employee is currently assigned to as a project member. Submitting a project to which the employee is not assigned will result in a validation error.
   *
   * This operation is strictly scoped to the timer's owner. Users who hold the `time:manage` permission are permitted to edit or delete already-created timelogs, but they are NOT permitted to operate another employee's active running timer through this endpoint. Only the employee who started the timer may call this operation.
   *
   * Related operations:
   * - `POST /timers` should be called first to start a timer session before editing it.
   * - `DELETE /timers/{timerId}` can be used to discard the timer without creating a timelog.
   * - `POST /timers/{timerId}/stop` can be used to stop the timer and convert it to a timelog.
   *
   * @param connection
   * @param timerId The UUID of the active timer to update. Must belong to the currently authenticated organization member.
   * @param body Fields to update on the running timer: description, associated project, and/or associated task.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification 1. Authenticate the requesting member from the session context.
   * 2. Load the timer record from `erp_hrm_timers` by the given `timerId` UUID.
   * 3. Verify the timer exists; if not, return 404.
   * 4. Verify that `organization_member_id` on the timer matches the authenticated member's organization member ID. If it does not match, return 403 — employees may only edit their own timer.
   * 5. Validate the incoming request body:
   *    a. If `project_id` is provided and differs from the current `project_id`:
   *       - Verify the authenticated member has a `erp_hrm_project_members` record linking them to the new project. If not, return 403/422.
   *       - Clear any currently set `task_id` (set to null) unless a new `task_id` is also provided in the same request.
   *    b. If `task_id` is provided:
   *       - Determine the effective project: use the new `project_id` if it was changed in this request, otherwise use the current `project_id`.
   *       - Verify the task exists in `erp_hrm_tasks` and its `project_id` matches the effective project. If not, return 422.
   *    c. `description` may be any string or null; no additional validation beyond length limits.
   * 6. Apply updates: UPDATE `erp_hrm_timers` SET project_id = ..., task_id = ..., description = ... WHERE id = timerId.
   * 7. Return the updated timer record with all fields including related project and task details.
   * 8. Note: No `updated_at` column exists on `erp_hrm_timers` per the schema — do not attempt to update such a field.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
