  /**
   * Start a new real-time tracking timer session for the currently authenticated organization member.
   *
   * This operation creates a new active timer record in the `erp_hrm_timers` table, representing a live work session the member is beginning. A timer is bound to exactly one project and optionally one task within that project. The `started_at` timestamp is recorded at the moment the timer is created, and it will be used to compute the elapsed duration when the timer is eventually stopped and converted into a timelog entry.
   *
   * A fundamental constraint enforced by the system is that each organization member may have at most one active timer at any time. The `erp_hrm_timers` table enforces this through a unique constraint on `organization_member_id`. If the authenticated member already has a running timer, this request will be rejected. The member must stop or discard their existing timer before starting a new one.
   *
   * The target project must be one that the authenticated member is currently assigned to as a project member. Providing a project the member is not a member of will result in a rejection. If a task is specified, it must belong to the selected project; tasks from other projects are not permitted. Providing a task that is not part of the given project will also result in a rejection.
   *
   * The optional `description` field allows the member to note what they are currently working on during the session. This can also be updated later while the timer is running via the timer update endpoint without interrupting the session.
   *
   * Once started, the timer runs indefinitely. There is no automatic timeout or system-enforced duration limit. The timer continues until the member explicitly stops it (which creates a timelog) or discards it (which removes the timer without creating any timelog).
   *
   * This operation is only available to authenticated members and applies exclusively to the caller's own timer. A member cannot start a timer on behalf of another member.
   *
   * @param connection
   * @param body Timer creation input specifying the project, optional task, and optional description for the new tracking session.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification 1. Authenticate the request and resolve the caller's organization member record from the session (organization_member_id).
   * 2. Check whether the member already has an active timer by querying erp_hrm_timers WHERE organization_member_id = <caller_id>. If a record exists, return HTTP 409 Conflict — a member may have at most one active timer.
   * 3. Validate that the provided project_id references an existing, non-deleted project within the same organization as the member (erp_hrm_projects WHERE id = project_id AND organization_id = member.organization_id AND deleted_at IS NULL). Return HTTP 404 if not found.
   * 4. Validate that the member is an active project member of the given project by querying erp_hrm_project_members WHERE project_id = <project_id> AND organization_member_id = <caller_id>. Return HTTP 403 if not found.
   * 5. If task_id is provided, validate that the task exists in erp_hrm_tasks WHERE id = task_id AND erp_hrm_project_id = project_id AND deleted_at IS NULL. Return HTTP 422 if the task does not belong to the project.
   * 6. Insert a new record into erp_hrm_timers: { id: uuid, organization_member_id, project_id, task_id (nullable), description (nullable), started_at: now(), created_at: now() }.
   * 7. Return the newly created timer record as IErpHrmTimer.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IErpHrmTimer.ICreate,
  ): Promise<IErpHrmTimer> {
    try {
      return await postErpHrmMemberTimers({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a paginated and filtered list of active timer sessions within the current organization context.
   *
   * This operation allows authenticated members to search and browse live real-time tracking sessions (timers) stored in the `erp_hrm_timers` table. Each timer record represents an active, in-flight time tracking session started by an organization member against a specific project and optionally a task. The `erp_hrm_timers` table enforces a unique constraint on `organization_member_id`, meaning at most one active timer exists per member at any given time.
   *
   * Access control is applied based on the requesting member's permissions. A regular employee without the `time:view_all` permission will only see their own active timer (if one exists). A user holding the `time:view_all` permission — typically a Manager or Owner — can see all active timers belonging to any employee within the same organization, which is the primary data source for the organization dashboard's active timer display and workforce activity overview.
   *
   * Search criteria include filtering by project, organization member, and whether a task is assigned. Sorting and pagination are supported to handle organizations with many concurrent active timers. The response includes timer details such as the associated project, optional task, optional description, and the exact timestamp when the timer was started (`started_at`), which clients use to compute live elapsed duration on the frontend.
   *
   * This endpoint is typically pre-executed before starting a new timer (`POST /timers`) or when rendering the organization dashboard. The existence of an active timer for the current user can also be checked here before attempting to start a new one, as the system only allows one active timer per member.
   *
   * Related operations:
   * - `POST /timers` — Start a new timer session (will fail if an active timer already exists for the member)
   * - `PUT /timers/{timerId}` — Update description, project, or task of a running timer
   * - `DELETE /timers/{timerId}` — Stop the timer and create a timelog, or discard without creating a timelog
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering active timer sessions
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification 1. Authenticate the requesting member and determine their organization context from the session.
   * 2. Check if the member has the `time:view_all` permission (via their role's permission codes).
   * 3. Build the base query on `erp_hrm_timers` joined with `erp_hrm_organization_members`, `erp_hrm_projects`, and optionally `erp_hrm_tasks`.
   * 4. Authorization filter:
   *    - If the member does NOT have `time:view_all`: add a WHERE clause restricting to `organization_member_id = <current_member_id>`.
   *    - If the member HAS `time:view_all`: filter by `organization_id` only (all timers within the organization).
   * 5. Apply optional search filters from the request body:
   *    - `projectId`: filter by `project_id`
   *    - `organizationMemberId`: filter by `organization_member_id` (only applies if requester has `time:view_all`)
   *    - `hasTask`: if true, filter WHERE `task_id IS NOT NULL`; if false, filter WHERE `task_id IS NULL`
   * 6. Apply pagination: `limit` and `offset` (or cursor) from the request body.
   * 7. Apply sorting: default sort by `started_at DESC` (most recently started timers first). Support sorting by `started_at`.
   * 8. Return paginated results including timer id, started_at, description, project summary (id, name, color), task summary (id, title) if present, and organization member summary (id, name).
   * 9. Compute total count for pagination metadata.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
