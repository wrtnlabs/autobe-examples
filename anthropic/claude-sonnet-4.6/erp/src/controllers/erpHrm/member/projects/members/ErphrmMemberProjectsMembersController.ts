  /**
   * Remove an organization member from a specific project within the ERP HRM system.
   *
   * This operation removes a project membership record identified by `projectMemberId` from the project identified by `projectId`. The membership is recorded in the `erp_hrm_project_members` table, which links an `erp_hrm_organization_members` record to an `erp_hrm_projects` record with a designated project-scoped role (`member` or `project-lead`). Upon successful removal, the membership record's `deleted_at` timestamp is set to the current time, preserving the historical participation record for audit purposes without physically destroying the data.
   *
   * This operation requires the authenticated member to hold the `project:manage` permission within the organization. Project leads may manage tasks within their assigned project but cannot remove project members unless they also hold the `project:manage` permission. Any attempt by a member without this permission is rejected with an authorization error.
   *
   * As a critical side effect of this operation, the system automatically clears the task assignee field on any tasks within the project that were previously assigned to the removed member. A task cannot remain assigned to an employee who is no longer a member of the project, since task assignees must always be current active project members. The tasks themselves are not deleted; they continue to exist within the project with their existing status, priority, and other attributes. Users with `project:manage` permission or project leads may subsequently reassign those tasks to other active project members.
   *
   * If the member being removed is already inactive (has a non-null `deleted_at` on their `erp_hrm_project_members` record), the system rejects the operation. The target project must also exist and not be marked as deleted. Related operations include `POST /projects/{projectId}/members` to assign members to a project and `GET /projects/{projectId}/members/{projectMemberId}` to retrieve membership details.
   *
   * @param connection
   * @param projectId The UUID of the project from which the member is to be removed.
   * @param projectMemberId The UUID of the project membership record to remove.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification 1. Authenticate the calling member and extract
     *   their organization context from the session. 2. Verify the caller has
     *   the `project:manage` permission within the organization. If not, return
     *   403 Forbidden. 3. Look up the project record in `erp_hrm_projects` by
     *   `projectId` where `deleted_at IS NULL`. If not found, return 404 Not
     *   Found. 4. Verify the project belongs to the caller's current
     *   organization. If not, return 404 Not Found (data isolation). 5. Look up
     *   the project membership record in `erp_hrm_project_members` by
     *   `projectMemberId` where `project_id = projectId` AND `deleted_at IS
     *   NULL`. If not found, return 404 Not Found. 6. Begin a database
     *   transaction. 7. Set `deleted_at = NOW()` and `updated_at = NOW()` on
     *   the `erp_hrm_project_members` record. 8. Query `erp_hrm_tasks` for all
     *   tasks in the project (`project_id = projectId`) where
     *   `assignee_organization_member_id = organization_member_id` of the
     *   removed member and `deleted_at IS NULL`. For each such task, set
     *   `assignee_organization_member_id = NULL` and update `updated_at =
     *   NOW()`. 9. Commit the transaction. If any step fails, roll back and
     *   return 500 Internal Server Error. 10. Return the updated project
     *   membership record (with `deleted_at` populated) as the response body,
     *   typed as `IErpHrmProjectMember`.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
