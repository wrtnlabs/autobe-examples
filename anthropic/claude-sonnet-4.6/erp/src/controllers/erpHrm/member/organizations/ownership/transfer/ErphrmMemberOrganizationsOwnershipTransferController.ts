import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IErpHrmOrganization } from "../../../../../../api/structures/IErpHrmOrganization";
import { MemberAuth } from "../../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../../decorators/payload/MemberPayload";
import { postErpHrmMemberOrganizationsOrganizationIdOwnershipTransfer } from "../../../../../../providers/postErpHrmMemberOrganizationsOrganizationIdOwnershipTransfer";

@Controller("/erpHrm/member/organizations/:organizationId/ownership/transfer")
export class ErphrmMemberOrganizationsOwnershipTransferController {
  /**
   * Transfer ownership of an organization from the current owner to another active organization member.
   *
   * This operation allows the organization's current Owner to hand over their ownership role to an existing active member of the same organization. The designated recipient must already be a member of the organization with an active status. Upon completion, the recipient is elevated to the Owner role, and the outgoing owner is reassigned to a non-Owner role as specified in the request body. The organization will always have exactly one owner at any point in time.
   *
   * Only the current Owner of the organization may invoke this endpoint. Members holding any other role — including Manager — are not authorized to perform an ownership transfer. Any unauthorized attempt will be rejected.
   *
   * Ownership transfer is a critical prerequisite in the account deletion flow. A user who is the sole owner of one or more organizations cannot delete their platform account until they either transfer ownership of each such organization to another active member, or delete those organizations entirely. This endpoint fulfills the transfer path of that requirement, ensuring continuity of ownership without interrupting organizational data.
   *
   * If the organization has no other active members, ownership transfer is not possible and the sole owner must instead delete the organization before proceeding with account deletion.
   *
   * Related operations:
   * - `DELETE /members/me` (account deletion) — requires this endpoint to be called first if the authenticated user is the sole owner of any organization.
   * - `DELETE /erpHrm/member/organizations/{organizationId}` — alternative path when there are no other active members to receive ownership.
   *
   * @param connection
   * @param organizationId The UUID of the organization whose ownership is being transferred.
   * @param body Ownership transfer details: the target member to receive the Owner role and the role to assign to the outgoing owner.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification 1. Authenticate the calling member via their
     *   session and resolve their erp_hrm_organization_members record for the
     *   given organizationId. 2. Verify the caller holds the Owner role
     *   (erp_hrm_roles.is_builtin = true, name = 'Owner') in this organization.
     *   If not, reject with 403 Forbidden. 3. Verify the organization
     *   (erp_hrm_organizations) exists and is not deleted (deleted_at IS NULL).
     *   If not found, reject with 404. 4. From the request body, extract
     *   targetMemberId (the erp_hrm_organization_members.id of the intended new
     *   owner) and outgoingOwnerRoleId (the erp_hrm_roles.id the former owner
     *   will be demoted to). 5. Validate that the target organization member:
     *   a. Exists in erp_hrm_organization_members for this organizationId. b.
     *   Has status = 'active'. c. Is not already the Owner (i.e., not the same
     *   member as the caller). 6. Validate that outgoingOwnerRoleId refers to a
     *   valid role in erp_hrm_roles scoped to this organization and is NOT the
     *   Owner role. 7. In a single database transaction: a. Update the target
     *   member's erp_hrm_organization_members.role_id to the Owner role ID. b.
     *   Update the caller's (former owner's)
     *   erp_hrm_organization_members.role_id to outgoingOwnerRoleId. c. Update
     *   erp_hrm_organizations.owner_member_id to the target member's
     *   erp_hrm_members.member_id (the platform-level member reference). d. Set
     *   updated_at = NOW() on both erp_hrm_organization_members records and the
     *   erp_hrm_organization record. 8. Return the updated
     *   erp_hrm_organizations record as IErpHrmOrganization.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async transferOwnership(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("organizationId")
    organizationId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IErpHrmOrganization.ITransferOwnership,
  ): Promise<IErpHrmOrganization> {
    try {
      return await postErpHrmMemberOrganizationsOrganizationIdOwnershipTransfer(
        {
          member,
          organizationId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
