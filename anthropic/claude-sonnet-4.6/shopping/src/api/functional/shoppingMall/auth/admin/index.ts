/**
 * Registers and activates a new administrator account on the shopping mall platform.
 *
 * Administrator accounts in the shopping mall platform are not created independently from scratch. Rather, they are promoted from existing customer (`shopping_mall_customers`) or seller (`shopping_mall_sellers`) accounts that have successfully passed the administrator request and approval process. This join operation finalizes the promotion by recording the admin's credentials — specifically their email address (inherited from the originating account) and a bcrypt-hashed password — into the `shopping_mall_admins` table.
 *
 * The `shopping_mall_admins` table stores the admin's `email` (unique, inherited from the originating account and used as the login identifier), `password_hash` (bcrypt one-way hash; plaintext is never persisted), `actor_type` discriminator (either 'customer' or 'seller' indicating the origin account type), and timestamps for `created_at` and `updated_at`. The `deleted_at` field is null for newly joined admins, indicating the account is active.
 *
 * Upon successful account creation, this endpoint immediately establishes a new JWT session by creating a record in `shopping_mall_admin_sessions` with the generated `access_token`, `refresh_token`, client connection metadata (`ip`, `href`, `referrer`), and expiration timestamp (`expired_at`). The response returns the full `IShoppingMallAdmin.IAuthorized` payload containing the tokens and admin profile details.
 *
 * Security considerations: the email must be unique within the `shopping_mall_admins` table (enforced by a unique index). Duplicate email registration attempts must be rejected. Passwords must be securely hashed using bcrypt before persistence. This endpoint requires admin-level authorization as it is the entry point for activating a promoted admin account.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Admin account registration (promotion activation) credentials including email and password.
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor admin
 * @x-autobe-specification 1. Validate that the provided email is not already
 *   registered in shopping_mall_admins (unique constraint check). 2. Hash the
 *   provided plaintext password using bcrypt with an appropriate cost factor.
 *   3. Determine the actor_type based on whether the promoter originated from a
 *   customer or seller account (passed as part of the join payload or resolved
 *   from the promotion context). 4. Insert a new record into
 *   shopping_mall_admins with id (UUID), actor_type, email, password_hash,
 *   created_at=now(), updated_at=now(), deleted_at=null. 5. Create a new
 *   session in shopping_mall_admin_sessions: generate UUID id, set
 *   shopping_mall_admin_id to the new admin id, generate JWT access_token and
 *   refresh_token, record ip/href/referrer from request context, set
 *   created_at=now(), set expired_at to access token expiry. 6. Return
 *   IShoppingMallAdmin.IAuthorized containing the access_token, refresh_token,
 *   and admin profile data. 7. Edge cases: if email already exists, return 409
 *   Conflict. If required fields are missing or invalid, return 400 Bad
 *   Request.
 * @path /shoppingMall/auth/admin/join
 * @accessor api.functional.shoppingMall.auth.admin.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
