import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallCustomerAddress } from "../../../../../api/structures/IPageIShoppingMallCustomerAddress";
import { IShoppingMallCustomerAddress } from "../../../../../api/structures/IShoppingMallCustomerAddress";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminCustomersCustomerIdAddressesAddressId } from "../../../../../providers/getShoppingMallAdminCustomersCustomerIdAddressesAddressId";
import { patchShoppingMallAdminCustomersCustomerIdAddresses } from "../../../../../providers/patchShoppingMallAdminCustomersCustomerIdAddresses";

@Controller("/shoppingMall/admin/customers/:customerId/addresses")
export class ShoppingmallAdminCustomersAddressesController {
  /**
   * Retrieve a paginated list of all shipping addresses saved by a specific customer, accessible to platform administrators.
   *
   * This operation returns all active (non-deleted) shipping addresses belonging to the customer identified by `customerId`. Each address record corresponds to a row in the `shopping_mall_customer_addresses` table where `deleted_at IS NULL`. The response includes full address details for each entry: recipient name, phone number, primary street address (`address_line1`), optional secondary address line (`address_line2`), city, state, postal code, country (stored as ISO 3166-1 alpha-2 code), and the `is_default` flag indicating the customer's currently designated default shipping address.
   *
   * This endpoint is restricted to authenticated administrators (regular admin or super-admin). Administrators have platform-wide read access and may look up the address book of any customer account by specifying the customer's UUID in the `customerId` path parameter. No ownership match between the caller and the customer is required — the admin role grants full oversight access by design.
   *
   * The response is paginated via `IShoppingMallCustomerAddress.IRequest` in the request body, which carries pagination parameters (page number, items per page) and optional sort configuration. The default sort order is `created_at DESC`, showing the most recently added addresses first. Administrators may also sort by `is_default` to surface the default address at the top of the list.
   *
   * Business rule: only one address per customer should carry `is_default = true` at a time; this is enforced at the application layer. The `deleted_at` column supports logical deletion, so addresses removed by the customer are excluded from this list while their records are preserved for historical order reference integrity.
   *
   * Related operations (customer-facing equivalents):
   * - `POST /customers/{customerId}/addresses` — customer adds a new shipping address.
   * - `PUT /customers/{customerId}/addresses/{addressId}` — customer edits an existing address.
   * - `DELETE /customers/{customerId}/addresses/{addressId}` — customer removes an address (sets `deleted_at`).
   * - `PUT /customers/{customerId}/addresses/{addressId}/default` — customer designates an address as default.
   *
   * @param connection
   * @param customerId The UUID of the customer whose shipping addresses are being listed (global scope).
   * @param body Pagination and sorting parameters for the customer's address list.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification 1. Authenticate and authorize: verify the calling customer's session token and confirm that their account ID matches `customerId`. Reject with 403 if mismatch.
   * 2. Query `shopping_mall_customer_addresses` WHERE `shopping_mall_customer_id = customerId` AND `deleted_at IS NULL`.
   * 3. Apply pagination from the request body: use `page` and `limit` fields to compute OFFSET/LIMIT. If not provided, use defaults (e.g., page=1, limit=20).
   * 4. Apply sorting: default to `created_at DESC`. Allow sorting by `is_default DESC, created_at DESC` to surface the default address first.
   * 5. Return the total count and paginated items as `IPageIShoppingMallCustomerAddress.ISummary`.
   * 6. Each item in the response includes: `id`, `recipient_name`, `phone`, `address_line1`, `address_line2` (nullable), `city`, `state`, `postal_code`, `country`, `is_default`, `created_at`, `updated_at`.
   * 7. Edge cases:
   *    - If the customer has no saved addresses, return an empty data array with pagination metadata.
   *    - If customerId does not match any active customer account, return 404.
   *    - Do not include addresses where `deleted_at IS NOT NULL`.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("customerId")
    customerId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallCustomerAddress.IRequest,
  ): Promise<IPageIShoppingMallCustomerAddress.ISummary> {
    try {
      return await patchShoppingMallAdminCustomersCustomerIdAddresses({
        admin,
        customerId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve the full details of a single saved shipping address belonging to a specific customer account.
   *
   * This operation fetches a complete `CustomerAddress` record from the `shopping_mall_customer_addresses` table, identified by both the owning customer's UUID (`customerId`) and the address's own UUID (`addressId`). The response includes all delivery-relevant fields: the recipient's full name, contact phone number, street address lines, city, state or province, postal code, country (stored as an ISO 3166-1 alpha-2 country code), and whether the address is currently designated as the customer's default shipping address (`is_default`).
   *
   * The `shopping_mall_customer_addresses` table supports soft deletion via the `deleted_at` column, meaning that addresses removed from a customer's active address book are not physically deleted but are instead marked with a deletion timestamp. This operation only returns addresses that are currently active (i.e., where `deleted_at` is null). If the requested address has been removed or does not exist, a 404 response is returned.
   *
   * Access to this endpoint is strictly scoped: a `customer` actor may only retrieve addresses that belong to their own account. The `customerId` path parameter must match the authenticated customer's own identity. Any attempt to access an address belonging to another customer is rejected by the system. Administrator actors (`admin` and `superAdmin`) may access addresses for any customer for oversight purposes.
   *
   * This endpoint is commonly used in conjunction with `GET /customers/{customerId}/addresses` (list of all addresses) to navigate from a list view to a detail view, or at checkout time to confirm the details of a pre-selected address. It also supports use cases where the client needs to display the current state of a specific saved address before presenting an edit form.
   *
   * Related operations:
   * - `GET /customers/{customerId}/addresses` — List all active saved addresses for the customer.
   * - `POST /customers/{customerId}/addresses` — Add a new shipping address to the customer's address book.
   * - `PUT /customers/{customerId}/addresses/{addressId}` — Update the fields of this specific address.
   * - `DELETE /customers/{customerId}/addresses/{addressId}` — Remove this address from the customer's active address book.
   *
   * @param connection
   * @param customerId UUID of the customer account whose address is being retrieved (global scope).
   * @param addressId UUID of the specific shipping address to retrieve (scoped to the customer).
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification 1. Authenticate the requesting user as either a `customer` or an `admin`/`superAdmin`.
   * 2. If the actor is a `customer`, verify that `customerId` matches the authenticated customer's own account ID. If it does not match, reject the request (ownership enforcement — a customer may not access another customer's addresses).
   * 3. Verify that the customer account identified by `customerId` exists and has not been deleted (`deleted_at IS NULL`).
   * 4. Query `shopping_mall_customer_addresses` where `id = addressId` AND `shopping_mall_customer_id = customerId` AND `deleted_at IS NULL`.
   * 5. If no matching record is found (address does not exist, belongs to a different customer, or has been soft-deleted), return a 404 Not Found error.
   * 6. Return the full address record, including all fields: `id`, `shopping_mall_customer_id`, `recipient_name`, `phone`, `address_line1`, `address_line2`, `city`, `state`, `postal_code`, `country`, `is_default`, `created_at`, `updated_at`.
   * 7. Do NOT return addresses where `deleted_at` is not null.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":addressId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("customerId")
    customerId: string & tags.Format<"uuid">,
    @TypedParam("addressId")
    addressId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallCustomerAddress> {
    try {
      return await getShoppingMallAdminCustomersCustomerIdAddressesAddressId({
        admin,
        customerId,
        addressId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
