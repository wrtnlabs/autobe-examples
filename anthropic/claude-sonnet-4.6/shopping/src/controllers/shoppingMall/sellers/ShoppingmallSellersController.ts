import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IShoppingMallSeller } from "../../../api/structures/IShoppingMallSeller";
import { getShoppingMallSellersSellerId } from "../../../providers/getShoppingMallSellersSellerId";

@Controller("/shoppingMall/sellers/:sellerId")
export class ShoppingmallSellersController {
  /**
   * Retrieve detailed information about a specific seller account by its unique identifier.
   *
   * This operation returns the full profile of a seller registered on the shopping mall platform, as stored in the `shopping_mall_sellers` table. The response includes the seller's shop name, email address, account state flags (`is_banned`, `is_suspended`), and timestamps for registration and last update.
   *
   * The seller's password hash is never included in the response. Historical shop profile snapshots (captured in `shopping_mall_seller_profile_snapshots` upon each profile edit) are not directly embedded in this response but can be accessed through dedicated profile snapshot endpoints.
   *
   * This endpoint is primarily used by administrators and super administrators to inspect individual seller accounts for oversight, moderation, or dispute resolution purposes. Sellers may also use this endpoint to view their own account information.
   *
   * If the seller account has been removed (i.e., `deleted_at` is set), the system treats the account as inactive and will return a not-found response.
   *
   * Related operations:
   * - `PATCH /sellers` — List and search all seller accounts with filtering.
   * - `GET /sellers/{sellerId}/approvals` — View the seller's approval history.
   * - `GET /sellers/{sellerId}/profileSnapshots` — View the seller's historical shop profile snapshots.
   *
   * @param connection
   * @param sellerId The UUID of the target seller account to retrieve.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor null
     * @x-autobe-specification 1. Extract the sellerId UUID from the path
     *   parameter. 2. Query the `shopping_mall_sellers` table for a record
     *   where `id = sellerId` AND `deleted_at IS NULL`. 3. If no matching
     *   record is found, return a 404 Not Found error. 4. Map the database
     *   record to the `IShoppingMallSeller` DTO, including: id, email,
     *   shop_name, is_banned, is_suspended, created_at, updated_at. 5. Never
     *   expose password_hash in the response. 6. Return the mapped DTO with
     *   HTTP 200.
   *
   * Authorization:
   * - admin and superAdmin actors may retrieve any seller's information.
   * - A seller actor may retrieve only their own account (verify session sellerId matches the path sellerId).
   * - Unauthorized access should return 403 Forbidden.
   *
   * Edge cases:
   * - Return 404 if the seller does not exist or has been marked deleted (deleted_at is not null).
   * - Return 403 if a non-admin seller attempts to access another seller's record.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallSeller> {
    try {
      return await getShoppingMallSellersSellerId({
        sellerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
