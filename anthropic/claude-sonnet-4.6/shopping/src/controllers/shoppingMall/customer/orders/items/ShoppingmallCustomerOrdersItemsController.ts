import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallOrderItem } from "../../../../../api/structures/IPageIShoppingMallOrderItem";
import { IShoppingMallOrderItem } from "../../../../../api/structures/IShoppingMallOrderItem";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { getShoppingMallCustomerOrdersOrderIdItemsItemId } from "../../../../../providers/getShoppingMallCustomerOrdersOrderIdItemsItemId";
import { patchShoppingMallCustomerOrdersOrderIdItems } from "../../../../../providers/patchShoppingMallCustomerOrdersOrderIdItems";

@Controller("/shoppingMall/customer/orders/:orderId/items")
export class ShoppingmallCustomerOrdersItemsController {
  /**
   * Retrieve a paginated and filtered list of order items belonging to a specific order.
   *
   * This operation provides access to all line items within a given order, identified by the `orderId` path parameter. Each order item (`shopping_mall_order_items`) represents a specific product variant purchased by the customer, capturing the quantity and unit price at checkout time. Items also hold an independent lifecycle status — one of `pending`, `paid`, `shipped`, `delivered`, `cancelled`, or `refunded` — allowing each item within the same order to progress through fulfillment independently.
   *
   * The response is paginated and supports filtering by item status (e.g., to list only `paid` or `shipped` items) and sorting by creation date or price. This is useful for customers who want to track the status of individual products within a multi-item order, and for administrators performing order oversight or dispute resolution.
   *
   * Access control is strictly enforced: a customer may only access order items for orders that belong to their own account. Any attempt by a customer to access items of an order placed by a different customer will be denied. Administrators (both regular and super administrators) have unrestricted access and may query the order items of any order on the platform, supporting their platform-wide oversight responsibilities.
   *
   * The order item list also reflects the independence of item statuses as described in the platform's business rules: cancelling or shipping one item does not affect the status of other items in the same order. The derived overall order status is computed from the combination of all item statuses.
   *
   * Related operations:
   * - `GET /orders/{orderId}` should be used first to retrieve the parent order's details including its overall status and shipping address snapshot.
   * - `GET /orders/{orderId}/items/{itemId}` retrieves the full detail of a single order item including its immutable snapshot (product name, variant options, seller profile at purchase time).
   *
   * @param connection
   * @param orderId The UUID of the parent order whose items are being listed. Customers may only provide an orderId belonging to their own account; administrators may provide any orderId on the platform.
   * @param body Search criteria, status filters, sorting options, and pagination parameters for listing order items.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification 1. Authenticate the caller and determine their
     *   role (customer or admin). 2. Look up the order in shopping_mall_orders
     *   by the provided orderId (UUID). If not found, return 404. 3.
     *   Authorization check: - If the caller is a customer, verify that
     *   shopping_mall_orders.shopping_mall_customer_id matches the
     *   authenticated customer's ID. If not, return 403. - If the caller is an
     *   admin or superAdmin, skip ownership check. 4. Apply the search/filter
     *   criteria from the request body to shopping_mall_order_items: - Filter
     *   by shopping_mall_order_id = orderId (always applied). - Optional
     *   filter: status (one or more values from: 'pending', 'paid', 'shipped',
     *   'delivered', 'cancelled', 'refunded'). - Optional date range filters on
     *   created_at. 5. Apply sorting (default: created_at ASC; support
     *   created_at DESC, unit_price ASC/DESC). 6. Apply pagination (page number
     *   and page size from request body). 7. For each matching
     *   shopping_mall_order_items record, include: - id,
     *   shopping_mall_product_variant_id, quantity, unit_price, status,
     *   created_at, updated_at. - Join with shopping_mall_order_item_snapshots
     *   (1:1) to include product name and variant SKU summary from the
     *   referenced product snapshot. 8. Return the paginated result set with
     *   total count and pagination metadata.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallOrderItem.IRequest,
  ): Promise<IPageIShoppingMallOrderItem.ISummary> {
    try {
      return await patchShoppingMallCustomerOrdersOrderIdItems({
        customer,
        orderId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve the complete detail of a single order item within a specified order.
   *
   * This endpoint returns all information about one line item from a customer order on the shopping mall platform. Each order item (`shopping_mall_order_items`) belongs to a parent order (`shopping_mall_orders`) and represents a specific product variant purchased by the customer. The response includes the item's quantity, unit price captured at checkout, current lifecycle status (one of: `pending`, `paid`, `shipped`, `delivered`, `cancelled`, `refunded`), and timestamps.
   *
   * The response also includes the order item's immutable snapshot (`shopping_mall_order_item_snapshots`), which is a 1:1 record created at the moment the order was placed and never modified thereafter. This snapshot references the product snapshot (`shopping_mall_product_snapshots`) that preserves the product's name, description, base price, and category name as they existed at purchase time, ensuring the customer always sees an accurate historical record of what they ordered — even if the product has since been edited or deleted by the seller.
   *
   * The snapshot further references the specific variant SKU snapshot (`shopping_mall_product_snapshot_skuses`) which records the exact combination of variant options (e.g., color, size) and price selected at the time of purchase, as well as the seller profile snapshot (`shopping_mall_seller_profile_snapshots`) that captures the seller's shop name and description as they appeared when the customer placed the order.
   *
   * If the order item has been assigned to a shipment, the response includes the shipment information (`shopping_mall_shipments` via `shopping_mall_shipment_items`), including the logistics carrier name, tracking number, and delivery timestamps.
   *
   * Access control is strictly enforced: authenticated customers may only retrieve items belonging to their own orders. If the specified `orderId` does not belong to the requesting customer, or the `itemId` does not belong to that order, the system will deny access. Administrators (both regular and super administrators) may access any order item on the platform without restriction, supporting oversight, dispute resolution, and platform management responsibilities.
   *
   * To obtain the list of all order items within an order, the order detail endpoint should be consulted first. This endpoint is intended for retrieving the granular detail of a specific line item once its identifier is known.
   *
   * @param connection
   * @param orderId The unique identifier (UUID) of the parent order.
   * @param itemId The unique identifier (UUID) of the target order item within the specified order.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification 1. Authenticate the requesting actor. Determine
     *   if the caller is a customer or administrator.
   *
   * 2. Look up the parent order by `orderId` from `shopping_mall_orders`. If not found, return 404.
   *
   * 3. Authorization check:
   *    - If the caller is a customer: verify that `shopping_mall_orders.shopping_mall_customer_id` matches the authenticated customer's ID. If not, return 403.
   *    - If the caller is an admin or superAdmin: allow unrestricted access.
   *
   * 4. Look up the order item by `itemId` from `shopping_mall_order_items` where `shopping_mall_order_id = orderId`. If not found or does not belong to the specified order, return 404.
   *
   * 5. Join `shopping_mall_order_item_snapshots` (1:1 on `order_item_id`) to get the immutable snapshot record.
   *
   * 6. From the snapshot, join:
   *    - `shopping_mall_product_snapshots` (via `product_snapshot_id`) to get product name, description, base price, category name.
   *    - `shopping_mall_product_snapshot_skuses` (via `product_snapshot_skus_id`) to get the variant SKU options and price.
   *    - `shopping_mall_seller_profile_snapshots` (via `seller_profile_snapshot_id`) to get shop name, description, logo URL.
   *
   * 7. Check if the order item is assigned to a shipment: query `shopping_mall_shipment_items` where `shopping_mall_order_item_id = itemId`. If found, join `shopping_mall_shipments` to retrieve carrier, tracking number, shipped_at, estimated_delivery_at, delivered_at.
   *
   * 8. Compose and return the full `IShoppingMallOrderItem` response object including all joined data.
   *
   * Edge cases:
   * - Product snapshot may have a null `product_id` (product was deleted) — still return the snapshot data.
   * - Shipment may not yet exist for the item (item status is `pending` or `paid`) — return null for shipment fields.
   * - Validate that `itemId` actually belongs to `orderId` to prevent cross-order item access.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":itemId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedParam("itemId")
    itemId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallOrderItem> {
    try {
      return await getShoppingMallCustomerOrdersOrderIdItemsItemId({
        customer,
        orderId,
        itemId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
