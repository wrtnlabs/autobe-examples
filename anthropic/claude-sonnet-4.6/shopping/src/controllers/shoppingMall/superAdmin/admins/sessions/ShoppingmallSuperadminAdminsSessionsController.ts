import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallAdminSession } from "../../../../../api/structures/IPageIShoppingMallAdminSession";
import { IShoppingMallAdminSession } from "../../../../../api/structures/IShoppingMallAdminSession";
import { SuperadminAuth } from "../../../../../decorators/SuperadminAuth";
import { SuperadminPayload } from "../../../../../decorators/payload/SuperadminPayload";
import { getShoppingMallSuperAdminAdminsAdminIdSessionsSessionId } from "../../../../../providers/getShoppingMallSuperAdminAdminsAdminIdSessionsSessionId";
import { patchShoppingMallSuperAdminAdminsAdminIdSessions } from "../../../../../providers/patchShoppingMallSuperAdminAdminsAdminIdSessions";

@Controller("/shoppingMall/superAdmin/admins/:adminId/sessions")
export class ShoppingmallSuperadminAdminsSessionsController {
  /**
   * Retrieve a paginated and filterable list of JWT session records for a specific administrator account.
   *
   * This operation returns all sessions associated with the given administrator, stored in the `shopping_mall_admin_sessions` table. Each session record represents a single device or browser login event and includes the JWT access token, refresh token, connection metadata (IP address, page href, referrer), creation timestamp, and expiration/logout timestamp.
   *
   * Access to this endpoint is restricted to administrators (`admin` and `superAdmin` actors), as session data is sensitive security information used for auditing purposes. The requesting actor must have an active authenticated session. Regular administrators and super administrators can both invoke this operation.
   *
   * Search and filtering capabilities include filtering by session status (active vs. expired based on `expired_at`), filtering by IP address, and filtering by creation date range. Pagination is supported with configurable page size and ordering, defaulting to most-recently-created first.
   *
   * The `adminId` path parameter must correspond to a valid, existing administrator account in `shopping_mall_admins`. If no administrator is found with the given ID, the system returns a not-found error. Sessions are returned regardless of their expiration state unless the caller explicitly filters by active status.
   *
   * This endpoint is typically used in conjunction with `GET /admins/{adminId}` to first retrieve the administrator's profile, and then inspect their session history for security or audit review purposes.
   *
   * @param connection
   * @param adminId The UUID of the target administrator account whose sessions are to be listed.
   * @param body Search criteria and pagination parameters for filtering administrator sessions.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification 1. Validate that the caller has an active admin or superAdmin session.
   * 2. Look up the administrator record in `shopping_mall_admins` using the `adminId` path parameter (UUID). If not found, return 404.
   * 3. Query `shopping_mall_admin_sessions` where `shopping_mall_admin_id = adminId`.
   * 4. Apply optional filters from the request body:
   *    - Filter by `expired_at > NOW()` if `onlyActive: true` is requested (active sessions only).
   *    - Filter by IP address substring/exact match if provided.
   *    - Filter by `created_at` range (from/to) if provided.
   * 5. Apply sorting: default to `created_at DESC` (most recent first). Allow `expired_at` as secondary sort option.
   * 6. Apply pagination using `page` and `limit` from the request body.
   * 7. Return the paginated result with `IShoppingMallAdminSession.ISummary` records, including id, ip, href, referrer, created_at, expired_at, and a derived `isActive` boolean indicating whether the session is still live.
   * 8. Edge cases: if adminId does not exist in `shopping_mall_admins`, return 404. If the admin has no sessions, return an empty paginated result.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SuperadminAuth()
    superAdmin: SuperadminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallAdminSession.IRequest,
  ): Promise<IPageIShoppingMallAdminSession.ISummary> {
    try {
      return await patchShoppingMallSuperAdminAdminsAdminIdSessions({
        superAdmin,
        adminId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve the details of a specific session record belonging to a regular administrator account.
   *
   * This operation returns a single session record from the `shopping_mall_admin_sessions` table, identified by both the parent administrator's unique identifier (`adminId`) and the session's own unique identifier (`sessionId`). The session record captures all information established at login time, including JWT access and refresh tokens, the client's IP address, the page URL from which the login was initiated (`href`), the HTTP referrer header, and the creation and expiry timestamps.
   *
   * Each session in the `shopping_mall_admin_sessions` table belongs to one administrator account in `shopping_mall_admins`. The foreign key `shopping_mall_admin_id` links the session to its owning administrator. This endpoint enforces that the session referenced by `sessionId` must belong to the administrator referenced by `adminId`; requests referencing mismatched administrator-session combinations will be rejected.
   *
   * Access to this endpoint is restricted to authenticated administrators. An administrator may retrieve their own session records for auditing or session management purposes. Super administrators have platform-wide access and may retrieve session records for any regular administrator account. Unauthenticated requests or requests from non-admin actors (customers, sellers) are denied.
   *
   * This endpoint is typically used in conjunction with `PATCH /admins/{adminId}/sessions` to first list all sessions for an administrator and then retrieve the details of a specific session. Session expiry is determined by the `expired_at` field — a session is considered active if `expired_at` is in the future, and inactive (logged out or expired) otherwise.
   *
   * @param connection
   * @param adminId The unique identifier (UUID) of the regular administrator account whose session is being retrieved.
   * @param sessionId The unique identifier (UUID) of the specific administrator session to retrieve.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification 1. Extract `adminId` and `sessionId` from the path parameters.
   * 2. Verify that the authenticated actor is either (a) the admin identified by `adminId` or (b) a super administrator with platform-wide access. Reject with 403 Forbidden if neither condition is met.
   * 3. Query the `shopping_mall_admins` table by `adminId`. If no record is found or `deleted_at` is non-null, return 404 Not Found.
   * 4. Query the `shopping_mall_admin_sessions` table where `id = sessionId` AND `shopping_mall_admin_id = adminId`. If no matching record is found, return 404 Not Found (this also handles the case where the session does not belong to the specified admin).
   * 5. Return the session record with all fields: id, shopping_mall_admin_id, access_token, refresh_token, ip, href, referrer, created_at, expired_at.
   * 6. Do not filter by expiry status — both active and expired sessions are retrievable for audit purposes.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @SuperadminAuth()
    superAdmin: SuperadminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallAdminSession> {
    try {
      return await getShoppingMallSuperAdminAdminsAdminIdSessionsSessionId({
        superAdmin,
        adminId,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
