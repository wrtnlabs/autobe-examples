import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallCustomer } from "../../../../api/structures/IShoppingMallCustomer";
import { postShoppingMallAuthCustomerJoin } from "../../../../providers/postShoppingMallAuthCustomerJoin";
import { postShoppingMallAuthCustomerLogin } from "../../../../providers/postShoppingMallAuthCustomerLogin";
import { postShoppingMallAuthCustomerRefresh } from "../../../../providers/postShoppingMallAuthCustomerRefresh";

@Controller("/shoppingMall/auth/customer")
export class ShoppingmallAuthCustomerController {
  /**
   * Registers a new customer account on the shopping mall platform and immediately returns an authorized session.
   *
   * This operation creates a new record in the `shopping_mall_customers` table. The customer's email address must be unique across all customer accounts, as enforced by the `@@unique([email])` index. The raw password provided by the user is never stored; instead, it is bcrypt-hashed before being persisted into the `password_hash` column. The `nickname` field stores a display name shown to other users (e.g., in product reviews) and does not need to be unique. The optional `phone` field is stored as a nullable string and may be omitted.
   *
   * Upon successful registration, the system creates a new session record in `shopping_mall_customer_sessions`, issuing a JWT access token and a refresh token. The session records the client's IP address (`ip`), page URL (`href`), and HTTP referrer (`referrer`) for security auditing purposes. The newly registered customer begins with `is_banned = false` and an active account (`deleted_at = null`).
   *
   * The response includes the full authorized session payload (`IShoppingMallCustomer.IAuthorized`) containing both the access token and refresh token required for subsequent authenticated API calls. Clients should securely store these tokens.
   *
   * If the provided email is already registered to an existing active customer account, the operation returns a conflict error. This endpoint is publicly accessible and does not require any prior authentication.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Customer registration information including email, password, nickname, and optional phone number.
     * @x-autobe-authorization-type join
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification 1. Validate the request body: email format,
     *   password minimum length, nickname non-empty, phone format if provided.
     *   2. Check that no active (non-deleted) shopping_mall_customers record
     *   exists with the same email. Return 409 Conflict if duplicate found. 3.
     *   Bcrypt-hash the plaintext password with an appropriate cost factor
     *   (e.g., 12). 4. Insert a new shopping_mall_customers row with: id = new
     *   UUID, email, password_hash, nickname, phone (nullable), is_banned =
     *   false, created_at = now(), updated_at = now(), deleted_at = null. 5.
     *   Generate a signed JWT access token (short-lived, e.g., 1 hour) and a
     *   refresh token (long-lived, e.g., 30 days), both containing the customer
     *   id as subject. 6. Insert a new shopping_mall_customer_sessions row
     *   with: id = new UUID, shopping_mall_customer_id = new customer id,
     *   access_token, refresh_token, ip (from request), href (from request
     *   header or body), referrer (from request header), created_at = now(),
     *   expired_at = now() + refresh token TTL. 7. Return
     *   IShoppingMallCustomer.IAuthorized containing the customer info and the
     *   token pair.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallCustomer.IJoin,
  ): Promise<IShoppingMallCustomer.IAuthorized> {
    try {
      return await postShoppingMallAuthCustomerJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticates an existing customer account using email and password credentials, returning a new authorized session.
   *
   * This operation looks up the `shopping_mall_customers` record by the provided email address using the `@@unique([email])` index. The provided plaintext password is compared against the stored `password_hash` column using bcrypt verification. If the email is not found or the password does not match, the operation returns a 401 Unauthorized error without revealing which field was incorrect, to prevent user enumeration attacks.
   *
   * Before issuing a session, the system checks the `is_banned` column. If the customer account has been banned by an administrator (`is_banned = true`), login is rejected with a 403 Forbidden response indicating the account is suspended. Additionally, accounts with a non-null `deleted_at` timestamp are treated as inactive and cannot log in.
   *
   * Upon successful authentication, a new session record is inserted into `shopping_mall_customer_sessions` with a freshly generated JWT access token and refresh token. The session captures the client's `ip`, `href`, and `referrer` context fields for security auditing. Multiple concurrent sessions are supported, as the schema allows multiple session rows per customer (indexed by `shopping_mall_customer_id, created_at`).
   *
   * The response (`IShoppingMallCustomer.IAuthorized`) includes both the access token (short-lived) and the refresh token (long-lived). Clients must securely store these tokens and use the refresh endpoint to renew the access token before expiry.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Customer login credentials consisting of email and plaintext password.
     * @x-autobe-authorization-type login
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification 1. Validate request body: email format, password
     *   non-empty. 2. Query shopping_mall_customers WHERE email = :email AND
     *   deleted_at IS NULL. Return 401 if not found. 3. Use
     *   bcrypt.compare(plaintextPassword, password_hash). Return 401 if
     *   mismatch (same generic error message as not found to avoid
     *   enumeration). 4. Check is_banned = true. Return 403 Forbidden with a
     *   message indicating the account is banned. 5. Generate signed JWT access
     *   token (short-lived) and refresh token (long-lived) with customer id as
     *   subject. 6. Insert shopping_mall_customer_sessions: id = new UUID,
     *   shopping_mall_customer_id, access_token, refresh_token, ip, href,
     *   referrer, created_at = now(), expired_at = now() + refresh token TTL.
     *   7. Return IShoppingMallCustomer.IAuthorized with the customer record
     *   and the token pair.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallCustomer.ILogin,
  ): Promise<IShoppingMallCustomer.IAuthorized> {
    try {
      return await postShoppingMallAuthCustomerLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Renews a customer's JWT session by exchanging a valid refresh token for a new access token and refresh token pair.
   *
   * This operation locates the existing session record in `shopping_mall_customer_sessions` using the `@@unique([refresh_token])` constraint. The refresh token is validated to ensure it has not expired (i.e., the `expired_at` timestamp is in the future). If the refresh token is unknown or already expired, the operation returns a 401 Unauthorized error and the client must re-authenticate via the login endpoint.
   *
   * After locating the session, the system loads the associated `shopping_mall_customers` record via the `shopping_mall_customer_id` foreign key. The customer's `is_banned` status and `deleted_at` are re-checked: banned customers receive a 403 Forbidden response, and accounts marked as deleted receive a 401 Unauthorized response.
   *
   * Upon validation, new JWT access and refresh tokens are generated. The existing session row in `shopping_mall_customer_sessions` is updated with the new `access_token`, `refresh_token`, and a new `expired_at` value computed from the refresh token's TTL. This implements a rolling token rotation strategy, atomically invalidating the old refresh token so it cannot be reused.
   *
   * The response (`IShoppingMallCustomer.IAuthorized`) contains the fresh token pair. Clients should replace their stored tokens immediately upon receiving this response to maintain uninterrupted authenticated access.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body The current refresh token used to obtain a new access token and refresh token pair.
     * @x-autobe-authorization-type refresh
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification 1. Validate request body: refresh_token non-empty
     *   string. 2. Query shopping_mall_customer_sessions WHERE refresh_token =
     *   :refreshToken using the @@unique([refresh_token]) index. Return 401 if
     *   not found. 3. Check session.expired_at > now(). Return 401 if expired.
     *   4. Load the related shopping_mall_customers record via
     *   shopping_mall_customer_id. Check deleted_at IS NULL (401 if deleted)
     *   and is_banned = false (403 if banned). 5. Generate new JWT access token
     *   (short-lived) and new refresh token (long-lived). 6. Update the
     *   existing shopping_mall_customer_sessions row: access_token =
     *   newAccessToken, refresh_token = newRefreshToken, expired_at = now() +
     *   refresh token TTL. This atomically invalidates the old refresh token.
     *   7. Return IShoppingMallCustomer.IAuthorized with the customer record
     *   and the new token pair.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IShoppingMallCustomer.IRefresh,
  ): Promise<IShoppingMallCustomer.IAuthorized> {
    try {
      return await postShoppingMallAuthCustomerRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
