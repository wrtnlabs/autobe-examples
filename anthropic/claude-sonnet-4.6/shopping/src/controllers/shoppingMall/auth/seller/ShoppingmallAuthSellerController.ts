import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallSeller } from "../../../../api/structures/IShoppingMallSeller";
import { postShoppingMallAuthSellerJoin } from "../../../../providers/postShoppingMallAuthSellerJoin";
import { postShoppingMallAuthSellerLogin } from "../../../../providers/postShoppingMallAuthSellerLogin";
import { postShoppingMallAuthSellerRefresh } from "../../../../providers/postShoppingMallAuthSellerRefresh";

@Controller("/shoppingMall/auth/seller")
export class ShoppingmallAuthSellerController {
  /**
   * Register a new seller account on the shopping mall platform.
   *
   * This endpoint creates a new record in the `shopping_mall_sellers` table, which stores the seller's unique email address, bcrypt-hashed password, and shop display name (`shop_name`). The email must be globally unique across all sellers; attempting to register with a duplicate email will result in a conflict error.
   *
   * Upon successful registration, the seller account is created with `is_banned = false` and `is_suspended = false`. A new session is immediately issued and recorded in `shopping_mall_seller_sessions`, returning an access token and refresh token so the seller can begin using authenticated endpoints without requiring a separate login step.
   *
   * Note that seller registration does not immediately grant access to product management features. Sellers must also complete the platform's approval workflow (tracked via SellerApproval entities and reviewed by administrators) before they can list products or manage inventory.
   *
   * The password provided in the request body is never stored in plaintext. It is hashed using bcrypt before being persisted to the `password_hash` column in `shopping_mall_sellers`.
   *
   * Related operations: After joining, sellers may need to submit a seller approval request to gain platform access. The `POST /auth/seller/login` endpoint provides an equivalent session for already-registered sellers.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Seller registration information including email, password, and shop name.
     * @x-autobe-authorization-type join
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification 1. Validate the request body: email format,
     *   password minimum length, shop_name non-empty. 2. Check uniqueness of
     *   email in shopping_mall_sellers (case-insensitive). Return 409 Conflict
     *   if duplicate. 3. Hash the password using bcrypt with appropriate work
     *   factor. 4. Insert a new row into shopping_mall_sellers: id (uuid),
     *   email, password_hash, shop_name, is_banned=false, is_suspended=false,
     *   created_at=now(), updated_at=now(), deleted_at=null. 5. Generate a JWT
     *   access_token and refresh_token pair. 6. Insert a new row into
     *   shopping_mall_seller_sessions: id (uuid), shopping_mall_seller_id=new
     *   seller id, access_token, refresh_token, ip from request context, href
     *   from request headers, referrer from request headers (nullable),
     *   created_at=now(), expired_at=now() + configured session TTL. 7. Return
     *   the IShoppingMallSeller.IAuthorized payload containing access_token,
     *   refresh_token, and the seller account data.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallSeller.IJoin,
  ): Promise<IShoppingMallSeller.IAuthorized> {
    try {
      return await postShoppingMallAuthSellerJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate an existing seller and issue a new JWT session.
   *
   * This endpoint validates the provided email and password against the `shopping_mall_sellers` table. The email is used to look up the seller record, and the submitted password is compared against the stored `password_hash` using bcrypt verification. If the credentials are invalid, a 401 Unauthorized response is returned without indicating which field was incorrect.
   *
   * Before issuing a session, this endpoint enforces account state checks defined on the `shopping_mall_sellers` record. Sellers with `is_banned = true` are permanently prohibited from logging in and will receive a 403 Forbidden response. Sellers with `is_suspended = true` may also be blocked from logging in per platform policy.
   *
   * Sellers whose account has been removed (`deleted_at` is not null) are treated as non-existent and will receive the same 401 Unauthorized response as an invalid credential attempt.
   *
   * Upon successful authentication, a new record is appended to `shopping_mall_seller_sessions` containing the issued `access_token`, `refresh_token`, the client's IP address, the page `href`, and an optional `referrer` header value. Multiple concurrent sessions per seller are supported for multi-device logins, as each login creates a separate session record.
   *
   * The returned `IShoppingMallSeller.IAuthorized` payload contains the access and refresh tokens needed for subsequent authenticated API calls.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Seller login credentials including email and password.
     * @x-autobe-authorization-type login
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification 1. Look up shopping_mall_sellers by email
     *   (case-insensitive). If not found or deleted_at is not null, return 401
     *   Unauthorized. 2. Compare submitted password against password_hash using
     *   bcrypt.compare(). If mismatch, return 401 Unauthorized. 3. Check
     *   is_banned flag. If true, return 403 Forbidden with appropriate message.
     *   4. Check is_suspended flag. If true, return 403 Forbidden with
     *   appropriate message. 5. Generate a new JWT access_token and
     *   refresh_token pair. 6. Insert a new row into
     *   shopping_mall_seller_sessions: id (uuid), shopping_mall_seller_id,
     *   access_token, refresh_token, ip, href, referrer (nullable),
     *   created_at=now(), expired_at=now() + configured session TTL. 7. Return
     *   IShoppingMallSeller.IAuthorized payload containing access_token,
     *   refresh_token, and seller account data.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallSeller.ILogin,
  ): Promise<IShoppingMallSeller.IAuthorized> {
    try {
      return await postShoppingMallAuthSellerLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Renew an expired or expiring seller session by exchanging a valid refresh token for a new token pair.
   *
   * This endpoint accepts a refresh token previously issued during seller login or registration. The provided refresh token is looked up against the `shopping_mall_seller_sessions` table using the `refresh_token` column (which carries a unique constraint). If the token is not found, has already expired (`expired_at` is in the past), or belongs to a session associated with a deleted seller account, the request is rejected with a 401 Unauthorized response.
   *
   * Before issuing new tokens, the endpoint re-validates the seller's account state on the `shopping_mall_sellers` table. Sellers with `is_banned = true` or `is_suspended = true` will not receive a refreshed session and will receive a 403 Forbidden response, effectively terminating their active access even if a valid refresh token exists.
   *
   * Token rotation is applied: the old session record in `shopping_mall_seller_sessions` is invalidated (or replaced) and a new session row is created with fresh `access_token`, `refresh_token`, and an updated `expired_at` timestamp. This prevents refresh token reuse and supports token rotation security patterns.
   *
   * The response payload `IShoppingMallSeller.IAuthorized` contains the new access token, the new refresh token, and the current seller account information for the client to update its stored credentials.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Seller refresh token used to obtain a new access token and refresh token pair.
     * @x-autobe-authorization-type refresh
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification 1. Extract the refresh_token from the request
     *   body. 2. Look up the matching row in shopping_mall_seller_sessions by
     *   refresh_token (unique index). If not found, return 401 Unauthorized. 3.
     *   Check that the session's expired_at > now(). If expired, return 401
     *   Unauthorized. 4. Load the associated shopping_mall_sellers record. If
     *   deleted_at is not null, return 401 Unauthorized. 5. Check is_banned on
     *   the seller. If true, return 403 Forbidden. 6. Check is_suspended on the
     *   seller. If true, return 403 Forbidden. 7. Generate a new JWT
     *   access_token and refresh_token pair. 8. Invalidate the old session
     *   (either delete the row or mark it as expired by setting
     *   expired_at=now()). 9. Insert a new row into
     *   shopping_mall_seller_sessions: id (uuid), shopping_mall_seller_id, new
     *   access_token, new refresh_token, ip, href, referrer, created_at=now(),
     *   expired_at=now() + configured session TTL. 10. Return
     *   IShoppingMallSeller.IAuthorized payload with the new token pair and
     *   seller account data.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IShoppingMallSeller.IRefresh,
  ): Promise<IShoppingMallSeller.IAuthorized> {
    try {
      return await postShoppingMallAuthSellerRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
