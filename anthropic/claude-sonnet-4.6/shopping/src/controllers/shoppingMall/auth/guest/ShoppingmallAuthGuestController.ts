import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallGuest } from "../../../../api/structures/IShoppingMallGuest";
import { postShoppingMallAuthGuestJoin } from "../../../../providers/postShoppingMallAuthGuestJoin";
import { postShoppingMallAuthGuestRefresh } from "../../../../providers/postShoppingMallAuthGuestRefresh";

@Controller("/shoppingMall/auth/guest")
export class ShoppingmallAuthGuestController {
  /**
   * Registers a new guest identity and issues JWT tokens for an unauthenticated visitor to the shopping mall platform.
   *
   * This endpoint initializes a transient guest record in the `shopping_mall_guests` table, uniquely identified by a device or browser fingerprint token. The guest record serves as the stable identity anchor for anonymous sessions before the visitor registers as a customer or logs into an existing account. Upon successful registration, a corresponding `shopping_mall_guest_sessions` record is created to track the session context including the visitor's IP address (`shopping_mall_guest_sessions.ip`), the full page URL (`shopping_mall_guest_sessions.href`), and the HTTP referrer URL (`shopping_mall_guest_sessions.referrer`).
   *
   * Guests are strictly transitional actors on the platform. They have access only to public endpoints such as customer registration, seller registration, and login flows. The guest identity is superseded once the visitor registers or logs in as a customer or seller. The `shopping_mall_guests.token` field must be unique across all guest records — if a fingerprint token already exists, the system reuses the existing guest identity rather than creating a duplicate, as enforced by the unique index on `shopping_mall_guests.token`.
   *
   * The `shopping_mall_guest_sessions.expired_at` field is set to a short window in the future relative to `created_at`, reflecting the transient nature of guest sessions. The issued JWT access token encodes the guest's identity and session context, while the refresh token allows the guest to obtain a new access token without re-joining.
   *
   * This is a fully public endpoint. It is the entry point for all anonymous visitors and must be called before any other guest-scoped operation. The `POST /auth/guest/refresh` endpoint can subsequently be used to renew tokens without re-joining.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Guest join request containing the device/browser fingerprint token and session context information (IP, href, referrer).
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification 1. Parse the request body to extract the fingerprint token, IP address, href, and referrer.
   * 2. Check if a guest record with the provided token already exists in `shopping_mall_guests` (unique constraint on token).
   *    - If exists: reuse the existing guest record (do not create a duplicate).
   *    - If not exists: insert a new row into `shopping_mall_guests` with a generated UUID, the provided token, and current timestamp as created_at.
   * 3. Insert a new row into `shopping_mall_guest_sessions` with: generated UUID, the guest's id, provided IP, href, referrer, current timestamp as created_at, and a short expiry (e.g., 1 hour) as expired_at.
   * 4. Generate a JWT access token encoding the guest id and session id, signed with the platform's secret key.
   * 5. Generate a refresh token (opaque or JWT) associated with this session.
   * 6. Return the IShoppingMallGuest.IAuthorized response containing: access token, refresh token, token expiry, and the guest identity (id, token, created_at).
   * 7. Validation: Reject requests with missing or empty fingerprint tokens. IP and href are required; referrer may be an empty string.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallGuest.IJoin,
  ): Promise<IShoppingMallGuest.IAuthorized> {
    try {
      return await postShoppingMallAuthGuestJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Renews the JWT access token for an existing guest session using a valid refresh token, without requiring the guest to re-join.
   *
   * Guest sessions in the `shopping_mall_guest_sessions` table are short-lived, as indicated by the `shopping_mall_guest_sessions.expired_at` column. When a guest's access token nears expiry, this endpoint can be called to exchange a valid refresh token for a new access token and refresh token pair. The guest's identity in `shopping_mall_guests` remains unchanged — only the session is renewed.
   *
   * The refresh operation validates the provided refresh token to ensure it corresponds to a non-expired guest session. If the session referenced by the refresh token has passed its `expired_at` timestamp, the request is rejected and the guest must call `POST /auth/guest/join` again to obtain a new session. Upon successful validation, a new `shopping_mall_guest_sessions` row is created with a fresh `expired_at` window, and new JWT tokens are issued.
   *
   * This endpoint is fully public and requires no authentication header — only the refresh token in the request body. It is designed to maintain continuity of the guest browsing session across short-lived token windows without interruption to the user experience.
   *
   * After a successful refresh, the previous refresh token is invalidated to prevent token replay attacks. The guest's stable identity (`shopping_mall_guests.id` and `shopping_mall_guests.token`) is preserved and returned in the response.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Guest refresh request containing the refresh token to renew the guest's JWT access token.
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification 1. Parse the request body to extract the refresh token.
   * 2. Validate the refresh token: verify its signature and extract the guest session id it references.
   * 3. Look up the corresponding `shopping_mall_guest_sessions` record by session id.
   *    - If not found or expired_at < now: return 401 Unauthorized.
   * 4. Look up the `shopping_mall_guests` record by shopping_mall_guest_id from the session.
   *    - If not found: return 401 Unauthorized.
   * 5. Invalidate the old refresh token (e.g., rotate or mark as used).
   * 6. Create a new `shopping_mall_guest_sessions` row with: generated UUID, same guest id, current timestamp as created_at, and a fresh expired_at window.
   * 7. Generate new JWT access token encoding the guest id and new session id.
   * 8. Generate a new refresh token associated with the new session.
   * 9. Return the IShoppingMallGuest.IAuthorized response with new tokens and guest identity.
   * 10. Error handling: invalid or malformed refresh tokens should return 401; expired sessions should return 401 prompting the client to re-join.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IShoppingMallGuest.IRefresh,
  ): Promise<IShoppingMallGuest.IAuthorized> {
    try {
      return await postShoppingMallAuthGuestRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
