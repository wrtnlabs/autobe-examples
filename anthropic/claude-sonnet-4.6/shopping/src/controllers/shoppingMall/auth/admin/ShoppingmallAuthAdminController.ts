import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallAdmin } from "../../../../api/structures/IShoppingMallAdmin";
import { postShoppingMallAuthAdminJoin } from "../../../../providers/postShoppingMallAuthAdminJoin";
import { postShoppingMallAuthAdminLogin } from "../../../../providers/postShoppingMallAuthAdminLogin";
import { postShoppingMallAuthAdminRefresh } from "../../../../providers/postShoppingMallAuthAdminRefresh";

@Controller("/shoppingMall/auth/admin")
export class ShoppingmallAuthAdminController {
  /**
   * Registers and activates a new administrator account on the shopping mall platform.
   *
   * Administrator accounts in the shopping mall platform are not created independently from scratch. Rather, they are promoted from existing customer (`shopping_mall_customers`) or seller (`shopping_mall_sellers`) accounts that have successfully passed the administrator request and approval process. This join operation finalizes the promotion by recording the admin's credentials — specifically their email address (inherited from the originating account) and a bcrypt-hashed password — into the `shopping_mall_admins` table.
   *
   * The `shopping_mall_admins` table stores the admin's `email` (unique, inherited from the originating account and used as the login identifier), `password_hash` (bcrypt one-way hash; plaintext is never persisted), `actor_type` discriminator (either 'customer' or 'seller' indicating the origin account type), and timestamps for `created_at` and `updated_at`. The `deleted_at` field is null for newly joined admins, indicating the account is active.
   *
   * Upon successful account creation, this endpoint immediately establishes a new JWT session by creating a record in `shopping_mall_admin_sessions` with the generated `access_token`, `refresh_token`, client connection metadata (`ip`, `href`, `referrer`), and expiration timestamp (`expired_at`). The response returns the full `IShoppingMallAdmin.IAuthorized` payload containing the tokens and admin profile details.
   *
   * Security considerations: the email must be unique within the `shopping_mall_admins` table (enforced by a unique index). Duplicate email registration attempts must be rejected. Passwords must be securely hashed using bcrypt before persistence. This endpoint requires admin-level authorization as it is the entry point for activating a promoted admin account.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Admin account registration (promotion activation) credentials including email and password.
     * @x-autobe-authorization-type join
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification 1. Validate that the provided email is not
     *   already registered in shopping_mall_admins (unique constraint check).
     *   2. Hash the provided plaintext password using bcrypt with an
     *   appropriate cost factor. 3. Determine the actor_type based on whether
     *   the promoter originated from a customer or seller account (passed as
     *   part of the join payload or resolved from the promotion context). 4.
     *   Insert a new record into shopping_mall_admins with id (UUID),
     *   actor_type, email, password_hash, created_at=now(), updated_at=now(),
     *   deleted_at=null. 5. Create a new session in
     *   shopping_mall_admin_sessions: generate UUID id, set
     *   shopping_mall_admin_id to the new admin id, generate JWT access_token
     *   and refresh_token, record ip/href/referrer from request context, set
     *   created_at=now(), set expired_at to access token expiry. 6. Return
     *   IShoppingMallAdmin.IAuthorized containing the access_token,
     *   refresh_token, and admin profile data. 7. Edge cases: if email already
     *   exists, return 409 Conflict. If required fields are missing or invalid,
     *   return 400 Bad Request.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallAdmin.IJoin,
  ): Promise<IShoppingMallAdmin.IAuthorized> {
    try {
      return await postShoppingMallAuthAdminJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticates a regular administrator using their email address and password, establishing a new JWT session.
   *
   * This endpoint validates the provided credentials against the `shopping_mall_admins` table. The admin's `email` serves as the unique login identifier, and the provided plaintext password is verified against the stored `password_hash` (bcrypt). Administrators whose accounts have been deactivated (i.e., `deleted_at` is non-null in `shopping_mall_admins`) are denied login access — the historical record is preserved for auditing, but active platform access is revoked.
   *
   * Admin accounts are promoted from existing customer or seller accounts, and the `actor_type` field ('customer' or 'seller') in `shopping_mall_admins` indicates the origin. This field does not affect the authentication flow but is returned as part of the admin profile in the response.
   *
   * Upon successful authentication, a new record is created in `shopping_mall_admin_sessions`, storing the generated `access_token` (used to authenticate subsequent API requests) and `refresh_token` (used to renew the access token), along with connection metadata: `ip` (client IP address), `href` (full URL of the login page), and `referrer` (HTTP Referer header), all recorded for security auditing. The session's `expired_at` is set to the token's expiration time. Multiple concurrent sessions (multi-device login) are supported — each login call creates an independent session record.
   *
   * The response returns `IShoppingMallAdmin.IAuthorized` containing the access and refresh tokens plus admin profile details. These tokens must be used in subsequent API calls requiring admin authentication. To renew tokens, use `POST /auth/admin/refresh`.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Admin login credentials containing email address and plaintext password.
     * @x-autobe-authorization-type login
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification 1. Look up the admin by email in
     *   shopping_mall_admins. Return 401 Unauthorized if not found. 2. Check
     *   that deleted_at is null. If non-null, return 401 Unauthorized (account
     *   deactivated). 3. Compare the provided plaintext password against
     *   password_hash using bcrypt.compare(). Return 401 Unauthorized if
     *   mismatch. 4. Create a new record in shopping_mall_admin_sessions:
     *   generate UUID id, set shopping_mall_admin_id, generate new JWT
     *   access_token and refresh_token (ensure uniqueness per unique
     *   constraints on those columns), capture ip/href/referrer from request,
     *   set created_at=now(), set expired_at to access token expiry. 5. Return
     *   IShoppingMallAdmin.IAuthorized with tokens and admin profile. 6. Do NOT
     *   invalidate previous sessions — multi-device concurrent sessions are
     *   supported. 7. Edge cases: invalid email → 401, wrong password → 401,
     *   deactivated account → 401. Never distinguish between 'account not
     *   found' and 'wrong password' in error messages to prevent enumeration
     *   attacks.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallAdmin.ILogin,
  ): Promise<IShoppingMallAdmin.IAuthorized> {
    try {
      return await postShoppingMallAuthAdminLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Renews an administrator's JWT session by exchanging a valid refresh token for a new access token and refresh token pair.
   *
   * This endpoint accepts the `refresh_token` previously issued during a login or join operation. The token is validated against the `shopping_mall_admin_sessions` table using the unique index on `refresh_token`. The session's `expired_at` timestamp is checked to ensure the session has not already expired or been explicitly invalidated.
   *
   * The associated `shopping_mall_admins` record is also verified to ensure the admin account is still active — i.e., `deleted_at` must be null. If the account has been deactivated since the session was created, the refresh is denied.
   *
   * Upon successful validation, new JWT `access_token` and `refresh_token` values are generated and the existing `shopping_mall_admin_sessions` record is updated: the old tokens are replaced with the newly issued ones, and `expired_at` is extended to the new access token's expiration time. This rotation strategy ensures that each refresh token can only be used once, invalidating the previous token pair.
   *
   * The response returns `IShoppingMallAdmin.IAuthorized` with the new tokens and admin profile. Clients should update their stored tokens immediately upon receiving the response. Attempting to use the old refresh token after a successful refresh will result in a 401 Unauthorized error, as the token will no longer match any active session record.
   *
   * Connection metadata (`ip`, `href`, `referrer`) in the session record may optionally be updated to reflect the refresh request's context for auditing purposes.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token payload used to obtain a new JWT access token and refresh token.
     * @x-autobe-authorization-type refresh
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification 1. Accept refresh_token from the request body
     *   (IShoppingMallAdmin.IRefresh). 2. Look up the session in
     *   shopping_mall_admin_sessions by refresh_token (unique index). Return
     *   401 if not found. 3. Check that session.expired_at > now(). Return 401
     *   if session is expired. 4. Load the associated shopping_mall_admins
     *   record via shopping_mall_admin_id. Verify deleted_at is null. Return
     *   401 if account is deactivated. 5. Generate new access_token and
     *   refresh_token (ensure uniqueness). 6. Update the
     *   shopping_mall_admin_sessions record: set access_token=new,
     *   refresh_token=new, expired_at=new expiry, optionally update
     *   ip/href/referrer. 7. Return IShoppingMallAdmin.IAuthorized with new
     *   tokens and admin profile. 8. Edge cases: expired session → 401,
     *   revoked/invalid refresh_token → 401, deactivated admin → 401.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IShoppingMallAdmin.IRefresh,
  ): Promise<IShoppingMallAdmin.IAuthorized> {
    try {
      return await postShoppingMallAuthAdminRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
