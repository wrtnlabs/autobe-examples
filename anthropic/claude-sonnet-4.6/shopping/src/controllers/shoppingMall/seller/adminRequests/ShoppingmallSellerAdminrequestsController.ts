import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallCancellationRequest } from "../../../../api/structures/IShoppingMallCancellationRequest";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { postShoppingMallSellerAdminRequests } from "../../../../providers/postShoppingMallSellerAdminRequests";

@Controller("/shoppingMall/seller/adminRequests")
export class ShoppingmallSellerAdminrequestsController {
  /**
   * Submit a new administrator promotion request on behalf of the authenticated customer or seller.
   *
   * Any registered platform user — whether a customer or a seller — may use this endpoint to formally apply to become a platform administrator. The request captures the applicant's identity (derived from the authenticated session) and a written reason text that explains why they wish to take on administrator responsibilities. Upon successful submission, the system assigns the request a status of 'pending' and records the exact submission timestamp, initiating the review workflow managed exclusively by super administrators.
   *
   * This operation enforces the following business rules: the caller must supply a non-empty, non-whitespace reason text; if the reason text is absent, empty, or whitespace-only, the request is rejected with a validation error. Additionally, a user may not have more than one pending admin request at a time — if the caller already has an outstanding pending request, this endpoint returns an error indicating that a new submission is not permitted until the existing one has been resolved.
   *
   * The submitted AdminRequest is immutable after creation. Neither the reason text nor any other field may be modified or withdrawn once the request has been successfully submitted. The record is preserved permanently regardless of the eventual outcome (pending, approved, or rejected) to maintain a complete, tamper-proof audit trail of all administrator appointment events on the platform.
   *
   * Upon approval by a super administrator, the requesting user is elevated to regular administrator status. Upon rejection, their existing role remains unchanged and the record is retained for audit purposes. Related operations include the super administrator's list and decision endpoints, which are the exclusive mechanisms through which the submitted request can transition from 'pending' to 'approved' or 'rejected'.
   *
   * @param connection
   * @param body Admin request creation payload containing the reason text explaining why the applicant wishes to become a platform administrator.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification 1. Authentication: Verify that the caller has an
     *   active authenticated session as a customer or seller. If the session is
     *   missing or invalid, return 401. If the caller is an admin, super admin,
     *   or guest, return 403.
   *
   * 2. Request validation: Extract the `reason` field from the request body. If it is absent, null, empty string, or contains only whitespace characters, reject the request with a 422 validation error indicating that the reason text is required.
   *
   * 3. Duplicate pending check: Query the admin requests store for any existing record where the requester identity matches the current caller AND the status is 'pending'. If such a record exists, return a 409 conflict error indicating that the user already has a pending admin request.
   *
   * 4. Record creation: Create a new admin request record with the following values:
   *    - `id`: a new UUID
   *    - `applicant_type`: 'customer' or 'seller' based on the authenticated session
   *    - `applicant_id`: the UUID of the authenticated customer or seller
   *    - `reason`: the trimmed reason text from the request body
   *    - `status`: 'pending'
   *    - `created_at`: current UTC timestamp
   *
   * 5. Response: Return the created admin request record with HTTP 201 Created, including the full AdminRequest object: id, applicant type, applicant identity summary, reason, status, and created_at timestamp.
   *
   * 6. Error cases:
   *    - 401: No valid session
   *    - 403: Caller is not a customer or seller
   *    - 409: Caller already has a pending admin request
   *    - 422: Reason text is empty or whitespace-only
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IShoppingMallCancellationRequest.ICreate,
  ): Promise<IShoppingMallCancellationRequest> {
    try {
      return await postShoppingMallSellerAdminRequests({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
