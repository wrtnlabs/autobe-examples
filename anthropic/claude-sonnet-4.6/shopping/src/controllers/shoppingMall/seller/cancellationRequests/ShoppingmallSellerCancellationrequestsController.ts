import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IShoppingMallCancellationRequest } from "../../../../api/structures/IShoppingMallCancellationRequest";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { getShoppingMallSellerCancellationRequestsCancellationRequestId } from "../../../../providers/getShoppingMallSellerCancellationRequestsCancellationRequestId";
import { putShoppingMallSellerCancellationRequestsCancellationRequestId } from "../../../../providers/putShoppingMallSellerCancellationRequestsCancellationRequestId";

@Controller("/shoppingMall/seller/cancellationRequests/:cancellationRequestId")
export class ShoppingmallSellerCancellationrequestsController {
  /**
   * Retrieve detailed information about a specific cancellation request.
   *
   * This operation fetches the full details of a single cancellation request identified by its unique `cancellationRequestId`. A cancellation request is created when a customer submits a request to cancel an individual order item that is currently in `paid` status. The returned record includes the request's current resolution status (`pending`, `approved`, or `rejected`), the customer's original reason text, submission and last-update timestamps, and the associated order item reference.
   *
   * The `shopping_mall_cancellation_requests` table enforces a 1:1 relationship between an order item and its cancellation request via a unique constraint on `shopping_mall_order_item_id`. This means each order item can have at most one active cancellation request at any time. The current `status` field on the request record reflects the most recent decision without requiring traversal of the snapshot history.
   *
   * The response also includes the complete audit trail of decision snapshots (`shopping_mall_cancellation_request_snapshots`). Each snapshot is an immutable record appended whenever a seller or administrator approves or rejects the request, capturing the decision status, the verbatim customer reason, and an exact timestamp. Once created, snapshots cannot be modified or deleted by any party, serving as a tamper-proof history for dispute resolution.
   *
   * Access to this endpoint is restricted to authorized parties: the customer who owns the related order item, the seller responsible for fulfilling that item, and platform administrators. Callers attempting to access a cancellation request that does not exist or to which they are not entitled will receive an appropriate error response.
   *
   * To obtain the list of cancellation requests for an order or item, use the corresponding list (index) endpoint first. To understand the full order item lifecycle, refer to the order item detail endpoint which exposes item status progression from `pending` through `paid`, `shipped`, `delivered`, `cancelled`, and `refunded`.
   *
   * @param connection
   * @param cancellationRequestId The unique UUID identifier of the cancellation request to retrieve.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification 1. Extract `cancellationRequestId` (UUID) from
     *   the path parameter. 2. Query `shopping_mall_cancellation_requests`
     *   where `id = cancellationRequestId`. - If no record is found, return 404
     *   Not Found. 3. Authorization check: - Join through
     *   `shopping_mall_order_items` → `shopping_mall_orders` to retrieve
     *   `shopping_mall_customer_id`. - If the caller is a customer, verify
     *   their customer ID matches
     *   `shopping_mall_orders.shopping_mall_customer_id`. - If the caller is a
     *   seller, verify they own the product variant referenced by
     *   `shopping_mall_order_items.shopping_mall_product_variant_id` (join
     *   through `shopping_mall_product_variants` → `shopping_mall_products` →
     *   seller). - If the caller is an admin or superAdmin, allow access
     *   unconditionally. - If authorization fails, return 403 Forbidden. 4.
     *   Load the associated `shopping_mall_cancellation_request_snapshots`
     *   ordered by `created_at` ASC to build the chronological audit trail. 5.
     *   Compose the response object: - `id`, `shopping_mall_order_item_id`,
     *   `status`, `reason`, `created_at`, `updated_at` from the main record. -
     *   `snapshots`: array of snapshot records each with `id`,
     *   `cancellation_request_id`, `status`, `reason`, `created_at`. 6. Return
     *   HTTP 200 with the assembled `IShoppingMallCancellationRequest` DTO.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("cancellationRequestId")
    cancellationRequestId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallCancellationRequest> {
    try {
      return await getShoppingMallSellerCancellationRequestsCancellationRequestId(
        {
          seller,
          cancellationRequestId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Respond to a customer's pending cancellation request by approving or rejecting it.
   *
   * This operation allows a seller (or administrator) to act on a cancellation request that a customer has submitted for an order item in 'paid' status. The cancellation request, stored in the `shopping_mall_cancellation_requests` table, must currently be in 'pending' status for this operation to succeed. The seller provides their decision — either 'approved' or 'rejected' — and the system updates the `status` field on the cancellation request accordingly.
   *
   * When the request is approved, the associated order item's status transitions to 'cancelled'. The overall order status is then recalculated from all constituent order items: if all items are now cancelled, the order is marked 'cancelled'; if some remain active, the order is marked 'partially_completed'. Cancellation is scoped strictly to the individual order item — other items in the same order are unaffected and continue through their normal statuses.
   *
   * Each time a seller responds to a cancellation request, the system automatically creates an immutable `shopping_mall_cancellation_request_snapshots` record. This snapshot captures the status decision made, the original reason text the customer submitted verbatim, and the precise timestamp of the response. These snapshots form a chronological, tamper-proof audit trail that serves as the authoritative evidence for dispute resolution by administrators.
   *
   * Sellers may only respond to cancellation requests for order items that belong to their own products. Administrators may respond to any cancellation request on the platform as part of their force-cancel oversight responsibilities. Only requests in 'pending' status can be acted upon; attempting to update an already-approved or already-rejected request will be rejected with an appropriate error.
   *
   * After calling this endpoint, clients may retrieve the full list of snapshots for the cancellation request's decision history. The updated cancellation request, including its new status and updated timestamp, is returned in the response.
   *
   * @param connection
   * @param cancellationRequestId The UUID of the cancellation request to respond to (global scope).
   * @param body The seller's or administrator's decision on the cancellation request, including the resolution status (approved or rejected).
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification 1. Authenticate the caller: confirm they are a
     *   seller or admin with a valid session. 2. Look up the cancellation
     *   request by `cancellationRequestId` UUID in
     *   `shopping_mall_cancellation_requests`. Return 404 if not found. 3.
     *   Authorization check: - If the caller is a seller, verify that the
     *   referenced `shopping_mall_order_item_id` belongs to an order item whose
     *   product variant belongs to a product owned by the authenticated seller.
     *   Return 403 if not. - If the caller is an admin, no additional ownership
     *   check is needed. 4. Validate that the cancellation request's current
     *   `status` is 'pending'. If it is already 'approved' or 'rejected',
     *   return a 422/409 error indicating the request has already been
     *   resolved. 5. Validate the request body: the `status` field must be
     *   either 'approved' or 'rejected'. No other values are permitted. 6.
     *   Within a database transaction: a. Update
     *   `shopping_mall_cancellation_requests.status` to the provided decision
     *   ('approved' or 'rejected') and set `updated_at` to the current
     *   timestamp. b. If approved, update the related
     *   `shopping_mall_order_items.status` to 'cancelled' and set its
     *   `updated_at`. c. Create a new
     *   `shopping_mall_cancellation_request_snapshots` record with: - `id`: new
     *   UUID - `cancellation_request_id`: the cancellation request's id -
     *   `status`: the decision ('approved' or 'rejected') - `reason`: the
     *   original `reason` text from the cancellation request (verbatim copy) -
     *   `created_at`: current timestamp d. Recalculate and update the parent
     *   order's `status` field in `shopping_mall_orders` based on the aggregate
     *   statuses of all its order items. 7. Return the updated
     *   `shopping_mall_cancellation_requests` record (with nested snapshots if
     *   applicable).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("cancellationRequestId")
    cancellationRequestId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallCancellationRequest.IUpdate,
  ): Promise<IShoppingMallCancellationRequest> {
    try {
      return await putShoppingMallSellerCancellationRequestsCancellationRequestId(
        {
          seller,
          cancellationRequestId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
