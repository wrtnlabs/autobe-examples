export async function getShoppingMallCustomerOrdersOrderId(props: {
  customer: CustomerPayload;
  orderId: string & tags.Format<"uuid">;
}): Promise<IShoppingMallOrder> {
  // Step 1: Verify the order exists and belongs to this customer
  const orderOwnership =
    await MyGlobal.prisma.shopping_mall_orders.findUniqueOrThrow({
      where: { id: props.orderId },
      select: {
        id: true,
        shopping_mall_customer_id: true,
      },
    });
  // Step 2: Authorization check — customer can only access their own orders
  if (orderOwnership.shopping_mall_customer_id !== props.customer.id) {
    throw new HttpException("Forbidden", 403);
  }
  // Step 3: Fetch the full order with all nested data using the transformer
  const order = await MyGlobal.prisma.shopping_mall_orders.findUniqueOrThrow({
    where: { id: props.orderId },
    ...ShoppingMallOrderTransformer.select(),
  });
  // Step 4: Transform and return the full IShoppingMallOrder DTO
  return ShoppingMallOrderTransformer.transform(order);
}
