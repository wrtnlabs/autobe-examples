export async function test_api_order_force_refund_already_refunded_item_rejected(
  connection: api.IConnection,
): Promise<void> {
  // ─── 1. Admin Setup ───────────────────────────────────────────────────────
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  // Admin creates a product category
  const category = await generate_random_shopping_mall_admin_categories_create(
    adminConnection,
    {},
  );
  typia.assert(category);
  // ─── 2. Seller Setup ──────────────────────────────────────────────────────
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {});
  // Seller submits approval request
  const approval = await generate_random_shopping_mall_seller_approvals_create(
    sellerConnection,
    {},
  );
  typia.assert(approval);
  // Admin approves the seller
  const approvedSeller =
    await api.functional.shoppingMall.admin.sellerApprovals.update(
      adminConnection,
      {
        approvalId: approval.id,
        body: {
          status: "approved",
          rejection_reason: null,
        } satisfies IShoppingMallSellerApproval.IUpdate,
      },
    );
  typia.assert(approvedSeller);
  // Seller creates a product
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        categoryId: category.id,
      },
    },
  );
  typia.assert(product);
  // Seller creates a variant
  const variant =
    await generate_random_shopping_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
      },
    );
  typia.assert(variant);
  // Seller adds inventory (10 units to allow order placement)
  const inventoryRecord =
    await generate_random_shopping_mall_seller_products_variants_inventory_records_create(
      sellerConnection,
      {
        params: {
          productId: product.id,
          variantId: variant.id,
        },
        body: {
          quantity: 10,
          note: "Initial stock for test",
        },
      },
    );
  typia.assert(inventoryRecord);
  // ─── 3. Customer Setup ────────────────────────────────────────────────────
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  // Customer places an order
  const order = await generate_random_shopping_mall_customer_orders_create(
    customerConnection,
    {
      body: {
        items: [
          {
            product_variant_id: variant.id,
            quantity: 1,
          },
        ],
      },
    },
  );
  typia.assert(order);
  // ─── 4. First Force Refund (must succeed) ─────────────────────────────────
  const refundedOrder =
    await api.functional.shoppingMall.admin.orders.forceRefund(
      adminConnection,
      {
        orderId: order.id,
        body: {
          refundAll: true,
        } satisfies IShoppingMallOrder.IForceRefund,
      },
    );
  typia.assert(refundedOrder);
  // Validate that the order status is refunded and all items are refunded
  TestValidator.equals(
    "order status should be refunded after first force-refund",
    refundedOrder.status,
    "refunded",
  );
  TestValidator.predicate(
    "all order items should be refunded after first force-refund",
    () => refundedOrder.items.every((item) => item.status === "refunded"),
  );
  // ─── 5. Second Force Refund on already-refunded order (must fail 422) ─────
  await TestValidator.httpError(
    "second force-refund on already-refunded items should be rejected with 422",
    422,
    async () => {
      await api.functional.shoppingMall.admin.orders.forceRefund(
        adminConnection,
        {
          orderId: order.id,
          body: {
            refundAll: true,
          } satisfies IShoppingMallOrder.IForceRefund,
        },
      );
    },
  );
}
