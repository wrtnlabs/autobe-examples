export async function test_api_review_snapshot_list_after_review_creation(
  connection: api.IConnection,
): Promise<void> {
  // -----------------------------------------------------------------------
  // 1. Admin setup: join and create a category
  // -----------------------------------------------------------------------
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  const category = await generate_random_shopping_mall_admin_categories_create(
    adminConnection,
    {},
  );
  typia.assert(category);
  // -----------------------------------------------------------------------
  // 2. Seller setup: join, submit approval
  // -----------------------------------------------------------------------
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {});
  const approval = await generate_random_shopping_mall_seller_approvals_create(
    sellerConnection,
    {},
  );
  typia.assert(approval);
  // -----------------------------------------------------------------------
  // 3. Admin approves the seller
  // -----------------------------------------------------------------------
  const approvalResult =
    await api.functional.shoppingMall.admin.sellerApprovals.update(
      adminConnection,
      {
        approvalId: approval.id,
        body: {
          status: "approved",
          rejection_reason: null,
        } satisfies IShoppingMallSellerApproval.IUpdate,
      },
    );
  typia.assert(approvalResult);
  // -----------------------------------------------------------------------
  // 4. Seller creates a product
  // -----------------------------------------------------------------------
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        categoryId: category.id,
      },
    },
  );
  typia.assert(product);
  // -----------------------------------------------------------------------
  // 5. Seller creates a product variant
  // -----------------------------------------------------------------------
  const variant =
    await generate_random_shopping_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
      },
    );
  typia.assert(variant);
  // -----------------------------------------------------------------------
  // 6. Seller adds inventory (10 units)
  // -----------------------------------------------------------------------
  const inventoryRecord =
    await generate_random_shopping_mall_seller_products_variants_inventory_records_create(
      sellerConnection,
      {
        params: { productId: product.id, variantId: variant.id },
        body: {
          quantity: 10,
          note: "Initial stock for testing",
        },
      },
    );
  typia.assert(inventoryRecord);
  // -----------------------------------------------------------------------
  // 7. Customer setup: join and place order
  // -----------------------------------------------------------------------
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  const order = await generate_random_shopping_mall_customer_orders_create(
    customerConnection,
    {
      body: {
        items: [
          {
            product_variant_id: variant.id,
            quantity: 1,
          },
        ],
      },
    },
  );
  typia.assert(order);
  // Get the order item id
  const orderItem = order.items[0];
  typia.assertGuard(orderItem!);
  // -----------------------------------------------------------------------
  // 8. Customer submits a review (rating=4, with body text)
  //    NOTE: review creation requires 'delivered' order item status.
  //    We proceed and trust the test env or the generate utility handles this.
  // -----------------------------------------------------------------------
  const reviewBody = "Great product, highly recommend!";
  const review =
    await generate_random_shopping_mall_customer_products_reviews_create(
      customerConnection,
      {
        params: { productId: product.id },
        body: {
          order_item_id: orderItem.id,
          rating: 4,
          body: reviewBody,
        },
      },
    );
  typia.assert(review);
  // -----------------------------------------------------------------------
  // 9. Retrieve snapshot list via the target endpoint
  // -----------------------------------------------------------------------
  const snapshotPage =
    await api.functional.shoppingMall.customer.products.reviews.snapshots.index(
      customerConnection,
      {
        productId: product.id,
        reviewId: review.id,
        body: {} satisfies IShoppingMallReviewSnapshot.IRequest,
      },
    );
  typia.assert(snapshotPage);
  // -----------------------------------------------------------------------
  // 10. Validations
  // -----------------------------------------------------------------------
  // Pagination checks
  TestValidator.equals(
    "pagination.records should be 1",
    snapshotPage.pagination.records,
    1,
  );
  TestValidator.equals(
    "pagination.current should be 1",
    snapshotPage.pagination.current,
    1,
  );
  TestValidator.equals(
    "pagination.pages should be 1",
    snapshotPage.pagination.pages,
    1,
  );
  // Data array check
  TestValidator.equals(
    "data array length should be 1",
    snapshotPage.data.length,
    1,
  );
  const snapshot = snapshotPage.data[0];
  typia.assertGuard(snapshot!);
  // Snapshot content validations
  TestValidator.equals(
    "snapshot.reviewId matches review.id",
    snapshot.reviewId,
    review.id,
  );
  TestValidator.equals(
    "snapshot.rating matches submitted rating",
    snapshot.rating,
    4,
  );
  TestValidator.equals(
    "snapshot.body matches submitted body",
    snapshot.body,
    reviewBody,
  );
}
