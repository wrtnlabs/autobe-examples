export async function test_api_review_snapshot_admin_access_active_review(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin setup
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  // 2. Seller setup: join
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {});
  // 2a. Seller submits approval
  const approval = await generate_random_shopping_mall_seller_approvals_create(
    sellerConnection,
    { body: {} },
  );
  typia.assert(approval);
  // 2b. Admin approves the seller
  const approvedApproval =
    await api.functional.shoppingMall.admin.sellerApprovals.update(
      adminConnection,
      {
        approvalId: approval.id,
        body: {
          status: "approved",
          rejection_reason: null,
        } satisfies IShoppingMallSellerApproval.IUpdate,
      },
    );
  typia.assert(approvedApproval);
  // 3. Admin creates a product category
  const category = await generate_random_shopping_mall_admin_categories_create(
    adminConnection,
    {},
  );
  typia.assert(category);
  // 4. Seller creates a product with the category
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        categoryId: category.id,
      },
    },
  );
  typia.assert(product);
  // 5. Seller creates a product variant
  const variant =
    await generate_random_shopping_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
      },
    );
  typia.assert(variant);
  // 6. Seller adds inventory (positive quantity)
  const inventoryRecord =
    await generate_random_shopping_mall_seller_products_variants_inventory_records_create(
      sellerConnection,
      {
        body: { quantity: 10, note: "Initial stock for testing" },
        params: { productId: product.id, variantId: variant.id },
      },
    );
  typia.assert(inventoryRecord);
  // 7. Customer setup: join
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  // 8. Customer places an order referencing the variant
  const order = await generate_random_shopping_mall_customer_orders_create(
    customerConnection,
    {
      body: {
        items: [
          {
            product_variant_id: variant.id,
            quantity: 1,
          },
        ],
      },
    },
  );
  typia.assert(order);
  // Get the order item
  const orderItem = order.items[0]!;
  // 9a. Seller creates a shipment with the order item
  const shipment =
    await generate_random_shopping_mall_seller_orders_shipments_create(
      sellerConnection,
      {
        body: {
          carrier: "TestCarrier",
          orderItemIds: [orderItem.id],
        },
        params: { orderId: order.id },
      },
    );
  typia.assert(shipment);
  // 9b. Seller updates shipment with shipped_at to progress fulfillment
  const updatedShipment =
    await api.functional.shoppingMall.seller.orders.shipments.update(
      sellerConnection,
      {
        orderId: order.id,
        shipmentId: shipment.id,
        body: {
          carrier: "TestCarrier",
          shipped_at: new Date().toISOString(),
          estimated_delivery_at: new Date().toISOString(),
        } satisfies IShoppingMallShipment.IUpdate,
      },
    );
  typia.assert(updatedShipment);
  // 10. Customer writes a review for the delivered order item
  const reviewBody = "Great product, highly recommend!";
  const review =
    await generate_random_shopping_mall_customer_products_reviews_create(
      customerConnection,
      {
        body: {
          order_item_id: orderItem.id,
          rating: 4 satisfies number &
            tags.Type<"int32"> &
            tags.Minimum<1> &
            tags.Maximum<5>,
          body: reviewBody,
        },
        params: { productId: product.id },
      },
    );
  typia.assert(review);
  // Get the first snapshot from the review
  const snapshot = review.snapshots[0]!;
  // Test execution: Admin retrieves the review snapshot
  const retrievedSnapshot =
    await api.functional.shoppingMall.admin.products.reviews.snapshots.at(
      adminConnection,
      {
        productId: product.id,
        reviewId: review.id,
        snapshotId: snapshot.id,
      },
    );
  typia.assert(retrievedSnapshot);
  // Validations: snapshot identity and immutability
  TestValidator.equals(
    "snapshot id matches requested snapshotId",
    retrievedSnapshot.id,
    snapshot.id,
  );
  TestValidator.equals(
    "reviewId in snapshot matches review id",
    retrievedSnapshot.reviewId,
    review.id,
  );
  TestValidator.equals(
    "rating matches original review submission",
    retrievedSnapshot.rating,
    review.rating,
  );
  TestValidator.equals(
    "body matches original review submission",
    retrievedSnapshot.body,
    review.body,
  );
}
