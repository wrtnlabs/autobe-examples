export async function test_api_review_statistics_no_reviews(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin setup - create admin connection and authenticate
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  // 2. Create a product category as admin
  const category = await generate_random_shopping_mall_admin_categories_create(
    adminConnection,
    {},
  );
  typia.assert(category);
  // 3. Create a seller connection and authenticate
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {});
  // 4. As seller, submit an approval request
  const approval = await generate_random_shopping_mall_seller_approvals_create(
    sellerConnection,
    {},
  );
  typia.assert(approval);
  // 5. As admin, approve the seller's approval request
  const approvedApproval =
    await api.functional.shoppingMall.admin.sellerApprovals.update(
      adminConnection,
      {
        approvalId: approval.id,
        body: {
          status: "approved",
          rejection_reason: null,
        } satisfies IShoppingMallSellerApproval.IUpdate,
      },
    );
  typia.assert(approvedApproval);
  // 6. As approved seller, create a product with the category from step 2
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        categoryId: category.id,
      },
    },
  );
  typia.assert(product);
  // 7. Call review statistics endpoint without authentication (publicly accessible)
  const publicConnection: api.IConnection = { host: connection.host };
  const statistics =
    await api.functional.shoppingMall.products.reviews.statistics(
      publicConnection,
      {
        productId: product.id,
      },
    );
  typia.assert(statistics);
  // 8. Validate business rules: no reviews means null average_rating and count of 0
  TestValidator.equals("product_id matches", statistics.product_id, product.id);
  TestValidator.equals(
    "average_rating is null when no reviews",
    statistics.average_rating,
    null,
  );
  TestValidator.equals(
    "review_count is zero when no reviews",
    statistics.review_count,
    0,
  );
}
