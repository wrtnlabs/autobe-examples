export async function test_api_admin_request_submission_by_customer(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create an actor-specific connection for the customer
  const customerConnection: api.IConnection = { host: connection.host };
  // 2. Register and authenticate a new customer
  await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      nickname: RandomGenerator.name(1),
      phone: null,
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IShoppingMallCustomer.IJoin,
  });
  // 3. Submit an admin promotion request with a meaningful reason
  const reason =
    "I have extensive experience in platform governance and would like to contribute as an administrator.";
  const adminRequest =
    await generate_random_shopping_mall_customer_admin_requests_create(
      customerConnection,
      {
        body: {
          reason,
        } satisfies IShoppingMallCancellationRequest.ICreate,
      },
    );
  // 4. Validate the full response structure
  typia.assert(adminRequest);
  // 5. Verify status is 'pending' immediately upon creation
  TestValidator.equals("status is pending", adminRequest.status, "pending");
  // 6. Verify reason is preserved verbatim
  TestValidator.equals(
    "reason matches submitted value",
    adminRequest.reason,
    reason,
  );
}
