export async function test_api_admin_request_detail_retrieval_by_super_admin(
  connection: api.IConnection,
): Promise<void> {
  // Step 1: Register a new customer and get authenticated connection
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      nickname: RandomGenerator.name(1),
      phone: null,
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  // Step 2: As customer, submit an admin promotion request
  const reason = "I want to contribute to platform governance";
  const adminRequest =
    await generate_random_shopping_mall_customer_admin_requests_create(
      customerConnection,
      {
        body: { reason },
      },
    );
  typia.assert(adminRequest);
  // Step 3: Register a new super administrator and get authenticated connection
  const superAdminConnection: api.IConnection = { host: connection.host };
  await authorize_super_admin_join(superAdminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  // Main test: Super admin retrieves the specific admin request by ID
  const retrieved =
    await api.functional.shoppingMall.superAdmin.adminRequests.at(
      superAdminConnection,
      {
        requestId: adminRequest.id,
      },
    );
  typia.assert(retrieved);
  // Validate business logic
  TestValidator.equals("request id matches", retrieved.id, adminRequest.id);
  TestValidator.equals("status is pending", retrieved.status, "pending");
  TestValidator.equals(
    "reason matches submitted reason",
    retrieved.reason,
    reason,
  );
}
