export async function test_api_seller_unban_already_unbanned_rejected(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create super admin connection and authenticate
  const superAdminConnection: api.IConnection = { host: connection.host };
  await authorize_super_admin_join(superAdminConnection, {});
  // 2. Create seller connection and register a new seller (isBanned = false by default)
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuthorized = await authorize_seller_join(sellerConnection, {});
  typia.assert(sellerAuthorized);
  // The seller's ID for the unban attempt
  const sellerId = sellerAuthorized.id;
  // 3. Attempt to unban the seller who is NOT currently banned
  // This must be rejected by the system (business rule: idempotency protection)
  await TestValidator.error(
    "unban a non-banned seller must be rejected",
    async () => {
      await api.functional.shoppingMall.superAdmin.sellers.unban(
        superAdminConnection,
        {
          sellerId,
        },
      );
    },
  );
}
