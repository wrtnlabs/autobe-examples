export async function test_api_seller_login_banned_account_blocked(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register a new seller account
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerEmail = typia.random<string & tags.Format<"email">>();
  const sellerPassword = RandomGenerator.alphaNumeric(16);
  const sellerAuthorized = await authorize_seller_join(sellerConnection, {
    body: {
      email: sellerEmail,
      password: sellerPassword,
      shop_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  typia.assert(sellerAuthorized);
  const sellerId = sellerAuthorized.id;
  // 2. Register an admin account and authenticate
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  // 3. Ban the seller using admin connection
  const bannedSeller = await api.functional.shoppingMall.admin.sellers.ban(
    adminConnection,
    {
      sellerId: sellerId,
    },
  );
  typia.assert(bannedSeller);
  TestValidator.predicate("seller is banned", bannedSeller.isBanned === true);
  // 4. Attempt to login as the banned seller - expect error (403 Forbidden)
  const bannedLoginConnection: api.IConnection = { host: connection.host };
  await TestValidator.error("banned seller cannot login", async () => {
    await authorize_seller_login(bannedLoginConnection, {
      body: {
        email: sellerEmail,
        password: sellerPassword,
      } satisfies IShoppingMallSeller.ILogin,
    });
  });
}
