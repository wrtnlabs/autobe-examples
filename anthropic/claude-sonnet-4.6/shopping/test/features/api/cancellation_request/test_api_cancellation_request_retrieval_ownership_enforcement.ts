export async function test_api_cancellation_request_retrieval_ownership_enforcement(
  connection: api.IConnection,
): Promise<void> {
  // ── 1. Admin setup ──────────────────────────────────────────────────────
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  // ── 2. Seller setup ─────────────────────────────────────────────────────
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {});
  // Seller submits approval
  const approval = await generate_random_shopping_mall_seller_approvals_create(
    sellerConnection,
    { body: {} },
  );
  typia.assert(approval);
  // Admin approves the seller
  const approvedApproval =
    await api.functional.shoppingMall.admin.sellerApprovals.update(
      adminConnection,
      {
        approvalId: approval.id,
        body: {
          status: "approved",
          rejection_reason: null,
        } satisfies IShoppingMallSellerApproval.IUpdate,
      },
    );
  typia.assert(approvedApproval);
  // ── 3. Create category, product, variant, inventory ─────────────────────
  const category = await generate_random_shopping_mall_admin_categories_create(
    adminConnection,
    {},
  );
  typia.assert(category);
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        categoryId: category.id,
      },
    },
  );
  typia.assert(product);
  const variant =
    await generate_random_shopping_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
        body: {},
      },
    );
  typia.assert(variant);
  const inventoryRecord =
    await generate_random_shopping_mall_seller_products_variants_inventory_records_create(
      sellerConnection,
      {
        params: { productId: product.id, variantId: variant.id },
        body: { quantity: 100 },
      },
    );
  typia.assert(inventoryRecord);
  // ── 4. Customer A: register, place order, submit cancellation request ────
  const customerAConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerAConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      nickname: RandomGenerator.name(1),
      phone: null,
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  const order = await generate_random_shopping_mall_customer_orders_create(
    customerAConnection,
    {
      body: {
        items: [
          {
            product_variant_id: variant.id,
            quantity: 1,
          },
        ],
      },
    },
  );
  typia.assert(order);
  const orderItemId = order.items[0]!.id;
  const cancellationRequest =
    await generate_random_shopping_mall_customer_orders_items_cancellation_requests_create(
      customerAConnection,
      {
        params: {
          orderId: order.id,
          orderItemId: orderItemId,
        },
        body: {
          reason: "I changed my mind and want to cancel",
        },
      },
    );
  typia.assert(cancellationRequest);
  // ── 5. Customer B: register ─────────────────────────────────────────────
  const customerBConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerBConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      nickname: RandomGenerator.name(1),
      phone: null,
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  // ── 6. Negative test: Customer B must NOT access Customer A's request ────
  await TestValidator.httpError(
    "Customer B should be denied access to Customer A's cancellation request",
    [403, 404],
    async () => {
      await api.functional.shoppingMall.customer.orders.items.cancellationRequests.at(
        customerBConnection,
        {
          orderId: order.id,
          orderItemId: orderItemId,
          cancellationRequestId: cancellationRequest.id,
        },
      );
    },
  );
  // ── 7. Positive test: Customer A CAN access their own request ───────────
  const retrieved =
    await api.functional.shoppingMall.customer.orders.items.cancellationRequests.at(
      customerAConnection,
      {
        orderId: order.id,
        orderItemId: orderItemId,
        cancellationRequestId: cancellationRequest.id,
      },
    );
  typia.assert(retrieved);
  TestValidator.equals(
    "retrieved cancellation request id matches original",
    retrieved.id,
    cancellationRequest.id,
  );
}
