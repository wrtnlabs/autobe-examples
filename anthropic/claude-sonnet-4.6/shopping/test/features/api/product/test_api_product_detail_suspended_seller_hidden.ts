export async function test_api_product_detail_suspended_seller_hidden(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin setup - register and authenticate admin
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  // 2. Create product category (admin)
  const category = await generate_random_shopping_mall_admin_categories_create(
    adminConnection,
    {},
  );
  typia.assert(category);
  // 3. Seller setup - register and authenticate seller
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {});
  typia.assert(sellerAuth);
  const sellerId = sellerAuth.id;
  // 4. Seller submits approval request
  const approval = await generate_random_shopping_mall_seller_approvals_create(
    sellerConnection,
    {},
  );
  typia.assert(approval);
  // 5. Admin approves the seller
  const approvedApproval =
    await api.functional.shoppingMall.admin.sellerApprovals.update(
      adminConnection,
      {
        approvalId: approval.id,
        body: {
          status: "approved",
          rejection_reason: null,
        } satisfies IShoppingMallSellerApproval.IUpdate,
      },
    );
  typia.assert(approvedApproval);
  // 6. Seller creates a product with valid categoryId
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        categoryId: category.id,
      },
    },
  );
  typia.assert(product);
  // 7. Public access - verify product is accessible before suspension
  const publicConnection: api.IConnection = { host: connection.host };
  const productBefore = await api.functional.shoppingMall.products.at(
    publicConnection,
    {
      productId: product.id,
    },
  );
  typia.assert(productBefore);
  // 8. Admin suspends the seller
  const suspendedSeller =
    await api.functional.shoppingMall.admin.sellers.suspend(adminConnection, {
      sellerId: sellerId,
    });
  typia.assert(suspendedSeller);
  TestValidator.predicate("seller is suspended", suspendedSeller.isSuspended);
  // 9. Public access - product should be hidden after suspension
  await TestValidator.httpError(
    "product hidden after seller suspension",
    [403, 404],
    async () => {
      await api.functional.shoppingMall.products.at(publicConnection, {
        productId: product.id,
      });
    },
  );
}
