export async function test_api_product_snapshot_detail_retrieval_by_owner_seller(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin joins and gets session
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  // 2. Admin creates a product category
  const category = await generate_random_shopping_mall_admin_categories_create(
    adminConnection,
    {},
  );
  typia.assert(category);
  // 3. Seller joins and gets session
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      shop_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  // 4. Seller submits an approval request
  const approval = await generate_random_shopping_mall_seller_approvals_create(
    sellerConnection,
    {},
  );
  typia.assert(approval);
  // 5. Admin approves the seller
  const approvedApproval =
    await api.functional.shoppingMall.admin.sellerApprovals.update(
      adminConnection,
      {
        approvalId: approval.id,
        body: {
          status: "approved",
          rejection_reason: null,
        } satisfies IShoppingMallSellerApproval.IUpdate,
      },
    );
  typia.assert(approvedApproval);
  // 6. Seller creates a product with the category (images and variants auto-generated by prepare)
  const productName = RandomGenerator.paragraph({ sentences: 2 });
  const productDescription = RandomGenerator.paragraph({ sentences: 3 });
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        categoryId: category.id,
        name: productName,
        description: productDescription,
        base_price: 9999,
      },
    },
  );
  typia.assert(product);
  // 7. List the product's snapshots to discover the snapshot ID
  const snapshotPage =
    await api.functional.shoppingMall.seller.products.snapshots.index(
      sellerConnection,
      {
        productId: product.id,
        body: {},
      },
    );
  typia.assert(snapshotPage);
  TestValidator.predicate(
    "at least one snapshot exists",
    snapshotPage.data.length > 0,
  );
  const firstSnapshot = snapshotPage.data[0]!;
  // Execute: Retrieve snapshot detail
  const snapshotDetail =
    await api.functional.shoppingMall.seller.products.snapshots.at(
      sellerConnection,
      {
        productId: product.id,
        snapshotId: firstSnapshot.id,
      },
    );
  typia.assert(snapshotDetail);
  // Validation
  TestValidator.equals(
    "snapshot id matches",
    snapshotDetail.id,
    firstSnapshot.id,
  );
  TestValidator.equals(
    "productId matches",
    snapshotDetail.productId,
    product.id,
  );
  TestValidator.equals("name matches", snapshotDetail.name, product.name);
}
