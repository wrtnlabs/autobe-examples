export async function test_api_order_item_snapshot_retrieved_by_owner(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin joins (connection headers set internally)
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  // 2. Admin creates a product category
  const category = await generate_random_shopping_mall_admin_categories_create(
    adminConnection,
    {
      body: {
        name: `Electronics-${RandomGenerator.alphabets(6)}`,
        description: "Electronic products",
      },
    },
  );
  typia.assert(category);
  // 3. Seller joins (connection headers set internally)
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerShopName = `Shop-${RandomGenerator.alphabets(6)}`;
  await authorize_seller_join(sellerConnection, {
    body: {
      shop_name: sellerShopName,
    },
  });
  // 4. Seller submits approval request
  const approval = await generate_random_shopping_mall_seller_approvals_create(
    sellerConnection,
    {},
  );
  typia.assert(approval);
  // 5. Admin approves the seller
  const approvedApproval =
    await api.functional.shoppingMall.admin.sellerApprovals.update(
      adminConnection,
      {
        approvalId: approval.id,
        body: {
          status: "approved",
          rejection_reason: null,
        } satisfies IShoppingMallSellerApproval.IUpdate,
      },
    );
  typia.assert(approvedApproval);
  // 6. Seller creates a product
  const productName = `Product-${RandomGenerator.alphabets(8)}`;
  const basePrice = 29999;
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        name: productName,
        description: RandomGenerator.paragraph({ sentences: 3 }),
        base_price: basePrice,
        categoryId: category.id,
      },
    },
  );
  typia.assert(product);
  // 7. Seller creates a product variant with SKU and options
  const variantSku = `SKU-${RandomGenerator.alphaNumeric(10)}`;
  const variant =
    await generate_random_shopping_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
        body: {
          sku: variantSku,
          priceOverride: null,
          options: [
            {
              id: typia.random<string & tags.Format<"uuid">>(),
              product_variant_id: typia.random<string & tags.Format<"uuid">>(),
              key: "color",
              value: "Red",
              sequence: 0,
              created_at: new Date().toISOString(),
            },
            {
              id: typia.random<string & tags.Format<"uuid">>(),
              product_variant_id: typia.random<string & tags.Format<"uuid">>(),
              key: "size",
              value: "L",
              sequence: 1,
              created_at: new Date().toISOString(),
            },
          ],
        },
      },
    );
  typia.assert(variant);
  // 8. Seller adds inventory record (quantity=50)
  const inventoryRecord =
    await generate_random_shopping_mall_seller_products_variants_inventory_records_create(
      sellerConnection,
      {
        params: { productId: product.id, variantId: variant.id },
        body: {
          quantity: 50,
          note: "Initial stock",
        },
      },
    );
  typia.assert(inventoryRecord);
  // 9. Customer joins (connection headers set internally)
  const customerConnection: api.IConnection = { host: connection.host };
  const customerAuth = await authorize_customer_join(customerConnection, {});
  typia.assert(customerAuth);
  // 10. Customer places an order referencing the variant
  const order = await generate_random_shopping_mall_customer_orders_create(
    customerConnection,
    {
      body: {
        recipient_name: RandomGenerator.name(),
        recipient_phone: RandomGenerator.mobile(),
        shipping_address_line1: "123 Main Street",
        shipping_address_line2: null,
        shipping_city: "Seoul",
        shipping_state: null,
        shipping_postal_code: "04524",
        shipping_country: "KR",
        items: [
          {
            product_variant_id: variant.id,
            quantity: 1,
          },
        ],
      },
    },
  );
  typia.assert(order);
  // Get the first order item
  const orderItem = order.items[0];
  typia.assertGuard(orderItem!);
  // 11. Customer retrieves the order item snapshot
  const snapshot =
    await api.functional.shoppingMall.customer.orders.items.snapshot.at(
      customerConnection,
      {
        orderId: order.id,
        itemId: orderItem.id,
      },
    );
  typia.assert(snapshot);
  // Validations: check snapshot fields match what was set up
  TestValidator.equals(
    "snapshot product name matches",
    snapshot.productSnapshot.name,
    productName,
  );
  TestValidator.equals(
    "snapshot base price matches",
    snapshot.productSnapshot.basePrice,
    basePrice,
  );
  TestValidator.equals(
    "snapshot category name matches",
    snapshot.productSnapshot.categoryName,
    category.name,
  );
  TestValidator.predicate(
    "snapshot skuses is non-empty",
    snapshot.productSnapshot.skuses.length > 0,
  );
  TestValidator.equals(
    "snapshot sku code matches",
    snapshot.productSnapshotSku.skuCode,
    variantSku,
  );
  TestValidator.predicate(
    "snapshot sku options non-empty",
    snapshot.productSnapshotSku.options.length > 0,
  );
  TestValidator.equals(
    "snapshot seller shop name matches",
    snapshot.sellerProfileSnapshot.shopName,
    sellerShopName,
  );
  TestValidator.predicate(
    "snapshot created_at is valid",
    snapshot.created_at.length > 0,
  );
}
