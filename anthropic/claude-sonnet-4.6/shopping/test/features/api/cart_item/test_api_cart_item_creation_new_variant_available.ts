export async function test_api_cart_item_creation_new_variant_available(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin joins and gets authenticated connection
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  // 2. Seller joins and gets authenticated connection
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {});
  // 3. Seller submits an approval request
  const approval = await generate_random_shopping_mall_seller_approvals_create(
    sellerConnection,
    { body: {} },
  );
  typia.assert(approval);
  // 4. Admin approves the seller
  const approvedApproval =
    await api.functional.shoppingMall.admin.sellerApprovals.update(
      adminConnection,
      {
        approvalId: approval.id,
        body: {
          status: "approved",
          rejection_reason: null,
        } satisfies IShoppingMallSellerApproval.IUpdate,
      },
    );
  typia.assert(approvedApproval);
  // 5. Admin creates a product category
  const category = await generate_random_shopping_mall_admin_categories_create(
    adminConnection,
    {
      body: { name: RandomGenerator.name() },
    },
  );
  typia.assert(category);
  // 6. Seller creates a product assigned to that category
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        name: RandomGenerator.name(),
        description: RandomGenerator.paragraph({ sentences: 2 }),
        base_price: 10000,
        categoryId: category.id,
      },
    },
  );
  typia.assert(product);
  // 7. Seller adds a variant to the product with at least one option
  const variant =
    await generate_random_shopping_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
        body: {
          sku: RandomGenerator.alphaNumeric(12),
          priceOverride: null,
          options: [
            {
              key: "color",
              value: "Red",
              sequence: 0,
            },
          ],
        },
      },
    );
  typia.assert(variant);
  // 8. Seller adds inventory stock (quantity=10) so variant becomes 'available'
  const inventoryRecord =
    await generate_random_shopping_mall_seller_products_variants_inventory_records_create(
      sellerConnection,
      {
        params: { productId: product.id, variantId: variant.id },
        body: {
          quantity: 10,
          note: "Initial stock",
        },
      },
    );
  typia.assert(inventoryRecord);
  // 9. Customer joins the platform
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  // 10. Customer adds the variant to the cart with quantity=3
  const cartItem =
    await generate_random_shopping_mall_customer_cart_items_create(
      customerConnection,
      {
        body: {
          product_variant_id: variant.id,
          quantity: 3,
        },
      },
    );
  typia.assert(cartItem);
  // Validations
  TestValidator.equals(
    "productVariant.id matches requested variant",
    cartItem.productVariant.id,
    variant.id,
  );
  TestValidator.equals("quantity is exactly 3", cartItem.quantity, 3);
  TestValidator.equals(
    "availabilityStatus is available",
    cartItem.availabilityStatus,
    "available",
  );
  TestValidator.equals("stockWarning is false", cartItem.stockWarning, false);
  // unitPrice: priceOverride is null, so falls back to product.base_price
  const expectedUnitPrice = variant.priceOverride ?? product.base_price;
  TestValidator.equals(
    "unitPrice matches expected",
    cartItem.unitPrice,
    expectedUnitPrice,
  );
  TestValidator.equals(
    "subtotal equals unitPrice * quantity",
    cartItem.subtotal,
    expectedUnitPrice * 3,
  );
}
