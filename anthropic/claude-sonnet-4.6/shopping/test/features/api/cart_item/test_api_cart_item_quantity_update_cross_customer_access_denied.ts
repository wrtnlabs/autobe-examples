export async function test_api_cart_item_quantity_update_cross_customer_access_denied(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin joins and creates a product category
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  const category = await generate_random_shopping_mall_admin_categories_create(
    adminConnection,
    {
      body: {
        name: RandomGenerator.alphabets(8),
        description: RandomGenerator.paragraph({ sentences: 2 }),
      },
    },
  );
  typia.assert(category);
  // 2. Seller joins and creates a product with a variant
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {});
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        name: RandomGenerator.paragraph({ sentences: 2 }),
        description: RandomGenerator.paragraph({ sentences: 3 }),
        base_price: 5000,
        categoryId: category.id,
      },
    },
  );
  typia.assert(product);
  const variant =
    await generate_random_shopping_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
        body: {
          sku: `SKU-${RandomGenerator.alphaNumeric(12)}`,
          priceOverride: null,
          options: [
            {
              key: "color",
              value: "Red",
              sequence: 0,
            },
          ],
        },
      },
    );
  typia.assert(variant);
  // 3. Customer A joins and adds the variant to their cart
  const customerAConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerAConnection, {});
  const cartItem =
    await generate_random_shopping_mall_customer_cart_items_create(
      customerAConnection,
      {
        body: {
          product_variant_id: variant.id,
          quantity: 2,
        },
      },
    );
  typia.assert(cartItem);
  // 4. Customer B joins as a separate, independent customer
  const customerBConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerBConnection, {});
  // 5. Customer B attempts to update Customer A's cart item — must fail with an error
  // The system enforces per-customer cart isolation and returns 404 to prevent enumeration attacks
  await TestValidator.error(
    "Customer B cannot update Customer A's cart item (cross-customer access denied)",
    async () => {
      await api.functional.shoppingMall.customer.cartItems.update(
        customerBConnection,
        {
          cartItemId: cartItem.id,
          body: {
            quantity: 10,
          } satisfies IShoppingMallCartItem.IUpdate,
        },
      );
    },
  );
}
