export async function test_api_cart_item_out_of_stock_variant_added(
  connection: api.IConnection,
): Promise<void> {
  // ─── 1. Admin joins ───────────────────────────────────────────────────────
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  // ─── 2. Seller joins ──────────────────────────────────────────────────────
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {});
  // ─── 3. Seller submits approval request ───────────────────────────────────
  const approval = await generate_random_shopping_mall_seller_approvals_create(
    sellerConnection,
    { body: {} },
  );
  typia.assert(approval);
  // ─── 4. Admin approves seller ─────────────────────────────────────────────
  const approvedApproval =
    await api.functional.shoppingMall.admin.sellerApprovals.update(
      adminConnection,
      {
        approvalId: approval.id,
        body: {
          status: "approved",
          rejection_reason: null,
        } satisfies IShoppingMallSellerApproval.IUpdate,
      },
    );
  typia.assert(approvedApproval);
  // ─── 5. Admin creates category ────────────────────────────────────────────
  const category = await generate_random_shopping_mall_admin_categories_create(
    adminConnection,
    {},
  );
  typia.assert(category);
  // ─── 6. Seller creates product ────────────────────────────────────────────
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        categoryId: category.id,
      },
    },
  );
  typia.assert(product);
  // ─── 7. Seller adds variant WITHOUT inventory (zero stock) ────────────────
  const variant =
    await generate_random_shopping_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: {
          productId: product.id,
        },
      },
    );
  typia.assert(variant);
  // ─── 8. Customer joins ────────────────────────────────────────────────────
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  // ─── Test: Customer adds the zero-stock variant to cart ───────────────────
  const cartItem =
    await generate_random_shopping_mall_customer_cart_items_create(
      customerConnection,
      {
        body: {
          product_variant_id: variant.id,
          quantity: 1,
        },
      },
    );
  typia.assert(cartItem);
  // ─── Validations ──────────────────────────────────────────────────────────
  // quantity must be 1
  TestValidator.equals("cart item quantity", cartItem.quantity, 1);
  // availabilityStatus must be 'out_of_stock' (zero inventory, no records exist)
  TestValidator.equals(
    "availability status is out_of_stock",
    cartItem.availabilityStatus,
    "out_of_stock",
  );
  // stockWarning must be false (stock=0, NOT 0 < stock < quantity)
  TestValidator.equals("stock warning is false", cartItem.stockWarning, false);
  // unitPrice: variant.priceOverride if set, else product.base_price
  const expectedUnitPrice =
    variant.priceOverride !== null ? variant.priceOverride : product.base_price;
  TestValidator.equals(
    "unit price matches",
    cartItem.unitPrice,
    expectedUnitPrice,
  );
  // subtotal = unitPrice * quantity = unitPrice * 1
  TestValidator.equals(
    "subtotal equals unitPrice * 1",
    cartItem.subtotal,
    expectedUnitPrice * 1,
  );
  // productVariant.inStock must be false (zero stock)
  TestValidator.equals(
    "productVariant.inStock is false",
    cartItem.productVariant.inStock,
    false,
  );
  // productVariant.stockQuantity must be 0
  TestValidator.equals(
    "productVariant.stockQuantity is 0",
    cartItem.productVariant.stockQuantity,
    0,
  );
}
