export async function test_api_shipment_tracking_number_cleared_with_full_timestamps(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register and authenticate seller
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {});
  // 2. Seller submits approval request
  const approval = await generate_random_shopping_mall_seller_approvals_create(
    sellerConnection,
    { body: {} },
  );
  typia.assert(approval);
  // 3. Register and authenticate admin
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  // 4. Admin approves the seller
  const approvedApproval =
    await api.functional.shoppingMall.admin.sellerApprovals.update(
      adminConnection,
      {
        approvalId: approval.id,
        body: {
          status: "approved",
          rejection_reason: null,
        } satisfies IShoppingMallSellerApproval.IUpdate,
      },
    );
  typia.assert(approvedApproval);
  // 5. Create a category
  const category = await generate_random_shopping_mall_admin_categories_create(
    adminConnection,
    {},
  );
  typia.assert(category);
  // 6. Seller creates a product
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        categoryId: category.id,
      },
    },
  );
  typia.assert(product);
  // 7. Seller creates a variant
  const variant =
    await generate_random_shopping_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
        body: {},
      },
    );
  typia.assert(variant);
  // 8. Seller adds inventory (positive quantity)
  const inventoryRecord =
    await generate_random_shopping_mall_seller_products_variants_inventory_records_create(
      sellerConnection,
      {
        params: { productId: product.id, variantId: variant.id },
        body: { quantity: 10, note: "Initial stock for test" },
      },
    );
  typia.assert(inventoryRecord);
  // 9. Register and authenticate customer
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  // 10. Customer places an order
  const order = await generate_random_shopping_mall_customer_orders_create(
    customerConnection,
    {
      body: {
        items: [
          {
            product_variant_id: variant.id,
            quantity: 1,
          },
        ],
      },
    },
  );
  typia.assert(order);
  // Extract the order item id
  const orderItemId = order.items[0]!.id;
  // 11. Seller creates an initial shipment with a tracking number
  const shipment =
    await generate_random_shopping_mall_seller_orders_shipments_create(
      sellerConnection,
      {
        params: { orderId: order.id },
        body: {
          carrier: "FedEx",
          trackingNumber: "INITIAL123456",
          orderItemIds: [orderItemId],
        },
      },
    );
  typia.assert(shipment);
  // --- First Update: Set all optional fields ---
  const now = new Date();
  const shippedAt = now.toISOString();
  const estimatedDeliveryAt = new Date(
    now.getTime() + 7 * 24 * 60 * 60 * 1000,
  ).toISOString();
  const firstUpdate =
    await api.functional.shoppingMall.seller.orders.shipments.update(
      sellerConnection,
      {
        orderId: order.id,
        shipmentId: shipment.id,
        body: {
          carrier: "UPS",
          tracking_number: "1Z999AA10123456784",
          shipped_at: shippedAt,
          estimated_delivery_at: estimatedDeliveryAt,
        } satisfies IShoppingMallShipment.IUpdate,
      },
    );
  typia.assert(firstUpdate);
  TestValidator.equals("first update carrier", firstUpdate.carrier, "UPS");
  TestValidator.equals(
    "first update tracking number",
    firstUpdate.tracking_number,
    "1Z999AA10123456784",
  );
  TestValidator.equals(
    "first update delivered_at is null",
    firstUpdate.delivered_at,
    null,
  );
  TestValidator.predicate(
    "first update items non-empty",
    firstUpdate.items.length > 0,
  );
  // --- Second Update: Clear tracking number, change carrier ---
  const secondUpdate =
    await api.functional.shoppingMall.seller.orders.shipments.update(
      sellerConnection,
      {
        orderId: order.id,
        shipmentId: shipment.id,
        body: {
          carrier: "DHL",
          tracking_number: null,
        } satisfies IShoppingMallShipment.IUpdate,
      },
    );
  typia.assert(secondUpdate);
  TestValidator.equals("second update carrier", secondUpdate.carrier, "DHL");
  TestValidator.equals(
    "second update tracking number is null",
    secondUpdate.tracking_number,
    null,
  );
  TestValidator.equals(
    "second update delivered_at is null",
    secondUpdate.delivered_at,
    null,
  );
  TestValidator.predicate(
    "second update items non-empty",
    secondUpdate.items.length > 0,
  );
}
