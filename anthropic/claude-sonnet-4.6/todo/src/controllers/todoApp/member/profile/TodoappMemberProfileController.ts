import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { ITodoAppUserProfile } from "../../../../api/structures/ITodoAppUserProfile";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getTodoAppMemberProfile } from "../../../../providers/getTodoAppMemberProfile";
import { putTodoAppMemberProfile } from "../../../../providers/putTodoAppMemberProfile";

@Controller("/todoApp/member/profile")
export class TodoappMemberProfileController {
  /**
   * Retrieve the authenticated member's own user profile.
   *
   * This operation returns the profile record belonging to the currently authenticated member. The profile, stored in the `todo_app_user_profiles` table, contains the member's chosen display name — the human-readable label that personalizes their account experience — along with timestamps indicating when the profile was created and last updated.
   *
   * Access is strictly restricted to authenticated members only. Unauthenticated guests are categorically denied access to any profile operation. The system resolves the caller's identity from the active session token and returns only the profile that belongs to that caller. It is not possible to retrieve another user's profile through this endpoint; the system always returns the caller's own profile data exclusively.
   *
   * The profile entity maintains a strict one-to-one relationship with the member account (`todo_app_members`). Every member has exactly one profile, which is automatically created at registration and permanently removed when the account is deleted. The `display_name` field is purely presentational and may be changed by the member at any time via the profile update operation (`PUT /profile`).
   *
   * This endpoint is typically used to populate profile display views in the client application, such as showing the member's current display name in a header or settings page. It should be called before initiating a profile edit flow so the client can pre-fill the current display name value.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification 1. Extract the authenticated member's ID from the active session token (JWT or session record). Reject the request with 401 Unauthorized if no valid session is present.
   * 2. Query the `todo_app_user_profiles` table with a WHERE clause on `todo_app_member_id = <authenticated member ID>`.
   * 3. Since every active member has exactly one profile (enforced by the @@unique([todo_app_member_id]) constraint and cascade creation at registration), a result is always expected for active accounts. If no profile row is found (edge case during account setup), respond with 404 Not Found.
   * 4. Return the full profile entity: id, todo_app_member_id, display_name, created_at, updated_at.
   * 5. Never accept or use any externally-supplied user/member identifier — always derive identity from the session context to enforce that members can only access their own profile.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @MemberAuth()
    member: MemberPayload,
  ): Promise<ITodoAppUserProfile> {
    try {
      return await getTodoAppMemberProfile({
        member,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update the authenticated member's own user profile, replacing the current display name with the value provided in the request body.
   *
   * This operation targets the `todo_app_user_profiles` table, which stores the human-readable display name for each registered member. Every member has exactly one profile (enforced by a unique constraint on `todo_app_member_id`), and the profile is created automatically when the member account is established. The profile's `display_name` column is the only user-editable field — all other columns are system-managed timestamps.
   *
   * Access is strictly restricted to the profile owner. Only the currently authenticated member may call this endpoint; the target profile is always implicitly the profile belonging to the session's member. There is no mechanism to modify another user's profile, and any attempt to do so is denied. Unauthenticated requests (i.e., requests made without a valid member session) are rejected outright before any profile data is processed.
   *
   * Upon successful update, the `updated_at` timestamp on the `todo_app_user_profiles` record is refreshed to reflect the moment of the change. The full updated profile is returned in the response, allowing the client to confirm the applied changes.
   *
   * Related operations:
   * - `GET /profile` — retrieves the current authenticated member's profile without modification.
   * - `PUT /members/password` — updates the member's password credential, which resides in `todo_app_members` rather than the profile.
   *
   * @param connection
   * @param body New display name to apply to the authenticated member's profile
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification 1. Authentication check: Verify that the request carries a valid member session token. If the session is absent or invalid, reject with 401 Unauthorized before accessing any data.
   *
   * 2. Resolve the target profile: Using the authenticated member's ID from the session, query `todo_app_user_profiles` where `todo_app_member_id = <session.memberId>`. Because of the @@unique([todo_app_member_id]) constraint, at most one record exists. If no profile is found (should not occur for a properly initialized account), return 404.
   *
   * 3. Validate the request body:
   *    - `display_name` must be a non-empty string.
   *    - Reject with 422 if `display_name` is missing, null, or blank after trimming.
   *
   * 4. Perform the update: Execute an UPDATE on `todo_app_user_profiles` setting `display_name = <body.display_name>` and `updated_at = NOW()` where `id = <profile.id>`.
   *
   * 5. Return the updated record: Fetch (or use the returned row from the UPDATE) and serialize it as `ITodoAppUserProfile`, including `id`, `todo_app_member_id`, `display_name`, `created_at`, and `updated_at`.
   *
   * 6. No cross-user access: The profile is always scoped to the session's member ID. There is no path parameter that could target a different member's profile. Authorization enforcement is inherent in the session-scoped lookup.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: ITodoAppUserProfile.IUpdate,
  ): Promise<ITodoAppUserProfile> {
    try {
      return await putTodoAppMemberProfile({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
