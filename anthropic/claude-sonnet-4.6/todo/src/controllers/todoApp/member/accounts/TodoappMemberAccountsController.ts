import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { ITodoAppMember } from "../../../../api/structures/ITodoAppMember";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getTodoAppMemberAccounts } from "../../../../providers/getTodoAppMemberAccounts";

@Controller("/todoApp/member/accounts")
export class TodoappMemberAccountsController {
  /**
   * Retrieve the currently authenticated member's own account information.
   *
   * This operation returns the full account record for the member who is currently logged in. The caller's identity is resolved from their active authentication session — no explicit identifier is required in the path or query. The response includes the member's email address, account creation timestamp, last update timestamp, and the associated user profile details (display name).
   *
   * The `todo_app_members` table is the root identity entity for every authenticated user in the todo application. Each member has a unique email address and a hashed password credential stored securely. This endpoint surfaces only the non-sensitive fields — the `password_hash` field is never included in any API response.
   *
   * The associated `todo_app_user_profiles` record is automatically created when the member registers and holds the member's chosen display name (`display_name`). The profile is strictly private and accessible only by the owning member. This operation reflects both the member account data and the embedded profile in a single response.
   *
   * Only authenticated members may call this endpoint. Guests and unauthenticated requests are rejected. Because this application has no administrator role, there is no way to view another member's account; every caller can only see their own data.
   *
   * After retrieving the account, related operations such as updating the display name (`PUT /userProfiles`) or changing the password (`PUT /accounts/password`) may be performed. To delete the account entirely, the member may call `DELETE /accounts`.
   *
   * @param connection
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Resolve the currently authenticated member from
     *   the active session token (JWT or session cookie). Query the
     *   `todo_app_members` table for the record matching the session's
     *   `todo_app_member_id`. Also JOIN or separately fetch the associated
     *   `todo_app_user_profiles` record via the `todo_app_member_id` foreign
     *   key to include display name in the response. Ensure the member record
     *   has a null `deleted_at` — if the account has been marked as deleted,
     *   return 401 or 404. Never return the `password_hash` field in the
     *   response. Map the result to `ITodoAppMember`, embedding the profile's
     *   `display_name`, `created_at`, and `updated_at`. No path parameters are
     *   required; the caller's identity is fully derived from the
     *   authentication context.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @MemberAuth()
    member: MemberPayload,
  ): Promise<ITodoAppMember> {
    try {
      return await getTodoAppMemberAccounts({
        member,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
