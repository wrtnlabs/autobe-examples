import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IPageITodoAppTodo } from "../../../../../api/structures/IPageITodoAppTodo";
import { ITodoAppTodo } from "../../../../../api/structures/ITodoAppTodo";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { patchTodoAppMemberTodosTrashed } from "../../../../../providers/patchTodoAppMemberTodosTrashed";

@Controller("/todoApp/member/todos/trashed")
export class TodoappMemberTodosTrashedController {
  /**
   * Retrieve a paginated list of trashed todo items belonging to the currently authenticated member.
   *
   * This operation returns all todos that have been moved to the trash — that is, all todo records in the `todo_app_todos` table where the `trashed_at` column is non-null and the `todo_app_member_id` matches the authenticated member's identity. The trash area allows members to review items they have soft-deleted before deciding to restore or permanently remove them.
   *
   * Each todo in the trash retains its complete information at the time of deletion, including `title`, `description`, `is_completed`, `started_at`, `due_at`, `created_at`, `updated_at`, and `trashed_at`. The `trashed_at` timestamp indicates when the todo was moved to the trash. No edits can be made to trashed todos; only restoration or permanent deletion are valid subsequent operations.
   *
   * Strict data ownership is enforced: members can only browse their own trashed todos. Active todos (where `trashed_at` is NULL) are not included in this list. This endpoint is strictly for the trash view and is separate from the active todo list.
   *
   * The request body supports pagination (page number and page size) as well as optional keyword search by title and sorting options (e.g., by `trashed_at`, `created_at`, `due_at`, or `started_at`). Sorting helps members find specific trashed items when the trash contains many entries.
   *
   * This operation is typically used before calling the restore endpoint (`PUT /todos/{todoId}/restore`) to bring a todo back to the active list, or before calling the permanent deletion endpoint (`DELETE /todos/{todoId}`) to irreversibly remove a todo and all its associated edit history.
   *
   * Only authenticated members may call this endpoint. Guest actors and unauthenticated requests will be rejected.
   *
   * @param connection
   * @param body Search criteria, sorting, and pagination options for listing trashed todos
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification 1. Authenticate the requesting member via session
     *   token. Reject unauthenticated requests with 401. 2. Extract the
     *   member's ID from the session (todo_app_member_id). 3. Query the
     *   todo_app_todos table with WHERE todo_app_member_id = :memberId AND
     *   trashed_at IS NOT NULL. 4. Apply optional keyword search: if the
     *   request body contains a search keyword, filter by title using ILIKE or
     *   trigram index (the table has a GIN index on title for trigram search).
     *   5. Apply optional completion status filter if provided (is_completed =
     *   true/false). 6. Apply sorting based on the request body's sort field
     *   and direction. Supported sort fields: trashed_at (default descending),
     *   created_at, due_at, started_at. Nulls last for optional date fields. 7.
     *   Apply pagination: use page number and page size from the request body
     *   to compute OFFSET and LIMIT. Default page size should be 20. 8. Return
     *   the paginated result wrapped in an IPage envelope with total count,
     *   current page, page size, and the array of todo summaries. 9. Each
     *   summary in the response includes: id, title, description, is_completed,
     *   started_at, due_at, created_at, updated_at, trashed_at.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: ITodoAppTodo.IRequest,
  ): Promise<IPageITodoAppTodo.ISummary> {
    try {
      return await patchTodoAppMemberTodosTrashed({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
