import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { deleteTodoAppMemberTodosTodoIdPermanent } from "../../../../../providers/deleteTodoAppMemberTodosTodoIdPermanent";

@Controller("/todoApp/member/todos/:todoId/permanent")
export class TodoappMemberTodosPermanentController {
  /**
   * Permanently and irreversibly deletes a trashed todo item along with its entire edit history.
   *
   * This operation physically removes the specified todo record from the `todo_app_todos` table and all of its associated audit log entries from the `todo_app_todo_edit_histories` table. Because the database relationship between todos and their edit histories is defined with `onDelete: Cascade`, all history records are automatically and atomically purged in the same operation. Once this operation completes, the data is completely gone and cannot be recovered by any means.
   *
   * The target todo must already reside in the trash — meaning its `trashed_at` column must be non-null — before permanent deletion is permitted. Active todos (where `trashed_at` is NULL) cannot be permanently deleted directly; the caller must first move the todo to the trash via the regular deletion endpoint, and then invoke this permanent deletion endpoint. Attempting to permanently delete a todo that is not currently in the trash will result in an error.
   *
   * Strict ownership enforcement is applied: only the authenticated member who originally created the todo may permanently delete it. The system identifies the requesting member from the active session. If the specified `todoId` does not exist, has already been permanently deleted, or belongs to a different member, the system responds as if the resource does not exist, preventing information leakage about other members' data.
   *
   * After successful permanent deletion, any subsequent request to retrieve this todo or its edit history will result in a not-found response, as both the todo and all history records are completely absent from the system.
   *
   * This operation is intended to be called after the todo has been placed in the trash. The typical workflow is: (1) move the todo to the trash via `DELETE /todos/{todoId}`, and then (2) permanently remove it via `DELETE /todos/{todoId}/permanent`.
   *
   * @param connection
   * @param todoId The UUID of the todo item to permanently delete. The todo must be owned by the authenticated member and currently reside in the trash (trashed_at is non-null).
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification 1. Extract the authenticated member's ID from the
     *   current session. Reject with 401 if not authenticated. 2. Look up the
     *   todo record in `todo_app_todos` by `id = todoId`. 3. If no record is
     *   found, return 404. 4. If the found record's `todo_app_member_id` does
     *   not match the authenticated member's ID, return 404 (do not reveal
     *   ownership information). 5. Check that `trashed_at` is non-null. If
     *   `trashed_at` is NULL (the todo is still active), reject with 400 or
     *   422, indicating the todo is not in the trash and cannot be permanently
     *   deleted. 6. Execute a hard DELETE on the `todo_app_todos` record where
     *   `id = todoId`. Due to the `onDelete: Cascade` constraint on
     *   `todo_app_todo_edit_histories.todo_app_todo_id`, all associated edit
     *   history records are automatically deleted in the same database
     *   transaction. 7. Return HTTP 204 No Content to indicate successful
     *   permanent deletion with no response body.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erasePermanent(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoAppMemberTodosTodoIdPermanent({
        member,
        todoId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
