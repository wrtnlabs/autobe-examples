  /**
   * Restore a trashed todo item back to the active todo list.
   *
   * This operation transitions a todo from the trash state back to active, making it visible again in the member's normal todo list. It is the counterpart to the delete (trash) operation and represents the recovery path in the todo lifecycle: Active → Trash → Active.
   *
   * The target todo is identified by `todoId` in the path. The system looks up the record in `todo_app_todos` and checks the `trashed_at` column — the soft-deletion timestamp that distinguishes active todos (NULL) from trashed ones (non-NULL). Only todos with a non-NULL `trashed_at` are eligible for restoration; the operation sets this field back to NULL, effectively returning the todo to the active list.
   *
   * Access is strictly private. Only the authenticated member who owns the todo may restore it. If the `todoId` does not exist or belongs to a different member, the system responds as if the resource does not exist, preventing any cross-user information leakage. Guest actors and unauthenticated requests are rejected outright.
   *
   * Attempting to restore a todo that is not currently in the trash (i.e., it is already active with `trashed_at = NULL`) results in a validation error. Similarly, attempting to restore a todo that has been permanently deleted (i.e., the record no longer exists in the database) results in a not-found error, as permanent deletion is irreversible.
   *
   * Upon successful restoration, the todo returns to the member's active list with its complete original data intact — title, description, completion status (`is_completed`), optional start date (`started_at`), and optional due date (`due_at`). The full edit history stored in `todo_app_todo_edit_histories` is also restored and accessible to the member. The todo becomes subject to all standard active-todo operations: editing, completion toggling, filtering, and sorting.
   *
   * Related operations:
   * - `DELETE /todos/{todoId}` — moves a todo to the trash (the inverse of this operation).
   * - `DELETE /todos/{todoId}/purge` — permanently removes a todo from the trash; this action is irreversible.
   * - `PATCH /todos/trash` — lists all currently trashed todos for the authenticated member.
   *
   * @param connection
   * @param todoId The UUID of the todo item to restore from the trash. Must be a todo owned by the authenticated member that is currently in the trash (trashed_at IS NOT NULL).
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification 1. Authenticate the requesting actor — must be a
     *   logged-in member. Reject unauthenticated requests. 2. Look up the todo
     *   by `todoId` (UUID) in `todo_app_todos`. If no record is found, return
     *   404. 3. Verify ownership: `todo_app_todos.todo_app_member_id` must
     *   match the authenticated member's ID. If it belongs to another member,
     *   treat the record as non-existent and return 404 (do not leak ownership
     *   information). 4. Check the trash state: `trashed_at` must be NOT NULL.
     *   If `trashed_at` IS NULL (todo is already active), reject the request
     *   with a 400/422 error indicating the todo is not in the trash and cannot
     *   be restored. 5. Perform the restore: set `trashed_at = NULL` and update
     *   `updated_at` to the current timestamp. Execute this as a single UPDATE
     *   statement within a transaction. 6. Return the updated `todo_app_todos`
     *   record as the response body, including all fields: id, title,
     *   description, is_completed, started_at, due_at, trashed_at (now null),
     *   created_at, updated_at. 7. The todo's associated
     *   `todo_app_todo_edit_histories` records remain intact and are accessible
     *   after restoration. 8. Error cases: - 401 Unauthorized: no valid
     *   session. - 404 Not Found: todoId not found or belongs to another
     *   member. - 422 Unprocessable: todo is not currently in the trash
     *   (trashed_at is NULL).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":todoId/restore")
  public async restore(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppTodo> {
    try {
      return await putTodoAppMemberTodosTodoIdRestore({
        member,
        todoId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
