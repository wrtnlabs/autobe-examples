  /**
   * Update an existing todo item owned by the authenticated member.
   *
   * This operation allows a member to modify the mutable attributes of one of their own todo items, identified by its unique UUID. The fields that may be updated include the todo's title, optional description, optional start date, optional due date, and completion status. The system will record the time of modification in the `updated_at` field automatically.
   *
   * The `todo_app_todos` table represents the central business entity for discrete, trackable tasks. Each todo is permanently owned by the member who created it, as captured by the `todo_app_member_id` foreign key. The `title` field is mandatory and cannot be cleared — a todo must always have a title that names or summarizes the task. The `description` field is optional free-form text for additional context and may be set to null. The `started_at` and `due_at` fields are optional timestamps representing the intended start and deadline dates respectively; either or both may be null. The `is_completed` flag tracks whether the member has finished the task; it can be freely toggled between true and false at any time while the todo is active.
   *
   * Access control is strictly enforced: only the authenticated member who owns the todo may update it. Attempting to update a todo belonging to another member will result in a denial regardless of the operation requested. Todos that are currently in the trash (where `trashed_at` is non-null) cannot be updated through this endpoint — they must be restored to active status first before editing.
   *
   * This operation should be used after retrieving the todo via `GET /todoApp/member/todos/{todoId}` to confirm the current state. Related operations include `POST /todoApp/member/todos` for creation, `GET /todoApp/member/todos/{todoId}` for detail retrieval, and `PATCH /todoApp/member/todos` for searching the todo list.
   *
   * @param connection
   * @param todoId The unique UUID of the todo item to update.
   * @param body Updated field values for the todo item, including title, description, completion status, and optional date fields.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification 1. Authenticate the requesting member via
     *   session. Return 401 if unauthenticated. 2. Look up the todo record in
     *   todo_app_todos by the given todoId (UUID). Return 404 if not found. 3.
     *   Verify that the todo's todo_app_member_id matches the authenticated
     *   member's ID. Return 403 if ownership check fails. 4. Verify that
     *   trashed_at IS NULL (todo is active). Return 422 or 400 if the todo is
     *   currently trashed — trashed todos must be restored before they can be
     *   edited. 5. Validate the request body: - title: required, non-empty
     *   string. - description: optional, may be null. - started_at: optional
     *   datetime, may be null. - due_at: optional datetime, may be null. -
     *   is_completed: required boolean. 6. Perform the UPDATE on todo_app_todos
     *   setting title, description, is_completed, started_at, due_at, and
     *   updated_at = NOW() WHERE id = todoId. 7. Return the full updated todo
     *   record as ITodoAppTodo.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
