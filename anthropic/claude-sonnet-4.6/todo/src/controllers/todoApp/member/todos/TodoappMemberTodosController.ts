  /**
   * Retrieve the full details of a specific todo item belonging to the currently authenticated member.
   *
   * This operation returns all available fields of a single todo record from the `todo_app_todos` table, identified by its unique UUID. The returned data includes the mandatory title, the optional free-form description, the completion status flag (`is_completed`), optional start date (`started_at`), optional due date (`due_at`), the soft-deletion timestamp (`trashed_at`), and the system-maintained timestamps for creation (`created_at`) and last update (`updated_at`).
   *
   * Strict data ownership and privacy enforcement is applied: the system will only return a todo if it belongs to the authenticated member making the request. If the requested todo belongs to a different member, or if the todo does not exist, the request will be denied. There is no mechanism for members to access, share, or view another member's todos.
   *
   * This endpoint returns todos regardless of their current visibility state — both active todos (where `trashed_at` is NULL) and trashed todos (where `trashed_at` is non-NULL) can be retrieved by their owner using this operation. Consumers can inspect the `trashed_at` field in the response to determine whether the todo is currently active or in the trash.
   *
   * Typically, this endpoint is used after listing todos via `PATCH /todos` to obtain the complete detail view of a specific item, including the full description field which may not be included in the list summary response.
   *
   * @param connection
   * @param todoId The unique UUID of the target todo item to retrieve.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification 1. Extract the authenticated member's ID from the
     *   session/JWT token. 2. Query the todo_app_todos table by the given
     *   todoId (UUID) with a WHERE clause: id = todoId AND todo_app_member_id =
     *   authenticatedMemberId. 3. If no record is found (either the todo does
     *   not exist or belongs to a different member), return a 404 Not Found
     *   error. Do NOT reveal whether the todo belongs to another user — treat
     *   both cases identically. 4. Map all columns of the found record to the
     *   ITodoAppTodo DTO: id, todo_app_member_id, title, description
     *   (nullable), is_completed, started_at (nullable), due_at (nullable),
     *   trashed_at (nullable), created_at, updated_at. 5. Return the mapped DTO
     *   with HTTP 200.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
