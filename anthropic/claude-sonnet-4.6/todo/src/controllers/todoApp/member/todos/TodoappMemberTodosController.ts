  /**
   * Create a new todo item for the currently authenticated member.
   *
   * This operation creates a new todo record in the `todo_app_todos` table and associates it exclusively with the member who submits the request. The member's identity is resolved automatically from the authenticated session — the caller does not supply a member identifier in the request body.
   *
   * A todo requires a mandatory `title` that names or summarizes the task. An optional `description` may be provided for additional free-form detail. Optional `started_at` and `due_at` timestamps capture when the user intends to begin and finish the task, respectively; both default to null if omitted. The `is_completed` flag is always initialized to `false` for every newly created todo — completion must be toggled explicitly via the dedicated update operation after creation.
   *
   * This operation is strictly protected: only authenticated members may call it. Unauthenticated requests are rejected with an authentication error. Furthermore, all data created through this endpoint is strictly private to the member who created it — no other member or guest can access, view, or modify the resulting todo.
   *
   * After successful creation the full todo entity is returned, including the system-generated `id`, `created_at`, and `updated_at` timestamps. The returned record reflects the exact state stored in the database and can be used immediately for further operations such as editing (`PUT /todos/{todoId}`), toggling completion, or moving to trash (`DELETE /todos/{todoId}`).
   *
   * Related operations:
   * - `PATCH /todos` — list and search active todos belonging to the authenticated member.
   * - `PUT /todos/{todoId}` — update the title, description, or dates of an existing todo.
   * - `DELETE /todos/{todoId}` — move a todo to the trash (marks it as deleted).
   *
   * @param connection
   * @param body Fields required to create a new todo item. Title is mandatory; description, start date, and due date are optional.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification 1. Authentication guard: Verify the request
     *   carries a valid member session token. Reject with 401 if absent or
     *   invalid. 2. Extract the authenticated member's id from the session
     *   context. 3. Validate request body: - `title` must be a non-empty
     *   string. Return 400 if missing or blank. - `description`, `started_at`,
     *   `due_at` are optional; accept null or omitted values. 4. Insert a new
     *   row into `todo_app_todos`: - `id`: generate a new UUID v4. -
     *   `todo_app_member_id`: set to the authenticated member's id. - `title`:
     *   set from request body. - `description`: set from request body
     *   (nullable). - `is_completed`: always set to `false`. - `started_at`:
     *   set from request body (nullable). - `due_at`: set from request body
     *   (nullable). - `trashed_at`: set to `null`. - `created_at`: set to
     *   current UTC timestamp. - `updated_at`: set to current UTC timestamp. 5.
     *   Return the fully populated `ITodoAppTodo` entity (all columns) with
     *   HTTP 201. 6. No additional side effects — edit history is NOT recorded
     *   on creation, only on subsequent edits.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
