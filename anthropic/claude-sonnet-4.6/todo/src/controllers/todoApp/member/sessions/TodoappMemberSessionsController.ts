import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageITodoAppMemberSession } from "../../../../api/structures/IPageITodoAppMemberSession";
import { ITodoAppMemberSession } from "../../../../api/structures/ITodoAppMemberSession";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getTodoAppMemberSessionsSessionId } from "../../../../providers/getTodoAppMemberSessionsSessionId";
import { patchTodoAppMemberSessions } from "../../../../providers/patchTodoAppMemberSessions";

@Controller("/todoApp/member/sessions")
export class TodoappMemberSessionsController {
  /**
   * Retrieve a paginated list of the currently authenticated member's login sessions.
   *
   * This operation allows an authenticated member to browse their own session records from the `todo_app_member_sessions` table. Each session record represents a single login event, capturing the connection context including the IP address, request URL (href), HTTP referrer, and timestamps for session creation and expiration.
   *
   * Access is strictly limited to the authenticated member's own sessions. The system enforces data isolation such that a member can never view sessions belonging to another account. Unauthenticated requests are rejected before any session data is processed.
   *
   * Sessions are append-only audit records created automatically by the system on each successful login event. They are not user-managed — members cannot create, update, or delete session records directly. This endpoint provides a read-only view into the member's authentication history.
   *
   * The response is paginated and includes summary-level session information suitable for display in a session management UI. Filters may be applied to narrow results by date range or expiration status, enabling members to identify active sessions versus expired ones.
   *
   * Related operations:
   * - `POST /members/login` — Creates a new session record upon successful authentication.
   * - `POST /members/logout` — Terminates the current session.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering the member's session list
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification 1. Authenticate the requesting member via their
     *   session token. Reject with 401 if unauthenticated. 2. Extract the
     *   member ID from the authenticated session context. 3. Accept an
     *   ITodoAppMemberSession.IRequest body containing optional search/filter
     *   criteria (e.g., date range for created_at, active/expired filter based
     *   on expired_at vs current timestamp) and pagination parameters (page
     *   number, page size, sort direction). 4. Query the
     *   `todo_app_member_sessions` table with a WHERE clause filtering
     *   `todo_app_member_id = <authenticated_member_id>`. 5. Apply any
     *   additional filters from the request body: - If filtering for active
     *   sessions: add WHERE expired_at > NOW() - If filtering for expired
     *   sessions: add WHERE expired_at <= NOW() - If date range is provided:
     *   add WHERE created_at BETWEEN start AND end 6. Apply ORDER BY created_at
     *   DESC by default (most recent sessions first). 7. Apply LIMIT/OFFSET for
     *   pagination. 8. Return the total count and paginated results as
     *   ITodoAppMemberSession.ISummary items. 9. Each summary item includes:
     *   id, ip, href, referrer, created_at, expired_at (and optionally a
     *   computed 'is_active' boolean). 10. Never expose sessions of other
     *   members — the member_id filter is mandatory and must always be applied.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: ITodoAppMemberSession.IRequest,
  ): Promise<IPageITodoAppMemberSession.ISummary> {
    try {
      return await patchTodoAppMemberSessions({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific session record belonging to the currently authenticated member.
   *
   * This operation returns the full detail of a single session (login event) identified by its unique UUID. Each session record in the `todo_app_member_sessions` table captures the connection context — including the client IP address, the full request URL (`href`), the HTTP Referrer header, the creation timestamp, and the expiration timestamp — at the moment the member authenticated.
   *
   * Access is strictly limited to the authenticated member who owns the session. The system enforces data isolation: a member can only retrieve sessions associated with their own account. Any attempt to access a session owned by another member, or any attempt made without a valid authenticated session, will be rejected.
   *
   * Sessions are append-only audit records created exclusively through authentication flows (login). They are not created, modified, or deleted through direct user CRUD operations. A session is considered active until its `expired_at` timestamp is reached.
   *
   * This operation is useful for inspecting the metadata of a particular login event, such as verifying the originating IP address or checking when the session expires. To list all sessions for the authenticated member, use the corresponding list endpoint.
   *
   * @param connection
   * @param sessionId The UUID of the target session record to retrieve. Must belong to the currently authenticated member.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification 1. Authenticate the requesting user: validate the
     *   bearer token from the Authorization header. Reject with 401 if missing
     *   or invalid. 2. Resolve the session record: query
     *   `todo_app_member_sessions` WHERE `id = sessionId` (UUID). If not found,
     *   return 404. 3. Enforce ownership: verify that
     *   `todo_app_member_sessions.todo_app_member_id` equals the authenticated
     *   member's ID. If the session belongs to a different member, return 403
     *   (or 404 to avoid enumeration). 4. Return the full session detail object
     *   including: id, todo_app_member_id, ip, href, referrer, created_at,
     *   expired_at. 5. No joins to other tables are required beyond the session
     *   record itself.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppMemberSession> {
    try {
      return await getTodoAppMemberSessionsSessionId({
        member,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
