/**
 * Register or retrieve a guest account using a device fingerprint and issue JWT tokens for anonymous access.
 *
 * This endpoint allows unauthenticated visitors to obtain a temporary guest session. The caller provides a device fingerprint — a unique anonymous identifier string that identifies the client device (stored in the `device_fingerprint` column of `todo_app_guests`). If a guest record with the given fingerprint already exists, the system recognizes the returning visitor and updates `updated_at`; otherwise, a new `todo_app_guests` record is created with the supplied fingerprint.
 *
 * Upon successful join, a new session record is created in `todo_app_guest_sessions`, capturing the session's IP address (`ip`), the page URL (`href`), optional referrer header (`referrer` — nullable when absent), creation timestamp (`created_at`), and expiry timestamp (`expired_at`). The response carries JWT access and refresh tokens encapsulated in `ITodoAppGuest.IAuthorized`.
 *
 * Guest accounts have strictly limited permissions compared to authenticated members. They cannot create, view, or manage todo items. This operation is the sole entry point for guest actors — no email, password, or credential exchange is involved since the `todo_app_guests` table has no such fields.
 *
 * This operation requires the `guest` actor authorization and is the first call made by any anonymous visitor before any other interaction with the system.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Guest join payload including the device fingerprint that uniquely identifies this anonymous visitor's client device.
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor guest
 * @x-autobe-specification 1. Parse and validate the request body of type
 *   ITodoAppGuest.IJoin — must include a non-empty device_fingerprint string.
 *   2. Attempt to find an existing todo_app_guests record with the matching
 *   device_fingerprint (unique constraint: @@unique([device_fingerprint])). 3.
 *   If not found, INSERT a new todo_app_guests row with a new UUID id, the
 *   provided device_fingerprint, and current timestamps for created_at and
 *   updated_at. 4. If found, UPDATE updated_at to current timestamp (upsert
 *   semantics). 5. INSERT a new todo_app_guest_sessions row: new UUID id, the
 *   guest id as todo_app_guest_id, client IP, request href, referrer (nullable
 *   from HTTP header), created_at = now(), expired_at = now() + session
 *   duration (e.g., 30 days). 6. Generate JWT access token (short-lived, e.g.,
 *   1 hour) and refresh token (long-lived, e.g., 30 days) embedding the guest
 *   id and session id as claims. 7. Return ITodoAppGuest.IAuthorized containing
 *   the guest record data, access token, refresh token, and expiry information.
 *   8. Edge cases: reject empty/null device_fingerprint with 400 Bad Request;
 *   handle concurrent duplicate fingerprint inserts gracefully using upsert
 *   logic.
 * @path /todoApp/auth/guest/join
 * @accessor api.functional.todoApp.auth.guest.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
