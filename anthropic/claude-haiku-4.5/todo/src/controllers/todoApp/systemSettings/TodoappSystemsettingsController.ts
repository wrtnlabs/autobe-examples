import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { getTodoAppSystemSettings } from "../../../providers/getTodoAppSystemSettings";
import { AdminAuth } from "../../../decorators/AdminAuth";
import { AdminPayload } from "../../../decorators/payload/AdminPayload";
import { patchTodoAppSystemSettings } from "../../../providers/patchTodoAppSystemSettings";

import { IPageITodoAppSystemSetting } from "../../../api/structures/IPageITodoAppSystemSetting";
import { ITodoAppSystemSetting } from "../../../api/structures/ITodoAppSystemSetting";

@Controller("/todoApp/systemSettings")
export class TodoappSystemsettingsController {
  /**
   * Retrieve all system configuration settings.
   *
   * Fetch the complete set of system-wide configuration settings that control
   * application behavior.
   *
   * This operation retrieves all settings from the todo_app_system_setting
   * table, providing administrators with a comprehensive view of the current
   * system configuration. Each setting includes its unique identifier
   * (setting_key), current value (setting_value), data type (setting_type),
   * category for organization, and human-readable description.
   *
   * The returned settings govern critical system behaviors including
   * authentication timeouts, password policies, maximum todos per user, rate
   * limiting parameters, data retention periods, and performance tuning
   * parameters. Administrators use these settings to adjust system behavior
   * without requiring code changes or deployment.
   *
   * Only administrators with the "admin" role can retrieve system settings.
   * This ensures that sensitive system configuration information remains
   * accessible only to authorized personnel responsible for system management
   * and maintenance.
   *
   * @param connection
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async list(
    @AdminAuth()
    admin: AdminPayload,
  ): Promise<IPageITodoAppSystemSetting> {
    try {
      return await getTodoAppSystemSettings({
        admin,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and filter system configuration settings with pagination.
   *
   * Search for system configuration settings using advanced filtering, sorting,
   * and pagination capabilities.
   *
   * This operation provides complex query support for the
   * todo_app_system_setting table, enabling administrators to locate specific
   * settings based on multiple criteria. The search supports filtering by
   * setting_key (exact or partial match), setting_type (integer, string,
   * boolean, decimal), setting_category (authentication, password_policy,
   * data_management, email_notification, rate_limiting, performance), and
   * temporal filters (created_at, updated_at date ranges).
   *
   * The operation returns paginated results allowing efficient navigation
   * through large configuration sets. Results can be sorted by any field
   * (setting_key, setting_type, setting_category, created_at, updated_at) in
   * ascending or descending order. Pagination parameters control the number of
   * results per page and which page to retrieve.
   *
   * Only administrators with the "admin" role can search and filter system
   * settings. This restriction ensures that sensitive system configuration
   * information remains accessible only to authorized personnel responsible for
   * system administration and maintenance.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering system
   *   settings
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: ITodoAppSystemSetting.IRequest,
  ): Promise<IPageITodoAppSystemSetting.ISummary> {
    try {
      return await patchTodoAppSystemSettings({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
