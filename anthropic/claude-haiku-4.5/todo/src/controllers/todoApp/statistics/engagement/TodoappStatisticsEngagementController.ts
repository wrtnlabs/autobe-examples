import { Controller } from "@nestjs/common";
import { TypedRoute } from "@nestia/core";
import typia from "typia";
import { getTodoAppStatisticsEngagement } from "../../../../providers/getTodoAppStatisticsEngagement";

import { ITodoAppEngagementStatistics } from "../../../../api/structures/ITodoAppEngagementStatistics";

@Controller("/todoApp/statistics/engagement")
export class TodoappStatisticsEngagementController {
  /**
   * Retrieve aggregate engagement and activity statistics for user accounts.
   *
   * This operation returns comprehensive engagement statistics about user and
   * admin accounts in the system. It computes aggregated metrics including
   * total active user count, total admin count, user account creation trends
   * over time, distribution of active versus inactive users, and engagement
   * patterns based on last_active_at timestamps.
   *
   * The statistics are calculated from both the todo_app_user and
   * todo_app_admin tables and include metrics such as users created per day,
   * average days since last activity, percentage of active users in the past 30
   * days, and retention patterns. Soft-deleted accounts (marked via deleted_at)
   * are excluded from active user counts but tracked separately for compliance
   * and analytics purposes.
   *
   * This is a read-only operation that performs aggregation and analysis on
   * user account data without modifying any records. The response is optimized
   * for dashboard displays, system monitoring, and engagement reporting. No
   * authentication is required as these are system-level aggregate statistics
   * that do not expose individual user information.
   *
   * Administrators and system operators use this data to monitor overall
   * platform health, track user growth, identify engagement trends, and make
   * data-driven decisions about feature adoption and user retention
   * strategies.
   *
   * @param connection
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async index(): Promise<ITodoAppEngagementStatistics> {
    try {
      return await getTodoAppStatisticsEngagement();
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
