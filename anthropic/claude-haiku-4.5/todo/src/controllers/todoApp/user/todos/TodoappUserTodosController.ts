import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postTodoAppUserTodos } from "../../../../providers/postTodoAppUserTodos";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { patchTodoAppUserTodos } from "../../../../providers/patchTodoAppUserTodos";
import { getTodoAppUserTodosTodoId } from "../../../../providers/getTodoAppUserTodosTodoId";
import { putTodoAppUserTodosTodoId } from "../../../../providers/putTodoAppUserTodosTodoId";
import { deleteTodoAppUserTodosTodoId } from "../../../../providers/deleteTodoAppUserTodosTodoId";

import { ITodoAppTodo } from "../../../../api/structures/ITodoAppTodo";
import { IPageITodoAppTodo } from "../../../../api/structures/IPageITodoAppTodo";

@Controller("/todoApp/user/todos")
export class TodoappUserTodosController {
  /**
   * Create a new todo item for the authenticated user.
   *
   * Create a new todo item and add it to the authenticated user's personal todo
   * list. This operation is a core feature of the application, enabling users
   * to capture new tasks and action items they need to complete. The operation
   * accepts a title (required) and optional description for the new todo item.
   *
   * Input validation enforces business rules: The title must be between 1 and
   * 255 characters in length, as specified in the todo_app_todo schema. The
   * description, if provided, must not exceed 2000 characters. The operation
   * automatically validates these constraints and returns appropriate
   * validation error messages if constraints are violated.
   *
   * Upon successful creation, the newly created todo is automatically marked as
   * incomplete (is_completed = false) and assigned a unique UUID identifier.
   * The system automatically records the creation timestamp (created_at) and
   * sets updated_at to the same value. The completed_at field is explicitly set
   * to null since the todo has not been marked complete. The todo is
   * automatically associated with the authenticated user through the
   * todo_app_user_id foreign key, ensuring that only the creating user can see,
   * modify, or delete this todo.
   *
   * The response includes the complete newly created todo item with all fields
   * populated, allowing the client to immediately display the created task
   * without requiring a follow-up read operation. This operation is essential
   * for the primary user workflow of managing daily todos.
   *
   * @param connection
   * @param body Title and optional description for the new todo item to be
   *   created
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoAppTodo.ICreate,
  ): Promise<ITodoAppTodo> {
    try {
      return await postTodoAppUserTodos({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve a filtered, paginated list of todo items for the
   * authenticated user.
   *
   * Retrieve a filtered and paginated list of todo items belonging to the
   * authenticated user. This operation provides comprehensive search
   * capabilities for finding todos based on multiple criteria including partial
   * title matching, description content search, completion status filtering,
   * and date range queries. Users can search for specific todos they need to
   * work on or review their complete task history.
   *
   * The operation supports full pagination with configurable page sizes and
   * sorting options. Todos can be sorted by creation date, last modification
   * date, completion date, or completion status in ascending or descending
   * order. This flexibility allows users to organize their todos according to
   * their preferred workflow, whether they prefer viewing recently created
   * tasks, recently modified tasks, or completed tasks.
   *
   * Security and data isolation are paramount: Only authenticated users can
   * access this endpoint, and each user can only view and search their own
   * todos. The system automatically filters results to include only todos owned
   * by the requesting user. Response includes todo summary information
   * optimized for list displays, with core fields needed for efficient task
   * management.
   *
   * This operation integrates with the todo_app_todo table from the Prisma
   * schema, respecting all field definitions and constraints. The operation
   * handles the todo_app_user_id foreign key relationship to ensure complete
   * data isolation between users. Response times are optimized through database
   * indexing on creation date and user-id combinations as defined in the
   * schema.
   *
   * @param connection
   * @param body Search criteria, filtering options, and pagination parameters
   *   for todo list retrieval
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoAppTodo.IRequest,
  ): Promise<IPageITodoAppTodo.ISummary> {
    try {
      return await patchTodoAppUserTodos({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific todo item by its unique identifier.
   *
   * Retrieve detailed information about a specific todo item from the
   * authenticated user's personal todo list. This operation returns complete
   * todo data including the task title, description, completion status, and all
   * temporal tracking information.
   *
   * The operation queries the todo_app_todo table to fetch the todo identified
   * by the provided todoId parameter. The response includes all todo
   * properties: the title (required task description), optional description
   * field for additional context, and status information showing whether the
   * task is marked as complete. Temporal data includes created_at (immutable
   * creation timestamp), updated_at (last modification timestamp), and
   * completed_at (timestamp when marked complete, or null if never completed).
   *
   * Security and authorization: The operation verifies that the authenticated
   * user owns the requested todo item. Each todo is owned by exactly one user
   * (todo_app_user_id foreign key relationship), and users can only access
   * their own todos. Attempting to retrieve a todo belonging to another user
   * returns an authorization error. This ensures complete data isolation and
   * privacy for each user's todo list.
   *
   * This operation is frequently used to display detailed todo information in
   * UI views, support todo editing workflows, and enable users to review task
   * details before making modifications. Related operations include updating a
   * todo (PUT /todos/{todoId}), listing all todos (PATCH /todos), and deleting
   * todos.
   *
   * @param connection
   * @param todoId Unique identifier of the target todo item to retrieve
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":todoId")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppTodo> {
    try {
      return await getTodoAppUserTodosTodoId({
        user,
        todoId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing todo item with new information.
   *
   * Update one or more properties of an existing todo item in the authenticated
   * user's personal todo list. This operation allows users to modify the task
   * title, add or update the description, and change the completion status of a
   * todo item.
   *
   * The operation modifies the todo_app_todo table for the specified todo.
   * Users can update the title (task description, required to be between 1-255
   * characters), description (optional context information up to 2000
   * characters), and is_completed status (boolean indicating if task is
   * finished). When a todo is marked as complete for the first time, the system
   * automatically sets completed_at to the current timestamp. If a completed
   * todo is marked as incomplete again, completed_at is cleared to null.
   *
   * Validation rules enforced: Title must be present and contain 1-255
   * characters. Description, if provided, must not exceed 2000 characters. The
   * is_completed status must be a boolean value. All input data is sanitized to
   * prevent injection attacks. The operation requires that the todo item exists
   * and belongs to the authenticated user.
   *
   * Security and authorization: Only the user who owns the todo (verified
   * through todo_app_user_id matching the authenticated user's id) can update
   * it. Attempting to update another user's todo returns an authorization
   * error. The updated_at timestamp is automatically set to the current time by
   * the system. The operation maintains data isolation and ownership
   * verification throughout the update process.
   *
   * Temporal tracking: The operation updates the updated_at field to reflect
   * the modification time. If the is_completed status changes from false to
   * true, completed_at is set to current timestamp. If changed from true to
   * false, completed_at is cleared. The created_at and user ownership
   * (todo_app_user_id) are never modified.
   *
   * Related operations include retrieving a todo (GET /todos/{todoId}), listing
   * all todos (PATCH /todos), creating new todos (POST /todos), and deleting
   * todos (DELETE /todos/{todoId}).
   *
   * @param connection
   * @param todoId Unique identifier of the target todo item to update
   * @param body Updated properties for the todo item
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":todoId")
  public async update(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoAppTodo.IUpdate,
  ): Promise<ITodoAppTodo> {
    try {
      return await putTodoAppUserTodosTodoId({
        user,
        todoId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a specific todo item from the user's todo list.
   *
   * Remove a specific todo item permanently from the database by its unique
   * identifier. This operation completely deletes the todo record and all its
   * associated data, making it unrecoverable. The deletion is irreversible and
   * should be performed with user confirmation.
   *
   * The todo_app_todo table stores individual todo items representing tasks on
   * a user's personal todo list. Each todo item is owned by exactly one user
   * and contains the task description, completion status, and temporal tracking
   * information. This operation removes one complete todo record from that
   * table.
   *
   * Security considerations include verifying that the requesting user owns the
   * todo item before allowing deletion, or that the user has administrative
   * privileges. The system automatically creates an immutable audit log entry
   * recording who deleted the todo, when it was deleted, and other relevant
   * details for security and compliance purposes.
   *
   * The operation expects a valid todo ID in UUID format as a path parameter.
   * If the todo does not exist or the user lacks permission to delete it, the
   * operation returns an appropriate error response. Related operations include
   * retrieving individual todos (GET /todos/{todoId}) and listing all todos
   * (PATCH /todos).
   *
   * @param connection
   * @param todoId Unique identifier of the todo item to be deleted
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":todoId")
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoAppUserTodosTodoId({
        user,
        todoId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
