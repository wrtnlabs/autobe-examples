import { Controller } from "@nestjs/common";
import { TypedRoute } from "@nestia/core";
import typia from "typia";
import { getTodoAppAdminSystemHealth } from "../../../../providers/getTodoAppAdminSystemHealth";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";

import { ITodoAppSystemHealth } from "../../../../api/structures/ITodoAppSystemHealth";

@Controller("/todoApp/admin/systemHealth")
export class TodoappAdminSystemhealthController {
  /**
   * Retrieve current system health status and component status indicators.
   *
   * Retrieve comprehensive system health information including the status of
   * all critical system components and operational metrics.
   *
   * This operation provides administrators with immediate visibility into
   * system operational status. It returns the current state of database
   * connectivity, API server operations, authentication system status, and data
   * storage accessibility. The endpoint also includes real-time performance
   * indicators such as average API response times, system error rates, active
   * sessions count, request queue length, and overall system uptime.
   *
   * Resource utilization metrics are included to help administrators monitor
   * capacity: CPU utilization percentage, memory usage percentage, disk storage
   * usage percentage, and database connection pool utilization. All metrics are
   * measured against defined thresholds (green for healthy, yellow for warning,
   * red for critical) to enable quick assessment of system status.
   *
   * This operation is designed for the system health monitoring dashboard
   * described in the Admin Features and Management requirements. Administrators
   * regularly access this endpoint to verify system stability, identify
   * emerging issues, and make decisions about system maintenance or scaling.
   *
   * The health status endpoint serves as the primary entry point for
   * administrative monitoring. It enables detection of performance degradation,
   * resource constraints, and component failures. Related administrative
   * operations include audit log viewing for investigating incidents, system
   * statistics retrieval for trend analysis, and system configuration
   * modification for tuning system behavior.
   *
   * Response times for this operation should be minimal (< 500ms) as it is
   * frequently accessed during administrative monitoring. The data is current
   * to within approximately 60 seconds as system metrics are refreshed at
   * regular intervals. No request body is required for this operation - it is a
   * simple read operation returning current system state.
   *
   * @param connection
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @AdminAuth()
    admin: AdminPayload,
  ): Promise<ITodoAppSystemHealth> {
    try {
      return await getTodoAppAdminSystemHealth({
        admin,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
