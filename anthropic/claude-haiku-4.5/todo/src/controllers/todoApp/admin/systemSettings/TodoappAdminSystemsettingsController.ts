import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia from "typia";
import { getTodoAppAdminSystemSettingsSettingKey } from "../../../../providers/getTodoAppAdminSystemSettingsSettingKey";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { putTodoAppAdminSystemSettingsSettingKey } from "../../../../providers/putTodoAppAdminSystemSettingsSettingKey";

import { ITodoAppSystemSetting } from "../../../../api/structures/ITodoAppSystemSetting";

@Controller("/todoApp/admin/systemSettings/:settingKey")
export class TodoappAdminSystemsettingsController {
  /**
   * Retrieve a system setting by its unique key identifier.
   *
   * Retrieve a specific system-wide configuration setting identified by its
   * unique setting key. This operation queries the todo_app_system_setting
   * table to return complete setting information including the current value,
   * setting type, category, and administrative metadata.
   *
   * The setting key uniquely identifies the configuration parameter (e.g.,
   * 'session_timeout_minutes', 'password_min_length', 'max_todos_per_user').
   * The response includes the setting's current value, data type indicator,
   * category classification, and optional description and validation bounds.
   *
   * This operation is essential for the application to read configuration
   * parameters that control system behavior. All system components and
   * administrators use this endpoint to retrieve individual settings without
   * fetching the entire configuration set. The response includes metadata
   * fields that help interpret and validate the setting value appropriately.
   *
   * Security consideration: This endpoint returns system configuration
   * information that may be sensitive. Access should be restricted to
   * administrators and authorized system components. The setting values
   * returned may include operational constraints that should not be exposed to
   * untrusted clients.
   *
   * @param connection
   * @param settingKey Unique identifier for the system configuration setting to
   *   retrieve (e.g., 'session_timeout_minutes', 'password_min_length',
   *   'max_todos_per_user')
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("settingKey")
    settingKey: string,
  ): Promise<ITodoAppSystemSetting> {
    try {
      return await getTodoAppAdminSystemSettingsSettingKey({
        admin,
        settingKey,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing system setting by its unique key identifier.
   *
   * Update a specific system-wide configuration setting identified by its
   * unique setting key. This operation modifies the setting_value in the
   * todo_app_system_setting table while enforcing validation rules and
   * constraints defined for that setting.
   *
   * Administrators use this endpoint to modify configuration parameters that
   * control application behavior. The operation validates that the new value
   * conforms to the setting's data type (integer, string, boolean, decimal) and
   * respects any defined min_value and max_value constraints for numeric
   * settings. Only settings with is_editable=true can be modified; attempting
   * to update non-editable settings should result in validation failure.
   *
   * The operation updates the setting's current value and automatically records
   * the modification timestamp in updated_at. Changes to configuration settings
   * take effect system-wide immediately for all subsequent operations,
   * affecting all users and system components that read those settings. Related
   * operation: GET /systemSettings/{settingKey} retrieves the current state of
   * a setting after updates are applied.
   *
   * Security consideration: This endpoint modifies critical system
   * configuration that affects all users. Access must be strictly limited to
   * system administrators. Changes to rate limiting, authentication timeouts,
   * or password policies can have significant security and operational impact.
   * All modifications should be audited through the audit logging system.
   *
   * @param connection
   * @param settingKey Unique identifier for the system configuration setting to
   *   update (e.g., 'session_timeout_minutes', 'password_min_length',
   *   'max_todos_per_user')
   * @param body Updated system setting values including the new setting value
   *   and optional description or bounds information
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("settingKey")
    settingKey: string,
    @TypedBody()
    body: ITodoAppSystemSetting.IUpdate,
  ): Promise<ITodoAppSystemSetting> {
    try {
      return await putTodoAppAdminSystemSettingsSettingKey({
        admin,
        settingKey,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
