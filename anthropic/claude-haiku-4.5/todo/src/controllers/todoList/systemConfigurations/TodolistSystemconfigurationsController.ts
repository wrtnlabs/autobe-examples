import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia from "typia";
import { getTodoListSystemConfigurationsConfigKey } from "../../../providers/getTodoListSystemConfigurationsConfigKey";
import { postTodoListSystemConfigurations } from "../../../providers/postTodoListSystemConfigurations";

import { ITodoListSystemConfig } from "../../../api/structures/ITodoListSystemConfig";

@Controller("/todoList/systemConfigurations")
export class TodolistSystemconfigurationsController {
  /**
   * Retrieve a specific system configuration entry by configuration key.
   *
   * Fetch a single system configuration entry from the todo_list_system_config
   * table using the unique config_key identifier. This operation enables
   * clients to query specific configuration values needed for runtime
   * operation, such as feature flags, deployment settings, or system
   * constraints.
   *
   * The configuration key must exactly match an existing configuration entry.
   * The response includes the configuration value, its data type designation,
   * descriptive metadata, version number, and both creation and last-modified
   * timestamps for audit trail purposes.
   *
   * This operation is read-only and does not modify any system state. It is
   * typically used by client applications during initialization to fetch
   * environment-specific settings or by administrators monitoring the current
   * configuration state. The returned object includes all fields from the
   * configuration entry, allowing clients to make type-aware decisions about
   * how to interpret the configuration value.
   *
   * @param connection
   * @param configKey Unique configuration key identifier to retrieve (e.g.,
   *   'max_todos_per_user', 'enable_feature_flag_xyz',
   *   'deployment_environment')
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":configKey")
  public async at(
    @TypedParam("configKey")
    configKey: string,
  ): Promise<ITodoListSystemConfig> {
    try {
      return await getTodoListSystemConfigurationsConfigKey({
        configKey,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Create a new system configuration entry in the todo_list_system_config
   * table. This operation stores operational settings, feature flags, and
   * deployment-specific configuration that applies across the entire Todo List
   * application.
   *
   * The request must provide a unique configuration key (e.g.,
   * 'max_todos_per_user', 'enable_feature_flag_xyz', 'deployment_environment'),
   * the configuration value as a string, and the value_type designation
   * ('string', 'integer', 'boolean', or 'float'). An optional description field
   * can be provided to document the purpose and usage of the configuration
   * setting for operations team reference.
   *
   * The created entry is automatically assigned version number 1 (incremented
   * on subsequent updates) and creation/modification timestamps are set by the
   * system in UTC. The configuration key is stored as a unique constraint,
   * preventing duplicate configuration keys from being created. This endpoint
   * is used by system administrators and deployment processes to initialize or
   * add new configuration entries that control system behavior.
   *
   * @param connection
   * @param body Configuration entry data including key, value, type, and
   *   optional description
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @TypedBody()
    body: ITodoListSystemConfig.ICreate,
  ): Promise<ITodoListSystemConfig> {
    try {
      return await postTodoListSystemConfigurations({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
