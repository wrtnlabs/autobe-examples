import { Controller } from "@nestjs/common";
import { TypedRoute } from "@nestia/core";
import typia from "typia";
import { postTodoListAuthGuestLogout } from "../../../../../providers/postTodoListAuthGuestLogout";

import { ITodoListAuth } from "../../../../../api/structures/ITodoListAuth";

@Controller("/todoList/auth/guest/logout")
export class TodolistAuthGuestController {
  /**
   * This operation terminates an active guest user session in the todo list
   * application. Guest users represent unauthenticated access with limited
   * functionality, typically unable to persist todos permanently. Logout for
   * guests clears their session state and invalidates any guest-specific access
   * tokens or session identifiers.
   *
   * Unlike authenticated user logout which must revoke tokens in the
   * todo_list_token_blacklist table and update todo_list_sessions records,
   * guest logout performs lightweight session cleanup appropriate for
   * unauthenticated users. The operation may clear browser-stored session
   * identifiers or local state associated with the guest session.
   *
   * Security considerations for guest logout include properly clearing any
   * client-side storage to prevent reuse of expired guest credentials. Since
   * guests are not tracked in the todo_list_users table (having no persistent
   * account), there is no user account to deactivate or permanent session
   * record to update.
   *
   * This operation completes the guest user lifecycle and should be called when
   * a guest decides to end their session. It may be followed by either creating
   * a user account (registration) to persist todos, or simply closing the
   * application. The endpoint returns a confirmation message that the guest
   * session has been successfully terminated.
   *
   * @param connection
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async logout(): Promise<ITodoListAuth.IGuestLogoutResponse> {
    try {
      return await postTodoListAuthGuestLogout();
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
