import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchTodoListUserUsersMeSessions } from "../../../../../../providers/patchTodoListUserUsersMeSessions";
import { UserAuth } from "../../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../../decorators/payload/UserPayload";
import { getTodoListUserUsersMeSessionsSessionId } from "../../../../../../providers/getTodoListUserUsersMeSessionsSessionId";
import { deleteTodoListUserUsersMeSessionsSessionId } from "../../../../../../providers/deleteTodoListUserUsersMeSessionsSessionId";

import { IPageITodoListUserSession } from "../../../../../../api/structures/IPageITodoListUserSession";
import { ITodoListUserSession } from "../../../../../../api/structures/ITodoListUserSession";

@Controller("/todoList/user/users/me/sessions")
export class TodolistUserUsersMeSessionsController {
  /**
   * Search and enumerate session records for the authenticated user
   * (todo_list_user_sessions).
   *
   * Searches and lists all session records for the currently authenticated
   * user, supporting advanced filtering, pagination, and sorting options. The
   * endpoint gives users visibility into their login activity over all devices
   * and browsers via the todo_list_user_sessions table.
   *
   * Session records can be filtered by activity (active/expired), connection
   * metadata (IP, origin URL, referrer), and time-range criteria. The response
   * contains session summaries, exposing only essential metadata (timestamps,
   * IPs, URLs) for privacy and account management.
   *
   * The operation is strictly read-only: users cannot create, modify, or delete
   * sessions directly through this endpoint. Invalidation of sessions (such as
   * logout from all devices) is handled by the authentication subsystem and not
   * via business application APIs. Only the user themselves may invoke this
   * operation; no administrative listing or cross-user queries are supported.
   *
   * This operation prevents arbitrary access, safeguards user privacy, and
   * supports best practices for session enumeration and monitoring.
   *
   * @param connection
   * @param body Complex search, filtering, and pagination criteria to enumerate
   *   user session records.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoListUserSession.IRequest,
  ): Promise<IPageITodoListUserSession.ISummary> {
    try {
      return await patchTodoListUserUsersMeSessions({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve the details of an authenticated user's session based on sessionId
   * (todo_list_user_sessions).
   *
   * Fetch a specific session's details for the authenticated user.
   *
   * This endpoint allows users to view the details of one of their active or
   * historical sessions, which may include login timestamp, device/network
   * info, referrer, and session expiration time. Only the user who owns the
   * session may retrieve its details; there is no public or administrative
   * access to session records from this endpoint.
   *
   * The session data provides auditability and transparency to account holders,
   * helping detect unauthorized access or monitor recent activity. All session
   * model fields, such as IP, href, referrer, and timestamps, are available in
   * the response.
   *
   * Access errors will occur if the sessionId does not belong to the current
   * user or does not exist.
   *
   * @param connection
   * @param sessionId Unique identifier of the session record belonging to the
   *   current user.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<ITodoListUserSession> {
    try {
      return await getTodoListUserUsersMeSessionsSessionId({
        user,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Erase an authenticated user's session by sessionId
   * (todo_list_user_sessions).
   *
   * Terminate and remove a user's session by sessionId.
   *
   * The DELETE endpoint allows a logged-in user to invalidate one of their
   * current or past sessions. Deleting a session immediately logs it out and
   * removes its audit record, helping users secure their accounts if they
   * suspect unauthorized activity.
   *
   * This operation is self-service and only applicable to the current user's
   * own sessions. Administrative or cross-user session deletion is not exposed.
   * Permanent deletion is performed, with no recovery for removed session
   * data.
   *
   * @param connection
   * @param sessionId Unique identifier of the session record belonging to the
   *   current user.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":sessionId")
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoListUserUsersMeSessionsSessionId({
        user,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
