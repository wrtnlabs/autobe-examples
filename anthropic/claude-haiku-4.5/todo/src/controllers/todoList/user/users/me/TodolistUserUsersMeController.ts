import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { getTodoListUserUsersMe } from "../../../../../providers/getTodoListUserUsersMe";
import { UserAuth } from "../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../decorators/payload/UserPayload";
import { putTodoListUserUsersMe } from "../../../../../providers/putTodoListUserUsersMe";
import { deleteTodoListUserUsersMe } from "../../../../../providers/deleteTodoListUserUsersMe";

import { ITodoListUser } from "../../../../../api/structures/ITodoListUser";

@Controller("/todoList/user/users/me")
export class TodolistUserUsersMeController {
  /**
   * View the authenticated user's own profile from the todo_list_users table.
   *
   * Retrieve the currently authenticated user's profile information.
   *
   * This operation allows a logged-in user to view their own account details,
   * including their email address and the date they registered. The response
   * omits sensitive fields such as password hashes and internal record IDs,
   * ensuring that confidential credential data remains secure.
   *
   * Access is restricted to authenticated users; the endpoint never exposes
   * data for other users or permits administrative overrides. The operation
   * integrates session authentication to confirm the user's identity. Its logic
   * is based on the 'todo_list_users' Prisma table, referencing the unique
   * email-based business identifier.
   *
   * This endpoint forms the primary method by which application users access
   * their own profile. Account modification requires the dedicated PUT
   * operation on the same path. Rate-limiting and audit logging should be
   * considered for security best practices.
   *
   * @param connection
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @UserAuth()
    user: UserPayload,
  ): Promise<ITodoListUser> {
    try {
      return await getTodoListUserUsersMe({
        user,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update the authenticated user's profile in the todo_list_users table.
   *
   * Update the currently authenticated user's account profile.
   *
   * This operation allows a logged-in user to modify their own profile details,
   * such as changing their email address or password. All updates are subject
   * to validation rules consistent with the 'todo_list_users' Prisma table: the
   * email must remain unique across the system, and the password is stored as a
   * secure hash. Attempts to update to a duplicate email or provide an invalid
   * password will result in errors as defined by the business rules.
   *
   * Only the authenticated user's own record can be updated by this endpoint.
   * Administrative changes to other accounts are not possible through this
   * operation. Password changes require providing a hash of the new password;
   * plain text passwords are never accepted or returned. After a successful
   * update, the response returns the updated profile information, excluding
   * credential hashes or internal-only fields. Audit logging and security
   * policies apply to profile update actions.
   *
   * @param connection
   * @param body Updated profile data for the authenticated user (email,
   *   password, etc.), subject to validation and constraints.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoListUser.IUpdate,
  ): Promise<ITodoListUser> {
    try {
      return await putTodoListUserUsersMe({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete the authenticated user's account from the
   * todo_list_users table.
   *
   * Permanently and irreversibly deletes the authenticated user's account from
   * the system. Upon invocation, this endpoint ensures the authenticated user
   * is identified through secure session or token context, allowing only the
   * user themselves to initiate the deletion.
   *
   * All associated data, including todo items (each record in todo_list_todos
   * owned by the user) and session records (from todo_list_user_sessions), are
   * also removed as part of a comprehensive, cascading deletion policy. This
   * supports both privacy and data minimization requirements, fulfilling
   * expectations for user-driven account destruction.
   *
   * Security is paramount: the endpoint validates user identity and enforces
   * that no other user or administrator can delete accounts on behalf of
   * someone else. Strict auditing and referential checks are applied. Related
   * operations include creating a user, modifying account details, or logging
   * out—all of which become invalid after this deletion.
   *
   * The operation is guided by the requirement that no soft deletion occurs, no
   * restoration is possible, and all deletions are performed immediately and
   * without retention.
   *
   * @param connection
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @UserAuth()
    user: UserPayload,
  ): Promise<void> {
    try {
      return await deleteTodoListUserUsersMe({
        user,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
