import { Controller } from "@nestjs/common";
import { TypedRoute } from "@nestia/core";
import typia from "typia";
import { postTodoListUserAuthUserLogout } from "../../../../../../providers/postTodoListUserAuthUserLogout";
import { UserAuth } from "../../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../../decorators/payload/UserPayload";

import { ITodoListLogoutResponse } from "../../../../../../api/structures/ITodoListLogoutResponse";

@Controller("/todoList/user/auth/user/logout")
export class TodolistUserAuthUserController {
  /**
   * Terminate the current user's authenticated session and invalidate the JWT
   * token used for this request.
   *
   * This operation invalidates the session associated with the current device
   * by marking it as expired in the todo_list_sessions table. The JWT token
   * (identified by the jti claim) is added to the todo_list_token_blacklist
   * with revocation reason 'logout' to prevent token reuse. The operation
   * requires an authenticated user - the session and user information are
   * extracted from the JWT token provided in the Authorization header.
   *
   * Security: Only authenticated users can logout. The revocation is tied to
   * the specific token/session being used, allowing users to maintain other
   * active sessions on different devices. This supports the multi-device login
   * requirement where a user can logout from one device while remaining logged
   * in on others.
   *
   * After successful logout, the invalidated token cannot be used for any
   * further authenticated requests. The session record is marked with an
   * expired_at timestamp, and the token becomes unusable immediately. This
   * operation should be called as part of the user logout flow before the
   * client discards the token.
   *
   * @param connection
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async logout(
    @UserAuth()
    user: UserPayload,
  ): Promise<ITodoListLogoutResponse> {
    try {
      return await postTodoListUserAuthUserLogout({
        user,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
