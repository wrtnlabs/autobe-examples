import { Controller } from "@nestjs/common";
import { TypedRoute } from "@nestia/core";
import typia from "typia";
import { postTodoListUserAuthUserLogoutAllDevices } from "../../../../../../providers/postTodoListUserAuthUserLogoutAllDevices";
import { UserAuth } from "../../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../../decorators/payload/UserPayload";

import { ITodoListLogoutResponse } from "../../../../../../api/structures/ITodoListLogoutResponse";

@Controller("/todoList/user/auth/user/logout-all-devices")
export class TodolistUserAuthUserLogout_all_devicesController {
  /**
   * Log out current user from all devices.
   *
   * Terminate all of the current user's active sessions across all devices and
   * invalidate all associated JWT tokens.
   *
   * This operation invalidates all sessions associated with the authenticated
   * user by marking all their session records in the todo_list_sessions table
   * as expired. All active JWT tokens (identified by their jti claims) are
   * added to the todo_list_token_blacklist with revocation reason
   * 'global_logout' to prevent any further use. This is a global logout that
   * affects every device the user is currently logged in from.
   *
   * Security: Only authenticated users can initiate a global logout. This
   * operation is particularly important for security scenarios such as password
   * changes, suspected account compromise, or when a user wants to ensure no
   * other devices have access to their account. The user must be authenticated
   * to perform this operation, typically as a follow-up action after changing
   * their password.
   *
   * After successful global logout, all active sessions are terminated and all
   * tokens become unusable. Subsequent requests from any device using
   * previously valid tokens will be rejected. Users must re-authenticate
   * (login) to regain access from any device.
   *
   * @param connection
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async logoutAllDevices(
    @UserAuth()
    user: UserPayload,
  ): Promise<ITodoListLogoutResponse> {
    try {
      return await postTodoListUserAuthUserLogoutAllDevices({
        user,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
