import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { getTodoListUserAuthUserProfile } from "../../../../../../providers/getTodoListUserAuthUserProfile";
import { UserAuth } from "../../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../../decorators/payload/UserPayload";
import { putTodoListUserAuthUserProfile } from "../../../../../../providers/putTodoListUserAuthUserProfile";

import { ITodoListUser } from "../../../../../../api/structures/ITodoListUser";

@Controller("/todoList/user/auth/user/profile")
export class TodolistUserAuthUserProfileController {
  /**
   * Retrieve the authenticated user's profile information.
   *
   * Get the complete profile of the currently authenticated user. This
   * operation returns all available user account information including email
   * address, account creation and update timestamps, and last login history.
   *
   * The authenticated user's identity is automatically extracted from the JWT
   * bearer token in the authorization header. Only the authenticated user can
   * access their own profile - there is no ability to view other users'
   * profiles through this endpoint. The user's account must be active (not
   * soft-deleted) to access this endpoint.
   *
   * Returned information includes email (stored in lowercase), account creation
   * timestamp (UTC, ISO 8601 format), most recent account update timestamp, and
   * the user's last successful login timestamp. The deleted_at field will be
   * null for active accounts, confirming the account has not been soft-deleted.
   * The password_hash field is never included in responses for security
   * reasons.
   *
   * This operation supports the user's ability to verify their current account
   * information and access profile data for display in user interface settings
   * pages. It is typically called after successful authentication to populate
   * user dashboard or profile screens.
   *
   * @param connection
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @UserAuth()
    user: UserPayload,
  ): Promise<ITodoListUser> {
    try {
      return await getTodoListUserAuthUserProfile({
        user,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update the authenticated user's profile information.
   *
   * Update the profile information of the currently authenticated user. This
   * operation allows users to modify their account details such as email
   * address while maintaining account security and data integrity.
   *
   * The authenticated user's identity is extracted from the JWT bearer token,
   * ensuring that users can only modify their own profile and not other users'
   * accounts. The user's account must be active (not soft-deleted) to perform
   * updates. The request body contains the updated profile information that
   * should be applied to the user's account.
   *
   * Email address updates must maintain the unique constraint - a new email
   * cannot be the same as any existing user's email in the system. The system
   * will automatically update the updated_at timestamp to reflect when this
   * modification occurred. Password changes are not handled through this
   * endpoint and must use a dedicated password change operation. System-managed
   * fields such as created_at, deleted_at, and last_login_at cannot be modified
   * through this endpoint.
   *
   * Upon successful update, the operation returns the complete updated user
   * profile with all current account information. This allows the client to
   * immediately reflect the changes in the user interface without requiring a
   * separate profile fetch operation. The password_hash field is excluded from
   * the response for security reasons.
   *
   * @param connection
   * @param body Updated profile information for the authenticated user (only
   *   updatable fields)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoListUser.IUpdate,
  ): Promise<ITodoListUser> {
    try {
      return await putTodoListUserAuthUserProfile({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
