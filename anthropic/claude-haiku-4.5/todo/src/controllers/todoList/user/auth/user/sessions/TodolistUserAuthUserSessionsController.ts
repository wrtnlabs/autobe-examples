import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchTodoListUserAuthUserSessions } from "../../../../../../providers/patchTodoListUserAuthUserSessions";
import { UserAuth } from "../../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../../decorators/payload/UserPayload";
import { getTodoListUserAuthUserSessionsSessionId } from "../../../../../../providers/getTodoListUserAuthUserSessionsSessionId";

import { IPageITodoListSession } from "../../../../../../api/structures/IPageITodoListSession";
import { ITodoListSession } from "../../../../../../api/structures/ITodoListSession";

@Controller("/todoList/user/auth/user/sessions")
export class TodolistUserAuthUserSessionsController {
  /**
   * Search and retrieve a filtered, paginated list of user authentication
   * sessions.
   *
   * Retrieve a comprehensive list of all authentication sessions belonging to
   * the authenticated user. This operation provides visibility into all devices
   * and browsers from which the user is currently logged in or has recently
   * logged in.
   *
   * The operation supports advanced filtering options including session status
   * (active sessions with null expired_at vs terminated sessions with set
   * expired_at), creation date ranges, last activity date ranges, and
   * expiration status. Users can identify unusual session activity or manage
   * their login devices by reviewing IP addresses and user agent information
   * associated with each session.
   *
   * Pagination support allows efficient retrieval of session lists for users
   * with many concurrent sessions. Results can be sorted by creation time, last
   * activity time, or expiration status to help users identify the most recent
   * or most active sessions.
   *
   * Security Consideration: Response includes session device context (IP
   * address, user agent) for device identification only. User password hash,
   * authentication credentials, and other sensitive user information are
   * strictly excluded from all responses.
   *
   * @param connection
   * @param body Search criteria, filtering options, and pagination parameters
   *   for session retrieval
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoListSession.IRequest,
  ): Promise<IPageITodoListSession.ISummary> {
    try {
      return await patchTodoListUserAuthUserSessions({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific user authentication session.
   *
   * Fetch complete details about a single authentication session identified by
   * session ID. This operation provides comprehensive session information
   * including device context (IP address and user agent), session timing
   * (creation, last activity, expiration), and current status.
   *
   * The operation returns all session attributes from the todo_list_sessions
   * table: the unique session identifier, associated user ID, IP address from
   * which the session was established, HTTP user agent string identifying the
   * device/browser, session creation timestamp, most recent activity timestamp,
   * explicit termination timestamp (if logged out), and absolute timeout
   * timestamp (30-day maximum session duration).
   *
   * Authorization: Only the authenticated user who owns the session can
   * retrieve its details. Attempting to access another user's session returns a
   * 403 Forbidden error. The session ID must correspond to a session owned by
   * the authenticated user.
   *
   * Security Note: Response provides complete session information including
   * device context (IP address, user agent). User password hash, authentication
   * credentials, and sensitive user account information are not included in any
   * response.
   *
   * @param connection
   * @param sessionId Unique identifier of the target session to retrieve
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<ITodoListSession> {
    try {
      return await getTodoListUserAuthUserSessionsSessionId({
        user,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
