import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postTodoListUserTodos } from "../../../../providers/postTodoListUserTodos";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { patchTodoListUserTodos } from "../../../../providers/patchTodoListUserTodos";
import { getTodoListUserTodosTodoId } from "../../../../providers/getTodoListUserTodosTodoId";
import { putTodoListUserTodosTodoId } from "../../../../providers/putTodoListUserTodosTodoId";
import { deleteTodoListUserTodosTodoId } from "../../../../providers/deleteTodoListUserTodosTodoId";

import { ITodoListTodo } from "../../../../api/structures/ITodoListTodo";
import { IPageITodoListTodo } from "../../../../api/structures/IPageITodoListTodo";

@Controller("/todoList/user/todos")
export class TodolistUserTodosController {
  /**
   * Create a new todo in todo_list_todos for the authenticated user.
   *
   * Create a new todo item for the authenticated user.
   *
   * This operation allows a logged-in user to add a new personal todo. The
   * mandatory title field must be a non-blank string between 1 and 255
   * characters and will be trimmed of whitespace; if a description is supplied,
   * it can be up to 1000 characters after trimming. Ownership is enforced by
   * associating the todo with the user making the request, and all
   * system-managed fields (id, completed, timestamps) will be set
   * automatically.
   *
   * Security is provided by requiring authentication and storing the ownerId
   * based on the session. User input is validated for maximum lengths and
   * required fields. No cross-user access or multi-user features are
   * permitted—the operation strictly ensures that only the authenticated user's
   * todo items are created and accessible.
   *
   * All validation errors or unauthorized access attempts yield clear
   * business-level error messages with no technical details. Deletion, viewing,
   * or editing of todos outside of authenticated personal scope is never
   * possible via this endpoint.
   *
   * @param connection
   * @param body Data for creating a new todo, including required title (1-255
   *   chars) and optional description (up to 1000 chars, both trimmed).
   *   Ownership is assigned by the system.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoListTodo.ICreate,
  ): Promise<ITodoListTodo> {
    try {
      return await postTodoListUserTodos({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search, filter, and paginate the authenticated user's todo_list_todos
   * records.
   *
   * Retrieve a paginated, filterable list of todo items owned by the
   * authenticated user. This endpoint enforces strict user-level data
   * partitioning, ensuring that each user can only access their own tasks as
   * per the foreign key constraint to todo_list_users. Advanced filtering
   * includes support for searching on title, completion status, creation and
   * completion timestamps, and partial or case-insensitive text search where
   * appropriate.
   *
   * The operation is designed for high performance with user-specific queries
   * and supports business workflow requirements for quick viewing, filtering,
   * and management of personal tasks. All responses are scoped: users only ever
   * see their own data. Pagination and sort options on creation date and
   * completion status provide flexibility for user-facing clients, and the
   * response returns summary representations for optimal list rendering.
   *
   * Authorization is enforced at the application layer; the server only returns
   * rows for the authenticated user extracted from the session. No
   * administrator, moderator, or cross-user search is permitted. This operation
   * does not display soft-deleted results, as all deletions are permanent
   * according to strict business requirements.
   *
   * @param connection
   * @param body Criteria for searching and paginating a user's todo items,
   *   including filters for completion status, creation timestamps, and
   *   free-text search on title or description.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoListTodo.IRequest,
  ): Promise<IPageITodoListTodo.ISummary> {
    try {
      return await patchTodoListUserTodos({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Get a detailed todo_list_todos record by its ID for the authenticated user.
   *
   * Retrieve all detailed information for an individual todo managed by the
   * authenticated user. The operation is protected so that only the recorded
   * owner, matched on user_id, may access this resource; unauthorized access or
   * attempts to fetch non-existent/other-user todos return not found responses,
   * supporting both security and data privacy.
   *
   * This endpoint aligns request and resource identities using the permanent,
   * non-recycled UUID from the database. Details returned include the required
   * title, optional description, current completion status and timestamp, audit
   * fields such as created_at and updated_at, and user ownership context (never
   * exposing unrelated user records).
   *
   * Field validations, error handling, and access control are consistently
   * enforced following the core business requirements from both the
   * requirements document and strict Prisma schema constraints. No unrelated
   * user or system actors are permitted; only self-service for the
   * authenticated user identity is supported by this operation.
   *
   * @param connection
   * @param todoId Unique identifier UUID of the todo item to retrieve (must be
   *   owned by the requesting user).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":todoId")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
  ): Promise<ITodoListTodo> {
    try {
      return await getTodoListUserTodosTodoId({
        user,
        todoId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update a todo in todo_list_todos by UUID for the authenticated user.
   *
   * Update a todo item belonging to the authenticated user by UUID.
   *
   * This operation allows a user to edit their own todo's title, description,
   * and completed status. Title and description are validated using the same
   * rules as creation (trimmed, 1-255 for title, <=1000 for description).
   * Changing the completed flag sets or clears the completedAt field
   * automatically. Security and privacy are strictly maintained: only the
   * owning user may perform updates, and attempts to interact with others' data
   * are rejected.
   *
   * System-managed fields not applicable to client updates (such as id,
   * ownerId, createdAt) cannot be changed by the user. Error scenarios, such as
   * not-found or unauthorized access, return business-context error messages
   * only. All update logic is atomic, ensuring that partial changes never occur
   * under normal operation.
   *
   * @param connection
   * @param todoId Unique identifier of the target todo item to update. Must be
   *   a valid UUID owned by the authenticated user.
   * @param body Data to update the todo item. Supports changes to title (1-255
   *   chars), description (up to 1000 chars), and completed status.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":todoId")
  public async update(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoListTodo.IUpdate,
  ): Promise<ITodoListTodo> {
    try {
      return await putTodoListUserTodosTodoId({
        user,
        todoId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a specific todo item by its identifier from todo_list_todos.
   *
   * Permanently remove a todo item with the specified identifier from the
   * database.
   *
   * This API operation allows an authenticated user to delete a todo item from
   * their todo list. Once deleted, the item is fully removed from the system
   * and cannot be recovered. The operation validates that the todoId exists and
   * that the requester has permission to perform this action.
   *
   * Security checks are enforced to ensure users may only delete their own todo
   * items. The operation handles error situations such as missing or invalid
   * identifiers, or attempts to delete items the user does not own. This
   * endpoint does not accept a request body and relies solely on the identifier
   * specified in the path.
   *
   * This hard delete complements other CRUD functionality for todo items,
   * enabling users to maintain and curate their own lists. Subsequent list
   * queries will not return any deleted items.
   *
   * @param connection
   * @param todoId Unique identifier of the todo item to be deleted.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":todoId")
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoId")
    todoId: string,
  ): Promise<void> {
    try {
      return await deleteTodoListUserTodosTodoId({
        user,
        todoId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
