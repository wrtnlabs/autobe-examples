import { Controller, Ip } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthAdminJoin } from "../../../providers/postAuthAdminJoin";
import { postAuthAdminLogin } from "../../../providers/postAuthAdminLogin";
import { postAuthAdminRefresh } from "../../../providers/postAuthAdminRefresh";

import { ITodoAppAdmin } from "../../../api/structures/ITodoAppAdmin";

@Controller("/auth/admin")
export class AuthAdminController {
  /**
   * Register a new administrator account and issue JWT tokens for admin
   * authentication.
   *
   * Create a new administrator account and issue initial JWT tokens.
   *
   * This endpoint enables the creation of new administrator accounts in the
   * system. Administrators are users with elevated system-wide permissions to
   * manage system settings, view usage statistics, and handle user management
   * tasks. The registration process accepts email and password credentials,
   * validates them according to security requirements, and issues both access
   * and refresh JWT tokens upon successful account creation.
   *
   * Admin accounts are distinguished by their elevated permission level in the
   * system architecture. The registration endpoint is public and does not
   * require prior authentication, allowing authorized personnel to provision
   * new admin accounts during system setup or administrative expansion.
   *
   * The operation validates that the provided email is unique within the admin
   * user base, meets email format standards, and the password meets configured
   * security requirements for admin accounts. Upon successful validation and
   * account creation, the system issues a JWT access token for immediate
   * authentication and a refresh token for token renewal operations.
   *
   * This operation is essential for establishing initial administrative access
   * to the system and for provisioning additional administrators as needed
   * during system operation. It should be called during system initialization
   * to create the first admin account and subsequently whenever new
   * administrators need to be added to the system.
   *
   * @param connection
   * @param body Administrator account creation credentials including email and
   *   password.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoAppAdmin.ICreate,
  ): Promise<ITodoAppAdmin.IAuthorized> {
    try {
      return await postAuthAdminJoin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate an administrator using email and password credentials.
   *
   * Authenticate an administrator and issue JWT access and refresh tokens.
   *
   * This endpoint provides authentication for administrator accounts in the
   * system. Administrators require elevated permissions and system-wide access
   * to perform administrative functions including system configuration, user
   * management, and usage monitoring. The login operation accepts email and
   * password credentials from an admin user and validates them against the
   * stored admin account information.
   *
   * The endpoint performs credential validation by checking the provided email
   * against registered admin accounts and verifying the password matches the
   * stored credentials for that account. Upon successful credential validation,
   * the system issues a JWT access token with appropriate admin-level claims
   * and a refresh token that can be used for token renewal without requiring
   * credential re-submission.
   *
   * Authentication failures are handled securely without disclosing whether the
   * email exists in the system, preventing email enumeration attacks. The login
   * endpoint is public and does not require prior authentication, as it serves
   * as the entry point for admin users to obtain their authentication tokens.
   *
   * This operation is critical for enabling administrators to access the system
   * and perform their administrative duties. It should be called whenever an
   * admin user needs to establish an authenticated session.
   *
   * @param connection
   * @param body Administrator authentication credentials including email and
   *   password.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoAppAdmin.ICreate,
  ): Promise<ITodoAppAdmin.IAuthorized> {
    try {
      return await postAuthAdminLogin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh an administrator's access token using a valid refresh token.
   *
   * This endpoint enables administrators to obtain a new access token by
   * submitting their current refresh token. The refresh token is a long-lived
   * token issued during login or registration that can be used multiple times
   * to obtain fresh access tokens without requiring the admin to re-submit
   * their email and password credentials.
   *
   * The operation validates that the provided refresh token is valid, has not
   * expired, and is associated with an active admin account. Upon successful
   * validation, the system issues a new access token with appropriate
   * admin-level claims. The refresh token itself typically remains valid and
   * can be reused for subsequent refresh operations, though token rotation
   * policies may be applied depending on security configuration.
   *
   * Token refresh is essential for maintaining continuous admin access to the
   * system while limiting the exposure window of access tokens. Administrators
   * should call this endpoint when their current access token approaches
   * expiration to obtain a new token and maintain uninterrupted session
   * access.
   *
   * The endpoint is secured and requires a valid refresh token issued during a
   * previous login or registration operation. Failed refresh attempts (due to
   * expired or invalid tokens) will require the administrator to perform a new
   * login operation.
   *
   * @param connection
   * @param body Administrator refresh token request containing the valid
   *   refresh token.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: ITodoAppAdmin.IRefresh,
  ): Promise<ITodoAppAdmin.IAuthorized> {
    try {
      return await postAuthAdminRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
