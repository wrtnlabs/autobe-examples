import { Controller, Ip } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthGuestJoin } from "../../../providers/postAuthGuestJoin";
import { postAuthGuestRefresh } from "../../../providers/postAuthGuestRefresh";

import { ITodoListGuest } from "../../../api/structures/ITodoListGuest";

@Controller("/auth/guest")
export class AuthGuestController {
  /**
   * Register a new guest user account in the todo_list_users table.
   *
   * Creates a new guest user account in the todo_list_users table with email
   * and password credentials. This endpoint is publicly accessible and allows
   * unauthenticated users to register for temporary access to the Todo List
   * application.
   *
   * The email field must be unique across all users in the todo_list_users
   * table (enforced by unique constraint on email column). The password is
   * securely hashed using bcrypt (minimum cost factor 10) before storage in the
   * password_hash field, ensuring passwords are never stored in plaintext.
   *
   * Upon successful registration, the API generates initial JWT tokens (access
   * token and refresh token) for immediate use. A corresponding session record
   * is created in the todo_list_sessions table with the current IP address,
   * user agent, and session timing constraints (7-day inactivity timeout and
   * 30-day absolute maximum).
   *
   * Guest accounts are created with null deleted_at field, indicating an active
   * account. The created_at timestamp is set to the current UTC time and is
   * immutable. The updated_at field is also initialized to the creation
   * timestamp and tracks any subsequent modifications.
   *
   * Password requirements follow security best practices with bcrypt hashing
   * using cost factor 10 or higher. The email is normalized to lowercase for
   * consistent case-insensitive matching during authentication. No email
   * verification is required for guest accounts - they can use the application
   * immediately upon registration.
   *
   * This operation must be called before the guest can access any protected
   * todo operations. It is the entry point for new guest users entering the
   * system.
   *
   * @param connection
   * @param body Guest registration credentials including email and password.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoListGuest.ICreate,
  ): Promise<ITodoListGuest.IAuthorized> {
    try {
      return await postAuthGuestJoin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh expired JWT tokens for a guest user session in the
   * todo_list_sessions table.
   *
   * Renews JWT access tokens for a guest user by validating the provided
   * refresh token against the session and token management system. This
   * endpoint is publicly accessible for guests with valid refresh tokens
   * obtained from the join operation.
   *
   * The refresh operation validates that the refresh token exists and is still
   * valid (not expired). The underlying session in the todo_list_sessions table
   * is checked to ensure it remains active (expired_at is null, indicating
   * logout has not occurred) and has not exceeded the absolute timeout
   * threshold (absolute_timeout_at timestamp).
   *
   * The last_activity_at field in the corresponding todo_list_sessions record
   * is updated to the current timestamp to refresh the 7-day inactivity timeout
   * counter. If the session has been inactive beyond 7 days, the refresh
   * request is rejected and the guest must re-register.
   *
   * Upon successful refresh, new JWT tokens are generated and returned: a fresh
   * access token with standard expiration (typically 15 minutes) and a refresh
   * token for the next refresh cycle. The old access token becomes invalid and
   * should not be used for subsequent requests.
   *
   * If the refresh token is invalid, expired, or the associated session has
   * been terminated (expired_at is not null), the refresh fails and the guest
   * must call the join operation again to register a new account and obtain new
   * tokens.
   *
   * This operation maintains session continuity for active guests without
   * requiring them to re-authenticate. It is essential for keeping guest users
   * logged in across multiple API calls and browser sessions.
   *
   * @param connection
   * @param body Refresh token from previous authentication response.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: ITodoListGuest.IRefresh,
  ): Promise<ITodoListGuest.IAuthorized> {
    try {
      return await postAuthGuestRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
