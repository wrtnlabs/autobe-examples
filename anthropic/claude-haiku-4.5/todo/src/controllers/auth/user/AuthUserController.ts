import { Controller, Ip } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthUserJoin } from "../../../providers/postAuthUserJoin";
import { postAuthUserLogin } from "../../../providers/postAuthUserLogin";
import { postAuthUserRefresh } from "../../../providers/postAuthUserRefresh";
import { postAuthUserLogout } from "../../../providers/postAuthUserLogout";
import { UserAuth } from "../../../decorators/UserAuth";
import { UserPayload } from "../../../decorators/payload/UserPayload";

import { ITodoListUser } from "../../../api/structures/ITodoListUser";

@Controller("/auth/user")
export class AuthUserController {
  /**
   * Register a new user account in todo_list_users and issue tokens.
   *
   * Registers a new user in the system and issues authentication tokens. Tied
   * to todo_list_users table. Validates unique email and hashes password as per
   * schema.
   *
   * @param connection
   * @param body Registration credentials: email and password. Email must be
   *   unique. Password will be hashed as per security rules.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoListUser.IJoin,
  ): Promise<ITodoListUser.IAuthorized> {
    try {
      return await postAuthUserJoin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate user via email/password (todo_list_users); issue tokens and
   * log session to todo_list_user_sessions.
   *
   * Authenticates a user with email and password. On success, creates a new
   * session in todo_list_user_sessions and issues JWT tokens. References
   * todo_list_users for credential verification and session management.
   *
   * @param connection
   * @param body Login credentials: email and password of existing user, as
   *   persisted in todo_list_users.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoListUser.ILogin,
  ): Promise<ITodoListUser.IAuthorized> {
    try {
      return await postAuthUserLogin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh JWT tokens for a user session (todo_list_users,
   * todo_list_user_sessions).
   *
   * Refreshes a user's authentication tokens (access and refresh) using a valid
   * refresh token, as tracked in todo_list_users and todo_list_user_sessions.
   * Audits session per schema fields.
   *
   * @param connection
   * @param body Valid refresh token, provided per secure transport policy. No
   *   other parameters accepted.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: ITodoListUser.IRefresh,
  ): Promise<ITodoListUser.IAuthorized> {
    try {
      return await postAuthUserRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Logout current user and invalidate their session (todo_list_user_sessions).
   *
   * Logs out the authenticated user by invalidating their active session in
   * todo_list_user_sessions (expiry set), revoking all JWT tokens for this
   * session. Only affects the current user's session context.
   *
   * @param connection
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("logout")
  public async logout(
    @UserAuth()
    user: UserPayload,
  ): Promise<ITodoListUser.ILogout> {
    try {
      return await postAuthUserLogout({
        user,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
