import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthUserPasswordResetRequest } from "../../../../../providers/postAuthUserPasswordResetRequest";

import { ITodoListUser } from "../../../../../api/structures/ITodoListUser";

@Controller("/auth/user/password/reset-request")
export class AuthUserPasswordReset_requestController {
  /**
   * Initiate password reset flow by generating a time-limited reset token for
   * the todo_list_password_reset_tokens table.
   *
   * This endpoint initiates the password reset process when users forget their
   * password. The operation receives an email address and queries the
   * todo_list_users table to locate the corresponding user account. If a user
   * with the provided email exists and is active (deleted_at is null), a
   * password reset token is created in the todo_list_password_reset_tokens
   * table.
   *
   * The reset token is a cryptographically secure random value that cannot be
   * guessed or brute-forced. This token is generated using a secure random
   * number generator with sufficient entropy. The token is stored in the
   * todo_list_password_reset_tokens table with the todo_list_user_id foreign
   * key referencing the user requesting the reset. The token field is hashed
   * before storage to prevent token exposure if the database is compromised -
   * plaintext tokens are never persisted.
   *
   * Token expiration is enforced through the expires_at field, set to 1 hour
   * from creation (created_at + 1 hour). Tokens cannot be used for password
   * reset after this time; if the user's reset link expires, they must request
   * a new token. This time-limited enforcement prevents token reuse attacks
   * where old tokens could be exploited if leaked. The consumed_at field is
   * initialized to null, indicating the token has not yet been used for a
   * password reset.
   *
   * The reset token is sent to the user's registered email address in a
   * password reset link (e.g., /reset-password?token={token}). The email is
   * sent asynchronously so the API response is not delayed. Users click the
   * link, which delivers them to a frontend form where they can enter a new
   * password and submit it to the password reset confirmation endpoint.
   *
   * For security, if the provided email does not exist in the todo_list_users
   * table or the account is deleted (deleted_at is not null), the response
   * still indicates success ("Reset link sent if account exists"). This
   * prevents email enumeration attacks where attackers could discover which
   * email addresses are registered in the system. Only the legitimate email
   * recipient receives the actual reset link.
   *
   * Multiple reset tokens can be generated for the same user if they request
   * multiple resets; each token is independent and valid for 1 hour. When the
   * user later uses one token to reset their password (via the password reset
   * confirmation endpoint), that token is marked as consumed_at, preventing
   * reuse of the same token. Other unexpired tokens for the same user remain
   * valid until their individual expiration times. Related operations include
   * the password reset confirmation endpoint (POST
   * /auth/user/password/reset-confirm) for completing the reset with a token.
   *
   * @param connection
   * @param body Email address for requesting a password reset token
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async resetPasswordRequest(
    @TypedBody()
    body: ITodoListUser.IPasswordResetRequest,
  ): Promise<ITodoListUser.IPasswordResetRequestResponse> {
    try {
      return await postAuthUserPasswordResetRequest({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
