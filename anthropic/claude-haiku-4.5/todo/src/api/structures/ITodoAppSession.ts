import { tags } from "typia";

/**
 * User authentication session representing an active login connection. Records
 * when a user successfully authenticates and maintains session state across
 * multiple requests. Each session is associated with a specific user and tracks
 * connection metadata (IP address, entry point URL, referrer). Sessions expire
 * after 30 minutes of inactivity or explicit logout, requiring user to
 * re-authenticate.
 *
 * Session records are immutable after creation and used for security tracking,
 * audit trail purposes, and enabling multi-device concurrent sessions for the
 * same user.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type ITodoAppSession = {
  /**
   * Unique session identifier (UUID). System-generated primary key for this
   * session record. Used to reference and track the specific authenticated
   * session throughout its lifetime.
   */
  id: string & tags.Format<"uuid">;

  /**
   * Foreign key reference to the authenticated user (todo_app_users.id).
   * Establishes which user this session belongs to. Each session is
   * associated with exactly one user account. Multiple concurrent sessions
   * are allowed per user across different devices.
   */
  todo_app_user_id: string & tags.Format<"uuid">;

  /**
   * Client IP address from which this session was established. Captured when
   * user successfully authenticates. Used for security monitoring, tracking
   * login locations from different networks, and audit trail purposes.
   * Example: '192.168.1.100' or '2001:db8::1'.
   */
  ip: string;

  /**
   * Connection URL / request URL when this session was established. Captures
   * the entry point that initiated the session creation. Represents the
   * application URL or page where the user logged in.
   */
  href: string & tags.Format<"uri">;

  /**
   * Referrer URL indicating the previous page or application that led to this
   * session creation. Tracks the source of the user's navigation to the login
   * page. Used for understanding user journey and traffic sources.
   */
  referrer: string & tags.Format<"uri">;

  /**
   * Timestamp in UTC when the session was established after successful user
   * authentication. Automatically set by the system when user logs in.
   * Recorded in ISO 8601 format (YYYY-MM-DDTHH:MM:SSZ). Used for session age
   * tracking and timeout calculations.
   */
  created_at: string & tags.Format<"date-time">;

  /**
   * Timestamp in UTC when the session expires or was explicitly terminated by
   * user logout. NULL (null value) indicates the session is currently active
   * and not expired. When populated, indicates user must re-authenticate.
   * Sessions expire after 30 minutes of inactivity or explicit logout. Stored
   * in ISO 8601 format.
   */
  expired_at?: (string & tags.Format<"date-time">) | null | undefined;
};
