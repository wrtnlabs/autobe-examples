import { tags } from "typia";

/**
 * Request body for password reset operations with two distinct phases.
 *
 * Phase 1 - Password Reset Initiation: User provides their email address to
 * request a password reset. The system validates the email exists in the
 * todo_app_users table and sends a password reset token to the user's email
 * address. The email field is required for this phase.
 *
 * Phase 2 - Password Reset Completion: User provides the password reset token
 * received via email and a new password. The system validates the token is
 * valid and not expired, validates the new password meets security requirements
 * (minimum 8 characters), and updates the user's password_hash in the database.
 * Both reset_token and new_password fields are required for this phase.
 *
 * The password reset process enforces strict security: tokens are single-use
 * and expire after 1 hour, passwords must be different from the current
 * password, new passwords are hashed using bcrypt or Argon2 before storage, and
 * all existing user sessions are terminated after successful password change.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type ITodoAppAuthPasswordResetRequest = {
  /**
   * User's email address for password reset initiation. Must be a valid email
   * format (RFC 5322 standard) and exist as a registered account in the
   * todo_app_users table. Used to identify which user account needs password
   * reset and to send the password reset token via email. Required for Phase
   * 1 (password reset request initiation). Can be omitted for Phase 2
   * (password reset completion). Example: 'john@example.com'
   */
  email?: (string & tags.Format<"email">) | undefined;

  /**
   * Secure password reset token sent to user's email address. Generated by
   * the system using cryptographically secure random data and valid for
   * exactly 1 hour from generation. Must be submitted along with new_password
   * to complete the password reset process. Required for Phase 2 (password
   * reset completion). Can be omitted for Phase 1 (password reset request
   * initiation). If token is expired or invalid, the system rejects the
   * request with error code 'PASSWORD_RESET_TOKEN_EXPIRED' or
   * 'PASSWORD_RESET_INVALID_TOKEN'.
   */
  reset_token?: string | undefined;

  /**
   * New password for the user account. Must be at least 8 characters long and
   * at most 256 characters. Will be hashed using bcrypt or Argon2 with unique
   * salt before storage in the password_hash field of todo_app_users table.
   * Must be different from the current password (system rejects if new
   * password matches previous password). Required for Phase 2 (password reset
   * completion). Can be omitted for Phase 1 (password reset request
   * initiation). The password is hashed server-side; client must send
   * plaintext password which the backend hashes before database storage.
   */
  new_password?: (string & tags.MinLength<8> & tags.MaxLength<256>) | undefined;

  /**
   * Password confirmation field to verify user typed new_password correctly.
   * Must match new_password exactly (character-for-character comparison).
   * Used for Phase 2 (password reset completion) to prevent typos in password
   * entry. Can be omitted for Phase 1 (password reset request initiation). If
   * confirm_password does not match new_password, system displays error
   * 'PASSWORD_MISMATCH' with message 'Passwords do not match. Please re-enter
   * your password.'
   */
  confirm_password?:
    | (string & tags.MinLength<8> & tags.MaxLength<256>)
    | undefined;
};
