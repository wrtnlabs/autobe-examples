/**
 * Represents a user account in the Todo application. This entity contains the
 * user's authentication credentials, account status, and temporal audit
 * information. Users are the primary actors in the system who authenticate and
 * manage their own todo lists. Each user has a unique email address for
 * authentication, a securely hashed password, account status tracking, and
 * timestamps recording account creation, modification, and soft deletion
 * events.
 *
 * Users form one-to-many relationships with todos (one user can have many
 * todos) and sessions (one user can have many active sessions). The user entity
 * is central to data isolation - all todos are owned exclusively by one user
 * and access is strictly enforced through user ID verification.
 *
 * Account status determines whether the user can currently access the system:
 * 'active' allows normal login and use, 'inactive' prevents login but preserves
 * account data. The deleted_at timestamp implements soft delete functionality
 * where deleted accounts are marked but preserved for audit trail purposes.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type ITodoAppUser = {
  /**
   * Unique identifier for the user account. This UUID is automatically
   * generated by the system when the user registers and serves as the primary
   * key for identifying this user throughout the application. The ID is
   * immutable after creation and is used in all references to this user from
   * other entities like todos and sessions. The ID establishes ownership
   * relationships - todos reference the user ID to indicate which user owns
   * them.
   */
  id: string & tags.Format<"uuid">;

  /**
   * User's email address serving as the unique authentication identifier.
   * This email must be unique across all user accounts in the system - no two
   * users can register with the same email address. The email is used as the
   * login identifier when users authenticate. Email addresses must follow RFC
   * 5322 standard email format (e.g., user@example.com). Email addresses are
   * normalized to lowercase for storage and comparison purposes to prevent
   * duplicate registrations of the same email with different cases.
   */
  email: string & tags.Format<"email">;

  /**
   * Current account status indicating whether the user can access the system.
   * Valid values are 'active' (user can log in and use the application) and
   * 'inactive' (user cannot log in but account data is preserved). Accounts
   * default to 'active' when first created. Admins can change user status to
   * suspend access without deleting account data. When status is 'inactive',
   * all login attempts are rejected with appropriate error message.
   */
  status: "active" | "inactive";

  /**
   * Timestamp in UTC when the user account was created and registered. This
   * timestamp is automatically generated by the system during account
   * creation and is immutable - it never changes after initial creation
   * regardless of subsequent account modifications. Created_at provides a
   * historical record of when the user first joined the system and is used
   * for sorting users by registration date or identifying new users.
   */
  created_at: string & tags.Format<"date-time">;

  /**
   * Timestamp in UTC of the most recent modification to any user account
   * field. This timestamp is automatically updated by the system whenever any
   * property of the user account is changed (email update, status change,
   * etc.). Updated_at is distinct from created_at and enables tracking of
   * account activity and modifications. The timestamp reflects the time of
   * the most recent change, allowing identification of recently modified
   * accounts.
   */
  updated_at: string & tags.Format<"date-time">;

  /**
   * Timestamp in UTC indicating soft deletion of the user account. When NULL
   * (empty), the account is active and accessible. When populated with a
   * timestamp, the account is marked as deleted but data is preserved in the
   * database for audit trail, compliance, and potential recovery purposes.
   * Soft-deleted users cannot log in and their account appears as deleted to
   * admins, but all associated data and history remains in the system. Hard
   * deletion of user data may occur after a retention period (typically 30
   * days) following the soft delete timestamp.
   */
  deleted_at?: (string & tags.Format<"date-time">) | null | undefined;
};
