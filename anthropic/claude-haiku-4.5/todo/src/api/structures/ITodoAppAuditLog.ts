/**
 * Immutable audit trail record documenting a single administrative action
 * performed by an admin user.
 *
 * Each audit log entry captures what admin performed what action, on what
 * resource, when, and from where. This entity implements the audit logging
 * requirements from 07-admin-features.md section 5.2.
 *
 * The audit trail is append-only - entries are never modified or deleted after
 * creation. Used for security monitoring, compliance reporting, investigating
 * security incidents, and tracking admin accountability. Every administrative
 * operation that affects user accounts or system state generates an audit log
 * entry.
 *
 * Audit logs are essential for compliance, enabling forensic analysis of
 * security incidents, and maintaining accountability for all administrative
 * actions. Access to audit logs is restricted to authorized administrators
 * only.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type ITodoAppAuditLog = {
  /**
   * Unique identifier for the audit log entry. System-generated UUID that
   * uniquely identifies this administrative action record within the system.
   */
  id: string & tags.Format<"uuid">;

  /**
   * Admin user ID who performed the action. Foreign key reference to
   * todo_app_admins.id. Identifies which administrator is responsible for
   * this audit log entry.
   */
  todo_app_admin_id: string & tags.Format<"uuid">;

  /**
   * User ID affected by the admin action (if applicable). Foreign key
   * reference to todo_app_users.id. NULL if the action does not target a
   * specific user (e.g., system configuration changes). Example: User ID of a
   * deleted user account.
   */
  target_user_id?: (string & tags.Format<"uuid">) | null | undefined;

  /**
   * Type of administrative action performed. Examples: 'user_created',
   * 'user_deleted', 'user_status_changed', 'password_reset',
   * 'config_updated', 'backup_initiated'. Enables filtering audit logs by
   * action category for compliance and security reviews.
   */
  action_type: string;

  /**
   * Detailed description of the action performed. Captures contextual
   * information about what the admin did and why. Example: 'User account
   * suspended due to security violation' or 'System configuration updated:
   * session timeout changed from 30 to 15 minutes'. Provides narrative
   * context for the audit entry.
   */
  description: string;

  /**
   * Previous value of the modified field (for update actions). Captured
   * before the change was applied. NULL for create or delete actions. Enables
   * tracking exactly what changed during the administrative operation.
   */
  before_value?: string | null | undefined;

  /**
   * New value of the modified field (for update actions). Captured after the
   * change was applied. NULL for delete actions. Enables tracking the new
   * state after admin action for change management.
   */
  after_value?: string | null | undefined;

  /**
   * IP address from which the admin performed the action. Used for tracking
   * admin activity location and detecting suspicious access patterns.
   * Example: '192.168.1.100' or '2001:db8::1'.
   */
  ip_address: string;

  /**
   * System-generated timestamp in UTC when the action was performed.
   * Automatically set by system when audit log entry is created. Stored in
   * ISO 8601 format. Establishes chronological timeline of administrative
   * actions for compliance and security review.
   */
  created_at: string & tags.Format<"date-time">;
};
