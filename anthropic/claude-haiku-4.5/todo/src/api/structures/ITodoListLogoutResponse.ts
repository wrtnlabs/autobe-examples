import { tags } from "typia";

/**
 * Response confirming successful logout operation.
 *
 * Returned by both single-device logout (POST /auth/user/logout) and global
 * logout (POST /auth/user/logout-all-devices) operations. The response confirms
 * that the user's session(s) have been terminated and token(s) have been
 * invalidated.
 *
 * For single-device logout, only the current session is affected. For global
 * logout, all sessions across all devices are terminated. In both cases, the
 * affected tokens are added to the todo_list_token_blacklist and become
 * unusable for any further API requests.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type ITodoListLogoutResponse = {
  /**
   * Indicates successful logout completion.
   *
   * Will always be true in a success response. If logout fails, an error
   * response is returned instead.
   */
  success: boolean;

  /**
   * Human-readable confirmation message.
   *
   * For single-device logout: 'You have been logged out from this device.'
   * For global logout: 'You have been logged out from all devices. Please log
   * in again.'
   *
   * Informs the user of the logout scope and next steps.
   */
  message: string;

  /**
   * Number of sessions that were terminated.
   *
   * For single-device logout, this is always 1 (the current session). For
   * global logout, this is the total number of active sessions the user had
   * before logout.
   *
   * Used to inform users how many devices were affected by the logout
   * operation.
   */
  sessions_affected: number & tags.Type<"int32">;

  /**
   * Timestamp when logout was completed.
   *
   * Recorded in UTC timezone, ISO 8601 format (e.g.,
   * 2025-11-18T09:03:30.084Z). Indicates when the session termination and
   * token invalidation took effect. Corresponds to when the
   * todo_list_sessions.expired_at field was set for the affected sessions.
   */
  logout_completed_at: string & tags.Format<"date-time">;
};
