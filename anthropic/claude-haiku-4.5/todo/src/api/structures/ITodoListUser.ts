/**
 * Complete user profile information for authenticated users.
 *
 * Represents the full account details of a user in the Todo List application.
 * Contains identification information, contact details, authentication
 * timestamps, and account lifecycle status. This type is used for profile
 * retrieval and display operations where complete user information is
 * required.
 *
 * The password_hash field is intentionally excluded from this response type for
 * security reasons - passwords are never exposed through the API, even in
 * hashed form. All timestamp fields are recorded in UTC timezone using ISO 8601
 * format for consistency and interoperability.
 *
 * The deleted_at field provides soft-delete support for audit trail
 * preservation. When null, the account is active; when non-null, the account
 * has been deleted but data is retained for historical purposes. The
 * last_login_at field may be null for newly created accounts that have not yet
 * logged in.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type ITodoListUser = {
  /**
   * Unique identifier for the user account. Immutable primary key generated
   * as UUID v4 at account creation.
   */
  id: string & tags.Format<"uuid">;

  /**
   * User's email address used for login and account recovery. Stored in
   * lowercase for case-insensitive matching. Must be unique across all users
   * to prevent duplicate accounts.
   */
  email: string & tags.Format<"email">;

  /**
   * Timestamp when user account was created. Immutable field recorded in UTC
   * timezone, ISO 8601 format. Represents the account creation moment.
   */
  created_at: string & tags.Format<"date-time">;

  /**
   * Timestamp of the most recent account modification. System-managed field
   * updated in UTC timezone whenever account information changes. Recorded in
   * ISO 8601 format.
   */
  updated_at: string & tags.Format<"date-time">;

  /**
   * Timestamp indicating soft deletion status of the account. Null value
   * means account is active. When set to non-null timestamp (UTC, ISO 8601
   * format), user cannot log in and associated sessions should be
   * invalidated. Used for audit trail preservation.
   */
  deleted_at: (string & tags.Format<"date-time">) | null;

  /**
   * Timestamp of user's most recent successful login. Updated automatically
   * each time user authenticates successfully. Null value indicates user has
   * never logged in. Recorded in UTC timezone, ISO 8601 format. Used for
   * tracking user activity and session management.
   */
  last_login_at: (string & tags.Format<"date-time">) | null;
};
