/**
 * Session record for a user login in the minimal Todo List application.
 *
 * Represents a single point-in-time authenticated session for a specific user.
 * Each session is established during successful login and includes audit
 * metadata such as IP address, referrer, session creation and expiration times.
 * Users may have multiple concurrent sessions for multi-device access, and
 * session termination (logout or expiration) is modeled via the 'expired_at'
 * field.
 *
 * This schema contains only publicly auditable session data (no tokens or
 * sensitive authentication fields) and follows strict privacy and access
 * control rules, allowing users to review their own session records for
 * transparency. All fields mirror those in the underlying Prisma model.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type ITodoListUserSession = {
  /**
   * Unique session identifier (UUID). Serves as the primary key and
   * correlates to a single login event. Used for session lookups, auditing,
   * and invalidation.
   */
  id: string & tags.Format<"uuid">;

  /**
   * IP address of the device from which the session originated. This value is
   * recorded for each session and is used for audit, analytics, and
   * suspicious login detection.
   */
  ip: string;

  /**
   * Full URL at which the session was established. Captured at login time to
   * provide an audit trail and for debugging session issues.
   */
  href: string;

  /**
   * Referrer URL indicating the page from where login occurred or the
   * preceding navigation step. Used for analytics and session source
   * tracking.
   */
  referrer: string;

  /** Timestamp when the session was created (ISO 8601 format). */
  created_at: string & tags.Format<"date-time">;

  /**
   * Timestamp when the session expired or was invalidated (ISO 8601). May be
   * null if session is still active.
   */
  expired_at?: (string & tags.Format<"date-time">) | null | undefined;
};
