/**
 * Get the complete profile of the currently authenticated user. This operation
 * returns all available user account information including email address,
 * account creation and update timestamps, and last login history.
 *
 * The authenticated user's identity is automatically extracted from the JWT
 * bearer token in the authorization header. Only the authenticated user can
 * access their own profile - there is no ability to view other users' profiles
 * through this endpoint. The user's account must be active (not soft-deleted)
 * to access this endpoint.
 *
 * Returned information includes email (stored in lowercase), account creation
 * timestamp (UTC, ISO 8601 format), most recent account update timestamp, and
 * the user's last successful login timestamp. The deleted_at field will be null
 * for active accounts, confirming the account has not been soft-deleted. The
 * password_hash field is never included in responses for security reasons.
 *
 * This operation supports the user's ability to verify their current account
 * information and access profile data for display in user interface settings
 * pages. It is typically called after successful authentication to populate
 * user dashboard or profile screens.
 *
 * @param props.connection
 * @path /todoList/user/auth/user/profile
 * @accessor api.functional.todoList.user.auth.user.profile.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(connection: IConnection): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(),
          status: null,
        },
      );
}
export namespace at {
  export type Response = ITodoListUser;

  export const METADATA = {
    method: "GET",
    path: "/todoList/user/auth/user/profile",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/todoList/user/auth/user/profile";
  export const random = (): ITodoListUser => typia.random<ITodoListUser>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}

/**
 * Update the profile information of the currently authenticated user. This
 * operation allows users to modify their account details such as email address
 * while maintaining account security and data integrity.
 *
 * The authenticated user's identity is extracted from the JWT bearer token,
 * ensuring that users can only modify their own profile and not other users'
 * accounts. The user's account must be active (not soft-deleted) to perform
 * updates. The request body contains the updated profile information that
 * should be applied to the user's account.
 *
 * Email address updates must maintain the unique constraint - a new email
 * cannot be the same as any existing user's email in the system. The system
 * will automatically update the updated_at timestamp to reflect when this
 * modification occurred. Password changes are not handled through this endpoint
 * and must use a dedicated password change operation. System-managed fields
 * such as created_at, deleted_at, and last_login_at cannot be modified through
 * this endpoint.
 *
 * Upon successful update, the operation returns the complete updated user
 * profile with all current account information. This allows the client to
 * immediately reflect the changes in the user interface without requiring a
 * separate profile fetch operation. The password_hash field is excluded from
 * the response for security reasons.
 *
 * @param props.connection
 * @param props.body Updated profile information for the authenticated user
 *   (only updatable fields)
 * @path /todoList/user/auth/user/profile
 * @accessor api.functional.todoList.user.auth.user.profile.update
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function update(
  connection: IConnection,
  props: update.Props,
): Promise<update.Response> {
  return true === connection.simulate
    ? update.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...update.METADATA,
          path: update.path(),
          status: null,
        },
        props.body,
      );
}
export namespace update {
  export type Props = {
    /**
     * Updated profile information for the authenticated user (only
     * updatable fields)
     */
    body: ITodoListUser.IUpdate;
  };
  export type Body = ITodoListUser.IUpdate;
  export type Response = ITodoListUser;

  export const METADATA = {
    method: "PUT",
    path: "/todoList/user/auth/user/profile",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/todoList/user/auth/user/profile";
  export const random = (): ITodoListUser => typia.random<ITodoListUser>();
  export const simulate = (
    connection: IConnection,
    props: update.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: update.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
