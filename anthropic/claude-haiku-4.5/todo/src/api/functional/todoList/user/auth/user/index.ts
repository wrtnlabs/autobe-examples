/**
 * Log out current user from the current device.
 *
 * Terminate the current user's authenticated session and invalidate the JWT
 * token used for this request.
 *
 * This operation invalidates the session associated with the current device by
 * marking it as expired in the todo_list_sessions table. The JWT token
 * (identified by the jti claim) is added to the todo_list_token_blacklist with
 * revocation reason 'logout' to prevent token reuse. The operation requires an
 * authenticated user - the session and user information are extracted from the
 * JWT token provided in the Authorization header.
 *
 * Security: Only authenticated users can logout. The revocation is tied to the
 * specific token/session being used, allowing users to maintain other active
 * sessions on different devices. This supports the multi-device login
 * requirement where a user can logout from one device while remaining logged in
 * on others.
 *
 * After successful logout, the invalidated token cannot be used for any further
 * authenticated requests. The session record is marked with an expired_at
 * timestamp, and the token becomes unusable immediately. This operation should
 * be called as part of the user logout flow before the client discards the
 * token.
 *
 * @param props.connection
 * @path /todoList/user/auth/user/logout
 * @accessor api.functional.todoList.user.auth.user.logout
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function logout(
  connection: IConnection,
): Promise<logout.Response> {
  return true === connection.simulate
    ? logout.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...logout.METADATA,
          path: logout.path(),
          status: null,
        },
      );
}
export namespace logout {
  export type Response = ITodoListLogoutResponse;

  export const METADATA = {
    method: "POST",
    path: "/todoList/user/auth/user/logout",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/todoList/user/auth/user/logout";
  export const random = (): ITodoListLogoutResponse =>
    typia.random<ITodoListLogoutResponse>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}
