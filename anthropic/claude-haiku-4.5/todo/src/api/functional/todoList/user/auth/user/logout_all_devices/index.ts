/**
 * Log out current user from all devices.
 *
 * Terminate all of the current user's active sessions across all devices and
 * invalidate all associated JWT tokens.
 *
 * This operation invalidates all sessions associated with the authenticated
 * user by marking all their session records in the todo_list_sessions table as
 * expired. All active JWT tokens (identified by their jti claims) are added to
 * the todo_list_token_blacklist with revocation reason 'global_logout' to
 * prevent any further use. This is a global logout that affects every device
 * the user is currently logged in from.
 *
 * Security: Only authenticated users can initiate a global logout. This
 * operation is particularly important for security scenarios such as password
 * changes, suspected account compromise, or when a user wants to ensure no
 * other devices have access to their account. The user must be authenticated to
 * perform this operation, typically as a follow-up action after changing their
 * password.
 *
 * After successful global logout, all active sessions are terminated and all
 * tokens become unusable. Subsequent requests from any device using previously
 * valid tokens will be rejected. Users must re-authenticate (login) to regain
 * access from any device.
 *
 * @param props.connection
 * @path /todoList/user/auth/user/logout-all-devices
 * @accessor api.functional.todoList.user.auth.user.logout_all_devices.logoutAllDevices
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function logoutAllDevices(
  connection: IConnection,
): Promise<logoutAllDevices.Response> {
  return true === connection.simulate
    ? logoutAllDevices.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...logoutAllDevices.METADATA,
          path: logoutAllDevices.path(),
          status: null,
        },
      );
}
export namespace logoutAllDevices {
  export type Response = ITodoListLogoutResponse;

  export const METADATA = {
    method: "POST",
    path: "/todoList/user/auth/user/logout-all-devices",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/todoList/user/auth/user/logout-all-devices";
  export const random = (): ITodoListLogoutResponse =>
    typia.random<ITodoListLogoutResponse>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}
