import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ITodoListUser } from "../../../../../structures/ITodoListUser";

/**
 * This endpoint initiates the password reset process when users forget their
 * password. The operation receives an email address and queries the
 * todo_list_users table to locate the corresponding user account. If a user
 * with the provided email exists and is active (deleted_at is null), a password
 * reset token is created in the todo_list_password_reset_tokens table.
 *
 * The reset token is a cryptographically secure random value that cannot be
 * guessed or brute-forced. This token is generated using a secure random number
 * generator with sufficient entropy. The token is stored in the
 * todo_list_password_reset_tokens table with the todo_list_user_id foreign key
 * referencing the user requesting the reset. The token field is hashed before
 * storage to prevent token exposure if the database is compromised - plaintext
 * tokens are never persisted.
 *
 * Token expiration is enforced through the expires_at field, set to 1 hour from
 * creation (created_at + 1 hour). Tokens cannot be used for password reset
 * after this time; if the user's reset link expires, they must request a new
 * token. This time-limited enforcement prevents token reuse attacks where old
 * tokens could be exploited if leaked. The consumed_at field is initialized to
 * null, indicating the token has not yet been used for a password reset.
 *
 * The reset token is sent to the user's registered email address in a password
 * reset link (e.g., /reset-password?token={token}). The email is sent
 * asynchronously so the API response is not delayed. Users click the link,
 * which delivers them to a frontend form where they can enter a new password
 * and submit it to the password reset confirmation endpoint.
 *
 * For security, if the provided email does not exist in the todo_list_users
 * table or the account is deleted (deleted_at is not null), the response still
 * indicates success ("Reset link sent if account exists"). This prevents email
 * enumeration attacks where attackers could discover which email addresses are
 * registered in the system. Only the legitimate email recipient receives the
 * actual reset link.
 *
 * Multiple reset tokens can be generated for the same user if they request
 * multiple resets; each token is independent and valid for 1 hour. When the
 * user later uses one token to reset their password (via the password reset
 * confirmation endpoint), that token is marked as consumed_at, preventing reuse
 * of the same token. Other unexpired tokens for the same user remain valid
 * until their individual expiration times. Related operations include the
 * password reset confirmation endpoint (POST /auth/user/password/reset-confirm)
 * for completing the reset with a token.
 *
 * @param props.connection
 * @param props.body Email address for requesting a password reset token
 * @path /auth/user/password/reset-request
 * @accessor api.functional.auth.user.password.reset_request.resetPasswordRequest
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function resetPasswordRequest(
  connection: IConnection,
  props: resetPasswordRequest.Props,
): Promise<resetPasswordRequest.Response> {
  return true === connection.simulate
    ? resetPasswordRequest.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...resetPasswordRequest.METADATA,
          path: resetPasswordRequest.path(),
          status: null,
        },
        props.body,
      );
}
export namespace resetPasswordRequest {
  export type Props = {
    /** Email address for requesting a password reset token */
    body: ITodoListUser.IPasswordResetRequest;
  };
  export type Body = ITodoListUser.IPasswordResetRequest;
  export type Response = ITodoListUser.IPasswordResetRequestResponse;

  export const METADATA = {
    method: "POST",
    path: "/auth/user/password/reset-request",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/user/password/reset-request";
  export const random = (): ITodoListUser.IPasswordResetRequestResponse =>
    typia.random<ITodoListUser.IPasswordResetRequestResponse>();
  export const simulate = (
    connection: IConnection,
    props: resetPasswordRequest.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: resetPasswordRequest.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
