/**
 * Complete password reset by validating token and updating password_hash in the
 * todo_list_users table.
 *
 * This endpoint completes the password reset process when users have received
 * and used their password reset link. The operation receives a reset token and
 * new password, then validates the token against the
 * todo_list_password_reset_tokens table to ensure it is legitimate and can be
 * used.
 *
 * Token validation includes: (1) querying the todo_list_password_reset_tokens
 * table with the provided token to locate the reset request record, (2)
 * verifying the token has not expired by checking that created_at + 1 hour
 * (expires_at field) is greater than current time, (3) ensuring the token has
 * not already been used by checking that consumed_at is null (if consumed_at
 * has a value, the token was already used and cannot be reused for security),
 * and (4) confirming the associated user account exists and is active in the
 * todo_list_users table (deleted_at is null).
 *
 * If token validation fails for any reason (invalid/not found, expired, already
 * consumed, or user deleted), the reset is rejected with an error response.
 * This prevents attackers from using leaked or old tokens to reset passwords of
 * other users.
 *
 * Once the token is validated, the user's password is updated. The new password
 * is validated for complexity requirements (minimum length, character variety
 * per security policy), then securely hashed using bcrypt (minimum cost factor
 * 10) and stored in the password_hash field of the todo_list_users table. The
 * plaintext password is never stored or logged. The updated_at field is set to
 * current UTC time, recording when this password change occurred.
 *
 * After the password is successfully updated, the reset token is marked as
 * consumed by setting the consumed_at field to the current UTC timestamp. This
 * single-use enforcement prevents the same token from being used again to reset
 * the password multiple times. The token record remains in the database for
 * audit trail purposes.
 *
 * As a security best practice, all existing sessions and tokens for this user
 * are invalidated upon password reset. All active sessions in the
 * todo_list_sessions table for this user are marked as expired (expired_at is
 * set to current time). All tokens that were issued before the password change
 * are added to the todo_list_token_blacklist table with revocation_reason set
 * to 'password_change', ensuring old tokens cannot be used for API requests or
 * token refresh. This forces the user to log in again with their new password,
 * preventing unauthorized access if a token was previously compromised.
 *
 * The endpoint returns a success response but does not issue new tokens; the
 * user must log in with their new password via the login endpoint to obtain
 * fresh credentials. This ensures the user has successfully proven they own the
 * account (by validating they received the email) and have set a new password.
 * Related operations include the password reset request endpoint (POST
 * /auth/user/password/reset-request) for initiating the reset flow and the
 * login endpoint (POST /auth/user/login) for re-authenticating with the new
 * password.
 *
 * @param props.connection
 * @param props.body Reset token and new password for completing password reset
 * @path /auth/user/password/reset-confirm
 * @accessor api.functional.auth.user.password.reset_confirm.resetPasswordConfirm
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function resetPasswordConfirm(
  connection: IConnection,
  props: resetPasswordConfirm.Props,
): Promise<resetPasswordConfirm.Response> {
  return true === connection.simulate
    ? resetPasswordConfirm.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...resetPasswordConfirm.METADATA,
          path: resetPasswordConfirm.path(),
          status: null,
        },
        props.body,
      );
}
