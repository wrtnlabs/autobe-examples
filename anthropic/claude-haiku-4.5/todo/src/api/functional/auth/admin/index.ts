/**
 * Authenticate admin user with email and password credentials to obtain JWT
 * access token.
 *
 * Admin login operation enables system administrators to authenticate with
 * email and password. WHEN an admin submits credentials, THE system SHALL
 * validate the email exists in the todo_app_admins table, verify the
 * password_hash matches using secure comparison, and upon successful
 * authentication create an admin session with enhanced security constraints
 * (15-minute inactivity timeout). THE system SHALL issue a JWT access token
 * containing admin role claim and permissions array. THE JWT token SHALL expire
 * after 30 minutes of issuance.
 *
 * Admin authentication differs from regular user authentication through
 * enhanced security measures: admin sessions expire after 15 minutes of
 * inactivity (compared to 30 minutes for users), all admin actions are logged
 * in the todo_app_audit_logs immutable audit trail with action_type,
 * description, before_value, after_value, and ip_address fields for
 * accountability and compliance. Admin login attempts are monitored for
 * security threats - after 5 failed login attempts within 15 minutes, the admin
 * account is temporarily locked for 30 minutes.
 *
 * IF admin credentials are invalid, THEN THE system SHALL deny access and
 * return error code AUTH_INVALID_CREDENTIALS without revealing whether email
 * exists or password was incorrect. IF admin account status is not 'active',
 * THEN THE system SHALL deny login and return error code AUTH_ACCOUNT_INACTIVE.
 * IF admin session already exists from another location, THE system SHALL allow
 * the login (concurrent admin sessions permitted) but optionally log the
 * unusual access pattern.
 *
 * Successful admin authentication triggers creation of todo_app_admin_sessions
 * record capturing ip, href, referrer, created_at timestamp, and expired_at
 * initially NULL. Admin can access all system features including user
 * management (view todo_app_users list, change user status, delete user
 * accounts and associated todos via cascade), system statistics, audit logs,
 * backup and recovery operations, and administrative configuration.
 *
 * @param props.connection
 * @param props.body Admin login credentials
 * @setHeader token.access Authorization
 *
 * @path /auth/admin/login
 * @accessor api.functional.auth.admin.login
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function login(
  connection: IConnection,
  props: login.Props,
): Promise<login.Response> {
  const output: login.Response =
    true === connection.simulate
      ? login.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...login.METADATA,
            path: login.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
export namespace login {
  export type Props = {
    /** Admin login credentials */
    body: ITodoAppAdmin.ILogin;
  };
  export type Body = ITodoAppAdmin.ILogin;
  export type Response = ITodoAppAdmin.IAuthorized;

  export const METADATA = {
    method: "POST",
    path: "/auth/admin/login",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/admin/login";
  export const random = (): ITodoAppAdmin.IAuthorized =>
    typia.random<ITodoAppAdmin.IAuthorized>();
  export const simulate = (
    connection: IConnection,
    props: login.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: login.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

