/**
 * Register a new administrator account and issue JWT tokens for admin
 * authentication.
 *
 * Create a new administrator account and issue initial JWT tokens.
 *
 * This endpoint enables the creation of new administrator accounts in the
 * system. Administrators are users with elevated system-wide permissions to
 * manage system settings, view usage statistics, and handle user management
 * tasks. The registration process accepts email and password credentials,
 * validates them according to security requirements, and issues both access and
 * refresh JWT tokens upon successful account creation.
 *
 * Admin accounts are distinguished by their elevated permission level in the
 * system architecture. The registration endpoint is public and does not require
 * prior authentication, allowing authorized personnel to provision new admin
 * accounts during system setup or administrative expansion.
 *
 * The operation validates that the provided email is unique within the admin
 * user base, meets email format standards, and the password meets configured
 * security requirements for admin accounts. Upon successful validation and
 * account creation, the system issues a JWT access token for immediate
 * authentication and a refresh token for token renewal operations.
 *
 * This operation is essential for establishing initial administrative access to
 * the system and for provisioning additional administrators as needed during
 * system operation. It should be called during system initialization to create
 * the first admin account and subsequently whenever new administrators need to
 * be added to the system.
 *
 * @param props.connection
 * @param props.body Administrator account creation credentials including email
 *   and password.
 * @setHeader token.access Authorization
 *
 * @path /auth/admin/join
 * @accessor api.functional.auth.admin.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
