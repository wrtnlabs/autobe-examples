/**
 * Creates a new guest user account in the todo_list_users table with email and
 * password credentials. This endpoint is publicly accessible and allows
 * unauthenticated users to register for temporary access to the Todo List
 * application.
 *
 * The email field must be unique across all users in the todo_list_users table
 * (enforced by unique constraint on email column). The password is securely
 * hashed using bcrypt (minimum cost factor 10) before storage in the
 * password_hash field, ensuring passwords are never stored in plaintext.
 *
 * Upon successful registration, the API generates initial JWT tokens (access
 * token and refresh token) for immediate use. A corresponding session record is
 * created in the todo_list_sessions table with the current IP address, user
 * agent, and session timing constraints (7-day inactivity timeout and 30-day
 * absolute maximum).
 *
 * Guest accounts are created with null deleted_at field, indicating an active
 * account. The created_at timestamp is set to the current UTC time and is
 * immutable. The updated_at field is also initialized to the creation timestamp
 * and tracks any subsequent modifications.
 *
 * Password requirements follow security best practices with bcrypt hashing
 * using cost factor 10 or higher. The email is normalized to lowercase for
 * consistent case-insensitive matching during authentication. No email
 * verification is required for guest accounts - they can use the application
 * immediately upon registration.
 *
 * This operation must be called before the guest can access any protected todo
 * operations. It is the entry point for new guest users entering the system.
 *
 * @param props.connection
 * @param props.body Guest registration credentials including email and
 *   password.
 * @setHeader token.access Authorization
 *
 * @path /auth/guest/join
 * @accessor api.functional.auth.guest.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
