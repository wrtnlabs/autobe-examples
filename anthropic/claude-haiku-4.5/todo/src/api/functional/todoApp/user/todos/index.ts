/**
 * Create a new todo item with title and optional details.
 *
 * Creates a new todo item for the authenticated user. The user provides a
 * required title (maximum 255 characters) that describes what needs to be done,
 * and may optionally provide a detailed description (maximum 2000 characters),
 * priority level (low/medium/high), and future due date (ISO 8601 format,
 * cannot be in past). The system validates all input fields according to
 * business rules specified in 06-business-rules.md.
 *
 * The system automatically assigns the todo to the authenticated user
 * exclusively, ensuring data isolation. Only the owner of the todo can view,
 * modify, or delete it. The system generates a unique identifier, sets the
 * initial status to 'active' (incomplete), records the creation timestamp, and
 * initializes the modification timestamp to match creation time.
 *
 * After successful creation, the todo is immediately available in the user's
 * todo list and can be viewed, updated, or deleted through subsequent API
 * operations. The completion timestamp is not set until the user explicitly
 * marks the todo as completed.
 *
 * This operation enforces strong validation on all input fields: title cannot
 * be empty and cannot exceed 255 characters; description if provided cannot
 * exceed 2000 characters; priority if provided must be one of the three valid
 * values; due date if provided must be in valid ISO 8601 date format and cannot
 * represent a date in the past. If any validation fails, the operation is
 * rejected and appropriate error messages are returned to guide the user.
 *
 * Permission: The operation requires the user to be authenticated. The system
 * verifies the user's session before allowing todo creation. The created todo
 * is automatically associated with the authenticated user's ID from their
 * authentication token.
 *
 * @param props.connection
 * @param props.body Todo creation data including required title and optional
 *   properties for the new todo item
 * @path /todoApp/user/todos
 * @accessor api.functional.todoApp.user.todos.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
