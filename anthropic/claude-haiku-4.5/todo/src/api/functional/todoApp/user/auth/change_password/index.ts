import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ITodoAppUser } from "../../../../../structures/ITodoAppUser";

/**
 * Change authenticated user's account password.
 *
 * This operation enables an authenticated user to change their password from
 * their current password to a new one. The user must provide their current
 * password for verification purposes to ensure they have authorization to
 * change the password. The system validates the current password against the
 * stored password hash using constant-time comparison to prevent timing
 * attacks.
 *
 * The new password must meet the following requirements: minimum 8 characters
 * in length. The new password must differ from the current password; users
 * cannot set a password to the same value as before. The system rejects
 * passwords that are identical to the previous password.
 *
 * Upon successful password change, the system performs two critical security
 * operations: (1) The password hash in the database is updated using bcrypt or
 * Argon2 with a unique salt, and (2) All existing JWT tokens and session
 * records for the user are invalidated after the success response is delivered.
 * The current user session is preserved temporarily to allow the success
 * response (HTTP 200) to be delivered to the client, then automatically expires
 * after the response is transmitted. This forces the user to re-authenticate
 * with their new password on their next request or page refresh, ensuring the
 * password change is propagated across all sessions and all devices.
 *
 * This operation is intended for authenticated users who want to change their
 * own password. Administrators cannot use this operation to change other users'
 * passwords; each user must change their own password directly. The operation
 * includes comprehensive audit logging of the password change attempt (success
 * or failure) for security purposes. Error responses provide specific feedback
 * about why the password change failed (e.g., 'Current password incorrect',
 * 'New password must be at least 8 characters', 'New password cannot be the
 * same as current password').
 *
 * @param props.connection
 * @param props.body User's current password for verification and new password
 *   meeting security requirements
 * @path /todoApp/user/auth/change-password
 * @accessor api.functional.todoApp.user.auth.change_password.changePassword
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function changePassword(
  connection: IConnection,
  props: changePassword.Props,
): Promise<changePassword.Response> {
  return true === connection.simulate
    ? changePassword.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...changePassword.METADATA,
          path: changePassword.path(),
          status: null,
        },
        props.body,
      );
}
export namespace changePassword {
  export type Props = {
    /**
     * User's current password for verification and new password meeting
     * security requirements
     */
    body: ITodoAppUser.IChangePassword;
  };
  export type Body = ITodoAppUser.IChangePassword;
  export type Response = ITodoAppUser.IPasswordChanged;

  export const METADATA = {
    method: "POST",
    path: "/todoApp/user/auth/change-password",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/todoApp/user/auth/change-password";
  export const random = (): ITodoAppUser.IPasswordChanged =>
    typia.random<ITodoAppUser.IPasswordChanged>();
  export const simulate = (
    connection: IConnection,
    props: changePassword.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: changePassword.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
