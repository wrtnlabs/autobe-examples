import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ITodoAppUser } from "../../../../structures/ITodoAppUser";

/**
 * Retrieve a specific user account by ID.
 *
 * Retrieve detailed information about a specific user account from the Todo
 * application. This operation fetches complete user profile data including
 * email address, account status (active or inactive), account creation
 * timestamp, last update timestamp, and soft-delete status.
 *
 * The operation enforces proper authorization: regular authenticated users can
 * only retrieve their own account information, while system administrators can
 * retrieve any user's information for administrative purposes. Attempting to
 * access another user's information as a regular user results in a 403
 * Forbidden error.
 *
 * The response includes all user properties stored in the todo_app_users table.
 * User passwords are never exposed in responses - the password_hash is stored
 * securely server-side and never returned to clients. The operation validates
 * that the requested user ID is a valid UUID format.
 *
 * This operation supports both regular user self-service account viewing and
 * admin user management workflows where administrators need to review user
 * account details for support, compliance, or administrative purposes.
 *
 * @param props.connection
 * @param props.userId Unique identifier of the user account to retrieve (UUID
 *   format)
 * @path /todoApp/user/users/:userId
 * @accessor api.functional.todoApp.user.users.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique identifier of the user account to retrieve (UUID format) */
    userId: string & tags.Format<"uuid">;
  };
  export type Response = ITodoAppUser;

  export const METADATA = {
    method: "GET",
    path: "/todoApp/user/users/:userId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/todoApp/user/users/${encodeURIComponent(props.userId ?? "null")}`;
  export const random = (): ITodoAppUser => typia.random<ITodoAppUser>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("userId")(() => typia.assert(props.userId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

/**
 * Update a user account.
 *
 * Update specific properties of a user account in the Todo application. This
 * operation allows modification of user profile information based on proper
 * authorization.
 *
 * Regular authenticated users can update only their own account information
 * including email address and account status (active/inactive). System
 * administrators can update any user account information for administrative
 * purposes including account status management and user data corrections.
 *
 * The operation validates all input data before persisting changes: email
 * addresses must be unique across the system and follow valid email format;
 * account status must be one of the allowed values ('active' or 'inactive').
 * Password changes are handled through a separate password reset flow, not
 * through this general user update endpoint.
 *
 * When a user updates their email address, the system verifies the new email is
 * not already in use by another account. When an admin updates a user's account
 * status, the system records the change with timestamp for audit trail
 * purposes. The updated_at timestamp is automatically updated to the current
 * time when any field is modified.
 *
 * This operation enforces data isolation: regular users cannot modify other
 * users' accounts and receive a 403 Forbidden error if attempting to do so. All
 * changes are logged and persisted immediately.
 *
 * @param props.connection
 * @param props.userId Unique identifier of the user account to update (UUID
 *   format)
 * @param props.body User account fields to update
 * @path /todoApp/user/users/:userId
 * @accessor api.functional.todoApp.user.users.update
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function update(
  connection: IConnection,
  props: update.Props,
): Promise<update.Response> {
  return true === connection.simulate
    ? update.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...update.METADATA,
          path: update.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace update {
  export type Props = {
    /** Unique identifier of the user account to update (UUID format) */
    userId: string & tags.Format<"uuid">;

    /** User account fields to update */
    body: ITodoAppUser.IUpdate;
  };
  export type Body = ITodoAppUser.IUpdate;
  export type Response = ITodoAppUser;

  export const METADATA = {
    method: "PUT",
    path: "/todoApp/user/users/:userId",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/todoApp/user/users/${encodeURIComponent(props.userId ?? "null")}`;
  export const random = (): ITodoAppUser => typia.random<ITodoAppUser>();
  export const simulate = (
    connection: IConnection,
    props: update.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: update.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("userId")(() => typia.assert(props.userId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
