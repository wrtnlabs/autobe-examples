/**
 * Terminate the authenticated user's session and invalidate their
 * authentication token.
 *
 * This operation allows an authenticated user to terminate their current
 * session and log out from the Todo application. When a user invokes logout,
 * the system invalidates their JWT authentication token, terminates their
 * active session, clears cached session data, and returns confirmation to the
 * user.
 *
 * The user must be properly authenticated with a valid JWT token to invoke this
 * operation. The system verifies the token is not already expired and belongs
 * to an active user session before processing the logout request.
 *
 * After successful logout, the user's authentication token becomes invalid
 * immediately and cannot be reused. Any subsequent API requests using the
 * invalidated token will receive an HTTP 401 Unauthorized response, requiring
 * the user to re-authenticate by logging in again.
 *
 * The system records the session termination timestamp in the
 * todo_app_user_sessions table, marking the session's expired_at field with the
 * current UTC timestamp. This creates an audit trail of the logout action.
 *
 * If the user attempts to logout while already logged out or with an expired
 * token, the system returns an error indicating the session is already
 * terminated or invalid. The operation is idempotent when attempted with an
 * already-expired session.
 *
 * Before processing logout, the system verifies the user making the request is
 * the owner of the session being terminated, preventing unauthorized logout
 * attempts on behalf of other users.
 *
 * @param props.connection
 * @path /todoApp/user/auth/logout
 * @accessor api.functional.todoApp.user.auth.logout
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function logout(
  connection: IConnection,
): Promise<logout.Response> {
  return true === connection.simulate
    ? logout.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...logout.METADATA,
          path: logout.path(),
          status: null,
        },
      );
}
export namespace logout {
  export type Response = ITodoAppLogoutResponse;

  export const METADATA = {
    method: "POST",
    path: "/todoApp/user/auth/logout",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/todoApp/user/auth/logout";
  export const random = (): ITodoAppLogoutResponse =>
    typia.random<ITodoAppLogoutResponse>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}

/**
 * Retrieve current authenticated user's active session information.
 *
 * This operation retrieves the current authenticated user's active session
 * information, including details about when they logged in, when their session
 * will expire, and metadata about the session origin (IP address, referrer
 * URL). The user must be authenticated with a valid JWT token to access this
 * endpoint.
 *
 * The system validates that the user's JWT token is still valid and has not
 * expired. If the token is invalid or expired, the operation returns a 401
 * Unauthorized error with message 'Your session has expired. Please log in
 * again.' The system then retrieves the corresponding session record from the
 * database using the user ID extracted from the JWT token.
 *
 * The response includes complete session information: (1) Current user's unique
 * identifier and email address, (2) Session ID (unique identifier for this
 * login session), (3) Session creation timestamp in UTC (when user logged in),
 * (4) Session expiration timestamp in UTC (when session will automatically
 * expire due to inactivity or timeout), (5) IP address from which the session
 * was established, (6) HTTP referrer URL that led to the login, (7) Connection
 * URL where session was initiated.
 *
 * Users can use this information to verify they recognize the IP address and
 * location from which they are logged in, supporting security awareness and
 * helping detect unauthorized access. For admin users, this endpoint works
 * identically but retrieves session information from todo_app_admin_sessions
 * instead of todo_app_user_sessions, with the same response structure
 * containing admin session details.
 *
 * @param props.connection
 * @path /todoApp/user/auth/session
 * @accessor api.functional.todoApp.user.auth.session
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
