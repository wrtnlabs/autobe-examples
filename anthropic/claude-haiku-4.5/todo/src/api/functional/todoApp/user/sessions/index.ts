/**
 * Retrieve all active sessions for the authenticated user or view all system
 * sessions for admins.
 *
 * This operation retrieves session information depending on the authenticated
 * user's role. For regular users, it returns all sessions associated with their
 * account, showing active and expired sessions. Each session record includes
 * the timestamp when the session was established, the IP address used to
 * authenticate, the browser/device information via referrer data, and the URL
 * where the session was created.
 *
 * For admin users, this operation returns all sessions across the entire system
 * - both user sessions and admin sessions - providing administrators with
 * visibility into who is currently logged in, from where, and for how long.
 * This enables admins to monitor for suspicious login patterns, detect
 * unauthorized access attempts, and manage user sessions if needed.
 *
 * The response includes complete session metadata: session ID (unique
 * identifier), user/admin ID, creation timestamp in UTC, expiration timestamp
 * (NULL for active sessions), IP address, connection URL, and referrer.
 * Sessions that have expired (where expired_at is populated) indicate previous
 * login sessions that are no longer active. Sessions with NULL expired_at are
 * currently active and the user/admin is logged in.
 *
 * This operation helps track user activity across devices, enables detection of
 * concurrent sessions, and provides the security foundation for session
 * management and audit logging. The list is ordered chronologically with most
 * recent sessions first.
 *
 * @param props.connection
 * @path /todoApp/user/sessions
 * @accessor api.functional.todoApp.user.sessions.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(connection: IConnection): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
      );
}
export namespace index {
  export type Response = IPageITodoAppSession;

  export const METADATA = {
    method: "GET",
    path: "/todoApp/user/sessions",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/todoApp/user/sessions";
  export const random = (): IPageITodoAppSession =>
    typia.random<IPageITodoAppSession>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}

/**
 * Logout the authenticated user by terminating their active session.
 *
 * This operation allows an authenticated user to logout and terminate their
 * current session. When a user initiates logout, the system marks their active
 * session as expired and invalidates their JWT authentication token.
 *
 * The logout operation performs the following steps: (1) verifies the user has
 * valid authentication credentials, (2) retrieves the current user's active
 * session from the database, (3) sets the expired_at timestamp on the session
 * record to mark it as terminated, (4) invalidates the JWT token so future
 * requests with this token are rejected, (5) clears any session data stored in
 * memory or cache, (6) returns a success confirmation to the user.
 *
 * From a security perspective, logout is critical for ensuring users can
 * explicitly terminate their sessions. This prevents unauthorized access if a
 * device is left unattended or if a user's session token is compromised.
 * Sessions are also automatically terminated after 30 minutes of inactivity or
 * when the user changes their password (forcing re-authentication on all
 * devices).
 *
 * The operation targets the todo_app_user_sessions table to record the session
 * termination. The user who is logged out is identified from the current
 * authentication context (JWT token claims). No request body is required; the
 * system determines which session to logout based on the authentication token
 * in the request header.
 *
 * If the user is not currently authenticated or their session is already
 * expired, the system returns an appropriate error. Successful logout returns
 * HTTP 200 OK with confirmation message indicating the session has been
 * terminated and the user must re-authenticate for future requests.
 *
 * @param props.connection
 * @path /todoApp/user/sessions
 * @accessor api.functional.todoApp.user.sessions.logout
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function logout(connection: IConnection): Promise<void> {
  return true === connection.simulate
    ? logout.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...logout.METADATA,
          path: logout.path(),
          status: null,
        },
      );
}
export namespace logout {
  export const METADATA = {
    method: "DELETE",
    path: "/todoApp/user/sessions",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/todoApp/user/sessions";
  export const random = (): void => typia.random<void>();
  export const simulate = (_connection: IConnection): void => {
    return random();
  };
}
