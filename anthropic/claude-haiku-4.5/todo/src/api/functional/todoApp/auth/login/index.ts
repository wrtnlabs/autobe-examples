import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ITodoAppUser } from "../../../../structures/ITodoAppUser";

/**
 * Authenticate user with email and password credentials.
 *
 * This operation enables registered users to authenticate into the Todo
 * application by submitting their email address and password. The system
 * verifies the credentials against the user account stored in the
 * todo_app_users table and establishes an authenticated session upon successful
 * verification.
 *
 * The login process performs secure credential validation including email
 * existence verification and password hash comparison using constant-time
 * comparison to prevent timing attacks. The system retrieves the user record by
 * email address, verifies the provided plaintext password matches the stored
 * password hash using bcrypt verification or equivalent, and confirms the
 * user's account status is 'active' (not suspended or deleted).
 *
 * Upon successful authentication, the system creates a new user session record
 * in todo_app_user_sessions table with connection metadata (IP address,
 * referrer URL), generates a JWT access token valid for 30 minutes of
 * inactivity, and optionally generates a refresh token valid for 7 days. The
 * authenticated user receives both tokens and is immediately redirected to
 * their personal todo dashboard where they can view and manage their todos.
 *
 * If authentication fails, the system implements security measures including
 * tracking failed login attempts per email address. After 5 consecutive failed
 * login attempts within 15 minutes, the system temporarily locks the account
 * for 15 minutes, preventing further login attempts and requiring the user to
 * use the password reset functionality. Failed login responses use generic
 * error messages ('Email or password is incorrect') to prevent email
 * enumeration attacks that could reveal which email addresses are registered in
 * the system.
 *
 * The operation ensures security by never revealing whether an email address is
 * registered, implementing rate limiting on login attempts, recording session
 * metadata for audit trail purposes, and invalidating all previous sessions if
 * the user logs in from a new device.
 *
 * @param props.connection
 * @param props.body User authentication credentials including email address and
 *   password
 * @path /todoApp/auth/login
 * @accessor api.functional.todoApp.auth.login.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(),
          status: null,
        },
        props.body,
      );
}
export namespace at {
  export type Props = {
    /** User authentication credentials including email address and password */
    body: ITodoAppUser.IRequest;
  };
  export type Body = ITodoAppUser.IRequest;
  export type Response = ITodoAppUser;

  export const METADATA = {
    method: "POST",
    path: "/todoApp/auth/login",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/todoApp/auth/login";
  export const random = (): ITodoAppUser => typia.random<ITodoAppUser>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
