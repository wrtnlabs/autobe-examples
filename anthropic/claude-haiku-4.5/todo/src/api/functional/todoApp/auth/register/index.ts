import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ITodoAppUser } from "../../../../structures/ITodoAppUser";

/**
 * Register a new user account with email and password.
 *
 * This operation allows prospective users to create a new Todo application
 * account by submitting their email address and desired password. The system
 * validates all input data according to security and business rules before
 * creating the user account.
 *
 * The registration process performs comprehensive validation including email
 * format verification, email uniqueness checking across all existing users, and
 * password security requirements enforcement. The email address must follow
 * valid RFC 5322 format (e.g., user@example.com) and must not already be
 * registered in the system. The password must be at least 8 characters long and
 * will be securely hashed using bcrypt or equivalent before storage.
 *
 * Upon successful registration, the system creates a new user record in the
 * todo_app_users table with status set to 'active', automatically initializes
 * the user's empty todo list, and generates a new authenticated session. The
 * newly registered user is automatically logged in and receives a JWT
 * authentication token valid for 30 minutes of inactivity, enabling immediate
 * access to their personal todo dashboard without requiring a separate login
 * step.
 *
 * If registration fails due to validation errors (invalid email format,
 * password too short, or duplicate email), the system rejects the request with
 * specific error messages guiding the user on how to correct the problem. The
 * registration process is atomic - either the complete user account is created
 * with all necessary initialization, or the operation fails entirely with no
 * partial account creation.
 *
 * @param props.connection
 * @param props.body User registration credentials including email address and
 *   password
 * @path /todoApp/auth/register
 * @accessor api.functional.todoApp.auth.register.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function create(
  connection: IConnection,
  props: create.Props,
): Promise<create.Response> {
  return true === connection.simulate
    ? create.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...create.METADATA,
          path: create.path(),
          status: null,
        },
        props.body,
      );
}
export namespace create {
  export type Props = {
    /** User registration credentials including email address and password */
    body: ITodoAppUser.ICreate;
  };
  export type Body = ITodoAppUser.ICreate;
  export type Response = ITodoAppUser;

  export const METADATA = {
    method: "POST",
    path: "/todoApp/auth/register",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/todoApp/auth/register";
  export const random = (): ITodoAppUser => typia.random<ITodoAppUser>();
  export const simulate = (
    connection: IConnection,
    props: create.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: create.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
