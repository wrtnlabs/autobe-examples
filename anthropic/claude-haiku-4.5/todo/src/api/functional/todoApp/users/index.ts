/**
 * Create a new user account with email and secure password authentication.
 *
 * Create a new user account by registering with an email address and secure
 * password. This operation implements the complete user registration workflow
 * where new users can sign up for the Todo application by providing their
 * authentication credentials. The system validates the email format, ensures
 * the email is unique across all registered user accounts, and enforces
 * password security requirements before creating the account.
 *
 * When a user submits registration information, the operation performs
 * comprehensive validation of all input fields. The email address must follow
 * valid email format (RFC 5322 standard) and must not already exist in the
 * system - duplicate email registration is rejected with error message
 * indicating the email is already in use. The password must meet minimum
 * security requirements (at least 8 characters) to ensure account security and
 * prevent brute force attacks.
 *
 * Security considerations are critical for this operation. Passwords are never
 * stored in plaintext; instead, the system generates a secure hash using bcrypt
 * with appropriate cost factor or Argon2 hashing algorithm before storing. Each
 * password is hashed with a unique salt to prevent rainbow table attacks. The
 * hashing occurs server-side, never trusting client-provided hash values. The
 * operation also implements rate limiting on registration attempts to prevent
 * abuse and automated account creation attacks.
 *
 * Upon successful registration, the operation creates a user record in the
 * todo_app_users table with automatically-generated unique user ID (UUID), the
 * provided email address (normalized to lowercase), the hashed password,
 * account status set to 'active' (enabling immediate login), and
 * system-generated creation timestamp in UTC. The operation returns the newly
 * created user account information but NEVER returns the password hash in the
 * response for security.
 *
 * If registration fails due to validation errors (invalid email format,
 * duplicate email, weak password, missing fields), the operation rejects the
 * request with specific error messages indicating which validation failed and
 * how to correct it. No partial user record is created if any validation fails
 * - the operation is atomic, either fully succeeding or fully failing.
 *
 * This operation is public and does not require authentication, allowing
 * unregistered users to create new accounts. However, after successful
 * registration, the user must authenticate with their credentials using the
 * login operation to access their personal todo list.
 *
 * @param props.connection
 * @param props.body User registration information including email address and
 *   secure password for account creation
 * @path /todoApp/users
 * @accessor api.functional.todoApp.users.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function create(
  connection: IConnection,
  props: create.Props,
): Promise<create.Response> {
  return true === connection.simulate
    ? create.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...create.METADATA,
          path: create.path(),
          status: null,
        },
        props.body,
      );
}
