/**
 * Restore the system from a backup file to a previous state.
 *
 * This admin-only operation restores the entire Todo application from a
 * previously created backup. The system will revert all data to the exact state
 * captured in the backup identified by backupId.
 *
 * The backup restoration process involves verifying the backup integrity,
 * ensuring data consistency, and writing all backed-up data to the production
 * database. During restoration, the system will be temporarily unavailable to
 * users. All application data created or modified after the backup timestamp
 * will be lost and replaced with the backed-up versions.
 *
 * This operation requires admin authentication and explicit confirmation due to
 * its destructive nature. The admin must verify they have selected the correct
 * backup before confirming the restoration. The system will validate the backup
 * exists, is not corrupted, and can be successfully restored before committing
 * to the operation.
 *
 * After successful restoration, all users will see the application state as it
 * existed when the backup was created. The restoration action is logged in the
 * admin audit trail with complete details including the admin ID, timestamp,
 * backup ID, and any error conditions encountered during restoration. Users
 * will need to log in again after the restoration completes.
 *
 * @param props.connection
 * @param props.backupId Unique identifier of the backup file to restore from
 *   (global scope)
 * @param props.body Confirmation and metadata for backup restoration operation
 * @path /todoApp/admin/backups/:backupId/restore
 * @accessor api.functional.todoApp.admin.backups.restore
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function restore(
  connection: IConnection,
  props: restore.Props,
): Promise<restore.Response> {
  return true === connection.simulate
    ? restore.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...restore.METADATA,
          path: restore.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace restore {
  export type Props = {
    /** Unique identifier of the backup file to restore from (global scope) */
    backupId: string & tags.Format<"uuid">;

    /** Confirmation and metadata for backup restoration operation */
    body: ITodoAppAdminBackup.IRestore;
  };
  export type Body = ITodoAppAdminBackup.IRestore;
  export type Response = ITodoAppAdminBackup.IRestoreResult;

  export const METADATA = {
    method: "POST",
    path: "/todoApp/admin/backups/:backupId/restore",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/todoApp/admin/backups/${encodeURIComponent(props.backupId ?? "null")}/restore`;
  export const random = (): ITodoAppAdminBackup.IRestoreResult =>
    typia.random<ITodoAppAdminBackup.IRestoreResult>();
  export const simulate = (
    connection: IConnection,
    props: restore.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: restore.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("backupId")(() => typia.assert(props.backupId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
