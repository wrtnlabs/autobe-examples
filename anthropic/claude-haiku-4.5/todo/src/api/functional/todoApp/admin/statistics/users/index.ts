import { IConnection } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";

import { ITodoAppUserStatistics } from "../../../../../structures/ITodoAppUserStatistics";

/**
 * Retrieve comprehensive user statistics and engagement metrics.
 *
 * Retrieve system-wide user statistics including total user counts, active user
 * metrics, registration trends, and user engagement indicators.
 *
 * This operation provides administrators with detailed insights into user base
 * characteristics and activity patterns. It returns total registered user
 * count, count of active users in the last 7 days, count of active users in the
 * last 30 days, and new user registrations in the last 24 hours, 7 days, and 30
 * days. The operation also includes daily registration trend data spanning the
 * last 30 days to enable visualization of registration patterns over time.
 *
 * Engagement metrics include count of users active today, users active this
 * week, and users active this month. The operation computes average session
 * duration in minutes and tracks user retention metrics such as the percentage
 * of users returning after their first week. Activity pattern data identifies
 * peak usage times and which days/hours show highest user activity
 * concentration.
 *
 * This operation supports system capacity planning by providing metrics on user
 * growth trends, average todos created per active user, and average todos
 * completed per active user. These metrics enable administrators to forecast
 * storage requirements, assess system load, and identify engagement trends that
 * might indicate need for feature enhancements or system improvements.
 *
 * The statistics endpoint is used in the monthly maintenance and review
 * workflows described in the Admin Features and Management requirements.
 * Administrators access this endpoint to understand system usage patterns,
 * monitor user growth, assess feature adoption, and make decisions about system
 * optimization or scaling.
 *
 * Related administrative operations include system health monitoring for
 * real-time component status, audit log viewing for detailed activity
 * investigation, and system configuration modification for adjusting
 * performance parameters. All metrics represent system state computed from
 * underlying data sources rather than pre-stored aggregate tables.
 *
 * Response times for this operation should be reasonable (< 2 seconds) even
 * when computing aggregates across large user bases. The data reflects recent
 * state (within approximately 5 minutes for aggregate calculations). No request
 * body is required for this operation.
 *
 * @param props.connection
 * @path /todoApp/admin/statistics/users
 * @accessor api.functional.todoApp.admin.statistics.users.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(connection: IConnection): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(),
          status: null,
        },
      );
}
export namespace at {
  export type Response = ITodoAppUserStatistics;

  export const METADATA = {
    method: "GET",
    path: "/todoApp/admin/statistics/users",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/todoApp/admin/statistics/users";
  export const random = (): ITodoAppUserStatistics =>
    typia.random<ITodoAppUserStatistics>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}
