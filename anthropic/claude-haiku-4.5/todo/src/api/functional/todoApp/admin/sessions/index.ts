import { IConnection } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";

import { IPageITodoAppSession } from "../../../../structures/IPageITodoAppSession";

/**
 * Retrieve all active sessions for the authenticated user or view all system
 * sessions for admins.
 *
 * This operation retrieves session information depending on the authenticated
 * user's role. For regular users, it returns all sessions associated with their
 * account, showing active and expired sessions. Each session record includes
 * the timestamp when the session was established, the IP address used to
 * authenticate, the browser/device information via referrer data, and the URL
 * where the session was created.
 *
 * For admin users, this operation returns all sessions across the entire system
 * - both user sessions and admin sessions - providing administrators with
 * visibility into who is currently logged in, from where, and for how long.
 * This enables admins to monitor for suspicious login patterns, detect
 * unauthorized access attempts, and manage user sessions if needed.
 *
 * The response includes complete session metadata: session ID (unique
 * identifier), user/admin ID, creation timestamp in UTC, expiration timestamp
 * (NULL for active sessions), IP address, connection URL, and referrer.
 * Sessions that have expired (where expired_at is populated) indicate previous
 * login sessions that are no longer active. Sessions with NULL expired_at are
 * currently active and the user/admin is logged in.
 *
 * This operation helps track user activity across devices, enables detection of
 * concurrent sessions, and provides the security foundation for session
 * management and audit logging. The list is ordered chronologically with most
 * recent sessions first.
 *
 * @param props.connection
 * @path /todoApp/admin/sessions
 * @accessor api.functional.todoApp.admin.sessions.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(connection: IConnection): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
      );
}
export namespace index {
  export type Response = IPageITodoAppSession;

  export const METADATA = {
    method: "GET",
    path: "/todoApp/admin/sessions",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/todoApp/admin/sessions";
  export const random = (): IPageITodoAppSession =>
    typia.random<IPageITodoAppSession>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}
