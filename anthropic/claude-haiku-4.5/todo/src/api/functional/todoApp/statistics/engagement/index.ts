import { IConnection } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";

import { ITodoAppEngagementStatistics } from "../../../../structures/ITodoAppEngagementStatistics";

/**
 * Retrieve aggregate engagement and activity statistics for user accounts.
 *
 * This operation returns comprehensive engagement statistics about user and
 * admin accounts in the system. It computes aggregated metrics including total
 * active user count, total admin count, user account creation trends over time,
 * distribution of active versus inactive users, and engagement patterns based
 * on last_active_at timestamps.
 *
 * The statistics are calculated from both the todo_app_user and todo_app_admin
 * tables and include metrics such as users created per day, average days since
 * last activity, percentage of active users in the past 30 days, and retention
 * patterns. Soft-deleted accounts (marked via deleted_at) are excluded from
 * active user counts but tracked separately for compliance and analytics
 * purposes.
 *
 * This is a read-only operation that performs aggregation and analysis on user
 * account data without modifying any records. The response is optimized for
 * dashboard displays, system monitoring, and engagement reporting. No
 * authentication is required as these are system-level aggregate statistics
 * that do not expose individual user information.
 *
 * Administrators and system operators use this data to monitor overall platform
 * health, track user growth, identify engagement trends, and make data-driven
 * decisions about feature adoption and user retention strategies.
 *
 * @param props.connection
 * @path /todoApp/statistics/engagement
 * @accessor api.functional.todoApp.statistics.engagement.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(connection: IConnection): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
      );
}
export namespace index {
  export type Response = ITodoAppEngagementStatistics;

  export const METADATA = {
    method: "GET",
    path: "/todoApp/statistics/engagement",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/todoApp/statistics/engagement";
  export const random = (): ITodoAppEngagementStatistics =>
    typia.random<ITodoAppEngagementStatistics>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}
