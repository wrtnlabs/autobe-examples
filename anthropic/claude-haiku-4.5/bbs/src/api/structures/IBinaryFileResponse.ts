import { tags } from "typia";

/**
 * Response body for file download operations returning the raw file content and
 * metadata.
 *
 * This DTO wraps the binary file content being downloaded along with essential
 * metadata for proper browser handling. The content field contains the actual
 * file bytes as application/octet-stream. The HTTP response includes
 * appropriate headers: Content-Type set to file_type (image/jpeg,
 * application/pdf, etc.), Content-Disposition set to attachment or inline based
 * on file type, and Content-Length set to file_size for accurate progress
 * indication.
 *
 * Image files (JPEG, PNG, GIF, WebP) are served with MIME types that allow
 * browser inline display. Document files (PDF, Word, Excel, archives) are
 * served to trigger download dialogs with the sanitized filename. The file_type
 * metadata allows clients to handle different file types appropriately and
 * determine whether to display or save the file.
 *
 * This response type is used for the file download endpoint that retrieves
 * attachment content from storage and serves it to authenticated or guest users
 * based on access permissions.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type IBinaryFileResponse = {
  /**
   * The raw binary file content being downloaded. Transmitted as
   * application/octet-stream MIME type. The actual file bytes served to the
   * client for download or display. For image files (JPEG, PNG, GIF, WebP),
   * the browser will typically display inline. For document files (PDF, Word,
   * Excel, archives), the browser will trigger download behavior with the
   * original filename.
   */
  content: string & tags.ContentMediaType<"application/octet-stream">;

  /**
   * Original sanitized filename for the downloaded file. Used in the HTTP
   * Content-Disposition header to specify the filename when the browser saves
   * the file. Example: 'economic-report-2024.pdf' or 'chart.jpg'.
   */
  filename: string;

  /**
   * MIME type of the file being served. Used in the HTTP Content-Type header
   * to instruct the browser how to handle the file. Examples: 'image/jpeg'
   * for JPG files (display inline), 'application/pdf' for PDF files (may
   * display or download depending on browser settings), 'application/zip' for
   * archive files (download).
   */
  file_type: string;

  /**
   * Size of the file in bytes. Provided for informational purposes and used
   * in HTTP Content-Length header for progress indication. Allows clients to
   * estimate download time and validate complete file receipt.
   */
  file_size: number & tags.Type<"int32">;
};
