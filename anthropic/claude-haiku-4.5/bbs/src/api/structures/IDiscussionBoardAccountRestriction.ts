  expires_at: (string & tags.Format<"date-time">) | null;

  /**
   * Timestamp when the restriction was manually lifted by a moderator. Null
   * if restriction expired naturally or is still active. Enables early
   * restriction removal for rehabilitated contributors.
   */
  lifted_at: (string & tags.Format<"date-time">) | null;

  /**
   * The contributor account being restricted. Provides identification context
   * for the restricted user.
   */
  contributor: IDiscussionBoardContributor.ISummary;

  /**
   * The moderator who imposed the restriction. Identifies the enforcement
   * authority.
   */
  imposed_by_moderator: IDiscussionBoardModerator.ISummary;

  /**
   * The moderator who manually lifted the restriction, if applicable. Null if
   * restriction was not manually lifted or expired naturally.
   */
  lifted_by_moderator: IDiscussionBoardModerator.ISummary | null;

  /**
   * Current status of the restriction. Determines whether restrictions are
   * actively enforced.
   *
   * Valid status values:
   *
   * - Active: Restrictions currently in effect
   * - Lifted: Moderator manually removed the restriction
   * - Expired: Restriction duration completed naturally
   *
   * Status determines whether the contributor account restrictions are
   * currently being enforced.
   */
