import { tags } from "typia";

/**
 * Historical revision record for an article capturing a specific version from
 * edit history.
 *
 * Each article edit creates a new revision record preserving the complete state
 * at that point in time. This snapshot-based approach enables full audit
 * trails, change tracking, and potential rollback to previous versions.
 * Revisions preserve both the content (title and body) and metadata about who
 * made the change and why.
 *
 * The record tracks whether edits were made by the article author (member) or
 * by moderators, supporting different audit and transparency requirements for
 * each type of modification. System edits are tracked separately for compliance
 * purposes.
 *
 * Revisions are immutable once created, forming a permanent historical record
 * of all changes to the article.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type IDiscussionBoardArticleRevision = {
  /**
   * Unique identifier for the article revision record. System-generated UUID
   * that uniquely identifies this specific version of the article in the
   * revision history.
   */
  id: string & tags.Format<"uuid">;

  /**
   * Reference to the article this revision belongs to. Foreign key to
   * discussion_board_articles.id. Links this revision record to the parent
   * article being tracked.
   */
  discussion_board_article_id: string & tags.Format<"uuid">;

  /**
   * Reference to the member who made this edit if the editor was a regular
   * member author. Null if this revision was made by a moderator. Foreign key
   * to discussion_board_members.id. Populated only for member edits.
   */
  editor_member_id?: (string & tags.Format<"uuid">) | null | undefined;

  /**
   * Reference to the moderator who made this edit if the editor was a
   * moderator. Null if this revision was made by a member author. Foreign key
   * to discussion_board_moderators.id. Populated only for moderator edits.
   */
  editor_moderator_id?: (string & tags.Format<"uuid">) | null | undefined;

  /**
   * Article title at the time this revision was created. Preserves the
   * complete title history showing how the title evolved through edits.
   * Between 3 and 200 characters as per article validation rules.
   */
  title: string;

  /**
   * Article body content at the time this revision was created. Preserves the
   * full historical content text immutably. Between 10 and 50,000 characters
   * as per article validation rules. Critical for audit trail and potential
   * rollback functionality.
   */
  content: string;

  /**
   * Type of edit that created this revision. Valid values: 'member_edit'
   * (author editing their own article), 'moderator_edit' (moderator modifying
   * article), 'system_update' (automated system change). Discriminator
   * indicating who made the change and why.
   */
  edit_type: "member_edit" | "moderator_edit" | "system_update";

  /**
   * Optional reason or explanation for the edit, particularly important for
   * moderator edits. Helps explain why content was modified and provides
   * transparency to the article author. Can include notes about policy
   * violations or corrections made.
   */
  change_reason?: string | null | undefined;

  /**
   * Timestamp when this revision was created (when the edit was made). Stored
   * in ISO 8601 UTC format. Used to track the sequence of edits
   * chronologically and determine edit history ordering.
   */
  created_at: string & tags.Format<"date-time">;
};
export namespace IDiscussionBoardArticleRevision {
  /**
   * Request body for moderator review and moderation action on articles.
   * Moderators use this DTO to approve, remove, or restore articles. The
   * operation updates article status (published/archived) and creates
   * corresponding moderation log entries for audit trails. When removing
   * articles, the status changes to 'archived' making them invisible to
   * regular users while preserving them for moderator visibility and audit
   * purposes. When approving articles, the status is set to 'published' and
   * any flags are cleared.
   */
  export type IUpdate = {
    /**
     * Type of moderation action to take on the article. Valid values are:
     * 'approve' (clear flags and set status to published), 'remove'
     * (archive article from public view), or 'restore' (restore previously
     * moderated article). This field determines how the article status will
     * be updated and what moderation log entry is created. Required to
     * specify the intended moderation outcome.
     */
    action_type: string;

    /**
     * Moderator-provided explanation for the moderation action taken.
     * Optional detailed reason explaining why the article was approved,
     * removed, or restored. Should reference specific community guideline
     * violations when applicable. Supports transparency by documenting the
     * basis for moderation decisions. Maximum 500 characters. Displayed to
     * article author and recorded in moderation audit log.
     */
    reason?: string | undefined;
  };
}
