/**
 * Comments representing member responses and engagement on published articles.
 *
 * Comments enable discussion and debate by allowing members to share
 * perspectives, ask questions, and respond to article content. Unlike articles,
 * comments are published immediately without moderation approval, creating
 * immediate visibility and real-time engagement.
 *
 * Each comment belongs exclusively to one article and extends that article's
 * discussion thread. Comments maintain author information, creation timestamp,
 * attachment references, and support editing for content correction and
 * deletion for content removal with soft deletion preserving comment records
 * for audit purposes.
 *
 * Comments form the interactive component of the discussion platform,
 * transforming the system from one-way content distribution into collaborative
 * conversation. They represent primary business entities requiring independent
 * management through search, filtering, and moderation capabilities.
 *
 * Comments are displayed in threaded format under their parent article,
 * enabling members to follow discussion progressions and understand
 * conversational context. Attachments (images and files) provide rich media
 * support for detailed explanations and evidence sharing. Comment counts
 * provide engagement metrics on articles while actual comments are retrieved
 * via dedicated endpoints.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type IDiscussionBoardComment = {
  /**
   * Unique identifier for the comment. System-generated UUID primary key used
   * to reference this comment in API responses and moderation actions.
   */
  id: string & tags.Format<"uuid">;

  /**
   * Comment text content. Must be between 1 and 5,000 characters. Contains
   * the member's response, perspective, or question about the article.
   * Supports plain text with basic formatting.
   */
  body: string;

  /**
   * Soft deletion flag indicating whether comment has been deleted. True if
   * deleted by author or moderator; false if active. Allows recovery of
   * deleted comments for audit purposes while hiding them from user views.
   * Defaults to false.
   */
  is_deleted: boolean;

  /**
   * Timestamp when comment was originally created. Immutable - never changes.
   * Records the exact moment comment was posted for chronological sorting and
   * rate limiting checks.
   */
  created_at: string & tags.Format<"date-time">;

  /**
   * Timestamp of last edit to comment. Null if comment has never been edited.
   * Updated whenever member modifies comment text or attachments. Allows
   * tracking of comment modifications with edit timestamps displayed to
   * users.
   */
  updated_at?: (string & tags.Format<"date-time">) | null | undefined;

  /**
   * The member who created this comment. Provides author attribution and
   * member identity context displayed with the comment. Always uses .ISummary
   * to prevent circular references while providing essential author
   * information.
   */
  author: IDiscussionBoardMember.ISummary;

  /**
   * Reference to the parent article this comment belongs to. Used to
   * associate comment with its article and for organizing comments by
   * article.
   */
  article_id: string & tags.Format<"uuid">;

  /**
   * Array of file and image attachments associated with the comment. Comments
   * can include multiple attachments (images, documents, etc.) uploaded
   * together with the comment content. Attachments are managed as part of the
   * comment composition and are deleted when the comment is deleted.
   */
  attachments: IDiscussionBoardAttachment[];
};
