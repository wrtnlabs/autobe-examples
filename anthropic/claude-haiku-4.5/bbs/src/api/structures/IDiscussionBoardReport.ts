/**
 * Discussion board report entity representing member-submitted reports of
 * inappropriate content.
 *
 * Reports provide the moderation system with community feedback on content that
 * may violate guidelines. Each report documents what content is reported
 * (articles or comments), who reported it (reporter), the reason category,
 * optional detailed description, and tracks the complete moderation workflow
 * from submission through resolution.
 *
 * Reports progress through the moderation workflow: pending_review (initial
 * state when report is created) → resolved (moderator took action on content)
 * or dismissed (moderator reviewed and determined no violation). The reporter
 * and assigned_moderator are provided as transformed reference objects
 * containing complete context.
 *
 * The report maintains a complete audit trail including reporter identity,
 * assigned moderator, resolution status, moderator investigation notes, and
 * timestamps. This enables accountability, consistent decision-making, pattern
 * analysis, and comprehensive moderation history tracking.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type IDiscussionBoardReport = {
  /**
   * Primary key identifier for the discussion board report. Unique identifier
   * assigned when the report is created. Used to reference this specific
   * report in all moderation operations.
   */
  id: string & tags.Format<"uuid">;

  /**
   * Predefined category for why this content was reported. Valid values:
   * offensive_language, personal_attack, spam, off_topic,
   * copyright_violation, harassment, other. Categorizes the report for
   * consistent moderator triage and pattern analysis.
   */
  reason: string;

  /**
   * Optional detailed explanation provided by the reporter explaining why
   * they believe the content violates community guidelines. Maximum 500
   * characters. Provides context and reasoning to help moderators understand
   * the member's concern during investigation.
   */
  description?: (string & tags.MaxLength<500>) | null | undefined;

  /**
   * Current status of the report in the moderation workflow. Progresses from
   * pending_review to either resolved (moderator took action) or dismissed
   * (no action needed). Tracks where the report is in the review process.
   */
  status: "pending_review" | "resolved" | "dismissed";

  /**
   * Summary information about the member who filed this report including
   * display name, account status, and creation timestamp. Provides context
   * about the reporter in moderation workflows.
   */
  reporter?: IDiscussionBoardMember.ISummary | undefined;

  /**
   * Summary information about the moderator assigned to review this report.
   * Null if no moderator has been assigned yet. Provides context about who is
   * investigating the report. Contains moderator id, display name, and
   * account status.
   */
  assigned_moderator?: IDiscussionBoardModerator.ISummary | null | undefined;

  /**
   * Notes added by the assigned moderator during investigation and review.
   * Maximum 500 characters. Records moderator's investigation findings,
   * reasoning for their decision, and any relevant context discovered.
   * Becomes part of the permanent audit trail explaining moderation
   * decisions.
   */
  moderator_notes?: (string & tags.MaxLength<500>) | null | undefined;

  /**
   * Timestamp when the report was created in UTC. Immutable. Marks when the
   * member submitted the report and entered it into the moderation queue.
   */
  created_at: string & tags.Format<"date-time">;

  /**
   * Timestamp of the last update to the report record in UTC. Updated when
   * report properties change (e.g., when moderator is assigned, notes are
   * added, status changes). Tracks modification history for audit purposes.
   */
  updated_at: string & tags.Format<"date-time">;

  /**
   * Timestamp when the report was resolved or dismissed in UTC. Null while
   * report is pending_review. Set when moderator completes investigation and
   * transitions report to resolved or dismissed status. Used to calculate
   * resolution time metrics.
   */
  resolved_at?: (string & tags.Format<"date-time">) | null | undefined;
};
