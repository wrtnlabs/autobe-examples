import { tags } from "typia";

/**
 * User account information for discussion board contributors and moderators.
 *
 * Represents the core user profile data returned in API responses for both
 * contributor and moderator accounts. Includes authentication identity, account
 * status, and profile metadata while excluding sensitive data like password
 * hashes and session tokens. This unified type accommodates both user types
 * with role-specific fields: contributors have null moderationTier, while
 * moderators have a defined tier value.
 *
 * The account lifecycle includes creation, verification, active operation,
 * potential restrictions or suspension by moderators, and eventual soft
 * deletion with audit trail preservation. All timestamps are recorded in ISO
 * 8601 format for audit compliance and system integration.
 *
 * Used in responses for profile retrieval and update operations. Never includes
 * password_hash or session information. Supports audit trail queries through
 * timestamp fields and enables account recovery within the 6-month soft
 * deletion window.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type IDiscussionBoardUser = {
  /**
   * Unique identifier for the user account (contributor or moderator).
   * Generated as UUID v4 on account creation.
   */
  id: string & tags.Format<"uuid">;

  /**
   * Email address used for authentication and account recovery. Unique across
   * all accounts of the same user type. Must follow RFC 5321 email format
   * standards (user@domain.com).
   */
  email: string & tags.Format<"email">;

  /**
   * Public display name used in articles, comments, and moderation actions.
   * Unique across accounts of the same user type. 3-50 characters,
   * alphanumeric and underscore only. Immutable after creation.
   */
  username: string;

  /**
   * Whether the user's email address has been verified through confirmation
   * link. Accounts cannot post articles or comments until email verification
   * is completed.
   */
  emailVerified: boolean;

  /**
   * Current account status indicating user capability and access permissions.
   * 'active' allows normal operation including posting articles and comments.
   * 'suspended' is a temporary ban preventing all platform access, used for
   * serious policy violations. 'restricted' allows limited posting
   * capabilities with moderation review required. 'deleted' marks the account
   * for soft deletion while retaining data for audit purposes and potential
   * recovery within 6 months.
   */
  accountStatus: "active" | "suspended" | "restricted" | "deleted";

  /**
   * Timestamp when the user account was created in ISO 8601 format
   * (YYYY-MM-DDTHH:mm:ssZ).
   */
  createdAt: string & tags.Format<"date-time">;

  /**
   * Timestamp of the most recent account modification. Updated when email,
   * username, password, or status changes. Not updated on session creation or
   * content posting.
   */
  updatedAt: string & tags.Format<"date-time">;

  /**
   * Timestamp of the most recent successful login. Null if account has never
   * been logged in. Updated only on successful authentication, not on failed
   * attempts.
   */
  lastLoginAt?: (string & tags.Format<"date-time">) | null | undefined;

  /**
   * Timestamp of the most recent password change. Null if password has never
   * been changed from initial setup. All active sessions are invalidated when
   * password changes for security enforcement.
   */
  passwordChangedAt?: (string & tags.Format<"date-time">) | null | undefined;

  /**
   * Timestamp when the account was soft-deleted. Null for active accounts.
   * Retained for 6 months to enable account recovery; after 6 months,
   * accounts marked for deletion can be permanently purged from the system.
   * Soft deletion preserves all associated content and audit trails for
   * compliance.
   */
  deletedAt?: (string & tags.Format<"date-time">) | null | undefined;

  /**
   * For moderator accounts only: permission level for moderation actions.
   * Current value is 'full' for all permissions granting access to all
   * moderation features. Null for contributor accounts, as contributors do
   * not have moderation capabilities.
   */
  moderationTier?: string | null | undefined;
};
