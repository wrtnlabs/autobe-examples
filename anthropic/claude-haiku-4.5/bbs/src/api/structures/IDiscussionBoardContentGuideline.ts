import { tags } from "typia";

/**
 * Content policy rules and moderation guidelines that define community
 * standards for articles and comments.
 *
 * The content guidelines entity stores the authoritative rules that moderators
 * enforce when reviewing articles and monitoring comments. Each guideline entry
 * specifies a policy rule, whether it applies to articles or comments, the
 * severity level if violated, and examples to help moderators make consistent
 * decisions.
 *
 * Guidelines are organized by policy area (hate speech, misinformation, spam,
 * off-topic, etc.) and include detailed descriptions of prohibited behavior.
 * The system maintains the complete set of active guidelines for reference by
 * moderators and contributors. Soft deletion is supported to preserve
 * historical policy changes while maintaining audit trails of previous
 * guidelines.
 *
 * Moderation decisions reference specific guidelines when removing content or
 * issuing warnings, creating accountability and transparency about why content
 * was removed.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type IDiscussionBoardContentGuideline = {
  /** Unique identifier for the content guideline policy rule. */
  id: string & tags.Format<"uuid">;

  /**
   * Machine-readable identifier for the guideline (e.g., 'hate-speech',
   * 'misinformation', 'spam'). 5-50 lowercase alphanumeric characters with
   * hyphens. Used in moderation logs and audit trails to uniquely identify
   * the policy rule being violated.
   */
  code: string &
    tags.MinLength<5> &
    tags.MaxLength<50> &
    tags.Pattern<"^[a-z0-9-]+$">;

  /**
   * Short, descriptive title of the guideline (e.g., 'Hate Speech',
   * 'Misinformation', 'Commercial Spam'). 10-100 characters. Displayed in
   * moderation dashboards and violation notices to moderators and
   * contributors.
   */
  title: string & tags.MinLength<10> & tags.MaxLength<100>;

  /**
   * Detailed explanation of the policy and what content violates it. Should
   * include clear examples of prohibited behavior and the rationale for the
   * policy. Maximum 2000 characters. Moderators use this when making judgment
   * calls about borderline content and contributors reference it to
   * understand community standards.
   */
  description: string & tags.MaxLength<2000>;

  /**
   * Whether this guideline applies to article content. If true, moderators
   * review articles against this guideline during approval process. Defaults
   * to true for most guidelines affecting discussion board articles.
   */
  applies_to_articles: boolean;

  /**
   * Whether this guideline applies to comment content. If true, moderators
   * monitor comments for violations of this guideline. Defaults to true for
   * most guidelines affecting discussion board comments.
   */
  applies_to_comments: boolean;

  /**
   * Classification of violation severity. 'minor' violations result in
   * edit/warning only. 'moderate' violations result in removal and warning.
   * 'severe' violations result in content removal and account suspension.
   * Guides moderator response proportionality and escalation decisions.
   */
  severity_level: "minor" | "moderate" | "severe";

  /**
   * Description of typical consequences for violating this guideline (e.g.,
   * 'comment removal', 'article rejection with feedback', 'account suspension
   * after 3 violations'). Maximum 500 characters. Helps set contributor
   * expectations and ensures consistent enforcement across moderators.
   */
  violation_consequence?: (string & tags.MaxLength<500>) | undefined;

  /**
   * Numeric order for displaying guidelines in user-facing policy
   * documentation. Lower numbers appear first. Defaults to 0. Used to
   * organize guidelines by importance or category for public visibility.
   */
  display_order: number & tags.Type<"int32"> & tags.Minimum<0>;

  /**
   * Whether this guideline is currently enforced. Active guidelines are
   * displayed in policy documentation and used by moderators. Inactive
   * guidelines are retained for historical reference but not actively
   * enforced. Defaults to true.
   */
  is_active: boolean;

  /**
   * Timestamp when the guideline was created. ISO 8601 format. Marks when the
   * policy rule was first established in the system.
   */
  created_at: string & tags.Format<"date-time">;

  /**
   * Timestamp when the guideline was last modified. ISO 8601 format. Updated
   * when policy descriptions or enforcement rules change.
   */
  updated_at: string & tags.Format<"date-time">;

  /**
   * Timestamp when the guideline was soft-deleted or made inactive. ISO 8601
   * format. Null for active guidelines. Soft deletion preserves historical
   * audit trail of policy changes and allows recovery.
   */
  deleted_at: (string & tags.Format<"date-time">) | null;
};
