import { tags } from "typia";

import { IAuthorizationToken } from "./IAuthorizationToken";

export namespace IDiscussionBoardGuest {
  /**
   * Request payload for guest user account registration.
   *
   * Guest registration is a simplified, lightweight onboarding process that
   * creates a temporary user session without requiring email addresses,
   * passwords, account verification, or any personal information. Guest
   * accounts enable unauthenticated visitors to browse published articles and
   * read comments on the discussion board.
   *
   * Unlike contributor or moderator accounts, guest registration has minimal
   * required information. Only an optional device identifier for session
   * tracking is accepted. The registration process is public and does not
   * require authentication. Each guest registration creates a fresh, isolated
   * session that can be used immediately.
   *
   * Guest users are limited to read-only access: they can view published
   * articles and their associated comments but cannot create articles, post
   * comments, upload files, or perform any moderation actions. Guest sessions
   * are temporary and managed through JWT tokens - a short-lived access token
   * (typically 15-60 minutes) and a longer-lived refresh token (typically 7
   * days) for session renewal. Guests may be automatically logged out or
   * their sessions cleaned up after extended inactivity based on
   * system_configurations timeout settings.
   */
  export type ICreate = {
    /**
     * Optional device identifier for session tracking and device-level
     * analytics.
     *
     * Can be a browser fingerprint, device UUID, user agent hash, or any
     * string that uniquely identifies the client device or browser session.
     * Used by the system to associate multiple API requests with the same
     * device for session continuity and usage analytics.
     *
     * When provided, helps track user activity patterns across sessions and
     * detect suspicious activity. Device identifiers enable the system to
     * maintain context across guest sessions and correlate requests from
     * the same device for security and analytics purposes. If not provided,
     * the system generates a temporary session identifier based on the
     * request itself.
     */
    device_identifier?: string | null | undefined;
  };

  /**
   * Guest authentication response containing guest user identifier and JWT
   * tokens. Returned after successful guest registration or token refresh
   * operation. Guest users receive both short-lived access tokens (valid 30
   * minutes) and longer-lived refresh tokens (valid 7 days) for session
   * management. Guest sessions enable browsing and reading articles without
   * email verification or account commitment.
   */
  export type IAuthorized = {
    /**
     * Unique identifier for the guest user session. Represents the guest's
     * temporary identity within the discussion board system.
     */
    id: string & tags.Format<"uuid">;

    /**
     * Optional device identifier provided during guest registration for
     * session tracking and user activity analysis. Used to associate
     * multiple API requests with the same device/browser session.
     */
    device_identifier?: string | null | undefined;

    /**
     * Timestamp when the guest account was created. Auto-generated by the
     * system.
     */
    created_at: string & tags.Format<"date-time">;

    /** JWT token information for authentication */
    token: IAuthorizationToken;
  };

  /**
   * Request to refresh an expired or expiring guest access token. The guest
   * provides their valid refresh token to obtain a new access token,
   * extending the session without requiring re-registration. This operation
   * is idempotent - calling multiple times with the same refresh token
   * produces the same result. Guest users receive both short-lived access
   * tokens (30 minutes) and longer-lived refresh tokens (7 days) upon
   * registration. As the access token approaches expiration, guests should
   * call this endpoint to seamlessly continue browsing.
   */
  export type IRefresh = {
    /**
     * Valid guest refresh token obtained from previous registration or
     * refresh operation. Token must not be expired or revoked. Guest
     * refresh tokens remain valid for 7 days from creation and can be used
     * multiple times until expiration.
     */
    refresh_token: string;
  };
}
