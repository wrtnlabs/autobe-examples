/**
 * Complete profile information and account details for a registered member of
 * the discussion board platform. Members are authenticated users who can create
 * articles, post comments, and participate in discussions. This represents the
 * core member entity with all account-level information needed for profile
 * management, authentication, and authorization checks throughout the
 * platform.
 *
 * The member profile includes account metadata such as email address used for
 * login and recovery, account status indicating whether the member can access
 * the platform (active, suspended, or banned), and timestamp tracking for audit
 * trails. The profile information is returned when members view their own
 * account settings or when the system needs to reference member account
 * details.
 *
 * Members are distinct from moderators who have elevated administrative
 * permissions. Each member maintains a unique email address for authentication
 * and account recovery. The account_status field controls platform access and
 * is managed by the moderation system when violations occur.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type IDiscussionBoardMember = {
  /**
   * Unique identifier for the member account in UUID format. System-generated
   * at account creation and immutable thereafter. Used throughout the
   * platform as the primary reference for this member.
   */
  id: string & tags.Format<"uuid">;

  /**
   * Member's email address used for authentication and account management.
   * Must be unique across all member accounts in the system. Used for login
   * credentials, password recovery, and communication. This field is required
   * and immutable after account creation for data integrity.
   */
  email: string & tags.Format<"email">;

  /**
   * Timestamp when the member account was created in ISO 8601 UTC format.
   * System-generated at registration and immutable thereafter. Represents the
   * account's creation date used for audit trails and account age tracking.
   */
  created_at: string & tags.Format<"date-time">;

  /**
   * Timestamp when the member account was last modified in ISO 8601 UTC
   * format. Updated whenever account details change such as email updates,
   * password resets, or profile modifications. Tracks the most recent account
   * modification for audit purposes.
   */
  updated_at: string & tags.Format<"date-time">;

  /**
   * Current status of the member account controlling access permissions. The
   * account status determines whether the member can authenticate and create
   * content on the platform.
   */
  account_status: "active" | "suspended" | "banned";

  /**
   * Timestamp when the member account was soft-deleted or deactivated in ISO
   * 8601 UTC format. NULL for active accounts. Set when member deletes their
   * account or is deleted by administrators. Enables account recovery and
   * maintains audit trail of deletions for compliance purposes.
   */
  deleted_at?: (string & tags.Format<"date-time">) | null | undefined;
};
