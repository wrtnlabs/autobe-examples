/**
 * Registered contributor user account for the discussion board.
 *
 * Stores authentication credentials, profile information, and account status
 * for contributors who can create articles and post comments. Each contributor
 * account is unique by email and username.
 *
 * Password security is enforced through bcrypt hashing with minimum 12 salt
 * rounds. Email addresses are stored for authentication flows (login, password
 * reset, notifications). Account creation requires email verification before
 * enabling login.
 *
 * Contributors maintain separate session management from moderators for
 * security isolation. Violation history and account restrictions track
 * contributor standing and enforcement actions. Soft deletion preserves
 * contributor information while enabling account recovery within 6 months.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type IDiscussionBoardContributor = {
  /** Primary key. Unique identifier for the contributor account. */
  id: string & tags.Format<"uuid">;

  /**
   * Email address used for authentication and account recovery. Must be
   * unique across all contributor accounts. Valid email format required.
   */
  email: string & tags.Format<"email">;

  /**
   * Public display name for articles and comments. Must be unique across all
   * contributors. 3-50 characters, alphanumeric and underscore only.
   * Immutable after creation.
   */
  username: string &
    tags.MinLength<3> &
    tags.MaxLength<50> &
    tags.Pattern<"^[a-zA-Z0-9_]+$">;

  /**
   * Whether the contributor's email address has been verified through
   * confirmation link. Account cannot post articles or comments until
   * verified.
   */
  email_verified: boolean;

  /**
   * Current account status. Valid values: 'active' (normal operation),
   * 'suspended' (temporary ban), 'restricted' (limited posting), 'deleted'
   * (marked for deletion but retained for audit).
   */
  account_status: "active" | "suspended" | "restricted" | "deleted";

  /** Timestamp when the contributor account was created in ISO 8601 format. */
  created_at: string & tags.Format<"date-time">;

  /** Timestamp of the most recent account modification in ISO 8601 format. */
  updated_at: string & tags.Format<"date-time">;

  /**
   * Timestamp when contributor account was deleted (soft delete). Null for
   * active accounts. Retained for 6 months to enable recovery.
   */
  deleted_at?: (string & tags.Format<"date-time">) | null | undefined;

  /**
   * Timestamp of the most recent successful login. Null if account has never
   * been logged in.
   */
  last_login_at?: (string & tags.Format<"date-time">) | null | undefined;
};
