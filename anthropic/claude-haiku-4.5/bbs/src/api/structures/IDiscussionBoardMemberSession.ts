import { tags } from "typia";

/**
 * Authentication session representing a single login instance from a member.
 *
 * Tracks connection context including IP address, referrer URL, and access page
 * (href) for security auditing and fraud detection. Each session is created
 * upon successful authentication and persists until logout or automatic
 * expiration after 7 days.
 *
 * Members can maintain multiple concurrent sessions across different devices or
 * browsers. Sessions are immutable once created, with only expiration timestamp
 * subject to modification.
 *
 * Note: Member identification is maintained through authentication context
 * (JWT), not exposed in the session response body for security purposes.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type IDiscussionBoardMemberSession = {
  /**
   * Unique identifier for this session instance. Immutable UUID generated at
   * login.
   */
  id: string & tags.Format<"uuid">;

  /**
   * IP address (IPv4 or IPv6) from which the login originated. Used for
   * security tracking, fraud detection, and geographic login monitoring.
   */
  ip: string;

  /**
   * Full URL/URI where login occurred. Captures the page context of
   * authentication. Used for understanding member access patterns and
   * security context.
   */
  href: string & tags.Format<"uri">;

  /**
   * HTTP Referrer header value when login occurred. Indicates which page
   * referred member to authentication. May be empty string if referrer
   * unavailable.
   */
  referrer: string;

  /**
   * Session creation timestamp (login time) in UTC. Records when this
   * authentication session was established. Immutable.
   */
  created_at: string & tags.Format<"date-time">;

  /**
   * Session termination timestamp. Non-null when session ends (member logout
   * or expiration). Null for active sessions. Sessions expire automatically
   * after 7 days or when member explicitly logs out.
   */
  expired_at?: (string & tags.Format<"date-time">) | null | undefined;
};
