/**
 * Comprehensive moderation dashboard aggregating key metrics, recent actions,
 * and content review queues. Provides moderators with unified administrative
 * oversight of platform moderation activities, user violations, and pending
 * content items requiring review.
 *
 * The dashboard aggregates data from multiple tables to present key sections:
 * violation tracking showing users approaching automatic enforcement thresholds
 * (3 violations within 30 days triggers 7-day account suspension, 5 violations
 * within 90 days triggers permanent account ban), recent moderation actions
 * taken by any moderator with full audit trail, pending content flagged for
 * review (articles and comments with status other than 'published'), and
 * platform moderation statistics including total violations recorded, active
 * suspensions, and enforcement trends.
 *
 * Moderation enforcement operates on a tiered violation system. Violations are
 * recorded in the discussion_board_user_violations table with violation_type
 * (spam, harassment, inappropriate_content, off_topic, misinformation,
 * copyright_violation, illegal_content), violation_date for threshold
 * calculations, and links to associated moderation_log_id when enforcement
 * action is taken. Automatic enforcement triggers when violation thresholds are
 * exceeded. All actions are recorded in discussion_board_moderation_logs with
 * complete audit trail including moderator_id (who took action), action_type
 * (remove_article, remove_comment, suspend_user, ban_user, restore_article,
 * restore_comment, warning_issued, flag_content), target_type (article,
 * comment, member) with polymorphic targeting, timestamp of action, and reason
 * documenting rationale.
 *
 * Content status tracking uses discussion_board_articles.status and
 * discussion_board_comments.status: 'published' indicates active visible
 * content, 'archived' indicates moderator-hidden articles, 'deleted' indicates
 * user or moderator deletion, 'moderated' indicates content removed by
 * moderators. Dashboard displays all non-published content and provides
 * controls for moderators to review, restore, or permanently delete flagged
 * items.
 *
 * This dashboard enables rapid assessment of platform moderation state,
 * identification of problematic users through cumulative violation patterns,
 * content review for policy compliance, and tracking of enforcement actions for
 * compliance and transparency purposes. The operation requires moderator
 * authentication and is not accessible to regular members or guests.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
