/**
 * Authenticate a moderator administrator with email and password to access
 * moderation features and content management dashboards.
 *
 * Authenticate a moderator with email and password credentials to gain access
 * to moderation dashboards and administrative functions.
 *
 * This login operation is designed specifically for moderator-level
 * administrators who manage content moderation, user account enforcement, and
 * community guidelines. The operation accepts email and password, validates the
 * credentials against the discussion_board_moderators table, and upon
 * successful authentication, generates JWT tokens containing moderator identity
 * and permissions.
 *
 * The authentication process verifies that the provided email exists in the
 * discussion_board_moderators table, validates the password_hash matches the
 * stored hashed password, confirms the moderator's account_status is 'active',
 * and creates a new moderator session record in
 * discussion_board_moderator_sessions with connection metadata (IP address,
 * referrer, etc.).
 *
 * Successful login creates both an access token (15-minute expiration) and
 * refresh token (7-day expiration) that enable moderator access to protected
 * endpoints. The access token contains claims including moderator user ID,
 * email, account status, and a permissions array reflecting moderator
 * capabilities (content removal, user suspension, moderation dashboard access,
 * etc.).
 *
 * The system enforces security constraints: maximum of 5 failed login attempts
 * within 15 minutes triggers temporary account lockout (15 minutes); locked
 * moderators receive error indicating lock duration and option to unlock via
 * password reset. Password reset functionality is available for forgotten
 * credentials, generating time-limited reset tokens valid for 24 hours.
 *
 * Moderation login failures are logged for audit purposes, differentiating
 * between invalid email, incorrect password, suspended account, and locked
 * account scenarios. All session creation is recorded in
 * discussion_board_moderator_sessions with timestamp, IP address, and referrer
 * for security auditing. Successful authentication redirects to moderation
 * dashboard or requested protected resource.
 *
 * @param props.connection
 * @param props.body Moderator login credentials containing email address and
 *   password for authentication
 * @setHeader token.access Authorization
 *
 * @path /auth/moderator/login
 * @accessor api.functional.auth.moderator.login
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function login(
  connection: IConnection,
  props: login.Props,
): Promise<login.Response> {
  const output: login.Response =
    true === connection.simulate
      ? login.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...login.METADATA,
            path: login.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
