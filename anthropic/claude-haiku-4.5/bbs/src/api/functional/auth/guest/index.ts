import { IConnection } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";

import { IDiscussionBoardMember } from "../../../structures/IDiscussionBoardMember";

/**
 * Register an unauthenticated guest visitor for temporary read-only access to
 * the discussion board.
 *
 * The guest registration endpoint creates a temporary guest account that
 * provides immediate read-only access to the discussion board platform. Guest
 * users can view published articles and comments but cannot create content,
 * post comments, upload attachments, or perform any write operations on the
 * platform. This operation is designed to allow unauthenticated visitors to
 * explore the discussion board without requiring account credentials.
 *
 * Guest accounts are created with a temporary access token and refresh token
 * that allow the user to maintain their session while browsing content. The
 * system generates a unique identifier for each guest session, enabling the
 * platform to track anonymous visitors while respecting their privacy and
 * read-only access restrictions.
 *
 * Guest users have restricted permissions that prevent them from accessing
 * authenticated-only features. The discussion_board_guests table supports
 * storing basic guest session information including created timestamp for
 * session tracking and temporary token management.
 *
 * The registration process is public and requires no authentication, making it
 * accessible to any unauthenticated visitor. Guest accounts may have
 * configurable session durations and can be managed through moderation tools if
 * necessary.
 *
 * Related operations include guest token refresh (GET /auth/guest/refresh) for
 * maintaining active sessions and article retrieval endpoints (GET /articles)
 * that respect guest user read-only permissions.
 *
 * @param props.connection
 * @setHeader token.access Authorization
 *
 * @path /auth/guest/join
 * @accessor api.functional.auth.guest.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(connection: IConnection): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
export namespace join {
  export type Response = IDiscussionBoardMember.IAuthorized;

  export const METADATA = {
    method: "POST",
    path: "/auth/guest/join",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/guest/join";
  export const random = (): IDiscussionBoardMember.IAuthorized =>
    typia.random<IDiscussionBoardMember.IAuthorized>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}

/**
 * Refresh temporary access tokens for an active guest session.
 *
 * The guest token refresh endpoint enables guest users to renew their temporary
 * access tokens without requiring re-registration. When a guest's access token
 * expires, they can use their valid refresh token to obtain a new access token,
 * allowing them to continue browsing published articles and comments on the
 * discussion board.
 *
 * Guest refresh tokens are short-lived credentials that authenticate the
 * guest's existing session. The refresh operation validates the provided
 * refresh token and, if valid, generates a new access token while potentially
 * extending or rotating the refresh token itself. This mechanism allows guests
 * to maintain continuous read-only access while providing security through
 * token expiration.
 *
 * The guest session information stored in the discussion_board_guests table is
 * updated with new token information when refresh operations occur. The system
 * tracks session lifecycle through timestamps, ensuring that abandoned guest
 * sessions can be identified and cleaned up appropriately.
 *
 * Guest refresh tokens are subject to configurable expiration windows and may
 * be invalidated if suspicious activity is detected. The refresh operation
 * maintains the same read-only access restrictions as the original guest
 * registration, preventing any privilege escalation or write access.
 *
 * This operation is a critical component of the guest user authentication flow,
 * working in conjunction with the guest join operation (POST /auth/guest/join)
 * to provide seamless temporary access management. Guest sessions refreshed
 * through this endpoint retain their original created timestamp for session
 * duration tracking.
 *
 * @param props.connection
 * @setHeader token.access Authorization
 *
 * @path /auth/guest/refresh
 * @accessor api.functional.auth.guest.refresh
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
