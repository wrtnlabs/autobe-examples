/**
 * Renew guest user access tokens using a valid refresh token.
 *
 * This endpoint allows guest users to obtain new access tokens by presenting a
 * valid refresh token, extending their session without requiring
 * re-registration.
 *
 * Guest users receive both short-lived access tokens and longer-lived refresh
 * tokens upon registration. As the access token approaches expiration, guest
 * clients should call this endpoint with their refresh token to obtain a new
 * access token. This enables seamless, continuous access to the discussion
 * board without interrupting the browsing experience.
 *
 * The refresh operation validates that the provided refresh token is still
 * valid (not expired, not revoked). The system_configurations table defines
 * session timeout policies that govern how long refresh tokens remain valid.
 * Upon successful validation, the operation returns a new access token with a
 * fresh expiration time.
 *
 * Guest refresh tokens have longer expiration periods than access tokens,
 * typically spanning hours or days depending on system_configurations. This
 * prevents guests from being logged out during extended browsing sessions.
 * However, refresh tokens do eventually expire, at which point guests must
 * re-register through the /auth/guest/join endpoint.
 *
 * This operation requires a valid refresh token in the request and does not
 * require email, password, or any credentials beyond the refresh token itself.
 * The operation is idempotent: calling it multiple times with the same refresh
 * token produces the same result.
 *
 * Error scenarios include expired refresh tokens (guest must re-register),
 * revoked refresh tokens (guest session terminated), or malformed token
 * formats. The system maintains audit logs of token refresh operations for
 * security and compliance purposes.
 *
 * @param props.connection
 * @param props.body Guest token refresh request with the refresh token.
 * @setHeader token.access Authorization
 *
 * @path /auth/guest/refresh
 * @accessor api.functional.auth.guest.refresh
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
