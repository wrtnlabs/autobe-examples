/**
 * Register a new guest user account for temporary access to the discussion
 * board.
 *
 * This endpoint allows unauthenticated visitors to create a temporary guest
 * account for browsing published articles and reading comments on the
 * discussion board without requiring email verification or user credentials.
 *
 * Guest registration is a simplified onboarding process that creates a
 * temporary user session. Unlike contributor or moderator accounts, guest
 * accounts do not require email addresses, passwords, or account verification.
 * The system issues both an access token and a refresh token to enable
 * stateless API authentication while maintaining guest session management.
 *
 * Guest users created through this endpoint can access only public resources:
 * published articles and their associated comments. They cannot create
 * articles, post comments, upload files, or perform any moderation actions. The
 * guest account exists temporarily for the session duration and may be cleaned
 * up after extended inactivity based on system_configurations timeout
 * settings.
 *
 * The system_configurations table controls password and session behavior,
 * though guest accounts bypass password requirements entirely. Session timeout
 * is configurable through the 'session_timeout_minutes' setting, and guests
 * receive refresh tokens that must be renewed before token expiration.
 *
 * This operation is public and requires no authentication. Each guest
 * registration creates a fresh, isolated session without requiring any personal
 * information or account recovery mechanisms. The response includes both an
 * access token (short-lived, typically 15-60 minutes) and a refresh token
 * (longer-lived, used to obtain new access tokens without re-registering).
 *
 * Related operations include the guest token refresh endpoint
 * (/auth/guest/refresh) which renews expired access tokens using the refresh
 * token.
 *
 * @param props.connection
 * @param props.body Guest registration request with optional device identifier
 *   for session tracking.
 * @setHeader token.access Authorization
 *
 * @path /auth/guest/join
 * @accessor api.functional.auth.guest.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
