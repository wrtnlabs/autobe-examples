import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardMember } from "../../../structures/IDiscussionBoardMember";

/**
 * Create temporary guest account and issue initial JWT tokens for
 * unauthenticated visitors.
 *
 * Guest user registration endpoint enabling temporary account creation for
 * unauthenticated visitors. Guest accounts are designed for quick,
 * anonymous-style access without requiring email verification or password
 * setup. When a guest initiates registration, the system creates a temporary
 * guest account session, generates JWT tokens (access token: 15 minutes,
 * refresh token: 7 days), and returns both tokens for immediate authenticated
 * access.
 *
 * Guest registration operates differently from member registration: guests do
 * not provide email addresses or passwords, do not receive verification emails,
 * and create sessions that may be temporary and device-specific. The guest
 * session is tracked by IP address and referrer URL for basic analytics and
 * security monitoring. Guest accounts exist in the database but are marked as
 * guest-type sessions rather than permanent member accounts.
 *
 * Upon successful registration, the system returns a guest access token that
 * grants read-only permissions (view articles, read comments, search
 * discussions) while denying write operations (create articles, post comments,
 * upload files). The guest JWT token contains minimized claims compared to
 * member tokens, including only session ID and guest role indicator.
 *
 * Guest registration is a public endpoint requiring no pre-authentication and
 * intentionally designed for low friction and immediate access. This supports
 * the platform's objective of allowing anyone to browse discussions without
 * signup barriers while maintaining basic session tracking for moderation and
 * analytics purposes. Failed registration attempts (such as system errors
 * during token generation) return appropriate error responses with guidance for
 * retry.
 *
 * @param props.connection
 * @setHeader token.access Authorization
 *
 * @path /auth/guest/join
 * @accessor api.functional.auth.guest.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(connection: IConnection): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
export namespace join {
  export type Response = IDiscussionBoardMember.IAuthorized;

  export const METADATA = {
    method: "POST",
    path: "/auth/guest/join",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/guest/join";
  export const random = (): IDiscussionBoardMember.IAuthorized =>
    typia.random<IDiscussionBoardMember.IAuthorized>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}

/**
 * Refresh expired guest access token using valid refresh token.
 *
 * Guest token refresh endpoint enabling guest users to extend their session by
 * obtaining new JWT access tokens using valid refresh tokens. Guest refresh
 * tokens expire after 7 days, after which guests must complete registration
 * again via the join endpoint to regain access.
 *
 * When a guest user's 15-minute access token expires during active browsing,
 * the guest uses the refresh endpoint to obtain a new access token without
 * disrupting their current activity. The system validates the submitted refresh
 * token against stored session records, verifies the token has not expired and
 * has not been revoked, and generates a replacement access token with 15-minute
 * expiration.
 *
 * Guest refresh tokens are rotated for security: when a refresh token is used
 * successfully, the system issues both a new access token and a new refresh
 * token. The original refresh token may be invalidated to prevent unauthorized
 * token reuse if the token were compromised. This rotation pattern provides
 * security while maintaining guest session continuity.
 *
 * Refresh token expiration is set to 7 days from issue. If a guest's refresh
 * token has been unused for 7 days, it automatically expires and the guest must
 * register a new guest account via the join endpoint. This time limit ensures
 * that guest sessions do not persist indefinitely and prevents accumulation of
 * inactive guest sessions.
 *
 * Failed refresh attempts (invalid token, expired token, revoked token) return
 * specific error responses indicating the failure reason and prompting the
 * guest to re-register. Successful refresh operations return new tokens
 * immediately, allowing guest users to continue browsing without re-entering
 * the registration flow.
 *
 * @param props.connection
 * @param props.body Refresh token from guest's current session
 * @setHeader token.access Authorization
 *
 * @path /auth/guest/refresh
 * @accessor api.functional.auth.guest.refresh
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function refresh(
  connection: IConnection,
  props: refresh.Props,
): Promise<refresh.Response> {
  const output: refresh.Response =
    true === connection.simulate
      ? refresh.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...refresh.METADATA,
            path: refresh.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
export namespace refresh {
  export type Props = {
    /** Refresh token from guest's current session */
    body: IDiscussionBoardMember.IRefreshRequest;
  };
  export type Body = IDiscussionBoardMember.IRefreshRequest;
  export type Response = IDiscussionBoardMember.IAuthorized;

  export const METADATA = {
    method: "POST",
    path: "/auth/guest/refresh",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/guest/refresh";
  export const random = (): IDiscussionBoardMember.IAuthorized =>
    typia.random<IDiscussionBoardMember.IAuthorized>();
  export const simulate = (
    connection: IConnection,
    props: refresh.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: refresh.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
