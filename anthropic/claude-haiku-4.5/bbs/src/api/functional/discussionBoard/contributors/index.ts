import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardContributor } from "../../../structures/IDiscussionBoardContributor";

/**
 * Fetch complete information about a discussion board contributor account by
 * their unique identifier. This operation returns all relevant contributor
 * metadata including email address, username, account status, email
 * verification state, creation and modification timestamps, and last login
 * information.
 *
 * The contributor entity represents registered user accounts capable of
 * creating articles and posting comments on the discussion board. Each
 * contributor maintains unique email and username fields enforced at the
 * database level. Account status can be 'active' for normal operations,
 * 'suspended' for temporary bans, 'restricted' for limited posting permissions,
 * or 'deleted' for accounts marked for soft deletion.
 *
 * Security and access control are important considerations. The operation
 * validates the contributor ID exists and is accessible. Email addresses and
 * authentication-related timestamps should be treated as sensitive information
 * requiring appropriate authorization checks. This operation complements list
 * retrieval operations (PATCH /articles) and other contributor-related
 * endpoints.
 *
 * The response includes timestamp information for account creation, last
 * modification, last successful login, and password changes. The deleted_at
 * field indicates soft deletion status; accounts are retained for 6 months
 * after deletion to enable recovery before permanent purge. Email verification
 * status determines whether the account can perform authenticated actions like
 * posting articles or comments.
 *
 * @param props.connection
 * @param props.contributorId Unique identifier (UUID) of the target discussion
 *   board contributor
 * @path /discussionBoard/contributors/:contributorId
 * @accessor api.functional.discussionBoard.contributors.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique identifier (UUID) of the target discussion board contributor */
    contributorId: string & tags.Format<"uuid">;
  };
  export type Response = IDiscussionBoardContributor;

  export const METADATA = {
    method: "GET",
    path: "/discussionBoard/contributors/:contributorId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/contributors/${encodeURIComponent(props.contributorId ?? "null")}`;
  export const random = (): IDiscussionBoardContributor =>
    typia.random<IDiscussionBoardContributor>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("contributorId")(() => typia.assert(props.contributorId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
