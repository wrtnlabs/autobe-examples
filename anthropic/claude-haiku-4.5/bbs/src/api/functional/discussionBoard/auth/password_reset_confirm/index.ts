import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardMemberSession } from "../../../../structures/IDiscussionBoardMemberSession";

/**
 * Confirm password reset with new password using reset token.
 *
 * Completes the password reset workflow for members who have forgotten their
 * access credentials. When a member initiates password recovery from the login
 * page, they receive a password reset email containing a unique reset token
 * valid for 24 hours. This endpoint validates that token, confirms its
 * expiration status, and applies the newly provided password to the member's
 * account.
 *
 * Password reset tokens are single-use, time-limited, and tied to the specific
 * member email address. The system validates token validity and ensures it
 * matches the requesting member. New passwords must meet security requirements
 * including minimum length (8 characters) and complexity (at least one
 * uppercase letter, one lowercase letter, and one number).
 *
 * Upon successful password change, the system invalidates all existing
 * authentication sessions for that member across all devices and browsers as a
 * security measure. The member must log in again with their new password. This
 * prevents unauthorized access if an account has been compromised. The system
 * records the password change timestamp for audit trail and security compliance
 * purposes.
 *
 * If the reset token is invalid, expired, has already been used, or the new
 * password fails validation, the system rejects the request with specific error
 * messaging. Members with invalid or expired tokens can request a new password
 * reset link from the login page.
 *
 * @param props.connection
 * @param props.body Password reset confirmation request containing reset token
 *   and new password
 * @path /discussionBoard/auth/password-reset-confirm
 * @accessor api.functional.discussionBoard.auth.password_reset_confirm.confirmPasswordReset
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function confirmPasswordReset(
  connection: IConnection,
  props: confirmPasswordReset.Props,
): Promise<confirmPasswordReset.Response> {
  return true === connection.simulate
    ? confirmPasswordReset.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...confirmPasswordReset.METADATA,
          path: confirmPasswordReset.path(),
          status: null,
        },
        props.body,
      );
}
export namespace confirmPasswordReset {
  export type Props = {
    /**
     * Password reset confirmation request containing reset token and new
     * password
     */
    body: IDiscussionBoardMemberSession.IPasswordResetConfirmRequest;
  };
  export type Body = IDiscussionBoardMemberSession.IPasswordResetConfirmRequest;
  export type Response =
    IDiscussionBoardMemberSession.IPasswordResetConfirmResponse;

  export const METADATA = {
    method: "POST",
    path: "/discussionBoard/auth/password-reset-confirm",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/discussionBoard/auth/password-reset-confirm";
  export const random =
    (): IDiscussionBoardMemberSession.IPasswordResetConfirmResponse =>
      typia.random<IDiscussionBoardMemberSession.IPasswordResetConfirmResponse>();
  export const simulate = (
    connection: IConnection,
    props: confirmPasswordReset.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: confirmPasswordReset.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
