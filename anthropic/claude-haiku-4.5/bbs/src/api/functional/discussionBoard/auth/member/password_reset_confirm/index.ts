import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardMember } from "../../../../../structures/IDiscussionBoardMember";

/**
 * Confirm password reset and set new password for a discussion board member.
 *
 * Completes the password reset workflow by validating the reset token received
 * in the password reset email and allowing the member to set a new password.
 * When a member clicks the reset link in their email, they are directed to a
 * form containing the reset token. The member enters a new password and
 * confirmation, then submits this operation.
 *
 * Token validation: The system validates that the reset token is valid (matches
 * stored token), has not expired (1-hour window from request), and has not been
 * previously used. If the token is invalid or expired, the operation returns an
 * error directing the member to request a new password reset.
 *
 * Password requirements enforcement: The new password must meet all complexity
 * requirements: minimum 8 characters, at least one uppercase letter, at least
 * one lowercase letter, at least one numeric digit, at least one special
 * character from {!@#$%^&*}. The password cannot contain the member's email
 * address or username. The password cannot match any of the member's last 3
 * passwords (password reuse prevention). If the new password fails any
 * requirement, the operation returns a specific error message indicating which
 * requirements are not met.
 *
 * Password confirmation: The new password must exactly match the password
 * confirmation field. If they do not match, the operation returns an error and
 * requires the user to re-enter both password fields.
 *
 * Database updates: Upon successful validation, the system hashes the new
 * password using bcrypt with minimum 12 salt rounds and updates the
 * password_hash field in the discussion_board_members table. The updated_at
 * timestamp is updated to the current time. The reset token is invalidated
 * (removed from storage) to prevent reuse.
 *
 * Session invalidation: All existing authentication sessions for the member are
 * immediately terminated. This forces the member to log in again on all devices
 * using their new password. All existing JWT refresh tokens are blacklisted.
 *
 * Notification: A confirmation email is sent to the member's registered email
 * address confirming that their password has been reset.
 *
 * Relationship to discussion_board_members table: This operation updates the
 * password_hash and updated_at fields for the member identified by the reset
 * token. The operation indirectly affects discussion_board_member_sessions
 * table by invalidating sessions.
 *
 * This is the second operation in a two-step password reset process. The
 * password-reset-request operation must be executed first to generate and email
 * the reset token.
 *
 * @param props.connection
 * @param props.body Password reset token and new password details for
 *   confirmation
 * @path /discussionBoard/auth/member/password-reset-confirm
 * @accessor api.functional.discussionBoard.auth.member.password_reset_confirm.confirmPasswordReset
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function confirmPasswordReset(
  connection: IConnection,
  props: confirmPasswordReset.Props,
): Promise<confirmPasswordReset.Response> {
  return true === connection.simulate
    ? confirmPasswordReset.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...confirmPasswordReset.METADATA,
          path: confirmPasswordReset.path(),
          status: null,
        },
        props.body,
      );
}
export namespace confirmPasswordReset {
  export type Props = {
    /** Password reset token and new password details for confirmation */
    body: IDiscussionBoardMember.IPasswordResetConfirm;
  };
  export type Body = IDiscussionBoardMember.IPasswordResetConfirm;
  export type Response = IDiscussionBoardMember.IPasswordResetConfirmResponse;

  export const METADATA = {
    method: "POST",
    path: "/discussionBoard/auth/member/password-reset-confirm",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () =>
    "/discussionBoard/auth/member/password-reset-confirm";
  export const random =
    (): IDiscussionBoardMember.IPasswordResetConfirmResponse =>
      typia.random<IDiscussionBoardMember.IPasswordResetConfirmResponse>();
  export const simulate = (
    connection: IConnection,
    props: confirmPasswordReset.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: confirmPasswordReset.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
