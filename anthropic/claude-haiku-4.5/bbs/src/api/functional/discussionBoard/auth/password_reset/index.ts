import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardMemberSession } from "../../../../structures/IDiscussionBoardMemberSession";

/**
 * Initiate password reset workflow by email verification.
 *
 * This operation initiates the password recovery workflow for members who have
 * forgotten their login password. Members provide their email address
 * registered with their account, and the system sends secure password reset
 * instructions.
 *
 * When a member requests password reset, THE system SHALL:
 *
 * - Accept email address from the request body
 * - Validate email format (user@domain.com pattern)
 * - Search discussion_board_members table for account with matching email
 * - IF email not found, THE system SHALL display "If an account exists with this
 *   email address, you will receive password reset instructions within 5
 *   minutes." (security best practice - doesn't reveal whether email is
 *   registered)
 * - IF email found, THE system SHALL:
 * - Generate cryptographically secure reset token with 24-hour expiration
 * - Store reset token in secure temporary storage (not persisted long-term in
 *   main tables)
 * - Compose password reset email with reset link containing token
 * - Send email to member's registered email address
 * - Log the password reset request for audit purposes
 *
 * The password reset email SHALL contain:
 *
 * - Clear instructions for resetting password
 * - Secure reset link with token (valid for 24 hours)
 * - Member's email address for confirmation
 * - Security warning: "If you didn't request this, you can ignore this email"
 * - Support contact information
 *
 * After email is sent, THE system SHALL display: "If an account exists with
 * this email address, you will receive password reset instructions within 5
 * minutes. Please check your inbox and spam folder."
 *
 * When member clicks reset link in email, THE system SHALL display password
 * reset form allowing them to:
 *
 * - Enter new password (minimum 6 characters, must contain letter and number)
 * - Confirm new password by re-entering
 *
 * When member submits new password, THE system SHALL:
 *
 * - Validate reset token is still valid (not expired, not used previously)
 * - Validate new password meets security requirements
 * - Hash new password using industry-standard algorithm (bcrypt, scrypt, or
 *   similar)
 * - Update password_hash in discussion_board_members table
 * - Invalidate all existing session tokens for the member (forcing re-login on
 *   all devices) by marking all discussion_board_member_sessions records with
 *   current timestamp in expired_at field
 * - Clear the reset token so it cannot be reused
 * - Display success message: "Password successfully reset. Please log in with
 *   your new password."
 * - Redirect to login page
 *
 * This operation is available to unauthenticated users. Only the email
 * verification step is required - no authentication token needed. Security is
 * maintained through email verification and time-limited tokens.
 *
 * @param props.connection
 * @param props.body Email address of the account for which password reset is
 *   requested
 * @path /discussionBoard/auth/password-reset
 * @accessor api.functional.discussionBoard.auth.password_reset.resetPassword
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function resetPassword(
  connection: IConnection,
  props: resetPassword.Props,
): Promise<void> {
  return true === connection.simulate
    ? resetPassword.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...resetPassword.METADATA,
          path: resetPassword.path(),
          status: null,
        },
        props.body,
      );
}
export namespace resetPassword {
  export type Props = {
    /** Email address of the account for which password reset is requested */
    body: IDiscussionBoardMemberSession.IPasswordResetRequest;
  };
  export type Body = IDiscussionBoardMemberSession.IPasswordResetRequest;

  export const METADATA = {
    method: "POST",
    path: "/discussionBoard/auth/password-reset",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/discussionBoard/auth/password-reset";
  export const random = (): void => typia.random<void>();
  export const simulate = (
    connection: IConnection,
    props: resetPassword.Props,
  ): void => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: resetPassword.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
