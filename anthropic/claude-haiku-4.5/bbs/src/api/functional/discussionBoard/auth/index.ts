/**
 * Register a new member account for the discussion board.
 *
 * Create a new user account in the discussion board platform. This operation
 * registers a new member by collecting email address and password credentials,
 * validating both fields meet security requirements, ensuring email uniqueness
 * across the system, and creating a member record with hashed password for
 * secure storage.
 *
 * Email addresses must be unique in the system - attempting to register with an
 * already-registered email will be rejected with a specific error message
 * directing the user to login or use a different email.
 *
 * Passwords are hashed using industry-standard algorithms (bcrypt, scrypt, or
 * equivalent) before storage. The plaintext password is never stored. Password
 * requirements include minimum 8 characters, at least one uppercase letter, at
 * least one lowercase letter, and at least one number.
 *
 * Upon successful registration, the system creates a new
 * discussion_board_members record with the provided email, hashed password,
 * creation timestamp, and initial account_status of 'active' allowing immediate
 * participation. The operation returns the created member information (without
 * sensitive password hash) confirming successful account creation.
 *
 * The registration operation does not require authentication - it is available
 * to all unauthenticated users. Registration initiates the member lifecycle and
 * enables subsequent authentication via the login operation. Members can
 * immediately create articles, post comments, and upload attachments upon
 * successful registration.
 *
 * @param props.connection
 * @param props.body User credentials for new account creation
 * @path /discussionBoard/auth/register
 * @accessor api.functional.discussionBoard.auth.register
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function register(
  connection: IConnection,
  props: register.Props,
): Promise<register.Response> {
  return true === connection.simulate
    ? register.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...register.METADATA,
          path: register.path(),
          status: null,
        },
        props.body,
      );
}
export namespace register {
  export type Props = {
    /** User credentials for new account creation */
    body: IDiscussionBoardMember.IRegisterRequest;
  };
  export type Body = IDiscussionBoardMember.IRegisterRequest;
  export type Response = IDiscussionBoardMember.IRegisterResponse;

  export const METADATA = {
    method: "POST",
    path: "/discussionBoard/auth/register",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/discussionBoard/auth/register";
  export const random = (): IDiscussionBoardMember.IRegisterResponse =>
    typia.random<IDiscussionBoardMember.IRegisterResponse>();
  export const simulate = (
    connection: IConnection,
    props: register.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: register.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
