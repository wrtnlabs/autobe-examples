import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardPasswordResetRequest } from "../../../../structures/IDiscussionBoardPasswordResetRequest";

/**
 * Initiate a password reset request by providing the email address associated
 * with a contributor account. This operation validates that the email address
 * exists in the system and generates a secure, time-limited token for password
 * recovery.
 *
 * The password reset token is sent via email to the registered address and is
 * valid for exactly 30 minutes from generation. The token is single-use and
 * becomes invalid after one successful password reset or after the 30-minute
 * expiration window closes. If a contributor requests multiple resets, only the
 * most recent token remains valid.
 *
 * Security considerations include rate limiting to prevent brute-force
 * enumeration attacks on email addresses. The operation does not reveal whether
 * an email address is registered in the system (returns success regardless) to
 * prevent account enumeration. Failed password resets due to expired or invalid
 * tokens should not expose token validity information.
 *
 * This operation works in conjunction with the reset-password endpoint, which
 * must be called with the token and new password to complete the account
 * recovery process. Contributors with suspended or deleted accounts cannot
 * request password resets, and the system returns generic responses for these
 * cases to avoid leaking account status information.
 *
 * @param props.connection
 * @param props.body Email address of the contributor account for which password
 *   reset is requested
 * @path /discussionBoard/auth/request-password-reset
 * @accessor api.functional.discussionBoard.auth.request_password_reset.requestPasswordReset
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function requestPasswordReset(
  connection: IConnection,
  props: requestPasswordReset.Props,
): Promise<void> {
  return true === connection.simulate
    ? requestPasswordReset.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...requestPasswordReset.METADATA,
          path: requestPasswordReset.path(),
          status: null,
        },
        props.body,
      );
}
export namespace requestPasswordReset {
  export type Props = {
    /**
     * Email address of the contributor account for which password reset is
     * requested
     */
    body: IDiscussionBoardPasswordResetRequest.ICreate;
  };
  export type Body = IDiscussionBoardPasswordResetRequest.ICreate;

  export const METADATA = {
    method: "POST",
    path: "/discussionBoard/auth/request-password-reset",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/discussionBoard/auth/request-password-reset";
  export const random = (): void => typia.random<void>();
  export const simulate = (
    connection: IConnection,
    props: requestPasswordReset.Props,
  ): void => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: requestPasswordReset.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
