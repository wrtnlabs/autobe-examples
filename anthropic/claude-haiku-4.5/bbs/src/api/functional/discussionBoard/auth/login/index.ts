import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardMember } from "../../../../structures/IDiscussionBoardMember";

/**
 * Authenticate a member or moderator and issue JWT authentication token.
 *
 * Authenticate registered users (members or moderators) by validating email and
 * password credentials against secure hashed values. Upon successful
 * authentication, the system issues a JWT token enabling authenticated access
 * to member and moderator functionality throughout the platform.
 *
 * The login operation serves two user types with separate account systems:
 * regular members (discussion_board_members table) and moderators
 * (discussion_board_moderators table). The system first checks for member
 * accounts, then moderator accounts if member lookup fails, to determine which
 * actor type is logging in. The returned JWT token reflects the appropriate
 * role (member or moderator) with corresponding permissions.
 *
 * Security measures include rate limiting preventing brute force attacks
 * (maximum 5 failed login attempts within 15-minute window triggers temporary
 * 15-minute account lock) and generic error messages that don't reveal whether
 * email exists or password was incorrect. This prevents attackers from
 * enumerating valid email addresses through repeated login attempts.
 *
 * Upon successful credential validation, the system creates a session record in
 * discussion_board_member_sessions (for members) or
 * discussion_board_moderator_sessions (for moderators) capturing connection
 * metadata: IP address from request, href of page where login occurred, and
 * HTTP referrer URL. This session tracking enables security auditing and
 * detection of suspicious access patterns.
 *
 * The JWT token returned includes claims: userId (UUID), userEmail (email
 * address), userName (display name if available), role ('member' or
 * 'moderator'), permissions array showing capabilities granted by role,
 * issuedAt (current timestamp), expiresAt (current time + 15 minutes), and jti
 * (unique JWT ID for tracking and revocation). The token expiration of 15
 * minutes requires refresh tokens or re-authentication for extended sessions.
 *
 * Failed login attempts with unregistered email address display: 'Email address
 * not found in our system. Please check your email or register for a new
 * account.' Accounts that haven't verified email (if verification required)
 * display: 'Your email address has not been verified. Please check your inbox
 * for a verification link.' Suspended accounts display: 'Your account is
 * currently suspended. Please contact support at [email] for more information.'
 * Permanently banned accounts display: 'Your account has been banned and access
 * is no longer available.'
 *
 * Successful login returns the JWT token in the response, which clients must
 * include in the Authorization header (Bearer scheme) for all subsequent
 * authenticated API requests. The token must be stored securely (httpOnly
 * cookies or localStorage based on implementation) and refreshed before
 * expiration using refresh tokens or by initiating new login.
 *
 * @param props.connection
 * @param props.body Email and password credentials for authentication
 * @path /discussionBoard/auth/login
 * @accessor api.functional.discussionBoard.auth.login.signIn
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function signIn(
  connection: IConnection,
  props: signIn.Props,
): Promise<signIn.Response> {
  return true === connection.simulate
    ? signIn.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...signIn.METADATA,
          path: signIn.path(),
          status: null,
        },
        props.body,
      );
}
export namespace signIn {
  export type Props = {
    /** Email and password credentials for authentication */
    body: IDiscussionBoardMember.ILoginRequest;
  };
  export type Body = IDiscussionBoardMember.ILoginRequest;
  export type Response = IDiscussionBoardMember.ILoginResponse;

  export const METADATA = {
    method: "POST",
    path: "/discussionBoard/auth/login",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/discussionBoard/auth/login";
  export const random = (): IDiscussionBoardMember.ILoginResponse =>
    typia.random<IDiscussionBoardMember.ILoginResponse>();
  export const simulate = (
    connection: IConnection,
    props: signIn.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: signIn.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
