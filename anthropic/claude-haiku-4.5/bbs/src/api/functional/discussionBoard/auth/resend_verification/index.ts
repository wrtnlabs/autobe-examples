import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardMemberSession } from "../../../../structures/IDiscussionBoardMemberSession";

/**
 * Resend email verification message to member's registered email address.
 *
 * This operation enables members to request a new email verification message
 * when their original verification email is lost, expired, or not received. The
 * system validates that the member account exists and has not already been
 * email-verified before generating a fresh verification token.
 *
 * When a member requests verification email resend, the system SHALL generate a
 * new verification token with 24-hour expiration, construct a verification
 * email with the new link, and send it to the member's registered email
 * address. The operation preserves the original account creation timestamp and
 * all other account data unchanged.
 *
 * This endpoint serves the authentication workflow by allowing members to
 * complete email verification at any time, not just during initial
 * registration. Members typically use this endpoint when they did not receive
 * the original verification email, the link expired, or they accidentally
 * deleted the email.
 *
 * The operation validates the email address is registered in the system before
 * sending the verification email. To prevent abuse, the system SHALL limit
 * resend requests to maximum 5 per hour per email address to prevent abuse and
 * protect against denial-of-service attacks.
 *
 * Upon successful resend, the member receives an email at their registered
 * address containing a verification link valid for 24 hours. Clicking the link
 * verifies their email address and activates their account for full membership
 * participation including article creation and commenting.
 *
 * @param props.connection
 * @param props.body Member's email address requesting verification email resend
 * @path /discussionBoard/auth/resend-verification
 * @accessor api.functional.discussionBoard.auth.resend_verification.resendVerification
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function resendVerification(
  connection: IConnection,
  props: resendVerification.Props,
): Promise<resendVerification.Response> {
  return true === connection.simulate
    ? resendVerification.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...resendVerification.METADATA,
          path: resendVerification.path(),
          status: null,
        },
        props.body,
      );
}
export namespace resendVerification {
  export type Props = {
    /** Member's email address requesting verification email resend */
    body: IDiscussionBoardMemberSession.IResendVerificationRequest;
  };
  export type Body = IDiscussionBoardMemberSession.IResendVerificationRequest;
  export type Response =
    IDiscussionBoardMemberSession.IResendVerificationResponse;

  export const METADATA = {
    method: "POST",
    path: "/discussionBoard/auth/resend-verification",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/discussionBoard/auth/resend-verification";
  export const random =
    (): IDiscussionBoardMemberSession.IResendVerificationResponse =>
      typia.random<IDiscussionBoardMemberSession.IResendVerificationResponse>();
  export const simulate = (
    connection: IConnection,
    props: resendVerification.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: resendVerification.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
