import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardMemberSession } from "../../../../structures/IDiscussionBoardMemberSession";

/**
 * Verify member email address using verification token from registration email.
 *
 * Completes the email verification workflow for newly registered discussion
 * board members. When a member registers, the system sends a verification email
 * containing a unique token valid for 24 hours. This endpoint validates that
 * token and activates the member's account, enabling them to log in and
 * participate in discussions.
 *
 * The verification process confirms email ownership and prevents account
 * creation with invalid email addresses. Verification tokens are single-use and
 * tied to the specific email address registered during account creation. The
 * system validates token expiration (24-hour window) and confirms the token has
 * not been previously used.
 *
 * Upon successful verification, the member account status is updated to
 * 'active', and the member can immediately log in using their registered email
 * and password. The system records the verification timestamp for audit trail
 * purposes.
 *
 * If the verification token is invalid, expired, or has already been used, the
 * system rejects the request with specific error messaging guiding the member
 * toward obtaining a new verification link or contacting support.
 *
 * @param props.connection
 * @param props.body Email verification request containing the token from the
 *   verification email link
 * @path /discussionBoard/auth/verify-email
 * @accessor api.functional.discussionBoard.auth.verify_email.verifyEmail
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function verifyEmail(
  connection: IConnection,
  props: verifyEmail.Props,
): Promise<verifyEmail.Response> {
  return true === connection.simulate
    ? verifyEmail.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...verifyEmail.METADATA,
          path: verifyEmail.path(),
          status: null,
        },
        props.body,
      );
}
export namespace verifyEmail {
  export type Props = {
    /**
     * Email verification request containing the token from the verification
     * email link
     */
    body: IDiscussionBoardMemberSession.IVerifyEmailRequest;
  };
  export type Body = IDiscussionBoardMemberSession.IVerifyEmailRequest;
  export type Response = IDiscussionBoardMemberSession.IVerifyEmailResponse;

  export const METADATA = {
    method: "POST",
    path: "/discussionBoard/auth/verify-email",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/discussionBoard/auth/verify-email";
  export const random =
    (): IDiscussionBoardMemberSession.IVerifyEmailResponse =>
      typia.random<IDiscussionBoardMemberSession.IVerifyEmailResponse>();
  export const simulate = (
    connection: IConnection,
    props: verifyEmail.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: verifyEmail.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
