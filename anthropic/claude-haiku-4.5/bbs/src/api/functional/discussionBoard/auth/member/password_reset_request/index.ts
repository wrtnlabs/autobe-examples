import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardMember } from "../../../../../structures/IDiscussionBoardMember";

/**
 * Request password reset via email for a discussion board member account.
 *
 * Initiates the password reset workflow for members who have forgotten their
 * password. When a member provides their email address, the system validates
 * that an account exists with that email, generates a cryptographically secure
 * password reset token with 1-hour expiration, and sends a password reset email
 * containing a secure reset link and instructions.
 *
 * Security considerations: The system deliberately does not reveal whether an
 * account exists with the provided email address. This prevents account
 * enumeration attacks where bad actors could discover which email addresses are
 * registered. The confirmation message displayed to the user is identical
 * regardless of whether the email exists in the system.
 *
 * The password reset token is valid for exactly 1 hour from generation. After 1
 * hour, the token expires and the user must request a new password reset. The
 * reset token is stored securely and validated when the user clicks the reset
 * link in their email.
 *
 * This operation relates to the discussion_board_members table, specifically
 * the email field which must match exactly (case-insensitive) and the
 * password_hash field which will be updated when the member confirms the reset.
 * The system records the password reset request timestamp for security audit
 * purposes.
 *
 * The password reset workflow is the first step in a two-step process. After
 * the member receives the email and clicks the reset link, they proceed to the
 * password-reset-confirm endpoint to set their new password. The reset token
 * ensures that only the member who owns the email address can complete the
 * password reset.
 *
 * Rate limiting is enforced to prevent abuse: members can request password
 * reset emails a maximum of once per 5 minutes per email address.
 *
 * @param props.connection
 * @param props.body Member email address for password reset request
 * @path /discussionBoard/auth/member/password-reset-request
 * @accessor api.functional.discussionBoard.auth.member.password_reset_request.requestPasswordReset
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function requestPasswordReset(
  connection: IConnection,
  props: requestPasswordReset.Props,
): Promise<requestPasswordReset.Response> {
  return true === connection.simulate
    ? requestPasswordReset.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...requestPasswordReset.METADATA,
          path: requestPasswordReset.path(),
          status: null,
        },
        props.body,
      );
}
export namespace requestPasswordReset {
  export type Props = {
    /** Member email address for password reset request */
    body: IDiscussionBoardMember.IPasswordResetRequest;
  };
  export type Body = IDiscussionBoardMember.IPasswordResetRequest;
  export type Response = IDiscussionBoardMember.IPasswordResetRequestResponse;

  export const METADATA = {
    method: "POST",
    path: "/discussionBoard/auth/member/password-reset-request",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () =>
    "/discussionBoard/auth/member/password-reset-request";
  export const random =
    (): IDiscussionBoardMember.IPasswordResetRequestResponse =>
      typia.random<IDiscussionBoardMember.IPasswordResetRequestResponse>();
  export const simulate = (
    connection: IConnection,
    props: requestPasswordReset.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: requestPasswordReset.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
