import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardArticle } from "../../../structures/IDiscussionBoardArticle";
import { IPageIDiscussionBoardSearchResult } from "../../../structures/IPageIDiscussionBoardSearchResult";

/**
 * Search across articles and comments with filtering and pagination.
 *
 * Retrieve search results for articles and comments based on keyword queries
 * across the discussion board platform.
 *
 * This operation provides comprehensive search functionality allowing members
 * to discover relevant discussions and comments. The search supports full-text
 * matching across article titles, article bodies, and comment content. Results
 * are returned with pagination support to handle large result sets
 * efficiently.
 *
 * Users can filter results by category, article status
 * (published/pending/rejected), member, date ranges, and other criteria to
 * narrow search results. Results are sorted by relevance by default, with
 * options to sort chronologically (newest/oldest) or by engagement metrics such
 * as view count and comment count.
 *
 * The search feature is essential for content discovery on the platform,
 * enabling members to find existing discussions before creating new articles
 * and allowing them to follow conversations of interest. Search results include
 * both published articles (visible to all members) and may include comments to
 * surface relevant discussion threads.
 *
 * Security considerations: Only published articles and non-deleted comments are
 * returned in search results. Articles with rejected or pending status are not
 * searchable by regular members. The operation respects article visibility
 * rules and member permissions—deleted accounts' content is excluded from
 * results. Rate limiting applies to prevent search abuse and excessive database
 * queries.
 *
 * @param props.connection
 * @param props.body Search criteria including keywords, filters, pagination
 *   parameters, and sorting options
 * @path /discussionBoard/search
 * @accessor api.functional.discussionBoard.search.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Search criteria including keywords, filters, pagination parameters,
     * and sorting options
     */
    body: IDiscussionBoardArticle.IRequest;
  };
  export type Body = IDiscussionBoardArticle.IRequest;
  export type Response = IPageIDiscussionBoardSearchResult;

  export const METADATA = {
    method: "PATCH",
    path: "/discussionBoard/search",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/discussionBoard/search";
  export const random = (): IPageIDiscussionBoardSearchResult =>
    typia.random<IPageIDiscussionBoardSearchResult>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
