import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardArticle } from "../../../../structures/IDiscussionBoardArticle";
import { IPageIDiscussionBoardArticle } from "../../../../structures/IPageIDiscussionBoardArticle";

/**
 * Search and retrieve a filtered, paginated list of articles matching search
 * criteria.
 *
 * Search for articles across the discussion board platform with comprehensive
 * filtering and sorting options. This operation enables users (guests and
 * members) to discover articles based on keywords, category selection, author
 * filtering, and date ranges. The search supports full-text matching on article
 * titles and content bodies, returning results ranked by relevance with title
 * matches weighted higher than content matches.
 *
 * The operation supports flexible pagination with configurable page sizes and
 * result ordering. Users can sort search results by relevance (default),
 * creation date (newest or oldest first), view count, or comment count. Search
 * respects visibility rules: guests and members see only published articles,
 * while moderators can search across all articles including archived ones.
 *
 * Security considerations include rate limiting to prevent search abuse
 * (maximum 100 queries per hour per user) and input validation to prevent
 * injection attacks. The search automatically escapes special characters and
 * supports standard phrase searching using quotation marks for exact matches.
 * Large result sets are paginated to maintain performance with typical queries
 * returning results within 3 seconds.
 *
 * This operation integrates with the discussion_board_articles and
 * discussion_board_categories tables from the Prisma schema. Related articles
 * are filtered by category, and article information includes creation
 * timestamp, last modification date, view count, comment count, and author
 * reference. The operation supports deep filtering by author email or user ID
 * for discovering specific member's contributions.
 *
 * Results are returned as article summaries optimized for list display,
 * including title, author name, creation date, category, excerpt preview of
 * first 200 characters, view count, and comment count. Each result includes a
 * direct link to view the full article. When no articles match the search
 * criteria, the system returns an empty results array with total count of zero
 * and suggests alternative search terms or category browsing.
 *
 * @param props.connection
 * @param props.body Search criteria, filtering options, pagination parameters,
 *   and sorting preferences for article discovery
 * @path /discussionBoard/search/articles
 * @accessor api.functional.discussionBoard.search.articles.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Search criteria, filtering options, pagination parameters, and
     * sorting preferences for article discovery
     */
    body: IDiscussionBoardArticle.IRequest;
  };
  export type Body = IDiscussionBoardArticle.IRequest;
  export type Response = IPageIDiscussionBoardArticle.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/discussionBoard/search/articles",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/discussionBoard/search/articles";
  export const random = (): IPageIDiscussionBoardArticle.ISummary =>
    typia.random<IPageIDiscussionBoardArticle.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
