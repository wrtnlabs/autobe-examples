/**
 * Create a new comment on a published discussion board article, enabling
 * contributors to participate in discussions. This operation accepts comment
 * content and optional image attachments, validates the article exists and is
 * published, and immediately publishes the comment without moderator approval.
 *
 * Comments support hierarchical threading where contributors can reply directly
 * to articles or reply to specific comments. When replying to a comment, the
 * parentCommentId field establishes the relationship and enables proper thread
 * organization. Top-level comments have no parent and appear at the article
 * level.
 *
 * Each comment maintains creation and modification timestamps, contributor
 * attribution, and soft deletion support. The operation automatically
 * initializes the edit count to zero and reply count to zero for new comments.
 * Comments include cached publication status of the parent article at creation
 * time for audit purposes.
 *
 * Optional image attachments (JPG, PNG, GIF formats) can be included with each
 * comment, limited to 2 files per comment with 5MB size limits. The system
 * validates attachment MIME types and stores metadata including original
 * filenames and file sizes for proper display and storage management.
 *
 * The operation requires authentication to identify the commenting contributor.
 * Security considerations include rate limiting for comment creation,
 * validation of article publication status, and protection against concurrent
 * modification of parent articles or comments.
 *
 * @param props.connection
 * @param props.articleId Unique identifier of the target article being
 *   commented on
 * @param props.body Comment content and optional attachment data for creating a
 *   new comment
 * @path /discussionBoard/contributor/articles/:articleId/comments
 * @accessor api.functional.discussionBoard.contributor.articles.comments.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function create(
  connection: IConnection,
  props: create.Props,
): Promise<create.Response> {
  return true === connection.simulate
    ? create.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...create.METADATA,
          path: create.path(props),
          status: null,
        },
        props.body,
      );
}
