/**
 * Retrieve the authenticated user's complete profile information.
 *
 * Fetch the current authenticated user's profile including account details,
 * email, username, account status, and verification state.
 *
 * This operation returns the authenticated user's complete profile information
 * from either the discussion_board_contributors or discussion_board_moderators
 * table depending on their user type. The response includes email address,
 * username, account status (active, suspended, restricted, or deleted), email
 * verification state, and timestamp information for account creation and last
 * login.
 *
 * For contributors, the response includes contributor-specific metadata such as
 * last login timestamp and password change timestamp. For moderators, the
 * response includes moderation tier information and last access to the
 * moderation dashboard.
 *
 * Security considerations: This operation requires authentication via JWT
 * token. The endpoint only returns profile information for the authenticated
 * user; cross-user profile access is not permitted. Sensitive information such
 * as password hash is never included in the response. The operation respects
 * the user's account status (suspended accounts can still view their own
 * profile) and returns current data reflecting any recent moderator actions or
 * account changes.
 *
 * Related operations: The PUT /profile endpoint allows users to update their
 * own profile information such as email or username. Account creation and
 * authentication are handled through separate authentication service endpoints
 * (not managed by this API).
 *
 * The operation maintains audit trail compatibility by recording access
 * timestamps in last_login_at (contributors) or updated profile state queries.
 *
 * @param props.connection
 * @path /discussionBoard/contributor/profile
 * @accessor api.functional.discussionBoard.contributor.profile.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(connection: IConnection): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(),
          status: null,
        },
      );
}
