import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardContributor } from "../../../../../structures/IDiscussionBoardContributor";

/**
 * This endpoint allows authenticated contributors to delete their own account
 * through a soft-delete operation. The account is marked for deletion by
 * setting the deleted_at timestamp to the current time and changing the
 * account_status to 'deleted', while all data is retained in the database for
 * audit trail and recovery purposes.
 *
 * The discussion_board_contributors table uses soft deletion to preserve
 * contributor information and maintain data integrity for associated articles
 * and comments. Deleted accounts are retained for 6 months to enable recovery
 * through administrator support; after 6 months, the account and related data
 * can be permanently purged from the system.
 *
 * Security and authorization require password verification before account
 * deletion to prevent unauthorized or accidental deletion. The operation
 * disables all active sessions for the contributor, preventing further access
 * immediately after deletion.
 *
 * Upon successful deletion, the contributor can no longer log in, create
 * articles, post comments, or access any features. Articles and comments
 * created by the deleted account remain visible in the system but are
 * associated with a deleted contributor account. Related operations include
 * password change (POST /profile/change-password) and account recovery (if
 * implemented).
 *
 * @param props.connection
 * @param props.body Password verification for account deletion confirmation
 * @path /discussionBoard/contributor/profile/delete
 * @accessor api.functional.discussionBoard.contributor.profile._delete.erase
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function erase(
  connection: IConnection,
  props: erase.Props,
): Promise<erase.Response> {
  return true === connection.simulate
    ? erase.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...erase.METADATA,
          path: erase.path(),
          status: null,
        },
        props.body,
      );
}
export namespace erase {
  export type Props = {
    /** Password verification for account deletion confirmation */
    body: IDiscussionBoardContributor.IDeleteAccount;
  };
  export type Body = IDiscussionBoardContributor.IDeleteAccount;
  export type Response = IDiscussionBoardContributor.IDeleteAccountResult;

  export const METADATA = {
    method: "POST",
    path: "/discussionBoard/contributor/profile/delete",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/discussionBoard/contributor/profile/delete";
  export const random = (): IDiscussionBoardContributor.IDeleteAccountResult =>
    typia.random<IDiscussionBoardContributor.IDeleteAccountResult>();
  export const simulate = (
    connection: IConnection,
    props: erase.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: erase.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
