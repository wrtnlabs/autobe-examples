/**
 * Create a new article draft in the discussion board.
 *
 * Create a new discussion board article in draft status. This operation allows
 * authenticated contributors to compose articles on economic and political
 * topics before submitting them for moderator review.
 *
 * The article is initialized with 'draft' status, allowing the contributor to
 * save their work, close the browser, and return later to continue editing
 * without requiring moderator approval at this stage. The system automatically
 * records the contributor's ID as the article author and sets the creation
 * timestamp. All article content and metadata are stored in the
 * discussion_board_articles table with references to the author contributor and
 * selected category.
 *
 * Validation is enforced for all required fields: title must be 5-200
 * characters describing the article topic, content must be 50-50,000 characters
 * containing the main discussion or analysis, and category must be selected
 * from the predefined article categories (Economics, Politics, Policy, Trade,
 * Markets, Regulation, International, Analysis, Opinion, Other Discussion).
 * Invalid category selections are rejected with an error listing valid
 * options.
 *
 * The operation supports optional attachment uploads (images and documents) up
 * to a maximum of 10 files per article. Attachments are validated for file type
 * (JPG, PNG, GIF, WebP for images; PDF, DOC, DOCX, TXT, XLS, XLSX for
 * documents) and size limits (10MB for images, 25MB for documents) during the
 * creation request. Multiple attachments can be provided in a single request.
 *
 * Security: Only authenticated contributors can access this endpoint. The
 * operation requires valid JWT token authentication and the contributor's
 * account must be in 'active' status with verified email address. The system
 * automatically associates the created article with the authenticated user's
 * contributor ID, preventing contributors from creating articles on behalf of
 * others. The operation returns HTTP 401 Unauthorized if authentication is
 * missing or invalid, and HTTP 403 Forbidden if the contributor account is not
 * active or email is unverified.
 *
 * Related operations: After creating an article in draft status, the
 * contributor uses PUT /articles/{articleId} to edit the article content before
 * submission. Once ready for moderation review, the contributor calls PATCH
 * /articles/{articleId}/submit to transition from draft to pending_approval
 * status. GET /articles/{articleId} retrieves the full article details
 * including metadata and attachments.
 *
 * @param props.connection
 * @param props.body Article creation payload including title, content,
 *   category, optional description, and attachment uploads
 * @path /discussionBoard/contributor/articles
 * @accessor api.functional.discussionBoard.contributor.articles.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
