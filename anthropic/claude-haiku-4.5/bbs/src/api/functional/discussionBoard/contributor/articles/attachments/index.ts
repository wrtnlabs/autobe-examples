/**
 * Upload and attach a file to a discussion board article for supporting
 * evidence, visual content, or supplementary documents.
 *
 * This operation allows contributors to attach files to their articles during
 * creation or editing. Supported file types include images (jpg, png, gif,
 * webp) and documents (pdf, docx, xlsx, txt) with appropriate file size
 * restrictions. Images are limited to 5MB while documents can be up to 25MB.
 * Each article can have up to 10 attachments, providing flexibility for
 * comprehensive documentation while preventing excessive file storage.
 *
 * The operation validates the uploaded file against type and size constraints
 * before storing the attachment metadata. The uploaded file is persisted to
 * storage, and a display URL is generated for accessing the file through the
 * web interface. File metadata is recorded including the original filename as
 * provided by the uploader, the determined file type/extension, MIME type for
 * proper browser handling, and the exact file size in bytes.
 *
 * Attachment ownership is tracked through the uploaded_by_contributor_id field,
 * recording which contributor uploaded each file. This enables audit trails and
 * contributor-specific attachment management. Attachments are immutably linked
 * to their parent article and cannot be reassigned or moved to different
 * articles.
 *
 * When an article transitions to published status, all existing attachments
 * remain accessible and visible. When an article is deleted (either hard or
 * soft delete), all associated attachments are automatically removed from both
 * the database and storage to maintain data integrity and prevent orphaned
 * files.
 *
 * @param props.connection
 * @param props.articleId Unique identifier of the article to which the file
 *   will be attached
 * @param props.body File upload data including the file content and metadata
 * @path /discussionBoard/contributor/articles/:articleId/attachments
 * @accessor api.functional.discussionBoard.contributor.articles.attachments.attach
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function attach(
  connection: IConnection,
  props: attach.Props,
): Promise<attach.Response> {
  return true === connection.simulate
    ? attach.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...attach.METADATA,
          path: attach.path(props),
          status: null,
        },
        props.body,
      );
}
