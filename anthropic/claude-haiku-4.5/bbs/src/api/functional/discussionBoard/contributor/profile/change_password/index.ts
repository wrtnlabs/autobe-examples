import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardContributor } from "../../../../../structures/IDiscussionBoardContributor";

/**
 * Change contributor account password.
 *
 * This endpoint allows authenticated contributors to update their account
 * password. The operation requires verification of the current password to
 * prevent unauthorized password changes. The new password must meet security
 * requirements with a minimum of 8 characters including uppercase letters,
 * lowercase letters, numbers, and special characters.
 *
 * The password_hash field in the discussion_board_contributors table stores the
 * Bcrypt-hashed password with a minimum of 12 salt rounds. When a contributor
 * changes their password, the password_changed_at timestamp is updated, and all
 * active sessions are invalidated immediately for security purposes.
 *
 * Security considerations include rate limiting on password change attempts and
 * logging of password change events for audit trails. The operation is
 * restricted to authenticated contributors who must provide their current
 * password before the new password is accepted.
 *
 * Related operations include account deletion (POST /profile/delete) and
 * session management. A successful password change will require the contributor
 * to log in again on all devices, as all existing session tokens are revoked.
 *
 * @param props.connection
 * @param props.body Current password and new password for the password change
 *   operation
 * @path /discussionBoard/contributor/profile/change-password
 * @accessor api.functional.discussionBoard.contributor.profile.change_password.changePassword
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function changePassword(
  connection: IConnection,
  props: changePassword.Props,
): Promise<changePassword.Response> {
  return true === connection.simulate
    ? changePassword.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...changePassword.METADATA,
          path: changePassword.path(),
          status: null,
        },
        props.body,
      );
}
export namespace changePassword {
  export type Props = {
    /** Current password and new password for the password change operation */
    body: IDiscussionBoardContributor.IChangePassword;
  };
  export type Body = IDiscussionBoardContributor.IChangePassword;
  export type Response = IDiscussionBoardContributor.IPasswordChangeResult;

  export const METADATA = {
    method: "POST",
    path: "/discussionBoard/contributor/profile/change-password",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () =>
    "/discussionBoard/contributor/profile/change-password";
  export const random = (): IDiscussionBoardContributor.IPasswordChangeResult =>
    typia.random<IDiscussionBoardContributor.IPasswordChangeResult>();
  export const simulate = (
    connection: IConnection,
    props: changePassword.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: changePassword.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
