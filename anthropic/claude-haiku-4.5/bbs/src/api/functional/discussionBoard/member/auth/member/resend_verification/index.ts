/**
 * Request a new email verification code and email.
 *
 * This operation handles the resend verification email workflow for members who
 * lost the original verification email, entered an incorrect code too many
 * times, or the original verification code expired (24-hour validity window).
 * Members can request a new verification email containing a fresh token and
 * code.
 *
 * The operation enforces rate limiting to prevent abuse—members can request
 * resend at most once per 5 minutes per account. If a member attempts to resend
 * more frequently, the system returns an error message indicating they must
 * wait before requesting another verification email.
 *
 * When a resend is requested, the system generates a new verification token and
 * code, invalidating the previous token/code pair. This prevents confusion from
 * multiple valid tokens in circulation. The new verification email is sent
 * immediately to the member's registered email address with clear instructions
 * for completing verification.
 *
 * The resend operation updates the verification data in the
 * discussion_board_members table (or verification tracking table if implemented
 * separately). The email_verified flag remains false until successful
 * verification using the new code. The member continues to have read-only
 * access but cannot create articles or post comments until email verification
 * is completed.
 *
 * This operation requires member authentication to identify which member is
 * requesting the resend. The authenticated member submitting the request must
 * have an account in discussion_board_members with unverified status
 * (email_verified = false). Members with already-verified emails can still call
 * this endpoint, which returns a success message for security reasons
 * (preventing account enumeration attacks).
 *
 * Rate limiting context: Failed attempts to resend (due to rate limiting)
 * should be tracked separately from successful resends. The 5-minute window
 * resets from the timestamp of the most recent resend request by that member.
 *
 * Related operations: POST /auth/member/verify-email (the endpoint that
 * consumes the verification code sent by this operation), which should be
 * called after the member receives and enters their verification code.
 *
 * @param props.connection
 * @path /discussionBoard/member/auth/member/resend-verification
 * @accessor api.functional.discussionBoard.member.auth.member.resend_verification.resendVerification
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function resendVerification(
  connection: IConnection,
): Promise<resendVerification.Response> {
  return true === connection.simulate
    ? resendVerification.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...resendVerification.METADATA,
          path: resendVerification.path(),
          status: null,
        },
      );
}
export namespace resendVerification {
  export type Response = IDiscussionBoardMember.IResendVerificationResponse;

  export const METADATA = {
    method: "POST",
    path: "/discussionBoard/member/auth/member/resend-verification",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () =>
    "/discussionBoard/member/auth/member/resend-verification";
  export const random =
    (): IDiscussionBoardMember.IResendVerificationResponse =>
      typia.random<IDiscussionBoardMember.IResendVerificationResponse>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}
