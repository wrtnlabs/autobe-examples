import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardReport } from "../../../../../structures/IDiscussionBoardReport";

/**
 * Create a report for an inappropriate comment.
 *
 * Create a new report flagging a comment as potentially violating community
 * guidelines. This operation enables members to submit feedback about comment
 * content they believe is offensive, spam, harassment, or otherwise
 * inappropriate. The reported comment must exist and belong to a published
 * article.
 *
 * Each report captures the reporter's reason for flagging (offensive language,
 * personal attack, spam, off-topic, copyright violation, harassment, or other)
 * and optional detailed description (maximum 500 characters) explaining the
 * concern. The report is immediately created with 'pending_review' status,
 * entering the moderator review queue for investigation and action.
 *
 * Reports are permanent audit records tracking member concerns and community
 * feedback. The combination of discussion_board_member_id (reporter),
 * discussion_board_comment_id (reported content), reason, and timestamps
 * enables moderators to analyze reporting patterns, prioritize high-impact
 * issues, and maintain community standards.
 *
 * Security: Only authenticated members can create reports. The system prevents
 * duplicate reports from the same member for the same content within a time
 * window. Rate limiting applies to prevent report spam. The creating member's
 * identity is captured automatically from the authentication context.
 *
 * @param props.connection
 * @param props.commentId Unique identifier of the comment being reported
 * @param props.body Report creation data including reason for flagging and
 *   optional detailed description
 * @path /discussionBoard/member/comments/:commentId/reports
 * @accessor api.functional.discussionBoard.member.comments.reports.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function create(
  connection: IConnection,
  props: create.Props,
): Promise<create.Response> {
  return true === connection.simulate
    ? create.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...create.METADATA,
          path: create.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace create {
  export type Props = {
    /** Unique identifier of the comment being reported */
    commentId: string & tags.Format<"uuid">;

    /**
     * Report creation data including reason for flagging and optional
     * detailed description
     */
    body: IDiscussionBoardReport.ICreate;
  };
  export type Body = IDiscussionBoardReport.ICreate;
  export type Response = IDiscussionBoardReport;

  export const METADATA = {
    method: "POST",
    path: "/discussionBoard/member/comments/:commentId/reports",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/discussionBoard/member/comments/${encodeURIComponent(props.commentId ?? "null")}/reports`;
  export const random = (): IDiscussionBoardReport =>
    typia.random<IDiscussionBoardReport>();
  export const simulate = (
    connection: IConnection,
    props: create.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: create.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("commentId")(() => typia.assert(props.commentId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
