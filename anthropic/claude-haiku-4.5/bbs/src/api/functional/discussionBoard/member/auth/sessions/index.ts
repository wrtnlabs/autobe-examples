import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardMemberSession } from "../../../../../structures/IDiscussionBoardMemberSession";

/**
 * Retrieve the current authentication session details.
 *
 * Fetch the currently active authentication session for the authenticated user
 * (member or moderator). The session contains metadata about the login context
 * including IP address, HTTP referrer, and session creation timestamp. This
 * endpoint is used to verify session validity and retrieve session context
 * information.
 *
 * Authentication is required for this operation. The system validates the
 * provided JWT token and returns the session details associated with that
 * token. Only the authenticated user can retrieve their own session
 * information.
 *
 * The response includes session metadata that can be used for security
 * verification, session management, and detecting suspicious activity. The IP
 * address and referrer information help validate legitimate sessions versus
 * potential unauthorized access attempts.
 *
 * @param props.connection
 * @path /discussionBoard/member/auth/sessions
 * @accessor api.functional.discussionBoard.member.auth.sessions.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(connection: IConnection): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
      );
}
export namespace index {
  export type Response = IDiscussionBoardMemberSession;

  export const METADATA = {
    method: "GET",
    path: "/discussionBoard/member/auth/sessions",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/discussionBoard/member/auth/sessions";
  export const random = (): IDiscussionBoardMemberSession =>
    typia.random<IDiscussionBoardMemberSession>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}

/**
 * Terminate a specific authentication session.
 *
 * Delete and invalidate a specific authentication session by its sessionId.
 * This operation logs out the user for that particular session, making the
 * associated JWT token invalid for future requests. The sessionId must belong
 * to the authenticated user (or user must be moderator with account management
 * permissions).
 *
 * When a session is deleted, the session record is removed from the database
 * and the associated JWT token is invalidated. Any subsequent API requests
 * using that token will be rejected with authentication error. This enables
 * users to log out from specific devices or sessions while maintaining active
 * sessions on other devices.
 *
 * Moderators have the ability to delete user sessions as part of account
 * management and enforcement activities, such as forcing logout of suspended or
 * problematic accounts. The deletion is immediate and permanent.
 *
 * @param props.connection
 * @param props.sessionId Unique identifier of the session to terminate (UUID
 *   format)
 * @path /discussionBoard/member/auth/sessions/:sessionId
 * @accessor api.functional.discussionBoard.member.auth.sessions.erase
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function erase(
  connection: IConnection,
  props: erase.Props,
): Promise<void> {
  return true === connection.simulate
    ? erase.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...erase.METADATA,
          path: erase.path(props),
          status: null,
        },
      );
}
export namespace erase {
  export type Props = {
    /** Unique identifier of the session to terminate (UUID format) */
    sessionId: string & tags.Format<"uuid">;
  };

  export const METADATA = {
    method: "DELETE",
    path: "/discussionBoard/member/auth/sessions/:sessionId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/member/auth/sessions/${encodeURIComponent(props.sessionId ?? "null")}`;
  export const random = (): void => typia.random<void>();
  export const simulate = (
    connection: IConnection,
    props: erase.Props,
  ): void => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: erase.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("sessionId")(() => typia.assert(props.sessionId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
