import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardMemberSession } from "../../../../../structures/IDiscussionBoardMemberSession";

/**
 * Change authenticated member's account password.
 *
 * This operation allows authenticated members to securely change their account
 * password. The member must be logged in and provide both their current
 * password (for verification) and the new desired password. The system
 * validates the current password matches the stored password hash before
 * allowing the change.
 *
 * When a member requests a password change, the system SHALL verify the member
 * is authenticated via valid JWT token. The system SHALL validate the provided
 * current password by comparing it against the member's stored password hash.
 * If the current password is incorrect, the system SHALL reject the request and
 * display error message "Current password is incorrect".
 *
 * The system SHALL validate the new password meets security requirements:
 * minimum 8 characters containing at least one uppercase letter, one lowercase
 * letter, and one number. If new password does not meet requirements, the
 * system SHALL reject the request and display specific validation error
 * message.
 *
 * The system SHALL NOT allow the new password to be identical to the current
 * password. If user attempts to set same password, the system SHALL reject and
 * display "Your new password must be different from your current password".
 *
 * Upon successful validation, the system SHALL update the member's
 * password_hash with the new hashed password, update the updated_at timestamp
 * to current time, and invalidate all existing authentication sessions and JWT
 * tokens for the member. This forces the member to re-authenticate on all
 * devices/browsers for security compliance.
 *
 * After successful password change, the system SHALL redirect the member to
 * login page with message "Password changed successfully. Please log in again."
 * This logout-all-sessions approach ensures only the member's current
 * device/session retains access after confirming new password.
 *
 * @param props.connection
 * @param props.body Member's current password and new password for password
 *   change request
 * @path /discussionBoard/member/auth/change-password
 * @accessor api.functional.discussionBoard.member.auth.change_password.changePassword
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function changePassword(
  connection: IConnection,
  props: changePassword.Props,
): Promise<changePassword.Response> {
  return true === connection.simulate
    ? changePassword.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...changePassword.METADATA,
          path: changePassword.path(),
          status: null,
        },
        props.body,
      );
}
export namespace changePassword {
  export type Props = {
    /**
     * Member's current password and new password for password change
     * request
     */
    body: IDiscussionBoardMemberSession.IChangePasswordRequest;
  };
  export type Body = IDiscussionBoardMemberSession.IChangePasswordRequest;
  export type Response = IDiscussionBoardMemberSession.IChangePasswordResponse;

  export const METADATA = {
    method: "POST",
    path: "/discussionBoard/member/auth/change-password",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/discussionBoard/member/auth/change-password";
  export const random =
    (): IDiscussionBoardMemberSession.IChangePasswordResponse =>
      typia.random<IDiscussionBoardMemberSession.IChangePasswordResponse>();
  export const simulate = (
    connection: IConnection,
    props: changePassword.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: changePassword.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
