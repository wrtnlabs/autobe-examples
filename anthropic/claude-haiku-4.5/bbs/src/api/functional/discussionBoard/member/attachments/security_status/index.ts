import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardAttachment } from "../../../../../structures/IDiscussionBoardAttachment";

/**
 * Retrieve the security validation status of an attachment file.
 *
 * This endpoint retrieves the current security validation status of a specific
 * attachment. The operation queries the attachment record from the
 * discussion_board_attachments table and returns the security_status field
 * indicating whether the file has passed malware scanning. Status values
 * include 'pending_scan' (awaiting antivirus scan), 'safe' (scan completed and
 * file is clean), 'infected' (malware detected), and 'quarantined' (isolated
 * due to security violation or policy violation).
 *
 * WHEN a user or moderator requests the security status of an attachment, THE
 * system SHALL return the current validation status with the
 * malware_scan_result details if the file has been scanned. This allows the
 * application to determine whether to allow the file to be displayed inline,
 * downloaded, or hidden from users.
 *
 * The attachment must exist in the system and not be deleted (deleted_at is
 * NULL). The operation respects visibility rules: guests and members can only
 * check status of attachments on published articles they have access to, while
 * moderators can check status of all attachments including those on archived
 * articles or deleted content.
 *
 * Security scanning is performed automatically when attachments are uploaded.
 * Files must pass security validation before they are marked as 'safe' and made
 * available for download. If a file fails security scanning, it is marked as
 * 'infected' and cannot be downloaded. Quarantined files indicate potential
 * security or policy violations detected during validation.
 *
 * @param props.connection
 * @param props.attachmentId Unique identifier (UUID) of the attachment whose
 *   security status is being requested
 * @path /discussionBoard/member/attachments/:attachmentId/security-status
 * @accessor api.functional.discussionBoard.member.attachments.security_status.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique identifier (UUID) of the attachment whose security status is
     * being requested
     */
    attachmentId: string & tags.Format<"uuid">;
  };
  export type Response = IDiscussionBoardAttachment.ISecurityStatus;

  export const METADATA = {
    method: "GET",
    path: "/discussionBoard/member/attachments/:attachmentId/security-status",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/member/attachments/${encodeURIComponent(props.attachmentId ?? "null")}/security-status`;
  export const random = (): IDiscussionBoardAttachment.ISecurityStatus =>
    typia.random<IDiscussionBoardAttachment.ISecurityStatus>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("attachmentId")(() => typia.assert(props.attachmentId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
