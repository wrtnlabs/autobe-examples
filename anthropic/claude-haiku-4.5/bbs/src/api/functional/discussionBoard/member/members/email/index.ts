import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardMember } from "../../../../../structures/IDiscussionBoardMember";

/**
 * Update a member's email address with verification requirement.
 *
 * Update the email address associated with a member account in the discussion
 * board system. This is a security-sensitive operation that requires the member
 * to verify their current password before the email can be changed. The new
 * email address must be validated for proper format and uniqueness to prevent
 * duplicate registrations.
 *
 * When a member initiates an email change, the system validates that the
 * provided email address is in valid RFC 5322 format and that no other member
 * account is already using this email address. The email must not exceed 254
 * characters. After validation, the system records the new email address in the
 * discussion_board_members table.
 *
 * Email verification is required for the email change to take full effect. Upon
 * successful email update, the system generates a unique verification token and
 * code valid for 24 hours, then sends a verification email to the new address
 * containing a clickable verification link and alphanumeric verification code.
 * Until the member verifies the new email address, the previous email remains
 * the active login credential.
 *
 * Once the member verifies the new email through the verification link or code
 * entry, the system marks the email_verified flag as true for the member
 * account. All future authentication and password recovery operations use the
 * newly verified email address.
 *
 * This operation is restricted to authenticated members and can only be
 * performed on the member's own account. The operation requires the current
 * password as an additional security measure to prevent unauthorized email
 * hijacking. All email changes are logged in the audit trail with the timestamp
 * and member identity for security monitoring and account recovery purposes.
 *
 * @param props.connection
 * @param props.memberId Unique identifier of the member account whose email
 *   will be updated
 * @param props.body Email update request containing new email address and
 *   current password for verification
 * @path /discussionBoard/member/members/:memberId/email
 * @accessor api.functional.discussionBoard.member.members.email.updateEmail
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function updateEmail(
  connection: IConnection,
  props: updateEmail.Props,
): Promise<updateEmail.Response> {
  return true === connection.simulate
    ? updateEmail.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...updateEmail.METADATA,
          path: updateEmail.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace updateEmail {
  export type Props = {
    /** Unique identifier of the member account whose email will be updated */
    memberId: string & tags.Format<"uuid">;

    /**
     * Email update request containing new email address and current
     * password for verification
     */
    body: IDiscussionBoardMember.IUpdateEmail;
  };
  export type Body = IDiscussionBoardMember.IUpdateEmail;
  export type Response = IDiscussionBoardMember;

  export const METADATA = {
    method: "PUT",
    path: "/discussionBoard/member/members/:memberId/email",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/discussionBoard/member/members/${encodeURIComponent(props.memberId ?? "null")}/email`;
  export const random = (): IDiscussionBoardMember =>
    typia.random<IDiscussionBoardMember>();
  export const simulate = (
    connection: IConnection,
    props: updateEmail.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: updateEmail.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("memberId")(() => typia.assert(props.memberId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
