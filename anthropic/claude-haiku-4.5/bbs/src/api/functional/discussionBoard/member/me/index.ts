/**
 * Get authenticated member's profile information.
 *
 * Retrieve the complete profile and account information for the currently
 * authenticated member. This operation queries the discussion_board_members
 * table to return the authenticated user's account details including email
 * address, account creation timestamp, account status, and modification
 * history.
 *
 * The profile endpoint is used for displaying user profile pages, account
 * settings dashboards, and anywhere the system needs to reference the
 * authenticated user's information. It returns non-sensitive member metadata
 * that the user themselves should be able to view and manage.
 *
 * Authorization requires an authenticated member account. Guest users cannot
 * access member profile information. The response includes account status
 * (active, suspended, banned) which affects user capabilities throughout the
 * platform. Members can view their own profile without restrictions.
 *
 * @param props.connection
 * @path /discussionBoard/member/me/profile
 * @accessor api.functional.discussionBoard.member.me.profile
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function profile(
  connection: IConnection,
): Promise<profile.Response> {
  return true === connection.simulate
    ? profile.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...profile.METADATA,
          path: profile.path(),
          status: null,
        },
      );
}
export namespace profile {
  export type Response = IDiscussionBoardMember;

  export const METADATA = {
    method: "GET",
    path: "/discussionBoard/member/me/profile",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/discussionBoard/member/me/profile";
  export const random = (): IDiscussionBoardMember =>
    typia.random<IDiscussionBoardMember>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}
