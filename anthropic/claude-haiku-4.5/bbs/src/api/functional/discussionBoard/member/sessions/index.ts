import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

/**
 * Delete a specific member authentication session and invalidate the associated
 * tokens.
 *
 * This operation terminates an active member authentication session and
 * invalidates the associated JWT refresh token. When a member logs out or a
 * session is revoked, this endpoint marks the session as expired by setting the
 * expired_at timestamp to the current time.
 *
 * The session parameter identifies the specific login instance to terminate.
 * Each member can maintain multiple concurrent sessions across different
 * devices; deleting one session affects only that specific device/login context
 * while preserving other active sessions. The operation is idempotent -
 * attempting to delete an already-expired session returns success without
 * error.
 *
 * Security considerations include verifying that the authenticated member
 * requesting deletion owns the session being terminated. Members can only
 * delete their own sessions; moderators with appropriate permissions may delete
 * any member's sessions for administrative purposes. The operation logs the
 * deletion event including session ID, member ID, moderator ID (if applicable),
 * and timestamp for audit purposes.
 *
 * Upon successful deletion, the member must obtain new authentication tokens
 * via the login endpoint to resume access. Any outstanding access tokens remain
 * valid until their natural expiration (15 minutes); only the refresh token
 * becomes invalid. Clients should immediately discard both tokens upon
 * receiving success response from this endpoint.
 *
 * This operation integrates with the JWT token invalidation and blacklisting
 * system. The session's refresh token is added to the token blacklist,
 * preventing token refresh attempts from generating new access tokens. The
 * session record is retained (soft deletion via expired_at timestamp) to
 * preserve the audit trail and security history.
 *
 * @param props.connection
 * @param props.sessionId Unique identifier of the member session to delete
 *   (UUID format)
 * @path /discussionBoard/member/sessions/:sessionId
 * @accessor api.functional.discussionBoard.member.sessions.erase
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function erase(
  connection: IConnection,
  props: erase.Props,
): Promise<void> {
  return true === connection.simulate
    ? erase.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...erase.METADATA,
          path: erase.path(props),
          status: null,
        },
      );
}
export namespace erase {
  export type Props = {
    /** Unique identifier of the member session to delete (UUID format) */
    sessionId: string & tags.Format<"uuid">;
  };

  export const METADATA = {
    method: "DELETE",
    path: "/discussionBoard/member/sessions/:sessionId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/member/sessions/${encodeURIComponent(props.sessionId ?? "null")}`;
  export const random = (): void => typia.random<void>();
  export const simulate = (
    connection: IConnection,
    props: erase.Props,
  ): void => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: erase.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("sessionId")(() => typia.assert(props.sessionId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
