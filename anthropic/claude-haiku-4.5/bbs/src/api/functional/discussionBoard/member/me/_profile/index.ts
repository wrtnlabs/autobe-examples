import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardMember } from "../../../../../structures/IDiscussionBoardMember";

/**
 * Update authenticated member's profile information.
 *
 * Update the authenticated member's profile information including email address
 * and account details. This operation allows members to modify their own
 * profile data after authentication verification. The request body contains
 * profile fields that the member wishes to update.
 *
 * The operation validates that the authenticated user has permission to modify
 * their own profile and that all profile data meets system requirements (unique
 * email, valid format, etc.). Email addresses must be unique in the system - if
 * the new email is already registered to another account, the update is
 * rejected with a conflict error.
 *
 * This operation is member-only and requires a valid JWT authentication token
 * indicating the logged-in member making the request. The operation implicitly
 * targets the authenticated member's own profile record - members cannot update
 * other users' profiles.
 *
 * When profile updates are successful, the operation updates the
 * discussion_board_members record with new values and sets the updated_at
 * timestamp to current time. The member's created_at timestamp remains
 * unchanged as a permanent creation record.
 *
 * @param props.connection
 * @param props.body Profile update information including any fields the member
 *   wants to modify (email, profile settings, etc.)
 * @path /discussionBoard/member/me/profile
 * @accessor api.functional.discussionBoard.member.me._profile.update
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function update(
  connection: IConnection,
  props: update.Props,
): Promise<update.Response> {
  return true === connection.simulate
    ? update.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...update.METADATA,
          path: update.path(),
          status: null,
        },
        props.body,
      );
}
export namespace update {
  export type Props = {
    /**
     * Profile update information including any fields the member wants to
     * modify (email, profile settings, etc.)
     */
    body: IDiscussionBoardMember.IUpdate;
  };
  export type Body = IDiscussionBoardMember.IUpdate;
  export type Response = IDiscussionBoardMember;

  export const METADATA = {
    method: "PUT",
    path: "/discussionBoard/member/me/profile",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/discussionBoard/member/me/profile";
  export const random = (): IDiscussionBoardMember =>
    typia.random<IDiscussionBoardMember>();
  export const simulate = (
    connection: IConnection,
    props: update.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: update.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
