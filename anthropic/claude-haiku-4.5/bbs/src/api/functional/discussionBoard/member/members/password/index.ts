/**
 * Update the password for an authenticated member account with complexity
 * validation and session invalidation.
 *
 * Update the password for an authenticated member's account.
 *
 * This operation allows members to change their password stored in the
 * discussion_board_members table. The member must provide their current
 * password (for verification that they have legitimate access to the account)
 * and a new password that meets all password complexity requirements. The
 * current password is verified by comparing its bcrypt hash against the stored
 * password_hash field.
 *
 * Password requirements are strictly enforced: minimum 8 characters in length,
 * must contain at least one uppercase letter (A-Z), at least one lowercase
 * letter (a-z), at least one numeric digit (0-9), and at least one special
 * character from the set (!@#$%^&*). The system rejects passwords that are
 * fewer than 8 characters, lack required character types, exceed 128
 * characters, contain the username, contain the email address.
 *
 * The authenticated member can only update their own password by providing
 * their memberId in the path. The system validates that the memberId path
 * parameter matches the authenticated user's ID to prevent unauthorized
 * password changes on other accounts. When the incorrect current password is
 * provided, the operation denies the change and returns an error without
 * revealing the nature of the mismatch.
 *
 * Upon successful password change, the system immediately invalidates all
 * existing authentication sessions for that member across all devices and
 * browsers. This forces the member to re-authenticate on all connected devices
 * using their new password, which is a critical security measure. The new
 * password is hashed using bcrypt with a minimum of 12 salt rounds before being
 * stored in the password_hash field. The system prevents password reuse by
 * checking against the member's last 3 passwords - if the new password matches
 * any recent password, the change is rejected.
 *
 * The operation updates the discussion_board_members.updated_at timestamp to
 * record when the password was changed. Password change operations are logged
 * for security audit purposes. The operation does not return the password or
 * password hash in the response - only confirmation of successful change.
 *
 * Related operations: PUT /memberPreferences/{memberId} allows updating
 * notification and display preferences separately from password security
 * changes.
 *
 * @param props.connection
 * @param props.memberId Unique identifier of the member whose password is being
 *   changed. Must match the authenticated user's ID to prevent unauthorized
 *   password changes. Format: UUID.
 * @param props.body Current password for verification and new password meeting
 *   complexity requirements
 * @path /discussionBoard/member/members/:memberId/password
 * @accessor api.functional.discussionBoard.member.members.password.updatePassword
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function updatePassword(
  connection: IConnection,
  props: updatePassword.Props,
): Promise<updatePassword.Response> {
  return true === connection.simulate
    ? updatePassword.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...updatePassword.METADATA,
          path: updatePassword.path(props),
          status: null,
        },
        props.body,
      );
}
