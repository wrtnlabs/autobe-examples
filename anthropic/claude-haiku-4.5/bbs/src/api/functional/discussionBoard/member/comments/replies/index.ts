import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardComment } from "../../../../../structures/IDiscussionBoardComment";

/**
 * Create a reply to an existing comment on an article.
 *
 * Creates a new comment as a direct reply to an existing comment, enabling
 * threaded discussions on article topics. This operation establishes a
 * parent-child relationship between the new reply comment and the specified
 * parent comment, maintaining full context about discussion hierarchy and
 * conversation flow.
 *
 * The reply must contain substantive text content between 1 and 5,000
 * characters. The system automatically associates the reply with the same
 * article as its parent comment, links it to the authenticated member as
 * author, and sets the thread depth level based on the parent comment's depth.
 * Replies at maximum depth (3) are attached to the parent at that depth rather
 * than creating deeper nesting.
 *
 * Reply validation ensures all required fields are provided and content meets
 * quality standards. The parent comment must exist, belong to an active
 * article, and not be marked as deleted or moderated. Failed validation returns
 * specific error messages identifying which requirement was not met.
 *
 * When reply creation succeeds, the system immediately displays the new comment
 * nested under its parent, notifies the parent comment's author that someone
 * replied to their comment, and increments the parent comment's reply count.
 * The reply is published immediately without moderation approval.
 *
 * This operation is member-restricted and requires active authentication. Guest
 * users attempting to reply receive a redirect to login with clear messaging
 * about the requirement. Suspended or banned user accounts are denied comment
 * creation with appropriate status messages. Reply posting is rate-limited to
 * prevent abuse: maximum 50 comments per hour across all article discussions
 * (includes both top-level comments and replies).
 *
 * @param props.connection
 * @param props.commentId Unique identifier of the parent comment being replied
 *   to
 * @param props.body Content and metadata for the new reply comment
 * @path /discussionBoard/member/comments/:commentId/replies
 * @accessor api.functional.discussionBoard.member.comments.replies.createReply
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function createReply(
  connection: IConnection,
  props: createReply.Props,
): Promise<createReply.Response> {
  return true === connection.simulate
    ? createReply.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...createReply.METADATA,
          path: createReply.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace createReply {
  export type Props = {
    /** Unique identifier of the parent comment being replied to */
    commentId: string & tags.Format<"uuid">;

    /** Content and metadata for the new reply comment */
    body: IDiscussionBoardComment.ICreate;
  };
  export type Body = IDiscussionBoardComment.ICreate;
  export type Response = IDiscussionBoardComment;

  export const METADATA = {
    method: "POST",
    path: "/discussionBoard/member/comments/:commentId/replies",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/discussionBoard/member/comments/${encodeURIComponent(props.commentId ?? "null")}/replies`;
  export const random = (): IDiscussionBoardComment =>
    typia.random<IDiscussionBoardComment>();
  export const simulate = (
    connection: IConnection,
    props: createReply.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: createReply.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("commentId")(() => typia.assert(props.commentId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
