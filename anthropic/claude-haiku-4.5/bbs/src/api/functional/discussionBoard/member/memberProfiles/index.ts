/**
 * Update a member's profile information including display name, bio, and
 * profile picture.
 *
 * Update an existing member profile with new display name, biographical
 * information, and profile picture URL. This operation allows members to manage
 * their public-facing profile information that is displayed as author
 * attribution on articles and comments throughout the discussion board
 * platform.
 *
 * The member profile is identified by the memberId path parameter which must
 * correspond to the requesting member's own account ID. Only the profile owner
 * can update their profile information. The operation validates all input data
 * according to business rules: display name must be 1-50 characters, bio is
 * optional and limited to 500 characters maximum, and profile picture URL must
 * be a valid URI if provided. The profile_picture_url field points to image
 * files in the attachment system that have been automatically resized to
 * 200x200 pixels and stripped of EXIF metadata for privacy protection.
 *
 * When the profile is successfully updated, the updated_at timestamp is
 * automatically set to the current UTC time, providing an audit trail of when
 * profile modifications occurred. The operation returns the complete updated
 * profile object reflecting all changes made, allowing the client to
 * synchronize with the latest profile state. Related profile data includes the
 * member_id foreign key relationship to the discussion_board_members table,
 * confirming the profile belongs to a valid member account.
 *
 * @param props.connection
 * @param props.memberId Unique identifier of the member whose profile is being
 *   updated. Must correspond to a valid discussion_board_members record and the
 *   requesting user's own member ID.
 * @param props.body Member profile update data containing display name,
 *   biography, and profile picture URL
 * @path /discussionBoard/member/memberProfiles/:memberId
 * @accessor api.functional.discussionBoard.member.memberProfiles.update
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function update(
  connection: IConnection,
  props: update.Props,
): Promise<update.Response> {
  return true === connection.simulate
    ? update.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...update.METADATA,
          path: update.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace update {
  export type Props = {
    /**
     * Unique identifier of the member whose profile is being updated. Must
     * correspond to a valid discussion_board_members record and the
     * requesting user's own member ID.
     */
    memberId: string & tags.Format<"uuid">;

    /**
     * Member profile update data containing display name, biography, and
     * profile picture URL
     */
    body: IDiscussionBoardMemberProfile.IUpdate;
  };
  export type Body = IDiscussionBoardMemberProfile.IUpdate;
  export type Response = IDiscussionBoardMemberProfile;

  export const METADATA = {
    method: "PUT",
    path: "/discussionBoard/member/memberProfiles/:memberId",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/discussionBoard/member/memberProfiles/${encodeURIComponent(props.memberId ?? "null")}`;
  export const random = (): IDiscussionBoardMemberProfile =>
    typia.random<IDiscussionBoardMemberProfile>();
  export const simulate = (
    connection: IConnection,
    props: update.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: update.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("memberId")(() => typia.assert(props.memberId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
