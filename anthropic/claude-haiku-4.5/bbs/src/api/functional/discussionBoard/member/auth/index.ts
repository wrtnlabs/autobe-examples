/**
 * Logout authenticated member and terminate session.
 *
 * This operation terminates the authenticated member's current session and logs
 * them out of the discussion board platform. The operation invalidates the
 * member's JWT authentication token and marks their session as expired,
 * preventing further use of their credentials for API requests.
 *
 * When a member executes logout, THE system SHALL:
 *
 * - Identify the currently authenticated member from their JWT token
 * - Locate the active session record in discussion_board_member_sessions
 * - Set the expired_at timestamp to current time to mark session as no longer
 *   valid
 * - Clear the authentication token from client storage
 * - Redirect or display confirmation message
 *
 * After successful logout, the member's JWT token becomes invalid and any
 * subsequent API requests using that token SHALL be rejected with "Your session
 * is no longer valid. Please log in again." The member must visit the login
 * page to authenticate again and obtain a new session token.
 *
 * This operation is available to all authenticated members regardless of
 * account status. Even suspended or banned members can log out to clear their
 * authentication state. The logout process is idempotent - logging out multiple
 * times returns the same success state.
 *
 * @param props.connection
 * @path /discussionBoard/member/auth/logout
 * @accessor api.functional.discussionBoard.member.auth.logout
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function logout(connection: IConnection): Promise<void> {
  return true === connection.simulate
    ? logout.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...logout.METADATA,
          path: logout.path(),
          status: null,
        },
      );
}
export namespace logout {
  export const METADATA = {
    method: "POST",
    path: "/discussionBoard/member/auth/logout",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/discussionBoard/member/auth/logout";
  export const random = (): void => typia.random<void>();
  export const simulate = (_connection: IConnection): void => {
    return random();
  };
}
