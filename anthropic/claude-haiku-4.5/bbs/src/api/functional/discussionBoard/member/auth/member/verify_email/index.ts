import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardMember } from "../../../../../../structures/IDiscussionBoardMember";

/**
 * Verify a member's email address using verification token or code.
 *
 * This operation completes the email verification process for newly registered
 * members. When a member registers, the system sends a verification email
 * containing a unique token or alphanumeric code. This endpoint allows the
 * member to submit that token or code to prove ownership of their email
 * address.
 *
 * The verification process is critical to the discussion board's security and
 * participation model. Members with unverified emails cannot create articles or
 * post comments, ensuring only legitimate email addresses are used for account
 * creation. The system must validate that the provided token or code matches
 * stored verification data and has not expired (24-hour validity window).
 *
 * Upon successful verification, the system updates the discussion_board_members
 * table, setting email_verified to true. This immediately enables the member to
 * create articles and post comments. The verification token is cleared from
 * storage after successful use to prevent replay attacks.
 *
 * If verification fails (invalid code, expired code, or already verified), the
 * system returns a specific error message indicating the issue. Expired tokens
 * trigger an offer to resend verification email, making the recovery path clear
 * to users.
 *
 * This operation requires member authentication context to identify which
 * member is verifying their email. The authenticated member submitting the
 * request must match the member_id associated with the verification data. This
 * prevents one member from verifying another member's email address.
 *
 * Related operations: POST /auth/member/resend-verification (to request new
 * verification email if code expires), which shares the same workflow context
 * and may be called before or after this verification attempt.
 *
 * @param props.connection
 * @param props.body Email verification token or code provided by the member
 * @path /discussionBoard/member/auth/member/verify-email
 * @accessor api.functional.discussionBoard.member.auth.member.verify_email.verifyEmail
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function verifyEmail(
  connection: IConnection,
  props: verifyEmail.Props,
): Promise<verifyEmail.Response> {
  return true === connection.simulate
    ? verifyEmail.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...verifyEmail.METADATA,
          path: verifyEmail.path(),
          status: null,
        },
        props.body,
      );
}
export namespace verifyEmail {
  export type Props = {
    /** Email verification token or code provided by the member */
    body: IDiscussionBoardMember.IVerifyEmail;
  };
  export type Body = IDiscussionBoardMember.IVerifyEmail;
  export type Response = IDiscussionBoardMember;

  export const METADATA = {
    method: "POST",
    path: "/discussionBoard/member/auth/member/verify-email",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/discussionBoard/member/auth/member/verify-email";
  export const random = (): IDiscussionBoardMember =>
    typia.random<IDiscussionBoardMember>();
  export const simulate = (
    connection: IConnection,
    props: verifyEmail.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: verifyEmail.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
