/**
 * List authenticated member's articles with filtering and search.
 *
 * Retrieve a paginated list of all articles created by the authenticated
 * member. This operation allows members to view and manage their own article
 * portfolio with advanced search, filtering, and sorting capabilities.
 *
 * The operation supports filtering by article category (Economics or Politics),
 * searching by keyword in article titles and content, and sorting by creation
 * date (newest/oldest first) or engagement metrics (most commented). Results
 * are returned in paginated format allowing members to browse through their
 * article history.
 *
 * This is a member-only operation requiring authentication. The operation
 * implicitly filters to show only articles authored by the authenticated member
 * - members see only their own articles, not other users' articles. Moderators
 * can view all articles including those they didn't author.
 *
 * The response includes article metadata for each result: title, category,
 * creation date, last modification timestamp, number of comments, number of
 * views, and publication status. Articles are returned with full details
 * enabling members to see engagement metrics and decide which articles to edit
 * or delete.
 *
 * Deleted articles (soft-deleted with deleted_at timestamp set) are excluded
 * from results by default, showing only active, published articles the member
 * can manage. Archived articles (status = 'archived') may be shown depending on
 * implementation.
 *
 * @param props.connection
 * @param props.body Search criteria, filtering options, pagination parameters,
 *   and sorting preferences for member's articles
 * @path /discussionBoard/member/me/articles
 * @accessor api.functional.discussionBoard.member.me.articles.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Search criteria, filtering options, pagination parameters, and
     * sorting preferences for member's articles
     */
    body: IDiscussionBoardArticle.IRequest;
  };
  export type Body = IDiscussionBoardArticle.IRequest;
  export type Response = IPageIDiscussionBoardArticle;

  export const METADATA = {
    method: "PATCH",
    path: "/discussionBoard/member/me/articles",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/discussionBoard/member/me/articles";
  export const random = (): IPageIDiscussionBoardArticle =>
    typia.random<IPageIDiscussionBoardArticle>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
