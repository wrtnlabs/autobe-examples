/**
 * Logout an authenticated member and terminate their current session.
 *
 * Terminate the authenticated member's current session and invalidate their
 * authentication credentials. This operation marks the session record in
 * discussion_board_member_sessions as expired by setting the expired_at
 * timestamp to the current UTC time.
 *
 * Authentication is required for this operation. The member must provide a
 * valid JWT access token in the Authorization header (Bearer scheme). The
 * authenticated user's member ID is extracted from the token claims (JWT sub
 * claim or user context) and used to identify which session to terminate.
 *
 * When logout is processed, the system performs the following actions: (1)
 * Locate the member's active session (where expired_at is null), (2) Set the
 * expired_at field to current timestamp, (3) Blacklist the member's refresh
 * token to prevent reuse, (4) Clear any session cookies on the client side (via
 * Set-Cookie header with Max-Age=0), (5) Record the logout event in audit logs
 * with timestamp.
 *
 * After logout succeeds, the member must authenticate again by providing
 * email/username and password to obtain new tokens. All subsequent API requests
 * using the invalidated access token will return HTTP 401 Unauthorized with
 * message "Token expired or invalid. Please log in again."
 *
 * The operation supports concurrent sessions—logging out from one
 * device/browser only invalidates that specific session. Other active sessions
 * on different devices remain valid and unaffected. For example, if a member is
 * logged in on desktop and mobile, logout on desktop invalidates only the
 * desktop session; the mobile session remains active.
 *
 * If the member has no active session (all sessions already have expired_at
 * timestamps), the operation still succeeds with HTTP 200 OK, treating logout
 * as idempotent. No error is returned for logging out when already logged out.
 *
 * WHEN a member's password is changed, THE system SHALL invalidate all refresh
 * tokens associated with that member account, forcing re-login on all devices.
 *
 * @param props.connection
 * @path /discussionBoard/member/auth/member/logout
 * @accessor api.functional.discussionBoard.member.auth.member.logout
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function logout(connection: IConnection): Promise<void> {
  return true === connection.simulate
    ? logout.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...logout.METADATA,
          path: logout.path(),
          status: null,
        },
      );
}
export namespace logout {
  export const METADATA = {
    method: "POST",
    path: "/discussionBoard/member/auth/member/logout",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/discussionBoard/member/auth/member/logout";
  export const random = (): void => typia.random<void>();
  export const simulate = (_connection: IConnection): void => {
    return random();
  };
}
