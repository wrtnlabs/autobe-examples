/**
 * Upload and set a profile picture for a member account.
 *
 * Upload a profile picture for a member's discussion board account. This
 * operation allows authenticated members to upload a new profile picture that
 * will be displayed with their articles, comments, and public profile page
 * throughout the platform.
 *
 * The profile picture must be an image file in one of the supported formats:
 * JPG, PNG, GIF, or WebP. The file size must not exceed 5 MB. The system
 * validates the file type by inspecting the file header (magic number) rather
 * than relying on file extension for security purposes. Upon upload, the system
 * automatically processes the image: resizing it to a standard 200x200 pixel
 * dimension for consistent display, stripping any EXIF metadata to protect
 * privacy, and computing a SHA-256 hash of the file content for integrity
 * verification.
 *
 * The uploaded image is stored in the secure attachment storage system with a
 * system-generated filename following the pattern timestamp_hash_originalname
 * to prevent directory traversal attacks and ensure unique storage paths. The
 * original filename provided by the member is preserved for audit purposes.
 *
 * Upon successful upload, the system updates the member's profile record in the
 * discussion_board_member_profiles table, setting the profile_picture_url field
 * to point to the newly stored image. A corresponding attachment record is
 * created in the discussion_board_attachments table with parent_type='profile'
 * to track all profile picture uploads for audit purposes. The operation is
 * restricted to authenticated members and can only be performed on the member's
 * own profile picture.
 *
 * If the member already has a profile picture, the new upload replaces the
 * previous image. The previous image file may be automatically cleaned up from
 * storage after a grace period. If the member wants to remove their profile
 * picture entirely, they would need to use a separate delete operation rather
 * than uploading a blank or placeholder image.
 *
 * The operation returns the updated member profile information including the
 * new profile_picture_url, allowing the client to immediately display the
 * uploaded picture to confirm successful upload.
 *
 * @param props.connection
 * @param props.memberId Unique identifier of the member account to which the
 *   profile picture will be uploaded
 * @param props.body Profile picture image file to be uploaded and associated
 *   with the member account
 * @path /discussionBoard/member/members/:memberId/profilePicture
 * @accessor api.functional.discussionBoard.member.members.profilePicture.uploadProfilePicture
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function uploadProfilePicture(
  connection: IConnection,
  props: uploadProfilePicture.Props,
): Promise<uploadProfilePicture.Response> {
  return true === connection.simulate
    ? uploadProfilePicture.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...uploadProfilePicture.METADATA,
          path: uploadProfilePicture.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace uploadProfilePicture {
  export type Props = {
    /**
     * Unique identifier of the member account to which the profile picture
     * will be uploaded
     */
    memberId: string & tags.Format<"uuid">;

    /**
     * Profile picture image file to be uploaded and associated with the
     * member account
     */
    body: IDiscussionBoardMember.IUploadProfilePicture;
  };
  export type Body = IDiscussionBoardMember.IUploadProfilePicture;
  export type Response = IDiscussionBoardMemberProfile;

  export const METADATA = {
    method: "POST",
    path: "/discussionBoard/member/members/:memberId/profilePicture",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/discussionBoard/member/members/${encodeURIComponent(props.memberId ?? "null")}/profilePicture`;
  export const random = (): IDiscussionBoardMemberProfile =>
    typia.random<IDiscussionBoardMemberProfile>();
  export const simulate = (
    connection: IConnection,
    props: uploadProfilePicture.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: uploadProfilePicture.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("memberId")(() => typia.assert(props.memberId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

/**
 * Delete a member's profile picture from their discussion board profile.
 *
 * Remove the profile picture associated with a specific member account. This
 * operation sets the profile_picture_url field to null in the
 * discussion_board_member_profiles table, causing the member's avatar to revert
 * to a system default placeholder.
 *
 * Authentication and authorization are enforced to ensure members can only
 * delete their own profile pictures. Attempting to delete another member's
 * profile picture returns a 403 Forbidden error with message "You do not have
 * permission to modify this profile."
 *
 * The profile_picture_url field in discussion_board_member_profiles stores a
 * URI reference to the member's profile picture. When deleted, this field
 * becomes null, and the system displays the default avatar in all locations
 * where the member's profile picture appears (article author attribution,
 * comment author display, profile view, etc.).
 *
 * Upon successful deletion, the profile's updated_at timestamp is updated to
 * the current UTC time, creating an audit trail of the modification. The
 * operation does not delete the actual image file from storage—that cleanup
 * happens asynchronously after confirmation that no other references exist.
 *
 * If the member has no profile picture currently set (profile_picture_url is
 * already null), the operation succeeds with HTTP 200 OK, treating it as an
 * idempotent operation. No error is returned for deleting a non-existent
 * profile picture.
 *
 * @param props.connection
 * @param props.memberId Unique identifier of the member whose profile picture
 *   is being deleted. Must match the authenticated user's member ID from the
 *   JWT token.
 * @path /discussionBoard/member/members/:memberId/profilePicture
 * @accessor api.functional.discussionBoard.member.members.profilePicture.erase
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
