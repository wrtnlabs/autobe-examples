import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardReport } from "../../../../structures/IDiscussionBoardReport";

/**
 * Create a new member report of inappropriate content for moderator review.
 *
 * This operation allows authenticated members to report articles or comments
 * they believe violate community guidelines. Members submit a report containing
 * a reference to the reported content (either an article or comment), a
 * predefined reason category (offensive_language, personal_attack, spam,
 * off_topic, copyright_violation, harassment, or other), and an optional
 * detailed description (maximum 500 characters) explaining their concern.
 *
 * When a report is submitted, the system stores it with pending_review status,
 * making it visible in the moderator review queue. The report captures the
 * reporting member's identity for audit purposes and allows moderators to
 * investigate and take appropriate action (deleting content, suspending
 * accounts, or dismissing the report if no violation is found).
 *
 * Reports are distinct from moderation actions themselves—this operation
 * captures user-generated feedback flagging problematic content, while actual
 * moderation decisions (deletions, suspensions, bans) are handled separately by
 * moderators. This separation enables tracking both member concerns and
 * moderator decisions independently for comprehensive audit trails.
 *
 * Each report is permanently recorded in the system for audit and moderation
 * history purposes. Members can report the same content multiple times
 * (multiple reports from different members), allowing moderators to see which
 * content has attracted multiple complaints. The status field allows moderators
 * to track report workflow: pending_review (awaiting investigation), resolved
 * (moderator took action), or dismissed (moderator reviewed and found no
 * violation).
 *
 * @param props.connection
 * @param props.body Report submission details including the reported content
 *   reference, reason, and optional description
 * @path /discussionBoard/member/reports
 * @accessor api.functional.discussionBoard.member.reports.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function create(
  connection: IConnection,
  props: create.Props,
): Promise<create.Response> {
  return true === connection.simulate
    ? create.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...create.METADATA,
          path: create.path(),
          status: null,
        },
        props.body,
      );
}
export namespace create {
  export type Props = {
    /**
     * Report submission details including the reported content reference,
     * reason, and optional description
     */
    body: IDiscussionBoardReport.ICreate;
  };
  export type Body = IDiscussionBoardReport.ICreate;
  export type Response = IDiscussionBoardReport;

  export const METADATA = {
    method: "POST",
    path: "/discussionBoard/member/reports",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/discussionBoard/member/reports";
  export const random = (): IDiscussionBoardReport =>
    typia.random<IDiscussionBoardReport>();
  export const simulate = (
    connection: IConnection,
    props: create.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: create.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
