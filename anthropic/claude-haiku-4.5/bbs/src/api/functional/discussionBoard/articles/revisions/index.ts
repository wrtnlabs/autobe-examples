import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IPageIDiscussionBoardArticleRevision } from "../../../../structures/IPageIDiscussionBoardArticleRevision";

/**
 * Retrieve the revision history of an article.
 *
 * Retrieve the complete edit history and revisions of a specific article. This
 * operation returns all historical versions of an article identified by
 * articleId, showing how the content has been modified over time. The revision
 * history includes every edit made to the article title and content, who made
 * the edits, when they were made, and the type of edit (member, moderator, or
 * system).
 *
 * Each revision record contains a snapshot of the article's state at the time
 * of that edit. This includes the full title and content text at that point in
 * time, allowing users and moderators to see exactly what changed across edits.
 * The revision records preserve the original author information even if article
 * content was subsequently edited by moderators.
 *
 * Revisions are returned in chronological order from oldest to newest, showing
 * the complete progression of article changes. For each revision, the system
 * provides: the revision ID, article ID, editor information (which member or
 * moderator made the edit), the edit type classification, change reason if
 * documented, and the exact timestamp when the revision was created.
 *
 * Edit type values indicate the nature of the edit: 'member_edit' indicates the
 * original author edited their own article, 'moderator_edit' indicates a
 * moderator modified the article (typically for policy violations or
 * formatting), and 'system_update' indicates automated system modifications.
 * The change_reason field may contain moderator notes explaining why an edit
 * was made.
 *
 * Guests can view revision history for public articles to understand edit
 * patterns. Members can see revision history for all articles including their
 * own and others'. Moderators have full access to all revision information
 * including moderator-only change reasons. This promotes transparency in
 * article modifications and helps users understand the article's evolution.
 *
 * @param props.connection
 * @param props.articleId Unique identifier of the article to retrieve revisions
 *   for
 * @path /discussionBoard/articles/:articleId/revisions
 * @accessor api.functional.discussionBoard.articles.revisions.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
      );
}
export namespace index {
  export type Props = {
    /** Unique identifier of the article to retrieve revisions for */
    articleId: string & tags.Format<"uuid">;
  };
  export type Response = IPageIDiscussionBoardArticleRevision;

  export const METADATA = {
    method: "GET",
    path: "/discussionBoard/articles/:articleId/revisions",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/articles/${encodeURIComponent(props.articleId ?? "null")}/revisions`;
  export const random = (): IPageIDiscussionBoardArticleRevision =>
    typia.random<IPageIDiscussionBoardArticleRevision>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("articleId")(() => typia.assert(props.articleId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
