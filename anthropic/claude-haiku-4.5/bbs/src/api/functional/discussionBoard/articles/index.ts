/**
 * Search and retrieve a filtered, paginated list of discussion board articles.
 *
 * Retrieve a filtered and paginated collection of discussion board articles
 * with comprehensive search and filtering capabilities. This operation provides
 * advanced discovery features for finding articles based on publication status,
 * category assignment, author, creation/publication dates, pinned status, and
 * full-text search across article titles and content.
 *
 * The article entity represents core discussion content in the platform.
 * Articles progress through a defined lifecycle: draft (author composition) →
 * pending_approval (moderator review) → published (publicly visible) → archived
 * or deleted (removed from active listings). Only published articles are
 * publicly visible by default, though filtering options allow access to other
 * statuses based on authorization levels.
 *
 * The operation supports multiple filtering dimensions: status filtering
 * (published, draft, pending_approval, rejected, archived, deleted), category
 * filtering for topic organization, author filtering to find contributions by
 * specific contributors, date range filtering for discovery by creation or
 * publication time, and full-text search capabilities across title and content
 * fields. Sorting options include creation date, publication date, view count,
 * comment count, and pinned status.
 *
 * Pagination is implemented with configurable page sizes and offsets to handle
 * large article collections efficiently. The response includes summary-level
 * information optimized for listing displays, including cached comment counts
 * for performance, view counts for popularity metrics, pinned status for
 * featured article highlighting, and locked status for editorial control.
 * Related operations include detailed article retrieval (GET
 * /articles/{articleId}) and article creation/modification endpoints.
 *
 * @param props.connection
 * @param props.body Search criteria, filtering options, pagination parameters,
 *   and sorting preferences for article discovery
 * @path /discussionBoard/articles
 * @accessor api.functional.discussionBoard.articles.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
