/**
 * Search and retrieve a filtered, paginated list of comments for a discussion
 * board article.
 *
 * Retrieve a filtered and paginated list of comments associated with a specific
 * article from the discussion board system. This operation provides advanced
 * search and filtering capabilities for finding comments based on multiple
 * criteria including content search, author filtering, creation date ranges,
 * and comment status (published, edited, flagged).
 *
 * Pagination and Sorting: The operation supports comprehensive pagination with
 * configurable page sizes and offset parameters. Comments can be sorted by
 * creation date (newest or oldest first), last edit date, author name, or
 * relevance score if full-text search is applied. The response includes
 * pagination metadata showing total comment count, current page, and available
 * pages.
 *
 * Content Access and Authorization: All users, including guests and
 * authenticated members, can view published comments on public articles.
 * However, visibility of certain comments (such as those flagged for review)
 * may be restricted based on user permissions. Moderators have access to view
 * all comments regardless of status. The operation filters results based on the
 * requesting user's authorization level.
 *
 * Article Context: Comments are always returned in the context of their parent
 * article, identified by the articleId path parameter. The operation validates
 * that the specified article exists before returning comments. If the article
 * does not exist, a 404 error is returned. The response includes the article ID
 * for reference and may include summary article information depending on
 * response body definition.
 *
 * @param props.connection
 * @param props.articleId Unique identifier of the article for which comments
 *   are being retrieved
 * @param props.body Search criteria, filtering options, pagination parameters,
 *   and sorting configuration for comment retrieval
 * @path /discussionBoard/articles/:articleId/comments
 * @accessor api.functional.discussionBoard.articles.comments.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Unique identifier of the article for which comments are being
     * retrieved
     */
    articleId: string & tags.Format<"uuid">;

    /**
     * Search criteria, filtering options, pagination parameters, and
     * sorting configuration for comment retrieval
     */
    body: IDiscussionBoardComment.IRequest;
  };
  export type Body = IDiscussionBoardComment.IRequest;
  export type Response = IPageIDiscussionBoardComment.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/discussionBoard/articles/:articleId/comments",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/discussionBoard/articles/${encodeURIComponent(props.articleId ?? "null")}/comments`;
  export const random = (): IPageIDiscussionBoardComment.ISummary =>
    typia.random<IPageIDiscussionBoardComment.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("articleId")(() => typia.assert(props.articleId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

