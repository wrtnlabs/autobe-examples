/**
 * Search and retrieve a filtered, paginated list of comments on a specific
 * article.
 *
 * Retrieve a filtered and paginated list of comments posted on a specific
 * article. This operation provides advanced search and filtering capabilities
 * for finding comments based on multiple criteria including comment text
 * content, author, creation date range, and moderation status. Members can
 * search within discussions to find relevant commentary and discover
 * participant viewpoints.
 *
 * The operation supports comprehensive pagination with configurable page sizes
 * (default 20 comments per page) and sorting options including creation date
 * (newest/oldest first), reply count (most discussed comments first), and
 * relevance for search queries. Comments are returned in their threaded
 * structure showing parent-reply relationships with proper nesting indicators
 * for easy discussion following.
 *
 * Security considerations include enforcing visibility rules based on
 * authenticated status: guests and members see only published comments with
 * deleted comments marked as '[Deleted by author]' and moderated comments shown
 * as '[Removed by moderator]'. Moderators can view all comments including
 * deleted and moderated content with full visibility of moderation details. The
 * operation includes rate limiting on search requests to prevent abuse (maximum
 * 100 search requests per hour per user).
 *
 * This operation integrates with the discussion_board_comments and
 * discussion_board_articles tables, respecting the article-comment relationship
 * and comment threading structure defined in the Prisma schema. The response
 * includes comment author information, timestamps, edit indicators, nested
 * reply structure, and attachment references where applicable. Comment threads
 * support up to 3 levels of nesting in the display with collapse/expand
 * controls for deeper nested conversations.
 *
 * Related operations: POST /articles/{articleId}/comments (create new comment),
 * GET /articles/{articleId} (view full article context), PATCH /articles
 * (search articles). Expected behavior includes instant search results for
 * typical queries, chronological ordering of comments to show discussion flow
 * naturally, and preservation of comment context through author attribution and
 * timestamps.
 *
 * @param props.connection
 * @param props.articleId Unique identifier of the target article whose comments
 *   are being retrieved
 * @param props.body Search criteria and pagination parameters for comment
 *   filtering, sorting, and result limiting
 * @path /discussionBoard/articles/:articleId/comments
 * @accessor api.functional.discussionBoard.articles.comments.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
