/**
 * Retrieve a specific attachment from a discussion board article.
 *
 * Retrieve detailed information about a single attachment file associated with
 * a discussion board article. This operation returns complete attachment
 * metadata including the original filename, file size, MIME type, storage path,
 * and for image attachments, the image dimensions (width and height).
 *
 * The attachment is identified by both the article ID (to scope the attachment
 * to a specific article) and the attachment ID (to identify the specific file).
 * This two-level identification ensures users can only access attachments that
 * belong to the requested article, preventing unauthorized access to
 * attachments from other articles.
 *
 * For image attachments, the response includes image dimensions (width and
 * height in pixels) which are used for rendering the image at the correct
 * aspect ratio. For non-image attachments, these dimension fields are null. The
 * is_image flag indicates whether this is an image file for display purposes.
 *
 * The response includes file metadata such as original filename (for display in
 * the UI), file size in bytes (for quota tracking and user information), MIME
 * type for proper content handling, and creation timestamp. The file_hash
 * provides integrity verification capability.
 *
 * Access control is enforced through the parent article - users can view this
 * attachment if they have access to view the article containing it. Guests can
 * view attachments from published articles, members can view attachments from
 * articles they created or published articles, and moderators can view
 * attachments from all articles including rejected and pending articles.
 *
 * This operation is commonly used to retrieve attachment details before
 * download, to display attachment information in article views, and to verify
 * attachment existence and properties.
 *
 * @param props.connection
 * @param props.articleId Unique identifier of the article containing this
 *   attachment (UUID format)
 * @param props.attachmentId Unique identifier of the attachment to retrieve
 *   (UUID format)
 * @path /discussionBoard/articles/:articleId/attachments/:attachmentId
 * @accessor api.functional.discussionBoard.articles.attachments.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique identifier of the article containing this attachment (UUID
     * format)
     */
    articleId: string & tags.Format<"uuid">;

    /** Unique identifier of the attachment to retrieve (UUID format) */
    attachmentId: string & tags.Format<"uuid">;
  };
  export type Response = IDiscussionBoardAttachment;

  export const METADATA = {
    method: "GET",
    path: "/discussionBoard/articles/:articleId/attachments/:attachmentId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/articles/${encodeURIComponent(props.articleId ?? "null")}/attachments/${encodeURIComponent(props.attachmentId ?? "null")}`;
  export const random = (): IDiscussionBoardAttachment =>
    typia.random<IDiscussionBoardAttachment>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("articleId")(() => typia.assert(props.articleId));
      assert.param("attachmentId")(() => typia.assert(props.attachmentId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

/**
 * Delete an attachment from a discussion board article.
 *
 * Delete a specific attachment file from a discussion board article. This
 * operation performs a soft deletion by recording the deletion timestamp
 * without removing the attachment record from the database, preserving the
 * audit trail and enabling recovery within the retention window.
 *
 * The attachment is identified by both the article ID (to scope to a specific
 * article) and the attachment ID (to identify the specific file to delete).
 * This two-level identification ensures users can only delete attachments from
 * articles they have permission to modify.
 *
 * Permission to delete an attachment is determined by the parent article's
 * permissions: Members can delete attachments from their own unpublished
 * (draft, rejected) articles, but cannot remove attachments from published
 * articles (to prevent retroactive changes to discussion content). Members can
 * also delete attachments from their own comments. Moderators can delete
 * attachments from any article or comment to remove problematic content.
 *
 * When an attachment is deleted, the associated file is marked as deleted
 * (deleted_at timestamp is set) and is hidden from user views. Moderators
 * retain access to deleted attachments for up to 30 days for audit purposes.
 * After the retention window, the physical file is permanently removed from
 * storage by automated cleanup jobs.
 *
 * If the parent article is deleted, all associated attachments are
 * automatically soft-deleted along with the article. Attempting to delete an
 * attachment from a published article when not a moderator will result in a
 * permission error.
 *
 * The operation returns the deleted attachment metadata confirming successful
 * deletion, or an appropriate error if the attachment does not exist, the user
 * lacks permission, or the attachment is already deleted.
 *
 * @param props.connection
 * @param props.articleId Unique identifier of the article containing this
 *   attachment (UUID format)
 * @param props.attachmentId Unique identifier of the attachment to delete (UUID
 *   format)
 * @path /discussionBoard/articles/:articleId/attachments/:attachmentId
 * @accessor api.functional.discussionBoard.articles.attachments.erase
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
