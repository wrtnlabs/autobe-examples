import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IBinaryFileResponse } from "../../../structures/IBinaryFileResponse";

/**
 * Download an attachment file from an article or comment.
 *
 * Retrieves and serves an attachment file that was previously uploaded to an
 * article or comment. The attachment download operation validates attachment
 * existence, verifies it has passed security scanning, and serves the file with
 * appropriate HTTP headers for browser handling.
 *
 * Guests can download attachments from published articles and comments without
 * requiring authentication. Authenticated members can download all attachments
 * they have access to. Moderators can download any attachment including those
 * from suspended or removed content for moderation review purposes.
 *
 * The operation retrieves the complete attachment metadata including original
 * filename (sanitized), file size in bytes, file MIME type, and image
 * dimensions if applicable. The file is served from secure storage using proper
 * HTTP headers: Content-Type matched to file MIME type, Content-Disposition
 * header to trigger download behavior for documents, and appropriate
 * cache-control directives.
 *
 * Images served with image/* MIME types may be displayed inline in browsers,
 * while document files (PDF, Word, Excel, etc.) and archives trigger download
 * dialogs with the original sanitized filename. The system tracks file
 * downloads for audit purposes if configured.
 *
 * Validation ensures the attachment exists and has a security_status of 'safe'
 * - attachments pending scan or flagged as infected cannot be downloaded.
 * Deleted or orphaned attachments (parent article/comment removed) cannot be
 * downloaded and return 'not found' errors. The operation fails gracefully with
 * specific error messages explaining why download is unavailable.
 *
 * Performance expectations: file download should begin within 2 seconds of
 * request. Large files stream to client rather than loading entirely in memory.
 * The operation respects HTTP range requests for resume capability on large
 * files if client supports it.
 *
 * @param props.connection
 * @param props.attachmentId Unique identifier of the attachment file to
 *   download
 * @path /discussionBoard/attachments/:attachmentId/download
 * @accessor api.functional.discussionBoard.attachments.download
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function download(
  connection: IConnection,
  props: download.Props,
): Promise<download.Response> {
  return true === connection.simulate
    ? download.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...download.METADATA,
          path: download.path(props),
          status: null,
        },
      );
}
export namespace download {
  export type Props = {
    /** Unique identifier of the attachment file to download */
    attachmentId: string & tags.Format<"uuid">;
  };
  export type Response = IBinaryFileResponse;

  export const METADATA = {
    method: "GET",
    path: "/discussionBoard/attachments/:attachmentId/download",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/attachments/${encodeURIComponent(props.attachmentId ?? "null")}/download`;
  export const random = (): IBinaryFileResponse =>
    typia.random<IBinaryFileResponse>();
  export const simulate = (
    connection: IConnection,
    props: download.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: download.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("attachmentId")(() => typia.assert(props.attachmentId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
