import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardMemberProfile } from "../../../structures/IDiscussionBoardMemberProfile";

/**
 * Retrieve a member's profile information.
 *
 * Retrieve the public profile information for a discussion board member by
 * their member ID. This operation returns the member's profile data from the
 * discussion_board_member_profiles table, including display name, biographical
 * information, and profile picture URL.
 *
 * The profile information is publicly visible on the platform and includes the
 * display_name field (1-50 characters) shown as author attribution on articles
 * and comments, an optional bio field (up to 500 characters) where members can
 * introduce themselves and share expertise, and a profile_picture_url that
 * references the member's profile image stored in the attachment system.
 *
 * Profile pictures are automatically resized to 200x200 pixels and EXIF
 * metadata is stripped during upload for privacy protection. The bio field can
 * contain information relevant to the economic and political discussion topics
 * of the platform.
 *
 * The profile record is created automatically when a member account is created
 * and maintains a 1:1 relationship with the discussion_board_members table. The
 * created_at timestamp indicates when the profile was created (typically when
 * the member account was registered), and updated_at tracks the most recent
 * modification to any profile field.
 *
 * This operation is public and does not require authentication, allowing all
 * users (including guests) to view member profile information. The profile data
 * supports community interaction by helping users understand other members'
 * backgrounds and expertise relevant to discussions.
 *
 * @param props.connection
 * @param props.memberId Unique identifier of the member whose profile
 *   information should be retrieved (UUID format)
 * @path /discussionBoard/memberProfiles/:memberId
 * @accessor api.functional.discussionBoard.memberProfiles.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique identifier of the member whose profile information should be
     * retrieved (UUID format)
     */
    memberId: string & tags.Format<"uuid">;
  };
  export type Response = IDiscussionBoardMemberProfile;

  export const METADATA = {
    method: "GET",
    path: "/discussionBoard/memberProfiles/:memberId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/memberProfiles/${encodeURIComponent(props.memberId ?? "null")}`;
  export const random = (): IDiscussionBoardMemberProfile =>
    typia.random<IDiscussionBoardMemberProfile>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("memberId")(() => typia.assert(props.memberId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
