import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardComment } from "../../../../structures/IDiscussionBoardComment";
import { IPageIDiscussionBoardComment } from "../../../../structures/IPageIDiscussionBoardComment";

/**
 * Retrieve a paginated list of replies to a specific comment within a threaded
 * discussion.
 *
 * Retrieve all replies (child comments) to a specific parent comment,
 * supporting threaded discussion viewing. This operation enables viewing
 * complete reply chains to any comment on an article. The endpoint returns a
 * paginated list of replies organized chronologically (oldest first by default,
 * with sort options), showing the full discussion thread with context.
 *
 * The operation supports pagination with configurable page sizes to handle
 * comments with many replies efficiently. Users can sort replies by creation
 * date (newest or oldest first) or relevance. The reply list respects
 * visibility rules: guests and members see only published replies, while
 * moderators can view deleted and moderated comments with annotations showing
 * their status and removal reasons.
 *
 * Security considerations include verification that the parent comment still
 * exists (returns 404 if deleted), and respect for article visibility (cannot
 * view replies to comments on archived articles). Rate limiting prevents abuse
 * of this endpoint with maximum 200 requests per hour per user. The operation
 * validates the commentId parameter is a valid UUID format.
 *
 * This operation integrates with the discussion_board_comments table, filtering
 * by parent_comment_id field to retrieve child comments. All replies are
 * guaranteed to be in the same thread (same parent comment), and the operation
 * preserves the original parent comment information for context. Replies
 * include author information (member name and avatar if available), creation
 * timestamp, last modification timestamp, edit count with "edited" indicator,
 * comment content, and any attached files or images.
 *
 * Results are returned as comment summaries optimized for discussion viewing,
 * showing author name, avatar, timestamp, comment text content, edit status,
 * and attached file list. Each result includes information about whether the
 * replying member is the original comment author for edit/delete permission
 * display. When a parent comment has been deleted, the system returns a 404
 * error or empty results with clear message indicating the parent comment is no
 * longer available.
 *
 * @param props.connection
 * @param props.commentId Unique identifier of the parent comment for which to
 *   retrieve replies
 * @param props.body Pagination parameters and sorting preferences for
 *   retrieving replies to the parent comment
 * @path /discussionBoard/comments/:commentId/replies
 * @accessor api.functional.discussionBoard.comments.replies.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /** Unique identifier of the parent comment for which to retrieve replies */
    commentId: string & tags.Format<"uuid">;

    /**
     * Pagination parameters and sorting preferences for retrieving replies
     * to the parent comment
     */
    body: IDiscussionBoardComment.IRequest;
  };
  export type Body = IDiscussionBoardComment.IRequest;
  export type Response = IPageIDiscussionBoardComment.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/discussionBoard/comments/:commentId/replies",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/discussionBoard/comments/${encodeURIComponent(props.commentId ?? "null")}/replies`;
  export const random = (): IPageIDiscussionBoardComment.ISummary =>
    typia.random<IPageIDiscussionBoardComment.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("commentId")(() => typia.assert(props.commentId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
