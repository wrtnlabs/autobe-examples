/**
 * Retrieve complete details for a specific article category identified by its
 * unique UUID identifier. This operation returns the full category record
 * including code, display name, description, activity status, and article
 * statistics.
 *
 * The category code is a unique machine-readable identifier (e.g.,
 * 'economic-policy', 'political-governance') consisting of 5-50 lowercase
 * alphanumeric characters with hyphens. The code serves as an alternative
 * lookup key for API operations and internal system references. The category
 * name is the human-readable display label between 10-100 characters used
 * throughout the user interface for category selection and navigation.
 *
 * The description field (up to 500 characters) provides detailed explanation of
 * the category scope and purpose, helping users understand which articles
 * should belong to that category. For example, the Economic Policy category
 * description might explain: 'Articles about taxation, trade, regulation, and
 * economic policy decisions'. The is_active status indicates whether this
 * category is currently available for article submission - active categories
 * appear in dropdown menus when users create articles, while inactive
 * categories are hidden from new submissions but referenced by historical
 * articles.
 *
 * The article_count field contains a denormalized count of published articles
 * currently assigned to this category. This count is maintained for display
 * efficiency and reflects the number of articles users will find when browsing
 * this category. The response also includes audit timestamps: created_at (when
 * the category was initially created) and updated_at (when it was last
 * modified), providing complete traceability of category lifecycle.
 *
 * Soft-deleted categories (deleted_at is not null) should be excluded from this
 * endpoint unless explicitly requested by authorized administrators. If a
 * category has been deleted, the operation should either return a 404 Not Found
 * response or return a restricted view of the data based on authorization
 * level.
 *
 * @param props.connection
 * @param props.categoryId Unique identifier of the target article category
 * @path /discussionBoard/categories/:categoryId
 * @accessor api.functional.discussionBoard.categories.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique identifier of the target article category */
    categoryId: string & tags.Format<"uuid">;
  };
  export type Response = IDiscussionBoardArticleCategory;

  export const METADATA = {
    method: "GET",
    path: "/discussionBoard/categories/:categoryId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/categories/${encodeURIComponent(props.categoryId ?? "null")}`;
  export const random = (): IDiscussionBoardArticleCategory =>
    typia.random<IDiscussionBoardArticleCategory>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("categoryId")(() => typia.assert(props.categoryId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
