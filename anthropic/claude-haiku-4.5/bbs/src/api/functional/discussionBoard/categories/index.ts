/**
 * Retrieve a paginated list of all active article categories from the
 * discussion board. Categories provide the organizational structure for
 * articles, enabling users to browse content by topic area including economics,
 * politics, and other discussion areas.
 *
 * This operation returns category metadata including the category code
 * (machine-readable identifier), display name, description explaining the
 * category scope, display order for UI rendering, and article count showing the
 * number of published articles in each category. The category code uses
 * lowercase alphanumeric characters with hyphens (e.g., 'economic-policy',
 * 'political-governance') and is between 5-50 characters. The display name is a
 * human-readable title between 10-100 characters designed for user interface
 * display in category selection dropdowns and article filters.
 *
 * Categories are filtered to show only active categories (is_active = true),
 * preventing users from selecting deprecated or inactive categories when
 * creating articles. Soft-deleted categories are excluded from this list but
 * may be referenced by historical articles for data integrity. The response
 * includes a denormalized article_count field for each category, reflecting the
 * number of published articles currently assigned to that category.
 *
 * Results are ordered by the display_order field to ensure consistent
 * presentation in user interfaces. Categories with lower display_order numbers
 * appear first in the category menu, enabling administrators to control
 * category prominence and browsing experience. This operation is typically
 * called during article creation to populate category selection dropdowns or
 * during initial page load to display the category navigation structure.
 *
 * Related operations: Use GET /categories/{categoryId} to retrieve detailed
 * information about a specific category.
 *
 * @param props.connection
 * @path /discussionBoard/categories
 * @accessor api.functional.discussionBoard.categories.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(connection: IConnection): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
      );
}
