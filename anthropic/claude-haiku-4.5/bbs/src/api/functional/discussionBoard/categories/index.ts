import { IConnection } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";

import { IPageIDiscussionBoardCategory } from "../../../structures/IPageIDiscussionBoardCategory";

/**
 * Retrieve all available article categories for classification and filtering.
 *
 * This operation retrieves the complete list of article categories available in
 * the discussion board system. Categories are system-managed reference data
 * defining the allowed classification options for articles (Economics,
 * Politics). The response includes all category metadata including unique code
 * identifier, human-readable name, descriptions, display order for UI
 * presentation, and active status indicating whether each category is currently
 * available for new article creation.
 *
 * The category system provides the canonical set of classification options for
 * the discussion board platform. All articles must be assigned to exactly one
 * category from this list. Categories are used throughout the platform for
 * content organization, user filtering, discovery mechanisms, and API filtering
 * operations.
 *
 * Guest users and authenticated members can access this endpoint to view
 * available categories for browsing articles and understanding content
 * classification. Moderators use this endpoint in administrative contexts for
 * category management. The endpoint is typically called during initial page
 * load to populate category selection dropdowns and filtering menus in the user
 * interface.
 *
 * @param props.connection
 * @path /discussionBoard/categories
 * @accessor api.functional.discussionBoard.categories.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(connection: IConnection): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
      );
}
export namespace index {
  export type Response = IPageIDiscussionBoardCategory;

  export const METADATA = {
    method: "GET",
    path: "/discussionBoard/categories",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/discussionBoard/categories";
  export const random = (): IPageIDiscussionBoardCategory =>
    typia.random<IPageIDiscussionBoardCategory>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}
