import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardMember } from "../../../structures/IDiscussionBoardMember";
import { IPageIDiscussionBoardMember } from "../../../structures/IPageIDiscussionBoardMember";

/**
 * Search and retrieve a paginated list of discussion board members.
 *
 * Retrieve a filtered and paginated list of registered members on the
 * discussion board platform.
 *
 * This operation provides member discovery and listing functionality supporting
 * both regular members browsing the community and administrators managing
 * member accounts. The operation filters members by account status (active,
 * suspended, terminated) and email verification status to support different use
 * cases. Members can search for other members by username or display name to
 * connect with contributors to specific discussions.
 *
 * Pagination parameters control result set size and offset for efficient
 * client-side rendering of large member lists. Sorting options allow ordering
 * by membership duration, display name, last login, article count, or other
 * member activity metrics. The operation respects member privacy settings and
 * only returns public member information.
 *
 * Security considerations: Only verified, active members are visible in public
 * member lists by default. Suspended or terminated accounts are excluded from
 * public discovery but may be visible to administrators. Personal information
 * such as email addresses are never included in list results—only
 * publicly-visible profile information. The operation implements rate limiting
 * to prevent automated member enumeration attacks.
 *
 * @param props.connection
 * @param props.body Search criteria, filters, pagination parameters, and
 *   sorting options for member listing
 * @path /discussionBoard/members
 * @accessor api.functional.discussionBoard.members.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Search criteria, filters, pagination parameters, and sorting options
     * for member listing
     */
    body: IDiscussionBoardMember.IRequest;
  };
  export type Body = IDiscussionBoardMember.IRequest;
  export type Response = IPageIDiscussionBoardMember.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/discussionBoard/members",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/discussionBoard/members";
  export const random = (): IPageIDiscussionBoardMember.ISummary =>
    typia.random<IPageIDiscussionBoardMember.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
