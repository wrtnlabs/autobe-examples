/**
 * Terminate a moderator authentication session by ID.
 *
 * This operation allows a moderator to terminate their active session,
 * effectively logging them out from the moderation dashboard. The session ID
 * corresponds to a record in the discussion_board_moderator_sessions table that
 * tracks the moderator's login context including IP address, access URL, and
 * referrer information.
 *
 * When the session is deleted, the system updates the expired_at timestamp
 * field to mark the session as terminated. This prevents further API requests
 * using tokens associated with this session. The moderator's refresh token for
 * this session is also invalidated immediately, requiring re-authentication to
 * access moderation features again.
 *
 * Security Context: Only the moderator who owns the session can terminate their
 * own session. Moderators cannot terminate other moderators' sessions. This
 * operation requires a valid access token proving the requester's identity and
 * matching the session's moderator association.
 *
 * Session Cleanup: The operation does not permanently delete the session record
 * from the database. Instead, it marks the session with an expiration timestamp
 * (expired_at), preserving the session history for audit and security logging
 * purposes. This audit trail allows administrators to review moderator login
 * and logout patterns for compliance and security monitoring.
 *
 * Related Operations: This operation works in conjunction with POST
 * /auth/moderator/validate-token to check session validity. Members typically
 * call this endpoint explicitly during logout, or the system may invalidate
 * expired sessions automatically based on the 7-day session expiration policy.
 *
 * @param props.connection
 * @param props.sessionId Unique identifier of the moderator session to
 *   terminate, in UUID format (global scope)
 * @path /discussionBoard/moderator/auth/moderator/sessions/:sessionId
 * @accessor api.functional.discussionBoard.moderator.auth.moderator.sessions.erase
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
