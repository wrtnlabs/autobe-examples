/**
 * Issue a warning to a discussion board member for policy violations or
 * guideline breaches.
 *
 * Issue a formal warning to a member account due to policy violations or
 * community guideline breaches. This operation documents moderator-initiated
 * disciplinary action without immediately restricting member access, serving as
 * a first escalation step before potential account suspension.
 *
 * The warning action is recorded in the discussion_board_user_warnings table
 * with action_type of 'warning', capturing the moderator identity, warning
 * reason, and optional detailed notes. The operation maintains an immutable
 * audit trail of all disciplinary actions for accountability and consistency
 * review. Warnings accumulate in a member's moderation history, allowing
 * moderators to review escalation patterns and understand the context for more
 * severe actions like suspension or termination.
 *
 * When a warning is issued, the system SHALL send a notification email to the
 * warned member's registered email address explaining the policy violation, the
 * specific reason for the warning, and what behavior changes are expected. The
 * email includes information about potential consequences of continued
 * violations (suspension, then termination). Members can view their warning
 * history in their account settings to understand their moderation status.
 *
 * When a moderator issues a warning, they must provide a business reason
 * (10-500 characters) explaining the violation category or specific problematic
 * behavior. Optional moderator notes (up to 1000 characters) allow detailed
 * context-setting for other moderators reviewing this member's history, such as
 * references to previous violations, specific comments/articles that triggered
 * the warning, or escalation justification.
 *
 * Warnings persist indefinitely in the member's moderation history and do not
 * auto-expire. They serve as permanent record of disciplinary actions, enabling
 * moderators to track patterns across extended timeframes. The warning does not
 * automatically restrict member posting rights—members continue to participate
 * normally. However, repeated warnings form the basis for escalation to
 * suspension or termination actions.
 *
 * This operation is exclusively available to moderator accounts. Only users
 * with moderator role can issue warnings through this endpoint. Member accounts
 * attempting to access this endpoint receive HTTP 403 Forbidden response.
 *
 * @param props.connection
 * @param props.memberId Unique identifier of the member account being warned
 * @param props.body Warning details including reason and optional moderator
 *   notes
 * @path /discussionBoard/moderator/members/:memberId/warn
 * @accessor api.functional.discussionBoard.moderator.members.warn
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
