/**
 * Retrieve filtered and paginated list of content policy violations with
 * enforcement history and contributor context.
 *
 * This operation provides moderators access to violation records across the
 * platform, enabling comprehensive monitoring of content policy enforcement and
 * contributor behavior patterns. The violation records table maintains a
 * complete, immutable audit trail of every policy violation detected in
 * articles and comments, creating institutional memory of enforcement actions.
 *
 * Moderators use this endpoint to review violation history for contributors,
 * guiding decisions about progressive escalation (warnings → restrictions →
 * suspensions). Each violation record includes the type of violation (hate
 * speech, personal attack, misinformation, harassment, spam, off-topic, graphic
 * content, threats, copyright, other), severity classification
 * (minor/moderate/severe), violation description with specific examples,
 * enforcement action taken
 * (edited/removed/warned/restricted/suspended/escalated), and detection
 * timestamp.
 *
 * The operation supports powerful filtering to enable targeted violation
 * analysis. Moderators can filter by violation type to identify patterns (e.g.,
 * repeated misinformation violations), filter by contributor to review their
 * complete violation history, filter by severity level to focus on serious
 * violations, filter by action taken to verify enforcement consistency, and
 * filter by date range to see recent or historical violations. These filters
 * combine to support sophisticated violation pattern analysis.
 *
 * Security and Authorization: Only authenticated moderators can access this
 * endpoint. The response includes violation details necessary for moderation
 * decisions but does not expose confidential moderator deliberations or
 * internal investigation notes. Moderators can view all violations system-wide
 * for oversight and learning purposes.
 *
 * Violation Escalation Context: Violations form the foundation of contributor
 * account management. The violation history directly informs moderation
 * decisions: first violation typically results in warning, second violation
 * within 30 days results in temporary restrictions, third violation within 30
 * days triggers suspension review. This endpoint enables moderators to quickly
 * assess violation history and make consistent escalation decisions. The
 * complete audit trail supports appeals and administrative oversight of
 * moderation consistency.
 *
 * Content Snapshot and Enforcement Tracking: Each violation record includes a
 * content snapshot (first 500 characters) of the violating content at time of
 * detection, preserving evidence even if the original content was edited or
 * deleted. This enables moderators to verify that enforcement was appropriate.
 * The action_details field captures specifics of moderator response (what was
 * edited, warning message text, restriction duration).
 *
 * Pagination and Performance: Results are paginated to handle systems with
 * thousands of violation records. The operation returns pagination metadata
 * including current page, total pages, total violation count, and optional
 * aggregation data (count by violation type, count by contributor, severity
 * distribution) for analytical insights into enforcement patterns.
 *
 * Response Includes: Each violation record includes violation type, severity
 * level, violation description, content snapshot, action taken and details,
 * contributor username, detection timestamp, and linked article/comment
 * reference. This information enables comprehensive violation review without
 * additional queries.
 *
 * @param props.connection
 * @param props.body Search and filtering parameters for violation records
 *   including violation type, contributor, severity level, action taken, and
 *   date range filters with pagination and sorting options
 * @path /discussionBoard/moderator/moderation/violations
 * @accessor api.functional.discussionBoard.moderator.moderation.violations.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Search and filtering parameters for violation records including
     * violation type, contributor, severity level, action taken, and date
     * range filters with pagination and sorting options
     */
    body: IDiscussionBoardContentViolationRecord.IRequest;
  };
  export type Body = IDiscussionBoardContentViolationRecord.IRequest;
  export type Response = IPageIDiscussionBoardContentViolationRecord.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/discussionBoard/moderator/moderation/violations",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/discussionBoard/moderator/moderation/violations";
  export const random =
    (): IPageIDiscussionBoardContentViolationRecord.ISummary =>
      typia.random<IPageIDiscussionBoardContentViolationRecord.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
