/**
 * Search and retrieve a filtered, paginated list of contributor account
 * suspensions and restrictions.
 *
 * Retrieve a comprehensive list of contributor account suspension and
 * restriction records with advanced filtering and search capabilities. This
 * operation provides moderators visibility into all enforcement actions taken
 * against contributor accounts, enabling tracking of restriction status,
 * enforcement history, and policy compliance.
 *
 * The operation supports filtering across multiple enforcement dimensions
 * including affected contributor, moderator who imposed the restriction,
 * restriction type (posting_restriction preventing article/comment submissions,
 * temporary_suspension denying login access, permanent_ban permanently
 * disabling account), current restriction status (active restrictions in
 * effect, lifted restrictions manually removed early, expired restrictions that
 * naturally concluded), and severity classification (minor for first offenses,
 * moderate for repeated violations, severe for serious violations, permanent
 * for irreversible bans). Date range filters enable analysis of restriction
 * periods and enforcement patterns over time.
 *
 * Results are returned in paginated format with configurable page size and
 * sorting options. Default sorting is by imposed_at timestamp in descending
 * order (most recent restrictions first), enabling quick identification of
 * active and recent enforcement actions. Alternative sorting by contributor,
 * expiration date, or severity provides different analytical perspectives for
 * moderation review and pattern analysis.
 *
 * Security considerations include role-based access (moderators only) to
 * prevent unauthorized visibility of enforcement actions and justifications.
 * The suspension records include lifting information and lift_reason to track
 * restriction removal decisions, supporting appeals processes and early release
 * programs for rehabilitated contributors.
 *
 * The operation integrates with the discussion_board_user_suspensions table as
 * defined in the Prisma schema, providing access to suspension_type, reason,
 * severity_level, duration_days, suspended_at, expiration_at, status,
 * lifted_at, and lift_reason fields along with references to the contributor
 * and imposing moderator. Active restrictions (where status is 'active' and
 * current time is before expiration_at) are automatically enforced in the
 * platform's posting and login systems.
 *
 * @param props.connection
 * @param props.body Search criteria, filtering options, and pagination
 *   parameters for the suspension records query
 * @path /discussionBoard/moderator/moderation/suspensions
 * @accessor api.functional.discussionBoard.moderator.moderation.suspensions.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Search criteria, filtering options, and pagination parameters for the
     * suspension records query
     */
    body: IDiscussionBoardUserSuspension.IRequest;
  };
  export type Body = IDiscussionBoardUserSuspension.IRequest;
  export type Response = IPageIDiscussionBoardUserSuspension.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/discussionBoard/moderator/moderation/suspensions",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/discussionBoard/moderator/moderation/suspensions";
  export const random = (): IPageIDiscussionBoardUserSuspension.ISummary =>
    typia.random<IPageIDiscussionBoardUserSuspension.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
