/**
 * Validate a moderator's authentication token and active session.
 *
 * This operation validates that a moderator's authentication token is still
 * valid and their associated session remains active. The operation requires the
 * moderator to include their current access token in the Authorization header
 * (Bearer token format).
 *
 * Validation Process: The system performs the following checks on the provided
 * token: (1) Verifies the token signature using the configured signing secret,
 * (2) Checks that the token has not expired by comparing the exp claim against
 * current time, (3) Extracts the moderator ID from the token claims, (4)
 * Queries the discussion_board_moderator_sessions table to confirm an active
 * session exists for that moderator, (5) Verifies the session's expired_at
 * field is null (indicating an active, non-terminated session), (6) Confirms
 * the moderator's account_status in discussion_board_moderators table is
 * 'active'.
 *
 * Token Structure: The access token contains JWT claims including userId
 * (moderator ID), email, username, displayName, role ('moderator'),
 * emailVerified status, issued-at timestamp (iat), and expiration timestamp
 * (exp). The token is signed using HS256 algorithm with a secure secret key.
 *
 * Session Management: Sessions represent individual logins and can persist
 * across multiple API requests. A moderator can have multiple concurrent
 * sessions (e.g., logged in from different devices). Each session has a unique
 * ID and tracks the IP address, URL, and referrer from which the session
 * originated. Sessions are marked expired after 7 days of creation or when
 * explicitly terminated via DELETE /auth/moderator/sessions/{sessionId}.
 *
 * Error Handling: If the token is invalid, expired, or the corresponding
 * session is inactive, the operation returns HTTP 401 Unauthorized. If the
 * moderator account has been suspended or terminated (account_status !=
 * 'active'), the operation denies validation even if the token appears valid.
 * This ensures immediate revocation of access when a moderator role is
 * removed.
 *
 * Use Cases: This operation is typically called by the client periodically or
 * when accessing protected resources to determine if session refresh is needed.
 * If validation fails, the client knows to request a new token using the
 * refresh token endpoint or prompt the moderator to log in again.
 *
 * @param props.connection
 * @param props.body Token validation request with the moderator's current
 *   access token
 * @path /discussionBoard/moderator/auth/moderator/validate-token
 * @accessor api.functional.discussionBoard.moderator.auth.moderator.validate_token.validateToken
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function validateToken(
  connection: IConnection,
  props: validateToken.Props,
): Promise<validateToken.Response> {
  return true === connection.simulate
    ? validateToken.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...validateToken.METADATA,
          path: validateToken.path(),
          status: null,
        },
        props.body,
      );
}
