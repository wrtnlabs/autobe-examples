import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardArticle } from "../../../../../structures/IDiscussionBoardArticle";
import { IPageIDiscussionBoardArticle } from "../../../../../structures/IPageIDiscussionBoardArticle";

/**
 * Search and retrieve pending articles awaiting moderator review and approval.
 *
 * Retrieve a filtered and paginated list of discussion board articles currently
 * pending moderator approval. This operation is the primary interface for
 * moderators to access the content review queue and manage articles awaiting
 * publication decisions.
 *
 * The operation supports comprehensive search and filtering capabilities
 * including sorting by submission date, article title, category, or creator.
 * Moderators can use pagination to navigate through pending items efficiently.
 * The status filter is automatically applied to return only articles with
 * status='pending_approval', excluding already published, rejected, or archived
 * articles.
 *
 * Response includes article summary information with creator details, category
 * assignment, submission timestamps, view count, and any previous rejection
 * reason if the article was submitted after initial rejection. This information
 * enables moderators to make informed approval or rejection decisions.
 *
 * Security and authorization: Only moderators with active status can access
 * this operation. The operation filters articles based on moderation queue
 * state, not user-specific permissions, ensuring all moderators see the
 * complete review queue for transparent workload distribution and consistent
 * moderation across the platform.
 *
 * @param props.connection
 * @param props.body Search criteria, filtering options, and pagination
 *   parameters for pending article retrieval
 * @path /discussionBoard/moderator/moderation/pending-articles
 * @accessor api.functional.discussionBoard.moderator.moderation.pending_articles.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Search criteria, filtering options, and pagination parameters for
     * pending article retrieval
     */
    body: IDiscussionBoardArticle.IRequest;
  };
  export type Body = IDiscussionBoardArticle.IRequest;
  export type Response = IPageIDiscussionBoardArticle.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/discussionBoard/moderator/moderation/pending-articles",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () =>
    "/discussionBoard/moderator/moderation/pending-articles";
  export const random = (): IPageIDiscussionBoardArticle.ISummary =>
    typia.random<IPageIDiscussionBoardArticle.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
