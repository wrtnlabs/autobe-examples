/**
 * Terminate the current moderator authentication session and invalidate login
 * credentials.
 *
 * Logs out the authenticated moderator by invalidating their current session.
 * This operation removes the active moderator session, forcing
 * re-authentication on the next moderation request. The session termination is
 * recorded with the logout timestamp in the expired_at field of the
 * discussion_board_moderator_sessions record.
 *
 * Security Context: This operation requires an authenticated moderator with an
 * active session. The system identifies the moderator from the JWT token in the
 * Authorization header and invalidates only that specific session, allowing the
 * moderator to maintain other concurrent sessions on different devices if
 * desired.
 *
 * Session Management: The operation performs a soft termination of the session
 * by setting the expired_at timestamp to the current UTC time. The session
 * record is retained in the database for audit purposes, maintaining a complete
 * history of moderator access. When the logout succeeds, authentication tokens
 * become invalid and subsequent API requests from that session will be rejected
 * with HTTP 401 Unauthorized.
 *
 * Audit Trail: The session termination event is recorded in the
 * discussion_board_moderator_sessions table with the precise expiration
 * timestamp. This creates an immutable audit record of when the moderator ended
 * their session, supporting security monitoring and accountability
 * requirements.
 *
 * Related Operations: The logout operation should be used when a moderator
 * intentionally ends their administrative session. To retrieve information
 * about current and past sessions, use the GET /auth/moderator/sessions
 * operation to view session history and login details.
 *
 * @param props.connection
 * @path /discussionBoard/moderator/auth/moderator/logout
 * @accessor api.functional.discussionBoard.moderator.auth.moderator.logout
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function logout(connection: IConnection): Promise<void> {
  return true === connection.simulate
    ? logout.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...logout.METADATA,
          path: logout.path(),
          status: null,
        },
      );
}
export namespace logout {
  export const METADATA = {
    method: "POST",
    path: "/discussionBoard/moderator/auth/moderator/logout",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/discussionBoard/moderator/auth/moderator/logout";
  export const random = (): void => typia.random<void>();
  export const simulate = (_connection: IConnection): void => {
    return random();
  };
}
