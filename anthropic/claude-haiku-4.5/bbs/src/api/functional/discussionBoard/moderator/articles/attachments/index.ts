import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

/**
 * Remove a file attachment from a discussion board article.
 *
 * Delete a specific file attachment that was previously uploaded to accompany
 * an article. This operation removes the attachment metadata record from the
 * discussion_board_article_attachments table and triggers deletion of the
 * physical file from storage.
 *
 * The attachment must exist and be associated with the specified article. The
 * operation validates that the requesting user has appropriate permissions to
 * delete attachments - the contributor who uploaded the file, the article
 * author, or a moderator with elevated privileges can perform this action.
 *
 * Once deleted, the attachment cannot be recovered as permanent deletion is
 * applied. The article itself remains unaffected by attachment deletion. If the
 * article contains multiple attachments, only the specified attachment is
 * removed.
 *
 * This operation is commonly performed when: contributors remove accidentally
 * uploaded files, moderators enforce content policies by removing inappropriate
 * attachments, or users clean up outdated supporting materials. The operation
 * supports audit logging to track which user deleted the attachment and when
 * the deletion occurred.
 *
 * @param props.connection
 * @param props.articleId Unique identifier of the article containing the
 *   attachment to be deleted
 * @param props.attachmentId Unique identifier of the attachment file record to
 *   be deleted from the article
 * @path /discussionBoard/moderator/articles/:articleId/attachments/:attachmentId
 * @accessor api.functional.discussionBoard.moderator.articles.attachments.erase
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function erase(
  connection: IConnection,
  props: erase.Props,
): Promise<void> {
  return true === connection.simulate
    ? erase.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...erase.METADATA,
          path: erase.path(props),
          status: null,
        },
      );
}
export namespace erase {
  export type Props = {
    /**
     * Unique identifier of the article containing the attachment to be
     * deleted
     */
    articleId: string & tags.Format<"uuid">;

    /**
     * Unique identifier of the attachment file record to be deleted from
     * the article
     */
    attachmentId: string & tags.Format<"uuid">;
  };

  export const METADATA = {
    method: "DELETE",
    path: "/discussionBoard/moderator/articles/:articleId/attachments/:attachmentId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/moderator/articles/${encodeURIComponent(props.articleId ?? "null")}/attachments/${encodeURIComponent(props.attachmentId ?? "null")}`;
  export const random = (): void => typia.random<void>();
  export const simulate = (
    connection: IConnection,
    props: erase.Props,
  ): void => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: erase.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("articleId")(() => typia.assert(props.articleId));
      assert.param("attachmentId")(() => typia.assert(props.attachmentId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
