import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardReport } from "../../../../../structures/IDiscussionBoardReport";

/**
 * Update moderator notes on a discussion board content report.
 *
 * Update the moderator notes associated with a specific content report in the
 * discussion board system. Moderators use this operation to document their
 * investigation findings, reasoning, and notes while reviewing reported content
 * (articles or comments) that members have flagged for policy violations.
 *
 * The moderator notes field records the moderator's assessment of whether the
 * content violates community guidelines, explains their decision-making
 * process, and documents any relevant context discovered during investigation.
 * Notes are limited to 500 characters to maintain concise, focused
 * documentation.
 *
 * This operation is exclusively available to moderators who are responsible for
 * content review and policy enforcement. The operation updates the updated_at
 * timestamp to track when notes were last modified, enabling audit trails and
 * tracking of moderator activity. Only moderators assigned to the report
 * (stored in the assigned_moderator_id field) can modify the notes for
 * consistency and accountability.
 *
 * The underlying discussion_board_reports table maintains a complete audit
 * history of all report information including reporter identity, reported
 * content reference, report reason, status, and moderator decisions. This
 * operation integrates with the moderation workflow where reports progress
 * through pending_review, resolved, or dismissed statuses.
 *
 * @param props.connection
 * @param props.reportId Unique identifier of the discussion board report to
 *   update
 * @param props.body Moderator notes and investigation findings for the content
 *   report
 * @path /discussionBoard/moderator/reports/:reportId/notes
 * @accessor api.functional.discussionBoard.moderator.reports.notes.update
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function update(
  connection: IConnection,
  props: update.Props,
): Promise<update.Response> {
  return true === connection.simulate
    ? update.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...update.METADATA,
          path: update.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace update {
  export type Props = {
    /** Unique identifier of the discussion board report to update */
    reportId: string & tags.Format<"uuid">;

    /** Moderator notes and investigation findings for the content report */
    body: IDiscussionBoardReport.IUpdate;
  };
  export type Body = IDiscussionBoardReport.IUpdate;
  export type Response = IDiscussionBoardReport;

  export const METADATA = {
    method: "PUT",
    path: "/discussionBoard/moderator/reports/:reportId/notes",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/discussionBoard/moderator/reports/${encodeURIComponent(props.reportId ?? "null")}/notes`;
  export const random = (): IDiscussionBoardReport =>
    typia.random<IDiscussionBoardReport>();
  export const simulate = (
    connection: IConnection,
    props: update.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: update.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("reportId")(() => typia.assert(props.reportId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
