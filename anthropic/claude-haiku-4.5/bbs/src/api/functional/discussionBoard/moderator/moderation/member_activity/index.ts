import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardModerationAction } from "../../../../../structures/IDiscussionBoardModerationAction";
import { IPageIDiscussionBoardModerationAction } from "../../../../../structures/IPageIDiscussionBoardModerationAction";

/**
 * Retrieve a filtered, paginated list of moderation actions affecting a
 * specific member.
 *
 * Retrieve the complete moderation history for a specific member, showing all
 * moderation actions taken on their content and account. This operation
 * displays all articles that were approved or rejected, all comments that were
 * deleted, any account status changes (suspensions, warnings, terminations),
 * and any editorial corrections made by moderators to the member's content.
 *
 * The operation provides context for member disputes or appeals, enabling both
 * moderators and members (with appropriate authorization) to understand why
 * specific content was rejected or removed. It supports filtering by action
 * type and date range to focus on specific moderation events, and results are
 * paginated chronologically from most recent to oldest.
 *
 * This operation serves multiple use cases: members can view their moderation
 * history and understand why their content was not published; moderators can
 * review moderation patterns against a specific user for consistency analysis
 * and identification of repeat violations; administrators can analyze user
 * behavior and enforcement patterns.
 *
 * Security: This operation can be accessed by moderators viewing member history
 * for administrative purposes. Members may be able to access their own
 * moderation history through authorization checking in the implementation
 * (checking if requesting member matches memberId in path).
 *
 * Related operations: PATCH /moderation/actions retrieves system-wide
 * moderation actions with broader filtering. GET /members/{memberId} provides
 * member account information.
 *
 * @param props.connection
 * @param props.memberId Unique identifier of the member whose moderation
 *   history is being retrieved (global scope)
 * @param props.body Filtering options and pagination parameters for retrieving
 *   moderation actions affecting the member
 * @path /discussionBoard/moderator/moderation/member-activity/:memberId
 * @accessor api.functional.discussionBoard.moderator.moderation.member_activity.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Unique identifier of the member whose moderation history is being
     * retrieved (global scope)
     */
    memberId: string & tags.Format<"uuid">;

    /**
     * Filtering options and pagination parameters for retrieving moderation
     * actions affecting the member
     */
    body: IDiscussionBoardModerationAction.IRequest;
  };
  export type Body = IDiscussionBoardModerationAction.IRequest;
  export type Response = IPageIDiscussionBoardModerationAction.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/discussionBoard/moderator/moderation/member-activity/:memberId",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/discussionBoard/moderator/moderation/member-activity/${encodeURIComponent(props.memberId ?? "null")}`;
  export const random = (): IPageIDiscussionBoardModerationAction.ISummary =>
    typia.random<IPageIDiscussionBoardModerationAction.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("memberId")(() => typia.assert(props.memberId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
