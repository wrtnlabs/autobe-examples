/**
 * Retrieve the moderation dashboard with content review queue, violation
 * tracking, and enforcement actions.
 *
 * Fetch the complete moderation dashboard providing comprehensive oversight of
 * platform moderation activities, content violations, and user enforcement.
 * This operation aggregates data from multiple tables to present moderators
 * with a unified administrative interface.
 *
 * The dashboard displays several key sections: pending content review items
 * (articles and comments flagged for violation), user violation tracking
 * showing cumulative violations per member and automatic enforcement
 * thresholds, recent moderation actions taken by any moderator with full audit
 * trail, and account status management allowing moderators to suspend or ban
 * problematic users.
 *
 * Moderation enforcement operates on a tiered violation system tracked in the
 * discussion_board_user_violations table. The system automatically triggers
 * account suspension when a member accumulates 3 violations within 30 days,
 * with suspension lasting 7 days by default. Permanent account bans occur when
 * members accumulate 5 violations within 90 days. All violations are logged
 * with violation_type (spam, harassment, inappropriate_content, off_topic,
 * misinformation, copyright_violation, illegal_content), violation_date for
 * threshold calculation, and associated moderation_log_id linking each
 * violation to the enforcement action taken.
 *
 * The moderation_logs table provides complete audit trail of all moderator
 * actions including action_type (remove_article, remove_comment, suspend_user,
 * ban_user, restore_article, restore_comment, warning_issued, flag_content),
 * target_type (article, comment, member) with polymorphic targeting,
 * moderator_id identifying who took action, and reason documenting why action
 * was taken. This enables transparent community enforcement and compliance
 * documentation.
 *
 * Content flagging uses the articles.status and comments.status fields:
 * articles and comments with status='published' are active content,
 * status='archived' indicates moderator-hidden articles, status='deleted'
 * indicates user or moderator deletion, status='moderated' indicates removed by
 * moderators. The dashboard displays all non-published content and allows
 * moderators to restore or permanently delete.
 *
 * The operation requires moderator authentication (JWT token with moderator
 * role). Non-moderators attempting access will be denied with permission error.
 * Response includes aggregated violation statistics, content flagging summary,
 * recent moderator actions log, and user account status overview enabling rapid
 * assessment of platform moderation state.
 *
 * @param props.connection
 * @path /discussionBoard/moderator/moderation/dashboard
 * @accessor api.functional.discussionBoard.moderator.moderation.dashboard
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function dashboard(
  connection: IConnection,
): Promise<dashboard.Response> {
  return true === connection.simulate
    ? dashboard.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...dashboard.METADATA,
          path: dashboard.path(),
          status: null,
        },
      );
}
export namespace dashboard {
  export type Response = IDiscussionBoardModerationDashboard;

  export const METADATA = {
    method: "GET",
    path: "/discussionBoard/moderator/moderation/dashboard",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/discussionBoard/moderator/moderation/dashboard";
  export const random = (): IDiscussionBoardModerationDashboard =>
    typia.random<IDiscussionBoardModerationDashboard>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}
