/**
 * Search and retrieve flagged or reported content for moderator review.
 *
 * This endpoint provides moderators with comprehensive content review
 * capabilities for managing community standards. The operation performs complex
 * queries against discussion_board_articles and discussion_board_comments
 * tables to return content requiring moderation attention, sorted by priority
 * and relevance.
 *
 * WHEN a moderator requests content for review, THE system SHALL return
 * articles and comments matching the specified filter criteria including:
 * content status (published, flagged for review, removed by moderator), content
 * type (articles or comments), author information, creation date ranges,
 * violation types, and moderation priority. The operation supports pagination
 * with configurable page size and sort order.
 *
 * The request body allows moderators to specify sophisticated search and filter
 * parameters: filter_type (article or comment), status_filter (published,
 * flagged, removed, all), author_id (optional UUID to filter by specific user),
 * violation_type (spam, harassment, inappropriate_content, off_topic,
 * misinformation, copyright_violation, illegal_content), date_range (from and
 * to timestamps in ISO 8601 format), priority_level (critical, high, normal,
 * low based on violation severity), and sort_by (priority, created_date,
 * updated_date, view_count for articles).
 *
 * The response includes full content details (title, body, author, timestamps),
 * metadata (view count for articles, nested comment context), attachment
 * information with security status, and complete moderation history including
 * previous removal reasons and moderator notes. This enables moderators to make
 * informed decisions about content enforcement and review policy violations.
 *
 * Access is restricted to moderators only. The operation respects database
 * constraints: soft-deleted content (deleted_at is not NULL) is still visible
 * to moderators for review purposes, allowing evaluation of removal decisions.
 * Paginated results prevent performance degradation with large datasets,
 * typically returning 20-50 items per page based on moderator configuration.
 *
 * @param props.connection
 * @param props.body Advanced search and filtering parameters for content
 *   moderation review
 * @path /discussionBoard/moderator/moderation/content
 * @accessor api.functional.discussionBoard.moderator.moderation.content.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Advanced search and filtering parameters for content moderation
     * review
     */
    body: IDiscussionBoardModerationLog.IContentRequest;
  };
  export type Body = IDiscussionBoardModerationLog.IContentRequest;
  export type Response = IPageIDiscussionBoardModerationLog.IContent;

  export const METADATA = {
    method: "PATCH",
    path: "/discussionBoard/moderator/moderation/content",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/discussionBoard/moderator/moderation/content";
  export const random = (): IPageIDiscussionBoardModerationLog.IContent =>
    typia.random<IPageIDiscussionBoardModerationLog.IContent>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
