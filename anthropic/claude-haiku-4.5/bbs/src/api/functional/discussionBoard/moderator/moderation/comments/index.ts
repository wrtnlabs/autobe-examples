/**
 * Review and update moderation status of a comment.
 *
 * This operation enables moderators to review flagged comments and take
 * moderation action. Moderators can approve comments that were submitted for
 * review (clearing flags and setting status to published), remove comments that
 * violate community guidelines (marking them as moderated), or restore
 * previously moderated comments. The operation provides a streamlined interface
 * for discussion moderation workflows.
 *
 * The moderation action applies business rules from the discussion board's
 * community guidelines. When content is removed by marking as moderated, the
 * comment becomes invisible to regular users and guests, displaying as
 * '[Removed by moderator]' instead of the original content. The comment record
 * itself remains preserved in the database for audit purposes and to maintain
 * thread integrity. Moderators retain full visibility of removed comments
 * including the original content.
 *
 * Security considerations include role-based access control - only
 * authenticated moderators can access this endpoint. When a moderator removes
 * content, the system records the action in an immutable audit log for
 * compliance and transparency. The operation validates that the comment exists
 * and belongs to a valid article before processing. Nested replies to moderated
 * comments are handled according to the moderation policy (preserved if parent
 * is moderated).
 *
 * This operation interacts with the comment management system
 * (discussion_board_comments) and creates moderation log records
 * (discussion_board_moderation_logs) for every action taken. Related operations
 * include retrieving comments for moderation review and accessing the
 * moderation audit log. Expected behavior includes immediate status updates,
 * creation of moderation records, and optional notification to the comment
 * author about removal or approval.
 *
 * @param props.connection
 * @param props.commentId Unique identifier of the comment being reviewed for
 *   moderation
 * @param props.body Moderation action details including action type, reason,
 *   and any applicable notes
 * @path /discussionBoard/moderator/moderation/comments/:commentId
 * @accessor api.functional.discussionBoard.moderator.moderation.comments.update
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function update(
  connection: IConnection,
  props: update.Props,
): Promise<update.Response> {
  return true === connection.simulate
    ? update.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...update.METADATA,
          path: update.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace update {
  export type Props = {
    /** Unique identifier of the comment being reviewed for moderation */
    commentId: string & tags.Format<"uuid">;

    /**
     * Moderation action details including action type, reason, and any
     * applicable notes
     */
    body: IDiscussionBoardCommentModeration.IUpdate;
  };
  export type Body = IDiscussionBoardCommentModeration.IUpdate;
  export type Response = IDiscussionBoardComment;

  export const METADATA = {
    method: "PATCH",
    path: "/discussionBoard/moderator/moderation/comments/:commentId",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/discussionBoard/moderator/moderation/comments/${encodeURIComponent(props.commentId ?? "null")}`;
  export const random = (): IDiscussionBoardComment =>
    typia.random<IDiscussionBoardComment>();
  export const simulate = (
    connection: IConnection,
    props: update.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: update.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("commentId")(() => typia.assert(props.commentId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
