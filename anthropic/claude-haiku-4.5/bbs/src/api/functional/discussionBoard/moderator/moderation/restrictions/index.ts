/**
 * Retrieve a filtered and paginated list of account restrictions from the
 * discussion board moderation system. This operation provides comprehensive
 * search and filtering capabilities for moderators to review all restrictions
 * imposed on contributor accounts, including active restrictions, expired
 * restrictions, and complete enforcement history.
 *
 * The operation searches the discussion_board_account_restrictions table, which
 * tracks all account restrictions and suspensions applied to contributors by
 * moderators. Each restriction record includes the restriction type (posting
 * restrictions, temporary suspensions, permanent bans), the reason for the
 * restriction, the moderator who imposed it, and the restriction duration and
 * status.
 *
 * Moderators can filter restrictions by multiple criteria: the contributor
 * being restricted, the moderator who imposed the restriction, the restriction
 * type, the restriction status (active, lifted, or expired), and the date range
 * when the restriction was imposed. Results can be sorted by imposition date,
 * contributor, or restriction type to support investigation and enforcement
 * tracking.
 *
 * Active restrictions (where the current time is before the expiration date, or
 * expiration date is null for permanent bans) prevent contributors from
 * creating new articles or posting comments. This operation helps moderators
 * monitor which contributors currently have active restrictions and review the
 * history of enforcement actions for pattern analysis and account management
 * decisions.
 *
 * Related operations: POST /contributors/{contributorId}/suspend creates new
 * suspensions, GET /contributors/{contributorId}/violations retrieves a
 * contributor's violation history, and PUT
 * /moderation/restrictions/{restrictionId}/lift manually lifts restrictions
 * before their scheduled expiration.
 *
 * @param props.connection
 * @param props.body Search criteria, filtering options, pagination parameters,
 *   and sorting preferences for restriction queries
 * @path /discussionBoard/moderator/moderation/restrictions
 * @accessor api.functional.discussionBoard.moderator.moderation.restrictions.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
