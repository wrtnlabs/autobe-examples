import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardAccountRestriction } from "../../../../../structures/IDiscussionBoardAccountRestriction";

/**
 * Lift an active account restriction that was previously imposed on a
 * discussion board contributor account.
 *
 * This endpoint allows authorized moderators to manually remove posting
 * restrictions or temporary suspensions from contributor accounts before the
 * scheduled expiration date. When a moderator determines that a
 * previously-restricted contributor has demonstrated rehabilitation or the
 * restriction was applied in error, they can use this operation to restore the
 * account to normal operation immediately.
 *
 * The operation updates the restriction record with the lift timestamp and the
 * moderator who performed the action. A reason for lifting the restriction is
 * required, which documents the decision and communicates the explanation to
 * the contributor. After the restriction is lifted, the contributor can
 * immediately resume creating articles and posting comments without waiting for
 * the automatic expiration date.
 *
 * Only active restrictions (where the current timestamp is before expires_at or
 * the restriction has not yet expired) can be lifted. Permanent bans can only
 * be lifted by senior moderators in extraordinary circumstances. The complete
 * restriction history is preserved in the database for compliance auditing and
 * to track enforcement patterns. If the contributor has no active restriction,
 * the operation returns an error indicating that there is nothing to lift.
 *
 * @param props.connection
 * @param props.contributorId Unique identifier of the contributor account whose
 *   restriction should be lifted (UUID format)
 * @param props.body Lift action parameters including reason for restriction
 *   removal
 * @path /discussionBoard/moderator/contributors/:contributorId/lift-restriction
 * @accessor api.functional.discussionBoard.moderator.contributors.lift_restriction.liftRestriction
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function liftRestriction(
  connection: IConnection,
  props: liftRestriction.Props,
): Promise<liftRestriction.Response> {
  return true === connection.simulate
    ? liftRestriction.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...liftRestriction.METADATA,
          path: liftRestriction.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace liftRestriction {
  export type Props = {
    /**
     * Unique identifier of the contributor account whose restriction should
     * be lifted (UUID format)
     */
    contributorId: string & tags.Format<"uuid">;

    /** Lift action parameters including reason for restriction removal */
    body: IDiscussionBoardAccountRestriction.IUpdate;
  };
  export type Body = IDiscussionBoardAccountRestriction.IUpdate;
  export type Response = IDiscussionBoardAccountRestriction;

  export const METADATA = {
    method: "POST",
    path: "/discussionBoard/moderator/contributors/:contributorId/lift-restriction",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/discussionBoard/moderator/contributors/${encodeURIComponent(props.contributorId ?? "null")}/lift-restriction`;
  export const random = (): IDiscussionBoardAccountRestriction =>
    typia.random<IDiscussionBoardAccountRestriction>();
  export const simulate = (
    connection: IConnection,
    props: liftRestriction.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: liftRestriction.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("contributorId")(() => typia.assert(props.contributorId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
