import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardReport } from "../../../../../structures/IDiscussionBoardReport";
import { IPageIDiscussionBoardReport } from "../../../../../structures/IPageIDiscussionBoardReport";

/**
 * Search and retrieve member content reports for moderator investigation and
 * action.
 *
 * Retrieve a filtered and paginated list of member-submitted content reports
 * awaiting moderator investigation and action. This operation provides the
 * primary interface for moderators to access the report queue and manage
 * content flagged by the community as violating guidelines.
 *
 * The operation supports advanced filtering and sorting including filtering by
 * report status (pending_review, resolved, dismissed), report reason
 * (offensive_language, personal_attack, spam, off_topic, copyright_violation,
 * harassment, other), reported content type (article or comment), reporter
 * identity, and assignment to specific moderators. Moderators can sort by
 * creation date, resolution date, priority, or other relevant criteria.
 *
 * Response includes comprehensive report details: the report submission
 * timestamp, reported content type and identifier, reporter member information,
 * reason category, detailed description, current status, assigned moderator,
 * moderator notes if any investigation occurred, and resolution timestamp if
 * applicable. This information enables moderators to understand context and
 * take appropriate moderation actions.
 *
 * Security and authorization: Only moderators with active status can access
 * this operation. The operation returns all reports regardless of assignment
 * status, enabling supervisory overview and workload balancing. Reports form
 * the evidence base for moderation decisions and are immutable audit records.
 *
 * @param props.connection
 * @param props.body Search criteria, filtering options, and pagination
 *   parameters for content report retrieval
 * @path /discussionBoard/moderator/moderation/content-reports
 * @accessor api.functional.discussionBoard.moderator.moderation.content_reports.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Search criteria, filtering options, and pagination parameters for
     * content report retrieval
     */
    body: IDiscussionBoardReport.IRequest;
  };
  export type Body = IDiscussionBoardReport.IRequest;
  export type Response = IPageIDiscussionBoardReport.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/discussionBoard/moderator/moderation/content-reports",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () =>
    "/discussionBoard/moderator/moderation/content-reports";
  export const random = (): IPageIDiscussionBoardReport.ISummary =>
    typia.random<IPageIDiscussionBoardReport.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
