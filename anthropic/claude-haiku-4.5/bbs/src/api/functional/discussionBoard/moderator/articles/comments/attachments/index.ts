import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

/**
 * Remove an image file attachment from a specific comment within an article
 * discussion. This operation enables contributors to manage their own
 * attachments by removing unwanted or erroneous files they have uploaded to
 * their comments. Moderators can also remove inappropriate or policy-violating
 * attachments when performing content moderation duties.
 *
 * The operation locates the attachment by its unique identifier within the
 * context of the specified comment and article. It verifies the attachment
 * exists and belongs to the specified comment before proceeding with deletion.
 * Upon confirmation, the attachment record is permanently removed from the
 * database and the file is no longer accessible through the system. This is a
 * hard delete operation that completely removes the attachment metadata and
 * associated file.
 *
 * Authorization and ownership validation ensure that only authorized parties
 * can delete attachments. Contributors can delete attachments they have
 * personally uploaded to their own comments. Moderators with elevated
 * privileges can delete any attachment as part of their content moderation
 * responsibilities. Attempting to delete an attachment not uploaded by the
 * requesting contributor (unless moderator) will result in an authorization
 * error.
 *
 * After successful deletion, the comment's attachment list is immediately
 * updated. If the deleted attachment was the last visual evidence supporting
 * the comment's context, other users should be aware that the visual reference
 * is no longer available. The operation does not modify the comment text itself
 * - only the attachment association is removed.
 *
 * This operation should be used when a contributor wants to remove an
 * attachment they uploaded (POST
 * /articles/{articleId}/comments/{commentId}/attachments) or when a moderator
 * needs to remove policy-violating content. Related operations include creating
 * new attachments (POST /articles/{articleId}/comments/{commentId}/attachments)
 * and retrieving comment details including all remaining attachments (GET
 * /articles/{articleId}/comments/{commentId}).
 *
 * @param props.connection
 * @param props.articleId Unique identifier of the discussion board article
 *   containing the target comment
 * @param props.commentId Unique identifier of the specific comment containing
 *   the attachment to delete
 * @param props.attachmentId Unique identifier of the specific attachment file
 *   to permanently remove
 * @path /discussionBoard/moderator/articles/:articleId/comments/:commentId/attachments/:attachmentId
 * @accessor api.functional.discussionBoard.moderator.articles.comments.attachments.erase
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function erase(
  connection: IConnection,
  props: erase.Props,
): Promise<void> {
  return true === connection.simulate
    ? erase.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...erase.METADATA,
          path: erase.path(props),
          status: null,
        },
      );
}
export namespace erase {
  export type Props = {
    /**
     * Unique identifier of the discussion board article containing the
     * target comment
     */
    articleId: string & tags.Format<"uuid">;

    /**
     * Unique identifier of the specific comment containing the attachment
     * to delete
     */
    commentId: string & tags.Format<"uuid">;

    /**
     * Unique identifier of the specific attachment file to permanently
     * remove
     */
    attachmentId: string & tags.Format<"uuid">;
  };

  export const METADATA = {
    method: "DELETE",
    path: "/discussionBoard/moderator/articles/:articleId/comments/:commentId/attachments/:attachmentId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/moderator/articles/${encodeURIComponent(props.articleId ?? "null")}/comments/${encodeURIComponent(props.commentId ?? "null")}/attachments/${encodeURIComponent(props.attachmentId ?? "null")}`;
  export const random = (): void => typia.random<void>();
  export const simulate = (
    connection: IConnection,
    props: erase.Props,
  ): void => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: erase.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("articleId")(() => typia.assert(props.articleId));
      assert.param("commentId")(() => typia.assert(props.commentId));
      assert.param("attachmentId")(() => typia.assert(props.attachmentId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
