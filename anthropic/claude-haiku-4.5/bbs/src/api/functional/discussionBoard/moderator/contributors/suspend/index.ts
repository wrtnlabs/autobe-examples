/**
 * Create a new account suspension or posting restriction on a contributor
 * account as an enforcement action for policy violations. This operation
 * records the suspension in the discussion_board_user_suspensions table, which
 * maintains the complete history of all account restrictions and suspensions
 * imposed on contributors.
 *
 * When a contributor has accumulated violations or committed severe violations,
 * moderators use this operation to enforce consequences. The operation requires
 * specifying the suspension type (posting_restriction prevents article and
 * comment submissions; account_suspension prevents login; permanent_ban
 * disables the account permanently), the reason for the suspension, and the
 * severity level (minor, moderate, severe, or permanent).
 *
 * For time-limited suspensions, moderators specify the duration in days (3, 7,
 * 30, or custom durations), and the system automatically calculates the
 * expiration timestamp. The suspension becomes immediately effective,
 * preventing the contributor from performing restricted actions. Suspension
 * records include the moderator who imposed the suspension and the timestamp of
 * the action for accountability and audit trails.
 *
 * The operation creates an immutable suspension record that is never deleted;
 * suspension history is retained indefinitely for compliance and pattern
 * analysis. Moderators can manually lift suspensions early by using a separate
 * lift operation if the contributor demonstrates rehabilitation, but the
 * lifting action is also recorded with reason and timestamp for
 * accountability.
 *
 * Escalation rules apply: a contributor's first major violation triggers a
 * warning, second violation within 30 days results in a 3-day posting
 * restriction, third violation results in a 7-day restriction, and fourth
 * violation triggers account suspension. Severe violations (hate speech,
 * threats, harassment) may skip escalation steps and result in immediate
 * suspension or permanent ban.
 *
 * The suspended contributor receives notification including the suspension
 * reason, duration (if applicable), and what they must do for account recovery.
 * Their articles and comments remain visible with attribution but authored as
 * 'suspended user' to preserve discussion context.
 *
 * @param props.connection
 * @param props.contributorId Unique identifier (UUID) of the contributor
 *   account to be suspended or restricted
 * @param props.body Suspension details including type, severity, duration, and
 *   reason for the enforcement action
 * @path /discussionBoard/moderator/contributors/:contributorId/suspend
 * @accessor api.functional.discussionBoard.moderator.contributors.suspend.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function create(
  connection: IConnection,
  props: create.Props,
): Promise<create.Response> {
  return true === connection.simulate
    ? create.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...create.METADATA,
          path: create.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace create {
  export type Props = {
    /**
     * Unique identifier (UUID) of the contributor account to be suspended
     * or restricted
     */
    contributorId: string & tags.Format<"uuid">;

    /**
     * Suspension details including type, severity, duration, and reason for
     * the enforcement action
     */
    body: IDiscussionBoardUserSuspension.ICreate;
  };
  export type Body = IDiscussionBoardUserSuspension.ICreate;
  export type Response = IDiscussionBoardUserSuspension;

  export const METADATA = {
    method: "POST",
    path: "/discussionBoard/moderator/contributors/:contributorId/suspend",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/discussionBoard/moderator/contributors/${encodeURIComponent(props.contributorId ?? "null")}/suspend`;
  export const random = (): IDiscussionBoardUserSuspension =>
    typia.random<IDiscussionBoardUserSuspension>();
  export const simulate = (
    connection: IConnection,
    props: create.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: create.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("contributorId")(() => typia.assert(props.contributorId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
