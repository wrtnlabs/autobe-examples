import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardModerationLog } from "../../../../../structures/IDiscussionBoardModerationLog";
import { IPageIDiscussionBoardModerationLog } from "../../../../../structures/IPageIDiscussionBoardModerationLog";

/**
 * Search and retrieve moderation action logs with filtering and pagination.
 *
 * This operation provides moderators with comprehensive visibility into all
 * moderation actions taken on the platform. The moderation logs table maintains
 * a complete audit trail of every enforcement action including article
 * removals, comment removals, user suspensions, user bans, warnings, and
 * content flags. Each log entry records which moderator took the action, what
 * entity was targeted, the reason for the action, and when it occurred.
 *
 * The operation supports advanced filtering to help moderators find specific
 * actions: filter by action type to see all suspensions or all article
 * removals, filter by target type to see all actions affecting users or all
 * actions affecting content, filter by moderator to audit a specific
 * moderator's actions, filter by affected member to see all enforcement actions
 * against a user, and filter by date range to see recent or historical actions.
 * Search capabilities enable finding actions by reason text.
 *
 * Security considerations include restricting access to moderators only - this
 * sensitive enforcement history should not be visible to regular members. The
 * audit trail must be immutable - logs should never be deleted or modified,
 * only added to as new actions are taken. This ensures compliance and
 * accountability in moderation decisions.
 *
 * The operation integrates with the moderation system defined in the Prisma
 * schema. The discussion_board_moderation_logs table stores all enforcement
 * actions with references to the moderator who acted, the affected member (if
 * applicable), the action type, and the target entity. Combined with the user
 * violations table which tracks individual policy violations, this provides
 * complete visibility into the enforcement ecosystem.
 *
 * @param props.connection
 * @param props.body Filtering, searching, and pagination parameters for
 *   moderation logs
 * @path /discussionBoard/moderator/moderation/logs
 * @accessor api.functional.discussionBoard.moderator.moderation.logs.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /** Filtering, searching, and pagination parameters for moderation logs */
    body: IDiscussionBoardModerationLog.IModerationLogsRequest;
  };
  export type Body = IDiscussionBoardModerationLog.IModerationLogsRequest;
  export type Response = IPageIDiscussionBoardModerationLog.IModerationLog;

  export const METADATA = {
    method: "PATCH",
    path: "/discussionBoard/moderator/moderation/logs",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/discussionBoard/moderator/moderation/logs";
  export const random = (): IPageIDiscussionBoardModerationLog.IModerationLog =>
    typia.random<IPageIDiscussionBoardModerationLog.IModerationLog>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
