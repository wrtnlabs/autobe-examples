/**
 * Create a new account restriction on a discussion board contributor account as
 * a moderation enforcement action.
 *
 * This endpoint allows authorized moderators to impose posting restrictions,
 * temporary suspensions, or permanent bans on contributor accounts that have
 * violated community guidelines or policies. The restriction prevents the
 * contributor from creating articles or posting comments during the restriction
 * period. For temporary restrictions, the system automatically enforces the
 * restriction until the expiration date; moderators can manually lift
 * restrictions early if the contributor demonstrates rehabilitation.
 *
 * The operation records comprehensive restriction metadata including the
 * restriction type, reason for enforcement, imposing moderator, and duration.
 * Multiple restriction types are supported: posting_restriction (cannot post
 * articles/comments), temporary_suspension (cannot login), and permanent_ban
 * (permanent account disablement). The reason field communicates to the
 * contributor why their account was restricted and what conduct triggered the
 * enforcement action.
 *
 * Active restrictions (where the current timestamp is before expires_at, or
 * expires_at is null for permanent restrictions) prevent new article
 * submissions and comment posts. The system maintains complete restriction
 * history for compliance auditing and pattern analysis. When a new restriction
 * is applied to a contributor with an existing active restriction, the
 * application-level logic replaces the previous one. Contributor notifications
 * include the restriction reason and end date for temporary restrictions.
 *
 * @param props.connection
 * @param props.contributorId Unique identifier of the contributor account to
 *   restrict (UUID format)
 * @param props.body Restriction details and enforcement action parameters
 * @path /discussionBoard/moderator/contributors/:contributorId/restrict
 * @accessor api.functional.discussionBoard.moderator.contributors.restrict
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function restrict(
  connection: IConnection,
  props: restrict.Props,
): Promise<restrict.Response> {
  return true === connection.simulate
    ? restrict.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...restrict.METADATA,
          path: restrict.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace restrict {
  export type Props = {
    /**
     * Unique identifier of the contributor account to restrict (UUID
     * format)
     */
    contributorId: string & tags.Format<"uuid">;

    /** Restriction details and enforcement action parameters */
    body: IDiscussionBoardAccountRestriction.ICreate;
  };
  export type Body = IDiscussionBoardAccountRestriction.ICreate;
  export type Response = IDiscussionBoardAccountRestriction;

  export const METADATA = {
    method: "POST",
    path: "/discussionBoard/moderator/contributors/:contributorId/restrict",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/discussionBoard/moderator/contributors/${encodeURIComponent(props.contributorId ?? "null")}/restrict`;
  export const random = (): IDiscussionBoardAccountRestriction =>
    typia.random<IDiscussionBoardAccountRestriction>();
  export const simulate = (
    connection: IConnection,
    props: restrict.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: restrict.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("contributorId")(() => typia.assert(props.contributorId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
