import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardModerationLog } from "../../../../../structures/IDiscussionBoardModerationLog";

/**
 * Retrieve moderation history and violations for a specific member account.
 *
 * This operation allows moderators to view the complete moderation history for
 * a specific member, including all recorded violations, enforcement actions,
 * and account status changes. Moderators can access detailed information about
 * what violations the member has committed, when they occurred, and what
 * moderation actions were taken in response.
 *
 * The operation retrieves data from multiple sources: the user violations table
 * showing all policy violations recorded against the member, the moderation
 * logs showing all enforcement actions taken by moderators, and the member
 * account status showing current suspension or ban status. This comprehensive
 * view enables moderators to understand the member's history before making
 * additional enforcement decisions.
 *
 * Security considerations include ensuring only authenticated moderators can
 * access this endpoint. The operation returns sensitive moderation information
 * that should not be visible to regular members. Access control must verify the
 * requesting user has moderator role before granting access to member
 * moderation data.
 *
 * This operation integrates with the members system and moderation framework
 * defined in the Prisma schema. The member's account_status field indicates
 * current restrictions (active, suspended, banned), while violation records
 * track individual policy violations and moderation logs track all moderator
 * actions. Together these provide complete visibility into the member's
 * standing with the platform.
 *
 * @param props.connection
 * @param props.memberId Unique identifier of the member whose moderation
 *   history is being reviewed
 * @param props.body Optional filtering and pagination parameters for moderation
 *   history retrieval
 * @path /discussionBoard/moderator/moderation/members/:memberId
 * @accessor api.functional.discussionBoard.moderator.moderation.members.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Unique identifier of the member whose moderation history is being
     * reviewed
     */
    memberId: string & tags.Format<"uuid">;

    /**
     * Optional filtering and pagination parameters for moderation history
     * retrieval
     */
    body: IDiscussionBoardModerationLog.IMemberHistoryRequest;
  };
  export type Body = IDiscussionBoardModerationLog.IMemberHistoryRequest;
  export type Response = IDiscussionBoardModerationLog.IMemberModerationHistory;

  export const METADATA = {
    method: "PATCH",
    path: "/discussionBoard/moderator/moderation/members/:memberId",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/discussionBoard/moderator/moderation/members/${encodeURIComponent(props.memberId ?? "null")}`;
  export const random =
    (): IDiscussionBoardModerationLog.IMemberModerationHistory =>
      typia.random<IDiscussionBoardModerationLog.IMemberModerationHistory>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("memberId")(() => typia.assert(props.memberId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
