/**
 * Retrieve a comprehensive, filtered list of moderator audit log entries that
 * track all moderation actions performed on the platform. This operation
 * provides deep visibility into moderation decisions, enabling compliance
 * review, dispute investigation, and moderation quality analysis.
 *
 * The operation supports advanced filtering across multiple dimensions
 * including action type (article_approved, article_rejected, article_deleted,
 * comment_removed, user_warned, user_suspended, etc.), moderator who performed
 * the action, contributor affected by the action, specific articles or comments
 * involved, date ranges, and textual reasons. Combined filters enable precise
 * audit trail examination for specific moderation scenarios, time periods, or
 * moderators.
 *
 * Results are returned in paginated format with configurable page size and
 * sorting options. Default sorting is by creation timestamp in descending order
 * (most recent first), enabling quick access to recent moderation activity.
 * Alternative sorting by action type or moderator provides different analytical
 * perspectives.
 *
 * Security considerations include role-based access restrictions (moderators
 * only) to prevent unauthorized visibility of sensitive moderation decisions
 * and reasoning. The audit log is read-only from the API perspective; audit
 * records are only created through moderation actions and never modified or
 * deleted, ensuring immutability and integrity of the compliance record.
 *
 * The operation integrates with the discussion_board_moderator_audit_log table
 * as defined in the Prisma schema, providing visibility into action_type,
 * reason, old_status, new_status, additional_metadata fields along with
 * references to the moderator, affected contributor, and related
 * article/comment. The audit log is essential infrastructure for platform
 * governance and regulatory compliance.
 *
 * @param props.connection
 * @param props.body Search criteria, filtering options, and pagination
 *   parameters for the audit log query
 * @path /discussionBoard/moderator/moderation/audit-log
 * @accessor api.functional.discussionBoard.moderator.moderation.audit_log.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
