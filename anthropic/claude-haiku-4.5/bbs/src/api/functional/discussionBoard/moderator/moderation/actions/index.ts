/**
 * Search and retrieve a filtered, paginated list of all discussion board
 * moderation actions.
 *
 * Retrieve a comprehensive, filterable list of moderation actions taken on
 * discussion board content. This operation provides moderators and
 * administrators with access to the complete audit trail of all moderation
 * decisions, including article approvals, rejections, deletions, comment
 * removals, and content edits. Each record includes the moderator who performed
 * the action, the affected content, the specific action taken, the business
 * reason, and detailed notes.
 *
 * The operation supports advanced filtering capabilities including action type
 * (approved, rejected, deleted_article, deleted_comment, etc.), content type
 * (article or comment), moderator assignment, member identification, date
 * ranges, and keyword search in reason and notes fields. Results can be sorted
 * by creation date, action type, or moderator for investigation and pattern
 * analysis.
 *
 * Pagination is provided with configurable page size to handle large audit
 * trails efficiently. This operation is critical for governance, compliance,
 * and dispute resolution workflows where moderation decisions must be
 * transparent and auditable.
 *
 * Security: This operation is restricted to moderators who need administrative
 * visibility into moderation history. The moderator accessing this operation
 * can view all moderation actions system-wide without filtering by their own
 * actions, enabling supervisory oversight and consistency review.
 *
 * Related operations: GET /moderation/actions/{actionId} retrieves a single
 * moderation action detail. PATCH /moderation/member-activity/{memberId}
 * retrieves moderation actions affecting a specific member.
 *
 * @param props.connection
 * @param props.body Search criteria, filtering options, and pagination
 *   parameters for retrieving moderation actions
 * @path /discussionBoard/moderator/moderation/actions
 * @accessor api.functional.discussionBoard.moderator.moderation.actions.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Search criteria, filtering options, and pagination parameters for
     * retrieving moderation actions
     */
    body: IDiscussionBoardModerationAction.IRequest;
  };
  export type Body = IDiscussionBoardModerationAction.IRequest;
  export type Response = IPageIDiscussionBoardModerationAction.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/discussionBoard/moderator/moderation/actions",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/discussionBoard/moderator/moderation/actions";
  export const random = (): IPageIDiscussionBoardModerationAction.ISummary =>
    typia.random<IPageIDiscussionBoardModerationAction.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
