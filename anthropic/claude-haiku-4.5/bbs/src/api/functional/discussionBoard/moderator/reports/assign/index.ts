import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardReport } from "../../../../../structures/IDiscussionBoardReport";

/**
 * Assign a report to a moderator for review.
 *
 * Assign a pending report to a moderator for investigation and resolution. This
 * operation updates the report's assigned_moderator_id field, transitioning the
 * report from unassigned to assigned state. Only moderators with appropriate
 * permissions can assign reports.
 *
 * When a report is assigned, the moderator takes responsibility for
 * investigating the reported content, reviewing the reporter's reason and
 * description, examining the flagged comment or article, and determining
 * appropriate action (keeping content as-is, editing content, or removing
 * content). The assignment captures moderator accountability for report
 * resolution.
 *
 * Reports can be reassigned from one moderator to another if needed. The
 * assignment operation does not change the report's status (remains
 * 'pending_review') - status transitions to 'resolved' or 'dismissed' only when
 * the moderator completes their investigation and takes final action.
 *
 * Security: Only moderators can assign reports. The operation validates that
 * the target moderator exists and is active. Assignment timestamps are recorded
 * for audit purposes. The moderator assignment enables tracking which moderator
 * is responsible for each report's resolution.
 *
 * @param props.connection
 * @param props.reportId Unique identifier of the report to assign
 * @param props.body Assignment data specifying the moderator to assign this
 *   report to
 * @path /discussionBoard/moderator/reports/:reportId/assign
 * @accessor api.functional.discussionBoard.moderator.reports.assign.update
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function update(
  connection: IConnection,
  props: update.Props,
): Promise<update.Response> {
  return true === connection.simulate
    ? update.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...update.METADATA,
          path: update.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace update {
  export type Props = {
    /** Unique identifier of the report to assign */
    reportId: string & tags.Format<"uuid">;

    /** Assignment data specifying the moderator to assign this report to */
    body: IDiscussionBoardReport.IUpdate;
  };
  export type Body = IDiscussionBoardReport.IUpdate;
  export type Response = IDiscussionBoardReport;

  export const METADATA = {
    method: "PUT",
    path: "/discussionBoard/moderator/reports/:reportId/assign",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/discussionBoard/moderator/reports/${encodeURIComponent(props.reportId ?? "null")}/assign`;
  export const random = (): IDiscussionBoardReport =>
    typia.random<IDiscussionBoardReport>();
  export const simulate = (
    connection: IConnection,
    props: update.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: update.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("reportId")(() => typia.assert(props.reportId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
