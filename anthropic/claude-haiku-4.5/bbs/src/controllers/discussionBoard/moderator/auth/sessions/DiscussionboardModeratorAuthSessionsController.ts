import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";

@Controller("/discussionBoard/moderator/auth/sessions/:sessionId")
export class DiscussionboardModeratorAuthSessionsController {
  /**
   * Terminate a specific authentication session.
   *
   * Delete and invalidate a specific authentication session by its sessionId.
   * This operation logs out the user for that particular session, making the
   * associated JWT token invalid for future requests. The sessionId must
   * belong to the authenticated user (or user must be moderator with account
   * management permissions).
   *
   * When a session is deleted, the session record is removed from the
   * database and the associated JWT token is invalidated. Any subsequent API
   * requests using that token will be rejected with authentication error.
   * This enables users to log out from specific devices or sessions while
   * maintaining active sessions on other devices.
   *
   * Moderators have the ability to delete user sessions as part of account
   * management and enforcement activities, such as forcing logout of
   * suspended or problematic accounts. The deletion is immediate and
   * permanent.
   *
   * @param connection
   * @param sessionId Unique identifier of the session to terminate (UUID
   *   format)
   * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
   */
  @TypedRoute.Delete()
  public async erase(
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<void> {
    sessionId;
    return typia.random<void>();
  }
}
