import { ArrayUtil, RandomGenerator, TestValidator } from "@nestia/e2e";
import { IConnection } from "@nestia/fetcher";
import typia, { tags } from "typia";

import api from "@ORGANIZATION/PROJECT-api";
import type { IDiscussionBoardMember } from "@ORGANIZATION/PROJECT-api/lib/structures/IDiscussionBoardMember";
import type { IDiscussionBoardPasswordReset } from "@ORGANIZATION/PROJECT-api/lib/structures/IDiscussionBoardPasswordReset";

/**
 * Test password reset request workflow and confirmation API structure.
 *
 * This test validates the password reset request and confirmation API endpoints
 * by:
 *
 * 1. Creating a new member account with valid credentials
 * 2. Requesting password reset to verify the request API works correctly
 * 3. Testing the password reset confirmation endpoint with properly formatted data
 *
 * Note: This test validates the API structure and request/response handling.
 * The actual token validation and password change verification would require
 * access to the email system or database, which is outside the scope of pure
 * API E2E testing.
 */
export async function test_api_password_reset_completion_with_valid_token(
  connection: api.IConnection,
) {
  // Step 1: Create a new member account
  const memberEmail = typia.random<string & tags.Format<"email">>();
  const originalPassword = "Original123!@#";
  const username = RandomGenerator.alphaNumeric(12);

  const memberData = {
    username: username,
    email: memberEmail,
    password: originalPassword,
    href: typia.random<string & tags.Format<"uri">>(),
    referrer: typia.random<string & tags.Format<"uri">>(),
  } satisfies IDiscussionBoardMember.ICreate;

  const createdMember: IDiscussionBoardMember.ISummary =
    await api.functional.discussionBoard.members.create(connection, {
      body: memberData,
    });
  typia.assert(createdMember);

  TestValidator.equals(
    "created member username matches",
    createdMember.username,
    username,
  );

  // Step 2: Request password reset
  const resetRequestData = {
    email: memberEmail,
  } satisfies IDiscussionBoardPasswordReset.IRequest;

  const resetRequestResponse: IDiscussionBoardPasswordReset.IRequestResponse =
    await api.functional.discussionBoard.auth.password_reset.request(
      connection,
      {
        body: resetRequestData,
      },
    );
  typia.assert(resetRequestResponse);

  TestValidator.predicate(
    "reset request response contains message",
    resetRequestResponse.message.length > 0,
  );

  // Step 3: Test password reset confirmation endpoint structure
  // Note: We generate a properly formatted token to test the API endpoint,
  // but this will likely fail validation since it's not the actual token
  // generated by the system. In a real E2E test environment, you would need
  // access to the email service or database to retrieve the actual token.
  const testToken = RandomGenerator.alphaNumeric(32);
  const newPassword = "NewSecure456!@#";

  const confirmData = {
    token: testToken,
    new_password: newPassword,
    password_confirmation: newPassword,
  } satisfies IDiscussionBoardPasswordReset.IConfirm;

  // The confirmation will likely fail with invalid token error,
  // which is expected behavior since we don't have access to the real token
  await TestValidator.error("invalid token should be rejected", async () => {
    await api.functional.discussionBoard.auth.password_reset.confirm(
      connection,
      {
        body: confirmData,
      },
    );
  });
}
