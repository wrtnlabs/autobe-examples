import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia from "typia";
import { patchDiscussionBoardTagsTagSlugArticles } from "../../../../providers/patchDiscussionBoardTagsTagSlugArticles";

import { IPageIDiscussionBoardArticle } from "../../../../api/structures/IPageIDiscussionBoardArticle";
import { IDiscussionBoardArticle } from "../../../../api/structures/IDiscussionBoardArticle";

@Controller("/discussionBoard/tags/:tagSlug/articles")
export class DiscussionboardTagsArticlesController {
  /**
   * Search and retrieve paginated list of articles with a specific tag.
   *
   * Retrieves a comprehensive, filtered, and paginated list of articles that
   * have been tagged with a specific tag, identified by its URL-friendly slug.
   * This operation provides advanced search capabilities for discovering
   * content related to specific topics within the economic and political
   * discussion board.
   *
   * The operation joins the discussion_board_articles table with the
   * discussion_board_article_tags junction table and discussion_board_tags
   * table to filter articles that have the specified tag applied. It supports
   * extensive search parameters including keyword search across article titles
   * and bodies, filtering by additional categories, date range filtering,
   * author filtering, sorting by various criteria (newest, oldest, most viewed,
   * most commented), and pagination controls. All searches exclude soft-deleted
   * articles (where deleted_at is not null) to ensure only active, published
   * content appears in results.
   *
   * This tag-based article discovery serves a critical user need described in
   * the Search and Discovery requirements: enabling users to find discussions
   * on specific topics through the granular tag taxonomy. Tags provide more
   * detailed topic classification than broad categories, allowing users to
   * discover articles on focused subjects like monetary-policy,
   * healthcare-reform, or climate-change. When users browse or click tags
   * throughout the platform, this operation delivers the relevant article
   * listings.
   *
   * Performance expectations are important for user experience. The operation
   * must return results within 2 seconds for typical tag-based searches as
   * specified in the Performance and Scalability requirements. The response
   * includes article summaries optimized for list display rather than full
   * article content, reducing payload size and improving rendering speed.
   * Pagination with 20 articles per page by default ensures fast loading even
   * for popular tags with hundreds of associated articles.
   *
   * Security and access control are straightforward: this is a public read
   * operation accessible to all users including unauthenticated guests, as
   * tag-based browsing is a core content discovery mechanism. The operation
   * respects article visibility rules, excluding deleted articles and
   * potentially filtering based on article status. Response data should include
   * article metadata (title, author, summary, creation date, view count,
   * comment count) along with category and tag information to enable rich
   * display in article listing interfaces.
   *
   * @param connection
   * @param tagSlug URL-friendly slug identifier of the tag to filter articles
   *   by (global scope)
   * @param body Search, filtering, sorting, and pagination parameters for
   *   retrieving articles tagged with the specified tag
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedParam("tagSlug")
    tagSlug: string,
    @TypedBody()
    body: IDiscussionBoardArticle.IRequest,
  ): Promise<IPageIDiscussionBoardArticle.ISummary> {
    try {
      return await patchDiscussionBoardTagsTagSlugArticles({
        tagSlug,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
