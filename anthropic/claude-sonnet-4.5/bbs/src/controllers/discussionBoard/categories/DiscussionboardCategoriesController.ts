import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchDiscussionBoardCategories } from "../../../providers/patchDiscussionBoardCategories";
import { getDiscussionBoardCategoriesCategoryId } from "../../../providers/getDiscussionBoardCategoriesCategoryId";

import { IPageIDiscussionBoardArticleCategory } from "../../../api/structures/IPageIDiscussionBoardArticleCategory";
import { IDiscussionBoardArticleCategory } from "../../../api/structures/IDiscussionBoardArticleCategory";

@Controller("/discussionBoard/categories")
export class DiscussionboardCategoriesController {
  /**
   * Search and retrieve a paginated list of discussion board article
   * categories.
   *
   * Retrieve a filtered and paginated list of article categories that organize
   * discussions by topic area. This operation provides search capabilities for
   * finding categories based on name, slug, or description keywords, with
   * support for pagination and sorting.
   *
   * Categories are the organizational taxonomy of the discussion board, helping
   * users discover relevant discussions by browsing topic areas. Each category
   * has a unique name, URL-friendly slug, optional description, and display
   * sort order. This endpoint returns category summary information optimized
   * for category browsing and selection interfaces.
   *
   * The operation supports comprehensive pagination with configurable page
   * sizes and sorting options. Users can sort categories by name, slug,
   * sort_order, or creation date in ascending or descending order. This enables
   * efficient category discovery and selection during article creation.
   *
   * Security considerations include public access for all users (guests,
   * members, and moderators) since categories are fundamental navigation
   * elements. Rate limiting applies to prevent excessive search requests. The
   * response includes category metadata to support UI rendering and article
   * categorization workflows.
   *
   * This operation integrates with the discussion_board_article_categories
   * table as defined in the Prisma schema, incorporating all available category
   * fields and metadata. The response provides category information suitable
   * for dropdown selectors, filter interfaces, and category browsing pages.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for category
   *   filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IDiscussionBoardArticleCategory.IRequest,
  ): Promise<IPageIDiscussionBoardArticleCategory.ISummary> {
    try {
      return await patchDiscussionBoardCategories({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific article category by unique identifier.
   *
   * Retrieve complete details of a specific article category identified by its
   * unique UUID. This operation returns the full category record including
   * name, slug, description, display sort order, and metadata timestamps.
   *
   * Categories organize discussion board articles into topic areas such as
   * Economic Discussion, Political Discussion, and General Discussion. Each
   * category provides a descriptive name, URL-friendly slug for routing,
   * optional description explaining topic guidelines, and sort order for UI
   * presentation. This endpoint delivers all category information needed for
   * display, editing, and article categorization.
   *
   * The operation is publicly accessible to all users (guests, members, and
   * moderators) since categories are fundamental navigation and organizational
   * elements. Category information is used in article browsing interfaces,
   * category filter controls, and article creation forms where members select
   * the appropriate topic area.
   *
   * Security considerations include standard read-only access patterns with no
   * authorization requirements. Rate limiting prevents excessive individual
   * category lookups. The response includes complete category metadata to
   * support both display and administrative management workflows.
   *
   * This operation integrates with the discussion_board_article_categories
   * table as defined in the Prisma schema, returning the complete category
   * record with all fields and relationships. Related operations include the
   * category list endpoint (PATCH /categories) which should be used to discover
   * available categories before retrieving specific details.
   *
   * @param connection
   * @param categoryId Unique identifier of the target article category
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":categoryId")
  public async at(
    @TypedParam("categoryId")
    categoryId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardArticleCategory> {
    try {
      return await getDiscussionBoardCategoriesCategoryId({
        categoryId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
