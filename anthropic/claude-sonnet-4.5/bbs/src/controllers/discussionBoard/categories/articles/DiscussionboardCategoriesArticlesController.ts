import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia from "typia";
import { patchDiscussionBoardCategoriesCategorySlugArticles } from "../../../../providers/patchDiscussionBoardCategoriesCategorySlugArticles";

import { IPageIDiscussionBoardArticle } from "../../../../api/structures/IPageIDiscussionBoardArticle";
import { IDiscussionBoardArticle } from "../../../../api/structures/IDiscussionBoardArticle";

@Controller("/discussionBoard/categories/:categorySlug/articles")
export class DiscussionboardCategoriesArticlesController {
  /**
   * Search and retrieve paginated articles within a specific category.
   *
   * This operation provides comprehensive search and filtering capabilities for
   * discovering articles within a specific discussion board category.
   * Categories are the primary taxonomy for organizing economic and political
   * discourse topics, and this endpoint enables users to explore all content
   * within a particular subject area with advanced filtering, sorting, and
   * pagination.
   *
   * The operation performs a complex query joining the
   * discussion_board_articles table with the
   * discussion_board_article_categories junction table to identify articles
   * belonging to the specified category (matched by slug from
   * discussion_board_categories). The request body supports extensive filtering
   * options including publication status (published, draft, archived), date
   * range filters for article creation, author filtering, keyword search across
   * both article titles and body content using PostgreSQL full-text search with
   * trigram indexing, view count ranges, and comment count ranges. Results
   * automatically exclude soft-deleted articles by filtering WHERE deleted_at
   * IS NULL, ensuring only active content appears in search results.
   *
   * The response returns paginated results using the
   * IPageIDiscussionBoardArticle.ISummary type, which contains both pagination
   * metadata (total count, page number, page size, total pages) and an array of
   * article summaries. The summary format provides essential information for
   * list display including article ID, title, excerpt (first 200 characters of
   * body or explicit summary field), author information (username, display
   * name), category and tag information, view and comment counts, and
   * publication timestamp. This optimized response format enables fast
   * rendering of article lists without transferring full article bodies.
   *
   * Sorting options allow users to organize results by creation date (newest or
   * oldest first), view count (most viewed first), comment count (most
   * discussed first), or last update timestamp (recently active first). The
   * operation supports all user actor types with appropriate permission
   * handling: guests can search published articles, members can search
   * published articles plus their own drafts, and moderators can search all
   * articles including those from suspended users for moderation purposes.
   * Performance is optimized through database indexing on created_at, status,
   * and trigram indexes on title and body columns, ensuring search results
   * return within 2 seconds even with large article datasets.
   *
   * @param connection
   * @param categorySlug URL-friendly unique identifier of the target category
   *   to filter articles (global scope)
   * @param body Advanced search criteria including filters, sorting
   *   preferences, and pagination parameters for category article discovery
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedParam("categorySlug")
    categorySlug: string,
    @TypedBody()
    body: IDiscussionBoardArticle.IRequest,
  ): Promise<IPageIDiscussionBoardArticle.ISummary> {
    try {
      return await patchDiscussionBoardCategoriesCategorySlugArticles({
        categorySlug,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
