import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postDiscussionBoardAuthVerifyEmail } from "../../../../providers/postDiscussionBoardAuthVerifyEmail";

import { IDiscussionBoardAuth } from "../../../../api/structures/IDiscussionBoardAuth";

@Controller("/discussionBoard/auth/verify-email")
export class DiscussionboardAuthVerify_emailController {
  /**
   * Verify user email address using verification token from registration email.
   *
   * Verify a user's email address to activate their account and enable full
   * platform access. This operation is a critical step in the user registration
   * workflow, confirming that the provided email address is valid and
   * accessible by the user.
   *
   * The operation validates an email verification token sent to the user's
   * email address during registration. Token validation is handled through
   * application logic with a secure token service or cache layer (such as
   * Redis), as the Prisma schema tables do not store verification tokens
   * directly. Tokens are unique, cryptographically secure, and time-limited to
   * 24 hours for security. Upon receiving a valid token, the system updates the
   * database by setting the email_verified field to true and transitions the
   * account status from pending_email_verification to active in the
   * discussion_board_members or discussion_board_moderators table.
   *
   * Security considerations include validating token authenticity through the
   * application's token service, checking token expiration (24-hour validity
   * window), ensuring the token has not been used previously, and verifying the
   * associated account exists and is in pending_email_verification status by
   * querying the status field. If the token is expired, the system provides
   * appropriate error messaging and allows users to request a new verification
   * email.
   *
   * This operation works with both member and moderator accounts, as both user
   * types require email verification before gaining full platform access.
   * Successful email verification is a prerequisite for logging in and
   * performing any authenticated actions such as creating articles, posting
   * comments, or accessing moderation tools. The operation follows the
   * authentication requirements specified in the user actors and authentication
   * documentation, ensuring only verified users can fully participate in the
   * discussion board by updating the email_verified and status fields in the
   * Prisma schema.
   *
   * @param connection
   * @param body Email verification token received in the verification email
   *   during registration
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async verify(
    @TypedBody()
    body: IDiscussionBoardAuth.IVerifyEmail,
  ): Promise<IDiscussionBoardAuth.IVerificationResult> {
    try {
      return await postDiscussionBoardAuthVerifyEmail({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
