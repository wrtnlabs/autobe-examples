import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { patchDiscussionBoardSearchArticles } from "../../../../providers/patchDiscussionBoardSearchArticles";

import { IPageIDiscussionBoardArticle } from "../../../../api/structures/IPageIDiscussionBoardArticle";
import { IDiscussionBoardArticle } from "../../../../api/structures/IDiscussionBoardArticle";

@Controller("/discussionBoard/search/articles")
export class DiscussionboardSearchArticlesController {
  /**
   * Search and retrieve filtered, paginated list of discussion board articles.
   *
   * Retrieve a comprehensive, filtered, and paginated list of discussion board
   * articles based on advanced search criteria. This operation enables users to
   * discover relevant economic and political discussions through keyword
   * search, category filtering, tag filtering, author filtering, and date range
   * constraints.
   *
   * The search functionality performs full-text search across article titles
   * and body content using PostgreSQL trigram indexes for efficient partial
   * matching. Users can search for keywords like "monetary policy" or "trade
   * agreements" and receive ranked results based on relevance. The system
   * prioritizes title matches over body content matches to surface the most
   * relevant articles.
   *
   * This operation supports comprehensive filtering options including multiple
   * category selection (articles matching any selected category), multiple tag
   * selection (articles matching all selected tags), author filtering by member
   * username, date range filtering for publication dates, and attachment
   * presence filtering (articles with images, documents, or any attachments).
   * Filters can be combined to create highly specific queries.
   *
   * Sorting capabilities include multiple options: relevance-based ranking for
   * keyword searches (default when search keywords are provided), newest first
   * by creation date (default when no keywords), oldest first, most viewed by
   * view_count, most commented by comment_count, and recently updated by
   * updated_at timestamp. The system maintains consistent performance even with
   * complex filter and sort combinations through appropriate database
   * indexing.
   *
   * Pagination follows standard patterns with configurable page size (10, 20,
   * 50, or 100 articles per page, default 20) and page number navigation.
   * Results include total article count, total page count, current page number,
   * and the array of matching articles in summary format optimized for list
   * display.
   *
   * Security considerations include rate limiting on search operations to
   * prevent abuse, filtering out soft-deleted articles (where deleted_at is not
   * null), respecting article status (only published articles visible to
   * guests, draft articles visible only to authors), and appropriate access
   * control based on the requesting user's authentication status. The operation
   * is accessible to all users including guests, members, and moderators, with
   * identical search capabilities for all user types.
   *
   * This operation integrates with the discussion_board_articles table as the
   * primary data source, joins with discussion_board_article_categories and
   * discussion_board_categories for category filtering, joins with
   * discussion_board_article_tags and discussion_board_tags for tag filtering,
   * joins with discussion_board_members for author information, and references
   * discussion_board_article_images and discussion_board_article_documents for
   * attachment filtering. The response returns summary information optimized
   * for search result display, including article metadata, excerpt from body
   * content, author information, category and tag lists, and attachment
   * indicators without loading full attachment details.
   *
   * @param connection
   * @param body Search criteria including keywords, filters, sorting
   *   preferences, and pagination parameters for article discovery
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async search(
    @TypedBody()
    body: IDiscussionBoardArticle.IRequest,
  ): Promise<IPageIDiscussionBoardArticle.ISummary> {
    try {
      return await patchDiscussionBoardSearchArticles({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
