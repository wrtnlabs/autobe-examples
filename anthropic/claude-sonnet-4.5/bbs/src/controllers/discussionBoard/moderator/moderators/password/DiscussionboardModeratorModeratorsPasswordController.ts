import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia from "typia";
import { putDiscussionBoardModeratorModeratorsModeratorUsernamePassword } from "../../../../../providers/putDiscussionBoardModeratorModeratorsModeratorUsernamePassword";
import { ModeratorAuth } from "../../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../../decorators/payload/ModeratorPayload";

import { IDiscussionBoardModerator } from "../../../../../api/structures/IDiscussionBoardModerator";

@Controller("/discussionBoard/moderator/moderators/:moderatorUsername/password")
export class DiscussionboardModeratorModeratorsPasswordController {
  /**
   * Update moderator account password with current password verification.
   *
   * This operation enables authenticated moderators to change their account
   * password by providing their current password for verification and
   * submitting a new password that meets security requirements. The password
   * change process is a critical security operation that ensures only the
   * legitimate account owner can modify authentication credentials.
   *
   * The operation validates that the current password matches the stored
   * password_hash in the discussion_board_moderators table before accepting the
   * new password. The new password must meet complexity requirements including
   * minimum 8 characters length, at least one uppercase letter, one lowercase
   * letter, one number, and one special character. Password strength is
   * validated server-side to prevent weak passwords that could compromise
   * account security.
   *
   * Upon successful password update, the system marks all existing moderator
   * sessions as expired by setting the expired_at timestamp to the current time
   * in the discussion_board_moderator_sessions table. This ensures the
   * moderator must re-authenticate on all devices with the new password,
   * providing security in case the password change was prompted by suspected
   * account compromise. The system updates the password_hash field and the
   * updated_at timestamp in the discussion_board_moderators table.
   *
   * Security measures implemented include requiring current password
   * verification to prevent unauthorized changes, enforcing strong password
   * complexity requirements to resist brute force attacks, expiring all active
   * sessions to invalidate potentially compromised access, and logging the
   * password change event for security audit trails. Note that JWT refresh
   * token management (if implemented) is handled at the application layer
   * outside the database schema.
   *
   * @param connection
   * @param moderatorUsername Unique username of the target moderator account
   *   (global scope). Format: 3-30 alphanumeric characters with underscores and
   *   hyphens allowed.
   * @param body Current password for verification and new password for update
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async updatePassword(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("moderatorUsername")
    moderatorUsername: string,
    @TypedBody()
    body: IDiscussionBoardModerator.IChangePassword,
  ): Promise<IDiscussionBoardModerator> {
    try {
      return await putDiscussionBoardModeratorModeratorsModeratorUsernamePassword(
        {
          moderator,
          moderatorUsername,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
