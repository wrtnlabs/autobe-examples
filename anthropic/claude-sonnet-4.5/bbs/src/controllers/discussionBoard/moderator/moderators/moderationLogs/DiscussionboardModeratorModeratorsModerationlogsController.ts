import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchDiscussionBoardModeratorModeratorsModeratorIdModerationLogs } from "../../../../../providers/patchDiscussionBoardModeratorModeratorsModeratorIdModerationLogs";
import { ModeratorAuth } from "../../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../../decorators/payload/ModeratorPayload";

import { IPageIDiscussionBoardModerationLog } from "../../../../../api/structures/IPageIDiscussionBoardModerationLog";
import { IDiscussionBoardModerationLog } from "../../../../../api/structures/IDiscussionBoardModerationLog";

@Controller("/discussionBoard/moderator/moderators/:moderatorId/moderationLogs")
export class DiscussionboardModeratorModeratorsModerationlogsController {
  /**
   * Retrieve a filtered, sorted, and paginated list of moderation action log
   * entries, providing comprehensive access to the platform's moderation audit
   * trail. This operation supports searching and filtering moderation logs by
   * action type, affected content, affected users, time periods, and specific
   * moderators.
   *
   * The moderation log serves as the authoritative audit trail for all content
   * moderation and user management actions on the platform. Each log entry
   * records what action was taken (article edited, article deleted, attachment
   * removed, account suspended, account banned, account restored), which
   * moderator performed it, what content or user was affected, when it
   * occurred, and the moderator's documented reason. This comprehensive record
   * ensures accountability, enables dispute resolution, supports moderation
   * quality review, and helps identify patterns requiring escalated action.
   *
   * Moderators can search logs by multiple criteria including action type (to
   * find all deletions or suspensions), specific article or member (to review
   * all actions affecting that entity), date ranges (to analyze moderation
   * activity over time), or specific moderator (to review an individual
   * moderator's actions). The operation supports complex filtering combinations
   * and returns paginated results with configurable page sizes for efficient
   * browsing of large audit trails.
   *
   * Security and access control: Only authenticated moderators can access
   * moderation logs, ensuring log data remains confidential and is used only
   * for legitimate oversight purposes. The moderatorId path parameter
   * identifies which moderator is requesting the logs, enabling tracking of log
   * access for security auditing.
   *
   * The response includes detailed log entries with moderator identity, action
   * type, affected content/user references, timestamps, reasons, and additional
   * action details. This supports comprehensive moderation review,
   * investigation of specific incidents, generation of moderation activity
   * reports, and verification that moderation decisions align with community
   * guidelines. Log entries are immutable and retained indefinitely per
   * business requirements, providing a permanent record of platform moderation
   * history.
   *
   * Related operations: Individual moderation actions (edit article, delete
   * article, suspend account) create log entries that appear in results from
   * this search operation. Moderators should use this endpoint regularly to
   * review their own actions and overall platform moderation patterns.
   *
   * @param connection
   * @param moderatorId Unique identifier of the moderator requesting moderation
   *   log access
   * @param body Search criteria, filters, sorting options, and pagination
   *   parameters for moderation log retrieval
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("moderatorId")
    moderatorId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardModerationLog.IRequest,
  ): Promise<IPageIDiscussionBoardModerationLog> {
    try {
      return await patchDiscussionBoardModeratorModeratorsModeratorIdModerationLogs(
        {
          moderator,
          moderatorId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
