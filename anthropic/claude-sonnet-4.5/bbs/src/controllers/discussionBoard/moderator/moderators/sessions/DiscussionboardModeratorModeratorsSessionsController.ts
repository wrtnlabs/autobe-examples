import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchDiscussionBoardModeratorModeratorsModeratorIdSessions } from "../../../../../providers/patchDiscussionBoardModeratorModeratorsModeratorIdSessions";
import { ModeratorAuth } from "../../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../../decorators/payload/ModeratorPayload";
import { deleteDiscussionBoardModeratorModeratorsModeratorIdSessionsSessionId } from "../../../../../providers/deleteDiscussionBoardModeratorModeratorsModeratorIdSessionsSessionId";

import { IPageIDiscussionBoardModeratorSession } from "../../../../../api/structures/IPageIDiscussionBoardModeratorSession";
import { IDiscussionBoardModeratorSession } from "../../../../../api/structures/IDiscussionBoardModeratorSession";

@Controller("/discussionBoard/moderator/moderators/:moderatorId/sessions")
export class DiscussionboardModeratorModeratorsSessionsController {
  /**
   * Retrieve a filtered, paginated list of authentication sessions for a
   * specific moderator from the discussion_board_moderator_sessions table. This
   * operation provides comprehensive search capabilities for reviewing
   * moderator login history, tracking session activity, and monitoring security
   * events such as unusual login locations or patterns.
   *
   * The operation supports advanced filtering options including date range
   * searches (created_at), IP address filtering for identifying sessions from
   * specific locations, and session status filtering (active sessions with null
   * expired_at vs terminated sessions). Results are returned in paginated
   * format with configurable page size and sorting options, typically ordered
   * by creation date descending to show most recent sessions first.
   *
   * Security and audit considerations: This operation is essential for security
   * monitoring and accountability. Administrators can use it to track moderator
   * login patterns, identify suspicious activity such as concurrent sessions
   * from different geographic locations, and investigate security incidents.
   * The session data includes connection context (IP, href, referrer) that
   * provides forensic information for security reviews.
   *
   * Session lifecycle information helps administrators understand moderator
   * activity patterns and identify inactive moderators who may need privilege
   * review. The expired_at timestamp distinguishes between active sessions
   * (null) and terminated sessions (logout or token expiration), enabling
   * precise session state tracking.
   *
   * Related operations: This operation is typically used in conjunction with
   * moderator account management endpoints. After reviewing session history,
   * administrators may decide to revoke moderator privileges (DELETE
   * /moderators/{moderatorId}) if suspicious patterns are detected. The session
   * data also correlates with moderation action logs to provide complete
   * activity context.
   *
   * @param connection
   * @param moderatorId Unique identifier of the moderator whose sessions are
   *   being retrieved
   * @param body Search criteria and pagination parameters for filtering
   *   moderator sessions
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("moderatorId")
    moderatorId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardModeratorSession.IRequest,
  ): Promise<IPageIDiscussionBoardModeratorSession> {
    try {
      return await patchDiscussionBoardModeratorModeratorsModeratorIdSessions({
        moderator,
        moderatorId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Terminate and remove a specific moderator authentication session,
   * effectively logging out the moderator from that particular session. This
   * operation implements explicit session termination, allowing moderators to
   * end their authenticated access to the platform.
   *
   * When a moderator logs out or when a session needs to be terminated for
   * security reasons, this endpoint deletes the session record from the
   * discussion_board_moderator_sessions table. The operation sets the
   * expired_at timestamp to mark session termination and removes the session
   * from active use. All JWT tokens associated with this session become invalid
   * immediately upon deletion.
   *
   * Security considerations: Only the moderator who owns the session can delete
   * it, enforcing session ownership. The moderatorId path parameter must match
   * the authenticated moderator's identity. This prevents unauthorized session
   * termination. Moderators can also use the "logout from all devices"
   * functionality to terminate all their sessions simultaneously.
   *
   * This operation supports the authentication requirements defined in the
   * business rules, implementing secure session lifecycle management. When a
   * moderator changes their password, all sessions except the current one
   * should be terminated using this operation. Session deletion is permanent
   * and cannot be reversed - the moderator must login again to create a new
   * session.
   *
   * Related operations: POST /moderators/login creates new sessions, and this
   * DELETE operation terminates them. Moderators should call this endpoint when
   * explicitly logging out to ensure proper session cleanup and security.
   *
   * @param connection
   * @param moderatorId Unique identifier of the moderator who owns the session
   * @param sessionId Unique identifier of the specific session to terminate
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":sessionId")
  public async erase(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("moderatorId")
    moderatorId: string & tags.Format<"uuid">,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteDiscussionBoardModeratorModeratorsModeratorIdSessionsSessionId(
        {
          moderator,
          moderatorId,
          sessionId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
