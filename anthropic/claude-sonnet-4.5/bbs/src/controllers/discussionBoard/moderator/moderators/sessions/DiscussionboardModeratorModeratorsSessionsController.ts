import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchDiscussionBoardModeratorModeratorsModeratorIdSessions } from "../../../../../providers/patchDiscussionBoardModeratorModeratorsModeratorIdSessions";
import { ModeratorAuth } from "../../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../../decorators/payload/ModeratorPayload";
import { getDiscussionBoardModeratorModeratorsModeratorIdSessionsSessionId } from "../../../../../providers/getDiscussionBoardModeratorModeratorsModeratorIdSessionsSessionId";
import { deleteDiscussionBoardModeratorModeratorsModeratorIdSessionsSessionId } from "../../../../../providers/deleteDiscussionBoardModeratorModeratorsModeratorIdSessionsSessionId";

import { IPageIDiscussionBoardModeratorSession } from "../../../../../api/structures/IPageIDiscussionBoardModeratorSession";
import { IDiscussionBoardModeratorSession } from "../../../../../api/structures/IDiscussionBoardModeratorSession";

@Controller("/discussionBoard/moderator/moderators/:moderatorId/sessions")
export class DiscussionboardModeratorModeratorsSessionsController {
  /**
   * Search and retrieve paginated list of authentication sessions for a
   * specific moderator.
   *
   * Retrieve a filtered and paginated list of authentication sessions
   * associated with a specific moderator account. This operation provides
   * comprehensive search capabilities for auditing and monitoring moderator
   * login activity, including filtering by session creation timestamps, IP
   * addresses, user agents, and session validity status.
   *
   * The operation supports advanced pagination with configurable page sizes and
   * sorting options. Sessions can be sorted by creation time, last activity
   * time, or expiration time in ascending or descending order. This is
   * particularly useful for security teams monitoring for unusual login
   * patterns, investigating potential account compromises, or conducting
   * routine security audits.
   *
   * Security considerations include strict access control limiting this
   * operation to moderators themselves viewing their own sessions or other
   * authorized moderators. The operation returns session metadata including
   * creation timestamps, IP addresses, and user agent strings, but excludes
   * sensitive session tokens or credentials. Rate limiting is applied to
   * prevent abuse of this search functionality.
   *
   * The operation integrates with the discussion_board_moderator_sessions table
   * as defined in the Prisma schema, accessing session records scoped to the
   * specific moderator identified by the moderatorId path parameter. The
   * response includes session summary information optimized for administrative
   * dashboards and security monitoring interfaces, with options to include
   * additional session details based on the requester's authorization level.
   *
   * @param connection
   * @param moderatorId Unique business identifier code of the target moderator
   *   whose sessions are being queried (global scope)
   * @param body Search criteria and pagination parameters for filtering
   *   moderator authentication sessions
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("moderatorId")
    moderatorId: string,
    @TypedBody()
    body: IDiscussionBoardModeratorSession.IRequest,
  ): Promise<IPageIDiscussionBoardModeratorSession.ISummary> {
    try {
      return await patchDiscussionBoardModeratorModeratorsModeratorIdSessions({
        moderator,
        moderatorId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific moderator session by ID.
   *
   * Retrieve detailed information about a specific moderator authentication
   * session.
   *
   * This operation allows moderators to view their own active session details,
   * including session token, creation timestamp, and expiration information.
   * The session data is essential for maintaining authentication state and
   * managing active login sessions across the discussion board platform.
   *
   * Security: Only the authenticated moderator who owns the session can
   * retrieve their own session information. The moderator's identity is
   * verified through JWT authentication, ensuring that moderators cannot access
   * other moderators' session data.
   *
   * The session information includes the complete session record from the
   * discussion_board_moderator_sessions table, providing full visibility into
   * the authentication state. This operation is commonly used for session
   * validation, session management dashboards, and debugging authentication
   * issues.
   *
   * Related operations: List moderator sessions (PATCH
   * /moderators/{moderatorId}/sessions), Delete moderator session (DELETE
   * /moderators/{moderatorId}/sessions/{sessionId}).
   *
   * @param connection
   * @param moderatorId Unique identifier of the target moderator (global scope)
   * @param sessionId Unique identifier of the target session (scoped to
   *   moderator)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("moderatorId")
    moderatorId: string & tags.Format<"uuid">,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardModeratorSession> {
    try {
      return await getDiscussionBoardModeratorModeratorsModeratorIdSessionsSessionId(
        {
          moderator,
          moderatorId,
          sessionId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a specific moderator session (logout).
   *
   * Delete a specific moderator authentication session, effectively logging out
   * the moderator from that session.
   *
   * This operation allows moderators to terminate their own active sessions,
   * which is the standard logout mechanism for the discussion board platform.
   * When a session is deleted, the moderator will need to re-authenticate to
   * access moderator-restricted features. This operation permanently removes
   * the session record from the database.
   *
   * Security: Only the authenticated moderator who owns the session can delete
   * their own sessions. The moderator's identity is verified through JWT
   * authentication, ensuring that moderators cannot terminate other moderators'
   * sessions. This operation is crucial for security best practices, allowing
   * moderators to explicitly end their authenticated sessions when logging
   * out.
   *
   * The deletion is permanent and cannot be undone. Once a session is deleted,
   * the associated session token becomes invalid immediately, and any
   * subsequent API requests using that token will be rejected. This operation
   * is commonly used when a moderator clicks "logout" in the user interface or
   * when implementing "logout from all devices" functionality.
   *
   * Related operations: Retrieve moderator session (GET
   * /moderators/{moderatorId}/sessions/{sessionId}), List moderator sessions
   * (PATCH /moderators/{moderatorId}/sessions).
   *
   * @param connection
   * @param moderatorId Unique identifier of the target moderator (global scope)
   * @param sessionId Unique identifier of the target session to delete (scoped
   *   to moderator)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":sessionId")
  public async erase(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("moderatorId")
    moderatorId: string & tags.Format<"uuid">,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardModeratorSession> {
    try {
      return await deleteDiscussionBoardModeratorModeratorsModeratorIdSessionsSessionId(
        {
          moderator,
          moderatorId,
          sessionId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
