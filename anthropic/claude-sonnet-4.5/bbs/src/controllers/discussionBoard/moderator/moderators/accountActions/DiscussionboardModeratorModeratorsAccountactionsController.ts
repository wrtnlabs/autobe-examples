import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchDiscussionBoardModeratorModeratorsModeratorIdAccountActions } from "../../../../../providers/patchDiscussionBoardModeratorModeratorsModeratorIdAccountActions";
import { ModeratorAuth } from "../../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../../decorators/payload/ModeratorPayload";

import { IPageIDiscussionBoardAccountAction } from "../../../../../api/structures/IPageIDiscussionBoardAccountAction";
import { IDiscussionBoardAccountAction } from "../../../../../api/structures/IDiscussionBoardAccountAction";

@Controller("/discussionBoard/moderator/moderators/:moderatorId/accountActions")
export class DiscussionboardModeratorModeratorsAccountactionsController {
  /**
   * Search and retrieve account moderation actions performed by a specific
   * moderator.
   *
   * Retrieve a filtered and paginated list of account-level moderation actions
   * (suspensions and bans) that were applied by a specific moderator on the
   * discussion board platform. This operation provides comprehensive search and
   * filtering capabilities for reviewing enforcement history, tracking
   * moderation patterns, and ensuring accountability in community guideline
   * enforcement.
   *
   * The operation queries the discussion_board_account_actions table, filtering
   * by the discussion_board_moderator_id foreign key to return only actions
   * performed by the specified moderator. Each action record includes the
   * affected member, action type (suspension or ban), reason provided by the
   * moderator, duration (for temporary suspensions), current status (active,
   * expired, or reversed), and relevant timestamps. This complete action
   * history enables administrators to monitor moderator activity and identify
   * enforcement trends.
   *
   * The request body supports advanced filtering options including action type
   * (suspension vs ban), status (active, expired, reversed), date ranges for
   * action creation, and text search within reason fields. Results can be
   * sorted by creation timestamp, expiration date, or affected member to
   * facilitate different review workflows. Pagination parameters allow
   * efficient navigation through large action histories.
   *
   * Security considerations require that only the moderator themselves or
   * administrators can access this endpoint, as it contains sensitive
   * enforcement information and moderator decision rationale. The operation
   * maintains transparency by preserving complete action records including
   * reversal information when moderators lift suspensions or bans in error.
   *
   * This operation integrates with the discussion_board_account_actions,
   * discussion_board_moderators, and discussion_board_members tables as defined
   * in the Prisma schema. The response includes summary information optimized
   * for moderation dashboard displays, with options to include detailed member
   * and moderator information based on authorization level and use case
   * requirements.
   *
   * @param connection
   * @param moderatorId Unique identifier of the moderator whose account actions
   *   should be retrieved
   * @param body Search criteria, filtering options, and pagination parameters
   *   for moderator account actions
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("moderatorId")
    moderatorId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardAccountAction.IRequest,
  ): Promise<IPageIDiscussionBoardAccountAction.ISummary> {
    try {
      return await patchDiscussionBoardModeratorModeratorsModeratorIdAccountActions(
        {
          moderator,
          moderatorId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
