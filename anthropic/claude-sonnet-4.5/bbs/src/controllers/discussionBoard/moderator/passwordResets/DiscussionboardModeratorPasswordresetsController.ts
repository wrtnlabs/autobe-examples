import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { getDiscussionBoardModeratorPasswordResetsResetId } from "../../../../providers/getDiscussionBoardModeratorPasswordResetsResetId";
import { ModeratorAuth } from "../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../decorators/payload/ModeratorPayload";

import { IDiscussionBoardPasswordReset } from "../../../../api/structures/IDiscussionBoardPasswordReset";

@Controller("/discussionBoard/moderator/passwordResets/:resetId")
export class DiscussionboardModeratorPasswordresetsController {
  /**
   * Retrieve a specific password reset request by ID (token excluded for
   * security).
   *
   * Retrieve detailed information about a password reset request identified by
   * its unique ID from the discussion_board_password_resets table.
   *
   * This operation returns comprehensive password reset request data including
   * the target email address, expiration timestamp (1 hour validity), usage
   * status, and creation timestamp. The response identifies whether the reset
   * request was initiated by a member or moderator through the actor_type
   * discriminator field.
   *
   * The system uses a polymorphic ownership pattern where password resets can
   * be associated with either members or moderators. The actual relationship to
   * the specific member or moderator account is maintained through separate
   * junction tables (discussion_board_password_reset_of_members and
   * discussion_board_password_reset_of_moderators), following the Compatible
   * Actor Pattern for proper database normalization.
   *
   * Security considerations: This endpoint is restricted to moderator access
   * only. The password reset token field is intentionally excluded from the
   * response as it is a sensitive security credential. Exposing the token would
   * allow unauthorized password changes. Tokens are single-use, expire after 1
   * hour, and are invalidated immediately upon successful password change. The
   * used_at timestamp indicates whether a token has been consumed.
   *
   * Use cases include administrative review of password reset requests,
   * debugging reset flow issues, and monitoring reset token usage patterns for
   * security auditing. The used_at timestamp helps identify pending versus
   * completed reset requests.
   *
   * @param connection
   * @param resetId Unique identifier of the password reset request
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("resetId")
    resetId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardPasswordReset> {
    try {
      return await getDiscussionBoardModeratorPasswordResetsResetId({
        moderator,
        resetId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
