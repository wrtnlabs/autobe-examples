import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia from "typia";
import { postDiscussionBoardModeratorCategories } from "../../../../providers/postDiscussionBoardModeratorCategories";
import { ModeratorAuth } from "../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../decorators/payload/ModeratorPayload";
import { putDiscussionBoardModeratorCategoriesCategorySlug } from "../../../../providers/putDiscussionBoardModeratorCategoriesCategorySlug";
import { deleteDiscussionBoardModeratorCategoriesCategorySlug } from "../../../../providers/deleteDiscussionBoardModeratorCategoriesCategorySlug";

import { IDiscussionBoardCategory } from "../../../../api/structures/IDiscussionBoardCategory";

@Controller("/discussionBoard/moderator/categories")
export class DiscussionboardModeratorCategoriesController {
  /**
   * Create a new article category for discussion board content organization.
   *
   * Create a new category in the discussion board categories taxonomy system.
   * Categories serve as the primary organizational structure for articles
   * discussing economic and political topics, providing high-level subject area
   * classification that helps users discover and browse content
   * systematically.
   *
   * This operation accepts category information including a display name and
   * optional description, then validates the input to ensure category names are
   * unique across the system. The system automatically generates a URL-friendly
   * slug derived from the category name for use in SEO-friendly routes and
   * permalinks. All category fields are validated according to business rules
   * defined in the requirements, with specific constraints on name uniqueness
   * and slug format.
   *
   * Security considerations include restricting this operation to moderators
   * only, as category management is an administrative function that shapes the
   * entire content taxonomy. Moderators must be authenticated and have
   * appropriate permissions to create new categories. The operation maintains
   * referential integrity by creating the category record with proper
   * timestamps and ensuring the category is immediately available for article
   * categorization.
   *
   * The newly created category becomes available in article creation and
   * editing interfaces, allowing members to classify their articles under this
   * new subject area. Categories play a crucial role in content discovery,
   * search filtering, and user navigation throughout the discussion board. This
   * operation integrates with the article management system defined in the
   * Article Management Requirements document, where categories are required
   * fields during article creation.
   *
   * @param connection
   * @param body Category creation data including display name, optional
   *   description, and auto-generated slug
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedBody()
    body: IDiscussionBoardCategory.ICreate,
  ): Promise<IDiscussionBoardCategory> {
    try {
      return await postDiscussionBoardModeratorCategories({
        moderator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing article category by its slug identifier.
   *
   * Update the name and description of an existing category in the discussion
   * board taxonomy system. This operation enables moderators to refine category
   * definitions, correct naming issues, or expand category descriptions as the
   * discussion board evolves and community needs change.
   *
   * The operation identifies the target category using the URL-friendly slug
   * path parameter, which provides a stable, human-readable identifier for SEO
   * optimization and user-friendly URLs. The slug corresponds to the unique
   * slug field in the discussion_board_categories table. When updating a
   * category, the system validates that the new name (if changed) does not
   * conflict with existing categories, maintains the slug-to-category mapping,
   * and optionally regenerates the slug if the name change warrants it.
   *
   * Security and authorization are critical for this operation - only
   * moderators can modify categories as this is an administrative function that
   * affects the entire content organization structure. The operation verifies
   * moderator authentication and permissions before allowing any modifications.
   * All changes are recorded with updated timestamps, and the system maintains
   * referential integrity with existing article-category associations in the
   * discussion_board_article_categories junction table.
   *
   * When a category is updated, all articles already associated with this
   * category remain associated, and the updated category information appears
   * immediately in article displays, category browsing pages, and search
   * filters. This operation integrates with the moderation system defined in
   * the Moderation and Content Management document, where category management
   * is part of moderator capabilities. The operation logs the modification for
   * audit purposes and ensures data consistency across all category
   * references.
   *
   * @param connection
   * @param categorySlug URL-friendly slug identifier of the target category
   *   (global scope)
   * @param body Category update data with modified name and/or description
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":categorySlug")
  public async update(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("categorySlug")
    categorySlug: string,
    @TypedBody()
    body: IDiscussionBoardCategory.IUpdate,
  ): Promise<IDiscussionBoardCategory> {
    try {
      return await putDiscussionBoardModeratorCategoriesCategorySlug({
        moderator,
        categorySlug,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a category from the discussion board system.
   *
   * This operation permanently removes a category from the discussion board's
   * taxonomy structure, completely deleting the category record from the
   * discussion_board_categories table. Categories serve as the primary
   * organizational framework for economic and political discussion topics,
   * providing structured browsing and content discovery for users.
   *
   * When a category is deleted, the system performs a hard delete operation
   * that completely removes the category record. The schema does NOT support
   * soft deletion for categories as there is no deleted_at timestamp column.
   * This means deletion is immediate and permanent. All associated
   * relationships in the discussion_board_article_categories junction table are
   * automatically removed through database cascade deletion constraints,
   * ensuring that no orphaned references remain. Articles previously
   * categorized under the deleted category will lose that categorization,
   * though the articles themselves remain intact.
   *
   * This operation is restricted to moderators only, as category management is
   * a system-wide administrative function that affects content organization for
   * all users. Moderators must exercise caution when deleting categories, as
   * the action is irreversible. Before deletion, moderators should consider
   * whether articles need to be recategorized, whether the category has
   * historical significance, and whether deletion might disrupt ongoing
   * discussions organized under that category. The operation should be logged
   * as a moderation action for audit purposes, and moderators may want to
   * notify the community when significant categories are removed from the
   * taxonomy.
   *
   * @param connection
   * @param categorySlug URL-friendly unique identifier of the target category
   *   to delete (global scope)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":categorySlug")
  public async erase(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("categorySlug")
    categorySlug: string,
  ): Promise<IDiscussionBoardCategory> {
    try {
      return await deleteDiscussionBoardModeratorCategoriesCategorySlug({
        moderator,
        categorySlug,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
