import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postDiscussionBoardModeratorCategories } from "../../../../providers/postDiscussionBoardModeratorCategories";
import { ModeratorAuth } from "../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../decorators/payload/ModeratorPayload";
import { putDiscussionBoardModeratorCategoriesCategoryId } from "../../../../providers/putDiscussionBoardModeratorCategoriesCategoryId";
import { deleteDiscussionBoardModeratorCategoriesCategoryId } from "../../../../providers/deleteDiscussionBoardModeratorCategoriesCategoryId";

import { IDiscussionBoardArticleCategory } from "../../../../api/structures/IDiscussionBoardArticleCategory";

@Controller("/discussionBoard/moderator/categories")
export class DiscussionboardModeratorCategoriesController {
  /**
   * Create a new article category for organizing discussions by topic area.
   *
   * Create a new article category in the discussion board system for organizing
   * articles by topic area. Categories provide the organizational taxonomy that
   * helps users discover relevant economic and political discussions and browse
   * articles by topic focus.
   *
   * This operation is restricted to moderators only, as categories are managed
   * by administrators to maintain a consistent and focused categorization
   * system. Creating categories requires careful consideration of the
   * discussion board's scope and topic coverage.
   *
   * The operation accepts a category name (displayed to users), URL-friendly
   * slug (used in routing and filters), optional description explaining the
   * category's scope, and sort order for controlling display priority. The
   * system validates that the category name and slug are unique across all
   * existing categories to prevent duplicates and URL conflicts.
   *
   * Upon successful creation, the category becomes immediately available for
   * member selection during article creation. The sort_order field allows
   * administrators to prioritize how categories appear in category lists and
   * filter menus, with lower numbers appearing first.
   *
   * Category descriptions should provide clear guidance to members about what
   * types of articles belong in each category, helping maintain focused and
   * relevant discussions. Examples include explaining that Economic Discussion
   * covers economic policy, markets, and fiscal topics, while Political
   * Discussion addresses governance, elections, and political systems.
   *
   * The created category record includes system-generated timestamps
   * (created_at, updated_at) for audit purposes and category management. All
   * category data follows the discussion_board_article_categories table schema
   * with proper validation and constraints.
   *
   * @param connection
   * @param body Category creation data including name, slug, description, and
   *   sort order
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedBody()
    body: IDiscussionBoardArticleCategory.ICreate,
  ): Promise<IDiscussionBoardArticleCategory> {
    try {
      return await postDiscussionBoardModeratorCategories({
        moderator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing article category's name, slug, description, or sort
   * order.
   *
   * Update an existing article category identified by its unique UUID in the
   * discussion board system. This operation allows moderators to modify
   * category information to refine the organizational taxonomy, correct
   * category details, or adjust display priority.
   *
   * Moderators can update the category name (display name shown to users), slug
   * (URL-friendly identifier used in routing), description (explanatory text
   * about category scope), and sort_order (display priority with lower numbers
   * appearing first). The operation is restricted to moderators only as
   * category management is an administrative function requiring careful
   * oversight.
   *
   * The system validates that updated name and slug values remain unique across
   * all categories except the category being updated. This prevents duplicate
   * category names and URL conflicts while allowing the same category to retain
   * its existing values if unchanged. Uniqueness validation ensures the
   * integrity of the categorization system and prevents user confusion.
   *
   * When the category slug is changed, existing article URLs referencing the
   * old slug may need handling through redirects or URL migration, though
   * articles reference categories by ID internally so the relationship remains
   * intact. Changing category names affects how categories appear in article
   * creation forms and filter menus.
   *
   * The sort_order field controls the display sequence in category lists,
   * allowing administrators to prioritize certain topic areas. For example,
   * setting Economic Discussion to sort_order 1 and Political Discussion to
   * sort_order 2 ensures economic topics appear first in category selectors.
   *
   * Category descriptions should be updated to provide clear, current guidance
   * about what content belongs in each category. Well-written descriptions help
   * members choose appropriate categories when creating articles, maintaining
   * focused discussions and improving content discoverability.
   *
   * The operation updates the updated_at timestamp automatically to track when
   * category information was last modified. All updates follow the
   * discussion_board_article_categories table schema constraints and validation
   * rules. The complete updated category record is returned, including the new
   * updated_at timestamp and all modified fields.
   *
   * @param connection
   * @param categoryId Unique identifier of the target category to update
   * @param body Updated category data including name, slug, description, and
   *   sort order
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":categoryId")
  public async update(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("categoryId")
    categoryId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardArticleCategory.IUpdate,
  ): Promise<IDiscussionBoardArticleCategory> {
    try {
      return await putDiscussionBoardModeratorCategoriesCategoryId({
        moderator,
        categoryId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Remove a discussion article category from the system.
   *
   * Permanently removes a category from the discussion board category taxonomy.
   * This operation is restricted to moderators who manage the organizational
   * structure of article categories.
   *
   * The category system provides the foundational taxonomy for organizing
   * discussions into topic areas like Economic Discussion, Political
   * Discussion, and General Discussion. Categories cannot be deleted if they
   * are currently assigned to any published or draft articles, as this would
   * violate referential integrity and leave articles without valid
   * categorization.
   *
   * Before executing deletion, the system verifies that the
   * discussion_board_article_category_id foreign key is not referenced by any
   * records in the discussion_board_articles table. If articles exist with this
   * category assignment, the operation fails with a clear error message
   * indicating the category is in use and cannot be deleted until all articles
   * are recategorized.
   *
   * Successful deletion permanently removes the category record from
   * discussion_board_article_categories, including the category name, slug,
   * description, and sort_order. This operation is irreversible and should be
   * used with caution. Moderators should ensure all articles are moved to
   * appropriate alternative categories before deleting a category.
   *
   * This operation supports category taxonomy management, allowing moderators
   * to retire outdated categories, consolidate similar categories, or refine
   * the organizational structure as the discussion board evolves. The
   * enforcement of referential integrity prevents data corruption and ensures
   * all articles maintain valid category assignments.
   *
   * @param connection
   * @param categoryId Unique identifier of the category to delete
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":categoryId")
  public async erase(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("categoryId")
    categoryId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteDiscussionBoardModeratorCategoriesCategoryId({
        moderator,
        categoryId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
