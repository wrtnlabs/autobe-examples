import { Controller } from "@nestjs/common";
import { TypedRoute } from "@nestia/core";
import typia from "typia";
import { postDiscussionBoardModeratorAuthLogout } from "../../../../../providers/postDiscussionBoardModeratorAuthLogout";
import { ModeratorAuth } from "../../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../../decorators/payload/ModeratorPayload";

import { IDiscussionBoardAuth } from "../../../../../api/structures/IDiscussionBoardAuth";

@Controller("/discussionBoard/moderator/auth/logout")
export class DiscussionboardModeratorAuthController {
  /**
   * Terminate current moderator session and invalidate authentication tokens.
   *
   * Terminate the currently authenticated moderator session by invalidating the
   * refresh token and recording the session end time in the
   * discussion_board_moderator_sessions table. This operation enables
   * moderators to securely end their authenticated session, preventing further
   * use of the current refresh token to obtain new access tokens.
   *
   * The logout process marks the current session as expired by setting the
   * expired_at timestamp to the current time, creating a complete audit trail
   * of session duration and moderator activity. The operation extracts the
   * moderator's identity and current session information from the JWT access
   * token, eliminating the need for request body parameters. After successful
   * logout, the client must discard both the access token and refresh token
   * from local storage to complete the logout process.
   *
   * This operation is particularly important for security when moderators
   * access the system from shared or public devices, as it ensures that
   * sessions are properly terminated rather than remaining active until the
   * 30-day refresh token expiration. The logout action only affects the current
   * device's session - moderators can remain logged in on other devices if they
   * have multiple active sessions across different browsers or devices. When a
   * moderator changes their password, all sessions across all devices are
   * invalidated automatically through a separate mechanism, but manual logout
   * only terminates the specific session from which it was initiated.
   *
   * The operation requires a valid moderator access token to identify the
   * session to be terminated. No request body is needed as all session
   * information is derived from the authentication token. The response confirms
   * successful logout, after which the moderator must authenticate again using
   * the login operation to regain access to protected moderator features such
   * as content moderation and user management.
   *
   * @param connection
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async logout(
    @ModeratorAuth()
    moderator: ModeratorPayload,
  ): Promise<IDiscussionBoardAuth.ILogoutResult> {
    try {
      return await postDiscussionBoardModeratorAuthLogout({
        moderator,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
