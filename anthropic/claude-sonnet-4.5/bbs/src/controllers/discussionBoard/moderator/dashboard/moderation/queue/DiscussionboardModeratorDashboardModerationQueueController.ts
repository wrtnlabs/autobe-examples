import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { patchDiscussionBoardModeratorDashboardModerationQueue } from "../../../../../../providers/patchDiscussionBoardModeratorDashboardModerationQueue";
import { ModeratorAuth } from "../../../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../../../decorators/payload/ModeratorPayload";

import { IPageIDiscussionBoardContentReport } from "../../../../../../api/structures/IPageIDiscussionBoardContentReport";
import { IDiscussionBoardContentReport } from "../../../../../../api/structures/IDiscussionBoardContentReport";

@Controller("/discussionBoard/moderator/dashboard/moderation/queue")
export class DiscussionboardModeratorDashboardModerationQueueController {
  /**
   * Retrieve a comprehensive list of content reports from the moderation queue
   * with advanced filtering, searching, sorting, and pagination capabilities.
   * This operation enables moderators to efficiently review community-submitted
   * reports about articles that allegedly violate community guidelines.
   *
   * The operation queries the discussion_board_content_reports table and
   * supports multiple filter criteria including report status (pending,
   * reviewed_no_action, reviewed_edited, reviewed_removed), date range
   * filtering for submission time, specific reporter filtering, specific
   * article filtering, and report category filtering. Moderators can sort
   * results by submission date, resolution date, or report priority (determined
   * by number of reports on the same article).
   *
   * Security considerations: This operation is restricted to authenticated
   * moderators only. Only users with moderator privileges can access the
   * moderation queue. The response includes sensitive information about
   * reporters and reported content that should not be exposed to regular
   * members. Rate limiting applies to prevent abuse of the moderation system.
   *
   * The paginated response includes report details such as report ID, reported
   * article information, reporter information, report category, detailed
   * explanation, current status, resolution notes (if resolved), submission
   * timestamp, and resolution timestamp. Each report entry provides sufficient
   * context for moderators to make informed moderation decisions without
   * requiring additional API calls.
   *
   * Related operations: After reviewing reports in the queue, moderators may
   * use PUT /articles/{articleId} to edit content, DELETE /articles/{articleId}
   * to remove content, or PUT /reports/{reportId}/resolve to mark reports as
   * resolved. The moderation queue is the entry point for the content review
   * workflow documented in the user workflows specification.
   *
   * @param connection
   * @param body Search and filter criteria for moderation queue reports
   *   including status filters, date ranges, and pagination parameters
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedBody()
    body: IDiscussionBoardContentReport.IRequest,
  ): Promise<IPageIDiscussionBoardContentReport.ISummary> {
    try {
      return await patchDiscussionBoardModeratorDashboardModerationQueue({
        moderator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
