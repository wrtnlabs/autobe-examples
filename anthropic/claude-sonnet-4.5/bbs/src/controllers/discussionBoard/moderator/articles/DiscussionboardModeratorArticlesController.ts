import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { putDiscussionBoardModeratorArticlesArticleId } from "../../../../providers/putDiscussionBoardModeratorArticlesArticleId";
import { ModeratorAuth } from "../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../decorators/payload/ModeratorPayload";
import { deleteDiscussionBoardModeratorArticlesArticleId } from "../../../../providers/deleteDiscussionBoardModeratorArticlesArticleId";

import { IDiscussionBoardArticle } from "../../../../api/structures/IDiscussionBoardArticle";

@Controller("/discussionBoard/moderator/articles/:articleId")
export class DiscussionboardModeratorArticlesController {
  /**
   * Update an existing discussion board article's content, metadata, and
   * publication status. This operation allows authorized users to modify
   * article properties including the title, URL slug, body content, excerpt,
   * category assignment, and publication status.
   *
   * Members can update only their own articles at any time, modifying content
   * in draft or published states. Moderators have elevated permissions to
   * update any article in the system for quality control, guideline
   * enforcement, or content correction purposes. When an article is updated
   * after initial publication, the is_edited flag is automatically set to true
   * to maintain transparency about content revisions.
   *
   * The operation validates that the article exists, verifies user
   * authorization (ownership for members, unrestricted for moderators), and
   * enforces business rules including title length (5-200 characters), body
   * length (50-50,000 characters), slug uniqueness, and valid category
   * references. The updated_at timestamp is automatically updated on successful
   * modification. If the status changes from 'draft' to 'published' and
   * published_at is null, the published_at timestamp is set to the current
   * time.
   *
   * Security considerations include ownership verification for members,
   * ensuring members cannot update articles they don't own. Moderators bypass
   * ownership checks but their actions should be logged through moderation_logs
   * for accountability. The slug must remain unique across all articles to
   * prevent URL conflicts. Related operations include GET /articles/{articleId}
   * to retrieve current article state before updating, and DELETE
   * /articles/{articleId} to remove articles.
   *
   * @param connection
   * @param articleId Unique identifier of the target article to update
   * @param body Updated article data including title, content, category, and
   *   status
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardArticle.IUpdate,
  ): Promise<IDiscussionBoardArticle> {
    try {
      return await putDiscussionBoardModeratorArticlesArticleId({
        moderator,
        articleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a discussion board article from the system using soft deletion. This
   * operation marks the article as deleted by setting the deleted_at timestamp,
   * enabling a 30-day retention period for potential recovery before permanent
   * removal from the database.
   *
   * Members can delete only their own articles at any time, regardless of
   * publication status (draft, published, or archived). This allows members to
   * remove content they no longer wish to maintain or that they consider
   * outdated. Moderators have elevated permissions to delete any article in the
   * system, enabling enforcement of community guidelines and removal of content
   * that violates policies, contains inappropriate material, or is reported by
   * other members.
   *
   * When an article is deleted, all associated attachments (images and files in
   * discussion_board_article_attachments table) should also be soft-deleted to
   * maintain data consistency and prevent orphaned attachments. The soft
   * deletion approach preserves article content and metadata for the retention
   * period, allowing for recovery if deletion was accidental or if moderation
   * decisions need review.
   *
   * Security considerations include strict ownership verification for members
   * to prevent unauthorized deletion of other members' content. Moderators
   * bypass ownership checks but their deletion actions should be logged in
   * moderation_logs for accountability and transparency. The operation
   * validates that the article exists and is not already deleted before
   * processing.
   *
   * Related operations include PUT /articles/{articleId} to update articles
   * before deletion decisions, and PATCH /articles to search for articles that
   * may need moderation review. The deletion operation returns the deleted
   * article data including the newly set deleted_at timestamp for
   * confirmation.
   *
   * @param connection
   * @param articleId Unique identifier of the target article to delete
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardArticle> {
    try {
      return await deleteDiscussionBoardModeratorArticlesArticleId({
        moderator,
        articleId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
