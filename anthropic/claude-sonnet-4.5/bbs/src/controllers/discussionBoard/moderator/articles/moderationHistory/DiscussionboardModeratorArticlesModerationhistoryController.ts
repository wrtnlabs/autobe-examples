import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchDiscussionBoardModeratorArticlesArticleIdModerationHistory } from "../../../../../providers/patchDiscussionBoardModeratorArticlesArticleIdModerationHistory";
import { ModeratorAuth } from "../../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../../decorators/payload/ModeratorPayload";

import { IPageIDiscussionBoardModerationLog } from "../../../../../api/structures/IPageIDiscussionBoardModerationLog";
import { IDiscussionBoardModerationLog } from "../../../../../api/structures/IDiscussionBoardModerationLog";

@Controller("/discussionBoard/moderator/articles/:articleId/moderationHistory")
export class DiscussionboardModeratorArticlesModerationhistoryController {
  /**
   * Search and retrieve the complete moderation history for a specific article.
   *
   * Retrieve a comprehensive, paginated list of all moderation actions that
   * have been applied to a specific article throughout its lifecycle. This
   * operation queries the discussion_board_moderation_logs table filtered by
   * the article ID to return every recorded moderation action affecting this
   * article.
   *
   * The moderation history includes all actions where moderators intervened on
   * the article content: article edits made by moderators (when they modified
   * the title, body, or category for policy compliance), attachment removals
   * (when specific images or files were deleted for violating guidelines), and
   * article deletion actions (when the entire article was removed from public
   * view or permanently deleted).
   *
   * This operation supports several critical use cases: moderators reviewing
   * the enforcement history of problematic content to understand patterns and
   * escalation, article authors understanding what changes were made to their
   * content and why, administrators auditing moderation consistency and
   * response times, and dispute resolution processes where complete action
   * history is needed to evaluate appeals.
   *
   * The request body accepts search and filtering criteria including date
   * ranges (to find actions within specific time periods), action types (to
   * filter by article_edited, attachment_removed, or article_deleted), and
   * specific moderator IDs (to review actions by particular moderators).
   * Pagination parameters control result size and allow navigation through long
   * moderation histories for frequently-moderated articles.
   *
   * Each log entry in the response includes the complete context captured when
   * the action was taken: what type of action was performed, which moderator
   * performed it, when it occurred, the documented reason the moderator
   * provided, and additional contextual details about what was changed. The
   * results are sorted in reverse chronological order by default, showing the
   * most recent moderation actions first.
   *
   * Access control should be carefully designed: moderators need full access to
   * review all moderation history, but article authors might be limited to
   * viewing only actions that directly affected their own articles. The
   * operation maintains transparency while respecting appropriate
   * confidentiality boundaries around moderation decisions.
   *
   * @param connection
   * @param articleId Unique identifier of the article whose moderation history
   *   is being retrieved
   * @param body Search criteria, filters, and pagination parameters for
   *   moderation history query
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardModerationLog.IRequest,
  ): Promise<IPageIDiscussionBoardModerationLog.ISummary> {
    try {
      return await patchDiscussionBoardModeratorArticlesArticleIdModerationHistory(
        {
          moderator,
          articleId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
