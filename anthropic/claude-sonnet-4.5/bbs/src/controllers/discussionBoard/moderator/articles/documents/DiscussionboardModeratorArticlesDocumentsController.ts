import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { postDiscussionBoardModeratorArticlesArticleIdDocuments } from "../../../../../providers/postDiscussionBoardModeratorArticlesArticleIdDocuments";
import { ModeratorAuth } from "../../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../../decorators/payload/ModeratorPayload";
import { deleteDiscussionBoardModeratorArticlesArticleIdDocumentsDocumentId } from "../../../../../providers/deleteDiscussionBoardModeratorArticlesArticleIdDocumentsDocumentId";

import { IDiscussionBoardArticleDocument } from "../../../../../api/structures/IDiscussionBoardArticleDocument";

@Controller("/discussionBoard/moderator/articles/:articleId/documents")
export class DiscussionboardModeratorArticlesDocumentsController {
  /**
   * Upload and attach document files to an article.
   *
   * Creates new document attachments for an existing article by uploading and
   * validating document files, then linking them to the parent article. This
   * operation enables article authors to enhance their economic and political
   * discussions with supporting materials such as PDF research papers, Word
   * documents with detailed analysis, or text files with supplementary data.
   *
   * The operation performs comprehensive validation on uploaded documents. Each
   * file is checked for format compatibility (must be PDF, DOCX, DOC, TXT, RTF,
   * or ODT), size constraints (maximum 10MB per document), and security threats
   * through malware scanning. Files are validated both by MIME type and actual
   * file content to prevent format spoofing. The system enforces article-level
   * limits, rejecting uploads that would exceed the maximum of 5 document
   * attachments per article or the total attachment size limit of 100MB across
   * all files and images.
   *
   * When validation passes, the system generates a unique storage filename to
   * prevent conflicts, stores the file securely, and creates a record in the
   * discussion_board_article_documents table. The record captures the original
   * filename for user display, the secure stored filename, file metadata (size,
   * MIME type), the uploader's member ID, and the creation timestamp. The
   * uploaded_by_member_id field tracks who added the document for
   * accountability and moderation purposes.
   *
   * Permissions are validated to ensure only the article author or moderators
   * can add documents to an article. Members can only attach documents to their
   * own articles, while moderators can attach documents to any article as part
   * of their content management capabilities. The operation returns the
   * complete document attachment information upon success, including the
   * generated document ID, stored metadata, and access URLs for downloading the
   * document.
   *
   * @param connection
   * @param articleId Unique identifier of the article to attach documents to
   * @param body Document file upload information including the file data and
   *   metadata for creating article document attachments
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardArticleDocument.ICreate,
  ): Promise<IDiscussionBoardArticleDocument> {
    try {
      return await postDiscussionBoardModeratorArticlesArticleIdDocuments({
        moderator,
        articleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a document attachment from an article.
   *
   * Permanently removes a document attachment from an article in the discussion
   * board. This operation allows article authors to remove documents they
   * uploaded, and moderators to remove any document for content management
   * purposes.
   *
   * The deletion process validates that the specified document belongs to the
   * specified article and that the requesting user has permission to delete it.
   * Members can only delete documents from their own articles, while moderators
   * can delete documents from any article as part of their content management
   * responsibilities.
   *
   * When a document is deleted, the system soft-deletes the record by setting
   * the deleted_at timestamp in the discussion_board_article_documents table.
   * The physical file is marked for cleanup and removed from storage. The
   * article's attachment list is immediately updated to reflect the removal,
   * and the total attachment size is recalculated.
   *
   * This operation is useful when users need to remove outdated supporting
   * materials, correct mistakenly uploaded files, or when moderators need to
   * remove attachments that violate community guidelines. The deletion is
   * immediate and the document becomes inaccessible to all users after the
   * operation completes.
   *
   * @param connection
   * @param articleId Unique identifier of the parent article that contains the
   *   document attachment
   * @param documentId Unique identifier of the specific document attachment to
   *   be deleted
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":documentId")
  public async erase(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedParam("documentId")
    documentId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteDiscussionBoardModeratorArticlesArticleIdDocumentsDocumentId(
        {
          moderator,
          articleId,
          documentId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
