import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchDiscussionBoardModeratorArticlesArticleIdReports } from "../../../../../providers/patchDiscussionBoardModeratorArticlesArticleIdReports";
import { ModeratorAuth } from "../../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../../decorators/payload/ModeratorPayload";

import { IPageIDiscussionBoardContentReport } from "../../../../../api/structures/IPageIDiscussionBoardContentReport";
import { IDiscussionBoardContentReport } from "../../../../../api/structures/IDiscussionBoardContentReport";

@Controller("/discussionBoard/moderator/articles/:articleId/reports")
export class DiscussionboardModeratorArticlesReportsController {
  /**
   * Retrieve a filtered and paginated list of content reports submitted against
   * a specific article in the discussion board.
   *
   * This operation allows moderators to view all reports that members have
   * submitted for a particular article, helping them understand community
   * concerns and prioritize moderation efforts. The operation queries the
   * discussion_board_content_reports table filtered by the specified article
   * ID, returning comprehensive report information including the reporting
   * member, violation category, detailed explanations, and resolution status.
   *
   * The request body supports advanced filtering capabilities including report
   * status (pending, reviewed, dismissed), report categories (Spam, Offensive
   * Content, Misinformation, Off-Topic, Other), date range filters for
   * submission and resolution timestamps, and search by reporter username.
   * Pagination parameters enable efficient navigation through large numbers of
   * reports, while sorting options allow ordering by submission date,
   * resolution date, or report category.
   *
   * Security considerations: This operation is restricted to moderators who
   * have permissions to review content reports. For moderator privacy and
   * security, the response abstracts moderator identity - specific moderator
   * information is excluded from the response and available only in system
   * audit logs. Reporter identity is included to provide context for moderation
   * decisions while maintaining appropriate confidentiality from article
   * authors.
   *
   * This operation integrates with the discussion_board_content_reports table
   * as defined in the Prisma schema, incorporating report fields including
   * report_category, report_details, status, resolution_notes, and timestamps.
   * Moderator-specific fields (resolved_by_moderator_id, resolver relation) are
   * excluded from the response for security. Related operations include POST
   * /articles/{articleId}/reports for creating new reports and moderator action
   * endpoints for resolving reports.
   *
   * @param connection
   * @param articleId Unique identifier of the article for which to retrieve
   *   content reports
   * @param body Search criteria, filters, and pagination parameters for content
   *   report retrieval
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardContentReport.IRequest,
  ): Promise<IPageIDiscussionBoardContentReport.ISummary> {
    try {
      return await patchDiscussionBoardModeratorArticlesArticleIdReports({
        moderator,
        articleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
