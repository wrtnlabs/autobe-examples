import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { deleteDiscussionBoardModeratorArticlesArticleIdCommentsCommentId } from "../../../../../providers/deleteDiscussionBoardModeratorArticlesArticleIdCommentsCommentId";
import { ModeratorAuth } from "../../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../../decorators/payload/ModeratorPayload";

import { IDiscussionBoardComment } from "../../../../../api/structures/IDiscussionBoardComment";

@Controller(
  "/discussionBoard/moderator/articles/:articleId/comments/:commentId",
)
export class DiscussionboardModeratorArticlesCommentsController {
  /**
   * Delete a comment from a discussion board article.
   *
   * Permanently remove a comment from a discussion board article.
   *
   * This operation allows registered members to delete their previously posted
   * comments on articles. The member must be the original author of the comment
   * to perform this deletion. Moderators have additional privileges to delete
   * any comment for moderation purposes, such as removing inappropriate content
   * or spam.
   *
   * Security: Only authenticated members can delete comments. Authorization
   * logic verifies that the requesting user is either the original comment
   * author or a moderator with deletion privileges. The operation performs a
   * hard delete, permanently removing the comment record from the database
   * without soft-delete preservation.
   *
   * Once deleted, the comment is immediately removed from the article's comment
   * thread and cannot be recovered. The deletion may affect comment threading
   * and reply structures if the deleted comment had child replies. The system
   * handles orphaned replies according to the business logic defined in the
   * requirements.
   *
   * Related operations: Create comment (POST /articles/{articleId}/comments),
   * Update comment (PUT /articles/{articleId}/comments/{commentId}), View
   * article with comments (GET /articles/{articleId}).
   *
   * @param connection
   * @param articleId Unique identifier of the target article containing the
   *   comment
   * @param commentId Unique identifier of the target comment to delete
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardComment> {
    try {
      return await deleteDiscussionBoardModeratorArticlesArticleIdCommentsCommentId(
        {
          moderator,
          articleId,
          commentId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
