import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { postDiscussionBoardModeratorArticlesArticleIdComments } from "../../../../../providers/postDiscussionBoardModeratorArticlesArticleIdComments";
import { ModeratorAuth } from "../../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../../decorators/payload/ModeratorPayload";
import { putDiscussionBoardModeratorArticlesArticleIdCommentsCommentId } from "../../../../../providers/putDiscussionBoardModeratorArticlesArticleIdCommentsCommentId";
import { deleteDiscussionBoardModeratorArticlesArticleIdCommentsCommentId } from "../../../../../providers/deleteDiscussionBoardModeratorArticlesArticleIdCommentsCommentId";

import { IDiscussionBoardComment } from "../../../../../api/structures/IDiscussionBoardComment";

@Controller("/discussionBoard/moderator/articles/:articleId/comments")
export class DiscussionboardModeratorArticlesCommentsController {
  /**
   * Create a new comment on a discussion board article.
   *
   * This operation enables authenticated members and moderators to post new
   * comments on articles within the discussion board system. Comments are the
   * primary mechanism for user engagement and discussion on economic and
   * political topics, allowing the community to respond to article content, ask
   * questions, and engage in substantive dialogue.
   *
   * The operation validates that the target article exists and is accessible,
   * verifies the user is authenticated as a member or moderator, and validates
   * the comment content meets length requirements (minimum 1 character, maximum
   * 5000 characters as specified in requirements). The comment is associated
   * with the article identified by the articleId path parameter and attributed
   * to the authenticated user through the author_type discriminator field and
   * corresponding discussion_board_member_id or discussion_board_moderator_id
   * foreign key.
   *
   * Upon successful creation, the comment appears immediately in the article's
   * comment thread without requiring moderation approval. The system
   * automatically records the creation timestamp, sets the comment status to
   * active, and increments the parent article's comment_count metadata.
   * Comments support single-level threading through the
   * discussion_board_parent_comment_id field, allowing replies to top-level
   * comments while maintaining simplicity by preventing deeply nested
   * conversation threads.
   *
   * Security considerations include authentication verification to prevent
   * unauthenticated posting, input sanitization to prevent XSS attacks, rate
   * limiting to prevent spam (members limited to reasonable posting frequency),
   * and content validation to ensure meaningful contributions. The operation
   * respects the article's publication status, allowing comments only on
   * published articles, not drafts or deleted content.
   *
   * Related operations include GET /articles/{articleId}/comments for
   * retrieving comment threads, PUT /comments/{commentId} for editing own
   * comments, and DELETE /comments/{commentId} for removing comments. This
   * operation is fundamental to the discussion board's core value proposition
   * of enabling evidence-based discourse on economic and political topics.
   *
   * @param connection
   * @param articleId Unique identifier of the target article where the comment
   *   will be posted
   * @param body Comment content and threading information for creating a new
   *   comment on the article
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardComment.ICreate,
  ): Promise<IDiscussionBoardComment> {
    try {
      return await postDiscussionBoardModeratorArticlesArticleIdComments({
        moderator,
        articleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing comment on a discussion board article.
   *
   * This operation enables members and moderators to edit the content of
   * existing comments on discussion board articles. The comment system supports
   * single-level threading where comments can be direct responses to articles
   * (top-level comments) or replies to other top-level comments.
   *
   * When a user edits a comment, the system validates that they have
   * appropriate permissions - either they are the original author of the
   * comment, or they are a moderator with elevated privileges. Members can only
   * edit their own comments, while moderators can edit any comment regardless
   * of authorship. The system validates the updated content against the same
   * rules as comment creation: minimum 1 character, maximum 5000 characters,
   * with sanitization to prevent XSS attacks.
   *
   * The operation updates the comment content in the discussion_board_comments
   * table, sets the updated_at timestamp to the current time, and creates a new
   * snapshot in discussion_board_comment_snapshots to preserve the edit
   * history. This ensures a complete audit trail of all comment modifications.
   * If the edit is performed by a moderator on another user's comment, this
   * moderation action is logged in the discussion_board_moderation_actions
   * table.
   *
   * The updated comment is returned immediately to the user and displayed with
   * an 'edited' indicator to maintain transparency about content modifications.
   * Comment edits do not affect the comment's position in the thread or its
   * relationship to parent articles or parent comments. The operation maintains
   * referential integrity with the parent article and optional parent comment
   * throughout the update process.
   *
   * @param connection
   * @param articleId Unique identifier of the parent article that contains the
   *   comment being updated
   * @param commentId Unique identifier of the specific comment to be updated
   * @param body Updated comment content and metadata for the comment
   *   modification
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":commentId")
  public async update(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardComment.IUpdate,
  ): Promise<IDiscussionBoardComment> {
    try {
      return await putDiscussionBoardModeratorArticlesArticleIdCommentsCommentId(
        {
          moderator,
          articleId,
          commentId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Soft-delete a comment from a discussion board article.
   *
   * This operation allows members and moderators to remove comments from
   * discussion board articles by performing a soft deletion. The comment system
   * maintains data integrity and audit trails by marking comments as deleted
   * rather than permanently removing them from the database.
   *
   * When a user deletes a comment, the system validates appropriate permissions
   * - either the user is the original comment author, or they are a moderator
   * with elevated privileges to manage any content. Members can only delete
   * their own comments, while moderators can delete any comment to enforce
   * community guidelines and maintain discussion quality.
   *
   * The deletion process sets the deleted_at timestamp in the
   * discussion_board_comments table to the current time, effectively hiding the
   * comment from public view while preserving the record for moderation review
   * and audit purposes. The soft-deleted comment remains in the database for
   * historical tracking, compliance requirements, and potential recovery
   * scenarios. The comment content is retained but marked as deleted, and it no
   * longer appears in comment listings or search results for regular users.
   *
   * For comments with single-level threading, when a top-level comment is
   * deleted, all its nested replies are also hidden from public view to
   * maintain thread coherence. The system maintains referential integrity
   * throughout the deletion process, ensuring that the parent article's
   * comment_count is decremented to reflect the hidden comment. If the deletion
   * is performed by a moderator on another user's comment, this action is
   * logged in the discussion_board_moderation_actions table with the reason and
   * details for accountability and transparency.
   *
   * @param connection
   * @param articleId Unique identifier of the parent article that contains the
   *   comment being deleted
   * @param commentId Unique identifier of the specific comment to be
   *   soft-deleted
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":commentId")
  public async erase(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardComment> {
    try {
      return await deleteDiscussionBoardModeratorArticlesArticleIdCommentsCommentId(
        {
          moderator,
          articleId,
          commentId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
