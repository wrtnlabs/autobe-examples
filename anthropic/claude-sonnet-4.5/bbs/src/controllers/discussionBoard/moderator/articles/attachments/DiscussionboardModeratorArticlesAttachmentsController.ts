import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { postDiscussionBoardModeratorArticlesArticleIdAttachments } from "../../../../../providers/postDiscussionBoardModeratorArticlesArticleIdAttachments";
import { ModeratorAuth } from "../../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../../decorators/payload/ModeratorPayload";

import { IDiscussionBoardArticleAttachment } from "../../../../../api/structures/IDiscussionBoardArticleAttachment";

@Controller("/discussionBoard/moderator/articles/:articleId/attachments")
export class DiscussionboardModeratorArticlesAttachmentsController {
  /**
   * Create a new attachment for a discussion board article.
   *
   * Upload and attach a new image or document file to an existing discussion
   * board article. This operation allows authenticated members to add
   * supporting materials, visual evidence, charts, documents, and reference
   * materials to their economic and political discussions.
   *
   * The operation validates file type, size, and security constraints before
   * creating the attachment record. Image attachments support JPEG, PNG, GIF,
   * and WebP formats with a maximum size of 5 MB each, and articles can have up
   * to 10 image attachments. Document attachments support PDF, DOC, DOCX, XLS,
   * XLSX, TXT, and CSV formats with a maximum size of 10 MB each, and articles
   * can have up to 5 document attachments. The combined total attachment size
   * per article cannot exceed 25 MB.
   *
   * Security validation includes file type verification by examining content
   * headers (not just extensions), malware scanning, and metadata stripping to
   * protect user privacy. The system generates unique storage paths and
   * sanitizes filenames to prevent security vulnerabilities. Only the article
   * author or moderators can add attachments to an article.
   *
   * The attachment is immediately associated with the parent article and
   * becomes visible when the article is viewed. The operation records the
   * member who uploaded the attachment for attribution and audit purposes. All
   * attachment uploads are subject to the business rules defined in the
   * attachment validation requirements including type restrictions, size
   * limits, and quantity constraints.
   *
   * @param connection
   * @param articleId Unique identifier of the target article to attach the file
   *   to
   * @param body Attachment creation data including file information and
   *   metadata
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardArticleAttachment.ICreate,
  ): Promise<IDiscussionBoardArticleAttachment> {
    try {
      return await postDiscussionBoardModeratorArticlesArticleIdAttachments({
        moderator,
        articleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
