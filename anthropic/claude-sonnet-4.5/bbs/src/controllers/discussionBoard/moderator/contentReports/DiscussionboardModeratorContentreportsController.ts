import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchDiscussionBoardModeratorContentReports } from "../../../../providers/patchDiscussionBoardModeratorContentReports";
import { ModeratorAuth } from "../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../decorators/payload/ModeratorPayload";
import { getDiscussionBoardModeratorContentReportsReportId } from "../../../../providers/getDiscussionBoardModeratorContentReportsReportId";
import { putDiscussionBoardModeratorContentReportsReportId } from "../../../../providers/putDiscussionBoardModeratorContentReportsReportId";
import { deleteDiscussionBoardModeratorContentReportsReportId } from "../../../../providers/deleteDiscussionBoardModeratorContentReportsReportId";

import { IPageIDiscussionBoardContentReport } from "../../../../api/structures/IPageIDiscussionBoardContentReport";
import { IDiscussionBoardContentReport } from "../../../../api/structures/IDiscussionBoardContentReport";

@Controller("/discussionBoard/moderator/contentReports")
export class DiscussionboardModeratorContentreportsController {
  /**
   * Retrieves a paginated list of content reports submitted by members, with
   * advanced filtering and search capabilities for efficient moderation
   * workflow management.
   *
   * This operation is exclusively available to moderators who need to review
   * community-submitted reports about potentially problematic articles. The
   * endpoint supports comprehensive filtering to help moderators prioritize and
   * manage the moderation queue effectively.
   *
   * Filtering capabilities include report status (pending, reviewed_no_action,
   * reviewed_edited, reviewed_removed), report category (Spam, Offensive
   * Content, Misinformation, Off-Topic, Other), date ranges for submission
   * time, specific articles being reported, and specific members who submitted
   * reports. Multiple filters can be combined to narrow down results
   * precisely.
   *
   * The response includes complete report information: reporting member
   * details, reported article summary, selected violation category, optional
   * detailed explanation from the reporter, current resolution status, and
   * resolution details if the report has been reviewed. This comprehensive data
   * enables moderators to understand context and make informed moderation
   * decisions.
   *
   * Results are paginated with configurable page size (default 20 reports per
   * page) and support sorting by submission date, resolution date, or report
   * priority. Articles with multiple reports are typically prioritized higher
   * in default sorting to surface content requiring urgent attention.
   *
   * Security: This endpoint requires moderator authentication and
   * authorization. Regular members and guests cannot access content reports.
   * The operation returns reports across all articles regardless of authorship,
   * providing moderators with system-wide visibility.
   *
   * Related operations: After reviewing reports through this endpoint,
   * moderators typically use article editing operations to modify content,
   * article deletion operations to remove violating content, or report
   * resolution operations to mark reports as reviewed. The moderation workflow
   * integrates tightly with article management operations.
   *
   * @param connection
   * @param body Search and filter criteria for content reports including
   *   status, category, date ranges, and pagination parameters
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedBody()
    body: IDiscussionBoardContentReport.IRequest,
  ): Promise<IPageIDiscussionBoardContentReport.ISummary> {
    try {
      return await patchDiscussionBoardModeratorContentReports({
        moderator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific content report submitted by
   * a member flagging an article for policy violations.
   *
   * This operation returns comprehensive details about a single content report,
   * including the violation category selected by the reporter, optional
   * detailed explanation, current resolution status (pending,
   * reviewed_no_action, reviewed_edited, reviewed_removed), moderator
   * resolution notes if reviewed, and all relevant timestamps. The response
   * includes relationships to the reported article, reporting member, and
   * resolving moderator if applicable.
   *
   * Security considerations include access control based on user role.
   * Moderators can view any content report to perform their review duties.
   * Members can only view reports they personally submitted to track resolution
   * status. Guest users have no access to content reports. The operation
   * validates that the requesting user has appropriate permissions before
   * returning report data.
   *
   * This operation integrates with the discussion_board_content_reports table
   * as defined in the Prisma schema. The response includes the report's current
   * status in the moderation workflow, enabling moderators to prioritize
   * pending reports and allowing reporting members to see how their concerns
   * were addressed. Reports track the complete lifecycle from submission
   * through moderator review to final resolution.
   *
   * @param connection
   * @param reportId Unique identifier of the target content report
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":reportId")
  public async at(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("reportId")
    reportId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardContentReport> {
    try {
      return await getDiscussionBoardModeratorContentReportsReportId({
        moderator,
        reportId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Updates an existing content report with moderator resolution details after
   * reviewing the reported article. This operation allows moderators to mark
   * reports as resolved by updating the status field to indicate their decision
   * (reviewed_no_action, reviewed_edited, or reviewed_removed) and recording
   * resolution notes explaining the reasoning.
   *
   * The operation sets the resolved_by_moderator_id to the authenticated
   * moderator's ID and records the resolved_at timestamp automatically.
   * Resolution notes provide transparency to the reporting member about why
   * their report was handled in a specific manner, supporting accountability in
   * the moderation process.
   *
   * Security: Only authenticated moderators can update content reports. The
   * system validates that the report exists and is in pending status before
   * allowing updates. Once resolved, reports cannot be modified again to
   * maintain audit trail integrity.
   *
   * Business rules from requirements specify that moderators must provide
   * resolution notes when marking reports as resolved. The status must
   * transition from 'pending' to one of the valid resolved states. Multiple
   * reports for the same article are handled independently, with each requiring
   * separate moderator review.
   *
   * This operation integrates with the moderation workflow where moderators
   * review flagged content from the moderation queue, take appropriate action
   * on the reported article (via separate article management APIs), then use
   * this endpoint to close the report with their decision recorded.
   *
   * @param connection
   * @param reportId Unique identifier of the content report to update
   * @param body Updated resolution status, notes, and moderator decision for
   *   the content report
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":reportId")
  public async update(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("reportId")
    reportId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardContentReport.IUpdate,
  ): Promise<IDiscussionBoardContentReport> {
    try {
      return await putDiscussionBoardModeratorContentReportsReportId({
        moderator,
        reportId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently removes a content report from the discussion board moderation
   * system. This operation completely deletes the report record from the
   * database, removing it from the moderation queue and all audit trails.
   *
   * Moderators use this endpoint to clean up invalid or duplicate reports. For
   * example, if a member accidentally submits the same report multiple times,
   * or if a report was made in error about content that clearly doesn't violate
   * guidelines, moderators can delete the redundant report rather than marking
   * it as reviewed.
   *
   * Security: Only authenticated moderators have permission to delete content
   * reports. The operation validates that the report exists before attempting
   * deletion. Once deleted, the report cannot be recovered.
   *
   * Best practices recommend using the update operation to mark reports as
   * 'reviewed_no_action' rather than deleting them, as this preserves the audit
   * trail and provides transparency to the reporting member. Deletion should be
   * reserved for truly invalid reports or system cleanup scenarios.
   *
   * The operation removes only the report record itself - it does not affect
   * the reported article or the member who submitted the report. If the same
   * article has multiple reports from different members, each report is handled
   * independently.
   *
   * @param connection
   * @param reportId Unique identifier of the content report to delete
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":reportId")
  public async erase(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("reportId")
    reportId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteDiscussionBoardModeratorContentReportsReportId({
        moderator,
        reportId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
