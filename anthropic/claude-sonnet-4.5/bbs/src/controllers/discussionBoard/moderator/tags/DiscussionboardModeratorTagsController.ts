import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia from "typia";
import { postDiscussionBoardModeratorTags } from "../../../../providers/postDiscussionBoardModeratorTags";
import { ModeratorAuth } from "../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../decorators/payload/ModeratorPayload";
import { putDiscussionBoardModeratorTagsTagSlug } from "../../../../providers/putDiscussionBoardModeratorTagsTagSlug";
import { deleteDiscussionBoardModeratorTagsTagSlug } from "../../../../providers/deleteDiscussionBoardModeratorTagsTagSlug";

import { IDiscussionBoardTag } from "../../../../api/structures/IDiscussionBoardTag";

@Controller("/discussionBoard/moderator/tags")
export class DiscussionboardModeratorTagsController {
  /**
   * Create a new tag for article categorization and content discovery.
   *
   * Creates a new tag in the discussion board system to enable flexible topic
   * labeling and content discovery. Tags provide granular, user-generated
   * keywords that complement the formal category structure, allowing detailed
   * filtering on economic and political discussion topics such as
   * monetary-policy, climate-change, or taxation.
   *
   * The operation validates that the tag name is unique across the system,
   * normalizes the name to lowercase to prevent duplicate tags with different
   * capitalization, and generates a URL-friendly slug derived from the tag
   * name. The slug is used in routes and tag browsing pages for SEO-friendly
   * URLs.
   *
   * This operation stores the new tag in the discussion_board_tags table with
   * creation and update timestamps automatically recorded. Once created, the
   * tag becomes available for members and moderators to apply to articles
   * through the article creation and editing workflows. Tags enhance content
   * discoverability by enabling users to search, filter, and browse articles by
   * specific topics beyond the primary category taxonomy.
   *
   * @param connection
   * @param body Tag creation data including the tag name and optionally a
   *   custom slug
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedBody()
    body: IDiscussionBoardTag.ICreate,
  ): Promise<IDiscussionBoardTag> {
    try {
      return await postDiscussionBoardModeratorTags({
        moderator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing tag's properties by its slug identifier.
   *
   * Updates an existing tag in the discussion board system identified by its
   * unique slug. Tags provide granular, user-generated keywords that complement
   * the formal category structure, enabling detailed content filtering and
   * discovery on economic and political topics.
   *
   * The operation allows moderators to modify tag properties including the tag
   * name and potentially the slug. When the tag name is updated, the system
   * validates that the new name is unique across all tags, normalizes it to
   * lowercase to prevent duplicate tags with different capitalization, and
   * regenerates the URL-friendly slug if necessary. All articles currently
   * associated with this tag through the discussion_board_article_tags junction
   * table maintain their relationship, ensuring continuity of tag-based content
   * organization.
   *
   * This operation updates the tag record in the discussion_board_tags table
   * with the updated_at timestamp automatically recorded to track modification
   * history. Tag updates are typically performed by moderators to refine the
   * tag taxonomy, merge similar tags, correct naming inconsistencies, or
   * improve SEO-friendliness of tag slugs. The updated tag immediately reflects
   * in all article displays, tag browsing pages, and search interfaces
   * throughout the discussion board.
   *
   * @param connection
   * @param tagSlug URL-friendly slug identifier of the target tag (global
   *   scope)
   * @param body Updated tag information including modified name or slug
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":tagSlug")
  public async update(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("tagSlug")
    tagSlug: string,
    @TypedBody()
    body: IDiscussionBoardTag.IUpdate,
  ): Promise<IDiscussionBoardTag> {
    try {
      return await putDiscussionBoardModeratorTagsTagSlug({
        moderator,
        tagSlug,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a tag by its slug identifier.
   *
   * Permanently removes a tag from the discussion board tag system using its
   * URL-friendly slug identifier. This operation performs a hard delete,
   * completely removing the tag record from the discussion_board_tags table and
   * all associated article-tag relationships from the
   * discussion_board_article_tags junction table.
   *
   * This operation is designed for moderators who need to maintain the tag
   * taxonomy by removing tags that are unused, inappropriate, misspelled,
   * redundant, or violate community guidelines. When a tag is deleted, articles
   * that were tagged with it remain fully functional and retain all other tags
   * and categories, ensuring content integrity is preserved.
   *
   * The deletion cascades automatically to all article-tag associations,
   * meaning if a tag was applied to 100 articles, all 100 relationships are
   * removed atomically with the tag deletion. This maintains referential
   * integrity and prevents orphaned junction table records. Since the
   * discussion_board_tags schema does not include a deleted_at column, this is
   * a permanent deletion that cannot be recovered through the system - deleted
   * tags must be manually recreated if needed again.
   *
   * Security and authorization considerations are critical for this operation.
   * Only users with moderator privileges can delete tags, as tag removal
   * affects content organization across the entire platform and all users. The
   * operation requires the moderator to be authenticated with a valid JWT token
   * containing moderator role claims. Tag deletion should be logged in
   * moderation action audit trails to maintain accountability for tag
   * management decisions.
   *
   * This operation works in coordination with the tag-based content discovery
   * system specified in the Search and Discovery requirements. When a tag is
   * deleted, any active user browsing or searching by that tag should receive
   * appropriate feedback that the tag no longer exists, with suggestions to
   * browse other related tags or categories.
   *
   * @param connection
   * @param tagSlug URL-friendly slug identifier of the tag to delete (global
   *   scope)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":tagSlug")
  public async erase(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("tagSlug")
    tagSlug: string,
  ): Promise<void> {
    try {
      return await deleteDiscussionBoardModeratorTagsTagSlug({
        moderator,
        tagSlug,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
