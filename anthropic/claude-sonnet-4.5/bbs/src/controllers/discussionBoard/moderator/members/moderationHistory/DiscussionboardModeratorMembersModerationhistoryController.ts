import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchDiscussionBoardModeratorMembersMemberIdModerationHistory } from "../../../../../providers/patchDiscussionBoardModeratorMembersMemberIdModerationHistory";
import { ModeratorAuth } from "../../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../../decorators/payload/ModeratorPayload";

import { IPageIDiscussionBoardModerationLog } from "../../../../../api/structures/IPageIDiscussionBoardModerationLog";
import { IDiscussionBoardModerationLog } from "../../../../../api/structures/IDiscussionBoardModerationLog";

@Controller("/discussionBoard/moderator/members/:memberId/moderationHistory")
export class DiscussionboardModeratorMembersModerationhistoryController {
  /**
   * Retrieve paginated moderation history for a specific member account.
   *
   * Retrieve a comprehensive, paginated history of all moderation actions taken
   * against a specific member account. This operation provides moderators with
   * complete visibility into a member's enforcement history, including both
   * content moderation actions (article edits, deletions, attachment removals)
   * and account-level actions (suspensions, bans, restorations).
   *
   * The moderation history combines data from the
   * discussion_board_moderation_logs table (which tracks content-level
   * moderator actions) and the discussion_board_account_actions table (which
   * records suspensions and bans). Each entry includes the action type, the
   * moderator who performed the action, timestamps, documented reasons, and
   * current status. This comprehensive view enables moderators to make informed
   * decisions about escalating enforcement based on violation patterns.
   *
   * Security and authorization: Only authenticated moderators can access
   * moderation history. The system validates that the requesting user has
   * moderator privileges before returning sensitive enforcement data. Member
   * accounts cannot view their own or others' moderation history to prevent
   * gaming of the enforcement system.
   *
   * The operation supports complex filtering by action type, date range,
   * moderator, and status to help moderators answer questions like "How many
   * times has this member been warned?", "What violations led to previous
   * suspensions?", or "Which moderator handled the most recent incident?".
   * Pagination ensures performance when members have extensive moderation
   * histories. Results are sorted chronologically by default (newest first) to
   * surface the most recent enforcement actions.
   *
   * This operation is essential for progressive enforcement workflows where
   * moderators review past violations before deciding on appropriate action
   * severity (warning → temporary suspension → extended suspension → permanent
   * ban). The documented reasons and action details provide context for appeals
   * and dispute resolution.
   *
   * Related operations: This operation should be used before applying new
   * moderation actions via account suspension endpoints. It helps moderators
   * understand the full context of a member's behavior patterns and enforcement
   * history.
   *
   * @param connection
   * @param memberId Unique identifier of the target member whose moderation
   *   history is being retrieved
   * @param body Search and filtering criteria for moderation history including
   *   action type filters, date ranges, moderator filters, and pagination
   *   parameters
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("memberId")
    memberId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardModerationLog.IRequest,
  ): Promise<IPageIDiscussionBoardModerationLog.ISummary> {
    try {
      return await patchDiscussionBoardModeratorMembersMemberIdModerationHistory(
        {
          moderator,
          memberId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
