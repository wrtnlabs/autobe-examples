import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchDiscussionBoardModeratorMembersMemberIdAccountActions } from "../../../../../providers/patchDiscussionBoardModeratorMembersMemberIdAccountActions";
import { ModeratorAuth } from "../../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../../decorators/payload/ModeratorPayload";
import { getDiscussionBoardModeratorMembersMemberIdAccountActionsActive } from "../../../../../providers/getDiscussionBoardModeratorMembersMemberIdAccountActionsActive";

import { IPageIDiscussionBoardAccountAction } from "../../../../../api/structures/IPageIDiscussionBoardAccountAction";
import { IDiscussionBoardAccountAction } from "../../../../../api/structures/IDiscussionBoardAccountAction";

@Controller("/discussionBoard/moderator/members/:memberId/accountActions")
export class DiscussionboardModeratorMembersAccountactionsController {
  /**
   * Retrieve a filtered and paginated list of all account-level moderation
   * actions (suspensions and bans) applied to a specific member account. This
   * operation provides comprehensive access to the member's disciplinary
   * history tracked in the discussion_board_account_actions table.
   *
   * The operation supports complex search and filtering capabilities including
   * action type (suspension vs ban), current status (active, expired,
   * reversed), date range filtering, and moderator identity. This enables
   * moderators and administrators to review the complete enforcement history
   * for a member account, understand patterns of violations, and make informed
   * decisions about escalating or de-escalating disciplinary measures.
   *
   * Security and authorization: Only moderators can access this endpoint to
   * review member moderation history. The member_id path parameter identifies
   * which member's action history to retrieve, ensuring proper scoping of
   * results. All suspension and ban records associated with the specified
   * member are searchable through the request body filter criteria.
   *
   * The response includes detailed information about each action including the
   * moderator who applied it, the reason documented, duration (for
   * suspensions), current status, and any reversal information. This
   * transparency supports accountability in moderation decisions and enables
   * dispute resolution through complete audit trail visibility.
   *
   * Related operations: This operation should be used in conjunction with GET
   * /members/{memberId}/accountActions/active to first check if the member has
   * any currently active enforcement actions before reviewing the complete
   * history.
   *
   * @param connection
   * @param memberId Unique identifier of the target member whose account action
   *   history is being retrieved
   * @param body Search and filter criteria for account actions including
   *   pagination, sorting, and filtering by action type, status, and date
   *   ranges
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("memberId")
    memberId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardAccountAction.IRequest,
  ): Promise<IPageIDiscussionBoardAccountAction.ISummary> {
    try {
      return await patchDiscussionBoardModeratorMembersMemberIdAccountActions({
        moderator,
        memberId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve the currently active account-level moderation action (suspension
   * or ban) applied to a specific member, if one exists. This operation
   * provides quick access to determine whether a member is currently under
   * enforcement action and the details of that restriction.
   *
   * The operation queries the discussion_board_account_actions table filtering
   * for the specified member and status 'active'. Only one account action can
   * be active at a time for any member (a member cannot be simultaneously
   * suspended and banned, or have multiple overlapping suspensions). If an
   * active action exists, the complete details are returned including action
   * type, reason, moderator who applied it, duration, and expiration
   * information.
   *
   * Security and authorization: Moderators use this endpoint to quickly check a
   * member's current enforcement status before taking additional moderation
   * actions or when investigating user reports. The member_id path parameter
   * ensures results are properly scoped to the specific member being reviewed.
   *
   * Business logic: This operation is particularly useful for login workflows
   * (checking if member can authenticate), content creation workflows
   * (verifying member can post), and moderation workflows (understanding
   * current restrictions before applying new ones). If no active action exists,
   * the response will be null indicating the member account has no current
   * restrictions.
   *
   * The response includes the moderator who applied the action, documented
   * reason, duration (for temporary suspensions), expiration timestamp, and
   * action type. For permanent bans, the expires_at field will be null. For
   * temporary suspensions, the system automatically updates status to 'expired'
   * when the expiration timestamp is reached.
   *
   * Related operations: Use PATCH /members/{memberId}/accountActions to
   * retrieve the complete history of all actions (active, expired, and
   * reversed) for comprehensive moderation review.
   *
   * @param connection
   * @param memberId Unique identifier of the target member whose active account
   *   action status is being checked
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get("active")
  public async active(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("memberId")
    memberId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardAccountAction> {
    try {
      return await getDiscussionBoardModeratorMembersMemberIdAccountActionsActive(
        {
          moderator,
          memberId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
