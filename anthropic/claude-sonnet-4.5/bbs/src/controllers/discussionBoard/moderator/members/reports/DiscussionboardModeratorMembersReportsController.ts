import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchDiscussionBoardModeratorMembersMemberIdReports } from "../../../../../providers/patchDiscussionBoardModeratorMembersMemberIdReports";
import { ModeratorAuth } from "../../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../../decorators/payload/ModeratorPayload";

import { IPageIDiscussionBoardContentReport } from "../../../../../api/structures/IPageIDiscussionBoardContentReport";
import { IDiscussionBoardContentReport } from "../../../../../api/structures/IDiscussionBoardContentReport";

@Controller("/discussionBoard/moderator/members/:memberId/reports")
export class DiscussionboardModeratorMembersReportsController {
  /**
   * Retrieve a filtered and paginated list of content reports submitted by a
   * specific discussion board member. This operation provides comprehensive
   * search capabilities for analyzing member reporting behavior, tracking
   * report resolution status, and identifying members who frequently report
   * content.
   *
   * The operation supports complex filtering including report category (Spam,
   * Offensive Content, Misinformation, Off-Topic, Other), resolution status
   * (pending, reviewed_no_action, reviewed_edited, reviewed_removed), date
   * ranges for submission and resolution timestamps, and text search within
   * report details. Results can be sorted by creation date, resolution date, or
   * status to prioritize review workflows.
   *
   * Security considerations: This operation requires moderator or administrator
   * authorization as it exposes member reporting patterns and potentially
   * sensitive report details. The response includes the reporting member's
   * information, reported article references, resolution status, and moderator
   * notes for resolved reports. Rate limiting applies to prevent abuse of
   * search functionality.
   *
   * The operation integrates with the discussion_board_content_reports table
   * and joins with related discussion_board_articles and
   * discussion_board_moderators tables to provide complete context. This
   * enables moderators to understand reporting patterns, identify potential
   * abuse of the reporting system, and review the complete history of a
   * member's community moderation participation.
   *
   * @param connection
   * @param memberId Unique identifier of the member whose submitted reports
   *   should be retrieved
   * @param body Search criteria, filtering options, sorting preferences, and
   *   pagination parameters for member's content reports
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("memberId")
    memberId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardContentReport.IRequest,
  ): Promise<IPageIDiscussionBoardContentReport.ISummary> {
    try {
      return await patchDiscussionBoardModeratorMembersMemberIdReports({
        moderator,
        memberId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
