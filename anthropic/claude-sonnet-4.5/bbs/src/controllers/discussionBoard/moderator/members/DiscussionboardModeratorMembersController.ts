import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchDiscussionBoardModeratorMembers } from "../../../../providers/patchDiscussionBoardModeratorMembers";
import { ModeratorAuth } from "../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../decorators/payload/ModeratorPayload";
import { getDiscussionBoardModeratorMembersMemberId } from "../../../../providers/getDiscussionBoardModeratorMembersMemberId";

import { IPageIDiscussionBoardMember } from "../../../../api/structures/IPageIDiscussionBoardMember";
import { IDiscussionBoardMember } from "../../../../api/structures/IDiscussionBoardMember";

@Controller("/discussionBoard/moderator/members")
export class DiscussionboardModeratorMembersController {
  /**
   * Search and retrieve a filtered, paginated list of discussion board members.
   *
   * Retrieve a filtered and paginated list of registered discussion board
   * members from the system. This operation provides advanced search
   * capabilities for finding members based on multiple criteria including
   * partial username matching, email filtering, registration date ranges, and
   * account status.
   *
   * The operation supports comprehensive pagination with configurable page
   * sizes and sorting options. Results can be sorted by registration date,
   * username, or other relevant fields in ascending or descending order. This
   * is essential for administrative oversight and member management tasks.
   *
   * Security considerations include appropriate filtering of sensitive member
   * information based on the requesting user's authorization level. Only users
   * with moderator or administrator permissions can access detailed member
   * information and perform comprehensive searches. The operation implements
   * rate limiting to prevent abuse and ensures that personal data is handled
   * according to privacy requirements.
   *
   * This operation integrates with the discussion_board_members table as
   * defined in the Prisma schema, incorporating all available member fields and
   * relationships. The response includes member summary information optimized
   * for list displays, with options to include additional details based on
   * authorization level.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for member filtering,
   *   including username patterns, registration date ranges, and sorting
   *   preferences
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedBody()
    body: IDiscussionBoardMember.IRequest,
  ): Promise<IPageIDiscussionBoardMember.ISummary> {
    try {
      return await patchDiscussionBoardModeratorMembers({
        moderator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific discussion board member.
   *
   * Retrieve complete profile information for a specific registered discussion
   * board member identified by their unique member ID. This operation returns
   * comprehensive member details including username, email, registration
   * timestamp, account status, and any associated profile metadata.
   *
   * The operation serves multiple purposes: allowing moderators to review
   * member accounts for moderation purposes, enabling administrators to manage
   * user accounts, and potentially allowing members to view their own profile
   * information. The level of detail returned depends on the authorization
   * level of the requesting user.
   *
   * Security is enforced through proper authorization checks. Moderators and
   * administrators can access full member details for oversight and management
   * purposes. Members may be able to access their own profile information when
   * authenticated. Sensitive information such as password hashes is never
   * included in the response.
   *
   * This operation integrates with the discussion_board_members table as
   * defined in the Prisma schema, returning a complete member entity with all
   * non-sensitive fields. The response structure supports both administrative
   * use cases and potential member self-service scenarios.
   *
   * @param connection
   * @param memberId Unique identifier of the target discussion board member
   *   (global scope)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":memberId")
  public async at(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("memberId")
    memberId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardMember> {
    try {
      return await getDiscussionBoardModeratorMembersMemberId({
        moderator,
        memberId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
