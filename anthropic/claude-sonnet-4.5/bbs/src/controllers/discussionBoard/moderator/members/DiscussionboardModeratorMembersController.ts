import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchDiscussionBoardModeratorMembers } from "../../../../providers/patchDiscussionBoardModeratorMembers";
import { ModeratorAuth } from "../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../decorators/payload/ModeratorPayload";
import { getDiscussionBoardModeratorMembersMemberId } from "../../../../providers/getDiscussionBoardModeratorMembersMemberId";

import { IPageIDiscussionBoardMember } from "../../../../api/structures/IPageIDiscussionBoardMember";
import { IDiscussionBoardMember } from "../../../../api/structures/IDiscussionBoardMember";

@Controller("/discussionBoard/moderator/members")
export class DiscussionboardModeratorMembersController {
  /**
   * Retrieve a comprehensive list of discussion board members with advanced
   * filtering, searching, and pagination capabilities. This operation queries
   * the discussion_board_members table and returns member summary information
   * suitable for administrative review and member management.
   *
   * The operation supports filtering by multiple criteria including email
   * verification status (email_verified field), account suspension status
   * (is_suspended field), registration date ranges (created_at field), and last
   * login activity (last_login_at field). Text search capabilities allow
   * finding members by username or display_name using partial matching with
   * case-insensitive comparison. Email addresses are included in the summary
   * results for moderators to support administrative functions and member
   * management. This personally identifiable information should be protected
   * according to data protection regulations.
   *
   * Security and authorization considerations: This operation is restricted to
   * moderators only, as it provides access to member account information
   * including email addresses, suspension status, and activity timestamps. The
   * password field from the Prisma schema is never included in response data
   * for security reasons. Pagination is mandatory to handle potentially large
   * member datasets efficiently.
   *
   * The response includes member summary data optimized for list displays,
   * excluding sensitive authentication credentials while providing sufficient
   * information for account management and moderation decisions. Results are
   * ordered by created_at timestamp in descending order by default, showing
   * newest members first.
   *
   * Related operations: Individual member details can be retrieved using GET
   * /discussionBoard/moderator/members/{memberId} for complete profile
   * information. This search operation should be used first to identify members
   * of interest before accessing detailed records.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for member filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedBody()
    body: IDiscussionBoardMember.IRequest,
  ): Promise<IPageIDiscussionBoardMember.ISummary> {
    try {
      return await patchDiscussionBoardModeratorMembers({
        moderator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve complete profile and account information for an individual
   * discussion board member identified by their unique member ID. This
   * operation queries the discussion_board_members table and returns
   * comprehensive member details suitable for profile viewing and moderation
   * review.
   *
   * The operation returns all non-sensitive member information including the
   * username field (unique public identifier), display_name field (optional
   * public display name), bio field (member biography up to 500 characters),
   * avatar_url field (profile picture URL), email_verified field and
   * email_verified_at timestamp (verification status), is_suspended field with
   * suspension_reason and suspended_until fields (suspension status),
   * last_login_at timestamp (activity tracking), and created_at/updated_at
   * timestamps (account lifecycle). The email field is included for moderators
   * to support administrative functions and member support.
   *
   * Security and authorization: This operation is accessible to moderators for
   * full administrative oversight. For security reasons, the password field is
   * excluded from the response even for moderators. Only hashed passwords are
   * stored in the database, but they are never transmitted via API responses
   * under any circumstances. Suspended members and members with deleted_at
   * timestamps set are still retrievable by moderators for review and potential
   * restoration.
   *
   * The response provides complete member profile data including verification
   * status, suspension status, and activity history. This detailed view
   * supports moderation decisions, member support inquiries, and profile
   * management. If the member ID does not exist or references a permanently
   * deleted account beyond the retention period, the operation returns a not
   * found error.
   *
   * Related operations: Use PATCH /discussionBoard/moderator/members to search
   * and filter members before retrieving individual details. Member account
   * updates would use PUT /discussionBoard/moderator/members/{memberId} if such
   * an operation exists.
   *
   * @param connection
   * @param memberId Unique identifier of the target member
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":memberId")
  public async at(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("memberId")
    memberId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardMember> {
    try {
      return await getDiscussionBoardModeratorMembersMemberId({
        moderator,
        memberId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
