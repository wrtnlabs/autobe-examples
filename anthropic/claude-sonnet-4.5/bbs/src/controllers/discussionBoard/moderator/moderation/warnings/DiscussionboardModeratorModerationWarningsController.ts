import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postDiscussionBoardModeratorModerationWarnings } from "../../../../../providers/postDiscussionBoardModeratorModerationWarnings";
import { ModeratorAuth } from "../../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../../decorators/payload/ModeratorPayload";
import { patchDiscussionBoardModeratorModerationWarnings } from "../../../../../providers/patchDiscussionBoardModeratorModerationWarnings";
import { getDiscussionBoardModeratorModerationWarningsWarningId } from "../../../../../providers/getDiscussionBoardModeratorModerationWarningsWarningId";
import { putDiscussionBoardModeratorModerationWarningsWarningId } from "../../../../../providers/putDiscussionBoardModeratorModerationWarningsWarningId";
import { deleteDiscussionBoardModeratorModerationWarningsWarningId } from "../../../../../providers/deleteDiscussionBoardModeratorModerationWarningsWarningId";

import { IDiscussionBoardUserWarning } from "../../../../../api/structures/IDiscussionBoardUserWarning";
import { IPageIDiscussionBoardUserWarning } from "../../../../../api/structures/IPageIDiscussionBoardUserWarning";

@Controller("/discussionBoard/moderator/moderation/warnings")
export class DiscussionboardModeratorModerationWarningsController {
  /**
   * Issue a new warning to a member for community guideline violations.
   *
   * Creates a new warning record for a member user who has violated community
   * guidelines or policies on the discussion board. This operation is part of
   * the progressive discipline system where warnings serve as formal notices
   * before escalating to suspensions or bans. Moderators use this endpoint to
   * document policy violations, provide specific feedback to users about
   * inappropriate behavior, and track violation history for consistent
   * enforcement.
   *
   * The warning creation process validates that the target member exists and is
   * in a state where warnings are appropriate (not already permanently banned).
   * The system records comprehensive information including the violation
   * category, detailed explanation of what rules were broken, and severity
   * level (minor, moderate, or severe) which influences future enforcement
   * actions. Each warning is permanently associated with the issuing moderator
   * for accountability.
   *
   * Upon successful warning creation, the system immediately notifies the
   * warned member via email and in-platform notification, displaying the
   * warning reason, details, and severity. The warning becomes part of the
   * member's violation history, visible to all moderators when reviewing future
   * reports or considering escalated enforcement actions. Members can view
   * their own warning history in their account settings and acknowledge receipt
   * of warnings, though acknowledgment is not required for the warning to be
   * effective.
   *
   * This operation supports the moderation workflow defined in the
   * requirements, enabling moderators to enforce community standards
   * consistently while maintaining complete audit trails. Warnings can
   * optionally reference related moderation actions or reports that triggered
   * the warning, creating a comprehensive record of the enforcement decision
   * chain.
   *
   * @param connection
   * @param body Warning creation details including target member, violation
   *   information, and severity level
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedBody()
    body: IDiscussionBoardUserWarning.ICreate,
  ): Promise<IDiscussionBoardUserWarning> {
    try {
      return await postDiscussionBoardModeratorModerationWarnings({
        moderator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve a filtered, paginated list of user warnings with
   * comprehensive filtering and sorting options.
   *
   * Search and retrieve a filtered, paginated list of user warnings issued for
   * community guideline violations. This operation provides comprehensive
   * search capabilities for finding warnings based on multiple criteria
   * including the warned user, issuing moderator, violation severity, warning
   * category, acknowledgment status, and date ranges.
   *
   * Warnings are a core component of the discussion board's progressive
   * discipline system, recorded in the discussion_board_user_warnings table.
   * Each warning captures the violation category, detailed explanation of the
   * issue, severity level (minor, moderate, severe), and whether the user has
   * acknowledged receipt. The warning system enables moderators to track user
   * behavior patterns over time and apply appropriate escalation when
   * violations are repeated.
   *
   * This operation supports essential moderation workflows including reviewing
   * a specific user's warning history before taking further enforcement action,
   * identifying patterns of violations across the community to inform policy
   * updates, verifying that warnings were properly communicated and
   * acknowledged by users, and generating reports on warning trends by category
   * or severity. The search capabilities enable efficient navigation of
   * potentially large warning datasets accumulated over the platform's
   * lifetime.
   *
   * The operation integrates with the broader moderation system by providing
   * warning context that informs suspension and ban decisions. Moderators
   * reviewing reports or considering enforcement actions can query warnings for
   * the involved user to understand their violation history and determine
   * appropriate progressive discipline responses.
   *
   * Security considerations include restricting access exclusively to
   * moderators, as warning records contain detailed information about user
   * violations and moderator enforcement decisions. The operation respects soft
   * deletion by excluding deleted warning records from results unless
   * specifically requested. Pagination ensures performance remains acceptable
   * even with thousands of warnings in the system.
   *
   * Search filters support complex queries such as finding all severe warnings
   * issued in the last 30 days, locating unacknowledged warnings for follow-up,
   * identifying all warnings issued by a specific moderator for consistency
   * review, and filtering by specific violation categories to analyze patterns.
   * Sorting options enable organizing warnings by issue date, severity, or
   * acknowledgment status to prioritize review tasks.
   *
   * Related operations include retrieving individual warning details for full
   * context, creating new warnings when moderators identify violations, and
   * updating warnings when users acknowledge them. This search operation serves
   * as the primary discovery mechanism for warning records within the
   * moderation dashboard.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering
   *   warnings by user, moderator, severity, reason, acknowledgment status, and
   *   date ranges
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedBody()
    body: IDiscussionBoardUserWarning.IRequest,
  ): Promise<IPageIDiscussionBoardUserWarning.ISummary> {
    try {
      return await patchDiscussionBoardModeratorModerationWarnings({
        moderator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific user warning.
   *
   * Retrieves comprehensive details about a specific warning issued to a member
   * for community guideline violations. This operation provides access to the
   * complete warning record including the violation category, detailed
   * explanation, severity level, acknowledgment status, and all associated
   * metadata. The endpoint supports both moderator access (who can view all
   * warnings for moderation purposes) and member access (who can view their own
   * warnings for transparency).
   *
   * The returned warning information includes the warning reason category (such
   * as spam, harassment, off-topic content, or misinformation), detailed
   * explanation of what specific behavior or content violated guidelines, and
   * the severity classification (minor, moderate, or severe) which indicates
   * the violation's seriousness in the progressive discipline framework. The
   * response also includes timestamps showing when the warning was issued and
   * when the member acknowledged it (if acknowledgment has occurred).
   *
   * For moderators, this operation provides complete context for reviewing a
   * member's violation history, including information about the moderator who
   * issued the warning and any related moderation actions or reports that led
   * to the warning. This comprehensive view enables moderators to make informed
   * decisions about future enforcement actions based on the member's complete
   * disciplinary record. For members viewing their own warnings, the response
   * helps them understand exactly what guidelines were violated and what
   * behavior changes are expected.
   *
   * The operation enforces proper access control by validating that moderators
   * can view any warning while members can only access warnings issued to their
   * own account. This ensures privacy while maintaining the transparency needed
   * for fair moderation practices and appeal processes.
   *
   * @param connection
   * @param warningId Unique identifier of the target warning
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":warningId")
  public async at(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("warningId")
    warningId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardUserWarning> {
    try {
      return await getDiscussionBoardModeratorModerationWarningsWarningId({
        moderator,
        warningId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing user warning in the moderation system.
   *
   * Updates the details of a previously issued user warning, allowing
   * moderators to modify warning content, severity level, or additional context
   * after the initial warning was created. This operation is essential for
   * maintaining accurate moderation records when circumstances change or
   * additional information comes to light.
   *
   * Moderators can update the warning reason, detailed explanation, and
   * severity classification while preserving the original warning's identity
   * and relationship to the warned user. This enables correction of errors in
   * initial warning descriptions, escalation or de-escalation of severity based
   * on new evidence, and addition of context discovered during subsequent
   * investigation.
   *
   * The operation maintains audit trail integrity by updating the warning
   * record's updated_at timestamp while preserving the original created_at
   * timestamp and issuing moderator reference. This ensures complete
   * traceability of when warnings were issued versus when they were modified.
   * The warned member may receive notification of significant changes to
   * warnings affecting their account standing.
   *
   * Security considerations include verification that the requesting user has
   * moderator privileges and validation that the warning exists and is not
   * soft-deleted. The operation respects the progressive discipline framework
   * by ensuring severity changes are logged appropriately. Only active warnings
   * can be modified; soft-deleted warnings must be restored before editing.
   *
   * @param connection
   * @param warningId Unique identifier of the target user warning to update
   * @param body Updated warning information including reason, details, and
   *   severity level
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":warningId")
  public async update(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("warningId")
    warningId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardUserWarning.IUpdate,
  ): Promise<IDiscussionBoardUserWarning> {
    try {
      return await putDiscussionBoardModeratorModerationWarningsWarningId({
        moderator,
        warningId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Soft delete a user warning from the moderation system.
   *
   * Removes a user warning from active status by marking it as deleted,
   * typically when a warning was issued in error or successfully appealed by
   * the warned member. This operation performs a soft delete by setting the
   * deleted_at timestamp, preserving the warning record for historical audit
   * purposes while removing it from the member's visible warning history.
   *
   * Soft deletion of warnings is crucial for maintaining moderation
   * accountability and audit trails. Even when warnings are retracted, the
   * system preserves records of what actions were taken, by whom, and when they
   * were reversed. This supports appeals processes where members can challenge
   * warnings, and reviewing moderators can overturn incorrect decisions without
   * erasing the historical record.
   *
   * The operation updates the warning's deleted_at timestamp to the current
   * time and sets the updated_at timestamp accordingly. The warning will no
   * longer appear in the user's active warnings list or count toward
   * progressive discipline escalation. However, moderators can still view the
   * deleted warning in audit logs and moderation history interfaces for full
   * transparency.
   *
   * Security and permission validation ensures only moderators can delete
   * warnings, and the operation confirms the warning exists and is not already
   * deleted before proceeding. Deleting a warning does not automatically
   * reverse any subsequent enforcement actions that may have been based on the
   * warning (such as suspensions), though it may be grounds for reviewing those
   * actions separately.
   *
   * @param connection
   * @param warningId Unique identifier of the target user warning to soft
   *   delete
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":warningId")
  public async erase(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("warningId")
    warningId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardUserWarning> {
    try {
      return await deleteDiscussionBoardModeratorModerationWarningsWarningId({
        moderator,
        warningId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
