import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postDiscussionBoardModeratorModerationSuspensions } from "../../../../../providers/postDiscussionBoardModeratorModerationSuspensions";
import { ModeratorAuth } from "../../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../../decorators/payload/ModeratorPayload";
import { patchDiscussionBoardModeratorModerationSuspensions } from "../../../../../providers/patchDiscussionBoardModeratorModerationSuspensions";
import { getDiscussionBoardModeratorModerationSuspensionsSuspensionId } from "../../../../../providers/getDiscussionBoardModeratorModerationSuspensionsSuspensionId";
import { postDiscussionBoardModeratorModerationSuspensionsSuspensionIdLift } from "../../../../../providers/postDiscussionBoardModeratorModerationSuspensionsSuspensionIdLift";

import { IDiscussionBoardUserSuspension } from "../../../../../api/structures/IDiscussionBoardUserSuspension";
import { IPageIDiscussionBoardUserSuspension } from "../../../../../api/structures/IPageIDiscussionBoardUserSuspension";

@Controller("/discussionBoard/moderator/moderation/suspensions")
export class DiscussionboardModeratorModerationSuspensionsController {
  /**
   * Create a new user account suspension for community guideline enforcement.
   *
   * Create a new user account suspension record to enforce community guidelines
   * and maintain discussion quality on the economic and political discussion
   * board. This operation enables moderators to temporarily or permanently
   * restrict a member's access to the platform following violations of
   * community standards, as part of the progressive discipline system.
   *
   * The suspension creation process requires moderators to specify the target
   * member being suspended, the suspension duration (start and end times), the
   * category of violation that triggered the suspension (aligned with report
   * reason categories), and detailed justification explaining the decision.
   * Moderators must provide comprehensive suspension details that document the
   * violation context, previous warnings or enforcement history, and rationale
   * for the chosen suspension length.
   *
   * Upon successful suspension creation, the system immediately updates the
   * target member's account status to suspended, terminates all active
   * authentication sessions to force logout from all devices, and stores the
   * suspension record with complete audit information including the suspending
   * moderator's identity, timestamps, and enforcement justification. The
   * suspended member receives notification of the suspension via email with
   * details about the duration, reason, and appeal process.
   *
   * Security and accountability measures include requiring moderator
   * authentication with verified moderator role, comprehensive audit logging of
   * all suspension creation events with moderator identity and justification,
   * validation that the target member exists and is not already suspended, and
   * enforcement of progressive discipline guidelines where suspension duration
   * reflects violation severity and user history. The operation integrates with
   * the moderation action logging system to maintain complete traceability of
   * all enforcement decisions.
   *
   * This operation implements the core enforcement capability defined in the
   * Moderation and Content Management requirements, supporting the platform's
   * commitment to maintaining civil, productive discussions through transparent
   * and accountable moderation. The suspension mechanism serves as a key tool
   * in the progressive discipline framework, escalating from warnings to
   * temporary suspensions to permanent bans based on violation patterns and
   * severity.
   *
   * @param connection
   * @param body Suspension creation details including target member, duration,
   *   reason, and justification
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedBody()
    body: IDiscussionBoardUserSuspension.ICreate,
  ): Promise<IDiscussionBoardUserSuspension> {
    try {
      return await postDiscussionBoardModeratorModerationSuspensions({
        moderator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve a filtered, paginated list of user account suspensions.
   *
   * Retrieve a comprehensive, filtered, and paginated list of user account
   * suspensions from the discussion board moderation system. This operation
   * provides moderators with advanced search capabilities for reviewing
   * suspension history, tracking enforcement actions, and ensuring consistent
   * application of community guidelines.
   *
   * The operation supports extensive filtering options including suspended
   * member identification, suspending moderator, suspension status (active,
   * expired, lifted early), suspension reason categories, severity levels, and
   * date ranges for suspension start and end times. Moderators can search
   * across suspension details and reasons to find specific cases or patterns of
   * enforcement.
   *
   * Security considerations include restricting access to moderators only, as
   * suspension records contain sensitive moderation decisions and user account
   * information. The operation implements comprehensive audit logging for all
   * suspension queries to maintain accountability and transparency in
   * moderation practices. Rate limiting is applied to prevent excessive queries
   * that could impact system performance.
   *
   * The operation integrates with the discussion_board_user_suspensions table
   * as defined in the Prisma schema, incorporating all available suspension
   * fields including suspension timestamps, expiration times, lifting
   * information, and related moderation action references. The response
   * provides suspension summary information optimized for list displays in
   * moderation dashboards, with options to include detailed suspension context
   * and related moderation action information based on moderator needs.
   *
   * This search operation enables moderators to identify patterns in user
   * behavior, review progressive discipline application, verify suspension
   * expirations, and manage ongoing enforcement actions. It supports the
   * platform's commitment to transparent, consistent, and accountable content
   * moderation while maintaining user privacy and due process standards.
   *
   * @param connection
   * @param body Search criteria, filtering parameters, and pagination settings
   *   for suspension record retrieval
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedBody()
    body: IDiscussionBoardUserSuspension.IRequest,
  ): Promise<IPageIDiscussionBoardUserSuspension.ISummary> {
    try {
      return await patchDiscussionBoardModeratorModerationSuspensions({
        moderator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific user suspension.
   *
   * Retrieve comprehensive details about a specific user account suspension
   * from the discussion board system. This operation provides moderators with
   * complete information about a suspension including which member was
   * suspended, which moderator issued the suspension, the reason and details of
   * the violation, suspension duration, and current status.
   *
   * The suspension information includes temporal data such as when the
   * suspension began, when it is scheduled to expire, and whether it has been
   * lifted early by a moderator. This enables moderators to make informed
   * decisions about appeals, early termination, or extension of suspensions.
   *
   * Security considerations require that only authenticated moderators can
   * access suspension details, as this information contains enforcement actions
   * and user account status. The operation integrates with the moderation
   * system defined in the Moderation and Content Management requirements,
   * supporting the progressive discipline workflow and enforcement tracking.
   *
   * The response includes references to the suspended member, the moderator who
   * issued the suspension, the moderator who lifted it (if applicable), and any
   * related moderation action that triggered the suspension. This comprehensive
   * view enables moderators to understand the full context of the enforcement
   * action and make appropriate decisions for community management.
   *
   * @param connection
   * @param suspensionId Unique identifier of the target user suspension record
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":suspensionId")
  public async at(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("suspensionId")
    suspensionId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardUserSuspension> {
    try {
      return await getDiscussionBoardModeratorModerationSuspensionsSuspensionId(
        {
          moderator,
          suspensionId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Lift an active user suspension early to restore account access.
   *
   * Lift an active user account suspension before its scheduled expiration,
   * immediately restoring the member's ability to log in and participate in the
   * discussion board. This operation is a critical component of the moderation
   * system's flexibility, allowing moderators to reverse or terminate
   * enforcement actions when appropriate.
   *
   * When a suspension is lifted, the system records which moderator performed
   * the action, the exact timestamp of the lift, and updates the member's
   * account status to restore full access. The original suspension record is
   * preserved for audit purposes, maintaining a complete enforcement history
   * for progressive discipline tracking.
   *
   * This operation supports several moderation workflows including processing
   * successful appeals where users demonstrate the original suspension was
   * inappropriate or disproportionate, early termination for good behavior
   * where suspended users show genuine understanding and reform, error
   * correction where a suspension was issued based on incomplete information or
   * misunderstanding, and administrative decisions where moderators
   * collectively decide to reduce the suspension duration.
   *
   * Security and audit requirements mandate that all suspension lifts are
   * logged as moderation actions with the lifting moderator's identity,
   * timestamp, and optional notes explaining the decision. The suspended member
   * receives immediate notification that their account access has been
   * restored, and they can log in without waiting for the original expiration
   * date.
   *
   * The operation validates that the suspension exists, is currently active,
   * and has not already been lifted. Only authenticated moderators have
   * permission to lift suspensions, ensuring accountability and proper
   * authorization for all enforcement modifications.
   *
   * @param connection
   * @param suspensionId Unique identifier of the target user suspension to be
   *   lifted
   * @param body Optional notes explaining the reason for lifting the suspension
   *   early, such as appeal outcome or administrative decision
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post(":suspensionId/lift")
  public async lift(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("suspensionId")
    suspensionId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardUserSuspension.ILift,
  ): Promise<IDiscussionBoardUserSuspension> {
    try {
      return await postDiscussionBoardModeratorModerationSuspensionsSuspensionIdLift(
        {
          moderator,
          suspensionId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
