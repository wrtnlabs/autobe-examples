import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchDiscussionBoardArticlesArticleIdImages } from "../../../../providers/patchDiscussionBoardArticlesArticleIdImages";
import { getDiscussionBoardArticlesArticleIdImagesImageId } from "../../../../providers/getDiscussionBoardArticlesArticleIdImagesImageId";

import { IPageIDiscussionBoardArticleImage } from "../../../../api/structures/IPageIDiscussionBoardArticleImage";
import { IDiscussionBoardArticleImage } from "../../../../api/structures/IDiscussionBoardArticleImage";

@Controller("/discussionBoard/articles/:articleId/images")
export class DiscussionboardArticlesImagesController {
  /**
   * Retrieve a filtered, paginated list of images attached to a specific
   * discussion board article.
   *
   * Retrieve a comprehensive list of image attachments for a specific
   * discussion board article with advanced filtering and pagination
   * capabilities.
   *
   * This operation provides flexible querying of article images, supporting
   * search criteria such as original filename matching, content type filters
   * (image/jpeg, image/png, image/gif, image/webp), file size constraints,
   * dimension filters (width and height), and upload date ranges. The response
   * is paginated to efficiently handle articles with numerous image
   * attachments.
   *
   * Security considerations include ensuring that only images belonging to the
   * specified article are returned. The operation respects the article's
   * visibility settings - if the article is not accessible to the requesting
   * user, the image list should not be exposed. By default, soft-deleted images
   * (deleted_at IS NOT NULL) are excluded from results. Rate limiting applies
   * to prevent abuse of the search functionality.
   *
   * The operation integrates with the discussion_board_article_images table as
   * defined in the Prisma schema, incorporating all available image metadata
   * including original_filename, file_size, content_type, storage_url,
   * dimensions (width and height when available), created_at timestamp, and
   * deleted_at status. The response includes image summary information
   * optimized for list displays.
   *
   * @param connection
   * @param articleId Unique identifier of the target discussion board article
   *   (global scope)
   * @param body Search criteria, filtering options (filename, content type,
   *   file size, dimensions, upload date), sorting preferences, and pagination
   *   parameters for article image retrieval
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardArticleImage.IRequest,
  ): Promise<IPageIDiscussionBoardArticleImage.ISummary> {
    try {
      return await patchDiscussionBoardArticlesArticleIdImages({
        articleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific image attached to a
   * discussion board article.
   *
   * Retrieve complete details of a specific image attachment associated with a
   * discussion board article.
   *
   * This operation returns comprehensive information about an individual image,
   * including its storage URL for file access, original filename as uploaded by
   * the user, file metadata (file size in bytes, content type/MIME type such as
   * image/jpeg or image/png), image dimensions (width and height in pixels when
   * available), upload timestamp (created_at), and soft deletion status
   * (deleted_at). This endpoint is typically used when displaying full image
   * details, accessing the actual image file, or managing image attachments.
   *
   * Security considerations ensure that the image can only be accessed if it
   * belongs to the specified article and the article itself is accessible to
   * the requesting user. The operation validates that both the articleId and
   * imageId parameters correctly identify an existing image-article
   * relationship. Soft-deleted images (deleted_at IS NOT NULL) may be excluded
   * based on authorization level.
   *
   * The operation retrieves data from the discussion_board_article_images table
   * as defined in the Prisma schema, returning all relevant image properties
   * including original_filename, file_size, content_type, storage_url, width
   * (nullable), height (nullable), created_at, and deleted_at (nullable). The
   * response provides the complete image entity suitable for detailed display,
   * image viewing interfaces, or image management operations.
   *
   * @param connection
   * @param articleId Unique identifier of the parent discussion board article
   *   (global scope)
   * @param imageId Unique identifier of the target image attachment
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":imageId")
  public async at(
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedParam("imageId")
    imageId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardArticleImage> {
    try {
      return await getDiscussionBoardArticlesArticleIdImagesImageId({
        articleId,
        imageId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
