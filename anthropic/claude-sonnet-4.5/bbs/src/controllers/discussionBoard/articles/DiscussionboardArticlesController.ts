import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postDiscussionBoardArticles } from "../../../providers/postDiscussionBoardArticles";
import { MemberAuth } from "../../../decorators/MemberAuth";
import { MemberPayload } from "../../../decorators/payload/MemberPayload";
import { patchDiscussionBoardArticles } from "../../../providers/patchDiscussionBoardArticles";
import { getDiscussionBoardArticlesArticleId } from "../../../providers/getDiscussionBoardArticlesArticleId";
import { putDiscussionBoardArticlesArticleId } from "../../../providers/putDiscussionBoardArticlesArticleId";

import { IDiscussionBoardArticle } from "../../../api/structures/IDiscussionBoardArticle";
import { IPageIDiscussionBoardArticle } from "../../../api/structures/IPageIDiscussionBoardArticle";

@Controller("/discussionBoard/articles")
export class DiscussionboardArticlesController {
  /**
   * Create a new discussion board article.
   *
   * Create a new article on the discussion board for economic and political
   * discussions. This operation allows authenticated members to publish new
   * content including a title and body content with rich text formatting
   * support.
   *
   * The member's identity is automatically extracted from the JWT
   * authentication token and associated as the article author
   * (discussion_board_member_id). The member's authentication session is also
   * tracked (discussion_board_member_session_id) for audit trail purposes. The
   * operation validates that the article content meets quality requirements:
   * title must be 5-200 characters, body content must be 10-50,000 characters.
   *
   * Security measures include authentication verification to ensure only
   * registered members can create articles, and rate limiting to prevent spam
   * posting. The operation validates content length constraints and ensures
   * proper text formatting before persisting to the database.
   *
   * Articles are immediately published and visible to all users upon creation,
   * as specified in the requirements. The system automatically initializes
   * view_count to 0, sets created_at and updated_at timestamps to the current
   * time, and leaves deleted_at as null. The operation returns the complete
   * created article object including all system-assigned metadata.
   *
   * Related operations include updating articles (PUT
   * /discussionBoard/articles/{articleId}), retrieving article details (GET
   * /discussionBoard/articles/{articleId}), and searching articles (PATCH
   * /discussionBoard/articles).
   *
   * @param connection
   * @param body Article creation data including title and body content with
   *   rich text formatting
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IDiscussionBoardArticle.ICreate,
  ): Promise<IDiscussionBoardArticle> {
    try {
      return await postDiscussionBoardArticles({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve a filtered, paginated list of discussion board
   * articles.
   *
   * Retrieve a filtered and paginated list of discussion board articles with
   * advanced search capabilities. This operation allows users to discover
   * articles based on multiple criteria including keyword search across titles
   * and body content (utilizing GIN indexes on title and body fields),
   * filtering by author (discussion_board_member_id), and date range filtering
   * (created_at timestamps).
   *
   * The operation supports comprehensive pagination with configurable page
   * sizes and flexible sorting options. Users can sort articles by publication
   * date (created_at), view count (view_count), or last update time
   * (updated_at) in ascending or descending order to find the most relevant
   * content.
   *
   * Security considerations include rate limiting for search operations to
   * prevent abuse. Guest users can access public articles without
   * authentication, while members have the same search capabilities. The search
   * automatically excludes soft-deleted articles (where deleted_at is not null)
   * to respect content moderation decisions.
   *
   * This operation integrates with the discussion_board_articles table as
   * defined in the Prisma schema. The response includes article summary
   * information optimized for list displays, showing essential metadata like
   * title, excerpt from body content, author information (via
   * discussion_board_member_id relationship), publication date, view count, and
   * comment count (derived from discussion_board_comments relationship).
   *
   * @param connection
   * @param body Search criteria including keyword search, author filtering,
   *   date range filtering, sorting options, and pagination settings for
   *   article discovery
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IDiscussionBoardArticle.IRequest,
  ): Promise<IPageIDiscussionBoardArticle.ISummary> {
    try {
      return await patchDiscussionBoardArticles({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information of a specific discussion board article.
   *
   * Retrieve comprehensive details of a specific article from the discussion
   * board system using its unique identifier.
   *
   * This operation returns the complete article data including the title,
   * content body, publication status, view count, author information, creation
   * and update timestamps, and associated image and file attachments. The
   * article content is formatted in the structure defined by the discussion
   * board schema.
   *
   * The endpoint is accessible to all users including guests and authenticated
   * members. View count is automatically incremented when the article is
   * successfully retrieved. The operation validates that the article exists and
   * is accessible based on its publication status and visibility settings.
   *
   * Security considerations: Published articles are publicly accessible. Draft
   * or unpublished articles may require appropriate authorization based on the
   * authorship. The response includes related entities such as author details
   * and attachment references to provide complete context.
   *
   * This operation integrates with the discussion_board_articles table as
   * defined in the Prisma schema. The response structure provides all necessary
   * information for rendering the article view including content, metadata, and
   * associated resources.
   *
   * @param connection
   * @param articleId Unique identifier of the target article
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":articleId")
  public async at(
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardArticle> {
    try {
      return await getDiscussionBoardArticlesArticleId({
        articleId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing discussion board article.
   *
   * Update the content and metadata of an existing article in the discussion
   * board system.
   *
   * This operation allows article authors to modify their published or draft
   * articles. Updateable fields include the article title, content body,
   * publication status, and associated metadata. The operation preserves the
   * original creation timestamp while updating the modification timestamp to
   * reflect the edit time.
   *
   * Authorization is enforced to ensure only the article author or authorized
   * moderators can perform updates. The system validates that the article
   * exists and that the requesting user has appropriate permissions. Members
   * can only update their own articles, while moderators can update any article
   * for content moderation purposes.
   *
   * Security and business rules: The operation maintains data integrity by
   * validating all input fields according to the schema constraints. Ownership
   * verification ensures members cannot modify other members' articles. Audit
   * trails may be maintained for significant changes.
   *
   * This operation integrates with the discussion_board_articles table as
   * defined in the Prisma schema. The response returns the updated article with
   * all current field values, allowing the client to refresh its view with the
   * latest data.
   *
   * @param connection
   * @param articleId Unique identifier of the target article to update
   * @param body Updated article data including modified title, content, status,
   *   and other editable fields
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":articleId")
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardArticle.IUpdate,
  ): Promise<IDiscussionBoardArticle> {
    try {
      return await putDiscussionBoardArticlesArticleId({
        member,
        articleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
