import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchDiscussionBoardArticlesArticleIdCommentsCommentIdReplies } from "../../../../../providers/patchDiscussionBoardArticlesArticleIdCommentsCommentIdReplies";

import { IPageIDiscussionBoardComment } from "../../../../../api/structures/IPageIDiscussionBoardComment";
import { IDiscussionBoardComment } from "../../../../../api/structures/IDiscussionBoardComment";

@Controller("/discussionBoard/articles/:articleId/comments/:commentId/replies")
export class DiscussionboardArticlesCommentsRepliesController {
  /**
   * Retrieve paginated list of replies to a specific comment on an article.
   *
   * Retrieve a filtered and paginated list of reply comments for a specific
   * top-level comment on an article in the discussion board system. This
   * operation provides advanced search and filtering capabilities for
   * discovering replies within a comment thread, supporting the single-level
   * threading model defined in the requirements.
   *
   * The operation targets the discussion_board_comments table where the
   * discussion_board_parent_comment_id matches the specified comment
   * identifier. It supports comprehensive filtering including date range
   * filters, author filters, content keyword search, and status filters.
   * Results can be sorted by creation date, update date, or relevance when
   * search keywords are provided.
   *
   * Security considerations include appropriate rate limiting to prevent abuse
   * of search operations and filtering of soft-deleted comments from results
   * unless accessed by moderators. The response includes summary information
   * optimized for displaying reply lists, with pagination support to handle
   * comment threads with many replies efficiently.
   *
   * This operation integrates with the comment system as defined in the Prisma
   * schema, respecting the author_type discriminator field that identifies
   * whether replies were created by members or moderators. The pagination
   * structure enables efficient loading of large reply sets while maintaining
   * fast response times as specified in the performance requirements.
   *
   * @param connection
   * @param articleId Unique identifier of the parent article containing the
   *   comment thread
   * @param commentId Unique identifier of the parent comment whose replies are
   *   being retrieved
   * @param body Search criteria, filtering parameters, and pagination options
   *   for retrieving replies
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardComment.IRequest,
  ): Promise<IPageIDiscussionBoardComment.ISummary> {
    try {
      return await patchDiscussionBoardArticlesArticleIdCommentsCommentIdReplies(
        {
          articleId,
          commentId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
