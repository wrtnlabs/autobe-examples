import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchDiscussionBoardArticlesArticleIdComments } from "../../../../providers/patchDiscussionBoardArticlesArticleIdComments";
import { getDiscussionBoardArticlesArticleIdCommentsCommentId } from "../../../../providers/getDiscussionBoardArticlesArticleIdCommentsCommentId";

import { IPageIDiscussionBoardComment } from "../../../../api/structures/IPageIDiscussionBoardComment";
import { IDiscussionBoardComment } from "../../../../api/structures/IDiscussionBoardComment";

@Controller("/discussionBoard/articles/:articleId/comments")
export class DiscussionboardArticlesCommentsController {
  /**
   * Retrieve a paginated list of comments for a specific discussion board
   * article.
   *
   * Search and retrieve comments associated with a specific discussion board
   * article with advanced filtering and pagination.
   *
   * This operation provides comprehensive access to all comments posted on a
   * particular article. Users can browse through comments with pagination
   * support, sort them by various criteria (creation date, author, etc.), and
   * apply filters to find specific comments.
   *
   * The operation supports both authenticated and unauthenticated access.
   * Guests can view public comments, while authenticated members and moderators
   * may see additional details or have different sorting/filtering options
   * based on their permissions.
   *
   * Pagination is implemented to handle articles with large numbers of comments
   * efficiently. The response includes comment summary information optimized
   * for display in discussion threads, showing essential details like content,
   * author, timestamps, and potentially nested reply structures.
   *
   * Security: The operation filters comments based on visibility rules and user
   * permissions. Deleted or hidden comments may be excluded from results for
   * regular users but visible to moderators.
   *
   * This operation is essential for rendering article discussion threads,
   * allowing users to engage with community conversations around economic and
   * political topics.
   *
   * @param connection
   * @param articleId Unique identifier of the discussion board article whose
   *   comments are being retrieved
   * @param body Search criteria, filtering options, sorting preferences, and
   *   pagination parameters for retrieving comments
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardComment.IRequest,
  ): Promise<IPageIDiscussionBoardComment.ISummary> {
    try {
      return await patchDiscussionBoardArticlesArticleIdComments({
        articleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific comment on an article.
   *
   * Retrieve complete details of a specific comment posted on a discussion
   * board article.
   *
   * This operation returns comprehensive information about an individual
   * comment, including the comment content, author details, creation timestamp,
   * and any associated metadata. It enables users to view specific comments in
   * isolation, which is valuable for moderation workflows, direct linking to
   * particular discussion points, or investigating reported content.
   *
   * The operation validates that both the article and comment exist and that
   * the comment belongs to the specified article. This ensures data integrity
   * and prevents unauthorized access to comments through path manipulation.
   *
   * Guests can view comments on public articles without authentication, while
   * access to comments on restricted articles follows the article's access
   * control rules. The response includes full comment details suitable for
   * display in comment detail views or moderation interfaces.
   *
   * This operation works with the discussion_board_comments table from the
   * Prisma schema, retrieving a single comment record with all associated data
   * including author information and timestamps.
   *
   * @param connection
   * @param articleId Unique identifier of the article containing the comment
   * @param commentId Unique identifier of the target comment to retrieve
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":commentId")
  public async at(
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardComment> {
    try {
      return await getDiscussionBoardArticlesArticleIdCommentsCommentId({
        articleId,
        commentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
