import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia from "typia";
import { patchDiscussionBoardMembersMemberUsernameComments } from "../../../../providers/patchDiscussionBoardMembersMemberUsernameComments";

import { IPageIDiscussionBoardComment } from "../../../../api/structures/IPageIDiscussionBoardComment";
import { IDiscussionBoardComment } from "../../../../api/structures/IDiscussionBoardComment";

@Controller("/discussionBoard/members/:memberUsername/comments")
export class DiscussionboardMembersCommentsController {
  /**
   * Retrieve paginated list of comments posted by a specific member.
   *
   * Retrieve a filtered and paginated list of comments posted by a specific
   * member identified by their username. This operation enables users to
   * explore the complete collection of comments and discussion contributions
   * made by a particular member across all articles on the discussion board
   * platform.
   *
   * The operation supports comprehensive filtering and sorting capabilities
   * including filtering by parent article to see comments on specific articles,
   * date range filtering to focus on recent or historical contributions, search
   * within the member's comments by content keywords to find specific
   * discussions, and multiple sorting options such as newest first, oldest
   * first, or grouped by article. This enables efficient discovery of a
   * member's discussion participation and engagement patterns.
   *
   * This operation queries the discussion_board_comments table with a filter on
   * the member author relationship (discussion_board_member_id) matching the
   * member identified by the username path parameter. The response includes
   * comment summaries with essential metadata including comment content
   * preview, parent article information (title and link), posting timestamp,
   * and edit indicators if the comment has been modified. The operation
   * respects single-level threading showing both top-level comments and replies
   * authored by the member.
   *
   * Security and privacy considerations include respecting the member's
   * activity visibility settings as defined in their profile (public,
   * members_only, or hidden). When a member's activity visibility is set to
   * hidden, only the member themselves and moderators can view their comment
   * list. When set to members_only, only authenticated members can access the
   * list. Public activity is accessible to all users including guests. Comments
   * on deleted articles are excluded from results. Soft-deleted comments are
   * excluded from public results but may be visible to moderators for audit
   * purposes. The operation supports pagination to handle members with
   * extensive comment histories efficiently, ensuring fast response times even
   * for highly active discussants with thousands of comments.
   *
   * @param connection
   * @param memberUsername Unique username of the target member whose comments
   *   are being retrieved
   * @param body Search criteria, filtering options, and pagination parameters
   *   for retrieving member's comments
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedParam("memberUsername")
    memberUsername: string,
    @TypedBody()
    body: IDiscussionBoardComment.IRequest,
  ): Promise<IPageIDiscussionBoardComment.ISummary> {
    try {
      return await patchDiscussionBoardMembersMemberUsernameComments({
        memberUsername,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
