import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia from "typia";
import { patchDiscussionBoardMembersMemberUsernameArticles } from "../../../../providers/patchDiscussionBoardMembersMemberUsernameArticles";

import { IPageIDiscussionBoardArticle } from "../../../../api/structures/IPageIDiscussionBoardArticle";
import { IDiscussionBoardArticle } from "../../../../api/structures/IDiscussionBoardArticle";

@Controller("/discussionBoard/members/:memberUsername/articles")
export class DiscussionboardMembersArticlesController {
  /**
   * Retrieve paginated list of articles authored by a specific member.
   *
   * Retrieve a filtered and paginated list of articles authored by a specific
   * member identified by their username. This operation enables users to
   * explore the complete collection of articles published by a particular
   * member, providing insight into their contributions to economic and
   * political discussions on the platform.
   *
   * The operation supports comprehensive filtering and sorting capabilities
   * including publication status filters, category and tag filters, date range
   * filtering, search within the member's articles by title or content
   * keywords, and multiple sorting options such as newest first, oldest first,
   * most viewed, or most commented. This enables efficient discovery of
   * specific content within a member's publishing history.
   *
   * This operation queries the discussion_board_articles table with a filter on
   * the author relationship (discussion_board_member_id) matching the member
   * identified by the username path parameter. The response includes article
   * summaries optimized for list display with essential metadata including
   * title, summary excerpt, publication date, view count, comment count,
   * categories, and tags. For members viewing their own articles, the response
   * may include additional private information such as draft status or edit
   * capabilities.
   *
   * Security and privacy considerations include respecting the member's
   * activity visibility settings as defined in their profile (public,
   * members_only, or hidden). When a member's activity visibility is set to
   * hidden, only the member themselves and moderators can view their article
   * list. When set to members_only, only authenticated members can access the
   * list. Public activity is accessible to all users including guests. The
   * operation supports pagination to handle members with extensive publication
   * histories efficiently, ensuring fast response times even for prolific
   * authors with hundreds of articles.
   *
   * @param connection
   * @param memberUsername Unique username of the target member whose articles
   *   are being retrieved
   * @param body Search criteria, filtering options, and pagination parameters
   *   for retrieving member's articles
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedParam("memberUsername")
    memberUsername: string,
    @TypedBody()
    body: IDiscussionBoardArticle.IRequest,
  ): Promise<IPageIDiscussionBoardArticle.ISummary> {
    try {
      return await patchDiscussionBoardMembersMemberUsernameArticles({
        memberUsername,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
