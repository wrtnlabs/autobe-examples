import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { patchDiscussionBoardPasswordResets } from "../../../providers/patchDiscussionBoardPasswordResets";

import { IDiscussionBoardPasswordReset } from "../../../api/structures/IDiscussionBoardPasswordReset";

@Controller("/discussionBoard/passwordResets")
export class DiscussionboardPasswordresetsController {
  /**
   * Request password reset token for account recovery.
   *
   * Initiate a password reset request by generating a secure reset token and
   * sending it to the user's registered email address. This operation supports
   * both member and moderator accounts through polymorphic actor pattern.
   *
   * The operation validates that the provided email address exists in either
   * the discussion_board_members or discussion_board_moderators table. It
   * generates a cryptographically secure random token, stores it in the
   * discussion_board_password_resets table with a 1-hour expiration timestamp,
   * and creates the corresponding subtype record
   * (discussion_board_password_reset_of_members or
   * discussion_board_password_reset_of_moderators) to maintain proper
   * normalization.
   *
   * Password reset tokens are sent to the user's registered email address and
   * allow users to set a new password without knowing their current password.
   * Each reset request includes the actor_type discriminator field to
   * distinguish between member and moderator requests. The token is single-use
   * and invalidated after successful password change.
   *
   * Security measures include rate limiting (maximum 3 password reset requests
   * per email per hour) to prevent abuse, and the system does not reveal
   * whether an email address exists in the database to prevent account
   * enumeration attacks. Previous reset tokens for the same account are
   * invalidated when a new request is made.
   *
   * The operation uses PATCH method because it requires complex request data
   * (email address and actor type) to search for the appropriate account and
   * initiate the reset process. After successful token generation, users
   * receive an email with a reset link valid for 1 hour.
   *
   * Related operations: Users complete password reset by accessing the reset
   * link sent via email, which triggers a separate password change operation
   * that validates the token and updates the password.
   *
   * @param connection
   * @param body Password reset request with email and actor type
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async create(
    @TypedBody()
    body: IDiscussionBoardPasswordReset.ICreate,
  ): Promise<IDiscussionBoardPasswordReset> {
    try {
      return await patchDiscussionBoardPasswordResets({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
