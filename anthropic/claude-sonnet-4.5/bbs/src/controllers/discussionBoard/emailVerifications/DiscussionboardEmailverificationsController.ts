import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postDiscussionBoardEmailVerifications } from "../../../providers/postDiscussionBoardEmailVerifications";

import { IDiscussionBoardEmailVerification } from "../../../api/structures/IDiscussionBoardEmailVerification";

@Controller("/discussionBoard/emailVerifications")
export class DiscussionboardEmailverificationsController {
  /**
   * Create a new email verification record and send verification email to a
   * member's registered email address. This operation generates a unique
   * verification token valid for 24 hours and sends it to the member's email.
   *
   * Email verification is required before members can create articles and
   * access full platform features. Upon registration, a verification token is
   * automatically generated through this endpoint and sent to the member's
   * email address. Members can also request new verification emails if the
   * original token expires.
   *
   * The operation validates that the member account exists and is not already
   * verified. It generates a cryptographically secure random token, stores it
   * in the discussion_board_email_verifications table with a 24-hour expiration
   * timestamp, and triggers the email sending process. Each verification record
   * contains the token, target email address, and expiration details.
   *
   * Security considerations include rate limiting to prevent abuse (maximum 3
   * verification emails per member per hour) and token uniqueness validation.
   * The verification token is single-use and invalidated after successful
   * verification or expiration.
   *
   * Related operations: Members complete verification by accessing the
   * verification link sent via email, which triggers a separate verification
   * confirmation process.
   *
   * @param connection
   * @param body Member email verification request details
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @TypedBody()
    body: IDiscussionBoardEmailVerification.ICreate,
  ): Promise<IDiscussionBoardEmailVerification> {
    try {
      return await postDiscussionBoardEmailVerifications({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
