import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { getDiscussionBoardModerationWarningsWarningId } from "../../../../providers/getDiscussionBoardModerationWarningsWarningId";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";

import { IDiscussionBoardUserWarning } from "../../../../api/structures/IDiscussionBoardUserWarning";

@Controller("/discussionBoard/moderation/warnings/:warningId")
export class DiscussionboardModerationWarningsController {
  /**
   * Retrieve detailed information about a specific user warning.
   *
   * Retrieves comprehensive details about a specific warning issued to a member
   * for community guideline violations. This operation provides access to the
   * complete warning record including the violation category, detailed
   * explanation, severity level, acknowledgment status, and all associated
   * metadata. The endpoint supports both moderator access (who can view all
   * warnings for moderation purposes) and member access (who can view their own
   * warnings for transparency) with permission validation enforced at the
   * implementation layer.
   *
   * The returned warning information includes the warning reason category (such
   * as spam, harassment, off-topic content, or misinformation), detailed
   * explanation of what specific behavior or content violated guidelines, and
   * the severity classification (minor, moderate, or severe) which indicates
   * the violation's seriousness in the progressive discipline framework. The
   * response also includes timestamps showing when the warning was issued and
   * when the member acknowledged it (if acknowledgment has occurred).
   *
   * For moderators, this operation provides complete context for reviewing a
   * member's violation history, including information about the moderator who
   * issued the warning and any related moderation actions or reports that led
   * to the warning. This comprehensive view enables moderators to make informed
   * decisions about future enforcement actions based on the member's complete
   * disciplinary record. For members viewing their own warnings, the response
   * helps them understand exactly what guidelines were violated and what
   * behavior changes are expected.
   *
   * The operation enforces proper access control by validating that moderators
   * can view any warning while members can only access warnings issued to their
   * own account (verified by comparing the warning's discussion_board_member_id
   * with the authenticated member's ID). This ensures privacy while maintaining
   * the transparency needed for fair moderation practices and appeal
   * processes.
   *
   * @param connection
   * @param warningId Unique identifier of the target warning
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("warningId")
    warningId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardUserWarning> {
    try {
      return await getDiscussionBoardModerationWarningsWarningId({
        member,
        warningId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
