import { Controller } from "@nestjs/common";
import { TypedRoute } from "@nestia/core";
import typia from "typia";
import { postDiscussionBoardMemberAuthLogout } from "../../../../../providers/postDiscussionBoardMemberAuthLogout";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";

import { IDiscussionBoardAuth } from "../../../../../api/structures/IDiscussionBoardAuth";

@Controller("/discussionBoard/member/auth/logout")
export class DiscussionboardMemberAuthController {
  /**
   * Terminate current member session and invalidate authentication tokens.
   *
   * Terminate the currently authenticated member session by invalidating the
   * refresh token and recording the session end time in the
   * discussion_board_member_sessions table. This operation enables members to
   * securely end their authenticated session, preventing further use of the
   * current refresh token to obtain new access tokens.
   *
   * The logout process marks the current session as expired by setting the
   * expired_at timestamp to the current time, creating a complete audit trail
   * of session duration and member activity. The operation extracts the
   * member's identity and current session information from the JWT access
   * token, eliminating the need for request body parameters. After successful
   * logout, the client must discard both the access token and refresh token
   * from local storage to complete the logout process.
   *
   * This operation is particularly important for security when members access
   * the system from shared or public devices, as it ensures that sessions are
   * properly terminated rather than remaining active until the 30-day refresh
   * token expiration. The logout action only affects the current device's
   * session - members can remain logged in on other devices if they have
   * multiple active sessions across different browsers or devices. When a
   * member changes their password, all sessions across all devices are
   * invalidated automatically through a separate mechanism, but manual logout
   * only terminates the specific session from which it was initiated.
   *
   * The operation requires a valid member access token to identify the session
   * to be terminated. No request body is needed as all session information is
   * derived from the authentication token. The response confirms successful
   * logout, after which the member must authenticate again using the login
   * operation to regain access to protected member features such as article
   * creation and comment posting.
   *
   * @param connection
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async logout(
    @MemberAuth()
    member: MemberPayload,
  ): Promise<IDiscussionBoardAuth.ILogoutResult> {
    try {
      return await postDiscussionBoardMemberAuthLogout({
        member,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
