import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { getDiscussionBoardMemberContentReportsReportId } from "../../../../providers/getDiscussionBoardMemberContentReportsReportId";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { postDiscussionBoardMemberContentReports } from "../../../../providers/postDiscussionBoardMemberContentReports";

import { IDiscussionBoardContentReport } from "../../../../api/structures/IDiscussionBoardContentReport";

@Controller("/discussionBoard/member/contentReports")
export class DiscussionboardMemberContentreportsController {
  /**
   * Retrieve detailed information about a specific content report submitted by
   * a member flagging an article for policy violations.
   *
   * This operation returns comprehensive details about a single content report,
   * including the violation category selected by the reporter, optional
   * detailed explanation, current resolution status (pending,
   * reviewed_no_action, reviewed_edited, reviewed_removed), moderator
   * resolution notes if reviewed, and all relevant timestamps. The response
   * includes relationships to the reported article, reporting member, and
   * resolving moderator if applicable.
   *
   * Security considerations include access control based on user role.
   * Moderators can view any content report to perform their review duties.
   * Members can only view reports they personally submitted to track resolution
   * status. Guest users have no access to content reports. The operation
   * validates that the requesting user has appropriate permissions before
   * returning report data.
   *
   * This operation integrates with the discussion_board_content_reports table
   * as defined in the Prisma schema. The response includes the report's current
   * status in the moderation workflow, enabling moderators to prioritize
   * pending reports and allowing reporting members to see how their concerns
   * were addressed. Reports track the complete lifecycle from submission
   * through moderator review to final resolution.
   *
   * @param connection
   * @param reportId Unique identifier of the target content report
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":reportId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("reportId")
    reportId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardContentReport> {
    try {
      return await getDiscussionBoardMemberContentReportsReportId({
        member,
        reportId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Create a new content report flagging an article for policy violations or
   * inappropriate content.
   *
   * This operation enables registered members to submit reports identifying
   * articles that may violate community guidelines, contain spam,
   * misinformation, offensive content, or other policy violations. Members
   * specify the article being reported, select a violation category from
   * predefined options (Spam, Offensive Content, Misinformation, Off-Topic,
   * Other), and optionally provide detailed explanation describing the specific
   * concern.
   *
   * The created report is automatically assigned 'pending' status and added to
   * the moderation queue for review. The reporting member's identity is
   * recorded for accountability and to enable follow-up if needed. Multiple
   * members can independently report the same article, with each report tracked
   * separately to measure community consensus about problematic content.
   *
   * Security considerations include authentication requirement - only
   * registered members can submit reports to prevent anonymous abuse. Rate
   * limiting prevents report spam. The operation validates that the referenced
   * article exists and is not already deleted. Business logic may prevent
   * duplicate reports from the same member for the same article within a time
   * window.
   *
   * This operation integrates with the discussion_board_content_reports table
   * as defined in the Prisma schema. The response returns the created report
   * with its assigned ID and initial pending status, enabling the reporting
   * member to track resolution progress through subsequent queries.
   *
   * @param connection
   * @param body Report submission data including article reference, violation
   *   category, and optional details
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IDiscussionBoardContentReport.ICreate,
  ): Promise<IDiscussionBoardContentReport> {
    try {
      return await postDiscussionBoardMemberContentReports({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
