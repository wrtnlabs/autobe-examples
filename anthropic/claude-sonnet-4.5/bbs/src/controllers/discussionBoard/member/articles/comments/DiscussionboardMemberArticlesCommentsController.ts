import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { postDiscussionBoardMemberArticlesArticleIdComments } from "../../../../../providers/postDiscussionBoardMemberArticlesArticleIdComments";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { putDiscussionBoardMemberArticlesArticleIdCommentsCommentId } from "../../../../../providers/putDiscussionBoardMemberArticlesArticleIdCommentsCommentId";
import { deleteDiscussionBoardMemberArticlesArticleIdCommentsCommentId } from "../../../../../providers/deleteDiscussionBoardMemberArticlesArticleIdCommentsCommentId";

import { IDiscussionBoardComment } from "../../../../../api/structures/IDiscussionBoardComment";

@Controller("/discussionBoard/member/articles/:articleId/comments")
export class DiscussionboardMemberArticlesCommentsController {
  /**
   * Create a new comment on a discussion board article to participate in
   * economic and political discussions.
   *
   * This operation enables authenticated members to contribute their thoughts,
   * opinions, and analyses to ongoing discussions by posting comments on
   * published articles. Each comment is permanently associated with the article
   * and the member who authored it, building a threaded discussion context.
   *
   * The member's identity is automatically extracted from the JWT
   * authentication token, ensuring proper attribution and accountability. The
   * system validates that the referenced article exists and is accessible
   * before creating the comment. All comments are immediately visible to other
   * users browsing the article.
   *
   * Security considerations include rate limiting to prevent spam, content
   * validation to ensure comments meet community standards, and proper
   * authorization to ensure only authenticated members can post comments. The
   * operation logs comment creation for moderation and audit purposes.
   *
   * This operation works with the discussion_board_comments and
   * discussion_board_articles tables from the Prisma schema. The created
   * comment becomes part of the article's discussion thread and contributes to
   * the platform's collaborative knowledge sharing on economic and political
   * topics.
   *
   * @param connection
   * @param articleId Unique identifier of the target article to comment on
   * @param body Comment content and metadata for creation
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardComment.ICreate,
  ): Promise<IDiscussionBoardComment> {
    try {
      return await postDiscussionBoardMemberArticlesArticleIdComments({
        member,
        articleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing comment on a discussion board article.
   *
   * Update the content of an existing comment posted on a discussion board
   * article.
   *
   * This operation allows registered members to modify their previously posted
   * comments on articles. The member must be the original author of the comment
   * to perform this update. The operation supports updating the comment's text
   * content while preserving the original creation timestamp and metadata.
   *
   * Security: Only authenticated members can update comments. Authorization
   * logic verifies that the requesting member is the original author of the
   * comment. Moderators may have additional privileges to edit any comment for
   * moderation purposes.
   *
   * The updated comment reflects changes immediately in the article's comment
   * thread. The system may track edit history internally for audit purposes.
   * Rate limiting applies to prevent abuse of the update functionality.
   *
   * Related operations: Create comment (POST /articles/{articleId}/comments),
   * Delete comment (DELETE /articles/{articleId}/comments/{commentId}), View
   * article with comments (GET /articles/{articleId}).
   *
   * @param connection
   * @param articleId Unique identifier of the target article containing the
   *   comment
   * @param commentId Unique identifier of the target comment to update
   * @param body Updated comment content and metadata
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":commentId")
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardComment.IUpdate,
  ): Promise<IDiscussionBoardComment> {
    try {
      return await putDiscussionBoardMemberArticlesArticleIdCommentsCommentId({
        member,
        articleId,
        commentId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a comment from a discussion board article.
   *
   * Permanently remove a comment from a discussion board article.
   *
   * This operation allows registered members to delete their previously posted
   * comments on articles. The member must be the original author of the comment
   * to perform this deletion. Moderators have additional privileges to delete
   * any comment for moderation purposes, such as removing inappropriate content
   * or spam.
   *
   * Security: Only authenticated members can delete comments. Authorization
   * logic verifies that the requesting user is either the original comment
   * author or a moderator with deletion privileges. The operation performs a
   * hard delete, permanently removing the comment record from the database
   * without soft-delete preservation.
   *
   * Once deleted, the comment is immediately removed from the article's comment
   * thread and cannot be recovered. The deletion may affect comment threading
   * and reply structures if the deleted comment had child replies. The system
   * handles orphaned replies according to the business logic defined in the
   * requirements.
   *
   * Related operations: Create comment (POST /articles/{articleId}/comments),
   * Update comment (PUT /articles/{articleId}/comments/{commentId}), View
   * article with comments (GET /articles/{articleId}).
   *
   * @param connection
   * @param articleId Unique identifier of the target article containing the
   *   comment
   * @param commentId Unique identifier of the target comment to delete
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":commentId")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardComment> {
    try {
      return await deleteDiscussionBoardMemberArticlesArticleIdCommentsCommentId(
        {
          member,
          articleId,
          commentId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
