import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { postDiscussionBoardMemberArticlesArticleIdAttachments } from "../../../../../providers/postDiscussionBoardMemberArticlesArticleIdAttachments";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { deleteDiscussionBoardMemberArticlesArticleIdAttachmentsAttachmentId } from "../../../../../providers/deleteDiscussionBoardMemberArticlesArticleIdAttachmentsAttachmentId";

import { IDiscussionBoardArticleAttachment } from "../../../../../api/structures/IDiscussionBoardArticleAttachment";

@Controller("/discussionBoard/member/articles/:articleId/attachments")
export class DiscussionboardMemberArticlesAttachmentsController {
  /**
   * Upload and attach a new image or document file to an existing discussion
   * board article. This operation allows authenticated members to add
   * supporting materials, visual evidence, charts, documents, and reference
   * materials to their economic and political discussions.
   *
   * The operation validates file type, size, and security constraints before
   * creating the attachment record. Image attachments support JPEG, PNG, GIF,
   * and WebP formats with a maximum size of 5 MB each, and articles can have up
   * to 10 image attachments. Document attachments support PDF, DOC, DOCX, XLS,
   * XLSX, TXT, and CSV formats with a maximum size of 10 MB each, and articles
   * can have up to 5 document attachments. The combined total attachment size
   * per article cannot exceed 25 MB.
   *
   * Security validation includes file type verification by examining content
   * headers (not just extensions), malware scanning, and metadata stripping to
   * protect user privacy. The system generates unique storage paths and
   * sanitizes filenames to prevent security vulnerabilities. Only the article
   * author or moderators can add attachments to an article.
   *
   * The attachment is immediately associated with the parent article and
   * becomes visible when the article is viewed. The operation records the
   * member who uploaded the attachment for attribution and audit purposes. All
   * attachment uploads are subject to the business rules defined in the
   * attachment validation requirements including type restrictions, size
   * limits, and quantity constraints.
   *
   * @param connection
   * @param articleId Unique identifier of the target article to attach the file
   *   to
   * @param body Attachment creation data including file information and
   *   metadata
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardArticleAttachment.ICreate,
  ): Promise<IDiscussionBoardArticleAttachment> {
    try {
      return await postDiscussionBoardMemberArticlesArticleIdAttachments({
        member,
        articleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently removes an attachment (image or document file) from a
   * discussion board article, deleting both the database record and the
   * physical file from storage.
   *
   * This operation is available to the article author for managing their own
   * article attachments during editing, and to moderators for removing
   * inappropriate attachments during content moderation. When an attachment is
   * deleted, it is immediately removed from the article view and cannot be
   * recovered.
   *
   * The operation validates that the specified attachment belongs to the
   * specified article before deletion. If the attachment does not exist or
   * belongs to a different article, the operation fails with an error. The
   * attachment type (image or file) does not affect the deletion process.
   *
   * Security: Members can only delete attachments from their own articles.
   * Moderators can delete attachments from any article. The operation checks
   * ownership before proceeding with deletion. When a moderator removes an
   * attachment, the action is logged in moderation logs for accountability.
   *
   * The deletion process removes the attachment record from
   * discussion_board_article_attachments table and deletes the physical file
   * from storage using the storage_path reference. This ensures no orphaned
   * files remain in the storage system.
   *
   * Related operations: After deleting an attachment, users typically continue
   * editing the article or add replacement attachments. The article itself
   * remains unchanged except for the removal of the attachment reference.
   *
   * @param connection
   * @param articleId Unique identifier of the article containing the attachment
   * @param attachmentId Unique identifier of the specific attachment to remove
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":attachmentId")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedParam("attachmentId")
    attachmentId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteDiscussionBoardMemberArticlesArticleIdAttachmentsAttachmentId(
        {
          member,
          articleId,
          attachmentId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
