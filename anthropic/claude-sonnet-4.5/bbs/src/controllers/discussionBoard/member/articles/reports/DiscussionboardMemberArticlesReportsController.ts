import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { postDiscussionBoardMemberArticlesArticleIdReports } from "../../../../../providers/postDiscussionBoardMemberArticlesArticleIdReports";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";

import { IDiscussionBoardContentReport } from "../../../../../api/structures/IDiscussionBoardContentReport";

@Controller("/discussionBoard/member/articles/:articleId/reports")
export class DiscussionboardMemberArticlesReportsController {
  /**
   * Create a new content report for an article flagging potential policy
   * violations.
   *
   * Submit a new content report flagging an article for potential policy
   * violations or inappropriate content.
   *
   * This operation empowers community members to participate in content quality
   * management by reporting articles that violate community guidelines, contain
   * spam, misinformation, offensive content, or other policy issues. The
   * operation creates a new record in the discussion_board_content_reports
   * table associated with the specified article and the authenticated member
   * who is submitting the report.
   *
   * The request body requires selection of a report_category from predefined
   * options (Spam, Offensive Content, Misinformation, Off-Topic, Other) to help
   * moderators categorize and prioritize reports. Members can optionally
   * provide detailed explanations in the report_details field to give
   * moderators context about the specific violation or concern. The reporting
   * member's identity is automatically captured from the authentication token
   * to track report authorship while maintaining appropriate confidentiality
   * from the article author.
   *
   * Business rules enforced include preventing duplicate reports (members
   * cannot report the same article multiple times), validating that the article
   * exists and is in a reportable state, and rate limiting to prevent report
   * spam abuse. The created report is automatically assigned 'pending' status
   * and added to the moderation queue with creation timestamp for moderator
   * review prioritization.
   *
   * Security considerations: Only authenticated members can submit reports to
   * prevent anonymous spam. The system should track reporting patterns to
   * identify potential coordinated abuse or excessive reporting by individual
   * members. Reporter identity is logged for accountability but should be
   * handled according to privacy policies regarding report confidentiality.
   *
   * This operation integrates with the discussion_board_content_reports table
   * as defined in the Prisma schema, setting appropriate foreign key
   * relationships to both the reported article (discussion_board_article_id)
   * and the reporting member (discussion_board_member_id). Related operations
   * include PATCH /articles/{articleId}/reports for viewing existing reports
   * and moderator endpoints for reviewing and resolving reports.
   *
   * @param connection
   * @param articleId Unique identifier of the article being reported for policy
   *   violations
   * @param body Report submission data including violation category and
   *   optional detailed explanation
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardContentReport.ICreate,
  ): Promise<IDiscussionBoardContentReport> {
    try {
      return await postDiscussionBoardMemberArticlesArticleIdReports({
        member,
        articleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
