import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { postDiscussionBoardMemberArticlesArticleIdCommentsCommentIdReplies } from "../../../../../../providers/postDiscussionBoardMemberArticlesArticleIdCommentsCommentIdReplies";
import { MemberAuth } from "../../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../../decorators/payload/MemberPayload";

import { IDiscussionBoardComment } from "../../../../../../api/structures/IDiscussionBoardComment";

@Controller(
  "/discussionBoard/member/articles/:articleId/comments/:commentId/replies",
)
export class DiscussionboardMemberArticlesCommentsRepliesController {
  /**
   * Create a new reply to a specific comment on an article as a member.
   *
   * Create a new reply comment to an existing top-level comment on an article
   * in the discussion board system. This operation enables members to
   * participate in threaded discussions by posting replies to existing
   * comments, implementing the single-level threading model specified in the
   * comment system requirements.
   *
   * The operation creates a new record in the discussion_board_comments table
   * with the discussion_board_parent_comment_id set to the specified comment
   * identifier from the path. The system validates that the parent comment
   * exists, belongs to the specified article, and is not soft-deleted. The
   * operation enforces the single-level threading constraint by validating that
   * the parent comment is itself a top-level comment (has null
   * discussion_board_parent_comment_id).
   *
   * Authentication is required to determine the author of the reply. The
   * author_type discriminator field is set to 'member' and the
   * discussion_board_member_id foreign key is populated with the authenticated
   * member's ID. The content field is validated according to comment validation
   * rules (1-5000 characters as per requirements).
   *
   * Upon successful creation, the system increments the parent article's
   * comment_count field, creates the reply with appropriate timestamps
   * (created_at, updated_at), and returns the complete reply information. The
   * operation respects the business rule that comments appear immediately
   * without requiring approval, as specified in the comment system
   * requirements.
   *
   * Security considerations include validating user authentication, enforcing
   * content validation rules to prevent XSS attacks through sanitization, rate
   * limiting to prevent spam, and ensuring the authenticated member has
   * permission to post replies. The operation maintains data integrity by
   * validating referential integrity between the reply, parent comment, and
   * parent article.
   *
   * @param connection
   * @param articleId Unique identifier of the parent article containing the
   *   comment thread
   * @param commentId Unique identifier of the parent comment to which this
   *   reply is being posted
   * @param body Reply comment content and metadata for creation
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardComment.ICreate,
  ): Promise<IDiscussionBoardComment> {
    try {
      return await postDiscussionBoardMemberArticlesArticleIdCommentsCommentIdReplies(
        {
          member,
          articleId,
          commentId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
