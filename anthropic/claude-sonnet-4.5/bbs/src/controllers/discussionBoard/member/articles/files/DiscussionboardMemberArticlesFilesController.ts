import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { postDiscussionBoardMemberArticlesArticleIdFiles } from "../../../../../providers/postDiscussionBoardMemberArticlesArticleIdFiles";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { deleteDiscussionBoardMemberArticlesArticleIdFilesFileId } from "../../../../../providers/deleteDiscussionBoardMemberArticlesArticleIdFilesFileId";

import { IDiscussionBoardArticleFile } from "../../../../../api/structures/IDiscussionBoardArticleFile";

@Controller("/discussionBoard/member/articles/:articleId/files")
export class DiscussionboardMemberArticlesFilesController {
  /**
   * Upload a file attachment to a discussion board article.
   *
   * Create a new file attachment record for a discussion board article.
   *
   * This operation allows article authors to attach document files that provide
   * supporting evidence and reference materials for their articles. The file
   * itself should be uploaded to external storage first (e.g., cloud storage
   * service), and this endpoint creates the database record linking the file to
   * the article.
   *
   * Security considerations: Only authenticated members can upload files. The
   * operation validates that the specified article exists and that the
   * requesting user has permission to add attachments. File size limits and
   * allowed file extensions are enforced to prevent abuse and ensure security.
   *
   * The file metadata (URL, name, extension, size) is stored in the database,
   * while the actual file content resides in external storage. The system
   * validates file extensions to prevent upload of potentially harmful file
   * types.
   *
   * Related operations: Delete file (DELETE
   * /articles/{articleId}/files/{fileId}), List article files (GET
   * /articles/{articleId}/files).
   *
   * @param connection
   * @param articleId Unique identifier of the target article to attach the file
   *   to
   * @param body File attachment metadata including storage URL, filename,
   *   extension, and size
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardArticleFile.ICreate,
  ): Promise<IDiscussionBoardArticleFile> {
    try {
      return await postDiscussionBoardMemberArticlesArticleIdFiles({
        member,
        articleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a file attachment from a discussion board article.
   *
   * Remove a specific file attachment from a discussion board article
   * permanently.
   *
   * This operation allows authorized users (the article author or moderators)
   * to delete file attachments that were previously uploaded to support an
   * article's content. When a file is deleted, the association between the
   * article and the file is removed from the discussion_board_article_files
   * table.
   *
   * Security considerations: Only the article author or moderators with
   * appropriate permissions can delete file attachments. The operation
   * validates ownership before allowing deletion. File deletion is permanent
   * and cannot be undone.
   *
   * The deletion removes the database record linking the file to the article.
   * Depending on file storage implementation, the actual file content may be
   * removed from storage or marked for cleanup.
   *
   * This operation is typically used when a file attachment is no longer
   * relevant, contains errors, or needs to be replaced with an updated
   * version.
   *
   * @param connection
   * @param articleId Unique identifier of the discussion board article
   *   containing the file attachment
   * @param fileId Unique identifier of the specific file attachment to be
   *   deleted
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":fileId")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedParam("fileId")
    fileId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteDiscussionBoardMemberArticlesArticleIdFilesFileId({
        member,
        articleId,
        fileId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
