import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { putDiscussionBoardMemberMembersMemberId } from "../../../../providers/putDiscussionBoardMemberMembersMemberId";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { deleteDiscussionBoardMemberMembersMemberId } from "../../../../providers/deleteDiscussionBoardMemberMembersMemberId";

import { IDiscussionBoardMember } from "../../../../api/structures/IDiscussionBoardMember";

@Controller("/discussionBoard/member/members/:memberId")
export class DiscussionboardMemberMembersController {
  /**
   * Update member account profile information.
   *
   * Update profile information for an existing member account in the discussion
   * board system.
   *
   * This operation allows authenticated members to modify their profile details
   * including display name, biography, and avatar image URL. **CRITICAL**: The
   * implementation MUST enforce ownership verification - members can ONLY
   * update their own profile (where the memberId parameter matches the
   * authenticated member's ID from the JWT token). Moderators with elevated
   * privileges can update any member profile for administrative purposes.
   *
   * The update operation modifies fields in the discussion_board_members table
   * while preserving critical authentication fields (email, password, username)
   * which require separate verification workflows. The updated_at timestamp is
   * automatically set to the current time when any profile changes are saved.
   *
   * Security considerations include MANDATORY ownership verification to ensure
   * members can only modify their own profiles, and moderator permission checks
   * for administrative profile updates. The operation will return 403 Forbidden
   * if a member attempts to update another member's profile without moderator
   * privileges. All changes are immediately visible in the member's public
   * profile and author attribution on their articles.
   *
   * Validation rules enforce bio maximum length of 500 characters, avatar URL
   * must be valid JPEG or PNG format, and display name follows the same
   * constraints as username (3-30 characters). The system maintains profile
   * consistency across all member content and interactions.
   *
   * @param connection
   * @param memberId Unique identifier of the member account to update. MUST
   *   match authenticated member's ID unless requester is a moderator.
   * @param body Updated profile information for the member account
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("memberId")
    memberId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardMember.IUpdate,
  ): Promise<IDiscussionBoardMember> {
    try {
      return await putDiscussionBoardMemberMembersMemberId({
        member,
        memberId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete member account from the discussion board.
   *
   * Mark a member account as deleted in the discussion board system through
   * soft deletion mechanism.
   *
   * This operation sets the deleted_at timestamp on the
   * discussion_board_members record to mark the account as deleted while
   * preserving the data for a 30-day retention period. **CRITICAL**: The
   * implementation MUST enforce ownership verification - members can ONLY
   * delete their own account (where the memberId parameter matches the
   * authenticated member's ID from the JWT token). Moderators with elevated
   * privileges can delete member accounts for policy violations or
   * administrative reasons.
   *
   * When a member account is deleted, the system archives all associated
   * articles created by that member and terminates all active authentication
   * sessions. The deleted account cannot login or perform any actions during
   * the retention period. After 30 days, the account becomes eligible for
   * permanent deletion during system maintenance operations.
   *
   * Security considerations include MANDATORY ownership verification ensuring
   * members can only delete their own account unless they have moderator
   * privileges. The operation will return 403 Forbidden if a member attempts to
   * delete another member's account without moderator privileges. Moderators
   * must provide a deletion reason when removing member accounts for
   * accountability and audit trail purposes.
   *
   * The soft deletion approach preserves content history and moderation records
   * while preventing account access. Member email addresses and usernames are
   * retained to prevent impersonation after deletion. Articles created by
   * deleted members are either anonymized (shown as 'Deleted User') or
   * completely removed based on moderator discretion and content value to
   * ongoing discussions.
   *
   * Related operations include account suspension (temporary access
   * restriction) and account restoration (reversing deletion within the
   * retention period). This deletion is reversible only within the 30-day
   * window, after which permanent deletion removes all personal identifiable
   * information.
   *
   * @param connection
   * @param memberId Unique identifier of the member account to delete. MUST
   *   match authenticated member's ID unless requester is a moderator.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("memberId")
    memberId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardMember> {
    try {
      return await deleteDiscussionBoardMemberMembersMemberId({
        member,
        memberId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
