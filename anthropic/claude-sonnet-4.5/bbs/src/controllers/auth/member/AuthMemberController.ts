import { Controller, Ip } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthMemberJoin } from "../../../providers/postAuthMemberJoin";
import { postAuthMemberLogin } from "../../../providers/postAuthMemberLogin";
import { postAuthMemberRefresh } from "../../../providers/postAuthMemberRefresh";

import { IDiscussionBoardMember } from "../../../api/structures/IDiscussionBoardMember";

@Controller("/auth/member")
export class AuthMemberController {
  /**
   * Register new member account with email verification workflow in
   * discussion_board_members table.
   *
   * Registers a new member account for the discussion board platform, enabling
   * users to create and participate in economic and political discussions. This
   * operation creates a new record in the discussion_board_members table with
   * the provided credentials and initiates the email verification process
   * required before full content creation privileges are granted.
   *
   * The registration process validates that the email and username are unique
   * across all existing members, enforcing the unique constraints defined in
   * the Prisma schema. The password is securely hashed using bcrypt with a work
   * factor of 10+ before storage, ensuring credentials are never stored in
   * plain text. Initial account status sets email_verified to false and
   * is_suspended to false.
   *
   * Upon successful registration, an email verification token is automatically
   * generated and stored in the discussion_board_email_verifications table with
   * a 24-hour expiration. This token is sent to the member's email address to
   * confirm ownership. Members must complete email verification before they can
   * create articles and access full platform features, as indicated by the
   * email_verified field requirement.
   *
   * The operation returns JWT tokens (access token with 30-minute expiration
   * and refresh token with 7-day expiration) immediately upon registration,
   * allowing the member to access read-only features and their profile while
   * awaiting email verification. The response includes the member's profile
   * information and verification status.
   *
   * This operation is public and requires no authentication. It implements the
   * first step in the member lifecycle, followed by email verification (POST
   * /auth/member/email/verify) and eventual login for returning members (POST
   * /auth/member/login).
   *
   * @param connection
   * @param body Member registration credentials including email, password, and
   *   username
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IDiscussionBoardMember.ICreate,
  ): Promise<IDiscussionBoardMember.IAuthorized> {
    try {
      return await postAuthMemberJoin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate member credentials and create session in
   * discussion_board_member_sessions table.
   *
   * Authenticates an existing member using email and password credentials,
   * validating against the discussion_board_members table and creating a new
   * authenticated session. This operation verifies the member's identity,
   * checks account status, and issues JWT tokens for subsequent API requests
   * requiring member authentication.
   *
   * The authentication process validates the provided password against the
   * bcrypt-hashed password stored in the discussion_board_members table. The
   * operation checks that the account is not suspended (is_suspended = false),
   * not deleted (deleted_at is null), and exists in the system. If the account
   * is suspended, the operation returns the suspension_reason and
   * suspended_until timestamp to inform the member.
   *
   * Upon successful authentication, a new session record is created in the
   * discussion_board_member_sessions table, capturing the IP address,
   * connection URL (href), and referrer for security monitoring and abuse
   * detection. The session enables stateless JWT authentication with a
   * 30-minute access token and 7-day refresh token. The last_login_at timestamp
   * in the discussion_board_members table is updated to track member activity.
   *
   * The operation returns JWT tokens along with the member's complete profile
   * information including username, display_name, bio, avatar_url, email
   * verification status (email_verified), and account status. Multiple
   * concurrent sessions are supported, allowing members to access the platform
   * from different devices simultaneously.
   *
   * This operation is public and requires no prior authentication. It follows
   * member registration (POST /auth/member/join) and email verification (POST
   * /auth/member/email/verify) in the authentication workflow. Sessions created
   * here can be refreshed using the refresh token endpoint (POST
   * /auth/member/refresh).
   *
   * @param connection
   * @param body Member login credentials with email and password
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IDiscussionBoardMember.ILogin,
  ): Promise<IDiscussionBoardMember.IAuthorized> {
    try {
      return await postAuthMemberLogin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh JWT access tokens using valid refresh token from
   * discussion_board_member_sessions.
   *
   * Refreshes expired or expiring JWT access tokens using a valid refresh
   * token, extending the member's authenticated session without requiring
   * credential re-entry. This operation validates the refresh token against
   * active sessions in the discussion_board_member_sessions table and issues
   * new JWT tokens for continued API access.
   *
   * The refresh process verifies that the refresh token corresponds to an
   * active session (expired_at is null) and that the associated member account
   * in discussion_board_members is in good standing (not suspended with
   * is_suspended = false, not deleted with deleted_at = null). If the account
   * has been suspended or deleted since the original login, the refresh
   * operation fails and requires re-authentication.
   *
   * Upon successful validation, new JWT tokens are issued with refreshed
   * expiration times: a 30-minute access token for immediate API requests and a
   * 7-day refresh token for future token renewal. The existing session record
   * in discussion_board_member_sessions remains active, maintaining the
   * original session context including IP address and creation timestamp.
   *
   * The operation returns the renewed JWT tokens along with the member's
   * current profile information from discussion_board_members, including any
   * updates to username, display_name, bio, avatar_url, and verification status
   * that may have occurred since the original login. This ensures the client
   * application has the latest member data without additional API calls.
   *
   * This operation requires a valid refresh token but does not require an
   * active access token, enabling seamless token renewal even after access
   * token expiration. It is a critical component of the stateless JWT
   * authentication flow, working in conjunction with login (POST
   * /auth/member/login) to maintain long-lived authenticated sessions across
   * the 30-minute access token expiration boundary.
   *
   * @param connection
   * @param body Refresh token for renewing authentication
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IDiscussionBoardMember.IRefresh,
  ): Promise<IDiscussionBoardMember.IAuthorized> {
    try {
      return await postAuthMemberRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
