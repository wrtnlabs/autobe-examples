import { Controller, Ip } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthMemberJoin } from "../../../providers/postAuthMemberJoin";
import { postAuthMemberLogin } from "../../../providers/postAuthMemberLogin";
import { postAuthMemberRefresh } from "../../../providers/postAuthMemberRefresh";

import { IDiscussionBoardMember } from "../../../api/structures/IDiscussionBoardMember";

@Controller("/auth/member")
export class AuthMemberController {
  /**
   * Register a new member account and issue authentication tokens for
   * discussion_board_members table.
   *
   * Creates a new member account for the discussion board platform and issues
   * initial JWT authentication tokens.
   *
   * This registration endpoint allows new users to join the community by
   * providing their email, password, and display name. The system validates the
   * uniqueness of the email address, securely hashes the password, and creates
   * a new record in the discussion_board_members table.
   *
   * Upon successful registration, the endpoint immediately authenticates the
   * user by generating and returning both an access token and a refresh token.
   * The access token is used for subsequent API requests, while the refresh
   * token enables token renewal without requiring re-authentication.
   *
   * The registration process includes validation of email format, password
   * strength requirements, and uniqueness constraints. If the email is already
   * registered, the operation returns an appropriate error response.
   *
   * This is a public endpoint accessible without authentication, as it
   * represents the entry point for new users to join the platform.
   *
   * @param connection
   * @param body Member registration information including credentials and
   *   profile data
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IDiscussionBoardMember.ICreate,
  ): Promise<IDiscussionBoardMember.IAuthorized> {
    try {
      return await postAuthMemberJoin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate member credentials and issue access tokens for
   * discussion_board_members table.
   *
   * Authenticates an existing member account and issues JWT authentication
   * tokens.
   *
   * This login endpoint allows registered members to authenticate with the
   * discussion board platform by providing their email address and password.
   * The system validates the credentials against the discussion_board_members
   * table, verifying both the email existence and password correctness through
   * secure hash comparison.
   *
   * Upon successful authentication, the endpoint generates and returns both an
   * access token and a refresh token. The access token is used for subsequent
   * API requests to access protected resources, while the refresh token enables
   * token renewal when the access token expires.
   *
   * The authentication process includes validation of credential format,
   * verification of account existence, and password hash comparison. If
   * credentials are invalid or the account does not exist, the operation
   * returns an appropriate error response.
   *
   * This is a public endpoint accessible without prior authentication, serving
   * as the primary entry point for existing members to access the platform.
   *
   * @param connection
   * @param body Member login credentials including email and password
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IDiscussionBoardMember.ILogin,
  ): Promise<IDiscussionBoardMember.IAuthorized> {
    try {
      return await postAuthMemberLogin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Renew member authentication tokens using valid refresh token from
   * discussion_board_member_sessions table.
   *
   * Refreshes authentication tokens for a member session using a valid refresh
   * token.
   *
   * This token refresh endpoint allows authenticated members to obtain new
   * access tokens without requiring re-authentication with credentials. When an
   * access token expires, members can use their refresh token to request a new
   * set of tokens, maintaining continuous authenticated access to the
   * platform.
   *
   * The endpoint validates the provided refresh token against the
   * discussion_board_member_sessions table, checking for token validity,
   * expiration status, and session integrity. If the refresh token is valid,
   * the system generates and returns a new access token and refresh token
   * pair.
   *
   * The token refresh process includes validation of the refresh token format,
   * verification of token existence and validity in the session store, and
   * expiration checking. If the refresh token is invalid, expired, or
   * associated with a terminated session, the operation returns an appropriate
   * error response requiring the user to log in again.
   *
   * This endpoint requires a valid refresh token but does not require an active
   * access token, as it specifically handles the scenario where the access
   * token has expired.
   *
   * @param connection
   * @param body Refresh token information for token renewal
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IDiscussionBoardMember.IRefresh,
  ): Promise<IDiscussionBoardMember.IAuthorized> {
    try {
      return await postAuthMemberRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
