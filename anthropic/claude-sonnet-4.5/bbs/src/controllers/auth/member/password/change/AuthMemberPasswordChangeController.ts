import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthMemberPasswordChange } from "../../../../../providers/postAuthMemberPasswordChange";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";

import { IDiscussionBoardMember } from "../../../../../api/structures/IDiscussionBoardMember";

@Controller("/auth/member/password/change")
export class AuthMemberPasswordChangeController {
  /**
   * Enables authenticated members to change their password as a security
   * maintenance operation, requiring knowledge of the current password to
   * authorize the change. This operation validates the existing password
   * against discussion_board_members, updates to a new bcrypt-hashed password,
   * and manages session lifecycle to maintain security across devices.
   *
   * The password change process first authenticates the request using the
   * member's JWT access token to identify the discussion_board_member_id. The
   * operation then validates that the provided current password matches the
   * hashed password stored in the discussion_board_members table using bcrypt
   * comparison. This verification prevents unauthorized password changes even
   * if a session token is compromised.
   *
   * Upon successful current password validation, the new password is hashed
   * using bcrypt with work factor 10+ and updates the password field in
   * discussion_board_members. The password is never stored or transmitted in
   * plain text, consistent with security standards throughout the
   * authentication system. The updated_at timestamp is set to track when the
   * password change occurred.
   *
   * As a security measure, all existing sessions in
   * discussion_board_member_sessions for this member are invalidated except the
   * current session by setting their expired_at timestamp. This forces
   * re-authentication on other devices while allowing the current session to
   * continue uninterrupted. This prevents potential unauthorized access from
   * previously authenticated devices after a password change.
   *
   * This operation requires member authentication via JWT access token
   * (authorizationActor: 'member') and differs from the password reset flow
   * which is designed for forgotten passwords. Members use this endpoint for
   * routine password updates or security improvements, maintaining continuous
   * authenticated access throughout the process.
   *
   * @param connection
   * @param body Current password and new password for authenticated member
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async changePassword(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IDiscussionBoardMember.IChangePassword,
  ): Promise<IDiscussionBoardMember.IPasswordChanged> {
    try {
      return await postAuthMemberPasswordChange({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
