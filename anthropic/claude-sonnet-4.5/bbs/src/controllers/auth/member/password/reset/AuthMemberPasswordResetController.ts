import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthMemberPasswordReset } from "../../../../../providers/postAuthMemberPasswordReset";

import { IDiscussionBoardMember } from "../../../../../api/structures/IDiscussionBoardMember";

@Controller("/auth/member/password/reset")
export class AuthMemberPasswordResetController {
  /**
   * Request password reset token for member account in
   * discussion_board_password_resets table.
   *
   * Initiates a password reset request for a member who has forgotten their
   * password, creating a secure single-use token that enables password change
   * without knowing the current password. This operation creates records in
   * both discussion_board_password_resets and
   * discussion_board_password_reset_of_members tables, following the Compatible
   * Actor Pattern for polymorphic password reset support.
   *
   * The password reset process begins by validating that the provided email
   * address corresponds to an active member account in discussion_board_members
   * (not deleted with deleted_at = null, not permanently suspended). A
   * cryptographically secure random token is generated and stored in
   * discussion_board_password_resets with actor_type set to 'member',
   * expires_at set to 1 hour from creation, and used_at initially null.
   *
   * The relationship to the specific member is maintained through
   * discussion_board_password_reset_of_members, which creates a linking record
   * with the discussion_board_password_reset_id and discussion_board_member_id
   * foreign keys. This subtype table enables proper 3NF normalization while
   * supporting password resets for both members and moderators through the same
   * base table.
   *
   * The generated token is sent to the member's registered email address with
   * instructions to complete the password reset process. The token is valid for
   * 1 hour for security purposes. Members can request multiple password reset
   * emails, with each request creating a new token; however, only unused tokens
   * (used_at is null) can be successfully redeemed.
   *
   * This operation is public and requires no authentication, as it's
   * specifically designed for users who cannot log in due to forgotten
   * passwords. It's the first step in the password recovery workflow, followed
   * by the password change operation (POST
   * /auth/member/password/reset/complete) which consumes the token and updates
   * the member's password in discussion_board_members.
   *
   * @param connection
   * @param body Member email address for password reset
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async requestPasswordReset(
    @TypedBody()
    body: IDiscussionBoardMember.IRequestPasswordReset,
  ): Promise<IDiscussionBoardMember.IPasswordResetRequested> {
    try {
      return await postAuthMemberPasswordReset({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
