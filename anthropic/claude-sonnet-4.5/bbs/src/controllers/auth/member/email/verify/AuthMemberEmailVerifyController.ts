import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthMemberEmailVerify } from "../../../../../providers/postAuthMemberEmailVerify";

import { IDiscussionBoardMember } from "../../../../../api/structures/IDiscussionBoardMember";

@Controller("/auth/member/email/verify")
export class AuthMemberEmailVerifyController {
  /**
   * Verifies a member's email address using the unique verification token sent
   * during registration, enabling full content creation privileges on the
   * discussion board platform. This operation validates the token against
   * discussion_board_email_verifications, confirms it hasn't expired or been
   * used, and updates the member's verification status in
   * discussion_board_members.
   *
   * The verification process retrieves the verification record using the
   * provided token, checking that it matches an entry in
   * discussion_board_email_verifications with a non-null
   * discussion_board_member_id foreign key. The operation validates that the
   * token hasn't expired (current time < expires_at) and hasn't been previously
   * used (verified_at is null). Tokens are valid for 24 hours from creation.
   *
   * Upon successful validation, the operation updates the
   * discussion_board_members table, setting email_verified to true and
   * email_verified_at to the current timestamp for the associated member
   * account. Simultaneously, the verification record in
   * discussion_board_email_verifications is marked as used by setting
   * verified_at to the current timestamp, preventing token reuse.
   *
   * The email verification requirement gates access to article creation and
   * full platform features. Until email_verified is true, members have limited
   * privileges and cannot create content in the discussion_board_articles
   * table. This security measure ensures account ownership and reduces spam or
   * fraudulent registrations.
   *
   * This operation is public and requires no authentication, as it's designed
   * to be accessed via email link by users who have just registered but not yet
   * logged in. If the token has expired, members can request a new verification
   * email through a separate endpoint. This operation is a critical
   * intermediate step between registration (POST /auth/member/join) and full
   * platform access.
   *
   * @param connection
   * @param body Email verification token sent to member's email address
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async verifyEmail(
    @TypedBody()
    body: IDiscussionBoardMember.IVerifyEmail,
  ): Promise<IDiscussionBoardMember> {
    try {
      return await postAuthMemberEmailVerify({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
