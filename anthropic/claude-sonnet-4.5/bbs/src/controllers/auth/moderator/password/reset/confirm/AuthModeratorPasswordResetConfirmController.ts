import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthModeratorPasswordResetConfirm } from "../../../../../../providers/postAuthModeratorPasswordResetConfirm";

import { IDiscussionBoardModerator } from "../../../../../../api/structures/IDiscussionBoardModerator";

@Controller("/auth/moderator/password/reset/confirm")
export class AuthModeratorPasswordResetConfirmController {
  /**
   * Completes the password reset process by validating the reset token and
   * updating the moderator's password.
   *
   * This operation enables moderators to set a new password after requesting a
   * password reset. The moderator provides the reset token (received via email)
   * and their desired new password. The system validates the token against
   * discussion_board_password_resets table, ensuring it belongs to a moderator
   * (actor_type='moderator'), hasn't been used (used_at=null), and hasn't
   * expired (expires_at > current time).
   *
   * The operation retrieves the associated moderator account through the
   * discussion_board_password_reset_of_moderators relationship table, which
   * links the reset request to the specific moderator
   * (discussion_board_moderator_id). Only active moderator accounts
   * (is_active=true, deleted_at=null) can successfully reset passwords.
   *
   * Upon successful validation, the new password is hashed using bcrypt with
   * work factor 10+ and stored in the discussion_board_moderators table,
   * replacing the old password. The used_at timestamp in the password reset
   * record is set to mark the token as consumed, preventing reuse. The reset
   * token becomes invalid after this operation.
   *
   * The operation enforces password security requirements through validation
   * rules, ensuring the new password meets minimum complexity standards. If the
   * token is invalid, expired, already used, or belongs to an inactive account,
   * appropriate error responses are returned.
   *
   * After successful password reset, the moderator can login using their email
   * and new password through the standard login endpoint.
   *
   * @param connection
   * @param body Password reset token and new password
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async resetPassword(
    @TypedBody()
    body: IDiscussionBoardModerator.IResetPassword,
  ): Promise<void> {
    try {
      return await postAuthModeratorPasswordResetConfirm({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
