import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthModeratorPasswordChange } from "../../../../../providers/postAuthModeratorPasswordChange";
import { ModeratorAuth } from "../../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../../decorators/payload/ModeratorPayload";

import { IDiscussionBoardModerator } from "../../../../../api/structures/IDiscussionBoardModerator";

@Controller("/auth/moderator/password/change")
export class AuthModeratorPasswordChangeController {
  /**
   * Enables authenticated moderators to change their password by providing
   * their current password and new password.
   *
   * This operation allows moderators to update their password while
   * authenticated. Unlike password reset which uses email tokens, password
   * change requires the moderator to provide their current password for
   * security validation. The moderator must be authenticated
   * (authorizationActor='moderator') to access this endpoint.
   *
   * The operation validates the provided current password against the stored
   * password hash in the discussion_board_moderators table using bcrypt
   * comparison. Only if the current password matches can the moderator proceed
   * with setting a new password. This prevents unauthorized password changes
   * even if an authenticated session is compromised.
   *
   * Upon successful validation of the current password, the new password is
   * hashed using bcrypt with work factor 10+ and stored in the
   * discussion_board_moderators table, replacing the old password hash. The
   * password field is never stored or transmitted in plain text for security.
   *
   * The operation enforces password security requirements through validation
   * rules, ensuring the new password meets minimum complexity standards
   * (length, character diversity, etc.). The new password must be different
   * from the current password to prevent accidental no-change updates.
   *
   * After successful password change, all existing moderator sessions in
   * discussion_board_moderator_sessions table can optionally be invalidated
   * (expired_at set to current timestamp) to force re-authentication with the
   * new password, enhancing security. The current session may be preserved to
   * avoid disrupting the moderator's workflow.
   *
   * This operation is distinct from password reset, which is used when
   * moderators have forgotten their password and cannot provide the current
   * password for validation.
   *
   * @param connection
   * @param body Current password and new password
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async changePassword(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedBody()
    body: IDiscussionBoardModerator.IChangePassword,
  ): Promise<void> {
    try {
      return await postAuthModeratorPasswordChange({
        moderator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
