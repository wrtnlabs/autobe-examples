import { Controller } from "@nestjs/common";
import { TypedRoute } from "@nestia/core";
import typia from "typia";
import { postAuthModeratorEmailVerifyRequest } from "../../../../../../providers/postAuthModeratorEmailVerifyRequest";
import { ModeratorAuth } from "../../../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../../../decorators/payload/ModeratorPayload";

@Controller("/auth/moderator/email/verify/request")
export class AuthModeratorEmailVerifyRequestController {
  /**
   * Generates and sends an email verification token to the moderator's
   * registered email address for email ownership confirmation.
   *
   * This operation enables moderators to verify their email address, which is
   * required before granting full moderation privileges. The moderator must be
   * authenticated (authorizationActor='moderator') to request email
   * verification. Upon request, the system generates a cryptographically secure
   * random token and stores it in the discussion_board_email_verifications
   * table.
   *
   * The verification record includes the moderator's ID
   * (discussion_board_member_id referencing discussion_board_moderators.id),
   * the unique token, the email address being verified, and a 24-hour
   * expiration timestamp (expires_at). The token is sent to the moderator's
   * registered email address via email, containing a verification link.
   *
   * Moderators can request new verification emails if the original token
   * expires (expires_at < current time) or if they didn't receive the initial
   * email. Each request generates a new token and creates a new record in
   * discussion_board_email_verifications table, while previous unused tokens
   * remain in the database for audit purposes.
   *
   * The operation validates that the authenticated moderator has an unverified
   * email (email_verified=false) before generating a new token. If the email is
   * already verified (email_verified=true), the operation returns an
   * appropriate response indicating verification is not needed.
   *
   * Verification tokens are single-use and invalidated after successful
   * verification (verified_at timestamp set) through the email verification
   * confirmation endpoint.
   *
   * @param connection
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async requestEmailVerification(
    @ModeratorAuth()
    moderator: ModeratorPayload,
  ): Promise<void> {
    try {
      return await postAuthModeratorEmailVerifyRequest({
        moderator,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
