import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthModeratorEmailVerifyConfirm } from "../../../../../../providers/postAuthModeratorEmailVerifyConfirm";
import { ModeratorAuth } from "../../../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../../../decorators/payload/ModeratorPayload";

import { IDiscussionBoardModerator } from "../../../../../../api/structures/IDiscussionBoardModerator";

@Controller("/auth/moderator/email/verify/confirm")
export class AuthModeratorEmailVerifyConfirmController {
  /**
   * Verify moderator email address using verification token.
   *
   * Confirms moderator email verification by validating the verification token
   * and updating the email_verified status.
   *
   * This operation completes the email verification process for moderators. The
   * moderator provides the verification token (received via email), and the
   * system validates it against the discussion_board_email_verifications table.
   * The token must belong to the authenticated moderator
   * (discussion_board_member_id matches the moderator's ID), must not be
   * expired (expires_at > current time), and must not have been used previously
   * (verified_at=null).
   *
   * Upon successful validation, the operation updates the
   * discussion_board_moderators table, setting email_verified=true and
   * email_verified_at to the current timestamp. This marks the email as
   * confirmed and grants the moderator full moderation privileges if previously
   * restricted.
   *
   * The verified_at timestamp in the discussion_board_email_verifications
   * record is set to mark the token as used, preventing token reuse. The
   * verification token becomes invalid after successful verification.
   *
   * The operation requires the moderator to be authenticated
   * (authorizationActor='moderator') to ensure only the account owner can
   * verify their email. If the token is invalid, expired, already used, or
   * belongs to a different moderator, appropriate error responses are
   * returned.
   *
   * Email verification is a required security measure before moderators can
   * exercise their full moderation capabilities. Moderators with unverified
   * emails (email_verified=false) may have limited access to moderation
   * features until verification is complete.
   *
   * @param connection
   * @param body Email verification token
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async verifyEmail(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedBody()
    body: IDiscussionBoardModerator.IVerifyEmail,
  ): Promise<void> {
    try {
      return await postAuthModeratorEmailVerifyConfirm({
        moderator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
