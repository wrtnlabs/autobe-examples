import { IDiscussionBoardReport } from "./IDiscussionBoardReport";
import { IDiscussionBoardModerationAction } from "./IDiscussionBoardModerationAction";
import { IDiscussionBoardUserSuspension } from "./IDiscussionBoardUserSuspension";
import { IDiscussionBoardModerationDashboardStatistics } from "./IDiscussionBoardModerationDashboardStatistics";

/**
 * Comprehensive moderation dashboard overview consolidating all critical
 * moderation information.
 *
 * This type provides moderators with a complete situational awareness snapshot,
 * aggregating data from multiple tables to enable efficient moderation
 * workflows. The dashboard overview serves as the primary entry point for
 * moderators, presenting pending work, ongoing reviews, recent team activity,
 * and system health metrics in a single unified response.
 *
 * The overview is designed to answer the moderator's key questions at a glance:
 * What needs my immediate attention (pending reports)? What are my teammates
 * working on (under review reports)? What enforcement actions have been taken
 * recently (recent moderation actions)? Which members are currently suspended
 * (active suspensions)? How is the moderation system performing overall
 * (statistics)?
 *
 * By consolidating this information from discussion_board_reports,
 * discussion_board_moderation_actions, and discussion_board_user_suspensions
 * tables, the dashboard enables single-call atomic information retrieval.
 * Moderators can load the dashboard and immediately understand the current
 * moderation state without making multiple sequential API calls for reports,
 * actions, and suspensions separately. This atomic operation design reduces
 * latency, simplifies client logic, and improves moderator productivity.
 *
 * The dashboard overview supports critical moderation workflows including daily
 * moderation queue review where moderators check pending reports and prioritize
 * review work, team coordination where moderators see what colleagues are
 * handling to avoid duplicate effort, enforcement oversight where moderators
 * monitor suspension expirations and enforcement patterns, and workload
 * assessment where moderation team leads evaluate whether current moderator
 * capacity is adequate.
 *
 * Each array in the overview is intentionally limited to recent or urgent items
 * to maintain fast response times. Pending reports show the most urgent issues
 * requiring immediate review, not the complete historical report archive.
 * Recent moderation actions cover the past 24 hours, not all historical
 * actions. Active suspensions show only current enforcement, not expired
 * historical suspensions. This scoping ensures the dashboard loads quickly even
 * as the moderation data grows over time.
 *
 * The statistics object provides quantitative metrics that complement the
 * qualitative report and action lists, giving moderators both detailed work
 * items and high-level system health indicators in a single comprehensive
 * response.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type IDiscussionBoardModerationDashboardOverview = {
  /**
   * List of pending content reports awaiting moderator review.
   *
   * This array contains all reports with status 'pending' that have not yet
   * been assigned to a moderator or begun review. Reports are ordered by
   * priority, with multiply-reported content and urgent reports appearing
   * first to help moderators address the most critical issues immediately.
   */
  pending_reports: IDiscussionBoardReport.ISummary[];

  /**
   * List of reports currently being reviewed by moderators.
   *
   * This array contains reports with status 'under_review', showing which
   * content is actively being evaluated by moderators. Each report indicates
   * which moderator is handling it, enabling team coordination and preventing
   * duplicate review efforts.
   */
  under_review_reports: IDiscussionBoardReport.ISummary[];

  /**
   * Recent moderation actions taken by all moderators in the past 24 hours.
   *
   * This array provides a chronological activity log of recent enforcement
   * decisions, content edits, deletions, warnings, and suspensions. It
   * enables moderators to see what actions their teammates have taken,
   * promoting consistency and coordination in enforcement standards.
   */
  recent_moderation_actions: IDiscussionBoardModerationAction.ISummary[];

  /**
   * Currently active user account suspensions.
   *
   * This array contains all suspensions where suspended_at is in the past,
   * expires_at is in the future (or null for permanent bans), and lifted_at
   * is null. It shows which members are currently prevented from accessing
   * their accounts, helping moderators track enforcement actions and upcoming
   * expirations.
   */
  active_suspensions: IDiscussionBoardUserSuspension.ISummary[];

  /**
   * Aggregated moderation system statistics and metrics.
   *
   * Provides quantitative overview of moderation workload, trends, and system
   * health including counts of pending reports, resolved reports, active
   * suspensions, recent warnings, and other key performance indicators for
   * the moderation system.
   */
  statistics: IDiscussionBoardModerationDashboardStatistics;
};
