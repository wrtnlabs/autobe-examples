  /**
   * Password change request DTO for authenticated member self-service
   * password management.
   *
   * This DTO represents the complete information required for a member to
   * securely update their account password. The password change operation is
   * a critical security function that must balance security requirements with
   * user convenience, implementing verification of current password
   * knowledge, enforcement of password strength requirements, and prevention
   * of common password-related mistakes.
   *
   * The three-field structure follows security best practices for password
   * change interfaces:
   *
   * 1. Current password verification ensures the authenticated user has actual
   *    account access (not just a stolen session token)
   * 2. New password field captures the desired new password with strength
   *    validation
   * 3. Confirmation field prevents typos that could lock users out of their
   *    accounts
   *
   * This DTO is used in the PUT
   * /discussionBoard/member/members/{memberUsername}/password operation,
   * which requires the authenticated member to be updating their own password
   * (verified by comparing the JWT token's member ID with the member
   * identified by the memberUsername path parameter). Members cannot use this
   * operation to change other members' passwords.
   *
   * Security context: The password change operation triggers several security
   * actions beyond updating the password_hash field. All existing JWT refresh
   * tokens are invalidated across all devices and sessions, forcing
   * re-authentication everywhere except the current session. This prevents
   * attackers who may have compromised old refresh tokens from maintaining
   * access after a password change. A confirmation email is sent to the
   * registered email address, enabling the legitimate account owner to detect
   * unauthorized password changes.
   *
   * Data flow: The DTO values are validated according to the business rules
   * defined in the Error Handling and Validation document. Current password
   * is verified against the stored hash. New password is validated for
   * strength requirements. Confirmation is verified to match the new
   * password. If all validations pass, the new password is securely hashed
   * and stored, replacing the old password_hash in the
   * discussion_board_members table.
   */
  export type IPasswordUpdate = {
    /**
     * The member's current password for verification and security
     * confirmation.
     *
     * This field is required to verify that the authenticated user has
     * knowledge of the current password before allowing the password
     * change. This prevents unauthorized password changes even if an
     * attacker has gained temporary session access through a stolen JWT
     * token or compromised browser session.
     *
     * The system validates this password against the stored password_hash
     * in the discussion_board_members table. If the current password is
     * incorrect, the password change request is rejected with an
     * appropriate error message.
     *
     * Validation rules for this field:
     *
     * - Required field, cannot be empty or null
     * - Must match the member's existing password exactly
     * - Validated using the same secure hashing comparison used for login
     *   authentication
     *
     * Security considerations:
     *
     * - This field is transmitted over HTTPS to protect the password in
     *   transit
     * - The password is never logged or stored in plain text
     * - Failed verification attempts are logged for security monitoring and
     *   potential account protection measures
     */
    current_password: string;

    /**
     * The new password that will replace the current password.
     *
     * This field must meet comprehensive password strength requirements to
     * ensure account security. The password is validated against multiple
     * criteria before being accepted, and the system provides real-time
     * feedback on password strength during the change process.
     *
     * Password strength requirements enforced by the system:
     *
     * - Minimum 8 characters in length (no maximum specified, but reasonable
     *   limits apply)
     * - Must contain at least one uppercase letter (A-Z)
     * - Must contain at least one lowercase letter (a-z)
     * - Must contain at least one numeric digit (0-9)
     * - Must contain at least one special character from the set:
     *   !@#$%^&*()_+-=[]{}|;:,.<>?
     * - Must differ from the current password (cannot reuse the same
     *   password)
     * - Should not match common compromised passwords (validated against
     *   breach databases)
     * - Should not contain the username or email address
     *
     * Password strength feedback: The system calculates password strength
     * based on length, character variety, and predictability, providing
     * feedback as weak, medium, or strong. While strong passwords are
     * encouraged, medium-strength passwords meeting the minimum
     * requirements are accepted.
     *
     * Security implementation: When this password is accepted, it is hashed
     * using a secure one-way hashing algorithm (bcrypt, Argon2, or
     * equivalent) with appropriate work factors and unique salts. The
     * resulting password_hash is stored in the discussion_board_members
     * table, replacing the old hash. The plain text password is never
     * stored or logged.
     */
    new_password: string;

    /**
     * Confirmation of the new password to prevent typos and ensure
     * intentional password selection.
     *
     * This field must exactly match the new_password field
     * character-for-character. The confirmation requirement prevents users
     * from accidentally setting a password they didn't intend due to typing
     * errors, which could lock them out of their account.
     *
     * Validation rules:
     *
     * - Required field, cannot be empty or null
     * - Must match new_password exactly (case-sensitive comparison)
     * - No additional validation beyond exact matching
     *
     * If the new_password and new_password_confirmation fields do not
     * match, the system rejects the password change request and displays an
     * error message: "Passwords do not match. Please ensure both password
     * fields are identical."
     *
     * User experience considerations: The system provides real-time
     * validation feedback, indicating whether the confirmation matches as
     * the user types. This immediate feedback helps users correct
     * mismatches before form submission, improving the user experience and
     * reducing frustration.
     */
    new_password_confirmation: string;
  };

  /**
   * Successful password change confirmation response with new authentication
   * tokens and security action details.
   *
   * This response DTO confirms that the member's password has been
   * successfully updated and provides all necessary information for the
   * client to continue authenticated access with the new credentials. The
   * response includes new JWT tokens to replace the invalidated ones, a count
   * of terminated sessions to inform the user of the security impact, and a
   * timestamp for audit trail purposes.
   *
   * Security workflow completed: When this response is returned, the
   * following security actions have been successfully completed:
   *
   * 1. Current password was verified against the stored password_hash
   * 2. New password was validated against all strength requirements and security
   *    policies
   * 3. New password was securely hashed using bcrypt or equivalent algorithm
   *    with appropriate work factor
   * 4. Password_hash field in discussion_board_members table was updated with
   *    the new hash
   * 5. All existing JWT refresh tokens (except current session) were invalidated
   *    and marked as expired
   * 6. New access token and refresh token were generated for the current session
   * 7. Security event was logged with timestamp, IP address, and session
   *    information
   * 8. Confirmation email was sent to the member's registered email address
   *
   * Client responsibilities upon receiving this response:
   *
   * 1. Replace stored access_token with the new token.access_token value
   * 2. Replace stored refresh_token with the new token.refresh_token value
   * 3. Update token expiration tracking with token.expires_at
   * 4. Display success confirmation to the user
   * 5. Optionally inform user that other sessions were logged out (using
   *    sessions_invalidated_count)
   *
   * Session continuity: The member remains logged in on the current device
   * and session because new tokens are provided. However, all other devices
   * and sessions are terminated and will require the user to log in again
   * with the new password. This security measure ensures that any potentially
   * compromised sessions are immediately invalidated when the password
   * changes.
   *
   * Error scenarios: If the password change fails, this response is not
   * returned. Instead, the API returns appropriate error responses:
   *
   * - 401 Unauthorized if current_password verification fails
   * - 400 Bad Request if new_password fails strength validation
   * - 403 Forbidden if the member attempts to change another member's password
   * - 500 Internal Server Error if the password update or token invalidation
   *   process encounters a system error
   *
   * This response type is critical for maintaining account security while
   * providing a seamless user experience during password changes, a balance
   * achieved through the token refresh mechanism that keeps the current
   * session active while protecting all other sessions.
   */
  export type IPasswordChange = {
    /**
     * Unique identifier of the member account whose password was
     * successfully changed.
     *
     * This UUID corresponds to the discussion_board_members.id field and
     * confirms which account was modified by the password change operation.
     * The ID is included in the response for client-side verification and
     * logging purposes, ensuring the frontend can confirm the correct
     * account was updated.
     *
     * The ID value matches the authenticated member's ID from the JWT
     * token, as members can only change their own passwords through this
     * self-service operation.
     */
    id: string & tags.Format<"uuid">;

    /**
     * New JWT token information issued after successful password change.
     *
     * When a member changes their password, the system invalidates all
     * existing JWT refresh tokens across all devices and sessions as a
     * security measure. This prevents attackers who may have compromised
     * old tokens from maintaining access after the password change.
     *
     * A new refresh token is immediately issued for the current session to
     * maintain the user's authenticated state. The member does not need to
     * log in again on the current device, but all other sessions (other
     * browsers, devices) are terminated and require fresh authentication
     * with the new password.
     *
     * The token object contains:
     *
     * - Access_token: Short-lived JWT for API authentication (30-minute
     *   expiration)
     * - Refresh_token: Long-lived JWT for obtaining new access tokens (14-day
     *   expiration)
     * - Expires_at: Timestamp when the access token expires
     *
     * Clients should replace their stored tokens with these new values
     * immediately upon receiving this response to ensure continued
     * authenticated access.
     */
    token: IAuthorizationToken;

    /**
     * Number of active sessions that were invalidated across all devices as
     * a result of the password change.
     *
     * This count represents how many active login sessions existed for the
     * member account before the password change operation. All of these
     * sessions have been terminated (their refresh tokens invalidated),
     * except for the current session which received new tokens.
     *
     * The count provides transparency to the user about the security impact
     * of their password change:
     *
     * - 0: No other active sessions (user was only logged in on current
     *   device)
     * - 1: One other session was terminated (e.g., user was logged in on
     *   desktop and mobile)
     * - 2+: Multiple other sessions were terminated (user was logged in
     *   across many devices)
     *
     * This information helps users understand the scope of the security
     * action and confirms that potential unauthorized sessions have been
     * terminated. If the count is higher than expected, it may indicate
     * unauthorized access that has now been blocked.
     *
     * From a security perspective, this metric is valuable for security
     * auditing and user awareness, helping members recognize when their
     * account may have been compromised if they see session counts that
     * don't match their expected usage patterns.
     */
    sessions_invalidated_count: number & tags.Type<"int32">;

    /**
     * Timestamp when the password was successfully changed.
     *
     * This ISO 8601 formatted datetime (e.g., 2025-01-15T10:30:00Z) records
     * the exact moment the password_hash field in the
     * discussion_board_members table was updated with the new password
     * hash. The timestamp serves multiple purposes:
     *
     * 1. Security Audit Trail: Provides precise timing for security event
     *    logging, enabling investigation of potential unauthorized password
     *    changes and correlating password changes with other security
     *    events.
     * 2. User Confirmation: Gives the member a specific reference point for
     *    when their password was changed, useful for verifying the change
     *    occurred as expected and for reporting purposes if the change was
     *    unauthorized.
     * 3. Session Management: Marks the cutoff point before which all refresh
     *    tokens were invalidated. Any refresh token issued before this
     *    timestamp is no longer valid.
     * 4. Compliance and Logging: Supports security compliance requirements for
     *    tracking authentication credential changes and maintaining
     *    detailed audit logs.
     *
     * The timestamp is also included in the confirmation email sent to the
     * member's registered email address, providing an additional security
     * verification mechanism. If the member did not initiate the password
     * change, they can see exactly when the unauthorized change occurred
     * and take immediate action to secure their account.
     */
    password_updated_at: string & tags.Format<"date-time">;

    /**
     * Timestamp when the member account record was last modified in the
     * database.
     *
     * This corresponds to the updated_at field in the
     * discussion_board_members table, which is automatically updated by the
     * system whenever any field in the member record changes. In the
     * context of a password change response, this timestamp reflects when
     * the password_hash field was updated and should match the
     * password_updated_at value.
     *
     * Including this field in the response maintains consistency with the
     * member entity schema and provides complete account state information.
     * The updated_at timestamp serves as a general-purpose modification
     * tracker for the entire member record, while password_updated_at
     * specifically tracks the password change event.
     *
     * This field enables clients to maintain synchronized state with the
     * server, detect concurrent modifications to the account, and provide
     * accurate last-modified information in user interface displays. The
     * timestamp is in ISO 8601 format with timezone information, typically
     * in UTC, matching the database storage format (timestamptz).
     */
    updated_at: string & tags.Format<"date-time">;
  };
