import { tags } from "typia";

import { IDiscussionBoardModerationLog } from "./IDiscussionBoardModerationLog";

/**
 * Real-time moderation dashboard overview with key metrics and pending tasks.
 *
 * This computed DTO aggregates data from multiple tables to provide moderators
 * with an at-a-glance view of platform health, pending work, and recent
 * enforcement activity. It combines counts, statistics, and summaries from
 * discussion_board_content_reports (pending reports needing review),
 * discussion_board_articles (recently published content),
 * discussion_board_account_actions (active suspensions and bans), and
 * discussion_board_moderation_logs (recent moderator activity across the
 * team).
 *
 * The dashboard serves as the entry point for moderators' daily workflow,
 * helping them prioritize tasks based on urgency and volume. High pending
 * report counts signal backlog requiring immediate attention, while low recent
 * activity combined with growing content volume may indicate need for
 * additional moderator resources. The recent actions summary provides team-wide
 * visibility into enforcement patterns and workload distribution.
 *
 * This is not a persistent entity but rather a computed aggregation response.
 * The data is calculated on-demand when moderators access the dashboard,
 * ensuring real-time accuracy. All counts and statistics reflect current
 * database state at the moment of request.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type IDiscussionBoardModerationDashboard = {
  /**
   * Number of content reports submitted by members that are currently pending
   * moderator review (status='pending'). Indicates backlog of flagged content
   * requiring attention. High counts signal need for immediate moderator
   * action.
   */
  pending_reports_count: number & tags.Type<"int32"> & tags.Minimum<0>;

  /**
   * Number of published articles that have received multiple content reports
   * or are flagged for immediate review. Represents content with community
   * concerns requiring moderator judgment and potential action.
   */
  flagged_articles_count: number & tags.Type<"int32"> & tags.Minimum<0>;

  /**
   * Number of member accounts currently suspended or banned (status='active'
   * in account_actions). Indicates current enforcement level and members
   * blocked from platform access. Includes both temporary suspensions and
   * permanent bans.
   */
  active_suspensions_count: number & tags.Type<"int32"> & tags.Minimum<0>;

  /**
   * Number of moderation actions performed by all moderators in the past 24
   * hours. Provides visibility into team-wide enforcement activity level.
   * Includes content moderation (edits, deletions) and account actions
   * (suspensions, bans).
   */
  recent_moderation_actions_count: number &
    tags.Type<"int32"> &
    tags.Minimum<0>;

  /**
   * Most recent moderation actions taken by any moderator in the past 24
   * hours, limited to 10 entries. Provides quick overview of recent
   * enforcement activity for team coordination and pattern awareness. Sorted
   * by timestamp descending (newest first).
   */
  recent_moderation_actions: IDiscussionBoardModerationLog.ISummary[] &
    tags.MaxItems<10>;

  /**
   * Number of articles published in the past 24 hours. Indicates content
   * creation velocity and potential need for quality review. High publication
   * rates may require additional moderator attention to ensure content
   * quality.
   */
  recent_published_articles_count: number &
    tags.Type<"int32"> &
    tags.Minimum<0>;
};
