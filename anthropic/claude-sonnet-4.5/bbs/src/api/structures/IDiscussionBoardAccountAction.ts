import { tags } from "typia";

/**
 * Complete account action record representing a suspension or ban applied to a
 * member account.
 *
 * This entity tracks all temporary suspensions and permanent bans applied to
 * discussion board members, maintaining a comprehensive history of disciplinary
 * actions. Each record captures the complete lifecycle of an enforcement action
 * including who was affected, who applied it, why it was applied, how long it
 * lasts, and whether it was reversed.
 *
 * Temporary suspensions prevent members from logging in and creating content
 * for a specified duration (1, 7, 14, or 30 days). When the suspension period
 * expires, the account is automatically restored to active status through the
 * status field transitioning from 'active' to 'expired'. Permanent bans prevent
 * all future access indefinitely and are typically reserved for severe or
 * repeated policy violations.
 *
 * Moderators can reverse suspensions or bans if they were applied in error or
 * if circumstances change. All status transitions are tracked with timestamps
 * to maintain complete audit trails for accountability and transparency. The
 * action history enables informed moderation decisions about enforcement
 * escalation based on violation patterns.
 *
 * This type is used in response bodies when retrieving or updating account
 * actions, providing complete visibility into the current state and history of
 * enforcement actions against member accounts.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type IDiscussionBoardAccountAction = {
  /**
   * Primary key uniquely identifying this account action record.
   *
   * This UUID is automatically generated when a moderator applies a
   * suspension or ban to a member account. It serves as the stable reference
   * for querying, updating, or reversing specific account actions throughout
   * their lifecycle.
   */
  id: string & tags.Format<"uuid">;

  /**
   * Identifier of the member whose account was suspended or banned.
   *
   * References the discussion_board_members table to establish which member
   * is affected by this disciplinary action. This foreign key enables
   * querying all enforcement actions taken against a specific member to
   * review their violation history and ensure consistent escalation of
   * consequences.
   */
  discussion_board_member_id: string & tags.Format<"uuid">;

  /**
   * Identifier of the moderator who applied this suspension or ban.
   *
   * References the discussion_board_moderators table to track which moderator
   * initiated this account action. This attribution maintains accountability
   * for enforcement decisions and enables analysis of moderator activity
   * patterns to ensure consistent application of community guidelines.
   */
  discussion_board_moderator_id: string & tags.Format<"uuid">;

  /**
   * Identifier of the moderator who reversed or lifted this suspension or
   * ban.
   *
   * References the discussion_board_moderators table when an action is
   * reversed. Null indicates the action has not been reversed and remains in
   * its original state. This field enables tracking which moderator made the
   * decision to restore account access and supports review of reversal
   * patterns.
   */
  reversed_by_moderator_id?: (string & tags.Format<"uuid">) | null | undefined;

  /**
   * Type of account action applied to the member.
   *
   * Valid values are 'suspension' for temporary account blocks with automatic
   * expiration, or 'ban' for permanent account blocks with no expiration.
   * This discriminator determines whether the action has an associated
   * duration_days and expires_at timestamp.
   */
  action_type: "suspension" | "ban";

  /**
   * Moderator's documented reason for suspending or banning the account.
   *
   * Required for accountability and transparency, this field explains the
   * specific policy violation or behavior that triggered the enforcement
   * action. The reason is communicated to the affected member and serves as
   * documentation for future moderation decisions. Examples include 'Repeated
   * spam violations', 'Harassment of other members', or 'Severe policy
   * violation'.
   */
  reason: string;

  /**
   * Duration of the suspension in days.
   *
   * For temporary suspensions, this field specifies how many days the
   * member's account will be blocked. Valid values are 1, 7, 14, or 30 days
   * to support standard enforcement escalation patterns. Null for permanent
   * bans which have no expiration. This value is used to calculate the
   * expires_at timestamp.
   */
  duration_days?: 1 | 7 | 14 | 30 | null | undefined;

  /**
   * Current status of the account action.
   *
   * Valid values indicate whether the action is currently in effect: 'active'
   * means the member is currently blocked from the platform, 'expired' means
   * a temporary suspension period has ended and the account is restored,
   * 'reversed' means a moderator manually lifted the action before its
   * natural expiration. This field determines whether the member can
   * currently access their account.
   */
  status: "active" | "expired" | "reversed";

  /**
   * Explanation for why the suspension or ban was reversed by a moderator.
   *
   * Null if the action has not been reversed. When present, provides
   * transparency about why the original enforcement decision was overturned.
   * Examples include 'Applied in error', 'User successfully appealed', or
   * 'Circumstances changed'. This documentation maintains accountability for
   * reversal decisions.
   */
  reversal_reason?: string | null | undefined;

  /**
   * Timestamp when the suspension or ban was applied.
   *
   * Records the exact moment the moderator initiated this account action.
   * Used to calculate expiration times for temporary suspensions by adding
   * duration_days to this timestamp. Also enables chronological tracking of
   * enforcement history and analysis of violation patterns over time.
   */
  created_at: string & tags.Format<"date-time">;

  /**
   * Timestamp when a temporary suspension will automatically expire.
   *
   * For suspensions, this is calculated as created_at plus duration_days.
   * When this time is reached, the system automatically updates the status to
   * 'expired' and restores account access. Null for permanent bans which
   * never expire. This field enables automated enforcement lifecycle
   * management.
   */
  expires_at?: (string & tags.Format<"date-time">) | null | undefined;

  /**
   * Timestamp when a moderator reversed or lifted the suspension or ban.
   *
   * Null if the action has not been reversed. When present, indicates exactly
   * when the moderator decided to restore account access manually rather than
   * waiting for automatic expiration. This timestamp supports audit trails
   * and analysis of reversal patterns.
   */
  reversed_at?: (string & tags.Format<"date-time">) | null | undefined;
};
