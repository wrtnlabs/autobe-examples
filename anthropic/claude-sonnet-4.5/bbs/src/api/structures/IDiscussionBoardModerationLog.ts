/**
 * Comprehensive audit trail entry recording a specific moderator action for
 * accountability and transparency.
 *
 * Records every content moderation and user management action taken by
 * moderators, including article edits, article deletions, attachment removals,
 * account suspensions, and account bans. Each log entry captures what action
 * was taken, which moderator performed it, what content or user was affected,
 * when it occurred, and the moderator's documented reason.
 *
 * The moderation log serves multiple critical purposes: accountability
 * (tracking who did what and why), transparency (allowing review of moderation
 * decisions), dispute resolution (providing evidence for appeals), and pattern
 * analysis (identifying problematic content or users requiring escalated
 * action).
 *
 * Log entries are immutable and retained indefinitely per business
 * requirements. Moderators and administrators can search and filter logs by
 * action type, moderator, affected content, affected user, or time period to
 * review moderation history, investigate specific incidents, or generate
 * moderation activity reports.
 *
 * This comprehensive audit trail ensures moderation decisions are documented,
 * reviewable, and consistent with community guidelines.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type IDiscussionBoardModerationLog = {
  /**
   * Primary Key.
   *
   * Unique identifier for this moderation log entry. Auto-generated when the
   * moderation action is recorded and used for retrieving specific log
   * entries from the audit trail.
   */
  id: string & tags.Format<"uuid">;

  /**
   * Moderator who performed this moderation action.
   *
   * References discussion_board_moderators.id to establish accountability for
   * this specific moderation decision. Critical for audit trail integrity and
   * tracking which moderator took what actions.
   */
  discussion_board_moderator_id: string & tags.Format<"uuid">;

  /**
   * Summary information about the moderator who performed this action.
   *
   * Provides moderator username and identification for audit trail
   * transparency. Enables quick identification of which moderator took this
   * action without requiring additional API calls.
   */
  moderator: IDiscussionBoardModerator.ISummary;

  /**
   * Type of moderation action performed.
   *
   * Valid values: 'article_edited' (moderator edited article content),
   * 'article_deleted' (moderator removed article), 'attachment_removed'
   * (moderator deleted specific attachment), 'account_suspended' (member
   * account temporarily suspended), 'account_banned' (member account
   * permanently banned), 'account_restored' (suspension or ban reversed).
   * Categorizes the moderation action for filtering and analysis.
   */
  action_type: string;

  /**
   * Moderator's documented explanation for taking this action.
   *
   * Required for all moderation actions to ensure accountability and
   * transparency. Examples: 'Removed spam content', 'Suspended for
   * harassment', 'Edited to remove personal information'. Provides context
   * for why this moderation decision was made.
   */
  reason: string;

  /**
   * Additional contextual details about the moderation action.
   *
   * May include what was changed in an edit, which attachment was removed, or
   * specific policy violations cited. Provides complete context for the audit
   * trail beyond the basic reason field.
   */
  action_details?: string | undefined;

  /**
   * Article that was moderated (edited, deleted, or had attachments removed).
   *
   * Null if action was user account management rather than content
   * moderation. References discussion_board_articles.id to link this log
   * entry to the affected content.
   */
  discussion_board_article_id?: (string & tags.Format<"uuid">) | undefined;

  /**
   * Summary information about the article that was moderated.
   *
   * Provides article title and basic context for content moderation actions.
   * Null if this log entry records account management actions rather than
   * content moderation.
   */
  article?: IDiscussionBoardArticle.ISummary | undefined;

  /**
   * Member whose account was affected by moderator action.
   *
   * Null if action was content moderation rather than account management.
   * References discussion_board_members.id for account suspensions, bans, or
   * restorations.
   */
  discussion_board_member_id?: (string & tags.Format<"uuid">) | undefined;

  /**
   * Summary information about the member whose account was affected.
   *
   * Provides member username and profile information for account management
   * actions (suspension, ban, restoration). Null if this log entry records
   * content moderation rather than account actions.
   */
  affectedMember?: IDiscussionBoardMember.ISummary | undefined;

  /**
   * Timestamp when the moderation action was performed.
   *
   * Used for chronological audit trail ordering, moderation activity
   * reporting, and tracking response times. Immutable once recorded to
   * maintain audit trail integrity.
   */
  created_at: string & tags.Format<"date-time">;
};
