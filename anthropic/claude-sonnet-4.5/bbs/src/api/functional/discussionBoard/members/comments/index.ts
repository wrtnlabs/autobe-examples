import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardComment } from "../../../../structures/IDiscussionBoardComment";
import { IPageIDiscussionBoardComment } from "../../../../structures/IPageIDiscussionBoardComment";

/**
 * Retrieve paginated list of comments posted by a specific member.
 *
 * Retrieve a filtered and paginated list of comments posted by a specific
 * member identified by their username. This operation enables users to explore
 * the complete collection of comments and discussion contributions made by a
 * particular member across all articles on the discussion board platform.
 *
 * The operation supports comprehensive filtering and sorting capabilities
 * including filtering by parent article to see comments on specific articles,
 * date range filtering to focus on recent or historical contributions, search
 * within the member's comments by content keywords to find specific
 * discussions, and multiple sorting options such as newest first, oldest first,
 * or grouped by article. This enables efficient discovery of a member's
 * discussion participation and engagement patterns.
 *
 * This operation queries the discussion_board_comments table with a filter on
 * the member author relationship (discussion_board_member_id) matching the
 * member identified by the username path parameter. The response includes
 * comment summaries with essential metadata including comment content preview,
 * parent article information (title and link), posting timestamp, and edit
 * indicators if the comment has been modified. The operation respects
 * single-level threading showing both top-level comments and replies authored
 * by the member.
 *
 * Security and privacy considerations include respecting the member's activity
 * visibility settings as defined in their profile (public, members_only, or
 * hidden). When a member's activity visibility is set to hidden, only the
 * member themselves and moderators can view their comment list. When set to
 * members_only, only authenticated members can access the list. Public activity
 * is accessible to all users including guests. Comments on deleted articles are
 * excluded from results. Soft-deleted comments are excluded from public results
 * but may be visible to moderators for audit purposes. The operation supports
 * pagination to handle members with extensive comment histories efficiently,
 * ensuring fast response times even for highly active discussants with
 * thousands of comments.
 *
 * @param props.connection
 * @param props.memberUsername Unique username of the target member whose
 *   comments are being retrieved
 * @param props.body Search criteria, filtering options, and pagination
 *   parameters for retrieving member's comments
 * @path /discussionBoard/members/:memberUsername/comments
 * @accessor api.functional.discussionBoard.members.comments.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Unique username of the target member whose comments are being
     * retrieved
     */
    memberUsername: string;

    /**
     * Search criteria, filtering options, and pagination parameters for
     * retrieving member's comments
     */
    body: IDiscussionBoardComment.IRequest;
  };
  export type Body = IDiscussionBoardComment.IRequest;
  export type Response = IPageIDiscussionBoardComment.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/discussionBoard/members/:memberUsername/comments",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/discussionBoard/members/${encodeURIComponent(props.memberUsername ?? "null")}/comments`;
  export const random = (): IPageIDiscussionBoardComment.ISummary =>
    typia.random<IPageIDiscussionBoardComment.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("memberUsername")(() => typia.assert(props.memberUsername));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
