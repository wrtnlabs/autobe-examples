import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardArticle } from "../../../../structures/IDiscussionBoardArticle";
import { IPageIDiscussionBoardArticle } from "../../../../structures/IPageIDiscussionBoardArticle";

/**
 * Retrieve paginated list of articles authored by a specific member.
 *
 * Retrieve a filtered and paginated list of articles authored by a specific
 * member identified by their username. This operation enables users to explore
 * the complete collection of articles published by a particular member,
 * providing insight into their contributions to economic and political
 * discussions on the platform.
 *
 * The operation supports comprehensive filtering and sorting capabilities
 * including publication status filters, category and tag filters, date range
 * filtering, search within the member's articles by title or content keywords,
 * and multiple sorting options such as newest first, oldest first, most viewed,
 * or most commented. This enables efficient discovery of specific content
 * within a member's publishing history.
 *
 * This operation queries the discussion_board_articles table with a filter on
 * the author relationship (discussion_board_member_id) matching the member
 * identified by the username path parameter. The response includes article
 * summaries optimized for list display with essential metadata including title,
 * summary excerpt, publication date, view count, comment count, categories, and
 * tags. For members viewing their own articles, the response may include
 * additional private information such as draft status or edit capabilities.
 *
 * Security and privacy considerations include respecting the member's activity
 * visibility settings as defined in their profile (public, members_only, or
 * hidden). When a member's activity visibility is set to hidden, only the
 * member themselves and moderators can view their article list. When set to
 * members_only, only authenticated members can access the list. Public activity
 * is accessible to all users including guests. The operation supports
 * pagination to handle members with extensive publication histories
 * efficiently, ensuring fast response times even for prolific authors with
 * hundreds of articles.
 *
 * @param props.connection
 * @param props.memberUsername Unique username of the target member whose
 *   articles are being retrieved
 * @param props.body Search criteria, filtering options, and pagination
 *   parameters for retrieving member's articles
 * @path /discussionBoard/members/:memberUsername/articles
 * @accessor api.functional.discussionBoard.members.articles.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Unique username of the target member whose articles are being
     * retrieved
     */
    memberUsername: string;

    /**
     * Search criteria, filtering options, and pagination parameters for
     * retrieving member's articles
     */
    body: IDiscussionBoardArticle.IRequest;
  };
  export type Body = IDiscussionBoardArticle.IRequest;
  export type Response = IPageIDiscussionBoardArticle.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/discussionBoard/members/:memberUsername/articles",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/discussionBoard/members/${encodeURIComponent(props.memberUsername ?? "null")}/articles`;
  export const random = (): IPageIDiscussionBoardArticle.ISummary =>
    typia.random<IPageIDiscussionBoardArticle.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("memberUsername")(() => typia.assert(props.memberUsername));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
