import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardArticle } from "../../../../structures/IDiscussionBoardArticle";
import { IPageIDiscussionBoardArticle } from "../../../../structures/IPageIDiscussionBoardArticle";

/**
 * Retrieve a filtered and paginated list of discussion articles authored by a
 * specific member from the discussion board platform.
 *
 * This operation provides comprehensive search and filtering capabilities for
 * discovering articles created by a particular member. It supports filtering by
 * article status (draft, published, archived), publication date ranges,
 * category selection, and full-text search across article titles and content.
 * Results can be sorted by various criteria including publication date,
 * creation date, view count, and last update timestamp.
 *
 * Authorization logic: Unauthenticated guests can ONLY view published articles.
 * Authenticated members can view their own draft, published, and archived
 * articles when the memberId parameter matches their authenticated user ID from
 * the JWT token. When viewing other members' articles (memberId doesn't match
 * token), authenticated members see only published articles. Moderators can
 * view all article states for any member.
 *
 * Security considerations include rate limiting for search operations to
 * prevent abuse, proper sanitization of search query inputs to prevent
 * injection attacks, and visibility controls based on article status and
 * requester authorization level. The view_count field is read-only and should
 * not be modified through this search operation. The filtering logic respects
 * soft deletion, excluding articles with deleted_at timestamps unless
 * specifically requested by authorized moderators.
 *
 * This operation integrates with the discussion_board_articles table as defined
 * in the Prisma schema, referencing the discussion_board_member_id foreign key
 * to establish article ownership. The response includes article summary
 * information optimized for list displays, with options to include author
 * details, category information, and engagement metrics based on the request
 * parameters.
 *
 * @param props.connection
 * @param props.memberId Unique identifier of the target member whose articles
 *   are being retrieved
 * @param props.body Search criteria, filtering options, pagination parameters,
 *   and sorting preferences for member articles
 * @path /discussionBoard/members/:memberId/articles
 * @accessor api.functional.discussionBoard.members.articles.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Unique identifier of the target member whose articles are being
     * retrieved
     */
    memberId: string & tags.Format<"uuid">;

    /**
     * Search criteria, filtering options, pagination parameters, and
     * sorting preferences for member articles
     */
    body: IDiscussionBoardArticle.IRequest;
  };
  export type Body = IDiscussionBoardArticle.IRequest;
  export type Response = IPageIDiscussionBoardArticle.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/discussionBoard/members/:memberId/articles",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/discussionBoard/members/${encodeURIComponent(props.memberId ?? "null")}/articles`;
  export const random = (): IPageIDiscussionBoardArticle.ISummary =>
    typia.random<IPageIDiscussionBoardArticle.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("memberId")(() => typia.assert(props.memberId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
