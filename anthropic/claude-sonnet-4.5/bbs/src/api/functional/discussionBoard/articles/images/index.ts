/**
 * Search and retrieve paginated list of image attachments for a specific
 * article.
 *
 * Retrieve a filtered and paginated list of image attachments associated with a
 * specific discussion board article. This operation provides comprehensive
 * search and filtering capabilities for browsing images attached to an article,
 * supporting queries based on image metadata such as dimensions, file size,
 * MIME type, upload date, and uploader information.
 *
 * The operation operates on the discussion_board_article_images table, which
 * stores image attachments in supported formats (JPEG, PNG, GIF, WebP) with a
 * maximum size of 5MB per image. Each image record includes original and stored
 * filenames, MIME type, file size in bytes, dimensions (width and height in
 * pixels), upload timestamp, and uploader tracking. The response includes
 * comprehensive image metadata to support display optimization and file
 * management. Images with deleted_at timestamp set are automatically excluded
 * from results, ensuring only active attachments are returned to users.
 *
 * Access control follows the article visibility model: if the parent article is
 * publicly visible, all users including guests can retrieve its image list. The
 * operation respects soft deletion - images with non-null deleted_at timestamps
 * are excluded from results unless specifically requested by moderators.
 * Pagination is implemented to handle articles with many attached images
 * efficiently, with configurable page sizes and sorting options including
 * upload date, file size, and image dimensions.
 *
 * This operation is particularly useful for image gallery views, attachment
 * management interfaces, and scenarios where users need to browse or download
 * multiple images from an article. The search capabilities enable filtering by
 * specific image characteristics, making it easy to find images meeting
 * particular criteria such as size ranges or upload timeframes. The operation
 * is optimized for articles with up to 10 image attachments (the system maximum
 * per article) and returns results within 2 seconds under normal load
 * conditions.
 *
 * @param props.connection
 * @param props.articleId Unique identifier of the parent article whose image
 *   attachments are being retrieved
 * @param props.body Search criteria, filtering options, and pagination
 *   parameters for querying article image attachments
 * @path /discussionBoard/articles/:articleId/images
 * @accessor api.functional.discussionBoard.articles.images.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Unique identifier of the parent article whose image attachments are
     * being retrieved
     */
    articleId: string & tags.Format<"uuid">;

    /**
     * Search criteria, filtering options, and pagination parameters for
     * querying article image attachments
     */
    body: IDiscussionBoardArticleImage.IRequest;
  };
  export type Body = IDiscussionBoardArticleImage.IRequest;
  export type Response = IPageIDiscussionBoardArticleImage.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/discussionBoard/articles/:articleId/images",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/discussionBoard/articles/${encodeURIComponent(props.articleId ?? "null")}/images`;
  export const random = (): IPageIDiscussionBoardArticleImage.ISummary =>
    typia.random<IPageIDiscussionBoardArticleImage.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("articleId")(() => typia.assert(props.articleId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

