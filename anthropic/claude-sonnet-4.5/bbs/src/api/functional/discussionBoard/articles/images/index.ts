/**
 * Retrieve a filtered, paginated list of images attached to a specific
 * discussion board article.
 *
 * Retrieve a comprehensive list of image attachments for a specific discussion
 * board article with advanced filtering and pagination capabilities.
 *
 * This operation provides flexible querying of article images, supporting
 * search criteria such as original filename matching, content type filters
 * (image/jpeg, image/png, image/gif, image/webp), file size constraints,
 * dimension filters (width and height), and upload date ranges. The response is
 * paginated to efficiently handle articles with numerous image attachments.
 *
 * Security considerations include ensuring that only images belonging to the
 * specified article are returned. The operation respects the article's
 * visibility settings - if the article is not accessible to the requesting
 * user, the image list should not be exposed. By default, soft-deleted images
 * (deleted_at IS NOT NULL) are excluded from results. Rate limiting applies to
 * prevent abuse of the search functionality.
 *
 * The operation integrates with the discussion_board_article_images table as
 * defined in the Prisma schema, incorporating all available image metadata
 * including original_filename, file_size, content_type, storage_url, dimensions
 * (width and height when available), created_at timestamp, and deleted_at
 * status. The response includes image summary information optimized for list
 * displays.
 *
 * @param props.connection
 * @param props.articleId Unique identifier of the target discussion board
 *   article (global scope)
 * @param props.body Search criteria, filtering options (filename, content type,
 *   file size, dimensions, upload date), sorting preferences, and pagination
 *   parameters for article image retrieval
 * @path /discussionBoard/articles/:articleId/images
 * @accessor api.functional.discussionBoard.articles.images.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Unique identifier of the target discussion board article (global
     * scope)
     */
    articleId: string & tags.Format<"uuid">;

    /**
     * Search criteria, filtering options (filename, content type, file
     * size, dimensions, upload date), sorting preferences, and pagination
     * parameters for article image retrieval
     */
    body: IDiscussionBoardArticleImage.IRequest;
  };
  export type Body = IDiscussionBoardArticleImage.IRequest;
  export type Response = IPageIDiscussionBoardArticleImage.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/discussionBoard/articles/:articleId/images",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/discussionBoard/articles/${encodeURIComponent(props.articleId ?? "null")}/images`;
  export const random = (): IPageIDiscussionBoardArticleImage.ISummary =>
    typia.random<IPageIDiscussionBoardArticleImage.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("articleId")(() => typia.assert(props.articleId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

