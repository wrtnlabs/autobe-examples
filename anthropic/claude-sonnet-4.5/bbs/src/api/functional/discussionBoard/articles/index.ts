/**
 * Search and retrieve a filtered, paginated list of discussion board articles.
 *
 * Retrieve a filtered and paginated list of discussion articles from the
 * platform with advanced search capabilities for discovering economic and
 * political discussions. This operation provides comprehensive querying
 * functionality to find articles based on multiple criteria including text
 * search, category selection, publication status, author identification, date
 * ranges, and popularity metrics.
 *
 * The operation queries the discussion_board_articles table and supports
 * full-text search across article titles and body content using the GIN indexes
 * defined in the Prisma schema. Users can filter articles by category (Economic
 * Discussion, Political Discussion, General Discussion), publication status
 * (draft, published, archived), author membership, publication date ranges, and
 * view count thresholds to identify popular discussions. Text search enables
 * keyword-based discovery across the title and body fields.
 *
 * Results can be sorted by multiple criteria including publication date (newest
 * first for discovery), view count (most popular first), creation date, or last
 * update timestamp. Pagination parameters allow efficient navigation through
 * large result sets with configurable page sizes. The operation returns article
 * summaries optimized for list displays, including title, excerpt, author
 * information, category, publication date, view count, and edit status.
 *
 * Security and visibility rules are enforced based on the requesting user's
 * authentication status. Guest users and members see only published articles,
 * while moderators can search across all statuses including drafts and archived
 * content for moderation purposes. Draft articles are visible only to their
 * authors unless the requester is a moderator. The deleted_at soft deletion
 * timestamp filters out deleted articles from all user-facing results.
 *
 * The operation integrates with the discussion_board_articles,
 * discussion_board_article_categories, and discussion_board_members tables as
 * defined in the Prisma schema. Response data includes denormalized author
 * display names and category information to minimize additional queries. The
 * excerpt field provides the first 200 characters of body content for preview
 * purposes in article listings.
 *
 * This operation serves as the primary article discovery mechanism for the
 * discussion board, supporting homepage listings, category browsing, search
 * results, and author-specific article collections. It should be called before
 * individual article detail retrieval to help users identify relevant
 * discussions.
 *
 * @param props.connection
 * @param props.body Search criteria, filtering options, sorting preferences,
 *   and pagination parameters for article discovery
 * @path /discussionBoard/articles
 * @accessor api.functional.discussionBoard.articles.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
