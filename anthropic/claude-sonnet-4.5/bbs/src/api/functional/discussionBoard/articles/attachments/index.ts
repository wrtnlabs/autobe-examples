/**
 * Search and retrieve paginated list of attachments for a specific article.
 *
 * Retrieves a filtered and paginated list of attachments associated with a
 * specific discussion article. This operation provides advanced search
 * capabilities for finding attachments based on type, format, size, filename,
 * and upload date criteria.
 *
 * Attachments support articles with visual evidence, charts, documents, and
 * reference materials. The unified attachment table handles both image
 * attachments (displayed inline in articles) and document attachments (provided
 * as downloadable links). Each attachment belongs to exactly one article and
 * includes complete metadata for display and download purposes.
 *
 * The operation supports comprehensive filtering including attachment type
 * discrimination (image vs file), specific format filtering (jpeg, png, pdf,
 * docx, etc.), file size range filtering, and date range filtering by upload
 * timestamp. Search functionality allows finding attachments by original
 * filename using partial text matching. This enables users to locate specific
 * supporting materials within articles that have multiple attachments.
 *
 * Sorting capabilities include ordering by creation date (newest or oldest
 * first), file size (largest or smallest first), and alphabetical filename
 * sorting. Pagination with configurable page size ensures efficient loading of
 * articles with many attachments. The default sort order is creation date
 * descending (most recently uploaded first).
 *
 * Security considerations include verifying that the parent article exists and
 * is accessible to the requesting user. While attachments in published articles
 * are publicly viewable by all users including guests, attachments in draft
 * articles are only accessible to the article author. The system enforces these
 * visibility rules based on the parent article's status field.
 *
 * The response includes comprehensive attachment details: unique attachment ID,
 * attachment type (image or file), specific format (file extension), file size
 * in bytes, original filename provided during upload, storage path reference
 * for retrieval, uploader member ID, upload timestamp, last update timestamp,
 * and soft deletion status. This complete metadata enables proper display,
 * download handling, and attachment management.
 *
 * This operation integrates with the article viewing workflow where users
 * browse article content and access supporting attachments. For articles with
 * many attachments, the pagination and filtering capabilities help users find
 * specific supporting materials efficiently. The search by filename feature is
 * particularly useful for articles referencing multiple research documents or
 * data files.
 *
 * @param props.connection
 * @param props.articleId Unique identifier of the parent article whose
 *   attachments to retrieve
 * @param props.body Search criteria, filtering options, sorting preferences,
 *   and pagination parameters for attachment listing
 * @path /discussionBoard/articles/:articleId/attachments
 * @accessor api.functional.discussionBoard.articles.attachments.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /** Unique identifier of the parent article whose attachments to retrieve */
    articleId: string & tags.Format<"uuid">;

    /**
     * Search criteria, filtering options, sorting preferences, and
     * pagination parameters for attachment listing
     */
    body: IDiscussionBoardArticleAttachment.IRequest;
  };
  export type Body = IDiscussionBoardArticleAttachment.IRequest;
  export type Response = IPageIDiscussionBoardArticleAttachment;

  export const METADATA = {
    method: "PATCH",
    path: "/discussionBoard/articles/:articleId/attachments",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/discussionBoard/articles/${encodeURIComponent(props.articleId ?? "null")}/attachments`;
  export const random = (): IPageIDiscussionBoardArticleAttachment =>
    typia.random<IPageIDiscussionBoardArticleAttachment>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("articleId")(() => typia.assert(props.articleId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

