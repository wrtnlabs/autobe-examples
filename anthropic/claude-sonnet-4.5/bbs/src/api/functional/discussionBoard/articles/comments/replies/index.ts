import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardComment } from "../../../../../structures/IDiscussionBoardComment";
import { IPageIDiscussionBoardComment } from "../../../../../structures/IPageIDiscussionBoardComment";

/**
 * Retrieve paginated list of replies to a specific comment on an article.
 *
 * Retrieve a filtered and paginated list of reply comments for a specific
 * top-level comment on an article in the discussion board system. This
 * operation provides advanced search and filtering capabilities for discovering
 * replies within a comment thread, supporting the single-level threading model
 * defined in the requirements.
 *
 * The operation targets the discussion_board_comments table where the
 * discussion_board_parent_comment_id matches the specified comment identifier.
 * It supports comprehensive filtering including date range filters, author
 * filters, content keyword search, and status filters. Results can be sorted by
 * creation date, update date, or relevance when search keywords are provided.
 *
 * Security considerations include appropriate rate limiting to prevent abuse of
 * search operations and filtering of soft-deleted comments from results unless
 * accessed by moderators. The response includes summary information optimized
 * for displaying reply lists, with pagination support to handle comment threads
 * with many replies efficiently.
 *
 * This operation integrates with the comment system as defined in the Prisma
 * schema, respecting the author_type discriminator field that identifies
 * whether replies were created by members or moderators. The pagination
 * structure enables efficient loading of large reply sets while maintaining
 * fast response times as specified in the performance requirements.
 *
 * @param props.connection
 * @param props.articleId Unique identifier of the parent article containing the
 *   comment thread
 * @param props.commentId Unique identifier of the parent comment whose replies
 *   are being retrieved
 * @param props.body Search criteria, filtering parameters, and pagination
 *   options for retrieving replies
 * @path /discussionBoard/articles/:articleId/comments/:commentId/replies
 * @accessor api.functional.discussionBoard.articles.comments.replies.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /** Unique identifier of the parent article containing the comment thread */
    articleId: string & tags.Format<"uuid">;

    /**
     * Unique identifier of the parent comment whose replies are being
     * retrieved
     */
    commentId: string & tags.Format<"uuid">;

    /**
     * Search criteria, filtering parameters, and pagination options for
     * retrieving replies
     */
    body: IDiscussionBoardComment.IRequest;
  };
  export type Body = IDiscussionBoardComment.IRequest;
  export type Response = IPageIDiscussionBoardComment.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/discussionBoard/articles/:articleId/comments/:commentId/replies",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/discussionBoard/articles/${encodeURIComponent(props.articleId ?? "null")}/comments/${encodeURIComponent(props.commentId ?? "null")}/replies`;
  export const random = (): IPageIDiscussionBoardComment.ISummary =>
    typia.random<IPageIDiscussionBoardComment.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("articleId")(() => typia.assert(props.articleId));
      assert.param("commentId")(() => typia.assert(props.commentId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
