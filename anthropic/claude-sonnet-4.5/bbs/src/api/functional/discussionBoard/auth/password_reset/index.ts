/**
 * Request password reset for forgotten password recovery.
 *
 * Initiates the password recovery process for users who have forgotten their
 * password and need to reset it. This operation allows users to request a
 * password reset by providing their registered email address, triggering the
 * system to send a password reset email with a secure reset link.
 *
 * When a user submits a password reset request, the system validates the email
 * format and checks if an account exists with that email address. For security
 * reasons, the system returns the same success message regardless of whether
 * the email exists in the database, preventing email enumeration attacks where
 * malicious actors could determine which email addresses are registered in the
 * system.
 *
 * If an account exists with the provided email, the system generates a unique
 * password reset token with a 2-hour expiration and sends an email to the user
 * containing a password reset link. The reset email includes the token,
 * expiration notice, security notice that if the user didn't request this they
 * can ignore the email, and instructions if the link doesn't work. The reset
 * token is single-use and cryptographically secure, ensuring that only the
 * legitimate account owner can reset the password.
 *
 * This operation implements rate limiting to prevent abuse, limiting password
 * reset requests to once every 5 minutes per email address. If a user attempts
 * to request multiple resets within the rate limit window, the system returns
 * an error indicating they must wait before requesting another reset.
 *
 * The operation is accessible to all users including guests, members, and
 * moderators, as password recovery is a pre-authentication function. This
 * operation must be followed by the password reset confirmation operation (POST
 * /auth/password-reset/confirm) to complete the password reset process. The
 * relationship between these two operations is critical: this operation
 * generates the reset token and sends it via email, while the confirmation
 * operation validates the token and actually updates the password.
 *
 * @param props.connection
 * @param props.body Password reset request containing the email address of the
 *   account to recover
 * @path /discussionBoard/auth/password-reset/request
 * @accessor api.functional.discussionBoard.auth.password_reset.request
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function request(
  connection: IConnection,
  props: request.Props,
): Promise<request.Response> {
  return true === connection.simulate
    ? request.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...request.METADATA,
          path: request.path(),
          status: null,
        },
        props.body,
      );
}
