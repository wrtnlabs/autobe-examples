import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardArticle } from "../../../../structures/IDiscussionBoardArticle";
import { IPageIDiscussionBoardArticle } from "../../../../structures/IPageIDiscussionBoardArticle";

/**
 * Search and retrieve filtered, paginated list of discussion board articles.
 *
 * Retrieve a comprehensive, filtered, and paginated list of discussion board
 * articles based on advanced search criteria. This operation enables users to
 * discover relevant economic and political discussions through keyword search,
 * category filtering, tag filtering, author filtering, and date range
 * constraints.
 *
 * The search functionality performs full-text search across article titles and
 * body content using PostgreSQL trigram indexes for efficient partial matching.
 * Users can search for keywords like "monetary policy" or "trade agreements"
 * and receive ranked results based on relevance. The system prioritizes title
 * matches over body content matches to surface the most relevant articles.
 *
 * This operation supports comprehensive filtering options including multiple
 * category selection (articles matching any selected category), multiple tag
 * selection (articles matching all selected tags), author filtering by member
 * username, date range filtering for publication dates, and attachment presence
 * filtering (articles with images, documents, or any attachments). Filters can
 * be combined to create highly specific queries.
 *
 * Sorting capabilities include multiple options: relevance-based ranking for
 * keyword searches (default when search keywords are provided), newest first by
 * creation date (default when no keywords), oldest first, most viewed by
 * view_count, most commented by comment_count, and recently updated by
 * updated_at timestamp. The system maintains consistent performance even with
 * complex filter and sort combinations through appropriate database indexing.
 *
 * Pagination follows standard patterns with configurable page size (10, 20, 50,
 * or 100 articles per page, default 20) and page number navigation. Results
 * include total article count, total page count, current page number, and the
 * array of matching articles in summary format optimized for list display.
 *
 * Security considerations include rate limiting on search operations to prevent
 * abuse, filtering out soft-deleted articles (where deleted_at is not null),
 * respecting article status (only published articles visible to guests, draft
 * articles visible only to authors), and appropriate access control based on
 * the requesting user's authentication status. The operation is accessible to
 * all users including guests, members, and moderators, with identical search
 * capabilities for all user types.
 *
 * This operation integrates with the discussion_board_articles table as the
 * primary data source, joins with discussion_board_article_categories and
 * discussion_board_categories for category filtering, joins with
 * discussion_board_article_tags and discussion_board_tags for tag filtering,
 * joins with discussion_board_members for author information, and references
 * discussion_board_article_images and discussion_board_article_documents for
 * attachment filtering. The response returns summary information optimized for
 * search result display, including article metadata, excerpt from body content,
 * author information, category and tag lists, and attachment indicators without
 * loading full attachment details.
 *
 * @param props.connection
 * @param props.body Search criteria including keywords, filters, sorting
 *   preferences, and pagination parameters for article discovery
 * @path /discussionBoard/search/articles
 * @accessor api.functional.discussionBoard.search.articles.search
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function search(
  connection: IConnection,
  props: search.Props,
): Promise<search.Response> {
  return true === connection.simulate
    ? search.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...search.METADATA,
          path: search.path(),
          status: null,
        },
        props.body,
      );
}
export namespace search {
  export type Props = {
    /**
     * Search criteria including keywords, filters, sorting preferences, and
     * pagination parameters for article discovery
     */
    body: IDiscussionBoardArticle.IRequest;
  };
  export type Body = IDiscussionBoardArticle.IRequest;
  export type Response = IPageIDiscussionBoardArticle.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/discussionBoard/search/articles",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/discussionBoard/search/articles";
  export const random = (): IPageIDiscussionBoardArticle.ISummary =>
    typia.random<IPageIDiscussionBoardArticle.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: search.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: search.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
