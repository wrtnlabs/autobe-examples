import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardPasswordReset } from "../../../../structures/IDiscussionBoardPasswordReset";

/**
 * Retrieve a specific password reset request by ID (token excluded for
 * security).
 *
 * Retrieve detailed information about a password reset request identified by
 * its unique ID from the discussion_board_password_resets table.
 *
 * This operation returns comprehensive password reset request data including
 * the target email address, expiration timestamp (1 hour validity), usage
 * status, and creation timestamp. The response identifies whether the reset
 * request was initiated by a member or moderator through the actor_type
 * discriminator field.
 *
 * The system uses a polymorphic ownership pattern where password resets can be
 * associated with either members or moderators. The actual relationship to the
 * specific member or moderator account is maintained through separate junction
 * tables (discussion_board_password_reset_of_members and
 * discussion_board_password_reset_of_moderators), following the Compatible
 * Actor Pattern for proper database normalization.
 *
 * Security considerations: This endpoint is restricted to moderator access
 * only. The password reset token field is intentionally excluded from the
 * response as it is a sensitive security credential. Exposing the token would
 * allow unauthorized password changes. Tokens are single-use, expire after 1
 * hour, and are invalidated immediately upon successful password change. The
 * used_at timestamp indicates whether a token has been consumed.
 *
 * Use cases include administrative review of password reset requests, debugging
 * reset flow issues, and monitoring reset token usage patterns for security
 * auditing. The used_at timestamp helps identify pending versus completed reset
 * requests.
 *
 * @param props.connection
 * @param props.resetId Unique identifier of the password reset request
 * @path /discussionBoard/moderator/passwordResets/:resetId
 * @accessor api.functional.discussionBoard.moderator.passwordResets.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique identifier of the password reset request */
    resetId: string & tags.Format<"uuid">;
  };
  export type Response = IDiscussionBoardPasswordReset;

  export const METADATA = {
    method: "GET",
    path: "/discussionBoard/moderator/passwordResets/:resetId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/moderator/passwordResets/${encodeURIComponent(props.resetId ?? "null")}`;
  export const random = (): IDiscussionBoardPasswordReset =>
    typia.random<IDiscussionBoardPasswordReset>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("resetId")(() => typia.assert(props.resetId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
