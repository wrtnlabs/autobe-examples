import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

/**
 * Delete a file attachment from a discussion board article.
 *
 * Remove a specific file attachment from a discussion board article
 * permanently.
 *
 * This operation allows authorized users (the article author or moderators) to
 * delete file attachments that were previously uploaded to support an article's
 * content. When a file is deleted, the association between the article and the
 * file is removed from the discussion_board_article_files table.
 *
 * Security considerations: Only the article author or moderators with
 * appropriate permissions can delete file attachments. The operation validates
 * ownership before allowing deletion. File deletion is permanent and cannot be
 * undone.
 *
 * The deletion removes the database record linking the file to the article.
 * Depending on file storage implementation, the actual file content may be
 * removed from storage or marked for cleanup.
 *
 * This operation is typically used when a file attachment is no longer
 * relevant, contains errors, or needs to be replaced with an updated version.
 *
 * @param props.connection
 * @param props.articleId Unique identifier of the discussion board article
 *   containing the file attachment
 * @param props.fileId Unique identifier of the specific file attachment to be
 *   deleted
 * @path /discussionBoard/moderator/articles/:articleId/files/:fileId
 * @accessor api.functional.discussionBoard.moderator.articles.files.erase
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function erase(
  connection: IConnection,
  props: erase.Props,
): Promise<void> {
  return true === connection.simulate
    ? erase.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...erase.METADATA,
          path: erase.path(props),
          status: null,
        },
      );
}
export namespace erase {
  export type Props = {
    /**
     * Unique identifier of the discussion board article containing the file
     * attachment
     */
    articleId: string & tags.Format<"uuid">;

    /** Unique identifier of the specific file attachment to be deleted */
    fileId: string & tags.Format<"uuid">;
  };

  export const METADATA = {
    method: "DELETE",
    path: "/discussionBoard/moderator/articles/:articleId/files/:fileId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/moderator/articles/${encodeURIComponent(props.articleId ?? "null")}/files/${encodeURIComponent(props.fileId ?? "null")}`;
  export const random = (): void => typia.random<void>();
  export const simulate = (
    connection: IConnection,
    props: erase.Props,
  ): void => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: erase.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("articleId")(() => typia.assert(props.articleId));
      assert.param("fileId")(() => typia.assert(props.fileId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
