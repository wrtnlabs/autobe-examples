import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardContentReport } from "../../../../../structures/IDiscussionBoardContentReport";
import { IPageIDiscussionBoardContentReport } from "../../../../../structures/IPageIDiscussionBoardContentReport";

/**
 * Retrieve a filtered and paginated list of content reports submitted against a
 * specific article in the discussion board.
 *
 * This operation allows moderators to view all reports that members have
 * submitted for a particular article, helping them understand community
 * concerns and prioritize moderation efforts. The operation queries the
 * discussion_board_content_reports table filtered by the specified article ID,
 * returning comprehensive report information including the reporting member,
 * violation category, detailed explanations, and resolution status.
 *
 * The request body supports advanced filtering capabilities including report
 * status (pending, reviewed, dismissed), report categories (Spam, Offensive
 * Content, Misinformation, Off-Topic, Other), date range filters for submission
 * and resolution timestamps, and search by reporter username. Pagination
 * parameters enable efficient navigation through large numbers of reports,
 * while sorting options allow ordering by submission date, resolution date, or
 * report category.
 *
 * Security considerations: This operation is restricted to moderators who have
 * permissions to review content reports. For moderator privacy and security,
 * the response abstracts moderator identity - specific moderator information is
 * excluded from the response and available only in system audit logs. Reporter
 * identity is included to provide context for moderation decisions while
 * maintaining appropriate confidentiality from article authors.
 *
 * This operation integrates with the discussion_board_content_reports table as
 * defined in the Prisma schema, incorporating report fields including
 * report_category, report_details, status, resolution_notes, and timestamps.
 * Moderator-specific fields (resolved_by_moderator_id, resolver relation) are
 * excluded from the response for security. Related operations include POST
 * /articles/{articleId}/reports for creating new reports and moderator action
 * endpoints for resolving reports.
 *
 * @param props.connection
 * @param props.articleId Unique identifier of the article for which to retrieve
 *   content reports
 * @param props.body Search criteria, filters, and pagination parameters for
 *   content report retrieval
 * @path /discussionBoard/moderator/articles/:articleId/reports
 * @accessor api.functional.discussionBoard.moderator.articles.reports.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Unique identifier of the article for which to retrieve content
     * reports
     */
    articleId: string & tags.Format<"uuid">;

    /**
     * Search criteria, filters, and pagination parameters for content
     * report retrieval
     */
    body: IDiscussionBoardContentReport.IRequest;
  };
  export type Body = IDiscussionBoardContentReport.IRequest;
  export type Response = IPageIDiscussionBoardContentReport.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/discussionBoard/moderator/articles/:articleId/reports",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/discussionBoard/moderator/articles/${encodeURIComponent(props.articleId ?? "null")}/reports`;
  export const random = (): IPageIDiscussionBoardContentReport.ISummary =>
    typia.random<IPageIDiscussionBoardContentReport.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("articleId")(() => typia.assert(props.articleId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
