/**
 * Retrieve filtered and paginated content reports from the moderation queue.
 *
 * Retrieve a comprehensive list of content reports from the moderation queue
 * with advanced filtering, searching, sorting, and pagination capabilities.
 * This operation enables moderators to efficiently review community-submitted
 * reports about articles that allegedly violate community guidelines.
 *
 * The operation queries the discussion_board_content_reports table and supports
 * multiple filter criteria including report status (pending,
 * reviewed_no_action, reviewed_edited, reviewed_removed), date range filtering
 * for submission time, specific reporter filtering, specific article filtering,
 * and report category filtering. Moderators can sort results by submission
 * date, resolution date, or report priority (determined by number of reports on
 * the same article).
 *
 * Security considerations: This operation is restricted to authenticated
 * moderators only. Only users with moderator privileges can access the
 * moderation queue. The response includes sensitive information about reporters
 * and reported content that should not be exposed to regular members. Rate
 * limiting applies to prevent abuse of the moderation system.
 *
 * The paginated response includes report details such as report ID, reported
 * article information, reporter information, report category, detailed
 * explanation, current status, resolution notes (if resolved), submission
 * timestamp, and resolution timestamp. Each report entry provides sufficient
 * context for moderators to make informed moderation decisions without
 * requiring additional API calls.
 *
 * Related operations: After reviewing reports in the queue, moderators may use
 * PUT /articles/{articleId} to edit content, DELETE /articles/{articleId} to
 * remove content, or PUT /reports/{reportId}/resolve to mark reports as
 * resolved. The moderation queue is the entry point for the content review
 * workflow documented in the user workflows specification.
 *
 * @param props.connection
 * @param props.body Search and filter criteria for moderation queue reports
 *   including status filters, date ranges, and pagination parameters
 * @path /discussionBoard/moderator/dashboard/moderation/queue
 * @accessor api.functional.discussionBoard.moderator.dashboard.moderation.queue.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
