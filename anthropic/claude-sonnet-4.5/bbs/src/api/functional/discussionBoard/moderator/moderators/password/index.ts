import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardModerator } from "../../../../../structures/IDiscussionBoardModerator";

/**
 * Update moderator account password with current password verification.
 *
 * This operation enables authenticated moderators to change their account
 * password by providing their current password for verification and submitting
 * a new password that meets security requirements. The password change process
 * is a critical security operation that ensures only the legitimate account
 * owner can modify authentication credentials.
 *
 * The operation validates that the current password matches the stored
 * password_hash in the discussion_board_moderators table before accepting the
 * new password. The new password must meet complexity requirements including
 * minimum 8 characters length, at least one uppercase letter, one lowercase
 * letter, one number, and one special character. Password strength is validated
 * server-side to prevent weak passwords that could compromise account
 * security.
 *
 * Upon successful password update, the system marks all existing moderator
 * sessions as expired by setting the expired_at timestamp to the current time
 * in the discussion_board_moderator_sessions table. This ensures the moderator
 * must re-authenticate on all devices with the new password, providing security
 * in case the password change was prompted by suspected account compromise. The
 * system updates the password_hash field and the updated_at timestamp in the
 * discussion_board_moderators table.
 *
 * Security measures implemented include requiring current password verification
 * to prevent unauthorized changes, enforcing strong password complexity
 * requirements to resist brute force attacks, expiring all active sessions to
 * invalidate potentially compromised access, and logging the password change
 * event for security audit trails. Note that JWT refresh token management (if
 * implemented) is handled at the application layer outside the database
 * schema.
 *
 * @param props.connection
 * @param props.moderatorUsername Unique username of the target moderator
 *   account (global scope). Format: 3-30 alphanumeric characters with
 *   underscores and hyphens allowed.
 * @param props.body Current password for verification and new password for
 *   update
 * @path /discussionBoard/moderator/moderators/:moderatorUsername/password
 * @accessor api.functional.discussionBoard.moderator.moderators.password.updatePassword
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function updatePassword(
  connection: IConnection,
  props: updatePassword.Props,
): Promise<updatePassword.Response> {
  return true === connection.simulate
    ? updatePassword.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...updatePassword.METADATA,
          path: updatePassword.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace updatePassword {
  export type Props = {
    /**
     * Unique username of the target moderator account (global scope).
     * Format: 3-30 alphanumeric characters with underscores and hyphens
     * allowed.
     */
    moderatorUsername: string;

    /** Current password for verification and new password for update */
    body: IDiscussionBoardModerator.IChangePassword;
  };
  export type Body = IDiscussionBoardModerator.IChangePassword;
  export type Response = IDiscussionBoardModerator;

  export const METADATA = {
    method: "PUT",
    path: "/discussionBoard/moderator/moderators/:moderatorUsername/password",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/discussionBoard/moderator/moderators/${encodeURIComponent(props.moderatorUsername ?? "null")}/password`;
  export const random = (): IDiscussionBoardModerator =>
    typia.random<IDiscussionBoardModerator>();
  export const simulate = (
    connection: IConnection,
    props: updatePassword.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: updatePassword.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("moderatorUsername")(() =>
        typia.assert(props.moderatorUsername),
      );
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
