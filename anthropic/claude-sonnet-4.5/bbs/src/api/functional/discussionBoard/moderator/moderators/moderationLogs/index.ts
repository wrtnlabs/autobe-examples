/**
 * Retrieve a filtered, sorted, and paginated list of moderation action log
 * entries, providing comprehensive access to the platform's moderation audit
 * trail. This operation supports searching and filtering moderation logs by
 * action type, affected content, affected users, time periods, and specific
 * moderators.
 *
 * The moderation log serves as the authoritative audit trail for all content
 * moderation and user management actions on the platform. Each log entry
 * records what action was taken (article edited, article deleted, attachment
 * removed, account suspended, account banned, account restored), which
 * moderator performed it, what content or user was affected, when it occurred,
 * and the moderator's documented reason. This comprehensive record ensures
 * accountability, enables dispute resolution, supports moderation quality
 * review, and helps identify patterns requiring escalated action.
 *
 * Moderators can search logs by multiple criteria including action type (to
 * find all deletions or suspensions), specific article or member (to review all
 * actions affecting that entity), date ranges (to analyze moderation activity
 * over time), or specific moderator (to review an individual moderator's
 * actions). The operation supports complex filtering combinations and returns
 * paginated results with configurable page sizes for efficient browsing of
 * large audit trails.
 *
 * Security and access control: Only authenticated moderators can access
 * moderation logs, ensuring log data remains confidential and is used only for
 * legitimate oversight purposes. The moderatorId path parameter identifies
 * which moderator is requesting the logs, enabling tracking of log access for
 * security auditing.
 *
 * The response includes detailed log entries with moderator identity, action
 * type, affected content/user references, timestamps, reasons, and additional
 * action details. This supports comprehensive moderation review, investigation
 * of specific incidents, generation of moderation activity reports, and
 * verification that moderation decisions align with community guidelines. Log
 * entries are immutable and retained indefinitely per business requirements,
 * providing a permanent record of platform moderation history.
 *
 * Related operations: Individual moderation actions (edit article, delete
 * article, suspend account) create log entries that appear in results from this
 * search operation. Moderators should use this endpoint regularly to review
 * their own actions and overall platform moderation patterns.
 *
 * @param props.connection
 * @param props.moderatorId Unique identifier of the moderator requesting
 *   moderation log access
 * @param props.body Search criteria, filters, sorting options, and pagination
 *   parameters for moderation log retrieval
 * @path /discussionBoard/moderator/moderators/:moderatorId/moderationLogs
 * @accessor api.functional.discussionBoard.moderator.moderators.moderationLogs.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /** Unique identifier of the moderator requesting moderation log access */
    moderatorId: string & tags.Format<"uuid">;

    /**
     * Search criteria, filters, sorting options, and pagination parameters
     * for moderation log retrieval
     */
    body: IDiscussionBoardModerationLog.IRequest;
  };
  export type Body = IDiscussionBoardModerationLog.IRequest;
  export type Response = IPageIDiscussionBoardModerationLog;

  export const METADATA = {
    method: "PATCH",
    path: "/discussionBoard/moderator/moderators/:moderatorId/moderationLogs",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/discussionBoard/moderator/moderators/${encodeURIComponent(props.moderatorId ?? "null")}/moderationLogs`;
  export const random = (): IPageIDiscussionBoardModerationLog =>
    typia.random<IPageIDiscussionBoardModerationLog>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("moderatorId")(() => typia.assert(props.moderatorId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
