/**
 * Retrieve moderation response time statistics and performance metrics.
 *
 * Calculate and return comprehensive moderation response time statistics that
 * measure how quickly moderators review and resolve community-submitted content
 * reports. This operation supports the platform's success metrics tracking as
 * defined in the business requirements.
 *
 * The operation performs statistical analysis on the
 * discussion_board_content_reports table, specifically examining the time
 * difference between created_at (report submission) and resolved_at (moderator
 * resolution) timestamps. It computes multiple performance indicators including
 * average response time in hours, median response time (50th percentile), 90th
 * percentile response time (to identify outliers), percentage of reports
 * resolved within 24 hours, percentage resolved within 7 days, and total number
 * of pending reports currently awaiting review.
 *
 * Additionally, the statistics break down response times by report category
 * (Spam, Offensive Content, Misinformation, Off-Topic, Other) to identify if
 * certain violation types receive faster or slower attention. This categorical
 * analysis helps administrators optimize moderation resource allocation.
 *
 * Security and authorization: This operation is restricted to moderators and
 * administrators who need visibility into moderation performance metrics.
 * Regular members and guests cannot access these operational statistics. The
 * response contains aggregated data only without exposing individual reporter
 * identities or specific report details.
 *
 * The computed statistics support the success criteria defined in
 * 10-success-metrics.md which emphasizes timely content review and effective
 * moderation response. Platform administrators use these metrics to ensure
 * moderators are meeting response time targets and to identify areas requiring
 * additional moderation resources or process improvements.
 *
 * This is a read-only statistical operation that does not modify any data. It
 * aggregates information from resolved reports to provide performance insights.
 * Unlike the moderation queue operation which returns individual reports, this
 * endpoint returns summary statistics and performance metrics.
 *
 * @param props.connection
 * @path /discussionBoard/moderator/statistics/moderation/responseTime
 * @accessor api.functional.discussionBoard.moderator.statistics.moderation.responseTime.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(connection: IConnection): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(),
          status: null,
        },
      );
}
export namespace at {
  export type Response = IDiscussionBoardModerationResponseTimeStatistics;

  export const METADATA = {
    method: "GET",
    path: "/discussionBoard/moderator/statistics/moderation/responseTime",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () =>
    "/discussionBoard/moderator/statistics/moderation/responseTime";
  export const random = (): IDiscussionBoardModerationResponseTimeStatistics =>
    typia.random<IDiscussionBoardModerationResponseTimeStatistics>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}
