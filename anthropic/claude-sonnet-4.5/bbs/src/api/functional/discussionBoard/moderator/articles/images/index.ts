/**
 * Upload and attach image files to an existing article.
 *
 * This operation enables authenticated moderators to enhance articles by
 * uploading image attachments such as charts, graphs, infographics, or
 * photographs that support economic or political analysis. Moderators can add
 * images to any article as part of their content management and moderation
 * responsibilities, not just articles they authored.
 *
 * The image upload process begins when a moderator submits image data along
 * with metadata. The system performs comprehensive validation before accepting
 * the upload. File type validation ensures the image is in one of the supported
 * formats: JPEG, PNG, GIF, or WebP. The system validates the MIME type matches
 * the file content, not just the file extension, preventing bypassing of
 * restrictions through file renaming. File size validation confirms the image
 * does not exceed the 5MB limit for individual images. Dimension validation
 * checks that the image is at least 50x50 pixels (minimum readable size) and
 * does not exceed 8000x8000 pixels (maximum practical size). The system also
 * verifies that adding this image will not cause the article to exceed the
 * maximum of 10 total image attachments.
 *
 * When all validations pass, the system proceeds with the upload process. The
 * image file is stored in the file storage system with a unique generated
 * filename (stored_name) to prevent filename conflicts while preserving the
 * original user-provided filename (original_name) for display purposes. The
 * system records comprehensive metadata in the discussion_board_article_images
 * table including the parent article reference (discussion_board_article_id),
 * the uploader's member ID (uploaded_by_member_id) captured from the
 * authenticated moderator session, original and stored filenames, MIME type,
 * file size in bytes, image dimensions (width and height), and the upload
 * timestamp (created_at). When a moderator uploads an image, this action may be
 * logged in the discussion_board_moderation_actions table for audit trail
 * purposes, particularly if the moderator is adding images to another user's
 * article.
 *
 * From a security perspective, the system must verify the moderator is properly
 * authenticated and has active moderator status before allowing image uploads.
 * The system should verify the target article exists and is accessible before
 * accepting uploads. Additionally, the system must scan uploaded images for
 * malware and reject any files that fail security validation, protecting the
 * community from malicious uploads. When an image is successfully uploaded by a
 * moderator, it becomes immediately visible on the article page in the order it
 * was uploaded. Note that uploaded images have soft delete support through the
 * deleted_at field, allowing recovery if images are removed in error or if
 * moderation decisions are reversed.
 *
 * @param props.connection
 * @param props.articleId Unique identifier of the target article to which the
 *   image will be attached
 * @param props.body Image file data and metadata for uploading a new image
 *   attachment to the article
 * @path /discussionBoard/moderator/articles/:articleId/images
 * @accessor api.functional.discussionBoard.moderator.articles.images.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
