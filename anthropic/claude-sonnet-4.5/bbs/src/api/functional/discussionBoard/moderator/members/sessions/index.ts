import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardMemberSession } from "../../../../../structures/IDiscussionBoardMemberSession";

/**
 * Delete a member's authentication session to log them out.
 *
 * Terminate and permanently remove an active authentication session for a
 * registered discussion board member.
 *
 * This operation performs an immediate logout by deleting the session record
 * from the discussion_board_member_sessions table. Once deleted, the session
 * token becomes invalid and cannot be used for further API authentication. This
 * is typically used when a member explicitly logs out or when an administrator
 * needs to force-terminate a session for security reasons.
 *
 * Security considerations: The operation validates that the requesting actor
 * has permission to delete the target session. Members can delete their own
 * sessions (self-logout), while moderators may have elevated permissions to
 * terminate any member's session for moderation purposes. The session is
 * permanently removed with no soft-delete mechanism.
 *
 * The operation requires both the member identifier and the specific session
 * identifier to prevent accidental deletion of all member sessions. After
 * successful deletion, the member must authenticate again to create a new
 * session and continue using the discussion board.
 *
 * @param props.connection
 * @param props.memberId Unique identifier of the discussion board member who
 *   owns the session
 * @param props.sessionId Unique identifier of the specific authentication
 *   session to terminate
 * @path /discussionBoard/moderator/members/:memberId/sessions/:sessionId
 * @accessor api.functional.discussionBoard.moderator.members.sessions.erase
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function erase(
  connection: IConnection,
  props: erase.Props,
): Promise<erase.Response> {
  return true === connection.simulate
    ? erase.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...erase.METADATA,
          path: erase.path(props),
          status: null,
        },
      );
}
export namespace erase {
  export type Props = {
    /** Unique identifier of the discussion board member who owns the session */
    memberId: string & tags.Format<"uuid">;

    /** Unique identifier of the specific authentication session to terminate */
    sessionId: string & tags.Format<"uuid">;
  };
  export type Response = IDiscussionBoardMemberSession;

  export const METADATA = {
    method: "DELETE",
    path: "/discussionBoard/moderator/members/:memberId/sessions/:sessionId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/moderator/members/${encodeURIComponent(props.memberId ?? "null")}/sessions/${encodeURIComponent(props.sessionId ?? "null")}`;
  export const random = (): IDiscussionBoardMemberSession =>
    typia.random<IDiscussionBoardMemberSession>();
  export const simulate = (
    connection: IConnection,
    props: erase.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: erase.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("memberId")(() => typia.assert(props.memberId));
      assert.param("sessionId")(() => typia.assert(props.sessionId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
