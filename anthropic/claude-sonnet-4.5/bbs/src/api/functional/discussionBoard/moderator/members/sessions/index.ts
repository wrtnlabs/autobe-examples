import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardMemberSession } from "../../../../../structures/IDiscussionBoardMemberSession";

/**
 * Terminate a specific member authentication session.
 *
 * Remove a specific active authentication session for a member, logging them
 * out from the associated device or browser.
 *
 * This operation allows members to manage their active sessions by terminating
 * specific sessions on devices they no longer use or suspect of unauthorized
 * access. When a session is deleted, the associated JWT refresh token is
 * invalidated immediately, preventing further authentication using that
 * session's credentials. The member will need to log in again from that device
 * to establish a new session.
 *
 * Security considerations: Members can only delete their own sessions unless
 * they are moderators. Moderators have elevated privileges to terminate any
 * member's session for security enforcement, such as when investigating
 * suspicious activity or enforcing account restrictions. All session deletion
 * actions by moderators are logged in the moderation audit trail.
 *
 * The operation validates that the session belongs to the specified member
 * before deletion. If the session does not exist or belongs to a different
 * member, the operation returns an error. The session record is marked with an
 * expired_at timestamp rather than being permanently deleted, maintaining an
 * audit trail of session lifecycle for security monitoring.
 *
 * Related operations: Members typically view their active sessions via GET
 * /members/{memberId}/sessions before selecting specific sessions to terminate.
 * The "logout from all devices" functionality is implemented by calling DELETE
 * on each active session for the member.
 *
 * @param props.connection
 * @param props.memberId Unique identifier of the member who owns the session
 * @param props.sessionId Unique identifier of the specific session to terminate
 * @path /discussionBoard/moderator/members/:memberId/sessions/:sessionId
 * @accessor api.functional.discussionBoard.moderator.members.sessions.erase
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function erase(
  connection: IConnection,
  props: erase.Props,
): Promise<erase.Response> {
  return true === connection.simulate
    ? erase.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...erase.METADATA,
          path: erase.path(props),
          status: null,
        },
      );
}
export namespace erase {
  export type Props = {
    /** Unique identifier of the member who owns the session */
    memberId: string & tags.Format<"uuid">;

    /** Unique identifier of the specific session to terminate */
    sessionId: string & tags.Format<"uuid">;
  };
  export type Response = IDiscussionBoardMemberSession;

  export const METADATA = {
    method: "DELETE",
    path: "/discussionBoard/moderator/members/:memberId/sessions/:sessionId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/moderator/members/${encodeURIComponent(props.memberId ?? "null")}/sessions/${encodeURIComponent(props.sessionId ?? "null")}`;
  export const random = (): IDiscussionBoardMemberSession =>
    typia.random<IDiscussionBoardMemberSession>();
  export const simulate = (
    connection: IConnection,
    props: erase.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: erase.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("memberId")(() => typia.assert(props.memberId));
      assert.param("sessionId")(() => typia.assert(props.sessionId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
