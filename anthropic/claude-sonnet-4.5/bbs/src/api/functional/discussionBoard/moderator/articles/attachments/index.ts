/**
 * Create a new attachment for a discussion board article.
 *
 * Upload and attach a new image or document file to an existing discussion
 * board article. This operation allows authenticated members to add supporting
 * materials, visual evidence, charts, documents, and reference materials to
 * their economic and political discussions.
 *
 * The operation validates file type, size, and security constraints before
 * creating the attachment record. Image attachments support JPEG, PNG, GIF, and
 * WebP formats with a maximum size of 5 MB each, and articles can have up to 10
 * image attachments. Document attachments support PDF, DOC, DOCX, XLS, XLSX,
 * TXT, and CSV formats with a maximum size of 10 MB each, and articles can have
 * up to 5 document attachments. The combined total attachment size per article
 * cannot exceed 25 MB.
 *
 * Security validation includes file type verification by examining content
 * headers (not just extensions), malware scanning, and metadata stripping to
 * protect user privacy. The system generates unique storage paths and sanitizes
 * filenames to prevent security vulnerabilities. Only the article author or
 * moderators can add attachments to an article.
 *
 * The attachment is immediately associated with the parent article and becomes
 * visible when the article is viewed. The operation records the member who
 * uploaded the attachment for attribution and audit purposes. All attachment
 * uploads are subject to the business rules defined in the attachment
 * validation requirements including type restrictions, size limits, and
 * quantity constraints.
 *
 * @param props.connection
 * @param props.articleId Unique identifier of the target article to attach the
 *   file to
 * @param props.body Attachment creation data including file information and
 *   metadata
 * @path /discussionBoard/moderator/articles/:articleId/attachments
 * @accessor api.functional.discussionBoard.moderator.articles.attachments.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function create(
  connection: IConnection,
  props: create.Props,
): Promise<create.Response> {
  return true === connection.simulate
    ? create.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...create.METADATA,
          path: create.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace create {
  export type Props = {
    /** Unique identifier of the target article to attach the file to */
    articleId: string & tags.Format<"uuid">;

    /** Attachment creation data including file information and metadata */
    body: IDiscussionBoardArticleAttachment.ICreate;
  };
  export type Body = IDiscussionBoardArticleAttachment.ICreate;
  export type Response = IDiscussionBoardArticleAttachment;

  export const METADATA = {
    method: "POST",
    path: "/discussionBoard/moderator/articles/:articleId/attachments",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/discussionBoard/moderator/articles/${encodeURIComponent(props.articleId ?? "null")}/attachments`;
  export const random = (): IDiscussionBoardArticleAttachment =>
    typia.random<IDiscussionBoardArticleAttachment>();
  export const simulate = (
    connection: IConnection,
    props: create.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: create.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("articleId")(() => typia.assert(props.articleId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
