/**
 * Search and retrieve a filtered, paginated list of discussion board members.
 *
 * Retrieve a comprehensive list of discussion board members with advanced
 * filtering, searching, and pagination capabilities. This operation queries the
 * discussion_board_members table and returns member summary information
 * suitable for administrative review and member management.
 *
 * The operation supports filtering by multiple criteria including email
 * verification status (email_verified field), account suspension status
 * (is_suspended field), registration date ranges (created_at field), and last
 * login activity (last_login_at field). Text search capabilities allow finding
 * members by username or display_name using partial matching with
 * case-insensitive comparison. Email addresses are included in the summary
 * results for moderators to support administrative functions and member
 * management. This personally identifiable information should be protected
 * according to data protection regulations.
 *
 * Security and authorization considerations: This operation is restricted to
 * moderators only, as it provides access to member account information
 * including email addresses, suspension status, and activity timestamps. The
 * password field from the Prisma schema is never included in response data for
 * security reasons. Pagination is mandatory to handle potentially large member
 * datasets efficiently.
 *
 * The response includes member summary data optimized for list displays,
 * excluding sensitive authentication credentials while providing sufficient
 * information for account management and moderation decisions. Results are
 * ordered by created_at timestamp in descending order by default, showing
 * newest members first.
 *
 * Related operations: Individual member details can be retrieved using GET
 * /discussionBoard/moderator/members/{memberId} for complete profile
 * information. This search operation should be used first to identify members
 * of interest before accessing detailed records.
 *
 * @param props.connection
 * @param props.body Search criteria and pagination parameters for member
 *   filtering
 * @path /discussionBoard/moderator/members
 * @accessor api.functional.discussionBoard.moderator.members.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /** Search criteria and pagination parameters for member filtering */
    body: IDiscussionBoardMember.IRequest;
  };
  export type Body = IDiscussionBoardMember.IRequest;
  export type Response = IPageIDiscussionBoardMember.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/discussionBoard/moderator/members",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/discussionBoard/moderator/members";
  export const random = (): IPageIDiscussionBoardMember.ISummary =>
    typia.random<IPageIDiscussionBoardMember.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

