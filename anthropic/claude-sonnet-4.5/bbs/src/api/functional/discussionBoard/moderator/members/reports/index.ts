import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardContentReport } from "../../../../../structures/IDiscussionBoardContentReport";
import { IPageIDiscussionBoardContentReport } from "../../../../../structures/IPageIDiscussionBoardContentReport";

/**
 * Retrieve paginated list of content reports submitted by a specific member.
 *
 * Retrieve a filtered and paginated list of content reports submitted by a
 * specific discussion board member. This operation provides comprehensive
 * search capabilities for analyzing member reporting behavior, tracking report
 * resolution status, and identifying members who frequently report content.
 *
 * The operation supports complex filtering including report category (Spam,
 * Offensive Content, Misinformation, Off-Topic, Other), resolution status
 * (pending, reviewed_no_action, reviewed_edited, reviewed_removed), date ranges
 * for submission and resolution timestamps, and text search within report
 * details. Results can be sorted by creation date, resolution date, or status
 * to prioritize review workflows.
 *
 * Security considerations: This operation requires moderator or administrator
 * authorization as it exposes member reporting patterns and potentially
 * sensitive report details. The response includes the reporting member's
 * information, reported article references, resolution status, and moderator
 * notes for resolved reports. Rate limiting applies to prevent abuse of search
 * functionality.
 *
 * The operation integrates with the discussion_board_content_reports table and
 * joins with related discussion_board_articles and discussion_board_moderators
 * tables to provide complete context. This enables moderators to understand
 * reporting patterns, identify potential abuse of the reporting system, and
 * review the complete history of a member's community moderation
 * participation.
 *
 * @param props.connection
 * @param props.memberId Unique identifier of the member whose submitted reports
 *   should be retrieved
 * @param props.body Search criteria, filtering options, sorting preferences,
 *   and pagination parameters for member's content reports
 * @path /discussionBoard/moderator/members/:memberId/reports
 * @accessor api.functional.discussionBoard.moderator.members.reports.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Unique identifier of the member whose submitted reports should be
     * retrieved
     */
    memberId: string & tags.Format<"uuid">;

    /**
     * Search criteria, filtering options, sorting preferences, and
     * pagination parameters for member's content reports
     */
    body: IDiscussionBoardContentReport.IRequest;
  };
  export type Body = IDiscussionBoardContentReport.IRequest;
  export type Response = IPageIDiscussionBoardContentReport.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/discussionBoard/moderator/members/:memberId/reports",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/discussionBoard/moderator/members/${encodeURIComponent(props.memberId ?? "null")}/reports`;
  export const random = (): IPageIDiscussionBoardContentReport.ISummary =>
    typia.random<IPageIDiscussionBoardContentReport.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("memberId")(() => typia.assert(props.memberId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
