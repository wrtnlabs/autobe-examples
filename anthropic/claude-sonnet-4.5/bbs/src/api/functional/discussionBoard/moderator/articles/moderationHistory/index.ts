import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardModerationLog } from "../../../../../structures/IDiscussionBoardModerationLog";
import { IPageIDiscussionBoardModerationLog } from "../../../../../structures/IPageIDiscussionBoardModerationLog";

/**
 * Search and retrieve the complete moderation history for a specific article.
 *
 * Retrieve a comprehensive, paginated list of all moderation actions that have
 * been applied to a specific article throughout its lifecycle. This operation
 * queries the discussion_board_moderation_logs table filtered by the article ID
 * to return every recorded moderation action affecting this article.
 *
 * The moderation history includes all actions where moderators intervened on
 * the article content: article edits made by moderators (when they modified the
 * title, body, or category for policy compliance), attachment removals (when
 * specific images or files were deleted for violating guidelines), and article
 * deletion actions (when the entire article was removed from public view or
 * permanently deleted).
 *
 * This operation supports several critical use cases: moderators reviewing the
 * enforcement history of problematic content to understand patterns and
 * escalation, article authors understanding what changes were made to their
 * content and why, administrators auditing moderation consistency and response
 * times, and dispute resolution processes where complete action history is
 * needed to evaluate appeals.
 *
 * The request body accepts search and filtering criteria including date ranges
 * (to find actions within specific time periods), action types (to filter by
 * article_edited, attachment_removed, or article_deleted), and specific
 * moderator IDs (to review actions by particular moderators). Pagination
 * parameters control result size and allow navigation through long moderation
 * histories for frequently-moderated articles.
 *
 * Each log entry in the response includes the complete context captured when
 * the action was taken: what type of action was performed, which moderator
 * performed it, when it occurred, the documented reason the moderator provided,
 * and additional contextual details about what was changed. The results are
 * sorted in reverse chronological order by default, showing the most recent
 * moderation actions first.
 *
 * Access control should be carefully designed: moderators need full access to
 * review all moderation history, but article authors might be limited to
 * viewing only actions that directly affected their own articles. The operation
 * maintains transparency while respecting appropriate confidentiality
 * boundaries around moderation decisions.
 *
 * @param props.connection
 * @param props.articleId Unique identifier of the article whose moderation
 *   history is being retrieved
 * @param props.body Search criteria, filters, and pagination parameters for
 *   moderation history query
 * @path /discussionBoard/moderator/articles/:articleId/moderationHistory
 * @accessor api.functional.discussionBoard.moderator.articles.moderationHistory.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Unique identifier of the article whose moderation history is being
     * retrieved
     */
    articleId: string & tags.Format<"uuid">;

    /**
     * Search criteria, filters, and pagination parameters for moderation
     * history query
     */
    body: IDiscussionBoardModerationLog.IRequest;
  };
  export type Body = IDiscussionBoardModerationLog.IRequest;
  export type Response = IPageIDiscussionBoardModerationLog.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/discussionBoard/moderator/articles/:articleId/moderationHistory",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/discussionBoard/moderator/articles/${encodeURIComponent(props.articleId ?? "null")}/moderationHistory`;
  export const random = (): IPageIDiscussionBoardModerationLog.ISummary =>
    typia.random<IPageIDiscussionBoardModerationLog.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("articleId")(() => typia.assert(props.articleId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
