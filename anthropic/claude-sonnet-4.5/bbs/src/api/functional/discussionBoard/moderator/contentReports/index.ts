/**
 * Retrieves a paginated list of content reports submitted by members, with
 * advanced filtering and search capabilities for efficient moderation workflow
 * management.
 *
 * This operation is exclusively available to moderators who need to review
 * community-submitted reports about potentially problematic articles. The
 * endpoint supports comprehensive filtering to help moderators prioritize and
 * manage the moderation queue effectively.
 *
 * Filtering capabilities include report status (pending, reviewed_no_action,
 * reviewed_edited, reviewed_removed), report category (Spam, Offensive Content,
 * Misinformation, Off-Topic, Other), date ranges for submission time, specific
 * articles being reported, and specific members who submitted reports. Multiple
 * filters can be combined to narrow down results precisely.
 *
 * The response includes complete report information: reporting member details,
 * reported article summary, selected violation category, optional detailed
 * explanation from the reporter, current resolution status, and resolution
 * details if the report has been reviewed. This comprehensive data enables
 * moderators to understand context and make informed moderation decisions.
 *
 * Results are paginated with configurable page size (default 20 reports per
 * page) and support sorting by submission date, resolution date, or report
 * priority. Articles with multiple reports are typically prioritized higher in
 * default sorting to surface content requiring urgent attention.
 *
 * Security: This endpoint requires moderator authentication and authorization.
 * Regular members and guests cannot access content reports. The operation
 * returns reports across all articles regardless of authorship, providing
 * moderators with system-wide visibility.
 *
 * Related operations: After reviewing reports through this endpoint, moderators
 * typically use article editing operations to modify content, article deletion
 * operations to remove violating content, or report resolution operations to
 * mark reports as reviewed. The moderation workflow integrates tightly with
 * article management operations.
 *
 * @param props.connection
 * @param props.body Search and filter criteria for content reports including
 *   status, category, date ranges, and pagination parameters
 * @path /discussionBoard/moderator/contentReports
 * @accessor api.functional.discussionBoard.moderator.contentReports.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
