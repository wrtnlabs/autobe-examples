import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardComment } from "../../../../../structures/IDiscussionBoardComment";

/**
 * Delete a comment from a discussion board article.
 *
 * Permanently remove a comment from a discussion board article.
 *
 * This operation allows registered members to delete their previously posted
 * comments on articles. The member must be the original author of the comment
 * to perform this deletion. Moderators have additional privileges to delete any
 * comment for moderation purposes, such as removing inappropriate content or
 * spam.
 *
 * Security: Only authenticated members can delete comments. Authorization logic
 * verifies that the requesting user is either the original comment author or a
 * moderator with deletion privileges. The operation performs a hard delete,
 * permanently removing the comment record from the database without soft-delete
 * preservation.
 *
 * Once deleted, the comment is immediately removed from the article's comment
 * thread and cannot be recovered. The deletion may affect comment threading and
 * reply structures if the deleted comment had child replies. The system handles
 * orphaned replies according to the business logic defined in the
 * requirements.
 *
 * Related operations: Create comment (POST /articles/{articleId}/comments),
 * Update comment (PUT /articles/{articleId}/comments/{commentId}), View article
 * with comments (GET /articles/{articleId}).
 *
 * @param props.connection
 * @param props.articleId Unique identifier of the target article containing the
 *   comment
 * @param props.commentId Unique identifier of the target comment to delete
 * @path /discussionBoard/moderator/articles/:articleId/comments/:commentId
 * @accessor api.functional.discussionBoard.moderator.articles.comments.erase
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function erase(
  connection: IConnection,
  props: erase.Props,
): Promise<erase.Response> {
  return true === connection.simulate
    ? erase.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...erase.METADATA,
          path: erase.path(props),
          status: null,
        },
      );
}
export namespace erase {
  export type Props = {
    /** Unique identifier of the target article containing the comment */
    articleId: string & tags.Format<"uuid">;

    /** Unique identifier of the target comment to delete */
    commentId: string & tags.Format<"uuid">;
  };
  export type Response = IDiscussionBoardComment;

  export const METADATA = {
    method: "DELETE",
    path: "/discussionBoard/moderator/articles/:articleId/comments/:commentId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/moderator/articles/${encodeURIComponent(props.articleId ?? "null")}/comments/${encodeURIComponent(props.commentId ?? "null")}`;
  export const random = (): IDiscussionBoardComment =>
    typia.random<IDiscussionBoardComment>();
  export const simulate = (
    connection: IConnection,
    props: erase.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: erase.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("articleId")(() => typia.assert(props.articleId));
      assert.param("commentId")(() => typia.assert(props.commentId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
