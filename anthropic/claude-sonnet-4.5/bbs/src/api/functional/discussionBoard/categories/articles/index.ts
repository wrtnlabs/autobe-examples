import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardArticle } from "../../../../structures/IDiscussionBoardArticle";
import { IPageIDiscussionBoardArticle } from "../../../../structures/IPageIDiscussionBoardArticle";

/**
 * Search and retrieve paginated articles within a specific category.
 *
 * This operation provides comprehensive search and filtering capabilities for
 * discovering articles within a specific discussion board category. Categories
 * are the primary taxonomy for organizing economic and political discourse
 * topics, and this endpoint enables users to explore all content within a
 * particular subject area with advanced filtering, sorting, and pagination.
 *
 * The operation performs a complex query joining the discussion_board_articles
 * table with the discussion_board_article_categories junction table to identify
 * articles belonging to the specified category (matched by slug from
 * discussion_board_categories). The request body supports extensive filtering
 * options including publication status (published, draft, archived), date range
 * filters for article creation, author filtering, keyword search across both
 * article titles and body content using PostgreSQL full-text search with
 * trigram indexing, view count ranges, and comment count ranges. Results
 * automatically exclude soft-deleted articles by filtering WHERE deleted_at IS
 * NULL, ensuring only active content appears in search results.
 *
 * The response returns paginated results using the
 * IPageIDiscussionBoardArticle.ISummary type, which contains both pagination
 * metadata (total count, page number, page size, total pages) and an array of
 * article summaries. The summary format provides essential information for list
 * display including article ID, title, excerpt (first 200 characters of body or
 * explicit summary field), author information (username, display name),
 * category and tag information, view and comment counts, and publication
 * timestamp. This optimized response format enables fast rendering of article
 * lists without transferring full article bodies.
 *
 * Sorting options allow users to organize results by creation date (newest or
 * oldest first), view count (most viewed first), comment count (most discussed
 * first), or last update timestamp (recently active first). The operation
 * supports all user actor types with appropriate permission handling: guests
 * can search published articles, members can search published articles plus
 * their own drafts, and moderators can search all articles including those from
 * suspended users for moderation purposes. Performance is optimized through
 * database indexing on created_at, status, and trigram indexes on title and
 * body columns, ensuring search results return within 2 seconds even with large
 * article datasets.
 *
 * @param props.connection
 * @param props.categorySlug URL-friendly unique identifier of the target
 *   category to filter articles (global scope)
 * @param props.body Advanced search criteria including filters, sorting
 *   preferences, and pagination parameters for category article discovery
 * @path /discussionBoard/categories/:categorySlug/articles
 * @accessor api.functional.discussionBoard.categories.articles.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * URL-friendly unique identifier of the target category to filter
     * articles (global scope)
     */
    categorySlug: string;

    /**
     * Advanced search criteria including filters, sorting preferences, and
     * pagination parameters for category article discovery
     */
    body: IDiscussionBoardArticle.IRequest;
  };
  export type Body = IDiscussionBoardArticle.IRequest;
  export type Response = IPageIDiscussionBoardArticle.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/discussionBoard/categories/:categorySlug/articles",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/discussionBoard/categories/${encodeURIComponent(props.categorySlug ?? "null")}/articles`;
  export const random = (): IPageIDiscussionBoardArticle.ISummary =>
    typia.random<IPageIDiscussionBoardArticle.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("categorySlug")(() => typia.assert(props.categorySlug));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
