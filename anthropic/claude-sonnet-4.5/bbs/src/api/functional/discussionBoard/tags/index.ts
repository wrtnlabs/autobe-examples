/**
 * Search and retrieve a filtered, paginated list of discussion board tags.
 *
 * Retrieve a filtered and paginated list of tags used throughout the discussion
 * board system. This operation provides advanced search capabilities for
 * discovering tags based on partial name matching, creation date ranges, and
 * popularity metrics.
 *
 * The operation supports comprehensive pagination with configurable page sizes
 * and multiple sorting options. Users can sort tags alphabetically by name, by
 * creation date to find newest or oldest tags, or by usage frequency to
 * identify the most popular discussion topics. This flexibility enables both
 * casual browsing and targeted tag discovery.
 *
 * Tags serve as granular topic keywords that complement the formal category
 * structure defined in discussion_board_categories. While categories provide
 * broad subject organization (Economic Policy, Political Analysis), tags offer
 * specific topic identification (monetary-policy, climate-change, taxation).
 * This operation is essential for content discovery, allowing users to explore
 * discussion topics at a detailed level and find articles related to specific
 * economic and political subjects.
 *
 * Security considerations include rate limiting for search operations to
 * prevent abuse. The operation is available to all user types including guests,
 * as tag browsing is a public discovery feature. Response includes tag metadata
 * such as creation dates and article counts to help users assess tag relevance
 * and popularity.
 *
 * @param props.connection
 * @param props.body Search criteria, filtering options, sorting preferences,
 *   and pagination parameters for tag retrieval
 * @path /discussionBoard/tags
 * @accessor api.functional.discussionBoard.tags.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
