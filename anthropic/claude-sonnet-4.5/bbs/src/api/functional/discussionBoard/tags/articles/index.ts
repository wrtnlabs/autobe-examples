import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardArticle } from "../../../../structures/IDiscussionBoardArticle";
import { IPageIDiscussionBoardArticle } from "../../../../structures/IPageIDiscussionBoardArticle";

/**
 * Search and retrieve paginated list of articles with a specific tag.
 *
 * Retrieves a comprehensive, filtered, and paginated list of articles that have
 * been tagged with a specific tag, identified by its URL-friendly slug. This
 * operation provides advanced search capabilities for discovering content
 * related to specific topics within the economic and political discussion
 * board.
 *
 * The operation joins the discussion_board_articles table with the
 * discussion_board_article_tags junction table and discussion_board_tags table
 * to filter articles that have the specified tag applied. It supports extensive
 * search parameters including keyword search across article titles and bodies,
 * filtering by additional categories, date range filtering, author filtering,
 * sorting by various criteria (newest, oldest, most viewed, most commented),
 * and pagination controls. All searches exclude soft-deleted articles (where
 * deleted_at is not null) to ensure only active, published content appears in
 * results.
 *
 * This tag-based article discovery serves a critical user need described in the
 * Search and Discovery requirements: enabling users to find discussions on
 * specific topics through the granular tag taxonomy. Tags provide more detailed
 * topic classification than broad categories, allowing users to discover
 * articles on focused subjects like monetary-policy, healthcare-reform, or
 * climate-change. When users browse or click tags throughout the platform, this
 * operation delivers the relevant article listings.
 *
 * Performance expectations are important for user experience. The operation
 * must return results within 2 seconds for typical tag-based searches as
 * specified in the Performance and Scalability requirements. The response
 * includes article summaries optimized for list display rather than full
 * article content, reducing payload size and improving rendering speed.
 * Pagination with 20 articles per page by default ensures fast loading even for
 * popular tags with hundreds of associated articles.
 *
 * Security and access control are straightforward: this is a public read
 * operation accessible to all users including unauthenticated guests, as
 * tag-based browsing is a core content discovery mechanism. The operation
 * respects article visibility rules, excluding deleted articles and potentially
 * filtering based on article status. Response data should include article
 * metadata (title, author, summary, creation date, view count, comment count)
 * along with category and tag information to enable rich display in article
 * listing interfaces.
 *
 * @param props.connection
 * @param props.tagSlug URL-friendly slug identifier of the tag to filter
 *   articles by (global scope)
 * @param props.body Search, filtering, sorting, and pagination parameters for
 *   retrieving articles tagged with the specified tag
 * @path /discussionBoard/tags/:tagSlug/articles
 * @accessor api.functional.discussionBoard.tags.articles.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * URL-friendly slug identifier of the tag to filter articles by (global
     * scope)
     */
    tagSlug: string;

    /**
     * Search, filtering, sorting, and pagination parameters for retrieving
     * articles tagged with the specified tag
     */
    body: IDiscussionBoardArticle.IRequest;
  };
  export type Body = IDiscussionBoardArticle.IRequest;
  export type Response = IPageIDiscussionBoardArticle.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/discussionBoard/tags/:tagSlug/articles",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/discussionBoard/tags/${encodeURIComponent(props.tagSlug ?? "null")}/articles`;
  export const random = (): IPageIDiscussionBoardArticle.ISummary =>
    typia.random<IPageIDiscussionBoardArticle.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("tagSlug")(() => typia.assert(props.tagSlug));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
