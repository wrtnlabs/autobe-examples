import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardEmailVerification } from "../../../structures/IDiscussionBoardEmailVerification";

/**
 * Create email verification token for member registration.
 *
 * Create a new email verification record and send verification email to a
 * member's registered email address. This operation generates a unique
 * verification token valid for 24 hours and sends it to the member's email.
 *
 * Email verification is required before members can create articles and access
 * full platform features. Upon registration, a verification token is
 * automatically generated through this endpoint and sent to the member's email
 * address. Members can also request new verification emails if the original
 * token expires.
 *
 * The operation validates that the member account exists and is not already
 * verified. It generates a cryptographically secure random token, stores it in
 * the discussion_board_email_verifications table with a 24-hour expiration
 * timestamp, and triggers the email sending process. Each verification record
 * contains the token, target email address, and expiration details.
 *
 * Security considerations include rate limiting to prevent abuse (maximum 3
 * verification emails per member per hour) and token uniqueness validation. The
 * verification token is single-use and invalidated after successful
 * verification or expiration.
 *
 * Related operations: Members complete verification by accessing the
 * verification link sent via email, which triggers a separate verification
 * confirmation process.
 *
 * @param props.connection
 * @param props.body Member email verification request details
 * @path /discussionBoard/emailVerifications
 * @accessor api.functional.discussionBoard.emailVerifications.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function create(
  connection: IConnection,
  props: create.Props,
): Promise<create.Response> {
  return true === connection.simulate
    ? create.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...create.METADATA,
          path: create.path(),
          status: null,
        },
        props.body,
      );
}
export namespace create {
  export type Props = {
    /** Member email verification request details */
    body: IDiscussionBoardEmailVerification.ICreate;
  };
  export type Body = IDiscussionBoardEmailVerification.ICreate;
  export type Response = IDiscussionBoardEmailVerification;

  export const METADATA = {
    method: "POST",
    path: "/discussionBoard/emailVerifications",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/discussionBoard/emailVerifications";
  export const random = (): IDiscussionBoardEmailVerification =>
    typia.random<IDiscussionBoardEmailVerification>();
  export const simulate = (
    connection: IConnection,
    props: create.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: create.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
