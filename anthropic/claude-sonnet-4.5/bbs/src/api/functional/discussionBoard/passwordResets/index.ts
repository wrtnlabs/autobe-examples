import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardPasswordReset } from "../../../structures/IDiscussionBoardPasswordReset";

/**
 * Initiate a password reset request by generating a secure reset token and
 * sending it to the user's registered email address. This operation supports
 * both member and moderator accounts through polymorphic actor pattern.
 *
 * The operation validates that the provided email address exists in either the
 * discussion_board_members or discussion_board_moderators table. It generates a
 * cryptographically secure random token, stores it in the
 * discussion_board_password_resets table with a 1-hour expiration timestamp,
 * and creates the corresponding subtype record
 * (discussion_board_password_reset_of_members or
 * discussion_board_password_reset_of_moderators) to maintain proper
 * normalization.
 *
 * Password reset tokens are sent to the user's registered email address and
 * allow users to set a new password without knowing their current password.
 * Each reset request includes the actor_type discriminator field to distinguish
 * between member and moderator requests. The token is single-use and
 * invalidated after successful password change.
 *
 * Security measures include rate limiting (maximum 3 password reset requests
 * per email per hour) to prevent abuse, and the system does not reveal whether
 * an email address exists in the database to prevent account enumeration
 * attacks. Previous reset tokens for the same account are invalidated when a
 * new request is made.
 *
 * The operation uses PATCH method because it requires complex request data
 * (email address and actor type) to search for the appropriate account and
 * initiate the reset process. After successful token generation, users receive
 * an email with a reset link valid for 1 hour.
 *
 * Related operations: Users complete password reset by accessing the reset link
 * sent via email, which triggers a separate password change operation that
 * validates the token and updates the password.
 *
 * @param props.connection
 * @param props.body Password reset request with email and actor type
 * @path /discussionBoard/passwordResets
 * @accessor api.functional.discussionBoard.passwordResets.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function create(
  connection: IConnection,
  props: create.Props,
): Promise<create.Response> {
  return true === connection.simulate
    ? create.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...create.METADATA,
          path: create.path(),
          status: null,
        },
        props.body,
      );
}
export namespace create {
  export type Props = {
    /** Password reset request with email and actor type */
    body: IDiscussionBoardPasswordReset.ICreate;
  };
  export type Body = IDiscussionBoardPasswordReset.ICreate;
  export type Response = IDiscussionBoardPasswordReset;

  export const METADATA = {
    method: "PATCH",
    path: "/discussionBoard/passwordResets",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/discussionBoard/passwordResets";
  export const random = (): IDiscussionBoardPasswordReset =>
    typia.random<IDiscussionBoardPasswordReset>();
  export const simulate = (
    connection: IConnection,
    props: create.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: create.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
