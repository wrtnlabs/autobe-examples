/**
 * Retrieve detailed information about a specific content report submitted by a
 * member flagging an article for policy violations.
 *
 * This operation returns comprehensive details about a single content report,
 * including the violation category selected by the reporter, optional detailed
 * explanation, current resolution status (pending, reviewed_no_action,
 * reviewed_edited, reviewed_removed), moderator resolution notes if reviewed,
 * and all relevant timestamps. The response includes relationships to the
 * reported article, reporting member, and resolving moderator if applicable.
 *
 * Security considerations include access control based on user role. Moderators
 * can view any content report to perform their review duties. Members can only
 * view reports they personally submitted to track resolution status. Guest
 * users have no access to content reports. The operation validates that the
 * requesting user has appropriate permissions before returning report data.
 *
 * This operation integrates with the discussion_board_content_reports table as
 * defined in the Prisma schema. The response includes the report's current
 * status in the moderation workflow, enabling moderators to prioritize pending
 * reports and allowing reporting members to see how their concerns were
 * addressed. Reports track the complete lifecycle from submission through
 * moderator review to final resolution.
 *
 * @param props.connection
 * @param props.reportId Unique identifier of the target content report
 * @path /discussionBoard/member/contentReports/:reportId
 * @accessor api.functional.discussionBoard.member.contentReports.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique identifier of the target content report */
    reportId: string & tags.Format<"uuid">;
  };
  export type Response = IDiscussionBoardContentReport;

  export const METADATA = {
    method: "GET",
    path: "/discussionBoard/member/contentReports/:reportId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/member/contentReports/${encodeURIComponent(props.reportId ?? "null")}`;
  export const random = (): IDiscussionBoardContentReport =>
    typia.random<IDiscussionBoardContentReport>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("reportId")(() => typia.assert(props.reportId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

