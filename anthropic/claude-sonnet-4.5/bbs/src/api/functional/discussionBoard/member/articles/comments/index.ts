/**
 * Create a new comment on a discussion board article.
 *
 * This operation enables authenticated members and moderators to post new
 * comments on articles within the discussion board system. Comments are the
 * primary mechanism for user engagement and discussion on economic and
 * political topics, allowing the community to respond to article content, ask
 * questions, and engage in substantive dialogue.
 *
 * The operation validates that the target article exists and is accessible,
 * verifies the user is authenticated as a member or moderator, and validates
 * the comment content meets length requirements (minimum 1 character, maximum
 * 5000 characters as specified in requirements). The comment is associated with
 * the article identified by the articleId path parameter and attributed to the
 * authenticated user through the author_type discriminator field and
 * corresponding discussion_board_member_id or discussion_board_moderator_id
 * foreign key.
 *
 * Upon successful creation, the comment appears immediately in the article's
 * comment thread without requiring moderation approval. The system
 * automatically records the creation timestamp, sets the comment status to
 * active, and increments the parent article's comment_count metadata. Comments
 * support single-level threading through the discussion_board_parent_comment_id
 * field, allowing replies to top-level comments while maintaining simplicity by
 * preventing deeply nested conversation threads.
 *
 * Security considerations include authentication verification to prevent
 * unauthenticated posting, input sanitization to prevent XSS attacks, rate
 * limiting to prevent spam (members limited to reasonable posting frequency),
 * and content validation to ensure meaningful contributions. The operation
 * respects the article's publication status, allowing comments only on
 * published articles, not drafts or deleted content.
 *
 * Related operations include GET /articles/{articleId}/comments for retrieving
 * comment threads, PUT /comments/{commentId} for editing own comments, and
 * DELETE /comments/{commentId} for removing comments. This operation is
 * fundamental to the discussion board's core value proposition of enabling
 * evidence-based discourse on economic and political topics.
 *
 * @param props.connection
 * @param props.articleId Unique identifier of the target article where the
 *   comment will be posted
 * @param props.body Comment content and threading information for creating a
 *   new comment on the article
 * @path /discussionBoard/member/articles/:articleId/comments
 * @accessor api.functional.discussionBoard.member.articles.comments.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function create(
  connection: IConnection,
  props: create.Props,
): Promise<create.Response> {
  return true === connection.simulate
    ? create.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...create.METADATA,
          path: create.path(props),
          status: null,
        },
        props.body,
      );
}
