import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardMemberSession } from "../../../../../structures/IDiscussionBoardMemberSession";
import { IPageIDiscussionBoardMemberSession } from "../../../../../structures/IPageIDiscussionBoardMemberSession";

/**
 * Retrieve a filtered and paginated list of authentication sessions for the
 * currently authenticated member from the discussion board platform.
 *
 * This operation provides session management and security monitoring
 * capabilities by allowing members to view all their sessions (both active and
 * expired). It supports filtering by session status (active vs expired),
 * creation date ranges, IP address patterns, and connection context. Results
 * can be sorted by creation date, expiration date, or other session attributes
 * to identify suspicious activity patterns or manage concurrent sessions.
 *
 * The member identity is automatically extracted from the JWT authentication
 * token - there is no memberId parameter. This ensures members can ONLY view
 * their own session history, preventing session enumeration attacks where users
 * could attempt to access other members' session data.
 *
 * Security considerations include proper authentication verification (401
 * Unauthorized if token is missing or invalid), rate limiting to prevent
 * automated session scraping (limited to 10 requests per minute per member),
 * and careful handling of sensitive session context data. Session tokens
 * themselves are never exposed through this API - only session metadata and
 * lifecycle information are returned.
 *
 * This operation integrates with the discussion_board_member_sessions table as
 * defined in the Prisma schema, using the discussion_board_member_id foreign
 * key to filter sessions belonging to the authenticated member. The response
 * includes session summary information displaying connection context (IP
 * address, referrer), session duration, and current status (active/expired) to
 * help members manage their active sessions and review historical
 * authentication activity for security awareness.
 *
 * @param props.connection
 * @param props.body Search criteria, filtering options, pagination parameters,
 *   and sorting preferences for member sessions
 * @path /discussionBoard/member/my/sessions
 * @accessor api.functional.discussionBoard.member.my.sessions.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Search criteria, filtering options, pagination parameters, and
     * sorting preferences for member sessions
     */
    body: IDiscussionBoardMemberSession.IRequest;
  };
  export type Body = IDiscussionBoardMemberSession.IRequest;
  export type Response = IPageIDiscussionBoardMemberSession.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/discussionBoard/member/my/sessions",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/discussionBoard/member/my/sessions";
  export const random = (): IPageIDiscussionBoardMemberSession.ISummary =>
    typia.random<IPageIDiscussionBoardMemberSession.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
