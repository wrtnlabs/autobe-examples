import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardMember } from "../../../../../structures/IDiscussionBoardMember";

/**
 * Update member account password with security verification.
 *
 * Updates the password for an authenticated member account, implementing
 * comprehensive security measures to protect account integrity and user data.
 * This operation follows the password change workflow defined in the User
 * Profiles and Settings requirements, requiring verification of the current
 * password before allowing the new password to be set, thus preventing
 * unauthorized password changes even if an attacker gains temporary session
 * access.
 *
 * The password update process enforces strict password strength requirements:
 * minimum 8 characters in length, must contain at least one uppercase letter
 * (A-Z), at least one lowercase letter (a-z), at least one numeric digit (0-9),
 * and at least one special character from the set (!@#$%^&*()_+-=[]{}|;:,.<>?).
 * The new password must differ from the current password to prevent users from
 * rotating back to the same password. The operation validates the new password
 * against common password breach databases to prevent use of compromised
 * passwords. Password strength is calculated and users are encouraged to choose
 * strong passwords, though medium-strength passwords meeting the minimum
 * requirements are accepted.
 *
 * When a password change completes successfully, the system performs critical
 * security actions: updates the password_hash field in the
 * discussion_board_members table using secure hashing (bcrypt or equivalent),
 * invalidates all existing JWT refresh tokens across all devices and sessions
 * to force re-authentication, issues a new refresh token for the current
 * session to maintain the user's login state, and sends a confirmation email to
 * the registered email address notifying the member of the password change with
 * instructions for reporting unauthorized changes. The operation maintains
 * comprehensive security event logging, recording the password change
 * timestamp, IP address, and session information for security auditing. This
 * operation is essential for account security, enabling members to maintain
 * control of their accounts and respond to potential security threats.
 *
 * @param props.connection
 * @param props.memberUsername Unique username of the member account whose
 *   password is being updated (global scope)
 * @param props.body Password change request containing current password for
 *   verification and new password meeting strength requirements
 * @path /discussionBoard/member/members/:memberUsername/password
 * @accessor api.functional.discussionBoard.member.members.password.updatePassword
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function updatePassword(
  connection: IConnection,
  props: updatePassword.Props,
): Promise<updatePassword.Response> {
  return true === connection.simulate
    ? updatePassword.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...updatePassword.METADATA,
          path: updatePassword.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace updatePassword {
  export type Props = {
    /**
     * Unique username of the member account whose password is being updated
     * (global scope)
     */
    memberUsername: string;

    /**
     * Password change request containing current password for verification
     * and new password meeting strength requirements
     */
    body: IDiscussionBoardMember.IPasswordUpdate;
  };
  export type Body = IDiscussionBoardMember.IPasswordUpdate;
  export type Response = IDiscussionBoardMember.IPasswordChange;

  export const METADATA = {
    method: "PUT",
    path: "/discussionBoard/member/members/:memberUsername/password",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/discussionBoard/member/members/${encodeURIComponent(props.memberUsername ?? "null")}/password`;
  export const random = (): IDiscussionBoardMember.IPasswordChange =>
    typia.random<IDiscussionBoardMember.IPasswordChange>();
  export const simulate = (
    connection: IConnection,
    props: updatePassword.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: updatePassword.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("memberUsername")(() => typia.assert(props.memberUsername));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
