import { IConnection } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";

import { IDiscussionBoardAuth } from "../../../../structures/IDiscussionBoardAuth";

/**
 * Terminate current member session and invalidate authentication tokens.
 *
 * Terminate the currently authenticated member session by invalidating the
 * refresh token and recording the session end time in the
 * discussion_board_member_sessions table. This operation enables members to
 * securely end their authenticated session, preventing further use of the
 * current refresh token to obtain new access tokens.
 *
 * The logout process marks the current session as expired by setting the
 * expired_at timestamp to the current time, creating a complete audit trail of
 * session duration and member activity. The operation extracts the member's
 * identity and current session information from the JWT access token,
 * eliminating the need for request body parameters. After successful logout,
 * the client must discard both the access token and refresh token from local
 * storage to complete the logout process.
 *
 * This operation is particularly important for security when members access the
 * system from shared or public devices, as it ensures that sessions are
 * properly terminated rather than remaining active until the 30-day refresh
 * token expiration. The logout action only affects the current device's session
 * - members can remain logged in on other devices if they have multiple active
 * sessions across different browsers or devices. When a member changes their
 * password, all sessions across all devices are invalidated automatically
 * through a separate mechanism, but manual logout only terminates the specific
 * session from which it was initiated.
 *
 * The operation requires a valid member access token to identify the session to
 * be terminated. No request body is needed as all session information is
 * derived from the authentication token. The response confirms successful
 * logout, after which the member must authenticate again using the login
 * operation to regain access to protected member features such as article
 * creation and comment posting.
 *
 * @param props.connection
 * @path /discussionBoard/member/auth/logout
 * @accessor api.functional.discussionBoard.member.auth.logout
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function logout(
  connection: IConnection,
): Promise<logout.Response> {
  return true === connection.simulate
    ? logout.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...logout.METADATA,
          path: logout.path(),
          status: null,
        },
      );
}
export namespace logout {
  export type Response = IDiscussionBoardAuth.ILogoutResult;

  export const METADATA = {
    method: "POST",
    path: "/discussionBoard/member/auth/logout",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/discussionBoard/member/auth/logout";
  export const random = (): IDiscussionBoardAuth.ILogoutResult =>
    typia.random<IDiscussionBoardAuth.ILogoutResult>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}
