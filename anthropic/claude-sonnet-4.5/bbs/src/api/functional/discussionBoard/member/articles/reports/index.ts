import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardContentReport } from "../../../../../structures/IDiscussionBoardContentReport";

/**
 * Submit a new content report flagging an article for potential policy
 * violations or inappropriate content.
 *
 * This operation empowers community members to participate in content quality
 * management by reporting articles that violate community guidelines, contain
 * spam, misinformation, offensive content, or other policy issues. The
 * operation creates a new record in the discussion_board_content_reports table
 * associated with the specified article and the authenticated member who is
 * submitting the report.
 *
 * The request body requires selection of a report_category from predefined
 * options (Spam, Offensive Content, Misinformation, Off-Topic, Other) to help
 * moderators categorize and prioritize reports. Members can optionally provide
 * detailed explanations in the report_details field to give moderators context
 * about the specific violation or concern. The reporting member's identity is
 * automatically captured from the authentication token to track report
 * authorship while maintaining appropriate confidentiality from the article
 * author.
 *
 * Business rules enforced include preventing duplicate reports (members cannot
 * report the same article multiple times), validating that the article exists
 * and is in a reportable state, and rate limiting to prevent report spam abuse.
 * The created report is automatically assigned 'pending' status and added to
 * the moderation queue with creation timestamp for moderator review
 * prioritization.
 *
 * Security considerations: Only authenticated members can submit reports to
 * prevent anonymous spam. The system should track reporting patterns to
 * identify potential coordinated abuse or excessive reporting by individual
 * members. Reporter identity is logged for accountability but should be handled
 * according to privacy policies regarding report confidentiality.
 *
 * This operation integrates with the discussion_board_content_reports table as
 * defined in the Prisma schema, setting appropriate foreign key relationships
 * to both the reported article (discussion_board_article_id) and the reporting
 * member (discussion_board_member_id). Related operations include PATCH
 * /articles/{articleId}/reports for viewing existing reports and moderator
 * endpoints for reviewing and resolving reports.
 *
 * @param props.connection
 * @param props.articleId Unique identifier of the article being reported for
 *   policy violations
 * @param props.body Report submission data including violation category and
 *   optional detailed explanation
 * @path /discussionBoard/member/articles/:articleId/reports
 * @accessor api.functional.discussionBoard.member.articles.reports.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function create(
  connection: IConnection,
  props: create.Props,
): Promise<create.Response> {
  return true === connection.simulate
    ? create.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...create.METADATA,
          path: create.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace create {
  export type Props = {
    /** Unique identifier of the article being reported for policy violations */
    articleId: string & tags.Format<"uuid">;

    /**
     * Report submission data including violation category and optional
     * detailed explanation
     */
    body: IDiscussionBoardContentReport.ICreate;
  };
  export type Body = IDiscussionBoardContentReport.ICreate;
  export type Response = IDiscussionBoardContentReport;

  export const METADATA = {
    method: "POST",
    path: "/discussionBoard/member/articles/:articleId/reports",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/discussionBoard/member/articles/${encodeURIComponent(props.articleId ?? "null")}/reports`;
  export const random = (): IDiscussionBoardContentReport =>
    typia.random<IDiscussionBoardContentReport>();
  export const simulate = (
    connection: IConnection,
    props: create.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: create.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("articleId")(() => typia.assert(props.articleId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
