import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardUserWarning } from "../../../../../structures/IDiscussionBoardUserWarning";

/**
 * Retrieve detailed information about a specific user warning.
 *
 * Retrieves comprehensive details about a specific warning issued to a member
 * for community guideline violations. This operation provides access to the
 * complete warning record including the violation category, detailed
 * explanation, severity level, acknowledgment status, and all associated
 * metadata. The endpoint supports both moderator access (who can view all
 * warnings for moderation purposes) and member access (who can view their own
 * warnings for transparency).
 *
 * The returned warning information includes the warning reason category (such
 * as spam, harassment, off-topic content, or misinformation), detailed
 * explanation of what specific behavior or content violated guidelines, and the
 * severity classification (minor, moderate, or severe) which indicates the
 * violation's seriousness in the progressive discipline framework. The response
 * also includes timestamps showing when the warning was issued and when the
 * member acknowledged it (if acknowledgment has occurred).
 *
 * For moderators, this operation provides complete context for reviewing a
 * member's violation history, including information about the moderator who
 * issued the warning and any related moderation actions or reports that led to
 * the warning. This comprehensive view enables moderators to make informed
 * decisions about future enforcement actions based on the member's complete
 * disciplinary record. For members viewing their own warnings, the response
 * helps them understand exactly what guidelines were violated and what behavior
 * changes are expected.
 *
 * The operation enforces proper access control by validating that moderators
 * can view any warning while members can only access warnings issued to their
 * own account. This ensures privacy while maintaining the transparency needed
 * for fair moderation practices and appeal processes.
 *
 * @param props.connection
 * @param props.warningId Unique identifier of the target warning
 * @path /discussionBoard/member/moderation/warnings/:warningId
 * @accessor api.functional.discussionBoard.member.moderation.warnings.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique identifier of the target warning */
    warningId: string & tags.Format<"uuid">;
  };
  export type Response = IDiscussionBoardUserWarning;

  export const METADATA = {
    method: "GET",
    path: "/discussionBoard/member/moderation/warnings/:warningId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/member/moderation/warnings/${encodeURIComponent(props.warningId ?? "null")}`;
  export const random = (): IDiscussionBoardUserWarning =>
    typia.random<IDiscussionBoardUserWarning>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("warningId")(() => typia.assert(props.warningId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
