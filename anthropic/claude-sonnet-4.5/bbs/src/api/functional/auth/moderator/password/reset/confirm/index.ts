import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardModerator } from "../../../../../../structures/IDiscussionBoardModerator";

/**
 * Reset moderator password using valid reset token.
 *
 * Completes the password reset process by validating the reset token and
 * updating the moderator's password.
 *
 * This operation enables moderators to set a new password after requesting a
 * password reset. The moderator provides the reset token (received via email)
 * and their desired new password. The system validates the token against
 * discussion_board_password_resets table, ensuring it belongs to a moderator
 * (actor_type='moderator'), hasn't been used (used_at=null), and hasn't expired
 * (expires_at > current time).
 *
 * The operation retrieves the associated moderator account through the
 * discussion_board_password_reset_of_moderators relationship table, which links
 * the reset request to the specific moderator (discussion_board_moderator_id).
 * Only active moderator accounts (is_active=true, deleted_at=null) can
 * successfully reset passwords.
 *
 * Upon successful validation, the new password is hashed using bcrypt with work
 * factor 10+ and stored in the discussion_board_moderators table, replacing the
 * old password. The used_at timestamp in the password reset record is set to
 * mark the token as consumed, preventing reuse. The reset token becomes invalid
 * after this operation.
 *
 * The operation enforces password security requirements through validation
 * rules, ensuring the new password meets minimum complexity standards. If the
 * token is invalid, expired, already used, or belongs to an inactive account,
 * appropriate error responses are returned.
 *
 * After successful password reset, the moderator can login using their email
 * and new password through the standard login endpoint.
 *
 * @param props.connection
 * @param props.body Password reset token and new password
 * @path /auth/moderator/password/reset/confirm
 * @accessor api.functional.auth.moderator.password.reset.confirm.resetPassword
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function resetPassword(
  connection: IConnection,
  props: resetPassword.Props,
): Promise<void> {
  return true === connection.simulate
    ? resetPassword.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...resetPassword.METADATA,
          path: resetPassword.path(),
          status: null,
        },
        props.body,
      );
}
export namespace resetPassword {
  export type Props = {
    /** Password reset token and new password */
    body: IDiscussionBoardModerator.IResetPassword;
  };
  export type Body = IDiscussionBoardModerator.IResetPassword;

  export const METADATA = {
    method: "POST",
    path: "/auth/moderator/password/reset/confirm",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/moderator/password/reset/confirm";
  export const random = (): void => typia.random<void>();
  export const simulate = (
    connection: IConnection,
    props: resetPassword.Props,
  ): void => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: resetPassword.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
