/**
 * Request password reset token for moderator account.
 *
 * Initiates a password reset process for moderators by generating and sending a
 * secure reset token to their registered email address.
 *
 * This operation enables moderators to securely recover their accounts when
 * they have forgotten their password. The moderator provides their registered
 * email address, and the system generates a cryptographically secure random
 * token that is stored in the discussion_board_password_resets table with
 * actor_type='moderator'.
 *
 * The password reset record is created with a 1-hour expiration timestamp
 * (expires_at) for security. The token is sent to the moderator's email
 * address, allowing them to click a reset link and set a new password without
 * knowing their current password. The email field is stored in the reset record
 * to validate requests against the current account email.
 *
 * A corresponding entry is created in
 * discussion_board_password_reset_of_moderators table to maintain the
 * relationship between the reset request and the specific moderator account
 * (discussion_board_moderator_id), following the Compatible Actor Pattern for
 * proper 3NF normalization.
 *
 * The operation validates that the provided email belongs to an active
 * moderator account (is_active=true, deleted_at=null) before generating the
 * reset token. If the email is not found or belongs to an inactive account, the
 * operation returns success without revealing account existence, preventing
 * account enumeration attacks.
 *
 * Reset tokens are single-use and invalidated after successful password change
 * (used_at timestamp set) or expiration. Moderators can request new reset
 * tokens if the original token expires before use.
 *
 * @param props.connection
 * @param props.body Moderator email address for password reset
 * @path /auth/moderator/password/reset/request
 * @accessor api.functional.auth.moderator.password.reset.request.requestPasswordReset
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function requestPasswordReset(
  connection: IConnection,
  props: requestPasswordReset.Props,
): Promise<void> {
  return true === connection.simulate
    ? requestPasswordReset.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...requestPasswordReset.METADATA,
          path: requestPasswordReset.path(),
          status: null,
        },
        props.body,
      );
}
