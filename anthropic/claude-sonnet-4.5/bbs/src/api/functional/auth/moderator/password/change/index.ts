import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardModerator } from "../../../../../structures/IDiscussionBoardModerator";

/**
 * Change moderator password with current password validation.
 *
 * Enables authenticated moderators to change their password by providing their
 * current password and new password.
 *
 * This operation allows moderators to update their password while
 * authenticated. Unlike password reset which uses email tokens, password change
 * requires the moderator to provide their current password for security
 * validation. The moderator must be authenticated
 * (authorizationActor='moderator') to access this endpoint.
 *
 * The operation validates the provided current password against the stored
 * password hash in the discussion_board_moderators table using bcrypt
 * comparison. Only if the current password matches can the moderator proceed
 * with setting a new password. This prevents unauthorized password changes even
 * if an authenticated session is compromised.
 *
 * Upon successful validation of the current password, the new password is
 * hashed using bcrypt with work factor 10+ and stored in the
 * discussion_board_moderators table, replacing the old password hash. The
 * password field is never stored or transmitted in plain text for security.
 *
 * The operation enforces password security requirements through validation
 * rules, ensuring the new password meets minimum complexity standards (length,
 * character diversity, etc.). The new password must be different from the
 * current password to prevent accidental no-change updates.
 *
 * After successful password change, all existing moderator sessions in
 * discussion_board_moderator_sessions table can optionally be invalidated
 * (expired_at set to current timestamp) to force re-authentication with the new
 * password, enhancing security. The current session may be preserved to avoid
 * disrupting the moderator's workflow.
 *
 * This operation is distinct from password reset, which is used when moderators
 * have forgotten their password and cannot provide the current password for
 * validation.
 *
 * @param props.connection
 * @param props.body Current password and new password
 * @path /auth/moderator/password/change
 * @accessor api.functional.auth.moderator.password.change.changePassword
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function changePassword(
  connection: IConnection,
  props: changePassword.Props,
): Promise<void> {
  return true === connection.simulate
    ? changePassword.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...changePassword.METADATA,
          path: changePassword.path(),
          status: null,
        },
        props.body,
      );
}
export namespace changePassword {
  export type Props = {
    /** Current password and new password */
    body: IDiscussionBoardModerator.IChangePassword;
  };
  export type Body = IDiscussionBoardModerator.IChangePassword;

  export const METADATA = {
    method: "POST",
    path: "/auth/moderator/password/change",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/moderator/password/change";
  export const random = (): void => typia.random<void>();
  export const simulate = (
    connection: IConnection,
    props: changePassword.Props,
  ): void => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: changePassword.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
