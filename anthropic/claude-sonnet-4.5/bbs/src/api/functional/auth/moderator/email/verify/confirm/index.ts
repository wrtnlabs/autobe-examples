import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardModerator } from "../../../../../../structures/IDiscussionBoardModerator";

/**
 * Verify moderator email address using verification token.
 *
 * Confirms moderator email verification by validating the verification token
 * and updating the email_verified status.
 *
 * This operation completes the email verification process for moderators. The
 * moderator provides the verification token (received via email), and the
 * system validates it against the discussion_board_email_verifications table.
 * The token must belong to the authenticated moderator
 * (discussion_board_member_id matches the moderator's ID), must not be expired
 * (expires_at > current time), and must not have been used previously
 * (verified_at=null).
 *
 * Upon successful validation, the operation updates the
 * discussion_board_moderators table, setting email_verified=true and
 * email_verified_at to the current timestamp. This marks the email as confirmed
 * and grants the moderator full moderation privileges if previously
 * restricted.
 *
 * The verified_at timestamp in the discussion_board_email_verifications record
 * is set to mark the token as used, preventing token reuse. The verification
 * token becomes invalid after successful verification.
 *
 * The operation requires the moderator to be authenticated
 * (authorizationActor='moderator') to ensure only the account owner can verify
 * their email. If the token is invalid, expired, already used, or belongs to a
 * different moderator, appropriate error responses are returned.
 *
 * Email verification is a required security measure before moderators can
 * exercise their full moderation capabilities. Moderators with unverified
 * emails (email_verified=false) may have limited access to moderation features
 * until verification is complete.
 *
 * @param props.connection
 * @param props.body Email verification token
 * @path /auth/moderator/email/verify/confirm
 * @accessor api.functional.auth.moderator.email.verify.confirm.verifyEmail
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function verifyEmail(
  connection: IConnection,
  props: verifyEmail.Props,
): Promise<void> {
  return true === connection.simulate
    ? verifyEmail.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...verifyEmail.METADATA,
          path: verifyEmail.path(),
          status: null,
        },
        props.body,
      );
}
export namespace verifyEmail {
  export type Props = {
    /** Email verification token */
    body: IDiscussionBoardModerator.IVerifyEmail;
  };
  export type Body = IDiscussionBoardModerator.IVerifyEmail;

  export const METADATA = {
    method: "POST",
    path: "/auth/moderator/email/verify/confirm",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/moderator/email/verify/confirm";
  export const random = (): void => typia.random<void>();
  export const simulate = (
    connection: IConnection,
    props: verifyEmail.Props,
  ): void => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: verifyEmail.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
