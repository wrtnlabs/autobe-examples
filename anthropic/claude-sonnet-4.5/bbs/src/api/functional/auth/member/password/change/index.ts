import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardMember } from "../../../../../structures/IDiscussionBoardMember";

/**
 * Change member password with current password validation in
 * discussion_board_members table.
 *
 * Enables authenticated members to change their password as a security
 * maintenance operation, requiring knowledge of the current password to
 * authorize the change. This operation validates the existing password against
 * discussion_board_members, updates to a new bcrypt-hashed password, and
 * manages session lifecycle to maintain security across devices.
 *
 * The password change process first authenticates the request using the
 * member's JWT access token to identify the discussion_board_member_id. The
 * operation then validates that the provided current password matches the
 * hashed password stored in the discussion_board_members table using bcrypt
 * comparison. This verification prevents unauthorized password changes even if
 * a session token is compromised.
 *
 * Upon successful current password validation, the new password is hashed using
 * bcrypt with work factor 10+ and updates the password field in
 * discussion_board_members. The password is never stored or transmitted in
 * plain text, consistent with security standards throughout the authentication
 * system. The updated_at timestamp is set to track when the password change
 * occurred.
 *
 * As a security measure, all existing sessions in
 * discussion_board_member_sessions for this member are invalidated except the
 * current session by setting their expired_at timestamp. This forces
 * re-authentication on other devices while allowing the current session to
 * continue uninterrupted. This prevents potential unauthorized access from
 * previously authenticated devices after a password change.
 *
 * This operation requires member authentication via JWT access token
 * (authorizationActor: 'member') and differs from the password reset flow which
 * is designed for forgotten passwords. Members use this endpoint for routine
 * password updates or security improvements, maintaining continuous
 * authenticated access throughout the process.
 *
 * @param props.connection
 * @param props.body Current password and new password for authenticated member
 * @path /auth/member/password/change
 * @accessor api.functional.auth.member.password.change.changePassword
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function changePassword(
  connection: IConnection,
  props: changePassword.Props,
): Promise<changePassword.Response> {
  return true === connection.simulate
    ? changePassword.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...changePassword.METADATA,
          path: changePassword.path(),
          status: null,
        },
        props.body,
      );
}
export namespace changePassword {
  export type Props = {
    /** Current password and new password for authenticated member */
    body: IDiscussionBoardMember.IChangePassword;
  };
  export type Body = IDiscussionBoardMember.IChangePassword;
  export type Response = IDiscussionBoardMember.IPasswordChanged;

  export const METADATA = {
    method: "POST",
    path: "/auth/member/password/change",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/member/password/change";
  export const random = (): IDiscussionBoardMember.IPasswordChanged =>
    typia.random<IDiscussionBoardMember.IPasswordChanged>();
  export const simulate = (
    connection: IConnection,
    props: changePassword.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: changePassword.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
