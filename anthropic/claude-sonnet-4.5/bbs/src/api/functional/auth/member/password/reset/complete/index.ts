import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardMember } from "../../../../../../structures/IDiscussionBoardMember";

/**
 * Complete password reset by updating member password in
 * discussion_board_members table.
 *
 * Completes the password reset process by validating the reset token and
 * updating the member's password in the discussion_board_members table. This
 * operation consumes a single-use token from discussion_board_password_resets,
 * verifies its validity, and securely updates the member's authentication
 * credentials with a new bcrypt-hashed password.
 *
 * The password reset completion process retrieves the reset record from
 * discussion_board_password_resets using the provided token, validating that
 * actor_type is 'member' and the token hasn't expired (current time <
 * expires_at) or been previously used (used_at is null). The operation then
 * joins to discussion_board_password_reset_of_members to identify the specific
 * member account requiring the password update.
 *
 * Upon successful token validation, the new password is hashed using bcrypt
 * with work factor 10+ and updates the password field in
 * discussion_board_members for the associated discussion_board_member_id. The
 * password is never stored or transmitted in plain text, maintaining security
 * standards consistent with the initial registration process. The reset token
 * is marked as consumed by setting used_at to the current timestamp in
 * discussion_board_password_resets, preventing token reuse.
 *
 * As a security measure, all existing sessions in
 * discussion_board_member_sessions for this member are invalidated by setting
 * their expired_at timestamp, forcing re-authentication with the new password
 * across all devices. This prevents unauthorized access if the password reset
 * was initiated maliciously. The member must login again using the new password
 * to create fresh authenticated sessions.
 *
 * This operation is public and requires no authentication, as it's designed for
 * users who have lost access to their accounts. It completes the password
 * recovery workflow initiated by the password reset request (POST
 * /auth/member/password/reset), restoring account access and requiring fresh
 * login (POST /auth/member/login) with the new credentials.
 *
 * @param props.connection
 * @param props.body Password reset token and new password
 * @path /auth/member/password/reset/complete
 * @accessor api.functional.auth.member.password.reset.complete.resetPassword
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function resetPassword(
  connection: IConnection,
  props: resetPassword.Props,
): Promise<resetPassword.Response> {
  return true === connection.simulate
    ? resetPassword.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...resetPassword.METADATA,
          path: resetPassword.path(),
          status: null,
        },
        props.body,
      );
}
export namespace resetPassword {
  export type Props = {
    /** Password reset token and new password */
    body: IDiscussionBoardMember.IResetPassword;
  };
  export type Body = IDiscussionBoardMember.IResetPassword;
  export type Response = IDiscussionBoardMember.IPasswordResetCompleted;

  export const METADATA = {
    method: "POST",
    path: "/auth/member/password/reset/complete",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/member/password/reset/complete";
  export const random = (): IDiscussionBoardMember.IPasswordResetCompleted =>
    typia.random<IDiscussionBoardMember.IPasswordResetCompleted>();
  export const simulate = (
    connection: IConnection,
    props: resetPassword.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: resetPassword.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
