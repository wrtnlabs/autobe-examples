import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardMember } from "../../../../../structures/IDiscussionBoardMember";

/**
 * Verify member email address using token from
 * discussion_board_email_verifications table.
 *
 * Verifies a member's email address using the unique verification token sent
 * during registration, enabling full content creation privileges on the
 * discussion board platform. This operation validates the token against
 * discussion_board_email_verifications, confirms it hasn't expired or been
 * used, and updates the member's verification status in
 * discussion_board_members.
 *
 * The verification process retrieves the verification record using the provided
 * token, checking that it matches an entry in
 * discussion_board_email_verifications with a non-null
 * discussion_board_member_id foreign key. The operation validates that the
 * token hasn't expired (current time < expires_at) and hasn't been previously
 * used (verified_at is null). Tokens are valid for 24 hours from creation.
 *
 * Upon successful validation, the operation updates the
 * discussion_board_members table, setting email_verified to true and
 * email_verified_at to the current timestamp for the associated member account.
 * Simultaneously, the verification record in
 * discussion_board_email_verifications is marked as used by setting verified_at
 * to the current timestamp, preventing token reuse.
 *
 * The email verification requirement gates access to article creation and full
 * platform features. Until email_verified is true, members have limited
 * privileges and cannot create content in the discussion_board_articles table.
 * This security measure ensures account ownership and reduces spam or
 * fraudulent registrations.
 *
 * This operation is public and requires no authentication, as it's designed to
 * be accessed via email link by users who have just registered but not yet
 * logged in. If the token has expired, members can request a new verification
 * email through a separate endpoint. This operation is a critical intermediate
 * step between registration (POST /auth/member/join) and full platform access.
 *
 * @param props.connection
 * @param props.body Email verification token sent to member's email address
 * @path /auth/member/email/verify
 * @accessor api.functional.auth.member.email.verify.verifyEmail
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function verifyEmail(
  connection: IConnection,
  props: verifyEmail.Props,
): Promise<verifyEmail.Response> {
  return true === connection.simulate
    ? verifyEmail.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...verifyEmail.METADATA,
          path: verifyEmail.path(),
          status: null,
        },
        props.body,
      );
}
export namespace verifyEmail {
  export type Props = {
    /** Email verification token sent to member's email address */
    body: IDiscussionBoardMember.IVerifyEmail;
  };
  export type Body = IDiscussionBoardMember.IVerifyEmail;
  export type Response = IDiscussionBoardMember;

  export const METADATA = {
    method: "POST",
    path: "/auth/member/email/verify",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/member/email/verify";
  export const random = (): IDiscussionBoardMember =>
    typia.random<IDiscussionBoardMember>();
  export const simulate = (
    connection: IConnection,
    props: verifyEmail.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: verifyEmail.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
