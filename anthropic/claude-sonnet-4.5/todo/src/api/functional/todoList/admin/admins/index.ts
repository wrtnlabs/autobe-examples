/**
 * Log out the current administrator session.
 *
 * This operation terminates the currently authenticated administrator's active
 * session, effectively logging them out from their current device or browser.
 * When an admin invokes this endpoint, the system validates their JWT access
 * token, identifies the associated admin session record in the
 * todo_list_admin_sessions table, and marks it as expired by setting the
 * expired_at timestamp to the current time.
 *
 * The logout process ensures that the admin's current access token becomes
 * invalid for subsequent authenticated requests. After successful logout, the
 * admin must authenticate again with their email and password to obtain new JWT
 * tokens and establish a new session. This operation affects only the current
 * session from which the logout request was made, allowing the admin to remain
 * logged in on other devices if they have multiple active sessions.
 *
 * Security considerations are paramount in this operation. The system validates
 * that the logout request comes from an authenticated admin by verifying the
 * JWT token signature and ensuring the token has not expired. The operation
 * maintains an audit trail by recording the session termination timestamp,
 * which can be used for security monitoring and compliance purposes. Admin
 * logout events should be logged for administrative oversight and security
 * auditing.
 *
 * This endpoint is essential for administrators who want to securely end their
 * session when finished using the system, especially when accessing the admin
 * dashboard from shared or public computers. It provides a clean session
 * termination mechanism that invalidates the current authentication state
 * without affecting other active admin sessions.
 *
 * @param props.connection
 * @path /todoList/admin/admins/logout
 * @accessor api.functional.todoList.admin.admins.logout
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function logout(
  connection: IConnection,
): Promise<logout.Response> {
  return true === connection.simulate
    ? logout.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...logout.METADATA,
          path: logout.path(),
          status: null,
        },
      );
}
export namespace logout {
  export type Response = ITodoListAdminAuth.ILogoutResponse;

  export const METADATA = {
    method: "POST",
    path: "/todoList/admin/admins/logout",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/todoList/admin/admins/logout";
  export const random = (): ITodoListAdminAuth.ILogoutResponse =>
    typia.random<ITodoListAdminAuth.ILogoutResponse>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}
