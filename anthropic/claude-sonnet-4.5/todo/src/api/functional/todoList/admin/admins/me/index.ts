/**
 * Retrieve the currently authenticated administrator's profile information
 * including account details and metadata.
 *
 * This operation allows administrators to view their own account information by
 * extracting the admin identity from the JWT access token. The admin ID is
 * obtained from the token claims rather than requiring a path parameter,
 * ensuring that admins can only access their own profile data through this
 * endpoint.
 *
 * Security: This endpoint requires admin authentication via JWT token. The
 * system validates the token and extracts the admin user ID to retrieve the
 * corresponding profile from the todo_list_admins table. Only the authenticated
 * admin's own data is returned, maintaining proper authorization boundaries
 * even for administrative accounts.
 *
 * The response includes the admin's email address used for authentication,
 * account creation timestamp for lifecycle tracking, and last update timestamp
 * indicating when credentials or account information were most recently
 * modified. Password hashes are never included in responses for security
 * reasons.
 *
 * This endpoint supports the admin actor's ability to 'View own profile' as
 * specified in the authentication requirements permission matrix. It follows
 * the same self-service account management patterns available to regular users
 * but applies to administrative accounts.
 *
 * @param props.connection
 * @path /todoList/admin/admins/me
 * @accessor api.functional.todoList.admin.admins.me.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(connection: IConnection): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(),
          status: null,
        },
      );
}
export namespace at {
  export type Response = ITodoListAdmin.ISummary;

  export const METADATA = {
    method: "GET",
    path: "/todoList/admin/admins/me",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/todoList/admin/admins/me";
  export const random = (): ITodoListAdmin.ISummary =>
    typia.random<ITodoListAdmin.ISummary>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}

/**
 * Update the currently authenticated administrator's account information,
 * primarily for changing account password through secure verification.
 *
 * This operation allows administrators to modify their own account credentials
 * following the secure password change process outlined in the authentication
 * requirements. The admin must provide their current password for identity
 * verification before the new password is accepted, preventing unauthorized
 * password changes even if a session token is compromised.
 *
 * Security: Admin authentication is required via JWT token. The system extracts
 * the admin user ID from the token claims to identify which account to update.
 * The current password must be validated against the stored password hash
 * before any changes are committed. The new password must meet all password
 * strength requirements including minimum 8 characters, uppercase, lowercase,
 * numeric, and special character requirements.
 *
 * When a password change succeeds, the system updates the password_hash field
 * in the todo_list_admins table and sets the updated_at timestamp. All existing
 * admin sessions except the current one are invalidated by revoking refresh
 * tokens, forcing re-authentication on other devices. The admin receives email
 * notification confirming the password change with timestamp and IP address for
 * security awareness.
 *
 * Validation: Current password verification fails with error 'Current password
 * is incorrect'. New password strength validation provides specific feedback
 * about which requirements are not met. The operation follows the same password
 * change flow as regular users but applies to administrative accounts.
 *
 * This endpoint implements the admin's self-service account management
 * capability defined in the Actor-Specific Business Requirements, allowing
 * admins to independently maintain their credential security without requiring
 * assistance from other administrators.
 *
 * @param props.connection
 * @param props.body Account update information including current and new
 *   password for secure verification
 * @path /todoList/admin/admins/me
 * @accessor api.functional.todoList.admin.admins.me.update
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function update(
  connection: IConnection,
  props: update.Props,
): Promise<update.Response> {
  return true === connection.simulate
    ? update.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...update.METADATA,
          path: update.path(),
          status: null,
        },
        props.body,
      );
}
export namespace update {
  export type Props = {
    /**
     * Account update information including current and new password for
     * secure verification
     */
    body: ITodoListAdmin.IUpdate;
  };
  export type Body = ITodoListAdmin.IUpdate;
  export type Response = ITodoListAdmin.ISummary;

  export const METADATA = {
    method: "PUT",
    path: "/todoList/admin/admins/me",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/todoList/admin/admins/me";
  export const random = (): ITodoListAdmin.ISummary =>
    typia.random<ITodoListAdmin.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: update.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: update.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
