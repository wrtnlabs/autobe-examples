import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

/**
 * Terminate a specific admin session by session ID.
 *
 * Terminates an administrator's specific session, effectively logging them out
 * from a particular device or browser while preserving other active sessions.
 * This operation is essential for security management, allowing administrators
 * to revoke access from individual devices without affecting their sessions on
 * other devices.
 *
 * When an admin terminates a session, the system performs a soft delete by
 * setting the expired_at timestamp in the todo_list_admin_sessions table to the
 * current time, marking the session as ended. The session record is preserved
 * for audit purposes and security monitoring, maintaining a complete history of
 * admin authentication activity.
 *
 * This operation requires the administrator to be authenticated and can only
 * terminate sessions belonging to the requesting admin. The sessionId path
 * parameter identifies which specific session to terminate, enabling selective
 * logout functionality. This is particularly useful when an administrator wants
 * to log out from a specific device they no longer have physical access to, or
 * when they suspect a session may have been compromised.
 *
 * The soft delete approach using expired_at ensures that session history
 * remains intact for security audits while immediately invalidating the session
 * for authentication purposes. All subsequent requests using the terminated
 * session's tokens will be rejected, requiring the administrator to
 * re-authenticate on that device.
 *
 * @param props.connection
 * @param props.sessionId Unique identifier of the admin session to terminate
 *   (global scope)
 * @path /todoList/admin/admins/me/sessions/:sessionId
 * @accessor api.functional.todoList.admin.admins.me.sessions.erase
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function erase(
  connection: IConnection,
  props: erase.Props,
): Promise<void> {
  return true === connection.simulate
    ? erase.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...erase.METADATA,
          path: erase.path(props),
          status: null,
        },
      );
}
export namespace erase {
  export type Props = {
    /** Unique identifier of the admin session to terminate (global scope) */
    sessionId: string & tags.Format<"uuid">;
  };

  export const METADATA = {
    method: "DELETE",
    path: "/todoList/admin/admins/me/sessions/:sessionId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/todoList/admin/admins/me/sessions/${encodeURIComponent(props.sessionId ?? "null")}`;
  export const random = (): void => typia.random<void>();
  export const simulate = (
    connection: IConnection,
    props: erase.Props,
  ): void => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: erase.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("sessionId")(() => typia.assert(props.sessionId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
