/**
 * Permanently delete a user from the todo_list_users table.
 *
 * Permanently erase a user account from the Todo List system, deleting their
 * credentials and all associated user data from the todo_list_users table.
 *
 * This operation must be performed only by authorized platform administrators
 * and has far-reaching effects: all active or historical sessions and personal
 * data become inaccessible once the operation completes. Security and
 * compliance considerations require this operation be logged and restricted to
 * privileged actors, as account deletion is both destructive and irreversible.
 * The record is fully removed with no recovery mechanism.
 *
 * This operation references the user by its UUID id field, ensuring exact match
 * in the database. All related child records (such as sessions and audit logs)
 * are handled per system policy on cascading deletes or orphaning. If the
 * specified user does not exist or is already deleted, the operation will
 * return a suitable error. Use with caution and only after confirmation of
 * intent.
 *
 * @param props.connection
 * @param props.userId UUID unique identifier of the user to be deleted (matches
 *   todo_list_users.id).
 * @path /todoList/admin/users/:userId
 * @accessor api.functional.todoList.admin.users.erase
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function erase(
  connection: IConnection,
  props: erase.Props,
): Promise<void> {
  return true === connection.simulate
    ? erase.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...erase.METADATA,
          path: erase.path(props),
          status: null,
        },
      );
}
export namespace erase {
  export type Props = {
    /**
     * UUID unique identifier of the user to be deleted (matches
     * todo_list_users.id).
     */
    userId: string & tags.Format<"uuid">;
  };

  export const METADATA = {
    method: "DELETE",
    path: "/todoList/admin/users/:userId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/todoList/admin/users/${encodeURIComponent(props.userId ?? "null")}`;
  export const random = (): void => typia.random<void>();
  export const simulate = (
    connection: IConnection,
    props: erase.Props,
  ): void => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: erase.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("userId")(() => typia.assert(props.userId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
