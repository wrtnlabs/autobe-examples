import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ITodoListAdmin } from "../../../../../../structures/ITodoListAdmin";

/**
 * Update the password for the currently authenticated administrator account.
 * This operation allows admins to change their own password as a self-service
 * security management feature.
 *
 * The operation requires verification of the current password before allowing
 * the password change to ensure that only the legitimate account owner can
 * modify credentials. The new password must meet the same strong password
 * requirements enforced during account creation, using industry-standard
 * hashing algorithms (bcrypt or argon2) to securely store the updated
 * password_hash.
 *
 * Successful password updates invalidate all existing admin sessions except the
 * current one, requiring re-authentication on all other devices. This security
 * measure prevents unauthorized access if the password was changed due to
 * suspected compromise. The updated_at timestamp in the todo_list_admins table
 * is automatically updated to reflect this credential change.
 *
 * This operation is restricted to authenticated administrators only and
 * operates on their own account (identified by the JWT token). Admins cannot
 * use this endpoint to change other administrators' passwords.
 *
 * @param props.connection
 * @param props.body Current and new password information for password update
 *   verification and execution
 * @path /todoList/admin/admins/me/password
 * @accessor api.functional.todoList.admin.admins.me.password.update
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function update(
  connection: IConnection,
  props: update.Props,
): Promise<update.Response> {
  return true === connection.simulate
    ? update.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...update.METADATA,
          path: update.path(),
          status: null,
        },
        props.body,
      );
}
export namespace update {
  export type Props = {
    /**
     * Current and new password information for password update verification
     * and execution
     */
    body: ITodoListAdmin.IUpdatePassword;
  };
  export type Body = ITodoListAdmin.IUpdatePassword;
  export type Response = ITodoListAdmin;

  export const METADATA = {
    method: "PUT",
    path: "/todoList/admin/admins/me/password",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/todoList/admin/admins/me/password";
  export const random = (): ITodoListAdmin => typia.random<ITodoListAdmin>();
  export const simulate = (
    connection: IConnection,
    props: update.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: update.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
