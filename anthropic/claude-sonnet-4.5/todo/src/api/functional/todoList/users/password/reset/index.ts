/**
 * Request password reset for user account via email.
 *
 * Initiates the password reset process for users who have forgotten their
 * passwords or need to reset them for security reasons. This operation
 * generates a unique, cryptographically secure reset token with a limited
 * expiration time (typically 1 hour) and sends it via email to the user's
 * registered email address.
 *
 * The operation implements security best practices by not revealing whether the
 * provided email address exists in the system. This prevents attackers from
 * using the password reset functionality to enumerate valid user accounts. The
 * system responds with a generic success message regardless of whether the
 * email exists, instructing the user to check their email for reset
 * instructions.
 *
 * When a valid email is found, the system generates a reset token that is
 * single-use, cryptographically random (at least 32 characters), and includes
 * an expiration timestamp. The reset link containing this token is sent to the
 * user's email. Any previously generated reset tokens for the same user are
 * invalidated to prevent token accumulation. The operation does not require
 * authentication since users who have forgotten their passwords cannot log in.
 *
 * This operation relates to the todo_list_users table in the Prisma schema,
 * specifically the email and password_hash fields. It does not modify the
 * password_hash directly but creates the necessary token for the subsequent
 * password reset verification step.
 *
 * @param props.connection
 * @param props.body Email address for the account requiring password reset
 * @path /todoList/users/password/reset
 * @accessor api.functional.todoList.users.password.reset.requestReset
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function requestReset(
  connection: IConnection,
  props: requestReset.Props,
): Promise<requestReset.Response> {
  return true === connection.simulate
    ? requestReset.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...requestReset.METADATA,
          path: requestReset.path(),
          status: null,
        },
        props.body,
      );
}
export namespace requestReset {
  export type Props = {
    /** Email address for the account requiring password reset */
    body: ITodoListUser.IPasswordResetRequest;
  };
  export type Body = ITodoListUser.IPasswordResetRequest;
  export type Response = ITodoListUser.IPasswordResetResponse;

  export const METADATA = {
    method: "POST",
    path: "/todoList/users/password/reset",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/todoList/users/password/reset";
  export const random = (): ITodoListUser.IPasswordResetResponse =>
    typia.random<ITodoListUser.IPasswordResetResponse>();
  export const simulate = (
    connection: IConnection,
    props: requestReset.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: requestReset.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
