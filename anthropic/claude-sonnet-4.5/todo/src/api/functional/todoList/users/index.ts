import { ITodoListUser } from "../../../structures/ITodoListUser";

/**
 * Retrieve a user account from the todo_list_users table by its unique
 * identifier.
 *
 * Fetch a registered user's account details by their unique identifier. The
 * response includes account-level information such as the user's email, account
 * creation and update timestamps, and disabled status, as defined in the Prisma
 * schema.
 *
 * Sensitive fields such as the password hash are never returned, in compliance
 * with best security practices. Only system administrators or the user
 * themselves (authorization not shown here) will be able to access this
 * endpoint to ensure privacy and data protection.
 *
 * Proper error handling ensures requests for non-existent users or
 * missing/invalid identifiers return a clear error response. This operation is
 * essential for user profile management use cases.
 *
 * @param props.connection
 * @param props.userId Unique identifier of the target user account (UUID
 *   format).
 * @path /todoList/users/:userId
 * @accessor api.functional.todoList.users.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique identifier of the target user account (UUID format). */
    userId: string & tags.Format<"uuid">;
  };
  export type Response = ITodoListUser;

  export const METADATA = {
    method: "GET",
    path: "/todoList/users/:userId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/todoList/users/${encodeURIComponent(props.userId ?? "null")}`;
  export const random = (): ITodoListUser => typia.random<ITodoListUser>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("userId")(() => typia.assert(props.userId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

