/**
 * Log out the authenticated user from their current session.
 *
 * This operation terminates the authenticated user's current session by
 * invalidating their refresh token and marking the session as expired in the
 * todo_list_user_sessions table. When a user logs out, the system sets the
 * expired_at timestamp to the current time for the active session, preventing
 * further use of the associated refresh token.
 *
 * The logout process ensures that the user's authentication state is properly
 * terminated, requiring them to log in again to access protected resources. The
 * access token will remain technically valid until its expiration (due to
 * stateless JWT design), but the client application should immediately discard
 * both access and refresh tokens upon receiving logout confirmation.
 *
 * This operation provides security benefits by allowing users to explicitly end
 * their sessions, particularly important when using shared or public computers.
 * The system records the logout event by updating the session record in the
 * todo_list_user_sessions table with the expired_at timestamp, maintaining an
 * audit trail of session lifecycle events.
 *
 * The operation only affects the current session associated with the user's
 * current device or browser. Other active sessions on different devices remain
 * valid unless the user chooses to log out from all devices using the separate
 * global logout operation.
 *
 * @param props.connection
 * @path /todoList/user/users/logout
 * @accessor api.functional.todoList.user.users.logout
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function logout(connection: IConnection): Promise<void> {
  return true === connection.simulate
    ? logout.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...logout.METADATA,
          path: logout.path(),
          status: null,
        },
      );
}
export namespace logout {
  export const METADATA = {
    method: "POST",
    path: "/todoList/user/users/logout",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/todoList/user/users/logout";
  export const random = (): void => typia.random<void>();
  export const simulate = (_connection: IConnection): void => {
    return random();
  };
}
