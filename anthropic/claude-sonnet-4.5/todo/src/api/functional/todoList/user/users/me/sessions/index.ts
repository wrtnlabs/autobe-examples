import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

/**
 * Delete a specific user session to log out from a particular device.
 *
 * This endpoint enables authenticated users to delete a specific session,
 * effectively logging out from a particular device or browser where they are
 * currently logged in. This is a critical security feature that allows users to
 * manage their active sessions and revoke access from devices they no longer
 * trust or use.
 *
 * The operation performs a soft delete on the todo_list_user_sessions table by
 * setting the deleted_at timestamp, as this field exists in the Prisma schema.
 * This preserves the session record for audit purposes while marking it as
 * inactive. The session will no longer be valid for authentication after
 * deletion.
 *
 * Security considerations are paramount: the system must verify that the
 * session being deleted belongs to the authenticated user making the request.
 * Users cannot delete sessions belonging to other users. The session ID is
 * provided as a path parameter, and the system validates ownership before
 * proceeding with deletion.
 *
 * This operation is commonly used when users want to log out from a specific
 * device remotely, such as when they've logged in from a public computer and
 * want to ensure that session is terminated, or when they notice suspicious
 * activity and want to revoke access from potentially compromised devices. It
 * complements the global logout functionality by providing granular control
 * over individual sessions.
 *
 * Upon successful deletion, the session becomes invalid immediately, and any
 * subsequent requests using that session's authentication token will be
 * rejected. The user remains logged in on other devices where they have active
 * sessions.
 *
 * @param props.connection
 * @param props.sessionId Unique identifier of the session to delete (global
 *   scope)
 * @path /todoList/user/users/me/sessions/:sessionId
 * @accessor api.functional.todoList.user.users.me.sessions.erase
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function erase(
  connection: IConnection,
  props: erase.Props,
): Promise<void> {
  return true === connection.simulate
    ? erase.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...erase.METADATA,
          path: erase.path(props),
          status: null,
        },
      );
}
export namespace erase {
  export type Props = {
    /** Unique identifier of the session to delete (global scope) */
    sessionId: string & tags.Format<"uuid">;
  };

  export const METADATA = {
    method: "DELETE",
    path: "/todoList/user/users/me/sessions/:sessionId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/todoList/user/users/me/sessions/${encodeURIComponent(props.sessionId ?? "null")}`;
  export const random = (): void => typia.random<void>();
  export const simulate = (
    connection: IConnection,
    props: erase.Props,
  ): void => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: erase.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("sessionId")(() => typia.assert(props.sessionId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
