import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ITodoListAdmin } from "../../../structures/ITodoListAdmin";

/**
 * Authenticate an administrator and create a new admin session.
 *
 * This endpoint handles administrator authentication, allowing admins to log
 * into the system with their credentials and gain access to administrative
 * functions. This is a critical security operation that validates admin
 * identity and establishes an authenticated session with elevated privileges.
 *
 * The authentication process follows industry-standard security practices: the
 * admin provides their email address and password through the request body. The
 * system validates the email exists in the todo_list_admins table, then
 * verifies the provided password against the stored password_hash using secure
 * comparison methods (constant-time comparison to prevent timing attacks). The
 * password is never transmitted or stored in plain text, and the system uses
 * industry-standard hashing algorithms like bcrypt, argon2, or PBKDF2.
 *
 * Upon successful authentication, the system performs several operations:
 * generates JWT access and refresh tokens containing the admin's ID and role,
 * creates a new session record in the todo_list_admin_sessions table with
 * metadata including IP address, connection URL, and referrer for audit
 * purposes, and returns the tokens along with admin profile information to the
 * client. The access token typically expires after 15-30 minutes, while the
 * refresh token has a longer lifespan of 7-30 days.
 *
 * Security measures include protection against brute force attacks through rate
 * limiting and temporary delays after multiple failed attempts, generic error
 * messages that don't reveal whether the email or password was incorrect to
 * prevent account enumeration, and comprehensive logging of all authentication
 * attempts for security monitoring and audit trails.
 *
 * If authentication fails due to invalid credentials, non-existent email, or
 * disabled admin account, the system returns an appropriate error without
 * exposing sensitive information about which credential was incorrect. This
 * endpoint is publicly accessible (no authentication required to attempt login)
 * but implements strict security controls to protect against unauthorized
 * access.
 *
 * @param props.connection
 * @param props.body Admin login credentials including email and password
 * @path /todoList/admins/login
 * @accessor api.functional.todoList.admins.login
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function login(
  connection: IConnection,
  props: login.Props,
): Promise<login.Response> {
  return true === connection.simulate
    ? login.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...login.METADATA,
          path: login.path(),
          status: null,
        },
        props.body,
      );
}
export namespace login {
  export type Props = {
    /** Admin login credentials including email and password */
    body: ITodoListAdmin.ILogin;
  };
  export type Body = ITodoListAdmin.ILogin;
  export type Response = ITodoListAdmin.ILoginResponse;

  export const METADATA = {
    method: "POST",
    path: "/todoList/admins/login",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/todoList/admins/login";
  export const random = (): ITodoListAdmin.ILoginResponse =>
    typia.random<ITodoListAdmin.ILoginResponse>();
  export const simulate = (
    connection: IConnection,
    props: login.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: login.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
