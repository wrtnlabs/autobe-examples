/**
 * Register a new guest user account in the todo_list_users table.
 *
 * Registers a new guest user account in the Todo list application by creating a
 * record in the todo_list_users table. This operation allows unauthenticated
 * visitors to create temporary guest accounts that provide limited access to
 * the system.
 *
 * The registration process accepts the user's email address, which must be
 * unique across all users and serves as the login identifier. The password is
 * cryptographically hashed using bcrypt with a cost factor of at least 12
 * before being stored in the password_hash field. An optional display name can
 * be provided for personalization purposes.
 *
 * Upon successful registration, the system immediately issues JWT access and
 * refresh tokens, allowing the guest to access public features without
 * requiring a separate login step. The created_at and updated_at timestamps are
 * automatically set to the current time, and the deleted_at field remains null
 * for active accounts.
 *
 * This endpoint is publicly accessible and requires no authentication. Email
 * uniqueness is enforced by the unique index on the email field in the
 * todo_list_users table. Password strength validation ensures secure
 * credentials are used.
 *
 * Related operations: After registration, guests can use the refresh endpoint
 * (/auth/guest/refresh) to renew their access tokens when they expire.
 *
 * @param props.connection
 * @param props.body Guest user registration information including email,
 *   password, and optional name
 * @setHeader token.access Authorization
 *
 * @path /auth/guest/join
 * @accessor api.functional.auth.guest.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
