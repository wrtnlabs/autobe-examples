/**
 * Register a new guest account and issue temporary JWT tokens for
 * unauthenticated access.
 *
 * Creates a new guest account and issues JWT tokens for temporary access to the
 * Todo list application.
 *
 * This endpoint allows unauthenticated visitors to register as guest users
 * without requiring full authentication credentials. Upon successful
 * registration, the system generates a guest account entry in the
 * todo_list_guests table and returns a JWT access token and refresh token
 * pair.
 *
 * Guest accounts are designed for temporary, limited access to the service.
 * They cannot create or manage todo items but can view public information and
 * explore the service interface. This provides a low-friction entry point for
 * users who want to experience the service before committing to full
 * registration.
 *
 * The response includes both access and refresh tokens in the
 * ITodoListGuest.IAuthorized format, enabling the guest to maintain their
 * session and refresh tokens as needed. The guest account remains active until
 * explicitly converted to a full user account or until it expires based on
 * system policies.
 *
 * This operation is publicly accessible and does not require any prior
 * authentication. It serves as the primary entry point for guest users to begin
 * interacting with the Todo list application.
 *
 * @param props.connection
 * @param props.body Guest registration information for creating a temporary
 *   account
 * @setHeader token.access Authorization
 *
 * @path /auth/guest/join
 * @accessor api.functional.auth.guest.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
export namespace join {
  export type Props = {
    /** Guest registration information for creating a temporary account */
    body: ITodoListGuest.ICreate;
  };
  export type Body = ITodoListGuest.ICreate;
  export type Response = ITodoListGuest.IAuthorized;

  export const METADATA = {
    method: "POST",
    path: "/auth/guest/join",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/guest/join";
  export const random = (): ITodoListGuest.IAuthorized =>
    typia.random<ITodoListGuest.IAuthorized>();
  export const simulate = (
    connection: IConnection,
    props: join.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: join.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

