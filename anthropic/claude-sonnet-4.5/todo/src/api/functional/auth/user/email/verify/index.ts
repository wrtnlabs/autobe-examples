import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ITodoListEmailVerification } from "../../../../../structures/ITodoListEmailVerification";

/**
 * Verify user email address using verification token from
 * todo_list_email_verifications table.
 *
 * Verifies user email addresses using verification tokens sent during
 * registration.
 *
 * This endpoint completes the email verification workflow, which is an
 * essential part of secure user account activation. When a user registers, a
 * verification token is generated and stored in the
 * todo_list_email_verifications table. This token is typically sent to the
 * user's email address as part of a verification link.
 *
 * When the user clicks the verification link or submits the token through this
 * endpoint, the system validates the token against records in the
 * todo_list_email_verifications table. The validation process checks token
 * authenticity, expiration status, and ensures the token hasn't been used
 * previously. Upon successful validation, the corresponding user record in the
 * todo_list_users table is updated to mark the email as verified.
 *
 * The Prisma schema defines the todo_list_email_verifications table with fields
 * for tracking verification tokens, their expiration, and usage status. This
 * operation leverages these fields to ensure secure and reliable email
 * verification.
 *
 * Security considerations include token expiration enforcement (tokens should
 * be time-limited), one-time use validation (tokens cannot be reused), and
 * protection against brute-force token guessing. Failed verification attempts
 * should be logged for security monitoring.
 *
 * This is a public endpoint that does not require authentication, as users need
 * to verify their email before they can fully access their accounts. However,
 * the operation does create an association with a specific user account based
 * on the verification token.
 *
 * @param props.connection
 * @param props.body Email verification token received via email
 * @path /auth/user/email/verify
 * @accessor api.functional.auth.user.email.verify.verifyEmail
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function verifyEmail(
  connection: IConnection,
  props: verifyEmail.Props,
): Promise<verifyEmail.Response> {
  return true === connection.simulate
    ? verifyEmail.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...verifyEmail.METADATA,
          path: verifyEmail.path(),
          status: null,
        },
        props.body,
      );
}
export namespace verifyEmail {
  export type Props = {
    /** Email verification token received via email */
    body: ITodoListEmailVerification.IVerify;
  };
  export type Body = ITodoListEmailVerification.IVerify;
  export type Response = ITodoListEmailVerification.IResult;

  export const METADATA = {
    method: "POST",
    path: "/auth/user/email/verify",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/user/email/verify";
  export const random = (): ITodoListEmailVerification.IResult =>
    typia.random<ITodoListEmailVerification.IResult>();
  export const simulate = (
    connection: IConnection,
    props: verifyEmail.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: verifyEmail.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
