import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ITodoListUser } from "../../../../../../structures/ITodoListUser";

/**
 * Complete password reset using validated token and set new password.
 *
 * Validates the password reset token and updates the user's password in
 * todo_list_users, completing the secure account recovery workflow.
 *
 * This endpoint handles the second step of the password reset flow after users
 * click the reset link from their email. The system validates the provided
 * token exists in todo_list_password_reset_tokens, hasn't expired (current time
 * < expires_at), hasn't been used (used_at is null), and matches the provided
 * email address for additional security verification.
 *
 * Upon successful token validation, the system updates the password_hash field
 * in todo_list_users with the new password securely hashed using bcrypt with
 * cost factor of at least 12. The updated_at timestamp is automatically updated
 * to reflect the password change. The token's used_at field is set to the
 * current timestamp, permanently preventing token reuse and enforcing the
 * single-use security requirement.
 *
 * As a security measure, successful password reset triggers invalidation of all
 * active sessions for the user by setting expired_at on all records in
 * todo_list_user_sessions. This implements a "logout from all devices"
 * behavior, ensuring that if an unauthorized party gained access, they are
 * immediately logged out when the legitimate user resets their password.
 *
 * Password reset failures occur when the token is not found, has expired based
 * on the expires_at timestamp, has already been used (used_at is not null), or
 * when the email doesn't match the token's stored email. The system enforces
 * strict token expiration through the 1-hour limit set during token creation,
 * and tokens are permanently deleted after successful use or expiration.
 *
 * This completes the self-service password recovery mechanism, allowing users
 * to regain access to their accounts securely while maintaining strict security
 * controls through time-limited, single-use tokens and automatic session
 * invalidation.
 *
 * @param props.connection
 * @param props.body Password reset token, email, and new password
 * @path /auth/user/password/reset/complete
 * @accessor api.functional.auth.user.password.reset.complete.completePasswordReset
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function completePasswordReset(
  connection: IConnection,
  props: completePasswordReset.Props,
): Promise<completePasswordReset.Response> {
  return true === connection.simulate
    ? completePasswordReset.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...completePasswordReset.METADATA,
          path: completePasswordReset.path(),
          status: null,
        },
        props.body,
      );
}
export namespace completePasswordReset {
  export type Props = {
    /** Password reset token, email, and new password */
    body: ITodoListUser.IPasswordResetComplete;
  };
  export type Body = ITodoListUser.IPasswordResetComplete;
  export type Response = ITodoListUser.IPasswordResetCompleteResponse;

  export const METADATA = {
    method: "POST",
    path: "/auth/user/password/reset/complete",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/user/password/reset/complete";
  export const random = (): ITodoListUser.IPasswordResetCompleteResponse =>
    typia.random<ITodoListUser.IPasswordResetCompleteResponse>();
  export const simulate = (
    connection: IConnection,
    props: completePasswordReset.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: completePasswordReset.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
