import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ITodoListUser } from "../../../../../structures/ITodoListUser";

/**
 * Initiates a user password reset flow by creating a reset token record.
 *
 * This endpoint accepts a password reset initiation request for a user
 * identified by their email address. The API validates existence of the user
 * (in 'todo_list_users'), then creates a one-time-use password reset record in
 * 'todo_list_password_reset_tokens', with a securely-generated token, creation
 * and expiration timestamps. Actual password changes are handled in a separate
 * endpoint after token validation.
 *
 * Security and compliance policies dictate that responses to this endpoint
 * NEVER disclose whether the submitted email exists—a generic success/failure
 * message is returned regardless. Timing and error details are masked to resist
 * brute force enumeration.
 *
 * Password reset tokens expire based on the 'expires_at' field and may only be
 * used once (see 'used_at'). Issued tokens are suitable for secure delivery
 * out-of-band (such as via email notification). All operations are audited per
 * privacy and incident response policy.
 *
 * This endpoint does not itself alter user credentials. A follow-up operation
 * (not defined here) will use the issued reset token to update the password,
 * after separate verification and security checks.
 *
 * @param props.connection
 * @param props.body Email address requesting password reset initiation.
 * @path /auth/user/password/request-reset
 * @accessor api.functional.auth.user.password.request_reset.requestPasswordReset
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function requestPasswordReset(
  connection: IConnection,
  props: requestPasswordReset.Props,
): Promise<requestPasswordReset.Response> {
  return true === connection.simulate
    ? requestPasswordReset.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...requestPasswordReset.METADATA,
          path: requestPasswordReset.path(),
          status: null,
        },
        props.body,
      );
}
export namespace requestPasswordReset {
  export type Props = {
    /** Email address requesting password reset initiation. */
    body: ITodoListUser.IRequestPasswordReset;
  };
  export type Body = ITodoListUser.IRequestPasswordReset;
  export type Response = ITodoListUser.IPasswordResetInitiated;

  export const METADATA = {
    method: "POST",
    path: "/auth/user/password/request-reset",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/user/password/request-reset";
  export const random = (): ITodoListUser.IPasswordResetInitiated =>
    typia.random<ITodoListUser.IPasswordResetInitiated>();
  export const simulate = (
    connection: IConnection,
    props: requestPasswordReset.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: requestPasswordReset.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
