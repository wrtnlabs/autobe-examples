import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ITodoListPasswordReset } from "../../../../../../structures/ITodoListPasswordReset";

/**
 * Reset user password using reset token from todo_list_password_resets table
 * for todo_list_users.
 *
 * Completes the password reset process by validating the reset token and
 * updating the user's password.
 *
 * This endpoint handles the second phase of the password recovery workflow.
 * After a user has requested a password reset and received a reset token via
 * email, they use this endpoint to set a new password. The system validates the
 * provided reset token against records in the todo_list_password_resets table
 * and, upon successful validation, updates the password in the corresponding
 * todo_list_users record.
 *
 * The validation process checks multiple security criteria: token authenticity
 * (the token must exist in the database), expiration status (the token must not
 * have exceeded its validity period), and usage status (the token must not have
 * been previously used). The Prisma schema for todo_list_password_resets
 * includes fields to track these validation requirements.
 *
 * Upon successful token validation, the operation updates the password field in
 * the todo_list_users table with the new hashed password. The reset token is
 * then marked as used in the todo_list_password_resets table to prevent reuse.
 * For additional security, all existing user sessions in the
 * todo_list_user_sessions table should be invalidated to ensure the user must
 * log in again with the new password.
 *
 * Security considerations include password strength validation (enforcing
 * minimum requirements for the new password), secure password hashing using
 * industry-standard algorithms, one-time token usage (preventing token replay
 * attacks), and session invalidation to protect against unauthorized access
 * with old credentials.
 *
 * This is a public endpoint that does not require authentication, as it serves
 * users who cannot currently authenticate. However, possession of the valid
 * reset token serves as proof of email ownership and authorization to change
 * the password.
 *
 * @param props.connection
 * @param props.body Password reset token and new password credentials
 * @path /auth/user/password/reset/confirm
 * @accessor api.functional.auth.user.password.reset.confirm.confirmPasswordReset
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function confirmPasswordReset(
  connection: IConnection,
  props: confirmPasswordReset.Props,
): Promise<confirmPasswordReset.Response> {
  return true === connection.simulate
    ? confirmPasswordReset.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...confirmPasswordReset.METADATA,
          path: confirmPasswordReset.path(),
          status: null,
        },
        props.body,
      );
}
export namespace confirmPasswordReset {
  export type Props = {
    /** Password reset token and new password credentials */
    body: ITodoListPasswordReset.IConfirm;
  };
  export type Body = ITodoListPasswordReset.IConfirm;
  export type Response = ITodoListPasswordReset.IConfirmResult;

  export const METADATA = {
    method: "POST",
    path: "/auth/user/password/reset/confirm",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/user/password/reset/confirm";
  export const random = (): ITodoListPasswordReset.IConfirmResult =>
    typia.random<ITodoListPasswordReset.IConfirmResult>();
  export const simulate = (
    connection: IConnection,
    props: confirmPasswordReset.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: confirmPasswordReset.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
