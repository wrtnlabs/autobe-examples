import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ITodoListUser } from "../../../../../structures/ITodoListUser";

/**
 * Change password for authenticated user with current password verification.
 *
 * Allows authenticated users to change their password in todo_list_users after
 * verifying their current password, implementing secure password update with
 * session management.
 *
 * This endpoint handles password changes for users who have access to their
 * accounts and want to update their credentials proactively. Unlike password
 * reset which is for account recovery, password change requires the user to be
 * authenticated and provide their current password for verification. This
 * prevents unauthorized password changes if someone gains temporary access to
 * an authenticated session.
 *
 * The system validates the current password against the stored password_hash in
 * todo_list_users using bcrypt verification before allowing the change. Upon
 * successful verification, the password_hash field is updated with the new
 * password securely hashed using bcrypt with cost factor of at least 12. The
 * updated_at timestamp is automatically set to reflect the password
 * modification.
 *
 * As a security best practice, successful password change triggers invalidation
 * of all other active sessions for the user by setting expired_at on all
 * records in todo_list_user_sessions except the current session. This
 * implements a "logout from all other devices" behavior, ensuring that if an
 * unauthorized party gained access on another device, they are immediately
 * logged out when the user changes their password.
 *
 * This operation maintains the current session's validity, allowing the user to
 * continue working after the password change without requiring
 * re-authentication. The user receives confirmation of the successful password
 * update and should be advised that all other devices were logged out for
 * security.
 *
 * Password change failures occur when the current password verification fails,
 * when the new password doesn't meet security requirements, or when the user
 * account has been soft-deleted. This endpoint requires authentication through
 * JWT token validation and can only be accessed by the account owner.
 *
 * @param props.connection
 * @param props.body Current password verification and new password
 * @path /auth/user/password/change
 * @accessor api.functional.auth.user.password.change.changePassword
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function changePassword(
  connection: IConnection,
  props: changePassword.Props,
): Promise<changePassword.Response> {
  return true === connection.simulate
    ? changePassword.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...changePassword.METADATA,
          path: changePassword.path(),
          status: null,
        },
        props.body,
      );
}
export namespace changePassword {
  export type Props = {
    /** Current password verification and new password */
    body: ITodoListUser.IPasswordChange;
  };
  export type Body = ITodoListUser.IPasswordChange;
  export type Response = ITodoListUser.IPasswordChangeResponse;

  export const METADATA = {
    method: "POST",
    path: "/auth/user/password/change",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/user/password/change";
  export const random = (): ITodoListUser.IPasswordChangeResponse =>
    typia.random<ITodoListUser.IPasswordChangeResponse>();
  export const simulate = (
    connection: IConnection,
    props: changePassword.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: changePassword.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
