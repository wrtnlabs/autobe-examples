import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ITodoListUser } from "../../../../../structures/ITodoListUser";

/**
 * Change password for authenticated user in todo_list_users table.
 *
 * Allows authenticated users to change their password by validating the current
 * password and setting a new one.
 *
 * This endpoint handles the password change workflow for users who are
 * currently authenticated and know their existing password. Unlike password
 * reset (which uses email-based token verification), this operation requires
 * the user to be logged in and to provide their current password as proof of
 * identity.
 *
 * The password change process validates that the provided current password
 * matches the stored hashed password in the todo_list_users table. This
 * additional verification step ensures that even if someone gains unauthorized
 * access to an authenticated session, they cannot change the password without
 * knowing the current password.
 *
 * Upon successful validation of the current password, the operation updates the
 * password field in the todo_list_users table with the new hashed password. For
 * enhanced security, the system should optionally invalidate all other active
 * sessions in the todo_list_user_sessions table, forcing the user to
 * re-authenticate on all devices with the new password.
 *
 * Security considerations include current password verification (preventing
 * unauthorized password changes), password strength validation for the new
 * password (enforcing security requirements), secure password hashing using
 * industry-standard algorithms, and optional session invalidation to prevent
 * unauthorized access from previously authenticated sessions.
 *
 * This endpoint requires authentication with the user actor, ensuring that only
 * the account owner can initiate a password change. The operation provides a
 * secure mechanism for users to proactively update their credentials as part of
 * good security hygiene.
 *
 * @param props.connection
 * @param props.body Current password for verification and new password for
 *   update
 * @path /auth/user/password/change
 * @accessor api.functional.auth.user.password.change.changePassword
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function changePassword(
  connection: IConnection,
  props: changePassword.Props,
): Promise<changePassword.Response> {
  return true === connection.simulate
    ? changePassword.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...changePassword.METADATA,
          path: changePassword.path(),
          status: null,
        },
        props.body,
      );
}
export namespace changePassword {
  export type Props = {
    /** Current password for verification and new password for update */
    body: ITodoListUser.IChangePassword;
  };
  export type Body = ITodoListUser.IChangePassword;
  export type Response = ITodoListUser.IChangePasswordResult;

  export const METADATA = {
    method: "POST",
    path: "/auth/user/password/change",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/user/password/change";
  export const random = (): ITodoListUser.IChangePasswordResult =>
    typia.random<ITodoListUser.IChangePasswordResult>();
  export const simulate = (
    connection: IConnection,
    props: changePassword.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: changePassword.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
