import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ITodoListUser } from "../../../../../../structures/ITodoListUser";

/**
 * Request password reset by generating and emailing a secure token.
 *
 * Initiates the password reset workflow by creating a cryptographically secure,
 * time-limited token in todo_list_password_reset_tokens and sending a password
 * reset link via email.
 *
 * This endpoint handles the first step of the "Forgot Password" self-service
 * recovery mechanism. When users provide their email address, the system
 * validates the email exists in todo_list_users and the account is not
 * soft-deleted (deleted_at is null). A cryptographically secure random token is
 * generated, stored in the todo_list_password_reset_tokens table with a 1-hour
 * expiration (expires_at set to created_at + 1 hour), and sent to the user's
 * email address.
 *
 * The generated token must be unique across all active tokens to prevent
 * collisions, enforced by the unique index on the token field. The system
 * stores both the token and the email address for validation, providing an
 * additional security layer during the password reset completion. Multiple
 * tokens can exist for the same user if they request password reset multiple
 * times before using a token.
 *
 * The password reset email contains a secure link with the token embedded,
 * directing users to the password reset completion page. This public endpoint
 * does not require authentication since users have lost access to their
 * accounts. For security, the endpoint should not reveal whether an email
 * exists in the system to prevent email enumeration attacks.
 *
 * The token creation follows strict security controls: tokens expire after 1
 * hour (enforced through expires_at validation), are single-use only (tracked
 * through used_at field), and are permanently deleted after successful password
 * reset or expiration. This implements industry-standard password recovery
 * while maintaining strict security requirements.
 *
 * @param props.connection
 * @param props.body Email address for password reset request
 * @path /auth/user/password/reset/request
 * @accessor api.functional.auth.user.password.reset.request.requestPasswordReset
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function requestPasswordReset(
  connection: IConnection,
  props: requestPasswordReset.Props,
): Promise<requestPasswordReset.Response> {
  return true === connection.simulate
    ? requestPasswordReset.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...requestPasswordReset.METADATA,
          path: requestPasswordReset.path(),
          status: null,
        },
        props.body,
      );
}
export namespace requestPasswordReset {
  export type Props = {
    /** Email address for password reset request */
    body: ITodoListUser.IPasswordResetRequest;
  };
  export type Body = ITodoListUser.IPasswordResetRequest;
  export type Response = ITodoListUser.IPasswordResetRequestResponse;

  export const METADATA = {
    method: "POST",
    path: "/auth/user/password/reset/request",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/user/password/reset/request";
  export const random = (): ITodoListUser.IPasswordResetRequestResponse =>
    typia.random<ITodoListUser.IPasswordResetRequestResponse>();
  export const simulate = (
    connection: IConnection,
    props: requestPasswordReset.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: requestPasswordReset.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
