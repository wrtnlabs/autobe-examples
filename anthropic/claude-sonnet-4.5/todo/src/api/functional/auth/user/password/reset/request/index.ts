/**
 * Request password reset token for todo_list_users table via
 * todo_list_password_resets.
 *
 * Initiates the password reset process by generating and sending a password
 * reset token to the user's email.
 *
 * This endpoint handles the first phase of the password recovery workflow. When
 * a user forgets their password and requests a reset, the system validates that
 * the provided email exists in the todo_list_users table, generates a secure
 * password reset token, and stores it in the todo_list_password_resets table.
 *
 * The Prisma schema defines the todo_list_password_resets table with fields for
 * tracking reset tokens, their expiration timestamps, and usage status. This
 * operation creates a new record in this table with a cryptographically secure
 * token and an expiration time to ensure tokens are time-limited.
 *
 * The password reset token is typically sent to the user's email address as
 * part of a secure reset link. The token allows the user to prove ownership of
 * the email account associated with their user account, providing a secure
 * mechanism for password recovery without requiring the old password.
 *
 * Security considerations include rate limiting to prevent abuse (limiting
 * reset requests per email), token expiration enforcement (tokens should expire
 * after a short period, typically 15-60 minutes), and protection against email
 * enumeration attacks (the response should not indicate whether the email
 * exists in the system).
 *
 * This is a public endpoint that does not require authentication, as users who
 * have forgotten their password cannot authenticate. The operation is designed
 * to be safe even if called with non-existent email addresses, returning a
 * generic success message to prevent information disclosure.
 *
 * @param props.connection
 * @param props.body Email address for which to generate password reset token
 * @path /auth/user/password/reset/request
 * @accessor api.functional.auth.user.password.reset.request.requestPasswordReset
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function requestPasswordReset(
  connection: IConnection,
  props: requestPasswordReset.Props,
): Promise<requestPasswordReset.Response> {
  return true === connection.simulate
    ? requestPasswordReset.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...requestPasswordReset.METADATA,
          path: requestPasswordReset.path(),
          status: null,
        },
        props.body,
      );
}
export namespace requestPasswordReset {
  export type Props = {
    /** Email address for which to generate password reset token */
    body: ITodoListPasswordReset.IRequest;
  };
  export type Body = ITodoListPasswordReset.IRequest;
  export type Response = ITodoListPasswordReset.IRequestResult;

  export const METADATA = {
    method: "POST",
    path: "/auth/user/password/reset/request",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/user/password/reset/request";
  export const random = (): ITodoListPasswordReset.IRequestResult =>
    typia.random<ITodoListPasswordReset.IRequestResult>();
  export const simulate = (
    connection: IConnection,
    props: requestPasswordReset.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: requestPasswordReset.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
