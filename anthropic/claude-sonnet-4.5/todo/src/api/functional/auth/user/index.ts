/**
 * Register a new user account with email and password for the todo_list_users
 * table.
 *
 * Creates a new user account in the Todo list application by registering with
 * email and password credentials.
 *
 * This operation handles the complete user registration workflow, including
 * validating the uniqueness of the email address against the todo_list_users
 * table, securely hashing the provided password using industry-standard
 * algorithms (bcrypt or argon2), and storing the new user record with
 * automatically generated timestamps for created_at and updated_at fields.
 *
 * Upon successful registration, the system immediately establishes an
 * authenticated session by generating JWT tokens (both access token and refresh
 * token) and returns them in the response. This allows the newly registered
 * user to begin using the application immediately without requiring a separate
 * login step.
 *
 * The email address must be unique across all user accounts in the system.
 * Email addresses are normalized to lowercase for consistency and
 * case-insensitive comparison, as defined in the todo_list_users schema. If the
 * provided email already exists, the operation will fail with an appropriate
 * error indicating the email is already registered.
 *
 * This is a public endpoint accessible without authentication, as it represents
 * the entry point for new users to join the application. The operation enforces
 * strict validation rules on the input data to ensure account security and data
 * integrity from the moment of account creation.
 *
 * @param props.connection
 * @param props.body User registration credentials including email and password
 * @setHeader token.access Authorization
 *
 * @path /auth/user/join
 * @accessor api.functional.auth.user.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
