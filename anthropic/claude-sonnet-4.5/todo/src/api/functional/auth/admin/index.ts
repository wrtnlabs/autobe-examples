/**
 * Creates a new administrator account with elevated system privileges for
 * managing users and performing administrative operations. This endpoint
 * processes admin registration requests by validating the provided email and
 * password, ensuring the email is unique across all administrator accounts, and
 * securely hashing the password using industry-standard algorithms (bcrypt or
 * argon2).
 *
 * The registration process stores the admin credentials in the todo_list_admins
 * table with fields including the unique email address (normalized to lowercase
 * for consistency), the securely hashed password in the password_hash field,
 * and timestamps for account lifecycle tracking (created_at and updated_at).
 * The email must be unique as enforced by the unique index on the email field.
 *
 * Upon successful registration, the endpoint immediately authenticates the new
 * administrator and returns JWT tokens (both access and refresh tokens) along
 * with the admin account information. This allows the newly registered admin to
 * begin using administrative functions without requiring a separate login step.
 * The refresh token is stored in a new session record in the
 * todo_list_admin_sessions table, capturing connection context including IP
 * address, referrer URL, and connection URL for security auditing purposes.
 *
 * Admin accounts are created through administrative processes rather than
 * public registration, so this endpoint should be protected by appropriate
 * access controls in production environments. The authentication tokens
 * returned include the admin role designation, granting access to elevated
 * permissions for user management, system monitoring, and administrative
 * operations.
 *
 * This operation follows the same secure JWT-based authentication pattern used
 * throughout the application, ensuring consistent security posture across all
 * actor types while providing the elevated permissions necessary for
 * administrative functions.
 *
 * @param props.connection
 * @param props.body Admin registration credentials including email and password
 * @setHeader token.access Authorization
 *
 * @path /auth/admin/join
 * @accessor api.functional.auth.admin.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
