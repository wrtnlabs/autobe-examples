import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ITodoListAdmin } from "../../../../../structures/ITodoListAdmin";

/**
 * Generates a secure password reset token record for authorized administrator.
 *
 * This endpoint initiates the administrator password reset process by
 * generating a new unique record in the todo_list_password_reset_tokens Prisma
 * table. The process requires a valid, unique administrator email that maps to
 * an enabled record in todo_list_admins (disabled_at is null). Upon request, a
 * new secure reset token is generated and associated with the correct admin id
 * (linking todo_list_password_reset_tokens to todo_list_admins by reference,
 * though user_id column is for user resets; extend for admin here). The token
 * is returned out-of-band, via audit-compliant means (e-mail/SMS/integration
 * not implemented here), and will expire at expires_at. Used tokens are kept
 * for full traceability.
 *
 * Security features enforce that token creation is not available for disabled
 * admins, and all requests are fully validated to avoid abuse. Requests from
 * unknown emails must not disclose whether the account exists for
 * anti-enumeration. Successful requests are auditable, and only one valid token
 * may exist per admin at a time (re-use forbidden). Reset attempts for already
 * disabled admins or nonexistent emails fail with generic error messages for
 * compliance.
 *
 * This endpoint does not actually reset the password, only commences the secure
 * reset flow via token generation. Actual password change must occur at
 * password reset confirmation endpoint.
 *
 * @param props.connection
 * @param props.body Administrator password reset request details; generally
 *   just the registered email.
 * @path /auth/admin/password/reset-token
 * @accessor api.functional.auth.admin.password.reset_token.generatePasswordResetToken
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function generatePasswordResetToken(
  connection: IConnection,
  props: generatePasswordResetToken.Props,
): Promise<generatePasswordResetToken.Response> {
  return true === connection.simulate
    ? generatePasswordResetToken.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...generatePasswordResetToken.METADATA,
          path: generatePasswordResetToken.path(),
          status: null,
        },
        props.body,
      );
}
export namespace generatePasswordResetToken {
  export type Props = {
    /**
     * Administrator password reset request details; generally just the
     * registered email.
     */
    body: ITodoListAdmin.IFindForPasswordReset;
  };
  export type Body = ITodoListAdmin.IFindForPasswordReset;
  export type Response = ITodoListAdmin.IPasswordResetToken;

  export const METADATA = {
    method: "POST",
    path: "/auth/admin/password/reset-token",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/admin/password/reset-token";
  export const random = (): ITodoListAdmin.IPasswordResetToken =>
    typia.random<ITodoListAdmin.IPasswordResetToken>();
  export const simulate = (
    connection: IConnection,
    props: generatePasswordResetToken.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: generatePasswordResetToken.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
