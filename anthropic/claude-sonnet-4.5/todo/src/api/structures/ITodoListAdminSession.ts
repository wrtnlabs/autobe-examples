import { tags } from "typia";

import { ITodoListAdmin } from "./ITodoListAdmin";

/**
 * Administrator session entity for audit, incident response, and compliance in
 * the Todo List application.
 *
 * Tracks login sessions associated with platform administrators, each uniquely
 * identified by a UUID and linked to an admin account (todo_list_admins) via a
 * foreign key. Sessions record network and context data (IP, href, referrer),
 * session start/end timestamps, and are used to review access history,
 * security, and incident traces.
 *
 * Each session belongs to one administrator and may be open (active) or closed
 * (expired). Used for security review, compliance investigations, and platform
 * support. System-generated fields are included as per Prisma schema.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type ITodoListAdminSession = {
  /**
   * Globally unique identifier for this admin session. Corresponds to the id
   * field in todo_list_admin_sessions.
   */
  id: string & tags.Format<"uuid">;

  /**
   * Reference to the administrator account (todo_list_admins) owning this
   * session. Embeds identity and status (id, email, disabled_at) for complete
   * audit and context analysis. Replaces the raw todo_list_admin_id.
   */
  admin: ITodoListAdmin.ISummary;

  /**
   * IP address for audit, geo-location, and risk tracking. Required for all
   * records. Typically captured from the HTTP request source.
   */
  ip: string;

  /**
   * Session initiation URL for context/audit. Records the requested resource
   * at the moment of login.
   */
  href: string;

  /**
   * Referrer URL (previous page) at session start for anomaly or attack
   * detection. Used to trace sources of login events.
   */
  referrer: string;

  /**
   * Session start timestamp (ISO8601). Recorded when authentication is
   * successful.
   */
  created_at: string & tags.Format<"date-time">;

  /**
   * Timestamp when session was terminated (logout or expire). Null for
   * currently active sessions. Used to determine session validity window.
   */
  expired_at?: (string & tags.Format<"date-time">) | null | undefined;
};
export namespace ITodoListAdminSession {
  /**
   * Summary representation of an administrator authentication session.
   *
   * Includes session context (ip, href, referrer), lifecycle timestamps, and
   * owner association for audit trails.
   *
   * References todo_list_admin_sessions; does not expose linked admin detail
   * or session authorization tokens.
   */
  export type ISummary = {
    /**
     * Globally unique identifier for this admin session. Maps to primary
     * key of todo_list_admin_sessions.
     */
    id: string & tags.Format<"uuid">;

    /**
     * Unique identifier of administrator who owns this session. References
     * todo_list_admins.id. Included for context in audit logs.
     */
    admin_id: string & tags.Format<"uuid">;

    /** Timestamp of session creation/start (ISO8601 UTC). */
    created_at: string & tags.Format<"date-time">;

    /**
     * Timestamp when the session was terminated, expired, or ended. Null
     * while active.
     */
    expired_at?: (string & tags.Format<"date-time">) | null | undefined;

    /** IP address for audit, compliance, and geo tracking at session start. */
    ip: string;

    /**
     * Session initiation URL for context and access traceability. Used in
     * audits.
     */
    href: string;

    /** Referrer URL at session start for anomaly or attack detection. */
    referrer: string;
  };

  /**
   * Request DTO for searching/filtering admin session records within a
   * specific administrator context.
   *
   * Supports pagination, sorting, and search filters (by IP, href, referrer,
   * time range). Used in PATCH /todoList/admin/admins/{adminId}/sessions. All
   * fields are optional for maximal query flexibility. Includes standard
   * page/limit/sort options and filtering criteria for forensic/incident
   * response workflows.
   *
   * Does not accept direct admin/session IDs (as those are in the path). Only
   * allows filter/search fields and pagination properties.
   */
  export type IRequest = {
    /** Page number for pagination (1-based). */
    page?: (number & tags.Type<"int32"> & tags.Minimum<1>) | undefined;

    /** Maximum number of records per page (default/system-capped at 100). */
    limit?:
      | (number & tags.Type<"int32"> & tags.Minimum<1> & tags.Maximum<100>)
      | undefined;

    /** Field to sort sessions by. Defaults to created_at. */
    sort_by?: "created_at" | "expired_at" | "ip" | undefined;

    /** Sort direction for sort_by column. Defaults to descending. */
    order_by?: "asc" | "desc" | undefined;

    /**
     * Optional filter: Match sessions where IP address contains this value
     * (partial pattern match).
     */
    ip?: string | undefined;

    /**
     * Optional filter: Match sessions with URL containing this string
     * (partial pattern match).
     */
    href?: string | undefined;

    /**
     * Optional filter: Match sessions with referrer containing this value
     * (partial pattern match).
     */
    referrer?: string | undefined;

    /**
     * Optional filter: Only sessions created at/after this timestamp
     * included.
     */
    created_from?: (string & tags.Format<"date-time">) | undefined;

    /**
     * Optional filter: Only sessions created at/before this timestamp
     * included.
     */
    created_to?: (string & tags.Format<"date-time">) | undefined;

    /**
     * Optional filter: True for only expired sessions; false for only
     * active; null/omitted for both.
     */
    expired?: boolean | undefined;
  };
}
