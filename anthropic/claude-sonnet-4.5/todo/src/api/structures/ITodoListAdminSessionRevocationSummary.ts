import { tags } from "typia";

/**
 * Summary response for bulk admin session revocation operation. This schema
 * provides comprehensive feedback about the 'logout from all devices' security
 * action, including metrics about how many sessions were terminated and
 * confirmation of security notifications.
 *
 * This response type is returned when an administrator invokes the session
 * revocation endpoint to terminate all their active sessions simultaneously.
 * The operation is typically performed for security purposes such as responding
 * to suspected account compromise, handling lost devices, or enforcing
 * re-authentication after password changes.
 *
 * The schema includes the count of revoked sessions to help administrators
 * understand the scope of the action, the precise timestamp of revocation for
 * audit trail purposes, and confirmation that security notifications were sent
 * to alert the admin about this significant account activity.
 *
 * Administrators can use this information to verify that the security action
 * completed as expected and that appropriate notifications were delivered.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type ITodoListAdminSessionRevocationSummary = {
  /**
   * Number of active admin sessions that were successfully revoked. This
   * count represents all sessions belonging to the authenticated
   * administrator that were marked as expired during the bulk revocation
   * operation.
   *
   * The count includes sessions from all devices and browsers where the admin
   * was logged in. A count of zero indicates the admin had no active sessions
   * at the time of revocation, which is unusual but possible if all sessions
   * had already expired naturally or were previously revoked individually.
   *
   * This metric is important for security auditing and helps administrators
   * verify the scope of the logout action.
   */
  revoked_count: number & tags.Type<"int32"> & tags.Minimum<0>;

  /**
   * Timestamp when the bulk session revocation was executed. This represents
   * the exact moment when all admin sessions were marked as expired by
   * setting their expired_at values.
   *
   * Recorded in ISO 8601 format with UTC timezone. This timestamp is critical
   * for security audit trails and correlating session termination with
   * potential security incidents or administrative actions.
   *
   * The same timestamp value is used as the expired_at value for all revoked
   * sessions, providing consistent temporal reference for the bulk
   * operation.
   */
  revoked_at: string & tags.Format<"date-time">;

  /**
   * Indicates whether the security notification email was successfully sent
   * to the administrator's registered email address.
   *
   * A value of true confirms that the admin received confirmation of the
   * session revocation action, including details about the timestamp and
   * originating IP address. This notification serves as both confirmation of
   * intentional actions and early warning of potential unauthorized access.
   *
   * A value of false indicates email delivery failure, which should prompt
   * administrators to verify their email settings or check spam filters for
   * the security notification.
   */
  notification_sent: boolean;
};
