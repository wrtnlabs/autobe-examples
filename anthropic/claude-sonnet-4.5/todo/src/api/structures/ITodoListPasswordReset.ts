/**
 * Password reset request entity for user account recovery in the Todo list
 * application.
 *
 * Represents a time-limited password reset token generated when a user requests
 * to reset their password. Each reset request is uniquely identified and
 * contains security information including the reset token, expiration
 * timestamp, and usage status.
 *
 * Password reset requests are created when users initiate the password recovery
 * workflow, typically by clicking a "Forgot Password" link. The reset token is
 * sent to the user's verified email address and must be used before the
 * expiration time. Once used or expired, the reset request becomes invalid.
 *
 * This entity implements security best practices including token expiration,
 * single-use tokens, and secure random token generation. Reset requests are
 * permanently associated with the user who initiated them and track whether the
 * reset has been completed.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type ITodoListPasswordReset = {
  /**
   * Unique identifier of the password reset request.
   *
   * Generated automatically by the system when a password reset is initiated.
   * This UUID serves as the primary key for the reset request record.
   */
  id: string & tags.Format<"uuid">;

  /**
   * Identifier of the user account requesting password reset.
   *
   * Foreign key reference to the todo_list_users table. Links this reset
   * request to the specific user account that initiated the password recovery
   * process.
   */
  todo_list_user_id: string & tags.Format<"uuid">;

  /**
   * Secure random token used to verify password reset authorization.
   *
   * Cryptographically secure random string that serves as the authorization
   * mechanism for password reset. This token is sent to the user's email and
   * must be provided to complete the password reset process. The token should
   * be treated as sensitive information and transmitted securely.
   */
  token: string;

  /**
   * Indicates whether this password reset token has been successfully used.
   *
   * Boolean flag that tracks the usage status of the reset token. When false,
   * the token is available for use (subject to expiration). When true, the
   * token has been consumed to reset the password and cannot be reused.
   *
   * This prevents token reuse attacks where an attacker might attempt to use
   * the same reset token multiple times. Once a password reset is completed,
   * this flag is set to true permanently.
   */
  used: boolean;

  /**
   * Timestamp when the password reset request was created.
   *
   * ISO 8601 date-time automatically set when the reset request is initiated.
   * Used to track when the user requested the password reset and to calculate
   * expiration time.
   */
  created_at: string & tags.Format<"date-time">;

  /**
   * Timestamp when this password reset token expires.
   *
   * ISO 8601 date-time indicating when the reset token becomes invalid.
   * Typically set to a short duration (e.g., 1 hour, 24 hours) after creation
   * to limit the window of vulnerability. After this time, the user must
   * request a new password reset.
   */
  expires_at: string & tags.Format<"date-time">;
};
