import { tags } from "typia";

import { IAuthorizationToken } from "./IAuthorizationToken";

/**
 * Registered user account for the Todo List application, as defined by the
 * todo_list_users table in the Prisma schema.
 *
 * This type includes all profile and account management fields needed for
 * reading or displaying a user's account state.
 *
 * Sensitive authentication fields (such as password_hash) are never included in
 * this type. The disabled_at field is used to support administrative suspension
 * of accounts for compliance or user-requested deactivation scenarios.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type ITodoListUser = {
  /**
   * Primary Key. Universally unique identifier for this user account.
   *
   * Generated at account registration. Used for all unique referencing of the
   * user entity throughout the system and within the todo_list_users table.
   * Never changes or re-used once assigned.
   */
  id: string & tags.Format<"uuid">;

  /**
   * Unique email address for user login and correspondence.
   *
   * Email serves as the principal identifier for sign-in and all notification
   * correspondence. Must be globally unique—accounts with duplicate email are
   * forbidden. Cannot be null or blank.
   */
  email: string & tags.Format<"email">;

  /**
   * Timestamp of account creation (ISO8601, always present).
   *
   * Represents the instant the account was established. Never changes once
   * set. Used for auditing, reporting, and data retention purposes.
   */
  created_at: string & tags.Format<"date-time">;

  /**
   * Timestamp of most recent account update (ISO8601, always present).
   *
   * Updated atomically with any profile or status change for the user record.
   * Essential for auditing changes and synchronization with client caches.
   */
  updated_at: string & tags.Format<"date-time">;

  /**
   * Optional timestamp set when the user account is disabled. Null means
   * active.
   */
  disabled_at?: (string & tags.Format<"date-time">) | null | undefined;
};
export namespace ITodoListUser {
  /**
   * Join/registration request DTO for creating a new user account in the Todo
   * List application.
   *
   * This schema is intended for direct client use when registering a new
   * user. Required properties include the core identity fields (unique email
   * and password) and metadata fields collected for compliance, security, and
   * audit trails (session context). Passwords are never stored or returned in
   * plaintext and must always meet system security policy.
   *
   * Session context fields ('ip', 'href', 'referrer') enable audit logging,
   * compliance investigations, and connection tracing, supporting
   * administrative and forensic processes. Audit metadata is required for
   * user self-registration and is critical for legal and operational
   * compliance reviews. However, these metadata fields may be omitted for
   * admin-initiated user creation where compliance requirements differ.
   *
   * Validation of all fields is enforced both at DTO and business rule stages
   * (see business requirements for details on length, format, and duplication
   * rules). Email must remain globally unique, and passwords require
   * entropy-preserving complexity per organizational standards.
   *
   * This DTO ensures that new user registration always creates a parallel
   * entry in the session log table (todo_list_user_sessions) for
   * authentication traceability.
   */
  export type IJoin = {
    /**
     * User's unique email address for authentication and correspondence, as
     * used in the todo_list_users database. Must adhere to RFC 5322 format
     * and is enforced as globally unique per compliance requirements. This
     * field acts as the principal login credential and primary notification
     * destination.
     */
    email: string & tags.Format<"email">;

    /**
     * Plaintext password to be securely hashed by server (bcrypt/Argon2)
     * before storage. The password must satisfy the system's minimum
     * complexity, entropy, and length policies; never stored or returned by
     * API in plaintext form. Required for all user-initiated account
     * creation.
     */
    password: string;

    /**
     * Client IP address at join. Captured for compliance auditing and
     * session investigation, but may be left null for admin-initiated
     * creation or when the server can infer from the HTTP request
     * environment. Enables precise attribution for forensic reviews.
     */
    ip?:
      | (string & tags.Format<"ipv4">)
      | (string & tags.Format<"ipv6">)
      | null
      | undefined;

    /**
     * Originating client URL (page or source) provided at registration.
     * This helps trace the point of initiation of user creation requests
     * for legal and compliance audits. Required for join flows directly
     * initiated by the user.
     */
    href: string & tags.Format<"uri">;

    /**
     * Referrer URL at registration, indicating prior browsing or linking
     * context. Aids in compliance and security traceability. Set to an
     * empty string if no referrer is available or provided.
     */
    referrer: string & tags.Format<"uri">;
  };

  /**
   * DTO returned when a user is successfully authenticated (registration,
   * login, or refresh). Represents the authenticated session context
   * including issued JWT tokens and core user identity for the Todo List
   * application. Never contains passwords or password hashes. References the
   * session record and grants access according to user role and system
   * policy. Includes user ID for client-side state tracking.
   *
   * Tokens must be securely stored on the client side for session continuity.
   * The DTO may be used for join, login, and token refresh responses.
   */
  export type IAuthorized = {
    /**
     * Unique identifier of the authenticated user account. Corresponds to
     * 'todo_list_users.id' primary key field.
     */
    id: string & tags.Format<"uuid">;

    /**
     * Unique email address for user login and correspondence.
     *
     * Email serves as the principal identifier for sign-in and all
     * notification correspondence. Must be globally unique—accounts with
     * duplicate email are forbidden. Cannot be null or blank.
     */
    email: string & tags.Format<"email">;

    /**
     * Timestamp of account creation (ISO8601, always present).
     *
     * Represents the instant the account was established. Never changes
     * once set. Used for auditing, reporting, and data retention purposes.
     */
    created_at: string & tags.Format<"date-time">;

    /**
     * Timestamp of most recent account update (ISO8601, always present).
     *
     * Updated atomically with any profile or status change for the user
     * record. Essential for auditing changes and synchronization with
     * client caches.
     */
    updated_at: string & tags.Format<"date-time">;

    /**
     * Optional timestamp set when the user account is disabled. Null means
     * active.
     */
    disabled_at?: (string & tags.Format<"date-time">) | null | undefined;

    /** JWT token information for authentication */
    token: IAuthorizationToken;
  };

  /**
   * Login request DTO for authenticating a user account in the Todo List
   * application.
   *
   * Used as the request body to the user login endpoint. Accepts the user's
   * unique email and their cleartext password (which is then securely
   * verified against the stored password hash in the database for credential
   * validation).
   *
   * Does not accept user ID or any authentication/session context fields
   * (session context managed separately upon successful authentication).
   * Email uniqueness and password requirements are enforced by the backend;
   * raw password is never stored, only compared for secure login.
   *
   * This schema does not accept system-managed fields (timestamps, account
   * state, etc.).
   */
  export type ILogin = {
    /**
     * Unique email address of the user for authentication. Must match a
     * registered email in the todo_list_users table. Must be a valid,
     * deliverable email address-conforms to RFC 5322.
     */
    email: string & tags.Format<"email">;

    /**
     * Cleartext password for authentication. Must be at least 8 characters
     * and no more than 72 characters (bcrypt safe max). This value is never
     * stored - compared to hash from database. Backend will apply
     * authentication-safe comparison.
     */
    password: string &
      tags.MinLength<8> &
      tags.MaxLength<72> &
      tags.Format<"password">;
  };

  /**
   * Refresh request DTO for obtaining new JWT authentication tokens using a
   * previously issued refresh token.
   *
   * Used as the request body for the token refresh endpoint. Accepts only the
   * current refresh token string originally issued from a prior successful
   * login. All session and device validation is performed server-side.
   *
   * This DTO accepts only the token string (other session/user context is
   * derived via backend validation; no additional fields are allowed). Never
   * accepts sensitive credentials or system-managed values.
   */
  export type IRefresh = {
    /**
     * The refresh token to be validated and exchanged for new
     * authentication tokens. Must be a valid, active token issued to the
     * current user session. Typically a long, opaque, signed JWT or similar
     * random token.
     */
    refresh_token: string;
  };

  /**
   * Request body schema for initiating a password reset via user email.
   *
   * This type enables the credential recovery flow by securely identifying
   * the user who intends to reset their password. It validates and accepts a
   * user-provided email address, never disclosing account existence per
   * security and compliance guidance.
   *
   * Submission triggers generation of a time-limited, one-time-use password
   * reset token. The actual password is never accepted here. Token delivery
   * is handled separately (e.g., via email) following further validation.
   *
   * All responses—and API behaviors—MUST avoid leaking information about
   * account presence or details. Field-level validation is enforced: email
   * must be in valid format, and improper or missing values must result in
   * generic error handling.
   *
   * Usage: POST /auth/user/password/request-reset (see password reset
   * endpoint overview).
   */
  export type IRequestPasswordReset = {
    /**
     * The email address of the user requesting password reset. Must conform
     * to the RFC 5322 email format and business validation rules. Entry
     * must be non-empty, unique per user in the todo_list_users table, and
     * trimmed of whitespace before processing. Submission of invalid email
     * addresses results in security-compliant error handling that never
     * indicates if the address exists.
     */
    email: string &
      tags.MinLength<3> &
      tags.MaxLength<320> &
      tags.Format<"email">;
  };

  /**
   * Response schema for password reset initiation requests.
   *
   * Returns an opaque message indicating that the password reset process has
   * been initiated (or at least treated as such). The message is
   * intentionally non-committal to prevent user enumeration or leakage of
   * account details. No token or details about account existence are included
   * — all API responses should be indistinguishable regardless of whether a
   * matching user account exists.
   *
   * Used in response to POST /auth/user/password/request-reset. This is a
   * business design mandated by the security and compliance requirements for
   * the Todo List application.
   */
  export type IPasswordResetInitiated = {
    /**
     * Opaque status message for password reset request. Always a generic
     * string such as 'If an account exists for this email, password reset
     * instructions will be sent.' NEVER includes details about whether the
     * account or email exists, about token delivery, or about
     * success/failure specifics. Example: 'If an account exists for this
     * email, password reset instructions will be sent.'
     */
    message: string;
  };

  /**
   * DTO for updating user account properties in the todo_list_users table.
   *
   * Allows changing the account email to a new unique value, or
   * administratively toggling the disabled state with the disabled_at field.
   * Cannot be used for changing credentials (password edits require a
   * separate mechanism). All properties are optional and can be independently
   * updated. Security critical fields like password_hash are never present.
   */
  export type IUpdate = {
    /**
     * New unique email address for user login if being changed via account
     * settings. Must remain globally unique across all users. Required only
     * if email is being updated.
     */
    email?: (string & tags.Format<"email">) | undefined;

    /**
     * Set or clear the administrative disabled state of a user. Null means
     * re-enable; a non-null date disables the account.
     */
    disabled_at?: (string & tags.Format<"date-time">) | null | undefined;
  };

  /**
   * Summary DTO with essential, publicly exposable information about a todo
   * list user. Used for nesting within other summary types and for
   * representing owners in lightweight operations. Excludes
   * sensitive/authentication fields.
   */
  export type ISummary = {
    /** Unique identifier for the user account. Maps to todo_list_users.id. */
    id: string & tags.Format<"uuid">;

    /**
     * Unique email address for login and correspondence. Maps to
     * todo_list_users.email.
     */
    email: string & tags.Format<"email">;

    /**
     * Datetime of user account creation. Corresponds to
     * todo_list_users.created_at.
     */
    created_at: string & tags.Format<"date-time">;

    /**
     * Datetime of account's latest update. Maps to
     * todo_list_users.updated_at.
     */
    updated_at: string & tags.Format<"date-time">;

    /**
     * If applicable, time when the account was disabled. Null if still
     * active; maps to todo_list_users.disabled_at.
     */
    disabled_at?: (string & tags.Format<"date-time">) | null | undefined;
  };
}
