/**
 * Platform administrator accounts for the Todo List application with
 * privileged, system-wide management capabilities.
 *
 * This schema represents administrators who have full access over all user
 * data, Todos, administrative support actions, and audit/compliance oversight
 * within the system. Each admin account is independently authenticated, managed
 * through unique email credentials (globally enforced), and traceable via all
 * access and update events. No user accounts appear here—admins are never mixed
 * with regular users in the same table by system design.
 *
 * All administrator account lifecycle events (creation, login, update,
 * compliance/action) are fully audit-logged. Disabling an admin account is
 * supported for incident response or compliance requirements and is recorded
 * via lifecycle timestamps. All authentication and credential management for
 * admins is handled via dedicated password hashing (see `password_hash` in
 * Prisma); this value is intentionally omitted from all returned DTOs for
 * security, following best practices. Only admin actors can access or update
 * admin records via the API, and all such access is audit-logged for compliance
 * enforcement.
 *
 * This model excludes password hashes and authentication secrets from outputs;
 * inclusion of authentication fields is restricted to tightly controlled
 * contexts only. Review and update activity is always associated with an
 * authenticated admin and fully traceable across system logs.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
