/**
 * Represents a single, auditable record of an authenticated user session in the
 * Todo List application. Used by administrators for security reviews,
 * compliance audits, and support investigations related to user account
 * access.
 *
 * Each session tracks the origin of authentication, associated user ID, IP
 * address, initial connection URL, referrer, and timestamps for both creation
 * and (if applicable) termination or expiry. Session events are linked
 * exclusively to one user and cannot be reassigned; linkage ensures full
 * traceability for compliance.
 *
 * This record is exposed exclusively via admin endpoints and is never
 * modifiable or creatable via direct API calls. Session details are retained
 * for audit, incident response, and system security purposes and do not include
 * personal user data beyond what is strictly necessary for authentication
 * traceability. Any deactivation, expiry, or forced logout is reflected in the
 * session's lifecycle fields, and all access is strictly logged for compliance
 * enforcement.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type ITodoListUserSession = {
  /**
   * Primary key and immutably unique identifier for this user session in the
   * database.
   *
   * Used in all audits, trace events, and administrative support cases to
   * reference a specific login instance. Never null or modifiable.
   */
  id: string & tags.Format<"uuid">;

  /**
   * Foreign key reference to the parent todo_list_users entity whose
   * authentication initiated this session.
   *
   * Links session access records to the user account for full auditability.
   * Used by admins to investigate user-specific access history.
   */
  todo_list_user_id: string & tags.Format<"uuid">;

  /**
   * IP address of the client/device that initiated this session. Used for
   * anomaly detection, security event review, and geographic compliance
   * audits.
   *
   * This field never contains personally sensitive information beyond
   * traceable network metadata. Always populated on successful
   * authentication.
   */
  ip: string;

  /**
   * URL (origin/context) from which the session was started by the end user
   * (e.g., browser origin or device landing page).
   *
   * Critical for forensic analysis and security monitoring by system
   * administrators.
   */
  href: string;

  /**
   * Full referrer URL provided by the client when authenticating for this
   * session. Commonly used to trace navigation flows or identify third-party
   * integrations in compliance scenarios.
   *
   * Collected at the moment of authentication event creation; never null.
   */
  referrer: string;

  /**
   * Timestamp (ISO 8601) when the session record was created in the database,
   * i.e., the authentication event occurred.
   *
   * Present in all session records. Used for reconstructing session timelines
   * during investigations.
   */
  created_at: string & tags.Format<"date-time">;

  /**
   * Denotes termination of session if completed, otherwise null for
   * still-active sessions.
   */
  expired_at?: (string & tags.Format<"date-time">) | null | undefined;
};
