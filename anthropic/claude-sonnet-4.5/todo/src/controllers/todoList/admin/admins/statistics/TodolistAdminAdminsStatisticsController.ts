import { Controller } from "@nestjs/common";
import { TypedRoute } from "@nestia/core";
import typia from "typia";
import { getTodoListAdminAdminsStatistics } from "../../../../../providers/getTodoListAdminAdminsStatistics";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";

import { ITodoListSystemStatistics } from "../../../../../api/structures/ITodoListSystemStatistics";

@Controller("/todoList/admin/admins/statistics")
export class TodolistAdminAdminsStatisticsController {
  /**
   * Retrieve system-wide statistics for administrative monitoring.
   *
   * Retrieve comprehensive system-wide statistics for administrative monitoring
   * and oversight. This operation provides administrators with aggregate
   * metrics about the Todo list application's usage, user activity, and overall
   * system health.
   *
   * The statistics include information about the total number of registered
   * users, active user counts, total todo items across all users, completion
   * rates, and other system-wide metrics. This data helps administrators
   * monitor system growth, user engagement patterns, and overall application
   * health without accessing individual users' private todo content.
   *
   * This operation aggregates data from the todo_list_users and todo_list_todos
   * tables in the Prisma schema. It respects user privacy by providing only
   * aggregate statistics rather than exposing individual user data.
   * Administrators can use these insights to make informed decisions about
   * system capacity, user support needs, and feature prioritization.
   *
   * Security considerations: This endpoint requires administrator
   * authentication and authorization. Only users with admin role (from
   * todo_list_admins table) can access system-wide statistics. The operation
   * logs admin access for audit purposes to maintain accountability and
   * security compliance.
   *
   * The response provides a comprehensive dashboard view of system metrics
   * including user registration trends, todo creation patterns, task completion
   * rates, and system activity levels. These metrics are essential for
   * monitoring system performance, identifying usage patterns, and planning for
   * future scalability needs.
   *
   * @param connection
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
  ): Promise<ITodoListSystemStatistics> {
    try {
      return await getTodoListAdminAdminsStatistics({
        admin,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
