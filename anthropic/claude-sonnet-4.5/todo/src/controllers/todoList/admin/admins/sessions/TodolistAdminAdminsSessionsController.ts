import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchTodoListAdminAdminsAdminIdSessions } from "../../../../../providers/patchTodoListAdminAdminsAdminIdSessions";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getTodoListAdminAdminsAdminIdSessionsSessionId } from "../../../../../providers/getTodoListAdminAdminsAdminIdSessionsSessionId";

import { IPageITodoListAdminSession } from "../../../../../api/structures/IPageITodoListAdminSession";
import { ITodoListAdminSession } from "../../../../../api/structures/ITodoListAdminSession";

@Controller("/todoList/admin/admins/:adminId/sessions")
export class TodolistAdminAdminsSessionsController {
  /**
   * Get a paginated, filtered list of sessions for a given admin
   * (todo_list_admin_sessions).
   *
   * Obtain a filtered and paginated list of session records for a specific
   * administrator account. Sessions represent each login event and record admin
   * activity for platform support, audit, and compliance purposes.
   *
   * This endpoint supports advanced search features, including sorting by
   * created_at, filtering by session activity periods, and searching by client
   * IP or URL context. Security-sensitive details such as IP address and
   * referrer information are available, allowing compliance teams to
   * investigate suspicious access patterns or incidents.
   *
   * Only administrators may view administrative session histories. The session
   * records relate to the todo_list_admin_sessions table and are always linked
   * to the todo_list_admins table via the todo_list_admin_id foreign key.
   * Errors are returned for invalid administrator IDs or when the administrator
   * does not exist.
   *
   * @param connection
   * @param adminId Unique identifier (UUID) of the administrator whose sessions
   *   are queried. Must correspond to the id field in todo_list_admins.
   * @param body Session search criteria, filters, and pagination options for
   *   admin session records.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoListAdminSession.IRequest,
  ): Promise<IPageITodoListAdminSession.ISummary> {
    try {
      return await patchTodoListAdminAdminsAdminIdSessions({
        admin,
        adminId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Get complete details of a specific admin session
   * (todo_list_admin_sessions).
   *
   * Fetch the complete details of an administrator session, including
   * timestamps, client network details, context URLs, and logout/expiry state.
   * This endpoint requires both the admin's UUID and the session UUID for
   * disambiguation and to ensure session records are correctly attributed to
   * the correct administrator.
   *
   * The underlying session record is sourced from the todo_list_admin_sessions
   * table and is always linked through the todo_list_admin_id foreign key to
   * the todo_list_admins table. All session information is intended for
   * administrative and security personnel only, and error responses are
   * provided if identifiers are invalid or if the session-admin relationship
   * does not exist.
   *
   * This endpoint is essential for forensic analysis and security oversight,
   * enabling identification of session-specific details in support of
   * compliance programs.
   *
   * @param connection
   * @param adminId Unique identifier (UUID) of the administrator who owns the
   *   session. Corresponds to id field in todo_list_admins.
   * @param sessionId Unique identifier (UUID) of the session to be retrieved.
   *   Corresponds to id field in todo_list_admin_sessions.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<ITodoListAdminSession> {
    try {
      return await getTodoListAdminAdminsAdminIdSessionsSessionId({
        admin,
        adminId,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
