import { Controller } from "@nestjs/common";
import { TypedRoute } from "@nestia/core";
import typia from "typia";
import { postTodoListAdminAdminsLogoutAll } from "../../../../../../providers/postTodoListAdminAdminsLogoutAll";
import { AdminAuth } from "../../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../../decorators/payload/AdminPayload";

import { ITodoListAdminAuth } from "../../../../../../api/structures/ITodoListAdminAuth";

@Controller("/todoList/admin/admins/logout/all")
export class TodolistAdminAdmins_logoutAllController {
  /**
   * Log out administrator from all active sessions on all devices.
   *
   * This operation provides a comprehensive session termination mechanism that
   * logs out the currently authenticated administrator from every active
   * session across all devices and browsers simultaneously. When an admin
   * invokes this endpoint, the system validates their JWT access token to
   * identify the admin, then locates all active session records in the
   * todo_list_admin_sessions table where expired_at is null, and marks all of
   * them as expired by setting the expired_at timestamp to the current time.
   *
   * This global logout functionality serves critical security purposes. If an
   * administrator suspects their account credentials have been compromised,
   * lost a device, or used a public computer and forgot to log out, they can
   * use this operation to immediately revoke access from all locations. After
   * successful execution, all existing JWT access tokens for this admin become
   * invalid, and the admin must re-authenticate on every device to regain
   * access to the system.
   *
   * The operation maintains complete audit trails by recording expiration
   * timestamps for all affected sessions. This provides administrators and
   * security teams with visibility into when global logouts occurred, which can
   * be correlated with security incidents or policy compliance requirements.
   * The system logs this significant security event with appropriate detail for
   * administrative oversight.
   *
   * Unlike the standard logout operation which only terminates the current
   * session, this endpoint affects every active session simultaneously. This
   * makes it particularly valuable for security-conscious administrators who
   * want to ensure no unauthorized access remains, for admins changing their
   * passwords who want to force re-authentication everywhere, or for security
   * teams responding to potential account compromise. The admin invoking this
   * operation will also be logged out from their current session and must log
   * in again to continue working.
   *
   * @param connection
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async logoutAll(
    @AdminAuth()
    admin: AdminPayload,
  ): Promise<ITodoListAdminAuth.ILogoutAllResponse> {
    try {
      return await postTodoListAdminAdminsLogoutAll({
        admin,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
