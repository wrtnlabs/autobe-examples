import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { getTodoListAdminAdminsMe } from "../../../../../providers/getTodoListAdminAdminsMe";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { putTodoListAdminAdminsMe } from "../../../../../providers/putTodoListAdminAdminsMe";
import { deleteTodoListAdminAdminsMe } from "../../../../../providers/deleteTodoListAdminAdminsMe";

import { ITodoListAdmin } from "../../../../../api/structures/ITodoListAdmin";

@Controller("/todoList/admin/admins/me")
export class TodolistAdminAdminsMeController {
  /**
   * Retrieve authenticated administrator's profile information.
   *
   * Retrieves the complete profile information for the currently authenticated
   * administrator user. This operation provides access to the admin's account
   * details stored in the todo_list_admins table, including their unique
   * identifier, email address, account creation timestamp, and last
   * modification timestamp.
   *
   * The operation requires valid admin authentication via JWT token. The system
   * extracts the admin user ID from the authenticated session and retrieves the
   * corresponding admin record from the database. Only the authenticated admin
   * can access their own profile information through this endpoint.
   *
   * This endpoint is commonly used when admins access their profile settings
   * page, account management interface, or when the application needs to
   * display the current admin's information. The response includes all
   * non-sensitive profile data, excluding the password hash for security
   * purposes.
   *
   * Security considerations: The operation enforces authentication requirements
   * and ensures that admins can only access their own profile data. The
   * password_hash field is excluded from the response to prevent exposure of
   * sensitive authentication credentials. The deleted_at timestamp indicates
   * whether the account has been soft deleted, which would typically prevent
   * access entirely during the authentication phase.
   *
   * @param connection
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @AdminAuth()
    admin: AdminPayload,
  ): Promise<ITodoListAdmin> {
    try {
      return await getTodoListAdminAdminsMe({
        admin,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update authenticated administrator's profile information.
   *
   * Updates the profile information for the currently authenticated
   * administrator user. This operation enables admins to modify their account
   * details stored in the todo_list_admins table, specifically allowing updates
   * to the email address and password.
   *
   * The operation requires valid admin authentication via JWT token. The system
   * extracts the admin user ID from the authenticated session and updates the
   * corresponding admin record in the database. Only the authenticated admin
   * can update their own profile information through this endpoint.
   *
   * When updating the email address, the system validates that the new email
   * follows proper email format and is not already in use by another admin
   * account. This ensures email uniqueness across all administrators. If the
   * email is changed, the admin should be informed that they may need to use
   * the new email for future login attempts.
   *
   * When updating the password, the system enforces password strength
   * requirements (minimum 8 characters, at least one letter and one number).
   * The provided password is securely hashed using industry-standard algorithms
   * (bcrypt, argon2, or PBKDF2) before storage. The system never stores
   * passwords in plain text. After a successful password change, all existing
   * admin sessions may be invalidated for security purposes, requiring the
   * admin to log in again with the new credentials.
   *
   * The updated_at timestamp is automatically set to the current time whenever
   * any profile modification occurs. This helps track when the admin last
   * modified their account information. The operation returns the updated admin
   * profile information, excluding the password hash for security.
   *
   * Validation rules enforce data integrity: email must be in valid format,
   * email must be unique if changed, and password must meet security
   * requirements if provided. Authorization ensures that admins can only update
   * their own profile, preventing cross-admin modifications.
   *
   * @param connection
   * @param body Updated profile information including optional email and
   *   password changes
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: ITodoListAdmin.IUpdate,
  ): Promise<ITodoListAdmin> {
    try {
      return await putTodoListAdminAdminsMe({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete own admin account (soft delete).
   *
   * Delete the authenticated administrator's own account from the Todo list
   * application. This operation performs a soft delete on the admin account,
   * marking it as deleted while preserving audit trail information.
   *
   * When an admin account is deleted, the system sets the deleted_at timestamp
   * in the todo_list_admins table to the current time, effectively deactivating
   * the account. All associated admin sessions (todo_list_admin_sessions) are
   * automatically removed through cascade deletion as defined in the database
   * schema relationship.
   *
   * This is a security-critical operation that permanently deactivates the
   * admin account. Once deleted, the admin will no longer be able to log in or
   * access administrative functions. The email address associated with the
   * deleted account becomes available for re-registration.
   *
   * The operation enforces strict authorization - admins can only delete their
   * own account through this endpoint. This prevents unauthorized deletion of
   * other administrator accounts and maintains system security. The soft delete
   * mechanism (using deleted_at timestamp) enables potential account recovery
   * and maintains audit trails as required by business policy.
   *
   * @param connection
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
  ): Promise<void> {
    try {
      return await deleteTodoListAdminAdminsMe({
        admin,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
