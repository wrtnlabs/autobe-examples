import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { getTodoListAdminAdminsMe } from "../../../../../providers/getTodoListAdminAdminsMe";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { putTodoListAdminAdminsMe } from "../../../../../providers/putTodoListAdminAdminsMe";

import { ITodoListAdmin } from "../../../../../api/structures/ITodoListAdmin";

@Controller("/todoList/admin/admins/me")
export class TodolistAdminAdminsMeController {
  /**
   * Retrieve authenticated administrator's own profile information.
   *
   * Retrieve the currently authenticated administrator's profile information
   * including account details and metadata.
   *
   * This operation allows administrators to view their own account information
   * by extracting the admin identity from the JWT access token. The admin ID is
   * obtained from the token claims rather than requiring a path parameter,
   * ensuring that admins can only access their own profile data through this
   * endpoint.
   *
   * Security: This endpoint requires admin authentication via JWT token. The
   * system validates the token and extracts the admin user ID to retrieve the
   * corresponding profile from the todo_list_admins table. Only the
   * authenticated admin's own data is returned, maintaining proper
   * authorization boundaries even for administrative accounts.
   *
   * The response includes the admin's email address used for authentication,
   * account creation timestamp for lifecycle tracking, and last update
   * timestamp indicating when credentials or account information were most
   * recently modified. Password hashes are never included in responses for
   * security reasons.
   *
   * This endpoint supports the admin actor's ability to 'View own profile' as
   * specified in the authentication requirements permission matrix. It follows
   * the same self-service account management patterns available to regular
   * users but applies to administrative accounts.
   *
   * @param connection
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @AdminAuth()
    admin: AdminPayload,
  ): Promise<ITodoListAdmin.ISummary> {
    try {
      return await getTodoListAdminAdminsMe({
        admin,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update authenticated administrator's own account information.
   *
   * Update the currently authenticated administrator's account information,
   * primarily for changing account password through secure verification.
   *
   * This operation allows administrators to modify their own account
   * credentials following the secure password change process outlined in the
   * authentication requirements. The admin must provide their current password
   * for identity verification before the new password is accepted, preventing
   * unauthorized password changes even if a session token is compromised.
   *
   * Security: Admin authentication is required via JWT token. The system
   * extracts the admin user ID from the token claims to identify which account
   * to update. The current password must be validated against the stored
   * password hash before any changes are committed. The new password must meet
   * all password strength requirements including minimum 8 characters,
   * uppercase, lowercase, numeric, and special character requirements.
   *
   * When a password change succeeds, the system updates the password_hash field
   * in the todo_list_admins table and sets the updated_at timestamp. All
   * existing admin sessions except the current one are invalidated by revoking
   * refresh tokens, forcing re-authentication on other devices. The admin
   * receives email notification confirming the password change with timestamp
   * and IP address for security awareness.
   *
   * Validation: Current password verification fails with error 'Current
   * password is incorrect'. New password strength validation provides specific
   * feedback about which requirements are not met. The operation follows the
   * same password change flow as regular users but applies to administrative
   * accounts.
   *
   * This endpoint implements the admin's self-service account management
   * capability defined in the Actor-Specific Business Requirements, allowing
   * admins to independently maintain their credential security without
   * requiring assistance from other administrators.
   *
   * @param connection
   * @param body Account update information including current and new password
   *   for secure verification
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: ITodoListAdmin.IUpdate,
  ): Promise<ITodoListAdmin.ISummary> {
    try {
      return await putTodoListAdminAdminsMe({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
