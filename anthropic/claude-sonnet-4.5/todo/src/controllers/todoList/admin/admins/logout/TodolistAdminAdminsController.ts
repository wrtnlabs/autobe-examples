import { Controller } from "@nestjs/common";
import { TypedRoute } from "@nestia/core";
import typia from "typia";
import { postTodoListAdminAdminsLogout } from "../../../../../providers/postTodoListAdminAdminsLogout";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";

import { ITodoListAdminAuth } from "../../../../../api/structures/ITodoListAdminAuth";

@Controller("/todoList/admin/admins/logout")
export class TodolistAdminAdminsController {
  /**
   * Log out the current administrator session.
   *
   * This operation terminates the currently authenticated administrator's
   * active session, effectively logging them out from their current device or
   * browser. When an admin invokes this endpoint, the system validates their
   * JWT access token, identifies the associated admin session record in the
   * todo_list_admin_sessions table, and marks it as expired by setting the
   * expired_at timestamp to the current time.
   *
   * The logout process ensures that the admin's current access token becomes
   * invalid for subsequent authenticated requests. After successful logout, the
   * admin must authenticate again with their email and password to obtain new
   * JWT tokens and establish a new session. This operation affects only the
   * current session from which the logout request was made, allowing the admin
   * to remain logged in on other devices if they have multiple active
   * sessions.
   *
   * Security considerations are paramount in this operation. The system
   * validates that the logout request comes from an authenticated admin by
   * verifying the JWT token signature and ensuring the token has not expired.
   * The operation maintains an audit trail by recording the session termination
   * timestamp, which can be used for security monitoring and compliance
   * purposes. Admin logout events should be logged for administrative oversight
   * and security auditing.
   *
   * This endpoint is essential for administrators who want to securely end
   * their session when finished using the system, especially when accessing the
   * admin dashboard from shared or public computers. It provides a clean
   * session termination mechanism that invalidates the current authentication
   * state without affecting other active admin sessions.
   *
   * @param connection
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async logout(
    @AdminAuth()
    admin: AdminPayload,
  ): Promise<ITodoListAdminAuth.ILogoutResponse> {
    try {
      return await postTodoListAdminAdminsLogout({
        admin,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
