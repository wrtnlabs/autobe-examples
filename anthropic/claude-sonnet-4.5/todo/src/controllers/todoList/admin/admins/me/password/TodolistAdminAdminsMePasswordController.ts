import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { putTodoListAdminAdminsMePassword } from "../../../../../../providers/putTodoListAdminAdminsMePassword";
import { AdminAuth } from "../../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../../decorators/payload/AdminPayload";

import { ITodoListAdmin } from "../../../../../../api/structures/ITodoListAdmin";

@Controller("/todoList/admin/admins/me/password")
export class TodolistAdminAdminsMePasswordController {
  /**
   * Change own admin account password.
   *
   * Update the authenticated administrator's password with a new secure
   * password. This operation allows admins to change their account password for
   * security purposes.
   *
   * The password change process requires the admin to provide their current
   * password for verification, ensuring that only the legitimate account owner
   * can modify the password. This protects against unauthorized password
   * changes in case an admin session is compromised.
   *
   * The new password must meet minimum security requirements: at least 8
   * characters in length, containing at least one letter and one number. The
   * system validates these requirements before accepting the password change.
   * The password is securely hashed using industry-standard algorithms (bcrypt,
   * argon2, or PBKDF2) before storage in the password_hash field.
   *
   * Upon successful password change, the system updates the updated_at
   * timestamp in the todo_list_admins table to reflect the modification time.
   * For enhanced security, the system should invalidate all existing admin
   * sessions (todo_list_admin_sessions) except the current session, forcing
   * re-authentication on all other devices. This ensures that if the password
   * was changed due to suspected compromise, any unauthorized sessions are
   * immediately terminated.
   *
   * This operation is essential for account security and compliance with
   * password rotation policies. Admins should be encouraged to change their
   * passwords regularly and immediately if they suspect their credentials have
   * been compromised.
   *
   * @param connection
   * @param body Current password for verification and new password that meets
   *   security requirements
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: ITodoListAdmin.IChangePassword,
  ): Promise<void> {
    try {
      return await putTodoListAdminAdminsMePassword({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
