import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { getTodoListAdminAdminsAdminId } from "../../../../providers/getTodoListAdminAdminsAdminId";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { putTodoListAdminAdminsAdminId } from "../../../../providers/putTodoListAdminAdminsAdminId";
import { deleteTodoListAdminAdminsAdminId } from "../../../../providers/deleteTodoListAdminAdminsAdminId";

import { ITodoListAdmin } from "../../../../api/structures/ITodoListAdmin";

@Controller("/todoList/admin/admins/:adminId")
export class TodolistAdminAdminsController {
  /**
   * Retrieve detailed administrator account information (todo_list_admins
   * table) by admin ID.
   *
   * Fetch the detailed profile and audit information for a single administrator
   * account by unique ID. This operation is available only to authenticated
   * admin actors for system oversight, support, or compliance events,
   * supporting internal audits or review of admin privileges. Details such as
   * admin email, registration, update times, and compliance status are returned
   * to facilitate incident handling and account lifecycle review.
   *
   * Security and compliance are enforced by restricting access to
   * administrators only, and all use is logged for traceability. The endpoint
   * does not allow for account creation, update, or disabling—modification
   * operations must be performed via out-of-band administrative channels, not
   * through this endpoint. The operation complies with the platform's
   * requirement that all admin activity trails are fully audit-logged.
   *
   * If an invalid ID or inaccessible record is provided, the system returns a
   * not found or forbidden error, avoiding data leakage.
   *
   * @param connection
   * @param adminId Unique identifier of the administrator account to retrieve.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
  ): Promise<ITodoListAdmin> {
    try {
      return await getTodoListAdminAdminsAdminId({
        admin,
        adminId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update existing administrator account in todo_list_admins table.
   *
   * Update the fields of a platform administrator account, as defined in the
   * todo_list_admins schema.
   *
   * This endpoint allows authorized system administrators to change critical
   * account information such as the admin's unique email or password hash.
   * Updates to sensitive attributes, including credential resets, are logged
   * for audit and compliance purposes. Only unique and validated email
   * addresses may be used, reflecting the constraints of the database.
   *
   * Security is critical: Only authenticated administrators with proper
   * authorization may initiate this action. Attempts to assign duplicate emails
   * or bypass unique constraints will result in validation errors. The system
   * keeps a record of when each change is made to support compliance
   * investigations and incident response.
   *
   * Related operations include disabling an admin account and recovering or
   * resetting passwords, which should be coordinated for full account lifecycle
   * management. Error handling covers unauthorized access, validation failures,
   * and change collisions.
   *
   * @param connection
   * @param adminId Unique identifier for the administrator account to update.
   * @param body Fields to update for the target admin account. Only values
   *   defined in ITodoListAdmin.IUpdate are allowed.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoListAdmin.IUpdate,
  ): Promise<ITodoListAdmin> {
    try {
      return await putTodoListAdminAdminsAdminId({
        admin,
        adminId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete (hard erase) the specified administrator account in todo_list_admins
   * table.
   *
   * Permanently erase a platform administrator account from the system by
   * targeting the record in the todo_list_admins database table.
   *
   * This operation is reserved for administrators, allowing for the secure
   * removal of privileged accounts in the event of role change, departure, or
   * security risk. The erased record is immediately and completely removed and
   * cannot be restored. All erasure actions are logged for regulatory
   * compliance and incident audits.
   *
   * Careful safeguards must be employed to prevent accidental erasure of
   * critical admin accounts. Errors may result from attempting to delete
   * non-existent accounts or lacking sufficient authorization for this
   * sensitive administrative operation.
   *
   * @param connection
   * @param adminId Unique identifier for the administrator account to delete.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoListAdminAdminsAdminId({
        admin,
        adminId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
