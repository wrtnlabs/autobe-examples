import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { getTodoListAdminAdminsAdminId } from "../../../../providers/getTodoListAdminAdminsAdminId";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { putTodoListAdminAdminsAdminId } from "../../../../providers/putTodoListAdminAdminsAdminId";
import { deleteTodoListAdminAdminsAdminId } from "../../../../providers/deleteTodoListAdminAdminsAdminId";
import { patchTodoListAdminAdmins } from "../../../../providers/patchTodoListAdminAdmins";

import { ITodoListAdmin } from "../../../../api/structures/ITodoListAdmin";
import { IPageITodoListAdmin } from "../../../../api/structures/IPageITodoListAdmin";

@Controller("/todoList/admin/admins")
export class TodolistAdminAdminsController {
  /**
   * Retrieve detailed information for a specific administrator account.
   *
   * Retrieve comprehensive details about a specific administrator account in
   * the Todo list application. This operation provides complete administrator
   * profile information including username, email, authentication status, and
   * account creation and update timestamps. For security reasons, password
   * hashes and other sensitive authentication credentials are excluded from the
   * response.
   *
   * This endpoint is restricted to authenticated administrator users who need
   * to view administrator account details. The operation supports retrieving
   * information about any administrator account in the system by their unique
   * identifier.
   *
   * Security considerations include ensuring that only authorized
   * administrators can access administrator account details. Sensitive
   * information such as password hashes are explicitly excluded from responses
   * to prevent security vulnerabilities. Rate limiting may apply to prevent
   * abuse of administrator information retrieval.
   *
   * The operation integrates with the todo_list_admins table as defined in the
   * Prisma schema, returning administrator fields while filtering out
   * password-related data. This operation is typically used in administrative
   * dashboards, user management interfaces, or security audit workflows.
   *
   * @param connection
   * @param adminId Unique identifier of the target administrator account
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":adminId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
  ): Promise<ITodoListAdmin.ISummary> {
    try {
      return await getTodoListAdminAdminsAdminId({
        admin,
        adminId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing administrator account's information.
   *
   * Update comprehensive details of an existing administrator account in the
   * Todo list application. This operation allows modification of administrator
   * profile information including username, email address, and password
   * credentials while enforcing validation rules and maintaining data
   * consistency.
   *
   * The operation supports updating administrator accounts with flexible field
   * modification. Only the fields provided in the request body will be updated,
   * while omitted fields remain unchanged. The system validates all input data
   * to ensure username uniqueness, email format correctness, and password
   * strength requirements before applying changes.
   *
   * Security considerations include strict authorization checks to ensure only
   * authorized administrators can modify administrator accounts. Password
   * updates trigger secure hashing mechanisms, and password hashes are never
   * exposed in API responses. The operation logs all modification attempts for
   * audit purposes and implements rate limiting to prevent abuse.
   *
   * The operation integrates with the todo_list_admins table as defined in the
   * Prisma schema, updating administrator records while maintaining referential
   * integrity with related entities such as admin sessions. The response
   * returns updated administrator information excluding sensitive password
   * data. This operation is commonly used in administrator management
   * workflows, profile update interfaces, and security credential rotation
   * processes.
   *
   * @param connection
   * @param adminId Unique identifier of the target administrator account to
   *   update
   * @param body Updated administrator account information including optional
   *   username, email, and password modifications
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":adminId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoListAdmin.IUpdate,
  ): Promise<ITodoListAdmin.ISummary> {
    try {
      return await putTodoListAdminAdminsAdminId({
        admin,
        adminId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Soft delete an administrator account by marking it as deleted.
   *
   * Soft delete an administrator account from the todo_list_admins table by
   * setting the deleted_at timestamp to the current time. The admin record is
   * preserved in the database to maintain audit trails and historical data for
   * compliance purposes.
   *
   * This operation marks the admin account as deleted without physically
   * removing it from the database. The deleted_at field is set to the current
   * timestamp, which excludes the account from normal authentication and query
   * operations while preserving all historical data. Related sessions in the
   * todo_list_admin_sessions table are retained to maintain complete security
   * audit logs.
   *
   * Security: This operation requires administrative authorization and should
   * only be accessible to super administrators or authorized system operators.
   * The soft deletion approach ensures accountability by preserving a complete
   * audit trail of all admin accounts that have been removed. All deletion
   * actions should be logged with details of who performed the deletion and
   * when.
   *
   * Use cases for admin soft deletion include: removing access for
   * administrators who have left the organization while preserving their
   * activity history, temporarily disabling admin accounts during security
   * investigations, maintaining compliance with data retention policies that
   * require historical admin access records, and enabling potential account
   * restoration if removal was performed in error.
   *
   * The soft-deleted admin account can potentially be restored by clearing the
   * deleted_at timestamp if needed. Session history remains intact for security
   * auditing and compliance reporting.
   *
   * @param connection
   * @param adminId Unique identifier of the administrator account to be soft
   *   deleted (global scope)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":adminId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
  ): Promise<ITodoListAdmin> {
    try {
      return await deleteTodoListAdminAdminsAdminId({
        admin,
        adminId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve a filtered, paginated list of system administrators.
   *
   * Retrieve a filtered and paginated list of system administrator accounts
   * from the Todo list application. This operation provides advanced search
   * capabilities for finding administrators based on multiple criteria
   * including partial username matching, email domain filtering, registration
   * date ranges, and account status.
   *
   * The operation supports comprehensive pagination with configurable page
   * sizes and sorting options. Administrators can sort by registration date,
   * last login, username, or other relevant fields in ascending or descending
   * order.
   *
   * Security considerations include strict authorization enforcement - only
   * existing administrators with appropriate permissions can access this
   * endpoint to view other administrator accounts. This ensures that the
   * administrator list remains protected from unauthorized access and maintains
   * system security integrity.
   *
   * This operation integrates with the todo_list_admins table as defined in the
   * Prisma schema, incorporating all available administrator fields and
   * relationships. The response includes administrator summary information
   * optimized for list displays, with appropriate filtering of sensitive
   * information.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for administrator
   *   filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: ITodoListAdmin.IRequest,
  ): Promise<IPageITodoListAdmin.ISummary> {
    try {
      return await patchTodoListAdminAdmins({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
