import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { deleteTodoListAdminAdminsMeSessionsSessionId } from "../../../../../../providers/deleteTodoListAdminAdminsMeSessionsSessionId";
import { AdminAuth } from "../../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../../decorators/payload/AdminPayload";

@Controller("/todoList/admin/admins/me/sessions/:sessionId")
export class TodolistAdminAdminsMeSessionsController {
  /**
   * Terminate a specific admin session by session ID.
   *
   * Terminates an administrator's specific session, effectively logging them
   * out from a particular device or browser while preserving other active
   * sessions. This operation is essential for security management, allowing
   * administrators to revoke access from individual devices without affecting
   * their sessions on other devices.
   *
   * When an admin terminates a session, the system performs a soft delete by
   * setting the expired_at timestamp in the todo_list_admin_sessions table to
   * the current time, marking the session as ended. The session record is
   * preserved for audit purposes and security monitoring, maintaining a
   * complete history of admin authentication activity.
   *
   * This operation requires the administrator to be authenticated and can only
   * terminate sessions belonging to the requesting admin. The sessionId path
   * parameter identifies which specific session to terminate, enabling
   * selective logout functionality. This is particularly useful when an
   * administrator wants to log out from a specific device they no longer have
   * physical access to, or when they suspect a session may have been
   * compromised.
   *
   * The soft delete approach using expired_at ensures that session history
   * remains intact for security audits while immediately invalidating the
   * session for authentication purposes. All subsequent requests using the
   * terminated session's tokens will be rejected, requiring the administrator
   * to re-authenticate on that device.
   *
   * @param connection
   * @param sessionId Unique identifier of the admin session to terminate
   *   (global scope)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoListAdminAdminsMeSessionsSessionId({
        admin,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
