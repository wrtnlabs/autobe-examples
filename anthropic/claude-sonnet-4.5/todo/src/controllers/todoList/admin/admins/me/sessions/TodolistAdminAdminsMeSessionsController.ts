import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { getTodoListAdminAdminsMeSessionsSessionId } from "../../../../../../providers/getTodoListAdminAdminsMeSessionsSessionId";
import { AdminAuth } from "../../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../../decorators/payload/AdminPayload";
import { deleteTodoListAdminAdminsMeSessionsSessionId } from "../../../../../../providers/deleteTodoListAdminAdminsMeSessionsSessionId";
import { deleteTodoListAdminAdminsMeSessions } from "../../../../../../providers/deleteTodoListAdminAdminsMeSessions";
import { postTodoListAdminAdminsMeSessionsRevokeAll } from "../../../../../../providers/postTodoListAdminAdminsMeSessionsRevokeAll";

import { ITodoListAdminSession } from "../../../../../../api/structures/ITodoListAdminSession";
import { ITodoListAdminSessionRevocationSummary } from "../../../../../../api/structures/ITodoListAdminSessionRevocationSummary";

@Controller("/todoList/admin/admins/me/sessions")
export class TodolistAdminAdminsMeSessionsController {
  /**
   * Retrieve complete information about a specific administrator session
   * identified by the session ID parameter. This operation provides detailed
   * session context for security monitoring and session management.
   *
   * The returned session information includes the IP address from which the
   * session was established, the connection URL and referrer that provide
   * context about how the admin authenticated, and timestamps tracking when the
   * session was created and when it expired (if applicable). Active sessions
   * will have a null expired_at value, while terminated sessions show when they
   * ended.
   *
   * This operation enables administrators to inspect their own session history
   * for security auditing purposes, helping them identify suspicious
   * authentication attempts or verify expected access patterns. Admins can view
   * both currently active sessions and historical expired sessions to maintain
   * awareness of their account activity.
   *
   * The operation is restricted to the authenticated administrator's own
   * sessions only. Admins cannot retrieve session information for other
   * administrator accounts. The session ID must belong to a session associated
   * with the authenticated admin's account, enforced through the
   * todo_list_admin_id foreign key relationship in the todo_list_admin_sessions
   * table.
   *
   * @param connection
   * @param sessionId Unique identifier of the target admin session
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<ITodoListAdminSession> {
    try {
      return await getTodoListAdminAdminsMeSessionsSessionId({
        admin,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Revoke a specific active administrator session identified by the session ID
   * parameter. This operation marks the session as expired by setting the
   * expired_at timestamp to the current time, which invalidates the associated
   * refresh token and prevents future token refresh attempts from that
   * session.
   *
   * This endpoint provides administrators with granular control over their
   * active sessions across multiple devices or browsers. When an admin realizes
   * they left a session active on a shared computer, forgot to log out from a
   * public terminal, or suspects a specific session may be compromised, they
   * can revoke that individual session without affecting their other active
   * sessions.
   *
   * The operation validates that the session being revoked actually belongs to
   * the authenticated admin making the request. Admins cannot revoke other
   * administrators' sessions through this endpoint - they can only manage their
   * own sessions. The session ID must be a valid UUID matching an existing
   * session in the todo_list_admin_sessions table.
   *
   * Upon successful revocation, the session's expired_at field is set to the
   * current timestamp, immediately invalidating the refresh token. Any
   * subsequent attempts to use that session's refresh token for obtaining new
   * access tokens will fail with authentication errors, forcing a full re-login
   * on that device.
   *
   * This operation returns an empty success response (204 No Content) upon
   * successful session revocation. It is part of the admin's session security
   * toolkit, complementing the logout-all-sessions functionality by allowing
   * selective session termination.
   *
   * @param connection
   * @param sessionId Unique identifier of the admin session to revoke
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":sessionId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoListAdminAdminsMeSessionsSessionId({
        admin,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Revoke all active administrator sessions for the currently authenticated
   * admin, implementing the "logout from all devices" functionality. This
   * operation marks all sessions belonging to the admin as expired by setting
   * the expired_at timestamp to the current time, which invalidates all
   * associated refresh tokens and forces re-authentication on every device.
   *
   * This endpoint serves critical security purposes including responding to
   * suspected account compromise, handling lost or stolen devices that were
   * logged in, enforcing security policy after administrative password changes,
   * and providing peace of mind when an admin is uncertain about their session
   * state across multiple devices.
   *
   * The operation queries the todo_list_admin_sessions table for all sessions
   * belonging to the authenticated admin (identified by the admin ID from the
   * JWT token) that have null expired_at values, indicating they are currently
   * active. All matching sessions are updated to set expired_at to the current
   * timestamp, effectively terminating them simultaneously.
   *
   * Upon successful execution, all of the admin's refresh tokens become
   * invalid. Any devices or browsers that had active admin sessions will be
   * unable to refresh their access tokens when they expire. Users on those
   * devices will be required to authenticate again with their email and
   * password to restore access to administrative functions.
   *
   * The system sends email notification to the admin's registered email address
   * confirming the security action, including the timestamp and originating IP
   * address of the revocation request. This notification helps detect
   * unauthorized revocation attempts and provides confirmation of intentional
   * security actions.
   *
   * This operation is distinct from single-session revocation and represents
   * the most aggressive session management action available to administrators.
   * It should be used when comprehensive session termination is required for
   * security purposes.
   *
   * @param connection
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async eraseAll(
    @AdminAuth()
    admin: AdminPayload,
  ): Promise<ITodoListAdminSessionRevocationSummary> {
    try {
      return await deleteTodoListAdminAdminsMeSessions({
        admin,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Revoke all active administrator sessions for the currently authenticated
   * admin, implementing the "logout from all devices" functionality. This
   * operation marks all sessions belonging to the admin as expired by setting
   * the expired_at timestamp to the current time, which invalidates all
   * associated refresh tokens and forces re-authentication on every device.
   *
   * This endpoint serves critical security purposes including responding to
   * suspected account compromise, handling lost or stolen devices that were
   * logged in, enforcing security policy after administrative password changes,
   * and providing peace of mind when an admin is uncertain about their session
   * state across multiple devices.
   *
   * The operation queries the todo_list_admin_sessions table for all sessions
   * belonging to the authenticated admin (identified by the admin ID from the
   * JWT token) that have null expired_at values, indicating they are currently
   * active. All matching sessions are updated to set expired_at to the current
   * timestamp, effectively terminating them simultaneously.
   *
   * Upon successful execution, all of the admin's refresh tokens become
   * invalid. Any devices or browsers that had active admin sessions will be
   * unable to refresh their access tokens when they expire. Users on those
   * devices will be required to authenticate again with their email and
   * password to restore access to administrative functions.
   *
   * The operation returns an empty success response (204 No Content) upon
   * successful completion. The system may send email notification to the
   * admin's registered email address confirming the security action, including
   * the timestamp and originating IP address of the revocation request.
   *
   * This operation is distinct from single-session revocation and represents
   * the most aggressive session management action available to administrators.
   * It should be used when comprehensive session termination is required for
   * security purposes.
   *
   * @param connection
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("revokeAll")
  public async revokeAll(
    @AdminAuth()
    admin: AdminPayload,
  ): Promise<void> {
    try {
      return await postTodoListAdminAdminsMeSessionsRevokeAll({
        admin,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
