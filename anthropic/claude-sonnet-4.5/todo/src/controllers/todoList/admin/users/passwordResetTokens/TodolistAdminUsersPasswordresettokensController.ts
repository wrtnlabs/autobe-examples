import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchTodoListAdminUsersUserIdPasswordResetTokens } from "../../../../../providers/patchTodoListAdminUsersUserIdPasswordResetTokens";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getTodoListAdminUsersUserIdPasswordResetTokensToken } from "../../../../../providers/getTodoListAdminUsersUserIdPasswordResetTokensToken";

import { IPageITodoListPasswordResetToken } from "../../../../../api/structures/IPageITodoListPasswordResetToken";
import { ITodoListPasswordResetToken } from "../../../../../api/structures/ITodoListPasswordResetToken";

@Controller("/todoList/admin/users/:userId/passwordResetTokens")
export class TodolistAdminUsersPasswordresettokensController {
  /**
   * List and search password reset tokens for a user using
   * todo_list_password_reset_tokens table.
   *
   * Retrieve all password reset tokens tied to a specific user for password
   * recovery in the Todo List application.
   *
   * This operation lets an authenticated user or an administrator list all
   * current and historical password reset tokens bound to their account. Use it
   * to audit issued tokens for security, such as checking for unused or expired
   * links. The request supports filtering by expiration state, usage (active or
   * used), and creation date to help track recent recovery attempts.
   *
   * The endpoint requires the user's unique account ID as a path parameter.
   * Only the account owner or authorized system actors may access this
   * information. Returned data includes secure token strings, issuance times,
   * intended expiration, and whether each token has been consumed. This
   * endpoint helps users manage account recovery history and supports security
   * auditing. It closely abides by schema descriptions, ensuring accurate field
   * exposure and access restrictions.
   *
   * @param connection
   * @param userId Unique identifier of the user to list tokens for.
   * @param body Token search and filtering parameters, such as status,
   *   creation/expiration dates, or pagination.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoListPasswordResetToken.IRequest,
  ): Promise<IPageITodoListPasswordResetToken.ISummary> {
    try {
      return await patchTodoListAdminUsersUserIdPasswordResetTokens({
        admin,
        userId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Get details for a specific user password reset token from
   * todo_list_password_reset_tokens table.
   *
   * Obtain complete information for a single issued password reset token
   * belonging to a user.
   *
   * By specifying the user's unique ID and the token string, callers retrieve
   * metadata for an individual credential reset attempt, including its creation
   * time, expiration, and any evidence of use. This endpoint is vital for
   * verifying the legitimacy and activity state of a password reset process,
   * supporting both user-driven and system-admin recovery flows.
   *
   * Successful execution requires both userId and token as path parameters,
   * reflecting their unique constraint. Access is limited to the account owner
   * or privileged administrative actors to protect account recovery flows. This
   * adheres strictly to the Prisma model structure for accurate and secure data
   * exposure.
   *
   * @param connection
   * @param userId Unique identifier of the user associated with the token.
   * @param token The unique password reset token string to look up.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":token")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedParam("token")
    token: string,
  ): Promise<ITodoListPasswordResetToken> {
    try {
      return await getTodoListAdminUsersUserIdPasswordResetTokensToken({
        admin,
        userId,
        token,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
