import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchTodoListAdminUsersUserIdSessions } from "../../../../../providers/patchTodoListAdminUsersUserIdSessions";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getTodoListAdminUsersUserIdSessionsSessionId } from "../../../../../providers/getTodoListAdminUsersUserIdSessionsSessionId";

import { IPageITodoListUserSession } from "../../../../../api/structures/IPageITodoListUserSession";
import { ITodoListUserSession } from "../../../../../api/structures/ITodoListUserSession";

@Controller("/todoList/admin/users/:userId/sessions")
export class TodolistAdminUsersSessionsController {
  /**
   * List and search all sessions for a specific user from
   * todo_list_user_sessions.
   *
   * Fetch a paginated, searchable history of all authenticated sessions
   * associated with a specific user account in the Todo List system. This
   * endpoint enables platform administrators to review login history, session
   * origination details, and session expiry information, drawing all data
   * directly from the todo_list_user_sessions table.
   *
   * Security and compliance requirements mandate a complete trace of session
   * metadata for each account, allowing audit and investigations if needed.
   * Results are sortable by date, filterable by criteria such as IP, referrer,
   * or session expiry, and include all fields necessary for security reviews.
   * This endpoint supports full administrative visibility but does not allow
   * session creation or deletion—operations here are strictly read-only for
   * audit purposes.
   *
   * The parent user is referenced by their UUID id field (matches
   * todo_list_users.id), ensuring all sessions returned are precisely scoped.
   * In case of invalid or nonexistent userId parameters, the API responds with
   * an appropriate error. Related operations: GET /users/{userId} for account
   * details, DELETE /users/{userId} for account removal.
   *
   * @param connection
   * @param userId UUID unique identifier of the parent user account (matches
   *   todo_list_users.id).
   * @param body Session filtering/search and pagination options for targeted
   *   lookup.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoListUserSession.IRequest,
  ): Promise<IPageITodoListUserSession.ISummary> {
    try {
      return await patchTodoListAdminUsersUserIdSessions({
        admin,
        userId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve details for a specific user session (todo_list_user_sessions
   * table) by user and session ID.
   *
   * Retrieve the detail of a specific authenticated user session, including
   * associated user, initiation metadata, and audit fields.
   *
   * Administrators may use this operation to investigate suspicious access
   * events, support user inquiries about session history, or perform policy
   * compliance reviews. Each session includes contextual data such as IP
   * address, URL origin, referrer, and timestamps for creation and expiry.
   * Session records are strictly linked to a user account by foreign key,
   * ensuring all data is traceable for audit purposes.
   *
   * Security is paramount: this endpoint is visible only to platform
   * administrators and is strictly read-only. No session management, renewal,
   * or invalidation is permitted via this interface. Sensitive information—such
   * as the session's IP and origins—are included to enable security event
   * traceability. Dependencies include administrative authentication and
   * privilege enforcement, as all access is recorded in audit trails for
   * compliance.
   *
   * @param connection
   * @param userId Unique identifier of the user account owning the session.
   * @param sessionId Unique identifier of the session record to retrieve.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<ITodoListUserSession> {
    try {
      return await getTodoListAdminUsersUserIdSessionsSessionId({
        admin,
        userId,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
