import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { getTodoListAdminUsersUserId } from "../../../../providers/getTodoListAdminUsersUserId";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { putTodoListAdminUsersUserId } from "../../../../providers/putTodoListAdminUsersUserId";
import { deleteTodoListAdminUsersUserId } from "../../../../providers/deleteTodoListAdminUsersUserId";
import { patchTodoListAdminUsers } from "../../../../providers/patchTodoListAdminUsers";

import { ITodoListUser } from "../../../../api/structures/ITodoListUser";
import { IPageITodoListUser } from "../../../../api/structures/IPageITodoListUser";

@Controller("/todoList/admin/users")
export class TodolistAdminUsersController {
  /**
   * Retrieve detailed information for a specific user account.
   *
   * Retrieve comprehensive details for a specific user account identified by
   * their unique user ID. This operation returns the complete user profile
   * including email, username, account status, verification state, and all
   * associated metadata.
   *
   * This endpoint provides access to full user account information necessary
   * for profile displays, account management interfaces, and administrative
   * oversight. The returned data includes authentication-related fields such as
   * email verification status and account creation timestamps.
   *
   * Security: This operation requires authentication. Users can retrieve their
   * own profile information, while administrators can access any user's
   * details. The authorization logic ensures users cannot access other users'
   * sensitive information without appropriate permissions. Rate limiting
   * applies to prevent enumeration attacks.
   *
   * The response structure corresponds directly to the todo_list_users table
   * schema, providing a complete representation of the user entity as stored in
   * the database.
   *
   * @param connection
   * @param userId Unique identifier of the target user account
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":userId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
  ): Promise<ITodoListUser> {
    try {
      return await getTodoListAdminUsersUserId({
        admin,
        userId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing user account's information.
   *
   * Update the modifiable fields of an existing user account identified by
   * their unique user ID. This operation allows changes to user profile
   * information such as email address, username, and password while maintaining
   * data integrity and security constraints.
   *
   * The update operation supports partial updates where only the fields
   * provided in the request body are modified. Unchanged fields retain their
   * existing values. Email updates may trigger re-verification workflows if the
   * system requires email confirmation. Password updates are securely hashed
   * before storage.
   *
   * Security: Users can update their own account information, while
   * administrators have the ability to modify any user account. The operation
   * includes ownership verification to ensure users cannot modify other users'
   * accounts without proper authorization. Password changes require additional
   * validation and may trigger security notifications.
   *
   * Validation ensures that updated email addresses are unique across the
   * system and that usernames meet the required format constraints. The
   * operation returns the updated user entity reflecting all applied changes,
   * allowing clients to synchronize their local state with the server.
   *
   * @param connection
   * @param userId Unique identifier of the target user account to update
   * @param body Updated user account information including optional email,
   *   username, and password fields
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":userId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoListUser.IUpdate,
  ): Promise<ITodoListUser> {
    try {
      return await putTodoListAdminUsersUserId({
        admin,
        userId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a user account and all associated data.
   *
   * Permanently remove a user account from the Todo List application database.
   *
   * This operation performs a hard delete that completely removes the user
   * record from the todo_list_users table along with all associated data. When
   * a user is deleted, the system automatically cascades the deletion to
   * related entities including all todo items created by the user, active
   * sessions, email verification records, and password reset tokens.
   *
   * This is an irreversible administrative operation intended for account
   * removal scenarios such as user requests for data deletion, compliance with
   * data protection regulations, or removal of inactive/fraudulent accounts.
   * The operation ensures complete data cleanup with no orphaned records
   * remaining in the system.
   *
   * Security: This operation requires administrative privileges and should only
   * be accessible to system administrators. Regular users cannot delete other
   * user accounts. The operation includes audit logging to track account
   * deletions for compliance and security purposes.
   *
   * @param connection
   * @param userId Unique identifier of the target user account to be
   *   permanently deleted
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":userId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
  ): Promise<ITodoListUser> {
    try {
      return await deleteTodoListAdminUsersUserId({
        admin,
        userId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve a filtered, paginated list of registered users.
   *
   * Retrieve a filtered and paginated list of registered user accounts from the
   * Todo list application. This operation provides advanced search capabilities
   * for finding users based on multiple criteria including partial username
   * matching, email domain filtering, registration date ranges, email
   * verification status, and account activity patterns.
   *
   * The operation supports comprehensive pagination with configurable page
   * sizes and sorting options. Users can be sorted by registration date, last
   * login, username, email verification status, or other relevant fields in
   * ascending or descending order. This enables efficient management and
   * analysis of the user base.
   *
   * Security considerations include authorization enforcement - this endpoint
   * is restricted to administrators who need to manage and monitor user
   * accounts. The operation includes appropriate filtering of sensitive user
   * information, ensuring that private data like password hashes are never
   * exposed in the response. Rate limiting applies to prevent abuse of user
   * data access.
   *
   * This operation integrates with the todo_list_users table as defined in the
   * Prisma schema, incorporating all available user fields and relationships.
   * The response includes user summary information optimized for administrative
   * list displays, providing essential account details while maintaining data
   * privacy standards.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for user filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: ITodoListUser.IRequest,
  ): Promise<IPageITodoListUser.ISummary> {
    try {
      return await patchTodoListAdminUsers({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
