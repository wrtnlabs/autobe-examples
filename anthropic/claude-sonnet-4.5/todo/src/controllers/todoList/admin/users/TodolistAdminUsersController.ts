import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { deleteTodoListAdminUsersUserId } from "../../../../providers/deleteTodoListAdminUsersUserId";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";

@Controller("/todoList/admin/users/:userId")
export class TodolistAdminUsersController {
  /**
   * Permanently delete a user from the todo_list_users table.
   *
   * Permanently erase a user account from the Todo List system, deleting their
   * credentials and all associated user data from the todo_list_users table.
   *
   * This operation must be performed only by authorized platform administrators
   * and has far-reaching effects: all active or historical sessions and
   * personal data become inaccessible once the operation completes. Security
   * and compliance considerations require this operation be logged and
   * restricted to privileged actors, as account deletion is both destructive
   * and irreversible. The record is fully removed with no recovery mechanism.
   *
   * This operation references the user by its UUID id field, ensuring exact
   * match in the database. All related child records (such as sessions and
   * audit logs) are handled per system policy on cascading deletes or
   * orphaning. If the specified user does not exist or is already deleted, the
   * operation will return a suitable error. Use with caution and only after
   * confirmation of intent.
   *
   * @param connection
   * @param userId UUID unique identifier of the user to be deleted (matches
   *   todo_list_users.id).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoListAdminUsersUserId({
        admin,
        userId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
