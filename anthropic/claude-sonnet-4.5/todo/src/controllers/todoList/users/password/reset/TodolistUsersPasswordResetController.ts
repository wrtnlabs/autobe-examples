import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postTodoListUsersPasswordReset } from "../../../../../providers/postTodoListUsersPasswordReset";

import { ITodoListUser } from "../../../../../api/structures/ITodoListUser";

@Controller("/todoList/users/password/reset")
export class TodolistUsersPasswordResetController {
  /**
   * Request password reset for user account via email.
   *
   * Initiates the password reset process for users who have forgotten their
   * passwords or need to reset them for security reasons. This operation
   * generates a unique, cryptographically secure reset token with a limited
   * expiration time (typically 1 hour) and sends it via email to the user's
   * registered email address.
   *
   * The operation implements security best practices by not revealing whether
   * the provided email address exists in the system. This prevents attackers
   * from using the password reset functionality to enumerate valid user
   * accounts. The system responds with a generic success message regardless of
   * whether the email exists, instructing the user to check their email for
   * reset instructions.
   *
   * When a valid email is found, the system generates a reset token that is
   * single-use, cryptographically random (at least 32 characters), and includes
   * an expiration timestamp. The reset link containing this token is sent to
   * the user's email. Any previously generated reset tokens for the same user
   * are invalidated to prevent token accumulation. The operation does not
   * require authentication since users who have forgotten their passwords
   * cannot log in.
   *
   * This operation relates to the todo_list_users table in the Prisma schema,
   * specifically the email and password_hash fields. It does not modify the
   * password_hash directly but creates the necessary token for the subsequent
   * password reset verification step.
   *
   * @param connection
   * @param body Email address for the account requiring password reset
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async requestReset(
    @TypedBody()
    body: ITodoListUser.IPasswordResetRequest,
  ): Promise<ITodoListUser.IPasswordResetResponse> {
    try {
      return await postTodoListUsersPasswordReset({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
