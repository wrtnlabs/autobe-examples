import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postTodoListUsersPasswordResetVerify } from "../../../../../../providers/postTodoListUsersPasswordResetVerify";

import { ITodoListUser } from "../../../../../../api/structures/ITodoListUser";

@Controller("/todoList/users/password/reset/verify")
export class TodolistUsersPasswordResetVerifyController {
  /**
   * Verify reset token and update user password.
   *
   * Completes the password reset process by validating the reset token and
   * updating the user's password to a new value. This operation is the second
   * step in the password reset workflow, following the initial reset request
   * that sends the token via email.
   *
   * The operation validates multiple security requirements before allowing the
   * password change. First, it verifies that the reset token is valid and
   * matches a pending reset request. Second, it checks that the token has not
   * expired (tokens typically expire after 1 hour to limit the window of
   * vulnerability). Third, it ensures the token has not been previously used,
   * as reset tokens are single-use only. If any of these validations fail, the
   * operation returns an appropriate error message.
   *
   * The new password must meet all security requirements defined in the
   * business rules: minimum 8 characters, containing at least one letter and
   * one number. The system validates the password strength before accepting it.
   * Once validated, the password is hashed using industry-standard algorithms
   * (bcrypt, argon2, or PBKDF2) before being stored in the password_hash field
   * of the todo_list_users table.
   *
   * For security purposes, when a password is successfully reset, the system
   * invalidates all existing refresh tokens and sessions
   * (todo_list_user_sessions records) for that user. This ensures that if the
   * account was compromised, the attacker's access is immediately revoked when
   * the legitimate user resets their password. The user must log in again with
   * the new password on all devices. A confirmation email is sent to the user's
   * email address to notify them that their password was changed.
   *
   * This operation does not require authentication since it is part of the
   * account recovery process. However, possession of the valid reset token
   * serves as proof of authorization.
   *
   * @param connection
   * @param body Reset token and new password for completing the password reset
   *   process
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async verifyReset(
    @TypedBody()
    body: ITodoListUser.IPasswordResetVerification,
  ): Promise<ITodoListUser.IPasswordResetConfirmation> {
    try {
      return await postTodoListUsersPasswordResetVerify({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
