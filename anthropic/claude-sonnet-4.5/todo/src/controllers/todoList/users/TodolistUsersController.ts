import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postTodoListUsersJoin } from "../../../providers/postTodoListUsersJoin";
import { postTodoListUsersLogin } from "../../../providers/postTodoListUsersLogin";

import { ITodoListUser } from "../../../api/structures/ITodoListUser";

@Controller("/todoList/users")
export class TodolistUsersController {
  /**
   * Register a new user account in the Todo list application by providing email
   * and password credentials.
   *
   * This operation creates a new user account in the todo_list_users table,
   * enabling users to authenticate and manage their personal todo lists. The
   * system enforces email uniqueness across all users and requires passwords to
   * meet minimum security requirements (at least 8 characters with letters and
   * numbers).
   *
   * The registration process validates the email format to ensure it follows
   * standard email conventions, checks that the email is not already registered
   * in the system to prevent duplicate accounts, validates the password meets
   * security requirements, and securely hashes the password using
   * industry-standard algorithms (bcrypt, argon2, or PBKDF2) before storage.
   *
   * Upon successful registration, the system creates a new user record with a
   * unique identifier, stores the email and hashed password, sets the
   * created_at and updated_at timestamps to the current time, and leaves
   * deleted_at as null to indicate an active account. The system then returns
   * confirmation of successful registration.
   *
   * Security considerations include never storing passwords in plain text,
   * using secure hashing with unique salts, preventing email enumeration
   * attacks by not revealing whether emails exist, and enforcing password
   * complexity requirements to ensure account security.
   *
   * @param connection
   * @param body User registration information including email and password
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @TypedBody()
    body: ITodoListUser.ICreate,
  ): Promise<ITodoListUser> {
    try {
      return await postTodoListUsersJoin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate user and create session.
   *
   * Authenticate a user with email and password credentials to establish a
   * session and obtain access tokens.
   *
   * This operation validates user login credentials by checking the provided
   * email exists in the todo_list_users table, verifying the password matches
   * the stored password_hash using secure comparison methods, and ensuring the
   * account is active (deleted_at is null). The system uses constant-time
   * comparison to prevent timing attacks during password verification.
   *
   * Upon successful authentication, the system generates a JWT access token
   * with 15-30 minute expiration containing the user ID, email, and role,
   * generates a JWT refresh token with 7-30 day expiration for obtaining new
   * access tokens, creates a new session record in the todo_list_user_sessions
   * table with the user's IP address, connection URL, referrer, and current
   * timestamp, and returns both tokens along with user profile information.
   *
   * Security considerations include using generic error messages that do not
   * specify whether the email or password was incorrect to prevent account
   * enumeration, implementing rate limiting to prevent brute-force attacks
   * (delays after 5 failed attempts, temporary lockout after 15 failed
   * attempts), logging failed authentication attempts for security monitoring,
   * and signing JWT tokens with a strong secret key to prevent tampering.
   *
   * The response includes the access token for immediate API request
   * authentication, refresh token for obtaining new access tokens when the
   * access token expires, and user profile information including user ID,
   * email, and role for client-side application state.
   *
   * @param connection
   * @param body User login credentials with email and password
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @TypedBody()
    body: ITodoListUser.ILogin,
  ): Promise<ITodoListUser.IAuthorization> {
    try {
      return await postTodoListUsersLogin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
