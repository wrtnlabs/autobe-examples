import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { getTodoListUsersUserId } from "../../../providers/getTodoListUsersUserId";
import { putTodoListUsersUserId } from "../../../providers/putTodoListUsersUserId";

import { ITodoListUser } from "../../../api/structures/ITodoListUser";

@Controller("/todoList/users/:userId")
export class TodolistUsersController {
  /**
   * Retrieve a user account from the todo_list_users table by its unique
   * identifier.
   *
   * Fetch a registered user's account details by their unique identifier. The
   * response includes account-level information such as the user's email,
   * account creation and update timestamps, and disabled status, as defined in
   * the Prisma schema.
   *
   * Sensitive fields such as the password hash are never returned, in
   * compliance with best security practices. Only system administrators or the
   * user themselves (authorization not shown here) will be able to access this
   * endpoint to ensure privacy and data protection.
   *
   * Proper error handling ensures requests for non-existent users or
   * missing/invalid identifiers return a clear error response. This operation
   * is essential for user profile management use cases.
   *
   * @param connection
   * @param userId Unique identifier of the target user account (UUID format).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
  ): Promise<ITodoListUser> {
    try {
      return await getTodoListUsersUserId({
        userId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update a user account in the todo_list_users table by its unique
   * identifier.
   *
   * Update the non-sensitive attributes of a registered user, such as the email
   * address, and administratively-controlled account status fields.
   *
   * Input validation ensures the update payload conforms to schema for email
   * (globally unique), and that system-reserved fields like password_hash
   * cannot be changed via this endpoint. All successful updates are recorded
   * with timestamp, and unsuccessful operations (such as attempts to use a
   * duplicate email) will result in explicit error responses.
   *
   * For security, this operation should be restricted to the user themselves or
   * system administrators (authorization not specified here, left for
   * integration with external system management).
   *
   * @param connection
   * @param userId Unique identifier of the target user account (UUID format).
   * @param body Payload to update user account properties, such as new email or
   *   administrative disabled status.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoListUser.IUpdate,
  ): Promise<ITodoListUser> {
    try {
      return await putTodoListUsersUserId({
        userId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
