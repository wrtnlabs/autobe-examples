import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postTodoListUserCategories } from "../../../../providers/postTodoListUserCategories";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { patchTodoListUserCategories } from "../../../../providers/patchTodoListUserCategories";
import { getTodoListUserCategoriesCategoryId } from "../../../../providers/getTodoListUserCategoriesCategoryId";
import { putTodoListUserCategoriesCategoryId } from "../../../../providers/putTodoListUserCategoriesCategoryId";
import { deleteTodoListUserCategoriesCategoryId } from "../../../../providers/deleteTodoListUserCategoriesCategoryId";

import { ITodoListCategory } from "../../../../api/structures/ITodoListCategory";
import { IPageITodoListCategory } from "../../../../api/structures/IPageITodoListCategory";

@Controller("/todoList/user/categories")
export class TodolistUserCategoriesController {
  /**
   * Create a new category for organizing todo items.
   *
   * Create a new category to help organize and group related todo items.
   * Categories are optional organizational structures that allow users to
   * classify todos into named groups such as Work, Personal, Shopping, or
   * Health.
   *
   * The category name is required and must be unique per user. The system
   * validates that the authenticated user does not already have a category with
   * the same name, preventing duplicate categories that could cause confusion.
   * Category names are limited to 50 characters maximum.
   *
   * The owner user ID is automatically determined from the JWT authentication
   * token, ensuring that categories are properly associated with the creating
   * user and maintaining complete data isolation between users. Creation and
   * update timestamps are automatically set by the system.
   *
   * Categories are entirely optional for todo management. Users can create
   * todos without assigning categories, and can add categorization later as
   * their organizational needs evolve. The normalized category structure
   * supports future enhancements such as category sharing, hierarchical
   * categories, or system default categories without requiring schema
   * modifications.
   *
   * Security: Authentication is required. The authenticated user automatically
   * becomes the category owner. Category name uniqueness is validated within
   * the user's own category list, not globally across all users.
   *
   * Related operations: After creating a category, users typically assign it to
   * todo items during todo creation (POST /todos) or update existing todos to
   * use the new category (PUT /todos/{todoId}).
   *
   * @param connection
   * @param body Category creation data including the category name
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoListCategory.ICreate,
  ): Promise<ITodoListCategory> {
    try {
      return await postTodoListUserCategories({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve filtered, paginated categories from the
   * todo_list_categories table.
   *
   * Retrieve a filtered and paginated list of categories owned by the
   * authenticated user.
   *
   * This operation provides comprehensive search and filtering capabilities for
   * categories stored in the todo_list_categories table. Users can search
   * categories by name using text matching, apply sorting preferences, and
   * configure pagination parameters to efficiently browse large category
   * collections. The response includes pagination metadata along with the
   * matching category data.
   *
   * The operation enforces strict user isolation - only categories belonging to
   * the authenticated user (matched via todo_list_user_id foreign key) are
   * returned in search results. Categories owned by other users are never
   * included in the response, maintaining complete data privacy and isolation
   * between users. This isolation is enforced at the database query level using
   * automatic filtering by user ownership.
   *
   * Authentication is required for this operation. Unauthenticated requests are
   * rejected with HTTP 401 Unauthorized. The authenticated user's identity is
   * extracted from the JWT token and automatically applied as a filter to all
   * category queries, ensuring users can only access their own categories.
   *
   * The request body supports multiple search and filtering options including
   * name-based text search, creation date filtering, and sorting preferences.
   * Pagination parameters allow clients to request specific page sizes and page
   * numbers to efficiently load large category lists. The response follows the
   * standard paginated collection format with pagination metadata and the array
   * of matching category objects.
   *
   * This operation is essential for category management workflows including
   * displaying category lists in user interfaces, implementing category
   * selection dropdowns for todo assignment, and providing category browsing
   * and organization features. The flexible filtering and sorting options
   * support various user interface patterns and use cases.
   *
   * @param connection
   * @param body Search criteria, filtering options, and pagination parameters
   *   for category retrieval
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoListCategory.IRequest,
  ): Promise<IPageITodoListCategory.ISummary> {
    try {
      return await patchTodoListUserCategories({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific todo category by ID.
   *
   * Retrieve complete details of a single category identified by its unique ID.
   * This operation returns all category information including the category
   * name, creation timestamp, last update timestamp, and owner user reference.
   *
   * Categories provide optional organizational structure for grouping related
   * todo items. Each category belongs to a specific user and maintains complete
   * data isolation, ensuring users can only access their own categories.
   *
   * The category ID must be a valid UUID corresponding to an existing category
   * in the system. The operation validates that the requesting user has
   * permission to access the specified category, enforcing the application's
   * data isolation security model.
   *
   * This operation is typically used when displaying category details for
   * editing, or when showing category metadata in the user interface. It
   * provides the foundation for category update operations by first retrieving
   * current category state.
   *
   * Security: Authentication is required. Users can only retrieve categories
   * they own. The system validates ownership and returns appropriate
   * authorization errors if the category belongs to a different user or does
   * not exist.
   *
   * @param connection
   * @param categoryId Unique identifier of the target category to retrieve
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":categoryId")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("categoryId")
    categoryId: string & tags.Format<"uuid">,
  ): Promise<ITodoListCategory> {
    try {
      return await getTodoListUserCategoriesCategoryId({
        user,
        categoryId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing category's properties.
   *
   * Update an existing category in the Todo list application with new property
   * values. This operation allows authenticated users to modify their category
   * information including the category name, description, visual attributes
   * (color and icon), and display order.
   *
   * The operation validates that the category exists and belongs to the
   * authenticated user before allowing modifications. Users can update any
   * combination of the category's editable fields. The name field has
   * validation constraints including minimum/maximum length requirements and
   * must remain unique within the user's category collection.
   *
   * Security considerations include ownership verification to ensure users can
   * only modify their own categories. The operation automatically updates the
   * updated_at timestamp to track modification history. Rate limiting may apply
   * to prevent abuse of the update functionality.
   *
   * This operation integrates with the todo_list_categories table as defined in
   * the Prisma schema. The response returns the complete updated category
   * object with all current field values, allowing clients to refresh their
   * local state with the authoritative server data.
   *
   * @param connection
   * @param categoryId Unique identifier of the target category to update
   * @param body Updated category properties including name, description, color,
   *   icon, and sort order
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":categoryId")
  public async update(
    @UserAuth()
    user: UserPayload,
    @TypedParam("categoryId")
    categoryId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoListCategory.IUpdate,
  ): Promise<ITodoListCategory> {
    try {
      return await putTodoListUserCategoriesCategoryId({
        user,
        categoryId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a category from the system.
   *
   * Permanently delete a category from the Todo list application. This
   * operation performs a hard delete that completely removes the category
   * record from the database without possibility of recovery.
   *
   * The operation validates that the category exists and belongs to the
   * authenticated user before allowing deletion. Security measures include
   * ownership verification to ensure users can only delete their own
   * categories. The system checks for any todos currently associated with this
   * category and handles them according to business rules (either preventing
   * deletion or reassigning todos to a default category).
   *
   * This is a destructive operation that cannot be undone. Once a category is
   * deleted, all its data is permanently removed from the system. Clients
   * should implement appropriate confirmation dialogs before calling this
   * endpoint to prevent accidental data loss.
   *
   * The operation integrates with the todo_list_categories table as defined in
   * the Prisma schema. Upon successful deletion, the operation returns the
   * deleted category object as confirmation of what was removed, allowing
   * clients to update their local state and provide user feedback.
   *
   * @param connection
   * @param categoryId Unique identifier of the target category to permanently
   *   delete
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":categoryId")
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("categoryId")
    categoryId: string & tags.Format<"uuid">,
  ): Promise<ITodoListCategory> {
    try {
      return await deleteTodoListUserCategoriesCategoryId({
        user,
        categoryId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
