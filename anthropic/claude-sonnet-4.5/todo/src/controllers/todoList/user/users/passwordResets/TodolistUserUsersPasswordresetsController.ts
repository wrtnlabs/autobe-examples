import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchTodoListUserUsersUserIdPasswordResets } from "../../../../../providers/patchTodoListUserUsersUserIdPasswordResets";
import { UserAuth } from "../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../decorators/payload/UserPayload";
import { getTodoListUserUsersUserIdPasswordResetsResetId } from "../../../../../providers/getTodoListUserUsersUserIdPasswordResetsResetId";

import { IPageITodoListPasswordReset } from "../../../../../api/structures/IPageITodoListPasswordReset";
import { ITodoListPasswordReset } from "../../../../../api/structures/ITodoListPasswordReset";

@Controller("/todoList/user/users/:userId/passwordResets")
export class TodolistUserUsersPasswordresetsController {
  /**
   * Search and retrieve password reset requests for a user.
   *
   * Search and retrieve password reset requests associated with a specific user
   * account in the Todo list application.
   *
   * This operation provides the ability to query password reset requests for a
   * given user, supporting filtering and pagination. It is primarily used for
   * administrative purposes to track password reset activities and for users to
   * check the status of their reset requests.
   *
   * Security considerations: This endpoint requires appropriate authorization
   * to prevent unauthorized access to password reset information. The operation
   * includes rate limiting to prevent abuse and enumeration attacks. Only the
   * user themselves or administrators should be able to access password reset
   * request information.
   *
   * The response includes password reset request details such as token status,
   * expiration time, and creation timestamp. Sensitive information like the
   * actual reset token is excluded from the response for security purposes.
   *
   * This operation integrates with the todo_list_password_resets table as
   * defined in the Prisma schema, incorporating all relevant fields for
   * password reset tracking and management.
   *
   * @param connection
   * @param userId Unique identifier of the target user account (global scope)
   * @param body Search criteria and pagination parameters for filtering
   *   password reset requests
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoListPasswordReset.IRequest,
  ): Promise<IPageITodoListPasswordReset.ISummary> {
    try {
      return await patchTodoListUserUsersUserIdPasswordResets({
        user,
        userId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific password reset request.
   *
   * Retrieve complete details of a specific password reset request for a user
   * account in the Todo list application.
   *
   * This operation returns comprehensive information about a password reset
   * request identified by its unique ID. It is used to verify the validity of
   * reset tokens, check expiration status, and retrieve metadata about the
   * reset request.
   *
   * Security considerations: Access to password reset details must be strictly
   * controlled. Only the user who initiated the reset or system administrators
   * should be able to retrieve this information. The endpoint implements
   * authorization checks to ensure users can only access their own password
   * reset requests unless they have administrative privileges.
   *
   * The response includes all relevant password reset information such as
   * creation timestamp, expiration time, usage status, and associated user
   * information. The actual reset token value may be excluded or masked in the
   * response depending on the security policy.
   *
   * This operation integrates with the todo_list_password_resets table as
   * defined in the Prisma schema, returning a complete password reset record
   * with all available fields and relationships.
   *
   * @param connection
   * @param userId Unique identifier of the target user account (global scope)
   * @param resetId Unique identifier of the target password reset request
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":resetId")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedParam("resetId")
    resetId: string & tags.Format<"uuid">,
  ): Promise<ITodoListPasswordReset> {
    try {
      return await getTodoListUserUsersUserIdPasswordResetsResetId({
        user,
        userId,
        resetId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
