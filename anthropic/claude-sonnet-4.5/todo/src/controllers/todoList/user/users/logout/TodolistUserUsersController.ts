import { Controller } from "@nestjs/common";
import { TypedRoute } from "@nestia/core";
import typia from "typia";
import { postTodoListUserUsersLogout } from "../../../../../providers/postTodoListUserUsersLogout";
import { UserAuth } from "../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../decorators/payload/UserPayload";

@Controller("/todoList/user/users/logout")
export class TodolistUserUsersController {
  /**
   * Log out the authenticated user from their current session.
   *
   * This operation terminates the authenticated user's current session by
   * invalidating their refresh token and marking the session as expired in the
   * todo_list_user_sessions table. When a user logs out, the system sets the
   * expired_at timestamp to the current time for the active session, preventing
   * further use of the associated refresh token.
   *
   * The logout process ensures that the user's authentication state is properly
   * terminated, requiring them to log in again to access protected resources.
   * The access token will remain technically valid until its expiration (due to
   * stateless JWT design), but the client application should immediately
   * discard both access and refresh tokens upon receiving logout confirmation.
   *
   * This operation provides security benefits by allowing users to explicitly
   * end their sessions, particularly important when using shared or public
   * computers. The system records the logout event by updating the session
   * record in the todo_list_user_sessions table with the expired_at timestamp,
   * maintaining an audit trail of session lifecycle events.
   *
   * The operation only affects the current session associated with the user's
   * current device or browser. Other active sessions on different devices
   * remain valid unless the user chooses to log out from all devices using the
   * separate global logout operation.
   *
   * @param connection
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async logout(
    @UserAuth()
    user: UserPayload,
  ): Promise<void> {
    try {
      return await postTodoListUserUsersLogout({
        user,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
