import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { putTodoListUserUsersMePassword } from "../../../../../../providers/putTodoListUserUsersMePassword";
import { UserAuth } from "../../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../../decorators/payload/UserPayload";

import { ITodoListUser } from "../../../../../../api/structures/ITodoListUser";

@Controller("/todoList/user/users/me/password")
export class TodolistUserUsersMePasswordController {
  /**
   * Update authenticated user's password.
   *
   * Change the password for the currently authenticated user account. This
   * operation provides secure password management capabilities allowing users
   * to update their credentials for security maintenance.
   *
   * The operation requires the user to provide their current password for
   * identity verification before allowing the password change. This security
   * measure prevents unauthorized password changes if a user's session is
   * compromised. The new password must meet all password complexity
   * requirements including minimum length, character type diversity, and
   * strength validation.
   *
   * When a password is successfully changed, the system updates the
   * password_hash field in the todo_list_users table with the new securely
   * hashed password. The operation then invalidates all existing refresh tokens
   * for that user by updating the expired_at field in todo_list_user_sessions
   * records, effectively logging the user out from all devices except the
   * current session. This security measure ensures that if a password was
   * changed due to suspected compromise, all potentially compromised sessions
   * are terminated.
   *
   * The operation follows the password security requirements defined in the
   * system specification, including using industry-standard password hashing
   * algorithms with appropriate computational cost factors. Password validation
   * enforces minimum 8 characters, at least one uppercase letter, one lowercase
   * letter, one digit, and one special character from the allowed set.
   *
   * This operation references the todo_list_users.password_hash field for
   * storage and the todo_list_user_sessions table for session revocation.
   * Related operations include user login and session management endpoints.
   *
   * @param connection
   * @param body Current and new password information for password change
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async updatePassword(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoListUser.IChangePassword,
  ): Promise<ITodoListUser.IPasswordChanged> {
    try {
      return await putTodoListUserUsersMePassword({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
