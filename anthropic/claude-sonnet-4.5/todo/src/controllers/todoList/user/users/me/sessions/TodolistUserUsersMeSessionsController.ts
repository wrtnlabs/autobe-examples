import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { getTodoListUserUsersMeSessionsSessionId } from "../../../../../../providers/getTodoListUserUsersMeSessionsSessionId";
import { UserAuth } from "../../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../../decorators/payload/UserPayload";
import { deleteTodoListUserUsersMeSessionsSessionId } from "../../../../../../providers/deleteTodoListUserUsersMeSessionsSessionId";
import { deleteTodoListUserUsersMeSessions } from "../../../../../../providers/deleteTodoListUserUsersMeSessions";

import { ITodoListUserSession } from "../../../../../../api/structures/ITodoListUserSession";

@Controller("/todoList/user/users/me/sessions")
export class TodolistUserUsersMeSessionsController {
  /**
   * Fetch detailed information about a specific authentication session for the
   * currently authenticated user. This operation enables users to view session
   * metadata and connection context for security monitoring and session
   * management purposes.
   *
   * The operation retrieves a single session record from the
   * todo_list_user_sessions table identified by the session ID path parameter.
   * The system verifies that the requested session belongs to the authenticated
   * user before returning data, ensuring users can only access their own
   * session information and maintaining strict data isolation.
   *
   * The returned session details include the IP address from which the session
   * was established, the connection URL (href) and referrer that provide
   * context about the application entry point, the session creation timestamp,
   * and the expiration timestamp if the session has ended. Active sessions have
   * a null expired_at value, while terminated sessions show when they were
   * ended through logout, token expiration, or security-related revocation.
   *
   * This operation supports user awareness of their active sessions across
   * different devices and browsers. Users can review session details to
   * identify unfamiliar sessions that might indicate unauthorized access, check
   * when sessions were created, and understand the connection context for
   * security purposes.
   *
   * Session information is critical for security auditing and helps users
   * maintain control over their account access. The operation references
   * todo_list_user_sessions fields including ip, href, referrer, created_at,
   * and expired_at to provide complete session visibility.
   *
   * Related operations include listing all user sessions, session revocation
   * (logout), and logout from all devices functionality.
   *
   * @param connection
   * @param sessionId Unique identifier of the target session to retrieve
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<ITodoListUserSession> {
    try {
      return await getTodoListUserUsersMeSessionsSessionId({
        user,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Terminates a specific authenticated session for the currently logged-in
   * user by setting the session's expired_at timestamp. This operation enables
   * users to log out from individual devices or browsers while keeping other
   * sessions active.
   *
   * The session identified by sessionId must belong to the authenticated user
   * making the request. The system validates ownership before allowing
   * termination to prevent users from ending other users' sessions. Upon
   * successful termination, the JWT refresh token associated with this session
   * becomes invalid and cannot be used to obtain new access tokens.
   *
   * This operation is essential for security workflows such as logging out from
   * a specific device, revoking access from a lost or stolen device, or
   * managing active sessions across multiple browsers. Users typically access
   * this through a "devices" or "active sessions" management interface where
   * they can view and terminate individual sessions.
   *
   * The session record remains in the database with expired_at set to the
   * current timestamp for audit trail purposes. Connection context (IP address,
   * URL, referrer) is preserved to support security investigations and user
   * activity tracking. The operation returns the terminated session details to
   * confirm successful logout.
   *
   * @param connection
   * @param sessionId Unique identifier of the session to terminate
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":sessionId")
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<ITodoListUserSession> {
    try {
      return await deleteTodoListUserUsersMeSessionsSessionId({
        user,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Terminates all active authenticated sessions for the currently logged-in
   * user by setting expired_at timestamps on all session records. This
   * operation implements the critical security feature of logging out from all
   * devices simultaneously.
   *
   * This bulk session termination is essential for security scenarios including
   * password changes, suspected account compromise, or user-initiated security
   * actions to revoke access from all devices. When executed, all JWT refresh
   * tokens associated with the user become immediately invalid, forcing
   * re-authentication on all devices to regain access.
   *
   * The operation affects only sessions belonging to the authenticated user
   * making the request. All session records remain in the database with
   * expired_at set to the current timestamp for comprehensive audit trails.
   * This preserves security-relevant connection information (IP addresses,
   * URLs, referrers) for forensic analysis if needed.
   *
   * Typical use cases include the user clicking 'logout from all devices' in
   * security settings, automatic execution following password changes, or
   * administrative security actions responding to potential account compromise.
   * The operation returns confirmation of how many sessions were terminated.
   *
   * After this operation completes, the user must re-authenticate on all
   * devices to establish new sessions and obtain fresh JWT tokens. This ensures
   * complete session revocation and forces verification of current credentials
   * across all access points.
   *
   * @param connection
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async eraseAll(
    @UserAuth()
    user: UserPayload,
  ): Promise<void> {
    try {
      return await deleteTodoListUserUsersMeSessions({
        user,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
