import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { getTodoListUserUsersMe } from "../../../../../providers/getTodoListUserUsersMe";
import { UserAuth } from "../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../decorators/payload/UserPayload";
import { putTodoListUserUsersMe } from "../../../../../providers/putTodoListUserUsersMe";
import { deleteTodoListUserUsersMe } from "../../../../../providers/deleteTodoListUserUsersMe";

import { ITodoListUser } from "../../../../../api/structures/ITodoListUser";

@Controller("/todoList/user/users/me")
export class TodolistUserUsersMeController {
  /**
   * Retrieve the authenticated user's profile information.
   *
   * Retrieve complete profile information for the currently authenticated user
   * from the todo_list_users table. This operation provides users with access
   * to their own account details, enabling them to review their registered
   * email address, account creation timestamp, and last modification
   * timestamp.
   *
   * The operation extracts the user identity from the JWT authentication token
   * provided in the request, ensuring that users can only access their own
   * profile information. This enforces strict data privacy and isolation
   * between different user accounts.
   *
   * This endpoint is essential for user account management workflows, allowing
   * users to verify their account information before making updates. It serves
   * as the foundation for profile management features and provides transparency
   * about what data the system stores for each user.
   *
   * Security considerations include requiring valid JWT authentication,
   * validating token signatures and expiration, and ensuring the user account
   * is active and not soft-deleted. The response excludes sensitive information
   * such as password hashes, which are never exposed through any API endpoint.
   *
   * Related operations include PUT /users/me for updating profile information.
   * This GET operation is typically called when users access their profile
   * settings or account management interface.
   *
   * @param connection
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @UserAuth()
    user: UserPayload,
  ): Promise<ITodoListUser> {
    try {
      return await getTodoListUserUsersMe({
        user,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update the authenticated user's profile information.
   *
   * Update profile information for the currently authenticated user in the
   * todo_list_users table. This operation enables users to modify their account
   * details, primarily the email address, while maintaining data integrity and
   * security constraints.
   *
   * The operation extracts the user identity from the JWT authentication token
   * to determine which user account to update, ensuring users can only modify
   * their own profile information. This strict authorization boundary prevents
   * unauthorized access to other users' accounts.
   *
   * When updating the email address, the system validates the new email follows
   * proper format conventions and is not already registered to another user
   * account. The email uniqueness constraint in the Prisma schema
   * (@@unique([email])) ensures no duplicate email addresses exist across the
   * system. If the provided email already exists, the operation fails with a
   * validation error.
   *
   * The system automatically updates the updated_at timestamp to the current
   * time whenever profile information is modified, maintaining an accurate
   * audit trail of account changes. The created_at timestamp remains immutable,
   * preserving the original account creation date.
   *
   * Security considerations include requiring valid JWT authentication,
   * validating all input data before persistence, preventing modification of
   * system-generated fields (id, created_at, password_hash through this
   * endpoint), and ensuring the user account is active and not soft-deleted.
   *
   * Password changes are intentionally excluded from this operation to enforce
   * separate, more secure password change workflows that require current
   * password verification. Users should use dedicated password management
   * endpoints for credential updates.
   *
   * Related operations include GET /users/me for viewing current profile
   * information before making updates. This PUT operation is typically called
   * when users modify their account settings or update their registered email
   * address.
   *
   * @param connection
   * @param body Updated profile information including the new email address and
   *   other modifiable account fields
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoListUser.IUpdate,
  ): Promise<ITodoListUser> {
    try {
      return await putTodoListUserUsersMe({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete the authenticated user's account and all associated todo items.
   *
   * Permanently delete the authenticated user's account and all associated data
   * from the Todo list application. This operation provides users with complete
   * control over their data and enables them to remove their presence from the
   * system entirely.
   *
   * When a user deletes their account, the system performs a cascade deletion
   * that removes all data associated with that user account. This includes the
   * user account record itself from the todo_list_users table, all todo items
   * owned by the user from the todo_list_todos table (due to the onDelete:
   * Cascade relationship), and all session records from the
   * todo_list_user_sessions table. The deletion is atomic - either all
   * associated data is removed successfully, or the operation fails and no data
   * is deleted.
   *
   * This operation implements hard delete functionality. The Prisma schema
   * includes a deleted_at field in the todo_list_users table for soft delete
   * capability, but this operation performs permanent deletion by completely
   * removing the user record from the database. This ensures that the user's
   * email address becomes immediately available for re-registration and that no
   * personal data remains in the system.
   *
   * Security considerations are paramount for this operation. The system
   * verifies that the authenticated user is deleting their own account by
   * extracting the user ID from the JWT token and ensuring it matches the
   * account being deleted. Users cannot delete other users' accounts. After
   * successful deletion, all active session tokens for that user are
   * invalidated, preventing any further access using old tokens.
   *
   * This operation aligns with data privacy best practices and user data
   * control requirements. Users have the right to remove their data from the
   * system, and this operation fulfills that requirement. The frontend
   * application should implement a confirmation dialog to prevent accidental
   * account deletions, but the backend executes the deletion immediately upon
   * receiving a valid authenticated request.
   *
   * Error scenarios include authentication failures (user not logged in),
   * authorization failures (though users can only delete their own accounts),
   * and database errors during the deletion process. The system provides clear
   * error messages for each scenario while maintaining security by not exposing
   * internal system details.
   *
   * @param connection
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @UserAuth()
    user: UserPayload,
  ): Promise<void> {
    try {
      return await deleteTodoListUserUsersMe({
        user,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
