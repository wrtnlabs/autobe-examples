import { Controller } from "@nestjs/common";
import { TypedRoute } from "@nestia/core";
import typia from "typia";
import { postTodoListUserUsersLogoutAll } from "../../../../../../providers/postTodoListUserUsersLogoutAll";
import { UserAuth } from "../../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../../decorators/payload/UserPayload";

@Controller("/todoList/user/users/logout/all")
export class TodolistUserUsers_logoutAllController {
  /**
   * Log out the authenticated user from all active sessions across all devices.
   *
   * This operation terminates all of the authenticated user's active sessions
   * by invalidating all refresh tokens and marking all sessions as expired in
   * the todo_list_user_sessions table. When a user performs a global logout,
   * the system sets the expired_at timestamp to the current time for all
   * sessions associated with their todo_list_user_id, effectively revoking
   * access from all devices and browsers where they were previously logged in.
   *
   * This global logout functionality is critical for security scenarios where
   * users suspect their account may have been compromised, want to ensure
   * they're logged out from a lost or stolen device, or need to force
   * re-authentication across all access points after a password change. The
   * operation provides users with complete control over their authentication
   * state across the entire system.
   *
   * All active sessions in the todo_list_user_sessions table belonging to the
   * authenticated user will be updated with the current timestamp in the
   * expired_at column, preventing any further use of associated refresh tokens.
   * This forces re-login on all devices, ensuring that only the user with
   * current valid credentials can regain access.
   *
   * The system maintains a complete audit trail by preserving all session
   * records with their creation timestamps (created_at) and expiration
   * timestamps (expired_at), allowing administrators to track security-related
   * events while respecting user privacy. After global logout, the user must
   * authenticate again on all devices to obtain new valid session tokens.
   *
   * @param connection
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async logoutAll(
    @UserAuth()
    user: UserPayload,
  ): Promise<void> {
    try {
      return await postTodoListUserUsersLogoutAll({
        user,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
