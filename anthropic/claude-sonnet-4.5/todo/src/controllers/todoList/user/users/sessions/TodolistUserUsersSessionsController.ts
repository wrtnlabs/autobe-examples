import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchTodoListUserUsersUserIdSessions } from "../../../../../providers/patchTodoListUserUsersUserIdSessions";
import { UserAuth } from "../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../decorators/payload/UserPayload";
import { getTodoListUserUsersUserIdSessionsSessionId } from "../../../../../providers/getTodoListUserUsersUserIdSessionsSessionId";
import { deleteTodoListUserUsersUserIdSessionsSessionId } from "../../../../../providers/deleteTodoListUserUsersUserIdSessionsSessionId";

import { IPageITodoListUserSession } from "../../../../../api/structures/IPageITodoListUserSession";
import { ITodoListUserSession } from "../../../../../api/structures/ITodoListUserSession";

@Controller("/todoList/user/users/:userId/sessions")
export class TodolistUserUsersSessionsController {
  /**
   * Retrieve filtered list of active sessions for a specific user.
   *
   * Retrieve a filtered and paginated list of active authentication sessions
   * for a specific user account.
   *
   * This operation provides comprehensive session management capabilities
   * allowing users to view all their active login sessions across different
   * devices and locations. The search supports filtering by session creation
   * date, last activity timestamp, IP address, user agent, and session status.
   * This enables users to identify and monitor all devices where they are
   * currently logged in.
   *
   * The operation returns paginated results with session summary information
   * including device type, browser, location (derived from IP), creation time,
   * and last activity time. Users can sort sessions by most recent activity,
   * creation date, or other relevant criteria to easily identify suspicious or
   * outdated sessions.
   *
   * Security considerations include ensuring users can only view their own
   * sessions unless they have administrative privileges. Administrators can
   * view sessions for any user for security monitoring and support purposes.
   * The operation supports rate limiting to prevent session enumeration
   * attacks.
   *
   * This integrates with the todo_list_user_sessions table as defined in the
   * Prisma schema, providing access to session tracking and management
   * functionality. The response includes session summary data optimized for
   * security monitoring displays.
   *
   * @param connection
   * @param userId Unique identifier of the user whose sessions are being
   *   queried
   * @param body Search criteria and pagination parameters for filtering user
   *   sessions
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoListUserSession.IRequest,
  ): Promise<IPageITodoListUserSession.ISummary> {
    try {
      return await patchTodoListUserUsersUserIdSessions({
        user,
        userId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific user authentication session.
   *
   * Retrieve complete details of a specific authentication session for a given
   * user in the Todo list application.
   *
   * This operation returns comprehensive session information including the
   * session ID, authentication token, creation timestamp, expiration timestamp,
   * and associated user details. It is essential for session validation,
   * administrative monitoring, and debugging authentication issues.
   *
   * Security considerations: This endpoint requires appropriate authorization
   * to prevent unauthorized access to sensitive session data. Session tokens
   * are sensitive credentials that must be protected. Only administrators or
   * the session owner should be able to access this information.
   *
   * The operation queries the todo_list_user_sessions table using both the user
   * ID and session ID to ensure the session belongs to the specified user. This
   * prevents unauthorized access to sessions belonging to other users.
   *
   * Related operations: This endpoint is typically used in conjunction with
   * session deletion (DELETE /users/{userId}/sessions/{sessionId}) for session
   * management workflows.
   *
   * @param connection
   * @param userId Unique identifier of the user who owns the session
   * @param sessionId Unique identifier of the specific authentication session
   *   to retrieve
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<ITodoListUserSession> {
    try {
      return await getTodoListUserUsersUserIdSessionsSessionId({
        user,
        userId,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a specific user authentication session to terminate access.
   *
   * Permanently remove a specific authentication session for a given user from
   * the Todo list application.
   *
   * This operation performs a hard delete of the session record from the
   * todo_list_user_sessions table, immediately invalidating the associated
   * authentication token. Once deleted, any requests using this session token
   * will be rejected, requiring the user to authenticate again.
   *
   * Security considerations: This endpoint is critical for security workflows
   * including explicit user logout, forced session termination by
   * administrators, and session revocation in response to suspicious activity.
   * The operation validates that the session belongs to the specified user
   * before deletion to prevent unauthorized session manipulation.
   *
   * Use cases include: User-initiated logout from the application,
   * administrative session termination for security enforcement, automatic
   * cleanup of compromised sessions, and session management during password
   * reset flows.
   *
   * The operation returns the deleted session information to provide
   * confirmation of which session was terminated. This allows clients to verify
   * the correct session was removed and maintain audit logs of session
   * lifecycle events.
   *
   * Related operations: This endpoint works in conjunction with session
   * retrieval (GET /users/{userId}/sessions/{sessionId}) and is part of the
   * broader authentication and session management workflow.
   *
   * @param connection
   * @param userId Unique identifier of the user who owns the session
   * @param sessionId Unique identifier of the authentication session to delete
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":sessionId")
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<ITodoListUserSession> {
    try {
      return await deleteTodoListUserUsersUserIdSessionsSessionId({
        user,
        userId,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
