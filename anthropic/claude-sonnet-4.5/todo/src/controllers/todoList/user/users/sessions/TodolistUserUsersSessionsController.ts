import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchTodoListUserUsersUserIdSessions } from "../../../../../providers/patchTodoListUserUsersUserIdSessions";
import { UserAuth } from "../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../decorators/payload/UserPayload";
import { getTodoListUserUsersUserIdSessionsSessionId } from "../../../../../providers/getTodoListUserUsersUserIdSessionsSessionId";
import { deleteTodoListUserUsersUserIdSessionsSessionId } from "../../../../../providers/deleteTodoListUserUsersUserIdSessionsSessionId";

import { IPageITodoListUserSession } from "../../../../../api/structures/IPageITodoListUserSession";
import { ITodoListUserSession } from "../../../../../api/structures/ITodoListUserSession";

@Controller("/todoList/user/users/:userId/sessions")
export class TodolistUserUsersSessionsController {
  /**
   * Search and retrieve a filtered, paginated list of user sessions.
   *
   * Retrieve a filtered and paginated list of authentication sessions for a
   * specific user from the system. This operation provides search capabilities
   * for finding sessions based on multiple criteria including creation date
   * ranges, expiration status, IP addresses, and connection metadata.
   *
   * The operation supports comprehensive pagination with configurable page
   * sizes and sorting options. Sessions can be sorted by creation date,
   * expiration date, or other relevant fields in ascending or descending order.
   * This allows users to view their login history and identify active sessions
   * across different devices.
   *
   * Security considerations include ensuring users can only access their own
   * session data through proper authorization checks. The operation filters
   * sessions based on the authenticated user's identity, preventing
   * unauthorized access to other users' session information. Session metadata
   * including IP addresses, referrer URLs, and connection URLs are included for
   * security auditing and suspicious activity detection.
   *
   * This operation integrates with the todo_list_user_sessions table as defined
   * in the Prisma schema, incorporating all available session fields including
   * connection context and lifecycle timestamps. The response includes session
   * summary information optimized for list displays, showing active and expired
   * sessions to help users manage their authenticated devices.
   *
   * @param connection
   * @param userId Unique identifier of the target user whose sessions are being
   *   retrieved
   * @param body Search criteria and pagination parameters for session filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoListUserSession.IRequest,
  ): Promise<IPageITodoListUserSession.ISummary> {
    try {
      return await patchTodoListUserUsersUserIdSessions({
        user,
        userId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific user session.
   *
   * Retrieve complete details of a specific authentication session for a user.
   * This operation provides comprehensive session information including the IP
   * address from which the session was created, connection URL, referrer
   * information, creation timestamp, and expiration timestamp.
   *
   * The operation returns detailed session data useful for security auditing
   * and session management. Users can view when and where they logged in,
   * helping identify suspicious login attempts from unfamiliar locations or
   * devices. The expiration timestamp indicates whether the session is
   * currently active or has been terminated through logout, password change, or
   * automatic timeout.
   *
   * Security considerations include verifying that the requesting user owns the
   * session being accessed. The system enforces strict authorization to prevent
   * users from viewing other users' session details. This operation supports
   * the "active sessions" management feature where users can review and revoke
   * individual login sessions.
   *
   * This operation integrates with the todo_list_user_sessions table as defined
   * in the Prisma schema, returning all session fields including connection
   * context (IP, href, referrer) and lifecycle timestamps (created_at,
   * expired_at). The response provides the complete session object with all
   * available metadata for detailed inspection.
   *
   * @param connection
   * @param userId Unique identifier of the user who owns the session
   * @param sessionId Unique identifier of the target session to retrieve
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<ITodoListUserSession> {
    try {
      return await getTodoListUserUsersUserIdSessionsSessionId({
        user,
        userId,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Terminate a specific user session.
   *
   * Permanently delete a specific authentication session for a user,
   * effectively logging them out from that particular device or browser
   * session.
   *
   * This operation removes the session record from the todo_list_user_sessions
   * table, immediately invalidating the associated JWT token and preventing
   * further API access using that session's credentials. The session is
   * identified by both the user ID and session ID to ensure proper ownership
   * validation.
   *
   * Common use cases include user-initiated logout from current device, logging
   * out from a specific device in a "manage sessions" interface, or
   * security-triggered session termination when suspicious activity is
   * detected. This operation supports the security requirement that users can
   * individually revoke sessions without affecting other active sessions on
   * different devices.
   *
   * The operation enforces strict authorization - users can only delete their
   * own sessions, and the session must belong to the specified user. Attempting
   * to delete another user's session or a non-existent session results in
   * appropriate error responses.
   *
   * Upon successful deletion, the session is immediately terminated and cannot
   * be recovered. The user must authenticate again to create a new session for
   * that device. This operation is idempotent - attempting to delete an
   * already-deleted session returns success.
   *
   * @param connection
   * @param userId Unique identifier of the user who owns the session
   * @param sessionId Unique identifier of the specific session to terminate
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":sessionId")
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<ITodoListUserSession> {
    try {
      return await deleteTodoListUserUsersUserIdSessionsSessionId({
        user,
        userId,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
