import { Controller } from "@nestjs/common";
import { TypedRoute } from "@nestia/core";
import typia from "typia";
import { getTodoListUserTodosStatistics } from "../../../../../providers/getTodoListUserTodosStatistics";
import { UserAuth } from "../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../decorators/payload/UserPayload";

import { ITodoListTodoStatistics } from "../../../../../api/structures/ITodoListTodoStatistics";

@Controller("/todoList/user/todos/statistics")
export class TodolistUserTodosStatisticsController {
  /**
   * Retrieve aggregated statistics about user's todo items.
   *
   * Retrieve comprehensive statistical metrics about the authenticated user's
   * todo items. This operation provides analytical insights into task
   * management patterns including completion rates, pending tasks, and overall
   * productivity metrics.
   *
   * The statistics are computed in real-time by aggregating data from the
   * user's todo collection. Metrics include total number of todos created,
   * number of completed todos, number of pending/incomplete todos, completion
   * percentage rate, and potentially time-based trends if additional filtering
   * is applied.
   *
   * Security: Only authenticated users can access statistics, and the data is
   * automatically filtered to include only the requesting user's todos. The
   * user's identity is extracted from the JWT authentication token, ensuring
   * complete data privacy and isolation between users.
   *
   * This operation serves dashboard and overview requirements, providing users
   * with at-a-glance insights into their task management effectiveness. The
   * computed metrics help users understand their productivity patterns and task
   * completion behavior.
   *
   * Implementation note: This operation executes aggregation queries (COUNT,
   * SUM, AVG) on the todo_list_todos table filtered by the authenticated user's
   * ID. The response is a computed DTO containing statistical summaries rather
   * than direct table rows.
   *
   * @param connection
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @UserAuth()
    user: UserPayload,
  ): Promise<ITodoListTodoStatistics> {
    try {
      return await getTodoListUserTodosStatistics({
        user,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
