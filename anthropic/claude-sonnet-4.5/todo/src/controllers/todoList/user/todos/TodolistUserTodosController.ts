import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postTodoListUserTodos } from "../../../../providers/postTodoListUserTodos";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { patchTodoListUserTodos } from "../../../../providers/patchTodoListUserTodos";
import { getTodoListUserTodosTodoId } from "../../../../providers/getTodoListUserTodosTodoId";
import { putTodoListUserTodosTodoId } from "../../../../providers/putTodoListUserTodosTodoId";
import { deleteTodoListUserTodosTodoId } from "../../../../providers/deleteTodoListUserTodosTodoId";

import { ITodoListTodo } from "../../../../api/structures/ITodoListTodo";
import { IPageITodoListTodo } from "../../../../api/structures/IPageITodoListTodo";

@Controller("/todoList/user/todos")
export class TodolistUserTodosController {
  /**
   * Create a new todo item for the authenticated user.
   *
   * Create a new todo item in the user's personal task list. This operation
   * allows authenticated users to add tasks they need to complete, with a title
   * describing the task.
   *
   * The todo item is automatically associated with the authenticated user based
   * on their JWT token, ensuring proper ownership and data isolation. New todos
   * are created in an incomplete state by default (completed: false), and the
   * system automatically records the creation timestamp.
   *
   * Security: Only authenticated users can create todos. The user_id field is
   * automatically populated from the JWT token, preventing users from creating
   * todos for other users. Rate limiting may apply to prevent spam todo
   * creation.
   *
   * Validation: The title field is required and must be a non-empty string. The
   * operation validates input data before persisting to the database.
   *
   * Related operations: List todos (PATCH /todos), Update todo (PUT
   * /todos/{todoId}), Retrieve single todo (GET /todos/{todoId}).
   *
   * @param connection
   * @param body Todo item creation data including title
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoListTodo.ICreate,
  ): Promise<ITodoListTodo> {
    try {
      return await postTodoListUserTodos({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve a filtered, paginated list of user's todo items.
   *
   * Retrieve a filtered and paginated list of todo items belonging to the
   * authenticated user. This operation provides comprehensive search and
   * filtering capabilities for managing personal task lists with support for
   * title-based search, completion status filtering, and flexible sorting
   * options.
   *
   * The operation supports pagination with configurable page sizes to
   * efficiently handle large todo lists. Users can search todos by partial
   * title matching, filter by completion status (completed/incomplete), and
   * sort results by creation date, update date, or completion status in
   * ascending or descending order.
   *
   * Security is enforced through user authentication where the
   * todo_list_user_id is automatically extracted from the JWT token to ensure
   * complete data isolation between users. Each user can only access their own
   * todos, preventing unauthorized access to other users' task data.
   *
   * This operation integrates with the todo_list_todos table as defined in the
   * Prisma schema, incorporating all relevant fields including title,
   * completion status, creation timestamps, and soft deletion support. The
   * response includes todo summary information optimized for list displays.
   * Soft-deleted todos (where deleted_at is not null) are excluded from results
   * by default to show only active tasks.
   *
   * @param connection
   * @param body Search criteria, filters, and pagination parameters for todo
   *   list retrieval
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoListTodo.IRequest,
  ): Promise<IPageITodoListTodo.ISummary> {
    try {
      return await patchTodoListUserTodos({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information for a specific todo item by ID.
   *
   * Retrieve detailed information for a specific todo item identified by its
   * unique ID. This operation provides access to complete todo data including
   * the task title, completion status, creation timestamp, last update
   * timestamp, completion timestamp, and soft deletion status.
   *
   * The operation enforces strict authorization where users can only access
   * their own todo items. The system automatically validates that the requested
   * todo belongs to the authenticated user (via todo_list_user_id matching the
   * JWT token user ID) to maintain complete data isolation and privacy between
   * users.
   *
   * This operation returns the full todo entity as defined in the
   * todo_list_todos Prisma schema, including all fields such as title (up to
   * 500 characters), completed boolean status, created_at and updated_at
   * timestamps for audit tracking, completed_at timestamp showing when the task
   * was finished, and deleted_at timestamp for soft deletion support.
   *
   * The response provides comprehensive todo details suitable for viewing,
   * editing, or analyzing individual task information. If the todo does not
   * exist or does not belong to the authenticated user, appropriate error
   * responses are returned.
   *
   * @param connection
   * @param todoId Unique identifier of the target todo item
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":todoId")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
  ): Promise<ITodoListTodo> {
    try {
      return await getTodoListUserTodosTodoId({
        user,
        todoId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing todo item by ID.
   *
   * Update an existing todo item in the user's personal task list. This
   * operation allows authenticated users to modify the title or completion
   * status of a specific todo item identified by its unique ID.
   *
   * Users can mark tasks as completed or incomplete, or change the title. All
   * fields in the update request are applied to the todo item. The system
   * automatically updates the updated_at timestamp to reflect the modification
   * time. When marking a todo as completed, the system automatically sets the
   * completed_at timestamp.
   *
   * Security: Only the owner of a todo item can update it. The operation
   * verifies that the authenticated user (from JWT token) matches the user_id
   * of the todo item being updated. Attempting to update another user's todo
   * will result in an authorization error.
   *
   * Validation: The todoId path parameter must be a valid UUID matching an
   * existing todo item. Update data is validated to ensure title remains
   * non-empty if provided. The operation performs ownership verification before
   * applying any changes.
   *
   * Common use cases include marking tasks as complete when finished, updating
   * task details as requirements change, or correcting information in existing
   * todos.
   *
   * Related operations: Create todo (POST /todos), List todos (PATCH /todos),
   * Delete todo (DELETE /todos/{todoId}).
   *
   * @param connection
   * @param todoId Unique identifier of the target todo item
   * @param body Todo item update data with fields to modify (title and/or
   *   completed status)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":todoId")
  public async update(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoListTodo.IUpdate,
  ): Promise<ITodoListTodo> {
    try {
      return await putTodoListUserTodosTodoId({
        user,
        todoId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Soft delete a specific todo item by ID.
   *
   * Delete a specific todo item from the user's todo list by its unique
   * identifier. This operation performs a soft delete by setting the deleted_at
   * timestamp, marking the todo as deleted while preserving the record for
   * audit trail purposes.
   *
   * The system verifies ownership before deletion - users can only delete their
   * own todo items. The operation will fail if the todo item does not exist or
   * belongs to a different user, ensuring data security and proper access
   * control.
   *
   * Soft deletion preserves the todo record in the database with the deleted_at
   * timestamp set to the current date and time. This maintains historical
   * records and supports potential data recovery while excluding the todo from
   * normal query results. The todo will no longer appear in the user's active
   * todo list but remains in the system for audit purposes.
   *
   * The operation returns the deleted todo item's data including the deleted_at
   * timestamp as confirmation of successful deletion, allowing the client to
   * update the UI appropriately and provide user feedback about which item was
   * removed.
   *
   * @param connection
   * @param todoId Unique identifier of the target todo item to be deleted
   *   (global scope)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":todoId")
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
  ): Promise<ITodoListTodo> {
    try {
      return await deleteTodoListUserTodosTodoId({
        user,
        todoId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
