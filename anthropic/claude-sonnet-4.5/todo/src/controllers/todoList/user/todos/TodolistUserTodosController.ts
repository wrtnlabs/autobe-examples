import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postTodoListUserTodos } from "../../../../providers/postTodoListUserTodos";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { patchTodoListUserTodos } from "../../../../providers/patchTodoListUserTodos";
import { getTodoListUserTodosTodoId } from "../../../../providers/getTodoListUserTodosTodoId";
import { putTodoListUserTodosTodoId } from "../../../../providers/putTodoListUserTodosTodoId";
import { deleteTodoListUserTodosTodoId } from "../../../../providers/deleteTodoListUserTodosTodoId";

import { ITodoListTodo } from "../../../../api/structures/ITodoListTodo";
import { IPageITodoListTodo } from "../../../../api/structures/IPageITodoListTodo";

@Controller("/todoList/user/todos")
export class TodolistUserTodosController {
  /**
   * Create a new personal Todo task in the todo_list_todos table for the
   * authenticated user.
   *
   * Create a new Todo task for the authenticated user. This API endpoint
   * enables users to add personal to-do items with business-enforced validation
   * and full auditability.
   *
   * The API validates the 'title' is non-empty and does not exceed 100
   * characters as per schema requirements. If provided, the 'description' must
   * be under 500 characters, and the 'due_date' (if given) cannot be in the
   * past. The 'status' field must be 'pending', 'completed', or 'deleted',
   * reflecting the task's current state. Status defaults to 'pending' for new
   * items. On insert, 'created_at' and 'updated_at' are set automatically;
   * 'completed_at' and 'deleted_at' are null. Duplicate titles for the same
   * user are rejected.
   *
   * Security: Only authenticated users can create todos, and the todo is always
   * linked to the user's own account in the database via a foreign key. All
   * timestamps and ownership fields are managed on the backend to ensure audit
   * trails and data privacy. Related endpoints include updating existing todos
   * and listing user todos.
   *
   * @param connection
   * @param body Data required to create a todo item: title (required), optional
   *   description, due date, and initial status. User association and
   *   timestamps are handled automatically by the backend.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoListTodo.ICreate,
  ): Promise<ITodoListTodo> {
    try {
      return await postTodoListUserTodos({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve a paginated, filtered list of Todo items
   * (todo_list_todos).
   *
   * Retrieve a filtered and paginated Todo list, enabling users to find tasks
   * that match specific criteria such as completion status, priority, labels,
   * and due date windows.
   *
   * This API supports advanced filter queries to improve productivity for users
   * with large task sets. Pagination parameters allow efficient client-side
   * navigation and management of large result sets.
   *
   * Security and permission logic ensures each user only sees their own Todos.
   * Filtering/sorting is performed server-side for scalability. Rate-limiting,
   * input validation, and error handling are managed according to the business
   * rules and schema definitions.
   *
   * @param connection
   * @param body Advanced search and pagination criteria for querying Todo
   *   items, including status, due date range, priority, and text search.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoListTodo.IRequest,
  ): Promise<IPageITodoListTodo.ISummary> {
    try {
      return await patchTodoListUserTodos({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information for a specific Todo item (todo_list_todos).
   *
   * Fetches the complete details of a Todo item identified by its unique Todo
   * ID. All core fields, such as task description, completion status, creation
   * date, and deadlines, are provided in the response according to the schema
   * definition.
   *
   * Strict permission checks ensure only the Todo owner or authorized users can
   * access the record. Sensitive fields are returned only if the requester has
   * valid access rights.
   *
   * Error scenarios include not found, permission denied, or invalid identifier
   * format. Uses precise type mappings to prevent information leakage across
   * users.
   *
   * @param connection
   * @param todoId Unique identifier of the target Todo item.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":todoId")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
  ): Promise<ITodoListTodo> {
    try {
      return await getTodoListUserTodosTodoId({
        user,
        todoId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing Todo in the todo_list_todos table for the authenticated
   * user.
   *
   * Update a specified Todo belonging to the authenticated user. This API
   * endpoint allows authorized modifications to key Todo attributes, reflecting
   * business logic and audit rules from the schema.
   *
   * The operation performs schema-driven validation: new 'title' values must
   * not be blank and max out at 100 characters. Optional 'description' is
   * limited to 500 characters. 'Due_date' must be today or in the future.
   * Status changes must conform to the defined state machine and allowed
   * values: 'pending', 'completed', or 'deleted'. 'updated_at' is set
   * automatically; 'completed_at' and 'deleted_at' change in line with business
   * status transitions. Only the record owner, as identified by the foreign
   * key, may update the Todo.
   *
   * Security: The endpoint checks current user's ownership of the Todo and
   * never allows cross-user modifications. Errors for constraint violations
   * (uniqueness, missing data, or invalid state transitions) are reported
   * clearly. Related endpoints include Todo creation and list/search
   * operations.
   *
   * @param connection
   * @param todoId Unique identifier of the Todo to be updated.
   * @param body Fields to update for the target Todo: new title, description,
   *   status, or due date. Only modifiable fields are accepted. Ownership and
   *   audit fields are controlled automatically.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":todoId")
  public async update(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoListTodo.IUpdate,
  ): Promise<ITodoListTodo> {
    try {
      return await putTodoListUserTodosTodoId({
        user,
        todoId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Mark a Todo as deleted by setting its deleted_at timestamp (todo_list_todos
   * table).
   *
   * Permanently marks a Todo record as deleted by setting the 'deleted_at'
   * timestamp in the database. This ensures that the record is retained for
   * audit and compliance purposes, in accordance with privacy and regulatory
   * requirements.
   *
   * Only the owner of the Todo is permitted to mark it as deleted. The system
   * validates ownership by checking the authenticated user's identity against
   * the user_id foreign key. If the Todo is already deleted, the operation has
   * no effect beyond ensuring idempotency.
   *
   * Related operations include the PATCH /todos endpoint for listing/filtering
   * by status, and the POST /todos endpoint for creation of new tasks. Error
   * handling includes validation of the todoId, existence checks, permission
   * verification, and proper user feedback if deletion is not permitted.
   *
   * @param connection
   * @param todoId Unique identifier of the target Todo record to delete.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":todoId")
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
  ): Promise<ITodoListTodo> {
    try {
      return await deleteTodoListUserTodosTodoId({
        user,
        todoId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
