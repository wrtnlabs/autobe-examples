import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { patchTodoListUserPasswordResetTokens } from "../../../../providers/patchTodoListUserPasswordResetTokens";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";

import { IPageITodoListPasswordResetToken } from "../../../../api/structures/IPageITodoListPasswordResetToken";
import { ITodoListPasswordResetToken } from "../../../../api/structures/ITodoListPasswordResetToken";

@Controller("/todoList/user/passwordResetTokens")
export class TodolistUserPasswordresettokensController {
  /**
   * Search and retrieve password reset tokens with filtering.
   *
   * Retrieve a filtered and paginated list of password reset tokens for
   * administrative monitoring, security auditing, and token management
   * purposes.
   *
   * This operation provides comprehensive search capabilities across the
   * todo_list_password_reset_tokens table, allowing administrators to query
   * tokens by user association, creation date ranges, expiration status, and
   * usage state. Results support pagination and sorting to handle large
   * datasets efficiently.
   *
   * Administrative use cases include monitoring password reset request patterns
   * to detect potential security threats, auditing token usage for compliance
   * purposes, identifying expired or unused tokens for cleanup operations, and
   * investigating user-reported issues with password reset emails.
   *
   * The operation filters tokens based on multiple criteria including user ID
   * to see all reset requests for a specific account, expiration status to find
   * expired tokens requiring cleanup, usage status to identify unused tokens
   * that may indicate email delivery issues, and creation date ranges for
   * time-based security analysis.
   *
   * Results include complete token metadata such as associated user, email
   * address where reset link was sent, creation and expiration timestamps, and
   * usage timestamp if the token has been consumed. Sensitive token values are
   * included only for administrative security auditing purposes.
   *
   * This operation requires administrative privileges as password reset tokens
   * contain sensitive security information. Regular users cannot access
   * password reset token data through the API.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering
   *   password reset tokens
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoListPasswordResetToken.IRequest,
  ): Promise<IPageITodoListPasswordResetToken.ISummary> {
    try {
      return await patchTodoListUserPasswordResetTokens({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
