import { Controller, Ip } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthAdminJoin } from "../../../providers/postAuthAdminJoin";
import { postAuthAdminLogin } from "../../../providers/postAuthAdminLogin";
import { postAuthAdminRefresh } from "../../../providers/postAuthAdminRefresh";

import { ITodoListAdmin } from "../../../api/structures/ITodoListAdmin";

@Controller("/auth/admin")
export class AuthAdminController {
  /**
   * Register a new system administrator account and issue authentication
   * tokens.
   *
   * Creates a new administrator account in the system and issues JWT
   * authentication tokens.
   *
   * This endpoint handles the registration process for new system
   * administrators. It accepts admin credentials (email and password),
   * validates the input according to business rules, creates a new admin record
   * in the todo_list_admins table with securely hashed password, and returns
   * JWT tokens for immediate system access.
   *
   * The admin account is created with full administrative privileges as defined
   * in the actor configuration. The password is hashed using industry-standard
   * cryptographic algorithms before storage, and the email must be unique
   * across all admin accounts.
   *
   * Upon successful registration, the response includes both an access token
   * (short-lived, for API requests) and a refresh token (long-lived, for
   * obtaining new access tokens). The admin session is tracked in the
   * todo_list_admin_sessions table.
   *
   * Security considerations: In production environments, this endpoint should
   * be protected with additional authorization checks or disabled entirely
   * after initial admin setup. Only authorized personnel should be able to
   * create new admin accounts to prevent privilege escalation attacks.
   *
   * @param connection
   * @param body Admin registration credentials including email and password
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoListAdmin.ICreate,
  ): Promise<ITodoListAdmin.IAuthorized> {
    try {
      return await postAuthAdminJoin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate administrator credentials and issue JWT access tokens.
   *
   * Authenticates an existing administrator using email and password
   * credentials and returns JWT tokens.
   *
   * This endpoint handles the login process for system administrators. It
   * accepts admin credentials (email and password), validates them against the
   * todo_list_admins table, verifies the password hash matches, and issues JWT
   * authentication tokens upon successful validation.
   *
   * The authentication process includes password verification using secure
   * cryptographic comparison to prevent timing attacks. If credentials are
   * invalid, the endpoint returns an authentication error without revealing
   * whether the email or password was incorrect (security best practice).
   *
   * Upon successful authentication, the response includes both an access token
   * (short-lived, typically 15-60 minutes) and a refresh token (long-lived,
   * typically 7-30 days). A new session record is created in the
   * todo_list_admin_sessions table to track the admin's authenticated session.
   *
   * Security considerations: This endpoint should implement rate limiting to
   * prevent brute force attacks. Failed login attempts should be logged for
   * security monitoring. The system should consider implementing account
   * lockout policies after repeated failed attempts.
   *
   * @param connection
   * @param body Admin login credentials with email and password
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoListAdmin.ILogin,
  ): Promise<ITodoListAdmin.IAuthorized> {
    try {
      return await postAuthAdminLogin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh JWT access tokens using a valid refresh token.
   *
   * Refreshes JWT access tokens for administrators using a valid refresh token.
   *
   * This endpoint enables administrators to obtain new access tokens without
   * requiring re-authentication with email and password. It accepts a valid
   * refresh token, validates it against the todo_list_admin_sessions table, and
   * issues a new access token (and optionally a new refresh token) if the
   * refresh token is valid and not expired.
   *
   * The refresh process verifies that the refresh token exists in the active
   * sessions table, has not expired, and corresponds to a valid admin account.
   * This mechanism allows for long-lived authenticated sessions while
   * maintaining security through short-lived access tokens.
   *
   * Upon successful refresh, the response includes a new access token with a
   * fresh expiration time. The system may also implement refresh token
   * rotation, where a new refresh token is issued and the old one is
   * invalidated, providing additional security against token theft.
   *
   * Security considerations: Refresh tokens should be stored securely by the
   * client (httpOnly cookies or secure storage). The endpoint should validate
   * that the refresh token hasn't been revoked or blacklisted. Session tracking
   * in todo_list_admin_sessions enables the system to invalidate all sessions
   * for an admin if needed (e.g., password change or security breach).
   *
   * @param connection
   * @param body Refresh token for obtaining new access token
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: ITodoListAdmin.IRefresh,
  ): Promise<ITodoListAdmin.IAuthorized> {
    try {
      return await postAuthAdminRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
