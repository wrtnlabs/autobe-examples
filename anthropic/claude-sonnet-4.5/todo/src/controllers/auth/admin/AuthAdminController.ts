import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthAdminJoin } from "../../../providers/postAuthAdminJoin";
import { AdminAuth } from "../../../decorators/AdminAuth";
import { AdminPayload } from "../../../decorators/payload/AdminPayload";
import { postAuthAdminLogin } from "../../../providers/postAuthAdminLogin";
import { postAuthAdminRefresh } from "../../../providers/postAuthAdminRefresh";

import { ITodoListAdmin } from "../../../api/structures/ITodoListAdmin";

@Controller("/auth/admin")
export class AuthAdminController {
  /**
   * Registers a new administrator in todo_list_admins with authentication
   * tokens on success.
   *
   * This endpoint enables new administrator registration by inserting a record
   * into the todo_list_admins Prisma table. The process requires a unique email
   * and hashed password, reflecting password_hash and email columns, both of
   * which are not nullable and are validated for uniqueness (email) and
   * security (password_hash). Upon successful registration, the created_at and
   * updated_at fields are set to the current timestamp, and disabled_at is
   * null, indicating the account is active. Only privileged system flows may
   * call this endpoint—public user sign-up is strictly forbidden to maintain
   * administrative integrity.
   *
   * Security is paramount: the API must hash input passwords before persisting
   * to the password_hash column. Only privileged flows may call this; never
   * allow user-initiated registration. The operation does not permit guest or
   * user accounts to register via this endpoint. Each successful call creates a
   * new admin log-in authorization session, which will be fully managed
   * elsewhere.
   *
   * Registration of admin users must be auditable. All new accounts receive a
   * unique id (UUID) and can be disabled (setting disabled_at) for compliance
   * or incident management—though this endpoint does not support disabling. The
   * registration response contains authorized tokens and an admin profile
   * structure, never exposing raw password hashes, and always returning success
   * only on full compliance with schema and uniqueness constraints.
   *
   * Related endpoint: POST /auth/admin/login for admin credential-based
   * authentication. This operation occurs only once per admin identity, and
   * must be coordinated with audit trail logging. If account with that email
   * exists, should error out with clear feedback for audit.
   *
   * On error (duplication, schema violation), the system responds with clear
   * validation explanations. Success returns admin tokens and profile summary.
   *
   * @param connection
   * @param body Administrator registration details, including secure password
   *   and unique email.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: ITodoListAdmin.IJoin,
  ): Promise<ITodoListAdmin.IAuthorized> {
    try {
      return await postAuthAdminJoin({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticates admin using todo_list_admins and records session; issues
   * tokens on success.
   *
   * Authenticates an existing administrator by validating their credentials
   * against the todo_list_admins table. The endpoint expects a correct, unique
   * email and a password, which is hashed and compared to the password_hash
   * field. On success, a new session record is created in
   * todo_list_admin_sessions for audit trail, automatically referencing the
   * admin's id, IP, href, and referrer. Admins whose accounts are disabled
   * (disabled_at not null) or absent receive a clear error response.
   *
   * Security best practices are enforced: invalid passwords, unknown emails, or
   * disabled accounts must be rejected with generic error messages for
   * anti-abuse. No enumeration of admin email addresses or timing attacks may
   * occur. On success, both access and refresh JWTs are issued, and detailed
   * session metadata is logged (in session table). All admin logins are
   * auditable via session and admin tables.
   *
   * Multiple authentication failures in quick succession should produce rate
   * limiting (not handled here but described for integration). A login triggers
   * a new admin session with context, tracked for compliance and incident
   * investigation. Use of unique indexes and session records should be
   * coordinated to avoid session duplication or confusion in logs.
   *
   * This operation is restricted to administrators with valid/active accounts;
   * regular users must use their own endpoints. Admin credential reset is
   * handled separately.
   *
   * @param connection
   * @param body Credentials for admin login, with secure password and
   *   registered email.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: ITodoListAdmin.ILogin,
  ): Promise<ITodoListAdmin.IAuthorized> {
    try {
      return await postAuthAdminLogin({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refreshes authentication tokens for active admin session using valid
   * refresh token.
   *
   * This endpoint refreshes JWT authentication tokens for an
   * already-authenticated administrator using a valid, unexpired refresh token.
   * It verifies the associated admin session (from todo_list_admin_sessions) is
   * still active (expired_at is null) and that the admin account (from
   * todo_list_admins) remains enabled (disabled_at is null). No credential
   * checking occurs here: refresh strictly operates on token and session
   * validity. On success, a new set of tokens and current admin profile
   * information are returned, in the schema of ITodoListAdmin.IAuthorized.
   *
   * If the refresh token is invalid, expired, or if the admin session/user is
   * disabled or missing, a clear error is returned. The operation is critical
   * for maintaining secure, continuous session flow without re-prompting for
   * passwords. All refreshes are logged via admin session for the fullest
   * audit. Integration with session expiration and compliance checks is
   * required elsewhere. Only valid sessions and active admins may successfully
   * refresh tokens.
   *
   * Related endpoints include POST /auth/admin/login for initial authentication
   * and POST /auth/admin/join for admin registration. Any invalid, expired, or
   * terminated tokens must result in prompt, clear failure.
   *
   * @param connection
   * @param body Refresh token payload for admin session token renewal.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: ITodoListAdmin.IRefresh,
  ): Promise<ITodoListAdmin.IAuthorized> {
    try {
      return await postAuthAdminRefresh({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
