import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthAdminPasswordResetToken } from "../../../../../providers/postAuthAdminPasswordResetToken";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";

import { ITodoListAdmin } from "../../../../../api/structures/ITodoListAdmin";

@Controller("/auth/admin/password/reset-token")
export class AuthAdminPasswordReset_tokenController {
  /**
   * Generates a secure password reset token record for authorized
   * administrator.
   *
   * This endpoint initiates the administrator password reset process by
   * generating a new unique record in the todo_list_password_reset_tokens
   * Prisma table. The process requires a valid, unique administrator email that
   * maps to an enabled record in todo_list_admins (disabled_at is null). Upon
   * request, a new secure reset token is generated and associated with the
   * correct admin id (linking todo_list_password_reset_tokens to
   * todo_list_admins by reference, though user_id column is for user resets;
   * extend for admin here). The token is returned out-of-band, via
   * audit-compliant means (e-mail/SMS/integration not implemented here), and
   * will expire at expires_at. Used tokens are kept for full traceability.
   *
   * Security features enforce that token creation is not available for disabled
   * admins, and all requests are fully validated to avoid abuse. Requests from
   * unknown emails must not disclose whether the account exists for
   * anti-enumeration. Successful requests are auditable, and only one valid
   * token may exist per admin at a time (re-use forbidden). Reset attempts for
   * already disabled admins or nonexistent emails fail with generic error
   * messages for compliance.
   *
   * This endpoint does not actually reset the password, only commences the
   * secure reset flow via token generation. Actual password change must occur
   * at password reset confirmation endpoint.
   *
   * @param connection
   * @param body Administrator password reset request details; generally just
   *   the registered email.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async generatePasswordResetToken(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: ITodoListAdmin.IFindForPasswordReset,
  ): Promise<ITodoListAdmin.IPasswordResetToken> {
    try {
      return await postAuthAdminPasswordResetToken({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
