import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthUserEmailVerify } from "../../../../../providers/postAuthUserEmailVerify";

import { ITodoListEmailVerification } from "../../../../../api/structures/ITodoListEmailVerification";

@Controller("/auth/user/email/verify")
export class AuthUserEmailVerifyController {
  /**
   * Verify user email address using verification token from
   * todo_list_email_verifications table.
   *
   * Verifies user email addresses using verification tokens sent during
   * registration.
   *
   * This endpoint completes the email verification workflow, which is an
   * essential part of secure user account activation. When a user registers, a
   * verification token is generated and stored in the
   * todo_list_email_verifications table. This token is typically sent to the
   * user's email address as part of a verification link.
   *
   * When the user clicks the verification link or submits the token through
   * this endpoint, the system validates the token against records in the
   * todo_list_email_verifications table. The validation process checks token
   * authenticity, expiration status, and ensures the token hasn't been used
   * previously. Upon successful validation, the corresponding user record in
   * the todo_list_users table is updated to mark the email as verified.
   *
   * The Prisma schema defines the todo_list_email_verifications table with
   * fields for tracking verification tokens, their expiration, and usage
   * status. This operation leverages these fields to ensure secure and reliable
   * email verification.
   *
   * Security considerations include token expiration enforcement (tokens should
   * be time-limited), one-time use validation (tokens cannot be reused), and
   * protection against brute-force token guessing. Failed verification attempts
   * should be logged for security monitoring.
   *
   * This is a public endpoint that does not require authentication, as users
   * need to verify their email before they can fully access their accounts.
   * However, the operation does create an association with a specific user
   * account based on the verification token.
   *
   * @param connection
   * @param body Email verification token received via email
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async verifyEmail(
    @TypedBody()
    body: ITodoListEmailVerification.IVerify,
  ): Promise<ITodoListEmailVerification.IResult> {
    try {
      return await postAuthUserEmailVerify({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
