import { Controller, Ip } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthUserJoin } from "../../../providers/postAuthUserJoin";
import { postAuthUserLogin } from "../../../providers/postAuthUserLogin";
import { postAuthUserRefresh } from "../../../providers/postAuthUserRefresh";

import { ITodoListUser } from "../../../api/structures/ITodoListUser";

@Controller("/auth/user")
export class AuthUserController {
  /**
   * Register a new user account in todo_list_users table.
   *
   * Creates a new authenticated user account in the todo_list_users table,
   * establishing the foundation for personal todo list management with complete
   * data isolation.
   *
   * This endpoint handles the complete user registration workflow including
   * email uniqueness validation, secure password hashing using bcrypt with cost
   * factor of at least 12, and initial JWT token issuance for immediate
   * authenticated access. The email address serves as the unique login
   * identifier and must be validated for proper format before account
   * creation.
   *
   * Upon successful registration, the system creates the user record with the
   * provided email, securely hashed password, and optional display name for
   * personalization. The created_at and updated_at timestamps are automatically
   * set to track account lifecycle. The account is created in active status
   * with deleted_at set to null.
   *
   * The response includes the complete user profile along with JWT access and
   * refresh tokens, allowing the newly registered user to immediately begin
   * using the application without requiring a separate login step. This
   * implements the standard registration flow where users can start managing
   * their todo lists immediately after account creation.
   *
   * Registration failures occur when the email address is already registered to
   * another user account, when the email format is invalid, or when password
   * requirements are not met. The system enforces email uniqueness through the
   * unique index on the email field in the todo_list_users table.
   *
   * @param connection
   * @param body User registration information including email, password, and
   *   optional name
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoListUser.ICreate,
  ): Promise<ITodoListUser.IAuthorized> {
    try {
      return await postAuthUserJoin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate user credentials and issue JWT tokens for todo_list_users.
   *
   * Validates user credentials against the todo_list_users table and
   * establishes an authenticated session with JWT token issuance.
   *
   * This endpoint handles the complete authentication workflow by verifying the
   * provided email exists in the system, comparing the submitted password
   * against the stored bcrypt password_hash, and validating the account is not
   * soft-deleted (deleted_at is null). The email serves as the unique login
   * identifier as defined in the todo_list_users table schema.
   *
   * Upon successful authentication, the system creates a new session record in
   * todo_list_user_sessions capturing connection metadata including IP address,
   * connection URL (href), and referrer information for security auditing. The
   * session tracks when it was created and manages expiration through the
   * expired_at field to enforce authentication timeout policies.
   *
   * The response provides the authenticated user's profile information along
   * with JWT access and refresh tokens. These tokens enable secure, stateless
   * authentication for subsequent API requests and support the application's
   * token refresh mechanism. The session supports multiple concurrent logins
   * from different devices simultaneously through the todo_list_user_sessions
   * tracking.
   *
   * Authentication failures occur when the email is not found, the password
   * verification fails against the bcrypt hash, or the account has been
   * soft-deleted. Failed login attempts should be logged for security
   * monitoring to detect potential unauthorized access attempts.
   *
   * @param connection
   * @param body User login credentials with email and password
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoListUser.ILogin,
  ): Promise<ITodoListUser.IAuthorized> {
    try {
      return await postAuthUserLogin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh JWT access tokens for continued authenticated access.
   *
   * Renews JWT access tokens using a valid refresh token, extending the user's
   * authenticated session without requiring password re-entry.
   *
   * This endpoint validates the provided refresh token against active sessions
   * in the todo_list_user_sessions table, ensuring the session hasn't expired
   * (expired_at is null or in the future) and belongs to a valid, non-deleted
   * user account in todo_list_users (deleted_at is null). The refresh mechanism
   * supports continuous authenticated access while maintaining security through
   * token rotation.
   *
   * Upon successful validation, the system issues a new pair of JWT tokens
   * (access and refresh) with extended expiration times. This follows the
   * standard OAuth 2.0 refresh token pattern where the old refresh token is
   * typically invalidated and replaced with a new one to prevent token reuse
   * attacks. The session's connection metadata (IP, href, referrer) is
   * preserved from the original login.
   *
   * The refresh operation maintains the user's authenticated state across the
   * configured session timeout period, which can be 7 days for standard
   * sessions or 30 days when "Remember Me" was selected during login. This
   * enables users to continue working without interruption from token
   * expiration.
   *
   * Refresh failures occur when the refresh token is invalid, expired, or
   * associated with a revoked session (expired_at is set), when the user
   * account has been deleted, or when the user has changed their password
   * triggering a "logout from all devices" scenario. Failed refresh attempts
   * should trigger re-authentication through the login endpoint.
   *
   * @param connection
   * @param body Refresh token for session renewal
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: ITodoListUser.IRefresh,
  ): Promise<ITodoListUser.IAuthorized> {
    try {
      return await postAuthUserRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
