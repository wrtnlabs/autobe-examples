import { Controller, Ip } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthUserJoin } from "../../../providers/postAuthUserJoin";
import { postAuthUserLogin } from "../../../providers/postAuthUserLogin";
import { postAuthUserRefresh } from "../../../providers/postAuthUserRefresh";

import { ITodoListUser } from "../../../api/structures/ITodoListUser";

@Controller("/auth/user")
export class AuthUserController {
  /**
   * Creates a new user account in the Todo list application by registering with
   * email and password credentials.
   *
   * This operation handles the complete user registration workflow, including
   * validating the uniqueness of the email address against the todo_list_users
   * table, securely hashing the provided password using industry-standard
   * algorithms (bcrypt or argon2), and storing the new user record with
   * automatically generated timestamps for created_at and updated_at fields.
   *
   * Upon successful registration, the system immediately establishes an
   * authenticated session by generating JWT tokens (both access token and
   * refresh token) and returns them in the response. This allows the newly
   * registered user to begin using the application immediately without
   * requiring a separate login step.
   *
   * The email address must be unique across all user accounts in the system.
   * Email addresses are normalized to lowercase for consistency and
   * case-insensitive comparison, as defined in the todo_list_users schema. If
   * the provided email already exists, the operation will fail with an
   * appropriate error indicating the email is already registered.
   *
   * This is a public endpoint accessible without authentication, as it
   * represents the entry point for new users to join the application. The
   * operation enforces strict validation rules on the input data to ensure
   * account security and data integrity from the moment of account creation.
   *
   * @param connection
   * @param body User registration credentials including email and password
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoListUser.ICreate,
  ): Promise<ITodoListUser.IAuthorized> {
    try {
      return await postAuthUserJoin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticates an existing user by validating their email and password
   * credentials against the todo_list_users table.
   *
   * This operation performs credential verification by looking up the user
   * account using the provided email address (normalized to lowercase for
   * case-insensitive matching) and comparing the provided password against the
   * stored password_hash using secure hash comparison methods. The
   * password_hash field stores passwords hashed with industry-standard
   * algorithms (bcrypt or argon2) and never exposes the original plain-text
   * password.
   *
   * Upon successful authentication, the system generates a new JWT-based
   * session by creating both an access token and a refresh token. The refresh
   * token information is persisted in the todo_list_user_sessions table for
   * session management and security tracking purposes. The response includes
   * the complete set of JWT tokens that the client must use for subsequent
   * authenticated API requests.
   *
   * If the credentials are invalid (either the email doesn't exist or the
   * password doesn't match), the operation fails with an authentication error
   * without revealing which specific credential was incorrect, following
   * security best practices to prevent user enumeration attacks.
   *
   * This is a public endpoint accessible without prior authentication, as it
   * represents the mechanism by which users establish authenticated sessions.
   * Once authenticated, users gain access to their personal todo items through
   * the returned JWT tokens.
   *
   * @param connection
   * @param body User login credentials including email and password
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoListUser.ILogin,
  ): Promise<ITodoListUser.IAuthorized> {
    try {
      return await postAuthUserLogin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refreshes JWT access tokens using a valid refresh token to extend the
   * user's authenticated session.
   *
   * This operation is essential for maintaining long-lived user sessions
   * without requiring users to repeatedly enter their credentials. When an
   * access token expires, clients can use the refresh token to obtain a new
   * access token seamlessly, providing a smooth user experience while
   * maintaining security.
   *
   * The operation validates the provided refresh token against the
   * todo_list_user_sessions table, which tracks all active refresh tokens and
   * their associated metadata including connection information for security
   * audit purposes. The refresh token must be valid, non-expired, and not
   * revoked to successfully generate new access tokens.
   *
   * Upon successful validation, the system generates a new set of JWT tokens
   * (both access token and refresh token) and may update the session record in
   * todo_list_user_sessions with the new token information and updated
   * timestamps. The old refresh token is typically invalidated to prevent token
   * reuse attacks, following JWT security best practices.
   *
   * If the refresh token is invalid, expired, or has been revoked, the
   * operation fails and the client must re-authenticate through the login
   * endpoint to establish a new session. This ensures that compromised or
   * leaked refresh tokens cannot be used indefinitely.
   *
   * This endpoint requires a valid refresh token to access, making it a
   * semi-protected endpoint. It does not require a valid access token, as the
   * purpose is to obtain new access tokens when the current one has expired.
   *
   * @param connection
   * @param body Refresh token credentials for generating new access tokens
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: ITodoListUser.IRefresh,
  ): Promise<ITodoListUser.IAuthorized> {
    try {
      return await postAuthUserRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
