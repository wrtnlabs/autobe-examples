import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthUserPasswordResetConfirm } from "../../../../../../providers/postAuthUserPasswordResetConfirm";

import { ITodoListPasswordReset } from "../../../../../../api/structures/ITodoListPasswordReset";

@Controller("/auth/user/password/reset/confirm")
export class AuthUserPasswordResetConfirmController {
  /**
   * Reset user password using reset token from todo_list_password_resets table
   * for todo_list_users.
   *
   * Completes the password reset process by validating the reset token and
   * updating the user's password.
   *
   * This endpoint handles the second phase of the password recovery workflow.
   * After a user has requested a password reset and received a reset token via
   * email, they use this endpoint to set a new password. The system validates
   * the provided reset token against records in the todo_list_password_resets
   * table and, upon successful validation, updates the password in the
   * corresponding todo_list_users record.
   *
   * The validation process checks multiple security criteria: token
   * authenticity (the token must exist in the database), expiration status (the
   * token must not have exceeded its validity period), and usage status (the
   * token must not have been previously used). The Prisma schema for
   * todo_list_password_resets includes fields to track these validation
   * requirements.
   *
   * Upon successful token validation, the operation updates the password field
   * in the todo_list_users table with the new hashed password. The reset token
   * is then marked as used in the todo_list_password_resets table to prevent
   * reuse. For additional security, all existing user sessions in the
   * todo_list_user_sessions table should be invalidated to ensure the user must
   * log in again with the new password.
   *
   * Security considerations include password strength validation (enforcing
   * minimum requirements for the new password), secure password hashing using
   * industry-standard algorithms, one-time token usage (preventing token replay
   * attacks), and session invalidation to protect against unauthorized access
   * with old credentials.
   *
   * This is a public endpoint that does not require authentication, as it
   * serves users who cannot currently authenticate. However, possession of the
   * valid reset token serves as proof of email ownership and authorization to
   * change the password.
   *
   * @param connection
   * @param body Password reset token and new password credentials
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async confirmPasswordReset(
    @TypedBody()
    body: ITodoListPasswordReset.IConfirm,
  ): Promise<ITodoListPasswordReset.IConfirmResult> {
    try {
      return await postAuthUserPasswordResetConfirm({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
