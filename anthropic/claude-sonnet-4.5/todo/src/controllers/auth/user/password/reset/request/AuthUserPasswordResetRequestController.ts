import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthUserPasswordResetRequest } from "../../../../../../providers/postAuthUserPasswordResetRequest";

import { ITodoListUser } from "../../../../../../api/structures/ITodoListUser";

@Controller("/auth/user/password/reset/request")
export class AuthUserPasswordResetRequestController {
  /**
   * Request password reset by generating and emailing a secure token.
   *
   * Initiates the password reset workflow by creating a cryptographically
   * secure, time-limited token in todo_list_password_reset_tokens and sending a
   * password reset link via email.
   *
   * This endpoint handles the first step of the "Forgot Password" self-service
   * recovery mechanism. When users provide their email address, the system
   * validates the email exists in todo_list_users and the account is not
   * soft-deleted (deleted_at is null). A cryptographically secure random token
   * is generated, stored in the todo_list_password_reset_tokens table with a
   * 1-hour expiration (expires_at set to created_at + 1 hour), and sent to the
   * user's email address.
   *
   * The generated token must be unique across all active tokens to prevent
   * collisions, enforced by the unique index on the token field. The system
   * stores both the token and the email address for validation, providing an
   * additional security layer during the password reset completion. Multiple
   * tokens can exist for the same user if they request password reset multiple
   * times before using a token.
   *
   * The password reset email contains a secure link with the token embedded,
   * directing users to the password reset completion page. This public endpoint
   * does not require authentication since users have lost access to their
   * accounts. For security, the endpoint should not reveal whether an email
   * exists in the system to prevent email enumeration attacks.
   *
   * The token creation follows strict security controls: tokens expire after 1
   * hour (enforced through expires_at validation), are single-use only (tracked
   * through used_at field), and are permanently deleted after successful
   * password reset or expiration. This implements industry-standard password
   * recovery while maintaining strict security requirements.
   *
   * @param connection
   * @param body Email address for password reset request
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async requestPasswordReset(
    @TypedBody()
    body: ITodoListUser.IPasswordResetRequest,
  ): Promise<ITodoListUser.IPasswordResetRequestResponse> {
    try {
      return await postAuthUserPasswordResetRequest({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
