import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthUserPasswordRequestReset } from "../../../../../providers/postAuthUserPasswordRequestReset";

import { ITodoListUser } from "../../../../../api/structures/ITodoListUser";

@Controller("/auth/user/password/request-reset")
export class AuthUserPasswordRequest_resetController {
  /**
   * Initiates a user password reset flow by creating a reset token record.
   *
   * This endpoint accepts a password reset initiation request for a user
   * identified by their email address. The API validates existence of the user
   * (in 'todo_list_users'), then creates a one-time-use password reset record
   * in 'todo_list_password_reset_tokens', with a securely-generated token,
   * creation and expiration timestamps. Actual password changes are handled in
   * a separate endpoint after token validation.
   *
   * Security and compliance policies dictate that responses to this endpoint
   * NEVER disclose whether the submitted email exists—a generic success/failure
   * message is returned regardless. Timing and error details are masked to
   * resist brute force enumeration.
   *
   * Password reset tokens expire based on the 'expires_at' field and may only
   * be used once (see 'used_at'). Issued tokens are suitable for secure
   * delivery out-of-band (such as via email notification). All operations are
   * audited per privacy and incident response policy.
   *
   * This endpoint does not itself alter user credentials. A follow-up operation
   * (not defined here) will use the issued reset token to update the password,
   * after separate verification and security checks.
   *
   * @param connection
   * @param body Email address requesting password reset initiation.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async requestPasswordReset(
    @TypedBody()
    body: ITodoListUser.IRequestPasswordReset,
  ): Promise<ITodoListUser.IPasswordResetInitiated> {
    try {
      return await postAuthUserPasswordRequestReset({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
