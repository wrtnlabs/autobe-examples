import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthUserPasswordResetComplete } from "../../../../../../providers/postAuthUserPasswordResetComplete";

import { ITodoListUser } from "../../../../../../api/structures/ITodoListUser";

@Controller("/auth/user/password/reset/complete")
export class AuthUserPasswordResetCompleteController {
  /**
   * Complete password reset using validated token and set new password.
   *
   * Validates the password reset token and updates the user's password in
   * todo_list_users, completing the secure account recovery workflow.
   *
   * This endpoint handles the second step of the password reset flow after
   * users click the reset link from their email. The system validates the
   * provided token exists in todo_list_password_reset_tokens, hasn't expired
   * (current time < expires_at), hasn't been used (used_at is null), and
   * matches the provided email address for additional security verification.
   *
   * Upon successful token validation, the system updates the password_hash
   * field in todo_list_users with the new password securely hashed using bcrypt
   * with cost factor of at least 12. The updated_at timestamp is automatically
   * updated to reflect the password change. The token's used_at field is set to
   * the current timestamp, permanently preventing token reuse and enforcing the
   * single-use security requirement.
   *
   * As a security measure, successful password reset triggers invalidation of
   * all active sessions for the user by setting expired_at on all records in
   * todo_list_user_sessions. This implements a "logout from all devices"
   * behavior, ensuring that if an unauthorized party gained access, they are
   * immediately logged out when the legitimate user resets their password.
   *
   * Password reset failures occur when the token is not found, has expired
   * based on the expires_at timestamp, has already been used (used_at is not
   * null), or when the email doesn't match the token's stored email. The system
   * enforces strict token expiration through the 1-hour limit set during token
   * creation, and tokens are permanently deleted after successful use or
   * expiration.
   *
   * This completes the self-service password recovery mechanism, allowing users
   * to regain access to their accounts securely while maintaining strict
   * security controls through time-limited, single-use tokens and automatic
   * session invalidation.
   *
   * @param connection
   * @param body Password reset token, email, and new password
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async completePasswordReset(
    @TypedBody()
    body: ITodoListUser.IPasswordResetComplete,
  ): Promise<ITodoListUser.IPasswordResetCompleteResponse> {
    try {
      return await postAuthUserPasswordResetComplete({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
