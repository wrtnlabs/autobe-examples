import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthUserPasswordChange } from "../../../../../providers/postAuthUserPasswordChange";
import { UserAuth } from "../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../decorators/payload/UserPayload";

import { ITodoListUser } from "../../../../../api/structures/ITodoListUser";

@Controller("/auth/user/password/change")
export class AuthUserPasswordChangeController {
  /**
   * Change password for authenticated user with current password verification.
   *
   * Allows authenticated users to change their password in todo_list_users
   * after verifying their current password, implementing secure password update
   * with session management.
   *
   * This endpoint handles password changes for users who have access to their
   * accounts and want to update their credentials proactively. Unlike password
   * reset which is for account recovery, password change requires the user to
   * be authenticated and provide their current password for verification. This
   * prevents unauthorized password changes if someone gains temporary access to
   * an authenticated session.
   *
   * The system validates the current password against the stored password_hash
   * in todo_list_users using bcrypt verification before allowing the change.
   * Upon successful verification, the password_hash field is updated with the
   * new password securely hashed using bcrypt with cost factor of at least 12.
   * The updated_at timestamp is automatically set to reflect the password
   * modification.
   *
   * As a security best practice, successful password change triggers
   * invalidation of all other active sessions for the user by setting
   * expired_at on all records in todo_list_user_sessions except the current
   * session. This implements a "logout from all other devices" behavior,
   * ensuring that if an unauthorized party gained access on another device,
   * they are immediately logged out when the user changes their password.
   *
   * This operation maintains the current session's validity, allowing the user
   * to continue working after the password change without requiring
   * re-authentication. The user receives confirmation of the successful
   * password update and should be advised that all other devices were logged
   * out for security.
   *
   * Password change failures occur when the current password verification
   * fails, when the new password doesn't meet security requirements, or when
   * the user account has been soft-deleted. This endpoint requires
   * authentication through JWT token validation and can only be accessed by the
   * account owner.
   *
   * @param connection
   * @param body Current password verification and new password
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async changePassword(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoListUser.IPasswordChange,
  ): Promise<ITodoListUser.IPasswordChangeResponse> {
    try {
      return await postAuthUserPasswordChange({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
