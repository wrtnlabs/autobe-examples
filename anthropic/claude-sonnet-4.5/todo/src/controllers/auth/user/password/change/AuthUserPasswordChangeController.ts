import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthUserPasswordChange } from "../../../../../providers/postAuthUserPasswordChange";
import { UserAuth } from "../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../decorators/payload/UserPayload";

import { ITodoListUser } from "../../../../../api/structures/ITodoListUser";

@Controller("/auth/user/password/change")
export class AuthUserPasswordChangeController {
  /**
   * Change password for authenticated user in todo_list_users table.
   *
   * Allows authenticated users to change their password by validating the
   * current password and setting a new one.
   *
   * This endpoint handles the password change workflow for users who are
   * currently authenticated and know their existing password. Unlike password
   * reset (which uses email-based token verification), this operation requires
   * the user to be logged in and to provide their current password as proof of
   * identity.
   *
   * The password change process validates that the provided current password
   * matches the stored hashed password in the todo_list_users table. This
   * additional verification step ensures that even if someone gains
   * unauthorized access to an authenticated session, they cannot change the
   * password without knowing the current password.
   *
   * Upon successful validation of the current password, the operation updates
   * the password field in the todo_list_users table with the new hashed
   * password. For enhanced security, the system should optionally invalidate
   * all other active sessions in the todo_list_user_sessions table, forcing the
   * user to re-authenticate on all devices with the new password.
   *
   * Security considerations include current password verification (preventing
   * unauthorized password changes), password strength validation for the new
   * password (enforcing security requirements), secure password hashing using
   * industry-standard algorithms, and optional session invalidation to prevent
   * unauthorized access from previously authenticated sessions.
   *
   * This endpoint requires authentication with the user actor, ensuring that
   * only the account owner can initiate a password change. The operation
   * provides a secure mechanism for users to proactively update their
   * credentials as part of good security hygiene.
   *
   * @param connection
   * @param body Current password for verification and new password for update
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async changePassword(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoListUser.IChangePassword,
  ): Promise<ITodoListUser.IChangePasswordResult> {
    try {
      return await postAuthUserPasswordChange({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
