import { Controller, Ip } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthGuestJoin } from "../../../providers/postAuthGuestJoin";
import { postAuthGuestRefresh } from "../../../providers/postAuthGuestRefresh";

import { ITodoListGuest } from "../../../api/structures/ITodoListGuest";

@Controller("/auth/guest")
export class AuthGuestController {
  /**
   * Register a new guest user account in the todo_list_users table.
   *
   * Registers a new guest user account in the Todo list application by creating
   * a record in the todo_list_users table. This operation allows
   * unauthenticated visitors to create temporary guest accounts that provide
   * limited access to the system.
   *
   * The registration process accepts the user's email address, which must be
   * unique across all users and serves as the login identifier. The password is
   * cryptographically hashed using bcrypt with a cost factor of at least 12
   * before being stored in the password_hash field. An optional display name
   * can be provided for personalization purposes.
   *
   * Upon successful registration, the system immediately issues JWT access and
   * refresh tokens, allowing the guest to access public features without
   * requiring a separate login step. The created_at and updated_at timestamps
   * are automatically set to the current time, and the deleted_at field remains
   * null for active accounts.
   *
   * This endpoint is publicly accessible and requires no authentication. Email
   * uniqueness is enforced by the unique index on the email field in the
   * todo_list_users table. Password strength validation ensures secure
   * credentials are used.
   *
   * Related operations: After registration, guests can use the refresh endpoint
   * (/auth/guest/refresh) to renew their access tokens when they expire.
   *
   * @param connection
   * @param body Guest user registration information including email, password,
   *   and optional name
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoListGuest.ICreate,
  ): Promise<ITodoListGuest.IAuthorized> {
    try {
      return await postAuthGuestJoin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh JWT tokens for guest users using a valid refresh token.
   *
   * Refreshes the JWT access and refresh tokens for an authenticated guest
   * user. This operation allows guests to maintain continuous access to the
   * system without re-entering their credentials when their access token
   * expires.
   *
   * The endpoint accepts a valid refresh token in the request body and
   * validates its authenticity, expiration status, and association with an
   * active guest account in the todo_list_users table. The guest account must
   * not be soft-deleted (deleted_at must be null).
   *
   * Upon successful validation, the system issues a new pair of JWT tokens
   * (access token and refresh token) with updated expiration times. The old
   * refresh token is invalidated to prevent reuse. This token rotation strategy
   * enhances security by limiting the lifetime of each token.
   *
   * This operation requires a valid refresh token but does not require an
   * active access token, making it suitable for scenarios where the access
   * token has expired but the refresh token is still valid. The endpoint is
   * publicly accessible in the sense that it doesn't require authentication
   * middleware, but it does require a valid refresh token in the request body.
   *
   * Security considerations: The refresh token must be stored securely on the
   * client side and transmitted only over HTTPS. Token rotation prevents replay
   * attacks and limits the impact of token theft.
   *
   * Related operations: This endpoint is typically used in conjunction with the
   * join endpoint (/auth/guest/join) which provides the initial token pair upon
   * registration.
   *
   * @param connection
   * @param body Refresh token for generating new access and refresh tokens
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: ITodoListGuest.IRefresh,
  ): Promise<ITodoListGuest.IAuthorized> {
    try {
      return await postAuthGuestRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
