import { Controller, Ip } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthGuestJoin } from "../../../providers/postAuthGuestJoin";
import { postAuthGuestRefresh } from "../../../providers/postAuthGuestRefresh";

import { ITodoListGuest } from "../../../api/structures/ITodoListGuest";

@Controller("/auth/guest")
export class AuthGuestController {
  /**
   * Register a new guest account and issue temporary JWT tokens for
   * unauthenticated access.
   *
   * Creates a new guest account and issues JWT tokens for temporary access to
   * the Todo list application.
   *
   * This endpoint allows unauthenticated visitors to register as guest users
   * without requiring full authentication credentials. Upon successful
   * registration, the system generates a guest account entry in the
   * todo_list_guests table and returns a JWT access token and refresh token
   * pair.
   *
   * Guest accounts are designed for temporary, limited access to the service.
   * They cannot create or manage todo items but can view public information and
   * explore the service interface. This provides a low-friction entry point for
   * users who want to experience the service before committing to full
   * registration.
   *
   * The response includes both access and refresh tokens in the
   * ITodoListGuest.IAuthorized format, enabling the guest to maintain their
   * session and refresh tokens as needed. The guest account remains active
   * until explicitly converted to a full user account or until it expires based
   * on system policies.
   *
   * This operation is publicly accessible and does not require any prior
   * authentication. It serves as the primary entry point for guest users to
   * begin interacting with the Todo list application.
   *
   * @param connection
   * @param body Guest registration information for creating a temporary account
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoListGuest.ICreate,
  ): Promise<ITodoListGuest.IAuthorized> {
    try {
      return await postAuthGuestJoin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh guest JWT access token using a valid refresh token.
   *
   * Refreshes the JWT access token for a guest account using a valid refresh
   * token.
   *
   * This endpoint enables guest users to renew their access tokens without
   * going through the registration process again. When a guest's access token
   * expires, they can use their refresh token to obtain a new access token,
   * maintaining their session continuity.
   *
   * The operation validates the provided refresh token against the
   * todo_list_guests table and associated session records. If the refresh token
   * is valid and not expired, the system issues a new access token and
   * optionally a new refresh token, depending on the token rotation policy.
   *
   * This follows standard JWT refresh token patterns, ensuring that guest users
   * can maintain long-lived sessions while still benefiting from the security
   * of short-lived access tokens. The refresh mechanism is essential for
   * providing a seamless user experience for guest accounts.
   *
   * Authentication is performed using the refresh token itself, which must be
   * valid and associated with an active guest account. The response follows the
   * ITodoListGuest.IAuthorized format, providing the renewed token pair.
   *
   * This operation requires a valid refresh token and will fail if the token is
   * expired, revoked, or invalid. Successful execution extends the guest's
   * session without requiring re-registration.
   *
   * @param connection
   * @param body Refresh token information for renewing guest access
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: ITodoListGuest.IRefresh,
  ): Promise<ITodoListGuest.IAuthorized> {
    try {
      return await postAuthGuestRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
