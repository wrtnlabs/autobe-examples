import { ArrayUtil, RandomGenerator, TestValidator } from "@nestia/e2e";
import { IConnection } from "@nestia/fetcher";
import typia, { tags } from "typia";

import api from "@ORGANIZATION/PROJECT-api";
import type { ITodoListPasswordResetToken } from "@ORGANIZATION/PROJECT-api/lib/structures/ITodoListPasswordResetToken";

/**
 * Test retrieval attempt for a non-existent password reset token.
 *
 * This test validates the system's error handling when attempting to retrieve a
 * password reset token that does not exist in the
 * todo_list_password_reset_tokens table. The scenario uses a valid UUID format
 * that has never been generated by the system to verify proper 404 error
 * responses.
 *
 * This ensures the password reset flow properly handles cases where users
 * provide invalid or fabricated token identifiers, preventing unauthorized
 * access and providing clear error messaging.
 *
 * Steps:
 *
 * 1. Generate a valid UUID that doesn't exist in the system
 * 2. Attempt to retrieve the non-existent token
 * 3. Verify that the API returns an appropriate error response
 */
export async function test_api_password_reset_token_retrieval_nonexistent(
  connection: api.IConnection,
) {
  // Generate a random UUID that has never been created in the system
  const nonExistentTokenId = typia.random<string & tags.Format<"uuid">>();

  // Attempt to retrieve the non-existent password reset token
  // This should fail because the token doesn't exist in the database
  await TestValidator.error(
    "retrieving non-existent token should fail",
    async () => {
      await api.functional.todoList.passwordResetTokens.at(connection, {
        tokenId: nonExistentTokenId,
      });
    },
  );
}
