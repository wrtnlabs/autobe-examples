/**
 * Validate complete multi-actor order creation workflow generating status
 * history audit trail for administrative oversight.
 *
 * This test demonstrates a realistic e-commerce workflow across three actor
 * types (admin, seller, buyer) culminating in order creation. While the
 * original scenario requested admin retrieval of specific status history
 * records, that operation is not implementable with available APIs since
 * there's no way to obtain status history IDs from created orders.
 *
 * Instead, this test validates the complete order creation workflow that
 * generates status history records internally, demonstrating the multi-actor
 * interactions and data flow that populate the audit trail system.
 *
 * Workflow:
 *
 * 1. Admin creates marketplace category infrastructure
 * 2. Seller registers, lists product, and adds purchasable SKU variant
 * 3. Buyer registers, configures delivery address and payment method
 * 4. Buyer adds product to cart and creates order
 * 5. Validate order creation success (which triggers status history generation)
 *
 * Validates:
 *
 * - Complete multi-actor authentication and authorization flow
 * - Proper category, product, and SKU creation workflow
 * - Buyer address and payment method setup
 * - Successful order creation from cart items
 * - Order structure includes all required relationships and data
 */
export async function test_api_order_status_history_admin_retrieval(
  connection: api.IConnection,
) {
  // Phase 1: Admin Setup and Category Creation
  const adminEmail = typia.random<string & tags.Format<"email">>();
  const adminPassword = typia.random<string & tags.Format<"password">>();
  const admin = await api.functional.auth.admin.join(connection, {
    body: {
      email: adminEmail,
      password: adminPassword,
      full_name: RandomGenerator.name(),
      phone_number: RandomGenerator.mobile(),
      admin_level: "super_admin",
      email_verified: true,
      href: "https://admin.marketplace.test/register",
      referrer: "https://admin.marketplace.test/home",
    } satisfies IShoppingMallAdmin.ICreate,
  });
  typia.assert(admin);

  const category = await api.functional.shoppingMall.admin.categories.create(
    connection,
    {
      body: {
        name: RandomGenerator.name(2),
        slug: RandomGenerator.alphaNumeric(10),
        description: RandomGenerator.paragraph({ sentences: 5 }),
        display_order: 1,
        status: "active",
      } satisfies IShoppingMallCategory.ICreate,
    },
  );
  typia.assert(category);

  // Phase 2: Seller Product Setup
  const sellerEmail = typia.random<string & tags.Format<"email">>();
  const seller = await api.functional.auth.seller.join(connection, {
    body: {
      email: sellerEmail,
      password: typia.random<string & tags.MinLength<8>>(),
      full_name: RandomGenerator.name(),
      phone_number: RandomGenerator.mobile(),
      business_name: RandomGenerator.name(3),
      business_description: RandomGenerator.content({ paragraphs: 2 }),
      store_name: RandomGenerator.name(2),
      href: "https://seller.marketplace.test/register",
      referrer: "https://marketplace.test/seller-info",
    } satisfies IShoppingMallSeller.ICreate,
  });
  typia.assert(seller);

  const sale = await api.functional.shoppingMall.seller.sales.create(
    connection,
    {
      body: {
        code: RandomGenerator.alphaNumeric(12),
        shopping_mall_category_id: category.id,
        title: RandomGenerator.paragraph({ sentences: 3 }),
        description: RandomGenerator.content({ paragraphs: 3 }),
        condition: "new",
        return_policy_days: 30,
        status: "published",
      } satisfies IShoppingMallSale.ICreate,
    },
  );
  typia.assert(sale);

  const sku = await api.functional.shoppingMall.seller.sales.skus.create(
    connection,
    {
      saleCode: sale.code,
      body: {
        sku_code: RandomGenerator.alphaNumeric(8),
        variant_combination: JSON.stringify({ Color: "Blue", Size: "M" }),
        base_price: 99.99,
        enabled: true,
      } satisfies IShoppingMallSaleSku.ICreate,
    },
  );
  typia.assert(sku);

  // Phase 3: Buyer Preparation
  const buyerEmail = typia.random<string & tags.Format<"email">>();
  const buyer = await api.functional.auth.buyer.join(connection, {
    body: {
      email: buyerEmail,
      password: typia.random<string & tags.MinLength<8>>(),
      full_name: RandomGenerator.name(),
      phone_number: RandomGenerator.mobile(),
      href: "https://marketplace.test/register",
      referrer: "https://marketplace.test/",
    } satisfies IShoppingMallBuyer.ICreate,
  });
  typia.assert(buyer);

  const address =
    await api.functional.shoppingMall.buyer.buyers.me.addresses.create(
      connection,
      {
        body: {
          recipient_name: RandomGenerator.name(),
          phone: RandomGenerator.mobile(),
          street_address_line1: RandomGenerator.paragraph({ sentences: 4 }),
          city: RandomGenerator.name(1),
          state: RandomGenerator.name(1),
          postal_code: typia
            .random<
              number &
                tags.Type<"uint32"> &
                tags.Minimum<10000> &
                tags.Maximum<99999>
            >()
            .toString(),
          country: "United States",
          address_label: "Home",
          address_type: "residential",
          is_default: true,
        } satisfies IShoppingMallBuyerAddress.ICreate,
      },
    );
  typia.assert(address);

  const paymentMethod =
    await api.functional.shoppingMall.buyer.paymentMethods.create(connection, {
      body: {
        payment_type: "credit_card",
        provider: "Stripe",
        provider_token: RandomGenerator.alphaNumeric(32),
        card_brand: "visa",
        last_four_digits: typia
          .random<
            number &
              tags.Type<"uint32"> &
              tags.Minimum<1000> &
              tags.Maximum<9999>
          >()
          .toString(),
        expiry_month: typia.random<
          number & tags.Type<"int32"> & tags.Minimum<1> & tags.Maximum<12>
        >(),
        expiry_year: typia.random<
          number & tags.Type<"int32"> & tags.Minimum<2024>
        >(),
        billing_name: RandomGenerator.name(),
        billing_postal_code: typia
          .random<
            number &
              tags.Type<"uint32"> &
              tags.Minimum<10000> &
              tags.Maximum<99999>
          >()
          .toString(),
        is_default: true,
      } satisfies IShoppingMallPaymentMethod.ICreate,
    });
  typia.assert(paymentMethod);

  // Phase 4: Order Creation Workflow
  const cartItem =
    await api.functional.shoppingMall.buyer.buyers.me.cart.items.create(
      connection,
      {
        body: {
          shopping_mall_sale_sku_id: sku.id,
          quantity: 2,
        } satisfies IShoppingMallCartItem.ICreate,
      },
    );
  typia.assert(cartItem);

  const order = await api.functional.shoppingMall.buyer.orders.create(
    connection,
    {
      body: {
        cart_item_ids: [cartItem.id],
        buyer_address_id: address.id,
        payment_method_id: paymentMethod.id,
        notes: RandomGenerator.paragraph({ sentences: 2 }),
      } satisfies IShoppingMallOrder.ICreate,
    },
  );
  typia.assert(order);

  // Validate order creation success
  TestValidator.equals(
    "order contains buyer information",
    order.shopping_mall_buyer_id,
    buyer.id,
  );
  TestValidator.equals(
    "order uses selected delivery address",
    order.shopping_mall_buyer_address_id,
    address.id,
  );
  TestValidator.predicate(
    "order has valid order number",
    order.order_number.length > 0,
  );
  TestValidator.predicate("order contains items", order.items.length > 0);
  TestValidator.predicate(
    "order has seller sub-orders",
    order.sellers.length > 0,
  );
}
