/**
 * Test submitting a negative helpfulness vote on a product review.
 *
 * This test validates the complete workflow for submitting a helpfulness vote
 * indicating a review was not helpful. It builds the complete prerequisite data
 * chain: category → product sale → SKU → buyer setup → order → review, then
 * authenticates as a different buyer to submit a negative vote.
 *
 * Workflow:
 *
 * 1. Admin creates product category
 * 2. Seller creates product sale and SKU variant
 * 3. First buyer completes purchase and writes review
 * 4. Second buyer submits negative helpfulness vote
 * 5. Verify vote record with is_helpful=false
 */
export async function test_api_review_helpfulness_vote_creation_not_helpful(
  connection: api.IConnection,
) {
  // 1. Admin authenticates and creates category
  const admin = await api.functional.auth.admin.join(connection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      full_name: RandomGenerator.name(),
      phone_number: RandomGenerator.mobile(),
      admin_level: "super_admin",
      email_verified: true,
      href: "https://admin.example.com/register" satisfies string &
        tags.Format<"uri">,
      referrer: "https://admin.example.com" satisfies string &
        tags.Format<"uri">,
    } satisfies IShoppingMallAdmin.ICreate,
  });
  typia.assert(admin);

  const category = await api.functional.shoppingMall.admin.categories.create(
    connection,
    {
      body: {
        name: RandomGenerator.name(2),
        slug: RandomGenerator.alphaNumeric(10),
        description: RandomGenerator.paragraph({ sentences: 5 }),
        display_order: 1,
        status: "active",
      } satisfies IShoppingMallCategory.ICreate,
    },
  );
  typia.assert(category);

  // 2. Seller authenticates and creates product
  const seller = await api.functional.auth.seller.join(connection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.MinLength<8>>(),
      full_name: RandomGenerator.name(),
      phone_number: RandomGenerator.mobile(),
      business_name: RandomGenerator.name(3),
      business_description: RandomGenerator.paragraph({ sentences: 10 }),
      store_name: RandomGenerator.name(2),
      href: "https://seller.example.com/register" satisfies string &
        tags.Format<"uri">,
      referrer: "https://seller.example.com" satisfies string &
        tags.Format<"uri">,
    } satisfies IShoppingMallSeller.ICreate,
  });
  typia.assert(seller);

  const sale = await api.functional.shoppingMall.seller.sales.create(
    connection,
    {
      body: {
        code: RandomGenerator.alphaNumeric(12),
        shopping_mall_category_id: category.id,
        title: RandomGenerator.paragraph({ sentences: 3 }),
        description: RandomGenerator.content({ paragraphs: 2 }),
        condition: "new",
        return_policy_days: 30,
      } satisfies IShoppingMallSale.ICreate,
    },
  );
  typia.assert(sale);

  // 3. Create SKU variant
  const sku = await api.functional.shoppingMall.seller.sales.skus.create(
    connection,
    {
      saleCode: sale.code,
      body: {
        sku_code: RandomGenerator.alphaNumeric(10),
        variant_combination: JSON.stringify({ Color: "Blue", Size: "Medium" }),
        base_price: 99.99,
        enabled: true,
      } satisfies IShoppingMallSaleSku.ICreate,
    },
  );
  typia.assert(sku);

  // 4. First buyer authenticates and creates address/payment method
  const buyer1Email = typia.random<string & tags.Format<"email">>();
  const buyer1Password = typia.random<string & tags.MinLength<8>>();

  const buyer1 = await api.functional.auth.buyer.join(connection, {
    body: {
      email: buyer1Email,
      password: buyer1Password,
      full_name: RandomGenerator.name(),
      href: "https://shop.example.com/register" satisfies string &
        tags.Format<"uri">,
      referrer: "https://shop.example.com" satisfies string &
        tags.Format<"uri">,
    } satisfies IShoppingMallBuyer.ICreate,
  });
  typia.assert(buyer1);

  const address =
    await api.functional.shoppingMall.buyer.buyers.me.addresses.create(
      connection,
      {
        body: {
          recipient_name: RandomGenerator.name(),
          phone: RandomGenerator.mobile(),
          street_address_line1: RandomGenerator.paragraph({ sentences: 4 }),
          city: RandomGenerator.name(1),
          postal_code: typia
            .random<
              number &
                tags.Type<"uint32"> &
                tags.Minimum<10000> &
                tags.Maximum<99999>
            >()
            .toString(),
          country: "United States",
          address_label: "Home",
          address_type: "residential",
          is_default: true,
        } satisfies IShoppingMallBuyerAddress.ICreate,
      },
    );
  typia.assert(address);

  const paymentMethod =
    await api.functional.shoppingMall.buyer.paymentMethods.create(connection, {
      body: {
        payment_type: "credit_card",
        provider: "Stripe",
        provider_token: RandomGenerator.alphaNumeric(32),
        card_brand: "visa",
        last_four_digits: typia
          .random<
            number &
              tags.Type<"uint32"> &
              tags.Minimum<1000> &
              tags.Maximum<9999>
          >()
          .toString(),
        expiry_month: typia.random<
          number & tags.Type<"int32"> & tags.Minimum<1> & tags.Maximum<12>
        >(),
        expiry_year: typia.random<
          number & tags.Type<"int32"> & tags.Minimum<2024>
        >(),
        billing_name: RandomGenerator.name(),
        billing_postal_code: typia
          .random<
            number &
              tags.Type<"uint32"> &
              tags.Minimum<10000> &
              tags.Maximum<99999>
          >()
          .toString(),
        is_default: true,
      } satisfies IShoppingMallPaymentMethod.ICreate,
    });
  typia.assert(paymentMethod);

  // 5. First buyer adds to cart and creates order
  const cartItem =
    await api.functional.shoppingMall.buyer.buyers.me.cart.items.create(
      connection,
      {
        body: {
          shopping_mall_sale_sku_id: sku.id,
          quantity: 1,
        } satisfies IShoppingMallCartItem.ICreate,
      },
    );
  typia.assert(cartItem);

  const order = await api.functional.shoppingMall.buyer.orders.create(
    connection,
    {
      body: {
        cart_item_ids: [cartItem.id],
        buyer_address_id: address.id,
        payment_method_id: paymentMethod.id,
      } satisfies IShoppingMallOrder.ICreate,
    },
  );
  typia.assert(order);

  // 6. First buyer writes review
  const review = await api.functional.shoppingMall.buyer.reviews.create(
    connection,
    {
      body: {
        shopping_mall_sale_id: sale.id,
        shopping_mall_sale_sku_id: sku.id,
        shopping_mall_order_id: order.id,
        star_rating: typia.random<
          number & tags.Type<"int32"> & tags.Minimum<1> & tags.Maximum<5>
        >(),
        review_title: RandomGenerator.paragraph({ sentences: 3 }),
        review_body: RandomGenerator.content({ paragraphs: 2 }),
        is_anonymous: false,
      } satisfies IShoppingMallReview.ICreate,
    },
  );
  typia.assert(review);

  // 7. Second buyer authenticates to submit vote
  const buyer2 = await api.functional.auth.buyer.join(connection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.MinLength<8>>(),
      full_name: RandomGenerator.name(),
      href: "https://shop.example.com/register" satisfies string &
        tags.Format<"uri">,
      referrer: "https://shop.example.com" satisfies string &
        tags.Format<"uri">,
    } satisfies IShoppingMallBuyer.ICreate,
  });
  typia.assert(buyer2);

  // 8. Second buyer submits negative helpfulness vote
  const vote =
    await api.functional.shoppingMall.buyer.reviews.helpfulnessVotes.create(
      connection,
      {
        reviewId: review.id,
        body: {
          is_helpful: false,
        } satisfies IShoppingMallReviewHelpfulnessVote.ICreate,
      },
    );
  typia.assert(vote);
}
