import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallSaleQuestion } from "../../../../../structures/IShoppingMallSaleQuestion";

/**
 * Delete a customer question from a product sale listing.
 *
 * Permanently remove a customer question from a specific product sale listing
 * in the shopping marketplace.
 *
 * This operation allows authorized users to delete questions that have been
 * posted about a product. The deletion is permanent and removes the question
 * record from the database along with any associated answers if they exist.
 *
 * Security considerations include authorization checks to ensure only the
 * question author or administrators can delete questions. The operation
 * validates that the question belongs to the specified sale before deletion.
 * Rate limiting may apply to prevent abuse of the deletion functionality.
 *
 * This operation integrates with the shopping_mall_sale_questions table as
 * defined in the Prisma schema. Upon successful deletion, the question and any
 * related answers are removed from the system. The sale itself remains
 * unaffected by this operation.
 *
 * @param props.connection
 * @param props.saleCode Unique business identifier code of the target product
 *   sale (global scope)
 * @param props.questionId Unique identifier of the target question to be
 *   deleted
 * @path /shoppingMall/admin/sales/:saleCode/questions/:questionId
 * @accessor api.functional.shoppingMall.admin.sales.questions.erase
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function erase(
  connection: IConnection,
  props: erase.Props,
): Promise<erase.Response> {
  return true === connection.simulate
    ? erase.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...erase.METADATA,
          path: erase.path(props),
          status: null,
        },
      );
}
export namespace erase {
  export type Props = {
    /**
     * Unique business identifier code of the target product sale (global
     * scope)
     */
    saleCode: string;

    /** Unique identifier of the target question to be deleted */
    questionId: string & tags.Format<"uuid">;
  };
  export type Response = IShoppingMallSaleQuestion;

  export const METADATA = {
    method: "DELETE",
    path: "/shoppingMall/admin/sales/:saleCode/questions/:questionId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/admin/sales/${encodeURIComponent(props.saleCode ?? "null")}/questions/${encodeURIComponent(props.questionId ?? "null")}`;
  export const random = (): IShoppingMallSaleQuestion =>
    typia.random<IShoppingMallSaleQuestion>();
  export const simulate = (
    connection: IConnection,
    props: erase.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: erase.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("saleCode")(() => typia.assert(props.saleCode));
      assert.param("questionId")(() => typia.assert(props.questionId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
