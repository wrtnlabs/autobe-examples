/**
 * Delete a product review from the system.
 *
 * Delete an existing product review from the shopping marketplace platform.
 * This operation permanently removes the review record from the database
 * including all associated review images and metadata.
 *
 * For buyers, this operation allows them to remove reviews they have previously
 * submitted on products they purchased. The buyer must be the original author
 * of the review to perform this deletion. For administrators, this operation
 * enables moderation capabilities to remove reviews that violate platform
 * policies, contain inappropriate content, or have been reported by users.
 *
 * Security considerations include strict ownership verification for buyer
 * deletions and admin permission validation for moderation deletions. When a
 * review is deleted, the product's aggregate rating statistics are
 * automatically recalculated to reflect the removal. Associated review images
 * are also removed from storage as part of the deletion process.
 *
 * This operation integrates with the shopping_mall_reviews table as defined in
 * the Prisma schema. The deletion is permanent and cannot be undone. Related
 * operations include creating reviews (POST /sales/{saleId}/reviews) and
 * updating reviews (PUT /reviews/{reviewId}).
 *
 * @param props.connection
 * @param props.reviewId Unique identifier of the target review to delete
 * @path /shoppingMall/admin/reviews/:reviewId
 * @accessor api.functional.shoppingMall.admin.reviews.erase
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function erase(
  connection: IConnection,
  props: erase.Props,
): Promise<erase.Response> {
  return true === connection.simulate
    ? erase.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...erase.METADATA,
          path: erase.path(props),
          status: null,
        },
      );
}
export namespace erase {
  export type Props = {
    /** Unique identifier of the target review to delete */
    reviewId: string & tags.Format<"uuid">;
  };
  export type Response = IShoppingMallReview;

  export const METADATA = {
    method: "DELETE",
    path: "/shoppingMall/admin/reviews/:reviewId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/admin/reviews/${encodeURIComponent(props.reviewId ?? "null")}`;
  export const random = (): IShoppingMallReview =>
    typia.random<IShoppingMallReview>();
  export const simulate = (
    connection: IConnection,
    props: erase.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: erase.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("reviewId")(() => typia.assert(props.reviewId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
