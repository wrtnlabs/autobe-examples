/**
 * Retrieve all platform commission records for a specific order.
 *
 * Retrieve a collection of platform commission records associated with a
 * specific order in the marketplace system. This operation provides access to
 * all commission entries related to a single order, enabling administrators to
 * view the complete commission breakdown for multi-seller orders or track
 * commission details for individual transactions.
 *
 * In marketplace systems, a single order may generate multiple platform
 * commission records, particularly when the order contains items from multiple
 * sellers. Each commission record represents the platform's fee for
 * facilitating that portion of the transaction. This operation aggregates all
 * such commission records for comprehensive financial tracking and reporting.
 *
 * Security considerations: This operation is restricted to admin users only, as
 * it exposes sensitive platform revenue data and seller transaction fees.
 * Administrators use this endpoint for financial auditing, revenue
 * verification, seller payout calculations, and dispute resolution. The
 * operation ensures that all commission records associated with an order are
 * accessible for complete financial transparency.
 *
 * This operation integrates with the shopping_mall_platform_commissions table
 * as defined in the Prisma schema, utilizing the order relationship to filter
 * and retrieve all relevant commission records. The response includes detailed
 * commission information for each record, supporting administrative financial
 * analysis and order-level revenue tracking.
 *
 * @param props.connection
 * @param props.orderId Unique identifier of the target order
 * @path /shoppingMall/admin/orders/:orderId/platformCommissions
 * @accessor api.functional.shoppingMall.admin.orders.platformCommissions.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
      );
}
export namespace index {
  export type Props = {
    /** Unique identifier of the target order */
    orderId: string & tags.Format<"uuid">;
  };
  export type Response = IShoppingMallPlatformCommissions;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/admin/orders/:orderId/platformCommissions",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/admin/orders/${encodeURIComponent(props.orderId ?? "null")}/platformCommissions`;
  export const random = (): IShoppingMallPlatformCommissions =>
    typia.random<IShoppingMallPlatformCommissions>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("orderId")(() => typia.assert(props.orderId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
