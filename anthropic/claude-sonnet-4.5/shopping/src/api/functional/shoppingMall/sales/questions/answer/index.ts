import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallSaleQuestionAnswer } from "../../../../../structures/IShoppingMallSaleQuestionAnswer";

/**
 * Retrieve the seller's response to a customer question posted on a specific
 * product sale listing.
 *
 * This operation returns the answer that a seller has provided to a customer's
 * question about their product. The answer includes the response text,
 * timestamp, and seller information. If no answer has been posted yet, the
 * operation returns null or an appropriate not-found response.
 *
 * This is a public endpoint that allows potential buyers to view
 * question-and-answer exchanges about products, helping them make informed
 * purchase decisions. The transparency of product Q&A supports buyer confidence
 * and reduces purchase hesitation.
 *
 * The operation integrates with the shopping_mall_sale_question_answers table
 * as defined in the Prisma schema. It validates that the question belongs to
 * the specified sale and returns the most recent answer if multiple answers
 * exist (though typically only one answer per question is allowed).
 *
 * @param props.connection
 * @param props.saleCode Unique business identifier code of the target product
 *   sale (global scope)
 * @param props.questionId Unique identifier of the target question
 * @path /shoppingMall/sales/:saleCode/questions/:questionId/answer
 * @accessor api.functional.shoppingMall.sales.questions.answer.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique business identifier code of the target product sale (global
     * scope)
     */
    saleCode: string;

    /** Unique identifier of the target question */
    questionId: string & tags.Format<"uuid">;
  };
  export type Response = IShoppingMallSaleQuestionAnswer;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/sales/:saleCode/questions/:questionId/answer",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/sales/${encodeURIComponent(props.saleCode ?? "null")}/questions/${encodeURIComponent(props.questionId ?? "null")}/answer`;
  export const random = (): IShoppingMallSaleQuestionAnswer =>
    typia.random<IShoppingMallSaleQuestionAnswer>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("saleCode")(() => typia.assert(props.saleCode));
      assert.param("questionId")(() => typia.assert(props.questionId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
