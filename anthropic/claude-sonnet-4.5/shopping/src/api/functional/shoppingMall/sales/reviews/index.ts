import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallReview } from "../../../../structures/IShoppingMallReview";
import { IPageIShoppingMallReview } from "../../../../structures/IPageIShoppingMallReview";

/**
 * Retrieve filtered and paginated reviews for a specific product sale.
 *
 * Retrieve a comprehensive list of product reviews for a specific sale listing
 * with advanced filtering and search capabilities. This operation provides
 * buyers with detailed feedback from other customers who purchased the same
 * product.
 *
 * The operation supports multiple filtering dimensions including star rating
 * ranges, verified purchase status, review date ranges, and keyword search
 * within review content. Results can be sorted by helpfulness votes, rating
 * (highest/lowest first), or chronological order (newest/oldest first).
 * Pagination enables efficient browsing of large review collections.
 *
 * Security and data integrity considerations include ensuring only approved and
 * published reviews are returned to public users. Reviews flagged for
 * moderation or deleted are excluded from results. The response includes review
 * metadata such as helpfulness vote counts, seller responses if available, and
 * verification badges for confirmed purchases.
 *
 * This operation integrates with the shopping_mall_reviews table as defined in
 * the Prisma schema, incorporating relationships to buyers, sales, review
 * images, seller responses, and helpfulness votes. The response provides review
 * summary information optimized for product detail page displays, helping
 * buyers assess product quality and seller reliability before making purchase
 * decisions.
 *
 * @param props.connection
 * @param props.saleId Unique identifier of the target product sale
 * @param props.body Search criteria, filtering options, and pagination
 *   parameters for review retrieval
 * @path /shoppingMall/sales/:saleId/reviews
 * @accessor api.functional.shoppingMall.sales.reviews.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /** Unique identifier of the target product sale */
    saleId: string & tags.Format<"uuid">;

    /**
     * Search criteria, filtering options, and pagination parameters for
     * review retrieval
     */
    body: IShoppingMallReview.IRequest;
  };
  export type Body = IShoppingMallReview.IRequest;
  export type Response = IPageIShoppingMallReview.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/sales/:saleId/reviews",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/shoppingMall/sales/${encodeURIComponent(props.saleId ?? "null")}/reviews`;
  export const random = (): IPageIShoppingMallReview.ISummary =>
    typia.random<IPageIShoppingMallReview.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("saleId")(() => typia.assert(props.saleId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
