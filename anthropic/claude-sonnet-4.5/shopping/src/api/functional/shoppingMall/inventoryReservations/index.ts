import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallInventoryReservation } from "../../../structures/IShoppingMallInventoryReservation";

/**
 * Delete an inventory reservation record to release the temporarily held stock
 * quantity back to available inventory. This operation is used when a
 * reservation is no longer needed and should be cancelled.
 *
 * Inventory reservations are created during the checkout process to temporarily
 * hold product quantities and prevent overselling while a buyer completes their
 * purchase. Each reservation has an expiration time, after which it becomes
 * invalid. This operation allows for manual cancellation of reservations before
 * their natural expiration.
 *
 * Common use cases include: (1) When a buyer removes items from their cart
 * before checkout completion, (2) When a checkout session is abandoned and
 * needs cleanup, (3) When an order is successfully placed and the reservation
 * should be released as inventory is deducted through the order fulfillment
 * process, (4) When system cleanup processes remove expired or orphaned
 * reservations.
 *
 * Security considerations: The operation validates that the reservation exists
 * and is in a valid state for deletion. The system ensures that releasing the
 * reservation properly updates the corresponding inventory stock levels. After
 * deletion, the reserved quantity becomes available again for other buyers to
 * purchase.
 *
 * This operation integrates with the shopping_mall_inventory_reservations table
 * from the Prisma schema. The deletion is permanent and cannot be undone. If
 * the reservation has already been consumed by order placement, the operation
 * may fail or have no effect depending on business rules.
 *
 * @param props.connection
 * @param props.reservationId Unique identifier of the target inventory
 *   reservation to be deleted
 * @path /shoppingMall/inventoryReservations/:reservationId
 * @accessor api.functional.shoppingMall.inventoryReservations.erase
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function erase(
  connection: IConnection,
  props: erase.Props,
): Promise<erase.Response> {
  return true === connection.simulate
    ? erase.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...erase.METADATA,
          path: erase.path(props),
          status: null,
        },
      );
}
export namespace erase {
  export type Props = {
    /** Unique identifier of the target inventory reservation to be deleted */
    reservationId: string & tags.Format<"uuid">;
  };
  export type Response = IShoppingMallInventoryReservation;

  export const METADATA = {
    method: "DELETE",
    path: "/shoppingMall/inventoryReservations/:reservationId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/inventoryReservations/${encodeURIComponent(props.reservationId ?? "null")}`;
  export const random = (): IShoppingMallInventoryReservation =>
    typia.random<IShoppingMallInventoryReservation>();
  export const simulate = (
    connection: IConnection,
    props: erase.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: erase.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("reservationId")(() => typia.assert(props.reservationId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
