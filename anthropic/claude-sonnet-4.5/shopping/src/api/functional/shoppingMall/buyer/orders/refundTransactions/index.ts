/**
 * Retrieve a filtered and paginated list of refund transactions for a specific
 * order in the shopping mall system. This operation provides comprehensive
 * search capabilities for finding refund transactions based on various criteria
 * including transaction status, refund amount ranges, processing dates, and
 * payment method information.
 *
 * The operation supports full pagination with configurable page sizes and
 * sorting options. Users can sort refund transactions by processing date,
 * refund amount, transaction status, or other relevant fields in ascending or
 * descending order. This is particularly useful for buyers tracking their
 * refund status and for admins auditing refund processing.
 *
 * Security considerations include authorization checks to ensure only the order
 * owner (buyer) or platform administrators can access refund transaction
 * details. The operation integrates with the shopping_mall_refund_transactions
 * table as defined in the Prisma schema, providing complete refund payment
 * processing information including transaction IDs, amounts, payment methods,
 * processing timestamps, and status tracking.
 *
 * This operation is typically used after a refund request has been approved,
 * allowing buyers to monitor the actual payment processing and track when
 * refunds are credited back to their payment methods. It provides transparency
 * in the refund workflow and helps resolve customer inquiries about refund
 * timing.
 *
 * @param props.connection
 * @param props.orderId Unique identifier of the target order (global scope)
 * @param props.body Search criteria and pagination parameters for filtering
 *   refund transactions by status, date range, amount, and payment method
 * @path /shoppingMall/buyer/orders/:orderId/refundTransactions
 * @accessor api.functional.shoppingMall.buyer.orders.refundTransactions.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /** Unique identifier of the target order (global scope) */
    orderId: string & tags.Format<"uuid">;

    /**
     * Search criteria and pagination parameters for filtering refund
     * transactions by status, date range, amount, and payment method
     */
    body: IShoppingMallRefundTransaction.IRequest;
  };
  export type Body = IShoppingMallRefundTransaction.IRequest;
  export type Response = IPageIShoppingMallRefundTransaction.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/buyer/orders/:orderId/refundTransactions",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/shoppingMall/buyer/orders/${encodeURIComponent(props.orderId ?? "null")}/refundTransactions`;
  export const random = (): IPageIShoppingMallRefundTransaction.ISummary =>
    typia.random<IPageIShoppingMallRefundTransaction.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("orderId")(() => typia.assert(props.orderId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
