import { IShoppingMallSaleQuestion } from "../../../../../structures/IShoppingMallSaleQuestion";

/**
 * Submit a new question about a specific product sale.
 *
 * Create a new customer question (inquiry) for a specific product sale in the
 * shopping marketplace. This operation enables authenticated buyers to ask
 * sellers questions about products they are considering purchasing,
 * facilitating informed buying decisions through direct communication.
 *
 * The operation automatically associates the question with the authenticated
 * buyer (extracted from JWT token) and the specified product sale. Questions
 * are submitted for seller review and response, creating a transparent Q&A
 * system that benefits all potential buyers researching the same product.
 *
 * Security considerations include authentication requirements to prevent spam
 * and associate questions with verified buyer accounts. The buyer_id field is
 * automatically populated from the authentication token, preventing buyers from
 * submitting questions on behalf of others. Rate limiting may be applied to
 * prevent question spam.
 *
 * The operation integrates with the shopping_mall_sale_questions table as
 * defined in the Prisma schema. Upon successful creation, the question becomes
 * visible to the seller for answering and may be published for other buyers to
 * view, depending on moderation settings. This supports the buyer research
 * workflow and improves marketplace transparency.
 *
 * Related operations include retrieving questions (PATCH
 * /sales/{saleCode}/questions) to view existing Q&A before submitting, and
 * sellers responding to questions through their dedicated answer management
 * endpoints.
 *
 * @param props.connection
 * @param props.saleCode Unique business identifier code of the target product
 *   sale (global scope)
 * @param props.body Question content and details submitted by the buyer about
 *   the product sale
 * @path /shoppingMall/buyer/sales/:saleCode/questions
 * @accessor api.functional.shoppingMall.buyer.sales.questions.postBySalecode
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function postBySalecode(
  connection: IConnection,
  props: postBySalecode.Props,
): Promise<postBySalecode.Response> {
  return true === connection.simulate
    ? postBySalecode.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...postBySalecode.METADATA,
          path: postBySalecode.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace postBySalecode {
  export type Props = {
    /**
     * Unique business identifier code of the target product sale (global
     * scope)
     */
    saleCode: string;

    /**
     * Question content and details submitted by the buyer about the product
     * sale
     */
    body: IShoppingMallSaleQuestion.ICreate;
  };
  export type Body = IShoppingMallSaleQuestion.ICreate;
  export type Response = IShoppingMallSaleQuestion;

  export const METADATA = {
    method: "POST",
    path: "/shoppingMall/buyer/sales/:saleCode/questions",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/shoppingMall/buyer/sales/${encodeURIComponent(props.saleCode ?? "null")}/questions`;
  export const random = (): IShoppingMallSaleQuestion =>
    typia.random<IShoppingMallSaleQuestion>();
  export const simulate = (
    connection: IConnection,
    props: postBySalecode.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: postBySalecode.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("saleCode")(() => typia.assert(props.saleCode));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

