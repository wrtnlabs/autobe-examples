import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallInventoryReservation } from "../../../../structures/IShoppingMallInventoryReservation";

/**
 * Retrieve complete details of a specific inventory reservation record from the
 * system. This operation provides comprehensive information about a temporary
 * inventory hold that was created during the checkout process to prevent
 * overselling.
 *
 * Inventory reservations are critical for maintaining inventory accuracy during
 * the purchase flow. When a buyer proceeds to checkout, inventory is
 * temporarily reserved to ensure availability while payment is being processed.
 * This operation allows tracking and verification of these temporary holds.
 *
 * The reservation record includes the reserved SKU identifier, quantity held,
 * creation timestamp, expiration timestamp, and associated order information.
 * Reservations automatically expire after a configured time period if the order
 * is not completed, releasing the inventory back to available stock.
 *
 * Security considerations: Only authenticated users with appropriate
 * permissions can access reservation details. Buyers can view their own
 * reservations, while sellers can view reservations for their products, and
 * admins have full access to all reservation records.
 *
 * This operation integrates with the shopping_mall_inventory_reservations table
 * as defined in the Prisma schema, providing all available reservation fields
 * and relationships to SKUs and orders.
 *
 * @param props.connection
 * @param props.reservationId Unique identifier of the target inventory
 *   reservation
 * @path /shoppingMall/buyer/inventoryReservations/:reservationId
 * @accessor api.functional.shoppingMall.buyer.inventoryReservations.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique identifier of the target inventory reservation */
    reservationId: string & tags.Format<"uuid">;
  };
  export type Response = IShoppingMallInventoryReservation;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/buyer/inventoryReservations/:reservationId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/buyer/inventoryReservations/${encodeURIComponent(props.reservationId ?? "null")}`;
  export const random = (): IShoppingMallInventoryReservation =>
    typia.random<IShoppingMallInventoryReservation>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("reservationId")(() => typia.assert(props.reservationId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
