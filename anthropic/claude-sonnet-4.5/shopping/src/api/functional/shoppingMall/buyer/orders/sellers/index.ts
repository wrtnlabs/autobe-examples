/**
 * Retrieve a filtered and paginated list of seller-specific order segments for
 * a given parent order. This operation provides comprehensive search
 * capabilities for analyzing how a multi-seller order is distributed across
 * different sellers, with each seller managing their portion of the order
 * independently.
 *
 * The operation supports advanced filtering by seller information, order item
 * details, fulfillment status, shipping tracking, payment status, and
 * commission calculations. Users can search for seller segments based on
 * various criteria including seller identity, item quantities, subtotal
 * amounts, shipping costs, order status, and payout status.
 *
 * Security considerations include proper authorization to ensure only
 * authorized users (buyers viewing their own orders, sellers viewing their
 * segments, or admins) can access order seller information. The response
 * includes comprehensive seller segment data including all items assigned to
 * each seller, shipping details, financial breakdowns, and current fulfillment
 * status.
 *
 * This operation integrates with the shopping_mall_order_sellers table as
 * defined in the Prisma schema, along with related order items, seller
 * information, and shipping data. The response provides seller segment summary
 * information optimized for order management displays, with support for
 * pagination and sorting by various fields including creation date, status, and
 * financial amounts.
 *
 * @param props.connection
 * @param props.orderId Unique identifier of the target parent order (global
 *   scope)
 * @param props.body Search criteria and pagination parameters for filtering
 *   seller segments within the order
 * @path /shoppingMall/buyer/orders/:orderId/sellers
 * @accessor api.functional.shoppingMall.buyer.orders.sellers.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /** Unique identifier of the target parent order (global scope) */
    orderId: string & tags.Format<"uuid">;

    /**
     * Search criteria and pagination parameters for filtering seller
     * segments within the order
     */
    body: IShoppingMallOrderSeller.IRequest;
  };
  export type Body = IShoppingMallOrderSeller.IRequest;
  export type Response = IPageIShoppingMallOrderSeller.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/buyer/orders/:orderId/sellers",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/shoppingMall/buyer/orders/${encodeURIComponent(props.orderId ?? "null")}/sellers`;
  export const random = (): IPageIShoppingMallOrderSeller.ISummary =>
    typia.random<IPageIShoppingMallOrderSeller.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("orderId")(() => typia.assert(props.orderId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

