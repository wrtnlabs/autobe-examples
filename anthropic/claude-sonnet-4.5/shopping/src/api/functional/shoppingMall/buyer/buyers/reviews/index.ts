import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallReview } from "../../../../../structures/IShoppingMallReview";
import { IPageIShoppingMallReview } from "../../../../../structures/IPageIShoppingMallReview";

/**
 * Retrieve a comprehensive list of all product reviews authored by a specific
 * buyer account with advanced filtering and search capabilities. This operation
 * enables buyers to view and manage their complete review history across all
 * purchases made on the platform.
 *
 * The operation supports filtering by multiple criteria including the products
 * reviewed, star ratings given, review creation date ranges, and review
 * publication status. Buyers can search within their own review content to find
 * specific feedback they provided. Results can be sorted chronologically or by
 * product category, helping buyers track their feedback contributions over
 * time.
 *
 * Security considerations include ensuring buyers can only access their own
 * reviews when using standard buyer authentication, while administrators may
 * access any buyer's review history for moderation and support purposes. The
 * response includes complete review details along with associated product
 * information, seller responses if available, and helpfulness metrics from
 * other users.
 *
 * This operation integrates with the shopping_mall_reviews table as defined in
 * the Prisma schema, incorporating relationships to the buyer account,
 * associated sales, review images, and engagement metrics. The response
 * provides detailed review information suitable for buyer profile pages and
 * review management interfaces, enabling buyers to track their marketplace
 * participation and edit or delete their reviews as needed.
 *
 * @param props.connection
 * @param props.buyerId Unique identifier of the target buyer account
 * @param props.body Search criteria, filtering options, and pagination
 *   parameters for buyer review retrieval
 * @path /shoppingMall/buyer/buyers/:buyerId/reviews
 * @accessor api.functional.shoppingMall.buyer.buyers.reviews.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /** Unique identifier of the target buyer account */
    buyerId: string & tags.Format<"uuid">;

    /**
     * Search criteria, filtering options, and pagination parameters for
     * buyer review retrieval
     */
    body: IShoppingMallReview.IRequest;
  };
  export type Body = IShoppingMallReview.IRequest;
  export type Response = IPageIShoppingMallReview.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/buyer/buyers/:buyerId/reviews",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/shoppingMall/buyer/buyers/${encodeURIComponent(props.buyerId ?? "null")}/reviews`;
  export const random = (): IPageIShoppingMallReview.ISummary =>
    typia.random<IPageIShoppingMallReview.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("buyerId")(() => typia.assert(props.buyerId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
