import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallReviewSellerResponse } from "../../../../structures/IShoppingMallReviewSellerResponse";

/**
 * Retrieve the seller's response associated with a specific product review from
 * the shopping marketplace. This operation allows users to view how sellers
 * have addressed customer feedback and concerns expressed in product reviews.
 *
 * The operation returns the complete seller response information including the
 * response text content, timestamp when the response was posted, and the seller
 * who authored the response. This transparency helps buyers make informed
 * purchase decisions by seeing how sellers engage with customer feedback.
 *
 * Security considerations: This is a public read operation as seller responses
 * are publicly visible alongside their associated reviews. The response data is
 * filtered to show only approved, non-deleted responses. The operation
 * validates that the review exists and that a seller response has been posted
 * before returning data.
 *
 * This operation integrates with the shopping_mall_review_seller_responses
 * table as defined in the Prisma schema. It provides read access to seller
 * engagement with customer reviews, supporting the marketplace's commitment to
 * transparency and customer service visibility.
 *
 * @param props.connection
 * @param props.reviewId Unique identifier of the target review (global scope)
 * @path /shoppingMall/reviews/:reviewId/sellerResponse
 * @accessor api.functional.shoppingMall.reviews.sellerResponse.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique identifier of the target review (global scope) */
    reviewId: string & tags.Format<"uuid">;
  };
  export type Response = IShoppingMallReviewSellerResponse;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/reviews/:reviewId/sellerResponse",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/reviews/${encodeURIComponent(props.reviewId ?? "null")}/sellerResponse`;
  export const random = (): IShoppingMallReviewSellerResponse =>
    typia.random<IShoppingMallReviewSellerResponse>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("reviewId")(() => typia.assert(props.reviewId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
