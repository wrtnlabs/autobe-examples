/**
 * Retrieve a filtered and paginated list of helpfulness votes submitted by
 * buyers for a specific product review. This operation provides comprehensive
 * search capabilities for analyzing vote patterns, including filtering by vote
 * type (helpful vs not helpful), voter identity, and submission timestamps.
 *
 * The operation supports pagination with configurable page sizes and various
 * sorting options such as by vote submission date, voter information, or vote
 * type. This enables detailed analysis of review helpfulness patterns and voter
 * behavior for individual reviews.
 *
 * Security considerations include ensuring that only authenticated users can
 * view detailed vote information, with potential rate limiting to prevent
 * scraping of voter data. The operation respects privacy settings and may
 * filter sensitive voter information based on authorization level.
 *
 * This operation integrates with the shopping_mall_review_helpfulness_votes
 * table as defined in the Prisma schema, providing vote summary information
 * optimized for analytics and display purposes. The response includes vote
 * statistics and patterns to help understand review credibility and
 * usefulness.
 *
 * @param props.connection
 * @param props.reviewId Unique identifier of the target review (global scope)
 * @param props.body Search criteria and pagination parameters for filtering
 *   helpfulness votes
 * @path /shoppingMall/reviews/:reviewId/helpfulnessVotes
 * @accessor api.functional.shoppingMall.reviews.helpfulnessVotes.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /** Unique identifier of the target review (global scope) */
    reviewId: string & tags.Format<"uuid">;

    /**
     * Search criteria and pagination parameters for filtering helpfulness
     * votes
     */
    body: IShoppingMallReviewHelpfulnessVote.IRequest;
  };
  export type Body = IShoppingMallReviewHelpfulnessVote.IRequest;
  export type Response = IPageIShoppingMallReviewHelpfulnessVote.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/reviews/:reviewId/helpfulnessVotes",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/shoppingMall/reviews/${encodeURIComponent(props.reviewId ?? "null")}/helpfulnessVotes`;
  export const random = (): IPageIShoppingMallReviewHelpfulnessVote.ISummary =>
    typia.random<IPageIShoppingMallReviewHelpfulnessVote.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("reviewId")(() => typia.assert(props.reviewId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
