/**
 * Retrieve a filtered and paginated list of product review images from a
 * specific review in the shopping mall platform. This operation provides
 * advanced search capabilities for finding review images based on multiple
 * criteria including upload date ranges, image status, display order, and other
 * relevant filters.
 *
 * The operation supports comprehensive pagination with configurable page sizes
 * and sorting options. Images can be sorted by upload date, display order, or
 * other relevant fields in ascending or descending order. This is particularly
 * useful for buyers viewing review images and for moderators managing review
 * content.
 *
 * Security considerations include appropriate filtering of images based on
 * review status and moderation state. Only approved review images are visible
 * to public users, while moderators and admins can access images from reviews
 * under moderation. The operation integrates with the
 * shopping_mall_review_images table as defined in the Prisma schema.
 *
 * This operation is essential for the review browsing experience, allowing
 * buyers to see visual evidence of product quality through images uploaded by
 * verified purchasers. It also supports administrative workflows for content
 * moderation and quality control.
 *
 * @param props.connection
 * @param props.reviewId Unique identifier of the target product review
 * @param props.body Search criteria and pagination parameters for filtering
 *   review images
 * @path /shoppingMall/reviews/:reviewId/images
 * @accessor api.functional.shoppingMall.reviews.images.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /** Unique identifier of the target product review */
    reviewId: string & tags.Format<"uuid">;

    /** Search criteria and pagination parameters for filtering review images */
    body: IShoppingMallReviewImage.IRequest;
  };
  export type Body = IShoppingMallReviewImage.IRequest;
  export type Response = IPageIShoppingMallReviewImage.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/reviews/:reviewId/images",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/shoppingMall/reviews/${encodeURIComponent(props.reviewId ?? "null")}/images`;
  export const random = (): IPageIShoppingMallReviewImage.ISummary =>
    typia.random<IPageIShoppingMallReviewImage.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("reviewId")(() => typia.assert(props.reviewId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

