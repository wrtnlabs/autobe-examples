/**
 * Search and retrieve a filtered, paginated list of product reviews.
 *
 * Retrieve a comprehensive, filterable list of product reviews from the
 * shopping mall platform. This operation provides advanced search and filtering
 * capabilities for discovering reviews based on multiple criteria including
 * product identification, seller identification, star ratings, verified
 * purchase status, review content keywords, and submission date ranges.
 *
 * The operation supports full pagination with configurable page sizes and
 * multiple sorting options. Users can sort reviews by submission date, rating
 * value, helpfulness vote count, or other relevant metrics in ascending or
 * descending order. This enables both chronological and quality-based review
 * browsing experiences.
 *
 * Security and access control considerations: Public access is allowed for
 * viewing approved reviews, while administrative users can access all reviews
 * including those pending moderation or flagged for policy violations. The
 * operation applies content filtering based on review moderation status and
 * excludes reviews marked as spam or policy-violating unless accessed by
 * administrators.
 *
 * This operation integrates with the shopping_mall_reviews table as defined in
 * the Prisma schema, incorporating relationships to products
 * (shopping_mall_sales), buyers (shopping_mall_buyers), and associated review
 * images (shopping_mall_review_images). The response includes review summary
 * information optimized for list displays, with options to include additional
 * details such as seller responses, helpfulness vote counts, and review images
 * based on the request parameters.
 *
 * Related operations that are commonly used in conjunction with this endpoint
 * include individual review detail retrieval (GET /reviews/{reviewId}), review
 * submission (POST /sales/{saleId}/reviews), and review helpfulness voting
 * operations.
 *
 * @param props.connection
 * @param props.body Search criteria and pagination parameters for review
 *   filtering including product ID, seller ID, rating range, verification
 *   status, text search, and date filters
 * @path /shoppingMall/reviews
 * @accessor api.functional.shoppingMall.reviews.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
