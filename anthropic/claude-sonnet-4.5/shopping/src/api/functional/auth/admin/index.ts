/**
 * Register a new platform administrator account and issue JWT tokens.
 *
 * Creates a new administrator account in the platform and issues initial JWT
 * authentication tokens (access token and refresh token) for immediate system
 * access.
 *
 * This endpoint is used during admin onboarding to establish new administrative
 * accounts with elevated privileges. Upon successful registration, the admin
 * receives both an access token for API authentication and a refresh token for
 * obtaining new access tokens when they expire.
 *
 * The operation validates the provided admin credentials, creates a new record
 * in the shopping_mall_admins table with a securely hashed password, and
 * generates a session record in shopping_mall_admin_sessions for authentication
 * tracking and audit trails.
 *
 * Security considerations include password strength validation, email
 * uniqueness verification, and secure token generation following JWT best
 * practices. The issued tokens contain the admin's identity claims and
 * permission scopes necessary for platform governance operations.
 *
 * This is a public endpoint that does not require prior authentication, as it
 * serves as the entry point for creating new admin accounts in the system.
 *
 * @param props.connection
 * @param props.body Admin registration information including credentials and
 *   profile data
 * @setHeader token.access Authorization
 *
 * @path /auth/admin/join
 * @accessor api.functional.auth.admin.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
export namespace join {
  export type Props = {
    /** Admin registration information including credentials and profile data */
    body: IShoppingMallAdmin.ICreate;
  };
  export type Body = IShoppingMallAdmin.ICreate;
  export type Response = IShoppingMallAdmin.IAuthorized;

  export const METADATA = {
    method: "POST",
    path: "/auth/admin/join",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/admin/join";
  export const random = (): IShoppingMallAdmin.IAuthorized =>
    typia.random<IShoppingMallAdmin.IAuthorized>();
  export const simulate = (
    connection: IConnection,
    props: join.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: join.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

