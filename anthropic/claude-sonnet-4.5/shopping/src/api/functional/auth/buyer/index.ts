/**
 * Register a new buyer account in the shopping mall platform and receive
 * initial JWT authentication tokens.
 *
 * This endpoint creates a new authenticated buyer account, allowing customers
 * to access the full range of platform features including shopping cart
 * management, order placement, review submission, and order tracking. Upon
 * successful registration, the system immediately issues both an access token
 * and a refresh token, enabling the buyer to start using the platform without
 * requiring a separate login step.
 *
 * The registration process validates the provided credentials, creates the
 * buyer record in the shopping_mall_buyers table, and generates a new session
 * record in shopping_mall_buyer_sessions for authentication tracking and audit
 * purposes. The system enforces unique email addresses to prevent duplicate
 * accounts.
 *
 * Security considerations include password strength requirements, email
 * validation, and secure token generation using JWT standards. The initial
 * session is created with appropriate expiration times for both access and
 * refresh tokens according to platform security policies.
 *
 * This operation is publicly accessible and does not require any prior
 * authentication. It serves as the entry point for new customers to join the
 * marketplace ecosystem.
 *
 * @param props.connection
 * @param props.body Buyer registration information including credentials and
 *   profile data
 * @setHeader token.access Authorization
 *
 * @path /auth/buyer/join
 * @accessor api.functional.auth.buyer.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
