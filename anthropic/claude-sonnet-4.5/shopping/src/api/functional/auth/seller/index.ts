/**
 * Register a new seller account and issue JWT tokens for the
 * shopping_mall_sellers table.
 *
 * Register a new seller account in the e-commerce marketplace and issue initial
 * JWT authentication tokens.
 *
 * This endpoint allows new merchants to create seller accounts on the platform.
 * Upon successful registration, the seller receives both access and refresh JWT
 * tokens, enabling immediate access to the seller dashboard and store
 * management features.
 *
 * The registration process creates a new record in the shopping_mall_sellers
 * database table with the provided seller information. The seller account is
 * created with member-level permissions, granting access to product listing
 * management, inventory control, order processing, and sales analytics.
 *
 * Security considerations include password hashing, email validation, and
 * duplicate account prevention. The system validates that the email address is
 * not already registered to prevent duplicate seller accounts.
 *
 * The response includes the complete seller profile information along with JWT
 * tokens (access token and refresh token) that should be used for subsequent
 * authenticated requests to seller-specific endpoints.
 *
 * @param props.connection
 * @param props.body Seller registration information including credentials and
 *   profile details
 * @setHeader token.access Authorization
 *
 * @path /auth/seller/join
 * @accessor api.functional.auth.seller.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
