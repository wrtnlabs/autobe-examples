import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { getShoppingMallSalesSaleCodeImagesImageId } from "../../../../providers/getShoppingMallSalesSaleCodeImagesImageId";

import { IShoppingMallSaleImage } from "../../../../api/structures/IShoppingMallSaleImage";

@Controller("/shoppingMall/sales/:saleCode/images/:imageId")
export class ShoppingmallSalesImagesController {
  /**
   * Retrieve detailed information about a specific product image associated
   * with a sale listing. This operation provides access to individual image
   * metadata including the image URL, display order, and other relevant
   * properties.
   *
   * The operation requires both the sale's unique business code and the image's
   * UUID identifier to locate the exact image resource. This dual-parameter
   * approach ensures precise image retrieval within the context of a specific
   * product sale.
   *
   * Security considerations include validating that the requested image
   * actually belongs to the specified sale to prevent unauthorized access to
   * image resources from other products. The operation returns complete image
   * details suitable for product display pages and image galleries.
   *
   * This operation integrates with the shopping_mall_sale_images table as
   * defined in the Prisma schema, providing access to all image properties
   * including URLs, alt text, and ordering information for proper visual
   * presentation.
   *
   * @param connection
   * @param saleCode Unique business identifier code of the target product sale
   *   (global scope)
   * @param imageId Unique identifier of the target product image
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @TypedParam("saleCode")
    saleCode: string,
    @TypedParam("imageId")
    imageId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallSaleImage> {
    try {
      return await getShoppingMallSalesSaleCodeImagesImageId({
        saleCode,
        imageId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
