import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { getShoppingMallSalesSaleCodeQuestionsQuestionIdAnswer } from "../../../../../providers/getShoppingMallSalesSaleCodeQuestionsQuestionIdAnswer";

import { IShoppingMallSaleQuestionAnswer } from "../../../../../api/structures/IShoppingMallSaleQuestionAnswer";

@Controller("/shoppingMall/sales/:saleCode/questions/:questionId/answer")
export class ShoppingmallSalesQuestionsAnswerController {
  /**
   * Retrieve the seller's response to a customer question posted on a specific
   * product sale listing.
   *
   * This operation returns the answer that a seller has provided to a
   * customer's question about their product. The answer includes the response
   * text, timestamp, and seller information. If no answer has been posted yet,
   * the operation returns null or an appropriate not-found response.
   *
   * This is a public endpoint that allows potential buyers to view
   * question-and-answer exchanges about products, helping them make informed
   * purchase decisions. The transparency of product Q&A supports buyer
   * confidence and reduces purchase hesitation.
   *
   * The operation integrates with the shopping_mall_sale_question_answers table
   * as defined in the Prisma schema. It validates that the question belongs to
   * the specified sale and returns the most recent answer if multiple answers
   * exist (though typically only one answer per question is allowed).
   *
   * @param connection
   * @param saleCode Unique business identifier code of the target product sale
   *   (global scope)
   * @param questionId Unique identifier of the target question
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @TypedParam("saleCode")
    saleCode: string,
    @TypedParam("questionId")
    questionId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallSaleQuestionAnswer> {
    try {
      return await getShoppingMallSalesSaleCodeQuestionsQuestionIdAnswer({
        saleCode,
        questionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
