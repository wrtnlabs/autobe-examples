import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallSalesSaleCodeQuestions } from "../../../../providers/patchShoppingMallSalesSaleCodeQuestions";
import { patchShoppingMallSalesShoppingMallSaleCodeQuestions } from "../../../../providers/patchShoppingMallSalesShoppingMallSaleCodeQuestions";
import { getShoppingMallSalesSaleCodeQuestionsQuestionId } from "../../../../providers/getShoppingMallSalesSaleCodeQuestionsQuestionId";
import { deleteShoppingMallSalesSaleCodeQuestionsQuestionId } from "../../../../providers/deleteShoppingMallSalesSaleCodeQuestionsQuestionId";
import { BuyerAuth } from "../../../../decorators/BuyerAuth";
import { BuyerPayload } from "../../../../decorators/payload/BuyerPayload";

import { IPageIShoppingMallSaleQuestion } from "../../../../api/structures/IPageIShoppingMallSaleQuestion";
import { IShoppingMallSaleQuestion } from "../../../../api/structures/IShoppingMallSaleQuestion";

@Controller("/shoppingMall/sales")
export class ShoppingmallSalesQuestionsController {
  /**
   * Retrieve a paginated list of customer questions (inquiries) submitted for a
   * specific product sale in the shopping marketplace. This operation allows
   * buyers to browse existing questions and answers to gain additional product
   * information before making a purchase decision.
   *
   * The operation supports comprehensive search and filtering capabilities
   * including searching by question content, filtering by answer status
   * (answered vs unanswered), and sorting by recency or helpfulness. Buyers can
   * use this to find answers to common questions without needing to submit
   * duplicate inquiries.
   *
   * Security considerations include appropriate filtering based on question
   * status and visibility. Only published questions should be visible to
   * general buyers, while sellers and admins may see additional questions
   * pending moderation. The operation integrates with the
   * shopping_mall_sale_questions table as defined in the Prisma schema,
   * returning question summaries optimized for list displays along with seller
   * answers when available.
   *
   * This operation serves the critical buyer workflow of product research and
   * information gathering, helping reduce purchase uncertainty and improve
   * conversion rates by providing transparent product information through
   * community questions and seller responses.
   *
   * @param connection
   * @param saleCode Unique business identifier code of the target product sale
   *   (global scope)
   * @param body Search criteria and pagination parameters for filtering product
   *   sale questions
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch(":saleCode/questions")
  public async patchBySalecode(
    @TypedParam("saleCode")
    saleCode: string,
    @TypedBody()
    body: IShoppingMallSaleQuestion.IRequest,
  ): Promise<IPageIShoppingMallSaleQuestion.ISummary> {
    try {
      return await patchShoppingMallSalesSaleCodeQuestions({
        saleCode,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a paginated list of customer questions (inquiries) submitted for a
   * specific product sale in the shopping marketplace. This operation allows
   * buyers to browse existing questions and answers to gain additional product
   * information before making a purchase decision.
   *
   * The operation supports comprehensive search and filtering capabilities
   * including searching by question content, filtering by answer status
   * (answered vs unanswered), and sorting by recency or helpfulness. Buyers can
   * use this to find answers to common questions without needing to submit
   * duplicate inquiries.
   *
   * Security considerations include appropriate filtering based on question
   * status and visibility. Only published questions should be visible to
   * general buyers, while sellers and admins may see additional questions
   * pending moderation. The operation integrates with the
   * shopping_mall_sale_questions table as defined in the Prisma schema,
   * returning question summaries optimized for list displays along with seller
   * answers when available.
   *
   * This operation serves the critical buyer workflow of product research and
   * information gathering, helping reduce purchase uncertainty and improve
   * conversion rates by providing transparent product information through
   * community questions and seller responses.
   *
   * @param connection
   * @param shoppingMallSaleCode Unique business identifier code of the target
   *   product sale (global scope)
   * @param body Search criteria and pagination parameters for filtering product
   *   sale questions
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch(":shoppingMallSaleCode/questions")
  public async patchByShoppingmallsalecode(
    @TypedParam("shoppingMallSaleCode")
    shoppingMallSaleCode: string,
    @TypedBody()
    body: IShoppingMallSaleQuestion.IRequest,
  ): Promise<IPageIShoppingMallSaleQuestion.ISummary> {
    try {
      return await patchShoppingMallSalesShoppingMallSaleCodeQuestions({
        shoppingMallSaleCode,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific customer question submitted
   * for a product sale. This operation returns the complete question context
   * including the buyer who asked the question, the question content,
   * submission timestamp, and any seller response that may have been provided.
   *
   * The operation is accessible to multiple actors with different visibility
   * rules. Buyers can view questions and answers to help inform purchase
   * decisions. Sellers can view questions on their products to monitor customer
   * inquiries and provide answers. Admins have full visibility for moderation
   * and support purposes.
   *
   * Security considerations include verifying that sellers can only access
   * questions on their own products, while buyers and admins have broader
   * access. The question content and any associated answer are returned
   * together to provide complete conversational context. This operation
   * integrates with the shopping_mall_sale_questions and
   * shopping_mall_sale_question_answers tables as defined in the Prisma
   * schema.
   *
   * Related operations include listing all questions for a sale (PATCH
   * /sales/{saleCode}/questions) and creating new questions (POST
   * /sales/{saleCode}/questions). This detail retrieval is typically used after
   * browsing the question list to view full question and answer content.
   *
   * @param connection
   * @param saleCode Unique business identifier code of the target product sale
   *   (global scope)
   * @param questionId Unique identifier of the target question
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":saleCode/questions/:questionId")
  public async at(
    @TypedParam("saleCode")
    saleCode: string,
    @TypedParam("questionId")
    questionId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallSaleQuestion> {
    try {
      return await getShoppingMallSalesSaleCodeQuestionsQuestionId({
        saleCode,
        questionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently remove a customer question from a specific product sale listing
   * in the shopping marketplace.
   *
   * This operation allows authorized users to delete questions that have been
   * posted about a product. Buyers can delete their own questions, while
   * administrators can delete any question. The deletion is permanent and
   * removes the question record from the database along with any associated
   * answers if they exist.
   *
   * Security considerations include authorization checks to ensure only the
   * question author or administrators can delete questions. The operation
   * validates that the question belongs to the specified sale before deletion.
   * For buyer requests, the system verifies ownership of the question. Rate
   * limiting may apply to prevent abuse of the deletion functionality.
   *
   * This operation integrates with the shopping_mall_sale_questions table as
   * defined in the Prisma schema. Upon successful deletion, the question and
   * any related answers are removed from the system. The sale itself remains
   * unaffected by this operation.
   *
   * @param connection
   * @param saleCode Unique business identifier code of the target product sale
   *   (global scope)
   * @param questionId Unique identifier of the target question to be deleted
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":saleCode/questions/:questionId")
  public async erase(
    @BuyerAuth()
    buyer: BuyerPayload,
    @TypedParam("saleCode")
    saleCode: string,
    @TypedParam("questionId")
    questionId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallSaleQuestion> {
    try {
      return await deleteShoppingMallSalesSaleCodeQuestionsQuestionId({
        buyer,
        saleCode,
        questionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
