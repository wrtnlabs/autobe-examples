import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia from "typia";
import { patchShoppingMallSales } from "../../../providers/patchShoppingMallSales";
import { getShoppingMallSalesSaleCode } from "../../../providers/getShoppingMallSalesSaleCode";

import { IPageIShoppingMallSale } from "../../../api/structures/IPageIShoppingMallSale";
import { IShoppingMallSale } from "../../../api/structures/IShoppingMallSale";

@Controller("/shoppingMall/sales")
export class ShoppingmallSalesController {
  /**
   * Retrieve a comprehensive, filtered, and paginated list of product sales
   * listings from the shopping mall marketplace. This operation provides
   * advanced search and filtering capabilities essential for product discovery,
   * inventory management, and marketplace analytics.
   *
   * The search supports multiple filter criteria including partial product name
   * matching, seller filtering, category hierarchy navigation, price range
   * constraints, sale status filtering (active, paused, sold_out), and stock
   * availability checks. Buyers can discover products across the marketplace,
   * sellers can manage their inventory listings, and admins can monitor all
   * marketplace activity.
   *
   * Pagination is fully configurable with adjustable page sizes and supports
   * multiple sorting options including creation date, price
   * (ascending/descending), popularity metrics, and alphabetical ordering. The
   * response returns summarized sale information optimized for list displays,
   * including essential product details, pricing, primary images, seller
   * information, and current stock status.
   *
   * Security and authorization are role-based: public access allows basic
   * product browsing for unauthenticated users, authenticated buyers receive
   * personalized features like wishlist status, sellers can filter to view only
   * their own listings, and admins have unrestricted access to all marketplace
   * data with additional moderation fields.
   *
   * This operation integrates with the shopping_mall_sales table as defined in
   * the Prisma schema, incorporating relationships to sellers, categories,
   * SKUs, and images. The search is optimized for performance with appropriate
   * database indexing on frequently queried fields like category_id, seller_id,
   * and created_at.
   *
   * @param connection
   * @param body Search criteria, filtering options, sorting preferences, and
   *   pagination parameters for product sales discovery
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IShoppingMallSale.IRequest,
  ): Promise<IPageIShoppingMallSale.ISummary> {
    try {
      return await patchShoppingMallSales({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve complete details of a product sale listing from the shopping
   * marketplace using its unique business identifier code. This operation
   * provides comprehensive information about the product including its
   * description, pricing across all SKU variants, images, seller details,
   * category assignment, and current inventory availability.
   *
   * The operation returns the full sale entity with all related data necessary
   * for displaying a detailed product page. This includes variant
   * configurations (attributes and values), SKU-level pricing and stock
   * information, product images, and metadata about the sale's status and
   * visibility.
   *
   * Security considerations: This is a public endpoint accessible without
   * authentication, as product details are meant to be viewable by all
   * marketplace visitors. However, certain administrative fields or draft
   * listings may be filtered based on the sale's published status. Rate
   * limiting may be applied to prevent scraping or abuse.
   *
   * This operation integrates with the shopping_mall_sales table as defined in
   * the Prisma schema, incorporating the unique code constraint for
   * business-friendly URLs. The code parameter allows for more readable and
   * SEO-friendly product URLs compared to UUID-based identifiers. The response
   * includes all sale properties and relationships necessary for a complete
   * product detail view.
   *
   * @param connection
   * @param saleCode Unique business identifier code of the target product sale
   *   listing (global scope)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":saleCode")
  public async at(
    @TypedParam("saleCode")
    saleCode: string,
  ): Promise<IShoppingMallSale> {
    try {
      return await getShoppingMallSalesSaleCode({
        saleCode,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
