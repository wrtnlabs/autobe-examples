import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallSalesSaleCodeVariantAttributes } from "../../../../providers/patchShoppingMallSalesSaleCodeVariantAttributes";
import { getShoppingMallSalesSaleCodeVariantAttributesVariantAttributeId } from "../../../../providers/getShoppingMallSalesSaleCodeVariantAttributesVariantAttributeId";

import { IPageIShoppingMallSaleVariantAttribute } from "../../../../api/structures/IPageIShoppingMallSaleVariantAttribute";
import { IShoppingMallSaleVariantAttribute } from "../../../../api/structures/IShoppingMallSaleVariantAttribute";

@Controller("/shoppingMall/sales/:saleCode/variantAttributes")
export class ShoppingmallSalesVariantattributesController {
  /**
   * Retrieve a filtered and paginated list of variant attributes associated
   * with a specific product sale in the shopping marketplace. This operation
   * provides advanced search capabilities for finding variant attributes based
   * on various criteria including attribute name, display order, and attribute
   * status.
   *
   * Variant attributes represent the configurable dimensions of a product (such
   * as Color, Size, Material, Style) that allow customers to select specific
   * product variants. Each attribute contains multiple variant values that
   * represent the specific options available (e.g., Color attribute has values
   * like Red, Blue, Green). This operation returns the attribute definitions
   * for a given sale, which can be used to display product configuration
   * options to buyers.
   *
   * The operation supports comprehensive pagination with configurable page
   * sizes and sorting options. Results can be sorted by display order,
   * attribute name, creation date, or other relevant fields in ascending or
   * descending order. Advanced filtering allows searching by attribute name
   * patterns or filtering by specific attribute characteristics.
   *
   * Security considerations: This is a read-only operation that retrieves
   * product configuration metadata. It can be accessed by authenticated users
   * who need to view product variant options. The sale is identified by its
   * unique business code, which must exist in the shopping_mall_sales table.
   * The operation integrates with the shopping_mall_sale_variant_attributes
   * table as defined in the Prisma schema, incorporating all available
   * attribute fields and their relationships to variant values.
   *
   * This operation is essential for displaying product configuration
   * interfaces, allowing buyers to understand what customization options are
   * available for a product before making a purchase decision.
   *
   * @param connection
   * @param saleCode Unique business identifier code of the target sale (global
   *   scope)
   * @param body Search criteria and pagination parameters for filtering variant
   *   attributes
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedParam("saleCode")
    saleCode: string,
    @TypedBody()
    body: IShoppingMallSaleVariantAttribute.IRequest,
  ): Promise<IPageIShoppingMallSaleVariantAttribute.ISummary> {
    try {
      return await patchShoppingMallSalesSaleCodeVariantAttributes({
        saleCode,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve comprehensive details about a specific variant attribute
   * definition for a product sale.
   *
   * This operation returns complete information about a single variant
   * attribute, including its name, display configuration, ordering sequence,
   * and any metadata associated with the attribute definition. The variant
   * attribute represents one dimension of product variation (such as 'Color',
   * 'Size', or 'Material') and is identified by its unique ID within the
   * context of a specific sale.
   *
   * The operation requires both the sale's unique business code and the variant
   * attribute's unique identifier to locate the specific attribute definition.
   * This dual-parameter approach ensures clear scoping and prevents ambiguity
   * when multiple sales might have similarly named attributes.
   *
   * Security considerations include seller authentication and ownership
   * verification when accessed by sellers, though the operation may also be
   * available to buyers and admins for viewing product variation structures.
   * The seller who owns the sale has full access to view their variant
   * attribute definitions. Buyers can view variant attributes to understand
   * available product options. Admins have oversight access for moderation and
   * support purposes.
   *
   * The operation integrates with the shopping_mall_sale_variant_attributes
   * table as defined in the Prisma schema, returning detailed attribute
   * information that can be used to understand the product's variation
   * structure. This information is typically used in conjunction with variant
   * values and SKU definitions to present complete product options to buyers.
   *
   * @param connection
   * @param saleCode Unique business identifier code of the target sale (global
   *   scope)
   * @param variantAttributeId Unique identifier of the target variant attribute
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":variantAttributeId")
  public async at(
    @TypedParam("saleCode")
    saleCode: string,
    @TypedParam("variantAttributeId")
    variantAttributeId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallSaleVariantAttribute> {
    try {
      return await getShoppingMallSalesSaleCodeVariantAttributesVariantAttributeId(
        {
          saleCode,
          variantAttributeId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
