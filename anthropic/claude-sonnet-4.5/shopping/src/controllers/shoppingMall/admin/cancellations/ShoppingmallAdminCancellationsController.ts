import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallAdminCancellations } from "../../../../providers/patchShoppingMallAdminCancellations";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminCancellationsCancellationId } from "../../../../providers/getShoppingMallAdminCancellationsCancellationId";
import { putShoppingMallAdminCancellationsCancellationId } from "../../../../providers/putShoppingMallAdminCancellationsCancellationId";
import { deleteShoppingMallAdminCancellationsCancellationId } from "../../../../providers/deleteShoppingMallAdminCancellationsCancellationId";

import { IPageIShoppingMallOrderCancellation } from "../../../../api/structures/IPageIShoppingMallOrderCancellation";
import { IShoppingMallOrderCancellation } from "../../../../api/structures/IShoppingMallOrderCancellation";

@Controller("/shoppingMall/admin/cancellations")
export class ShoppingmallAdminCancellationsController {
  /**
   * Search and retrieve a filtered, paginated list of order cancellation
   * requests.
   *
   * Retrieve a comprehensive, filtered list of order cancellation requests with
   * advanced search and pagination capabilities. This operation provides
   * marketplace administrators and authorized users with the ability to query
   * cancellation requests based on various criteria including cancellation
   * status, order identifiers, buyer information, date ranges, and approval
   * workflow states.
   *
   * The operation supports comprehensive pagination with configurable page
   * sizes and sorting options. Users can sort cancellation requests by creation
   * date, approval date, cancellation reason, or other relevant fields in
   * ascending or descending order. This enables efficient management of the
   * cancellation workflow and helps identify patterns in buyer cancellation
   * behavior.
   *
   * Security considerations include proper authorization checks to ensure only
   * administrators or relevant sellers can access cancellation request data.
   * The operation implements rate limiting for search operations and filters
   * sensitive information based on the requesting user's authorization level.
   * Cancellation requests contain important business data including refund
   * processing status, seller responses, and admin approval decisions.
   *
   * This operation integrates with the shopping_mall_order_cancellations table
   * as defined in the Prisma schema, incorporating all available cancellation
   * fields and relationships to orders, buyers, and approval workflows. The
   * response includes cancellation summary information optimized for list
   * displays, with options to include additional details based on authorization
   * level and business requirements.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering order
   *   cancellation requests
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallOrderCancellation.IRequest,
  ): Promise<IPageIShoppingMallOrderCancellation.ISummary> {
    try {
      return await patchShoppingMallAdminCancellations({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific order cancellation request.
   *
   * Retrieve comprehensive details about a specific order cancellation request
   * identified by its unique cancellation ID. This operation provides
   * authorized users with complete visibility into the cancellation workflow
   * including the buyer's cancellation reason, submission timestamp, current
   * approval status, admin review decisions, and refund processing state.
   *
   * The response includes full relationship data connecting the cancellation
   * request to its parent order, the buyer who requested the cancellation, and
   * any administrative actions taken. This comprehensive view enables informed
   * decision-making for approving or rejecting cancellation requests and
   * tracking the complete lifecycle of the cancellation workflow from initial
   * request through final resolution.
   *
   * Security measures ensure that only authorized administrators or relevant
   * sellers can access detailed cancellation information. The operation
   * validates the cancellation ID format and existence before retrieving data,
   * returning appropriate error responses for invalid or non-existent
   * cancellation requests. Access controls prevent unauthorized users from
   * viewing sensitive cancellation details including buyer personal information
   * and refund processing status.
   *
   * This operation integrates with the shopping_mall_order_cancellations table
   * structure as defined in the Prisma schema, returning all available fields
   * and nested relationships. The detailed response supports administrative
   * workflows for cancellation approval, refund processing coordination, and
   * marketplace policy enforcement related to order cancellations.
   *
   * @param connection
   * @param cancellationId Unique identifier of the target order cancellation
   *   request
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":cancellationId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("cancellationId")
    cancellationId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallOrderCancellation> {
    try {
      return await getShoppingMallAdminCancellationsCancellationId({
        admin,
        cancellationId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an order cancellation request status (admin approval/rejection).
   *
   * Update an existing order cancellation request, typically to approve or
   * reject the buyer's cancellation request. This operation is primarily used
   * by administrators to review and process cancellation requests submitted by
   * buyers.
   *
   * Administrators can update the cancellation status to approved or rejected,
   * and must provide admin notes explaining the decision. When a cancellation
   * is approved, the system may trigger additional workflows such as refund
   * processing and inventory restoration. When rejected, the order continues
   * its normal fulfillment process and the buyer is notified of the rejection
   * reason.
   *
   * Security considerations include restricting this operation to admin actors
   * only, as buyers should not be able to modify cancellation requests after
   * submission. The admin's identity is automatically extracted from the JWT
   * authentication token and recorded with the decision. All status changes are
   * audited with timestamps.
   *
   * This operation integrates with the shopping_mall_order_cancellations table
   * as defined in the Prisma schema. The operation validates that the
   * cancellation request exists via the cancellationId path parameter. Related
   * operations include creating cancellation requests (POST /cancellations) and
   * viewing cancellation history.
   *
   * @param connection
   * @param cancellationId Unique identifier of the target order cancellation
   *   request
   * @param body Updated cancellation status and admin decision details
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":cancellationId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("cancellationId")
    cancellationId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallOrderCancellation.IUpdate,
  ): Promise<IShoppingMallOrderCancellation> {
    try {
      return await putShoppingMallAdminCancellationsCancellationId({
        admin,
        cancellationId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete an order cancellation request.
   *
   * Permanently remove an order cancellation request from the system by its
   * unique identifier.
   *
   * This operation performs a hard delete on the cancellation record,
   * completely removing it from the shopping_mall_order_cancellations table.
   * Once deleted, the cancellation request cannot be recovered. This operation
   * should be used cautiously and typically only by administrators to clean up
   * erroneous or test cancellation requests.
   *
   * Security considerations: This operation requires appropriate administrative
   * permissions as it permanently destroys data. The operation validates that
   * the cancellation request exists before attempting deletion. If the
   * cancellation has already been processed or is in a final state, the
   * business logic should prevent deletion to maintain data integrity and audit
   * trails.
   *
   * The deletion is immediate and permanent. No soft-delete mechanism is
   * employed. Related order status and history records are not affected by this
   * operation, ensuring that the order's state transition history remains
   * intact even if the cancellation request itself is removed.
   *
   * @param connection
   * @param cancellationId Unique identifier of the target order cancellation
   *   request to be deleted
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":cancellationId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("cancellationId")
    cancellationId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallAdminCancellationsCancellationId({
        admin,
        cancellationId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
