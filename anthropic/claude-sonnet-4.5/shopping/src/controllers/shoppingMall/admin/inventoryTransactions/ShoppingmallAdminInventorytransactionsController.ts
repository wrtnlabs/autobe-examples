import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallAdminInventoryTransactions } from "../../../../providers/patchShoppingMallAdminInventoryTransactions";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminInventoryTransactionsTransactionId } from "../../../../providers/getShoppingMallAdminInventoryTransactionsTransactionId";

import { IPageIShoppingMallInventoryTransaction } from "../../../../api/structures/IPageIShoppingMallInventoryTransaction";
import { IShoppingMallInventoryTransaction } from "../../../../api/structures/IShoppingMallInventoryTransaction";

@Controller("/shoppingMall/admin/inventoryTransactions")
export class ShoppingmallAdminInventorytransactionsController {
  /**
   * Retrieve a comprehensive list of inventory transaction records with
   * advanced filtering and pagination capabilities. This operation provides
   * detailed audit trail access for all inventory movements across the shopping
   * mall platform.
   *
   * The inventory transactions table serves as a complete historical ledger of
   * all stock changes, capturing every addition, removal, reservation, and
   * release of inventory. Each transaction record includes the associated SKU,
   * transaction type, quantity change, timestamp, and optional reference
   * information linking to orders or other business events that triggered the
   * inventory movement.
   *
   * This operation supports filtering by multiple criteria including specific
   * SKUs, transaction types (such as 'purchase', 'sale', 'adjustment',
   * 'reservation', 'release'), date ranges for when transactions occurred, and
   * sorting by timestamp or quantity. The search capabilities enable
   * administrators and sellers to perform detailed inventory audits, reconcile
   * stock levels, investigate discrepancies, and generate inventory movement
   * reports.
   *
   * Security considerations: This operation requires authentication and is
   * restricted to administrators and sellers. Sellers can only view
   * transactions for SKUs belonging to their own products, while administrators
   * have platform-wide visibility. The response includes pagination to handle
   * large transaction histories efficiently, with configurable page sizes and
   * cursor-based navigation for optimal performance.
   *
   * The operation integrates with the shopping_mall_inventory_transactions
   * table as defined in the Prisma schema, which maintains a complete
   * snapshot-based audit trail of all inventory changes. Transaction records
   * are immutable once created, ensuring data integrity for compliance and
   * auditing purposes.
   *
   * @param connection
   * @param body Search criteria including SKU filters, transaction type
   *   filters, date ranges, pagination parameters, and sorting options
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallInventoryTransaction.IRequest,
  ): Promise<IPageIShoppingMallInventoryTransaction.ISummary> {
    try {
      return await patchShoppingMallAdminInventoryTransactions({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve comprehensive details for a single inventory transaction record
   * identified by its unique transaction ID. This operation provides complete
   * visibility into a specific inventory movement event for audit and
   * reconciliation purposes.
   *
   * Each inventory transaction represents an immutable historical record of a
   * stock level change, capturing the exact details of what happened, when it
   * happened, and why it happened. The transaction record includes the
   * associated SKU identifier, the type of transaction (such as purchase, sale,
   * adjustment, reservation, or release), the quantity that was added or
   * removed, the precise timestamp of the transaction, and optional reference
   * fields that may link to related business entities like orders or manual
   * adjustments.
   *
   * This operation is essential for detailed inventory investigations, allowing
   * administrators and sellers to trace the complete history of stock movements
   * for any SKU. When discrepancies occur or audits are required, this endpoint
   * provides the granular transaction-level details needed to understand and
   * verify inventory changes.
   *
   * Security and authorization: Access to transaction details requires
   * authentication. Sellers can only view transactions related to their own
   * product SKUs, while administrators have unrestricted access to all platform
   * inventory transactions. The operation validates that the requested
   * transaction exists and that the requesting user has appropriate permissions
   * before returning the data.
   *
   * The response includes all fields from the
   * shopping_mall_inventory_transactions Prisma schema model, providing a
   * complete snapshot of the transaction as it was recorded. This ensures full
   * transparency and auditability of all inventory movements across the
   * platform.
   *
   * @param connection
   * @param transactionId Unique identifier of the target inventory transaction
   *   record
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":transactionId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("transactionId")
    transactionId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallInventoryTransaction> {
    try {
      return await getShoppingMallAdminInventoryTransactionsTransactionId({
        admin,
        transactionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
