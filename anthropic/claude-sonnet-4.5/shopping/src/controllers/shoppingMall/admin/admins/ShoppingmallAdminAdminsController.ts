import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallAdminAdmins } from "../../../../providers/patchShoppingMallAdminAdmins";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminAdminsAdminId } from "../../../../providers/getShoppingMallAdminAdminsAdminId";
import { putShoppingMallAdminAdminsAdminId } from "../../../../providers/putShoppingMallAdminAdminsAdminId";
import { deleteShoppingMallAdminAdminsAdminId } from "../../../../providers/deleteShoppingMallAdminAdminsAdminId";

import { IPageIShoppingMallAdmin } from "../../../../api/structures/IPageIShoppingMallAdmin";
import { IShoppingMallAdmin } from "../../../../api/structures/IShoppingMallAdmin";

@Controller("/shoppingMall/admin/admins")
export class ShoppingmallAdminAdminsController {
  /**
   * Retrieve a filtered and paginated list of platform administrator accounts
   * with advanced search capabilities. This operation provides comprehensive
   * querying to find administrators based on multiple criteria including
   * partial username matching, email domain filtering, role-based filtering,
   * account status, and registration date ranges.
   *
   * The operation supports full pagination with configurable page sizes and
   * sorting options. Administrators can be sorted by creation date, last login,
   * username, or other relevant fields in ascending or descending order. This
   * is essential for administrative oversight and user management workflows.
   *
   * Security considerations include strict authorization requirements - only
   * existing administrators with appropriate permissions can access the admin
   * user list. The operation may filter or redact sensitive information based
   * on the requesting admin's permission level. Rate limiting is applied to
   * prevent abuse of search functionality.
   *
   * This operation integrates with the shopping_mall_admins table as defined in
   * the Prisma schema, incorporating all available admin account fields and
   * relationships. The response includes admin summary information optimized
   * for list displays in administrative dashboards.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for administrator
   *   filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallAdmin.IRequest,
  ): Promise<IPageIShoppingMallAdmin.ISummary> {
    try {
      return await patchShoppingMallAdminAdmins({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve comprehensive details about a specific platform administrator
   * account identified by their unique admin ID. This operation provides access
   * to the admin's complete profile information including personal details,
   * account status, and metadata such as creation and last update timestamps.
   *
   * This endpoint is restricted to authenticated admin users who need to view
   * admin account information for administrative purposes such as account
   * management, audit trails, or security reviews. The operation returns the
   * admin entity with all available fields as defined in the
   * shopping_mall_admins Prisma schema, excluding sensitive authentication
   * credentials such as passwords, password hashes, and security tokens for
   * security purposes.
   *
   * Security considerations include proper authorization verification to ensure
   * only admins with appropriate permissions can access admin account details.
   * Sensitive fields such as passwords, salts, and internal security tokens are
   * excluded from all responses. Rate limiting applies to prevent abuse of this
   * endpoint.
   *
   * This operation integrates with the shopping_mall_admins table as defined in
   * the Prisma schema, returning admin account information optimized for
   * administrative viewing and account management purposes.
   *
   * @param connection
   * @param adminId Unique identifier of the target admin account
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":adminId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallAdmin> {
    try {
      return await getShoppingMallAdminAdminsAdminId({
        admin,
        adminId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update the profile and configuration details of an existing platform
   * administrator account identified by their unique admin ID. This operation
   * allows authorized administrators to modify admin account information
   * including personal details, authentication credentials, and account
   * status.
   *
   * The update operation supports modification of fields such as admin name,
   * email address, and any other editable attributes defined in the
   * shopping_mall_admins schema. Password changes are processed securely with
   * proper encryption. The system automatically updates the updated_at
   * timestamp to track when the modification occurred, maintaining a clear
   * audit trail of account changes.
   *
   * Security considerations include strict authorization verification to ensure
   * only admins with appropriate permissions can modify admin accounts. The
   * operation validates all input data against business rules such as email
   * format validation and uniqueness constraints. Changes to critical fields
   * may trigger additional security measures such as notification emails or
   * audit log entries. Sensitive fields such as passwords, salts, and internal
   * security tokens are excluded from all responses.
   *
   * This operation integrates with the shopping_mall_admins table as defined in
   * the Prisma schema, updating existing admin records while preserving data
   * integrity. The response returns the updated admin entity reflecting all
   * applied changes (excluding sensitive authentication credentials), allowing
   * the caller to verify the update was successful.
   *
   * @param connection
   * @param adminId Unique identifier of the target admin account to update
   * @param body Updated admin account information including modified fields
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":adminId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallAdmin.IUpdate,
  ): Promise<IShoppingMallAdmin> {
    try {
      return await putShoppingMallAdminAdminsAdminId({
        admin,
        adminId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently remove an administrator account from the shopping mall
   * platform. This operation performs a hard deletion, completely removing the
   * admin record from the database along with all associated session records
   * and audit trails.
   *
   * This is a critical administrative operation that should only be executed
   * when an admin account needs to be permanently removed from the system, such
   * as when an administrator leaves the organization, access needs to be
   * revoked for security reasons, or during account cleanup operations.
   *
   * Security considerations: This operation requires the highest level of
   * administrative privileges. Only super admins or system administrators with
   * explicit account management permissions should be able to execute this
   * deletion. The operation should be logged in system audit trails for
   * compliance and security monitoring purposes. Once deleted, the admin
   * account cannot be recovered and the administrator will lose all access to
   * the platform immediately.
   *
   * The deletion cascades to related records including all session records
   * associated with this administrator. This ensures complete removal of the
   * admin's presence from the system. Related operations include creating admin
   * accounts (POST /admins), updating admin information (PUT
   * /admins/{adminId}), and retrieving admin details (GET /admins/{adminId}).
   *
   * @param connection
   * @param adminId Unique identifier of the target administrator account to be
   *   permanently deleted
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":adminId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallAdmin> {
    try {
      return await deleteShoppingMallAdminAdminsAdminId({
        admin,
        adminId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
