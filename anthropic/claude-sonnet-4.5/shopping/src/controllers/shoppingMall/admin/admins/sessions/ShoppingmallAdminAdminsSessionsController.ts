import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallAdminAdminsAdminIdSessions } from "../../../../../providers/patchShoppingMallAdminAdminsAdminIdSessions";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminAdminsAdminIdSessionsSessionId } from "../../../../../providers/getShoppingMallAdminAdminsAdminIdSessionsSessionId";
import { deleteShoppingMallAdminAdminsAdminIdSessionsSessionId } from "../../../../../providers/deleteShoppingMallAdminAdminsAdminIdSessionsSessionId";

import { IPageIShoppingMallAdminSession } from "../../../../../api/structures/IPageIShoppingMallAdminSession";
import { IShoppingMallAdminSession } from "../../../../../api/structures/IShoppingMallAdminSession";

@Controller("/shoppingMall/admin/admins/:adminId/sessions")
export class ShoppingmallAdminAdminsSessionsController {
  /**
   * Retrieve filtered, paginated list of admin authentication sessions for
   * security monitoring.
   *
   * Retrieve a filtered and paginated list of authentication sessions for a
   * specific administrator account. This operation provides comprehensive
   * session tracking capabilities essential for security monitoring, audit
   * compliance, and access pattern analysis.
   *
   * The operation supports advanced search and filtering capabilities including
   * filtering by session status (active/expired/revoked), creation date ranges,
   * IP address patterns, user agent strings, and last activity timestamps.
   * Administrators can sort sessions by creation time, last activity,
   * expiration date, or other relevant fields in ascending or descending order
   * to identify patterns or anomalies.
   *
   * Security and audit considerations: This operation is critical for security
   * monitoring and compliance. It enables administrators to track all login
   * sessions for a specific admin user, identify concurrent sessions, detect
   * suspicious access patterns such as logins from unusual locations or
   * devices, and monitor session expiration and revocation events. The session
   * data includes authentication timestamps, IP addresses, user agent
   * information, and session status, providing a complete audit trail of
   * administrative access.
   *
   * This operation integrates with the shopping_mall_admin_sessions table as
   * defined in the Prisma schema, returning session records that track
   * authentication events and maintain JWT token associations. The response
   * includes session summary information optimized for security dashboards and
   * audit reports, with options to include additional details such as
   * associated JWT token metadata based on authorization level.
   *
   * Related operations include viewing individual session details (GET
   * /admins/{adminId}/sessions/{sessionId}), revoking active sessions (DELETE
   * /admins/{adminId}/sessions/{sessionId}), and retrieving the admin's current
   * active session count for concurrent login monitoring.
   *
   * @param connection
   * @param adminId Unique identifier of the administrator whose sessions are
   *   being retrieved
   * @param body Search criteria and pagination parameters for filtering
   *   administrator sessions including date ranges, session status, IP
   *   addresses, and sorting options
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallAdminSession.IRequest,
  ): Promise<IPageIShoppingMallAdminSession.ISummary> {
    try {
      return await patchShoppingMallAdminAdminsAdminIdSessions({
        admin,
        adminId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific admin session.
   *
   * Retrieve comprehensive details about a specific admin authentication
   * session from the system. This operation provides complete session
   * information including JWT tokens, login/logout timestamps, IP address, user
   * agent, and session status.
   *
   * The operation is designed for administrative session management and
   * security auditing purposes. It allows administrators to inspect their own
   * active and historical sessions, enabling them to verify login activity,
   * detect suspicious access patterns, and manage their authentication state.
   *
   * Security considerations include strict authorization enforcement ensuring
   * administrators can only access their own session records. The session data
   * includes sensitive authentication tokens and should be transmitted
   * securely. This operation supports session tracking for compliance, audit
   * trails, and security monitoring.
   *
   * The response includes all session metadata as defined in the
   * shopping_mall_admin_sessions Prisma schema, providing complete visibility
   * into the authentication session lifecycle. This operation is commonly used
   * in conjunction with session listing endpoints to provide detailed
   * drill-down capabilities for session management interfaces.
   *
   * @param connection
   * @param adminId Unique identifier of the target admin account (global scope)
   * @param sessionId Unique identifier of the target admin session record
   *   (scoped to admin)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallAdminSession> {
    try {
      return await getShoppingMallAdminAdminsAdminIdSessionsSessionId({
        admin,
        adminId,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a specific admin session to terminate authentication.
   *
   * Permanently delete a specific admin authentication session from the system,
   * effectively logging out the admin user and invalidating the associated JWT
   * authentication tokens. This operation implements secure session termination
   * for admin accounts.
   *
   * The operation is essential for security management, enabling administrators
   * to explicitly end their authentication sessions. Common use cases include
   * logging out from the admin panel, invalidating sessions after suspicious
   * activity detection, or clearing sessions when switching devices. Session
   * deletion ensures that authentication tokens can no longer be used to access
   * the system.
   *
   * Security considerations include strict authorization enforcement ensuring
   * administrators can only delete their own session records, preventing
   * unauthorized session termination attacks. The deletion process invalidates
   * all authentication state associated with the session, requiring the admin
   * to re-authenticate for future access. This operation creates an audit trail
   * entry documenting the session termination.
   *
   * The operation performs a permanent deletion of the session record from the
   * shopping_mall_admin_sessions table. Upon successful deletion, the admin's
   * JWT token becomes invalid and subsequent API requests using that token will
   * be rejected. This operation is commonly invoked when users click logout
   * buttons in admin interfaces or when implementing session timeout
   * mechanisms.
   *
   * @param connection
   * @param adminId Unique identifier of the target admin account (global scope)
   * @param sessionId Unique identifier of the target admin session record to be
   *   deleted (scoped to admin)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":sessionId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallAdminSession> {
    try {
      return await deleteShoppingMallAdminAdminsAdminIdSessionsSessionId({
        admin,
        adminId,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
