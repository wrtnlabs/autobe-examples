import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallAdminRefundTransactions } from "../../../../providers/patchShoppingMallAdminRefundTransactions";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminRefundTransactionsRefundTransactionId } from "../../../../providers/getShoppingMallAdminRefundTransactionsRefundTransactionId";

import { IPageIShoppingMallRefundTransaction } from "../../../../api/structures/IPageIShoppingMallRefundTransaction";
import { IShoppingMallRefundTransaction } from "../../../../api/structures/IShoppingMallRefundTransaction";

@Controller("/shoppingMall/admin/refundTransactions")
export class ShoppingmallAdminRefundtransactionsController {
  /**
   * Retrieve a comprehensive, filtered list of refund transactions with
   * advanced search and pagination capabilities. This operation enables
   * administrators to search through all refund payment processing records in
   * the shopping mall platform.
   *
   * The operation supports complex filtering criteria including refund request
   * references, transaction status, payment method filters, amount ranges, and
   * timestamp-based searches. Administrators can sort results by transaction
   * date, refund amount, processing status, or other relevant fields in
   * ascending or descending order. The response includes paginated results
   * optimized for administrative dashboards and financial reporting.
   *
   * Security considerations include restricting access to authorized
   * administrators only, as refund transactions contain sensitive financial
   * information. The operation implements rate limiting to prevent abuse and
   * includes comprehensive audit logging of all search activities. This
   * operation integrates directly with the shopping_mall_refund_transactions
   * table as defined in the Prisma schema, providing access to all transaction
   * details including payment gateway responses, processing timestamps, and
   * associated refund request information.
   *
   * This operation is essential for financial reconciliation, dispute
   * resolution, and administrative oversight of the refund processing workflow.
   * It enables tracking of refund payment status, identifying failed
   * transactions, and generating financial reports for platform accounting and
   * seller payout calculations.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering refund
   *   transactions
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallRefundTransaction.IRequest,
  ): Promise<IPageIShoppingMallRefundTransaction.ISummary> {
    try {
      return await patchShoppingMallAdminRefundTransactions({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve complete details of a single refund transaction identified by its
   * unique transaction ID. This operation provides administrators with
   * comprehensive information about a specific refund payment processing
   * record.
   *
   * The response includes all refund transaction details such as the associated
   * refund request reference, transaction amount, payment method used,
   * processing status, payment gateway response data, transaction timestamps
   * (created, processed, completed), and any error information if the
   * transaction failed. The operation also provides related information about
   * the refund request that triggered this transaction.
   *
   * Security is enforced through administrator-only access restrictions,
   * ensuring that only authorized personnel can view sensitive financial
   * transaction details. The operation implements comprehensive audit logging
   * to track all access to refund transaction records for compliance and
   * security purposes.
   *
   * This operation is critical for investigating refund processing issues,
   * verifying successful refund completions, troubleshooting failed
   * transactions, and providing customer support when buyers inquire about
   * refund status. It enables administrators to access the complete transaction
   * history and diagnose any problems in the refund payment workflow.
   *
   * @param connection
   * @param refundTransactionId Unique identifier of the target refund
   *   transaction
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":refundTransactionId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("refundTransactionId")
    refundTransactionId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallRefundTransaction> {
    try {
      return await getShoppingMallAdminRefundTransactionsRefundTransactionId({
        admin,
        refundTransactionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
