import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallAdminPlatformCommissions } from "../../../../providers/patchShoppingMallAdminPlatformCommissions";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminPlatformCommissionsCommissionId } from "../../../../providers/getShoppingMallAdminPlatformCommissionsCommissionId";

import { IPageIShoppingMallPlatformCommission } from "../../../../api/structures/IPageIShoppingMallPlatformCommission";
import { IShoppingMallPlatformCommission } from "../../../../api/structures/IShoppingMallPlatformCommission";

@Controller("/shoppingMall/admin/platformCommissions")
export class ShoppingmallAdminPlatformcommissionsController {
  /**
   * Search and retrieve a filtered, paginated list of platform commission
   * records.
   *
   * Retrieve a filtered and paginated list of platform commission records
   * tracking revenue generated by the marketplace. This operation provides
   * comprehensive search capabilities for finding commission records based on
   * multiple criteria including date ranges, commission amount ranges,
   * associated orders, and commission calculation status.
   *
   * The operation supports full pagination with configurable page sizes and
   * sorting options. Administrators can sort commission records by transaction
   * date, commission amount, order reference, or other relevant fields in
   * ascending or descending order. This enables detailed financial reporting
   * and revenue analysis.
   *
   * Security considerations include strict authorization to ensure only
   * platform administrators can access commission data, as this represents
   * sensitive financial information. The response includes detailed commission
   * information including calculated amounts, associated order references,
   * commission rates applied, and timestamps for audit and accounting
   * purposes.
   *
   * This operation integrates with the shopping_mall_platform_commissions table
   * as defined in the Prisma schema, incorporating all commission tracking
   * fields and relationships to orders and transactions. The response is
   * optimized for financial reporting dashboards and accounting reconciliation
   * processes.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering
   *   platform commission records
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallPlatformCommission.IRequest,
  ): Promise<IPageIShoppingMallPlatformCommission.ISummary> {
    try {
      return await patchShoppingMallAdminPlatformCommissions({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific platform commission record by commission ID.
   *
   * Retrieve detailed information about a specific platform commission record
   * from the marketplace system. This operation provides complete commission
   * details including the commission amount, percentage rate, order reference,
   * seller information, and transaction timestamps.
   *
   * Platform commissions represent the fees charged by the marketplace platform
   * on seller transactions. Each commission record is associated with a
   * specific order and tracks the revenue generated by the platform from that
   * transaction. The commission amount is calculated based on the platform's
   * commission rate applied to the order value.
   *
   * Security considerations: This operation is restricted to admin users only,
   * as platform commission data contains sensitive financial information about
   * platform revenue and seller transaction fees. The operation returns
   * complete commission details for administrative review, financial reporting,
   * and revenue analysis purposes.
   *
   * This operation integrates with the shopping_mall_platform_commissions table
   * as defined in the Prisma schema, providing access to all commission fields
   * including relationships to orders and sellers. The response includes
   * comprehensive commission information optimized for administrative financial
   * analysis and audit purposes.
   *
   * @param connection
   * @param commissionId Unique identifier of the target platform commission
   *   record
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":commissionId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("commissionId")
    commissionId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallPlatformCommission> {
    try {
      return await getShoppingMallAdminPlatformCommissionsCommissionId({
        admin,
        commissionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
