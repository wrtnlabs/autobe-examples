import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallAdminSellersSellerIdPlatformCommissions } from "../../../../../providers/patchShoppingMallAdminSellersSellerIdPlatformCommissions";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";

import { IPageIShoppingMallPlatformCommission } from "../../../../../api/structures/IPageIShoppingMallPlatformCommission";
import { IShoppingMallPlatformCommission } from "../../../../../api/structures/IShoppingMallPlatformCommission";

@Controller("/shoppingMall/admin/sellers/:sellerId/platformCommissions")
export class ShoppingmallAdminSellersPlatformcommissionsController {
  /**
   * Search and retrieve platform commission records for a specific seller.
   *
   * Retrieve a filtered and paginated list of platform commission records for a
   * specific seller in the shopping mall marketplace. This operation provides
   * comprehensive search capabilities for analyzing commission charges, payment
   * history, and financial reconciliation.
   *
   * The operation supports advanced filtering by date ranges, commission
   * amounts, payment status, and associated order information. Users can sort
   * results by commission date, amount, payment status, or other relevant
   * fields in ascending or descending order. Pagination allows efficient
   * navigation through large commission record sets.
   *
   * Security considerations: Only the authenticated seller can view their own
   * commission records, while platform administrators have access to all seller
   * commission data for oversight and financial management purposes. The
   * operation includes appropriate authorization checks to ensure data access
   * compliance.
   *
   * This operation integrates with the shopping_mall_platform_commissions table
   * as defined in the Prisma schema, which maintains the relationship between
   * sellers and their commission obligations. Commission records are created
   * automatically when orders are completed, and this endpoint provides
   * visibility into those financial transactions for accounting and
   * reconciliation purposes.
   *
   * @param connection
   * @param sellerId Unique identifier of the target seller (UUID format)
   * @param body Search criteria and pagination parameters for filtering
   *   platform commission records
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallPlatformCommission.IRequest,
  ): Promise<IPageIShoppingMallPlatformCommission.ISummary> {
    try {
      return await patchShoppingMallAdminSellersSellerIdPlatformCommissions({
        admin,
        sellerId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
