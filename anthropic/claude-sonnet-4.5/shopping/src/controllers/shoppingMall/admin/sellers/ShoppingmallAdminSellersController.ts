import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallAdminSellers } from "../../../../providers/patchShoppingMallAdminSellers";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminSellersSellerId } from "../../../../providers/getShoppingMallAdminSellersSellerId";

import { IPageIShoppingMallSeller } from "../../../../api/structures/IPageIShoppingMallSeller";
import { IShoppingMallSeller } from "../../../../api/structures/IShoppingMallSeller";

@Controller("/shoppingMall/admin/sellers")
export class ShoppingmallAdminSellersController {
  /**
   * Search and retrieve a filtered, paginated list of marketplace sellers.
   *
   * Retrieve a comprehensive, filtered and paginated list of seller accounts
   * from the shopping mall marketplace. This operation provides advanced search
   * capabilities for finding sellers based on multiple criteria including
   * partial store name matching, seller approval status, account status
   * (active, suspended, pending), registration date ranges, and other relevant
   * seller attributes.
   *
   * The operation supports comprehensive pagination with configurable page
   * sizes and flexible sorting options. Sellers can be sorted by registration
   * date, approval date, store name, or other relevant fields in ascending or
   * descending order. This enables efficient browsing of large seller datasets
   * and supports various administrative workflows.
   *
   * Security considerations include appropriate authorization checks to ensure
   * only authorized personnel (typically admins or moderators) can access
   * seller account information. The operation implements rate limiting for
   * search operations and filters sensitive seller information based on the
   * requesting user's authorization level. Personal and financial details are
   * protected according to data privacy requirements.
   *
   * This operation integrates with the shopping_mall_sellers table as defined
   * in the Prisma schema, incorporating all available seller fields including
   * store information, contact details, approval status, and account metadata.
   * The response includes seller summary information optimized for list
   * displays in administrative dashboards, with options to include additional
   * details based on authorization level and use case requirements.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for seller filtering,
   *   including store name search, approval status, account status, and date
   *   range filters
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallSeller.IRequest,
  ): Promise<IPageIShoppingMallSeller.ISummary> {
    try {
      return await patchShoppingMallAdminSellers({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific seller account.
   *
   * Retrieve complete detailed information about a specific seller account in
   * the shopping mall marketplace. This operation returns comprehensive seller
   * data including store name, business information, contact details, approval
   * status, registration date, account status, and all other relevant seller
   * attributes stored in the system.
   *
   * The operation is designed for administrative use cases including seller
   * account review, approval workflows, support ticket resolution, and
   * marketplace governance. It provides a complete view of the seller's account
   * status, business details, and historical information necessary for informed
   * decision-making by marketplace administrators.
   *
   * Security considerations ensure that only authorized users with appropriate
   * permissions can access detailed seller information. The seller_id parameter
   * must be a valid UUID corresponding to an existing seller account in the
   * system. The operation implements authorization checks to verify the
   * requesting user has admin-level access rights.
   *
   * This operation integrates with the shopping_mall_sellers table as defined
   * in the Prisma schema, returning all available seller fields and
   * relationships. The response includes complete seller information optimized
   * for detailed display in administrative interfaces, support dashboards, and
   * seller management tools. Related data such as approval history and account
   * modifications may be included based on business requirements.
   *
   * @param connection
   * @param sellerId Unique identifier of the target seller account
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sellerId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallSeller> {
    try {
      return await getShoppingMallAdminSellersSellerId({
        admin,
        sellerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
