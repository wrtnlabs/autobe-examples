import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallAdminCategories } from "../../../../providers/postShoppingMallAdminCategories";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { putShoppingMallAdminCategoriesCategoryCode } from "../../../../providers/putShoppingMallAdminCategoriesCategoryCode";
import { putShoppingMallAdminCategoriesCategorySlug } from "../../../../providers/putShoppingMallAdminCategoriesCategorySlug";
import { deleteShoppingMallAdminCategoriesCategoryId } from "../../../../providers/deleteShoppingMallAdminCategoriesCategoryId";

import { IShoppingMallCategory } from "../../../../api/structures/IShoppingMallCategory";

@Controller("/shoppingMall/admin/categories")
export class ShoppingmallAdminCategoriesController {
  /**
   * Create a new product category in the marketplace taxonomy.
   *
   * Create a new product category within the shopping mall marketplace's
   * hierarchical category structure. This operation allows platform
   * administrators to expand the product taxonomy by adding new categories that
   * organize and classify products for buyer discovery and navigation.
   *
   * The operation supports creating both root-level categories and nested
   * subcategories by optionally specifying a parent category. Administrators
   * must provide essential category information including a unique category
   * name, descriptive content, and optional metadata such as sort order for
   * controlling category display sequence. The category structure directly
   * impacts how products are organized and discovered throughout the
   * marketplace.
   *
   * Security is enforced through admin-only authorization, as category
   * structure management is a critical administrative function that affects the
   * entire marketplace's organization. Only authenticated admin users can
   * create new categories to maintain taxonomy integrity and prevent
   * unauthorized modifications to the product classification system.
   *
   * The operation validates category data including name uniqueness, proper
   * parent-child relationships, and status values. Upon successful creation,
   * the new category becomes immediately available for product assignment and
   * appears in category navigation throughout the marketplace. The created
   * category is returned with complete details including its assigned unique
   * identifier and hierarchical position.
   *
   * This operation integrates with the shopping_mall_categories table as
   * defined in the Prisma schema, ensuring proper enforcement of unique
   * constraints, hierarchical relationships, and data integrity rules. Category
   * creation is a fundamental administrative task for marketplace setup and
   * ongoing catalog organization as the product inventory grows and evolves.
   *
   * @param connection
   * @param body Category creation data including name, description, parent
   *   category reference, sort order, and initial status
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallCategory.ICreate,
  ): Promise<IShoppingMallCategory> {
    try {
      return await postShoppingMallAdminCategories({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing product category's information.
   *
   * Update the attributes of an existing product category identified by its
   * unique category code. This operation allows administrators to modify
   * category information including name, description, parent category
   * relationships, and display order within the hierarchy.
   *
   * The category hierarchy can be restructured by changing parent
   * relationships, enabling flexible taxonomy management. However, operations
   * must validate that hierarchy changes don't create circular references or
   * orphan categories.
   *
   * Security: This operation is restricted to platform administrators only, as
   * category structure directly impacts the entire marketplace product
   * organization. Only users with the admin actor role can modify categories.
   * The operation logs all changes for audit purposes.
   *
   * Validation rules enforce data integrity including unique code constraints,
   * valid parent references, and proper hierarchy depth limits. The operation
   * rejects updates that would violate these constraints or create inconsistent
   * category structures.
   *
   * Related operations: Create category (POST /categories), Delete category
   * (DELETE /categories/{categoryCode}), List categories (PATCH /categories).
   * Changes to categories may affect product listings and search indexes that
   * reference the updated category.
   *
   * @param connection
   * @param categoryCode Unique business identifier code of the target category
   *   to update (global scope)
   * @param body Updated category information including name, description,
   *   parent relationships, and metadata
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":categoryCode")
  public async putByCategorycode(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("categoryCode")
    categoryCode: string,
    @TypedBody()
    body: IShoppingMallCategory.IUpdate,
  ): Promise<IShoppingMallCategory> {
    try {
      return await putShoppingMallAdminCategoriesCategoryCode({
        admin,
        categoryCode,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing product category's information.
   *
   * Update the attributes of an existing product category identified by its
   * unique category slug. This operation allows administrators to modify
   * category information including name, description, parent category
   * relationships, and display order within the hierarchy.
   *
   * The category hierarchy can be restructured by changing parent
   * relationships, enabling flexible taxonomy management. However, operations
   * must validate that hierarchy changes don't create circular references or
   * orphan categories.
   *
   * Security: This operation is restricted to platform administrators only, as
   * category structure directly impacts the entire marketplace product
   * organization. Only users with the admin actor role can modify categories.
   * The operation logs all changes for audit purposes.
   *
   * Validation rules enforce data integrity including unique slug constraints,
   * valid parent references, and proper hierarchy depth limits. The operation
   * rejects updates that would violate these constraints or create inconsistent
   * category structures.
   *
   * Related operations: Create category (POST /categories), Delete category
   * (DELETE /categories/{categorySlug}), List categories (PATCH /categories).
   * Changes to categories may affect product listings and search indexes that
   * reference the updated category.
   *
   * @param connection
   * @param categorySlug URL-friendly unique identifier of the target category
   *   to update (global scope)
   * @param body Updated category information including name, description,
   *   parent relationships, and metadata
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":categorySlug")
  public async putByCategoryslug(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("categorySlug")
    categorySlug: string,
    @TypedBody()
    body: IShoppingMallCategory.IUpdate,
  ): Promise<IShoppingMallCategory> {
    try {
      return await putShoppingMallAdminCategoriesCategorySlug({
        admin,
        categorySlug,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a product category from the marketplace catalog.
   *
   * Permanently remove a product category entity from the shopping mall catalog
   * system. This operation performs a hard delete, completely removing the
   * category record from the database rather than marking it as inactive or
   * archived.
   *
   * The deletion process validates that the target category exists and can be
   * safely removed. Categories that have child categories or associated product
   * sales cannot be deleted until those relationships are resolved. The
   * operation protects referential integrity by preventing deletion of
   * categories that are actively referenced by other entities in the system.
   *
   * Security considerations include restricting this operation to admin users
   * only, as category deletion is a destructive administrative action that
   * affects the entire marketplace structure. The operation logs all deletion
   * attempts for audit purposes and tracks which admin performed the deletion.
   *
   * This operation integrates with the shopping_mall_categories table from the
   * Prisma schema. Before deletion, the system checks for dependent entities
   * including child categories in the hierarchical structure and any product
   * sales assigned to this category. If dependencies exist, the deletion is
   * rejected with an appropriate error message guiding admins to resolve the
   * dependencies first.
   *
   * @param connection
   * @param categoryId Unique identifier of the target category to be
   *   permanently deleted from the system
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":categoryId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("categoryId")
    categoryId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallAdminCategoriesCategoryId({
        admin,
        categoryId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
