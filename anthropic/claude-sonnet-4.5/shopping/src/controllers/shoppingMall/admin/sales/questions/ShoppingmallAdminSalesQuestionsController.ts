import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { deleteShoppingMallAdminSalesSaleCodeQuestionsQuestionId } from "../../../../../providers/deleteShoppingMallAdminSalesSaleCodeQuestionsQuestionId";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";

import { IShoppingMallSaleQuestion } from "../../../../../api/structures/IShoppingMallSaleQuestion";

@Controller("/shoppingMall/admin/sales/:saleCode/questions/:questionId")
export class ShoppingmallAdminSalesQuestionsController {
  /**
   * Permanently remove a customer question from a specific product sale listing
   * in the shopping marketplace.
   *
   * This operation allows authorized users to delete questions that have been
   * posted about a product. The deletion is permanent and removes the question
   * record from the database along with any associated answers if they exist.
   *
   * Security considerations include authorization checks to ensure only the
   * question author or administrators can delete questions. The operation
   * validates that the question belongs to the specified sale before deletion.
   * Rate limiting may apply to prevent abuse of the deletion functionality.
   *
   * This operation integrates with the shopping_mall_sale_questions table as
   * defined in the Prisma schema. Upon successful deletion, the question and
   * any related answers are removed from the system. The sale itself remains
   * unaffected by this operation.
   *
   * @param connection
   * @param saleCode Unique business identifier code of the target product sale
   *   (global scope)
   * @param questionId Unique identifier of the target question to be deleted
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("saleCode")
    saleCode: string,
    @TypedParam("questionId")
    questionId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallSaleQuestion> {
    try {
      return await deleteShoppingMallAdminSalesSaleCodeQuestionsQuestionId({
        admin,
        saleCode,
        questionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
