import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia from "typia";
import { deleteShoppingMallAdminSalesSaleCode } from "../../../../providers/deleteShoppingMallAdminSalesSaleCode";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";

@Controller("/shoppingMall/admin/sales/:saleCode")
export class ShoppingmallAdminSalesController {
  /**
   * Permanently delete a product sale listing and all associated data.
   *
   * Permanently delete a product sale listing from the shopping marketplace
   * system. This operation removes the sale record identified by its unique
   * business code from the database.
   *
   * This is a hard deletion that completely removes the sale entity and all its
   * associated subsidiary data from the system. The deletion cascades to all
   * related entities including sale snapshots, variant attributes, variant
   * values, SKUs, product images, customer questions, and seller answers. This
   * ensures no orphaned data remains in the system.
   *
   * Security considerations: This operation requires elevated administrative
   * permissions as it permanently destroys business data. Only platform
   * administrators should have access to this endpoint. The operation should be
   * used cautiously as the deletion is irreversible and may affect historical
   * order data, reviews, and inventory records that reference this sale.
   *
   * Before deletion, the system should validate that the sale can be safely
   * removed. Consider checking for active orders, pending transactions, or
   * other critical dependencies. The sale code must match an existing sale
   * record in the shopping_mall_sales table as defined in the Prisma schema.
   *
   * @param connection
   * @param saleCode Unique business identifier code of the target sale to be
   *   deleted (global scope)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("saleCode")
    saleCode: string,
  ): Promise<void> {
    try {
      return await deleteShoppingMallAdminSalesSaleCode({
        admin,
        saleCode,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
