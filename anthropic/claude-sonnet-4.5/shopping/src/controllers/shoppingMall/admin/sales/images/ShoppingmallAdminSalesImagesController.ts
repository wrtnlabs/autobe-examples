import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia from "typia";
import { postShoppingMallAdminSalesSaleCodeImages } from "../../../../../providers/postShoppingMallAdminSalesSaleCodeImages";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { patchShoppingMallAdminSalesSaleCodeImages } from "../../../../../providers/patchShoppingMallAdminSalesSaleCodeImages";

import { IShoppingMallSaleImage } from "../../../../../api/structures/IShoppingMallSaleImage";
import { IPageIShoppingMallSaleImage } from "../../../../../api/structures/IPageIShoppingMallSaleImage";

@Controller("/shoppingMall/admin/sales/:saleCode/images")
export class ShoppingmallAdminSalesImagesController {
  /**
   * Create a new product image record associated with a specific sale listing
   * in the shopping marketplace. This operation allows authenticated sellers to
   * add visual assets to their product listings, which are essential for
   * attracting buyers and showcasing product details effectively.
   *
   * The operation accepts comprehensive image metadata including the image URL
   * (which should reference a pre-uploaded file in the storage system), display
   * order for gallery sequencing, alt text for accessibility, and optional
   * dimension information. The seller's identity is automatically extracted
   * from the JWT authentication token to ensure proper ownership association.
   *
   * Security considerations include strict validation that the requesting
   * seller owns the target sale listing. Only the seller who created the sale
   * can add images to it, while admins have override capabilities for
   * moderation purposes. The operation validates that the referenced sale
   * exists and is in a state that allows image uploads (not finalized or
   * archived).
   *
   * Business rules enforced by this operation include maximum image count
   * limits per sale (typically 10-20 images), file size restrictions,
   * acceptable image formats (JPEG, PNG, WebP), and minimum resolution
   * requirements for quality assurance. The display_order field is used to
   * control the sequence of images in the product gallery, with the first image
   * (order 0) serving as the primary thumbnail.
   *
   * The created image becomes immediately visible in the seller's product
   * management interface and, if the sale is published, in the buyer-facing
   * product detail pages. Related operations include PATCH
   * /sales/{saleCode}/images for retrieving the image list, PUT
   * /sales/{saleCode}/images/{imageId} for updating image metadata, and DELETE
   * /sales/{saleCode}/images/{imageId} for removing images.
   *
   * @param connection
   * @param saleCode Unique business identifier code of the target sale (scoped
   *   to seller)
   * @param body Image creation data including URL, display order, alt text, and
   *   metadata
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("saleCode")
    saleCode: string,
    @TypedBody()
    body: IShoppingMallSaleImage.ICreate,
  ): Promise<IShoppingMallSaleImage> {
    try {
      return await postShoppingMallAdminSalesSaleCodeImages({
        admin,
        saleCode,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a filtered and paginated list of product images associated with a
   * specific sale listing in the shopping marketplace. This operation provides
   * advanced search capabilities for finding images based on various criteria
   * including display order, image status, creation date, and metadata
   * attributes.
   *
   * The operation supports comprehensive pagination with configurable page
   * sizes and sorting options. Images can be sorted by display order, upload
   * date, file size, or other relevant fields in ascending or descending order.
   * This is essential for sellers managing multiple product images and
   * organizing their visual presentation.
   *
   * Security considerations include verifying that the requesting user has
   * appropriate permissions to view the images. Sellers can only access images
   * for their own products, while admins have full access to all product images
   * across the platform. The operation filters sensitive image metadata based
   * on the requesting user's authorization level.
   *
   * This operation integrates with the shopping_mall_sale_images table as
   * defined in the Prisma schema, incorporating all available image fields
   * including URLs, dimensions, alt text, display order, and status flags. The
   * response includes image summary information optimized for list displays in
   * seller dashboards and admin panels, with options to include additional
   * technical details like file size and format based on authorization level.
   *
   * Related operations: This operation is typically used in conjunction with
   * GET /sales/{saleCode}/images/{imageId} for viewing individual image
   * details, and POST /sales/{saleCode}/images for uploading new product
   * images. Sellers often use this endpoint to review and reorder their product
   * gallery before publishing a sale listing.
   *
   * @param connection
   * @param saleCode Unique business identifier code of the target sale (scoped
   *   to seller)
   * @param body Search criteria and pagination parameters for filtering product
   *   images
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("saleCode")
    saleCode: string,
    @TypedBody()
    body: IShoppingMallSaleImage.IRequest,
  ): Promise<IPageIShoppingMallSaleImage.ISummary> {
    try {
      return await patchShoppingMallAdminSalesSaleCodeImages({
        admin,
        saleCode,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
