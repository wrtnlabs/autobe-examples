import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { patchShoppingMallAdminStatisticsRevenue } from "../../../../../providers/patchShoppingMallAdminStatisticsRevenue";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";

import { IShoppingMallRevenueStatistics } from "../../../../../api/structures/IShoppingMallRevenueStatistics";

@Controller("/shoppingMall/admin/statistics/revenue")
export class ShoppingmallAdminStatisticsRevenueController {
  /**
   * Retrieve aggregated revenue statistics and financial metrics for the
   * platform.
   *
   * Retrieve comprehensive revenue statistics and financial analytics for the
   * shopping mall platform. This operation provides aggregated financial
   * metrics computed from order transactions, payment records, platform
   * commissions, seller payouts, and refund data.
   *
   * The operation supports flexible time-based filtering to analyze revenue
   * trends across different periods (daily, weekly, monthly, quarterly,
   * yearly). Users can filter by date ranges, seller segments, product
   * categories, or other business dimensions to gain insights into revenue
   * performance and financial health.
   *
   * Key metrics returned include total gross revenue, net revenue after
   * refunds, platform commission earnings, seller payout amounts, average order
   * values, transaction counts, and growth rates compared to previous periods.
   * The response structure is optimized for dashboard displays and business
   * intelligence reporting.
   *
   * Security: This operation is restricted to platform administrators only, as
   * it exposes sensitive financial data and business performance metrics. The
   * data aggregation executes complex SQL queries joining shopping_mall_orders,
   * shopping_mall_payment_transactions, shopping_mall_platform_commissions,
   * shopping_mall_seller_payouts, and shopping_mall_refund_transactions tables
   * to compute comprehensive revenue analytics.
   *
   * This analytics operation serves the business need for financial reporting,
   * trend analysis, and strategic decision-making by providing a consolidated
   * view of platform revenue performance.
   *
   * @param connection
   * @param body Revenue analytics request parameters including time ranges,
   *   filters, and aggregation dimensions
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallRevenueStatistics.IRequest,
  ): Promise<IShoppingMallRevenueStatistics> {
    try {
      return await patchShoppingMallAdminStatisticsRevenue({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
