import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallAdminOrdersOrderIdItems } from "../../../../../providers/patchShoppingMallAdminOrdersOrderIdItems";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminOrdersOrderIdItemsItemId } from "../../../../../providers/getShoppingMallAdminOrdersOrderIdItemsItemId";

import { IPageIShoppingMallOrderItem } from "../../../../../api/structures/IPageIShoppingMallOrderItem";
import { IShoppingMallOrderItem } from "../../../../../api/structures/IShoppingMallOrderItem";

@Controller("/shoppingMall/admin/orders/:orderId/items")
export class ShoppingmallAdminOrdersItemsController {
  /**
   * Search and retrieve order items within a specific order.
   *
   * Retrieve a filtered and paginated list of order items for a specific order.
   * This operation provides search capabilities for buyers, sellers, and admins
   * to find specific items within an order based on multiple criteria including
   * product name, SKU details, price ranges, and fulfillment status.
   *
   * The operation supports comprehensive pagination with configurable page
   * sizes and sorting options. Items can be sorted by creation date, price,
   * product name, or other relevant fields in ascending or descending order.
   * This is particularly useful for orders containing many items where buyers
   * need to find specific products.
   *
   * Security considerations include authorization checks to ensure only the
   * order's buyer, the seller of items, or platform admins can access the order
   * items. The response includes detailed item information including product
   * details, SKU specifications, pricing, quantity, and current fulfillment
   * status. This operation is essential for order detail pages and seller order
   * management interfaces.
   *
   * This operation integrates with the shopping_mall_order_items table as
   * defined in the Prisma schema, along with related product and order
   * information to provide comprehensive item details.
   *
   * @param connection
   * @param orderId Unique identifier of the parent order containing the items
   *   (global scope)
   * @param body Search criteria and pagination parameters for filtering order
   *   items within the specified order
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallOrderItem.IRequest,
  ): Promise<IPageIShoppingMallOrderItem.ISummary> {
    try {
      return await patchShoppingMallAdminOrdersOrderIdItems({
        admin,
        orderId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information for a specific order item.
   *
   * Retrieve comprehensive details for a specific order item within an order.
   * This operation provides complete item information including product
   * details, SKU specifications with variant attributes, pricing breakdown,
   * quantity ordered, current fulfillment status, and associated seller
   * information.
   *
   * This endpoint is essential for displaying detailed item information on
   * order detail pages, tracking individual item status within multi-item
   * orders, and providing sellers with complete item details for fulfillment
   * purposes. The response includes all relevant item data needed for order
   * management and customer service.
   *
   * Security considerations include authorization checks to ensure only the
   * order's buyer, the item's seller, or platform admins can access the
   * detailed item information. The operation validates that the item actually
   * belongs to the specified order to prevent unauthorized access through
   * direct item ID manipulation.
   *
   * This operation integrates with the shopping_mall_order_items table as
   * defined in the Prisma schema, providing full item details with related
   * product, SKU, and seller information for comprehensive order item
   * visibility.
   *
   * @param connection
   * @param orderId Unique identifier of the parent order containing the item
   *   (global scope)
   * @param itemId Unique identifier of the specific order item (global scope)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":itemId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedParam("itemId")
    itemId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallOrderItem> {
    try {
      return await getShoppingMallAdminOrdersOrderIdItemsItemId({
        admin,
        orderId,
        itemId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
