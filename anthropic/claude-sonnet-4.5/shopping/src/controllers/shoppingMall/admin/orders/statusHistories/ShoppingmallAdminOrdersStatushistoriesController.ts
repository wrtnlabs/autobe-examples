import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallAdminOrdersOrderIdStatusHistories } from "../../../../../providers/patchShoppingMallAdminOrdersOrderIdStatusHistories";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminOrdersOrderIdStatusHistoriesHistoryId } from "../../../../../providers/getShoppingMallAdminOrdersOrderIdStatusHistoriesHistoryId";

import { IPageIShoppingMallOrderStatusHistory } from "../../../../../api/structures/IPageIShoppingMallOrderStatusHistory";
import { IShoppingMallOrderStatusHistory } from "../../../../../api/structures/IShoppingMallOrderStatusHistory";

@Controller("/shoppingMall/admin/orders/:orderId/statusHistories")
export class ShoppingmallAdminOrdersStatushistoriesController {
  /**
   * Search and retrieve filtered order status history records for a specific
   * order.
   *
   * Retrieve a comprehensive audit trail of status transitions for a specific
   * order in the shopping mall platform. This operation provides visibility
   * into the complete lifecycle of an order by returning all status change
   * events that have occurred from order placement through fulfillment,
   * cancellation, or refund.
   *
   * The operation supports advanced filtering capabilities including searching
   * by specific status types (e.g., pending, confirmed, shipped, delivered,
   * cancelled, refunded), filtering by date ranges to find transitions within
   * specific time periods, and sorting by timestamp to view the chronological
   * progression of order states. This enables administrators, sellers, and
   * support staff to understand exactly when and how an order progressed
   * through various states.
   *
   * Security considerations include ensuring that only authorized users can
   * view order status histories - typically the buyer who placed the order, the
   * seller fulfilling it, or platform administrators. The operation implements
   * proper authorization checks to prevent unauthorized access to sensitive
   * order progression data. Rate limiting is applied to prevent abuse of the
   * search functionality.
   *
   * This operation integrates with the shopping_mall_order_status_histories
   * table as defined in the Prisma schema, which captures each status
   * transition with timestamp, status type, optional notes, and actor
   * information. The response includes paginated status history records
   * optimized for timeline displays, providing complete visibility into order
   * state management and audit trails for compliance and customer service
   * purposes.
   *
   * @param connection
   * @param orderId Unique identifier of the target order for which to retrieve
   *   status history (global scope)
   * @param body Search criteria and pagination parameters for filtering order
   *   status history records
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallOrderStatusHistory.IRequest,
  ): Promise<IPageIShoppingMallOrderStatusHistory.ISummary> {
    try {
      return await patchShoppingMallAdminOrdersOrderIdStatusHistories({
        admin,
        orderId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific order status history record.
   *
   * Retrieve comprehensive details about a single status transition event in an
   * order's lifecycle. This operation returns complete information about a
   * specific status change including when it occurred, what status was set, any
   * notes or comments associated with the transition, and which actor (buyer,
   * seller, or admin) initiated the change.
   *
   * The operation provides detailed audit information essential for order
   * tracking, dispute resolution, and compliance requirements. It enables users
   * to examine the exact circumstances of a particular status transition,
   * including any contextual information recorded at the time of the change.
   * This is particularly valuable for customer service investigations, order
   * troubleshooting, and maintaining transparent communication about order
   * progression.
   *
   * Security considerations include verifying that the requesting user has
   * authorization to view this specific order's status history. Typically only
   * the buyer who placed the order, the seller fulfilling it, or platform
   * administrators should have access. The operation validates both the order
   * ownership/involvement and the existence of the requested status history
   * record.
   *
   * This operation integrates with the shopping_mall_order_status_histories
   * table as defined in the Prisma schema, returning the complete snapshot
   * record of a single status transition event. The response includes all
   * available details about the transition including timestamp, status type,
   * optional notes, and actor identification for complete audit trail
   * visibility.
   *
   * @param connection
   * @param orderId Unique identifier of the parent order containing the status
   *   history record (global scope)
   * @param historyId Unique identifier of the specific status history record to
   *   retrieve (scoped to order)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":historyId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedParam("historyId")
    historyId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallOrderStatusHistory> {
    try {
      return await getShoppingMallAdminOrdersOrderIdStatusHistoriesHistoryId({
        admin,
        orderId,
        historyId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
