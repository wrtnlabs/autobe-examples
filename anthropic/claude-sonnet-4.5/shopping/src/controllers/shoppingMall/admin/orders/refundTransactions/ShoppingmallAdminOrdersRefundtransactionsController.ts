import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallAdminOrdersOrderIdRefundTransactions } from "../../../../../providers/patchShoppingMallAdminOrdersOrderIdRefundTransactions";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";

import { IPageIShoppingMallRefundTransaction } from "../../../../../api/structures/IPageIShoppingMallRefundTransaction";
import { IShoppingMallRefundTransaction } from "../../../../../api/structures/IShoppingMallRefundTransaction";

@Controller("/shoppingMall/admin/orders/:orderId/refundTransactions")
export class ShoppingmallAdminOrdersRefundtransactionsController {
  /**
   * Retrieve paginated list of refund transactions for a specific order.
   *
   * Retrieve a filtered and paginated list of refund transactions for a
   * specific order in the shopping mall system. This operation provides
   * comprehensive search capabilities for finding refund transactions based on
   * various criteria including transaction status, refund amount ranges,
   * processing dates, and payment method information.
   *
   * The operation supports full pagination with configurable page sizes and
   * sorting options. Users can sort refund transactions by processing date,
   * refund amount, transaction status, or other relevant fields in ascending or
   * descending order. This is particularly useful for buyers tracking their
   * refund status and for admins auditing refund processing.
   *
   * Security considerations include authorization checks to ensure only the
   * order owner (buyer) or platform administrators can access refund
   * transaction details. The operation integrates with the
   * shopping_mall_refund_transactions table as defined in the Prisma schema,
   * providing complete refund payment processing information including
   * transaction IDs, amounts, payment methods, processing timestamps, and
   * status tracking.
   *
   * This operation is typically used after a refund request has been approved,
   * allowing buyers to monitor the actual payment processing and track when
   * refunds are credited back to their payment methods. It provides
   * transparency in the refund workflow and helps resolve customer inquiries
   * about refund timing.
   *
   * @param connection
   * @param orderId Unique identifier of the target order (global scope)
   * @param body Search criteria and pagination parameters for filtering refund
   *   transactions by status, date range, amount, and payment method
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallRefundTransaction.IRequest,
  ): Promise<IPageIShoppingMallRefundTransaction.ISummary> {
    try {
      return await patchShoppingMallAdminOrdersOrderIdRefundTransactions({
        admin,
        orderId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
