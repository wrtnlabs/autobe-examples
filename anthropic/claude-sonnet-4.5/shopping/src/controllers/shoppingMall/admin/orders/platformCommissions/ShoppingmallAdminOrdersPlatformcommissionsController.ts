import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { getShoppingMallAdminOrdersOrderIdPlatformCommissions } from "../../../../../providers/getShoppingMallAdminOrdersOrderIdPlatformCommissions";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";

import { IShoppingMallPlatformCommissions } from "../../../../../api/structures/IShoppingMallPlatformCommissions";

@Controller("/shoppingMall/admin/orders/:orderId/platformCommissions")
export class ShoppingmallAdminOrdersPlatformcommissionsController {
  /**
   * Retrieve a collection of platform commission records associated with a
   * specific order in the marketplace system. This operation provides access to
   * all commission entries related to a single order, enabling administrators
   * to view the complete commission breakdown for multi-seller orders or track
   * commission details for individual transactions.
   *
   * In marketplace systems, a single order may generate multiple platform
   * commission records, particularly when the order contains items from
   * multiple sellers. Each commission record represents the platform's fee for
   * facilitating that portion of the transaction. This operation aggregates all
   * such commission records for comprehensive financial tracking and
   * reporting.
   *
   * Security considerations: This operation is restricted to admin users only,
   * as it exposes sensitive platform revenue data and seller transaction fees.
   * Administrators use this endpoint for financial auditing, revenue
   * verification, seller payout calculations, and dispute resolution. The
   * operation ensures that all commission records associated with an order are
   * accessible for complete financial transparency.
   *
   * This operation integrates with the shopping_mall_platform_commissions table
   * as defined in the Prisma schema, utilizing the order relationship to filter
   * and retrieve all relevant commission records. The response includes
   * detailed commission information for each record, supporting administrative
   * financial analysis and order-level revenue tracking.
   *
   * @param connection
   * @param orderId Unique identifier of the target order
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallPlatformCommissions> {
    try {
      return await getShoppingMallAdminOrdersOrderIdPlatformCommissions({
        admin,
        orderId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
