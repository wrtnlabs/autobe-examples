import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallAdminSellerPayouts } from "../../../../providers/postShoppingMallAdminSellerPayouts";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { patchShoppingMallAdminSellerPayouts } from "../../../../providers/patchShoppingMallAdminSellerPayouts";
import { getShoppingMallAdminSellerPayoutsPayoutId } from "../../../../providers/getShoppingMallAdminSellerPayoutsPayoutId";
import { putShoppingMallAdminSellerPayoutsPayoutId } from "../../../../providers/putShoppingMallAdminSellerPayoutsPayoutId";

import { IShoppingMallSellerPayout } from "../../../../api/structures/IShoppingMallSellerPayout";
import { IPageIShoppingMallSellerPayout } from "../../../../api/structures/IPageIShoppingMallSellerPayout";

@Controller("/shoppingMall/admin/sellerPayouts")
export class ShoppingmallAdminSellerpayoutsController {
  /**
   * Create a new seller payout transaction to settle accumulated earnings for a
   * seller account. This operation initiates the payout process by creating a
   * payout record that represents the transfer of seller earnings from the
   * platform to the seller's registered payment account.
   *
   * This endpoint is typically used by the platform's automated payout system
   * or by administrators to manually process seller payments. The payout
   * creation includes calculating the payout amount based on completed orders,
   * deducting platform commissions, and initiating the payment transfer through
   * the configured payment gateway.
   *
   * Security considerations: This operation requires administrative privileges
   * as it involves financial transactions and payment processing. Only platform
   * administrators or authorized automated systems can create payout
   * transactions to prevent unauthorized fund transfers. The operation
   * validates seller account status, earnings balance, and payment method
   * availability before processing.
   *
   * This operation integrates with the shopping_mall_seller_payouts table as
   * defined in the Prisma schema, creating new payout records with proper
   * financial tracking and audit trail information. The created payout record
   * includes amount, status, timestamps, and references to the seller account
   * and associated transactions.
   *
   * @param connection
   * @param body Payout creation information including seller reference, payout
   *   amount, and payment details
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallSellerPayout.ICreate,
  ): Promise<IShoppingMallSellerPayout> {
    try {
      return await postShoppingMallAdminSellerPayouts({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a filtered and paginated list of seller payout records from the
   * shopping mall platform. This operation provides advanced search
   * capabilities for finding seller payouts based on multiple criteria
   * including payout status, settlement period, payout amounts, processing
   * dates, seller identification, and payment method information.
   *
   * The operation supports comprehensive pagination with configurable page
   * sizes and flexible sorting options. Users can sort payouts by settlement
   * date, payout amount, processing status, seller name, or other relevant
   * fields in ascending or descending order. This functionality is essential
   * for sellers tracking their earnings and for platform administrators
   * managing the payout workflow.
   *
   * Security and authorization are carefully managed in this operation. Sellers
   * can only view their own payout records, while platform administrators have
   * access to all seller payouts for financial reconciliation and dispute
   * resolution. The operation implements proper filtering based on the
   * authenticated user's actor type to ensure data privacy and security.
   *
   * This operation integrates with the shopping_mall_seller_payouts table as
   * defined in the Prisma schema, incorporating all payout-related fields
   * including gross revenue, platform commission deductions, net payout
   * amounts, payment processing fees, settlement periods, and payout status
   * tracking. The response provides sellers with complete visibility into their
   * earnings settlement process.
   *
   * Typical use cases include sellers monitoring their monthly earnings
   * settlements, tracking pending payouts, reviewing historical payout records,
   * and reconciling revenue against sales performance. Administrators use this
   * operation for financial reporting, payout batch processing verification,
   * and resolving seller payout inquiries.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering seller
   *   payouts by status, settlement period, amount range, seller
   *   identification, and payment processing details
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallSellerPayout.IRequest,
  ): Promise<IPageIShoppingMallSellerPayout.ISummary> {
    try {
      return await patchShoppingMallAdminSellerPayouts({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve comprehensive details about a specific seller payout transaction
   * from the shopping mall platform. This operation provides complete
   * information about a payout including the payout amount, current status,
   * creation and processing timestamps, and the associated seller account.
   *
   * This endpoint is essential for sellers to track their earnings settlements
   * and for platform administrators to audit payout transactions. The payout
   * information includes all relevant financial details and status tracking
   * necessary for accounting and reconciliation purposes.
   *
   * Security considerations: Only authenticated sellers can access their own
   * payout records, while administrators have access to all payout transactions
   * for platform oversight and financial auditing. The operation implements
   * proper authorization checks to ensure sellers can only view their own
   * payout history.
   *
   * This operation integrates with the shopping_mall_seller_payouts table as
   * defined in the Prisma schema, returning complete payout record details
   * including all financial and status information for the specified payout
   * transaction.
   *
   * @param connection
   * @param payoutId Unique identifier of the target seller payout transaction
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":payoutId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("payoutId")
    payoutId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallSellerPayout> {
    try {
      return await getShoppingMallAdminSellerPayoutsPayoutId({
        admin,
        payoutId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update the details of an existing seller payout transaction in the
   * platform. This operation allows administrators to modify payout information
   * including payment status updates, transaction reference updates, and payout
   * amount adjustments.
   *
   * This operation is critical for managing the seller payment settlement
   * process. Administrators can use this endpoint to update payout records when
   * payment processing status changes, when transaction IDs are received from
   * payment processors, or when corrections are needed to payout amounts.
   *
   * Security considerations include strict authorization checks to ensure only
   * platform administrators can modify payout records. All payout modifications
   * are tracked through audit trails. The operation validates that the payout
   * exists, that status transitions are valid according to business rules, and
   * that any amount modifications are within acceptable ranges. Updates to
   * completed payouts may be restricted based on business policies.
   *
   * @param connection
   * @param payoutId Unique identifier of the target seller payout record
   * @param body Updated payout information including payment status,
   *   transaction details, and payout amounts
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":payoutId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("payoutId")
    payoutId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallSellerPayout.IUpdate,
  ): Promise<IShoppingMallSellerPayout> {
    try {
      return await putShoppingMallAdminSellerPayoutsPayoutId({
        admin,
        payoutId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
