import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallAdminPaymentTransactions } from "../../../../providers/patchShoppingMallAdminPaymentTransactions";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminPaymentTransactionsTransactionId } from "../../../../providers/getShoppingMallAdminPaymentTransactionsTransactionId";

import { IPageIShoppingMallPaymentTransaction } from "../../../../api/structures/IPageIShoppingMallPaymentTransaction";
import { IShoppingMallPaymentTransaction } from "../../../../api/structures/IShoppingMallPaymentTransaction";

@Controller("/shoppingMall/admin/paymentTransactions")
export class ShoppingmallAdminPaymenttransactionsController {
  /**
   * Retrieve a filtered and paginated list of payment transactions from the
   * shopping mall platform. This operation provides advanced search
   * capabilities for finding payment transactions based on multiple criteria
   * including payment method, transaction status, associated order information,
   * buyer details, payment amount ranges, and transaction timestamps.
   *
   * The operation supports comprehensive pagination with configurable page
   * sizes and sorting options. Transactions can be sorted by transaction date,
   * payment amount, status, or other relevant fields in ascending or descending
   * order. This enables efficient navigation through potentially large
   * transaction datasets.
   *
   * Security considerations include strict authorization controls ensuring that
   * only administrators can access payment transaction records. The operation
   * implements rate limiting for search operations to prevent abuse and ensures
   * that sensitive payment information is properly filtered and protected.
   * Transaction data includes references to payment methods, orders, and buyers
   * while maintaining PCI compliance by not exposing sensitive payment card
   * details.
   *
   * This operation integrates with the shopping_mall_payment_transactions table
   * as defined in the Prisma schema, incorporating all available transaction
   * fields and relationships to orders, buyers, and payment methods. The
   * response includes transaction summary information optimized for list
   * displays, with options to include additional details based on authorization
   * level.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for payment
   *   transaction filtering, including order ID, buyer ID, payment status, date
   *   ranges, and amount filters
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallPaymentTransaction.IRequest,
  ): Promise<IPageIShoppingMallPaymentTransaction.ISummary> {
    try {
      return await patchShoppingMallAdminPaymentTransactions({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve comprehensive details about a specific payment transaction
   * identified by its unique transaction ID. This operation returns complete
   * transaction information including payment processing status, payment method
   * details, associated order reference, buyer information, transaction
   * amounts, processing timestamps, and any relevant payment gateway response
   * data.
   *
   * The operation provides full visibility into the payment transaction
   * lifecycle, including when the payment was initiated, processed, and
   * confirmed. It includes relationships to the associated order, buyer
   * account, and payment method used for the transaction. This detailed view is
   * essential for payment reconciliation, dispute resolution, and financial
   * auditing purposes.
   *
   * Security considerations include strict authorization controls ensuring that
   * only administrators can access detailed payment transaction records. The
   * operation protects sensitive payment information by filtering out full
   * payment card numbers and other PCI-sensitive data while providing
   * sufficient transaction details for administrative and support purposes. All
   * access to payment transaction details is logged for audit trail
   * compliance.
   *
   * This operation integrates with the shopping_mall_payment_transactions table
   * as defined in the Prisma schema, incorporating all available transaction
   * fields and relationships to payment methods, orders, and buyers. The
   * response provides complete transaction information necessary for
   * administrative oversight and financial operations.
   *
   * @param connection
   * @param transactionId Unique identifier of the target payment transaction
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":transactionId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("transactionId")
    transactionId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallPaymentTransaction> {
    try {
      return await getShoppingMallAdminPaymentTransactionsTransactionId({
        admin,
        transactionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
