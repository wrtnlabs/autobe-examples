import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallAdminReviewsReviewIdReports } from "../../../../../providers/patchShoppingMallAdminReviewsReviewIdReports";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminReviewsReviewIdReportsReportId } from "../../../../../providers/getShoppingMallAdminReviewsReviewIdReportsReportId";

import { IPageIShoppingMallReviewReport } from "../../../../../api/structures/IPageIShoppingMallReviewReport";
import { IShoppingMallReviewReport } from "../../../../../api/structures/IShoppingMallReviewReport";

@Controller("/shoppingMall/admin/reviews/:reviewId/reports")
export class ShoppingmallAdminReviewsReportsController {
  /**
   * Retrieve a filtered and paginated list of review reports submitted for a
   * specific product review in the shopping mall marketplace. This operation
   * provides advanced search capabilities for finding reports based on multiple
   * criteria including report reason categories, moderation status, reporter
   * information, and submission timestamps.
   *
   * The operation supports comprehensive pagination with configurable page
   * sizes and sorting options. Reports can be sorted by submission date,
   * moderation status, report reason, or other relevant fields in ascending or
   * descending order. This enables administrators and moderators to efficiently
   * manage and process flagged reviews.
   *
   * Security considerations include restricting access to authorized moderators
   * and administrators only, as review reports contain sensitive moderation
   * information. The operation applies appropriate filtering based on the
   * requesting user's authorization level. Regular buyers cannot access report
   * data to prevent gaming the moderation system.
   *
   * This operation integrates with the shopping_mall_review_reports table as
   * defined in the Prisma schema, incorporating all available report fields and
   * relationships to reviews and reporters. The response includes report
   * summary information optimized for moderation workflows, with options to
   * include additional context based on authorization level. Related operations
   * include retrieving individual report details (GET
   * /reviews/{reviewId}/reports/{reportId}) and creating new reports (POST
   * /reviews/{reviewId}/reports).
   *
   * @param connection
   * @param reviewId Unique identifier of the target review for which reports
   *   are being retrieved
   * @param body Search criteria and pagination parameters for filtering review
   *   reports
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallReviewReport.IRequest,
  ): Promise<IPageIShoppingMallReviewReport.ISummary> {
    try {
      return await patchShoppingMallAdminReviewsReviewIdReports({
        admin,
        reviewId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Fetch complete details of a review report submission including the report
   * reason, description, reporter information, submission timestamp, and
   * current moderation status. This operation provides transparency into the
   * review reporting and moderation process.
   *
   * The response includes comprehensive report information such as the reason
   * category (spam, offensive, fake, irrelevant, etc.), the optional detailed
   * description provided by the reporter, the buyer who submitted the report,
   * when the report was created, and any moderation actions taken.
   *
   * Security: Access control depends on the requesting user. Admins can view
   * all reports for moderation purposes. Buyers may only view their own
   * submitted reports. The operation validates that the report belongs to the
   * specified review and enforces appropriate authorization rules.
   *
   * This operation is commonly used in admin moderation dashboards to review
   * flagged content and make decisions about review visibility or user actions.
   * It may also be used by buyers to check the status of reports they
   * submitted.
   *
   * @param connection
   * @param reviewId Unique identifier of the review associated with this report
   * @param reportId Unique identifier of the target report
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":reportId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
    @TypedParam("reportId")
    reportId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallReviewReport> {
    try {
      return await getShoppingMallAdminReviewsReviewIdReportsReportId({
        admin,
        reviewId,
        reportId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
