import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallAdminReviewsReviewIdModerationLogs } from "../../../../../providers/patchShoppingMallAdminReviewsReviewIdModerationLogs";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminReviewsReviewIdModerationLogsLogId } from "../../../../../providers/getShoppingMallAdminReviewsReviewIdModerationLogsLogId";

import { IPageIShoppingMallReviewModerationLog } from "../../../../../api/structures/IPageIShoppingMallReviewModerationLog";
import { IShoppingMallReviewModerationLog } from "../../../../../api/structures/IShoppingMallReviewModerationLog";

@Controller("/shoppingMall/admin/reviews/:reviewId/moderationLogs")
export class ShoppingmallAdminReviewsModerationlogsController {
  /**
   * Retrieve a comprehensive audit trail of all moderation actions performed on
   * a specific product review. This operation provides administrators with
   * complete visibility into the review moderation lifecycle, including who
   * made changes, when changes occurred, what actions were taken, and the
   * reasoning behind moderation decisions.
   *
   * The operation supports advanced filtering capabilities to help
   * administrators analyze moderation patterns, investigate specific incidents,
   * and ensure moderation policy compliance. Filters include date ranges,
   * specific moderator accounts, moderation action types (approved, rejected,
   * content_edited, reinstated), and moderation status outcomes.
   *
   * Security: This operation is restricted to platform administrators only, as
   * moderation logs contain sensitive administrative information and internal
   * policy enforcement details. The logs provide complete transparency into the
   * moderation process for audit and compliance purposes. Rate limiting is
   * applied to prevent abuse of this administrative endpoint.
   *
   * This operation integrates with the shopping_mall_review_moderation_logs
   * table as defined in the Prisma schema, returning complete log entries with
   * moderator information, timestamps, action details, and reasoning. The
   * response includes paginated results optimized for administrative review
   * interfaces.
   *
   * @param connection
   * @param reviewId Unique identifier of the target product review whose
   *   moderation history is being retrieved
   * @param body Search criteria and pagination parameters for filtering review
   *   moderation logs by moderator, action type, date range, and other
   *   attributes
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallReviewModerationLog.IRequest,
  ): Promise<IPageIShoppingMallReviewModerationLog.ISummary> {
    try {
      return await patchShoppingMallAdminReviewsReviewIdModerationLogs({
        admin,
        reviewId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve comprehensive details about a single moderation action performed
   * on a product review. This operation provides administrators with in-depth
   * information about a specific moderation event, including the complete
   * context of the action, the moderator's decision-making rationale, and any
   * supporting documentation or evidence.
   *
   * The detailed moderation log includes the moderator's identity, precise
   * timestamp of the action, the specific moderation action type (such as
   * approval, rejection, content editing, or reinstatement), the review's state
   * before and after the action, and the moderator's detailed reasoning or
   * notes explaining the decision. This information is critical for moderation
   * quality assurance, dispute resolution, and policy compliance audits.
   *
   * Security: Access to individual moderation logs is restricted to platform
   * administrators only, as these records contain sensitive internal
   * decision-making information and may include references to user reports,
   * policy violations, or legal considerations. The operation ensures that
   * moderation actions remain transparent and accountable within the
   * administrative team while protecting sensitive information from public
   * access.
   *
   * This operation integrates with the shopping_mall_review_moderation_logs
   * table as defined in the Prisma schema, returning the complete log entry
   * with all associated metadata, moderator information, and action details for
   * comprehensive administrative review and audit purposes.
   *
   * @param connection
   * @param reviewId Unique identifier of the product review associated with
   *   this moderation log entry
   * @param logId Unique identifier of the specific moderation log entry to
   *   retrieve
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":logId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
    @TypedParam("logId")
    logId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallReviewModerationLog> {
    try {
      return await getShoppingMallAdminReviewsReviewIdModerationLogsLogId({
        admin,
        reviewId,
        logId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
