import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallAdminBuyers } from "../../../../providers/patchShoppingMallAdminBuyers";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminBuyersBuyerId } from "../../../../providers/getShoppingMallAdminBuyersBuyerId";
import { putShoppingMallAdminBuyersBuyerId } from "../../../../providers/putShoppingMallAdminBuyersBuyerId";
import { deleteShoppingMallAdminBuyersBuyerId } from "../../../../providers/deleteShoppingMallAdminBuyersBuyerId";

import { IPageIShoppingMallBuyer } from "../../../../api/structures/IPageIShoppingMallBuyer";
import { IShoppingMallBuyer } from "../../../../api/structures/IShoppingMallBuyer";

@Controller("/shoppingMall/admin/buyers")
export class ShoppingmallAdminBuyersController {
  /**
   * Search and retrieve a filtered, paginated list of shopping mall buyers.
   *
   * Retrieve a filtered and paginated list of authenticated buyer accounts from
   * the shopping mall marketplace. This operation provides comprehensive search
   * capabilities for finding buyers based on multiple criteria including name
   * matching, email filtering, registration date ranges, and account status.
   *
   * The operation supports full pagination with configurable page sizes and
   * advanced sorting options. Administrators can sort buyer lists by
   * registration date, last login time, name, email, or other relevant fields
   * in ascending or descending order. The search functionality enables partial
   * text matching on buyer names and emails for flexible discovery.
   *
   * Security considerations include appropriate filtering of sensitive buyer
   * information based on the requesting administrator's authorization level.
   * Only users with administrative permissions can access buyer account lists.
   * The operation includes rate limiting to prevent abuse and protect buyer
   * privacy. Audit logging tracks all buyer list access for compliance and
   * security monitoring.
   *
   * This operation integrates with the shopping_mall_buyers table as defined in
   * the Prisma schema, incorporating all available buyer fields and
   * relationships. The response returns buyer summary information optimized for
   * administrative list displays, including essential account details while
   * protecting sensitive authentication credentials. Related operations include
   * retrieving individual buyer details (GET /buyers/{buyerId}) and updating
   * buyer accounts (PUT /buyers/{buyerId}).
   *
   * @param connection
   * @param body Search criteria and pagination parameters for buyer account
   *   filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallBuyer.IRequest,
  ): Promise<IPageIShoppingMallBuyer.ISummary> {
    try {
      return await patchShoppingMallAdminBuyers({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific buyer account.
   *
   * Retrieve comprehensive details about a specific buyer account in the
   * shopping mall marketplace. This operation returns the complete buyer
   * profile including personal information, contact details, account status,
   * and registration metadata.
   *
   * The operation provides access to buyer account information for
   * administrative purposes and buyer self-service scenarios. Buyers can view
   * their own account details, while administrators can access any buyer
   * account for customer support, account management, and platform governance
   * purposes.
   *
   * Security considerations include proper authorization checks to ensure
   * buyers can only access their own account information unless they have
   * administrative privileges. The response includes sensitive personal
   * information that must be handled according to data protection requirements
   * and privacy policies.
   *
   * This operation integrates with the shopping_mall_buyers table as defined in
   * the Prisma schema, returning all available buyer fields including
   * registration timestamps, account status indicators, and contact
   * information. The response provides detailed buyer information optimized for
   * profile display and account management interfaces.
   *
   * @param connection
   * @param buyerId Unique identifier of the target buyer account
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":buyerId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("buyerId")
    buyerId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallBuyer> {
    try {
      return await getShoppingMallAdminBuyersBuyerId({
        admin,
        buyerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing buyer account's information.
   *
   * Update the profile information and account details of an existing buyer in
   * the shopping mall marketplace. This operation allows modification of buyer
   * account data including personal information, contact details, and account
   * preferences.
   *
   * The operation supports buyer self-service profile management as well as
   * administrative account updates. Buyers can update their own account
   * information to maintain accurate profile data, while administrators can
   * modify buyer accounts for customer support purposes, account corrections,
   * or compliance requirements.
   *
   * Security considerations include proper authorization to ensure buyers can
   * only update their own accounts unless they possess administrative
   * privileges. The operation validates all input data according to business
   * rules and data integrity constraints. Certain sensitive fields may be
   * restricted from modification depending on the actor's authorization level.
   *
   * This operation integrates with the shopping_mall_buyers table as defined in
   * the Prisma schema, updating modifiable buyer fields while preserving
   * system-managed fields such as registration timestamps and account
   * identifiers. The response returns the updated buyer account information
   * reflecting all applied changes.
   *
   * @param connection
   * @param buyerId Unique identifier of the target buyer account to update
   * @param body Updated buyer account information and profile data
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":buyerId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("buyerId")
    buyerId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallBuyer.IUpdate,
  ): Promise<IShoppingMallBuyer> {
    try {
      return await putShoppingMallAdminBuyersBuyerId({
        admin,
        buyerId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a buyer account from the platform.
   *
   * Permanently remove a buyer account from the shopping mall platform. This
   * operation performs a hard delete, completely removing the buyer record and
   * all associated data from the database.
   *
   * This is a destructive administrative operation that cannot be undone. When
   * a buyer account is deleted, all related data including cart items, wishlist
   * items, addresses, orders, and reviews associated with this buyer will be
   * handled according to the database cascade rules defined in the Prisma
   * schema.
   *
   * Security: Only platform administrators with elevated permissions can delete
   * buyer accounts. This operation should be used with extreme caution and
   * typically only for compliance purposes (e.g., GDPR data deletion requests),
   * account cleanup of fraudulent accounts, or other administrative
   * necessities.
   *
   * The deletion is immediate and permanent. There is no soft-delete or
   * archival mechanism in this operation - the data is completely removed from
   * the system. Administrators should ensure proper backups and audit trails
   * are maintained before performing this operation.
   *
   * @param connection
   * @param buyerId Unique identifier of the buyer account to be permanently
   *   deleted
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":buyerId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("buyerId")
    buyerId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallAdminBuyersBuyerId({
        admin,
        buyerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
