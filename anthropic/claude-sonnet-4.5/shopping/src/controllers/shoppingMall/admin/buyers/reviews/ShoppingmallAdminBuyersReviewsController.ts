import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallAdminBuyersBuyerIdReviews } from "../../../../../providers/patchShoppingMallAdminBuyersBuyerIdReviews";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";

import { IPageIShoppingMallReview } from "../../../../../api/structures/IPageIShoppingMallReview";
import { IShoppingMallReview } from "../../../../../api/structures/IShoppingMallReview";

@Controller("/shoppingMall/admin/buyers/:buyerId/reviews")
export class ShoppingmallAdminBuyersReviewsController {
  /**
   * Retrieve a comprehensive list of all product reviews authored by a specific
   * buyer account with advanced filtering and search capabilities. This
   * operation enables buyers to view and manage their complete review history
   * across all purchases made on the platform.
   *
   * The operation supports filtering by multiple criteria including the
   * products reviewed, star ratings given, review creation date ranges, and
   * review publication status. Buyers can search within their own review
   * content to find specific feedback they provided. Results can be sorted
   * chronologically or by product category, helping buyers track their feedback
   * contributions over time.
   *
   * Security considerations include ensuring buyers can only access their own
   * reviews when using standard buyer authentication, while administrators may
   * access any buyer's review history for moderation and support purposes. The
   * response includes complete review details along with associated product
   * information, seller responses if available, and helpfulness metrics from
   * other users.
   *
   * This operation integrates with the shopping_mall_reviews table as defined
   * in the Prisma schema, incorporating relationships to the buyer account,
   * associated sales, review images, and engagement metrics. The response
   * provides detailed review information suitable for buyer profile pages and
   * review management interfaces, enabling buyers to track their marketplace
   * participation and edit or delete their reviews as needed.
   *
   * @param connection
   * @param buyerId Unique identifier of the target buyer account
   * @param body Search criteria, filtering options, and pagination parameters
   *   for buyer review retrieval
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("buyerId")
    buyerId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallReview.IRequest,
  ): Promise<IPageIShoppingMallReview.ISummary> {
    try {
      return await patchShoppingMallAdminBuyersBuyerIdReviews({
        admin,
        buyerId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
