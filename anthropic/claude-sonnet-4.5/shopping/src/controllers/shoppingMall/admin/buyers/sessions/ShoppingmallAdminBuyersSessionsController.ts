import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallAdminBuyersBuyerIdSessions } from "../../../../../providers/patchShoppingMallAdminBuyersBuyerIdSessions";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminBuyersBuyerIdSessionsSessionId } from "../../../../../providers/getShoppingMallAdminBuyersBuyerIdSessionsSessionId";
import { deleteShoppingMallAdminBuyersBuyerIdSessionsSessionId } from "../../../../../providers/deleteShoppingMallAdminBuyersBuyerIdSessionsSessionId";

import { IPageIShoppingMallBuyerSession } from "../../../../../api/structures/IPageIShoppingMallBuyerSession";
import { IShoppingMallBuyerSession } from "../../../../../api/structures/IShoppingMallBuyerSession";

@Controller("/shoppingMall/admin/buyers/:buyerId/sessions")
export class ShoppingmallAdminBuyersSessionsController {
  /**
   * Search and retrieve buyer authentication sessions with filtering and
   * pagination.
   *
   * Retrieve a filtered, paginated list of authentication sessions for a
   * specific buyer account. This operation provides comprehensive search
   * capabilities for monitoring buyer login activities, tracking active
   * sessions, and conducting security audits.
   *
   * The operation supports advanced filtering options including session
   * creation date ranges, session status (active/expired), IP address
   * filtering, and user agent matching. Administrators can sort results by
   * session creation time, last activity time, or expiration date in ascending
   * or descending order.
   *
   * Security considerations: This operation is restricted to platform
   * administrators only, as session information contains sensitive security
   * data including IP addresses, authentication tokens, and login patterns. The
   * operation implements rate limiting to prevent abuse and excessive querying
   * of session data.
   *
   * This operation integrates with the shopping_mall_buyer_sessions table as
   * defined in the Prisma schema. The response includes session summary
   * information optimized for administrative monitoring and security analysis.
   * Administrators can use this data to identify suspicious login patterns,
   * manage active sessions, or investigate security incidents related to
   * specific buyer accounts.
   *
   * Related operations: Individual session details can be retrieved using GET
   * /buyers/{buyerId}/sessions/{sessionId} for more detailed investigation.
   *
   * @param connection
   * @param buyerId Unique identifier of the buyer whose sessions are being
   *   queried
   * @param body Search criteria and pagination parameters for filtering buyer
   *   sessions
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("buyerId")
    buyerId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallBuyerSession.IRequest,
  ): Promise<IPageIShoppingMallBuyerSession.ISummary> {
    try {
      return await patchShoppingMallAdminBuyersBuyerIdSessions({
        admin,
        buyerId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific buyer authentication
   * session.
   *
   * Retrieve comprehensive details about a specific buyer authentication
   * session in the shopping mall platform. This operation provides complete
   * session information including authentication timestamps, JWT token details,
   * IP address, user agent, and session status.
   *
   * This endpoint serves multiple purposes including session verification,
   * security auditing, and administrative oversight. Buyers can view their own
   * active and historical sessions to monitor account access, while
   * administrators can inspect any buyer's sessions for security
   * investigations, fraud detection, or support purposes.
   *
   * Security considerations include strict authorization checks to ensure
   * buyers can only access their own sessions unless the requester has
   * administrative privileges. The operation returns sensitive session data
   * including token information and authentication metadata, so appropriate
   * access controls are enforced. Session data includes creation timestamps,
   * expiration times, last activity indicators, and the authentication context
   * that established the session.
   *
   * This operation integrates with the shopping_mall_buyer_sessions table as
   * defined in the Prisma schema, returning complete session details optimized
   * for security monitoring and session management interfaces. The response
   * includes all session attributes necessary for session validation, renewal
   * decisions, and security audit trails.
   *
   * @param connection
   * @param buyerId Unique identifier of the buyer account that owns the session
   * @param sessionId Unique identifier of the specific authentication session
   *   to retrieve
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("buyerId")
    buyerId: string & tags.Format<"uuid">,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallBuyerSession> {
    try {
      return await getShoppingMallAdminBuyersBuyerIdSessionsSessionId({
        admin,
        buyerId,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Terminate and delete a specific buyer authentication session.
   *
   * Terminate an active buyer authentication session, effectively logging out
   * the buyer from that specific session. This operation permanently removes
   * the session record from the database, invalidating any JWT tokens
   * associated with the session and preventing further authenticated requests
   * using those credentials.
   *
   * This endpoint supports multiple use cases including user-initiated logout,
   * administrative session termination for security reasons, and cleanup of
   * compromised or suspicious sessions. Buyers can delete their own active
   * sessions to log out from specific devices or browsers, while administrators
   * can force-terminate any buyer's sessions during security incidents, account
   * suspensions, or fraud investigations.
   *
   * Security considerations include strict ownership verification to ensure
   * buyers can only delete their own sessions unless the requester has
   * administrative privileges. The operation immediately invalidates the
   * session, requiring the user to re-authenticate to access protected
   * resources. Multi-device session management is supported, allowing buyers to
   * maintain sessions on multiple devices while selectively terminating
   * specific ones.
   *
   * This operation integrates with the shopping_mall_buyer_sessions table as
   * defined in the Prisma schema, performing a permanent deletion of the
   * session record. Upon successful deletion, the session cannot be recovered
   * and any associated authentication tokens become invalid. The operation is
   * idempotent - attempting to delete an already-deleted session returns
   * success without error.
   *
   * @param connection
   * @param buyerId Unique identifier of the buyer account that owns the session
   * @param sessionId Unique identifier of the authentication session to
   *   terminate and delete
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":sessionId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("buyerId")
    buyerId: string & tags.Format<"uuid">,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallAdminBuyersBuyerIdSessionsSessionId({
        admin,
        buyerId,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
