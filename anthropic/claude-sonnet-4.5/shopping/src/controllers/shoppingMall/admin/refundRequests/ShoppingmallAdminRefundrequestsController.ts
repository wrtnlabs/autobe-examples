import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallAdminRefundRequests } from "../../../../providers/patchShoppingMallAdminRefundRequests";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminRefundRequestsRefundRequestId } from "../../../../providers/getShoppingMallAdminRefundRequestsRefundRequestId";
import { putShoppingMallAdminRefundRequestsRefundRequestId } from "../../../../providers/putShoppingMallAdminRefundRequestsRefundRequestId";
import { deleteShoppingMallAdminRefundRequestsRefundRequestId } from "../../../../providers/deleteShoppingMallAdminRefundRequestsRefundRequestId";

import { IPageIShoppingMallRefundRequest } from "../../../../api/structures/IPageIShoppingMallRefundRequest";
import { IShoppingMallRefundRequest } from "../../../../api/structures/IShoppingMallRefundRequest";

@Controller("/shoppingMall/admin/refundRequests")
export class ShoppingmallAdminRefundrequestsController {
  /**
   * Retrieve a comprehensive list of refund requests with advanced filtering,
   * searching, sorting, and pagination capabilities.
   *
   * This operation provides administrators with powerful search functionality
   * to find and review refund requests based on multiple criteria. Filters can
   * include buyer information, associated order details, approval status
   * (pending, approved, rejected), submission date ranges, refund amount
   * ranges, and request reasons. The search supports partial text matching on
   * refund reasons and notes fields.
   *
   * The operation returns paginated results optimized for administrative
   * dashboards and refund management interfaces. Each result includes summary
   * information about the refund request including the requesting buyer,
   * associated order, requested amount, current approval status, submission
   * timestamp, and any admin notes or decisions. Sorting options allow ordering
   * by submission date, refund amount, approval status, or last update
   * timestamp in ascending or descending order.
   *
   * Security and authorization: This operation is restricted to administrative
   * users who have permissions to review and manage refund requests. The
   * response filters sensitive buyer financial information based on the admin's
   * authorization level. Rate limiting applies to prevent abuse of the search
   * functionality.
   *
   * Business context: Refund requests are submitted by buyers after receiving
   * orders, typically due to product issues, shipping problems, or buyer's
   * remorse within the platform's refund policy window. Admins use this search
   * operation to queue, prioritize, and process refund requests systematically.
   * The operation integrates with the shopping_mall_refund_requests table and
   * related buyer, order, and transaction records to provide complete context
   * for refund decisions.
   *
   * @param connection
   * @param body Search criteria, filtering options, sorting preferences, and
   *   pagination parameters for refund request retrieval
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallRefundRequest.IRequest,
  ): Promise<IPageIShoppingMallRefundRequest.ISummary> {
    try {
      return await patchShoppingMallAdminRefundRequests({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve complete details of a specific refund request identified by its
   * unique ID. This operation provides comprehensive information about a
   * buyer's refund request including the associated order, requested refund
   * amount, reason for refund, current processing status, and administrative
   * decision details if the request has been reviewed.
   *
   * This endpoint serves multiple user actors with different access purposes.
   * Buyers can view their own refund requests to track the status and outcome
   * of their refund submissions. Admins access this endpoint to review refund
   * request details when making approval or rejection decisions, viewing all
   * submitted evidence and justification provided by the buyer.
   *
   * The response includes the complete refund request entity with full details
   * about the refund reason, requested amount, current status (pending,
   * approved, rejected), timestamps for submission and processing, and if
   * processed by an admin, the decision details including admin notes and
   * decision timestamp. The operation validates that the requesting user has
   * appropriate authorization to view the refund request - buyers can only
   * access their own requests while admins can view any refund request in the
   * system.
   *
   * Security considerations include proper authorization checking to ensure
   * buyers cannot view other buyers' refund requests, and appropriate filtering
   * of sensitive admin notes that should only be visible to admin users. The
   * operation integrates with the shopping_mall_refund_requests table as
   * defined in the Prisma schema, returning the complete refund request record
   * with all available fields and relationships.
   *
   * @param connection
   * @param refundRequestId Unique identifier of the target refund request
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":refundRequestId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("refundRequestId")
    refundRequestId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallRefundRequest> {
    try {
      return await getShoppingMallAdminRefundRequestsRefundRequestId({
        admin,
        refundRequestId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update the status and administrative review information for a specific
   * refund request in the shopping mall platform. This operation is exclusively
   * available to platform administrators who are responsible for reviewing and
   * processing buyer refund requests.
   *
   * Admins can approve or reject refund requests by updating the status field
   * to either 'approved' or 'rejected'. When processing a refund request,
   * admins must provide detailed notes explaining their decision rationale. The
   * system automatically records which admin processed the request and when the
   * decision was made, creating a complete audit trail for refund operations.
   *
   * Security considerations include strict authorization enforcement ensuring
   * only admins can access this endpoint. The operation validates that the
   * refund request exists and is in a valid state for status updates. Business
   * rules enforce that approved refunds trigger the creation of corresponding
   * refund transaction records in the shopping_mall_refund_transactions table.
   * Rate limiting and audit logging apply to track all administrative actions
   * on refund requests.
   *
   * This operation integrates with the shopping_mall_refund_requests table as
   * defined in the Prisma schema, updating the status, admin_notes, reviewed_at
   * timestamp, and reviewed_by_admin_id fields. The response includes the
   * complete updated refund request information including buyer details, order
   * information, and the admin's review decision.
   *
   * @param connection
   * @param refundRequestId Unique identifier of the target refund request
   *   (global scope)
   * @param body Updated refund request status and admin review information
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":refundRequestId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("refundRequestId")
    refundRequestId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallRefundRequest.IUpdate,
  ): Promise<IShoppingMallRefundRequest> {
    try {
      return await putShoppingMallAdminRefundRequestsRefundRequestId({
        admin,
        refundRequestId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently remove a specific refund request record from the shopping mall
   * platform. This operation is exclusively available to platform
   * administrators and should be used cautiously as it performs a hard delete
   * operation.
   *
   * This endpoint is designed for administrative cleanup scenarios such as
   * removing duplicate refund requests, eliminating fraudulent refund claims
   * identified during investigation, or cleaning up test data from the system.
   * Records are completely deleted and cannot be recovered after this operation
   * executes successfully.
   *
   * Security considerations include strict authorization enforcement ensuring
   * only admins can access this endpoint. The operation validates that the
   * refund request exists before attempting deletion. Business rules should
   * prevent deletion of refund requests that have already been approved and
   * have associated refund transactions, as this would create data integrity
   * issues. Audit logging captures all deletion actions with admin identity and
   * timestamp for compliance and accountability.
   *
   * This operation integrates with the shopping_mall_refund_requests table as
   * defined in the Prisma schema. The deletion cascades to any related records
   * as defined by the schema's referential integrity constraints. The response
   * returns the deleted refund request information for confirmation and audit
   * purposes.
   *
   * @param connection
   * @param refundRequestId Unique identifier of the target refund request
   *   (global scope)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":refundRequestId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("refundRequestId")
    refundRequestId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallRefundRequest> {
    try {
      return await deleteShoppingMallAdminRefundRequestsRefundRequestId({
        admin,
        refundRequestId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
