import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallReviewsReviewIdImages } from "../../../../providers/patchShoppingMallReviewsReviewIdImages";
import { getShoppingMallReviewsReviewIdImagesImageId } from "../../../../providers/getShoppingMallReviewsReviewIdImagesImageId";

import { IPageIShoppingMallReviewImage } from "../../../../api/structures/IPageIShoppingMallReviewImage";
import { IShoppingMallReviewImage } from "../../../../api/structures/IShoppingMallReviewImage";

@Controller("/shoppingMall/reviews/:reviewId/images")
export class ShoppingmallReviewsImagesController {
  /**
   * Search and retrieve a filtered, paginated list of review images for a
   * specific product review.
   *
   * Retrieve a filtered and paginated list of product review images from a
   * specific review in the shopping mall platform. This operation provides
   * advanced search capabilities for finding review images based on multiple
   * criteria including upload date ranges, image status, display order, and
   * other relevant filters.
   *
   * The operation supports comprehensive pagination with configurable page
   * sizes and sorting options. Images can be sorted by upload date, display
   * order, or other relevant fields in ascending or descending order. This is
   * particularly useful for buyers viewing review images and for moderators
   * managing review content.
   *
   * Security considerations include appropriate filtering of images based on
   * review status and moderation state. Only approved review images are visible
   * to public users, while moderators and admins can access images from reviews
   * under moderation. The operation integrates with the
   * shopping_mall_review_images table as defined in the Prisma schema.
   *
   * This operation is essential for the review browsing experience, allowing
   * buyers to see visual evidence of product quality through images uploaded by
   * verified purchasers. It also supports administrative workflows for content
   * moderation and quality control.
   *
   * @param connection
   * @param reviewId Unique identifier of the target product review
   * @param body Search criteria and pagination parameters for filtering review
   *   images
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallReviewImage.IRequest,
  ): Promise<IPageIShoppingMallReviewImage.ISummary> {
    try {
      return await patchShoppingMallReviewsReviewIdImages({
        reviewId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific product review image.
   *
   * Retrieve complete details of a specific product review image from the
   * shopping mall platform. This operation returns comprehensive information
   * about a single review image including its URL, upload timestamp, display
   * order within the review, moderation status, and relationship to the parent
   * review.
   *
   * The operation provides full image details necessary for displaying review
   * images in product detail pages, review galleries, and moderation
   * interfaces. It includes metadata about when the image was uploaded, its
   * position in the review's image sequence, and any moderation flags or status
   * information.
   *
   * Security considerations ensure that only approved images from approved
   * reviews are accessible to public users. Moderators and administrators can
   * access images regardless of approval status for content moderation
   * purposes. The operation validates that the imageId corresponds to an image
   * that actually belongs to the specified reviewId to prevent unauthorized
   * access.
   *
   * This operation is crucial for the product review experience, enabling
   * buyers to view high-quality images uploaded by verified purchasers. It also
   * supports administrative workflows for image moderation, quality control,
   * and content policy enforcement.
   *
   * @param connection
   * @param reviewId Unique identifier of the target product review
   * @param imageId Unique identifier of the target review image
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":imageId")
  public async at(
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
    @TypedParam("imageId")
    imageId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallReviewImage> {
    try {
      return await getShoppingMallReviewsReviewIdImagesImageId({
        reviewId,
        imageId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
