import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { getShoppingMallBuyerRefundRequestsRefundRequestId } from "../../../../providers/getShoppingMallBuyerRefundRequestsRefundRequestId";
import { BuyerAuth } from "../../../../decorators/BuyerAuth";
import { BuyerPayload } from "../../../../decorators/payload/BuyerPayload";
import { postShoppingMallBuyerRefundRequests } from "../../../../providers/postShoppingMallBuyerRefundRequests";

import { IShoppingMallRefundRequest } from "../../../../api/structures/IShoppingMallRefundRequest";

@Controller("/shoppingMall/buyer/refundRequests")
export class ShoppingmallBuyerRefundrequestsController {
  /**
   * Retrieve detailed information about a specific refund request.
   *
   * Retrieve complete details of a specific refund request identified by its
   * unique ID. This operation provides comprehensive information about a
   * buyer's refund request including the associated order, requested refund
   * amount, reason for refund, current processing status, and administrative
   * decision details if the request has been reviewed.
   *
   * This endpoint serves multiple user actors with different access purposes.
   * Buyers can view their own refund requests to track the status and outcome
   * of their refund submissions. Admins access this endpoint to review refund
   * request details when making approval or rejection decisions, viewing all
   * submitted evidence and justification provided by the buyer.
   *
   * The response includes the complete refund request entity with full details
   * about the refund reason, requested amount, current status (pending,
   * approved, rejected), timestamps for submission and processing, and if
   * processed by an admin, the decision details including admin notes and
   * decision timestamp. The operation validates that the requesting user has
   * appropriate authorization to view the refund request - buyers can only
   * access their own requests while admins can view any refund request in the
   * system.
   *
   * Security considerations include proper authorization checking to ensure
   * buyers cannot view other buyers' refund requests, and appropriate filtering
   * of sensitive admin notes that should only be visible to admin users. The
   * operation integrates with the shopping_mall_refund_requests table as
   * defined in the Prisma schema, returning the complete refund request record
   * with all available fields and relationships.
   *
   * @param connection
   * @param refundRequestId Unique identifier of the target refund request
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":refundRequestId")
  public async at(
    @BuyerAuth()
    buyer: BuyerPayload,
    @TypedParam("refundRequestId")
    refundRequestId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallRefundRequest> {
    try {
      return await getShoppingMallBuyerRefundRequestsRefundRequestId({
        buyer,
        refundRequestId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Create a new refund request for a delivered order.
   *
   * Create a new refund request submission for a delivered order that a buyer
   * wishes to return and receive a refund for. This operation allows
   * authenticated buyers to formally request a refund by providing the order
   * identifier, detailed reason for the refund, and the requested refund
   * amount.
   *
   * The refund request creation process validates several business rules before
   * accepting the submission. The system verifies that the specified order
   * exists, belongs to the authenticated buyer making the request, and has a
   * status of 'delivered' - ensuring that refund requests can only be submitted
   * for orders that have been successfully delivered to the buyer. The
   * operation also validates that the requested refund amount does not exceed
   * the original order total amount.
   *
   * Upon successful creation, the refund request is initialized with a status
   * of 'pending' and queued for administrative review. The buyer's identity is
   * automatically extracted from the JWT authentication token and associated
   * with the refund request record. The system captures the submission
   * timestamp for audit trail purposes and tracks the complete refund request
   * lifecycle from submission through admin decision.
   *
   * Security considerations include authentication requirement to ensure only
   * legitimate buyers can submit refund requests, authorization validation to
   * prevent buyers from creating refund requests for orders they do not own,
   * and business rule validation to maintain data integrity such as preventing
   * duplicate refund requests for the same order and enforcing reasonable
   * refund amount limits.
   *
   * This operation integrates with the shopping_mall_refund_requests table as
   * defined in the Prisma schema, creating a new refund request record with all
   * required fields populated. The created refund request becomes immediately
   * visible to admin users for review and decision-making while the buyer can
   * track its status through their order history and refund request views.
   *
   * @param connection
   * @param body Refund request creation data including order identifier, refund
   *   reason, and requested amount
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @BuyerAuth()
    buyer: BuyerPayload,
    @TypedBody()
    body: IShoppingMallRefundRequest.ICreate,
  ): Promise<IShoppingMallRefundRequest> {
    try {
      return await postShoppingMallBuyerRefundRequests({
        buyer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
