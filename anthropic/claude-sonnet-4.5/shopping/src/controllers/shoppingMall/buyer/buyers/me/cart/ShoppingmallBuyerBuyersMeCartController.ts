import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { patchShoppingMallBuyerBuyersMeCart } from "../../../../../../providers/patchShoppingMallBuyerBuyersMeCart";
import { BuyerAuth } from "../../../../../../decorators/BuyerAuth";
import { BuyerPayload } from "../../../../../../decorators/payload/BuyerPayload";

import { IPageIShoppingMallCartItem } from "../../../../../../api/structures/IPageIShoppingMallCartItem";
import { IShoppingMallCartItem } from "../../../../../../api/structures/IShoppingMallCartItem";

@Controller("/shoppingMall/buyer/buyers/me/cart")
export class ShoppingmallBuyerBuyersMeCartController {
  /**
   * Search and retrieve the authenticated buyer's shopping cart items with
   * filtering.
   *
   * Retrieve a filtered and paginated list of shopping cart items for the
   * currently authenticated buyer. This operation provides the buyer's personal
   * cart contents with support for complex queries including product filtering,
   * sorting, and pagination.
   *
   * The shopping cart is a buyer-specific collection of products they intend to
   * purchase. Each cart item references a specific product SKU (variant) with a
   * desired quantity. The cart persists across sessions, allowing buyers to
   * save items for later purchase. This operation returns the current state of
   * the buyer's cart with full product details for each item.
   *
   * The operation supports comprehensive filtering and search capabilities
   * including: filtering by product category, price range filtering,
   * availability status filtering (in-stock vs out-of-stock items), sorting by
   * date added, price, or product name, and pagination for large carts. The
   * response includes detailed information about each cart item including the
   * product details, selected SKU variant, current price, availability status,
   * and quantity.
   *
   * Security considerations: This operation is restricted to authenticated
   * buyers and only returns cart items belonging to the current user based on
   * their JWT token. Buyers cannot access other users' carts. The operation
   * performs real-time validation of item availability and pricing, alerting
   * buyers to any changes since items were added.
   *
   * Business rules: Cart items may reference products that are no longer
   * available or have changed in price. The response indicates such
   * discrepancies so the buyer can make informed decisions. Quantity limits per
   * item may apply based on available inventory. Items in the cart do not
   * create inventory reservations until the buyer begins checkout.
   *
   * This operation integrates with the shopping_mall_cart_items table and
   * related product, SKU, and inventory tables from the Prisma schema. It
   * provides essential functionality for the shopping experience, allowing
   * buyers to review and manage their intended purchases before proceeding to
   * checkout.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering cart
   *   items
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @BuyerAuth()
    buyer: BuyerPayload,
    @TypedBody()
    body: IShoppingMallCartItem.IRequest,
  ): Promise<IPageIShoppingMallCartItem.ISummary> {
    try {
      return await patchShoppingMallBuyerBuyersMeCart({
        buyer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
