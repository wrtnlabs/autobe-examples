import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { patchShoppingMallBuyerBuyersMeWishlist } from "../../../../../../providers/patchShoppingMallBuyerBuyersMeWishlist";
import { BuyerAuth } from "../../../../../../decorators/BuyerAuth";
import { BuyerPayload } from "../../../../../../decorators/payload/BuyerPayload";

import { IPageIShoppingMallWishlistItem } from "../../../../../../api/structures/IPageIShoppingMallWishlistItem";
import { IShoppingMallWishlistItem } from "../../../../../../api/structures/IShoppingMallWishlistItem";

@Controller("/shoppingMall/buyer/buyers/me/wishlist")
export class ShoppingmallBuyerBuyersMeWishlistController {
  /**
   * Retrieve a filtered and paginated list of wishlist items belonging to the
   * currently authenticated buyer. This operation provides advanced search
   * capabilities for buyers to find items they have saved for future purchase
   * consideration based on multiple criteria including product name matching,
   * category filtering, price range, and date when items were added to the
   * wishlist.
   *
   * The operation supports comprehensive pagination with configurable page
   * sizes and sorting options. Buyers can sort by date added, product name,
   * price, or other relevant fields in ascending or descending order. This
   * allows buyers to organize their wishlist effectively and prioritize items
   * they want to purchase. Automatically filters out soft-deleted wishlist
   * items where deleted_at is not null.
   *
   * Security considerations include automatic filtering to show only the
   * authenticated buyer's own wishlist items based on the JWT token. Rate
   * limiting applies to prevent excessive API usage. The buyer_id is
   * automatically extracted from the authentication token and used to filter
   * results, ensuring data isolation between different buyers.
   *
   * This operation integrates with the shopping_mall_wishlist_items table as
   * defined in the Prisma schema, incorporating product information through
   * relationships to shopping_mall_sale_skus (with sale information accessed
   * via the sku.sale nested relation). The response includes wishlist item
   * summary information optimized for list displays, showing essential product
   * details, pricing, availability status, and when the item was added to the
   * wishlist.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering
   *   wishlist items including product name, category, price range, and date
   *   filters
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @BuyerAuth()
    buyer: BuyerPayload,
    @TypedBody()
    body: IShoppingMallWishlistItem.IRequest,
  ): Promise<IPageIShoppingMallWishlistItem.ISummary> {
    try {
      return await patchShoppingMallBuyerBuyersMeWishlist({
        buyer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
