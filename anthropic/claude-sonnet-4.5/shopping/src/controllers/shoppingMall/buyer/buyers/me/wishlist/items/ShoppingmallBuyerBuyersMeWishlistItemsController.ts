import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallBuyerBuyersMeWishlistItems } from "../../../../../../../providers/postShoppingMallBuyerBuyersMeWishlistItems";
import { BuyerAuth } from "../../../../../../../decorators/BuyerAuth";
import { BuyerPayload } from "../../../../../../../decorators/payload/BuyerPayload";
import { getShoppingMallBuyerBuyersMeWishlistItemsWishlistItemId } from "../../../../../../../providers/getShoppingMallBuyerBuyersMeWishlistItemsWishlistItemId";
import { deleteShoppingMallBuyerBuyersMeWishlistItemsWishlistItemId } from "../../../../../../../providers/deleteShoppingMallBuyerBuyersMeWishlistItemsWishlistItemId";
import { postShoppingMallBuyerBuyersMeWishlistItemsWishlistItemIdMoveToCart } from "../../../../../../../providers/postShoppingMallBuyerBuyersMeWishlistItemsWishlistItemIdMoveToCart";

import { IShoppingMallWishlistItem } from "../../../../../../../api/structures/IShoppingMallWishlistItem";
import { IShoppingMallCartItem } from "../../../../../../../api/structures/IShoppingMallCartItem";

@Controller("/shoppingMall/buyer/buyers/me/wishlist/items")
export class ShoppingmallBuyerBuyersMeWishlistItemsController {
  /**
   * Create a new wishlist item for the currently authenticated buyer by adding
   * a specific product SKU variant to their saved items list. This operation
   * allows buyers to bookmark products they are interested in but not ready to
   * purchase immediately, enabling them to track items for future consideration
   * and receive notifications about price changes or availability updates.
   *
   * The operation validates that the specified product SKU exists and is
   * currently available for wishlisting. It prevents duplicate entries via the
   * unique constraint on (shopping_mall_buyer_id, shopping_mall_sale_sku_id)
   * defined in the schema. If a duplicate is detected, the operation returns an
   * appropriate error. The buyer_id is automatically extracted from the JWT
   * authentication token to associate the wishlist item with the correct buyer
   * account.
   *
   * Security considerations include authentication enforcement to ensure only
   * logged-in buyers can add items to wishlists, and validation to prevent
   * buyers from adding items to other users' wishlists. The operation also
   * validates that the product sale and SKU referenced are active and not
   * deleted from the system.
   *
   * This operation integrates with the shopping_mall_wishlist_items table as
   * defined in the Prisma schema, creating relationships to
   * shopping_mall_buyers and shopping_mall_sale_skus tables (with sale
   * information accessible through the sku.sale nested relation). The response
   * returns the complete created wishlist item with populated product
   * information, allowing the buyer to immediately see confirmation of the
   * saved item with full details including product name, image, price, and
   * availability status.
   *
   * @param connection
   * @param body Product SKU information to be added to the wishlist including
   *   the sale SKU identifier
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @BuyerAuth()
    buyer: BuyerPayload,
    @TypedBody()
    body: IShoppingMallWishlistItem.ICreate,
  ): Promise<IShoppingMallWishlistItem> {
    try {
      return await postShoppingMallBuyerBuyersMeWishlistItems({
        buyer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific wishlist item from the
   * authenticated buyer's wishlist. This operation allows buyers to view
   * complete details about a product they have previously saved to their
   * wishlist.
   *
   * The operation fetches the wishlist item by its unique identifier and
   * returns comprehensive information including the associated product details,
   * pricing information, variant specifications (if applicable), and when the
   * item was added to the wishlist. This enables buyers to review saved
   * products before deciding to move them to their shopping cart or make a
   * purchase decision.
   *
   * Security considerations include strict ownership validation to ensure
   * buyers can only access their own wishlist items. The operation
   * automatically filters results based on the authenticated buyer's identity
   * extracted from the JWT token, preventing unauthorized access to other
   * buyers' wishlist data.
   *
   * This operation integrates with the shopping_mall_wishlist_items table as
   * defined in the Prisma schema. The response provides detailed wishlist item
   * information optimized for single-item display, including all necessary
   * product context to help buyers make informed purchase decisions. Related
   * operations include listing all wishlist items (PATCH
   * /buyers/me/wishlist/items) and removing items from the wishlist (DELETE
   * /buyers/me/wishlist/items/{wishlistItemId}).
   *
   * @param connection
   * @param wishlistItemId Unique identifier of the target wishlist item
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":wishlistItemId")
  public async at(
    @BuyerAuth()
    buyer: BuyerPayload,
    @TypedParam("wishlistItemId")
    wishlistItemId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallWishlistItem> {
    try {
      return await getShoppingMallBuyerBuyersMeWishlistItemsWishlistItemId({
        buyer,
        wishlistItemId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Remove a specific product from the authenticated buyer's wishlist by
   * permanently deleting the wishlist item record. This operation allows buyers
   * to clean up their wishlist by removing products they are no longer
   * interested in purchasing.
   *
   * The operation performs a permanent deletion of the wishlist item from the
   * database. Once deleted, the product will no longer appear in the buyer's
   * wishlist and the buyer will need to add it again if they change their mind.
   * This is a destructive operation that cannot be undone, so clients should
   * implement appropriate confirmation dialogs before calling this endpoint.
   *
   * Security considerations include strict ownership validation to ensure
   * buyers can only delete their own wishlist items. The operation
   * automatically validates that the wishlist item belongs to the authenticated
   * buyer based on their JWT token identity, preventing unauthorized deletion
   * of other buyers' wishlist data. Rate limiting may be applied to prevent
   * abuse.
   *
   * This operation integrates with the shopping_mall_wishlist_items table as
   * defined in the Prisma schema. The deletion is immediate and permanent.
   * Related operations include viewing wishlist item details (GET
   * /buyers/me/wishlist/items/{wishlistItemId}), listing all wishlist items
   * (PATCH /buyers/me/wishlist/items), and adding items to the wishlist (POST
   * /buyers/me/wishlist/items).
   *
   * @param connection
   * @param wishlistItemId Unique identifier of the target wishlist item to be
   *   removed
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":wishlistItemId")
  public async erase(
    @BuyerAuth()
    buyer: BuyerPayload,
    @TypedParam("wishlistItemId")
    wishlistItemId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallBuyerBuyersMeWishlistItemsWishlistItemId({
        buyer,
        wishlistItemId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Move a specific product from the authenticated buyer's wishlist to their
   * shopping cart for immediate purchase preparation.
   *
   * This operation transfers a wishlist item to the cart by removing it from
   * the wishlist and creating a corresponding cart entry with the buyer's
   * specified quantity. Since wishlist items represent passive interest without
   * quantities, the buyer must provide the desired purchase quantity during the
   * move operation. The operation validates the requested quantity against
   * current inventory availability to prevent overselling.
   *
   * The product's current price is captured as the unit_price_snapshot in the
   * newly created cart item, which may differ from the price_snapshot stored in
   * the original wishlist item if prices changed since the item was wishlisted.
   * This enables price change detection and buyer notification during cart
   * viewing.
   *
   * The wishlist item is soft-deleted (deleted_at timestamp set) rather than
   * hard-deleted, supporting potential undo functionality within the 10-second
   * recovery window. The cart item is created with the same SKU variant
   * (preserving selected color, size, and options) from the wishlist item.
   *
   * This operation requires buyer authentication and validates that the
   * wishlist item belongs to the authenticated buyer before performing the
   * move. Cart synchronization across devices occurs within 5 seconds for
   * authenticated buyers.
   *
   * @param connection
   * @param wishlistItemId Unique identifier of the wishlist item to move to
   *   cart
   * @param body Quantity specification for the cart item being created from the
   *   wishlist item
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post(":wishlistItemId/moveToCart")
  public async moveToCart(
    @BuyerAuth()
    buyer: BuyerPayload,
    @TypedParam("wishlistItemId")
    wishlistItemId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallWishlistItem.IMoveToCart,
  ): Promise<IShoppingMallCartItem> {
    try {
      return await postShoppingMallBuyerBuyersMeWishlistItemsWishlistItemIdMoveToCart(
        {
          buyer,
          wishlistItemId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
