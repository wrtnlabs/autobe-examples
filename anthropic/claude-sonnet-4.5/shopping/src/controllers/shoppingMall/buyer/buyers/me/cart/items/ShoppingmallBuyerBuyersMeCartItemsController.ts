import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallBuyerBuyersMeCartItems } from "../../../../../../../providers/postShoppingMallBuyerBuyersMeCartItems";
import { BuyerAuth } from "../../../../../../../decorators/BuyerAuth";
import { BuyerPayload } from "../../../../../../../decorators/payload/BuyerPayload";
import { getShoppingMallBuyerBuyersMeCartItemsCartItemId } from "../../../../../../../providers/getShoppingMallBuyerBuyersMeCartItemsCartItemId";
import { putShoppingMallBuyerBuyersMeCartItemsCartItemId } from "../../../../../../../providers/putShoppingMallBuyerBuyersMeCartItemsCartItemId";
import { deleteShoppingMallBuyerBuyersMeCartItemsCartItemId } from "../../../../../../../providers/deleteShoppingMallBuyerBuyersMeCartItemsCartItemId";

import { IShoppingMallCartItem } from "../../../../../../../api/structures/IShoppingMallCartItem";

@Controller("/shoppingMall/buyer/buyers/me/cart/items")
export class ShoppingmallBuyerBuyersMeCartItemsController {
  /**
   * Add a product SKU to the authenticated buyer's shopping cart.
   *
   * Add a new product item to the shopping cart for the currently authenticated
   * buyer. This operation enables buyers to select products they intend to
   * purchase by adding them to their cart with a specified quantity.
   *
   * The operation performs comprehensive validation before creating the cart
   * item. It verifies that the specified SKU exists and is currently available
   * for purchase, checks that sufficient inventory stock is available for the
   * requested quantity, and validates that the quantity meets any minimum or
   * maximum order constraints. If the same SKU already exists in the buyer's
   * cart, the system may either update the existing cart item quantity or
   * create a duplicate entry based on business rules.
   *
   * Security considerations include authentication requirement to ensure only
   * logged-in buyers can add items to their cart. The buyer identity is
   * automatically extracted from the JWT authentication token, ensuring cart
   * items are correctly associated with the authenticated user. Rate limiting
   * may be applied to prevent cart manipulation abuse.
   *
   * This operation integrates with the shopping_mall_cart_items table as
   * defined in the Prisma schema, creating records that link buyers to specific
   * product SKUs with their desired quantities. The cart persists across
   * sessions, allowing buyers to add items over time before proceeding to
   * checkout. Related operations include viewing cart contents, updating cart
   * item quantities, and removing items from the cart.
   *
   * @param connection
   * @param body Product SKU selection and quantity information for adding to
   *   cart
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @BuyerAuth()
    buyer: BuyerPayload,
    @TypedBody()
    body: IShoppingMallCartItem.ICreate,
  ): Promise<IShoppingMallCartItem> {
    try {
      return await postShoppingMallBuyerBuyersMeCartItems({
        buyer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific cart item.
   *
   * Retrieve complete details for a single cart item from the authenticated
   * buyer's shopping cart. This operation provides comprehensive information
   * about a specific product that the buyer has added to their cart, including
   * current pricing, availability status, and quantity.
   *
   * The operation returns detailed cart item information that includes the
   * associated product details, SKU variant information (such as color, size,
   * or other attributes), current unit price, requested quantity, and total
   * line item price. It also provides current stock availability information to
   * inform the buyer if inventory levels have changed since the item was added
   * to the cart.
   *
   * Security considerations include ownership validation to ensure buyers can
   * only access their own cart items. The operation verifies that the requested
   * cart item belongs to the authenticated buyer before returning any
   * information. The buyer identity is automatically extracted from the JWT
   * authentication token.
   *
   * This operation integrates with the shopping_mall_cart_items table as
   * defined in the Prisma schema, along with related product and SKU
   * information through database relationships. This enables buyers to review
   * individual cart items in detail before proceeding to checkout, verify
   * product specifications, and confirm quantities. Related operations include
   * listing all cart items, updating cart item quantities, and removing items
   * from the cart.
   *
   * @param connection
   * @param cartItemId Unique identifier of the target cart item
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":cartItemId")
  public async at(
    @BuyerAuth()
    buyer: BuyerPayload,
    @TypedParam("cartItemId")
    cartItemId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallCartItem> {
    try {
      return await getShoppingMallBuyerBuyersMeCartItemsCartItemId({
        buyer,
        cartItemId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update the quantity of a specific item in the buyer's shopping cart.
   *
   * Update the quantity of a specific product item in the authenticated buyer's
   * shopping cart. This operation allows buyers to increase or decrease the
   * quantity of items they intend to purchase without removing the item
   * entirely from their cart.
   *
   * The operation performs several validations before updating the cart item.
   * First, it verifies that the cart item exists and belongs to the
   * authenticated buyer to prevent unauthorized modifications. Second, it
   * validates that the requested quantity does not exceed available inventory
   * stock levels for the specific SKU. Third, it ensures the quantity is a
   * positive integer value.
   *
   * Security considerations include authentication requirement to ensure only
   * the cart owner can modify their items. The buyer's identity is
   * automatically extracted from the JWT authentication token, ensuring users
   * can only modify their own cart items. Rate limiting may apply to prevent
   * abuse.
   *
   * Inventory validation occurs in real-time to prevent overselling situations.
   * If the requested quantity exceeds available stock, the operation returns an
   * error with current stock availability information. The updated cart item is
   * returned with current pricing and availability details.
   *
   * Related operations include retrieving the full cart (PATCH
   * /buyers/me/cart/items), adding items to cart (POST /buyers/me/cart/items),
   * and removing items from cart (DELETE /buyers/me/cart/items/{cartItemId}).
   *
   * @param connection
   * @param cartItemId Unique identifier of the target cart item to update
   * @param body Updated quantity information for the cart item
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":cartItemId")
  public async update(
    @BuyerAuth()
    buyer: BuyerPayload,
    @TypedParam("cartItemId")
    cartItemId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallCartItem.IUpdate,
  ): Promise<IShoppingMallCartItem> {
    try {
      return await putShoppingMallBuyerBuyersMeCartItemsCartItemId({
        buyer,
        cartItemId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Remove a specific item from the buyer's shopping cart.
   *
   * Remove a specific product item from the authenticated buyer's shopping
   * cart. This operation allows buyers to delete items they no longer wish to
   * purchase without affecting other items in their cart.
   *
   * The operation verifies ownership before deletion to ensure security. The
   * buyer's identity is automatically extracted from the JWT authentication
   * token, and the system confirms that the cart item with the specified
   * cartItemId belongs to the authenticated buyer. If the cart item doesn't
   * exist or belongs to a different buyer, the operation returns an appropriate
   * error.
   *
   * Security considerations include authentication requirement and ownership
   * validation. Only the cart owner can delete their cart items, preventing
   * unauthorized modifications to other users' shopping carts. The operation is
   * idempotent - attempting to delete an already-deleted or non-existent cart
   * item returns a success response.
   *
   * When a cart item is removed, any associated inventory reservations are
   * released, making the stock available for other buyers. The operation
   * completes immediately and does not return the deleted cart item data.
   *
   * Related operations include updating cart item quantity (PUT
   * /buyers/me/cart/items/{cartItemId}), retrieving the full cart (PATCH
   * /buyers/me/cart/items), and adding items to cart (POST
   * /buyers/me/cart/items). Buyers may also move items to their wishlist before
   * deletion using the wishlist operations.
   *
   * @param connection
   * @param cartItemId Unique identifier of the target cart item to remove from
   *   the shopping cart
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":cartItemId")
  public async erase(
    @BuyerAuth()
    buyer: BuyerPayload,
    @TypedParam("cartItemId")
    cartItemId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallBuyerBuyersMeCartItemsCartItemId({
        buyer,
        cartItemId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
