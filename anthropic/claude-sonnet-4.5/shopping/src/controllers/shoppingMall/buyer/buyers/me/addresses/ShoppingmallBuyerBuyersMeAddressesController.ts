import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallBuyerBuyersMeAddresses } from "../../../../../../providers/postShoppingMallBuyerBuyersMeAddresses";
import { BuyerAuth } from "../../../../../../decorators/BuyerAuth";
import { BuyerPayload } from "../../../../../../decorators/payload/BuyerPayload";
import { patchShoppingMallBuyerBuyersMeAddresses } from "../../../../../../providers/patchShoppingMallBuyerBuyersMeAddresses";
import { getShoppingMallBuyerBuyersMeAddressesAddressId } from "../../../../../../providers/getShoppingMallBuyerBuyersMeAddressesAddressId";
import { putShoppingMallBuyerBuyersMeAddressesAddressId } from "../../../../../../providers/putShoppingMallBuyerBuyersMeAddressesAddressId";
import { deleteShoppingMallBuyerBuyersMeAddressesAddressId } from "../../../../../../providers/deleteShoppingMallBuyerBuyersMeAddressesAddressId";
import { postShoppingMallBuyerBuyersMeAddressesAddressIdSetDefault } from "../../../../../../providers/postShoppingMallBuyerBuyersMeAddressesAddressIdSetDefault";

import { IShoppingMallBuyerAddress } from "../../../../../../api/structures/IShoppingMallBuyerAddress";
import { IPageIShoppingMallBuyerAddress } from "../../../../../../api/structures/IPageIShoppingMallBuyerAddress";

@Controller("/shoppingMall/buyer/buyers/me/addresses")
export class ShoppingmallBuyerBuyersMeAddressesController {
  /**
   * Create a new delivery address for the authenticated buyer to use for order
   * shipping and delivery. This operation allows buyers to add multiple
   * shipping addresses to their account, which can be selected during the
   * checkout process for order fulfillment.
   *
   * The operation validates all address fields including recipient name, street
   * address, city, state, postal code, country, and contact phone number to
   * ensure complete and accurate delivery information. Address validation
   * ensures that orders can be successfully shipped to the specified location.
   *
   * Security considerations include JWT token validation to authenticate the
   * buyer and automatic association of the new address with the authenticated
   * buyer's account. The buyer_id field is automatically populated from the
   * authentication token, preventing buyers from creating addresses for other
   * users.
   *
   * This operation integrates with the shopping_mall_buyer_addresses table as
   * defined in the Prisma schema, creating a new address record with all
   * provided details. Buyers can create multiple addresses for different
   * delivery locations such as home, office, or alternative shipping
   * destinations. The created address becomes immediately available for
   * selection during checkout processes.
   *
   * Related operations: Buyers can retrieve their address list (PATCH
   * /buyers/me/addresses), view specific address details (GET
   * /buyers/me/addresses/{addressId}), update existing addresses (PUT
   * /buyers/me/addresses/{addressId}), and delete addresses (DELETE
   * /buyers/me/addresses/{addressId}).
   *
   * @param connection
   * @param body Complete delivery address information for the new address
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @BuyerAuth()
    buyer: BuyerPayload,
    @TypedBody()
    body: IShoppingMallBuyerAddress.ICreate,
  ): Promise<IShoppingMallBuyerAddress> {
    try {
      return await postShoppingMallBuyerBuyersMeAddresses({
        buyer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve authenticated buyer's delivery addresses with filtering
   * and pagination.
   *
   * Retrieve a filtered, paginated list of delivery addresses from the
   * authenticated buyer's address book.
   *
   * This operation provides comprehensive search and filtering capabilities for
   * buyers managing their saved delivery addresses. Buyers can filter by
   * address type (residential or commercial), search by address label, filter
   * for default addresses, or perform text search across recipient names and
   * location fields (street address, city, state, postal code).
   *
   * The response includes complete address information including recipient
   * details, full location data, delivery instructions, and metadata such as
   * creation and modification timestamps. Addresses are returned in reverse
   * chronological order by default (most recently created first) unless
   * alternative sorting is specified in the request.
   *
   * Each buyer can maintain up to 10 delivery addresses in their address book.
   * The operation only returns addresses owned by the authenticated buyer,
   * ensuring proper data isolation and privacy. Soft-deleted addresses (those
   * with deleted_at set) are excluded from results.
   *
   * This operation supports pagination to handle address lists efficiently,
   * though most buyers have fewer than 10 addresses making pagination less
   * critical than for product catalogs. The operation requires buyer
   * authentication to ensure address data security and proper ownership
   * validation.
   *
   * Address data returned by this operation can be used during checkout for
   * delivery address selection, in buyer account management interfaces for
   * address book maintenance, and for identifying the default shipping address
   * for streamlined purchasing.
   *
   * @param connection
   * @param body Search criteria, filtering options, sorting preferences, and
   *   pagination parameters for address retrieval
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @BuyerAuth()
    buyer: BuyerPayload,
    @TypedBody()
    body: IShoppingMallBuyerAddress.IRequest,
  ): Promise<IPageIShoppingMallBuyerAddress> {
    try {
      return await patchShoppingMallBuyerBuyersMeAddresses({
        buyer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific delivery address for the authenticated buyer.
   *
   * Retrieve detailed information about a specific delivery address belonging
   * to the authenticated buyer. This operation allows buyers to view the
   * complete details of one of their saved shipping addresses, which is
   * essential for reviewing address information before selecting it during
   * checkout or for address management purposes.
   *
   * The operation validates that the requested address belongs to the
   * authenticated buyer, ensuring proper data isolation and security. Only the
   * owner of the address can access its details through this endpoint.
   *
   * Security considerations include JWT token validation to authenticate the
   * buyer and ownership verification to prevent unauthorized access to other
   * buyers' addresses. The address ID must be a valid UUID format matching an
   * existing address record in the system.
   *
   * This operation integrates with the shopping_mall_buyer_addresses table as
   * defined in the Prisma schema, returning all relevant address fields
   * including recipient information, street address, city, state, postal code,
   * country, phone number, and any special delivery instructions. The response
   * provides complete address details for display and confirmation purposes.
   *
   * @param connection
   * @param addressId Unique identifier of the target buyer delivery address
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":addressId")
  public async at(
    @BuyerAuth()
    buyer: BuyerPayload,
    @TypedParam("addressId")
    addressId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallBuyerAddress> {
    try {
      return await getShoppingMallBuyerBuyersMeAddressesAddressId({
        buyer,
        addressId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update a specific delivery address in the authenticated buyer's address
   * book.
   *
   * Update an existing delivery address for the authenticated buyer. This
   * operation allows buyers to modify their saved shipping addresses by
   * providing updated address information including recipient details, contact
   * information, and complete postal address components.
   *
   * The buyer can update any address field including recipient name, phone
   * number, street address lines, city, state/province, postal code, and
   * country. The address record is identified by the addressId path parameter,
   * which must correspond to an address owned by the authenticated buyer.
   *
   * Security considerations: Only the authenticated buyer who owns the address
   * can update it. The buyer's identity is extracted from the JWT
   * authentication token. The system validates that the addressId belongs to
   * the authenticated buyer before allowing the update. Address validation may
   * be performed to ensure postal address components are valid and
   * deliverable.
   *
   * This operation is typically used when buyers need to correct address
   * information, update contact details, or modify shipping preferences for an
   * existing saved address. Updated addresses are immediately available for use
   * in the checkout process for future orders.
   *
   * @param connection
   * @param addressId Unique identifier of the target delivery address to update
   * @param body Updated address information including recipient details and
   *   complete postal address
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":addressId")
  public async update(
    @BuyerAuth()
    buyer: BuyerPayload,
    @TypedParam("addressId")
    addressId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallBuyerAddress.IUpdate,
  ): Promise<IShoppingMallBuyerAddress> {
    try {
      return await putShoppingMallBuyerBuyersMeAddressesAddressId({
        buyer,
        addressId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a specific delivery address from the authenticated buyer's address
   * book.
   *
   * Remove a delivery address from the authenticated buyer's saved address
   * book. This operation allows buyers to delete addresses they no longer need
   * or use for shipping purposes.
   *
   * The address to be deleted is identified by the addressId path parameter.
   * The system validates that the address belongs to the authenticated buyer
   * before allowing the deletion. Buyers can only delete their own addresses
   * and cannot delete addresses belonging to other users.
   *
   * Security considerations: Only the authenticated buyer who owns the address
   * can delete it. The buyer's identity is extracted from the JWT
   * authentication token. The system performs ownership verification to ensure
   * the addressId corresponds to an address owned by the requesting buyer.
   *
   * Business rules: The operation may prevent deletion of addresses that are
   * currently associated with pending or in-progress orders to maintain order
   * fulfillment integrity. If an address is set as the default shipping
   * address, the system may require the buyer to designate a different default
   * address before allowing deletion, or automatically clear the default flag
   * upon deletion.
   *
   * This operation is typically used when buyers want to remove outdated
   * addresses, clean up their address book, or remove addresses that are no
   * longer valid or needed for deliveries.
   *
   * @param connection
   * @param addressId Unique identifier of the target delivery address to delete
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":addressId")
  public async erase(
    @BuyerAuth()
    buyer: BuyerPayload,
    @TypedParam("addressId")
    addressId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallBuyerAddress> {
    try {
      return await deleteShoppingMallBuyerBuyersMeAddressesAddressId({
        buyer,
        addressId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Set a buyer's delivery address as their default address.
   *
   * Mark a specific delivery address as the default address for the
   * authenticated buyer. This operation updates the is_default flag for the
   * specified address and automatically unsets the default flag on all other
   * addresses belonging to the same buyer.
   *
   * The operation enforces the business rule that each buyer can have exactly
   * one default address at any given time. When a new default address is set,
   * the system automatically handles the transition by updating the previous
   * default address to non-default status in a single atomic transaction.
   *
   * Security: Only authenticated buyers can access this endpoint through the
   * "buyer" authorization actor. The operation validates that the specified
   * addressId belongs to the authenticated buyer to prevent unauthorized access
   * to other buyers' addresses. The buyer's identity is automatically extracted
   * from the JWT authentication token, ensuring users can only modify their own
   * address preferences.
   *
   * This operation integrates with the shopping_mall_buyer_addresses table as
   * defined in the Prisma schema. The default address is automatically used
   * during checkout processes to streamline order placement. Related operations
   * include creating new addresses (POST /buyers/me/addresses), updating
   * address details (PUT /buyers/me/addresses/{addressId}), and retrieving the
   * address list (PATCH /buyers/me/addresses).
   *
   * @param connection
   * @param addressId Unique identifier of the target delivery address to set as
   *   default
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post(":addressId/setDefault")
  public async setDefault(
    @BuyerAuth()
    buyer: BuyerPayload,
    @TypedParam("addressId")
    addressId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallBuyerAddress> {
    try {
      return await postShoppingMallBuyerBuyersMeAddressesAddressIdSetDefault({
        buyer,
        addressId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
