import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallBuyerReviewsReviewIdHelpfulnessVotes } from "../../../../../providers/postShoppingMallBuyerReviewsReviewIdHelpfulnessVotes";
import { BuyerAuth } from "../../../../../decorators/BuyerAuth";
import { BuyerPayload } from "../../../../../decorators/payload/BuyerPayload";
import { deleteShoppingMallBuyerReviewsReviewIdHelpfulnessVotesVoteId } from "../../../../../providers/deleteShoppingMallBuyerReviewsReviewIdHelpfulnessVotesVoteId";

import { IShoppingMallReviewHelpfulnessVote } from "../../../../../api/structures/IShoppingMallReviewHelpfulnessVote";

@Controller("/shoppingMall/buyer/reviews/:reviewId/helpfulnessVotes")
export class ShoppingmallBuyerReviewsHelpfulnessvotesController {
  /**
   * Create a new helpfulness vote record for a specific product review,
   * allowing authenticated buyers to indicate whether they found the review
   * useful. This operation enables the review helpfulness voting system that
   * helps other buyers identify the most valuable reviews.
   *
   * The operation enforces critical business rules including preventing
   * duplicate votes from the same buyer on the same review. Each buyer can only
   * vote once per review, and attempting to vote again will update their
   * existing vote rather than creating a duplicate. The voter's identity is
   * automatically extracted from the JWT authentication token to ensure vote
   * authenticity.
   *
   * Security considerations include requiring buyer authentication to prevent
   * vote manipulation, rate limiting to prevent automated voting attacks, and
   * validation that the target review exists and is published. The operation
   * may also implement cooldown periods between vote changes to prevent gaming
   * the system.
   *
   * This operation integrates with the shopping_mall_review_helpfulness_votes
   * table as defined in the Prisma schema, creating a permanent record of the
   * vote that contributes to the review's overall helpfulness score. The vote
   * immediately affects the review's helpfulness statistics displayed to other
   * buyers.
   *
   * @param connection
   * @param reviewId Unique identifier of the target review (global scope)
   * @param body Helpfulness vote submission data including vote type (helpful
   *   or not helpful)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @BuyerAuth()
    buyer: BuyerPayload,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallReviewHelpfulnessVote.ICreate,
  ): Promise<IShoppingMallReviewHelpfulnessVote> {
    try {
      return await postShoppingMallBuyerReviewsReviewIdHelpfulnessVotes({
        buyer,
        reviewId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Remove a buyer's helpfulness vote from a product review in the shopping
   * mall marketplace. This operation allows authenticated buyers to retract
   * their previously submitted vote indicating whether a specific review was
   * helpful to them.
   *
   * The operation performs a permanent deletion of the vote record from the
   * shopping_mall_review_helpfulness_votes table. Once removed, the vote no
   * longer contributes to the review's helpfulness statistics. Buyers can use
   * this operation to change their mind about a review's helpfulness, typically
   * following up by submitting a new vote with a different assessment.
   *
   * Security considerations include authentication verification to ensure only
   * the original voter can delete their own vote. The operation validates that
   * the voteId belongs to the authenticated buyer and is associated with the
   * specified reviewId. The review's helpfulness statistics are automatically
   * recalculated after vote removal to maintain accurate aggregate data.
   *
   * This operation integrates with the shopping_mall_review_helpfulness_votes
   * table as defined in the Prisma schema. The deletion cascades appropriately
   * to maintain referential integrity. Related operations include creating a
   * new helpfulness vote (POST /reviews/{reviewId}/helpfulnessVotes) and
   * retrieving vote statistics (GET /reviews/{reviewId}).
   *
   * @param connection
   * @param reviewId Unique identifier of the target review containing the
   *   helpfulness vote
   * @param voteId Unique identifier of the target helpfulness vote to be
   *   removed
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":voteId")
  public async erase(
    @BuyerAuth()
    buyer: BuyerPayload,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
    @TypedParam("voteId")
    voteId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallReviewHelpfulnessVote> {
    try {
      return await deleteShoppingMallBuyerReviewsReviewIdHelpfulnessVotesVoteId(
        {
          buyer,
          reviewId,
          voteId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
