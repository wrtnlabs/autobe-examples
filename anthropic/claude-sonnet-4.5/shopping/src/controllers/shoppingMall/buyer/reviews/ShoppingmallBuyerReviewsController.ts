import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallBuyerReviews } from "../../../../providers/postShoppingMallBuyerReviews";
import { BuyerAuth } from "../../../../decorators/BuyerAuth";
import { BuyerPayload } from "../../../../decorators/payload/BuyerPayload";
import { putShoppingMallBuyerReviewsReviewId } from "../../../../providers/putShoppingMallBuyerReviewsReviewId";
import { deleteShoppingMallBuyerReviewsReviewId } from "../../../../providers/deleteShoppingMallBuyerReviewsReviewId";

import { IShoppingMallReview } from "../../../../api/structures/IShoppingMallReview";

@Controller("/shoppingMall/buyer/reviews")
export class ShoppingmallBuyerReviewsController {
  /**
   * Create a new product review for an item that the authenticated buyer has
   * purchased and received. This operation allows buyers to share their
   * experience with a product by providing a star rating (1-5), review title,
   * detailed review content, and optional product images to support their
   * feedback.
   *
   * The review submission process enforces several critical business rules:
   * First, only buyers who have actually purchased and received the product can
   * submit reviews (verified purchase validation). Second, each buyer can
   * submit only one review per product purchase. Third, the order containing
   * the reviewed product must be in a delivered or completed status. Fourth,
   * review content must comply with platform content policies and will enter a
   * pending status for moderation.
   *
   * Security and validation: The buyer's identity is automatically extracted
   * from the JWT authentication token, ensuring review attribution accuracy.
   * The operation validates that the specified order item belongs to the
   * authenticated buyer and that the order has been successfully delivered.
   * Review content is screened for prohibited content, and all new reviews
   * enter a pending moderation status before public display. Buyers receive
   * notifications when their reviews are approved or rejected.
   *
   * The operation supports optional image uploads (up to a platform-defined
   * limit) to provide visual evidence supporting the review. Images are stored
   * in the shopping_mall_review_images table with references to the parent
   * review. Reviews become part of the product's overall rating calculation
   * once approved, influencing product discoverability and buyer decisions.
   *
   * Related operations: Retrieve review details (GET /reviews/{reviewId}),
   * Update review (PUT /reviews/{reviewId}), Seller response submission (POST
   * /reviews/{reviewId}/responses).
   *
   * @param connection
   * @param body Review submission data including rating, content, order
   *   reference, and optional images
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @BuyerAuth()
    buyer: BuyerPayload,
    @TypedBody()
    body: IShoppingMallReview.ICreate,
  ): Promise<IShoppingMallReview> {
    try {
      return await postShoppingMallBuyerReviews({
        buyer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing product review that was previously submitted by the
   * authenticated buyer. This operation allows buyers to modify their review
   * rating, title, content, and associated images after initial submission.
   *
   * The operation validates that the review exists and belongs to the
   * authenticated buyer making the request. Only the buyer who originally
   * created the review can update it. The review must be in a modifiable state
   * - reviews that have been flagged for moderation or removed cannot be
   * updated.
   *
   * Security considerations include ownership verification to ensure buyers can
   * only modify their own reviews. The operation validates review content
   * against platform guidelines including length requirements, prohibited
   * content, and image upload limits. All updates are timestamped and may be
   * subject to re-moderation if significant changes are made.
   *
   * This operation integrates with the shopping_mall_reviews table as defined
   * in the Prisma schema. The updated review immediately reflects in the
   * product's review listing with the modified rating contributing to updated
   * aggregate statistics. Related operations include creating reviews (POST
   * /sales/{saleId}/reviews) and deleting reviews (DELETE
   * /reviews/{reviewId}).
   *
   * @param connection
   * @param reviewId Unique identifier of the target review to update
   * @param body Updated review information including rating, title, content,
   *   and images
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":reviewId")
  public async update(
    @BuyerAuth()
    buyer: BuyerPayload,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallReview.IUpdate,
  ): Promise<IShoppingMallReview> {
    try {
      return await putShoppingMallBuyerReviewsReviewId({
        buyer,
        reviewId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete an existing product review from the shopping marketplace platform.
   * This operation permanently removes the review record from the database
   * including all associated review images and metadata.
   *
   * For buyers, this operation allows them to remove reviews they have
   * previously submitted on products they purchased. The buyer must be the
   * original author of the review to perform this deletion. For administrators,
   * this operation enables moderation capabilities to remove reviews that
   * violate platform policies, contain inappropriate content, or have been
   * reported by users.
   *
   * Security considerations include strict ownership verification for buyer
   * deletions and admin permission validation for moderation deletions. When a
   * review is deleted, the product's aggregate rating statistics are
   * automatically recalculated to reflect the removal. Associated review images
   * are also removed from storage as part of the deletion process.
   *
   * This operation integrates with the shopping_mall_reviews table as defined
   * in the Prisma schema. The deletion is permanent and cannot be undone.
   * Related operations include creating reviews (POST /sales/{saleId}/reviews)
   * and updating reviews (PUT /reviews/{reviewId}).
   *
   * @param connection
   * @param reviewId Unique identifier of the target review to delete
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":reviewId")
  public async erase(
    @BuyerAuth()
    buyer: BuyerPayload,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallReview> {
    try {
      return await deleteShoppingMallBuyerReviewsReviewId({
        buyer,
        reviewId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
