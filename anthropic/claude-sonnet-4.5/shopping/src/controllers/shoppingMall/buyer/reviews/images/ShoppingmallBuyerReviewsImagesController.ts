import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallBuyerReviewsReviewIdImages } from "../../../../../providers/postShoppingMallBuyerReviewsReviewIdImages";
import { BuyerAuth } from "../../../../../decorators/BuyerAuth";
import { BuyerPayload } from "../../../../../decorators/payload/BuyerPayload";
import { deleteShoppingMallBuyerReviewsReviewIdImagesImageId } from "../../../../../providers/deleteShoppingMallBuyerReviewsReviewIdImagesImageId";

import { IShoppingMallReviewImage } from "../../../../../api/structures/IShoppingMallReviewImage";

@Controller("/shoppingMall/buyer/reviews/:reviewId/images")
export class ShoppingmallBuyerReviewsImagesController {
  /**
   * Upload additional product images to supplement an existing review with
   * visual evidence. This operation allows verified buyers to add photographic
   * proof of their product experience after initially submitting their review.
   *
   * The operation validates that the review exists and belongs to the
   * authenticated buyer before allowing image uploads. Each review can contain
   * multiple images up to the platform's configured maximum limit. Images must
   * meet size and format requirements defined in the platform configuration.
   *
   * Security considerations include authentication verification to ensure only
   * the review author can add images, file type validation to prevent malicious
   * uploads, and storage quota enforcement per user and per review. The
   * uploaded images are processed for optimization and stored in the platform's
   * media storage system.
   *
   * This operation integrates with the shopping_mall_review_images table as
   * defined in the Prisma schema. The response includes the newly created image
   * record with its storage URL and metadata for immediate display in the
   * review interface.
   *
   * @param connection
   * @param reviewId Unique identifier of the target review to which images will
   *   be added
   * @param body Image upload data including the image file reference and
   *   optional metadata
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @BuyerAuth()
    buyer: BuyerPayload,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallReviewImage.ICreate,
  ): Promise<IShoppingMallReviewImage> {
    try {
      return await postShoppingMallBuyerReviewsReviewIdImages({
        buyer,
        reviewId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Remove a specific image from a product review. This operation allows
   * verified buyers to delete images they previously uploaded to their reviews,
   * useful for correcting mistakes or removing images that no longer represent
   * their experience accurately.
   *
   * The operation validates that both the review and the specific image exist,
   * that the review belongs to the authenticated buyer, and that the image is
   * associated with the specified review. This prevents unauthorized deletion
   * of images from other users' reviews.
   *
   * Security considerations include ownership verification to ensure only the
   * review author can delete images, and cascading cleanup of the actual image
   * file from the media storage system. The deletion is permanent and cannot be
   * undone.
   *
   * This operation integrates with the shopping_mall_review_images table as
   * defined in the Prisma schema. Upon successful deletion, the image is
   * removed from both the database and the storage system, and the review's
   * image count is updated accordingly.
   *
   * @param connection
   * @param reviewId Unique identifier of the review containing the image to be
   *   deleted
   * @param imageId Unique identifier of the specific image to be removed from
   *   the review
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":imageId")
  public async erase(
    @BuyerAuth()
    buyer: BuyerPayload,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
    @TypedParam("imageId")
    imageId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallReviewImage> {
    try {
      return await deleteShoppingMallBuyerReviewsReviewIdImagesImageId({
        buyer,
        reviewId,
        imageId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
