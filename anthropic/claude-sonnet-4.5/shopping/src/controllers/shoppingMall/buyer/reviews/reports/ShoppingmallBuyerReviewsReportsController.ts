import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallBuyerReviewsReviewIdReports } from "../../../../../providers/postShoppingMallBuyerReviewsReviewIdReports";
import { BuyerAuth } from "../../../../../decorators/BuyerAuth";
import { BuyerPayload } from "../../../../../decorators/payload/BuyerPayload";
import { getShoppingMallBuyerReviewsReviewIdReportsReportId } from "../../../../../providers/getShoppingMallBuyerReviewsReviewIdReportsReportId";

import { IShoppingMallReviewReport } from "../../../../../api/structures/IShoppingMallReviewReport";

@Controller("/shoppingMall/buyer/reviews/:reviewId/reports")
export class ShoppingmallBuyerReviewsReportsController {
  /**
   * Submit a report against a product review that violates platform policies
   * such as spam, offensive content, fake reviews, or other policy violations.
   * This operation allows authenticated buyers to flag problematic reviews for
   * moderator review.
   *
   * The reporting system helps maintain review quality and authenticity by
   * enabling the community to identify policy violations. Each report includes
   * a reason category (from predefined options like 'spam', 'offensive',
   * 'fake', 'irrelevant') and an optional detailed description explaining the
   * concern.
   *
   * Security: Only authenticated buyers can submit reports. The buyer_id is
   * automatically extracted from the JWT authentication token. Duplicate
   * reports from the same buyer for the same review may be prevented based on
   * business rules. Rate limiting applies to prevent abuse.
   *
   * The created report enters a pending moderation queue where admins can
   * review and take appropriate action. Related operations include viewing
   * report details (GET /reviews/{reviewId}/reports/{reportId}) and admin
   * moderation workflows.
   *
   * @param connection
   * @param reviewId Unique identifier of the target review being reported
   * @param body Report information including reason category and optional
   *   detailed description
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @BuyerAuth()
    buyer: BuyerPayload,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallReviewReport.ICreate,
  ): Promise<IShoppingMallReviewReport> {
    try {
      return await postShoppingMallBuyerReviewsReviewIdReports({
        buyer,
        reviewId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Fetch complete details of a review report submission including the report
   * reason, description, reporter information, submission timestamp, and
   * current moderation status. This operation provides transparency into the
   * review reporting and moderation process.
   *
   * The response includes comprehensive report information such as the reason
   * category (spam, offensive, fake, irrelevant, etc.), the optional detailed
   * description provided by the reporter, the buyer who submitted the report,
   * when the report was created, and any moderation actions taken.
   *
   * Security: Access control depends on the requesting user. Admins can view
   * all reports for moderation purposes. Buyers may only view their own
   * submitted reports. The operation validates that the report belongs to the
   * specified review and enforces appropriate authorization rules.
   *
   * This operation is commonly used in admin moderation dashboards to review
   * flagged content and make decisions about review visibility or user actions.
   * It may also be used by buyers to check the status of reports they
   * submitted.
   *
   * @param connection
   * @param reviewId Unique identifier of the review associated with this report
   * @param reportId Unique identifier of the target report
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":reportId")
  public async at(
    @BuyerAuth()
    buyer: BuyerPayload,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
    @TypedParam("reportId")
    reportId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallReviewReport> {
    try {
      return await getShoppingMallBuyerReviewsReviewIdReportsReportId({
        buyer,
        reviewId,
        reportId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
