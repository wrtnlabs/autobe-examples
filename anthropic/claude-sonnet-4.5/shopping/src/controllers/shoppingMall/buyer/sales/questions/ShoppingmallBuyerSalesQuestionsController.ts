import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallBuyerSalesSaleCodeQuestions } from "../../../../../providers/postShoppingMallBuyerSalesSaleCodeQuestions";
import { BuyerAuth } from "../../../../../decorators/BuyerAuth";
import { BuyerPayload } from "../../../../../decorators/payload/BuyerPayload";
import { postShoppingMallBuyerSalesShoppingMallSaleCodeQuestions } from "../../../../../providers/postShoppingMallBuyerSalesShoppingMallSaleCodeQuestions";
import { deleteShoppingMallBuyerSalesSaleCodeQuestionsQuestionId } from "../../../../../providers/deleteShoppingMallBuyerSalesSaleCodeQuestionsQuestionId";

import { IShoppingMallSaleQuestion } from "../../../../../api/structures/IShoppingMallSaleQuestion";

@Controller("/shoppingMall/buyer/sales")
export class ShoppingmallBuyerSalesQuestionsController {
  /**
   * Create a new customer question (inquiry) for a specific product sale in the
   * shopping marketplace. This operation enables authenticated buyers to ask
   * sellers questions about products they are considering purchasing,
   * facilitating informed buying decisions through direct communication.
   *
   * The operation automatically associates the question with the authenticated
   * buyer (extracted from JWT token) and the specified product sale. Questions
   * are submitted for seller review and response, creating a transparent Q&A
   * system that benefits all potential buyers researching the same product.
   *
   * Security considerations include authentication requirements to prevent spam
   * and associate questions with verified buyer accounts. The buyer_id field is
   * automatically populated from the authentication token, preventing buyers
   * from submitting questions on behalf of others. Rate limiting may be applied
   * to prevent question spam.
   *
   * The operation integrates with the shopping_mall_sale_questions table as
   * defined in the Prisma schema. Upon successful creation, the question
   * becomes visible to the seller for answering and may be published for other
   * buyers to view, depending on moderation settings. This supports the buyer
   * research workflow and improves marketplace transparency.
   *
   * Related operations include retrieving questions (PATCH
   * /sales/{saleCode}/questions) to view existing Q&A before submitting, and
   * sellers responding to questions through their dedicated answer management
   * endpoints.
   *
   * @param connection
   * @param saleCode Unique business identifier code of the target product sale
   *   (global scope)
   * @param body Question content and details submitted by the buyer about the
   *   product sale
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post(":saleCode/questions")
  public async postBySalecode(
    @BuyerAuth()
    buyer: BuyerPayload,
    @TypedParam("saleCode")
    saleCode: string,
    @TypedBody()
    body: IShoppingMallSaleQuestion.ICreate,
  ): Promise<IShoppingMallSaleQuestion> {
    try {
      return await postShoppingMallBuyerSalesSaleCodeQuestions({
        buyer,
        saleCode,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Create a new customer question (inquiry) for a specific product sale in the
   * shopping marketplace. This operation enables authenticated buyers to ask
   * sellers questions about products they are considering purchasing,
   * facilitating informed buying decisions through direct communication.
   *
   * The operation automatically associates the question with the authenticated
   * buyer (extracted from JWT token) and the specified product sale. Questions
   * are submitted for seller review and response, creating a transparent Q&A
   * system that benefits all potential buyers researching the same product.
   *
   * Security considerations include authentication requirements to prevent spam
   * and associate questions with verified buyer accounts. The buyer_id field is
   * automatically populated from the authentication token, preventing buyers
   * from submitting questions on behalf of others. Rate limiting may be applied
   * to prevent question spam.
   *
   * The operation integrates with the shopping_mall_sale_questions table as
   * defined in the Prisma schema. Upon successful creation, the question
   * becomes visible to the seller for answering and may be published for other
   * buyers to view, depending on moderation settings. This supports the buyer
   * research workflow and improves marketplace transparency.
   *
   * Related operations include retrieving questions (PATCH
   * /sales/{shoppingMallSaleCode}/questions) to view existing Q&A before
   * submitting, and sellers responding to questions through their dedicated
   * answer management endpoints.
   *
   * @param connection
   * @param shoppingMallSaleCode Unique business identifier code of the target
   *   product sale (global scope)
   * @param body Question content and details submitted by the buyer about the
   *   product sale
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post(":shoppingMallSaleCode/questions")
  public async postByShoppingmallsalecode(
    @BuyerAuth()
    buyer: BuyerPayload,
    @TypedParam("shoppingMallSaleCode")
    shoppingMallSaleCode: string,
    @TypedBody()
    body: IShoppingMallSaleQuestion.ICreate,
  ): Promise<IShoppingMallSaleQuestion> {
    try {
      return await postShoppingMallBuyerSalesShoppingMallSaleCodeQuestions({
        buyer,
        shoppingMallSaleCode,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently remove a customer question from a specific product sale listing
   * in the shopping marketplace.
   *
   * This operation allows authorized users to delete questions that have been
   * posted about a product. The deletion is permanent and removes the question
   * record from the database along with any associated answers if they exist.
   *
   * Security considerations include authorization checks to ensure only the
   * question author or administrators can delete questions. The operation
   * validates that the question belongs to the specified sale before deletion.
   * Rate limiting may apply to prevent abuse of the deletion functionality.
   *
   * This operation integrates with the shopping_mall_sale_questions table as
   * defined in the Prisma schema. Upon successful deletion, the question and
   * any related answers are removed from the system. The sale itself remains
   * unaffected by this operation.
   *
   * @param connection
   * @param saleCode Unique business identifier code of the target product sale
   *   (global scope)
   * @param questionId Unique identifier of the target question to be deleted
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":saleCode/questions/:questionId")
  public async erase(
    @BuyerAuth()
    buyer: BuyerPayload,
    @TypedParam("saleCode")
    saleCode: string,
    @TypedParam("questionId")
    questionId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallSaleQuestion> {
    try {
      return await deleteShoppingMallBuyerSalesSaleCodeQuestionsQuestionId({
        buyer,
        saleCode,
        questionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
