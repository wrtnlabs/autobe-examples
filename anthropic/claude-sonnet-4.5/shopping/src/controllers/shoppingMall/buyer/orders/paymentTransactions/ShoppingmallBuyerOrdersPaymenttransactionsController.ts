import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallBuyerOrdersOrderIdPaymentTransactions } from "../../../../../providers/postShoppingMallBuyerOrdersOrderIdPaymentTransactions";
import { BuyerAuth } from "../../../../../decorators/BuyerAuth";
import { BuyerPayload } from "../../../../../decorators/payload/BuyerPayload";
import { patchShoppingMallBuyerOrdersOrderIdPaymentTransactions } from "../../../../../providers/patchShoppingMallBuyerOrdersOrderIdPaymentTransactions";

import { IShoppingMallPaymentTransaction } from "../../../../../api/structures/IShoppingMallPaymentTransaction";
import { IPageIShoppingMallPaymentTransaction } from "../../../../../api/structures/IPageIShoppingMallPaymentTransaction";

@Controller("/shoppingMall/buyer/orders/:orderId/paymentTransactions")
export class ShoppingmallBuyerOrdersPaymenttransactionsController {
  /**
   * Create a new payment transaction for an order.
   *
   * Create a new payment transaction record for a specific order in the
   * shopping mall system. This operation is invoked during the order checkout
   * process when a buyer selects a payment method and confirms their purchase.
   * The operation creates a payment transaction record, initiates communication
   * with the payment gateway, and returns transaction details including the
   * payment status and any required redirect URLs for completing the payment.
   *
   * The operation validates that the order exists and is in a valid state for
   * payment processing (typically in 'pending_payment' status). It verifies
   * that the selected payment method is valid and active for the buyer. The
   * system then creates a payment transaction record with an initial status of
   * 'pending' or 'processing' and communicates with the appropriate payment
   * gateway (credit card processor, digital wallet provider, or bank transfer
   * system) to initiate the payment.
   *
   * Security considerations include ensuring that only the order owner (buyer)
   * can create payment transactions for their orders. The operation validates
   * that the payment amount matches the order total to prevent manipulation.
   * All sensitive payment information is handled according to PCI DSS
   * standards, with card details tokenized and transmitted securely to payment
   * gateways. The operation logs all payment attempts for fraud detection and
   * audit purposes.
   *
   * Upon successful creation, the operation returns the payment transaction
   * details including transaction ID, status, payment method information
   * (masked), and any additional data required by the buyer to complete payment
   * (such as redirect URLs for 3D Secure authentication or bank transfer
   * instructions). The response integrates with the
   * shopping_mall_payment_transactions table and related entities including
   * shopping_mall_orders, shopping_mall_payment_methods, and
   * shopping_mall_buyers as defined in the Prisma schema.
   *
   * @param connection
   * @param orderId Unique identifier of the target order (global scope)
   * @param body Payment transaction creation data including payment method
   *   selection and amount verification
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @BuyerAuth()
    buyer: BuyerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallPaymentTransaction.ICreate,
  ): Promise<IShoppingMallPaymentTransaction> {
    try {
      return await postShoppingMallBuyerOrdersOrderIdPaymentTransactions({
        buyer,
        orderId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve filtered payment transactions for a specific order.
   *
   * Retrieve a filtered and paginated list of payment transactions associated
   * with a specific order in the shopping mall system. This operation provides
   * advanced search capabilities for finding payment transactions based on
   * multiple criteria including transaction status, payment method type,
   * transaction date ranges, amount ranges, and payment gateway responses.
   *
   * The operation supports comprehensive pagination with configurable page
   * sizes and sorting options. Users can sort payment transactions by
   * transaction date, amount, status, or other relevant fields in ascending or
   * descending order. This is particularly useful for buyers reviewing their
   * payment history, sellers tracking received payments, and administrators
   * monitoring payment system health.
   *
   * Security considerations include ensuring that only authorized actors can
   * access payment transaction details. Buyers can only view transactions for
   * their own orders, sellers can view transactions related to their order
   * portions, and administrators have full access for dispute resolution and
   * financial auditing. Sensitive payment information such as full card numbers
   * or bank account details are masked in the response, showing only the last 4
   * digits or partial information as required by PCI compliance standards.
   *
   * This operation integrates with the shopping_mall_payment_transactions table
   * as defined in the Prisma schema, along with related entities such as
   * shopping_mall_orders, shopping_mall_payment_methods, and
   * shopping_mall_buyers. The response includes payment transaction summary
   * information optimized for list displays, with support for including
   * additional transaction details based on authorization level and business
   * requirements.
   *
   * @param connection
   * @param orderId Unique identifier of the target order (global scope)
   * @param body Search criteria and pagination parameters for filtering payment
   *   transactions within the specified order
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @BuyerAuth()
    buyer: BuyerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallPaymentTransaction.IRequest,
  ): Promise<IPageIShoppingMallPaymentTransaction.ISummary> {
    try {
      return await patchShoppingMallBuyerOrdersOrderIdPaymentTransactions({
        buyer,
        orderId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
