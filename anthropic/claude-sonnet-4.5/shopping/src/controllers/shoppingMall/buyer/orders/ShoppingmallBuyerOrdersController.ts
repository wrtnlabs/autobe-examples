import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallBuyerOrders } from "../../../../providers/postShoppingMallBuyerOrders";
import { BuyerAuth } from "../../../../decorators/BuyerAuth";
import { BuyerPayload } from "../../../../decorators/payload/BuyerPayload";
import { patchShoppingMallBuyerOrders } from "../../../../providers/patchShoppingMallBuyerOrders";
import { getShoppingMallBuyerOrdersOrderId } from "../../../../providers/getShoppingMallBuyerOrdersOrderId";
import { putShoppingMallBuyerOrdersOrderId } from "../../../../providers/putShoppingMallBuyerOrdersOrderId";
import { deleteShoppingMallBuyerOrdersOrderId } from "../../../../providers/deleteShoppingMallBuyerOrdersOrderId";

import { IShoppingMallOrder } from "../../../../api/structures/IShoppingMallOrder";
import { IPageIShoppingMallOrder } from "../../../../api/structures/IPageIShoppingMallOrder";

@Controller("/shoppingMall/buyer/orders")
export class ShoppingmallBuyerOrdersController {
  /**
   * Create a new order by processing selected items from the authenticated
   * buyer's shopping cart, validating inventory availability, calculating
   * totals, processing payment, and reserving inventory for fulfillment. This
   * operation executes the complete checkout workflow that transforms cart
   * items into a confirmed purchase order.
   *
   * The operation validates that all cart items are available and in stock,
   * calculates order totals including product prices, quantities, taxes,
   * shipping costs, and platform fees. It processes payment through the
   * specified payment method, creates inventory reservations to prevent
   * overselling, and splits the order into seller-specific portions when items
   * come from multiple sellers. Each seller receives their portion of the order
   * for independent fulfillment.
   *
   * Security considerations include authentication to identify the buyer,
   * validation of payment method ownership, verification of shipping address
   * ownership, and prevention of race conditions during inventory reservation.
   * The operation enforces business rules such as minimum order amounts,
   * seller-specific shipping policies, and payment processing requirements.
   *
   * This operation integrates with multiple Prisma schema tables including
   * shopping_mall_orders (parent order), shopping_mall_order_sellers
   * (seller-specific portions), shopping_mall_order_items (line items),
   * shopping_mall_inventory_reservations (stock holds),
   * shopping_mall_payment_transactions (payment records), and
   * shopping_mall_cart_items (source items that are cleared after successful
   * order creation). The response includes the complete created order with all
   * nested relationships, payment confirmation, and order tracking
   * information.
   *
   * Related operations: Buyers must first add items to cart (POST /cart-items),
   * manage shipping addresses (POST /buyer-addresses), and configure payment
   * methods (POST /payment-methods) before creating orders. After order
   * creation, buyers track orders (GET /orders/{orderId}) and sellers fulfill
   * orders (PUT /order-sellers/{orderSellerId}).
   *
   * @param connection
   * @param body Order creation details including cart item selection, shipping
   *   address, payment method, and delivery preferences
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @BuyerAuth()
    buyer: BuyerPayload,
    @TypedBody()
    body: IShoppingMallOrder.ICreate,
  ): Promise<IShoppingMallOrder> {
    try {
      return await postShoppingMallBuyerOrders({
        buyer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a comprehensive, filtered, and paginated list of orders from the
   * marketplace. This operation provides advanced search capabilities for
   * finding orders based on multiple criteria including order number, status,
   * creation date ranges, buyer information, seller information, payment
   * status, shipping status, and order total amounts.
   *
   * The operation supports role-based data filtering to ensure users only see
   * orders they are authorized to access. Buyers see only their own orders,
   * sellers see orders containing items they are selling, and administrators
   * have access to all orders across the platform. The filtering logic is
   * automatically applied based on the authenticated user's actor type
   * extracted from the JWT token.
   *
   * Comprehensive pagination is supported with configurable page sizes and
   * sorting options. Orders can be sorted by creation date, order total,
   * status, or other relevant fields in ascending or descending order. The
   * response includes order summary information optimized for list displays,
   * with options to include related data such as order items, seller
   * information, and shipping details based on the actor's authorization
   * level.
   *
   * Security considerations include rate limiting for search operations to
   * prevent abuse, and appropriate filtering of sensitive order information
   * based on the requesting user's authorization level. Personal information
   * and payment details are masked or excluded for users without proper
   * permissions.
   *
   * This operation integrates with the shopping_mall_orders table as defined in
   * the Prisma schema, along with related tables including
   * shopping_mall_order_sellers, shopping_mall_order_items, and
   * shopping_mall_order_status_histories. The response provides comprehensive
   * order information necessary for order management, fulfillment tracking, and
   * customer service operations. Related operations include retrieving order
   * details (GET /orders/{orderId}), creating new orders (POST /orders), and
   * updating order status (PUT /orders/{orderId}/status).
   *
   * @param connection
   * @param body Search criteria and pagination parameters for order filtering,
   *   including status filters, date ranges, buyer/seller filters, payment
   *   status, and sorting options
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @BuyerAuth()
    buyer: BuyerPayload,
    @TypedBody()
    body: IShoppingMallOrder.IRequest,
  ): Promise<IPageIShoppingMallOrder.ISummary> {
    try {
      return await patchShoppingMallBuyerOrders({
        buyer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve comprehensive details of a specific order identified by its unique
   * order ID. This operation provides complete order information including
   * buyer information, current order status, payment details, shipping address,
   * timestamps, and all line items within the order.
   *
   * The operation returns the full order entity with nested relationships to
   * order items, seller-specific order portions, payment transactions, and
   * shipping information. Buyers can access their own orders to track purchase
   * status and review order details. Sellers can access orders containing their
   * products to fulfill and ship items. Administrators can access any order for
   * customer support, dispute resolution, and platform oversight.
   *
   * Security considerations include authorization checks to ensure buyers can
   * only access their own orders, sellers can only access orders containing
   * their products, and administrators have unrestricted access. The operation
   * validates the order ID format and returns appropriate error responses for
   * non-existent or inaccessible orders.
   *
   * This operation integrates with the shopping_mall_orders table as defined in
   * the Prisma schema, including all order fields, relationships to buyers,
   * addresses, order items, and order status history. The response provides
   * detailed order information optimized for order tracking, fulfillment
   * workflows, and customer service operations.
   *
   * @param connection
   * @param orderId Unique identifier of the target order
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":orderId")
  public async at(
    @BuyerAuth()
    buyer: BuyerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallOrder> {
    try {
      return await getShoppingMallBuyerOrdersOrderId({
        buyer,
        orderId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing order in the shopping mall platform with modified
   * information. This operation allows buyers to update certain aspects of
   * their orders, typically before the order has been processed or shipped by
   * sellers.
   *
   * The operation supports updating mutable order properties such as delivery
   * address changes, special delivery instructions, or contact information
   * updates. Not all order fields are editable - certain fields like order
   * totals, purchased items, and payment information are immutable once the
   * order is placed.
   *
   * Security considerations include ownership verification to ensure only the
   * order owner can modify the order, and business rule validation to prevent
   * updates to orders that are already in shipping or delivered status. The
   * operation validates that the order exists, belongs to the authenticated
   * buyer, and is in a state that allows modifications.
   *
   * This operation integrates with the shopping_mall_orders table as defined in
   * the Prisma schema. The response returns the complete updated order object
   * reflecting all changes. Related operations include retrieving order details
   * (GET /orders/{orderId}) and canceling orders (DELETE /orders/{orderId}).
   *
   * @param connection
   * @param orderId Unique identifier of the target order
   * @param body Updated order information with fields that can be modified
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":orderId")
  public async update(
    @BuyerAuth()
    buyer: BuyerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallOrder.IUpdate,
  ): Promise<IShoppingMallOrder> {
    try {
      return await putShoppingMallBuyerOrdersOrderId({
        buyer,
        orderId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Mark an order record as deleted in the shopping mall platform by setting
   * the deleted_at timestamp. This operation uses soft deletion to preserve the
   * order record for historical, legal, and compliance purposes while hiding it
   * from active buyer views.
   *
   * The deletion operation is restricted to specific order states and user
   * roles. Typically, only orders that have not been confirmed or paid can be
   * deleted by buyers. Orders that are in processing, shipped, or delivered
   * states generally cannot be deleted and should use the cancellation workflow
   * instead through the dedicated cancellation operations.
   *
   * Security validation ensures that only authorized users can delete orders
   *
   * - Buyers can only delete their own orders in eligible states. The operation
   *   validates order ownership, current status eligibility, and performs the
   *   soft deletion by setting the deleted_at field in the shopping_mall_orders
   *   table.
   *
   * This operation integrates with the shopping_mall_orders table as defined in
   * the Prisma schema. The soft deletion preserves all order data including
   * items, status history, and payment information for audit trails. Deleted
   * orders are filtered from normal queries but remain accessible for
   * administrative review and compliance reporting. For orders that need to be
   * reversed after processing, use the cancellation or refund request workflows
   * instead. Related operations include order cancellation (POST
   * /orders/{orderId}/cancel) and refund requests (POST
   * /orders/{orderId}/refund-requests).
   *
   * @param connection
   * @param orderId Unique identifier of the target order
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":orderId")
  public async erase(
    @BuyerAuth()
    buyer: BuyerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallOrder> {
    try {
      return await deleteShoppingMallBuyerOrdersOrderId({
        buyer,
        orderId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
