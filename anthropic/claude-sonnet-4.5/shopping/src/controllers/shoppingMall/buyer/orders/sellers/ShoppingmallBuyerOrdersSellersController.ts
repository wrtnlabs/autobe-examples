import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallBuyerOrdersOrderIdSellers } from "../../../../../providers/patchShoppingMallBuyerOrdersOrderIdSellers";
import { BuyerAuth } from "../../../../../decorators/BuyerAuth";
import { BuyerPayload } from "../../../../../decorators/payload/BuyerPayload";
import { getShoppingMallBuyerOrdersOrderIdSellersSellerId } from "../../../../../providers/getShoppingMallBuyerOrdersOrderIdSellersSellerId";

import { IPageIShoppingMallOrderSeller } from "../../../../../api/structures/IPageIShoppingMallOrderSeller";
import { IShoppingMallOrderSeller } from "../../../../../api/structures/IShoppingMallOrderSeller";

@Controller("/shoppingMall/buyer/orders/:orderId/sellers")
export class ShoppingmallBuyerOrdersSellersController {
  /**
   * Search and retrieve seller segments within a specific order.
   *
   * Retrieve a filtered and paginated list of seller-specific order segments
   * for a given parent order. This operation provides comprehensive search
   * capabilities for analyzing how a multi-seller order is distributed across
   * different sellers, with each seller managing their portion of the order
   * independently.
   *
   * The operation supports advanced filtering by seller information, order item
   * details, fulfillment status, shipping tracking, payment status, and
   * commission calculations. Users can search for seller segments based on
   * various criteria including seller identity, item quantities, subtotal
   * amounts, shipping costs, order status, and payout status.
   *
   * Security considerations include proper authorization to ensure only
   * authorized users (buyers viewing their own orders, sellers viewing their
   * segments, or admins) can access order seller information. The response
   * includes comprehensive seller segment data including all items assigned to
   * each seller, shipping details, financial breakdowns, and current
   * fulfillment status.
   *
   * This operation integrates with the shopping_mall_order_sellers table as
   * defined in the Prisma schema, along with related order items, seller
   * information, and shipping data. The response provides seller segment
   * summary information optimized for order management displays, with support
   * for pagination and sorting by various fields including creation date,
   * status, and financial amounts.
   *
   * @param connection
   * @param orderId Unique identifier of the target parent order (global scope)
   * @param body Search criteria and pagination parameters for filtering seller
   *   segments within the order
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @BuyerAuth()
    buyer: BuyerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallOrderSeller.IRequest,
  ): Promise<IPageIShoppingMallOrderSeller.ISummary> {
    try {
      return await patchShoppingMallBuyerOrdersOrderIdSellers({
        buyer,
        orderId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific seller segment within an
   * order.
   *
   * Retrieve complete detailed information about a specific seller's segment
   * within a multi-seller order. This operation provides comprehensive
   * visibility into how a particular seller is handling their portion of the
   * order, including all assigned items, shipping details, financial breakdown,
   * and fulfillment status.
   *
   * The response includes complete seller segment information such as all order
   * items assigned to this seller, calculated subtotals, shipping costs,
   * commission amounts, payment status, shipping tracking information, and
   * current order status for this seller's segment. This enables buyers to
   * track each seller's fulfillment progress independently and sellers to view
   * their specific responsibilities.
   *
   * Security considerations include authorization validation to ensure only the
   * order's buyer, the specific seller managing this segment, or platform
   * administrators can access this detailed information. The operation
   * validates that the seller segment actually belongs to the specified parent
   * order to prevent unauthorized cross-order access.
   *
   * This operation integrates with the shopping_mall_order_sellers table and
   * related entities including shopping_mall_order_items,
   * shopping_mall_sellers, and shipping information. The response provides the
   * complete seller segment entity with all related data fully populated for
   * comprehensive order segment viewing.
   *
   * @param connection
   * @param orderId Unique identifier of the target parent order (global scope)
   * @param sellerId Unique identifier of the target seller segment within the
   *   order
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sellerId")
  public async at(
    @BuyerAuth()
    buyer: BuyerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallOrderSeller> {
    try {
      return await getShoppingMallBuyerOrdersOrderIdSellersSellerId({
        buyer,
        orderId,
        sellerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
