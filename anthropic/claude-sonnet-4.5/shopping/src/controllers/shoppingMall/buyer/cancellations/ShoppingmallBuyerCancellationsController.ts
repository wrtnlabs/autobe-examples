import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postShoppingMallBuyerCancellations } from "../../../../providers/postShoppingMallBuyerCancellations";
import { BuyerAuth } from "../../../../decorators/BuyerAuth";
import { BuyerPayload } from "../../../../decorators/payload/BuyerPayload";

import { IShoppingMallOrderCancellation } from "../../../../api/structures/IShoppingMallOrderCancellation";

@Controller("/shoppingMall/buyer/cancellations")
export class ShoppingmallBuyerCancellationsController {
  /**
   * Create a new order cancellation request for an order that a buyer wants to
   * cancel. This operation allows authenticated buyers to submit cancellation
   * requests for their orders that are in eligible states for cancellation.
   *
   * The cancellation request requires the buyer to provide the order ID they
   * wish to cancel and a reason for the cancellation. The system validates that
   * the order exists, belongs to the authenticated buyer, and is in a state
   * that allows cancellation (typically orders that haven't been shipped yet).
   * Once created, the cancellation request enters a pending state awaiting
   * admin review and approval.
   *
   * Security considerations include verifying order ownership to prevent buyers
   * from cancelling others' orders. The buyer's identity is automatically
   * extracted from the JWT authentication token. The operation creates an audit
   * trail by recording the cancellation request with timestamp and reason.
   *
   * This operation integrates with the shopping_mall_order_cancellations table
   * as defined in the Prisma schema. Upon successful creation, the cancellation
   * request is stored with status 'pending' and can be reviewed by
   * administrators through the admin approval workflow. Related operations
   * include updating cancellation status (PUT /cancellations/{cancellationId})
   * and viewing cancellation details.
   *
   * @param connection
   * @param body Order cancellation request details including order ID and
   *   cancellation reason
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @BuyerAuth()
    buyer: BuyerPayload,
    @TypedBody()
    body: IShoppingMallOrderCancellation.ICreate,
  ): Promise<IShoppingMallOrderCancellation> {
    try {
      return await postShoppingMallBuyerCancellations({
        buyer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
