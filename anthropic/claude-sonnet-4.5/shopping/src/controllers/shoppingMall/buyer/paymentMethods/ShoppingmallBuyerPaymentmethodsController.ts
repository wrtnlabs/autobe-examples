import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallBuyerPaymentMethods } from "../../../../providers/postShoppingMallBuyerPaymentMethods";
import { BuyerAuth } from "../../../../decorators/BuyerAuth";
import { BuyerPayload } from "../../../../decorators/payload/BuyerPayload";
import { patchShoppingMallBuyerPaymentMethods } from "../../../../providers/patchShoppingMallBuyerPaymentMethods";
import { getShoppingMallBuyerPaymentMethodsPaymentMethodId } from "../../../../providers/getShoppingMallBuyerPaymentMethodsPaymentMethodId";
import { putShoppingMallBuyerPaymentMethodsPaymentMethodId } from "../../../../providers/putShoppingMallBuyerPaymentMethodsPaymentMethodId";
import { deleteShoppingMallBuyerPaymentMethodsPaymentMethodId } from "../../../../providers/deleteShoppingMallBuyerPaymentMethodsPaymentMethodId";
import { postShoppingMallBuyerPaymentMethodsPaymentMethodIdSetDefault } from "../../../../providers/postShoppingMallBuyerPaymentMethodsPaymentMethodIdSetDefault";

import { IShoppingMallPaymentMethod } from "../../../../api/structures/IShoppingMallPaymentMethod";
import { IPageIShoppingMallPaymentMethod } from "../../../../api/structures/IPageIShoppingMallPaymentMethod";

@Controller("/shoppingMall/buyer/paymentMethods")
export class ShoppingmallBuyerPaymentmethodsController {
  /**
   * Register a new payment method for the authenticated buyer.
   *
   * Register a new payment method to the authenticated buyer's account for use
   * in future transactions. This operation enables buyers to save their
   * preferred payment methods including credit cards, debit cards, or other
   * supported payment instruments for convenient checkout experiences.
   *
   * The buyer's identity is automatically extracted from the JWT authentication
   * token, ensuring that payment methods are securely associated with the
   * correct account. The shopping_mall_buyer_id field is automatically
   * populated from the JWT token and must not be included in the request body.
   * The operation validates the payment method details according to the payment
   * provider's requirements and stores the information securely using
   * tokenization.
   *
   * Security considerations include encryption of sensitive payment data,
   * tokenization through payment providers (Stripe, PayPal, Square, Braintree),
   * and PCI DSS compliance for handling card information. The provider_token
   * must be obtained from a supported payment provider before submission. Only
   * the authenticated buyer can add payment methods to their own account. The
   * operation supports various payment method types as defined in the platform
   * configuration.
   *
   * This operation integrates with the shopping_mall_payment_methods table as
   * defined in the Prisma schema. The newly registered payment method becomes
   * immediately available for selection during the checkout process. Buyers can
   * manage multiple payment methods and designate a default method for faster
   * checkouts. If is_default is set to true, the system automatically sets
   * other payment methods' is_default field to false to maintain uniqueness.
   *
   * @param connection
   * @param body Payment method registration information including payment
   *   instrument details and billing information. The shopping_mall_buyer_id is
   *   automatically populated from JWT and must not be included.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @BuyerAuth()
    buyer: BuyerPayload,
    @TypedBody()
    body: IShoppingMallPaymentMethod.ICreate,
  ): Promise<IShoppingMallPaymentMethod> {
    try {
      return await postShoppingMallBuyerPaymentMethods({
        buyer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve a filtered, paginated list of buyer payment methods.
   *
   * Retrieve a filtered and paginated list of saved payment methods for
   * authenticated buyers from the system. This operation provides advanced
   * search capabilities for finding payment methods based on multiple criteria
   * including payment method type (credit card, debit card, digital wallet),
   * partial card number matching, expiration date ranges, and active status.
   *
   * The operation supports comprehensive pagination with configurable page
   * sizes and sorting options. Buyers can sort by creation date, last used
   * date, card type, or other relevant fields in ascending or descending order.
   * This endpoint is essential for buyers managing multiple saved payment
   * methods during checkout or account management workflows.
   *
   * Security considerations include strict authentication enforcement to ensure
   * buyers can only access their own payment methods. Sensitive card
   * information is masked in the response, displaying only the last four digits
   * of card numbers and expiration dates. Full card details are never exposed
   * through this API. The operation integrates with the
   * shopping_mall_payment_methods table as defined in the Prisma schema.
   *
   * This operation is typically used in checkout flows where buyers select from
   * saved payment methods, or in account settings where buyers manage their
   * stored payment options. Rate limiting applies to prevent enumeration
   * attacks and unauthorized access attempts.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for payment method
   *   filtering including optional filters for payment type, card brand,
   *   expiration status, and active status
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @BuyerAuth()
    buyer: BuyerPayload,
    @TypedBody()
    body: IShoppingMallPaymentMethod.IRequest,
  ): Promise<IPageIShoppingMallPaymentMethod.ISummary> {
    try {
      return await patchShoppingMallBuyerPaymentMethods({
        buyer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information of a specific payment method by ID.
   *
   * Retrieve complete details of a specific saved payment method identified by
   * its unique payment method ID. This operation provides comprehensive
   * information about the payment method including payment type (credit card,
   * debit card, digital wallet), masked card number (showing only last four
   * digits), card brand, expiration date, billing address association, and
   * active status.
   *
   * The operation enforces strict ownership validation to ensure that
   * authenticated buyers can only retrieve payment methods that belong to their
   * own account. Any attempt to access another buyer's payment method will
   * result in an authorization error. This security measure prevents
   * unauthorized access to sensitive payment information.
   *
   * Sensitive card details are appropriately masked in the response. The full
   * card number is never exposed - only the last four digits are returned along
   * with the card brand and expiration date. This approach balances usability
   * (allowing buyers to identify their cards) with security (protecting full
   * card numbers from exposure).
   *
   * This operation integrates with the shopping_mall_payment_methods table as
   * defined in the Prisma schema, incorporating all available payment method
   * fields and relationships including associations with the buyer account and
   * billing addresses. The response provides detailed information optimized for
   * payment method selection during checkout or for managing saved payment
   * options in account settings.
   *
   * @param connection
   * @param paymentMethodId Unique identifier of the target payment method
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":paymentMethodId")
  public async at(
    @BuyerAuth()
    buyer: BuyerPayload,
    @TypedParam("paymentMethodId")
    paymentMethodId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallPaymentMethod> {
    try {
      return await getShoppingMallBuyerPaymentMethodsPaymentMethodId({
        buyer,
        paymentMethodId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing payment method for the authenticated buyer.
   *
   * Update the details of an existing payment method in the authenticated
   * buyer's account. This operation enables buyers to modify payment method
   * information such as billing_name, billing_postal_code, or is_default status
   * without needing to delete and re-add the payment method.
   *
   * The buyer's identity is automatically extracted from the JWT authentication
   * token, and the operation validates that the specified payment method
   * belongs to the authenticated buyer. The system verifies that
   * payment_method.shopping_mall_buyer_id matches the authenticated buyer's ID
   * from the JWT token before allowing updates. This ensures buyers can only
   * modify their own payment methods, preventing unauthorized access to other
   * users' payment information.
   *
   * Security considerations include ownership verification through buyer_id
   * matching, encryption of updated sensitive data, and audit logging of all
   * payment method modifications. The operation supports partial updates,
   * allowing buyers to modify specific fields without affecting other payment
   * method details. Immutable fields like provider_token and card_brand cannot
   * be updated for security and compliance reasons - buyers must delete and
   * re-add payment methods to change these values.
   *
   * This operation integrates with the shopping_mall_payment_methods table as
   * defined in the Prisma schema. Updated payment methods remain available for
   * immediate use in checkout transactions. The operation validates all updated
   * information according to payment provider requirements and platform
   * security policies. If is_default is set to true, other payment methods are
   * automatically updated to is_default false.
   *
   * @param connection
   * @param paymentMethodId Unique identifier of the target payment method to
   *   update
   * @param body Updated payment method information including modifiable fields
   *   like billing details and default status preferences
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":paymentMethodId")
  public async update(
    @BuyerAuth()
    buyer: BuyerPayload,
    @TypedParam("paymentMethodId")
    paymentMethodId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallPaymentMethod.IUpdate,
  ): Promise<IShoppingMallPaymentMethod> {
    try {
      return await putShoppingMallBuyerPaymentMethodsPaymentMethodId({
        buyer,
        paymentMethodId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a saved payment method from buyer's account.
   *
   * Permanently remove a specific payment method from the authenticated buyer's
   * saved payment methods in the shopping mall platform.
   *
   * This operation allows buyers to delete payment methods they have previously
   * saved for checkout convenience. When a payment method is deleted, it is
   * permanently removed from the database and can no longer be used for future
   * purchases. This is a hard delete operation that completely removes the
   * record from the shopping_mall_payment_methods table.
   *
   * Security considerations include verifying that the authenticated buyer owns
   * the payment method being deleted, preventing unauthorized deletion of other
   * users' payment methods. The operation will fail if the payment method does
   * not belong to the authenticated buyer. If the payment method being deleted
   * is currently set as the default payment method, the buyer's default payment
   * method reference will be cleared, requiring them to set a new default if
   * they have other saved payment methods.
   *
   * Business rules enforce that payment methods can only be deleted by their
   * owner. The operation integrates with the shopping_mall_payment_methods
   * table as defined in the Prisma schema. After successful deletion, the
   * payment method will no longer appear in the buyer's list of saved payment
   * methods and cannot be selected during checkout.
   *
   * @param connection
   * @param paymentMethodId Unique identifier of the target payment method to be
   *   deleted
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":paymentMethodId")
  public async erase(
    @BuyerAuth()
    buyer: BuyerPayload,
    @TypedParam("paymentMethodId")
    paymentMethodId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallBuyerPaymentMethodsPaymentMethodId({
        buyer,
        paymentMethodId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Set a payment method as the default for checkout.
   *
   * Mark a specific saved payment method as the default payment method for the
   * authenticated buyer's future checkout transactions.
   *
   * This operation allows buyers to designate one of their saved payment
   * methods as their preferred default payment option. When a payment method is
   * set as default, it will be automatically pre-selected during the checkout
   * process, streamlining the purchase experience. The operation updates the
   * is_default field in the shopping_mall_payment_methods table, setting it to
   * true for the specified payment method while ensuring any previously default
   * payment method is updated to is_default false, maintaining the business
   * rule that only one payment method can be default at a time.
   *
   * Security considerations include verifying that the authenticated buyer owns
   * the payment method being set as default. The operation will fail if the
   * payment method does not belong to the authenticated buyer, preventing
   * unauthorized modification of other users' payment preferences. The buyer's
   * identity is automatically extracted from the JWT authentication token.
   *
   * Business rules enforce exclusive default status - when setting a new
   * default payment method, the system automatically clears the default flag
   * from any other payment method belonging to the same buyer. This operation
   * integrates with the shopping_mall_payment_methods table as defined in the
   * Prisma schema. After successful execution, the updated payment method
   * becomes the buyer's default payment option for all future checkout
   * operations.
   *
   * @param connection
   * @param paymentMethodId Unique identifier of the target payment method to be
   *   set as default
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post(":paymentMethodId/setDefault")
  public async setDefault(
    @BuyerAuth()
    buyer: BuyerPayload,
    @TypedParam("paymentMethodId")
    paymentMethodId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallPaymentMethod> {
    try {
      return await postShoppingMallBuyerPaymentMethodsPaymentMethodIdSetDefault(
        {
          buyer,
          paymentMethodId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
