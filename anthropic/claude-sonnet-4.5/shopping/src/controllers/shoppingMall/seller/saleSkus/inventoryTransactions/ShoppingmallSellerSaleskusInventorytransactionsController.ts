import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallSellerSaleSkusSaleSkuIdInventoryTransactions } from "../../../../../providers/patchShoppingMallSellerSaleSkusSaleSkuIdInventoryTransactions";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";

import { IPageIShoppingMallInventoryTransaction } from "../../../../../api/structures/IPageIShoppingMallInventoryTransaction";
import { IShoppingMallInventoryTransaction } from "../../../../../api/structures/IShoppingMallInventoryTransaction";

@Controller("/shoppingMall/seller/saleSkus/:saleSkuId/inventoryTransactions")
export class ShoppingmallSellerSaleskusInventorytransactionsController {
  /**
   * Retrieve paginated inventory transaction history for a specific product
   * SKU.
   *
   * Retrieve a filtered and paginated list of inventory transactions for a
   * specific product SKU variant. This operation provides a complete audit
   * trail of all inventory quantity changes and movements, essential for
   * inventory reconciliation, stock analysis, and operational auditing.
   *
   * The operation supports comprehensive filtering capabilities including date
   * range queries, transaction type filtering (stock additions, order
   * reservations, sales deductions, cancellation reversals), and flexible
   * sorting options. Users can query transactions by specific time periods to
   * analyze inventory patterns and investigate discrepancies.
   *
   * Security considerations include appropriate authorization checks to ensure
   * only authorized personnel can view detailed inventory transaction history.
   * The operation implements pagination to handle large transaction volumes
   * efficiently. Transaction data includes timestamps, quantity changes,
   * transaction types, reference IDs for related orders or operations, and any
   * associated notes or metadata.
   *
   * This operation integrates with the shopping_mall_inventory_transactions
   * table as defined in the Prisma schema, which maintains a complete
   * historical audit trail of all inventory movements. The response provides
   * transaction summary information optimized for analysis and reporting,
   * enabling sellers and administrators to track inventory flow, identify
   * patterns, and ensure accuracy of stock levels.
   *
   * @param connection
   * @param saleSkuId Unique identifier of the target product SKU variant
   *   (global scope)
   * @param body Search criteria and pagination parameters for filtering
   *   inventory transactions
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("saleSkuId")
    saleSkuId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallInventoryTransaction.IRequest,
  ): Promise<IPageIShoppingMallInventoryTransaction> {
    try {
      return await patchShoppingMallSellerSaleSkusSaleSkuIdInventoryTransactions(
        {
          seller,
          saleSkuId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
