import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { getShoppingMallSellerSaleSkusSaleSkuIdInventoryStock } from "../../../../../providers/getShoppingMallSellerSaleSkusSaleSkuIdInventoryStock";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { postShoppingMallSellerSaleSkusSaleSkuIdInventoryStock } from "../../../../../providers/postShoppingMallSellerSaleSkusSaleSkuIdInventoryStock";
import { putShoppingMallSellerSaleSkusSaleSkuIdInventoryStock } from "../../../../../providers/putShoppingMallSellerSaleSkusSaleSkuIdInventoryStock";

import { IShoppingMallInventoryStock } from "../../../../../api/structures/IShoppingMallInventoryStock";

@Controller("/shoppingMall/seller/saleSkus/:saleSkuId/inventoryStock")
export class ShoppingmallSellerSaleskusInventorystockController {
  /**
   * Retrieve current inventory stock levels for a product SKU variant.
   *
   * Retrieve the current inventory stock information for a specific product SKU
   * variant from the shopping_mall_inventory_stocks table. This operation
   * provides real-time visibility into stock levels, availability status, and
   * inventory thresholds for a single product variant.
   *
   * The inventory stock record represents the single source of truth for how
   * many units of a specific SKU are currently available for purchase. The
   * response includes total quantity (complete stock level), reserved quantity
   * (units temporarily held during checkout), and available quantity
   * (calculated as total minus reserved, representing units buyers can
   * immediately purchase).
   *
   * This endpoint is critical for several workflows: buyers checking product
   * availability before purchase, sellers monitoring inventory levels across
   * their catalog, and the checkout system validating stock availability during
   * order placement. The low stock threshold field indicates the
   * seller-configured level that triggers restock alerts.
   *
   * Stock quantities are maintained through inventory transactions including
   * sales, returns, restocks, and manual adjustments. Reserved quantities
   * represent units in pending checkouts that are temporarily allocated but not
   * yet confirmed as sold. When available quantity reaches zero, the SKU
   * becomes unavailable for purchase until restocked.
   *
   * The operation supports both seller self-service inventory monitoring
   * (sellers viewing their own SKU stock levels) and administrative oversight
   * (admins monitoring platform-wide inventory). Accurate real-time inventory
   * data prevents overselling and ensures buyers see correct availability
   * information.
   *
   * Related operations: PATCH /inventoryStocks searches across multiple SKUs
   * for bulk inventory monitoring, while this endpoint provides detailed stock
   * information for a single SKU variant.
   *
   * @param connection
   * @param saleSkuId Unique identifier of the product SKU variant
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("saleSkuId")
    saleSkuId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallInventoryStock> {
    try {
      return await getShoppingMallSellerSaleSkusSaleSkuIdInventoryStock({
        seller,
        saleSkuId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Create initial inventory stock record for a product SKU variant.
   *
   * Initialize inventory tracking for a specific product SKU variant in the
   * shopping marketplace. This operation creates the first inventory stock
   * record for a given sale SKU, establishing baseline quantity tracking that
   * will be used throughout the product's lifecycle.
   *
   * The operation is performed by sellers when they first add inventory for a
   * new product variant. It sets the initial available quantity and creates the
   * foundation for all subsequent inventory management operations including
   * reservations, sales deductions, and restocking.
   *
   * Security considerations: Only the seller who owns the parent product sale
   * can create inventory stock records for its SKUs. The system validates that
   * the specified saleSkuId belongs to a product owned by the authenticated
   * seller. The operation enforces business rules around minimum stock
   * quantities and validates that inventory tracking hasn't already been
   * initialized for this SKU.
   *
   * This operation integrates with the shopping_mall_inventory_stocks table as
   * defined in the Prisma schema. Upon successful creation, the inventory stock
   * becomes immediately available for reservation during checkout processes and
   * visible in seller inventory management dashboards.
   *
   * @param connection
   * @param saleSkuId Unique identifier of the target product SKU variant for
   *   inventory tracking initialization
   * @param body Initial inventory stock data including baseline quantity and
   *   tracking metadata
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("saleSkuId")
    saleSkuId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallInventoryStock.ICreate,
  ): Promise<IShoppingMallInventoryStock> {
    try {
      return await postShoppingMallSellerSaleSkusSaleSkuIdInventoryStock({
        seller,
        saleSkuId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update inventory stock information for a product SKU variant.
   *
   * Modify existing inventory stock tracking for a specific product SKU variant
   * in the shopping marketplace. This operation allows sellers to update
   * inventory quantities and tracking metadata for their product variants,
   * supporting restocking operations, inventory corrections, and manual
   * adjustments.
   *
   * The operation is typically used when sellers receive new inventory
   * shipments, perform inventory audits that reveal discrepancies, or need to
   * adjust stock levels for other business reasons. Updates may include
   * quantity adjustments, status changes, or metadata modifications while
   * maintaining a complete audit trail through the
   * shopping_mall_inventory_transactions table.
   *
   * Security considerations: Only the seller who owns the parent product sale
   * can update inventory stock records for its SKUs. The system validates
   * ownership and enforces business rules around minimum stock levels and
   * reserved quantity constraints. Updates that would result in available
   * quantity falling below reserved quantity are rejected to prevent
   * overselling.
   *
   * This operation integrates with the shopping_mall_inventory_stocks table as
   * defined in the Prisma schema. All updates are logged in the inventory
   * transaction history for complete traceability. The updated inventory levels
   * immediately affect product availability displayed to buyers and influence
   * low stock alerts sent to sellers.
   *
   * @param connection
   * @param saleSkuId Unique identifier of the target product SKU variant for
   *   inventory update
   * @param body Updated inventory stock data including quantity adjustments and
   *   metadata changes
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("saleSkuId")
    saleSkuId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallInventoryStock.IUpdate,
  ): Promise<IShoppingMallInventoryStock> {
    try {
      return await putShoppingMallSellerSaleSkusSaleSkuIdInventoryStock({
        seller,
        saleSkuId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
