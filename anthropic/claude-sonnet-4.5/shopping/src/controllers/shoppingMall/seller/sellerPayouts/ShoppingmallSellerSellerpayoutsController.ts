import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallSellerSellerPayouts } from "../../../../providers/patchShoppingMallSellerSellerPayouts";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { getShoppingMallSellerSellerPayoutsPayoutId } from "../../../../providers/getShoppingMallSellerSellerPayoutsPayoutId";

import { IPageIShoppingMallSellerPayout } from "../../../../api/structures/IPageIShoppingMallSellerPayout";
import { IShoppingMallSellerPayout } from "../../../../api/structures/IShoppingMallSellerPayout";

@Controller("/shoppingMall/seller/sellerPayouts")
export class ShoppingmallSellerSellerpayoutsController {
  /**
   * Retrieve a filtered and paginated list of seller payout records from the
   * shopping mall platform. This operation provides advanced search
   * capabilities for finding seller payouts based on multiple criteria
   * including payout status, settlement period, payout amounts, processing
   * dates, seller identification, and payment method information.
   *
   * The operation supports comprehensive pagination with configurable page
   * sizes and flexible sorting options. Users can sort payouts by settlement
   * date, payout amount, processing status, seller name, or other relevant
   * fields in ascending or descending order. This functionality is essential
   * for sellers tracking their earnings and for platform administrators
   * managing the payout workflow.
   *
   * Security and authorization are carefully managed in this operation. Sellers
   * can only view their own payout records, while platform administrators have
   * access to all seller payouts for financial reconciliation and dispute
   * resolution. The operation implements proper filtering based on the
   * authenticated user's actor type to ensure data privacy and security.
   *
   * This operation integrates with the shopping_mall_seller_payouts table as
   * defined in the Prisma schema, incorporating all payout-related fields
   * including gross revenue, platform commission deductions, net payout
   * amounts, payment processing fees, settlement periods, and payout status
   * tracking. The response provides sellers with complete visibility into their
   * earnings settlement process.
   *
   * Typical use cases include sellers monitoring their monthly earnings
   * settlements, tracking pending payouts, reviewing historical payout records,
   * and reconciling revenue against sales performance. Administrators use this
   * operation for financial reporting, payout batch processing verification,
   * and resolving seller payout inquiries.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering seller
   *   payouts by status, settlement period, amount range, seller
   *   identification, and payment processing details
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IShoppingMallSellerPayout.IRequest,
  ): Promise<IPageIShoppingMallSellerPayout.ISummary> {
    try {
      return await patchShoppingMallSellerSellerPayouts({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve comprehensive details about a specific seller payout transaction
   * from the shopping mall platform. This operation provides complete
   * information about a payout including the payout amount, current status,
   * creation and processing timestamps, and the associated seller account.
   *
   * This endpoint is essential for sellers to track their earnings settlements
   * and for platform administrators to audit payout transactions. The payout
   * information includes all relevant financial details and status tracking
   * necessary for accounting and reconciliation purposes.
   *
   * Security considerations: Only authenticated sellers can access their own
   * payout records, while administrators have access to all payout transactions
   * for platform oversight and financial auditing. The operation implements
   * proper authorization checks to ensure sellers can only view their own
   * payout history.
   *
   * This operation integrates with the shopping_mall_seller_payouts table as
   * defined in the Prisma schema, returning complete payout record details
   * including all financial and status information for the specified payout
   * transaction.
   *
   * @param connection
   * @param payoutId Unique identifier of the target seller payout transaction
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":payoutId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("payoutId")
    payoutId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallSellerPayout> {
    try {
      return await getShoppingMallSellerSellerPayoutsPayoutId({
        seller,
        payoutId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
