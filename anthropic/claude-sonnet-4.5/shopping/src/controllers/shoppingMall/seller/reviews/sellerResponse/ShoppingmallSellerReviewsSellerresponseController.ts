import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallSellerReviewsReviewIdSellerResponse } from "../../../../../providers/postShoppingMallSellerReviewsReviewIdSellerResponse";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { putShoppingMallSellerReviewsReviewIdSellerResponse } from "../../../../../providers/putShoppingMallSellerReviewsReviewIdSellerResponse";
import { deleteShoppingMallSellerReviewsReviewIdSellerResponse } from "../../../../../providers/deleteShoppingMallSellerReviewsReviewIdSellerResponse";

import { IShoppingMallReviewSellerResponse } from "../../../../../api/structures/IShoppingMallReviewSellerResponse";

@Controller("/shoppingMall/seller/reviews/:reviewId/sellerResponse")
export class ShoppingmallSellerReviewsSellerresponseController {
  /**
   * Create a seller's response to a specific product review.
   *
   * Create a new seller response to address a specific product review in the
   * shopping marketplace. This operation allows authenticated sellers to engage
   * with customer feedback by posting thoughtful, professional responses to
   * reviews on their products.
   *
   * The operation enforces strict business rules to maintain response quality
   * and authenticity. Only the seller whose product was reviewed can post a
   * response, ensuring responses come from the appropriate merchant. Each
   * review can have at most one seller response to prevent spam and maintain
   * clarity for buyers reading the feedback. The seller's identity is
   * automatically extracted from the JWT authentication token.
   *
   * Security and validation considerations: The operation validates that the
   * authenticated seller owns the product that was reviewed before allowing
   * response creation. It checks that no existing response already exists for
   * this review. The response text content is validated for length and
   * appropriateness to maintain professional marketplace standards. Rate
   * limiting may apply to prevent abuse.
   *
   * The created seller response becomes immediately visible alongside the
   * review, providing transparency to potential buyers about how sellers handle
   * customer feedback and concerns. This operation integrates with the
   * shopping_mall_review_seller_responses table as defined in the Prisma
   * schema.
   *
   * Related operations: Retrieve seller response (GET
   * /reviews/{reviewId}/sellerResponse) should be used to view existing
   * responses before attempting to create one.
   *
   * @param connection
   * @param reviewId Unique identifier of the target review (global scope)
   * @param body Seller response content and metadata for creating a response to
   *   the review
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallReviewSellerResponse.ICreate,
  ): Promise<IShoppingMallReviewSellerResponse> {
    try {
      return await postShoppingMallSellerReviewsReviewIdSellerResponse({
        seller,
        reviewId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Create or update seller response to a product review.
   *
   * Create or update a seller's response to a customer review on their product.
   * This operation enables sellers to engage with buyers who have provided
   * feedback by posting official responses to reviews.
   *
   * The seller's identity is automatically extracted from the JWT
   * authentication token to ensure that only the product's seller can respond
   * to reviews on their own products. The system validates that the
   * authenticated seller owns the product associated with the review before
   * allowing the response.
   *
   * Sellers can use this endpoint to thank customers for positive reviews,
   * address concerns raised in negative reviews, provide additional product
   * information, or offer solutions to problems mentioned in reviews. Each
   * review can have only one seller response, so subsequent calls will update
   * the existing response rather than creating duplicates.
   *
   * Security considerations: Only authenticated sellers can create responses,
   * and they can only respond to reviews on their own products. The operation
   * includes validation to prevent sellers from responding to reviews on
   * competitors' products. Rate limiting may apply to prevent spam responses.
   *
   * @param connection
   * @param reviewId Unique identifier of the target review (global scope)
   * @param body Seller response content and metadata
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallReviewSellerResponse.ICreate,
  ): Promise<IShoppingMallReviewSellerResponse> {
    try {
      return await putShoppingMallSellerReviewsReviewIdSellerResponse({
        seller,
        reviewId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete seller response to a product review.
   *
   * Permanently remove a seller's response to a customer review. This operation
   * enables sellers to delete their previously posted responses if they wish to
   * retract their comments or if the response is no longer relevant.
   *
   * The seller's identity is automatically extracted from the JWT
   * authentication token to ensure that only the seller who created the
   * response can delete it. The system validates ownership of both the response
   * and the underlying product before allowing deletion.
   *
   * Sellers might use this operation when they want to completely remove their
   * response rather than updating it, or when their response contained errors
   * or inappropriate content that should be removed entirely. Once deleted, the
   * review will no longer display any seller response.
   *
   * Security considerations: Only authenticated sellers can delete responses,
   * and they can only delete their own responses to reviews on their products.
   * The operation validates that the authenticated seller is the owner of both
   * the response and the product. This performs a hard delete, permanently
   * removing the response from the database.
   *
   * @param connection
   * @param reviewId Unique identifier of the target review (global scope)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallReviewSellerResponse> {
    try {
      return await deleteShoppingMallSellerReviewsReviewIdSellerResponse({
        seller,
        reviewId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
