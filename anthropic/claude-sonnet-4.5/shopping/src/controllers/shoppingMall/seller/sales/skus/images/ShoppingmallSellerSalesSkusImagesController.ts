import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallSellerSalesSaleCodeSkusSkuCodeImages } from "../../../../../../providers/postShoppingMallSellerSalesSaleCodeSkusSkuCodeImages";
import { SellerAuth } from "../../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../../decorators/payload/SellerPayload";
import { putShoppingMallSellerSalesSaleCodeSkusSkuCodeImagesImageId } from "../../../../../../providers/putShoppingMallSellerSalesSaleCodeSkusSkuCodeImagesImageId";
import { deleteShoppingMallSellerSalesSaleCodeSkusSkuCodeImagesImageId } from "../../../../../../providers/deleteShoppingMallSellerSalesSaleCodeSkusSkuCodeImagesImageId";

import { IShoppingMallSaleImage } from "../../../../../../api/structures/IShoppingMallSaleImage";

@Controller("/shoppingMall/seller/sales/:saleCode/skus/:skuCode/images")
export class ShoppingmallSellerSalesSkusImagesController {
  /**
   * Upload and attach a new product image to a specific SKU variant within a
   * sale listing. This operation enables sellers to add visual content to their
   * product variants, enhancing the buyer's ability to evaluate the product
   * before purchase.
   *
   * The operation validates that the sale exists, the SKU belongs to the
   * specified sale, and the seller has permission to modify the sale. Images
   * are uploaded as URI references rather than binary data, following the API's
   * content-type convention of application/json. The system may enforce limits
   * on the number of images per SKU and validate image format requirements.
   *
   * Security: Only the seller who owns the sale listing can upload images to
   * their SKUs. The seller's identity is automatically extracted from the JWT
   * authentication token and validated against the sale's ownership. The
   * operation includes validation to prevent unauthorized image uploads and
   * ensures the SKU code is valid within the context of the specified sale.
   *
   * The uploaded image becomes immediately visible in product displays and
   * search results. Images should represent the actual product variant
   * accurately to maintain marketplace trust and reduce return rates. Related
   * operations include retrieving SKU images (GET
   * /sales/{saleCode}/skus/{skuCode}/images/{imageId}) and managing the parent
   * sale listing.
   *
   * @param connection
   * @param saleCode Unique business identifier code of the target sale listing
   *   (global scope)
   * @param skuCode Unique business identifier code of the target SKU variant
   *   within the sale (scoped to sale)
   * @param body Image upload information including the image URI and optional
   *   metadata such as display order and alt text
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("saleCode")
    saleCode: string,
    @TypedParam("skuCode")
    skuCode: string,
    @TypedBody()
    body: IShoppingMallSaleImage.ICreate,
  ): Promise<IShoppingMallSaleImage> {
    try {
      return await postShoppingMallSellerSalesSaleCodeSkusSkuCodeImages({
        seller,
        saleCode,
        skuCode,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update the properties of an existing product image associated with a
   * specific SKU variant in a sale listing. This operation allows sellers to
   * modify image details such as the image URL, display order position, and
   * alternative text for accessibility.
   *
   * The operation validates that the sale exists, the SKU belongs to the
   * specified sale, and the image belongs to the specified SKU. Sellers can
   * only update images for their own products. The image URL should point to a
   * valid, accessible image resource.
   *
   * Security considerations include verifying seller ownership of the sale
   * listing before allowing modifications. The operation ensures data integrity
   * by validating the relationships between sale, SKU, and image entities.
   * Image order updates may affect how products are displayed to buyers in
   * search results and product detail pages.
   *
   * This operation integrates with the shopping_mall_sales,
   * shopping_mall_sale_skus, and shopping_mall_sale_images tables as defined in
   * the Prisma schema. The update affects only the specified image without
   * modifying other images in the SKU's image collection.
   *
   * @param connection
   * @param saleCode Unique business identifier code of the target sale listing
   *   (global scope)
   * @param skuCode Unique business identifier code of the target SKU variant
   *   within the sale (scoped to sale)
   * @param imageId Unique identifier of the target product image
   * @param body Updated image properties including URL, display order, and
   *   alternative text
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":imageId")
  public async update(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("saleCode")
    saleCode: string,
    @TypedParam("skuCode")
    skuCode: string,
    @TypedParam("imageId")
    imageId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallSaleImage.IUpdate,
  ): Promise<IShoppingMallSaleImage> {
    try {
      return await putShoppingMallSellerSalesSaleCodeSkusSkuCodeImagesImageId({
        seller,
        saleCode,
        skuCode,
        imageId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently remove a product image associated with a specific SKU variant
   * in a sale listing. This operation performs a hard delete, completely
   * removing the image record from the database. The deletion is immediate and
   * cannot be reversed.
   *
   * The operation validates that the sale exists, the SKU belongs to the
   * specified sale, and the image belongs to the specified SKU before
   * proceeding with deletion. Only sellers who own the sale listing can delete
   * images from their products. The system ensures referential integrity by
   * validating the complete ownership chain from sale to SKU to image.
   *
   * Security considerations include strict seller ownership verification to
   * prevent unauthorized image deletion. After deletion, the image will no
   * longer appear in product displays, and any references to the image URL
   * should be handled appropriately. If this was the last or only image for the
   * SKU, sellers should be aware that the product variant may appear without
   * visual representation.
   *
   * This operation integrates with the shopping_mall_sales,
   * shopping_mall_sale_skus, and shopping_mall_sale_images tables as defined in
   * the Prisma schema. The deletion affects only the specified image record
   * without impacting other images or SKU data.
   *
   * @param connection
   * @param saleCode Unique business identifier code of the target sale listing
   *   (global scope)
   * @param skuCode Unique business identifier code of the target SKU variant
   *   within the sale (scoped to sale)
   * @param imageId Unique identifier of the target product image to be deleted
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":imageId")
  public async erase(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("saleCode")
    saleCode: string,
    @TypedParam("skuCode")
    skuCode: string,
    @TypedParam("imageId")
    imageId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallSaleImage> {
    try {
      return await deleteShoppingMallSellerSalesSaleCodeSkusSkuCodeImagesImageId(
        {
          seller,
          saleCode,
          skuCode,
          imageId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
