import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia from "typia";
import { postShoppingMallSellerSales } from "../../../../providers/postShoppingMallSellerSales";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { putShoppingMallSellerSalesSaleCode } from "../../../../providers/putShoppingMallSellerSalesSaleCode";

import { IShoppingMallSale } from "../../../../api/structures/IShoppingMallSale";

@Controller("/shoppingMall/seller/sales")
export class ShoppingmallSellerSalesController {
  /**
   * Create a new product sale listing in the shopping mall marketplace,
   * enabling sellers to offer products to buyers. This operation is restricted
   * to authenticated sellers and represents the first step in the complete
   * product listing workflow.
   *
   * Sellers provide comprehensive product information including product name,
   * detailed description, category assignment for proper marketplace
   * organization, base pricing structure, and initial sale configuration. The
   * seller's identity is automatically extracted from the JWT authentication
   * token, ensuring proper ownership assignment and preventing unauthorized
   * listing creation.
   *
   * The operation validates that the assigned category exists and is a valid
   * leaf-level category in the hierarchy, preventing assignment to parent
   * categories. Product names and descriptions must meet content guidelines,
   * and pricing must be within acceptable ranges. The initial sale status is
   * typically set to draft or pending, allowing sellers to complete variant
   * setup, SKU configuration, and image uploads before activating the listing.
   *
   * Upon successful creation, the operation returns the complete sale entity
   * including the generated sale ID, which is required for subsequent
   * operations such as adding variant attributes, creating SKUs, uploading
   * images, and setting inventory levels. The created sale is associated with
   * the authenticated seller and inherits default marketplace settings.
   *
   * Security considerations include authentication enforcement (only sellers
   * can create sales), rate limiting to prevent spam listings, content
   * validation to ensure marketplace quality standards, and category validation
   * to maintain proper taxonomy structure. This operation is foundational to
   * the seller product management workflow.
   *
   * Related operations: Update sale details (PUT /sales/{saleId}), Add sale
   * variants (POST /sales/{saleId}/variants), Upload sale images (POST
   * /sales/{saleId}/images), Manage inventory (POST /inventory-stocks).
   *
   * @param connection
   * @param body Product sale creation data including name, description,
   *   category assignment, pricing, and initial configuration
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IShoppingMallSale.ICreate,
  ): Promise<IShoppingMallSale> {
    try {
      return await postShoppingMallSellerSales({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update the details of an existing product sale listing in the shopping
   * marketplace using its unique business identifier code. This operation
   * allows authenticated sellers to modify their product information including
   * the title, description, category assignment, base pricing information, and
   * publication status.
   *
   * The operation supports partial updates of sale properties while maintaining
   * data integrity and business rules. Sellers can update product metadata,
   * change category assignments, modify descriptions, and control the
   * visibility of their listings. The update process validates that all
   * required fields remain populated and that any category references are
   * valid.
   *
   * Security considerations: This operation requires seller authentication and
   * ownership verification. Only the seller who created the listing can update
   * it. Authorization is enforced through JWT token validation, and the system
   * verifies that the authenticated seller's ID matches the sale's owner.
   * Administrative users may have elevated permissions to moderate or update
   * any listing.
   *
   * Business rules enforced during updates include category existence
   * validation, ensuring the sale code remains unique if modified, and
   * maintaining referential integrity with related entities like SKUs and
   * images. The update operation does not cascade to child entities - SKU
   * updates, image management, and variant configurations require separate API
   * operations.
   *
   * This operation integrates with the shopping_mall_sales table as defined in
   * the Prisma schema, using the unique code constraint for identification.
   * Related operations include SKU management (for variant-level updates),
   * image management (for product photos), and inventory updates (for stock
   * levels).
   *
   * @param connection
   * @param saleCode Unique business identifier code of the target product sale
   *   listing (global scope)
   * @param body Updated product sale information including title, description,
   *   category, and status
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":saleCode")
  public async update(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("saleCode")
    saleCode: string,
    @TypedBody()
    body: IShoppingMallSale.IUpdate,
  ): Promise<IShoppingMallSale> {
    try {
      return await putShoppingMallSellerSalesSaleCode({
        seller,
        saleCode,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
