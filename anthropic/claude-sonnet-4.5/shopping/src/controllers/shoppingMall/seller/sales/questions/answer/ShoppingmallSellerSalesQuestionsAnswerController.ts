import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallSellerSalesSaleCodeQuestionsQuestionIdAnswer } from "../../../../../../providers/postShoppingMallSellerSalesSaleCodeQuestionsQuestionIdAnswer";
import { SellerAuth } from "../../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../../decorators/payload/SellerPayload";
import { putShoppingMallSellerSalesSaleCodeQuestionsQuestionIdAnswer } from "../../../../../../providers/putShoppingMallSellerSalesSaleCodeQuestionsQuestionIdAnswer";
import { deleteShoppingMallSellerSalesSaleCodeQuestionsQuestionIdAnswer } from "../../../../../../providers/deleteShoppingMallSellerSalesSaleCodeQuestionsQuestionIdAnswer";

import { IShoppingMallSaleQuestionAnswer } from "../../../../../../api/structures/IShoppingMallSaleQuestionAnswer";

@Controller("/shoppingMall/seller/sales/:saleCode/questions/:questionId/answer")
export class ShoppingmallSellerSalesQuestionsAnswerController {
  /**
   * Create a new answer from the seller in response to a customer's question
   * about a product sale. This operation enables sellers to provide detailed
   * responses to potential buyers' inquiries, helping customers make informed
   * purchase decisions.
   *
   * The seller's identity is automatically extracted from the JWT
   * authentication token, ensuring that only the actual seller of the product
   * can answer questions about their listings. The operation validates that the
   * question exists and belongs to the specified sale before creating the
   * answer.
   *
   * Security considerations include authentication verification to ensure only
   * authorized sellers can answer questions about their own products. The
   * system prevents unauthorized users from posting answers on behalf of
   * sellers. Rate limiting may be applied to prevent spam responses.
   *
   * This operation integrates with the shopping_mall_sale_questions and
   * shopping_mall_sale_question_answers tables as defined in the Prisma schema.
   * Once an answer is created, it becomes immediately visible to all users
   * viewing the product question, helping potential buyers understand product
   * details and seller responsiveness.
   *
   * @param connection
   * @param saleCode Unique business identifier code of the target sale (global
   *   scope)
   * @param questionId Unique identifier of the target product question
   * @param body Answer content and details to be created by the seller
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("saleCode")
    saleCode: string,
    @TypedParam("questionId")
    questionId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallSaleQuestionAnswer.ICreate,
  ): Promise<IShoppingMallSaleQuestionAnswer> {
    try {
      return await postShoppingMallSellerSalesSaleCodeQuestionsQuestionIdAnswer(
        {
          seller,
          saleCode,
          questionId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing answer from the seller in response to a customer's
   * question about a product sale. This operation enables sellers to modify
   * their responses to provide better information, correct errors, or add
   * additional details that may help customers.
   *
   * The seller's identity is automatically extracted from the JWT
   * authentication token, ensuring that only the original seller who created
   * the answer can modify it. The operation validates that both the question
   * and the existing answer belong to the specified sale and seller before
   * allowing the update.
   *
   * Security considerations include ownership verification to ensure sellers
   * can only update their own answers and cannot modify answers from other
   * sellers. The system maintains audit trails of answer modifications to track
   * changes over time. Rate limiting may be applied to prevent abuse.
   *
   * This operation integrates with the shopping_mall_sale_questions and
   * shopping_mall_sale_question_answers tables as defined in the Prisma schema.
   * Updated answers are immediately reflected to all users viewing the product
   * question, ensuring customers always see the most current and accurate
   * information from sellers.
   *
   * @param connection
   * @param saleCode Unique business identifier code of the target sale (global
   *   scope)
   * @param questionId Unique identifier of the target product question
   * @param body Updated answer content and details
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("saleCode")
    saleCode: string,
    @TypedParam("questionId")
    questionId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallSaleQuestionAnswer.IUpdate,
  ): Promise<IShoppingMallSaleQuestionAnswer> {
    try {
      return await putShoppingMallSellerSalesSaleCodeQuestionsQuestionIdAnswer({
        seller,
        saleCode,
        questionId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Remove a seller's response to a customer question about a product sale
   * listing.
   *
   * This operation enables sellers to delete their answers to customer
   * inquiries about their products. When a seller decides to retract or remove
   * their response to a question, this endpoint permanently deletes the answer
   * record from the system. The answer is identified through the hierarchical
   * context: first locating the sale by its unique business code, then finding
   * the specific question within that sale, and finally removing the associated
   * answer.
   *
   * Security considerations: Only the seller who owns the product sale can
   * delete answers to questions about their products. The operation validates
   * that the authenticated seller matches the sale owner before allowing answer
   * deletion. This prevents unauthorized users from removing responses that
   * don't belong to them.
   *
   * Business rules: Deleting an answer may affect customer decision-making, as
   * they will no longer see the seller's response. The system does not maintain
   * a soft-delete or history of deleted answers - removal is permanent. Sellers
   * should be cautious when deleting answers, as customers may have already
   * read and relied on the information. After deletion, the question returns to
   * an unanswered state, potentially prompting the seller or customer service
   * to provide a new response.
   *
   * This operation integrates with the shopping_mall_sale_question_answers
   * table as defined in the Prisma schema. The answer entity is a subsidiary
   * record that depends on both the parent question and ultimately the sale
   * listing. Related operations include creating answers (POST) and retrieving
   * question details with answers (GET).
   *
   * @param connection
   * @param saleCode Unique business identifier code of the target product sale
   *   (global scope)
   * @param questionId Unique identifier of the target question within the sale
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("saleCode")
    saleCode: string,
    @TypedParam("questionId")
    questionId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallSaleQuestionAnswer> {
    try {
      return await deleteShoppingMallSellerSalesSaleCodeQuestionsQuestionIdAnswer(
        {
          seller,
          saleCode,
          questionId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
