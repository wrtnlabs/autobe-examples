import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { putShoppingMallSellerSalesSaleCodeQuestionsQuestionId } from "../../../../../providers/putShoppingMallSellerSalesSaleCodeQuestionsQuestionId";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";

import { IShoppingMallSaleQuestion } from "../../../../../api/structures/IShoppingMallSaleQuestion";
import { IShoppingMallSaleQuestionAnswer } from "../../../../../api/structures/IShoppingMallSaleQuestionAnswer";

@Controller("/shoppingMall/seller/sales/:saleCode/questions/:questionId")
export class ShoppingmallSellerSalesQuestionsController {
  /**
   * Provide or update an answer to a customer question about a product sale.
   * This operation allows sellers to respond to buyer inquiries, helping
   * customers make informed purchase decisions and demonstrating seller
   * engagement and customer service quality.
   *
   * Only the authenticated seller who owns the product sale can answer
   * questions on that product. The operation validates seller ownership before
   * allowing the answer submission. If an answer already exists for this
   * question, it will be updated with the new content and timestamp. If no
   * answer exists, a new answer record is created.
   *
   * The answer content should be helpful, accurate, and professional, as it
   * will be visible to all potential buyers viewing the product. Answer quality
   * impacts seller reputation and buyer confidence. The system tracks answer
   * submission and modification timestamps for transparency.
   *
   * Security considerations include strict seller ownership validation to
   * prevent unauthorized users from answering questions on products they don't
   * own. The operation integrates with the shopping_mall_sale_question_answers
   * table as defined in the Prisma schema.
   *
   * Related operations include viewing the question details (GET
   * /sales/{saleCode}/questions/{questionId}) to understand the buyer's inquiry
   * before answering, and listing all questions (PATCH
   * /sales/{saleCode}/questions) to manage multiple inquiries efficiently.
   *
   * @param connection
   * @param saleCode Unique business identifier code of the target product sale
   *   (global scope)
   * @param questionId Unique identifier of the target question to answer
   * @param body Answer content and submission details for the seller's response
   *   to the customer question
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("saleCode")
    saleCode: string,
    @TypedParam("questionId")
    questionId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallSaleQuestionAnswer.IUpdate,
  ): Promise<IShoppingMallSaleQuestion> {
    try {
      return await putShoppingMallSellerSalesSaleCodeQuestionsQuestionId({
        seller,
        saleCode,
        questionId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
