import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallSellerSalesSaleCodeVariantAttributes } from "../../../../../providers/postShoppingMallSellerSalesSaleCodeVariantAttributes";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { putShoppingMallSellerSalesSaleCodeVariantAttributesVariantAttributeId } from "../../../../../providers/putShoppingMallSellerSalesSaleCodeVariantAttributesVariantAttributeId";
import { deleteShoppingMallSellerSalesSaleCodeVariantAttributesVariantAttributeId } from "../../../../../providers/deleteShoppingMallSellerSalesSaleCodeVariantAttributesVariantAttributeId";

import { IShoppingMallSaleVariantAttribute } from "../../../../../api/structures/IShoppingMallSaleVariantAttribute";

@Controller("/shoppingMall/seller/sales/:saleCode/variantAttributes")
export class ShoppingmallSellerSalesVariantattributesController {
  /**
   * Create a new variant attribute definition for a product sale.
   *
   * Create a new variant attribute definition for a specific product sale,
   * establishing the foundational structure for product variations.
   *
   * This operation allows authenticated sellers to define variant attributes
   * (such as 'Color', 'Size', 'Material', 'Style') that will be used to
   * differentiate between different SKUs of the same product. Each variant
   * attribute serves as a dimension along which product variations can be
   * specified, and multiple attributes can be combined to create complex
   * product configurations.
   *
   * The variant attribute creation is scoped to a specific sale identified by
   * its unique business code. The seller must have ownership of the target sale
   * to create variant attributes for it. The operation validates that the
   * attribute name is meaningful and that the sale exists and is accessible to
   * the authenticated seller.
   *
   * Security considerations include seller authentication and ownership
   * verification. Only the seller who owns the sale can define its variant
   * attributes. The operation integrates with the
   * shopping_mall_sale_variant_attributes table as defined in the Prisma
   * schema, creating the attribute structure that will later be populated with
   * specific variant values through separate operations.
   *
   * This operation is a prerequisite for creating variant values and ultimately
   * defining individual SKUs with specific variant combinations. The created
   * attribute will be referenced when defining variant values and configuring
   * product SKUs.
   *
   * @param connection
   * @param saleCode Unique business identifier code of the target sale (global
   *   scope)
   * @param body Variant attribute creation data including attribute name and
   *   configuration
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("saleCode")
    saleCode: string,
    @TypedBody()
    body: IShoppingMallSaleVariantAttribute.ICreate,
  ): Promise<IShoppingMallSaleVariantAttribute> {
    try {
      return await postShoppingMallSellerSalesSaleCodeVariantAttributes({
        seller,
        saleCode,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update a variant attribute for a specific product sale.
   *
   * Update the properties of an existing variant attribute for a specific
   * product sale in the shopping mall marketplace.
   *
   * This operation allows authenticated sellers to modify variant attribute
   * information for their products. Variant attributes define the configuration
   * dimensions for products with multiple options (such as Color, Size,
   * Material, etc.). Each variant attribute can have multiple variant values
   * that buyers can choose from when purchasing.
   *
   * Security: Only the seller who owns the product sale can update its variant
   * attributes. The seller's identity is automatically extracted from the JWT
   * authentication token and validated against the sale ownership. The
   * operation validates that the referenced sale exists, belongs to the
   * authenticated seller, and that the variant attribute exists for that sale.
   *
   * Business rules: Variant attributes that are already associated with
   * existing SKUs may have restrictions on modification to maintain data
   * integrity. The system ensures that updates to variant attributes do not
   * invalidate existing SKU configurations. Changes to variant attribute names
   * are reflected across all associated variant values and SKUs.
   *
   * Related operations: Create variant attribute (POST
   * /sales/{saleCode}/variantAttributes), Delete variant attribute (DELETE
   * /sales/{saleCode}/variantAttributes/{variantAttributeId}), List variant
   * attributes (GET /sales/{saleCode}/variantAttributes).
   *
   * @param connection
   * @param saleCode Unique business identifier code of the target product sale
   *   (global scope)
   * @param variantAttributeId Unique identifier of the target variant attribute
   *   to update
   * @param body Updated variant attribute properties including the attribute
   *   name
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":variantAttributeId")
  public async update(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("saleCode")
    saleCode: string,
    @TypedParam("variantAttributeId")
    variantAttributeId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallSaleVariantAttribute.IUpdate,
  ): Promise<IShoppingMallSaleVariantAttribute> {
    try {
      return await putShoppingMallSellerSalesSaleCodeVariantAttributesVariantAttributeId(
        {
          seller,
          saleCode,
          variantAttributeId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a variant attribute from a specific product sale.
   *
   * Permanently remove a variant attribute from a specific product sale in the
   * shopping mall marketplace.
   *
   * This operation allows authenticated sellers to delete variant attributes
   * from their products. Variant attributes can only be deleted if they are not
   * actively being used in existing SKU configurations. This prevents data
   * integrity issues where SKUs would reference non-existent variant
   * attributes.
   *
   * Security: Only the seller who owns the product sale can delete its variant
   * attributes. The seller's identity is automatically extracted from the JWT
   * authentication token and validated against the sale ownership. The
   * operation validates that the referenced sale exists, belongs to the
   * authenticated seller, and that the variant attribute exists for that sale.
   *
   * Business rules: The operation will fail if the variant attribute has
   * associated variant values that are referenced by existing SKUs. Sellers
   * must first remove or reconfigure affected SKUs before deleting the variant
   * attribute. This ensures product catalog integrity and prevents orphaned SKU
   * configurations. The deletion cascades to remove all associated variant
   * values that are not referenced by SKUs.
   *
   * Related operations: Create variant attribute (POST
   * /sales/{saleCode}/variantAttributes), Update variant attribute (PUT
   * /sales/{saleCode}/variantAttributes/{variantAttributeId}), List variant
   * attributes (GET /sales/{saleCode}/variantAttributes).
   *
   * @param connection
   * @param saleCode Unique business identifier code of the target product sale
   *   (global scope)
   * @param variantAttributeId Unique identifier of the target variant attribute
   *   to delete
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":variantAttributeId")
  public async erase(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("saleCode")
    saleCode: string,
    @TypedParam("variantAttributeId")
    variantAttributeId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallSaleVariantAttribute> {
    try {
      return await deleteShoppingMallSellerSalesSaleCodeVariantAttributesVariantAttributeId(
        {
          seller,
          saleCode,
          variantAttributeId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
