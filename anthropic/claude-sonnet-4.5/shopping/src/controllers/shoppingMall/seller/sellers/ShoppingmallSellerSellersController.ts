import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { putShoppingMallSellerSellersSellerId } from "../../../../providers/putShoppingMallSellerSellersSellerId";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { deleteShoppingMallSellerSellersSellerId } from "../../../../providers/deleteShoppingMallSellerSellersSellerId";

import { IShoppingMallSeller } from "../../../../api/structures/IShoppingMallSeller";

@Controller("/shoppingMall/seller/sellers/:sellerId")
export class ShoppingmallSellerSellersController {
  /**
   * Update the authenticated seller's account information including profile
   * details, business information, and account settings. This operation allows
   * sellers to modify their marketplace presence and ensure their account
   * information remains current.
   *
   * Sellers can update various aspects of their account such as business name,
   * contact information, profile descriptions, and operational settings. The
   * update is applied to the seller's own account, with the seller identity
   * verified through JWT authentication to prevent unauthorized modifications.
   *
   * Security considerations include validation that the authenticated seller
   * matches the sellerId path parameter, ensuring sellers cannot modify other
   * sellers' accounts. All updates are subject to business validation rules and
   * may trigger approval workflows if significant changes are made to verified
   * information.
   *
   * This operation integrates with the shopping_mall_sellers table as defined
   * in the Prisma schema. The request body contains the fields to be updated,
   * and the response returns the complete updated seller account information
   * for confirmation.
   *
   * @param connection
   * @param sellerId Unique identifier of the target seller account (must match
   *   authenticated seller)
   * @param body Updated seller account information and profile settings
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallSeller.IUpdate,
  ): Promise<IShoppingMallSeller> {
    try {
      return await putShoppingMallSellerSellersSellerId({
        seller,
        sellerId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Deactivate the authenticated seller's account from the shopping mall
   * marketplace by setting the deleted_at timestamp. This operation implements
   * a soft delete pattern, preserving the seller account data for audit and
   * compliance purposes while preventing login and hiding all product
   * listings.
   *
   * When a seller account is deactivated, the system handles related data
   * according to business rules. Active product listings are automatically
   * hidden from search results and product pages, pending orders must be
   * fulfilled or cancelled appropriately, and historical transaction data is
   * preserved for audit and compliance purposes.
   *
   * Security considerations include validation that the authenticated seller
   * matches the sellerId path parameter, ensuring sellers cannot deactivate
   * other sellers' accounts. The operation may be subject to business
   * constraints such as requiring all active orders to be completed, all
   * pending payments to be settled, and all outstanding disputes to be resolved
   * before account deactivation is permitted.
   *
   * This operation integrates with the shopping_mall_sellers table as defined
   * in the Prisma schema. The soft delete is implemented by setting the
   * deleted_at timestamp field. The response returns the deactivated seller
   * account information for confirmation and audit trail purposes. Accounts can
   * be reactivated within 90 days by clearing the deleted_at field.
   *
   * @param connection
   * @param sellerId Unique identifier of the target seller account (must match
   *   authenticated seller)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallSeller> {
    try {
      return await deleteShoppingMallSellerSellersSellerId({
        seller,
        sellerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
