import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallSellerSellersSellerIdSessions } from "../../../../../providers/patchShoppingMallSellerSellersSellerIdSessions";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { getShoppingMallSellerSellersSellerIdSessionsSessionId } from "../../../../../providers/getShoppingMallSellerSellersSellerIdSessionsSessionId";
import { deleteShoppingMallSellerSellersSellerIdSessionsSessionId } from "../../../../../providers/deleteShoppingMallSellerSellersSellerIdSessionsSessionId";

import { IPageIShoppingMallSellerSession } from "../../../../../api/structures/IPageIShoppingMallSellerSession";
import { IShoppingMallSellerSession } from "../../../../../api/structures/IShoppingMallSellerSession";

@Controller("/shoppingMall/seller/sellers/:sellerId/sessions")
export class ShoppingmallSellerSellersSessionsController {
  /**
   * Search and retrieve a filtered, paginated list of seller authentication
   * sessions.
   *
   * Retrieve a filtered and paginated list of seller authentication sessions
   * from the system. This operation provides advanced search capabilities for
   * finding sessions based on multiple criteria including session creation
   * timestamps, last activity times, IP addresses, user agent strings, and
   * session status (active/expired).
   *
   * The operation supports comprehensive pagination with configurable page
   * sizes and sorting options. Sessions can be sorted by creation date, last
   * activity, expiration time, or other relevant fields in ascending or
   * descending order. This is particularly useful for security auditing,
   * tracking concurrent logins, and identifying stale or suspicious sessions.
   *
   * Security considerations include ensuring that sellers can only access their
   * own session data, while administrators with elevated permissions can view
   * sessions across all sellers for platform-wide security monitoring. The
   * operation implements rate limiting for search operations to prevent abuse.
   * Session data includes metadata such as IP addresses, user agents, and
   * authentication timestamps which are critical for security audit trails.
   *
   * This operation integrates with the shopping_mall_seller_sessions table as
   * defined in the Prisma schema, incorporating all available session fields
   * and relationships to the parent seller account. The response includes
   * session summary information optimized for list displays, with options to
   * include additional security-relevant details based on authorization level.
   *
   * @param connection
   * @param sellerId Unique identifier of the target seller account (global
   *   scope)
   * @param body Search criteria and pagination parameters for session filtering
   *   including date ranges, IP addresses, and session status
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallSellerSession.IRequest,
  ): Promise<IPageIShoppingMallSellerSession.ISummary> {
    try {
      return await patchShoppingMallSellerSellersSellerIdSessions({
        seller,
        sellerId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific seller authentication
   * session.
   *
   * Retrieve complete details of a specific seller authentication session
   * identified by its unique session ID. This operation returns comprehensive
   * session information including creation timestamp, last activity time,
   * expiration timestamp, IP address, user agent string, and current session
   * status.
   *
   * This endpoint serves multiple critical security and operational purposes.
   * Sellers can view details of their own active sessions to verify legitimate
   * access and identify unauthorized logins. Administrators can inspect session
   * details across all sellers for security auditing, fraud detection, and
   * compliance monitoring. The detailed session information enables tracking of
   * login patterns, device fingerprinting, and geographic access analysis.
   *
   * Security considerations include strict authorization checks ensuring
   * sellers can only access their own session data unless they have
   * administrative privileges. The operation returns sensitive authentication
   * metadata that should be protected and logged for audit purposes. Session
   * details include cryptographic token information, IP addresses, and browser
   * fingerprints which are essential for detecting session hijacking or
   * credential sharing.
   *
   * This operation integrates with the shopping_mall_seller_sessions table as
   * defined in the Prisma schema, returning the complete session entity with
   * all fields and relationships. The response provides full session details
   * suitable for security dashboards, session management interfaces, and
   * administrative oversight tools.
   *
   * @param connection
   * @param sellerId Unique identifier of the target seller account (global
   *   scope)
   * @param sessionId Unique identifier of the target authentication session
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallSellerSession> {
    try {
      return await getShoppingMallSellerSellersSellerIdSessionsSessionId({
        seller,
        sellerId,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Terminate a specific seller authentication session (logout).
   *
   * Delete an active authentication session for a seller account, effectively
   * logging the seller out from the platform. This operation is used when a
   * seller explicitly logs out or when an admin needs to forcibly terminate a
   * seller's session for security reasons.
   *
   * The operation validates that the session exists and belongs to the
   * specified seller before deletion. It removes the session record from the
   * shopping_mall_seller_sessions table, immediately invalidating the
   * associated JWT token and preventing further API access using that session.
   *
   * Security considerations include ensuring that sellers can only delete their
   * own sessions unless the requesting user is an admin with elevated
   * permissions. The operation maintains an audit trail of session terminations
   * for security monitoring and compliance purposes.
   *
   * This operation is part of the authentication and session management
   * subsystem as defined in the Prisma schema. It works in conjunction with
   * seller login operations to manage the complete authentication lifecycle.
   *
   * @param connection
   * @param sellerId Unique identifier of the target seller account (global
   *   scope)
   * @param sessionId Unique identifier of the target session to terminate
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":sessionId")
  public async erase(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallSellerSession> {
    try {
      return await deleteShoppingMallSellerSellersSellerIdSessionsSessionId({
        seller,
        sellerId,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
