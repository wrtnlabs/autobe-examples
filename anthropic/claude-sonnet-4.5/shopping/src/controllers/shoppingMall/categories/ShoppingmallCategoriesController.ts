import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia from "typia";
import { patchShoppingMallCategories } from "../../../providers/patchShoppingMallCategories";
import { getShoppingMallCategoriesCategoryCode } from "../../../providers/getShoppingMallCategoriesCategoryCode";
import { getShoppingMallCategoriesCategorySlug } from "../../../providers/getShoppingMallCategoriesCategorySlug";

import { IPageIShoppingMallCategory } from "../../../api/structures/IPageIShoppingMallCategory";
import { IShoppingMallCategory } from "../../../api/structures/IShoppingMallCategory";

@Controller("/shoppingMall/categories")
export class ShoppingmallCategoriesController {
  /**
   * Search and retrieve a filtered, paginated list of product categories.
   *
   * Retrieve a comprehensive list of product categories from the shopping mall
   * marketplace with advanced filtering, searching, and hierarchical navigation
   * capabilities. This operation provides access to the complete category
   * taxonomy that organizes the marketplace's product catalog.
   *
   * The operation supports flexible querying including category name search,
   * hierarchical filtering (root categories vs subcategories), status-based
   * filtering, and sorting options. Users can navigate the category tree
   * structure by filtering for specific parent categories or retrieving only
   * top-level categories. The response includes essential category information
   * optimized for category browsing, navigation menus, and administrative
   * management.
   *
   * This is a public endpoint accessible without authentication, as category
   * browsing is a fundamental marketplace feature. The operation supports
   * pagination for efficient data retrieval when dealing with large category
   * hierarchies. Categories are organized hierarchically with parent-child
   * relationships, enabling multi-level navigation through the product
   * taxonomy. The category structure directly impacts product organization and
   * discovery throughout the marketplace.
   *
   * Security considerations include appropriate rate limiting for search
   * operations and ensuring category visibility rules are applied correctly.
   * The operation integrates with the shopping_mall_categories table as defined
   * in the Prisma schema, incorporating all category fields including name,
   * description, parent relationships, sort order, and status. This endpoint is
   * essential for building category navigation menus, product filtering
   * interfaces, and category management tools.
   *
   * @param connection
   * @param body Search criteria, filtering options, hierarchical navigation
   *   parameters, and pagination settings for category retrieval
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IShoppingMallCategory.IRequest,
  ): Promise<IPageIShoppingMallCategory.ISummary> {
    try {
      return await patchShoppingMallCategories({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information for a specific product category by its code.
   *
   * Retrieve comprehensive details for a single product category identified by
   * its unique category code. This operation provides access to the complete
   * category information including name, description, hierarchical position,
   * parent category relationships, and metadata.
   *
   * The category system supports hierarchical organization with parent-child
   * relationships, allowing for nested category structures. Categories are
   * identified by their unique code field for better URL readability and
   * developer experience, rather than using UUID identifiers.
   *
   * Security: This is a public read operation requiring no authentication, as
   * category information is essential for product browsing and discovery. All
   * users, including anonymous visitors, can access category details to
   * understand the product taxonomy and navigate the marketplace.
   *
   * The response includes complete category information as defined in the
   * shopping_mall_categories Prisma schema, with parent category relationships
   * populated for understanding the category hierarchy. This operation is
   * commonly used for category detail pages, breadcrumb navigation, and product
   * filtering interfaces.
   *
   * @param connection
   * @param categoryCode Unique business identifier code of the target category
   *   (global scope)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":categoryCode")
  public async getByCategorycode(
    @TypedParam("categoryCode")
    categoryCode: string,
  ): Promise<IShoppingMallCategory> {
    try {
      return await getShoppingMallCategoriesCategoryCode({
        categoryCode,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information for a specific product category by its slug.
   *
   * Retrieve comprehensive details for a single product category identified by
   * its unique category slug. This operation provides access to the complete
   * category information including name, description, hierarchical position,
   * parent category relationships, and metadata.
   *
   * The category system supports hierarchical organization with parent-child
   * relationships, allowing for nested category structures. Categories are
   * identified by their unique slug field for better URL readability, SEO
   * benefits, and developer experience, rather than using UUID identifiers.
   *
   * Security: This is a public read operation requiring no authentication, as
   * category information is essential for product browsing and discovery. All
   * users, including anonymous visitors, can access category details to
   * understand the product taxonomy and navigate the marketplace.
   *
   * The response includes complete category information as defined in the
   * shopping_mall_categories Prisma schema, with parent category relationships
   * populated for understanding the category hierarchy. This operation is
   * commonly used for category detail pages, breadcrumb navigation, and product
   * filtering interfaces.
   *
   * @param connection
   * @param categorySlug URL-friendly unique identifier of the target category
   *   (global scope)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":categorySlug")
  public async getByCategoryslug(
    @TypedParam("categorySlug")
    categorySlug: string,
  ): Promise<IShoppingMallCategory> {
    try {
      return await getShoppingMallCategoriesCategorySlug({
        categorySlug,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
