import { Controller, Ip } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthSellerJoin } from "../../../providers/postAuthSellerJoin";
import { postAuthSellerLogin } from "../../../providers/postAuthSellerLogin";
import { postAuthSellerRefresh } from "../../../providers/postAuthSellerRefresh";

import { IShoppingMallSeller } from "../../../api/structures/IShoppingMallSeller";

@Controller("/auth/seller")
export class AuthSellerController {
  /**
   * Register a new seller account and issue JWT tokens for the
   * shopping_mall_sellers table.
   *
   * Register a new seller account in the e-commerce marketplace and issue
   * initial JWT authentication tokens.
   *
   * This endpoint allows new merchants to create seller accounts on the
   * platform. Upon successful registration, the seller receives both access and
   * refresh JWT tokens, enabling immediate access to the seller dashboard and
   * store management features.
   *
   * The registration process creates a new record in the shopping_mall_sellers
   * database table with the provided seller information. The seller account is
   * created with member-level permissions, granting access to product listing
   * management, inventory control, order processing, and sales analytics.
   *
   * Security considerations include password hashing, email validation, and
   * duplicate account prevention. The system validates that the email address
   * is not already registered to prevent duplicate seller accounts.
   *
   * The response includes the complete seller profile information along with
   * JWT tokens (access token and refresh token) that should be used for
   * subsequent authenticated requests to seller-specific endpoints.
   *
   * @param connection
   * @param body Seller registration information including credentials and
   *   profile details
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallSeller.ICreate,
  ): Promise<IShoppingMallSeller.IAuthorized> {
    try {
      return await postAuthSellerJoin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate seller credentials and issue JWT tokens for the
   * shopping_mall_sellers table.
   *
   * Authenticate a seller account using email and password credentials and
   * issue JWT tokens.
   *
   * This endpoint validates seller login credentials and provides JWT
   * authentication tokens for accessing seller-specific features. Sellers must
   * provide their registered email address and password to authenticate.
   *
   * The authentication process verifies the provided credentials against the
   * shopping_mall_sellers table, checking that the email exists and the
   * password matches the hashed password stored in the database. Password
   * comparison is performed securely using cryptographic hashing.
   *
   * Upon successful authentication, the system issues both an access token
   * (short-lived, for API requests) and a refresh token (long-lived, for
   * obtaining new access tokens). These tokens enable access to seller
   * dashboard features including product management, inventory control, order
   * processing, and sales analytics.
   *
   * Security measures include rate limiting to prevent brute force attacks,
   * secure password verification, and token generation following JWT best
   * practices. Failed login attempts should be logged for security monitoring.
   *
   * The response contains the authenticated seller's profile information along
   * with the JWT token pair that must be included in subsequent requests to
   * seller-protected endpoints.
   *
   * @param connection
   * @param body Seller login credentials including email and password
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallSeller.ILogin,
  ): Promise<IShoppingMallSeller.IAuthorized> {
    try {
      return await postAuthSellerLogin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh seller JWT access tokens using a valid refresh token from
   * shopping_mall_seller_sessions.
   *
   * Refresh seller access tokens using a valid refresh token to extend the
   * authenticated session.
   *
   * This endpoint enables sellers to obtain new access tokens without
   * re-entering their credentials. When the access token expires or is near
   * expiration, sellers can use their refresh token to request a new access
   * token, maintaining continuous authenticated access to the platform.
   *
   * The refresh process validates the provided refresh token against the
   * shopping_mall_seller_sessions table to ensure it is valid, not expired, and
   * belongs to an active seller account. If validation succeeds, the system
   * issues a new access token and optionally a new refresh token.
   *
   * This mechanism provides a balance between security and user experience.
   * Access tokens have shorter lifespans (typically minutes to hours) to limit
   * the window of vulnerability if compromised, while refresh tokens have
   * longer lifespans (days to weeks) to reduce the frequency of full
   * re-authentication.
   *
   * Security considerations include refresh token rotation (issuing new refresh
   * tokens with each refresh operation), refresh token revocation on logout,
   * and detection of refresh token reuse which may indicate token theft.
   *
   * The response includes new JWT tokens (access and optionally refresh) along
   * with the seller's current profile information, allowing the client to
   * update its authentication state and continue making authenticated requests
   * seamlessly.
   *
   * @param connection
   * @param body Valid refresh token for obtaining new access tokens
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IShoppingMallSeller.IRefresh,
  ): Promise<IShoppingMallSeller.IAuthorized> {
    try {
      return await postAuthSellerRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
