import { Controller, Ip } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthAdminJoin } from "../../../providers/postAuthAdminJoin";
import { postAuthAdminLogin } from "../../../providers/postAuthAdminLogin";
import { postAuthAdminRefresh } from "../../../providers/postAuthAdminRefresh";

import { IShoppingMallAdmin } from "../../../api/structures/IShoppingMallAdmin";

@Controller("/auth/admin")
export class AuthAdminController {
  /**
   * Creates a new administrator account in the platform and issues initial JWT
   * authentication tokens (access token and refresh token) for immediate system
   * access.
   *
   * This endpoint is used during admin onboarding to establish new
   * administrative accounts with elevated privileges. Upon successful
   * registration, the admin receives both an access token for API
   * authentication and a refresh token for obtaining new access tokens when
   * they expire.
   *
   * The operation validates the provided admin credentials, creates a new
   * record in the shopping_mall_admins table with a securely hashed password,
   * and generates a session record in shopping_mall_admin_sessions for
   * authentication tracking and audit trails.
   *
   * Security considerations include password strength validation, email
   * uniqueness verification, and secure token generation following JWT best
   * practices. The issued tokens contain the admin's identity claims and
   * permission scopes necessary for platform governance operations.
   *
   * This is a public endpoint that does not require prior authentication, as it
   * serves as the entry point for creating new admin accounts in the system.
   *
   * @param connection
   * @param body Admin registration information including credentials and
   *   profile data
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallAdmin.ICreate,
  ): Promise<IShoppingMallAdmin.IAuthorized> {
    try {
      return await postAuthAdminJoin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticates an existing administrator account using email and password
   * credentials, then issues new JWT authentication tokens (access token and
   * refresh token) for platform access.
   *
   * This endpoint is the primary authentication mechanism for administrators
   * who already have accounts in the system. It validates the provided
   * credentials against stored admin records in the shopping_mall_admins table,
   * verifying the password hash and account status.
   *
   * Upon successful authentication, the system creates a new session record in
   * shopping_mall_admin_sessions for audit tracking and security monitoring,
   * then generates fresh JWT tokens containing the admin's identity claims and
   * permission scopes.
   *
   * The operation implements security best practices including password
   * verification using secure hashing algorithms, failed login attempt
   * tracking, and protection against brute-force attacks through rate limiting
   * and account lockout mechanisms.
   *
   * This is a public endpoint that does not require prior authentication, as it
   * serves as the entry point for established administrators to access the
   * platform's governance and management capabilities.
   *
   * @param connection
   * @param body Admin login credentials including email and password
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallAdmin.ILogin,
  ): Promise<IShoppingMallAdmin.IAuthorized> {
    try {
      return await postAuthAdminLogin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refreshes the administrator's JWT access token using a valid refresh token,
   * extending the authenticated session without requiring credential re-entry.
   *
   * This endpoint implements token rotation security patterns where
   * administrators can maintain authenticated sessions beyond the access
   * token's expiration period. When an access token expires, the admin presents
   * their refresh token to obtain a new access token without interrupting their
   * workflow.
   *
   * The operation validates the provided refresh token against stored session
   * records in shopping_mall_admin_sessions, verifying token authenticity,
   * expiration status, and session validity. Upon successful validation, it
   * issues a new access token while optionally rotating the refresh token to
   * enhance security.
   *
   * This mechanism balances security and user experience by keeping access
   * tokens short-lived (reducing the window of vulnerability if compromised)
   * while allowing longer-lived refresh tokens for session continuity. The
   * system tracks all token refresh events in the session audit trail for
   * security monitoring.
   *
   * The endpoint requires a valid refresh token for authentication, as it
   * serves to renew access credentials for administrators who have previously
   * authenticated through join or login operations.
   *
   * @param connection
   * @param body Refresh token for obtaining new access token
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IShoppingMallAdmin.IRefresh,
  ): Promise<IShoppingMallAdmin.IAuthorized> {
    try {
      return await postAuthAdminRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
