import { Controller, Ip } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthBuyerJoin } from "../../../providers/postAuthBuyerJoin";
import { postAuthBuyerLogin } from "../../../providers/postAuthBuyerLogin";
import { postAuthBuyerRefresh } from "../../../providers/postAuthBuyerRefresh";

import { IShoppingMallBuyer } from "../../../api/structures/IShoppingMallBuyer";

@Controller("/auth/buyer")
export class AuthBuyerController {
  /**
   * Register new buyer account and issue initial authentication tokens.
   *
   * Register a new buyer account in the shopping mall platform and receive
   * initial JWT authentication tokens.
   *
   * This endpoint creates a new authenticated buyer account, allowing customers
   * to access the full range of platform features including shopping cart
   * management, order placement, review submission, and order tracking. Upon
   * successful registration, the system immediately issues both an access token
   * and a refresh token, enabling the buyer to start using the platform without
   * requiring a separate login step.
   *
   * The registration process validates the provided credentials, creates the
   * buyer record in the shopping_mall_buyers table, and generates a new session
   * record in shopping_mall_buyer_sessions for authentication tracking and
   * audit purposes. The system enforces unique email addresses to prevent
   * duplicate accounts.
   *
   * Security considerations include password strength requirements, email
   * validation, and secure token generation using JWT standards. The initial
   * session is created with appropriate expiration times for both access and
   * refresh tokens according to platform security policies.
   *
   * This operation is publicly accessible and does not require any prior
   * authentication. It serves as the entry point for new customers to join the
   * marketplace ecosystem.
   *
   * @param connection
   * @param body Buyer registration information including credentials and
   *   profile data
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallBuyer.ICreate,
  ): Promise<IShoppingMallBuyer.IAuthorized> {
    try {
      return await postAuthBuyerJoin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate buyer credentials and issue authentication tokens.
   *
   * Authenticate an existing buyer account and receive JWT authentication
   * tokens.
   *
   * This endpoint validates buyer credentials and issues fresh authentication
   * tokens, allowing returning customers to access their accounts and resume
   * shopping activities. The login process verifies the provided email and
   * password against stored buyer credentials in the shopping_mall_buyers
   * table.
   *
   * Upon successful authentication, the system generates a new session record
   * in shopping_mall_buyer_sessions for tracking and audit purposes. This
   * session record maintains the authentication state and provides an audit
   * trail of buyer login activities. The system issues both an access token for
   * API authorization and a refresh token for obtaining new access tokens
   * without re-entering credentials.
   *
   * Security measures include password hashing verification, account status
   * validation (ensuring the account is not suspended or deactivated), and
   * secure JWT token generation following industry best practices. Failed login
   * attempts should be monitored for security purposes.
   *
   * This operation is publicly accessible and does not require prior
   * authentication. It serves as the primary authentication entry point for
   * existing buyers to access their accounts and utilize platform features such
   * as order management, shopping cart access, and review submission.
   *
   * @param connection
   * @param body Buyer login credentials including email and password
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallBuyer.ILogin,
  ): Promise<IShoppingMallBuyer.IAuthorized> {
    try {
      return await postAuthBuyerLogin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh buyer access token using a valid refresh token.
   *
   * Refresh buyer authentication tokens using a valid refresh token.
   *
   * This endpoint enables buyers to obtain new access tokens without requiring
   * them to re-enter their login credentials. When an access token expires, the
   * buyer can use their refresh token to seamlessly continue their
   * authenticated session and maintain uninterrupted access to platform
   * features.
   *
   * The refresh process validates the provided refresh token against the
   * shopping_mall_buyer_sessions table, verifies the session is still valid and
   * not expired, and issues a fresh access token. Depending on platform
   * security policies, the system may also issue a new refresh token (token
   * rotation) to enhance security.
   *
   * Security considerations include refresh token validation, session status
   * verification, token expiration checking, and potential token rotation
   * strategies. The system should invalidate compromised or suspicious refresh
   * tokens and maintain session integrity throughout the refresh process.
   *
   * This operation requires a valid refresh token to be provided in the
   * request. It does not require an access token, making it suitable for
   * scenarios where the access token has expired but the refresh token remains
   * valid. This design pattern follows OAuth 2.0 and JWT best practices for
   * token-based authentication systems.
   *
   * The refresh operation maintains the audit trail by updating the
   * corresponding session record in shopping_mall_buyer_sessions, ensuring
   * complete tracking of authentication activities.
   *
   * @param connection
   * @param body Refresh token to obtain new access token
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IShoppingMallBuyer.IRefresh,
  ): Promise<IShoppingMallBuyer.IAuthorized> {
    try {
      return await postAuthBuyerRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
