/**
 * Retrieve a paginated and filterable list of user accounts for administrative
 * purposes.
 *
 * This operation provides search and pagination over the user base, including
 * advanced filter capabilities such as partial matching of email addresses,
 * filtering by account status, and sorting by registration time or last
 * activity. It enables system administrators to monitor, audit, and manage user
 * accounts efficiently.
 *
 * Security considerations restrict access to users with administrative
 * privileges. Sensitive user information, such as password hashes or
 * authentication tokens, is never exposed in the API response. Users returned
 * in the result will include summary information relevant for administrative
 * review and bulk management.
 *
 * The operation integrates with the todo_app_users table in the Prisma schema
 * and enforces all associated field validation and unique constraints. Errors
 * are reported with clear causes, such as invalid search parameters or
 * excessive page sizes. Related operations include retrieving individual user
 * account details and managing account status changes.
 *
 * @param props.connection
 * @param props.body Search and filter criteria for retrieving a paginated list
 *   of user accounts, including pagination options, text search, and account
 *   status filters.
 * @path /todoApp/admin/users
 * @accessor api.functional.todoApp.admin.users.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Search and filter criteria for retrieving a paginated list of user
     * accounts, including pagination options, text search, and account
     * status filters.
     */
    body: ITodoAppUser.IRequest;
  };
  export type Body = ITodoAppUser.IRequest;
  export type Response = IPageITodoAppUser.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/todoApp/admin/users",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/todoApp/admin/users";
  export const random = (): IPageITodoAppUser.ISummary =>
    typia.random<IPageITodoAppUser.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

