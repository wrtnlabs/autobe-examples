/**
 * Retrieve a filtered and paginated list of todo items from the application.
 * This operation provides advanced search capabilities, including partial
 * matching of titles or descriptions, deadline-based filtering, completion
 * status filtering, and flexible sorting by various fields.
 *
 * The operation leverages pagination for performance and scalability, allowing
 * users to efficiently browse their todo lists, and administrators to audit
 * tasks systemwide. Filtering options are implemented following the request
 * body schema and can include creator, due date, state, and custom properties
 * if available in the schema. Search strategies are case-insensitive where
 * applicable, and partial matches are supported where string fields exist.
 *
 * Security: Permissions are enforced based on the authenticated user and actor
 * role. Users can typically view their own todos, while administrators may
 * access all users' todos dependent on system policy. Access control is
 * strictly verified according to the permission matrix defined for
 * todo_app_todos. Returned fields and result set size are constrained for
 * security and performance as described in requirements.
 *
 * @param props.connection
 * @param props.body Request body containing search query, filter, sorting, and
 *   pagination parameters for finding todo items.
 * @path /todoApp/admin/todos
 * @accessor api.functional.todoApp.admin.todos.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Request body containing search query, filter, sorting, and pagination
     * parameters for finding todo items.
     */
    body: ITodoAppTodo.IRequest;
  };
  export type Body = ITodoAppTodo.IRequest;
  export type Response = IPageITodoAppTodo.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/todoApp/admin/todos",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/todoApp/admin/todos";
  export const random = (): IPageITodoAppTodo.ISummary =>
    typia.random<IPageITodoAppTodo.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

