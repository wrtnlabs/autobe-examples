/**
 * Batch update multiple todos in the todo_app_todos table using a single bulk
 * operation.
 *
 * Modify multiple todo items in a single request for advanced user convenience
 * and workflow optimization.
 *
 * This operation lets users perform actions (such as batch completion, updating
 * descriptions, or soft-deletion) on multiple todos at once, identified by
 * their unique UUIDs. The request body provides a list of todo IDs and an
 * update object specifying the fields to apply to all selected todos. Security
 * checks ensure each todo belongs to the requesting user or that administrative
 * permissions are in effect. Title uniqueness among active todos is enforced
 * per business rules; conflicts should generate errors for affected items
 * without breaking the batch.
 *
 * The operation is optimized for efficiency and integrates audit trail
 * recording for all changes. Use-case examples include 'complete all overdue
 * tasks' or 'assign due date to selected todos'. Permanent deletion is not
 * supported by this endpoint and must be done individually via the erase
 * endpoint or by system administrators.
 *
 * @param props.connection
 * @param props.body Payload containing todo IDs and the fields to update for
 *   all included todos. Enforces todo ownership and update business logic.
 * @path /todoApp/user/todos/bulk
 * @accessor api.functional.todoApp.user.todos.bulk.updateBulk
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function updateBulk(
  connection: IConnection,
  props: updateBulk.Props,
): Promise<updateBulk.Response> {
  return true === connection.simulate
    ? updateBulk.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...updateBulk.METADATA,
          path: updateBulk.path(),
          status: null,
        },
        props.body,
      );
}
export namespace updateBulk {
  export type Props = {
    /**
     * Payload containing todo IDs and the fields to update for all included
     * todos. Enforces todo ownership and update business logic.
     */
    body: ITodoAppTodo.IBulkUpdate;
  };
  export type Body = ITodoAppTodo.IBulkUpdate;
  export type Response = ITodoAppTodo.IBulkUpdateResult;

  export const METADATA = {
    method: "PATCH",
    path: "/todoApp/user/todos/bulk",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/todoApp/user/todos/bulk";
  export const random = (): ITodoAppTodo.IBulkUpdateResult =>
    typia.random<ITodoAppTodo.IBulkUpdateResult>();
  export const simulate = (
    connection: IConnection,
    props: updateBulk.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: updateBulk.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
