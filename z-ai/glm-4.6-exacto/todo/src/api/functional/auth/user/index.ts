/**
 * Registers a new todo_app_users account using unique email and password hash,
 * issuing JWT tokens upon success.
 *
 * This endpoint allows the creation of a new user account in the todo_app_users
 * table, capturing a unique email and securely hashed password as required by
 * schema definitions.
 *
 * It accepts an email (unique across all accounts, per unique index) and a
 * password, which is stored as a secure hash in password_hash—never in
 * plaintext, in compliance with security standards detailed in the prisma
 * schema. Upon account creation, system timestamps are recorded in created_at
 * and updated_at for compliance and tracking.
 *
 * This operation is public: anyone may register as a user but users must not
 * duplicate existing emails. If an email already exists, an error is returned
 * as enforced by the unique index constraint in the database model.
 *
 * Account creation also provisionally grants access, as JWT tokens are issued
 * immediately after successful registration, following the business rules
 * defined in both requirements and schema. The process does not permit creation
 * of admin accounts; those are managed in a separate table by design to
 * preserve role separation.
 *
 * This endpoint complements other authentication endpoints such as login and
 * refresh, ensuring consistent entry into the authentication workflow for the
 * user actor. It handles error and validation scenarios according to the
 * underlying schema and operational requirements.
 *
 * @param props.connection
 * @param props.body Information required to create a new user account: unique
 *   email address and password (in plain text, to be securely hashed before
 *   storage).
 * @setHeader token.access Authorization
 *
 * @path /auth/user/join
 * @accessor api.functional.auth.user.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
