/**
 * Register a new administrator in the todo_app_admins table and issue a new
 * login session.
 *
 * This endpoint supports secure administrative onboarding by registering a new
 * admin record in the todo_app_admins Prisma table.
 *
 * The input requires a unique email and password, both strictly validated per
 * the table's constraints. The email must be unique among all admins, enforced
 * by a unique index, while the password is processed and stored as a
 * cryptographically secure password_hash. Creation and update timestamps are
 * automatically managed for auditability.
 *
 * Admin creation flows integrate with authentication event tracking in the
 * todo_app_admin_sessions table, supporting compliance and non-repudiation. All
 * issued JWT tokens contain the admin's userId and role for downstream
 * authorization gates. Registered admins may immediately use all admin-level
 * application operations upon joining.
 *
 * Security within this flow is critical: failed attempts for duplicate emails
 * or password policy violations result in error responses without leaking
 * details about the existence of admin accounts.
 *
 * The operation forms part of the foundational authentication workflow for
 * privileged Todo application access, in conjunction with admin login and
 * session management endpoints.
 *
 * @param props.connection
 * @param props.body Administrative registration requiring a unique email and
 *   password, validated to business and schema rules.
 * @setHeader token.access Authorization
 *
 * @path /auth/admin/join
 * @accessor api.functional.auth.admin.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
