import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { putTodoAppUserUsersUserId } from "../../../../providers/putTodoAppUserUsersUserId";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { deleteTodoAppUserUsersUserId } from "../../../../providers/deleteTodoAppUserUsersUserId";

import { ITodoAppUser } from "../../../../api/structures/ITodoAppUser";

@Controller("/todoApp/user/users/:userId")
export class TodoappUserUsersController {
  /**
   * Update an existing user's account details securely.
   *
   * This endpoint enables individual users to modify their personal account
   * data, including password and email, as per defined validation rules. The
   * operation strictly restricts updates to the authenticated user's own
   * record, guaranteeing privacy and access control. Email updates are
   * permitted only if the new email does not conflict with another registered
   * user account.
   *
   * All modifications update the updated_at field to the current timestamp. Any
   * required password changes must be provided as a securely hashed value. The
   * endpoint does not allow changes to administrative privileges. System audit
   * trails record all changes for compliance and forensic analysis.
   *
   * If the specified userId does not match the authenticated user, the request
   * is denied for security reasons. Related endpoints include the account
   * retrieval API (GET /users/{userId}) and account deletion (DELETE
   * /users/{userId}).
   *
   * @param connection
   * @param userId Unique identifier of the target user account (UUID format)
   *   (global scope)
   * @param body Fields for updating the user's account data, including password
   *   and email, following appropriate validation.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoAppUser.IUpdate,
  ): Promise<ITodoAppUser> {
    try {
      return await putTodoAppUserUsersUserId({
        user,
        userId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a user account in a secure and compliant manner by marking the
   * account with a deletion timestamp rather than physical removal.
   *
   * This endpoint supports soft deletion of a user's account, satisfying GDPR
   * and user privacy requirements. Account deletion is user-initiated and
   * strictly limited to the authenticated user. Upon execution, the system
   * assigns the current time to the deleted_at field, rendering the account
   * inaccessible for login and removing the user from active listings.
   *
   * The operation does not remove audit data or system logs associated with the
   * user, which are retained for compliance. Any attempt to delete an account
   * by an unauthorized actor will be denied. Related APIs include user
   * retrieval and user update endpoints. Recovery of deleted accounts depends
   * on additional system features outside the scope of this operation.
   *
   * @param connection
   * @param userId Unique identifier of the target user account (UUID format)
   *   (global scope)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppUser> {
    try {
      return await deleteTodoAppUserUsersUserId({
        user,
        userId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
