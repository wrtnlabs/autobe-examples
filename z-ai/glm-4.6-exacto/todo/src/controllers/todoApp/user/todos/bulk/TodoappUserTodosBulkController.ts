import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { patchTodoAppUserTodosBulk } from "../../../../../providers/patchTodoAppUserTodosBulk";
import { UserAuth } from "../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../decorators/payload/UserPayload";

import { ITodoAppTodo } from "../../../../../api/structures/ITodoAppTodo";

@Controller("/todoApp/user/todos/bulk")
export class TodoappUserTodosBulkController {
  /**
   * Batch update multiple todos in the todo_app_todos table using a single bulk
   * operation.
   *
   * Modify multiple todo items in a single request for advanced user
   * convenience and workflow optimization.
   *
   * This operation lets users perform actions (such as batch completion,
   * updating descriptions, or soft-deletion) on multiple todos at once,
   * identified by their unique UUIDs. The request body provides a list of todo
   * IDs and an update object specifying the fields to apply to all selected
   * todos. Security checks ensure each todo belongs to the requesting user or
   * that administrative permissions are in effect. Title uniqueness among
   * active todos is enforced per business rules; conflicts should generate
   * errors for affected items without breaking the batch.
   *
   * The operation is optimized for efficiency and integrates audit trail
   * recording for all changes. Use-case examples include 'complete all overdue
   * tasks' or 'assign due date to selected todos'. Permanent deletion is not
   * supported by this endpoint and must be done individually via the erase
   * endpoint or by system administrators.
   *
   * @param connection
   * @param body Payload containing todo IDs and the fields to update for all
   *   included todos. Enforces todo ownership and update business logic.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async updateBulk(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoAppTodo.IBulkUpdate,
  ): Promise<ITodoAppTodo.IBulkUpdateResult> {
    try {
      return await patchTodoAppUserTodosBulk({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
