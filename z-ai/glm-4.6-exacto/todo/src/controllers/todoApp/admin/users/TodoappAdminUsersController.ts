import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchTodoAppAdminUsers } from "../../../../providers/patchTodoAppAdminUsers";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getTodoAppAdminUsersUserId } from "../../../../providers/getTodoAppAdminUsersUserId";

import { IPageITodoAppUser } from "../../../../api/structures/IPageITodoAppUser";
import { ITodoAppUser } from "../../../../api/structures/ITodoAppUser";

@Controller("/todoApp/admin/users")
export class TodoappAdminUsersController {
  /**
   * Paginated search and retrieval of user accounts for admin oversight
   * (todo_app_users).
   *
   * Retrieve a paginated and filterable list of user accounts for
   * administrative purposes.
   *
   * This operation provides search and pagination over the user base, including
   * advanced filter capabilities such as partial matching of email addresses,
   * filtering by account status, and sorting by registration time or last
   * activity. It enables system administrators to monitor, audit, and manage
   * user accounts efficiently.
   *
   * Security considerations restrict access to users with administrative
   * privileges. Sensitive user information, such as password hashes or
   * authentication tokens, is never exposed in the API response. Users returned
   * in the result will include summary information relevant for administrative
   * review and bulk management.
   *
   * The operation integrates with the todo_app_users table in the Prisma schema
   * and enforces all associated field validation and unique constraints. Errors
   * are reported with clear causes, such as invalid search parameters or
   * excessive page sizes. Related operations include retrieving individual user
   * account details and managing account status changes.
   *
   * @param connection
   * @param body Search and filter criteria for retrieving a paginated list of
   *   user accounts, including pagination options, text search, and account
   *   status filters.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: ITodoAppUser.IRequest,
  ): Promise<IPageITodoAppUser.ISummary> {
    try {
      return await patchTodoAppAdminUsers({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information for a user account by userId
   * (todo_app_users).
   *
   * Fetch complete details for a specific user account by its unique identifier
   * for administrative purposes.
   *
   * This operation validates the provided userId and returns the associated
   * user's profile, status, registration information, and activity metadata as
   * modeled in the todo_app_users Prisma table. It does not return sensitive
   * authentication data, such as password hashes or refresh tokens. The
   * operation is intended for administrative support, such as reviewing a
   * user's status or troubleshooting account-specific issues.
   *
   * Only administrators are permitted to use this endpoint, guaranteeing that
   * detailed personal data is only accessible to authorized personnel. Errors
   * are explicitly reported for nonexistent userIds or unauthorized access
   * attempts. It is related to the bulk search operation for users and can be
   * used together for administration workflows.
   *
   * @param connection
   * @param userId Unique identifier of the target user account.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":userId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppUser> {
    try {
      return await getTodoAppAdminUsersUserId({
        admin,
        userId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
