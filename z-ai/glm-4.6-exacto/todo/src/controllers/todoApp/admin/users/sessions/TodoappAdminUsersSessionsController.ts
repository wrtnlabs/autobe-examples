import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchTodoAppAdminUsersUserIdSessions } from "../../../../../providers/patchTodoAppAdminUsersUserIdSessions";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getTodoAppAdminUsersUserIdSessionsSessionId } from "../../../../../providers/getTodoAppAdminUsersUserIdSessionsSessionId";
import { deleteTodoAppAdminUsersUserIdSessionsSessionId } from "../../../../../providers/deleteTodoAppAdminUsersUserIdSessionsSessionId";

import { IPageITodoAppUserSession } from "../../../../../api/structures/IPageITodoAppUserSession";
import { ITodoAppUserSession } from "../../../../../api/structures/ITodoAppUserSession";

@Controller("/todoApp/admin/users/:userId/sessions")
export class TodoappAdminUsersSessionsController {
  /**
   * Retrieve a paginated and filterable list of all sessions linked to a
   * specific user's account for administrative security audits and user
   * activity tracing.
   *
   * This endpoint allows system administrators to review every login session a
   * user has created, both active and expired. It is essential for tracking
   * suspicious behaviors, supporting regulatory compliance, and facilitating
   * user management requests such as forced logout or account review. Sessions
   * are returned with precise attributes, including creation time, expiration,
   * IP, and sign-in sources.
   *
   * Access to this operation is restricted to actors with 'admin' authority to
   * guarantee privacy and compliance with strict account separation rules. The
   * operation references the todo_app_user_sessions subsidiary table,
   * leveraging its relationship with todo_app_users. Admins can employ advanced
   * filtering, ordering, and pagination to efficiently locate relevant
   * sessions. Requests that reference nonexistent users will return an
   * appropriate error message, and requests for session data are always fully
   * audited.
   *
   * @param connection
   * @param userId Unique identifier of the target user whose sessions are being
   *   listed. Must correspond to a valid todo_app_users.id (UUID).
   * @param body Filtering, pagination, and advanced query parameters for
   *   searching user session records. Structured to
   *   ITodoAppUserSession.IRequest shape.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoAppUserSession.IRequest,
  ): Promise<IPageITodoAppUserSession.ISummary> {
    try {
      return await patchTodoAppAdminUsersUserIdSessions({
        admin,
        userId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve the full details of a specific session for a user to support
   * targeted administrative forensics and investigation workflows.
   *
   * System administrators can use this endpoint to examine every attribute of a
   * selected login session, understand session context, evaluate historical
   * authentication events, and trace security-relevant activity. Only sessions
   * belonging to the given userId will be accessible.
   *
   * This operation is strictly limited to admins, ensuring strict privacy and
   * access controls. If the userId or sessionId do not exist or are not
   * associated, an appropriate error response is provided. The operation
   * interacts with todo_app_users for user context and todo_app_user_sessions
   * for session data. All access to this endpoint is recorded for audit and
   * compliance.
   *
   * @param connection
   * @param userId Unique identifier of the user owning the session. Must
   *   correspond to a valid todo_app_users.id (UUID).
   * @param sessionId Unique identifier of the session to retrieve. Must
   *   correspond to a valid todo_app_user_sessions.id (UUID) associated with
   *   the user.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppUserSession> {
    try {
      return await getTodoAppAdminUsersUserIdSessionsSessionId({
        admin,
        userId,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a user session for compliance, security response, or user account
   * management in the Todo List application.
   *
   * This API operation grants administrators the ability to forcibly terminate
   * any user's session for account security, regulatory compliance, or support
   * operations. Session removal ensures that the user's authentication state is
   * revoked and the session can no longer be used for any operation in the
   * system.
   *
   * The operation references the unique user account and the session ID,
   * strictly enforcing that only administrators can invoke this capability. A
   * successful operation ensures the session is either deleted from the
   * database or marked as expired depending on the implementation of session
   * lifecycle rules.
   *
   * This endpoint is critical for complying with user account deletion
   * requests, fraud mitigation, and regulatory requirements for audit logging.
   * All actions are logged with admin ID and timestamp for future forensics and
   * auditability. Only users with admin role may invoke this operation;
   * attempts by non-admins are denied with a clear error.
   *
   * @param connection
   * @param userId Unique identifier of the target user. (UUID format, global
   *   scope)
   * @param sessionId Unique identifier of the session to be deleted (UUID
   *   format, scoped per user)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":sessionId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoAppAdminUsersUserIdSessionsSessionId({
        admin,
        userId,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
