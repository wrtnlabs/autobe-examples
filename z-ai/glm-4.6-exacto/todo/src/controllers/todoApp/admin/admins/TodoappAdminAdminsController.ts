import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchTodoAppAdminAdmins } from "../../../../providers/patchTodoAppAdminAdmins";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getTodoAppAdminAdminsAdminId } from "../../../../providers/getTodoAppAdminAdminsAdminId";
import { putTodoAppAdminAdminsAdminId } from "../../../../providers/putTodoAppAdminAdminsAdminId";
import { deleteTodoAppAdminAdminsAdminId } from "../../../../providers/deleteTodoAppAdminAdminsAdminId";

import { IPageITodoAppAdmin } from "../../../../api/structures/IPageITodoAppAdmin";
import { ITodoAppAdmin } from "../../../../api/structures/ITodoAppAdmin";

@Controller("/todoApp/admin/admins")
export class TodoappAdminAdminsController {
  /**
   * Search and retrieve a filtered, paginated list of todo_app_admins (admin
   * listing).
   *
   * List all administrator accounts with advanced search, filtering, and
   * pagination for privileged access review.
   *
   * Only users with admin privilege may invoke this operation. The endpoint
   * returns key non-sensitive admin details (such as email, creation time),
   * omitting password or sensitive security fields. Filtering and sorting can
   * be applied to streamline access reviews, manage admin accounts, or conduct
   * compliance checks. Rate limiting may be enforced due to the sensitive
   * nature of the data returned.
   *
   * Typical use cases include managing admin privileges, reviewing
   * administrator activity, or prepping for policy audits. All activities using
   * this API are logged for audit trail and regulatory investigation. Non-admin
   * users cannot utilize this operation; attempts will result in access denied
   * errors.
   *
   * @param connection
   * @param body Pagination and filter input for admin account searching (e.g.,
   *   email, date created, etc.)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: ITodoAppAdmin.IRequest,
  ): Promise<IPageITodoAppAdmin.ISummary> {
    try {
      return await patchTodoAppAdminAdmins({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Fetch complete detail for a specific administrator account (todo_app_admins
   * table) by ID.
   *
   * Retrieve detailed information for a specific administrator account in the
   * Todo application. The operation is performed by providing the unique
   * administrator ID (UUID) as the path parameter. It returns all persisted
   * data for the admin, including identifying fields, security credentials
   * (hashed only), and internal status timestamps (creation, update, optional
   * soft deletion).
   *
   * Access to this endpoint is strictly limited to privileged administrative
   * users managing the Todo application. The endpoint enables oversight for
   * actions like account review, auditing changes, and compliance verification.
   * Sensitive data such as password_hash is included only for system integrity
   * and should never be exposed to non-administrative roles. Logging and
   * auditing of access are recommended for all calls.
   *
   * If the specified administrator does not exist or has been soft deleted, a
   * suitable not found error should be returned. Data fields and types are
   * strictly defined based on the Prisma schema for todo_app_admins,
   * maintaining consistency with the underlying database definition.
   *
   * @param connection
   * @param adminId Unique identifier (UUID) for the target administrator
   *   account. Corresponds to the 'id' field of the todo_app_admins table.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":adminId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppAdmin> {
    try {
      return await getTodoAppAdminAdminsAdminId({
        admin,
        adminId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update all updatable fields of a specific administrator account
   * (todo_app_admins table) by ID.
   *
   * Update all applicable fields of an existing administrator account. This
   * operation requires specifying the target admin by UUID ID path parameter
   * and providing the new data in the request body. Updatable fields include
   * email and password_hash for credential rotation, as well as management of
   * soft delete status for compliance or admin deactivation events. Protected
   * fields such as id and created_at cannot be changed and are excluded from
   * the request DTO schema.
   *
   * Only users with elevated administrative privileges may perform this update.
   * Rigorous validation is performed on email uniqueness and all business logic
   * enforced by the Prisma model. Attempts to update to an already existing
   * email or to manipulate system-reserved fields should be rejected. All
   * modifications are logged for audit purposes, and security-sensitive changes
   * such as password resets must be recorded in application logs.
   *
   * If the specified admin does not exist or is already soft deleted, the
   * operation should return the appropriate error response. The returned
   * administrator object reflects the successful update as persisted in the
   * underlying database, consistent with the ITodoAppAdmin DTO contract.
   *
   * @param connection
   * @param adminId Unique identifier (UUID) for the target administrator
   *   account. Corresponds to the 'id' field of the todo_app_admins table.
   * @param body All updatable administrator fields for updating the specified
   *   admin. Follows ITodoAppAdmin.IUpdate DTO, omitting system-controlled or
   *   immutable fields.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":adminId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoAppAdmin.IUpdate,
  ): Promise<ITodoAppAdmin> {
    try {
      return await putTodoAppAdminAdminsAdminId({
        admin,
        adminId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Soft-delete (mark as removed) an administrator account using
   * todo_app_admins table.
   *
   * Permanently remove an administrator account from the system using its
   * unique identifier. This operation marks the todo_app_admins record as
   * deleted by updating the deleted_at column, rather than physically removing
   * the row, in order to preserve compliance with audit requirements and enable
   * potential future data recovery.
   *
   * The request requires the unique adminId as a path parameter and ensures
   * that only system-level actors with sufficient privilege may invoke the
   * operation. Audit logging is performed at the service level for forensics
   * and tracking destructive administrative actions.
   *
   * All active admin sessions associated with the account are revoked or
   * expired by system process, and future authentication requests for the
   * soft-deleted account will be denied. Other business operations reliant on
   * the existence of the admin record must properly exclude soft-deleted
   * entries using the deleted_at filter in their queries. Related endpoints
   * include admin session revocation and administrative account management
   * APIs.
   *
   * @param connection
   * @param adminId Unique identifier of the administrator account in UUID
   *   format.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":adminId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoAppAdminAdminsAdminId({
        admin,
        adminId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
