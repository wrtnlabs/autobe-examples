import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchTodoAppAdminAdminsAdminIdSessions } from "../../../../../providers/patchTodoAppAdminAdminsAdminIdSessions";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getTodoAppAdminAdminsAdminIdSessionsSessionId } from "../../../../../providers/getTodoAppAdminAdminsAdminIdSessionsSessionId";
import { deleteTodoAppAdminAdminsAdminIdSessionsSessionId } from "../../../../../providers/deleteTodoAppAdminAdminsAdminIdSessionsSessionId";

import { IPageITodoAppAdminSession } from "../../../../../api/structures/IPageITodoAppAdminSession";
import { ITodoAppAdminSession } from "../../../../../api/structures/ITodoAppAdminSession";

@Controller("/todoApp/admin/admins/:adminId/sessions")
export class TodoappAdminAdminsSessionsController {
  /**
   * Retrieve the list of authentication and usage sessions associated with a
   * target administrator. The PATCH method allows complex querying of the
   * todo_app_admin_sessions table, filtering session records by administrator,
   * session start and expired timestamps, IP address, or other
   * business-relevant fields.
   *
   * This operation is intended to support administrative review, security
   * audit, and session lifecycle investigations. Session data must only be
   * exposed to actors with sufficient privileges ('admin' role), and response
   * data must reflect the session's associated administrator.
   *
   * Query options support advanced filtering, sorting, and paging to aid
   * compliance reporting and efficient data access. Returned data is paginated
   * and contains summary information for each session. Related endpoints
   * include session detail retrieval and broader administrative account
   * management APIs.
   *
   * @param connection
   * @param adminId Unique identifier of the administrator whose sessions are
   *   being listed (UUID format).
   * @param body Query and search options for administrator session retrieval,
   *   including pagination and filtering parameters.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoAppAdminSession.IRequest,
  ): Promise<IPageITodoAppAdminSession.ISummary> {
    try {
      return await patchTodoAppAdminAdminsAdminIdSessions({
        admin,
        adminId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Fetch a specific administrator session record from the system, allowing
   * privileged users to view all the recorded properties related to a given
   * session, including login metadata, IP context, timestamps, and navigation
   * context. This facilitates detailed security audits and enables review of
   * administrative activities for compliance oversight.
   *
   * Only users with administrative actor authority are allowed to perform this
   * operation. The session record is always tied to a valid admin, with
   * explicit linkage via the `adminId` path parameter. The operation references
   * all available session fields, such as IP, referrer, and creation/expiration
   * timestamps, and incorporates precise access boundaries through the
   * `todo_app_admin_sessions` schema design.
   *
   * Strict authorization measures are in place, so only `admin` actors are
   * permitted. The response provides full detail on the session in question for
   * security review and support diagnostics.
   *
   * @param connection
   * @param adminId Unique identifier of the administrator (referencing
   *   todo_app_admins.id).
   * @param sessionId Unique identifier of the administrator session record
   *   (todo_app_admin_sessions.id).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppAdminSession> {
    try {
      return await getTodoAppAdminAdminsAdminIdSessionsSessionId({
        admin,
        adminId,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Erase a specific administrator session, ensuring permanent removal from the
   * system database. This operation directly deletes the session identified by
   * the provided `sessionId` within the scope of the given admin. Actions are
   * strictly limited to actors with full administrative privileges, and every
   * deletion is directly linked with the subject admin for clear auditability.
   *
   * Authorization logic restricts execution to legitimate `admin` actors. The
   * endpoint is designed to facilitate audit-cleanup scenarios, post-incident
   * response, or compliance-driven artifact removal, with full reference to the
   * session record's origin and deletion event in accordance with the
   * `todo_app_admin_sessions` schema specification.
   *
   * No soft delete is used: the record is completely expunged, and any attempt
   * to access it after erasure will fail. Security boundary and privilege
   * checks are enforced rigorously in controller and provider layers.
   *
   * @param connection
   * @param adminId Unique identifier of the administrator (referencing
   *   todo_app_admins.id).
   * @param sessionId Unique identifier of the administrator session record
   *   (todo_app_admin_sessions.id).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":sessionId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoAppAdminAdminsAdminIdSessionsSessionId({
        admin,
        adminId,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
