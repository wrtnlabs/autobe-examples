import { Controller, Ip } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthAdminJoin } from "../../../providers/postAuthAdminJoin";
import { postAuthAdminLogin } from "../../../providers/postAuthAdminLogin";
import { postAuthAdminRefresh } from "../../../providers/postAuthAdminRefresh";

import { ITodoAppAdmin } from "../../../api/structures/ITodoAppAdmin";

@Controller("/auth/admin")
export class AuthAdminController {
  /**
   * Register a new administrator in the todo_app_admins table and issue a new
   * login session.
   *
   * This endpoint supports secure administrative onboarding by registering a
   * new admin record in the todo_app_admins Prisma table.
   *
   * The input requires a unique email and password, both strictly validated per
   * the table's constraints. The email must be unique among all admins,
   * enforced by a unique index, while the password is processed and stored as a
   * cryptographically secure password_hash. Creation and update timestamps are
   * automatically managed for auditability.
   *
   * Admin creation flows integrate with authentication event tracking in the
   * todo_app_admin_sessions table, supporting compliance and non-repudiation.
   * All issued JWT tokens contain the admin's userId and role for downstream
   * authorization gates. Registered admins may immediately use all admin-level
   * application operations upon joining.
   *
   * Security within this flow is critical: failed attempts for duplicate emails
   * or password policy violations result in error responses without leaking
   * details about the existence of admin accounts.
   *
   * The operation forms part of the foundational authentication workflow for
   * privileged Todo application access, in conjunction with admin login and
   * session management endpoints.
   *
   * @param connection
   * @param body Administrative registration requiring a unique email and
   *   password, validated to business and schema rules.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoAppAdmin.IJoin,
  ): Promise<ITodoAppAdmin.IAuthorized> {
    try {
      return await postAuthAdminJoin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate an admin in todo_app_admins table and issue access and refresh
   * tokens.
   *
   * This endpoint allows administrative users to sign in securely by validating
   * their email and password credentials against the todo_app_admins Prisma
   * table.
   *
   * Authentication requires the unique email (restricted by a unique index
   * constraint) and a password matching the stored password_hash after
   * cryptographic verification. Login attempts are denied if the admin account
   * has been deactivated or soft-deleted, enforcing authorization checks on the
   * deleted_at field. All successful login attempts result in new JWT access
   * and refresh tokens being generated, and a corresponding session is
   * persisted in todo_app_admin_sessions.
   *
   * This flow provides the baseline for persistent admin access throughout the
   * Todo application, underpinning all privileged maintenance and management
   * functions. Security is enforced per requirements including error
   * concealment and audit event generation.
   *
   * Invalid login attempts are indistinguishable in failure response,
   * preventing information leaks about registered accounts, and failed sessions
   * are logged for security and compliance audits.
   *
   * This operation supports session lifecycle management by coordinating with
   * refresh and logout operations and may be extended for multifactor
   * authentication in the future.
   *
   * @param connection
   * @param body Credentials for administrative login: unique email address and
   *   associated password.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoAppAdmin.ILogin,
  ): Promise<ITodoAppAdmin.IAuthorized> {
    try {
      return await postAuthAdminLogin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Renew access and refresh tokens for authenticated admin in todo_app_admins.
   *
   * This endpoint allows an authenticated admin to renew their session using a
   * valid refresh token. It revalidates the token against admin record status
   * in todo_app_admins, including deleted_at and security flags, and generates
   * new JWT tokens for continued privileged application access.
   *
   * The endpoint supports stateless authentication with strict session duration
   * controls, and it checks for admin account integrity before permitting
   * refresh. The session entry in todo_app_admin_sessions is updated as part of
   * this operation, and all session activity is auditable for compliance.
   *
   * Any attempt to use an invalidated or expired refresh token, or where the
   * admin has been deactivated or soft-deleted, results in an access denied
   * response.
   *
   * This operation fits tightly with the login and join endpoints, together
   * ensuring secure and controllable admin access lifecycles across the Todo
   * application's privileged features.
   *
   * Security is paramount: responses never leak any account status or system
   * details, providing only generic renewal failures where necessary.
   *
   * @param connection
   * @param body Refresh token payload for renewing admin session authentication
   *   tokens.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: ITodoAppAdmin.IRefresh,
  ): Promise<ITodoAppAdmin.IAuthorized> {
    try {
      return await postAuthAdminRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
