import { Controller, Ip } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthUserJoin } from "../../../providers/postAuthUserJoin";
import { postAuthUserLogin } from "../../../providers/postAuthUserLogin";
import { postAuthUserRefresh } from "../../../providers/postAuthUserRefresh";

import { ITodoAppUser } from "../../../api/structures/ITodoAppUser";

@Controller("/auth/user")
export class AuthUserController {
  /**
   * Registers a new todo_app_users account using unique email and password
   * hash, issuing JWT tokens upon success.
   *
   * This endpoint allows the creation of a new user account in the
   * todo_app_users table, capturing a unique email and securely hashed password
   * as required by schema definitions.
   *
   * It accepts an email (unique across all accounts, per unique index) and a
   * password, which is stored as a secure hash in password_hash—never in
   * plaintext, in compliance with security standards detailed in the prisma
   * schema. Upon account creation, system timestamps are recorded in created_at
   * and updated_at for compliance and tracking.
   *
   * This operation is public: anyone may register as a user but users must not
   * duplicate existing emails. If an email already exists, an error is returned
   * as enforced by the unique index constraint in the database model.
   *
   * Account creation also provisionally grants access, as JWT tokens are issued
   * immediately after successful registration, following the business rules
   * defined in both requirements and schema. The process does not permit
   * creation of admin accounts; those are managed in a separate table by design
   * to preserve role separation.
   *
   * This endpoint complements other authentication endpoints such as login and
   * refresh, ensuring consistent entry into the authentication workflow for the
   * user actor. It handles error and validation scenarios according to the
   * underlying schema and operational requirements.
   *
   * @param connection
   * @param body Information required to create a new user account: unique email
   *   address and password (in plain text, to be securely hashed before
   *   storage).
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoAppUser.IJoin,
  ): Promise<ITodoAppUser.IAuthorized> {
    try {
      return await postAuthUserJoin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticates a member (todo_app_users) and issues JWT tokens upon correct
   * credentials.
   *
   * This endpoint provides login functionality for member users in the
   * todo_app_users table. Users must supply their registered email and
   * password; the submitted password is hashed and compared securely with the
   * stored password_hash value for account validation.
   *
   * If the provided credentials are correct and the user exists (row found by
   * unique email), JWT tokens are issued for session establishment, granting
   * access to protected resources as specified by requirements. Invalid
   * credentials or a non-existent email results in an error, with no account
   * details returned, aligning with security best practices described in the
   * schema.
   *
   * This operation does not accept admin credentials—those accounts are handled
   * in a separate authentication flow per schema design.
   *
   * Timing and event information (e.g., created_at/updated_at fields) are
   * handled in accordance with the model; password_hash is never exposed
   * outside authentication context.
   *
   * This endpoint works in concert with the join and refresh flows, together
   * forming the entire authentication lifecycle for user actors.
   *
   * @param connection
   * @param body Login credentials: user email and password (plain text, to be
   *   securely hashed for comparison).
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoAppUser.ILogin,
  ): Promise<ITodoAppUser.IAuthorized> {
    try {
      return await postAuthUserLogin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Renews JWT authentication tokens for an existing todo_app_users account
   * using a valid refresh token.
   *
   * This endpoint allows member users to renew (refresh) their JWT
   * authentication tokens, supporting persistent secure access for
   * todo_app_users. The user supplies a valid refresh token (granted during
   * previous login or registration), which is validated against the session
   * context.
   *
   * A successfully validated token results in new JWT tokens, containing user
   * identification referencing the todo_app_users database schema (id field and
   * email). If the token is invalid, expired, or associated with a user account
   * marked with a deleted_at timestamp, the request fails per schema-based
   * business rules.
   *
   * This operation is part of the authentication lifecycle and works in
   * coordination with the join and login endpoints. It relies on proper token
   * management and storage at the client side to function securely.
   *
   * Session context and event tracking may be managed in subsidiary tables for
   * audit trails, but this endpoint focuses directly on token renewal for an
   * active user.
   *
   * It ensures that no cross-actor token refresh is possible by confirming the
   * existence and current status of the related todo_app_users record. Error
   * responses strictly follow business logic and schema validation.
   *
   * @param connection
   * @param body Valid refresh token issued during prior authentication
   *   (registration or login).
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: ITodoAppUser.IRefresh,
  ): Promise<ITodoAppUser.IAuthorized> {
    try {
      return await postAuthUserRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
