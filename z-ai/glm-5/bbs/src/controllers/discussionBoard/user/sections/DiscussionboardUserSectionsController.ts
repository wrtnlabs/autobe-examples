import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IDiscussionBoardSection } from "../../../../api/structures/IDiscussionBoardSection";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { deleteDiscussionBoardUserSectionsSectionId } from "../../../../providers/deleteDiscussionBoardUserSectionsSectionId";
import { postDiscussionBoardUserSections } from "../../../../providers/postDiscussionBoardUserSections";
import { putDiscussionBoardUserSectionsSectionId } from "../../../../providers/putDiscussionBoardUserSectionsSectionId";

@Controller("/discussionBoard/user/sections")
export class DiscussionboardUserSectionsController {
  /**
   * Create a new discussion board section for organizing articles by topic categories.
   *
   * This operation allows administrators to create new sections such as Politics, Economy, or Current Affairs. Each section serves as a primary organizational structure for articles, enabling topic-based content discovery.
   *
   * The section name must be unique across all sections in the system. If a section with the same name already exists, the operation will fail with a validation error.
   *
   * This operation requires administrator or super administrator privileges. Regular members will receive an authorization error when attempting to create sections.
   *
   * Upon successful creation, the system automatically records the creating administrator's ID and the current timestamp for audit purposes. The section becomes immediately available for article association and user browsing.
   *
   * @param connection
   * @param body Section creation data including unique name and description
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Implementation steps:
   *
   * 1. Validate user authentication and administrator privileges (check user.permission_level is ADMINISTRATOR or SUPER_ADMINISTRATOR)
   *
   * 2. Validate request body:
   *    - name: required, string, 2-100 characters, trimmed, not whitespace-only
   *    - description: required, string, 10-500 characters, trimmed, not whitespace-only
   *
   * 3. Check name uniqueness by querying discussion_board_sections where name equals the provided name and deleted_at is null
   *
   * 4. If duplicate name exists, return 409 Conflict error with message indicating name conflict
   *
   * 5. Create new section record:
   *    - Generate UUID for id
   *    - Set creator_id to authenticated user's id
   *    - Set modifier_id to null (no modification yet)
   *    - Set name and description from request
   *    - Set created_at and updated_at to current timestamp
   *    - Set deleted_at to null
   *
   * 6. Return the created section with all fields
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: IDiscussionBoardSection.ICreate,
  ): Promise<IDiscussionBoardSection> {
    try {
      return await postDiscussionBoardUserSections({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing discussion board section's name and description.
   *
   * This operation allows administrators to modify section properties including the section name and description. The section name must be unique across all sections; attempting to use a name that already exists will result in a validation error. Only administrators have permission to perform this operation.
   *
   * Upon successful update, the system records the administrator who made the modification and updates the timestamp accordingly. All existing articles within the section remain associated with the section under its updated properties.
   *
   * Related operations:
   * - POST /sections: Create a new section
   * - DELETE /sections/{sectionId}: Delete a section
   * - GET /sections: List all sections
   *
   * @param connection
   * @param sectionId Unique identifier of the section to update
   * @param body Section update data containing new name and description
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Implementation steps:
   *
   * 1. Validate user is authenticated and has ADMINISTRATOR or SUPER_ADMINISTRATOR permission level
   * 2. Query discussion_board_sections table to find the section by id
   * 3. Return 404 error if section not found or is soft-deleted (deleted_at is not null)
   * 4. Validate request body:
   *    - name: required, 2-100 characters, trimmed, unique across all sections (excluding current section)
   *    - description: required, 10-500 characters, trimmed
   * 5. If new name conflicts with another section, return 400 error with message 'A section with this name already exists.'
   * 6. Update the section record:
   *    - Set name to new value
   *    - Set description to new value
   *    - Set modifier_id to current user's id
   *    - Set updated_at to current timestamp
   * 7. Return the updated section with all fields including related creator and modifier user references
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":sectionId")
  public async update(
    @UserAuth()
    user: UserPayload,
    @TypedParam("sectionId")
    sectionId: string,
    @TypedBody()
    body: IDiscussionBoardSection.IUpdate,
  ): Promise<IDiscussionBoardSection> {
    try {
      return await putDiscussionBoardUserSectionsSectionId({
        user,
        sectionId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Soft deletes a discussion board section, making it and all its content inaccessible to users.
   *
   * This administrator-only operation marks a section as deleted by setting its deleted_at timestamp. All articles within the section are also soft-deleted, along with their associated comments, file attachments, image attachments, and tag associations becoming hidden from normal browsing.
   *
   * The operation enforces strict authorization requirements, allowing only users with administrator or super administrator permissions to execute. Non-administrators will receive an authorization error response.
   *
   * After soft deletion:
   * - The section and all its articles remain in the database for audit trail preservation
   * - Content becomes invisible to all users during normal browsing
   * - Banned users' content visibility rules may still apply
   * - Physical files remain in storage until cleaned up by an asynchronous process
   *
   * Business rules enforced:
   * - Administrator permission required (ADMINISTRATOR or SUPER_ADMINISTRATOR level)
   * - Section must exist and not already be deleted
   * - All articles in the section are soft-deleted (deleted_at set)
   * - Related content (comments, attachments, tags) remains linked but becomes hidden
   *
   * @param connection
   * @param sectionId Unique identifier of the section to delete (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Implementation workflow for section deletion:
   *
   * 1. **Authorization Check**: Verify the authenticated user has ADMINISTRATOR or SUPER_ADMINISTRATOR permission level. Return 403 Forbidden if insufficient permissions.
   *
   * 2. **Section Lookup**: Query discussion_board_sections table by id (UUID) where deleted_at IS NULL. Return 404 Not Found if section does not exist or is already deleted.
   *
   * 3. **Cascade Article Soft-Delete**: Update all discussion_board_articles records where discussion_board_section_id matches the target section, setting their deleted_at to current timestamp.
   *
   * 4. **Section Soft-Delete**: Set the section's deleted_at to current timestamp.
   *
   * 5. **Response**: Return the soft-deleted section object with id, name, description, creator_id, created_at, updated_at, and deleted_at fields.
   *
   * Transaction scope: All updates must be atomic within a single database transaction to ensure consistency.
   *
   * Note: Physical file deletion (attachments) may be handled asynchronously by a cleanup process after the transaction completes.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":sectionId")
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("sectionId")
    sectionId: string,
  ): Promise<void> {
    try {
      return await deleteDiscussionBoardUserSectionsSectionId({
        user,
        sectionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
