import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IDiscussionBoardComment } from "../../../../../api/structures/IDiscussionBoardComment";
import { UserAuth } from "../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../decorators/payload/UserPayload";
import { deleteDiscussionBoardUserArticlesArticleIdCommentsCommentId } from "../../../../../providers/deleteDiscussionBoardUserArticlesArticleIdCommentsCommentId";
import { postDiscussionBoardUserArticlesArticleIdComments } from "../../../../../providers/postDiscussionBoardUserArticlesArticleIdComments";
import { putDiscussionBoardUserArticlesArticleIdCommentsCommentId } from "../../../../../providers/putDiscussionBoardUserArticlesArticleIdCommentsCommentId";

@Controller("/discussionBoard/user/articles/:articleId/comments")
export class DiscussionboardUserArticlesCommentsController {
  /**
   * Create a new comment on an article.
   *
   * This endpoint allows authenticated users to post comments on articles within the discussion board. Comments are stored in the `discussion_board_comments` table as single-level attachments to articles, supporting direct discussions without nested replies. Each comment references the parent `discussion_board_articles` record via `discussion_board_article_id` and the author's `discussion_board_users` record via `discussion_board_user_id`.
   *
   * The comment `content` field must contain meaningful text between 1 and 10,000 characters after whitespace trimming, as defined in the comment system requirements. The system automatically generates a sequential `citizen_id` from `discussion_board_comment_citizens` for human-readable identification.
   *
   * Authentication is required for this operation. Unauthenticated requests will be rejected with an authentication error. Banned users (where `is_banned` is true in `discussion_board_users`) are prohibited from creating comments and will receive a 403 Forbidden error with code `ACCOUNT_BANNED`.
   *
   * The target article must exist and not be soft-deleted (`deleted_at` is null). If the specified articleId does not correspond to an existing article, the operation will fail with a 404 Not Found error.
   *
   * Upon successful creation, the comment is immediately visible in the article's comment section, sorted chronologically by `created_at` with oldest comments first. The response includes the newly generated comment with its unique `id`, sequential `citizen_id`, and creation timestamp.
   *
   * @param connection
   * @param articleId Unique identifier of the article to which the comment will be attached
   * @param body Comment content and creation details
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Implementation steps for comment creation:
   *
   * 1. **Authentication Validation**: Verify the request includes valid authentication credentials. Extract the authenticated user's ID from the JWT token.
   *
   * 2. **Ban Status Check**: Query discussion_board_users table to verify the authenticated user is not currently banned (check for active ban records in discussion_board_bans where user_id matches and unban does not exist). Return 403 Forbidden if banned.
   *
   * 3. **Article Existence Check**: Query discussion_board_articles table to verify the articleId exists and is not soft-deleted (deleted_at is null). Return 404 Not Found if article does not exist.
   *
   * 4. **Content Validation**: Validate comment content meets requirements:
   *    - Trim leading/trailing whitespace
   *    - Ensure at least 1 non-whitespace character remains
   *    - Ensure content does not exceed 10,000 characters
   *    - Return 400 Bad Request with validation errors if constraints violated
   *
   * 5. **Citizen ID Generation**: Create a new record in discussion_board_comment_citizens table to obtain a sequential citizen_id for human-readable comment identification.
   *
   * 6. **Comment Creation**: Insert new record into discussion_board_comments table with:
   *    - id: Generate new UUID
   *    - citizen_id: UUID from step 5
   *    - discussion_board_article_id: From path parameter
   *    - discussion_board_user_id: From authenticated user context
   *    - content: Trimmed comment text
   *    - created_at: Current timestamp
   *    - updated_at: null (never edited)
   *    - deleted_at: null (active comment)
   *
   * 7. **Response**: Return the created comment entity with all fields populated.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @UserAuth()
    user: UserPayload,
    @TypedParam("articleId")
    articleId: string,
    @TypedBody()
    body: IDiscussionBoardComment.ICreate,
  ): Promise<IDiscussionBoardComment> {
    try {
      return await postDiscussionBoardUserArticlesArticleIdComments({
        user,
        articleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Updates the content of an existing comment.
   *
   * This endpoint allows authenticated users to edit their own comments. Only the comment author has permission to modify a comment; administrators cannot edit user comments regardless of their role. The new content must adhere to the same validation rules as comment creation: minimum 1 non-whitespace character and maximum 10,000 characters. Leading and trailing whitespace is automatically trimmed before storage.
   *
   * Upon successful update, the comment's updated_at timestamp is set to the current time while the original created_at timestamp is preserved. An "edited" indicator will be displayed on the comment when viewed. There is no time limitation on editing; users may edit their comments at any time after posting.
   *
   * The operation validates that:
   * - The user is authenticated
   * - The article exists and has not been deleted
   * - The comment exists and has not been deleted
   * - The user is the author of the comment
   *
   * If any validation fails, an appropriate error response is returned. The system does not maintain edit history; each update overwrites the previous content.
   *
   * @param connection
   * @param articleId Unique identifier of the article that contains the comment to be updated
   * @param commentId Unique identifier of the comment to update. Only the comment author can perform this operation.
   * @param body Updated comment content. Must contain between 1 and 10,000 characters (whitespace trimmed).
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Implementation steps for updating a comment:
   *
   * 1. Authentication check: Verify JWT token, extract user ID
   * 2. Authorization check: Query discussion_board_comments by commentId, verify discussion_board_user_id matches authenticated user ID
   * 3. Validate comment exists and deleted_at is null
   * 4. Validate article exists via discussion_board_article_id and article has not been deleted
   * 5. Validate request body: content must have at least 1 non-whitespace character and maximum 10,000 characters
   * 6. Trim leading/trailing whitespace from content
   * 7. Update comment record:
   *    - Set content to new trimmed value
   *    - Set updated_at to current timestamp
   *    - Preserve created_at and all other fields
   * 8. Return updated comment entity with author relation loaded
   *
   * Error handling:
   * - 401 Unauthorized if not authenticated
   * - 403 Forbidden if user is not the comment author
   * - 404 Not Found if article or comment doesn't exist
   * - 400 Bad Request if content validation fails
   *
   * Database query: UPDATE discussion_board_comments SET content = ?, updated_at = NOW() WHERE id = ? AND deleted_at IS NULL
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":commentId")
  public async update(
    @UserAuth()
    user: UserPayload,
    @TypedParam("articleId")
    articleId: string,
    @TypedParam("commentId")
    commentId: string,
    @TypedBody()
    body: IDiscussionBoardComment.IUpdate,
  ): Promise<IDiscussionBoardComment> {
    try {
      return await putDiscussionBoardUserArticlesArticleIdCommentsCommentId({
        user,
        articleId,
        commentId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Soft deletes a comment from an article's discussion thread.
   *
   * This operation allows authorized users to delete comments from articles. There are two types of authorized deletors: the comment author who wishes to remove their own comment, and administrators performing content moderation. When a comment is deleted, the system marks it as deleted via the deleted_at timestamp field rather than permanently removing the record from the database.
   *
   * The soft delete approach preserves the comment record for audit purposes while excluding it from public display. Once deleted, the comment content is no longer visible to any user, including administrators. The article's comment count is automatically updated to reflect the deletion.
   *
   * Authorization is enforced by verifying that the authenticated user is either the comment author (matching discussion_board_user_id) or holds administrator privileges (permission_level of ADMINISTRATOR or SUPER_ADMINISTRATOR). Users who are neither the comment author nor administrators will receive a 403 Forbidden error.
   *
   * The operation validates that both the article (discussion_board_articles.id) and comment (discussion_board_comments.id) exist and are not already deleted. If the article has been soft-deleted, attempting to delete its comments will result in a 404 Not Found error. Similarly, attempting to delete an already-deleted comment returns a 404 Not Found error.
   *
   * @param connection
   * @param articleId Unique identifier of the article containing the comment. Must be a valid UUID referencing an existing, non-deleted article in the discussion_board_articles table.
   * @param commentId Unique identifier of the comment to delete. Must be a valid UUID referencing an existing, non-deleted comment that belongs to the specified article in the discussion_board_comments table.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Implementation steps:
   *
   * 1. **Authentication Check**: Verify the request includes a valid JWT token. Extract the authenticated user's ID from the token.
   *
   * 2. **Parameter Validation**: Validate both path parameters:
   *    - articleId: Must be a valid UUID format
   *    - commentId: Must be a valid UUID format
   *
   * 3. **Article Existence Check**: Query discussion_board_articles table to verify the article exists and is not soft-deleted (deleted_at IS NULL). Return 404 if article not found or deleted.
   *
   * 4. **Comment Existence Check**: Query discussion_board_comments table to verify:
   *    - The comment exists (id = commentId)
   *    - The comment belongs to the specified article (discussion_board_article_id = articleId)
   *    - The comment is not already deleted (deleted_at IS NULL)
   *    Return 404 if comment not found, doesn't belong to the article, or is already deleted.
   *
   * 5. **Authorization Check**: Verify the authenticated user has permission to delete:
   *    - Option A: User is the comment author (discussion_board_user_id matches authenticated user's ID)
   *    - Option B: User has administrator privileges (permission_level = 'ADMINISTRATOR' or 'SUPER_ADMINISTRATOR')
   *    Return 403 Forbidden if neither condition is met.
   *
   * 6. **Soft Delete Execution**: Update the comment record:
   *    - Set deleted_at to current timestamp
   *    - Do NOT modify updated_at (that field tracks content edits, not deletions)
   *
   * 7. **Comment Count Update**: Decrement the article's comment count in any cached/aggregated storage (if applicable). This may be handled by a database trigger or application logic.
   *
   * 8. **Response**: Return 204 No Content (null response body) on successful deletion.
   *
   * Error handling:
   * - 401 Unauthorized: Missing or invalid JWT token
   * - 403 Forbidden: User is not comment author and not an administrator
   * - 404 Not Found: Article or comment not found, or comment already deleted
   * - 500 Internal Server Error: Database or system errors
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":commentId")
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("articleId")
    articleId: string,
    @TypedParam("commentId")
    commentId: string,
  ): Promise<void> {
    try {
      return await deleteDiscussionBoardUserArticlesArticleIdCommentsCommentId({
        user,
        articleId,
        commentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
