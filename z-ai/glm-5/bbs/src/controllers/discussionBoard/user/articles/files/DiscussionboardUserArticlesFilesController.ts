import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IDiscussionBoardArticleFile } from "../../../../../api/structures/IDiscussionBoardArticleFile";
import { UserAuth } from "../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../decorators/payload/UserPayload";
import { deleteDiscussionBoardUserArticlesArticleIdFilesFileId } from "../../../../../providers/deleteDiscussionBoardUserArticlesArticleIdFilesFileId";
import { postDiscussionBoardUserArticlesArticleIdFiles } from "../../../../../providers/postDiscussionBoardUserArticlesArticleIdFiles";

@Controller("/discussionBoard/user/articles/:articleId/files")
export class DiscussionboardUserArticlesFilesController {
  /**
   * Attach a file to an existing article.
   *
   * This operation allows authenticated users to upload and attach files to their articles. Files are stored with their original filename preserved for display purposes, while receiving a unique server-side storage path. The system validates the file against allowed types (PDF, Word documents, Excel spreadsheets, PowerPoint presentations, and archive files) and enforces size limits (10MB per file, 50MB total per article, maximum 10 files per article).
   *
   * Only the article author can attach files to their article. Administrators cannot modify user articles, including adding attachments.
   *
   * The request body contains file metadata including a URI reference to the uploaded file, the original filename for display, file size for quota enforcement, and MIME type for validation and download headers. The response includes the generated unique file ID and all associated metadata.
   *
   * @param connection
   * @param articleId Target article's unique identifier (UUID format)
   * @param body File attachment metadata including URI, filename, size, and MIME type
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Implementation steps:
   * 1. Validate authentication - return 401 if not authenticated
   * 2. Query discussion_board_articles by articleId (UUID)
   * 3. Return 404 if article not found
   * 4. Verify requesting user is the article author - return 403 if not
   * 5. Check user is not banned - return 403 if banned
   * 6. Validate file type against allowed MIME types (PDF, DOC, DOCX, TXT, RTF, XLS, XLSX, CSV, PPT, PPTX, ZIP, RAR, 7Z)
   * 7. Validate file size <= 10MB (10,485,760 bytes)
   * 8. Count existing files for article - reject if >= 10 files
   * 9. Calculate total size including new file - reject if > 50MB total
   * 10. Generate unique storage path for the file
   * 11. Create discussion_board_article_files record with UUID id, article reference, original filename, storage path, file size, MIME type, and timestamp
   * 12. Return created file record with 201 status
   *
   * Database operations:
   * - SELECT article by id from discussion_board_articles
   * - SELECT COUNT(*) from discussion_board_article_files where article_id = articleId
   * - SELECT SUM(file_size) from discussion_board_article_files where article_id = articleId
   * - INSERT into discussion_board_article_files
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @UserAuth()
    user: UserPayload,
    @TypedParam("articleId")
    articleId: string,
    @TypedBody()
    body: IDiscussionBoardArticleFile.ICreate,
  ): Promise<IDiscussionBoardArticleFile> {
    try {
      return await postDiscussionBoardUserArticlesArticleIdFiles({
        user,
        articleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Removes a file attachment from an article, deleting both the physical file from storage and the database record.
   *
   * This operation is part of the article editing capability and is restricted to the article's author. When a file attachment is removed, the system permanently deletes the physical file from storage and removes the corresponding database record from the discussion_board_article_files table. This action cannot be undone.
   *
   * Authorization requires the authenticated user to be the author of the parent article. Banned users are denied access regardless of ownership. Administrators do not have permission to remove individual file attachments as they can only delete entire articles, not edit them.
   *
   * The articleId parameter identifies the parent article, and the fileId parameter identifies the specific file attachment to remove. The system validates that the file belongs to the specified article before deletion.
   *
   * This operation affects the article's total attachment size calculation and the file count limit (maximum 10 files per article). After successful deletion, the freed storage quota becomes available for new attachments.
   *
   * @param connection
   * @param articleId Unique identifier of the article containing the file attachment to be removed. The authenticated user must be the author of this article to perform the deletion.
   * @param fileId Unique identifier of the file attachment to be removed. The file must belong to the specified article for the deletion to succeed.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Implementation steps:
   *
   * 1. Validate authentication - return 401 if not authenticated
   * 2. Query discussion_board_articles table to find the article by articleId
   * 3. Return 404 if article not found
   * 4. Verify user is the article author (discussion_board_user_id matches authenticated user)
   * 5. Return 403 if not the author
   * 6. Check if user is banned via discussion_board_bans table
   * 7. Return 403 with USER_BANNED if banned
   * 8. Query discussion_board_article_files to find the file by fileId
   * 9. Verify the file belongs to the specified article (discussion_board_article_id matches articleId)
   * 10. Return 404 if file not found or doesn't belong to article
   * 11. Delete the physical file from storage using storage_path
   * 12. Delete the database record from discussion_board_article_files
   * 13. Return HTTP 204 No Content
   *
   * Edge cases:
   * - File already deleted: return 404
   * - Article soft-deleted: allow deletion if author matches (article still exists)
   * - Concurrent deletion: handle gracefully with transaction
   * - Storage deletion failure: still remove database record, log error for manual cleanup
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":fileId")
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("articleId")
    articleId: string,
    @TypedParam("fileId")
    fileId: string,
  ): Promise<void> {
    try {
      return await deleteDiscussionBoardUserArticlesArticleIdFilesFileId({
        user,
        articleId,
        fileId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
