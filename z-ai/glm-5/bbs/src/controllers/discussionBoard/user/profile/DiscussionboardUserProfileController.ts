import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IDiscussionBoardUser } from "../../../../api/structures/IDiscussionBoardUser";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { putDiscussionBoardUserProfile } from "../../../../providers/putDiscussionBoardUserProfile";

@Controller("/discussionBoard/user/profile")
export class DiscussionboardUserProfileController {
  /**
   * Update the authenticated user's profile information including display name and biography.
   *
   * This operation allows users to personalize their profile by modifying their display name (visible to other users alongside their content) and an optional biographical text. The display name serves as the primary identifier shown on articles, comments, and profile pages.
   *
   * **Display Name Validation:**
   * - Maximum 50 characters
   * - Allowed characters: letters (A-Z, a-z), numbers (0-9), spaces, hyphens (-), underscores (_), apostrophes (')
   * - No consecutive spaces allowed
   * - No leading or trailing spaces
   * - Display name uniqueness is NOT required - multiple users may have the same display name
   *
   * **Bio Validation:**
   * - Maximum 500 characters
   * - HTML tags and JavaScript code are not permitted
   * - Line breaks and basic text formatting are preserved
   * - The bio field is optional and may be null or empty
   *
   * **Security Considerations:**
   * - Users can only update their own profile through the authenticated session
   * - All input is sanitized to prevent HTML/JavaScript injection
   * - The updated_at timestamp is automatically refreshed upon successful update
   *
   * **Related Operations:**
   * - GET /profile/at - Retrieve the authenticated user's own profile
   * - GET /users/{userId} - View another user's profile
   *
   * This operation updates the discussion_board_users table record associated with the authenticated user.
   *
   * @param connection
   * @param body Profile update data containing the new display name and/or biography
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Update the authenticated user's profile in the discussion_board_users table.
   *
   * **Implementation Steps:**
   * 1. Extract user ID from the authenticated JWT session context
   * 2. Validate request body:
   *    - display_name: Check length (1-50 chars), character whitelist (alphanumeric, spaces, hyphens, underscores, apostrophes), no consecutive/leading/trailing spaces
   *    - bio: Check length (<=500 chars), sanitize HTML/JavaScript tags
   * 3. Execute UPDATE query on discussion_board_users:
   *    - SET display_name = $displayName, bio = $bio, updated_at = NOW()
   *    - WHERE id = $authenticatedUserId AND deleted_at IS NULL
   * 4. Return the updated user record
   *
   * **Validation Rules:**
   * - Display name regex pattern: ^[a-zA-Z0-9\s\-_']+$ after trimming
   * - No consecutive spaces: check with regex \s{2,}
   * - Bio sanitization: strip HTML tags, limit to 500 chars
   *
   * **Edge Cases:**
   * - User not found: Return 404 (account may have been deleted)
   * - Banned user: Allow profile update (ban status doesn't prevent profile management)
   * - Empty bio: Accept null or empty string
   * - Partial update: Only update provided fields (display_name and/or bio)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: IDiscussionBoardUser.IUpdate,
  ): Promise<IDiscussionBoardUser> {
    try {
      return await putDiscussionBoardUserProfile({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
