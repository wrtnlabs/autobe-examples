import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IDiscussionBoardAdmin } from "../../../../api/structures/IDiscussionBoardAdmin";
import { postDiscussionBoardAuthAdminJoin } from "../../../../providers/postDiscussionBoardAuthAdminJoin";
import { postDiscussionBoardAuthAdminLogin } from "../../../../providers/postDiscussionBoardAuthAdminLogin";
import { postDiscussionBoardAuthAdminRefresh } from "../../../../providers/postDiscussionBoardAuthAdminRefresh";

@Controller("/discussionBoard/auth/admin")
export class DiscussionboardAuthAdminController {
  /**
   * Registers a new administrator account with email and password credentials.
   *
   * This endpoint creates a new administrator account in the discussion board system. The administrator will have the 'regular' grade by default, which grants content moderation and user management capabilities. Promotion to 'super' grade requires approval from an existing super administrator through the admin request workflow.
   *
   * The registration process validates that the provided email is unique across all administrator accounts and conforms to valid email format. The password must meet minimum security requirements including length and complexity. Upon successful registration, the administrator is automatically authenticated and receives JWT tokens for subsequent API access.
   *
   * This operation references the discussion_board_admins table which stores email (unique identifier), password_hash (securely hashed password), display_name (shown on profile), bio (optional biographical text), grade (privilege level), and account status fields (banned_at, ban_reason, deleted_at).
   *
   * Related operations: After registration, the admin can use /auth/admin/login for subsequent authentications and /auth/admin/refresh to renew tokens.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Administrator registration credentials including email and password
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Implementation: 1) Validate email format and check uniqueness against discussion_board_admins.email (unique constraint). 2) Validate password meets security requirements (minimum length, complexity). 3) Hash password using bcrypt or argon2. 4) Create new admin record with email, password_hash, default display_name (can be same as email initially), optional bio, grade='regular' (new admins start as regular, promotion to super requires super admin approval). 5) Create session record in discussion_board_admin_sessions with admin_id, IP, href, referrer, created_at, and expired_at (based on configured session duration). 6) Generate JWT access token with admin id, session id, expiration claim. 7) Generate refresh token. 8) Return IAuthorized with both tokens. 9) Enforce single session policy by invalidating any existing sessions for this admin.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IDiscussionBoardAdmin.IJoin,
  ): Promise<IDiscussionBoardAdmin.IAuthorized> {
    try {
      return await postDiscussionBoardAuthAdminJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticates an administrator with email and password credentials.
   *
   * This endpoint validates administrator credentials and establishes an authenticated session. The system checks both credential validity and account status, ensuring banned or soft-deleted administrators cannot access the platform.
   *
   * The login process validates the provided email exists in discussion_board_admins.email and the password matches the stored password_hash. For security, the system returns a generic error message without revealing whether the email or password was incorrect. This prevents email enumeration attacks.
   *
   * Account status checks include: 1) deleted_at - if set, the account has been soft-deleted and authentication is rejected, 2) banned_at - if set, the admin is banned and authentication is rejected with appropriate messaging. The ban_reason field provides context for banned accounts.
   *
   * Upon successful authentication, a new session is created in discussion_board_admin_sessions, recording the IP address, href, and referrer for audit purposes. The system enforces single session policy by terminating any existing sessions for this admin before creating the new one. JWT tokens (access and refresh) are returned for subsequent API authentication.
   *
   * Related operations: Use /auth/admin/refresh to renew tokens without re-authentication, /auth/admin/join to create new administrator accounts.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Administrator login credentials with email and password
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Implementation: 1) Validate email and password are present. 2) Query discussion_board_admins by email (unique index lookup). 3) If admin not found, return generic authentication error (do not reveal email existence). 4) Verify password_hash using bcrypt/argon2 comparison. 5) If password invalid, return generic authentication error. 6) Check deleted_at field - if set, account is soft-deleted, reject authentication. 7) Check banned_at field - if set, admin is banned, reject with banned status. 8) Create new session in discussion_board_admin_sessions with admin_id, IP, href, referrer, created_at, expired_at. 9) Invalidate any existing sessions for this admin (single session policy). 10) Generate JWT access token with admin id, session id, expiration. 11) Generate refresh token. 12) Return IAuthorized with tokens.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IDiscussionBoardAdmin.ILogin,
  ): Promise<IDiscussionBoardAdmin.IAuthorized> {
    try {
      return await postDiscussionBoardAuthAdminLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Renews JWT access and refresh tokens using a valid refresh token.
   *
   * This endpoint allows administrators to obtain new authentication tokens without re-entering credentials, maintaining continuous access during active sessions. The refresh token must be valid and the associated session must still be active.
   *
   * The refresh process validates the provided refresh token's cryptographic signature and expiration timestamp. The token contains claims identifying the admin (discussion_board_admins.id) and session (discussion_board_admin_sessions.id). The system verifies the session record exists and has not expired based on the expired_at timestamp.
   *
   * Additional validation ensures the admin account remains in good standing: 1) deleted_at must be null (account not soft-deleted), 2) banned_at must be null (admin not banned). If the admin has been banned or deleted since the original token was issued, the refresh is rejected and the session may be terminated.
   *
   * Upon successful refresh, new access and refresh tokens are issued with fresh expiration times. The old refresh token is invalidated to prevent replay attacks. This rotation pattern enhances security by ensuring each refresh token can only be used once.
   *
   * Related operations: Use /auth/admin/login to obtain initial tokens, /auth/admin/join to create new administrator accounts.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Valid refresh token to exchange for new access and refresh tokens
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Implementation: 1) Extract refresh token from request body. 2) Validate refresh token signature using JWT secret. 3) Check refresh token expiration. 4) Extract admin id and session id from token claims. 5) Query discussion_board_admin_sessions to verify session exists and is not expired (expired_at field). 6) Query discussion_board_admins to verify admin account: a) exists, b) deleted_at is null (not soft-deleted), c) banned_at is null (not banned). 7) If any validation fails, reject with authentication error and optionally terminate session. 8) Generate new access token with admin id, session id, new expiration. 9) Generate new refresh token. 10) Update session expired_at if needed (extend session). 11) Invalidate old refresh token. 12) Return IAuthorized with new tokens.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IDiscussionBoardAdmin.IRefresh,
  ): Promise<IDiscussionBoardAdmin.IAuthorized> {
    try {
      return await postDiscussionBoardAuthAdminRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
