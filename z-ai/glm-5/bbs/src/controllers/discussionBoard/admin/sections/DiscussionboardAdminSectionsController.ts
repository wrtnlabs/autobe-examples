import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IDiscussionBoardSection } from "../../../../api/structures/IDiscussionBoardSection";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { deleteDiscussionBoardAdminSectionsSectionId } from "../../../../providers/deleteDiscussionBoardAdminSectionsSectionId";
import { postDiscussionBoardAdminSections } from "../../../../providers/postDiscussionBoardAdminSections";
import { putDiscussionBoardAdminSectionsSectionId } from "../../../../providers/putDiscussionBoardAdminSectionsSectionId";

@Controller("/discussionBoard/admin/sections")
export class DiscussionboardAdminSectionsController {
  /**
   * Create a new section for organizing discussion board articles.
   *
   * This endpoint allows administrators to create new thematic categories that organize articles into distinct discussion topics. Each section represents a topic area such as Politics, Economy, or Current Affairs, providing users with a clear navigation hierarchy for discovering articles.
   *
   * The operation validates that the section name is unique (case-insensitive) and meets the required length constraints. Upon successful creation, the section becomes immediately visible to all users including unauthenticated guests.
   *
   * Administrative privileges are required for this operation. Non-administrator users attempting to create a section will receive an authorization error. The system automatically records the creating administrator's identity for audit trail purposes.
   *
   * Related operations:
   * - GET /sections - List all sections (publicly accessible)
   * - PUT /sections/{sectionId} - Update section (admin only)
   * - DELETE /sections/{sectionId} - Delete section (admin only, restricted to empty sections)
   *
   * @param connection
   * @param body Section creation data with name and description
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Implementation steps:
   *
   * 1. Validate user authentication and administrator role
   * 2. Validate request body:
   *    - name: 1-100 characters, trimmed, case-insensitive unique check against existing sections
   *    - description: 1-500 characters, trimmed
   * 3. Auto-generate fields:
   *    - id: UUID v4
   *    - created_by: Current authenticated administrator's ID
   *    - sequence: Calculate next sequence number (MAX(sequence) + 1 or 1 if first section)
   *    - created_at: Current timestamp
   *    - updated_at: Current timestamp
   * 4. Insert new section record into discussion_board_sections table
   * 5. Return complete section entity
   *
   * Business rules:
   * - Reject if user is not administrator
   * - Reject if name already exists (case-insensitive)
   * - Reject if name or description is empty/whitespace-only
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IDiscussionBoardSection.ICreate,
  ): Promise<IDiscussionBoardSection> {
    try {
      return await postDiscussionBoardAdminSections({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing section's name and description.
   *
   * This operation allows administrators to modify section details in the `discussion_board_sections` table. The section's name must remain unique across all sections (case-insensitive per `@@unique([name])` constraint). Both name and description fields can be updated in a single atomic operation.
   *
   * Only administrators can perform this operation. Regular members and guests do not have permission to edit sections. The `created_by` field (audit trail) and `sequence` field (display order) are preserved during updates and cannot be modified through this endpoint.
   *
   * Changes are immediately visible to all users browsing sections. The `updated_at` timestamp is automatically set to the current time.
   *
   * Related operations:
   * - POST /discussionBoard/admin/sections: Create a new section (admin only)
   * - DELETE /discussionBoard/admin/sections/{sectionId}: Delete a section (admin only, empty sections only)
   * - GET /discussionBoard/sections: List all sections (public access)
   * - GET /discussionBoard/sections/{sectionId}/articles: View articles in a section (public access)
   *
   * @param connection
   * @param sectionId Unique identifier of the section to update (UUID format)
   * @param body Section update data containing new name and description
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Update an existing section record in discussion_board_sections table.
   *
   * 1. Authenticate and verify the requester is an administrator
   * 2. Validate sectionId exists in database (return 404 if not found)
   * 3. Validate request body:
   *    - name: 1-100 characters, must be unique (case-insensitive check)
   *    - description: 1-500 characters
   * 4. If name is being changed, check for uniqueness conflict with existing sections
   * 5. Update the section record with new name and description
   * 6. Update the updated_at timestamp to current time
   * 7. Return the complete updated section entity
   *
   * Edge cases:
   * - Duplicate name: Return 409 Conflict with error detail
   * - Non-existent sectionId: Return 404 Not Found
   * - Non-admin requester: Return 403 Forbidden
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":sectionId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("sectionId")
    sectionId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardSection.IUpdate,
  ): Promise<IDiscussionBoardSection> {
    try {
      return await putDiscussionBoardAdminSectionsSectionId({
        admin,
        sectionId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently removes a discussion board section from the system.
   *
   * This operation allows administrators to delete topic categories from the discussion board. Section deletion is subject to business rule constraints: a section that contains articles cannot be deleted directly. The system will reject deletion attempts for non-empty sections, requiring administrators to first delete or reassign all articles within that section.
   *
   * The discussion_board_sections table stores section information including unique name, description, display sequence, and creation metadata. Each section is identified by a UUID primary key and references the administrator who created it for audit purposes.
   *
   * Security: This endpoint requires administrator authentication. Only users with admin or super admin privileges can execute this operation. The system validates administrator identity before performing deletion.
   *
   * Related operations:
   * - GET /sections - List all sections (available to all users)
   * - POST /sections - Create new section (administrator only)
   * - PUT /sections/{sectionId} - Update section (administrator only)
   * - DELETE /articles?section={sectionId} - Delete articles in section (for clearing before section deletion)
   *
   * Error conditions: Returns 400 Bad Request if the section contains articles, prompting the administrator to first remove or reassign those articles. Returns 404 Not Found if the section ID does not exist. Returns 403 Forbidden if the requester is not an administrator.
   *
   * @param connection
   * @param sectionId Unique identifier of the section to delete (UUID format). The section must exist and must not contain any articles for successful deletion.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Delete a discussion board section by its UUID identifier.
   *
   * Implementation steps:
   * 1. Validate the requesting user is authenticated as an administrator
   * 2. Query the section by sectionId from discussion_board_sections table
   * 3. If section not found, return 404 error
   * 4. Query discussion_board_articles table to check if any articles reference this section
   * 5. If articles exist, return 400 error with message indicating articles must be handled first
   * 6. If no articles, delete the section record from discussion_board_sections
   * 7. Return the deleted section information
   *
   * Transaction boundary: Single atomic transaction for the deletion.
   *
   * Authorization: Administrator role required.
   *
   * Error handling:
   * - 401: Not authenticated
   * - 403: Not an administrator
   * - 404: Section not found
   * - 400: Section contains articles - requires deletion/reassignment first
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":sectionId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("sectionId")
    sectionId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteDiscussionBoardAdminSectionsSectionId({
        admin,
        sectionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
