  /**
   * Update a pending administrator request's reason field.
   *
   * This endpoint allows members to modify the explanation text of their submitted admin request while it is still pending review. Only the member who originally submitted the request can perform this update, and only if the request status remains 'pending'. Once a super administrator approves or rejects the request, it becomes permanently immutable for audit trail integrity.
   *
   * The discussion_board_admin_requests table stores administrator privilege elevation requests from members seeking admin status. Each request contains the member's written reason explaining why they should be granted administrative privileges, along with status tracking through the review lifecycle.
   *
   * Security considerations:
   * - Only the original requester (member_id) can update the request
   * - Updates are blocked if status is not 'pending'
   * - The reason field cannot be empty or whitespace
   * - Super administrators cannot edit requests (they approve/reject instead)
   *
   * Related operations:
   * - POST /admin-requests: Submit a new admin request
   * - GET /admin-requests/{adminRequestId}: View request details
   * - PATCH /admin-requests: List/search admin requests (super admin only for pending)
   * - POST /admin-requests/{adminRequestId}/approve: Approve a pending request (super admin only)
   * - POST /admin-requests/{adminRequestId}/reject: Reject a pending request (super admin only)
   *
   * @param connection
   * @param adminRequestId Unique identifier of the admin request to update. The request must belong to the authenticated member and be in pending status.
   * @param body Updated reason text for the admin request. Only the reason field can be modified; status changes require separate approve/reject endpoints.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Implementation steps for updating an admin request:
   *
   * 1. **Authorization Check**: Extract the authenticated user from the session. Verify the user is a member (not a guest or admin). Retrieve the admin request by ID and verify that the member_id matches the authenticated user's ID. Return 403 Forbidden if the user is not the original requester.
   *
   * 2. **Status Validation**: Query the discussion_board_admin_requests table for the specified adminRequestId. Verify the status column equals 'pending'. Return 409 Conflict if the request is already approved or rejected, as those states are immutable.
   *
   * 3. **Input Validation**: Validate the reason field in the request body:
   *    - Must not be empty or whitespace
   *    - Apply length constraints per business rules
   *    - Sanitize for XSS prevention
   *
   * 4. **Database Update**: Execute UPDATE on discussion_board_admin_requests:
   *    - Set reason = the new reason text
   *    - Set updated_at = current timestamp
   *    - WHERE id = adminRequestId AND status = 'pending'
   *    - Return 404 Not Found if no rows affected (request doesn't exist)
   *
   * 5. **Response**: Return the updated IDiscussionBoardAdminRequest object with all fields including the updated reason and new updated_at timestamp.
   *
   * Edge cases:
   * - Concurrent updates: Use optimistic locking with updated_at check
   * - Request deleted: Return 404 Not Found if deleted_at is not null
   * - Banned user: Allow update if user was banned after submission (the ban check occurs during approval)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
