import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IDashboardSummary } from "../../../../api/structures/IDashboardSummary";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getDiscussionBoardAdminDashboard } from "../../../../providers/getDiscussionBoardAdminDashboard";

@Controller("/discussionBoard/admin/dashboard")
export class DiscussionboardAdminDashboardController {
  /**
   * Retrieve a comprehensive administrative dashboard overview with aggregated platform statistics and metrics.
   *
   * This endpoint provides administrators with a consolidated view of platform health, user activity, and content statistics. The response includes real-time counts of articles, comments, members, and sections, along with administrative metrics such as pending administrator requests.
   *
   * The dashboard aggregates data from multiple database entities: discussion_board_articles for content metrics, discussion_board_comments for engagement tracking, discussion_board_members for user statistics, discussion_board_sections for topic categorization, and discussion_board_admin_requests for administrative workflow visibility.
   *
   * Statistics are computed at request time to ensure real-time accuracy. The response includes both current totals and recent activity metrics (last 7 days) to help administrators identify trends and monitor platform growth.
   *
   * This operation requires administrator authentication. Regular members and guests cannot access this endpoint as it exposes platform-wide metrics that are considered sensitive administrative information.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Implementation aggregates counts from multiple tables in a single efficient query execution:
   *
   * 1. Article Statistics:
   *    - COUNT(*) from discussion_board_articles WHERE deleted_at IS NULL
   *    - Group by section_id to provide section-wise breakdown
   *    - Include recent articles count (last 7 days)
   *
   * 2. Comment Statistics:
   *    - COUNT(*) from discussion_board_comments WHERE deleted_at IS NULL
   *    - Calculate average comments per article
   *
   * 3. Member Statistics:
   *    - COUNT(*) from discussion_board_members WHERE deleted_at IS NULL AND banned = false
   *    - COUNT(*) of banned members
   *    - COUNT(*) of new registrations (last 7 days)
   *
   * 4. Section Statistics:
   *    - COUNT(*) from discussion_board_sections
   *    - Include section with most articles
   *
   * 5. Admin Request Statistics:
   *    - COUNT(*) from discussion_board_admin_requests WHERE status = 'pending' AND deleted_at IS NULL
   *    - COUNT(*) of approved requests (all time)
   *    - COUNT(*) of rejected requests (all time)
   *
   * All queries should be executed in parallel where possible. Consider caching for 1-5 minutes to reduce database load on frequently accessed dashboard. Response should be computed fresh on each request for real-time accuracy.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @AdminAuth()
    admin: AdminPayload,
  ): Promise<IDashboardSummary> {
    try {
      return await getDiscussionBoardAdminDashboard({
        admin,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
