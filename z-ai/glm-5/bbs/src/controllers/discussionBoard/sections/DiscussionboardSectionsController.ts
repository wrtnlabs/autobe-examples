import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IDiscussionBoardSection } from "../../../api/structures/IDiscussionBoardSection";
import { IPageIDiscussionBoardSection } from "../../../api/structures/IPageIDiscussionBoardSection";
import { getDiscussionBoardSectionsSectionId } from "../../../providers/getDiscussionBoardSectionsSectionId";
import { patchDiscussionBoardSections } from "../../../providers/patchDiscussionBoardSections";

@Controller("/discussionBoard/sections")
export class DiscussionboardSectionsController {
  /**
   * Retrieve a paginated list of all available discussion board sections.
   *
   * This operation provides access to the thematic categories that organize articles in the discussion board. Each section represents a distinct topic area such as Politics, Economy, or Current Affairs, allowing users to discover and browse articles by their interests.
   *
   * All users including unauthenticated guests can access the section list without restriction. The response includes each section's unique identifier, display name, descriptive text, and ordering sequence. Sections are presented in their configured display order for consistent navigation.
   *
   * Sections are always displayed regardless of whether they contain articles or not. Empty sections remain visible in the list, allowing users to see all available topic areas and encouraging content creation in underrepresented categories.
   *
   * The operation supports pagination to handle large numbers of sections efficiently, with optional search filtering on section names.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for section listing
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query discussion_board_sections table with pagination and optional filtering. Apply filters on name (partial match) if provided. Sort results by sequence field ascending for consistent navigation ordering. Return cursor-based pagination with configurable page sizes. Include all sections regardless of article count - empty sections must be visible. No authentication required - accessible to all users including guests. Join with discussion_board_admins via created_by for audit trail if needed, but not exposed in response for security. Return simplified section summary with id, name, description, and sequence fields.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IDiscussionBoardSection.IRequest,
  ): Promise<IPageIDiscussionBoardSection.ISummary> {
    try {
      return await patchDiscussionBoardSections({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific discussion board section by its unique identifier.
   *
   * This operation provides access to a single section's complete details including its name, description, display sequence, and creation metadata. Sections represent thematic categories that organize articles into distinct discussion topics such as Politics, Economy, and Current Affairs.
   *
   * All users including unauthenticated guests can access section information without restriction. This endpoint supports the navigation hierarchy where users first browse sections, then select a section to view its contained articles.
   *
   * The response includes the section's unique identifier, display name, descriptive text explaining what types of articles belong in the section, sequence number for navigation ordering, and timestamps for creation and last modification. The creator relation provides information about which administrator created the section.
   *
   * Use this endpoint when displaying section details or when beginning article browsing within a specific topic area.
   *
   * @param connection
   * @param sectionId Unique identifier of the section to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query the discussion_board_sections table by primary key id. Include the creator relation (discussion_board_admins) to populate the createdBy field. Return 404 NOT FOUND if the section does not exist. No authentication or authorization checks required as sections are publicly visible. The response should include all section fields: id, name, description, sequence, created_by, created_at, updated_at, with the creator relation resolved to include basic admin information.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sectionId")
  public async at(
    @TypedParam("sectionId")
    sectionId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardSection> {
    try {
      return await getDiscussionBoardSectionsSectionId({
        sectionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
