import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IDiscussionBoardSection } from "../../../api/structures/IDiscussionBoardSection";
import { IPageIDiscussionBoardSection } from "../../../api/structures/IPageIDiscussionBoardSection";
import { getDiscussionBoardSectionsSectionId } from "../../../providers/getDiscussionBoardSectionsSectionId";
import { patchDiscussionBoardSections } from "../../../providers/patchDiscussionBoardSections";

@Controller("/discussionBoard/sections")
export class DiscussionboardSectionsController {
  /**
   * Retrieve a paginated list of all active discussion board sections.
   *
   * This endpoint provides public access to browse all available sections on the discussion board. Each section represents a topic category such as Politics, Economy, or Current Affairs, and serves as the primary organizational structure for articles.
   *
   * The response includes each section's name, description, and the current count of articles within that section. Results are sorted alphabetically by section name to facilitate easy navigation. Soft-deleted sections are automatically excluded from the list.
   *
   * This endpoint is accessible to all users, including non-authenticated visitors, enabling content discovery without requiring login. For detailed article listings within a specific section, use the article list endpoint with the section identifier.
   *
   * @param connection
   * @param body Pagination and search parameters for section list
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query discussion_board_sections table with pagination support.
   *
   * Implementation steps:
   * 1. Filter records where deleted_at IS NULL to exclude soft-deleted sections
   * 2. Apply pagination using standard limit/offset pattern
   * 3. Count articles in each section via discussion_board_articles table (where deleted_at IS NULL on articles as well)
   * 4. Sort results alphabetically by name (case-insensitive)
   * 5. Return paginated response with section summaries
   *
   * The article count should reflect only active (non-deleted) articles in each section. Use LEFT JOIN with articles table and COUNT aggregation for efficiency. Consider caching section list if frequently accessed.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IDiscussionBoardSection.IRequest,
  ): Promise<IPageIDiscussionBoardSection.ISummary> {
    try {
      return await patchDiscussionBoardSections({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific discussion board section.
   *
   * This endpoint returns comprehensive information about a section identified by its unique UUID identifier. The response includes the section's display name, description, creator and modifier information, article count, and timestamps.
   *
   * Sections serve as the primary organizational structure for the discussion board, grouping articles by topic categories such as Politics, Economy, and Current Affairs. This endpoint is the entry point for users to explore content within a specific section.
   *
   * All users, including non-authenticated users, can access this endpoint to browse available discussion topics.
   *
   * After retrieving section details, clients can use the section ID to fetch the list of articles within that section through a separate articles endpoint with pagination support.
   *
   * If the specified section does not exist or has been deleted, a 404 Not Found error is returned.
   *
   * @param connection
   * @param sectionId Unique identifier of the section to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query the discussion_board_sections table by primary key ID with a filter for null deleted_at to exclude soft-deleted sections. Join with discussion_board_users table on creator_id to retrieve creator's display name and profile information. Optionally join on modifier_id if present to retrieve modifier's display name. Count the number of associated articles by querying discussion_board_articles with filter on discussion_board_section_id and null deleted_at (only count active articles). Return 404 Not Found if section does not exist or has been soft-deleted. Map the database result to IDiscussionBoardSection response type including: id (UUID), name (unique string), description (string), creator information (IDiscussionBoardSection.IAuthor with id and displayName), modifier information if exists (IDiscussionBoardSection.IAuthor optional), articleCount (integer), createdAt (timestamp), updatedAt (timestamp).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sectionId")
  public async at(
    @TypedParam("sectionId")
    sectionId: string,
  ): Promise<IDiscussionBoardSection> {
    try {
      return await getDiscussionBoardSectionsSectionId({
        sectionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
