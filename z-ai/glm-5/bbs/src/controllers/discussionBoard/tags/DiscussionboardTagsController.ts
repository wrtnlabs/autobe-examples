import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IDiscussionBoardTag } from "../../../api/structures/IDiscussionBoardTag";
import { IPageIDiscussionBoardTag } from "../../../api/structures/IPageIDiscussionBoardTag";
import { getDiscussionBoardTagsTagId } from "../../../providers/getDiscussionBoardTagsTagId";
import { patchDiscussionBoardTags } from "../../../providers/patchDiscussionBoardTags";

@Controller("/discussionBoard/tags")
export class DiscussionboardTagsController {
  /**
   * Retrieve a paginated list of tags available in the discussion board system.
   *
   * This operation enables users to discover and search for tags used across articles. Tags provide flexible, user-defined categorization that complements section-based organization. Users can filter tags by name to find specific topics or discover related content across all sections.
   *
   * The response includes tag names that can be used for article filtering. When searching articles, users can combine multiple tags to narrow results. Tags are stored case-sensitively but searched case-insensitively for user convenience.
   *
   * All actors (guest, member, administrator) can access this endpoint to browse and discover tags. The paginated response supports efficient navigation through large tag collections with cursor-based pagination.
   *
   * Related operations:
   * - PATCH /articles - Filter articles by tag IDs obtained from this endpoint
   * - GET /articles/{articleId} - View article details with associated tags
   *
   * @param connection
   * @param body Search criteria and pagination parameters for tag listing
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query the discussion_board_tags table with pagination and filtering capabilities. Apply case-insensitive partial matching on tag name when search query is provided. Filter out soft-deleted tags by checking deleted_at IS NULL. Support sorting by name, created_at, or updated_at in ascending or descending order. Return paginated results with tag id, name, created_at, updated_at, and optionally article_count (count of articles using each tag via discussion_board_article_tags junction table). Use cursor-based pagination for efficient large result set handling.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IDiscussionBoardTag.IRequest,
  ): Promise<IPageIDiscussionBoardTag.ISummary> {
    try {
      return await patchDiscussionBoardTags({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific tag by its unique identifier.
   *
   * This operation allows users to fetch a single tag's details, including its name and metadata. Tags are used for flexible article categorization and cross-section topic discovery, enabling users to filter articles by topics of interest.
   *
   * The tag must be active (not soft-deleted) to be returned. All actors (guest, member, admin) can access tag information as tags are public entities used for content organization and filtering.
   *
   * Tags are stored case-sensitively and provide organic content organization based on actual discussion topics. Each tag can be associated with multiple articles through the article-tag junction table.
   *
   * @param connection
   * @param tagId Unique identifier of the tag to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query the discussion_board_tags table by primary key id. Filter out soft-deleted tags by checking deleted_at IS NULL. Return 404 if tag not found or has been soft-deleted. Include all tag fields in response: id, name, created_at, updated_at. The tag name is unique (enforced by @@unique constraint) and contains free-form text up to 50 characters for article categorization.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":tagId")
  public async at(
    @TypedParam("tagId")
    tagId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardTag> {
    try {
      return await getDiscussionBoardTagsTagId({
        tagId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
