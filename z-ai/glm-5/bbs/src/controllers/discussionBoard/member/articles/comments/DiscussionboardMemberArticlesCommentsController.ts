import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IDiscussionBoardComment } from "../../../../../api/structures/IDiscussionBoardComment";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { deleteDiscussionBoardMemberArticlesArticleIdCommentsCommentId } from "../../../../../providers/deleteDiscussionBoardMemberArticlesArticleIdCommentsCommentId";
import { postDiscussionBoardMemberArticlesArticleIdComments } from "../../../../../providers/postDiscussionBoardMemberArticlesArticleIdComments";
import { putDiscussionBoardMemberArticlesArticleIdCommentsCommentId } from "../../../../../providers/putDiscussionBoardMemberArticlesArticleIdCommentsCommentId";

@Controller("/discussionBoard/member/articles/:articleId/comments")
export class DiscussionboardMemberArticlesCommentsController {
  /**
   * Create a new comment on an article.
   *
   * This operation allows authenticated members to post their written responses to articles in the discussion board. Comments represent members' opinions, questions, or feedback on the article's topic.
   *
   * The comment follows a flat, single-level structure without nested replies, keeping discussions straightforward and easy to follow. Each comment is permanently linked to its article and attributed to the member who created it.
   *
   * Comments are displayed in chronological order (oldest first) on articles. The author can modify their comment content later while preserving the original creation timestamp.
   *
   * Business rules:
   * - Only authenticated members can create comments
   * - Banned members cannot create comments
   * - Content must be between 10 and 10,000 characters
   * - Empty or whitespace-only content is rejected
   * - Single-level comments only - no nested replies permitted
   *
   * The articleId path parameter specifies which article to comment on. The author is automatically determined from the authenticated member session, ensuring secure attribution.
   *
   * @param connection
   * @param articleId The unique identifier of the article to comment on. Must reference an existing, non-deleted article.
   * @param body Comment creation data containing the text content
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Create a new comment on an article.
   *
   * 1. Validate the requester is authenticated as a member
   * 2. Check the member is not banned (banned = false)
   * 3. Verify the article exists and is not soft-deleted (deleted_at IS NULL)
   * 4. Validate content length is between 10-10,000 characters
   * 5. Create comment record with:
   *    - discussion_board_article_id from path parameter articleId
   *    - discussion_board_member_id from authenticated session
   *    - content from request body
   *    - created_at and updated_at set to current timestamp
   * 6. Return the created comment with author information joined
   *
   * Error cases:
   * - 401 Unauthorized if not authenticated
   * - 403 Forbidden if member is banned
   * - 404 Not Found if article doesn't exist or is deleted
   * - 400 Bad Request if content validation fails
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardComment.ICreate,
  ): Promise<IDiscussionBoardComment> {
    try {
      return await postDiscussionBoardMemberArticlesArticleIdComments({
        member,
        articleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update the content of an existing comment on an article.
   *
   * This operation allows authenticated members to modify the content of their own comments. The comment must belong to the specified article, and the member must be the original author of the comment. Comments authored by other members cannot be edited.
   *
   * The comment content is the only modifiable field. The updated_at timestamp is automatically set to reflect when the modification occurred. The original created_at timestamp is preserved to maintain the chronological record.
   *
   * **Authorization Requirements:**
   * - Only the comment author can update their comment
   * - Administrator accounts cannot edit member comments (administrators can only delete comments)
   *
   * **Validation Rules:**
   * - Content must be between 10 and 10,000 characters
   * - Content cannot be empty or whitespace-only
   * - Article must exist and not be deleted
   * - Comment must exist and not be deleted
   * - Comment must belong to the specified article
   *
   * **Related Operations:**
   * - POST /articles/{articleId}/comments - Create a new comment
   * - DELETE /articles/{articleId}/comments/{commentId} - Delete a comment (author or admin)
   *
   * @param connection
   * @param articleId Unique identifier of the article that contains the comment to be updated. The comment must belong to this article.
   * @param commentId Unique identifier of the comment to be updated. The authenticated member must be the author of this comment.
   * @param body Updated comment content. Must be between 10 and 10,000 characters.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Update an existing comment owned by the authenticated member.
   *
   * **Authentication & Authorization:**
   * - Requires authenticated member session
   * - Only the comment author can update their own comment
   * - Reject with 403 Forbidden if member attempts to edit another user's comment
   *
   * **Validation Steps:**
   * 1. Verify article exists and is not deleted (check deleted_at is null)
   * 2. Verify comment exists and is not deleted
   * 3. Verify comment belongs to the specified article (discussion_board_article_id matches articleId)
   * 4. Verify authenticated member is the comment author (discussion_board_member_id matches)
   * 5. Validate comment content: minimum 10 characters, maximum 10,000 characters
   * 6. Reject if content is empty or whitespace-only
   *
   * **Database Operations:**
   * - UPDATE discussion_board_comments SET content = $1, updated_at = NOW() WHERE id = $commentId
   * - Return the updated comment record
   *
   * **Edge Cases:**
   * - Article deleted: Return 404 Not Found
   * - Comment deleted: Return 404 Not Found
   * - Comment not belonging to article: Return 404 Not Found
   * - Not the author: Return 403 Forbidden
   * - Content too short (< 10 chars): Return 400 Bad Request
   * - Content too long (> 10,000 chars): Return 400 Bad Request
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":commentId")
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardComment.IUpdate,
  ): Promise<IDiscussionBoardComment> {
    try {
      return await putDiscussionBoardMemberArticlesArticleIdCommentsCommentId({
        member,
        articleId,
        commentId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently removes a comment from an article's discussion thread.
   *
   * This operation allows comment authors to remove their own comments from articles, or administrators to delete any comment for moderation purposes. The comment is marked as deleted via a timestamp and removed from all public comment listings.
   *
   * **Authorization**: Only the comment author or users with administrator privileges can perform this deletion. Regular members cannot delete comments authored by other members.
   *
   * **Path Validation**: The articleId parameter ensures the comment being deleted belongs to the specified article. If the comment does not belong to the article, the operation returns a 404 error.
   *
   * **Deletion Behavior**: The comment is soft-deleted by setting the deleted_at timestamp. Once deleted, the comment is permanently removed from the article's comment list and cannot be recovered by regular members. The comment's content and metadata are retained in the database for audit purposes but are no longer accessible through the API.
   *
   * **Related Operations**: After deletion, the comment count on the article should reflect the change. Use GET /articles/{articleId}/comments to view remaining comments on the article.
   *
   * @param connection
   * @param articleId The unique identifier of the article containing the comment. Used to validate that the comment belongs to this article.
   * @param commentId The unique identifier of the comment to be deleted.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Implementation steps:
   * 1. Validate articleId path parameter exists in discussion_board_articles table
   * 2. Validate commentId path parameter exists in discussion_board_comments table
   * 3. Verify the comment's discussion_board_article_id matches the provided articleId (returns 404 if mismatch)
   * 4. Check authorization: authenticated user must be either:
   *    - The comment author (discussion_board_member_id matches current user's member ID)
   *    - An administrator (check admin session and admin grade)
   * 5. If not authorized, return 403 Forbidden
   * 6. Set deleted_at timestamp to current time (soft delete)
   * 7. Update updated_at timestamp
   * 8. Commit transaction
   * 9. Return null response (204 No Content)
   *
   * Edge cases:
   * - Comment already deleted (deleted_at not null): return 404
   * - Article not found: return 404
   * - Comment not found: return 404
   * - Banned user trying to delete: check if banned users retain deletion rights (business rule states banned user content remains visible, but doesn't explicitly remove deletion rights)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":commentId")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteDiscussionBoardMemberArticlesArticleIdCommentsCommentId(
        {
          member,
          articleId,
          commentId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
