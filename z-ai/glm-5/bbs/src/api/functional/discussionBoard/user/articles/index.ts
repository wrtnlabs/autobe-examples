/**
 * Update an existing article's content, metadata, and attachments.
 *
 * This operation allows authenticated users to modify their own articles within the discussion board platform. The operation targets the discussion_board_articles table, updating records identified by their UUID primary key while preserving data integrity through transactional processing.
 *
 * **Authorization and Security**
 *
 * Only the article's author can perform updates, verified by matching the authenticated user's ID against discussion_board_articles.discussion_board_user_id. Banned users (discussion_board_users.is_banned = true) cannot edit their articles regardless of ownership. Administrators are explicitly prohibited from editing user articles—this restriction is enforced by the author-only authorization check, as administrators have deletion rights only.
 *
 * **Editable and Protected Fields**
 *
 * The operation supports partial updates of the following fields:
 * - **Title**: Must be 3-200 characters if provided
 * - **Content**: Must be 10-50,000 characters if provided
 * - **Section**: Article can be moved to a different section by providing sectionId; referenced section must exist in discussion_board_sections
 * - **File Attachments**: Add, remove, or replace files (max 10 per article)
 * - **Image Attachments**: Add, remove, or replace images (max 20 per article)
 * - **Tags**: Add, remove, or replace tags (max 15 per article)
 *
 * Non-editable fields that remain protected:
 * - **Author (discussion_board_user_id)**: Cannot be changed after creation
 * - **Created At**: Immutable timestamp from article creation
 * - **Deleted At**: Managed only through delete operations
 *
 * **Validation and Business Rules**
 *
 * The article must exist and not be soft-deleted (deleted_at IS NULL). All referenced sections must be active. Tags are normalized to lowercase and validated for allowed characters. File and image attachment limits are enforced per article.
 *
 * **Related Operations**
 *
 * - PATCH /discussionBoard/user/articles: Search and list articles with pagination
 * - GET /discussionBoard/user/articles/{articleId}: Retrieve article details
 * - DELETE /discussionBoard/user/articles/{articleId}: Delete an article
 * - GET /discussionBoard/sections: Browse available sections for article assignment
 *
 * **Response Behavior**
 *
 * Returns the complete updated article entity with all nested relations (section, author, files, images, tags). The updated_at timestamp is automatically set to the current server time.
 *
 * @param props.connection
 * @param props.articleId Unique identifier of the article to update. Must be a valid UUID referencing an existing, non-deleted article.
 * @param props.body Article update data. Only provided fields will be updated; omitted fields remain unchanged. Supports partial updates with at least one field required.
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor user
 * @x-autobe-specification Implementation steps for article update:
 *
 * 1. **Authentication Check**: Verify JWT token from Authorization header. Extract user ID from token payload. Return 401 if unauthenticated.
 *
 * 2. **Article Lookup**: Query discussion_board_articles table by articleId. Include relations: files, images, articleTags (with tag). Check deleted_at is null. Return 404 if not found.
 *
 * 3. **Authorization Check**: Compare article.discussion_board_user_id with authenticated user ID. Return 403 if mismatch (NOT_ARTICLE_OWNER). Check user.is_banned is false. Return 403 if banned.
 *
 * 4. **Field Validation** (if provided in request body):
 *    - title: Validate length 3-200 characters
 *    - content: Validate length 10-50,000 characters
 *    - sectionId: Query discussion_board_sections to verify existence and deleted_at is null
 *    - tags: Validate count <= 15, each tag 1-50 chars, alphanumeric/hyphens/underscores only
 *
 * 5. **Transaction Processing**:
 *    - Begin database transaction
 *    - Update article fields (title, content, discussion_board_section_id)
 *    - Set updated_at to current timestamp
 *    - Handle file attachments: Process new uploads, delete removed files from storage and DB
 *    - Handle image attachments: Process new uploads, delete removed images from storage and DB
 *    - Handle tags: Normalize to lowercase, create new tags if needed, update article_tags junction table
 *    - Commit transaction
 *
 * 6. **Response**: Query updated article with all relations. Return IDiscussionBoardArticle with populated files, images, and tags arrays.
 *
 * **Error Codes**:
 * - AUTH_REQUIRED (401): User not authenticated
 * - ARTICLE_NOT_FOUND (404): Article doesn't exist or is deleted
 * - NOT_ARTICLE_OWNER (403): User is not the article author
 * - USER_BANNED (403): User is banned
 * - ARTICLE_SECTION_NOT_FOUND (404): Referenced section doesn't exist
 * - ARTICLE_TITLE_TOO_SHORT/LONG (400): Title validation failed
 * - ARTICLE_CONTENT_TOO_SHORT/LONG (400): Content validation failed
 * @path /discussionBoard/user/articles/:articleId
 * @accessor api.functional.discussionBoard.user.articles.update
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
