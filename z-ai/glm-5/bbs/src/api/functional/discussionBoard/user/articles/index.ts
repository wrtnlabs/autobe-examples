/**
 * Create a new article in the discussion board.
 *
 * This endpoint allows authenticated users to create articles within designated sections of the platform. Each article consists of a title, content body, and is assigned to exactly one section. Users can optionally attach files and images, and add free-form tags for categorization.
 *
 * **Authorization Requirements**:
 * - User must be authenticated
 * - User must not be banned
 *
 * **Validation Rules**:
 * - Title: 3-200 characters, required
 * - Content: 10-50,000 characters, required
 * - Section: must reference an existing section
 * - Files: maximum 10 files, 10MB each, 50MB total per article
 * - Images: maximum 20 images, 5MB each, 25MB total per article
 * - Tags: maximum 15 tags per article, 1-50 characters each, alphanumeric with hyphens and underscores only
 *
 * **Automatic Fields**:
 * - Author: set to the authenticated user
 * - Created At: set to current server time
 * - Updated At: initially matches Created At
 *
 * **Related Entities**:
 * - Files and images are stored and associated with the article
 * - Tags are normalized to lowercase and associated with the article
 * - Tag associations are created in the junction table
 *
 * **Response**:
 * Returns the complete article data including all attachments and tags upon successful creation.
 *
 * @param props.connection
 * @param props.body Article creation data including title, content, section reference, and optional attachments and tags.
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor user
 * @x-autobe-specification Implementation steps for article creation:
 *
 * 1. **Authentication Check**: Validate JWT token from Authorization header. Return 401 AUTH_REQUIRED if missing or invalid.
 *
 * 2. **Authorization Check**: Query discussion_board_users to verify user is not banned (check ban status). Return 403 USER_BANNED if banned.
 *
 * 3. **Validate Input**:
 *    - Validate title length (3-200 chars)
 *    - Validate content length (10-50,000 chars)
 *    - Validate section exists in discussion_board_sections table
 *    - Validate file attachments (count <= 10, individual size <= 10MB, total <= 50MB, allowed MIME types)
 *    - Validate image attachments (count <= 20, individual size <= 5MB, total <= 25MB, allowed formats, dimensions <= 8000x8000)
 *    - Validate tags (count <= 15, each 1-50 chars, alphanumeric with hyphens/underscores)
 *
 * 4. **Process Files**: For each file attachment:
 *    - Generate unique storage path
 *    - Store file in file system
 *    - Create discussion_board_article_files record
 *
 * 5. **Process Images**: For each image attachment:
 *    - Validate image integrity
 *    - Extract dimensions
 *    - Generate unique storage path
 *    - Store image in file system
 *    - Create discussion_board_article_images record
 *
 * 6. **Process Tags**: For each tag:
 *    - Normalize to lowercase, trim whitespace
 *    - Check if tag exists in discussion_board_tags (by unique value)
 *    - If not exists, create new tag record
 *    - Create discussion_board_article_tags association
 *
 * 7. **Create Article**: Insert record into discussion_board_articles with:
 *    - id: generated UUID
 *    - discussion_board_section_id: from request
 *    - discussion_board_user_id: authenticated user's id
 *    - title: from request
 *    - content: from request
 *    - created_at: current timestamp
 *    - updated_at: current timestamp
 *    - deleted_at: null
 *
 * 8. **Return Response**: Query and return the complete article with all relations (section, author, files, images, tags).
 * @path /discussionBoard/user/articles
 * @accessor api.functional.discussionBoard.user.articles.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
