/**
 * Retrieve a paginated list of ban and unban history records for a specific user.
 *
 * This endpoint provides administrators with comprehensive visibility into the moderation actions taken against a user. Each history entry captures whether the action was a ban or unban, the administrator who performed the action, the reason provided, and the timestamp.
 *
 * The discussion_board_ban_histories table maintains an immutable audit trail as specified in FR-AUDIT-001. Records persist even after users are deleted or unbanned, ensuring compliance and administrative accountability.
 *
 * Administrators can filter the history by action type (BAN or UNBAN) to focus on specific types of moderation actions. Date range filtering supports compliance audits and historical analysis. Results are sorted by creation timestamp in descending order, showing the most recent actions first.
 *
 * This operation supports FR-AUDIT-002 which requires displaying ban/unban history when administrators view a user's profile.
 *
 * @param props.connection
 * @param props.userId The unique identifier of the user whose ban history is being retrieved
 * @param props.body Search criteria including pagination and filter options for action type and date range
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor user
 * @x-autobe-specification Query discussion_board_ban_histories table filtering by discussion_board_user_id matching the path parameter.
 *
 * Apply search filters:
 * - Filter by action_type if provided (BAN or UNBAN)
 * - Filter by created_at date range if provided (from/to)
 *
 * Join with discussion_board_users table to resolve administrator details (actor_id) for display name.
 *
 * Implement cursor-based pagination with configurable page size (default 20, max 100).
 *
 * Sort results by created_at in descending order (most recent first).
 *
 * Include referenced ban details via discussion_board_ban_id for unban actions.
 *
 * Return paginated response with data array and pagination metadata (total count, has_more, cursor).
 * @path /discussionBoard/user/users/:userId/ban-histories
 * @accessor api.functional.discussionBoard.user.users.ban_histories.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * The unique identifier of the user whose ban history is being retrieved
     */
    userId: string;

    /**
     * Search criteria including pagination and filter options for action type and date range
     */
    body: IDiscussionBoardBanHistory.IRequest;
  };
  export type Body = IDiscussionBoardBanHistory.IRequest;
  export type Response = IPageIDiscussionBoardBanHistory.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/discussionBoard/user/users/:userId/ban-histories",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/discussionBoard/user/users/${encodeURIComponent(props.userId ?? "null")}/ban-histories`;
  export const random = (): IPageIDiscussionBoardBanHistory.ISummary =>
    typia.random<IPageIDiscussionBoardBanHistory.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("userId")(() => typia.assert(props.userId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
