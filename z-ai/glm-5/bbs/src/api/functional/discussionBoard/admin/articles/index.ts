/**
 * Permanently removes an article from public view with cascade deletion of all associated content.
 *
 * This operation allows article authors to remove their own articles when they no longer wish to keep them published. Administrators can delete any article regardless of authorship for moderation purposes. When an article is deleted, all comments and attachments associated with the article are automatically removed from the system.
 *
 * The deletion is implemented as a soft delete operation - the article is marked as deleted via a timestamp but retained in the database. This preserves referential integrity and allows for potential data recovery if needed. Once deleted, the article is no longer visible in any public listings or search results.
 *
 * Authorization requirements:
 * - Members: Can only delete articles they authored
 * - Administrators: Can delete any article
 * - Banned users: Cannot delete articles even if they own them
 *
 * Related operations:
 * - PATCH /articles - List articles to find the articleId before deletion
 * - GET /articles/{articleId} - View article details before deciding to delete
 *
 * @param props.connection
 * @param props.articleId Unique identifier of the article to delete. Must be a valid UUID referencing an existing article that has not been previously deleted.
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor admin
 * @x-autobe-specification Implementation logic:
 *
 * 1. AUTHENTICATION CHECK
 *    - Require authenticated user (member or admin)
 *    - Reject with 401 if not authenticated
 *
 * 2. ARTICLE LOOKUP
 *    - Query discussion_board_articles by articleId (UUID)
 *    - Include where deleted_at IS NULL to exclude already deleted articles
 *    - Return 404 if article not found
 *
 * 3. OWNERSHIP VALIDATION
 *    - If user is member (not admin): verify member.id === article.member_id
 *    - If user is admin: skip ownership check (admins can delete any article)
 *    - Return 403 if ownership validation fails
 *
 * 4. BANNED STATUS CHECK
 *    - If user is banned (member.banned === true): reject with 403
 *    - Note: Even if banned user owns the article, they cannot perform actions
 *
 * 5. SOFT DELETE EXECUTION
 *    - Set article.deleted_at = current timestamp
 *    - Cascade soft delete all comments: UPDATE discussion_board_comments SET deleted_at = NOW() WHERE discussion_board_article_id = articleId AND deleted_at IS NULL
 *    - Note: Attachments have Cascade relation, but for soft delete pattern, consider whether to mark them deleted or keep them
 *
 * 6. TRANSACTION BOUNDARY
 *    - Perform all updates in single transaction
 *    - Atomic operation - all or nothing
 *
 * 7. RESPONSE
 *    - Return the deleted article object with updated deleted_at timestamp
 * @path /discussionBoard/admin/articles/:articleId
 * @accessor api.functional.discussionBoard.admin.articles.erase
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function erase(
  connection: IConnection,
  props: erase.Props,
): Promise<void> {
  return true === connection.simulate
    ? erase.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...erase.METADATA,
          path: erase.path(props),
          status: null,
        },
      );
}
export namespace erase {
  export type Props = {
    /**
     * Unique identifier of the article to delete. Must be a valid UUID referencing an existing article that has not been previously deleted.
     */
    articleId: string & tags.Format<"uuid">;
  };

  export const METADATA = {
    method: "DELETE",
    path: "/discussionBoard/admin/articles/:articleId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/admin/articles/${encodeURIComponent(props.articleId ?? "null")}`;
  export const random = (): void => typia.random<void>();
  export const simulate = (
    connection: IConnection,
    props: erase.Props,
  ): void => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: erase.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("articleId")(() => typia.assert(props.articleId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
