/**
 * Ban a user from the platform, preventing them from logging in while preserving their existing content.
 *
 * This operation allows administrators to restrict platform access for users who violate community guidelines or terms of service. When a user is banned, they cannot log in to the platform, but their existing articles and comments remain visible to other users to maintain discussion continuity.
 * The operation enforces strict authorization rules based on the administrative hierarchy:
 * - Regular administrators can ban regular users but cannot ban other administrators or super administrators
 * - Super administrators can ban regular users and regular administrators
 * - Super administrators can ban other super administrators
 * - No administrator can ban themselves
 *
 * The ban reason must be between 10 and 1000 characters and is recorded for transparency, audit purposes, and potential appeals processes. All ban records in the discussion_board_bans table are immutable and persist indefinitely for compliance and administrative oversight, even after unbanning.
 *
 * Upon successful ban execution, the system immediately terminates all active sessions for the banned user from the discussion_board_user_sessions table, ensuring they cannot continue using authenticated features. The user's is_banned flag in discussion_board_users is updated to reflect the banned state.
 *
 * This operation may fail with the following error conditions:
 * - BAN_SELF_PROHIBITED (400): Administrator attempting to ban themselves
 * - BAN_INSUFFICIENT_PERMISSION (403): Administrator lacks permission to ban target user
 * - USER_ALREADY_BANNED (400): Target user is already banned
 * - BAN_REASON_REQUIRED (400): Ban reason not provided
 * - BAN_REASON_TOO_SHORT (400): Ban reason is less than 10 characters
 * - BAN_REASON_TOO_LONG (400): Ban reason exceeds 1,000 characters
 *
 * @param props.connection
 * @param props.body Ban creation details including target user identifier and ban reason text (10-1000 characters).
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor null
 * @x-autobe-specification Implementation steps for ban creation:
 *
 * 1. **Authorization Validation**:
 *    - Extract administrator ID from authenticated session
 *    - Verify the authenticated user has ADMINISTRATOR or SUPER_ADMINISTRATOR permission level
 *    - Return 401 if not authenticated, 403 if not an administrator
 *
 * 2. **Self-Ban Prevention**:
 *    - Compare target user ID with administrator's own user ID
 *    - If equal, return error with code BAN_SELF_PROHIBITED (400)
 *
 * 3. **Permission Hierarchy Check**:
 *    - Query discussion_board_users to get target user's permission_level
 *    - Compare administrator's permission level with target's:
 *      - MEMBER < ADMINISTRATOR < SUPER_ADMINISTRATOR
 *    - If target has equal or higher permission, return error with code BAN_INSUFFICIENT_PERMISSION (403)
 *
 * 4. **Already-Banned Check**:
 *    - Check if target user's is_banned field is true
 *    - If already banned, return error with code USER_ALREADY_BANNED (400)
 *
 * 5. **Reason Validation**:
 *    - Verify reason is provided and not empty
 *    - If missing, return error with code BAN_REASON_REQUIRED (400)
 *    - If length > 1000 characters, return error with code BAN_REASON_TOO_LONG (400)
 *
 * 6. **Ban Record Creation**:
 *    - Generate UUID for new ban record
 *    - Insert record into discussion_board_bans with:
 *      - id: generated UUID
 *      - discussion_board_user_id: target user ID from request
 *      - discussion_board_administrator_id: administrator's user ID from session
 *      - reason: validated reason text
 *      - created_at: current timestamp
 *
 * 7. **User Status Update**:
 *    - Update discussion_board_users record for target user:
 *      - Set is_banned = true
 *      - Set banned_by = administrator's user ID
 *      - Set updated_at = current timestamp
 *
 * 8. **Session Invalidation**:
 *    - Query discussion_board_user_sessions for all sessions belonging to target user
 *    - Delete all found session records (or mark as invalidated)
 *
 * 9. **Response**:
 *    - Return the created ban record with full details including administrator info and timestamp
 * @path /discussionBoard/bans
 * @accessor api.functional.discussionBoard.bans.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
