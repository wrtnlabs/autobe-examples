/**
 * Update the set of tags associated with a specific article.
 *
 * This operation allows authenticated users to replace all tags on their own articles. Tags provide flexible, user-defined categorization beyond section-based organization. The operation validates each tag value, normalizes them to lowercase, removes duplicates, and updates the article-tag associations.
 *
 * **Authorization**: Only the article author can update tags. Banned users are denied access regardless of ownership. Administrators cannot edit user article tags (only deletion rights are granted to administrators).
 *
 * **Validation Rules**:
 * - Maximum 15 tags per article
 * - Each tag must be 1-50 characters
 * - Tags can only contain alphanumeric characters, hyphens (-), and underscores (_)
 * - Tags are normalized to lowercase before storage
 * - Duplicate tags (after normalization) are automatically removed
 *
 * **Process**:
 * 1. Verify article exists and user is the author
 * 2. Validate each tag in the request
 * 3. Normalize tags to lowercase and remove duplicates
 * 4. For each tag, create or reference existing tag in discussion_board_tags
 * 5. Remove existing article-tag associations
 * 6. Create new article-tag associations in discussion_board_article_tags
 *
 * **Database References**:
 * - discussion_board_articles.id - the target article
 * - discussion_board_tags - master tag registry (tags are reused platform-wide)
 * - discussion_board_article_tags - junction table for article-tag relationships
 *
 * @param props.connection
 * @param props.articleId Unique identifier of the article whose tags are being updated
 * @param props.body Array of tag strings to associate with the article (replaces existing tags)
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor null
 * @x-autobe-specification Implementation requires transaction-based tag replacement workflow:
 *
 * 1. **Authentication & Authorization Check**:
 *    - Extract user ID from JWT token
 *    - Query discussion_board_articles to verify articleId exists
 *    - Verify discussion_board_user_id matches authenticated user ID
 *    - Check user is not banned (via discussion_board_users.permission_level or discussion_board_bans)
 *
 * 2. **Tag Validation & Normalization**:
 *    - Validate array length <= 15
 *    - For each tag string:
 *      - Trim whitespace
 *      - Validate length 1-50 characters
 *      - Validate regex pattern: ^[a-zA-Z0-9_-]+$ (alphanumeric, hyphen, underscore only)
 *      - Convert to lowercase for normalization
 *    - Remove duplicate values after normalization
 *
 * 3. **Transaction-Based Update**:
 *    - Begin database transaction
 *    - For each normalized tag value:
 *      - INSERT INTO discussion_board_tags (id, value, created_at, updated_at) if not exists (ON CONFLICT DO NOTHING)
 *      - Retrieve tag ID (existing or newly created)
 *    - DELETE FROM discussion_board_article_tags WHERE discussion_board_article_id = :articleId
 *    - For each tag:
 *      - INSERT INTO discussion_board_article_tags (id, discussion_board_article_id, discussion_board_tag_id, created_at)
 *    - Commit transaction
 *
 * 4. **Response Construction**:
 *    - Query updated tags for the article
 *    - Return paginated format with all associated tags
 * @path /discussionBoard/articles/:articleId/tags
 * @accessor api.functional.discussionBoard.articles.tags.updateTags
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function updateTags(
  connection: IConnection,
  props: updateTags.Props,
): Promise<updateTags.Response> {
  return true === connection.simulate
    ? updateTags.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...updateTags.METADATA,
          path: updateTags.path(props),
          status: null,
        },
        props.body,
      );
}
