/**
 * Retrieve a paginated list of attachments associated with a specific article.
 *
 * This operation allows users to browse and search through all file and image attachments belonging to an article. Each attachment is displayed with its type classification (file or image), original filename, file extension, size in bytes, and upload timestamp. The operation supports filtering by attachment type and searching by filename.
 *
 * Access to attachments follows the parent article's visibility rules. Users who can view the article (guests, members, administrators) can also view the attachment list. Attachment type classification enables proper display handling - images can be shown inline while files are presented as downloadable links.
 *
 * The attachment metadata returned by this endpoint is used to populate the attachment section of article detail pages. For actual file download, use the separate attachment download endpoint with the attachment ID.
 *
 * Administrators can view attachments for any article, while members and guests can view attachments only for articles they have permission to read. This operation does not expose internal storage paths; file retrieval requires the dedicated download endpoint.
 *
 * @param props.connection
 * @param props.articleId Unique identifier of the article whose attachments are being listed. The article must exist and not be soft-deleted. User must have permission to view the article to access its attachment list.
 * @param props.body Search criteria for filtering and paginating attachments. Supports filtering by attachment type (file or image), partial filename search, extension filtering, and pagination parameters.
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor null
 * @x-autobe-specification Query discussion_board_article_attachments table with pagination and filtering capabilities.
 *
 * 1. Validate the articleId path parameter exists in discussion_board_articles table (not soft-deleted).
 * 2. Verify the user has permission to view the article (article not deleted, user is guest/member/admin with article view access).
 * 3. Build WHERE clause:
 *    - Always filter by discussion_board_article_id = articleId
 *    - Optional: type filter ('file' or 'image')
 *    - Optional: name ILIKE '%searchTerm%' for partial name matching
 *    - Optional: extension IN (...) for extension filtering
 * 4. Apply sorting: default created_at DESC, configurable by name, size, created_at
 * 5. Execute paginated query returning total count and page data.
 * 6. Transform results to summary format excluding internal 'path' field.
 * 7. Return IPageIDiscussionBoardArticleAttachment.ISummary with pagination metadata.
 *
 * Edge cases:
 * - Article not found or deleted: return 404
 * - No attachments: return empty page with zero total
 * - Invalid type filter value: return 400
 * @path /discussionBoard/articles/:articleId/attachments
 * @accessor api.functional.discussionBoard.articles.attachments.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Unique identifier of the article whose attachments are being listed. The article must exist and not be soft-deleted. User must have permission to view the article to access its attachment list.
     */
    articleId: string & tags.Format<"uuid">;

    /**
     * Search criteria for filtering and paginating attachments. Supports filtering by attachment type (file or image), partial filename search, extension filtering, and pagination parameters.
     */
    body: IDiscussionBoardArticleAttachment.IRequest;
  };
  export type Body = IDiscussionBoardArticleAttachment.IRequest;
  export type Response = IPageIDiscussionBoardArticleAttachment.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/discussionBoard/articles/:articleId/attachments",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/discussionBoard/articles/${encodeURIComponent(props.articleId ?? "null")}/attachments`;
  export const random = (): IPageIDiscussionBoardArticleAttachment.ISummary =>
    typia.random<IPageIDiscussionBoardArticleAttachment.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("articleId")(() => typia.assert(props.articleId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

