/**
 * Registers a new user account on the Economic/Political Discussion Board platform.
 *
 * The join operation creates a new user account with email and password authentication. The email must be unique across all users in the discussion_board_users table. The password must meet security requirements: minimum 8 characters, at least one uppercase letter, at least one lowercase letter, at least one number, and at least one special character. The password is securely hashed using bcrypt before storage in the password_hash field.
 *
 * Upon successful registration, the user is assigned MEMBER permission_level, which grants access to create articles, write comments, and manage their own content. A display_name is required and will be shown publicly alongside the user's content and on their profile.
 *
 * The response includes a JWT access token (valid for 15 minutes) and a refresh token (valid for 7 days), enabling immediate authenticated access without requiring a separate login. The access token contains the user's id, email, and permission_level claims for authorization checks on subsequent API calls.
 *
 * This is a public endpoint requiring no prior authentication. After registration, users can immediately access all member-level features including article creation, commenting, and profile management.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body User registration information including email, password, and display name.
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor user
 * @x-autobe-specification Implementation: 1) Validate email format and check uniqueness against discussion_board_users.email (unique constraint). 2) Validate password meets security requirements: minimum 8 characters, at least one uppercase, one lowercase, one number, one special character. 3) Hash password using bcrypt with appropriate salt rounds. 4) Generate new UUID for user id. 5) Create citizen record for sequential ID via discussion_board_user_citizens. 6) Insert new user record with permission_level='MEMBER', is_banned=false, display_name from request. 7) Create new session record in discussion_board_user_sessions with access_token (15min expiry), refresh_token (7day expiry), and connection metadata. 8) Return tokens and user profile in IAuthorized response.
 * @path /discussionBoard/auth/user/join
 * @accessor api.functional.discussionBoard.auth.user.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
