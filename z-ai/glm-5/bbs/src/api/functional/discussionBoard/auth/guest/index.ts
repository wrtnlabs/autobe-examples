/**
 * Renews JWT access and refresh tokens for an existing guest session.
 *
 * This endpoint handles token refresh for guest actors who have already established a session through the join operation. The system validates the provided refresh token by verifying its cryptographic signature, checking that the session identifier exists in the discussion_board_guest_sessions table, and confirming the session has not exceeded its expiration time defined in expired_at.
 *
 * Upon successful validation, the operation generates a new access token and refresh token pair, implementing the single-use refresh token pattern where the previous refresh token is invalidated upon use. This approach enhances security by preventing token replay attacks. The new access token contains updated claims including the guest identifier (discussion_board_guests.id), session identifier, fresh expiration timestamp, and token type 'access'. The new refresh token follows the same structure with token type 'refresh'.
 *
 * Connection metadata can be updated during refresh to maintain accurate session tracking. The href (current page URL) and referrer information captured during refresh help maintain navigation context analytics and traffic source analysis. The IP address is automatically captured from the request for security auditing purposes.
 *
 * The refresh operation maintains the guest's read-only access to public content. If the guest account has been soft-deleted (deleted_at is not null) or the session has been terminated, the refresh request is rejected and the client must initiate a new join operation.
 *
 * Token validation failures are handled securely without revealing implementation details. Failed validation due to expired tokens, invalid signatures, or session termination results in an authentication error that prompts the client to re-establish a new guest session through the join endpoint.
 *
 * Related operations: This operation follows the join operation in the guest authentication workflow. A successful refresh should be followed by using the new access token for subsequent API requests until it expires.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Refresh token and optional connection metadata for renewing guest session tokens.
 * @x-autobe-authorization-type refresh
 * @x-autobe-authorization-actor guest
 * @x-autobe-specification Implementation of guest token refresh operation:
 *
 * 1. Validate the refresh token format and signature using the stored cryptographic key
 * 2. Extract claims from the refresh token: user identifier (guest.id), session identifier
 * 3. Verify the session exists and is still active in discussion_board_guest_sessions table
 * 4. Verify the session has not expired (check expired_at against current timestamp)
 * 5. Verify the guest account is not deleted (check deleted_at is null in discussion_board_guests table)
 * 6. Update the session record with new connection metadata:
 *    - ip (from request IP, if changed)
 *    - href (from request body, if provided)
 *    - referrer (from request body, if provided)
 * 7. Generate new JWT access token with fresh expiration
 * 8. Generate new JWT refresh token with fresh expiration
 * 9. Invalidate the previous refresh token (single-use refresh token pattern for security)
 * 10. Return both new tokens with updated expiration information
 *
 * Edge cases:
 * - Expired refresh token: Return authentication error, require re-join
 * - Invalid refresh token signature: Return authentication error, terminate session
 * - Session not found: Return authentication error
 * - Guest account deleted: Return authentication error
 * - Token tampering detected: Reject request, invalidate session for security
 *
 * This endpoint requires a valid refresh token from a previous join or refresh operation.
 * @path /discussionBoard/auth/guest/refresh
 * @accessor api.functional.discussionBoard.auth.guest.refresh
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
