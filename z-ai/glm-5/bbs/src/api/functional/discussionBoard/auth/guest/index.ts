/**
 * Creates a new guest identity and establishes an initial session for unauthenticated visitors.
 *
 * This endpoint handles the registration of new guest actors in the discussion board system. Unlike traditional user registration, guests are identified by their device fingerprint rather than email and password credentials. The system creates a new record in the discussion_board_guests table with the provided device_fingerprint, which serves as the unique identifier for anonymous visitor tracking.
 *
 * Upon successful guest creation, a new session is established in the discussion_board_guest_sessions table, capturing connection metadata including the IP address for security tracking, the current page URL (href) for navigation context analytics, and optional referrer information for traffic source analysis. Each session has an explicit expiration time defined in expired_at to enforce session lifecycle management.
 *
 * The operation returns JWT tokens for subsequent authenticated requests: an access token for API authorization and a refresh token for token renewal. Both tokens contain claims for user identifier (the guest's UUID), session identifier, expiration timestamp, and token type. The access token has a shorter lifespan for security, while the refresh token enables seamless session continuation.
 *
 * Guest accounts have read-only access to public content including sections, articles, comments, and user profiles. They cannot create, edit, or delete any content on the platform. This join operation is the entry point for the guest authentication workflow, followed by refresh operations to maintain session validity.
 *
 * Security considerations: Device fingerprint provides anonymous identification without requiring personal information. Session metadata (IP, href, referrer) is captured for security auditing and fraud prevention. Tokens should be transmitted over HTTPS and stored securely by the client.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Guest registration information including device fingerprint for anonymous identification and optional connection metadata for session tracking.
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor guest
 * @x-autobe-specification Implementation of guest join operation:
 *
 * 1. Validate the device_fingerprint is provided and check for uniqueness (if already exists, may return existing guest or reject - business decision)
 * 2. Create a new record in discussion_board_guests table with the provided device_fingerprint
 * 3. Create a new session record in discussion_board_guest_sessions table with:
 *    - discussion_board_guest_id (from newly created guest)
 *    - ip (from request IP)
 *    - href (from request body)
 *    - referrer (from request body, nullable)
 *    - created_at (current timestamp)
 *    - expired_at (calculated based on session duration policy)
 * 4. Generate JWT access token with claims: user identifier (guest.id), session identifier, expiration timestamp, token type 'access'
 * 5. Generate JWT refresh token with claims: user identifier, session identifier, expiration timestamp, token type 'refresh'
 * 6. Return both tokens with expiration information
 *
 * Edge cases:
 * - Device fingerprint already exists: Should return existing guest or create new (business logic decision)
 * - Invalid fingerprint format: Return validation error
 * - Session creation failure: Rollback guest creation
 *
 * This is a public endpoint - no pre-authentication required.
 * @path /discussionBoard/auth/guest/join
 * @accessor api.functional.discussionBoard.auth.guest.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
