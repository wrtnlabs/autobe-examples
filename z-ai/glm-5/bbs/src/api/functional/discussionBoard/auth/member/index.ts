/**
 * Registers a new member account with email and password credentials on the discussion board platform.
 *
 * This operation creates a new member account in the discussion_board_members table. The system requires a valid email address (unique across all members) and a password meeting security complexity requirements. The email is validated for proper format, and the system checks for duplicate registrations.
 *
 * Upon successful registration, the member receives an authenticated session with JWT tokens. The access token is short-lived for security, while the refresh token allows session continuation. A session record is created in discussion_board_member_sessions to track the login with client metadata (IP address, href, referrer) for audit purposes.
 *
 * The system initializes the member with default profile values: display_name (required field), empty bio (optional), and active status (banned=false). The password is securely hashed before storage using bcrypt. No email verification is required - the member can immediately access platform features.
 *
 * Error handling includes duplicate email rejection, invalid email format, and password complexity validation failures. All error messages are generic to prevent email enumeration attacks.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Member registration credentials and initial profile information
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor member
 * @x-autobe-specification Implement member registration by creating a new discussion_board_members record. Validate email format and uniqueness (email must not exist in discussion_board_members). Validate password meets security requirements. Hash password using bcrypt. Initialize with display_name from email prefix or empty, null bio, banned=false, created_at=now, updated_at=now, deleted_at=null. Generate JWT access token and refresh token. Create discussion_board_member_sessions record with IP, href, referrer, created_at=now, expired_at=access token expiry. Return IAuthorized with tokens and member info.
 * @path /discussionBoard/auth/member/join
 * @accessor api.functional.discussionBoard.auth.member.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
