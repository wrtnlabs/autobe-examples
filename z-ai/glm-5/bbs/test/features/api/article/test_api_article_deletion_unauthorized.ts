export async function test_api_article_deletion_unauthorized(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register member A (article author)
  const memberAConnection: api.IConnection = { host: connection.host };
  const memberA = await authorize_member_join(memberAConnection, {});
  typia.assert(memberA);
  // 2. Create article as member A
  const article = await generate_random_discussion_board_member_articles_create(
    memberAConnection,
    {},
  );
  typia.assert(article);
  // 3. Register member B (different member - unauthorized for this article)
  const memberBConnection: api.IConnection = { host: connection.host };
  const memberB = await authorize_member_join(memberBConnection, {});
  typia.assert(memberB);
  // 4. Attempt to delete member A's article as member B (should fail with 403)
  await TestValidator.httpError(
    "member B cannot delete member A's article",
    403,
    async () =>
      await api.functional.discussionBoard.member.articles.erase(
        memberBConnection,
        { articleId: article.id },
      ),
  );
}
