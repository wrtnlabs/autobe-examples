export async function test_api_article_attachment_deletion_by_author(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as a member
  const memberConnection: api.IConnection = { host: connection.host };
  const member = await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      displayName: RandomGenerator.name(),
      bio: null,
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    },
  });
  typia.assert(member);
  // 2. Create an article
  const article = await generate_random_discussion_board_member_articles_create(
    memberConnection,
    {
      body: {
        title: RandomGenerator.paragraph({ sentences: 2 }),
        content: RandomGenerator.content({ paragraphs: 3 }),
        section_id: typia.random<string & tags.Format<"uuid">>(),
      },
    },
  );
  typia.assert(article);
  // 3. Create an attachment for the article
  const attachment =
    await generate_random_discussion_board_member_articles_attachments_create(
      memberConnection,
      {
        params: { articleId: article.id },
        body: {
          type: "file",
          name: RandomGenerator.name() + ".pdf",
          extension: "pdf",
          size: typia.random<
            number &
              tags.Type<"int32"> &
              tags.Minimum<1> &
              tags.Maximum<1000000>
          >(),
          url: typia.random<string & tags.Format<"uri">>(),
        },
      },
    );
  typia.assert(attachment);
  // 4. Delete the attachment by the author
  await api.functional.discussionBoard.member.articles.attachments.erase(
    memberConnection,
    {
      articleId: article.id,
      attachmentId: attachment.id,
    },
  );
  // 5. Verify deletion - attempting to delete again should return 404
  await TestValidator.httpError(
    "deleted attachment should not be found",
    404,
    async () => {
      await api.functional.discussionBoard.member.articles.attachments.erase(
        memberConnection,
        {
          articleId: article.id,
          attachmentId: attachment.id,
        },
      );
    },
  );
}
