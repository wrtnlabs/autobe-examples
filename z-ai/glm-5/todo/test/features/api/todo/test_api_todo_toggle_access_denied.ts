export async function test_api_todo_toggle_access_denied(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create member A who will own the todo
  const memberAConnection: api.IConnection = { host: connection.host };
  const memberA = await authorize_member_join(memberAConnection, {});
  typia.assert(memberA);
  // 2. Create a todo owned by member A
  const todo = await generate_random_private_todo_app_member_todos_create(
    memberAConnection,
    {},
  );
  typia.assert(todo);
  // 3. Create member B who will attempt unauthorized toggle
  const memberBConnection: api.IConnection = { host: connection.host };
  const memberB = await authorize_member_join(memberBConnection, {});
  typia.assert(memberB);
  // 4. As member B, attempt to toggle member A's todo - should fail with 403
  await TestValidator.httpError(
    "unauthorized toggle returns 403",
    403,
    async () => {
      await api.functional.privateTodoApp.member.todos.toggle(
        memberBConnection,
        {
          todoId: todo.id,
        },
      );
    },
  );
}
