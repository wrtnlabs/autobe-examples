export async function test_api_todo_update_cross_member_denied(
  connection: api.IConnection,
): Promise<void> {
  // Step 1: Create a todo as Member A (first authenticated member)
  const memberAConnection: api.IConnection = { host: connection.host };
  const memberAAuth = await authorize_member_join(memberAConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      displayName: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  typia.assert(memberAAuth);
  // Create a todo owned by Member A
  const todo = await api.functional.todoApp.member.todos.create(
    memberAConnection,
    {
      body: {
        title: RandomGenerator.paragraph({ sentences: 2 }),
        description: RandomGenerator.content({ paragraphs: 1 }),
      } satisfies ITodoAppTodo.ICreate,
    },
  );
  typia.assert(todo);
  // Step 2: Authenticate as Member B (second member) with fresh credentials
  const memberBConnection: api.IConnection = { host: connection.host };
  const memberBAuth = await authorize_member_join(memberBConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      displayName: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  typia.assert(memberBAuth);
  // Step 3: Attempt to update Member A's todo using its todoId while authenticated as Member B
  // This should be denied with appropriate authorization error
  await TestValidator.error(
    "should deny cross-member todo update",
    async () => {
      await api.functional.todoApp.member.todos.update(memberBConnection, {
        todoId: todo.id,
        body: {
          title: "Attempted Unauthorized Update",
          description: "This should not succeed",
        } satisfies ITodoAppTodo.IUpdate,
      });
    },
  );
}
