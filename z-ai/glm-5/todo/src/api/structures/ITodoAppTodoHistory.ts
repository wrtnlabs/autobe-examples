import { tags } from "typia";

export namespace ITodoAppTodoHistory {
  /**
   * Summary representation of a todo edit history entry capturing a single edit operation. Shows when the edit occurred (created_at) and which fields were modified. Fields that were not changed during this edit are null, while modified fields contain their new values. Provides a clear audit trail of all modifications to a todo item.
   */
  export type ISummary = {
    /**
     * Unique identifier for this edit history entry.
     *
     * @x-autobe-database-schema-property id
     * @x-autobe-specification Direct mapping from todo_app_todo_histories.id. UUID primary key uniquely identifying this history entry.
     */
    id: string & tags.Format<"uuid">;

    /**
     * Timestamp when this edit was performed.
     *
     * @x-autobe-database-schema-property created_at
     * @x-autobe-specification Direct mapping from todo_app_todo_histories.created_at. Timestamp when this edit operation occurred, used for sorting history entries from most recent to oldest.
     */
    created_at: string & tags.Format<"date-time">;

    /**
     * New title value after the edit, or null if title was unchanged.
     *
     * @x-autobe-database-schema-property title
     * @x-autobe-specification Direct mapping from todo_app_todo_histories.title. Nullable string containing the new title value after this edit. Null indicates the title was not modified during this edit operation.
     */
    title: string | null;

    /**
     * New description value after the edit, or null if description was unchanged.
     *
     * @x-autobe-database-schema-property description
     * @x-autobe-specification Direct mapping from todo_app_todo_histories.description. Nullable string containing the new description value after this edit. Null indicates the description was not modified during this edit operation.
     */
    description: string | null;

    /**
     * New start date value after the edit, or null if start date was unchanged.
     *
     * @x-autobe-database-schema-property start_date
     * @x-autobe-specification Direct mapping from todo_app_todo_histories.start_date. Nullable timestamp containing the new start date value after this edit. Null indicates the start date was not modified during this edit operation.
     */
    start_date: (string & tags.Format<"date-time">) | null;

    /**
     * New due date value after the edit, or null if due date was unchanged.
     *
     * @x-autobe-database-schema-property due_date
     * @x-autobe-specification Direct mapping from todo_app_todo_histories.due_date. Nullable timestamp containing the new due date value after this edit. Null indicates the due date was not modified during this edit operation.
     */
    due_date: (string & tags.Format<"date-time">) | null;
  };

  /**
   * Pagination parameters for retrieving edit history entries. Supports cursor-based and page-based navigation for efficiently paging through history entries sorted from most recent to oldest.
   */
  export type IRequest = {
    /**
     * Cursor token for cursor-based pagination. Pass the cursor from a previous response to fetch the next page of results.
     *
     * @x-autobe-specification Base64-encoded cursor token representing the position in the result set. Used for cursor-based pagination where the cursor encodes the last seen record's created_at value. When provided, returns records after this cursor position. Takes precedence over page parameter if both are provided. Generated by the server and included in previous page's pagination metadata.
     */
    cursor?: string | null | undefined;

    /**
     * Maximum number of history entries to return per page (1-100).
     *
     * @x-autobe-specification Maximum number of history entries to return per page. Applied as LIMIT clause in SQL query. Minimum value is 1, maximum is 100. If not provided, defaults to 20. Actual count may be less on the last page.
     */
    limit?:
      | (number & tags.Type<"int32"> & tags.Minimum<1> & tags.Maximum<100>)
      | undefined;

    /**
     * Target page number to retrieve (1-indexed). Defaults to 1 if not provided.
     *
     * @x-autobe-specification 1-indexed page number for offset-based pagination. Used to calculate OFFSET as (page - 1) * limit. If omitted or null, defaults to page 1 (first page). Requesting a page beyond available range returns empty data array with valid pagination metadata. Ignored if cursor parameter is provided.
     */
    page?: null | (number & tags.Type<"int32"> & tags.Minimum<0>) | undefined;
  };
}
