import { IPrivateTodoAppMember } from "../../../../structures/IPrivateTodoAppMember";

/**
 * Retrieve the authenticated member's profile information.
 *
 * This operation allows authenticated members to view their own profile, which contains their display name. The profile is completely private - each member can only access their own profile, and there is no mechanism to view other members' profiles.
 *
 * The display_name field in the private_todo_app_members table is an optional display name shown in the member's profile. It can be left empty or unset at any time, and is only visible to the profile owner.
 *
 * This operation requires authentication. Unauthenticated requests will be rejected with an authorization error.
 *
 * @param props.connection
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor member
 * @x-autobe-specification Query the private_todo_app_members table by the
 *   authenticated member's ID derived from the session token. Return only
 *   profile-safe fields: display_name. Exclude sensitive fields: email,
 *   password_hash. Enforce that the member can only retrieve their own profile
 *   - the session context provides the member ID. If no valid session exists,
 *   return 401 Unauthorized. The display_name field is optional and may be null
 *   if the member has not set it.
 * @path /privateTodoApp/member/profile
 * @accessor api.functional.privateTodoApp.member.profile.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(connection: IConnection): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(),
          status: null,
        },
      );
}
export namespace at {
  export type Response = IPrivateTodoAppMember;

  export const METADATA = {
    method: "GET",
    path: "/privateTodoApp/member/profile",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/privateTodoApp/member/profile";
  export const random = (): IPrivateTodoAppMember =>
    typia.random<IPrivateTodoAppMember>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}

/**
 * Update the authenticated member's profile display name.
 *
 * This operation allows members to modify their display name, which is the only editable field in their private profile. The display name is only visible to the profile owner and is stored in the private_todo_app_members table.
 *
 * Members can set a display name to any valid string value, or clear it by passing null. This is a self-service operation restricted to the authenticated member's own profile - there is no mechanism to access or modify other members' profiles.
 *
 * Security and Privacy:
 * - Only authenticated members can access this endpoint
 * - Each member can only update their own profile
 * - The display name is private and visible only to the profile owner
 * - Profile updates do not affect any other member data
 *
 * @param props.connection
 * @param props.body Profile update data containing the new display name
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor member
 * @x-autobe-specification Update the authenticated member's display_name field
 *   in the private_todo_app_members table.
 *
 * 1. Extract the authenticated member's ID from the JWT token in the request context
 * 2. Validate the request body - display_name can be a string or null (to unset)
 * 3. If display_name is provided as a string, validate it meets length/format requirements
 * 4. Update the member record with the new display_name value
 * 5. Set updated_at to the current timestamp
 * 6. Return the updated member record (id, email, display_name, created_at, updated_at)
 *
 * Error handling:
 * - 401 Unauthorized if not authenticated
 * - 400 Bad Request if validation fails
 *
 * Note: display_name is nullable, so passing null clears the display name.
 * @path /privateTodoApp/member/profile
 * @accessor api.functional.privateTodoApp.member.profile.update
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function update(
  connection: IConnection,
  props: update.Props,
): Promise<update.Response> {
  return true === connection.simulate
    ? update.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...update.METADATA,
          path: update.path(),
          status: null,
        },
        props.body,
      );
}
export namespace update {
  export type Props = {
    /**
     * Profile update data containing the new display name
     */
    body: IPrivateTodoAppMember.IUpdate;
  };
  export type Body = IPrivateTodoAppMember.IUpdate;
  export type Response = IPrivateTodoAppMember;

  export const METADATA = {
    method: "PUT",
    path: "/privateTodoApp/member/profile",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/privateTodoApp/member/profile";
  export const random = (): IPrivateTodoAppMember =>
    typia.random<IPrivateTodoAppMember>();
  export const simulate = (
    connection: IConnection,
    props: update.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: update.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
