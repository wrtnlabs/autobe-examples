/**
 * Enables unauthenticated guests to sign up for a new member account in the private todo application.
 *
 * This operation is the primary entry point for new users joining the application. Guests provide their email address and password credentials to create a new member account. Upon successful registration, the system creates a new member record and returns authentication tokens (access token and refresh token) that establish an authenticated session.
 *
 * The email address must be unique across the system - if the email is already registered, the operation fails with a conflict error. The password must meet the system's security requirements including minimum length and complexity standards.
 *
 * Once the join operation succeeds, the guest transitions from an unauthenticated state to an authenticated member state with full access to their personal todo features including creating, viewing, editing, completing, and deleting todos.
 *
 * The response includes both an access token (short-lived, for API authentication) and a refresh token (long-lived, for token renewal), enabling the new member to maintain their authenticated session.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Guest join request containing email and password for new account registration.
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor guest
 * @x-autobe-specification Implementation of guest join operation for new user registration.
 *
 * **Service Layer Logic:**
 * 1. Validate the request body containing email and password
 * 2. Check if email already exists in the member table (prevent duplicate accounts)
 * 3. Hash the password using secure hashing algorithm (bcrypt/argon2)
 * 4. Create a new member record with email and hashed password
 * 5. Generate JWT access token and refresh token for the new member
 * 6. Optionally link the current guest session to the new member for analytics
 *
 * **Database Operations:**
 * - Read: Check member table for existing email
 * - Write: Create new member record
 * - Write: Create member session record
 *
 * **Business Rules:**
 * - Email must be unique across all members
 * - Password must meet minimum security requirements (length, complexity)
 * - Access token expires in 2 hours, refresh token in 14 days
 *
 * **Error Handling:**
 * - 400: Invalid email format or password requirements not met
 * - 409: Email already exists in system
 * - 500: Database or internal errors
 * @path /privateTodoApp/auth/guest/join
 * @accessor api.functional.privateTodoApp.auth.guest.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
