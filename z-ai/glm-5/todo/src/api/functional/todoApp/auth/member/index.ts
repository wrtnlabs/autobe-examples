/**
 * Registers a new member account in the todo application with email and password credentials.
 *
 * This endpoint creates a new authenticated user account in the todo_app_members table. The member's email serves as the unique authentication identifier across the system, and the password is securely hashed before storage. Upon successful registration, a JWT session is created in todo_app_member_sessions with the token identifier (jti claim), client connection metadata (IP address, href, referrer), and expiration timestamp.
 *
 * The todo_app_members table schema defines email as unique and required, password_hash as required, and display_name as required. The todo_app_member_sessions table enforces single-active-session-per-user policy through the unique token_identifier constraint.
 *
 * After registration, members gain full access to create, manage, and track their private todos with complete data isolation from other members. All todos and their edit histories are privately owned by the member.
 *
 * Related operations:
 * - POST /auth/member/login - Authenticate with registered credentials
 * - POST /auth/member/refresh - Renew access tokens
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Member registration credentials including email, password, and optional display name
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor member
 * @x-autobe-specification Implement user registration by validating email uniqueness against todo_app_members table, hashing the provided password using a secure algorithm (bcrypt/argon2), generating a unique UUID for the member, setting default display_name from the request or a generated default, recording created_at and updated_at timestamps, creating an initial session record in todo_app_member_sessions with a new JWT token (jti stored in token_identifier), and returning the access/refresh tokens with member profile information. The response includes the member's id, email, display_name, and JWT tokens. Email format validation must be performed before database operations. If email already exists, return a conflict error without revealing whether the email exists.
 * @path /todoApp/auth/member/join
 * @accessor api.functional.todoApp.auth.member.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
