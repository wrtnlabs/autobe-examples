import { HttpError, IConnection } from "@nestia/fetcher";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";

import { ITodoAppUser } from "../../../../structures/ITodoAppUser";

/**
 * Retrieve the authenticated user's profile information.
 *
 * This operation returns the current user's display name, which serves as their personalized identifier within the application. The display name is initialized to the user's email address upon registration and can be customized at any time through the profile update operation.
 *
 * Privacy is strictly enforced: users can only access their own profile through this endpoint. The response contains only the display name field, excluding all internal identifiers, authentication data, and metadata to maintain the privacy-first design principle of this application.
 *
 * The display name must be between 1 and 50 characters and cannot consist solely of whitespace. Multiple users may have identical display names as uniqueness is not required.
 *
 * @param props.connection
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor user
 * @x-autobe-specification Implementation steps:
 *
 * 1. Extract authenticated user ID from the JWT session token in the Authorization header
 * 2. Query the todo_app_users table to find the user record by ID
 * 3. Verify the user exists and is not soft-deleted (deleted_at IS NULL)
 * 4. Return only the display_name field in the response
 * 5. If user not found or session invalid, return 401 Unauthorized error
 *
 * Database query:
 * - SELECT display_name FROM todo_app_users WHERE id = ? AND deleted_at IS NULL
 *
 * Response construction:
 * - Build ITodoAppUser object containing only display_name
 * - Do not expose id, email, password_hash, or any other fields
 *
 * Error handling:
 * - 401 if not authenticated or session expired
 * - 401 if user account has been deleted
 * @path /todoApp/user/profile
 * @accessor api.functional.todoApp.user.profile.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(connection: IConnection): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(),
          status: null,
        },
      );
}
export namespace at {
  export type Response = ITodoAppUser;

  export const METADATA = {
    method: "GET",
    path: "/todoApp/user/profile",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/todoApp/user/profile";
  export const random = (): ITodoAppUser => typia.random<ITodoAppUser>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}

/**
 * Update the authenticated user's profile display name.
 *
 * This operation allows authenticated users to update their display name, which serves as their chosen identifier within the application. The display name is used for personalization and can be changed any number of times without restrictions.
 *
 * The display name must be between 1 and 50 characters in length and cannot consist solely of whitespace characters. Unlike the email address which is used for authentication, the display name can be customized to reflect the user's preferred identity and does not need to be unique across the system.
 *
 * This operation is subject to complete privacy enforcement - users can only update their own profile, and no mechanism exists to modify other users' profiles.
 *
 * @param props.connection
 * @param props.body New display name for the user profile
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor user
 * @x-autobe-specification Implementation steps:
 * 1. Extract authenticated user ID from JWT token in request headers
 * 2. Validate request body: display_name must be 1-50 chars, not blank
 * 3. Query todo_app_users table to find user by ID
 * 4. Verify user exists and is not deleted (deleted_at is null)
 * 5. Update display_name field in todo_app_users table
 * 6. Update updated_at timestamp to current time
 * 7. Return updated profile with display_name
 *
 * Validation rules:
 * - display_name minLength: 1 character
 * - display_name maxLength: 50 characters
 * - display_name must not be blank (not just whitespace)
 *
 * Error handling:
 * - Return 401 if not authenticated
 * - Return 400 if validation fails with specific error codes:
 *   - PROFILE_DISPLAY_NAME_TOO_SHORT
 *   - PROFILE_DISPLAY_NAME_TOO_LONG
 *   - PROFILE_DISPLAY_NAME_BLANK
 * @path /todoApp/user/profile
 * @accessor api.functional.todoApp.user.profile.update
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function update(
  connection: IConnection,
  props: update.Props,
): Promise<update.Response> {
  return true === connection.simulate
    ? update.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...update.METADATA,
          path: update.path(),
          status: null,
        },
        props.body,
      );
}
export namespace update {
  export type Props = {
    /**
     * New display name for the user profile
     */
    body: ITodoAppUser.IUpdate;
  };
  export type Body = ITodoAppUser.IUpdate;
  export type Response = ITodoAppUser;

  export const METADATA = {
    method: "PUT",
    path: "/todoApp/user/profile",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/todoApp/user/profile";
  export const random = (): ITodoAppUser => typia.random<ITodoAppUser>();
  export const simulate = (
    connection: IConnection,
    props: update.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: update.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
