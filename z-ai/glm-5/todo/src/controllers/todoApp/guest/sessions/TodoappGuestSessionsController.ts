import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageITodoAppMemberSession } from "../../../../api/structures/IPageITodoAppMemberSession";
import { ITodoAppMemberSession } from "../../../../api/structures/ITodoAppMemberSession";
import { GuestAuth } from "../../../../decorators/GuestAuth";
import { GuestPayload } from "../../../../decorators/payload/GuestPayload";
import { getTodoAppGuestSessionsSessionId } from "../../../../providers/getTodoAppGuestSessionsSessionId";
import { patchTodoAppGuestSessions } from "../../../../providers/patchTodoAppGuestSessions";

@Controller("/todoApp/guest/sessions")
export class TodoappGuestSessionsController {
  /**
   * Retrieve a paginated list of the authenticated member's active sessions.
   *
   * This operation allows members to view all their active authentication sessions for security monitoring and management purposes. Each session entry includes connection metadata such as the IP address from which the session was initiated, the URL endpoint accessed during authentication, and the HTTP referrer if available.
   *
   * Sessions are ordered by creation time with the most recent sessions appearing first. The response includes session lifecycle information including when the session was created, when it was last refreshed, and when it will expire. This information helps members identify potentially unauthorized access and manage their authentication state.
   *
   * The list is automatically filtered to show only sessions belonging to the authenticated member, ensuring complete data isolation between users. Members can use this information to identify unfamiliar devices or locations that may indicate compromised credentials.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for session listing
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification Query todo_app_member_sessions table with pagination for the authenticated member.
   *
   * Implementation steps:
   * 1. Extract authenticated member ID from JWT token
   * 2. Build query with WHERE clause: todo_app_member_id = authenticated_member_id
   * 3. Apply optional filters if provided in request body
   * 4. Apply pagination using cursor-based approach
   * 5. Order by created_at descending (most recent first)
   * 6. Return paginated results with total count
   *
   * The session list helps members monitor their active sessions for security purposes, showing where and when they logged in.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @GuestAuth()
    guest: GuestPayload,
    @TypedBody()
    body: ITodoAppMemberSession.IRequest,
  ): Promise<IPageITodoAppMemberSession.ISummary> {
    try {
      return await patchTodoAppGuestSessions({
        guest,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific authenticated member session.
   *
   * This operation allows authenticated members to view their own session details, including connection context and temporal lifecycle information. Members can use this endpoint to verify their session status, review connection metadata for security purposes, or check when their session will expire.
   *
   * The session information includes the client IP address, the URL endpoint accessed during authentication, and the HTTP referrer from the original authentication request. Timestamps indicate when the session was created, last refreshed, and when it will expire.
   *
   * Authorization: This operation enforces strict ownership validation. Members can only retrieve sessions that belong to their own account. Any attempt to access another member's session will result in a 404 Not Found response. This ensures complete data isolation between users in this private todo application.
   *
   * Related Operations: Use POST /auth/login to create a new session, or POST /auth/logout to invalidate an existing session.
   *
   * @param connection
   * @param sessionId Unique identifier of the session to retrieve (global scope)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification Query the todo_app_member_sessions table by primary key ID. Join with todo_app_members to validate ownership. Apply authorization check: the session's todo_app_member_id must match the authenticated user's ID. Return 404 if session not found or does not belong to the authenticated user. Include all session fields: id, connection metadata (ip, href, referrer), and timestamps (created_at, updated_at, expired_at). Do NOT expose the token_identifier (JWT jti claim) in the response as this is a sensitive security credential.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @GuestAuth()
    guest: GuestPayload,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppMemberSession> {
    try {
      return await getTodoAppGuestSessionsSessionId({
        guest,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
