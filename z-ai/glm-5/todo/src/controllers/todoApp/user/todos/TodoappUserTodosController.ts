  /**
   * Removes a todo from the active list by moving it to the trash.
   *
   * This operation performs a soft delete on the specified todo, setting the is_deleted flag to true without removing the data from storage. The todo will no longer appear in normal todo list queries but remains accessible through the trash endpoint for potential restoration.
   *
   * The operation verifies that the authenticated user owns the todo before performing the deletion. If the todo belongs to another user or does not exist, the system returns a not found error without revealing the existence of other users' data.
   *
   * All todo data is preserved during this operation, including the title, description, dates, completion status, and the complete edit history stored in todo_app_todo_histories. The updated_at timestamp is set to the current time to reflect when the deletion occurred.
   *
   * After deletion, the todo can be viewed in the trash list (GET /trash), restored to the active list (POST /trash/{todoId}/restore), or permanently deleted (DELETE /trash/{todoId}) which removes both the todo and its edit history.
   *
   * @param connection
   * @param todoId Unique identifier of the todo to delete (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Implementation steps:
   *
   * 1. Validate the todoId path parameter is a valid UUID format
   * 2. Query todo_app_todos table for the todo with matching id
   * 3. Verify the todo exists and belongs to the authenticated user (user_id matches)
   * 4. Verify the todo is not already soft-deleted (is_deleted = false)
   * 5. If todo not found, belongs to another user, or already deleted: return 404 Not Found
   * 6. Update the todo record:
   *    - SET is_deleted = true
   *    - SET updated_at = current timestamp
   * 7. Return the updated todo entity
   *
   * Database query:
   * ```sql
   * UPDATE todo_app_todos
   * SET is_deleted = true, updated_at = NOW()
   * WHERE id = $1 AND user_id = $2 AND is_deleted = false
   * RETURNING *
   * ```
   *
   * Privacy enforcement: The user_id condition in the WHERE clause ensures users can only delete their own todos. The same 404 response is returned whether the todo doesn't exist, belongs to another user, or is already deleted, preventing information leakage.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
