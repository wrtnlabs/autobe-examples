  /**
   * Retrieve a paginated and filtered list of todos belonging to the authenticated user.
   *
   * This operation provides comprehensive todo list viewing capabilities with multiple organization options. Users can filter todos by completion status to view all todos, only completed todos, or only incomplete todos. Multiple sorting options are available including by creation date (newest or oldest first), start date (earliest or latest first), and due date (earliest or latest first).
   *
   * When sorting by start_date or due_date, todos without those dates set appear at the end of the results, ensuring consistent ordering behavior. Only active (non-deleted) todos are shown in this list; deleted todos in the trash are accessed through separate trash endpoints.
   *
   * Each todo in the response includes the title, completion status, start_date if set, due_date if set, and creation date. The full description is not included in list items to optimize response size; use the individual todo endpoint to retrieve complete details.
   *
   * Privacy is strictly enforced: users can only view their own todos, and all queries are automatically scoped to the authenticated user's data.
   *
   * @param connection
   * @param body Search criteria including completion status filter, sorting options, and pagination parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Implementation requires querying the todo_app_todos table with the following constraints:
   *
   * 1. Always filter by user_id matching the authenticated user's ID
   * 2. Always filter is_deleted = false to exclude trashed todos
   * 3. Apply completion status filter based on request: is_completed = true for 'complete', is_completed = false for 'incomplete', no filter for 'all'
   * 4. Apply sorting based on request parameter: created_at, start_date, or due_date with ASC or DESC direction
   * 5. For start_date and due_date sorting, use NULLS LAST to place todos without dates at the end
   * 6. Implement cursor-based or offset-based pagination with configurable page size
   * 7. Return todos with id, title, is_completed, start_date, due_date, created_at fields
   *
   * Database indexes available for optimization: (user_id, is_deleted, created_at), (user_id, is_deleted, start_date), (user_id, is_deleted, due_date). Select appropriate index based on sort field.
   *
   * Edge cases: Empty result set returns empty data array with pagination showing zero total. Invalid filter values default to 'all'. Invalid sort field defaults to created_at descending.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
