  /**
   * Create a new todo item for the authenticated user.
   *
   * This operation allows users to create personal todo items with a required title and optional additional details. The title field is mandatory and must not exceed 200 characters. An optional description can be provided up to 5000 characters, preserving all formatting including line breaks and whitespace.
   *
   * Optional start_date and due_date fields can be specified in ISO 8601 format to indicate when the todo should be started and completed. These dates can include or exclude time components according to user preference.
   *
   * Upon creation, the todo is automatically associated with the authenticated user ensuring complete privacy isolation. The system generates a unique identifier and sets initial timestamps (created_at and updated_at). The completion status defaults to incomplete (is_completed = false) and the soft delete flag is set to false.
   *
   * All todo data is strictly scoped to the owning user - no cross-user access is possible. The response includes the complete todo entity with all fields as stored in the database.
   *
   * @param connection
   * @param body Todo creation data with required title and optional description, start_date, and due_date
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Implementation steps:
   *
   * 1. Validate authentication - extract user_id from JWT token in Authorization header
   * 2. Validate request body:
   *    - title: required, non-empty after trimming, max 200 characters
   *    - description: optional, max 5000 characters if provided, can be null
   *    - startDate: optional, valid ISO 8601 date/datetime if provided
   *    - dueDate: optional, valid ISO 8601 date/datetime if provided
   * 3. Generate UUID for todo id
   * 4. Set defaults:
   *    - is_completed = false
   *    - is_deleted = false
   *    - created_at = current timestamp
   *    - updated_at = current timestamp
   * 5. Insert into todo_app_todos table with user_id from authenticated session
   * 6. Return complete entity with all fields including generated id and timestamps
   *
   * Error handling:
   * - 401 Unauthorized if not authenticated
   * - 400 Bad Request with validation errors for:
   *   - Missing/empty title (TODO_TITLE_REQUIRED)
   *   - Title > 200 chars (TODO_TITLE_TOO_LONG)
   *   - Description > 5000 chars (TODO_DESCRIPTION_TOO_LONG)
   *   - Invalid date format (TODO_INVALID_DATE)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
