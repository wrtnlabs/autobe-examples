import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IPageITodoAppUserSession } from "../../../../api/structures/IPageITodoAppUserSession";
import { ITodoAppUserSession } from "../../../../api/structures/ITodoAppUserSession";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { getTodoAppUserSessionsSessionId } from "../../../../providers/getTodoAppUserSessionsSessionId";
import { patchTodoAppUserSessions } from "../../../../providers/patchTodoAppUserSessions";

@Controller("/todoApp/user/sessions")
export class TodoappUserSessionsController {
  /**
   * Retrieve a filtered and paginated list of the authenticated user's login sessions.
   *
   * This operation provides visibility into all active and expired sessions for security awareness and account management purposes. Users can monitor where and when they have authenticated, helping identify suspicious activity or manage sessions across multiple devices.
   *
   * Each session record includes the IP address from which authentication occurred, the full request URL path, and timestamps for session creation and expiration. This enables users to verify their login history and identify any unauthorized access attempts.
   *
   * The session list is automatically scoped to the authenticated user, ensuring complete privacy. Users cannot view sessions belonging to other accounts. Sessions are typically ordered by creation date (newest first) to show recent authentication activity.
   *
   * This endpoint supports the session management workflow where users can review their active logins before deciding to logout from specific devices or change their password to invalidate all sessions.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for session list
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Query todo_app_user_sessions table with automatic user-scoped filtering.
   *
   * Implementation steps:
   * 1. Extract authenticated user ID from JWT token context
   * 2. Build Prisma query with WHERE clause: todo_app_user_id = current_user_id
   * 3. Apply optional filters from request body:
   *    - created_at range (from/to)
   *    - expired_at range (from/to)
   *    - is_active boolean (expired_at > now() for active sessions)
   *    - IP address partial match
   * 4. Apply pagination with cursor-based or offset-based approach
   * 5. Order by created_at DESC (newest first) by default
   * 6. Include related user information for display_name if needed
   * 7. Transform results to ISummary format with essential fields only
   *
   * Response fields:
   * - id: session identifier
   * - ip: IP address from authentication
   * - href: request URL path
   * - created_at: when session was created
   * - expired_at: when session expires
   *
   * No sensitive data (passwords, tokens) should be included in the response.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoAppUserSession.IRequest,
  ): Promise<IPageITodoAppUserSession.ISummary> {
    try {
      return await patchTodoAppUserSessions({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves detailed information about a specific user session for security and audit purposes.
   *
   * This endpoint allows authenticated users to view their own session details, including the IP address from which the session was created, the request URL that initiated authentication, and the HTTP referrer header. This information helps users monitor their account security and identify potentially unauthorized access.
   *
   * The session includes creation and expiration timestamps, enabling users to understand session lifetime and validity. Sessions are automatically created during the login process and cannot be manually created or modified by users.
   *
   * Users can only access sessions that belong to their own account. Attempting to access another user's session will result in a 404 Not Found response to prevent information disclosure about the existence of other users' sessions.
   *
   * @param connection
   * @param sessionId Unique identifier of the session to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Query the todo_app_user_sessions table by primary key (id) to retrieve a single session record.
   *
   * Implementation steps:
   * 1. Extract sessionId from path parameters
   * 2. Validate sessionId is a valid UUID format
   * 3. Query todo_app_user_sessions where id = sessionId
   * 4. Verify the session belongs to the authenticated user (todo_app_user_id matches current user's id)
   * 5. If not found or not owned, return 404 Not Found
   * 6. Return the session entity with all fields
   *
   * The query should include a join with todo_app_users to verify ownership. The response includes: id, ip, href, referrer (nullable), created_at, and expired_at. Do not include the todo_app_user_id in the response for security reasons.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("sessionId")
    sessionId: string,
  ): Promise<ITodoAppUserSession> {
    try {
      return await getTodoAppUserSessionsSessionId({
        user,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
