import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { ITodoAppMember } from "../../../../api/structures/ITodoAppMember";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getTodoAppMemberProfile } from "../../../../providers/getTodoAppMemberProfile";
import { putTodoAppMemberProfile } from "../../../../providers/putTodoAppMemberProfile";

@Controller("/todoApp/member/profile")
export class TodoappMemberProfileController {
  /**
   * Retrieve the authenticated member's profile information.
   *
   * This endpoint allows members to view their own profile data including their email address, display name, and account timestamps. The profile is completely private and can only be accessed by the owning member through their authenticated session.
   *
   * The response includes the member's unique email identifier used for authentication, their display name for personalization within the application, and timestamps showing when the account was created and last updated.
   *
   * Security and Privacy:
   * - Only the authenticated member can access their own profile
   * - There is no mechanism to view other members' profiles
   * - The password hash is never exposed in any API response
   * - Authentication is required via valid session token
   *
   * Related Operations:
   * - PUT /profile - Update the member's display name
   * - PUT /profile/password - Change the member's password
   * - DELETE /profile - Permanently delete the member account and all associated data
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Retrieve the authenticated member's profile from todo_app_members table.
   *
   * 1. Extract member ID from the authenticated session/JWT token
   * 2. Query todo_app_members table by the authenticated member's ID
   * 3. Return member profile with the following fields:
   *    - id: Member's UUID
   *    - email: Member's unique email address
   *    - display_name: Member's display name
   *    - created_at: Account creation timestamp
   *    - updated_at: Last profile update timestamp
   * 4. Exclude password_hash from response for security
   *
   * Error handling:
   * - 401 Unauthorized if no valid session/token provided
   * - 404 Not Found if member record doesn't exist (edge case, shouldn't happen with valid token)
   *
   * Privacy enforcement:
   * - No parameter to specify which profile - always returns authenticated user's own profile
   * - This design enforces the private profile restriction at the API level
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @MemberAuth()
    member: MemberPayload,
  ): Promise<ITodoAppMember> {
    try {
      return await getTodoAppMemberProfile({
        member,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update the authenticated member's profile display name.
   *
   * This operation allows authenticated members to change their display name, which is a personalization feature within the application. The display name is stored in the todo_app_members table and is completely private - it is not shared with other users since this is a private todo application.
   *
   * The display name can be changed at any time while logged in, and can be updated multiple times. No password verification is required for display name changes, as this setting is separate from authentication credentials. The system does not impose uniqueness constraints on display names, allowing any valid text value.
   *
   * Security and Privacy:
   * - Each member's profile is completely private and isolated
   * - Members can only update their own profile
   * - The display name is not exposed to any other user
   * - Display name changes do not affect email or password settings
   *
   * @param connection
   * @param body New display name for the member's profile
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Update the authenticated member's display name in the todo_app_members table.
   *
   * 1. Extract the authenticated member's ID from the JWT session token
   * 2. Validate the displayName field in the request body (required, non-empty string)
   * 3. Update the display_name column and updated_at timestamp in the todo_app_members table
   * 4. Return the complete updated member profile
   *
   * Edge cases:
   * - Display name can be any valid text value, no uniqueness constraint
   * - Display name changes do not affect authentication credentials (email, password)
   * - The operation is atomic - either the complete update succeeds or fails
   *
   * Authorization: Only the authenticated member can update their own profile.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: ITodoAppMember.IUpdate,
  ): Promise<ITodoAppMember> {
    try {
      return await putTodoAppMemberProfile({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
