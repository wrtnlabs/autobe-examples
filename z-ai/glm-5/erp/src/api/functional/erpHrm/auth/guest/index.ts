/**
 * Creates a new member account from guest status and establishes the user's first organization.
 *
 * This operation represents the sign-up path for guests transitioning to authenticated members. The guest provides their email address and password to create a new account. Per the multi-tenancy requirements, the user must also provide an organization name to create their first organization during the sign-up process.
 *
 * Upon successful registration, the user immediately becomes an authenticated member with the owner role for the newly created organization. The system generates both an access token (for API authentication) and a refresh token (for session renewal), returning them in the response body.
 *
 * The email address must be unique across the entire platform - if an account with the provided email already exists, the operation will fail with an appropriate error. The password must meet the platform's security requirements (minimum length, complexity rules).
 *
 * This operation is public and does not require any prior authentication. Once completed successfully, the guest transitions to member status and can access all features available to their role within the organization.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Guest registration credentials and initial organization name. Email must be unique across the platform. Password must meet security requirements. Organization name is required as users create their first organization during sign-up.
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor guest
 * @x-autobe-specification Implementation Steps:
 *
 * 1. **Validate Request**: Ensure email format is valid, password meets security requirements (minimum 8 characters, contains uppercase, lowercase, number, and special character), and organization name is not empty.
 *
 * 2. **Check Email Uniqueness**: Query the member table to verify the email is not already registered. If duplicate, return 409 Conflict error.
 *
 * 3. **Hash Password**: Use bcrypt or argon2 to securely hash the password before storage.
 *
 * 4. **Create Member Record**: Insert a new member record with:
 *    - email (unique)
 *    - hashed password
 *    - display_name (initially extracted from email or provided separately)
 *    - created_at, updated_at timestamps
 *
 * 5. **Create Organization**: Insert a new organization record with:
 *    - name from request
 *    - owner_id set to the new member's id
 *    - created_at, updated_at timestamps
 *
 * 6. **Create Owner Employee Record**: Insert an employee record linking the member to the organization with owner role.
 *
 * 7. **Generate JWT Tokens**: Create access token (short-lived, e.g., 15 minutes) and refresh token (longer-lived, e.g., 7 days) containing:
 *    - member_id
 *    - email
 *    - organization_id (default to newly created organization)
 *
 * 8. **Store Refresh Token**: Record the refresh token in the session table for validation and revocation capability.
 *
 * 9. **Return Response**: Return IErpHrmGuest.IAuthorized with tokens and expiration information.
 * @path /erpHrm/auth/guest/join
 * @accessor api.functional.erpHrm.auth.guest.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
