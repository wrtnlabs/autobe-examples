import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IErpHrmMember } from "../../../../api/structures/IErpHrmMember";
import { postErpHrmAuthMemberJoin } from "../../../../providers/postErpHrmAuthMemberJoin";
import { postErpHrmAuthMemberLogin } from "../../../../providers/postErpHrmAuthMemberLogin";
import { postErpHrmAuthMemberRefresh } from "../../../../providers/postErpHrmAuthMemberRefresh";

@Controller("/erpHrm/auth/member")
export class ErphrmAuthMemberController {
  /**
   * Creates a new member account with email and password credentials, establishing the member's identity in the platform.
   *
   * During the join process, the member provides their email address (which must be unique across the entire platform), a secure password, and their display name. The display name is a required field that identifies the member to others within organizations. The email serves as the unique identifier for all future authentication attempts and can be used for organization invitations.
   *
   * Per requirements, sign-up requires creating the member's first organization simultaneously. The member becomes the owner of this organization with full permissions. This ensures every member has at least one organization context to work in after registration.
   *
   * The response includes JWT tokens (access token and refresh token) for immediate authentication, along with the newly created member's profile information. The access token is short-lived for security, while the refresh token enables obtaining new access tokens without re-authentication.
   *
   * This operation corresponds to the 'join' authorization type and uses the IErpHrmMember.IJoin request body and IErpHrmMember.IAuthorized response body types.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Registration information including email, password, display name, and initial organization name
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Implementation: 1) Validate email uniqueness by querying erp_hrm_members table for existing email. 2) Hash the provided password using bcrypt or argon2. 3) Create new member record with email, hashed password, and display_name. 4) Create the member's first organization using the provided organization name, setting the member as owner. 5) Create initial employee record linking member to organization with owner role. 6) Generate JWT access token (short-lived, e.g., 15 minutes) and refresh token (longer-lived, e.g., 7 days). 7) Create session record in erp_hrm_member_sessions with tokens, IP, href, referrer, and organization context. 8) Return tokens and member profile data. Error handling: Duplicate email returns 409 Conflict. Invalid email format returns 400 Bad Request. Password strength validation failure returns 400.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IErpHrmMember.IJoin,
  ): Promise<IErpHrmMember.IAuthorized> {
    try {
      return await postErpHrmAuthMemberJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticates a member with email and password credentials, providing JWT tokens for platform access.
   *
   * The login operation validates the member's email and password combination against the stored credentials in erp_hrm_members. The email field serves as the unique identifier for authentication. The password is verified using secure hash comparison to prevent timing attacks.
   *
   * Upon successful authentication, the system retrieves all organizations the member belongs to (via erp_hrm_employees). If the member belongs to multiple organizations, the response includes the organization list allowing the member to select their working context. The selected organization is stored in the session (erp_hrm_member_sessions.organization_id) and all subsequent actions are scoped to this organization.
   *
   * The response includes JWT access token and refresh token. The access token is used for API authentication and is short-lived (typically 15 minutes). The refresh token enables obtaining new access tokens without requiring the member to re-enter credentials. Session metadata (IP address, current URL, referrer) is recorded for security auditing.
   *
   * This operation corresponds to the 'login' authorization type and uses the IErpHrmMember.ILogin request body and IErpHrmMember.IAuthorized response body types.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Login credentials including email and password
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Implementation: 1) Query erp_hrm_members table by email address. 2) Verify member exists and is not soft-deleted (deleted_at is null). 3) Compare provided password against stored hash using constant-time comparison. 4) If credentials valid, query erp_hrm_employees to get all organizations the member belongs to. 5) If member belongs to multiple organizations, include organization list in response for selection. 6) Generate JWT access token and refresh token. 7) Create session record in erp_hrm_member_sessions with tokens, client metadata (IP, href, referrer), and optionally the selected organization_id. 8) Return tokens and member profile. Error handling: Invalid credentials return 401 Unauthorized. Soft-deleted account returns 403 Forbidden. Rate limiting should be applied to prevent brute force attacks.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IErpHrmMember.ILogin,
  ): Promise<IErpHrmMember.IAuthorized> {
    try {
      return await postErpHrmAuthMemberLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Renews JWT access tokens using a valid refresh token, enabling continued platform access without re-authentication.
   *
   * The refresh operation allows members to obtain new access tokens when their current access token expires. This provides a seamless authentication experience without requiring the member to re-enter their email and password frequently. The refresh token is long-lived (typically 7 days) while the access token is short-lived for security.
   *
   * When refreshing, the system validates the refresh token against active sessions in erp_hrm_member_sessions. The session must exist, must not be expired, and the associated member must not be soft-deleted. Upon successful validation, new tokens are generated and the session record is updated with the refreshed tokens.
   *
   * For enhanced security, the system may implement refresh token rotation, where a new refresh token is issued with each refresh operation and the old one is invalidated. This limits the window of vulnerability if a refresh token is compromised.
   *
   * This operation corresponds to the 'refresh' authorization type and uses the IErpHrmMember.IRefresh request body and IErpHrmMember.IAuthorized response body types.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token for obtaining new access tokens
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Implementation: 1) Validate the refresh token structure and signature. 2) Query erp_hrm_member_sessions to find the session associated with the refresh token. 3) Verify the session exists and has not expired (expired_at > current time). 4) Verify the session's member is not soft-deleted. 5) Generate new JWT access token and optionally a new refresh token (token rotation for security). 6) Update the session record with new tokens and updated_at timestamp. 7) If token rotation is used, invalidate the old refresh token. 8) Return new tokens. Error handling: Invalid or expired refresh token returns 401 Unauthorized. Session not found returns 401. Soft-deleted member returns 403 Forbidden.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IErpHrmMember.IRefresh,
  ): Promise<IErpHrmMember.IAuthorized> {
    try {
      return await postErpHrmAuthMemberRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
