import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IErpHrmDashboard } from "../../../../../api/structures/IErpHrmDashboard";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { getErpHrmMemberReportsDashboard } from "../../../../../providers/getErpHrmMemberReportsDashboard";

@Controller("/erpHrm/member/reports/dashboard")
export class ErphrmMemberReportsController {
  /**
   * Retrieve organization-wide dashboard metrics for administrative oversight and reporting.
   *
   * This endpoint provides a comprehensive overview of organizational activity, aggregating data across employees, time tracking, project budgets, and timesheet workflows. The dashboard is designed for users with report viewing permission who need high-level insights into organizational productivity and pending approvals.
   *
   * The response includes five key metrics:
   * - Total count of active employees in the organization
   * - Total hours logged by all employees during the current week (Monday through Sunday)
   * - Number of timesheets currently awaiting manager approval
   * - List of projects exceeding 80% budget utilization for proactive management
   * - Top 5 employees ranked by hours logged this week
   *
   * Access requires the 'report:view' permission. Data is strictly scoped to the currently selected organization context, ensuring multi-tenancy data isolation. Personal dashboards for individual employees are available through a separate endpoint.
   *
   * This operation supports organizational oversight workflows described in the weekly time tracking and approval scenarios, enabling managers and owners to monitor productivity, identify budget concerns, and track timesheet approval queues.
   *
   * @param connection
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query multiple tables to compute organization
     *   dashboard metrics:
   *
   * 1. Count active employees: SELECT COUNT(*) FROM erp_hrm_employees WHERE organization_id = current_org AND status = 'active' AND deleted_at IS NULL
   *
   * 2. Calculate total hours this week: SELECT COALESCE(SUM(duration), 0) / 60.0 FROM erp_hrm_timelogs tl JOIN erp_hrm_employees e ON tl.employee_id = e.id WHERE e.organization_id = current_org AND tl.date >= current_week_monday AND tl.date <= current_week_sunday AND tl.deleted_at IS NULL
   *
   * 3. Count pending timesheets: SELECT COUNT(*) FROM erp_hrm_timesheets ts JOIN erp_hrm_employees e ON ts.employee_id = e.id WHERE e.organization_id = current_org AND ts.status = 'submitted' AND ts.deleted_at IS NULL
   *
   * 4. Find projects with budget utilization over 80%: For each project with budget_hours, calculate (total logged hours / budget_hours * 100), return projects where result > 80
   *
   * 5. Top 5 employees by hours this week: SELECT e.id, e.position, m.name, SUM(tl.duration)/60.0 as total_hours FROM erp_hrm_timelogs tl JOIN erp_hrm_employees e ON tl.employee_id = e.id JOIN erp_hrm_members m ON e.erp_hrm_member_id = m.id WHERE e.organization_id = current_org AND tl.date >= current_week_monday GROUP BY e.id ORDER BY total_hours DESC LIMIT 5
   *
   * All queries are read-only, no transactions needed. Cache results for performance if needed.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async dashboard(
    @MemberAuth()
    member: MemberPayload,
  ): Promise<IErpHrmDashboard.IOrganization> {
    try {
      return await getErpHrmMemberReportsDashboard({
        member,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
