import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IErpHrmProject } from "../../../../../../api/structures/IErpHrmProject";
import { IPageIErpHrmProject } from "../../../../../../api/structures/IPageIErpHrmProject";
import { MemberAuth } from "../../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../../decorators/payload/MemberPayload";
import { patchErpHrmMemberReportsProjectsBudget } from "../../../../../../providers/patchErpHrmMemberReportsProjectsBudget";

@Controller("/erpHrm/member/reports/projects/budget")
export class ErphrmMemberReportsProjectsBudgetController {
  /**
   * Retrieve a paginated project budget utilization report comparing planned budget hours against actual hours logged.
   *
   * This report helps managers track which projects are consuming their allocated budgets and identify projects that may require budget adjustments or additional resource planning. The report displays budget hours defined for each project, the actual hours logged by team members, and the utilization percentage.
   *
   * Only projects with defined budget hours are included in this report. Projects without budget hours are automatically excluded as they have no baseline for comparison. This ensures meaningful utilization metrics are presented to users.
   *
   * The report can be filtered by project status to focus on active projects, archived projects, or completed projects. Results are paginated to handle organizations with many projects.
   *
   * Requires report:view permission. Users without this permission receive an authorization error.
   *
   * @param connection
   * @param body Filter criteria and pagination parameters for project budget report
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query erp_hrm_projects table to find all projects within the organization that have budget_hours defined (not null). Filter by status if provided in request body (active, archived, completed).
   *
   * For each matching project, aggregate total hours from erp_hrm_timelogs where project_id matches and deleted_at is null. Calculate budget utilization percentage as (actual_hours / budget_hours) * 100.
   *
   * Return paginated results sorted by budget utilization percentage (highest first) or by project name. Include project details (id, name, color_code, status), budget_hours, actual_hours, utilization_percentage.
   *
   * Projects without budget_hours are automatically excluded from results regardless of filter criteria.
   *
   * Requires member actor with report:view permission.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IErpHrmProject.IBudgetRequest,
  ): Promise<IPageIErpHrmProject.IBudgetSummary> {
    try {
      return await patchErpHrmMemberReportsProjectsBudget({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
