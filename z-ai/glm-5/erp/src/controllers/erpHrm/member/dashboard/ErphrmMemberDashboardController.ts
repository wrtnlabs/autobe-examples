import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IErpHrmDashboard } from "../../../../api/structures/IErpHrmDashboard";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getErpHrmMemberDashboard } from "../../../../providers/getErpHrmMemberDashboard";

@Controller("/erpHrm/member/dashboard")
export class ErphrmMemberDashboardController {
  /**
   * Retrieve the dashboard data for the authenticated user, displaying both personal and organization-level information based on permissions.
   *
   * This endpoint provides a comprehensive overview of time tracking and project status. Every employee sees their personal dashboard containing hours logged today and this week, their currently active timer (if any), the five most recent timelog entries, pending timesheet status for the current week, and tasks assigned to them that are open or in-progress.
   *
   * Users with the `report:view` permission additionally see organization-level metrics: total active employees in the organization, aggregate hours logged by all employees this week, count of timesheets awaiting approval, projects exceeding 80% budget utilization, and the top 5 employees ranked by hours logged this week.
   *
   * Data access is strictly enforced through the organization context. All data is scoped to the currently selected organization, and cross-organization data isolation is maintained.
   *
   * The response structure adapts dynamically based on the authenticated user's permissions. The personal section is always populated for any employee, while the organization section is included only when the user's role includes the report viewing permission.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Implementation logic for the dashboard endpoint:
   *
   * 1. **Authentication & Context**: Extract authenticated member and current organization context from session. Load employee record for the member within the organization.
   *
   * 2. **Personal Dashboard Computation**:
   *    - Query erp_hrm_timelogs where employee_id = current employee AND date = today, sum duration for hours_logged_today
   *    - Query erp_hrm_timelogs where employee_id = current employee AND date within current week (Monday-Sunday), sum duration for hours_logged_this_week
   *    - Query erp_hrm_timers where erp_hrm_employee_id = current employee AND deleted_at IS NULL, if exists return timer details (project, task, started_at, elapsed time calculated from started_at to now)
   *    - Query erp_hrm_timelogs where employee_id = current employee ORDER BY created_at DESC LIMIT 5, return as recent_timelogs array
   *    - Query erp_hrm_timesheets where employee_id = current employee AND week_start_date = current week's Monday, return status as pending_timesheet_status (null if no timesheet exists)
   *    - Query erp_hrm_tasks where employee_id = current employee AND status IN ('open', 'in-progress'), return as assigned_tasks array
   *
   * 3. **Organization Dashboard Computation** (conditional):
   *    - Check if employee's role has 'report:view' permission via erp_hrm_role_permissions join
   *    - If has permission:
   *      - Query erp_hrm_employees where organization_id = current org AND status = 'active', count for total_active_employees
   *      - Query erp_hrm_timelogs joined with erp_hrm_employees, filter by organization, date within current week, sum for total_hours_this_week
   *      - Query erp_hrm_timesheets where organization matches AND status = 'submitted', count for pending_timesheets_count
   *      - Query erp_hrm_projects where organization_id = current org AND budget_hours IS NOT NULL AND status = 'active', for each calculate (sum of timelog durations / budget_hours * 100), filter those > 80%, return projects_over_budget array
   *      - Query employees with their total hours this week, ORDER BY hours DESC LIMIT 5, return top_employees_by_hours array
   *
   * 4. **Response Construction**: Return IErpHrmDashboard with personal section always populated and organization section conditionally populated.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @MemberAuth()
    member: MemberPayload,
  ): Promise<IErpHrmDashboard> {
    try {
      return await getErpHrmMemberDashboard({
        member,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
