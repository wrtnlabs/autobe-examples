  /**
   * Soft deletes a task from a project by marking it as deleted.
   *
   * This operation allows project leads and users with project management permission to remove tasks that are no longer needed. The deletion is implemented as a soft delete, marking the task as deleted by setting the deleted_at timestamp while preserving the record for audit and recovery purposes.
   *
   * **Authorization Requirements:**
   *
   * Access to this operation is restricted to:
   * - Project leads assigned to the project containing the task
   * - Users with the 'project:manage' permission
   *
   * If the requesting user does not meet either condition, the operation is rejected with an authorization error.
   *
   * **Business Constraints:**
   *
   * Tasks that have associated time entries (timelogs) cannot be deleted. This restriction ensures that historical time tracking data remains properly linked and reportable. If deletion is attempted on a task with timelogs, the system will reject the request and suggest closing the task instead, which preserves the task record while marking it as inactive.
   *
   * Tasks that have subtasks should have their subtasks deleted first before the parent task can be removed. This prevents orphaned subtasks in the system.
   *
   * **Related Operations:**
   *
   * - Use PATCH /projects/{projectId}/tasks to list and filter tasks within a project
   * - Use PUT /projects/{projectId}/tasks/{taskId} to update task details or status
   * - Use GET /projects/{projectId}/tasks/{taskId} to retrieve specific task information before deletion
   *
   * @param connection
   * @param projectId UUID of the project containing the task to delete
   * @param taskId UUID of the task to delete
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Implementation Steps:
   *
   * 1. Authorization Check:
   *    - Verify authenticated member has either:
   *      a) project-lead role in erp_hrm_project_members for this project, OR
   *      b) project:manage permission through their role
   *    - If neither condition met, reject with 403 Forbidden
   *
   * 2. Task Retrieval:
   *    - Query erp_hrm_tasks by taskId
   *    - Verify task belongs to the specified projectId (path consistency)
   *    - Verify task is not already deleted (deleted_at IS NULL)
   *    - If not found or already deleted, return 404 Not Found
   *
   * 3. Timelog Association Check:
   *    - Query erp_hrm_timelogs for any records with task_id = taskId
   *    - If timelogs exist:
   *      - Do NOT perform deletion
   *      - Instead, transition task status to 'closed'
   *      - Create task history entry recording status change
   *      - Return 409 Conflict with message explaining closure requirement
   *
   * 4. Subtask Check:
   *    - Query erp_hrm_tasks for any subtasks (parent_task_id = taskId)
   *    - If subtasks exist:
   *      - Either prevent deletion (recommended), OR
   *      - Cascade soft-delete all subtasks
   *    - Recommended: Reject with 409 Conflict, requiring user to delete subtasks first
   *
   * 5. Soft Delete Execution:
   *    - Set deleted_at = current timestamp
   *    - Do NOT physically remove the record
   *    - Update updated_at timestamp
   *
   * 6. Activity Logging:
   *    - Create entry in erp_hrm_activity_logs:
   *      - action_type: 'task_deleted'
   *      - entity_type: 'task'
   *      - entity_id: taskId
   *      - organization_id: from task's project
   *
   * 7. Transaction Requirements:
   *    - Wrap all operations in a database transaction
   *    - Ensure atomicity of deletion and logging
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
