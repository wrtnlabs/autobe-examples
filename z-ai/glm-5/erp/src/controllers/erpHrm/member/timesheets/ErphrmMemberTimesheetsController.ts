  /**
   * Reject a submitted timesheet and return it to draft status for revision.
   *
   * This operation allows managers with time approval permission to reject a timesheet that has been submitted for review. When a timesheet is rejected, it returns to the employee for modification. The employee can then address the issues raised in the rejection reason and resubmit the timesheet.
   *
   * The rejection requires a reason to be provided, which helps the employee understand what needs to be corrected. This reason is stored in the timesheet record and made visible to the employee.
   *
   * Only timesheets with status 'submitted' can be rejected. Attempting to reject a timesheet in any other status (draft, approved, or already rejected) will result in an error. This ensures the approval workflow is followed correctly.
   *
   * Upon rejection, the system records the reviewer (the user who rejected the timesheet), the timestamp of the review, and the rejection reason. This provides a complete audit trail of the timesheet's journey through the approval process.
   *
   * After rejection, the timesheet status changes to 'rejected' and all included timelogs become editable again. The employee can modify the timelogs, add or remove entries from the timesheet, and then resubmit it for approval.
   *
   * This operation requires the 'time:approve' permission. Users without this permission will receive a 403 Forbidden error.
   *
   * @param connection
   * @param timesheetId Unique identifier of the timesheet to reject
   * @param body Rejection details including the reason for rejection
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Reject a submitted timesheet with the following
     *   steps:
   *
   * 1. Validate the timesheet exists and belongs to the current organization
   * 2. Verify the timesheet status is 'submitted' - if not, reject with error
   * 3. Verify the authenticated user has 'time:approve' permission
   * 4. Update the timesheet record:
   *    - Set status to 'rejected'
   *    - Set reviewer_id to the authenticated user's member id
   *    - Set reviewed_at to current timestamp
   *    - Set rejection_reason from request body
   *    - Update updated_at timestamp
   * 5. The timesheet will return to editable state for the employee to modify and resubmit
   *
   * Database query: UPDATE erp_hrm_timesheets SET status = 'rejected', reviewer_id = ?, reviewed_at = NOW(), rejection_reason = ?, updated_at = NOW() WHERE id = ? AND status = 'submitted'
   *
   * Error conditions:
   * - Timesheet not found: 404 error
   * - Timesheet not in submitted status: 400 error with message indicating timesheet must be in submitted status
   * - Missing rejection reason: 400 error requiring reason to be provided
   * - User lacks time:approve permission: 403 forbidden
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post(":timesheetId/reject")
  public async reject(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("timesheetId")
    timesheetId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IErpHrmTimesheet.IReject,
  ): Promise<IErpHrmTimesheet> {
    try {
      return await postErpHrmMemberTimesheetsTimesheetIdReject({
        member,
        timesheetId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
