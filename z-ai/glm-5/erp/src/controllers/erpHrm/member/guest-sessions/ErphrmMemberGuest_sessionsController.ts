import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IErpHrmGuestSession } from "../../../../api/structures/IErpHrmGuestSession";
import { IPageIErpHrmGuestSession } from "../../../../api/structures/IPageIErpHrmGuestSession";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getErpHrmMemberGuestSessionsSessionId } from "../../../../providers/getErpHrmMemberGuestSessionsSessionId";
import { patchErpHrmMemberGuestSessions } from "../../../../providers/patchErpHrmMemberGuestSessions";

@Controller("/erpHrm/member/guest-sessions")
export class ErphrmMemberGuest_sessionsController {
  /**
   * Retrieve a filtered and paginated list of guest session records for administrative monitoring and analytics.
   *
   * This endpoint provides authorized members with visibility into pre-authentication visitor activity across the platform. Guest sessions capture connection context including IP addresses, accessed URLs, referrer information, and session timing for security monitoring and visitor behavior analysis.
   *
   * The operation supports comprehensive filtering capabilities including IP address matching for security investigations, URL path filtering for entry point analysis, and date range queries for temporal analysis. Results are paginated with configurable page sizes to handle large volumes of visitor data efficiently.
   *
   * **Access Control**: This endpoint requires authentication. The guest actor cannot access this endpoint as it is restricted to authorized members for administrative purposes. Guest sessions are system-generated records and cannot be created, modified, or deleted through the API - they are managed automatically by the system during visitor browsing.
   *
   * **Related Entities**: Each session belongs to a guest record identified by device fingerprint. Use GET /guest-sessions/{sessionId} to retrieve detailed information about a specific session.
   *
   * @param connection
   * @param body Search criteria including IP filtering, URL path matching, referrer search, date range, and pagination parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query erp_hrm_guest_sessions table with joins to erp_hrm_guests for fingerprint information. Apply pagination with configurable page size and cursor-based navigation. Support filtering by: IP address (partial match for security analysis), href path (partial match for entry point tracking), referrer domain (partial match), date range (created_at between from and to), and expiration status (active vs expired). Return results sorted by created_at descending by default, with configurable sorting options. Join with erp_hrm_guests to include fingerprint and guest metadata. Calculate session duration where applicable. Handle soft-deleted guests appropriately (exclude by default, include if explicitly requested). Enforce authentication requirement - guest actor must not have access.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IErpHrmGuestSession.IRequest,
  ): Promise<IPageIErpHrmGuestSession.ISummary> {
    try {
      return await patchErpHrmMemberGuestSessions({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific guest session.
   *
   * This endpoint allows authenticated members to access guest session tracking data for administrative and audit purposes. The session information includes the IP address of the connection, the URL path accessed, the HTTP referrer if available, and expiration timestamp.
   *
   * The guest session table (erp_hrm_guest_sessions) provides the foundation for session tracking and enables the platform to maintain state for browsing visitors before authentication. Each guest identified by device fingerprint can have multiple concurrent sessions across different devices.
   *
   * This operation requires authentication and is accessible to members with appropriate permissions for viewing guest session data.
   *
   * @param connection
   * @param sessionId Unique identifier of the guest session to retrieve (global scope)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Retrieve a single guest session record from erp_hrm_guest_sessions table by UUID primary key.
   *
   * Query includes join with erp_hrm_guests table via erp_hrm_guest_id foreign key to fetch complete guest context including fingerprint.
   *
   * Validation:
   * - Verify sessionId is a valid UUID format
   * - Return 404 if session does not exist or has expired and been cleaned up
   *
   * Response includes all session fields: id, ip address, href (URL path accessed), referrer (nullable), created_at, expired_at, plus nested guest object with id, fingerprint, created_at, updated_at, and deleted_at.
   *
   * This operation is accessible to the guest actor (unauthenticated) for session tracking purposes during pre-authentication browsing.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<IErpHrmGuestSession> {
    try {
      return await getErpHrmMemberGuestSessionsSessionId({
        member,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
