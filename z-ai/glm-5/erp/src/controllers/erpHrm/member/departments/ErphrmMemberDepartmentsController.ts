import { putErpHrmMemberDepartmentsDepartmentId } from "../../../../providers/putErpHrmMemberDepartmentsDepartmentId";

@Controller("/erpHrm/member/departments")
export class ErphrmMemberDepartmentsController {
  /**
   * Create a new department within the organization to group employees by functional areas.
   *
   * Departments represent organizational units such as Engineering, Marketing, Human Resources, or Finance. This operation allows organization managers to establish the departmental structure that categorizes employees within the company.
   *
   * The department name must be unique within the organization to prevent confusion when assigning employees or filtering lists. An optional description can provide additional context about the department's purpose or responsibilities.
   *
   * Optionally, a parent department can be specified to create a hierarchical relationship. This supports a two-level structure where broad functional areas (e.g., Engineering) can have sub-departments (e.g., Backend Development, Frontend Team) beneath them. The hierarchy is limited to one level of nesting—a department with a parent cannot itself become a parent to another department.
   *
   * This operation requires the 'org:manage' permission. Only organization owners and users assigned a role with this permission can create departments.
   *
   * @param connection
   * @param body Department creation data including name, optional description, and optional parent department for hierarchy
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Create a new department within the authenticated user's current organization context.
   *
   * 1. Extract organization_id from the authenticated member's current organization context
   * 2. Validate that the user has 'org:manage' permission (return 403 Forbidden if not)
   * 3. Validate request body:
   *    - name: required, non-empty string
   *    - description: optional string
   *    - parent_id: optional UUID, must reference an existing department in the same organization
   * 4. Check department name uniqueness within the organization (return 409 Conflict if duplicate)
   * 5. If parent_id is provided:
   *    - Verify parent department exists in the same organization
   *    - Verify parent department does not already have a parent (enforce one-level hierarchy)
   * 6. Generate UUID for the new department
   * 7. Set created_at and updated_at to current timestamp
   * 8. Set deleted_at to null
   * 9. Insert department record into erp_hrm_departments table
   * 10. Return the created department object
   *
   * Edge cases:
   * - Parent department deleted (soft-deleted): reject with 400 Bad Request
   * - Parent department in different organization: reject with 400 Bad Request
   * - Parent has its own parent (would create 2-level nesting): reject with 400 Bad Request
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IErpHrmDepartment.ICreate,
  ): Promise<IErpHrmDepartment> {
    try {
      return await postErpHrmMemberDepartments({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a filtered and paginated list of departments within the current organization.
   *
   * This operation allows employees to browse the organizational structure and understand departmental groupings. All employees can access this information without special permissions.
   *
   * Departments support a single-level hierarchy where a department can optionally have a parent department. The response includes parent relationship information to help visualize the organizational structure. For example, "Backend Development" might appear as a child of "Engineering".
   *
   * The list can be filtered by name for quick lookup, or by parent to navigate the hierarchy level by level. Setting parent filter to null returns only top-level departments; providing a department ID returns only that department's direct children.
   *
   * Results are paginated and sorted alphabetically by department name by default. Soft-deleted departments are excluded from results.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering departments
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query erp_hrm_departments table filtered by organization_id from session context. Apply optional filters: search by name (case-insensitive partial match), filter by parent_id (null for top-level, specific UUID for children of a department). Support pagination with cursor-based or offset-based approach per standard patterns. Include parent department name via JOIN for hierarchy display. Filter out soft-deleted records (deleted_at IS NULL). Sort by name ascending by default, with configurable sort field and direction.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IErpHrmDepartment.IRequest,
  ): Promise<IPageIErpHrmDepartment.ISummary> {
    try {
      return await patchErpHrmMemberDepartments({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific department within the current organization context.
   *
   * This endpoint allows authenticated employees to view individual department details including the department name, description, and hierarchical relationship (parent department if exists). All employees within an organization have access to view department information regardless of their role or permissions.
   *
   * The response includes the department's basic information (name, description, timestamps) and the parent department reference if the department is part of a hierarchical structure. Departments support single-level nesting, where a department can have a parent but departments with parents cannot have children.
   *
   * Department names are unique within each organization. When a department is deleted, it is soft-deleted (marked with deleted_at timestamp) and will not appear in query results. Employees previously assigned to deleted departments have their department reference cleared.
   *
   * @param connection
   * @param departmentId Unique identifier of the department to retrieve (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query erp_hrm_departments table by id to retrieve a single department record.
   *
   * Implementation steps:
   * 1. Extract departmentId from path parameters
   * 2. Validate departmentId is a valid UUID
   * 3. Query erp_hrm_departments WHERE id = departmentId AND organization_id = current_organization_context AND deleted_at IS NULL
   * 4. If not found, return 404 Not Found
   * 5. Optionally join with parent department to include parent name in response
   * 6. Return full department entity with parent relationship info
   *
   * Data isolation: Must enforce organization context from current session to prevent cross-organization data access.
   *
   * Soft delete filter: Exclude departments where deleted_at IS NOT NULL.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":departmentId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("departmentId")
    departmentId: string & tags.Format<"uuid">,
  ): Promise<IErpHrmDepartment> {
    try {
      return await getErpHrmMemberDepartmentsDepartmentId({
        member,
        departmentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing department's name and description within the organization.
   *
   * This operation allows users with organization management permission to modify department information. The department name must be unique within the organization and serves as a recognizable business identifier. The description provides additional context about the department's purpose or responsibilities.
   *
   * **Editable Fields**:
   * - name: Required. The department name must be unique across all departments in the same organization.
   * - description: Optional. Additional context about the department's purpose, scope, or the types of work performed.
   *
   * **Restrictions**:
   * - The parent department relationship cannot be changed after creation. To restructure the hierarchy, the department must be deleted and recreated.
   * - Only users with the org:manage permission can modify departments.
   *
   * **Related Operations**:
   * - GET /departments - View all departments in the organization
   * - POST /departments - Create a new department
   * - DELETE /departments/{departmentId} - Delete a department
   *
   * @param connection
   * @param departmentId Unique identifier of the department to update
   * @param body Department update data with name and optional description
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Update an existing department's name and description.
   *
   * **Authorization**: Requires org:manage permission.
   *
   * **Implementation Steps**:
   * 1. Validate user has org:manage permission in the current organization context
   * 2. Find the department by departmentId within the current organization (enforce tenant isolation)
   * 3. Return 404 if department not found or belongs to different organization
   * 4. Validate the new name is unique within the organization (excluding the current department)
   * 5. Return 409 conflict if name already exists in the organization
   * 6. Update the department record with new name and description
   * 7. Set updated_at to current timestamp
   * 8. Return the updated department with organization and parent relations populated
   *
   * **Validation Rules**:
   * - name: required, must be unique within organization
   * - description: optional, nullable
   *
   * **Tenant Isolation**: Ensure the department belongs to the current organization context before allowing update.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":departmentId")
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("departmentId")
    departmentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IErpHrmDepartment.IUpdate,
  ): Promise<IErpHrmDepartment> {
    try {
      return await putErpHrmMemberDepartmentsDepartmentId({
        member,
        departmentId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently remove a department from the organization by marking it as deleted.
   *
   * This operation allows organization administrators to remove departments that are no longer needed. The deletion is implemented as a soft delete, preserving the department record for audit purposes while marking it as deleted with a timestamp.
   *
   * When a department is deleted, all employees previously assigned to that department have their department reference automatically cleared. The employees themselves remain active in the organization; only their department assignment is removed. Historical data such as timelogs and timesheets created by these employees while they were assigned to the department remain unchanged.
   *
   * Authorization: Only users with the org:manage permission can delete departments. If an employee without this permission attempts the operation, the request is rejected with a 403 Forbidden response.
   *
   * If the department has child departments (sub-departments in the hierarchy), they are also deleted due to the cascade delete constraint in the database schema.
   *
   * The response returns the deleted department record including the deleted_at timestamp, confirming the successful soft deletion.
   *
   * @param connection
   * @param departmentId Unique identifier of the department to delete. Must be a valid UUID referencing an existing department within the current organization.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Implementation steps:
   *
   * 1. Validate the authenticated member has org:manage permission in the current organization context
   * 2. Query erp_hrm_departments by departmentId within the current organization scope
   * 3. Return 404 if department not found or does not belong to current organization
   * 4. Check if department is already soft-deleted (deleted_at is not null) - return 410 if already deleted
   * 5. In a transaction:
   *    a. Find all employees in erp_hrm_employees where erp_hrm_department_id equals departmentId
   *    b. Update those employees to set erp_hrm_department_id to null
   *    c. Set deleted_at to current timestamp on the department record
   *    d. Update updated_at timestamp on the department
   * 6. Return the department record with deleted_at populated
   *
   * Database queries:
   * - SELECT * FROM erp_hrm_departments WHERE id = $1 AND organization_id = $2 AND deleted_at IS NULL
   * - UPDATE erp_hrm_employees SET erp_hrm_department_id = NULL, updated_at = NOW() WHERE erp_hrm_department_id = $1
   * - UPDATE erp_hrm_departments SET deleted_at = NOW(), updated_at = NOW() WHERE id = $1
   *
   * Edge cases:
   * - Department already deleted: return 410 Gone
   * - Department has children (sub-departments): cascade delete via schema onDelete Cascade handles this
   * - No permission: return 403 Forbidden
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":departmentId")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("departmentId")
    departmentId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteErpHrmMemberDepartmentsDepartmentId({
        member,
        departmentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
