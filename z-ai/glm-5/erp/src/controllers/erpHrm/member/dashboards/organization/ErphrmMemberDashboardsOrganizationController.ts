import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IErpHrmOrganizationDashboard } from "../../../../../api/structures/IErpHrmOrganizationDashboard";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { getErpHrmMemberDashboardsOrganization } from "../../../../../providers/getErpHrmMemberDashboardsOrganization";

@Controller("/erpHrm/member/dashboards/organization")
export class ErphrmMemberDashboardsOrganizationController {
  /**
   * Retrieve organization dashboard metrics for users with report viewing permissions.
   *
   * This operation provides a comprehensive overview of the organization's current operational status. The dashboard aggregates data across multiple entities to present key performance indicators and alerts.
   *
   * **Metrics included:**
   *
   * - Total active employees: Count of all employees with 'active' status within the organization
   * - Weekly hours: Total hours logged by all employees for the current week (Monday through Sunday)
   * - Pending approvals: Count of timesheets with 'submitted' status awaiting manager review
   * - Budget alerts: Projects where logged hours exceed 80% of allocated budget hours
   * - Top performers: Top 5 employees ranked by hours logged in the current week
   *
   * **Authorization requirements:**
   *
   * Users must have the 'report:view' permission to access this dashboard. This permission is typically granted to managers, organization owners, and users who need organization-wide visibility.
   *
   * **Related operations:**
   *
   * - PATCH /employees - View detailed employee list
   * - PATCH /timesheets - Access individual timesheet records
   * - GET /projects/{projectId} - View project details for budget utilization
   *
   * The dashboard provides a starting point for managers to identify areas requiring attention, such as pending approvals or projects approaching budget limits.
   *
   * @param connection
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query erp_hrm_employees table to count active
     *   employees (status = 'active') within the organization.
   *
   * Query erp_hrm_timelogs joined with erp_hrm_employees to calculate total hours logged this week (Monday to Sunday of current week). Sum duration field and convert minutes to hours.
   *
   * Query erp_hrm_timesheets to count records with status = 'submitted' awaiting approval.
   *
   * Query erp_hrm_projects with budget_hours not null, calculate utilization by summing timelog durations for each project, filter those with (actual_hours / budget_hours) > 0.8.
   *
   * Query erp_hrm_timelogs aggregated by employee for current week, sort by total hours descending, limit to top 5, join with erp_hrm_employees to get employee names.
   *
   * All queries must be scoped to the current organization context from the authenticated session.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @MemberAuth()
    member: MemberPayload,
  ): Promise<IErpHrmOrganizationDashboard> {
    try {
      return await getErpHrmMemberDashboardsOrganization({
        member,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
