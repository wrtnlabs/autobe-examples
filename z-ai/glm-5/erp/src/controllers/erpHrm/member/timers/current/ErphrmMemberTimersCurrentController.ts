import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IErpHrmTimer } from "../../../../../api/structures/IErpHrmTimer";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { getErpHrmMemberTimersCurrent } from "../../../../../providers/getErpHrmMemberTimersCurrent";

@Controller("/erpHrm/member/timers/current")
export class ErphrmMemberTimersCurrentController {
  /**
   * Retrieve the currently running timer for the authenticated employee.
   *
   * This endpoint allows employees to check the status and details of their active timer session. The response includes the timer's unique identifier, the start timestamp, the calculated elapsed time since the timer began, the selected project information, optional task assignment, and any description notes added during the tracking session.
   *
   * Security and authorization are enforced through employee ownership validation. Employees can only view their own timer and cannot access timers belonging to other employees. The timer must belong to a project the employee is assigned to as a project member through the erp_hrm_project_members junction table. If the employee has been deactivated, they cannot access their timer through this endpoint.
   *
   * The timer data is retrieved from the erp_hrm_timers table where deleted_at IS NULL, indicating an active timer. The response includes joined project details from erp_hrm_projects and optional task details from erp_hrm_tasks. If no active timer exists (no record with null deleted_at for the employee), the endpoint returns null to indicate no timer is running.
   *
   * This operation is typically used in conjunction with POST /erpHrm/member/timers to start a new timer, PUT /erpHrm/member/timers/current to edit timer details, POST /erpHrm/member/timers/current/stop to stop and create a timelog, and DELETE /erpHrm/member/timers/current to discard without creating a timelog.
   *
   * @param connection
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query the erp_hrm_timers table for the timer
     *   belonging to the authenticated employee where deleted_at IS NULL
     *   (indicating an active timer). Join with erp_hrm_projects to include
     *   project details (id, name) and optionally join with erp_hrm_tasks for
     *   task details (id, name) if erp_hrm_task_id is present. Calculate
     *   elapsed time as the difference between current timestamp and
     *   started_at. Return the complete timer record with project and task
     *   information if found, or null if no active timer exists. The employee
     *   ID is obtained from the authenticated user's employee record in the
     *   current organization context.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @MemberAuth()
    member: MemberPayload,
  ): Promise<IErpHrmTimer> {
    try {
      return await getErpHrmMemberTimersCurrent({
        member,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
