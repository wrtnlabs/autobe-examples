export async function test_api_timer_current_no_active_timer(
  connection: api.IConnection,
): Promise<void> {
  // Setup: Create member and authenticate
  const memberConnection: api.IConnection = { host: connection.host };
  await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      displayName: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  // Test: Call GET current timer when no timer has been started
  const currentTimer =
    await api.functional.erpHrm.member.timers.current.at(memberConnection);
  // Validation: Response should be null when no active timer exists
  TestValidator.equals(
    "current timer should be null when no timer active",
    currentTimer,
    null,
  );
}
