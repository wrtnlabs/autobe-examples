export async function test_api_timer_discard_unauthorized_non_owner(
  connection: api.IConnection,
): Promise<void> {
  // Step 1: Create Member A and establish organization context
  const memberAConnection: api.IConnection = { host: connection.host };
  const memberA = await authorize_member_join(memberAConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "Password123!",
      displayName: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  typia.assert(memberA);
  // Step 2: Create a project for timer association
  const project = await generate_random_erp_hrm_member_projects_create(
    memberAConnection,
    {
      body: {
        name: RandomGenerator.name(2),
        color_code: "#FF5733",
      },
    },
  );
  typia.assert(project);
  // Step 3: Member A creates a timer
  const timer = await generate_random_erp_hrm_member_timers_create(
    memberAConnection,
    {
      body: {
        project_id: project.id,
        description: RandomGenerator.paragraph({ sentences: 3 }),
      },
    },
  );
  typia.assert(timer);
  // Step 4: Create Member B (separate organization context)
  const memberBConnection: api.IConnection = { host: connection.host };
  const memberB = await authorize_member_join(memberBConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "Password456!",
      displayName: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  typia.assert(memberB);
  // Step 5: Member B attempts to discard Member A's timer
  // This should fail with 403 Forbidden (ownership violation)
  await TestValidator.httpError(
    "Member B cannot discard Member A's timer",
    403,
    async () => {
      await api.functional.erpHrm.member.timers.erase(memberBConnection, {
        timerId: timer.id,
      });
    },
  );
}
