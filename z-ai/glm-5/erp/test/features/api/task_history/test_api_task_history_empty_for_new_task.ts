export async function test_api_task_history_empty_for_new_task(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as a member (becomes owner of first organization)
  const memberConnection: api.IConnection = { host: connection.host };
  const memberAuth = await authorize_member_join(memberConnection, {});
  typia.assert(memberAuth);
  // 2. Create a new project
  const project = await generate_random_erp_hrm_member_projects_create(
    memberConnection,
    {},
  );
  typia.assert(project);
  // 3. Create a new task within the project
  const task = await generate_random_erp_hrm_member_projects_tasks_create(
    memberConnection,
    {
      params: { projectId: project.id },
    },
  );
  typia.assert(task);
  // 4. Retrieve history for the newly created task
  const historyResponse =
    await api.functional.erpHrm.member.projects.tasks.histories.index(
      memberConnection,
      {
        projectId: project.id,
        taskId: task.id,
        body: {},
      },
    );
  typia.assert(historyResponse);
  // 5. Verify the response is a valid pagination wrapper with empty data array
  TestValidator.equals("history data is empty", historyResponse.data, []);
  TestValidator.equals(
    "pagination records is 0",
    historyResponse.pagination.records,
    0,
  );
  TestValidator.equals(
    "pagination pages is 0",
    historyResponse.pagination.pages,
    0,
  );
}
