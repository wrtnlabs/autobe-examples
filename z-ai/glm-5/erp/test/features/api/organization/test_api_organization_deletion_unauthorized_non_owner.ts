export async function test_api_organization_deletion_unauthorized_non_owner(
  connection: api.IConnection,
): Promise<void> {
  // Member A joins - creates account and first organization (becomes owner)
  const memberAConnection: api.IConnection = { host: connection.host };
  const memberAAuthorized = await authorize_member_join(memberAConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      displayName: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  typia.assert(memberAAuthorized);
  // Member B joins - separate account with no ownership rights to Member A's organization
  const memberBConnection: api.IConnection = { host: connection.host };
  const memberBAuthorized = await authorize_member_join(memberBConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      displayName: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  typia.assert(memberBAuthorized);
  // Member B attempts to delete an organization using a random organization ID
  // Since Member B is not the owner of any organization they don't own,
  // this should return 403 Forbidden (authorization check before existence check)
  const organizationId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.httpError(
    "non-owner cannot delete organization",
    403,
    async () => {
      await api.functional.erpHrm.member.organizations.erase(
        memberBConnection,
        {
          organizationId,
        },
      );
    },
  );
}
