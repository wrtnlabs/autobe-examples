export async function test_api_task_creation_unauthorized_member(
  connection: api.IConnection,
): Promise<void> {
  // Step 1: Create member A (organization owner with project:manage permission)
  const ownerConnection: api.IConnection = { host: connection.host };
  const ownerAuth = await authorize_member_join(ownerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      displayName: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  typia.assert(ownerAuth);
  // Step 2: Create a project as the owner
  const project = await generate_random_erp_hrm_member_projects_create(
    ownerConnection,
    {
      body: {
        name: RandomGenerator.paragraph({ sentences: 2 }),
        color_code: `#${Math.floor(Math.random() * 16777215)
          .toString(16)
          .padStart(6, "0")}`,
      },
    },
  );
  typia.assert(project);
  // Step 3: Create member B (regular user without project:manage permission)
  const memberBConnection: api.IConnection = { host: connection.host };
  const memberBAuth = await authorize_member_join(memberBConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      displayName: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  typia.assert(memberBAuth);
  // Step 4: Create employee record for member B in owner's organization
  // Note: roleId will be generated by the utility; in real E2E this requires a valid role ID
  const employeeB = await generate_random_erp_hrm_member_employees_create(
    ownerConnection,
    {
      body: {
        email: memberBAuth.email,
        employmentType: "full_time",
      },
    },
  );
  typia.assert(employeeB);
  // Step 5: Add employee B to project as regular 'member' (not 'project_lead')
  const projectMember =
    await generate_random_erp_hrm_member_projects_members_create(
      ownerConnection,
      {
        params: {
          projectId: project.id,
        },
        body: {
          employee_id: employeeB.id,
          role: "member",
        },
      },
    );
  typia.assert(projectMember);
  // Step 6: Attempt to create a task as member B (should fail with 403 Forbidden)
  await TestValidator.httpError(
    "should reject task creation by regular project member",
    403,
    async () => {
      await api.functional.erpHrm.member.projects.tasks.create(
        memberBConnection,
        {
          projectId: project.id,
          body: {
            title: RandomGenerator.paragraph({ sentences: 1 }),
          } satisfies IErpHrmTask.ICreate,
        },
      );
    },
  );
}
