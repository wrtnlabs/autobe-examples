export async function test_api_task_retrieval_unauthorized_non_member(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create member A (project creator and task creator)
  const memberAConnection: api.IConnection = { host: connection.host };
  await authorize_member_join(memberAConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      displayName: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  // 2. Create a project (member A has project:manage permission as org owner)
  const project = await generate_random_erp_hrm_member_projects_create(
    memberAConnection,
    {},
  );
  typia.assert(project);
  // 3. Create a task within the project
  const task = await generate_random_erp_hrm_member_projects_tasks_create(
    memberAConnection,
    {
      params: {
        projectId: project.id,
      },
    },
  );
  typia.assert(task);
  // 4. Create member B (unauthorized user - NOT a project member, in different org)
  const memberBConnection: api.IConnection = { host: connection.host };
  await authorize_member_join(memberBConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      displayName: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  // 5. Attempt to retrieve the task with member B's connection (should fail)
  // Member B is not a project member and cannot access the task
  await TestValidator.httpError(
    "non-project-member should not be able to retrieve task",
    [403, 404],
    async () => {
      await api.functional.erpHrm.member.projects.tasks.at(memberBConnection, {
        projectId: project.id,
        taskId: task.id,
      });
    },
  );
}
