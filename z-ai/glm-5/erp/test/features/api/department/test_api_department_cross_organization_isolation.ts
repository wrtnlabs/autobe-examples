export async function test_api_department_cross_organization_isolation(
  connection: api.IConnection,
): Promise<void> {
  // Step 1: Create Member A and their organization
  const memberAConnection: api.IConnection = { host: connection.host };
  const memberA = await authorize_member_join(memberAConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      displayName: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  typia.assert(memberA);
  // Step 2: Create a department in Member A's organization
  const departmentA = await generate_random_erp_hrm_member_departments_create(
    memberAConnection,
    {
      body: {
        name: RandomGenerator.name(),
        description: RandomGenerator.paragraph({ sentences: 2 }),
      },
    },
  );
  typia.assert(departmentA);
  // Step 3: Create Member B with a different organization
  const memberBConnection: api.IConnection = { host: connection.host };
  const memberB = await authorize_member_join(memberBConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      displayName: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  typia.assert(memberB);
  // Step 4: Member B attempts to access Member A's department
  // Should return 404 Not Found (not 403 - to prevent information leakage)
  await TestValidator.httpError(
    "cross-organization department access should return 404",
    404,
    async () => {
      await api.functional.erpHrm.member.departments.at(memberBConnection, {
        departmentId: departmentA.id,
      });
    },
  );
}
