import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallReview } from "../../../../api/structures/IShoppingMallReview";
import { getShoppingMallProductsProductIdReviewStats } from "../../../../providers/getShoppingMallProductsProductIdReviewStats";

@Controller("/shoppingMall/products/:productId/review-stats")
export class ShoppingmallProductsReview_statsController {
  /**
   * Retrieve aggregated review statistics for a specific product.
   *
   * This endpoint returns computed review statistics including the average rating, total review count, and rating distribution (count of reviews for each star rating from 1 to 5). The statistics are calculated from all non-deleted reviews associated with the product.
   *
   * The average rating is computed as the mean of all non-deleted review ratings for the product. If the product has no reviews, the average rating will be null and the total count will be zero.
   *
   * This endpoint is used by:
   * - Product search and category listing pages to display rating summaries alongside each product
   * - Product detail pages to show overall rating summary before listing individual reviews
   * - Seller dashboard to monitor product reception
   *
   * Related endpoint: GET /products/{productId}/reviews returns paginated individual reviews for detailed browsing.
   *
   * @param connection
   * @param productId Product ID to retrieve review statistics for
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query shopping_mall_reviews table where shopping_mall_product_id = productId AND deleted_at IS NULL.
   *
   * Calculate:
   * 1. COUNT(*) as total_reviews
   * 2. AVG(rating) as average_rating (rounded to 2 decimal places)
   * 3. For each rating 1-5: COUNT(*) WHERE rating = n as rating_{n}_count
   *
   * Return statistics object with:
   * - averageRating: number | null (null if no reviews)
   * - totalReviews: integer
   * - ratingDistribution: array of { rating: 1-5, count: integer }
   *
   * Edge cases:
   * - If product has no reviews: return { averageRating: null, totalReviews: 0, ratingDistribution: [{rating:1,count:0}...] }
   * - All soft-deleted reviews (deleted_at IS NOT NULL) are excluded from calculations
   * - Verify productId exists in shopping_mall_products (return 404 if not found)
   *
   * Performance: Consider caching these statistics and updating them via triggers or background jobs when reviews are created/edited/deleted.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async get(
    @TypedParam("productId")
    productId: string,
  ): Promise<IShoppingMallReview.IStat> {
    try {
      return await getShoppingMallProductsProductIdReviewStats({
        productId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
