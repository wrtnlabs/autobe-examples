import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallReview } from "../../../../api/structures/IPageIShoppingMallReview";
import { IShoppingMallReview } from "../../../../api/structures/IShoppingMallReview";
import { patchShoppingMallProductsProductIdReviews } from "../../../../providers/patchShoppingMallProductsProductIdReviews";

@Controller("/shoppingMall/products/:productId/reviews")
export class ShoppingmallProductsReviewsController {
  /**
   * Retrieve a paginated list of customer reviews for a specific product.
   *
   * This endpoint returns all non-deleted reviews for the specified product, sorted by creation date with newest reviews appearing first. Each review includes the customer's display name (shown as 'deleted user' if the customer account has been deleted), the star rating from 1 to 5, optional text content, and the creation timestamp.
   *
   * Reviews can only be written by customers who have purchased and received the product, ensuring authentic feedback from verified buyers. The one-review-per-product-per-order constraint prevents review manipulation. Reviews contribute to the product's overall average rating, which is calculated from all non-deleted reviews.
   *
   * This endpoint supports pagination for efficient browsing of review history. The default page size is 10 items, with a maximum of 100 items per page. Results are always sorted by creation date descending to surface the most recent customer feedback first.
   *
   * @param connection
   * @param productId Unique identifier of the product to retrieve reviews for
   * @param body Pagination and search parameters for review listing
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query shopping_mall_reviews table where shopping_mall_product_id equals the productId parameter and deleted_at IS NULL. Join with shopping_mall_customers to retrieve display_name for each review author. Sort by created_at in descending order (newest first). Support pagination with configurable page size (default 10, max 100) and page number. Return paginated results with review summary data including author display name (or 'deleted user' if customer account deleted), rating, content, and created_at timestamp. Calculate and optionally include total review count and average rating for the product from non-deleted reviews only.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallReview.IRequest,
  ): Promise<IPageIShoppingMallReview.ISummary> {
    try {
      return await patchShoppingMallProductsProductIdReviews({
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
