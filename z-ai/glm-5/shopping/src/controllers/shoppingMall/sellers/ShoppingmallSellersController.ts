import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallSeller } from "../../../api/structures/IPageIShoppingMallSeller";
import { IShoppingMallSeller } from "../../../api/structures/IShoppingMallSeller";
import { getShoppingMallSellersSellerId } from "../../../providers/getShoppingMallSellersSellerId";
import { patchShoppingMallSellers } from "../../../providers/patchShoppingMallSellers";

@Controller("/shoppingMall/sellers")
export class ShoppingmallSellersController {
  /**
   * Retrieve a filtered and paginated list of seller accounts for administrative oversight.
   *
   * This endpoint provides administrators with comprehensive seller management capabilities including searching by shop name, filtering by approval status and account standing, and browsing seller registrations. The response includes essential seller information optimized for administrative dashboards and approval workflows.
   *
   * Administrators can use this endpoint to:
   * - Review pending seller approval requests
   * - Monitor approved, suspended, or banned seller accounts
   * - Search for specific sellers by shop name
   * - Track seller registration trends over time
   *
   * Results are paginated and can be sorted by registration date or shop name. The response includes seller identification, shop profile details, approval status, and account standing information.
   *
   * **Related Database Schema**: shopping_mall_sellers - Contains seller account information including approval workflow status (pending/approved/rejected), suspension/banning flags, and soft-delete tracking via deleted_at field.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for seller listing
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query shopping_mall_sellers table with pagination and filtering capabilities.
   *
   * 1. Apply search filters:
   *    - shopName: Partial match using LIKE or full-text search with Gin trigram index
   *    - approvalStatus: Exact match filter (pending/approved/rejected)
   *    - suspended: Boolean filter for suspended accounts
   *    - banned: Boolean filter for banned accounts
   *    - createdAt range filters (from/to)
   *
   * 2. Sorting options:
   *    - created_at (default descending)
   *    - shop_name ascending
   *
   * 3. Pagination:
   *    - Use cursor-based or offset-based pagination
   *    - Include total count in pagination metadata
   *
   * 4. Exclude soft-deleted sellers (deleted_at IS NULL)
   *
   * 5. Return summarized seller information for administrative dashboard display.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IShoppingMallSeller.IRequest,
  ): Promise<IPageIShoppingMallSeller.ISummary> {
    try {
      return await patchShoppingMallSellers({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a seller's public shop profile information.
   *
   * This operation allows customers to view seller shop details when browsing products or reviewing order information. The response includes the shop name, description, and logo image - all information visible on product listings and order details.
   *
   * **Public Profile Information**
   * The returned profile contains only publicly visible information that customers need to make purchase decisions:
   * - Shop name: Displayed on product listings and order details
   * - Shop description: Additional information about the seller's business
   * - Logo image: Visual branding shown on product pages and seller profile
   *
   * **Privacy Protection**
   * Sensitive seller information is not exposed through this endpoint:
   * - Email addresses remain private
   * - Approval status and rejection reasons are administrative data
   * - Account standing (suspended/banned status) is not disclosed
   *
   * **Related Operations**
   * - Product listings reference the seller's shop name
   * - Order details include seller information captured at purchase time
   * - Seller profile snapshots preserve historical seller information for orders
   *
   * @param connection
   * @param sellerId Unique identifier of the seller whose profile to retrieve (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Retrieve a seller's public shop profile by ID. Query the shopping_mall_sellers table where id equals the provided sellerId parameter and deleted_at is null. Only return publicly visible fields (shop_name, shop_description, logo_image). Do not expose sensitive fields such as email, password_hash, approval_status, rejection_reason, suspended, or banned. Return 404 Not Found if the seller does not exist or has been soft-deleted. This operation does not require authentication as customers can freely browse seller profiles.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sellerId")
  public async at(
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallSeller> {
    try {
      return await getShoppingMallSellersSellerId({
        sellerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
