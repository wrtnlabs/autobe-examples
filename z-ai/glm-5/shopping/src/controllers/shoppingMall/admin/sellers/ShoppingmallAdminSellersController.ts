import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IShoppingMallSeller } from "../../../../api/structures/IShoppingMallSeller";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { putShoppingMallAdminSellersSellerIdApprove } from "../../../../providers/putShoppingMallAdminSellersSellerIdApprove";
import { putShoppingMallAdminSellersSellerIdBan } from "../../../../providers/putShoppingMallAdminSellersSellerIdBan";
import { putShoppingMallAdminSellersSellerIdReject } from "../../../../providers/putShoppingMallAdminSellersSellerIdReject";
import { putShoppingMallAdminSellersSellerIdSuspend } from "../../../../providers/putShoppingMallAdminSellersSellerIdSuspend";
import { putShoppingMallAdminSellersSellerIdUnban } from "../../../../providers/putShoppingMallAdminSellersSellerIdUnban";
import { putShoppingMallAdminSellersSellerIdUnsuspend } from "../../../../providers/putShoppingMallAdminSellersSellerIdUnsuspend";

@Controller("/shoppingMall/admin/sellers/:sellerId")
export class ShoppingmallAdminSellersController {
  /**
   * Approve a pending seller registration, enabling the seller to operate on the platform.
   *
   * This administrator-only endpoint transitions a seller's registration from 'pending' status to 'approved' status. Once approved, the seller gains full platform capabilities including product creation, inventory management, order processing, and shop profile management.
   *
   * The operation validates that the target seller exists and currently has 'pending' approval status. If the seller is already approved, rejected, or suspended, the operation will fail with an appropriate error message.
   *
   * Upon successful approval:
   * - The seller's approval_status is changed to 'approved'
   * - The approving administrator's identity is recorded in the audit log
   * - The approval timestamp is captured
   * - The seller receives notification that they can now sell on the platform
   *
   * This endpoint is accessible to both regular administrators and super administrators. The approval decision is final unless the seller is later suspended or banned for policy violations.
   *
   * @param connection
   * @param sellerId Unique identifier of the seller account to approve. Must reference an existing seller with 'pending' approval status.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Implementation steps for seller approval:
   *
   * 1. Authenticate and authorize the requesting administrator
   *    - Verify JWT token is valid and belongs to an administrator account
   *    - Both regular and super administrators have approval permission
   *
   * 2. Validate the sellerId path parameter
   *    - Ensure sellerId is a valid UUID format
   *    - Query shopping_mall_sellers table to find the seller
   *    - Return 404 Not Found if seller doesn't exist
   *
   * 3. Validate seller's current approval_status
   *    - Seller must have approval_status = 'pending'
   *    - Return 400 Bad Request if seller is already 'approved', 'rejected', or 'suspended'
   *    - Include current status in error message
   *
   * 4. Process the approval
   *    - Update seller's approval_status to 'approved'
   *    - Set updated_at to current timestamp
   *    - Create audit log entry recording:
   *      - Approving administrator's ID
   *      - Target seller's ID
   *      - Action type: 'SELLER_APPROVAL'
   *      - Timestamp
   *
   * 5. Send notification to seller
   *    - Trigger email notification informing seller of approval
   *    - Include instructions for setting up shop profile if not complete
   *
   * 6. Return the updated seller object
   *    - Include all seller fields in response
   *    - Exclude sensitive fields like password_hash
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put("approve")
  public async approve(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("sellerId")
    sellerId: string,
  ): Promise<IShoppingMallSeller> {
    try {
      return await putShoppingMallAdminSellersSellerIdApprove({
        admin,
        sellerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Rejects a pending seller registration request, preventing the seller from operating on the platform.
   *
   * This administrative operation allows administrators to decline seller registration applications. Upon rejection, the seller's approval_status is changed from 'pending' to 'rejected', and the provided rejection reason is stored and made visible to the rejected seller.
   *
   * The rejection reason is mandatory and must clearly explain why the registration was denied. This reason is displayed to the seller when they log in, allowing them to understand the decision and potentially submit a new registration request addressing the concerns.
   *
   * Only sellers with 'pending' approval_status can be rejected. Attempting to reject an already approved, rejected, suspended, or banned seller will result in an error. The administrator's identity and the rejection timestamp are recorded for audit trail purposes.
   *
   * After rejection, sellers can view the rejection reason and submit a new registration request if they wish to address the administrator's concerns.
   *
   * @param connection
   * @param sellerId Unique identifier of the seller account to reject. Must be a UUID referencing a seller with 'pending' approval status in the shopping_mall_sellers table.
   * @param body Rejection details including mandatory reason explaining why the seller registration is denied
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Implementation Steps:
   *
   * 1. **Authentication & Authorization**: Verify the requesting user is authenticated and has admin role (regular or super administrator).
   *
   * 2. **Parameter Validation**: Validate sellerId is a valid UUID format.
   *
   * 3. **Request Body Validation**: Ensure rejection reason is provided and not empty (minimum length validation recommended).
   *
   * 4. **Seller Lookup**: Query shopping_mall_sellers table by id.
   *
   * 5. **Status Check**: Verify the seller exists and has approval_status = 'pending'. Return 400 error if seller cannot be rejected (already processed, suspended, or banned).
   *
   * 6. **Update Operation**: Update the seller record:
   *    - Set approval_status = 'rejected'
   *    - Set rejection_reason = provided reason
   *    - Set updated_at = current timestamp
   *
   * 7. **Audit Logging**: Record the rejection action in shopping_mall_admin_audit_logs including:
   *    - Administrator ID
   *    - Target seller ID
   *    - Action type: 'seller_reject'
   *    - Reason provided
   *    - Timestamp
   *
   * 8. **Notification** (optional): Trigger notification to the rejected seller's email.
   *
   * 9. **Response**: Return the updated seller object with new status and rejection reason.
   *
   * Error Cases:
   * - 401: Unauthorized (no valid admin session)
   * - 403: Forbidden (user is not an admin)
   * - 404: Seller not found
   * - 400: Seller not in pending status (cannot reject)
   * - 400: Rejection reason missing or invalid
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put("reject")
  public async reject(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("sellerId")
    sellerId: string,
    @TypedBody()
    body: IShoppingMallSeller.IReject,
  ): Promise<IShoppingMallSeller> {
    try {
      return await putShoppingMallAdminSellersSellerIdReject({
        admin,
        sellerId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Suspend a seller account, preventing them from selling and creating/editing products while allowing existing orders to be processed.
   *
   * This administrative action changes the seller's approval_status to 'suspended', effectively pausing their ability to conduct business on the platform. Suspended sellers cannot create new products, edit existing products, or make sales. However, their existing orders remain fully processable to ensure customer obligations are met.
   *
   * The suspension affects the seller's products by hiding them from search results and product listings, and preventing new purchases. Customers with existing orders from this seller will still receive their items, and the seller can still process shipments for pending orders.
   *
   * This operation is reversible through the unsuspend endpoint. The seller will not be notified automatically; administrators should communicate the suspension reason through appropriate channels.
   *
   * @param connection
   * @param sellerId Unique identifier of the seller to suspend
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Update the shopping_mall_sellers table, setting approval_status to 'suspended' for the specified seller ID.
   *
   * Implementation steps:
   * 1. Validate the seller exists and is not already suspended
   * 2. Check current status - can suspend from 'approved' or 'rejected' states
   * 3. Update approval_status to 'suspended'
   * 4. Update the updated_at timestamp
   *
   * Business rules:
   * - Cannot suspend a seller with status 'pending' (must approve/reject first)
   * - Cannot suspend a seller who is already suspended (idempotent - return current state)
   * - Cannot suspend a deleted seller (deleted_at is not null)
   *
   * Side effects:
   * - Seller's products become hidden from search and listings
   * - Seller's products become unpurchasable
   * - Seller cannot create new products or edit existing products
   * - Existing orders remain processable
   * - Seller can still process shipments and respond to cancellation/refund requests
   *
   * Authorization: Requires administrator role (ADMIN or SUPER_ADMIN)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put("suspend")
  public async suspend(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallSeller> {
    try {
      return await putShoppingMallAdminSellersSellerIdSuspend({
        admin,
        sellerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Restore a suspended seller account to active status.
   *
   * This administrator-only operation transitions a seller's approval_status from 'suspended' back to 'approved', immediately restoring full seller capabilities. When a seller is unsuspended, their products become visible in search results and category listings, customers can purchase their products again, and the seller regains the ability to edit their shop profile and create new products.
   *
   * Unlike suspension which restricts certain operations while allowing order processing, unsuspension fully restores the seller to their previous active state. The seller can immediately resume all normal business operations.
   *
   * This operation requires administrator privileges (regular or super administrator). The system records the unsuspending administrator's identity and the timestamp for audit purposes. Only sellers with 'suspended' approval_status can be unsuspended; attempting to unsuspend a seller in any other status will result in an error.
   *
   * Related operations: GET /sellers (list sellers), PUT /sellers/{sellerId}/suspend (suspend seller), PUT /sellers/{sellerId}/ban (ban seller).
   *
   * @param connection
   * @param sellerId Unique identifier of the seller account to unsuspend. Must be a valid UUID of an existing seller with 'suspended' approval_status.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Implementation steps for unsuspending a seller account:
   *
   * 1. Validate authentication and authorization:
   *    - Require authenticated administrator (regular or super admin)
   *    - Verify the requesting user has admin privileges
   *
   * 2. Validate the seller exists and is eligible for unsuspension:
   *    - Query shopping_mall_sellers table by sellerId
   *    - Verify seller exists (not deleted_at is null)
   *    - Verify seller's current approval_status is 'suspended'
   *    - If seller is in different status, return 400 error with appropriate message
   *
   * 3. Update the seller record:
   *    - Set approval_status to 'approved'
   *    - Update updated_at to current timestamp
   *    - Execute UPDATE on shopping_mall_sellers table
   *
   * 4. Audit logging:
   *    - Create an entry in shopping_mall_admin_audit_logs
   *    - Record: admin_id, action_type='unsuspend_seller', target_entity='seller', target_id=sellerId, timestamp
   *
   * 5. Response:
   *    - Return the complete updated seller object
   *    - Include all seller fields (id, email, shop_name, shop_description, logo_url, approval_status, created_at, updated_at)
   *
   * Edge cases:
   * - Seller not found: Return 404
   * - Seller already approved: Return 400 with message 'Seller is not suspended'
   * - Non-admin attempting access: Return 403
   * - Seller is deleted (deleted_at not null): Return 404
   *
   * The operation does not require a reason parameter for unsuspension, as it is a restoration of normal access rather than a punitive action.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put("unsuspend")
  public async unsuspend(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallSeller> {
    try {
      return await putShoppingMallAdminSellersSellerIdUnsuspend({
        admin,
        sellerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Suspend a seller account, preventing them from logging into the platform.
   *
   * This administrative action blocks the seller's ability to authenticate by setting their approval_status to 'suspended'. All seller data including products, orders, and order history is preserved.
   *
   * When a seller is suspended:
   * - The seller cannot log in to their account
   * - Products are hidden from search and category listings
   * - Products cannot be purchased (marked as unavailable)
   * - Existing orders remain processable by the seller if they regain access
   * - Shop information is preserved in order history
   *
   * This action can be reversed using the unsuspend endpoint to restore the seller's approval_status to 'approved'.
   *
   * Related to shopping_mall_sellers.approval_status field and shopping_mall_seller_sessions for session management.
   *
   * @param connection
   * @param sellerId Unique identifier of the seller to ban (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Implementation steps for banning a seller:
   *
   * 1. Validate the sellerId path parameter exists in shopping_mall_sellers table
   * 2. Verify the seller account is not already deleted (deleted_at should be null)
   * 3. Update the seller's account status to banned state (this may involve setting a banned flag or updating approval_status to 'banned' depending on schema implementation)
   * 4. Invalidate any active sessions for this seller by deleting records from shopping_mall_seller_sessions
   * 5. Return 204 No Content on success
   *
   * Error handling:
   * - 404 if seller not found
   * - 409 if seller is already banned
   * - 403 if requester is not an administrator
   *
   * The ban should NOT:
   * - Delete the seller account (deleted_at remains null)
   * - Delete or modify products
   * - Affect existing orders or order history
   * - Remove seller information from historical snapshots
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put("ban")
  public async ban(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await putShoppingMallAdminSellersSellerIdBan({
        admin,
        sellerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Restore access to a previously banned seller account, allowing the seller to log in and resume all platform activities.
   *
   * This administrator-only operation reverses a previous ban action, immediately restoring the seller's ability to authenticate and access the platform. Upon unban, the seller regains full access to all seller features including product creation, editing, order processing, and shop profile management.
   *
   * **Effects of Unban:**
   * - The seller's ability to log in is immediately restored
   * - All seller features become accessible again
   * - Products become visible in search and category listings
   * - Products become purchasable by customers
   *
   * **Audit Trail:**
   * The operation records the unbanning administrator's identity and the precise timestamp of the unban action for compliance and dispute resolution purposes.
   *
   * **Related Operations:**
   * This operation reverses the effects of PUT /sellers/{sellerId}/ban. Sellers can only be banned via PUT /sellers/{sellerId}/ban and unbanned through this endpoint.
   *
   * @param connection
   * @param sellerId Unique identifier of the seller account to unban
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Implement the unban seller operation as follows:
   *
   * 1. **Authentication & Authorization:**
   *    - Require authenticated administrator (regular or super admin)
   *    - Extract administrator identity from JWT token for audit trail
   *
   * 2. **Input Validation:**
   *    - Validate sellerId is a valid UUID format
   *    - Query shopping_mall_sellers table to verify seller exists
   *    - Return 404 if seller not found
   *
   * 3. **Business Logic:**
   *    - Check if seller is currently banned (implementation depends on ban tracking mechanism)
   *    - If seller is not banned, return appropriate error (seller not in banned state)
   *    - Update seller's ban status to unban the seller
   *    - Clear any ban-related metadata
   *
   * 4. **State Restoration:**
   *    - Restore seller's login capability
   *    - Restore product visibility in search/category listings
   *    - Restore product purchasability
   *    - Restore all seller editing capabilities
   *
   * 5. **Audit Recording:**
   *    - Record the unbanning administrator's identity
   *    - Record the unban timestamp
   *    - Create audit log entry for the unban action
   *
   * 6. **Response:**
   *    - Return updated seller object
   *    - Include success confirmation
   *
   * 7. **Error Handling:**
   *    - 401: Not authenticated
   *    - 403: Not authorized (not an admin)
   *    - 404: Seller not found
   *    - 400: Seller not in banned state
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put("unban")
  public async unban(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("sellerId")
    sellerId: string,
  ): Promise<IShoppingMallSeller> {
    try {
      return await putShoppingMallAdminSellersSellerIdUnban({
        admin,
        sellerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
