import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IShoppingMallCancellationRequest } from "../../../../../api/structures/IShoppingMallCancellationRequest";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { putShoppingMallAdminCancellationRequestsCancellationRequestIdForceApprove } from "../../../../../providers/putShoppingMallAdminCancellationRequestsCancellationRequestIdForceApprove";

@Controller(
  "/shoppingMall/admin/cancellation-requests/:cancellationRequestId/force-approve",
)
export class ShoppingmallAdminCancellation_requestsForce_approveController {
  /**
   * Force-approve a pending cancellation request as an administrator, bypassing the seller approval workflow.
   *
   * This endpoint allows administrators to intervene in the cancellation process when seller response is delayed or when administrative decision is required. The administrator takes responsibility for the approval decision, which is recorded in the snapshot system for audit purposes.
   *
   * When a cancellation request is force-approved, the system performs the following actions automatically:
   * 1. Updates the cancellation request status from 'pending' to 'approved'
   * 2. Changes the associated order item status from 'paid' to 'cancelled'
   * 3. Creates a positive inventory record to restore stock for the cancelled variant
   * 4. Initiates the refund process for the cancelled item
   * 5. Creates a snapshot recording the admin intervention with 'force-approve' action
   * 6. Sends notifications to both the customer and the seller about the cancellation approval
   *
   * This operation cannot be reversed. The force-approval is permanently recorded in the audit trail. Only cancellation requests with 'pending' status can be force-approved. Requests that have already been approved or rejected by the seller are not eligible for this operation.
   *
   * Administrators should use this power judiciously, as it overrides the normal seller-driven cancellation workflow. The action is logged with the administrator's identity for accountability.
   *
   * @param connection
   * @param cancellationRequestId Unique identifier of the cancellation request to force-approve. The request must exist and have 'pending' status.
   * @param body Optional administrator note explaining the reason for force-approval. This note will be included in the snapshot for audit purposes.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Implementation steps for force-approving a cancellation request:
   *
   * 1. VALIDATION:
   *    - Verify the authenticated user has administrator role (regular or super admin)
   *    - Fetch the cancellation request by ID, return 404 if not found
   *    - Verify the cancellation request status is 'pending', return 400 if already processed
   *    - Fetch the associated order item
   *    - Verify the order item status is 'paid' (cancellation eligibility), return 400 if not
   *
   * 2. TRANSACTION (all-or-nothing):
   *    a. Create cancellation request snapshot:
   *       - previous_status: 'pending'
   *       - new_status: 'approved'
   *       - reason: original customer reason
   *       - seller_response: admin note or 'Force approved by administrator'
   *       - Record administrator identity in snapshot
   *
   *    b. Update cancellation request:
   *       - status: 'approved'
   *       - seller_response: admin note or 'Force approved by administrator'
   *       - updated_at: current timestamp
   *
   *    c. Update order item status:
   *       - status: 'cancelled'
   *
   *    d. Create inventory restoration record:
   *       - shopping_mall_product_variant_id: from order item's variant reference
   *       - quantity_change: +[order item quantity]
   *       - reason: 'Cancellation force-approved by administrator - [order number]'
   *
   *    e. Update derived order status:
   *       - Recalculate overall order status based on all item statuses
   *       - If all items cancelled: order status = 'cancelled'
   *       - If mixed statuses: order status = 'partially_completed'
   *
   *    f. Initiate refund process:
   *       - Queue refund job for the cancelled item amount (unit_price * quantity)
   *       - Use original payment method where possible
   *
   * 3. NOTIFICATIONS:
   *    - Send notification to customer: cancellation approved, refund processing
   *    - Send notification to seller: cancellation was force-approved by administrator
   *
   * 4. RETURN:
   *    - Return the updated cancellation request with full details
   *    - Include order item status change confirmation
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async forceApprove(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("cancellationRequestId")
    cancellationRequestId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallCancellationRequest.IForceApprove,
  ): Promise<IShoppingMallCancellationRequest> {
    try {
      return await putShoppingMallAdminCancellationRequestsCancellationRequestIdForceApprove(
        {
          admin,
          cancellationRequestId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
