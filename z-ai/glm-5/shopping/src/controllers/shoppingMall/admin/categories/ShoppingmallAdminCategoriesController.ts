import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallCategory } from "../../../../api/structures/IShoppingMallCategory";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { deleteShoppingMallAdminCategoriesCategoryId } from "../../../../providers/deleteShoppingMallAdminCategoriesCategoryId";
import { postShoppingMallAdminCategories } from "../../../../providers/postShoppingMallAdminCategories";
import { putShoppingMallAdminCategoriesCategoryId } from "../../../../providers/putShoppingMallAdminCategoriesCategoryId";

@Controller("/shoppingMall/admin/categories")
export class ShoppingmallAdminCategoriesController {
  /**
   * Create a new product category in the e-commerce platform.
   *
   * This administrator-only operation creates a new category for organizing products. The platform supports a two-level hierarchy: top-level categories (parent categories) and subcategories. When parentId is null, a top-level category is created. When parentId is provided, a subcategory is created under the specified parent category.
   *
   * Category names must be unique among siblings within the same parent category. For example, two top-level categories cannot share the same name, and two subcategories under the same parent cannot share the same name. However, a subcategory can have the same name as a top-level category or a subcategory under a different parent.
   *
   * Administrators should ensure appropriate category naming and hierarchy structure before creation. Once created, categories can be used to classify products for browsing and search functionality.
   *
   * @param connection
   * @param body Category creation data including name, optional description, and optional parent category ID for subcategory creation
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Create a new category record in shopping_mall_categories table.
   *
   * 1. Validate that the requesting user has administrator role
   * 2. If parentId is provided:
   *    - Verify the parent category exists and is not soft-deleted
   *    - Verify that parent_id is null (cannot create subcategory under another subcategory - two-level limit)
   * 3. Check uniqueness constraint: query for existing category with same name under same parent
   *    - If parentId is null: check no top-level category with same name
   *    - If parentId provided: check no sibling subcategory with same name
   * 4. Create category record with:
   *    - id: generate new UUID
   *    - parent_id: from request (or null)
   *    - name: from request
   *    - description: from request (or null)
   *    - created_at: current timestamp
   *    - updated_at: current timestamp
   *    - deleted_at: null
   * 5. Return the created category
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallCategory.ICreate,
  ): Promise<IShoppingMallCategory> {
    try {
      return await postShoppingMallAdminCategories({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing category's name and description.
   *
   * This operation allows administrators to modify category information. The category name must remain unique among sibling categories (categories sharing the same parent). The category's parent relationship and ID cannot be changed through this endpoint.
   *
   * The shopping_mall_categories table stores category data with name uniqueness enforced at the sibling level through the @@unique([parent_id, name]) constraint. Each category has a name for display identification and an optional description for explaining the category's purpose and scope.
   *
   * Administrators should use this endpoint to correct typos, improve descriptions, or update category names while maintaining the two-level hierarchy structure. Changes take effect immediately in product listings and navigation.
   *
   * Security: This endpoint requires administrator authentication. Only administrators and super administrators can modify categories.
   *
   * @param connection
   * @param categoryId Unique identifier of the category to update (UUID format)
   * @param body Category update data containing new name and description
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Implementation steps:
   *
   * 1. Authenticate and authorize: Verify JWT token belongs to admin or super admin role
   * 2. Validate path parameter: Ensure categoryId is a valid UUID format
   * 3. Fetch category: Query shopping_mall_categories by id where deleted_at is null
   * 4. Return 404 if category not found or is soft-deleted
   * 5. Validate request body: Ensure name is provided and meets length requirements
   * 6. Check sibling uniqueness: Query shopping_mall_categories where parent_id equals target category's parent_id and name equals the new name, excluding the current category by id
   * 7. If duplicate name found among siblings, return 409 Conflict
   * 8. Update category record: Set new name and description, update updated_at to current timestamp
   * 9. Return updated category entity with all fields
   *
   * Database queries:
   * - SELECT * FROM shopping_mall_categories WHERE id = $categoryId AND deleted_at IS NULL
   * - SELECT COUNT(*) FROM shopping_mall_categories WHERE parent_id = $parent_id AND name = $newName AND id != $categoryId AND deleted_at IS NULL
   * - UPDATE shopping_mall_categories SET name = $name, description = $description, updated_at = NOW() WHERE id = $categoryId
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":categoryId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("categoryId")
    categoryId: string,
    @TypedBody()
    body: IShoppingMallCategory.IUpdate,
  ): Promise<IShoppingMallCategory> {
    try {
      return await putShoppingMallAdminCategoriesCategoryId({
        admin,
        categoryId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Mark a category as deleted by setting the deleted_at timestamp, removing it from active platform listings while preserving its data for audit purposes.
   *
   * This administrator-only operation soft-deletes a category, removing it from category listings and navigation while maintaining data integrity. When a category is deleted, all products previously assigned to that category become uncategorized (their category_id is set to null) and remain available for purchase. These products will no longer appear in category-specific listings but will still be visible in search results.
   *
   * For parent categories (categories with subcategories), this operation will cascade the soft-delete to all child subcategories. The entire category hierarchy under the deleted parent will be marked as deleted, ensuring category tree integrity is maintained. The shopping_mall_categories table enforces a two-level hierarchy where parent_id references another category for subcategories or is null for top-level categories.
   *
   * Administrators should be warned about the number of affected products and subcategories before confirming deletion. This endpoint is accessible only to users with administrator role (regular or super administrator).
   *
   * @param connection
   * @param categoryId Unique identifier of the category to delete. This is a UUID that references the primary key in the shopping_mall_categories table.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Implementation steps for category deletion:
   *
   * 1. **Authorization Check**: Verify the requesting user has admin role. Return 403 Forbidden if not authorized.
   *
   * 2. **Category Lookup**: Query shopping_mall_categories table by categoryId (UUID). Return 404 Not Found if category does not exist or is already soft-deleted (deleted_at is not null).
   *
   * 3. **Identify Affected Entities**:
   *    - Count products referencing this category (shopping_mall_products where category_id matches)
   *    - If parent category: find all subcategories where parent_id matches
   *
   * 4. **Transaction Execution**:
   *    - Begin database transaction
   *    - Set deleted_at = now() on the target category
   *    - For parent categories: cascade soft-delete to all children (UPDATE shopping_mall_categories SET deleted_at = now() WHERE parent_id = categoryId AND deleted_at IS NULL)
   *    - Set category_id = null for all products in the deleted category and its subcategories (UPDATE shopping_mall_products SET category_id = null WHERE category_id IN (deleted category and child IDs))
   *    - Commit transaction
   *
   * 5. **Response**: Return the soft-deleted category object with updated deleted_at timestamp.
   *
   * 6. **Error Handling**: Return appropriate error codes for invalid UUID format (400), category not found (404), unauthorized access (403).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":categoryId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("categoryId")
    categoryId: string,
  ): Promise<void> {
    try {
      return await deleteShoppingMallAdminCategoriesCategoryId({
        admin,
        categoryId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
