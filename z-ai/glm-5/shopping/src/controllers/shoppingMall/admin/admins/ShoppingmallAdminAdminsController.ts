import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallAdmin } from "../../../../api/structures/IPageIShoppingMallAdmin";
import { IShoppingMallAdmin } from "../../../../api/structures/IShoppingMallAdmin";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminAdminsAdminId } from "../../../../providers/getShoppingMallAdminAdminsAdminId";
import { patchShoppingMallAdminAdmins } from "../../../../providers/patchShoppingMallAdminAdmins";
import { putShoppingMallAdminAdminsAdminIdDemote } from "../../../../providers/putShoppingMallAdminAdminsAdminIdDemote";
import { putShoppingMallAdminAdminsAdminIdPromote } from "../../../../providers/putShoppingMallAdminAdminsAdminIdPromote";

@Controller("/shoppingMall/admin/admins")
export class ShoppingmallAdminAdminsController {
  /**
   * Retrieve a paginated and filtered list of administrator accounts on the platform.
   *
   * This endpoint provides comprehensive search capabilities for administrators to manage and oversee other admin accounts. It supports filtering by email address, display name, administrator grade (regular or super), and account deletion status.
   *
   * The response includes essential administrator information optimized for list displays, including unique identifier, email, display name, grade level, and timestamps. Soft-deleted administrators can be included or excluded based on the filter criteria.
   *
   * This operation is restricted to authenticated administrators only. Super administrators typically use this endpoint to manage other administrator accounts, including promotions and demotions.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for administrator listing
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query shopping_mall_admins table with pagination, filtering, and sorting support.
   *
   * Implementation steps:
   * 1. Validate administrator authentication and role
   * 2. Apply search filters:
   *    - Email: partial match (case-insensitive)
   *    - Name: partial match (case-insensitive)
   *    - Grade: exact match ('regular' or 'super')
   *    - Deleted status: include/exclude soft-deleted accounts
   * 3. Apply sorting (default: created_at descending)
   * 4. Execute paginated query with cursor-based pagination
   * 5. Transform results to ISummary format excluding sensitive fields (password_hash)
   * 6. Return paginated response with pagination metadata
   *
   * Database query:
   * - SELECT id, email, grade, name, created_at, updated_at, deleted_at
   * - Apply WHERE clauses for filters
   * - Apply ORDER BY for sorting
   * - Apply LIMIT/OFFSET for pagination
   *
   * Security considerations:
   * - Never expose password_hash in response
   * - Only administrators can access this endpoint
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallAdmin.IRequest,
  ): Promise<IPageIShoppingMallAdmin.ISummary> {
    try {
      return await patchShoppingMallAdminAdmins({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific administrator account.
   *
   * This endpoint allows authenticated super administrators to view administrator account details. Super administrators can view any administrator account on the platform, including both regular and super administrator accounts.
   *
   * The response includes the administrator's email address, permission grade (regular or super), display name, and account creation/modification timestamps. For security reasons, the password hash is never included in the response.
   *
   * If the administrator account has been soft-deleted (deleted_at is not null), the record will still be returned. This allows super administrators to audit and review historical administrative actions even after account deletion.
   *
   * @param connection
   * @param adminId Unique identifier of the administrator to retrieve (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query the shopping_mall_admins table by primary key (id) to retrieve a single administrator record.
   *
   * Implementation steps:
   * 1. Validate the adminId path parameter as a valid UUID format
   * 2. Query shopping_mall_admins table WHERE id = adminId
   * 3. If no record found, return 404 Not Found error
   * 4. Map the database record to IShoppingMallAdmin response DTO
   * 5. Explicitly exclude password_hash field from the response for security
   * 6. Return the administrator details
   *
   * Authorization: Require authenticated admin user. Super admins can view any admin; regular admins may have restricted access based on platform policy.
   *
   * Error handling:
   * - 400 Bad Request: Invalid UUID format for adminId
   * - 401 Unauthorized: Missing or invalid authentication token
   * - 403 Forbidden: Insufficient permissions (non-admin attempting access)
   * - 404 Not Found: Administrator with specified ID does not exist
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":adminId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string,
  ): Promise<IShoppingMallAdmin> {
    try {
      return await getShoppingMallAdminAdminsAdminId({
        admin,
        adminId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Elevate a regular administrator to super administrator grade.
   *
   * This operation allows super administrators to promote existing regular administrators to super administrator status, granting them elevated platform management capabilities including the ability to manage other administrator accounts.
   *
   * **Authorization Requirements:**
   * - Only super administrators can perform this operation
   * - Regular administrators are denied access
   * - Cannot promote a super administrator (already at highest grade)
   *
   * **Business Rules:**
   * - The target administrator must currently have 'regular' grade
   * - A super administrator cannot promote themselves (no effect)
   * - The promotion takes effect immediately upon successful execution
   * - An audit log entry is created recording: the promoting administrator, target administrator, reason, and timestamp
   *
   * **Related Operations:**
   * - PUT /admins/{adminId}/demote - Reverse operation to demote super administrators
   * - GET /admins - View all administrators (for identifying promotion candidates)
   *
   * **Security Considerations:**
   * - Promotion grants significant platform control including user management
   * - All promotions are permanently logged for security auditing
   * - IP address is recorded for security investigations
   *
   * @param connection
   * @param adminId UUID of the administrator to promote from regular to super grade (global scope)
   * @param body Promotion request containing the reason for elevating the administrator to super grade
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Implementation steps for administrator promotion:
   *
   * 1. **Authorization Check:**
   *    - Extract the authenticated administrator from JWT token
   *    - Verify the administrator has 'super' grade
   *    - Return 403 Forbidden if not a super administrator
   *
   * 2. **Target Validation:**
   *    - Query shopping_mall_admins table for the adminId parameter
   *    - Verify the administrator exists and is not soft-deleted (deleted_at is null)
   *    - Check current grade is 'regular' (cannot promote super administrators)
   *    - Return appropriate error if validation fails
   *
   * 3. **Self-Promotion Prevention:**
   *    - Compare the authenticated administrator's id with the target adminId
   *    - If same, return 400 Bad Request (cannot promote self)
   *
   * 4. **Database Update:**
   *    - Update shopping_mall_admins.grade to 'super'
   *    - Update updated_at timestamp to current time
   *    - Use transaction to ensure atomicity with audit log
   *
   * 5. **Audit Log Creation:**
   *    - Create record in shopping_mall_admin_audit_logs
   *    - Set shopping_mall_admin_id to the promoting administrator's id
   *    - Set action to 'admin_promote'
   *    - Set target_type to 'admin'
   *    - Set target_id to the promoted administrator's id
   *    - Set details to JSON containing the reason from request body
   *    - Set ip to the request client IP
   *    - Set created_at to current timestamp
   *
   * 6. **Response:**
   *    - Return the updated administrator entity with grade='super'
   *    - Include all standard fields except password_hash
   *
   * **Edge Cases:**
   * - Administrator already promoted by another super admin: grade check will fail
   * - Concurrent requests: Use database transaction and optimistic locking
   * - Soft-deleted administrator: Check deleted_at is null
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":adminId/promote")
  public async promote(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string,
    @TypedBody()
    body: IShoppingMallAdmin.IPromote,
  ): Promise<IShoppingMallAdmin> {
    try {
      return await putShoppingMallAdminAdminsAdminIdPromote({
        admin,
        adminId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Demotes a super administrator to regular administrator status.
   *
   * This privileged operation is available only to super administrators and allows them to reduce the permission level of another super administrator from 'super' to 'regular'. The demotion immediately reduces the target administrator's capabilities, removing their ability to manage other administrator accounts.
   *
   * **Authorization Requirements:**
   * - Only super administrators can perform this operation
   * - A super administrator cannot demote themselves (self-demotion prevention)
   * - The target administrator must exist and currently have 'super' grade
   *
   * **Business Rules:**
   * - After demotion, the target administrator retains all regular administrator capabilities (seller approvals, category management, product oversight, order management, user moderation)
   * - The demoted administrator loses the ability to promote/demote other administrators
   * - This action is logged in the admin audit trail for accountability
   *
   * **Related Operations:**
   * - PUT /admins/{adminId}/promote - Counterpart operation to promote regular admins to super
   * - GET /admins - List all administrators to identify candidates for demotion
   *
   * @param connection
   * @param adminId Unique identifier of the administrator to demote from super to regular grade
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Implementation steps for demoting a super administrator:
   *
   * 1. **Authorization Check:**
   *    - Verify the requesting user is authenticated as an administrator
   *    - Verify the requesting administrator has 'super' grade
   *    - Return 403 Forbidden if not a super administrator
   *
   * 2. **Self-Demotion Prevention:**
   *    - Compare the target adminId with the requesting administrator's ID
   *    - Return 400 Bad Request with appropriate error if attempting self-demotion
   *
   * 3. **Target Validation:**
   *    - Query shopping_mall_admins table for the target adminId
   *    - Return 404 Not Found if administrator does not exist
   *    - Verify the target's deleted_at is null (active account)
   *    - Verify the target's grade is currently 'super'
   *    - Return 400 Bad Request if target is not a super administrator
   *
   * 4. **Perform Demotion:**
   *    - Update the target administrator's grade from 'super' to 'regular'
   *    - Update the updated_at timestamp to current time
   *    - Execute within a transaction
   *
   * 5. **Audit Logging:**
   *    - Create an entry in shopping_mall_admin_audit_logs recording:
   *      - Action type: 'admin_demoted'
   *      - Performed by: requesting administrator ID
   *      - Target: demoted administrator ID
   *      - Previous value: 'super'
   *      - New value: 'regular'
   *      - Timestamp
   *
   * 6. **Response:**
   *    - Return the updated administrator record (excluding password_hash)
   *    - Include id, email, grade ('regular'), name, created_at, updated_at
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":adminId/demote")
  public async demote(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallAdmin> {
    try {
      return await putShoppingMallAdminAdminsAdminIdDemote({
        admin,
        adminId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
