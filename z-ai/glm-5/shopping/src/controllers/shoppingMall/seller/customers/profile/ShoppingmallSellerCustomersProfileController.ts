import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallCustomer } from "../../../../../api/structures/IShoppingMallCustomer";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { getShoppingMallSellerCustomersProfile } from "../../../../../providers/getShoppingMallSellerCustomersProfile";

@Controller("/shoppingMall/seller/customers/profile")
export class ShoppingmallSellerCustomersProfileController {
  /**
   * Retrieve the authenticated customer's profile information including display name and phone number.
   *
   * This endpoint allows logged-in customers to view their personal profile data. The profile contains optional fields that customers can set for their public identity and contact purposes. Display names are shown in reviews and public interactions on the platform.
   *
   * The response includes the customer's current display name and phone number. Both fields are optional and may be null if the customer has not provided this information. The email field from authentication credentials is separate from profile information.
   *
   * **Authorization**: Only authenticated customers can access their own profile. The customer is identified from the JWT token in the request header.
   *
   * **Database Reference**: This operation queries the shopping_mall_customers table, specifically the display_name and phone_number columns which are nullable text fields that can be edited by customers at any time without approval.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Retrieve the authenticated customer's profile from the shopping_mall_customers table.
   *
   * 1. Extract customer ID from JWT token in Authorization header
   * 2. Query shopping_mall_customers table by ID
   * 3. Verify customer account is not deleted (deleted_at is null)
   * 4. Return profile data including:
   *    - id: UUID primary key
   *    - email: Customer's authentication email
   *    - displayName: Optional display name (max 50 chars)
   *    - phoneNumber: Optional contact phone number
   *    - banned: Account ban status
   *    - createdAt: Account creation timestamp
   *    - updatedAt: Last profile update timestamp
   *
   * Edge cases:
   * - If customer not found, return 404 NOT_FOUND
   * - If customer is deleted (deleted_at not null), return 401 UNAUTHORIZED
   * - Return null values for display_name/phone_number if not set
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @SellerAuth()
    seller: SellerPayload,
  ): Promise<IShoppingMallCustomer> {
    try {
      return await getShoppingMallSellerCustomersProfile({
        seller,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
