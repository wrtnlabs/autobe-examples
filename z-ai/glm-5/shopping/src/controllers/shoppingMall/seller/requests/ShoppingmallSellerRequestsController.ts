import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallAdministratorSession } from "../../../../api/structures/IShoppingMallAdministratorSession";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { postShoppingMallSellerRequests } from "../../../../providers/postShoppingMallSellerRequests";

@Controller("/shoppingMall/seller/requests")
export class ShoppingmallSellerRequestsController {
  /**
   * Create a new administrator request submission.
   *
   * This endpoint allows authenticated customers and sellers to submit a request to become a platform administrator. The request includes a reason text explaining why the user should be granted administrator privileges. Upon creation, the request is assigned 'pending' status and awaits review by a super administrator.
   *
   * **Request Submission Process**:
   * - Any customer or seller may submit an administrator request
   * - Users who are already administrators cannot submit requests
   * - The reason field is required and must contain meaningful justification
   * - Multiple requests may be submitted over time; previous rejections do not block new submissions
   *
   * **Authentication Requirements**:
   * - User must be authenticated as either a customer or seller
   * - User must not already hold an administrator role
   *
   * **Initial State**:
   * - Status is automatically set to 'pending'
   * - reviewedAt and reviewedBy fields are null until a super administrator reviews the request
   *
   * **Related Operations**:
   * - GET /requests - List pending requests (super administrator only)
   * - PATCH /requests/{id}/approve - Approve a request (super administrator only)
   * - PATCH /requests/{id}/reject - Reject a request (super administrator only)
   *
   * The created request will appear in the pending requests list visible to super administrators for review and approval.
   *
   * @param connection
   * @param body Administrator request creation data containing the reason text for the administrator role request
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Implementation Steps:
   *
   * 1. **Authentication & Authorization**:
   *    - Extract user from authentication context
   *    - Verify user is authenticated
   *    - Verify user is NOT an administrator (reject if already administrator)
   *    - Accept either customer or seller user type
   *
   * 2. **Request Validation**:
   *    - Validate 'reason' field is provided and non-empty
   *    - Validate reason text length (recommended: min 10 characters for meaningful request)
   *    - Sanitize reason text for security
   *
   * 3. **Database Operations**:
   *    - Create new AdministratorRequest record
   *    - Set status = 'pending'
   *    - Set reviewedAt = null
   *    - Set reviewedBy = null
   *    - Link to requesting user (customer_id or seller_id)
   *    - Set createdAt = current timestamp
   *    - Set updatedAt = current timestamp
   *
   * 4. **Response Construction**:
   *    - Return complete request object with:
   *      - id (generated UUID)
   *      - reason (from request body)
   *      - status ('pending')
   *      - reviewedAt (null)
   *      - reviewer (null)
   *      - requester info (customer or seller reference)
   *      - createdAt timestamp
   *
   * 5. **Error Handling**:
   *    - 401 if not authenticated
   *    - 403 if user is already an administrator
   *    - 400 if reason is empty or missing
   *    - 400 if reason validation fails
   *
   * 6. **Business Rule Enforcement**:
   *    - Preserve history of all previous requests by this user
   *    - Allow multiple submissions over time (no limit per requirements)
   *    - Do NOT check for existing pending requests (new request allowed regardless of previous)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IShoppingMallAdministratorSession.ICreate,
  ): Promise<IShoppingMallAdministratorSession> {
    try {
      return await postShoppingMallSellerRequests({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
