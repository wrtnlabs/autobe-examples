import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IPageIShoppingMallProductInventoryHistory } from "../../../../../../api/structures/IPageIShoppingMallProductInventoryHistory";
import { IShoppingMallProductInventoryHistory } from "../../../../../../api/structures/IShoppingMallProductInventoryHistory";
import { SellerAuth } from "../../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../../decorators/payload/SellerPayload";
import { patchShoppingMallSellerVariantsVariantIdInventoryHistories } from "../../../../../../providers/patchShoppingMallSellerVariantsVariantIdInventoryHistories";

@Controller("/shoppingMall/seller/variants/:variantId/inventory/histories")
export class ShoppingmallSellerVariantsInventoryHistoriesController {
  /**
   * Retrieve a paginated list of inventory history records for a specific product variant.
   *
   * This endpoint provides sellers with a complete audit trail of all stock movements for their product variants. Each history record captures the quantity change (positive for restocks, cancellations, and refunds; negative for orders and adjustments), the reason for the change, and the timestamp when it occurred.
   *
   * The inventory history is an append-only audit trail that supports inventory tracking, dispute resolution, and compliance requirements. Current stock for any variant is calculated by summing all quantity_change values across its history records.
   *
   * **Use Cases:**
   * - Monitor stock movement patterns over time
   * - Investigate discrepancies in inventory levels
   * - Track impact of orders, cancellations, and refunds on stock
   * - Verify restock and adjustment records
   *
   * **Filtering Options:**
   * - Date range filtering to view specific time periods
   * - Reason filtering to view specific types of changes (restock, order, cancellation, refund, adjustment, loss)
   *
   * **Related Operations:**
   * - POST /variants/{variantId}/inventory/add - Add stock to a variant
   * - POST /variants/{variantId}/inventory/subtract - Subtract stock from a variant
   *
   * This operation is restricted to authenticated sellers who own the product variant.
   *
   * @param connection
   * @param variantId Unique identifier of the product variant whose inventory history is being queried
   * @param body Search criteria including date range filters, reason filters, and pagination parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query shopping_mall_product_inventory_histories table filtered by shopping_mall_product_variant_id matching the path parameter.
   *
   * **Database Query:**
   * 1. Verify the variant exists and belongs to the authenticated seller (join through shopping_mall_product_variants -> shopping_mall_products -> seller_id)
   * 2. If variant not found or seller doesn't own it, return 404/403 error
   * 3. Apply request body filters:
   *    - Filter by created_at range if date filters provided
   *    - Filter by reason if provided
   * 4. Order by created_at descending (most recent first)
   * 5. Apply pagination using cursor-based or offset-based pagination
   * 6. Calculate running balance for each record (cumulative sum of quantity_change)
   *
   * **Response Fields:**
   * - Include quantity_change, reason, created_at
   * - Include computed running_balance for each record
   * - Include variant basic info (sku_code) in response metadata
   *
   * **Authorization:**
   * - Seller must own the product variant
   * - Return 403 if seller doesn't own the variant
   * - Return 404 if variant doesn't exist
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("variantId")
    variantId: string,
    @TypedBody()
    body: IShoppingMallProductInventoryHistory.IRequest,
  ): Promise<IPageIShoppingMallProductInventoryHistory.ISummary> {
    try {
      return await patchShoppingMallSellerVariantsVariantIdInventoryHistories({
        seller,
        variantId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
