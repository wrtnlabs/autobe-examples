import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallOrderItem } from "../../../../api/structures/IShoppingMallOrderItem";
import { IShoppingMallOrderItemStat } from "../../../../api/structures/IShoppingMallOrderItemStat";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { patchShoppingMallSellerOrderItemStats } from "../../../../providers/patchShoppingMallSellerOrderItemStats";

@Controller("/shoppingMall/seller/order-item-stats")
export class ShoppingmallSellerOrder_item_statsController {
  /**
   * Retrieve aggregated statistics and filtered list of order items for seller dashboard analytics.
   *
   * This operation provides comprehensive order item analytics essential for seller dashboard functionality. It returns both aggregated statistics (total counts, quantities, values, and status breakdowns) and individual order item details matching the filter criteria.
   *
   * The shopping_mall_order_items table maintains complete snapshot data for each item including product_name, variant_sku_code, seller_shop_name, quantity, unit_price, and status. This snapshot data is captured at order placement time and preserved immutably for historical accuracy and dispute resolution, even if the original products or seller profiles are later modified or deleted.
   *
   * Item status values follow the order lifecycle: 'paid' (awaiting shipment), 'shipped' (in transit), 'delivered' (received by customer), 'cancelled' (cancelled before shipping), and 'refunded' (refunded after delivery). Each item has independent status enabling item-level operations.
   *
   * For sellers, this endpoint provides dashboard metrics including total order items count, pending cancellations count, and pending refunds count. The authorization ensures sellers can only access their own items through the shopping_mall_seller_id relationship.
   *
   * @param connection
   * @param body Filter criteria for order item statistics including status array for breakdown, date range for historical analysis, and optional seller/product ID for administrative queries
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query shopping_mall_order_items table with applied filters and aggregation.
   *
   * Implementation steps:
   * 1. Parse request body for filter criteria (status array, date range, seller ID, product ID)
   * 2. Apply WHERE conditions based on provided filters
   * 3. Execute two queries in parallel:
   *    a. COUNT query with status breakdown
   *    b. Detail query with pagination for individual items
   * 4. Calculate aggregates: SUM(quantity), SUM(quantity * unit_price)
   * 5. Combine results into IShoppingMallOrderItemStats response structure
   *
   * Filter handling:
   * - status: Array of status strings to include (empty = all statuses)
   * - fromDate/toDate: Filter by created_at timestamp range
   * - sellerId: Filter by shopping_mall_seller_id (for admin cross-seller queries)
   * - productId: Filter by shopping_mall_product_id
   *
   * Security:
   * - Sellers can only query their own items (shopping_mall_seller_id = current seller)
   * - Admins can query across all sellers
   * - Customers cannot access this endpoint
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async aggregateStats(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IShoppingMallOrderItem.IRequest,
  ): Promise<IShoppingMallOrderItemStat> {
    try {
      return await patchShoppingMallSellerOrderItemStats({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
