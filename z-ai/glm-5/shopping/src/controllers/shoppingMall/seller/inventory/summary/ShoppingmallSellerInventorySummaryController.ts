import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IPageIShoppingMallProductVariant } from "../../../../../api/structures/IPageIShoppingMallProductVariant";
import { IShoppingMallProductVariant } from "../../../../../api/structures/IShoppingMallProductVariant";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { patchShoppingMallSellerInventorySummary } from "../../../../../providers/patchShoppingMallSellerInventorySummary";

@Controller("/shoppingMall/seller/inventory/summary")
export class ShoppingmallSellerInventorySummaryController {
  /**
   * Retrieve a filtered and paginated inventory summary for the authenticated seller's product variants.
   *
   * This operation provides sellers with a comprehensive view of their inventory status across all product variants. The response includes calculated stock quantities derived from inventory records, enabling sellers to monitor stock levels, identify out-of-stock items, and plan restocking activities.
   *
   * Stock quantity is calculated in real-time by summing all inventory records for each variant, following the additive inventory tracking approach described in the shopping_mall_inventory_records schema. Each inventory record documents a quantity change (positive for restocks, negative for orders/adjustments) with a reason and timestamp. Current stock for any variant is calculated by summing all inventory records for that variant.
   *
   * This ensures accurate stock visibility and maintains complete audit trail integrity. The inventory record schema enforces immutability - records cannot be modified or deleted after creation, providing a reliable foundation for stock calculations.
   *
   * Supports filtering by product ID, stock status (in-stock vs out-of-stock), and search by SKU code or product name. Results can be sorted by creation date, stock quantity, or product name. Pagination allows efficient browsing of large inventories.
   *
   * Sellers use this endpoint to:
   * - Monitor overall inventory health
   * - Identify variants that need restocking
   * - Track stock levels across products
   * - Plan inventory management activities
   *
   * The operation respects seller data ownership - only variants belonging to the authenticated seller's products are visible.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for inventory summary
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query shopping_mall_product_variants belonging to the authenticated seller, joining with shopping_mall_products to verify ownership via shopping_mall_seller_id.
   *
   * Calculate current stock quantity by summing all shopping_mall_inventory_records for each variant (SUM of quantity_change where variant_id matches). This is done via a subquery or JOIN with aggregation.
   *
   * Apply search filters:
   * - productId: Filter variants by specific product ID (UUID)
   * - search: Search by SKU code (partial match) or product name (partial match)
   * - stockStatus: Filter by 'in_stock' (calculated_stock > 0) or 'out_of_stock' (calculated_stock <= 0)
   *
   * Sort options:
   * - 'created_at_asc' / 'created_at_desc': By variant creation date
   * - 'stock_asc' / 'stock_desc': By calculated stock quantity
   * - 'product_name_asc' / 'product_name_desc': By product name
   *
   * Return cursor-based pagination with variant summary including: variant ID, product ID, product name, SKU code, option values (parsed JSON), calculated stock quantity, stock status indicator.
   *
   * Access control: Only sellers can view their own inventory. Verify authenticated seller owns the products via shopping_mall_products.shopping_mall_seller_id.
   *
   * Business rules enforced:
   * - Include only non-deleted variants (deleted_at IS NULL)
   * - Include only variants from products belonging to the authenticated seller
   * - Stock calculation must never return negative values (minimum is 0)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IShoppingMallProductVariant.IRequest,
  ): Promise<IPageIShoppingMallProductVariant.ISummary> {
    try {
      return await patchShoppingMallSellerInventorySummary({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
