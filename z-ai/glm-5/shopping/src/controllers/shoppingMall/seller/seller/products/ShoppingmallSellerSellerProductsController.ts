import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallProduct } from "../../../../../api/structures/IShoppingMallProduct";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { postShoppingMallSellerSellerProducts } from "../../../../../providers/postShoppingMallSellerSellerProducts";

@Controller("/shoppingMall/seller/seller/products")
export class ShoppingmallSellerSellerProductsController {
  /**
   * Create a new product listing for sale on the platform.
   *
   * This operation allows approved sellers to create new product entries in their catalog. Each product represents a sellable item with a name, description, base price, and category assignment. The product is automatically associated with the authenticated seller account.
   *
   * Products must be assigned to exactly one category, which can be either a top-level category or a subcategory. When assigned to a subcategory, the product will appear in both the subcategory and parent category listings.
   *
   * The product creation does not include variants - sellers must add at least one variant using the POST /seller/products/{productId}/variants endpoint before the product becomes purchasable. Products without variants will display in search results but will be marked as unavailable and cannot be added to carts.
   *
   * Suspended sellers cannot create products. Attempting to create a product while suspended will result in an access denied error. Banned sellers cannot authenticate and thus cannot access this endpoint.
   *
   * Security: This endpoint requires seller authentication. The seller must have approval_status='approved' and must not be suspended or banned. The product is automatically associated with the authenticated seller - attempting to specify a different seller will result in an authorization error.
   *
   * @param connection
   * @param body Product creation data including name, description, category assignment, and base price
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Implementation steps:
   *
   * 1. Authenticate the seller via JWT token from the Authorization header
   * 2. Verify the seller's account status:
   *    - approval_status must be 'approved'
   *    - suspended must be false
   *    - banned must be false
   *    - If any check fails, return 403 Forbidden with appropriate error message
   * 3. Validate the categoryId exists in shopping_mall_categories and is not soft-deleted
   * 4. Create a new record in shopping_mall_products table:
   *    - id: generate new UUID
   *    - shopping_mall_seller_id: from authenticated seller's id
   *    - shopping_mall_category_id: from request body categoryId
   *    - name: from request body
   *    - description: from request body
   *    - base_price: from request body
   *    - created_at: current timestamp
   *    - updated_at: current timestamp
   *    - deleted_at: null
   * 5. Return the created product object
   *
   * Edge cases:
   * - If categoryId does not exist or is deleted, return 400 Bad Request
   * - If seller is suspended, return 403 Forbidden with message indicating account is suspended
   * - If seller's approval_status is not 'approved', return 403 Forbidden
   * - Name must be unique per seller (enforced by @@unique constraint), return 400 if duplicate
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IShoppingMallProduct.ICreate,
  ): Promise<IShoppingMallProduct> {
    try {
      return await postShoppingMallSellerSellerProducts({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
