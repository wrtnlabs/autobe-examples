import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallSeller } from "../../../../api/structures/IShoppingMallSeller";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { postShoppingMallSellerReapply } from "../../../../providers/postShoppingMallSellerReapply";

@Controller("/shoppingMall/seller/reapply")
export class ShoppingmallSellerController {
  /**
   * Allows a rejected seller to submit a new approval request by resetting their approval status to 'pending'.
   *
   * This endpoint is part of the seller approval workflow. When a seller's registration is rejected by an administrator, they can use this endpoint to reapply for approval. The system will reset their approval_status from 'rejected' to 'pending', making their application visible to administrators again for review.
   *
   * Optionally, the seller can update their shop profile information (shop name, description, logo) as part of the reapplication. This is recommended if the rejection reason indicates issues with the provided information.
   *
   * **Authorization Requirements:**
   * - Seller must be authenticated via JWT token
   * - Seller's current approval_status must be 'rejected'
   * - Sellers with 'pending', 'approved', or 'suspended' status cannot use this endpoint
   *
   * **Related Operations:**
   * - GET /api/auth/sellers/approval-status - View current approval status and rejection reason
   * - PUT /api/admin/seller-approvals/:id/approve - Admin approves seller
   * - PUT /api/admin/seller-approvals/:id/reject - Admin rejects seller
   *
   * @param connection
   * @param body Optional shop profile updates to include with the reapplication request
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Implementation steps for seller reapplication:
   *
   * 1. **Authentication & Authorization**:
   *    - Extract seller ID from JWT token
   *    - Query shopping_mall_sellers table by ID
   *    - Verify seller exists and is not deleted (deleted_at IS NULL)
   *    - Verify seller's approval_status equals 'rejected'
   *    - If status is not 'rejected', return 400 Bad Request with message indicating eligibility
   *
   * 2. **Update Processing**:
   *    - If request body contains shopName, update shop_name field
   *    - If request body contains shopDescription, update shop_description field
   *    - If request body contains logoUrl, update logo_url field
   *    - Clear rejection_reason field (set to NULL)
   *    - Set approval_status to 'pending'
   *    - Update updated_at to current timestamp
   *
   * 3. **Database Transaction**:
   *    - Execute UPDATE on shopping_mall_sellers table
   *    - All changes must be atomic within a single transaction
   *
   * 4. **Response**:
   *    - Return updated seller record (excluding password_hash)
   *    - Include all fields: id, email, shop_name, shop_description, logo_url, approval_status, created_at, updated_at
   *    - rejection_reason should be null in response
   *
   * 5. **Edge Cases**:
   *    - If seller is deleted (deleted_at IS NOT NULL), return 404 Not Found
   *    - If seller has 'approved' status, return 400 - suggest using profile update endpoint instead
   *    - If seller has 'suspended' status, return 403 Forbidden - must contact admin
   *    - If seller has 'pending' status, return 400 - already awaiting review
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async reapply(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IShoppingMallSeller.IReapply,
  ): Promise<IShoppingMallSeller> {
    try {
      return await postShoppingMallSellerReapply({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
