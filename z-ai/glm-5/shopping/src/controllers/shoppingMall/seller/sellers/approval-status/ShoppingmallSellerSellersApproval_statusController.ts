import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallSeller } from "../../../../../api/structures/IShoppingMallSeller";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { getShoppingMallSellerSellersApprovalStatus } from "../../../../../providers/getShoppingMallSellerSellersApprovalStatus";

@Controller("/shoppingMall/seller/sellers/approval-status")
export class ShoppingmallSellerSellersApproval_statusController {
  /**
   * Retrieve the approval status of the currently authenticated seller account.
   *
   * This endpoint allows sellers to check their registration approval status after signing up. New seller accounts start with approval_status='pending' and require administrator review before they can sell on the platform.
   *
   * **Approval Status Values**:
   * - 'pending': Registration is awaiting administrator review. Sellers cannot create products while pending.
   * - 'approved': Registration has been approved. Seller can create products and manage inventory.
   * - 'rejected': Registration has been rejected. Seller can view rejection_reason and submit a new registration request.
   *
   * **Response Details**:
   * - approval_status: Current approval status of the seller account (pending/approved/rejected)
   * - rejection_reason: Reason provided by administrator when rejecting registration. Only populated when approval_status is 'rejected'. Null for pending and approved statuses.
   *
   * **Authentication**: Requires seller authentication. Returns the approval status of the currently logged-in seller.
   *
   * **Related Operations**: If rejected, seller can use POST /sellers/resubmit to submit a new registration request. Administrators manage approvals via GET /admin/seller-approvals and PATCH /admin/seller-approvals/:id/approve or PATCH /admin/seller-approvals/:id/reject.
   *
   * @param connection
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Query the shopping_mall_sellers table to retrieve
     *   the approval_status and rejection_reason columns for the currently
     *   authenticated seller. The seller ID is obtained from the authenticated
     *   session context (JWT token claims). Return only these two fields in the
     *   response - do not expose other seller information. If the authenticated
     *   actor is not a seller, return 401 Unauthorized. The rejection_reason
     *   field may be null, which should be handled gracefully in the response.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async get(
    @SellerAuth()
    seller: SellerPayload,
  ): Promise<IShoppingMallSeller.IApprovalStatus> {
    try {
      return await getShoppingMallSellerSellersApprovalStatus({
        seller,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
