import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IShoppingMallCancellationRequest } from "../../../../../../api/structures/IShoppingMallCancellationRequest";
import { SellerAuth } from "../../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../../decorators/payload/SellerPayload";
import { putShoppingMallSellerSellersMeCancellationRequestsCancellationRequestId } from "../../../../../../providers/putShoppingMallSellerSellersMeCancellationRequestsCancellationRequestId";

@Controller(
  "/shoppingMall/seller/sellers/me/cancellation-requests/:cancellationRequestId",
)
export class ShoppingmallSellerSellersMeCancellation_requestsController {
  /**
   * Allows sellers to respond to customer cancellation requests for order items.
   *
   * Sellers can either approve or reject pending cancellation requests. When approving, the order item will be cancelled and the customer will receive a refund. When rejecting, the seller must provide a rejection reason explaining why the cancellation cannot be processed.
   *
   * This operation validates that:
   * - The cancellation request exists and is in 'pending' status
   * - The authenticated seller owns the order item (derived through order_item → seller relationship)
   * - If rejecting, a rejection_reason is provided
   *
   * Upon approval:
   * - The order item status changes to 'cancelled'
   * - Stock is restored via inventory history record
   * - Refund is processed for the customer
   * - A snapshot is created to record the state transition
   *
   * Upon rejection:
   * - The cancellation request status changes to 'rejected'
   * - The rejection_reason is recorded
   * - A snapshot is created for audit trail
   * - The customer can see the rejection reason
   *
   * Related to shopping_mall_cancellation_requests table which stores the cancellation request with status tracking, and shopping_mall_cancellation_request_snapshots which preserves complete audit trail of all state changes.
   *
   * @param connection
   * @param cancellationRequestId Unique identifier of the cancellation request to respond to. The seller must own the associated order item.
   * @param body Seller's response to the cancellation request including the decision (approve/reject), optional response message, and rejection reason if applicable
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Implementation steps for responding to a cancellation request:
   *
   * 1. AUTHORIZATION CHECK:
   *    - Validate the authenticated user is a seller
   *    - Query cancellation request by cancellationRequestId
   *    - Join with order_items to verify shopping_mall_seller_id matches authenticated seller
   *    - Return 404 if not found or 403 if not authorized
   *
   * 2. STATUS VALIDATION:
   *    - Verify cancellation request status is 'pending'
   *    - Return 400 if already approved or rejected
   *
   * 3. BUSINESS RULE VALIDATION:
   *    - If request body status is 'rejected', validate rejection_reason is provided
   *    - Return 400 with validation error if missing
   *
   * 4. UPDATE CANCELLATION REQUEST:
   *    - Update status to 'approved' or 'rejected'
   *    - Set seller_response if provided
   *    - Set rejection_reason if status is 'rejected'
   *    - Update updated_at timestamp
   *
   * 5. IF APPROVED:
   *    - Update order_item status to 'cancelled'
   *    - Create positive inventory history record to restore stock
   *    - Trigger refund process for the order item amount
   *    - Recalculate parent order status based on all item statuses
   *
   * 6. CREATE SNAPSHOT:
   *    - Create shopping_mall_cancellation_request_snapshots record
   *    - Capture previous_status ('pending'), new_status, reason, seller_response, rejection_reason
   *    - Set created_at timestamp
   *
   * 7. RETURN RESPONSE:
   *    - Return the updated cancellation request with all fields
   *
   * Transaction: Use database transaction to ensure atomicity of updates, snapshot creation, and stock restoration.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async respond(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("cancellationRequestId")
    cancellationRequestId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallCancellationRequest.IUpdate,
  ): Promise<IShoppingMallCancellationRequest> {
    try {
      return await putShoppingMallSellerSellersMeCancellationRequestsCancellationRequestId(
        {
          seller,
          cancellationRequestId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
