import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallOrderShipment } from "../../../../../../api/structures/IShoppingMallOrderShipment";
import { SellerAuth } from "../../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../../decorators/payload/SellerPayload";
import { postShoppingMallSellerSellersMeShipments } from "../../../../../../providers/postShoppingMallSellerSellersMeShipments";

@Controller("/shoppingMall/seller/sellers/me/shipments")
export class ShoppingmallSellerSellersMeShipmentsController {
  /**
   * Create a new shipment for seller's order items.
   *
   * This operation allows authenticated sellers to ship one or more order items from their products by creating a shipment record with carrier and tracking information. The seller selects which 'paid' order items to include in the shipment, enters the carrier name (e.g., FedEx, UPS, DHL) and the tracking number provided by the carrier.
   *
   * **Business Rules:**
   * - All selected order items must have 'paid' status (not already shipped, cancelled, or refunded)
   * - All selected order items must belong to the authenticated seller's products
   * - Multiple items can be bundled into a single shipment with one tracking number
   * - When shipment is created, all included items' status changes to 'shipped'
   *
   * **Security Requirements:**
   * - Requires seller authentication
   * - Seller must be approved (not pending or rejected)
   * - Seller can only ship items from their own products
   *
   * **Database Entities:**
   * - shopping_mall_order_shipments: Stores shipment record with carrier_name, tracking_number, shipped_at, seller_id
   * - shopping_mall_order_shipment_items: Junction table linking shipment to order items
   * - shopping_mall_order_items: Source items with status field updated to 'shipped'
   *
   * **Related Operations:**
   * - GET /sellers/me/order-items: Pre-execution to view items awaiting shipment
   * - POST /customers/me/shipments/{id}/confirm-delivery: Post-execution by customer to confirm delivery
   *
   * @param connection
   * @param body Shipment creation data including selected order item IDs, carrier name, and tracking number
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Implementation steps:
   *
   * 1. **Authentication & Authorization:**
   *    - Verify seller JWT token
   *    - Check seller is approved (status = 'approved')
   *
   * 2. **Input Validation:**
   *    - orderItemIds: Required, non-empty array of UUIDs
   *    - carrierName: Required, 2-100 characters
   *    - trackingNumber: Required, 5-100 characters
   *
   * 3. **Order Item Validation:**
   *    - Query shopping_mall_order_items for provided IDs
   *    - Verify ALL items exist
   *    - Verify ALL items have status = 'paid'
   *    - Verify ALL items belong to authenticated seller (shopping_mall_seller_id matches)
   *    - If any validation fails, return 400 with specific error message
   *
   * 4. **Shipment Creation (Transaction):**
   *    - Create record in shopping_mall_order_shipments:
   *      - shopping_mall_seller_id = authenticated seller's ID
   *      - carrier_name = input carrierName
   *      - tracking_number = input trackingNumber
   *      - shipped_at = current timestamp
   *      - delivered_at = null
   *      - delivery_confirmation_method = null
   *    - Create records in shopping_mall_order_shipment_items for each order item
   *    - Update all order items status to 'shipped'
   *
   * 5. **Response:**
   *    - Return created shipment with items included
   *    - Include shipment ID, carrier info, tracking number, shipped_at, and list of shipped items
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IShoppingMallOrderShipment.ICreate,
  ): Promise<IShoppingMallOrderShipment> {
    try {
      return await postShoppingMallSellerSellersMeShipments({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
