import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallAdmin } from "../../../../api/structures/IShoppingMallAdmin";
import { postShoppingMallAuthAdminJoin } from "../../../../providers/postShoppingMallAuthAdminJoin";
import { postShoppingMallAuthAdminLogin } from "../../../../providers/postShoppingMallAuthAdminLogin";
import { postShoppingMallAuthAdminRefresh } from "../../../../providers/postShoppingMallAuthAdminRefresh";

@Controller("/shoppingMall/auth/admin")
export class ShoppingmallAuthAdminController {
  /**
   * This endpoint registers a new administrator account for the e-commerce platform management system.
   *
   * Administrator accounts provide elevated permissions for platform oversight including seller approval, category management, product oversight, order management, and user moderation. New administrators are created with 'regular' grade by default - super administrator status must be granted by an existing super administrator through a separate promotion process.
   *
   * The registration process validates:
   * - Email uniqueness across all administrator accounts
   * - Password strength requirements for security
   * - Display name for identification in admin panels and audit logs
   *
   * Upon successful registration, the administrator receives a JWT access token (valid for 15-30 minutes) and a refresh token (valid for 7-30 days). The session is recorded in shopping_mall_admin_sessions with connection context for security auditing.
   *
   * Related operations: After joining, administrators can login (/auth/admin/login) to establish new sessions and refresh (/auth/admin/refresh) to renew tokens.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Administrator registration information including email, password, and display name.
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Implementation creates a new administrator account in the shopping_mall_admins table. The system hashes the password using bcrypt, generates a UUID for the admin ID, sets the grade to 'regular' by default (new admins start as regular, not super), and records creation/update timestamps. The system validates email uniqueness before creation. A refresh token is generated and stored in shopping_mall_admin_sessions with device context (IP, href, referrer) for audit purposes. The response includes both access and refresh tokens.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallAdmin.IJoin,
  ): Promise<IShoppingMallAdmin.IAuthorized> {
    try {
      return await postShoppingMallAuthAdminJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This endpoint authenticates an administrator and issues JWT tokens for platform management access.
   *
   * Administrators use this endpoint to establish authenticated sessions after initial registration. The authentication process validates credentials against the shopping_mall_admins table where passwords are stored as bcrypt hashes for security.
   *
   * Security measures implemented:
   * - Password comparison against bcrypt-hashed stored value
   * - Session recording with device context (IP address, URL accessed, HTTP referrer)
   * - Token generation with appropriate expiration (access: 15-30 min, refresh: 7-30 days)
   * - Failed attempt logging for security monitoring
   *
   * The response includes the administrator's grade ('regular' or 'super') which determines available permissions. Regular administrators can approve sellers, manage categories, oversee products/orders, and ban users. Super administrators have all regular capabilities plus the ability to promote/demote other administrators.
   *
   * Related operations: Use refresh (/auth/admin/refresh) to renew tokens without re-authentication. New administrators must first join (/auth/admin/join) before they can login.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Administrator login credentials including email and password.
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Implementation authenticates an administrator by verifying email and password against shopping_mall_admins table. The password is compared against the stored bcrypt hash. If authentication succeeds, the system creates a new session record in shopping_mall_admin_sessions capturing IP address, accessed URL (href), and referrer for security tracking. A JWT access token and refresh token are generated. The response includes tokens and admin profile with grade information. Failed login attempts should be logged for security monitoring.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallAdmin.ILogin,
  ): Promise<IShoppingMallAdmin.IAuthorized> {
    try {
      return await postShoppingMallAuthAdminLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This endpoint renews authentication tokens for an administrator session using a valid refresh token.
   *
   * JWT tokens have limited lifespans for security: access tokens expire in 15-30 minutes, refresh tokens in 7-30 days. When an access token expires, clients use this endpoint to obtain new tokens without requiring the administrator to re-enter credentials.
   *
   * The refresh process:
   * 1. Validates the refresh token signature and expiration
   * 2. Verifies the associated session has not expired in shopping_mall_admin_sessions
   * 3. Issues new access and refresh tokens
   * 4. Invalidates the old refresh token to prevent replay attacks
   * 5. Updates session timestamps for activity tracking
   *
   * This endpoint enables seamless user experience by maintaining authentication across extended sessions while preserving security through token rotation and expiration enforcement.
   *
   * Related operations: After initial authentication via login (/auth/admin/login), tokens can be refreshed periodically. If refresh token expires, the administrator must login again.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token issued during login or previous refresh operation.
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Implementation validates the provided refresh token and issues new access and refresh tokens. The system verifies the refresh token's validity and checks if the corresponding session in shopping_mall_admin_sessions has not expired. If valid, a new session may be created or the existing session extended. The old refresh token should be invalidated to prevent reuse. The admin's current profile information is retrieved from shopping_mall_admins to include in the response.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IShoppingMallAdmin.IRefresh,
  ): Promise<IShoppingMallAdmin.IAuthorized> {
    try {
      return await postShoppingMallAuthAdminRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
