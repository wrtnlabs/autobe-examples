import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallCategory } from "../../../../../api/structures/IShoppingMallCategory";
import { AdministratorAuth } from "../../../../../decorators/AdministratorAuth";
import { AdministratorPayload } from "../../../../../decorators/payload/AdministratorPayload";
import { putShoppingMallAdministratorAdminCategoriesCategoryId } from "../../../../../providers/putShoppingMallAdministratorAdminCategoriesCategoryId";

@Controller("/shoppingMall/administrator/admin/categories/:categoryId")
export class ShoppingmallAdministratorAdminCategoriesController {
  /**
   * Updates an existing category's name and description by an administrator.
   *
   * This operation allows administrators to modify category information while preserving the category's hierarchical structure. The category name must remain unique across all categories in the system. Only the name and description fields can be updated; the parent_id and hierarchical relationships cannot be changed through this operation.
   *
   * The category must exist and not be soft-deleted. Upon successful update, the updated_at timestamp is automatically refreshed. This operation does not affect products assigned to the category or any subcategories under it.
   *
   * Related operations:
   * - POST /admin/categories - Create a new category
   * - POST /admin/categories/{parentId}/subcategories - Create a subcategory
   * - DELETE /admin/categories/{categoryId} - Delete a category
   * - GET /categories - List all categories (public)
   *
   * @param connection
   * @param categoryId Unique identifier of the category to update (UUID format)
   * @param body Category update data containing name and optional description
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Implementation steps:
   *
   * 1. Authenticate administrator from JWT token
   * 2. Validate categoryId as UUID format
   * 3. Query shopping_mall_categories table for the category where id = categoryId AND deleted_at IS NULL
   * 4. Return 404 if category not found
   * 5. Validate request body:
   *    - name must be non-empty string
   *    - description is optional (can be null or empty)
   * 6. Check uniqueness: SELECT COUNT(*) FROM shopping_mall_categories WHERE name = requestBody.name AND id != categoryId AND deleted_at IS NULL
   * 7. Return 409 conflict if name already exists
   * 8. Update the category record:
   *    - SET name = requestBody.name
   *    - SET description = requestBody.description (allow null)
   *    - SET updated_at = NOW()
   * 9. Return the updated category entity
   *
   * Edge cases:
   * - Category is soft-deleted: return 404
   * - Name already exists: return 409 with error message
   * - Empty name string: return 400 validation error
   * - Partial update allowed (only name or only description provided)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("categoryId")
    categoryId: string,
    @TypedBody()
    body: IShoppingMallCategory.IUpdate,
  ): Promise<IShoppingMallCategory> {
    try {
      return await putShoppingMallAdministratorAdminCategoriesCategoryId({
        administrator,
        categoryId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
