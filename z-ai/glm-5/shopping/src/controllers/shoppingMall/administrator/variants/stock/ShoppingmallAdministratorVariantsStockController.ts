import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IShoppingMallProductVariantStock } from "../../../../../api/structures/IShoppingMallProductVariantStock";
import { AdministratorAuth } from "../../../../../decorators/AdministratorAuth";
import { AdministratorPayload } from "../../../../../decorators/payload/AdministratorPayload";
import { getShoppingMallAdministratorVariantsVariantIdStock } from "../../../../../providers/getShoppingMallAdministratorVariantsVariantIdStock";

@Controller("/shoppingMall/administrator/variants/:variantId/stock")
export class ShoppingmallAdministratorVariantsStockController {
  /**
   * Retrieve stock information for a specific product variant.
   *
   * This endpoint provides inventory status for a product variant, supporting both seller inventory management and customer purchase decisions. The current stock quantity is calculated in real-time by summing all inventory records for the variant, ensuring accurate and up-to-date stock information.
   *
   * Sellers use this endpoint to view the exact stock quantity for their variants, enabling them to make informed decisions about restocking and inventory management. Customers use this information to determine product availability before adding items to their cart.
   *
   * The stock calculation follows the additive inventory record approach where each record documents a quantity change (positive for restocks, negative for orders/adjustments). A variant is considered 'in_stock' when the calculated stock quantity is greater than zero, and 'out_of_stock' when it reaches zero. Out of stock variants cannot be added to shopping carts.
   *
   * @param connection
   * @param variantId Unique identifier of the product variant whose stock information is being retrieved
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification 1. Retrieve the product variant by its UUID identifier from shopping_mall_product_variants table
   * 2. If variant not found or is soft-deleted (deleted_at is not null), return 404 error
   * 3. Calculate current stock by summing all quantity_change values from shopping_mall_inventory_records where variant_id matches
   * 4. Determine availability status: 'in_stock' if calculated stock > 0, 'out_of_stock' if calculated stock == 0
   * 5. Return variant identification (id, skuCode, optionValues) along with stock quantity and availability
   * 6. Authorization note: Both sellers and customers can access; sellers see full stockQuantity, customers only see availability (implementation filters response based on actor type)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("variantId")
    variantId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallProductVariantStock> {
    try {
      return await getShoppingMallAdministratorVariantsVariantIdStock({
        administrator,
        variantId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
