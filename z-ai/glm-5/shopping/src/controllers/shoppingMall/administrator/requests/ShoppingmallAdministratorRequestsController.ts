import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallAdministratorSession } from "../../../../api/structures/IPageIShoppingMallAdministratorSession";
import { IShoppingMallAdministratorSession } from "../../../../api/structures/IShoppingMallAdministratorSession";
import { AdministratorAuth } from "../../../../decorators/AdministratorAuth";
import { AdministratorPayload } from "../../../../decorators/payload/AdministratorPayload";
import { getShoppingMallAdministratorRequestsRequestId } from "../../../../providers/getShoppingMallAdministratorRequestsRequestId";
import { patchShoppingMallAdministratorRequests } from "../../../../providers/patchShoppingMallAdministratorRequests";
import { patchShoppingMallAdministratorRequestsRequestIdReview } from "../../../../providers/patchShoppingMallAdministratorRequestsRequestIdReview";

@Controller("/shoppingMall/administrator/requests")
export class ShoppingmallAdministratorRequestsController {
  /**
   * Retrieve a filtered and paginated list of administrator role requests.
   *
   * This operation allows super administrators to view and manage all administrator role requests submitted by customers and sellers across the platform. Regular customers and sellers can use this endpoint to view their own submitted requests and check their current status.
   *
   * Super administrators have full visibility and can filter requests by status (pending, approved, rejected) to efficiently manage the approval workflow. The response includes comprehensive request information including the submitted reason, current status, timestamps, and reviewer details for processed requests.
   *
   * For regular users (customers and sellers), this endpoint provides visibility into their own request history, allowing them to track the progress of their administrator role application and view any rejection decisions with associated information.
   *
   * The returned data is paginated for efficient browsing of large request volumes, with results sorted by submission date in descending order.
   *
   * @param connection
   * @param body Search criteria including optional status filter and pagination parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Query shopping_mall_administrator_requests table with pagination and filtering.
   *
   * Authorization:
   * - Super administrators: Full access to all requests across the platform
   * - Regular administrators: No access (per business rules)
   * - Customers/Sellers: Access to their own submitted requests only
   *
   * Implementation:
   * 1. Authenticate the requesting user
   * 2. Determine access scope based on user role:
   *    - If super administrator: Apply status filter if provided, return all matching requests
   *    - If customer or seller: Filter to show only their own requests, ignore other filters
   *    - If regular administrator: Deny access
   * 3. Apply pagination using cursor-based approach
   * 4. Join with administrator table for reviewedBy information when available
   * 5. Join with customer/seller tables to show requester information
   * 6. Return paginated list with summary information
   *
   * Filtering:
   * - Filter by status (pending, approved, rejected) - optional
   * - When no filter provided, return all statuses
   *
   * Sorting:
   * - Default sort: created_at descending (newest first)
   *
   * Response includes:
   * - Request ID, reason, status
   * - Creation timestamp
   * - Review timestamp and reviewer info (if reviewed)
   * - Requester information (email, type: customer/seller)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedBody()
    body: IShoppingMallAdministratorSession.IRequest,
  ): Promise<IPageIShoppingMallAdministratorSession.ISummary> {
    try {
      return await patchShoppingMallAdministratorRequests({
        administrator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific administrator request.
   *
   * This endpoint allows super administrators to view complete details of an administrator request, including the requester's identity, the reason for requesting administrator status, current request status, and review information if applicable.
   *
   * The endpoint is restricted to super administrators only. Regular administrators and non-authenticated users cannot access this endpoint. When a super administrator views a request, they can see:
   *
   * - Requester's email and current role (customer or seller)
   * - The reason text provided by the requester
   * - Current status (pending, approved, or rejected)
   * - Creation timestamp
   * - Review timestamp and reviewer information (if reviewed)
   * - Rejection reason (if rejected)
   *
   * This information helps super administrators make informed decisions when approving or rejecting administrator requests.
   *
   * @param connection
   * @param requestId Unique identifier of the administrator request to retrieve (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Retrieve a specific administrator request by ID for super administrator review.
   *
   * 1. Authentication: Validate the requester is an authenticated super administrator
   * 2. Authorization: Reject if the administrator is not a super administrator
   * 3. Fetch the administrator request record by requestId from the database
   * 4. If not found, return 404 Not Found
   * 5. Include requester information: retrieve the associated customer or seller account
   * 6. Include reviewer information if reviewed: retrieve the administrator who reviewed
   * 7. Return the complete request details with all timestamps and status
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":requestId")
  public async at(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("requestId")
    requestId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallAdministratorSession> {
    try {
      return await getShoppingMallAdministratorRequestsRequestId({
        administrator,
        requestId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Allows super administrators to review and respond to pending administrator requests submitted by customers or sellers.
   *
   * This operation is restricted to super administrators only. Regular administrators cannot review administrator requests. The super administrator can either approve or reject a pending request.
   *
   * When a request is approved, the requester's account is granted administrator privileges with 'regular' grade, allowing them to perform standard administrative functions such as seller approval, category management, and user moderation.
   *
   * When a request is rejected, the requester remains in their current role (customer or seller) but may submit a new administrator request in the future. The rejection does not require the super administrator to provide additional justification beyond their decision.
   *
   * The operation records the reviewing super administrator's identity and the timestamp of the review for audit purposes. Once reviewed, a request cannot be modified or re-reviewed. The request status transitions from 'pending' to either 'approved' or 'rejected' as a final state.
   *
   * Self-review is explicitly prevented - a super administrator cannot review their own administrator request.
   *
   * @param connection
   * @param requestId Unique identifier of the administrator request to review
   * @param body Review decision containing approval or rejection status
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Implementation steps for reviewing an administrator request:
   *
   * 1. **Authentication & Authorization**: Verify the requester is authenticated as an administrator with grade 'super'. Regular administrators and non-administrators must be rejected.
   *
   * 2. **Request Validation**:
   *    - Fetch the administrator request by requestId
   *    - Verify the request exists and has status 'pending'
   *    - Verify the super administrator is not reviewing their own request (self-review prevention)
   *
   * 3. **Status Update Process**:
   *    - If decision is 'approved':
   *      - Update request status to 'approved'
   *      - Set reviewedAt to current timestamp
   *      - Set reviewedBy to the super administrator's ID
   *      - Create a new administrator account for the requester with grade 'regular'
   *      - The requester (customer or seller) gains administrator privileges
   *    - If decision is 'rejected':
   *      - Update request status to 'rejected'
   *      - Set reviewedAt to current timestamp
   *      - Set reviewedBy to the super administrator's ID
   *      - The requester can submit a new administrator request later
   *
   * 4. **Transaction**: All updates must be atomic within a single transaction to ensure data consistency.
   *
   * 5. **Response**: Return the updated administrator request with reviewer details populated.
   *
   * Edge cases:
   * - Request not found: Return 404 error
   * - Request already reviewed: Return 400 error (cannot re-review)
   * - Self-review attempt: Return 400 error
   * - Non-super admin attempt: Return 403 error
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch(":requestId/review")
  public async review(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("requestId")
    requestId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallAdministratorSession.IReview,
  ): Promise<IShoppingMallAdministratorSession> {
    try {
      return await patchShoppingMallAdministratorRequestsRequestIdReview({
        administrator,
        requestId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
