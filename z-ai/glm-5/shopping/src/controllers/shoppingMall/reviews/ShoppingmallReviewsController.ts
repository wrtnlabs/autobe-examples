import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IShoppingMallReview } from "../../../api/structures/IShoppingMallReview";
import { getShoppingMallReviewsReviewId } from "../../../providers/getShoppingMallReviewsReviewId";

@Controller("/shoppingMall/reviews/:reviewId")
export class ShoppingmallReviewsController {
  /**
   * Retrieve detailed information about a specific product review.
   *
   * This endpoint returns a single review identified by its unique reviewId. Reviews contain a star rating from 1 to 5 and optional text content submitted by customers who have purchased and received the product. Each review is associated with a verified purchase through the customer-product-order relationship.
   *
   * The response includes the review's rating value, text content (if provided), and timestamps. Additionally, contextual information is provided including the customer's display name and the product being reviewed, enabling proper display on product detail pages or review listings.
   *
   * Reviews that have been soft-deleted by customers are not accessible through this endpoint. If a review has been deleted, the operation returns a 404 response, maintaining the public visibility rule that only active, non-deleted reviews are displayed.
   *
   * @param connection
   * @param reviewId Unique identifier of the review to retrieve (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Retrieve a single review record from shopping_mall_reviews table by the provided reviewId UUID. Join with shopping_mall_customers to include the reviewer's display name. Join with shopping_mall_products to include the product name and reference. Filter out soft-deleted reviews (where deleted_at IS NOT NULL) to ensure only publicly visible reviews are returned. Return 404 if the review is not found or has been soft-deleted. The response includes the review's rating, content, timestamps, and contextual information about the customer and product.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallReview> {
    try {
      return await getShoppingMallReviewsReviewId({
        reviewId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
