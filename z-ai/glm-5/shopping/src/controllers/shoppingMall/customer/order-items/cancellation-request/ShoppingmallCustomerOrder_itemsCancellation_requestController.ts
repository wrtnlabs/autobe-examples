import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IShoppingMallCancellationRequest } from "../../../../../api/structures/IShoppingMallCancellationRequest";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { getShoppingMallCustomerOrderItemsOrderItemIdCancellationRequest } from "../../../../../providers/getShoppingMallCustomerOrderItemsOrderItemIdCancellationRequest";
import { postShoppingMallCustomerOrderItemsOrderItemIdCancellationRequest } from "../../../../../providers/postShoppingMallCustomerOrderItemsOrderItemIdCancellationRequest";

@Controller(
  "/shoppingMall/customer/order-items/:orderItemId/cancellation-request",
)
export class ShoppingmallCustomerOrder_itemsCancellation_requestController {
  /**
   * Retrieve the cancellation request for a specific order item with complete audit trail.
   *
   * This endpoint returns the cancellation request details including the customer's reason, current status, seller response, rejection reason (if applicable), and all associated snapshots that capture the complete lifecycle of the request.
   *
   * The cancellation request is only accessible by the customer who owns the order item. The response includes all snapshots created during the request's lifecycle, providing complete transparency for dispute resolution purposes as required by the snapshot principle.
   *
   * Key business rules:
   * - Only the customer who owns the order item can view its cancellation request
   * - The order item must have an associated cancellation request
   * - All snapshots are included for complete audit trail visibility
   * - The status field indicates: 'pending' (awaiting seller review), 'approved' (seller accepted), or 'rejected' (seller declined)
   *
   * Related operations:
   * - POST /order-items/{orderItemId}/cancellation-request to create a new cancellation request
   * - PUT /sellers/me/cancellations/{id}/approve for seller approval
   * - PUT /sellers/me/cancellations/{id}/reject for seller rejection
   *
   * @param connection
   * @param orderItemId Unique identifier of the order item to retrieve cancellation request for
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Implementation steps:
   *
   * 1. Authenticate the customer using JWT token from Authorization header
   * 2. Validate orderItemId is a valid UUID format
   * 3. Query shopping_mall_cancellation_requests table where order_item_id = orderItemId
   * 4. Join with shopping_mall_order_items to verify customer ownership:
   *    - Find order_item where id = orderItemId
   *    - Verify order_item.shopping_mall_order_id references an order belonging to the authenticated customer
   *    - Return 404 if order item not found or not owned by customer
   * 5. If no cancellation request exists for this order item, return 404
   * 6. Query shopping_mall_cancellation_request_snapshots where shopping_mall_cancellation_request_id matches the request ID
   * 7. Order snapshots by created_at ascending to show chronological progression
   * 8. Build response object with cancellation request fields and snapshots array
   * 9. Return 200 with complete cancellation request data
   *
   * Edge cases:
   * - Order item has no cancellation request: return 404
   * - Customer tries to view another customer's cancellation request: return 404 (don't reveal existence)
   * - Invalid UUID format: return 400 validation error
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderItemId")
    orderItemId: string,
  ): Promise<IShoppingMallCancellationRequest> {
    try {
      return await getShoppingMallCustomerOrderItemsOrderItemIdCancellationRequest(
        {
          customer,
          orderItemId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Create a new cancellation request for an order item that has not yet been shipped.
   *
   * This endpoint allows authenticated customers to request cancellation of specific order items with 'paid' status. Cancellation is only available before the item is shipped; once an item has status 'shipped' or 'delivered', customers must use the refund process instead.
   *
   * **Validation Requirements:**
   * - The order item must exist in the system
   * - The order item must belong to the authenticated customer (verified via shopping_mall_orders.shopping_mall_customer_id)
   * - The order item must have status 'paid' (items with 'shipped', 'delivered', 'cancelled', or 'refunded' status are not eligible)
   * - No existing cancellation request may exist for this order item (unique constraint on order_item_id)
   *
   * **Request Body:**
   * The customer must provide a reason for the cancellation request. This reason will be visible to the seller when reviewing the request and will be preserved in the cancellation request snapshots for audit purposes.
   *
   * **Post-Creation Behavior:**
   * - The cancellation request is created with status 'pending'
   * - The seller who owns the order item is notified of the pending request
   * - The customer receives confirmation of the request submission
   * - The order item status remains 'paid' until the seller approves or rejects the request
   *
   * **Related Operations:**
   * - Sellers can approve cancellation requests via PUT /sellers/me/cancellations/{id}/approve
   * - Sellers can reject cancellation requests via PUT /sellers/me/cancellations/{id}/reject
   * - Approved cancellations trigger automatic refund processing and stock restoration
   *
   * @param connection
   * @param orderItemId Unique identifier of the order item for which cancellation is requested. Must be a valid UUID referencing an existing order item in shopping_mall_order_items table that belongs to the authenticated customer and has 'paid' status.
   * @param body Cancellation request details containing the customer's reason for wanting to cancel this order item
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Implementation requires the following steps:
   *
   * 1. **Authentication Verification**: Extract customer ID from JWT token in Authorization header.
   *
   * 2. **Order Item Validation**:
   *    - Query shopping_mall_order_items by orderItemId
   *    - Return 404 if order item not found
   *    - Join with shopping_mall_orders to verify customer ownership (shopping_mall_customer_id matches authenticated customer)
   *    - Return 403 if customer does not own this order item
   *    - Check order item status equals 'paid'
   *    - Return 400 BAD_REQUEST with message 'Cancellation only available for items with paid status' if status is 'shipped', 'delivered', 'cancelled', or 'refunded'
   *
   * 3. **Duplicate Request Check**:
   *    - Query shopping_mall_cancellation_requests by order_item_id
   *    - Return 409 CONFLICT if a cancellation request already exists for this order item
   *
   * 4. **Create Cancellation Request**:
   *    - Insert new record into shopping_mall_cancellation_requests with:
   *      - id: generated UUID
   *      - order_item_id: from path parameter
   *      - customer_id: from authenticated user
   *      - reason: from request body
   *      - status: 'pending'
   *      - seller_response: null
   *      - rejection_reason: null
   *      - created_at, updated_at: current timestamp
   *
   * 5. **Post-Creation Actions**:
   *    - Retrieve seller information via order item's shopping_mall_seller_id
   *    - Trigger notification to seller about pending cancellation request (async)
   *
   * 6. **Response**: Return the created cancellation request with 201 CREATED status
   *
   * **Transaction Scope**: All database operations should be wrapped in a transaction to ensure atomicity.
   *
   * **Error Responses**:
   * - 401 UNAUTHORIZED: Missing or invalid JWT token
   * - 403 FORBIDDEN: Customer does not own this order item
   * - 404 NOT FOUND: Order item does not exist
   * - 409 CONFLICT: Cancellation request already exists for this item
   * - 400 BAD REQUEST: Order item not eligible for cancellation (wrong status)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderItemId")
    orderItemId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallCancellationRequest.ICreate,
  ): Promise<IShoppingMallCancellationRequest> {
    try {
      return await postShoppingMallCustomerOrderItemsOrderItemIdCancellationRequest(
        {
          customer,
          orderItemId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
