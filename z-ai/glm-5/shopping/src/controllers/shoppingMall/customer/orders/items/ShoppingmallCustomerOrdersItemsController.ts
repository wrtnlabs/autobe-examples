import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallOrderItem } from "../../../../../api/structures/IPageIShoppingMallOrderItem";
import { IShoppingMallOrderItem } from "../../../../../api/structures/IShoppingMallOrderItem";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { getShoppingMallCustomerOrdersOrderIdItemsOrderItemId } from "../../../../../providers/getShoppingMallCustomerOrdersOrderIdItemsOrderItemId";
import { patchShoppingMallCustomerOrdersOrderIdItems } from "../../../../../providers/patchShoppingMallCustomerOrdersOrderIdItems";

@Controller("/shoppingMall/customer/orders/:orderId/items")
export class ShoppingmallCustomerOrdersItemsController {
  /**
   * Retrieve a filtered and paginated list of order items within a specific order.
   *
   * This operation provides comprehensive order item retrieval capabilities for customers viewing their order details, sellers managing items they need to fulfill, and administrators overseeing platform transactions. Each order item contains complete snapshot data captured at the time of purchase, including product information, variant details, and seller profile.
   *
   * The order items within an order can originate from multiple sellers in a multi-seller marketplace scenario. Sellers can use this endpoint to filter and view only their own items within a customer's order. Each item maintains an independent status lifecycle (paid → shipped → delivered, or paid → cancelled, or delivered → refunded).
   *
   * Supports filtering by item status values ('paid', 'shipped', 'delivered', 'cancelled', 'refunded') and by seller ID for multi-seller order scenarios. Results are paginated with configurable page sizes and sorted by creation date by default.
   *
   * Authentication is required. Authorization enforces that only the order's owning customer, sellers with items in the order, or administrators can access this endpoint.
   *
   * @param connection
   * @param orderId Unique identifier of the order to retrieve items from. Must be a valid UUID referencing an existing order in the shopping_mall_orders table.
   * @param body Search criteria for filtering order items including status and seller filters with pagination parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Implementation requirements:
   *
   * 1. AUTHORIZATION:
   *    - Extract authenticated user from JWT token
   *    - Verify user is either:
   *      a) The customer who owns the order (shopping_mall_orders.shopping_mall_customer_id)
   *      b) A seller with items in this order (check shopping_mall_order_items.shopping_mall_seller_id)
   *      c) An administrator (check admin role)
   *    - Return 403 Forbidden if authorization fails
   *
   * 2. QUERY EXECUTION:
   *    - Start from shopping_mall_order_items table
   *    - Filter by shopping_mall_order_id = :orderId (path parameter)
   *    - Apply optional status filter from request body
   *    - Apply optional seller filter from request body
   *    - Count total matching items for pagination metadata
   *    - Apply pagination (page, limit from request body)
   *    - Sort by created_at descending (newest first)
   *
   * 3. RESPONSE CONSTRUCTION:
   *    - For each order item, include:
   *      - id, status, quantity, unit_price
   *      - product_name, product_thumbnail_url
   *      - variant_sku_code, variant_price
   *      - seller_shop_name
   *      - variant options from shopping_mall_order_item_variant_options
   *    - Include pagination metadata (total count, current page, total pages)
   *
   * 4. RELATED DATA:
   *    - Fetch variant options for each item from shopping_mall_order_item_variant_options
   *    - Group options by key-value pairs for display
   *
   * 5. ERROR HANDLING:
   *    - Return 404 if order does not exist
   *    - Return 400 for invalid status values in filter
   *    - Return 401 if not authenticated
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderId")
    orderId: string,
    @TypedBody()
    body: IShoppingMallOrderItem.IRequest,
  ): Promise<IPageIShoppingMallOrderItem.ISummary> {
    try {
      return await patchShoppingMallCustomerOrdersOrderIdItems({
        customer,
        orderId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific order item within an order.
   *
   * This endpoint provides comprehensive order item details including product snapshot data captured at purchase time, variant information with options, quantity and pricing, current status, and seller information. The snapshot principle ensures that all product, variant, and seller data is preserved exactly as it was when the order was placed, regardless of subsequent modifications or deletions of the source entities.
   *
   * The order item status determines what actions can be performed:
   * - 'paid': Can request cancellation
   * - 'shipped': Awaiting delivery
   * - 'delivered': Can request refund (within 7 days) or write review
   * - 'cancelled': Item was cancelled and refunded
   * - 'refunded': Item was refunded after delivery
   *
   * The response includes variant options as key-value pairs (e.g., color: 'Red', size: 'Large') stored in the order_item_variant_options table. Product and variant references may be null if the original entities have been deleted, but snapshot data is always preserved for order history integrity.
   *
   * Related operations:
   * - GET /orders/{orderId} - View full order with all items
   * - POST /customers/me/order-items/{id}/cancellation - Request cancellation for paid items
   * - POST /customers/me/order-items/{id}/refund - Request refund for delivered items
   *
   * @param connection
   * @param orderId Unique identifier of the order containing the target item (UUID format)
   * @param orderItemId Unique identifier of the specific order item to retrieve (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query shopping_mall_order_items table by id with shopping_mall_order_id validation to ensure the item belongs to the specified order.
   *
   * 1. Verify the order item exists and belongs to the specified order
   * 2. Load variant options from shopping_mall_order_item_variant_options table (key-value pairs)
   * 3. Include all snapshot fields: product_name, product_description, product_category_name, product_base_price, product_thumbnail_url, variant_sku_code, variant_price
   * 4. Include seller snapshot: seller_shop_name, seller_shop_description, seller_logo_url
   * 5. Include quantity, unit_price, and status
   * 6. Product and variant FK references may be null if deleted - snapshot data is authoritative
   *
   * Authorization: Customer who owns the order, or the seller who sold the item, or administrator can access.
   *
   * Error cases:
   * - 404 if order not found
   * - 404 if order item not found or doesn't belong to the order
   * - 403 if user lacks permission to view this item
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":orderItemId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedParam("orderItemId")
    orderItemId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallOrderItem> {
    try {
      return await getShoppingMallCustomerOrdersOrderIdItemsOrderItemId({
        customer,
        orderId,
        orderItemId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
