import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallOrderItemSnapshot } from "../../../../../../api/structures/IShoppingMallOrderItemSnapshot";
import { CustomerAuth } from "../../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../../decorators/payload/CustomerPayload";
import { getShoppingMallCustomerOrdersOrderIdItemsItemIdSnapshot } from "../../../../../../providers/getShoppingMallCustomerOrdersOrderIdItemsItemIdSnapshot";

@Controller("/shoppingMall/customer/orders/:orderId/items/:itemId/snapshot")
export class ShoppingmallCustomerOrdersItemsSnapshotController {
  /**
   * Retrieve the immutable purchase-time snapshot for a specific order item.
   *
   * This endpoint provides access to the historical record that preserves the complete product state at the moment of purchase. The snapshot captures the product name, product description, exact price paid, seller shop name, seller logo image, and variant options exactly as they existed when the customer placed their order.
   *
   * **Authorization**: Access is granted to:
   * - The customer who owns the order (verified through order ownership)
   * - The seller whose product was purchased (verified through order item seller reference)
   * - Any administrator for platform oversight purposes
   *
   * **Immutability**: Snapshots are permanent historical records that cannot be modified or deleted. They serve as authoritative evidence for dispute resolution and maintain historical accuracy regardless of subsequent changes to products, variants, or seller profiles.
   *
   * **Use Cases**:
   * - Customers reviewing what they purchased for verification
   * - Sellers confirming product details at time of sale
   * - Administrators investigating disputes or order issues
   * - Historical reference when original product has been deleted
   *
   * The snapshot remains accessible even if the original product, variant, or seller account has been deleted or modified.
   *
   * @param connection
   * @param orderId Unique identifier of the order containing the item (UUID format)
   * @param itemId Unique identifier of the order item whose snapshot is being retrieved (UUID format)
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification Query the shopping_mall_order_item_snapshots
     *   table by order_item_id to retrieve the snapshot.
   *
   * **Authorization Steps**:
   * 1. Load the order item using itemId to verify it belongs to the specified orderId
   * 2. Check if the authenticated user is:
   *    - Customer: Match shopping_mall_orders.shopping_mall_customer_id with authenticated customer ID
   *    - Seller: Match shopping_mall_order_items.shopping_mall_seller_id with authenticated seller ID
   *    - Administrator: Allow access (check session for admin role)
   * 3. Return 403 Forbidden if authorization fails
   * 4. Return 404 Not Found if order item or snapshot doesn't exist
   *
   * **Query**:
   * - SELECT from shopping_mall_order_item_snapshots WHERE order_item_id = {itemId}
   * - JOIN shopping_mall_order_item_snapshot_variant_options to include variant options array
   * - Include all fields: id, product_name, product_description, price, seller_shop_name, seller_logo_image, created_at, and nested variantOptions with option_key and option_value
   *
   * **Response Construction**:
   * - Map database fields to IShoppingMallOrderItemSnapshot type
   * - Include variantOptions as nested array with option_key and option_value pairs
   *
   * **Error Handling**:
   * - 404: Order item not found or snapshot not found
   * - 403: User not authorized to view this snapshot
   * - 400: Order item doesn't belong to specified order
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderId")
    orderId: string,
    @TypedParam("itemId")
    itemId: string,
  ): Promise<IShoppingMallOrderItemSnapshot> {
    try {
      return await getShoppingMallCustomerOrdersOrderIdItemsItemIdSnapshot({
        customer,
        orderId,
        itemId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
