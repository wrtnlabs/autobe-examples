import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallRefundRequest } from "../../../../../../api/structures/IShoppingMallRefundRequest";
import { CustomerAuth } from "../../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../../decorators/payload/CustomerPayload";
import { postShoppingMallCustomerOrdersOrderIdItemsOrderItemIdRefund } from "../../../../../../providers/postShoppingMallCustomerOrdersOrderIdItemsOrderItemIdRefund";

@Controller("/shoppingMall/customer/orders/:orderId/items/:orderItemId/refund")
export class ShoppingmallCustomerOrdersItemsRefundController {
  /**
   * Submit a refund request for a delivered order item.
   *
   * This operation allows customers to request a refund for order items that have been delivered. The request captures the customer's reason for the refund and initiates the seller approval workflow. Upon successful creation, the refund request enters 'pending' status awaiting seller review.
   *
   * Eligibility Requirements:
   * - The order item must have 'delivered' status
   * - The refund request must be submitted within 7 days of delivery confirmation
   * - No existing pending refund request for the same order item
   * - The requesting customer must be the owner of the order item
   *
   * The 7-day refund window is calculated from:
   * - The customer's manual delivery confirmation timestamp, OR
   * - The automatic delivery confirmation timestamp (14 days after shipping if not manually confirmed)
   *
   * Upon seller approval, the order item status changes to 'refunded', stock is restored via positive inventory record, and the refund payment is processed. All state changes are captured in refund request snapshots for audit trail and dispute resolution purposes as required by the snapshot principle.
   *
   * This operation notifies the seller who owns the order item about the pending refund request.
   *
   * @param connection
   * @param orderId Unique identifier of the order containing the item to refund. Must be a valid UUID belonging to the authenticated customer.
   * @param orderItemId Unique identifier of the delivered order item for which the refund is requested. Must have 'delivered' status and be within the 7-day refund window.
   * @param body Refund request details including the customer's explanation for requesting the refund
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Implementation steps for refund request creation:
   *
   * 1. **Authentication & Authorization**:
   *    - Validate JWT token and extract customer ID
   *    - Verify the customer owns the order (via shopping_mall_orders.shopping_mall_customer_id)
   *    - Verify the order item belongs to the specified order
   *
   * 2. **Eligibility Validation**:
   *    - Query shopping_mall_order_items to get the item status and check it equals 'delivered'
   *    - Query shopping_mall_order_shipments joined with shopping_mall_order_shipment_audit_logs to find delivery confirmation timestamp
   *    - Calculate if current timestamp is within 7 days of delivery confirmation
   *    - Query to verify no existing refund request with 'pending' status exists for this order item
   *
   * 3. **Refund Request Creation**:
   *    - Create record in shopping_mall_refund_requests table with:
   *      - order_item_id: from path parameter
   *      - customer_id: from authenticated user
   *      - reason: from request body
   *      - status: 'pending'
   *      - created_at, updated_at: current timestamp
   *    - Create initial snapshot in shopping_mall_refund_request_snapshots capturing the submission state
   *
   * 4. **Notification**:
   *    - Trigger notification to the seller who owns the order item (via shopping_mall_order_items.shopping_mall_seller_id)
   *
   * 5. **Response**:
   *    - Return the created refund request entity with all fields
   *
   * Error handling:
   * - 401 Unauthorized if not authenticated
   * - 403 Forbidden if customer doesn't own the order
   * - 404 Not Found if order or order item doesn't exist
   * - 400 Bad Request if item status is not 'delivered'
   * - 400 Bad Request if outside 7-day refund window
   * - 409 Conflict if pending refund request already exists
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderId")
    orderId: string,
    @TypedParam("orderItemId")
    orderItemId: string,
    @TypedBody()
    body: IShoppingMallRefundRequest.ICreate,
  ): Promise<IShoppingMallRefundRequest> {
    try {
      return await postShoppingMallCustomerOrdersOrderIdItemsOrderItemIdRefund({
        customer,
        orderId,
        orderItemId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
