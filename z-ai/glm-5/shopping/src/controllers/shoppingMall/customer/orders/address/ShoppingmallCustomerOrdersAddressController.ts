import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallOrderAddress } from "../../../../../api/structures/IShoppingMallOrderAddress";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { getShoppingMallCustomerOrdersOrderIdAddress } from "../../../../../providers/getShoppingMallCustomerOrdersOrderIdAddress";

@Controller("/shoppingMall/customer/orders/:orderId/address")
export class ShoppingmallCustomerOrdersAddressController {
  /**
   * Retrieve the shipping address snapshot for a specific order.
   *
   * This endpoint returns the immutable shipping address that was captured at the time of order placement. The address snapshot preserves the complete delivery information exactly as the customer provided, ensuring historical accuracy even if the customer modifies or deletes addresses from their address book.
   *
   * The shipping address contains the recipient's full name, contact phone number, and complete delivery location including street address, city, state/province, postal code, and country. This information is used for order fulfillment and delivery tracking.
   *
   * Security considerations: This operation requires customer authentication. Customers can only access addresses for their own orders. The orderId parameter must reference an order belonging to the authenticated customer.
   *
   * The address data is retrieved from the shopping_mall_order_addresses table which maintains a one-to-one relationship with shopping_mall_orders. Address records are append-only and never modified after creation to maintain data integrity for dispute resolution and legal compliance.
   *
   * @param connection
   * @param orderId Unique identifier of the order to retrieve the shipping address for
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query shopping_mall_order_addresses table by shopping_mall_order_id to retrieve the address snapshot. Validate that the order (referenced by orderId) belongs to the authenticated customer before returning address data. Join with shopping_mall_orders to verify ownership via shopping_mall_customer_id matching the current user's customer ID. Return all address fields: recipient_name, phone, street, city, state, postal_code, country, and created_at timestamp. If no address found for the order, return null or appropriate error. Handle case where order does not exist with 404 response. Handle unauthorized access with 403 response.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderId")
    orderId: string,
  ): Promise<IShoppingMallOrderAddress> {
    try {
      return await getShoppingMallCustomerOrdersOrderIdAddress({
        customer,
        orderId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
