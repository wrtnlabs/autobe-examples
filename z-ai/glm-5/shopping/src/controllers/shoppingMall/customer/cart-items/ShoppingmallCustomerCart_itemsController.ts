  /**
   * Update a shopping cart item's quantity for the authenticated customer.
   *
   * This operation allows customers to modify the quantity of a specific item in their shopping cart. The cart item must belong to the authenticated customer, and the quantity must be between 1 and 99 units.
   *
   * **Ownership Validation:**
   * Only the customer who owns the cart item can update it. Attempting to update another customer's cart item will result in a 404 Not Found response.
   *
   * **Quantity Rules:**
   * - Minimum quantity: 1 (use DELETE endpoint to remove items)
   * - Maximum quantity: 99 per cart item
   * - If the requested quantity exceeds available stock, the update is allowed but the item will be flagged with a low stock warning during cart viewing
   *
   * **Database Reference:**
   * Updates the `shopping_mall_cart_items` table, modifying the `quantity` and `updated_at` fields. The `unit_price` and `shopping_product_variant_id` remain unchanged.
   *
   * **Related Operations:**
   * - POST /cart-items - Add item to cart
   * - GET /cart-items - View all cart items
   * - DELETE /cart-items/{cartItemId} - Remove item from cart
   *
   * @param connection
   * @param cartItemId Unique identifier of the cart item to update (UUID format). The cart item must belong to the authenticated customer.
   * @param body Cart item update data containing the new quantity. Quantity must be between 1 and 99.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Update a cart item's quantity with the following implementation:
   *
   * 1. **Authentication Check:** Verify the customer is authenticated via JWT token
   * 2. **Cart Item Lookup:** Query shopping_mall_cart_items by id (UUID)
   * 3. **Ownership Validation:** Ensure shopping_customer_id matches the authenticated customer's ID
   * 4. **Quantity Validation:**
   *    - Minimum: 1 (reject with 400 if less)
   *    - Maximum: 99 (reject with 400 if greater)
   *    - Type: positive integer
   * 5. **Database Update:**
   *    - Update quantity field
   *    - Update updated_at to current timestamp
   *    - Keep shopping_product_variant_id and unit_price unchanged
   * 6. **Response:** Return the updated cart item object
   *
   * **Error Handling:**
   * - 401 Unauthorized: Missing or invalid authentication token
   * - 404 Not Found: Cart item does not exist or does not belong to the customer
   * - 400 Bad Request: Invalid quantity (less than 1 or greater than 99)
   *
   * **Transaction:** Use a database transaction to ensure atomic update.
   *
   * **Note:** Stock validation is NOT performed at update time. Stock warnings are displayed during cart viewing, not during quantity updates.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
