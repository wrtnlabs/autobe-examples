  /**
   * Add a product variant to the authenticated customer's shopping cart.
   *
   * This operation allows authenticated customers to add a specific product variant (SKU) to their shopping cart with a specified quantity. The system stores the unit price at the time of addition to enable price change detection during checkout.
   *
   * When a customer adds the same variant that already exists in their cart, the quantities are automatically combined into a single cart item. The system enforces business constraints: maximum 99 units per cart item and maximum 50 distinct variants per customer cart.
   *
   * The cart item references the shopping_mall_cart_items table, which links to shopping_mall_customers for ownership and shopping_mall_product_variants for the specific SKU. The unique constraint on (shopping_customer_id, shopping_product_variant_id) ensures only one cart item per variant per customer.
   *
   * Related operations:
   * - GET /cart-items - View all cart items with availability status
   * - PUT /cart-items/{cartItemId} - Update cart item quantity
   * - DELETE /cart-items/{cartItemId} - Remove item from cart
   *
   * @param connection
   * @param body Product variant and quantity to add to cart
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Implementation steps:
   *
   * 1. Authenticate customer via JWT token, extract customer ID
   * 2. Validate request body: variantId must be valid UUID, quantity must be 1-99
   * 3. Query shopping_mall_product_variants to verify variant exists and is not deleted (deleted_at is null)
   * 4. Query shopping_mall_products to verify product is active and seller is not suspended
   * 5. Calculate current price: use variant.price if set, otherwise product.base_price
   * 6. Check if cart item already exists for this customer+variant combination (unique constraint)
   * 7. If exists: update quantity (sum existing + new, capped at 99), update updated_at
   * 8. If not exists:
   *    a. Count existing cart items for customer (must be < 50)
   *    b. Create new cart_mall_cart_items record with customer_id, variant_id, quantity, current unit_price
   * 9. Return the created/updated cart item with variant and product information
   *
   * Edge cases:
   * - Variant not found: return 404 error
   * - Variant deleted (soft delete): return 410 Gone or treat as unavailable
   * - Product deleted: variant unavailable
   * - Seller suspended: product not purchasable
   * - Quantity exceeds 99 after combination: cap at 99
   * - Cart at 50 item limit: return 400 error
   * - Price change since last addition: keep original unit_price, warn during checkout
   *
   * Database operations:
   * - SELECT shopping_mall_product_variants JOIN shopping_mall_products
   * - SELECT shopping_mall_sellers (for suspension check)
   * - SELECT shopping_mall_cart_items (check existing, count items)
   * - INSERT or UPDATE shopping_mall_cart_items
   *
   * Transaction required for atomicity of check-and-create/update operations.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallCartItem.ICreate,
  ): Promise<IShoppingMallCartItem> {
    try {
      return await postShoppingMallCustomerCartItems({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a filtered and paginated list of items in the customer's shopping cart.
   *
   * This operation provides the authenticated customer with a comprehensive view of their cart contents, including product variant information, pricing, stock availability, and warnings for unavailable items.
   *
   * Each cart item includes the product name, variant options (color, size, etc.), price per unit, quantity, and calculated subtotal. The response also indicates availability status - items are marked as unavailable if the product variant has been deleted or has insufficient stock.
   *
   * The endpoint supports advanced filtering capabilities including availability status filtering and sorting by creation date or price. This enables customers to quickly identify problematic items before checkout.
   *
   * Stock warnings are displayed for items with insufficient quantity, helping customers adjust their orders accordingly. Unavailable items (deleted variants or out-of-stock) are highlighted but preserved in the cart for customer visibility, allowing them to remove or modify items before proceeding to checkout.
   *
   * This endpoint is typically used before checkout preparation to review cart contents and address any availability issues.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for cart items
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query shopping_mall_cart_items table for the authenticated customer (shopping_customer_id from JWT token).
   *
   * Join with shopping_mall_product_variants to get variant details (SKU code, price, stock).
   * Join with shopping_mall_products to get product name and images.
   * Join with shopping_mall_sellers to get shop name.
   *
   * Calculate availability status:
   * - If variant is deleted (soft-delete check on products or variants) → mark as 'unavailable'
   * - If variant stock < cart quantity → mark as 'insufficient_stock'
   * - Otherwise → 'available'
   *
   * Apply filters from request body:
   * - availability status filter (available/unavailable/all)
   * - pagination with cursor-based or offset-based approach
   * - sorting by created_at (newest/oldest) or unit_price (asc/desc)
   *
   * Response includes per-item:
   * - cart item id, quantity, unit_price, subtotal
   * - product id, name, thumbnail image
   * - variant id, SKU code, option values as key-value pairs
   * - current stock, availability status
   * - seller shop name
   *
   * Also include cart summary:
   * - total item count
   * - total price
   * - count of unavailable items
   *
   * Handle edge cases:
   * - Empty cart returns empty data array
   * - Deleted variants still appear with unavailable status
   * - Soft-deleted products by seller deletion preserved with seller snapshot name
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
