  /**
   * Remove a specific item from the authenticated customer's shopping cart.
   *
   * This operation permanently deletes a cart item record from the customer's shopping cart. The customer must be authenticated, and the cart item must belong to the authenticated customer for the deletion to succeed.
   *
   * The shopping_mall_cart_items table stores individual product variants that customers intend to purchase. Each cart item captures the variant reference, quantity, and unit price at the time of addition. When a cart item is removed, all associated information is permanently deleted.
   *
   * Security considerations:
   * - Only the cart item owner (the customer whose shopping_customer_id matches the authenticated user) can remove the item
   * - Attempts to delete another customer's cart item will result in a 404 Not Found response (to prevent information disclosure)
   * - Authentication is required via JWT Bearer token
   *
   * This operation is typically used when a customer decides they no longer want to purchase a specific product variant, or when clearing items before abandoning the cart.
   *
   * @param connection
   * @param cartItemId Unique identifier of the cart item to remove. Must belong to the authenticated customer.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Implementation steps:
   *
   * 1. Extract authenticated customer ID from JWT token payload
   * 2. Query shopping_mall_cart_items table for the specified cartItemId
   * 3. Verify the cart item exists and shopping_customer_id matches the authenticated customer
   * 4. If not found or ownership mismatch, return 404 Not Found
   * 5. Delete the cart item record from database
   * 6. Return the deleted cart item data for confirmation
   *
   * Database operations:
   * - SELECT to verify existence and ownership
   * - DELETE to remove the cart item record
   *
   * The foreign key constraint on shopping_product_variant_id has ON DELETE CASCADE, but this operation deletes the cart item itself, not the variant. No cascade effects.
   *
   * Edge cases:
   * - Cart item does not exist: return 404
   * - Cart item belongs to different customer: return 404 (not 403, to prevent enumeration)
   * - Variant has been soft-deleted: cart item can still be removed normally
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":cartItemId")
  public async erase(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("cartItemId")
    cartItemId: string,
  ): Promise<void> {
    try {
      return await deleteShoppingMallCustomerCartItemsCartItemId({
        customer,
        cartItemId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
