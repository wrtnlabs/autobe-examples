import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallCartItem } from "../../../../../api/structures/IShoppingMallCartItem";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { deleteShoppingMallCustomerCartsItemsCartItemId } from "../../../../../providers/deleteShoppingMallCustomerCartsItemsCartItemId";
import { putShoppingMallCustomerCartsItemsCartItemId } from "../../../../../providers/putShoppingMallCustomerCartsItemsCartItemId";

@Controller("/shoppingMall/customer/carts/items/:cartItemId")
export class ShoppingmallCustomerCartsItemsController {
  /**
   * Update the quantity of a specific item in the customer's shopping cart.
   *
   * This operation allows authenticated customers to modify the quantity of an existing cart item. The cart item must belong to the customer's own cart - ownership validation is enforced. If the same product variant was added again after this update, quantities would be merged according to the duplicate variant handling rules.
   *
   * Security and Validation:
   * - Only the cart owner (authenticated customer) can update cart items
   * - The cart item must exist in the customer's cart
   * - Quantity must be a positive integer (minimum 1)
   * - Unavailable items (deleted variants or out of stock) cannot have quantity changes
   *
   * The operation updates the cart item's quantity and the cart's updated_at timestamp. The cart structure is preserved for future additions.
   *
   * Related Operations:
   * - POST /carts/items - Add a new variant to cart
   * - DELETE /carts/items/{cartItemId} - Remove item from cart
   * - GET /carts - View cart contents
   *
   * @param connection
   * @param cartItemId Unique identifier of the cart item to update
   * @param body New quantity for the cart item
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Update the quantity of an existing cart item belonging to the authenticated customer.
   *
   * Implementation Steps:
   * 1. Validate the cartItemId path parameter exists and is a valid UUID
   * 2. Query shopping_mall_cart_items joined with shopping_mall_carts to verify ownership
   * 3. Verify the cart's shopping_mall_customer_id matches the authenticated customer
   * 4. If cart item not found or ownership mismatch, return 404 Not Found
   * 5. Check if the cart item's unavailable flag is true - if so, return 400 Bad Request
   * 6. Validate the new quantity is a positive integer >= 1
   * 7. Update the cart item's quantity field
   * 8. Update the cart's updated_at timestamp
   * 9. Return the updated cart item with variant and product information
   *
   * Database Queries:
   * - SELECT with JOIN to verify ownership: shopping_mall_cart_items JOIN shopping_mall_carts
   * - UPDATE shopping_mall_cart_items SET quantity = ?, updated_at = NOW()
   * - UPDATE shopping_mall_carts SET updated_at = NOW()
   *
   * Edge Cases:
   * - If variant stock is less than requested quantity, allow update but show warning in cart view
   * - If customer attempts to update another customer's cart item, return 404 (not 403 to avoid enumeration)
   * - If cart item doesn't exist, return 404
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("cartItemId")
    cartItemId: string,
    @TypedBody()
    body: IShoppingMallCartItem.IUpdate,
  ): Promise<IShoppingMallCartItem> {
    try {
      return await putShoppingMallCustomerCartsItemsCartItemId({
        customer,
        cartItemId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Remove a specific item from the customer's shopping cart.
   *
   * This operation permanently deletes a cart item from the authenticated customer's shopping cart. The customer must own the cart containing the specified cart item - attempting to remove items from another customer's cart will be rejected.
   *
   * Upon successful removal, the cart's updated_at timestamp is updated to reflect the modification. If this is the last item in the cart, the cart is retained as an empty cart for future use.
   *
   * The operation does not require confirmation before deletion. If a customer later adds the same variant again, it will be treated as a new cart item rather than restoring the deleted one.
   *
   * Related operations:
   * - GET /carts - View all items in the cart before removal
   * - POST /carts - Add items to the cart
   * - PATCH /carts/items/{cartItemId} - Change quantity instead of removing
   *
   * @param connection
   * @param cartItemId Unique identifier of the cart item to remove from the shopping cart. The cart item must belong to the authenticated customer's cart.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Implementation steps:
   *
   * 1. Extract cartItemId from path parameters
   * 2. Query shopping_mall_cart_items table to find the cart item by id
   * 3. If cart item not found, return 404 Not Found
   * 4. Join with shopping_mall_carts to verify the cart's shopping_mall_customer_id matches the authenticated customer's ID
   * 5. If ownership validation fails, return 403 Forbidden
   * 6. Delete the cart item record from shopping_mall_cart_items
   * 7. Update the parent cart's updated_at timestamp in shopping_mall_carts to current time
   * 8. Return 204 No Content on success
   *
   * Edge cases:
   * - Cart item does not exist: 404 Not Found
   * - Cart item belongs to another customer's cart: 403 Forbidden
   * - Item marked as unavailable can still be removed: allowed
   * - Last item in cart: cart retained as empty
   *
   * Transaction: Wrap deletion and timestamp update in a single transaction to ensure consistency.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("cartItemId")
    cartItemId: string,
  ): Promise<void> {
    try {
      return await deleteShoppingMallCustomerCartsItemsCartItemId({
        customer,
        cartItemId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
