import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallCart } from "../../../../api/structures/IShoppingMallCart";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { getShoppingMallCustomerCarts } from "../../../../providers/getShoppingMallCustomerCarts";

@Controller("/shoppingMall/customer/carts")
export class ShoppingmallCustomerCartsController {
  /**
   * Retrieve the authenticated customer's shopping cart with all item details.
   *
   * This endpoint returns the complete contents of the customer's cart, including all cart items with their associated product information, variant details, pricing, and seller information. Each customer has exactly one cart associated with their account.
   *
   * **Cart Contents Display:**
   * Each cart item includes:
   * - Product name from the shopping_mall_products table
   * - Variant options (e.g., color, size) from shopping_mall_product_variants.option_values
   * - Current unit price from the variant (shopping_mall_product_variants.price) or product base_price if variant price is not set
   * - Quantity selected
   * - Subtotal (current price multiplied by quantity)
   * - Stock status indicator (calculated from inventory records)
   * - Seller shop name from shopping_mall_sellers
   *
   * **Item Ordering:** Items are displayed in the order they were added to the cart (oldest first), using the shopping_mall_cart_items.created_at timestamp.
   *
   * **Unavailable Items:** Items whose variants have been deleted (shopping_mall_product_variants.deleted_at is not null) or whose products have been deleted (shopping_mall_products.deleted_at is not null) or are out of stock are marked with the unavailable flag. These items remain visible in the cart but cannot be checked out.
   *
   * **Suspended Sellers:** Products from suspended sellers remain visible in the cart and can still be purchased. No suspension indicators are shown.
   *
   * **Empty Cart:** If the customer has not added any items or has no cart record, returns a cart structure with null id and an empty items array. Cart is created only when the first item is added.
   *
   * **Security:** Cart ownership is strictly validated - customers can only access their own cart. The cart is identified by the authenticated customer's ID from the session token.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query the shopping_mall_carts table to find the cart belonging to the authenticated customer (where shopping_mall_customer_id matches the authenticated customer's ID). If no cart exists, create a new cart record for the customer (though this typically happens when first item is added).
   *
   * For the cart items, join shopping_mall_cart_items with shopping_mall_product_variants, shopping_mall_products, and shopping_mall_sellers tables to retrieve:
   * 1. Cart item: id, quantity, unavailable flag, created_at
   * 2. Variant: sku_code, option_values, price (current price), deleted_at (for availability check)
   * 3. Product: name, base_price, deleted_at (for availability check)
   * 4. Seller: shop_name, suspended status
   *
   * Calculate stock quantity by summing shopping_mall_inventory_records.quantity_change for each variant.
   *
   * Sort items by shopping_mall_cart_items.created_at ascending (oldest first).
   *
   * Calculate cart total by summing (item price × quantity) for all available items.
   *
   * Handle the unavailable flag: an item is unavailable if variant.deleted_at is not null OR if stock quantity is less than the cart item quantity.
   *
   * Response includes:
   * - Cart ID and timestamps
   * - Array of items with all computed fields
   * - Total price calculation
   * - Stock status per item
   *
   * Return empty items array if no cart items exist.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
  ): Promise<IShoppingMallCart> {
    try {
      return await getShoppingMallCustomerCarts({
        customer,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
