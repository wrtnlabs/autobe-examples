import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallOrderItem } from "../../../../api/structures/IPageIShoppingMallOrderItem";
import { IShoppingMallOrderItem } from "../../../../api/structures/IShoppingMallOrderItem";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { getShoppingMallCustomerOrderItemsOrderItemId } from "../../../../providers/getShoppingMallCustomerOrderItemsOrderItemId";
import { patchShoppingMallCustomerOrderItems } from "../../../../providers/patchShoppingMallCustomerOrderItems";

@Controller("/shoppingMall/customer/orderItems")
export class ShoppingmallCustomerOrderitemsController {
  /**
   * Retrieve a filtered and paginated list of order items for the authenticated seller's products.
   *
   * This endpoint enables sellers to view all order items for products they own, supporting comprehensive order management and fulfillment workflows. Sellers can track items awaiting shipment, in transit, delivered, cancelled, or refunded, and respond to customer requests accordingly.
   *
   * **Seller Data Isolation**: The operation enforces strict data isolation - sellers can only view order items for their own products. The seller ID is extracted from authentication context and applied as a mandatory filter, preventing access to other sellers' order data.
   *
   * **Status Filtering**: Sellers can filter order items by fulfillment status:
   * - `paid`: Items awaiting shipment - seller should create shipments for these
   * - `shipped`: Items in transit - customer has tracking information
   * - `delivered`: Items confirmed delivered by customer or auto-confirmed after 14 days
   * - `cancelled`: Items cancelled before shipment with stock restored
   * - `refunded`: Items refunded after delivery with stock restored
   *
   * **Order Context**: Each order item includes complete order context including order number for customer reference, shipping address for fulfillment, and customer information for communication purposes.
   *
   * **Product and Variant Details**: The response includes product name and variant details (SKU code, option values like color/size) to help sellers identify exactly what needs to be shipped.
   *
   * **Related Operations**:
   * - Use PATCH /orderItems with status='paid' to get items needing shipment
   * - Use POST /shipments to create shipments for paid items
   * - Use GET /orderItems/{id} to view complete order item details
   * - Use PATCH /cancellationRequests to respond to cancellation requests
   * - Use PATCH /refundRequests to respond to refund requests
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering seller's order items
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Implementation Steps:
   *
   * 1. **Authentication & Authorization**: Extract seller ID from authentication context. Verify the user is authenticated as a seller (not customer or administrator).
   *
   * 2. **Query Building**:
   *    - Base query filters by shopping_mall_seller_id = authenticated seller ID
   *    - Apply optional status filter if provided (paid, shipped, delivered, cancelled, refunded)
   *    - Apply pagination with cursor-based or offset-based approach
   *    - Sort by created_at descending (newest first) by default
   *
   * 3. **Data Retrieval**:
   *    - Join with shopping_mall_orders for order context (order_number, shipping address, customer info)
   *    - Join with shopping_mall_products for product name
   *    - Join with shopping_mall_product_variants for variant info (SKU, option values)
   *    - Join with shopping_mall_sellers is implicit (already filtered by seller_id)
   *
   * 4. **Response Assembly**:
   *    - Return paginated results with each item containing:
   *      - Order item summary (id, quantity, price, status)
   *      - Product info (id, name)
   *      - Variant info (id, sku_code, option_values)
   *      - Order info (id, order_number, created_at)
   *      - Customer info (from order)
   *      - Shipping address snapshot (from order)
   *
   * 5. **Data Isolation**: Never return order items belonging to other sellers. The seller_id filter is mandatory and applied before any other filtering.
   *
   * 6. **Performance**: Use database indexes on seller_id, status, and created_at for efficient querying.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallOrderItem.IRequest,
  ): Promise<IPageIShoppingMallOrderItem.ISummary> {
    try {
      return await patchShoppingMallCustomerOrderItems({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific order item by its unique identifier.
   *
   * This endpoint provides comprehensive order item details including the purchased product variant, quantity, price at time of purchase, and current fulfillment status. The response includes related product and variant information, seller shop details, order context, and shipment tracking information if the item has been shipped.
   *
   * Each order item represents a specific product variant purchased by a customer within an order, with its own independent status progression through paid, shipped, delivered, cancelled, or refunded states. Order items can be individually cancelled before shipment or refunded after delivery, making this endpoint essential for customers tracking their purchases.
   *
   * The order item snapshot preserves the complete product, variant, and seller profile state at the time of purchase, ensuring historical accuracy for dispute resolution and customer reference. This immutable snapshot remains unchanged even if the original product is modified, variant is deleted, or seller changes their shop profile.
   *
   * Access is restricted to the authenticated customer who placed the order containing this order item.
   *
   * @param connection
   * @param orderItemId Unique identifier of the order item to retrieve (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Retrieve a single order item by its UUID identifier.
   *
   * 1. Validate the orderItemId path parameter as a valid UUID format.
   * 2. Query shopping_mall_order_items table with the provided ID.
   * 3. If not found, return 404 Not Found error.
   * 4. Include related entities through joins:
   *    - shopping_mall_orders for order context (order number, status)
   *    - shopping_mall_products for product details
   *    - shopping_mall_product_variants for variant configuration
   *    - shopping_mall_sellers for seller shop information
   *    - shopping_mall_shipments for tracking info (if shipped)
   *    - shopping_mall_order_item_snapshots for purchase-time state
   * 5. Apply authorization check:
   *    - If authenticated as customer: verify the order item belongs to an order owned by this customer
   *    - If authenticated as seller: verify the order item references a product owned by this seller
   *    - If authenticated as administrator: allow access to any order item
   * 6. Return complete order item data with all relationships.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":orderItemId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderItemId")
    orderItemId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallOrderItem> {
    try {
      return await getShoppingMallCustomerOrderItemsOrderItemId({
        customer,
        orderItemId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
