import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IShoppingMallOrderShipment } from "../../../../../api/structures/IShoppingMallOrderShipment";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { postShoppingMallCustomerShipmentsShipmentIdConfirmDelivery } from "../../../../../providers/postShoppingMallCustomerShipmentsShipmentIdConfirmDelivery";

@Controller("/shoppingMall/customer/shipments/:shipmentId/confirm-delivery")
export class ShoppingmallCustomerShipmentsConfirm_deliveryController {
  /**
   * Confirm delivery of a shipment received by the customer.
   *
   * This operation allows customers to manually confirm that they have received a shipment containing their purchased items. Upon confirmation, the system records the delivery timestamp and updates the status of all order items in the shipment from 'shipped' to 'delivered'.
   *
   * **Prerequisites:**
   * - The shipment must belong to an order placed by the authenticated customer
   * - The shipment must have 'shipped' status (not already delivered)
   * - The shipment must not have been previously confirmed
   *
   * **Post-Confirmation Effects:**
   * - The shipment's delivered_at timestamp is set to the current time
   * - The delivery_confirmation_method is set to 'manual'
   * - All order items in the shipment change to 'delivered' status
   * - Customers can write reviews for delivered items
   * - The 7-day refund request window begins for each item
   *
   * **Related Operations:**
   * - GET /customers/me/orders/{orderId}/shipments - View shipments for an order
   * - POST /customers/me/order-items/{id}/refund - Request refund after delivery
   * - POST /customers/me/reviews - Write review for delivered item
   *
   * @param connection
   * @param shipmentId Unique identifier of the shipment to confirm delivery for
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Implement delivery confirmation for customer-owned shipments.
   *
   * **Authentication:**
   * - Requires authenticated customer (customer role)
   * - Validate that the shipment belongs to an order owned by the authenticated customer
   *
   * **Database Operations:**
   * 1. Query shopping_mall_order_shipments by shipmentId
   * 2. Verify shipment exists and is not deleted (deleted_at is null)
   * 3. Verify ownership: join through shopping_mall_order_shipment_items → shopping_mall_order_items → shopping_mall_orders → validate shopping_mall_customer_id matches authenticated user
   * 4. Verify delivered_at is null (not already delivered)
   *
   * **Transaction:**
   * 1. Update shopping_mall_order_shipments:
   *    - delivered_at = current timestamp
   *    - delivery_confirmation_method = 'manual'
   *    - updated_at = current timestamp
   * 2. Update all shopping_mall_order_items linked to this shipment (via shopping_mall_order_shipment_items junction table):
   *    - status = 'delivered'
   *
   * **Edge Cases:**
   * - Shipment not found: return 404
   * - Shipment already delivered: return 400 with message "Shipment has already been confirmed as delivered"
   * - Shipment not owned by customer: return 403
   * - Shipment deleted: return 404
   *
   * **Response:**
   * Return the updated shipment with all fields including delivery confirmation data.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async confirmDelivery(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("shipmentId")
    shipmentId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallOrderShipment> {
    try {
      return await postShoppingMallCustomerShipmentsShipmentIdConfirmDelivery({
        customer,
        shipmentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
