import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IShoppingMallShipment } from "../../../../../api/structures/IShoppingMallShipment";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { putShoppingMallCustomerShipmentsShipmentIdDelivery } from "../../../../../providers/putShoppingMallCustomerShipmentsShipmentIdDelivery";

@Controller("/shoppingMall/customer/shipments/:shipmentId/delivery")
export class ShoppingmallCustomerShipmentsDeliveryController {
  /**
   * Confirm delivery of a shipment containing one or more order items.
   *
   * This operation allows customers to confirm that they have received a shipment. When confirmed, the system records the delivery timestamp and updates all order items within the shipment from 'shipped' to 'delivered' status.
   *
   * The delivery confirmation is performed per shipment, not per individual item. All items bundled in the same shipment are marked as delivered together. This ensures consistency when a seller ships multiple items in a single package.
   *
   * **Authorization**: Only the customer who placed the order containing this shipment can confirm delivery. Attempts by other users to confirm delivery are rejected.
   *
   * **Validation Rules**:
   * - The shipment must exist and belong to an order owned by the authenticated customer
   * - The shipment must have shipped status (delivered_at must be null)
   * - If the shipment has already been confirmed as delivered, the request is rejected
   *
   * **Status Cascade**:
   * When delivery is confirmed:
   * - All order items in the shipment change from 'shipped' to 'delivered'
   * - The parent order status is recalculated based on all item statuses
   * - If all items are delivered, the order status becomes 'delivered'
   * - If some items are delivered and others are still in transit or cancelled/refunded, the order status becomes 'partially_completed'
   *
   * **Automatic Confirmation**:
   * If a customer does not confirm delivery within 14 days from the shipment date, the system automatically confirms delivery. Customers cannot manually confirm shipments that have already been auto-confirmed.
   *
   * **Related Operations**:
   * - Sellers create shipments via POST /sellers/shipments with carrier and tracking information
   * - Customers view shipment tracking via GET /orders/{orderId} which lists all shipments
   * - After delivery confirmation, customers can request refunds for delivered items via POST /orders/items/{itemId}/refund within 7 days
   *
   * @param connection
   * @param shipmentId Unique identifier of the shipment to confirm delivery for
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Implementation:
   *
   * 1. **Authorization**: Verify the authenticated customer owns the order containing this shipment
   *    - Query shipment with order relation
   *    - Check order.customer_id matches authenticated customer.id
   *    - Return 403 if ownership mismatch
   *
   * 2. **Validation**:
   *    - Return 404 if shipment not found
   *    - Check shipment.delivered_at is null (not already delivered)
   *    - Return 400 conflict if already delivered
   *    - Verify shipment.shipped_at exists (shipment was created)
   *
   * 3. **Database Transaction**:
   *    - Set shipment.delivered_at = current timestamp
   *    - Update all order_items with this shipment_id:
   *      - Set status = 'delivered'
   *      - Set updated_at = current timestamp
   *    - Recalculate parent order.status based on all item statuses
   *    - Commit transaction
   *
   * 4. **Response**: Return updated shipment with relations
   *
   * Edge Cases:
   * - Shipment already delivered: Reject with 400
   * - Shipment not found: Return 404
   * - Not the order owner: Return 403
   * - Order status recalculation: Check all items, derive appropriate status
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async confirmDelivery(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("shipmentId")
    shipmentId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallShipment> {
    try {
      return await putShoppingMallCustomerShipmentsShipmentIdDelivery({
        customer,
        shipmentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
