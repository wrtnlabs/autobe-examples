import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IPageIShoppingMallOrder } from "../../../../../api/structures/IPageIShoppingMallOrder";
import { IShoppingMallOrder } from "../../../../../api/structures/IShoppingMallOrder";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { patchShoppingMallCustomerAdminOrders } from "../../../../../providers/patchShoppingMallCustomerAdminOrders";

@Controller("/shoppingMall/customer/admin/orders")
export class ShoppingmallCustomerAdminOrdersController {
  /**
   * Retrieve a filtered and paginated list of all orders in the system.
   *
   * This administrator-only operation provides comprehensive search capabilities across all customer orders. Administrators can filter orders by status (single or multiple values), order number (partial match), customer ID, date range (created_at), and price range. Results are returned with pagination support and include order summary information with basic details.
   *
   * **Order Status Values:**
   * - 'paid': Order placed, awaiting shipment
   * - 'shipped': One or more items in transit
   * - 'delivered': All items delivered
   * - 'cancelled': All items cancelled before shipment
   * - 'refunded': All items refunded after delivery
   * - 'partially_completed': Mixed states (some shipped, some cancelled, etc.)
   *
   * **Security Considerations:**
   * - Only administrators (regular or super) can access this endpoint
   * - Orders from deleted customer accounts are included (customer_id may be null)
   * - Soft-deleted orders are excluded from results by default
   *
   * **Related Operations:**
   * - Use GET /customers/orders/{id} for detailed order information with items and shipments
   * - Use GET /seller/orders for seller-specific order item views
   * - Use admin order intervention APIs for force-cancel or force-refund operations
   *
   * **Data References:**
   * Orders reference the shopping_mall_orders table, which captures shipping address as immutable fields at checkout time. Each order has a unique order_number generated at creation. The status field is derived from individual order item statuses.
   *
   * @param connection
   * @param body Search criteria including status filters, date ranges, price ranges, customer filter, and order number search
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification Implement as a paginated search query on
     *   shopping_mall_orders table with the following logic:
   *
   * 1. **Authentication & Authorization:**
   *    - Require administrator authentication
   *    - Verify actor is 'administrator' with regular or super grade
   *
   * 2. **Query Building:**
   *    - Base query: SELECT FROM shopping_mall_orders WHERE deleted_at IS NULL
   *    - Apply filters from request body:
   *      - statuses (array): WHERE status IN (provided values)
   *      - orderNumber (string): WHERE order_number ILIKE '%{value}%' (case-insensitive partial match)
   *      - customerId (UUID): WHERE shopping_mall_customer_id = value
   *      - createdFrom (datetime): WHERE created_at >= value
   *      - createdTo (datetime): WHERE created_at <= value
   *      - minPrice (number): WHERE total_price >= value
   *      - maxPrice (number): WHERE total_price <= value
   *    - Combine filters with AND logic
   *
   * 3. **Sorting:**
   *    - Default: ORDER BY created_at DESC
   *    - Support custom sorting via request body sort field
   *
   * 4. **Pagination:**
   *    - Use cursor-based pagination for large result sets
   *    - Include total count in response metadata
   *    - Default page size: 20 items, max: 100 items
   *
   * 5. **Response Assembly:**
   *    - Return order summary fields: id, order_number, status, total_price, created_at
   *    - Include customer info if available (customer_id, customer email from join)
   *    - Count of order items per order
   *
   * 6. **Edge Cases:**
   *    - Empty filter results return empty array with pagination metadata
   *    - Invalid UUID format for customerId returns validation error
   *    - Date range validation: createdFrom must be <= createdTo
   *    - Price range validation: minPrice must be <= maxPrice
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallOrder.IRequest,
  ): Promise<IPageIShoppingMallOrder.ISummary> {
    try {
      return await patchShoppingMallCustomerAdminOrders({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
