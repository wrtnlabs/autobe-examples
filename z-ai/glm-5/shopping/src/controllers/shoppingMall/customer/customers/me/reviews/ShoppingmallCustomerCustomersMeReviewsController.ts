import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallReview } from "../../../../../../api/structures/IShoppingMallReview";
import { CustomerAuth } from "../../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../../decorators/payload/CustomerPayload";
import { postShoppingMallCustomerCustomersMeReviews } from "../../../../../../providers/postShoppingMallCustomerCustomersMeReviews";

@Controller("/shoppingMall/customer/customers/me/reviews")
export class ShoppingmallCustomerCustomersMeReviewsController {
  /**
   * Create a new review for a purchased product.
   *
   * This operation allows authenticated customers to submit reviews and ratings for products they have purchased and received. The review system enforces verified purchase requirements to ensure authenticity: the customer must have a delivered order item for the specified product-order combination.
   *
   * **Eligibility Requirements:**
   * - Customer must be authenticated
   * - The specified order must belong to the authenticated customer
   * - The order item for the specified product must have status "delivered"
   * - Only one review is allowed per product per order (enforced by unique constraint on customer_id, product_id, order_id)
   *
   * **Validation Rules:**
   * - Rating must be an integer between 1 and 5 (required)
   * - Content is optional but limited to 2,000 characters maximum
   * - The (productId, orderId) combination must correspond to a delivered order item owned by the customer
   *
   * **Business Context:**
   * Reviews are critical for building trust in the e-commerce platform, helping other customers make informed purchase decisions. All reviews display a "Verified Purchase" badge indicating the reviewer purchased through the platform. Reviews are preserved even if the customer deletes their account, displaying as "deleted user".
   *
   * **Related Operations:**
   * - GET /products/{id} displays product reviews
   * - PUT /customers/me/reviews/{id} allows editing
   * - DELETE /customers/me/reviews/{id} allows deletion
   *
   * @param connection
   * @param body Review creation data including product reference, order reference, rating, and optional text content
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Implement review creation with the following logic:
   *
   * 1. **Authentication Check**: Extract customer ID from JWT token. Return 401 if unauthenticated.
   *
   * 2. **Request Validation**:
   *    - Validate rating is integer 1-5
   *    - Validate content length ≤ 2000 if provided
   *    - Validate productId and orderId are valid UUIDs
   *
   * 3. **Eligibility Verification**:
   *    - Query shopping_mall_orders to verify order belongs to authenticated customer
   *    - Query shopping_mall_order_items to find item matching (order_id, product_id) with status = 'delivered'
   *    - Return 400 with appropriate error if no eligible order item found
   *
   * 4. **Duplicate Check**:
   *    - Query shopping_mall_reviews for existing review with (customer_id, product_id, order_id)
   *    - Return 400 with error if review already exists for this combination
   *
   * 5. **Create Review**:
   *    - Insert into shopping_mall_reviews with:
   *      - id: generate UUID
   *      - customer_id: from JWT
   *      - product_id, order_id, rating, content: from request
   *      - created_at, updated_at: current timestamp
   *      - deleted_at: null
   *
   * 6. **Response**: Return created review entity with 201 status
   *
   * **Error Scenarios:**
   * - 401: Not authenticated
   * - 400: No delivered order item for this product-order combination
   * - 400: Review already exists for this product-order
   * - 400: Invalid rating value (not 1-5)
   * - 400: Content exceeds 2000 characters
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallReview.ICreate,
  ): Promise<IShoppingMallReview> {
    try {
      return await postShoppingMallCustomerCustomersMeReviews({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
