import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallWishlist } from "../../../../../../api/structures/IShoppingMallWishlist";
import { CustomerAuth } from "../../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../../decorators/payload/CustomerPayload";
import { postShoppingMallCustomerCustomersMeWishlist } from "../../../../../../providers/postShoppingMallCustomerCustomersMeWishlist";

@Controller("/shoppingMall/customer/customers/me/wishlist")
export class ShoppingmallCustomerCustomersMeWishlistController {
  /**
   * Add a product to the authenticated customer's wishlist.
   *
   * This operation allows authenticated customers to save products they are interested in for later viewing. The wishlist tracks products at the product level, not specific variants, allowing customers to select variants when they decide to purchase.
   *
   * **Database Relationships:**
   * The shopping_mall_wishlists table maintains a foreign key relationship to shopping_mall_products with CASCADE DELETE, meaning wishlist entries are automatically removed when the referenced product is deleted by the seller.
   *
   * **Authentication Required:** This endpoint requires a valid customer JWT token. The customer ID is automatically extracted from the authentication context.
   *
   * **Business Rules:**
   * - Maximum of 200 products allowed per wishlist
   * - Unique constraint on customer_id + product_id prevents duplicate entries
   * - Products must exist and not be soft-deleted (deleted_at IS NULL)
   * - Seller of the product must not be suspended
   *
   * **Related Endpoints:**
   * - PATCH /customers/me/wishlist - View the paginated wishlist
   * - DELETE /customers/me/wishlist/{productId} - Remove a product from wishlist
   *
   * @param connection
   * @param body Product to add to wishlist, identified by product ID
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Create a wishlist entry linking the authenticated customer to a product.
   *
   * **Implementation Steps:**
   * 1. Extract customer ID from JWT authentication context
   * 2. Validate productId exists in shopping_mall_products table
   * 3. Verify product is not soft-deleted (deleted_at is null)
   * 4. Verify product's seller is not suspended
   * 5. Check current wishlist count does not exceed 200 products for this customer
   * 6. Use upsert pattern: if product already in wishlist, return existing entry; otherwise create new entry
   * 7. Return created/existing wishlist entry with product summary information
   *
   * **Database Operations:**
   * - SELECT from shopping_mall_products WHERE id = productId AND deleted_at IS NULL
   * - JOIN with shopping_mall_sellers to check seller status
   * - SELECT COUNT from shopping_mall_wishlists WHERE customer_id = authenticatedCustomerId
   * - INSERT into shopping_mall_wishlists (or return existing if duplicate)
   *
   * **Error Handling:**
   * - 404: Product not found or deleted
   * - 400: Wishlist limit reached (200 products)
   * - 400: Product seller suspended
   * - 401: Authentication required
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallWishlist.ICreate,
  ): Promise<IShoppingMallWishlist.ISummary> {
    try {
      return await postShoppingMallCustomerCustomersMeWishlist({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
