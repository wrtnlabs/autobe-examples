import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallCustomer } from "../../../../../api/structures/IShoppingMallCustomer";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { putShoppingMallCustomerCustomersMe } from "../../../../../providers/putShoppingMallCustomerCustomersMe";

@Controller("/shoppingMall/customer/customers/me")
export class ShoppingmallCustomerCustomersMeController {
  /**
   * Update the authenticated customer's profile information.
   *
   * This operation allows customers to modify their optional profile fields: display name shown in reviews and order communications, and phone number for delivery coordination. Both fields are optional and can be set, changed, or cleared independently.
   *
   * **Display Name Usage:**
   * - Shown as author name in product reviews
   * - Used in order communication notifications
   * - Displayed as 'Customer' if not set
   *
   * **Phone Number Usage:**
   * - Used for delivery coordination
   * - Contact for shipping notifications
   *
   * **Validation Rules:**
   * - Display name: Maximum 100 characters, cannot contain profanity or impersonate admin/seller
   * - Phone number: Valid international format (E.164), maximum 20 characters
   *
   * The operation updates the profile atomically and records the update timestamp. Customers can only update their own profile.
   *
   * @param connection
   * @param body Profile update data with optional display name and phone number
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Update customer profile fields in shopping_mall_customers table.
   *
   * 1. Authenticate customer from JWT token
   * 2. Validate request body fields:
   *    - displayName: If provided, check max length (100), check for profanity filter, check for reserved terms (admin, seller)
   *    - phoneNumber: If provided, validate E.164 format, max length (20)
   * 3. Update customer record:
   *    - SET display_name = request.displayName (can be null to clear)
   *    - SET phone_number = request.phoneNumber (can be null to clear)
   *    - SET updated_at = NOW()
   * 4. Return updated customer profile (excluding password_hash)
   *
   * Business rules:
   * - Customer can only update their own profile
   * - Both fields are optional - can update one or both
   * - Setting field to null clears the value
   * - No snapshot required for profile updates (only for seller profiles)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallCustomer.IUpdate,
  ): Promise<IShoppingMallCustomer> {
    try {
      return await putShoppingMallCustomerCustomersMe({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
