export async function getShoppingMallCustomerRefundRequestsRefundRequestId(props: {
  customer: CustomerPayload;
  refundRequestId: string;
}): Promise<IShoppingMallRefundRequest> {
  // Authorization check: verify customer owns the order
  const authCheck =
    await MyGlobal.prisma.shopping_mall_refund_requests.findUniqueOrThrow({
      where: { id: props.refundRequestId },
      select: {
        id: true,
        orderItem: {
          select: {
            order: {
              select: {
                shopping_mall_customer_id: true,
              },
            },
          },
        },
      },
    });
  if (
    authCheck.orderItem.order.shopping_mall_customer_id !== props.customer.id
  ) {
    throw new HttpException("Forbidden", 403);
  }
  // Fetch full data with transformer
  const refundRequest =
    await MyGlobal.prisma.shopping_mall_refund_requests.findUniqueOrThrow({
      where: { id: props.refundRequestId },
      ...ShoppingMallRefundRequestTransformer.select(),
    });
  return await ShoppingMallRefundRequestTransformer.transform(refundRequest);
}
