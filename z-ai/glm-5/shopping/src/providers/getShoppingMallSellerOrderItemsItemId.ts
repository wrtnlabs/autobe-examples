export async function getShoppingMallSellerOrderItemsItemId(props: {
  seller: SellerPayload;
  itemId: string;
}): Promise<IShoppingMallOrderItem> {
  // Query order item - filter by ID and exclude soft-deleted
  const orderItem =
    await MyGlobal.prisma.shopping_mall_order_items.findFirstOrThrow({
      where: {
        id: props.itemId,
        deleted_at: null,
      },
      ...ShoppingMallOrderItemTransformer.select(),
    });
  // Validate seller ownership - seller must own the product for this order item
  if (orderItem.seller.id !== props.seller.id) {
    throw new HttpException("Forbidden", 403);
  }
  // Transform and return the complete order item
  return await ShoppingMallOrderItemTransformer.transform(orderItem);
}
