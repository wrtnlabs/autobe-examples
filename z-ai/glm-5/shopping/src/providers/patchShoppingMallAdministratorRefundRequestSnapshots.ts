export async function patchShoppingMallAdministratorRefundRequestSnapshots(props: {
  administrator: AdministratorPayload;
  body: IShoppingMallRefundRequestSnapshot.IRequest;
}): Promise<IPageIShoppingMallRefundRequestSnapshot.ISummary> {
  const page = props.body.page ?? 1;
  const limit = props.body.limit ?? 20;
  const skip = (page - 1) * limit;
  const whereConditions: Prisma.shopping_mall_refund_request_snapshotsWhereInput["created_at"] =
    {};
  if (props.body.from !== undefined) {
    whereConditions.gte = new Date(props.body.from);
  }
  if (props.body.to !== undefined) {
    whereConditions.lte = new Date(props.body.to);
  }
  const whereInput: Prisma.shopping_mall_refund_request_snapshotsWhereInput = {
    ...(props.body.shoppingMallRefundRequestId !== undefined && {
      shopping_mall_refund_request_id: props.body.shoppingMallRefundRequestId,
    }),
    ...(props.body.status !== undefined && {
      status: props.body.status,
    }),
    ...(Object.keys(whereConditions).length > 0 && {
      created_at: whereConditions,
    }),
  };
  const [data, total] = await Promise.all([
    MyGlobal.prisma.shopping_mall_refund_request_snapshots.findMany({
      where: whereInput,
      skip,
      take: limit,
      orderBy: { created_at: "desc" },
      ...ShoppingMallRefundRequestSnapshotAtSummaryTransformer.select(),
    }),
    MyGlobal.prisma.shopping_mall_refund_request_snapshots.count({
      where: whereInput,
    }),
  ]);
  return {
    pagination: {
      current: page,
      limit: limit,
      records: total,
      pages: Math.ceil(total / limit),
    } satisfies IPage.IPagination,
    data: await ArrayUtil.asyncMap(
      data,
      ShoppingMallRefundRequestSnapshotAtSummaryTransformer.transform,
    ),
  };
}
