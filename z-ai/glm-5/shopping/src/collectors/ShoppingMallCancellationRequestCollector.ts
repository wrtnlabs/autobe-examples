export namespace ShoppingMallCancellationRequestCollector {
  export async function collect(props: {
    body: IShoppingMallCancellationRequest.ICreate;
  }) {
    const id: string = v4();
    return {
      id,
      reason: props.body.reason,
      status: "pending",
      created_at: new Date(),
      updated_at: new Date(),
      responded_at: null,
      // BelongsTo relations (use connect)
      orderItem: { connect: { id: props.body.orderItemId.id } },
      // Optional belongsTo (use undefined, NOT null)
      seller: undefined,
    } satisfies Prisma.shopping_mall_cancellation_requestsCreateInput;
  }
}
