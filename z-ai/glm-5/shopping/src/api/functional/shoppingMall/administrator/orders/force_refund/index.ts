/**
 * Force-refunds all items in an order, bypassing normal refund approval processes and timing constraints.
 *
 * This administrative intervention operation allows platform administrators to process full order refunds regardless of item delivery status, the 7-day refund window, or any existing refund request status. When executed, all items in the order are marked as refunded, stock quantities are restored for each product variant, and the payment is refunded to the customer.
 *
 * The force-refund operation is used in dispute resolution scenarios where customers and sellers cannot reach agreement, or when platform policy violations warrant direct administrative action. This operation overrides seller authority to approve or reject refund requests.
 *
 * A mandatory reason field documents the justification for the intervention, which is preserved in the audit trail and visible to all parties. The administrator's identity, timestamp, and reason are permanently recorded for accountability and potential dispute resolution.
 *
 * Related to shopping_mall_orders table (order status management), shopping_mall_order_items table (individual item status), shopping_mall_inventory_records table (stock restoration), and shopping_mall_administrators table (action attribution).
 *
 * @param props.connection
 * @param props.orderId Unique identifier of the order to force-refund. The order must exist in the shopping_mall_orders table.
 * @param props.body Force-refund request containing the required reason for the administrative intervention
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor administrator
 * @x-autobe-specification 1. Validate administrator authentication and retrieve administrator record from shopping_mall_administrators table.
 * 2. Retrieve the order by orderId from shopping_mall_orders table.
 * 3. If order not found, return 404 error.
 * 4. Retrieve all order items for this order from shopping_mall_order_items table.
 * 5. For each order item:
 *    a. If item status is already 'refunded' or 'cancelled', skip (no duplicate refund).
 *    b. Update item status to 'refunded'.
 *    c. Create inventory record in shopping_mall_inventory_records with positive quantity_change (item.quantity), reason: 'Administrator force-refund: {provided reason}', and variant_id.
 *    d. If there's an existing pending refund request for this item, close it.
 * 6. Update order status to 'refunded' in shopping_mall_orders.
 * 7. Process payment refunds for all items (integration with payment gateway).
 * 8. Record audit log with administrator ID, action type 'force-refund', order ID, reason, and timestamp.
 * 9. Return the updated order with all items in refunded status.
 * @path /shoppingMall/administrator/orders/:orderId/force-refund
 * @accessor api.functional.shoppingMall.administrator.orders.force_refund.forceRefund
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function forceRefund(
  connection: IConnection,
  props: forceRefund.Props,
): Promise<forceRefund.Response> {
  return true === connection.simulate
    ? forceRefund.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...forceRefund.METADATA,
          path: forceRefund.path(props),
          status: null,
        },
        props.body,
      );
}
