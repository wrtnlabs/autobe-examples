/**
 * Force-cancel an individual order item as an administrator, bypassing the normal seller approval process.
 *
 * This administrative intervention endpoint allows administrators to forcibly cancel any order item regardless of its current status. When executed, the operation immediately changes the item status to 'cancelled', processes a refund to the customer for that specific item, and restores the stock quantity for the affected product variant via an inventory record.
 *
 * Administrators use this power for dispute resolution, policy enforcement, or exceptional customer service situations. The force-cancel authority overrides any existing pending cancellation request from the customer - if a request exists, it is automatically closed and the cancellation proceeds immediately.
 *
 * The operation requires documenting the reason for the force-cancel action, which is preserved in the inventory record for audit purposes. This ensures transparency and accountability for all administrative order interventions.
 *
 * After cancellation, if remaining items in the order continue processing normally, the overall order status is recalculated and may become 'partially_completed'. If all items in the order are cancelled, the order status becomes 'cancelled'.
 *
 * Security: Only administrators (regular or super grade) can perform force-cancel operations. The administrator's identity and timestamp are recorded for audit trail purposes.
 *
 * @param props.connection
 * @param props.orderItemId Unique identifier of the order item to force-cancel. References shopping_mall_order_items.id.
 * @param props.body Force cancellation details including the required reason for administrative documentation.
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor administrator
 * @x-autobe-specification Implementation steps:
 *
 * 1. Validate the order item exists by orderItemId (UUID lookup on shopping_mall_order_items table)
 *
 * 2. Verify administrator authorization (admin role required)
 *
 * 3. Check if order item status allows force-cancel - administrator can force-cancel items in any status (paid, shipped, delivered)
 *
 * 4. If there is an existing pending cancellation request for this item:
 *    - Close the cancellation request (set status to approved)
 *    - Record the force-cancel override
 *
 * 5. Update the order item:
 *    - Set status to 'cancelled'
 *    - Update updated_at timestamp
 *
 * 6. Create inventory restoration record:
 *    - Insert record into shopping_mall_inventory_records
 *    - Set variant_id from the order item's shopping_mall_product_variant_id
 *    - Set quantity_change to (order_item.quantity) positive value
 *    - Set reason to 'Force-cancelled by administrator: {provided reason}'
 *    - Set created_at to current timestamp
 *
 * 7. Recalculate the parent order status:
 *    - Query all order items for the parent order
 *    - Apply status derivation rules: if all cancelled → 'cancelled', if mixed states → 'partially_completed', etc.
 *
 * 8. Process refund (integration with payment gateway)
 *
 * 9. Return the updated order item with complete details
 *
 * Transaction boundary: All database updates (order item status, inventory record, order status) must be atomic.
 * @path /shoppingMall/administrator/orderItems/:orderItemId/force-cancel
 * @accessor api.functional.shoppingMall.administrator.orderItems.force_cancel.forceCancel
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function forceCancel(
  connection: IConnection,
  props: forceCancel.Props,
): Promise<forceCancel.Response> {
  return true === connection.simulate
    ? forceCancel.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...forceCancel.METADATA,
          path: forceCancel.path(props),
          status: null,
        },
        props.body,
      );
}
