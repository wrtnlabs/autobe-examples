import {
  HttpError,
  IConnection,
  NestiaSimulator,
  PlainFetcher,
} from "@nestia/fetcher";
import typia from "typia";

import { IShoppingMallShipment } from "../../../../../structures/IShoppingMallShipment";

/**
 * Confirm delivery of a shipment by the customer who placed the order.
 *
 * This operation allows customers to acknowledge receipt of their shipped package. When confirmed, the shipment's delivered_at timestamp is set to the current time, and all order items within that shipment have their status changed from 'shipped' to 'delivered'.
 *
 * The operation is restricted to the customer who placed the order containing the shipment. The system validates that the shipment exists, belongs to the authenticated customer's order, has been shipped (shipped_at is set), and has not already been confirmed (delivered_at is null).
 *
 * If a customer does not confirm delivery within 14 days from the shipped_at date, the system automatically marks the shipment as delivered. Customers cannot confirm delivery after automatic confirmation has occurred.
 *
 * Related operations:
 * - GET /customers/orders/{orderId}/shipments - View all shipments for an order
 * - POST /seller/shipments - Seller creates shipment with tracking information
 *
 * @param props.connection
 * @param props.shipmentId Unique identifier of the shipment to confirm delivery for
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor customer
 * @x-autobe-specification Implementation steps:
 *
 * 1. Validate shipment exists by ID from path parameter
 * 2. Retrieve the shipment with its related order via order_id foreign key
 * 3. Verify the authenticated customer matches the order's shopping_mall_customer_id
 * 4. Check shipment.shipped_at is not null (shipment has been created/shipped)
 * 5. Check shipment.delivered_at is null (not already confirmed)
 * 6. If 14 days have passed since shipped_at, return error indicating auto-confirmed
 * 7. Set shipment.delivered_at = current_timestamp
 * 8. Update all order_items where shopping_mall_shipment_id = shipment.id:
 *    - Set status = 'delivered'
 *    - Set updated_at = current_timestamp
 * 9. Recalculate and update the parent order's derived status based on all its items
 * 10. Return the updated shipment record
 *
 * Edge cases:
 * - Shipment not found: return 404
 * - Customer not authorized (different customer's shipment): return 403
 * - Already delivered (delivered_at set): return 400 with 'already delivered' error
 * - Not yet shipped (shipped_at null): return 400 with 'not yet shipped' error
 * - Auto-confirmed after 14 days: return 400 with 'already auto-confirmed' error
 * @path /shoppingMall/customer/shipments/:shipmentId/confirm-delivery
 * @accessor api.functional.shoppingMall.customer.shipments.confirm_delivery.confirmDelivery
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function confirmDelivery(
  connection: IConnection,
  props: confirmDelivery.Props,
): Promise<confirmDelivery.Response> {
  return true === connection.simulate
    ? confirmDelivery.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...confirmDelivery.METADATA,
          path: confirmDelivery.path(props),
          status: null,
        },
      );
}
export namespace confirmDelivery {
  export type Props = {
    /**
     * Unique identifier of the shipment to confirm delivery for
     */
    shipmentId: string;
  };
  export type Response = IShoppingMallShipment;

  export const METADATA = {
    method: "POST",
    path: "/shoppingMall/customer/shipments/:shipmentId/confirm-delivery",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/customer/shipments/${encodeURIComponent(props.shipmentId ?? "null")}/confirm-delivery`;
  export const random = (): IShoppingMallShipment =>
    typia.random<IShoppingMallShipment>();
  export const simulate = (
    connection: IConnection,
    props: confirmDelivery.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: confirmDelivery.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("shipmentId")(() => typia.assert(props.shipmentId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
