/**
 * Retrieve a filtered and paginated list of shipments for a specific order.
 *
 * This operation allows customers to view all shipments associated with their order, providing tracking information including carrier name, tracking number, shipping date, and delivery status. Each shipment groups order items from the same seller, supporting the multi-seller order model.
 *
 * The shipment data is derived from the shopping_mall_shipments table, linked to shopping_mall_orders via the order_id foreign key. Shipments are created by sellers when they fulfill order items, and each shipment may contain multiple order items from the same seller.
 *
 * For orders where items have not yet been shipped (items with 'paid' status), no shipment records exist. Customers can use this endpoint to track delivery progress and view which items are included in each shipment. Delivery confirmation is handled through a separate endpoint.
 *
 * This endpoint only returns shipments for orders belonging to the authenticated customer. Customers can only view their own order shipments.
 *
 * @param props.connection
 * @param props.orderId Unique identifier of the order to retrieve shipments for
 * @param props.body Search criteria and pagination parameters for shipment listing
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor customer
 * @x-autobe-specification Query shopping_mall_shipments table filtering by
 *   order_id matching the orderId path parameter.
 *
 * Implementation steps:
 * 1. Verify the authenticated user has access to the order (customer who placed the order OR seller with items in the order OR administrator)
 * 2. Query shopping_mall_shipments where order_id = orderId and deleted_at IS NULL
 * 3. Apply optional filters from request body:
 *    - deliveryStatus: filter by whether delivered_at is null (pending) or not null (delivered)
 *    - carrierName: partial match on carrier_name field
 *    - search: search in carrier_name and tracking_number fields
 * 4. Apply pagination using cursor-based or offset-based approach
 * 5. Sort by created_at descending (newest first) by default, configurable via request body
 * 6. For each shipment, join with shopping_mall_order_items to get the list of items in that shipment
 * 7. Include seller information (shopping_mall_sellers) for each shipment
 * 8. Return paginated results with shipment summaries
 *
 * Edge cases:
 * - If order not found or user lacks access, return 404
 * - If order has no shipments yet (all items still in 'paid' status), return empty list
 * - Soft-deleted shipments are excluded from results
 *
 * Response includes: shipment id, carrier name, tracking number, shipped_at, delivered_at, seller info, and list of included order item ids with product names.
 * @path /shoppingMall/customer/orders/:orderId/shipments
 * @accessor api.functional.shoppingMall.customer.orders.shipments.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
