/**
 * Retrieve a filtered and paginated list of shipments for a specific order.
 *
 * This operation provides customers with visibility into all shipments associated with their order, enabling them to track packages and confirm delivery. Each shipment represents a package sent by a seller containing one or more order items from that seller.
 *
 * The shipment list displays comprehensive tracking information including carrier name, tracking number, shipping date, and delivery confirmation status. Each shipment entry includes the seller's shop information and a list of order items contained within that package.
 *
 * Key business rules enforced:
 * - Each shipment belongs to exactly one seller and contains only that seller's items
 * - Different sellers always ship separately, resulting in multiple shipments for multi-seller orders
 * - Items awaiting shipment (status 'paid') are not associated with any shipment yet
 * - Customers can filter shipments by delivery status to distinguish in-transit from delivered packages
 * - Customers can filter by seller to focus on specific seller's shipments
 *
 * This endpoint requires customer authentication and only returns shipments for orders belonging to the authenticated customer. Unauthorized access attempts are rejected with appropriate error responses.
 *
 * @param props.connection
 * @param props.orderId Unique identifier of the order to retrieve shipments for
 * @param props.body Filter criteria for shipment search including delivery status and seller
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor customer
 * @x-autobe-specification Query shopping_mall_shipments table filtered by order_id matching the path parameter orderId. Join with shopping_mall_sellers to include seller shop name and logo. Join with shopping_mall_order_items to retrieve items included in each shipment. Apply request body filters: deliveryStatus (delivered for delivered_at not null, in-transit for delivered_at null), sellerId for filtering by specific seller. Sort by shipped_at descending. Return paginated results with pagination metadata. Verify the authenticated customer owns the order before returning shipments. If order not found or not owned by customer, return appropriate error.
 * @path /shoppingMall/customer/orders/:orderId/shipments
 * @accessor api.functional.shoppingMall.customer.orders.shipments.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Unique identifier of the order to retrieve shipments for
     */
    orderId: string & tags.Format<"uuid">;

    /**
     * Filter criteria for shipment search including delivery status and seller
     */
    body: IShoppingMallShipment.IRequest;
  };
  export type Body = IShoppingMallShipment.IRequest;
  export type Response = IPageIShoppingMallShipment.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/customer/orders/:orderId/shipments",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/shoppingMall/customer/orders/${encodeURIComponent(props.orderId ?? "null")}/shipments`;
  export const random = (): IPageIShoppingMallShipment.ISummary =>
    typia.random<IPageIShoppingMallShipment.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("orderId")(() => typia.assert(props.orderId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
