import { HttpError, IConnection } from "@nestia/fetcher";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";

import { IShoppingMallReview } from "../../../structures/IShoppingMallReview";

/**
 * Retrieve a single customer review by its unique identifier.
 *
 * This endpoint returns detailed information about a specific review, including the star rating, text content, timestamps, and customer display name. If the customer has deleted their account, the author will display as 'deleted user'.
 *
 * The review must be active (not soft-deleted). If the review has been deleted by the customer, a 404 error is returned.
 *
 * This endpoint is publicly accessible without authentication, allowing anyone to view reviews on product detail pages for informed purchase decisions.
 *
 * @param props.connection
 * @param props.reviewId Unique identifier of the review to retrieve
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor null
 * @x-autobe-specification Query the shopping_mall_reviews table by id (UUID). Filter out soft-deleted reviews (deleted_at IS NULL). Join with shopping_mall_customers to retrieve display_name. If customer has deleted their account (customer record does not exist or is soft-deleted), return 'deleted user' as the author. Include rating (1-5), content (may be null), created_at, and updated_at timestamps. Return 404 if review not found or is soft-deleted.
 * @path /shoppingMall/reviews/:reviewId
 * @accessor api.functional.shoppingMall.reviews.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique identifier of the review to retrieve
     */
    reviewId: string;
  };
  export type Response = IShoppingMallReview;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/reviews/:reviewId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/reviews/${encodeURIComponent(props.reviewId ?? "null")}`;
  export const random = (): IShoppingMallReview =>
    typia.random<IShoppingMallReview>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("reviewId")(() => typia.assert(props.reviewId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
