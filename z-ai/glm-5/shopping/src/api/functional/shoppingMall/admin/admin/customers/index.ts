/**
 * Restore access to a banned customer account.
 *
 * This administrative operation allows administrators to unban a previously banned customer, immediately restoring their ability to log in and access all platform features. The operation is typically used when a ban was issued in error or when a customer has successfully appealed their ban.
 *
 * **Administrative Access Required**
 * This endpoint requires administrator authentication. Both regular administrators and super administrators have permission to unban customers.
 *
 * **Audit Trail**
 * When a customer is unbanned, the system records:
 * - The administrator who performed the unban action
 * - The timestamp of the operation
 * - The target customer ID
 *
 * This information is stored in the admin audit logs for security compliance and accountability.
 *
 * **Effects of Unban**
 * - Customer can log in immediately
 * - Customer can browse products
 * - Customer can place orders
 * - Customer can view order history
 * - Customer can manage wishlist and write reviews
 * - All customer data is preserved
 *
 * **Related Operations**
 * - Use GET /admin/customers to list all customers and identify banned accounts
 * - Use PUT /admin/customers/{customerId}/ban to ban a customer
 *
 * @param props.connection
 * @param props.customerId Unique identifier of the customer to unban (global scope)
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor admin
 * @x-autobe-specification Implementation steps for customer unban operation:
 *
 * 1. **Authentication & Authorization Check**
 *    - Verify the requester is an authenticated administrator (regular or super admin)
 *    - Return 401 Unauthorized if not authenticated
 *    - Return 403 Forbidden if not an administrator
 *
 * 2. **Customer Lookup**
 *    - Query shopping_mall_customers table by customerId
 *    - Return 404 Not Found if customer does not exist
 *    - Check if customer is currently banned
 *    - Return appropriate response if customer is not banned
 *
 * 3. **Unban Execution**
 *    - Update the customer's ban status to active (clear banned_at or is_banned flag)
 *    - Update the updated_at timestamp
 *
 * 4. **Audit Log Creation**
 *    - Create a record in shopping_mall_admin_audit_logs with:
 *      - shopping_mall_admin_id: ID of the performing administrator
 *      - action: 'customer_unban'
 *      - target_type: 'customer'
 *      - target_id: customerId
 *      - ip: Requester's IP address
 *      - created_at: Current timestamp
 *
 * 5. **Response**
 *    - Return the updated customer object
 *    - Include relevant customer fields: id, email, display_name, phone_number, created_at, updated_at, ban status
 *
 * **Database Transactions**
 * Wrap the unban and audit log operations in a transaction to ensure atomicity.
 *
 * **Error Handling**
 * - 401: Not authenticated
 * - 403: Not authorized (not an admin)
 * - 404: Customer not found
 * - 409: Customer is not currently banned
 * @path /shoppingMall/admin/admin/customers/:customerId/unban
 * @accessor api.functional.shoppingMall.admin.admin.customers.unban
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function unban(
  connection: IConnection,
  props: unban.Props,
): Promise<unban.Response> {
  return true === connection.simulate
    ? unban.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...unban.METADATA,
          path: unban.path(props),
          status: null,
        },
      );
}
export namespace unban {
  export type Props = {
    /**
     * Unique identifier of the customer to unban (global scope)
     */
    customerId: string & tags.Format<"uuid">;
  };
  export type Response = IShoppingMallCustomer;

  export const METADATA = {
    method: "PUT",
    path: "/shoppingMall/admin/admin/customers/:customerId/unban",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/admin/admin/customers/${encodeURIComponent(props.customerId ?? "null")}/unban`;
  export const random = (): IShoppingMallCustomer =>
    typia.random<IShoppingMallCustomer>();
  export const simulate = (
    connection: IConnection,
    props: unban.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: unban.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("customerId")(() => typia.assert(props.customerId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
