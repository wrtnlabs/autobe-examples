import { HttpError, IConnection } from "@nestia/fetcher";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";

import { IShoppingMallCustomer } from "../../../../structures/IShoppingMallCustomer";

/**
 * Bans a customer account, preventing them from logging in and accessing the platform.
 *
 * This administrative action immediately revokes all customer access privileges. When a customer is banned:
 *
 * **Access Revocation:**
 * - The customer cannot log in to their account
 * - All active sessions are immediately invalidated
 * - All platform features become inaccessible
 *
 * **Data Preservation:**
 * - The customer's profile information is preserved
 * - Order history is maintained for seller records
 * - Reviews remain visible (displayed as written by the banned customer)
 * - Wishlist and cart data are retained
 *
 * **Audit Trail:**
 * - The banning administrator's identity is recorded
 * - The ban reason is documented
 * - The timestamp of the ban action is captured
 * - A permanent audit log entry is created
 *
 * **Related Operations:**
 * - Use GET /admin/customers to list all customers
 * - Use PUT /customers/{customerId}/unban to restore customer access
 * - Use GET /admin/customers/{customerId} to view customer details before banning
 *
 * **Security Considerations:**
 * This operation requires administrator privileges (regular or super administrator). The action is logged for compliance and dispute resolution purposes. Banned customers retain their data but cannot access it until unbanned.
 *
 * @param props.connection
 * @param props.customerId UUID of the customer account to ban
 * @param props.body Ban reason and administrative notes
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor admin
 * @x-autobe-specification Execute customer ban operation with the following steps:
 *
 * 1. **Authorization Check:** Verify the requesting user has admin privileges (regular or super admin grade from shopping_mall_admins table).
 *
 * 2. **Customer Lookup:** Query shopping_mall_customers by customerId (UUID). Return 404 if not found.
 *
 * 3. **Idempotency Check:** If customer is already banned (banned_at is not null), return success without further action.
 *
 * 4. **Set Ban Status:** Update shopping_mall_customers record:
 *    - Set banned_at to current timestamp
 *    - Update updated_at to current timestamp
 *
 * 5. **Invalidate Sessions:** Delete all records from shopping_mall_customer_sessions where shopping_mall_customer_id matches the banned customer. This prevents further API access with existing tokens.
 *
 * 6. **Create Audit Log:** Insert record into shopping_mall_admin_audit_logs:
 *    - shopping_mall_admin_id: ID of the administrator performing the ban
 *    - action: 'customer_ban'
 *    - target_type: 'customer'
 *    - target_id: the banned customer's ID
 *    - details: JSON containing { reason: string }
 *    - ip: administrator's IP address
 *    - created_at: current timestamp
 *
 * 7. **Return Response:** Return the updated customer record with ban status reflected.
 * @path /shoppingMall/admin/customers/:customerId/ban
 * @accessor api.functional.shoppingMall.admin.customers.ban
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function ban(
  connection: IConnection,
  props: ban.Props,
): Promise<ban.Response> {
  return true === connection.simulate
    ? ban.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...ban.METADATA,
          path: ban.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace ban {
  export type Props = {
    /**
     * UUID of the customer account to ban
     */
    customerId: string;

    /**
     * Ban reason and administrative notes
     */
    body: IShoppingMallCustomer.IBan;
  };
  export type Body = IShoppingMallCustomer.IBan;
  export type Response = IShoppingMallCustomer;

  export const METADATA = {
    method: "PUT",
    path: "/shoppingMall/admin/customers/:customerId/ban",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/shoppingMall/admin/customers/${encodeURIComponent(props.customerId ?? "null")}/ban`;
  export const random = (): IShoppingMallCustomer =>
    typia.random<IShoppingMallCustomer>();
  export const simulate = (
    connection: IConnection,
    props: ban.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: ban.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("customerId")(() => typia.assert(props.customerId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
