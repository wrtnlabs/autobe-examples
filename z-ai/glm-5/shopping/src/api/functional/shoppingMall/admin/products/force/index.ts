/**
 * Soft-deletes a product from the platform due to policy violations, setting the deleted_at timestamp.
 *
 * This administrative operation bypasses normal product deletion constraints and allows administrators to remove any product from the marketplace. Unlike seller-initiated deletion which requires no pending orders or requests, force deletion proceeds regardless of current product activity.
 *
 * When a product is force-deleted:
 * - The product's deleted_at timestamp is set, hiding it from search results and category listings
 * - All product variants (SKUs) are cascade-deleted
 * - All inventory history records for those variants are deleted
 * - All wishlist entries referencing the product are automatically removed
 * - Product snapshots are preserved for historical accuracy and dispute resolution
 *
 * This operation is restricted to administrators (both regular and super admin grades) and requires a reason to be recorded in the administrative audit log.
 *
 * The product information returned in the response represents the final state of the product before deletion, allowing administrators to confirm the action taken.
 *
 * @param props.connection
 * @param props.productId Unique identifier of the product to be force-deleted. References shopping_mall_products.id in the database.
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor admin
 * @x-autobe-specification Implement force-delete for products with administrative override:
 *
 * 1. **Authentication & Authorization Check:**
 *    - Verify user is authenticated with admin role
 *    - Both regular admin and super admin have this permission
 *
 * 2. **Product Lookup:**
 *    - Query shopping_mall_products by productId
 *    - Return 404 if product not found
 *
 * 3. **Deletion Execution:**
 *    - Set deleted_at timestamp on the product record (soft delete)
 *    - Database cascade handles:
 *      - shopping_mall_product_variants (deleted via onDelete: Cascade)
 *      - shopping_mall_product_inventory_histories (deleted via cascade)
 *      - shopping_mall_product_images (deleted via onDelete: Cascade)
 *      - shopping_mall_wishlists entries (deleted via onDelete: Cascade)
 *    - Preserve shopping_mall_product_snapshots (not cascade deleted)
 *
 * 4. **Audit Trail:**
 *    - Record deletion action in admin audit log
 *    - Include: admin ID, product ID, deletion reason, timestamp
 *
 * 5. **Response:**
 *    - Return the deleted product information
 *    - Include final state: name, description, base_price, category_id, seller_id
 *
 * **Important Notes:**
 * - Force deletion bypasses pending order checks (unlike seller deletion)
 * - Existing order items preserve their snapshot data
 * - The seller retains order history for their records
 * - Product is hidden from search/listings immediately
 * @path /shoppingMall/admin/products/:productId/force
 * @accessor api.functional.shoppingMall.admin.products.force.eraseForce
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function eraseForce(
  connection: IConnection,
  props: eraseForce.Props,
): Promise<void> {
  return true === connection.simulate
    ? eraseForce.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...eraseForce.METADATA,
          path: eraseForce.path(props),
          status: null,
        },
      );
}
export namespace eraseForce {
  export type Props = {
    /**
     * Unique identifier of the product to be force-deleted. References shopping_mall_products.id in the database.
     */
    productId: string & tags.Format<"uuid">;
  };

  export const METADATA = {
    method: "DELETE",
    path: "/shoppingMall/admin/products/:productId/force",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/admin/products/${encodeURIComponent(props.productId ?? "null")}/force`;
  export const random = (): void => typia.random<void>();
  export const simulate = (
    connection: IConnection,
    props: eraseForce.Props,
  ): void => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: eraseForce.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("productId")(() => typia.assert(props.productId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
