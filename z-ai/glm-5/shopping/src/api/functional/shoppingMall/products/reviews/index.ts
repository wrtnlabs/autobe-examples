import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";

import { IPageIShoppingMallReview } from "../../../../structures/IPageIShoppingMallReview";
import { IShoppingMallReview } from "../../../../structures/IShoppingMallReview";

/**
 * Retrieve a paginated list of customer reviews for a specific product.
 *
 * This endpoint returns all non-deleted reviews for the specified product, sorted by creation date with newest reviews appearing first. Each review includes the customer's display name (shown as 'deleted user' if the customer account has been deleted), the star rating from 1 to 5, optional text content, and the creation timestamp.
 *
 * Reviews can only be written by customers who have purchased and received the product, ensuring authentic feedback from verified buyers. The one-review-per-product-per-order constraint prevents review manipulation. Reviews contribute to the product's overall average rating, which is calculated from all non-deleted reviews.
 *
 * This endpoint supports pagination for efficient browsing of review history. The default page size is 10 items, with a maximum of 100 items per page. Results are always sorted by creation date descending to surface the most recent customer feedback first.
 *
 * @param props.connection
 * @param props.productId Unique identifier of the product to retrieve reviews for
 * @param props.body Pagination and search parameters for review listing
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor null
 * @x-autobe-specification Query shopping_mall_reviews table where shopping_mall_product_id equals the productId parameter and deleted_at IS NULL. Join with shopping_mall_customers to retrieve display_name for each review author. Sort by created_at in descending order (newest first). Support pagination with configurable page size (default 10, max 100) and page number. Return paginated results with review summary data including author display name (or 'deleted user' if customer account deleted), rating, content, and created_at timestamp. Calculate and optionally include total review count and average rating for the product from non-deleted reviews only.
 * @path /shoppingMall/products/:productId/reviews
 * @accessor api.functional.shoppingMall.products.reviews.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Unique identifier of the product to retrieve reviews for
     */
    productId: string & tags.Format<"uuid">;

    /**
     * Pagination and search parameters for review listing
     */
    body: IShoppingMallReview.IRequest;
  };
  export type Body = IShoppingMallReview.IRequest;
  export type Response = IPageIShoppingMallReview.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/products/:productId/reviews",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/shoppingMall/products/${encodeURIComponent(props.productId ?? "null")}/reviews`;
  export const random = (): IPageIShoppingMallReview.ISummary =>
    typia.random<IPageIShoppingMallReview.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("productId")(() => typia.assert(props.productId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
