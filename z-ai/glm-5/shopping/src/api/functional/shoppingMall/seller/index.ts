export async function resubmit(
  connection: IConnection,
  props: resubmit.Props,
): Promise<resubmit.Response> {
  return true === connection.simulate
    ? resubmit.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...resubmit.METADATA,
          path: resubmit.path(),
          status: null,
        },
        props.body,
      );
}
