export async function test_api_wishlist_item_cross_customer_access_denied(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create seller and product for wishlist
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {});
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    {},
  );
  typia.assert(product);
  // 2. Create Customer A and add product to their wishlist
  const customerAConnection: api.IConnection = { host: connection.host };
  const customerA = await authorize_customer_join(customerAConnection, {});
  typia.assert(customerA);
  const wishlistItemA =
    await generate_random_shopping_mall_customer_wishlists_items_create(
      customerAConnection,
      {
        body: {
          shopping_mall_product_id: product.id,
        },
      },
    );
  typia.assert(wishlistItemA);
  // 3. Create Customer B (separate account with different email)
  const customerBConnection: api.IConnection = { host: connection.host };
  const customerB = await authorize_customer_join(customerBConnection, {});
  typia.assert(customerB);
  // 4. Verify customers are different
  TestValidator.notEquals(
    "customers have different IDs",
    customerA.id,
    customerB.id,
  );
  // 5. Attempt to retrieve Customer A's wishlist item as Customer B
  await TestValidator.error(
    "customer B cannot access customer A's wishlist item",
    async () => {
      await api.functional.shoppingMall.customer.wishlists.items.at(
        customerBConnection,
        {
          wishlistItemId: wishlistItemA.id,
        },
      );
    },
  );
}
