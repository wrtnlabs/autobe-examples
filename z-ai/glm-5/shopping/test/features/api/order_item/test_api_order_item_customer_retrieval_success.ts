export async function test_api_order_item_customer_retrieval_success(
  connection: api.IConnection,
): Promise<void> {
  // Step 1: Seller setup - create seller, product, and variant
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {});
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    {},
  );
  typia.assert(product);
  const variant =
    await generate_random_shopping_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
      },
    );
  typia.assert(variant);
  // Step 2: Customer setup - create customer, add to cart, and place order
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  // Add variant to cart
  const cartItem =
    await generate_random_shopping_mall_customer_cart_items_create(
      customerConnection,
      {
        body: {
          variant_id: variant.id,
          quantity: 2,
        },
      },
    );
  typia.assert(cartItem);
  // Place order via checkout
  const order = await generate_random_shopping_mall_customer_checkout_create(
    customerConnection,
    {},
  );
  typia.assert(order);
  // Step 3: Retrieve order item
  // NOTE: The checkout endpoint returns IShoppingMallOrder without items.
  // In a complete system, there would be an endpoint to list order items.
  // For this test, we assume we need to get the order item ID somehow.
  // Since there's no list endpoint available, we'll validate the order was created
  // and document that order item retrieval requires a list endpoint.
  // Validate order was created successfully
  TestValidator.predicate("order has valid ID", order.id.length > 0);
  TestValidator.predicate(
    "order has order number",
    order.orderNumber.length > 0,
  );
  TestValidator.equals("order status is paid", order.status, "paid");
  TestValidator.predicate("order has total price", order.totalPrice >= 0);
  // Validate order customer is our authenticated customer
  TestValidator.predicate("order has customer info", order.customer !== null);
  // The order item retrieval test cannot be completed without a list order items endpoint.
  // This test validates the order creation flow and documents the API gap.
  // When a GET /shoppingMall/customer/orders/{orderId}/items endpoint is available,
  // the full retrieval test can be completed.
}
