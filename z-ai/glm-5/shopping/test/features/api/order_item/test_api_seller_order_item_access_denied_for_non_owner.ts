export async function test_api_seller_order_item_access_denied_for_non_owner(
  connection: api.IConnection,
): Promise<void> {
  // 1. Seller A setup - owns the product
  const sellerAConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerAConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      shopName: `Seller A Shop ${RandomGenerator.alphabets(5)}`,
    },
  });
  // 2. Seller A creates product
  const product =
    await generate_random_shopping_mall_seller_seller_products_create(
      sellerAConnection,
      { body: {} },
    );
  typia.assert(product);
  // 3. Seller A creates variant
  const variant =
    await generate_random_shopping_mall_seller_products_variants_create(
      sellerAConnection,
      {
        params: { productId: product.id },
        body: {},
      },
    );
  typia.assert(variant);
  // 4. Customer setup
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    },
  });
  // 5. Customer adds to cart
  const cartItem =
    await generate_random_shopping_mall_customer_customers_cart_items_create(
      customerConnection,
      {
        body: {
          variantId: variant.id,
          quantity: 1,
        },
      },
    );
  typia.assert(cartItem);
  // 6. Customer completes checkout
  const order = await generate_random_shopping_mall_customer_checkout_complete(
    customerConnection,
    { body: {} },
  );
  typia.assert(order);
  // Get order item ID from the created order
  TestValidator.predicate("order has items", order.orderItems.length > 0);
  const orderItem = order.orderItems[0];
  // 7. Seller B setup - does NOT own the product
  const sellerBConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerBConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      shopName: `Seller B Shop ${RandomGenerator.alphabets(5)}`,
    },
  });
  // 8. Seller B attempts to access Seller A's order item - should fail with 403
  await TestValidator.httpError(
    "Seller B cannot access Seller A's order item",
    403,
    async () =>
      await api.functional.shoppingMall.seller.orderItems.at(
        sellerBConnection,
        {
          itemId: orderItem.id,
        },
      ),
  );
}
