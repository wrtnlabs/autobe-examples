export async function test_api_cart_self_purchase_prevention(
  connection: api.IConnection,
): Promise<void> {
  // <E2E TEST CODE HERE>
  // 1. Administrator setup - create admin and category
  const adminConnection: api.IConnection = { host: connection.host };
  const admin = await authorize_administrator_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  typia.assert(admin);
  const category =
    await api.functional.shoppingMall.administrator.categories.create(
      adminConnection,
      {
        body: {
          name: RandomGenerator.name(),
          description: RandomGenerator.paragraph({ sentences: 3 }),
        } satisfies IShoppingMallCategory.ICreate,
      },
    );
  typia.assert(category);
  // 2. Seller setup - create seller account (same email will be used for customer)
  const sellerEmail = typia.random<string & tags.Format<"email">>();
  const sellerPassword = RandomGenerator.alphaNumeric(16);
  const sellerConnection: api.IConnection = { host: connection.host };
  const seller = await authorize_seller_join(sellerConnection, {
    body: {
      email: sellerEmail,
      password: sellerPassword,
      shop_name: RandomGenerator.name(),
      shop_description: RandomGenerator.paragraph({ sentences: 2 }),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  typia.assert(seller);
  // 3. Seller creates product and variant with inventory
  const product = await api.functional.shoppingMall.seller.products.create(
    sellerConnection,
    {
      body: {
        name: RandomGenerator.name(),
        description: RandomGenerator.paragraph({ sentences: 5 }),
        categoryId: category.id,
        basePrice: typia.random<
          number & tags.Type<"uint32"> & tags.Minimum<1000>
        >(),
      } satisfies IShoppingMallProduct.ICreate,
    },
  );
  typia.assert(product);
  const variant =
    await api.functional.shoppingMall.seller.products.variants.create(
      sellerConnection,
      {
        productId: product.id,
        body: {
          skuCode: RandomGenerator.alphaNumeric(10),
          optionValues: {
            color: RandomGenerator.pick(["Red", "Blue", "Green"] as const),
            size: RandomGenerator.pick(["S", "M", "L"] as const),
          },
        } satisfies IShoppingMallProductVariant.ICreate,
      },
    );
  typia.assert(variant);
  // Add positive inventory to make the variant purchasable
  const inventory =
    await api.functional.shoppingMall.seller.variants.inventory_records.create(
      sellerConnection,
      {
        variantId: variant.id,
        body: {
          quantity_change: 100,
          reason: "Initial inventory for self-purchase prevention test",
        } satisfies IShoppingMallInventoryRecord.ICreate,
      },
    );
  typia.assert(inventory);
  // 4. Customer setup - create customer account with SAME email as seller
  const customerConnection: api.IConnection = { host: connection.host };
  const customer = await authorize_customer_join(customerConnection, {
    body: {
      email: sellerEmail, // Same email as seller - this triggers self-purchase prevention
      password: RandomGenerator.alphaNumeric(16),
      displayName: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  typia.assert(customer);
  // Verify the email matches between seller and customer
  TestValidator.equals(
    "seller and customer have same email",
    seller.email,
    customer.email,
  );
  // 5. Self-purchase attempt - customer tries to add their own product variant to cart
  await TestValidator.error(
    "customer cannot add own product to cart",
    async () => {
      await api.functional.shoppingMall.customer.cart.items.create(
        customerConnection,
        {
          body: {
            variant_id: variant.id,
            quantity: 1,
          } satisfies IShoppingMallCartItem.ICreate,
        },
      );
    },
  );
}
