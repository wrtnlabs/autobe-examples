export async function test_api_shipment_delivery_confirmation_already_delivered(
  connection: api.IConnection,
): Promise<void> {
  // Setup: Admin, Seller, Customer
  const adminConnection: api.IConnection = { host: connection.host };
  const adminAuth = await authorize_admin_join(adminConnection, {});
  typia.assert(adminAuth);
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {});
  typia.assert(sellerAuth);
  // Admin approves seller
  await api.functional.shoppingMall.admin.sellers.approve(adminConnection, {
    sellerId: sellerAuth.id,
  });
  // Seller creates product with variant
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    {},
  );
  typia.assert(product);
  const variant =
    await generate_random_shopping_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
        body: {
          stockQuantity: 10,
        },
      },
    );
  typia.assert(variant);
  // Customer joins and places order
  const customerConnection: api.IConnection = { host: connection.host };
  const customerAuth = await authorize_customer_join(customerConnection, {});
  typia.assert(customerAuth);
  await generate_random_shopping_mall_customer_cart_items_create(
    customerConnection,
    {
      body: {
        variantId: variant.id,
        quantity: 1,
      },
    },
  );
  const order = await generate_random_shopping_mall_customer_orders_create(
    customerConnection,
    {},
  );
  typia.assert(order);
  // Seller ships the order
  const shipment =
    await generate_random_shopping_mall_seller_sellers_me_shipments_create(
      sellerConnection,
      {
        body: {
          orderItemIds: [order.orderItems[0].id],
        },
      },
    );
  typia.assert(shipment);
  // First confirmation should succeed
  const confirmedShipment =
    await api.functional.shoppingMall.customer.shipments.confirm_delivery.confirmDelivery(
      customerConnection,
      {
        shipmentId: shipment.id,
      },
    );
  typia.assert(confirmedShipment);
  // Verify first confirmation succeeded
  TestValidator.predicate(
    "delivered_at should be set after first confirmation",
    confirmedShipment.delivered_at !== null,
  );
  TestValidator.equals(
    "delivery_confirmation_method should be manual",
    confirmedShipment.delivery_confirmation_method,
    "manual",
  );
  // Second confirmation should fail
  await TestValidator.error(
    "should reject second delivery confirmation",
    async () => {
      await api.functional.shoppingMall.customer.shipments.confirm_delivery.confirmDelivery(
        customerConnection,
        {
          shipmentId: shipment.id,
        },
      );
    },
  );
}
