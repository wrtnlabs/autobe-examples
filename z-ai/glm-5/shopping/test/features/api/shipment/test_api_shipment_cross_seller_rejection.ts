export async function test_api_shipment_cross_seller_rejection(
  connection: api.IConnection,
): Promise<void> {
  // Step 1: Register and authenticate as Seller A (the seller attempting to ship)
  const sellerAConnection: api.IConnection = { host: connection.host };
  const sellerA = await authorize_seller_join(sellerAConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      shop_name: RandomGenerator.name(1),
    },
  });
  typia.assert(sellerA);
  // Step 2: Register and authenticate as Seller B (another seller)
  const sellerBConnection: api.IConnection = { host: connection.host };
  const sellerB = await authorize_seller_join(sellerBConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      shop_name: RandomGenerator.name(1),
    },
  });
  typia.assert(sellerB);
  // Step 3: Register and authenticate as a customer
  const customerConnection: api.IConnection = { host: connection.host };
  const customer = await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    },
  });
  typia.assert(customer);
  // Step 4: Customer creates a shipping address
  const address = await generate_random_shopping_mall_customer_addresses_create(
    customerConnection,
    {},
  );
  typia.assert(address);
  // Step 5: Customer completes checkout (creates order with order items)
  const order = await generate_random_shopping_mall_customer_checkout_create(
    customerConnection,
    {
      body: {
        address_id: address.id,
      },
    },
  );
  typia.assert(order);
  // Step 6: Attempt to create shipment with cross-seller items
  // Seller A tries to create a shipment, but since Seller A doesn't own any items
  // in this order (or the order items belong to different sellers), this should fail
  const shipmentBody = {
    order_id: order.id,
    order_item_ids: [typia.random<string & tags.Format<"uuid">>()],
    carrier_name: "DHL",
    tracking_number: `DHL${RandomGenerator.alphaNumeric(10)}`,
  } satisfies IShoppingMallShipment.ICreate;
  // Validate that cross-seller shipment creation is rejected with 403 Forbidden
  await TestValidator.httpError(
    "cross-seller shipment should be rejected",
    403,
    async () => {
      await api.functional.shoppingMall.seller.shipments.create(
        sellerAConnection,
        {
          body: shipmentBody,
        },
      );
    },
  );
}
