export async function test_api_order_force_cancel_with_pending_request(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create and authenticate administrator
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_administrator_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    },
  });
  // 2. Create and authenticate customer
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      displayName: RandomGenerator.name(),
      phoneNumber: RandomGenerator.mobile(),
    },
  });
  // 3. Create shipping address for customer
  const address = await generate_random_shopping_mall_customer_addresses_create(
    customerConnection,
    {},
  );
  typia.assert(address);
  // 4. Create order via checkout
  const order = await generate_random_shopping_mall_customer_checkout_create(
    customerConnection,
    {
      body: {
        address_id: address.id,
      },
    },
  );
  typia.assert(order);
  // 5. Verify order was created with paid status
  TestValidator.equals("initial order status is paid", order.status, "paid");
  // 6. Administrator force-cancels the order
  const forceCancelReason =
    "Customer service intervention - dispute resolution";
  const cancelledOrder =
    await api.functional.shoppingMall.administrator.orders.force_cancel.forceCancel(
      adminConnection,
      {
        orderId: order.id,
        body: {
          reason: forceCancelReason,
        } satisfies IShoppingMallOrder.IForceCancel,
      },
    );
  typia.assert(cancelledOrder);
  // 7. Validate order is cancelled
  TestValidator.equals(
    "order status is cancelled",
    cancelledOrder.status,
    "cancelled",
  );
  TestValidator.equals("order ID matches", cancelledOrder.id, order.id);
  TestValidator.equals(
    "order number preserved",
    cancelledOrder.orderNumber,
    order.orderNumber,
  );
  TestValidator.predicate(
    "total price preserved",
    cancelledOrder.totalPrice === order.totalPrice,
  );
  TestValidator.equals(
    "customer preserved",
    cancelledOrder.customer?.id,
    order.customer?.id,
  );
}
