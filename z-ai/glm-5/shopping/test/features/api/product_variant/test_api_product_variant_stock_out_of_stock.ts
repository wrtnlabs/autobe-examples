export async function test_api_product_variant_stock_out_of_stock(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create and authenticate seller
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {});
  // 2. Create a product
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    {},
  );
  typia.assert(product);
  // 3. Create a variant for the product (starts with 0 stock)
  const variant =
    await generate_random_shopping_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: {
          productId: product.id,
        },
      },
    );
  typia.assert(variant);
  // 4. Retrieve stock information for the variant
  const stock = await api.functional.shoppingMall.seller.variants.stock.at(
    sellerConnection,
    {
      variantId: variant.id,
    },
  );
  typia.assert(stock);
  // 5. Validate response
  TestValidator.equals("variant id matches", stock.id, variant.id);
  TestValidator.equals("sku code matches", stock.skuCode, variant.skuCode);
  TestValidator.equals(
    "option values match",
    stock.optionValues,
    variant.optionValues,
  );
  TestValidator.equals("stock quantity is zero", stock.stockQuantity, 0);
  TestValidator.equals(
    "availability is out_of_stock",
    stock.availability,
    "out_of_stock",
  );
}
