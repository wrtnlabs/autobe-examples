export async function test_api_order_items_unauthorized_access_denied(
  connection: api.IConnection,
): Promise<void> {
  // Step 1: Customer A registers and authenticates
  const customerAConnection: api.IConnection = { host: connection.host };
  const customerA = await authorize_customer_join(customerAConnection, {});
  typia.assert(customerA);
  // Step 2: Customer B registers and authenticates (attacker)
  const customerBConnection: api.IConnection = { host: connection.host };
  const customerB = await authorize_customer_join(customerBConnection, {});
  typia.assert(customerB);
  // Step 3: Use a random orderId (representing Customer A's hypothetical order)
  const targetOrderId = typia.random<string & tags.Format<"uuid">>();
  // Step 4: Customer B attempts to access Customer A's order items
  // Expected: System denies access (either 403 Forbidden or 404 Not Found)
  await TestValidator.error(
    "unauthorized access to another customer's order items",
    async () => {
      await api.functional.shoppingMall.customer.orders.items.index(
        customerBConnection,
        {
          orderId: targetOrderId,
          body: {} satisfies IShoppingMallOrderItem.IRequest,
        },
      );
    },
  );
}
