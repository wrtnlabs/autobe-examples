export async function test_api_wishlist_item_removal_success(
  connection: api.IConnection,
): Promise<void> {
  // 1. Administrator setup - create category
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_administrator_join(adminConnection, {});
  const category =
    await generate_random_shopping_mall_administrator_categories_create(
      adminConnection,
      {},
    );
  typia.assert(category);
  // 2. Seller setup - create product
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {});
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        name: RandomGenerator.name(),
        description: RandomGenerator.paragraph({ sentences: 5 }),
        categoryId: category.id,
        basePrice: typia.random<
          number & tags.Type<"uint32"> & tags.Minimum<1000>
        >(),
      },
    },
  );
  typia.assert(product);
  // 3. Customer setup - add product to wishlist
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  const wishlistItem =
    await generate_random_shopping_mall_customer_wishlists_items_create(
      customerConnection,
      {
        body: {
          shopping_mall_product_id: product.id,
        },
      },
    );
  typia.assert(wishlistItem);
  // 4. Store the wishlist item ID for deletion
  const wishlistItemId = wishlistItem.id;
  // 5. Delete the wishlist item
  await api.functional.shoppingMall.customer.wishlists.items.erase(
    customerConnection,
    {
      wishlistItemId,
    },
  );
  // 6. Verify deletion - attempting to delete again should fail
  await TestValidator.error(
    "deleting already deleted wishlist item should fail",
    async () => {
      await api.functional.shoppingMall.customer.wishlists.items.erase(
        customerConnection,
        {
          wishlistItemId,
        },
      );
    },
  );
}
