export async function test_api_product_deletion_success_no_pending_orders(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin setup - create admin and category
  const adminConnection: api.IConnection = { host: connection.host };
  const adminAuth = await authorize_admin_join(adminConnection, {});
  typia.assert(adminAuth);
  const category = await generate_random_shopping_mall_admin_categories_create(
    adminConnection,
    {},
  );
  typia.assert(category);
  // 2. Seller registration
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {
    body: {
      shop_name: RandomGenerator.name(),
    },
  });
  typia.assert(sellerAuth);
  TestValidator.equals(
    "seller initial status",
    sellerAuth.approvalStatus,
    "pending",
  );
  // 3. Admin approves the seller
  const approvedSeller =
    await api.functional.shoppingMall.admin.sellers.approve(adminConnection, {
      sellerId: sellerAuth.id,
    });
  typia.assert(approvedSeller);
  TestValidator.equals(
    "seller approved status",
    approvedSeller.approvalStatus,
    "approved",
  );
  // 4. Seller creates a product
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        name: RandomGenerator.name(),
        description: RandomGenerator.paragraph({ sentences: 5 }),
        base_price: typia.random<
          number & tags.Type<"uint32"> & tags.Minimum<1000>
        >(),
        category_id: category.id,
      },
    },
  );
  typia.assert(product);
  TestValidator.equals(
    "product seller matches",
    product.seller.id,
    sellerAuth.id,
  );
  TestValidator.predicate("product has valid id", product.id.length > 0);
  // 5. Seller deletes the product (no pending orders)
  await api.functional.shoppingMall.seller.sellers.me.products.erase(
    sellerConnection,
    { productId: product.id },
  );
  // 6. Deletion completed successfully - void response indicates success
}
