/**
 * Test that administrators can erase products even when pending orders exist.
 *
 * This test verifies the admin's governance authority to remove products from the
 * platform regardless of pending transactions. Unlike seller-initiated deletion
 * which may be blocked by active orders, administrators can enforce policy compliance.
 *
 * Setup: Create category, product with variant, inventory, and customer cart items
 * Execution: Administrator submits DELETE request with policy violation reason
 * Validation: Deletion succeeds with 204 No Content, product is soft-deleted
 */
export async function test_api_product_erasure_with_pending_orders(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create administrator connection for governance authority
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_administrator_join(adminConnection, {});
  // 2. Create category for product assignment
  const category =
    await generate_random_shopping_mall_administrator_categories_create(
      adminConnection,
      {},
    );
  typia.assert(category);
  // 3. Create seller connection for product management
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {
    body: { shopName: RandomGenerator.name() },
  });
  // 4. Create product that will be subject to administrative erasure
  const product =
    await generate_random_shopping_mall_seller_seller_products_create(
      sellerConnection,
      { body: { categoryId: category.id } },
    );
  typia.assert(product);
  // 5. Create variant for the product to enable ordering
  const variant =
    await generate_random_shopping_mall_seller_products_variants_create(
      sellerConnection,
      { params: { productId: product.id } },
    );
  typia.assert(variant);
  // 6. Add inventory to the variant for order fulfillment
  const inventory =
    await generate_random_shopping_mall_seller_variants_inventory_adjust(
      sellerConnection,
      {
        params: { variantId: variant.id },
        body: {
          quantity_change: 100,
          reason: "Initial stock for order fulfillment",
        },
      },
    );
  typia.assert(inventory);
  // 7. Create customer and add to cart (simulating pending purchase intent)
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  const cartItem =
    await generate_random_shopping_mall_customer_customers_cart_items_create(
      customerConnection,
      {
        body: {
          variantId: variant.id,
          quantity: 1,
        },
      },
    );
  typia.assert(cartItem);
  // 8. Administrator erases the product with governance authority
  // This demonstrates that admin can remove products even with pending cart items
  const eraseReason = {
    reason: "Emergency removal - product found to contain prohibited content",
  } satisfies IShoppingMallProduct.IErase;
  await api.functional.shoppingMall.seller.products.erase(adminConnection, {
    productId: product.id,
    body: eraseReason,
  });
  // Success: Erase completed without error (204 No Content)
  // Product and variants are soft-deleted by the system
  // Order history and snapshots are preserved for audit purposes
}
