export async function test_api_cart_item_quantity_boundary_max(
  connection: api.IConnection,
): Promise<void> {
  // 1. Setup admin and approve seller
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  // 2. Create seller account
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {
    body: {
      shop_name: RandomGenerator.name(),
    },
  });
  // 3. Admin approves the seller
  const approvedSeller =
    await api.functional.shoppingMall.admin.sellers.approve(adminConnection, {
      sellerId: sellerAuth.id,
    });
  typia.assert(approvedSeller);
  // 4. Seller creates a product
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    {},
  );
  typia.assert(product);
  // 5. Seller creates a variant with sufficient stock (at least 99 units)
  const variant =
    await generate_random_shopping_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
        body: {
          stockQuantity: 100,
        },
      },
    );
  typia.assert(variant);
  // 6. Create customer and add variant to cart
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  const cartItem =
    await generate_random_shopping_mall_customer_cart_items_create(
      customerConnection,
      {
        body: {
          variantId: variant.id,
          quantity: 1,
        },
      },
    );
  typia.assert(cartItem);
  // 7. Test: Update quantity to maximum allowed value (99)
  const maxQuantity = 99;
  const updatedItem = await api.functional.shoppingMall.customer.cart.update(
    customerConnection,
    {
      cartItemId: cartItem.id,
      body: { quantity: maxQuantity } satisfies IShoppingMallCartItem.IUpdate,
    },
  );
  typia.assert(updatedItem);
  TestValidator.equals(
    "quantity updated to max",
    updatedItem.quantity,
    maxQuantity,
  );
  // 8. Test: Attempt to update to 100 (above maximum) should fail
  await TestValidator.error("quantity above maximum should fail", async () => {
    await api.functional.shoppingMall.customer.cart.update(customerConnection, {
      cartItemId: cartItem.id,
      body: { quantity: 100 } satisfies IShoppingMallCartItem.IUpdate,
    });
  });
}
