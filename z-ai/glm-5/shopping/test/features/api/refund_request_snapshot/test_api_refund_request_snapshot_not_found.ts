/**
 * Test refund request snapshot retrieval with non-existent ID.
 *
 * An administrator attempts to retrieve a refund request snapshot that does not exist
 * in the system. This validates proper error handling when an invalid snapshot ID is
 * provided. The system should return a 404 Not Found response with an appropriate error
 * message. This test ensures the administrator receives clear feedback when attempting
 * to access non-existent audit records.
 */
export async function test_api_refund_request_snapshot_not_found(
  connection: api.IConnection,
): Promise<void> {
  // 1. Administrator authentication
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_administrator_join(adminConnection, {});
  // 2. Generate a non-existent UUID for snapshot ID
  const nonExistentSnapshotId = typia.random<string & tags.Format<"uuid">>();
  // 3. Attempt to retrieve non-existent snapshot - should throw error
  await TestValidator.error("snapshot not found", async () => {
    await api.functional.shoppingMall.administrator.refund_request_snapshots.at(
      adminConnection,
      { snapshotId: nonExistentSnapshotId },
    );
  });
}
