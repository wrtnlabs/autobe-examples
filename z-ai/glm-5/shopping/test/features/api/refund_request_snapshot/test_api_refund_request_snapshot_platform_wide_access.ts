export async function test_api_refund_request_snapshot_platform_wide_access(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as administrator
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_administrator_join(adminConnection, {});
  // 2. Call endpoint with default pagination (no filters)
  const response =
    await api.functional.shoppingMall.administrator.refund_request_snapshots.index(
      adminConnection,
      {
        body: {} satisfies IShoppingMallRefundRequestSnapshot.IRequest,
      },
    );
  typia.assert(response);
  // 3. Validate business logic: snapshots sorted by created_at descending
  if (response.data.length > 1) {
    for (let i = 0; i < response.data.length - 1; i++) {
      const current = new Date(response.data[i].created_at).getTime();
      const next = new Date(response.data[i + 1].created_at).getTime();
      TestValidator.predicate(
        "snapshots sorted by created_at descending",
        current >= next,
      );
    }
  }
}
