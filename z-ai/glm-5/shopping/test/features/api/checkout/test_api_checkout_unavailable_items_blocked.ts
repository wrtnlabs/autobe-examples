export async function test_api_checkout_unavailable_items_blocked(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate seller and create product with variant
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {});
  const product =
    await generate_random_shopping_mall_seller_seller_products_create(
      sellerConnection,
      {},
    );
  typia.assert(product);
  const variant =
    await generate_random_shopping_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
      },
    );
  typia.assert(variant);
  // 2. Add initial inventory (quantity = 1)
  await generate_random_shopping_mall_seller_variants_inventory_adjust(
    sellerConnection,
    {
      params: { variantId: variant.id },
      body: {
        quantity_change: 1,
        reason: "Initial stock",
      },
    },
  );
  // 3. Authenticate customer
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  // 4. Add variant to customer's cart
  const cartItem =
    await generate_random_shopping_mall_customer_customers_cart_items_create(
      customerConnection,
      {
        body: {
          variantId: variant.id,
          quantity: 1,
        },
      },
    );
  typia.assert(cartItem);
  // 5. Create shipping address
  const address = await generate_random_shopping_mall_customer_addresses_create(
    customerConnection,
    {},
  );
  typia.assert(address);
  // 6. Deplete inventory to 0
  await generate_random_shopping_mall_seller_variants_inventory_adjust(
    sellerConnection,
    {
      params: { variantId: variant.id },
      body: {
        quantity_change: -1,
        reason: "Stock depletion for testing",
      },
    },
  );
  // 7. Attempt checkout - should fail with unavailable items
  await TestValidator.error(
    "checkout should fail with unavailable items",
    async () =>
      await api.functional.shoppingMall.customer.checkout.create(
        customerConnection,
        {
          body: {
            addressId: address.id,
          } satisfies IShoppingMallOrder.ICreate,
        },
      ),
  );
}
