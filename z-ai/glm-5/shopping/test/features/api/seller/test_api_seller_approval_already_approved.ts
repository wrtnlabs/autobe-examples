export async function test_api_seller_approval_already_approved(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin authentication
  const adminConnection: api.IConnection = { host: connection.host };
  const adminAuth = await authorize_admin_join(adminConnection, {});
  typia.assert(adminAuth);
  // 2. Create a new seller with pending status
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {});
  typia.assert(sellerAuth);
  // Verify seller has pending status
  TestValidator.equals(
    "seller initial status",
    sellerAuth.approvalStatus,
    "pending",
  );
  // 3. First approval should succeed
  const approvedSeller =
    await api.functional.shoppingMall.admin.sellers.approve(adminConnection, {
      sellerId: sellerAuth.id,
    });
  typia.assert(approvedSeller);
  // Verify seller is now approved
  TestValidator.equals(
    "seller approved status",
    approvedSeller.approvalStatus,
    "approved",
  );
  // 4. Second approval should fail with error
  await TestValidator.error(
    "cannot approve already approved seller",
    async () => {
      await api.functional.shoppingMall.admin.sellers.approve(adminConnection, {
        sellerId: sellerAuth.id,
      });
    },
  );
}
