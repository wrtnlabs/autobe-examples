/**
 * Test successful creation of a cancellation request for an order item with 'paid' status.
 *
 * This test validates the complete workflow:
 * 1. Administrator creates a product category
 * 2. Approved seller creates product with variant and inventory
 * 3. Customer places order (items have 'paid' status)
 * 4. Customer requests cancellation for an order item
 * 5. System creates pending cancellation request
 */
export async function test_api_order_item_cancellation_request_success(
  connection: api.IConnection,
): Promise<void> {
  // Step 1: Administrator setup and category creation
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_administrator_join(adminConnection, {});
  const category =
    await generate_random_shopping_mall_administrator_categories_create(
      adminConnection,
      {},
    );
  typia.assert(category);
  // Step 2: Seller setup (seller join automatically sets approval_status)
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {});
  // Step 3: Seller creates product
  const product =
    await generate_random_shopping_mall_seller_seller_products_create(
      sellerConnection,
      {
        body: {
          name: RandomGenerator.name(2),
          description: RandomGenerator.paragraph({ sentences: 5 }),
          categoryId: category.id,
          basePrice: typia.random<
            number & tags.Minimum<1000> & tags.Maximum<100000>
          >(),
        },
      },
    );
  typia.assert(product);
  // Step 4: Seller creates variant
  const variant =
    await generate_random_shopping_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
        body: {
          sku_code: RandomGenerator.alphaNumeric(8).toUpperCase(),
          option_values: { color: "Blue", size: "Medium" },
          price: null,
        },
      },
    );
  typia.assert(variant);
  // Step 5: Seller adds inventory
  const inventory =
    await generate_random_shopping_mall_seller_variants_inventory_adjust(
      sellerConnection,
      {
        params: { variantId: variant.id },
        body: {
          quantity_change: 100,
          reason: "Initial stock for test",
        },
      },
    );
  typia.assert(inventory);
  // Step 6: Customer setup
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  // Step 7: Customer adds item to cart
  const cartItem =
    await generate_random_shopping_mall_customer_customers_cart_items_create(
      customerConnection,
      {
        body: {
          variantId: variant.id,
          quantity: typia.random<
            number & tags.Type<"uint32"> & tags.Minimum<1> & tags.Maximum<5>
          >(),
        },
      },
    );
  typia.assert(cartItem);
  // Step 8: Customer completes checkout
  // Note: Using utility function which handles order creation
  const order = await generate_random_shopping_mall_customer_checkout_complete(
    customerConnection,
    {
      body: {
        addressId: typia.random<string & tags.Format<"uuid">>(),
      },
    },
  );
  typia.assert(order);
  // Validate order was created with items
  TestValidator.predicate("order has items", order.orderItems.length > 0);
  // Get the first order item for cancellation request
  const orderItem = order.orderItems[0];
  typia.assert(orderItem);
  TestValidator.equals("order item status", orderItem.status, "paid");
  // Step 9: Customer creates cancellation request
  const cancellationReason = RandomGenerator.paragraph({ sentences: 2 });
  const cancellationRequest =
    await generate_random_shopping_mall_customer_customers_orders_items_cancellation_request_request(
      customerConnection,
      {
        params: {
          orderId: order.id,
          itemId: orderItem.id,
        },
        body: {
          reason: cancellationReason,
        },
      },
    );
  typia.assert(cancellationRequest);
  // Step 10: Validate cancellation request
  TestValidator.equals(
    "status is pending",
    cancellationRequest.status,
    "pending",
  );
  TestValidator.equals(
    "reason matches",
    cancellationRequest.reason,
    cancellationReason,
  );
  TestValidator.equals(
    "orderItem id matches",
    cancellationRequest.orderItem.id,
    orderItem.id,
  );
  TestValidator.predicate(
    "seller is null",
    cancellationRequest.seller === null,
  );
}
