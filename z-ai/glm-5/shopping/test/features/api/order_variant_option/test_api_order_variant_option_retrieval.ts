export async function test_api_order_variant_option_retrieval(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create seller and get approved
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {});
  typia.assert(sellerAuth);
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  const approvedSeller =
    await api.functional.shoppingMall.admin.sellers.approve(adminConnection, {
      sellerId: sellerAuth.id,
    });
  typia.assert(approvedSeller);
  // 2. Seller creates product with variant options
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    {},
  );
  typia.assert(product);
  const variant =
    await generate_random_shopping_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
        body: {
          optionValues: [
            { key: "color", value: "Red" },
            { key: "size", value: "Large" },
          ],
          stockQuantity: 100,
        },
      },
    );
  typia.assert(variant);
  // 3. Customer places order
  const customerConnection: api.IConnection = { host: connection.host };
  const customerAuth = await authorize_customer_join(customerConnection, {});
  typia.assert(customerAuth);
  const order = await generate_random_shopping_mall_customer_orders_create(
    customerConnection,
    {},
  );
  typia.assert(order);
  // 4. Retrieve variant option from order item
  const orderItem = order.orderItems[0];
  const variantOption = orderItem.variantOptions[0];
  const retrievedOption =
    await api.functional.shoppingMall.customer.orders.items.variant_options.at(
      customerConnection,
      {
        orderId: order.id,
        orderItemId: orderItem.id,
        optionId: variantOption.id,
      },
    );
  typia.assert(retrievedOption);
  // 5. Validate variant option data matches snapshot
  TestValidator.equals(
    "variant option key",
    retrievedOption.key,
    variantOption.key,
  );
  TestValidator.equals(
    "variant option value",
    retrievedOption.value,
    variantOption.value,
  );
  TestValidator.equals(
    "variant option id",
    retrievedOption.id,
    variantOption.id,
  );
}
