export async function test_api_review_deletion_by_author(
  connection: api.IConnection,
): Promise<void> {
  // 1. Seller setup - register and authenticate seller
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {});
  typia.assert(sellerAuth);
  // 2. Create product (generate function handles category internally)
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    {},
  );
  typia.assert(product);
  // 3. Create product variant for the product
  const variant =
    await generate_random_shopping_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
      },
    );
  typia.assert(variant);
  // 4. Add inventory to the variant to make it purchasable
  const inventoryRecord =
    await generate_random_shopping_mall_seller_variants_inventory_records_create(
      sellerConnection,
      {
        params: { variantId: variant.id },
        body: {
          quantity_change: 100,
          reason: "Initial inventory for review deletion test",
        },
      },
    );
  typia.assert(inventoryRecord);
  // 5. Customer setup - register and authenticate customer
  const customerConnection: api.IConnection = { host: connection.host };
  const customerAuth = await authorize_customer_join(customerConnection, {});
  typia.assert(customerAuth);
  // 6. Create shipping address for customer
  const address = await generate_random_shopping_mall_customer_addresses_create(
    customerConnection,
    {},
  );
  typia.assert(address);
  // 7. Add product variant to cart
  const cartItem =
    await generate_random_shopping_mall_customer_cart_items_create(
      customerConnection,
      {
        body: {
          variant_id: variant.id,
          quantity: 1,
        },
      },
    );
  typia.assert(cartItem);
  // 8. Checkout to create order
  const order = await generate_random_shopping_mall_customer_checkout_create(
    customerConnection,
    {
      body: {
        address_id: address.id,
      },
    },
  );
  typia.assert(order);
  // 9. Seller creates shipment for the order
  // The shipment generation needs order_id and order_item_ids
  // We use the order ID and let the generate function handle order_item_ids
  const shipmentBody: IShoppingMallShipment.ICreate = {
    order_id: order.id,
    order_item_ids: [], // Will be populated by generate function
    carrier_name: "Test Carrier",
    tracking_number: RandomGenerator.alphaNumeric(12),
  };
  const shipment = await generate_random_shopping_mall_seller_shipments_create(
    sellerConnection,
    {
      body: shipmentBody,
    },
  );
  typia.assert(shipment);
  // Get order item IDs from shipment for delivery confirmation
  const orderItemIds = shipment.orderItems.map((item) => item.id);
  // 10. Customer confirms delivery of the shipment
  const confirmedShipment =
    await api.functional.shoppingMall.customer.shipments.delivery.confirmDelivery(
      customerConnection,
      {
        shipmentId: shipment.id,
      },
    );
  typia.assert(confirmedShipment);
  // 11. Customer creates review for the delivered product
  const review = await generate_random_shopping_mall_customer_reviews_create(
    customerConnection,
    {
      body: {
        shopping_mall_product_id: product.id,
        shopping_mall_order_id: order.id,
        rating: typia.random<
          number & tags.Type<"int32"> & tags.Minimum<1> & tags.Maximum<5>
        >(),
        content: RandomGenerator.paragraph({ sentences: 3 }),
      },
    },
  );
  typia.assert(review);
  // 12. Verify review was created successfully
  TestValidator.equals("review product matches", review.product.id, product.id);
  TestValidator.equals("review order matches", review.order.id, order.id);
  TestValidator.predicate(
    "review rating is valid",
    review.rating >= 1 && review.rating <= 5,
  );
  // 13. Customer deletes the review (the main operation being tested)
  await api.functional.shoppingMall.customer.reviews.erase(customerConnection, {
    reviewId: review.id,
  });
  // 14. Verify deletion succeeded by attempting to create another review for the same product/order
  // (Since deleted reviews shouldn't prevent new reviews)
  const newReview = await generate_random_shopping_mall_customer_reviews_create(
    customerConnection,
    {
      body: {
        shopping_mall_product_id: product.id,
        shopping_mall_order_id: order.id,
        rating: typia.random<
          number & tags.Type<"int32"> & tags.Minimum<1> & tags.Maximum<5>
        >(),
        content: RandomGenerator.paragraph({ sentences: 2 }),
      },
    },
  );
  typia.assert(newReview);
  TestValidator.notEquals(
    "new review has different ID",
    review.id,
    newReview.id,
  );
}
