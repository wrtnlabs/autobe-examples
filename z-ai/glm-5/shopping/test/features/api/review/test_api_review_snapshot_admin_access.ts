export async function test_api_review_snapshot_admin_access(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create and approve seller
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {});
  typia.assert(sellerAuth);
  // Create admin to approve seller
  const adminConnection: api.IConnection = { host: connection.host };
  const adminAuth = await authorize_admin_join(adminConnection, {});
  typia.assert(adminAuth);
  // Approve the seller
  const approvedSeller =
    await api.functional.shoppingMall.admin.sellers.approve(adminConnection, {
      sellerId: sellerAuth.id,
    });
  typia.assert(approvedSeller);
  // 2. Create product and variant
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    {},
  );
  typia.assert(product);
  const variant =
    await generate_random_shopping_mall_seller_products_variants_create(
      sellerConnection,
      { params: { productId: product.id } },
    );
  typia.assert(variant);
  // Add inventory
  const inventory =
    await generate_random_shopping_mall_seller_sellers_me_variants_inventory_add_add_inventory(
      sellerConnection,
      {
        params: { variantId: variant.id },
        body: { quantity: 100, reason: "Initial stock for testing" },
      },
    );
  typia.assert(inventory);
  // 3. Create customer
  const customerConnection: api.IConnection = { host: connection.host };
  const customerAuth = await authorize_customer_join(customerConnection, {});
  typia.assert(customerAuth);
  // 4. Add to cart
  const cartItem =
    await generate_random_shopping_mall_customer_cart_items_create(
      customerConnection,
      { body: { variantId: variant.id, quantity: 1 } },
    );
  typia.assert(cartItem);
  // 5. Place order
  const order = await generate_random_shopping_mall_customer_orders_create(
    customerConnection,
    {},
  );
  typia.assert(order);
  // 6. Create review (after order is delivered - using order from above)
  const review =
    await generate_random_shopping_mall_customer_customers_me_reviews_create(
      customerConnection,
      {
        body: {
          product_id: product.id,
          order_id: order.id,
          rating: 2,
          content: "Disappointing quality",
        },
      },
    );
  typia.assert(review);
  // 7. Edit review to create snapshot
  const updatedReview =
    await api.functional.shoppingMall.customer.reviews.update(
      customerConnection,
      {
        reviewId: review.id,
        body: {
          rating: 1,
          content: "Very poor quality, requested refund",
        } satisfies IShoppingMallReview.IUpdate,
      },
    );
  typia.assert(updatedReview);
  // 8. Admin accesses review snapshots (admin has elevated access to any review)
  const snapshots =
    await api.functional.shoppingMall.customer.reviews.snapshots.index(
      adminConnection,
      {
        reviewId: review.id,
        body: {
          limit: 10,
          page: 1,
        } satisfies IShoppingMallReviewSnapshot.IRequest,
      },
    );
  typia.assert(snapshots);
  // 9. Validate admin can access and snapshots show correct history
  TestValidator.predicate(
    "admin can access review snapshots",
    snapshots.data.length > 0,
  );
  const snapshot = snapshots.data[0];
  TestValidator.equals("previous rating is 2", snapshot.previousRating, 2);
  TestValidator.equals("new rating is 1", snapshot.newRating, 1);
  TestValidator.equals(
    "previous content",
    snapshot.previousContent,
    "Disappointing quality",
  );
  TestValidator.equals(
    "new content",
    snapshot.newContent,
    "Very poor quality, requested refund",
  );
}
