/**
 * Test successful review deletion by the review owner.
 *
 * This test validates the core business workflow:
 * 1. Customer creates a review for a delivered product
 * 2. Customer deletes their own review via DELETE /reviews/{reviewId}
 * 3. Deletion succeeds (returns void without error)
 * 4. Second deletion attempt fails (review already deleted)
 */
export async function test_api_review_deletion_by_owner_success(
  connection: api.IConnection,
): Promise<void> {
  // 1. Customer joins the platform
  const customerConnection: api.IConnection = { host: connection.host };
  const customer = await authorize_customer_join(customerConnection, {});
  typia.assert(customer);
  // 2. Seller joins the platform
  const sellerConnection: api.IConnection = { host: connection.host };
  const seller = await authorize_seller_join(sellerConnection, {});
  typia.assert(seller);
  // 3. Seller creates a product
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    {},
  );
  typia.assert(product);
  // 4. Customer places an order
  const order = await generate_random_shopping_mall_customer_orders_create(
    customerConnection,
    {},
  );
  typia.assert(order);
  // 5. Customer creates a review for the delivered product
  const review =
    await generate_random_shopping_mall_customer_customers_me_reviews_create(
      customerConnection,
      {
        body: {
          product_id: product.id,
          order_id: order.id,
        },
      },
    );
  typia.assert(review);
  // 6. Customer deletes their own review - this should succeed
  await api.functional.shoppingMall.customer.reviews.erase(customerConnection, {
    reviewId: review.id,
  });
  // 7. Verify deletion - second attempt should fail
  await TestValidator.error("review already deleted", async () => {
    await api.functional.shoppingMall.customer.reviews.erase(
      customerConnection,
      { reviewId: review.id },
    );
  });
}
