import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchTodoUserUsersUserIdSessions } from "../../../../../providers/patchTodoUserUsersUserIdSessions";
import { UserAuth } from "../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../decorators/payload/UserPayload";
import { getTodoUserUsersUserIdSessionsSessionId } from "../../../../../providers/getTodoUserUsersUserIdSessionsSessionId";
import { deleteTodoUserUsersUserIdSessionsSessionId } from "../../../../../providers/deleteTodoUserUsersUserIdSessionsSessionId";

import { IPageITodoUserSession } from "../../../../../api/structures/IPageITodoUserSession";
import { ITodoUserSession } from "../../../../../api/structures/ITodoUserSession";

@Controller("/todo/user/users/:userId/sessions")
export class TodoUserUsersSessionsController {
  /**
   * Search and retrieve a paginated list of authentication sessions for a user
   * (todo_user_sessions table).
   *
   * Retrieve a paginated and filterable list of authentication sessions for a
   * given user within the Todo List application.
   *
   * This operation enables detailed forensic examination or security audits of
   * user sessions, providing context such as IP address, login location,
   * referrer, and session duration for each authentication event. Advanced
   * search parameters allow location of session records by date range,
   * originating client, or referrer URLs.
   *
   * All sessions are strictly tied to a user, with queries filtered by
   * todo_users.id. Only users with the necessary permissions may access this
   * endpoint. This read-only endpoint does not allow session creation, update,
   * or deletion, reflecting strict business controls.
   *
   * @param connection
   * @param userId Unique identifier of the target user whose sessions are being
   *   retrieved (UUID as per todo_users.id)
   * @param body Advanced search, filtering, and pagination criteria for
   *   sessions belonging to the indicated user
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoUserSession.IRequest,
  ): Promise<IPageITodoUserSession.ISummary> {
    try {
      return await patchTodoUserUsersUserIdSessions({
        user,
        userId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed data of a specific authentication session for a user
   * (todo_user_sessions table).
   *
   * Retrieve the full technical and business details for a single
   * authentication session belonging to a given user in the Todo List
   * application.
   *
   * This operation is designed for security, compliance, and forensic analysis,
   * returning all session-related fields including connection context, creation
   * and (if expired) expiration time, user association, and audit metadata.
   * Session establishment or termination is managed by privileged
   * authentication flows, not by this API.
   *
   * Both path parameters must match (userId for parent user, sessionId for
   * session record), with comprehensive access controls enforced for privacy
   * reasons. This endpoint cannot be used to edit or delete session data.
   *
   * @param connection
   * @param userId Unique identifier of the parent user for this session (UUID
   *   as per todo_users.id)
   * @param sessionId Unique session identifier of the authentication session
   *   record (UUID as per todo_user_sessions.id)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<ITodoUserSession> {
    try {
      return await getTodoUserUsersUserIdSessionsSessionId({
        user,
        userId,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Remove an authenticated user's session (logout) in the 'todo_user_sessions'
   * table by sessionId and userId.
   *
   * Delete a single user session, terminating the current authenticated context
   * for the requesting user.
   *
   * This API operation requires both the user ID and the session ID as path
   * parameters. It ensures that only the user who owns the session can delete
   * (invalidate) their own session, following strict ownership and isolation
   * rules for security. If the provided IDs do not correspond to a valid
   * session owned by the user, the operation returns a clear error indicating
   * unauthorized access or resource not found.
   *
   * No request body is required. The operation permanently removes the session
   * from the database (no soft-deletion); once deleted, all further API
   * requests using this session are immediately denied. This supports secure
   * logout flows and session management, in full compliance with requirements
   * for user isolation and auditability.
   *
   * This operation is related to session management features, and pairs with
   * provider logic to revoke tokens and log authentication events. Other API
   * endpoints requiring authentication must always verify session validity.
   *
   * @param connection
   * @param userId Unique identifier of the user who owns the session (must
   *   match the authenticated user).
   * @param sessionId Unique identifier of the session to be deleted (from
   *   'todo_user_sessions' table).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":sessionId")
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoUserUsersUserIdSessionsSessionId({
        user,
        userId,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
