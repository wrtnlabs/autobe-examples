import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchTodoUserUsers } from "../../../../providers/patchTodoUserUsers";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { getTodoUserUsersUserId } from "../../../../providers/getTodoUserUsersUserId";
import { putTodoUserUsersUserId } from "../../../../providers/putTodoUserUsersUserId";
import { deleteTodoUserUsersUserId } from "../../../../providers/deleteTodoUserUsersUserId";

import { IPageITodoUser } from "../../../../api/structures/IPageITodoUser";
import { ITodoUser } from "../../../../api/structures/ITodoUser";

@Controller("/todo/user/users")
export class TodoUserUsersController {
  /**
   * Search and retrieve a paginated, filtered list of registered users for the
   * Todo List application.
   *
   * This operation supports searching by user email, sign-up timestamp, and
   * last update time. It delivers summary data—sufficient for building
   * administrative tables, analytics dashboards, or audit reports. Pagination
   * and sorting options are available by default, following standard
   * summary-list conventions.
   *
   * No user passwords are ever exposed in the results, maintaining privacy and
   * security guarantees as described in the schema. By returning only summary
   * fields, sensitive details are protected. Rate-limiting and query complexity
   * restrictions should be enforced to maintain service stability.
   *
   * @param connection
   * @param body Request body for filtering, sorting, and paginating the user
   *   list.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoUser.IRequest,
  ): Promise<IPageITodoUser.ISummary> {
    try {
      return await patchTodoUserUsers({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve the detailed account record for a specific user by their unique
   * identifier.
   *
   * This operation returns full, non-sensitive user information—such as email
   * address and account creation timestamps—based on the uuid. Used for
   * displaying the profile details to the user themselves (for personal account
   * management) or by system administrators (for managing users and resolving
   * support requests).
   *
   * Only registered users with authorization may access user data; strict
   * checks ensure that users cannot see or access data for other users. Only
   * the user themselves or privileged staff can view these records, in
   * accordance with access control rules described in the schema.
   *
   * @param connection
   * @param userId Unique identifier (UUID) of the user to retrieve (from
   *   todo_users).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":userId")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
  ): Promise<ITodoUser> {
    try {
      return await getTodoUserUsersUserId({
        user,
        userId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update the account information of an existing user in the Todo List system
   * using their unique identifier. This operation gives authorized clients the
   * ability to change the email address and/or password of a user, provided all
   * new values meet schema constraints and uniqueness requirements for email
   * addresses.
   *
   * The todo_users table enforces that every email in the system is unique, so
   * attempting to update a user's email to one already in use will result in a
   * validation error. Similarly, passwords are handled securely, and must be
   * updated as cryptographically strong hashes; the system never allows or
   * stores plain-text passwords.
   *
   * Modifications to a user's information trigger an update to the `updated_at`
   * timestamp, providing an accurate history of changes. Only the specified
   * fields are changed in each update, while all other user data remains
   * unaltered. If the user ID does not exist, an appropriate error is returned.
   * This operation is essential for supporting profile editing and account
   * recovery features in compliance with the underlying schema's security and
   * uniqueness rules.
   *
   * @param connection
   * @param userId Unique identifier of the target user. Must be a valid UUID as
   *   defined in the todo_users schema.
   * @param body Fields and updated values for the specified user account. All
   *   schema constraints—such as unique email and secure hashed passwords—are
   *   enforced.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":userId")
  public async update(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoUser.IUpdate,
  ): Promise<ITodoUser> {
    try {
      return await putTodoUserUsersUserId({
        user,
        userId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently remove a user account from the Todo List application using the
   * provided unique identifier. This operation leads to irreversible deletion
   * of all the user's personal data, including their registration record and
   * access credentials as described by the todo_users schema.
   *
   * Account records are only deleted when a valid UUID is supplied, and
   * appropriate authorization is confirmed. Once processed, all owned todos and
   * private information linked to the user must also be securely deleted or
   * made inaccessible according to the business's privacy and compliance
   * requirements.
   *
   * This function is intended for scenarios such as user-requested account
   * termination. If the userId does not reference an existing account, a not
   * found error is generated. Strict attention to security and data integrity
   * is required for this operation.
   *
   * @param connection
   * @param userId Unique identifier of the target user. Must be a valid UUID as
   *   defined in the todo_users schema.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":userId")
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoUserUsersUserId({
        user,
        userId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
