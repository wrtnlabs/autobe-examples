import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postTodoUserTodos } from "../../../../providers/postTodoUserTodos";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { patchTodoUserTodos } from "../../../../providers/patchTodoUserTodos";
import { getTodoUserTodosTodoId } from "../../../../providers/getTodoUserTodosTodoId";
import { putTodoUserTodosTodoId } from "../../../../providers/putTodoUserTodosTodoId";
import { deleteTodoUserTodosTodoId } from "../../../../providers/deleteTodoUserTodosTodoId";

import { ITodoTodo } from "../../../../api/structures/ITodoTodo";
import { IPageITodoTodo } from "../../../../api/structures/IPageITodoTodo";

@Controller("/todo/user/todos")
export class TodoUserTodosController {
  /**
   * Create a new todo item assigned to the authenticated user.
   *
   * The request body must supply the todo's title (required), status (required,
   * must be 'incomplete' or 'complete'), and (optionally) a description. The
   * server will assign the todo_user_id based on the authenticated user. All
   * business and validation rules for field length, allowed values, and
   * ownership are strictly enforced and validated prior to persistence.
   *
   * On success, the created todo item is returned with all persisted
   * information, including UUID, timestamps, user ownership, and initial
   * status. Related operations: fetching a list of todos, fetching details by
   * id (GET /todos/{todoId}), updating (PUT), and deletion (DELETE).
   *
   * Errors will be returned for invalid values, missing required fields, or
   * authentication failures. Description of the request and response DTOs refer
   * to strict schema naming and domain conventions.
   *
   * @param connection
   * @param body Data required to create a new todo, enforcing title, status,
   *   and optional description, with ownership implied.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoTodo.ICreate,
  ): Promise<ITodoTodo> {
    try {
      return await postTodoUserTodos({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve a personalized, paginated list of todo items belonging
   * to the authenticated user in the Todo List application.
   *
   * This endpoint enables users to filter todos by completion status
   * ('complete' or 'incomplete'), partial matches in title or description, and
   * sort results as desired. Pagination and sorting help users efficiently
   * manage large todo lists. Security, privacy, and ownership are strictly
   * enforced: only todos created by the authenticated user are accessible.
   * Attempts to search for todos of other users will always return empty result
   * sets and do not leak resource existence information.
   *
   * Validation rules (as per schema) apply to every field: titles must be 1-255
   * characters, descriptions up to 1000 characters if present, and status must
   * be 'complete' or 'incomplete'. The response structure follows best
   * practices for API search—users receive summary information suitable for
   * listing, with detailed fields available in separate detail queries if
   * required. All query behaviors match non-functional and business criteria
   * described in requirements.
   *
   * @param connection
   * @param body Search and filter criteria for retrieving the user's todos;
   *   supports filtering by status, title, description, and custom
   *   sort/pagination options.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoTodo.IRequest,
  ): Promise<IPageITodoTodo.ISummary> {
    try {
      return await patchTodoUserTodos({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Fetch details for a specific todo item.
   *
   * This operation returns all persisted information for the designated todo
   * item, as defined in the todo_todos table. Users must supply the unique
   * identifier of the target todo via path parameter. Returned data includes
   * the todo's required title (1-255 characters), optional description (up to
   * 1000 characters), status (only 'complete' or 'incomplete' allowed),
   * timestamps for creation, last update, and (if applicable) completion.
   *
   * Security: Only the owning user (as specified by todo_user_id foreign key)
   * can access this resource. No sharing or delegation is possible under
   * current business and schema rules. Attempts by any other user will result
   * in an authorization error.
   *
   * The implementation must strictly enforce validation, field access, and
   * error handling in accordance with the table's schema-level comments.
   * Related operations include creation, editing (PUT), and deletion (DELETE)
   * of todo items.
   *
   * Returned structure references ITodoTodo detail DTO, guaranteeing type
   * safety and full property coverage. Errors are handled for not-found and
   * unauthorized access cases.
   *
   * @param connection
   * @param todoId Globally unique identifier (UUID) of the todo item to
   *   retrieve.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":todoId")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
  ): Promise<ITodoTodo> {
    try {
      return await getTodoUserTodosTodoId({
        user,
        todoId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing todo item for the authenticated user.
   *
   * This endpoint allows a user to update properties of their own todo entry,
   * as defined in the todo_todos Prisma schema. The fields available for update
   * include the title (always required), an optional description, and the
   * completion status which must be either 'incomplete' or 'complete.'
   *
   * Security is strictly enforced so only the owner (per the todo_user_id
   * foreign key) may update their own todos. Any attempt to update another
   * user's todo will be rejected. Timestamp management is handled as follows:
   * the updated_at field is set automatically to the request time, and
   * completed_at is updated if status is changed to 'complete.' All updates are
   * atomic and fully validated against schema length and value constraints.
   *
   * Business logic applies all necessary validation for title length (1-255),
   * optional description (up to 1000 chars), and accepted status values.
   * Attempts to use invalid status or out-of-bounds text will result in clear
   * error messages. No multi-user sharing or delegation is possible by design.
   * This operation references the todo_todos schema and directly incorporates
   * its validation and security principles.
   *
   * @param connection
   * @param todoId Unique identifier of the todo item to update (UUID,
   *   required).
   * @param body Data for updating the todo item. Fields include title
   *   (required), description (optional), and status ('incomplete' or
   *   'complete').
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":todoId")
  public async update(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoTodo.IUpdate,
  ): Promise<ITodoTodo> {
    try {
      return await putTodoUserTodosTodoId({
        user,
        todoId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a todo item belonging to the authenticated user.
   *
   * This endpoint provides hard deletion of an individual todo, as mandated by
   * the todo_todos Prisma schema and the service's business rules. Only the
   * user who owns the todo (per the todo_user_id foreign key) may invoke this
   * operation. Unauthorized deletion attempts are rejected with clear errors.
   *
   * No soft delete or recovery mechanism exists—deletion is absolute and cannot
   * be undone. Upon success, the specified todo is fully purged from the
   * database; no residual data remains accessible. This operation reflects the
   * schema's strong stance on ownership and irreversible deletion by design.
   * Deleted_at or similar fields do not exist—in accordance with strict
   * deletion requirements.
   *
   * @param connection
   * @param todoId Unique identifier of the todo item to delete (UUID,
   *   required).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":todoId")
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoUserTodosTodoId({
        user,
        todoId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
