import { Controller, Ip } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthUserJoin } from "../../../providers/postAuthUserJoin";
import { postAuthUserLogin } from "../../../providers/postAuthUserLogin";
import { postAuthUserRefresh } from "../../../providers/postAuthUserRefresh";

import { ITodoUser } from "../../../api/structures/ITodoUser";

@Controller("/auth/user")
export class AuthUserController {
  /**
   * User registration endpoint for todo_users table with initial
   * authentication.
   *
   * Registers a new user in the todo_users table and issues access/refresh
   * tokens. Enforces email uniqueness and password policy. Returns authorized
   * JWTs on success. Account creation is public and unauthenticated. Strict
   * validation is applied as per schema and requirements. Immediate login
   * effect on registration.
   *
   * @param connection
   * @param body User registration fields from todo_users schema. Includes
   *   email, password, and any other required fields.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoUser.ICreate,
  ): Promise<ITodoUser.IAuthorized> {
    try {
      return await postAuthUserJoin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * User login endpoint for todo_users table with JWT issuance.
   *
   * Authenticates a registered user against the todo_users table. Validates
   * email and password fields. Issues authorized JWTs on success. Error
   * handling and rate-limiting are strictly enforced as per security
   * requirements. Complements join (registration) and refresh (token renewal)
   * endpoints.
   *
   * @param connection
   * @param body User login credentials—email and password as defined in
   *   todo_users schema.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoUser.ILogin,
  ): Promise<ITodoUser.IAuthorized> {
    try {
      return await postAuthUserLogin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * User token refresh endpoint utilizing todo_user_sessions tracking.
   *
   * Refreshes JWT tokens for a user based on a valid refresh token. Operates
   * using todo_user_sessions schema. Enforces secure token rotation, session
   * tracking, and strict invalidation on misuse. Critical to long-life
   * authentication protocols. See join and login for initial token
   * provisioning.
   *
   * @param connection
   * @param body Refresh token string. Structure and validation as per
   *   requirements and session schema.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: ITodoUser.IRefresh,
  ): Promise<ITodoUser.IAuthorized> {
    try {
      return await postAuthUserRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
