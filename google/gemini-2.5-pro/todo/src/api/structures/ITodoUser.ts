/**
 * Registered user entity for the Todo List application.
 *
 * Represents an individual account in the Todo List system. All todo list data
 * is strictly scoped by this identity. Each user is uniquely identified by
 * their email address. Passwords are stored using cryptographic hashes only,
 * never in plain text. No user can access or modify another user's data; strict
 * privacy and ownership rules apply.
 *
 * Timestamps indicate when the account was created and when it was most
 * recently modified. This entity is foundational to all authentication,
 * permission checks, and separation of user data within the system.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type ITodoUser = {
  /**
   * Universally unique identifier of the user. Serves as the primary key for
   * identity and authentication.
   */
  id: string & tags.Format<"uuid">;

  /**
   * Unique email address for the user. Used for authentication and business
   * communication. Must be unique across all users.
   */
  email: string & tags.Format<"email">;

  /**
   * Timestamp of when the user account was first created. Used for auditing
   * and registration analytics.
   */
  created_at: string & tags.Format<"date-time">;

  /**
   * Timestamp of the most recent update to the user account (such as email or
   * password changes).
   */
  updated_at: string & tags.Format<"date-time">;
};
