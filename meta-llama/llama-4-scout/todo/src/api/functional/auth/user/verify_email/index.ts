import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ITodoListUserEmailVerification } from "../../../../structures/ITodoListUserEmailVerification";

/**
 * Finalizes user registration by activating account via email token in
 * todo_list_user_email_verifications.
 *
 * This endpoint accepts the email verification token (found in the
 * 'todo_list_user_email_verifications' table) and, if valid, activates the
 * associated user's account (sets 'is_verified' to true). Upon redemption, the
 * 'consumed_at' timestamp is set, and the user's status transitions from
 * pending to active, enabling the login operation.
 *
 * If the verification token does not exist, has already been used
 * ('consumed_at' not null), or is expired, the action is denied and the user
 * remains unable to log in. Each verification token is single-use and
 * time-limited, referencing the 'expires_at' and 'consumed_at' columns for
 * validity.
 *
 * This operation completes new user onboarding after registration. Invalid or
 * expired tokens result in clear error messages, promoting security and
 * usability.
 *
 * Related operations are registration (creates the token), and login (requires
 * successful verification before tokens are issued).
 *
 * Failure scenarios cover incorrect usage and timeouts, maintaining
 * auditability via the verification events log.
 *
 * @param props.connection
 * @param props.body Payload containing the email verification token.
 * @path /auth/user/verify-email
 * @accessor api.functional.auth.user.verify_email.verifyEmail
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function verifyEmail(
  connection: IConnection,
  props: verifyEmail.Props,
): Promise<verifyEmail.Response> {
  return true === connection.simulate
    ? verifyEmail.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...verifyEmail.METADATA,
          path: verifyEmail.path(),
          status: null,
        },
        props.body,
      );
}
export namespace verifyEmail {
  export type Props = {
    /** Payload containing the email verification token. */
    body: ITodoListUserEmailVerification.IVerify;
  };
  export type Body = ITodoListUserEmailVerification.IVerify;
  export type Response = ITodoListUserEmailVerification.IVerified;

  export const METADATA = {
    method: "POST",
    path: "/auth/user/verify-email",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/user/verify-email";
  export const random = (): ITodoListUserEmailVerification.IVerified =>
    typia.random<ITodoListUserEmailVerification.IVerified>();
  export const simulate = (
    connection: IConnection,
    props: verifyEmail.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: verifyEmail.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
