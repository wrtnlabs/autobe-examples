import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ITodoListUserPasswordReset } from "../../../../structures/ITodoListUserPasswordReset";

/**
 * Updates user's password via valid reset token in
 * todo_list_user_password_resets; single-use only.
 *
 * Redemption endpoint for password reset: accepts the one-time reset token
 * (from 'todo_list_user_password_resets') along with a new password. If the
 * token is present, unconsumed, and not expired, the associated user's password
 * is updated to the securely-hashed new value in 'todo_list_users', and the
 * reset token event is marked as consumed ('consumed_at').
 *
 * Used tokens cannot be re-used, and expired ones are rejected. Password reset
 * is a sensitive operation and is audited in the event log for traceability,
 * allowing enforcement of security/compliance policies.
 *
 * Failing this operation (invalid or expired token) triggers a generic error
 * message, preventing attackers from probing for valid tokens or emails.
 *
 * Related flow requires a prior password reset initiation request, logged in
 * the password resets table, and enforces the single-use, time-limited
 * guarantee via database schema constraints.
 *
 * @param props.connection
 * @param props.body Payload containing reset token and new password.
 * @path /auth/user/reset-password
 * @accessor api.functional.auth.user.reset_password.resetPassword
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function resetPassword(
  connection: IConnection,
  props: resetPassword.Props,
): Promise<resetPassword.Response> {
  return true === connection.simulate
    ? resetPassword.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...resetPassword.METADATA,
          path: resetPassword.path(),
          status: null,
        },
        props.body,
      );
}
export namespace resetPassword {
  export type Props = {
    /** Payload containing reset token and new password. */
    body: ITodoListUserPasswordReset.IReset;
  };
  export type Body = ITodoListUserPasswordReset.IReset;
  export type Response = ITodoListUserPasswordReset.IResetResult;

  export const METADATA = {
    method: "POST",
    path: "/auth/user/reset-password",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/user/reset-password";
  export const random = (): ITodoListUserPasswordReset.IResetResult =>
    typia.random<ITodoListUserPasswordReset.IResetResult>();
  export const simulate = (
    connection: IConnection,
    props: resetPassword.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: resetPassword.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
