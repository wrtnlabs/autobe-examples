import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ITodoListUserPasswordReset } from "../../../../structures/ITodoListUserPasswordReset";

/**
 * Initiates password reset process for user by generating time-limited reset
 * token (todo_list_user_password_resets).
 *
 * Initiates a password reset for user accounts. The endpoint accepts an email
 * address and, if the corresponding user is present in 'todo_list_users',
 * generates a unique single-use reset token (persisted in
 * 'todo_list_user_password_resets'). This token is sent to the email on record.
 * No information is leaked about whether the email exists, always replying
 * success to prevent user enumeration.
 *
 * All requests are audited; excessive attempts can be rate-limited using the
 * password resets schema. The reset token includes strict expiration
 * ('expires_at') and is unique per reset event ('reset_token').
 *
 * The reset process itself is completed in a separate endpoint, where the user
 * redeems the token by setting a new password.
 *
 * Failed or expired token submissions handled in a companion operation.
 *
 * Related entities: user (identity), resets (event log, token issue).
 *
 * This operation never reveals presence of non-existent accounts for privacy
 * and security reasons.
 *
 * @param props.connection
 * @param props.body Payload with user's email address for password reset
 *   request.
 * @path /auth/user/request-password-reset
 * @accessor api.functional.auth.user.request_password_reset.requestPasswordReset
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function requestPasswordReset(
  connection: IConnection,
  props: requestPasswordReset.Props,
): Promise<requestPasswordReset.Response> {
  return true === connection.simulate
    ? requestPasswordReset.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...requestPasswordReset.METADATA,
          path: requestPasswordReset.path(),
          status: null,
        },
        props.body,
      );
}
export namespace requestPasswordReset {
  export type Props = {
    /** Payload with user's email address for password reset request. */
    body: ITodoListUserPasswordReset.IRequest;
  };
  export type Body = ITodoListUserPasswordReset.IRequest;
  export type Response = ITodoListUserPasswordReset.IRequested;

  export const METADATA = {
    method: "POST",
    path: "/auth/user/request-password-reset",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/user/request-password-reset";
  export const random = (): ITodoListUserPasswordReset.IRequested =>
    typia.random<ITodoListUserPasswordReset.IRequested>();
  export const simulate = (
    connection: IConnection,
    props: requestPasswordReset.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: requestPasswordReset.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
