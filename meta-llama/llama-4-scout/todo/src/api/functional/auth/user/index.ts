/**
 * This endpoint enables registration for new users by accepting a unique email
 * address and password. The registration process involves strict email
 * uniqueness enforcement—if a duplicate is detected in the 'todo_list_users'
 * table, the system will reject the registration with a conflict error
 * (referencing the 'email' unique index). The user's account is created in a
 * pending (unverified) state, and a verification email is sent to the provided
 * address using a unique token.
 *
 * Only after verifying the email (using a separate operation) will the account
 * become active (see 'is_verified' and 'is_active' fields in
 * 'todo_list_users'). The password is securely stored as a salted cryptographic
 * hash in 'password_hash' and never returned.
 *
 * Upon successful registration, further authentication is blocked until email
 * verification is completed. Users cannot change the email after registration,
 * as enforced by the immutable 'email' column.
 *
 * This registration operation is related to the email verification process,
 * which users must complete before being able to log in.
 *
 * Unsuccessful attempts due to invalid input or existing email result in clear
 * error messages, following the validation rules established in the schema.
 * Only user-facing data is returned—never internal account or security
 * metadata.
 *
 * @param props.connection
 * @param props.body Registration payload, including email and password.
 * @setHeader token.access Authorization
 *
 * @path /auth/user/join
 * @accessor api.functional.auth.user.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
