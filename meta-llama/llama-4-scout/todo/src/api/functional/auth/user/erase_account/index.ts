import { IConnection } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";

import { ITodoListUser } from "../../../../structures/ITodoListUser";

/**
 * Permanently deletes authenticated user's account and related data; removes
 * from todo_list_users and subsidiaries.
 *
 * Irreversible removal endpoint that deletes the authenticated user’s account
 * data from 'todo_list_users' and all dependent relations (todos, sessions,
 * verifications, password resets). Sets 'deleted_at' on the user entity,
 * disables login, and wipes associated data by policy.
 *
 * This is a logged and traceable destructive operation: once successful, the
 * account cannot be restored or re-registered. The operation ensures no
 * credentials or residual personal data persist. Breaks all session tokens and
 * revokes authentication immediately on execution, preventing any future login
 * attempts for this email.
 *
 * Unauthorized or unauthenticated requests are denied, ensuring only valid,
 * verified users can erase their account. All error cases provide clear reasons
 * for operation failure.
 *
 * @param props.connection
 * @path /auth/user/erase-account
 * @accessor api.functional.auth.user.erase_account.eraseAccount
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function eraseAccount(
  connection: IConnection,
): Promise<eraseAccount.Response> {
  return true === connection.simulate
    ? eraseAccount.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...eraseAccount.METADATA,
          path: eraseAccount.path(),
          status: null,
        },
      );
}
export namespace eraseAccount {
  export type Response = ITodoListUser.IDeletionResult;

  export const METADATA = {
    method: "DELETE",
    path: "/auth/user/erase-account",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/user/erase-account";
  export const random = (): ITodoListUser.IDeletionResult =>
    typia.random<ITodoListUser.IDeletionResult>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}
