import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ITodoListUser } from "../../../../structures/ITodoListUser";

/**
 * Allows a logged-in user to change their account password by submitting both
 * the current password and a valid new password. The operation compares the
 * submitted current password against the cryptographic hash in 'password_hash'
 * (from 'todo_list_users'), and if correct, stores the new hash securely.
 *
 * If the current password is incorrect, the change is denied, and a relevant
 * error is returned. The endpoint only operates for active, verified users, as
 * enforced by the 'is_verified' and 'is_active' fields.
 *
 * Password changes are logged with account 'updated_at' timestamp. All
 * successful changes require validation of the proposed new password by
 * policy.
 *
 * Operation is related to authentication, password reset, and user entity
 * management workflows. Failures are handled by consistent, informative error
 * messages to assist the user.
 *
 * @param props.connection
 * @param props.body Payload with both current and new passwords for password
 *   change.
 * @path /auth/user/change-password
 * @accessor api.functional.auth.user.change_password.changePassword
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function changePassword(
  connection: IConnection,
  props: changePassword.Props,
): Promise<changePassword.Response> {
  return true === connection.simulate
    ? changePassword.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...changePassword.METADATA,
          path: changePassword.path(),
          status: null,
        },
        props.body,
      );
}
export namespace changePassword {
  export type Props = {
    /** Payload with both current and new passwords for password change. */
    body: ITodoListUser.IChangePassword;
  };
  export type Body = ITodoListUser.IChangePassword;
  export type Response = ITodoListUser.IChangePasswordResult;

  export const METADATA = {
    method: "POST",
    path: "/auth/user/change-password",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/user/change-password";
  export const random = (): ITodoListUser.IChangePasswordResult =>
    typia.random<ITodoListUser.IChangePasswordResult>();
  export const simulate = (
    connection: IConnection,
    props: changePassword.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: changePassword.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
