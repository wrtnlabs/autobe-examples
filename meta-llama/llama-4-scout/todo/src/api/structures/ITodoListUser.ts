/**
 * Registered Todo List application user profile.
 *
 * Represents the identity, authentication, and business presence of each unique
 * user account. Core fields include immutable login credential (email),
 * updatable display name, and status/audit flags. All sensitive/internal
 * authentication values (such as password hash) are strictly omitted in all API
 * responses.
 *
 * Ownership of all todo items is tied to this identity, and users manage only
 * their own information. This schema is used in profile views, account settings
 * pages, and authorization verification endpoints.
 *
 * Readonly fields (id, email, created_at, updated_at, deleted_at) are
 * guaranteed safe for display. Mutability is targeted for display_name, with
 * verification and activation states controlled by the system.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type ITodoListUser = {
  /**
   * Unique identifier for the user account. This value is generated by the
   * system upon registration and cannot be changed.
   *
   * Used as the primary key for user records and referenced by all
   * authentication and business logic. Always returned for profile queries
   * but never exposed in unauthenticated APIs.
   */
  id: string & tags.Format<"uuid">;

  /**
   * The registered email address for the account, used as the unique global
   * login credential and for all system notifications.
   *
   * The email address must be valid per RFC 5322 and is strictly unique and
   * immutable once set. This field is never exposed in search APIs and always
   * hidden except in "my profile" views.
   */
  email: string & tags.Format<"email">;

  /**
   * The user's display name, visible in personal dashboards and application
   * UI.
   *
   * While not required to be globally unique, it must be present and remain
   * within 100 characters per business rules. Users can update their display
   * name any time, subject to validation constraints.
   */
  display_name: string & tags.MinLength<1> & tags.MaxLength<100>;

  /**
   * Indicates whether the user's email address has been verified through
   * system confirmation flows.
   *
   * Set to true only after the email verification link has been consumed.
   * Controls UI display and feature unlock.
   */
  is_verified: boolean;

  /**
   * Indicates whether the account is currently enabled for login and
   * interaction.
   *
   * Set to false in cases of permanent deletion, security suspension, or
   * user-initiated deactivation. New logins are rejected when false.
   */
  is_active: boolean;

  /**
   * Date and time of initial registration and account creation, stored in UTC
   * ISO 8601 format.
   *
   * This field is set once by the system and cannot be modified by users.
   * Used for audit and eligibility checks.
   */
  created_at: string & tags.Format<"date-time">;

  /**
   * Timestamp of the most recent change to the account record (profile
   * updates, credential changes, etc.), in UTC ISO 8601 format.
   *
   * System-managed for audit and support purposes.
   */
  updated_at: string & tags.Format<"date-time">;

  /**
   * Timestamp indicating when the account was permanently deleted (if
   * applicable), in UTC ISO 8601 format. Null if account is still active.
   *
   * Set only during irreversible deletion flows. Otherwise remains empty.
   */
  deleted_at?: (string & tags.Format<"date-time">) | null | undefined;
};
