import { Controller, Ip } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthUserJoin } from "../../../providers/postAuthUserJoin";
import { postAuthUserLogin } from "../../../providers/postAuthUserLogin";
import { postAuthUserRefresh } from "../../../providers/postAuthUserRefresh";
import { postAuthUserLogout } from "../../../providers/postAuthUserLogout";
import { UserAuth } from "../../../decorators/UserAuth";
import { UserPayload } from "../../../decorators/payload/UserPayload";

import { ITodoListUser } from "../../../api/structures/ITodoListUser";

@Controller("/auth/user")
export class AuthUserController {
  /**
   * Registers a new user in the todo_list_users table (pending verification).
   *
   * This endpoint enables registration for new users by accepting a unique
   * email address and password. The registration process involves strict email
   * uniqueness enforcement—if a duplicate is detected in the 'todo_list_users'
   * table, the system will reject the registration with a conflict error
   * (referencing the 'email' unique index). The user's account is created in a
   * pending (unverified) state, and a verification email is sent to the
   * provided address using a unique token.
   *
   * Only after verifying the email (using a separate operation) will the
   * account become active (see 'is_verified' and 'is_active' fields in
   * 'todo_list_users'). The password is securely stored as a salted
   * cryptographic hash in 'password_hash' and never returned.
   *
   * Upon successful registration, further authentication is blocked until email
   * verification is completed. Users cannot change the email after
   * registration, as enforced by the immutable 'email' column.
   *
   * This registration operation is related to the email verification process,
   * which users must complete before being able to log in.
   *
   * Unsuccessful attempts due to invalid input or existing email result in
   * clear error messages, following the validation rules established in the
   * schema. Only user-facing data is returned—never internal account or
   * security metadata.
   *
   * @param connection
   * @param body Registration payload, including email and password.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoListUser.IJoin,
  ): Promise<ITodoListUser.IAuthorized> {
    try {
      return await postAuthUserJoin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticates verified user from todo_list_users and issues tokens.
   *
   * Handles user login, validating submitted credentials against the
   * 'todo_list_users' table using the combination of 'email' and
   * securely-hashed 'password_hash' values. Only users marked as both
   * 'is_verified' and 'is_active' can successfully receive tokens. The endpoint
   * denies authentication if credentials are incorrect, if the email has not
   * been verified, or the account is deactivated.
   *
   * The operation returns JWT access and refresh tokens for valid users,
   * leveraging the account's unique ID, and does not expose any internal
   * security data or hashed passwords. Login requires that the email correspond
   * to an existing, verified account in the user table.
   *
   * The endpoint distinguishes only between correct and incorrect credentials,
   * using generic error messages to prevent user enumeration or disclosing
   * security-sensitive information.
   *
   * Related operations include registration (for creating a pending account)
   * and email verification (to activate the user).
   *
   * Multiple concurrent sessions are supported via the
   * 'todo_list_user_sessions' table, with each session generating its own
   * tracked row for audit and security analysis.
   *
   * @param connection
   * @param body Login credentials including email and password.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoListUser.ILogin,
  ): Promise<ITodoListUser.IAuthorized> {
    try {
      return await postAuthUserLogin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Issues new tokens for users with valid refresh tokens via
   * todo_list_user_sessions.
   *
   * Allows users to obtain a new access token by submitting a valid, unexpired
   * refresh token. The operation cross-checks the provided token against the
   * active session records in 'todo_list_user_sessions', confirming that the
   * token is active, not expired ('expired_at' is null or in the future), and
   * properly assigned to the user session indicated.
   *
   * Session audits are enforced at the database level, tying each refresh token
   * to its session and preventing reuse after logout or expiration. Expired,
   * invalid, or missing tokens result in authentication failure. All critical
   * information—such as token lifetime, IP, session metadata—is managed in the
   * session log.
   *
   * Refresh operations are central to secure, long-lived user authentication in
   * stateless environments. No user profile or business data is returned except
   * new token(s).
   *
   * This endpoint is expected to be called by clients automatically on access
   * token expiry. Failures trigger re-authentication via the login operation.
   *
   * @param connection
   * @param body The valid refresh token to be exchanged for new tokens.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: ITodoListUser.IRefresh,
  ): Promise<ITodoListUser.IAuthorized> {
    try {
      return await postAuthUserRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Logs out authenticated user, invalidating all todo_list_user_sessions,
   * forcing re-authentication.
   *
   * Terminates all active user sessions, including access and refresh tokens,
   * by updating or marking all corresponding entries as expired in the
   * 'todo_list_user_sessions' table. This operation is exclusively for the
   * authenticated user, requiring a valid session. Ensures any subsequent
   * attempt to use old tokens results in authentication failure.
   *
   * The endpoint updates session log entries (sets 'expired_at'), supporting
   * full session invalidation as a security measure, useful for lost devices or
   * account compromise recovery. Sessions are immediately invalidated and
   * cannot be restored.
   *
   * Operation is related to login, authentication, refresh, and session
   * management endpoints. Success means user must re-authenticate to restore
   * access.
   *
   * Audit logs for each session are maintained for security analysis and
   * troubleshooting. Error handling is robust, capturing rare failures in
   * session update logic.
   *
   * @param connection
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("logout")
  public async logout(
    @UserAuth()
    user: UserPayload,
  ): Promise<ITodoListUser.ILogoutResult> {
    try {
      return await postAuthUserLogout({
        user,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
