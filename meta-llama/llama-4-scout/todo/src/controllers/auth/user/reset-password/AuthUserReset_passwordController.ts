import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthUserResetPassword } from "../../../../providers/postAuthUserResetPassword";

import { ITodoListUserPasswordReset } from "../../../../api/structures/ITodoListUserPasswordReset";

@Controller("/auth/user/reset-password")
export class AuthUserReset_passwordController {
  /**
   * Updates user's password via valid reset token in
   * todo_list_user_password_resets; single-use only.
   *
   * Redemption endpoint for password reset: accepts the one-time reset token
   * (from 'todo_list_user_password_resets') along with a new password. If the
   * token is present, unconsumed, and not expired, the associated user's
   * password is updated to the securely-hashed new value in 'todo_list_users',
   * and the reset token event is marked as consumed ('consumed_at').
   *
   * Used tokens cannot be re-used, and expired ones are rejected. Password
   * reset is a sensitive operation and is audited in the event log for
   * traceability, allowing enforcement of security/compliance policies.
   *
   * Failing this operation (invalid or expired token) triggers a generic error
   * message, preventing attackers from probing for valid tokens or emails.
   *
   * Related flow requires a prior password reset initiation request, logged in
   * the password resets table, and enforces the single-use, time-limited
   * guarantee via database schema constraints.
   *
   * @param connection
   * @param body Payload containing reset token and new password.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async resetPassword(
    @TypedBody()
    body: ITodoListUserPasswordReset.IReset,
  ): Promise<ITodoListUserPasswordReset.IResetResult> {
    try {
      return await postAuthUserResetPassword({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
