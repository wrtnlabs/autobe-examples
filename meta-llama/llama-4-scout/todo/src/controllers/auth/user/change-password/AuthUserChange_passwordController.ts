import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthUserChangePassword } from "../../../../providers/postAuthUserChangePassword";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";

import { ITodoListUser } from "../../../../api/structures/ITodoListUser";

@Controller("/auth/user/change-password")
export class AuthUserChange_passwordController {
  /**
   * Allows a logged-in user to change their account password by submitting both
   * the current password and a valid new password. The operation compares the
   * submitted current password against the cryptographic hash in
   * 'password_hash' (from 'todo_list_users'), and if correct, stores the new
   * hash securely.
   *
   * If the current password is incorrect, the change is denied, and a relevant
   * error is returned. The endpoint only operates for active, verified users,
   * as enforced by the 'is_verified' and 'is_active' fields.
   *
   * Password changes are logged with account 'updated_at' timestamp. All
   * successful changes require validation of the proposed new password by
   * policy.
   *
   * Operation is related to authentication, password reset, and user entity
   * management workflows. Failures are handled by consistent, informative error
   * messages to assist the user.
   *
   * @param connection
   * @param body Payload with both current and new passwords for password
   *   change.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async changePassword(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoListUser.IChangePassword,
  ): Promise<ITodoListUser.IChangePasswordResult> {
    try {
      return await postAuthUserChangePassword({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
