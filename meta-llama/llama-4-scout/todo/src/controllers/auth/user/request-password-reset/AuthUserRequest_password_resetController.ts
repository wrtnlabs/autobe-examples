import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthUserRequestPasswordReset } from "../../../../providers/postAuthUserRequestPasswordReset";

import { ITodoListUserPasswordReset } from "../../../../api/structures/ITodoListUserPasswordReset";

@Controller("/auth/user/request-password-reset")
export class AuthUserRequest_password_resetController {
  /**
   * Initiates password reset process for user by generating time-limited reset
   * token (todo_list_user_password_resets).
   *
   * Initiates a password reset for user accounts. The endpoint accepts an email
   * address and, if the corresponding user is present in 'todo_list_users',
   * generates a unique single-use reset token (persisted in
   * 'todo_list_user_password_resets'). This token is sent to the email on
   * record. No information is leaked about whether the email exists, always
   * replying success to prevent user enumeration.
   *
   * All requests are audited; excessive attempts can be rate-limited using the
   * password resets schema. The reset token includes strict expiration
   * ('expires_at') and is unique per reset event ('reset_token').
   *
   * The reset process itself is completed in a separate endpoint, where the
   * user redeems the token by setting a new password.
   *
   * Failed or expired token submissions handled in a companion operation.
   *
   * Related entities: user (identity), resets (event log, token issue).
   *
   * This operation never reveals presence of non-existent accounts for privacy
   * and security reasons.
   *
   * @param connection
   * @param body Payload with user's email address for password reset request.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async requestPasswordReset(
    @TypedBody()
    body: ITodoListUserPasswordReset.IRequest,
  ): Promise<ITodoListUserPasswordReset.IRequested> {
    try {
      return await postAuthUserRequestPasswordReset({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
