import { Controller } from "@nestjs/common";
import { TypedRoute } from "@nestia/core";
import typia from "typia";
import { deleteAuthUserEraseAccount } from "../../../../providers/deleteAuthUserEraseAccount";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";

import { ITodoListUser } from "../../../../api/structures/ITodoListUser";

@Controller("/auth/user/erase-account")
export class AuthUserErase_accountController {
  /**
   * Permanently deletes authenticated user's account and related data; removes
   * from todo_list_users and subsidiaries.
   *
   * Irreversible removal endpoint that deletes the authenticated user’s account
   * data from 'todo_list_users' and all dependent relations (todos, sessions,
   * verifications, password resets). Sets 'deleted_at' on the user entity,
   * disables login, and wipes associated data by policy.
   *
   * This is a logged and traceable destructive operation: once successful, the
   * account cannot be restored or re-registered. The operation ensures no
   * credentials or residual personal data persist. Breaks all session tokens
   * and revokes authentication immediately on execution, preventing any future
   * login attempts for this email.
   *
   * Unauthorized or unauthenticated requests are denied, ensuring only valid,
   * verified users can erase their account. All error cases provide clear
   * reasons for operation failure.
   *
   * @param connection
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async eraseAccount(
    @UserAuth()
    user: UserPayload,
  ): Promise<ITodoListUser.IDeletionResult> {
    try {
      return await deleteAuthUserEraseAccount({
        user,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
