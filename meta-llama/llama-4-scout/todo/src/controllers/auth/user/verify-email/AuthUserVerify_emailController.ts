import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthUserVerifyEmail } from "../../../../providers/postAuthUserVerifyEmail";

import { ITodoListUserEmailVerification } from "../../../../api/structures/ITodoListUserEmailVerification";

@Controller("/auth/user/verify-email")
export class AuthUserVerify_emailController {
  /**
   * Finalizes user registration by activating account via email token in
   * todo_list_user_email_verifications.
   *
   * This endpoint accepts the email verification token (found in the
   * 'todo_list_user_email_verifications' table) and, if valid, activates the
   * associated user's account (sets 'is_verified' to true). Upon redemption,
   * the 'consumed_at' timestamp is set, and the user's status transitions from
   * pending to active, enabling the login operation.
   *
   * If the verification token does not exist, has already been used
   * ('consumed_at' not null), or is expired, the action is denied and the user
   * remains unable to log in. Each verification token is single-use and
   * time-limited, referencing the 'expires_at' and 'consumed_at' columns for
   * validity.
   *
   * This operation completes new user onboarding after registration. Invalid or
   * expired tokens result in clear error messages, promoting security and
   * usability.
   *
   * Related operations are registration (creates the token), and login
   * (requires successful verification before tokens are issued).
   *
   * Failure scenarios cover incorrect usage and timeouts, maintaining
   * auditability via the verification events log.
   *
   * @param connection
   * @param body Payload containing the email verification token.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async verifyEmail(
    @TypedBody()
    body: ITodoListUserEmailVerification.IVerify,
  ): Promise<ITodoListUserEmailVerification.IVerified> {
    try {
      return await postAuthUserVerifyEmail({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
