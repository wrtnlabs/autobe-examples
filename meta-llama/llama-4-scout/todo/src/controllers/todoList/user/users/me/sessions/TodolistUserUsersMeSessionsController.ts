import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchTodoListUserUsersMeSessions } from "../../../../../../providers/patchTodoListUserUsersMeSessions";
import { UserAuth } from "../../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../../decorators/payload/UserPayload";
import { getTodoListUserUsersMeSessionsSessionId } from "../../../../../../providers/getTodoListUserUsersMeSessionsSessionId";
import { deleteTodoListUserUsersMeSessionsSessionId } from "../../../../../../providers/deleteTodoListUserUsersMeSessionsSessionId";

import { IPageITodoListUserSession } from "../../../../../../api/structures/IPageITodoListUserSession";
import { ITodoListUserSession } from "../../../../../../api/structures/ITodoListUserSession";

@Controller("/todoList/user/users/me/sessions")
export class TodolistUserUsersMeSessionsController {
  /**
   * Fetch a paginated/searchable list of all login and authentication sessions
   * for the currently logged-in user, as stored in the todo_list_user_sessions
   * table.
   *
   * This operation helps users monitor their own authentication history and
   * manage their security posture. It exposes session metadata such as
   * originating IP address, the URL/login context, referrer, session creation
   * time, and expiration. All records pertain only to the requesting
   * user—cross-user access is never allowed, and attempts are denied by both
   * API logic and database filtering, following strict Prisma schema business
   * rules.
   *
   * The API supports complex search and pagination via filter criteria on
   * fields such as session start/end dates and status. Sessions are ordered by
   * creation date (most recent first) for usability. Security is enforced at
   * both the endpoint and service layer: only the authenticated user can access
   * this information about themselves, and attempts by unauthenticated or other
   * actors are rejected. The maximum page size per response follows performance
   * and privacy guidelines (see requirements), and error scenarios (such as
   * invalid paging parameters or unauthorized access) trigger clear, standard
   * error messages.
   *
   * No session deletion or cross-user audit is ever allowed via this endpoint;
   * this is strictly for self-service access by the account owner only.
   *
   * @param connection
   * @param body Filter, sorting, and pagination parameters to select relevant
   *   user session records.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoListUserSession.IRequest,
  ): Promise<IPageITodoListUserSession> {
    try {
      return await patchTodoListUserUsersMeSessions({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve details about a specific login session for the currently
   * authenticated user.
   *
   * This API allows a user to see details such as the originating IP, creation
   * and expiration timestamps, and context information for a single session.
   * Only the owner of the session may use this endpoint; administrators and
   * other users may not retrieve session data for another user for privacy and
   * security.
   *
   * The sessionId parameter is the unique identifier of the desired
   * authentication session, as stored in the 'todo_list_user_sessions' table.
   * The system enforces that the session belongs to the currently logged-in
   * account. This ensures secure, audit-friendly API behavior and restricts
   * information exposure to the account owner.
   *
   * This operation supports account auditability and user transparency, but not
   * administration of global session data. Session records remain after
   * expiration for audit purposes, so users can view both active and expired
   * sessions.
   *
   * Related operations include session termination (DELETE
   * /users/me/sessions/{sessionId}) and session listing (not shown here).
   * Errors are returned for invalid sessionId or attempts to access another
   * user's session.
   *
   * @param connection
   * @param sessionId Unique identifier of the target session belonging to the
   *   currently authenticated user. Must be a valid session UUID from the
   *   todo_list_user_sessions table.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<ITodoListUserSession> {
    try {
      return await getTodoListUserUsersMeSessionsSessionId({
        user,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a specific authentication session for the current user, revoking
   * access for the identified browser or device.
   *
   * This API endpoint enables a user to forcibly log out a particular session
   * (such as an open tab or another device) from their
   * 'todo_list_user_sessions' records. Deletion here means marking the session
   * as expired—actual session records remain for compliance and traceability,
   * and no soft or hard deletion occurs. Only the session owner may perform
   * this operation; system or admin-initiated deletions are handled elsewhere.
   * Attempts to delete another user's session will be denied.
   *
   * Security is strictly enforced by verifying both authentication and
   * sessionId ownership before performing the operation. This enables users to
   * maintain account security by revoking lost or suspicious sessions on
   * demand.
   *
   * Related endpoints include viewing session details (GET
   * /users/me/sessions/{sessionId}) and listing all current sessions.
   *
   * @param connection
   * @param sessionId Unique identifier of the session to be revoked, belonging
   *   to the currently authenticated user.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":sessionId")
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<ITodoListUserSession> {
    try {
      return await deleteTodoListUserUsersMeSessionsSessionId({
        user,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
