import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia from "typia";
import { patchTodoListUserUsersMePasswordResets } from "../../../../../../providers/patchTodoListUserUsersMePasswordResets";
import { UserAuth } from "../../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../../decorators/payload/UserPayload";
import { getTodoListUserUsersMePasswordResetsResetToken } from "../../../../../../providers/getTodoListUserUsersMePasswordResetsResetToken";

import { IPageITodoListUserPasswordReset } from "../../../../../../api/structures/IPageITodoListUserPasswordReset";
import { ITodoListUserPasswordReset } from "../../../../../../api/structures/ITodoListUserPasswordReset";

@Controller("/todoList/user/users/me/passwordResets")
export class TodolistUserUsersMePasswordresetsController {
  /**
   * Retrieve password reset history for the authenticated user's account using
   * the password reset log table.
   *
   * This endpoint allows an authenticated user to query the log of all password
   * reset requests and their status for their own account. Results include
   * events whether used, expired, or still active. The operation supports
   * filtering by date range, token status (expired/used/active), and is ordered
   * by creation time for ease of review.
   *
   * Security is critical: only the owner of the account may access their own
   * password reset event history. The operation relies on user identity
   * provided by authentication context, not a path parameter, so no sensitive
   * user ID is directly exchanged or exposed. Rate limiting is enforced to
   * prevent probing, and data is filtered strictly for the authenticated user
   * only.
   *
   * This history is sourced from the todo_list_user_password_resets table. Each
   * item includes timestamps for issuance, expiry, and redemption/consumption.
   * This operation can be used in account security dashboards, help users
   * recognize unwanted resets, and provide a compliance trail for security
   * events. Related operations: GET /users/me/passwordResets/{resetToken} for
   * inspecting a single reset event in detail.
   *
   * @param connection
   * @param body Search, filter, and pagination parameters for password reset
   *   event history on the user's account.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoListUserPasswordReset.IRequest,
  ): Promise<IPageITodoListUserPasswordReset.ISummary> {
    try {
      return await patchTodoListUserUsersMePasswordResets({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve details for a password reset event by token for the user's account
   * using the password reset log table.
   *
   * This endpoint allows the authenticated user to inspect the details of a
   * password reset event from their own account by specifying the event's
   * unique reset token in the path. Information returned includes creation,
   * expiration, and consumption timestamps, as well as verification that the
   * reset token belongs to the querying user and has not been used or expired.
   *
   * Strict security and privacy controls are enforced: only the user who owns
   * the reset token may access its event details, and tokens are checked for
   * validity, expiration, and ownership. The token parameter does not expose
   * the internal reset event ID, but is a single-use, cryptographically strong
   * identifier.
   *
   * The operation references the todo_list_user_password_resets table,
   * returning all related event information for UI display or suspicious
   * activity review. If the token is invalid or no longer associated with the
   * authenticated user, a not-found or error response is returned. Related
   * operation: PATCH /users/me/passwordResets for listing all events.
   *
   * @param connection
   * @param resetToken Unique, single-use password reset token for identifying
   *   the reset event (scoped to the authenticated user).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":resetToken")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("resetToken")
    resetToken: string,
  ): Promise<ITodoListUserPasswordReset> {
    try {
      return await getTodoListUserUsersMePasswordResetsResetToken({
        user,
        resetToken,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
