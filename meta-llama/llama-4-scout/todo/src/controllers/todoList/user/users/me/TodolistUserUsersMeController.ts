import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { getTodoListUserUsersMe } from "../../../../../providers/getTodoListUserUsersMe";
import { UserAuth } from "../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../decorators/payload/UserPayload";
import { putTodoListUserUsersMe } from "../../../../../providers/putTodoListUserUsersMe";
import { deleteTodoListUserUsersMe } from "../../../../../providers/deleteTodoListUserUsersMe";

import { ITodoListUser } from "../../../../../api/structures/ITodoListUser";

@Controller("/todoList/user/users/me")
export class TodolistUserUsersMeController {
  /**
   * Retrieve the authenticated user's profile, containing their basic identity
   * and account settings. This operation ensures only the user themself can
   * access their own data; no IDs are exposed or required in the path because
   * 'me' references the current session or JWT.
   *
   * Authentication is mandatory; unauthenticated requests are rejected. The
   * response mirrors the database structure: email (unique, immutable), display
   * name (user-controlled), is_verified (reflecting email verification state),
   * is_active (account enabled/disabled), and audit timestamps. All sensitive
   * data such as password hash are excluded. The endpoint ensures no other
   * user's data can be accessed via 'me'.
   *
   * Other user-related endpoints (admin search, system logs of user activity)
   * are separate and not included in 'me'. All business logic for 'me' is
   * validated at the provider layer for secure and accurate information
   * delivery.
   *
   * @param connection
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @UserAuth()
    user: UserPayload,
  ): Promise<ITodoListUser> {
    try {
      return await getTodoListUserUsersMe({
        user,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update the profile information for the currently authenticated user. This
   * endpoint allows users to update mutable fields in their own profile, such
   * as display name (global uniqueness not enforced per schema). Email address
   * changes are not permitted by policy and require dedicated flows; password
   * changes are handled elsewhere.
   *
   * Requests must be authenticated and reference the current session/JWT
   * context, with all input validated for correctness and completeness. Only
   * allowed fields are updatable; others will be ignored or cause validation
   * failure. The operation returns the updated user object so clients can
   * reflect UI changes or perform post-update logic. Audit timestamps are
   * updated per business rules, and changes are logged for compliance
   * purposes.
   *
   * All update logic is driven from the todo_list_users table and respects any
   * policy constraints on allowed self-updates. Security checks prevent one
   * user from updating another's profile via this endpoint.
   *
   * @param connection
   * @param body Fields to update for the current user, e.g. display name. Email
   *   and password updates are not permitted via this endpoint.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoListUser.IUpdate,
  ): Promise<ITodoListUser> {
    try {
      return await putTodoListUserUsersMe({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete the current authenticated user's account and all owned data,
   * including todos and every authentication/session trace.
   *
   * This operation is restricted to the user themselves—no account can be
   * deleted by anyone else, and no restoration, recovery, or cross-user
   * deletion is permitted. Access is strictly controlled at the business logic
   * and API middleware layer. On successful execution, the user's account row
   * from todo_list_users, all records from todo_list_todos belonging to the
   * user, and all session/audit records are fully and permanently removed from
   * the database.
   *
   * Security and privacy are paramount: this operation is only accessible to
   * authenticated users, and triggers immediate token/session revocation along
   * with all downstream deletions. All Prisma schema business rules regarding
   * foreign keys and parent-child relationships are enforced for database
   * consistency. Attempting to delete an account that does not belong to the
   * requester or that is not authenticated results in a clear access denied
   * error. There is no soft-deletion or retention—the removal is complete and
   * all data is purged.
   *
   * The operation assumes the user is certain about deletion, as recovery is
   * impossible. All session tokens are invalidated, and any further access will
   * require registration of a new account.
   *
   * @param connection
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @UserAuth()
    user: UserPayload,
  ): Promise<void> {
    try {
      return await deleteTodoListUserUsersMe({
        user,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
