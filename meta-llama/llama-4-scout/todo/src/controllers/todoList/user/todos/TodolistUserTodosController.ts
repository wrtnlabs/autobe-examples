import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postTodoListUserTodos } from "../../../../providers/postTodoListUserTodos";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { patchTodoListUserTodos } from "../../../../providers/patchTodoListUserTodos";
import { getTodoListUserTodosTodoId } from "../../../../providers/getTodoListUserTodosTodoId";
import { putTodoListUserTodosTodoId } from "../../../../providers/putTodoListUserTodosTodoId";
import { deleteTodoListUserTodosTodoId } from "../../../../providers/deleteTodoListUserTodosTodoId";

import { ITodoListTodo } from "../../../../api/structures/ITodoListTodo";
import { IPageITodoListTodo } from "../../../../api/structures/IPageITodoListTodo";

@Controller("/todoList/user/todos")
export class TodolistUserTodosController {
  /**
   * Create a new todo item in todo_list_todos.
   *
   * Create a new todo item for the current authenticated user. The operation
   * requires at minimum a trimmed, non-empty title between 1 and 100
   * characters, which must be unique within the user's list for business logic
   * clarity, though not enforced at the database level.
   *
   * Optionally, the user may specify a description (up to 1000 characters) and
   * a due date restricted to the present or future (ISO 8601 UTC format).
   * Initial completion status is always false unless explicitly provided;
   * completed_at must be null at creation. All timestamps
   * (created_at/updated_at) are generated by the system upon insertion.
   *
   * Authentication is mandatory, and the creating user is assigned as the owner
   * via the session/user principal without needing to pass a user ID in the
   * request. Immediate error responses are produced for invalid title length,
   * improperly formatted due dates, or attempts to create todos for other
   * users. This endpoint is the standard entry for all todo creation workflows
   * in the system.
   *
   * @param connection
   * @param body Information necessary to create a new todo item for the
   *   authenticated user.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoListTodo.ICreate,
  ): Promise<ITodoListTodo> {
    try {
      return await postTodoListUserTodos({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve a filtered, paginated list of todo items from
   * todo_list_todos table.
   *
   * Search and filter todo list items matching user-supplied criteria with
   * support for pagination and flexible sorting.
   *
   * This endpoint enables users and admins to retrieve lists of todo items,
   * specifying criteria such as completion status, associated user, and time
   * range.
   *
   * Security and filtering considerations are implemented according to the
   * requesting user's role and permissions. Only items visible or accessible to
   * the user will be returned. Pagination prevents overloading responses, while
   * input validation and error handling protect against malformed queries or
   * constraint violations.
   *
   * @param connection
   * @param body Search and filtering parameters for todo items (completion
   *   state, user, query, pagination, etc.)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoListTodo.IRequest,
  ): Promise<IPageITodoListTodo.ISummary> {
    try {
      return await patchTodoListUserTodos({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve complete details about a specific todo item by ID from
   * todo_list_todos table.
   *
   * Obtain full detail for a specific todo item by its unique identifier.
   *
   * This endpoint is designed to provide complete information for a particular
   * todo item, including all fields and metadata stored in the database.
   * Permissions and access control ensure that only authorized users can
   * retrieve this information.
   *
   * The response structure complies with the ITodoListTodo data model,
   * providing clients with all attributes necessary for viewing, editing, or
   * auditing the todo item. Error responses handle cases where the todo item
   * does not exist or access is denied.
   *
   * @param connection
   * @param todoId Unique identifier of the target todo item (UUID format, as
   *   defined by todo_list_todos schema)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":todoId")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
  ): Promise<ITodoListTodo> {
    try {
      return await getTodoListUserTodosTodoId({
        user,
        todoId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing todo item in todo_list_todos by unique todoId.
   *
   * Update an existing todo item belonging to the authenticated user. The
   * todoId parameter uniquely identifies the target todo, which must be owned
   * by the requesting user, preventing unauthorized access or edits.
   *
   * Field updates may include a new title (validated for trim and length), a
   * description (up to 1000 characters), a due date (present or future, ISO
   * 8601 format), and changes to completion status (is_completed and
   * completed_at handled automatically). System-managed columns updated_at and,
   * if applicable, completed_at are set at the time of update by the service
   * logic. Any transition of is_completed from false to true also updates
   * completed_at; resetting to false clears it.
   *
   * Attempting to update a todo not owned by the user, or passing invalid field
   * data (e.g., too long title/description, invalid dates, unauthorized changes
   * to other users' todos) results in a clear error. All validation rules
   * reflect the strict requirements and privacy model of the todo_list_todos
   * schema.
   *
   * @param connection
   * @param todoId Unique identifier of the target todo item to update.
   * @param body Fields and values to update for the specified todo item.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":todoId")
  public async update(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoListTodo.IUpdate,
  ): Promise<ITodoListTodo> {
    try {
      return await putTodoListUserTodosTodoId({
        user,
        todoId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a todo item from the todo_list_todos table.
   *
   * Permanently delete a todo item that belongs to the authenticated user. This
   * endpoint directly erases the specified todo from the todo_list_todos
   * table.
   *
   * Only the owner of the todo is permitted to perform this operation.
   * Authentication and authorization must be enforced at the application layer
   * to guarantee that each user can manage only their own todos. Attempting to
   * access or delete another user's todo will result in a forbidden error.
   *
   * Upon successful deletion, all information for the deleted todo is
   * immediately and irreversibly removed from persistent storage. This action
   * does not support recovery, soft delete, or undo. Auditability is provided
   * by the system's timestamping prior to deletion, but the record itself will
   * not exist after this operation. If the todo does not exist or the id is
   * invalid, a 404 Not Found error is returned.
   *
   * This operation should be used when the user intends to irreversibly remove
   * a task from their todo list, such as to clean up completed or abandoned
   * tasks. It is recommended to confirm user intent in the UI before invoking
   * this endpoint, as recovery is impossible post-deletion.
   *
   * @param connection
   * @param todoId Unique identifier of the target todo to delete (UUID format).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":todoId")
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoListUserTodosTodoId({
        user,
        todoId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
