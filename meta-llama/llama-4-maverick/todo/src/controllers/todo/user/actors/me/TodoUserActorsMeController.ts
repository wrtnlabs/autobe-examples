import { Controller } from "@nestjs/common";
import { TypedRoute } from "@nestia/core";
import typia from "typia";
import { getTodoUserActorsMe } from "../../../../../providers/getTodoUserActorsMe";
import { UserAuth } from "../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../decorators/payload/UserPayload";

import { ITodoUser } from "../../../../../api/structures/ITodoUser";

@Controller("/todo/user/actors/me")
export class TodoUserActorsMeController {
  /**
   * Retrieve the authenticated user profile from the todo_users table.
   *
   * Retrieve the profile and metadata for the currently authenticated user in
   * the Todo List application.
   *
   * This operation uses the authentication context to identify the user making
   * the request. It returns the user's unique email, registration and last
   * update timestamps, but omits password information and any administrative
   * fields to comply with privacy requirements.
   *
   * As the application supports only personal todo management, no roles or
   * group-level data are ever exposed. The endpoint is secured for self-use
   * only, meaning users cannot retrieve profiles for other users. Related
   * operations include updating credentials (handled elsewhere) and managing
   * session information.
   *
   * Errors occur if the requester is unauthenticated or if the underlying user
   * record cannot be found, for example if the account was deleted after
   * login.
   *
   * @param connection
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @UserAuth()
    user: UserPayload,
  ): Promise<ITodoUser> {
    try {
      return await getTodoUserActorsMe({
        user,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
