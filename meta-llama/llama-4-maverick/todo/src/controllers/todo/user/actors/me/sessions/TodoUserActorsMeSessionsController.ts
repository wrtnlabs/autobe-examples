import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchTodoUserActorsMeSessions } from "../../../../../../providers/patchTodoUserActorsMeSessions";
import { UserAuth } from "../../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../../decorators/payload/UserPayload";
import { getTodoUserActorsMeSessionsSessionId } from "../../../../../../providers/getTodoUserActorsMeSessionsSessionId";

import { IPageITodoUserSession } from "../../../../../../api/structures/IPageITodoUserSession";
import { ITodoUserSession } from "../../../../../../api/structures/ITodoUserSession";

@Controller("/todo/user/actors/me/sessions")
export class TodoUserActorsMeSessionsController {
  /**
   * List all sessions for the authenticated user from the todo_user_sessions
   * table.
   *
   * Retrieve a paginated and optionally filtered list of all current and past
   * session records for the authenticated user.
   *
   * The list can be filtered by connection time, expiration, and device/browser
   * context, and supports searching for session context details, including IP,
   * URL, and referrer. The returned data only includes sessions owned by the
   * currently authenticated user, enforcing strict privacy and ownership. This
   * operation is essential for security awareness and enables users to review
   * and manage device/browser logins.
   *
   * If provided, pagination and sorting parameters enable clients to
   * efficiently browse large session histories. Security errors are raised if
   * the requester is unauthenticated. The response always omits any information
   * about other users' sessions for privacy compliance.
   *
   * @param connection
   * @param body Optional search, pagination, and filter parameters for user
   *   session listing.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoUserSession.IRequest,
  ): Promise<IPageITodoUserSession> {
    try {
      return await patchTodoUserActorsMeSessions({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve authenticated user's own session by sessionId from
   * todo_user_sessions.
   *
   * This API operation allows an authenticated user to fetch the details of a
   * specific login session belonging to their own account. The sessionId path
   * parameter must reference a valid session record which is both owned by the
   * requesting user and exists in the todo_user_sessions table.
   *
   * Only the session data for the current user is accessible—attempting to
   * query a session owned by another user will result in a clear access-denied
   * error, as mandated by strict privacy requirements. The payload includes all
   * session audit and context fields (IP, href, referrer, created_at,
   * expired_at), making this endpoint essential for session management and user
   * transparency.
   *
   * Security is enforced via both path checking (me = current user context) and
   * foreign key validation. This endpoint does not permit the creation, update,
   * or deletion of sessions—administrative modification is intentionally
   * excluded to comply with requirements that sessions are managed exclusively
   * via authentication flows.
   *
   * @param connection
   * @param sessionId Unique identifier (UUID) for the login session to be
   *   viewed. Must belong to the current authenticated user and exist in
   *   todo_user_sessions.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<ITodoUserSession> {
    try {
      return await getTodoUserActorsMeSessionsSessionId({
        user,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
