import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postTodoUserTodos } from "../../../../providers/postTodoUserTodos";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { patchTodoUserTodos } from "../../../../providers/patchTodoUserTodos";
import { getTodoUserTodosTodoId } from "../../../../providers/getTodoUserTodosTodoId";
import { putTodoUserTodosTodoId } from "../../../../providers/putTodoUserTodosTodoId";
import { deleteTodoUserTodosTodoId } from "../../../../providers/deleteTodoUserTodosTodoId";

import { ITodoTodo } from "../../../../api/structures/ITodoTodo";
import { IPageITodoTodo } from "../../../../api/structures/IPageITodoTodo";

@Controller("/todo/user/todos")
export class TodoUserTodosController {
  /**
   * Create a new todo_todos record for the authenticated user with title and
   * optional details.
   *
   * Create a new personal todo item for the authenticated user.
   *
   * This API endpoint allows users to add a task to their private list,
   * specifying a required title along with optional details such as
   * description, due date, and priority. Upon creation, the todo is linked to
   * the user's account (user_id is assigned server-side) and marked incomplete
   * by default.
   *
   * Business rules enforce uniqueness of title and due date per user to avoid
   * accidental duplicate entries, as defined by the unique index in the schema.
   * Security is enforced by bypassing any external user_id in the request body;
   * only the session's user is honored. On success, the API returns the
   * complete todo record as persisted in the database, including all audit
   * fields and associations. The operation aligns with the todo_todos database
   * schema and respects all privacy boundaries.
   *
   * @param connection
   * @param body Details for creating a new todo item: title (required), and
   *   optional description, due_date, priority.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoTodo.ICreate,
  ): Promise<ITodoTodo> {
    try {
      return await postTodoUserTodos({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search, filter, and paginate the authenticated user's own todos using
   * advanced criteria from todo_todos.
   *
   * This API operation provides a paginated list of personal todo items for the
   * authenticated user, supporting business rule-driven filtering, sorting, and
   * searching. The operation accepts a complex search/filter request body
   * aligned with ITodoTodo.IRequest, which allows filtering by completion
   * status, due date, priority (restricted to 'low', 'medium', or 'high'), and
   * full-text search on both the title and the description fields.
   *
   * Only the requesting user's own todos are included in the result set,
   * ensuring privacy per requirements. The response contains paginated summary
   * information for each todo, including metadata such as creation/update
   * timestamps, status, and all custom fields visible to the user (from
   * todo_todos). Pagination and sorting follow standard conventions to support
   * efficient list views in the UI.
   *
   * This endpoint does not expose any information from other users' todos,
   * ensuring strict business and security rules are upheld. All filtering and
   * sorting are performed server-side for performance and data security.
   *
   * @param connection
   * @param body Advanced search, filter, sorting, and paging options for
   *   querying user's own todos. Refer to ITodoTodo.IRequest for available
   *   request fields.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoTodo.IRequest,
  ): Promise<IPageITodoTodo.ISummary> {
    try {
      return await patchTodoUserTodos({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single todo item (todo_todos) by ID for the authenticated user.
   *
   * Retrieve a single todo item by its unique identifier for the authenticated
   * user.
   *
   * This endpoint allows users to view the details of an individual todo,
   * including title, description, due date, priority, completion status, and
   * all associated timestamps. All data returned is strictly limited to the
   * requesting user's own todos; access to other users' todos is not permitted
   * under business privacy rules.
   *
   * Security checks are enforced, verifying that the todoId provided belongs to
   * the currently authenticated user in the system. Attempts to access another
   * user's todo will result in a not found or forbidden response. The operation
   * references the todo_todos table from the database schema and covers all
   * base fields as documented. Error handling includes missing or invalid
   * identifiers and unauthorized access attempts.
   *
   * Related operations include creating a new todo (POST /todos) and searching
   * a user's todos (PATCH /todos).
   *
   * @param connection
   * @param todoId Unique identifier (UUID) of the todo item. Must belong to the
   *   authenticated user.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":todoId")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
  ): Promise<ITodoTodo> {
    try {
      return await getTodoUserTodosTodoId({
        user,
        todoId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update a specific todo item in the todo_todos table.
   *
   * Update a user's personal todo item with new attributes.
   *
   * The operation allows an authenticated user to modify the title,
   * description, due date, priority, and completion status of a todo item they
   * own. Updates are subject to business validation rules from the Prisma
   * schema, including unique constraints on title and due date per user,
   * preservation of task privacy, and correct handling of date and priority
   * fields as described in the schema comments.
   *
   * Authentication is required; only the owning user can update their todos.
   * Attempts to update a todo owned by another user result in access denial.
   * The system automatically manages audit fields for tracking changes.
   *
   * Clients are expected to send only modifiable fields in the request body,
   * using the ITodoTodo.IUpdate type. In case of conflict with validation rules
   * or ownership, detailed error messages are returned. This operation centers
   * on direct user-driven management of their todo list, with robust
   * schema-driven protections against data leakage or integrity violation.
   *
   * @param connection
   * @param todoId Primary Key. Unique identifier for a todo item.
   * @param body Fields to update for the specified todo. Follows schema
   *   validations and uniqueness constraints per user.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":todoId")
  public async update(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoTodo.IUpdate,
  ): Promise<ITodoTodo> {
    try {
      return await putTodoUserTodosTodoId({
        user,
        todoId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a user's specific todo item from the todo_todos table.
   *
   * Permanently remove a personal todo item from the authenticated user's list.
   *
   * This operation enforces strict ownership validation: only the owner of a
   * todo may delete it, as verified by the user_id foreign key. No soft
   * deletion is performed—deleted records are gone permanently in accordance
   * with the schema's business rules and design comments. This supports a
   * privacy-first model in which each user's todos are fully private and
   * isolated.
   *
   * The delete is final and does not affect any shared or public data, as todos
   * are never shared. Operations track access, validate user ownership, and
   * fail with appropriate messages for unauthorized attempts. Users must
   * exercise caution when invoking this endpoint, given the irreversible nature
   * of the operation. The response confirms the deleted todo item data
   * immediately before deletion.
   *
   * @param connection
   * @param todoId Primary Key. Unique identifier for a todo item.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":todoId")
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
  ): Promise<ITodoTodo> {
    try {
      return await deleteTodoUserTodosTodoId({
        user,
        todoId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
