import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postTodoListUserTasks } from "../../../../providers/postTodoListUserTasks";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { putTodoListUserTasksTaskId } from "../../../../providers/putTodoListUserTasksTaskId";

import { ITodoListTask } from "../../../../api/structures/ITodoListTask";

@Controller("/todoList/user/tasks")
export class TodolistUserTasksController {
  /**
   * This operation creates a new task in the todo list system. It requires
   * details such as task title, description, due date, and priority. The task
   * is associated with the authenticated user who initiates the creation. The
   * operation validates the input data to ensure that required fields are
   * provided and that the task details are consistent with the system's
   * constraints.
   *
   * @param connection
   * @param body Details of the task to be created
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoListTask.ICreate,
  ): Promise<ITodoListTask> {
    try {
      return await postTodoListUserTasks({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This operation updates an existing task identified by its unique task ID.
   * It allows users to modify various task attributes and is typically used to
   * mark tasks as completed or to update task details. The operation checks for
   * the existence of the task and validates the user's authorization to update
   * the task.
   *
   * @param connection
   * @param taskId The unique identifier of the task to be updated
   * @param body Updated details of the task
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":taskId")
  public async update(
    @UserAuth()
    user: UserPayload,
    @TypedParam("taskId")
    taskId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoListTask.IUpdate,
  ): Promise<ITodoListTask> {
    try {
      return await putTodoListUserTasksTaskId({
        user,
        taskId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
