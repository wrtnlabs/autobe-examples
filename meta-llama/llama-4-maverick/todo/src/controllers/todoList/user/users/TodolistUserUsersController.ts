import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchTodoListUserUsers } from "../../../../providers/patchTodoListUserUsers";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { getTodoListUserUsersUserId } from "../../../../providers/getTodoListUserUsersUserId";
import { putTodoListUserUsersUserId } from "../../../../providers/putTodoListUserUsersUserId";

import { IPageITodoListUser } from "../../../../api/structures/IPageITodoListUser";
import { ITodoListUser } from "../../../../api/structures/ITodoListUser";

@Controller("/todoList/user/users")
export class TodolistUserUsersController {
  /**
   * Search and retrieve a filtered, paginated list of users.
   *
   * Retrieve a filtered and paginated list of users from the system. This
   * operation provides advanced search capabilities for finding users based on
   * multiple criteria including partial name matching, email domain filtering,
   * registration date ranges, and account status.
   *
   * The operation supports comprehensive pagination with configurable page
   * sizes and sorting options. Users can sort by registration date, last login,
   * name, or other relevant fields in ascending or descending order.
   *
   * Security considerations include rate limiting for search operations and
   * appropriate filtering of sensitive user information based on the requesting
   * user's authorization level. Only users with appropriate permissions can
   * access detailed user information, while basic user lists may be available
   * to authenticated users.
   *
   * This operation integrates with the User table as defined in the Prisma
   * schema, incorporating all available user fields and relationships. The
   * response includes user summary information optimized for list displays,
   * with options to include additional details based on authorization level.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for user filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoListUser.IRequest,
  ): Promise<IPageITodoListUser.ISummary> {
    try {
      return await patchTodoListUserUsers({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single user by ID.
   *
   * Retrieve detailed information about a specific user identified by their
   * unique user ID. This operation returns the user's profile data, related
   * entities, and other relevant information as defined in the Prisma schema.
   *
   * Security considerations include proper authorization checks to ensure that
   * only authorized users can access the requested user's information. The
   * operation may include additional validation for sensitive data access.
   *
   * The response includes comprehensive user information, potentially including
   * related data such as associated entities or activity history, depending on
   * the user's authorization level and the data's availability.
   *
   * @param connection
   * @param userId Unique identifier of the target user
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":userId")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
  ): Promise<ITodoListUser> {
    try {
      return await getTodoListUserUsersUserId({
        user,
        userId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update user information.
   *
   * This operation updates the details of an existing user identified by their
   * user ID. It requires appropriate authorization and follows the
   * IUser.IUpdate schema for the request body. The user ID is a path parameter
   * that must be provided in the URL.
   *
   * @param connection
   * @param userId The unique identifier of the user to be updated
   * @param body The updated user information
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":userId")
  public async updateUser(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoListUser.IUpdate,
  ): Promise<ITodoListUser> {
    try {
      return await putTodoListUserUsersUserId({
        user,
        userId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
