import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia from "typia";
import { patchTodoListUserUsersUserIdSessions } from "../../../../../providers/patchTodoListUserUsersUserIdSessions";
import { UserAuth } from "../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../decorators/payload/UserPayload";
import { getTodoListUserUsersUserIdSessionsSessionId } from "../../../../../providers/getTodoListUserUsersUserIdSessionsSessionId";

import { IPageITodoListUserSession } from "../../../../../api/structures/IPageITodoListUserSession";
import { ITodoListUserSession } from "../../../../../api/structures/ITodoListUserSession";

@Controller("/todoList/user/users/:userId/sessions")
export class TodolistUserUsersSessionsController {
  /**
   * Retrieve a list of user sessions for a specific user identified by their
   * user ID. The operation validates the user ID and returns a list of session
   * objects containing details such as IP address, login time, and session
   * status. It requires appropriate authorization to access user session
   * information.
   *
   * @param connection
   * @param userId The unique identifier of the user
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string,
  ): Promise<IPageITodoListUserSession> {
    try {
      return await patchTodoListUserUsersUserIdSessions({
        user,
        userId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Get a specific user session by user ID and session ID. The operation
   * validates both the user ID and session ID, then returns the session details
   * if the requesting user is authorized to access the session information.
   *
   * @param connection
   * @param userId The unique identifier of the user
   * @param sessionId The unique identifier of the session
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string,
    @TypedParam("sessionId")
    sessionId: string,
  ): Promise<ITodoListUserSession> {
    try {
      return await getTodoListUserUsersUserIdSessionsSessionId({
        user,
        userId,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
