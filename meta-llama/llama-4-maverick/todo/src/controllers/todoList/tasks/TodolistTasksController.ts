import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchTodoListTasks } from "../../../providers/patchTodoListTasks";
import { getTodoListTasksTaskId } from "../../../providers/getTodoListTasksTaskId";
import { deleteTodoListTasksTaskId } from "../../../providers/deleteTodoListTasksTaskId";

import { IPageITodoListTask } from "../../../api/structures/IPageITodoListTask";
import { ITodoListTask } from "../../../api/structures/ITodoListTask";

@Controller("/todoList/tasks")
export class TodolistTasksController {
  /**
   * Search and retrieve tasks with filtering and pagination.
   *
   * This operation provides advanced search capabilities for tasks, allowing
   * users to filter by multiple criteria, sort results, and paginate through
   * large datasets. It supports complex queries and returns a paginated list of
   * tasks matching the search criteria.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for task filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: ITodoListTask.IRequest,
  ): Promise<IPageITodoListTask.ISummary> {
    try {
      return await patchTodoListTasks({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific task by ID.
   *
   * This operation fetches a single task identified by its unique task ID. It
   * returns comprehensive details about the task, including its current status,
   * description, and any relevant metadata. This is useful for viewing task
   * details or for further processing in subsequent operations.
   *
   * @param connection
   * @param taskId Unique identifier of the task to retrieve
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":taskId")
  public async at(
    @TypedParam("taskId")
    taskId: string & tags.Format<"uuid">,
  ): Promise<ITodoListTask> {
    try {
      return await getTodoListTasksTaskId({
        taskId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a specific task by ID.
   *
   * Deletes a task identified by the taskId path parameter. This operation
   * permanently removes the task from the database. The taskId must be a valid
   * UUID corresponding to an existing task. Upon successful deletion, the
   * operation returns a confirmation.
   *
   * @param connection
   * @param taskId Unique identifier of the task to be deleted
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":taskId")
  public async erase(
    @TypedParam("taskId")
    taskId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoListTasksTaskId({
        taskId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
