import { Controller, Ip } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthUserJoin } from "../../../providers/postAuthUserJoin";
import { postAuthUserLogin } from "../../../providers/postAuthUserLogin";
import { postAuthUserRefresh } from "../../../providers/postAuthUserRefresh";

import { ITodoUser } from "../../../api/structures/ITodoUser";

@Controller("/auth/user")
export class AuthUserController {
  /**
   * Register a new todo user in todo_users table and issue initial JWT tokens.
   *
   * This endpoint enables a new todo user to register for personal access to
   * the service, directly creating a record in the 'todo_users' table. All
   * fields required for account creation, such as username and password, are
   * validated against the schema constraints. Uniqueness of username is
   * enforced at the database level according to comments on
   * 'todo_users.username'.
   *
   * The join process is critical for user onboarding, as described in the
   * requirements. Upon successful registration, the system issues a JWT-based
   * access token and refresh token, following the platform's authentication
   * policy. No authentication or prior session is needed to call this
   * endpoint.
   *
   * Business context: The registering todo user establishes a secure identity
   * in the application, enabling secure ownership of todo items and
   * associations with their sessions in 'todo_user_sessions'.
   *
   * Security practices such as email verification or password constraints are
   * enforced according to project requirements documented in analysis files and
   * the 'todo_users' schema. Detailed error reporting is provided for failed
   * registration attempts.
   *
   * This operation is closely related to the user login and token refresh
   * operations, serving as the initial entry point to the authentication
   * workflow for 'user' actors.
   *
   * @param connection
   * @param body The required registration data for a new todo user, as defined
   *   by ITodoUser.ICreate schema (matches fields in todo_users table needed
   *   for account creation).
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoUser.ICreate,
  ): Promise<ITodoUser.IAuthorized> {
    try {
      return await postAuthUserJoin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate todo user in todo_users table and issue new JWT tokens.
   *
   * Authenticate an existing todo user via credentials stored in the
   * 'todo_users' schema. The endpoint validates the username and password
   * exactly as described in schema comments or requirements for secure
   * authentication.
   *
   * Upon successful authentication, a new JWT-based access token and refresh
   * token are generated and returned to the user in the ITodoUser.IAuthorized
   * DTO structure. Failed login attempts (e.g., invalid credentials) result in
   * standard error responses following error handling policy.
   *
   * This operation implements the core authentication logic needed for a user
   * to access the todo API securely. It is publicly accessible but enforces
   * strict validation for login data.
   *
   * Business context: Successful login links the authenticated user to their
   * personal todo data through 'todo_user_sessions', as described in business
   * requirements.
   *
   * Closely related operations: user registration (join) and token refresh,
   * which together provide full authentication capability for the 'user'
   * actor.
   *
   * @param connection
   * @param body Login credentials corresponding to a user in todo_users.
   *   Defined by ITodoUser.ILogin DTO (must match schema fields for credential
   *   authentication).
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoUser.ILogin,
  ): Promise<ITodoUser.IAuthorized> {
    try {
      return await postAuthUserLogin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh JWT authentication tokens for todo user using a valid refresh
   * token.
   *
   * Refresh JWT tokens for a todo user, validating the provided refresh token
   * according to session records in 'todo_user_sessions' schema.
   *
   * This endpoint is accessible only with a valid refresh token, and returns
   * new access and refresh tokens as specified in schema and requirements.
   * Security policies on refreshing and revoking tokens are enforced as
   * described in the service configuration.
   *
   * Business context: Token refresh links authenticated clients to their
   * ongoing user sessions and allows seamless access to todo data.
   *
   * Closely related endpoints: user login (issue tokens with credentials) and
   * registration (initial join and token provisioning). Together, these
   * endpoints enable a secure, session-based authentication workflow for todo
   * users.
   *
   * Error conditions such as expired, revoked, or invalid tokens are handled
   * precisely as documented in error-handling requirements and schema
   * comments.
   *
   * @param connection
   * @param body Refresh token data as required for the session, matching
   *   ITodoUser.IRefresh DTO definition.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: ITodoUser.IRefresh,
  ): Promise<ITodoUser.IAuthorized> {
    try {
      return await postAuthUserRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
