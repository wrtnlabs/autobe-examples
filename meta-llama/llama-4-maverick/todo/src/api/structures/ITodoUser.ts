import { tags } from "typia";

import { IAuthorizationToken } from "./IAuthorizationToken";

/**
 * User accounts for personal todo management.
 *
 * Represents an authenticated user of the Todo List application. Each user has
 * a unique email and a securely set password (never exposed by this schema).
 * The profile exposes account metadata only for the authenticated user,
 * strictly omitting any role, group, or administrative fields. This guarantees
 * privacy and ensures only account holders can access this information.
 * Timestamps support UX and audit logging. All user management operations refer
 * to this type.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type ITodoUser = {
  /**
   * Primary Key. Unique identifier for the user. Assigned upon account
   * creation and used for authentication and entity relations.
   */
  id: string & tags.Format<"uuid">;

  /**
   * Email address used for account authentication and identifier. Must be
   * unique across all users. Serves as the login principal and for password
   * resets.
   */
  email: string & tags.Format<"email">;

  /**
   * Timestamp when the user account was created (UTC). Used for audit and
   * business reporting.
   */
  created_at: string & tags.Format<"date-time">;

  /**
   * Timestamp of the last change to this user account (credentials, metadata,
   * etc.). Allows business auditing and security checks.
   */
  updated_at: string & tags.Format<"date-time">;
};
export namespace ITodoUser {
  /**
   * Request body schema for registering a new todo user in the system.
   * Corresponds to the creation of a record in the 'todo_users' table and
   * enforces unique, secure user authentication. This schema accepts all and
   * only the fields required for user self-registration, deferring identity
   * context and system-managed fields to the backend. Registration is the
   * foundational entry for todo system authentication workflows.
   *
   * The schema includes required fields for account creation according to the
   * database schema: a unique email and a password (plain text for validation
   * and hashing, never a hash). It enforces business logic documented in the
   * schema comments—such as uniqueness and required validation rules for the
   * email field. System-managed information like IDs or timestamps, and
   * authentication context fields are not included. Password security,
   * uniqueness, and field validation are described in the provider's security
   * requirements.
   *
   * Business context: After submission, the backend will create a secure user
   * record, hash the password, and issue an authentication token.
   */
  export type ICreate = {
    /**
     * User's email address for authentication. Must be unique across all
     * users. This field is required for account creation and subsequent
     * login. Must be a valid RFC 5322 email address per schema comments and
     * API requirements.
     */
    email: string & tags.Format<"email">;

    /**
     * User's account password (plain text, will be hashed on the backend).
     * Minimum length 8 characters. Should not be stored or logged in plain
     * text. Must satisfy password policy from requirements.
     */
    password: string & tags.MinLength<8> & tags.MaxLength<128>;

    /**
     * Current connection URL (the client page from which the registration
     * was made). Used for audit and security context tracking. Required for
     * self-registration by the actor.
     */
    href: string & tags.Format<"uri">;

    /**
     * Referrer URL captured at the time of registration. Provides context
     * around the user journey leading to registration. Required for session
     * context.
     */
    referrer: string & tags.Format<"uri">;

    /**
     * Optional client IP address. Can be null if not provided by client.
     * Used for session audit and fraud detection. The server may also
     * extract this. Not required, but included for SSR and audit
     * scenarios.
     */
    ip?:
      | (string & tags.Format<"ipv4">)
      | (string & tags.Format<"ipv6">)
      | null
      | undefined;
  };

  /**
   * Response body schema for authenticated todo user after registration,
   * login, or token refresh. Delivers the JWT tokens and essential authorized
   * user context as required for authenticated API communication. Used as the
   * return type for both join and login flows (and refresh).
   *
   * This schema delivers a newly issued JWT token and refresh token as a
   * nested IAuthorizationToken reference, along with the basic identifying
   * context for the authorized user. Tokens enable continued authenticated
   * access and association with the underlying todo user records. This type
   * is atomic for authentication—contains only what the client and server
   * need post-authentication (no password field).
   *
   * Fulfills atomicity for authentication responses, ensuring clients receive
   * all information needed to establish or refresh an authenticated session.
   */
  export type IAuthorized = {
    /**
     * Unique identifier for the authorized todo user. Maps to todo_users.id
     * in the database. Identifies the principal for all future client
     * activity.
     */
    id: string & tags.Format<"uuid">;

    /**
     * Email address used for account authentication and identifier. Must be
     * unique across all users. Serves as the login principal and for
     * password resets.
     */
    email: string & tags.Format<"email">;

    /**
     * Timestamp when the user account was created (UTC). Used for audit and
     * business reporting.
     */
    created_at: string & tags.Format<"date-time">;

    /**
     * Timestamp of the last change to this user account (credentials,
     * metadata, etc.). Allows business auditing and security checks.
     */
    updated_at: string & tags.Format<"date-time">;

    /** JWT token information for authentication */
    token: IAuthorizationToken;
  };

  /**
   * Login credentials for the todo user authentication flow.
   *
   * Contains the fields required for credential verification against the
   * 'todo_users' table, supporting secure login via email and password as
   * described in requirements.
   *
   * Session context fields (href and referrer) are required to comply with
   * audit, security, and session management, enabling tracing of login
   * activity per business rules. IP is optional and, if absent, should be
   * captured from the connection by the backend.
   *
   * Never include password hashes or non-plain secrets; clients MUST only
   * submit plain passwords, which are hashed server-side. See security
   * rules.
   */
  export type ILogin = {
    /**
     * User's unique email address for authentication. Must match an email
     * in the 'todo_users' database table. Used as the login identifier.
     */
    email: string & tags.Format<"email">;

    /**
     * Plain user password to be authenticated. NEVER hashed in the request.
     * Backend will verify this against the stored password_hash.
     */
    password: string;

    /**
     * Client IP address for audit logging and context tracking. Useful for
     * tracing suspicious login activity. Optional: backend will supply if
     * the frontend omits.
     */
    ip?: string | null | undefined;

    /**
     * URL that the client was visiting at time of login. Required for
     * proper session and audit trail. Used for UX/analytics.
     */
    href: string & tags.Format<"uri">;

    /**
     * The referring URL provided by the browser/client when login was
     * triggered. Required for session context and audit purpose.
     */
    referrer: string & tags.Format<"uri">;
  };

  /**
   * Refresh token request for authenticated todo users.
   *
   * Used to obtain new authentication tokens (JWT) by presenting a valid
   * refresh token issued during a prior login. Ensures continued access while
   * maintaining security as defined in requirements and session schema rules.
   * Structure is minimal, only requiring the token for renewal.
   */
  export type IRefresh = {
    /**
     * Refresh token string previously issued to the user via
     * ITodoUser.IAuthorized. Required to validate and issue new
     * access/refresh tokens.
     */
    refresh_token: string;
  };
}
