  export const METADATA = {
    method: "PATCH",
    path: "/todoList/tasks",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/todoList/tasks";
