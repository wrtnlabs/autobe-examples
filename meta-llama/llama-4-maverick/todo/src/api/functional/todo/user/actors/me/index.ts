import { IConnection } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";

import { ITodoUser } from "../../../../../structures/ITodoUser";
export * as sessions from "./sessions/index";

/**
 * Retrieve the authenticated user profile from the todo_users table.
 *
 * Retrieve the profile and metadata for the currently authenticated user in the
 * Todo List application.
 *
 * This operation uses the authentication context to identify the user making
 * the request. It returns the user's unique email, registration and last update
 * timestamps, but omits password information and any administrative fields to
 * comply with privacy requirements.
 *
 * As the application supports only personal todo management, no roles or
 * group-level data are ever exposed. The endpoint is secured for self-use only,
 * meaning users cannot retrieve profiles for other users. Related operations
 * include updating credentials (handled elsewhere) and managing session
 * information.
 *
 * Errors occur if the requester is unauthenticated or if the underlying user
 * record cannot be found, for example if the account was deleted after login.
 *
 * @param props.connection
 * @path /todo/user/actors/me
 * @accessor api.functional.todo.user.actors.me.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(connection: IConnection): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(),
          status: null,
        },
      );
}
export namespace at {
  export type Response = ITodoUser;

  export const METADATA = {
    method: "GET",
    path: "/todo/user/actors/me",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/todo/user/actors/me";
  export const random = (): ITodoUser => typia.random<ITodoUser>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}
