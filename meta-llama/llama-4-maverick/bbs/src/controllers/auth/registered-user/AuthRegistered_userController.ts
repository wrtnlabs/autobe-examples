import { Controller, Ip } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthRegisteredUserJoin } from "../../../providers/postAuthRegisteredUserJoin";
import { postAuthRegisteredUserLogin } from "../../../providers/postAuthRegisteredUserLogin";
import { postAuthRegisteredUserRefresh } from "../../../providers/postAuthRegisteredUserRefresh";

import { IDiscussionBoardRegisteredUser } from "../../../api/structures/IDiscussionBoardRegisteredUser";
import { IAuthRefresh } from "../../../api/structures/IAuthRefresh";

@Controller("/auth/registered-user")
export class AuthRegistered_userController {
  /**
   * This operation creates a new registered user account in the system. It
   * requires user registration information such as username, email, and
   * password. The operation validates the input data, creates the user record
   * in the database, and generates an access token for the new user.
   *
   * The request body must contain the necessary user details as defined in the
   * IRegisteredUser.ICreate schema.
   *
   * Upon successful creation, the response includes the new user's information
   * and an access token as defined in the
   * IDiscussionBoardRegisteredUser.IAuthorized schema.
   *
   * This operation is public and does not require authentication.
   *
   * @param connection
   * @param body New user registration information
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IDiscussionBoardRegisteredUser.ICreate,
  ): Promise<IDiscussionBoardRegisteredUser.IAuthorized> {
    try {
      return await postAuthRegisteredUserJoin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This operation authenticates a registered user based on their login
   * credentials. It requires the user's email/username and password.
   *
   * The request body must contain the login credentials as defined in the
   * IRegisteredUser.ILogin schema.
   *
   * Upon successful authentication, the response includes the user's
   * information and an access token as defined in the
   * IDiscussionBoardRegisteredUser.IAuthorized schema.
   *
   * This operation is public and does not require authentication.
   *
   * @param connection
   * @param body User login credentials
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IDiscussionBoardRegisteredUser.ILogin,
  ): Promise<IDiscussionBoardRegisteredUser.IAuthorized> {
    try {
      return await postAuthRegisteredUserLogin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This operation refreshes the access token for an authenticated registered
   * user using their refresh token.
   *
   * The request body must contain the refresh token as defined in the
   * IAuthRefresh.IRequest schema.
   *
   * Upon successful refresh, the response includes the new access token
   * information as defined in the IDiscussionBoardRegisteredUser.IAuthorized
   * schema.
   *
   * This operation is protected and requires a valid refresh token.
   *
   * @param connection
   * @param body Refresh token information
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IAuthRefresh.IRequest,
  ): Promise<IDiscussionBoardRegisteredUser.IAuthorized> {
    try {
      return await postAuthRegisteredUserRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
