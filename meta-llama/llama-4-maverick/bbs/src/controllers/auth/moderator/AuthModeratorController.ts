import { Controller, Ip } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthModeratorJoin } from "../../../providers/postAuthModeratorJoin";
import { postAuthModeratorLogin } from "../../../providers/postAuthModeratorLogin";
import { postAuthModeratorRefresh } from "../../../providers/postAuthModeratorRefresh";

import { IDiscussionBoardModerator } from "../../../api/structures/IDiscussionBoardModerator";

@Controller("/auth/moderator")
export class AuthModeratorController {
  /**
   * Create a new moderator account
   *
   * The moderator registration operation creates a new moderator account in the
   * system. This operation is crucial for adding new moderators who will manage
   * content and handle user reports.
   *
   * ### Purpose and Functionality
   *
   * The moderator registration operation allows administrators to create new
   * moderator accounts. It requires essential information such as username,
   * email, and password.
   *
   * ### Implementation
   *
   * The operation is implemented as a POST request to `/auth/moderator/join`.
   * The request body includes the necessary details for creating a moderator
   * account, such as username, email, and password.
   *
   * ### Related Operations
   *
   * This operation is related to other authentication operations such as login
   * and refresh token operations.
   *
   * @param connection
   * @param body Moderator registration information
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IDiscussionBoardModerator.ICreate,
  ): Promise<IDiscussionBoardModerator.IAuthorized> {
    try {
      return await postAuthModeratorJoin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate a moderator
   *
   * The moderator login operation authenticates a moderator in the system. This
   * operation is crucial for allowing moderators to access their accounts and
   * perform their duties.
   *
   * ### Purpose and Functionality
   *
   * The moderator login operation allows moderators to authenticate themselves
   * using their credentials. It requires information such as username/email and
   * password.
   *
   * ### Implementation
   *
   * The operation is implemented as a POST request to `/auth/moderator/login`.
   * The request body includes the necessary details for authenticating a
   * moderator, such as username/email and password.
   *
   * ### Related Operations
   *
   * This operation is related to other authentication operations such as
   * registration and refresh token operations.
   *
   * @param connection
   * @param body Moderator login credentials
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IDiscussionBoardModerator.ILogin,
  ): Promise<IDiscussionBoardModerator.IAuthorized> {
    try {
      return await postAuthModeratorLogin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh moderator's access token
   *
   * The moderator refresh token operation refreshes the access token for a
   * moderator. This operation is crucial for maintaining the moderator's
   * session without requiring them to log in again.
   *
   * ### Purpose and Functionality
   *
   * The moderator refresh token operation allows moderators to obtain a new
   * access token using their refresh token. It requires the refresh token in
   * the request body.
   *
   * ### Implementation
   *
   * The operation is implemented as a POST request to
   * `/auth/moderator/refresh`. The request body includes the refresh token.
   *
   * ### Related Operations
   *
   * This operation is related to other authentication operations such as login
   * and registration.
   *
   * @param connection
   * @param body Refresh token for the moderator
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IDiscussionBoardModerator.IRefresh,
  ): Promise<IDiscussionBoardModerator.IAuthorized> {
    try {
      return await postAuthModeratorRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
