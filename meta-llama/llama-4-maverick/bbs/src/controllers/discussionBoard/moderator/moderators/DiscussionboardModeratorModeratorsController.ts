import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchDiscussionBoardModeratorModerators } from "../../../../providers/patchDiscussionBoardModeratorModerators";
import { ModeratorAuth } from "../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../decorators/payload/ModeratorPayload";
import { getDiscussionBoardModeratorModeratorsModeratorId } from "../../../../providers/getDiscussionBoardModeratorModeratorsModeratorId";

import { IPageIDiscussionBoardModerator } from "../../../../api/structures/IPageIDiscussionBoardModerator";
import { IDiscussionBoardModerator } from "../../../../api/structures/IDiscussionBoardModerator";

@Controller("/discussionBoard/moderator/moderators")
export class DiscussionboardModeratorModeratorsController {
  /**
   * Search and retrieve a filtered list of moderators.
   *
   * Retrieve a list of moderators with advanced filtering and pagination. This
   * operation allows administrators to search for moderators based on various
   * criteria such as name, email, status, and permissions. It supports complex
   * queries and returns a paginated result set.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for moderators
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedBody()
    body: IDiscussionBoardModerator.IRequest,
  ): Promise<IPageIDiscussionBoardModerator.ISummary> {
    try {
      return await patchDiscussionBoardModeratorModerators({
        moderator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific moderator.
   *
   * Get detailed information about a moderator by their unique identifier. This
   * operation returns comprehensive details about the moderator, including
   * their permissions, status, and activity history. It is designed for
   * administrative use to monitor and manage moderator activities.
   *
   * @param connection
   * @param moderatorId Unique identifier of the moderator
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":moderatorId")
  public async at(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("moderatorId")
    moderatorId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardModerator> {
    try {
      return await getDiscussionBoardModeratorModeratorsModeratorId({
        moderator,
        moderatorId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
