import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchDiscussionBoardModeratorReportedContent } from "../../../../providers/patchDiscussionBoardModeratorReportedContent";
import { ModeratorAuth } from "../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../decorators/payload/ModeratorPayload";
import { getDiscussionBoardModeratorReportedContentReportedContentId } from "../../../../providers/getDiscussionBoardModeratorReportedContentReportedContentId";

import { IPageIDiscussionBoardReportedContent } from "../../../../api/structures/IPageIDiscussionBoardReportedContent";
import { IDiscussionBoardReportedContent } from "../../../../api/structures/IDiscussionBoardReportedContent";

@Controller("/discussionBoard/moderator/reportedContent")
export class DiscussionboardModeratorReportedcontentController {
  /**
   * Retrieves a paginated list of reported content from the discussion board,
   * allowing moderators to filter by report status, content type, and other
   * criteria. Supports sorting and pagination parameters.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering
   *   reported content
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async searchReportedContent(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedBody()
    body: IDiscussionBoardReportedContent.IRequest,
  ): Promise<IPageIDiscussionBoardReportedContent.ISummary> {
    try {
      return await patchDiscussionBoardModeratorReportedContent({
        moderator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This operation allows moderators to retrieve detailed information about a
   * specific reported content item. The reportedContentId path parameter is
   * used to identify the content. The response includes the content details,
   * reporting reason, and any additional metadata associated with the reported
   * content.
   *
   * @param connection
   * @param reportedContentId Unique identifier of the reported content item
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":reportedContentId")
  public async at(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("reportedContentId")
    reportedContentId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardReportedContent> {
    try {
      return await getDiscussionBoardModeratorReportedContentReportedContentId({
        moderator,
        reportedContentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
