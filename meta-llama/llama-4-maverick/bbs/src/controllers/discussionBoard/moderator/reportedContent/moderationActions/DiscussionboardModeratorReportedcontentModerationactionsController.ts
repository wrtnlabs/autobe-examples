import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchDiscussionBoardModeratorReportedContentReportedContentIdModerationActions } from "../../../../../providers/patchDiscussionBoardModeratorReportedContentReportedContentIdModerationActions";
import { ModeratorAuth } from "../../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../../decorators/payload/ModeratorPayload";

import { IDiscussionBoardModerationAction } from "../../../../../api/structures/IDiscussionBoardModerationAction";

@Controller(
  "/discussionBoard/moderator/reportedContent/:reportedContentId/moderationActions",
)
export class DiscussionboardModeratorReportedcontentModerationactionsController {
  /**
   * This operation enables moderators to update the moderation actions taken on
   * a reported content item. The reportedContentId path parameter identifies
   * the content, and the request body contains the moderation action details.
   * The response includes the updated moderation action information.
   *
   * @param connection
   * @param reportedContentId Unique identifier of the reported content item
   * @param body Moderation action details to be updated
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async update(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("reportedContentId")
    reportedContentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardModerationAction.IUpdate,
  ): Promise<IDiscussionBoardModerationAction> {
    try {
      return await patchDiscussionBoardModeratorReportedContentReportedContentIdModerationActions(
        {
          moderator,
          reportedContentId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
