import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { patchDiscussionBoardModeratorSystemConfigurations } from "../../../../../providers/patchDiscussionBoardModeratorSystemConfigurations";
import { ModeratorAuth } from "../../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../../decorators/payload/ModeratorPayload";

import { IDiscussionBoardConfiguration } from "../../../../../api/structures/IDiscussionBoardConfiguration";

@Controller("/discussionBoard/moderator/system/configurations")
export class DiscussionboardModeratorSystemConfigurationsController {
  /**
   * Modify system configuration settings using a patch operation. This allows
   * for updating specific configuration values while leaving other settings
   * unchanged. The request body should contain the configuration fields to be
   * updated along with their new values.
   *
   * @param connection
   * @param body Configuration settings to be updated
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async update(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedBody()
    body: IDiscussionBoardConfiguration.IUpdate,
  ): Promise<IDiscussionBoardConfiguration> {
    try {
      return await patchDiscussionBoardModeratorSystemConfigurations({
        moderator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
