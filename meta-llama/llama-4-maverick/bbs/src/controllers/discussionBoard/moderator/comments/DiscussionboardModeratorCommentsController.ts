import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia from "typia";
import { deleteDiscussionBoardModeratorCommentsCommentId } from "../../../../providers/deleteDiscussionBoardModeratorCommentsCommentId";
import { ModeratorAuth } from "../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../decorators/payload/ModeratorPayload";

@Controller("/discussionBoard/moderator/comments/:commentId")
export class DiscussionboardModeratorCommentsController {
  /**
   * Delete a comment by its ID. This operation allows authenticated users to
   * delete their own comments or moderators/admins to delete any comment.
   *
   * @param connection
   * @param commentId The ID of the comment to be deleted
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("commentId")
    commentId: string,
  ): Promise<void> {
    try {
      return await deleteDiscussionBoardModeratorCommentsCommentId({
        moderator,
        commentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
