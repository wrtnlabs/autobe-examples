import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { deleteDiscussionBoardModeratorCommentsCommentIdRepliesReplyId } from "../../../../../providers/deleteDiscussionBoardModeratorCommentsCommentIdRepliesReplyId";
import { ModeratorAuth } from "../../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../../decorators/payload/ModeratorPayload";

@Controller("/discussionBoard/moderator/comments/:commentId/replies/:replyId")
export class DiscussionboardModeratorCommentsRepliesController {
  /**
   * Permanently removes a reply to a comment from the discussion board.
   * Requires moderator privileges. The operation validates both commentId and
   * replyId before performing the deletion.
   *
   * @param connection
   * @param commentId UUID of the comment that the reply belongs to
   * @param replyId UUID of the reply to be deleted
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async deleteCommentReply(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
    @TypedParam("replyId")
    replyId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteDiscussionBoardModeratorCommentsCommentIdRepliesReplyId(
        {
          moderator,
          commentId,
          replyId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
