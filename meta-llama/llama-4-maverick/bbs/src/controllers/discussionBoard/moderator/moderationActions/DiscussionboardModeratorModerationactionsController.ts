import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia from "typia";
import { patchDiscussionBoardModeratorModerationActions } from "../../../../providers/patchDiscussionBoardModeratorModerationActions";
import { ModeratorAuth } from "../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../decorators/payload/ModeratorPayload";
import { getDiscussionBoardModeratorModerationActionsModerationActionId } from "../../../../providers/getDiscussionBoardModeratorModerationActionsModerationActionId";

import { IPageIDiscussionBoardModerationAction } from "../../../../api/structures/IPageIDiscussionBoardModerationAction";
import { IDiscussionBoardModerationAction } from "../../../../api/structures/IDiscussionBoardModerationAction";

@Controller("/discussionBoard/moderator/moderationActions")
export class DiscussionboardModeratorModerationactionsController {
  /**
   * Retrieve a paginated list of moderation actions from the system. This
   * operation provides advanced search capabilities for finding moderation
   * actions based on multiple criteria including action type, date range, and
   * associated content. The operation supports comprehensive pagination with
   * configurable page sizes and sorting options. Moderators can sort by action
   * date, content type, or other relevant fields in ascending or descending
   * order. Security considerations include rate limiting for search operations
   * and appropriate filtering of sensitive information based on the requesting
   * user's authorization level. Only moderators can access detailed moderation
   * action information.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for moderation action
   *   filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async search(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedBody()
    body: IDiscussionBoardModerationAction.IRequest,
  ): Promise<IPageIDiscussionBoardModerationAction.ISummary> {
    try {
      return await patchDiscussionBoardModeratorModerationActions({
        moderator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a single moderation action identified
   * by its unique moderationActionId. This operation returns comprehensive
   * details about the moderation action, including the action type, execution
   * date, associated content information, and details about the moderator who
   * performed the action. The operation is primarily used for administrative
   * review, auditing, and investigation of moderation activities. Security
   * considerations include strict authorization checks to ensure only
   * authorized users (moderators) can access moderation action details.
   *
   * @param connection
   * @param moderationActionId Unique identifier of the moderation action to
   *   retrieve
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":moderationActionId")
  public async at(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("moderationActionId")
    moderationActionId: string,
  ): Promise<IDiscussionBoardModerationAction> {
    try {
      return await getDiscussionBoardModeratorModerationActionsModerationActionId(
        {
          moderator,
          moderationActionId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
