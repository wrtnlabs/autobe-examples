import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchDiscussionBoardModeratorArticlesArticleIdVersions } from "../../../../../providers/patchDiscussionBoardModeratorArticlesArticleIdVersions";
import { ModeratorAuth } from "../../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../../decorators/payload/ModeratorPayload";

import { IPageIDiscussionBoardArticleVersion } from "../../../../../api/structures/IPageIDiscussionBoardArticleVersion";
import { IDiscussionBoardArticleVersion } from "../../../../../api/structures/IDiscussionBoardArticleVersion";

@Controller("/discussionBoard/moderator/articles/:articleId/versions")
export class DiscussionboardModeratorArticlesVersionsController {
  /**
   * This operation returns a paginated list of article versions for the
   * specified articleId. It supports complex search queries, filtering, and
   * sorting. The results are paginated to allow for efficient retrieval of
   * large datasets. Users can specify various query parameters to customize the
   * search and filtering criteria.
   *
   * @param connection
   * @param articleId The unique identifier of the article for which to retrieve
   *   versions
   * @param body Search criteria and pagination parameters for retrieving
   *   article versions
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardArticleVersion.IRequest,
  ): Promise<IPageIDiscussionBoardArticleVersion.ISummary> {
    try {
      return await patchDiscussionBoardModeratorArticlesArticleIdVersions({
        moderator,
        articleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
