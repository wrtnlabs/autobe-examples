import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia from "typia";
import { getDiscussionBoardRegisteredUserSystemConfigurationsConfigKey } from "../../../../../providers/getDiscussionBoardRegisteredUserSystemConfigurationsConfigKey";
import { RegisteredUserAuth } from "../../../../../decorators/RegisteredUserAuth";
import { RegisteredUserPayload } from "../../../../../decorators/payload/RegisteredUserPayload";
import { putDiscussionBoardRegisteredUserSystemConfigurationsConfigKey } from "../../../../../providers/putDiscussionBoardRegisteredUserSystemConfigurationsConfigKey";
import { deleteDiscussionBoardRegisteredUserSystemConfigurationsConfigKey } from "../../../../../providers/deleteDiscussionBoardRegisteredUserSystemConfigurationsConfigKey";
import { postDiscussionBoardRegisteredUserSystemConfigurations } from "../../../../../providers/postDiscussionBoardRegisteredUserSystemConfigurations";

import { IDiscussionBoardConfiguration } from "../../../../../api/structures/IDiscussionBoardConfiguration";

@Controller("/discussionBoard/registeredUser/system/configurations")
export class DiscussionboardRegistereduserSystemConfigurationsController {
  /**
   * Retrieve a system configuration by key.
   *
   * This operation retrieves a specific system configuration identified by the
   * configKey path parameter. It returns the configuration details including
   * the key, value, and description. The operation is typically used by system
   * administrators to verify or retrieve specific configuration settings.
   *
   * @param connection
   * @param configKey The unique key of the configuration to retrieve
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":configKey")
  public async at(
    @RegisteredUserAuth()
    registeredUser: RegisteredUserPayload,
    @TypedParam("configKey")
    configKey: string,
  ): Promise<IDiscussionBoardConfiguration> {
    try {
      return await getDiscussionBoardRegisteredUserSystemConfigurationsConfigKey(
        {
          registeredUser,
          configKey,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update system configuration value.
   *
   * This operation updates the system configuration value associated with the
   * specified configuration key. It requires the new configuration value to be
   * provided in the request body. The operation validates that the provided
   * configuration key exists in the database before updating its value. Upon
   * successful update, the new configuration value is immediately effective for
   * subsequent operations. The operation returns the updated configuration
   * details upon success.
   *
   * @param connection
   * @param configKey The configuration key to update
   * @param body The new configuration value to be updated
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":configKey")
  public async update(
    @RegisteredUserAuth()
    registeredUser: RegisteredUserPayload,
    @TypedParam("configKey")
    configKey: string,
    @TypedBody()
    body: IDiscussionBoardConfiguration.IUpdate,
  ): Promise<IDiscussionBoardConfiguration> {
    try {
      return await putDiscussionBoardRegisteredUserSystemConfigurationsConfigKey(
        {
          registeredUser,
          configKey,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete system configuration.
   *
   * This operation deletes the system configuration associated with the
   * specified configuration key. It requires the configuration key to be
   * provided as a path parameter. The operation validates that the
   * configuration key exists before attempting deletion. Upon successful
   * deletion, the configuration setting is removed from the database, and any
   * subsequent attempts to access this configuration will result in a 'not
   * found' response. No response body is returned upon successful deletion.
   *
   * @param connection
   * @param configKey The configuration key to delete
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":configKey")
  public async erase(
    @RegisteredUserAuth()
    registeredUser: RegisteredUserPayload,
    @TypedParam("configKey")
    configKey: string,
  ): Promise<void> {
    try {
      return await deleteDiscussionBoardRegisteredUserSystemConfigurationsConfigKey(
        {
          registeredUser,
          configKey,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Create a new system configuration.
   *
   * This operation creates a new system configuration entry. It requires the
   * configuration key, value, and optionally a description in the request body.
   * The operation is typically used during system setup or to add new
   * configuration settings. Proper validation is performed to ensure unique
   * configuration keys.
   *
   * @param connection
   * @param body The configuration details to create
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @RegisteredUserAuth()
    registeredUser: RegisteredUserPayload,
    @TypedBody()
    body: IDiscussionBoardConfiguration.ICreate,
  ): Promise<IDiscussionBoardConfiguration> {
    try {
      return await postDiscussionBoardRegisteredUserSystemConfigurations({
        registeredUser,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
