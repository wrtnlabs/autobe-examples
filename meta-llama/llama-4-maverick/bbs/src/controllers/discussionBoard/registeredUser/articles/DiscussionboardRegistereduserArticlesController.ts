import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia from "typia";
import { postDiscussionBoardRegisteredUserArticles } from "../../../../providers/postDiscussionBoardRegisteredUserArticles";
import { RegisteredUserAuth } from "../../../../decorators/RegisteredUserAuth";
import { RegisteredUserPayload } from "../../../../decorators/payload/RegisteredUserPayload";
import { putDiscussionBoardRegisteredUserArticlesArticleId } from "../../../../providers/putDiscussionBoardRegisteredUserArticlesArticleId";

import { IDiscussionBoardArticle } from "../../../../api/structures/IDiscussionBoardArticle";

@Controller("/discussionBoard/registeredUser/articles")
export class DiscussionboardRegistereduserArticlesController {
  /**
   * Create a new article in the discussion board system.
   *
   * This operation allows authenticated users to create new article content.
   * The article is created with the provided title and content, and is
   * initially unpublished.
   *
   * The operation validates that the user is authenticated and has the
   * necessary permissions to create articles. It also validates the input data
   * to ensure that the title and content are not empty.
   *
   * Upon successful creation, the operation returns the newly created article
   * resource with its assigned ID and other relevant details.
   *
   * @param connection
   * @param body The details of the article to be created
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @RegisteredUserAuth()
    registeredUser: RegisteredUserPayload,
    @TypedBody()
    body: IDiscussionBoardArticle.ICreate,
  ): Promise<IDiscussionBoardArticle> {
    try {
      return await postDiscussionBoardRegisteredUserArticles({
        registeredUser,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing article in the discussion board system.
   *
   * This operation allows authenticated users to update the title and/or
   * content of an existing article that they own. The operation validates that
   * the user is authenticated, owns the article being updated, and that the new
   * title and content are not empty.
   *
   * Upon successful update, the operation returns the updated article resource
   * with its latest version details.
   *
   * @param connection
   * @param articleId The ID of the article to be updated
   * @param body The updated details of the article
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":articleId")
  public async update(
    @RegisteredUserAuth()
    registeredUser: RegisteredUserPayload,
    @TypedParam("articleId")
    articleId: string,
    @TypedBody()
    body: IDiscussionBoardArticle.IUpdate,
  ): Promise<IDiscussionBoardArticle> {
    try {
      return await putDiscussionBoardRegisteredUserArticlesArticleId({
        registeredUser,
        articleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
