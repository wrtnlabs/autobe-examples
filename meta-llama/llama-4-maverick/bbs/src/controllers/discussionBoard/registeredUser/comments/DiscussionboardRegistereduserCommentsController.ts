import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { getDiscussionBoardRegisteredUserCommentsCommentId } from "../../../../providers/getDiscussionBoardRegisteredUserCommentsCommentId";
import { RegisteredUserAuth } from "../../../../decorators/RegisteredUserAuth";
import { RegisteredUserPayload } from "../../../../decorators/payload/RegisteredUserPayload";
import { putDiscussionBoardRegisteredUserCommentsCommentId } from "../../../../providers/putDiscussionBoardRegisteredUserCommentsCommentId";
import { postDiscussionBoardRegisteredUserComments } from "../../../../providers/postDiscussionBoardRegisteredUserComments";

import { IDiscussionBoardComment } from "../../../../api/structures/IDiscussionBoardComment";

@Controller("/discussionBoard/registeredUser/comments")
export class DiscussionboardRegistereduserCommentsController {
  /**
   * This operation allows authenticated users to retrieve detailed information
   * about a specific comment identified by its unique commentId. The comment
   * details include its content, creation timestamp, and associated resource or
   * article information. The operation validates the commentId format and
   * ensures the requesting user has appropriate permissions to view the
   * comment. It returns the comment data in a structured format, using the
   * appropriate DTO type based on the service prefix.
   *
   * @param connection
   * @param commentId Unique identifier of the comment to retrieve
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":commentId")
  public async at(
    @RegisteredUserAuth()
    registeredUser: RegisteredUserPayload,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardComment> {
    try {
      return await getDiscussionBoardRegisteredUserCommentsCommentId({
        registeredUser,
        commentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update a comment by its ID. This operation allows authenticated users to
   * modify their own comments. The request body should contain the updated
   * content of the comment.
   *
   * @param connection
   * @param commentId The ID of the comment to be updated
   * @param body The updated content of the comment
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":commentId")
  public async update(
    @RegisteredUserAuth()
    registeredUser: RegisteredUserPayload,
    @TypedParam("commentId")
    commentId: string,
    @TypedBody()
    body: IDiscussionBoardComment.IUpdate,
  ): Promise<IDiscussionBoardComment> {
    try {
      return await putDiscussionBoardRegisteredUserCommentsCommentId({
        registeredUser,
        commentId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This operation allows authenticated users to create new comments on
   * articles or resources. The request body must conform to the ICreate DTO
   * type for comments, including required fields such as content and associated
   * article/resource ID. The operation validates the input data, ensures the
   * user is authenticated, and creates the new comment record in the database.
   * Upon successful creation, it returns the newly created comment data in the
   * appropriate DTO format.
   *
   * @param connection
   * @param body Creation data for the new comment
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @RegisteredUserAuth()
    registeredUser: RegisteredUserPayload,
    @TypedBody()
    body: IDiscussionBoardComment.ICreate,
  ): Promise<IDiscussionBoardComment> {
    try {
      return await postDiscussionBoardRegisteredUserComments({
        registeredUser,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
