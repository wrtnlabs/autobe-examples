import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { postDiscussionBoardRegisteredUserCommentsCommentIdReplies } from "../../../../../providers/postDiscussionBoardRegisteredUserCommentsCommentIdReplies";
import { RegisteredUserAuth } from "../../../../../decorators/RegisteredUserAuth";
import { RegisteredUserPayload } from "../../../../../decorators/payload/RegisteredUserPayload";
import { putDiscussionBoardRegisteredUserCommentsCommentIdRepliesReplyId } from "../../../../../providers/putDiscussionBoardRegisteredUserCommentsCommentIdRepliesReplyId";

import { IDiscussionBoardCommentReply } from "../../../../../api/structures/IDiscussionBoardCommentReply";

@Controller("/discussionBoard/registeredUser/comments/:commentId/replies")
export class DiscussionboardRegistereduserCommentsRepliesController {
  /**
   * Create a new reply to a comment.
   *
   * This operation allows users to create replies to existing comments on
   * discussion board articles. The reply content is associated with the
   * specified comment ID and is stored in the database. The operation requires
   * authentication to identify the user creating the reply.
   *
   * @param connection
   * @param commentId The unique identifier of the comment to which the reply is
   *   being made.
   * @param body The content of the reply being created.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @RegisteredUserAuth()
    registeredUser: RegisteredUserPayload,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardCommentReply.ICreate,
  ): Promise<IDiscussionBoardCommentReply> {
    try {
      return await postDiscussionBoardRegisteredUserCommentsCommentIdReplies({
        registeredUser,
        commentId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing reply to a comment.
   *
   * This operation allows users to update their previously created replies to
   * comments on discussion board articles. The operation requires
   * authentication to verify that the user updating the reply is the same user
   * who originally created it.
   *
   * @param connection
   * @param commentId The unique identifier of the comment to which the reply
   *   belongs.
   * @param replyId The unique identifier of the reply being updated.
   * @param body The updated content of the reply.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":replyId")
  public async update(
    @RegisteredUserAuth()
    registeredUser: RegisteredUserPayload,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
    @TypedParam("replyId")
    replyId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardCommentReply.IUpdate,
  ): Promise<IDiscussionBoardCommentReply> {
    try {
      return await putDiscussionBoardRegisteredUserCommentsCommentIdRepliesReplyId(
        {
          registeredUser,
          commentId,
          replyId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
