import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { getDiscussionBoardArticlesArticleIdVersionsVersionId } from "../../../../providers/getDiscussionBoardArticlesArticleIdVersionsVersionId";

import { IDiscussionBoardArticleVersion } from "../../../../api/structures/IDiscussionBoardArticleVersion";

@Controller("/discussionBoard/articles/:articleId/versions/:versionId")
export class DiscussionboardArticlesVersionsController {
  /**
   * This operation allows users to retrieve a specific version of an article by
   * providing both the article ID and the version ID. It is useful for tracking
   * changes and viewing historical versions of articles. The operation
   * validates both IDs and returns the corresponding version details.
   *
   * @param connection
   * @param articleId Unique identifier of the article
   * @param versionId Unique identifier of the version
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedParam("versionId")
    versionId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardArticleVersion> {
    try {
      return await getDiscussionBoardArticlesArticleIdVersionsVersionId({
        articleId,
        versionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
