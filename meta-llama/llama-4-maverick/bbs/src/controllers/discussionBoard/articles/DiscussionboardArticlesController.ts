import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchDiscussionBoardArticles } from "../../../providers/patchDiscussionBoardArticles";
import { getDiscussionBoardArticlesArticleId } from "../../../providers/getDiscussionBoardArticlesArticleId";

import { IPageIDiscussionBoardArticle } from "../../../api/structures/IPageIDiscussionBoardArticle";
import { IDiscussionBoardArticle } from "../../../api/structures/IDiscussionBoardArticle";

@Controller("/discussionBoard/articles")
export class DiscussionboardArticlesController {
  /**
   * Search and retrieve a filtered, paginated list of articles.
   *
   * This operation provides comprehensive search capabilities for articles
   * including filtering, sorting, and pagination. It supports complex queries
   * across multiple article attributes and metadata. The operation is designed
   * for users who need to find specific articles based on various criteria.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for article filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IDiscussionBoardArticle.IRequest,
  ): Promise<IPageIDiscussionBoardArticle.ISummary> {
    try {
      return await patchDiscussionBoardArticles({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single article by its unique identifier.
   *
   * This operation provides detailed information about a specific article,
   * including its content, metadata, and associated data. It is designed for
   * users who need to view the full details of an article. The operation
   * includes appropriate access controls to ensure that sensitive information
   * is only available to authorized users. It is optimized for performance and
   * includes error handling for cases where the requested article is not found
   * or the user lacks appropriate permissions.
   *
   * @param connection
   * @param articleId Unique identifier of the article to retrieve
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":articleId")
  public async at(
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardArticle> {
    try {
      return await getDiscussionBoardArticlesArticleId({
        articleId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
