import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { postDiscussionBoardArticlesArticleIdAttachments } from "../../../../providers/postDiscussionBoardArticlesArticleIdAttachments";
import { patchDiscussionBoardArticlesArticleIdAttachments } from "../../../../providers/patchDiscussionBoardArticlesArticleIdAttachments";
import { getDiscussionBoardArticlesArticleIdAttachmentsAttachmentId } from "../../../../providers/getDiscussionBoardArticlesArticleIdAttachmentsAttachmentId";

import { IDiscussionBoardArticleAttachment } from "../../../../api/structures/IDiscussionBoardArticleAttachment";
import { IPageIDiscussionBoardArticleAttachment } from "../../../../api/structures/IPageIDiscussionBoardArticleAttachment";

@Controller("/discussionBoard/articles/:articleId/attachments")
export class DiscussionboardArticlesAttachmentsController {
  /**
   * This operation enables users to upload and create a new attachment
   * associated with a specific article. It requires the article ID as a path
   * parameter and the attachment file in the request body. The operation
   * validates the article ID and handles the file upload process, storing the
   * attachment details in the database.
   *
   * @param connection
   * @param articleId Unique identifier of the article to which the attachment
   *   is being added
   * @param body Attachment file to be uploaded
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardArticleAttachment.ICreate,
  ): Promise<IDiscussionBoardArticleAttachment> {
    try {
      return await postDiscussionBoardArticlesArticleIdAttachments({
        articleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This operation returns a paginated list of attachments associated with a
   * specific article identified by the articleId path parameter. It operates on
   * the discussion_board_article_attachments table and related article
   * metadata. The response includes attachment details such as file name, type,
   * and size. The operation supports pagination parameters in the request
   * body.
   *
   * The operation is designed for users who need to manage or view attachments
   * associated with articles. It provides essential information for attachment
   * management and verification.
   *
   * Security considerations include proper validation of the articleId and
   * appropriate authorization checks based on user roles.
   *
   * Related operations: POST /articles/{articleId}/attachments for adding new
   * attachments, DELETE /articles/{articleId}/attachments/{attachmentId} for
   * removing attachments.
   *
   * @param connection
   * @param articleId Unique identifier of the article whose attachments are
   *   being retrieved
   * @param body Pagination and filtering criteria for attachment retrieval
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardArticleAttachment.IRequest,
  ): Promise<IPageIDiscussionBoardArticleAttachment.ISummary> {
    try {
      return await patchDiscussionBoardArticlesArticleIdAttachments({
        articleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This operation allows users to retrieve a specific attachment associated
   * with an article. It requires both the article ID and attachment ID as path
   * parameters. The operation validates that the attachment exists and is
   * linked to the specified article before returning the attachment details.
   *
   * @param connection
   * @param articleId Unique identifier of the article
   * @param attachmentId Unique identifier of the attachment
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":attachmentId")
  public async at(
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedParam("attachmentId")
    attachmentId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardArticleAttachment> {
    try {
      return await getDiscussionBoardArticlesArticleIdAttachmentsAttachmentId({
        articleId,
        attachmentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
