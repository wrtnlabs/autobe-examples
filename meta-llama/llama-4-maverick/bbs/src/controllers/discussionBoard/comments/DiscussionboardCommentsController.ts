import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { patchDiscussionBoardComments } from "../../../providers/patchDiscussionBoardComments";

import { IPageIDiscussionBoardComment } from "../../../api/structures/IPageIDiscussionBoardComment";
import { IDiscussionBoardComment } from "../../../api/structures/IDiscussionBoardComment";

@Controller("/discussionBoard/comments")
export class DiscussionboardCommentsController {
  /**
   * This operation allows users to search for comments using multiple criteria
   * such as content, author, date range, and more. It supports advanced
   * features like pagination and sorting to efficiently retrieve large
   * datasets. The operation returns a paginated list of comments matching the
   * search criteria.
   *
   * @param connection
   * @param body Search criteria and pagination parameters
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async search(
    @TypedBody()
    body: IDiscussionBoardComment.IRequest,
  ): Promise<IPageIDiscussionBoardComment.ISummary> {
    try {
      return await patchDiscussionBoardComments({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
