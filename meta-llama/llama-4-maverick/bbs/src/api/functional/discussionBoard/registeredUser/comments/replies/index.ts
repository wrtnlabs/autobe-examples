import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardCommentReply } from "../../../../../structures/IDiscussionBoardCommentReply";

/**
 * Create a new reply to a comment.
 *
 * This operation allows users to create replies to existing comments on
 * discussion board articles. The reply content is associated with the specified
 * comment ID and is stored in the database. The operation requires
 * authentication to identify the user creating the reply.
 *
 * @param props.connection
 * @param props.commentId The unique identifier of the comment to which the
 *   reply is being made.
 * @param props.body The content of the reply being created.
 * @path /discussionBoard/registeredUser/comments/:commentId/replies
 * @accessor api.functional.discussionBoard.registeredUser.comments.replies.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function create(
  connection: IConnection,
  props: create.Props,
): Promise<create.Response> {
  return true === connection.simulate
    ? create.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...create.METADATA,
          path: create.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace create {
  export type Props = {
    /**
     * The unique identifier of the comment to which the reply is being
     * made.
     */
    commentId: string & tags.Format<"uuid">;

    /** The content of the reply being created. */
    body: IDiscussionBoardCommentReply.ICreate;
  };
  export type Body = IDiscussionBoardCommentReply.ICreate;
  export type Response = IDiscussionBoardCommentReply;

  export const METADATA = {
    method: "POST",
    path: "/discussionBoard/registeredUser/comments/:commentId/replies",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/discussionBoard/registeredUser/comments/${encodeURIComponent(props.commentId ?? "null")}/replies`;
  export const random = (): IDiscussionBoardCommentReply =>
    typia.random<IDiscussionBoardCommentReply>();
  export const simulate = (
    connection: IConnection,
    props: create.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: create.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("commentId")(() => typia.assert(props.commentId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

