  export type Props = {
    /** Unique identifier of the article */
    articleId: string & tags.Format<"uuid">;

    /** Unique identifier of the version */
    versionId: string & tags.Format<"uuid">;
  };
  export type Response = IDiscussionBoardArticleVersion;

  export const METADATA = {
    method: "GET",
    path: "/discussionBoard/articles/:articleId/versions/:versionId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/articles/${encodeURIComponent(props.articleId ?? "null")}/versions/${encodeURIComponent(props.versionId ?? "null")}`;
  export const random = (): IDiscussionBoardArticleVersion =>
    typia.random<IDiscussionBoardArticleVersion>();
