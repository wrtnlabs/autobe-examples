/**
 * Search moderation actions by moderator ID with pagination.
 *
 * Retrieve a filtered and paginated list of moderation actions performed by a
 * specific moderator. This operation provides advanced search capabilities for
 * finding moderation actions based on multiple criteria. It supports
 * comprehensive pagination with configurable page sizes and sorting options.
 * The operation integrates with the ModerationActions table as defined in the
 * Prisma schema, incorporating all available fields and relationships.
 *
 * @param props.connection
 * @param props.moderatorId Unique identifier of the moderator whose actions are
 *   being retrieved
 * @param props.body Search criteria and pagination parameters for moderation
 *   actions
 * @path /discussionBoard/moderator/moderators/:moderatorId/moderationActions
 * @accessor api.functional.discussionBoard.moderator.moderators.moderationActions.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /** Unique identifier of the moderator whose actions are being retrieved */
    moderatorId: string;

    /** Search criteria and pagination parameters for moderation actions */
    body: IDiscussionBoardModerationAction.IRequest;
  };
  export type Body = IDiscussionBoardModerationAction.IRequest;
  export type Response = IPageIDiscussionBoardModerationAction.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/discussionBoard/moderator/moderators/:moderatorId/moderationActions",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/discussionBoard/moderator/moderators/${encodeURIComponent(props.moderatorId ?? "null")}/moderationActions`;
  export const random = (): IPageIDiscussionBoardModerationAction.ISummary =>
    typia.random<IPageIDiscussionBoardModerationAction.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("moderatorId")(() => typia.assert(props.moderatorId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
