import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardConfiguration } from "../../../../../structures/IDiscussionBoardConfiguration";

/**
 * Update discussion board configurations.
 *
 * Modify system configuration settings using a patch operation. This allows for
 * updating specific configuration values while leaving other settings
 * unchanged. The request body should contain the configuration fields to be
 * updated along with their new values.
 *
 * @param props.connection
 * @param props.body Configuration settings to be updated
 * @path /discussionBoard/moderator/system/configurations
 * @accessor api.functional.discussionBoard.moderator.system.configurations.update
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function update(
  connection: IConnection,
  props: update.Props,
): Promise<update.Response> {
  return true === connection.simulate
    ? update.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...update.METADATA,
          path: update.path(),
          status: null,
        },
        props.body,
      );
}
export namespace update {
  export type Props = {
    /** Configuration settings to be updated */
    body: IDiscussionBoardConfiguration.IUpdate;
  };
  export type Body = IDiscussionBoardConfiguration.IUpdate;
  export type Response = IDiscussionBoardConfiguration;

  export const METADATA = {
    method: "PATCH",
    path: "/discussionBoard/moderator/system/configurations",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/discussionBoard/moderator/system/configurations";
  export const random = (): IDiscussionBoardConfiguration =>
    typia.random<IDiscussionBoardConfiguration>();
  export const simulate = (
    connection: IConnection,
    props: update.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: update.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
