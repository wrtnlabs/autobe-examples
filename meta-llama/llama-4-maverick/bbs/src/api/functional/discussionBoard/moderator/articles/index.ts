/**
 * Permanently delete an article by ID.
 *
 * This operation completely removes an article from the database along with all
 * related data such as attachments and comments. It requires the articleId path
 * parameter to identify the target article. The operation is restricted to
 * users with moderator roles. After deletion, the article and all associated
 * data are irretrievable.
 *
 * The operation interacts with the discussion_board_articles table and related
 * subsidiary tables. It performs a hard delete, meaning the data is permanently
 * removed from the database.
 *
 * Security considerations include proper authorization checks to ensure only
 * authorized personnel can perform this operation. The user's role is verified
 * against the required roles for this operation.
 *
 * Related operations: GET /articles/{articleId} for retrieving article details
 * before deletion, PATCH /articles/{articleId}/restore for restoring deleted
 * articles.
 *
 * @param props.connection
 * @param props.articleId Unique identifier of the article to be deleted
 * @path /discussionBoard/moderator/articles/:articleId
 * @accessor api.functional.discussionBoard.moderator.articles.erase
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function erase(
  connection: IConnection,
  props: erase.Props,
): Promise<void> {
  return true === connection.simulate
    ? erase.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...erase.METADATA,
          path: erase.path(props),
          status: null,
        },
      );
}
export namespace erase {
  export type Props = {
    /** Unique identifier of the article to be deleted */
    articleId: string & tags.Format<"uuid">;
  };

  export const METADATA = {
    method: "DELETE",
    path: "/discussionBoard/moderator/articles/:articleId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/moderator/articles/${encodeURIComponent(props.articleId ?? "null")}`;
  export const random = (): void => typia.random<void>();
  export const simulate = (
    connection: IConnection,
    props: erase.Props,
  ): void => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: erase.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("articleId")(() => typia.assert(props.articleId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
