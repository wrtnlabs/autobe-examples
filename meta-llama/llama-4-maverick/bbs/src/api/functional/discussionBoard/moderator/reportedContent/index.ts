/**
 * Search reported content with filtering and pagination.
 *
 * Retrieves a paginated list of reported content from the discussion board,
 * allowing moderators to filter by report status, content type, and other
 * criteria. Supports sorting and pagination parameters.
 *
 * @param props.connection
 * @param props.body Search criteria and pagination parameters for filtering
 *   reported content
 * @path /discussionBoard/moderator/reportedContent
 * @accessor api.functional.discussionBoard.moderator.reportedContent.searchReportedContent
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function searchReportedContent(
  connection: IConnection,
  props: searchReportedContent.Props,
): Promise<searchReportedContent.Response> {
  return true === connection.simulate
    ? searchReportedContent.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...searchReportedContent.METADATA,
          path: searchReportedContent.path(),
          status: null,
        },
        props.body,
      );
}
export namespace searchReportedContent {
  export type Props = {
    /**
     * Search criteria and pagination parameters for filtering reported
     * content
     */
    body: IDiscussionBoardReportedContent.IRequest;
  };
  export type Body = IDiscussionBoardReportedContent.IRequest;
  export type Response = IPageIDiscussionBoardReportedContent.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/discussionBoard/moderator/reportedContent",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/discussionBoard/moderator/reportedContent";
  export const random = (): IPageIDiscussionBoardReportedContent.ISummary =>
    typia.random<IPageIDiscussionBoardReportedContent.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: searchReportedContent.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: searchReportedContent.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

