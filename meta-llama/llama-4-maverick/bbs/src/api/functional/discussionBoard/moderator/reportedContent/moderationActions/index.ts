import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardModerationAction } from "../../../../../structures/IDiscussionBoardModerationAction";

/**
 * Update moderation actions for a reported content item.
 *
 * This operation enables moderators to update the moderation actions taken on a
 * reported content item. The reportedContentId path parameter identifies the
 * content, and the request body contains the moderation action details. The
 * response includes the updated moderation action information.
 *
 * @param props.connection
 * @param props.reportedContentId Unique identifier of the reported content item
 * @param props.body Moderation action details to be updated
 * @path /discussionBoard/moderator/reportedContent/:reportedContentId/moderationActions
 * @accessor api.functional.discussionBoard.moderator.reportedContent.moderationActions.update
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function update(
  connection: IConnection,
  props: update.Props,
): Promise<update.Response> {
  return true === connection.simulate
    ? update.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...update.METADATA,
          path: update.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace update {
  export type Props = {
    /** Unique identifier of the reported content item */
    reportedContentId: string & tags.Format<"uuid">;

    /** Moderation action details to be updated */
    body: IDiscussionBoardModerationAction.IUpdate;
  };
  export type Body = IDiscussionBoardModerationAction.IUpdate;
  export type Response = IDiscussionBoardModerationAction;

  export const METADATA = {
    method: "PATCH",
    path: "/discussionBoard/moderator/reportedContent/:reportedContentId/moderationActions",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/discussionBoard/moderator/reportedContent/${encodeURIComponent(props.reportedContentId ?? "null")}/moderationActions`;
  export const random = (): IDiscussionBoardModerationAction =>
    typia.random<IDiscussionBoardModerationAction>();
  export const simulate = (
    connection: IConnection,
    props: update.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: update.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("reportedContentId")(() =>
        typia.assert(props.reportedContentId),
      );
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
