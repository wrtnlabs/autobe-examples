/**
 * Create new registered user account.
 *
 * This operation creates a new registered user account in the system. It
 * requires user registration information such as username, email, and password.
 * The operation validates the input data, creates the user record in the
 * database, and generates an access token for the new user.
 *
 * The request body must contain the necessary user details as defined in the
 * IRegisteredUser.ICreate schema.
 *
 * Upon successful creation, the response includes the new user's information
 * and an access token as defined in the
 * IDiscussionBoardRegisteredUser.IAuthorized schema.
 *
 * This operation is public and does not require authentication.
 *
 * @param props.connection
 * @param props.body New user registration information
 * @setHeader token.access Authorization
 *
 * @path /auth/registered-user/join
 * @accessor api.functional.auth.registered_user.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
export namespace join {
  export type Props = {
    /** New user registration information */
    body: IDiscussionBoardRegisteredUser.ICreate;
  };
  export type Body = IDiscussionBoardRegisteredUser.ICreate;
  export type Response = IDiscussionBoardRegisteredUser.IAuthorized;

  export const METADATA = {
    method: "POST",
    path: "/auth/registered-user/join",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/registered-user/join";
  export const random = (): IDiscussionBoardRegisteredUser.IAuthorized =>
    typia.random<IDiscussionBoardRegisteredUser.IAuthorized>();
  export const simulate = (
    connection: IConnection,
    props: join.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: join.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

