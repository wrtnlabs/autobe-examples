import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceSellerProfileSnapshot } from "../../../../api/structures/IEcommerceSellerProfileSnapshot";
import { IPageIEcommerceSellerProfileSnapshot } from "../../../../api/structures/IPageIEcommerceSellerProfileSnapshot";
import { getEcommerceSellersSellerIdSellerProfileSnapshotsSnapshotId } from "../../../../providers/getEcommerceSellersSellerIdSellerProfileSnapshotsSnapshotId";
import { patchEcommerceSellersSellerIdSellerProfileSnapshots } from "../../../../providers/patchEcommerceSellersSellerIdSellerProfileSnapshots";
import { postEcommerceSellersSellerIdSellerProfileSnapshots } from "../../../../providers/postEcommerceSellersSellerIdSellerProfileSnapshots";

@Controller("/ecommerce/sellers/:sellerId/seller-profile-snapshots")
export class EcommerceSellersSeller_profile_snapshotsController {
  /**
   * Creates a snapshot of a seller profile change with complete before/after state values. This operation implements the automatic snapshot requirement from business rules to maintain immutable change history.
   *
   * The snapshot captures all modified profile fields including shop name, description, and logo with exact values before and after the change. All snapshot data is stored in a single transaction with timestamps and actor references.
   *
   * This operation is intentionally designed to be used internally when a seller's profile is updated, not by external consumers. It ensures the system automatically creates a complete audit trail for all profile modifications without requiring additional user interaction.
   *
   * @param connection
   * @param sellerId Unique identifier of the seller whose profile is being changed
   * @param body Profile change data with current state (before) and new state (after) for shop name, description, and logo
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Capture profile change by storing all modified fields (shop name, description, logo) before and after in ecommerce_seller_profile_snapshots. Validate sellerId exists. Generate unique ID for snapshot. Store timestamps in created_at field. Relate to seller via ecommerce_sellers_id (path parameter) and profile via ecommerce_seller_profiles_id (request body). Ensure all required fields (before/after values) are provided by client. Store only modified fields (not full profile).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceSellerProfileSnapshot.ICreate,
  ): Promise<IEcommerceSellerProfileSnapshot> {
    try {
      return await postEcommerceSellersSellerIdSellerProfileSnapshots({
        sellerId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a paginated history of profile updates for a specific seller's account.
   *
   * This operation provides comprehensive historical records of all modifications to a seller's profile information. Each snapshot contains the exact state of the profile before and after changes, along with timestamp and actor details.
   *
   * The response includes only summary-level data optimized for list views (seller_id, timestamp, actor_id, and key changed fields) while preserving full revision context in the data structures. Can be filtered by time range, specific actors, or profile field changes.
   *
   * @param connection
   * @param sellerId Unique identifier of the target seller
   * @param body Search criteria and pagination options for snapshot history
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query ecommerce_seller_profile_snapshots table where seller_id = path parameter. Apply filtering from IRequest parameters: timestamp range, actor_id filter, and revision field filters. Perform cursor-based pagination for large datasets. Return full snapshot details with before/after field comparisons.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedParam("sellerId")
    sellerId: string,
    @TypedBody()
    body: IEcommerceSellerProfileSnapshot.IRequest,
  ): Promise<IPageIEcommerceSellerProfileSnapshot.ISummary> {
    try {
      return await patchEcommerceSellersSellerIdSellerProfileSnapshots({
        sellerId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific profile modification history record showing the transition from one seller profile state to another.
   *
   * This operation provides complete change history for seller profile modifications, including the exact values of shop name, description, and logo before and after the change, along with the timestamp of the modification. The snapshot data is immutable and maintained for audit purposes according to the system's Snapshot Principle.
   *
   * The response includes all historical data without modification, allowing users to view the full context of profile changes made to seller accounts. This operation is read-only as required by the snapshot entity stance, and is designed for administrative review of profile modifications.
   *
   * @param connection
   * @param sellerId The seller identifier to which the profile snapshot belongs (corresponds to ecommerce_sellers.id)
   * @param snapshotId The unique identifier of the profile snapshot
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query ecommerce_seller_profile_snapshots table for snapshot with ID = snapshotId. Verify association with sellerId via ecommerce_sellers_id. Return all snapshot fields including before/after values for shop name, description, logo, and created timestamp. Validate relationship between snapshot and seller using foreign key constraints.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":snapshotId")
  public async at(
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
    @TypedParam("snapshotId")
    snapshotId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceSellerProfileSnapshot> {
    try {
      return await getEcommerceSellersSellerIdSellerProfileSnapshotsSnapshotId({
        sellerId,
        snapshotId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
