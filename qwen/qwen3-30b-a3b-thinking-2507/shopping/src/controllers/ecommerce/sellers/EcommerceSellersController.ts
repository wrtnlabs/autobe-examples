import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceSeller } from "../../../api/structures/IEcommerceSeller";
import { IPageIEcommerceSeller } from "../../../api/structures/IPageIEcommerceSeller";
import { getEcommerceSellersSellerId } from "../../../providers/getEcommerceSellersSellerId";
import { patchEcommerceSellers } from "../../../providers/patchEcommerceSellers";

@Controller("/ecommerce/sellers")
export class EcommerceSellersController {
  /**
   * Retrieve filtered and paginated list of seller accounts for administrative management.
   *
   * This endpoint enables system administrators to search and manage seller registrations efficiently. It supports filtering by current account status (pending, approved, rejected), partial email matching, and shop name search. The results include essential seller profile information with status indicators for quick review of pending applications. Response includes pagination metadata for handling large seller directories. This endpoint only returns seller profile summaries (not full details) for performance reasons.
   *
   * @param connection
   * @param body Search criteria and pagination parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query ecommerce_sellers table with support for filtering by status (pending/approved/rejected), email address, and shop name. Apply pagination via cursor-based scrolling in query layer. Join with ecommerce_seller_profiles for shop name and status display. Return only essential fields for list view (email, shopName, status, lastUpdate). Handle sorting by lastUpdate field. Implement 12 items per page default.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IEcommerceSeller.IRequest,
  ): Promise<IPageIEcommerceSeller.ISummary> {
    try {
      return await patchEcommerceSellers({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves comprehensive seller profile information for customer-facing displays. Includes verification status to indicate legitimate sellers, shop name, description, logo URL, and active product count. Enables customers to view seller profile details before purchasing. Response includes current business status (approved, pending, rejected) to inform customers of seller legitimacy.
   *
   * This operation supports customer trust through clear seller profile transparency. Seller approval status provides important context about the seller's verification status, allowing customers to make informed purchasing decisions.
   *
   * @param connection
   * @param sellerId Unique identifier of seller to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query ecommerce_sellers table with joined ecommerce_seller_profiles. Include seller approval status, email, authentication details, and profile data (shop name, description, logo URL, active product count). Exclude sensitive fields like password hashes in response.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sellerId")
  public async at(
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceSeller> {
    try {
      return await getEcommerceSellersSellerId({
        sellerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
