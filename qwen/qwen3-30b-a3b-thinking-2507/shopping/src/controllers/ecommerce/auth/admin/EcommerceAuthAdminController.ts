import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IEcommerceAdmin } from "../../../../api/structures/IEcommerceAdmin";
import { postEcommerceAuthAdminJoin } from "../../../../providers/postEcommerceAuthAdminJoin";
import { postEcommerceAuthAdminLogin } from "../../../../providers/postEcommerceAuthAdminLogin";
import { postEcommerceAuthAdminRefresh } from "../../../../providers/postEcommerceAuthAdminRefresh";

@Controller("/ecommerce/auth/admin")
export class EcommerceAuthAdminController {
  /**
   * The admin registration endpoint creates a new administrator account with email and password. The system verifies email format, enforces password complexity (minimum 8 characters, alphanumeric mix), and securely hashes credentials using bcrypt. Upon successful registration, it generates JWT access and refresh tokens with valid claims. This operation is exclusively for administrative use case where new administrators are added to the system.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Registration request containing email and password
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Handle new admin registration. Validate credentials, create user record, and generate initial tokens. Requires email, password with complexity validation, and admin-specific validation rules.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEcommerceAdmin.IJoin,
  ): Promise<IEcommerceAdmin.IAuthorized> {
    try {
      return await postEcommerceAuthAdminJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * The admin login endpoint authenticates credentials for administrators. It verifies email and password against stored bcrypt hashes, confirms account is active, and generates JWT tokens with 30-minute expiration. Successful login returns access/refresh tokens. This operation validates email/password combinations for admin accounts only, restricting access to authorized administrative users.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Login request containing email and password
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Authenticate admin credentials. Verify stored password hash, generate new tokens, and handle failed attempts with security measures.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEcommerceAdmin.ILogin,
  ): Promise<IEcommerceAdmin.IAuthorized> {
    try {
      return await postEcommerceAuthAdminLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * The admin token refresh endpoint generates a new access token using a valid refresh token. It validates the refresh token against stored tokens, confirms the admin account's active status, and creates new access/refresh tokens with updated expiration. This operation enables continuous session use without password re-entry.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh request containing valid refresh token
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Renew JWT access tokens without requiring password. Validate and refresh tokens securely to extend session longevity.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IEcommerceAdmin.IRefresh,
  ): Promise<IEcommerceAdmin.IAuthorized> {
    try {
      return await postEcommerceAuthAdminRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
