import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IEcommerceSeller } from "../../../../api/structures/IEcommerceSeller";
import { postEcommerceAuthSellerJoin } from "../../../../providers/postEcommerceAuthSellerJoin";
import { postEcommerceAuthSellerLogin } from "../../../../providers/postEcommerceAuthSellerLogin";
import { postEcommerceAuthSellerRefresh } from "../../../../providers/postEcommerceAuthSellerRefresh";

@Controller("/ecommerce/auth/seller")
export class EcommerceAuthSellerController {
  /**
   * The join operation allows new sellers to register for an account on the platform. Sellers provide email, password, and business documentation (e.g., company registration). The registration process queues the seller for administrative approval. The system verifies the email address via verification code sent to provided email.
   *
   * Registration requires valid business domain email (e.g., name@company.com), password (min 8 characters, complexity), and valid business documents. After registration, seller account remains in 'pending' status until approved by administrator.
   *
   * This operation supports Seller Account Management feature as specified in functional requirements, ensuring proper validation of business credentials and structured registration workflow.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Seller registration details including email, password, and business documentation
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Handles seller account registration. Creates new seller record, queues for admin approval, sets up email verification. Requires business documents upload. Uses ecommerce_sellers.create() and ecommerce_seller_email_verifications.create() database methods.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEcommerceSeller.IJoin,
  ): Promise<IEcommerceSeller.IAuthorized> {
    try {
      return await postEcommerceAuthSellerJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * The login operation authenticates sellers using registered email and password. System verifies credentials securely using bcrypt hashing.
   *
   * Upon successful authentication, the service returns JWT tokens with 15-minute validity period including access and refresh tokens. Sellers provide valid, non-deleted email address and matching password.
   *
   * Failed login attempts are tracked with 5-minute cooldown for successive attempts. This operation directly supports Seller Account Management, allowing sellers to access their accounts for product management. Response contains signed JWT access token for session validation.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Seller login credentials with email and password
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Validates seller credentials, generates JWT token with 15-minute session timeout, handles failed attempts with rate limiting. Uses bcrypt for password comparison against ecommerce_sellers table.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEcommerceSeller.ILogin,
  ): Promise<IEcommerceSeller.IAuthorized> {
    try {
      return await postEcommerceAuthSellerLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * The refresh operation extends a seller's active session by generating new access token when current one expires. Sellers provide valid refresh token from previous login response.
   *
   * System validates freshness and authenticity of refresh token against ecommerce_seller_sessions table. Upon successful validation, new access token issued with 15-minute expiration, invalidating old access token.
   *
   * This operation maintains uninterrupted seller access during extended sessions, supporting continuous product management without repeated logins. Response provides new token set for subsequent requests.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token for token renewal
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Generates new access token from valid refresh token, invalidates old access token, extends session with 15-minute duration. Validates refresh tokens against ecommerce_seller_sessions table.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IEcommerceSeller.IRefresh,
  ): Promise<IEcommerceSeller.IAuthorized> {
    try {
      return await postEcommerceAuthSellerRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
