import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IEcommerceSeller } from "../../../../api/structures/IEcommerceSeller";
import { postEcommerceAuthSellerJoin } from "../../../../providers/postEcommerceAuthSellerJoin";
import { postEcommerceAuthSellerLogin } from "../../../../providers/postEcommerceAuthSellerLogin";
import { postEcommerceAuthSellerRefresh } from "../../../../providers/postEcommerceAuthSellerRefresh";

@Controller("/ecommerce/auth/seller")
export class EcommerceAuthSellerController {
  /**
   * The join operation handles new seller account registration on the platform. Required fields include email address formatted as a valid email, password meeting minimum 8-character complexity, and other standard authentication fields. The API validates email format and password requirements before processing. Upon successful registration, the system creates a new seller record with 'pending' approval status, stores credentials using bcrypt hashing, sends a verification email for email authentication, and initializes a new session with JWT tokens.
   *
   * The seller account starts with 'pending' status requiring administrator review before becoming active. This operation follows the platform's business rules for seller onboarding, including email verification requirement for account safety.
   *
   * After registration, the seller must verify their email address before they can proceed with product listings or seller-specific operations. The API validates that the email is not already registered during the join process.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Seller registration details including email and password
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Implement seller registration: validate email format, password complexity, and store credentials with secure hashing. Create new seller record with pending approval status. Send verification email. Generate JWT tokens. Ensure session management with 30-minute timeout.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEcommerceSeller.IJoin,
  ): Promise<IEcommerceSeller.IAuthorized> {
    try {
      return await postEcommerceAuthSellerJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * The login operation authenticates existing sellers by validating email and password credentials. The API securely compares provided credentials using bcrypt hash comparison against stored credentials in the database. Upon successful authentication, the system validates the seller's account status is not pending or suspended.
   *
   * For successful logins, the system generates JWT access tokens with 30-minute expiration and refresh tokens for session management. The response includes the necessary token information with appropriate HTTP status codes.
   *
   * The system enforces security by returning specific error messages for each failure scenario (wrong password, account pending, etc.) to improve user experience while maintaining security. Login is only permitted for sellers in active status (not pending or rejected).
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Seller login details including email and password
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Implement seller login: validate credentials using bcrypt, generate JWT tokens with 30-minute expiration, return authentication tokens, and handle incorrect credential scenarios with specific error messages.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEcommerceSeller.ILogin,
  ): Promise<IEcommerceSeller.IAuthorized> {
    try {
      return await postEcommerceAuthSellerLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * The refresh operation handles token renewal for active seller sessions. It validates the existing refresh token, ensures it's valid and hasn't expired, and then generates a new access token with standard 30-minute expiration and a new refresh token with extended expiration for continued access.
   *
   * This operation is designed for maintaining session continuity during user interactions without requiring repeated login. It returns the updated access token and refresh token to the client, which then updates their session state.
   *
   * The system enforces security by requiring refresh tokens to be bound to specific sessions and not reusable. Expired tokens trigger authentication errors and require the user to provide credentials again. Refresh tokens have limited validity to prevent abuse.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token to renew session
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Implement token refresh: validate refresh token, generate new access token and refresh token with extended expiration, handle expired tokens, and maintain session continuity.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IEcommerceSeller.IRefresh,
  ): Promise<IEcommerceSeller.IAuthorized> {
    try {
      return await postEcommerceAuthSellerRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
