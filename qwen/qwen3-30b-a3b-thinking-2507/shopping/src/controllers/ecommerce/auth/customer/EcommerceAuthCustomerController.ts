import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IEcommerceCustomer } from "../../../../api/structures/IEcommerceCustomer";
import { postEcommerceAuthCustomerJoin } from "../../../../providers/postEcommerceAuthCustomerJoin";
import { postEcommerceAuthCustomerLogin } from "../../../../providers/postEcommerceAuthCustomerLogin";
import { postEcommerceAuthCustomerRefresh } from "../../../../providers/postEcommerceAuthCustomerRefresh";

@Controller("/ecommerce/auth/customer")
export class EcommerceAuthCustomerController {
  /**
   * Creates a new customer account with email and password credentials. The email field is validated against format requirements and must be unique across all customer accounts per the ecommerce_customers table. Password is securely hashed using bcrypt and stored in the password_hash field. Validates email format and enforces minimum 8-character password complexity before creating the account entry. References ecommerce_customers.email and password_hash fields for storage and uniqueness constraints.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Customer registration request containing required email and password
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Service layer validates email format and uniqueness, hashes password with bcrypt, creates new ecommerce_customers record with email and password_hash. Sets default display_name to null, phone to null. Sets created_at/updated_at to current UTC time. Returns JWT tokens containing customer ID and actor type in IAuthorized response. Handles email uniqueness constraint exception by returning 409 error.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEcommerceCustomer.IJoin,
  ): Promise<IEcommerceCustomer.IAuthorized> {
    try {
      return await postEcommerceAuthCustomerJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticates an existing customer account using email and password. Validates the provided password hash against the password_hash field in ecommerce_customers table. Returns JWT tokens with 30-minute expiration. Handles incorrect password by returning specific error messages that don't reveal if account exists. References ecommerce_customers.email for authentication lookup and password_hash for verification.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Customer login request containing validated email and password
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Service layer verifies email exists in ecommerce_customers, compares bcrypt-hashed password with password_hash, generates JWT tokens with 30-minute expiration. Invalidates all previous customer_sessions for current user on successful login. Stores new session in ecommerce_customer_sessions table. Returns tokens in IAuthorized response. Returns 401 for invalid credentials without disclosing account status.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEcommerceCustomer.ILogin,
  ): Promise<IEcommerceCustomer.IAuthorized> {
    try {
      return await postEcommerceAuthCustomerLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Renews access tokens using a valid refresh token. Ensures refresh token is valid and has not expired. Generates new access and refresh tokens with updated expiration. Maintains session continuity without requiring re-authentication. Works with the existing customer session tokens stored in ecommerce_customer_sessions table.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token request containing valid refresh token
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Service layer validates refresh token against ecommerce_customer_sessions, ensures token is not expired or invalid. Creates new access and refresh tokens with 30-minute access expiration. Updates the session entry to replace the old refresh token with a new one. Returns new tokens in IAuthorized response. Returns 401 for invalid or expired refresh tokens.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IEcommerceCustomer.IRefresh,
  ): Promise<IEcommerceCustomer.IAuthorized> {
    try {
      return await postEcommerceAuthCustomerRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
