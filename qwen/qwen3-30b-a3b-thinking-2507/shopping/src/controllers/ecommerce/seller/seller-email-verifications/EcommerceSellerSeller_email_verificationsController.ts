import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceSellerEmailVerification } from "../../../../api/structures/IEcommerceSellerEmailVerification";
import { IPageIEcommerceSellerEmailVerification } from "../../../../api/structures/IPageIEcommerceSellerEmailVerification";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { getEcommerceSellerSellerEmailVerificationsVerificationId } from "../../../../providers/getEcommerceSellerSellerEmailVerificationsVerificationId";
import { patchEcommerceSellerSellerEmailVerifications } from "../../../../providers/patchEcommerceSellerSellerEmailVerifications";

@Controller("/ecommerce/seller/seller-email-verifications")
export class EcommerceSellerSeller_email_verificationsController {
  /**
   * Retrieve a filtered and paginated list of seller email verification records.
   *
   * This endpoint allows sellers to view their email verification tokens, supporting filtering by status, expiration dates, and creation timestamps to track verification workflows.
   *
   * Supports advanced search parameters including date ranges and status filters. Response structure provides efficient client-side pagination with total records count and next page metadata for handling large datasets.
   *
   * Returns verification tokens with associated seller IDs, expiration timestamps, and verification status for sellers to manage their account verification process.
   *
   * @param connection
   * @param body Search criteria and pagination parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query ecommerce_seller_email_verifications table with filtering on is_verified, expires_at, and created_at fields. Implement cursor-based pagination with page size and token parameters. Validate date ranges to prevent invalid queries. Ensure response includes pagination metadata for client-side navigation.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IEcommerceSellerEmailVerification.IRequest,
  ): Promise<IPageIEcommerceSellerEmailVerification.ISummary> {
    try {
      return await patchEcommerceSellerSellerEmailVerifications({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single email verification token record for seller account verification.
   *
   * This endpoint provides complete details about an email verification token including its expiration status, verification confirmation, and associated seller account. Used during the seller registration flow to confirm email addresses before account activation.
   *
   * Security note: Verification tokens expire after 24 hours (specified in expires_at field). The is_verified flag determines if the email address has been successfully confirmed. System automatically skips deleted records (using soft delete logic).
   *
   * @param connection
   * @param verificationId Unique identifier of the email verification record
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Fetch verification record by ID from ecommerce_seller_email_verifications table with soft delete check. Validate token expiration (expires_at). Return full verification object including seller reference and verification status. Skip deleted records (deleted_at is not null).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":verificationId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("verificationId")
    verificationId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceSellerEmailVerification> {
    try {
      return await getEcommerceSellerSellerEmailVerificationsVerificationId({
        seller,
        verificationId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
