import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceProductImage } from "../../../../../api/structures/IEcommerceProductImage";
import { IPageIEcommerceProductImage } from "../../../../../api/structures/IPageIEcommerceProductImage";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { deleteEcommerceSellerProductsProductIdImagesImageId } from "../../../../../providers/deleteEcommerceSellerProductsProductIdImagesImageId";
import { getEcommerceSellerProductsProductIdImagesImageId } from "../../../../../providers/getEcommerceSellerProductsProductIdImagesImageId";
import { patchEcommerceSellerProductsProductIdImages } from "../../../../../providers/patchEcommerceSellerProductsProductIdImages";
import { postEcommerceSellerProductsProductIdImages } from "../../../../../providers/postEcommerceSellerProductsProductIdImages";
import { putEcommerceSellerProductsProductIdImagesImageId } from "../../../../../providers/putEcommerceSellerProductsProductIdImagesImageId";

@Controller("/ecommerce/seller/products/:productId/images")
export class EcommerceSellerProductsImagesController {
  /**
   * Add a new image to a product with specific position and optional main image designation.
   *
   * This operation allows sellers to upload images for product listings with precise ordering and main image designation. The created image will be associated with the specified product ID and its position determines its order in the product's gallery view.
   *
   * The first image in the gallery (position 0) is auto-marked as the main thumbnail which appears in product listings. Additional images can be marked as main to change the thumbnail. When a new image is added, the position value determines where it appears in the sequence.
   *
   * @param connection
   * @param productId The ID of the product to add the image to
   * @param body Image details for creation
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification 1. Verify productId matches a valid product ID in the database
   * 2. Validate incoming image_url (must be a URL format)
   * 3. Confirm position is a non-negative integer
   * 4. Ensure is_main is boolean or omitted
   * 5. Create new image record with provided values
   * 6. If is_main is true for new image, toggle is_main to false for all existing main images (position 0)
   * 7. Set created_at and updated_at to current timestamp
   * 8. Respond with full image record including all fields
   * 9. Ensure seller has ownership of the product
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceProductImage.ICreate,
  ): Promise<IEcommerceProductImage> {
    try {
      return await postEcommerceSellerProductsProductIdImages({
        seller,
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Manage the image ordering and main image configuration for a product.
   *
   * This operation allows sellers to reorder product images and designate a main thumbnail image for the product gallery. The system requires exactly one main image per product, with images displayed in ascending position order (position 0 is first, position 1 is second, etc.).
   *
   * For security, authenticated sellers must own the product being updated. Each image modification creates a snapshot for audit purposes. The endpoint is idempotent when position parameters are consistent with current state.
   *
   * This endpoint is part of the product image management workflow, and should be used in conjunction with GET /products/{productId}/images for current state verification.
   *
   * @param connection
   * @param productId Product ID (UUID)
   * @param body Image configuration array: specifies position order and main image selection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Implement image order management via position updates. Use transaction to ensure atomic updates. Accept array of image configs with `position`, `is_main`, and validate `position` ordering (0-based integer indices). Enforce uniqueness constraint on (ecommerce_product_id, position) via index. Check product ID existence and user permission in service layer. Update all positions in batch, setting new main image if `is_main` is true (must have exactly one main image per product). Handle empty array by removing all images (mark for soft delete).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceProductImage.IRequest,
  ): Promise<IPageIEcommerceProductImage.ISummary> {
    try {
      return await patchEcommerceSellerProductsProductIdImages({
        seller,
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific image associated with a product.
   *
   * This endpoint returns the image metadata including URL, position in the gallery, and whether it's the main thumbnail. The response includes all fields currently stored in the image record, allowing frontend applications to display the image correctly in the product gallery.
   *
   * Security: Requires valid authentication token of the seller associated with the product. Attempts to access images without proper authorization will return 403 Forbidden response. The product must exist and the seller must have access to view the product.
   *
   * @param connection
   * @param productId The unique identifier of the product.
   * @param imageId The unique identifier of the product image.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification 1. Verify productId and imageId exist in ecommerce_product_images table
   * 2. Check user is authenticated and has access to the product
   * 3. Fetch image record with all fields: image_url, is_main, position, created_at, updated_at, deleted_at
   * 4. Handle soft delete: if deleted_at is not null, return 404
   * 5. Validate imageId belongs to the specified productId
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":imageId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedParam("imageId")
    imageId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceProductImage> {
    try {
      return await getEcommerceSellerProductsProductIdImagesImageId({
        seller,
        productId,
        imageId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update product image properties including URL, main image status, and display order within a product.
   *
   * This operation allows sellers to modify product images with specific details:
   * - Updated image URL for the product listing
   * - Main image designation (only one main image allowed per product)
   * - Position in the image gallery (position = 0 is the main image, others are in order)
   *
   * The system validates that the position parameter is an integer ≥ 0 and ensures only one main image exists per product. The updated image record includes the new values for all modified fields.
   *
   * The response contains the complete updated image record with the most recent values for all applicable properties.
   *
   * Note: This operation requires seller authentication with appropriate permissions to modify product images.
   *
   * @param connection
   * @param productId Product ID (UUID) the image belongs to
   * @param imageId Image ID (UUID) to update
   * @param body Image update details (URL, main status, position)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Validate product exists and image belongs to that product. Update specified image fields (image_url, is_main, position). Position must be integer ≥ 0. Ensure is_main flag is correctly handled (only one main image per product allowed). Return updated image record with current version. Handle transactional updates via Prisma.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":imageId")
  public async update(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedParam("imageId")
    imageId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceProductImage.IUpdate,
  ): Promise<IEcommerceProductImage> {
    try {
      return await putEcommerceSellerProductsProductIdImagesImageId({
        seller,
        productId,
        imageId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Soft delete a product image from the gallery. This operation marks the image as deleted via the 'deleted_at' timestamp without permanently removing it from the database, preserving the historical record for product snapshots and audit trails.
   *
   * The image will no longer be visible in active product listings or gallery displays. All historical data, including original image URL and position, remains intact for review in product snapshots. Audit logs capture this soft-delete action for compliance tracking.
   *
   * This is a soft delete operation (not a hard delete). The image can be restored via a dedicated RESTORE endpoint which is not implemented in this operation.
   *
   * @param connection
   * @param productId ID of the product the image belongs to
   * @param imageId ID of the image to delete
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification 1. Verify product exists and image exists under that product
   * 2. Set deleted_at timestamp to current time in ecommerce_product_images table
   * 3. Return complete image record with deleted_at value
   * 4. Trigger snapshot creation for product image deletion (automatically handled by Prisma hook)
   * 5. Ensure audit logging records the soft delete event
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":imageId")
  public async erase(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedParam("imageId")
    imageId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteEcommerceSellerProductsProductIdImagesImageId({
        seller,
        productId,
        imageId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
