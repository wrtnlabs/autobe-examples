import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceProduct } from "../../../../api/structures/IEcommerceProduct";
import { IPageIEcommerceProduct } from "../../../../api/structures/IPageIEcommerceProduct";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { deleteEcommerceSellerProductsProductId } from "../../../../providers/deleteEcommerceSellerProductsProductId";
import { getEcommerceSellerProductsProductId } from "../../../../providers/getEcommerceSellerProductsProductId";
import { patchEcommerceSellerProducts } from "../../../../providers/patchEcommerceSellerProducts";
import { postEcommerceSellerProducts } from "../../../../providers/postEcommerceSellerProducts";
import { putEcommerceSellerProductsProductId } from "../../../../providers/putEcommerceSellerProductsProductId";

@Controller("/ecommerce/seller/products")
export class EcommerceSellerProductsController {
  /**
   * Create a new product listing for the e-commerce platform. This operation enables sellers to register new products with mandatory business validations.
   *
   * Product creation requires minimum text lengths for name and description to prevent incomplete listings. The base price must be at least $0.01 to ensure valid pricing. Category selection must reference an existing category to maintain data integrity.
   *
   * The operation creates a new product entry with all specified fields. The system requires that at least one variant is added after creation through the POST /products/{id}/variants endpoint. Sellers cannot proceed with product visibility until variants are added.
   *
   * This operation may be called immediately after seller authentication (POST /sellers). The resulting product becomes visible to customers only after completing variant configuration.
   *
   * @param connection
   * @param body Product creation details with mandatory validations
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Validate product creation with: name length ≥ 5 characters, description length ≥ 10 characters, basePrice ≥ 0.01. Enforce category ID reference to existing categories. Create new product record with all provided fields. Verify product has at least one variant (requires subsequent variant addition operation). Do not allow creation if validation fails. Log creation with user ID and timestamp. Check category existence before creation. Handle case where category is deleted (return 404).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IEcommerceProduct.ICreate,
  ): Promise<IEcommerceProduct> {
    try {
      return await postEcommerceSellerProducts({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a filtered and paginated list of product listings available on the platform.
   *
   * This endpoint provides comprehensive search capabilities including product name partial matching, category filtering, and price range constraints. Supports dynamic pagination for optimal performance with large datasets. The results include abbreviated product information suitable for shopping cart interfaces and product listing pages.
   *
   * The API respects product lifecycle rules: only active products (not deleted) are displayed, though administrators can view historical product snapshots via separate endpoints. Product variants are not included in the summary response.
   *
   * This operation is protected with authentication - customers and sellers can view their own product listings, while administrators can view all products.
   *
   * @param connection
   * @param body Search criteria and pagination parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query ecommerce_products table with pagination and filtering. Apply search filters on product name (partial match), category ID, base price range, and creation date. Return cursor-based pagination with total count and page metadata. Handle empty results case gracefully without errors.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IEcommerceProduct.IRequest,
  ): Promise<IPageIEcommerceProduct.ISummary> {
    try {
      return await patchEcommerceSellerProducts({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves detailed information for a specific product by its unique identifier.
   *
   * This operation provides comprehensive product information including the product name, description, base price, creation timestamp, and last update timestamp. The data is sourced directly from the ecommerce_products database table, which stores all publicly visible product attributes.
   *
   * The response includes the complete product entity with no related data (such as category details or product images), ensuring focused and efficient data retrieval. This design aligns with the product detail requirements specified in the functional requirements and matches the database schema structure.
   *
   * @param connection
   * @param productId Unique identifier of the product to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Retrieve the complete product record by ID from the ecommerce_products table. Validate that the product ID is a valid UUID and exists in the database. Exclude soft-deleted products (deleted_at IS NULL). The implementation should only query product fields present in the database schema (id, name, description, base_price, category_id, created_at, updated_at). Return the product without related data (category, images) to maintain single-responsibility and avoid N+1 query problems.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":productId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string,
  ): Promise<IEcommerceProduct> {
    try {
      return await getEcommerceSellerProductsProductId({
        seller,
        productId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update product details with validations and immutable snapshot creation.
   *
   * This operation allows sellers to modify product properties including name, description, category, and base price. The system automatically validates input fields against minimum length requirements (name: 5+ characters, description: 10+ characters, base price: min $0.01) before persisting changes.
   *
   * When the product is updated, an immutable snapshot record is created containing all previous field values before modification. This snapshot includes timestamp (ISO 8601 format), the user who made the change, and all previous values.
   *
   * The response returns the updated product data immediately after modification, enabling the client interface to display the new product state without requiring additional API calls.
   *
   * All fields are mandatory (except those not present in the schema) to prevent incomplete product modifications. Validation errors should be returned with specific field details to guide the seller in correcting inputs.
   *
   * @param connection
   * @param productId Product identifier (UUID)
   * @param body Product property updates (name, description, category_id, base_price)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification 1. Validate input against business rules:
   *    - Name: min 5 characters
   *    - Description: min 10 characters
   *    - Base price: > $0.01
   *    - Category: must exist in database
   * 2. Verify product exists and belongs to seller
   * 3. Generate product snapshot with CURRENT values
   * 4. Update main product table
   * 5. Return updated product entity with latest data
   *
   * This operation must not alter the product variants' structure - variant management has separate endpoints. Eventual consistency is maintained through the snapshot creation process before updating the main product record.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":productId")
  public async update(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceProduct.IUpdate,
  ): Promise<IEcommerceProduct> {
    try {
      return await putEcommerceSellerProductsProductId({
        seller,
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Soft-delete a product listing after confirming no linked orders or pending refunds.
   *
   * This endpoint enables sellers to remove product listings from active visibility. The system enforces critical validation that all product variants have zero pending orders and no active cancellation/refund requests before deletion. Successful deletion marks the product as inactive while preserving all historical snapshots for legal compliance and audit purposes.
   *
   * Product metadata remains accessible through historical snapshots but is excluded from live search results and active listings. Sellers receive confirmation of the soft deletion with a note about snapshot preservation for compliance requirements.
   *
   * @param connection
   * @param productId Unique identifier for the product (UUID)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Validate product variants for pending orders: 1. Check ecommerce_order_items where product_id = ${productId} has status = 'pending' or 'processing' → fail if found 2. Check ecommerce_refund_requests for any variant of product_id → fail if found 3. If validation passes, set deleted_at to current timestamp, preserving all snapshots via snapshot mechanism 4. Notify seller of successful deletion with 'product preserved in historical snapshots' message
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":productId")
  public async erase(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteEcommerceSellerProductsProductId({
        seller,
        productId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
