import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceProductVariant } from "../../../../../api/structures/IEcommerceProductVariant";
import { IPageIEcommerceProductVariant } from "../../../../../api/structures/IPageIEcommerceProductVariant";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { deleteEcommerceSellerProductsProductIdVariantsVariantId } from "../../../../../providers/deleteEcommerceSellerProductsProductIdVariantsVariantId";
