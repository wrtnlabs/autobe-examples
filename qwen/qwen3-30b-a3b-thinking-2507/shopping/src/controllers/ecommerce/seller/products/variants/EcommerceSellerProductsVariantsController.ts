import { postEcommerceSellerProductsProductIdVariants } from "../../../../../providers/postEcommerceSellerProductsProductIdVariants";
import { putEcommerceSellerProductsProductIdVariantsVariantId } from "../../../../../providers/putEcommerceSellerProductsProductIdVariantsVariantId";

@Controller("/ecommerce/seller/products/:productId/variants")
export class EcommerceSellerProductsVariantsController {
  /**
   * Create a new product variant compatible with the specified product. This operation enables sellers to extend product options with unique SKU codes, price tiers, and inventory quantities.
   *
   * Sellers must provide a valid SKU code unique to the product, non-zero price, and stock quantity. The system validates SKU uniqueness against the product's existing variants to prevent duplicates.
   *
   * Upon successful creation, the system automatically generates a product snapshot to record the modification history for audit purposes, ensuring all configuration changes remain traceable.
   *
   * @param connection
   * @param productId Product identifier for which the variant is created
   * @param body New product variant specification with required fields
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Validates seller ownership of product, checks SKU uniqueness per product, enforces price > 0 and stock ≥ 0. Creates variant record and triggers product snapshot (for modification tracking). Prevents duplicate SKU validation during creation. Uses warehouse inventory system to validate stock levels against current system state.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceProductVariant.ICreate,
  ): Promise<IEcommerceProductVariant> {
    try {
      return await postEcommerceSellerProductsProductIdVariants({
        seller,
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves all product variants associated with a specific product ID, supporting advanced search filtering and pagination. This endpoint enables customers to view available product variants (e.g., different colors, sizes) for a given product, along with their current price, stock status, and variant options. Supports filtering by variant attributes and price ranges to improve product discovery.
   *
   * The response includes paginated results optimized for display in product detail pages, containing only essential information for frontend rendering such as variant ID, option labels, price, and stock quantity.
   *
   * @param connection
   * @param productId Product ID identifier (scoped to specific product)
   * @param body Search criteria and pagination parameters for product variants
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query ecommerce_product_variants table with pagination and filtering. Filter by productId from path parameter and request body search criteria. Handle option-based filtering (size, color), price ranges, and stock availability. Apply cursor-based pagination for performance.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceProductVariant.IRequest,
  ): Promise<IPageIEcommerceProductVariant.ISummary> {
    try {
      return await patchEcommerceSellerProductsProductIdVariants({
        seller,
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific product variant within a product. This operation provides the SKU code, variant-specific price (or uses product's base price if null), creation timestamp, update timestamp, and active status for the variant.
   *
   * This endpoint is primarily used in product detail views and shopping workflows where individual variant selection is required. The response includes complete variant data excluding soft-deleted records (deleted_at field is null).
   *
   * The operation is protected by authentication and requires the requesting user to either own the product (seller) or have permission to view it (customer).
   *
   * @param connection
   * @param productId Unique identifier for the product
   * @param variantId Unique identifier for the product variant
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Fetch product variant with specified variantId under productId. Filter out deleted variants (deleted_at IS NULL). Validate product and variant exist before returning data. Use foreign key relationship ecommerce_product_id → ecommerce_products.id. Handle UUID parameters correctly in service layer.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":variantId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string,
    @TypedParam("variantId")
    variantId: string,
  ): Promise<IEcommerceProductVariant> {
    try {
      return await getEcommerceSellerProductsProductIdVariantsVariantId({
        seller,
        productId,
        variantId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update a product variant's SKU code and/or price.
   *
   * This operation allows sellers to modify specific variant details of a product. The SKU code must be unique within the product to prevent conflicts, while the price can override the product's base price or be set to null to revert to the default.
   *
   * Changes to variant details automatically trigger creation of an immutable snapshot, preserving the change history for audit purposes. The operation requires the seller who created the product to own the variant to make modifications.
   *
   * The updated variant data includes all fields with the new values applied, including the updated timestamp to indicate the most recent modification.
   *
   * @param connection
   * @param productId Product identifier (UUID)
   * @param variantId Variant identifier (UUID)
   * @param body Variant update payload
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification 1. Verify product variant exists and belongs to the product.
   * 2. Check sku_code uniqueness within product's variants.
   * 3. Validate price is positive when provided, or allow null for base price inheritance.
   * 4. Update fields: sku_code, price.
   * 5. Set updated_at timestamp.
   * 6. Create immutable snapshot of previous/updated values.
   * 7. Perform database transaction with validation errors.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":variantId")
  public async update(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string,
    @TypedParam("variantId")
    variantId: string,
    @TypedBody()
    body: IEcommerceProductVariant.IUpdate,
  ): Promise<IEcommerceProductVariant> {
    try {
      return await putEcommerceSellerProductsProductIdVariantsVariantId({
        seller,
        productId,
        variantId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently remove a product variant from active inventory while preserving its historical record for audit and compliance purposes.
   *
   * This operation sets the 'deleted_at' timestamp on the variant record, marking it as inactive without physical removal from the database. Historical data remains available for compliance reporting, order processing, and audit trails.
   *
   * Variants may only be deleted when no related order items exist (verified during implementation). Any pending cancellation/refund requests for the variant must be resolved prior to deletion.
   *
   * This operation does not affect parent product record, category associations, or other variants.
   *
   * @param connection
   * @param productId The ID of the product the variant belongs to
   * @param variantId The ID of the specific variant to delete
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Service method should:
   * 1. Validate variant exists and belongs to specified product
   * 2. Check for any active order items referencing this variant
   * 3. Verify no pending cancellation/refund requests for the variant
   * 4. Set deleted_at timestamp to current time
   * 5. Return HTTP 204 No Content indicating successful soft deletion
   *
   * Edge cases:
   * - Return 404 if variant/product not found
   * - Return 409 Conflict if active order items exist
   * - Return 409 Conflict if pending requests exist
   * - Validate product ID and variant ID are UUIDs
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":variantId")
  public async erase(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedParam("variantId")
    variantId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteEcommerceSellerProductsProductIdVariantsVariantId({
        seller,
        productId,
        variantId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
