import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IPageIEcommerceSystemStatus } from "../../../../api/structures/IPageIEcommerceSystemStatus";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { getEcommerceSellerDashboard } from "../../../../providers/getEcommerceSellerDashboard";

@Controller("/ecommerce/seller/dashboard")
export class EcommerceSellerDashboardController {
  /**
   * Retrieve a prioritized overview of system health status for monitoring purposes.
   *
   * This dashboard endpoint provides real-time insight into the operational status of system components, presenting the most critical health issues first. It's designed for system administrators to quickly assess the platform's health by highlighting components requiring attention.
   *
   * The response includes only essential metrics (component name, status, and health score) for optimal dashboard performance, with healthy components filtered out to focus on actionable items.
   *
   * Component statuses use standard monitoring terminology: 'healthy' (100), 'warning' (50-99), 'unhealthy' (0-49).
   *
   * This endpoint does not accept any parameters and uses default pagination for best performance.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query ecommerce_system_statuses using health_score DESC sorting with default pagination (page 1, limit 50). Filter to include components with status 'warning' or 'unhealthy' with priority. Return only summary fields (component_name, status, health_score) for efficient dashboard display.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
  ): Promise<IPageIEcommerceSystemStatus.ISummary> {
    try {
      return await getEcommerceSellerDashboard({
        seller,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
