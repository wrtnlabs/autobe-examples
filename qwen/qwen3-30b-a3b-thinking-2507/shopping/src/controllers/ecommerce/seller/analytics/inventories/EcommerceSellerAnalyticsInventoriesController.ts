import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceVariantInventory } from "../../../../../api/structures/IEcommerceVariantInventory";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { getEcommerceSellerAnalyticsInventories } from "../../../../../providers/getEcommerceSellerAnalyticsInventories";

@Controller("/ecommerce/seller/analytics/inventories")
export class EcommerceSellerAnalyticsInventoriesController {
  /**
   * Retrieve aggregate inventory analytics data including stock trends, adjustment history, and current inventory status for all product variants.
   *
   * Provides detailed insights into inventory movement patterns, including restocking events, order deductions, and manual inventory adjustments. The data enables sellers to monitor stock health, identify slow-moving items, and optimize purchase orders based on historical trends.
   *
   * Includes real-time inventory status metrics (in-stock/out-of-stock), adjustment count per product variant, and time-based trends showing inventory changes. For analytics purposes, all data in the response is aggregated across time periods rather than showing individual records.
   *
   * The data is optimized for dashboard displays in the seller management interface and is accessible only to seller actors with full account access. Requires valid JWT authentication with seller role to access.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query ecommerce_variant_inventories table to generate aggregate inventory analytics including stock trend metrics, adjustment reasons, and current inventory status across all product variants. Implement date range filtering via query parameters with default to last 30 days.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async inventoryAnalytics(
    @SellerAuth()
    seller: SellerPayload,
  ): Promise<IEcommerceVariantInventory> {
    try {
      return await getEcommerceSellerAnalyticsInventories({
        seller,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
