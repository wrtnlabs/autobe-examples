import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceCustomerProfile } from "../../../../api/structures/IEcommerceCustomerProfile";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { patchEcommerceSellerProfile } from "../../../../providers/patchEcommerceSellerProfile";

@Controller("/ecommerce/seller/profile")
export class EcommerceSellerProfileController {
  /**
   * Update the currently authenticated customer's profile display name and phone number.
   *
   * The profile update operation allows customers to modify their public display name and phone number. Display name must be between 2-50 characters and avoid offensive language. Phone number must be in valid E.164 international format with country code.
   *
   * All changes are immediately reflected in customer-facing interfaces. A snapshot of the previous profile state is created automatically for audit purposes. Updates are only permitted for the authenticated customer's own profile.
   *
   * @param connection
   * @param body Updated profile fields for display name and phone number
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Validate display_name length (2-50 characters) and profanity screening. Validate phone_number in E.164 format. Apply updated fields to profile record. Create a snapshot of previous profile state using IEcommerceCustomerProfileSnapshot service with actor=auth.currentUserId. Update timestamp field automatically. All validation rules match those in 03-functional-requirements.md and 06-exception-handling.md.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async update(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IEcommerceCustomerProfile.IUpdate,
  ): Promise<IEcommerceCustomerProfile> {
    try {
      return await patchEcommerceSellerProfile({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
