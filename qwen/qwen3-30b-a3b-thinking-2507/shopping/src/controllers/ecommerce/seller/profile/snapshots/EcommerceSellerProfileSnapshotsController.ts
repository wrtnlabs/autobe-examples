import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IPageIEcommerceCustomerProfileSnapshot } from "../../../../../api/structures/IPageIEcommerceCustomerProfileSnapshot";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { getEcommerceSellerProfileSnapshots } from "../../../../../providers/getEcommerceSellerProfileSnapshots";

@Controller("/ecommerce/seller/profile/snapshots")
export class EcommerceSellerProfileSnapshotsController {
  /**
   * Retrieve the full history of modifications to a customer's profile.
   *
   * This endpoint provides a chronological view of all changes made to the customer's profile information, including display name, phone number, and other editable fields. Each snapshot preserves the previous values before the change, the date and time of the modification, and the actor (user) who made the change.
   *
   * The response is paginated with a maximum of 10 records per page. Each item in the response represents a complete historical version of the profile at the time of modification, allowing customers to review their entire profile modification history.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query ecommerce_customer_profile_snapshots table for all snapshots belonging to the currently authenticated customer. Apply default pagination (10 records per page) with cursor-based pagination. Return snapshots with timestamp, previous values, and operation type. Ensure only the customer's own snapshots are returned.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async list(
    @SellerAuth()
    seller: SellerPayload,
  ): Promise<IPageIEcommerceCustomerProfileSnapshot.ISummary> {
    try {
      return await getEcommerceSellerProfileSnapshots({
        seller,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
