import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceRefundRequest } from "../../../../../api/structures/IEcommerceRefundRequest";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { getEcommerceSellerOrdersOrderIdRefundRequestsRefundRequestId } from "../../../../../providers/getEcommerceSellerOrdersOrderIdRefundRequestsRefundRequestId";
import { putEcommerceSellerOrdersOrderIdRefundRequestsRefundRequestId } from "../../../../../providers/putEcommerceSellerOrdersOrderIdRefundRequestsRefundRequestId";

@Controller(
  "/ecommerce/seller/orders/:orderId/refund-requests/:refundRequestId",
)
export class EcommerceSellerOrdersRefund_requestsController {
  /**
   * Retrieve a specific refund request for an order item that has been delivered within the 7-day window.
   *
   * This operation provides detailed information about a customer's refund request, including the reason for the refund, current status, and timestamps. The refund request is associated with a specific order item that has reached a 'delivered' status.
   *
   * The API is accessible to customers who submitted the refund request and sellers associated with the product. The refund request status may be 'pending', 'approved', or 'rejected' indicating the current stage of the refund process. The reason for the refund is provided in free text by the customer.
   *
   * The operation requires the order ID and refund request ID as parameters. The order ID is used to verify the context of the refund request, while the refund request ID uniquely identifies the specific refund request record.
   *
   * @param connection
   * @param orderId The order identifier associated with this refund request
   * @param refundRequestId The specific refund request identifier to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification 1. Verify orderId exists and matches refund request order item
   * 2. Confirm refund request exists with the given refundRequestId
   * 3. Check refund request status is 'delivered' for order item
   * 4. Handle soft-delete: return record if deleted_at is null, otherwise return 404
   * 5. Select all relevant fields from ecommerce_refund_requests table with relationship to order item
   * 6. Return only authorized fields based on actor (customer/seller)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedParam("refundRequestId")
    refundRequestId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceRefundRequest> {
    try {
      return await getEcommerceSellerOrdersOrderIdRefundRequestsRefundRequestId(
        {
          seller,
          orderId,
          refundRequestId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update the status of a refund request for an item within an order.
   *
   * This operation allows sellers to approve or reject customer refund requests for delivered items within the allowed 7-day window. The refund request must be in 'pending' state to be updated. Approved requests trigger stock restoration and refund processing, while rejected requests update the status immediately with an optional reason.
   *
   * The system validates that the order item is in 'delivered' status and that the refund request submission falls within 7 days of delivery. This operation requires seller authentication and can only be executed by sellers who manage the affected order.
   *
   * Refund request updates are recorded in the database and trigger corresponding business processes through the Order component. A successful update returns the updated refund request data with the new status.
   *
   * @param connection
   * @param orderId ID of the order containing the item requiring refund
   * @param refundRequestId ID of the refund request to update
   * @param body Status update for the refund request (pending, approved, rejected)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification 1. Validate that the refund request exists and is associated with the specified order item
   * 2. Verify refund request status is 'pending' for update
   * 3. Check if the request falls within 7 days of delivery
   * 4. Update the 'status' field to 'approved' or 'rejected' based on the request body
   * 5. If approval: create positive inventory record (restore stock) and process refund
   * 6. If rejection: update status to 'rejected' and notify customer via email
   * 7. Prevent updates to 'delivered' items outside 7-day window (per 7-day rule)
   * 8. Include timestamp update during status change
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedParam("refundRequestId")
    refundRequestId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceRefundRequest.IUpdate,
  ): Promise<IEcommerceRefundRequest> {
    try {
      return await putEcommerceSellerOrdersOrderIdRefundRequestsRefundRequestId(
        {
          seller,
          orderId,
          refundRequestId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
