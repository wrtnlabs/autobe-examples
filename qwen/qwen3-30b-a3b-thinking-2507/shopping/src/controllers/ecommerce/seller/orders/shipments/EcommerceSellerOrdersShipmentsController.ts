import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceShipment } from "../../../../../api/structures/IEcommerceShipment";
import { IPageIEcommerceShipment } from "../../../../../api/structures/IPageIEcommerceShipment";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { getEcommerceSellerOrdersOrderIdShipmentsShipmentId } from "../../../../../providers/getEcommerceSellerOrdersOrderIdShipmentsShipmentId";
import { patchEcommerceSellerOrdersIdShipments } from "../../../../../providers/patchEcommerceSellerOrdersIdShipments";
import { postEcommerceSellerOrdersIdShipments } from "../../../../../providers/postEcommerceSellerOrdersIdShipments";
import { putEcommerceSellerOrdersOrderIdShipmentsShipmentId } from "../../../../../providers/putEcommerceSellerOrdersOrderIdShipmentsShipmentId";

@Controller("/ecommerce/seller/orders")
export class EcommerceSellerOrdersShipmentsController {
  /**
   * Create a new shipment for order items belonging to the same seller.
   *
   * This operation enables sellers to provide carrier information and tracking number for items in an order. The system automatically groups all items from the same seller into a single shipment with a unified tracking number.
   *
   * Upon successful creation, all order items linked to this shipment will update to 'shipped' status. The response contains complete shipment details for integration with carrier tracking systems. Only one shipment may be created per seller per order (preventing duplicate shipments for same seller's items).
   *
   * @param connection
   * @param id Order ID to associate the shipment with (UUID format)
   * @param body Shipment details including carrier and tracking number
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Validates order ID exists and is owned by current seller. Creates shipment with provided carrier and tracking number. Groups all order items belonging to the same seller into this shipment. Automatically sets shipment status to 'shipped'. Creates shipment_items records linking all order items to the new shipment. Returns the newly created shipment details with tracking ID.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post(":id/shipments")
  public async create(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceShipment.ICreate,
  ): Promise<IEcommerceShipment> {
    try {
      return await postEcommerceSellerOrdersIdShipments({
        seller,
        id,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a paginated list of shipment details for a specific order.
   *
   * This operation provides comprehensive shipment tracking information for the specified order, including carrier names, tracking numbers, and current status information. Shipments are grouped by seller and include full shipping details with expected delivery dates.
   *
   * The endpoint supports filtering shipments by status (e.g., 'shipped', 'delivered') and carrier name, allowing customers and sellers to view shipment progress at a granular level. Results are paginated with configurable page size for efficient data loading.
   *
   * Responses include shipment status transitions following operational rules: 'pending' → 'in_progress' → 'shipped' → 'delivered' or 'cancelled', with automatic 'delivered' status after 14 days if not confirmed by customer.
   *
   * @param connection
   * @param id Order identifier used to fetch related shipments
   * @param body Pagination parameters and shipment filters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Fetch all shipments associated with specified order.
   * Retrieve shipments with carrier name, tracking number, status, and delivery dates.
   * Implement filters on shipment status and carrier name.
   * Use cursor-based pagination for large result sets.
   * Join with ecommerce_orders to verify order ownership before proceeding.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch(":id/shipments")
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceShipment.IRequest,
  ): Promise<IPageIEcommerceShipment.ISummary> {
    try {
      return await patchEcommerceSellerOrdersIdShipments({
        seller,
        id,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed shipment information for a specific shipment within an order.
   *
   * This endpoint enables sellers to view the current status and tracking information of a shipment for a particular order. The response includes carrier details, tracking number, current status, and delivery dates for the shipment.
   *
   * Available shipment statuses include 'pending', 'in_progress', 'shipped', 'delivered', and 'cancelled', with the status updated in real-time as the shipment progresses through the delivery process. The tracking information is sourced directly from the carrier's system and is visible to sellers for managing shipment logistics efficiently.
   *
   * @param connection
   * @param orderId The unique identifier of the order
   * @param shipmentId The unique identifier of the shipment within the order
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Fetch shipment from ecommerce_shipments table where id = shipmentId and ecommerce_order_id = orderId. Validate shipment belongs to the specified order. Check for soft-deleted records (deleted_at not null) and return 404 if found. Return all shipment fields including carrier_name, tracking_number, status, shipment_date, existing_delivery_date.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":orderId/shipments/:shipmentId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedParam("shipmentId")
    shipmentId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceShipment> {
    try {
      return await getEcommerceSellerOrdersOrderIdShipmentsShipmentId({
        seller,
        orderId,
        shipmentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update shipment details for a specific order's shipment. This operation allows sellers to modify carrier information, tracking numbers, and shipment status for items within an order.
   *
   * The primary focus is on updating tracking data, which requires a valid carrier selection from the predefined options (FedEx, UPS, USPS) and a tracking number of at least 10 characters. The system automatically validates these constraints to prevent invalid input.
   *
   * This API operation is used when sellers provide shipping details or update shipping information after an order has been processed. Sellers must ensure that all shipment fields are accurately updated to reflect the actual shipment status for customer visibility.
   *
   * @param connection
   * @param orderId ID of the order this shipment belongs to
   * @param shipmentId ID of the shipment to update
   * @param body Shipment updates including carrier information, tracking details, and status
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query ecommerce_shipments table to update specified shipment. Validate carrier_name is in ['FedEx', 'UPS', 'USPS'] and tracking_number has minimum length 10. Verify shipment belongs to order via ecommerce_order_id relation. Update all specified fields with input and set updated_at timestamp. Handle date fields as ISO 8601 strings.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":orderId/shipments/:shipmentId")
  public async update(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedParam("shipmentId")
    shipmentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceShipment.IUpdate,
  ): Promise<IEcommerceShipment> {
    try {
      return await putEcommerceSellerOrdersOrderIdShipmentsShipmentId({
        seller,
        orderId,
        shipmentId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
