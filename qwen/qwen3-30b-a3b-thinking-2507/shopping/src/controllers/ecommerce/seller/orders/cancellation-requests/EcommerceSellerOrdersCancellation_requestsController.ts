import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceCancellationRequest } from "../../../../../api/structures/IEcommerceCancellationRequest";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { getEcommerceSellerOrdersOrderIdCancellationRequestsCancellationRequestId } from "../../../../../providers/getEcommerceSellerOrdersOrderIdCancellationRequestsCancellationRequestId";
import { putEcommerceSellerOrdersOrderIdCancellationRequestsCancellationRequestId } from "../../../../../providers/putEcommerceSellerOrdersOrderIdCancellationRequestsCancellationRequestId";

@Controller(
  "/ecommerce/seller/orders/:orderId/cancellation-requests/:cancellationRequestId",
)
export class EcommerceSellerOrdersCancellation_requestsController {
  /**
   * Retrieve detailed information about a specific cancellation request for an order item.
   *
   * This endpoint provides the complete cancellation request details including reason provided by customer, current status (pending/approved/rejected), timestamps for creation, status changes, and any associated notes. Linked to order items with status 'paid' that haven't shipped.
   *
   * Customers can view their own requests; sellers can access for 48-hour processing window. System ensures only 'paid' items are accessible.
   *
   * @param connection
   * @param orderId Identifier of the order containing the item to be cancelled
   * @param cancellationRequestId Unique identifier of the cancellation request
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Retrieves specific cancellation request record from ecommerce_cancellation_requests table. Validates query against business rules (only 'paid' order items). Checks authentication context for customer/seller. Returns complete record with status and timestamps.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedParam("cancellationRequestId")
    cancellationRequestId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceCancellationRequest> {
    try {
      return await getEcommerceSellerOrdersOrderIdCancellationRequestsCancellationRequestId(
        {
          seller,
          orderId,
          cancellationRequestId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update the status of a cancellation request for a specific order item.
   *
   * This operation handles the seller's approval or rejection of a customer's cancellation request. The system will validate the cancellation request's state before processing, ensuring the request is still pending and the associated product item has not been shipped.
   *
   * Upon approval, the order item is marked as cancelled, variant inventory is restored, and a refund processing workflow is initiated. The seller's decision is recorded in the cancellation request log with a timestamp and actor reference.
   *
   * The operation creates an immutable snapshot of the cancellation request status change for audit purposes. Only order items in 'paid' status can be cancelled before shipment, and the order must not have been partially shipped.
   *
   * @param connection
   * @param orderId ID of the parent order this cancellation request belongs to
   * @param cancellationRequestId ID of the cancellation request being updated
   * @param body Seller's decision on the cancellation request
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification 1. Verify cancellation request status is currently 'pending'
   * 2. Check associated order items are still in 'paid' status and not shipped
   * 3. Validate request ID matches order ID
   * 4. Update cancellation request status to 'approved' or 'rejected'
   * 5. If status change to 'approved', update order item status to 'cancelled', restore variant inventory, and create snapshot
   * 6. On approval, initiate partial refund process for the item
   * 7. Create immutable status change snapshot with actor ID and timestamp
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedParam("cancellationRequestId")
    cancellationRequestId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceCancellationRequest.IUpdate,
  ): Promise<IEcommerceCancellationRequest> {
    try {
      return await putEcommerceSellerOrdersOrderIdCancellationRequestsCancellationRequestId(
        {
          seller,
          orderId,
          cancellationRequestId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
