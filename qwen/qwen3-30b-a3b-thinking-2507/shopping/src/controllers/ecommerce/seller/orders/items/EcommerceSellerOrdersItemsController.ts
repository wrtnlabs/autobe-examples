import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceOrderItem } from "../../../../../api/structures/IEcommerceOrderItem";
import { IPageIEcommerceOrderItem } from "../../../../../api/structures/IPageIEcommerceOrderItem";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { getEcommerceSellerOrdersOrderIdItemsOrderItemId } from "../../../../../providers/getEcommerceSellerOrdersOrderIdItemsOrderItemId";
import { patchEcommerceSellerOrdersIdItems } from "../../../../../providers/patchEcommerceSellerOrdersIdItems";

@Controller("/ecommerce/seller/orders")
export class EcommerceSellerOrdersItemsController {
  /**
   * Retrieve a paginated list of items within a specific order, showing purchase details and current lifecycle status.
   *
   * This operation provides comprehensive item-level information for order management, including the exact product variant details, purchase price, quantity, and current status (paid, shipped, delivered, cancelled, or refunded). The item list is essential for customers to track order progress, for sellers to manage fulfillment, and to calculate order status transitions based on item statuses.
   *
   * The response includes all relevant item information in a summary format optimized for UI display, with pagination allowing efficient loading of large order histories without overwhelming the frontend.
   *
   * @param connection
   * @param id Order identifier (UUID)
   * @param body Pagination parameters for items list (page, limit, sort, filters)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Fetch all order items matching order_id from path parameter. Apply pagination parameters (page, limit) from request body. Join with ecommerce_product_variants to include variant details (name, options) in summary. Return cursor-based pagination. Validate order ID exists and belongs to authenticated user.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch(":id/items")
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceOrderItem.IRequest,
  ): Promise<IPageIEcommerceOrderItem.ISummary> {
    try {
      return await patchEcommerceSellerOrdersIdItems({
        seller,
        id,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about an individual item within a specific order.
   *
   * This endpoint provides complete details for a purchased product variant in an order, including the exact purchase price, quantity, and current status in the fulfillment workflow. The status field reflects the item's progression through the order lifecycle (Paid, Shipped, Delivered, Cancelled, or Refunded) as defined in business rules.
   *
   * The response includes only essential fields required for order history and detail views, optimized for performance. Data structure strictly matches the ecommerce_order_items database schema with all non-deleted fields included.
   *
   * @param connection
   * @param orderId Unique identifier for the order containing the item
   * @param orderItemId Unique identifier for the specific order item within the order
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query ecommerce_order_items table using orderId parameter and orderItemId (id column). Validate order item existence and active status. Return all fields from schema for non-deleted items with status value validation against business rules.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":orderId/items/:orderItemId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("orderId")
    orderId: string,
    @TypedParam("orderItemId")
    orderItemId: string,
  ): Promise<IEcommerceOrderItem> {
    try {
      return await getEcommerceSellerOrdersOrderIdItemsOrderItemId({
        seller,
        orderId,
        orderItemId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
