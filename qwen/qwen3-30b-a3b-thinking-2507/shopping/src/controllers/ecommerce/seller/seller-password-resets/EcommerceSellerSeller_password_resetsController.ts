import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceSellerPasswordReset } from "../../../../api/structures/IEcommerceSellerPasswordReset";
import { IPageIEcommerceSellerPasswordReset } from "../../../../api/structures/IPageIEcommerceSellerPasswordReset";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { getEcommerceSellerSellerPasswordResetsResetId } from "../../../../providers/getEcommerceSellerSellerPasswordResetsResetId";
import { patchEcommerceSellerSellerPasswordResets } from "../../../../providers/patchEcommerceSellerSellerPasswordResets";

@Controller("/ecommerce/seller/seller-password-resets")
export class EcommerceSellerSeller_password_resetsController {
  /**
   * Retrieve a paginated list of active seller password reset tokens with search filtering capabilities.
   *
   * This endpoint provides administrative visibility into seller password reset workflows. Results include token details within their 24-hour validity window, seller identity, and timestamps for verification purposes. Filters can be applied to narrow results by seller, token status, or expiration window.
   *
   * The response efficiently returns summary data optimized for display in administrative interfaces, excluding sensitive fields like the actual token value. Data follows the Snapshot Principle for auditability, with results reflecting current state (soft-deleted records are excluded from results).
   *
   * @param connection
   * @param body Search, filter, and pagination specifications for password reset tokens
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query ecommerce_seller_password_resets table with filters for seller_id, token validity (expires_at > current time), and pagination. Apply cursor-based pagination with limit/offset parameters. Filter out soft-deleted records (deleted_at is null). Validate filters against database schema constraints to prevent null references.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IEcommerceSellerPasswordReset.IRequest,
  ): Promise<IPageIEcommerceSellerPasswordReset.ISummary> {
    try {
      return await patchEcommerceSellerSellerPasswordResets({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific password reset token for seller accounts by its unique identifier.
   *
   * This endpoint returns the complete details of a password reset token, including its token value, expiration timestamp, and creation details. The response is used to verify token validity during the password reset process.
   *
   * The token expires 24 hours after creation. The operation returns the full token record, which the frontend uses to process password reset requests. Tokens that have expired or been marked as soft-deleted are not returned. The seller_id field links to the corresponding seller account for authentication context.
   *
   * @param connection
   * @param resetId Unique identifier for the password reset token
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query ecommerce_seller_password_resets table by primary key 'id'. Return full record including all fields (token, expires_at, created_at, updated_at, seller_id) without soft-delete filtering. Validate token against current time and expiration (expires_at > current timestamp). Ensure association with active seller account via foreign key relationship.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":resetId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("resetId")
    resetId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceSellerPasswordReset> {
    try {
      return await getEcommerceSellerSellerPasswordResetsResetId({
        seller,
        resetId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
