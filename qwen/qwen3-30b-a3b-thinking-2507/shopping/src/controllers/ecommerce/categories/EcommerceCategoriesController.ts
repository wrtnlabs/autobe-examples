import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceCategory } from "../../../api/structures/IEcommerceCategory";
import { IPageIEcommerceCategory } from "../../../api/structures/IPageIEcommerceCategory";
import { deleteEcommerceCategoriesCategoryId } from "../../../providers/deleteEcommerceCategoriesCategoryId";
import { getEcommerceCategoriesCategoryId } from "../../../providers/getEcommerceCategoriesCategoryId";
import { patchEcommerceCategories } from "../../../providers/patchEcommerceCategories";
import { postEcommerceCategories } from "../../../providers/postEcommerceCategories";
import { putEcommerceCategoriesCategoryId } from "../../../providers/putEcommerceCategoriesCategoryId";

@Controller("/ecommerce/categories")
export class EcommerceCategoriesController {
  /**
   * Create a new category for product organization.
   *
   * This operation enables administrators to add new categories to the product catalog with one-level subcategory support. The system validates category names against predefined business terms to maintain consistent vocabulary across the catalog.
   *
   * Categories can be organized hierarchically with a single parent level (e.g. Electronics > Laptops). Each category must have a unique name matching predefined terms and cannot use reserved category names.
   *
   * Requires administrator authentication. Response contains the newly created category with all attributes including hierarchical relationships and system metadata.
   *
   * @param connection
   * @param body Category creation specification.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Create new category via IEcommerceCategory.ICreate DTO. Validate category name against predefined terms (e.g. food, electronics), enforce single-level hierarchy via parentCategoryId. Return full IEcommerceCategory object on success. Handle validation errors for invalid names and duplicate category names.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @TypedBody()
    body: IEcommerceCategory.ICreate,
  ): Promise<IEcommerceCategory> {
    try {
      return await postEcommerceCategories({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve paginated list of categories with optional search filtering.
   *
   * This operation provides comprehensive access to the category hierarchy including parent-child relationships. Users can search by category name or description, and view results with sorting capabilities.
   *
   * The response includes detailed category information including unique name, description, and timestamps. Excludes deleted categories by default.
   *
   * Pagination uses cursor-based implementation to handle large result sets efficiently. Category tree structure is preserved in the response for hierarchical navigation.
   *
   * @param connection
   * @param body Search criteria and pagination parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query ecommerce_categories table with sorting, filtering by name (case-insensitive), and description (full-text search). Implement cursor-based pagination with page size of 20. Apply soft delete exclusion for deleted entities. Include category parent-child relationships in results.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IEcommerceCategory.IRequest,
  ): Promise<IPageIEcommerceCategory.ISummary> {
    try {
      return await patchEcommerceCategories({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single category record identified by its unique identifier.
   *
   * This endpoint provides complete category details including name, description, and hierarchy relationship data. The category metadata supports storefront navigation for product categorization and organizational structure display.
   *
   * The response includes the category's full descriptive information and timestamped creation and update details. Parent-child relationships are represented through the parent_id field, enabling hierarchical category organization in the user interface.
   *
   * Note: Categories may be in a soft-deleted state with a non-null deleted_at value, but the endpoint still returns all available category data for administrative purposes.
   *
   * @param connection
   * @param categoryId Unique identifier of the category (UUID format).
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query ecommerce_categories table using path parameter 'categoryId' as id column value. Apply no filtering or pagination. Return all fields including parent_id and deleted_at to maintain full state. Handle non-existent categories with 404 error. Ensure no circular relationships in the object tree when hydrating parent relations.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":categoryId")
  public async at(
    @TypedParam("categoryId")
    categoryId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceCategory> {
    try {
      return await getEcommerceCategoriesCategoryId({
        categoryId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update category properties including name, description, and parent relationship.
   *
   * This operation allows administrators to modify category information while respecting hierarchical relationships. Updates include name changes, description updates, and reorganization of category hierarchy.
   *
   * The response contains the updated category details including hierarchical position information. Only system administrators can modify category definitions; regular users cannot access this endpoint.
   *
   * Updates to category names must be unique within the same root level, and the response will reflect this constraint without explicit error messages.
   *
   * When updating the parent relationship, child categories are automatically repositioned under the new parent, maintaining their relative order.
   *
   * @param connection
   * @param categoryId Unique identifier for the category to update
   * @param body Modified category fields
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Update category details using provided request body. Validate that category exists and that caller has admin privileges. If parentCategoryId is provided, verify it belongs to the same root hierarchy level. Apply category name and description updates. Maintain existing child category hierarchy. If parentCategoryId is removed, move all child categories to root level. Always maintain category name uniqueness per root. Return complete category with updated fields and ID, without any additional state.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":categoryId")
  public async update(
    @TypedParam("categoryId")
    categoryId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceCategory.IUpdate,
  ): Promise<IEcommerceCategory> {
    try {
      return await putEcommerceCategoriesCategoryId({
        categoryId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Mark a category as inactive in the catalog.
   *
   * This operation sets the 'deleted_at' timestamp, making the category invisible to customers and standard API queries while preserving all associated data through the immutable snapshot system. The category is no longer available for product assignment but remains accessible for administrative historical reference.
   *
   * Administrators use this function to clean up outdated or inappropriate categories without permanent data loss, maintaining full auditability through the system's snapshot principle.
   *
   * @param connection
   * @param categoryId The unique identifier of the category to mark as deleted
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Performs soft deletion by setting 'deleted_at' timestamp in ecommerce_categories table. Updates the category record to mark as 'deleted', excluding it from standard list queries. Ensures transaction safety with database update and audit log entry. Does not physically delete the record.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":categoryId")
  public async erase(
    @TypedParam("categoryId")
    categoryId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceCategory> {
    try {
      return await deleteEcommerceCategoriesCategoryId({
        categoryId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
