import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IPageIEcommerceProduct } from "../../../../../api/structures/IPageIEcommerceProduct";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { getEcommerceCustomerAnalyticsTopProducts } from "../../../../../providers/getEcommerceCustomerAnalyticsTopProducts";

@Controller("/ecommerce/customer/analytics/top-products")
export class EcommerceCustomerAnalyticsTop_productsController {
  /**
   * Retrieve top-selling products for business analytics and dashboard displays. This operation provides a comprehensive view of the most popular products across the platform, calculated based on total units sold.
   *
   * The data includes product name, image, price, category, and current sales rank. This information is presented in paginated format optimized for dashboard performance requirements (max 10 items per page initially).
   *
   * For business intelligence purposes, this endpoint is integrated with the system's order processing and snapshot lifecycle features to ensure historical accuracy and auditability of analytics data. The top products list is updated in near real-time based on recent purchase activity.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query ecommerce_order_items to sum quantity sold per product, join with ecommerce_products for details. Order by total quantity descending. Limit to top 10 products for initial response (supports pagination in future). Filter by active products only. Implement cursor-based pagination. Aggregate sales data for last 30 days by default, with optional date range parameter in future.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async topProducts(
    @CustomerAuth()
    customer: CustomerPayload,
  ): Promise<IPageIEcommerceProduct.ISummary> {
    try {
      return await getEcommerceCustomerAnalyticsTopProducts({
        customer,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
