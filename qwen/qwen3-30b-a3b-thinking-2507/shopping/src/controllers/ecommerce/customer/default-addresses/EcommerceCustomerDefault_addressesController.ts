import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceDefaultAddress } from "../../../../api/structures/IEcommerceDefaultAddress";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { getEcommerceCustomerDefaultAddressesDefaultAddressId } from "../../../../providers/getEcommerceCustomerDefaultAddressesDefaultAddressId";
import { patchEcommerceCustomerDefaultAddresses } from "../../../../providers/patchEcommerceCustomerDefaultAddresses";

@Controller("/ecommerce/customer/default-addresses")
export class EcommerceCustomerDefault_addressesController {
  /**
   * Retrieve the current customer's default shipping address configuration.
   *
   * This operation returns the user's primary shipping address, which is used for all future orders. Each customer can have exactly one default address, and the system automatically ensures compliance with this rule.
   *
   * The response provides the configuration record for the default address link, including internal identifiers and timestamps. The actual address details are managed through the associated address entities.
   *
   * Note: The authenticated customer context is used to determine which default address is retrieved. This operation is designed for the customer profile management workflow and should not be used for administrative access.
   *
   * @param connection
   * @param body Search criteria (none needed, uses authenticated user context)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query ecommerce_default_addresses table using authenticated customer ID. Return single record or 404 if no default address is set. Include all relevant fields from the table structure and ensure soft-delete checks are applied during lookup.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IEcommerceDefaultAddress.IRequest,
  ): Promise<IEcommerceDefaultAddress> {
    try {
      return await patchEcommerceCustomerDefaultAddresses({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves a specific customer's default shipping address.
   *
   * This operation provides the active default address configured for a customer, which is used as the primary shipping address for their orders. The response includes all address details with timestamped metadata about when the address was set as default.
   *
   * The response does not include customer details - only the address record. This is a read-only operation managed exclusively through customer entity updates.
   *
   * Note: Address records are soft-deleted (deleted_at timestamped) but not physically removed, allowing historical tracking of address changes.
   *
   * @param connection
   * @param defaultAddressId Unique identifier of the default address record
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Retrieve the default address record by ID. Check for soft delete (deleted_at null). Join with customer entity to ensure valid relationship. Return all schema fields including timestamps. Handle soft-deleted records as absent in results.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":defaultAddressId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("defaultAddressId")
    defaultAddressId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceDefaultAddress> {
    try {
      return await getEcommerceCustomerDefaultAddressesDefaultAddressId({
        customer,
        defaultAddressId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
