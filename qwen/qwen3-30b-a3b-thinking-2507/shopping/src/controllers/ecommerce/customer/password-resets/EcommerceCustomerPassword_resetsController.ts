import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceCustomerPasswordReset } from "../../../../api/structures/IEcommerceCustomerPasswordReset";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { getEcommerceCustomerPasswordResetsResetId } from "../../../../providers/getEcommerceCustomerPasswordResetsResetId";
import { patchEcommerceCustomerPasswordResets } from "../../../../providers/patchEcommerceCustomerPasswordResets";

@Controller("/ecommerce/customer/password-resets")
export class EcommerceCustomerPassword_resetsController {
  /**
   * Retrieve password reset request details for token validation.
   *
   * This operation allows the system to verify a secure password reset token used by customers. The endpoint checks token validity and expiration status (within 24-hour window) before allowing password reset functionality. The response structure returns essential token metadata and status information required for token validation workflow.
   *
   * The token must be present and unexpired for successful validation. Results include token details with verification expiration and creation timestamps. The system automatically removes expired tokens from the result set and prevents re-use via strict token expiration checks.
   *
   * This operation is used in the password reset flow to validate reset links before proceeding with password change requests.
   *
   * @param connection
   * @param body Token to validate and search criteria
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query ecommerce_customer_password_resets table with 'token' value lookup in request body. Validate token exists and not expired (current time < expires_at). Apply security filters to prevent exposure of non-expired tokens. Return single matching token record with summary data. Transactional query to ensure data consistency.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IEcommerceCustomerPasswordReset.IRequest,
  ): Promise<IEcommerceCustomerPasswordReset.ISummary> {
    try {
      return await patchEcommerceCustomerPasswordResets({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a customer password reset token by its unique identifier.
   *
   * This endpoint allows retrieval of password reset tokens used for account recovery processes. The token is active within a 24-hour window from creation, and the endpoint will automatically validate token expiration before returning results.
   *
   * Returns the complete token data including expiration timestamp, creation timestamp, and associated customer ID. The token itself is not returned in the response for security reasons.
   *
   * This operation requires customer authentication (customer actor) but does not require token authentication.
   *
   * @param connection
   * @param resetId Unique password reset token ID
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Fetch password reset token from ecommerce_customer_password_resets table using provided resetId. Validate token exists, hasn't expired (expires_at > current timestamp), and return complete token object with customer association details. Handle soft delete if deleted_at is set (return 404).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":resetId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("resetId")
    resetId: string,
  ): Promise<IEcommerceCustomerPasswordReset> {
    try {
      return await getEcommerceCustomerPasswordResetsResetId({
        customer,
        resetId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
