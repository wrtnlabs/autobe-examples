import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceAddress } from "../../../../api/structures/IEcommerceAddress";
import { IPageIEcommerceAddress } from "../../../../api/structures/IPageIEcommerceAddress";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { getEcommerceCustomerAddressesAddressId } from "../../../../providers/getEcommerceCustomerAddressesAddressId";
import { patchEcommerceCustomerAddresses } from "../../../../providers/patchEcommerceCustomerAddresses";

@Controller("/ecommerce/customer/addresses")
export class EcommerceCustomerAddressesController {
  /**
   * Retrieve a filtered and paginated list of customer shipping addresses.
   *
   * This endpoint allows customers to search for their stored addresses using various criteria including city, state, postal code, and country. The results are returned in a paginated format suitable for display in user interfaces.
   *
   * The address data is retrieved from the database's ecommerce_addresses table, which stores recipient name, phone, street, city, state, postal code, and country. All fields are available for filtering as long as the user has access to that address data.
   *
   * Response includes a page object with pagination metadata and address summaries for efficient client-side rendering and navigation.
   *
   * @param connection
   * @param body Search criteria for addressing the addresses
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query ecommerce_addresses table with filtering capabilities on city, state, postal code, and country fields. Apply pagination with page size and offset parameters. Return comprehensive address summaries to match the API's list operation pattern.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IEcommerceAddress.IRequest,
  ): Promise<IPageIEcommerceAddress.ISummary> {
    try {
      return await patchEcommerceCustomerAddresses({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific shipping address associated with a customer account. This operation provides complete shipping address details including recipient name, contact phone, and complete geographical information necessary for order fulfillment.
   *
   * The address details include standardized street information with building numbers, city, state, postal code, and country. All addresses in the system are stored with standardized international postal code validation. This endpoint is used by the customer profile section to display and manage shipping addresses.
   *
   * Requires valid addressId parameter in the URL and customer authentication.
   *
   * @param connection
   * @param addressId Unique identifier for the shipping address
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query ecommerce_addresses table using addressId parameter. Return all required fields: recipientName, phone, street, city, state, postalCode, country. Validate addressId is a valid UUID before querying. Return 404 if not found.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":addressId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("addressId")
    addressId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceAddress> {
    try {
      return await getEcommerceCustomerAddressesAddressId({
        customer,
        addressId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
