import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceCustomerAddress } from "../../../../api/structures/IEcommerceCustomerAddress";
import { IPageIEcommerceCustomerAddress } from "../../../../api/structures/IPageIEcommerceCustomerAddress";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { deleteEcommerceCustomerAddressesAddressId } from "../../../../providers/deleteEcommerceCustomerAddressesAddressId";
import { patchEcommerceCustomerAddresses } from "../../../../providers/patchEcommerceCustomerAddresses";
import { putEcommerceCustomerAddressesAddressId } from "../../../../providers/putEcommerceCustomerAddressesAddressId";

@Controller("/ecommerce/customer/addresses")
export class EcommerceCustomerAddressesController {
  /**
   * Retrieve a paginated list of the customer's shipping addresses with filtering capabilities.
   *
   * This endpoint allows customers to view their address book with filter options to locate specific address entries by location, postal code, or country. All address fields except sensitive information (phone number and recipient name) are visible in summaries for efficiency.
   *
   * The response includes a cursor-based pagination system with `page` and `limit` parameters. Filters support partial matches for city, state, and postal code to assist users finding addresses by location. The API ensures customers can only view their own addresses for privacy and security.
   *
   * Addresses displayed must have been created with valid international address formats as validated in the address creation process. Only active addresses (deleted_at is null) are included in results.
   *
   * @param connection
   * @param body Search and pagination parameters for fetching addresses
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Fetch customer's shipping addresses with filtering, sorting and pagination. Implement Prisma query with where clauses for address fields (city, state, postal code, country). Include pagination parameters (page, limit) in request body. Return summarized address data excluding sensitive fields. Enforce customer ownership check: only addresses belonging to the current user are returned. For non-authenticated requests, return 401. For non-owning users, return 403.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IEcommerceCustomerAddress.IRequest,
  ): Promise<IPageIEcommerceCustomerAddress.ISummary> {
    try {
      return await patchEcommerceCustomerAddresses({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing shipping address for the current user.
   *
   * This operation allows modification of all shipping address fields for the current customer, with the exception of the country field. The system will automatically create a snapshot of the previous address values before applying changes. The country field cannot be modified through this operation to maintain consistency with address validation requirements and to prevent accidental region changes.
   *
   * This is used when customers need to update address details such as street information, city, postal code, phone number, or address default status. The snapshot ensures full address history is preserved for audit purposes, as required by business rules.
   *
   * The operation requires the address to belong to the currently authenticated customer.
   *
   * @param connection
   * @param addressId The unique identifier of the address to update
   * @param body Address update request containing modified fields (excluding country)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification 1. Validate ownership of address by authenticated user
   * 2. Apply update to all address fields except country
   * 3. Prevent country field modification
   * 4. Create snapshot of previous address before update
   * 5. Update is_default if explicitly specified
   * 6. Maintain existing address integrity
   * 7. Apply validation rules for phone (E.164 format), postal code, and required fields
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":addressId")
  public async update(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("addressId")
    addressId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceCustomerAddress.IUpdate,
  ): Promise<IEcommerceCustomerAddress> {
    try {
      return await putEcommerceCustomerAddressesAddressId({
        customer,
        addressId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently remove a customer's shipping address from active delivery options while preserving historical data. This operation cannot be reversed and removes the address from all future shipping selections.
   *
   * The system preserves the address record for legal and order history integrity, ensuring contributions to all orders remain visible and intact. All modifications to customer addresses trigger snapshot creation for audit purposes as required by the Snapshot Principle.
   *
   * Only the customer who owns the address can initiate deletion. The operation requires confirmation to prevent accidental deletions, following user experience best practices from the Product Design guidelines.
   *
   * @param connection
   * @param addressId Unique identifier of the customer shipping address to delete
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification 1. Verify customer ownership of address
   * 2. Confirm deletion via modal confirmation (user interaction)
   * 3. Update address status to 'inactive' (not physically deleted)
   * 4. Create snapshot of address record before deletion
   * 5. Remove from active address options but preserve in orders history
   * 6. Update customer's address record count
   * 7. Return 204 No Content success status
   * 8. Track audit with administrator access
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":addressId")
  public async erase(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("addressId")
    addressId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteEcommerceCustomerAddressesAddressId({
        customer,
        addressId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
