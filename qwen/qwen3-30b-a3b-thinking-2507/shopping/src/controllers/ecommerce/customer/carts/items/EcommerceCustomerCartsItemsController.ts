import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceCartItem } from "../../../../../api/structures/IEcommerceCartItem";
import { IPageIEcommerceCartItem } from "../../../../../api/structures/IPageIEcommerceCartItem";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { getEcommerceCustomerCartsCartIdItemsItemId } from "../../../../../providers/getEcommerceCustomerCartsCartIdItemsItemId";
import { patchEcommerceCustomerCartsCartIdItems } from "../../../../../providers/patchEcommerceCustomerCartsCartIdItems";

@Controller("/ecommerce/customer/carts/:cartId/items")
export class EcommerceCustomerCartsItemsController {
  /**
   * Retrieve a paginated list of items belonging to a specific shopping cart.
   *
   * This operation provides advanced search capabilities for cart contents including: pagination, filtering by product variants, and quantity ranges. The response includes detailed cart item data with historical pricing for pricing changes.
   *
   * The cart's items are retrieved exclusively via the cartId path parameter, ensuring all response data belongs to a single cart context. This operation is designed for use by customers and their frontend to manage shopping session contents.
   *
   * Response data includes current quantities and historical pricing to maintain accuracy if product prices change after cart was created, but excludes soft-deleted items to maintain data integrity.
   *
   * @param connection
   * @param cartId Unique identifier of the cart
   * @param body Search criteria and pagination parameters for cart items
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification 1. Fetch all cart items for the specified cartId from ecommerce_cart_items table
   * 2. Filter out soft-deleted items (deleted_at is NULL)
   * 3. Apply pagination and sorting from request body parameters
   * 4. Return cursor-based pagination for large result sets
   * 5. For each item, include: id, product variant reference, quantity, price_at_addition (historical price), created_at
   * 6. Do NOT include deleted_at in response (soft delete handled by not returning deleted items)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("cartId")
    cartId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceCartItem.IRequest,
  ): Promise<IPageIEcommerceCartItem.ISummary> {
    try {
      return await patchEcommerceCustomerCartsCartIdItems({
        customer,
        cartId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific cart item within a customer's shopping cart.
   *
   * This operation provides detailed information about a particular item in a customer's cart, including the product variant reference, quantity, and price at the time of addition (historical accuracy for pricing changes). The system ensures the cart item corresponds to the customer's active cart and that the requested item exists in the cart.
   *
   * Access is restricted to authenticated customers with valid session tokens. The response includes all relevant fields from the ecommerce_cart_items database table, enabling clients to display accurate cart contents including product details at the purchase point. No write operations are permitted through this endpoint, and the data reflects the state at the time of cart item creation.
   *
   * @param connection
   * @param cartId Cart ID (ecommerce_carts.id) associated with the cart item
   * @param itemId Cart item ID (ecommerce_cart_items.id) identifying the specific cart item
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query ecommerce_cart_items table by id (itemId) and validate that ecommerce_carts_id matches cartId path parameter. Return all cart item fields including product variant reference, quantity, and price_at_addition for historical pricing accuracy.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":itemId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("cartId")
    cartId: string & tags.Format<"uuid">,
    @TypedParam("itemId")
    itemId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceCartItem> {
    try {
      return await getEcommerceCustomerCartsCartIdItemsItemId({
        customer,
        cartId,
        itemId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
