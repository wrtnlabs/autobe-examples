import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceCustomer } from "../../../../api/structures/IEcommerceCustomer";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { putEcommerceCustomerProfile } from "../../../../providers/putEcommerceCustomerProfile";

@Controller("/ecommerce/customer/profile")
export class EcommerceCustomerProfileController {
  /**
   * Update the current customer's profile information including display name and phone number.
   *
   * This operation allows authenticated customers to modify their visible display name and contact phone number as requested.
   *
   * The system validates that display names do not exceed 50 characters and do not contain prohibited terms. Phone numbers are validated against E.164 international format standards and stored in a standardized normalized format across all system references.
   *
   * The operation updates the current user's profile only. Only the fields provided in the request body are modified; other profile fields remain unchanged.
   *
   * Operation requires valid customer authentication token. Returns the full updated customer profile after successful modification.
   *
   * @param connection
   * @param body Profile update request containing new display name and/or phone number
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Update customer profile fields (display_name, phone) in ecommerce_customers table. Implement E.164 phone number validation and normalization. Validate display_name length (max 50 characters) against prohibited terms list. Only update provided fields - existing values for omitted fields remain unchanged. Use Prisma transactions for database updates.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IEcommerceCustomer.IUpdate,
  ): Promise<IEcommerceCustomer> {
    try {
      return await putEcommerceCustomerProfile({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
