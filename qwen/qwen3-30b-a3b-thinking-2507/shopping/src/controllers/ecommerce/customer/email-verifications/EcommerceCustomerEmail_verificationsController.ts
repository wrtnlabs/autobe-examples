import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceCustomerEmailVerification } from "../../../../api/structures/IEcommerceCustomerEmailVerification";
import { IPageIEcommerceCustomerEmailVerification } from "../../../../api/structures/IPageIEcommerceCustomerEmailVerification";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { getEcommerceCustomerEmailVerificationsVerificationId } from "../../../../providers/getEcommerceCustomerEmailVerificationsVerificationId";
import { patchEcommerceCustomerEmailVerifications } from "../../../../providers/patchEcommerceCustomerEmailVerifications";

@Controller("/ecommerce/customer/email-verifications")
export class EcommerceCustomerEmail_verificationsController {
  /**
   * Retrieve verified email confirmation records with pagination and filtering options.
   *
   * This operation retrieves email verification tokens used for customer authentication flows, supporting search by token status, expiration dates, and verification completion. The operation requires token validation against system timestamps and automatically records verification completion in audit logs.
   *
   * Email verification tokens are validated against expiration periods (30 minutes) and confirmed email addresses. The system ensures all tokens expire before processing while preserving immutable verification history. Supports real-time pagination and filtering for security audits and user verification monitoring.
   *
   * The operation integrates with user account management flows as documented in section 3.1 of functional requirements.
   *
   * @param connection
   * @param body Search parameters for email verification tokens
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification 1. Verify if token is present in request body
   * 2. Validate token against database records (case-insensitive)
   * 3. Check token expiration (current time < expires_at)
   * 4. Confirm token validity for customer account
   * 5. Update confirmed_at timestamp if valid
   * 6. Return paginated results with verification history
   * 7. Apply security filters to prevent token reuse across sessions
   * 8. Track verification attempts for security monitoring
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IEcommerceCustomerEmailVerification.IRequest,
  ): Promise<IPageIEcommerceCustomerEmailVerification.ISummary> {
    try {
      return await patchEcommerceCustomerEmailVerifications({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed state of an email verification token associated with customer account verification.
   *
   * This endpoint provides complete information about an email verification token including confirmation status, expiration timestamp, and creation history. The response includes all relevant verification data allowing clients to determine if the email address has been successfully confirmed and the token's validity period.
   *
   * Verification records are maintained indefinitely with soft-delete semantics, so the endpoint automatically excludes records with a confirmed_at timestamp (indicating completed verification) and deleted_at timestamps (indicating security audit deletion). The response provides all necessary information for the customer's verification status in the user interface.
   *
   * @param connection
   * @param verificationId Unique identifier of the email verification token
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query ecommerce_customer_email_verifications table by id (UUID) and return full entity record. Exclude soft-deleted records (deleted_at IS NOT NULL) from results. Join with ecommerce_customers for customer context in implementation (not exposed in response). Ensure authorization checks for customer identity or admin access.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":verificationId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("verificationId")
    verificationId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceCustomerEmailVerification> {
    try {
      return await getEcommerceCustomerEmailVerificationsVerificationId({
        customer,
        verificationId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
