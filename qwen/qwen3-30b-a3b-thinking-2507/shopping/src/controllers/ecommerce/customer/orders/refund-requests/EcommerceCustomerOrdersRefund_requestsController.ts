import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceRefundRequest } from "../../../../../api/structures/IEcommerceRefundRequest";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { getEcommerceCustomerOrdersOrderIdRefundRequestsRefundRequestId } from "../../../../../providers/getEcommerceCustomerOrdersOrderIdRefundRequestsRefundRequestId";
import { postEcommerceCustomerOrdersIdRefundRequests } from "../../../../../providers/postEcommerceCustomerOrdersIdRefundRequests";

@Controller("/ecommerce/customer/orders")
export class EcommerceCustomerOrdersRefund_requestsController {
  /**
   * Initiate a refund request for a delivered order item within the 7-day window.
   *
   * This endpoint allows customers to request refunds for items they've received (status 'delivered'). The system automatically sets the initial request status to 'pending' and records the provided reason.
   *
   * Request validation ensures:
   * - The order item is in 'delivered' state
   * - The request is submitted within 7 days of delivery date
   * - Only authenticated customers can initiate requests
   *
   * Refund requests are permanently stored with immutable snapshots preserving all request details for audit purposes.
   *
   * @param connection
   * @param id Order item ID this refund request applies to
   * @param body Reason for refund request
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification 1. Validate order item exists and status is 'delivered'
   * 2. Verify refund request is made within 7 days of delivery date
   * 3. Create new refund request with status 'pending'
   * 4. Store reason in database
   * 5. Record snapshot of initial request state
   * 6. Return full refund request object with timestamps
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post(":id/refund-requests")
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceRefundRequest.ICreate,
  ): Promise<IEcommerceRefundRequest> {
    try {
      return await postEcommerceCustomerOrdersIdRefundRequests({
        customer,
        id,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific refund request for an order item that has been delivered within the 7-day window.
   *
   * This operation provides detailed information about a customer's refund request, including the reason for the refund, current status, and timestamps. The refund request is associated with a specific order item that has reached a 'delivered' status.
   *
   * The API is accessible to customers who submitted the refund request and sellers associated with the product. The refund request status may be 'pending', 'approved', or 'rejected' indicating the current stage of the refund process. The reason for the refund is provided in free text by the customer.
   *
   * The operation requires the order ID and refund request ID as parameters. The order ID is used to verify the context of the refund request, while the refund request ID uniquely identifies the specific refund request record.
   *
   * @param connection
   * @param orderId The order identifier associated with this refund request
   * @param refundRequestId The specific refund request identifier to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification 1. Verify orderId exists and matches refund request order item
   * 2. Confirm refund request exists with the given refundRequestId
   * 3. Check refund request status is 'delivered' for order item
   * 4. Handle soft-delete: return record if deleted_at is null, otherwise return 404
   * 5. Select all relevant fields from ecommerce_refund_requests table with relationship to order item
   * 6. Return only authorized fields based on actor (customer/seller)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":orderId/refund-requests/:refundRequestId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedParam("refundRequestId")
    refundRequestId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceRefundRequest> {
    try {
      return await getEcommerceCustomerOrdersOrderIdRefundRequestsRefundRequestId(
        {
          customer,
          orderId,
          refundRequestId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
