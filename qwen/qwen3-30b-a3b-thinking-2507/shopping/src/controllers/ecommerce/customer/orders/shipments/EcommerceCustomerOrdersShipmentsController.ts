import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceShipment } from "../../../../../api/structures/IEcommerceShipment";
import { IPageIEcommerceShipment } from "../../../../../api/structures/IPageIEcommerceShipment";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { getEcommerceCustomerOrdersOrderIdShipmentsShipmentId } from "../../../../../providers/getEcommerceCustomerOrdersOrderIdShipmentsShipmentId";
import { patchEcommerceCustomerOrdersIdShipments } from "../../../../../providers/patchEcommerceCustomerOrdersIdShipments";

@Controller("/ecommerce/customer/orders")
export class EcommerceCustomerOrdersShipmentsController {
  /**
   * Retrieve a paginated list of shipment details for a specific order.
   *
   * This operation provides comprehensive shipment tracking information for the specified order, including carrier names, tracking numbers, and current status information. Shipments are grouped by seller and include full shipping details with expected delivery dates.
   *
   * The endpoint supports filtering shipments by status (e.g., 'shipped', 'delivered') and carrier name, allowing customers and sellers to view shipment progress at a granular level. Results are paginated with configurable page size for efficient data loading.
   *
   * Responses include shipment status transitions following operational rules: 'paid' → 'shipped' → 'delivered' or 'cancelled', with automatic 'delivered' status after 14 days if not confirmed by customer.
   *
   * @param connection
   * @param id Order identifier used to fetch related shipments
   * @param body Pagination parameters and shipment filters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Fetch all shipments associated with specified order.
   * Retrieve shipments with carrier name, tracking number, status, and delivery dates.
   * Implement filters on shipment status and carrier name.
   * Use cursor-based pagination for large result sets.
   * Join with ecommerce_orders to verify order ownership before proceeding.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch(":id/shipments")
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceShipment.IRequest,
  ): Promise<IPageIEcommerceShipment.ISummary> {
    try {
      return await patchEcommerceCustomerOrdersIdShipments({
        customer,
        id,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed shipment information for a specific shipment within a customer's order.
   *
   * This endpoint enables customers and sellers to view the current status and tracking information of a shipment for a particular order. The response includes carrier details, tracking number, current status, and delivery dates for the shipment.
   *
   * Available shipment statuses include 'pending', 'in_progress', 'shipped', 'delivered', and 'cancelled', with the status updated in real-time as the shipment progresses through the delivery process. The tracking information is sourced directly from the carrier's system and is visible to both the customer and seller.
   *
   * For each shipment, the carrier name (e.g., 'USPS', 'FedEx', 'DHL'), tracking number, current status, shipping date, and expected delivery date are provided. This enables customers to monitor the progress of their order's delivery and sellers to manage shipment logistics efficiently.
   *
   * @param connection
   * @param orderId The unique identifier of the order
   * @param shipmentId The unique identifier of the shipment within the order
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Fetch shipment from ecommerce_shipments table where id = shipmentId and ecommerce_order_id = orderId. Validate shipment belongs to the specified order. Check for soft-deleted records (deleted_at not null) and return 404 if found. Return all shipment fields including carrier_name, tracking_number, status, shipment_date, existing_delivery_date.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":orderId/shipments/:shipmentId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedParam("shipmentId")
    shipmentId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceShipment> {
    try {
      return await getEcommerceCustomerOrdersOrderIdShipmentsShipmentId({
        customer,
        orderId,
        shipmentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
