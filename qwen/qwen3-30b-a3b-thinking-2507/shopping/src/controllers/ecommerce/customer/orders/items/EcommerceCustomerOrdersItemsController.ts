import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceOrderItem } from "../../../../../api/structures/IEcommerceOrderItem";
import { IPageIEcommerceOrderItem } from "../../../../../api/structures/IPageIEcommerceOrderItem";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { getEcommerceCustomerOrdersOrderIdItemsId } from "../../../../../providers/getEcommerceCustomerOrdersOrderIdItemsId";
import { patchEcommerceCustomerOrdersOrderIdItems } from "../../../../../providers/patchEcommerceCustomerOrdersOrderIdItems";

@Controller("/ecommerce/customer/orders/:orderId/items")
export class EcommerceCustomerOrdersItemsController {
  /**
   * Retrieve a filtered and paginated list of order items within a specific order.
   *
   * This operation provides comprehensive filtering capabilities including partial product name matching, price ranges, and item status filters. Supports pagination parameters for efficient data retrieval.
   *
   * The response returns detailed order items with product name, selected variant options, price, quantity, and status. Includes order ID for context and maintains data consistency with the parent order.
   *
   * @param connection
   * @param orderId Global unique order identifier for which to retrieve items
   * @param body Search criteria and pagination parameters for order items
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query ecommerce_order_items table with joins to ecommerce_products and ecommerce_product_variants. Apply filters from request body for product name, price range, status, and variant options. Implement cursor-based pagination with page size of 20 items. Handle sorting parameters (price, date) in request body. Return items belonging to specified order and matching search criteria.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceOrderItem.IRequest,
  ): Promise<IPageIEcommerceOrderItem.ISummary> {
    try {
      return await patchEcommerceCustomerOrdersOrderIdItems({
        customer,
        orderId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific item within an order.
   *
   * This operation provides comprehensive data about a single line item within an order, including historical product variant details at the time of purchase. The response contains product name, variant options, original price, quantity, and associated seller profile information.
   *
   * The endpoint requires both an order ID and a specific order item ID to identify the precise resource. Item data includes immutable historical values, following the Snapshot Principle implementation from business rules 7.
   *
   * Customer can view their order items without any restrictions as part of order history management.
   *
   * @param connection
   * @param orderId Unique identifier of the order containing the item
   * @param id Unique identifier of the specific order item within the order
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query ecommerce_orders and ecommerce_order_items tables using provided IDs to retrieve order item details. Filter by order_id = {orderId} and id = {id}. Return product variant details at the time of purchase, including category, price, quantity, and seller profile data. Ensure transactional isolation to prevent data inconsistencies during read operation.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":id")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<IEcommerceOrderItem> {
    try {
      return await getEcommerceCustomerOrdersOrderIdItemsId({
        customer,
        orderId,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
