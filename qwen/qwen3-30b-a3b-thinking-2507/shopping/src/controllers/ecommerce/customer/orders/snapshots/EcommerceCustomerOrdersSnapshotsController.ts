import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceOrderSnapshot } from "../../../../../api/structures/IEcommerceOrderSnapshot";
import { IPageIEcommerceOrderSnapshot } from "../../../../../api/structures/IPageIEcommerceOrderSnapshot";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { getEcommerceCustomerOrdersOrderIdSnapshotsSnapshotId } from "../../../../../providers/getEcommerceCustomerOrdersOrderIdSnapshotsSnapshotId";
import { patchEcommerceCustomerOrdersIdSnapshots } from "../../../../../providers/patchEcommerceCustomerOrdersIdSnapshots";

@Controller("/ecommerce/customer/orders")
export class EcommerceCustomerOrdersSnapshotsController {
  /**
   * Retrieve historical snapshot records for a specific order, providing complete audit trails of state transitions throughout the system lifecycle.
   *
   * This operation returns chronological snapshots of the order including timestamps, previous values, and new values at each state change. Each snapshot is preserved indefinitely for legal compliance, dispute resolution, and customer support purposes.
   *
   * The response contains summary information optimized for list display, including the operation type (update), timestamp, and key field changes without full entity details. This enables efficient display of order history without excessive data transfer.
   *
   * @param connection
   * @param id Order ID associated with the snapshots to retrieve
   * @param body Pagination and sorting parameters for order snapshot listing
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query ecommerce_order_snapshots table using ecommerce_order_id = path 'id' parameter. Apply pagination, sorting, and filtering from request body. Use cursor-based pagination for large datasets. The relationship is defined by ecommerce_order_snapshots.ecommerce_order_id linking to ecommerce_orders.id.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch(":id/snapshots")
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceOrderSnapshot.IRequest,
  ): Promise<IPageIEcommerceOrderSnapshot.ISummary> {
    try {
      return await patchEcommerceCustomerOrdersIdSnapshots({
        customer,
        id,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific historical snapshot of an e-commerce order's state at a particular point in time.
   *
   * This operation provides detailed historical data about an order when it was modified, including the state of the order, product variants, seller profile, and associated metadata. The snapshot is immutable and preserved indefinitely as required by legal compliance and dispute resolution requirements.
   *
   * The snapshot contains the order status, total price, and customer reference at the moment of modification. It also preserves all relevant details including product variants with exact prices, seller profile information (shop name, logo), and the timestamp of the snapshot creation.
   *
   * This endpoint is primarily used by administrators and customer support personnel to review order history for audit purposes or to resolve disputes with customers. The snapshot data is guaranteed to match exactly what was present at the time of the order modification without any subsequent changes.
   *
   * @param connection
   * @param orderId The unique identifier of the order for which the snapshot belongs
   * @param snapshotId The unique identifier of the order snapshot to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query ecommerce_order_snapshots table using snapshotId. Join with ecommerce_orders to verify order existence. Return snapshot details including ecommerce_order_id and all snapshot fields. Ensure the snapshot belongs to the specified order. Implement permission check to allow access for authorized user roles (customer with order ownership, support staff, admin). Handle 404 if snapshot not found or order doesn't match the snapshot's order ID. All fields retrieved from the database without any modification.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":orderId/snapshots/:snapshotId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedParam("snapshotId")
    snapshotId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceOrderSnapshot> {
    try {
      return await getEcommerceCustomerOrdersOrderIdSnapshotsSnapshotId({
        customer,
        orderId,
        snapshotId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
