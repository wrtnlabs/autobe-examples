import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceCancellationRequest } from "../../../../../api/structures/IEcommerceCancellationRequest";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { getEcommerceCustomerOrdersOrderIdCancellationRequestsCancellationRequestId } from "../../../../../providers/getEcommerceCustomerOrdersOrderIdCancellationRequestsCancellationRequestId";
import { postEcommerceCustomerOrdersOrderIdCancellationRequests } from "../../../../../providers/postEcommerceCustomerOrdersOrderIdCancellationRequests";

@Controller("/ecommerce/customer/orders/:orderId/cancellation-requests")
export class EcommerceCustomerOrdersCancellation_requestsController {
  /**
   * Create a cancellation request for a specific order item.
   *
   * This operation allows customers to request cancellation for order items that are in 'paid' status and have not yet been shipped. The system requires a valid reason text between 10 and 500 characters.
   *
   * Upon successful request submission:
   * - The system creates a cancellation request record with status 'pending-seller'
   * - Generates an immutable snapshot of the order item's prior state
   * - Sends email notification to the seller with request details
   * - Allows the seller to approve or reject within 48 hours
   *
   * Note: Cancellation requests must be submitted within 24 hours of payment approval. Only order items without shipment status can be cancelled.
   *
   * @param connection
   * @param orderId Order ID (global scope)
   * @param body Cancellation request details including reason
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Validate cancellation reason length (10-500 characters). Create cancellation_request record with status 'pending-seller'. Generate snapshot of current order item state (before cancellation). Notify seller via email with request details. Apply constraints: only 'paid' items with no existing shipment. Return created cancellation request object with snapshot metadata.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceCancellationRequest.ICreate,
  ): Promise<IEcommerceCancellationRequest> {
    try {
      return await postEcommerceCustomerOrdersOrderIdCancellationRequests({
        customer,
        orderId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific cancellation request for an order item.
   *
   * This endpoint provides the complete cancellation request details including reason provided by customer, current status (pending/approved/rejected), timestamps for creation, status changes, and any associated notes. Linked to order items with status 'paid' that haven't shipped.
   *
   * Customers can view their own requests; sellers can access for 48-hour processing window. System ensures only 'paid' items are accessible.
   *
   * @param connection
   * @param orderId Identifier of the order containing the item to be cancelled
   * @param cancellationRequestId Unique identifier of the cancellation request
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Retrieves specific cancellation request record from ecommerce_cancellation_requests table. Validates query against business rules (only 'paid' order items). Checks authentication context for customer/seller. Returns complete record with status and timestamps.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":cancellationRequestId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedParam("cancellationRequestId")
    cancellationRequestId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceCancellationRequest> {
    try {
      return await getEcommerceCustomerOrdersOrderIdCancellationRequestsCancellationRequestId(
        {
          customer,
          orderId,
          cancellationRequestId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
