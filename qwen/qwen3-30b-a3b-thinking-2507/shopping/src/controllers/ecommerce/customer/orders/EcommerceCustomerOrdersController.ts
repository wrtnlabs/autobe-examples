import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceOrder } from "../../../../api/structures/IEcommerceOrder";
import { IPageIEcommerceOrder } from "../../../../api/structures/IPageIEcommerceOrder";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { getEcommerceCustomerOrdersOrderId } from "../../../../providers/getEcommerceCustomerOrdersOrderId";
import { patchEcommerceCustomerOrders } from "../../../../providers/patchEcommerceCustomerOrders";

@Controller("/ecommerce/customer/orders")
export class EcommerceCustomerOrdersController {
  /**
   * Retrieve paginated list of customer orders with advanced search, filtering, and sorting capabilities.
   *
   * This operation provides all order information including status transitions, item details, and snapshot history for historical context. The response includes only essential fields for list display while maintaining complete order detail accessibility through related endpoints.
   *
   * For performance-critical use cases, this endpoint implements cursor-based pagination to handle large order volumes efficiently. Status filtering allows users to quickly view orders by current state (paid, shipped, delivered, cancelled) while date range filtering helps with historical analysis.
   *
   * The endpoint respects order status transition rules from business requirements: 'WHEN all items are delivered, THE system SHALL display order status as 'delivered'.', and integrates order item snapshot data for historical tracking.
   *
   * @param connection
   * @param body Search filters and pagination parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query ecommerce_orders table with optional filters for status, date range, and customer ID.
   * Apply JOINs with ecommerce_order_items for status aggregation.
   * Implement cursor-based pagination with max 20 results per page.
   * Include snapshot history references for audit purposes.
   * Return only summary fields optimized for list display.
   * Use index scans on status and date fields for performance matching 2-second requirement.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IEcommerceOrder.IRequest,
  ): Promise<IPageIEcommerceOrder.ISummary> {
    try {
      return await patchEcommerceCustomerOrders({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve complete order details with status, total amount, and customer information.
   *
   * This operation provides comprehensive order information including the current status computed from all order items, total amount, and timestamps. The status field reflects the aggregate state of all items within the order (paid, shipped, delivered, etc.).
   *
   * For customer-owned orders, this endpoint returns order details with the customer's profile information and shipping address reference. Seller-owned orders return order items with seller-specific product details. Admin requests return full order history for auditing purposes.
   *
   * Note: The 'status' field is stored in the order table and represents the aggregation of all item statuses. This endpoint does not include full item details or product variants; use /orders/{id}/items for line item information.
   *
   * @param connection
   * @param orderId Order ID in UUID format
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Fetch ecommerce_orders record with ID matching path parameter. Join with ecommerce_customers and ecommerce_customer_addresses relationships to resolve customer name and shipping address data (only IDs are included in the main response per schema). Compute order status from order items' statuses (though this is stored in the 'status' field for reporting). Handle deleted_at: if present, return the order as 'soft-deleted' (though typically not exposed for GET operations). Validate order belongs to current user for customer requests, or is accessible to seller/admin.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":orderId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceOrder> {
    try {
      return await getEcommerceCustomerOrdersOrderId({
        customer,
        orderId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
