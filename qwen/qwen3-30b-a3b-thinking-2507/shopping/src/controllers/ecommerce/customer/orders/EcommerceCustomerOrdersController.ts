import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceOrder } from "../../../../api/structures/IEcommerceOrder";
import { IPageIEcommerceOrder } from "../../../../api/structures/IPageIEcommerceOrder";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { getEcommerceCustomerOrdersId } from "../../../../providers/getEcommerceCustomerOrdersId";
import { patchEcommerceCustomerOrders } from "../../../../providers/patchEcommerceCustomerOrders";

@Controller("/ecommerce/customer/orders")
export class EcommerceCustomerOrdersController {
  /**
   * Retrieve a paginated list of current orders with filters by status, customer, and date range.
   *
   * This operation enables users to search for their order history based on various criteria. For customer users, it lists only their own orders; for admin users, it shows all orders in the system. The API returns minimal order data including the status, order date, and relevant identifiers to optimize list display performance.
   *
   * Filters support status (pending, processing, shipped, delivered, cancelled), customer ID, and date range. The system calculates order total amounts on query time for performance, so the response includes only the relevant fields without recalculating for each order.
   *
   * Results are paginated with cursor-based pagination for efficient handling of large order histories. Orders that have been marked for deletion are automatically excluded from results.
   *
   * @param connection
   * @param body Search criteria and pagination parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query the ecommerce_orders table while excluding any records with deleted_at timestamp set (excluding soft-deleted orders). Apply search filters on status, customer ID, and order date range to return paginated order summaries with minimal fields. Utilize cursor-based pagination for large result sets and handle date comparisons using proper timestamp ranges. Include only active orders with status values: pending, processing, shipped, delivered, cancelled.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IEcommerceOrder.IRequest,
  ): Promise<IPageIEcommerceOrder.ISummary> {
    try {
      return await patchEcommerceCustomerOrders({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves detailed information about a specific order within the e-commerce platform. This endpoint is used to view the complete state of an order including all items, associated customer information, and current processing status.
   *
   * The response contains the order's current status, order date, customer reference, and other business-relevant fields. The order status follows the defined transitions: 'pending' → 'processing' → 'shipped' → 'delivered' → 'cancelled'. The system implements soft-deletion where deleted orders are marked with a deleted_at timestamp but remain visible in historical records.
   *
   * This operation is accessible to both customer actors for their own orders and admin actors for all orders. Permissions are enforced based on the actor's role to maintain data privacy. The order data is returned in a comprehensive format suitable for display in the order history interface.
   *
   * This endpoint is the foundational operation for order detail viewing and is used as a prerequisite for order-related operations such as cancellation requests and shipment tracking.
   *
   * @param connection
   * @param id Order's unique identifier in UUID format
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query ecommerce_orders table with order_id = path parameter. Join with ecommerce_customers to fetch customer name and email. Filter out deleted orders (deleted_at IS NULL). Validate order exists and belongs to requesting user if customer actor. For admin, skip ownership validation. Return all columns from order table including status, order_date, and customer reference.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":id")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<IEcommerceOrder> {
    try {
      return await getEcommerceCustomerOrdersId({
        customer,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
