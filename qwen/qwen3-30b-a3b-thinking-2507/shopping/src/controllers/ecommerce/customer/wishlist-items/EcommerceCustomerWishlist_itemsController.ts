import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceWishlistItem } from "../../../../api/structures/IEcommerceWishlistItem";
import { IPageIEcommerceWishlistItem } from "../../../../api/structures/IPageIEcommerceWishlistItem";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { deleteEcommerceCustomerWishlistItemsWishlistItemId } from "../../../../providers/deleteEcommerceCustomerWishlistItemsWishlistItemId";
import { getEcommerceCustomerWishlistItemsWishlistItemId } from "../../../../providers/getEcommerceCustomerWishlistItemsWishlistItemId";
import { patchEcommerceCustomerWishlistItems } from "../../../../providers/patchEcommerceCustomerWishlistItems";
