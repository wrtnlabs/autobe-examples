import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceProduct } from "../../../../../api/structures/IEcommerceProduct";
import { IPageIEcommerceProduct } from "../../../../../api/structures/IPageIEcommerceProduct";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { patchEcommerceCustomerProductsSearch } from "../../../../../providers/patchEcommerceCustomerProductsSearch";

@Controller("/ecommerce/customer/products/search")
export class EcommerceCustomerProductsSearchController {
  /**
   * Retrieve a filtered and paginated list of all products for customers to browse.
   *
   * This operation enables comprehensive product searches with case-insensitive name matching, detailed description text search, category filtering, and price range selection.
   *
   * Supports advanced search through the request body for customers to refine product discovery. Returns product summaries optimized for efficient listings with essential information.
   *
   * @param connection
   * @param body Search criteria and pagination parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query ecommerce_products table with pagination and filtering. Apply search filters on name (partial), description, category (via categories_id), and base_price range. Exclude soft-deleted products (deleted_at is null). Join with ecommerce_categories for category name details when needed in response. Implement cursor-based pagination for scalability. Include all product summary fields in response.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IEcommerceProduct.IRequest,
  ): Promise<IPageIEcommerceProduct.ISummary> {
    try {
      return await patchEcommerceCustomerProductsSearch({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
