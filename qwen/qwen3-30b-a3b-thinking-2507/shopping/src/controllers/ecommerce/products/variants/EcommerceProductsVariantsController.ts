import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceProductVariant } from "../../../../api/structures/IEcommerceProductVariant";
import { IPageIEcommerceProductVariant } from "../../../../api/structures/IPageIEcommerceProductVariant";
import { getEcommerceProductsProductIdVariantsVariantId } from "../../../../providers/getEcommerceProductsProductIdVariantsVariantId";
import { patchEcommerceProductsProductIdVariants } from "../../../../providers/patchEcommerceProductsProductIdVariants";
import { postEcommerceProductsProductIdVariants } from "../../../../providers/postEcommerceProductsProductIdVariants";
import { putEcommerceProductsProductIdVariantsVariantId } from "../../../../providers/putEcommerceProductsProductIdVariantsVariantId";

@Controller("/ecommerce/products/:productId/variants")
export class EcommerceProductsVariantsController {
  /**
   * Add a new product variant to a specific product.
   *
   * This operation enables sellers to create new variants for a product, each with a unique SKU, optional price override, and stock quantity. The variant will be associated with the specified product.
   *
   * The system validates that the SKU is unique across all variants, the product ID exists, and stock quantity is a positive integer. The creation timestamp and update timestamp are automatically set upon variant creation.
   *
   * Access to this operation is restricted to seller actors. The seller must have permission to modify the product's variants.
   *
   * To use this endpoint, the product ID must correspond to a valid product in the system. The SKU must be unique globally to prevent duplicate variant identification.
   *
   * @param connection
   * @param productId ID of the product to add a variant for (UUID format)
   * @param body Product variant creation data with SKU, optional price override, and stock quantity
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification 1. Validate product exists using products_id from the path param.
   * 2. Check sku uniqueness across ecommerce_product_variants table.
   * 3. Generate new UUID for variant ID.
   * 4. Populate created_at and updated_at timestamps.
   * 5. Handle price as optional field (use base product price if null).
   * 6. Use transaction for database write to ensure atomicity.
   * 7. Set stock_quantity as required integer > 0.
   * 8. Handle exceptions for invalid SKU, product not existing, or invalid stock quantity.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceProductVariant.ICreate,
  ): Promise<IEcommerceProductVariant> {
    try {
      return await postEcommerceProductsProductIdVariants({
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve paginated variants for a specific product with optional filters.
   *
   * This operation provides a flexible search capability for product variants associated with a specific product ID. Customers can filter variants by SKU, price range, and stock status. The API supports pagination to handle large variant collections efficiently.
   *
   * Each variant includes detailed pricing information with the ability to override the base product price. The response contains a summary view optimized for product listing interfaces, including stock status and current price. This endpoint is used by the frontend to display product options during checkout and shopping.
   *
   * Filtering capabilities include minimum and maximum price ranges, and stock availability status (stock_quantity > 0). Results are returned in ascending order of SKU for consistent sorting across search results.
   *
   * @param connection
   * @param productId Unique identifier for the product whose variants are being retrieved.
   * @param body Search parameters and pagination specifications
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Perform database query on 'ecommerce_product_variants' table with 'products_id' = {productId}. Apply filters from IRequest body:
   * - sku (case-insensitive search)
   * - minPrice, maxPrice (price range filtering)
   * - includeOutOfStock (boolean, default false)
   *
   * Implement pagination using cursor-based pagination (not offset), with page size up to 50 items. Use PostgreSQL array_agg for efficient data retrieval. Handle missing productId with 404 error.
   *
   * Include in result: sku, price (as number, null if not set), stock_quantity, and created_at. For stock status, use stock_quantity > 0 to indicate in-stock. Return summary objects only (avoid including full details of related products for performance).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceProductVariant.IRequest,
  ): Promise<IPageIEcommerceProductVariant.ISummary> {
    try {
      return await patchEcommerceProductsProductIdVariants({
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves specific product variant details including price, stock quantity, and associated product information. This operation provides the current price (which may override the base product price), available quantity, and product name/description to support customer decision-making.
   *
   * The response includes both the variant-specific attributes (price, stock) and the product's name and description. This ensures the front-end can display the variant's pricing context without needing additional API calls.
   *
   * The operation handles soft deletion by ignoring any records with non-null deleted_at timestamps, maintaining data integrity and consistency with the database schema.
   *
   * @param connection
   * @param productId Unique identifier of the product
   * @param variantId Unique identifier of the variant
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Fetch product variant by variantId with joined product information. Check deleted_at is null. Return variant details with product metadata for UI display.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":variantId")
  public async at(
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedParam("variantId")
    variantId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceProductVariant> {
    try {
      return await getEcommerceProductsProductIdVariantsVariantId({
        productId,
        variantId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update details for a specific product variant within its parent product.
   *
   * This endpoint allows modification of variant-specific attributes such as price and available stock quantity. It ensures the variant belongs to the specified product before applying updates.
   *
   * The operation requires precise matching of product ID to variant's parent product to maintain data integrity. Price updates support float values for currency representation. Stock quantity updates are validated to remain non-negative.
   *
   * The updated_at timestamp is automatically adjusted on successful completion to track the most recent modification to this variant.
   *
   * @param connection
   * @param productId Parent product identifier that the variant belongs to (must match variant's products_id)
   * @param variantId Unique identifier for the product variant
   * @param body Updated variant data including price and stock quantity
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Update product variant details including price and stock quantity. Validates that the provided productId matches variant's products_id foreign key. Updates only price and stock_quantity fields with provided values. Adjusts stock quantity with validation logic (must not be negative). Updates updated_at timestamp on successful update. Verifies variant exists before applying changes.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":variantId")
  public async update(
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedParam("variantId")
    variantId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceProductVariant.IUpdate,
  ): Promise<IEcommerceProductVariant> {
    try {
      return await putEcommerceProductsProductIdVariantsVariantId({
        productId,
        variantId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
