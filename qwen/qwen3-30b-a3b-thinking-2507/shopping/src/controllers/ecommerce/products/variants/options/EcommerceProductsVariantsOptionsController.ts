import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceProductVariantOption } from "../../../../../api/structures/IEcommerceProductVariantOption";
import { IPageIEcommerceProductVariantOption } from "../../../../../api/structures/IPageIEcommerceProductVariantOption";
import { getEcommerceProductsProductIdVariantsVariantIdOptionsOptionId } from "../../../../../providers/getEcommerceProductsProductIdVariantsVariantIdOptionsOptionId";
import { patchEcommerceProductsProductIdVariantsVariantIdOptions } from "../../../../../providers/patchEcommerceProductsProductIdVariantsVariantIdOptions";
import { postEcommerceProductsProductIdVariantsVariantIdOptions } from "../../../../../providers/postEcommerceProductsProductIdVariantsVariantIdOptions";

@Controller("/ecommerce/products/:productId/variants/:variantId/options")
export class EcommerceProductsVariantsOptionsController {
  /**
   * Add a new option-value pair to a specific product variant's configuration.
   *
   * This operation enables detailed product attribute management by creating option-value combinations (e.g., color=Red, size=Large) for product variants. Options are subsidiary records automatically linked to their parent variant through the ecommerce_product_variants.id foreign key.
   *
   * The endpoint requires valid productId (parent product's identifier) and variantId (specific product variation identifier) as path parameters, with option_key and option_value provided in the request body. System validation enforces that both key and value are non-empty strings following the option naming rules defined in the product configuration schema.
   *
   * The response includes the complete option record with all generated fields (ID, timestamps) to support subsequent modification or deletion operations. This operation should only be performed by product administrators or authorized sellers with write permissions to variant configurations.
   *
   * @param connection
   * @param productId The product ID this variant belongs to
   * @param variantId The variant ID to which this option is being added
   * @param body Option key-value pair details to create
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification 1. Verify product exists with the provided productId via ecommerce_products table
   * 2. Verify variant exists with provided variantId and belongs to the product via ecommerce_product_variants
   * 3. Validate option_key and option_value are non-empty strings
   * 4. Insert new row into ecommerce_product_variant_options with these fields
   * 5. Set created_at/updated_at to current timestamps, leave deleted_at null
   * 6. Return full created option with all fields
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedParam("variantId")
    variantId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceProductVariantOption.ICreate,
  ): Promise<IEcommerceProductVariantOption> {
    try {
      return await postEcommerceProductsProductIdVariantsVariantIdOptions({
        productId,
        variantId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a filtered and paginated list of product variant options.
   *
   * This operation provides advanced search capabilities including partial matching on option key and value, as well as filtering by variant ID. Supports comprehensive pagination with customizable page sizes and sorting.
   *
   * Response includes summary information optimized for listing purposes, including option key-value pairs and relevant metadata. All options retrieved reflect the current state of the variant, not historical versions.
   *
   * @param connection
   * @param productId Product ID that the variant belongs to
   * @param variantId Variant ID to query options for
   * @param body Search criteria and pagination parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query ecommerce_product_variant_options table with pagination and filtering. Apply search filters on option_key, option_value, and variant ID. Return cursor-based pagination for large result sets.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedParam("variantId")
    variantId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceProductVariantOption.IRequest,
  ): Promise<IPageIEcommerceProductVariantOption.ISummary> {
    try {
      return await patchEcommerceProductsProductIdVariantsVariantIdOptions({
        productId,
        variantId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves a specific product variant option that belongs to a variant of a product.
   *
   * This operation allows the frontend to display detailed option information for product configurations, such as color or size choices. The option details (key and value pairs) are part of the product variant's configuration, which is a subsidiary entity managed through its parent variant.
   *
   * The endpoint requires three path parameters: product ID, variant ID, and option ID, which together uniquely identify the desired option. The response includes all relevant fields from the ecommerce_product_variant_options table, including option key, option value, and timestamps.
   *
   * This is a read-only operation used by the shopping system to display product configuration options to customers.
   *
   * @param connection
   * @param productId ID of the product containing the variant
   * @param variantId ID of the variant containing the option
   * @param optionId ID of the specific option to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Retrieve the specific product variant option with the given IDs using Prisma ORM.
   *
   * 1. Verify product with given productId exists.
   * 2. Verify variant with given variantId exists and belongs to product.
   * 3. Verify option with given optionId exists and belongs to variant.
   * 4. Return the option record including optionKey, optionValue, and timestamp fields.
   *
   * Business Rules:
   * - Option must belong to the specific variant.
   * - Variant must belong to the specific product.
   * - Product must exist.
   *
   * Edge Cases:
   * - If product doesn't exist, return 404.
   * - If variant doesn't exist, return 404.
   * - If option doesn't exist, return 404.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":optionId")
  public async at(
    @TypedParam("productId")
    productId: string,
    @TypedParam("variantId")
    variantId: string,
    @TypedParam("optionId")
    optionId: string,
  ): Promise<IEcommerceProductVariantOption> {
    try {
      return await getEcommerceProductsProductIdVariantsVariantIdOptionsOptionId(
        {
          productId,
          variantId,
          optionId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
