import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceCategory } from "../../../../api/structures/IEcommerceCategory";
import { IEcommerceProductCategoryLink } from "../../../../api/structures/IEcommerceProductCategoryLink";
import { IPageIEcommerceCategory } from "../../../../api/structures/IPageIEcommerceCategory";
import { getEcommerceProductsProductIdCategoriesCategoryLinkId } from "../../../../providers/getEcommerceProductsProductIdCategoriesCategoryLinkId";
import { patchEcommerceProductsProductIdCategories } from "../../../../providers/patchEcommerceProductsProductIdCategories";

@Controller("/ecommerce/products/:productId/categories")
export class EcommerceProductsCategoriesController {
  /**
   * Retrieves the categories associated with a specific product, including their priority position within the product's category listing.
   *
   * The response displays each category's name and description along with its assigned position (lower numbers indicate higher priority, such as primary categories). This endpoint powers the category management interface for product listings, showing how products are organized in the catalog hierarchy.
   *
   * Supports pagination and sorting via the request body parameters, returning up to 12 categories per page with clear ordering based on the category's position value. The results are optimized for display in the product management UI where users see the main and secondary categories assigned to each product.
   *
   * @param connection
   * @param productId The unique identifier of the product
   * @param body Pagination and sorting parameters for category list
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Fetch categories by joining ecommerce_product_category_links (product_id={productId}) with ecommerce_categories. Sort by order field. Handle pagination with criteria from request body. Include category details and order position in response.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceCategory.IRequest,
  ): Promise<IPageIEcommerceCategory.ISummary> {
    try {
      return await patchEcommerceProductsProductIdCategories({
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific product category relationship link.
   *
   * This endpoint fetches the precise category relationship for a product, including its position in the category listing order. The response includes the order priority, creation/last modified timestamps, and ensures only active links are returned.
   *
   * Products may belong to multiple categories with different positions (lower numbers = higher priority). The main category (position 0) will appear first in the UI.
   *
   * This operation is used when displaying a product's category hierarchy, enabling users to view and manage category associations.
   *
   * Note: Links that do not exist are not returned and will return 404.
   *
   * @param connection
   * @param productId Product identifier from the ecommerce_products table
   * @param categoryLinkId The unique identifier for the product-category relationship link
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Fetch the ecommerce_product_category_links record using ecommerce_product_id and id parameters.
   *
   * Check that the link is not soft-deleted (deleted_at is NULL).
   *
   * Verify the product exists and is accessible to the requesting actor (seller or admin).
   *
   * Return all fields from the junction table including order, created_at, updated_at.
   *
   * Handle 404 when link or product is not found or soft-deleted.
   *
   * Validate parameter types (UUID) before database query.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":categoryLinkId")
  public async at(
    @TypedParam("productId")
    productId: string,
    @TypedParam("categoryLinkId")
    categoryLinkId: string,
  ): Promise<IEcommerceProductCategoryLink> {
    try {
      return await getEcommerceProductsProductIdCategoriesCategoryLinkId({
        productId,
        categoryLinkId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
