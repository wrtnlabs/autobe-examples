import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceProductImage } from "../../../../api/structures/IEcommerceProductImage";
import { IPageIEcommerceProductImage } from "../../../../api/structures/IPageIEcommerceProductImage";
import { getEcommerceProductsProductIdImagesImageId } from "../../../../providers/getEcommerceProductsProductIdImagesImageId";
import { patchEcommerceProductsProductIdImages } from "../../../../providers/patchEcommerceProductsProductIdImages";
import { postEcommerceProductsProductIdImages } from "../../../../providers/postEcommerceProductsProductIdImages";

@Controller("/ecommerce/products/:productId/images")
export class EcommerceProductsImagesController {
  /**
   * Add a new image to a product for display in search results and product views.
   *
   * This operation allows customers, administrators, and sellers to add product images to the system. Images are stored in a publicly accessible CDN and associated with the product through the ecommerce_product_id foreign key. The main image for product displays in search results can be designated using the is_primary flag.
   *
   * The image_url must be a valid URI pointing to a publically accessible image. Caption is optional text displayed on product view pages. The images remain immutable through product snapshot history.
   *
   * This operation requires the product to exist with the specified productId.
   *
   * @param connection
   * @param productId The product's unique identifier (UUID) as per database schema
   * @param body Image details for the new product image
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Create a new product image record. Validate image_url as a valid URL using @format uri. Check that product exists before creation. Default is_primary to false if not provided. Handle storage URL updates and ensure image is properly associated with the product via ecommerce_product_id. Create timestamp is automatically set by database.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceProductImage.ICreate,
  ): Promise<IEcommerceProductImage> {
    try {
      return await postEcommerceProductsProductIdImages({
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a paginated list of images associated with a specific product.
   *
   * This operation provides all images available for a given product, including main display images and secondary images used in search results and wishlist interfaces.
   *
   * The response includes the image URL, optional caption, and whether it's the primary image. Images are displayed in their original order based on image creation timestamp.
   *
   * For product display purposes, customers, sellers, and administrators can view product images as part of the product information. This endpoint ensures that only active (non-deleted) images are returned, respecting the soft delete constraint from the database schema.
   *
   * @param connection
   * @param productId The unique identifier of the product
   * @param body Search and pagination criteria for product images
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query the ecommerce_product_images table for entries matching the product_id parameter, filtering out records where deleted_at is not null. Apply pagination parameters from request body including page and size. Return images with image_url, caption, and is_primary fields. Use cursor-based pagination for datasets larger than 100 records. Include soft delete handling by default for all image operations. Ensure security context allows all authenticated actors (customers, sellers, admins) to view public product images.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedParam("productId")
    productId: string,
    @TypedBody()
    body: IEcommerceProductImage.IRequest,
  ): Promise<IPageIEcommerceProductImage.ISummary> {
    try {
      return await patchEcommerceProductsProductIdImages({
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific product image associated with a product.
   *
   * This endpoint provides detailed information about a product's image, including the URL, optional caption, and whether it is marked as the primary image. Product images are stored as immutable records per the Snapshot Principle, making them suitable for display in product listings, search results, and wishlist previews.
   *
   * Access is available to all users without authentication requirements. The endpoint is commonly used by frontend views to display product imagery and supports client-side image optimization based on returned file URLs.
   *
   * @param connection
   * @param productId ID of the product containing the image
   * @param imageId ID of the specific image
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Fetch image record from ecommerce_product_images table where id = {imageId} and ecommerce_product_id = {productId}. Verify product exists and is visible. Return image details including URL, caption (optional), primary status, and timestamps. Handle soft-deleted images by not returning them
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":imageId")
  public async at(
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedParam("imageId")
    imageId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceProductImage> {
    try {
      return await getEcommerceProductsProductIdImagesImageId({
        productId,
        imageId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
