import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceProduct } from "../../../api/structures/IEcommerceProduct";
import { IEcommerceProductReview } from "../../../api/structures/IEcommerceProductReview";
import { IPageIEcommerceProduct } from "../../../api/structures/IPageIEcommerceProduct";
import { IPageIEcommerceProductReview } from "../../../api/structures/IPageIEcommerceProductReview";
import { deleteEcommerceProductsProductId } from "../../../providers/deleteEcommerceProductsProductId";
import { getEcommerceProductsProductId } from "../../../providers/getEcommerceProductsProductId";
import { patchEcommerceProducts } from "../../../providers/patchEcommerceProducts";
import { patchEcommerceProductsProductId } from "../../../providers/patchEcommerceProductsProductId";
import { postEcommerceProducts } from "../../../providers/postEcommerceProducts";
import { putEcommerceProductsProductId } from "../../../providers/putEcommerceProductsProductId";

@Controller("/ecommerce/products")
export class EcommerceProductsController {
  /**
   * Create a new product entry in the system with all required business validation checks.
   *
   * This operation enables sellers to register new products on the platform following the defined business rules. It validates product name length, description length, and base price minimum to ensure product listings meet platform standards.
   *
   * Product creation requires the following fields: a unique name (minimum 5 characters), a detailed description (minimum 10 characters), a valid category reference, and a base price of at least $0.01. The system automatically generates the primary key and timestamp fields.
   *
   * When a new product is created, the system also initiates a product snapshot for future tracking and history, as per the Snapshot Principle Implementation requirements. This creates an immutable record of the product's initial state.
   *
   * @param connection
   * @param body Product creation data with required business validations
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification 1. Validate request body fields:
   *    - name: min 5 chars, max 255
   *    - description: min 10 chars, max 2000
   *    - basePrice: >= 0.01
   *    - categoriesId: valid UUID reference
   * 2. Generate new UUID for id
   * 3. Set created_at and updated_at to current timestamp
   * 4. Call product model create method
   * 5. Create product snapshot using Snapshot Principle
   * 6. Return full product object with all fields including generated id
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @TypedBody()
    body: IEcommerceProduct.ICreate,
  ): Promise<IEcommerceProduct> {
    try {
      return await postEcommerceProducts({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a filtered and paginated list of products in the marketplace.
   *
   * This operation supports advanced product discovery features for customers, including partial name matching, description search, and price range filtering. The response includes product summaries optimized for display in search results and product listings.
   *
   * Supports comprehensive pagination with configurable page sizes, cursor-based navigation for infinite scrolling, and sorting options. Response includes essential product attributes with category relationship information for contextual understanding.
   *
   * @param connection
   * @param body Search criteria and pagination parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query ecommerce_products table with pagination and filtering. Apply search filters on name, description, base_price range, and category. Join with ecommerce_categories for category details. Return cursor-based pagination for large result sets with efficient paging parameters.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async patch(
    @TypedBody()
    body: IEcommerceProduct.IRequest,
  ): Promise<IPageIEcommerceProduct.ISummary> {
    try {
      return await patchEcommerceProducts({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve comprehensive details about a specific product for customer view.
   *
   * This endpoint provides complete product information including name, description, base pricing, category associations, and current status. The information is displayed in the customer product detail page and reflects the latest available data from the database.
   *
   * Product details include all relevant specifications and features necessary for purchase decision-making. The API ensures customers receive accurate, up-to-date product information before completing transactions.
   *
   * @param connection
   * @param productId Unique identifier for the product
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Retrieve product details from ecommerce_products table with category join. Verify product existence, handle soft delete status appropriately. Return full product details with category name.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":productId")
  public async at(
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceProduct> {
    try {
      return await getEcommerceProductsProductId({
        productId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update existing product attributes with new values while preserving modification history.
   *
   * This operation allows sellers to modify product details including name, description, and base price. All changes trigger a system-wide snapshot recorded in the immutable `ecommerce_product_snapshots` table, enabling full audit history of product modifications through the Snapshot Principle.
   *
   * Validations ensure product name meets minimum 5-character requirement, description requires 10+ characters, and base price must be at least $0.01. The update operation preserves the product's category association and handles validation errors with specific response codes. The updated product will be returned with all current attributes including the system-generated `updated_at` timestamp. This operation is strictly for product modifications and does not affect product variants, images, or associated reviews.
   *
   * @param connection
   * @param productId The unique identifier of the product to update
   * @param body Updated product attributes including name, description, and price
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Validate productId exists in database, return 404 if not found. Update specified fields (name, description, base_price) with provided values. Apply input validation: name (5-50 chars), description (10+ chars), base_price ($0.01+). Create snapshot in `ecommerce_product_snapshots` table with before/after values. Ensure product relationships (e.g., `category_id`) are preserved. Return updated entity with all current attributes including `updated_at` timestamp.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":productId")
  public async update(
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceProduct.IUpdate,
  ): Promise<IEcommerceProduct> {
    try {
      return await putEcommerceProductsProductId({
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve paginated customer reviews for a specific product.
   *
   * This operation returns all active customer reviews associated with the specified product ID. Each review contains the customer's rating (1-5), textual comment, timestamps, and links to related product and customer entities. The response uses cursor-based pagination for efficient loading of large review sets.
   *
   * By design, the list operation does NOT include the customer's personal details (email, name) for privacy compliance. The system automatically filters out deleted reviews based on the deleted_at timestamp. This operation supports sorting by creation date (default: newest first) and can handle pagination with configurable page sizes.
   *
   * @param connection
   * @param productId The product's unique identifier for which reviews are being retrieved (UUID format).
   * @param body Pagination and sorting parameters for review listing
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query ecommerce_product_reviews table with product_id = path parameter value. Apply pagination and sorting parameters from request body. Return active reviews (deleted_at is null) in ascending order of created_at. Use cursor-based pagination with page and pageSize parameters. Handle missing product ID with 404 error.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch(":productId")
  public async patchByProductid(
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceProductReview.IRequest,
  ): Promise<IPageIEcommerceProductReview.ISummary> {
    try {
      return await patchEcommerceProductsProductId({
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Removes a product from active product listings and search results while preserving historical data.
   *
   * This operation marks the product as deleted via the deleted_at timestamp, ensuring immediate visibility changes across customer-facing interfaces including product listings and search results. The product remains in the system for compliance, audit, and historical tracking purposes.
   *
   * All existing order items, variant data, and associated product images retain their reference to the deleted product, maintaining complete order history integrity. No customer notifications or external system integrations are triggered by this operation.
   *
   * Intended for use by system administrators to deactivate discontinued or inappropriate products without data loss or business process disruption.
   *
   * @param connection
   * @param productId Unique identifier of the product to be deleted
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Execute Prisma update to set deleted_at to current timestamp. Preserve all other product data fields. Transactionally consistent. No response body returned (HTTP 204).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":productId")
  public async erase(
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteEcommerceProductsProductId({
        productId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
