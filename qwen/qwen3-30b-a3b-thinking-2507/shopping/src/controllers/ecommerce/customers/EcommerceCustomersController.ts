import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceCustomer } from "../../../api/structures/IEcommerceCustomer";
import { IPageIEcommerceCustomer } from "../../../api/structures/IPageIEcommerceCustomer";
import { getEcommerceCustomersCustomerId } from "../../../providers/getEcommerceCustomersCustomerId";
import { patchEcommerceCustomers } from "../../../providers/patchEcommerceCustomers";

@Controller("/ecommerce/customers")
export class EcommerceCustomersController {
  /**
   * Retrieve a filtered and paginated list of customer accounts.
   *
   * This operation provides advanced search capabilities including partial name matching, email domain filtering, account creation date range (based on created_at field), and account status (active/inactive) filtering. Supports comprehensive pagination with configurable page sizes and sorting.
   *
   * The response includes customer summary information optimized for list displays, including display name, email, and phone number. This endpoint requires authentication with 'customer' or 'admin' role.
   *
   * @param connection
   * @param body Search criteria and pagination parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query ecommerce_customers table with pagination and filtering. Apply search filters on display_name, email, phone, registration_date_range, and account_status. Handle authentication and authorization checks. Implement cursor-based pagination for large result sets. Validate search criteria to prevent invalid queries. Handle edge cases like empty result sets and invalid filter values properly.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IEcommerceCustomer.IRequest,
  ): Promise<IPageIEcommerceCustomer.ISummary> {
    try {
      return await patchEcommerceCustomers({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a complete customer profile including verified information and last update timestamp.
   *
   * This operation provides detailed profile information for customers that is fully normalized and validated for display purposes. The response includes all public profile fields with verification status indicators.
   *
   * The customer data includes display name, phone number, and verification details. Profile updates are reflected in real-time with version tracking, but only the current active version is returned. Historical snapshots of previous profiles are not included in the response.
   *
   * When a customer views their own profile, all public information is displayed. For administrators viewing other customers' profiles, additional fields like registration date and account status are shown.
   *
   * @param connection
   * @param customerId Unique identifier of the customer account
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query ecommerce_customers table with customerId path parameter to return full customer profile. Handle authentication via customer JWT and verify user has access to view profile. Return normalized profile data with last update timestamp. Handle 404 if customer not found, 403 if unauthorized.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":customerId")
  public async at(
    @TypedParam("customerId")
    customerId: string,
  ): Promise<IEcommerceCustomer> {
    try {
      return await getEcommerceCustomersCustomerId({
        customerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
