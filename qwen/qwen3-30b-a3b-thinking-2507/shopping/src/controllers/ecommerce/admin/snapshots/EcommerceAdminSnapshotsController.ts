import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceSnapshot } from "../../../../api/structures/IEcommerceSnapshot";
import { IPageIEcommerceSnapshot } from "../../../../api/structures/IPageIEcommerceSnapshot";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getEcommerceAdminSnapshotsId } from "../../../../providers/getEcommerceAdminSnapshotsId";
import { patchEcommerceAdminSnapshots } from "../../../../providers/patchEcommerceAdminSnapshots";

@Controller("/ecommerce/admin/snapshots")
export class EcommerceAdminSnapshotsController {
  /**
   * Retrieve paginated snapshots for auditing and historical data analysis across all system entities.
   *
   * This operation provides programmatic access to the immutable snapshot trail that records every data modification across the system according to the Snapshot Principle. The results include the entity type, entity ID, snapshot data, and timestamps of all modifications.
   *
   * Access is restricted to admin actors only as this endpoint exposes system-level audit information. The API returns a paginated list of snapshot summaries with essential fields to support audit trail analysis and historical data reconstruction.
   *
   * The API is designed for direct backend integration with analytics tools and administrative interfaces requiring comprehensive audit data. All snapshot data is preserved in its original state without transformation or modification.
   *
   * @param connection
   * @param body Search criteria and pagination parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query ecommerce_snapshots table with pagination and filtering capabilities. Apply search filters on entity_type, entity_id, created_at range, and snapshot_data keywords. Include standard cursor-based pagination for large datasets. Implement sorting by creation timestamp as default. Return complete snapshot data in immutable format without modification context.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IEcommerceSnapshot.IRequest,
  ): Promise<IPageIEcommerceSnapshot.ISummary> {
    try {
      return await patchEcommerceAdminSnapshots({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific snapshot record that captures a complete data modification event.
   *
   * This API endpoint provides access to detailed audit records of all data changes made to the system, including before and after state of the modified entity. Snapshot records are generated automatically by the system according to the Snapshot Principle Implementation.
   *
   * The response includes the entity type being modified, the exact before and after JSON representations, the timestamp of the change, the actor ID who initiated the change, and the reference to the modified entity. This information is used for audit trails, data lineage tracking, and historical analysis.
   *
   * Access to snapshot details is restricted to authorized personnel with administrative privileges and is intended for system audits, compliance requirements, and debugging purposes. Normal user-facing applications should not rely on this API directly.
   *
   * @param connection
   * @param id Unique identifier of the snapshot record to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query the ecommerce_snapshots table to retrieve the complete snapshot record by ID. Return all fields from the snapshot table including type, before, after, timestamp, actorId, and entityRef. Ensure the response includes the raw JSON representations of the before and after states. Do not transform or filter any data fields as this is a raw audit record access. Only return one snapshot record per request (single ID lookup).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":id")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<IEcommerceSnapshot> {
    try {
      return await getEcommerceAdminSnapshotsId({
        admin,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
