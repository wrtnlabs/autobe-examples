import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceCustomer } from "../../../../api/structures/IEcommerceCustomer";
import { IPageIEcommerceCustomer } from "../../../../api/structures/IPageIEcommerceCustomer";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getEcommerceAdminCustomersCustomerId } from "../../../../providers/getEcommerceAdminCustomersCustomerId";
import { patchEcommerceAdminCustomers } from "../../../../providers/patchEcommerceAdminCustomers";

@Controller("/ecommerce/admin/customers")
export class EcommerceAdminCustomersController {
  /**
   * Retrieve a filtered and paginated list of customer accounts.
   *
   * This operation provides comprehensive search capabilities including partial name matching, email domain filtering, account status filtering, and registration date ranges. It supports efficient pagination with configurable page size.
   *
   * Customers can view their own account details through this endpoint with appropriate filtering, while administrators can access full customer lists with expanded search criteria. Response includes customer summary information optimized for UI lists and includes status indicators for account verification and activity.
   *
   * The returned data includes essential details like registration date, account status (active, pending, suspended), and basic profile information while excluding sensitive fields such as password hashes or email verification status.
   *
   * @param connection
   * @param body Search criteria and pagination parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query ecommerce_customers table with pagination and filtering. Apply search filters on name, email, status, and registration date range. Include customer status and profile details in results. Implement cursor-based pagination for large result sets. Respect customer profile permissions (no admin details in customer view).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IEcommerceCustomer.IRequest,
  ): Promise<IPageIEcommerceCustomer.ISummary> {
    try {
      return await patchEcommerceAdminCustomers({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific customer account.
   *
   * This endpoint provides customer profile information including email verification status (email_verified) and account suspension status (is_suspended), both critical for access control decisions.
   *
   * The response includes timestamps for account creation and last update (created_at, updated_at), along with soft deletion information (deleted_at) if applicable. This ensures consistency with the platform's snapshot principle.
   *
   * Customer accounts require email verification before full platform access, and may be suspended for policy violations. Account information is presented without sensitive fields like password hashes to maintain security.
   *
   * @param connection
   * @param customerId Unique identifier for the customer account
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query ecommerce_customers table using customerId path parameter with UUID validation. Fetch all fields including email_verified, is_suspended, password_hash, and soft-delete information. Handle suspended accounts by returning full data but preventing actions through separate authorization checks. Validate parameter format before database access.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":customerId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("customerId")
    customerId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceCustomer> {
    try {
      return await getEcommerceAdminCustomersCustomerId({
        admin,
        customerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
