import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceAdminAuditLog } from "../../../../api/structures/IEcommerceAdminAuditLog";
import { IPageIEcommerceAdminAuditLog } from "../../../../api/structures/IPageIEcommerceAdminAuditLog";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getEcommerceAdminAuditLogsAuditLogId } from "../../../../providers/getEcommerceAdminAuditLogsAuditLogId";
import { patchEcommerceAdminAuditLogs } from "../../../../providers/patchEcommerceAdminAuditLogs";

@Controller("/ecommerce/admin/audit-logs")
export class EcommerceAdminAudit_logsController {
  /**
   * Retrieve a paginated list of administrative audit logs with filtering capabilities.
   *
   * This operation provides detailed records of all administrative actions performed on the platform, including the action performed (create/update/delete/etc.), target entity, and before/after state changes. Each audit log entry includes the admin user who performed the action, timestamp of the action, and complete state information.
   *
   * The operation supports filtering by action type (e.g., 'create', 'update', 'delete'), target entity (e.g., 'ecommerce_products', 'ecommerce_sellers'), and date range. Pagination parameters allow for efficient retrieval of large datasets without overloading the client.
   *
   * Note: Audit logs are immutable and preserved permanently for compliance and dispute resolution, following the Snapshot Principle requirements in the business rules.
   *
   * @param connection
   * @param body Filtering and pagination parameters for audit logs
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query ecommerce_admin_audit_logs table with pagination and filtering parameters. Apply filters on action type, target entity, and date range (created_at). Implement cursor-based pagination for large datasets. Include only non-deleted audit entries (deleted_at is null). Return the summary object with key metadata for each log entry.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IEcommerceAdminAuditLog.IRequest,
  ): Promise<IPageIEcommerceAdminAuditLog.ISummary> {
    try {
      return await patchEcommerceAdminAuditLogs({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves a specific administrative audit log entry capturing system modifications for accountability purposes.
   *
   * This endpoint provides detailed information about a specific administrative action including the timestamp of the change, the user who performed the action, the type of operation, and the previous and new values for the modified fields. The audit log history is preserved indefinitely for compliance and dispute resolution.
   *
   * The response includes the transaction identifier, actor (internal user system ID), operation type, and complete before/after state of the modified data. This is exclusively for administrative oversight and compliance requirements, not for public user-facing features.
   *
   * @param connection
   * @param auditLogId Unique identifier for the audit log entry
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Fetch admin audit log entries by ID from ecommerce_admin_audit_logs table. Enforce authorization checks to ensure only authorized admins can view audit logs. Include transactional ID, actor (user ID), change type, old/new values, and timestamp. Validate auditLogId exists and is within current system audit period.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":auditLogId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("auditLogId")
    auditLogId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceAdminAuditLog> {
    try {
      return await getEcommerceAdminAuditLogsAuditLogId({
        admin,
        auditLogId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
