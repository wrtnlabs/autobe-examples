import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceSeller } from "../../../../api/structures/IEcommerceSeller";
import { IPageIEcommerceSeller } from "../../../../api/structures/IPageIEcommerceSeller";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getEcommerceAdminSellersSellerId } from "../../../../providers/getEcommerceAdminSellersSellerId";
import { patchEcommerceAdminSellers } from "../../../../providers/patchEcommerceAdminSellers";

@Controller("/ecommerce/admin/sellers")
export class EcommerceAdminSellersController {
  /**
   * Retrieve a paginated list of seller accounts with optional filters for status and creation date.
   *
   * This operation provides comprehensive search capabilities for system administrators to review seller registration applications. It enables filtering by approval status (pending/approved/rejected) to prioritize pending applications for review. The response includes essential seller information optimized for admin workflow, including shop name, status, and registration timeline.
   *
   * Access requires 'admin' role permissions. The search interface supports filtering to quickly identify pending applications needing approval while maintaining audit readiness for all seller statuses.
   *
   * @param connection
   * @param body Search criteria and pagination parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query ecommerce_sellers table with pagination and filtering on status and creation date range. Apply filters for 'pending' status first as primary use case. Join with required relationships for admin context. Return cursor-based pagination for large result sets. Handle empty results as valid response.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IEcommerceSeller.IRequest,
  ): Promise<IPageIEcommerceSeller.ISummary> {
    try {
      return await patchEcommerceAdminSellers({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve comprehensive seller profile information by unique ID.
   *
   * This operation fetches the full profile of a seller account including their business name, public description, and current approval status (pending/approved/rejected). The response includes timestamps for account creation and modification to support audit trail requirements.
   *
   * Access to this endpoint is restricted to authenticated admin users. The seller's status field determines access eligibility: only approved sellers have active profiles visible via this operation.
   *
   * The seller's account deletion process requires validation for no pending orders or requests, but does not use soft deletion - accounts are permanently removed when deletion requirements are met.
   *
   * @param connection
   * @param sellerId Unique identifier of the seller account to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Retrieve seller profile by ID from ecommerce_sellers table with validation for active status. Handle deleted_at timestamp to exclude soft-deleted records. Implement authorization check for seller profile access permissions.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sellerId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceSeller> {
    try {
      return await getEcommerceAdminSellersSellerId({
        admin,
        sellerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
