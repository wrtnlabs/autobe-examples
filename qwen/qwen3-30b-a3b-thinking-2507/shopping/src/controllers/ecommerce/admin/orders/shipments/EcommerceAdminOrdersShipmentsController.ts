import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceShipment } from "../../../../../api/structures/IEcommerceShipment";
import { IPageIEcommerceShipment } from "../../../../../api/structures/IPageIEcommerceShipment";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getEcommerceAdminOrdersOrderIdShipmentsId } from "../../../../../providers/getEcommerceAdminOrdersOrderIdShipmentsId";
import { patchEcommerceAdminOrdersOrderIdShipments } from "../../../../../providers/patchEcommerceAdminOrdersOrderIdShipments";
import { postEcommerceAdminOrdersOrderIdShipments } from "../../../../../providers/postEcommerceAdminOrdersOrderIdShipments";
import { putEcommerceAdminOrdersOrderIdShipmentsId } from "../../../../../providers/putEcommerceAdminOrdersOrderIdShipmentsId";

@Controller("/ecommerce/admin/orders/:orderId/shipments")
export class EcommerceAdminOrdersShipmentsController {
  /**
   * Create a new shipment record for an existing order with shipping carrier and tracking details.
   *
   * This operation adds shipping information for an order when it has been dispatched. The shipment record includes carrier details, tracking number for customer tracking, and shipping status updates.
   *
   * Customers can view this shipment information in their order history. The implementation ensures shipment status updates are linked to the corresponding order and its line items.
   *
   * All fields are validated against business rules: shipping date must be present, tracking number must be unique (enforced at database level), and status must follow allowed values ('shipped', 'in transit', 'delivered', 'out for delivery').
   *
   * @param connection
   * @param orderId Unique identifier of the order for which shipment is being created
   * @param body Shipment creation details including carrier, tracking number, shipping date, and status
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification 1. Validate orderId exists and belongs to valid order
   * 2. Check tracking_number is unique (database will handle via @@unique constraint)
   * 3. Ensure shipping_date is in the past (order should be shipped)
   * 4. Validate status is in allowed values
   * 5. Create new ecommerce_shipments record with:
   *    - ecommerce_order_id = orderId
   *    - carrier = from request
   *    - tracking_number = from request
   *    - shipping_date = from request
   *    - status = from request
   *    - estimated_delivery_date and actual_delivery_date default to null
   * 6. Return newly created shipment object with all fields
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("orderId")
    orderId: string,
    @TypedBody()
    body: IEcommerceShipment.ICreate,
  ): Promise<IEcommerceShipment> {
    try {
      return await postEcommerceAdminOrdersOrderIdShipments({
        admin,
        orderId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a paginated list of shipment details associated with a specific order.
   *
   * This endpoint allows customers and administrators to view shipping information for a particular order, including tracking numbers, carrier details, shipping dates, and delivery status. The response is optimized for list display with essential shipping information.
   *
   * Business context: Each shipment represents a shipment event for items from the same seller in an order, providing customers with real-time tracking capabilities and delivery estimates.
   *
   * Security: Access is restricted to the order owner (customer) or system administrators. Unauthorized access returns HTTP 403 Forbidden. Active shipments (not soft-deleted) are displayed by default.
   *
   * Related operations: For detailed shipment information, use GET /orders/{orderId}/shipments/{shipmentId}.
   *
   * @param connection
   * @param orderId Unique identifier of the order to retrieve shipments for
   * @param body Optional filter criteria including shipment status and shipping date ranges
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query ecommerce_shipments table joining with ecommerce_orders on ecommerce_order_id, filtering by the supplied orderId and excluded soft-deleted records (deleted_at IS NULL). Apply request body filters on status and shipping_date ranges. Implement cursor-based pagination for large datasets using IPageIEcommerceShipment.ISummary structure. Handle status transitions as per the shipment status values (shipped, in transit, delivered, out for delivery). Include shipping tracking details, carrier information, and delivery estimates in the response.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceShipment.IRequest,
  ): Promise<IPageIEcommerceShipment.ISummary> {
    try {
      return await patchEcommerceAdminOrdersOrderIdShipments({
        admin,
        orderId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific shipment within an order.
   *
   * This operation provides complete shipment information for a specific shipment identified by its unique ID within a particular order. The response includes tracking details, carrier information, and shipping cost data.
   *
   * This API is primarily used by customers and system administrators to track the delivery status of ordered items. The shipment data is directly linked to the order's product variants and shipping details.
   *
   * Authentication: Requires valid customer or admin authentication. Customers can only access their own orders. Admins can access all orders.
   *
   * Relationship to Other APIs: This operation is called by the order details interface to display shipment history.
   *
   * @param connection
   * @param orderId Order identifier for the parent order to which the shipment belongs
   * @param id Shipment identifier within the specified order
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query the ecommerce_shipments table to retrieve a specific shipment by ID with an associated order ID. This operation implements an exact match retrieval with validation to ensure the shipment belongs to the specified order. Return the shipment's carrier, tracking number, status, and shipping cost in the response.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":id")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<IEcommerceShipment> {
    try {
      return await getEcommerceAdminOrdersOrderIdShipmentsId({
        admin,
        orderId,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update shipping details for a shipment within an order.
   *
   * This operation allows modification of shipping carrier, tracking information, and status for an existing shipment. The carrier must be a validated shipping provider (e.g., 'FedEx', 'DHL', 'USPS'). The tracking number must be unique across all shipments and will be verified during the update process. Status transitions are restricted to valid sequences (e.g., cannot change from 'delivered' to 'shipped').
   *
   * The actual_delivery_date field is automatically populated when updating status to 'delivered'. Shipping date and system timestamps are managed internally and cannot be modified through this API. The shipment's order relationship must match the orderId parameter to validate context.
   *
   * Note: This operation is only visible to authenticated customers with order ownership and administrators.
   *
   * @param connection
   * @param orderId The ID of the order containing the shipment
   * @param id The ID of the shipment to update
   * @param body Updated shipment details including carrier, tracking number, and status
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Update ecommerce_shipments table with provided attributes. Validate carrier name against allowed values (FedEx, DHL, USPS). Check tracking number uniqueness. Ensure status transitions are valid (shipped → in transit → delivered). If status is updated to 'delivered', set actual_delivery_date to current time. Verify shipment belongs to the specified order. Update updated_at timestamp. Omit system-managed fields (shipping_date, created_at, deleted_at).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":id")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceShipment.IUpdate,
  ): Promise<IEcommerceShipment> {
    try {
      return await putEcommerceAdminOrdersOrderIdShipmentsId({
        admin,
        orderId,
        id,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
