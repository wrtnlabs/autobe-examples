import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceAdmin } from "../../../../api/structures/IEcommerceAdmin";
import { IPageIEcommerceAdmin } from "../../../../api/structures/IPageIEcommerceAdmin";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getEcommerceAdminAdminsAdminId } from "../../../../providers/getEcommerceAdminAdminsAdminId";
import { patchEcommerceAdminAdmins } from "../../../../providers/patchEcommerceAdminAdmins";

@Controller("/ecommerce/admin/admins")
export class EcommerceAdminAdminsController {
  /**
   * Retrieve a filtered and paginated list of eCommerce admin accounts.
   *
   * This operation provides advanced search capabilities including email matching, date range filtering for account creation, and filtering by account status (including soft-deleted accounts using the deleted_at timestamp). Returns a comprehensive list of admin accounts with basic profile information optimized for management interfaces.
   *
   * Supports comprehensive pagination with configurable page sizes and sorting. Response includes admin summary information without sensitive fields (password_hash).
   *
   * @param connection
   * @param body Search criteria and pagination parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query ecommerce_admins table with pagination and filtering. Apply search filters on email, creation date range, and soft delete status. Return cursor-based pagination. Exclude sensitive fields (password_hash) in response. Handle soft delete state in filtering.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IEcommerceAdmin.IRequest,
  ): Promise<IPageIEcommerceAdmin.ISummary> {
    try {
      return await patchEcommerceAdminAdmins({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific admin account profile by unique identifier.
   *
   * This endpoint provides detailed information about an individual admin account holder authorized to perform system administration tasks. The response includes the admin's name, registered email address, account creation date and time, last modification timestamp, and current status within the system.
   *
   * The endpoint strictly returns active admin accounts unless the requesting actor has appropriate permissions to view non-active statuses. Response data is normalized and consistent with the database schema for ecommerce_admins table, including all relevant fields but excluding sensitive authentication data.
   *
   * For security, this endpoint is only accessible to auth-entified requests from admins with elevated privileges. The path parameter adminId is guaranteed to be a valid UUID as per the system's internal identifier format.
   *
   * @param connection
   * @param adminId Unique identifier for the admin account (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Fetch the admin account from ecommerce_admins table using the provided UUID. Validate actor authentication with admin role. Return full profile including name, email, creation date, last update timestamp, and current stage (active/pending/suspended). Ensure no sensitive fields like passwords are exposed. Implement authorization check before database access.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":adminId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceAdmin> {
    try {
      return await getEcommerceAdminAdminsAdminId({
        admin,
        adminId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
