import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceAdmin } from "../../../../api/structures/IEcommerceAdmin";
import { IPageIEcommerceAdmin } from "../../../../api/structures/IPageIEcommerceAdmin";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getEcommerceAdminAdminsAdminId } from "../../../../providers/getEcommerceAdminAdminsAdminId";
import { patchEcommerceAdminAdmins } from "../../../../providers/patchEcommerceAdminAdmins";

@Controller("/ecommerce/admin/admins")
export class EcommerceAdminAdminsController {
  /**
   * Retrieve a paginated list of administrator accounts with their details.
   *
   * This operation provides secure access to manage administrator accounts, displaying essential information including email addresses, roles (admin/super admin), and account status (active/pending).
   *
   * Supports configurable page sizes and sorting by email or role. Response includes summary data optimized for administrative dashboards without sensitive fields like password hashes.
   *
   * Only administrators with appropriate permissions can access this endpoint to maintain security and data integrity.
   *
   * @param connection
   * @param body Search criteria for admin accounts including filters, pagination parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query ecommerce_admins table with pagination and filtering. Apply search filters on email, role, and account status. Return cursor-based pagination for large result sets. Enforce role-based access for admins only.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IEcommerceAdmin.IRequest,
  ): Promise<IPageIEcommerceAdmin.ISummary> {
    try {
      return await patchEcommerceAdminAdmins({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve the complete details of an administrative account identified by a unique identifier.
   *
   * This endpoint provides full administrative account information including the registered email address, account creation timestamp, last update timestamp, and deletion status. The returned data includes system timestamps required for audit trails and security monitoring.
   *
   * Access to this endpoint is strictly limited to super administrators to maintain account security and prevent unauthorized information exposure. The 'deleted_at' timestamp field may contain a value indicating the account has been marked for deletion but remains accessible for auditing purposes.
   *
   * This operation serves as the primary data source for administrative management interfaces requiring full profile visibility, such as account troubleshooting and audit verification workflows.
   *
   * @param connection
   * @param adminId Unique identifier for the administrative account
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query ecommerce_admins table by id parameter with all columns selected. Return all fields including deleted_at timestamp. Handle non-existent IDs with 404 error. Include all database schema fields as defined: id, email, password_hash, created_at, updated_at, deleted_at.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":adminId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceAdmin> {
    try {
      return await getEcommerceAdminAdminsAdminId({
        admin,
        adminId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
