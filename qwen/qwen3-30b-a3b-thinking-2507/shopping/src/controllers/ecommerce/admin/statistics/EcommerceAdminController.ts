import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceSystemStatus } from "../../../../api/structures/IEcommerceSystemStatus";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getEcommerceAdminStatistics } from "../../../../providers/getEcommerceAdminStatistics";

@Controller("/ecommerce/admin/statistics")
export class EcommerceAdminController {
  /**
   * Provides high-level aggregated statistics for the platform's operational metrics. This endpoint delivers essential business intelligence data including customer base size, order volume trends, and revenue metrics essential for strategic planning and analytics. Statistics are calculated from current database records and represent the platform's active state.
   *
   * The data includes total customers (from `ecommerce_customers` table), total orders (from `ecommerce_orders` table), and total revenue (sum of `ecommerce_orders.total_amount`), providing a comprehensive view of platform health. This endpoint is primarily for integration with the analytics system.
   *
   * Access to this endpoint is limited to platform administrators only. The statistics data is not intended for direct client display but serves as input for internal analytics processes and executive dashboards.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Calculate platform statistics from database aggregations: total customers (ecommerce_customers.count), total orders (ecommerce_orders.count), total revenue (sum of ecommerce_orders.total_amount), and average order value (total revenue / total orders). Implement using prisma aggregation queries. Handle potential nulls for zero values with default 0.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async statistics(
    @AdminAuth()
    admin: AdminPayload,
  ): Promise<IEcommerceSystemStatus> {
    try {
      return await getEcommerceAdminStatistics({
        admin,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
