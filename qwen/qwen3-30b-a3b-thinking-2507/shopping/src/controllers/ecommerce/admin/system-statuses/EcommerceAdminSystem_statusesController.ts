import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceSystemStatus } from "../../../../api/structures/IEcommerceSystemStatus";
import { IPageIEcommerceSystemStatus } from "../../../../api/structures/IPageIEcommerceSystemStatus";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { deleteEcommerceAdminSystemStatusesId } from "../../../../providers/deleteEcommerceAdminSystemStatusesId";
import { getEcommerceAdminSystemStatusesId } from "../../../../providers/getEcommerceAdminSystemStatusesId";
import { patchEcommerceAdminSystemStatuses } from "../../../../providers/patchEcommerceAdminSystemStatuses";
import { postEcommerceAdminSystemStatuses } from "../../../../providers/postEcommerceAdminSystemStatuses";
import { putEcommerceAdminSystemStatusesId } from "../../../../providers/putEcommerceAdminSystemStatusesId";

@Controller("/ecommerce/admin/system-statuses")
export class EcommerceAdminSystem_statusesController {
  /**
   * Create a new system status record representing the operational health of a monitored component.
   *
   * This endpoint allows system components to report their current health status to the monitoring service. The status must be one of 'healthy', 'warning', or 'unhealthy', with health_score indicating severity (0-100). The last_check_timestamp must be provided as the moment of status reporting.
   *
   * The system automatically generates created_at and updated_at timestamps upon storage. This endpoint is specifically for external system components reporting their status via monitoring agents.
   *
   * This is a core monitoring endpoint and requires valid component_name, status, health_score, and last_check_timestamp parameters to be provided in the request body.
   *
   * @param connection
   * @param body System status creation data with component details
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Validate status against 'healthy', 'warning', 'unhealthy'. Validate health_score between 0-100. Set last_check_timestamp to provided value. Save to ecommerce_system_statuses table. Trigger monitoring system event if status changes from healthy. Do NOT accept auto-generated fields (created_at/updated_at) from client.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IEcommerceSystemStatus.ICreate,
  ): Promise<IEcommerceSystemStatus> {
    try {
      return await postEcommerceAdminSystemStatuses({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve real-time health status monitoring data for various system components.
   *
   * This operation provides comprehensive access to system health status information across all monitored components. Users can filter results based on component name, operational status (healthy, warning, or unhealthy), and health score ranges to identify potential issues or monitor overall platform health.
   *
   * Responses include paginated results with essential status information, optimized for monitoring dashboards and alerting systems.
   *
   * @param connection
   * @param body Search criteria and pagination parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query ecommerce_system_statuses table with pagination and filtering. Apply search filters on component_name, status (healthy/warning/unhealthy), and health_score ranges. Return cursor-based pagination for large result sets.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IEcommerceSystemStatus.IRequest,
  ): Promise<IPageIEcommerceSystemStatus.ISummary> {
    try {
      return await patchEcommerceAdminSystemStatuses({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed status information for a specific operational system component.
   *
   * This operation provides comprehensive details about the current operational status of a system service, including health indicators, last check timestamp, and current state. The response includes all relevant metrics for monitoring and debugging purposes.
   *
   * System status information is critical for administrators to assess operational health and identify potential issues. This endpoint should be used when investigating specific service health or when system status details are needed for troubleshooting.
   *
   * @param connection
   * @param id Unique identifier for the system status record
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Retrieve system status record from database, validate ID format, check for existence, and format health data response. Handle 'NotFound' if ID does not exist.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":id")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("id")
    id: string,
  ): Promise<IEcommerceSystemStatus> {
    try {
      return await getEcommerceAdminSystemStatusesId({
        admin,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update the operational status of a system component.
   *
   * This operation enables system administrators to modify the current health status and operational details of system components. Updated status information is immediately reflected in monitoring dashboards and system health displays.
   *
   * The request body contains the fields that can be modified, including status (values: 'healthy', 'warning', 'unhealthy') and health_score (numeric value between 0-100). Updates to system status are automatically recorded in the system's permanent snapshot history for audit and troubleshooting purposes.
   *
   * Changes require admin-level authentication with valid session tokens. This operation is critical for operational teams to communicate current system states during maintenance, outages, or health adjustments. The endpoint follows the Snapshot Principle by automatically preserving the previous state before applying changes.
   *
   * @param connection
   * @param id System status identifier
   * @param body Updated system status details
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Update the specified system status record with the provided changes. Validate that all necessary fields are present in the request. Update the 'status' field with the new operational state and 'healthCheckValue' with the updated metric. Set 'updatedById' to the authenticated admin user ID and 'updatedAt' to the current timestamp. Record the current state in the snapshots system before applying changes. The status must be one of the allowed enumeration values (up, down, maintenance).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":id")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceSystemStatus.IUpdate,
  ): Promise<IEcommerceSystemStatus> {
    try {
      return await putEcommerceAdminSystemStatusesId({
        admin,
        id,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a system status record for monitoring components.
   *
   * This endpoint allows system administrators to remove a monitored system status from the database. The system status will be completely removed and is not recoverable. System status records are preserved via snapshots (using the ecommerce_snapshots table) for audit trails and historical analysis.
   *
   * The endpoint follows permanent delete protocol (not soft), which means records are immediately and permanently removed from the database.
   *
   * Note: This is a permanent deletion. System status entries will no longer appear in the GET /system-statuses API call results, as they are completely removed from the main database.
   *
   * @param connection
   * @param id System status identifier (UUID)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Execute soft delete on ecommerce_system_statuses table by setting deleted_at timestamp to current time.
   *
   * 1. Verify record exists and is not already soft-deleted
   * 2. Check current status to ensure it's in a deletable state (active status)
   * 3. Set deleted_at = now()
   * 4. Return 204 No Content on success
   * 5. Handle soft delete validation through Prisma transaction
   *
   * Edge cases:
   * - If record not found: return 404
   * - If already deleted: return 400
   * - If no permissions: return 403
   *
   * Relationship to other operations:
   * - Complements GET /system-statuses/{id} which should display deleted statuses as inactive
   * - Requires authorization for system administrators with 'admin' role
   * - Does not affect related system component monitoring records (separate from component data)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":id")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteEcommerceAdminSystemStatusesId({
        admin,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
