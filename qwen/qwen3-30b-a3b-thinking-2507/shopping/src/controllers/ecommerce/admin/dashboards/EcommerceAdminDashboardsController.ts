import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceSystemConfig } from "../../../../api/structures/IEcommerceSystemConfig";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getEcommerceAdminDashboards } from "../../../../providers/getEcommerceAdminDashboards";

@Controller("/ecommerce/admin/dashboards")
export class EcommerceAdminDashboardsController {
  /**
   * Retrieve the administrative dashboard overview for the current context.
   *
   * This endpoint provides a comprehensive performance overview for platform administrators, displaying critical metrics including active system status, order volume, revenue, and operational health. The data is sourced directly from the platform's business integrity infrastructure to ensure accuracy and historical context.
   *
   * Key metrics displayed:
   * - Current system status (operational, degraded, critical)
   * - New orders placed today (cumulative)
   * - Revenue generated today (USD)
   * - Active sellers (count with new sellers ratio)
   * - System uptime percentage (last 24 hours)
   * - Pending cancellation requests (count)
   *
   * The dashboard data refreshes every 5 minutes to maintain relevance. All metrics are strictly for administrative use with system status data derived from ecommerce_system_statuses.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Gather real-time metrics from ecommerce_system_statuses, ecommerce_orders (count of new orders today), ecommerce_inventories (current stock status), and ecommerce_system_configs (system uptime). Aggregate into single dashboard structure with business context. Use pagination for system status data. Include only admin-authorized metrics.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @AdminAuth()
    admin: AdminPayload,
  ): Promise<IEcommerceSystemConfig> {
    try {
      return await getEcommerceAdminDashboards({
        admin,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
