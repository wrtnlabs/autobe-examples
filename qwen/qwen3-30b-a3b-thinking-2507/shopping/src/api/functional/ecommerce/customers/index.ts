/**
 * Retrieve a filtered and paginated list of customer accounts.
 *
 * This operation provides advanced search capabilities including partial name matching, email domain filtering, account creation date range (based on created_at field), and account status (active/inactive) filtering. Supports comprehensive pagination with configurable page sizes and sorting.
 *
 * The response includes customer summary information optimized for list displays, including display name, email, and phone number. This endpoint requires authentication with 'customer' or 'admin' role.
 *
 * @param props.connection
 * @param props.body Search criteria and pagination parameters
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor null
 * @x-autobe-specification Query ecommerce_customers table with pagination and filtering. Apply search filters on display_name, email, phone, registration_date_range, and account_status. Handle authentication and authorization checks. Implement cursor-based pagination for large result sets. Validate search criteria to prevent invalid queries. Handle edge cases like empty result sets and invalid filter values properly.
 * @path /ecommerce/customers
 * @accessor api.functional.ecommerce.customers.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Search criteria and pagination parameters
     */
    body: IEcommerceCustomer.IRequest;
  };
  export type Body = IEcommerceCustomer.IRequest;
  export type Response = IPageIEcommerceCustomer.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/ecommerce/customers",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/ecommerce/customers";
  export const random = (): IPageIEcommerceCustomer.ISummary =>
    typia.random<IPageIEcommerceCustomer.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

