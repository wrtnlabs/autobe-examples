/**
 * Update the currently authenticated customer's profile display name and phone number.
 *
 * The profile update operation allows customers to modify their public display name and phone number. Display name must be between 2-50 characters and avoid offensive language. Phone number must be in valid E.164 international format with country code.
 *
 * All changes are immediately reflected in customer-facing interfaces. A snapshot of the previous profile state is created automatically for audit purposes. Updates are only permitted for the authenticated customer's own profile.
 *
 * @param props.connection
 * @param props.body Updated profile fields for display name and phone number
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor seller
 * @x-autobe-specification Validate display_name length (2-50 characters) and profanity screening. Validate phone_number in E.164 format. Apply updated fields to profile record. Create a snapshot of previous profile state using IEcommerceCustomerProfileSnapshot service with actor=auth.currentUserId. Update timestamp field automatically. All validation rules match those in 03-functional-requirements.md and 06-exception-handling.md.
 * @path /ecommerce/seller/profile
 * @accessor api.functional.ecommerce.seller.profile.update
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function update(
  connection: IConnection,
  props: update.Props,
): Promise<update.Response> {
  return true === connection.simulate
    ? update.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...update.METADATA,
          path: update.path(),
          status: null,
        },
        props.body,
      );
}
export namespace update {
  export type Props = {
    /**
     * Updated profile fields for display name and phone number
     */
    body: IEcommerceCustomerProfile.IUpdate;
  };
  export type Body = IEcommerceCustomerProfile.IUpdate;
  export type Response = IEcommerceCustomerProfile;

  export const METADATA = {
    method: "PATCH",
    path: "/ecommerce/seller/profile",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/ecommerce/seller/profile";
  export const random = (): IEcommerceCustomerProfile =>
    typia.random<IEcommerceCustomerProfile>();
  export const simulate = (
    connection: IConnection,
    props: update.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: update.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
