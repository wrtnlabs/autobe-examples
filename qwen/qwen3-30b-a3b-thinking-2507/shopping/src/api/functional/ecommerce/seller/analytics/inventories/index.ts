export async function inventoryAnalytics(
  connection: IConnection,
): Promise<inventoryAnalytics.Response> {
  return true === connection.simulate
    ? inventoryAnalytics.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...inventoryAnalytics.METADATA,
          path: inventoryAnalytics.path(),
          status: null,
        },
      );
}
export namespace inventoryAnalytics {
  export type Response = IEcommerceVariantInventory;

  export const METADATA = {
    method: "GET",
    path: "/ecommerce/seller/analytics/inventories",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/ecommerce/seller/analytics/inventories";
  export const random = (): IEcommerceVariantInventory =>
    typia.random<IEcommerceVariantInventory>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}
