/**
 * Verifies system health and accessibility of the API without performing any business operations. This endpoint is used primarily for monitoring services and network health checks.
 *
 * The response contains a confirmation message to indicate the service is operational. This endpoint is non-functional in terms of business logic but essential for infrastructure monitoring.
 *
 * This endpoint is intended for automated checks by system monitoring tools and API gateways.
 *
 * @param props.connection
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor null
 * @x-autobe-specification Returns a static 'OK' response to indicate API operational readiness. No database access, no validation, no business logic. Implementation is a single line response payload.
 * @path /ecommerce/noop
 * @accessor api.functional.ecommerce.noop
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function noop(connection: IConnection): Promise<noop.Response> {
  return true === connection.simulate
    ? noop.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...noop.METADATA,
          path: noop.path(),
          status: null,
        },
      );
}
export namespace noop {
  export type Response = IEcommerceNoopResponse;

  export const METADATA = {
    method: "GET",
    path: "/ecommerce/noop",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/ecommerce/noop";
  export const random = (): IEcommerceNoopResponse =>
    typia.random<IEcommerceNoopResponse>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}
