import typia from "typia";

import { IEcommerceAdmin } from "../../../../structures/IEcommerceAdmin";

/**
 * The admin registration endpoint creates a new administrator account with email and password. The system verifies email format, enforces password complexity (minimum 8 characters, alphanumeric mix), and securely hashes credentials using bcrypt. Upon successful registration, it generates JWT access and refresh tokens with valid claims. This operation is exclusively for administrative use case where new administrators are added to the system.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Registration request containing email and password
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor admin
 * @x-autobe-specification Handle new admin registration. Validate credentials, create user record, and generate initial tokens. Requires email, password with complexity validation, and admin-specific validation rules.
 * @path /ecommerce/auth/admin/join
 * @accessor api.functional.ecommerce.auth.admin.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
export namespace join {
  export type Props = {
    /**
     * Registration request containing email and password
     */
    body: IEcommerceAdmin.IJoin;
  };
  export type Body = IEcommerceAdmin.IJoin;
  export type Response = IEcommerceAdmin.IAuthorized;

  export const METADATA = {
    method: "POST",
    path: "/ecommerce/auth/admin/join",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/ecommerce/auth/admin/join";
  export const random = (): IEcommerceAdmin.IAuthorized =>
    typia.random<IEcommerceAdmin.IAuthorized>();
  export const simulate = (
    connection: IConnection,
    props: join.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: join.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

