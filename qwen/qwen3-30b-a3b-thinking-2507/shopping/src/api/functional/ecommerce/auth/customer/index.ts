/**
 * Creates a new customer account with email and password credentials. The email field is validated against format requirements and must be unique across all customer accounts per the ecommerce_customers table. Password is securely hashed using bcrypt and stored in the password_hash field. Validates email format and enforces minimum 8-character password complexity before creating the account entry. References ecommerce_customers.email and password_hash fields for storage and uniqueness constraints.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Customer registration request containing required email and password
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor customer
 * @x-autobe-specification Service layer validates email format and uniqueness, hashes password with bcrypt, creates new ecommerce_customers record with email and password_hash. Sets default display_name to null, phone to null. Sets created_at/updated_at to current UTC time. Returns JWT tokens containing customer ID and actor type in IAuthorized response. Handles email uniqueness constraint exception by returning 409 error.
 * @path /ecommerce/auth/customer/join
 * @accessor api.functional.ecommerce.auth.customer.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
