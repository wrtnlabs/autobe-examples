import { IConnection } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";

import { IEcommerceSystemStatus } from "../../../../structures/IEcommerceSystemStatus";

/**
 * Retrieve the current distribution of system health statuses across all monitored components.
 *
 * This endpoint provides a real-time overview of system health state distribution for monitoring and alerting purposes. It aggregates the status field (healthy, warning, unhealthy) from the ecommerce_system_statuses table to show the count of components in each health state.
 *
 * The response enables system administrators to quickly assess the overall system health without drilling into individual components. This is a system-level metric that helps identify potential widespread issues across the platform architecture.
 *
 * The data represents the most recent status check values recorded in the system, with no filtering or pagination applied.
 *
 * @param props.connection
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor admin
 * @x-autobe-specification Group ecommerce_system_statuses records by status field to count healthy/warning/unhealthy components. Return the counts per status type. Use SQL aggregation query with GROUP BY status.
 * @path /ecommerce/admin/status-distribution
 * @accessor api.functional.ecommerce.admin.status_distribution.statusDistribution
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function statusDistribution(
  connection: IConnection,
): Promise<statusDistribution.Response> {
  return true === connection.simulate
    ? statusDistribution.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...statusDistribution.METADATA,
          path: statusDistribution.path(),
          status: null,
        },
      );
}
export namespace statusDistribution {
  export type Response = IEcommerceSystemStatus;

  export const METADATA = {
    method: "GET",
    path: "/ecommerce/admin/status-distribution",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/ecommerce/admin/status-distribution";
  export const random = (): IEcommerceSystemStatus =>
    typia.random<IEcommerceSystemStatus>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}
