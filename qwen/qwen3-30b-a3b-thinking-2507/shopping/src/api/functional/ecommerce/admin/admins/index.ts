/**
 * Retrieve a paginated list of administrator accounts with their details.
 *
 * This operation provides secure access to manage administrator accounts, displaying essential information including email addresses, roles (admin/super admin), and account status (active/pending).
 *
 * Supports configurable page sizes and sorting by email or role. Response includes summary data optimized for administrative dashboards without sensitive fields like password hashes.
 *
 * Only administrators with appropriate permissions can access this endpoint to maintain security and data integrity.
 *
 * @param props.connection
 * @param props.body Search criteria for admin accounts including filters, pagination parameters
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor admin
 * @x-autobe-specification Query ecommerce_admins table with pagination and filtering. Apply search filters on email, role, and account status. Return cursor-based pagination for large result sets. Enforce role-based access for admins only.
 * @path /ecommerce/admin/admins
 * @accessor api.functional.ecommerce.admin.admins.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Search criteria for admin accounts including filters, pagination parameters
     */
    body: IEcommerceAdmin.IRequest;
  };
  export type Body = IEcommerceAdmin.IRequest;
  export type Response = IPageIEcommerceAdmin.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/ecommerce/admin/admins",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/ecommerce/admin/admins";
  export const random = (): IPageIEcommerceAdmin.ISummary =>
    typia.random<IPageIEcommerceAdmin.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

