/**
 * Retrieve a filtered and paginated list of customer accounts.
 *
 * This operation provides comprehensive search capabilities including partial name matching, email domain filtering, account status filtering, and registration date ranges. It supports efficient pagination with configurable page size.
 *
 * Customers can view their own account details through this endpoint with appropriate filtering, while administrators can access full customer lists with expanded search criteria. Response includes customer summary information optimized for UI lists and includes status indicators for account verification and activity.
 *
 * The returned data includes essential details like registration date, account status (active, pending, suspended), and basic profile information while excluding sensitive fields such as password hashes or email verification status.
 *
 * @param props.connection
 * @param props.body Search criteria and pagination parameters
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor admin
 * @x-autobe-specification Query ecommerce_customers table with pagination and filtering. Apply search filters on name, email, status, and registration date range. Include customer status and profile details in results. Implement cursor-based pagination for large result sets. Respect customer profile permissions (no admin details in customer view).
 * @path /ecommerce/admin/customers
 * @accessor api.functional.ecommerce.admin.customers.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Search criteria and pagination parameters
     */
    body: IEcommerceCustomer.IRequest;
  };
  export type Body = IEcommerceCustomer.IRequest;
  export type Response = IPageIEcommerceCustomer.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/ecommerce/admin/customers",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/ecommerce/admin/customers";
  export const random = (): IPageIEcommerceCustomer.ISummary =>
    typia.random<IPageIEcommerceCustomer.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

