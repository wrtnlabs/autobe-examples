import { HttpError, IConnection } from "@nestia/fetcher";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";

import { IEcommerceSeller } from "../../../../structures/IEcommerceSeller";
import { IEcommerceSellerProfile } from "../../../../structures/IEcommerceSellerProfile";

/**
 * Retrieve detailed profile for a specific seller. Presents email address, approval status, and timestamp information.
 *
 * The approval status reflects current registration state (pending/awaiting_approval/approved/rejected). Data is read-only and mirrors current profile without modifications.
 *
 * Uses UUID-based identifier to fetch from ecommerce_sellers table. Returns all relevant profile fields without pagination or filtering.
 *
 * @param props.connection
 * @param props.sellerId Unique seller identifier (UUID)
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor null
 * @x-autobe-specification Fetch seller profile via primary ID from ecommerce_sellers table, filtering out soft-deleted records (deleted_at is null). Return complete profile data including email, approval_status, and timestamps. Handle 404 for non-existent sellers.
 * @path /ecommerce/sellers/:sellerId/profile
 * @accessor api.functional.ecommerce.sellers.profile.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique seller identifier (UUID)
     */
    sellerId: string & tags.Format<"uuid">;
  };
  export type Response = IEcommerceSeller;

  export const METADATA = {
    method: "GET",
    path: "/ecommerce/sellers/:sellerId/profile",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/ecommerce/sellers/${encodeURIComponent(props.sellerId ?? "null")}/profile`;
  export const random = (): IEcommerceSeller =>
    typia.random<IEcommerceSeller>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("sellerId")(() => typia.assert(props.sellerId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

/**
 * Update a seller's public profile information including shop name, description, and logo URL.
 *
 * This operation modifies the seller's public-facing profile including shop name, description, and logo URL. The shop name must be unique across all sellers and cannot be empty. The description is limited to 500 characters for clarity. The logo URL must be a valid URI string pointing to the stored image.
 *
 * The system automatically creates a snapshot record in ecommerce_seller_profile_snapshots to preserve historical changes with timestamp and before/after values. Previous shop name and description are saved for reference when comparing profile version history.
 *
 * @param props.connection
 * @param props.sellerId Unique identifier of the seller profile to update
 * @param props.body Seller profile update data
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor null
 * @x-autobe-specification Validate shopName uniqueness across all existing shops. Enforce description max length of 500 characters. Process logo URL as URI string, validate image format but don't handle actual image processing. Update profile fields while maintaining historical snapshots via ecommerce_seller_profile_snapshots. Handle partial updates (allow omitting fields).
 * @path /ecommerce/sellers/:sellerId/profile
 * @accessor api.functional.ecommerce.sellers.profile.update
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function update(
  connection: IConnection,
  props: update.Props,
): Promise<update.Response> {
  return true === connection.simulate
    ? update.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...update.METADATA,
          path: update.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace update {
  export type Props = {
    /**
     * Unique identifier of the seller profile to update
     */
    sellerId: string & tags.Format<"uuid">;

    /**
     * Seller profile update data
     */
    body: IEcommerceSellerProfile.IUpdate;
  };
  export type Body = IEcommerceSellerProfile.IUpdate;
  export type Response = IEcommerceSellerProfile;

  export const METADATA = {
    method: "PUT",
    path: "/ecommerce/sellers/:sellerId/profile",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/ecommerce/sellers/${encodeURIComponent(props.sellerId ?? "null")}/profile`;
  export const random = (): IEcommerceSellerProfile =>
    typia.random<IEcommerceSellerProfile>();
  export const simulate = (
    connection: IConnection,
    props: update.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: update.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("sellerId")(() => typia.assert(props.sellerId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
