/**
 * Retrieve filtered and paginated list of seller accounts for administrative management.
 *
 * This endpoint enables system administrators to search and manage seller registrations efficiently. It supports filtering by current account status (pending, approved, rejected), partial email matching, and shop name search. The results include essential seller profile information with status indicators for quick review of pending applications. Response includes pagination metadata for handling large seller directories. This endpoint only returns seller profile summaries (not full details) for performance reasons.
 *
 * @param props.connection
 * @param props.body Search criteria and pagination parameters
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor null
 * @x-autobe-specification Query ecommerce_sellers table with support for filtering by status (pending/approved/rejected), email address, and shop name. Apply pagination via cursor-based scrolling in query layer. Join with ecommerce_seller_profiles for shop name and status display. Return only essential fields for list view (email, shopName, status, lastUpdate). Handle sorting by lastUpdate field. Implement 12 items per page default.
 * @path /ecommerce/sellers
 * @accessor api.functional.ecommerce.sellers.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Search criteria and pagination parameters
     */
    body: IEcommerceSeller.IRequest;
  };
  export type Body = IEcommerceSeller.IRequest;
  export type Response = IPageIEcommerceSeller.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/ecommerce/sellers",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/ecommerce/sellers";
  export const random = (): IPageIEcommerceSeller.ISummary =>
    typia.random<IPageIEcommerceSeller.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

