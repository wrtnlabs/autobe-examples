/**
 * Create a new customer review for a product. This endpoint allows authenticated customers to submit ratings and comments about products they've purchased. Reviews require a 1-5 star rating and a minimum 10-character comment. The system validates that the customer has purchased the product (to be implemented in Phase 2) and records the review with timestamp. All reviews automatically create snapshot records for historical tracking under the Snapshot Principle. Response includes the created review object with full details including rating and comment. Product reviews are visible to other customers on the product detail page with the reviewer's profile status (active/deleted).
 *
 * @param props.connection
 * @param props.productId Unique identifier of the product being reviewed
 * @param props.body Review details including rating and comment
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor customer
 * @x-autobe-specification Validate rating is between 1-5 (integer). Validate comment minimum 10 characters. Check if customer has purchased product (not implemented yet). If valid, create record in ecommerce_product_reviews with current timestamp and reference to customer session. Add to review snapshot history. If any check fails, return relevant error code with message.
 * @path /ecommerce/customer/products/:productId
 * @accessor api.functional.ecommerce.customer.products.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function create(
  connection: IConnection,
  props: create.Props,
): Promise<create.Response> {
  return true === connection.simulate
    ? create.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...create.METADATA,
          path: create.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace create {
  export type Props = {
    /**
     * Unique identifier of the product being reviewed
     */
    productId: string & tags.Format<"uuid">;

    /**
     * Review details including rating and comment
     */
    body: IEcommerceProductReview.ICreate;
  };
  export type Body = IEcommerceProductReview.ICreate;
  export type Response = IEcommerceProductReview;

  export const METADATA = {
    method: "POST",
    path: "/ecommerce/customer/products/:productId",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/ecommerce/customer/products/${encodeURIComponent(props.productId ?? "null")}`;
  export const random = (): IEcommerceProductReview =>
    typia.random<IEcommerceProductReview>();
  export const simulate = (
    connection: IConnection,
    props: create.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: create.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("productId")(() => typia.assert(props.productId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
