/**
 * Retrieve detailed session information including security context and navigation history.
 *
 * This endpoint provides full session metadata for auditing and security purposes. The response includes the client's IP address, page URL from which the session was initiated, and previous page URL that led to the session creation. Session expiration automatically occurs 30 minutes after creation per security policy.
 *
 * Active sessions are indicated by the absence of a deletion timestamp; sessions with a deletion timestamp are no longer active but retained for audit purposes. Only customers can view their own session history, while administrators have full access for security monitoring. Session records are maintained in the database until automatically purged by maintenance job.
 *
 * @param props.connection
 * @param props.sessionId Unique identifier of the session to retrieve
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor customer
 * @x-autobe-specification 1. Check session ID format validate as UUID
 * 2. Fetch session record by ID from ecommerce_customer_sessions table
 * 3. Determine session validity:
 *    - If expired_at < current time → return 401
 *    - If deleted_at exists → return 404
 * 4. Return session metadata including IP, href, referrer, created/updated timestamps
 * 5. Apply soft delete check before returning data (deleted_at column exists)
 * 6. Handle session quorum: only allow access to customer owning session or admin role
 * @path /ecommerce/customer/sessions/:sessionId
 * @accessor api.functional.ecommerce.customer.sessions.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
