/**
 * Retrieve customer session records with search capabilities for auditing and security monitoring.
 *
 * This operation enables administrators to filter and view session data for specific customers, providing visibility into user authentication patterns and security events. The endpoint returns a paginated list of session metadata including timestamps of creation and expiration, client IP addresses, navigation paths, and session status.
 *
 * Sessions are automatically managed according to the 30-minute inactivity policy, with their status determined by the expired_at field. This API provides critical insights for security audits and session management by showing historical session activity without compromising the integrity of the immutable session data.
 *
 * The endpoint supports filtering by multiple criteria including customer identifier, IP address, session creation period, and navigation paths, making it suitable for investigating potential security incidents or monitoring user behavior patterns.
 *
 * @param props.connection
 * @param props.body Search criteria and pagination parameters for customer session records
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor customer
 * @x-autobe-specification Query ecommerce_customer_sessions table with filtering on customer_id, expired_at, ip, href, and referrer. Apply pagination and sorting based on provided parameters. Exclude sessions marked as deleted (deleted_at is null for active sessions). Return a paginated summary of session records with key metadata including creation timestamp, IP address, and navigation context.
 * @path /ecommerce/customer/sessions
 * @accessor api.functional.ecommerce.customer.sessions.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
