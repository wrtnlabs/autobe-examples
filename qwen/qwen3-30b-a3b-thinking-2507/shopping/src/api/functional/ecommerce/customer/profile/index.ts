import { IConnection } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";

import { IEcommerceCustomerProfile } from "../../../../structures/IEcommerceCustomerProfile";

/**
 * Retrieve the complete profile information for the currently authenticated customer.
 *
 * This endpoint provides the customer's current profile details including display name, phone number, and profile image data. The response contains only non-deleted profile information that is visible to the customer and is updated in real-time after any profile modifications.
 *
 * The system validates that the requesting customer owns the profile being retrieved and returns only their visible profile information, excluding sensitive fields like password hashes. This operation follows the snapshot principle where profile updates create immutable history entries without affecting the active profile view.
 *
 * @param props.connection
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor customer
 * @x-autobe-specification Query ecommerce_customer_profiles table to retrieve current profile information for authenticated customer. Apply business rules: display name (2-50 characters), phone number (E.164 format with country code), and profile images. Validate user owns the profile before returning data.
 * @path /ecommerce/customer/profile
 * @accessor api.functional.ecommerce.customer.profile.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(connection: IConnection): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(),
          status: null,
        },
      );
}
export namespace at {
  export type Response = IEcommerceCustomerProfile;

  export const METADATA = {
    method: "GET",
    path: "/ecommerce/customer/profile",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/ecommerce/customer/profile";
  export const random = (): IEcommerceCustomerProfile =>
    typia.random<IEcommerceCustomerProfile>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}
