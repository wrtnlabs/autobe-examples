/**
 * Create a manual snapshot of a cart's current state.
 *
 * This endpoint allows administrators to manually create a snapshot of a cart's state at a specific point in time. Snapshots are stored as immutable records, preserving the cart's content, product variants, and quantity information at the moment of capture.
 *
 * Normal cart state changes (adding items, changing quantities) automatically trigger snapshot creation for audit and history tracking. This manual endpoint is provided for specific administrative use cases where a snapshot must be captured outside the normal snapshotting mechanism.
 *
 * The response contains the complete snapshot details including the timestamp, cart ID, and the full cart state captured at the time of snapshot creation.
 *
 * @param props.connection
 * @param props.cartId Unique identifier of the cart to snapshot (UUID format)
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor customer
 * @x-autobe-specification Validate cart exists with given cartId. Trigger snapshot creation process by capturing current cart state including all cart items, product variants, quantities, and prices. Store as immutable record in ecommerce_cart_snapshots table with timestamp and user ID. Include related cart item details with historical variant information. Return the created snapshot data.
 * @path /ecommerce/customer/carts/:cartId/snapshots
 * @accessor api.functional.ecommerce.customer.carts.snapshots.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function create(
  connection: IConnection,
  props: create.Props,
): Promise<create.Response> {
  return true === connection.simulate
    ? create.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...create.METADATA,
          path: create.path(props),
          status: null,
        },
      );
}
export namespace create {
  export type Props = {
    /**
     * Unique identifier of the cart to snapshot (UUID format)
     */
    cartId: string & tags.Format<"uuid">;
  };
  export type Response = IEcommerceCartSnapshot;

  export const METADATA = {
    method: "POST",
    path: "/ecommerce/customer/carts/:cartId/snapshots",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/ecommerce/customer/carts/${encodeURIComponent(props.cartId ?? "null")}/snapshots`;
  export const random = (): IEcommerceCartSnapshot =>
    typia.random<IEcommerceCartSnapshot>();
  export const simulate = (
    connection: IConnection,
    props: create.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: create.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("cartId")(() => typia.assert(props.cartId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

