import { HttpError, IConnection } from "@nestia/fetcher";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";

import { IEcommerceCustomerAddress } from "../../../../../../structures/IEcommerceCustomerAddress";

/**
 * Set an address as the default shipping address for the authenticated customer.
 *
 * This operation changes the default shipping address for the current user, ensuring only one address remains marked as default across all future orders. The endpoint requires the address identifier in the path parameter and returns the full address object with updated default status.
 *
 * When called, the system automatically updates all existing orders using the previous default address to reference the new default address. A confirmation notification is sent to the customer upon successful update.
 *
 * The API responds with the complete address object to provide immediate feedback on the current state of the address after default status update.
 *
 * @param props.connection
 * @param props.addressId Unique identifier for the shipping address (UUID)
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor customer
 * @x-autobe-specification 1. Verify address exists and belongs to current user.
 * 2. Ensure no other address is marked as default.
 * 3. Update {addressId} row's `is_default` column to true.
 * 4. Update all related orders' shipping address to this address.
 * 5. Return updated address DTO.
 * 6. Trigger notification for default address change.
 * @path /ecommerce/customer/me/addresses/:addressId/default
 * @accessor api.functional.ecommerce.customer.me.addresses._default.setDefault
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function setDefault(
  connection: IConnection,
  props: setDefault.Props,
): Promise<setDefault.Response> {
  return true === connection.simulate
    ? setDefault.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...setDefault.METADATA,
          path: setDefault.path(props),
          status: null,
        },
      );
}
export namespace setDefault {
  export type Props = {
    /**
     * Unique identifier for the shipping address (UUID)
     */
    addressId: string & tags.Format<"uuid">;
  };
  export type Response = IEcommerceCustomerAddress;

  export const METADATA = {
    method: "POST",
    path: "/ecommerce/customer/me/addresses/:addressId/default",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/ecommerce/customer/me/addresses/${encodeURIComponent(props.addressId ?? "null")}/default`;
  export const random = (): IEcommerceCustomerAddress =>
    typia.random<IEcommerceCustomerAddress>();
  export const simulate = (
    connection: IConnection,
    props: setDefault.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: setDefault.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("addressId")(() => typia.assert(props.addressId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
