/**
 * Retrieve password reset request details for token validation.
 *
 * This operation allows the system to verify a secure password reset token used by customers. The endpoint checks token validity and expiration status (within 24-hour window) before allowing password reset functionality. The response structure returns essential token metadata and status information required for token validation workflow.
 *
 * The token must be present and unexpired for successful validation. Results include token details with verification expiration and creation timestamps. The system automatically removes expired tokens from the result set and prevents re-use via strict token expiration checks.
 *
 * This operation is used in the password reset flow to validate reset links before proceeding with password change requests.
 *
 * @param props.connection
 * @param props.body Token to validate and search criteria
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor customer
 * @x-autobe-specification Query ecommerce_customer_password_resets table with 'token' value lookup in request body. Validate token exists and not expired (current time < expires_at). Apply security filters to prevent exposure of non-expired tokens. Return single matching token record with summary data. Transactional query to ensure data consistency.
 * @path /ecommerce/customer/password-resets
 * @accessor api.functional.ecommerce.customer.password_resets.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Token to validate and search criteria
     */
    body: IEcommerceCustomerPasswordReset.IRequest;
  };
  export type Body = IEcommerceCustomerPasswordReset.IRequest;
  export type Response = IEcommerceCustomerPasswordReset.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/ecommerce/customer/password-resets",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/ecommerce/customer/password-resets";
  export const random = (): IEcommerceCustomerPasswordReset.ISummary =>
    typia.random<IEcommerceCustomerPasswordReset.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

