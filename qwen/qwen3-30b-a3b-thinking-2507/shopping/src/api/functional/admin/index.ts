import { IConnection } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";

import { IShoppingMallAdmin } from "../../structures/IShoppingMallAdmin";

/**
 * Retrieves administrative dashboard information with complete access to all
 * system features. This operation provides a summary view of platform health,
 * active orders, new user registrations, and security metrics, enabling
 * comprehensive platform oversight. The response includes all necessary system
 * statuses and indicator data required for administrative decision-making.
 *
 * This dashboard view accumulates real-time data across multiple system
 * components, including order processing pipelines, user engagement statistics,
 * and security event logs. It serves as the central command center for admin
 * monitoring and decision support.
 *
 * The operation integrates with shopping_mall_orders for order status,
 * shopping_mall_customers for user management, and shopping_mall_inventory_logs
 * for stock health metrics. This is the primary access point for administering
 * the entire platform.
 *
 * Information displayed on the dashboard must reflect real-time system health.
 * All included data is accurate as of the current request time and is expected
 * to be updated regularly throughout the platform's operational hours.
 *
 * This dashboard operation is only accessible to authenticated admin users with
 * complete platform permissions and serves as the central entry point for all
 * admin monitoring activities.
 *
 * @param props.connection
 * @path /admin/dashboard
 * @accessor api.functional.admin.dashboard
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function dashboard(
  connection: IConnection,
): Promise<dashboard.Response> {
  return true === connection.simulate
    ? dashboard.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...dashboard.METADATA,
          path: dashboard.path(),
          status: null,
        },
      );
}
export namespace dashboard {
  export type Response = IShoppingMallAdmin.IAuthorized;

  export const METADATA = {
    method: "GET",
    path: "/admin/dashboard",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/admin/dashboard";
  export const random = (): IShoppingMallAdmin.IAuthorized =>
    typia.random<IShoppingMallAdmin.IAuthorized>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}
