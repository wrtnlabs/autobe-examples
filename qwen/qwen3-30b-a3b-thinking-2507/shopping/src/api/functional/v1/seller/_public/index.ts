import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallSeller } from "../../../../structures/IShoppingMallSeller";

/**
 * Retrieves public seller profile information visible to all users without
 * authentication. The endpoint provides a compressed view of seller details
 * including business name, category specialization, and activity statistics.
 * Data is filtered to avoid sensitive information like contact details or
 * financial metrics.
 *
 * The public seller details are defined in the shopping_mall_sellers table with
 * fields explicitly permitted for public access. This endpoint adheres to
 * schema-defined data exposure rules for non-sensitive attributes.
 *
 * Returns fast-loading profile summary data optimized for quick display in
 * search results and product listings. The response includes standard seller
 * attributes like rating, sales count, and verified status based on available
 * schema fields.
 *
 * This operation is suitable for use in product listings where multiple sellers
 * may be displayed without requiring user authentication. It serves as the
 * primary public-facing contact point for seller information retrieval.
 *
 * The path structure follows the standard for public resources, avoiding any
 * auth-based prefix and enabling direct access. Response data is optimized for
 * mobile and web display performance in search contexts.
 *
 * @param props.connection
 * @param props.sellerId Identifier of the seller profile to retrieve
 * @path /v1/seller/:sellerId/public
 * @accessor api.functional.v1.seller._public.publicProfile
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function publicProfile(
  connection: IConnection,
  props: publicProfile.Props,
): Promise<publicProfile.Response> {
  return true === connection.simulate
    ? publicProfile.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...publicProfile.METADATA,
          path: publicProfile.path(props),
          status: null,
        },
      );
}
export namespace publicProfile {
  export type Props = {
    /** Identifier of the seller profile to retrieve */
    sellerId: string;
  };
  export type Response = IShoppingMallSeller.ISummary;

  export const METADATA = {
    method: "GET",
    path: "/v1/seller/:sellerId/public",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/v1/seller/${encodeURIComponent(props.sellerId ?? "null")}/public`;
  export const random = (): IShoppingMallSeller.ISummary =>
    typia.random<IShoppingMallSeller.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: publicProfile.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: publicProfile.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("sellerId")(() => typia.assert(props.sellerId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
