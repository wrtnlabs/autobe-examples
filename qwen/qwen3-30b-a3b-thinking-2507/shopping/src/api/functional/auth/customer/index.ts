/**
 * Creates a new customer account with verified email and secure password. The
 * system validates email uniqueness before creating the record, ensuring no
 * duplicate accounts exist. Account activation is handled through email
 * verification tokens stored in the email_verification_tokens table, which
 * tracks token validity and usage. Password hashing is performed using Bcrypt
 * with a work factor of 12 to prevent brute-force attacks. Customer data is
 * stored in the shopping_mall_customers table with mandatory fields: email,
 * password_hash, and verification_status. The response includes JWT access and
 * refresh tokens along with the customer's basic information for immediate
 * session initialization.
 *
 * This operation ensures GDPR compliance by collecting minimal necessary
 * personal data during registration. The system implements rate limiting to
 * prevent automated account creation attacks, with a maximum of 10 attempts per
 * hour from the same IP address. During registration, the customer is prompted
 * to provide a unique username, which is validated against existing usernames
 * in the shopping_mall_customers table before creation.
 *
 * The email verification process is critical to prevent impersonation attacks,
 * as it confirms the email address belongs to the account creator. The system
 * uses time-bound tokens (5 minutes validity) to enhance security,
 * automatically expiring after the verification period. Customer registration
 * must follow the service's security policy as documented in the
 * Authentication_Requirements.md analysis file.
 *
 * This endpoint handles international email formats as specified in RFC 5322,
 * while rejecting non-compliant addresses through schema validation. The
 * response structure includes both user-facing data and security-related fields
 * for client-side session management. Any errors during account creation (e.g.,
 * duplicate email) trigger specific error codes documented in the system's
 * error handling guidelines.
 *
 * The registration process requires email verification before account
 * activation, preventing unverified accounts from accessing premium features.
 * This security measure prevents bots from creating fraudulent accounts and
 * protects the integrity of customer data. The created account defaults to
 * 'pending_verification' status until the verification process completes
 * successfully.
 *
 * @param props.connection
 * @param props.body New customer registration data
 * @setHeader token.access Authorization
 *
 * @path /auth/customer/join
 * @accessor api.functional.auth.customer.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
