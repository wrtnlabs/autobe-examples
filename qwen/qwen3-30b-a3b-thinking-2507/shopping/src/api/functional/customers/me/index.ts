export async function getProfile(
  connection: IConnection,
): Promise<getProfile.Response> {
  return true === connection.simulate
    ? getProfile.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...getProfile.METADATA,
          path: getProfile.path(),
          status: null,
        },
      );
}
export namespace getProfile {
  export type Response = IShoppingMallCustomer;

  export const METADATA = {
    method: "GET",
    path: "/customers/me",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/customers/me";
  export const random = (): IShoppingMallCustomer =>
    typia.random<IShoppingMallCustomer>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}
