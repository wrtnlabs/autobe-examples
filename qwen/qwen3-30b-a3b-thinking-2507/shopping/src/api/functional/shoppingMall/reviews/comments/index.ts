/**
 * Retrieve a paginated list of comments associated with a specific product
 * review. This operation fetches comments from the ShoppingMallReviewComment
 * table using the reviewCode parameter to identify the parent review. The
 * response returns paged results including comment content, author information,
 * and rating.
 *
 * Security consideration: This operation is accessible to all users without
 * authentication as comments are public information. The implementation
 * leverages the unique reviewCode identifier which is globally unique across
 * the system, ensuring accurate data retrieval without ambiguity. Each comment
 * record links to a specific review via the reviewCode, maintained as a foreign
 * key in the shopping_mall_review_comments table.
 *
 * The operation follows OpenAPI REST principles with PATCH method for complex
 * search parameters. This allows flexible querying including pagination,
 * filtering, and sorting to efficiently support client-side presentation of
 * review comments. The response structure implements
 * IPageIShoppingMallReviewComment.ISummary for optimal performance and
 * readability in user interfaces.
 *
 * @param props.connection
 * @param props.reviewCode Unique business identifier code of the target review
 *   (global scope)
 * @param props.body Pagination and filtering parameters for retrieving review
 *   comments.
 * @path /shoppingMall/reviews/:reviewCode/comments
 * @accessor api.functional.shoppingMall.reviews.comments.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /** Unique business identifier code of the target review (global scope) */
    reviewCode: string;

    /** Pagination and filtering parameters for retrieving review comments. */
    body: IShoppingMallReviewComment.IRequest;
  };
  export type Body = IShoppingMallReviewComment.IRequest;
  export type Response = IPageIShoppingMallReviewComment.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/reviews/:reviewCode/comments",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/shoppingMall/reviews/${encodeURIComponent(props.reviewCode ?? "null")}/comments`;
  export const random = (): IPageIShoppingMallReviewComment.ISummary =>
    typia.random<IPageIShoppingMallReviewComment.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("reviewCode")(() => typia.assert(props.reviewCode));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

