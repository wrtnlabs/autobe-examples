import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallReviewVote } from "../../../../structures/IShoppingMallReviewVote";

/**
 * Retrieve a specific vote on a review by its unique code identifiers. This
 * operation allows anyone to fetch detailed information about a specific vote
 * on a product review, which helps in understanding the helpfulness rating of a
 * review from a user's perspective.
 *
 * The endpoint uses the unique identifiers {reviewCode} and {voteCode} to
 * directly reference the specific vote within the database. This is a read-only
 * operation that returns the vote's details, including the user's vote
 * (positive or negative) and any associated metadata.
 *
 * Security considerations include ensuring that votes are publicly viewable to
 * maintain transparency regarding customer review ratings. This endpoint has no
 * authentication requirements as vote data is meant to be publicly available
 * for review integrity.
 *
 * @param props.connection
 * @param props.reviewCode Unique business identifier code of the product review
 *   (global scope)
 * @param props.voteCode Unique business identifier code of the specific vote
 *   within the review (scoped to review)
 * @path /shoppingMall/reviews/:reviewCode/votes/:voteCode
 * @accessor api.functional.shoppingMall.reviews.votes.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique business identifier code of the product review (global scope) */
    reviewCode: string;

    /**
     * Unique business identifier code of the specific vote within the
     * review (scoped to review)
     */
    voteCode: string;
  };
  export type Response = IShoppingMallReviewVote;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/reviews/:reviewCode/votes/:voteCode",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/reviews/${encodeURIComponent(props.reviewCode ?? "null")}/votes/${encodeURIComponent(props.voteCode ?? "null")}`;
  export const random = (): IShoppingMallReviewVote =>
    typia.random<IShoppingMallReviewVote>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("reviewCode")(() => typia.assert(props.reviewCode));
      assert.param("voteCode")(() => typia.assert(props.voteCode));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
