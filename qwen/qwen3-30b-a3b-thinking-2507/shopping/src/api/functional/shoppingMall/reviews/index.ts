/**
 * Retrieve paginated list of product reviews for customers with advanced search
 * capabilities. This operation implements a comprehensive search interface for
 * the Reviews table in the database schema, supporting filtering by product ID,
 * user ID, rating range, and date ranges. The response includes minimal review
 * data (summary) optimized for list views, without exposing sensitive personal
 * information. Security features include automatic pagination with standard
 * page size (20 items) and sorting controls, with all input parameters
 * validated against business rules.
 *
 * This operation uses the IShoppingMallReview.IRequest data structure for
 * search parameters, which supports optional filtering by product ID (for
 * specific product reviews), user ID (for customer-specific review history),
 * and rating (to filter by star value). The response delivers a paginated
 * result set with IPageIShoppingMallReview.ISummary structure, containing
 * minimal review details including product ID, star rating, review text
 * summary, and creation timestamp. The system enforces 99th percentile response
 * time under 2 seconds for these search operations.
 *
 * The data is sourced directly from the shopping_mall_reviews database table,
 * which stores customer reviews for shopping products. Fields included in the
 * response match exactly with the schema's public-facing fields as per business
 * rules: product_id, user_id, rating, content, created_at. No system-managed
 * fields (like deleted_at) are exposed in the response. This endpoint is
 * designed exclusively for customer-facing review discovery in product catalog
 * interfaces, not for internal admin review management which uses separate
 * endpoints.
 *
 * @param props.connection
 * @param props.body Search parameters for filtering reviews including product,
 *   rating, and user filters
 * @path /shoppingMall/reviews
 * @accessor api.functional.shoppingMall.reviews.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Search parameters for filtering reviews including product, rating,
     * and user filters
     */
    body: IShoppingMallReview.IRequest;
  };
  export type Body = IShoppingMallReview.IRequest;
  export type Response = IPageIShoppingMallReview.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/reviews",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/shoppingMall/reviews";
  export const random = (): IPageIShoppingMallReview.ISummary =>
    typia.random<IPageIShoppingMallReview.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
