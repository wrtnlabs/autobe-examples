import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallProductCategory } from "../../../structures/IShoppingMallProductCategory";

/**
 * Retrieve detailed information about a specific product category in the
 * shopping mall platform. This operation provides access to the main category
 * details including name, description, hierarchical parent category
 * information, and associated metadata. The category details are retrieved from
 * the Product Categories model in the database schema, which stores the
 * official categorization structure used across the platform for product
 * organization and discovery. Security considerations include ensuring that
 * public category listings are accessible to all users while preventing
 * unauthorized modification of category structures. The response includes all
 * non-sensitive category attributes that enable product filtering and browsing
 * capabilities across the platform.
 *
 * @param props.connection
 * @param props.categoryCode Unique business identifier code of the target
 *   category (global scope)
 * @path /shoppingMall/categories/:categoryCode
 * @accessor api.functional.shoppingMall.categories.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique business identifier code of the target category (global scope) */
    categoryCode: string;
  };
  export type Response = IShoppingMallProductCategory;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/categories/:categoryCode",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/categories/${encodeURIComponent(props.categoryCode ?? "null")}`;
  export const random = (): IShoppingMallProductCategory =>
    typia.random<IShoppingMallProductCategory>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("categoryCode")(() => typia.assert(props.categoryCode));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
