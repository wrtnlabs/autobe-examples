import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallEmailVerificationToken } from "../../../structures/IShoppingMallEmailVerificationToken";

/**
 * Retrieves the details of a specific email verification token used for account
 * registration and email updates. This operation fetches token metadata
 * including expiration timestamp, associated email address, and verification
 * status. The token is globally unique across the system, designed as a
 * one-time verification mechanism sent to user emails via email channel.
 * Security is enforced through token expiration (typically 24 hours) rather
 * than user authentication, as it's used in email click workflows. The
 * operation validates the token exists in the database and has not expired
 * before returning details. This endpoint is strictly read-only for
 * verification workflows and not used for token creation or modification,
 * aligning with system-generated data constraints where tokens are
 * automatically created and managed by the registration process.
 *
 * @param props.connection
 * @param props.emailVerificationTokenId Unique token identifier for the
 *   verification process (global scope)
 * @path /shoppingMall/email-verification-tokens/:emailVerificationTokenId
 * @accessor api.functional.shoppingMall.email_verification_tokens.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique token identifier for the verification process (global scope) */
    emailVerificationTokenId: string;
  };
  export type Response = IShoppingMallEmailVerificationToken;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/email-verification-tokens/:emailVerificationTokenId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/email-verification-tokens/${encodeURIComponent(props.emailVerificationTokenId ?? "null")}`;
  export const random = (): IShoppingMallEmailVerificationToken =>
    typia.random<IShoppingMallEmailVerificationToken>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("emailVerificationTokenId")(() =>
        typia.assert(props.emailVerificationTokenId),
      );
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
