import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallChannel } from "../../../structures/IShoppingMallChannel";

/**
 * Retrieve detailed information about a specific sales channel configuration
 * from the platform. This operation accesses the shopping_mall_channels
 * database table, providing all available channel attributes including
 * configuration details, associated sales channel identifiers, and platform
 * settings.
 *
 * The operation is designed for public access to channel information, allowing
 * users to view available channel types without authentication. Channel data
 * includes both technical configuration parameters and user-facing attributes
 * for display purposes. The channelCode parameter uniquely identifies the
 * channel in a globally scoped manner, eliminating ambiguity across different
 * channel types.
 *
 * Security considerations: Since this operation is intended for public
 * consumption, no authentication is required. This endpoint is part of the
 * standard channel information API used by the platform's front-end to populate
 * sales channel selection options during checkout flows or merchant setup
 * processes.
 *
 * @param props.connection
 * @param props.channelCode Unique channel identifier code for the sales channel
 *   (global scope)
 * @path /shoppingMall/channels/:channelCode
 * @accessor api.functional.shoppingMall.channels.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique channel identifier code for the sales channel (global scope) */
    channelCode: string;
  };
  export type Response = IShoppingMallChannel;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/channels/:channelCode",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/channels/${encodeURIComponent(props.channelCode ?? "null")}`;
  export const random = (): IShoppingMallChannel =>
    typia.random<IShoppingMallChannel>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("channelCode")(() => typia.assert(props.channelCode));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
