import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";
export * as reviews from "./reviews/index";

/**
 * Permanently remove a product from the shopping mall platform. This operation
 * deletes the product record and all associated data including product images,
 * reviews, and inventory records. The operation is designed for two user roles:
 * sellers are allowed to delete products they have listed, and administrators
 * can delete any product.
 *
 * Security: Access is restricted to the 'seller' and 'admin' actors. Sellers
 * can only delete their own products (based on seller ownership), while
 * administrators have global deletion privileges. Each deletion attempt is
 * logged for audit purposes.
 *
 * Implementation: The operation executes a hard delete (not soft) on the
 * shopping_mall_products table. This means the record is removed from the
 * database immediately and cannot be recovered. The deletion also cascades to
 * related tables such as shopping_mall_product_images and
 * shopping_mall_product_reviews to maintain data integrity.
 *
 * Related operations: To ensure safe deletion, users should first check the
 * product's status with GET /products/{productCode}. The product must not be
 * part of active orders (which should be handled by business logic to prevent
 * deletion until orders are closed).
 *
 * @param props.connection
 * @param props.productCode Unique business identifier code of the product
 *   (global scope)
 * @path /shoppingMall/admin/products/:productCode
 * @accessor api.functional.shoppingMall.admin.products.erase
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function erase(
  connection: IConnection,
  props: erase.Props,
): Promise<void> {
  return true === connection.simulate
    ? erase.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...erase.METADATA,
          path: erase.path(props),
          status: null,
        },
      );
}
export namespace erase {
  export type Props = {
    /** Unique business identifier code of the product (global scope) */
    productCode: string;
  };

  export const METADATA = {
    method: "DELETE",
    path: "/shoppingMall/admin/products/:productCode",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/admin/products/${encodeURIComponent(props.productCode ?? "null")}`;
  export const random = (): void => typia.random<void>();
  export const simulate = (
    connection: IConnection,
    props: erase.Props,
  ): void => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: erase.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("productCode")(() => typia.assert(props.productCode));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
