export async function index(connection: IConnection): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
      );
}
export namespace index {
  export type Response = IShoppingMallReviewDashboard;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/admin/reviews/moderation/dashboard",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/shoppingMall/admin/reviews/moderation/dashboard";
  export const random = (): IShoppingMallReviewDashboard =>
    typia.random<IShoppingMallReviewDashboard>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}
