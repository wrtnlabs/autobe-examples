import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallReview } from "../../../../structures/IShoppingMallReview";
export * as moderation from "./moderation/index";
export * as analytics from "./analytics/index";

/**
 * Delete a product review from the shopping mall platform. This operation
 * permanently removes the review record from the database, immediately updating
 * all associated product review counts and summary views.
 *
 * The operation is designed for two scenarios: the customer who created the
 * review may delete it at any time, and administrators may delete reviews to
 * maintain platform integrity following specific moderation policies. Security
 * mechanisms ensure only the review owner or an administrator can initiate this
 * action.
 *
 * The operation references the shopping_mall_reviews database table structure,
 * which includes fields such as reviewCode, productId, customerId, content,
 * rating, and createdAt. The database record is permanently deleted (hard
 * delete) as per system requirements for operational simplicity and data
 * consistency.
 *
 * This endpoint should be used after pre-validating review ownership with GET
 * /reviews/{reviewCode}, and will trigger immediate updates to product review
 * counts through adjacent API operations.
 *
 * @param props.connection
 * @param props.reviewCode Unique business identifier code of the review (global
 *   scope)
 * @path /shoppingMall/admin/reviews/:reviewCode
 * @accessor api.functional.shoppingMall.admin.reviews.erase
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function erase(
  connection: IConnection,
  props: erase.Props,
): Promise<erase.Response> {
  return true === connection.simulate
    ? erase.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...erase.METADATA,
          path: erase.path(props),
          status: null,
        },
      );
}
export namespace erase {
  export type Props = {
    /** Unique business identifier code of the review (global scope) */
    reviewCode: string;
  };
  export type Response = IShoppingMallReview;

  export const METADATA = {
    method: "DELETE",
    path: "/shoppingMall/admin/reviews/:reviewCode",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/admin/reviews/${encodeURIComponent(props.reviewCode ?? "null")}`;
  export const random = (): IShoppingMallReview =>
    typia.random<IShoppingMallReview>();
  export const simulate = (
    connection: IConnection,
    props: erase.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: erase.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("reviewCode")(() => typia.assert(props.reviewCode));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
