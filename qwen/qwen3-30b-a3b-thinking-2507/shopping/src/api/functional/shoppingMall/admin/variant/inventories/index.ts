import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallVariantInventory } from "../../../../../structures/IShoppingMallVariantInventory";

/**
 * Retrieve detailed stock level and availability information for a specific
 * product variant inventory record from the system. This operation retrieves
 * data directly from the ShoppingMallVariantInventory table, providing complete
 * details about a specific inventory entry including stock quantity, status,
 * and last update time.
 *
 * Security considerations include strict role-based access control where only
 * authenticated sellers and system administrators can view inventory records.
 * Sellers can only access their own product variants' inventory data, while
 * administrators have full visibility across all inventory entries. The API
 * enforces this access control through the authorizationActors setting for this
 * endpoint.
 *
 * The operation supports retrieving complete inventory details without partial
 * data, which is necessary for inventory management systems that require
 * precise stock tracking. Related operations include inventory update (PUT
 * /variant/inventories/{inventoryId}) and inventory listing (PATCH
 * /variant/inventories), where inventory listing typically requires search
 * parameters to filter results.
 *
 * @param props.connection
 * @param props.inventoryId Unique identifier of the target inventory record
 * @path /shoppingMall/admin/variant/inventories/:inventoryId
 * @accessor api.functional.shoppingMall.admin.variant.inventories.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique identifier of the target inventory record */
    inventoryId: string;
  };
  export type Response = IShoppingMallVariantInventory;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/admin/variant/inventories/:inventoryId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/admin/variant/inventories/${encodeURIComponent(props.inventoryId ?? "null")}`;
  export const random = (): IShoppingMallVariantInventory =>
    typia.random<IShoppingMallVariantInventory>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("inventoryId")(() => typia.assert(props.inventoryId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
