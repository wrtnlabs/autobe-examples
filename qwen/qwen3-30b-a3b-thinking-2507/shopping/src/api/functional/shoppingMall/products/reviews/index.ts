import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallProductReview } from "../../../../structures/IShoppingMallProductReview";
import { IPageIShoppingMallProductReview } from "../../../../structures/IPageIShoppingMallProductReview";

/**
 * Retrieve paginated reviews for a specific product identified by its unique
 * code. This endpoint serves the business need for customers to view product
 * feedback and ratings in the catalog. The operation uses the ProductReview
 * model from the database schema to fetch reviews, applying pagination and
 * optional filters like date range and rating thresholds.
 *
 * Security considerations include no authentication required for public review
 * access, with rate limiting applied to prevent abuse. The productCode
 * parameter is required and must correspond to an existing product code in the
 * Product table. This endpoint does not require any request body parameters
 * beyond pagination and search filters, making it ideal for client-side
 * navigation and display.
 *
 * The response structure uses IPageIShoppingMallProductReview.ISummary to
 * provide a standardized paginated result format that matches platform API
 * conventions, ensuring efficient UI rendering with minimal data transfer.
 *
 * @param props.connection
 * @param props.productCode Unique business identifier code of the product
 *   (global scope)
 * @param props.body Pagination and search parameters for product reviews
 * @path /shoppingMall/products/:productCode/reviews
 * @accessor api.functional.shoppingMall.products.reviews.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /** Unique business identifier code of the product (global scope) */
    productCode: string;

    /** Pagination and search parameters for product reviews */
    body: IShoppingMallProductReview.IRequest;
  };
  export type Body = IShoppingMallProductReview.IRequest;
  export type Response = IPageIShoppingMallProductReview.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/products/:productCode/reviews",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/shoppingMall/products/${encodeURIComponent(props.productCode ?? "null")}/reviews`;
  export const random = (): IPageIShoppingMallProductReview.ISummary =>
    typia.random<IPageIShoppingMallProductReview.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("productCode")(() => typia.assert(props.productCode));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
