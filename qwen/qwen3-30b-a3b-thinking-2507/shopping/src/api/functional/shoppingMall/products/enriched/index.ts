import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallProductEnriched } from "../../../../structures/IShoppingMallProductEnriched";

/**
 * Return enriched product details including product information, associated
 * seller details, and category hierarchy.
 *
 * This operation retrieves a product with additional context information from
 * its associated tables, providing a single comprehensive response rather than
 * requiring multiple API calls. The enriched product includes all necessary
 * product details plus detailed seller information and the full category
 * hierarchy.
 *
 * The response is designed for optimal performance by pre-joining data related
 * to the product, eliminating the need for multiple client-side API calls to
 * get complete product information. This data structure combines information
 * from the products, sellers, and categories tables into a single unified
 * object.
 *
 * This endpoint is available to all users without authentication and returns
 * only publicly viewable product information, which aligns with the platform's
 * core functionality for product discovery and browsing.
 *
 * @param props.connection
 * @param props.productId Unique identifier of the target product
 * @path /shoppingMall/products/:productId/enriched
 * @accessor api.functional.shoppingMall.products.enriched.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique identifier of the target product */
    productId: string & tags.Format<"uuid">;
  };
  export type Response = IShoppingMallProductEnriched;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/products/:productId/enriched",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/products/${encodeURIComponent(props.productId ?? "null")}/enriched`;
  export const random = (): IShoppingMallProductEnriched =>
    typia.random<IShoppingMallProductEnriched>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("productId")(() => typia.assert(props.productId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
