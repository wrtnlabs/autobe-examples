import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallProductImage } from "../../../../structures/IShoppingMallProductImage";

/**
 * Retrieves the detailed information for a specific product image within the
 * product catalog. This operation is designed to provide direct access to an
 * individual image file associated with a product, serving as the primary means
 * to fetch product image metadata for display in product listings.
 *
 * The image data is retrieved from the ShoppingMallProductImage table in the
 * database schema, which contains the image URL, dimensions, and other catalog
 * presentation information. The operation uses the productCode to identify the
 * parent product and imageCode to locate the specific image file within the
 * product's image set.
 *
 * This is a public endpoint with no authentication required, as product images
 * are part of the public product catalog. There are no restrictions on who can
 * access this image data, making it suitable for client-side product listings
 * and catalog display systems.
 *
 * @param props.connection
 * @param props.productCode Unique business identifier code of the target
 *   product (global scope)
 * @param props.imageCode Unique business identifier code of the target image
 *   within the product (scoped to product)
 * @path /shoppingMall/products/:productCode/images/:imageCode
 * @accessor api.functional.shoppingMall.products.images.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique business identifier code of the target product (global scope) */
    productCode: string;

    /**
     * Unique business identifier code of the target image within the
     * product (scoped to product)
     */
    imageCode: string;
  };
  export type Response = IShoppingMallProductImage;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/products/:productCode/images/:imageCode",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/products/${encodeURIComponent(props.productCode ?? "null")}/images/${encodeURIComponent(props.imageCode ?? "null")}`;
  export const random = (): IShoppingMallProductImage =>
    typia.random<IShoppingMallProductImage>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("productCode")(() => typia.assert(props.productCode));
      assert.param("imageCode")(() => typia.assert(props.imageCode));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
