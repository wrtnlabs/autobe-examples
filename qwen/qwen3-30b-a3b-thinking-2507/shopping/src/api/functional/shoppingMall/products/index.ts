import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallProduct } from "../../../structures/IShoppingMallProduct";
export * as images from "./images/index";
export * as reviews from "./reviews/index";
export * as enriched from "./enriched/index";

/**
 * Retrieves detailed information about a specific product using its globally
 * unique business code. This operation provides the complete product metadata
 * including name, description, pricing, category association, and availability
 * status as defined in the shopping_mall_products database table.
 *
 * The product code serves as the primary identifier, uniquely mapping to one
 * product record without ambiguity. This public endpoint allows all users to
 * access product details for browsing, filtering, and catalog display purposes
 * without requiring authentication.
 *
 * Implementation note: The operation leverages the code field from
 * shopping_mall_products table for direct lookup. This avoids UUID-based
 * identifiers, providing more user-friendly URLs and better error handling for
 * end-users when product codes are part of marketing materials or customer
 * communication.
 *
 * Security: As a public read operation, no sensitive data fields like cost or
 * internal pricing are exposed through this endpoint.
 *
 * @param props.connection
 * @param props.productCode Unique product business identifier code that
 *   uniquely identifies the product (global scope)
 * @path /shoppingMall/products/:productCode
 * @accessor api.functional.shoppingMall.products.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique product business identifier code that uniquely identifies the
     * product (global scope)
     */
    productCode: string;
  };
  export type Response = IShoppingMallProduct;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/products/:productCode",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/products/${encodeURIComponent(props.productCode ?? "null")}`;
  export const random = (): IShoppingMallProduct =>
    typia.random<IShoppingMallProduct>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("productCode")(() => typia.assert(props.productCode));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
