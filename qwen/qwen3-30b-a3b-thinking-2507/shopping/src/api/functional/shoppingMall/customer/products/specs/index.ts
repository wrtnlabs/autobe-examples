/**
 * Retrieve detailed specifications for a specific product based on its unique
 * code identifier. This operation allows users to view the specs associated
 * with a particular product in the catalog, such as technical details,
 * attributes, variants, and configuration options.
 *
 * The operation is designed to work with the Product Specs table from the
 * database schema, specifically for products accessed via their code-based
 * unique identifier, which provides a better user experience than UUID
 * identifiers. The search parameters support filtering and sorting to allow
 * precise specification retrieval.
 *
 * Security considerations include rate limiting for product specs queries and
 * appropriate verification that the product exists and is active. The operation
 * returns a paginated list of specifications with summary information optimized
 * for display, allowing for efficient filtering on properties like attribute
 * name, value, and version.
 *
 * This operation integrates with the Product Specs database table as defined in
 * the schema, incorporating all available specification fields including
 * attributes, values, and relationships to product variants. The response
 * includes localized spec details based on the user's language preference where
 * applicable.
 *
 * @param props.connection
 * @param props.productCode Unique business identifier code of the product
 *   (global scope)
 * @param props.body Filtering and pagination parameters for product spec
 *   retrieval
 * @path /shoppingMall/customer/products/:productCode/specs
 * @accessor api.functional.shoppingMall.customer.products.specs.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /** Unique business identifier code of the product (global scope) */
    productCode: string;

    /** Filtering and pagination parameters for product spec retrieval */
    body: IShoppingMallProductSpec.IRequest;
  };
  export type Body = IShoppingMallProductSpec.IRequest;
  export type Response = IPageIShoppingMallProductSpec.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/customer/products/:productCode/specs",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/shoppingMall/customer/products/${encodeURIComponent(props.productCode ?? "null")}/specs`;
  export const random = (): IPageIShoppingMallProductSpec.ISummary =>
    typia.random<IPageIShoppingMallProductSpec.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("productCode")(() => typia.assert(props.productCode));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

