/**
 * Retrieves the list of authentication sessions associated with a specific
 * customer account. This operation provides detailed information about active
 * and historical authentication sessions including session identifiers,
 * creation timestamps, last activity times, device details, and location
 * information. The data helps customers monitor and manage their active login
 * sessions for enhanced security awareness. Security is enforced through
 * customer-specific session access, ensuring only the customer can view their
 * own session history. The API returns paginated results with summary-level
 * session data for efficient frontend rendering and performance optimization.
 *
 * The implementation directly references the shopping_mall_customer_sessions
 * database model, which tracks all authentication session records. Each session
 * entry is linked to the corresponding customer through the customerId foreign
 * key, ensuring accurate session filtering. The response structure uses
 * IPageIShoppingMallCustomerSession.ISummary format to provide optimized
 * client-side data consumption with summary properties.
 *
 * Security considerations include automatic filtering of sensitive
 * authentication tokens and expiration details. Session data is structured to
 * show only user-observable information, while all security-critical data
 * remains in the backend for processing.
 *
 * @param props.connection
 * @param props.customerId Unique identifier of the customer for whom session
 *   history is requested
 * @path /shoppingMall/customer/customers/:customerId/sessions
 * @accessor api.functional.shoppingMall.customer.customers.sessions.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
      );
}
export namespace index {
  export type Props = {
    /**
     * Unique identifier of the customer for whom session history is
     * requested
     */
    customerId: string;
  };
  export type Response = IPageIShoppingMallCustomerSession.ISummary;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/customer/customers/:customerId/sessions",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/customer/customers/${encodeURIComponent(props.customerId ?? "null")}/sessions`;
  export const random = (): IPageIShoppingMallCustomerSession.ISummary =>
    typia.random<IPageIShoppingMallCustomerSession.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("customerId")(() => typia.assert(props.customerId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

