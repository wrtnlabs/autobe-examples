import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallConfiguration } from "../../../../structures/IShoppingMallConfiguration";

/**
 * Retrieves detailed system configuration settings identified by a unique
 * configuration code. This operation provides the complete configuration
 * information for platform behavior and feature flag management, allowing the
 * system to dynamically adjust functionality based on runtime configuration
 * values.
 *
 * The operation directly accesses the shopping_mall_configurations database
 * table, which stores all system-wide configuration settings such as feature
 * toggles, system parameters, and environment-specific values. Each
 * configuration entry has a unique code identifier (config_code) that serves as
 * the primary access point.
 *
 * Security considerations include ensuring that the requesting user has
 * appropriate authorization to access system configuration settings. The
 * operation returns configuration details in a format optimized for system
 * consumption, containing minimal sensitive information to maintain security
 * boundaries. This endpoint is primarily used by administration interfaces, API
 * gateways, and system management tools to fetch active configuration values
 * for feature management and operational adjustments.
 *
 * @param props.connection
 * @param props.configCode Unique configuration code identifier (global scope)
 * @path /shoppingMall/customer/configurations/:configCode
 * @accessor api.functional.shoppingMall.customer.configurations.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique configuration code identifier (global scope) */
    configCode: string;
  };
  export type Response = IShoppingMallConfiguration;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/customer/configurations/:configCode",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/customer/configurations/${encodeURIComponent(props.configCode ?? "null")}`;
  export const random = (): IShoppingMallConfiguration =>
    typia.random<IShoppingMallConfiguration>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("configCode")(() => typia.assert(props.configCode));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
