/**
 * Retrieve a filtered and paginated list of shopping mall products from the
 * system. This operation utilizes the ShoppingMallProduct database schema to
 * provide comprehensive product search capabilities including name matching,
 * category filtering, price range, inventory status, and product variant
 * availability.
 *
 * The operation supports advanced pagination with configurable page size and
 * sorting options. Products can be sorted by name, price, rating, or creation
 * date in ascending or descending order. The search function intelligently
 * handles both product names and product variant descriptions to improve
 * discoverability.
 *
 * Security considerations include authorization checks for both customer and
 * seller roles, with appropriate privacy filtering of product inventory levels
 * based on the user's permissions. Sensitive fields like cost prices are
 * excluded from the response to maintain business confidentiality.
 *
 * This implementation integrates directly with the shopping_mall_products table
 * schema, incorporating all available product fields such as name, description,
 * category, price, and inventory status. The response includes product summary
 * information optimized for catalog display, with additional details available
 * through the product detail endpoint.
 *
 * @param props.connection
 * @param props.body Search criteria and pagination parameters for product
 *   filtering
 * @path /shoppingMall/customer/products
 * @accessor api.functional.shoppingMall.customer.products.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /** Search criteria and pagination parameters for product filtering */
    body: IShoppingMallProduct.IRequest;
  };
  export type Body = IShoppingMallProduct.IRequest;
  export type Response = IPageIShoppingMallProduct.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/customer/products",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/shoppingMall/customer/products";
  export const random = (): IPageIShoppingMallProduct.ISummary =>
    typia.random<IPageIShoppingMallProduct.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
