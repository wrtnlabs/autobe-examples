import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallProductImage } from "../../../../../structures/IShoppingMallProductImage";
import { IPageIShoppingMallProductImage } from "../../../../../structures/IPageIShoppingMallProductImage";

/**
 * Retrieve paginated list of product images associated with a specific product
 * identified by its unique code. This operation queries the
 * ShoppingMallProductImage database table to fetch all images related to the
 * target product, supporting configurable pagination, sorting, and filtering
 * options to optimize display in product galleries.
 *
 * The operation automatically filters images to show only those relevant to the
 * specified product code (global scope), ensuring no ambiguous results. Product
 * image data includes file metadata, display order, and alternate text for
 * accessibility, with proper relationship to the primary product entity in the
 * database schema.
 *
 * Security considerations include ensuring that only authenticated customers
 * and sellers can access product images. Customers can view images for all
 * products, while sellers are restricted to images for their own products. The
 * operation implements rate limiting to prevent abuse of the image loading
 * API.
 *
 * @param props.connection
 * @param props.productCode Unique business identifier code of the target
 *   product (global scope)
 * @param props.body Pagination and filtering parameters for product image
 *   search
 * @path /shoppingMall/customer/products/:productCode/images
 * @accessor api.functional.shoppingMall.customer.products.images.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /** Unique business identifier code of the target product (global scope) */
    productCode: string;

    /** Pagination and filtering parameters for product image search */
    body: IShoppingMallProductImage.IRequest;
  };
  export type Body = IShoppingMallProductImage.IRequest;
  export type Response = IPageIShoppingMallProductImage.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/customer/products/:productCode/images",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/shoppingMall/customer/products/${encodeURIComponent(props.productCode ?? "null")}/images`;
  export const random = (): IPageIShoppingMallProductImage.ISummary =>
    typia.random<IPageIShoppingMallProductImage.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("productCode")(() => typia.assert(props.productCode));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
