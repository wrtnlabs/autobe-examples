import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallProduct } from "../../../../../../structures/IShoppingMallProduct";
import { IPageIShoppingMallProduct } from "../../../../../../structures/IPageIShoppingMallProduct";

/**
 * Allows authenticated users to perform complex product searches with advanced
 * filtering across multiple product attributes, categories, and specifications.
 * This endpoint utilizes the Products database model to support full-text
 * search, category-based filtering, price ranges, and attribute-based queries
 * including color, size, material, and variant-specific details. The search
 * operation supports pagination, sorting options, and comprehensive filtering
 * capabilities to provide an optimized shopping experience for customers and
 * sellers. Implementation leverages the shopping_mall_products and
 * shopping_mall_product_specs tables with join operations for full attribute
 * coverage.
 *
 * Security considerations include authentication using the 'customer' actor
 * with appropriate permissions. Only authenticated customers can access product
 * search functionality. The endpoint does not require any sensitive data access
 * or authorization beyond basic user authentication. This search endpoint can
 * be used in conjunction with other product-related operations such as product
 * detail retrieval (GET /products/{productId}) and product category browsing
 * (GET /categories/{categoryId}).
 *
 * @param props.connection
 * @param props.body Advanced search parameters including filters, sorting
 *   options, and pagination settings
 * @path /shoppingMall/customer/search/products/advanced
 * @accessor api.functional.shoppingMall.customer.search.products.advanced.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Advanced search parameters including filters, sorting options, and
     * pagination settings
     */
    body: IShoppingMallProduct.IRequest;
  };
  export type Body = IShoppingMallProduct.IRequest;
  export type Response = IPageIShoppingMallProduct.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/customer/search/products/advanced",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/shoppingMall/customer/search/products/advanced";
  export const random = (): IPageIShoppingMallProduct.ISummary =>
    typia.random<IPageIShoppingMallProduct.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
