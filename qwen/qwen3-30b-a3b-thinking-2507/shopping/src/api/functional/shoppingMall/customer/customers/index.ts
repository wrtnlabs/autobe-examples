/**
 * Retrieve detailed information about a specific customer account in the
 * shopping platform. This operation allows authenticated users to view their
 * own account details including personal profile, preferences, and account
 * status.
 *
 * The operation requires a valid customerId parameter in UUID format and
 * returns a comprehensive customer profile compatible with the shopping mall's
 * user management system. All response fields are derived directly from the
 * customer database table as defined in the schema.
 *
 * Security considerations include validation that the requesting user has
 * access to the specified customer account. This operation is intentionally
 * restricted to the customer themselves, preventing unauthorized access to
 * account details.
 *
 * This operation depends on the core customer management system and does not
 * require any additional prior operations to function properly.
 *
 * @param props.connection
 * @param props.customerId Unique identifier of the target customer account
 *   (UUID format)
 * @path /shoppingMall/customer/customers/:customerId
 * @accessor api.functional.shoppingMall.customer.customers.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique identifier of the target customer account (UUID format) */
    customerId: string;
  };
  export type Response = IShoppingMallCustomer;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/customer/customers/:customerId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/customer/customers/${encodeURIComponent(props.customerId ?? "null")}`;
  export const random = (): IShoppingMallCustomer =>
    typia.random<IShoppingMallCustomer>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("customerId")(() => typia.assert(props.customerId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

