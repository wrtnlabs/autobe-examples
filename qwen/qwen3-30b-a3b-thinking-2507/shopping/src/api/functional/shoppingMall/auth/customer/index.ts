/**
 * Creates a new customer account with email and password.
 *
 * Customer registration requires email validation (valid format) and password complexity (min 8 characters, mixed case). After registration, an email verification token is sent to the provided email address, and the account status is temporarily 'pending' until verification.
 *
 * The system implements a security check during registration to prevent brute force attacks. All user inputs are sanitized to prevent XSS and other injection attacks. Registration attempts exceeding 5 in 5 minutes from the same IP are rate-limited.
 *
 * Schema field verification:
 * - 'email' field: Validated as required, must match email standards
 * - 'password_hash' field: Password hashed and stored, not plaintext
 * - 'email_verified_at' field: Set to NULL initially, populated after verification
 * - 'password_reset_token' field: Generated for future password recovery
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Customer registration request with email and password.
 * @x-autobe-specification 1. Validation: Check email format, password complexity (min 8 chars, mixed case), and ensure email isn't already registered.
 * 2. Rate Limiting: Implement 5-registration limit from same IP in 5 minutes.
 * 3. Registration Step: Create customer record with email and hashed password.
 * 4. Email Verification: Generate verification token, store in email_verification table, and send confirmation email.
 * 5. Token Generation: Create JWT access and refresh tokens for newly registered account.
 * 6. Response: Return tokens in IAuthorized format for frontend token storage.
 * @path /shoppingMall/auth/customer/join
 * @accessor api.functional.shoppingMall.auth.customer.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
