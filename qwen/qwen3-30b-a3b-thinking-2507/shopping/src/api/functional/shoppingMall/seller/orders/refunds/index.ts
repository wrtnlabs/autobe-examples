import { IShoppingMallOrderRefund } from "../../../../../structures/IShoppingMallOrderRefund";

/**
 * Initiates a refund process for an existing shopping order. This operation
 * allows both customers and sellers to request refunds for completed orders,
 * with the system handling authorization through ownership verification logic
 * (only orders belonging to the requesting user can be refunded).
 *
 * The operation checks that the order exists and is eligible for refunds (not
 * already refunded or cancelled). It verifies the refund request against the
 * order status and amount. This creates an order refund record and triggers the
 * appropriate financial processing.
 *
 * Security considerations include ownership verification - the user must own
 * the order (or be a seller) to initiate a refund. Rate limiting is applied to
 * prevent abuse, and sensitive financial data is properly masked in responses.
 *
 * Implementation references the shopping_mall_orders and
 * shopping_mall_order_refunds database tables. The order code in the path
 * parameter provides a user-friendly and globally unique identifier for
 * retrieval, avoiding UUIDs in the URL as per business requirements. This is a
 * standard POST operation that creates a new refund record, not modifying the
 * existing order.
 *
 * @param props.connection
 * @param props.orderCode Unique business identifier code of the target shopping
 *   mall order (global scope)
 * @param props.body Refund request details including amount and reason
 * @path /shoppingMall/seller/orders/:orderCode/refunds
 * @accessor api.functional.shoppingMall.seller.orders.refunds.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function create(
  connection: IConnection,
  props: create.Props,
): Promise<create.Response> {
  return true === connection.simulate
    ? create.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...create.METADATA,
          path: create.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace create {
  export type Props = {
    /**
     * Unique business identifier code of the target shopping mall order
     * (global scope)
     */
    orderCode: string;

    /** Refund request details including amount and reason */
    body: IShoppingMallOrderRefund.ICreate;
  };
  export type Body = IShoppingMallOrderRefund.ICreate;
  export type Response = IShoppingMallOrderRefund;

  export const METADATA = {
    method: "POST",
    path: "/shoppingMall/seller/orders/:orderCode/refunds",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/shoppingMall/seller/orders/${encodeURIComponent(props.orderCode ?? "null")}/refunds`;
  export const random = (): IShoppingMallOrderRefund =>
    typia.random<IShoppingMallOrderRefund>();
  export const simulate = (
    connection: IConnection,
    props: create.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: create.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("orderCode")(() => typia.assert(props.orderCode));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
