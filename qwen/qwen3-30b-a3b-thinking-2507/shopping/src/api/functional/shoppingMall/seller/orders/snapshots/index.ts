import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallOrderSnapshot } from "../../../../../structures/IShoppingMallOrderSnapshot";

/**
 * Retrieve a specific historical snapshot of an order from the system. This
 * operation allows customers, sellers, and administrators to view the
 * point-in-time state of an order at the moment a snapshot was created,
 * including the order status, associated products, and fulfillment details that
 * were current at that specific moment in time.
 *
 * The operation uses the business-readable order code to identify the parent
 * order (instead of UUID for better readability in URLs) and then uses the
 * unique business identifier code of the target snapshot (within the order) to
 * pinpoint the exact historical record within that order. This composite
 * identification structure ensures that order snapshots can be accurately and
 * unambiguously retrieved based on both business context (order code) and
 * technical context (snapshot code).
 *
 * Security considerations include that only authenticated users (customers,
 * sellers, or admins) can access order snapshots. The system verifies that the
 * authenticated user has permission to access the order's historical
 * information, maintaining data privacy and security. This operation should be
 * used as part of the standard order management workflow when reviewing order
 * history or investigating order status changes.
 *
 * @param props.connection
 * @param props.orderCode Unique business identifier code of the target order
 *   (global scope)
 * @param props.snapshotId Unique identifier of the target snapshot (within the
 *   order)
 * @path /shoppingMall/seller/orders/:orderCode/snapshots/:snapshotId
 * @accessor api.functional.shoppingMall.seller.orders.snapshots.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique business identifier code of the target order (global scope) */
    orderCode: string;

    /** Unique identifier of the target snapshot (within the order) */
    snapshotId: string;
  };
  export type Response = IShoppingMallOrderSnapshot;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/seller/orders/:orderCode/snapshots/:snapshotId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/seller/orders/${encodeURIComponent(props.orderCode ?? "null")}/snapshots/${encodeURIComponent(props.snapshotId ?? "null")}`;
  export const random = (): IShoppingMallOrderSnapshot =>
    typia.random<IShoppingMallOrderSnapshot>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("orderCode")(() => typia.assert(props.orderCode));
      assert.param("snapshotId")(() => typia.assert(props.snapshotId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
