/**
 * Retrieve a paginated list of authentication sessions for a specific seller
 * account. This operation accesses the Seller Sessions database table to fetch
 * all active authentication sessions associated with the specified seller,
 * enabling the seller to view and manage their active session status. The
 * implementation uses the seller's unique identifier to filter results
 * precisely, ensuring no data leakage to other sellers.
 *
 * Security considerations include strict authorization checks to ensure only
 * the seller themselves can access their own session data. Session data
 * includes token information and timestamps, but excludes sensitive token
 * values for security. The response is structured as a paginated summary to
 * optimize performance and reduce data payload size, as full session details
 * are handled internally in the service layer.
 *
 * This operation aligns with the 'shopping_mall_seller_sessions' database
 * model, which tracks valid login states and tokens specifically for seller
 * accounts. The endpoint follows the REST principles for resource nesting,
 * where sessions are a child resource of the seller.
 *
 * @param props.connection
 * @param props.sellerId Unique identifier of the target seller for whom
 *   sessions are being retrieved
 * @path /shoppingMall/seller/sellers/:sellerId/sessions
 * @accessor api.functional.shoppingMall.seller.sellers.sessions.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
      );
}
export namespace index {
  export type Props = {
    /**
     * Unique identifier of the target seller for whom sessions are being
     * retrieved
     */
    sellerId: string;
  };
  export type Response = IPageIShoppingMallSellerSession.ISummary;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/seller/sellers/:sellerId/sessions",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/seller/sellers/${encodeURIComponent(props.sellerId ?? "null")}/sessions`;
  export const random = (): IPageIShoppingMallSellerSession.ISummary =>
    typia.random<IPageIShoppingMallSellerSession.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("sellerId")(() => typia.assert(props.sellerId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

