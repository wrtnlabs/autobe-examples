import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallSection } from "../../../../structures/IShoppingMallSection";
import { IPageIShoppingMallSection } from "../../../../structures/IPageIShoppingMallSection";

/**
 * Retrieve paginated collection of sales channel sections from the platform.
 * This operation fetches sections that are used to organize content within
 * sales channels including online storefronts and mobile app experiences.
 *
 * The endpoint supports filtering by channel ID, section name pattern, and
 * visibility status. Sections are returned in the primary language and include
 * their hierarchical position within the channel structure. The results are
 * paginated and can be sorted by creation date, update date, or position for
 * optimal content organization.
 *
 * This operation serves the business need of displaying and managing
 * organizational structures for platform content. Sellers can use this endpoint
 * to see available section structures for content placement within their own
 * sales channels. The response includes concise summary information for each
 * section, optimized for UI display.
 *
 * The section data is sourced directly from the shopping_mall_sections database
 * table which stores the section configurations including associated channel
 * identifiers, titles, hierarchical relationships, and visibility status. This
 * operation requires seller authentication with authorizationActor set to
 * "seller" and is scoped to the requesting seller's data.
 *
 * @param props.connection
 * @param props.body Search criteria including filters, sorting, and pagination
 *   options for section listing
 * @path /shoppingMall/seller/sections
 * @accessor api.functional.shoppingMall.seller.sections.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Search criteria including filters, sorting, and pagination options
     * for section listing
     */
    body: IShoppingMallSection.IRequest;
  };
  export type Body = IShoppingMallSection.IRequest;
  export type Response = IPageIShoppingMallSection.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/seller/sections",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/shoppingMall/seller/sections";
  export const random = (): IPageIShoppingMallSection.ISummary =>
    typia.random<IPageIShoppingMallSection.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
