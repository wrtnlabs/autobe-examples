import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallRefundRequest } from "../../../../../structures/IShoppingMallRefundRequest";

/**
 * Retrieve a specific refund request details from the platform. This operation
 * allows authenticated users to fetch detailed information about an individual
 * refund request, including its current status, associated order information,
 * requested reasons, and processing notes.
 *
 * The operation retrieves data directly from the RefundRequest table in the
 * database, providing a comprehensive view of the refund request with all
 * relevant properties and relationships. The response includes detailed
 * information about the refund request itself, the associated order, and the
 * customer who initiated the request.
 *
 * Security considerations include ensuring that users can only access refund
 * requests they're authorized to view. Customers can view their own requests,
 * sellers can view requests related to their orders, and administrative users
 * can access all requests for auditing and processing purposes. The operation
 * implements role-based access control using the authorizationActors field.
 *
 * The response structure includes comprehensive refund request data with all
 * relevant fields, relationships, and status transitions. No additional fields
 * are included that are not explicitly defined in the database schema. The
 * response will contain the primary request details along with any related
 * information necessary for complete context.
 *
 * @param props.connection
 * @param props.requestId Unique identifier of the refund request to retrieve
 * @path /shoppingMall/seller/refunds/requests/:requestId
 * @accessor api.functional.shoppingMall.seller.refunds.requests.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique identifier of the refund request to retrieve */
    requestId: string;
  };
  export type Response = IShoppingMallRefundRequest;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/seller/refunds/requests/:requestId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/seller/refunds/requests/${encodeURIComponent(props.requestId ?? "null")}`;
  export const random = (): IShoppingMallRefundRequest =>
    typia.random<IShoppingMallRefundRequest>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("requestId")(() => typia.assert(props.requestId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
