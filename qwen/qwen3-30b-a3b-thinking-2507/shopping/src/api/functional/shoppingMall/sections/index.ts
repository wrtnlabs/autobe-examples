import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallSection } from "../../../structures/IShoppingMallSection";

/**
 * Retrieve detailed platform section metadata using the globally unique section
 * code. This operation queries the shopping_mall_sections database table to
 * fetch content organization structure for the platform's navigation system.
 * The section code serves as the primary identifier for hierarchical content
 * grouping within sales channels and product catalogs.
 *
 * Publicly accessible endpoint designed for client-side navigation components.
 * No authentication required as this metadata serves general platform
 * structure. The implementation leverages the sectionCode parameter to directly
 * fetch the section record, providing name, active status, priority ordering,
 * and channel assignment for use in UI rendering.
 *
 * This operation supports rapid website navigation loading by returning
 * complete metadata with minimal database overhead. The data structure is
 * optimized for UI components that display category hierarchies across
 * different sales channels without requiring user-specific context.
 *
 * @param props.connection
 * @param props.sectionCode Unique business identifier code of the target
 *   section (global scope)
 * @path /shoppingMall/sections/:sectionCode
 * @accessor api.functional.shoppingMall.sections.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique business identifier code of the target section (global scope) */
    sectionCode: string;
  };
  export type Response = IShoppingMallSection;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/sections/:sectionCode",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/sections/${encodeURIComponent(props.sectionCode ?? "null")}`;
  export const random = (): IShoppingMallSection =>
    typia.random<IShoppingMallSection>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("sectionCode")(() => typia.assert(props.sectionCode));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
