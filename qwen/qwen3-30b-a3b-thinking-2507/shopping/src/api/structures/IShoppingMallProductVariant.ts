import { tags } from "typia";

export namespace IShoppingMallProductVariant {
  /**
   * Summary view of a product variant optimized for display in order,
   * inventory, and inventory adjustment contexts. Includes only essential
   * fields necessary for referencing product variants without data bloat.
   * This summary form contains id, name, and SKU information for quick
   * identification during inventory management and order processing
   * operations. Used as references in order items, low stock alerts, and
   * inventory adjustments.
   *
   * The schema follows security-first principles by excluding all
   * system-managed fields while maintaining complete business context. It's
   * designed to provide the minimal necessary information for efficient
   * listing in paginated responses without requiring additional API calls for
   * context.
   *
   * This type is optimized for performance in list views, ensuring small
   * payloads while keeping all business-critical information. The schema's
   * structure matches exactly what's referenced in
   * IShoppingMallLowStockAlert, IShoppingMallInventoryAdjustment, and
   * IShoppingMallOrderItem schemas to maintain relationship consistency
   * across the API.
   */
  export type ISummary = {
    /**
     * Unique identifier for the product variant instance. Represents the
     * primary key in the product specifications table and is used for
     * referencing specific variant records across the system. Must follow
     * standard UUID format for uniqueness and security against guessing
     * attacks.
     *
     * This field is never provided by the client but is generated by the
     * system upon product version creation. It serves as the stable
     * identifier for the variant, enabling consistent tracking throughout
     * order and inventory management processes.
     */
    id: string & tags.Format<"uuid">;

    /**
     * Human-readable name of the product variant. Includes distinctive
     * features such as color, size, or other variant-specific information
     * (e.g., 'Red, 128GB', 'Medium, Black').
     *
     * The name is visible to users in product listings and inventory
     * management interfaces. It's designed to help customers quickly
     * identify variant differences and to enable efficient inventory
     * categorization without requiring full product details.
     */
    name: string;

    /**
     * Stock Keeping Unit code for the variant. Uniquely identifies the
     * specific variant in inventory tracking systems, used for tracking
     * inventory levels across warehouses.
     *
     * The SKU follows the business's standardized naming convention,
     * enabling accurate inventory management and cross-referencing with
     * external systems. It's a critical identifier used throughout the
     * fulfillment process, from order placement to inventory updates.
     */
    sku: string;
  };
}
