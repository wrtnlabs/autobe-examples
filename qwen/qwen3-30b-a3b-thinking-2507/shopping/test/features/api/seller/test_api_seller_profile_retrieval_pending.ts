export async function test_api_seller_profile_retrieval_pending(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin setup
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_login(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "admin123",
    } satisfies IEcommerceAdmin.ILogin,
  });
  // 2. Create pending seller account
  const sellerConnection: api.IConnection = { host: connection.host };
  const seller = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(12),
    } satisfies IEcommerceSeller.IJoin,
  });
  // 3. Validate pending seller profile is not accessible
  await TestValidator.error(
    "Pending seller profile should return 404",
    async () => {
      await api.functional.ecommerce.admin.sellers.at(adminConnection, {
        sellerId: seller.id,
      });
    },
  );
}
