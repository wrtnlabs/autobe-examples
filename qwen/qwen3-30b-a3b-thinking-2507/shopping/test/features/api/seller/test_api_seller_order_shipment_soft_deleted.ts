export async function test_api_seller_order_shipment_soft_deleted(
  connection: api.IConnection,
): Promise<void> {
  // Seller authentication
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(8),
      name: RandomGenerator.name(),
      description: RandomGenerator.paragraph({ sentences: 3 }),
    },
  });
  const softDeletedShipmentId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.httpError(
    "should return 404 for soft-deleted shipment",
    404,
    async () => {
      await api.functional.ecommerce.seller.orders.shipments.at(
        sellerConnection,
        {
          orderId: typia.random<string & tags.Format<"uuid">>(),
          shipmentId: softDeletedShipmentId,
        },
      );
    },
  );
}
