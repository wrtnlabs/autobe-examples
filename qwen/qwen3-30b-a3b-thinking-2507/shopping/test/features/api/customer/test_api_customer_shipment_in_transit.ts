export async function test_api_customer_shipment_in_transit(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin setup
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_login(adminConnection, {
    body: {
      email: "admin@test.com",
      password: "1234",
    } satisfies IEcommerceAdmin.ILogin,
  });
  // 2. Create a shipment with 'in transit' status
  const orderId = typia.random<string & tags.Format<"uuid">>();
  const shipment =
    await generate_random_ecommerce_admin_orders_shipments_create(
      adminConnection,
      {
        body: {
          carrier: "FedEx",
          tracking_number: RandomGenerator.alphaNumeric(10),
          shipping_date: new Date().toISOString(),
          status: "in transit",
        } satisfies IEcommerceShipment.ICreate,
        params: { orderId },
      },
    );
  typia.assert(shipment);
  // 3. Customer setup
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "1234",
      display_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IEcommerceCustomer.IJoin,
  });
  // 4. Retrieve the shipment details
  const retrievedShipment =
    await api.functional.ecommerce.customer.orders.shipments.at(
      customerConnection,
      {
        orderId,
        id: shipment.id,
      },
    );
  typia.assert(retrievedShipment);
  // 5. Validate the shipment status
  TestValidator.equals(
    "status matches",
    retrievedShipment.status,
    "in transit",
  );
}
