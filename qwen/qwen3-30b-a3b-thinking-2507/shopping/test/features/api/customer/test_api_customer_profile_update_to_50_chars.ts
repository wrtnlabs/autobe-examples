export async function test_api_customer_profile_update_to_50_chars(
  connection: api.IConnection,
): Promise<void> {
  // 1. Auth as customer
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(8),
      display_name: RandomGenerator.name(),
      href: "http://localhost",
      referrer: "http://localhost",
    } satisfies IEcommerceCustomer.IJoin,
  });
  // 2. Create exactly 50-character display name
  const displayName = RandomGenerator.alphabets(50);
  // 3. Update customer profile
  const updatedCustomer =
    await api.functional.ecommerce.customer.profile.update(customerConnection, {
      body: { display_name: displayName } satisfies IEcommerceCustomer.IUpdate,
    });
  typia.assert(updatedCustomer);
  // 4. Validate update
  TestValidator.equals(
    "display name matches",
    updatedCustomer.display_name,
    displayName,
  );
}
