export async function test_api_refund_request_for_delivered_order(
  connection: api.IConnection,
): Promise<void> {
  // Create customer using utility function
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "password123",
      display_name: RandomGenerator.name(),
      href: RandomGenerator.alphabets(10),
      referrer: RandomGenerator.alphabets(10),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IEcommerceCustomer.IJoin,
  });
  // Generate refund request using available utility function
  const refundRequest =
    await generate_random_ecommerce_customer_orders_refund_requests_create(
      customerConnection,
      {
        body: {
          reason: RandomGenerator.paragraph({ sentences: 3 }),
        } satisfies IEcommerceRefundRequest.ICreate,
        params: {
          orderId: "valid-delivered-order-id",
        },
      },
    );
  typia.assert(refundRequest);
  // Validate status is 'pending' as required
  TestValidator.equals(
    "refund request status should be 'pending'",
    refundRequest.status,
    "pending",
  );
}
