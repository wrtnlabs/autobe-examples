export async function test_api_customer_order_list_with_shipped_status(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create customer account
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "password123",
      display_name: RandomGenerator.name(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    },
  });
  // 2. Get list of shipped orders
  const shippedOrders = await api.functional.ecommerce.customer.orders.index(
    customerConnection,
    {
      body: {
        status: "shipped",
      },
    },
  );
  typia.assert(shippedOrders);
  // 3. Validate the response contains shipped orders
  TestValidator.predicate(
    "At least one shipped order",
    shippedOrders.data.length > 0,
  );
  for (const order of shippedOrders.data) {
    TestValidator.equals("Order status is shipped", order.status, "shipped");
  }
}
