export async function test_api_customer_login(connection: api.IConnection) {
  // 1. Create customer account using join endpoint
  const customerConnection: api.IConnection = { host: connection.host };
  const joinInput: IEcommerceCustomer.IJoin = {
    email: typia.random<string & tags.Format<"email">>(),
    password: RandomGenerator.alphaNumeric(16),
    display_name: RandomGenerator.name(),
    href: typia.random<string & tags.Format<"uri">>(),
    referrer: typia.random<string & tags.Format<"uri">>(),
    ip: typia.random<string & tags.Format<"ipv4">>(),
  };
  const customer = await authorize_customer_join(customerConnection, {
    body: joinInput,
  });
  typia.assert(customer);
  // 2. Authenticate with the new customer credentials using login endpoint
  const authConnection: api.IConnection = { host: connection.host };
  const authenticated = await authorize_customer_login(authConnection, {
    body: {
      email: customer.email,
      password: joinInput.password,
    } satisfies IEcommerceCustomer.ILogin,
  });
  typia.assert(authenticated);
  // 3. Validate that the login was successful
  TestValidator.equals("customer ID matches", authenticated.id, customer.id);
  TestValidator.predicate("token has access", !!authenticated.token.access);
  TestValidator.predicate(
    "token has expiration",
    !!authenticated.token.expired_at,
  );
}
