export async function test_api_customer_expired_email_filtered(connection: api.IConnection): Promise<void> {
    const customerConnection: api.IConnection = { host: connection.host };
    const customer = await authorize_customer_join(customerConnection, {
        body: {
            email: typia.random<string & tags.Format<"email">>(),
            password: "123456",
            display_name: RandomGenerator.name(),
            href: typia.random<string & tags.Format<"uri">>(),
            referrer: typia.random<string & tags.Format<"uri">>(),
            ip: typia.random<string & tags.Format<"ipv4">>(),
        } satisfies IEcommerceCustomer.IJoin,
    });
    await new Promise(resolve => setTimeout(resolve, 1000));
    const result = await api.functional.ecommerce.customer.email_verifications.index(customerConnection, {
        body: {
            isExpired: true,
            page: 1,
            limit: 10,
        } satisfies IEcommerceCustomerEmailVerification.IRequest,
    });
    typia.assert(result);
    TestValidator.predicate('Result should contain expired tokens', result.data.length > 0);
    for (const token of result.data) {
        TestValidator.predicate('Token should be expired', new Date(token.expires_at) < new Date());
    }
}