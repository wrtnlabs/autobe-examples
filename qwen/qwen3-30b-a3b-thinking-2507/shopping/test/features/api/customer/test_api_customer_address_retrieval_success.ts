export async function test_api_customer_address_retrieval_success(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create customer account
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "password123",
      display_name: RandomGenerator.name(),
      href: "https://example.com",
      referrer: "https://example.com/sign-up",
    } satisfies IEcommerceCustomer.IJoin,
  });
  // 2. Create cart (prerequisite for address retrieval)
  await generate_random_ecommerce_customer_carts_create(customerConnection, {
    body: {} as IEcommerceCart.ICreate,
  });
  // 3. Retrieve the address
  const addressId = typia.random<string & tags.Format<"uuid">>();
  const address = await api.functional.ecommerce.customer.addresses.at(
    customerConnection,
    {
      addressId,
    },
  );
  typia.assert(address);
}
