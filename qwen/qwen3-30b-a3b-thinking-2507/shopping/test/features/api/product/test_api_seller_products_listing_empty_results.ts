export async function test_api_seller_products_listing_empty_results(
  connection: api.IConnection,
): Promise<void> {
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {});
  const product = await generate_random_ecommerce_seller_products_create(
    sellerConnection,
    {
      body: {
        base_price: 100.01,
      },
    },
  );
  const response = await api.functional.ecommerce.seller.products.index(
    sellerConnection,
    {
      body: {
        max_price: 100.0,
      },
    },
  );
  typia.assert(response);
  TestValidator.equals("data should be empty", response.data.length, 0);
  TestValidator.equals("records should be 0", response.pagination.records, 0);
  TestValidator.equals("pages should be 0", response.pagination.pages, 0);
  TestValidator.equals(
    "current page should be 1",
    response.pagination.current,
    1,
  );
  TestValidator.equals(
    "limit should be default 12",
    response.pagination.limit,
    12,
  );
}
