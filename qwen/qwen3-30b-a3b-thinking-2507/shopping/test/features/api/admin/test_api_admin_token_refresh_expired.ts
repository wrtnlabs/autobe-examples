import { authorize_admin_refresh } from "../../../authorize/authorize_admin_refresh";

class TestClass {}
export async function test_api_admin_token_refresh_expired(
  connection: api.IConnection,
): Promise<void> {
  const adminConnection: api.IConnection = { host: connection.host };
  const admin = await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "1234",
    } satisfies IEcommerceAdmin.IJoin,
  });
  await TestValidator.error(
    "should reject expired admin refresh token",
    async () => {
      await authorize_admin_refresh(adminConnection, {
        body: {
          refresh_token: admin.token.refresh,
        } satisfies IEcommerceAdmin.IRefresh,
      });
    },
  );
}
