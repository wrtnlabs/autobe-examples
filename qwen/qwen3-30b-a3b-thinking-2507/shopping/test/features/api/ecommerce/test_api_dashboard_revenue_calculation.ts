export async function test_api_dashboard_revenue_calculation(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin account creation
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "1234",
    },
  });
  // 2. Dashboard data retrieval
  const dashboard: IEcommerceSystemConfig =
    await api.functional.ecommerce.admin.dashboards.at(adminConnection);
  typia.assert(dashboard);
  // 3. Revenue validation
  TestValidator.predicate(
    "revenueToday should be positive",
    dashboard.revenueToday > 0,
  );
}
