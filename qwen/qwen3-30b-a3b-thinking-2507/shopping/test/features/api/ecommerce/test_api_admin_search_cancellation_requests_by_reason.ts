export async function test_api_admin_search_cancellation_requests_by_reason(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin login
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_login(adminConnection, {
    body: {
      email: "admin@test.com",
      password: "1234",
    } satisfies IEcommerceAdmin.ILogin,
  });
  // 2. Create a random search string for testing
  const searchKey = `Search reason: ${RandomGenerator.paragraph({ sentences: 1 })}`;
  const searchKeyFragment = searchKey.substring(0, 5);
  // 3. Search cancellation requests
  const orderId = typia.random<string & tags.Format<"uuid">>();
  const searchResult =
    await api.functional.ecommerce.admin.orders.cancellation_requests.index(
      adminConnection,
      {
        orderId,
        body: {
          search: searchKeyFragment,
        } satisfies IEcommerceCancellationRequest.IRequest,
      },
    );
  typia.assert(searchResult);
  // 4. Validate search results - No need to check reason (doesn't exist in summary)
  TestValidator.predicate(
    `Search should find cancellation requests containing '${searchKeyFragment}'`,
    searchResult.data.length > 0,
  );
}
