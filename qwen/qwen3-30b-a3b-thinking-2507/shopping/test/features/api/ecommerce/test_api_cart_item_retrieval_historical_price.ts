export async function test_api_cart_item_retrieval_historical_price(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create customer account
  const customerConnection: api.IConnection = { host: connection.host };
  const customer = await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "1234",
      display_name: RandomGenerator.name(),
      href: "http://localhost",
      referrer: "http://localhost",
      ip: "127.0.0.1",
    } satisfies IEcommerceCustomer.IJoin,
  });
  typia.assert(customer);
  // 2. Create active cart (assumes cart with items)
  const cart = await generate_random_ecommerce_customer_carts_create(
    customerConnection,
    {
      body: {},
    },
  );
  typia.assert(cart);
  // Ensure cart has items
  if (cart.items.length === 0) {
    throw new Error("Cart has no items after creation");
  }
  // 3. Retrieve cart item (use first item)
  const cartItem = await api.functional.ecommerce.customer.carts.items.at(
    customerConnection,
    {
      cartId: cart.id,
      itemId: cart.items[0].id,
    },
  );
  typia.assert(cartItem);
  // 4. Validate historical pricing
  TestValidator.predicate(
    "price_at_addition should be a positive value",
    () => cartItem.price_at_addition > 0,
  );
}
