export async function test_api_product_top_products_empty(
  connection: api.IConnection,
) {
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "1234",
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    },
  });
  const output =
    await api.functional.ecommerce.customer.analytics.top_products.topProducts(
      customerConnection,
    );
  typia.assert(output);
  TestValidator.equals("data length", output.data.length, 0);
  TestValidator.equals("pagination records", output.pagination.records, 0);
  TestValidator.equals("pagination pages", output.pagination.pages, 0);
}
