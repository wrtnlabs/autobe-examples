export async function test_api_product_snapshot_no_history(
  connection: api.IConnection,
) {
  const sellerConnection: api.IConnection = { host: connection.host };
  const user = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(8),
      name: RandomGenerator.name(),
    },
  });
  const product = await generate_random_ecommerce_seller_products_create(
    sellerConnection,
    {
      body: {
        name: RandomGenerator.paragraph({ sentences: 2 }),
        description: RandomGenerator.paragraph({ sentences: 3 }),
        category_id: typia.random<string & tags.Format<"uuid">>(),
        base_price: typia.random<
          number & tags.Type<"uint32"> & tags.Minimum<1000>
        >(),
      },
    } satisfies {
      body: DeepPartial<IEcommerceProduct.ICreate>;
    },
  );
  typia.assert(product);
  const response = await api.functional.ecommerce.products.snapshots.index(
    sellerConnection,
    {
      productId: product.id,
      body: {
        page: 1,
        limit: 10,
      },
    } satisfies {
      productId: string;
      body: IEcommerceProductSnapshot.IRequest;
    },
  );
  typia.assert(response);
  TestValidator.equals(
    "snapshot history should be empty",
    response.data.length,
    0,
  );
  TestValidator.equals(
    "pagination records should be 0",
    response.pagination.records,
    0,
  );
  TestValidator.equals(
    "pagination pages should be 0",
    response.pagination.pages,
    0,
  );
}
