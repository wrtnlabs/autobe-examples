export async function test_api_password_reset_token_retrieval(connection: api.IConnection) {
    // 1. Create customer account
    const customerConnection: api.IConnection = { host: connection.host };
    const authResponse = await authorize_customer_join(customerConnection, {
        body: {
            email: typia.random<string & tags.Format<"email">>(),
            password: RandomGenerator.alphaNumeric(16),
            display_name: RandomGenerator.name(),
            href: typia.random<string & tags.Format<"uri">>(),
            referrer: typia.random<string & tags.Format<"uri">>(),
            ip: typia.random<string & tags.Format<"ipv4">>(),
        },
    });

    // 2. Retrieve password reset token
    const token = await api.functional.ecommerce.customer.password_resets.at(customerConnection, {
        resetId: typia.random<string>(),
    });
    typia.assert(token);

    // 3. Validate token expiration (must be in future)
    const tokenExpiration = new Date(token.expires_at);
    TestValidator.predicate("Token expiration should be in future", tokenExpiration > new Date());

    // 4. Validate customer association
    TestValidator.equals("Token customer ID matches auth response", token.customer.id, authResponse.id);
}