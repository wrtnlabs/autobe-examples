export async function test_api_order_deletion_by_admin(
  connection: api.IConnection,
) {
  // 1. Authenticate as admin
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      name: RandomGenerator.name(),
    },
  });
  // 2. Create a test order code for deletion
  const orderCode = RandomGenerator.alphaNumeric(8);
  // 3. Delete the order using admin connection
  await api.functional.shoppingMall.admin.orders.erase(adminConnection, {
    orderCode,
  });
}
