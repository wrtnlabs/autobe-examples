export async function test_api_order_cancellation_with_reason(
  connection: api.IConnection,
): Promise<void> {
  // 1. Customer authentication
  const customerConnection: api.IConnection = { host: connection.host };
  const customer = await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "1234",
      display_name: RandomGenerator.name(),
      href: "https://your-site.com",
      referrer: "https://your-site.com",
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IEcommerceCustomer.IJoin,
  });
  // 2. Create a valid order (we'll assume we can get an order ID)
  const orderId: string = typia.random<string & tags.Format<"uuid">>();
  // 3. Request order cancellation with a reason
  const cancellationRequest =
    await generate_random_ecommerce_customer_orders_cancellation_requests_create(
      customerConnection,
      {
        body: {
          reason: RandomGenerator.paragraph({ sentences: 1 }),
        },
        params: {
          orderId: orderId,
        },
      },
    );
  typia.assert(cancellationRequest);
  // 4. Validate that reason was accepted and stored
  TestValidator.equals(
    "Cancellation request reason matches input",
    cancellationRequest.reason,
    cancellationRequest.reason as string | null | undefined,
  );
}