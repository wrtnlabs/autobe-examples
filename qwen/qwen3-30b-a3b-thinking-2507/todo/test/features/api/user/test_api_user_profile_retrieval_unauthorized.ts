import { authorize_user_refresh } from "../../../authorize/authorize_user_refresh";
export async function test_api_user_profile_retrieval_unauthorized(
  connection: api.IConnection,
) {
  // Create first user account
  const user1Connection: api.IConnection = { host: connection.host };
  const user1 = await authorize_user_join(user1Connection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(12),
    },
  });
  // Create second user account
  const user2Connection: api.IConnection = { host: connection.host };
  const user2 = await authorize_user_join(user2Connection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(12),
    },
  });
  // Attempt to retrieve second user's profile using first user's connection
  await TestValidator.error(
    "user1 should not be able to retrieve user2's profile",
    async () => {
      await api.functional.todo.user.users.at(user1Connection, {
        userId: user2.id,
      });
    },
  );
}
