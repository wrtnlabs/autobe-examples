export async function test_api_todo_delete_other_user_todo(
  connection: api.IConnection,
) {
  // 1. Create User A
  const userAConnection: api.IConnection = { host: connection.host };
  await authorize_user_join(userAConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    },
  });
  // 2. User A creates a todo
  const todoFromUserA = await generate_random_todo_app_user_todos_create(
    userAConnection,
    {},
  );
  // 3. Create User B
  const userBConnection: api.IConnection = { host: connection.host };
  await authorize_user_join(userBConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    },
  });
  // 4. User B attempts to delete User A's todo
  await TestValidator.error("should return 404 for unowned todo", async () => {
    await api.functional.todoApp.user.todos.erase(userBConnection, {
      id: todoFromUserA.id,
    });
  });
}
