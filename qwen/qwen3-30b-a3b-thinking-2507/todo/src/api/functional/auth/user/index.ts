import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ITodoTodoUser } from "../../../structures/ITodoTodoUser";

/**
 * User registration endpoint, creates a new account with authentication data.
 *
 * This endpoint handles user registration for the Todo application.\n\nUsers
 * must provide authentication credentials to create a new account, after which
 * the system issues an initial JWT token.\n\nAuthentication data is stored
 * securely in the database with minimal required fields ensuring simplicity and
 * speed.\nThe implementation follows the business requirement for a minimal
 * registration process with no unnecessary fields or steps.\n\nThe system
 * validates the input to ensure it meets basic security requirements before
 * proceeding with account creation.
 *
 * @param props.connection
 * @param props.body Registration request payload. Contains authentication
 *   credentials required to create a new account.
 * @setHeader token.access Authorization
 *
 * @path /auth/user/join
 * @accessor api.functional.auth.user.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
export namespace join {
  export type Props = {
    /**
     * Registration request payload. Contains authentication credentials
     * required to create a new account.
     */
    body: ITodoTodoUser.ICreate;
  };
  export type Body = ITodoTodoUser.ICreate;
  export type Response = ITodoTodoUser.IAuthorized;

  export const METADATA = {
    method: "POST",
    path: "/auth/user/join",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/user/join";
  export const random = (): ITodoTodoUser.IAuthorized =>
    typia.random<ITodoTodoUser.IAuthorized>();
  export const simulate = (
    connection: IConnection,
    props: join.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: join.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

