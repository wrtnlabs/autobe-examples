import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ITodoTodo } from "../../../structures/ITodoTodo";

/**
 * Retrieve a single todo item by ID.
 *
 * Retrieves a single todo item from the database by its unique ID. This
 * operation supports both active and soft-deleted todos, but returns only
 * non-deleted items to the user. If the item has been soft-deleted (deleted_at
 * is set), it will not be returned in the response.
 *
 * This operation is designed to provide a detailed view of a single to-do item,
 * including its title, completion status, and timestamps. The response includes
 * only the item's essential data required for display and editing purposes.
 *
 * Security considerations include checking that the user has access to this
 * specific item (though this is simplified to no authentication requirement for
 * MVP). The operation properly handles soft deletion by excluding deleted items
 * from the response, maintaining data integrity.
 *
 * @param props.connection
 * @param props.todoId Unique identifier of the target todo (UUID format)
 * @path /todo/todos/:todoId
 * @accessor api.functional.todo.todos.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique identifier of the target todo (UUID format) */
    todoId: string;
  };
  export type Response = ITodoTodo;

  export const METADATA = {
    method: "GET",
    path: "/todo/todos/:todoId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/todo/todos/${encodeURIComponent(props.todoId ?? "null")}`;
  export const random = (): ITodoTodo => typia.random<ITodoTodo>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("todoId")(() => typia.assert(props.todoId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
