/**
 * Retrieves a paginated list of authentication sessions associated with the
 * specified user. This operation fetches session records from the
 * todo_user_sessions table, which tracks active login states and token validity
 * for user authentication. The session data includes session ID, login
 * timestamp, device information, and session status, providing a comprehensive
 * view of a user's active sessions. The userId parameter identifies the target
 * user via foreign key relationship to the todo_users table, ensuring session
 * data is scoped to the correct account. Pagination parameters allow for
 * efficient retrieval of recent sessions with configurable limit and offset.
 *
 * Security considerations include strict access control where only the
 * authenticated user can view their own session history, preventing access to
 * other users' session data. Session records are treated as user-specific
 * personal data requiring appropriate privacy controls. The operation aligns
 * with the todo_user_sessions database table schema which defines the session
 * relationships without using soft delete, eliminating need for special
 * handling in the operation logic.
 *
 * This endpoint serves user interface needs for session management, allowing
 * users to view and potentially revoke active sessions. The database schema
 * validation confirms presence of userId foreign key reference and all relevant
 * session fields without assuming additional unverified fields.
 *
 * @param props.connection
 * @param props.userId Unique identifier of the target user (UUID)
 * @param props.body Pagination and search parameters for session filtering
 * @path /todo/user/users/:userId/sessions
 * @accessor api.functional.todo.user.users.sessions.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
