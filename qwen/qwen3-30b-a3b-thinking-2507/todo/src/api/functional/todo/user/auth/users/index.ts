import { IConnection } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";

import { INull } from "../../../../../structures/INull";

export * as verify from "./verify/index";

/**
 * This endpoint is intentionally not implemented in the main API. Session termination is exclusively managed by the specialized authentication service. The system handles logout workflow through token invalidation and session management within the authentication layer, not through business-domain API operations. Business domain services should never handle session state or authentication tokens.
 *
 * Any attempt to call this endpoint would be redirected to the authentication service for proper session termination. The business API remains stateless and secure by design.
 *
 * @param props.connection
 * @x-autobe-specification No implementation should be generated for this endpoint as it is exclusively handled by authentication microservice. The authentication agent manages all session lifecycle operations in a secure, standardized manner without exposing them in the business API.
 * @path /todo/user/auth/users/logout
 * @accessor api.functional.todo.user.auth.users.logout
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function logout(
  connection: IConnection,
): Promise<logout.Response> {
  return true === connection.simulate
    ? logout.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...logout.METADATA,
          path: logout.path(),
          status: null,
        },
      );
}
export namespace logout {
  export type Response = INull;

  export const METADATA = {
    method: "POST",
    path: "/todo/user/auth/users/logout",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/todo/user/auth/users/logout";
  export const random = (): INull => typia.random<INull>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}
