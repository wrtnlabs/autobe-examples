import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageITodoAuditLog } from "../../../api/structures/IPageITodoAuditLog";
import { ITodoAuditLog } from "../../../api/structures/ITodoAuditLog";
import { getTodoAuditLogsAuditLogId } from "../../../providers/getTodoAuditLogsAuditLogId";
import { patchTodoAuditLogs } from "../../../providers/patchTodoAuditLogs";
import { postTodoAuditLogs } from "../../../providers/postTodoAuditLogs";

@Controller("/todo/audit-logs")
export class TodoAudit_logsController {
  /**
   * Create a new audit log entry to track system-level events and user actions. This operation records all significant system events including user account changes and administrative actions.
   *
   * The event_type field specifies the nature of the event using a standardized format of [module].[action] (e.g., 'user.created', 'account.deleted'). The todo_user_id field associates the event with a specific user's account.
   *
   * Optional event_description provides additional context about the event. The API automatically sets the created_at timestamp upon creation.
   *
   * This operation is designed for internal use by the system to maintain a complete audit trail of all critical events.
   *
   * @param connection
   * @param body Audit log creation parameters including event type and optional description
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Create a new audit log entry with event type and user context. Verify that todo_user_id exists in todo_users table. Set created_at to current timestamp automatically. Event description is optional and stored as is without processing. Validate event_type follows format "[module].[action]" (e.g., "user.created", "account.deleted").
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @TypedBody()
    body: ITodoAuditLog.ICreate,
  ): Promise<ITodoAuditLog> {
    try {
      return await postTodoAuditLogs({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a paginated list of system audit logs showing all user and system events.
   *
   * This operation provides comprehensive visibility into system activities including user account actions, administrative modifications, and system-level events. The audit logs include essential details such as event type, description, user context, and timestamps for complete historical tracing.
   *
   * Access to this endpoint is restricted to system administrators. The response includes only active audit logs (excluding soft-deleted entries) and supports filtering by event type, user ID, and date ranges.
   *
   * Pagination allows efficient handling of large volumes of audit data with configurable page sizes and sorting.
   *
   * @param connection
   * @param body Search criteria including event type, date range, and user ID filters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query todo_audit_logs table with pagination and filtering options. Implement date range filtering on created_at, event_type filtering, and user_id filtering. Exclude soft-deleted records (deleted_at IS NULL). Use join with todo_users to include user context if required. Return cursor-based pagination for large datasets.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: ITodoAuditLog.IRequest,
  ): Promise<IPageITodoAuditLog.ISummary> {
    try {
      return await patchTodoAuditLogs({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific system audit log entry corresponding to a user's account activity.
   *
   * This endpoint provides detailed information about a single event tracked in the system, including the type of event (e.g., 'user.created', 'account.deleted'), a description of what occurred, and timestamps for when the event was recorded and last updated.
   *
   * The response includes complete context about the user action, allowing system administrators and users to review specific events in the audit trail. Event types follow a standardized naming convention to maintain consistency across the system's logging mechanisms.
   *
   * Audit logs are immutable historical records of system events and cannot be modified or deleted, ensuring a trustworthy audit trail for compliance and security purposes.
   *
   * @param connection
   * @param auditLogId Unique identifier of the audit log entry to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Retrieves a specific audit log entry with full event context. The implementation should:
   * - Verify the audit log ID exists in the database
   * - Ensure the requesting user owns the associated todo_user_id
   * - Join with the todo_users table to include user context details
   * - Exclude deleted entries (soft delete not supported for audit logs)
   * - Return timestamped event data with clear event type context
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":auditLogId")
  public async at(
    @TypedParam("auditLogId")
    auditLogId: string & tags.Format<"uuid">,
  ): Promise<ITodoAuditLog> {
    try {
      return await getTodoAuditLogsAuditLogId({
        auditLogId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
