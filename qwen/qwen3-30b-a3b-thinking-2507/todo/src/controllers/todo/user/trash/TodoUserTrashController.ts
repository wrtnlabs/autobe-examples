import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageITodoTodo } from "../../../../api/structures/IPageITodoTodo";
import { ITodoTodo } from "../../../../api/structures/ITodoTodo";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { deleteTodoUserTrashTodoId } from "../../../../providers/deleteTodoUserTrashTodoId";
import { getTodoUserTrash } from "../../../../providers/getTodoUserTrash";
import { postTodoUserTrashTodoIdRestore } from "../../../../providers/postTodoUserTrashTodoIdRestore";

@Controller("/todo/user/trash")
export class TodoUserTrashController {
  /**
   * Retrieve a paginated list of soft-deleted todo items currently stored in the user's trash.
   *
   * This endpoint is part of the trash management system that allows users to view, restore, or permanently delete their previously deleted todo items. The response includes only the deleted todos that belong to the currently authenticated user, with proper data isolation enforced.
   *
   * Returned todos include essential details such as title, creation timestamp, deletion timestamp, and completion status. Pagination allows users to view all deleted items across multiple pages. This operation does not affect the database state directly; additional requests are needed for restore or deletion actions.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Query todo_todos table where deleted_at is not null and todo_user_id matches current authenticated user. Returns paginated list of todos in summary format with soft deletion metadata. Implements strict user data isolation by filtering on user ID.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async index(
    @UserAuth()
    user: UserPayload,
  ): Promise<IPageITodoTodo.ISummary> {
    try {
      return await getTodoUserTrash({
        user,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Restore a previously soft-deleted todo item from the trash back to the active todo list.
   *
   * This operation moves a todo item from trash (marking it as deleted) back to active state by setting deleted_at to null. Restored todos become visible in the main todo list and are no longer displayed in the trash.
   *
   * Only the original owner of the todo can perform this restore operation. The operation enforces strict user data isolation - trying to restore another user's todo will return 403 Forbidden.
   *
   * This operation is the counterpart to soft deletion (DELETE /todos/{id}), where the todo remains in database with deleted_at set. After restore, the todo will appear in the /todos list.
   *
   * @param connection
   * @param todoId ID of the soft-deleted todo to restore (UUID)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification 1. Verify todo exists and belongs to current authenticated user 2. Check deleted_at is not null (exists in trash) 3. Set deleted_at to null to mark as active 4. Update updated_at timestamp 5. Return restored ITodo entity 6. Ensure data isolation (user can't restore others' todos)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post(":todoId/restore")
  public async restore(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
  ): Promise<ITodoTodo> {
    try {
      return await postTodoUserTrashTodoIdRestore({
        user,
        todoId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Mark a todo item for deletion using soft delete mechanism. This operation updates the 'deleted_at' timestamp to archive the todo item without physically removing it from the database. The todo item is immediately excluded from active todo lists and moved to the trash viewing interface.
   *
   * The system enforces strict user ownership validation before performing deletion. Users can only delete their own todo items - attempting to delete another user's todo will return a 403 Forbidden response. After successful deletion, all related history entries remain accessible in the trash, allowing users to restore deleted items.
   *
   * This implementation uses the 'deleted_at' timestamp field which was specifically designed for soft delete operations as per the database schema. The timestamp is automatically set to the current moment when the delete operation is executed.
   *
   * @param connection
   * @param todoId The unique identifier of the todo item to delete (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Handler logic:
   * - Validate path parameter todoId as UUID
   * - Check if todo exists for current user via todo_user_id
   * - If not user's own todo, return 403 Forbidden
   * - If todo not found, return 404 Not Found
   * - If valid, set deleted_at = NOW()
   * - Save updated todo record
   * - Return 204 No Content with no body
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":todoId")
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoUserTrashTodoId({
        user,
        todoId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
