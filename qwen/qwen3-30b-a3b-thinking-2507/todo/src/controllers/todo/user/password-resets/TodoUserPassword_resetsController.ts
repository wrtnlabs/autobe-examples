import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { ITodoUser } from "../../../../api/structures/ITodoUser";
import { ITodoUserPasswordReset } from "../../../../api/structures/ITodoUserPasswordReset";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { getTodoUserPasswordResetsResetId } from "../../../../providers/getTodoUserPasswordResetsResetId";
import { patchTodoUserPasswordResets } from "../../../../providers/patchTodoUserPasswordResets";
import { postTodoUserPasswordResets } from "../../../../providers/postTodoUserPasswordResets";

@Controller("/todo/user/password-resets")
export class TodoUserPassword_resetsController {
  /**
   * Initiates the password reset process for a user account.
   *
   * This API operation begins the password reset workflow by accepting an email address. The system validates the email format, locates the corresponding user account, generates a secure password reset token with 60-minute expiration, and stores it in the password reset records table.
   *
   * The system automatically sends a password reset email containing the unique token to the user's registered email address. The token is generated using secure cryptographic methods and stored with a timestamp for expiration tracking.
   *
   * Password reset tokens are designed for single-use and expire after 60 minutes of creation to ensure security. The API returns a confirmation response immediately after initiating the process without exposing the token value.
   *
   * @param connection
   * @param body Email address for password reset initiation
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification 1. Validate email format
   * 2. Find user ID in todo_users table using provided email
   * 3. Generate unique token with 60-minute expiration (expires_at = current time + 60 minutes)
   * 4. Store token, user_id, expiration, and timestamp in todo_user_password_resets table
   * 5. Send email with reset link containing token
   * 6. Return confirmation response
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoUserPasswordReset.ICreate,
  ): Promise<ITodoUserPasswordReset> {
    try {
      return await postTodoUserPasswordResets({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Reset a user's password using a valid token from password reset workflow.
   *
   * This operation securely updates a user's password after validating the password reset token. The token must be valid and not expired (60-minute window), and the new password must meet security requirements.
   *
   * After successful password update, all active JWT sessions are invalidated to enhance security. The operation returns a summary of the user account without exposing password details.
   *
   * The system checks for token validity using the todo_user_password_resets table, which tracks password reset tokens along with their expiration timestamps.
   *
   * @param connection
   * @param body Password reset request containing token and new password
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification 1. Validates token against todo_user_password_resets
   * 2. Checks token expiration (60-minute limit)
   * 3. Updates user password using bcrypt (work factor 12)
   * 4. Invalidates all active sessions by clearing todo_user_sessions
   * 5. Deletes used password reset token record
   * 6. Returns summary of updated user profile
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async updatePassword(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoUserPasswordReset.IRequest,
  ): Promise<ITodoUser.ISummary> {
    try {
      return await patchTodoUserPasswordResets({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific password reset record.
   *
   * This operation provides access to the full record of a password reset request, including the reset token, expiration timestamp, and usage status. The password reset record is tied to a specific user and has a one-hour validity period.
   *
   * The endpoint is typically called during the password reset verification process to ensure the token is valid and not expired. A successful response contains the full record including details about the user account associated with the reset.
   *
   * Note: This operation requires authorization with the corresponding user's access rights. Only the user who requested the password reset may access their own reset records.
   *
   * @param connection
   * @param resetId The unique identifier of the password reset record
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Fetch the password reset record by its ID. Verify the record exists and belongs to the current user. Check if the token is expired (expires_at < current time) or already used (used_at is not null). Return the full record for verification or admin purposes.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":resetId")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("resetId")
    resetId: string & tags.Format<"uuid">,
  ): Promise<ITodoUserPasswordReset> {
    try {
      return await getTodoUserPasswordResetsResetId({
        user,
        resetId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
