import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { ITodoUserEmailVerification } from "../../../../../../../api/structures/ITodoUserEmailVerification";
import { UserAuth } from "../../../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../../../decorators/payload/UserPayload";
import { postTodoUserAuthUsersVerifyEmail } from "../../../../../../../providers/postTodoUserAuthUsersVerifyEmail";

@Controller("/todo/user/auth/users/verify/email")
export class TodoUserAuthUsersVerifyEmailController {
  /**
   * Validate and complete email verification for new user registrations. This operation processes the email verification token sent to new users during signup to confirm their email address.
   *
   * The token is validated against the todo_user_email_verifications table to ensure it exists, hasn't expired, and matches the intended user's registration. Upon successful validation, the token is marked as verified and the user's email is confirmed in the system. This enables full account activation without requiring additional email confirmation steps.
   *
   * Security: All operations are strictly scoped to the user account associated with the token. Failed validations return specific error messages without revealing token validity status to prevent enumeration attacks.
   *
   * Business rules: Token expiration is enforced at 15 minutes from creation. Only one active verification per email address is allowed. Already-verified tokens return specific error responses to prevent duplicate processing.
   *
   * @param connection
   * @param body Email verification token for validation
   * @x-autobe-specification Validate email verification token. Check token existence, expiration, and user association. If valid, mark token as verified and update user's email verification status in the database. Handle expired tokens, invalid tokens, and already-verified tokens with appropriate error responses. Update related user account status as verified upon successful validation.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async verifyEmail(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoUserEmailVerification.IVerify,
  ): Promise<void> {
    try {
      return await postTodoUserAuthUsersVerifyEmail({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
