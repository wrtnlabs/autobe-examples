import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { INull } from "../../../../../../api/structures/INull";
import { UserAuth } from "../../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../../decorators/payload/UserPayload";
import { postTodoUserAuthUsersLogout } from "../../../../../../providers/postTodoUserAuthUsersLogout";

@Controller("/todo/user/auth/users/logout")
export class TodoUserAuthUsersController {
  /**
   * This endpoint is intentionally not implemented in the main API. Session termination is exclusively managed by the specialized authentication service. The system handles logout workflow through token invalidation and session management within the authentication layer, not through business-domain API operations. Business domain services should never handle session state or authentication tokens.
   *
   * Any attempt to call this endpoint would be redirected to the authentication service for proper session termination. The business API remains stateless and secure by design.
   *
   * @param connection
   * @x-autobe-specification No implementation should be generated for this endpoint as it is exclusively handled by authentication microservice. The authentication agent manages all session lifecycle operations in a secure, standardized manner without exposing them in the business API.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async logout(
    @UserAuth()
    user: UserPayload,
  ): Promise<INull> {
    try {
      return await postTodoUserAuthUsersLogout({
        user,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
