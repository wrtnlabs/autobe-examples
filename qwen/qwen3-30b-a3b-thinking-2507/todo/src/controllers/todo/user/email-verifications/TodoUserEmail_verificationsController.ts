import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IPageITodoUserEmailVerification } from "../../../../api/structures/IPageITodoUserEmailVerification";
import { ITodoUserEmailVerification } from "../../../../api/structures/ITodoUserEmailVerification";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { getTodoUserEmailVerificationsVerificationId } from "../../../../providers/getTodoUserEmailVerificationsVerificationId";
import { patchTodoUserEmailVerifications } from "../../../../providers/patchTodoUserEmailVerifications";
import { postTodoUserEmailVerifications } from "../../../../providers/postTodoUserEmailVerifications";

@Controller("/todo/user/email-verifications")
export class TodoUserEmail_verificationsController {
  /**
   * Creates a new email verification token for user account activation.
   *
   * This operation is used after user account creation to generate verification tokens. The token is valid for exactly 15 minutes from creation. It connects to the user account via the provided user ID.
   *
   * The verification token is stored hashed for security. A verification email is automatically sent to the user's registered email address with the token for account activation.
   *
   * System automatically handles timestamping of creation and expiration. The token is required through the authentication flow to complete registration and activate user accounts.
   *
   * @param connection
   * @param body User ID for which to create email verification token
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Generate random token string hashed for storage. Set expires_at to 15 minutes from creation. Verify user_id exists in database. Create new todo_user_email_verifications record with generated token and timestamps. Send verification email using system email service.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoUserEmailVerification.ICreate,
  ): Promise<ITodoUserEmailVerification> {
    try {
      return await postTodoUserEmailVerifications({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a paginated list of email verification tokens associated with the currently authenticated user.
   *
   * This operation provides an interface for users to view their pending email verification tokens, which can be used for account registration and recovery processes. The system automatically handles token expiration (15-minute window) and marks tokens as expired in the database.
   *
   * The response includes detailed token information including expiration time, creation timestamp, and the associated user account. Pagination allows users to efficiently manage their verification tokens without loading excessive data.
   *
   * Note: This endpoint is restricted to authenticated users and returns only tokens belonging to the currently logged-in user, enforcing strict data isolation between users.
   *
   * @param connection
   * @param body Filter criteria and pagination parameters for email verification tokens
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Query todo_user_email_verifications table with filter conditions provided in request body. Apply authentication to restrict to currently logged-in user's email verifications. Handle pagination parameters (page, pageSize, sort, order) for large result sets. Ensure results are sorted by created_at descending by default. Return only active (non-deleted) verification tokens.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoUserEmailVerification.IRequest,
  ): Promise<IPageITodoUserEmailVerification.ISummary> {
    try {
      return await patchTodoUserEmailVerifications({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves the details of an email verification token used during user account registration.
   *
   * This operation fetches the verification token's metadata including associated email address, expiration timestamp, and creation time. The token expires after 15 minutes from the time of generation, as required by the service's account verification process.
   *
   * Security Note: The token value itself is redacted in the response to prevent security exposure. Only the email address, expiration time, and account status are returned to the client. This endpoint is designed to be called by the frontend during the account verification flow after the user clicks the verification link in their email.
   *
   * Relationship to Database: Directly maps to the todo_user_email_verifications Prisma model which stores all email verification tokens with their associated metadata and expiration constraints.
   *
   * @param connection
   * @param verificationId Verification token identifier
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Query the todo_user_email_verifications table for a specific verification record using the verificationId parameter. Verify the token's expiration status (15-minute window) and usage status before returning details. Ensure the email address matches the current authenticated user's account to prevent token reuse by unauthorized users. Return only minimal sensitive information (redacted token value) to prevent security exposure.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":verificationId")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("verificationId")
    verificationId: string,
  ): Promise<ITodoUserEmailVerification> {
    try {
      return await getTodoUserEmailVerificationsVerificationId({
        user,
        verificationId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
