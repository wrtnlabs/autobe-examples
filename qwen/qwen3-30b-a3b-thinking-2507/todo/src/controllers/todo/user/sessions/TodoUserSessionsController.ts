import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageITodoUserSession } from "../../../../api/structures/IPageITodoUserSession";
import { ITodoUserSession } from "../../../../api/structures/ITodoUserSession";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { getTodoUserSessionsSessionId } from "../../../../providers/getTodoUserSessionsSessionId";
import { patchTodoUserSessions } from "../../../../providers/patchTodoUserSessions";

@Controller("/todo/user/sessions")
export class TodoUserSessionsController {
  /**
   * Retrieve a paginated list of user sessions for the currently authenticated user.
   *
   * This operation provides detailed session information including IP addresses, original navigation URLs, and session expiration details. The response includes both active sessions (not yet expired) and expired sessions, allowing users to manage their login sessions across devices.
   *
   * Session data is structured with minimal payload to optimize bandwidth usage, featuring only essential session identifiers, creation timestamps, and expiration data. The list supports pagination and filtering by expiration status, making it suitable for user session management interfaces.
   *
   * Note: Session records are automatically filtered to show only entries associated with the currently authenticated user, maintaining strict data isolation between user accounts.
   *
   * @param connection
   * @param body Search criteria for session filtering
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Query todo_user_sessions table for sessions associated with current authenticated user. Implement pagination with default page size of 10. Apply request body filters to expired_at timestamp for active/expired sessions. Include IP, href, referrer details in session summaries. Ensure all sessions are scoped to current user via foreign key relationship. Return cursor-based pagination metadata.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoUserSession.IRequest,
  ): Promise<IPageITodoUserSession.ISummary> {
    try {
      return await patchTodoUserSessions({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific user session.
   *
   * This operation provides the complete session record including creation timestamp, expiration timestamp, IP address, and original reference URL. The response is filtered to show sessions owned by the authenticated user.
   *
   * Session data includes technical metadata such as IP addresses and referrer information, which can be used for security analytics and session management. The endpoint also validates whether the session is still active (not expired) before returning the complete session details.
   *
   * @param connection
   * @param sessionId Session ID from todo_user_sessions.id field
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Fetch session record by ID, verify user ownership, and check expiration status. Return fully populated session data for authorized user.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<ITodoUserSession> {
    try {
      return await getTodoUserSessionsSessionId({
        user,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
