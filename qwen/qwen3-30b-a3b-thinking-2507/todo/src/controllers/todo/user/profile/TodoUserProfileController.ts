import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { ITodoProfile } from "../../../../api/structures/ITodoProfile";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { getTodoUserProfile } from "../../../../providers/getTodoUserProfile";
import { putTodoUserProfile } from "../../../../providers/putTodoUserProfile";

@Controller("/todo/user/profile")
export class TodoUserProfileController {
  /**
   * Retrieve current authenticated user's profile details including display name and timestamps.
   *
   * This endpoint provides the complete profile information for the user making the request, including:
   * - Display name (1-20 character alphanumeric string)
   * - Creation timestamp
   * - Last update timestamp
   * - Soft delete timestamp (if applicable)
   *
   * The response includes all profile fields as defined in the database schema. Display names are strictly validated to 1-20 characters with no special characters as per business rules. Soft delete status is represented by the deleted_at timestamp.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Query todo_profiles table via authenticated user context (no path parameters). Return record with display_name (validated 1-20 chars), created_at, updated_at, deleted_at. Apply business rules: display_name should be returned as-is without modification. Handle soft delete status via deleted_at property (nullable).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @UserAuth()
    user: UserPayload,
  ): Promise<ITodoProfile> {
    try {
      return await getTodoUserProfile({
        user,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update the user's display name in their profile.
   *
   * This operation allows users to modify their display name with a maximum length of 20 characters. The system enforces strict user data isolation so that users can only modify their own profile information. All other profile fields remain read-only.
   *
   * The display name field must be between 1-20 characters in length. Attempts to set a name outside this range will return a 400 Bad Request with detailed validation errors. The operation enforces user ownership verification by comparing the current user's identity with the target profile's owner before proceeding with the update.
   *
   * @param connection
   * @param body Updated display name for user profile
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Update the user's display name in the todo_profiles table. Validate display name length (1-20 characters) against database constraint. Verify user ownership context in service layer. Return updated profile details. Ensure authentication context matches the profile user to prevent unauthorized access.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoProfile.IUpdate,
  ): Promise<ITodoProfile> {
    try {
      return await putTodoUserProfile({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
