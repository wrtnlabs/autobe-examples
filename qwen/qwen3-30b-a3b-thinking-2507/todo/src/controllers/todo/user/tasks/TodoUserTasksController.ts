import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia from "typia";
import { postTodoUserTasks } from "../../../../providers/postTodoUserTasks";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { patchTodoUserTasks } from "../../../../providers/patchTodoUserTasks";
import { getTodoUserTasksTaskCode } from "../../../../providers/getTodoUserTasksTaskCode";
import { putTodoUserTasksTaskCode } from "../../../../providers/putTodoUserTasksTaskCode";
import { deleteTodoUserTasksTaskCode } from "../../../../providers/deleteTodoUserTasksTaskCode";

import { ITodoTask } from "../../../../api/structures/ITodoTask";
import { IPageITodoTask } from "../../../../api/structures/IPageITodoTask";

@Controller("/todo/user/tasks")
export class TodoUserTasksController {
  /**
   * Create a new to-do item in the system. This endpoint allows authenticated
   * users to add new tasks to their to-do list. The task must include a title
   * and can optionally include initial completion status. The system
   * automatically sets the createdAt and updatedAt timestamps upon creation.
   *
   * The operation validates that the title is not empty and meets length
   * requirements. Security considerations include authentication verification
   * to ensure the user creating the task is authorized. The task is added to
   * the user's personal task list based on the authenticated user's context.
   *
   * This operation uses the todo_tasks database table, creating a new record
   * with the specified title and completion status. The created task is
   * returned immediately with all properties, including the system-generated ID
   * and timestamps. This endpoint serves the primary user workflow for task
   * creation in the todo application.
   *
   * @param connection
   * @param body Task creation data with title and completion status
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoTask.ICreate,
  ): Promise<ITodoTask> {
    try {
      return await postTodoUserTasks({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a filtered and paginated list of tasks from the system. This
   * operation uses the todo_tasks database table to provide advanced search
   * capabilities for tasks based on status, completion state, and date ranges,
   * while respecting user privacy for task ownership.
   *
   * The operation supports comprehensive pagination with configurable page
   * sizes, sorting options by creation date, priority, or due date, and complex
   * filtering including search terms and status ranges. Tasks can be sorted in
   * ascending or descending order for better user experience.
   *
   * Security considerations include automatic data separation based on user
   * ownership, ensuring users can only access their own tasks. The operation
   * incorporates business rules from the functional requirements, including
   * validation for incomplete task state transitions. This operation is crucial
   * for the core task management workflow as described in the functional
   * requirements documentation.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for task filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoTask.IRequest,
  ): Promise<IPageITodoTask.ISummary> {
    try {
      return await patchTodoUserTasks({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific task from the system. This
   * endpoint provides a single task's complete details, including title,
   * description, completion status, and audit timestamps from the Todo system's
   * database model.
   *
   * The taskCode parameter specifies the unique identifier for the requested
   * task, which is maintained as part of the system's primary task storage with
   * a global unique constraint. This endpoint is intended for authenticated
   * users to view their task details, with security ensuring users can only
   * access their own tasks through authorization flow.
   *
   * This operation does not require any request body and returns the full task
   * representation, which matches the database schema's field definitions. The
   * data provided is intended for user interface display and task management
   * workflows within the to-do application, with all timestamps automatically
   * populated from the database creation and update events.
   *
   * @param connection
   * @param taskCode Unique task identifier code (global scope)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":taskCode")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("taskCode")
    taskCode: string,
  ): Promise<ITodoTask> {
    try {
      return await getTodoUserTasksTaskCode({
        user,
        taskCode,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update a specific to-do task's details using its unique code identifier.
   * This operation modifies the task's title, description, completion status,
   * and related metadata within the core task management system. The target
   * task's code field serves as its global unique identifier, ensuring
   * unambiguous operation scope without needing to reference parent entities.
   *
   * Business rules require that only the owner can modify tasks, with
   * validation that title is non-empty and the status transitions follow
   * defined workflow constraints (active → in_progress → completed). The
   * operation automatically records updated_at timestamp via database triggers
   * without requiring client input.
   *
   * Implementation aligns with the todo_tasks database model's unique
   * constraints and field definitions. The endpoint supports only authenticated
   * users, with verification that the requesting user owns the task (handled in
   * service logic, not at endpoint level).
   *
   * @param connection
   * @param taskCode Unique business identifier code of the target task (global
   *   scope)
   * @param body Updated task details for partial or full modification of task
   *   attributes
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":taskCode")
  public async update(
    @UserAuth()
    user: UserPayload,
    @TypedParam("taskCode")
    taskCode: string,
    @TypedBody()
    body: ITodoTask.IUpdate,
  ): Promise<ITodoTask> {
    try {
      return await putTodoUserTasksTaskCode({
        user,
        taskCode,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently remove a user's task from the system. This operation targets
   * the TodoTasks table in the database schema and requires the task's unique
   * identifier for identification.
   *
   * The operation validates that the requesting user is the owner of the task
   * and that the task is not completed (isCompleted = false) before deletion.
   * Completed tasks (isCompleted = true) are not eligible for deletion via this
   * API operation. The task will be permanently removed from the database with
   * no possibility of recovery.
   *
   * Security considerations include user ownership verification and permission
   * checks to prevent accidental deletion by unauthorized users. The operation
   * does not return any data in the response body as it's a destructive
   * operation where a successful HTTP 204 response suffices to confirm
   * deletion. This approach aligns with RESTful design principles for safe
   * DELETE operations.
   *
   * @param connection
   * @param taskCode Unique business identifier code of the target task (global
   *   scope)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":taskCode")
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("taskCode")
    taskCode: string,
  ): Promise<void> {
    try {
      return await deleteTodoUserTasksTaskCode({
        user,
        taskCode,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
