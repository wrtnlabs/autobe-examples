import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageITodoTodo } from "../../../../api/structures/IPageITodoTodo";
import { ITodoTodo } from "../../../../api/structures/ITodoTodo";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { deleteTodoUserTodosTodoId } from "../../../../providers/deleteTodoUserTodosTodoId";
import { getTodoUserTodosTodoId } from "../../../../providers/getTodoUserTodosTodoId";
import { patchTodoUserTodos } from "../../../../providers/patchTodoUserTodos";
import { postTodoUserTodos } from "../../../../providers/postTodoUserTodos";
import { putTodoUserTodosTodoId } from "../../../../providers/putTodoUserTodosTodoId";

@Controller("/todo/user/todos")
export class TodoUserTodosController {
  /**
   * Create a new todo item for the authenticated user. This operation enables users to add new tasks to their personal todo list with minimum title requirements.
   *
   * The database schema requires a title (min 1 character) and supports optional description, start date, and due date fields. The system automatically sets is_completed to false on creation with appropriate timestamps.
   *
   * This operation follows the standard ITodoTodo.ICreate request body pattern. The response includes the full todo item with all fields set as they appear in the database schema. There is no external dependency on other API operations for this creation process.
   *
   * @param connection
   * @param body New todo item data
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification 1. Validate title length (min 1 character)
   * 2. If provided, validate start_date < due_date
   * 3. Create new todo record with:
   *    - user_id from authenticated session
   *    - title
   *    - optional description
   *    - optional start_date
   *    - optional due_date
   *    - is_completed = false
   *    - created_at = current timestamp
   *    - updated_at = current timestamp
   * 4. Return full todo record including is_completed and timestamps
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoTodo.ICreate,
  ): Promise<ITodoTodo> {
    try {
      return await postTodoUserTodos({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a filtered and paginated list of the user's todo items.
   *
   * This operation provides users with advanced filtering capabilities to manage their todo items efficiently. Users can view all todos, filter by completion status (all, complete, or incomplete), and sort their todo list by creation date, start date, or due date.
   *
   * The response includes a paginated list with essential information for each todo item. The API ensures strict data isolation, returning only the authenticated user's todos and preventing unauthorized access.
   *
   * Pagination defaults to 10 items per page, with configurable page sizes and sorting directions. Each summary item includes the title, completion status, creation date, and due date (if available), optimized for display in the user interface.
   *
   * @param connection
   * @param body Filter and pagination parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Query the 'todo_todos' table with conditions for completion status, use cursor-based pagination for the results, and order by specified field and direction. Implement filtering: status (all/completed/incomplete) and sorting (creation date, start date, due date). Return paginated results with total count and summary data.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoTodo.IRequest,
  ): Promise<IPageITodoTodo.ISummary> {
    try {
      return await patchTodoUserTodos({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single todo item by identifier, providing complete details including title, description, dates, and completion status.
   *
   * This endpoint enforces strict user data isolation, ensuring users can only access their own todo items. The operation automatically excludes soft-deleted items, returning a 404 Not Found response when an item is deleted or not found. Retrieved data includes all relevant fields such as start_date, due_date, and completion status with accurate timestamps.
   *
   * The implementation must verify ownership through the todo_user_id relationship and exclude items marked for deletion via the deleted_at timestamp to maintain data integrity and user privacy requirements.
   *
   * @param connection
   * @param todoId Unique identifier for the todo item
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Fetch the todo item by ID with user-data isolation (validate todo_user_id matches authenticated user). Ensure item is not soft-deleted (deleted_at = null). Return all fields from the todo_todos table including title, description, start_date, due_date, and is_completed. Handle 404 for missing or deleted items, 403 for accessing others' todos.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":todoId")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
  ): Promise<ITodoTodo> {
    try {
      return await getTodoUserTodosTodoId({
        user,
        todoId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update specific attributes of a user's todo item.
   *
   * This operation allows users to modify key attributes including title, description, start date, and due date for their own todo items. The title must be at least 1 character long and cannot be empty. Users cannot update the completion status or date fields (use separate toggle endpoint for completion).
   *
   * The operation enforces strict data isolation - it will reject requests attempting to modify another user's todo items with a 403 Forbidden response. All validation rules from the requirements document (including date validation) are applied.
   *
   * Required security context: User must be authenticated and own the todo item being updated. This API replaces the "edit" feature in user workflows.
   *
   * @param connection
   * @param todoId ID of the todo item to update (UUID format)
   * @param body Fields to update for the todo item
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification 1. Fetch todo by id and verify it belongs to authenticated user.
   * 2. Validate title (min 1 character, required).
   * 3. Update provided fields (title, description, start_date, due_date) while preserving others.
   * 4. Apply business rules: start_date must not exceed due_date.
   * 5. Save updated entity and return full object. Edge case: invalid todoId returns 404, ownership mismatch returns 403.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":todoId")
  public async update(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoTodo.IUpdate,
  ): Promise<ITodoTodo> {
    try {
      return await putTodoUserTodosTodoId({
        user,
        todoId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently soft-deletes a todo item owned by the current user.
   *
   * This operation marks a todo item as deleted by setting the deleted_at timestamp without physical removal from the database. The operation enforces strict user data isolation, ensuring a user can only delete their own todos. The response includes the updated todo entity with the deleted_at timestamp, allowing clients to confirm deletion state.
   *
   * The soft-delete mechanism implemented through the deleted_at field provides a recovery path through the trash management process. Deleted items are automatically excluded from active todo lists but can be restored from the trash interface.
   *
   * Note: Unlike hard deletion, this operation preserves historical context for audit purposes while maintaining application integrity.
   *
   * @param connection
   * @param todoId ID of the todo item to soft-delete
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification 1. Find todo by id matching current user's account.
   * 2. Verify user ownership to prevent cross-user deletions.
   * 3. Set deleted_at to current timestamp to mark as soft-deleted.
   * 4. Return the updated todo entity with deleted_at timestamp.
   * 5. Do not physically remove from database - maintain history for trash recovery.
   * 6. Enforce user isolation by matching user_id in todo_todos table.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":todoId")
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
  ): Promise<ITodoTodo> {
    try {
      return await deleteTodoUserTodosTodoId({
        user,
        todoId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
