import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageITodoHistory } from "../../../../../api/structures/IPageITodoHistory";
import { ITodoHistory } from "../../../../../api/structures/ITodoHistory";
import { UserAuth } from "../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../decorators/payload/UserPayload";
import { getTodoUserTodosTodoIdHistoriesHistoryId } from "../../../../../providers/getTodoUserTodosTodoIdHistoriesHistoryId";
import { patchTodoUserTodosTodoIdHistories } from "../../../../../providers/patchTodoUserTodosTodoIdHistories";

@Controller("/todo/user/todos/:todoId/histories")
export class TodoUserTodosHistoriesController {
  /**
   * Retrieve paginated edit history for a specific todo item.
   *
   * This operation provides detailed records of all modifications made to a particular todo, including timestamp, previous values, and new values for each edited field. The history includes all title, description, start date and due date changes.
   *
   * Supports chronological pagination with configurable page sizes. Returns only history entries for the current user's own todos, enforcing strict data isolation between users. Response includes minimal summary data for list display optimization.
   *
   * @param connection
   * @param todoId Target todo's ID (scoped to user's owned todos)
   * @param body Search criteria and pagination parameters for history records
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Query todo_histories table with pagination and filtering. Apply search filters on timestamp ranges, previous field values, and new field values. Ensure access control verifies current user owns the todo. Return cursor-based pagination with timestamp-based ordering for historical consistency.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoHistory.IRequest,
  ): Promise<IPageITodoHistory.ISummary> {
    try {
      return await patchTodoUserTodosTodoIdHistories({
        user,
        todoId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Get the specific history record for a user's todo item modification.
   *
   * @param connection
   * @param todoId The ID of the todo item being retrieved
   * @param historyId The ID of the specific history record being retrieved
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification 1. Verify user owns the specified todo (match todo_owner_id with current user ID)
   * 2. Fetch history record using both todoId and historyId parameters
   * 3. Validate both IDs exist and correspond to a valid history entry
   * 4. Include all history fields in result (prev_title, new_title, etc.)
   * 5. Return 404 if no match found
   * 6. Must not include raw database timestamps (use iso8601 formatted date strings in response)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":historyId")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
    @TypedParam("historyId")
    historyId: string & tags.Format<"uuid">,
  ): Promise<ITodoHistory> {
    try {
      return await getTodoUserTodosTodoIdHistoriesHistoryId({
        user,
        todoId,
        historyId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
