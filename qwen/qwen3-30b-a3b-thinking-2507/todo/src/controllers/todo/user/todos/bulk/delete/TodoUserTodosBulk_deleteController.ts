import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { ITodoTodo } from "../../../../../../api/structures/ITodoTodo";
import { UserAuth } from "../../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../../decorators/payload/UserPayload";
import { postTodoUserTodosBulkDelete } from "../../../../../../providers/postTodoUserTodosBulkDelete";

@Controller("/todo/user/todos/bulk/delete")
export class TodoUserTodosBulk_deleteController {
  /**
   * Permanently delete multiple to-do items from the user's account in a single operation. This endpoint requires a list of todo IDs which must belong exclusively to the authenticated user. The operation immediately removes the specified todos from the user's active list, clears them from the trash, and purges all associated edit history entries from the system.
   *
   * Security protocol dictates that each todo ID must be validated against the user's account ownership before deletion. The service logs each deletion action for audit purposes without exposing sensitive details in the response. This operation is irreversible - deleted items cannot be recovered.
   *
   * Permanent deletion (removing records from the database) differs from standard soft deletion (moving to trash). This endpoint should only be used when the user intends to permanently remove todos, typically after explicitly confirming through a user interface.
   *
   * @param connection
   * @param body List of todo IDs to permanently delete
   * @x-autobe-specification Confirm user ownership for all todo IDs in request. Perform bulk permanent deletion by marking todos as deleted in database (removing entries from database), and purge associated edit history from todo_histories table. Count and return successful deletions. Validate input: max 50 IDs per request, all IDs must exist, and belong to the current user.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoTodo.IRequest,
  ): Promise<void> {
    try {
      return await postTodoUserTodosBulkDelete({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
