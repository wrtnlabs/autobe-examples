import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchTodoUserUsersUserIdSessions } from "../../../../../providers/patchTodoUserUsersUserIdSessions";
import { UserAuth } from "../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../decorators/payload/UserPayload";
import { getTodoUserUsersUserIdSessionsSessionId } from "../../../../../providers/getTodoUserUsersUserIdSessionsSessionId";

import { IPageITodoUserSession } from "../../../../../api/structures/IPageITodoUserSession";
import { ITodoUserSession } from "../../../../../api/structures/ITodoUserSession";

@Controller("/todo/user/users/:userId/sessions")
export class TodoUserUsersSessionsController {
  /**
   * Retrieves a paginated list of authentication sessions associated with the
   * specified user. This operation fetches session records from the
   * todo_user_sessions table, which tracks active login states and token
   * validity for user authentication. The session data includes session ID,
   * login timestamp, device information, and session status, providing a
   * comprehensive view of a user's active sessions. The userId parameter
   * identifies the target user via foreign key relationship to the todo_users
   * table, ensuring session data is scoped to the correct account. Pagination
   * parameters allow for efficient retrieval of recent sessions with
   * configurable limit and offset.
   *
   * Security considerations include strict access control where only the
   * authenticated user can view their own session history, preventing access to
   * other users' session data. Session records are treated as user-specific
   * personal data requiring appropriate privacy controls. The operation aligns
   * with the todo_user_sessions database table schema which defines the session
   * relationships without using soft delete, eliminating need for special
   * handling in the operation logic.
   *
   * This endpoint serves user interface needs for session management, allowing
   * users to view and potentially revoke active sessions. The database schema
   * validation confirms presence of userId foreign key reference and all
   * relevant session fields without assuming additional unverified fields.
   *
   * @param connection
   * @param userId Unique identifier of the target user (UUID)
   * @param body Pagination and search parameters for session filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string,
    @TypedBody()
    body: ITodoUserSession.IRequest,
  ): Promise<IPageITodoUserSession.ISummary> {
    try {
      return await patchTodoUserUsersUserIdSessions({
        user,
        userId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific authentication session associated with a user account.
   * This operation provides detailed session information including login
   * timestamp, device information, and session validity without sensitive
   * authentication tokens. The session data is directly mapped from the
   * todo_user_sessions database entity, which contains serialized
   * authentication details tightly coupled with the user's account.
   *
   * Security: Access is strictly restricted to the account owner. Session data
   * is masked to prevent authentication token exposure while preserving
   * necessary operational context. This endpoint implements proper ownership
   * verification during authorization checks to prevent session bleeding
   * between users.
   *
   * Integration: This operation serves as the backend substrate for session
   * management features in the user interface including active session
   * monitoring, session revocation UI components, and device management tools.
   * The response format aligns with other entity retrieval endpoints for
   * consistency.
   *
   * @param connection
   * @param userId Unique identifier of the target user
   * @param sessionId Unique identifier of the target session
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<ITodoUserSession> {
    try {
      return await getTodoUserUsersUserIdSessionsSessionId({
        user,
        userId,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
