import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { ITodoUser } from "../../../../api/structures/ITodoUser";
import { postTodoAuthUserJoin } from "../../../../providers/postTodoAuthUserJoin";
import { postTodoAuthUserLogin } from "../../../../providers/postTodoAuthUserLogin";
import { postTodoAuthUserRefresh } from "../../../../providers/postTodoAuthUserRefresh";

@Controller("/todo/auth/user")
export class TodoAuthUserController {
  /**
   * Performs user registration by creating a new account with the provided credentials.
   *
   * This operation validates the email format and password strength. If the email is already registered, it returns a 409 Conflict response.
   *
   * The system stores encrypted password in the database using bcrypt algorithm, sets email_verified_at to null, and creates a pending verification entry in the email verification table.
   *
   * After successful creation, the user is required to verify their email before using the service. The registration process does not allow the user to set a display name at signup - that is part of user profile management.
   *
   * The response includes the newly created user identifier and a verification token for email verification flow.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body User registration information including email and password.
   * @x-autobe-specification User registration process. Creates a new user account, hashes the password, stores in database, and sets email verification status to pending. Generates a random verification token and stores it in todo_user_email_verifications. Sends verification email through email service.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoUser.IJoin,
  ): Promise<ITodoUser.IAuthorized> {
    try {
      return await postTodoAuthUserJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticates an existing user with their credentials.
   *
   * This operation verifies the email and password combinations against the database records. If the email is not found or the password is incorrect, it returns a 401 Unauthorized response.
   *
   * Upon successful authentication, the system generates a JWT access token with 15-minute expiration and refresh token with 7-day expiration. The refresh token is stored in the database to support session management and logout functionality.
   *
   * The email verification status is checked during authentication. If the email is not verified, the user will not be allowed to log in, and a message will be returned indicating the account needs verification.
   *
   * The response includes the access token, refresh token, and the user's authorized profile, which can be used to fetch profile data.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body User authentication credentials including email and password.
   * @x-autobe-specification User authentication process. Validates credentials against stored hashed password, creates a JWT access token valid for 15 minutes, and creates a refresh token valid for 7 days. Stores session details in todo_user_sessions table.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoUser.ILogin,
  ): Promise<ITodoUser.IAuthorized> {
    try {
      return await postTodoAuthUserLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Renews the user's access token using their valid refresh token.
   *
   * This operation verifies the refresh token's validity and expiration. If the refresh token is invalid or expired, it returns a 401 Unauthorized response.
   *
   * Upon successful refresh, the system generates a new access token with 15-minute expiration and a new refresh token with 7-day expiration. The old refresh token is invalidated from the session store, and the new token is stored for future refresh operations.
   *
   * This operation does not require re-authentication with credentials, but the user must still have a valid session. If the user has changed their password or logged out, refresh operations will be invalidated.
   *
   * The response includes the new access token, new refresh token, and user's authorized identity data, allowing the user to continue using the application with updated tokens.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token information to renew access tokens.
   * @x-autobe-specification Token refresh process. Validates the refresh token, replaces the access token with a new one, and refreshes the session expiration. Invalidates the old refresh token and generates a new one.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: ITodoUser.IRefresh,
  ): Promise<ITodoUser.IAuthorized> {
    try {
      return await postTodoAuthUserRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
