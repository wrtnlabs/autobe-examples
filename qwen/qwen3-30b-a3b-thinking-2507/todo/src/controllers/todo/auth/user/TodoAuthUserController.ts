import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { ITodoUser } from "../../../../api/structures/ITodoUser";
import { postTodoAuthUserJoin } from "../../../../providers/postTodoAuthUserJoin";
import { postTodoAuthUserLogin } from "../../../../providers/postTodoAuthUserLogin";
import { postTodoAuthUserRefresh } from "../../../../providers/postTodoAuthUserRefresh";

@Controller("/todo/auth/user")
export class TodoAuthUserController {
  /**
   * User registration endpoint that creates a new account with email and password. Requires email address and password with minimum 8 characters including one uppercase letter and one special character for strong password enforcement.
   *
   * The registration process includes sending a verification email with a 15-minute expiration time as part of system requirements, ensuring users can confirm their email before account activation.
   *
   * The system must validate all input, including email format (using regex pattern for valid business domain emails), and apply bcrypt hashing to passwords with a work factor of 12 as specified in security requirements.
   *
   * After successful registration, the system creates a user record in the database, stores the email address (validated against system's email format requirements), and sets up the user's initial password hash. The verification process is designed to meet security requirements and prevent fake accounts.
   *
   * This operation strictly follows the authorizationType 'join' and uses the required ITodoUser.IJoin type for request body and ITodoUser.IAuthorized for response.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body User registration request containing the user's email address and password for creating a new account in the system. Validation rules include email format, password complexity requirements, and system-specific security constraints.
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor user
   * @x-autobe-specification In the service implementation:
   * 1. Validate email format and password complexity
   * 2. Check if email is already registered
   * 3. Hash password with bcrypt (work factor 12)
   * 4. Create user record in database
   * 5. Send verification email with 15-minute expiration
   * 6. Return token response with access and refresh tokens
   *
   * Validation rules:
   * - Email must be a valid business email (non-personal domains)
   * - Password must be 8+ characters with 1 uppercase, 1 special character
   * - No duplicate emails allowed
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoUser.IJoin,
  ): Promise<ITodoUser.IAuthorized> {
    try {
      return await postTodoAuthUserJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Login endpoint that authenticates users with their email and password credentials. Validates user credentials against the user store and handles authentication failures according to security requirements.
   *
   * Handles authentication failures according to specified rules: if authentication fails after 5 attempts, account is locked for 30 minutes. After successful authentication, a JWT token with 2-hour lifespan is returned to the client.
   *
   * The system processes the request by comparing the provided password with the stored bcrypt hash, ensuring strong security practices. Password validation occurs in the same way as registration with the same complexity requirements.
   *
   * This operation strictly follows the authorizationType 'login' and uses the required ITodoUser.ILogin type for request body and ITodoUser.IAuthorized for response.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body User login request containing email address and the password for authentication against the user store. The password must meet complexity requirements to match registration standards.
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor user
   * @x-autobe-specification In the service implementation:
   * 1. Validate input data (email and password)
   * 2. Check account status (locked or active)
   * 3. Hash provided password for comparison with stored hash
   * 4. Compare against stored bcrypt hash
   * 5. Generate authentication tokens with 2-hour access time
   * 6. Update authentication record with new token
   * 7. Return response with access token details
   *
   * Validation rules:
   * - Email must be in valid format
   * - Password must meet complexity requirements
   * - Account status checks before authentication
   * - Maximum 5 failed login attempts before locking
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoUser.ILogin,
  ): Promise<ITodoUser.IAuthorized> {
    try {
      return await postTodoAuthUserLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Token refresh endpoint that generates new access tokens using a valid refresh token. This operation does not require user credentials but validates the refresh token against the user's session data.
   *
   * The system manages token rotation by generating a new access token when a refresh token is valid, maintaining session continuity while ensuring security. After each successful refresh operation, the system invalidates the previous refresh token to maintain token rotation security.
   *
   * This operation strictly follows the authorizationType 'refresh' and uses the required ITodoUser.IRefresh type for request body and ITodoUser.IAuthorized for response.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Token refresh request containing the existing refresh token that will be used to generate a new access token. The system validates the refresh token and ensures it belongs to the current user session.
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor user
   * @x-autobe-specification In the service implementation:
   * 1. Validate refresh token
   * 2. Check token expiration
   * 3. Ensure token is associated with current user
   * 4. Generate fresh access token
   * 5. Create new refresh token
   * 6. Store new token records
   * 7. Invalidate previous refresh token
   * 8. Return new token response
   *
   * Validation rules:
   * - Refresh token must be valid
   * - Must belong to current user session
   * - Must not be expired
   * - Previous refresh token must be invalidated after new one is generated
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: ITodoUser.IRefresh,
  ): Promise<ITodoUser.IAuthorized> {
    try {
      return await postTodoAuthUserRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
