import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IPageITodoAppTodo } from "../../../../api/structures/IPageITodoAppTodo";
import { ITodoAppTodo } from "../../../../api/structures/ITodoAppTodo";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { patchTodoAppUserTrash } from "../../../../providers/patchTodoAppUserTrash";

@Controller("/todoApp/user/trash")
export class TodoappUserTrashController {
  /**
   * Retrieve a paginated list of soft-deleted todos in the trash.
   *
   * This operation provides users with access to their deleted todos that are stored in the trash. The trash view displays all soft-deleted todos for the current user, with the same fields as the main todo list: title, completion status, start date, due date, and creation date.
   *
   * Users can filter the trash items by completion status (all, complete, incomplete) or paginate through results. The endpoint is essential for managing deleted todos, allowing users to restore or permanently delete items from their trash.
   *
   * All todos shown in the trash are owned by the authenticated user, with strict isolation enforced via the authentication system. The system will never return todos belonging to other users.
   *
   * @param connection
   * @param body Pagination and filtering parameters for trash todos
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Query the todo_app_todos table where deleted_at is not null, filtered by current user ID from authentication. Implement cursor-based pagination with default page 1, limit 10. Support filtering by completion status (all, complete, incomplete). Return todos with title, status, start_date, due_date, and creation_date fields. The response should include pagination metadata (total count, current page, page size).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoAppTodo.IRequest,
  ): Promise<IPageITodoAppTodo.ISummary> {
    try {
      return await patchTodoAppUserTrash({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
