import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageITodoAppUserSession } from "../../../../api/structures/IPageITodoAppUserSession";
import { ITodoAppUserSession } from "../../../../api/structures/ITodoAppUserSession";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { getTodoAppUserSessionsSessionId } from "../../../../providers/getTodoAppUserSessionsSessionId";
import { patchTodoAppUserSessions } from "../../../../providers/patchTodoAppUserSessions";

@Controller("/todoApp/user/sessions")
export class TodoappUserSessionsController {
  /**
   * Retrieve a paginated list of active and expired user sessions associated with the current user.
   *
   * This operation provides comprehensive session management capabilities, allowing users to view all active sessions including device information, location details, and session duration. Each session entry includes the IP address used during login, current URL, and referrer information for security auditing.
   *
   * The response supports filtering by IP address patterns, session creation timestamps, and expiration dates. Session management features enable users to identify and terminate sessions from unfamiliar devices, enhancing account security.
   *
   * @param connection
   * @param body Session listing criteria with filters and pagination parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Query todo_app_user_sessions table with filtering and pagination. Key fields: ip, href, referrer, created_at, expired_at. Support time-based range filters (creation date, expiration date), IP pattern matching, and session status (active vs expired). Apply filtering to current user's sessions via user_id from authentication context. Return paginated results using cursor-based pagination for scalability.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoAppUserSession.IRequest,
  ): Promise<IPageITodoAppUserSession.ISummary> {
    try {
      return await patchTodoAppUserSessions({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific user session.
   *
   * This endpoint provides comprehensive details about a user's active session, including the associated user's IP address, current URL, referrer URL, and session timestamps.
   *
   * The session details returned include:
   *
   * - Session identifier (UUID)
   * - IP address used for session initialization
   * - Current URL of the session
   * - Referrer URL that initiated the session
   * - Session creation timestamp
   * - Session expiration timestamp
   *
   * Responses for session details are always scoped to the authenticated user's own sessions. Any attempt to access another user's session results in '404 Not Found'.
   *
   * @param connection
   * @param sessionId The unique identifier for the active session
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Fetch session record from todo_app_user_sessions table using provided sessionId. Verify session belongs to the authenticated user. Return fields: id, ip, href, referrer, created_at, expired_at. Exclude sensitive tokens. Use explicit user relation for ownership checking.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppUserSession> {
    try {
      return await getTodoAppUserSessionsSessionId({
        user,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
