import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { ITodoAppUser } from "../../../../api/structures/ITodoAppUser";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { getTodoAppUserProfile } from "../../../../providers/getTodoAppUserProfile";
import { putTodoAppUserProfile } from "../../../../providers/putTodoAppUserProfile";

@Controller("/todoApp/user/profile")
export class TodoappUserProfileController {
  /**
   * Retrieve the current user's profile display name which is visible only to the owner.
   *
   * This API operation provides the user's customizable display name, accessible only to the authenticated user. The display name must not exceed 50 characters per privacy controls and must be alphanumeric with spaces.
   *
   * The endpoint implements mandatory ownership verification to ensure users can only access their own profile data. No other user data such as email address, account creation dates, or historical data is exposed in the response.
   *
   * Profile access is restricted to authenticated users only. Any request to access another user's profile results in immediate 403 Forbidden response without any profile data leakage.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Retrieve the currently authenticated user's display name from the database. Implement strict user ownership verification using JWT claims. Return NULL for display_name if not set. Never fetch or include any other user data. Log access attempt for audit purposes.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @UserAuth()
    user: UserPayload,
  ): Promise<ITodoAppUser.ISummary> {
    try {
      return await getTodoAppUserProfile({
        user,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update the current user's display name.
   *
   * This operation allows authenticated users to change their display name within the specified constraints. The display name can contain alphanumeric characters and spaces (no special characters), with a maximum length of 30 characters. All other user profile fields remain unchanged.
   *
   * The operation enforces strict user data isolation - users can only modify their own profile, never another user's profile. Any attempt to access another user's profile will return 403 Forbidden.
   *
   * Updated display name is stored immediately in the database, and the full updated user profile is returned in the response for direct UI update.
   *
   * @param connection
   * @param body Updated display name (1-30 characters, alphanumeric + spaces)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Update user display name in database with validation. Ensure only current user's display name can be updated (no cross-user access). Verify display name length (1-30 characters) and format (alphanumeric + spaces only) before updating. Update database record immediately without affecting other fields. Return full user object with updated display name. Log profile update event for audit purposes.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoAppUser.IUpdate,
  ): Promise<ITodoAppUser> {
    try {
      return await putTodoAppUserProfile({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
