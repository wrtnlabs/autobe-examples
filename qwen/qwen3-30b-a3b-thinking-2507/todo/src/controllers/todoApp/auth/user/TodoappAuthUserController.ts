import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { ITodoAppUser } from "../../../../api/structures/ITodoAppUser";
import { postTodoAppAuthUserJoin } from "../../../../providers/postTodoAppAuthUserJoin";
import { postTodoAppAuthUserLogin } from "../../../../providers/postTodoAppAuthUserLogin";
import { postTodoAppAuthUserRefresh } from "../../../../providers/postTodoAppAuthUserRefresh";

@Controller("/todoApp/auth/user")
export class TodoappAuthUserController {
  /**
   * This endpoint creates a new user account in the system. The request requires a valid email address formatted as per standard email policies and a password meeting the minimum length requirement of 12 characters. The system validates the email format, checks password strength, securely hashes the password using industry-standard algorithms, and establishes a new user record with a pending verification status.
   *
   * The user's display name is set to the email username (e.g., 'johnsmith' from 'johnsmith@example.com'). A welcome email with account confirmation instructions is sent to the provided email address. Upon successful account creation, the system returns JWT access and refresh tokens for authentication. The user must complete email verification before gaining full access to application features.
   *
   * This implementation ensures all security requirements are met including password hashing, email verification, and secure token generation. The operation complies with privacy requirements by restricting personal data access to the user themselves.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body User registration details with email and password
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Create new user account with email, password, and default display name. Securely hash password, send welcome email, set verification status to 'pending', and generate JWT access/refresh tokens. Validate email format and password requirements before account creation.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoAppUser.IJoin,
  ): Promise<ITodoAppUser.IAuthorized> {
    try {
      return await postTodoAppAuthUserJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This endpoint authenticates users by validating their credentials against the database. The request requires a valid email address and matching password to verify user identity. The system checks for active account status and email verification completion before granting access.
   *
   * Upon successful validation, the system generates an access token with a standard expiration period and a refresh token with extended validity. The access token contains user ID and basic role information for authorization. The refresh token allows for token renewal without requiring user re-authentication.
   *
   * Security considerations include preventing brute-force attacks through rate limiting and using secure token storage practices. The operation ensures all authentication activities are logged for audit purposes, and previous sessions are invalidated when a new session is created. The operation strictly follows the privacy requirements by ensuring credentials are never stored or transmitted in plaintext.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body User login credentials with email and password
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Validate user credentials and generate JWT tokens for authenticated sessions. Check email/password against database records, verify account status, and generate both access and refresh tokens. Enforce session management rules and token rotation.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoAppUser.ILogin,
  ): Promise<ITodoAppUser.IAuthorized> {
    try {
      return await postTodoAppAuthUserLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This endpoint refreshes the access token using a valid refresh token previously issued to the user. The request validates the refresh token against the database record to ensure it has not expired or been revoked. The system checks for active user session status and validates the token against the user's current session.
   *
   * If valid, the system generates a new access token with extended expiration and keeps the refresh token unchanged for future use. This operation enables seamless user experience without requiring re-login while maintaining security through short-lived access tokens.
   *
   * The refresh process maintains all security protocols including token rotation, session management, and audit logging. The operation complies with privacy requirements by ensuring no personal data is exposed during token refresh. The refresh token remains stored securely on the client side, and the system enforces refresh token expiration policies to prevent abuse.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token for token renewal
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Generate new access token using a valid refresh token. Verify refresh token validity, check session status, create new access token with updated expiration, and maintain session continuity without requiring user re-authentication.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: ITodoAppUser.IRefresh,
  ): Promise<ITodoAppUser.IAuthorized> {
    try {
      return await postTodoAppAuthUserRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
