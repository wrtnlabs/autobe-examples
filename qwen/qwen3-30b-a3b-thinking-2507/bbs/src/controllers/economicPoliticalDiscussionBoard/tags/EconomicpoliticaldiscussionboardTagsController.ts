import { IEconomicPoliticalDiscussionBoardTag } from "../../../api/structures/IEconomicPoliticalDiscussionBoardTag";
import { IPageIEconomicPoliticalDiscussionBoardTag } from "../../../api/structures/IPageIEconomicPoliticalDiscussionBoardTag";
