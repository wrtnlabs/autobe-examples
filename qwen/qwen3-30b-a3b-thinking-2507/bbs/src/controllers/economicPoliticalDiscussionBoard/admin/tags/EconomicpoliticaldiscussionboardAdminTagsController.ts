import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEconomicPoliticalDiscussionBoardTag } from "../../../../api/structures/IEconomicPoliticalDiscussionBoardTag";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { deleteEconomicPoliticalDiscussionBoardAdminTagsTagId } from "../../../../providers/deleteEconomicPoliticalDiscussionBoardAdminTagsTagId";
import { postEconomicPoliticalDiscussionBoardAdminTags } from "../../../../providers/postEconomicPoliticalDiscussionBoardAdminTags";
import { putEconomicPoliticalDiscussionBoardAdminTagsTagId } from "../../../../providers/putEconomicPoliticalDiscussionBoardAdminTagsTagId";

@Controller("/economicPoliticalDiscussionBoard/admin/tags")
export class EconomicpoliticaldiscussionboardAdminTagsController {
  /**
   * Create a new tag for article categorization across economic and political topics.
   *
   * This operation enables users to define custom tags for content organization. The system validates tag uniqueness before creation, ensuring tags can be reliably used for filtering and search functionality.
   *
   * The tag name must be unique across the entire system. Existing tags cannot have the same name in any case. This uniqueness constraint directly impacts search and filtering results (07-search-and-filtering.md).
   *
   * Successful creation returns the new tag's full details, including ID and timestamps for reference in subsequent operations.
   *
   * @param connection
   * @param body Tag creation details
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification 1. Verify tag name doesn't exist (case-insensitive comparison)
   * 2. Validate name meets minimal length requirement (2+ characters)
   * 3. If valid, create new tag record with current timestamps
   * 4. Return created tag with generated ID and timestamps
   * 5. Enforce uniqueness constraint at database level
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IEconomicPoliticalDiscussionBoardTag.ICreate,
  ): Promise<IEconomicPoliticalDiscussionBoardTag> {
    try {
      return await postEconomicPoliticalDiscussionBoardAdminTags({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing tag's name in the economic/political discussion platform.
   *
   * This operation modifies the name of a tag used for article categorization, ensuring the new name remains unique across all tags. The system automatically updates the last modification timestamp to reflect the change.
   *
   * The operation supports only the name field; other tag properties (creation date, deletion status) are system-managed and not modifiable through this endpoint.
   *
   * Authorization requires admin role. The current admin user must be identified as the actor making the change.
   *
   * @param connection
   * @param tagId The unique identifier of the tag to be updated
   * @param body New tag name (must be unique)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification 1. Verify tag exists and is not deleted
   * 2. Validate new name is unique and not empty
   * 3. Check authorization: only admin can update tags
   * 4. Update the 'name' field in the database
   * 5. Record updated_at timestamp
   * 6. Return full tag object with updated values
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":tagId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("tagId")
    tagId: string,
    @TypedBody()
    body: IEconomicPoliticalDiscussionBoardTag.IUpdate,
  ): Promise<IEconomicPoliticalDiscussionBoardTag> {
    try {
      return await putEconomicPoliticalDiscussionBoardAdminTagsTagId({
        admin,
        tagId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Mark a tag as deleted using soft delete mechanism with the `deleted_at` timestamp.
   *
   * This operation is used to remove a tag from active use while preserving historical data, enabling recovery if needed. Admins and content managers have permission to delete tags.
   *
   * Deleting a tag marks the record as deleted without removing it from the database, allowing audit trails and preventing accidental data loss. The `deleted_at` timestamp indicates when the tag was soft-deleted.
   *
   * Note: Associated article tags will remain linked to the deleted tag, though the tag itself will no longer be selectable in content creation.
   *
   * @param connection
   * @param tagId Unique identifier for the tag
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification 1. Verify tag with given ID exists in the database.
   * 2. Check that the current user has admin role (using authorization middleware).
   * 3. Set deleted_at timestamp to current time.
   * 4. Return the updated tag record including all fields.
   * 5. Log the deletion action to audit logs for admin oversight.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":tagId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("tagId")
    tagId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteEconomicPoliticalDiscussionBoardAdminTagsTagId({
        admin,
        tagId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
