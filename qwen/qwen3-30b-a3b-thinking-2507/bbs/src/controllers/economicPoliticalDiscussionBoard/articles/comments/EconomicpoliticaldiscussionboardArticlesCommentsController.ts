import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEconomicPoliticalDiscussionBoardComment } from "../../../../api/structures/IEconomicPoliticalDiscussionBoardComment";
import { IPageIEconomicPoliticalDiscussionBoardComment } from "../../../../api/structures/IPageIEconomicPoliticalDiscussionBoardComment";
import { getEconomicPoliticalDiscussionBoardArticlesArticleIdCommentsCommentId } from "../../../../providers/getEconomicPoliticalDiscussionBoardArticlesArticleIdCommentsCommentId";
import { patchEconomicPoliticalDiscussionBoardArticlesArticleIdComments } from "../../../../providers/patchEconomicPoliticalDiscussionBoardArticlesArticleIdComments";

@Controller("/economicPoliticalDiscussionBoard/articles/:articleId/comments")
export class EconomicpoliticaldiscussionboardArticlesCommentsController {
  /**
   * Retrieve paginated list of comments for a specific article. This operation supports filtering by comment content and sorting by chronological order.
   *
   * The response includes comments sorted from oldest to newest, with each comment showing the author's display name (via linked profile), content, and timestamp. Pagination handles 15 comments per page.
   *
   * Access requires authenticated user (role: guest, user, or admin). Guest users can view public comments, while user/admin roles can also access their own comments for editing/deletion. All comment content is filtered for profanity before display.
   *
   * @param connection
   * @param articleId Unique identifier for the article whose comments are being listed
   * @param body Pagination, sorting, and search parameters for comments listing
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query economic_political_discussion_board_comments table with:
   * - Article ID from path parameter
   * - Pagination (15 items/page max)
   * - Sorting by createdAt (oldest first)
   * - Optional text search in content
   * Return cursor-based pagination with cursor and data array.
   * Validates comment content length (10-500 chars) before query.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEconomicPoliticalDiscussionBoardComment.IRequest,
  ): Promise<IPageIEconomicPoliticalDiscussionBoardComment.ISummary> {
    try {
      return await patchEconomicPoliticalDiscussionBoardArticlesArticleIdComments(
        {
          articleId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific comment from a public article with full content and metadata.
   *
   * This operation provides detailed information about a single comment on an article. The comment's content (10-500 characters), associated author, and timestamp data are returned to enable full view of the discussion.
   *
   * The response includes all comment fields as defined in the database schema, including creation and update timestamps, ensuring developers have complete context about comment history and ownership. Public access is granted to all comments without authentication requirements.
   *
   * @param connection
   * @param articleId Unique article identifier
   * @param commentId Unique comment identifier
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Fetch comment by articleId and commentId, validating both identifiers exist. Check if comment is soft-deleted (deleted_at is set) and return 404 if so. Join with articles and users tables to include all comment fields. Handle edge cases - non-existent IDs return 404, invalid UUIDs return 400.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":commentId")
  public async at(
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
  ): Promise<IEconomicPoliticalDiscussionBoardComment> {
    try {
      return await getEconomicPoliticalDiscussionBoardArticlesArticleIdCommentsCommentId(
        {
          articleId,
          commentId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
