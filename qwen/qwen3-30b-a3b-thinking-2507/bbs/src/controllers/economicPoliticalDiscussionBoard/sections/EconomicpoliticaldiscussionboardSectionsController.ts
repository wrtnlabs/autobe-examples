import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEconomicPoliticalDiscussionBoardSection } from "../../../api/structures/IEconomicPoliticalDiscussionBoardSection";
import { IPageIEconomicPoliticalDiscussionBoardSection } from "../../../api/structures/IPageIEconomicPoliticalDiscussionBoardSection";
import { getEconomicPoliticalDiscussionBoardSectionsId } from "../../../providers/getEconomicPoliticalDiscussionBoardSectionsId";
import { patchEconomicPoliticalDiscussionBoardSections } from "../../../providers/patchEconomicPoliticalDiscussionBoardSections";

@Controller("/economicPoliticalDiscussionBoard/sections")
export class EconomicpoliticaldiscussionboardSectionsController {
  /**
   * Retrieve a paginated list of all accessible sections.
   *
   * This operation provides a public view of all sections available for article categorization.
   *
   * Supports filtering by section name and description, with pagination for large section lists. Each section entry includes the section name, description, and article count for users to understand topic coverage.
   *
   * Results are sorted alphabetically by section name with pagination configured for 20 items per page. The endpoint is accessible to all users regardless of authentication status.
   *
   * @param connection
   * @param body Filtering and pagination parameters for sections
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query sections table with pagination and filtering.
   * - Apply filters on section name and description
   * - Support cursor-based pagination (page, limit)
   * - Include article count per section in summary
   * - Return sorted results by name (alphabetical)
   * - Implement pagination without offset limitation
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IEconomicPoliticalDiscussionBoardSection.IRequest,
  ): Promise<IPageIEconomicPoliticalDiscussionBoardSection.ISummary> {
    try {
      return await patchEconomicPoliticalDiscussionBoardSections({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information for a specific section in the economic and political discussion platform.
   *
   * This endpoint allows users to view the complete metadata of any section, including its name and descriptive overview. Sections serve as organizational categories for economic and political articles, enabling users to navigate content by topic through the platform's categorized sections.
   *
   * The API returns a detailed representation of the requested section, including its display name and description, without requiring authentication. The response includes only active sections (those not marked for deletion via the deleted_at timestamp).
   *
   * @param connection
   * @param id Unique identifier for the section
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Fetch section record from database using section ID parameter. Check for existence and visibility (deleted_at not set). Return complete section details including name and description.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":id")
  public async at(
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<IEconomicPoliticalDiscussionBoardSection> {
    try {
      return await getEconomicPoliticalDiscussionBoardSectionsId({
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
