import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IEconomicPoliticalDiscussionBoardGuest } from "../../../../api/structures/IEconomicPoliticalDiscussionBoardGuest";
import { postEconomicPoliticalDiscussionBoardAuthGuestJoin } from "../../../../providers/postEconomicPoliticalDiscussionBoardAuthGuestJoin";
import { postEconomicPoliticalDiscussionBoardAuthGuestRefresh } from "../../../../providers/postEconomicPoliticalDiscussionBoardAuthGuestRefresh";

@Controller("/economicPoliticalDiscussionBoard/auth/guest")
export class EconomicpoliticaldiscussionboardAuthGuestController {
  /**
   * This endpoint enables unauthenticated users to register for the Economic/Political Discussion Board. The guest registration process begins with providing a valid email address and password meeting complexity requirements. The system verifies email uniqueness, sends a verification link, and creates a temporary guest account in the database. Once email is verified, the account transitions to valid membership status. Required: valid email (validated format), strong password (8+ characters, 1 uppercase). Post-registration, the user can access limited public content without further verification. The registration process cannot be completed without email verification - as per 04-authentication-flow.md: 'WHEN a user requests to register, THE system SHALL require a valid email address (validated by format and SMTP check)'.
   *
   * The response contains JWT access and refresh tokens with expiration durations inherited from the guest session configuration (15-minute access token, 7-day refresh token) as specified in the 'economic_political_discussion_board_guest_sessions' schema.
   *
   * This operation creates a new guest account which will be linked to any user accounts later after email verification.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Registration information required for new guest account
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification Implementation handles guest registration via email verification. Uses user_email_verifications table for token storage. HTTP 201 on successful creation, token returned with 15-minute validity. Services: email, user registration, token management
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEconomicPoliticalDiscussionBoardGuest.IJoin,
  ): Promise<IEconomicPoliticalDiscussionBoardGuest.IAuthorized> {
    try {
      return await postEconomicPoliticalDiscussionBoardAuthGuestJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This endpoint allows guests to refresh their session tokens when access tokens expire. The guest session (in economic_political_discussion_board_guest_sessions table) has defined refresh token validity (7-day expiration). The refresh process verifies the refresh token's validity, creates a new access token (15-minute lifespan) and refresh token (7-day), and updates the session record with the new tokens. Required: valid refresh token in authorization header.
   *
   * The refresh operation processes the refresh token from the Authorization header and returns new tokens. This follows standard authentication patterns where refresh operations include refresh token in header.
   *
   * Response provides new access token (valid for 15 minutes), refresh token (valid for 7 days), and user role (guest) as specified in the service model's session management schema.
   *
   * This operation enables uninterrupted access to public content without requiring re-registration after access token expiration, as described in 04-authentication-flow.md: 'WHEN a user remains inactive for 30 minutes, THE system SHALL automatically terminate their session.'
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token for guest session validation
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification Implementation handles JWT token refresh for guest sessions. Checks refresh token validity and returns new access/refresh tokens. Services: token management, session renewal
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IEconomicPoliticalDiscussionBoardGuest.IRefresh,
  ): Promise<IEconomicPoliticalDiscussionBoardGuest.IAuthorized> {
    try {
      return await postEconomicPoliticalDiscussionBoardAuthGuestRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
