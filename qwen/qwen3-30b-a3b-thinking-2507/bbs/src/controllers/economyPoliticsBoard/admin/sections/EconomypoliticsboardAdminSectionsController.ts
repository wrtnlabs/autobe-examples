import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEconomyPoliticsBoardSection } from "../../../../api/structures/IEconomyPoliticsBoardSection";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { deleteEconomyPoliticsBoardAdminSectionsSectionId } from "../../../../providers/deleteEconomyPoliticsBoardAdminSectionsSectionId";
import { postEconomyPoliticsBoardAdminSections } from "../../../../providers/postEconomyPoliticsBoardAdminSections";
import { putEconomyPoliticsBoardAdminSectionsSectionId } from "../../../../providers/putEconomyPoliticsBoardAdminSectionsSectionId";

@Controller("/economyPoliticsBoard/admin/sections")
export class EconomypoliticsboardAdminSectionsController {
  /**
   * Create a new section for categorizing articles on the economic/political discussion board.
   *
   * This operation is available only to administrators with appropriate permissions. Sections serve as categories where users can create and manage articles.
   *
   * The section name must be unique across the platform to prevent duplicate categories. The description must be at least 20 characters to ensure sections are adequately defined and meaningful to users.
   *
   * This operation creates a section that can be browsed and used by all users, while maintaining clear organization of content on the platform.
   *
   * @param connection
   * @param body Section information for creation
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Validate section name uniqueness and description minimum length (20 characters). Create new section record with current timestamp. Associate with default creator (system). Enforce database constraints on name uniqueness as per schema. Handle validation errors by returning 400 with error details. Return created section with ID and timestamps in response.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IEconomyPoliticsBoardSection.ICreate,
  ): Promise<IEconomyPoliticsBoardSection> {
    try {
      return await postEconomyPoliticsBoardAdminSections({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update the metadata for an existing economic/political discussion board section.
   *
   * This endpoint allows administrators to modify the name and description of a section. The name must remain globally unique across all sections, and the description must be at least 20 characters in length. The operation enforces these validation rules to maintain data integrity and consistent section categorization.
   *
   * Updates to section metadata are immediately visible to all users, and the updated_at timestamp reflects the exact moment of change. The operation returns the complete updated section record instead of a confirmation message to maintain consistency with other write operations.
   *
   * Validation rules:
   * - Section name must be unique across all sections (database constraint)
   * - Section description must be at least 20 characters
   * - Section ID must exist in database
   *
   * @param connection
   * @param sectionId The unique identifier of the section to update
   * @param body New section name and description
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification 1. Validate section ID exists and is associated with an existing section
   * 2. Check new name is not already used by another section
   * 3. Verify description meets minimum 20 characters
   * 4. Update the section record with new name and description
   * 5. Update updated_at timestamp to current time
   * 6. Return the fully updated section record with all fields
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":sectionId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("sectionId")
    sectionId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEconomyPoliticsBoardSection.IUpdate,
  ): Promise<IEconomyPoliticsBoardSection> {
    try {
      return await putEconomyPoliticsBoardAdminSectionsSectionId({
        admin,
        sectionId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Mark a section as deleted using soft deletion.
   *
   * This operation enables administrators to remove sections from public visibility without permanently deleting data. The section is marked as deleted by setting the `deleted_at` timestamp, which hides it from public views while preserving the data for audit purposes.
   *
   * The section must be identified by its ID in UUID format. Access requires administrative privileges. A 204 response indicates successful deletion with no body returned.
   *
   * @param connection
   * @param sectionId Unique identifier of the section to delete
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Validate section exists and user is admin. Set deleted_at to current timestamp. Return 204 No Content. Handle 404 if section not found.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":sectionId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("sectionId")
    sectionId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteEconomyPoliticsBoardAdminSectionsSectionId({
        admin,
        sectionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
