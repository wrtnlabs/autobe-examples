import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEconomyPoliticsBoardSection } from "../../../api/structures/IEconomyPoliticsBoardSection";
import { IPageIEconomyPoliticsBoardSection } from "../../../api/structures/IPageIEconomyPoliticsBoardSection";
import { getEconomyPoliticsBoardSectionsSectionId } from "../../../providers/getEconomyPoliticsBoardSectionsSectionId";
import { patchEconomyPoliticsBoardSections } from "../../../providers/patchEconomyPoliticsBoardSections";

@Controller("/economyPoliticsBoard/sections")
export class EconomypoliticsboardSectionsController {
  /**
   * Retrieve a paginated list of all platform sections.
   *
   * This operation provides detailed information about all sections in the economic/political discussion platform. Sections are listed alphabetically by name with their descriptive information, enabling users to browse categories for article discussions.
   *
   * The response includes paginated results with customizable page size. Administrators can use the filtering capabilities to discover sections based on partial name matches or description content. Each section entry displays both the name and description to help users identify relevant categories.
   *
   * Requires administrator or user role with appropriate permissions. No personal data is included in the list response for privacy reasons.
   *
   * @param connection
   * @param body Search and pagination parameters for sections
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query economy_politics_board_sections table with alphabetical ordering by name. Apply filtering on section name (partial match) and description. Implement cursor-based pagination with default 20 items per page. Filter only sections where 'name' is not null. Return only name and description fields for efficiency. Handle case-insensitive alphabetical sorting.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IEconomyPoliticsBoardSection.IRequest,
  ): Promise<IPageIEconomyPoliticsBoardSection.ISummary> {
    try {
      return await patchEconomyPoliticsBoardSections({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific economic/political discussion section.
   *
   * This operation provides comprehensive information about a single section, including its unique name, descriptive content, and creation timestamp. Each section must have a unique name meeting the platform's validation requirements.
   *
   * Section browsing is available to all registered users, allowing them to explore the category structure and find relevant topics. The response includes all essential section attributes necessary for the user interface to display category details clearly.
   *
   * Authentication is not required to access section information since this is part of public browsing functionality supporting user content discovery.
   *
   * @param connection
   * @param sectionId Unique identifier for the section
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Fetch section details from economy_politics_board_sections table using sectionId parameter. Validate existence of section record before returning. Include all columns: name, description, createdAt. No authorization filtering needed (all users can view sections).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sectionId")
  public async at(
    @TypedParam("sectionId")
    sectionId: string & tags.Format<"uuid">,
  ): Promise<IEconomyPoliticsBoardSection> {
    try {
      return await getEconomyPoliticsBoardSectionsSectionId({
        sectionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
