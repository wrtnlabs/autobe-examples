import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEconomyPoliticsBoardArticle } from "../../../api/structures/IEconomyPoliticsBoardArticle";
import { IPageIEconomyPoliticsBoardArticle } from "../../../api/structures/IPageIEconomyPoliticsBoardArticle";
import { getEconomyPoliticsBoardArticlesArticleId } from "../../../providers/getEconomyPoliticsBoardArticlesArticleId";
import { patchEconomyPoliticsBoardArticles } from "../../../providers/patchEconomyPoliticsBoardArticles";

@Controller("/economyPoliticsBoard/articles")
export class EconomypoliticsboardArticlesController {
  /**
   * Retrieve detailed information about a specific article including its content, associated section, author profile, and timestamp. This operation provides the complete view of an article as it appears on the platform, with all relevant contextual information.
   *
   * The response includes the full article body, displaying title, content, creation date, associated section name, and author's display name. This operation supports users viewing individual articles in the economic/political discussion board platform.
   *
   * This endpoint is accessible to all users viewing the article details, with permissions managed through the article's visibility settings. Article content is sanitized to prevent XSS attacks before being returned.
   *
   * @param connection
   * @param articleId Unique identifier of the article to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Fetch article from economy_politics_board_articles table using provided articleId. Join with sections for section name and with users for author name. Return full article content with title, content, section, author, creation timestamp, and article-specific metadata. Handle 404 if article not found.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":articleId")
  public async at(
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
  ): Promise<IEconomyPoliticsBoardArticle> {
    try {
      return await getEconomyPoliticsBoardArticlesArticleId({
        articleId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a paginated list of articles with customizable search filters.
   *
   * This operation provides comprehensive filtering capabilities to find relevant articles by title, content, section, or author. The response includes a paginated list with summary data optimized for display in user interfaces.
   *
   * Supports advanced search using full-text indexes on title and content columns. Pagination allows efficient traversal of large article collections with configurable page sizes.
   *
   * Filtering parameters can be combined to refine search results precisely. The response includes necessary pagination metadata and article summaries.
   *
   * @param connection
   * @param body Search criteria and pagination parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query economy_politics_board_articles table using GIN indexes on title and content columns for full-text search. Apply filters on title, content, section_id, and author_id. Implement cursor-based pagination for efficient large result sets. Return summarized data in IPageIEconomyPoliticsBoardArticle.ISummary format.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IEconomyPoliticsBoardArticle.IRequest,
  ): Promise<IPageIEconomyPoliticsBoardArticle.ISummary> {
    try {
      return await patchEconomyPoliticsBoardArticles({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
