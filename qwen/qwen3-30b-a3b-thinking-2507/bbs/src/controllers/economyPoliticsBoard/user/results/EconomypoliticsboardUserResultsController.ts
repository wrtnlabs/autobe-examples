import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEconomyPoliticsBoardSearchResult } from "../../../../api/structures/IEconomyPoliticsBoardSearchResult";
import { IPageIEconomyPoliticsBoardSearchResult } from "../../../../api/structures/IPageIEconomyPoliticsBoardSearchResult";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { getEconomyPoliticsBoardUserResultsResultId } from "../../../../providers/getEconomyPoliticsBoardUserResultsResultId";
import { patchEconomyPoliticsBoardUserResults } from "../../../../providers/patchEconomyPoliticsBoardUserResults";

@Controller("/economyPoliticsBoard/user/results")
export class EconomypoliticsboardUserResultsController {
  /**
   * Retrieve paginated search results cache with article and tag context.
   *
   * This operation provides access to the cached search results that power user search functionality. Each result records a search query along with the referenced articles and tags, enabling efficient search history and analytics.
   *
   * Supports complex filtering by search query, specific articles, tags, and date ranges. Response returns a paginated list of summary data optimized for search result display, with detailed article and tag references available through separate endpoints.
   *
   * @param connection
   * @param body Search criteria, filter parameters, and pagination options
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Query the economy_politics_board_search_results table with paginated results. Filter based on search term, article ID, tag ID, and date range parameters. Join with articles and tags for detailed context. Support cursor-based pagination for large result sets. Cache results should reference their parent article and tag relationships.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: IEconomyPoliticsBoardSearchResult.IRequest,
  ): Promise<IPageIEconomyPoliticsBoardSearchResult.ISummary> {
    try {
      return await patchEconomyPoliticsBoardUserResults({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific search result cache record from the database.
   *
   * This endpoint provides the detailed information about a particular search result, including the associated article content and user-added tags for categorization. The search result cache is used to optimize search performance while maintaining reference to the original article content and tagging structure.
   *
   * The response includes all relevant data fields including creation and update timestamps to support auditing and version tracking. Records marked as deleted (soft delete) are excluded from this endpoint.
   *
   * @param connection
   * @param resultId ID of the search result to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Perform database query on economy_politics_board_search_results table using 'resultId' parameter. Join with economy_politics_board_articles and economy_politics_board_article_tags tables for related data. Verify record exists and is not soft-deleted (deleted_at null). If deleted, return 404. Return all fields including associated article and tag details.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":resultId")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("resultId")
    resultId: string & tags.Format<"uuid">,
  ): Promise<IEconomyPoliticsBoardSearchResult> {
    try {
      return await getEconomyPoliticsBoardUserResultsResultId({
        user,
        resultId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
