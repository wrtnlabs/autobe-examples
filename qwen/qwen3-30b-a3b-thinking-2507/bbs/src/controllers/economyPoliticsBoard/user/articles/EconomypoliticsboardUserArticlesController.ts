import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEconomyPoliticsBoardArticle } from "../../../../api/structures/IEconomyPoliticsBoardArticle";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { deleteEconomyPoliticsBoardUserArticlesArticleId } from "../../../../providers/deleteEconomyPoliticsBoardUserArticlesArticleId";
import { postEconomyPoliticsBoardUserArticles } from "../../../../providers/postEconomyPoliticsBoardUserArticles";
import { putEconomyPoliticsBoardUserArticlesArticleId } from "../../../../providers/putEconomyPoliticsBoardUserArticlesArticleId";

@Controller("/economyPoliticsBoard/user/articles")
export class EconomypoliticsboardUserArticlesController {
  /**
   * Update an existing article with new title and content.
   *
   * This operation allows authors to modify their published articles, maintaining the same section and author relationships while updating critical content fields.
   *
   * The operation validates that:
   * - Title meets the minimum 5 character requirement
   * - Content meets the minimum 50 character requirement
   * - The updating user is the article's author (authorization handled at service layer)
   * - Article exists before modification (404 if not found)
   *
   * Updated articles maintain their original creation timestamp but receive a new update timestamp. All article attachments and tags remain preserved without modification to the database relationship structure.
   *
   * @param connection
   * @param articleId Unique identifier for the article to update
   * @param body Updated article fields (title and content)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification 1. Verify article exists and belongs to authenticated user (author_id matches current user)
   * 2. Validate title length (5-255 characters)
   * 3. Validate content length (50-5000 characters)
   * 4. Update title and content fields only (preserve section_id, author_id)
   * 5. Set updated_at timestamp
   * 6. Return full article record with new timestamp
   * 7. Trigger content indexing for search optimization
   * 8. Log modification event in audit trail
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":articleId")
  public async update(
    @UserAuth()
    user: UserPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEconomyPoliticsBoardArticle.IUpdate,
  ): Promise<IEconomyPoliticsBoardArticle> {
    try {
      return await putEconomyPoliticsBoardUserArticlesArticleId({
        user,
        articleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Mark an article as deleted using soft delete, retaining it in the database for audit and moderation purposes.
   *
   * This operation allows authors and administrators to remove articles from public view without permanent deletion. The article remains in the system while its deleted_at timestamp is set, allowing for potential recovery through moderation tools or audit trails.
   *
   * The response includes the complete article object with the deleted_at field populated, confirming the operation's execution and providing all article details for reference. Only the article's author or administrators can execute this operation.
   *
   * This implementation strictly follows the database schema with soft delete column and provides necessary audit information in the response.
   *
   * @param connection
   * @param articleId Unique identifier for the article to be soft-deleted
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Perform soft delete by setting deleted_at timestamp. Check authorization (article author or admin). Validate article exists and is not already deleted. Return full article object after deletion.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":articleId")
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
  ): Promise<IEconomyPoliticsBoardArticle> {
    try {
      return await deleteEconomyPoliticsBoardUserArticlesArticleId({
        user,
        articleId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Create a new article in the economic and political discussion board. Users can create articles within any available section after registration and authentication.
   *
   * This operation supports full article creation with title, content, and section association. Articles must meet minimum length requirements for title (5 characters) and content (50 characters). The current user's ID is automatically associated as the author.
   *
   * Section selection is mandatory to categorize articles properly. Content validation ensures meaningful contributions to the platform. All new articles receive immediate publication timestamp and are visible to other users upon creation.
   *
   * This endpoint requires authentication with user credentials. Article creation is subject to platform content policies, including a 20-file attachment limit (handled in separate attachment API).
   *
   * @param connection
   * @param body Article creation request data
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Validate title (≥5 characters), content (≥50 characters), and valid section_id (UUID). Verify the section exists in economy_politics_board_sections table. Auto-set author_id based on authenticated user from session. Create new article record with current timestamps. Return the created article object including auto-generated ID and timestamps.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: IEconomyPoliticsBoardArticle.ICreate,
  ): Promise<IEconomyPoliticsBoardArticle> {
    try {
      return await postEconomyPoliticsBoardUserArticles({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
