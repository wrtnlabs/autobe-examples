import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEconomyPoliticsBoardArticle } from "../../../../api/structures/IEconomyPoliticsBoardArticle";
import { IEconomyPoliticsBoardSearchFilter } from "../../../../api/structures/IEconomyPoliticsBoardSearchFilter";
import { IPageIEconomyPoliticsBoardArticle } from "../../../../api/structures/IPageIEconomyPoliticsBoardArticle";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { deleteEconomyPoliticsBoardUserFiltersFilterId } from "../../../../providers/deleteEconomyPoliticsBoardUserFiltersFilterId";
import { getEconomyPoliticsBoardUserFiltersFilterId } from "../../../../providers/getEconomyPoliticsBoardUserFiltersFilterId";
import { patchEconomyPoliticsBoardUserFilters } from "../../../../providers/patchEconomyPoliticsBoardUserFilters";
import { postEconomyPoliticsBoardUserFilters } from "../../../../providers/postEconomyPoliticsBoardUserFilters";
import { putEconomyPoliticsBoardUserFiltersFilterId } from "../../../../providers/putEconomyPoliticsBoardUserFiltersFilterId";

@Controller("/economyPoliticsBoard/user/filters")
export class EconomypoliticsboardUserFiltersController {
  /**
   * Creates a personalized search filter configuration for the user's account.
   *
   * This operation enables users to save recurring search criteria (such as tag combinations, date ranges, or recent articles) as a named filter. Saved filters appear in the user's filter management UI and can be reused across multiple search operations.
   *
   * The filter configuration is stored as a JSON string (e.g., {"tags":["economy","politics"],"recent":true}), which the search service parses to apply the filter parameters in subsequent searches.
   *
   * Returns the newly created filter record with full details including timestamp information.
   *
   * @param connection
   * @param body Personal search filter configuration settings
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Create new search filter configuration for authenticated user. User_id is automatically assigned from the session. Requires filter_name (string, min 1 char), config (JSON string in format "{\"tags\":[\"economy\",\"politics\"],\"recent\":true}"). Config is stored as string and parsed later by search service. Validates that filter_name is provided and config is valid JSON string. Returns newly created filter record with id, timestamps.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: IEconomyPoliticsBoardSearchFilter.ICreate,
  ): Promise<IEconomyPoliticsBoardSearchFilter> {
    try {
      return await postEconomyPoliticsBoardUserFilters({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve filtered and paginated list of economic and political articles.
   *
   * This operation allows users to search by keyword across article titles and content, and filter results by multiple tags (articles must match all selected tags). The API handles partial word matching for search terms and returns results sorted by creation date (newest first) by default. Each page includes 20 article summaries optimized for display in the user interface.
   *
   * Pagination is implemented as cursor-based (not position-based) for optimal performance on large datasets. Tag filtering is designed for 'AND' relationship (all selected tags must match), and results can be refined through subsequent filtering requests.
   *
   * @param connection
   * @param body Search criteria including keyword, tags, and pagination parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Query economy_politics_board_articles table with full-text search on title and content fields. Apply tag filtering by joining with economy_politics_board_article_tags table and requiring all selected tags to match. Implement cursor-based pagination with default page size of 20. Apply sorting by creation date (newest first) by default. Handle partial word matching for search terms using GIN index on title and content fields.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: IEconomyPoliticsBoardArticle.IRequest,
  ): Promise<IPageIEconomyPoliticsBoardArticle.ISummary> {
    try {
      return await patchEconomyPoliticsBoardUserFilters({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific saved filter configuration by ID.
   *
   * This operation provides access to a user's personalized search filter configuration which may include tag preferences, search parameters, and other filtering criteria. The response contains the filter's name, description, and serialized configuration data that can be directly applied in search operations.
   *
   * The filter configuration is associated with the user who created it, and the response will only include filters visible to the requesting user (with administrators having access to all filters). The returned configuration data is stored in JSON format as the 'config' field and contains parameters like selected tags and recent search indicators.
   *
   * This endpoint enables users to manage their search preferences without requiring them to reconfigure filters repeatedly, improving the user experience for ongoing searches.
   *
   * @param connection
   * @param filterId ID of the filter configuration
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Query the economy_politics_board_search_filters table to find the filter record where id = {filterId}. If the user is not a super admin, verify that the user_id matches the authenticated user's ID. Return the entire filter record including user_id, filter_name, description, config, and timestamps.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":filterId")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("filterId")
    filterId: string & tags.Format<"uuid">,
  ): Promise<IEconomyPoliticsBoardSearchFilter> {
    try {
      return await getEconomyPoliticsBoardUserFiltersFilterId({
        user,
        filterId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update a user's saved search filter configuration.
   *
   * This endpoint allows users to modify the name, description, and filtering criteria associated with their saved search configurations. The operation updates the filter configuration's metadata and serialized filter settings in the database.
   *
   * Users can update the filter name, provide a description, or adjust the filter configuration (stored as JSON) to match their search preferences. The filter name must be at least 2 characters and the configuration must be valid JSON.
   *
   * The API operation automatically updates the 'updated_at' timestamp upon successful modification. Modified filter configurations are immediately available for future search operations.
   *
   * This operation requires the user to be authenticated and have ownership of the filter being updated.
   *
   * @param connection
   * @param filterId ID of the filter configuration to update
   * @param body Updated filter configuration data
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Update the specified filter configuration by ID. Requires filter_name and config fields. Update the updated_at timestamp automatically. Handle partial updates by only modifying provided fields. Validate filter_name (min 2 chars) and config (JSON string) formats. Ensure user_id matches current authenticated user's account.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":filterId")
  public async update(
    @UserAuth()
    user: UserPayload,
    @TypedParam("filterId")
    filterId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEconomyPoliticsBoardSearchFilter.IUpdate,
  ): Promise<IEconomyPoliticsBoardSearchFilter> {
    try {
      return await putEconomyPoliticsBoardUserFiltersFilterId({
        user,
        filterId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a user's saved filter configuration.
   *
   * This operation marks a filter configuration as deleted using the system's soft delete mechanism. The filter will no longer appear in active search results but remains accessible for historical tracking. The operation validates that the requesting user owns the filter or has administrative privileges.
   *
   * Soft deletion preserves data integrity while allowing user content management. Deleted filters can be recovered through system administration tools but will not appear in regular user searches. This behavior maintains the platform's content governance policy for user-owned resources. The operation returns a 204 No Content response upon successful deletion.
   *
   * @param connection
   * @param filterId ID of the filter configuration to delete (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification 1. Check if filter record exists and is not already soft-deleted
   * 2. Verify user ownership (filter.user_id matches current user) or user has admin privileges
   * 3. If valid, set deleted_at = current timestamp on filter record
   * 4. Log audit event
   * 5. Return success status without response body
   * Implementation uses Prisma update mutation with where clause on id and current user context.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":filterId")
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("filterId")
    filterId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteEconomyPoliticsBoardUserFiltersFilterId({
        user,
        filterId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
