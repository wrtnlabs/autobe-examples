/**
 * Search for discussion board articles based on various criteria including
 * title, content, author, and date ranges. This search operation allows users
 * and guests to efficiently find relevant content across the discussion
 * platform without needing authentication.
 *
 * The search functionality supports full-text matching on article titles and
 * content fields, as well as filtering by author, publication date ranges, and
 * article status. This capability enables users to quickly locate specific
 * discussions relevant to their interests or needs.
 *
 * Results are returned as paginated collections containing only essential
 * article information (title, summary, author, and publication date) to
 * optimize performance and reduce bandwidth usage. Users can sort search
 * results by relevance, date, or popularity based on their preferences.
 *
 * Implementation note: This operation queries the discussion_board_articles
 * table using full-text search capabilities on title and content fields.
 * Pagination is implemented using offset and page size parameters for efficient
 * navigation of potentially large result sets.
 *
 * @param props.connection
 * @param props.body Search criteria including query terms, filters, pagination
 *   parameters, and sorting options
 * @path /discussionBoard/search/articles
 * @accessor api.functional.discussionBoard.search.articles.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Search criteria including query terms, filters, pagination
     * parameters, and sorting options
     */
    body: IDiscussionBoardArticle.IRequest;
  };
  export type Body = IDiscussionBoardArticle.IRequest;
  export type Response = IPageIDiscussionBoardArticle.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/discussionBoard/search/articles",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/discussionBoard/search/articles";
  export const random = (): IPageIDiscussionBoardArticle.ISummary =>
    typia.random<IPageIDiscussionBoardArticle.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
