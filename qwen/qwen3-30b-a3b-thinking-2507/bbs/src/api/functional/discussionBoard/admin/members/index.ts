/**
 * This operation permanently removes the specified member account from the
 * system's database.
 *
 * The member identified by the provided memberId parameter is completely
 * removed from the database. Unlike soft delete operations that mark records as
 * deleted, this operation performs a hard deletion, removing all associated
 * data immediately with no possibility of recovery.
 *
 * Security considerations include strict authorization requirements - only
 * administrators are permitted to initiate this operation to prevent accidental
 * or unauthorized account deletions.
 *
 * For system integrity, this operation does not return any response body - the
 * server responds with a 204 No Content status upon successful deletion,
 * indicating the resource has been removed but no data is sent back. Any
 * attempt to access the previously deleted member will result in a 404 Not
 * Found response.
 *
 * @param props.connection
 * @param props.memberId Unique identifier of the target member
 * @path /discussionBoard/admin/members/:memberId
 * @accessor api.functional.discussionBoard.admin.members.erase
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function erase(
  connection: IConnection,
  props: erase.Props,
): Promise<void> {
  return true === connection.simulate
    ? erase.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...erase.METADATA,
          path: erase.path(props),
          status: null,
        },
      );
}
export namespace erase {
  export type Props = {
    /** Unique identifier of the target member */
    memberId: string;
  };

  export const METADATA = {
    method: "DELETE",
    path: "/discussionBoard/admin/members/:memberId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/admin/members/${encodeURIComponent(props.memberId ?? "null")}`;
  export const random = (): void => typia.random<void>();
  export const simulate = (
    connection: IConnection,
    props: erase.Props,
  ): void => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: erase.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("memberId")(() => typia.assert(props.memberId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
