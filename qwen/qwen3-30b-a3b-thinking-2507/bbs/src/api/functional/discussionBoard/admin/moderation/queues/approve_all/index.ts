import { IDiscussionBoardModerationQueue } from "../../../../../../structures/IDiscussionBoardModerationQueue";

/**
 * Approve all pending articles in a specified moderation queue. This operation
 * marks all articles in the target queue as approved and moves them into the
 * published state.
 *
 * The operation is designed for moderation workflows where articles need to be
 * bulk-approved. It updates the status of all articles in the queue to
 * 'approved' (or equivalent), triggering the publication process without
 * requiring individual article handling. The moderation_queue table stores the
 * status of articles before publication, and this operation directly modifies
 * the status field.
 *
 * Security considerations require this endpoint to be limited to moderator
 * accounts only. Unauthorized users will receive a 403 response. The operation
 * is implemented as a single database transaction to ensure atomicity,
 * approving all articles in the queue or none. After approval, the articles are
 * immediately visible to all users in the system as published content. This
 * should be used cautiously as a final step in the moderation process, as it
 * bypasses individual article review.
 *
 * @param props.connection
 * @param props.queueCode Unique code identifier of the moderation queue (global
 *   scope)
 * @path /discussionBoard/admin/moderation/queues/:queueCode/approve-all
 * @accessor api.functional.discussionBoard.admin.moderation.queues.approve_all.approveAll
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function approveAll(
  connection: IConnection,
  props: approveAll.Props,
): Promise<approveAll.Response> {
  return true === connection.simulate
    ? approveAll.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...approveAll.METADATA,
          path: approveAll.path(props),
          status: null,
        },
      );
}
export namespace approveAll {
  export type Props = {
    /** Unique code identifier of the moderation queue (global scope) */
    queueCode: string;
  };
  export type Response = IDiscussionBoardModerationQueue.IApproveAllResult;

  export const METADATA = {
    method: "POST",
    path: "/discussionBoard/admin/moderation/queues/:queueCode/approve-all",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/admin/moderation/queues/${encodeURIComponent(props.queueCode ?? "null")}/approve-all`;
  export const random = (): IDiscussionBoardModerationQueue.IApproveAllResult =>
    typia.random<IDiscussionBoardModerationQueue.IApproveAllResult>();
  export const simulate = (
    connection: IConnection,
    props: approveAll.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: approveAll.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("queueCode")(() => typia.assert(props.queueCode));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
