import { IConnection } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";

import { IPageIDiscussionBoardModerationQueue } from "../../../../../../structures/IPageIDiscussionBoardModerationQueue";

/**
 * Retrieves the list of articles pending moderation for administrative review,
 * providing paginated access to articles requiring content approval. This
 * operation enables administrators to efficiently manage the moderation
 * workflow by displaying key metadata including submission timestamp, article
 * status, and associated article details without exposing sensitive moderation
 * history.
 *
 * The implementation directly accesses the discussion_board_moderation_queue
 * database table to fetch pending article entries, which contains the necessary
 * state information (status, submission time) and references to the associated
 * articles. This operation supports the core business requirement for content
 * moderation where unverified submissions must be reviewed before publication.
 *
 * Security: This endpoint is restricted to administrative users only through
 * actor-based authorization. The system enforces that only users with the
 * 'admin' actor role can access this endpoint, aligning with the permissions
 * matrix for moderation workflows. Each request must include a valid
 * administrative session token.
 *
 * @param props.connection
 * @path /discussionBoard/admin/dashboard/admin/moderation
 * @accessor api.functional.discussionBoard.admin.dashboard.admin.moderation.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(connection: IConnection): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
      );
}
export namespace index {
  export type Response = IPageIDiscussionBoardModerationQueue.ISummary;

  export const METADATA = {
    method: "GET",
    path: "/discussionBoard/admin/dashboard/admin/moderation",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/discussionBoard/admin/dashboard/admin/moderation";
  export const random = (): IPageIDiscussionBoardModerationQueue.ISummary =>
    typia.random<IPageIDiscussionBoardModerationQueue.ISummary>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}
