/**
 * Retrieve a paginated list of file attachments associated with a specific
 * discussion board article. This operation directly maps to the
 * discussion_board_article_files database table, which stores all uploaded
 * files attached to articles with metadata about file_type (validated to accept
 * only PDF, DOCX, XLSX), file_size (in bytes), and display_info (which includes
 * the icon and size string). The implementation handles file type validation
 * for PDF, DOCX, and XLSX formats (maximum 10MB size) as specified in Business
 * Requirement (Y8) and displays the file type icon and size indicator as per
 * Requirement (Y9). Authentication ensures only the article creator (member) or
 * administrators (admin) can access the file attachments, respecting the
 * moderation workflow described in Business Requirements (Y11-Y14). The
 * response includes file summary information optimized for display with
 * relevant metadata.
 *
 * This operation supports pagination, filtering, and sorting options to
 * facilitate efficient file management within the article context. All file
 * metadata remains consistent with the media handling processes described in
 * the Business Process Diagram for File Attachment.
 *
 * Security considerations include validating the articleCode against the
 * requester's membership status and ensuring only articles in 'published' state
 * return downloadable files. The operation automatically filters to exclude any
 * attachments marked for moderation when the requester does not have
 * administrative privileges.
 *
 * @param props.connection
 * @param props.articleCode Unique business identifier code of the target
 *   article (global scope)
 * @param props.body Pagination parameters, search filters, and sorting options
 *   for file attachments
 * @path /discussionBoard/admin/articles/:articleCode/files
 * @accessor api.functional.discussionBoard.admin.articles.files.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /** Unique business identifier code of the target article (global scope) */
    articleCode: string;

    /**
     * Pagination parameters, search filters, and sorting options for file
     * attachments
     */
    body: IDiscussionBoardArticleFile.IRequest;
  };
  export type Body = IDiscussionBoardArticleFile.IRequest;
  export type Response = IPageIDiscussionBoardArticleFile.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/discussionBoard/admin/articles/:articleCode/files",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/discussionBoard/admin/articles/${encodeURIComponent(props.articleCode ?? "null")}/files`;
  export const random = (): IPageIDiscussionBoardArticleFile.ISummary =>
    typia.random<IPageIDiscussionBoardArticleFile.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("articleCode")(() => typia.assert(props.articleCode));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

