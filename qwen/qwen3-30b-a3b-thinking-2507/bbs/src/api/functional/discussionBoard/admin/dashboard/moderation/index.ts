import { IConnection } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";

import { IDiscussionBoardModerationQueue } from "../../../../../structures/IDiscussionBoardModerationQueue";

/**
 * This operation returns the overview statistics for the discussion board
 * moderation dashboard. It provides key metrics about the moderation status
 * across the system, including the count of articles currently awaiting review
 * and summary information about recent moderation activities. The data is
 * pulled from the discussion_board_moderation_queue and
 * discussion_board_moderation_actions tables to provide a comprehensive view of
 * current moderation tasks. This endpoint is intended for administrative users
 * to quickly assess the moderation workload and effectiveness of the moderation
 * system. The response includes counts of articles in queue, recent action
 * types, and key metrics that help administrators prioritize their moderation
 * efforts.
 *
 * @param props.connection
 * @path /discussionBoard/admin/dashboard/moderation/overview
 * @accessor api.functional.discussionBoard.admin.dashboard.moderation.overview
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function overview(
  connection: IConnection,
): Promise<overview.Response> {
  return true === connection.simulate
    ? overview.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...overview.METADATA,
          path: overview.path(),
          status: null,
        },
      );
}
export namespace overview {
  export type Response = IDiscussionBoardModerationQueue;

  export const METADATA = {
    method: "GET",
    path: "/discussionBoard/admin/dashboard/moderation/overview",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () =>
    "/discussionBoard/admin/dashboard/moderation/overview";
  export const random = (): IDiscussionBoardModerationQueue =>
    typia.random<IDiscussionBoardModerationQueue>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}
