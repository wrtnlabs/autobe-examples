import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardArticleFile } from "../../../../../structures/IDiscussionBoardArticleFile";

/**
 * Retrieve specific file details attached to a discussion board article.
 *
 * This operation allows guests to access file metadata from the DiscussionBoard
 * system. The file must be attached to an article that is in the published
 * status to be accessible, ensuring that only approved content is delivered to
 * users. The operation coordinates with the article moderation workflow to
 * validate the article's current status before returning the file data.
 *
 * File metadata includes the original filename, MIME type, file size, and
 * display information fields specific to common document formats (PDF, DOCX,
 * XLSX). This information is stored in the discussion_board_article_files
 * table, which tracks all attached files with their relative paths, validation
 * details, and associated display preferences.
 *
 * Security considerations include rate limiting for file retrieval operations
 * to prevent abuse. The operation enforces authorization checks based on the
 * article's published status and user role, ensuring that only users with guest
 * permissions can access files from publicly visible articles, while restricted
 * content remains inaccessible to unauthenticated users.
 *
 * @param props.connection
 * @param props.articleId Unique identifier of the target article (UUID)
 * @param props.fileId Unique identifier of the target file (UUID)
 * @path /discussionBoard/guest/articles/:articleId/files/:fileId
 * @accessor api.functional.discussionBoard.guest.articles.files.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique identifier of the target article (UUID) */
    articleId: string & tags.Format<"uuid">;

    /** Unique identifier of the target file (UUID) */
    fileId: string & tags.Format<"uuid">;
  };
  export type Response = IDiscussionBoardArticleFile;

  export const METADATA = {
    method: "GET",
    path: "/discussionBoard/guest/articles/:articleId/files/:fileId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/guest/articles/${encodeURIComponent(props.articleId ?? "null")}/files/${encodeURIComponent(props.fileId ?? "null")}`;
  export const random = (): IDiscussionBoardArticleFile =>
    typia.random<IDiscussionBoardArticleFile>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("articleId")(() => typia.assert(props.articleId));
      assert.param("fileId")(() => typia.assert(props.fileId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
