/**
 * Retrieves a paginated list of discussion board member profiles with
 * customizable search filtering. This operation serves the requirements
 * outlined in 03-discussion-features.md for member management and visibility
 * features, supporting search by username, email patterns, registration date
 * ranges, and membership status.
 *
 * The implementation queries the discussion_board_members table via Prisma,
 * honoring the "primary" stance which indicates this entity is user-managed
 * with full CRUD capabilities. Results are optimized for listing efficiency
 * with summary information that excludes sensitive fields like password hashes
 * and authentication tokens.
 *
 * Security considerations include authorization by 'member' actor to ensure
 * only authenticated users can view member lists, and rate limiting to prevent
 * mass user enumeration attacks. The response includes pagination metadata for
 * seamless client-side implementation.
 *
 * This operation integrates directly with the database schema's member profile
 * structure, using existing fields without assumptions of non-existent soft
 * delete columns or financial data. The schema explicitly defines all required
 * fields for this endpoint.
 *
 * @param props.connection
 * @param props.body Complex search criteria for member filtering including
 *   pagination offsets and filters
 * @path /discussionBoard/member/members
 * @accessor api.functional.discussionBoard.member.members.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
