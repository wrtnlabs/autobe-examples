import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardChannel } from "../../../structures/IDiscussionBoardChannel";

/**
 * Retrieve detailed information about a specific channel by its unique business
 * identifier. This operation queries the `discussion_board_channels` database
 * table using the `channelCode` field for exact matching. The channel data
 * includes business name, description, creation timestamp, and active status
 * information. Publicly accessible channels are returned without authentication
 * requirements.
 *
 * Security considerations include that this endpoint is designed for read-only
 * access to channel metadata. No user-specific data is included in the
 * response, ensuring it can be safely accessed by both authenticated users and
 * guests. The operation validates that the channelCode exists before returning
 * data.
 *
 * The response includes the main channel entity with full attributes, ensuring
 * all required fields from the database schema are present in the response
 * structure. This serves as the primary method for retrieving channel details
 * in the discussion platform's frontend and mobile applications.
 *
 * @param props.connection
 * @param props.channelCode Unique business identifier code of the channel
 *   (global scope)
 * @path /discussionBoard/channels/:channelCode
 * @accessor api.functional.discussionBoard.channels.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique business identifier code of the channel (global scope) */
    channelCode: string;
  };
  export type Response = IDiscussionBoardChannel;

  export const METADATA = {
    method: "GET",
    path: "/discussionBoard/channels/:channelCode",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/channels/${encodeURIComponent(props.channelCode ?? "null")}`;
  export const random = (): IDiscussionBoardChannel =>
    typia.random<IDiscussionBoardChannel>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("channelCode")(() => typia.assert(props.channelCode));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
