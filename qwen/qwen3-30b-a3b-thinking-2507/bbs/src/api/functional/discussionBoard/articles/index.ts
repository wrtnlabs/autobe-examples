import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IDiscussionBoardArticle } from "../../../structures/IDiscussionBoardArticle";
import { IPageIDiscussionBoardArticle } from "../../../structures/IPageIDiscussionBoardArticle";

/**
 * Retrieve a filtered and paginated list of discussion board articles from the
 * system. This operation operates on the DiscussionBoardArticles table from the
 * database schema and provides advanced search capabilities for finding
 * articles based on multiple criteria including title, author, publication
 * status, and date ranges.
 *
 * The operation supports comprehensive pagination with configurable page sizes
 * and sorting options. Articles can sort by publication date, update date,
 * title, or other relevant fields in ascending or descending order. The search
 * can filter on published status, article categories (if implemented), and
 * keywords in the title or content.
 *
 * Security considerations include filtering of sensitive article content based
 * on the requesting user's authorization level. Public access to the article
 * listing is provided without authentication. For production deployment, rate
 * limiting should be implemented to guard against excessive search requests.
 * This endpoint is designed for frontend consumption and displays a summary
 * view of each article.
 *
 * @param props.connection
 * @param props.body Search criteria and pagination parameters for filtering
 *   articles
 * @path /discussionBoard/articles
 * @accessor api.functional.discussionBoard.articles.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /** Search criteria and pagination parameters for filtering articles */
    body: IDiscussionBoardArticle.IRequest;
  };
  export type Body = IDiscussionBoardArticle.IRequest;
  export type Response = IPageIDiscussionBoardArticle.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/discussionBoard/articles",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/discussionBoard/articles";
  export const random = (): IPageIDiscussionBoardArticle.ISummary =>
    typia.random<IPageIDiscussionBoardArticle.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

/**
 * Retrieve a specific discussion board article by its URL-safe code. This
 * operation fetches the most recent version of the article from the
 * 'discussion_board_articles' table. The article content includes title,
 * author, content body, creation timestamp, and moderation status which
 * determines public visibility.
 *
 * Public access to 'approved' articles is allowed without authentication. For
 * 'draft' and 'pending' articles, access is restricted to administrators and
 * authors. The operation returns article content exactly as stored, with all
 * fields mapped to response type.
 *
 * This endpoint serves as the foundational article display mechanism, used to
 * render content on the discussion board website. View counts are automatically
 * incremented and access patterns logged for analytics purposes. The response
 * includes all necessary data for frontend display, including media references
 * and author information.
 *
 * @param props.connection
 * @param props.articleCode Unique URL-safe code of the target article (global
 *   scope)
 * @path /discussionBoard/articles/:articleCode
 * @accessor api.functional.discussionBoard.articles.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique URL-safe code of the target article (global scope) */
    articleCode: string;
  };
  export type Response = IDiscussionBoardArticle;

  export const METADATA = {
    method: "GET",
    path: "/discussionBoard/articles/:articleCode",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/articles/${encodeURIComponent(props.articleCode ?? "null")}`;
  export const random = (): IDiscussionBoardArticle =>
    typia.random<IDiscussionBoardArticle>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("articleCode")(() => typia.assert(props.articleCode));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
