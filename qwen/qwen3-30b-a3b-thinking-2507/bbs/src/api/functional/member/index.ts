import { IConnection } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";

import { IDiscussionBoardMember } from "../../structures/IDiscussionBoardMember";

/**
 * GET operation retrieves the current member's profile information. This
 * endpoint verifies the authenticated member has access to their own profile
 * and returns detailed information about the user account including name,
 * email, and account status. The response includes all profile information
 * without authentication-sensitive data. This operation is used to fetch and
 * display member profile data in the user interface.
 *
 * @param props.connection
 * @path /member/profile
 * @accessor api.functional.member.profile
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function profile(
  connection: IConnection,
): Promise<profile.Response> {
  return true === connection.simulate
    ? profile.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...profile.METADATA,
          path: profile.path(),
          status: null,
        },
      );
}
export namespace profile {
  export type Response = IDiscussionBoardMember;

  export const METADATA = {
    method: "GET",
    path: "/member/profile",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/member/profile";
  export const random = (): IDiscussionBoardMember =>
    typia.random<IDiscussionBoardMember>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}
