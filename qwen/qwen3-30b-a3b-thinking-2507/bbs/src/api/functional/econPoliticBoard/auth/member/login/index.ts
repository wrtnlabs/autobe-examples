import { HttpError, IConnection } from "@nestia/fetcher";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";

import { IEconPoliticBoardMember } from "../../../../../structures/IEconPoliticBoardMember";

/**
 * Authenticates an existing member using their email and password. Validates credentials against bcrypt-hashed password in database. Generates JWT access token (1 hour expiration) and refresh token (30 days validity). The email must exist in the database and match the password hash.
 *
 * This operation requires a valid email address and password. The system uses bcrypt to securely compare the provided password against the stored hash. The authentication process occurs within 500ms.
 *
 * Security considerations: Passwords are never stored in plain text. Token generation follows standard JWT practices with expiration policies. Failed login attempts trigger account security protocols to prevent brute force attacks.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Member's login credentials (email and password)
 * @x-autobe-specification Authenticates member using email/password credentials. Validates password against bcrypt-stored hash, generates JWT tokens.
 * @path /econPoliticBoard/auth/member/login
 * @accessor api.functional.econPoliticBoard.auth.member.login.signIn
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function signIn(
  connection: IConnection,
  props: signIn.Props,
): Promise<signIn.Response> {
  const output: signIn.Response =
    true === connection.simulate
      ? signIn.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...signIn.METADATA,
            path: signIn.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
export namespace signIn {
  export type Props = {
    /**
     * Member's login credentials (email and password)
     */
    body: IEconPoliticBoardMember.ILogin;
  };
  export type Body = IEconPoliticBoardMember.ILogin;
  export type Response = IEconPoliticBoardMember.IAuthorized;

  export const METADATA = {
    method: "POST",
    path: "/econPoliticBoard/auth/member/login",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/econPoliticBoard/auth/member/login";
  export const random = (): IEconPoliticBoardMember.IAuthorized =>
    typia.random<IEconPoliticBoardMember.IAuthorized>();
  export const simulate = (
    connection: IConnection,
    props: signIn.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: signIn.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
