import { HttpError, IConnection } from "@nestia/fetcher";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";

import { IEconPoliticBoardMember } from "../../../../../structures/IEconPoliticBoardMember";

/**
 * Refreshes the user's access token using a valid refresh token. Validates the refresh token against the system's stored tokens in the database. Generates a new access token with 1 hour expiration and maintains the refresh token validity period of 30 days. The refresh token must be valid and not expired.
 *
 * This operation requires an existing refresh token associated with the user's account. The system validates the token against stored tokens and checks expiration. Token refresh occurs within typical request time limits without noticeable performance impact.
 *
 * Security considerations: Refresh tokens are stored securely on the client side. The endpoint validates token freshness and origin. This operation only succeeds if the refresh token is valid and associated with the requesting user.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Refresh token payload including the current refresh token
 * @x-autobe-specification Refreshes access token using valid refresh token. Validates refresh token against database, generates new access token.
 * @path /econPoliticBoard/auth/member/refresh
 * @accessor api.functional.econPoliticBoard.auth.member.refresh.refreshToken
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function refreshToken(
  connection: IConnection,
  props: refreshToken.Props,
): Promise<refreshToken.Response> {
  const output: refreshToken.Response =
    true === connection.simulate
      ? refreshToken.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...refreshToken.METADATA,
            path: refreshToken.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
export namespace refreshToken {
  export type Props = {
    /**
     * Refresh token payload including the current refresh token
     */
    body: IEconPoliticBoardMember.IRefresh;
  };
  export type Body = IEconPoliticBoardMember.IRefresh;
  export type Response = IEconPoliticBoardMember.IAuthorized;

  export const METADATA = {
    method: "POST",
    path: "/econPoliticBoard/auth/member/refresh",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/econPoliticBoard/auth/member/refresh";
  export const random = (): IEconPoliticBoardMember.IAuthorized =>
    typia.random<IEconPoliticBoardMember.IAuthorized>();
  export const simulate = (
    connection: IConnection,
    props: refreshToken.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: refreshToken.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
