/**
 * User registration creates a new account with validated email and password. This operation enforces email format validation as described in the economic_political_discussion_board_users.email field and requires password strength (8+ characters, uppercase) as documented in the registration requirements. The operation validates email uniqueness against the database before creating the account. Response includes JWT token and user object populated with the newly created user's id, email, and role.
 *
 * The registration process triggers an email verification token creation, which is handled through the economic_political_discussion_board_user_email_verifications schema with 15-minute expiration. This ensures the email address is valid before account activation.
 *
 * This endpoint is public (no authentication required), allowing guests to register new accounts.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body User registration credentials with email and password
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor user
 * @x-autobe-specification Validate email format (regex), check uniqueness against users table. Hash password using bcrypt. Create user record in economic_political_discussion_board_users table. Generate email verification token with 15-minute expiration in economic_political_discussion_board_user_email_verifications. Return JWT token valid for 24 hours and user object containing id, email, role.
 * @path /economicPoliticalDiscussionBoard/auth/user/join
 * @accessor api.functional.economicPoliticalDiscussionBoard.auth.user.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
