/**
 * This endpoint allows for the registration of new administrator accounts. The system validates the email format and password strength requirements as specified in the business model (password must be at least 8 characters with one uppercase letter). Upon successful registration, the system creates an entry in the economic_political_discussion_board_admins table with the provided credentials, initializes the account, and generates a JWT access token valid for 15 minutes and refresh token valid for 7 days. The registered admin must verify their email address before the account becomes fully active.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Admin registration data including email and password
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor admin
 * @x-autobe-specification Validates registration details against schema constraints, registers new admin via system approval workflow, stores credentials in economic_political_discussion_board_admins table, and returns authorization tokens with session setup.
 * @path /economicPoliticalDiscussionBoard/auth/admin/join
 * @accessor api.functional.economicPoliticalDiscussionBoard.auth.admin.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
