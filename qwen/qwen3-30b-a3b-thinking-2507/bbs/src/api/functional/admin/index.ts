import { IConnection } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";

import { IDiscussionBoardAdmin } from "../../structures/IDiscussionBoardAdmin";

/**
 * This endpoint retrieves the current authenticated admin's profile details,
 * including account status, role information, last login timestamp, and session
 * details. The operation accesses the discussion_board_admins table for the
 * admin's personal details and the discussion_board_admin_sessions table to
 * verify active sessions. The response includes the admin's unique identifier,
 * account email, account status (active/inactive), last login time, and token
 * expiry information. This endpoint requires authentication and is accessible
 * only to the currently logged-in admin. It serves as the primary way for admin
 * users to verify their own account state and session status within the
 * system.
 *
 * @param props.connection
 * @path /admin/me
 * @accessor api.functional.admin.me
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function me(connection: IConnection): Promise<me.Response> {
  return true === connection.simulate
    ? me.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...me.METADATA,
          path: me.path(),
          status: null,
        },
      );
}
export namespace me {
  export type Response = IDiscussionBoardAdmin;

  export const METADATA = {
    method: "GET",
    path: "/admin/me",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/admin/me";
  export const random = (): IDiscussionBoardAdmin =>
    typia.random<IDiscussionBoardAdmin>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}
