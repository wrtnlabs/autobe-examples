/**
 * Creates a new temporary guest account for unauthenticated users with limited
 * access to view content. This endpoint generates a unique identifier and
 * temporary session token without requiring credentials or email validation,
 * enabling immediate access to public content within the discussion board. The
 * registration process initializes basic guest session data including the
 * guest's unique identifier and current timestamp. Temporary session
 * information is stored in the system for tracking purposes but does not link
 * to any permanent user records. No security validation or password
 * requirements are applied to this registration flow. This operation directly
 * supports the guest actor's description as 'unauthenticated users who can view
 * content but cannot create posts or access private features' by creating the
 * minimal necessary account structure for their use case. Security
 * considerations focus on preventing excessive guest creation while maintaining
 * open access. Session lifetimes track temporary access duration, and all data
 * is stored without persistent user history to maintain guest privacy
 * standards. This join operation must be called before any other guest-oriented
 * interactions to establish a valid session token. Subsequent refresh
 * operations can then maintain this temporary access without repeated
 * registration.
 *
 * @param props.connection
 * @param props.body Guest account registration payload. Contains minimal data
 *   for temporary session initialization.
 * @setHeader token.access Authorization
 *
 * @path /auth/guest/join
 * @accessor api.functional.auth.guest.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
export namespace join {
  export type Props = {
    /**
     * Guest account registration payload. Contains minimal data for
     * temporary session initialization.
     */
    body: IDiscussionBoardMember.IJoin;
  };
  export type Body = IDiscussionBoardMember.IJoin;
  export type Response = IDiscussionBoardMember.IAuthorized;

  export const METADATA = {
    method: "POST",
    path: "/auth/guest/join",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/guest/join";
  export const random = (): IDiscussionBoardMember.IAuthorized =>
    typia.random<IDiscussionBoardMember.IAuthorized>();
  export const simulate = (
    connection: IConnection,
    props: join.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: join.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

