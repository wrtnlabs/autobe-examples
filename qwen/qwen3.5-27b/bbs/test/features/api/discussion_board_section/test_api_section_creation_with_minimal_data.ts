/**
 * Test section creation with minimal data (name only, no description).
 *
 * This test verifies that an authenticated administrator can create a section
 * by providing only the required name field, without the optional description.
 * The created section should have a null description and all required fields
 * properly populated.
 */
export async function test_api_section_creation_with_minimal_data(
  connection: api.IConnection,
): Promise<void> {
  // 1. Administrator setup
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_administrator_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  // 2. Create section with minimal data (name only, no description)
  const section =
    await api.functional.discussionBoard.administrator.sections.create(
      adminConnection,
      {
        body: {
          name: "Economy",
        } satisfies IDiscussionBoardSection.ICreate,
      },
    );
  typia.assert(section);
  // 3. Validate response
  TestValidator.equals("section name matches input", section.name, "Economy");
  TestValidator.equals("description is null", section.description, null);
  TestValidator.predicate(
    "has valid UUID",
    /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i.test(
      section.id,
    ),
  );
  TestValidator.predicate(
    "created_at is valid date-time",
    /^[0-9]{4}-[0-9]{2}-[0-9]{2}T[0-9]{2}:[0-9]{2}:[0-9]{2}/.test(
      section.created_at,
    ),
  );
  TestValidator.predicate(
    "updated_at is valid date-time",
    /^[0-9]{4}-[0-9]{2}-[0-9]{2}T[0-9]{2}:[0-9]{2}:[0-9]{2}/.test(
      section.updated_at,
    ),
  );
}
