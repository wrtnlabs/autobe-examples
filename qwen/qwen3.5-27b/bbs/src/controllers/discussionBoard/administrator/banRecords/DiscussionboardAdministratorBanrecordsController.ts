import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IDiscussionBoardBanRecord } from "../../../../api/structures/IDiscussionBoardBanRecord";
import { IPageIDiscussionBoardBanRecord } from "../../../../api/structures/IPageIDiscussionBoardBanRecord";
import { AdministratorAuth } from "../../../../decorators/AdministratorAuth";
import { AdministratorPayload } from "../../../../decorators/payload/AdministratorPayload";
import { getDiscussionBoardAdministratorBanRecordsBanRecordId } from "../../../../providers/getDiscussionBoardAdministratorBanRecordsBanRecordId";
import { patchDiscussionBoardAdministratorBanRecords } from "../../../../providers/patchDiscussionBoardAdministratorBanRecords";
