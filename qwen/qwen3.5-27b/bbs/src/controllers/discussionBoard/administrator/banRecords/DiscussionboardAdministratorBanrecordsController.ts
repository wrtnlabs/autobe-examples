@Controller("/discussionBoard/administrator/banRecords")
export class DiscussionboardAdministratorBanrecordsController {
  /**
   * Create a new ban record to suspend a user account from the discussion board platform.
   *
   * This operation allows administrators to ban members or other administrators who have violated platform policies or engaged in harmful behavior. When a ban is created, the system records the ban reason, timestamp, and which administrator imposed the ban. The banned user will be prevented from logging in to the platform.
   *
   * The ban record maintains a complete audit trail for moderation accountability. All existing articles and comments written by the banned user are preserved in the system, ensuring content history is maintained even when user accounts are suspended.
   *
   * Administrators must provide a detailed ban reason explaining the policy violation or harmful behavior that warranted the ban. This reason is stored for potential appeal purposes and audit trail maintenance. The system prevents duplicate ban records for users who are already banned.
   *
   * This operation requires administrator authentication and appropriate privileges. Only authenticated administrators can create ban records. The operation links the ban to either a member account or administrator account through the polymorphic ownership pattern.
   *
   * @param connection
   * @param body Ban record creation data including target user and reason
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Validate that the requesting user is an authenticated administrator with appropriate privileges.
   *
   * Extract the target user ID and actor type from the request body. Validate that the ban reason is provided and not empty.
   *
   * Check if the target user already has an active ban record by querying discussion_board_ban_records where the user is referenced in either discussion_board_ban_record_of_members or discussion_board_ban_record_of_administrators and unbanned_at is null. If an active ban exists, reject the request.
   *
   * Create a new ban record in discussion_board_ban_records with:
   * - id: generate UUID
   * - banned_by: ID of the administrator creating the ban (from authenticated session)
   * - actor_type: from request body ('member' or 'administrator')
   * - ban_reason: from request body
   * - banned_at: current timestamp
   * - unbanned_at: null
   * - created_at: current timestamp
   * - updated_at: current timestamp
   *
   * Create the appropriate subtype record:
   * - If actor_type is 'member', create record in discussion_board_ban_record_of_members with the ban record ID and member ID
   * - If actor_type is 'administrator', create record in discussion_board_ban_record_of_administrators with the ban record ID and administrator ID
   *
   * Update the target user's banned flag to true in their respective table (discussion_board_members or discussion_board_administrators).
   *
   * Return the created ban record with full details including the administrator who imposed the ban.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedBody()
    body: IDiscussionBoardBanRecord.ICreate,
  ): Promise<IDiscussionBoardBanRecord> {
    try {
      return await postDiscussionBoardAdministratorBanRecords({
        administrator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a filtered and paginated list of ban records from the discussion board platform.
   *
   * This operation provides administrators with comprehensive search and filtering capabilities for reviewing user suspension history. Ban records are audit trail entries that document when users (members or administrators) were banned, the reason for the ban, which administrator imposed it, and when the ban was lifted.
   *
   * The operation supports filtering by ban status (active or lifted), actor type (member or administrator), date ranges for ban timestamps, and text search on ban reasons. Results are returned with cursor-based pagination for efficient browsing of large datasets.
   *
   * Only authenticated administrators have access to this endpoint. The returned ban record summaries include essential information such as the banned user identifier, ban reason, timestamps, and the administrator who imposed the ban. For detailed information about a specific ban record, use the GET /banRecords/{banRecordId} endpoint.
   *
   * This operation is part of the moderation and audit functionality, enabling administrators to review enforcement actions, track ban history for specific users, and maintain accountability for moderation decisions.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for ban records
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Query the discussion_board_ban_records table with pagination and filtering support.
   *
   * 1. Parse request body for search criteria: actor_type filter, ban status filter (active vs lifted based on unbanned_at null check), banned_at date range, ban_reason text search.
   *
   * 2. Apply authorization check: verify the requesting user is an authenticated administrator (regular or super).
   *
   * 3. Build query with filters:
   *    - actor_type: exact match on 'member' or 'administrator'
   *    - status: filter by unbanned_at IS NULL (active) or IS NOT NULL (lifted)
   *    - banned_at range: BETWEEN start and end timestamps
   *    - ban_reason: ILIKE search with %text% for partial matching
   *
   * 4. Apply sorting: default by banned_at DESC (most recent first), support custom sort fields.
   *
   * 5. Apply pagination: use cursor-based pagination with limit (default 20, max 100) and cursor parameters.
   *
   * 6. Join with discussion_board_administrators to fetch banned_by display_name for the summary.
   *
   * 7. For actor_type='member', optionally join with discussion_board_ban_record_of_members to get member details.
   *
   * 8. For actor_type='administrator', optionally join with discussion_board_ban_record_of_administrators to get administrator details.
   *
   * 9. Return paginated results with metadata: current page, total count, has_next, next_cursor.
   *
   * 10. Handle edge cases: empty results, invalid filter combinations, missing cursor values.
   *
   * 11. Log access for audit trail: record which administrator viewed which ban records.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedBody()
    body: IDiscussionBoardBanRecord.IRequest,
  ): Promise<IPageIDiscussionBoardBanRecord.ISummary> {
    try {
      return await patchDiscussionBoardAdministratorBanRecords({
        administrator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific ban record by its unique identifier.
   *
   * This operation returns comprehensive information about a user suspension action, including the ban reason, timestamps for when the ban was imposed and lifted (if applicable), the administrator who imposed the ban, and the user who was banned. The ban record serves as an audit trail for moderation accountability and enforcement history.
   *
   * The response includes nested objects for both the administrator who imposed the ban (with their display name, email, and grade) and the banned user (with their account details). This enables administrators to review the complete context of moderation actions.
   *
   * Access to this operation is restricted to authenticated administrators only. Regular members and guests cannot view ban records to protect the privacy of moderation actions and maintain platform governance integrity.
   *
   * @param connection
   * @param banRecordId Unique identifier of the ban record to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Query the discussion_board_ban_records table by primary key (id) matching the banRecordId path parameter.
   *
   * Join with discussion_board_administrators on banned_by to retrieve the administrator who imposed the ban.
   *
   * Join with the appropriate subtype table (discussion_board_ban_record_of_members or discussion_board_ban_record_of_administrators) based on the actor_type field to retrieve the banned user's details.
   *
   * For actor_type = 'member', join discussion_board_ban_record_of_members to get discussion_board_member_id, then join discussion_board_members.
   *
   * For actor_type = 'administrator', join discussion_board_ban_record_of_administrators to get discussion_board_administrator_id, then join discussion_board_administrators.
   *
   * Return the ban record with nested bannedBy administrator object and bannedUser object (either member or administrator).
   *
   * Validate that the requesting user is an administrator before allowing access.
   *
   * Return 404 if ban record not found.
   *
   * Return 403 if requesting user is not an administrator.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":banRecordId")
  public async at(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("banRecordId")
    banRecordId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardBanRecord> {
    try {
      return await getDiscussionBoardAdministratorBanRecordsBanRecordId({
        administrator,
        banRecordId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing ban record to modify ban status or details.
   *
   * This operation allows administrators to modify ban records, primarily to lift bans by setting the unbanned_at timestamp. When a user is unbanned, the original ban record is preserved for audit purposes, with only the unbanned_at field being updated to indicate when the ban was lifted.
   *
   * The ban record maintains critical audit information including the ban reason, the timestamp when the ban was imposed (banned_at), and the administrator who imposed the ban (banned_by). These fields are immutable to ensure the integrity of the moderation audit trail.
   *
   * Security considerations: Only administrators with appropriate privileges can update ban records. The system validates that the requesting administrator has sufficient clearance to modify ban records. Regular members and guests cannot access this operation.
   *
   * Related operations: Use GET /banRecords/{banRecordId} to retrieve ban record details before updating. Use PATCH /banRecords to search and list ban records with filtering options. Use POST /banRecords to create new ban records when banning users.
   *
   * @param connection
   * @param banRecordId Unique identifier of the ban record to update
   * @param body Update data for the ban record
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Update the ban record identified by banRecordId with provided fields.
   *
   * 1. Validate that the requesting user is an administrator with appropriate privileges to modify ban records.
   * 2. Retrieve the ban record from discussion_board_ban_records table by ID.
   * 3. If updating unbanned_at: Verify the ban record exists and is currently active (unbanned_at is null). Set unbanned_at to current timestamp.
   * 4. If updating ban_reason: Allow only if the ban is still active (unbanned_at is null). Update the ban_reason field with the new value.
   * 5. Update the updated_at timestamp automatically.
   * 6. Return the updated ban record with full details including related administrator and user information.
   * 7. Handle edge cases: Ban record not found (404), insufficient privileges (403), attempting to modify immutable fields (400), ban already lifted (400 if trying to unban again).
   *
   * The banned_at, banned_by, and actor_type fields are immutable and cannot be modified through this operation to preserve audit trail integrity.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":banRecordId")
  public async update(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("banRecordId")
    banRecordId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardBanRecord.IUpdate,
  ): Promise<IDiscussionBoardBanRecord> {
    try {
      return await putDiscussionBoardAdministratorBanRecordsBanRecordId({
        administrator,
        banRecordId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
