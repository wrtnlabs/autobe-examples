import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IDiscussionBoardAdminRequest } from "../../../../api/structures/IDiscussionBoardAdminRequest";
import { IPageIDiscussionBoardAdminRequest } from "../../../../api/structures/IPageIDiscussionBoardAdminRequest";
import { AdministratorAuth } from "../../../../decorators/AdministratorAuth";
import { AdministratorPayload } from "../../../../decorators/payload/AdministratorPayload";
import { getDiscussionBoardAdministratorAdminRequestsRequestId } from "../../../../providers/getDiscussionBoardAdministratorAdminRequestsRequestId";
import { patchDiscussionBoardAdministratorAdminRequests } from "../../../../providers/patchDiscussionBoardAdministratorAdminRequests";

@Controller("/discussionBoard/administrator/admin-requests")
export class DiscussionboardAdministratorAdmin_requestsController {
  /**
   * Retrieve a filtered and paginated list of administrator privilege escalation requests.
   *
   * This operation enables users to search and browse administrator promotion requests with flexible filtering options. Members can view only their own submitted requests, while administrators have access to view all requests across the platform. The search supports filtering by request status (pending, approved, rejected), submission date ranges, and other criteria.
   *
   * The response includes summarized request information optimized for list displays, including request ID, submitting member details, status, submission timestamp, and review information when available. For approved or rejected requests, the reviewing administrator information is included.
   *
   * Security considerations ensure proper data isolation: regular members can only access their own requests, while administrators can view the complete request history. Super administrators have full access to all requests regardless of status.
   *
   * This operation is commonly used together with GET /admin-requests/{requestId} to retrieve detailed information about a specific request after identifying it in the list view.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for admin requests
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Query the discussion_board_admin_requests table with pagination and filtering support.
   *
   * Apply the following filters from the request body:
   * - status: Filter by request status (pending, approved, rejected)
   * - submittedAtFrom/submittedAtTo: Date range filter on submitted_at column
   * - reviewedAtFrom/reviewedAtTo: Date range filter on reviewed_at column
   * - search: Full-text search on reason field
   *
   * For authorization:
   * - If actor is member: Filter results to only include requests where discussion_board_member_id equals the authenticated member's ID
   * - If actor is administrator: No member ID filter applied, return all requests
   *
   * Join with discussion_board_members to include member information (email, display name) in the response.
   * Join with discussion_board_administrators (left join) to include reviewing administrator information when reviewed_at is not null.
   *
   * Apply sorting based on request parameters (default: submitted_at descending).
   * Apply pagination using cursor-based or offset-based pagination as configured.
   *
   * Return paginated response with IPageIDiscussionBoardAdminRequest.ISummary structure containing pagination metadata and data array.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedBody()
    body: IDiscussionBoardAdminRequest.IRequest,
  ): Promise<IPageIDiscussionBoardAdminRequest.ISummary> {
    try {
      return await patchDiscussionBoardAdministratorAdminRequests({
        administrator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific administrator privilege escalation request by its unique identifier.
   *
   * This operation returns complete information about an administrator request, including the applicant's reason for requesting elevated privileges, the current status of the request (pending, approved, or rejected), submission timestamp, and review details if a decision has been made. The response includes the applicant's information and, if applicable, the decision context provided by the reviewing super administrator.
   *
   * Access to this endpoint is restricted to administrators only. This enables administrators to review request details before making approval or rejection decisions as part of their governance responsibilities. The operation queries the discussion_board_admin_requests table and joins with discussion_board_admin_request_decisions to provide comprehensive request information.
   *
   * The request status indicates the current state: 'pending' means the request is awaiting super administrator review, 'approved' indicates the member has been promoted to regular administrator status, and 'rejected' means the request was denied and the member retains their current permissions. When a decision has been made, the response includes the decision type and any additional context provided by the reviewing super administrator.
   *
   * Related operations include PATCH /admin-requests for listing and filtering requests, POST /admin-requests for submitting new requests, and GET /admin-requests/{requestId}/decision for detailed decision information.
   *
   * @param connection
   * @param requestId Unique identifier of the administrator privilege escalation request to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Query the discussion_board_admin_requests table for a record matching the provided requestId UUID.
   *
   * Validate that the requesting user has permission to view this request:
   * - Members can only view their own admin requests (match discussion_board_member_id with authenticated user)
   * - Administrators can view any admin request for review purposes
   * - Super administrators can view all admin requests
   *
   * Perform a JOIN with discussion_board_admin_request_decisions to include decision details if a decision exists (decision_type, decision_context, reviewer information).
   *
   * Perform a LEFT JOIN with discussion_board_members to include applicant information (email, display_name).
   *
   * Return 404 Not Found if the request record does not exist or has been soft-deleted (deleted_at is not null).
   *
   * Return 403 Forbidden if the user does not have permission to view this specific request.
   *
   * Include all fields: id, discussion_board_member_id, discussion_board_administrator_id, reason, status, submitted_at, reviewed_at, created_at, updated_at, and nested decision object if exists.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":requestId")
  public async at(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("requestId")
    requestId: string & tags.Format<"uuid">,
  ): Promise<IDiscussionBoardAdminRequest> {
    try {
      return await getDiscussionBoardAdministratorAdminRequestsRequestId({
        administrator,
        requestId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
