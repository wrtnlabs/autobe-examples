import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IDiscussionBoardTag } from "../../../../api/structures/IDiscussionBoardTag";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { postDiscussionBoardMemberTags } from "../../../../providers/postDiscussionBoardMemberTags";

@Controller("/discussionBoard/member/tags")
export class DiscussionboardMemberTagsController {
  /**
   * Create a new tag for categorizing articles in the discussion board system.
   *
   * This operation allows registered members to create new tags that can be used to categorize and organize articles. Tags are free-text labels with no predefined vocabulary, allowing users to create custom categorization schemes. Tag names are case-sensitive, meaning "Economy" and "economy" are treated as distinct tags.
   *
   * The tag name must be non-empty and will be stored exactly as entered, preserving capitalization, spacing, and special characters. Each tag name must be unique across the system; attempting to create a tag with a name that already exists will result in an error.
   *
   * Tags created through this endpoint persist independently and can be assigned to articles through the article creation or editing workflows. Tags are soft-deleted rather than permanently removed, preserving historical associations with articles.
   *
   * Only authenticated members can create new tags. Guests do not have permission to create tags. This operation is typically used when a member wants to pre-create a tag before assigning it to articles, though tags can also be created implicitly during article creation or editing.
   *
   * @param connection
   * @param body Tag creation data containing the tag name
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Create a new tag record in the discussion_board_tags table.
   *
   * 1. Validate that the requesting user is an authenticated member (not a guest).
   * 2. Validate that the tag name in the request body is non-empty and not just whitespace.
   * 3. Check if a tag with the exact name already exists (case-sensitive comparison) and is not soft-deleted.
   * 4. If tag exists, return 409 Conflict error.
   * 5. Insert new record into discussion_board_tags with:
   *    - id: generate UUID
   *    - name: from request body (preserve exact text)
   *    - created_at: current timestamp
   *    - updated_at: current timestamp
   *    - deleted_at: null
   * 6. Return the created tag entity with all fields.
   *
   * Error handling:
   * - 401 Unauthorized: if user is not authenticated
   * - 403 Forbidden: if user is a guest (only members can create tags)
   * - 400 Bad Request: if tag name is empty or whitespace only
   * - 409 Conflict: if tag name already exists
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IDiscussionBoardTag.ICreate,
  ): Promise<IDiscussionBoardTag> {
    try {
      return await postDiscussionBoardMemberTags({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
