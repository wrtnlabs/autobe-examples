import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IDiscussionBoardComment } from "../../../../../api/structures/IDiscussionBoardComment";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { deleteDiscussionBoardMemberArticlesArticleIdCommentsCommentId } from "../../../../../providers/deleteDiscussionBoardMemberArticlesArticleIdCommentsCommentId";
import { postDiscussionBoardMemberArticlesArticleIdComments } from "../../../../../providers/postDiscussionBoardMemberArticlesArticleIdComments";
import { putDiscussionBoardMemberArticlesArticleIdCommentsCommentId } from "../../../../../providers/putDiscussionBoardMemberArticlesArticleIdCommentsCommentId";

@Controller("/discussionBoard/member/articles/:articleId/comments")
export class DiscussionboardMemberArticlesCommentsController {
  /**
   * Create a new comment on a discussion board article.
   *
   * This operation allows registered members to post comments on articles as part of community discussions. Comments are stored in the discussion_board_comments table and are displayed in chronological order (oldest first) when viewing an article. Each comment is authored by a registered member and permanently associated with a specific article.
   *
   * Security and validation: Only authenticated members can create comments. Guests and banned users are prevented from posting. The system validates that the target article exists, has not been deleted, and belongs to an active section. Comment content must be non-empty after trimming whitespace.
   *
   * The comment structure is single-level with no nested replies or threaded discussions. All comments on an article appear as a flat, linear list. When an article is deleted, all its associated comments are automatically removed through cascading delete.
   *
   * Related operations: Use GET /articles/{articleId}/comments to retrieve all comments on an article, PUT /articles/{articleId}/comments/{commentId} to edit your own comment, and DELETE /articles/{articleId}/comments/{commentId} to remove your own comment.
   *
   * @param connection
   * @param articleId UUID of the article to comment on
   * @param body Comment creation data including content
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Validate that the authenticated user is a registered member (not guest or banned).
   *
   * Verify the article exists by querying discussion_board_articles where id = articleId and deleted_at IS NULL.
   *
   * Validate that the article's section still exists (section should not be deleted).
   *
   * Check that the authenticated member is not banned by verifying discussion_board_members banned status.
   *
   * Create a new comment record in discussion_board_comments with:
   * - id: generate UUID
   * - discussion_board_article_id: from path parameter articleId
   * - discussion_board_member_id: from authenticated session
   * - content: from request body (validate non-empty, trim whitespace)
   * - created_at: current timestamp
   * - updated_at: current timestamp
   * - deleted_at: NULL
   *
   * Return the created comment with all fields including generated id and timestamps.
   *
   * Handle errors: article not found, article deleted, user banned, user not authenticated, empty content.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardComment.ICreate,
  ): Promise<IDiscussionBoardComment> {
    try {
      return await postDiscussionBoardMemberArticlesArticleIdComments({
        member,
        articleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing comment's content on a discussion board article.
   *
   * This operation allows authenticated users to modify the text content of a comment they have authored. Members can only edit their own comments, while administrators have the privilege to edit any comment regardless of authorship. The comment must be active (not deleted) and must belong to the specified article.
   *
   * The update operation modifies only the content field and the updated_at timestamp. All other fields including the author identity, article association, and creation timestamp remain unchanged. This ensures audit trail integrity while allowing content corrections.
   *
   * Comments are displayed in chronological order with oldest first, and the updated comment maintains its original position in the sequence. The author's display name and original creation time are preserved, with only the content text being replaced.
   *
   * Related operations include GET /articles/{articleId}/comments/{commentId} for retrieving a single comment, DELETE /articles/{articleId}/comments/{commentId} for removing a comment, and POST /articles/{articleId}/comments for creating new comments.
   *
   * @param connection
   * @param articleId The unique identifier of the article to which this comment belongs
   * @param commentId The unique identifier of the comment to update
   * @param body Updated content for the comment
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Update a comment's content with authorization validation.
   *
   * 1. Parse path parameters: articleId (UUID) and commentId (UUID)
   * 2. Authenticate the request and extract the actor (member or administrator)
   * 3. Query discussion_board_comments table for the comment record:
   *    - WHERE id = commentId AND discussion_board_article_id = articleId
   *    - Ensure comment belongs to the specified article
   *    - Check deleted_at IS NULL (comment must be active)
   * 4. Verify authorization:
   *    - If actor is member: verify discussion_board_member_id matches actor's ID
   *    - If actor is administrator: allow any comment update
   *    - Reject if neither condition is met (403 Forbidden)
   * 5. Update the comment record:
   *    - Set content field from request body
   *    - Update updated_at to current timestamp
   *    - Do not modify created_at, discussion_board_article_id, or discussion_board_member_id
   * 6. Return the updated comment with full details including author information
   *
   * Error handling:
   * - 404 if comment not found or deleted
   * - 404 if article not found
   * - 403 if unauthorized (member trying to edit another's comment)
   * - 400 if content is empty or exceeds length limits
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":commentId")
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardComment.IUpdate,
  ): Promise<IDiscussionBoardComment> {
    try {
      return await putDiscussionBoardMemberArticlesArticleIdCommentsCommentId({
        member,
        articleId,
        commentId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a specific comment from an article in the discussion board.
   *
   * This operation removes a comment from the discussion_board_comments table, completely deleting the comment content and removing it from all article views. The comment will no longer be accessible through any API operations or user interfaces.
   *
   * Authorization is enforced based on comment ownership and user roles. Only the original author of the comment or an administrator can delete the comment. When a member deletes their own comment, the system permanently removes it from all articles. When an administrator deletes a comment, the system removes it regardless of the original author.
   *
   * The comment must exist and not already be deleted. If the comment does not exist or has already been deleted, the system rejects the request with an appropriate error. Banned users cannot delete content, and the system enforces this restriction by checking account status before allowing the operation.
   *
   * This operation is part of the comment management workflow, complementing comment creation, viewing, and editing operations. It ensures users maintain control over their own content while administrators retain moderation capabilities.
   *
   * @param connection
   * @param articleId The unique identifier of the article this comment belongs to
   * @param commentId The unique identifier of the comment to delete
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Delete a comment from the discussion_board_comments table using soft deletion.
   *
   * Authorization verification:
   * 1. Retrieve the comment by commentId from discussion_board_comments table
   * 2. Verify the comment exists and is not already deleted (deleted_at is null)
   * 3. Check if the authenticated user is the comment author by comparing discussion_board_member_id
   * 4. If not the author, verify the user has administrator privileges
   * 5. Reject with 403 Forbidden if authorization fails
   *
   * Deletion process:
   * 1. Update the comment record by setting deleted_at to current timestamp
   * 2. This implements soft deletion to preserve audit trail
   * 3. The comment will no longer appear in active comment lists
   * 4. Related data (article reference) remains intact
   *
   * Error handling:
   * - Return 404 Not Found if comment does not exist
   * - Return 404 Not Found if comment is already deleted
   * - Return 403 Forbidden if user is not authorized (not author and not admin)
   * - Return 401 Unauthorized if user is not authenticated
   *
   * The articleId parameter is used to establish the hierarchical path structure but the actual deletion operates on the comment record directly.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":commentId")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteDiscussionBoardMemberArticlesArticleIdCommentsCommentId(
        {
          member,
          articleId,
          commentId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
