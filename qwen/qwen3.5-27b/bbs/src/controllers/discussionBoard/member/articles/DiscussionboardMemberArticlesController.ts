import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IDiscussionBoardArticle } from "../../../../api/structures/IDiscussionBoardArticle";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { deleteDiscussionBoardMemberArticlesArticleId } from "../../../../providers/deleteDiscussionBoardMemberArticlesArticleId";
import { postDiscussionBoardMemberArticles } from "../../../../providers/postDiscussionBoardMemberArticles";
import { putDiscussionBoardMemberArticlesArticleId } from "../../../../providers/putDiscussionBoardMemberArticlesArticleId";

@Controller("/discussionBoard/member/articles")
export class DiscussionboardMemberArticlesController {
  /**
   * Create a new article in a discussion board section.
   *
   * This operation allows authenticated members to create articles with title, content, section assignment, and optional tags. Every article must be assigned to exactly one active section for organizational categorization. The article is automatically associated with the authenticated member's account and creation session for ownership tracking and audit purposes.
   *
   * Security and authorization: Only authenticated members can create articles. Guests and banned users are rejected. The system validates that the member's account is active and not banned before allowing article creation. The authenticated member's ID and session ID are automatically captured from the request context.
   *
   * Section validation: The specified section must exist and be active (not soft-deleted). If the section has been deleted by an administrator, the article creation is rejected with an error. The system ensures every article belongs to exactly one section as required by business rules.
   *
   * Tag assignment: Articles can have multiple free-text tags assigned for categorization and filtering. Tags are created dynamically if they don't already exist in the system. The many-to-many relationship between articles and tags is managed through the discussion_board_article_tags junction table.
   *
   * Related operations: After creation, use GET /articles/{articleId} to retrieve the full article details. Use PATCH /articles to search and list articles with filtering. Use PUT /articles/{articleId} to edit the article. Use DELETE /articles/{articleId} to delete the article.
   *
   * @param connection
   * @param body Article creation data including title, content, section, and optional tags
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Service layer implementation for article creation:
   *
   * 1. Authentication: Extract member ID and session ID from the authenticated request context. Verify the member exists and is not banned (banned = false) and not soft-deleted (deleted_at is null).
   *
   * 2. Section validation: Query discussion_board_sections by the provided sectionId. Verify the section exists and is active (deleted_at is null). If section is deleted or doesn't exist, throw a validation error.
   *
   * 3. Article creation: Insert a new record into discussion_board_articles with:
   *    - id: Generate new UUID
   *    - discussion_board_section_id: From request body
   *    - discussion_board_member_id: From authenticated context
   *    - discussion_board_member_session_id: From authenticated context
   *    - title: From request body (validate not empty)
   *    - content: From request body (validate not empty)
   *    - created_at: Current timestamp
   *    - updated_at: Current timestamp
   *    - deleted_at: null
   *
   * 4. Tag processing: For each tag name in the request:
   *    - Query discussion_board_tags by name (case-sensitive, exact match)
   *    - If tag exists, use its ID
   *    - If tag doesn't exist, insert new record into discussion_board_tags with generated UUID, name, and current timestamp
   *    - Insert record into discussion_board_article_tags linking article ID and tag ID with current created_at timestamp
   *
   * 5. Return the created article with full details including author display name and assigned tags.
   *
   * Error handling:
   * - Return 401 if not authenticated
   * - Return 403 if member is banned
   * - Return 404 if section doesn't exist or is deleted
   * - Return 400 if title or content is empty
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IDiscussionBoardArticle.ICreate,
  ): Promise<IDiscussionBoardArticle> {
    try {
      return await postDiscussionBoardMemberArticles({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing article's title, content, and section assignment.
   *
   * This operation allows authenticated users to modify the content of articles they own. Only the article's original author or an administrator can perform updates. Regular members can only update articles they created, while administrators have elevated permissions to modify any article for content moderation purposes. This dual authorization model ensures content integrity while enabling necessary editorial oversight.
   *
   * The operation supports partial updates - clients can provide only the fields they wish to change while leaving others unchanged. Article updates are restricted to active articles only; soft-deleted articles cannot be updated through this endpoint. The soft-delete status (deleted_at field) is preserved and cannot be modified, ensuring that this operation does not restore deleted content.
   *
   * Section reassignment is supported, allowing articles to be moved between sections. When changing an article's section, the target section must exist and be active (not deleted). This enables administrators to reorganize content as section structures evolve over time.
   *
   * The operation preserves critical audit information including the original author, creation timestamp, and soft-delete status. The updated_at timestamp is automatically refreshed to reflect the modification time, maintaining an accurate audit trail for content changes. This aligns with the discussion_board_articles table schema which tracks both created_at and updated_at for revision history.
   *
   * @param connection
   * @param articleId Unique identifier of the article to update (UUID format)
   * @param body Article update data including title, content, and optional section reassignment
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Update an existing article's title, content, and/or section assignment.
   *
   * Authorization:
   * - Verify authenticated user is either the article's author (discussion_board_member_id matches current user) OR has administrator role
   * - Reject with 403 Forbidden if unauthorized
   *
   * Validation:
   * - Verify article exists by articleId
   * - Verify article is not soft-deleted (deleted_at is NULL)
   * - If sectionId provided in request, verify section exists and is not deleted
   * - Validate title is non-empty string
   * - Validate content is non-empty string
   * - If updating section, ensure target section is active (deleted_at is NULL)
   *
   * Business Logic:
   * - Update title field if provided in request
   * - Update content field if provided in request
   * - Update discussion_board_section_id if sectionId provided in request
   * - Update updated_at timestamp to current time
   * - Preserve discussion_board_member_id (author cannot change)
   * - Preserve created_at timestamp
   * - Preserve deleted_at value (this is not a restore operation)
   *
   * Database Operations:
   * - Single UPDATE query on discussion_board_articles table
   * - SET title = ?, content = ?, discussion_board_section_id = ?, updated_at = ?
   * - WHERE id = ? AND deleted_at IS NULL
   * - Use transaction if section change is involved to ensure referential integrity
   *
   * Error Handling:
   * - 404 Not Found: article does not exist or is soft-deleted
   * - 403 Forbidden: user is not article author and not administrator
   * - 400 Bad Request: invalid title, content, or sectionId
   * - 400 Bad Request: target section does not exist or is deleted
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":articleId")
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IDiscussionBoardArticle.IUpdate,
  ): Promise<IDiscussionBoardArticle> {
    try {
      return await putDiscussionBoardMemberArticlesArticleId({
        member,
        articleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete an article from the discussion board platform.
   *
   * This operation permanently removes an article from all public views and listings. When an article is deleted, the system also cascades deletion to all associated comments and attachments to maintain data integrity and prevent orphaned records.
   *
   * Authorization is enforced based on user roles and ownership:
   *
   * - **Article Authors**: Registered members can delete articles they created. The system verifies that the requesting user's member ID matches the article's author ID before allowing deletion.
   * - **Administrators**: Administrators have elevated permissions to delete any article regardless of authorship. This enables content moderation and enforcement of community guidelines.
   * - **Banned Users**: Users with banned accounts cannot perform deletion operations, even on their own articles.
   *
   * The deletion process uses soft deletion by setting the deleted_at timestamp. This preserves the article record in the database for audit purposes while removing it from active article listings, search results, and section views. Soft deletion ensures historical data integrity and supports potential restoration workflows.
   *
   * Related operations:
   *
   * - `PATCH /articles` - List and search articles with filters
   * - `GET /articles/{articleId}` - Retrieve a specific article by ID
   * - `PUT /articles/{articleId}` - Update an existing article
   * - `POST /articles` - Create a new article
   *
   * @param connection
   * @param articleId Unique identifier of the article to delete
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Validate the articleId parameter as a UUID format string.
   *
   * Retrieve the article record from discussion_board_articles table using the articleId.
   *
   * Verify authorization:
   * 1. Check if the requesting user is an administrator - if yes, allow deletion
   * 2. If not administrator, verify the requesting user's member ID matches the article's discussion_board_member_id
   * 3. Check if the requesting user's account is banned - reject if banned
   *
   * Perform soft deletion:
   * 1. Set deleted_at timestamp to current time on the article record
   * 2. Cascade soft delete to all comments in discussion_board_comments where discussion_board_article_id matches
   * 3. Cascade delete to all attachments associated with the article
   * 4. Cascade delete to all article views in discussion_board_article_views
   * 5. Cascade delete to all tag assignments in discussion_board_article_tags
   *
   * Return 204 No Content status on successful deletion.
   *
   * Handle edge cases:
   * - Return 404 Not Found if article does not exist
   * - Return 403 Forbidden if user lacks authorization
   * - Return 403 Forbidden if user account is banned
   * - Return 400 Bad Request if articleId is invalid UUID format
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":articleId")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteDiscussionBoardMemberArticlesArticleId({
        member,
        articleId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
