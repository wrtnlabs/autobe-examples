/**
 * Delete a specific comment from an article in the discussion board.
 *
 * This operation removes a comment from active view using soft deletion, which preserves the comment record in the database while marking it as deleted. The comment will no longer appear in comment lists or article views, but the data remains available for audit purposes.
 *
 * Authorization is enforced based on comment ownership and user roles. Only the original author of the comment or an administrator can delete the comment. When a member deletes their own comment, the system permanently removes it from all articles. When an administrator deletes a comment, the system removes it regardless of the original author.
 *
 * The comment must exist and not already be deleted. If the comment does not exist or has already been deleted, the system rejects the request with an appropriate error. Banned users cannot delete content, and the system enforces this restriction by checking account status before allowing the operation.
 *
 * This operation is part of the comment management workflow, complementing comment creation, viewing, and editing operations. It ensures users maintain control over their own content while administrators retain moderation capabilities.
 *
 * @param props.connection
 * @param props.articleId The unique identifier of the article this comment belongs to
 * @param props.commentId The unique identifier of the comment to delete
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor administrator
 * @x-autobe-specification Delete a comment from the discussion_board_comments table using soft deletion.
 *
 * Authorization verification:
 * 1. Retrieve the comment by commentId from discussion_board_comments table
 * 2. Verify the comment exists and is not already deleted (deleted_at is null)
 * 3. Check if the authenticated user is the comment author by comparing discussion_board_member_id
 * 4. If not the author, verify the user has administrator privileges
 * 5. Reject with 403 Forbidden if authorization fails
 *
 * Deletion process:
 * 1. Update the comment record by setting deleted_at to current timestamp
 * 2. This implements soft deletion to preserve audit trail
 * 3. The comment will no longer appear in active comment lists
 * 4. Related data (article reference) remains intact
 *
 * Error handling:
 * - Return 404 Not Found if comment does not exist
 * - Return 404 Not Found if comment is already deleted
 * - Return 403 Forbidden if user is not authorized (not author and not admin)
 * - Return 401 Unauthorized if user is not authenticated
 *
 * The articleId parameter is used to establish the hierarchical path structure but the actual deletion operates on the comment record directly.
 * @path /discussionBoard/administrator/articles/:articleId/comments/:commentId
 * @accessor api.functional.discussionBoard.administrator.articles.comments.erase
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function erase(
  connection: IConnection,
  props: erase.Props,
): Promise<void> {
  return true === connection.simulate
    ? erase.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...erase.METADATA,
          path: erase.path(props),
          status: null,
        },
      );
}
export namespace erase {
  export type Props = {
    /**
     * The unique identifier of the article this comment belongs to
     */
    articleId: string & tags.Format<"uuid">;

    /**
     * The unique identifier of the comment to delete
     */
    commentId: string & tags.Format<"uuid">;
  };

  export const METADATA = {
    method: "DELETE",
    path: "/discussionBoard/administrator/articles/:articleId/comments/:commentId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/discussionBoard/administrator/articles/${encodeURIComponent(props.articleId ?? "null")}/comments/${encodeURIComponent(props.commentId ?? "null")}`;
  export const random = (): void => typia.random<void>();
  export const simulate = (
    connection: IConnection,
    props: erase.Props,
  ): void => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: erase.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("articleId")(() => typia.assert(props.articleId));
      assert.param("commentId")(() => typia.assert(props.commentId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
