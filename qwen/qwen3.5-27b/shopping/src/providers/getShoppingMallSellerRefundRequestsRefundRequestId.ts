export async function getShoppingMallSellerRefundRequestsRefundRequestId(props: {
  seller: SellerPayload;
  refundRequestId: string & tags.Format<"uuid">;
}): Promise<IShoppingMallRefundRequest> {
  const record =
    await MyGlobal.prisma.shopping_mall_refund_requests.findFirstOrThrow({
      ...ShoppingMallRefundRequestTransformer.select(),
      where: {
        id: props.refundRequestId,
        deleted_at: null,
      },
    });
  // Verify authorization: seller must be the seller of the order item
  // The orderItem relation is already loaded by the transformer's select()
  if (record.orderItem.seller.id !== props.seller.id) {
    throw new HttpException("Forbidden", 403);
  }
  return await ShoppingMallRefundRequestTransformer.transform(record);
}


