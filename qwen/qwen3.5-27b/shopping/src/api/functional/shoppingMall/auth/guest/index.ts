/**
 * Creates a temporary guest session for unauthenticated users to access public platform features.
 *
 * This operation registers a new guest account identified by device fingerprint and generates JWT tokens for temporary access. Guests can browse public content, view products, and access registration pages without providing email or password credentials.
 *
 * The guest session is stored in the shopping_mall_guest_sessions table with associated access and refresh tokens. The guest identity is recorded in the shopping_mall_guests table with device fingerprint tracking.
 *
 * Guests have limited permissions compared to authenticated customers or sellers. They cannot place orders, write reviews, or access protected resources. To perform these actions, guests must register as a customer account.
 *
 * The operation returns IShoppingMallGuest.IAuthorized containing both access and refresh tokens. The access token is short-lived for API authentication, while the refresh token allows extending the session without re-joining.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Guest registration request with device fingerprint for temporary session creation.
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor guest
 * @x-autobe-specification 1. Generate a unique device fingerprint from request
 *   headers (User-Agent, IP address, or client-provided fingerprint). 2. Check
 *   if a guest account with this device fingerprint already exists in
 *   shopping_mall_guests table. 3. If exists, update the last_activity
 *   timestamp; if not, create a new guest record with the device fingerprint.
 *   4. Generate a new access token (JWT) with short expiration (e.g., 15
 *   minutes) and a refresh token (JWT) with longer expiration (e.g., 24 hours).
 *   5. Create a new session record in shopping_mall_guest_sessions table with
 *   both tokens, guest ID, and expiration timestamps. 6. Invalidate any
 *   existing sessions for this guest device. 7. Return the tokens in
 *   IShoppingMallGuest.IAuthorized format. 8. Handle edge cases: rate limiting
 *   for repeated join attempts, device fingerprint collision handling, and
 *   session cleanup for expired tokens.
 * @path /shoppingMall/auth/guest/join
 * @accessor api.functional.shoppingMall.auth.guest.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
