/**
 * Register a new administrator account with email and password credentials.
 *
 * This operation creates a new administrator account in the shopping_mall_administrators table. The email must be unique across all administrators and serves as the login credential. The password is hashed using bcrypt for secure storage. New administrators are created with 'regular' grade and 'banned=false' status by default.
 *
 * Upon successful registration, the system generates JWT access and refresh tokens stored in shopping_mall_administrator_sessions. The access token expires in 15 minutes for short-lived authentication, while the refresh token expires in 7 days for token renewal.
 *
 * The operation captures the client's IP address, current page URL (href), and referrer URL for security auditing and session tracking purposes.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Registration credentials for new administrator account
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor administrator
 * @x-autobe-specification 1. Validate request body: email must be valid format,
 *   password must meet complexity requirements (min 8 chars, uppercase,
 *   lowercase, number). 2. Check if email already exists in
 *   shopping_mall_administrators table (unique constraint). 3. Hash password
 *   using bcrypt with salt rounds >= 10. 4. Insert new record into
 *   shopping_mall_administrators with: email, password_hash, grade='regular',
 *   banned=false, created_at=now(), updated_at=now(), deleted_at=null. 5.
 *   Generate access token (expires in 15 minutes) and refresh token (expires in
 *   7 days). 6. Insert session record into shopping_mall_administrator_sessions
 *   with administrator_id, ip, href, referrer, created_at, expired_at. 7.
 *   Return tokens in IShoppingMallAdministrator.IAuthorized response. 8. Handle
 *   errors: 400 for validation failures, 409 for duplicate email, 500 for
 *   server errors.
 * @path /shoppingMall/auth/administrator/join
 * @accessor api.functional.shoppingMall.auth.administrator.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
