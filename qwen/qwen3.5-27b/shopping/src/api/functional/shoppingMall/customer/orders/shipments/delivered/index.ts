/**
 * Confirm delivery for a shipment, marking all included order items as delivered.
 *
 * When a customer confirms delivery for a shipment, the system records the confirmation timestamp and transitions all order items contained in that shipment from 'shipped' status to 'delivered' status. This manual confirmation starts the 7-day refund window for the customer. If the customer does not manually confirm delivery within 14 days of the shipping date, the system automatically marks the shipment as delivered.
 *
 * Customers can view which shipments require delivery confirmation in their order details page. The delivery confirmation is permanent and cannot be undone once submitted.
 *
 * @param props.connection
 * @param props.orderId UUID of the order containing the shipment (global scope)
 * @param props.shipmentId UUID of the shipment to confirm as delivered (global scope)
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor customer
 * @x-autobe-specification 1. Validate that the authenticated customer owns the order referenced by orderId.
 * 2. Validate that the shipment exists and belongs to the specified order.
 * 3. Verify that the shipment's delivered_at field is null (not already confirmed).
 * 4. Verify that all order items in the shipment are in 'shipped' status.
 * 5. Set delivered_at to current timestamp on the shipment record.
 * 6. Update all order items included in this shipment to 'delivered' status.
 * 7. Return the updated shipment object with delivered_at timestamp.
 * 8. Handle edge cases: if shipment already delivered, return 400 Bad Request with error message. If order items not in shipped status, return 400 Bad Request. If customer doesn't own the order, return 403 Forbidden.
 * @path /shoppingMall/customer/orders/:orderId/shipments/:shipmentId/delivered
 * @accessor api.functional.shoppingMall.customer.orders.shipments.delivered.confirmDelivery
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function confirmDelivery(
  connection: IConnection,
  props: confirmDelivery.Props,
): Promise<confirmDelivery.Response> {
  return true === connection.simulate
    ? confirmDelivery.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...confirmDelivery.METADATA,
          path: confirmDelivery.path(props),
          status: null,
        },
      );
}
export namespace confirmDelivery {
  export type Props = {
    /**
     * UUID of the order containing the shipment (global scope)
     */
    orderId: string & tags.Format<"uuid">;

    /**
     * UUID of the shipment to confirm as delivered (global scope)
     */
    shipmentId: string & tags.Format<"uuid">;
  };
  export type Response = IShoppingMallShipment;

  export const METADATA = {
    method: "POST",
    path: "/shoppingMall/customer/orders/:orderId/shipments/:shipmentId/delivered",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/customer/orders/${encodeURIComponent(props.orderId ?? "null")}/shipments/${encodeURIComponent(props.shipmentId ?? "null")}/delivered`;
  export const random = (): IShoppingMallShipment =>
    typia.random<IShoppingMallShipment>();
  export const simulate = (
    connection: IConnection,
    props: confirmDelivery.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: confirmDelivery.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("orderId")(() => typia.assert(props.orderId));
      assert.param("shipmentId")(() => typia.assert(props.shipmentId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
