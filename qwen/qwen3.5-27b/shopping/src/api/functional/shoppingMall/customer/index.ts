/**
 * Terminates the current user's authentication session and invalidates their access tokens.
 *
 * This operation logs out the authenticated user (customer, seller, or administrator) by invalidating their current session tokens. After logout, the user must authenticate again to access any platform features. All user-specific data becomes inaccessible immediately after session termination.
 *
 * The session is identified through the authentication token provided in the request header. No additional parameters or request body are required. The operation returns a success response with no content upon successful logout.
 *
 * @param props.connection
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor customer
 * @x-autobe-specification 1. Extract the current user's session token from the
 *   authentication middleware (JWT access token from Authorization header). 2.
 *   Identify the session type (customer, seller, or administrator) based on the
 *   token claims. 3. Query the corresponding session table
 *   (shopping_mall_customer_sessions, shopping_mall_seller_sessions, or
 *   shopping_mall_administrator_sessions) to find the active session matching
 *   the token. 4. Mark the session as expired by setting the expiration
 *   timestamp to the current time, or delete the session record entirely. 5. If
 *   refresh tokens are used, also invalidate the corresponding refresh token.
 *   6. Return HTTP 204 No Content to indicate successful logout. 7. Handle edge
 *   cases: if no active session is found, still return 204 (idempotent
 *   operation). If the token is invalid, the authentication middleware should
 *   have already rejected the request with 401.
 * @path /shoppingMall/customer/logout
 * @accessor api.functional.shoppingMall.customer.logout
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function logout(connection: IConnection): Promise<void> {
  return true === connection.simulate
    ? logout.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...logout.METADATA,
          path: logout.path(),
          status: null,
        },
      );
}
