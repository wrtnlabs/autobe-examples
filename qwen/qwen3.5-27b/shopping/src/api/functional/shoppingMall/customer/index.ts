/**
 * Places an order by processing payment and creating order records from the customer's shopping cart.
 *
 * This endpoint validates that all cart items are available, processes payment through the external payment gateway, creates the order and order items, clears the cart, and deducts inventory. The shipping address is locked at checkout and cannot be changed after order placement.
 *
 * @param props.connection
 * @param props.body Checkout request containing shipping address selection and payment information for order placement.
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor customer
 * @x-autobe-specification 1. Validate customer authentication and retrieve
 *   their current cart from shopping_mall_customer_carts.
 *
 * 2. Validate the provided shopping_mall_customer_address_id exists, belongs to the authenticated customer, and is not soft-deleted.
 *
 * 3. For each cart item in shopping_mall_customer_cart_items:
 *    - Verify the referenced product variant exists and is not soft-deleted
 *    - Check inventory availability (current stock >= cart quantity)
 *    - Mark any unavailable items and reject checkout if any exist
 *
 * 4. Process payment through external payment gateway using the payment_token:
 *    - If payment fails: return error response, do not create order, cart remains intact
 *    - If payment succeeds: proceed to order creation
 *
 * 5. Create order record in shopping_mall_orders:
 *    - Generate unique order_number
 *    - Set shopping_mall_customer_id to authenticated customer
 *    - Set shopping_mall_customer_address_id to the provided address
 *    - Set created_at and updated_at to current timestamp
 *
 * 6. For each cart item, create order item in shopping_mall_order_items:
 *    - Set shopping_mall_order_id to the new order
 *    - Set shopping_mall_product_variant_id from cart item
 *    - Set shopping_mall_seller_id from the product variant's product
 *    - Set quantity from cart item
 *    - Set price from product variant (use variant price if set, otherwise product base_price)
 *    - Set status to 'paid'
 *    - Set created_at and updated_at to current timestamp
 *
 * 7. Deduct inventory for each product variant:
 *    - Update inventory records in shopping_mall_inventory_records
 *    - Create inventory adjustment records with reason 'order_purchase'
 *
 * 8. Clear cart by soft-deleting all cart items in shopping_mall_customer_cart_items:
 *    - Set deleted_at to current timestamp
 *    - Do not delete the cart container itself
 *
 * 9. Return the created order with all order items and shipping address details.
 * @path /shoppingMall/customer/checkout
 * @accessor api.functional.shoppingMall.customer.checkout
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function checkout(
  connection: IConnection,
  props: checkout.Props,
): Promise<checkout.Response> {
  return true === connection.simulate
    ? checkout.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...checkout.METADATA,
          path: checkout.path(),
          status: null,
        },
        props.body,
      );
}
