export async function dashboard(
  connection: IConnection,
): Promise<dashboard.Response> {
  return true === connection.simulate
    ? dashboard.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...dashboard.METADATA,
          path: dashboard.path(),
          status: null,
        },
      );
}
