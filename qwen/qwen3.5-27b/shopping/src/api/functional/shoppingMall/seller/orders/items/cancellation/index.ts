/**
 * Approve a cancellation request for a specific order item, cancelling the item and processing a refund.
 *
 * This endpoint allows sellers to approve cancellation requests submitted by customers for order items containing their products. When a seller approves a cancellation request, the system transitions the order item status to 'cancelled', restores the product variant stock through inventory records, and processes a refund for that specific item only. The approval creates an immutable snapshot of the request state for dispute resolution purposes.
 *
 * Only the seller who owns the order item can approve the cancellation request. If the order contains multiple items from different sellers, each seller can only approve cancellation requests for their own items. The remaining items in the order continue their normal processing flow unaffected by this approval. If all items in an order are cancelled, the overall order status becomes cancelled.
 *
 * The system validates that the order item is in 'paid' status (not yet shipped) before allowing approval. Attempting to approve a cancellation request for an already shipped item will be rejected with an error.
 *
 * @param props.connection
 * @param props.orderId UUID of the order containing the item to be cancelled.
 * @param props.itemId UUID of the order item for which the cancellation request is being approved.
 * @param props.body Seller's response reason explaining the approval decision for the cancellation request.
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor seller
 * @x-autobe-specification 1. Validate seller authentication and authorization - ensure the authenticated seller owns the order item referenced by itemId.
 *
 * 2. Retrieve the cancellation request for the order item by joining shopping_mall_cancellation_requests with shopping_mall_order_items on itemId.
 *
 * 3. Validate the cancellation request exists and has status 'pending' - reject if already approved or rejected.
 *
 * 4. Validate the order item status is 'paid' (not yet shipped) - reject with error if item is already shipped.
 *
 * 5. Update the cancellation request: set status to 'approved', populate response_reason from request body, update updated_at timestamp.
 *
 * 6. Update the order item: set status to 'cancelled', update updated_at timestamp.
 *
 * 7. Create an inventory record for the product variant: add the cancelled item quantity back to stock with reason 'cancellation_approved'.
 *
 * 8. Create an immutable snapshot in shopping_mall_cancellation_request_snapshots capturing the request state before and after approval, including the response timestamp.
 *
 * 9. Process refund for the customer (integration with payment system - out of scope for this operation).
 *
 * 10. Check if all order items are now cancelled - if yes, update the overall order status to 'cancelled'.
 *
 * 11. Return the updated cancellation request with status 'approved'.
 *
 * Error handling:
 * - 404 if cancellation request or order item not found
 * - 409 if cancellation request is not in 'pending' status
 * - 409 if order item is not in 'paid' status (already shipped)
 * - 403 if seller does not own the order item
 * @path /shoppingMall/seller/orders/:orderId/items/:itemId/cancellation/approve
 * @accessor api.functional.shoppingMall.seller.orders.items.cancellation.approve
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
