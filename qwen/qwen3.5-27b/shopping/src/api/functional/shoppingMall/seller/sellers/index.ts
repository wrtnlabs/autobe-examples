/**
 * Allows a rejected seller to resubmit their registration request for administrator review.
 *
 * This operation enables sellers whose registration was previously rejected to apply for approval again. When a seller reapplies, their approval status changes from 'rejected' to 'pending', and the previous rejection reason is cleared. The new registration request is evaluated independently by administrators, who can view all historical registration requests from the same seller.
 *
 * Sellers can only use this operation if their current approval status is 'rejected'. Sellers with 'pending' or 'approved' status cannot reapply. The reapplication does not require additional information beyond the seller's existing registration data.
 *
 * @param props.connection
 * @param props.sellerId Unique identifier of the seller account submitting the reapplication (global scope)
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor seller
 * @x-autobe-specification Verify the seller exists and the authenticated user is the seller themselves (or an administrator acting on their behalf).
 *
 * Check that the seller's current approval_status is 'rejected'. If status is 'pending' or 'approved', return a 400 Bad Request error.
 *
 * Update the shopping_mall_sellers table:
 * - Set approval_status to 'pending'
 * - Clear rejection_reason (set to NULL)
 * - Update updated_at timestamp
 *
 * Update the related shopping_mall_seller_profiles table:
 * - Set approval_status to 'pending'
 * - Clear rejection_reason (set to NULL)
 * - Update updated_at timestamp
 *
 * Return the updated seller profile with the new 'pending' approval status.
 *
 * The previous rejection history is preserved in the database for administrator reference when reviewing the new request.
 * @path /shoppingMall/seller/sellers/:sellerId/reapply
 * @accessor api.functional.shoppingMall.seller.sellers.reapply
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function reapply(
  connection: IConnection,
  props: reapply.Props,
): Promise<reapply.Response> {
  return true === connection.simulate
    ? reapply.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...reapply.METADATA,
          path: reapply.path(props),
          status: null,
        },
      );
}
export namespace reapply {
  export type Props = {
    /**
     * Unique identifier of the seller account submitting the reapplication (global scope)
     */
    sellerId: string & tags.Format<"uuid">;
  };
  export type Response = IShoppingMallSellerProfile;

  export const METADATA = {
    method: "POST",
    path: "/shoppingMall/seller/sellers/:sellerId/reapply",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/seller/sellers/${encodeURIComponent(props.sellerId ?? "null")}/reapply`;
  export const random = (): IShoppingMallSellerProfile =>
    typia.random<IShoppingMallSellerProfile>();
  export const simulate = (
    connection: IConnection,
    props: reapply.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: reapply.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("sellerId")(() => typia.assert(props.sellerId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
