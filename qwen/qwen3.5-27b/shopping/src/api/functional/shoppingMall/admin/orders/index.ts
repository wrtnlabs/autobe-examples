/**
 * Retrieve detailed information about a specific customer order including all line items, shipping address, and order status.
 *
 * This operation provides complete order details for customers, sellers, and administrators. The order information includes the shipping address as it was captured at the time of order placement (preserved as a snapshot for historical accuracy), the total price at purchase time, and the overall order status which is derived from the statuses of all constituent order items.
 *
 * Order details include all line items with their individual product information, quantities, prices, and fulfillment statuses. Each order item contains snapshots of the product, variant, and seller profile as they existed at order placement time, ensuring order history remains accurate even if products or seller profiles are later modified or deleted.
 *
 * The shipping address is stored as a JSON snapshot and will be displayed exactly as it was when the order was placed, even if the customer later modifies or deletes that address from their address book. This ensures sellers always have accurate shipping information for order fulfillment.
 *
 * Order status reflects the current state of all items: paid (all items awaiting shipment), shipped (all items dispatched), delivered (all items received), cancelled (all items cancelled), refunded (all items refunded), or partially_completed (mixed states across items).
 *
 * @param props.connection
 * @param props.orderId Unique identifier of the order to retrieve
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor admin
 * @x-autobe-specification Query the shopping_mall_orders table for the order with the specified UUID.
 *
 * 1. Validate the order exists and is not soft-deleted (deleted_at is NULL).
 * 2. Check authorization: customer can only view their own orders, sellers can view orders containing their products, admins can view all orders.
 * 3. Join with shopping_mall_order_items to retrieve all line items for this order.
 * 4. For each order item, include the product_snapshot, variant_snapshot, and seller_profile_snapshot fields as JSON strings.
 * 5. Include the shipping_address_snapshot field from the order as a JSON string.
 * 6. Return the order with nested order items array.
 * 7. Handle edge cases: order not found (404), unauthorized access (403), soft-deleted order (404).
 * 8. Ensure the response includes all fields: id, shopping_mall_customer_id, shipping_address_snapshot, total_price, status, created_at, updated_at, and orderItems array with each item's id, quantity, price, status, and snapshots.
 * @path /shoppingMall/admin/orders/:orderId
 * @accessor api.functional.shoppingMall.admin.orders.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique identifier of the order to retrieve
     */
    orderId: string & tags.Format<"uuid">;
  };
  export type Response = IShoppingMallOrder;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/admin/orders/:orderId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/admin/orders/${encodeURIComponent(props.orderId ?? "null")}`;
  export const random = (): IShoppingMallOrder =>
    typia.random<IShoppingMallOrder>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("orderId")(() => typia.assert(props.orderId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
