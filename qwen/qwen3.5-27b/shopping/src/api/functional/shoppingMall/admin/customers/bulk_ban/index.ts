import {
  HttpError,
  IConnection,
  NestiaSimulator,
  PlainFetcher,
} from "@nestia/fetcher";
import typia from "typia";

import { IShoppingMallCustomerBulkBan } from "../../../../../structures/IShoppingMallCustomerBulkBan";

/**
 * Bulk ban multiple customer accounts for policy violations or abuse.
 *
 * This administrative operation allows platform administrators to ban multiple customer accounts simultaneously. When customers are banned, their account status is changed from 'active' to 'banned' in the shopping_mall_customers table. Banned customers are immediately prevented from logging in and cannot access any customer features including browsing products, placing orders, managing addresses, or updating their profile.
 *
 * The operation requires administrator authentication and updates the status field for each specified customer. All ban actions are logged with timestamps for audit purposes. The ban reason provided is stored for reference and can be used to notify customers if they are unbanned later.
 *
 * Related operations include PUT /admin/customers/:customerId/unban to restore access, GET /admin/customers to list all customers, and GET /customers/me for individual customer profile access. This bulk operation is more efficient than calling the single ban endpoint multiple times when dealing with multiple policy violators.
 *
 * @param props.connection
 * @param props.body Bulk ban request with customer IDs and ban reason
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor admin
 * @x-autobe-specification Validate administrator authentication and permissions (regular or super admin).
 *
 * Parse request body to extract customerIds array and ban reason.
 *
 * For each customer ID in the array:
 * 1. Query shopping_mall_customers table by ID
 * 2. Check if customer exists and is not already banned
 * 3. If already banned, mark as skipped in response
 * 4. Update status field from 'active' to 'banned'
 * 5. Update updated_at timestamp
 * 6. Log the ban action with admin ID, customer ID, reason, and timestamp
 *
 * Return response with success count, failure count, and detailed results for each customer.
 *
 * Handle edge cases:
 * - Non-existent customer IDs: mark as failed with 'not found' error
 * - Already banned customers: mark as skipped
 * - Insufficient permissions: return 403 unauthorized
 * - Empty customer IDs array: return validation error
 * @path /shoppingMall/admin/customers/bulk-ban
 * @accessor api.functional.shoppingMall.admin.customers.bulk_ban.bulkBan
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function bulkBan(
  connection: IConnection,
  props: bulkBan.Props,
): Promise<bulkBan.Response> {
  return true === connection.simulate
    ? bulkBan.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...bulkBan.METADATA,
          path: bulkBan.path(),
          status: null,
        },
        props.body,
      );
}
export namespace bulkBan {
  export type Props = {
    /**
     * Bulk ban request with customer IDs and ban reason
     */
    body: IShoppingMallCustomerBulkBan.ICreate;
  };
  export type Body = IShoppingMallCustomerBulkBan.ICreate;
  export type Response = IShoppingMallCustomerBulkBan.IResult;

  export const METADATA = {
    method: "POST",
    path: "/shoppingMall/admin/customers/bulk-ban",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/shoppingMall/admin/customers/bulk-ban";
  export const random = (): IShoppingMallCustomerBulkBan.IResult =>
    typia.random<IShoppingMallCustomerBulkBan.IResult>();
  export const simulate = (
    connection: IConnection,
    props: bulkBan.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: bulkBan.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
