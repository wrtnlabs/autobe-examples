/**
 * Retrieve aggregated review statistics for a specific product including average rating and review distribution.
 *
 * This operation provides comprehensive review metrics that help customers evaluate product quality and popularity before making purchasing decisions. The statistics are prominently displayed on product detail pages and product listing pages to enable quick product comparison and evaluation.
 *
 * The response includes the total number of reviews for the product, the average star rating (rounded to one decimal place), and a breakdown of how many reviews exist for each rating level from 1 to 5 stars. Only non-deleted reviews are included in these calculations, ensuring accuracy while preserving historical data integrity.
 *
 * Reviews from customers who have deleted their accounts are still included in the statistics, maintaining the integrity of product feedback even after account deletion. This ensures that valuable customer experiences remain visible to help future buyers make informed decisions.
 *
 * Related operations include GET /products/{productId}/reviews to retrieve individual review details and GET /products/{productId} to view the complete product information with embedded review statistics.
 *
 * @param props.connection
 * @param props.productId UUID of the product to retrieve review statistics for
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor null
 * @x-autobe-specification Query shopping_mall_reviews table joined with shopping_mall_order_items to retrieve reviews for the specified product.
 *
 * 1. Accept productId as UUID path parameter
 * 2. Join shopping_mall_reviews with shopping_mall_order_items on shopping_order_item_id
 * 3. Filter by product through order item's product reference
 * 4. Exclude soft-deleted reviews (where deleted_at is null)
 * 5. Calculate aggregate statistics:
 *    - Total count of non-deleted reviews
 *    - Average rating (arithmetic mean of all rating values)
 *    - Rating distribution: count of reviews for each rating value (1, 2, 3, 4, 5)
 * 6. Round average rating to one decimal place
 * 7. If no reviews exist, return statistics with zero counts and null average rating
 * 8. Optionally check if current authenticated customer has written a review for this product
 * 9. Return statistics object with all computed metrics
 *
 * Business rules:
 * - Include reviews from deleted customer accounts in statistics
 * - Exclude only soft-deleted reviews (deleted_at is not null)
 * - Average rating calculation includes all non-deleted reviews regardless of customer account status
 * - Rating distribution must sum to total review count
 * @path /shoppingMall/products/:productId/reviews/statistics
 * @accessor api.functional.shoppingMall.products.reviews.statistics.getReviewStatistics
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function getReviewStatistics(
  connection: IConnection,
  props: getReviewStatistics.Props,
): Promise<getReviewStatistics.Response> {
  return true === connection.simulate
    ? getReviewStatistics.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...getReviewStatistics.METADATA,
          path: getReviewStatistics.path(props),
          status: null,
        },
      );
}
export namespace getReviewStatistics {
  export type Props = {
    /**
     * UUID of the product to retrieve review statistics for
     */
    productId: string & tags.Format<"uuid">;
  };
  export type Response = IShoppingMallProductReviewStatistic;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/products/:productId/reviews/statistics",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/products/${encodeURIComponent(props.productId ?? "null")}/reviews/statistics`;
  export const random = (): IShoppingMallProductReviewStatistic =>
    typia.random<IShoppingMallProductReviewStatistic>();
  export const simulate = (
    connection: IConnection,
    props: getReviewStatistics.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: getReviewStatistics.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("productId")(() => typia.assert(props.productId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
