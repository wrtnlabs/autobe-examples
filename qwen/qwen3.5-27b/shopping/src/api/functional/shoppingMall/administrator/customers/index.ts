import {
  HttpError,
  IConnection,
  NestiaSimulator,
  PlainFetcher,
} from "@nestia/fetcher";
import typia, { tags } from "typia";

import { IShoppingMallCustomer } from "../../../../structures/IShoppingMallCustomer";

/**
 * Administrators can ban or unban customer accounts to control platform access.
 *
 * When a customer account is banned, the customer loses the ability to log in to the platform and access any features. Banned accounts retain their order history, reviews (shown as 'deleted user'), and all associated data. This preserves transaction records for legal and business purposes while preventing further platform usage.
 *
 * When a customer account is unbanned, the customer immediately regains full login and platform access. The customer's profile information, order history, and all associated data remain intact during both the ban and unban process.
 *
 * This operation requires administrator privileges and is used for platform policy enforcement and user management.
 *
 * @param props.connection
 * @param props.customerId Unique identifier of the customer account to ban or unban (global scope)
 * @param props.body Ban status to set for the customer account. Set to true to ban the customer (prevent login), set to false to unban the customer (restore login access).
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor administrator
 * @x-autobe-specification Update the banned boolean field in shopping_mall_customers table based on the request body.
 *
 * 1. Validate that the customerId exists in shopping_mall_customers table
 * 2. Verify the customer is not soft-deleted (deleted_at is null)
 * 3. Update the banned field to the value provided in request body
 * 4. Update the updated_at timestamp to current time
 * 5. Return the updated customer entity with the new banned status
 *
 * Error handling:
 * - Return 404 if customer with given customerId does not exist
 * - Return 404 if customer is soft-deleted (deleted_at is not null)
 * - Return 400 if banned field is not a boolean value
 * - Ensure only authenticated administrators can access this operation
 * @path /shoppingMall/administrator/customers/:customerId/ban
 * @accessor api.functional.shoppingMall.administrator.customers.ban
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function ban(
  connection: IConnection,
  props: ban.Props,
): Promise<ban.Response> {
  return true === connection.simulate
    ? ban.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...ban.METADATA,
          path: ban.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace ban {
  export type Props = {
    /**
     * Unique identifier of the customer account to ban or unban (global scope)
     */
    customerId: string & tags.Format<"uuid">;

    /**
     * Ban status to set for the customer account. Set to true to ban the customer (prevent login), set to false to unban the customer (restore login access).
     */
    body: IShoppingMallCustomer.IBanRequest;
  };
  export type Body = IShoppingMallCustomer.IBanRequest;
  export type Response = IShoppingMallCustomer;

  export const METADATA = {
    method: "POST",
    path: "/shoppingMall/administrator/customers/:customerId/ban",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/shoppingMall/administrator/customers/${encodeURIComponent(props.customerId ?? "null")}/ban`;
  export const random = (): IShoppingMallCustomer =>
    typia.random<IShoppingMallCustomer>();
  export const simulate = (
    connection: IConnection,
    props: ban.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: ban.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("customerId")(() => typia.assert(props.customerId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
