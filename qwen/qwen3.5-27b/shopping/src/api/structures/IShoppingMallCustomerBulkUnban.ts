import { tags } from "typia";

export namespace IShoppingMallCustomerBulkUnban {
  /**
   * Request body for bulk unbanning multiple customer accounts. This administrative operation allows platform administrators to restore access for customers who have been previously banned due to policy violations or other infractions. Provide an array of customer UUIDs to unban. Each customer will be processed independently - partial failures do not prevent successful unbans from being applied. Only customers with 'banned' status can be unbanned; others will be reported as failures in the response.
   */
  export type ICreate = {
    /**
     * Array of customer UUIDs to unban. Each UUID represents a customer account that should have their status changed from 'banned' to 'active'. Provide multiple customer IDs to unban them in a single operation. Each customer is processed independently, so partial failures do not prevent successful unbans from being applied.
     *
     * @x-autobe-specification Array of customer UUIDs extracted from request body. Each UUID is used to query shopping_mall_customers table by id field. For each customer: validate existence (id must exist), check not soft-deleted (deleted_at is null), verify status is 'banned'. If all validations pass, update status from 'banned' to 'active'. Each UUID in the array is processed independently - partial failures do not rollback successful unbans. Empty array is valid and returns empty success results.
     */
    customerIds: (string & tags.Format<"uuid">)[];
  };

  /**
   * Result object returned after attempting to unban multiple customer accounts in bulk. Contains two arrays: 'success' lists all customer IDs that were successfully unbanned (status changed from banned to active), and 'failed' lists objects with customer IDs and error reasons for customers that could not be unbanned. This allows administrators to see exactly which unbans succeeded and which failed, along with specific reasons for failures such as customer not found, customer not banned, or customer already deleted.
   */
  export type IResult = {
    /**
     * Array of customer IDs that were successfully unbanned. Each UUID represents a customer whose account status was changed from 'banned' to 'active', restoring their ability to log in and use the platform.
     *
     * @x-autobe-specification Computed array of customer UUIDs that were successfully unbanned. Generated by the service layer after updating shopping_mall_customers.status from 'banned' to 'active'. Each UUID in this array represents a customer whose unban operation completed successfully. The array may be empty if all unbans failed.
     */
    success: (string & tags.Format<"uuid">)[];

    /**
     * Array of failed unban results. Each object contains a customer ID and error reason explaining why the unban could not be completed. Common reasons include: customer not found, customer not currently banned, or customer account already deleted.
     *
     * @x-autobe-specification Computed array of IShoppingMallCustomerBulkUnban.IResultFailedItem objects for customers that could not be unbanned. Each object contains the customer ID and an error reason. Error reasons include: 'customer not found' (ID does not exist), 'customer not banned' (status is not 'banned'), 'customer already deleted' (deleted_at is not null), or other validation failures. Generated by the service layer after attempting to process each customer ID from the request.
     */
    failed: IShoppingMallCustomerBulkUnban.IResultFailedItem[];
  };

  /**
   * Failed unban result object containing the customer ID that could not be unbanned and the specific reason for the failure. This allows administrators to understand exactly why each unban operation failed, enabling them to take appropriate corrective actions such as verifying customer IDs, checking account status, or addressing other issues.
   */
  export type IResultFailedItem = {
    /**
     * The customer UUID that failed to be unbanned. This is the same ID provided in the request body that could not be processed successfully.
     *
     * @x-autobe-specification Computed value from the bulk unban request. This is the customer UUID that was provided in the request body but could not be successfully unbanned. The value is extracted directly from the input array of customer IDs that failed validation or processing.
     */
    customerId: string & tags.Format<"uuid">;

    /**
     * The specific reason why the unban operation failed. Common values include: 'customer not found' (ID doesn't exist), 'customer not banned' (status is not 'banned'), 'customer already deleted' (deleted_at is not null), or other validation errors.
     *
     * @x-autobe-specification Computed string describing why the unban operation failed for this specific customer. Generated by the bulk unban service based on validation results: 'customer not found' (UUID doesn't exist in shopping_mall_customers table), 'customer not banned' (current status is not 'banned'), 'customer already deleted' (deleted_at column is not null), or other validation/business rule violations. Each failure scenario produces a distinct reason string for clarity.
     */
    reason: string;
  };
}
