import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IPageIShoppingMallReview } from "../../../../../api/structures/IPageIShoppingMallReview";
import { IShoppingMallReview } from "../../../../../api/structures/IShoppingMallReview";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { patchShoppingMallCustomerReviewsMyHistory } from "../../../../../providers/patchShoppingMallCustomerReviewsMyHistory";

@Controller("/shoppingMall/customer/reviews/my-history")
export class ShoppingmallCustomerReviewsMy_historyController {
  /**
   * Retrieve a paginated list of reviews written by the authenticated customer across all their purchased products.
   *
   * This operation provides customers with access to their complete review history, enabling them to track their feedback across different products. Reviews are displayed with their star ratings, text content (if provided), creation timestamps, and associated product information.
   *
   * The system filters reviews to show only those written by the authenticated customer, ensuring data isolation between users. Reviews are sorted by creation date with the most recent reviews appearing first. Deleted reviews (those soft-deleted by the customer) are excluded from the results.
   *
   * Supports advanced filtering capabilities including rating value filtering (1-5 stars), date range filtering by review creation date, and text search within review content. Customers can also filter by specific product to view all their reviews for that particular item.
   *
   * Related operations include:
   * - `GET /products/{productId}/reviews` to view all reviews for a specific product
   * - `PUT /reviews/{reviewId}` to update an existing review
   * - `DELETE /reviews/{reviewId}` to delete a review
   *
   * @param connection
   * @param body Search criteria and pagination parameters for review history
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query shopping_mall_reviews table filtered by authenticated customer's ID (shopping_customer_id).
   *
   * Apply soft delete filter: exclude reviews where deleted_at is NOT NULL.
   *
   * Support filtering from request body:
   * - rating: exact match on rating field (1-5)
   * - startDate/endDate: filter by created_at range
   * - search: partial match on review content using trigram index
   * - productId: join with shopping_mall_order_items to filter by product
   *
   * Sort by created_at in descending order (newest first).
   *
   * Apply pagination with page and limit parameters (default: page=1, limit=20, max=100).
   *
   * Join with shopping_mall_order_items to include product snapshot data in response.
   *
   * Join with shopping_mall_customers to get customer display name (handle deleted accounts by showing 'deleted user').
   *
   * Return paginated response with:
   * - pagination: { page, limit, total, totalPages }
   * - data: array of review summaries with id, rating, content, created_at, product_name, product_snapshot
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallReview.IRequest,
  ): Promise<IPageIShoppingMallReview.ISummary> {
    try {
      return await patchShoppingMallCustomerReviewsMyHistory({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
