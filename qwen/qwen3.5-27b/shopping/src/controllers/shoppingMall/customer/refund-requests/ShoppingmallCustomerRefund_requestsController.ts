import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallRefundRequest } from "../../../../api/structures/IPageIShoppingMallRefundRequest";
import { IShoppingMallRefundRequest } from "../../../../api/structures/IShoppingMallRefundRequest";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { getShoppingMallCustomerRefundRequestsRefundRequestId } from "../../../../providers/getShoppingMallCustomerRefundRequestsRefundRequestId";
import { patchShoppingMallCustomerRefundRequests } from "../../../../providers/patchShoppingMallCustomerRefundRequests";
import { postShoppingMallCustomerRefundRequests } from "../../../../providers/postShoppingMallCustomerRefundRequests";

@Controller("/shoppingMall/customer/refund-requests")
export class ShoppingmallCustomerRefund_requestsController {
  /**
   * Create a new refund request for a delivered order item within the seven-day post-delivery window.
   *
   * This operation allows customers to request refunds for individual order items that have been delivered. The customer must provide a reason text explaining why they are requesting the refund. The system validates that the order item belongs to the requesting customer, has a "delivered" status, and is within the seven-day eligibility window from the delivery date.
   *
   * Upon successful creation, the refund request is stored with status "pending" and awaits seller approval or rejection. The system creates an immutable snapshot of the refund request state for audit trail purposes. The requesting customer can view their refund requests and their current status through the refund requests list endpoint.
   *
   * Security: Only authenticated customers can create refund requests. The system validates that the order item belongs to the authenticated customer's orders. Customers cannot create refund requests for items from other customers' orders or for items that are not delivered or outside the refund window.
   *
   * @param connection
   * @param body Refund request creation data including order item reference and reason
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Implementation steps for creating a refund request:
   *
   * 1. **Authentication & Authorization**: Verify the customer is authenticated via JWT token. Extract customer_id from the authenticated session.
   *
   * 2. **Input Validation**: Validate the request body contains:
   *    - order_item_id (UUID): The specific order item to request refund for
   *    - reason (string, required): Customer's explanation for the refund request
   *
   * 3. **Order Item Lookup**: Query shopping_mall_order_items table for the specified order_item_id. Verify the order item exists and is not soft-deleted.
   *
   * 4. **Ownership Validation**: Verify the order item belongs to the authenticated customer by checking the order's customer_id matches the authenticated customer.
   *
   * 5. **Eligibility Checks**:
   *    - Verify order item status is "delivered" (not paid, shipped, cancelled, or already refunded)
   *    - Calculate delivery date from the shipment's delivered_at timestamp
   *    - Verify current time is within 7 days of delivery date
   *    - Check no existing refund request exists for this order item with "pending" status
   *
   * 6. **Create Refund Request**: Insert new record into shopping_mall_refund_requests table with:
   *    - id: Generate new UUID
   *    - shopping_mall_order_item_id: From request
   *    - shopping_mall_customer_id: From authenticated session
   *    - shopping_mall_customer_session_id: From current session
   *    - reason: From request body
   *    - status: "pending"
   *    - requested_at: Current timestamp
   *    - responded_at: NULL
   *    - created_at: Current timestamp
   *    - updated_at: Current timestamp
   *    - deleted_at: NULL
   *
   * 7. **Create Snapshot**: Automatically create a refund snapshot in shopping_mall_refund_snapshots table capturing the initial state for audit trail.
   *
   * 8. **Response**: Return the created refund request object with all fields including the generated id, status, and timestamps.
   *
   * 9. **Error Handling**:
   *    - Return 404 if order item not found
   *    - Return 403 if order item does not belong to customer
   *    - Return 400 if order item status is not "delivered"
   *    - Return 400 if outside 7-day refund window
   *    - Return 400 if duplicate pending refund request exists
   *    - Return 400 if reason is missing or empty
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallRefundRequest.ICreate,
  ): Promise<IShoppingMallRefundRequest> {
    try {
      return await postShoppingMallCustomerRefundRequests({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a filtered and paginated list of refund requests for the authenticated customer.
   *
   * This operation allows customers to view their refund request history with advanced search capabilities. Customers can filter refund requests by status (pending, approved, or rejected), date ranges for request submission (requested_at) and seller response (responded_at), and sort results by various criteria. The response includes essential refund request information such as the associated order item, refund reason, current status, and relevant timestamps.
   *
   * Each refund request is tied to a specific order item via shopping_mall_order_item_id and requires a reason text explaining why the refund is being requested. The status field tracks the approval workflow: requests start as 'pending' until the seller reviews and responds with either 'approved' or 'rejected'. When approved, the corresponding order item status changes to 'refunded' and inventory stock is restored through inventory records.
   *
   * The shopping_mall_refund_requests table includes soft delete support via the deleted_at field. When a refund request is soft deleted, it is removed from active queries but preserved for audit trail purposes. This operation only returns active (non-deleted) refund requests.
   *
   * Security considerations ensure that customers can only view their own refund requests through data isolation at the database query level using shopping_mall_customer_id filtering. The system prevents unauthorized access to other customers' refund information. All refund requests are preserved for audit trail purposes, including those that have been rejected.
   *
   * This operation is typically used in conjunction with GET /refund-requests/{refundRequestId} to view detailed information about a specific refund request, and POST /refund-requests to create new refund requests for eligible delivered order items.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for refund requests
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query shopping_mall_refund_requests table with pagination and filtering support.
   *
   * 1. Apply authentication to identify the requesting customer from the session token.
   * 2. Filter refund requests by customer_id (data isolation - only show requests belonging to authenticated customer).
   * 3. Apply search filters from request body:
   *    - status filter (pending, approved, rejected)
   *    - requested_at date range filter
   *    - responded_at date range filter (for approved/rejected requests)
   * 4. Apply sorting (default: requested_at DESC for newest first).
   * 5. Apply pagination with page and limit parameters (default page=1, limit=20, max limit=100).
   * 6. Join with shopping_mall_order_items to include order item information in response.
   * 7. Join with shopping_mall_customers to validate customer ownership.
   * 8. Return paginated response with data array and pagination metadata.
   *
   * Error handling:
   * - Return 401 if authentication fails.
   * - Return 403 if customer tries to access another customer's refund requests.
   * - Return 400 for invalid filter parameters or pagination values.
   * - Return 404 if no refund requests match the criteria.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallRefundRequest.IRequest,
  ): Promise<IPageIShoppingMallRefundRequest.ISummary> {
    try {
      return await patchShoppingMallCustomerRefundRequests({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific refund request by its unique identifier.
   *
   * This operation provides complete details of a refund request submitted by a customer for a delivered order item. The response includes the request reason, current status (pending, approved, or rejected), submission timestamp, response timestamp if the seller has acted on it, and references to the related order item and customer.
   *
   * Security and authorization: Customers can only view refund requests they have submitted themselves. Administrators can view any refund request on the platform for oversight and audit purposes. Sellers can view refund requests for their products to review and respond to them.
   *
   * The refund request record includes the shopping_mall_order_item_id which references the specific line item being refunded, the shopping_mall_customer_id identifying the requesting customer, and the status field indicating whether the request is pending seller response or has been approved/rejected. The requested_at timestamp is used to validate the seven-day refund eligibility window from the delivery date.
   *
   * Related operations: Use PATCH /refund-requests to list and search refund requests with filters. Use POST /orders/{orderId}/items/{itemId}/refund to create a new refund request. Sellers can approve or reject pending requests using PUT /sellers/me/refund-requests/{refundRequestId}.
   *
   * @param connection
   * @param refundRequestId Unique identifier of the refund request to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query the shopping_mall_refund_requests table for a single record by primary key (id field matching refundRequestId parameter).
   *
   * Authorization logic:
   * - If customer actor: verify shopping_mall_customer_id matches the authenticated customer's ID
   * - If seller actor: verify the refund request's order item belongs to the seller's products (join with shopping_mall_order_items to check shopping_mall_seller_id)
   * - If admin actor: allow access to any refund request
   *
   * Join with shopping_mall_order_items to include order item details (product_snapshot, variant_snapshot, seller_profile_snapshot, quantity, price, status).
   *
   * Join with shopping_mall_customers to include customer information (display_name, phone_number) if needed for the response.
   *
   * Include related refund snapshots from shopping_mall_refund_snapshots table ordered by created_at descending.
   *
   * Return 404 Not Found if the refund request does not exist or has been soft deleted (deleted_at is not null).
   *
   * Return 403 Forbidden if the authenticated user does not have permission to view this specific refund request.
   *
   * Handle soft deletion: exclude records where deleted_at is not null from the query results.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":refundRequestId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("refundRequestId")
    refundRequestId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallRefundRequest> {
    try {
      return await getShoppingMallCustomerRefundRequestsRefundRequestId({
        customer,
        refundRequestId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
