import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IShoppingMallShipment } from "../../../../../api/structures/IShoppingMallShipment";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { postShoppingMallCustomerShipmentsShipmentIdConfirmDelivery } from "../../../../../providers/postShoppingMallCustomerShipmentsShipmentIdConfirmDelivery";

@Controller("/shoppingMall/customer/shipments/:shipmentId/confirm-delivery")
export class ShoppingmallCustomerShipmentsConfirm_deliveryController {
  /**
   * Confirm delivery of a shipment to mark all included order items as delivered and enable post-delivery features.
   *
   * This operation allows customers to confirm that they have received a shipment. When delivery is confirmed, the system updates the shipment record with the delivery timestamp and sets the delivery_confirmed flag to true. All order items included in this shipment are automatically updated to 'delivered' status, enabling customers to write reviews for those items and starting the 7-day refund window.
   *
   * Security and authorization: Only the customer who owns the order containing the shipment's order items can confirm delivery. The system validates that the authenticated customer is associated with all order items in the shipment before allowing confirmation. Attempts to confirm delivery for shipments not associated with the customer's orders are rejected.
   *
   * Business rules and validation: Delivery confirmation is only allowed for shipments where delivery_confirmed is false. Duplicate delivery confirmations for the same shipment are prevented. If any order items in the shipment are already cancelled or refunded, delivery confirmation is still allowed for the remaining items. The system automatically marks shipments as delivered after 14 days if not manually confirmed, but manual confirmation prevents this automatic trigger.
   *
   * After confirming delivery, customers can write reviews for delivered items and request refunds within the 7-day post-delivery window. Sellers can view delivery confirmation status through their shipment management operations.
   *
   * @param connection
   * @param shipmentId Unique identifier of the shipment to confirm delivery for
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Validate the authenticated customer has permission to confirm delivery for this shipment:
   * 1. Load the shipment by shipmentId from shopping_mall_shipments table
   * 2. Check that shipment.deleted_at is null (shipment is active)
   * 3. Check that shipment.delivery_confirmed is false (not already confirmed)
   * 4. Load all order items in this shipment via shopping_mall_shipment_items junction table
   * 5. Verify all order items belong to orders owned by the authenticated customer
   * 6. Verify shipment status allows delivery confirmation (items should be in 'shipped' status)
   *
   * Execute delivery confirmation in a database transaction:
   * 1. Update shopping_mall_shipments: set delivery_confirmed = true, delivered_at = current timestamp
   * 2. Update all associated shopping_mall_order_items: set status = 'delivered'
   * 3. Record audit log entry for delivery confirmation
   *
   * Return the updated shipment object with delivery confirmation details.
   *
   * Error handling:
   * - Return 404 if shipment not found or soft-deleted
   * - Return 400 if shipment already confirmed (delivery_confirmed = true)
   * - Return 403 if customer does not own any order items in the shipment
   * - Return 400 if shipment is not in valid state for delivery confirmation
   * - Return 500 for database transaction failures
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async confirmDelivery(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("shipmentId")
    shipmentId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallShipment> {
    try {
      return await postShoppingMallCustomerShipmentsShipmentIdConfirmDelivery({
        customer,
        shipmentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
