import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IPageIShoppingMallProduct } from "../../../../api/structures/IPageIShoppingMallProduct";
import { IShoppingMallProduct } from "../../../../api/structures/IShoppingMallProduct";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { patchShoppingMallCustomerProducts } from "../../../../providers/patchShoppingMallCustomerProducts";

@Controller("/shoppingMall/customer/products")
export class ShoppingmallCustomerProductsController {
  /**
   * Retrieve a filtered and paginated list of products available in the shopping mall platform.
   *
   * This operation provides comprehensive product browsing capabilities for customers and guests. It supports advanced filtering by category, price range, and stock availability, as well as sorting by various criteria including newest arrivals, price ascending, and price descending.
   *
   * Products are organized by sellers and categories. Each product may have multiple variants (SKUs) with different options such as color, size, or material. A product is considered available for purchase only if it has at least one variant in stock. Products without any variants or with all variants out of stock are marked as unavailable.
   *
   * The response includes product summary information optimized for list displays, including the product name, base price, category, seller information, and availability status. For detailed product information including all variants, images, and reviews, use the GET /products/{productId} endpoint.
   *
   * This endpoint is accessible to all users including guests (unauthenticated users). No authentication is required to browse products, but authenticated customers may have access to additional personalized features.
   *
   * @param connection
   * @param body Search criteria, filters, and pagination parameters for product listing
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query the shopping_mall_products table with optional filtering and sorting.
   *
   * **Filtering Logic:**
   * - Category filter: Join with shopping_mall_categories table, support filtering by category_id or parent category (include subcategories)
   * - Price range: Filter by base_price field using min/max bounds
   * - Stock availability: Join with shopping_mall_product_variants, check if any variant has stockQuantity > 0
   * - Search text: Partial match on product name and description fields
   *
   * **Sorting Options:**
   * - newest: Order by createdAt descending
   * - price_asc: Order by basePrice ascending
   * - price_desc: Order by basePrice descending
   *
   * **Pagination:**
   * - Implement cursor-based or offset-based pagination
   * - Default page size: 20, maximum: 100
   * - Return total count for client-side pagination UI
   *
   * **Availability Check:**
   * - For each product, determine availability by checking variant stock
   * - Product is available if at least one variant exists and has stockQuantity > 0
   * - Product is unavailable if no variants exist or all variants have stockQuantity = 0
   *
   * **Response Construction:**
   * - Return product summary with: id, name, description, basePrice, categoryId, categoryName, sellerId, sellerShopName, imageUrl (main thumbnail), available flag, variantCount
   * - Do not include full variant details, images array, or reviews in list response
   *
   * **Performance Considerations:**
   * - Use database indexes on category_id, base_price, created_at, and deleted_at
   * - Pre-compute availability status if performance requires optimization
   * - Cache category lookups to avoid repeated joins
   *
   * **Error Handling:**
   * - Return empty list if no products match criteria
   * - Validate pagination parameters (page >= 1, limit between 1-100)
   * - Ignore invalid filter values gracefully
   * - Handle soft-deleted products by excluding them from results
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallProduct.IRequest,
  ): Promise<IPageIShoppingMallProduct.ISummary> {
    try {
      return await patchShoppingMallCustomerProducts({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
