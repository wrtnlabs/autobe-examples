import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallCustomerPasswordReset } from "../../../../api/structures/IPageIShoppingMallCustomerPasswordReset";
import { IShoppingMallCustomerPasswordReset } from "../../../../api/structures/IShoppingMallCustomerPasswordReset";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { getShoppingMallCustomerPasswordResetsResetId } from "../../../../providers/getShoppingMallCustomerPasswordResetsResetId";
import { patchShoppingMallCustomerPasswordResets } from "../../../../providers/patchShoppingMallCustomerPasswordResets";

@Controller("/shoppingMall/customer/password-resets")
export class ShoppingmallCustomerPassword_resetsController {
  /**
   * Search and list password reset requests across all user types in the shopping mall platform.
   *
   * This administrative endpoint provides visibility into password reset activity for security monitoring and audit purposes. Administrators can filter reset requests by user type, email address, status, and date range to investigate suspicious activity or assist users with account recovery issues.
   *
   * The endpoint aggregates password reset records from customer, seller, and administrator accounts into a unified view. Each record shows when the reset token was generated, when it expires, and whether it has been used or expired.
   *
   * Access to this endpoint is restricted to administrators only. Regular users cannot view password reset requests for security and privacy reasons.
   *
   * @param connection
   * @param body Search criteria for filtering password reset requests including user type, email, status, date range, and pagination parameters.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query password reset records from shopping_mall_customer_password_resets, shopping_mall_seller_password_resets, and shopping_mall_administrator_password_resets tables.
   *
   * Apply filters from request body:
   * - user_type: filter by 'customer', 'seller', or 'administrator'
   * - email: search by user email address
   * - status: filter by 'active' (not expired and not deleted), 'expired' (past expired_at), or 'used' (deleted_at is set)
   * - date_range: filter by created_at between start and end dates
   *
   * Join with respective user tables to retrieve email addresses and user information.
   *
   * Apply pagination from request body (page, pageSize, sortBy, sortOrder).
   *
   * Return paginated results with summary fields: id, user_type, user_email, token (masked), created_at, expired_at, status, deleted_at.
   *
   * Only administrators can access this endpoint. Validate user has administrator role before processing.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallCustomerPasswordReset.IRequest,
  ): Promise<IPageIShoppingMallCustomerPasswordReset.ISummary> {
    try {
      return await patchShoppingMallCustomerPasswordResets({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve password reset token information by unique identifier for administrative oversight and security auditing purposes.
   *
   * This endpoint allows platform administrators to view details of password reset tokens generated for customer, seller, or administrator accounts. It provides visibility into password reset requests for troubleshooting, security monitoring, and audit trail purposes.
   *
   * The response includes the reset token's creation time, expiration time, usage status, and the associated user account information. Administrators can use this information to verify legitimate password reset requests, investigate suspicious activity, or assist users experiencing password recovery issues.
   *
   * Access to this endpoint is restricted to authorized administrators only. The endpoint supports viewing password resets across all user types (customers, sellers, administrators) from a unified interface.
   *
   * @param connection
   * @param resetId Unique identifier of the password reset token record (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query password reset tables (shopping_mall_customer_password_resets, shopping_mall_seller_password_resets, shopping_mall_administrator_password_resets) by the provided resetId.
   *
   * 1. Accept resetId as UUID path parameter
   * 2. Search across all three password reset tables to find matching record
   * 3. Join with corresponding user table (customers/sellers/administrators) to include user information
   * 4. Return password reset record with associated user details
   * 5. Handle case where resetId doesn't exist in any table (return 404)
   * 6. Ensure only authorized administrators can access this endpoint
   * 7. Consider masking or excluding the actual token value in response for security if required by security policy
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":resetId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("resetId")
    resetId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallCustomerPasswordReset> {
    try {
      return await getShoppingMallCustomerPasswordResetsResetId({
        customer,
        resetId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
