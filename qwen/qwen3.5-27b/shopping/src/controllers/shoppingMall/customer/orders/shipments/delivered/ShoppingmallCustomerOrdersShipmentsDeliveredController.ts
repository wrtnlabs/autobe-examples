import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IShoppingMallShipment } from "../../../../../../api/structures/IShoppingMallShipment";
import { CustomerAuth } from "../../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../../decorators/payload/CustomerPayload";
import { postShoppingMallCustomerOrdersOrderIdShipmentsShipmentIdDelivered } from "../../../../../../providers/postShoppingMallCustomerOrdersOrderIdShipmentsShipmentIdDelivered";

@Controller(
  "/shoppingMall/customer/orders/:orderId/shipments/:shipmentId/delivered",
)
export class ShoppingmallCustomerOrdersShipmentsDeliveredController {
  /**
   * Confirm delivery for a shipment, marking all included order items as delivered.
   *
   * When a customer confirms delivery for a shipment, the system records the confirmation timestamp and transitions all order items contained in that shipment from 'shipped' status to 'delivered' status. This manual confirmation starts the 7-day refund window for the customer. If the customer does not manually confirm delivery within 14 days of the shipping date, the system automatically marks the shipment as delivered.
   *
   * Customers can view which shipments require delivery confirmation in their order details page. The delivery confirmation is permanent and cannot be undone once submitted.
   *
   * @param connection
   * @param orderId UUID of the order containing the shipment (global scope)
   * @param shipmentId UUID of the shipment to confirm as delivered (global scope)
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification 1. Validate that the authenticated customer owns
     *   the order referenced by orderId. 2. Validate that the shipment exists
     *   and belongs to the specified order. 3. Verify that the shipment's
     *   delivered_at field is null (not already confirmed). 4. Verify that all
     *   order items in the shipment are in 'shipped' status. 5. Set
     *   delivered_at to current timestamp on the shipment record. 6. Update all
     *   order items included in this shipment to 'delivered' status. 7. Return
     *   the updated shipment object with delivered_at timestamp. 8. Handle edge
     *   cases: if shipment already delivered, return 400 Bad Request with error
     *   message. If order items not in shipped status, return 400 Bad Request.
     *   If customer doesn't own the order, return 403 Forbidden.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async confirmDelivery(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedParam("shipmentId")
    shipmentId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallShipment> {
    try {
      return await postShoppingMallCustomerOrdersOrderIdShipmentsShipmentIdDelivered(
        {
          customer,
          orderId,
          shipmentId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
