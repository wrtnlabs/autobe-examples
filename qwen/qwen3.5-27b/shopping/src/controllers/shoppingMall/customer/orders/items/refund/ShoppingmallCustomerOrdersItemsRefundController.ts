import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IShoppingMallRefundRequest } from "../../../../../../api/structures/IShoppingMallRefundRequest";
import { CustomerAuth } from "../../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../../decorators/payload/CustomerPayload";
import { postShoppingMallCustomerOrdersOrderIdItemsItemIdRefund } from "../../../../../../providers/postShoppingMallCustomerOrdersOrderIdItemsItemIdRefund";

@Controller("/shoppingMall/customer/orders/:orderId/items/:itemId/refund")
export class ShoppingmallCustomerOrdersItemsRefundController {
  /**
   * Create a refund request for a delivered order item.
   *
   * This endpoint allows customers to submit refund requests for individual order items that have been delivered. The refund request must be submitted within 7 days of the item's delivery date. When submitted, the request enters 'pending' status and awaits seller approval or rejection.
   *
   * The refund request includes a reason text that helps sellers evaluate the request. Upon approval, the order item status changes to 'refunded' and stock quantities are automatically restored. If rejected, the request remains in 'rejected' status and the item maintains its 'delivered' status.
   *
   * Customers can only request refunds for items they purchased that have 'delivered' status. Items with 'paid', 'shipped', 'cancelled', or 'refunded' status cannot have refund requests created.
   *
   * @param connection
   * @param orderId Unique identifier of the order containing the item being refunded.
   * @param itemId Unique identifier of the order item for which the refund is being requested.
   * @param body Refund request details including the reason for requesting the refund.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification 1. Validate the orderId and itemId path
     *   parameters exist and are valid UUIDs. 2. Verify the order item exists
     *   and belongs to the authenticated customer's order. 3. Check that the
     *   order item status is 'delivered'. Return 400 Bad Request if status is
     *   not 'delivered'. 4. Calculate the time elapsed since the item was
     *   delivered. Return 400 Bad Request if more than 7 days have passed. 5.
     *   Verify no existing refund request exists for this order item with
     *   'pending' status. Return 409 Conflict if one exists. 6. Create a new
     *   shopping_mall_refund_requests record with: -
     *   shopping_mall_order_item_id: the itemId parameter -
     *   shopping_mall_customer_id: authenticated customer's ID -
     *   shopping_mall_customer_session_id: current session ID -
     *   shopping_mall_seller_id: null (will be set when seller responds) -
     *   shopping_mall_seller_session_id: null - reason: from request body -
     *   status: 'pending' - created_at: current timestamp - updated_at: current
     *   timestamp - responded_at: null 7. Return the created refund request
     *   with 201 Created status. 8. Handle edge cases: item not found (404),
     *   customer not authorized (403), item not delivered (400), outside 7-day
     *   window (400), duplicate request (409).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedParam("itemId")
    itemId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallRefundRequest.ICreate,
  ): Promise<IShoppingMallRefundRequest> {
    try {
      return await postShoppingMallCustomerOrdersOrderIdItemsItemIdRefund({
        customer,
        orderId,
        itemId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
