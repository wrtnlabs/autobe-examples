import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallCustomerCart } from "../../../../api/structures/IShoppingMallCustomerCart";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { getShoppingMallCustomerCart } from "../../../../providers/getShoppingMallCustomerCart";

@Controller("/shoppingMall/customer/cart")
export class ShoppingmallCustomerCartController {
  /**
   * Retrieves the authenticated customer's shopping cart with all items and their details.
   *
   * This endpoint returns the customer's active shopping cart containing all cart items with product information, variant options, quantities, prices, and availability status. Each cart item displays the product name, variant options (e.g., color, size), unit price, quantity, and calculated subtotal. The response also includes the cart total price calculated from all items.
   *
   * Cart items that reference unavailable or deleted product variants are marked as unavailable and cannot be included in checkout. The cart persists across sessions and is automatically emptied after successful order placement.
   *
   * @param connection
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification Query shopping_mall_customer_carts table for the
     *   cart belonging to the authenticated customer's ID.
   *
   * Join with shopping_mall_customer_cart_items to retrieve all active cart items (deleted_at IS NULL).
   *
   * For each cart item, join with shopping_mall_product_variants to get variant details including SKU code, price, and options.
   *
   * Join with shopping_mall_products to get product name and description.
   *
   * Join with shopping_mall_product_variant_options to get variant option values (e.g., color, size).
   *
   * Check variant availability by joining with shopping_mall_inventory_records to determine current stock levels.
   *
   * Mark cart items as unavailable if:
   * - The referenced product variant no longer exists
   * - The variant's available stock is less than the cart item quantity
   * - The variant is marked as deleted
   *
   * Calculate subtotal for each cart item (unit_price * quantity).
   *
   * Calculate cart total by summing all cart item subtotals.
   *
   * Return cart with nested cart_items array containing full product and variant information.
   *
   * Handle edge cases:
   * - Customer has no cart: Return empty cart object with empty cart_items array
   * - Cart has no items: Return cart with empty cart_items array and total of 0
   * - Some items unavailable: Include them with unavailable flag set to true
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
  ): Promise<IShoppingMallCustomerCart> {
    try {
      return await getShoppingMallCustomerCart({
        customer,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
