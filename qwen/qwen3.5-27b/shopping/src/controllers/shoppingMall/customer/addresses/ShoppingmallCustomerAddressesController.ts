import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallCustomerAddress } from "../../../../api/structures/IPageIShoppingMallCustomerAddress";
import { IShoppingMallCustomerAddress } from "../../../../api/structures/IShoppingMallCustomerAddress";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { deleteShoppingMallCustomerAddressesAddressId } from "../../../../providers/deleteShoppingMallCustomerAddressesAddressId";
import { getShoppingMallCustomerAddressesAddressId } from "../../../../providers/getShoppingMallCustomerAddressesAddressId";
import { patchShoppingMallCustomerAddresses } from "../../../../providers/patchShoppingMallCustomerAddresses";
import { postShoppingMallCustomerAddresses } from "../../../../providers/postShoppingMallCustomerAddresses";

@Controller("/shoppingMall/customer/addresses")
export class ShoppingmallCustomerAddressesController {
  /**
   * Creates a new shipping address for the authenticated customer's account.
   *
   * This operation allows customers to add a new delivery destination to their profile. The address includes recipient name, phone number, street address, city, state/province, postal code, and country information.
   *
   * Once created, the address can be used as a shipping destination during checkout. Customers can maintain multiple addresses for different recipients (home, work, gifts, etc.).
   *
   * @param connection
   * @param body New shipping address details including recipient name, contact number, and complete location information for package delivery.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification 1. Validate the request body contains all required fields: recipient_name, phone_number, street_address, city, postal_code, country.
   * 2. Set is_default to false initially (can be set as default later via separate endpoint).
   * 3. Set created_at and updated_at to the current timestamp.
   * 4. Set deleted_at to null (address is active).
   * 5. Associate the address with the currently authenticated customer (shopping_mall_customer_id).
   * 6. Insert the new record into shopping_mall_customer_addresses table.
   * 7. Return the complete address object including the generated id.
   *
   * Error handling:
   * - Return 401 if user is not authenticated.
   * - Return 400 if any required field is missing or invalid.
   * - Return 500 on any other server-side error.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallCustomerAddress.ICreate,
  ): Promise<IShoppingMallCustomerAddress> {
    try {
      return await postShoppingMallCustomerAddresses({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a paginated list of shipping addresses for the authenticated customer.
   *
   * This endpoint allows customers to view all their saved shipping addresses with optional filtering and sorting capabilities. Each address includes recipient name, phone number, street address, city, state/province, postal code, country, and default status indicator.
   *
   * The response supports cursor-based pagination for efficient browsing of large address lists. Customers can filter addresses by various criteria such as recipient name, default status, or country to quickly find the address they need.
   *
   * Only addresses belonging to the authenticated customer are returned. Soft-deleted addresses are excluded from results. The default address is clearly marked to facilitate quick selection during checkout.
   *
   * @param connection
   * @param body Search and pagination criteria for customer addresses. Supports filtering by recipient name, default status, and country. Includes sorting options and pagination parameters for efficient list navigation.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query shopping_mall_customer_addresses table for the authenticated customer's addresses.
   *
   * Apply filtering based on request body criteria:
   * - Search by recipient_name (partial match)
   * - Filter by is_default flag (true/false)
   * - Filter by country
   * - Sort by created_at, updated_at, or is_default
   * - Pagination with cursor or offset/limit
   *
   * Exclude soft-deleted addresses (deleted_at IS NULL).
   *
   * Join with shopping_mall_customers to verify ownership (addresses must belong to authenticated customer).
   *
   * Return paginated results with metadata (total count, cursor for next page).
   *
   * Business rules:
   * - Only return addresses belonging to the authenticated customer
   * - Default address should be easily identifiable in the response
   * - Support sorting by is_default to show default address first
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallCustomerAddress.IRequest,
  ): Promise<IPageIShoppingMallCustomerAddress.ISummary> {
    try {
      return await patchShoppingMallCustomerAddresses({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single shipping address by its unique identifier.
   *
   * This operation allows authenticated customers to fetch the complete details of one of their saved shipping addresses. The address information includes recipient name, phone number, street address, city, state/province, postal code, country, and default status indicator.
   *
   * Address data is used for order shipping destinations and checkout address selection. Each customer can maintain multiple addresses for different shipping locations such as home, work, or gift recipients. Only the address owner can retrieve their own address details - cross-customer access is not permitted.
   *
   * The addressId parameter must be a valid UUID that corresponds to an existing address in the customer's account. If the address has been soft-deleted, it will not be returned.
   *
   * @param connection
   * @param addressId Unique identifier of the shipping address to retrieve (global scope)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query the shopping_mall_customer_addresses table for a single record matching the provided addressId parameter.
   *
   * Authentication: Verify the request is made by an authenticated customer. Extract the customer ID from the session token.
   *
   * Authorization: Validate that the address belongs to the authenticated customer by checking shopping_mall_customer_id matches the session customer ID. Reject with 403 Forbidden if ownership verification fails.
   *
   * Database query: SELECT * FROM shopping_mall_customer_addresses WHERE id = :addressId AND shopping_mall_customer_id = :customerId AND deleted_at IS NULL.
   *
   * Validation: Ensure addressId is a valid UUID format. Return 404 Not Found if no matching address exists or if the address has been soft-deleted.
   *
   * Response: Return the complete address entity with all fields including id, recipient_name, phone_number, street_address, city, state_province, postal_code, country, is_default, created_at, and updated_at.
   *
   * Error handling: Return 401 Unauthorized if not authenticated, 403 Forbidden if address does not belong to customer, 404 Not Found if address does not exist.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":addressId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("addressId")
    addressId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallCustomerAddress> {
    try {
      return await getShoppingMallCustomerAddressesAddressId({
        customer,
        addressId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a shipping address from the customer's account.
   *
   * This operation permanently removes a shipping address from the customer's available addresses. The address is soft-deleted (marked with deleted_at timestamp) rather than hard-deleted from the database, preserving it for historical order records.
   *
   * **Constraints**:
   * - Customers cannot delete their last remaining address - at least one address must be maintained
   * - Customers cannot delete their default address without first setting another address as the default
   * - Only the address owner can delete their own addresses
   *
   * **Important**: Deleting an address does not affect any orders that were placed using that address. Order records preserve the shipping address information at the time of purchase, so deleted addresses will still appear in order history.
   *
   * @param connection
   * @param addressId UUID of the address to delete (global scope)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification DELETE operation for removing a customer's shipping address from their account.
   *
   * **Authorization**: Verify the authenticated customer owns the address being deleted (check shopping_mall_customer_id matches current user).
   *
   * **Validation Rules**:
   * 1. Check if the address is the only one for this customer - reject with error if true
   * 2. Check if the address is set as default (is_default = true) - reject with error requiring new default to be set first
   * 3. Verify the address belongs to the authenticated customer
   *
   * **Implementation**:
   * 1. Fetch the address record by addressId
   * 2. Validate ownership against current authenticated customer
   * 3. Query total count of active (deleted_at IS NULL) addresses for this customer
   * 4. If count is 1, reject with 'cannot delete last address' error
   * 5. If is_default is true, reject with 'cannot delete default address' error
   * 6. Set deleted_at to current timestamp (soft delete)
   * 7. Return 204 No Content or null response
   *
   * **Error Handling**:
   * - 404 if address not found
   * - 403 if customer doesn't own the address
   * - 400 if trying to delete last address
   * - 400 if trying to delete default address without setting new default first
   *
   * **Note**: Soft delete preserves the address for historical orders. Orders that used this address will still show the address information when viewed.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":addressId")
  public async erase(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("addressId")
    addressId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallCustomerAddressesAddressId({
        customer,
        addressId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
