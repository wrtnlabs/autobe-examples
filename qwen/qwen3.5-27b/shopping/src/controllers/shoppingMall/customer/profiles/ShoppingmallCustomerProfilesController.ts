import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallCustomerProfile } from "../../../../api/structures/IPageIShoppingMallCustomerProfile";
import { IShoppingMallCustomerProfile } from "../../../../api/structures/IShoppingMallCustomerProfile";
import { IShoppingMallSellerProfile } from "../../../../api/structures/IShoppingMallSellerProfile";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { getShoppingMallCustomerProfilesProfileId } from "../../../../providers/getShoppingMallCustomerProfilesProfileId";
import { patchShoppingMallCustomerProfiles } from "../../../../providers/patchShoppingMallCustomerProfiles";

@Controller("/shoppingMall/customer/profiles")
export class ShoppingmallCustomerProfilesController {
  /**
   * Search and list customer and seller profiles on the shopping mall platform.
   *
   * This administrative endpoint allows searching for profiles using various filters including profile type (customer or seller), name, email, approval status, suspension status, and date ranges. Results are returned in a paginated format with profile summaries optimized for administrative oversight and reporting.
   *
   * Administrators can use this endpoint to find specific profiles, generate reports, and monitor platform user activity. The search supports flexible filtering to help administrators quickly locate the profiles they need to review. Customer profiles include display name and phone number, while seller profiles include shop name, description, logo, and approval status.
   *
   * @param connection
   * @param body Search criteria including profile type filter, name/email search, status filters, date ranges, and pagination parameters.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification Search customer and seller profiles across the
     *   platform. Query shopping_mall_customer_profiles and
     *   shopping_mall_seller_profiles tables with filtering on profile type,
     *   name, email, approval status, suspension status, and date ranges. Join
     *   with shopping_mall_customers and shopping_mall_sellers for additional
     *   context including email and account status. Apply pagination and
     *   sorting based on request parameters. Filter out soft-deleted profiles
     *   unless explicitly requested. Return paginated profile summaries with
     *   relevant fields for each profile type.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallCustomerProfile.IRequest,
  ): Promise<IPageIShoppingMallCustomerProfile.ISummary> {
    try {
      return await patchShoppingMallCustomerProfiles({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves a single seller profile by its unique identifier.
   *
   * This endpoint returns complete seller profile information including shop name, description, logo image URL, approval status, rejection reason, suspension and ban flags, and creation/update timestamps. Seller profiles are publicly visible to all users on the platform for product listings and order records.
   *
   * The profile identifier is a UUID that uniquely identifies the seller profile across the system. If the profile is soft-deleted or does not exist, the endpoint returns a 404 Not Found response. Authentication is not required as seller profiles are public information.
   *
   * @param connection
   * @param profileId Unique identifier of the seller profile (global scope)
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification Query the shopping_mall_seller_profiles table by
     *   the id column (UUID primary key) matching the profileId parameter.
     *   Return the full profile record including all fields: id, shop_name,
     *   shop_description, logo_uri, approval_status, rejection_reason,
     *   is_suspended, is_banned, created_at, updated_at, and deleted_at.
   *
   * Validation: If the profile is soft-deleted (deleted_at is not null), return 404 Not Found. If no profile matches the provided profileId, return 404 Not Found.
   *
   * The response should include the complete seller profile entity. Do not include sensitive authentication fields from the related shopping_mall_sellers table (email, password_hash). The profile information is public and does not require authentication.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":profileId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("profileId")
    profileId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallSellerProfile> {
    try {
      return await getShoppingMallCustomerProfilesProfileId({
        customer,
        profileId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
