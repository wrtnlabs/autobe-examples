import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IShoppingMallCategory } from "../../../../api/structures/IShoppingMallCategory";
import { AdministratorAuth } from "../../../../decorators/AdministratorAuth";
import { AdministratorPayload } from "../../../../decorators/payload/AdministratorPayload";
import { postShoppingMallAdministratorCategories } from "../../../../providers/postShoppingMallAdministratorCategories";
import { putShoppingMallAdministratorCategoriesCategoryId } from "../../../../providers/putShoppingMallAdministratorCategoriesCategoryId";

@Controller("/shoppingMall/administrator/categories")
export class ShoppingmallAdministratorCategoriesController {
  /**
   * Create a new product category or subcategory for organizing products on the shopping mall platform.
   *
   * This operation allows administrators to establish the hierarchical category structure used for product organization and customer browsing. Categories can be created as top-level categories or as subcategories under existing parent categories. The system enforces a one-level nesting structure, preventing subcategories from having their own subcategories.
   *
   * When creating a subcategory, the parent_category_id must reference an existing top-level category. Category names must be unique within their parent scope (unique among top-level categories if no parent, or unique among siblings if a subcategory). Categories are immediately available for product assignment after creation.
   *
   * @param connection
   * @param body Category creation data including name, description, and optional parent category reference for subcategory creation.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Insert a new record into shopping_mall_categories table with provided name, description, and optional parent_category_id.
   *
   * Validation rules:
   * 1. Verify requester has administrator role - reject if not authorized
   * 2. Validate name is provided and not empty (min 1 character, max 255 characters)
   * 3. Validate description is provided and not empty (min 1 character, max 2000 characters)
   * 4. If parent_category_id is provided:
   *    - Verify parent category exists and is not deleted
   *    - Verify parent category is a top-level category (parent_category_id is NULL) - reject if attempting to create nested subcategories
   *    - Verify category name is unique among siblings (same parent_category_id)
   * 5. If parent_category_id is NULL:
   *    - Verify category name is unique among top-level categories
   * 6. Set created_at and updated_at to current timestamp
   * 7. Set deleted_at to NULL
   * 8. Return the created category with all fields including generated id
   *
   * Error handling:
   * - Return 401 Unauthorized if requester is not an administrator
   * - Return 400 Bad Request if name or description is missing or exceeds length limits
   * - Return 400 Bad Request if parent_category_id references a non-existent or deleted category
   * - Return 400 Bad Request if parent_category_id references a subcategory (nested subcategories not allowed)
   * - Return 409 Conflict if category name already exists within the same parent scope
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedBody()
    body: IShoppingMallCategory.ICreate,
  ): Promise<IShoppingMallCategory> {
    try {
      return await postShoppingMallAdministratorCategories({
        administrator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update a category's name and description.
   *
   * This endpoint allows administrators to modify existing category information. Only administrators have permission to update categories. When a category is updated, the change is immediately reflected across all product listings and category browsing pages. Category edits do not affect products assigned to the category—products remain in the same category after edits. The system preserves the category structure when edits are made, maintaining all parent-child relationships between categories and subcategories.
   *
   * @param connection
   * @param categoryId Unique identifier of the category to update (global scope).
   * @param body Category update data including name and/or description fields.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Query shopping_mall_categories table by id (UUID). Validate that the requesting user is an administrator. Update the name and/or description fields based on request body. Automatically update the updated_at timestamp to the current time. Return the updated category entity. If the category has been soft-deleted (deleted_at is not null), reject the update with a 404 or 410 error. Ensure the new name is unique within the same parent category (respect @@unique([parent_category_id, name]) constraint).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":categoryId")
  public async update(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("categoryId")
    categoryId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallCategory.IUpdate,
  ): Promise<IShoppingMallCategory> {
    try {
      return await putShoppingMallAdministratorCategoriesCategoryId({
        administrator,
        categoryId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
