import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallAdministratorPromotionRequestSnapshot } from "../../../../../api/structures/IPageIShoppingMallAdministratorPromotionRequestSnapshot";
import { IShoppingMallAdministratorPromotionRequestSnapshot } from "../../../../../api/structures/IShoppingMallAdministratorPromotionRequestSnapshot";
import { AdministratorAuth } from "../../../../../decorators/AdministratorAuth";
import { AdministratorPayload } from "../../../../../decorators/payload/AdministratorPayload";
import { getShoppingMallAdministratorPromotionRequestsRequestIdSnapshotsSnapshotId } from "../../../../../providers/getShoppingMallAdministratorPromotionRequestsRequestIdSnapshotsSnapshotId";
import { patchShoppingMallAdministratorPromotionRequestsRequestIdSnapshots } from "../../../../../providers/patchShoppingMallAdministratorPromotionRequestsRequestIdSnapshots";

@Controller(
  "/shoppingMall/administrator/promotion-requests/:requestId/snapshots",
)
export class ShoppingmallAdministratorPromotion_requestsSnapshotsController {
  /**
   * Retrieve paginated list of snapshots for a specific administrator promotion request with optional filtering.
   *
   * This endpoint returns all immutable audit snapshots that capture the state of a promotion request at each status transition (pending → approved, pending → rejected). Each snapshot preserves the complete request state including the submitting user's identity, reason, status, and any administrator response information.
   *
   * Sellers can view snapshots of their own promotion requests. Customers can view snapshots of their own promotion requests. Administrators can view snapshots of any promotion request on the platform for oversight and dispute resolution purposes.
   *
   * Snapshots are ordered by creation timestamp and include before/after values for all changed fields, enabling complete audit trail visibility.
   *
   * @param connection
   * @param requestId UUID of the administrator promotion request whose snapshots to retrieve.
   * @param body Search criteria for filtering promotion request snapshots including pagination parameters and optional filters for status and date range.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor administrator
     * @x-autobe-specification Query
     *   shopping_mall_administrator_promotion_request_snapshots table filtered
     *   by shopping_mall_administrator_promotion_request_id from path
     *   parameter.
   *
   * Apply pagination from request body: page size (default 20), cursor for cursor-based pagination.
   *
   * Apply optional filters from request body:
   * - status filter: filter snapshots by specific status (pending, approved, rejected)
   * - date range filter: filter by created_at between start and end dates
   *
   * Sort by created_at in descending order (newest first) by default.
   *
   * Join with shopping_mall_administrator_promotion_requests to verify request exists and check access permissions.
   *
   * Authorization:
   * - If requester is customer: verify user_id in snapshot matches requester's customer ID
   * - If requester is seller: verify user_id in snapshot matches requester's seller ID
   * - If requester is administrator: allow access to all snapshots
   *
   * Return paginated response with:
   * - snapshots array with summary fields (id, created_at, status, user_type, reason)
   * - pagination metadata (page size, has next page, next cursor)
   *
   * Handle edge cases:
   * - Return empty array if no snapshots exist for the request
   * - Return 404 if promotion request does not exist
   * - Return 403 if user attempts to access another user's snapshots (non-admin)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("requestId")
    requestId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallAdministratorPromotionRequestSnapshot.IRequest,
  ): Promise<IPageIShoppingMallAdministratorPromotionRequestSnapshot.ISummary> {
    try {
      return await patchShoppingMallAdministratorPromotionRequestsRequestIdSnapshots(
        {
          administrator,
          requestId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific administrator promotion request snapshot by request ID and snapshot ID.
   *
   * This operation returns the complete state of an administrator promotion request at a specific point in time. Snapshots are immutable audit records created automatically whenever a promotion request status changes (from pending to approved or rejected). Each snapshot captures the user's identity, promotion reason, request status, and any administrator response information.
   *
   * Only administrators have access to view these snapshots. They serve as an audit trail for the administrator promotion workflow and enable dispute resolution by preserving historical request states.
   *
   * The snapshot includes the original user who submitted the request, their user type (customer or seller), the promotion reason they provided, the status at snapshot time, the super administrator who responded (if applicable), and any rejection reason provided.
   *
   * @param connection
   * @param requestId UUID of the administrator promotion request (global scope)
   * @param snapshotId UUID of the specific snapshot to retrieve (global scope)
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor administrator
     * @x-autobe-specification Query
     *   shopping_mall_administrator_promotion_request_snapshots table for the
     *   snapshot with matching id and
     *   shopping_mall_administrator_promotion_request_id.
   *
   * Validation:
   * 1. Verify both requestId and snapshotId are valid UUIDs
   * 2. Verify the authenticated user is an administrator (only administrators can view promotion request snapshots)
   * 3. Verify the snapshot exists for the given requestId
   *
   * Implementation:
   * 1. Execute SELECT query with WHERE clause: id = snapshotId AND shopping_mall_administrator_promotion_request_id = requestId
   * 2. Return 404 if no matching snapshot found
   * 3. Return the complete snapshot record including all fields: id, user_id, user_type, reason, status, approved_by, response_reason, created_at
   *
   * Error handling:
   * - 404 Not Found: snapshot does not exist or doesn't belong to the specified request
   * - 403 Forbidden: user is not an administrator
   * - 400 Bad Request: invalid UUID format in path parameters
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":snapshotId")
  public async at(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("requestId")
    requestId: string & tags.Format<"uuid">,
    @TypedParam("snapshotId")
    snapshotId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallAdministratorPromotionRequestSnapshot> {
    try {
      return await getShoppingMallAdministratorPromotionRequestsRequestIdSnapshotsSnapshotId(
        {
          administrator,
          requestId,
          snapshotId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
