import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallAdministratorPromotionRequest } from "../../../../api/structures/IPageIShoppingMallAdministratorPromotionRequest";
import { IShoppingMallAdministratorPromotionRequest } from "../../../../api/structures/IShoppingMallAdministratorPromotionRequest";
import { AdministratorAuth } from "../../../../decorators/AdministratorAuth";
import { AdministratorPayload } from "../../../../decorators/payload/AdministratorPayload";
import { getShoppingMallAdministratorPromotionRequestsRequestId } from "../../../../providers/getShoppingMallAdministratorPromotionRequestsRequestId";
import { patchShoppingMallAdministratorPromotionRequests } from "../../../../providers/patchShoppingMallAdministratorPromotionRequests";
import { putShoppingMallAdministratorPromotionRequestsRequestId } from "../../../../providers/putShoppingMallAdministratorPromotionRequestsRequestId";

@Controller("/shoppingMall/administrator/promotion-requests")
export class ShoppingmallAdministratorPromotion_requestsController {
  /**
   * Retrieve a paginated list of administrator promotion requests with filtering and sorting capabilities.
   *
   * This endpoint allows super administrators to view all promotion requests submitted by customers or sellers who want to become administrators. Requests can be filtered by status (pending, approved, rejected) and actor type (customer, seller). The list is sorted by creation date with newest requests appearing first by default.
   *
   * Each promotion request includes the reason provided by the requesting user, current status, and if rejected, the rejection reason from the super administrator. The response also indicates which super administrator processed the request when available.
   *
   * Only super administrators have access to this endpoint. Regular administrators and other users cannot view promotion requests.
   *
   * @param connection
   * @param body Search criteria for filtering promotion requests including status, actor type, pagination parameters, and sorting options.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor administrator
     * @x-autobe-specification Query
     *   shopping_mall_administrator_promotion_requests table with pagination
     *   and filtering.
   *
   * Apply search filters from request body:
   * - Filter by status (pending, approved, rejected)
   * - Filter by actor_type (customer, seller)
   * - Optional text search on reason field
   * - Sort by created_at (default descending for newest first)
   *
   * Join with subtype tables (shopping_mall_administrator_promotion_request_of_customers, shopping_mall_administrator_promotion_request_of_sellers) to retrieve user identity information.
   *
   * Join with shopping_mall_administrators to get processed_by_administrator details when populated.
   *
   * Return cursor-based pagination for large result sets.
   *
   * Only super administrators can access this endpoint. Validate authorization before executing query.
   *
   * Return summary records with essential fields: id, actor_type, reason, status, created_at, processed_by_administrator_id, rejected_reason (if applicable).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedBody()
    body: IShoppingMallAdministratorPromotionRequest.IRequest,
  ): Promise<IPageIShoppingMallAdministratorPromotionRequest.ISummary> {
    try {
      return await patchShoppingMallAdministratorPromotionRequests({
        administrator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single administrator promotion request by its unique identifier.
   *
   * This endpoint returns complete details of an administrator promotion request including the requesting user's identity (customer or seller), the reason provided for the request, current status (pending, approved, or rejected), and any administrator response information. The response includes the super administrator who processed the request (if approved or rejected) and a complete audit trail of status transition snapshots.
   *
   * Super administrators use this endpoint to review specific promotion requests before making approval or rejection decisions. The endpoint provides all necessary information to evaluate the request and maintain accountability for administrative actions.
   *
   * @param connection
   * @param requestId Unique identifier of the administrator promotion request to retrieve (global scope)
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor administrator
     * @x-autobe-specification Query
     *   shopping_mall_administrator_promotion_requests table by primary key (id
     *   = requestId). Join with
     *   shopping_mall_administrator_promotion_request_of_customers or
     *   shopping_mall_administrator_promotion_request_of_sellers based on
     *   actor_type field to retrieve the requesting user's identity. Join with
     *   shopping_mall_administrators to get the super administrator who
     *   processed the request (if any). Include related
     *   shopping_mall_administrator_promotion_request_snapshots ordered by
     *   created_at descending for audit trail. Return 404 if request not found.
     *   Return 403 if current user is not a super administrator (authorization
     *   handled by middleware).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":requestId")
  public async at(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("requestId")
    requestId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallAdministratorPromotionRequest> {
    try {
      return await getShoppingMallAdministratorPromotionRequestsRequestId({
        administrator,
        requestId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an administrator promotion request by approving or rejecting it.
   *
   * This endpoint allows super administrators to process pending administrator promotion requests. When a request is approved, the submitting user (customer or seller) is granted regular administrator privileges. When rejected, the request is denied with an optional reason that is visible to the requesting user.
   *
   * The operation creates an immutable snapshot of the request state before updating, preserving the audit trail for dispute resolution and compliance purposes. The snapshot captures the user identity, reason for the request, status transition, and the administrator who processed it.
   *
   * Only super administrators can perform this operation. Regular administrators cannot approve or reject promotion requests.
   *
   * @param connection
   * @param requestId Unique identifier of the administrator promotion request to update (global scope).
   * @param body Update payload containing the new status (approved or rejected) and optional rejection reason.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor administrator
     * @x-autobe-specification Update an administrator promotion request's
     *   status from pending to approved or rejected.
   *
   * 1. Validate that the requesting administrator is a super administrator.
   * 2. Find the promotion request by requestId from shopping_mall_administrator_promotion_requests table.
   * 3. Verify the request status is 'pending' - reject if already processed.
   * 4. Validate the new status is either 'approved' or 'rejected'.
   * 5. If status is 'rejected', validate that rejected_reason is provided and non-empty.
   * 6. Create a snapshot of the current state before updating (shopping_mall_administrator_promotion_request_snapshots).
   * 7. Update the promotion request:
   *    - Set status to the new value
   *    - Set processed_by_administrator_id to the current super administrator's ID
   *    - Set rejected_reason if status is 'rejected'
   *    - Update updated_at timestamp
   * 8. If status is 'approved':
   *    - Look up the user (customer or seller) who submitted the request via subtype tables
   *    - Create a new administrator account for the user
   *    - Set the new administrator's grade to 'regular'
   *    - Link the new administrator to the original user account
   * 9. Return the updated promotion request with full details including user information.
   *
   * Error handling:
   * - Return 404 if request not found
   * - Return 400 if status is not pending
   * - Return 400 if rejected_reason is missing when status is 'rejected'
   * - Return 403 if caller is not a super administrator
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":requestId")
  public async update(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("requestId")
    requestId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallAdministratorPromotionRequest.IUpdate,
  ): Promise<IShoppingMallAdministratorPromotionRequest> {
    try {
      return await putShoppingMallAdministratorPromotionRequestsRequestId({
        administrator,
        requestId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
