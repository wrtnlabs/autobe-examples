import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IShoppingMallCustomer } from "../../../../../api/structures/IShoppingMallCustomer";
import { AdministratorAuth } from "../../../../../decorators/AdministratorAuth";
import { AdministratorPayload } from "../../../../../decorators/payload/AdministratorPayload";
import { postShoppingMallAdministratorCustomersCustomerIdBan } from "../../../../../providers/postShoppingMallAdministratorCustomersCustomerIdBan";

@Controller("/shoppingMall/administrator/customers/:customerId/ban")
export class ShoppingmallAdministratorCustomersController {
  /**
   * Administrators can ban or unban customer accounts to control platform access.
   *
   * When a customer account is banned, the customer loses the ability to log in to the platform and access any features. Banned accounts retain their order history, reviews (shown as 'deleted user'), and all associated data. This preserves transaction records for legal and business purposes while preventing further platform usage.
   *
   * When a customer account is unbanned, the customer immediately regains full login and platform access. The customer's profile information, order history, and all associated data remain intact during both the ban and unban process.
   *
   * This operation requires administrator privileges and is used for platform policy enforcement and user management.
   *
   * @param connection
   * @param customerId Unique identifier of the customer account to ban or unban (global scope)
   * @param body Ban status to set for the customer account. Set to true to ban the customer (prevent login), set to false to unban the customer (restore login access).
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor administrator
     * @x-autobe-specification Update the banned boolean field in
     *   shopping_mall_customers table based on the request body.
   *
   * 1. Validate that the customerId exists in shopping_mall_customers table
   * 2. Verify the customer is not soft-deleted (deleted_at is null)
   * 3. Update the banned field to the value provided in request body
   * 4. Update the updated_at timestamp to current time
   * 5. Return the updated customer entity with the new banned status
   *
   * Error handling:
   * - Return 404 if customer with given customerId does not exist
   * - Return 404 if customer is soft-deleted (deleted_at is not null)
   * - Return 400 if banned field is not a boolean value
   * - Ensure only authenticated administrators can access this operation
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async ban(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("customerId")
    customerId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallCustomer.IBanRequest,
  ): Promise<IShoppingMallCustomer> {
    try {
      return await postShoppingMallAdministratorCustomersCustomerIdBan({
        administrator,
        customerId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
