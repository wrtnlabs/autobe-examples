import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IShoppingMallSeller } from "../../../../../api/structures/IShoppingMallSeller";
import { IShoppingMallSellerProfile } from "../../../../../api/structures/IShoppingMallSellerProfile";
import { AdministratorAuth } from "../../../../../decorators/AdministratorAuth";
import { AdministratorPayload } from "../../../../../decorators/payload/AdministratorPayload";
import { postShoppingMallAdministratorSellersSellerIdBan } from "../../../../../providers/postShoppingMallAdministratorSellersSellerIdBan";

@Controller("/shoppingMall/administrator/sellers/:sellerId/ban")
export class ShoppingmallAdministratorSellersBanController {
  /**
   * Toggle ban status for a seller account. This administrative operation allows administrators to ban or unban seller accounts, controlling their platform access while preserving all existing orders and data.
   *
   * **Ban Action**: When a seller is banned, they cannot log in to the platform. Their existing orders remain in the system and are preserved for record-keeping. This is a severe action typically used for policy violations or fraudulent activity.
   *
   * **Unban Action**: When a seller is unbanned, they regain the ability to log in and use the platform. All their historical data including orders, products, and profiles remain intact.
   *
   * **Authorization**: Only administrators with appropriate permissions can perform this operation. The operation updates both the seller account's banned flag and the seller profile's is_banned field for data consistency.
   *
   * @param connection
   * @param sellerId Unique identifier of the seller account to ban or unban (global scope)
   * @param body Action to perform on the seller account. Must be either 'ban' to prevent login or 'unban' to restore login access.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification 1. Validate sellerId exists in shopping_mall_sellers table
   * 2. Retrieve the seller record and associated seller profile from shopping_mall_seller_profiles
   * 3. Parse request body to extract action field ('ban' or 'unban')
   * 4. Validate action is one of the allowed values
   * 5. If action is 'ban':
   *    - Set shopping_mall_sellers.banned = true
   *    - Set shopping_mall_seller_profiles.is_banned = true
   * 6. If action is 'unban':
   *    - Set shopping_mall_sellers.banned = false
   *    - Set shopping_mall_seller_profiles.is_banned = false
   * 7. Update shopping_mall_sellers.updated_at to current timestamp
   * 8. Update shopping_mall_seller_profiles.updated_at to current timestamp
   * 9. Return the updated seller profile with current ban status
   * 10. Log the ban/unban action in administrator audit trail
   * 11. Handle edge cases:
   *     - Seller not found: return 404 Not Found
   *     - Invalid action value: return 400 Bad Request
   *     - Seller profile not found: return 404 Not Found
   *     - Insufficient permissions: return 403 Forbidden
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async toggleBan(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallSeller.IBanAction,
  ): Promise<IShoppingMallSellerProfile> {
    try {
      return await postShoppingMallAdministratorSellersSellerIdBan({
        administrator,
        sellerId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
