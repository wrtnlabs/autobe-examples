import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IShoppingMallSeller } from "../../../../api/structures/IShoppingMallSeller";
import { IShoppingMallSellerProfile } from "../../../../api/structures/IShoppingMallSellerProfile";
import { AdministratorAuth } from "../../../../decorators/AdministratorAuth";
import { AdministratorPayload } from "../../../../decorators/payload/AdministratorPayload";
import { postShoppingMallAdministratorSellersSellerIdApprove } from "../../../../providers/postShoppingMallAdministratorSellersSellerIdApprove";
import { postShoppingMallAdministratorSellersSellerIdReject } from "../../../../providers/postShoppingMallAdministratorSellersSellerIdReject";
import { postShoppingMallAdministratorSellersSellerIdSuspend } from "../../../../providers/postShoppingMallAdministratorSellersSellerIdSuspend";

@Controller("/shoppingMall/administrator/sellers/:sellerId")
export class ShoppingmallAdministratorSellersController {
  /**
   * Toggle suspension status for a seller account.
   *
   * This operation allows platform administrators to temporarily suspend or unsuspend a seller account. When a seller is suspended, their products are hidden from search results and category listings, and customers cannot purchase their products. However, suspended sellers retain the ability to process existing orders, ship items, and respond to cancellation or refund requests. They cannot create new products or edit existing products while suspended. When unsuspended, the seller's products become visible and purchasable again, and they regain full product management capabilities.
   *
   * @param connection
   * @param sellerId Unique identifier of the seller account to suspend or unsuspend (global scope).
   * @param body Suspension state to set for the seller account. Set to true to suspend, false to unsuspend.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification 1. Validate that the authenticated user is an administrator with seller management permissions.
   * 2. Validate that sellerId exists and is a valid UUID.
   * 3. Query the shopping_mall_sellers table to verify the seller exists and is not deleted (deleted_at is null).
   * 4. Update the 'suspended' boolean field in shopping_mall_sellers table to the value provided in request body.
   * 5. Update the 'is_suspended' boolean field in shopping_mall_seller_profiles table to match.
   * 6. Update the 'updated_at' timestamp in both tables.
   * 7. Return the updated seller profile information including the new suspension status.
   * 8. Handle edge cases: seller not found, seller already deleted, insufficient permissions.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("suspend")
  public async suspend(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallSeller.ISuspendRequest,
  ): Promise<IShoppingMallSellerProfile> {
    try {
      return await postShoppingMallAdministratorSellersSellerIdSuspend({
        administrator,
        sellerId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Approve a pending seller registration request, allowing the seller to begin selling products on the platform.
   *
   * This operation is available to administrators only. It transitions a seller account from 'pending' approval status to 'approved', enabling the seller to create and manage products, process orders, and access all seller features. The approval reason is recorded for audit trail purposes.
   *
   * Security: Requires administrator authentication. Only sellers with 'pending' approval status can be approved. The operation validates that the seller exists and is in the correct state before performing the approval.
   *
   * Business Logic: Upon approval, the seller's approval_status is updated to 'approved', the approval_reason is recorded, and the seller gains full platform access. The seller can immediately begin creating products and managing their shop profile.
   *
   * @param connection
   * @param sellerId Unique identifier of the seller account to approve (global scope).
   * @param body Optional approval reason to be recorded for audit trail purposes.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification 1. Validate administrator authentication and authorization.
   * 2. Verify sellerId exists and corresponds to a valid seller account.
   * 3. Check that seller's approval_status is 'pending' - reject if already approved or rejected.
   * 4. Check that seller is not banned or suspended - if suspended, unsuspend first.
   * 5. Update seller record:
   *    - Set approval_status to 'approved'
   *    - Set approval_reason from request body (if provided)
   *    - Update updated_at timestamp
   * 6. Update seller profile record:
   *    - Set approval_status to 'approved'
   *    - Clear rejection_reason (if exists)
   *    - Update updated_at timestamp
   * 7. Return the updated seller entity including their profile information.
   * 8. Log the approval action in administrator audit trail.
   *
   * Edge Cases:
   * - If seller is already approved, return 409 Conflict error
   * - If seller is rejected, return 409 Conflict error (seller must reapply)
   * - If seller is banned, return 403 Forbidden error
   * - If seller does not exist, return 404 Not Found error
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("approve")
  public async approve(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallSeller.IApprove,
  ): Promise<IShoppingMallSeller> {
    try {
      return await postShoppingMallAdministratorSellersSellerIdApprove({
        administrator,
        sellerId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Reject a pending seller registration request and provide a rejection reason.
   *
   * Administrators use this operation to deny seller registration applications. When rejecting a seller, the administrator must provide a detailed rejection reason that explains why the application was denied. This reason is stored in the system and visible to the seller so they understand what needs to be corrected.
   *
   * After rejection, the seller's approval status changes to 'rejected' and they can submit a new registration request. The rejection reason helps sellers improve their application for resubmission. This operation can only be performed on sellers with 'pending' approval status.
   *
   * @param connection
   * @param sellerId Unique identifier of the seller account to reject (global scope)
   * @param body Rejection reason explaining why the seller registration was denied.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Validate that the seller's current approval_status is 'pending' in shopping_mall_sellers table - cannot reject already approved or already rejected sellers. Update the seller's approval_status to 'rejected' in shopping_mall_sellers table. Store the rejection_reason from request body in both shopping_mall_sellers.rejection_reason and shopping_mall_seller_profiles.rejection_reason fields. Create an audit log entry in shopping_mall_administrator_audit_logs recording the rejection action, administrator ID, seller ID, and rejection reason. Return the updated seller record with rejection details. Throw an error if the seller is not in pending status, if the seller is already banned or suspended, or if rejection reason is missing or empty.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("reject")
  public async reject(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallSeller.IReject,
  ): Promise<IShoppingMallSeller> {
    try {
      return await postShoppingMallAdministratorSellersSellerIdReject({
        administrator,
        sellerId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
