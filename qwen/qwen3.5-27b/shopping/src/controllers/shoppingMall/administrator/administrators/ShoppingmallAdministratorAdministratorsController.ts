import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IShoppingMallAdministrator } from "../../../../api/structures/IShoppingMallAdministrator";
import { AdministratorAuth } from "../../../../decorators/AdministratorAuth";
import { AdministratorPayload } from "../../../../decorators/payload/AdministratorPayload";
import { postShoppingMallAdministratorAdministratorsAdministratorIdBan } from "../../../../providers/postShoppingMallAdministratorAdministratorsAdministratorIdBan";
import { postShoppingMallAdministratorAdministratorsAdministratorIdDemote } from "../../../../providers/postShoppingMallAdministratorAdministratorsAdministratorIdDemote";
import { postShoppingMallAdministratorAdministratorsAdministratorIdPromote } from "../../../../providers/postShoppingMallAdministratorAdministratorsAdministratorIdPromote";

@Controller("/shoppingMall/administrator/administrators/:administratorId")
export class ShoppingmallAdministratorAdministratorsController {
  /**
   * Ban or unban an administrator account.
   *
   * This operation allows super administrators to prevent other administrators from logging in and accessing the system. When an administrator is banned, their account data is preserved for audit purposes, but they cannot authenticate or perform any administrative actions.
   *
   * ### Banning Behavior
   *
   * - When banned: The administrator cannot log in or access any system features
   * - When unbanned: The administrator can log in and exercise their privileges again
   * - Account data (including action logs) is always preserved
   * - Only super administrators can ban other administrators
   *
   * ### Use Cases
   *
   * - Remove administrative access for policy violations
   * - Temporarily restrict access during investigations
   * - Revoke access when an administrator leaves their role
   * - Reinstatement after review or appeal
   *
   * @param connection
   * @param administratorId The unique identifier of the administrator account to ban or unban.
   * @param body Request to ban or unban the administrator. Set 'ban' to true to ban, or false to unban.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor administrator
     * @x-autobe-specification 1. Validate that the current user is a super
     *   administrator (grade = 'super'). 2. Fetch the target administrator by
     *   administratorId from shopping_mall_administrators table. 3. If the
     *   target administrator is the same as the current user, reject the
     *   operation (self-protection). 4. Update the 'banned' boolean field on
     *   the target administrator record based on the request body. 5. Update
     *   the 'updated_at' timestamp. 6. Log the ban/unban action in the
     *   administrator audit log with before/after states. 7. Return the updated
     *   administrator record with the new banned status.
   *
   * ### Error Cases
   *
   * - 403 Forbidden: Current user is not a super administrator
   * - 403 Forbidden: Attempting to self-ban
   * - 404 Not Found: Target administrator does not exist
   * - 400 Bad Request: Invalid ban status value
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("ban")
  public async ban(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("administratorId")
    administratorId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallAdministrator.IBanRequest,
  ): Promise<IShoppingMallAdministrator> {
    try {
      return await postShoppingMallAdministratorAdministratorsAdministratorIdBan(
        {
          administrator,
          administratorId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Promotes a regular administrator to super administrator grade.
   *
   * This operation allows super administrators to elevate a regular administrator's privilege level, granting them full system access including the ability to manage administrator grades. The promotion is immediate and the administrator gains super administrator privileges upon successful completion.
   *
   * Only super administrators can perform this operation. The target administrator must currently have regular administrator grade. Administrator grade changes are recorded in the system audit trail for accountability and compliance purposes.
   *
   * @param connection
   * @param administratorId Unique identifier of the administrator to promote to super administrator grade (global scope).
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor administrator
     * @x-autobe-specification Validate that the calling administrator has super
     *   administrator grade. Verify the target administratorId exists and the
     *   administrator has regular grade. Check that the target administrator is
     *   not banned. Update the grade field from 'regular' to 'super' in the
     *   shopping_mall_administrators table. Update the updated_at timestamp.
     *   Create an audit log entry recording the grade change with the acting
     *   administrator's ID, target administrator ID, old grade, new grade, and
     *   timestamp. Return the updated administrator record excluding the
     *   password_hash field. Handle edge cases: throw error if caller is not
     *   super administrator, if target administrator doesn't exist, if target
     *   is already super administrator, or if target is banned.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("promote")
  public async promote(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("administratorId")
    administratorId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallAdministrator> {
    try {
      return await postShoppingMallAdministratorAdministratorsAdministratorIdPromote(
        {
          administrator,
          administratorId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Demote a super administrator to regular administrator grade.
   *
   * This operation allows super administrators to reduce the privilege level of another super administrator. When executed, the target administrator's grade is changed from 'super' to 'regular', removing their ability to manage administrator grades while retaining all regular administrator capabilities. The grade change is permanently recorded in the audit log for accountability and dispute resolution.
   *
   * Only super administrators can perform this operation. Super administrators cannot demote themselves to maintain system integrity and ensure at least one super administrator is always available.
   *
   * @param connection
   * @param administratorId Unique identifier of the super administrator to demote to regular administrator grade.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor administrator
     * @x-autobe-specification 1. Verify the calling administrator is
     *   authenticated and has 'super' grade level. 2. Fetch the target
     *   administrator by administratorId from shopping_mall_administrators
     *   table. 3. Validate the target administrator exists and has 'super'
     *   grade (cannot demote regular administrators). 4. Validate the target
     *   administrator is not the same as the calling administrator (cannot
     *   self-demote). 5. Validate there is at least one other super
     *   administrator in the system (prevent removing all super admins). 6.
     *   Begin database transaction. 7. Update the target administrator's grade
     *   from 'super' to 'regular' in shopping_mall_administrators table. 8.
     *   Insert a new record into shopping_mall_administrator_grade_changes
     *   with: - administrator_id: target administrator's id - performed_by_id:
     *   calling administrator's id - previous_grade: 'super' - new_grade:
     *   'regular' - change_type: 'demotion' - created_at: current timestamp 9.
     *   Commit transaction. 10. Return the updated administrator record.
   *
   * Error handling:
   * - Return 401 if calling administrator is not authenticated
   * - Return 403 if calling administrator is not a super administrator
   * - Return 404 if target administrator not found
   * - Return 409 if target administrator is already a regular administrator
   * - Return 409 if attempting to self-demote
   * - Return 409 if this would remove the last super administrator
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("demote")
  public async demote(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("administratorId")
    administratorId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallAdministrator> {
    try {
      return await postShoppingMallAdministratorAdministratorsAdministratorIdDemote(
        {
          administrator,
          administratorId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
