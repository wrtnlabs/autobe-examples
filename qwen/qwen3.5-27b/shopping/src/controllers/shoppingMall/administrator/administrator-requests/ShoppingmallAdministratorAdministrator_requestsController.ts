import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallAdministratorRequest } from "../../../../api/structures/IPageIShoppingMallAdministratorRequest";
import { IShoppingMallAdministratorRequest } from "../../../../api/structures/IShoppingMallAdministratorRequest";
import { AdministratorAuth } from "../../../../decorators/AdministratorAuth";
import { AdministratorPayload } from "../../../../decorators/payload/AdministratorPayload";
import { getShoppingMallAdministratorAdministratorRequestsAdministratorRequestId } from "../../../../providers/getShoppingMallAdministratorAdministratorRequestsAdministratorRequestId";
import { patchShoppingMallAdministratorAdministratorRequests } from "../../../../providers/patchShoppingMallAdministratorAdministratorRequests";
import { putShoppingMallAdministratorAdministratorRequestsAdministratorRequestId } from "../../../../providers/putShoppingMallAdministratorAdministratorRequestsAdministratorRequestId";

@Controller("/shoppingMall/administrator/administrator-requests")
export class ShoppingmallAdministratorAdministrator_requestsController {
  /**
   * Search and retrieve administrator promotion requests with filtering and pagination.
   *
   * This endpoint allows super administrators to view all administrator requests submitted by platform users. Requests can be filtered by status (pending, approved, rejected) and actor type (customer or seller). Results are returned in paginated format optimized for administrative list displays.
   *
   * Only super administrators have access to this endpoint. The request includes the user's justification reason, submission timestamp, and current status. Rejected requests include the rejection reason provided by the processing super administrator.
   *
   * @param connection
   * @param body Search criteria for administrator requests including status filter, actor type filter, and pagination parameters.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Query shopping_mall_administrator_requests table with filtering and pagination.
   *
   * Filtering:
   * - status: Filter by 'pending', 'approved', or 'rejected' (optional)
   * - actor_type: Filter by 'customer' or 'seller' (optional)
   * - Default behavior: Return all requests if no filters specified
   *
   * Pagination:
   * - page: Page number (1-indexed, default: 1)
   * - pageSize: Items per page (default: 20, max: 100)
   * - Return cursor-based pagination metadata (total, hasNext, hasPrev)
   *
   * Sorting:
   * - Default: Order by created_at DESC (newest first)
   *
   * Joins:
   * - Left join with shopping_mall_administrators on processed_by_administrator_id to include processor info
   * - Do not join with subtype tables (shopping_mall_administrator_request_of_customers, shopping_mall_administrator_request_of_sellers) in list view
   *
   * Validation:
   * - Verify current user has super administrator privileges
   * - Reject requests with invalid status values
   * - Reject requests with page < 1 or pageSize < 1
   *
   * Response:
   * - Return paginated summary with id, actor_type, reason, status, rejection_reason, processed_by_administrator_id, created_at, updated_at
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedBody()
    body: IShoppingMallAdministratorRequest.IRequest,
  ): Promise<IPageIShoppingMallAdministratorRequest.ISummary> {
    try {
      return await patchShoppingMallAdministratorAdministratorRequests({
        administrator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single administrator promotion request by its unique identifier.
   *
   * This operation returns complete details of an administrator request including the requestor's reason, current status, processing administrator (if any), and rejection reason (if rejected). The request status can be 'pending' (awaiting super administrator review), 'approved' (requestor became regular administrator), or 'rejected' (request denied with explanation).
   *
   * Authorization: Super administrators can view any administrator request. Regular administrators cannot view these requests. The original requestor (customer or seller) can view their own request to check its status.
   *
   * @param connection
   * @param administratorRequestId Unique identifier of the administrator promotion request to retrieve.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Query the shopping_mall_administrator_requests table by id (UUID).
   *
   * Authorization checks:
   * - Super administrators: Allow access to any request
   * - Regular administrators: Deny access (403 Forbidden)
   * - Requestor (customer/seller): Allow access only to their own request (check actor_type and join with shopping_mall_administrator_request_of_customers or shopping_mall_administrator_request_of_sellers)
   * - Other users: Deny access (403 Forbidden)
   *
   * Return the full request object including:
   * - id, actor_type, reason, status, rejection_reason
   * - processed_by_administrator_id (nullable, null if pending)
   * - created_at, updated_at
   *
   * Handle edge cases:
   * - Request not found: Return 404 Not Found
   * - Insufficient authorization: Return 403 Forbidden
   * - Invalid UUID format: Return 400 Bad Request
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":administratorRequestId")
  public async at(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("administratorRequestId")
    administratorRequestId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallAdministratorRequest> {
    try {
      return await getShoppingMallAdministratorAdministratorRequestsAdministratorRequestId(
        {
          administrator,
          administratorRequestId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an administrator promotion request's status and rejection reason.
   *
   * This endpoint allows super administrators to approve or reject pending administrator promotion requests submitted by customers or sellers. When approving, the requestor becomes a regular administrator. When rejecting, a rejection reason must be provided to explain the decision.
   *
   * The operation updates the request status from 'pending' to either 'approved' or 'rejected', records which super administrator processed the request, and optionally includes a rejection reason if the request is denied.
   *
   * Only super administrators can perform this operation. Regular administrators and other users do not have permission to update administrator requests.
   *
   * @param connection
   * @param administratorRequestId Unique identifier of the administrator promotion request to update.
   * @param body Update payload containing the new status and optional rejection reason for the administrator request.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification 1. Validate that the authenticated user is a super administrator.
   * 2. Retrieve the administrator request by administratorRequestId from shopping_mall_administrator_requests table.
   * 3. Verify the request exists and has status 'pending' (only pending requests can be updated).
   * 4. Validate the request body: status must be 'approved' or 'rejected'.
   * 5. If status is 'rejected', ensure rejection_reason is provided and not empty.
   * 6. If status is 'approved', set rejection_reason to null.
   * 7. Update the request record with:
   *    - status: new status value
   *    - rejection_reason: provided reason or null
   *    - processed_by_administrator_id: ID of the authenticated super administrator
   *    - updated_at: current timestamp
   * 8. If status is 'approved', create a new administrator account for the requestor:
   *    - Join with shopping_mall_administrator_request_of_customers or shopping_mall_administrator_request_of_sellers based on actor_type
   *    - Retrieve the customer_id or seller_id
   *    - Create a new record in shopping_mall_administrators with the appropriate user reference
   *    - Set initial grade to 'regular' (not super)
   * 9. Return the updated administrator request with full details including the linked user information.
   * 10. Handle errors: request not found, request already processed, invalid status value, missing rejection reason for rejected status, insufficient privileges.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":administratorRequestId")
  public async update(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("administratorRequestId")
    administratorRequestId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallAdministratorRequest.IUpdate,
  ): Promise<IShoppingMallAdministratorRequest> {
    try {
      return await putShoppingMallAdministratorAdministratorRequestsAdministratorRequestId(
        {
          administrator,
          administratorRequestId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
