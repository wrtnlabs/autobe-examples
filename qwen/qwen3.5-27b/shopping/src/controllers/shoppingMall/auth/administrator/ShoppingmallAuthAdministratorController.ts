import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallAdministrator } from "../../../../api/structures/IShoppingMallAdministrator";
import { postShoppingMallAuthAdministratorJoin } from "../../../../providers/postShoppingMallAuthAdministratorJoin";
import { postShoppingMallAuthAdministratorLogin } from "../../../../providers/postShoppingMallAuthAdministratorLogin";
import { postShoppingMallAuthAdministratorRefresh } from "../../../../providers/postShoppingMallAuthAdministratorRefresh";

@Controller("/shoppingMall/auth/administrator")
export class ShoppingmallAuthAdministratorController {
  /**
   * Register a new administrator account with email and password credentials.
   *
   * This operation creates a new administrator account in the shopping_mall_administrators table. The email must be unique across all administrators and serves as the login credential. The password is hashed using bcrypt for secure storage. New administrators are created with 'regular' grade and 'banned=false' status by default.
   *
   * Upon successful registration, the system generates JWT access and refresh tokens stored in shopping_mall_administrator_sessions. The access token expires in 15 minutes for short-lived authentication, while the refresh token expires in 7 days for token renewal.
   *
   * The operation captures the client's IP address, current page URL (href), and referrer URL for security auditing and session tracking purposes.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Registration credentials for new administrator account
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification 1. Validate request body: email must be valid format, password must meet complexity requirements (min 8 chars, uppercase, lowercase, number).
   * 2. Check if email already exists in shopping_mall_administrators table (unique constraint).
   * 3. Hash password using bcrypt with salt rounds >= 10.
   * 4. Insert new record into shopping_mall_administrators with: email, password_hash, grade='regular', banned=false, created_at=now(), updated_at=now(), deleted_at=null.
   * 5. Generate access token (expires in 15 minutes) and refresh token (expires in 7 days).
   * 6. Insert session record into shopping_mall_administrator_sessions with administrator_id, ip, href, referrer, created_at, expired_at.
   * 7. Return tokens in IShoppingMallAdministrator.IAuthorized response.
   * 8. Handle errors: 400 for validation failures, 409 for duplicate email, 500 for server errors.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallAdministrator.IJoin,
  ): Promise<IShoppingMallAdministrator.IAuthorized> {
    try {
      return await postShoppingMallAuthAdministratorJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate an administrator with email and password credentials.
   *
   * This operation validates administrator credentials against the shopping_mall_administrators table. The email must match an existing administrator account that is not soft-deleted (deleted_at=null). The password is verified by comparing the bcrypt hash of the input password with the stored password_hash.
   *
   * Before issuing tokens, the operation checks if the administrator account is banned. Banned administrators (banned=true) cannot authenticate and receive a 403 Forbidden response. This allows super administrators to revoke access while preserving account data for audit purposes.
   *
   * Upon successful authentication, new JWT tokens are generated and a session record is created in shopping_mall_administrator_sessions with the client's IP address, current page URL, and referrer for security monitoring.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Authentication credentials for administrator login
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification 1. Validate request body: email and password must be provided and non-empty.
   * 2. Query shopping_mall_administrators for record with matching email and deleted_at=null.
   * 3. If not found, return 401 Unauthorized.
   * 4. Check if administrator is banned (banned=true). If banned, return 403 Forbidden.
   * 5. Verify password by hashing input password and comparing with stored password_hash using bcrypt.compare().
   * 6. If password mismatch, return 401 Unauthorized.
   * 7. Generate new access token (expires in 15 minutes) and refresh token (expires in 7 days).
   * 8. Insert new session record into shopping_mall_administrator_sessions with administrator_id, ip, href, referrer, created_at=now(), expired_at=now() + 7 days.
   * 9. Return tokens in IShoppingMallAdministrator.IAuthorized response.
   * 10. Handle errors: 401 for invalid credentials, 403 for banned accounts, 500 for server errors.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallAdministrator.ILogin,
  ): Promise<IShoppingMallAdministrator.IAuthorized> {
    try {
      return await postShoppingMallAuthAdministratorLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh authentication tokens for an existing administrator session.
   *
   * This operation extends the administrator's authentication session by issuing new access and refresh tokens. The provided refresh token is validated against the shopping_mall_administrator_sessions table to ensure it exists, has not expired, and belongs to an active administrator account.
   *
   * The operation also verifies that the administrator is not banned before issuing new tokens. This ensures that banned administrators cannot continue accessing the system even with valid refresh tokens.
   *
   * Upon successful validation, new JWT tokens are generated: an access token with 15-minute expiration for API authentication, and a refresh token with 7-day expiration for future token renewal. The session record is updated with the new expiration time.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token for token renewal
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification 1. Validate request body: refresh_token must be provided and non-empty.
   * 2. Query shopping_mall_administrator_sessions for valid session with matching refresh token.
   * 3. Check if session exists, is not expired (expired_at > now()), and belongs to an active administrator (deleted_at=null).
   * 4. If invalid, return 401 Unauthorized.
   * 5. Verify the associated administrator is not banned (banned=false). If banned, return 403 Forbidden.
   * 6. Generate new access token (expires in 15 minutes) and new refresh token (expires in 7 days from now).
   * 7. Update the session record's expired_at to new refresh token expiration time.
   * 8. Return new tokens in IShoppingMallAdministrator.IAuthorized response.
   * 9. Handle errors: 401 for invalid/expired tokens, 403 for banned accounts, 500 for server errors.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IShoppingMallAdministrator.IRefresh,
  ): Promise<IShoppingMallAdministrator.IAuthorized> {
    try {
      return await postShoppingMallAuthAdministratorRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
