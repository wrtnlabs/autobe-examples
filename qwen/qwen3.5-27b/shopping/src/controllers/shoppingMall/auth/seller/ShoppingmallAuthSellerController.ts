import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallSeller } from "../../../../api/structures/IShoppingMallSeller";
import { postShoppingMallAuthSellerJoin } from "../../../../providers/postShoppingMallAuthSellerJoin";
import { postShoppingMallAuthSellerLogin } from "../../../../providers/postShoppingMallAuthSellerLogin";
import { postShoppingMallAuthSellerRefresh } from "../../../../providers/postShoppingMallAuthSellerRefresh";

@Controller("/shoppingMall/auth/seller")
export class ShoppingmallAuthSellerController {
  /**
   * Register a new seller account on the shopping mall platform. This endpoint allows users to create a seller account with email and password credentials, along with initial shop information including shop name and optional description.
   *
   * The seller account is created with an initial approval_status of 'pending', meaning the seller cannot list products or receive orders until an administrator reviews and approves their registration. The status field is set to 'active' by default, indicating the account is not banned.
   *
   * Upon successful registration, the system creates a record in the shopping_mall_sellers table with the provided email, hashed password, and shop details. The email must be unique across all seller accounts. The password is securely hashed using BCrypt before storage.
   *
   * After registration, sellers must wait for administrator approval before they can access seller-specific features like product creation, order management, and inventory control. Sellers can check their approval status using the dedicated status endpoint and resubmit their registration if rejected.
   *
   * Related operations include POST /auth/seller/login for authentication after approval, and password reset endpoints for account recovery if credentials are lost.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Seller registration information including email, password, and shop details
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification 1. Validate request body: email must be valid format and unique, password must meet complexity requirements (min 8 chars, uppercase, lowercase, number), shop_name required (min 2 chars), shop_description optional
   * 2. Check if email already exists in shopping_mall_sellers table - return conflict error if found
   * 3. Hash password using BCrypt with salt rounds
   * 4. Create new seller record in shopping_mall_sellers with: email, password_hash, shop_name, shop_description, approval_status='pending', status='active', created_at, updated_at
   * 5. Generate JWT access token (1 hour expiry) and refresh token (7 days expiry)
   * 6. Create session record in shopping_mall_seller_sessions with tokens and connection metadata (ip, href, referrer from request)
   * 7. Return authorization response with access_token and refresh_token
   * 8. Send approval notification email to seller (async)
   * 9. Handle transaction rollback on any error
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallSeller.IJoin,
  ): Promise<IShoppingMallSeller.IAuthorized> {
    try {
      return await postShoppingMallAuthSellerJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate a seller account using email and password credentials. This endpoint validates the seller's credentials against the shopping_mall_sellers table and generates JWT tokens for API access.
   *
   * The login process verifies that the email exists in the system, the password hash matches the provided password, the account status is 'active' (not banned), and the account has not been soft-deleted. Additionally, the seller's approval_status must be 'approved' to allow login - sellers with 'pending', 'rejected', or 'suspended' status cannot authenticate.
   *
   * Upon successful authentication, the system generates a new JWT access token (valid for 1 hour) and refresh token (valid for 7 days). Any existing active session for this seller is automatically revoked to enforce the single-session policy, preventing concurrent access from multiple devices.
   *
   * Connection metadata including IP address, current URL (href), and referrer URL are logged for security auditing and fraud detection. This information helps identify suspicious login patterns and provides an audit trail for account access.
   *
   * Related operations include POST /auth/seller/refresh for token renewal, password reset endpoints for account recovery, and seller profile management endpoints that require valid authentication.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Seller login credentials including email and password
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification 1. Validate request body: email and password required
   * 2. Query shopping_mall_sellers for email match with deleted_at IS NULL
   * 3. Verify password using BCrypt.compare(password, password_hash)
   * 4. Check status = 'active' (not banned) - return unauthorized if banned
   * 5. Check approval_status = 'approved' - return forbidden if pending/rejected/suspended
   * 6. Revoke any existing active session: set revoked_at = NOW() in shopping_mall_seller_sessions where shopping_mall_seller_id = seller_id AND revoked_at IS NULL
   * 7. Generate new JWT access token (1 hour expiry) and refresh token (7 days expiry)
   * 8. Create new session record in shopping_mall_seller_sessions with: seller_id, access_token, refresh_token, ip, href, referrer, created_at, expired_at
   * 9. Return authorization response with access_token and refresh_token
   * 10. Log login event for audit trail
   * 11. Handle transaction rollback on any error
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallSeller.ILogin,
  ): Promise<IShoppingMallSeller.IAuthorized> {
    try {
      return await postShoppingMallAuthSellerLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh the authentication tokens for an authenticated seller session. This endpoint allows sellers to obtain new access and refresh tokens using a valid refresh token, extending their session without requiring re-authentication with email and password.
   *
   * The refresh token validation process checks that the token exists in the shopping_mall_seller_sessions table, has not expired (expired_at is in the future), has not been revoked (revoked_at is NULL), and belongs to an active seller account (status = 'active', deleted_at IS NULL, approval_status = 'approved').
   *
   * Upon successful validation, the system generates new JWT access and refresh tokens. The old refresh token is invalidated by setting revoked_at timestamp, and a new session record is created with the fresh tokens. This token rotation strategy enhances security by limiting the window of opportunity for token misuse.
   *
   * The refresh operation maintains the same session metadata (ip, href, referrer) from the original login for consistency in security auditing. If the seller's account status has changed (e.g., banned or suspended) since the refresh token was issued, the refresh will fail and the seller must resolve the account issue before re-authenticating.
   *
   * Related operations include POST /auth/seller/login for initial authentication and password reset endpoints for account recovery scenarios.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token for obtaining new authentication tokens
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification 1. Validate request body: refresh_token required
   * 2. Query shopping_mall_seller_sessions for refresh_token match with revoked_at IS NULL AND expired_at > NOW()
   * 3. Verify associated seller exists in shopping_mall_sellers with deleted_at IS NULL
   * 4. Check seller status = 'active' (not banned)
   * 5. Check seller approval_status = 'approved' (not pending/rejected/suspended)
   * 6. Revoke old refresh token: UPDATE shopping_mall_seller_sessions SET revoked_at = NOW() WHERE id = session_id
   * 7. Generate new JWT access token (1 hour expiry) and refresh token (7 days expiry)
   * 8. Create new session record in shopping_mall_seller_sessions with: seller_id, new access_token, new refresh_token, ip, href, referrer (from old session), created_at, expired_at
   * 9. Return authorization response with new access_token and refresh_token
   * 10. Log token refresh event for audit trail
   * 11. Handle transaction rollback on any error
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IShoppingMallSeller.IRefresh,
  ): Promise<IShoppingMallSeller.IAuthorized> {
    try {
      return await postShoppingMallAuthSellerRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
