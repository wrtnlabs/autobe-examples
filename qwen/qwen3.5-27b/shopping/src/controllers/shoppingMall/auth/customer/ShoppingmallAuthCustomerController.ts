import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallCustomer } from "../../../../api/structures/IShoppingMallCustomer";
import { postShoppingMallAuthCustomerJoin } from "../../../../providers/postShoppingMallAuthCustomerJoin";
import { postShoppingMallAuthCustomerLogin } from "../../../../providers/postShoppingMallAuthCustomerLogin";
import { postShoppingMallAuthCustomerRefresh } from "../../../../providers/postShoppingMallAuthCustomerRefresh";

@Controller("/shoppingMall/auth/customer")
export class ShoppingmallAuthCustomerController {
  /**
   * Register a new customer account with email and password credentials.
   *
   * This operation creates a new customer account in the shopping mall platform. The customer will be able to browse products, manage their shopping cart, place orders, write reviews, and manage their profile, addresses, and wishlist after successful registration.
   *
   * The email address serves as the unique identifier and login credential. The password is hashed using bcrypt for security. Upon successful registration, the customer receives JWT access and refresh tokens for authenticated API access.
   *
   * New customers start with 'active' status and can immediately use all customer features. No approval process is required for customer accounts.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Customer registration credentials including email address and password.
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Implement customer registration by:
   * 1. Validate email format and check for existing customer with same email in shopping_mall_customers table
   * 2. Hash password using bcrypt with salt rounds >= 10
   * 3. Insert new record into shopping_mall_customers with email, password_hash, and default status 'active'
   * 4. Create associated customer_profile record in shopping_mall_customer_profiles
   * 5. Generate JWT access token (expires in 15 minutes) and refresh token (expires in 7 days)
   * 6. Insert session record into shopping_mall_customer_sessions with both tokens and customer_id
   * 7. Return tokens in IAuthorized response
   *
   * Error handling:
   * - Return 400 if email format invalid
   * - Return 409 if email already exists
   * - Return 500 for database errors
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallCustomer.IJoin,
  ): Promise<IShoppingMallCustomer.IAuthorized> {
    try {
      return await postShoppingMallAuthCustomerJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate a customer with email and password credentials.
   *
   * This operation validates customer credentials and establishes an authenticated session. The customer provides their registered email address and password, which are verified against the shopping_mall_customers table.
   *
   * Upon successful authentication, the customer receives JWT access and refresh tokens. The access token is used for authenticated API requests and expires after 15 minutes. The refresh token is used to obtain new access tokens without requiring re-login and expires after 7 days.
   *
   * Failed login attempts do not lock the account but should be monitored for suspicious activity. Customers with banned or inactive status cannot log in.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Customer login credentials including email address and password.
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Implement customer login by:
   * 1. Find customer record in shopping_mall_customers table by email
   * 2. Verify customer status is 'active' (not banned or deleted)
   * 3. Compare provided password hash with stored password_hash using bcrypt
   * 4. If valid, generate new JWT access token (expires in 15 minutes) and refresh token (expires in 7 days)
   * 5. Insert new session record into shopping_mall_customer_sessions with both tokens and customer_id
   * 6. Return tokens in IAuthorized response
   *
   * Error handling:
   * - Return 401 if customer not found or password incorrect
   * - Return 403 if customer account is banned or inactive
   * - Return 500 for database errors
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallCustomer.ILogin,
  ): Promise<IShoppingMallCustomer.IAuthorized> {
    try {
      return await postShoppingMallAuthCustomerLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh customer authentication tokens without requiring re-login.
   *
   * This operation extends the customer's authenticated session by exchanging a valid refresh token for new access and refresh tokens. This allows customers to maintain continuous access to the platform without repeatedly entering their credentials.
   *
   * The refresh token must be valid and not expired. The associated customer account must have 'active' status. Upon successful refresh, both the access token (15-minute expiry) and refresh token (7-day expiry) are renewed.
   *
   * This operation enables seamless user experience for active shoppers browsing products, managing cart, and completing orders without interruption.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token for extending customer authentication session.
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Implement customer token refresh by:
   * 1. Validate the provided refresh token signature and expiration
   * 2. Find the corresponding session record in shopping_mall_customer_sessions table
   * 3. Verify the associated customer record exists and has 'active' status
   * 4. Generate new JWT access token (expires in 15 minutes) and new refresh token (expires in 7 days)
   * 5. Update the shopping_mall_customer_sessions record with new tokens
   * 6. Return new tokens in IAuthorized response
   *
   * Error handling:
   * - Return 401 if refresh token is invalid, expired, or not found
   * - Return 403 if customer account is banned or inactive
   * - Return 500 for database errors
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IShoppingMallCustomer.IRefresh,
  ): Promise<IShoppingMallCustomer.IAuthorized> {
    try {
      return await postShoppingMallAuthCustomerRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
