import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallGuest } from "../../../../api/structures/IShoppingMallGuest";
import { postShoppingMallAuthGuestJoin } from "../../../../providers/postShoppingMallAuthGuestJoin";
import { postShoppingMallAuthGuestRefresh } from "../../../../providers/postShoppingMallAuthGuestRefresh";

@Controller("/shoppingMall/auth/guest")
export class ShoppingmallAuthGuestController {
  /**
   * Creates a temporary guest session for unauthenticated users to access public platform features.
   *
   * This operation registers a new guest account identified by device fingerprint and generates JWT tokens for temporary access. Guests can browse public content, view products, and access registration pages without providing email or password credentials.
   *
   * The guest session is stored in the shopping_mall_guest_sessions table with associated access and refresh tokens. The guest identity is recorded in the shopping_mall_guests table with device fingerprint tracking.
   *
   * Guests have limited permissions compared to authenticated customers or sellers. They cannot place orders, write reviews, or access protected resources. To perform these actions, guests must register as a customer account.
   *
   * The operation returns IShoppingMallGuest.IAuthorized containing both access and refresh tokens. The access token is short-lived for API authentication, while the refresh token allows extending the session without re-joining.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Guest registration request with device fingerprint for temporary session creation.
     * @x-autobe-authorization-type join
     * @x-autobe-authorization-actor guest
     * @x-autobe-specification 1. Generate a unique device fingerprint from
     *   request headers (User-Agent, IP address, or client-provided
     *   fingerprint). 2. Check if a guest account with this device fingerprint
     *   already exists in shopping_mall_guests table. 3. If exists, update the
     *   last_activity timestamp; if not, create a new guest record with the
     *   device fingerprint. 4. Generate a new access token (JWT) with short
     *   expiration (e.g., 15 minutes) and a refresh token (JWT) with longer
     *   expiration (e.g., 24 hours). 5. Create a new session record in
     *   shopping_mall_guest_sessions table with both tokens, guest ID, and
     *   expiration timestamps. 6. Invalidate any existing sessions for this
     *   guest device. 7. Return the tokens in IShoppingMallGuest.IAuthorized
     *   format. 8. Handle edge cases: rate limiting for repeated join attempts,
     *   device fingerprint collision handling, and session cleanup for expired
     *   tokens.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallGuest.IJoin,
  ): Promise<IShoppingMallGuest.IAuthorized> {
    try {
      return await postShoppingMallAuthGuestJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Extends an existing guest session by validating the refresh token and issuing new access and refresh tokens.
   *
   * This operation allows guests to maintain their temporary session without re-joining. The refresh token is validated against the shopping_mall_guest_sessions table to ensure it's valid, not expired, and associated with an active guest account.
   *
   * Upon successful validation, the operation generates a new access token with fresh expiration and optionally rotates the refresh token for security. The guest's session record is updated with the new tokens and timestamps.
   *
   * This operation is essential for maintaining continuous guest browsing sessions without requiring re-authentication. It supports the guest workflow of exploring the platform before deciding to register as a customer.
   *
   * The operation returns IShoppingMallGuest.IAuthorized containing the new access and refresh tokens. If the refresh token is invalid or expired, the guest must call join again to create a new session.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Guest session refresh request containing the refresh token to extend session validity.
     * @x-autobe-authorization-type refresh
     * @x-autobe-authorization-actor guest
     * @x-autobe-specification 1. Extract and validate the refresh token from
     *   the request body. 2. Look up the session record in
     *   shopping_mall_guest_sessions table using the refresh token. 3. Verify
     *   the session exists, is not expired, and is associated with an active
     *   guest in shopping_mall_guests. 4. If validation fails, return 401
     *   Unauthorized error. 5. Generate a new access token (JWT) with short
     *   expiration and a new refresh token (JWT) with extended expiration. 6.
     *   Update the session record in shopping_mall_guest_sessions with the new
     *   tokens and current timestamp. 7. Optionally implement refresh token
     *   rotation for enhanced security. 8. Return the new tokens in
     *   IShoppingMallGuest.IAuthorized format. 9. Handle edge cases: concurrent
     *   refresh attempts, token rotation policies, and session cleanup on
     *   guest-to-customer conversion.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IShoppingMallGuest.IRefresh,
  ): Promise<IShoppingMallGuest.IAuthorized> {
    try {
      return await postShoppingMallAuthGuestRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
