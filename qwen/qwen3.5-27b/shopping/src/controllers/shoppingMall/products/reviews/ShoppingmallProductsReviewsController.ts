import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallReview } from "../../../../api/structures/IPageIShoppingMallReview";
import { IShoppingMallReview } from "../../../../api/structures/IShoppingMallReview";
import { patchShoppingMallProductsProductIdReviews } from "../../../../providers/patchShoppingMallProductsProductIdReviews";

@Controller("/shoppingMall/products/:productId/reviews")
export class ShoppingmallProductsReviewsController {
  /**
   * Retrieves all non-deleted reviews for a specific product, sorted by newest first.
   *
   * This endpoint returns customer reviews associated with a product, displaying the most recent reviews at the top. Each review includes the customer's rating (1-5 stars), optional text content, and timestamp information. Reviews are essential for helping potential customers make informed purchasing decisions based on other customers' experiences.
   *
   * Deleted reviews are automatically filtered out and not included in the response or average rating calculations. The response includes pagination metadata for efficient data loading when dealing with products that have many reviews.
   *
   * Reviews are sorted by created_at in descending order, showing the newest reviews first as per platform display requirements.
   *
   * @param connection
   * @param productId Unique identifier of the product whose reviews are being retrieved.
   * @param body Search criteria including pagination parameters for retrieving product reviews.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor null
     * @x-autobe-specification Query the shopping_mall_reviews table for all
     *   reviews where: 1. shopping_mall_product_id matches the provided
     *   productId parameter 2. deleted_at is null (exclude soft-deleted reviews
     *   per business rules) 3. Sort by created_at in descending order (newest
     *   first) 4. Apply server-side pagination using cursor or offset-based
     *   pagination from request body 5. Return paginated results with metadata
     *   (total count, page info)
   *
   * Do not include reviews where deleted_at is set. Ensure only non-deleted reviews are returned for display on product detail pages.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallReview.IRequest,
  ): Promise<IPageIShoppingMallReview.ISummary> {
    try {
      return await patchShoppingMallProductsProductIdReviews({
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
