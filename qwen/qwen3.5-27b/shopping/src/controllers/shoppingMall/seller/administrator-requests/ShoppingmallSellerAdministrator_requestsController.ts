import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallAdministratorRequest } from "../../../../api/structures/IPageIShoppingMallAdministratorRequest";
import { IShoppingMallAdministratorRequest } from "../../../../api/structures/IShoppingMallAdministratorRequest";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { getShoppingMallSellerAdministratorRequestsAdministratorRequestId } from "../../../../providers/getShoppingMallSellerAdministratorRequestsAdministratorRequestId";
import { patchShoppingMallSellerAdministratorRequests } from "../../../../providers/patchShoppingMallSellerAdministratorRequests";
import { postShoppingMallSellerAdministratorRequests } from "../../../../providers/postShoppingMallSellerAdministratorRequests";

@Controller("/shoppingMall/seller/administrator-requests")
export class ShoppingmallSellerAdministrator_requestsController {
  /**
   * Submit a request to become an administrator on the shopping mall platform.
   *
   * Any registered user (customer or seller) can request administrator privileges by providing a justification reason. The request is reviewed by super administrators who can approve or reject it. Approved requestors become regular administrators with platform oversight capabilities.
   *
   * The request includes a reason text explaining why the user should be granted administrator privileges. Rejected requests do not prevent the user from submitting new requests in the future. All requests are preserved for audit purposes.
   *
   * @param connection
   * @param body Administrator promotion request with justification reason.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Create administrator promotion request for authenticated user.
   *
   * 1. Validate user is authenticated as customer or seller (not administrator or guest).
   * 2. Validate reason text is provided and not empty.
   * 3. Determine actor_type based on authenticated user role ('customer' or 'seller').
   * 4. Create shopping_mall_administrator_requests record with:
   *    - actor_type: determined from user role
   *    - reason: from request body
   *    - status: 'pending'
   *    - processed_by_administrator_id: null
   *    - rejection_reason: null
   *    - created_at: current timestamp
   *    - updated_at: current timestamp
   * 5. Create corresponding subtype record:
   *    - If actor_type is 'customer': create shopping_mall_administrator_request_of_customers linking the request to customer_id
   *    - If actor_type is 'seller': create shopping_mall_administrator_request_of_sellers linking the request to shopping_mall_seller_id
   * 6. Return the created administrator request with id, actor_type, reason, status, and timestamps.
   * 7. Handle errors: missing reason, unauthorized access, database errors.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IShoppingMallAdministratorRequest.ICreate,
  ): Promise<IShoppingMallAdministratorRequest> {
    try {
      return await postShoppingMallSellerAdministratorRequests({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve administrator promotion requests with filtering and pagination.
   *
   * This endpoint allows super administrators to view all administrator requests submitted by platform users. Requests can be filtered by status (pending, approved, rejected) and actor type (customer or seller). Results are returned in paginated format optimized for administrative list displays.
   *
   * Only super administrators have access to this endpoint. The request includes the user's justification reason, submission timestamp, and current status. Rejected requests include the rejection reason provided by the processing super administrator.
   *
   * @param connection
   * @param body Search criteria for administrator requests including status filter, actor type filter, and pagination parameters.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query shopping_mall_administrator_requests table with filtering and pagination.
   *
   * Filtering:
   * - status: Filter by 'pending', 'approved', or 'rejected' (optional)
   * - actor_type: Filter by 'customer' or 'seller' (optional)
   * - Default behavior: Return all requests if no filters specified
   *
   * Pagination:
   * - page: Page number (1-indexed, default: 1)
   * - pageSize: Items per page (default: 20, max: 100)
   * - Return cursor-based pagination metadata (total, hasNext, hasPrev)
   *
   * Sorting:
   * - Default: Order by created_at DESC (newest first)
   *
   * Joins:
   * - Left join with shopping_mall_administrators on processed_by_administrator_id to include processor info
   * - Do not join with subtype tables (shopping_mall_administrator_request_of_customers, shopping_mall_administrator_request_of_sellers) in list view
   *
   * Validation:
   * - Verify current user has super administrator privileges
   * - Reject requests with invalid status values
   * - Reject requests with page < 1 or pageSize < 1
   *
   * Response:
   * - Return paginated summary with id, actor_type, reason, status, rejection_reason, processed_by_administrator_id, created_at, updated_at
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IShoppingMallAdministratorRequest.IRequest,
  ): Promise<IPageIShoppingMallAdministratorRequest.ISummary> {
    try {
      return await patchShoppingMallSellerAdministratorRequests({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single administrator promotion request by its unique identifier.
   *
   * This operation returns complete details of an administrator request including the requestor's reason, current status, processing administrator (if any), and rejection reason (if rejected). The request status can be 'pending' (awaiting super administrator review), 'approved' (requestor became regular administrator), or 'rejected' (request denied with explanation).
   *
   * Authorization: Super administrators can view any administrator request. Regular administrators cannot view these requests. The original requestor (customer or seller) can view their own request to check its status.
   *
   * @param connection
   * @param administratorRequestId Unique identifier of the administrator promotion request to retrieve.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query the shopping_mall_administrator_requests table by id (UUID).
   *
   * Authorization checks:
   * - Super administrators: Allow access to any request
   * - Regular administrators: Deny access (403 Forbidden)
   * - Requestor (customer/seller): Allow access only to their own request (check actor_type and join with shopping_mall_administrator_request_of_customers or shopping_mall_administrator_request_of_sellers)
   * - Other users: Deny access (403 Forbidden)
   *
   * Return the full request object including:
   * - id, actor_type, reason, status, rejection_reason
   * - processed_by_administrator_id (nullable, null if pending)
   * - created_at, updated_at
   *
   * Handle edge cases:
   * - Request not found: Return 404 Not Found
   * - Insufficient authorization: Return 403 Forbidden
   * - Invalid UUID format: Return 400 Bad Request
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":administratorRequestId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("administratorRequestId")
    administratorRequestId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallAdministratorRequest> {
    try {
      return await getShoppingMallSellerAdministratorRequestsAdministratorRequestId(
        {
          seller,
          administratorRequestId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
