import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IPageIShoppingMallReview } from "../../../../../api/structures/IPageIShoppingMallReview";
import { IShoppingMallReview } from "../../../../../api/structures/IShoppingMallReview";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { patchShoppingMallSellerReviewsMyProducts } from "../../../../../providers/patchShoppingMallSellerReviewsMyProducts";

@Controller("/shoppingMall/seller/reviews/my-products")
export class ShoppingmallSellerReviewsMy_productsController {
  /**
   * Retrieve a filtered and paginated list of customer reviews for products sold by the authenticated seller.
   *
   * This operation allows sellers to monitor customer feedback on their products. Reviews are filtered to show only those written for order items where the seller is responsible for fulfillment. The response includes review ratings, content, timestamps, and associated product information from the order item snapshots.
   *
   * Reviews are excluded if they have been soft-deleted by the customer or if the associated order item has a status of cancelled or refunded. This ensures sellers only see valid, active reviews for delivered products.
   *
   * The operation supports advanced filtering including rating range, text content search, date range filtering, and product name search. Results are paginated with configurable page sizes and sorted by creation date in descending order by default (newest reviews first).
   *
   * Related operations include GET /products/:id/reviews for viewing all reviews on a specific product, and POST /products/:id/reviews for customers to create new reviews.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering reviews
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query shopping_mall_reviews table with pagination and filtering for the authenticated seller's products.
   *
   * 1. Extract seller_id from authenticated user session
   * 2. Join shopping_mall_reviews with shopping_mall_order_items on shopping_order_item_id
   * 3. Filter by seller_id from order_items where status is not cancelled or refunded
   * 4. Apply search filters from request body: rating range, content text search, date range, product name search
   * 5. Apply pagination: page, limit, sort (default: created_at DESC)
   * 6. Exclude deleted reviews (deleted_at IS NULL)
   * 7. Join with product snapshots from order_items to include product name in response
   * 8. Return paginated review summaries with product context and order item status
   *
   * Business rules:
   * - Only return reviews for products where the seller is the seller_id in order_items
   * - Exclude reviews for cancelled or refunded order items
   * - Exclude soft-deleted reviews
   * - Sort by created_at descending by default (newest first)
   * - Support filtering by rating (1-5), content text, date range
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IShoppingMallReview.IRequest,
  ): Promise<IPageIShoppingMallReview.ISummary> {
    try {
      return await patchShoppingMallSellerReviewsMyProducts({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
