import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallVariantSnapshot } from "../../../../../../api/structures/IPageIShoppingMallVariantSnapshot";
import { IShoppingMallVariantSnapshot } from "../../../../../../api/structures/IShoppingMallVariantSnapshot";
import { SellerAuth } from "../../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../../decorators/payload/SellerPayload";
import { getShoppingMallSellerProductsProductIdVariantsVariantIdSnapshotsSnapshotId } from "../../../../../../providers/getShoppingMallSellerProductsProductIdVariantsVariantIdSnapshotsSnapshotId";
import { patchShoppingMallSellerProductsProductIdVariantsVariantIdSnapshots } from "../../../../../../providers/patchShoppingMallSellerProductsProductIdVariantsVariantIdSnapshots";

@Controller(
  "/shoppingMall/seller/products/:productId/variants/:variantId/snapshots",
)
export class ShoppingmallSellerProductsVariantsSnapshotsController {
  /**
   * Search and retrieve variant snapshots with filtering and pagination for a specific product variant.
   *
   * This operation returns immutable snapshots of a product variant's state at different modification points. Each snapshot captures the SKU code, price, and option values as they existed when the variant was modified. Snapshots provide an audit trail for dispute resolution and historical tracking.
   *
   * Sellers can view snapshots of their own variants. Administrators can view snapshots of any variant on the platform. Snapshots are preserved even after a variant is deleted.
   *
   * Access requires authentication. Sellers have access only to their own variants. Administrators have platform-wide access.
   *
   * @param connection
   * @param productId UUID of the product containing the variant (global scope)
   * @param variantId UUID of the product variant whose snapshots to retrieve (global scope)
   * @param body Search criteria including date range filters, price range filters, SKU code search, and pagination parameters (offset, limit, sortBy, sortOrder).
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Query shopping_mall_variant_snapshots table with
     *   filtering and pagination.
   *
   * Path parameters:
   * - productId: Used to identify the product context (for authorization and path structure)
   * - variantId: Foreign key to shopping_mall_product_variants.id, used to filter snapshots
   *
   * Authorization:
   * - For sellers: Verify the variant belongs to the seller's products (join shopping_mall_product_variants -> shopping_mall_products -> shopping_mall_seller_id)
   * - For administrators: Allow access to all variants
   *
   * Query logic:
   * 1. Validate variantId exists and belongs to productId (optional validation)
   * 2. Filter snapshots by shopping_mall_product_variant_id = variantId
   * 3. Apply search filters from request body (date range, price range, SKU code)
   * 4. Apply pagination (offset, limit) and sorting (created_at descending by default)
   * 5. Return paginated results with metadata
   *
   * Error handling:
   * - Return 404 if variant not found
   * - Return 403 if seller tries to access another seller's variant
   * - Return 400 for invalid filter parameters
   *
   * Response includes snapshot id, sku_code, price, created_at, and option values from joined shopping_mall_variant_snapshot_options table.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedParam("variantId")
    variantId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallVariantSnapshot.IRequest,
  ): Promise<IPageIShoppingMallVariantSnapshot.ISummary> {
    try {
      return await patchShoppingMallSellerProductsProductIdVariantsVariantIdSnapshots(
        {
          seller,
          productId,
          variantId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves a specific product variant snapshot by its unique identifier, showing the exact state of the variant at the time the snapshot was created.
   *
   * This endpoint provides immutable historical records of product variant modifications, including SKU code, price, and all option attributes (such as color, size, material). Variant snapshots are automatically created whenever a variant is modified and serve as audit trails for compliance and dispute resolution.
   *
   * Sellers can access snapshots of their own variants, while administrators can view snapshots of any variant on the platform. Snapshots remain accessible even after the variant or product is deleted, ensuring order history and audit trails are preserved.
   *
   * @param connection
   * @param productId Unique identifier of the product that owns the variant containing this snapshot.
   * @param variantId Unique identifier of the product variant for which this snapshot was created.
   * @param snapshotId Unique identifier of the variant snapshot to retrieve.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Query shopping_mall_variant_snapshots table by
     *   snapshotId (primary key).
   *
   * Validate that the snapshot belongs to the specified variantId (shopping_mall_product_variant_id matches variantId).
   *
   * Validate that the variant belongs to the specified productId (join with shopping_mall_product_variants to verify shopping_mall_product_id matches productId).
   *
   * Apply authorization: sellers can only access snapshots of their own variants; administrators can access all snapshots.
   *
   * Join with shopping_mall_variant_snapshot_options to retrieve all option key-value pairs for this snapshot.
   *
   * Return 404 if snapshot not found, variant not found, product not found, or authorization fails.
   *
   * Return snapshot data including id, sku_code, price, created_at, and nested variantSnapshotOptions array with key-value pairs.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":snapshotId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedParam("variantId")
    variantId: string & tags.Format<"uuid">,
    @TypedParam("snapshotId")
    snapshotId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallVariantSnapshot> {
    try {
      return await getShoppingMallSellerProductsProductIdVariantsVariantIdSnapshotsSnapshotId(
        {
          seller,
          productId,
          variantId,
          snapshotId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
