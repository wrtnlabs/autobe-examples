import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallProductInventoryStatus } from "../../../../../../api/structures/IShoppingMallProductInventoryStatus";
import { SellerAuth } from "../../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../../decorators/payload/SellerPayload";
import { patchShoppingMallSellerProductsInventoryStatus } from "../../../../../../providers/patchShoppingMallSellerProductsInventoryStatus";

@Controller("/shoppingMall/seller/products/inventory/status")
export class ShoppingmallSellerProductsInventoryStatusController {
  /**
   * Retrieve comprehensive inventory status and statistics for product variants across the shopping mall platform.
   *
   * This operation provides sellers and administrators with critical inventory health information, including current stock levels, out-of-stock alerts, and low-stock warnings. The endpoint aggregates data from the inventory_records table to calculate real-time stock quantities for each product variant.
   *
   * The response includes both summary statistics (total variants, out-of-stock count, low-stock count) and detailed variant-level information with current stock quantities. This enables proactive inventory management and helps prevent stockouts that could impact customer orders.
   *
   * Filters allow narrowing results by category, seller, or stock thresholds. The out_of_stock_only filter is particularly useful for quickly identifying variants that need immediate restocking attention.
   *
   * @param connection
   * @param body Filter and pagination criteria for inventory status query
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Aggregate inventory statistics across all product variants by calculating current stock quantities from inventory_records table.
   *
   * 1. Query inventory_records grouped by variant_id to calculate current stock (SUM of quantityChange)
   * 2. Join with product_variants to get product relationships and seller information
   * 3. Join with products to get category and product details
   * 4. Apply filters from request body: category_id, seller_id, min_stock, max_stock, out_of_stock_only
   * 5. Calculate aggregate statistics:
   *    - Total variants tracked
   *    - Variants with stock > 0
   *    - Variants with stock = 0 (out of stock)
   *    - Variants with stock < threshold (low stock)
   *    - Total stock quantity across all variants
   * 6. Return paginated results with variant-level details and summary statistics
   * 7. Support sorting by stock quantity, product name, or last updated timestamp
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async inventoryStatus(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IShoppingMallProductInventoryStatus.IRequest,
  ): Promise<IShoppingMallProductInventoryStatus> {
    try {
      return await patchShoppingMallSellerProductsInventoryStatus({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
