import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IShoppingMallInventoryRecord } from "../../../../../../api/structures/IShoppingMallInventoryRecord";
import { SellerAuth } from "../../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../../decorators/payload/SellerPayload";
import { getShoppingMallSellerProductsProductIdVariantsVariantIdInventoryRecordId } from "../../../../../../providers/getShoppingMallSellerProductsProductIdVariantsVariantIdInventoryRecordId";
import { postShoppingMallSellerProductsProductIdVariantsVariantIdInventory } from "../../../../../../providers/postShoppingMallSellerProductsProductIdVariantsVariantIdInventory";

@Controller(
  "/shoppingMall/seller/products/:productId/variants/:variantId/inventory",
)
export class ShoppingmallSellerProductsVariantsInventoryController {
  /**
   * Creates a new inventory record to add or subtract stock quantity from a product variant.
   *
   * This operation allows sellers to manage inventory levels by recording stock movements. Positive quantity values indicate stock increases (restocking, cancellations, refunds), while negative values indicate stock decreases (adjustments, losses). Each inventory record is immutable and serves as an audit trail for stock changes. The current stock quantity for a variant is calculated by summing all inventory records.
   *
   * Authorization: Only the seller who owns the product can create inventory records for its variants. The system validates seller ownership before processing the request.
   *
   * Validation: Quantity must be a non-zero integer. Negative quantities are allowed for adjustments but not for restocking operations (use positive quantity for restocking). Reason text is required and should describe the purpose of the inventory change.
   *
   * @param connection
   * @param productId UUID of the product that owns the variant
   * @param variantId UUID of the product variant whose inventory is being modified
   * @param body Inventory change details including quantity adjustment and reason for the change.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification 1. Validate authentication: Verify the requester is an authenticated seller.
   * 2. Validate ownership: Query shopping_mall_products to confirm the seller owns the product (shopping_mall_seller_id matches current seller).
   * 3. Validate variant existence: Query shopping_mall_product_variants to confirm the variant exists and belongs to the product (shopping_mall_product_id matches productId).
   * 4. Validate quantity: Ensure quantity_change is non-zero (reject zero values). Allow negative values for adjustments.
   * 5. Validate reason: Ensure reason text is provided and not empty.
   * 6. Create inventory record: Insert new record into shopping_mall_inventory_records with:
   *    - id: Generate UUID
   *    - shopping_mall_product_variant_id: variantId from path
   *    - quantity_change: Value from request body
   *    - reason: Text from request body
   *    - created_at: Current timestamp
   *    - updated_at: Current timestamp
   *    - deleted_at: null
   * 7. Return the created inventory record with all fields including generated id and timestamps.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedParam("variantId")
    variantId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallInventoryRecord.ICreate,
  ): Promise<IShoppingMallInventoryRecord> {
    try {
      return await postShoppingMallSellerProductsProductIdVariantsVariantIdInventory(
        {
          seller,
          productId,
          variantId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves a single inventory record detail for a specific product variant.
   *
   * This endpoint returns the complete inventory record including the quantity change amount, reason for the change, and timestamps. Inventory records are immutable audit trail entries that track all stock movements for product variants, including restocking, order placements, cancellations, refunds, and manual adjustments.
   *
   * The recordId uniquely identifies a specific inventory event. The productId and variantId parameters provide hierarchical context for navigation and verification that the record belongs to the specified variant.
   *
   * @param connection
   * @param productId UUID of the product containing the variant
   * @param variantId UUID of the product variant
   * @param recordId UUID of the inventory record to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query shopping_mall_inventory_records table by id (recordId).
   *
   * Verify the record exists and is not soft-deleted (deleted_at IS NULL).
   *
   * Join with shopping_mall_product_variants to verify the record belongs to the specified variantId.
   *
   * Join with shopping_mall_products to verify the variant belongs to the specified productId.
   *
   * Return the full inventory record with all fields: id, shopping_mall_product_variant_id, quantity_change, reason, created_at, updated_at.
   *
   * Handle edge cases:
   * - Record not found: return 404 Not Found
   * - Record soft-deleted: return 404 Not Found
   * - Variant mismatch: return 404 Not Found
   * - Product mismatch: return 404 Not Found
   *
   * Authorization: Only the seller who owns the product variant can access their inventory records. Administrators can access all inventory records.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":recordId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedParam("variantId")
    variantId: string & tags.Format<"uuid">,
    @TypedParam("recordId")
    recordId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallInventoryRecord> {
    try {
      return await getShoppingMallSellerProductsProductIdVariantsVariantIdInventoryRecordId(
        {
          seller,
          productId,
          variantId,
          recordId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
