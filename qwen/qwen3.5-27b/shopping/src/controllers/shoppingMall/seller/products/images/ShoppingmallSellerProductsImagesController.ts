  /**
   * Reorder images for a product to change their display sequence in the product gallery.
   *
   * This operation allows sellers to arrange their product images in a custom order. The image with the lowest display_order value appears first and serves as the main thumbnail in product listings and search results. When images are reordered, a product snapshot is automatically created to preserve the previous state for audit purposes and dispute resolution.
   *
   * Image reordering is immediate and visible to all customers browsing the product. Sellers can reorder images at any time as part of their product management workflow. The operation validates that the seller owns the product and that all image IDs belong to the specified product.
   *
   * @param connection
   * @param productId UUID of the product whose images are being reordered.
   * @param body Array of image UUIDs in the desired display order. The first image in the array will have display_order 1 and become the main thumbnail.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Validate that the authenticated seller owns the product by checking shopping_mall_seller_id matches the seller's ID.
   *
   * Validate that all image IDs in the request body belong to the specified product (shopping_mall_product_id matches productId).
   *
   * Validate that the product is not deleted (deleted_at is null).
   *
   * Update the display_order field for each image in the shopping_mall_product_images table according to the new order provided in the request body. The first image in the array gets display_order 1, the second gets 2, and so on.
   *
   * After successfully updating all image orders, create a product snapshot in shopping_mall_product_snapshots to record the change for audit trail purposes.
   *
   * Return the updated list of images with their new display_order values, sorted by display_order ascending.
   *
   * Handle edge cases:
   * - If the product is not found, return 404 Not Found
   * - If the seller doesn't own the product, return 403 Forbidden
   * - If the product is deleted, return 404 Not Found
   * - If any image ID in the request doesn't belong to the product, return 400 Bad Request
   * - If the request body is empty or invalid, return 400 Bad Request
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
