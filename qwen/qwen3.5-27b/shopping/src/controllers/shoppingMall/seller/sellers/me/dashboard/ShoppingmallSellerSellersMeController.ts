import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallSellerDashboard } from "../../../../../../api/structures/IShoppingMallSellerDashboard";
import { SellerAuth } from "../../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../../decorators/payload/SellerPayload";
import { getShoppingMallSellerSellersMeDashboard } from "../../../../../../providers/getShoppingMallSellerSellersMeDashboard";

@Controller("/shoppingMall/seller/sellers/me/dashboard")
export class ShoppingmallSellerSellersMeController {
  /**
   * Retrieve the seller dashboard summary showing key metrics about the seller's shop activities.
   *
   * This endpoint provides sellers with an at-a-glance view of their business performance including total product count, order item count, and pending request counts. The data helps sellers monitor their shop status and prioritize responses to customer requests.
   *
   * **Dashboard Metrics**
   *
   * - **Total Products**: Count of all products created by the seller (including active and soft-deleted)
   * - **Total Order Items**: Count of all order items for the seller's products across all orders
   * - **Pending Cancellation Requests**: Count of cancellation requests awaiting seller approval
   * - **Pending Refund Requests**: Count of refund requests awaiting seller approval
   *
   * **Access Control**
   *
   * Only authenticated sellers can access their own dashboard. Each seller sees only their own shop data, not other sellers' information.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query the following aggregates for the authenticated seller:
   *
   * 1. **Total Products**: COUNT(*) from shopping_mall_products WHERE shopping_mall_seller_id = current_seller_id
   *
   * 2. **Total Order Items**: COUNT(*) from shopping_mall_order_items WHERE shopping_mall_seller_id = current_seller_id
   *
   * 3. **Pending Cancellation Requests**: COUNT(*) from shopping_mall_cancellation_requests JOIN shopping_mall_order_items ON cancellation_request.shopping_mall_order_item_id = order_item.id WHERE order_item.shopping_mall_seller_id = current_seller_id AND cancellation_request.status = 'pending'
   *
   * 4. **Pending Refund Requests**: COUNT(*) from shopping_mall_refund_requests JOIN shopping_mall_order_items ON refund_request.shopping_mall_order_item_id = order_item.id WHERE order_item.shopping_mall_seller_id = current_seller_id AND refund_request.status = 'pending'
   *
   * **Authorization**: Verify the request is made by an authenticated seller. Use the seller_id from the current session.
   *
   * **Error Handling**: Return 401 if not authenticated, 403 if the authenticated user is not a seller.
   *
   * **Performance**: Use indexed queries on seller_id and status fields for efficient aggregation.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async dashboard(
    @SellerAuth()
    seller: SellerPayload,
  ): Promise<IShoppingMallSellerDashboard> {
    try {
      return await getShoppingMallSellerSellersMeDashboard({
        seller,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
