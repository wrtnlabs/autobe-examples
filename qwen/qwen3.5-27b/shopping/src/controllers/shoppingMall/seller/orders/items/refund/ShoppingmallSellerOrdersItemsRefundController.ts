import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IShoppingMallRefundRequest } from "../../../../../../api/structures/IShoppingMallRefundRequest";
import { SellerAuth } from "../../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../../decorators/payload/SellerPayload";
import { postShoppingMallSellerOrdersOrderIdItemsItemIdRefundApprove } from "../../../../../../providers/postShoppingMallSellerOrdersOrderIdItemsItemIdRefundApprove";
import { postShoppingMallSellerOrdersOrderIdItemsItemIdRefundReject } from "../../../../../../providers/postShoppingMallSellerOrdersOrderIdItemsItemIdRefundReject";

@Controller("/shoppingMall/seller/orders/:orderId/items/:itemId/refund")
export class ShoppingmallSellerOrdersItemsRefundController {
  /**
   * Approve a refund request for a specific order item. This operation is available to sellers who own the product variant in the order item.
   *
   * When a seller approves a refund request, the order item status changes to 'refunded', the stock quantity is restored through inventory records, and a snapshot of the request state is created for audit purposes. The refund approval applies only to the specific item and does not affect other items in the same order.
   *
   * The seller must provide a response reason when approving the refund request. This reason is stored in the snapshot and can be used for dispute resolution. After approval, the customer receives their refund and the product variant becomes available for purchase again.
   *
   * @param connection
   * @param orderId Unique identifier of the order containing the item to be refunded (global scope).
   * @param itemId Unique identifier of the order item for which the refund is being approved (global scope).
   * @param body Seller's response reason for approving the refund request.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Validate the seller has permission to approve this refund request by checking they own the product variant in the order item.
   *
   * Query shopping_mall_refund_requests for the refund request linked to the order item (shopping_mall_order_item_id = itemId). Verify the request exists, status is 'pending', and the seller_id matches the authenticated seller.
   *
   * Begin database transaction:
   * 1. Update the refund request: set status to 'approved', shopping_mall_seller_id to the responding seller, shopping_mall_seller_session_id to the current session, responded_at to current timestamp.
   * 2. Update the order item: set status to 'refunded', updated_at to current timestamp.
   * 3. Create an inventory record in shopping_mall_inventory_records: shopping_mall_product_variant_id from the order item, quantity_change as positive (equal to the order item quantity), reason as 'Refund for order item {itemId}', created_at to current timestamp.
   * 4. Create a snapshot in shopping_mall_refund_request_snapshots: shopping_mall_refund_request_id, shopping_mall_seller_id, shopping_mall_customer_session_id from the refund request, status_before as 'pending', status_after as 'approved', response_text from request body, created_at to current timestamp.
   * 5. Update the parent order's updated_at timestamp.
   *
   * Commit transaction and return the updated refund request.
   *
   * Error handling:
   * - Return 404 if refund request not found
   * - Return 409 if refund request is not in 'pending' status
   * - Return 403 if seller does not own the product variant in the order item
   * - Return 400 if the order item status is not 'delivered'
   * - Return 400 if the refund request is outside the 7-day window from delivery
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("approve")
  public async approve(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedParam("itemId")
    itemId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallRefundRequest.IApprove,
  ): Promise<IShoppingMallRefundRequest> {
    try {
      return await postShoppingMallSellerOrdersOrderIdItemsItemIdRefundApprove({
        seller,
        orderId,
        itemId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Reject a refund request for an order item, denying the customer's refund.
   *
   * This operation allows sellers to deny refund requests submitted by customers for delivered order items. When a seller rejects a refund request, the request status changes from 'pending' to 'rejected', preventing the refund from being processed. A snapshot of the request state is automatically created and preserved for audit and dispute resolution purposes. Only the seller who owns the specific order item can reject the refund request. The rejection is final and cannot be undone through this endpoint.
   *
   * @param connection
   * @param orderId UUID of the order containing the order item
   * @param itemId UUID of the order item for which the refund request is being rejected
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Verify the refund request exists for the given order item ID and has 'pending' status. Verify the authenticated seller owns the order item (matches shopping_mall_seller_id in shopping_mall_order_items). If validation passes, update the refund request status to 'rejected', set responded_at to current timestamp, and set shopping_mall_seller_id and shopping_mall_seller_session_id. Create an immutable snapshot in shopping_mall_refund_request_snapshots capturing the request state at time of rejection. Return the updated refund request entity. Throw validation error if: refund request not found, status is not 'pending', seller does not own the item, or request was already responded to.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("reject")
  public async reject(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedParam("itemId")
    itemId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallRefundRequest> {
    try {
      return await postShoppingMallSellerOrdersOrderIdItemsItemIdRefundReject({
        seller,
        orderId,
        itemId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
