import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IShoppingMallShipment } from "../../../../../api/structures/IShoppingMallShipment";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { postShoppingMallSellerOrdersOrderIdShipments } from "../../../../../providers/postShoppingMallSellerOrdersOrderIdShipments";

@Controller("/shoppingMall/seller/orders/:orderId/shipments")
export class ShoppingmallSellerOrdersShipmentsController {
  /**
   * Create a new shipment package containing one or more order items from the same seller.
   *
   * This endpoint allows sellers to bundle their order items into a physical shipment package. When creating a shipment, sellers must specify which order items to include (all must belong to the same seller and the specified order), provide the carrier name, and enter the tracking number. Upon successful creation, all included order items automatically transition from 'paid' status to 'shipped' status.
   *
   * Shipment creation is restricted to sellers who own the order items being shipped. Each shipment belongs to exactly one order and is sent by exactly one seller. Different sellers must create separate shipments for their respective items, even within the same order.
   *
   * The tracking information becomes immediately visible to the customer in their order details, allowing them to monitor delivery progress through the carrier's system.
   *
   * @param connection
   * @param orderId UUID of the order containing the items to be shipped. The seller must have order items in this order.
   * @param body Shipment creation data including the list of order item IDs to include, carrier name, and tracking number.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Create a new shipment record in shopping_mall_shipments table.
   *
   * 1. Validate that the authenticated user is a seller with appropriate permissions.
   * 2. Validate orderId exists and belongs to an order that contains items from this seller.
   * 3. From the request body, validate that all specified order item IDs:
   *    - Exist in the shopping_mall_order_items table
   *    - Belong to the specified orderId
   *    - Belong to the authenticated seller (shopping_mall_seller_id matches)
   *    - Have status 'paid' (only unpaid items can be shipped)
   * 4. Validate carrier_name and tracking_number are provided and non-empty.
   * 5. Begin database transaction:
   *    a. Insert new shipment record with order_id, seller_id, carrier_name, tracking_number
   *    b. Set created_at and updated_at to current timestamp
   *    c. Update all included order items: set status to 'shipped', update updated_at
   * 6. Commit transaction.
   * 7. Return the created shipment entity with all included order items.
   *
   * Error handling:
   * - 404 if orderId not found or any order item ID not found
   * - 403 if seller doesn't own any of the specified order items
   * - 409 if any order item is not in 'paid' status
   * - 400 if carrier_name or tracking_number is missing/empty
   * - 400 if no order items are specified in request
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallShipment.ICreate,
  ): Promise<IShoppingMallShipment> {
    try {
      return await postShoppingMallSellerOrdersOrderIdShipments({
        seller,
        orderId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
