import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallDashboard } from "../../../../api/structures/IShoppingMallDashboard";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { getShoppingMallSellerDashboard } from "../../../../providers/getShoppingMallSellerDashboard";

@Controller("/shoppingMall/seller/dashboard")
export class ShoppingmallSellerDashboardController {
  /**
   * Retrieve a personalized dashboard summary for the authenticated user.
   *
   * This endpoint provides a quick overview of key metrics and statistics relevant to the user's role in the shopping mall platform. The response structure adapts based on whether the authenticated user is a customer or a seller.
   *
   * For sellers, the dashboard displays the total number of products listed, the count of order items associated with their products, the number of pending cancellation requests awaiting response, and the number of pending refund requests requiring action. This gives sellers a comprehensive at-a-glance view of their shop's activity and items requiring attention.
   *
   * For customers, the dashboard shows summary information about their order history, current shopping cart status, and wishlist item counts. This helps customers quickly access their shopping activity overview.
   *
   * The endpoint requires valid authentication via JWT token in the Authorization header. The response is tailored to the authenticated user's role and only includes data they have permission to view.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query the database based on the authenticated user's role from the session.
   *
   * For sellers:
   * 1. Count total products from shopping_mall_products where seller_id matches the authenticated seller
   * 2. Count order items from shopping_mall_order_items where seller_id matches
   * 3. Count pending cancellation requests from shopping_mall_cancellation_requests where seller_id matches and status is 'pending'
   * 4. Count pending refund requests from shopping_mall_refund_requests (join with order_items to find seller's products) where status is 'pending'
   * 5. Return aggregated counts in IShoppingMallDashboard response
   *
   * For customers:
   * 1. Count total orders from shopping_mall_orders where customer_id matches
   * 2. Count cart items from shopping_mall_cart_items where customer_id matches
   * 3. Count wishlist items from shopping_mall_wishlist_items where customer_id matches
   * 4. Return aggregated counts in IShoppingMallDashboard response
   *
   * Error handling:
   * - Return 401 if user is not authenticated
   * - Return 403 if user role is not recognized (e.g., admin accessing this endpoint)
   * - Return 500 for database query failures
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @SellerAuth()
    seller: SellerPayload,
  ): Promise<IShoppingMallDashboard> {
    try {
      return await getShoppingMallSellerDashboard({
        seller,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
