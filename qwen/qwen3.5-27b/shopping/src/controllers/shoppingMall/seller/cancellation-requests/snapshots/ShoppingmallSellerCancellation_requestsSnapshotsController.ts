import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallCancellationRequestSnapshot } from "../../../../../api/structures/IPageIShoppingMallCancellationRequestSnapshot";
import { IShoppingMallCancellationRequestSnapshot } from "../../../../../api/structures/IShoppingMallCancellationRequestSnapshot";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { getShoppingMallSellerCancellationRequestsSnapshotsSnapshotId } from "../../../../../providers/getShoppingMallSellerCancellationRequestsSnapshotsSnapshotId";
import { patchShoppingMallSellerCancellationRequestsSnapshots } from "../../../../../providers/patchShoppingMallSellerCancellationRequestsSnapshots";

@Controller("/shoppingMall/seller/cancellation-requests/snapshots")
export class ShoppingmallSellerCancellation_requestsSnapshotsController {
  /**
   * Search and filter cancellation request snapshots for administrative oversight and dispute resolution.
   *
   * This endpoint returns a paginated list of cancellation request snapshots, which are immutable audit records capturing the state of cancellation requests when sellers approve or reject them. Each snapshot includes the status transition (before and after), seller response details, and the timestamp of the response.
   *
   * Administrators can use this endpoint to investigate order disputes, audit seller responses, and verify the complete history of cancellation request handling. The snapshots provide an immutable audit trail that cannot be modified or deleted.
   *
   * Filters available include cancellation request ID, seller ID, status transitions, and date ranges. Results are sorted by creation date with newest snapshots first.
   *
   * @param connection
   * @param body Search criteria for filtering cancellation request snapshots including cancellation request ID, seller ID, status filters, date range, and pagination parameters.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query shopping_mall_cancellation_request_snapshots table with pagination and filtering capabilities.
   *
   * Filtering:
   * - Filter by cancellation request ID (shopping_mall_cancellation_request_id) to view all snapshots for a specific request
   * - Filter by seller ID (shopping_mall_seller_id) to view all snapshots where a seller responded
   * - Filter by status_before and status_after to find specific state transitions
   * - Filter by created_at date range to find snapshots within a time period
   *
   * Pagination:
   * - Support cursor-based or offset-based pagination
   * - Default page size: 20, maximum: 100
   * - Sort by created_at descending (newest first) by default
   *
   * Joins:
   * - Optionally join with shopping_mall_cancellation_requests to include request details
   * - Optionally join with shopping_mall_sellers to include seller information
   *
   * Authorization:
   * - Only administrators can access this endpoint
   * - Sellers can only view snapshots for their own responses (different endpoint scope)
   *
   * Error handling:
   * - Return 404 if no snapshots match the criteria
   * - Return 403 if user lacks administrator privileges
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IShoppingMallCancellationRequestSnapshot.IRequest,
  ): Promise<IPageIShoppingMallCancellationRequestSnapshot.ISummary> {
    try {
      return await patchShoppingMallSellerCancellationRequestsSnapshots({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves a specific cancellation request snapshot by its unique identifier.
   *
   * This endpoint provides access to immutable audit records that capture the state of cancellation requests when sellers respond to them. Each snapshot preserves the status transition (from pending to approved or rejected), the seller's response text, and the exact timestamp of the response.
   *
   * Snapshots are used for dispute resolution, order history completeness, and audit trail purposes. They cannot be modified or deleted once created, ensuring a permanent record of all cancellation request lifecycle events.
   *
   * @param connection
   * @param snapshotId Unique identifier of the cancellation request snapshot to retrieve (global scope)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query the shopping_mall_cancellation_request_snapshots table by primary key (id) using the snapshotId parameter.
   *
   * Return the complete snapshot record including:
   * - id: Primary key UUID
   * - shopping_mall_cancellation_request_id: Reference to the cancellation request
   * - shopping_mall_seller_id: Reference to the responding seller
   * - status_before: Previous status value (e.g., 'pending')
   * - status_after: New status value (e.g., 'approved' or 'rejected')
   * - seller_response: Optional seller explanation text
   * - created_at: Timestamp of snapshot creation
   *
   * Handle edge cases:
   * - Return 404 if snapshotId does not exist
   * - Ensure proper UUID validation for the path parameter
   * - No authorization checks needed beyond session validation (snapshots are read-only audit data)
   *
   * The snapshot is immutable and should be returned as-is without any modifications.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":snapshotId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("snapshotId")
    snapshotId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallCancellationRequestSnapshot> {
    try {
      return await getShoppingMallSellerCancellationRequestsSnapshotsSnapshotId(
        {
          seller,
          snapshotId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
