import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallCategorySnapshot } from "../../../../api/structures/IPageIShoppingMallCategorySnapshot";
import { IShoppingMallCategorySnapshot } from "../../../../api/structures/IShoppingMallCategorySnapshot";
import { getShoppingMallCategoriesCategoryIdSnapshotsSnapshotId } from "../../../../providers/getShoppingMallCategoriesCategoryIdSnapshotsSnapshotId";
import { patchShoppingMallCategoriesCategoryIdSnapshots } from "../../../../providers/patchShoppingMallCategoriesCategoryIdSnapshots";

@Controller("/shoppingMall/categories/:categoryId/snapshots")
export class ShoppingmallCategoriesSnapshotsController {
  /**
   * Retrieve paginated list of modification snapshots for a specific category, showing all changes made to category name, description, and parent category relationship.
   *
   * This endpoint provides a complete audit trail of category modifications, displaying before and after values for each change. It is designed for administrative oversight and dispute resolution, allowing administrators to track the evolution of category structure over time.
   *
   * The operation supports filtering by date range and change type, with cursor-based pagination for efficient browsing of large audit histories. All snapshots are immutable and preserved even after category deletion.
   *
   * @param connection
   * @param categoryId UUID of the category to retrieve snapshots for (global scope)
   * @param body Search criteria including date range filters, change type filters, and pagination parameters for browsing category modification history.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor null
     * @x-autobe-specification Query shopping_mall_category_snapshots table
     *   where shopping_mall_category_id matches the path parameter categoryId.
   *
   * Apply filtering from request body:
   * - Filter by created_at date range if specified
   * - Filter by change type (name, description, parent_category) if specified
   *
   * Apply sorting: order by created_at descending (newest first) by default.
   *
   * Apply pagination using cursor-based approach:
   * - Use limit parameter (default 20, max 100)
   * - Use cursor parameter for subsequent pages
   * - Return next_cursor in response for pagination
   *
   * Join with shopping_mall_categories to verify category exists and is accessible to requesting administrator.
   *
   * Return snapshot records with all before/after fields populated.
   *
   * Error handling:
   * - Return 404 if category not found
   * - Return 403 if user is not an administrator
   * - Return 400 for invalid pagination parameters
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedParam("categoryId")
    categoryId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallCategorySnapshot.IRequest,
  ): Promise<IPageIShoppingMallCategorySnapshot.ISummary> {
    try {
      return await patchShoppingMallCategoriesCategoryIdSnapshots({
        categoryId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves a specific category snapshot by category ID and snapshot ID.
   *
   * This endpoint returns the complete audit record of a single category modification, including before and after values for name, description, and parent category relationship. Category snapshots are immutable records created whenever administrators edit categories, preserving the exact state at the time of change for compliance and dispute resolution purposes.
   *
   * The snapshot includes all modification details: previous and new values for category name, description, and parent category ID (for subcategory hierarchy changes). Each snapshot is timestamped to provide temporal context for the audit trail.
   *
   * @param connection
   * @param categoryId Category ID (global scope)
   * @param snapshotId Category snapshot ID (global scope)
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor null
     * @x-autobe-specification Query the shopping_mall_category_snapshots table
     *   to retrieve a single snapshot record.
   *
   * 1. Validate both categoryId and snapshotId as UUIDs
   * 2. Query shopping_mall_category_snapshots where id = snapshotId AND shopping_mall_category_id = categoryId
   * 3. The dual filter ensures proper scoping - the snapshot must belong to the specified category
   * 4. Return the complete snapshot record with all fields: id, shopping_mall_category_id, name_before, name_after, description_before, description_after, parent_category_id_before, parent_category_id_after, created_at
   * 5. If no snapshot found matching both criteria, return 404 Not Found
   * 6. No joins needed - snapshot contains all required data
   * 7. Ensure proper error handling for invalid UUIDs or non-existent records
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":snapshotId")
  public async at(
    @TypedParam("categoryId")
    categoryId: string & tags.Format<"uuid">,
    @TypedParam("snapshotId")
    snapshotId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallCategorySnapshot> {
    try {
      return await getShoppingMallCategoriesCategoryIdSnapshotsSnapshotId({
        categoryId,
        snapshotId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
