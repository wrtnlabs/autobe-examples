import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IShoppingMallSellerOrderAnalytic } from "../../../../../../api/structures/IShoppingMallSellerOrderAnalytic";
import { AdminAuth } from "../../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminSellersSellerIdAnalyticsOrders } from "../../../../../../providers/getShoppingMallAdminSellersSellerIdAnalyticsOrders";

@Controller("/shoppingMall/admin/sellers/:sellerId/analytics/orders")
export class ShoppingmallAdminSellersAnalyticsOrdersController {
  /**
   * Retrieve comprehensive order analytics and performance metrics for a specific seller in the shopping mall platform.
   *
   * This endpoint provides sellers and administrators with detailed business intelligence about order performance. The analytics include total order counts, revenue metrics, item quantities sold, and a breakdown of orders by fulfillment status (paid, shipped, delivered, cancelled, refunded). The response also includes recent order activity to help sellers monitor their current business performance.
   *
   * Sellers can access this endpoint to view their own order analytics for business planning and performance tracking. Administrators can access analytics for any seller to monitor platform-wide performance, identify top-performing sellers, or investigate potential issues with specific sellers' order fulfillment.
   *
   * The analytics data is derived from the shopping_mall_order_items table, which tracks individual line items within customer orders. Each order item is associated with a seller through the shopping_mall_seller_id foreign key. The endpoint aggregates this data to provide meaningful business metrics that help sellers understand their sales performance and order fulfillment patterns.
   *
   * Related operations include GET /sellers/me/orders for listing individual order items, and GET /sellers/me/dashboard for a high-level summary of seller metrics.
   *
   * @param connection
   * @param sellerId Unique identifier of the seller whose order analytics to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query shopping_mall_order_items table filtered by shopping_mall_seller_id equal to the sellerId path parameter.
   *
   * Aggregate the following metrics:
   * - Total order count: COUNT of distinct shopping_mall_order_id
   * - Total items sold: SUM of quantity
   * - Total revenue: SUM of (quantity * price)
   * - Status breakdown: GROUP BY status with COUNT for each status (paid, shipped, delivered, cancelled, refunded)
   * - Average order value: total revenue / total order count
   * - Recent orders: JOIN with shopping_mall_orders to get order dates, ORDER BY created_at DESC, LIMIT 10
   *
   * Join with shopping_mall_orders to get order-level information including customer_id and order timestamps.
   *
   * Apply data isolation: if authenticated user is a seller, verify sellerId matches their own ID. If admin, allow access to any sellerId.
   *
   * Handle soft-deleted records: exclude order items where deleted_at is not null.
   *
   * Return null or empty analytics if seller has no order items.
   *
   * Cache results for 5 minutes to reduce database load on repeated requests.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async getOrderAnalytics(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallSellerOrderAnalytic> {
    try {
      return await getShoppingMallAdminSellersSellerIdAnalyticsOrders({
        admin,
        sellerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
