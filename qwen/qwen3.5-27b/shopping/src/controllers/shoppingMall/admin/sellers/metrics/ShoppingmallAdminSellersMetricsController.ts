import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IShoppingMallSeller } from "../../../../../api/structures/IShoppingMallSeller";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminSellersSellerIdMetrics } from "../../../../../providers/getShoppingMallAdminSellersSellerIdMetrics";

@Controller("/shoppingMall/admin/sellers/:sellerId/metrics")
export class ShoppingmallAdminSellersMetricsController {
  /**
   * Retrieve comprehensive business metrics and performance statistics for a specific seller account.
   *
   * This operation provides sellers and administrators with aggregated analytics data derived from order history, shipment records, cancellation requests, refund requests, and customer reviews. The metrics include total order item counts broken down by fulfillment status (paid, shipped, delivered, cancelled, refunded), total revenue calculated from all completed transactions, and shipment performance indicators including delivery confirmation rates.
   *
   * The response includes cancellation and refund request statistics showing pending, approved, and rejected counts, enabling sellers to monitor their customer service workload and resolution rates. Customer satisfaction metrics are provided through average product ratings and total review counts across all products sold by the seller.
   *
   * Monthly order trends for the past 12 months are included to help sellers identify seasonal patterns and growth trajectories. Derived metrics such as cancellation rate, refund rate, and delivery confirmation rate provide quick insights into overall seller performance and customer satisfaction levels.
   *
   * This endpoint is accessible to sellers for viewing their own metrics and to administrators for oversight of all seller accounts on the platform. The data is read-only and does not modify any database records.
   *
   * @param connection
   * @param sellerId Unique identifier of the seller whose metrics are being retrieved
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query aggregated metrics from multiple tables for the specified seller.
   *
   * 1. Retrieve seller record from shopping_mall_sellers by sellerId. Return 404 if not found.
   * 2. Query shopping_mall_order_items where seller_id matches, grouping by status to get order item counts per status (paid, shipped, delivered, cancelled, refunded).
   * 3. Calculate total revenue by summing (quantity * price) for all order items.
   * 4. Query shopping_mall_shipments where seller_id matches, counting total shipments and delivery confirmation rate.
   * 5. Query shopping_mall_cancellation_requests where seller_id matches, counting pending, approved, and rejected requests.
   * 6. Query shopping_mall_refund_requests where seller_id matches, counting pending, approved, and rejected requests.
   * 7. Join shopping_mall_order_items with shopping_mall_reviews to calculate average rating and total review count for seller's products.
   * 8. Query shopping_mall_order_items grouped by created_at month to generate monthly order trends (last 12 months).
   * 9. Calculate derived metrics: cancellation rate (approved cancellations / total orders), refund rate (approved refunds / delivered orders), delivery confirmation rate.
   * 10. Return aggregated metrics object with all computed statistics.
   *
   * Authorization: Seller can access their own metrics (seller_id matches authenticated user). Admin can access any seller's metrics.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallSeller.IMetric> {
    try {
      return await getShoppingMallAdminSellersSellerIdMetrics({
        admin,
        sellerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
