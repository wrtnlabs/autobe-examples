import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallSellerApprovalSnapshot } from "../../../../../api/structures/IPageIShoppingMallSellerApprovalSnapshot";
import { IShoppingMallSellerApprovalSnapshot } from "../../../../../api/structures/IShoppingMallSellerApprovalSnapshot";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { patchShoppingMallAdminSellersSellerIdSnapshots } from "../../../../../providers/patchShoppingMallAdminSellersSellerIdSnapshots";

@Controller("/shoppingMall/admin/sellers/:sellerId/snapshots")
export class ShoppingmallAdminSellersSnapshotsController {
  /**
   * Retrieve a filtered and paginated list of seller profile snapshots for a specific seller.
   *
   * This operation provides access to the immutable audit trail of seller profile changes. Each snapshot captures the complete state of a seller's approval request at key moments, preserving historical records for data integrity and dispute resolution purposes.
   *
   * **Access Control**:
   * - Sellers can view snapshots of their own approval requests
   * - Administrators can view snapshots for any seller on the platform
   * - Customers and guests cannot access this endpoint
   *
   * **Snapshot Contents**:
   * Each snapshot contains the complete JSON state of the seller approval request including seller_id, reason, status (pending/approved/rejected), submitted_at timestamp, and responded_at timestamp. Snapshots are immutable and cannot be modified or deleted once created.
   *
   * **Filtering and Pagination**:
   * Supports filtering by approval status and date range. Results are paginated with configurable page size and sorted by creation date (newest first).
   *
   * **Use Cases**:
   * - Sellers reviewing their application history and approval workflow progression
   * - Administrators conducting audits or investigating disputes
   * - Tracking status transitions from pending to approved/rejected over time
   *
   * **Related Operations**:
   * - `GET /sellers/{sellerId}` - Get current seller profile
   * - `PATCH /sellers/{sellerId}/approval-requests` - List seller approval requests
   * - `PATCH /sellers` - List all sellers (admin only)
   *
   * @param connection
   * @param sellerId UUID of the seller whose profile snapshots to retrieve
   * @param body Filter and pagination parameters for snapshots
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query shopping_mall_seller_approval_snapshots table filtered by seller_id.
   *
   * Authorization logic:
   * - If caller is seller: verify sellerId matches authenticated seller's ID
   * - If caller is admin: allow access to any sellerId
   * - Return 403 Forbidden if authorization fails
   *
   * Query execution:
   * 1. Validate sellerId exists in shopping_mall_sellers table
   * 2. Filter snapshots where shopping_mall_seller_approval_request_id belongs to requests for the given seller
   * 3. Join with shopping_mall_seller_approval_requests to get seller_id
   * 4. Apply optional filters from request body (status, date range)
   * 5. Order by created_at descending (newest first)
   * 6. Apply pagination from request body (default: page=1, limit=20, max 100)
   *
   * Data transformation:
   * - Parse snapshot_data JSON field to extract structured data
   * - Return summary view with: id, snapshot_data (parsed), created_at
   * - Include pagination metadata: total, page, limit, totalPages
   *
   * Error handling:
   * - 404 Not Found if sellerId doesn't exist
   * - 403 Forbidden if unauthorized access attempt
   * - Validate pagination parameters (page >= 1, limit 1-100)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallSellerApprovalSnapshot.IRequest,
  ): Promise<IPageIShoppingMallSellerApprovalSnapshot.ISummary> {
    try {
      return await patchShoppingMallAdminSellersSellerIdSnapshots({
        admin,
        sellerId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
