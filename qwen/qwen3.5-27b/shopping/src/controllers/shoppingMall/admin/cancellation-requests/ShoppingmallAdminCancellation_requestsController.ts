  /**
   * Approve or reject a customer's cancellation request for an order item.
   *
   * This operation allows sellers to respond to pending cancellation requests submitted by customers. When a customer requests cancellation of an order item that has not yet been shipped, the seller must review and either approve or reject the request.
   *
   * When approving a cancellation request, the order item status changes to 'cancelled', the product variant's inventory is restored, and the customer is notified. The order item is no longer eligible for shipment or delivery.
   *
   * When rejecting a cancellation request, the seller must provide a rejection reason explaining why the cancellation cannot be processed. The order item remains in its current status and continues through the normal fulfillment workflow.
   *
   * An immutable cancellation snapshot is automatically created when the seller responds, preserving the complete state of the request at the time of response. This snapshot includes the previous state, new state, seller's decision, response timestamp, and all relevant fields. Customers can view these snapshots for transparency and dispute resolution.
   *
   * Only the seller who owns the order item can respond to the cancellation request. The system validates ownership before allowing the update operation.
   *
   * @param connection
   * @param cancellationRequestId Unique identifier of the cancellation request to update
   * @param body Cancellation request response with status and optional rejection reason
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Update a cancellation request record in shopping_mall_cancellation_requests table.
   *
   * 1. Validate cancellationRequestId exists and belongs to the authenticated seller (via order item relationship)
   * 2. Verify current status is 'pending' - only pending requests can be responded to
   * 3. Validate request body: status must be 'approved' or 'rejected'; if 'rejected', rejection_reason is required
   * 4. Create cancellation snapshot in shopping_mall_cancellation_snapshots BEFORE updating status:
   *    - Capture current state (previous status, reason, requested_at)
   *    - Capture new state (approved/rejected, rejection_reason, responded_at, seller_id)
   *    - Store as immutable JSON in snapshot_data field
   * 5. If snapshot creation fails, abort operation and return error (per section 760)
   * 6. Update cancellation request:
   *    - Set status to 'approved' or 'rejected'
   *    - Set rejection_reason if provided
   *    - Set shopping_mall_seller_id to responding seller's ID
   *    - Set responded_at to current timestamp
   *    - Set updated_at to current timestamp
   * 7. If status is 'approved', update related order item status to 'cancelled' and restore inventory
   * 8. Return updated cancellation request with all fields including snapshot reference
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
