  /**
   * Update a seller approval request to approve or reject a seller's registration application.
   *
   * This operation allows platform administrators to respond to pending seller approval requests. When an administrator approves a request, the seller's account status is updated to 'approved', enabling them to list products and operate their shop. When an administrator rejects a request, the seller's account status is set to 'rejected' and the rejection reason is stored and communicated to the seller.
   *
   * The approval request must be in 'pending' status to be updated. Attempts to update already approved or rejected requests will be rejected. When rejecting a seller application, administrators must provide a rejection reason explaining why the application was denied. This reason is visible to the seller and helps them understand what improvements are needed.
   *
   * This operation updates both the seller approval request record and the related seller profile in the shopping_mall_sellers table. The responded_at timestamp is automatically set when the administrator responds, creating an audit trail of when decisions were made.
   *
   * Related operations include GET /sellerApprovalRequests/{requestId} to view request details before responding, and PATCH /sellerApprovalRequests to list all pending approval requests requiring administrator attention.
   *
   * @param connection
   * @param requestId Target seller approval request's UUID identifier
   * @param body Update data for the seller approval request including new status and optional rejection reason
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Update a seller approval request record in the shopping_mall_seller_approval_requests table.
   *
   * 1. Validate the requestId exists and is not soft-deleted
   * 2. Verify the current user is an administrator (admin or super_admin grade)
   * 3. Check that the approval request status is 'pending' - reject if already approved or rejected
   * 4. If status is being set to 'rejected', validate that rejection_reason is provided and not empty
   * 5. If status is being set to 'approved', update the related seller's approval_status to 'approved' in shopping_mall_sellers table
   * 6. If status is being set to 'rejected', update the related seller's approval_status to 'rejected' and store rejection_reason in shopping_mall_sellers table
   * 7. Update the responded_at timestamp to the current time
   * 8. Update the updated_at timestamp
   * 9. Return the updated approval request with all fields including the seller relationship
   *
   * Error handling:
   * - Return 404 if approval request not found or soft-deleted
   * - Return 403 if user is not an administrator
   * - Return 400 if status is already approved or rejected (cannot update)
   * - Return 400 if rejection_reason is missing when status is 'rejected'
   * - Return 400 if invalid status value provided
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
