import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IShoppingMallOrderItem } from "../../../../../api/structures/IShoppingMallOrderItem";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { putShoppingMallAdminOrdersOrderIdItemsItemId } from "../../../../../providers/putShoppingMallAdminOrdersOrderIdItemsItemId";

@Controller("/shoppingMall/admin/orders/:orderId/items/:itemId")
export class ShoppingmallAdminOrdersItemsController {
  /**
   * Update an existing order item's status or details in the shopping mall platform.
   *
   * This operation allows authorized users (sellers and administrators) to modify order item properties, primarily the fulfillment status. Order items represent individual line items within customer orders, each tracking a specific product variant purchase with quantity, price, and current status.
   *
   * Status transitions follow strict business rules:
   * - Items in "paid" status can transition to "shipped" (when seller creates shipment) or "cancelled" (when cancellation request is approved)
   * - Items in "shipped" status can transition to "delivered" (when customer confirms delivery or auto-delivery occurs after 14 days)
   * - Items in "delivered" status can transition to "refunded" (when refund request is approved within 7 days)
   * - Items in "cancelled" or "refunded" status are terminal and cannot be changed
   *
   * Sellers can only update order items for their own products. Administrators have full access to update any order item. Regular customers cannot use this endpoint directly; they must use the cancellation or refund request workflows instead.
   *
   * The order item contains purchase-time snapshots of product details, variant information, and seller profile to preserve historical accuracy even if the original entities are modified or deleted. These snapshots cannot be modified through this endpoint.
   *
   * Related operations:
   * - `GET /orders/{orderId}/items/{itemId}` - Retrieve order item details
   * - `POST /orders/{orderId}/items/{itemId}/cancel` - Request cancellation
   * - `POST /orders/{orderId}/items/{itemId}/refund` - Request refund
   * - `POST /shipments` - Create shipment (updates items to shipped)
   *
   * @param connection
   * @param orderId Target order's ID (UUID)
   * @param itemId Target order item's ID (UUID)
   * @param body Update data for the order item
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query shopping_mall_order_items table to find the order item by orderId and itemId.
   *
   * Validate authorization:
   * - Seller can only update order items belonging to their products (check shopping_mall_seller_id)
   * - Admin can update any order item
   * - Customer cannot directly update order items (use cancellation/refund workflows instead)
   *
   * Validate status transition rules:
   * - paid → shipped: Allowed for seller when creating shipment
   * - shipped → delivered: Allowed when delivery is confirmed
   * - paid → cancelled: Allowed only before shipment (cancellation request approved)
   * - delivered → refunded: Allowed within 7 days of delivery (refund request approved)
   * - Invalid transitions return error
   *
   * If status is updated:
   * - Update order item status in shopping_mall_order_items
   * - Update updated_at timestamp
   * - Recalculate parent order status based on all item statuses
   * - If status is shipped, ensure shipment record exists
   * - If status is delivered, update delivered_at timestamp
   *
   * If reason is provided, store it for audit purposes.
   *
   * Return updated order item with all fields including snapshots.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedParam("itemId")
    itemId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallOrderItem.IUpdate,
  ): Promise<IShoppingMallOrderItem> {
    try {
      return await putShoppingMallAdminOrdersOrderIdItemsItemId({
        admin,
        orderId,
        itemId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
