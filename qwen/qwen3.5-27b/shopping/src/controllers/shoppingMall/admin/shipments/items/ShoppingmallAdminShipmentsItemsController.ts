import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallShipmentItem } from "../../../../../api/structures/IPageIShoppingMallShipmentItem";
import { IShoppingMallOrderItem } from "../../../../../api/structures/IShoppingMallOrderItem";
import { IShoppingMallShipmentItem } from "../../../../../api/structures/IShoppingMallShipmentItem";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminShipmentsShipmentIdItemsItemId } from "../../../../../providers/getShoppingMallAdminShipmentsShipmentIdItemsItemId";
import { patchShoppingMallAdminShipmentsShipmentIdItems } from "../../../../../providers/patchShoppingMallAdminShipmentsShipmentIdItems";

@Controller("/shoppingMall/admin/shipments/:shipmentId/items")
export class ShoppingmallAdminShipmentsItemsController {
  /**
   * Retrieve a paginated list of order items included in a specific shipment.
   *
   * This operation returns all order items that are part of the specified shipment, including product details, quantity, price at time of purchase, and current fulfillment status. Each shipment can contain multiple order items from the same seller, consolidated for delivery tracking purposes.
   *
   * The response includes comprehensive order item information such as product snapshots, variant details, seller profile information, and the current status of each item (paid, shipped, delivered, cancelled, or refunded). This enables sellers and administrators to view the complete contents of a shipment and track the fulfillment status of individual items.
   *
   * Access is restricted to the seller who created the shipment or administrators with appropriate permissions. Customers can view shipment items through their order detail pages, which provides a customer-specific view of their purchases.
   *
   * @param connection
   * @param shipmentId Unique identifier of the shipment to retrieve items for
   * @param body Search criteria and pagination parameters for shipment items
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query the shopping_mall_shipment_items junction table filtered by the provided shipmentId from the path parameter. Join with shopping_mall_order_items to retrieve complete order item details including quantity, price, status, and snapshot data.
   *
   * Apply pagination parameters from the request body (page, limit) to limit result set size. Default page size is 20, maximum is 100.
   *
   * Support optional filtering on order item status if provided in the request body (e.g., filter by 'shipped' or 'delivered' items only).
   *
   * Sort results by created_at in descending order (newest items first) unless a different sort order is specified.
   *
   * Validate that the shipment exists and is not soft-deleted. Return 404 if shipment not found.
   *
   * Verify authorization: only the seller who created the shipment or administrators can access this endpoint. Deny access for other users with 403.
   *
   * Return paginated response with total count, current page, page size, and array of order item summaries.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("shipmentId")
    shipmentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallShipmentItem.IRequest,
  ): Promise<IPageIShoppingMallShipmentItem.ISummary> {
    try {
      return await patchShoppingMallAdminShipmentsShipmentIdItems({
        admin,
        shipmentId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific order item within a shipment.
   *
   * This operation provides granular access to individual order items that are part of a shipment. It returns the complete order item record including the product snapshot, variant snapshot, and seller profile snapshot that were captured at the time of order placement. These snapshots ensure historical accuracy even if the original product, variant, or seller profile is later modified or deleted.
   *
   * The response includes the order item's current fulfillment status (paid, shipped, delivered, cancelled, or refunded), quantity purchased, and unit price at time of purchase. Additionally, shipment tracking information is included such as the carrier name, tracking number, shipment date, delivery date, and delivery confirmation status.
   *
   * This endpoint is useful for customers who want to view detailed information about specific items in their shipments, for sellers who need to manage individual items within their shipments, and for administrators who require oversight capabilities for order and shipment management.
   *
   * Authorization is enforced at multiple levels: customers can only access items from their own orders, sellers can only access items for their own products, and administrators have full access to all order items across the platform.
   *
   * @param connection
   * @param shipmentId Target shipment's unique identifier
   * @param itemId Target order item's unique identifier
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query the shopping_mall_shipment_items junction table to verify the order item exists in the specified shipment using the unique constraint on shopping_mall_order_item_id.
   *
   * Retrieve the complete order item from shopping_mall_order_items by the itemId path parameter.
   *
   * Verify authorization: the requesting customer must be the owner of the order (via shopping_mall_order_id relationship), or the requesting seller must be the seller of the order item (via shopping_mall_seller_id relationship), or the user must have admin privileges.
   *
   * Join with shopping_mall_shipments to include shipment tracking information (tracking_carrier, tracking_number, shipped_at, delivered_at, delivery_confirmed) in the response.
   *
   * Return the order item with all fields including product_snapshot, variant_snapshot, seller_profile_snapshot, quantity, price, status, and timestamps.
   *
   * Handle soft-deleted order items by checking deleted_at field and returning appropriate error if the item is deleted.
   *
   * Handle soft-deleted shipments similarly by checking the shipment's deleted_at field.
   *
   * Validate that the shipment and order item relationship exists before returning data.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":itemId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("shipmentId")
    shipmentId: string & tags.Format<"uuid">,
    @TypedParam("itemId")
    itemId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallOrderItem> {
    try {
      return await getShoppingMallAdminShipmentsShipmentIdItemsItemId({
        admin,
        shipmentId,
        itemId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
