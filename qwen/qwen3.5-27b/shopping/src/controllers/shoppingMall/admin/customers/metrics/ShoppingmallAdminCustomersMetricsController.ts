import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IShoppingMallCustomerMetric } from "../../../../../api/structures/IShoppingMallCustomerMetric";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminCustomersCustomerIdMetrics } from "../../../../../providers/getShoppingMallAdminCustomersCustomerIdMetrics";

@Controller("/shoppingMall/admin/customers/:customerId/metrics")
export class ShoppingmallAdminCustomersMetricsController {
  /**
   * Retrieve comprehensive metrics and analytics for a specific customer account in the shopping mall platform.
   *
   * This operation provides aggregated statistics about a customer's engagement and activity across the platform. The metrics include order history summaries, wishlist and cart statistics, review activity, and cancellation/refund request history. This endpoint is useful for customer service representatives, administrators, and customers themselves to understand purchasing patterns and account activity.
   *
   * The response includes order statistics such as total number of orders, total spending amount, average order value, and breakdown of orders by status (paid, shipped, delivered, cancelled, refunded). Wishlist and cart metrics show the current number of items saved for later purchase and items in the active shopping cart.
   *
   * Review statistics display the total number of product reviews written by the customer and their average rating given. Cancellation and refund request metrics provide insight into return behavior and customer satisfaction issues.
   *
   * Access to this endpoint requires authentication. Customers can view their own metrics, while administrators have permission to view metrics for any customer account for support and analytics purposes. The customerId parameter must be a valid UUID corresponding to an existing customer in the shopping_mall_customers table.
   *
   * @param connection
   * @param customerId The unique identifier of the customer whose metrics to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query and aggregate customer metrics from multiple database tables:
   *
   * 1. Order Statistics:
   *    - Count total orders from shopping_mall_orders where customer_id = customerId
   *    - Sum total_price from shopping_mall_orders for total spending
   *    - Calculate average order value (total_spending / order_count)
   *    - Count orders by status (paid, shipped, delivered, cancelled, refunded) from shopping_mall_order_items
   *
   * 2. Wishlist Statistics:
   *    - Count total wishlist items from shopping_mall_wishlist_items where customer_id = customerId
   *
   * 3. Cart Statistics:
   *    - Count total cart items from shopping_mall_cart_items where customer_id = customerId
   *    - Sum total cart value by joining with shopping_mall_product_variants
   *
   * 4. Review Statistics:
   *    - Count total reviews from shopping_mall_reviews where customer_id = customerId
   *    - Calculate average rating given by customer
   *
   * 5. Cancellation Statistics:
   *    - Count total cancellation requests from shopping_mall_cancellation_requests where customer_id = customerId
   *    - Count by status (pending, approved, rejected)
   *
   * 6. Refund Statistics:
   *    - Count total refund requests from shopping_mall_refund_requests where customer_id = customerId
   *    - Count by status (pending, approved, rejected)
   *
   * 7. Account Information:
   *    - Get customer registration date from shopping_mall_customers
   *    - Calculate account age in days
   *
   * Authorization:
   * - Verify customer is authenticated
   * - Allow customers to view their own metrics (customerId matches authenticated user)
   * - Allow administrators to view any customer metrics
   *
   * Error Handling:
   * - Return 404 if customerId not found
   * - Return 403 if unauthorized access attempt
   * - Return 500 for aggregation query failures
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("customerId")
    customerId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallCustomerMetric> {
    try {
      return await getShoppingMallAdminCustomersCustomerIdMetrics({
        admin,
        customerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
