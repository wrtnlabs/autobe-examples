/**
 * Prepare random shopping mall order creation data for E2E testing.
 *
 * Generates a complete IShoppingMallOrder.ICreate with randomized values.
 * This DTO represents the checkout request body containing the shipping address
 * reference for order creation. The customer identity is derived from authentication,
 * and the order number is auto-generated by the system.
 *
 * @param input - Optional partial input to override specific fields
 * @returns Complete IShoppingMallOrder.ICreate instance with all required fields
 */
export function prepare_random_shopping_mall_order(
  input?: DeepPartial<IShoppingMallOrder.ICreate> | undefined,
): IShoppingMallOrder.ICreate {
  return {
    shopping_mall_customer_address_id:
      input?.shopping_mall_customer_address_id ??
      typia.random<string & tags.Format<"uuid">>(),
  };
}
