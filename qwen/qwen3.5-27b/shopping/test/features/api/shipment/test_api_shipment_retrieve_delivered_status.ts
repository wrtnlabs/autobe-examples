/**
 * Test that a customer can retrieve shipment information after delivery confirmation, verifying the delivered_at timestamp is set.
 *
 * This test validates the complete order fulfillment workflow from product creation through delivery confirmation. It ensures that when a customer confirms delivery for a shipment, the system correctly updates the shipment's delivered_at timestamp and transitions all included order items to 'delivered' status. The test also verifies that the order status reflects the delivery confirmation.
 *
 * The workflow covers:
 * - Customer and seller authentication
 * - Product and variant creation with inventory
 * - Customer checkout process
 * - Seller shipment creation
 * - Customer delivery confirmation
 * - Shipment retrieval with delivery status validation
 *
 * Special attention is given to verifying that the delivered_at timestamp is properly set after delivery confirmation and that the order status correctly reflects the delivery state.
 */
export async function test_api_shipment_retrieve_delivered_status(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register and authenticate customer
  const customerConnection: api.IConnection = { host: connection.host };
  const customerAuth = await authorize_customer_join(customerConnection, {});
  typia.assert(customerAuth);
  // 2. Register and authenticate seller
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {});
  typia.assert(sellerAuth);
  // 3. Seller creates a product
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    {},
  );
  typia.assert(product);
  // 4. Seller creates a variant with inventory
  const variant =
    await generate_random_shopping_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
        body: {
          initialStockQuantity: 10,
        },
      },
    );
  typia.assert(variant);
  // 5. Customer adds variant to cart
  const cartItem =
    await generate_random_shopping_mall_customer_cart_items_create(
      customerConnection,
      {
        body: {
          productVariantId: variant.id,
          quantity: 1,
        },
      },
    );
  typia.assert(cartItem);
  // 6. Customer completes checkout (creates order)
  const order = await generate_random_shopping_mall_customer_checkout(
    customerConnection,
    {},
  );
  typia.assert(order);
  // 7. Seller creates shipment for the order item
  const shipment = await generate_random_shopping_mall_seller_shipments_create(
    sellerConnection,
    {
      body: {
        order_item_ids: [order.items[0].id],
        order_id: order.id,
      },
    },
  );
  typia.assert(shipment);
  // 8. Customer confirms delivery
  const confirmedShipment =
    await api.functional.shoppingMall.customer.orders.shipments.delivered.confirmDelivery(
      customerConnection,
      {
        orderId: order.id,
        shipmentId: shipment.id,
      },
    );
  typia.assert(confirmedShipment);
  // 9. Customer retrieves shipment information
  const retrievedShipment =
    await api.functional.shoppingMall.customer.shipments.at(
      customerConnection,
      {
        shipmentId: shipment.id,
      },
    );
  typia.assert(retrievedShipment);
  // 10. Validate delivered_at is set
  TestValidator.predicate(
    "delivered_at should be set after delivery confirmation",
    () => retrievedShipment.delivered_at !== null,
  );
  // 11. Validate delivered_at is after created_at
  TestValidator.predicate("delivered_at should be after created_at", () => {
    if (retrievedShipment.delivered_at === null) return false;
    return (
      new Date(retrievedShipment.delivered_at).getTime() >
      new Date(retrievedShipment.created_at).getTime()
    );
  });
  // 12. Validate order status is 'delivered'
  TestValidator.equals(
    "order status should be 'delivered' after all items delivered",
    retrievedShipment.order.status,
    "delivered",
  );
}
