/**
 * Test the successful soft deletion of an administrator promotion request by a super administrator.
 *
 * This test validates that a super administrator can delete (soft-delete) an
 * administrator promotion request. The workflow involves:
 * 1. Registering a super administrator
 * 2. Creating a regular administrator account
 * 3. The regular administrator submits a promotion request
 * 4. The super administrator deletes the promotion request
 * 5. Verifying the deletion was successful
 */
export async function test_api_admin_promotion_request_delete_by_super_admin(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register and authenticate as super administrator
  const superAdminConnection: api.IConnection = { host: connection.host };
  const superAdmin = await authorize_admin_join(superAdminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IShoppingMallAdmin.IJoin,
  });
  typia.assert(superAdmin);
  // 2. Create a regular administrator account
  const regularAdminConnection: api.IConnection = { host: connection.host };
  const regularAdmin = await authorize_admin_join(regularAdminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IShoppingMallAdmin.IJoin,
  });
  typia.assert(regularAdmin);
  // 3. Regular administrator submits a promotion request
  const promotionRequest =
    await generate_random_shopping_mall_admin_admin_promotion_requests_create(
      regularAdminConnection,
      {
        body: {
          reason: RandomGenerator.paragraph({ sentences: 3 }),
        } satisfies IShoppingMallAdminPromotionRequest.ICreate,
      },
    );
  typia.assert(promotionRequest);
  // 4. Super administrator deletes the promotion request
  await api.functional.shoppingMall.admin.admin_promotion_requests.erase(
    superAdminConnection,
    {
      requestId: promotionRequest.id,
    },
  );
  // 5. Validate the deletion was successful
  // The erase endpoint returns void, so successful execution means the deletion succeeded
  TestValidator.predicate(
    "promotion request was deleted successfully by super administrator",
    true,
  );
}
