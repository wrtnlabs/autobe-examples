/**
 * Test that banned customers cannot access their order history.
 * 1. Create customer account via join endpoint
 * 2. Add products to cart
 * 3. Create an order
 * 4. Admin bans the customer account
 * 5. Banned customer attempts to access their order
 * 6. Verify 403 Forbidden response
 */
export async function test_api_order_detail_access_denied_for_banned_customer(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create admin connection and authenticate
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: "admin@test.com",
      password: "1234",
    },
  });
  // 2. Create customer connection and authenticate
  const customerConnection: api.IConnection = { host: connection.host };
  const customerAuth = await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "1234",
      display_name: RandomGenerator.name(),
    },
  });
  typia.assert(customerAuth);
  // 3. Add product to cart
  const cartItem =
    await generate_random_shopping_mall_customer_customers_me_cart_items_create(
      customerConnection,
      {},
    );
  typia.assert(cartItem);
  // 4. Create order
  const order =
    await generate_random_shopping_mall_customer_customers_me_orders_create(
      customerConnection,
      {},
    );
  typia.assert(order);
  // 5. Ban the customer account via admin
  const banResult = await api.functional.shoppingMall.admin.customers.ban(
    adminConnection,
    {
      customerId: customerAuth.id,
      body: {
        reason: "Test ban for access denial verification",
      } satisfies IShoppingMallCustomer.IBan,
    },
  );
  typia.assert(banResult);
  // 6. Verify customer status is now banned
  TestValidator.equals("customer status is banned", banResult.status, "banned");
  // 7. Verify banned customer cannot access their order (403 Forbidden)
  await TestValidator.httpError(
    "banned customer cannot access order details",
    403,
    async () =>
      await api.functional.shoppingMall.customer.orders.at(customerConnection, {
        orderId: order.id,
      }),
  );
}
