/**
 * Test administrator force-cancel override capability when a customer cancellation request is pending seller response.
 *
 * Validates the complete administrative override flow including seller product setup, customer order placement, cancellation request creation, and administrator force-cancel action. Ensures that administrators can bypass the normal cancellation workflow where sellers approve or reject customer requests.
 *
 * Special attention is given to verifying that the force-cancel action immediately changes the order item status to 'cancelled' regardless of the pending cancellation request state, and that stock restoration and customer refund occur without seller intervention.
 *
 * 1. Administrator registers and authenticates to the platform.
 * 2. Seller registers and authenticates to create products.
 * 3. Customer registers and authenticates to place orders.
 * 4. Seller creates a product with name, description, and base price.
 * 5. Customer creates a shipping address for order delivery.
 * 6. Customer adds product variant to shopping cart with quantity.
 * 7. Customer places order through checkout process.
 * 8. Customer requests cancellation for the order item (creates pending cancellation request).
 * 9. Administrator force-cancels the order item with optional reason.
 * 10. Validates order item status changed to 'cancelled' after force-cancel.
 * 11. Validates force-cancel bypassed normal cancellation workflow.
 */
export async function test_api_order_item_force_cancel_override_pending_cancellation(
  connection: api.IConnection,
): Promise<void> {
  // 1. Administrator setup
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_administrator_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    },
  });
  // 2. Seller setup
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  // 3. Customer setup
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    },
  });
  // 4. Seller creates product
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        name: RandomGenerator.paragraph({ sentences: 2 }),
        description: RandomGenerator.paragraph({ sentences: 5 }),
        base_price: typia.random<
          number & tags.Type<"uint32"> & tags.Minimum<1000>
        >(),
      },
    },
  );
  typia.assert(product);
  // 5. Customer creates shipping address
  const address = await generate_random_shopping_mall_customer_addresses_create(
    customerConnection,
    {
      body: {
        recipient_name: RandomGenerator.name(),
        phone_number: RandomGenerator.mobile(),
        street_address: RandomGenerator.paragraph({ sentences: 2 }),
        city: RandomGenerator.name(1),
        state_province: RandomGenerator.name(1),
        postal_code: RandomGenerator.alphaNumeric(5),
        country: "South Korea",
      },
    },
  );
  typia.assert(address);
  // 6. Customer adds product variant to cart
  const cartItem =
    await generate_random_shopping_mall_customer_cart_items_create(
      customerConnection,
      {
        body: {
          productVariantId: product.variants[0].id,
          quantity: typia.random<
            number & tags.Type<"int32"> & tags.Minimum<1> & tags.Maximum<5>
          >(),
        },
      },
    );
  typia.assert(cartItem);
  // 7. Customer places order (checkout)
  const order = await generate_random_shopping_mall_customer_checkout(
    customerConnection,
    {
      body: {
        shopping_mall_customer_address_id: address.id,
        payment_token: typia.random<string>(),
      },
    },
  );
  typia.assert(order);
  // Get the first order item
  const orderItem = order.items[0];
  typia.assert(orderItem);
  // 8. Customer requests cancellation (creates pending cancellation request)
  const cancellationRequest =
    await generate_random_shopping_mall_customer_orders_items_cancellation_create(
      customerConnection,
      {
        body: {
          reason: RandomGenerator.paragraph({ sentences: 3 }),
        },
        params: {
          orderId: order.id,
          itemId: orderItem.id,
        },
      },
    );
  typia.assert(cancellationRequest);
  // Validate cancellation request is in pending status
  TestValidator.equals(
    "cancellation request status is pending",
    cancellationRequest.status,
    "pending",
  );
  // 9. Administrator force-cancels the order item
  const forceCancelledItem =
    await api.functional.shoppingMall.administrator.orders.items.force_cancel.forceCancel(
      adminConnection,
      {
        orderId: order.id,
        itemId: orderItem.id,
        body: {
          reason: "Administrator override - policy violation",
        } satisfies IShoppingMallOrderItem.IForceCancelRequest,
      },
    );
  typia.assert(forceCancelledItem);
  // 10. Validate order item status changed to 'cancelled'
  TestValidator.equals(
    "order item status is cancelled after force-cancel",
    forceCancelledItem.status,
    "cancelled",
  );
  // 11. Validate force-cancel bypassed normal cancellation workflow
  TestValidator.predicate(
    "force-cancel succeeded with pending cancellation request",
    forceCancelledItem.status === "cancelled",
  );
}
