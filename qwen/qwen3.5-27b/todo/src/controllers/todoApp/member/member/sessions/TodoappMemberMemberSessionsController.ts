import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageITodoAppMemberSession } from "../../../../../api/structures/IPageITodoAppMemberSession";
import { ITodoAppMemberSession } from "../../../../../api/structures/ITodoAppMemberSession";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { getTodoAppMemberMemberSessionsSessionId } from "../../../../../providers/getTodoAppMemberMemberSessionsSessionId";
import { patchTodoAppMemberMemberSessions } from "../../../../../providers/patchTodoAppMemberMemberSessions";

@Controller("/todoApp/member/member/sessions")
export class TodoappMemberMemberSessionsController {
  /**
   * Retrieve a paginated list of session records for the authenticated member with optional filtering and sorting.
   *
   * This endpoint allows members to view their login session history, including IP addresses, login URLs, and session timestamps. Sessions are filtered to show only those belonging to the authenticated user. The response includes both active and expired sessions, with an indicator showing whether each session is currently active.
   *
   * Filtering options include session status (active/expired), date ranges for session creation, and IP address or URL pattern matching. Sorting is available by creation date, expiration date, or network details. Results are paginated using cursor-based navigation for efficient handling of large session histories.
   *
   * @param connection
   * @param body Search criteria including session status filter, creation date range, IP address patterns, URL patterns, and pagination parameters.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query todo_app_member_sessions table for the
     *   authenticated member's sessions.
   *
   * 1. Retrieve current member ID from active session context
   * 2. Apply filtering on:
   *    - Status (active vs expired based on expired_at vs current time)
   *    - Date range (created_at between start and end dates)
   *    - IP address pattern matching
   *    - Href/referrer URL patterns
   * 3. Apply sorting on:
   *    - created_at (default: newest first)
   *    - expired_at
   *    - ip or href (alphabetical)
   * 4. Apply cursor-based pagination with page size limits
   * 5. Return session summaries with id, ip, href, referrer, created_at, expired_at, and is_active flag
   * 6. Exclude member_id from response (already known from context)
   *
   * Error handling:
   * - Return 401 if no active session exists
   * - Return empty list if no sessions found matching criteria
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: ITodoAppMemberSession.IRequest,
  ): Promise<IPageITodoAppMemberSession.ISummary> {
    try {
      return await patchTodoAppMemberMemberSessions({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific member session by its unique identifier.
   *
   * This endpoint returns complete session details including the IP address used during login, the URL where authentication occurred, the referrer page, session creation timestamp, and expiration timestamp. Sessions are private and isolated per user.
   *
   * Authentication is required to access this endpoint. Users can only retrieve their own session information. Attempts to access another user's session are rejected with a forbidden error.
   *
   * The session ID is a UUID that uniquely identifies each authentication session. This endpoint is useful for session management, security auditing, and monitoring active login sessions.
   *
   * @param connection
   * @param sessionId Unique identifier of the member session to retrieve (global scope).
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query todo_app_member_sessions table for the
     *   session with matching id.
   *
   * Validate that the authenticated member owns this session by checking todo_app_member_id matches the current user's ID. Reject with 403 Forbidden if ownership validation fails.
   *
   * Return the complete session record including id, todo_app_member_id, ip, href, referrer, created_at, and expired_at fields.
   *
   * Handle edge cases:
   * - Session not found: return 404 Not Found
   * - Session belongs to another user: return 403 Forbidden
   * - Session already expired: still return the record (for audit purposes)
   *
   * Ensure authentication middleware validates the request has a valid session before processing.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppMemberSession> {
    try {
      return await getTodoAppMemberMemberSessionsSessionId({
        member,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
