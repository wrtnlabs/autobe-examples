import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { ITodoAppMember } from "../../../../api/structures/ITodoAppMember";
import { postTodoAppAuthMemberJoin } from "../../../../providers/postTodoAppAuthMemberJoin";
import { postTodoAppAuthMemberLogin } from "../../../../providers/postTodoAppAuthMemberLogin";
import { postTodoAppAuthMemberRefresh } from "../../../../providers/postTodoAppAuthMemberRefresh";

@Controller("/todoApp/auth/member")
export class TodoappAuthMemberController {
  /**
   * Register a new member account with email and password credentials.
   *
   * This operation creates a new authenticated user account in the todo_app_members table. The email address must be unique and not already associated with an existing account. Upon successful registration, the member is immediately authenticated and can access their private todos and profile.
   *
   * **Validation Requirements**:
   * - Email must be unique across all members
   * - Password must be provided and cannot be empty
   * - Both email and password are required fields
   *
   * **Account Creation**:
   * - The email field serves as the primary login credential
   * - Password is hashed using BCrypt algorithm for security
   * - Display name is optional and can be set later
   * - Account is created with current timestamp for created_at and updated_at fields
   *
   * **Authentication Flow**:
   * - Upon successful registration, JWT access and refresh tokens are generated
   * - A session record is created in todo_app_member_sessions
   * - The member can immediately access todo functionality without additional login
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Registration credentials for new member account
     * @x-autobe-authorization-type join
     * @x-autobe-authorization-actor member
     * @x-autobe-specification 1. Validate request body contains email and
     *   password fields. 2. Check if email already exists in todo_app_members
     *   table (unique constraint). 3. If email exists, return 409 Conflict
     *   error. 4. Hash the password using BCrypt algorithm. 5. Insert new
     *   record into todo_app_members table with email, password_hash, and
     *   current timestamp for created_at/updated_at. 6. Generate JWT access
     *   token and refresh token for the new member. 7. Create session record in
     *   todo_app_member_sessions table. 8. Return ITodoAppMember.IAuthorized
     *   with tokens.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoAppMember.IJoin,
  ): Promise<ITodoAppMember.IAuthorized> {
    try {
      return await postTodoAppAuthMemberJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate a member with existing email and password credentials.
   *
   * This operation validates member credentials against the todo_app_members table and grants access to the todo application. The email must match an existing account and the password must be correct. Upon successful authentication, the member can access their private todos and profile.
   *
   * **Authentication Requirements**:
   * - Email must match an existing account in the system
   * - Password must match the stored hash for the email
   * - Account must not be soft deleted
   *
   * **Session Management**:
   * - A new session is created in todo_app_member_sessions table
   * - Session includes IP address, href, and optional referrer for security tracking
   * - Session remains active until logout or account deletion
   * - Session is validated on every authenticated request
   *
   * **Access Control**:
   * - Upon successful login, member gains access to their own todos
   * - Member can view, create, edit, complete, and delete their todos
   * - Member can view and edit their own profile
   * - All access is isolated to the authenticated member's data only
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Login credentials for existing member account
     * @x-autobe-authorization-type login
     * @x-autobe-authorization-actor member
     * @x-autobe-specification 1. Validate request body contains email and
     *   password fields. 2. Query todo_app_members table for matching email
     *   address. 3. If no member found with the email, return 401 Unauthorized
     *   error. 4. Compare provided password with stored password_hash using
     *   BCrypt verification. 5. If password doesn't match, return 401
     *   Unauthorized error. 6. Check if member account is soft deleted
     *   (deleted_at is not null). 7. If account is deleted, return 401
     *   Unauthorized error. 8. Generate JWT access token and refresh token. 9.
     *   Create session record in todo_app_member_sessions with IP, href, and
     *   referrer if available. 10. Return ITodoAppMember.IAuthorized with
     *   tokens.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoAppMember.ILogin,
  ): Promise<ITodoAppMember.IAuthorized> {
    try {
      return await postTodoAppAuthMemberLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Renew authentication tokens for an existing member session.
   *
   * This operation allows members to extend their authentication session without re-entering credentials. The refresh token is validated against the todo_app_member_sessions table to ensure the session is still active and valid.
   *
   * **Token Renewal**:
   * - Validates the provided refresh token against active sessions
   * - Generates new access and refresh tokens
   * - Updates session expiration timestamp
   * - Maintains the same session context
   *
   * **Session Validation**:
   * - Refresh token must be valid and not expired
   * - Associated session must exist in todo_app_member_sessions
   * - Member account must not be deleted
   * - Session must not have been terminated by logout
   *
   * **Security Considerations**:
   * - Refresh tokens have a longer expiration than access tokens
   * - Each refresh operation updates the session expiration
   * - Invalid or expired refresh tokens result in 401 Unauthorized
   * - Members must log in again if their session is terminated
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token for session renewal
     * @x-autobe-authorization-type refresh
     * @x-autobe-authorization-actor member
     * @x-autobe-specification 1. Validate the refresh token from request body.
     *   2. Verify the refresh token is valid and not expired. 3. Query
     *   todo_app_member_sessions table to find the associated session. 4. If
     *   session not found or expired, return 401 Unauthorized error. 5. Verify
     *   the member account still exists and is not deleted. 6. Generate new JWT
     *   access token and refresh token. 7. Update the session record with new
     *   expiration timestamp. 8. Return ITodoAppMember.IAuthorized with new
     *   tokens.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: ITodoAppMember.IRefresh,
  ): Promise<ITodoAppMember.IAuthorized> {
    try {
      return await postTodoAppAuthMemberRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
