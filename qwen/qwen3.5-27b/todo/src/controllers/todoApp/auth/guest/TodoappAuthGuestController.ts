import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { ITodoAppGuest } from "../../../../api/structures/ITodoAppGuest";
import { postTodoAppAuthGuestJoin } from "../../../../providers/postTodoAppAuthGuestJoin";
import { postTodoAppAuthGuestRefresh } from "../../../../providers/postTodoAppAuthGuestRefresh";

@Controller("/todoApp/auth/guest")
export class TodoappAuthGuestController {
  /**
   * Register a new guest user or activate an existing guest session using device fingerprint.
   *
   * This operation allows unauthenticated visitors to create a temporary guest account identified by their device fingerprint. The guest can then access the todo application without email/password credentials. If a guest with the same device fingerprint already exists, their session is reactivated.
   *
   * The guest identity is stored in the todo_app_guests table with the deviceFingerprint field. Session tokens are managed in the todo_app_guest_sessions table with access and refresh token support.
   *
   * No authentication is required to call this endpoint since it is the entry point for unauthenticated users.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Guest registration request containing device fingerprint identifier
     * @x-autobe-authorization-type join
     * @x-autobe-authorization-actor guest
     * @x-autobe-specification 1. Extract deviceFingerprint from request body 2.
     *   Check if guest with this deviceFingerprint already exists in
     *   todo_app_guests table 3. If exists, update lastActiveAt timestamp; if
     *   not, create new guest record with current timestamp 4. Generate JWT
     *   access token and refresh token with guest identity 5. Create session
     *   record in todo_app_guest_sessions with tokens and expiration 6. Return
     *   tokens in IAuthorized response format
   *
   * Edge cases:
   * - Handle duplicate device fingerprints gracefully by reusing existing guest
   * - Ensure tokens have appropriate expiration times
   * - Validate deviceFingerprint format if constraints exist
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoAppGuest.IJoin,
  ): Promise<ITodoAppGuest.IAuthorized> {
    try {
      return await postTodoAppAuthGuestJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh the guest's authentication tokens to extend their session.
   *
   * This operation allows guest users to obtain new access and refresh tokens using their existing valid refresh token. This extends the guest's session without requiring re-registration.
   *
   * The refresh process validates the existing refresh token against the todo_app_guest_sessions table, generates new token pairs, and updates the session record with the new tokens and expiration times.
   *
   * No authentication is required since the refresh token itself serves as proof of prior authentication.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Token refresh request containing valid refresh token
     * @x-autobe-authorization-type refresh
     * @x-autobe-authorization-actor guest
     * @x-autobe-specification 1. Extract refreshToken from request body 2.
     *   Validate refresh token signature and expiration 3. Look up guest
     *   session in todo_app_guest_sessions table using refresh token 4. Verify
     *   session is still valid and not expired 5. Generate new access token and
     *   refresh token pair 6. Update session record in todo_app_guest_sessions
     *   with new tokens and expiration 7. Return new tokens in IAuthorized
     *   response format
   *
   * Error handling:
   * - Return 401 if refresh token is invalid or expired
   * - Return 404 if session not found
   * - Return 403 if session has been revoked
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: ITodoAppGuest.IRefresh,
  ): Promise<ITodoAppGuest.IAuthorized> {
    try {
      return await postTodoAppAuthGuestRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
