import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageITodoAppMember } from "../../../api/structures/IPageITodoAppMember";
import { ITodoAppMember } from "../../../api/structures/ITodoAppMember";
import { getTodoAppMembersMemberId } from "../../../providers/getTodoAppMembersMemberId";
import { patchTodoAppMembers } from "../../../providers/patchTodoAppMembers";

@Controller("/todoApp/members")
export class TodoappMembersController {
  /**
   * Retrieve a paginated list of member accounts with search and filtering capabilities.
   *
   * This endpoint returns member profile summaries including email, display name, and account timestamps. Members can search for accounts by email or display name using partial matching. The list can be filtered by account status (active or deleted) and sorted by creation date, update date, email, or display name.
   *
   * By default, only active (non-deleted) members are returned. To include soft-deleted accounts, set the include_deleted filter to true. This is useful for administrative purposes to review account deletion history.
   *
   * All member data is private and accessible only to authenticated users. The password hash is never included in responses for security reasons.
   *
   * @param connection
   * @param body Search criteria including email and display name filters, account status filter, date range filters, sorting options, and pagination parameters.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query todo_app_members table with pagination and filtering support.
   *
   * Apply search filters on email and display_name fields using case-insensitive partial matching.
   *
   * Filter by account status: active (deleted_at IS NULL) or deleted (deleted_at IS NOT NULL).
   *
   * Filter by date ranges: created_at and updated_at for account creation and modification tracking.
   *
   * Support sorting by: created_at (default, descending), updated_at, email, display_name.
   *
   * Return cursor-based pagination for large result sets with metadata (total count, page size, current page).
   *
   * Exclude password_hash from all responses for security.
   *
   * Default behavior excludes soft-deleted members unless explicitly requested via include_deleted flag.
   *
   * Apply data isolation: only authenticated members can access this endpoint (no guest access).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: ITodoAppMember.IRequest,
  ): Promise<IPageITodoAppMember.ISummary> {
    try {
      return await patchTodoAppMembers({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves the complete profile information for a specific member account.
   *
   * This endpoint returns full member profile details including display name, email address, and account timestamps. Members can only access their own profile information due to strict data isolation policies. The endpoint is used for profile viewing and display purposes within the application.
   *
   * Authentication is required to access this endpoint. The system validates that the requesting member is authorized to view the requested profile, ensuring users cannot access other members' data.
   *
   * @param connection
   * @param memberId Unique identifier of the member account to retrieve (global scope).
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query the todo_app_members table for a single member record by UUID primary key.
   *
   * 1. Extract memberId from path parameter and validate UUID format
   * 2. Query todo_app_members WHERE id = memberId AND deleted_at IS NULL
   * 3. If no active record found, return 404 Not Found
   * 4. Verify the authenticated member's ID matches the requested memberId (data isolation enforcement)
   * 5. If IDs don't match, return 403 Forbidden
   * 6. Return full member record excluding password_hash field for security
   * 7. Include: id, email, display_name, created_at, updated_at
   *
   * Error handling:
   * - 404 if member not found or account is soft-deleted
   * - 403 if member attempts to access another user's profile
   * - 401 if not authenticated
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":memberId")
  public async at(
    @TypedParam("memberId")
    memberId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppMember> {
    try {
      return await getTodoAppMembersMemberId({
        memberId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
