import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IMultiUserTodoMember } from "../../../../api/structures/IMultiUserTodoMember";
import { postMultiUserTodoAuthMemberJoin } from "../../../../providers/postMultiUserTodoAuthMemberJoin";
import { postMultiUserTodoAuthMemberLogin } from "../../../../providers/postMultiUserTodoAuthMemberLogin";
import { postMultiUserTodoAuthMemberRefresh } from "../../../../providers/postMultiUserTodoAuthMemberRefresh";

@Controller("/multiUserTodo/auth/member")
export class MultiusertodoAuthMemberController {
  /**
   * Register a new member account in the multi-user todo application. This operation creates a new member record in the multi_user_todo_members table with the provided email address, password hash, and display name.
   *
   * The email field serves as the unique identifier for authentication and must not already exist in the system. The password is hashed using BCrypt algorithm before storage in the password_hash column for security. The display_name is stored as the user's public identification name shown in the application interface.
   *
   * Upon successful registration, a new member account is created with created_at and updated_at timestamps set to the current time. The deleted_at field remains null, indicating an active account. The member can then proceed to login using the registered email and password credentials.
   *
   * This operation is designated for the member actor and generates authentication tokens that allow immediate access to protected resources without requiring a separate login step.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Registration information for new member account including email, password, and display name
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Implementation steps:
   * 1. Validate request body: email must be valid format and unique (check against multi_user_todo_members table), password must meet security requirements (minimum length, complexity), display_name must be provided
   * 2. Hash the password using BCrypt algorithm with appropriate salt rounds
   * 3. Create new member record in multi_user_todo_members table with: id (UUID), email, password_hash, display_name, created_at (current timestamp), updated_at (current timestamp), deleted_at (null)
   * 4. Generate JWT access token and refresh token for the new member
   * 5. Optionally create initial session record in multi_user_todo_member_sessions for audit trail
   * 6. Return IAuthorized response containing access_token, refresh_token, and token_type
   * 7. Handle errors: duplicate email returns 409 Conflict, validation errors return 400 Bad Request
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IMultiUserTodoMember.IJoin,
  ): Promise<IMultiUserTodoMember.IAuthorized> {
    try {
      return await postMultiUserTodoAuthMemberJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate a member user with email and password credentials. This operation validates the provided credentials against the multi_user_todo_members table and generates new authentication tokens upon successful verification.
   *
   * The email field is used to locate the member account in the database. The system retrieves the stored BCrypt hashed password and compares it with the provided password. The account must be active (deleted_at is null) for login to succeed. If the member has been soft-deleted, login is denied.
   *
   * Upon successful authentication, new JWT access and refresh tokens are generated. A new session record is created in multi_user_todo_member_sessions table with connection metadata including IP address, href, and referrer for security auditing. The session includes created_at and expired_at timestamps for session lifecycle management.
   *
   * This operation is designated for the member actor and the response includes tokens that enable access to protected member resources.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Login credentials including email and password
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Implementation steps:
   * 1. Validate request body: email and password must be provided
   * 2. Query multi_user_todo_members table for member with matching email and deleted_at is null
   * 3. If member not found or deleted_at is not null, return 401 Unauthorized
   * 4. Verify password by comparing provided password with stored password_hash using BCrypt comparison
   * 5. If password verification fails, return 401 Unauthorized
   * 6. Generate new JWT access token and refresh token
   * 7. Create new session record in multi_user_todo_member_sessions with: id (UUID), multi_user_todo_member_id, ip (from request), href (from request), referrer (from request), created_at (current timestamp), expired_at (calculated expiration)
   * 8. Return IAuthorized response containing access_token, refresh_token, and token_type
   * 9. Implement rate limiting to prevent brute force attacks
   * 10. Log authentication attempt for security auditing
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IMultiUserTodoMember.ILogin,
  ): Promise<IMultiUserTodoMember.IAuthorized> {
    try {
      return await postMultiUserTodoAuthMemberLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh authentication tokens for a member user. This operation validates the provided refresh token and generates new access and refresh tokens, extending the authentication session without requiring re-login with credentials.
   *
   * The refresh token is validated for authenticity, expiration, and association with an active member account. The system verifies that the refresh token corresponds to a valid session in multi_user_todo_member_sessions table and that the associated member account has not been deleted (deleted_at is null).
   *
   * Upon successful validation, new JWT access and refresh tokens are generated using token rotation strategy. The old refresh token is invalidated, and a new session record may be created or the existing session updated with new expiration timestamp. This rotation enhances security by limiting the window of opportunity for token misuse.
   *
   * This operation is designated for the member actor and requires a valid refresh token in the request body. The response includes new tokens that maintain the authenticated session for continued access to protected resources.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token for generating new authentication tokens
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Implementation steps:
   * 1. Validate request body: refresh_token must be provided
   * 2. Decode and validate the refresh token (signature, expiration, claims)
   * 3. Extract member ID from token claims
   * 4. Verify member exists in multi_user_todo_members and deleted_at is null
   * 5. Verify refresh token is valid and not expired (check against session or token blacklist)
   * 6. Generate new JWT access token and new refresh token (token rotation)
   * 7. Invalidate old refresh token (mark as used or add to blacklist)
   * 8. Optionally update or create session record in multi_user_todo_member_sessions with new expired_at
   * 9. Return IAuthorized response containing new access_token, refresh_token, and token_type
   * 10. Handle errors: invalid token returns 401 Unauthorized, expired token returns 401 Unauthorized, deleted account returns 401 Unauthorized
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IMultiUserTodoMember.IRefresh,
  ): Promise<IMultiUserTodoMember.IAuthorized> {
    try {
      return await postMultiUserTodoAuthMemberRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
