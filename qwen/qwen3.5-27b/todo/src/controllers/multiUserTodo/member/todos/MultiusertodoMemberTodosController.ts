  /**
   * Update an existing todo item's information including title, description, dates, or completion status.
   *
   * This operation allows authenticated members to modify their own todo items. The todo can be updated with a new title, description, start date, due date, or completion status. All changes are tracked in the edit history for audit purposes, except for completion status toggles which are not recorded in edit history.
   *
   * Security and ownership: Only the member who owns the todo can update it. The system verifies ownership by checking that the authenticated user's ID matches the todo's multi_user_todo_member_id field. Attempts to update another member's todo are rejected with a 403 Forbidden error.
   *
   * Edit history tracking: When a todo is updated, the system automatically creates edit history entries in the multi_user_todo_todo_edit_histories table for each field that changes (title, description, start_date, due_date). Each history entry records the field name, old value, new value, and timestamp. Completion status changes are not tracked in edit history as they represent state transitions rather than content edits.
   *
   * Atomicity guarantees: The update operation and edit history creation are performed atomically within a single database transaction. If any part of the operation fails, all changes are rolled back, ensuring data consistency. No partial updates or orphaned history entries are created.
   *
   * Related operations: Use GET /todos/{todoId} to retrieve current todo details before updating. Use GET /todos/{todoId}/history to view the complete edit history after making changes.
   *
   * @param connection
   * @param todoId Unique identifier of the todo item to update (UUID format)
   * @param body Update data for the todo item
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Update a todo item's fields for an authenticated member user.
   *
   * 1. Authentication: Verify the request includes valid authentication token and extract member ID.
   *
   * 2. Ownership verification: Query multi_user_todo_todos table for the todo with matching todoId. Verify that multi_user_todo_member_id matches the authenticated member's ID. Reject with 403 Forbidden if ownership doesn't match.
   *
   * 3. Field validation: Validate incoming update fields:
   *    - title: Required, non-empty string
   *    - description: Optional, nullable string
   *    - start_date: Optional, nullable DateTime
   *    - due_date: Optional, nullable DateTime
   *    - completed: Optional, boolean
   *
   * 4. Detect changes: Compare incoming values with current database values to determine which fields actually changed.
   *
   * 5. Atomic update transaction:
   *    - Begin database transaction
   *    - Update multi_user_todo_todos record with new field values
   *    - Set updated_at to current timestamp
   *    - For each changed field (excluding completed status), insert a new record into multi_user_todo_todo_edit_histories with:
   *      * multi_user_todo_todos_id: the todo ID
   *      * edit_timestamp: current timestamp
   *      * field_name: the field that changed (e.g., 'title', 'description', 'start_date', 'due_date')
   *      * old_value: previous value as string
   *      * new_value: new value as string
   *      * created_at: current timestamp
   *    - Commit transaction
   *
   * 6. Error handling:
   *    - If any part of the transaction fails, roll back all changes
   *    - Do not create partial edit history entries
   *    - Return appropriate error codes (404 if todo not found, 403 if not owner, 400 for validation errors)
   *
   * 7. Response: Return the updated todo entity with all current field values.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
