  /**
   * Soft delete a todo item by moving it to the user's trash.
   *
   * This operation performs a soft delete on the specified todo, marking it as deleted without permanently removing it from the database. The todo's deleted flag is set to true and the deletion timestamp is recorded. All original data including title, description, start date, due date, and completion status are preserved.
   *
   * The todo's edit history is also retained and will remain accessible when viewing the trash or if the todo is later restored. This soft delete approach enables users to recover accidentally deleted todos.
   *
   * Only the owner of the todo can delete it. The system validates that the authenticated member owns the target todo before performing the deletion. Attempting to delete another member's todo will result in a forbidden error.
   *
   * After soft deletion, the todo will no longer appear in the user's active todo list but will be visible in the trash list. The user can later restore the todo from trash or permanently delete it.
   *
   * @param connection
   * @param todoId UUID of the todo to soft delete
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Verify the authenticated member owns the target todo by checking multi_user_todo_member_id matches the session user.
   *
   * Update the todo record atomically:
   * 1. Set deleted column to true
   * 2. Set deleted_at column to current timestamp
   * 3. Keep all other fields unchanged (title, description, start_date, due_date, completed)
   *
   * The edit history in multi_user_todo_todo_edit_histories is preserved and not modified.
   *
   * Return 204 No Content on success.
   *
   * Throw 404 Not Found if todo does not exist or already permanently deleted.
   *
   * Throw 403 Forbidden if the authenticated member does not own the todo.
   *
   * This is a soft delete operation - the record remains in the database but is marked as deleted and will appear in trash list queries.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
