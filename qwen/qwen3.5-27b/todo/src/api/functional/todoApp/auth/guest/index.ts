/**
 * Register a new guest user or activate an existing guest session using device fingerprint.
 *
 * This operation allows unauthenticated visitors to create a temporary guest account identified by their device fingerprint. The guest can then access the todo application without email/password credentials. If a guest with the same device fingerprint already exists, their session is reactivated.
 *
 * The guest identity is stored in the todo_app_guests table with the deviceFingerprint field. Session tokens are managed in the todo_app_guest_sessions table with access and refresh token support.
 *
 * No authentication is required to call this endpoint since it is the entry point for unauthenticated users.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Guest registration request containing device fingerprint identifier
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor guest
 * @x-autobe-specification 1. Extract deviceFingerprint from request body 2.
 *   Check if guest with this deviceFingerprint already exists in
 *   todo_app_guests table 3. If exists, update lastActiveAt timestamp; if not,
 *   create new guest record with current timestamp 4. Generate JWT access token
 *   and refresh token with guest identity 5. Create session record in
 *   todo_app_guest_sessions with tokens and expiration 6. Return tokens in
 *   IAuthorized response format
 *
 * Edge cases:
 * - Handle duplicate device fingerprints gracefully by reusing existing guest
 * - Ensure tokens have appropriate expiration times
 * - Validate deviceFingerprint format if constraints exist
 * @path /todoApp/auth/guest/join
 * @accessor api.functional.todoApp.auth.guest.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
