/**
 * Register a new member account with email and password credentials.
 *
 * This operation creates a new authenticated user account in the todo_app_members table. The email address must be unique and not already associated with an existing account. Upon successful registration, the member is immediately authenticated and can access their private todos and profile.
 *
 * **Validation Requirements**:
 * - Email must be unique across all members
 * - Password must be provided and cannot be empty
 * - Both email and password are required fields
 *
 * **Account Creation**:
 * - The email field serves as the primary login credential
 * - Password is hashed using BCrypt algorithm for security
 * - Display name is optional and can be set later
 * - Account is created with current timestamp for created_at and updated_at fields
 *
 * **Authentication Flow**:
 * - Upon successful registration, JWT access and refresh tokens are generated
 * - A session record is created in todo_app_member_sessions
 * - The member can immediately access todo functionality without additional login
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Registration credentials for new member account
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor member
 * @x-autobe-specification 1. Validate request body contains email and password
 *   fields. 2. Check if email already exists in todo_app_members table (unique
 *   constraint). 3. If email exists, return 409 Conflict error. 4. Hash the
 *   password using BCrypt algorithm. 5. Insert new record into todo_app_members
 *   table with email, password_hash, and current timestamp for
 *   created_at/updated_at. 6. Generate JWT access token and refresh token for
 *   the new member. 7. Create session record in todo_app_member_sessions table.
 *   8. Return ITodoAppMember.IAuthorized with tokens.
 * @path /todoApp/auth/member/join
 * @accessor api.functional.todoApp.auth.member.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
