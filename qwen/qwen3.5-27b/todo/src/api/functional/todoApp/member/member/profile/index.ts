/**
 * Update the current authenticated member's profile information, specifically the display name.
 *
 * This endpoint allows members to modify their display name at any time. The display name is a user-friendly identifier that appears in the UI instead of the email address. Members can choose to provide a display name or leave it empty.
 *
 * The update operation automatically records the modification timestamp. Only the currently authenticated member can update their own profile - attempts to access other members' profiles are denied.
 *
 * @param props.connection
 * @param props.body Profile update payload containing the new display name. The display name can be set to a string value or null to clear it. Empty strings are not allowed.
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor member
 * @x-autobe-specification Update the current authenticated member's display
 *   name.
 *
 * 1. Verify the member is authenticated via session middleware.
 * 2. Extract the member ID from the authenticated session.
 * 3. Validate that display_name is not an empty string if provided (null is allowed).
 * 4. Update the display_name field in todo_app_members table for the authenticated member.
 * 5. Automatically update the updated_at timestamp to the current time.
 * 6. Return the updated member record with all profile fields.
 *
 * Error handling:
 * - Return 401 if member is not authenticated.
 * - Return 400 if display_name is an empty string (null is acceptable).
 * - Return 403 if member attempts to update another member's profile (should be prevented by authentication context).
 * @path /todoApp/member/member/profile
 * @accessor api.functional.todoApp.member.member.profile.update
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function update(
  connection: IConnection,
  props: update.Props,
): Promise<update.Response> {
  return true === connection.simulate
    ? update.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...update.METADATA,
          path: update.path(),
          status: null,
        },
        props.body,
      );
}
