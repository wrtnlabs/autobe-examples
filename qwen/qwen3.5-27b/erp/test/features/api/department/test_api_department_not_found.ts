/**
 * Test that attempting to retrieve a non-existent department returns a 404 error.
 * Validates proper error handling for missing resources and ensures the system
 * doesn't expose information about departments from other organizations.
 */
export async function test_api_department_not_found(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as admin
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IHrmPlatformAdmin.IJoin,
  });
  // 2. Generate an invalid UUID that doesn't exist
  const invalidDepartmentId: string & tags.Format<"uuid"> = typia.random<
    string & tags.Format<"uuid">
  >();
  // 3. Verify that attempting to retrieve non-existent department throws 404
  await TestValidator.httpError(
    "should return 404 for non-existent department",
    404,
    async () =>
      await api.functional.hrmPlatform.admin.departments.at(adminConnection, {
        departmentId: invalidDepartmentId,
      }),
  );
}
