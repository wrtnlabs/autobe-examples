export async function test_api_department_retrieve_not_found(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate member
  const memberConnection: api.IConnection = { host: connection.host };
  await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    },
  });
  // 2. Generate a non-existent department UUID
  const nonExistentDepartmentId: string & tags.Format<"uuid"> = typia.random<
    string & tags.Format<"uuid">
  >();
  // 3. Attempt to retrieve non-existent department and verify 404 error
  await TestValidator.httpError(
    "should return 404 for non-existent department",
    404,
    async () =>
      await api.functional.hrmPlatform.member.departments.at(memberConnection, {
        departmentId: nonExistentDepartmentId,
      }),
  );
}
