export async function test_api_timer_view_unauthorized_access(
  connection: api.IConnection,
): Promise<void> {
  /**
   * Test authorization enforcement by attempting to retrieve another employee's timer.
   * First member creates a timer, then second member attempts to retrieve it using the timer ID.
   * Verify that the system returns 403 Forbidden error, confirming that employees can only view their own timers.
   * This validates the organization-level data isolation and employee-specific access control.
   */
  // 1. Authenticate first member
  const firstMemberConnection: api.IConnection = { host: connection.host };
  await authorize_member_join(firstMemberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IHrmPlatformMember.IJoin,
  });
  // 2. Create a timer for first member
  const timer = await generate_random_hrm_platform_member_timers_create(
    firstMemberConnection,
    {},
  );
  typia.assert(timer);
  // 3. Authenticate second member
  const secondMemberConnection: api.IConnection = { host: connection.host };
  await authorize_member_join(secondMemberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IHrmPlatformMember.IJoin,
  });
  // 4. Attempt to access first member's timer as second member
  // This should fail with 403 Forbidden
  await TestValidator.httpError(
    "unauthorized access to another employee's timer",
    403,
    async () =>
      await api.functional.hrmPlatform.member.timers.at(
        secondMemberConnection,
        {
          timerId: timer.id,
        },
      ),
  );
}
