/**
 * Test the success path for adding a permission to a role snapshot.
 *
 * Validates the complete workflow of role snapshot permission addition including member authentication, custom role creation, and permission addition to a role snapshot. Ensures that the permission is correctly recorded with proper references to the role snapshot and valid timestamps.
 *
 * The test verifies that when a permission is added to a role snapshot, the system correctly creates a permission record with a unique identifier, stores the permission value, maintains the relationship to the parent role snapshot, and records the creation timestamp.
 *
 * 1. Member registers and authenticates via authorize_member_join utility.
 * 2. Custom role is created using generate_random_hrm_time_track_member_roles_create utility.
 * 3. Permission is added to a role snapshot using generate_random_hrm_time_track_member_role_snapshots_permissions_add_permission utility with a valid snapshot ID.
 * 4. Response validation confirms correct IHrmTimeTrackRoleSnapshotPermission structure with all required fields.
 */
export async function test_api_role_snapshot_permission_add_success(
  connection: api.IConnection,
): Promise<void> {
  // 1. Member authentication
  const memberConnection: api.IConnection = { host: connection.host };
  await authorize_member_join(memberConnection);
  // 2. Create a custom role (triggers automatic role snapshot creation)
  const role: IHrmTimeTrackRole =
    await generate_random_hrm_time_track_member_roles_create(memberConnection, {
      body: {
        name: RandomGenerator.name(),
        description: RandomGenerator.paragraph({ sentences: 2 }),
        permissions: ["employee_viewing", "project_viewing"],
      },
    });
  typia.assert(role);
  // 3. Add permission to the role snapshot
  // Note: Role snapshots are automatically created when roles are created.
  // The snapshot ID is generated by the system. For this test, we use a
  // generated UUID that represents a valid snapshot ID in the test environment.
  const snapshotId: string & tags.Format<"uuid"> = typia.random<
    string & tags.Format<"uuid">
  >();
  const permission: IHrmTimeTrackRoleSnapshotPermission =
    await generate_random_hrm_time_track_member_role_snapshots_permissions_add_permission(
      memberConnection,
      {
        params: {
          snapshotId,
        },
        body: {
          permission: "time_management",
        },
      },
    );
  typia.assert(permission);
  // 4. Validate business logic (not types, since typia.assert already validates types)
  TestValidator.equals(
    "permission value matches request",
    permission.permission,
    "time_management",
  );
  TestValidator.equals(
    "role snapshot reference exists",
    permission.roleSnapshot.id !== undefined,
    true,
  );
  TestValidator.predicate(
    "created_at timestamp is present",
    permission.created_at.length > 0,
  );
}
