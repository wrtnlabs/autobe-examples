/**
 * Test that retrieving a non-existent task snapshot returns 404 error.
 * 1. Authenticate as admin user
 * 2. Generate a random non-existent snapshot UUID
 * 3. Attempt to retrieve the snapshot
 * 4. Verify 404 error is thrown
 */
export async function test_api_task_snapshot_not_found(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin authentication
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  // 2. Generate a random non-existent snapshot UUID
  const nonExistentSnapshotId: string & tags.Format<"uuid"> = typia.random<
    string & tags.Format<"uuid">
  >();
  // 3. Verify that attempting to retrieve non-existent snapshot throws 404 error
  await TestValidator.httpError(
    "non-existent task snapshot returns 404",
    404,
    async () =>
      await api.functional.hrmPlatform.admin.task_snapshots.at(
        adminConnection,
        {
          snapshotId: nonExistentSnapshotId,
        },
      ),
  );
}
