/**
 * Test that a member can successfully retrieve a snapshot of their own employment contract.
 *
 * This test validates:
 * 1. Member authentication and organization membership
 * 2. Contract creation with various terms
 * 3. Snapshot retrieval by the authenticated member
 * 4. Snapshot data integrity and immutability
 */
export async function test_api_contract_snapshot_retrieve_by_member(
  connection: api.IConnection,
): Promise<void> {
  // 1. Member authentication
  const memberConnection: api.IConnection = { host: connection.host };
  const member = await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "1234",
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IHrmPlatformMember.IJoin,
  });
  typia.assert(member);
  // 2. Create a contract for the member's employee
  const contract = await generate_random_hrm_platform_contracts_create(
    memberConnection,
    {
      body: {
        pay_rate: typia.random<
          number & tags.Type<"uint32"> & tags.Minimum<1000>
        >(),
        pay_period: RandomGenerator.pick([
          "hourly",
          "daily",
          "weekly",
          "monthly",
        ]),
        working_hours_per_week: typia.random<
          number & tags.Type<"uint32"> & tags.Minimum<1> & tags.Maximum<60>
        >(),
        start_at: new Date().toISOString(),
      },
    },
  );
  typia.assert(contract);
  // 3. Retrieve a snapshot of the contract
  // Note: Snapshot ID is generated by the system when snapshot is created
  // For this test, we use the contract ID as a reference - actual snapshot ID
  // would be obtained from snapshot creation or listing operation
  const snapshotId: string & tags.Format<"uuid"> = typia.random<
    string & tags.Format<"uuid">
  >();
  const snapshot = await api.functional.hrmPlatform.contracts.snapshots.at(
    memberConnection,
    {
      contractId: contract.id,
      snapshotId: snapshotId,
    },
  );
  typia.assert(snapshot);
  // 4. Validate business logic - snapshot belongs to the authenticated member's contract
  TestValidator.equals(
    "snapshot belongs to correct contract",
    snapshot.contract.id,
    contract.id,
  );
  TestValidator.equals(
    "snapshot employee matches contract employee",
    snapshot.employee.id,
    contract.employee.id,
  );
  // 5. Test with contract that has specific end date
  const contractWithEndDate =
    await generate_random_hrm_platform_contracts_create(memberConnection, {
      body: {
        employee_id: contract.employee.id,
        pay_rate: typia.random<
          number & tags.Type<"uint32"> & tags.Minimum<1000>
        >(),
        pay_period: "monthly",
        working_hours_per_week: 40,
        start_at: new Date(Date.now() + 86400000).toISOString(),
        end_at: new Date(Date.now() + 86400000 * 365).toISOString(),
      } satisfies IHrmPlatformContract.ICreate,
    });
  typia.assert(contractWithEndDate);
  // 6. Retrieve snapshot for contract with end date
  const snapshotId2: string & tags.Format<"uuid"> = typia.random<
    string & tags.Format<"uuid">
  >();
  const snapshotWithEndDate =
    await api.functional.hrmPlatform.contracts.snapshots.at(memberConnection, {
      contractId: contractWithEndDate.id,
      snapshotId: snapshotId2,
    });
  typia.assert(snapshotWithEndDate);
  // 7. Validate contract with end date
  TestValidator.equals(
    "snapshot has correct end_at",
    snapshotWithEndDate.end_at,
    contractWithEndDate.end_at,
  );
  TestValidator.predicate(
    "snapshot end_at is not null",
    snapshotWithEndDate.end_at !== null,
  );
}
