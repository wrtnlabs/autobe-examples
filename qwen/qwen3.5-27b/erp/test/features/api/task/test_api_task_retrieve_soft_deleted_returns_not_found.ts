/**
 * Test that retrieving a soft-deleted task returns 404 Not Found.
 *
 * This test verifies the soft deletion behavior for tasks:
 * 1. A task is created within a project
 * 2. The task is soft-deleted (deleted_at is set)
 * 3. Attempting to retrieve the task by ID returns HTTP 404 Not Found
 * 4. Soft-deleted tasks are excluded from normal retrieval operations
 */
export async function test_api_task_retrieve_soft_deleted_returns_not_found(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as member
  const memberConnection: api.IConnection = { host: connection.host };
  await authorize_member_join(memberConnection, {});
  // 2. Create a project
  const project = await generate_random_hrm_platform_member_projects_create(
    memberConnection,
    {},
  );
  typia.assert(project);
  // 3. Create a task within the project
  const task = await generate_random_hrm_platform_member_projects_tasks_create(
    memberConnection,
    {
      params: { projectId: project.id },
      body: {},
    },
  );
  typia.assert(task);
  // 4. Soft delete the task
  await api.functional.hrmPlatform.member.tasks.erase(memberConnection, {
    taskId: task.id,
  });
  // 5. Attempt to retrieve the deleted task - should throw 404
  await TestValidator.httpError(
    "retrieving soft-deleted task returns 404",
    404,
    async () =>
      await api.functional.hrmPlatform.member.tasks.at(memberConnection, {
        taskId: task.id,
      }),
  );
}
