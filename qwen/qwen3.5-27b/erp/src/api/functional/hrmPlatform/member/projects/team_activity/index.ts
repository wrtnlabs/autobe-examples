/**
 * Retrieve comprehensive team activity statistics for a specific project, providing insights into time tracking contributions from all assigned team members.
 *
 * This operation aggregates time entry data across all employees assigned to the project through project memberships. It provides both overall project-level metrics and individual team member breakdowns, enabling project leads and managers to understand work distribution and team productivity.
 *
 * The response includes total hours logged by the entire team, per-member activity statistics showing hours contributed and timelog counts, and recent activity summaries highlighting work completed in the last week. This data helps identify active contributors, detect potential bottlenecks, and assess whether work is being distributed appropriately across the team.
 *
 * Access to this endpoint requires project view permission within the organization. Users can view team activity for any project they have permission to access, regardless of whether they are assigned as team members themselves. The operation respects project status - team activity data is available for active, completed, and archived projects, providing historical visibility into past project work.
 *
 * Related operations include GET /projects/{projectId} for project details, PATCH /projects/{projectId}/members for managing team assignments, and PATCH /timelogs for viewing individual time entries that contribute to these aggregated statistics.
 *
 * @param props.connection
 * @param props.projectId UUID of the target project to retrieve team activity statistics for
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor member
 * @x-autobe-specification Query hrm_platform_projects to validate project existence and organization context.
 *
 * Join hrm_platform_project_memberships to retrieve all team members assigned to the project, filtering out soft-deleted memberships.
 *
 * For each team member, aggregate timelog data from hrm_platform_timelogs:
 * - Sum duration (in minutes) for total hours logged
 * - Count timelogs for activity frequency
 * - Calculate average daily hours
 * - Get most recent timelog date
 *
 * Join hrm_platform_employees to retrieve employee display names and profile information.
 *
 * Apply organization context filtering - only include timelogs from the current organization.
 *
 * Filter out soft-deleted timelogs (deleted_at IS NULL).
 *
 * Calculate aggregate statistics:
 * - Total hours logged by all team members (sum of all durations / 60)
 * - Number of active team members (memberships without deleted_at)
 * - Average hours per team member
 * - Most active team member (highest total hours)
 * - Recent activity count (timelogs within last 7 days)
 *
 * Return structured response with per-member breakdown and overall project statistics.
 *
 * Handle edge cases:
 * - Project with no team members: return empty team array with zero totals
 * - Team members with no timelogs: include in response with zero hours
 * - Completed/archived projects: still return historical activity data
 * @path /hrmPlatform/member/projects/:projectId/team-activity
 * @accessor api.functional.hrmPlatform.member.projects.team_activity.getTeamActivity
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function getTeamActivity(
  connection: IConnection,
  props: getTeamActivity.Props,
): Promise<getTeamActivity.Response> {
  return true === connection.simulate
    ? getTeamActivity.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...getTeamActivity.METADATA,
          path: getTeamActivity.path(props),
          status: null,
        },
      );
}
