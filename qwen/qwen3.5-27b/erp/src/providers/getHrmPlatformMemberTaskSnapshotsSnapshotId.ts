export async function getHrmPlatformMemberTaskSnapshotsSnapshotId(props: {
  member: MemberPayload;
  snapshotId: string & tags.Format<"uuid">;
}): Promise<IHrmPlatformTaskSnapshot> {
  const snapshot =
    await MyGlobal.prisma.hrm_platform_task_snapshots.findUniqueOrThrow({
      where: { id: props.snapshotId },
      ...HrmPlatformTaskSnapshotTransformer.select(),
    });
  return await HrmPlatformTaskSnapshotTransformer.transform(snapshot);
}
