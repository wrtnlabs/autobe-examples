export async function getHrmPlatformMemberProjectsProjectId(props: {
  member: MemberPayload;
  projectId: string & tags.Format<"uuid">;
}): Promise<IHrmPlatformProject> {
  // Get the member's current organization from their employee record
  const employee = await MyGlobal.prisma.hrm_platform_employees.findFirst({
    where: {
      member_id: props.member.id,
      deleted_at: null,
    },
    select: {
      id: true,
      organization_id: true,
    },
  });
  if (employee === null) {
    throw new HttpException("You're not enrolled", 403);
  }
  // Find the project by ID with transformer select
  const project = await MyGlobal.prisma.hrm_platform_projects.findUniqueOrThrow(
    {
      where: {
        id: props.projectId,
        deleted_at: null,
      },
      ...HrmPlatformProjectTransformer.select(),
    },
  );
  // Verify the project belongs to the member's organization
  if (project.organization.id !== employee.organization_id) {
    throw new HttpException("Forbidden", 403);
  }
  return await HrmPlatformProjectTransformer.transform(project);
}
