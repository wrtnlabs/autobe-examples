import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmPlatformGuestSession } from "../../../../api/structures/IHrmPlatformGuestSession";
import { IHrmPlatformMemberSession } from "../../../../api/structures/IHrmPlatformMemberSession";
import { IPageIHrmPlatformGuestSession } from "../../../../api/structures/IPageIHrmPlatformGuestSession";
import { GuestAuth } from "../../../../decorators/GuestAuth";
import { GuestPayload } from "../../../../decorators/payload/GuestPayload";
import { getHrmPlatformGuestSessionsSessionId } from "../../../../providers/getHrmPlatformGuestSessionsSessionId";
import { patchHrmPlatformGuestSessions } from "../../../../providers/patchHrmPlatformGuestSessions";

@Controller("/hrmPlatform/guest/sessions")
export class HrmplatformGuestSessionsController {
  /**
   * Retrieve a filtered and paginated list of authentication sessions across all user types (member, admin, guest).
   *
   * This operation provides comprehensive session visibility for security monitoring and administrative auditing. Sessions represent active authentication states maintained by the system when users log in, containing connection metadata such as IP addresses, referrer URLs, and session lifecycle timestamps.
   *
   * The endpoint supports advanced filtering by session type (member/admin/guest), organization context, authentication status (active/expired), date ranges, and search capabilities on connection metadata. This enables administrators to monitor concurrent sessions, detect suspicious activity patterns, and audit user access history.
   *
   * Session records are automatically created during successful authentication and terminated when users log out or when their accounts are deleted. The system does not implement automatic session expiration based on time or inactivity, so sessions persist until explicitly terminated.
   *
   * Access to this endpoint is restricted to administrators with elevated privileges. Members can only view their own session information through dedicated profile endpoints. Guest sessions are included for security monitoring but contain minimal data due to their temporary nature.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for session list
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification Query all three session tables (hrm_platform_member_sessions, hrm_platform_admin_sessions, hrm_platform_guest_sessions) with unified filtering and pagination.
   *
   * Implementation steps:
   * 1. Validate admin authentication and organization context
   * 2. Parse request body for search filters: session type, organization ID, status (active/expired), date range, IP address, search text
   * 3. Build unified query combining results from all three session tables with type discriminator
   * 4. Apply filters: status based on expired_at null check, date range on created_at, organization filter on hrm_platform_organization_id
   * 5. Apply text search across ip, href, referrer fields
   * 6. Apply pagination with cursor-based or offset-based approach
   * 7. Sort by created_at descending by default (most recent first)
   * 8. Transform results to unified IPageIHrmPlatformSession.ISummary format with session_type discriminator field
   * 9. Return paginated response with metadata
   *
   * Edge cases:
   * - Handle null expired_at for active sessions
   * - Guest sessions may have null referrer
   * - Organization filter only applies to member sessions (admin sessions organization-agnostic, guest sessions have no organization)
   * - Ensure proper type casting for unified response
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @GuestAuth()
    guest: GuestPayload,
    @TypedBody()
    body: IHrmPlatformGuestSession.IRequest,
  ): Promise<IPageIHrmPlatformGuestSession.ISummary> {
    try {
      return await patchHrmPlatformGuestSessions({
        guest,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific authenticated session by its unique identifier.
   *
   * This operation returns comprehensive session data including the authenticated member's identity, current organization context, connection metadata (IP address, href, referrer URL), and session lifecycle timestamps. Sessions represent the authenticated state of users within the HRM Platform and are scoped to specific organizations.
   *
   * The session data includes the member account reference, optional active organization for multi-organization members, the IP address from which the session was initiated, the URL where authentication occurred, the referrer URL that directed the user to the platform, the creation timestamp when the session was established, and the expiration timestamp when the session was terminated through logout or system action.
   *
   * Authorization is enforced at the session level - only the session owner (the authenticated user whose session is being queried) or administrators with elevated privileges can access session details. This ensures privacy and security of authentication state information while allowing legitimate administrative oversight.
   *
   * Related operations include session creation during login, session termination through logout, and organization context switching which updates the active organization without creating a new session. All session actions are recorded in the activity log for audit trail purposes.
   *
   * @param connection
   * @param sessionId Unique identifier of the session to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification Query the hrm_platform_member_sessions table for a session record matching the provided sessionId UUID.
   *
   * 1. Validate that the sessionId parameter is a valid UUID format
   * 2. Execute SELECT query on hrm_platform_member_sessions WHERE id = sessionId
   * 3. Join with hrm_platform_members to include member identity information
   * 4. Join with hrm_platform_organizations to include organization context if activeOrganizationId exists
   * 5. Verify authorization: only the session owner (matching authenticated user) or administrators with elevated privileges can access session details
   * 6. Return 404 if no session found with the given ID
   * 7. Return 403 if user is not authorized to view this session
   * 8. Return complete session object with all fields including member reference, organization reference, connection metadata, and timestamps
   *
   * Edge cases:
   * - Handle expired sessions (expired_at is not null) - still return session data
   * - Handle sessions without active organization context (organization_id is null)
   * - Ensure proper error messages for unauthorized access attempts
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @GuestAuth()
    guest: GuestPayload,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<IHrmPlatformMemberSession> {
    try {
      return await getHrmPlatformGuestSessionsSessionId({
        guest,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
