import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IPageIWeeklySummaryReport } from "../../../../api/structures/IPageIWeeklySummaryReport";
import { IWeeklySummaryReport } from "../../../../api/structures/IWeeklySummaryReport";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { patchHrmPlatformAdminWeeklySummaryReports } from "../../../../providers/patchHrmPlatformAdminWeeklySummaryReports";

@Controller("/hrmPlatform/admin/weekly-summary-reports")
export class HrmplatformAdminWeekly_summary_reportsController {
  /**
   * Retrieve weekly summary reports showing aggregated time tracking data organized by calendar week. This report provides week-by-week breakdowns of organizational time activity, including total hours logged, number of time entries, and employee participation metrics.
   *
   * Each weekly summary covers a complete calendar week from Monday to Sunday. The report aggregates data from all timesheets within the specified date range, providing insights into work patterns and productivity trends over time.
   *
   * Administrators can filter reports by specific projects to analyze time allocation for particular initiatives. The date range filter allows comparison of activity across different periods, supporting both short-term weekly reviews and long-term trend analysis.
   *
   * This operation requires the report:view permission. Users without this permission cannot access any organization reports. The results are scoped to the current organization context.
   *
   * Related operations include the time report endpoint for employee-level breakdowns and the project budget report for budget utilization analysis.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for weekly summary reports
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query the hrm_platform_timesheets table to aggregate weekly summary data.
   *
   * 1. Parse request body for date range (start_date, end_date), optional project_id filter, and pagination parameters.
   *
   * 2. Validate date range: ensure start_date is before end_date, both dates are valid ISO date format.
   *
   * 3. For each week within the date range (Monday to Sunday):
   *    - Calculate week start (Monday) and week end (Sunday)
   *    - Query timesheets for that week where organization_id matches current context
   *    - If project_id filter provided, join with hrm_platform_timelogs to filter by project
   *    - Aggregate: total_hours (sum of all timelog durations), timelog_count (count of timelogs), employee_count (distinct employee_ids)
   *
   * 4. Apply pagination: offset and limit on the weekly results.
   *
   * 5. Sort results by week_start_date descending (most recent week first).
   *
   * 6. Return paginated response with weekly summary data.
   *
   * Authorization: Require report:view permission. Verify user has access to the organization context.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IWeeklySummaryReport.IRequest,
  ): Promise<IPageIWeeklySummaryReport.ISummary> {
    try {
      return await patchHrmPlatformAdminWeeklySummaryReports({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
