@Controller("/hrmPlatform/admin/project-budget-reports")
export class HrmplatformAdminProject_budget_reportsController {
  /**
   * Retrieve a paginated list of project budget reports showing budget hours versus actual hours logged for projects with defined budgets.
   *
   * This operation provides comprehensive budget tracking capabilities for organization administrators. It aggregates time tracking data from all timelogs associated with each project and compares actual hours against the project's budget_hours field. Only projects that have budget_hours explicitly defined are included in the results, allowing organizations to track budget consumption for projects where effort estimation was performed.
   *
   * The report includes the percentage of budget consumed for each project, enabling administrators to identify projects that are approaching or exceeding their allocated effort estimates. Projects can be filtered by status (active, completed, archived) to focus on specific project lifecycle stages. Date range filtering allows analysis of budget consumption over specific periods.
   *
   * Security: This operation requires admin-level authorization with report viewing permissions. Only administrators can access organization-wide budget reports. The operation respects organization context isolation, ensuring users only see data from their own organization.
   *
   * Related operations: Use GET /projects/{projectId} to view detailed project information including individual timelogs. Use PATCH /timelogs to filter and list time entries by project for granular analysis.
   *
   * @param connection
   * @param body Filter criteria and pagination parameters for project budget reports
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query hrm_platform_projects table filtered by organization_id from authenticated user's context and where budget_hours is not null.
   *
   * For each project, calculate actual hours by:
   * 1. Query hrm_platform_timelogs where hrm_platform_project_id = project.id
   * 2. Sum duration (in minutes) and convert to hours (divide by 60)
   * 3. Apply date range filter if provided in request body
   * 4. Only include timelogs where deleted_at is null
   *
   * Calculate budget_consumption_percentage as: (actual_hours / budget_hours) * 100
   *
   * Apply additional filters from request body:
   * - project_status: filter by hrm_platform_projects.status
   * - date_range_start/date_range_end: filter timelogs by date field
   * - organization_id: from authenticated context (mandatory)
   *
   * Apply pagination: limit and offset from request body
   *
   * Sort results by budget_consumption_percentage descending by default, or by specified sort field.
   *
   * Return paginated response with project summary data including: project id, name, status, color_code, budget_hours, actual_hours, budget_consumption_percentage, timelog_count.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IHrmPlatformProjectBudgetReport.IRequest,
  ): Promise<IPageIHrmPlatformProjectBudgetReport.ISummary> {
    try {
      return await patchHrmPlatformAdminProjectBudgetReports({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
