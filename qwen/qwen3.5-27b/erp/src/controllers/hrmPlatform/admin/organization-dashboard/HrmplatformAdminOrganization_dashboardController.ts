import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IHrmPlatformOrganizationDashboard } from "../../../../api/structures/IHrmPlatformOrganizationDashboard";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { patchHrmPlatformAdminOrganizationDashboard } from "../../../../providers/patchHrmPlatformAdminOrganizationDashboard";

@Controller("/hrmPlatform/admin/organization-dashboard")
export class HrmplatformAdminOrganization_dashboardController {
  /**
   * Retrieve comprehensive organization-wide dashboard metrics and key performance indicators.
   *
   * This operation provides a consolidated view of organizational performance by aggregating data from employees, time tracking, projects, and timesheets. The dashboard displays critical metrics including total employee count broken down by employment type and department, total hours logged across all projects, pending timesheet approvals requiring manager attention, and budget warnings for projects exceeding their allocated hours.
   *
   * The dashboard includes a top performers section that ranks employees by hours logged during the specified period, helping identify the most active contributors. It also shows project health indicators including the count of active, completed, and archived projects, along with any projects that have exceeded their budget allocations.
   *
   * Access to this dashboard is restricted to users with administrative privileges (organization owners and managers) to ensure sensitive organizational metrics are only visible to authorized personnel. The operation supports filtering by date range to view metrics for specific periods, and all data is scoped to the currently selected organization context.
   *
   * Related operations include PATCH /employees for detailed employee management, PATCH /timesheets for timesheet oversight, and PATCH /projects for project portfolio management.
   *
   * @param connection
   * @param body Dashboard filtering criteria and date range parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query and aggregate data from multiple tables to generate organization dashboard metrics.
   *
   * 1. Employee Statistics:
   *    - Count total active employees from hrm_platform_employees
   *    - Group by employment_type (full-time, part-time, contractor, intern)
   *    - Group by department_id for department breakdown
   *    - Count inactive/deactivated employees separately
   *
   * 2. Time Tracking Statistics:
   *    - Sum total hours from hrm_platform_timelogs for the specified date range
   *    - Calculate average hours per employee
   *    - Count active timers from hrm_platform_timers
   *    - Group by project_id for project-wise breakdown
   *
   * 3. Timesheet Statistics:
   *    - Count timesheets by status (draft, submitted, approved, rejected)
   *    - Identify pending approvals (status = 'submitted')
   *    - Calculate approval rate for the period
   *
   * 4. Project Statistics:
   *    - Count active, completed, and archived projects from hrm_platform_projects
   *    - Identify projects exceeding budget_hours (compare with actual logged hours)
   *    - List top 5 projects by hours logged
   *
   * 5. Top Performers:
   *    - Query hrm_platform_timelogs grouped by employee
   *    - Rank employees by total hours logged in the period
   *    - Return top 5 employees with their names and hours
   *
   * 6. Apply organization context from authenticated user's session
   * 7. Enforce role-based access: only owners and managers can view full dashboard
   * 8. Apply date range filters from request body if provided
   * 9. Return aggregated metrics in structured response
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async overview(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IHrmPlatformOrganizationDashboard.IRequest,
  ): Promise<IHrmPlatformOrganizationDashboard> {
    try {
      return await patchHrmPlatformAdminOrganizationDashboard({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
