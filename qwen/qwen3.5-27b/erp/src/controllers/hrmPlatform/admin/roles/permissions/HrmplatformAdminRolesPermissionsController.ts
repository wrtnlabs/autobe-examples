import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmPlatformRole } from "../../../../../api/structures/IHrmPlatformRole";
import { IHrmPlatformRolePermission } from "../../../../../api/structures/IHrmPlatformRolePermission";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { deleteHrmPlatformAdminRolesRoleIdPermissionsPermissionCode } from "../../../../../providers/deleteHrmPlatformAdminRolesRoleIdPermissionsPermissionCode";
import { getHrmPlatformAdminRolesRoleIdPermissionsPermissionCode } from "../../../../../providers/getHrmPlatformAdminRolesRoleIdPermissionsPermissionCode";
import { patchHrmPlatformAdminRolesRoleIdPermissions } from "../../../../../providers/patchHrmPlatformAdminRolesRoleIdPermissions";
import { postHrmPlatformAdminRolesRoleIdPermissions } from "../../../../../providers/postHrmPlatformAdminRolesRoleIdPermissions";

@Controller("/hrmPlatform/admin/roles/:roleId/permissions")
export class HrmplatformAdminRolesPermissionsController {
  /**
   * Add a permission to a role within an organization.
   *
   * This operation allows organization owners to grant a specific permission to a custom role. When a permission is added to a role, all employees assigned to that role immediately gain the corresponding capability. This is part of the role-based access control system that enables flexible authorization management.
   *
   * The permission must be one of the predefined permission codes that define specific capabilities such as organization management, employee management, project management, time tracking approval, or report viewing. Built-in roles (Owner, Manager, Employee) cannot have their permissions modified through this operation.
   *
   * Security considerations: Only organization owners with role management permissions can add permissions to roles. The role must belong to the same organization as the requesting user. Attempting to modify built-in roles will result in an error.
   *
   * Related operations: Use PATCH /roles to list all roles in the organization, GET /roles/{roleId} to view role details including current permissions, DELETE /roles/{roleId}/permissions/{permissionId} to remove a permission, and PATCH /employees/{employeeId}/role to assign roles to employees.
   *
   * @param connection
   * @param roleId UUID of the role to add the permission to
   * @param body Permission code to add to the role
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Validate that the authenticated user is an organization owner with role management permission for the role's organization.
   *
   * Retrieve the role by roleId from hrm_platform_roles table, ensuring it belongs to the user's organization and is not deleted.
   *
   * Validate that the role is not a built-in role (is_builtin = false), as built-in roles cannot have their permissions modified.
   *
   * Validate that the permission_code in the request body is one of the allowed permission codes: 'org:manage', 'employee:manage', 'employee:view', 'project:manage', 'project:view', 'time:manage', 'time:approve', 'time:view_all', 'report:view'.
   *
   * Check if a permission assignment already exists for this role and permission_code combination in hrm_platform_role_permissions table (using the unique constraint on hrm_platform_role_id and permission_code).
   *
   * If no existing assignment, create a new record in hrm_platform_role_permissions with:
   * - hrm_platform_role_id: the roleId from path parameter
   * - permission_code: from request body
   * - created_at: current timestamp
   * - updated_at: current timestamp
   * - deleted_at: null
   *
   * Record the permission addition in hrm_platform_activity_logs with action type 'role_permission_added', including role name, permission code, and actor information.
   *
   * Return the created permission record with all fields including generated id and timestamps.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("roleId")
    roleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IHrmPlatformRolePermission.ICreate,
  ): Promise<IHrmPlatformRolePermission> {
    try {
      return await postHrmPlatformAdminRolesRoleIdPermissions({
        admin,
        roleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update the permission set for a custom role within the organization.
   *
   * This operation allows organization owners to modify which permissions are granted to a custom role. When permissions are updated, all employees assigned to that role immediately gain or lose the corresponding access rights. This provides dynamic role-based access control without requiring individual employee updates.
   *
   * **Permission Management**:
   *
   * Available permissions include organization management (edit organization settings), employee management (add, edit, or deactivate employees), employee viewing (view employee list and details), project management (create, edit, delete projects and tasks), project viewing (view projects and tasks), time management (edit or delete any employee's timelogs), time approval (approve or reject timesheets), time viewing (view all employees' timelogs and timesheets), and report viewing (view organization reports).
   *
   * **Built-in Role Protection**:
   *
   * Built-in roles (Owner, Manager, Employee) cannot have their permissions modified. This operation only accepts custom roles (is_builtin = false). Attempting to modify a built-in role will result in a 403 Forbidden error.
   *
   * **Related Operations**:
   *
   * - `GET /roles/{roleId}` retrieves the current role details with permissions
   * - `PATCH /roles/{roleId}` updates role name and description
   * - `DELETE /roles/{roleId}` deletes a custom role (if no employees assigned)
   * - `PATCH /employees/{employeeId}` assigns or changes employee role
   *
   * @param connection
   * @param roleId Unique identifier of the role to update permissions for
   * @param body New permission set for the role
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Update the permission set for a custom role in the organization.
   *
   * **Authorization**:
   * - Verify the authenticated user has organization management permission
   * - Verify the role belongs to the user's current organization
   * - Verify the role is not a built-in role (is_builtin = false)
   *
   * **Validation**:
   * - Role must exist and not be soft-deleted
   * - Role must be a custom role (built-in roles cannot be modified)
   * - All permission codes in the request must be valid
   * - Permission codes must be from the allowed set: organization_edit, employee_manage, employee_view, project_manage, project_view, time_manage, time_approve, time_view, report_view
   *
   * **Business Logic**:
   * 1. Retrieve the role by roleId
   * 2. Validate role ownership and modification eligibility
   * 3. Begin database transaction
   * 4. Delete all existing permissions for this role (soft delete with deleted_at timestamp)
   * 5. Insert new permission records for each permission code in the request
   * 6. Update the role's updated_at timestamp
   * 7. Create activity log entry recording the permission change
   * 8. Commit transaction
   *
   * **Error Handling**:
   * - Return 404 if role not found
   * - Return 403 if role is built-in or user lacks permission
   * - Return 400 if permission codes are invalid
   * - Return 400 if role belongs to different organization
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async updatePermissions(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("roleId")
    roleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IHrmPlatformRolePermission.IUpdate,
  ): Promise<IHrmPlatformRole> {
    try {
      return await patchHrmPlatformAdminRolesRoleIdPermissions({
        admin,
        roleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific permission assignment from a role within an organization.
   *
   * This operation fetches the details of a single permission that has been granted to a specific role. The permission is identified by the role's ID and the permission code string. The response includes the permission code, timestamps for when it was created and last updated, and the relationship to the parent role.
   *
   * Permission codes define specific capabilities within the system, such as 'organization_edit', 'employee_manage', 'employee_view', 'project_manage', 'project_view', 'time_manage', 'time_approve', 'time_view', and 'report_view'. Each role can have multiple permissions assigned through the hrm_platform_role_permissions junction table.
   *
   * This endpoint is primarily used by organization administrators who need to inspect the permission configuration of custom roles, verify permission assignments, or debug access control issues. The operation requires the requesting user to have appropriate authorization to view role configurations within the organization.
   *
   * The role must exist and not be soft-deleted. The permission must be currently assigned to the role (not soft-deleted). If either the role or the permission assignment does not exist, a 404 Not Found error is returned.
   *
   * Related operations include listing all permissions for a role (GET /roles/{roleId}/permissions), updating role permissions (PUT /roles/{roleId}/permissions), and listing all roles in an organization (PATCH /roles).
   *
   * @param connection
   * @param roleId Unique identifier of the role from which to retrieve the permission (global scope)
   * @param permissionCode Permission code string identifying the specific capability (e.g., 'employee_manage', 'project_view')
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query the hrm_platform_role_permissions table for a record matching the given roleId and permissionCode.
   *
   * 1. Validate that the roleId is a valid UUID and permissionCode is a non-empty string.
   * 2. Verify the requesting user has access to the organization that owns the role.
   * 3. Check that the user has permission to view role permissions (typically admin role with appropriate permissions).
   * 4. Query hrm_platform_role_permissions WHERE hrm_platform_role_id = :roleId AND permission_code = :permissionCode AND deleted_at IS NULL.
   * 5. Join with hrm_platform_roles to verify the role exists and belongs to an accessible organization.
   * 6. If no record found, return 404 Not Found.
   * 7. If role not found or deleted, return 404 Not Found.
   * 8. Return the permission object with all fields: id, hrm_platform_role_id, permission_code, created_at, updated_at.
   * 9. Handle edge cases: deleted roles, deleted permissions, insufficient permissions, invalid UUID format.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":permissionCode")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("roleId")
    roleId: string & tags.Format<"uuid">,
    @TypedParam("permissionCode")
    permissionCode: string,
  ): Promise<IHrmPlatformRolePermission> {
    try {
      return await getHrmPlatformAdminRolesRoleIdPermissionsPermissionCode({
        admin,
        roleId,
        permissionCode,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Remove a specific permission from a custom role within an organization.
   *
   * This operation allows organization owners to remove individual permissions from custom roles, thereby reducing the access level granted to employees assigned to that role. When a permission is removed from a role, all employees with that role immediately lose the associated capability.
   *
   * The permission removal is implemented as a soft delete in the hrm_platform_role_permissions junction table, maintaining an audit trail of permission changes. The deleted_at timestamp marks when the permission was removed while preserving the historical record.
   *
   * Only organization owners have the authority to modify role permissions. Built-in roles (Owner, Manager, Employee) are protected and cannot have their permissions modified under any circumstances. Attempting to remove a permission from a built-in role will result in a 405 Method Not Allowed error.
   *
   * This operation is typically used in conjunction with GET /roles/{roleId} to view current permissions before making changes, and PUT /roles/{roleId}/permissions/{permissionCode} to add permissions back if needed.
   *
   * The permission removal takes effect immediately for all employees assigned to the role. No additional action is required to propagate the change to employee access controls.
   *
   * @param connection
   * @param roleId UUID of the role from which to remove the permission (scoped to organization)
   * @param permissionCode Permission code identifier to remove from the role (e.g., 'organization_edit', 'employee_manage', 'project_view')
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Delete a permission assignment from a role in the hrm_platform_role_permissions table.
   *
   * Implementation steps:
   * 1. Verify the requesting user is authenticated as a member with organization context
   * 2. Resolve the role by roleId from hrm_platform_roles table, scoped to the user's organization
   * 3. Validate that the role exists and is not soft-deleted (deleted_at is NULL)
   * 4. Check that the role is not a built-in role (is_builtin = false). Built-in roles cannot have permissions modified.
   * 5. Query hrm_platform_role_permissions for the record matching hrm_platform_role_id = roleId AND permission_code = permissionCode AND deleted_at IS NULL
   * 6. If no matching record exists, return 404 Not Found
   * 7. Soft delete the permission assignment by setting deleted_at to current timestamp
   * 8. Record the permission removal in hrm_platform_activity_logs with action type 'role_permission_removed'
   * 9. The permission is immediately removed from all employees assigned to this role
   * 10. Return 204 No Content on successful deletion
   *
   * Validation rules:
   * - Role must belong to the authenticated user's organization
   * - Role must not be a built-in role (is_builtin = true roles are protected)
   * - Permission code must be one of the valid permission codes: 'organization_edit', 'employee_manage', 'employee_view', 'project_manage', 'project_view', 'time_manage', 'time_approve', 'time_view', 'report_view'
   * - The permission assignment must exist before deletion
   *
   * Error handling:
   * - 401 Unauthorized: User not authenticated or missing organization context
   * - 403 Forbidden: User is not an organization owner attempting to modify role permissions
   * - 404 Not Found: Role not found, role is soft-deleted, or permission assignment does not exist
   * - 405 Method Not Allowed: Attempting to modify built-in role permissions
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":permissionCode")
  public async erasePermission(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("roleId")
    roleId: string & tags.Format<"uuid">,
    @TypedParam("permissionCode")
    permissionCode: string,
  ): Promise<void> {
    try {
      return await deleteHrmPlatformAdminRolesRoleIdPermissionsPermissionCode({
        admin,
        roleId,
        permissionCode,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
