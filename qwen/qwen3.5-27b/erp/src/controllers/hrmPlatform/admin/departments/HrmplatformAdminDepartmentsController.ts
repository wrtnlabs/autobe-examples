  /**
   * Create a new department within the organization to provide structural grouping for employees.
   *
   * This operation enables organization administrators to establish organizational units that serve as logical containers for employee assignment and reporting structures. Each department must have a unique name within its organization and may optionally include a description clarifying its business purpose.
   *
   * Departments support a one-level hierarchical structure, allowing the creation of subdepartments under top-level departments. When creating a department with a parent, the system validates that the selected parent is a top-level department (not already a child department) to enforce the hierarchy constraint.
   *
   * The department creation process automatically sets the organization context based on the authenticated user's current organization. Timestamps for creation and last update are automatically managed by the system. The department becomes immediately available for employee assignments once created.
   *
   * Related operations include listing departments (PATCH /departments), viewing department details (GET /departments/{departmentId}), editing departments (PUT /departments/{departmentId}), and deleting departments (DELETE /departments/{departmentId}).
   *
   * @param connection
   * @param body Department creation information including name, optional description, and optional parent department reference
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Create a new department record in the hrm_platform_departments table.
   *
   * 1. Extract organization_id from the authenticated user's current organization context.
   * 2. Validate that the name is provided and not empty.
   * 3. Check for name uniqueness within the organization using the @@unique([hrm_platform_organization_id, name]) constraint.
   * 4. If parent_id is provided:
   *    - Verify the parent department exists and belongs to the same organization.
   *    - Validate that the parent department does not already have a parent (enforce one-level nesting).
   *    - Query: SELECT parent_id FROM hrm_platform_departments WHERE id = parent_id
   * 5. Generate UUID for the new department id.
   * 6. Set created_at and updated_at to current timestamp.
   * 7. Set deleted_at to null.
   * 8. Insert the new department record into hrm_platform_departments.
   * 9. Return the created department with all fields.
   * 10. Log the department creation in the activity log with action type, user, and department details.
   *
   * Error handling:
   * - Return 400 if name is missing or empty.
   * - Return 409 if a department with the same name already exists in the organization.
   * - Return 404 if parent_id references a non-existent department.
   * - Return 400 if parent_id references a department from a different organization.
   * - Return 400 if parent_id references a department that already has a parent (violates one-level nesting).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
