import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmPlatformContractSnapshot } from "../../../../api/structures/IHrmPlatformContractSnapshot";
import { IPageIHrmPlatformContractSnapshot } from "../../../../api/structures/IPageIHrmPlatformContractSnapshot";
import { getHrmPlatformContractsContractIdSnapshotsSnapshotId } from "../../../../providers/getHrmPlatformContractsContractIdSnapshotsSnapshotId";
import { patchHrmPlatformContractsContractIdSnapshots } from "../../../../providers/patchHrmPlatformContractsContractIdSnapshots";

@Controller("/hrmPlatform/contracts/:contractId/snapshots")
export class HrmplatformContractsSnapshotsController {
  /**
   * Retrieve a filtered and paginated list of contract snapshots for a specific employment contract.
   *
   * This operation provides access to the complete audit trail of an employment contract, showing all historical states captured when the contract was modified. Contract snapshots are immutable records that preserve the exact terms of employment agreements at specific points in time, including compensation rates, pay periods, working hours, and contract duration.
   *
   * Each snapshot captures the complete state of the contract at the moment it was created, enabling organizations to maintain accurate historical records for compliance, auditing, and legal reference purposes. The snapshots show the evolution of contract terms over the employee's tenure, documenting all changes to compensation, working conditions, and employment duration.
   *
   * Access to contract snapshots is restricted based on authorization: employees can view snapshots of their own contracts, while users with employee:view permission can view snapshots for any employee's contracts. The snapshots are read-only and cannot be modified or deleted, ensuring the integrity of the historical record.
   *
   * This operation supports advanced filtering by creation date range and pagination parameters to efficiently browse through the complete history of contract modifications. The response includes snapshot summaries optimized for list displays, with full details available through individual snapshot retrieval operations.
   *
   * @param connection
   * @param contractId The unique identifier of the contract whose snapshots to retrieve
   * @param body Search criteria and pagination parameters for contract snapshots
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query hrm_platform_contract_snapshots table for snapshots belonging to the specified contract (hrm_platform_contract_id = contractId).
   *
   * Apply filtering from request body:
   * - created_at range filter (start and end dates)
   * - Pagination parameters (page number, page size)
   * - Sorting by created_at (default: descending, most recent first)
   *
   * Join with hrm_platform_employees to verify authorization - ensure requesting user has permission to view the contract's employee records.
   *
   * Validate that the contract exists and belongs to the requesting user's organization context.
   *
   * Return paginated results with snapshot summaries including: id, start_at, end_at, pay_rate, pay_period, working_hours_per_week, created_at.
   *
   * Do not include soft-deleted contracts in results (deleted_at IS NULL on parent contract).
   *
   * Handle edge cases:
   * - Contract not found: return 404
   * - Unauthorized access: return 403
   * - Invalid pagination parameters: return 400
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedParam("contractId")
    contractId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IHrmPlatformContractSnapshot.IRequest,
  ): Promise<IPageIHrmPlatformContractSnapshot.ISummary> {
    try {
      return await patchHrmPlatformContractsContractIdSnapshots({
        contractId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific point-in-time snapshot of a contract record by its unique identifier.
   *
   * This operation provides access to historical contract states that were captured at specific moments in time for audit trail and compliance purposes. Contract snapshots preserve the complete state of employment agreements including compensation terms, pay period classification, working hours standards, and contract duration at the time the snapshot was created.
   *
   * Each snapshot is immutable once created and serves as an authoritative historical record of the employment agreement. The snapshot includes all contract terms that were in effect: start date, optional end date, pay rate, pay period frequency, and standard working hours per week. The created_at timestamp records when the snapshot was captured.
   *
   * Security and authorization are enforced based on user roles. Members can only view snapshots of their own employment contracts, while administrators with appropriate permissions can view all contract snapshots within their organization. This ensures proper data isolation and compliance with privacy requirements.
   *
   * Related operations include listing all snapshots for a contract (PATCH /contracts/{contractId}/snapshots) and viewing the current active contract (GET /contracts/{contractId}). These operations work together to provide complete visibility into contract history and current terms.
   *
   * @param connection
   * @param contractId The unique identifier of the contract that this snapshot belongs to
   * @param snapshotId The unique identifier of the contract snapshot to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query the hrm_platform_contract_snapshots table for a single snapshot record matching the provided contractId and snapshotId.
   *
   * Validation:
   * 1. Verify contractId and snapshotId are valid UUIDs
   * 2. Check that the snapshot belongs to the specified contract (hrm_platform_contract_id = contractId)
   * 3. Verify the snapshot exists (snapshotId matches the record's id)
   * 4. Enforce authorization: member can only access snapshots of their own contracts, admin can access all snapshots in their organization
   *
   * Query:
   * - SELECT * FROM hrm_platform_contract_snapshots WHERE id = snapshotId AND hrm_platform_contract_id = contractId
   * - Join with hrm_platform_contracts to verify ownership and organization context
   * - Join with hrm_platform_employees to verify employee ownership for member access
   * - Join with hrm_platform_organizations to verify organization membership
   *
   * Return the complete snapshot record with all fields: id, hrm_platform_contract_id, hrm_platform_employee_id, hrm_platform_organization_id, start_at, end_at, pay_rate, pay_period, working_hours_per_week, created_at
   *
   * Error handling:
   * - Return 404 if snapshot not found
   * - Return 403 if user lacks permission to view this snapshot
   * - Return 400 if contractId and snapshotId don't match (snapshot belongs to different contract)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":snapshotId")
  public async at(
    @TypedParam("contractId")
    contractId: string & tags.Format<"uuid">,
    @TypedParam("snapshotId")
    snapshotId: string & tags.Format<"uuid">,
  ): Promise<IHrmPlatformContractSnapshot> {
    try {
      return await getHrmPlatformContractsContractIdSnapshotsSnapshotId({
        contractId,
        snapshotId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
