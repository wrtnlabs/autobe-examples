import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmPlatformContract } from "../../../api/structures/IHrmPlatformContract";
import { IPageIHrmPlatformContract } from "../../../api/structures/IPageIHrmPlatformContract";
import { getHrmPlatformContractsContractId } from "../../../providers/getHrmPlatformContractsContractId";
import { patchHrmPlatformContracts } from "../../../providers/patchHrmPlatformContracts";
import { postHrmPlatformContracts } from "../../../providers/postHrmPlatformContracts";
import { putHrmPlatformContractsContractId } from "../../../providers/putHrmPlatformContractsContractId";

@Controller("/hrmPlatform/contracts")
export class HrmplatformContractsController {
  /**
   * Create a new employment contract for an employee within an organization.
   *
   * This operation establishes a formal employment agreement between an organization and an employee, defining compensation terms, payment frequency, and working hour expectations. The contract serves as the authoritative record of employment arrangements and is essential for payroll calculations and compliance tracking.
   *
   * Each contract is tied to a specific employee record in the hrm_platform_employees table and cannot exist independently. The contract belongs to the same organization as the employee, ensuring multi-tenancy data isolation. When creating a new contract, the system automatically manages contract versioning by ending any previously active contract for the same employee.
   *
   * The previous active contract's end_at date is set to the day before the new contract's start_at date, ensuring continuous coverage without gaps in employment terms. This versioning mechanism maintains a complete chronological history of all contracts for each employee. Historical contracts (those with end_at in the past) become immutable records for compliance and auditing purposes.
   *
   * Authorization requires the employee:manage permission, which is typically held by organization administrators and managers. Members can view their own contracts but cannot create new ones. The operation validates that the specified employee exists within the organization and that the contract terms meet business rules (e.g., end date must be on or after start date if provided).
   *
   * Related operations include GET /contracts/{contractId} to view contract details, PATCH /contracts to list all contracts with filtering, and PUT /contracts/{contractId} to edit active contracts. Soft-deleted contracts (those with deleted_at timestamp) are excluded from active queries but preserved for audit trail purposes.
   *
   * @param connection
   * @param body New contract creation information
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query hrm_platform_employees table to validate the employee exists and belongs to the requesting user's organization context.
   *
   * Check for any existing active contract for this employee (contract with end_at NULL or end_at > current timestamp).
   *
   * If an active contract exists, update it by setting end_at to the day before the new contract's start_at date. This ensures continuous coverage without gaps.
   *
   * Insert new contract record into hrm_platform_contracts table with:
   * - hrm_platform_employee_id from request
   * - hrm_platform_organization_id from employee record (for multi-tenancy)
   * - start_at from request (required)
   * - end_at from request (optional, null means ongoing)
   * - pay_rate from request (required)
   * - pay_period from request (required, enum: hourly/daily/weekly/monthly)
   * - working_hours_per_week from request (required)
   * - created_at and updated_at set to current timestamp
   * - deleted_at set to NULL
   *
   * Validate contract terms:
   * - start_at must be a valid datetime
   * - If end_at is provided, it must be >= start_at
   * - pay_rate must be positive number
   * - pay_period must be one of: hourly, daily, weekly, monthly
   * - working_hours_per_week must be positive number
   *
   * Return the created contract with all fields including generated id and timestamps.
   *
   * Handle edge cases:
   * - Employee not found: return 404 Not Found
   * - Employee belongs to different organization: return 403 Forbidden
   * - Invalid contract terms: return 400 Bad Request with specific validation errors
   * - Insufficient permissions: return 403 Forbidden
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @TypedBody()
    body: IHrmPlatformContract.ICreate,
  ): Promise<IHrmPlatformContract> {
    try {
      return await postHrmPlatformContracts({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a filtered and paginated list of employment contracts within the organization.
   *
   * This operation provides comprehensive search capabilities for browsing employee contracts including active and historical agreements. Contracts represent formal employment agreements that establish compensation terms, payment frequency, and working hour expectations between the organization and employees.
   *
   * The endpoint supports filtering by employee, contract status (active or historical), pay period type, and date ranges. Active contracts are those without an end date or with an end date in the future, while historical contracts have ended and are preserved as immutable records for compliance and auditing purposes.
   *
   * Organization administrators with employee management permissions can view all contracts across the organization. Regular employees can view only their own contracts. The response includes contract summary information optimized for list displays, showing start date, end date, pay rate, pay period, and working hours per week.
   *
   * Related operations include retrieving individual contract details via GET /contracts/{contractId}, creating new contracts via POST /contracts, and editing active contracts via PUT /contracts/{contractId}. Historical contracts with past end dates cannot be modified and serve as the authoritative employment record.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for contract listing
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query the hrm_platform_contracts table with organization scoping based on authenticated user's organization context.
   *
   * Apply filtering based on IRequest parameters:
   * - Filter by employee_id if provided (UUID)
   * - Filter by status: 'active' contracts have end_at is null OR end_at > current timestamp, 'historical' contracts have end_at < current timestamp
   * - Filter by pay_period if provided (exact match: hourly, daily, weekly, monthly)
   * - Filter by date range: start_at between from_date and to_date if provided
   * - Support text search on employee name via join with hrm_platform_employees and hrm_platform_members tables
   *
   * Apply pagination using cursor-based or offset-based approach with configurable page size (default 20, max 100).
   *
   * Apply sorting by specified field and direction (default: start_at DESC).
   *
   * For each contract, return summary fields: id, employee reference (id, name, employment type), start_at, end_at, pay_rate, pay_period, working_hours_per_week, created_at.
   *
   * Enforce authorization: admins with employee management permission see all contracts in their organization; members see only contracts for their own employee record.
   *
   * Handle edge cases: empty result sets return empty data array with pagination metadata; invalid filter combinations return valid subset; soft-deleted contracts are excluded from results.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IHrmPlatformContract.IRequest,
  ): Promise<IPageIHrmPlatformContract.ISummary> {
    try {
      return await patchHrmPlatformContracts({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific employment contract by its unique identifier.
   *
   * This operation returns comprehensive contract details including the employment start date, optional end date, compensation rate, payment frequency, and standard working hours per week. The contract represents the formal employment agreement between an organization and an employee, establishing the specific terms under which the employee works.
   *
   * Security and Access Control:
   * - Members can view their own employment contracts
   * - Users with employee:view permission can view any employee's contracts within their organization
   * - Admin actors have full access to view all contracts across the organization
   * - Access is scoped to the requesting user's organization context for multi-tenancy data isolation
   *
   * Contract Information:
   * The response includes the contract's compensation rate (pay_rate) expressed in the organization's configured currency, the payment frequency (pay_period: hourly, daily, weekly, or monthly), and the standard working hours per week that establish the full-time equivalent baseline. The start_at date marks when employment terms begin, while end_at indicates when terms conclude (null represents ongoing employment).
   *
   * Related Operations:
   * - PATCH /contracts - List and search contracts with filtering and pagination
   * - POST /contracts - Create a new employment contract
   * - PUT /contracts/{contractId} - Update an active contract's terms
   * - GET /employees/{employeeId} - View employee details including their contracts
   *
   * @param connection
   * @param contractId Unique identifier of the employment contract to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query the hrm_platform_contracts table for a single record matching the provided contractId UUID.
   *
   * Authorization Flow:
   * 1. Verify the requesting user has valid authentication and organization context
   * 2. For members: verify the contract belongs to their employee record
   * 3. For users with employee:view permission: verify the contract belongs to their organization
   * 4. For admins: allow access to any contract in the organization
   *
   * Database Query:
   * - SELECT contract record WHERE id = contractId AND deleted_at IS NULL
   * - Join with hrm_platform_employees to verify ownership if needed
   * - Join with hrm_platform_organizations to verify organization context
   * - Return 404 if contract not found or soft-deleted
   *
   * Validation:
   * - Verify contractId is a valid UUID format
   * - Check that the contract exists and is not soft-deleted
   * - Enforce organization-scoped access control
   * - Return appropriate error responses for unauthorized access attempts
   *
   * Response Construction:
   * - Map database fields to IHrmPlatformContract response type
   * - Include all contract fields: id, start_at, end_at, pay_rate, pay_period, working_hours_per_week, created_at, updated_at
   * - Include related employee and organization identifiers
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":contractId")
  public async at(
    @TypedParam("contractId")
    contractId: string & tags.Format<"uuid">,
  ): Promise<IHrmPlatformContract> {
    try {
      return await getHrmPlatformContractsContractId({
        contractId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an active employee contract with new employment terms.
   *
   * This operation allows authorized administrators to modify the terms of an active employee contract. Only contracts that are currently active (no end date or end date in the future) can be updated. Once a contract has ended (end date in the past), it becomes an immutable historical record and cannot be modified to preserve accurate employment history for compliance and auditing purposes.
   *
   * The contract can be updated with new compensation terms including pay rate, pay period frequency (hourly, daily, weekly, or monthly), and standard working hours per week. The end date can also be modified to extend or terminate the contract early. All changes are immediately reflected in the system and logged for audit trail purposes.
   *
   * Authorization requires the requesting user to have employee management permissions within the organization. The contract must belong to the same organization as the authenticated user's current context. Users cannot modify contracts for employees outside their organization or for contracts they don't have permission to manage.
   *
   * Related operations include GET /contracts/{contractId} to retrieve contract details before editing, PATCH /employees/{employeeId}/contracts to list all contracts for an employee, and POST /employees/{employeeId}/contracts to create new contracts which automatically end the previous active contract.
   *
   * @param connection
   * @param contractId Target contract's unique identifier
   * @param body Contract update information
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query the hrm_platform_contracts table by contractId (UUID). Validate that the contract exists and belongs to the authenticated user's organization context. Check that the contract is active (end_at is null or in the future) - reject update requests for past contracts with appropriate error message. Verify the user has employee management permission for the organization. Validate request body: pay_rate must be positive number, pay_period must be one of [hourly, daily, weekly, monthly], working_hours_per_week must be positive number, end_at if provided must be on or after start_at. Update the contract record with new values and set updated_at to current timestamp. Return the updated contract with all fields including employee and organization references. Log the update action in activity_logs for audit trail.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":contractId")
  public async update(
    @TypedParam("contractId")
    contractId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IHrmPlatformContract.IUpdate,
  ): Promise<IHrmPlatformContract> {
    try {
      return await putHrmPlatformContractsContractId({
        contractId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
