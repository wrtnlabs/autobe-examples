import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IHrmPlatformGuest } from "../../../../api/structures/IHrmPlatformGuest";
import { postHrmPlatformAuthGuestJoin } from "../../../../providers/postHrmPlatformAuthGuestJoin";
import { postHrmPlatformAuthGuestRefresh } from "../../../../providers/postHrmPlatformAuthGuestRefresh";

@Controller("/hrmPlatform/auth/guest")
export class HrmplatformAuthGuestController {
  /**
   * This API operation registers a new guest user or retrieves an existing guest session based on device fingerprint. Guests are unauthenticated visitors who access the platform without persistent credentials, identified solely by their device fingerprint generated from browser and device characteristics.
   *
   * The operation creates a record in the hrm_platform_guests table containing the device_fingerprint (unique identifier), ip_address for security monitoring, and user_agent string for device identification. A corresponding session is created in hrm_platform_guest_sessions with connection metadata including the IP address, href (current URL), and referrer (source URL) for tracking access patterns.
   *
   * If a guest with the same device_fingerprint already exists and has not been soft-deleted (deleted_at is null), the operation reuses that existing guest record rather than creating a duplicate. This ensures consistent tracking of returning visitors across sessions.
   *
   * The operation generates JWT access and refresh tokens for the guest session. Guest sessions are temporary and short-lived compared to authenticated member sessions, with expiration times set in the expired_at field of the session record. These tokens allow the guest to access public resources and potentially transition to a registered member account.
   *
   * Security considerations include logging all guest access attempts for monitoring, validating the device_fingerprint format, and ensuring proper session expiration to prevent indefinite anonymous access.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Guest registration information including device fingerprint and connection metadata
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification Implementation creates a new guest record in hrm_platform_guests table with device_fingerprint, ip_address, and user_agent from the request. A corresponding session record is created in hrm_platform_guest_sessions with the guest's id, connection metadata (ip, href, referrer), and expiration timestamp. The device_fingerprint must be unique - if a guest with the same fingerprint exists and is not deleted, reuse that record instead of creating a new one. Generate JWT tokens (access and refresh) for the session. Return tokens in IAuthorized response format. Set appropriate expiration times for guest sessions (typically shorter than member sessions). Log the access attempt for security monitoring.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IHrmPlatformGuest.IJoin,
  ): Promise<IHrmPlatformGuest.IAuthorized> {
    try {
      return await postHrmPlatformAuthGuestJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This API operation refreshes the authentication tokens for an existing guest session. Guest sessions are temporary and short-lived, requiring periodic token refresh to maintain access to public resources and features.
   *
   * The operation validates the provided refresh token against the hrm_platform_guest_sessions table to verify the session's authenticity and check if it has expired (comparing current time with expired_at timestamp). If the session is still valid, new access and refresh tokens are generated with updated expiration times, extending the guest's temporary access period.
   *
   * If the session has expired but the associated guest record in hrm_platform_guests has not been soft-deleted (deleted_at is null), the operation creates a new session record with fresh expiration timestamps. This allows returning guests to seamlessly continue their session without re-entering device information.
   *
   * If the guest record has been soft-deleted or no longer exists, the refresh request is rejected, requiring the guest to re-register through the join operation. This enforces retention policies and prevents access for guests who have been marked for cleanup.
   *
   * The operation updates the session's created_at timestamp to reflect the refresh time and maintains connection metadata for security monitoring purposes. Guest token refresh does not require email/password validation since guests authenticate via device fingerprint and session tokens only.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token for extending guest session
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification Implementation validates the refresh token from the request and looks up the corresponding guest session in hrm_platform_guest_sessions table. If the session exists and has not expired (expired_at is in the future), generate new access and refresh tokens with updated expiration times. If the session has expired but the guest record still exists (not soft-deleted), create a new session record with fresh expiration. If the guest record is deleted, reject the refresh request. Update the session's created_at timestamp to the current time. Return new tokens in IAuthorized response format. This allows guests to maintain temporary access without re-registering.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IHrmPlatformGuest.IRefresh,
  ): Promise<IHrmPlatformGuest.IAuthorized> {
    try {
      return await postHrmPlatformAuthGuestRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
