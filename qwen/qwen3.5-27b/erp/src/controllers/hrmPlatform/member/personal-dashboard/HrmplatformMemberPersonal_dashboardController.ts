import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IHrmPlatformPersonalDashboard } from "../../../../api/structures/IHrmPlatformPersonalDashboard";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { patchHrmPlatformMemberPersonalDashboard } from "../../../../providers/patchHrmPlatformMemberPersonalDashboard";

@Controller("/hrmPlatform/member/personal-dashboard")
export class HrmplatformMemberPersonal_dashboardController {
  /**
   * Retrieve the authenticated employee's personal dashboard with aggregated work statistics and activity overview.
   *
   * This operation provides a comprehensive personal overview including hours worked today and this week, current active timer status, recent time entries, pending timesheets awaiting approval, and assigned tasks with deadlines. The dashboard serves as the primary landing view for employees to monitor their work progress and pending actions.
   *
   * The hours worked calculations aggregate data from the hrm_platform_timelogs table, summing duration values for the specified time periods. The active timer status is determined by checking hrm_platform_timers for running sessions where stopped_at is null. Recent timelogs are retrieved from the last 7 days with project and task context.
   *
   * Pending timesheets are filtered from hrm_platform_timesheets where status equals 'submitted', indicating timesheets awaiting manager approval. Assigned tasks are retrieved from hrm_platform_tasks, filtered to only include tasks in projects where the employee is a member via hrm_platform_project_memberships.
   *
   * This endpoint requires authenticated member access within an organization context. The employee must have an active status to access their dashboard. All data is scoped to the authenticated employee's organization and respects role-based access control permissions.
   *
   * @param connection
   * @param body Optional filter parameters for personal dashboard data
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query the authenticated employee's personal dashboard data from multiple tables.
   *
   * 1. Retrieve the authenticated employee record from hrm_platform_employees using the session context.
   * 2. Calculate hours worked today:
   *    - Query hrm_platform_timelogs for the employee with date = current date
   *    - Sum duration in minutes and convert to hours (divide by 60)
   *    - Round to 2 decimal places
   * 3. Calculate hours worked this week:
   *    - Determine the current week's Monday date
   *    - Query hrm_platform_timelogs for the employee with date >= week start and date < next week start
   *    - Sum duration and convert to hours
   * 4. Check active timer status:
   *    - Query hrm_platform_timers for the employee where stopped_at IS NULL
   *    - If found, return timer details: started_at, project_id, task_id, project name, task title
   * 5. Retrieve recent timelogs (last 7 days):
   *    - Query hrm_platform_timelogs for the employee ordered by date DESC, limit 10
   *    - Include project and task information via joins
   * 6. Retrieve pending timesheets:
   *    - Query hrm_platform_timesheets for the employee where status = 'submitted'
   *    - Include week_start_date, total_hours, submitted_at
   * 7. Retrieve assigned tasks:
   *    - Query hrm_platform_tasks where assigned_employee_id = employee id AND deleted_at IS NULL
   *    - Filter to tasks in projects where employee is a member
   *    - Include status, priority, due_date, title
   *    - Order by due_date ASC, priority DESC
   *    - Limit to 10 tasks
   * 8. Return aggregated dashboard data with all sections.
   *
   * Error handling:
   * - Return 404 if employee not found in organization context
   * - Return 403 if employee status is 'deactivated'
   * - Handle null values gracefully for optional fields
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async personalDashboard(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmPlatformPersonalDashboard.IRequest,
  ): Promise<IHrmPlatformPersonalDashboard> {
    try {
      return await patchHrmPlatformMemberPersonalDashboard({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
