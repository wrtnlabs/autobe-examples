import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmPlatformEmployee } from "../../../../api/structures/IHrmPlatformEmployee";
import { IPageIHrmPlatformEmployee } from "../../../../api/structures/IPageIHrmPlatformEmployee";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getHrmPlatformMemberEmployeesEmployeeId } from "../../../../providers/getHrmPlatformMemberEmployeesEmployeeId";
import { patchHrmPlatformMemberEmployees } from "../../../../providers/patchHrmPlatformMemberEmployees";

@Controller("/hrmPlatform/member/employees")
export class HrmplatformMemberEmployeesController {
  /**
   * Retrieve a filtered and paginated list of employee records within the organization.
   *
   * This operation provides comprehensive search and filtering capabilities for employee management. Users can filter employees by department, employment type (full-time, part-time, contractor, intern), and status (active, deactivated). The search functionality supports partial name matching across employee records.
   *
   * Employee records represent the work relationship between a user and an organization. Each employee is assigned to exactly one role which determines their permissions and authorization level within the organization. Employees may optionally be assigned to a department for organizational grouping.
   *
   * The response includes essential employee information such as member identity, employment type, status, department assignment, and role. Paginated results include cursor-based pagination for efficient browsing of large employee lists.
   *
   * This operation requires employee viewing permission. Managers and organization owners have full access to view all employees across the organization regardless of department boundaries.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for employee listing
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query hrm_platform_employees table with pagination and filtering support.
   *
   * 1. Apply organization context filter based on authenticated user's current organization.
   * 2. Apply role-based access control: verify user has employee viewing permission.
   * 3. Process filter parameters:
   *    - department_id: Filter by specific department (optional)
   *    - employment_type: Filter by employment classification (full-time, part-time, contractor, intern)
   *    - status: Filter by employment status (active, deactivated)
   * 4. Process search parameter: Perform case-insensitive partial match on member display name.
   * 5. Apply sorting: Default sort by created_at descending.
   * 6. Apply pagination: Use cursor-based pagination with configurable page size (default 20, max 100).
   * 7. Join with hrm_platform_members to retrieve member display name for search.
   * 8. Join with hrm_platform_departments to include department name in response.
   * 9. Join with hrm_platform_roles to include role name in response.
   * 10. Return paginated response with employee summaries and pagination metadata.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmPlatformEmployee.IRequest,
  ): Promise<IPageIHrmPlatformEmployee.ISummary> {
    try {
      return await patchHrmPlatformMemberEmployees({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific employee within the organization.
   *
   * This operation returns comprehensive employee data including their personal information, employment details, role assignment, and department affiliation. The employee record contains the member identity link, organizational context, department assignment, role assignment, employment type classification, and current employment status.
   *
   * The response includes nested objects for related entities: the member account (with email and creation timestamp), the assigned role (with name, description, and built-in status), and the department (with name, description, and parent department reference if applicable). This provides a complete view of the employee's organizational position and permissions.
   *
   * Access to this endpoint requires the authenticated user to have employee view permission within the organization. The system enforces organization-level data isolation, ensuring users can only view employees from their own organization. Deactivated employees (status = 'deactivated') are still retrievable for historical reference, but soft-deleted employee records (deleted_at IS NOT NULL) are excluded from results.
   *
   * This operation is commonly used in conjunction with employee list operations (PATCH /employees) to view detailed information after identifying an employee from the list. It is also used when managing employee contracts, project assignments, or role changes, as these operations require the employee's full context.
   *
   * @param connection
   * @param employeeId Unique identifier of the employee to retrieve (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query the hrm_platform_employees table by the employeeId path parameter.
   *
   * 1. Validate that the employeeId is a valid UUID format
   * 2. Execute a SELECT query on hrm_platform_employees where id = employeeId AND deleted_at IS NULL
   * 3. Join with hrm_platform_members to include member information (email, created_at)
   * 4. Join with hrm_platform_roles to include role information (name, description, is_builtin)
   * 5. Join with hrm_platform_departments to include department information (name, description, parent_id) if department_id is not null
   * 6. Verify organization context from the authenticated user's session matches the employee's organization_id for data isolation
   * 7. Verify the authenticated user has employee view permission through their assigned role
   * 8. Return the employee record with all related data in a nested structure
   * 9. If no employee found or access denied, return appropriate error response
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":employeeId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("employeeId")
    employeeId: string & tags.Format<"uuid">,
  ): Promise<IHrmPlatformEmployee> {
    try {
      return await getHrmPlatformMemberEmployeesEmployeeId({
        member,
        employeeId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
