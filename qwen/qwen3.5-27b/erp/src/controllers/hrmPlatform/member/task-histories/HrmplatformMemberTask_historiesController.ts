import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmPlatformTaskHistory } from "../../../../api/structures/IHrmPlatformTaskHistory";
import { IPageIHrmPlatformTaskHistory } from "../../../../api/structures/IPageIHrmPlatformTaskHistory";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getHrmPlatformMemberTaskHistoriesHistoryId } from "../../../../providers/getHrmPlatformMemberTaskHistoriesHistoryId";
import { patchHrmPlatformMemberTaskHistories } from "../../../../providers/patchHrmPlatformMemberTaskHistories";

@Controller("/hrmPlatform/member/task-histories")
export class HrmplatformMemberTask_historiesController {
  /**
   * Retrieve a filtered and paginated list of task history records showing status changes across tasks.
   *
   * This operation provides comprehensive search capabilities for viewing task status transitions. Each history entry documents when a task status changed, what the previous status was, what the new status is, and which member made the change. This audit trail is automatically maintained by the system whenever task statuses are modified.
   *
   * The task history is read-only and cannot be modified, updated, or deleted. These records serve as an immutable audit trail that provides accountability and visibility into how tasks progress through their lifecycle. Managers and team members can review history to understand task evolution and decision-making patterns.
   *
   * Supports filtering by task ID, date range, status values, and the member who made changes. Results are paginated with configurable page sizes and sorted by creation date in descending order by default. Only history entries for tasks that the requesting member has permission to view will be returned.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for task history filtering
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query hrm_platform_task_histories table with pagination and filtering support.
   *
   * Apply search filters from request body:
   * - taskId: Filter by specific task UUID (hrm_platform_task_id)
   * - dateRange: Filter by created_at date range (from/to)
   * - oldStatus: Filter by previous status value
   * - newStatus: Filter by new status value
   * - memberId: Filter by member who made the change (hrm_platform_member_id)
   *
   * Join with hrm_platform_tasks to validate task access permissions.
   * Join with hrm_platform_members to include member display information.
   *
   * Apply cursor-based pagination for large result sets.
   * Sort by created_at in descending order (newest first) by default.
   *
   * Ensure the requesting member has permission to view the associated tasks.
   * Return only history entries for tasks the member can access.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmPlatformTaskHistory.IRequest,
  ): Promise<IPageIHrmPlatformTaskHistory.ISummary> {
    try {
      return await patchHrmPlatformMemberTaskHistories({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific task history entry by its unique identifier. This endpoint provides access to the immutable audit trail that documents task status changes throughout the task lifecycle.
   *
   * Each task history entry captures the complete transition information: the exact timestamp when the status change occurred, the previous status value, the new status value, and which member performed the modification. This creates a permanent, unalterable record of task evolution that supports accountability and workflow analysis.
   *
   * Access to task history is controlled by task viewing permissions. Users can only view history entries for tasks they have permission to access. The history entries are read-only and cannot be modified or deleted after creation, ensuring the integrity of the audit trail.
   *
   * This operation is typically used after retrieving a task to examine its complete progression through different statuses. It provides visibility into decision-making patterns and helps teams understand how work flows through their processes.
   *
   * @param connection
   * @param historyId Unique identifier of the task history entry to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query the hrm_platform_task_histories table for a single record matching the provided historyId UUID.
   *
   * 1. Validate the historyId parameter is a valid UUID format
   * 2. Verify the authenticated user has permission to view the associated task (join with hrm_platform_tasks to check task access)
   * 3. Perform a SELECT query on hrm_platform_task_histories WHERE id = historyId
   * 4. Join with hrm_platform_tasks to verify task access permissions
   * 5. Join with hrm_platform_members to include member information (display name, etc.)
   * 6. Return the task history entry with all fields: id, hrm_platform_task_id, hrm_platform_member_id, old_status, new_status, created_at
   * 7. If no record found, return 404 Not Found
   * 8. If user lacks permission to view the associated task, return 403 Forbidden
   *
   * The operation must enforce organization context isolation - users can only access history entries within their organization scope.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":historyId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("historyId")
    historyId: string & tags.Format<"uuid">,
  ): Promise<IHrmPlatformTaskHistory> {
    try {
      return await getHrmPlatformMemberTaskHistoriesHistoryId({
        member,
        historyId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
