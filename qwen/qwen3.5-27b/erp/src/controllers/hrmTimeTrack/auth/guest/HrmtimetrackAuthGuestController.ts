import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IHrmTimeTrackGuest } from "../../../../api/structures/IHrmTimeTrackGuest";
import { postHrmTimeTrackAuthGuestJoin } from "../../../../providers/postHrmTimeTrackAuthGuestJoin";
import { postHrmTimeTrackAuthGuestRefresh } from "../../../../providers/postHrmTimeTrackAuthGuestRefresh";

@Controller("/hrmTimeTrack/auth/guest")
export class HrmtimetrackAuthGuestController {
  /**
   * Accept a guest invitation and create an account for the invited email address.
   *
   * This operation allows unregistered guests to accept organization invitations by creating a new account. The guest provides their email address and invitation token, which are validated against the hrm_time_track_guests table. The invitation must have status 'pending' and not be expired (expires_at must be in the future).
   *
   * Upon successful validation, the system creates a new user account in hrm_time_track_members, a user profile in hrm_time_track_user_profiles, and an employee record in hrm_time_track_employees linking the user to the inviting organization with the pre-assigned role from the invitation. The guest invitation status is updated to 'accepted' to prevent reuse.
   *
   * A guest session is created in hrm_time_track_guest_sessions with the client's IP address, current page URL (href), and referrer for security tracking. JWT access and refresh tokens are generated and returned to enable authenticated access during the invitation acceptance workflow.
   *
   * This operation is associated with the guest actor. The invitation token ensures only the intended recipient can accept the invitation.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Guest invitation acceptance request containing email address and invitation token.
     * @x-autobe-authorization-type join
     * @x-autobe-authorization-actor guest
     * @x-autobe-specification Implement guest invitation acceptance and account
     *   creation flow.
   *
   * 1. Validate the invitation token from the request body
   * 2. Query hrm_time_track_guests table to find the invitation by email and token
   * 3. Verify invitation status is 'pending' and expires_at is in the future
   * 4. Verify the invitation's organization and role exist and are valid
   * 5. Create a new user account (hrm_time_track_members table) with the invited email
   * 6. Create a user profile (hrm_time_track_user_profiles table) linked to the new user
   * 7. Create an employee record (hrm_time_track_employees table) linking the user to the organization with the assigned role
   * 8. Update the guest invitation status to 'accepted' and set updated_at timestamp
   * 9. Create a guest session record (hrm_time_track_guest_sessions) with current IP, href, and expiration
   * 10. Generate JWT tokens (access token, refresh token) and return in IAuthorized response
   *
   * Error handling:
   * - Return 404 if invitation not found
   * - Return 400 if invitation status is not 'pending'
   * - Return 400 if invitation has expired (expires_at < now)
   * - Return 400 if email is already registered
   * - Return 500 for database or token generation failures
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IHrmTimeTrackGuest.IJoin,
  ): Promise<IHrmTimeTrackGuest.IAuthorized> {
    try {
      return await postHrmTimeTrackAuthGuestJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh guest session tokens to extend access during the invitation acceptance workflow.
   *
   * This operation allows guests to renew their JWT tokens without re-authenticating. The guest provides their current refresh token, which is validated against the hrm_time_track_guest_sessions table. The session must exist and not be expired (expired_at must be in the future).
   *
   * The system verifies that the linked guest invitation in hrm_time_track_guests is still valid (status is 'pending' or 'accepted', not expired). Upon successful validation, the guest session's expired_at timestamp is updated to extend the session validity period.
   *
   * New JWT access and refresh tokens are generated with updated expiration times and returned to the client. This allows guests to maintain authenticated access throughout the invitation acceptance process without interruption.
   *
   * This operation is associated with the guest actor. The refresh token ensures only valid sessions can be extended.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Guest token refresh request containing the current refresh token.
     * @x-autobe-authorization-type refresh
     * @x-autobe-authorization-actor guest
     * @x-autobe-specification Implement guest session token refresh flow.
   *
   * 1. Validate the refresh token from the request body
   * 2. Decode the refresh token to extract guest session ID and email
   * 3. Query hrm_time_track_guest_sessions table to find the session by ID
   * 4. Verify the session exists and expired_at is in the future
   * 5. Query hrm_time_track_guests table using the session's guest_id to verify the invitation
   * 6. Verify the invitation status is 'pending' or 'accepted' (not expired)
   * 7. Update the guest session's expired_at to extend the session validity
   * 8. Generate new JWT tokens (access token, refresh token) with updated expiration
   * 9. Return the new tokens in IAuthorized response
   *
   * Error handling:
   * - Return 401 if refresh token is invalid or expired
   * - Return 404 if guest session not found
   * - Return 400 if guest session has expired (expired_at < now)
   * - Return 400 if linked invitation is expired or deleted
   * - Return 500 for token generation failures
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IHrmTimeTrackGuest.IRefresh,
  ): Promise<IHrmTimeTrackGuest.IAuthorized> {
    try {
      return await postHrmTimeTrackAuthGuestRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
