import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IHrmTimeTrackEffectivePermission } from "../../../../api/structures/IHrmTimeTrackEffectivePermission";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getHrmTimeTrackMemberEffectivePermissions } from "../../../../providers/getHrmTimeTrackMemberEffectivePermissions";

@Controller("/hrmTimeTrack/member/effective-permissions")
export class HrmtimetrackMemberEffective_permissionsController {
  /**
   * Retrieves the effective permissions for the currently authenticated member within their selected organization context.
   *
   * This endpoint returns the list of permission codes granted to the member through their assigned role. The permissions determine what actions the member can perform within the organization, including organization management, employee management, project management, time tracking, and reporting capabilities.
   *
   * The effective permissions are calculated based on the member's employee record and the role assigned to that employee. If the member has no employee record in the organization or no role assigned, an empty permission list is returned.
   *
   * @param connection
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Retrieve the current authenticated member's
     *   effective permissions from their role assignment.
   *
   * 1. Extract member_id from the authentication session token.
   * 2. Extract organization_id from the organization context in the session.
   * 3. Query hrm_time_track_employees to find the employee record matching member_id and organization_id.
   * 4. If no employee record exists, return empty permissions array.
   * 5. If employee has no role assigned (role_id is null), return empty permissions array.
   * 6. Query hrm_time_track_role_permissions using the employee's role_id to get all permission codes.
   * 7. Return the list of permission strings.
   *
   * Error handling:
   * - If member_id is not found in session, return 401 Unauthorized.
   * - If organization_id is not found in session, return 400 Bad Request.
   * - If employee record is soft-deleted (deleted_at is not null), return empty permissions array.
   * - If role is soft-deleted, return empty permissions array.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @MemberAuth()
    member: MemberPayload,
  ): Promise<IHrmTimeTrackEffectivePermission> {
    try {
      return await getHrmTimeTrackMemberEffectivePermissions({
        member,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
