import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmTimeTrackRole } from "../../../../api/structures/IHrmTimeTrackRole";
import { IPageIHrmTimeTrackRole } from "../../../../api/structures/IPageIHrmTimeTrackRole";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { deleteHrmTimeTrackMemberRolesRoleId } from "../../../../providers/deleteHrmTimeTrackMemberRolesRoleId";
import { getHrmTimeTrackMemberRolesRoleId } from "../../../../providers/getHrmTimeTrackMemberRolesRoleId";
import { patchHrmTimeTrackMemberRoles } from "../../../../providers/patchHrmTimeTrackMemberRoles";
import { postHrmTimeTrackMemberRoles } from "../../../../providers/postHrmTimeTrackMemberRoles";
import { putHrmTimeTrackMemberRolesRoleId } from "../../../../providers/putHrmTimeTrackMemberRolesRoleId";

@Controller("/hrmTimeTrack/member/roles")
export class HrmtimetrackMemberRolesController {
  /**
   * Create a new custom role within the authenticated user's organization.
   *
   * This operation allows organization owners to define custom roles with specific permission combinations. Each role must have a unique name within the organization. The role is immediately available for assignment to employees after creation. Built-in roles (Owner, Manager, Employee) cannot be created through this API as they are automatically provisioned when an organization is created.
   *
   * Role creation requires organization owner permissions. The system validates that the role name is unique within the organization and that all requested permissions are valid. Upon successful creation, the role receives a unique identifier and timestamps are automatically recorded.
   *
   * @param connection
   * @param body Role creation data including name, optional description, and list of permission codes to grant to this role.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Create a new custom role record in hrm_time_track_roles table.
   *
   * 1. Extract organization ID from authenticated user's context (token/claims)
   * 2. Validate user has organization_management permission for the target organization
   * 3. Validate role name is not empty and does not already exist for this organization (check @@unique constraint)
   * 4. Validate all permission codes in the request against allowed values: organization_management, employee_management, employee_viewing, project_management, project_viewing, time_management, timesheet_approval, time_viewing_all, report_viewing
   * 5. Insert new role record with:
   *    - id: generate UUID
   *    - hrm_time_track_organization_id: from auth context
   *    - name: from request
   *    - description: from request (nullable)
   *    - is_builtin: false (custom roles only via this API)
   *    - created_at: current timestamp
   *    - updated_at: current timestamp
   *    - deleted_at: null
   * 6. For each permission in request, insert corresponding hrm_time_track_role_permissions record:
   *    - id: generate UUID
   *    - hrm_time_track_role_id: newly created role id
   *    - permission: permission code
   *    - created_at: current timestamp
   * 7. Return the created role with associated permissions
   * 8. Handle errors: duplicate name (409), invalid permissions (400), insufficient permissions (403)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmTimeTrackRole.ICreate,
  ): Promise<IHrmTimeTrackRole> {
    try {
      return await postHrmTimeTrackMemberRoles({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and list roles within the organization with filtering and pagination.
   *
   * This operation retrieves a paginated list of roles available in the organization. Users can filter roles by name, built-in status, and other criteria. The endpoint supports sorting and cursor-based pagination for efficient browsing of large role sets. Only active (non-deleted) roles are returned by default.
   *
   * Role permissions include viewing role details, assigned permissions, and usage statistics. Organization owners and users with appropriate permissions can access this endpoint to manage role assignments and review permission structures.
   *
   * @param connection
   * @param body Search criteria for role listing including name filter, built-in status filter, sorting preferences, and pagination parameters.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query hrm_time_track_roles table with organization scoping.
   *
   * 1. Filter by hrm_time_track_organization_id from authenticated user's organization context
   * 2. Exclude soft-deleted roles (deleted_at IS NULL) unless explicitly requested
   * 3. Apply search filters from request body:
   *    - name: partial match using ILIKE or trigram similarity
   *    - is_builtin: exact match for built-in vs custom roles
   *    - has_description: filter roles with or without descriptions
   * 4. Apply sorting from request body (default: created_at DESC)
   * 5. Apply pagination (cursor-based or offset-based) from request body
   * 6. Join with hrm_time_track_role_permissions to count permissions per role (optional)
   * 7. Return paginated response with role summaries
   *
   * Validation:
   * - Ensure user has permission to view roles in their organization
   * - Validate pagination parameters (page size limits, cursor format)
   * - Handle empty result sets gracefully
   *
   * Edge cases:
   * - No roles exist: return empty page with metadata
   * - Search term too short: return all roles or minimum length validation
   * - Invalid cursor: return first page with error or warning
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmTimeTrackRole.IRequest,
  ): Promise<IPageIHrmTimeTrackRole.ISummary> {
    try {
      return await patchHrmTimeTrackMemberRoles({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves a single role definition by its unique identifier.
   *
   * This operation returns complete role information including the role name, description, whether it is built-in or custom, and timestamps. Roles define permission sets that control what actions users can perform within an organization. Built-in roles (Owner, Manager, Employee) provide standard permission configurations, while custom roles allow organizations to create specialized access patterns.
   *
   * Role data includes the organization scope, creation and modification timestamps, and soft-delete status. The returned role can be used to understand permission assignments or to display role details in administrative interfaces.
   *
   * @param connection
   * @param roleId Unique identifier of the role to retrieve (global scope)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query hrm_time_track_roles table for a single record where id equals the provided roleId parameter.
   *
   * 1. Validate that roleId is a valid UUID format
   * 2. Execute SELECT query on hrm_time_track_roles with WHERE id = ?
   * 3. Return 404 Not Found if no role exists with the given ID
   * 4. Return 404 Not Found if the role is soft-deleted (deleted_at is not null)
   * 5. Join with hrm_time_track_role_permissions to include associated permissions if needed
   * 6. Return the complete role entity with all fields
   * 7. Ensure organization-scoped authorization - caller must have access to the role's organization
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":roleId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("roleId")
    roleId: string & tags.Format<"uuid">,
  ): Promise<IHrmTimeTrackRole> {
    try {
      return await getHrmTimeTrackMemberRolesRoleId({
        member,
        roleId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing role's attributes within an organization.
   *
   * This operation modifies role properties such as name and description. Built-in roles (Owner, Manager, Employee) have restricted update capabilities - their names cannot be changed, only descriptions can be modified. Custom roles can have both name and description updated. Role names must remain unique within the organization.
   *
   * Authorization requires appropriate role management permissions. The operation validates that the role exists, belongs to the current organization, and that the requested changes comply with built-in role protection rules.
   *
   * @param connection
   * @param roleId Unique identifier of the role to update (global scope)
   * @param body Update payload containing new role attributes. Name and description can be updated for custom roles. Built-in roles only allow description updates.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Update an existing role in the hrm_time_track_roles table by roleId.
   *
   * Validation Rules:
   * 1. Verify the role exists and belongs to the current organization context
   * 2. If role is built-in (is_builtin = true), only allow updating description field; name cannot be changed
   * 3. If role is custom (is_builtin = false), allow updating name and description
   * 4. Validate that the new name (if provided) is unique within the organization (check @@unique constraint on [hrm_time_track_organization_id, name])
   * 5. Prevent updating is_builtin, hrm_time_track_organization_id, created_at, deleted_at fields
   * 6. Automatically update updated_at timestamp on successful modification
   * 7. Return 404 if role not found or already soft-deleted
   * 8. Return 409 if name uniqueness constraint is violated
   * 9. Return 403 if attempting to modify built-in role name
   *
   * Implementation:
   * - Query role by id with organization context validation
   * - Apply validation rules based on is_builtin flag
   * - Update allowed fields (name, description for custom roles; description only for built-in)
   * - Set updated_at to current timestamp
   * - Return updated role entity with permissions array included
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":roleId")
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("roleId")
    roleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IHrmTimeTrackRole.IUpdate,
  ): Promise<IHrmTimeTrackRole> {
    try {
      return await putHrmTimeTrackMemberRolesRoleId({
        member,
        roleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a role from the organization by setting its deleted_at timestamp.
   *
   * This operation permanently removes a role from active use within an organization. The deletion is implemented as a soft delete, which sets the deleted_at timestamp while preserving the record for audit purposes. Built-in roles (Owner, Manager, Employee) cannot be deleted under any circumstances. Custom roles can only be deleted when no employees are currently assigned to them. If employees are using the role, the deletion request is rejected with information about which employees are affected.
   *
   * Role deletion affects permission assignments for employees who had this role. When a custom role is successfully deleted, any employees previously assigned to it must have been reassigned to a different role beforehand. The soft-deleted role remains in the database but cannot be assigned to new employees.
   *
   * @param connection
   * @param roleId UUID of the role to delete (global scope)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Implement soft delete for hrm_time_track_roles table:
   *
   * 1. Validate the role exists and belongs to the requesting organization
   * 2. Check if the role is a built-in role (is_builtin = true). If yes, reject with error: 'Built-in roles cannot be deleted'
   * 3. Query hrm_time_track_employees table to check if any employees have this role assigned (WHERE hrm_time_track_role_id = :roleId AND deleted_at IS NULL)
   * 4. If employees are found with this role, reject with error listing the affected employees
   * 5. If validation passes, set deleted_at = current timestamp
   * 6. Return 204 No Content on success
   * 7. Handle edge cases:
   *    - Role not found: return 404
   *    - Role already deleted: return 409 or 204 (idempotent)
   *    - Insufficient permissions: return 403
   *    - Built-in role deletion attempt: return 400 with specific error message
   *    - Role has assigned employees: return 400 with list of affected employee IDs
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":roleId")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("roleId")
    roleId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteHrmTimeTrackMemberRolesRoleId({
        member,
        roleId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
