import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmTimeTrackOrganization } from "../../../../../api/structures/IHrmTimeTrackOrganization";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { postHrmTimeTrackMemberOrganizationsOrganizationIdSwitch } from "../../../../../providers/postHrmTimeTrackMemberOrganizationsOrganizationIdSwitch";

@Controller("/hrmTimeTrack/member/organizations/:organizationId/switch")
export class HrmtimetrackMemberOrganizations_switchController {
  /**
   * Switch the authenticated user's organization context to a different organization they belong to without logging out.
   *
   * This operation updates the user's active organization context for all subsequent API requests. The user must be a member of the target organization to perform the switch. After switching, all data access and operations are scoped to the newly selected organization.
   *
   * The operation validates that the user belongs to the specified organization and has an active employee record within it. If validation succeeds, the session context is updated and the organization details are returned for client confirmation.
   *
   * @param connection
   * @param organizationId The UUID of the organization to switch to. The user must be a member of this organization.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification 1. Extract organizationId from path parameter and
     *   validate UUID format. 2. Verify the authenticated user has an active
     *   session with current organization context. 3. Query
     *   hrm_time_track_organizations table to find the target organization by
     *   id. 4. Validate the organization exists and is not soft-deleted
     *   (deleted_at is null). 5. Verify the authenticated user belongs to the
     *   target organization by checking hrm_time_track_members and related
     *   employee records. 6. Ensure the user has an active employee record in
     *   the target organization (status is not deactivated). 7. Update the
     *   user's session context to set the new organization_id. 8. Return the
     *   organization details including id, name, description, logo, currency,
     *   timezone, and fiscal_start_month. 9. Log the organization switch event
     *   in hrm_time_track_activity_logs for audit trail. 10. Handle errors:
     *   organization not found, user not a member, organization deleted, or
     *   invalid organization ID.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async switchContext(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("organizationId")
    organizationId: string & tags.Format<"uuid">,
  ): Promise<IHrmTimeTrackOrganization> {
    try {
      return await postHrmTimeTrackMemberOrganizationsOrganizationIdSwitch({
        member,
        organizationId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
