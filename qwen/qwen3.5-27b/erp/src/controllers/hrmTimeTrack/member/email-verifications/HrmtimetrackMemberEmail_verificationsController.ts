import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmTimeTrackMemberEmailVerification } from "../../../../api/structures/IHrmTimeTrackMemberEmailVerification";
import { IPageIHrmTimeTrackMemberEmailVerification } from "../../../../api/structures/IPageIHrmTimeTrackMemberEmailVerification";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getHrmTimeTrackMemberEmailVerificationsVerificationId } from "../../../../providers/getHrmTimeTrackMemberEmailVerificationsVerificationId";
