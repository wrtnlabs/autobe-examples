import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IHrmTimeTrackDepartmentReport } from "../../../../../api/structures/IHrmTimeTrackDepartmentReport";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { getHrmTimeTrackMemberReportsDepartments } from "../../../../../providers/getHrmTimeTrackMemberReportsDepartments";

@Controller("/hrmTimeTrack/member/reports/departments")
export class HrmtimetrackMemberReportsDepartmentsController {
  /**
   * Retrieve a hierarchical department report with employee statistics for organizational analysis.
   *
   * This endpoint returns a structured view of all departments within the organization, showing the parent-child relationships and the number of employees assigned to each department. The report supports organizational analysis by displaying workforce distribution across different business units.
   *
   * The response includes department identification (id, name, description), hierarchical structure (parent-child relationships), and employee counts for each department. Top-level departments appear at the root level, with child departments nested under their respective parents.
   *
   * This report is useful for understanding organizational structure, analyzing team sizes, and making management decisions about resource allocation across departments.
   *
   * @param connection
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query hrm_time_track_departments table to build a
     *   hierarchical department report.
   *
   * 1. Fetch all active departments (deleted_at IS NULL) for the current organization from the authenticated user's context.
   * 2. For each department, count the number of active employees (deleted_at IS NULL) assigned to it from hrm_time_track_employees table.
   * 3. Build a hierarchical tree structure by joining departments with their parent departments using parent_department_id.
   * 4. Include department id, name, description, parent_department_id (if exists), and employee_count for each department.
   * 5. Sort departments by name alphabetically within each parent level.
   * 6. Return the hierarchical structure with child departments nested under their parents.
   *
   * Authorization: Verify the authenticated user belongs to the organization and has permission to view department reports.
   *
   * Error handling: Return 404 if organization not found, 403 if user lacks permission.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async report(
    @MemberAuth()
    member: MemberPayload,
  ): Promise<IHrmTimeTrackDepartmentReport.IStatistic> {
    try {
      return await getHrmTimeTrackMemberReportsDepartments({
        member,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
