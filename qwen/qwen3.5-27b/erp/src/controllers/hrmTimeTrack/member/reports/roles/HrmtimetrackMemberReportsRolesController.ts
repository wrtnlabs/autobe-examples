import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IHrmTimeTrackRoleReport } from "../../../../../api/structures/IHrmTimeTrackRoleReport";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { getHrmTimeTrackMemberReportsRoles } from "../../../../../providers/getHrmTimeTrackMemberReportsRoles";

@Controller("/hrmTimeTrack/member/reports/roles")
export class HrmtimetrackMemberReportsRolesController {
  /**
   * Retrieve role analytics and statistics for the current organization.
   *
   * This endpoint provides aggregated insights into role distribution, permission assignments, and role usage patterns within the organization. The report includes counts of employees per role, breakdown of permissions across roles, and identification of built-in versus custom roles.
   *
   * Role reports help administrators understand their permission structure, identify potential role consolidation opportunities, and audit access control configurations. The data is scoped to the currently selected organization and reflects active roles only (excluding soft-deleted roles).
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query hrm_time_track_roles table filtered by the current organization's ID and excluding soft-deleted roles (deleted_at IS NULL).
   *
   * For each active role, compute:
   * 1. Role count: total number of active roles in the organization
   * 2. Built-in vs custom breakdown: count of is_builtin = true vs false
   * 3. Employee count per role: join with hrm_time_track_employees to count employees assigned to each role
   * 4. Permission count per role: count entries in hrm_time_track_role_permissions for each role
   * 5. Permission distribution: aggregate which permissions are most commonly assigned across roles
   *
   * Return aggregated statistics including:
   * - Total role count
   * - Built-in role count and list
   * - Custom role count and list
   * - Employee distribution across roles
   * - Most common permissions
   * - Roles with highest employee counts
   *
   * Ensure organization-scoped query using the authenticated user's current organization context. Do not include soft-deleted roles in the report.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @MemberAuth()
    member: MemberPayload,
  ): Promise<IHrmTimeTrackRoleReport> {
    try {
      return await getHrmTimeTrackMemberReportsRoles({
        member,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
