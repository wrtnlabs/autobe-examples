import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmTimeTrackTimesheetSnapshot } from "../../../../../api/structures/IHrmTimeTrackTimesheetSnapshot";
import { IPageIHrmTimeTrackTimesheetSnapshot } from "../../../../../api/structures/IPageIHrmTimeTrackTimesheetSnapshot";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { getHrmTimeTrackMemberTimesheetsTimesheetIdSnapshotsSnapshotId } from "../../../../../providers/getHrmTimeTrackMemberTimesheetsTimesheetIdSnapshotsSnapshotId";
import { patchHrmTimeTrackMemberTimesheetsTimesheetIdSnapshots } from "../../../../../providers/patchHrmTimeTrackMemberTimesheetsTimesheetIdSnapshots";

@Controller("/hrmTimeTrack/member/timesheets/:timesheetId/snapshots")
export class HrmtimetrackMemberTimesheetsSnapshotsController {
  /**
   * Retrieve the audit trail of status changes for a specific timesheet.
   *
   * This endpoint returns all snapshot records capturing the timesheet's approval workflow history, including submission, approval, and rejection events. Each snapshot records the status value, the member who performed the action, and the timestamp. Results are returned in paginated format with optional filtering by status.
   *
   * @param connection
   * @param timesheetId UUID of the timesheet to retrieve snapshots for. The timesheet must exist and belong to the requesting member's organization.
   * @param body Filtering and pagination parameters for timesheet snapshots. Includes optional status filter to narrow results to specific status values (draft, submitted, approved, rejected) and pagination configuration for result set size and cursor.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query hrm_time_track_timesheets table to verify
     *   the timesheet exists and belongs to the requesting member's
     *   organization.
   *
   * Query hrm_time_track_timesheet_snapshots table filtering by:
   * - hrm_time_track_timesheet_id = timesheetId (path parameter)
   * - Optional: status filter from request body
   *
   * Apply pagination using cursor-based or offset-based pagination from request body.
   *
   * Sort results by created_at in descending order (most recent first) by default.
   *
   * Join with hrm_time_track_members to include member information (email, display name) for the action performer.
   *
   * Return paginated response with snapshot summaries including status, member reference, and created_at timestamp.
   *
   * Validate that the timesheet exists and is not soft-deleted before returning snapshots.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("timesheetId")
    timesheetId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IHrmTimeTrackTimesheetSnapshot.IRequest,
  ): Promise<IPageIHrmTimeTrackTimesheetSnapshot.ISummary> {
    try {
      return await patchHrmTimeTrackMemberTimesheetsTimesheetIdSnapshots({
        member,
        timesheetId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific timesheet snapshot by timesheet ID and snapshot ID.
   *
   * This operation returns the complete details of a timesheet snapshot, which captures a point-in-time status change during the timesheet approval workflow. Each snapshot records the timesheet status, the member who performed the action, and the exact timestamp of the status change.
   *
   * Snapshots are immutable audit records that provide compliance and accountability for timesheet status transitions including submission, approval, and rejection events. Organizations can use this data to review the complete approval history and verify who performed each action and when it occurred.
   *
   * @param connection
   * @param timesheetId UUID of the timesheet to which this snapshot belongs. Identifies the specific timesheet whose status change is captured in this snapshot.
   * @param snapshotId UUID of the specific timesheet snapshot to retrieve. Uniquely identifies the point-in-time status change record within the timesheet's approval history.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query the hrm_time_track_timesheet_snapshots
     *   table for a record matching both the timesheet_id and the snapshot id.
   *
   * 1. Validate that the timesheetId and snapshotId parameters are valid UUIDs.
   * 2. Execute a SELECT query on hrm_time_track_timesheet_snapshots where id equals snapshotId and hrm_time_track_timesheet_id equals timesheetId.
   * 3. Verify the snapshot exists and belongs to the specified timesheet.
   * 4. Return the complete snapshot record including all fields: id, hrm_time_track_timesheet_id, hrm_time_track_member_id, status, and created_at.
   * 5. If no matching snapshot is found, return a 404 Not Found error.
   * 6. Ensure proper authorization checks verify the requesting user has permission to view timesheet snapshots for the specified timesheet.
   * 7. The snapshot data is read-only and immutable; no modifications are allowed through this endpoint.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":snapshotId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("timesheetId")
    timesheetId: string & tags.Format<"uuid">,
    @TypedParam("snapshotId")
    snapshotId: string & tags.Format<"uuid">,
  ): Promise<IHrmTimeTrackTimesheetSnapshot> {
    try {
      return await getHrmTimeTrackMemberTimesheetsTimesheetIdSnapshotsSnapshotId(
        {
          member,
          timesheetId,
          snapshotId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
