import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmTimeTrackTimesheet } from "../../../../../api/structures/IHrmTimeTrackTimesheet";
import { IHrmTimeTrackTimesheetTimelog } from "../../../../../api/structures/IHrmTimeTrackTimesheetTimelog";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { getHrmTimeTrackMemberTimesheetsTimesheetIdTimelogsTimesheetTimelogId } from "../../../../../providers/getHrmTimeTrackMemberTimesheetsTimesheetIdTimelogsTimesheetTimelogId";
import { patchHrmTimeTrackMemberTimesheetsTimesheetIdTimelogs } from "../../../../../providers/patchHrmTimeTrackMemberTimesheetsTimesheetIdTimelogs";

@Controller("/hrmTimeTrack/member/timesheets/:timesheetId/timelogs")
export class HrmtimetrackMemberTimesheetsTimelogsController {
  /**
   * Update the timelog associations for a specific timesheet by adding or removing timelogs.
   *
   * This operation allows employees to modify which timelogs are included in their draft timesheets. Timelogs can be added to include additional work entries or removed to exclude entries from the weekly submission. The operation validates that the timesheet is in draft status, as only draft timesheets can be modified. Once a timesheet is submitted or approved, timelog associations become locked and cannot be changed through this endpoint.
   *
   * @param connection
   * @param timesheetId UUID of the timesheet whose timelog associations are being updated.
   * @param body Timelog association update request containing arrays of timelog IDs to add to or remove from the timesheet.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification 1. Validate the timesheet exists and is not soft-deleted.
   * 2. Verify the timesheet status is 'draft' - reject if submitted, approved, or rejected.
   * 3. Verify the authenticated employee owns the timesheet (hrm_time_track_employee_id matches).
   * 4. For timelogs to add:
   *    - Validate each timelog exists and is not soft-deleted.
   *    - Verify each timelog belongs to the same employee as the timesheet.
   *    - Verify each timelog's date falls within the timesheet's week range (week_start_date to week_end_date).
   *    - Check if timelog is already associated with this timesheet - skip if already present.
   *    - Create new records in hrm_time_track_timesheet_timelogs junction table.
   * 5. For timelogs to remove:
   *    - Validate the association exists in hrm_time_track_timesheet_timelogs.
   *    - Delete the association records from the junction table.
   * 6. Recalculate and update the timesheet's total hours based on included timelogs.
   * 7. Update the timesheet's updated_at timestamp.
   * 8. Return the updated timesheet with its associated timelogs.
   * 9. Handle edge cases: empty add/remove arrays, duplicate timelog IDs in request, timelogs outside week range.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("timesheetId")
    timesheetId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IHrmTimeTrackTimesheet.ITimelogUpdate,
  ): Promise<IHrmTimeTrackTimesheet> {
    try {
      return await patchHrmTimeTrackMemberTimesheetsTimesheetIdTimelogs({
        member,
        timesheetId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific timelog association within a timesheet by its unique identifier.
   *
   * This operation returns detailed information about a single timelog entry that is explicitly included in a weekly timesheet for approval processing. The response includes the association metadata (when the timelog was added to the timesheet) along with the complete timelog details (date, duration, project, task, billable status, and notes).
   *
   * Access control requires the requesting user to have appropriate permissions to view the timesheet and its associated timelogs. Employees can view their own timesheet timelog associations, while users with time management permissions can view all associations within their organization.
   *
   * @param connection
   * @param timesheetId Unique identifier of the parent timesheet that contains this timelog association (global scope)
   * @param timesheetTimelogId Unique identifier of the timesheet-timelog association record (global scope)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query the hrm_time_track_timesheet_timelogs table for the record matching the provided timesheet_id and the specific timesheet-timelog association id.
   *
   * 1. Validate that the timesheet_id exists and belongs to the requesting user's organization
   * 2. Validate that the timesheetTimelogId exists and is associated with the specified timesheet
   * 3. Join with hrm_time_track_timelogs to retrieve complete timelog details
   * 4. Join with hrm_time_track_projects to include project information
   * 5. Optionally join with hrm_time_track_tasks if task_id is present
   * 6. Apply authorization checks: employee can view their own timesheet associations, users with time:view_all permission can view all
   * 7. Return the full entity with all relationships populated
   * 8. Handle cases where the timesheet or timelog has been soft deleted by returning 404
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":timesheetTimelogId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("timesheetId")
    timesheetId: string & tags.Format<"uuid">,
    @TypedParam("timesheetTimelogId")
    timesheetTimelogId: string & tags.Format<"uuid">,
  ): Promise<IHrmTimeTrackTimesheetTimelog> {
    try {
      return await getHrmTimeTrackMemberTimesheetsTimesheetIdTimelogsTimesheetTimelogId(
        {
          member,
          timesheetId,
          timesheetTimelogId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
