@Controller("/hrmTimeTrack/member/timesheets")
export class HrmtimetrackMemberTimesheetsController {
  /**
   * Creates a new draft timesheet for an employee covering a specific week period.
   *
   * This operation allows employees to create a timesheet for a given week (Monday to Sunday). The timesheet is created in draft status and automatically includes all timelogs that the employee has logged during that week period. The week is identified by its start date (Monday), and the end date (Sunday) is calculated automatically.
   *
   * A timesheet can only be created if no existing timesheet (draft, submitted, approved, or rejected) exists for the same employee and week. This ensures one timesheet per employee per week. The created timesheet can be modified by the employee until it is submitted for approval.
   *
   * @param connection
   * @param body Timesheet creation request containing the week start date (Monday) for the new timesheet. The week end date will be automatically calculated as Sunday (6 days after the start date).
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Create a new timesheet record in
     *   hrm_time_track_timesheets table with the following logic:
   *
   * 1. Validate that the authenticated user has an employee record in the organization context.
   * 2. Extract week_start_date from request body and calculate week_end_date (Sunday, 6 days after Monday).
   * 3. Check for existing timesheet with same hrm_time_track_employee_id and week_start_date combination (unique constraint).
   * 4. If exists, return 409 Conflict error.
   * 5. Create timesheet record with:
   *    - hrm_time_track_employee_id: from authenticated user's employee record
   *    - status: 'draft'
   *    - week_start_date: from request (normalized to start of day)
   *    - week_end_date: calculated (week_start_date + 6 days, end of day)
   *    - created_at, updated_at: current timestamp
   *    - hrm_time_track_member_id, approved_at, rejected_at, rejection_reason: null
   * 6. The timesheet automatically includes all timelogs from hrm_time_track_timelogs where:
   *    - hrm_time_track_employee_id matches the timesheet's employee
   *    - date falls between week_start_date and week_end_date (inclusive)
   * 7. Return the created timesheet entity with full details.
   *
   * Error handling:
   * - 400 Bad Request: Invalid date format, week_start_date not on Monday
   * - 409 Conflict: Timesheet already exists for this employee and week
   * - 403 Forbidden: User not authorized or not an employee in the organization
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmTimeTrackTimesheet.ICreate,
  ): Promise<IHrmTimeTrackTimesheet> {
    try {
      return await postHrmTimeTrackMemberTimesheets({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and list timesheets with filtering by status and date range.
   *
   * This endpoint enables employees to browse their timesheets with support for status filtering (draft, submitted, approved, rejected) and date range queries. Employees can only view their own timesheets, while users with time:approve permission can view all submitted timesheets within their organization.
   *
   * Timesheets are returned in paginated format with cursor-based pagination for efficient browsing of large result sets. The response includes summary information optimized for list displays, including week dates, status, and total hours.
   *
   * Rejected timesheets are returned to draft status for modification and resubmission. Approved timesheets have locked timelogs that cannot be edited or deleted.
   *
   * @param connection
   * @param body Search criteria for timesheets including status filter, date range, employee filter, pagination parameters, and sorting options.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query hrm_time_track_timesheets table with
     *   pagination and filtering based on request body criteria.
   *
   * Authorization: Verify the requesting user's access level. Employees can only query timesheets where hrm_time_track_employee_id matches their employee record. Users with time:approve permission can query all timesheets within their organization context.
   *
   * Filtering: Apply status filter from request body (draft, submitted, approved, rejected). Apply date range filter on week_start_date and week_end_date fields. Support filtering by employee ID for administrative views.
   *
   * Join: Left join with hrm_time_track_employees to include employee name and department information. Left join with hrm_time_track_members (approver) to include approver name when status is approved.
   *
   * Aggregation: Calculate total_hours by summing duration_seconds from related hrm_time_track_timelogs (where timelog deleted_at is null and timelog date falls within week_start_date to week_end_date).
   *
   * Pagination: Implement cursor-based pagination using week_start_date and id as composite cursor. Return pagination metadata including has_next, has_previous, and cursor values.
   *
   * Sorting: Default sort by week_start_date descending (newest first). Support custom sorting on week_start_date, status, or total_hours.
   *
   * Exclusions: Filter out timesheets where deleted_at is not null. Only return active timesheets.
   *
   * Response transformation: Map database fields to IHrmTimeTrackTimesheet.ISummary DTO. Include id, status, week_start_date, week_end_date, total_hours, employee information, and approver information (when approved).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmTimeTrackTimesheet.IRequest,
  ): Promise<IPageIHrmTimeTrackTimesheet.ISummary> {
    try {
      return await patchHrmTimeTrackMemberTimesheets({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single timesheet by its unique identifier.
   *
   * This operation returns complete timesheet details including the associated employee, approval status, week period, and approval metadata. Timesheets represent weekly collections of timelogs organized from Monday to Sunday for employee time tracking and approval workflows.
   *
   * Access Control: Employees can view their own timesheets. Users with time:approve permission can view all timesheets within their organization. The system enforces organization-level data isolation.
   *
   * Status Information: The response includes the current approval status (draft, submitted, approved, or rejected), approval timestamp and approver details if approved, and rejection reason if rejected.
   *
   * @param connection
   * @param timesheetId Unique identifier of the timesheet to retrieve (UUID format).
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query the hrm_time_track_timesheets table for a
     *   single record matching the provided timesheetId UUID.
   *
   * Authorization: Verify the requesting user has permission to view this timesheet. Employees can only view their own timesheets (where hrm_time_track_employee_id matches their employee record). Users with time:approve permission can view any timesheet in their organization.
   *
   * Query: SELECT * FROM hrm_time_track_timesheets WHERE id = {timesheetId} AND deleted_at IS NULL.
   *
   * Join: Include employee information via left join with hrm_time_track_employees on hrm_time_track_employee_id. Include approver member information via left join with hrm_time_track_members on hrm_time_track_member_id when present.
   *
   * Error handling: Return 404 Not Found if no timesheet matches the ID or if the timesheet is soft-deleted. Return 403 Forbidden if the user lacks permission to view this timesheet.
   *
   * Return the complete timesheet entity with all fields including nested employee and approver references.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":timesheetId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("timesheetId")
    timesheetId: string & tags.Format<"uuid">,
  ): Promise<IHrmTimeTrackTimesheet> {
    try {
      return await getHrmTimeTrackMemberTimesheetsTimesheetId({
        member,
        timesheetId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Updates a timesheet's properties, primarily managing status transitions in the approval workflow.
   *
   * This operation allows employees to submit draft timesheets for approval, administrators to approve or reject submitted timesheets, and employees to modify rejected timesheets back to draft status. The operation enforces strict status transition rules and validates that approved timesheets cannot be modified. When rejecting a timesheet, a rejection reason must be provided to inform the employee of issues to address before resubmission.
   *
   * @param connection
   * @param timesheetId Unique identifier of the timesheet to update (global scope).
   * @param body Timesheet update data including status transition and optional rejection reason when rejecting a submitted timesheet.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification 1. Validate timesheet exists and retrieve current
     *   record from hrm_time_track_timesheets table by id.
   *
   * 2. Check authorization: verify requesting user has permission to modify this timesheet (employee owner or time management permission).
   *
   * 3. Validate status transition rules:
   *    - draft → submitted: allowed for employee owner
   *    - submitted → approved: allowed for users with time:approve permission
   *    - submitted → rejected: allowed for users with time:approve permission, requires rejection_reason
   *    - rejected → draft: allowed for employee owner
   *    - approved → any: NOT ALLOWED (approved timesheets are locked)
   *    - Any other transitions: NOT ALLOWED
   *
   * 4. If status is transitioning to 'submitted':
   *    - Verify timesheet has at least one timelog (join with hrm_time_track_timesheet_timelogs)
   *    - Verify no other timesheet for same employee and week exists with status 'submitted' or 'approved' (check unique constraint)
   *
   * 5. If status is transitioning to 'approved':
   *    - Set approved_at to current timestamp
   *    - Set hrm_time_track_member_id to approver's member id
   *    - Lock all associated timelogs from editing
   *
   * 6. If status is transitioning to 'rejected':
   *    - Validate rejection_reason is provided and not empty
   *    - Set rejected_at to current timestamp
   *    - Timesheet automatically returns to 'draft' status for employee modification
   *
   * 7. Update the timesheet record with validated changes.
   *
   * 8. Record activity log entry for audit trail.
   *
   * 9. Return updated timesheet entity.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":timesheetId")
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("timesheetId")
    timesheetId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IHrmTimeTrackTimesheet.IUpdate,
  ): Promise<IHrmTimeTrackTimesheet> {
    try {
      return await putHrmTimeTrackMemberTimesheetsTimesheetId({
        member,
        timesheetId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a timesheet by ID.
   *
   * This operation removes a timesheet from the system. Deletion permissions depend on the user's role and the timesheet's current status. Employees can only delete their own timesheets that are in draft status. Users with time management permissions can delete any timesheet regardless of status or ownership.
   *
   * Timesheets in submitted, approved, or rejected status are protected from deletion by regular employees to maintain the integrity of the approval workflow. Only authorized administrators can remove timesheets that have progressed beyond draft status.
   *
   * The deletion is performed as a soft delete, preserving the timesheet record in the database while marking it as deleted. This maintains referential integrity and enables audit trail capabilities.
   *
   * @param connection
   * @param timesheetId Unique identifier of the timesheet to delete (global scope).
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Delete a timesheet by ID with authorization
     *   validation.
   *
   * Authorization checks:
   * 1. Verify the authenticated user is either:
   *    - The employee who owns the timesheet AND the timesheet status is 'draft'
   *    - A user with time:management permission (can delete any timesheet regardless of status)
   *
   * Validation rules:
   * - Reject deletion if employee attempts to delete another employee's timesheet
   * - Reject deletion if employee attempts to delete a timesheet with status 'submitted', 'approved', or 'rejected'
   * - Users with time:management permission bypass status restrictions
   *
   * Implementation steps:
   * 1. Fetch the timesheet by ID, including employee relationship
   * 2. Verify authorization based on rules above
   * 3. Perform soft delete by setting deleted_at to current timestamp
   * 4. If user has time:management permission, record deletion in activity log
   * 5. Return 204 No Content on success
   *
   * Error handling:
   * - 404 Not Found if timesheet doesn't exist
   * - 403 Forbidden if unauthorized deletion attempt
   * - 409 Conflict if timesheet is part of approved workflow (for non-admin users)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":timesheetId")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("timesheetId")
    timesheetId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteHrmTimeTrackMemberTimesheetsTimesheetId({
        member,
        timesheetId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
