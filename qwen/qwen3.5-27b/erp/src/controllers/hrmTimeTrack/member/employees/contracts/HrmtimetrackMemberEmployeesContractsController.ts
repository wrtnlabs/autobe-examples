  /**
   * Retrieve a paginated list of employment contracts for a specific employee with optional filtering and sorting capabilities.
   *
   * This endpoint returns all contracts associated with an employee, including both active and historical records. Contracts are displayed with their start date, end date, pay rate, pay period, working hours per week, and any associated notes. The results can be filtered by date ranges, contract status (active or ended), and sorted by various fields.
   *
   * Access control is enforced based on user permissions: employees can view only their own contracts, while users with employee view permissions can access any employee's contracts within the organization. Historical contracts are preserved and remain viewable even after the employee is deactivated.
   *
   * @param connection
   * @param employeeId UUID of the employee whose contracts are being retrieved (global scope)
   * @param body Search criteria for filtering employee contracts including date ranges, status filters, pay period, and pagination parameters.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query hrm_time_track_employee_contracts table filtering by hrm_time_track_employee_id from path parameter.
   *
   * Apply search filters from request body:
   * - Filter by start_date range if startDateFrom/startDateTo provided
   * - Filter by end_date range if endDateFrom/endDateTo provided
   * - Filter by contract status (active if end_date is null, ended if end_date is not null)
   * - Filter by pay_period if specified
   *
   * Apply sorting from request body (default: start_date descending).
   *
   * Apply pagination from request body (page, pageSize) with cursor-based pagination for large result sets.
   *
   * Join with hrm_time_track_employees to verify employee exists and enforce access control.
   *
   * Return paginated summary records with contract id, start_date, end_date, pay_rate, pay_period, working_hours_per_week, notes, created_at, updated_at.
   *
   * Handle edge cases:
   * - Return empty page if no contracts exist for employee
   * - Return 404 if employee not found
   * - Enforce soft delete filtering (exclude deleted_at is not null)
   * - Ensure only one contract marked as active (end_date is null) per employee
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
