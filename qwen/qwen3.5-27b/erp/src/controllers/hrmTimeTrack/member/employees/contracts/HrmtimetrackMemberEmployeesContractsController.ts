  /**
   * Update an employee contract's terms and conditions.
   *
   * This operation modifies an active employee contract's compensation and working conditions. You can update the pay rate, pay period (hourly/daily/weekly/monthly), working hours per week, optional notes, and extend the end date. The contract start date cannot be modified once the contract is created. Only active contracts (those without an end date or with an end date in the future) can be edited. Past contracts with end dates in the past are immutable historical records and cannot be modified.
   *
   * @param connection
   * @param employeeId UUID of the employee whose contract is being updated (scoped to employee).
   * @param contractId UUID of the contract to update (scoped to employee).
   * @param body Update payload containing editable contract fields: pay rate, pay period, working hours per week, optional end date extension, and notes. Start date cannot be modified.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification 1. Validate that employeeId and contractId exist and belong to the same organization as the requesting user.
   * 2. Verify the requesting user has employee management permissions for the target employee.
   * 3. Fetch the contract by contractId and verify it belongs to the specified employeeId.
   * 4. Check if the contract is active (end_date is null or in the future). Reject with 400 if the contract has ended.
   * 5. Validate request body fields:
   *    - pay_rate: must be positive number
   *    - pay_period: must be one of hourly, daily, weekly, monthly
   *    - working_hours_per_week: must be positive number
   *    - end_date: if provided, must be after start_date
   *    - notes: optional string
   *    - start_date: must be rejected if provided (immutable field)
   * 6. Execute update query on hrm_time_track_employee_contracts table, excluding start_date and created_at fields.
   * 7. Set updated_at to current timestamp.
   * 8. Return the updated contract entity with all fields including relationships.
   * 9. Handle edge cases: concurrent modifications, invalid pay_period values, negative pay rates.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
