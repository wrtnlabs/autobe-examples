import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmTimeTrackGuest } from "../../../api/structures/IHrmTimeTrackGuest";
import { IPageIHrmTimeTrackGuest } from "../../../api/structures/IPageIHrmTimeTrackGuest";
import { getHrmTimeTrackGuestsGuestId } from "../../../providers/getHrmTimeTrackGuestsGuestId";
import { patchHrmTimeTrackGuests } from "../../../providers/patchHrmTimeTrackGuests";

@Controller("/hrmTimeTrack/guests")
export class HrmtimetrackGuestsController {
  /**
   * Search and list pending organization invitations for unregistered email addresses.
   *
   * This operation retrieves guest invitations with filtering capabilities for email address, invitation status, organization, and date ranges. Guests represent unregistered users who have been invited to join an organization but have not yet created accounts.
   *
   * Invitation statuses include pending (awaiting acceptance), accepted (consumed during account creation), and expired (past expiration date). Results are returned in paginated format optimized for administrative list displays.
   *
   * @param connection
   * @param body Search criteria including email, status, organization filters, date ranges, and pagination parameters.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query hrm_time_track_guests table with pagination and filtering support.
   *
   * Apply search filters from request body:
   * - email: exact or partial match on email field
   * - status: filter by pending, accepted, or expired
   * - organizationId: filter by organization UUID
   * - date range: filter by created_at or expires_at
   *
   * Join with hrm_time_track_organizations and hrm_time_track_roles for enriched data if requested.
   *
   * Exclude soft-deleted records (deleted_at IS NULL).
   *
   * Return cursor-based pagination for large result sets.
   *
   * Sort by created_at descending by default (newest first).
   *
   * Apply organization scoping based on authenticated user's permissions.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IHrmTimeTrackGuest.IRequest,
  ): Promise<IPageIHrmTimeTrackGuest.ISummary> {
    try {
      return await patchHrmTimeTrackGuests({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves a single guest invitation record by unique identifier.
   *
   * This endpoint returns the complete details of a pending organization invitation, including the invited email address, the organization that sent the invitation, the role that will be assigned upon acceptance, and the current invitation status. Guest invitations represent unregistered email addresses that have been invited to join an organization but have not yet created accounts.
   *
   * The invitation status indicates whether the invitation is still pending acceptance, has been accepted during account creation, or has expired. When a guest creates an account using the invited email address, the invitation is automatically consumed and marked as accepted.
   *
   * @param connection
   * @param guestId Unique identifier of the guest invitation record (global scope)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query the hrm_time_track_guests table for a record matching the provided guestId UUID.
   *
   * 1. Validate that guestId is a valid UUID format
   * 2. Perform a SELECT query on hrm_time_track_guests WHERE id = guestId AND deleted_at IS NULL
   * 3. Join with hrm_time_track_organizations to include organization details
   * 4. Join with hrm_time_track_roles to include role details
   * 5. Return 404 if no active record found
   * 6. Return the full guest entity with all fields including email, status, expires_at, timestamps, and related organization and role data
   * 7. Handle soft-deleted records by excluding them from results
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":guestId")
  public async at(
    @TypedParam("guestId")
    guestId: string & tags.Format<"uuid">,
  ): Promise<IHrmTimeTrackGuest> {
    try {
      return await getHrmTimeTrackGuestsGuestId({
        guestId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
