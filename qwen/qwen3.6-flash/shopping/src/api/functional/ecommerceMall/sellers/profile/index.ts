/**
 * Retrieves the public storefront profile of a registered seller on the marketplace.
 *
 * Returns the seller's business identity details such as their shop name, full description, logo image URL, and the public shop handle used for storefront navigation.
 *
 * @param props.connection
 * @param props.sellerId The unique identifier of the seller whose public storefront profile is being viewed.
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor null
 * @x-autobe-specification Query the ecommerce_mall_seller_profiles table joined
 *   with the ecommerce_mall_sellers table using the relation
 *   ecommerce_mall_seller_profiles.ecommerce_mall_sellers_id =
 *   ecommerce_mall_sellers.id. Filter the results by ecommerce_mall_sellers.id
 *   matching the {sellerId} path parameter. Project the following fields:
 *   shop_name, shop_description, logo_url, created_at, updated_at from
 *   ecommerce_mall_seller_profiles, and the shop_handle field from
 *   ecommerce_mall_sellers. Map snake_case column names to camelCase properties
 *   in the response. Return a 404 Not Found error if no matching seller profile
 *   or seller account exists.
 * @path /ecommerceMall/sellers/:sellerId/profile
 * @accessor api.functional.ecommerceMall.sellers.profile.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * The unique identifier of the seller whose public storefront profile is being viewed.
     */
    sellerId: string & tags.Format<"uuid">;
  };
  export type Response = IEcommerceMallSellerProfile;

  export const METADATA = {
    method: "GET",
    path: "/ecommerceMall/sellers/:sellerId/profile",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/ecommerceMall/sellers/${encodeURIComponent(props.sellerId ?? "null")}/profile`;
  export const random = (): IEcommerceMallSellerProfile =>
    typia.random<IEcommerceMallSellerProfile>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("sellerId")(() => typia.assert(props.sellerId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
