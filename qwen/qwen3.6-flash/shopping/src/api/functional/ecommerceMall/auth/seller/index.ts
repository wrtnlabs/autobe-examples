/**
 * Register a new seller account on the ecommerceMall platform.
 *
 * Accepts email, password, and shop_handle to create a new seller identity. Validates that email and shop_handle are both unique in the ecommerce_mall_sellers table. Password is hashed using bcrypt before storage. The new seller account starts with is_verified set to false, requiring email verification before the account becomes fully operational. Upon successful registration, both access and refresh JWT tokens are issued.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Seller registration credentials including email, password, and shop handle.
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor seller
 * @x-autobe-specification Register a new seller account. Request body contains
 *   email, password, and shop_handle. Validate email format and uniqueness
 *   against ecommerce_mall_sellers.email. Validate password meets minimum
 *   complexity (≥8 characters). Validate shop_handle uniqueness against
 *   ecommerce_mall_sellers.shop_handle. Hash password using bcrypt and store as
 *   password_hash. Set is_verified to false (requires email verification). Set
 *   is_active to true. Set created_at and updated_at to current timestamp.
 *   Generate both access_token (JWT, short-lived) and refresh_token (JWT,
 *   long-lived). Return IEcommerceMallSeller.IAuthorized with tokens.
 * @path /ecommerceMall/auth/seller/join
 * @accessor api.functional.ecommerceMall.auth.seller.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
