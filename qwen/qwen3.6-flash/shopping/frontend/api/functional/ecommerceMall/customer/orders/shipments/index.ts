/**
 * Fetches a paginated list of all shipments associated with a specific order.
 *
 * This endpoint allows customers to track their order fulfillment progress by retrieving detailed shipment information, including carrier name, tracking numbers, shipping dates, and delivery milestones. The operation strictly verifies that the authenticated customer is the owner of the specified order before revealing any shipment data, ensuring complete data isolation.
 *
 * The response provides summary data necessary for the order tracking interface, such as carrier selection, tracking links, estimated arrival time, and confirmed delivery timestamps. Destination address details are included to confirm the delivery location.
 *
 * Customers can filter shipments and sort the results by shipping date or carrier details via the request body. If the order contains multiple items shipped separately by the same seller, each package will appear as a distinct shipment entry in the list.
 *
 * @param props.connection
 * @param props.orderId Unique identifier of the order whose shipments are being retrieved.
 * @param props.body Search filter criteria, sorting options, and pagination boundaries for the shipment list.
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor customer
 * @x-autobe-specification Query ecommerce_mall_orders to verify the
 *   authenticated customer owns the order identified by {orderId}. Return HTTP
 *   404 if the order does not exist or lacks ownership.
 *
 * Query the ecommerce_mall_shipments table where ecommerce_mall_order_id matches {orderId}. Join with ecommerce_mall_sellers to retrieve the seller's display name and ecommerce_mall_shipping_addresses to fetch the delivery destination details.
 *
 * Apply optional status filtering, sorting, and offset-based pagination provided in the request body. Return a paginated cursor or offset-based result set.
 * @path /ecommerceMall/customer/orders/:orderId/shipments
 * @accessor api.functional.ecommerceMall.customer.orders.shipments.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Unique identifier of the order whose shipments are being retrieved.
     */
    orderId: string & tags.Format<"uuid">;

    /**
     * Search filter criteria, sorting options, and pagination boundaries for the shipment list.
     */
    body: IEcommerceMallShipment.IRequest;
  };
  export type Body = IEcommerceMallShipment.IRequest;
  export type Response = IPageIEcommerceMallShipment.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/ecommerceMall/customer/orders/:orderId/shipments",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/ecommerceMall/customer/orders/${encodeURIComponent(props.orderId ?? "null")}/shipments`;
  export const random = (): IPageIEcommerceMallShipment.ISummary =>
    typia.random<IPageIEcommerceMallShipment.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("orderId")(() => typia.assert(props.orderId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
