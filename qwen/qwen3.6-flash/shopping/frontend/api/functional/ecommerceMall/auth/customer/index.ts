/**
 * Registers a new customer account using an email and password.
 *
 * Creates a permanent identity in the ecommerce_mall_customers table after verifying the provided email does not already exist. The user's password is cryptographically hashed prior to storage to ensure security compliance. Following account creation, an email verification token is generated and stored in the ecommerce_mall_customer_email_verifications table, establishing the foundation for the address validation workflow.
 *
 * Security protocols automatically initiate a new session record in the ecommerce_mall_customer_sessions audit trail upon successful registration.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Customer registration credentials
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor customer
 * @x-autobe-specification Accepts IJoin DTO containing 'email' (up to 320
 *   chars) and 'password'. Queries ecommerce_mall_customers to verify email
 *   uniqueness. Hashes the provided password before insertion. Sets the account
 *   'status' to 'active' and clears 'deleted_at'. Creates a new verification
 *   record in ecommerce_mall_customer_email_verifications with a
 *   cryptographically secure token and expiration window. Upon successful
 *   insertion, generates a JWT access and refresh token pair. Logs the new
 *   session into ecommerce_mall_customer_sessions, capturing the client IP
 *   address and creation timestamp. Returns IAuthorized DTO with the tokens.
 * @path /ecommerceMall/auth/customer/join
 * @accessor api.functional.ecommerceMall.auth.customer.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
