/**
 * Registers a new platform administrator account.
 *
 * Creates a new identity in the administrators table with a unique email address, a cryptographically hashed password, and an administrative grade level. The system enforces unique email constraints and applies a default grade assignment when none is specified during the registration request.
 *
 * Upon successful account creation, the system immediately authenticates the new administrator and issues an access token along with a refresh token to initialize the session securely.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Request payload for registering a new platform administrator.
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor admin
 * @x-autobe-specification 1. Validate request body: email (string), password
 *   (string), grade (optional string). 2. Hash the password using a secure
 *   cryptographic algorithm (e.g., bcrypt or Argon2). 3. Query
 *   ecommerce_mall_admins for an existing record matching the provided email.
 *   If found, return 409 Conflict. 4. Insert a new record into the admins table
 *   with the provided email, hashed password, and the provided grade (assign a
 *   default grade of 'regular' if omitted). 5. Generate a new JWT access token
 *   and refresh token bound to the new admin identity. 6. Return the token
 *   payload, new admin ID, email, and grade. Error handling: 400 for malformed
 *   input, 409 for duplicate email, 500 for database errors.
 * @path /ecommerceMall/auth/admin/join
 * @accessor api.functional.ecommerceMall.auth.admin.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
