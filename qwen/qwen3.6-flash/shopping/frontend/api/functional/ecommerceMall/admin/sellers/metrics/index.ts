import { IConnection, PlainFetcher } from "@nestia/fetcher";
import typia from "typia";

import { IEcommerceMallAdmin } from "../../../../../structures/IEcommerceMallAdmin";

/**
 * Provides an aggregated snapshot of seller platform health and high-level administrative overview metrics.
 *
 * This endpoint is exclusively accessible to platform administrators, allowing them to quickly assess the current state of the seller ecosystem without loading detailed individual records. It dynamically aggregates seller account data to provide real-time counts for various operational buckets, including total sellers, approved merchants, suspended accounts, and unverified registrations.
 *
 * The metrics are computed directly from the seller accounts table via internal aggregation queries. This delivers a synchronous, lightweight response that reflects the latest registration and status changes, ideal for dashboard visualizations.
 *
 * @param props.connection
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor admin
 * @x-autobe-specification Query the `ecommerce_mall_sellers` table to compute
 *   aggregated counts grouped by `is_verified` and `is_active` boolean flags.
 *   Return a single JSON object containing the total seller count, the count of
 *   active approved sellers, and the count of suspended or unverified sellers.
 *   No pagination is needed as this returns a single snapshot object.
 * @path /ecommerceMall/admin/sellers/metrics
 * @accessor api.functional.ecommerceMall.admin.sellers.metrics.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(connection: IConnection): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(),
          status: null,
        },
      );
}
export namespace at {
  export type Response = IEcommerceMallAdmin.IMetric;

  export const METADATA = {
    method: "GET",
    path: "/ecommerceMall/admin/sellers/metrics",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/ecommerceMall/admin/sellers/metrics";
  export const random = (): IEcommerceMallAdmin.IMetric =>
    typia.random<IEcommerceMallAdmin.IMetric>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}
