import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { getTodoListUserUsersUserId } from "../../../../providers/getTodoListUserUsersUserId";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { putTodoListUserUsersUserId } from "../../../../providers/putTodoListUserUsersUserId";
import { deleteTodoListUserUsersUserId } from "../../../../providers/deleteTodoListUserUsersUserId";

import { ITodoListUser } from "../../../../api/structures/ITodoListUser";

@Controller("/todoList/user/users/:userId")
export class TodolistUserUsersController {
  /**
   * Retrieve user detail from todo_list_users by userId (UUID).
   *
   * Fetch detailed information for a specific user account in the Todo List
   * service.
   *
   * This API endpoint safely retrieves one user's profile based on their unique
   * system-assigned identifier. Returned fields include the user's email
   * address, the ISO 8601 timestamp when the account was created, and the most
   * recent update time. The underlying table is todo_list_users, which ensures
   * email uniqueness and isolates each user from others. The password hash and
   * authentication details are never included in the API response for security
   * reasons.
   *
   * The API fully enforces access controls to ensure isolation: users may only
   * access their own records unless extended for privileged administrative
   * roles in the future. All error conditions—including requests for
   * nonexistent or unauthorized users—yield clear error responses. Related
   * endpoints may include user self-update and account deletion operations.
   *
   * @param connection
   * @param userId Unique identifier (UUID) of the user account to retrieve.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
  ): Promise<ITodoListUser> {
    try {
      return await getTodoListUserUsersUserId({
        user,
        userId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update a user profile in todo_list_users by userId (UUID).
   *
   * Update profile information for a specific Todo List user. Only the user may
   * update their own record; there are no cross-user operations or delegated
   * administrative access in this system. User updates support changing email
   * (with uniqueness enforced) and password_hash fields; all changes are
   * subject to validation rules as described in the todo_list_users Prisma
   * schema. Updates automatically refresh the updated_at timestamp while
   * maintaining full audit traceability.
   *
   * The operation is designed to strictly prohibit unauthenticated or
   * cross-user modifications, rejecting any request where authentication or
   * ownership validation fails. Error responses are descriptive in cases of
   * conflict (e.g., duplicate email), invalid data, or permission violations.
   * The endpoint is foundational for secure account management and is paired
   * with endpoints for account fetch and (when required) account deletion.
   *
   * @param connection
   * @param userId Unique identifier (UUID) of the user account to update.
   * @param body New user profile data for update. Includes only fields to be
   *   edited—supported: email and password hash.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoListUser.IUpdate,
  ): Promise<ITodoListUser> {
    try {
      return await putTodoListUserUsersUserId({
        user,
        userId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a user (todo_list_users table) by ID.
   *
   * Permanently delete a user account from the system, including all
   * authentication, ownership, and related records. Primarily used in
   * exceptional cases such as compliance with user deletion policies, not for
   * routine account management.
   *
   * This operation is highly privileged and intended for administrative or
   * automated routines, not for self-service by ordinary users. All associated
   * resources owned by the deleted user will be cascaded or orphaned according
   * to database constraints.
   *
   * Security: Only users ("user" actor) according to current schema may invoke
   * this endpoint, but should be guarded in implementation. Attempts by
   * unauthorized actors are blocked.
   *
   * Failure to find the specified userId returns a 404 error. Deletion is
   * irreversible.
   *
   * @param connection
   * @param userId Unique identifier of the target user.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoListUserUsersUserId({
        user,
        userId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
