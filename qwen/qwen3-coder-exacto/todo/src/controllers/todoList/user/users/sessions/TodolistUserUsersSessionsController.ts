import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchTodoListUserUsersUserIdSessions } from "../../../../../providers/patchTodoListUserUsersUserIdSessions";
import { UserAuth } from "../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../decorators/payload/UserPayload";
import { getTodoListUserUsersUserIdSessionsSessionId } from "../../../../../providers/getTodoListUserUsersUserIdSessionsSessionId";
import { deleteTodoListUserUsersUserIdSessionsSessionId } from "../../../../../providers/deleteTodoListUserUsersUserIdSessionsSessionId";

import { IPageITodoListUserSession } from "../../../../../api/structures/IPageITodoListUserSession";
import { ITodoListUserSession } from "../../../../../api/structures/ITodoListUserSession";

@Controller("/todoList/user/users/:userId/sessions")
export class TodolistUserUsersSessionsController {
  /**
   * Session audit: Retrieve paginated user sessions (todo_list_user_sessions)
   * by user ID.
   *
   * Retrieve a paginated, filterable list of all authentication sessions for a
   * given user. Sessions include IP address, URL context, referrer, creation
   * timestamp, and expiry timestamp.
   *
   * This endpoint is defined to allow access by users ("user" actor), even
   * though in normal business context it would be restricted for audit or
   * operational support. It allows diagnosing login activity, understanding
   * session distribution, and enforcing compliance policies. End users will see
   * only their own sessions.
   *
   * Security: "user" actor required by schema. Sensitive data such as session
   * IPs are protected against inappropriate disclosure.
   *
   * @param connection
   * @param userId Unique identifier of the target user.
   * @param body Session audit/search request parameters for the specified user.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoListUserSession.IRequest,
  ): Promise<IPageITodoListUserSession> {
    try {
      return await patchTodoListUserUsersUserIdSessions({
        user,
        userId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Get detailed info for a single user session from todo_list_user_sessions
   * table.
   *
   * Retrieve information about a single authentication session for the
   * signed-in user. This operation is used by the account owner to view
   * metadata related to a specific login session, which includes connection IP,
   * originating/referring URLs, and session creation/expiry timestamps.
   *
   * Access to session metadata is restricted exclusively to the user who owns
   * the session, with permissions enforced by verifying the `userId` path
   * parameter matches the authenticated user's identity. All fields align
   * precisely with the `todo_list_user_sessions` Prisma schema and reference
   * the associated user, without exposing any cross-user or admin session
   * details.
   *
   * This endpoint supports client-side session management, account security
   * review, and personal audit. It does not allow session removal or
   * modification—only read access limited to the valid session and its owner is
   * granted. In cases of invalid or expired session IDs, or unauthorized
   * access, the server will return an appropriate error response.
   *
   * @param connection
   * @param userId Unique identifier of the user who owns the session. Must
   *   match the authenticated user's ID.
   * @param sessionId Unique identifier of the specific session to retrieve, as
   *   defined in the todo_list_user_sessions table.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<ITodoListUserSession> {
    try {
      return await getTodoListUserUsersUserIdSessionsSessionId({
        user,
        userId,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Erase a user session from todo_list_user_sessions table for the
   * authenticated user.
   *
   * Delete a user session belonging to the logged-in account. This
   * hard-deletion operation is permitted strictly when the session belongs to
   * the authenticated user as indicated by the `userId` path parameter.
   *
   * The session identified by `sessionId` will be permanently removed from the
   * `todo_list_user_sessions` table, eliminating all audit and metadata
   * pertaining to that session. The operation supports use cases such as
   * session invalidation upon logout from devices and manual removal of
   * previous authentication records.
   *
   * Security and permission enforcement are handled both at the parameter
   * validation layer and by checking that the session belongs to the provided
   * `userId` matching the current user's authenticated identity. If the session
   * does not exist, is already expired, or the user attempts to access sessions
   * belonging to another account, an error is returned. This is a hard-delete;
   * session data is unrecoverable after execution.
   *
   * @param connection
   * @param userId Unique identifier of the user who owns the session. Must
   *   match the authenticated user's ID.
   * @param sessionId Unique identifier of the session to delete, as defined in
   *   todo_list_user_sessions.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":sessionId")
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoListUserUsersUserIdSessionsSessionId({
        user,
        userId,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
