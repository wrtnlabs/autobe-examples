  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
  ): Promise<ITodoListTodo> {
    try {
      return await getTodoListUserTodosTodoId({
        user,
        todoId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update a todo item in todo_list_todos by ID, enforcing ownership and
   * validation rules.
   *
   * Update an existing todo item belonging to the authenticated user.
   *
   * Authentication is required. The operation checks that the todoId in the
   * path refers to a todo owned by the calling user. The request body must
   * specify at least one field to change (title, description, completed, or due
   * date). Field constraints are strictly enforced: title cannot be empty or
   * over 255 characters; description, if provided, is limited to 1000
   * characters; completed status is a boolean; due date, if present, must be a
   * valid future ISO 8601 string. If the todo is not found, not owned, or
   * request is invalid, a precise error is returned indicating the cause.
   *
   * On successful update, the todo's updated_at timestamp is refreshed and the
   * full DTO is returned. This maintains strict ownership and privacy
   * guarantees in line with business and database requirements.
   *
   * @param connection
   * @param todoId Unique identifier of the todo item to update (UUID).
   * @param body Fields to update for the specified todo item (at least one must
   *   be provided).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
