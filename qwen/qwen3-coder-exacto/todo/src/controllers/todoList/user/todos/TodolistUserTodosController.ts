  /**
   * Create a new todo item in todo_list_todos owned by the authenticated user.
   *
   * Create a new todo item for the authenticated user in the system.
   *
   * This operation requires JWT-based authentication and checks that the
   * incoming request comes from a valid session. The request body must contain
   * a non-empty title of at most 255 characters; if a description is provided,
   * it must not exceed 1000 characters. Optionally, the client may provide a
   * due date, which must be a valid, future ISO 8601 string. The business logic
   * enforces that ownership is attributed to the user extracted from the access
   * token, regardless of any supplied ownership hints.
   *
   * Upon successful creation, the system sets completed to false, assigns the
   * todo to the current user, records creation and update timestamps, and
   * persists the row with strict normalization. Any violation of field
   * constraints, authentication, or ownership rules results in a descriptive
   * error response, as defined in the requirements analysis.
   *
   * On success, the complete todo DTO is returned, containing all main fields
   * defined in the Prisma model, including id, title, description, completed,
   * created_at, updated_at, and any additional business metadata as
   * appropriate.
   *
   * @param connection
   * @param body Data for creating a new todo item, including title, optional
   *   description, and due date.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
