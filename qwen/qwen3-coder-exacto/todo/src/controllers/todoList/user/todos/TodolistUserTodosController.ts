  /**
   * Retrieve the complete detail of a specific todo item from todo_list_todos.
   *
   * Fetch full details about a single todo item from the todo_list_todos table
   * using its unique ID.
   *
   * The endpoint returns all fields and relationships for the specified todo,
   * including title, description, status, due date, owner, and any tags or
   * priority attributes defined in the schema. Security is enforced to ensure
   * only owners or users with explicit permission can access the todo details.
   * Unauthorized access is prevented, and error responses are returned for
   * invalid or missing identifiers.
   *
   * This operation underpins detail pages, edit functions, and contextual views
   * throughout the Todo List application. The design ensures strong consistency
   * and data integrity, with clear error handling for not-found or unauthorized
   * cases.
   *
   * @param connection
   * @param todoId Unique identifier of the target todo item.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
