import { Controller, Ip } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthUserJoin } from "../../../providers/postAuthUserJoin";
import { postAuthUserLogin } from "../../../providers/postAuthUserLogin";
import { postAuthUserRefresh } from "../../../providers/postAuthUserRefresh";

import { ITodoListUser } from "../../../api/structures/ITodoListUser";

@Controller("/auth/user")
export class AuthUserController {
  /**
   * Create a new registered user account as a member in the todo_list_users
   * table.
   *
   * This operation allows new users to join the application as authenticated
   * members by registering their account in the system. The request payload
   * must supply all mandatory fields defined in the 'todo_list_users' Prisma
   * model, which may include credentials such as 'email', 'username', and
   * 'password' if present. Validation and business logic ensure that all
   * required registration data is properly checked for uniqueness (such as
   * unique email or username), and passwords are securely handled according to
   * best practices if the schema supports them.
   *
   * Upon successful registration, the system issues both a JWT access token and
   * a refresh token, allowing the user to authenticate further requests and
   * refresh expired sessions securely. The tokens are returned using the
   * standardized response DTO for the TodoList user actor, making integration
   * straightforward for clients.
   *
   * This endpoint is public, meaning no prior authentication is required to
   * invoke it—a core requirement for initial user sign-up. The data submitted
   * is strictly validated and stored, and appropriate error responses are sent
   * if registration fails due to business logic violations (such as duplicate
   * accounts or weak passwords).
   *
   * The design adheres to the intended permission model for member-level users.
   * After completion, the authenticated session context is managed per session
   * policies defined elsewhere in your application.
   *
   * Related operations involve user login and token refresh, forming the
   * foundation of the full authentication lifecycle as captured in this API
   * set.
   *
   * @param connection
   * @param body Data required to register a new user. Schema reflects the
   *   registration fields of the 'todo_list_users' model.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoListUser.ICreate,
  ): Promise<ITodoListUser.IAuthorized> {
    try {
      return await postAuthUserJoin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate a registered user in the todo_list_users table and issue
   * tokens.
   *
   * This operation provides secure login for registered user actors. The
   * request body requires fields typically defined in the 'todo_list_users'
   * Prisma model, such as 'email' or 'username' and 'password', depending on
   * the schema. The input data is strictly validated for authenticity and
   * integrity, ensuring only correct credential pairs can authenticate.
   *
   * Upon successful authentication, new JWT access and refresh tokens are
   * issued to the user, encapsulated in the standardized response DTO for the
   * TodoList user actor. The login process incorporates security best
   * practices, such as hashed password comparison and failure responses for
   * incorrect credentials, without disclosing account existence details.
   *
   * No authentication is required to use this endpoint, as it is public for
   * user login purposes. The operation's authentication flow establishes the
   * session context for the user, controlled by session policies tied to the
   * 'user' actor kind.
   *
   * Error conditions, such as account lockouts, expired credentials, or
   * incorrect login details, are handled by returning the appropriate error
   * responses as per system policy and schema specification.
   *
   * This login is part of the authentication workflow, typically followed by
   * token refresh when access tokens expire. Related operations include join
   * (registration) and refresh endpoints.
   *
   * @param connection
   * @param body Credentials for user login (usually email/username and password
   *   as defined in 'todo_list_users').
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoListUser.ILogin,
  ): Promise<ITodoListUser.IAuthorized> {
    try {
      return await postAuthUserLogin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh JWT tokens for an authenticated user based on current session
   * policies.
   *
   * This operation enables registered users to refresh their authentication
   * tokens using a valid refresh token. The endpoint accepts a request body (or
   * cookie, depending on architecture) containing the refresh token, and
   * returns a new set of JWT authorization tokens.
   *
   * Token refresh flow leverages the secure field design in the
   * 'todo_list_users' table and adheres to the session and expiration policies
   * in the business logic. This operation ensures continued access without
   * requiring the user to re-authenticate using their credentials, following
   * best security practices.
   *
   * The endpoint is protected to accept only valid, non-expired refresh tokens.
   * If the refresh token is missing, invalid, or expired, the operation returns
   * an error, instructing the client to re-authenticate via login or
   * registration.
   *
   * Security is strictly enforced by using cryptographically secure token
   * structures and adhering to server-controlled session metadata from the
   * schema if relevant.
   *
   * This completes the core authentication lifecycle together with user
   * registration (join) and login endpoints, facilitating token rotation and
   * long-lived authenticated user experience within permission boundaries.
   *
   * @param connection
   * @param body Refresh token payload required to obtain new JWT tokens for the
   *   user.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: ITodoListUser.IRefresh,
  ): Promise<ITodoListUser.IAuthorized> {
    try {
      return await postAuthUserRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
