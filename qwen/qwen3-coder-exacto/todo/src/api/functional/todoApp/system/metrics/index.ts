export async function at(connection: IConnection): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(),
          status: null,
        },
      );
}
export namespace at {
  export type Response = ITodoAppSystemMetric;

  export const METADATA = {
    method: "GET",
    path: "/todoApp/system/metrics",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/todoApp/system/metrics";
  export const random = (): ITodoAppSystemMetric =>
    typia.random<ITodoAppSystemMetric>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}
