/**
 * Register a new user account in the todo application.
 *
 * This endpoint creates a new user profile with the provided email address and password. The email address must be unique across all users in the system. The password will be validated against the system's password complexity requirements before being securely hashed and stored.
 *
 * The system SHALL collect the email address and password during registration. The email address SHALL be validated for proper format and uniqueness. The password SHALL be validated for complexity requirements before being securely hashed.
 *
 * Upon successful validation and account creation, the system SHALL return initial authentication tokens to the client, enabling immediate access to the todo management features. The new user account SHALL be created with default settings and an active status.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body User registration information including email and password.
 * @x-autobe-specification Implement user registration by validating email uniqueness and password complexity, then create new user record with hashed password. Generate initial JWT tokens for immediate API access. Return tokens along with basic user profile information.
 * @path /todoApp/auth/todo-user/join
 * @accessor api.functional.todoApp.auth.todo_user.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
