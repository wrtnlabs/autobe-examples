/**
 * Retrieve user detail from todo_list_users by userId (UUID).
 *
 * Fetch detailed information for a specific user account in the Todo List
 * service.
 *
 * This API endpoint safely retrieves one user's profile based on their unique
 * system-assigned identifier. Returned fields include the user's email address,
 * the ISO 8601 timestamp when the account was created, and the most recent
 * update time. The underlying table is todo_list_users, which ensures email
 * uniqueness and isolates each user from others. The password hash and
 * authentication details are never included in the API response for security
 * reasons.
 *
 * The API fully enforces access controls to ensure isolation: users may only
 * access their own records unless extended for privileged administrative roles
 * in the future. All error conditions—including requests for nonexistent or
 * unauthorized users—yield clear error responses. Related endpoints may include
 * user self-update and account deletion operations.
 *
 * @param props.connection
 * @param props.userId Unique identifier (UUID) of the user account to retrieve.
 * @path /todoList/user/users/:userId
 * @accessor api.functional.todoList.user.users.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique identifier (UUID) of the user account to retrieve. */
    userId: string & tags.Format<"uuid">;
  };
  export type Response = ITodoListUser;

  export const METADATA = {
    method: "GET",
    path: "/todoList/user/users/:userId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/todoList/user/users/${encodeURIComponent(props.userId ?? "null")}`;
  export const random = (): ITodoListUser => typia.random<ITodoListUser>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("userId")(() => typia.assert(props.userId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

