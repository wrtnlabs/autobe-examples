/**
 * Authentication session entity for tracking user login events and access
 * history.
 *
 * Represents a single session record belonging to a user (from todo_list_users)
 * in the Todo List application. This entity holds metadata for an authenticated
 * session, including client IP address, login entry point (URL), referrer URL,
 * session creation/expiry time, and a reference to the owning user. Session
 * records support audit, diagnostics, and enforcement of session policies
 * across the platform.
 *
 * Each session is subsidiary to its owning user, providing no independent
 * business identity aside from audit and security analytics context.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type ITodoListUserSession = {
  /**
   * Unique identifier for the session record. Assigned automatically by the
   * database at creation time and guaranteed unique for each session.
   *
   * Used as the primary key for referencing, updating, and deleting session
   * records. Keeps integrity with associated user records.
   */
  id: string & tags.Format<"uuid">;

  /**
   * Summary of the user account that owns this session record. References the
   * ITodoListUser.ISummary type for efficient business context and avoids the
   * need for additional API calls to reconstruct session/user associations.
   *
   * Replaces the raw foreign key `todo_list_user_id` in the response type for
   * clarity, context, and single-call atomic operations.
   */
  user: ITodoListUser.ISummary;

  /**
   * Client IP address captured at login time for session creation. Used for
   * security analytics, audit trails, and possible anomaly detection.
   * Required and non-nullable by schema.
   */
  ip: string;

  /**
   * URL of the page or application context where the session was initiated.
   * Used for audit, support, and analytics. Required and non-nullable.
   */
  href: string;

  /**
   * URL that referred the user to the entry/login page when starting this
   * session. Used for historical analysis and referrer-based controls.
   * Required and non-nullable.
   */
  referrer: string;

  /**
   * Timestamp (RFC 3339 date-time) for when this session was established.
   * Used for audit, support, and time-window-based controls. Non-nullable.
   */
  created_at: string & tags.Format<"date-time">;

  /**
   * Timestamp or null for session expiry; required for session lifecycle and
   * security analytics.
   */
  expired_at?: (string & tags.Format<"date-time">) | null | undefined;
};
