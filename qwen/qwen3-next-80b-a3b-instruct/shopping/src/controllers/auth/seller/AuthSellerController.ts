import { Controller, Ip } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthSellerJoin } from "../../../providers/postAuthSellerJoin";
import { postAuthSellerLogin } from "../../../providers/postAuthSellerLogin";
import { postAuthSellerRefresh } from "../../../providers/postAuthSellerRefresh";

import { IShoppingMallSeller } from "../../../api/structures/IShoppingMallSeller";

@Controller("/auth/seller")
export class AuthSellerController {
  /**
   * Register a new seller account on the shoppingMall platform. This operation
   * creates a seller record with initial status 'pending_verification'. The
   * seller must provide a unique business email and secure password, which are
   * stored in the email and password_hash fields respectively. The account is
   * initially suspended until an admin reviews the submitted business
   * information including business_name, business_address, and tax_id. The
   * created_at timestamp records the registration time, and deleted_at remains
   * null indicating the account is active but unverified. This operation is
   * public and does not require authentication.
   *
   * Security considerations require password hashing using BCrypt algorithm as
   * specified in the schema. The email must be unique across the entire system
   * as enforced by the unique index on the email field. This operation creates
   * a foundational identity for the seller who will subsequently manage
   * products, inventory, and customer orders.
   *
   * The seller account is linked to the shopping_mall_seller_sessions table for
   * session management and to shopping_mall_products for product listings. Upon
   * successful registration, a temporary access token is issued for
   * verification purposes. If the account remains unverified, it may be
   * auto-deleted after 30 days as per platform policy.
   *
   * This operation must be completed before the seller can upload products or
   * access their storefront. The verification process requires submission of
   * supporting documents and may take 1-3 business days.
   *
   * No related API operations are required as prerequisites since this is the
   * initial entry point for seller onboarding.
   *
   * @param connection
   * @param body Payload containing seller registration details.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallSeller.ICreate,
  ): Promise<IShoppingMallSeller.IAuthorized> {
    try {
      return await postAuthSellerJoin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate an existing seller account using email and password
   * credentials. This operation validates the email and password_hash values
   * against the seller database record. When successful, the authentication
   * system verifies the account status is 'active' and deleted_at is null,
   * ensuring the seller account is not suspended or deactivated. The password
   * must be verified using BCrypt protocol as established in the schema.
   *
   * The authentication system enforces rate limiting on login attempts to
   * prevent brute force attacks. Each successful login creates a corresponding
   * record in the shopping_mall_seller_sessions table to track active sessions.
   * The login operation returns a refresh token that can be used to obtain new
   * access tokens without re-entering credentials.
   *
   * This operation is crucial for granting sellers access to their management
   * dashboard where they can perform product listing, order processing, and
   * sales analytics. Before login, the seller must have completed the
   * registration process and received admin approval, as indicated by a status
   * value of 'active'.
   *
   * Login attempts with invalid credentials are logged in the
   * shopping_mall_access_logs table for security auditing. Multiple failed
   * attempts trigger account lockout mechanisms. This operation has no
   * prerequisites since it is the primary authentication entry point for
   * sellers.
   *
   * @param connection
   * @param body Request body containing the seller's email and password for
   *   authentication.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallSeller.IRequest,
  ): Promise<IShoppingMallSeller.IAuthorized> {
    try {
      return await postAuthSellerLogin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Renew access to seller services using a valid refresh token without
   * requiring email and password re-entry. This operation validates the refresh
   * token against the shopping_mall_seller_sessions table to confirm the
   * session is active and authenticated. Upon validation, a new access token is
   * issued with a fresh lifecycle while maintaining the same seller identity.
   *
   * The refresh token has a longer expiration period than the access token and
   * must be stored securely by the client application. This operation ensures
   * continuous access to seller management features without forcing frequent
   * re-authentication, which would disrupt business operations like order
   * fulfillment, inventory management, and customer communication.
   *
   * The refresh operation does not change the seller's account status, which
   * must remain 'active' with deleted_at = null for continued service. The
   * refresh token is invalidated if the seller changes their password, their
   * account is suspended by an admin, or if the session expires.
   *
   * This operation is essential for maintaining uninterrupted seller experience
   * across multiple devices and sessions. It follows the OAuth 2.0 refresh
   * token pattern and complements the login operation. This operation has no
   * prerequisites as it is designed to work independently after initial
   * authentication.
   *
   * @param connection
   * @param body Contains the refresh token obtained during the login operation.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IShoppingMallSeller.IRequest,
  ): Promise<IShoppingMallSeller.IAuthorized> {
    try {
      return await postAuthSellerRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
