import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthCustomerRefresh } from "../../../../providers/postAuthCustomerRefresh";

import { IShoppingMallCustomer } from "../../../../api/structures/IShoppingMallCustomer";

@Controller("/auth/customer/refresh")
export class AuthCustomerController {
  /**
   * Extends the validity of the customer's access token by exchanging a valid
   * refresh token for new access and refresh tokens. This operation is used
   * when the current access token has expired but the refresh token is still
   * valid.
   *
   * The refresh token must be present and valid in the customer_session record
   * associated with the customer's account. The system validates the refresh
   * token against the stored token in the customer_session table and checks
   * that the corresponding customer account has 'active' status. If the
   * customer is suspended or deleted, the refresh will be denied.
   *
   * This process updates the refresh_token field in the customer_session record
   * and resets the expiration timestamp for both the access and refresh tokens.
   * The operation does not change the customer's authentication status or
   * verify credentials again.
   *
   * This operation is essential for maintaining a seamless user experience
   * without requiring re-authentication for every API call. The access token
   * typically expires after 15 minutes while the refresh token remains valid
   * for up to 7 days.
   *
   * Related operations: POST /auth/customer/join, POST /auth/customer/login,
   * and GET /auth/customer/logout. Exchange is used after login or previous
   * refresh operation, and must be called before the access token expires to
   * maintain continuous session.
   *
   * @param connection
   * @param body Request body for token refresh using a valid refresh token.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async refresh(
    @TypedBody()
    body: IShoppingMallCustomer.IRequest,
  ): Promise<IShoppingMallCustomer.IAuthorized> {
    try {
      return await postAuthCustomerRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
