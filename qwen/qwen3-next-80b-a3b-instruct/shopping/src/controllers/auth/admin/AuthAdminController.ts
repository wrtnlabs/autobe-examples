import { Controller, Ip } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthAdminJoin } from "../../../providers/postAuthAdminJoin";
import { postAuthAdminLogin } from "../../../providers/postAuthAdminLogin";
import { postAuthAdminRefresh } from "../../../providers/postAuthAdminRefresh";

import { IShoppingMallAdmin } from "../../../api/structures/IShoppingMallAdmin";

@Controller("/auth/admin")
export class AuthAdminController {
  /**
   * Registers a new admin account for platform administrators. This operation
   * creates a new administrative identity with the provided email and password
   * hash, initializing system access for privileged operations. The operation
   * requires email validation through an out-of-band process, as admin accounts
   * are manually created through secure internal procedures and cannot be
   * self-registered publicly. The account begins in 'pending_verification'
   * status until manually approved by an existing admin through the
   * administrative console, after which status transitions to 'active'. All
   * admin accounts must have a unique email, enforced by the unique index on
   * shopping_mall_admins.email field. The password_hash field is stored as a
   * BCrypt hash, never in plain text, as required by security protocols
   * referenced in the security_and_compliance.md requirements document. When a
   * new admin is created, the system automatically logs this event in the
   * shopping_mall_audit_logs table for compliance tracking. This operation
   * should be triggered by platform administrators through secure HR onboarding
   * systems, not through public API endpoints.
   *
   * Security considerations: This is a privileged operation requiring human
   * approval and secure channel verification. Access to this endpoint is
   * restricted to internal systems with physical and network security
   * controls.
   *
   * Relationship: This operation directly creates records in the
   * shopping_mall_admins table. The account's status will be initialized as
   * 'pending_verification' and must be manually upgraded to 'active' by an
   * existing admin.
   *
   * Related operations: Once the account is active, the admin can use the
   * /auth/admin/login operation to authenticate.
   *
   * @param connection
   * @param body Registration parameters for creating a new admin account.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallAdmin.ICreate,
  ): Promise<IShoppingMallAdmin.IAuthorized> {
    try {
      return await postAuthAdminJoin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticates an admin user by verifying their email and password against
   * the system database. This operation checks the provided email against the
   * unique index on shopping_mall_admins.email field and validates the
   * BCrypt-hashed password against the stored password_hash value. If
   * authentication is successful, the user's status field must be 'active' to
   * proceed; accounts with 'suspended' or 'pending_verification' status are
   * denied access. On successful authentication, a new session record is
   * created in the shopping_mall_admin_sessions table with the client's IP
   * address, referrer URL, and href details. The session expires according to
   * the platform's security policy (typically 8 hours of inactivity). The
   * operation returns a refresh token and access token that are
   * cryptographically signed and valid for subsequent API calls.
   *
   * Security considerations: All login attempts are logged in the
   * shopping_mall_access_logs table for audit purposes. Multiple failed
   * attempts within 10 minutes trigger account lockout for 15 minutes, as
   * defined by the security_and_compliance.md requirements. This operation
   * requires secure HTTPS transmission and does not allow requests from
   * untrusted domains.
   *
   * Relationship: This operation reads from shopping_mall_admins table and
   * creates records in shopping_mall_admin_sessions table. The operation is
   * restricted to admin actors only.
   *
   * Related operations: After successful login, admins can use the refresh
   * operation to renew their access token, and the logout operation (if
   * implemented) to terminate the session.
   *
   * @param connection
   * @param body Authentication parameters for admin login.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallAdmin.IRequest,
  ): Promise<IShoppingMallAdmin.IAuthorized> {
    try {
      return await postAuthAdminLogin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Renews the access token for an authenticated admin session using a valid
   * refresh token. This operation validates the refresh token against the
   * system's token store, verifies that the associated
   * shopping_mall_admin_sessions record is still active (expired_at is null),
   * and checks that the admin account status is active. Upon validation, a new
   * access token and refresh token pair are generated, extending the session
   * duration according to the session timeout policy. The existing refresh
   * token is invalidated and replaced with a new one following best practices
   * for token rotation. The operation logs the refresh event in the
   * shopping_mall_access_logs table for audit trail purposes.
   *
   * Security considerations: Refresh tokens must be stored securely and should
   * never be transmitted over insecure channels. Refresh token rotation
   * prevents replay attacks and mitigates token theft risks. After successful
   * token refresh, a new session record is created while the old one is marked
   * for cleanup. This operation has an additional security layer requiring MFA
   * validation if the user has configured it in their preferences, as
   * referenced in the Authentication_Requirements.md document.
   *
   * Relationship: This operation validates against shopping_mall_admin_sessions
   * and shopping_mall_admins tables. It does not directly modify user data but
   * updates authentication session state.
   *
   * Related operations: This operation typically follows login. Once the access
   * token expires, it's the only way to continue the session without
   * re-authenticating with credentials.
   *
   * @param connection
   * @param body Refresh token for extending authenticated session.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IShoppingMallAdmin.IRefresh,
  ): Promise<IShoppingMallAdmin.IAuthorized> {
    try {
      return await postAuthAdminRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
