import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { putShoppingMallAdminInventoryReservationsReservationId } from "../../../../../providers/putShoppingMallAdminInventoryReservationsReservationId";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { deleteShoppingMallAdminInventoryReservationsReservationId } from "../../../../../providers/deleteShoppingMallAdminInventoryReservationsReservationId";

import { IShoppingMallInventoryReservation } from "../../../../../api/structures/IShoppingMallInventoryReservation";

@Controller("/shoppingMall/admin/inventory/reservations/:reservationId")
export class ShoppingmallAdminInventoryReservationsController {
  /**
   * Update an existing inventory reservation by its unique identifier. This
   * operation allows modification of the reservation quantity or expiration
   * time for pending orders. The reservation must still be active (expires_at
   * in the future) for updates to be permitted. The system will validate that
   * the updated quantity does not exceed available inventory for the referenced
   * inventory unit, and that the new expiration time falls within allowable
   * limits (minimum 5 minutes, maximum 30 minutes from now).
   *
   * This operation works with the shopping_mall_inventory_reservations model in
   * the Prisma schema, which tracks temporary inventory locks for orders in the
   * checkout process. When a reservation is updated, the system recalculates
   * the available inventory for the associated inventory_unit_id and may
   * trigger inventory alerts if thresholds are approached.
   *
   * Security: Only authenticated users who created the reservation or have
   * admin privileges can update it. The operation validates ownership by
   * checking that the reservation's order_item_id links to a valid order
   * belonging to the authenticated user.
   *
   * Related operations: DELETE /inventory/reservations/{reservationId} (cancels
   * reservation), GET /inventory/reservations/{reservationId} (retrieves
   * reservation details).
   *
   * @param connection
   * @param reservationId Unique identifier of the inventory reservation to
   *   update. This corresponds to the id field in the
   *   shopping_mall_inventory_reservations table.
   * @param body Updated properties for the inventory reservation.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("reservationId")
    reservationId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallInventoryReservation.IUpdate,
  ): Promise<IShoppingMallInventoryReservation> {
    try {
      return await putShoppingMallAdminInventoryReservationsReservationId({
        admin,
        reservationId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently cancel and release an inventory reservation by its unique
   * identifier. This operation immediately releases the reserved inventory back
   * to the available stock pool and removes the reservation record from the
   * system. This typically occurs when a customer cancels a pending order or
   * when the reservation expires (though expired reservations are automatically
   * handled by a background process).
   *
   * This operation works with the shopping_mall_inventory_reservations model in
   * the Prisma schema, which tracks temporary inventory locks for orders in the
   * checkout process. The system ensures that only the creator of the
   * reservation or an administrator can cancel it, preventing unauthorized
   * inventory release.
   *
   * After cancellation, the system logs the event in the
   * shopping_mall_inventory_transactions table as a "reservation_cancelled"
   * transaction and triggers inventory alerts if the release causes inventory
   * levels to rise above threshold points.
   *
   * Security: Only authenticated users who created the reservation or have
   * admin privileges can cancel it. The operation validates ownership by
   * checking that the reservation's order_item_id links to a valid order
   * belonging to the authenticated user.
   *
   * Related operations: PUT /inventory/reservations/{reservationId} (updates
   * reservation), GET /inventory/reservations/{reservationId} (retrieves
   * reservation details).
   *
   * @param connection
   * @param reservationId Unique identifier of the inventory reservation to
   *   cancel. This corresponds to the id field in the
   *   shopping_mall_inventory_reservations table.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("reservationId")
    reservationId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallAdminInventoryReservationsReservationId({
        admin,
        reservationId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
