import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IPageIShoppingMallInventoryLog } from "../../../../../api/structures/IPageIShoppingMallInventoryLog";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { patchShoppingMallAdminInventoryVariantIdHistory } from "../../../../../providers/patchShoppingMallAdminInventoryVariantIdHistory";

@Controller("/shoppingMall/admin/inventory/:variantId/history")
export class ShoppingmallAdminInventoryHistoryController {
  /**
   * Retrieve the complete immutable history of inventory changes for a specific product variant.
   *
   * This endpoint returns an ordered list of all inventory events (restock, order deductions, cancellations, refunds, manual adjustments) associated with the specified variant. Each entry includes the change amount, business reason, timestamp, and optional reference to the origin event (e.g., order item). The system maintains these records permanently for audit purposes, and no deletions or modifications are permitted.
   *
   * Sellers can view their own variant history, while administrators have access to all variants across the platform. The order of records is always newest to oldest (descending timestamp). This history enables accurate calculation of current stock levels by applying each change sequentially.
   *
   * This operation does not support search or filtering parameters in the request body by design. History is always returned in full chronological order with pagination, ensuring consistency and preventing ambiguity in access patterns. Any filtering must be performed by the client using the provided pagination controls.
   *
   * @param connection
   * @param variantId The unique identifier of the product variant whose inventory history is being requested. This corresponds to the variant_id field in the shopping_mall_inventory_logs table.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query shopping_mall_inventory_logs table filtered by variant_id parameter.
   * Sort results by created_at DESC to ensure newest entries appear first.
   * Apply pagination using cursor-based or offset-based pagination (offset-based as per standard).
   * Return only the fields specified in the response schema: id, change_quantity, reason, reference_id, created_at, notes.
   * Ensure no data from other tables (products, variants, sellers) is joined or included.
   * No caching allowed - this is an audit log, must always reflect real-time state.
   * Apply authorization: seller can only access their own variants; admin can access all.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("variantId")
    variantId: string,
  ): Promise<IPageIShoppingMallInventoryLog> {
    try {
      return await patchShoppingMallAdminInventoryVariantIdHistory({
        admin,
        variantId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
