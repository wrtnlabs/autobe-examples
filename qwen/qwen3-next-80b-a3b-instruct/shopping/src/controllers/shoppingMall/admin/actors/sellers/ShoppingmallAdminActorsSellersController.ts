import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallAdminActorsSellers } from "../../../../../providers/patchShoppingMallAdminActorsSellers";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { putShoppingMallAdminActorsSellersSellerId } from "../../../../../providers/putShoppingMallAdminActorsSellersSellerId";
import { deleteShoppingMallAdminActorsSellersSellerId } from "../../../../../providers/deleteShoppingMallAdminActorsSellersSellerId";

import { IPageIShoppingMallSeller } from "../../../../../api/structures/IPageIShoppingMallSeller";
import { IShoppingMallSeller } from "../../../../../api/structures/IShoppingMallSeller";

@Controller("/shoppingMall/admin/actors/sellers")
export class ShoppingmallAdminActorsSellersController {
  /**
   * Retrieve a filtered and paginated list of seller accounts from the
   * shoppingMall platform.
   *
   * This operation queries the shopping_mall_sellers table and returns a
   * paginated result set of seller records based on specified search criteria.
   * It allows admins and platform analysts to find sellers by business name,
   * status, region, or other attributes.
   *
   * The operation supports comprehensive filtering including:
   *
   * - Exact business name matching
   * - Partial business name searching
   * - Status filtering (active, suspended, pending_verification, rejected)
   * - Date range filters for creation and update timestamps
   *
   * Also supports sorting by business_name, created_at, updated_at, and status
   * in ascending or descending order.
   *
   * Response includes the complete seller profile information including
   * business_name, email, tax_id, business_address, status, created_at, and
   * updated_at fields.
   *
   * All seller records are filtered to exclude any records with deleted_at
   * populated (already deleted sellers).
   *
   * Security: This operation requires authentication as a platform admin user,
   * but the results include all seller records regardless of admin permissions
   * level.
   *
   * This is a read-only operation that does not modify any data in the
   * database. For creating or updating seller records, use the POST and PUT
   * operations respectively.
   *
   * @param connection
   * @param body Search filters and pagination parameters for querying seller
   *   records
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallSeller.IRequest,
  ): Promise<IPageIShoppingMallSeller> {
    try {
      return await patchShoppingMallAdminActorsSellers({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing seller's registration information in the shoppingMall
   * system. This operation allows administrators to modify seller account
   * details including business name, address, tax ID, and account status. For
   * security and compliance, this operation does not update sensitive
   * authentication fields like email or password_hash, which are managed
   * through separate secure workflows. The operation validates that the seller
   * account exists and is not already deleted. If the status is changed to
   * 'rejected' or 'suspended', all associated product listings are
   * automatically deactivated and customers are notified of the change. The
   * updated_at timestamp is automatically set by the system to record when the
   * modification occurred. When status changes from 'pending_verification' to
   * 'active', the system triggers background processes to validate tax
   * documents and initialize the seller's storefront. This operation is
   * governed by audit logs that record who made the changes and when, ensuring
   * full compliance with financial and e-commerce regulations.
   *
   * Note: This operation should only be used by admins for manual account
   * management. Seller self-updates occur through the separate frontend profile
   * management flow.
   *
   * Related operations: GET /actors/sellers/{sellerId} - to view current seller
   * data before modification.
   *
   * IMPORTANT: The 'deleted_at' field, if present in the schema, is not
   * modified by this operation. This is a soft-delete system, and sellers are
   * not permanently removed but marked as inactive when necessary.
   *
   * @param connection
   * @param sellerId Unique identifier of the target seller account. Must match
   *   the UUID format of the ID field in shopping_mall_sellers table.
   * @param body The updated seller information fields to be modified.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":sellerId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallSeller.IUpdate,
  ): Promise<IShoppingMallSeller> {
    try {
      return await putShoppingMallAdminActorsSellersSellerId({
        admin,
        sellerId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently remove a seller account from the shoppingMall system. Unlike
   * soft-deletion implemented through the deleted_at field, this operation
   * performs a hard delete that removes the seller's entire record from the
   * database. This should only be invoked under extreme compliance
   * circumstances, such as verified fraudulent activity, legal court orders for
   * data removal, or when a seller has been permanently revoked and all
   * associated data has been archived or transferred according to regulatory
   * requirements.
   *
   * When this operation is executed, the system will:
   *
   * - Delete the seller's record from the shopping_mall_sellers table
   * - Remove all associated seller session records from
   *   shopping_mall_seller_sessions
   * - Purge all seller-specified integration keys and credentials
   * - Archive related audit logs in a secure archival system rather than
   *   permanently deleting them
   *
   * This hard delete affects several related entities including payment
   * methods, coupons issued by this seller, and loyalty points associated with
   * this seller's account. The operation is irreversible and cannot be undone.
   *
   * Due to the irreversible nature of this operation, it is subject to
   * multi-factor administrative approval. The caller must have direct 'admin'
   * privileges, and an additional manual review by a senior compliance officer
   * is required before execution.
   *
   * This hard delete operation is exceptionally rare and should only occur
   * after careful review of the financial and legal implications. The standard
   * process for deactivating problematic sellers is to set status: 'rejected'
   * or 'suspended' using the PUT /actors/sellers/{sellerId} operation instead.
   *
   * Related operations: PUT /actors/sellers/{sellerId} - to suspend or reject a
   * seller without permanent deletion.
   *
   * IMPORTANT: Hard delete of any record is a compliance-critical action
   * reserved for extreme situations only. This operation does NOT use the
   * soft_delete_column convention and instead performs a direct database
   * deletion of the entire row.
   *
   * NOTE: This operation is fundamentally different from setting deleted_at to
   * a date, which is the standard soft-delete mechanism used by the system for
   * almost all records.
   *
   * @param connection
   * @param sellerId Unique identifier of the target seller account. Must match
   *   the UUID format of the ID field in shopping_mall_sellers table.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":sellerId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallAdminActorsSellersSellerId({
        admin,
        sellerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
