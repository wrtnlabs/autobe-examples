import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallAdminActorsAdmins } from "../../../../../providers/postShoppingMallAdminActorsAdmins";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { patchShoppingMallAdminActorsAdmins } from "../../../../../providers/patchShoppingMallAdminActorsAdmins";
import { getShoppingMallAdminActorsAdminsAdminId } from "../../../../../providers/getShoppingMallAdminActorsAdminsAdminId";
import { putShoppingMallAdminActorsAdminsAdminId } from "../../../../../providers/putShoppingMallAdminActorsAdminsAdminId";
import { deleteShoppingMallAdminActorsAdminsAdminId } from "../../../../../providers/deleteShoppingMallAdminActorsAdminsAdminId";

import { IShoppingMallAdmin } from "../../../../../api/structures/IShoppingMallAdmin";
import { IPageIShoppingMallAdmin } from "../../../../../api/structures/IPageIShoppingMallAdmin";

@Controller("/shoppingMall/admin/actors/admins")
export class ShoppingmallAdminActorsAdminsController {
  /**
   * Create a new platform administrator account with elevated privileges for
   * managing the shoppingMall platform.
   *
   * This operation allows the creation of new admin accounts, which are
   * required to perform administrative tasks such as approving/rejecting seller
   * registrations, moderating content, managing user accounts, and accessing
   * system-wide reports.
   *
   * Administrative accounts are created manually through internal processes and
   * are not accessible to regular users. The system enforces strict security
   * requirements including mandatory multi-factor authentication (MFA) and
   * encrypted password storage.
   *
   * The operation validates that the admin email is unique across all actor
   * types and follows the platform's email format requirements. Passwords must
   * meet minimum security requirements of 12 characters with mixed case,
   * numbers, and symbols.
   *
   * Upon successful creation, the system automatically sends a secure
   * onboarding email with instructions for setting up MFA. The admin account is
   * initially created in 'pending_verification' status until the new admin
   * completes the MFA setup process.
   *
   * This operation is only available to existing admins with appropriate
   * permissions and creates an audit log entry for compliance purposes.
   *
   * @param connection
   * @param body Creation data for a new platform administrator account
   *   including authentication credentials and identity information.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallAdmin.ICreate,
  ): Promise<IShoppingMallAdmin> {
    try {
      return await postShoppingMallAdminActorsAdmins({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a paginated, filtered list of all admin accounts in the
   * shoppingMall administrative system. This operation operates on the
   * shopping_mall_admins table and allows administrators with appropriate
   * permissions to search for specific admins based on email, name, or status
   * criteria.
   *
   * The response includes comprehensive admin profile information optimized for
   * administrative dashboards and audit listings. Support for pagination,
   * filtering by status (active/suspended/pending_verification), and sorting by
   * creation date or name ensures efficient management of large admin
   * populations. The system enforces strict read-access controls where only
   * authenticated users with administrative privileges can execute this
   * operation.
   *
   * This operation is critical for platform oversight and security auditing as
   * it provides complete visibility into all administrative identities on the
   * platform. The implementation leverages the existing shopping_mall_admins
   * schema and joins with related session data to provide comprehensive context
   * for each admin account while maintaining data consistency with the
   * authoritative source.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering admin
   *   accounts.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallAdmin.IRequest,
  ): Promise<IPageIShoppingMallAdmin.ISummary> {
    try {
      return await patchShoppingMallAdminActorsAdmins({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific admin account identified by
   * the adminId path parameter. This operation accesses the
   * shopping_mall_admins table to return the complete administrative profile
   * including personal details, account status, and timestamps.
   *
   * The response provides a comprehensive view of the admin's identity and
   * account health, including email, names, creation and update timestamps, and
   * current status. This detailed view is essential for administrative
   * investigations, access reviews, and security audits where full context of
   * an admin account is required.
   *
   * Access to this detailed information is restricted to other administrators
   * and follows a principle of least privilege. The sensitive nature of
   * administrative credentials means this endpoint requires elevated
   * authorization. Operations on this endpoint cannot be performed by ordinary
   * users and serve solely for platform governance and management.
   *
   * This read operation is designed to provide trustworthy, authoritative
   * information directly from the source shopping_mall_admins table with no
   * derived fields or aggregations.
   *
   * @param connection
   * @param adminId Unique identifier of the target admin account. This is a
   *   UUID that directly corresponds to the id field in the
   *   shopping_mall_admins table.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":adminId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallAdmin> {
    try {
      return await getShoppingMallAdminActorsAdminsAdminId({
        admin,
        adminId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing platform administrator account's details.
   *
   * This operation allows existing administrators to modify specific details of
   * another admin account, including name information and status (only to
   * suspend an account - admins cannot be deleted). The email address cannot be
   * changed through this operation for security reasons - if an administrator's
   * email needs to be updated, a new account must be created and the old
   * account deactivated.
   *
   * Only administrators with elevated privileges (typically system
   * super-admins) can update other admins. Regular admins cannot modify other
   * admin accounts.
   *
   * The operation validates that the adminId corresponds to an existing admin
   * account that is still active (not suspended or deleted). If the status is
   * changed from 'active' to 'suspended', the system immediately revokes all
   * active sessions and tokens for that admin to prevent unauthorized access.
   *
   * All modifications to admin accounts are logged in the system audit trail
   * with the operator's identity and timestamp for security accountability.
   *
   * Administrators and their roles are considered sensitive entity data; thus
   * the operation handles the update with appropriate access controls and
   * permission validation.
   *
   * @param connection
   * @param adminId Unique identifier of the administrator account to update.
   *   This must match the ID of an existing admin account.
   * @param body Update data for an existing platform administrator account
   *   including name fields and status change options.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":adminId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallAdmin.IUpdate,
  ): Promise<IShoppingMallAdmin> {
    try {
      return await putShoppingMallAdminActorsAdminsAdminId({
        admin,
        adminId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently remove an administrative account from the shoppingMall
   * platform.
   *
   * This operation executes a hard delete of an admin record in the
   * shopping_mall_admins table. The admin's account is completely removed from
   * the system with no possibility of recovery. All associated session records
   * and audit trails are also purged from the database.
   *
   * Security considerations: This operation requires admin-level authorization.
   * Only an authenticated admin user with elevated privileges can delete
   * another admin account. This operation bypasses all soft-delete protections
   * and cannot be reversed. After successful deletion, the admin's email
   * becomes available for new registrations. This operation should only be used
   * in cases of permanent account termination.
   *
   * Implementation details: This operation directly removes the record from the
   * shopping_mall_admins table in the database. Unlike other entities that use
   * soft-deletion (deleted_at timestamp), admin accounts are subject to hard
   * deletion for security and compliance reasons.
   *
   * Related operations: This operation is an exception to the platform's usual
   * soft-delete policy. The GET /actors/admins/{adminId} operation cannot
   * retrieve any data after this delete operation has been executed, as the
   * record is permanently removed.
   *
   * Error handling: If the specified adminId does not exist, the system will
   * return HTTP 404. If the requesting admin attempts to delete their own
   * account, the system will return HTTP 403 with error code
   * "CANNOT_DELETE_ADMIN".
   *
   * @param connection
   * @param adminId Unique identifier of the admin account to be permanently
   *   deleted.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":adminId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallAdminActorsAdminsAdminId({
        admin,
        adminId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
