  public async update(
    @TypedParam("shippingMethodId")
    shippingMethodId: string,
    @TypedBody()
    body: IShoppingMallShippingMethod.IUpdate,
  ): Promise<IShoppingMallShippingMethod> {
    shippingMethodId;
    body;
    return typia.random<IShoppingMallShippingMethod>();
  }

  /**
   * Permanently remove a shipping method from the system. This operation
   * deletes the shipping method record from the shopping_mall_shipping_methods
   * table in the database schema. This endpoint is exclusively available to
   * administrative users who have the necessary permissions to manage shipping
   * configurations.
   *
   * The operation will immediately and permanently delete the shipping method
   * record with the specified ID. This action cannot be undone and will remove
   * all references to this shipping method from the system. The deletion will
   * cascade to any dependent records that reference this shipping method, such
   * as order shippings.
   *
   * Security: This operation requires admin authorization. The system verifies
   * the authenticated admin user has the necessary permissions to manage
   * shipping configurations. The shipping method is identified by its unique ID
   * in the database.
   *
   * Behavior: After successful deletion, the shipping method will no longer be
   * available for selection in customer checkout flows, admin shipping
   * configuration panels, or reporting metrics. Any orders in progress that
   * reference this shipping method will continue to use the original shipping
   * method configuration as captured at order time.
   *
   * Related operations: List shipping methods (GET /shipping-methods), Retrieve
   * shipping method details (GET /shipping-methods/{shippingMethodId}), Create
   * shipping method (POST /shipping-methods), Update shipping method (PUT
   * /shipping-methods/{shippingMethodId}).
   *
   * @param connection
   * @param shippingMethodId Unique identifier of the target shipping method to
   *   be deleted (global scope)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
