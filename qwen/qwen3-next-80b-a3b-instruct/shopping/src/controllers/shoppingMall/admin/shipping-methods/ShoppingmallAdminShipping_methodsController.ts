  /**
   * Create a new shipping method configuration for the shopping mall platform.
   *
   * This operation enables administrators to register new shipping service
   * options that customers can select during checkout. Each shipping method
   * represents a distinct carrier service with unique characteristics such as
   * delivery timeframes, cost structures, geographic coverage, and service
   * level agreements.
   *
   * Shipping methods are stored in the shopping_mall_shipping_methods table and
   * are associated with specific service tiers, regions, and carrier partners.
   * The system automatically calculates applicable shipping costs based on the
   * selected method, order weight, destination zone, and product dimensions
   * during checkout processing.
   *
   * Each shipping method must have a unique code, name, and delivery window
   * specification. The shipping method's status determines whether it is active
   * for customer selection. Inactive methods are preserved in the system for
   * historical order reference but cannot be selected for new orders.
   *
   * This operation integrates directly with the shipping methods database table
   * and enforces validation rules including uniqueness of method codes, valid
   * delivery time ranges, and appropriate cost thresholds. The created shipping
   * method becomes immediately available for use in the customer checkout
   * workflow.
   *
   * After creation, the new shipping method may appear in customer-facing
   * shipping selection interfaces, catalog search filters, and administrative
   * reporting dashboards.
   *
   * System-generated audit logs are automatically created to track all changes
   * to shipping methods for compliance and reconciliation purposes.
   *
   * Related operations:
   *
   * - PATCH /shipping-methods: List available shipping methods
   * - PUT /shipping-methods/{methodCode}: Update an existing shipping method
   * - DELETE /shipping-methods/{methodCode}: Deactivate a shipping method
   *   (soft-delete)
   *
   * @param connection
   * @param body Configuration parameters for creating a new shipping method.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
