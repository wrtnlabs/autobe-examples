import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallSeller } from "../../../../../api/structures/IShoppingMallSeller";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { postShoppingMallAdminSellersSellerIdApprove } from "../../../../../providers/postShoppingMallAdminSellersSellerIdApprove";

@Controller("/shoppingMall/admin/sellers/:sellerId/approve")
export class ShoppingmallAdminSellersApproveController {
  /**
   * Approve a seller account that is currently pending administrator review. This operation transitions the seller's status from 'pending_approval' to 'approved', thereby granting the seller full privileges to list products, manage inventory, and receive orders.
   *
   * This endpoint is exclusively available to administrators or super administrators, as per the Authorization agent's configuration. Upon approval, the system automatically creates an immutable snapshot of the seller's profile as it existed at the time of approval, including shop name, description, and logo URL. This snapshot is preserved in accordance with the snapshot principle documented in 14-snapshot-principle.md.
   *
   * The initial seller registration process requires email confirmation followed by administrator evaluation. When an administrator approves the seller, the system notifies the seller through email with the message: "Your application has been approved. You may now list products." The approval action is recorded in the audit trail with the administrator ID, IP address, and timestamp.
   *
   * This operation serves as the final step in the seller onboarding workflow. After approval, the seller gains access to the seller dashboard and can begin submitting product listings. Existing rejection reasons are cleared, and the seller can reapply if previously rejected. Previous refusal history is retained for compliance but does not interfere with approval.
   *
   * This endpoint does not modify the seller's profile directly — it only changes the approval status and triggers the snapshot creation. Profile updates must be handled through PUT /sellers/me. Prior to approval, the seller account is inactive and cannot engage in commerce on the platform.
   *
   * @param connection
   * @param sellerId Unique identifier of the seller account to be approved.
   * @x-autobe-specification Query shopping_mall_sellers table with sellerId matching path parameter. Verify seller status is 'pending_approval'. Set status to 'approved', clear any rejection_reason and deleted_at if present. Create an immutable seller profile snapshot with current profile data (shopName, shopDescription, logoImageUrl), action: 'approve', actorId (from auth context), and timestamp. Send notification email to seller. Log approval event in audit table with sellerId, adminId, IP, and action.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("sellerId")
    sellerId: string,
  ): Promise<IShoppingMallSeller.ISummary> {
    try {
      return await postShoppingMallAdminSellersSellerIdApprove({
        admin,
        sellerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
