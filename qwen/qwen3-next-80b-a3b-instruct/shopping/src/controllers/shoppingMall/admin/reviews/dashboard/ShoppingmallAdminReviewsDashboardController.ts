import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallReviewSnapshot } from "../../../../../api/structures/IShoppingMallReviewSnapshot";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminReviewsDashboard } from "../../../../../providers/getShoppingMallAdminReviewsDashboard";

@Controller("/shoppingMall/admin/reviews/dashboard")
export class ShoppingmallAdminReviewsDashboardController {
  /**
   * Retrieve aggregated metrics and statistics for all product reviews across the platform.
   *
   * This dashboard endpoint provides a high-level overview of review activity, based on the immutable snapshot policy defined in 13-reviews-and-ratings.md. It calculates and returns summaries of review volume, average rating, and review status distribution (active vs user-deleted vs admin-deleted), enabling administrators and seller managers to monitor content integrity and customer feedback trends without exposing individual review content.
   *
   * The system aggregates data from the Reviews table, respecting the rules for dynamic rating calculation: user-deleted reviews retain their numeric rating in the average, while admin-deleted reviews are fully excluded from all calculations. Snapshots preserve all edits and deletions as historical records accessible only to authorized actors per the Snapshot Principle.
   *
   * This endpoint does not return individual reviews — it returns only summary aggregates to protect privacy and ensure compliance with data retention policies.
   *
   * Security note: This endpoint is authorized only for admin and seller roles. Customers do not have access to this aggregation endpoint. Cache policy enforces 1-minute TTL to enable real-time updates under load, as reviews can be edited or deleted dynamically.
   *
   * Related operations: GET /products/{productId}/reviews retrieves individual product reviews; POST /products/{productId}/reviews creates new reviews; DELETE /reviews/{reviewId} deletes a review and triggers snapshot preservation.
   *
   * @param connection
   * @x-autobe-specification Perform a database aggregation query across the shopping_mall_reviews table. Calculate: total count of non-deleted reviews; total count of user-deleted reviews; total count of admin-deleted reviews; average rating of non-deleted reviews (rounded to one decimal place). Join with shopping_mall_products to verify product existence (temporary filter). Avoid including individual review text or customer details. Use Prisma's aggregate functions: count(), avg(), groupBy(). Apply caching for 60 seconds. Do not use cursor pagination — return full summaries.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
  ): Promise<IShoppingMallReviewSnapshot> {
    try {
      return await getShoppingMallAdminReviewsDashboard({
        admin,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
