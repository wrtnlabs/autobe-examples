import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { deleteShoppingMallAdminReviewsReviewId } from "../../../../providers/deleteShoppingMallAdminReviewsReviewId";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";

@Controller("/shoppingMall/admin/reviews/:reviewId")
export class ShoppingmallAdminReviewsController {
  /**
   * Permanently delete a product review from the shoppingMall platform.
   *
   * This operation performs a hard delete of a review record from the
   * shopping_mall_reviews table. Unlike soft deletion which marks records as
   * deleted with a timestamp, this operation completely removes the review from
   * the database with no possibility of recovery.
   *
   * This deletion is permanent and irreversible. All associated review images
   * in the shopping_mall_review_images table are also automatically deleted
   * through database foreign key cascading when a parent review is deleted.
   *
   * Security: Only the original review creator or an admin moderator can delete
   * a review. The operation verifies the requesting user's identity against the
   * review's shopping_mall_customer_id field or checks for admin privileges.
   *
   * This operation is designed for extreme cases such as user account
   * termination, extensive moderation violations, or legal compliance
   * requirements where complete data erasure is mandated.
   *
   * @param connection
   * @param reviewId Unique identifier of the target review to be deleted. This
   *   is a UUID that corresponds to the primary key in the
   *   shopping_mall_reviews table.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallAdminReviewsReviewId({
        admin,
        reviewId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
