  /**
   * Upload one or more images to associate with a specific product in the
   * shopping mall platform. This operation creates new product image records
   * linked to the specified product entity from the shopping_mall_products
   * table. Each uploaded image is stored as a record in the
   * shopping_mall_product_images table with a reference to the product ID, a
   * unique identifier, and metadata about the image file.
   *
   * This operation supports multiple image uploads in a single request and
   * automatically assigns the images to the product with the matching productId
   * path parameter. The system validates that the referenced product exists and
   * that the requesting actor has appropriate permissions to modify the product
   * images. Seller and admin actors can upload images for products they manage,
   * while customers can upload images only for products they have purchased.
   *
   * Each uploaded image must be a valid image file (JPEG, PNG, GIF) with a
   * maximum size of 5MB. The system will generate unique file names and store
   * the images in the designated cloud storage. The response contains the full
   * metadata of all uploaded images, including their unique IDs, URLs, and
   * ordering positions.
   *
   * Security: Only authenticated users with appropriate roles can upload
   * images. The system verifies product ownership and prevents unauthorized
   * image uploads. The product_id parameter must match an existing product in
   * the shopping_mall_products table.
   *
   * Related operations: GET /products/{productId}/images to retrieve product
   * images, PATCH /products/{productId}/images/{imageId} to update image order
   * or alt text, DELETE /products/{productId}/images/{imageId} to remove an
   * image.
   *
   * Validation: The system checks for valid file types, file sizes, and
   * existence of the target product. If the product does not exist, the
   * operation returns a 404 error. File names that match prohibited patterns
   * (such as executable files or scripts) are rejected.
   *
   * Business logic: Images are assigned sequential ordering positions based on
   * upload order. The first uploaded image becomes the primary image for the
   * product. Products can have a maximum of 10 images.
   *
   * Error handling: Invalid file types return 400 Bad Request. Files exceeding
   * size limits return 413 Payload Too Large. If the product is not found or
   * the user lacks permission, a 403 Forbidden or 404 Not Found error is
   * returned.
   *
   * @param connection
   * @param productId Unique identifier of the target product being uploaded to.
   *   This must correspond to an existing product in the shopping_mall_products
   *   table with a primary key in snake_case format.
   * @param body Form data containing one or more image files to upload for the
   *   specified product. Each file must be a valid image format (JPEG, PNG,
   *   GIF) with dimensions appropriate for product display.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
