import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallAdminProductsProductIdImages } from "../../../../../providers/patchShoppingMallAdminProductsProductIdImages";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { putShoppingMallAdminProductsProductIdImagesImageId } from "../../../../../providers/putShoppingMallAdminProductsProductIdImagesImageId";
import { deleteShoppingMallAdminProductsProductIdImagesImageId } from "../../../../../providers/deleteShoppingMallAdminProductsProductIdImagesImageId";

import { IPageIShoppingMallProductImage } from "../../../../../api/structures/IPageIShoppingMallProductImage";
import { IShoppingMallProductImage } from "../../../../../api/structures/IShoppingMallProductImage";

@Controller("/shoppingMall/admin/products/:productId/images")
export class ShoppingmallAdminProductsImagesController {
  /**
   * Retrieve a paginated and filtered list of product images associated with a
   * specific product. This endpoint provides a comprehensive view of all visual
   * assets linked to the product, enabling efficient browsing and management of
   * product media.
   *
   * The operation queries the shopping_mall_product_images table to return
   * images associated with the specified product_id. Results can be filtered by
   * primary status, sort order, or other criteria to facilitate efficient media
   * selection. The response includes a pagination structure to handle products
   * with large image collections.
   *
   * Images returned may include both primary and secondary images, ordered by
   * sort_order ascending, with primary images (is_primary=true) appearing first
   * by default. Only images related to the specified product (and not its
   * variants) are returned. The operation excludes deleted images (where
   * deleted_at is not null).
   *
   * This operation is commonly paired with GET /products/{productId} to present
   * a complete product view, and with POST /products/{productId}/images to
   * upload new images. The Shopify's media management approach inspired this
   * design for scalable image handling.
   *
   * Security enforcement ensures the requesting user has appropriate
   * permissions to view the product images via the authorizationActors. The
   * result set can be used by UI components to generate gallery views, carousel
   * sliders, or media selection interfaces.
   *
   * @param connection
   * @param productId Unique identifier of the product whose images are being
   *   retrieved. Must reference a valid shopping_mall_products.id. All returned
   *   images must be directly associated with this product, not its variants.
   * @param body Search, filter, and pagination parameters for product images
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallProductImage.IRequest,
  ): Promise<IPageIShoppingMallProductImage> {
    try {
      return await patchShoppingMallAdminProductsProductIdImages({
        admin,
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update the primary image of a product. This operation modifies the existing
   * image record associated with a specific product and image identifier. The
   * operation updates all metadata including alt_text, sort_order, and
   * is_primary flags while preserving the existing image file reference. The
   * product must be in 'published' or 'draft' status for image updates. This
   * update triggers validation to ensure the image is properly linked to the
   * product and follows size and format requirements. The operation is
   * idempotent - applying the same update multiple times produces identical
   * results. Security: Only the product's seller or an admin can update product
   * images. The authentication token is used to verify ownership or
   * administrative privileges. Related operations: DELETE
   * /products/{productId}/images/{imageId} (to remove an image), GET
   * /products/{productId}/images (to list all images).
   *
   * Implementation note: This operation maps directly to the
   * shopping_mall_product_images table in the Prisma schema. The image_url
   * field is never modified by this operation - only metadata fields (alt_text,
   * sort_order, is_primary) are updated. The product's status must be checked
   * before update to ensure it is not 'archived'.
   *
   * @param connection
   * @param productId Unique identifier of the target product. This must match
   *   the product's ID in the shopping_mall_products table.
   * @param imageId Unique identifier of the target image. This must match the
   *   image's ID in the shopping_mall_product_images table.
   * @param body Updated metadata for the product image.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":imageId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedParam("imageId")
    imageId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallProductImage.IUpdate,
  ): Promise<IShoppingMallProductImage> {
    try {
      return await putShoppingMallAdminProductsProductIdImagesImageId({
        admin,
        productId,
        imageId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently remove a product image record from the system. This operation
   * deletes the metadata reference to an image but does not delete the actual
   * image file from storage. The image file remains accessible via its URL
   * until manually purged by system maintenance. This operation can only be
   * performed on images associated with products that are not archived. The
   * product can be in 'published', 'draft', or 'archived' status for deletion.
   * This is a soft delete operation - the image record is marked with a
   * deleted_at timestamp and is preserved for audit purposes. Product owners or
   * administrators can perform this operation to clean up outdated or
   * inappropriate images. After deletion, the image will no longer appear in
   * product image lists. Security: Only the product's seller or an admin can
   * delete product images. The authentication token is used to verify ownership
   * or administrative privileges. Related operations: PUT
   * /products/{productId}/images/{imageId} (to update image metadata), GET
   * /products/{productId}/images (to list all images).
   *
   * @param connection
   * @param productId Unique identifier of the target product. This must match
   *   the product's ID in the shopping_mall_products table.
   * @param imageId Unique identifier of the target image. This must match the
   *   image's ID in the shopping_mall_product_images table.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":imageId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedParam("imageId")
    imageId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallAdminProductsProductIdImagesImageId({
        admin,
        productId,
        imageId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
