import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallAdminOrdersOrderNumberItems } from "../../../../../providers/patchShoppingMallAdminOrdersOrderNumberItems";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { putShoppingMallAdminOrdersOrderNumberItemsId } from "../../../../../providers/putShoppingMallAdminOrdersOrderNumberItemsId";
import { deleteShoppingMallAdminOrdersOrderNumberItemsId } from "../../../../../providers/deleteShoppingMallAdminOrdersOrderNumberItemsId";

import { IPageIShoppingMallOrderItem } from "../../../../../api/structures/IPageIShoppingMallOrderItem";
import { IShoppingMallOrderItem } from "../../../../../api/structures/IShoppingMallOrderItem";

@Controller("/shoppingMall/admin/orders/:orderNumber/items")
export class ShoppingmallAdminOrdersItemsController {
  /**
   * Retrieves all items within a specific order, providing comprehensive
   * product details and pricing information at time of purchase.
   *
   * This operation queries the shopping_mall_order_items table and returns a
   * list of all items associated with the specified order. The response
   * includes each item's quantity, unit price (as it was at purchase time),
   * item total, and product variant details, enabling full historical order
   * auditing.
   *
   * The operation supports pagination and sorting of order items by product
   * name, quantity, or unit price. It does not support filtering by product
   * category or other criteria as order items are always retrieved in context
   * of their parent order.
   *
   * This endpoint serves customer service, accounting, and dispute resolution
   * workflows where complete item-level order history must be verified.
   *
   * Security: Read access is permitted to the order's customer, the associated
   * seller, and platform administrators.
   *
   * Related operations: GET /orders/{orderNumber} (retrieve order summary),
   * PATCH /orders/{orderNumber} (search orders).
   *
   * @param connection
   * @param orderNumber Unique order identifier in format ORD-YYYYMMDD-NNNNN
   *   (global scope).
   * @param body Search parameters for filtering and sorting order items.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("orderNumber")
    orderNumber: string,
    @TypedBody()
    body: IShoppingMallOrderItem.IRequest,
  ): Promise<IPageIShoppingMallOrderItem.ISummary> {
    try {
      return await patchShoppingMallAdminOrdersOrderNumberItems({
        admin,
        orderNumber,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update a specific order item within an order.
   *
   * This operation allows users or system agents to modify the quantity or
   * special notes of an existing order item. The operation requires the order
   * number and item ID to identify the specific order item for modification.
   *
   * The update is permitted only when the order status is in a modifiable state
   * (draft, pending_payment). Once an order reaches confirmed or paid status,
   * further modifications to items are prohibited to ensure financial
   * integrity.
   *
   * This operation works on the shopping_mall_order_items model, where the
   * unit_price, quantity, and notes fields can be updated. The unit_price
   * defaults to the current product variant price at time of update, but can be
   * overridden with special approval for promotional adjustments.
   *
   * The item_total is computed automatically as quantity × unit_price and
   * cannot be manually modified. This ensures audit trail integrity for
   * financial accuracy. Any change to quantity or unit_price triggers a
   * recalculation of the overall order's subtotal and total_amount through
   * automatic cascading updates.
   *
   * This operation is read-only for customers when the order status is
   * confirmed or beyond, and requires administrative privileges for updates
   * when status is paid or higher. Only sellers associated with the items or
   * system administrators can perform updates after confirmation.
   *
   * Related operations: GET /orders/{orderNumber}/items/{id} (retrieval),
   * DELETE /orders/{orderNumber}/items/{id} (removal).
   *
   * @param connection
   * @param orderNumber Unique order identifier in format ORD-YYYYMMDD-NNNNN.
   *   Must be globally unique. Used to identify the parent order containing the
   *   item.
   * @param id Unique identifier of the specific order item. This is the
   *   internal database ID for the shopping_mall_order_items record to be
   *   updated.
   * @param body Fields to update in the order item.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":id")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("orderNumber")
    orderNumber: string,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallOrderItem.IUpdate,
  ): Promise<IShoppingMallOrderItem> {
    try {
      return await putShoppingMallAdminOrdersOrderNumberItemsId({
        admin,
        orderNumber,
        id,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a specific order item from an order.
   *
   * This operation removes a specific item from an order, recalculating the
   * order totals accordingly. It requires both the order number and item ID to
   * uniquely identify the item to be removed.
   *
   * Deletion is permitted only when the order status is in a modifiable state
   * (draft, pending_payment). Once an order has been confirmed or paid,
   * individual item deletion is disabled to maintain financial and inventory
   * integrity. In such cases, customers must initiate a return request
   * instead.
   *
   * This operation affects the shopping_mall_order_items model. Upon deletion,
   * the item's quantity is removed from the order's subtotal, and the tax,
   * shipping, and total amounts are automatically recalculated to reflect the
   * updated order composition.
   *
   * The system preserves a record of deleted items for audit purposes through
   * the shopping_mall_order_status_history table, but the
   * shopping_mall_order_items record is physically removed from the database.
   *
   * This operation does not restore inventory to the warehouse because the item
   * was never reserved in inventory during the draft/pending_payment stage. If
   * the order was already paid and delivery processing began, the customer must
   * navigate the return workflow instead of item deletion.
   *
   * Following deletion, the system sends a notification to the seller to update
   * their fulfillment preparation and to the customer to confirm the change.
   *
   * Related operations: PUT /orders/{orderNumber}/items/{id} (update), GET
   * /orders/{orderNumber}/items (retrieve all items).
   *
   * @param connection
   * @param orderNumber Unique order identifier in format ORD-YYYYMMDD-NNNNN.
   *   Must be globally unique. Used to identify the parent order containing the
   *   item.
   * @param id Unique identifier of the specific order item. This is the
   *   internal database ID for the shopping_mall_order_items record to be
   *   deleted.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":id")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("orderNumber")
    orderNumber: string,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallOrderItem> {
    try {
      return await deleteShoppingMallAdminOrdersOrderNumberItemsId({
        admin,
        orderNumber,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
