import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia from "typia";
import { getShoppingMallAdminOrdersOrderNumberPayment } from "../../../../../providers/getShoppingMallAdminOrdersOrderNumberPayment";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { putShoppingMallAdminOrdersOrderNumberPayment } from "../../../../../providers/putShoppingMallAdminOrdersOrderNumberPayment";

import { IShoppingMallOrderPayment } from "../../../../../api/structures/IShoppingMallOrderPayment";

@Controller("/shoppingMall/admin/orders/:orderNumber/payment")
export class ShoppingmallAdminOrdersPaymentController {
  /**
   * Retrieve the payment details for a specific order using its unique order
   * number.
   *
   * This operation fetches the complete payment information associated with an
   * order, including payment status, amount, currency, transaction ID, and
   * processing timestamp. The payment record is maintained in a 1:1
   * relationship with the order entity in the database, and this endpoint
   * provides read-only access to this financial data.
   *
   * Security: This operation requires authentication as the order owner or an
   * administrator. The order number serves as a human-readable identifier that
   * maps to the internal UUID-based order ID. The payment details are returned
   * in the order's currency and include all financial metadata recorded at the
   * time of payment processing.
   *
   * Implementation: The system joins the shopping_mall_orders table with the
   * shopping_mall_order_payments table using the order_number as a lookup key
   * and returns a structured payment record with all relevant financial
   * fields.
   *
   * Related operations: PUT /orders/{orderNumber}/payment (update payment
   * status for pre-authorized transactions), GET /orders/{orderNumber}
   * (retrieve order summary including payment status).
   *
   * @param connection
   * @param orderNumber Unique human-readable identifier for the order in format
   *   ORD-YYYYMMDD-NNNNN. Must exactly match the order_number field in the
   *   shopping_mall_orders table.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("orderNumber")
    orderNumber: string,
  ): Promise<IShoppingMallOrderPayment> {
    try {
      return await getShoppingMallAdminOrdersOrderNumberPayment({
        admin,
        orderNumber,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update the payment status for a specific order using its unique order
   * number.
   *
   * This operation allows internal systems and authorized administrators to
   * update the payment status of an order, typically for handling payment
   * gateway failures, manual payment confirmations, or fraud review outcomes.
   * The payment status can transition between: pending, processing, authorized,
   * captured, failed, refunded, or chargeback.
   *
   * Security: This operation can only be performed by system services or
   * administrators. Regular users cannot update payment status; this is
   * strictly a backend administrative function. The operation is idempotent and
   * validates that the target order exists and is in a state that permits
   * payment status changes.
   *
   * Business Logic: Changes to payment status trigger downstream workflow
   * events like order status updates, inventory reservation adjustments, and
   * notification generation. This endpoint does not process real payments; it
   * updates the system's record of payment status based on external payment
   * gateway events.
   *
   * Implementation: The system updates the shopping_mall_order_payments table
   * with the new payment_status value and logs the change in the
   * shopping_mall_order_status_history table. The payment amount and currency
   * remain immutable once recorded.
   *
   * Related operations: GET /orders/{orderNumber}/payment (retrieve payment
   * details), GET /orders/{orderNumber} (retrieve order summary with current
   * payment status).
   *
   * @param connection
   * @param orderNumber Unique human-readable identifier for the order in format
   *   ORD-YYYYMMDD-NNNNN. Must exactly match the order_number field in the
   *   shopping_mall_orders table.
   * @param body New payment status and optional approval details for the order
   *   payment.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("orderNumber")
    orderNumber: string,
    @TypedBody()
    body: IShoppingMallOrderPayment.IUpdate,
  ): Promise<IShoppingMallOrderPayment> {
    try {
      return await putShoppingMallAdminOrdersOrderNumberPayment({
        admin,
        orderNumber,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
