import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia from "typia";
import { deleteShoppingMallAdminOrdersOrderNumber } from "../../../../providers/deleteShoppingMallAdminOrdersOrderNumber";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";

@Controller("/shoppingMall/admin/orders/:orderNumber")
export class ShoppingmallAdminOrdersController {
  /**
   * Permanently removes an order record from the system, marking it as
   * irreversibly deleted.
   *
   * This operation executes a hard delete on the shopping_mall_orders table,
   * removing all associated order data permanently from the database. Unlike
   * soft deletion (which only sets a deleted_at timestamp), this operation
   * erases the order and all its related records in a single atomic
   * transaction.
   *
   * Due to the critical nature of order data in financial and audit systems,
   * this operation is restricted to administrators only. Once executed, the
   * order cannot be recovered, and all related entities (order items, payments,
   * shipping records, etc.) are also permanently removed.
   *
   * This endpoint exists only for regulatory compliance scenarios where data
   * must be completely eradicated under legal requirements.
   *
   * Security: This operation triggers comprehensive audit logging and requires
   * explicit admin authorization.
   *
   * Related operations: DELETE /orders/{orderNumber} (soft delete), PATCH
   * /orders/{orderNumber} (update status).
   *
   * @param connection
   * @param orderNumber Unique order identifier in format ORD-YYYYMMDD-NNNNN
   *   (global scope).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("orderNumber")
    orderNumber: string,
  ): Promise<void> {
    try {
      return await deleteShoppingMallAdminOrdersOrderNumber({
        admin,
        orderNumber,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
