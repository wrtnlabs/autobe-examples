import { Controller } from "@nestjs/common";
import { TypedRoute } from "@nestia/core";
import typia from "typia";
import { getShoppingMallAdminAccessLogs } from "../../../../../providers/getShoppingMallAdminAccessLogs";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";

import { IPageIShoppingMallAccessLog } from "../../../../../api/structures/IPageIShoppingMallAccessLog";

@Controller("/shoppingMall/admin/access/logs")
export class ShoppingmallAdminAccessLogsController {
  /**
   * Retrieve a paginated list of all access logs from the shoppingMall system.
   * This operation queries the shopping_mall_access_logs table to provide a
   * comprehensive security audit trail of all authentication events.
   *
   * The operation supports advanced filtering by actor type ('customer',
   * 'seller', 'admin'), action type ('login', 'logout', 'session_refresh',
   * 'token_regeneration'), application ('web_portal', 'mobile_app',
   * 'admin_dashboard'), and time range. Results are sorted chronologically with
   * support for pagination.
   *
   * Security implications: This operation requires administrative authorization
   * to prevent unauthorized access to security audit data. The logs contain
   * sensitive information about user authentication patterns and system access,
   * making this a critical compliance feature for SOC 2, ISO 27001, and
   * financial regulations.
   *
   * All access logs are immutable and append-only. This operation retrieves
   * historical records for forensic analysis, security investigations, and
   * compliance reporting purposes.
   *
   * Related operations: This complements the data-change-logs operation which
   * tracks modifications to business data, while this operation tracks system
   * access patterns.
   *
   * @param connection
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
  ): Promise<IPageIShoppingMallAccessLog> {
    try {
      return await getShoppingMallAdminAccessLogs({
        admin,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
