import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallSeller } from "../../../../../../api/structures/IShoppingMallSeller";
import { AdminAuth } from "../../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../../decorators/payload/AdminPayload";
import { postShoppingMallAdminAdminsSellersSellerIdUnsuspend } from "../../../../../../providers/postShoppingMallAdminAdminsSellersSellerIdUnsuspend";

@Controller("/shoppingMall/admin/admins/sellers/:sellerId/unsuspend")
export class ShoppingmallAdminAdminsSellersUnsuspendController {
  /**
   * Restore a suspended seller's account to active status for platform operation.
   *
   * This operation is restricted to administrators with appropriate privileges and is used to reverse a previous suspension action. When executed, the system will change the seller's account status from 'suspended' to 'active', thereby restoring their ability to log in, manage products, and receive order notifications. This action is irreversible without administrative oversight and must be logged for audit compliance.
   *
   * The seller's shop visibility is immediately restored across all platform interfaces, including product listings and search results. No customer-facing notifications are automatically sent, but administrators may choose to communicate the reinstatement directly. The system generates a snapshot preserving the seller's state prior to unsuspension per the snapshot principle documentation.
   *
   * Security: Only administrators with elevated privileges can perform this action. The sellerId must belong to a currently suspended seller account. If the seller is not suspended or the sellerId does not exist, the system will return a 404 error.
   *
   * This operation has no effect on order history, previous cancellations, or outstanding refund requests. It only modifies the seller's access permissions within the system. Related operations: POST /admins/sellers/{sellerId}/suspend (to suspend) and GET /sellers/manage (to view suspension status).
   *
   * @param connection
   * @param sellerId Unique identifier of the seller account to be unsuspended.
   * @x-autobe-specification Update the seller record in shopping_mall_sellers table setting is_suspended to false and update_at timestamp. Create a seller profile snapshot capturing the seller's status before update (is_suspended: true to false). Log administrative action with admin ID and timestamp.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("sellerId")
    sellerId: string,
  ): Promise<IShoppingMallSeller> {
    try {
      return await postShoppingMallAdminAdminsSellersSellerIdUnsuspend({
        admin,
        sellerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
