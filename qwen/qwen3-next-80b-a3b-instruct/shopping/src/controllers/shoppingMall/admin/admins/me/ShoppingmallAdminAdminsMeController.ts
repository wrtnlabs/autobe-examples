import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallAdmin } from "../../../../../api/structures/IShoppingMallAdmin";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminAdminsMe } from "../../../../../providers/getShoppingMallAdminAdminsMe";
import { putShoppingMallAdminAdminsMe } from "../../../../../providers/putShoppingMallAdminAdminsMe";

@Controller("/shoppingMall/admin/admins/me")
export class ShoppingmallAdminAdminsMeController {
  /**
   * Retrieve the authenticated administrator's profile details.
   *
   * This operation returns the profile information of the currently authenticated admin user. The response includes essential information such as admin identifier, email address, and administrative role level (regular or super). This endpoint serves administrative users who need to view their own profile and affiliation with the platform.
   *
   * Security considerations: This endpoint does not expose sensitive credentials, tokens, or permissions. It returns only non-secret attributes that identify the admin within the system. Access requires a valid JWT token with admin role.
   *
   * The operation retrieves data from the shopping_mall_admins table in the database, specifically the fields: admin_id, email, and admin_type. The user relationship is resolved to provide email information.
   *
   * For security reasons, this endpoint does not return any nested arrays, such as dependent roles or audit histories. Related administrator operations (e.g., managing other admins) must use distinct endpoints and are subject to role-based authorization. This endpoint is strictly read-only and self-referential.
   *
   * No dependencies on other API operations are required for this endpoint to function. It operates independently based on the authentication context provided by the JWT token.
   *
   * @param connection
   * @x-autobe-specification Retrieve the admin profile from the shopping_mall_admins table using the authenticated user's ID from the JWT token. Join with the users table to get the email. Return only admin_id, email, and admin_type fields. Do not return any other fields like passwords, tokens, or audit information. Use the service prefix 'ShoppingMall' to build the response type IShoppingMallAdmin. Return 401 if no valid admin token, 403 if not an admin role.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @AdminAuth()
    admin: AdminPayload,
  ): Promise<IShoppingMallAdmin> {
    try {
      return await getShoppingMallAdminAdminsMe({
        admin,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update the current authenticated administrator's profile information.
   *
   * This operation allows administrators to modify their own profile details, specifically their name and email address. The request must include a valid JWT authentication token that corresponds to the administrator's account. The operation ensures that the administrator can only update their own profile and not those of other system users.
   *
   * The implementation requires verification of JWT token integrity and authentication success before any updates occur. Email address updates are subject to uniqueness validation across all administrator records to prevent duplicate contacts. The update operation is performed within a database transaction to ensure data consistency.
   *
   * Security considerations include immediate invalidation of all existing sessions upon email change, as this represents a critical security event that requires re-authentication. The operation does not permit modification of administrative privileges, permissions, or role assignments through this endpoint.
   *
   * This operation complements the system's administrative access control by providing a self-service profile management interface while maintaining strict separation between profile information and account privileges.
   *
   * @param connection
   * @param body Update fields for the administrator's profile
   * @x-autobe-specification Update the authenticated administrator's profile using the user's JWT token for authentication. Query shopping_mall_admins table for the admin with ID matching the authenticated user from the JWT token. Update only the name and email fields if provided in the request body. Validate that the new email is unique across all administrators. Apply transaction to ensure atomic update. Return updated admin object with modified fields. Do not allow role or privilege modifications through this endpoint.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallAdmin.IUpdate,
  ): Promise<IShoppingMallAdmin> {
    try {
      return await putShoppingMallAdminAdminsMe({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
