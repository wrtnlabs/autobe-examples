import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia from "typia";
import { postShoppingMallAdminPromotionsCoupons } from "../../../../../providers/postShoppingMallAdminPromotionsCoupons";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { putShoppingMallAdminPromotionsCouponsCouponCode } from "../../../../../providers/putShoppingMallAdminPromotionsCouponsCouponCode";
import { deleteShoppingMallAdminPromotionsCouponsCouponCode } from "../../../../../providers/deleteShoppingMallAdminPromotionsCouponsCouponCode";

import { IShoppingMallCoupon } from "../../../../../api/structures/IShoppingMallCoupon";

@Controller("/shoppingMall/admin/promotions/coupons")
export class ShoppingmallAdminPromotionsCouponsController {
  /**
   * Create a new promotional coupon code for customer discounts. This operation
   * allows platform administrators to generate unique coupon codes that
   * customers can use during checkout to receive discounts on their orders.
   * Each coupon must specify either a fixed discount amount or a percentage
   * discount, along with validity period, usage limits, and eligibility
   * criteria.
   *
   * The coupon creation process validates that the specified code is unique
   * across the system and that discount parameters are properly configured
   * (exactly one of discount_amount or discount_percentage must be set, but not
   * both). The coupon status is set to 'active' by default upon creation,
   * making it immediately available for redemption.
   *
   * This operation requires admin authentication as only authorized personnel
   * can create promotional coupons. The system automatically logs the creation
   * event for audit purposes, and the newly created coupon is immediately
   * available in the promotion system for customer use.
   *
   * Related operations: GET /promotions/coupons/{couponCode} to view coupon
   * details, PUT /promotions/coupons/{couponCode} to update coupon details, and
   * POST /promotions/coupons/{couponCode}/redeem to process customer
   * redemption.
   *
   * @param connection
   * @param body Creation data for a new promotional coupon.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallCoupon.ICreate,
  ): Promise<IShoppingMallCoupon> {
    try {
      return await postShoppingMallAdminPromotionsCoupons({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing promotional coupon's details. This operation allows
   * platform administrators to modify the configuration of an existing coupon
   * code, including changing its discount amount or percentage, adjusting
   * validity dates, or modifying usage limits.
   *
   * Important requirements:
   *
   * - The coupon code must be unique and cannot be changed once created (the code
   *   in the path is immutable)
   * - Exactly one of discount_amount or discount_percentage must be specified,
   *   but not both
   * - Discount_amount must be a non-negative value (≥ 0)
   * - Discount_percentage must be between 0.1 and 100.0
   * - Min_order_value must be greater than 0 if specified
   * - Max_usage_count must be a positive integer
   * - Valid_from must precede valid_until
   * - Status can be changed to 'expired' or 'limited_exceeded' but not back to
   *   'active' once changed
   *
   * The operation validates all constraints before updating and returns the
   * complete updated coupon record. Changes are immediately reflected in the
   * system and affect any future redemption attempts.
   *
   * For historical reasons, coupon redemption records remain immutable once
   * created - this update only affects future redemptions of the same coupon
   * code.
   *
   * Admin authorization is required for this operation as it modifies
   * promotional incentives that impact revenue.
   *
   * Related operations: GET /promotions/coupons/{couponCode} to view coupon
   * details, POST /promotions/coupons to create new coupons, and POST
   * /promotions/coupons/{couponCode}/redeem to process customer redemption.
   *
   * @param connection
   * @param couponCode Unique alphanumeric coupon code that identifies the
   *   coupon to update. Must exactly match an existing coupon code in the
   *   system. This identifier is case-insensitive and URL-safe.
   * @param body Updated configuration data for the existing coupon.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":couponCode")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("couponCode")
    couponCode: string,
    @TypedBody()
    body: IShoppingMallCoupon.IUpdate,
  ): Promise<IShoppingMallCoupon> {
    try {
      return await putShoppingMallAdminPromotionsCouponsCouponCode({
        admin,
        couponCode,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently remove a coupon from the promotional system.
   *
   * This operation permanently deletes a coupon record from the
   * shopping_mall_coupons table in the database. The coupon code specified in
   * the path parameter is searched and removed entirely from the system.
   *
   * This is a hard delete operation that removes all traces of the coupon,
   * including its association with any promotional campaign and its redemption
   * history. Once deleted, the coupon code cannot be reused or recovered.
   *
   * The operation validates that the coupon exists and is not currently in
   * active use (no pending redemptions) before deletion. Admins performing this
   * action should ensure the coupon is no longer needed for historical or
   * accounting purposes.
   *
   * Note: This differs from marking a coupon as expired or inactive - this
   * deletes the record completely.
   *
   * The coupon code must be provided in the URL path as {couponCode}.
   *
   * Related operations:
   *
   * - GET /promotions/coupons/{couponCode} - Retrieve coupon details
   * - PATCH /promotions/coupons - Search for coupons
   * - POST /promotions/coupons - Create new coupons
   *
   * @param connection
   * @param couponCode The unique alphanumeric code of the coupon to be
   *   permanently deleted from the system. This code must match exactly with
   *   the coupon.code field in the shopping_mall_coupons table. It is
   *   case-insensitive in matching but preserved in storage.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":couponCode")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("couponCode")
    couponCode: string,
  ): Promise<void> {
    try {
      return await deleteShoppingMallAdminPromotionsCouponsCouponCode({
        admin,
        couponCode,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
