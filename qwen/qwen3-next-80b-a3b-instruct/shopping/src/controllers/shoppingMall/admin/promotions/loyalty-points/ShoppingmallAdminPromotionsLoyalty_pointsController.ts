import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallAdminPromotionsLoyaltyPoints } from "../../../../../providers/patchShoppingMallAdminPromotionsLoyaltyPoints";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminPromotionsLoyaltyPointsLoyaltyPointId } from "../../../../../providers/getShoppingMallAdminPromotionsLoyaltyPointsLoyaltyPointId";

import { IPageIShoppingMallLoyaltyPointTransaction } from "../../../../../api/structures/IPageIShoppingMallLoyaltyPointTransaction";
import { IShoppingMallLoyaltyPointTransaction } from "../../../../../api/structures/IShoppingMallLoyaltyPointTransaction";

@Controller("/shoppingMall/admin/promotions/loyalty-points")
export class ShoppingmallAdminPromotionsLoyalty_pointsController {
  /**
   * Retrieve paginated list of loyalty point transactions with advanced
   * filtering capabilities.
   *
   * This operation queries the shopping_mall_loyalty_point_transactions table
   * to return a paged collection of loyalty point transactions based on search
   * criteria. It allows customers and administrators to filter transactions by
   * type, status, date range, and customer, with full support for sorting and
   * pagination.
   *
   * The operation supports complex filtering scenarios including multiple
   * transaction types, specific status conditions, and date range queries.
   * Search results are optimized for performance with proper indexing on the
   * customer_id, transaction_type, status, and created_at fields. The response
   * format is designed for integration with UI component libraries that handle
   * paginated data displays.
   *
   * This endpoint is designed for comprehensive review and reconciliation use
   * cases where users need to analyze their loyalty point activity over time.
   * The operation preserves the integrity of the points system by providing a
   * read-only view of the audit trail without allowing any modifications to
   * transaction records.
   *
   * Related operations: GET /promotions/loyalty-points/{loyaltyPointId} for
   * detailed individual transaction information.
   *
   * @param connection
   * @param body Search parameters for filtering loyalty point transactions
   *   including date ranges, transaction types, statuses, and pagination
   *   controls.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallLoyaltyPointTransaction.IRequest,
  ): Promise<IPageIShoppingMallLoyaltyPointTransaction> {
    try {
      return await patchShoppingMallAdminPromotionsLoyaltyPoints({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific loyalty point transaction.
   *
   * This operation fetches a single loyalty point transaction record from the
   * shopping_mall_loyalty_point_transactions table using its unique identifier.
   * The transaction details include the exact points change (+/-), transaction
   * type (purchase_reward, sign_up_bonus, point_redemption, etc.), status
   * (pending, completed, reversed), description, and associated order or
   * promotion information.
   *
   * The response provides complete context for each transaction, showing the
   * customer who earned or redeemed the points, any associated order that
   * generated the points, and any promotional campaign that awarded bonus
   * points. This granular level of detail enables accurate reconciliation with
   * other systems and helps resolve customer service inquiries regarding
   * loyalty point history.
   *
   * The operation returns the complete transaction record excluding any
   * sensitive personal information beyond the customer relationship. The
   * transaction details are immutable since they represent historical audit
   * trail records that should never be modified after creation.
   *
   * Related operations: PATCH /promotions/loyalty-points for finding
   * transactions with search criteria.
   *
   * @param connection
   * @param loyaltyPointId Unique identifier of the target loyalty point
   *   transaction.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":loyaltyPointId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("loyaltyPointId")
    loyaltyPointId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallLoyaltyPointTransaction> {
    try {
      return await getShoppingMallAdminPromotionsLoyaltyPointsLoyaltyPointId({
        admin,
        loyaltyPointId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
