import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallAdminPromotionsPromotionalCampaigns } from "../../../../../providers/postShoppingMallAdminPromotionsPromotionalCampaigns";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { patchShoppingMallAdminPromotionsPromotionalCampaigns } from "../../../../../providers/patchShoppingMallAdminPromotionsPromotionalCampaigns";
import { putShoppingMallAdminPromotionsPromotionalCampaignsCampaignId } from "../../../../../providers/putShoppingMallAdminPromotionsPromotionalCampaignsCampaignId";
import { deleteShoppingMallAdminPromotionsPromotionalCampaignsCampaignId } from "../../../../../providers/deleteShoppingMallAdminPromotionsPromotionalCampaignsCampaignId";

import { IShoppingMallPromotionalCampaign } from "../../../../../api/structures/IShoppingMallPromotionalCampaign";
import { IPageIShoppingMallPromotionalCampaign } from "../../../../../api/structures/IPageIShoppingMallPromotionalCampaign";

@Controller("/shoppingMall/admin/promotions/promotional-campaigns")
export class ShoppingmallAdminPromotionsPromotional_campaignsController {
  /**
   * Create a new promotional campaign to manage marketing initiatives with
   * defined start/end dates, budget constraints, and target audience criteria.
   *
   * This operation allows authorized administrators to establish a new
   * marketing campaign that can generate multiple coupons or offer special
   * promotions to customers. The campaign must specify a name, description,
   * temporal bounds (start_date and end_date), budget allocation
   * (total_budget), and an initial status (draft or active).
   *
   * When a new campaign is created, the system automatically initializes the
   * used_budget to 0, created_at to the current timestamp, and updated_at to
   * the current timestamp. The campaign is stored in the
   * shopping_mall_promotional_campaigns table with the admin who created it
   * linked via created_by_admin_id.
   *
   * Security: Only authenticated admin users can create campaigns. The system
   * validates that the start_date is before end_date and that total_budget is
   * greater than zero. Campaigns with invalid status values or missing required
   * fields are rejected.
   *
   * This operation is the entry point for establishing marketing initiatives in
   * the system. Related operations include retrieving campaign details (GET
   * /promotions/promotional-campaigns/{campaignId}), updating campaign details
   * (PUT /promotions/promotional-campaigns/{campaignId}), and listing all
   * campaigns (GET /promotions/promotional-campaigns).
   *
   * @param connection
   * @param body The complete configuration data required to establish a new
   *   promotional campaign.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallPromotionalCampaign.ICreate,
  ): Promise<IShoppingMallPromotionalCampaign> {
    try {
      return await postShoppingMallAdminPromotionsPromotionalCampaigns({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve paginated lists of promotional campaigns based on
   * various filters and sorting criteria. This operation operates on the
   * shopping_mall_promotional_campaigns table to provide administrative and
   * analytical views of active and completed marketing campaigns across the
   * shoppingMall platform.
   *
   * The operation supports complex filtering by campaign status, date ranges,
   * creation date, target segments, and budget usage. Results can be sorted by
   * various fields including name, start date, end date, total budget, and used
   * budget. Pagination is required to handle potentially large result sets from
   * campaign reporting.
   *
   * This is a read-only operation that does not modify any campaign data. It
   * enables users to analyze campaign performance, identify underperforming
   * campaigns, and estimate remaining budget for future planning.
   *
   * Security: This operation requires administrator access, as promotional
   * campaign data contains business-sensitive financial and strategic
   * information that should not be exposed to regular customers or sellers.
   *
   * Related operations: This operation works with GET
   * /promotions/promotional-campaigns/{campaignId} to provide detailed views of
   * individual campaigns, and GET /promotions/coupons?campaignId={campaignId}
   * to see coupons generated from specific campaigns.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering and
   *   sorting promotional campaigns.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallPromotionalCampaign.IRequest,
  ): Promise<IPageIShoppingMallPromotionalCampaign.ISummary> {
    try {
      return await patchShoppingMallAdminPromotionsPromotionalCampaigns({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing promotional campaign configuration in the shoppingMall
   * system. This operation modifies the details, schedule, and budget
   * parameters of an active or draft promotional campaign in the
   * shopping_mall_promotional_campaigns table.
   *
   * The operation enables marketing teams to modify campaign parameters such as
   * the name, description, dates, budget allocation, targeting criteria, and
   * status without needing to create a new campaign. This allows for iterative
   * optimization of marketing initiatives based on performance data or changing
   * business needs.
   *
   * The campaign must be in 'draft' or 'active' status to be updated. Campaigns
   * in 'completed' or 'expired' status cannot be modified to preserve
   * historical accuracy and ensure compliance with financial reporting.
   *
   * All updates to the campaign trigger a timestamp update in the updated_at
   * field. If the status changes from 'active' to 'paused', any newly generated
   * coupons will be disabled immediately. If the end_date is changed to a past
   * date, the campaign status will automatically transition to 'expired'. The
   * used_budget field is read-only and cannot be manipulated through this
   * endpoint as it is calculated from actual coupon redemptions.
   *
   * Security: Only authenticated admins who created the campaign, or admins
   * with elevated permissions, can update the campaign. This ensures
   * accountability for financial and marketing decisions.
   *
   * This operation directly interacts with the
   * shopping_mall_promotional_campaigns table. The operation expects the full
   * campaign entity to be provided in the request body as
   * IShoppingMallPromotionalCampaign.IUpdate, not partial updates. This ensures
   * consistency and prevents data corruption from partial updates. Related
   * operations: Create campaign (POST /promotions/promotional-campaigns), List
   * campaigns (PATCH /promotions/promotional-campaigns), Retrieve campaign (GET
   * /promotions/promotional-campaigns/{campaignId}).
   *
   * @param connection
   * @param campaignId Unique identifier of the target promotional campaign.
   *   This identifier references the primary key in the
   *   shopping_mall_promotional_campaigns table.
   * @param body The complete set of updated parameters for the promotional
   *   campaign. This object contains all fields that can be modified, including
   *   name, description, schedule, budget, targeting, and status.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":campaignId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("campaignId")
    campaignId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallPromotionalCampaign.IUpdate,
  ): Promise<IShoppingMallPromotionalCampaign> {
    try {
      return await putShoppingMallAdminPromotionsPromotionalCampaignsCampaignId(
        {
          admin,
          campaignId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a promotional campaign from the shoppingMall system,
   * removing its record and data from the shopping_mall_promotional_campaigns
   * table.
   *
   * This operation performs a hard delete - the campaign record is completely
   * and irreversibly removed from the database. This action cannot be undone
   * and will permanently eliminate all associated metadata, configuration,
   * designations, and relationship references.
   *
   * Hard deletion is permitted only for campaigns in 'draft' status. This
   * restriction prevents the deletion of active, completed, or expired
   * campaigns that have already generated coupons or been referenced in user
   * transactions.
   *
   * If a campaign has already generated coupons or been referenced in any
   * user-facing system (even if the campaign is inactive), it must not be
   * deleted to preserve data integrity for financial reporting, compliance,
   * customer service, and audit security. Instead, inactive campaigns should be
   * marked as 'archived' through status transition.
   *
   * This is a critical security and compliance operation. After deletion, all
   * related data including auto-generated logs, metrics, or notification
   * records associated with this campaign will also be removed.
   *
   * Security: Only administrators with elevated permissions can perform hard
   * deletion. This prevents accidental or malicious removal of financial data.
   * This operation requires additional 2-factor authentication and approval
   * from a second admin level.
   *
   * This operation directly interacts with the
   * shopping_mall_promotional_campaigns table and will completely remove the
   * record. Related operations: Update campaign (PUT
   * /promotions/promotional-campaigns/{campaignId}), Retrieve campaign (GET
   * /promotions/promotional-campaigns/{campaignId}).
   *
   * @param connection
   * @param campaignId Unique identifier of the target promotional campaign.
   *   This identifier references the primary key in the
   *   shopping_mall_promotional_campaigns table.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":campaignId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("campaignId")
    campaignId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallAdminPromotionsPromotionalCampaignsCampaignId(
        {
          admin,
          campaignId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
