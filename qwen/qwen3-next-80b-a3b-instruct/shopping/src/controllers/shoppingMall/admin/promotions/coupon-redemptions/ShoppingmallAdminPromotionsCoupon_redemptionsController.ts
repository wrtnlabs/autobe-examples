import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallAdminPromotionsCouponRedemptions } from "../../../../../providers/patchShoppingMallAdminPromotionsCouponRedemptions";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminPromotionsCouponRedemptionsRedemptionId } from "../../../../../providers/getShoppingMallAdminPromotionsCouponRedemptionsRedemptionId";

import { IPageIShoppingMallCouponRedemption } from "../../../../../api/structures/IPageIShoppingMallCouponRedemption";
import { IShoppingMallCouponRedemption } from "../../../../../api/structures/IShoppingMallCouponRedemption";

@Controller("/shoppingMall/admin/promotions/coupon-redemptions")
export class ShoppingmallAdminPromotionsCoupon_redemptionsController {
  /**
   * Retrieve a filtered and paginated list of coupon redemptions from the
   * system.
   *
   * This operation returns a collection of coupon redemption records from the
   * shopping_mall_coupon_redemptions table. It supports advanced search,
   * filtering, and sorting capabilities for analyzing redemption patterns
   * across customers, coupons, and time periods.
   *
   * The operation accepts search parameters in the request body, allowing
   * complex queries such as:
   *
   * - Redemption date ranges
   * - Specific customer identifiers
   * - Coupon codes or IDs
   * - Redemption status (valid/invalid)
   * - Order value thresholds
   *
   * Response includes pagination metadata (page, limit, total, pages) and the
   * paginated list of redemption records. Users can request summary data or
   * full detail records.
   *
   * This operation supports authorization based on actor roles. Only users with
   * appropriate permissions can access redemption data beyond their own
   * transactions.
   *
   * The redemption records contain full context about each application of a
   * coupon to an order, including the customer, coupon, order, discount amount,
   * and timestamp.
   *
   * Related operations:
   *
   * - GET /promotions/coupon-redemptions/{id} - Retrieve a specific redemption
   *   record
   * - POST /promotions/coupon-redemptions - Create new redemption records
   *
   * Note: This is a search operation that does not use GET with query
   * parameters; POST/PATCH is used for complex search requirements.
   *
   * @param connection
   * @param body Search, filter, and pagination parameters for coupon
   *   redemptions
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallCouponRedemption.IRequest,
  ): Promise<IPageIShoppingMallCouponRedemption.ISummary> {
    try {
      return await patchShoppingMallAdminPromotionsCouponRedemptions({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific coupon redemption event from
   * the shoppingMall system. This operation accesses the
   * shopping_mall_coupon_redemptions table to provide full context about a
   * single coupon redemption transaction. The redemption record includes
   * complete details about the customer, coupon, order, discount applied, and
   * timestamp.
   *
   * The operation returns a comprehensive view of the redemption event that
   * occurred at checkout. This data is essential for customer support
   * inquiries, financial reconciliation, abuse detection, and understanding
   * coupon usage patterns.
   *
   * Security: Only authenticated users can access their own redemption records.
   * Administrators can access any redemption record for auditing and support
   * purposes.
   *
   * This operation does not modify any data - it is read-only and provides a
   * snapshot of the redemption as it occurred at the moment of checkout.
   *
   * Linked operations: This operation complements the GET
   * /promotions/coupons/{couponId} operation, which provides metadata about the
   * coupon itself, while this operation provides the actual redemption event
   * data.
   *
   * @param connection
   * @param redemptionId Unique identifier of the coupon redemption record to
   *   retrieve. This ID corresponds to the primary key of the
   *   shopping_mall_coupon_redemptions table.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":redemptionId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("redemptionId")
    redemptionId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallCouponRedemption> {
    try {
      return await getShoppingMallAdminPromotionsCouponRedemptionsRedemptionId({
        admin,
        redemptionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
