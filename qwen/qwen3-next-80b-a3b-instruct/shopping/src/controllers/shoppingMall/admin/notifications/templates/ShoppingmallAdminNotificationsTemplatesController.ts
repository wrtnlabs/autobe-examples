import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallAdminNotificationsTemplates } from "../../../../../providers/postShoppingMallAdminNotificationsTemplates";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { putShoppingMallAdminNotificationsTemplatesTemplateId } from "../../../../../providers/putShoppingMallAdminNotificationsTemplatesTemplateId";
import { deleteShoppingMallAdminNotificationsTemplatesTemplateId } from "../../../../../providers/deleteShoppingMallAdminNotificationsTemplatesTemplateId";

import { IShoppingMallNotificationTemplate } from "../../../../../api/structures/IShoppingMallNotificationTemplate";

@Controller("/shoppingMall/admin/notifications/templates")
export class ShoppingmallAdminNotificationsTemplatesController {
  /**
   * Create a new notification template for the shoppingMall platform.
   *
   * This operation allows admin users to define new system notification
   * templates that will be used to generate automated communications to
   * customers and sellers. Templates are structured with a title, subject line,
   * and body content that may include dynamic placeholders (e.g.,
   * {customer_name}, {order_id}) to personalize messages.
   *
   * The template is stored in the shopping_mall_notification_templates table
   * and becomes available for use by the notification system across all
   * platform modules. Each template is a single record that can be soft-deleted
   * by setting the deleted_at timestamp to preserve the record for audit
   * purposes while preventing its use in future notifications.
   *
   * Security: Only users with admin role can create templates. The system
   * validates template type against predefined categories (order_confirmed,
   * payment_failed, seller_approved, etc.) and language codes against supported
   * languages (en, ko, es, etc.). Validation ensures no missing required
   * placeholders and that content complies with messaging compliance
   * guidelines.
   *
   * All templates are created as inactive by default and require admin
   * activation before they can be used in production notifications.
   *
   * Relationships: This operation references the
   * shopping_mall_notification_templates model in the Prisma schema, which has
   * fields for title, subject, body, type, language, active status, creation
   * timestamp, and soft delete capability.
   *
   * Related operations: Get template (GET
   * /notifications/templates/{templateId}), Update template (PUT
   * /notifications/templates/{templateId}), List templates (PATCH
   * /notifications/templates), Activate template (PUT
   * /notifications/templates/{templateId}/activate), Deactivate template (PUT
   * /notifications/templates/{templateId}/deactivate).
   *
   * @param connection
   * @param body Template definition for a new notification message.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallNotificationTemplate.ICreate,
  ): Promise<IShoppingMallNotificationTemplate> {
    try {
      return await postShoppingMallAdminNotificationsTemplates({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing notification template on the shoppingMall platform.
   *
   * This operation allows admin users to modify the content and configuration
   * of an existing notification template. The template is identified by its
   * unique templateId and must exist in the system and not be marked as
   * deleted. Updates can modify the template's title, subject, body, type,
   * language, or activate/deactivate status.
   *
   * Changes to templates affect future notifications but do not alter
   * previously sent messages. The system maintains a single active version of
   * each template and supports soft deletion by setting the deleted_at field to
   * preserve records for audit purposes.
   *
   * Security: Only admin users can update templates. Validation ensures
   * template type and language codes remain valid. If updating the active
   * status, the system verifies that no other template with the same type and
   * language is already active, to prevent conflicts in message routing.
   *
   * The operation respects the soft-delete constraint of the
   * shopping_mall_notification_templates table. An attempt to update a template
   * with deleted_at set will return a 404 error. Updates to the body or subject
   * may trigger validation for mandatory placeholders, ensuring readability and
   * proper templating.
   *
   * Relationships: This operation references the
   * shopping_mall_notification_templates model in the Prisma schema, which has
   * fields for title, subject, body, type, language, active status, creation
   * timestamp, update timestamp, and soft-delete timestamp.
   *
   * Related operations: Create template (POST /notifications/templates), Get
   * template (GET /notifications/templates/{templateId}), List templates (PATCH
   * /notifications/templates), Activate template (PUT
   * /notifications/templates/{templateId}/activate), Deactivate template (PUT
   * /notifications/templates/{templateId}/deactivate).
   *
   * @param connection
   * @param templateId Unique identifier of the template to update. Matches the
   *   id field in the shopping_mall_notification_templates table.
   * @param body Updated fields for the notification template. Only fields
   *   provided will be updated.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":templateId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("templateId")
    templateId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallNotificationTemplate.IUpdate,
  ): Promise<IShoppingMallNotificationTemplate> {
    try {
      return await putShoppingMallAdminNotificationsTemplatesTemplateId({
        admin,
        templateId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently remove a notification template from the system. This operation
   * deletes the specified notification template record identified by
   * {templateId} from the shopping_mall_notification_templates table. This is a
   * hard delete operation that removes the template permanently from the
   * database, with no possibility of recovery.
   *
   * This operation is intended for system administrators who need to remove
   * outdated, incorrect, or obsolete notification templates. Unlike soft
   * deletion used in other system tables, notification templates are completely
   * removed because they are configuration artifacts that should be maintained
   * through controlled versioning and replacement rather than archival.
   *
   * Before invoking this operation, ensure that no pending notifications in the
   * shopping_mall_notification_queue reference this template, as the system
   * does not enforce referential integrity for these templates to allow for
   * template evolution. The decision to delete should be made with care, as it
   * may impact any scheduled notifications that depend on this template.
   *
   * This operation requires administrative privileges and is not available to
   * customer or seller actors.
   *
   * @param connection
   * @param templateId Unique identifier of the notification template to be
   *   deleted. This must be a UUID string that corresponds to an existing
   *   template in the shopping_mall_notification_templates table.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":templateId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("templateId")
    templateId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallAdminNotificationsTemplatesTemplateId({
        admin,
        templateId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
