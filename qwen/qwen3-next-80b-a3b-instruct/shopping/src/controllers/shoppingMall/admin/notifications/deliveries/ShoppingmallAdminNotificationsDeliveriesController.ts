import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { patchShoppingMallAdminNotificationsDeliveries } from "../../../../../providers/patchShoppingMallAdminNotificationsDeliveries";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";

import { IPageIShoppingMallNotificationDelivery } from "../../../../../api/structures/IPageIShoppingMallNotificationDelivery";
import { IShoppingMallNotificationDelivery } from "../../../../../api/structures/IShoppingMallNotificationDelivery";

@Controller("/shoppingMall/admin/notifications/deliveries")
export class ShoppingmallAdminNotificationsDeliveriesController {
  /**
   * Retrieve a paginated list of notification delivery attempts and outcomes.
   *
   * This operation provides access to the shopping_mall_notification_deliveries
   * audit trail, which records every delivery attempt for every notification
   * sent through the platform. Unlike the queuing system that represents
   * pending notifications, this endpoint returns historical records of what
   * actually happened during delivery attempts.
   *
   * The deliveries collection serves as a permanent audit log for compliance
   * and debugging. Each record captures:
   *
   * - Which specific queue entry triggered the delivery (via queue_id)
   * - The delivery channel used (email, in_app, push)
   * - The outcome status (success, failed, skipped)
   * - The response from the delivery service gateway
   * - The timestamp of delivery completion
   *
   * This endpoint supports advanced filtering through search parameters,
   * pagination, and sorting to enable comprehensive analysis of notification
   * delivery performance.
   *
   * Use cases:
   *
   * - Validate delivery success rates for specific notification types
   * - Investigate patterns in delivery failures by actor or channel
   * - Identify system issues affecting specific notification providers
   * - Produce reports on notification delivery effectiveness
   *
   * Note: This endpoint uses PATCH semantics for complex filtering - a GET
   * request would be insufficient for the required search parameters like date
   * ranges, delivery status filters, and actor type criteria. The request body
   * contains the complete search criteria.
   *
   * Related operations:
   *
   * - GET /notifications/queue/{queueId} - View a specific pending notification
   * - GET /notifications/templates - List available notification templates
   *
   * The delivery records are immutable - they are never updated after creation.
   * New records are appended on retry attempts, creating a complete history of
   * delivery attempts for each notification.
   *
   * @param connection
   * @param body Search parameters for filtering notification delivery records.
   *   Includes date ranges, delivery status filters, and actor type criteria.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IShoppingMallNotificationDelivery.IRequest,
  ): Promise<IPageIShoppingMallNotificationDelivery> {
    try {
      return await patchShoppingMallAdminNotificationsDeliveries({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
