import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IShoppingMallShipment } from "../../../../api/structures/IShoppingMallShipment";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getShoppingMallAdminShipmentsShipmentId } from "../../../../providers/getShoppingMallAdminShipmentsShipmentId";

@Controller("/shoppingMall/admin/shipments/:shipmentId")
export class ShoppingmallAdminShipmentsController {
  /**
   * Retrieve the complete details of a specific shipment using its unique identifier.
   *
   * This endpoint returns immutable shipment information from the shopping_mall_shipments table, including the carrier name, tracking number, shipment status, and creation timestamp. The shipment record is preserved exactly as created by the seller and cannot be modified after creation, ensuring a persistent audit trail for delivery tracking.
   *
   * The status field indicates the current phase of the shipment: 'shipped' (initial status upon creation), 'delivered' (confirmed by customer), or 'auto-delivered' (automatically set after 14 days without customer confirmation). This enterprise-grade tracking system prevents any post-creation tampering with shipment information, maintaining integrity for dispute resolution and compliance purposes.
   *
   * Authorized actors include customers who placed the order and sellers who created the shipment, who can track delivery progress using the provided tracking number. The endpoint returns full details to ensure accurate customer communication and logistics management without exposing sensitive system information.
   *
   * @param connection
   * @param shipmentId Unique identifier of the shipment to retrieve. This UUID corresponds to the shopping_mall_shipments.id field and cannot be modified or reused.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query shopping_mall_shipments table using shipmentId (UUID) as primary key. Return shipment record with carrier, tracking_number, status, and created_at fields. Validate that shipmentId exists and is not deleted. Return 404 if shipment not found. Do not join with order_items as shipmentId is unique primary key. Do not modify any data as this is a read-only operation.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("shipmentId")
    shipmentId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallShipment> {
    try {
      return await getShoppingMallAdminShipmentsShipmentId({
        admin,
        shipmentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
