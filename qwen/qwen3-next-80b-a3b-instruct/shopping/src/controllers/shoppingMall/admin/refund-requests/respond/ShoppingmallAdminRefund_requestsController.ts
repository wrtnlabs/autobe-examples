@Controller("/shoppingMall/admin/refund-requests/:requestId/respond")
export class ShoppingmallAdminRefund_requestsController {
  /**
   * Respond to a pending refund request initiated by a customer.
   *
   * This operation allows a seller to approve or reject a refund request for a delivered order item. The seller must choose one of two actions: 'approve' or 'reject'. If the seller chooses 'reject', they must provide a reason between 10 and 500 characters. Approval is final and triggers immediate actions: the item status is set to 'refunded', inventory is restored, and a payment refund is initiated through the external gateway. Rejection maintains the original 'delivered' status and notifies the customer.
   *
   * The seller may only respond once. If no response is provided within 72 hours, the system automatically approves the refund. This endpoint does not support changing a previously submitted response. The request must be authenticated as the seller who owns the product in the referenced order item.
   *
   * This operation is tightly coupled with refund request snapshots, which preserve immutable audit records of every state change for compliance and reconciliation.
   *
   * @param connection
   * @param requestId The UUID of the refund request to respond to, referenced from shopping_mall_refund_requests.id.
   * @param body Action and optional reason for responding to a refund request.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Retrieve refund request by ID from shopping_mall_refund_requests table.
   * Verify status is 'pending'.
   * If action is 'approve':
   *   - Update status to 'approved'
   *   - Set responded_at to current timestamp
   *   - Create snapshot with status 'approved', changed_by 'seller', response_reason null
   *   - Restore inventory via shopping_mall_inventory_logs (positive adjustment)
   *   - Trigger external payment refund flow
   * If action is 'reject':
   *   - Update status to 'rejected'
   *   - Set responded_at to current timestamp
   *   - Validate reason length (10-500 chars)
   *   - Create snapshot with status 'rejected', changed_by 'seller', response_reason from request
   *   - Keep inventory unchanged
   * If no response within 72 hours, auto-approval is handled by system timer, not this endpoint.
   * All changes must be transactional.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async respond(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("requestId")
    requestId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallRefundRequest.IRespond,
  ): Promise<void> {
    try {
      return await postShoppingMallAdminRefundRequestsRequestIdRespond({
        admin,
        requestId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
