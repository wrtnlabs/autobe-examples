import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallAdmin } from "../../../../api/structures/IShoppingMallAdmin";
import { postShoppingMallAuthAdminJoin } from "../../../../providers/postShoppingMallAuthAdminJoin";
import { postShoppingMallAuthAdminLogin } from "../../../../providers/postShoppingMallAuthAdminLogin";
import { postShoppingMallAuthAdminRefresh } from "../../../../providers/postShoppingMallAuthAdminRefresh";

@Controller("/shoppingMall/auth/admin")
export class ShoppingmallAuthAdminController {
  /**
   * Registers a new system administrator account. This operation requires the admin to provide a valid email address and password. The email must not already be registered in the shopping_mall_admins table. Upon successful registration, the system creates a new admin record with password hashing and issues an initial JWT access and refresh token. The operation does not require email verification to proceed — pending verification status is managed internally via the shopping_mall_admin_email_verifications table, which triggers a separate email confirmation workflow after the join completion. This ensures that the authentication flow is not blocked by external validation, in accordance with the platform's principle of immediate system access upon identity creation. The request body type IShoppingMallAdmin.IJoin defines the structure: { email: string, password: string }, ensuring type safety and schema compliance. This operation is the foundational entry point for any new administrator to gain access to the administrative interface.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Request body for creating a new admin account with email and password. Must include a valid email (non-empty, valid format) and a password meeting security requirements (minimum 8 characters). No other fields are permitted.
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification The service layer creates a new record in shopping_mall_admins with hashed password. It generates a JWT access token (30 min expiry) and refresh token (30 day expiry). The refresh token is stored in shopping_mall_admin_sessions. It does not trigger or wait for email verification — that is handled asynchronously via a separate system event. Returns success with tokens on success. If email exists, returns 409 Conflict. If password is too weak, returns 422 Unprocessable Entity. All responses are typed and validated by the Prisma schema and NestJS DTO validation.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallAdmin.IJoin,
  ): Promise<IShoppingMallAdmin.IAuthorized> {
    try {
      return await postShoppingMallAuthAdminJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticates a registered administrator and issues access and refresh JWT tokens. The system validates the provided email and password against the shopping_mall_admins table. The email must be registered and the password must hash-match the stored value. The operation is rejected if the admin account is suspended or has been permanently banned. Upon successful authentication, an access token with 30-minute expiration and a refresh token with 30-day expiration are returned. The refresh token is stored in the shopping_mall_admin_sessions table to support token refresh cycles. This operation does not verify email status — a suspended account returns 403 Forbidden without disclosing whether the issue is suspension, deletion, or wrong credentials, enhancing security. The response includes admin_id to identify the authenticated actor. The request body type IShoppingMallAdmin.ILogin defines the structure: { email: string, password: string }, ensuring strict type compliance.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Request body for logging in an admin account. Must contain a valid email and password. No other fields are allowed. Password is transmitted securely as plaintext over HTTPS and is never stored; hashing occurs server-side.
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification The system retrieves the admin record from shopping_mall_admins using the email. Verifies the password using bcrypt comparison. If account is suspended (suspended_at not null), returns 403 Forbidden. If authentication fails, returns 401 Unauthorized. Upon success, generates tokens and stores refresh token in shopping_mall_admin_sessions. Returns tokens with admin_id. All logic is transactional and secured with rate limiting on auth attempts per email.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallAdmin.ILogin,
  ): Promise<IShoppingMallAdmin.IAuthorized> {
    try {
      return await postShoppingMallAuthAdminLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Renews a valid access token using a valid refresh token. The operation requires the client to submit a previously issued refresh token from the shopping_mall_admin_sessions table. If the refresh token is valid, not expired, and not blacklisted, the system issues a new access token (30 min expiry) and a new refresh token (30 day expiry), replacing the old one. The old refresh token is invalidated and removed from the session store. The new refresh token is stored, and the expiration is reset. This operation supports seamless long-term session persistence without requiring the admin to re-enter credentials. It does not validate email or password — only token validity and integrity. The request body type IShoppingMallAdmin.IRefresh defines the structure: { refresh_token: string }, ensuring only the token is exchanged. This mechanism prevents token theft since even if an access token is intercepted, it cannot renew itself without the refresh token.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Request body for refreshing admin tokens. Must contain one field: refresh_token, which is a valid refresh token previously issued by the system and still active within its 30-day window.
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification The system validates the refresh token by looking it up in shopping_mall_admin_sessions. If found and not expired, it generates new access and refresh tokens, deletes the old refresh token entry, and inserts the new one. If token is invalid, expired, or missing, returns 401 Unauthorized. The admin_id is derived from the session record. All operations use strict atomic database transactions to prevent race conditions.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IShoppingMallAdmin.IRefresh,
  ): Promise<IShoppingMallAdmin.IAuthorized> {
    try {
      return await postShoppingMallAuthAdminRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
