import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallAdmin } from "../../../../../api/structures/IShoppingMallAdmin";
import { postShoppingMallAuthAdminLogin } from "../../../../../providers/postShoppingMallAuthAdminLogin";

@Controller("/shoppingMall/auth/admin/login")
export class ShoppingmallAuthAdminLoginController {
  /**
   * This operation authenticates an administrator using email and password credentials, granting them a JWT access token and refresh token for subsequent authenticated requests.
   *
   * Key schema fields referenced: admin_email, admin_password_hash, admin_is_active, admin_is_suspended. The system checks authentication success by comparing the hashed password against the stored value in shopping_mall_admins. If the admin is suspended (admin_is_suspended=true), authentication is denied with 403 status.
   *
   * This operation is public — no authentication required to access the endpoint. Upon successful login, the system creates an entry in the shopping_mall_admin_sessions table with the issued access token, refresh token, and expiration time.
   *
   * The admin profile returned includes admin_id, admin_email, admin_role, admin_is_active, and admin_created_at. The access token is valid for 15 minutes; the refresh token is valid for 7 days.
   *
   * This operation is distinct from user/customer login, which uses different tables, schemas, and token rules.
   *
   * This operation is permanently available for admin authentication. No prerequisites are required. Access is strictly controlled via the authorizationType: "login".
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Login credentials to authenticate the admin.
   * @x-autobe-specification Service layer validates credentials against admin_email and admin_password_hash stored in shopping_mall_admins. If valid and admin_is_active=true, generates JWT access and refresh tokens. Creates entry in shopping_mall_admin_sessions. Returns 200 with tokens and admin profile. Returns 401 for invalid credentials or suspended account.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async signIn(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallAdmin.ILogin,
  ): Promise<IShoppingMallAdmin.IAuthorized> {
    try {
      return await postShoppingMallAuthAdminLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
