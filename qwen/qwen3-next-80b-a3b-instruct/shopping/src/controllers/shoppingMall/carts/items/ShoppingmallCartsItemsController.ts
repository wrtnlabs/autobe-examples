import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { putShoppingMallCartsCartIdItemsItemId } from "../../../../providers/putShoppingMallCartsCartIdItemsItemId";
import { deleteShoppingMallCartsCartIdItemsItemId } from "../../../../providers/deleteShoppingMallCartsCartIdItemsItemId";

import { IShoppingMallCartItem } from "../../../../api/structures/IShoppingMallCartItem";

@Controller("/shoppingMall/carts/:cartId/items/:itemId")
export class ShoppingmallCartsItemsController {
  /**
   * Update a specific item within a customer's shopping cart.
   *
   * This operation modifies the quantity or status of an individual cart item
   * identified by its unique cart and item IDs. When a customer adjusts their
   * cart (increasing/decreasing item quantity or removing an item from purchase
   * intent), this endpoint handles the modification with atomic validation.
   *
   * The operation validates that the cart exists and is still active (not
   * expired or checked out), that the cart item belongs to the specified cart
   * (enforced by foreign key constraint), and that the new quantity does not
   * exceed the current inventory of the product variant. The price is not
   * modified as it was captured at the time of cart addition to ensure purchase
   * consistency.
   *
   * Security: Only the cart owner (authenticated customer) can modify cart
   * items. The cart's customer_id is verified against the authenticated user's
   * identity.
   *
   * State transitions:
   *
   * - If quantity becomes 0, item.status transitions to 'removed'
   * - If inventory becomes insufficient after quantity adjustment, item.status
   *   transitions to 'out_of_stock'
   * - If quantity increases and inventory becomes available, item.status
   *   transitions back to 'active'
   *
   * This operation directly modifies the shopping_mall_cart_items table and is
   * atomic - either all changes succeed or none do.
   *
   * Related Operations:
   *
   * - GET /carts/{cartId}/items - View all items in a cart
   * - DELETE /carts/{cartId}/items/{itemId} - Remove the item from cart
   * - POST /carts/{cartId}/items - Add a new item to cart
   * - PATCH /carts/{cartId} - Check out the entire cart
   *
   * @param connection
   * @param cartId Unique identifier of the shopping cart containing the item.
   *   Must match the cart_id in shopping_mall_carts table. This property
   *   provides the context for the cart item update.
   * @param itemId Unique identifier of the cart item to be updated. Must match
   *   the id in shopping_mall_cart_items table. This identifies the specific
   *   item within the cart to be modified.
   * @param body Updated quantity and status information for the cart item.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @TypedParam("cartId")
    cartId: string & tags.Format<"uuid">,
    @TypedParam("itemId")
    itemId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallCartItem.IUpdate,
  ): Promise<IShoppingMallCartItem> {
    try {
      return await putShoppingMallCartsCartIdItemsItemId({
        cartId,
        itemId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Remove a specific item from a customer's shopping cart.
   *
   * This operation permanently removes an individual cart item from the cart,
   * reducing the cart's total item count and value. Unlike marking an item as
   * 'removed' in status, this operation deletes the cart item record entirely
   * from the database.
   *
   * The operation validates that the cart exists and is still active (not
   * expired or checked out), that the cart item belongs to the specified cart
   * (enforced by foreign key constraint), and that no other system processes
   * are currently modifying this item. This prevents race conditions during
   * cart modifications.
   *
   * Security: Only the cart owner (authenticated customer) can remove items
   * from their cart. The cart's customer_id is verified against the
   * authenticated user's identity.
   *
   * After removal, the system does not track this specific cart item any
   * longer. For audit purposes, the removal event may be logged separately in
   * shopping_mall_audit_logs table.
   *
   * This is a hard delete operation that permanently removes the record. The
   * cart item record is not subject to soft deletion.
   *
   * Related Operations:
   *
   * - PUT /carts/{cartId}/items/{itemId} - Update cart item details
   * - GET /carts/{cartId}/items - View all items in a cart
   * - POST /carts/{cartId}/items - Add a new item to cart
   *
   * @param connection
   * @param cartId Unique identifier of the shopping cart from which to remove
   *   the item. Must match the cart_id in shopping_mall_carts table.
   * @param itemId Unique identifier of the cart item to be permanently removed.
   *   Must match the id in shopping_mall_cart_items table.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @TypedParam("cartId")
    cartId: string & tags.Format<"uuid">,
    @TypedParam("itemId")
    itemId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallCartsCartIdItemsItemId({
        cartId,
        itemId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
