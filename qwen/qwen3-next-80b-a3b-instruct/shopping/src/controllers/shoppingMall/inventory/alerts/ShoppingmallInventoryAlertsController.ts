import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia from "typia";
import { patchShoppingMallInventoryAlerts } from "../../../../providers/patchShoppingMallInventoryAlerts";
import { getShoppingMallInventoryAlertsAlertId } from "../../../../providers/getShoppingMallInventoryAlertsAlertId";

import { IPageIShoppingMallInventoryAlert } from "../../../../api/structures/IPageIShoppingMallInventoryAlert";
import { IShoppingMallInventoryAlert } from "../../../../api/structures/IShoppingMallInventoryAlert";

@Controller("/shoppingMall/inventory/alerts")
export class ShoppingmallInventoryAlertsController {
  /**
   * Retrieve a paginated list of inventory alerts generated when stock levels
   * fall below configured thresholds. This operation operates on the
   * shopping_mall_inventory_alerts table which tracks alert events for
   * inventory units whose current stock quantity drops below
   * min_stock_threshold.
   *
   * The alerts may have types: 'low_stock', 'critical_stock', or
   * 'back_in_stock' indicating the severity level of the alert. Results are
   * filtered and sorted based on search parameters including date range, alert
   * type, status, and associated seller.
   *
   * Security: This is a public endpoint accessible without authentication as
   * inventory alerts are non-sensitive system notifications about stock
   * conditions. The endpoint supports pagination to handle large result sets
   * efficiently without performance degradation.
   *
   * Related operations: GET /inventory/alerts/{alertId} retrieves detailed
   * information about a specific alert.
   *
   * @param connection
   * @param body Search parameters for filtering inventory alerts by type,
   *   status, time range, and seller.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IShoppingMallInventoryAlert.IRequest,
  ): Promise<IPageIShoppingMallInventoryAlert> {
    try {
      return await patchShoppingMallInventoryAlerts({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific inventory alert identified
   * by its unique alertId. This operation returns full details from the
   * shopping_mall_inventory_alerts table including the alert type, current
   * stock quantity, threshold value, alert creation timestamp, and clearance
   * status.
   *
   * The alertId parameter corresponds to the primary key field in the
   * inventory_alerts table. This endpoint provides granular visibility into a
   * single alert event that may have been triggered by inventory units falling
   * below their configured min_stock_threshold.
   *
   * Security: This is a public endpoint as inventory alert data contains only
   * system-generated stock condition information with no private user data.
   *
   * @param connection
   * @param alertId Unique identifier of the inventory alert. This corresponds
   *   to the primary key in the shopping_mall_inventory_alerts table and is
   *   used to retrieve a specific alert record.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":alertId")
  public async at(
    @TypedParam("alertId")
    alertId: string,
  ): Promise<IShoppingMallInventoryAlert> {
    try {
      return await getShoppingMallInventoryAlertsAlertId({
        alertId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
