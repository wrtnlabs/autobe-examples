import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallRequestResponse } from "../../../../../../api/structures/IShoppingMallRequestResponse";
import { SellerAuth } from "../../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../../decorators/payload/SellerPayload";
import { getShoppingMallSellerSellerRequestsPending } from "../../../../../../providers/getShoppingMallSellerSellerRequestsPending";

@Controller("/shoppingMall/seller/seller/requests/pending")
export class ShoppingmallSellerSellerRequestsPendingController {
  /**
   * Retrieve a consolidated list of all pending cancellation and refund requests for products owned by the authenticated seller.
   *
   * This endpoint provides sellers with a unified view of all unresolved customer claims requiring their attention, combining both cancellation requests (for paid but unshipped items) and refund requests (for delivered items) into a single interface. The response includes the request type, customer information, reason for the request, creation timestamp, and any associated seller response.
   *
   * Security: Only the seller who owns the products associated with these requests can access this information. The endpoint automatically filters requests based on the authentication context, ensuring sellers can only see requests for their own products.
   *
   * Business context: This endpoint is critical for seller dispute resolution workflows. Sellers have a time-limited window (48 hours for cancellations, 72 hours for refunds) to respond to these requests before automatic approval occurs. This dashboard provides the primary interface through which sellers manage these time-sensitive business decisions.
   *
   * Related operations:
   * - POST /seller/requests/{requestId}/respond - Submit response to a pending request (follow-up operation)
   * - GET /seller/requests/history - View historical responses to completed requests
   * - GET /customer/requests/pending - View customer's own pending requests
   *
   * This endpoint does NOT include requests that have been completed (approved or rejected) or requests for products owned by other sellers.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query shopping_mall_cancellation_requests and shopping_mall_refund_requests tables for records with status='pending' and associated with the authenticated seller's products. Join with shopping_mall_request_responses to get response status and reason. Combine results into unified response with request_type field to distinguish cancellation from refund requests. Order by created_at descending. Include only requests for products owned by the authenticated seller. Use pagination with default 20 records per page.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
  ): Promise<IShoppingMallRequestResponse> {
    try {
      return await getShoppingMallSellerSellerRequestsPending({
        seller,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
