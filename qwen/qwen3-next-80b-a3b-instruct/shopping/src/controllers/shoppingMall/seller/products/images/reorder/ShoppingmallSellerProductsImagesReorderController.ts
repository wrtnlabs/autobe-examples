import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IShoppingMallProductImage } from "../../../../../../api/structures/IShoppingMallProductImage";
import { SellerAuth } from "../../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../../decorators/payload/SellerPayload";
import { putShoppingMallSellerProductsProductIdImagesReorder } from "../../../../../../providers/putShoppingMallSellerProductsProductIdImagesReorder";

@Controller("/shoppingMall/seller/products/:productId/images/reorder")
export class ShoppingmallSellerProductsImagesReorderController {
  /**
   * Reorder the images associated with a product to control display sequence and thumbnail selection.
   *
   * This operation allows sellers to define the visual order of product images, which directly impacts customer experience and the primary thumbnail displayed in listings. The first image in the updated sequence becomes the main product image.
   *
   * All changes are preserved as an immutable product snapshot to ensure historical accuracy in case of disputes or audits. This operation is restricted to the product's seller and requires explicit authorization. Images cannot be reordered across products or during product deletion states. The system enforces a maximum of 10 images per product with positions strictly between 0 and 9.
   *
   * The operation triggers an audit trail in the product snapshot system, ensuring that the exact visual presentation of the product at any point in time can be reconstructed. This is critical for resolving customer disputes where product imagery is a point of contention.
   *
   * @param connection
   * @param productId The globally unique identifier of the product whose images are being reordered. Must be a valid UUID referencing an active product.
   * @param body Array of image objects with updated position values. All images must belong to the product identified by the path parameter.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Validate all image IDs in request belong to the product identified by {productId}. Ensure each image has a unique position value (0 to 9). Update all image position values atomically using a single transaction. Set the image with position 0 as the primary thumbnail. Create a product snapshot with the previous and new image order. Return success if all validations pass. Do not update images that belong to a different product or have invalid positions.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async updateImageOrder(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallProductImage.IReorderRequest,
  ): Promise<IShoppingMallProductImage.IReorderResponse> {
    try {
      return await putShoppingMallSellerProductsProductIdImagesReorder({
        seller,
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
