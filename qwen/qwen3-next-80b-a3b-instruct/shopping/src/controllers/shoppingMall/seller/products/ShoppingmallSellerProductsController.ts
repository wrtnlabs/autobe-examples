import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallSellerProducts } from "../../../../providers/postShoppingMallSellerProducts";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { putShoppingMallSellerProductsProductId } from "../../../../providers/putShoppingMallSellerProductsProductId";
import { deleteShoppingMallSellerProductsProductId } from "../../../../providers/deleteShoppingMallSellerProductsProductId";

import { IShoppingMallProduct } from "../../../../api/structures/IShoppingMallProduct";

@Controller("/shoppingMall/seller/products")
export class ShoppingmallSellerProductsController {
  /**
   * Create a new product listing in the shoppingMall marketplace.
   *
   * This operation allows authenticated sellers to create new product offerings
   * for sale. The seller's identity is automatically extracted from the JWT
   * authentication token and associated with the new product record. A product
   * can only be created by a seller with active status ('active'), and the
   * product's status is initially set to 'draft' to allow for review before
   * publishing.
   *
   * The product creation process requires: a title (3-100 characters), a
   * description (minimum 20 characters), a price (minimum $0.01, maximum
   * $5000.00), and a tax category (shopping_mall_tax_categories.id). The
   * product can optionally be associated with a category through the
   * shopping_mall_product_categories junction table, but this is handled
   * separately after product creation.
   *
   * Security: Only authenticated sellers can create products. This is enforced
   * through the authorizationActors field, which accepts only ['seller'] actor
   * types. The system validates that the authenticated seller has active status
   * before processing the request.
   *
   * The created product record is stored in the shopping_mall_products table
   * with the following field mappings:
   *
   * - Title → shopping_mall_products.title
   * - Description → shopping_mall_products.description
   * - Price → shopping_mall_products.price
   * - Shopping_mall_seller_id → mapping from JWT authenticated actor
   * - Shopping_mall_tax_category_id → provided in request body
   * - Status → automatically set to 'draft' initially
   * - Created_at, updated_at → automatically set
   *
   * The response returns the newly created product as a complete object with
   * all fields, including the generated ID and timestamps. This allows the
   * client to immediately use the returned product object for subsequent
   * operations like associating images or categories.
   *
   * Related operations: GET /products/{productId} retrieves the product after
   * creation. PATCH /products allows searching products. PUT
   * /products/{productId} updates an existing product (requires product status
   * to be 'draft').
   *
   * Error handling: Returns 400 Bad Request if validation fails (wrong title
   * length, price out of range, invalid tax category). Returns 401 Unauthorized
   * if the user is not authenticated as a seller. Returns 403 Forbidden if the
   * seller account is not active.
   *
   * @param connection
   * @param body Creation data for a new product listing.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IShoppingMallProduct.ICreate,
  ): Promise<IShoppingMallProduct> {
    try {
      return await postShoppingMallSellerProducts({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing product in the shoppingMall catalog. This operation
   * allows authorized sellers to modify product information including title,
   * description, price, and status. The product must be in 'draft' or
   * 'published' status to be updated. Seller identity is extracted from the
   * authentication token and verified against the product owner. Updates to
   * published products trigger a moderation review if significant changes are
   * detected.
   *
   * Security: Only the owning seller or platform administrators can update
   * products. The operation validates that all field changes comply with
   * content policies and business rules (minimum/maximum character lengths,
   * price ranges, etc.). The updated_at timestamp is automatically set to the
   * modification time.
   *
   * Special handling: When a product's status changes from 'draft' to
   * 'published', it triggers validation of all associated product variants and
   * images to ensure completeness. Products with missing required information
   * cannot be published. Products that have been archived cannot be updated.
   *
   * Related operations: GET /products/{productId} to view current product
   * details before update, and DELETE /products/{productId} to permanently
   * remove products.
   *
   * @param connection
   * @param productId Unique identifier of the target product to update. This is
   *   the product's system-generated UUID.
   * @param body Updated product fields for the modification.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":productId")
  public async update(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallProduct.IUpdate,
  ): Promise<IShoppingMallProduct> {
    try {
      return await putShoppingMallSellerProductsProductId({
        seller,
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a product from the shoppingMall catalog. This operation
   * removes the product record entirely from the system and cannot be undone.
   * Before deletion, the system verifies that no active orders contain this
   * product and that the product is not referenced by any other system
   * entities.
   *
   * This is a hard delete operation performed only on products with 'draft'
   * status. Products that are 'published' cannot be deleted directly — they
   * must first be archived and then purged through a separate system process
   * after a retention period.
   *
   * Security: Only the owning seller or platform administrators can delete
   * products. Deletions trigger an audit log entry for compliance tracking. All
   * associated product variants, images, and category assignments are also
   * permanently removed.
   *
   * Special handling: If the product is associated with any active customer
   * wishlists or pending cart items, those references are removed but the other
   * entities preserved. The deletion is immediate and irreversible.
   *
   * Related operations: PATCH /products/{productId} with status=archived to
   * mark a product for archival (soft delete), which is the recommended
   * approach for published products.
   *
   * @param connection
   * @param productId Unique identifier of the target product to delete. This is
   *   the product's system-generated UUID.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":productId")
  public async erase(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallSellerProductsProductId({
        seller,
        productId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
