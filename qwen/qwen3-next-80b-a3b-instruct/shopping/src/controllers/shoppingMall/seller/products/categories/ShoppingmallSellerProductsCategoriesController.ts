import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia from "typia";
import { getShoppingMallSellerProductsProductIdCategoriesCategoryId } from "../../../../../providers/getShoppingMallSellerProductsProductIdCategoriesCategoryId";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { deleteShoppingMallSellerProductsProductIdCategoriesCategoryId } from "../../../../../providers/deleteShoppingMallSellerProductsProductIdCategoriesCategoryId";

import { IShoppingMallProductCategory } from "../../../../../api/structures/IShoppingMallProductCategory";

@Controller("/shoppingMall/seller/products/:productId/categories/:categoryId")
export class ShoppingmallSellerProductsCategoriesController {
  /**
   * Retrieve a specific category assignment for a product.
   *
   * This operation fetches the relationship between a specific product and its
   * assigned category. It verifies that the product is indeed linked to the
   * requested category in the shopping_mall_product_categories junction table.
   * The product's status and category's active status are checked to ensure
   * both entities are in valid states.
   *
   * This operation is primarily used in product management interfaces and
   * category exploration features where users need to confirm the hierarchical
   * relationship between products and categories.
   *
   * The data returned corresponds to the shopping_mall_product_categories
   * table, with additional context from shopping_mall_products and
   * shopping_mall_categories to validate that both entities are active and
   * properly configured.
   *
   * Related operations:
   *
   * - DELETE /products/{productId}/categories/{categoryId}: Removes this
   *   product-category association
   * - PATCH /products/{productId}/categories: Lists all categories assigned to a
   *   product
   * - GET /categories/{categoryId}/products: Lists all products assigned to a
   *   category
   *
   * @param connection
   * @param productId Unique identifier of the target product. This references
   *   the shopping_mall_products.id field. The product must exist and be in
   *   'published' or 'draft' status to be accessible.
   * @param categoryId Unique identifier of the target product category. This
   *   references the shopping_mall_categories.id field. The category must exist
   *   and have is_active set to true to be accessible.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string,
    @TypedParam("categoryId")
    categoryId: string,
  ): Promise<IShoppingMallProductCategory.IInvert> {
    try {
      return await getShoppingMallSellerProductsProductIdCategoriesCategoryId({
        seller,
        productId,
        categoryId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Remove a specific category assignment from a product.
   *
   * This operation deletes the relationship between a product and one of its
   * assigned categories in the shopping_mall_product_categories junction table.
   * The deletion does not remove the product or category from the system, but
   * only breaks the association between them.
   *
   * The operation requires the product to be in 'draft' status, as published
   * products cannot have their categories modified directly. If the product is
   * 'published', this operation will fail with a 403 error. Seller ownership
   * verification is performed to ensure the caller has permission to modify the
   * product.
   *
   * This functionality enables sellers to refine product categorization during
   * the product creation process before publication. Once a product is
   * published, category changes require creating a new product or using an
   * alternatives such as duplication.
   *
   * Related operations:
   *
   * - GET /products/{productId}/categories/{categoryId}: Retrieves the
   *   product-category association
   * - POST /products/{productId}/categories: Adds a new category association
   * - PATCH /products/{productId}/categories: Lists all categories assigned to a
   *   product
   *
   * @param connection
   * @param productId Unique identifier of the target product. This references
   *   the shopping_mall_products.id field. The product must exist and be in
   *   'draft' status to allow category modification.
   * @param categoryId Unique identifier of the target product category to be
   *   disassociated. This references the shopping_mall_categories.id field.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string,
    @TypedParam("categoryId")
    categoryId: string,
  ): Promise<void> {
    try {
      return await deleteShoppingMallSellerProductsProductIdCategoriesCategoryId(
        {
          seller,
          productId,
          categoryId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
