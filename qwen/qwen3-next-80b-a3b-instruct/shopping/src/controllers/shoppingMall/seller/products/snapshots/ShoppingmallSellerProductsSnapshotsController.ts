import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IPageIShoppingMallProductSnapshot } from "../../../../../api/structures/IPageIShoppingMallProductSnapshot";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { getShoppingMallSellerProductsProductIdSnapshots } from "../../../../../providers/getShoppingMallSellerProductsProductIdSnapshots";

@Controller("/shoppingMall/seller/products/:productId/snapshots")
export class ShoppingmallSellerProductsSnapshotsController {
  /**
   * Retrieve the complete immutable history of product changes for audit, compliance, and dispute resolution.
   *
   * This endpoint returns a paginated list of all historical snapshots of a product’s metadata—including product_id, version, changed_at, and changed_by_id—at the exact moment each change was made by a seller or administrator. Each snapshot captures the product’s state as it existed before modification, preserving the factual record for legal and operational integrity.
   *
   * This functionality is central to shoppingMall’s principle of immutable audit trails, enabling customers to verify what was advertised at the time of purchase, sellers to prove their product descriptions remained consistent, and administrators to investigate disputes with unalterable evidence. Changes are versioned sequentially and always traceable to the actor who made the edit.
   *
   * Responses include the version number, change timestamp, and actor (seller or admin), but do not include variant-level data or product images—these are accessible via dedicated snapshot endpoints for variants and images. The list is ordered from newest to oldest to prioritize recent modifications.
   *
   * This operation is read-only and returns no data if the product does not exist or has never been modified.
   *
   * @param connection
   * @param productId The unique identifier of the product whose snapshot history is being requested. This is the product_id referenced from the shopping_mall_products table.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query shopping_mall_product_snapshots table filtered by product_id. Join with shopping_mall_users to get changed_by display name. Order by version DESC to show newest versions first. Apply pagination with page and limit parameters. Return only fields: version, name, description, base_price, category_id, changed_at, changed_by_id, and snapshot_id. Do not include variant snapshots or product images in this response—they are accessible via separate linked endpoints. Use immutable snapshot records only—no live product data.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string,
  ): Promise<IPageIShoppingMallProductSnapshot.ISummary> {
    try {
      return await getShoppingMallSellerProductsProductIdSnapshots({
        seller,
        productId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
