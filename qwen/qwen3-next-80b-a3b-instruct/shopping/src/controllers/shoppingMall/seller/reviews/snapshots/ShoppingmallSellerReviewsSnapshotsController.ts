import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IPageIShoppingMallReviewSnapshot } from "../../../../../api/structures/IPageIShoppingMallReviewSnapshot";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { getShoppingMallSellerReviewsReviewIdSnapshots } from "../../../../../providers/getShoppingMallSellerReviewsReviewIdSnapshots";

@Controller("/shoppingMall/seller/reviews/:reviewId/snapshots")
export class ShoppingmallSellerReviewsSnapshotsController {
  /**
   * Retrieve the complete immutable history of a review's changes, including rating, content, and deletion status over time.
   *
   * This endpoint provides access to all historical snapshots of a specific review, preserving every change made since its creation. Each snapshot captures the exact state of the review — including rating value, text content, and deletion status — at the moment the change occurred, along with the identity of the actor who made the change and the timestamp of the modification.
   *
   * This feature is critical for dispute resolution between customers and sellers, regulatory compliance, and forensic auditing. Since reviews are subject to editing and deletion, this read-only history ensures that no change can be erased, allowing any party to reconstruct the review's evolution. The returned data is unalterable and cryptographically verifiable, reinforcing the platform's commitment to transactional transparency.
   *
   * Access is restricted by actor role: customers may only view snapshots of their own reviews; sellers may view snapshots for reviews on their products; and administrators have full access to all snapshots across the platform.
   *
   * @param connection
   * @param reviewId The unique identifier of the review whose snapshot history is being requested.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query shopping_mall_review_snapshots table filtered by review_id, ordered by changed_at descending (newest first). Apply pagination with offset/limit based on page and limit query parameters. Include total count for pagination metadata. Return only snapshots where is_deleted is either true or false (include both active and deleted states). Do not join with shopping_mall_reviews table — use only snapshot data. Ensure actor permissions are enforced: customer can only view their own review snapshots via review ID ownership check, seller can view if review's product belongs to them, admin can view all. Return error 404 if reviewId does not exist in shopping_mall_reviews.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("reviewId")
    reviewId: string,
  ): Promise<IPageIShoppingMallReviewSnapshot> {
    try {
      return await getShoppingMallSellerReviewsReviewIdSnapshots({
        seller,
        reviewId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
