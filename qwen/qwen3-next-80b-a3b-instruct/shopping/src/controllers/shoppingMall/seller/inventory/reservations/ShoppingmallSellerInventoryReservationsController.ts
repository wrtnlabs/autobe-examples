import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { patchShoppingMallSellerInventoryReservations } from "../../../../../providers/patchShoppingMallSellerInventoryReservations";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";

import { IPageIShoppingMallInventoryReservation } from "../../../../../api/structures/IPageIShoppingMallInventoryReservation";
import { IShoppingMallInventoryReservation } from "../../../../../api/structures/IShoppingMallInventoryReservation";

@Controller("/shoppingMall/seller/inventory/reservations")
export class ShoppingmallSellerInventoryReservationsController {
  /**
   * Retrieves all inventory reservations for the authenticated seller's
   * inventory units.
   *
   * This operation performs a comprehensive search across all inventory
   * reservations in the shopping_mall_inventory_reservations table. The query
   * filters reservations to include only those associated with inventory units
   * owned by the authenticated seller (via seller_id foreign key
   * relationship).
   *
   * Results can be filtered by reservation status (active, expired), quantity
   * thresholds, expiration date ranges, and order item status. Sorting options
   * are available by creation date, expiration date, or quantity.
   *
   * This operation supports pagination with configurable page sizes (default is
   * 20 items per page). The response returns a paginated set of reservations
   * with essential details including product information, reservation quantity,
   * expiration time, and associated order information.
   *
   * The operation is designed for inventory management workflows where sellers
   * need to track which products are reserved for pending orders. It helps
   * sellers balance inventory availability and order fulfillment timelines.
   *
   * Related operations: DELETE /shoppingMall/seller/inventory/units/{unitId}
   * (delete inventory), GET /shoppingMall/seller/inventory/units/{unitId} (view
   * inventory status).
   *
   * @param connection
   * @param body Search, filter, and pagination parameters for inventory
   *   reservations. page_size must be between 1 and 100.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IShoppingMallInventoryReservation.IRequest,
  ): Promise<IPageIShoppingMallInventoryReservation> {
    try {
      return await patchShoppingMallSellerInventoryReservations({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
