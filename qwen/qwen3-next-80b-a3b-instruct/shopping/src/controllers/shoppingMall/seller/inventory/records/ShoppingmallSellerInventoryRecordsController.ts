import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IPageIShoppingMallInventoryRecord } from "../../../../../api/structures/IPageIShoppingMallInventoryRecord";
import { IShoppingMallInventoryRecord } from "../../../../../api/structures/IShoppingMallInventoryRecord";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { getShoppingMallSellerInventoryRecordsInventoryId } from "../../../../../providers/getShoppingMallSellerInventoryRecordsInventoryId";
import { patchShoppingMallSellerInventoryRecords } from "../../../../../providers/patchShoppingMallSellerInventoryRecords";
import { postShoppingMallSellerInventoryRecords } from "../../../../../providers/postShoppingMallSellerInventoryRecords";

@Controller("/shoppingMall/seller/inventory/records")
export class ShoppingmallSellerInventoryRecordsController {
  /**
   * Create a new inventory record to document stock adjustments or restocking events for product variants in the Shopping Mall platform.
   *
   * This operation allows authenticated sellers to record changes to their product inventory levels, including restocking with positive quantities and adjustments for losses, damages, or manual corrections with negative quantities. Each inventory record is permanently logged in the shopping_mall_inventory_records table, creating an immutable audit trail of all inventory changes for compliance, reconciliation, and debugging purposes.
   *
   * Security: Only authenticated sellers can create inventory records, and only for product variants that they own. The system validates that the provided variantId belongs to the authenticated seller's product catalog. This prevents unauthorized inventory manipulation across different sellers' products.
   *
   * The reason field requires a descriptive justification for the inventory change, ensuring transparency and accountability for all stock movements. This helps sellers track why adjustments occurred and provides evidence for disputes or inventory reconciliation processes.
   *
   * The sourceType field classifies the nature of each change, distinguishing between restocking activities (positive quantity changes from supplier orders) and adjustments (negative or positive changes from internal inventory audits, damages, or manual corrections). This classification enables detailed reporting on inventory movement patterns and helps identify potential issues with supply chain or warehouse management.
   *
   * This operation is not intended for bulk operations or the creation of the initial inventory record when a variant is first created - those should be handled during variant creation. This endpoint is specifically for documenting subsequent inventory changes after the variant is already in circulation.
   *
   * Related operations: GET /inventory/{variantId}/history to view the complete inventory history for a specific variant.
   *
   * @param connection
   * @param body Details of the inventory adjustment or restock event, including the variant being modified, the quantity change, and the reason for the change.
   * @x-autobe-specification Create new inventory record for restock or adjustment events. Validate that variantId corresponds to an existing product variant. For restock events, quantityChange must be positive. For adjustment events, quantityChange must be negative. Record the reason provided by the seller and sourceType as either 'restock' or 'adjustment'. Link the record to the authenticated seller's context so only sellers can add inventory records for their products. Do not allow updates or deletions - inventory history is immutable. Store timezone-aware UTC timestamps. Trigger real-time inventory updates for the associated variant to reflect the new stock level immediately.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IShoppingMallInventoryRecord.ICreate,
  ): Promise<IShoppingMallInventoryRecord> {
    try {
      return await postShoppingMallSellerInventoryRecords({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve paginated inventory records for analysis and auditing purposes. This operation provides access to the audit trail of all inventory adjustments made to product variants across the platform, allowing sellers and administrators to track stock changes, investigate discrepancies, and analyze restocking patterns.
   *
   * The system captures every inventory change as a record in the shopping_mall_inventory_records table, whether it's a restock, adjustment, or impact from order placement/refund/cancellation. Each record contains the variant identifier, quantity change (positive for restocks, negative for adjustments), a reason for the change, the source type indicating whether it came from an order, refund, cancellation, restock, or manual adjustment, the source ID linking to the related transaction, and a timestamp of when the change occurred.
   *
   * This endpoint allows sellers to audit their own inventory history and identify patterns in stock movements, while administrators can perform comprehensive cross-seller inventory analysis for compliance and reporting. The full-text search capability on the reason field enables detailed investigation of specific events from natural language descriptions.
   *
   * Security measures ensure sellers can only access inventory records for products they manage, while administrators have full visibility across all sellers. Each request must be authenticated and authorized to prevent unauthorized access to inventory audit data. Rate limiting prevents abuse of this high-volume audit endpoint.
   *
   * The results are returned in paginated format to handle potentially large volumes of historical data without degrading system performance. This operation does not modify any inventory data - it is strictly a read-only audit trail interface.
   *
   * @param connection
   * @param body Search criteria for filtering inventory records with advanced filtering options
   * @x-autobe-specification Query shopping_mall_inventory_records table with comprehensive filtering and pagination. Apply filters on variantId, sourceType, reason (full-text search), and date ranges (createdAt). Support sorting by createdAt (default), quantityChange, or sourceType. Use cursor-based pagination for optimal performance with large datasets. Cache results for 1 minute with combined filter parameters as cache key. Join with shopping_mall_product_variants to get SKU codes for display. Validate user has permission to view inventory records based on role (seller can only view their own records, admin can view all). Apply rate limiting of 100 requests per minute per user.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IShoppingMallInventoryRecord.IRequest,
  ): Promise<IPageIShoppingMallInventoryRecord.ISummary> {
    try {
      return await patchShoppingMallSellerInventoryRecords({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific inventory adjustment record.
   *
   * This operation fetches a single inventory record by its unique inventoryId from the shopping_mall_inventory_records table. The inventory record captures the history of stock changes, including the quantity change, reason for adjustment, source type, and timestamp. This information is essential for inventory auditing, reconciliation, and troubleshooting stock discrepancies.
   *
   * The operation returns the complete record including the variantId that was affected, the quantity change amount (positive for restock, negative for deduction), the reason for the adjustment, the source type (e.g., 'restock', 'adjustment', 'order_placement'), and the associated sourceId when applicable (e.g., order_id, cancellation_id). The createdAt field indicates when the adjustment was logged in the system.
   *
   * Security: Only authenticated users with appropriate permissions (seller or admin) can access this endpoint. The system checks that the requesting user has ownership or administrative rights to the associated product or seller account.
   *
   * This endpoint is critical for inventory management workflows, allowing sellers to track stock changes and administrators to perform audit investigations. Related operations: GET /shoppingMall/seller/inventory/records/{variantId}/history returns all inventory records for a specific variant, while POST /shoppingMall/seller/inventory/add and POST /shoppingMall/seller/inventory/subtract create new inventory records for restocking or adjustments.
   *
   * This inventory adjustment record is permanently stored as part of the audit trail and cannot be undone or modified.
   *
   * @param connection
   * @param inventoryId Unique identifier for the inventory record
   * @x-autobe-specification Query shopping_mall_inventory_records table by inventoryId using exact match. Return single record with all fields: inventoryId, variantId, quantityChange, reason, sourceType, sourceId, createdAt. Ensure proper authorization checks: seller can only access records for variants they own, admin can access all. Return 404 if record not found. Return 403 if unauthorized access attempt. Cache results for 30 seconds for performance optimization.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":inventoryId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("inventoryId")
    inventoryId: string,
  ): Promise<IShoppingMallInventoryRecord> {
    try {
      return await getShoppingMallSellerInventoryRecordsInventoryId({
        seller,
        inventoryId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
