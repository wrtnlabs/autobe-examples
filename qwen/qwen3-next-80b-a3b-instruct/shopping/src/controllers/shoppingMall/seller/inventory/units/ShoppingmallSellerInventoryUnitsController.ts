import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallSellerInventoryUnits } from "../../../../../providers/postShoppingMallSellerInventoryUnits";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { putShoppingMallSellerInventoryUnitsUnitId } from "../../../../../providers/putShoppingMallSellerInventoryUnitsUnitId";
import { deleteShoppingMallSellerInventoryUnitsUnitId } from "../../../../../providers/deleteShoppingMallSellerInventoryUnitsUnitId";

import { IShoppingMallInventoryUnit } from "../../../../../api/structures/IShoppingMallInventoryUnit";

@Controller("/shoppingMall/seller/inventory/units")
export class ShoppingmallSellerInventoryUnitsController {
  /**
   * Create a new inventory unit in the shoppingMall system.
   *
   * This operation creates a new inventory unit record for a specific product
   * variant owned by a seller. The inventory unit represents the available
   * stock quantity for that variant and serves as the authoritative source for
   * stock availability during checkout.
   *
   * When creating an inventory unit, the system requires the product variant ID
   * and seller ID to establish the correct ownership and product association.
   * The quantity must be a non-negative integer, and min_stock_threshold must
   * be set to trigger alerts when inventory levels become critical.
   *
   * This operation is used by sellers to add new products to their inventory
   * after onboarding or when new stock is received. The inventory_unit record
   * is created before any orders can be fulfilled for this variant.
   *
   * The system automatically sets created_at and updated_at timestamps to track
   * when the inventory record was established and last modified.
   *
   * Security: Only authenticated sellers can create inventory units for
   * products they own. The seller_id is validated against the authenticated
   * user's identity, and the product_variant_id must belong to the same
   * seller.
   *
   * Related operations:
   *
   * - GET /inventory/units/{unitId} - Check inventory status
   * - PUT /inventory/units/{unitId} - Update inventory quantities
   * - PATCH /inventory/units - Search and filter inventory units
   *
   * Note: This operation does not track inventory changes directly. All
   * quantity modifications are recorded in inventory_transactions for audit
   * purposes.
   *
   * This operation directly references the shopping_mall_inventory_units Prisma
   * model with its fields: id, product_variant_id, seller_id, quantity,
   * min_stock_threshold, last_updated, created_at, updated_at.
   *
   * @param connection
   * @param body Creation data for a new inventory unit.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IShoppingMallInventoryUnit.ICreate,
  ): Promise<IShoppingMallInventoryUnit> {
    try {
      return await postShoppingMallSellerInventoryUnits({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing inventory unit in the shoppingMall system.
   *
   * This operation allows sellers to modify the available quantity of an
   * inventory unit for their product variant. The quantity adjustment can be
   * positive (restock) or negative (deduct for anticipated sales), but the
   * final quantity must remain non-negative.
   *
   * The min_stock_threshold can be updated to change when low-stock alerts are
   * triggered. The updated_at timestamp is automatically set to the current
   * time.
   *
   * This operation follows a full update pattern where the entire inventory
   * unit object is replaced with the provided values. The product_variant_id
   * and seller_id cannot be modified through this operation as they establish
   * the fundamental relationship between the inventory unit and its
   * product/seller.
   *
   * Security: Only the seller who owns the inventory unit can update it. The
   * authentication system validates that the requesting user's seller_id
   * matches the inventory unit's seller_id, ensuring sellers can only modify
   * their own inventory.
   *
   * Note: All changes to inventory quantities are recorded in the
   * inventory_transactions table for audit purposes. This operation triggers a
   * corresponding transaction record with type 'adjusted'.
   *
   * Related operations:
   *
   * - POST /inventory/units - Create new inventory units
   * - GET /inventory/units/{unitId} - View inventory details
   * - PATCH /inventory/units - Search inventory units
   *
   * This operation directly references the shopping_mall_inventory_units Prisma
   * model with its fields: id, product_variant_id, seller_id, quantity,
   * min_stock_threshold, last_updated, created_at, updated_at.
   *
   * @param connection
   * @param unitId Unique identifier of the inventory unit to update. This
   *   corresponds to the id field in the shopping_mall_inventory_units model.
   * @param body Updated fields for the inventory unit. Only quantity and
   *   min_stock_threshold can be modified.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":unitId")
  public async update(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("unitId")
    unitId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallInventoryUnit.IUpdate,
  ): Promise<IShoppingMallInventoryUnit> {
    try {
      return await putShoppingMallSellerInventoryUnitsUnitId({
        seller,
        unitId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently removes an inventory unit from the system. This operation
   * completely erases the inventory record and all associated tracking data.
   * This is a hard delete that cannot be undone. The system automatically
   * releases all associated inventory reservations in
   * shopping_mall_inventory_reservations table that reference this unit_id.
   * This process requires atomic transaction handling to ensure data
   * consistency.
   *
   * The operation validates that the authenticated seller is the owner of this
   * inventory unit (via seller_id foreign key). Only the seller who owns the
   * inventory can delete it. This prevents unauthorized deletion of inventory
   * units from other sellers.
   *
   * After deletion, the product variant becomes unavailable for sale until a
   * new inventory unit is created. This is a critical business decision as it
   * affects product availability to customers. Related operations: GET
   * /shoppingMall/seller/inventory/units/{productVariantId} (view inventory),
   * PATCH /shoppingMall/seller/inventory/reservations (search inventory).
   *
   * @param connection
   * @param unitId Unique identifier of the inventory unit to be deleted. This
   *   corresponds to the id field in the shopping_mall_inventory_units table,
   *   which serves as the primary key for database lookup.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":unitId")
  public async erase(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("unitId")
    unitId: string,
  ): Promise<void> {
    try {
      return await deleteShoppingMallSellerInventoryUnitsUnitId({
        seller,
        unitId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
