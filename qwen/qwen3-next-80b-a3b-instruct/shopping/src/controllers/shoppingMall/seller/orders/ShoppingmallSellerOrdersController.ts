import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IPageIShoppingMallOrder } from "../../../../api/structures/IPageIShoppingMallOrder";
import { IShoppingMallOrder } from "../../../../api/structures/IShoppingMallOrder";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { patchShoppingMallSellerOrders } from "../../../../providers/patchShoppingMallSellerOrders";

@Controller("/shoppingMall/seller/orders")
export class ShoppingmallSellerOrdersController {
  /**
   * Retrieve a filtered and paginated list of all orders on the platform for administrative oversight.
   *
   * This operation allows administrators to search and filter orders using multiple criteria including: order number, customer email or ID, seller shop name, date range (created_at), and order status. The results are returned in a paginated format optimized for administrative dashboards.
   *
   * All order data returned reflects the immutable state at the time of transaction, including order totals, customer information, and shipping addresses as they existed when the order was placed. This ensures audit compliance and accurate historical reporting.
   *
   * The system does not permit any modifications to order data via this endpoint. All order alterations must be performed through specific administrative action endpoints (e.g., /admin/orders/{order_id}/items/{item_id}/cancel).
   *
   * @param connection
   * @param body Search criteria and pagination parameters for administrator order overview
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query shopping_mall_orders table with pagination and multiple search filters.
   * - Filter by order_number (exact match)
   * - Filter by customer_id (exact match)
   * - Filter by customer_email (substring match)
   * - Filter by seller_id (exact match)
   * - Filter by seller_shop_name (substring match)
   * - Filter by date range: created_at between start_date and end_date
   * - Filter by status: pay, shipped, delivered, cancelled, refunded, partially_completed
   * - Sort by created_at (default descending), order_number, total_price
   * - Return cursor-based pagination for large result sets
   * - Join with shopping_mall_customers and shopping_mall_sellers for customer and seller display names
   * - Use shopping_mall_order_item_snapshots to validate total_price calculation at time of order
   * - Limit result set to 100 records per page
   * - Apply enforcing created_at DESC as default sort
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IShoppingMallOrder.IRequest,
  ): Promise<IPageIShoppingMallOrder.ISummary> {
    try {
      return await patchShoppingMallSellerOrders({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
