import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallSellerEmailVerification } from "../../../../../../api/structures/IShoppingMallSellerEmailVerification";
import { SellerAuth } from "../../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../../decorators/payload/SellerPayload";
import { postShoppingMallSellerAuthSellersEmailResend } from "../../../../../../providers/postShoppingMallSellerAuthSellersEmailResend";
import { postShoppingMallSellerAuthSellersEmailVerify } from "../../../../../../providers/postShoppingMallSellerAuthSellersEmailVerify";

@Controller("/shoppingMall/seller/auth/sellers/email")
export class ShoppingmallSellerAuthSellersEmailController {
  /**
   * Verify seller email address using a verification token sent during registration.
   *
   * This endpoint completes the seller email verification workflow initiated during registration. When a seller signs up, a unique verification token is generated and sent to their email address. This endpoint receives that token and validates it against the shopping_mall_seller_email_verifications database table. Upon successful validation, the seller's account is marked as verified in the system, enabling full access to seller functionalities such as product listing and order management.
   *
   * Security: The verification token must be a cryptographically secure, single-use token issued only to the registered seller's email address. Token validation ensures that only the person with access to the registered email address can verify the account. Tokens have a limited lifespan (typically expiration within 24-48 hours) to prevent reuse or misuse.
   *
   * This operation is critical for fraud prevention and ensures only legitimate business entities can become sellers. Only sellers with verified emails can access seller dashboards, manage products, and handle customer orders.
   *
   * Related operations: POST /auth/register (initiates seller registration and triggers email verification), GET /sellers/me (retrieves verified seller profile).
   *
   * @param connection
   * @param body Verification token issued for seller email verification
   * @x-autobe-specification Accept POST request with an email verification token in the request body. Validate the token against the shopping_mall_seller_email_verifications table in the database. Check token expiration time - reject tokens older than 48 hours. If token is valid and not expired, update the corresponding seller record in shopping_mall_sellers to set email_verified = true, and mark this verification token as used. If token is invalid, expired, or already used, return appropriate error (400 Bad Request). Clear the verification token record from the database after successful verification to prevent reuse.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("verify")
  public async verify(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IShoppingMallSellerEmailVerification.IRequest,
  ): Promise<void> {
    try {
      return await postShoppingMallSellerAuthSellersEmailVerify({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Resend the verification email to a seller who hasn't completed the registration email verification process.
   *
   * This operation allows sellers who have registered but haven't verified their email address to request a new verification email if they didn't receive the original or if the previous token has expired. The system validates the seller's authenticated identity through their JWT token, then checks that their account status is either 'pending_verification' or 'pending_approval'. When validated, the system generates a new cryptographically secure verification token with a 24-hour expiration period, updates the database record, and sends a new verification email with the new token.
   *
   * Security: This operation requires a valid seller authentication token. Sellers who have already been approved, rejected, or suspended cannot trigger this operation. Rate limiting is applied to prevent abuse of the resend functionality. Email verification tokens are single-use and have a 24-hour expiration window. The email contains a secure link that validates the token and updates the seller account status to 'pending_approval'.
   *
   * Related operations: POST /auth/register (initial registration), POST /auth/login (account authentication), PATCH /sellers/approve (administrator approval of seller registration).
   *
   * @param connection
   * @x-autobe-specification Verify seller identity from JWT token. Check that seller exists with status 'pending_verification' or 'pending_approval'. Confirm email verification token exists and is expired or not yet used. Generate new verification token with 24-hour expiration. Update database record with new token and timestamp. Send new verification email containing the token. Return 204 No Content on success. Return 400 if seller status is not pending, 401 if token is invalid, 403 if seller has been approved/rejected/suspended, and 429 if rate limited.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("resend")
  public async resend(
    @SellerAuth()
    seller: SellerPayload,
  ): Promise<void> {
    try {
      return await postShoppingMallSellerAuthSellersEmailResend({
        seller,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
