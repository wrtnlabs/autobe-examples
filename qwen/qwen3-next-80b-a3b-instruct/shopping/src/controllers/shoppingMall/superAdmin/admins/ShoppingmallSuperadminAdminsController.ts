import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IShoppingMallAdmin } from "../../../../api/structures/IShoppingMallAdmin";
import { SuperadminAuth } from "../../../../decorators/SuperadminAuth";
import { SuperadminPayload } from "../../../../decorators/payload/SuperadminPayload";
import { patchShoppingMallSuperAdminAdminsAdminIdDowngrade } from "../../../../providers/patchShoppingMallSuperAdminAdminsAdminIdDowngrade";
import { patchShoppingMallSuperAdminAdminsAdminIdUpgrade } from "../../../../providers/patchShoppingMallSuperAdminAdminsAdminIdUpgrade";

@Controller("/shoppingMall/superAdmin/admins/:adminId")
export class ShoppingmallSuperadminAdminsController {
  /**
   * Promote a regular administrator to super administrator status.
   *
   * This operation is exclusively accessible to super administrators and is used to elevate a regular admin to full system-level privileges. Only admins with adminType 'regular' can be promoted. This change grants the promoted admin full permissions over all other administrators, including promotion, demotion, and oversight of the entire platform.
   *
   * The operation does not require a request body because the action is implied by the endpoint path. The admin to be promoted is identified by the adminId in the path parameter. Upon successful execution, the adminType field in the shopping_mall_admins database table is updated from 'regular' to 'super'.
   *
   * All admin promotion requests must be audited in the system's audit log, capturing the identity of the approving super admin and the timestamp of the change.
   *
   * This operation cannot be reversed by regular admins or other super admins. Only system-level recovery procedures can downgrade a super admin.
   *
   * Related operations: PATCH /admins/{adminId}/downgrade
   *
   * @param connection
   * @param adminId Unique identifier of the administrator to promote. Must be a valid UUID reference in the shopping_mall_admins table.
   * @x-autobe-specification Query shopping_mall_admins table for the admin with provided adminId. Validate that the current adminType is 'regular' and that the calling user has adminType 'super'. If valid, update the adminType to 'super' using a database transaction. Log the promotion event in the audit trail. Return updated admin object with new adminType. Throw 403 if caller is not a super admin or target is not a regular admin. Throw 404 if adminId does not exist.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch("upgrade")
  public async upgrade(
    @SuperadminAuth()
    superAdmin: SuperadminPayload,
    @TypedParam("adminId")
    adminId: string,
  ): Promise<IShoppingMallAdmin> {
    try {
      return await patchShoppingMallSuperAdminAdminsAdminIdUpgrade({
        superAdmin,
        adminId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Demote a regular administrator to standard user status with all administrative privileges removed.
   *
   * This privileged operation allows super-administrators to demote regular administrators by changing their adminType from 'regular' to 'user'. The targeted admin loses all administrative capabilities and reverts to standard user status with only member-level permissions. This action cannot be undone and automatically triggers system audit logging for compliance tracking.
   *
   * Authorization: Only super-administrators may invoke this endpoint. The system validates the requesting user's admin_type field in their JWT token to ensure they have the required super-admin privileges. No one can downgrade themselves or other super-administrators.
   *
   * Security: This action is irreversible and permanently removes administrative access. The target admin's authentication token remains active until expiration but loses all administrative permissions upon next validation. Any pending administrative tasks associated with the downgraded user are flagged for reassignment.
   *
   * Related operations: /admins/{adminId}/upgrade (promote user to admin), /admins/requests (approve admin applications), /admins/manage (list all admins).
   *
   * @param connection
   * @param adminId Unique identifier of the regular administrator to be downgraded (scoped to regular admin accounts)
   * @x-autobe-specification Perform an admin downgrade operation by updating the adminType field in the shopping_mall_admins table from 'regular' to 'user'. Authenticate request with super-admin JWT token. Verify target adminId exists and has adminType 'regular'. Log administrative downgrade action in system audit logs. Return 204 No Content on success. Return 403 Forbidden if requester is not a super-admin. Return 404 Not Found if adminId does not exist or is not a regular admin. Return 409 Conflict if target is already a super-admin or non-admin.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch("downgrade")
  public async downgrade(
    @SuperadminAuth()
    superAdmin: SuperadminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await patchShoppingMallSuperAdminAdminsAdminIdDowngrade({
        superAdmin,
        adminId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
