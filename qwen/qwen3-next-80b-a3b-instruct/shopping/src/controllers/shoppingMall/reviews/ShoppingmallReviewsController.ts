import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia from "typia";
import { getShoppingMallReviewsReviewId } from "../../../providers/getShoppingMallReviewsReviewId";
import { patchShoppingMallReviews } from "../../../providers/patchShoppingMallReviews";

import { IShoppingMallReview } from "../../../api/structures/IShoppingMallReview";
import { IPageIShoppingMallReview } from "../../../api/structures/IPageIShoppingMallReview";

@Controller("/shoppingMall/reviews")
export class ShoppingmallReviewsController {
  /**
   * Retrieve a specific product review from the shoppingMall platform. This
   * operation operates on the shopping_mall_reviews table and returns the
   * complete review details including title, body, rating, and status.
   *
   * The review is identified by its unique reviewId and can be accessed by any
   * authenticated user. The operation returns the review as-is regardless of
   * its status (published, pending, rejected, or hidden). This ensures that
   * users who have previously seen a review can still access it, even if it has
   * since been moderated. The operation retrieves all fields from the
   * shopping_mall_reviews table as defined in the Prisma schema, including
   * metadata like created_at, updated_at, and deleted_at timestamps.
   *
   * Security: This is a public endpoint with no authentication required.
   * However, the response may contain a soft-deleted review if deleted_at is
   * not null, which should be handled appropriately by consuming applications.
   *
   * Related operations: This operation should be used in conjunction with PATCH
   * /reviews to retrieve the list of reviews for a product, and with POST
   * /reviews to create new reviews. Any client displaying a review should
   * handle soft-deleted records by hiding them from view while still allowing
   * access to the original data for auditing purposes.
   *
   * @param connection
   * @param reviewId Unique identifier of the target review. UUID format as
   *   defined in the Prisma schema.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":reviewId")
  public async at(
    @TypedParam("reviewId")
    reviewId: string,
  ): Promise<IShoppingMallReview> {
    try {
      return await getShoppingMallReviewsReviewId({
        reviewId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a filtered, sorted, and paginated list of product reviews on the
   * shoppingMall platform. This operation operates on the shopping_mall_reviews
   * table and provides advanced search capabilities for finding reviews based
   * on multiple criteria including product association, customer, rating range,
   * status, and date ranges.
   *
   * The operation supports comprehensive pagination with configurable page
   * sizes and sorting options. Reviews can be sorted by rating, creation date,
   * or update date in ascending or descending order. Filtering by product_id,
   * customer_id, status, and rating range (1-5) are supported. The response
   * returns only reviews with status 'published' by default, but the status
   * filter can be overridden in the request to include other statuses for
   * administrative purposes.
   *
   * The implementation uses indexes on status, shopping_mall_product_id, and
   * created_at columns for optimal query performance. Full-text search on title
   * and body fields is enabled via GIN indexes for keyword search.
   *
   * Security: This is a public endpoint with no authentication required.
   * However, access to reviews with status 'pending', 'rejected', or 'hidden'
   * is restricted to administrative actors. Consumers should handle
   * soft-deleted reviews by excluding them from display unless specifically
   * requested by administrators.
   *
   * Related operations: This operation should be used to populate review lists
   * on product pages. After retrieving a list of reviews, a client can use GET
   * /reviews/{reviewId} to retrieve detailed information about any specific
   * review.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for review filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IShoppingMallReview.IRequest,
  ): Promise<IPageIShoppingMallReview.ISummary> {
    try {
      return await patchShoppingMallReviews({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
