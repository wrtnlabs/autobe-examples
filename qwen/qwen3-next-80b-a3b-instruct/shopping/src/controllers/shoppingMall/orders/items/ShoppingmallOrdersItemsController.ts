import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia from "typia";
import { getShoppingMallOrdersOrderNumberItemsId } from "../../../../providers/getShoppingMallOrdersOrderNumberItemsId";
import { postShoppingMallOrdersOrderNumberItems } from "../../../../providers/postShoppingMallOrdersOrderNumberItems";

import { IShoppingMallOrderItem } from "../../../../api/structures/IShoppingMallOrderItem";

@Controller("/shoppingMall/orders/:orderNumber/items")
export class ShoppingmallOrdersItemsController {
  /**
   * Retrieve a specific order item by its ID within the context of an order
   * identified by its unique order number.
   *
   * This operation fetches an individual product item from an order using the
   * order's globally unique order_number (not UUID ID) and the item's internal
   * ID. The operation ensures data integrity by validating that the requested
   * item belongs to the specified order before returning results. This prevents
   * unauthorized access to items from other orders.
   *
   * The response includes the complete item details as they existed at the time
   * of purchase, including the unit price, quantity, total amount, and any
   * special customer notes. This provides an immutable historical record of the
   * purchase.
   *
   * Security: Public access since order items are accessible to anyone who
   * knows the order_number and item ID, as order items are not considered
   * sensitive private information beyond the order context.
   *
   * This operation is used during order tracking, customer service inquiries,
   * and invoice generation where specific line items need to be referenced.
   *
   * Relationships: This endpoint depends on both the shopping_mall_orders and
   * shopping_mall_order_items models. The order_number is a unique field in
   * shopping_mall_orders, and the item ID is a primary key in
   * shopping_mall_order_items with a foreign key relationship to
   * shopping_mall_orders.
   *
   * @param connection
   * @param orderNumber Unique order identifier in format ORD-YYYYMMDD-NNNNN
   *   (global scope). Must match exactly with an existing order.
   * @param id Unique identifier of the specific order item within the order.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":id")
  public async at(
    @TypedParam("orderNumber")
    orderNumber: string,
    @TypedParam("id")
    id: string,
  ): Promise<IShoppingMallOrderItem> {
    try {
      return await getShoppingMallOrdersOrderNumberItemsId({
        orderNumber,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Add a new product item to an existing order based on the order's unique
   * order number.
   *
   * This operation creates a new order line item within an existing order
   * context, identified by the order's unique order_number (not UUID ID). The
   * operation validates that the specified order exists and is in a modifiable
   * state (draft or pending_payment) before adding the item.
   *
   * The request body specifies the product variant and quantity to be added.
   * The system automatically calculates and populates the unit_price based on
   * the product variant's current market price at the time of addition,
   * ensuring historical pricing accuracy. The item_total is calculated as
   * quantity × unit_price.
   *
   * This operation supports product selection during the checkout process
   * before payment completion. Once an order reaches paid or confirmed status,
   * no further items can be added.
   *
   * Security: Public access since adding items to an order doesn't require user
   * authentication, as the order is identified by its public order_number.
   * Authorization is enforced at the business logic level to ensure that items
   * can only be added to orders in modifiable states.
   *
   * This operation is crucial for the shopping cart workflow where customers
   * can iteratively add multiple products to an order before finalizing
   * checkout.
   *
   * Relationships: This endpoint depends on both the shopping_mall_orders model
   * (for order validation and context) and the shopping_mall_product_variants
   * model (for product pricing and inventory information). The item is then
   * persisted in the shopping_mall_order_items table with a foreign key
   * relationship to the order.
   *
   * @param connection
   * @param orderNumber Unique order identifier in format ORD-YYYYMMDD-NNNNN
   *   (global scope). Must match exactly with an existing order.
   * @param body Details for adding a new product item to the order, including
   *   the product variant and quantity.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @TypedParam("orderNumber")
    orderNumber: string,
    @TypedBody()
    body: IShoppingMallOrderItem.ICreate,
  ): Promise<IShoppingMallOrderItem> {
    try {
      return await postShoppingMallOrdersOrderNumberItems({
        orderNumber,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
