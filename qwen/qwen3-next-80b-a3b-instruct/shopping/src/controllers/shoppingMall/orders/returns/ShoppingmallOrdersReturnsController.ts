import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallOrdersOrderNumberReturns } from "../../../../providers/patchShoppingMallOrdersOrderNumberReturns";
import { getShoppingMallOrdersOrderNumberReturnsId } from "../../../../providers/getShoppingMallOrdersOrderNumberReturnsId";
import { deleteShoppingMallOrdersOrderNumberReturnsId } from "../../../../providers/deleteShoppingMallOrdersOrderNumberReturnsId";

import { IPageIShoppingMallOrderReturn } from "../../../../api/structures/IPageIShoppingMallOrderReturn";
import { IShoppingMallOrderReturn } from "../../../../api/structures/IShoppingMallOrderReturn";

@Controller("/shoppingMall/orders/:orderNumber/returns")
export class ShoppingmallOrdersReturnsController {
  /**
   * Retrieve return records associated with a specific order using its order
   * number.
   *
   * This operation performs a search across all return requests linked to the
   * order identified by the provided orderNumber. It returns a paginated list
   * of return records with comprehensive details about return status, requested
   * products, refund amounts, and processing history.
   *
   * The system uses the orderNumber to locate the internal UUID-based order
   * record, then retrieves all return records associated with that order
   * through the shopping_mall_order_returns table's foreign key relationship.
   * The operation supports filtering by return status and sorting by return
   * date.
   *
   * This is a read-only operation that does not modify any return records. The
   * response includes summary information for each return, with links to
   * detailed return records if needed.
   *
   * Authorization: Any authenticated user can search for returns on their own
   * orders. Admin users can search for returns across all orders.
   *
   * Related operations: POST /orders/{orderNumber}/returns (to create a new
   * return request) and GET /returns/{returnId} (to retrieve a specific return
   * record details).
   *
   * @param connection
   * @param orderNumber Unique order identifier in format ORD-YYYYMMDD-NNNNN.
   *   Must be globally unique and exactly match the orderNumber field in the
   *   shopping_mall_orders table.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedParam("orderNumber")
    orderNumber: string,
  ): Promise<IPageIShoppingMallOrderReturn.ISummary> {
    try {
      return await patchShoppingMallOrdersOrderNumberReturns({
        orderNumber,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed return information for a specific order return.
   *
   * This operation provides comprehensive details about a return request
   * associated with an order. The return record contains information about the
   * original order, reason for return, processing status, refund amounts, and
   * tracking details.
   *
   * The endpoint is accessed via the order's unique order_number (not order ID)
   * and the return's UUID id. The system uses order_number in the path for
   * human-readable URLs rather than UUID identifiers, improving usability and
   * debugging.
   *
   * Security: The return information is only accessible to the original
   * customer who placed the order or to system administrators. The
   * authentication system validates that the requesting user either owns the
   * order or has administrative privileges.
   *
   * Business Logic: The return must exist and be associated with the specified
   * order. If the return has been deleted (soft-deleted), this endpoint will
   * return 404 Not Found. If the return status is 'denied', this endpoint still
   * returns all details about the denied return.
   *
   * Related Operations:
   *
   * - PUT /orders/{orderNumber}/returns/{id} - Update return status and details
   * - PATCH /orders/{orderNumber}/returns - List all returns for an order
   *
   * Implementation Note: This operation joins shopping_mall_order_returns with
   * shopping_mall_orders to validate the relationship between returned item and
   * original purchase, ensuring data integrity.
   *
   * @param connection
   * @param orderNumber Unique order identifier in format ORD-YYYYMMDD-NNNNN.
   *   Must match the order_number field in shopping_mall_orders table.
   * @param id Unique identifier of the return request. Must match the id field
   *   in shopping_mall_order_returns table.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":id")
  public async at(
    @TypedParam("orderNumber")
    orderNumber: string,
    @TypedParam("id")
    id: string,
  ): Promise<IShoppingMallOrderReturn> {
    try {
      return await getShoppingMallOrdersOrderNumberReturnsId({
        orderNumber,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a specific return request associated with an order.
   *
   * This operation permanently removes a return record identified by its unique
   * ID within the context of a specific order. It should be used when a return
   * request needs to be canceled or discarded before processing.
   *
   * The return request must be in 'requested' or 'denied' status to be deleted.
   * Returns in 'approved', 'awaiting_return', 'received', or 'refunded' status
   * cannot be deleted to maintain audit integrity and prevent fraudulent
   * activity.
   *
   * This path requires both the order's order_number and the return's unique ID
   * to identify the return record. This ensures that return requests are scoped
   * to their parent order, preventing unauthorized access to other orders'
   * return data.
   *
   * The system will not send any confirmation or response body - deletion is
   * considered final.
   *
   * The operation references the shopping_mall_order_returns model in the
   * Prisma schema, which tracks return requests with status, reason, and
   * tracking information.
   *
   * Related operations: GET /orders/{orderNumber}/returns/{id} to view return
   * details, PATCH /orders/{orderNumber}/returns to list returns for an order.
   *
   * @param connection
   * @param orderNumber Unique order identifier in format ORD-YYYYMMDD-NNNNN.
   *   Represents the parent order for the return.
   * @param id Unique identifier of the return request in the system (UUID).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":id")
  public async erase(
    @TypedParam("orderNumber")
    orderNumber: string,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallOrdersOrderNumberReturnsId({
        orderNumber,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
