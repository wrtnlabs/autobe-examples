import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia from "typia";
import { patchShoppingMallOrders } from "../../../providers/patchShoppingMallOrders";
import { getShoppingMallOrdersOrderNumber } from "../../../providers/getShoppingMallOrdersOrderNumber";

import { IPageIShoppingMallOrder } from "../../../api/structures/IPageIShoppingMallOrder";
import { IShoppingMallOrder } from "../../../api/structures/IShoppingMallOrder";

@Controller("/shoppingMall/orders")
export class ShoppingmallOrdersController {
  /**
   * Retrieve a filtered and paginated list of shopping mall orders from the
   * system. This operation operates on the shopping_mall_orders table and
   * provides advanced search capabilities for finding orders based on multiple
   * criteria including customer identifier, date ranges, status filters,
   * payment method, and order amount thresholds.
   *
   * The operation supports comprehensive pagination with configurable page
   * sizes and sorting options. Orders can be sorted by creation date, total
   * amount, status, or other relevant fields in ascending or descending order.
   * Additional filtering capabilities include status selection (draft,
   * pending_payment, paid, confirmed, shipped, delivered, cancelled, refunded,
   * completed), customer ID filtering, date range filtering for creation and
   * update timestamps, and amount range filtering for total_amount.
   *
   * Security considerations include rate limiting for search operations and
   * appropriate filtering of sensitive customer information based on the
   * requesting user's authorization level. Only users with appropriate
   * permissions can access detailed order information, while basic order lists
   * may be available to authenticated users.
   *
   * This operation integrates with the shopping_mall_orders table as defined in
   * the Prisma schema, incorporating all available order fields and
   * relationships. The response includes order summary information optimized
   * for list displays, with options to include additional details based on
   * authorization level.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for order filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IShoppingMallOrder.IRequest,
  ): Promise<IPageIShoppingMallOrder.ISummary> {
    try {
      return await patchShoppingMallOrders({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific shopping mall order by its unique order number. This
   * operation operates on the shopping_mall_orders table and returns complete
   * details of a single order identified by its globally unique order_number
   * field.
   *
   * The order_number is a human-readable identifier in format
   * ORD-YYYYMMDD-NNNNN that uniquely identifies each order across the entire
   * platform. This provides a more user-friendly and audit-friendly alternative
   * to UUID identifiers. The operation validates that the requested
   * order_number exists and is active (not soft-deleted).
   *
   * Security considerations include verification that the requesting user has
   * appropriate access rights to view this specific order. Each order is linked
   * to a specific customer, and the system enforces ownership access control -
   * only the order's customer, admin, or authorized personnel can retrieve
   * order details. The response includes full order details with all associated
   * line items, payment information, and shipping details.
   *
   * This operation provides a direct reference to the shopping_mall_orders
   * table and uses the order_number field to locate the specific record in
   * accordance with the unique index defined in the Prisma schema. The details
   * returned are comprehensive including subtotal, tax amount, shipping fee,
   * discount amount, and total_amount, as well as order status and business
   * status for comprehensive reporting and auditing purposes.
   *
   * @param connection
   * @param orderNumber Unique order identifier in format ORD-YYYYMMDD-NNNNN
   *   that must be globally unique in the system
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":orderNumber")
  public async at(
    @TypedParam("orderNumber")
    orderNumber: string,
  ): Promise<IShoppingMallOrder> {
    try {
      return await getShoppingMallOrdersOrderNumber({
        orderNumber,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
