import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia from "typia";
import { getShoppingMallOrdersOrderNumberShipping } from "../../../../providers/getShoppingMallOrdersOrderNumberShipping";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { putShoppingMallOrdersOrderNumberShipping } from "../../../../providers/putShoppingMallOrdersOrderNumberShipping";

import { IShoppingMallOrderShipping } from "../../../../api/structures/IShoppingMallOrderShipping";

@Controller("/shoppingMall/orders/:orderNumber/shipping")
export class ShoppingmallOrdersShippingController {
  /**
   * Retrieve detailed shipping information for a specific order using its
   * unique order number. This operation accesses the
   * shopping_mall_order_shipping table to return comprehensive delivery details
   * including recipient information, carrier data, and tracking information.
   * The order_number field serves as the primary reference since it's globally
   * unique and designed for human readability, avoiding UUID-based identifiers.
   * The shipping data represents the state of delivery information at the time
   * of order processing, allowing accurate historical retrieval even if
   * customer addresses change later. This operation supports the business need
   * to provide customers with real-time shipping status updates and allows
   * customer support to access complete delivery details for inquiries.
   *
   * When an order reaches the 'pending_payment' status, a corresponding
   * shopping_mall_order_shipping record is created with the customer's provided
   * shipping address. The tracking_number and tracking_url fields are populated
   * when the seller marks the order as shipped, enabling customers to monitor
   * delivery progress through carrier websites. The estimated_delivery_date is
   * calculated based on the selected shipping method and destination, while
   * real_delivery_date is recorded when confirmed by the carrier's system.
   *
   * Security considerations: This read operation is available to the order's
   * customer (the authenticated user who created the order) and to
   * administrative personnel. The operation uses the order_number parameter
   * rather than the internal ID to expose a user-friendly identifier, while
   * maintaining security through careful authorization validation against the
   * customer-seller relationship.
   *
   * Related operations: Update shipping details (PUT
   * /orders/{orderNumber}/shipping), List all orders for a customer (PATCH
   * /orders).
   *
   * @param connection
   * @param orderNumber Unique business identifier code of the target order
   *   (global scope). This operates as the primary key for order retrieval and
   *   follows the format ORD-YYYYMMDD-NNNNN as defined in the
   *   shopping_mall_orders schema.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("orderNumber")
    orderNumber: string,
  ): Promise<IShoppingMallOrderShipping> {
    try {
      return await getShoppingMallOrdersOrderNumberShipping({
        admin,
        orderNumber,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update the shipping information for a specific order using its unique order
   * number. This operation modifies the shopping_mall_order_shipping record
   * associated with the target order, allowing updates to delivery details
   * before the order is marked as shipped. The order_number field serves as the
   * primary reference since it's globally unique and designed for human
   * readability, avoiding UUID-based identifiers.
   *
   * Required fields include recipient name, address components, and contact
   * phone number. Updates can modify any portion of the shipping information
   * except the associated order ID (which remains fixed). This operation is
   * designed for use during the order preparation phase, particularly when
   * customers need to correct delivery addresses after placing an order but
   * before fulfillment begins. After shipping, this endpoint becomes
   * read-only.
   *
   * When the order status is 'draft' or 'pending_payment', customers can modify
   * their shipping details. The system validates all address components against
   * international formatting standards and requires at minimum: first_name,
   * last_name, address_line1, city, state, postal_code, and country. The phone
   * field is required for carrier delivery attempts.
   *
   * The carrier field cannot be modified via this operation as it's determined
   * by the shipping method selection. Tracking_number and tracking_url fields
   * are system-managed and updated automatically by sellers or fulfillment
   * systems when the order is progressed to 'shipped' status. Manual updates to
   * tracking information are prohibited to maintain data integrity and prevent
   * fraudulent activities.
   *
   * Security considerations: Only the customer who created the order can update
   * its shipping information. Admins can also modify shipping details for
   * support purposes, but must provide proper justification in audit logs. This
   * prevents unauthorized alterations to delivery addresses that could
   * facilitate fraud or theft.
   *
   * Related operations: View shipping details (GET
   * /orders/{orderNumber}/shipping), List all orders for a customer (PATCH
   * /orders).
   *
   * @param connection
   * @param orderNumber Unique business identifier code of the target order
   *   (global scope). This operates as the primary key for order retrieval and
   *   follows the format ORD-YYYYMMDD-NNNNN as defined in the
   *   shopping_mall_orders schema.
   * @param body Shipping information fields to be updated for the order.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("orderNumber")
    orderNumber: string,
    @TypedBody()
    body: IShoppingMallOrderShipping.IUpdate,
  ): Promise<IShoppingMallOrderShipping> {
    try {
      return await putShoppingMallOrdersOrderNumberShipping({
        admin,
        orderNumber,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
