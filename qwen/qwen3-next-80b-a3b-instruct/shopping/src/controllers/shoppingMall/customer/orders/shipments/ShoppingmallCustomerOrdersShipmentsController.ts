import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallShipment } from "../../../../../api/structures/IPageIShoppingMallShipment";
import { IShoppingMallShipment } from "../../../../../api/structures/IShoppingMallShipment";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { getShoppingMallCustomerOrdersOrderIdShipmentsShipmentId } from "../../../../../providers/getShoppingMallCustomerOrdersOrderIdShipmentsShipmentId";
import { patchShoppingMallCustomerOrdersOrderIdShipments } from "../../../../../providers/patchShoppingMallCustomerOrdersOrderIdShipments";

@Controller("/shoppingMall/customer/orders/:orderId/shipments")
export class ShoppingmallCustomerOrdersShipmentsController {
  /**
   * Retrieve a paginated list of all shipments associated with a specific order.
   *
   * This operation returns complete shipment details for the specified order, including carrier information, tracking numbers, shipment timestamps, and the list of order items contained in each shipment. This view allows customers to track the physical delivery progress of their purchase from seller to doorstep. The shipments are returned in chronological order (oldest first) to represent the sequence of delivery events.
   *
   * Security: Only the customer who created the order, the seller who produced any items in the order, or administrative personnel may access this information. The endpoint enforces strict ownership validation: the customer_id of the order must match the authenticated customer, or the seller_id of any shipment's order items must match the authenticated seller, or the caller must have admin privileges.
   *
   * Relationships: This endpoint depends on two related operations: GET /shopping_mall/customer/orders/{orderId} to validate order ownership, and GET /shopping_mall/sellers/orders/{orderId} to validate seller access if requested by seller. Each shipment's items are linked back to shopping_mall_order_items, which in turn reference immutable product and variant snapshots.
   *
   * Business Logic: Shipment records are created by sellers when they dispatch order items. Every shipment belongs to exactly one order and contains one or more order items. Shipping information (carrier, tracking_number) is provided by the seller at shipment creation and remains immutable. Delivery confirmation is handled by a separate endpoint POST /shopping_mall/customer/shipments/{shipmentId}/confirm-delivery. Automatic delivery status changes occur after 14 days if no customer confirmation is received, as specified in 05-inventory-handling.md.
   *
   * The response includes a summary of each shipment's items, which allows customers to see which products are in each delivery without loading the full order item details. For detailed product and variant state at time of purchase, refer to the immutable snapshots embedded in the order item records.
   *
   * Status Handling: Shipment status is derived from its items. If all items in a shipment have been delivered, the shipment status is "delivered". If at least one item has been delivered but others are not, the status is "partially_delivered". If no items have been delivered, it remains "shipped". This status is reflected in the summary response.
   *
   * @param connection
   * @param orderId The unique identifier of the order whose shipments are being requested.
   * @param body Filtering and pagination parameters for shipment retrieval
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query shopping_mall_shipments table joined with shopping_mall_shipment_items where order_id = {orderId}. Group results by shipment_id. For each shipment, aggregate the count of items and determine overall status based on item statuses: 'shipped' if all items are 'shipped', 'partially_delivered' if some items are 'delivered' and some are 'shipped', 'delivered' if all are 'delivered'. Apply pagination: 10 shipments per page, cursor-based for performance. Sort by shipped_at ascending. Include only active shipments (deleted_at is null). Return shipment properties: id, carrier_name, tracking_number, shipped_at, delivered_at (if any), status, and total items in shipment. For each shipment, include a list of associated order_item_ids (not full item details).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderId")
    orderId: string,
    @TypedBody()
    body: IShoppingMallShipment.IRequest,
  ): Promise<IPageIShoppingMallShipment.ISummary> {
    try {
      return await patchShoppingMallCustomerOrdersOrderIdShipments({
        customer,
        orderId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve the complete and immutable record of a specific shipment within a customer's order.
   *
   * This operation returns a verifiable, historical snapshot of the shipment as it existed at the moment of dispatch, including the carrier name, tracking number, and exact timestamp of shipment creation. It also includes a list of all order items in the shipment, each with their product name, variant SKU, quantity, and purchase price exactly as they existed at the time of checkout.
   *
   * All data is sourced from immutable snapshots maintained by the system according to the snapshot principle: product details, variant specifications, and seller profiles are preserved as they appeared at purchase, not as they exist today. This ensures auditability and dispute resolution integrity.
   *
   * Customers may only request shipments associated with their own orders. Authorization is enforced by verifying the order's customer_id matches the authenticated user. No seller, product, or variant data is ever hydrated from live records—only from persistent snapshots.
   *
   * @param connection
   * @param orderId The unique identifier of the order that contains this shipment. Must be a UUID and belong to the authenticated customer.
   * @param shipmentId The unique identifier of the shipment to retrieve. Must be a UUID and belong to the specified order.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Join shopping_mall_shipments with shopping_mall_order_items using shipment_id to fetch all order items within this shipment. Validate that the order_id in shopping_mall_shipments matches the provided orderId path parameter and that the order.customer_id matches the authenticated customer. Return shipment object with carrier_name, tracking_number, shipped_at, and array of order_items with product_name, variant_sku, quantity, price_at_time_of_purchase, and reference to snapshot_ids (if needed for audit). Do not include seller or product details beyond what is stored in order_items — rely on snapshots. Do not perform any updates or state changes.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":shipmentId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedParam("shipmentId")
    shipmentId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallShipment.ISummary> {
    try {
      return await getShoppingMallCustomerOrdersOrderIdShipmentsShipmentId({
        customer,
        orderId,
        shipmentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
