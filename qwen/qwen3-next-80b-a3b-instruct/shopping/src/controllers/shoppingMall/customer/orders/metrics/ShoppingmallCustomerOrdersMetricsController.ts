import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallOrderItem } from "../../../../../api/structures/IShoppingMallOrderItem";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { getShoppingMallCustomerOrdersMetrics } from "../../../../../providers/getShoppingMallCustomerOrdersMetrics";

@Controller("/shoppingMall/customer/orders/metrics")
export class ShoppingmallCustomerOrdersMetricsController {
  /**
   * Compute aggregated metrics for platform order performance and financial health. This endpoint calculates key business intelligence metrics from the shopping_mall_orders and shopping_mall_order_items tables to provide executives and administrators with an overview of marketplace activity without requiring examination of individual orders.
   *
   * The operation returns a comprehensive summary including total order volume (orderCount), total revenue generated (totalRevenue), average order value (averageOrderValue), and distribution of orders across all status categories. This aggregated analysis enables strategic decision-making regarding platform growth, fulfillment efficiency, and financial performance. The metrics are calculated from the complete order dataset, using the immutable order and order item snapshots guaranteed by the snapshot principle to ensure auditability and data integrity.
   *
   * This operation implements a critical analytical requirement for dashboard visibility - it provides an at-a-glance assessment of order patterns without exposing individual customer data. The calculation methodology combines direct order totals from shopping_mall_orders with derived revenue calculations by summing the quantity × price from each associated order item in shopping_mall_order_items. This cross-table aggregation ensures accuracy and prevents data duplication.
   *
   * The status breakdown provides insight into order fulfillment efficiency by showing how many orders are pending processing, completed, canceled, or refunded. This helps identify potential bottlenecks in the order fulfillment workflow and enables timely intervention if abnormal patterns emerge, such as high cancellation rates in specific seller categories or product types.
   *
   * @param connection
   * @x-autobe-specification Compute aggregate order metrics from shopping_mall_orders and shopping_mall_order_items tables.
   *
   * Query shopping_mall_orders to count total number of orders and sum of total_amount.
   * Join with shopping_mall_order_items to calculate total revenue (sum of quantity × price) from all order items.
   * Calculate average order value by dividing total revenue by total order count.
   * Group orders by status to count number of orders in each status category: paid, shipped, delivered, cancelled, refunded, partially_completed.
   *
   * Exclude any orders with status 'deleted' (if exists) or null.
   *
   * Return all metrics in single response object including:
   * - orderCount: total number of completed orders
   * - totalRevenue: sum of all order item amounts (quantity × unit price)
   * - averageOrderValue: totalRevenue / orderCount
   * - statusBreakdown: object with count for each status category
   *
   * Execute as single optimized SQL query with appropriate indexes on created_at and status fields for performance.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
  ): Promise<IShoppingMallOrderItem> {
    try {
      return await getShoppingMallCustomerOrdersMetrics({
        customer,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
