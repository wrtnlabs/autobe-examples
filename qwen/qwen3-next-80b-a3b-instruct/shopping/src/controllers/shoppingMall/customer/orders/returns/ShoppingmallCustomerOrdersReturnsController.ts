import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia from "typia";
import { postShoppingMallCustomerOrdersOrderNumberReturns } from "../../../../../providers/postShoppingMallCustomerOrdersOrderNumberReturns";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { patchShoppingMallCustomerOrdersOrderNumberReturns } from "../../../../../providers/patchShoppingMallCustomerOrdersOrderNumberReturns";

import { IShoppingMallOrderReturn } from "../../../../../api/structures/IShoppingMallOrderReturn";
import { IPageIShoppingMallOrderReturn } from "../../../../../api/structures/IPageIShoppingMallOrderReturn";

@Controller("/shoppingMall/customer/orders/:orderNumber/returns")
export class ShoppingmallCustomerOrdersReturnsController {
  /**
   * Submit a return request for an order. This operation creates a new return
   * record that initiates the return workflow for products associated with the
   * specified order.
   *
   * When a customer submits a return request, the system validates that the
   * order exists and is in a state that permits returns (paid, delivered, or
   * completed). The request captures the primary return reason and any
   * additional details provided by the customer. The system then creates a
   * return record linked to the order and places the return in 'requested'
   * status awaiting admin review.
   *
   * This operation fulfills the requirement for customers to initiate return
   * processes and creates the necessary audit trail of return intent. The
   * actual processing (approval, receipt of items, refund issuance) requires
   * separate administrative actions and is not performed by this endpoint.
   *
   * Security: Customers can only create return requests for orders they have
   * placed. The system validates ownership by matching the authenticated user's
   * ID against the order's customer ID.
   *
   * Related Operations: PATCH /orders/{orderNumber}/returns (to retrieve return
   * status), PUT /orders/{orderNumber}/returns (to update return request), GET
   * /orders/{orderNumber}/returns (to view existing return requests)
   *
   * @param connection
   * @param orderNumber Unique order identifier in format ORD-YYYYMMDD-NNNNN.
   *   This must match exactly with the order_number field in the
   *   shopping_mall_orders table.
   * @param body Return request details submitted by customer
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderNumber")
    orderNumber: string,
    @TypedBody()
    body: IShoppingMallOrderReturn.ICreate,
  ): Promise<IShoppingMallOrderReturn> {
    try {
      return await postShoppingMallCustomerOrdersOrderNumberReturns({
        customer,
        orderNumber,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve the current return request status and details for a specific
   * order. This operation fetches all return records associated with the given
   * order number and provides comprehensive information about each return
   * request, including its current status, reason, refund amount, and
   * processing progress.
   *
   * The operation returns return data for all return requests issued against
   * the specified order, supporting scenarios where multiple products may be
   * returned in separate requests. Returns are sorted chronologically with the
   * most recent first. Only returns with statuses 'requested', 'approved',
   * 'awaiting_return', 'received', or 'refunded' will be included in the
   * response; denied or completed returns may be excluded based on business
   * policy.
   *
   * This endpoint supports an authenticated user viewing their own return
   * requests. Admins can view return requests for any order. The response
   * includes full return details but excludes sensitive administrative notes
   * that may be in the raw system logs.
   *
   * Security: Users can only access return information for orders they have
   * placed. Administrators can view return information for all orders. The
   * system performs strict ownership validation before returning any data.
   *
   * Implementation note: This operation retrieves data from the
   * shopping_mall_order_returns table, joining with all related information
   * such as the original order details and customer information when
   * appropriate. The operation returns a complete Return entity for each return
   * record, including timestamps, refund amounts, and status history.
   *
   * Related Operations: POST /orders/{orderNumber}/returns (to create a new
   * return request), PUT /orders/{orderNumber}/returns (to update return
   * request)
   *
   * @param connection
   * @param orderNumber Unique order identifier in format ORD-YYYYMMDD-NNNNN.
   *   This must match exactly with the order_number field in the
   *   shopping_mall_orders table.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedParam("orderNumber")
    orderNumber: string,
  ): Promise<IPageIShoppingMallOrderReturn> {
    try {
      return await patchShoppingMallCustomerOrdersOrderNumberReturns({
        orderNumber,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
