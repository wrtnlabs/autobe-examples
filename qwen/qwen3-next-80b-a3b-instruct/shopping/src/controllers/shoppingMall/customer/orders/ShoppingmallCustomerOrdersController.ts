import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia from "typia";
import { postShoppingMallCustomerOrders } from "../../../../providers/postShoppingMallCustomerOrders";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { putShoppingMallCustomerOrdersOrderNumber } from "../../../../providers/putShoppingMallCustomerOrdersOrderNumber";

import { IShoppingMallOrder } from "../../../../api/structures/IShoppingMallOrder";

@Controller("/shoppingMall/customer/orders")
export class ShoppingmallCustomerOrdersController {
  /**
   * Create a new order in the shoppingMall system. This operation allows
   * customers to initiate a purchase transaction by creating a draft order that
   * can be completed through payment and fulfillment. The order creates a
   * record in the shopping_mall_orders table, with an automatically generated
   * unique order_number in the format ORD-YYYYMMDD-NNNNN. The order contains
   * initial information from the customer's cart, including subtotal, tax
   * calculation, and selected shipping method if available.
   *
   * Security: Only authenticated customers can create orders. The
   * shopping_mall_customer_id is automatically populated from the JWT
   * authentication token. The system validates that the customer has items in
   * their cart and that the cart items reference valid, published products.
   * Rate limiting applies to prevent automated bulk order creation.
   *
   * This operation triggers automatic inventory reservations for items in the
   * cart. Once payment is completed, the order status transitions from 'draft'
   * to 'pending_payment', and inventory is officially assigned to the order.
   *
   * Related operations: PUT /orders/{orderNumber} (update order), GET
   * /orders/{orderNumber} (retrieve order), PATCH /orders (search orders).
   *
   * @param connection
   * @param body Order creation data with cart items and shipping preferences.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallOrder.ICreate,
  ): Promise<IShoppingMallOrder> {
    try {
      return await postShoppingMallCustomerOrders({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing order using its unique order_number identifier. This
   * operation allows customers to modify specific aspects of their order before
   * payment processing is completed, such as changing the shipping address,
   * selecting a different payment method, adding gift messages, or adjusting
   * item quantities within cart limits.
   *
   * The order must be in 'draft', 'pending_payment', or 'confirmed' status to
   * allow updates. Once payment is processed, the order becomes immutable. The
   * operation validates that the updating customer owns the order by checking
   * the JWT token against shopping_mall_customer_id.
   *
   * When updating, only specified fields are modified in a PATCH-like behavior.
   * Items cannot be added unless they are already in the cart, and existing
   * items cannot have their quantities increased beyond available inventory.
   *
   * Valid updates include: shipping_address, payment_method_id, notes, and cart
   * item quantities (within inventory limits). The system recalculates
   * tax_amount, shipping_fee, and total_amount automatically based on changes.
   *
   * This operation corresponds to the shopping_mall_orders table and validates
   * that the order_number reference points to an existing, non-archived order.
   *
   * Related operations: POST /orders (create order), GET /orders/{orderNumber}
   * (retrieve order), PATCH /orders (search orders).
   *
   * @param connection
   * @param orderNumber Unique order identifier in format ORD-YYYYMMDD-NNNNN.
   *   This is the system-generated order number, not the UUID id.
   * @param body Partial update fields for the order. Only fields that can be
   *   modified before payment processing can be included.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":orderNumber")
  public async update(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderNumber")
    orderNumber: string,
    @TypedBody()
    body: IShoppingMallOrder.IUpdate,
  ): Promise<IShoppingMallOrder> {
    try {
      return await putShoppingMallCustomerOrdersOrderNumber({
        customer,
        orderNumber,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
