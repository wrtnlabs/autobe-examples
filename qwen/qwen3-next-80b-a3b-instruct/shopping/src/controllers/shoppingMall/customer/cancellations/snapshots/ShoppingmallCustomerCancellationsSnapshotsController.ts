import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IPageIShoppingMallCancellationRequestSnapshot } from "../../../../../api/structures/IPageIShoppingMallCancellationRequestSnapshot";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { getShoppingMallCustomerCancellationsCancellationRequestIdSnapshots } from "../../../../../providers/getShoppingMallCustomerCancellationsCancellationRequestIdSnapshots";

@Controller(
  "/shoppingMall/customer/cancellations/:cancellationRequestId/snapshots",
)
export class ShoppingmallCustomerCancellationsSnapshotsController {
  /**
   * Retrieve all historical snapshots of a specific cancellation request.
   *
   * This endpoint provides a complete audit trail of all state changes for a cancellation request, including when the request was created, when it was approved or rejected by the seller, and the corresponding reasons provided by either party. Each snapshot is an immutable record capturing the full state of the cancellation request at a point in time.
   *
   * Only the customer who created the request, the seller whose product was involved, and system administrators have access to these snapshots. No other actors may view them. The data is served for audit, dispute resolution, and compliance purposes — and no modifications to snapshots are allowed.
   *
   * The snapshot records include the original request reason, timestamps, response status and reason, and the actor who initiated each change. This ensures full transparency in the cancellation process.
   *
   * This endpoint must be called after obtaining the cancellation request ID from the /cancellation-requests endpoints. It is essential for customer support workflows and merchant dispute escalation procedures.
   *
   * @param connection
   * @param cancellationRequestId Unique identifier of the cancellation request for which to retrieve snapshot history.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query shopping_mall_cancellation_request_snapshots table ordered by created_at ascending.
   * Filter by request_id = {cancellationRequestId}.
   * Return all snapshot records including: id, status, reason, response_reason, response_at, response_by, created_at, updated_at, request_id.
   * No joins or secondary lookups needed — snapshots contain all required state data.
   * Apply pagination with cursor-based offset and limit.
   * Return highest version (latest) last for chronological display.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async search(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("cancellationRequestId")
    cancellationRequestId: string,
  ): Promise<IPageIShoppingMallCancellationRequestSnapshot.ISummary> {
    try {
      return await getShoppingMallCustomerCancellationsCancellationRequestIdSnapshots(
        {
          customer,
          cancellationRequestId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
