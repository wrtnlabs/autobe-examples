  /**
   * Update an existing shopping cart with new items, quantities, or
   * configuration settings. This operation modifies the shopping_mall_carts
   * table in the database schema and allows customers to update cart contents
   * including item quantities, add new products, or adjust cart metadata such
   * as delivery preferences.
   *
   * The operation accepts a request body containing updated cart information
   * identified by the cartId path parameter. The cartId must reference an
   * existing cart owned by the authenticated user. The system validates that
   * all product variants referenced in the request are available for sale and
   * that quantities do not exceed available inventory.
   *
   * This is a full update operation where the entire cart state is replaced
   * with the provided data. The operation ensures that all cart items maintain
   * referential integrity with product variants in the
   * shopping_mall_product_variants table and that pricing reflects current
   * market rates at the time of update.
   *
   * Security: Only authenticated customers can update carts they own. The cart
   * owner's identity is verified through the authentication token and matched
   * against the cart's customer_id field in the database schema. Unauthorized
   * access attempts are logged and blocked.
   *
   * All cart item quantities are validated against current inventory levels in
   * shopping_mall_product_variant_inventory. If any variant is out of stock or
   * insufficient in quantity, the operation fails with a specific HTTP 409
   * conflict status. The system does not allow negative quantities or
   * zero-quantity items to be persisted in the cart.
   *
   * This operation may trigger real-time inventory adjustments in the
   * shopping_mall_product_variant_inventory table, where inventory counts are
   * temporarily reserved based on the updated cart quantities. These
   * reservations are released if the cart is later abandoned or the order isn't
   * completed.
   *
   * Important: This operation does not create new carts. New cart creation
   * requires POST /carts. This PUT operation only updates existing carts
   * identified by their cartId.
   *
   * @param connection
   * @param cartId Unique identifier of the cart to be updated. This UUID must
   *   reference a cart that exists in the shopping_mall_carts table and belongs
   *   to the authenticated customer.
   * @param body Complete updated cart state with new items, quantities, and
   *   customer preferences. All existing cart items are replaced with those
   *   provided in this payload.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
