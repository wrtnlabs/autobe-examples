import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallCustomerCarts } from "../../../../providers/postShoppingMallCustomerCarts";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { patchShoppingMallCustomerCarts } from "../../../../providers/patchShoppingMallCustomerCarts";
import { getShoppingMallCustomerCartsCartId } from "../../../../providers/getShoppingMallCustomerCartsCartId";
import { putShoppingMallCustomerCartsCartId } from "../../../../providers/putShoppingMallCustomerCartsCartId";
import { deleteShoppingMallCustomerCartsCartId } from "../../../../providers/deleteShoppingMallCustomerCartsCartId";

import { IShoppingMallCart } from "../../../../api/structures/IShoppingMallCart";
import { IPageIShoppingMallCart } from "../../../../api/structures/IPageIShoppingMallCart";

@Controller("/shoppingMall/customer/carts")
export class ShoppingmallCustomerCartsController {
  /**
   * Create a new shopping cart for a customer.
   *
   * This operation allows authenticated customers to create a new shopping cart
   * that serves as a temporary workspace for selecting products for purchase.
   * Each cart is uniquely associated with a specific customer and has a 24-hour
   * expiration period for logged-in users (7 days for anonymous users). The
   * cart begins in 'active' status and can contain multiple cart items that
   * represent product selections.
   *
   * The cart creation process automatically assigns a unique identifier, sets
   * the creation and update timestamps, and initializes the expiration time
   * based on the user's authentication status. No cart items are added during
   * creation - they must be added separately through the cart items endpoint.
   *
   * This operation is related to shopping_mall_carts table in the Prisma schema
   * and is used as the starting point for the customer purchasing workflow.
   * After creating a cart, customers typically add items using the POST
   * /carts/{cartId}/items endpoint.
   *
   * Security: Only authenticated users can create carts. The customer_id is
   * automatically derived from the authentication token and cannot be specified
   * in the request body. Anonymous users can create carts but have a longer
   * expiration period for better user experience.
   *
   * Related operations: GET /carts/{cartId} to retrieve cart details, PUT
   * /carts/{cartId} to update cart status or properties, POST
   * /carts/{cartId}/items to add products to the cart.
   *
   * @param connection
   * @param body Creation parameters for a new shopping cart.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallCart.ICreate,
  ): Promise<IShoppingMallCart> {
    try {
      return await postShoppingMallCustomerCarts({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a filtered and paginated list of shopping carts from the system.
   * This operation operates on the shopping_mall_carts table from the Prisma
   * schema and provides advanced search capabilities for finding carts based on
   * customer, status, and expiration criteria.
   *
   * The operation supports comprehensive pagination with configurable page
   * sizes and sorting options. Carts can be sorted by creation date, expiration
   * date, status, or last update in ascending or descending order.
   *
   * Security considerations include rate limiting for search operations and
   * appropriate filtering of cart data based on the requesting user's
   * authorization level. Only users with appropriate permissions can access
   * detailed cart information, while basic cart summaries may be available to
   * authenticated users.
   *
   * This operation integrates with the shopping_mall_carts table as defined in
   * the Prisma schema, incorporating all available cart fields and
   * relationships. The response includes cart summary information optimized for
   * list displays, with options to include additional details based on
   * authorization level.
   *
   * Related operations: Retrieve a specific cart (GET /carts/{cartId}), Create
   * a new cart (POST /carts), Update a cart (PUT /carts/{cartId}), Delete a
   * cart (DELETE /carts/{cartId}).
   *
   * @param connection
   * @param body Search criteria and pagination parameters for cart filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallCart.IRequest,
  ): Promise<IPageIShoppingMallCart.ISummary> {
    try {
      return await patchShoppingMallCustomerCarts({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific shopping cart by its unique
   * identifier.
   *
   * This operation fetches a complete cart record from the shopping_mall_carts
   * table based on the cartId path parameter. The cart is returned with all its
   * associated metadata including creation time, expiration time, and current
   * status.
   *
   * The cart data is linked to the shopping_mall_customer table via
   * shopping_mall_customer_id, ensuring proper ownership validation. Only
   * authenticated customers can access their own carts. Admin users may access
   * any cart for support purposes.
   *
   * The cart item data is not included in this response to maintain
   * performance. To view cart items, use the dedicated /carts/{cartId}/items
   * endpoint.
   *
   * Related operations: List all carts (PATCH /carts), Create a new cart (POST
   * /carts), Update a cart (PUT /carts/{cartId}), Delete a cart (DELETE
   * /carts/{cartId}).
   *
   * @param connection
   * @param cartId Unique identifier of the target shopping cart. This is the
   *   primary key from the shopping_mall_carts table.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":cartId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("cartId")
    cartId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallCart> {
    try {
      return await getShoppingMallCustomerCartsCartId({
        customer,
        cartId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing shopping cart's properties.
   *
   * This operation allows customers to modify the state of their shopping cart
   * after creation. Valid updates include changing the cart's status (for
   * example, from 'active' to 'checked_out' when a customer is ready to
   * checkout), or updating cart-level properties for experience improvements.
   *
   * According to the Prisma schema for shopping_mall_carts, the cart can have
   * status values: active, expired, or checked_out. This endpoint specifically
   * enables transitioning a cart from 'active' to 'checked_out' as part of the
   * checkout process. Other properties like expires_at, created_at, and
   * updated_at are automatically managed by the system and cannot be modified
   * through this API.
   *
   * Security: Only the cart owner (authenticated user) can update their cart.
   * The system validates that the cart_id in the path matches the authenticated
   * user's cart.
   *
   * Important business rule: When a cart's status is changed to 'checked_out',
   * the system automatically initiates the order creation workflow, converting
   * all cart items into order items, reserving inventory, and creating payment
   * transactions.
   *
   * Related operations: POST /carts to create a new cart, POST
   * /carts/{cartId}/items to add products to cart, DELETE /carts/{cartId} to
   * cancel a cart, GET /carts/{cartId} to retrieve cart details.
   *
   * @param connection
   * @param cartId Unique identifier of the cart to update. This must correspond
   *   to a cart owned by the authenticated user.
   * @param body Update parameters for the shopping cart. Currently only
   *   supports status changes.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":cartId")
  public async update(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("cartId")
    cartId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallCart.IUpdate,
  ): Promise<IShoppingMallCart> {
    try {
      return await putShoppingMallCustomerCartsCartId({
        customer,
        cartId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently removes a shopping cart and all its associated items from the
   * system.
   *
   * This operation performs a hard delete of the cart record, removing it
   * entirely from the database. All cart items linked to this cart are also
   * permanently deleted in a cascading operation.
   *
   * This endpoint is intended for user-initiated cart deletion where the
   * customer wishes to completely remove their shopping session. The cart
   * cannot be recovered after deletion. The operation cannot be undone.
   *
   * The cart deletion is immediate and does not follow soft delete patterns.
   * Even carts that were previously marked with a deleted_at timestamp will be
   * permanently removed when this endpoint is invoked.
   *
   * This operation invokes native database cascading deletes through the
   * foreign key relationship between shopping_mall_carts and
   * shopping_mall_cart_items. The associated cart items are automatically
   * removed by the database due to their CASCADE deletion constraint.
   *
   * Authorization: Only the cart owner (authenticated customer) can delete
   * their own cart. The system verifies ownership by comparing the
   * authenticated user ID with the cart's shopping_mall_customer_id.
   *
   * Error scenarios: Returns 404 if cartId does not exist or if the
   * authenticated user does not own this cart. Returns 403 if the user is not
   * authenticated.
   *
   * @param connection
   * @param cartId Unique identifier of the cart to delete. This is the primary
   *   key (UUID) from the shopping_mall_carts table.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":cartId")
  public async erase(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("cartId")
    cartId: string,
  ): Promise<void> {
    try {
      return await deleteShoppingMallCustomerCartsCartId({
        customer,
        cartId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
