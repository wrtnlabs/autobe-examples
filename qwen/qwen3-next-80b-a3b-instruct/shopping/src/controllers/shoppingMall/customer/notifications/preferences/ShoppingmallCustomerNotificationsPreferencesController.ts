import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallCustomerNotificationsPreferences } from "../../../../../providers/postShoppingMallCustomerNotificationsPreferences";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { patchShoppingMallCustomerNotificationsPreferences } from "../../../../../providers/patchShoppingMallCustomerNotificationsPreferences";
import { getShoppingMallCustomerNotificationsPreferencesPreferenceId } from "../../../../../providers/getShoppingMallCustomerNotificationsPreferencesPreferenceId";
import { putShoppingMallCustomerNotificationsPreferencesPreferenceId } from "../../../../../providers/putShoppingMallCustomerNotificationsPreferencesPreferenceId";
import { deleteShoppingMallCustomerNotificationsPreferencesPreferenceId } from "../../../../../providers/deleteShoppingMallCustomerNotificationsPreferencesPreferenceId";

import { IShoppingMallNotificationPreference } from "../../../../../api/structures/IShoppingMallNotificationPreference";
import { IPageIShoppingMallNotificationPreference } from "../../../../../api/structures/IPageIShoppingMallNotificationPreference";

@Controller("/shoppingMall/customer/notifications/preferences")
export class ShoppingmallCustomerNotificationsPreferencesController {
  /**
   * Create a new notification preference configuration for an authenticated
   * user actor. This operation allows customers, sellers, or admins to define
   * their preferred notification delivery methods for specific notification
   * types. Each preference is tied to the authenticated actor's identity and a
   * specific notification type, ensuring personalized communication controls.
   *
   * The operation validates that the notification_type field matches one of the
   * system-defined notification template types, ensuring consistency across the
   * platform. The preference is created with default values based on system
   * defaults: email_enabled and in_app_enabled defaults to true for critical
   * notifications, while push_enabled is set to null to inherit the system
   * default.
   *
   * The actor's identity is automatically resolved from the JWT authentication
   * token, making this operation actor-specific without requiring explicit
   * actor_id in the request body. The operation uses the
   * shopping_mall_notification_preferences table to store preferences, storing
   * values for email_enabled, in_app_enabled, and push_enabled in a way that
   * allows optional override of system defaults while preserving the ability to
   * revert to defaults by setting send_push to null.
   *
   * User experience considerations include immediate feedback on preference
   * saving and clear indicators of which notifications are currently enabled or
   * disabled. The system will automatically expose all available
   * notification_type options through a read-only endpoint for user reference,
   * with predefined marketing and system alerts determined by platform policy.
   *
   * This operation is the foundational mechanism for user control over
   * communication channels. Related operations include retrieving all
   * preferences (GET /notifications/preferences), retrieving a specific
   * preference (GET /notifications/preferences/{preferenceId}), and updating
   * preferences (PUT /notifications/preferences/{preferenceId}).
   *
   * @param connection
   * @param body Configuration for a new notification preference entry.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallNotificationPreference.ICreate,
  ): Promise<IShoppingMallNotificationPreference> {
    try {
      return await postShoppingMallCustomerNotificationsPreferences({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a paginated list of notification preferences for the authenticated
   * user, with advanced filtering, sorting, and search capabilities.
   *
   * This operation operates on the shopping_mall_notification_preferences table
   * and allows users to search their own notification preferences by
   * notification_type, email_enabled state, or in_app_enabled status. The
   * operation supports full pagination (page, pageSize), sorting by created_at
   * or updated_at in ascending or descending order, and text search across
   * notification_type field.
   *
   * Each preference is associated with an actor_id that must match the
   * authenticated user's ID. The operation enforces strict ownership
   * verification - users can only view their own preferences. System-wide
   * notification types are defined in the shopping_mall_notification_templates
   * table.
   *
   * Filters can be applied to return only email-enabled preferences, only
   * in-app enabled preferences, or any combination thereof. Users have the
   * ability to override system default behavior by configuring their personal
   * preferences for each notification type.
   *
   * This operation is typically triggered when a user navigates to the
   * notification settings panel in the application.
   *
   * Related operations: GET
   * /shoppingMall/customer/notifications/preferences/{notification_type} to
   * retrieve an individual preference by type.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering and
   *   sorting notification preferences.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallNotificationPreference.IRequest,
  ): Promise<IPageIShoppingMallNotificationPreference> {
    try {
      return await patchShoppingMallCustomerNotificationsPreferences({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single notification preference record by its unique identifier.
   *
   * This operation retrieves a specific notification preference from the
   * shopping_mall_notification_preferences table. The preferenceId parameter
   * identifies a unique preference record, which must be owned by the
   * authenticated user. Access is restricted to the user who owns the
   * preference, enforced by comparing the preference's actor_id with the
   * authenticated user's identity.
   *
   * The operation returns all fields of the notification preference including
   * email_enabled, in_app_enabled, push_enabled, notification_type, and
   * timestamps. The notification_type field references a predefined system
   * notification type from shopping_mall_notification_templates.
   *
   * If the requested preferenceId does not exist, or if it exists but belongs
   * to a different user, the operation returns a 404 Not Found response. This
   * operation is typically used when a user displays detailed information about
   * a single notification preference or when editing their notification
   * settings.
   *
   * Related operations: PATCH /notifications/preferences to search multiple
   * preferences, PATCH /notifications/preferences/{preferenceId} to update a
   * preference.
   *
   * @param connection
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":preferenceId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("preferenceId")
    preferenceId: string,
  ): Promise<IShoppingMallNotificationPreference> {
    try {
      return await getShoppingMallCustomerNotificationsPreferencesPreferenceId({
        customer,
        preferenceId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing notification preference configuration for an
   * authenticated user actor. This operation allows users to modify the
   * delivery preferences for a specific notification type that they have
   * previously configured.
   *
   * The preference is identified by preferenceId, which is a unique identifier
   * generated at creation time. The actor's identity is automatically resolved
   * from the JWT authentication token, and the operation performs ownership
   * validation to ensure the authenticated user owns the preference being
   * updated. Only the fields specified in the request body are updated;
   * unspecified fields retain their existing values.
   *
   * The operation validates that the notification_type field matches one of the
   * system-defined notification template types and enforces proper boolean
   * values for email_enabled, in_app_enabled, and push_enabled fields (true,
   * false, or null for push_enabled to inherit system defaults). This prevents
   * invalid state transitions that could disrupt the notification system.
   *
   * When push_enabled is set to null, the system reverts to the global default
   * setting for that notification type, allowing users to easily reset to
   * system defaults without having to remember or query what those defaults
   * are. This design ensures that preferences are always explicitly controlled
   * but with sensible fallback behaviour.
   *
   * The operation blesses the most recent version of the preference when
   * updates are made, ensuring data consistency. The updated preference object
   * is returned as a complete representation of the current state after the
   * update.
   *
   * Related operations include creating a preference (POST
   * /notifications/preferences), retrieving all preferences (GET
   * /notifications/preferences), and retrieving a specific preference (GET
   * /notifications/preferences/{preferenceId}).
   *
   * @param connection
   * @param preferenceId Unique identifier of the notification preference to
   *   update. This is a system-generated UUID that uniquely identifies each
   *   user's preference record.
   * @param body Updated fields for the notification preference. Only fields
   *   included in the request will be modified.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":preferenceId")
  public async update(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("preferenceId")
    preferenceId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallNotificationPreference.IUpdate,
  ): Promise<IShoppingMallNotificationPreference> {
    try {
      return await putShoppingMallCustomerNotificationsPreferencesPreferenceId({
        customer,
        preferenceId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently deletes a user's notification preference record from the
   * system.
   *
   * This operation removes the specified notification preference entry
   * identified by preferenceId from the shopping_mall_notification_preferences
   * table. The deletion is permanent and cannot be undone. This action applies
   * only to preferences owned by the authenticated user and serves as the final
   * step in the notification preference lifecycle.
   *
   * Implementation notes: This executes a hard delete on the
   * shopping_mall_notification_preferences table. The deleted_at field is not
   * used for this operation - records are completely removed from the database.
   * This is done because notification preferences are considered
   * user-configurable settings that can be recreated if needed, rather than
   * audit records that must be preserved. The operation is only available to
   * the owner of the preference (the actor_id matching the authenticated user).
   * After successful deletion, the system will revert to the system default
   * notification setting for that preference type.
   *
   * Related operations: GET /notifications/preferences (list preferences), PUT
   * /notifications/preferences/{preferenceId} (update preferences).
   *
   * @param connection
   * @param preferenceId Unique identifier of the notification preference to
   *   delete. This must match the id field in the
   *   shopping_mall_notification_preferences table.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":preferenceId")
  public async erase(
    @TypedParam("preferenceId")
    preferenceId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallCustomerNotificationsPreferencesPreferenceId(
        {
          preferenceId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
