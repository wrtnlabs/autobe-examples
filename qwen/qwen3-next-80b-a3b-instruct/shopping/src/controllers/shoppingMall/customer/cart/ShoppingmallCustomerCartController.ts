import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallCart } from "../../../../api/structures/IShoppingMallCart";
import { IShoppingMallCartItem } from "../../../../api/structures/IShoppingMallCartItem";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { postShoppingMallCustomerCart } from "../../../../providers/postShoppingMallCustomerCart";

@Controller("/shoppingMall/customer/cart")
export class ShoppingmallCustomerCartController {
  /**
   * Add a product variant to the customer's shopping cart.
   *
   * This operation allows customers to store items they intend to purchase later. When a variant is added, the system captures and preserves its exact price, SKU, and product metadata at the moment of addition, ensuring that price changes or product updates after this point do not affect the cart. This ensures price stability and transparency during the shopping session.
   *
   * The system handles both new additions and quantity updates. If the customer adds a variant that is already in their cart, the system merges the quantities rather than creating a duplicate. All cart modifications are immediately validated against current inventory levels and seller status.
   *
   * This endpoint is exclusive to authenticated customers. The cart serves as a temporary container and does not constitute a purchase—inventory is not deducted until checkout. During checkout, cart items are converted into immutable order items.
   *
   * To add an item, the client must provide the variant ID and desired quantity. The quantity is limited to 50 units per item. If the requested quantity exceeds available stock, the request fails with an appropriate error message. Multiple items can be added sequentially by calling this endpoint for each variant.
   *
   * Related operations:
   * - GET /cart — view current cart contents
   * - PUT /cart/{cart_item_id} — update quantity of existing cart item
   * - DELETE /cart/{cart_item_id} — remove an item from cart
   * - POST /checkout — convert cart to order and deduct inventory
   *
   * @param connection
   * @param body The variant ID and quantity to be added to the cart.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Create a new cart item or update existing (merge) if variant already exists in cart.
   * - Validate customer is authenticated (JWT required)
   * - Validate variant exists and is active (not deleted or suspended)
   * - Validate variant has available stock > 0
   * - Validate seller account is not suspended
   * - Validate quantity is ≥1 and ≤50
   * - If cart item with same variant_id exists for customer:
   *   - Update quantity: existing_quantity + requested_quantity
   *   - Validate new total ≤ available stock
   * - Else:
   *   - Fetch variant and seller details
   *   - Create cart item with:
   *     - customer_id
   *     - variant_id
   *     - product_snapshot_id
   *     - variant_snapshot_id
   *     - seller_id
   *     - quantity (as requested)
   *     - unit_price (from variant_snapshot)
   *     - item_total (quantity × unit_price)
   *     - created_at
   *     - updated_at
   *     - deleted_at: null
   * - Return created/updated cart item with full details
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallCart.ICreate,
  ): Promise<IShoppingMallCartItem> {
    try {
      return await postShoppingMallCustomerCart({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
