import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallAdminPasswordReset } from "../../../../../api/structures/IShoppingMallAdminPasswordReset";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { postShoppingMallCustomerAdminsRequests } from "../../../../../providers/postShoppingMallCustomerAdminsRequests";

@Controller("/shoppingMall/customer/admins/requests")
export class ShoppingmallCustomerAdminsRequestsController {
  /**
   * Submit a formal application to become an administrator of the shopping mall platform.
   *
   * This operation allows any authenticated user to initiate the process of becoming an administrator by submitting a formal application. The application requires a reason explaining why the user wishes to obtain administrator privileges, which will be reviewed by super administrators. This process ensures that administrator privileges are granted only to users with legitimate needs and proper justification, maintaining platform security and governance.
   *
   * When a user submits an application, it enters a pending approval state visible to super administrators in the admin dashboard. Super administrators can then review the requested reason, verify the applicant's account history, and either approve or reject the application. Approved applicants gain administrator privileges with permissions scoped according to platform policy, while rejected applicants receive feedback on their submission.
   *
   * This is a critical access control mechanism that prevents unauthorized privilege escalation while allowing qualified users to request elevated permissions. The operation is designed with a strong audit trail, and applications are permanently logged in the system for compliance and security review purposes. All administrator applications require explicit review and approval by super administrators.
   *
   * Important note: This operation does not directly grant administrator roles - it only creates an application record that requires human review. The application cannot be processed or changed by the original submitter after submission.
   *
   * @param connection
   * @param body The application request payload containing the reason for seeking administrator privileges.
   * @x-autobe-specification Create a new admin request record in the shopping_mall_admin_requests table with status set to 'pending' and current timestamp.
   * Store the authenticated user ID from JWT token as the requester_id.
   * Store the submitted reason string.
   * Generate a unique adminRequestId using UUID v4.
   * Return the created object with adminRequestId, status, reason, requestedAt, and userId.
   * Apply rate limiting of 10 requests per hour per user to prevent spam.
   * Send email notification to all super administrators that a new admin application has been submitted.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallAdminPasswordReset.ICreate,
  ): Promise<IShoppingMallAdminPasswordReset> {
    try {
      return await postShoppingMallCustomerAdminsRequests({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
