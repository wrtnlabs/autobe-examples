import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallCustomer } from "../../../../api/structures/IShoppingMallCustomer";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { putShoppingMallCustomerProfile } from "../../../../providers/putShoppingMallCustomerProfile";

@Controller("/shoppingMall/customer/profile")
export class ShoppingmallCustomerProfileController {
  /**
   * Update customer profile information excluding sensitive authentication fields.
   *
   * This operation allows a registered customer to modify their display name and phone number in their profile. The update is performed atomically against the customer account record identified by the authenticated session. For security and compliance, the customer's email address and password hash are protected from modification via this endpoint. The operation returns the updated customer entity to confirm state changes.
   *
   * The profile update respects application-layer audit logging: all updates are recorded with timestamps and actor IDs for lifetime retention. Unlike product and seller changes, profile modifications are not captured in immutable database snapshots because they are not part of the transactional narrative of purchases or sales.
   *
   * This endpoint assumes the customer is authenticated. Any request from an unauthenticated user or a different actor (seller, admin) will return a 401 Authorization Required error. Operations conducted under a spoiled or expired JWT token will be rejected with 401. Username, email, and password are maintained as protected identifiers and cannot be changed through this endpoint - these require separate, elevated workflows with additional validation steps.
   *
   * Relationship to Other APIs:
   * - This API changes customer profile properties referenced by order histories, reviews, and wishlist entries.
   * - It does NOT affect orderItem snapshots - those preserve the profile state as of purchase time.
   * - Does NOT trigger inventory updates, cart changes, or shipping processes.
   * - Does NOT affect seller or admin profile behavior - this is exclusively a customer-centric operation.
   *
   * @param connection
   * @param body Profile update fields for display_name and phone_number. Only these two fields are permitted. Other fields will cause validation failure.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Update customer profile using data provided in request body. Retrieve customer from authenticated session using JWT token. Validate that customer exists and is not deleted. Ensure only allowed fields (display_name, phone_number) are present in request. Validate phone_number conforms to E.164 format. Update customer record with new values, preserving email and password_hash. Record update timestamp. Return updated customer entity in response. If any protected field (email, password_hash, id) is provided in request body, return 400 Bad Request.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallCustomer.IUpdate,
  ): Promise<IShoppingMallCustomer> {
    try {
      return await putShoppingMallCustomerProfile({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
