import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallAdmin } from "../../../../api/structures/IShoppingMallAdmin";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { getShoppingMallCustomerDashboard } from "../../../../providers/getShoppingMallCustomerDashboard";

@Controller("/shoppingMall/customer/dashboard")
export class ShoppingmallCustomerDashboardController {
  /**
   * Retrieve a consolidated operational summary for sellers or administrators based on authenticated identity.
   *
   * For sellers, this dashboard provides real-time metrics including: total active products listed, total order items sold (all statuses), pending cancellation requests, pending refund requests, monthly revenue generated from approved orders, average customer rating across products, and total customer reviews.
   *
   * For administrators, the same endpoint returns platform-wide totals: total registered customers, approved sellers, listed products, created orders, pending seller approvals, and aggregated pending cancellation/refund requests across all sellers.
   *
   * This endpoint is optimized for fast, non-interactive dashboard loading—it does not support filtering, pagination, or search. All metrics are computed through aggregated database queries for performance, and sensitive transaction details are intentionally omitted to protect privacy and reduce surface area for exploitation.
   *
   * Authenticated session determines actor scope (seller or admin) and filters data accordingly. No authentication header or token is required to be specified in request body since authentication is resolved at the service layer.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Aggregate metrics from multiple entities:
   * - Total products: count of shopping_mall_products where seller_id = current_user_id and is_active = true
   * - Total order items: count of shopping_mall_order_items where seller_id = current_user_id
   * - Pending cancellation requests: count of shopping_mall_cancellation_requests where seller_id = current_user_id and status = 'pending'
   * - Pending refund requests: count of shopping_mall_refund_requests where seller_id = current_user_id and status = 'pending'
   * - Monthly revenue: sum of order_item.quantity * order_item.variant_price for orders created in last 30 days where seller_id = current_user_id
   * - Customer rating average: average of shopping_mall_reviews.rating for products owned by current seller
   * - Total customer reviews: count of shopping_mall_reviews where product_id in (products owned by current seller) and is_deleted = false
   *
   * For admin: return platform-wide totals (all sellers, all customers) instead of current_user_id-filtered metrics.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async summary(
    @CustomerAuth()
    customer: CustomerPayload,
  ): Promise<IShoppingMallAdmin.ISummary> {
    try {
      return await getShoppingMallCustomerDashboard({
        customer,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
