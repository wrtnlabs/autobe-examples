import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IShoppingMallReviewVote } from "../../../../../api/structures/IShoppingMallReviewVote";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { getShoppingMallCustomerReviewsReviewIdVotesVoteId } from "../../../../../providers/getShoppingMallCustomerReviewsReviewIdVotesVoteId";
import { patchShoppingMallCustomerReviewsReviewIdVotes } from "../../../../../providers/patchShoppingMallCustomerReviewsReviewIdVotes";
import { postShoppingMallCustomerReviewsReviewIdVotes } from "../../../../../providers/postShoppingMallCustomerReviewsReviewIdVotes";

@Controller("/shoppingMall/customer/reviews/:reviewId/votes")
export class ShoppingmallCustomerReviewsVotesController {
  /**
   * Submit a helpful or not helpful vote on a specific review.
   *
   * This endpoint allows authenticated customers to vote on the usefulness of review content to help surface valuable feedback across the marketplace. Each customer may cast exactly one vote per review, as enforced by the unique constraint on (review_id, customer_id).
   *
   * The vote type must be explicitly specified as either 'helpful' or 'not_helpful'. The customer's identity is derived from the authenticated session; it is not included in the request body.
   *
   * Voting is not subject to time limits, and the vote cannot be changed once submitted — customers must submit a new vote if their assessment changes (which will be recorded as a separate record).
   *
   * Note: This endpoint is only accessible to authenticated customers.
   *
   * @param connection
   * @param reviewId The UUID of the review being voted on. Must reference an existing shopping_mall_reviews record that is not logically deleted.
   * @param body The type of vote to cast: 'helpful' or 'not_helpful'.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Insert a new shopping_mall_review_votes record with provided shopping_mall_review_id, shopping_mall_customer_id, and vote_type. Validate that:
   * 1. reviewId references existing shopping_mall_reviews.id with deleted_at IS NULL
   * 2. customer_id from authentication context matches the provided shopping_mall_customer_id
   * 3. Vote does not already exist for this review-customer pair (enforces @@unique constraint)
   * 4. vote_type is either 'helpful' or 'not_helpful'
   * 5. Return generated record with id, created_at, updated_at
   * Use atomic transaction to prevent race conditions during creation.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallReviewVote.ICreate,
  ): Promise<IShoppingMallReviewVote> {
    try {
      return await postShoppingMallCustomerReviewsReviewIdVotes({
        customer,
        reviewId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Submit or update a customer's vote on a specific review.
   *
   * This endpoint allows an authenticated customer to cast a vote indicating whether they found a review helpful or not. Each customer can vote only once per review, as enforced by a unique constraint on the combination of review_id and customer_id. If a vote exists for this customer-review pair, it will be updated with the new value. Otherwise, a new vote record will be created. The vote type must be either 'helpful' or 'not_helpful'.
   *
   * The operation is idempotent. The review must exist and be active (not marked as permanently deleted). If the review does not exist or has been permanently deleted, the system returns '404 Not Found'. For any authorization failure (including unauthenticated requests), the system returns '403 Forbidden'.
   *
   * This operation has no dependencies on other APIs and relies on the review having been previously created through a valid order delivery process.
   *
   * @param connection
   * @param reviewId The unique identifier of the review to vote on. Must correspond to an existing review record.
   * @param body The type of vote to submit: 'helpful' or 'not_helpful'. Must be one of these two values.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Validate that the requesting customer is authenticated and has the associated review as part of their order history.
   * Find the review by reviewId and verify it is not soft-deleted (deleted_at IS NULL).
   * Verify the review's shopping_mall_order_item_id links to a completed order item belonging to the authenticated customer.
   * If an existing vote by this customer for this review exists, overwrite its vote_type field with the new value.
   * If no vote exists, create a new record in shopping_mall_review_votes with the customer_id, review_id, vote_type, and timestamps.
   * Use a transaction to ensure atomicity.
   * Return HTTP 204 No Content on success.
   * Return 403 if customer is not authorized to vote on this review.
   * Return 404 if review does not exist or is deleted.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async vote(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("reviewId")
    reviewId: string,
    @TypedBody()
    body: IShoppingMallReviewVote.IRequest,
  ): Promise<void> {
    try {
      return await patchShoppingMallCustomerReviewsReviewIdVotes({
        customer,
        reviewId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific customer vote on a product review.
   *
   * This operation returns the exact type of vote (helpful or not_helpful) cast by a customer on a particular product review. Each vote is uniquely identified by both the review ID and the vote ID, ensuring precise access to individual feedback interactions.
   *
   * The vote record includes the vote type and timestamps indicating when it was created and last updated. Since votes are immutable once cast, the updated_at field will typically equal created_at. This endpoint provides direct access to community feedback data, enabling review quality assessment and filtering of helpful content.
   *
   * This operation is part of the review ecosystem where customers can rate the usefulness of other customers' reviews. The data returned here helps surface high-quality reviews and improves the review experience by highlighting valuable feedback from the community.
   *
   * @param connection
   * @param reviewId The unique identifier of the review being voted on. Must correspond to a valid shopping_mall_reviews record.
   * @param voteId The unique identifier of the specific vote record. Must correspond to a valid shopping_mall_review_votes record.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query shopping_mall_review_votes table by id field to retrieve single vote record.
   * Validate that reviewId corresponds to the record's shopping_mall_review_id.
   * Return vote_type, created_at, and updated_at fields.
   * Return 404 if vote not found or if reviewId does not match the vote's review association.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":voteId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
    @TypedParam("voteId")
    voteId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallReviewVote> {
    try {
      return await getShoppingMallCustomerReviewsReviewIdVotesVoteId({
        customer,
        reviewId,
        voteId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
