import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia from "typia";
import { postShoppingMallCustomerReviewsReviewIdReactions } from "../../../../../providers/postShoppingMallCustomerReviewsReviewIdReactions";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { deleteShoppingMallCustomerReviewsReviewIdReactionsReactionId } from "../../../../../providers/deleteShoppingMallCustomerReviewsReviewIdReactionsReactionId";

import { IShoppingMallReviewReaction } from "../../../../../api/structures/IShoppingMallReviewReaction";

@Controller("/shoppingMall/customer/reviews/:reviewId/reactions")
export class ShoppingmallCustomerReviewsReactionsController {
  /**
   * Create a new reaction (upvote or downvote) to a specific product review.
   * This operation adds an entry to the shopping_mall_review_reactions table,
   * recording a customer's feedback on the helpfulness of a review. Each
   * customer can create only one reaction per review, and the system enforces
   * this uniqueness constraint. The operation validates that the review exists,
   * the user is authenticated, and they have not already voted on this
   * particular review. This creates a record that helps surface the most
   * helpful reviews through community-based quality assessment.
   *
   * Security: Only authenticated customers can create reactions. Users cannot
   * react to reviews they created themselves. This prevents self-promotion and
   * manipulation of review quality metrics.
   *
   * Implementation note: Inserts a new row into shopping_mall_review_reactions
   * with operation_id from JWT token and validation against unique constraint
   * on (shopping_mall_review_id, shopping_mall_customer_id). If a duplicate is
   * attempted, the server returns a 409 Conflict error. Reactions are not
   * subject to moderation and become immediately visible.
   *
   * Related operations: PATCH /reviews/{reviewId}/reactions (to view existing
   * reactions), GET /reviews/{reviewId} (to view the review).
   *
   * @param connection
   * @param reviewId Unique identifier of the target review. This UUID refers to
   *   the shopping_mall_review_id in the shopping_mall_reviews table.
   * @param body The reaction data including type ('upvote' or 'downvote') to
   *   record for this review.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("reviewId")
    reviewId: string,
    @TypedBody()
    body: IShoppingMallReviewReaction.ICreate,
  ): Promise<IShoppingMallReviewReaction> {
    try {
      return await postShoppingMallCustomerReviewsReviewIdReactions({
        customer,
        reviewId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a specific reaction to a product review. This operation permanently
   * removes a user's upvote or downvote reaction from a review. The reaction
   * must belong to the authenticated user and be associated with the specified
   * review ID. This is an idempotent operation - deleting a non-existent
   * reaction will not produce an error. The action is atomic and immediate,
   * with no confirmation step required.
   *
   * Implementation note: This operation deletes from the
   * shopping_mall_review_reactions table, removing the record where
   * shopping_mall_review_id matches the path parameter reviewId and
   * shopping_mall_customer_id matches the authenticated user's ID. The
   * reaction_type ('upvote' or 'downvote') is not validated in the request body
   * since it's part of the record being deleted and irrelevant to the delete
   * operation itself. No request body is required since the unique identifier
   * is provided via path parameters.
   *
   * Security: The system enforces ownership verification - only the user who
   * created the reaction can delete it. The operation rejects any attempt to
   * delete another user's reaction. No administrative override is available as
   * reactions are user-generated subjective feedback and should not be subject
   * to administrative deletion.
   *
   * Related operations: GET /reviews/{reviewId}/reactions to list all reactions
   * to a review, POST /reviews/{reviewId}/reactions to create a new reaction.
   *
   * @param connection
   * @param reviewId Unique identifier of the review to which the reaction
   *   belongs. Must be a valid UUID format.
   * @param reactionId Unique identifier of the specific reaction to be deleted.
   *   Must be a valid UUID format.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":reactionId")
  public async erase(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("reviewId")
    reviewId: string,
    @TypedParam("reactionId")
    reactionId: string,
  ): Promise<void> {
    try {
      return await deleteShoppingMallCustomerReviewsReviewIdReactionsReactionId(
        {
          customer,
          reviewId,
          reactionId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
