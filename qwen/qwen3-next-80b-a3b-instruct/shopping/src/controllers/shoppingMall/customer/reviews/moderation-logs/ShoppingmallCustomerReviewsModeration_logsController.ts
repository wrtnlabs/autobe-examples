import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia from "typia";
import { getShoppingMallCustomerReviewsReviewIdModerationLogs } from "../../../../../providers/getShoppingMallCustomerReviewsReviewIdModerationLogs";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";

import { IPageIShoppingMallReviewModerationLog } from "../../../../../api/structures/IPageIShoppingMallReviewModerationLog";

@Controller("/shoppingMall/customer/reviews/:reviewId/moderation-logs")
export class ShoppingmallCustomerReviewsModeration_logsController {
  /**
   * Retrieve the complete audit history of moderation actions taken on a
   * specific product review. This operation returns an ordered list of all
   * moderation events associated with the specified review, including status
   * changes, moderator actions, and reason codes. The data comes from the
   * shopping_mall_review_moderation_logs table and provides a forensic-level
   * audit trail of all administrative interventions.
   *
   * The results are ordered chronologically from oldest to newest, showing the
   * complete evolution of a review's moderation status from creation through
   * any number of moderation actions. Each log entry includes the status before
   * and after the action, the admin who performed the action, and any
   * explanation provided by the moderator.
   *
   * This operation supports filtering based on the status of the review at the
   * time of each log entry or the ID of the moderator who performed the action.
   * While there is no search filter in the request, users can paginate through
   * the results for reviews with extensive moderation histories.
   *
   * Security: Any authenticated user can view the moderation log for any
   * review. This transparency is intentional to build trust in the moderation
   * system - all moderation decisions are public by design to prevent abuse of
   * moderation power.
   *
   * Implementation note: This operation executes a query on
   * shopping_mall_review_moderation_logs table filtered by
   * shopping_mall_review_id, projecting all fields including previous_status,
   * new_status, action_reason, created_at, and admin details. No pagination
   * parameters are supported in the request body as this is a complete audit
   * history of a single review.
   *
   * Related operations: PATCH /reviews/{reviewId} to change review status
   * (which creates a new moderation log entry), GET /reviews/{reviewId} to view
   * current review status.
   *
   * @param connection
   * @param reviewId Unique identifier of the review whose moderation log is
   *   being requested. Must be a valid UUID format.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("reviewId")
    reviewId: string,
  ): Promise<IPageIShoppingMallReviewModerationLog> {
    try {
      return await getShoppingMallCustomerReviewsReviewIdModerationLogs({
        customer,
        reviewId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
