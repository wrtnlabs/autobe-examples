import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallReview } from "../../../../../api/structures/IShoppingMallReview";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { getShoppingMallCustomerReviewsMetrics } from "../../../../../providers/getShoppingMallCustomerReviewsMetrics";

@Controller("/shoppingMall/customer/reviews/metrics")
export class ShoppingmallCustomerReviewsMetricsController {
  /**
   * Compute and return key review analytics metrics for all products on the platform. This operation aggregates data from the shopping_mall_reviews table to calculate overall review metrics that serve business intelligence needs for product owners and administrators.
   *
   * The operation computes the average rating across all reviews, the total count of reviews, and the distribution of ratings across the 1-5 scale. Since the shopping_mall_reviews table has no delete flags (no status or isDeleted fields), all reviews are included in the analytics calculation regardless of user deletions or administrative actions.
   *
   * Implementation note: This does NOT map to a single database table - instead it executes:
   *
   * SELECT
   * AVG(rating) as averageRating,
   * COUNT(*) as totalCount,
   * SUM(CASE WHEN rating = 1 THEN 1 ELSE 0 END) as rating1Count,
   * SUM(CASE WHEN rating = 2 THEN 1 ELSE 0 END) as rating2Count,
   * SUM(CASE WHEN rating = 3 THEN 1 ELSE 0 END) as rating3Count,
   * SUM(CASE WHEN rating = 4 THEN 1 ELSE 0 END) as rating4Count,
   * SUM(CASE WHEN rating = 5 THEN 1 ELSE 0 END) as rating5Count
   * FROM shopping_mall_reviews
   *
   * This statistical aggregation serves the explicit business need for review analytics as specified in the 13-reviews-and-ratings.md document.
   *
   * Security considerations: This endpoint requires no authentication as the data is public analytics. The operation will include all reviews from the shopping_mall_reviews table since there are no delete fields in the schema to filter by. The operation has been designed to be read-only and will not affect any review records.
   *
   * @param connection
   * @x-autobe-specification Query shopping_mall_reviews table with JOIN to shopping_mall_review_snapshots.
   *
   * Calculate average rating, total count, and rating distribution across 1-5 scale.
   *
   * Use SQL: SELECT AVG(rating) as averageRating, COUNT(*) as totalCount, SUM(CASE WHEN rating = 1 THEN 1 ELSE 0 END) as rating1Count, etc.
   *
   * Exclude reviews where status = 'deleted_by_admin' (admin-deleted) - these remove rating from average.
   *
   * Include reviews where isDeleted = true (user-deleted) - these retain rating in average.
   *
   * Use cached results for 5 minutes with no cache key (global aggregate).
   *
   * Return JSON object with fields: averageRating, totalCount, rating1Count, rating2Count, rating3Count, rating4Count, rating5Count.
   *
   * No authentication required - public analytics endpoint.
   *
   * Return 200 OK with JSON response body.
   *
   * No transactions or write operations involved.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
  ): Promise<IShoppingMallReview> {
    try {
      return await getShoppingMallCustomerReviewsMetrics({
        customer,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
