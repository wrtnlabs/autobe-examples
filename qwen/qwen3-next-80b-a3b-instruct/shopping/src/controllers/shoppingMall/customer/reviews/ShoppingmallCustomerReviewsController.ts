import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallCustomerReviews } from "../../../../providers/postShoppingMallCustomerReviews";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { putShoppingMallCustomerReviewsReviewId } from "../../../../providers/putShoppingMallCustomerReviewsReviewId";
import { deleteShoppingMallCustomerReviewsReviewId } from "../../../../providers/deleteShoppingMallCustomerReviewsReviewId";

import { IShoppingMallReview } from "../../../../api/structures/IShoppingMallReview";

@Controller("/shoppingMall/customer/reviews")
export class ShoppingmallCustomerReviewsController {
  /**
   * Create a new product review on the shoppingMall platform.
   *
   * This operation enables authenticated customers to submit written feedback
   * about a specific product after purchase. Each review includes a title, body
   * text, and a 1-5 star rating that quantifies the customer's satisfaction.
   * The review is initially created in 'pending' status and requires moderation
   * by an admin before becoming publicly visible.
   *
   * The operation validates that the requesting user is an authenticated
   * customer who has purchased the product being reviewed. The relationship
   * between the customer and product is checked against order history in the
   * shopping_mall_orders and shopping_mall_order_items tables. The review body
   * must be at least 10 characters to ensure meaningful feedback.
   *
   * Upon successful creation, the review is stamped with the current timestamp
   * and assigned a unique identifier. The operation returns the complete review
   * record including all metadata, but the status will remain 'pending' until
   * moderated. This design separates the submission process from the visibility
   * control, allowing for quality control and moderation workflows.
   *
   * This endpoint directly corresponds to the shopping_mall_reviews Prisma
   * table and uses all required fields: shopping_mall_product_id,
   * shopping_mall_customer_id, title, body, rating, status, created_at,
   * updated_at.
   *
   * Related operations: GET /reviews/{reviewId} (retrieve individual review),
   * PUT /reviews/{reviewId} (update review), PATCH /reviews (search and filter
   * reviews).
   *
   * @param connection
   * @param body Data required to create a new product review.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallReview.ICreate,
  ): Promise<IShoppingMallReview> {
    try {
      return await postShoppingMallCustomerReviews({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing product review on the shoppingMall platform.
   *
   * This operation allows customers to modify their own previously submitted
   * reviews, provided the review is still in 'pending' or 'published' status
   * and hasn't been permanently deleted. Changes can include updating the
   * title, body content, or rating value.
   *
   * The system enforces strict ownership verification: only the customer who
   * originally created the review can update it. The operation compares the
   * authenticated user's ID with the shopping_mall_customer_id field in the
   * target review to ensure proper authorization. Updates to reviews that have
   * been 'rejected' or 'hidden' are prohibited as these indicate moderation
   * decisions.
   *
   * The update operation persists all changes to the shopping_mall_reviews
   * table, updating the 'updated_at' timestamp while preserving the
   * 'created_at' timestamp. A record of this edit is maintained in the system
   * logs for auditability.
   *
   * 🆕 NEW: When a review is revised, its moderation status is automatically
   * reset to 'pending' to ensure any content changes are re-evaluated by
   * moderators. This prevents bypassing review moderation policies through
   * simple edits.
   *
   * This endpoint links directly to the shopping_mall_reviews Prisma table and
   * uses all relevant fields: title, body, rating, updated_at, and status
   * (reset to 'pending').
   *
   * Related operations: POST /reviews (create review), GET /reviews/{reviewId}
   * (retrieve review), DELETE /reviews/{reviewId} (delete review).
   *
   * @param connection
   * @param reviewId Unique identifier of the review to be updated. This maps to
   *   the 'id' field in the shopping_mall_reviews table.
   * @param body Updated data for the product review, containing fields that can
   *   be modified: title, body, and rating.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":reviewId")
  public async update(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallReview.IUpdate,
  ): Promise<IShoppingMallReview> {
    try {
      return await putShoppingMallCustomerReviewsReviewId({
        customer,
        reviewId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a product review from the shoppingMall platform.
   *
   * This operation performs a hard delete of a review record from the
   * shopping_mall_reviews table. Unlike soft deletion which marks records as
   * deleted with a timestamp, this operation completely removes the review from
   * the database with no possibility of recovery.
   *
   * This deletion is permanent and irreversible. All associated review images
   * in the shopping_mall_review_images table are also automatically deleted
   * through database foreign key cascading when a parent review is deleted.
   *
   * Security: Only the original review creator or an admin moderator can delete
   * a review. The operation verifies the requesting user's identity against the
   * review's shopping_mall_customer_id field or checks for admin privileges.
   *
   * This operation is designed for extreme cases such as user account
   * termination, extensive moderation violations, or legal compliance
   * requirements where complete data erasure is mandated.
   *
   * @param connection
   * @param reviewId Unique identifier of the target review to be deleted. This
   *   is a UUID that corresponds to the primary key in the
   *   shopping_mall_reviews table.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":reviewId")
  public async erase(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallCustomerReviewsReviewId({
        customer,
        reviewId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
