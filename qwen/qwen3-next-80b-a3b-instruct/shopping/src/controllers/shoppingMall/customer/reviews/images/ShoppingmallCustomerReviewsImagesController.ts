import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallCustomerReviewsReviewIdImages } from "../../../../../providers/postShoppingMallCustomerReviewsReviewIdImages";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { patchShoppingMallCustomerReviewsReviewIdImages } from "../../../../../providers/patchShoppingMallCustomerReviewsReviewIdImages";
import { deleteShoppingMallCustomerReviewsReviewIdImagesImageId } from "../../../../../providers/deleteShoppingMallCustomerReviewsReviewIdImagesImageId";

import { IShoppingMallReviewImage } from "../../../../../api/structures/IShoppingMallReviewImage";
import { IShoppingMallReviewImageSet } from "../../../../../api/structures/IShoppingMallReviewImageSet";

@Controller("/shoppingMall/customer/reviews/:reviewId/images")
export class ShoppingmallCustomerReviewsImagesController {
  /**
   * Upload an image to accompany a product review.
   *
   * This operation allows authenticated customers to attach visual evidence to
   * their product reviews. Each review can have multiple images that provide
   * additional context about the product experience, including photos of
   * product quality, usage scenarios, or issues encountered. Images are
   * strictly associated with their parent review and cannot exist
   * independently.
   *
   * Images are uploaded as URIs referencing stored files in a content delivery
   * network. The system generates secure, permanent URLs upon successful
   * upload. Each review image is moderated separately from the review text and
   * may be removed if it violates content policies.
   *
   * After upload, images become visible only after the parent review has been
   * published. If the review is rejected, all associated images are
   * automatically hidden. Admins can view all uploaded images for moderation
   * purposes with full audit trails.
   *
   * Related operations: DELETE /reviews/{reviewId}/images/{imageId} (removes
   * specific image)
   *
   * Implementation note: Image URLs are generated by a secure file upload
   * service and cannot be directly manipulated by clients.
   *
   * @param connection
   * @param reviewId Unique identifier of the parent product review. This is the
   *   review to which the image will be attached. Every image must belong to
   *   exactly one review.
   *
   *                 This references {@link shopping_mall_reviews.id} in the Prisma schema.
   * @param body Image data for upload with secure URI reference.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallReviewImage.ICreate,
  ): Promise<IShoppingMallReviewImage> {
    try {
      return await postShoppingMallCustomerReviewsReviewIdImages({
        customer,
        reviewId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update the associated images for a specific product review on the
   * shoppingMall platform.
   *
   * This operation allows the review creator or an admin moderator to modify
   * the visual evidence associated with a product review. The operation
   * replaces the entire set of review images with the new set provided in the
   * request.
   *
   * All existing review images linked to the review through the
   * shopping_mall_review_images table are deleted and replaced with the new
   * images provided in the request body. This ensures the review maintains a
   * clean, up-to-date set of visual documentation.
   *
   * The images provided must be URLs to images already uploaded to the content
   * delivery network, as the shoppingMall platform doesn't handle direct binary
   * file uploads in API calls. Each image URL must be a valid, permanent URI
   * that remains accessible after the operation completes.
   *
   * The review images are a subsidiary entity (shopping_mall_review_images)
   * that cannot exist independently from their parent review
   * (shopping_mall_reviews). The relationship is strictly one-to-many, where
   * each image belongs to exactly one review.
   *
   * This operation does not support partial updates - the entire set of images
   * for the review must be provided in each request, as this approach ensures
   * consistent visual representation and prevents orphaned or conflicting
   * images in the system.
   *
   * Security: This operation is restricted to the review's original creator
   * (matching shopping_mall_customer_id) or users with admin privileges.
   *
   * @param connection
   * @param reviewId Unique identifier of the target review whose images are
   *   being updated. This UUID must correspond to an existing review in the
   *   shopping_mall_reviews table.
   * @param body Request containing the new set of image URLs to associate with
   *   the review. The existing images for this review will be completely
   *   replaced with this new set.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async update(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallReviewImageSet.IUpdate,
  ): Promise<IShoppingMallReviewImageSet> {
    try {
      return await patchShoppingMallCustomerReviewsReviewIdImages({
        customer,
        reviewId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Remove a specific image from a product review.
   *
   * This operation permits authenticated customers to delete images they
   * previously uploaded to their own reviews. Only the original uploader of an
   * image may delete it, unless an administrator initiates the deletion. When
   * an image is deleted, it is permanently removed from the system with no
   * possibility of recovery.
   *
   * This endpoint cannot be used to delete images from reviews that have been
   * rejected or hidden. In such cases, image deletion is handled automatically
   * by system rules when reviews are moderated.
   *
   * After image deletion, any references to the image are removed from review
   * display, and the system records this action in the audit log. Deleted
   * images cannot be restored.
   *
   * Related operations: POST /reviews/{reviewId}/images (upload new image)
   *
   * Implementation note: Deletion is handled by a secure content management
   * service that permanently erases the file from storage. The associated
   * database record is marked as deleted with metadata. This is a hard delete
   * operation with no soft delete functionality.
   *
   * @param connection
   * @param reviewId Unique identifier of the parent product review. This
   *   identifies which review the target image belongs to.
   *
   *                 This references {@link shopping_mall_reviews.id} in the Prisma schema.
   * @param imageId Unique identifier of the specific review image to be
   *   deleted.
   *
   *                This references {@link shopping_mall_review_images.id} in the Prisma schema.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":imageId")
  public async erase(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
    @TypedParam("imageId")
    imageId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteShoppingMallCustomerReviewsReviewIdImagesImageId({
        customer,
        reviewId,
        imageId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
