import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallAdminSession } from "../../../../api/structures/IPageIShoppingMallAdminSession";
import { IShoppingMallAdminSession } from "../../../../api/structures/IShoppingMallAdminSession";
import { IShoppingMallCustomerSession } from "../../../../api/structures/IShoppingMallCustomerSession";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { deleteShoppingMallCustomerSessionsSessionId } from "../../../../providers/deleteShoppingMallCustomerSessionsSessionId";
import { getShoppingMallCustomerSessions } from "../../../../providers/getShoppingMallCustomerSessions";
import { getShoppingMallCustomerSessionsSessionId } from "../../../../providers/getShoppingMallCustomerSessionsSessionId";
import { patchShoppingMallCustomerSessions } from "../../../../providers/patchShoppingMallCustomerSessions";

@Controller("/shoppingMall/customer/sessions")
export class ShoppingmallCustomerSessionsController {
  /**
   * Retrieve the active authentication sessions for the currently authenticated actor (customer, seller, or admin).
   *
   * This endpoint provides a comprehensive view of the user's active login sessions across their respective actor type. The system resolves the actor type automatically from the session token (JWT) and queries only the appropriate session table (shopping_mall_admin_sessions, shopping_mall_customer_sessions, or shopping_mall_seller_sessions). This ensures strict actor isolation and security compliance by preventing cross-type session enumeration.
   *
   * Each returned session represents a single authentication event, capturing connection context including IP address, referrer, and timestamps. Sessions are immutable audit records - they are created upon login and become invalid upon expiration, logout, or account suspension. Deleting or modifying sessions is not permitted; they are preserved permanently for security auditing.
   *
   * The response includes session properties common across actor types: creation timestamp, expiration timestamp, IP address, referrer, and the absolute URL (href) of the page where login occurred. The response structure preserves actor context to prevent ambiguity: the actor type is embedded in the response schema through the leading prefix "shopping_mall_" in the table name context.
   *
   * This endpoint is not used for troubleshooting sessions or initiating logout - to terminate a session, use platform logout functionality, which revokes the refresh token and invalidates the session at the protocol level.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Detect actor type from JWT payload (admin, customer, or seller). Query corresponding session table: shopping_mall_admin_sessions, shopping_mall_customer_sessions, or shopping_mall_seller_sessions. Filter results by actor_id from JWT. Order by created_at descending to show most recent sessions first. Ensure no cross-actor data leakage. Return minimum list of session properties: id, created_at, expired_at, ip, href, referrer, and actor type identifier. Attach actor type as metadata field without exposing internal table names.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async get(
    @CustomerAuth()
    customer: CustomerPayload,
  ): Promise<IPageIShoppingMallAdminSession> {
    try {
      return await getShoppingMallCustomerSessions({
        customer,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a filtered and paginated list of authentication sessions across admin, customer, and seller actors.
   *
   * This operation provides advanced auditing capabilities for security compliance and anomaly detection. Administrators can search across all session types, filtering by actor type, IP address, creation date range, session status, and user agent. The results are optimized for audit dashboards and reporting, showing only key session metadata without exposing sensitive authentication tokens or connection details.
   *
   * Supports comprehensive pagination with configurable page sizes and sorting. All queried data is immutable as sessions are append-only audit records. This endpoint is only accessible to administrators with elevated privileges to ensure privacy of user authentication data.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for authentication sessions
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query all session tables (shopping_mall_admin_sessions, shopping_mall_customer_sessions, shopping_mall_seller_sessions) using UNION with actor_type discriminator.
   * Apply filters for: actor_type, created_at range, expired_at range, is_active status, ip address.
   * Sort by created_at DESC as default.
   * Apply pagination with offset/limit or cursor-based pagination based on created_at + id.
   * Return only summary fields: id, actor_type, actor_id, created_at, expired_at, is_active, ip, href, referrer.
   * Do not include access_token, refresh_token, or any private auth data.
   * Join with actor tables (admins, customers, sellers) to optionally include actor_name or shop_name if requested via query parameter.
   * Ensure all session records are read-only and audit-only.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async patch(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallAdminSession.IRequest,
  ): Promise<IPageIShoppingMallAdminSession.ISummary> {
    try {
      return await patchShoppingMallCustomerSessions({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed authentication session metadata by sessionId for security auditing and access verification.
   *
   * This endpoint provides read-only access to session records that track authentication events for both customers and sellers. The system maintains immutable session records with comprehensive connection metadata to ensure security compliance and auditability. This operation retrieves a specific session record by its unique sessionId, which can belong to either a customer or seller account.
   *
   * The session record contains essential security information including access and refresh tokens, client IP address, referrer URL, and session expiration details. This data is critical for security investigations, authentication validation, and compliance audits.
   *
   * Session records are immutable and never modified. When a user logs out or a session expires, a new session record is created. Previous sessions remain in the system for historical reference and forensic analysis. The system distinguishes between customer and seller sessions through separate database tables, but this endpoint abstracts that distinction for API consumers.
   *
   * Note: This endpoint does not support token regeneration or session modification. Any attempt to modify session data will result in an error. This endpoint is for audit and validation purposes only.
   *
   * @param connection
   * @param sessionId The unique identifier of the authentication session to retrieve. This sessionId references either a customer session or seller session in the system.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query shopping_mall_customer_sessions or shopping_mall_seller_sessions table by sessionId. First attempt to find by customerId in shopping_mall_customer_sessions. If not found, attempt to find by sellerId in shopping_mall_seller_sessions. Return the matching session record including access_token, refresh_token, ip, href, referrer, created_at, expired_at, and is_active fields. Return 404 if no session found with the given sessionId.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallCustomerSession> {
    try {
      return await getShoppingMallCustomerSessionsSessionId({
        customer,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Terminate an active session by invalidating its JWT tokens and marking it as inactive.
   *
   * This endpoint implements session termination for both admin and customer authentication sessions. According to the system's audit trails design, all session records are immutable and append-only. This operation does not delete the session record but instead sets the is_active flag to false to indicate that the session has been terminated.
   *
   * This pattern ensures that all authentication events are permanently preserved for security auditing, compliance, and forensic analysis. The actual JWT tokens (access_token and refresh_token) are not stored for future validation but are immediately invalidated with this operation.
   *
   * The system maintains separate session tables for admin and customer actors, but both follow the same audit pattern: session ID is a UUID, a created_at timestamp is recorded, and the session is terminated by setting is_active to false when logout occurs or tokens expire. This endpoint allows users to manually terminate their sessions before automatic expiration.
   *
   * The session identified by sessionId must exist in either the shopping_mall_admin_sessions or shopping_mall_customer_sessions tables, as these are the only session entities maintained by the system. Attempting to terminate a non-existent session will return a 404 error.
   *
   * Note: This operation leaves the session record intact for historical audit purposes. The session is logically deleted (soft delete) by the is_active flag and cannot be restored.
   *
   * @param connection
   * @param sessionId The unique identifier of the session to terminate. Must be a UUID that exists in either shopping_mall_admin_sessions or shopping_mall_customer_sessions table.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Look up the session record with the provided sessionId in either shopping_mall_admin_sessions or shopping_mall_customer_sessions tables. If found, update the is_active field to false. This is an atomic operation that does not change any other fields (to preserve audit integrity). Return a 204 No Content response on success. If the session ID does not exist in either table, return a 404 Not Found response. Never delete the record physically - only set is_active=false to comply with the immutable audit trail principle.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":sessionId")
  public async erase(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("sessionId")
    sessionId: string,
  ): Promise<void> {
    try {
      return await deleteShoppingMallCustomerSessionsSessionId({
        customer,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
