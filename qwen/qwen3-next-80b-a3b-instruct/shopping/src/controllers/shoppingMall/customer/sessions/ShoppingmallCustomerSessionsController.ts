import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IPageIShoppingMallCustomerSession } from "../../../../api/structures/IPageIShoppingMallCustomerSession";
import { IShoppingMallCustomerSession } from "../../../../api/structures/IShoppingMallCustomerSession";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { getShoppingMallCustomerSessionsSessionId } from "../../../../providers/getShoppingMallCustomerSessionsSessionId";
import { patchShoppingMallCustomerSessions } from "../../../../providers/patchShoppingMallCustomerSessions";

@Controller("/shoppingMall/customer/sessions")
export class ShoppingmallCustomerSessionsController {
  /**
   * Retrieve a paginated list of active user sessions across all actor types.
   *
   * This endpoint enables administrators and system services to audit and manage active authentication sessions across the platform. Sessions may belong to customers, sellers, or administrators, and can be filtered by actor type, token status, expiration date, and issuance time.
   *
   * Each session represents an active JWT authentication state with associated access and refresh tokens. Valid sessions are authenticated and active; expired sessions have their access token time window passed; invalidated sessions have been explicitly logged out or flagged for security reasons.
   *
   * This operation should be used in conjunction with user management and security monitoring tools. The response includes summary information optimized for session management dashboards, with details available through the underlying user and authentication records.
   *
   * @param connection
   * @param body Search criteria for filtering active sessions
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query shopping_mall_customer_sessions, shopping_mall_seller_sessions, and shopping_mall_admin_sessions tables.
   * Filter by actor_type (customer, seller, admin), status (active, expired, invalidated), token_issued_at range, and token_expires_at range.
   * Join with respective user tables (shopping_mall_customers, shopping_mall_sellers, shopping_mall_admins) to get user email or display name.
   * Apply pagination with cursor-based offset to support large datasets.
   * Return only the most recent session per actor session_id to avoid duplicates.
   * Order results by token_issued_at DESC to show most recent sessions first.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallCustomerSession.IRequest,
  ): Promise<IPageIShoppingMallCustomerSession.ISummary> {
    try {
      return await patchShoppingMallCustomerSessions({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed metadata for a specific active session by session ID.
   *
   * This endpoint allows authenticated customers and administrators to view the context of their own active authentication sessions. The response includes IP address, referring page, and timestamps to support security monitoring and session audit.
   *
   * Sessions are created upon successful login and remain active until expiration. Access to this endpoint is restricted to the owner of the session. Only sessions belonging to the authenticated user may be retrieved. System does not expose session metadata for other users.
   *
   * Session expiration is enforced automatically. Expired sessions are not returned. The expired_at timestamp indicates when the access token will expire (30 minutes) and when the refresh token will expire (30 days).
   *
   * Use this endpoint to diagnose login inconsistencies or detect unauthorized access.
   *
   * Related operations: POST /auth/customers/login, POST /auth/sellers/login, DELETE /auth/customers/account, DELETE /auth/sellers/account.
   *
   * @param connection
   * @param sessionId Unique session ID that was issued upon login and stored in the session cookie
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query the shopping_mall_customer_sessions table by id field using the sessionId path parameter. Validate that the authenticated user (via JWT token) owns this session by comparing shopping_mall_customer_id to the authenticated user ID. Return all fields: ip, href, referrer, created_at, expired_at. Return 404 if session not found. Return 403 if session does not belong to authenticated user. No caching.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("sessionId")
    sessionId: string,
  ): Promise<IShoppingMallCustomerSession.IDetail> {
    try {
      return await getShoppingMallCustomerSessionsSessionId({
        customer,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
