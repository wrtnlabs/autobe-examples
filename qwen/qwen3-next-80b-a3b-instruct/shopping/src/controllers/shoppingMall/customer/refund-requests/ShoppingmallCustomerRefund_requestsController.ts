import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallRefundRequest } from "../../../../api/structures/IPageIShoppingMallRefundRequest";
import { IShoppingMallRefundRequest } from "../../../../api/structures/IShoppingMallRefundRequest";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { getShoppingMallCustomerRefundRequestsRequestId } from "../../../../providers/getShoppingMallCustomerRefundRequestsRequestId";
import { patchShoppingMallCustomerRefundRequests } from "../../../../providers/patchShoppingMallCustomerRefundRequests";
import { postShoppingMallCustomerRefundRequests } from "../../../../providers/postShoppingMallCustomerRefundRequests";

@Controller("/shoppingMall/customer/refund-requests")
export class ShoppingmallCustomerRefund_requestsController {
  /**
   * Initiate a new refund request for a delivered order item within the 7-day window after delivery confirmation.
   *
   * This endpoint allows customers to request a refund for an order item that has been delivered. The system validates that the item's status is 'delivered' and that the request is submitted within 168 hours (7 days) of the delivery confirmation timestamp. Refund requests submitted outside this window are rejected.
   *
   * The customer must provide a reason for the refund request, which must be between 10 and 500 characters in length. This reason is stored as part of the refund request and preserved in an immutable snapshot for audit and compliance purposes.
   *
   * When the request is submitted, the system creates a new refund request record in 'pending' status. The refund request is linked to the specific order item and customer who initiated it. The initial refund request snapshot is created simultaneously to preserve the exact state of the order item at the time of request (including product name, variant options, price, quantity, seller ID, and delivery timestamp). This snapshot is immutable and retained indefinitely per the snapshot principle (12-snapshot-principle.md), ensuring complete audit trail and legal compliance for dispute resolution.
   *
   * After submission, the refund request remains in 'pending' status until the seller responds. If no response is made within 72 hours, the system automatically approves the refund request and initiates the refund process.
   *
   * Note: Refund requests are processed per order item, not per entire order.
   *
   * This operation cannot be used to request refunds for order items with status other than 'delivered'. Attempting to do so will result in a 400 Bad Request error.
   *
   * @param connection
   * @param body The reason for the refund request and the target order item
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Create a new shopping_mall_refund_requests record linked to the provided order_item_id and customer_id from the authenticated session.
   * Validate that the referenced order_item has status 'delivered' and created_at + 168 hours > current time.
   * Validate that the reason is 10-500 characters long.
   * Create a new refund_request with status='pending', reason from input, customer_id from auth context, order_item_id from request body.
   * Create an initial refund request snapshot (shopping_mall_refund_request_snapshots) with version=1, reason from input, status='pending', changed_by='customer', changed_at=current timestamp.
   * Return the fully formed refund_request object including generated id, created_at, and updated_at fields.
   * Reject with 400 if validation fails.
   * Reject with 404 if order_item_id does not exist or is not owned by the requesting customer.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallRefundRequest.ICreate,
  ): Promise<IShoppingMallRefundRequest> {
    try {
      return await postShoppingMallCustomerRefundRequests({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a paginated and filtered list of refund requests across the platform.
   *
   * This endpoint allows administrators and sellers to search for refund requests based on multiple criteria: status (pending, approved, rejected), associated customer ID, associated seller ID, and creation/response date ranges. The response provides summarized refund request data optimized for display in list views.
   *
   * For administrators, this endpoint provides comprehensive oversight of all refund activity across the platform, enabling efficient dispute resolution and compliance monitoring. For sellers, it allows filtering to view only refund requests related to their own products. The system enforces strict access control: customers cannot access this endpoint, only sellers can see refunds related to their products, and administrators can view all.
   *
   * Each refund request in the result set represents the current state of a customer-initiated request for a delivered order item. Refund requests are only permitted within 7 days after delivery confirmation as specified in 09-cancellation-refund.md, and the status follows an immutable workflow: pending → approved/rejected.
   *
   * Requests can be filtered by customer or seller ID for ownership-based access restriction. Date filters allow finding requests within specific timeframes for audit and reporting purposes. Pagination ensures responsive user experience even when large lists of refund requests are returned.
   *
   * This operation depends on the refund_request_snapshots table for historical audit data and the refund_requests table for current status. It does not return full snapshot details—those are available via separate snapshot endpoints.
   *
   * This endpoint may be preceded by retrieving the list of order items for a customer or seller to identify which refund requests are relevant to a particular context.
   *
   * @param connection
   * @param body Search criteria including status, associated users, date ranges, and pagination parameters.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query shopping_mall_refund_requests table with pagination. Apply filters on status, customer_id, responder_id, created_at range, and responded_at range. Join with shopping_mall_customers and shopping_mall_sellers to include user names in summary. Order by created_at descending. Return only the current state from shopping_mall_refund_requests (not snapshots). Return truncated reason and response_reason fields (if present) to reduce payload size. Ensure seller can only see their own product's refund requests. Ensure admin sees all refund requests.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallRefundRequest.IRequest,
  ): Promise<IPageIShoppingMallRefundRequest.ISummary> {
    try {
      return await patchShoppingMallCustomerRefundRequests({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve the complete lifecycle of a refund request for an order item, including its current state and all historical snapshots.
   *
   * This endpoint provides a detailed audit trail of a customer-initiated refund request, showing every state change from creation through approval or rejection. The refund request is made for a delivered order item within a 7-day window after delivery confirmation and requires a written reason (10–500 characters). The system captures the exact state of the order at request time and preserves every subsequent change.
   *
   * The response includes the current refund request status ('pending', 'approved', or 'rejected'), the customer's reason for requesting the refund, and if the request has been resolved, the seller's or admin's response and optional rejection reason. All changes to the refund request—including creation, approval, rejection, and auto-approval after 72 hours—are recorded as immutable snapshots with timestamp, actor, and state data.
   *
   * Access is strictly controlled: customers can only view their own refund requests, sellers can view requests for their products, and administrators can view all refund requests across the platform. This ensures data privacy and audit compliance.
   *
   * This operation is essential for dispute resolution, financial reconciliation, and customer service. It guarantees full traceability of refund decisions and maintains data integrity through immutable snapshots.
   *
   * @param connection
   * @param requestId The unique identifier of the refund request. Must be a valid UUID referencing a record in the shopping_mall_refund_requests table.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query shopping_mall_refund_requests by id. Include all fields: id, order_item_id, customer_id, responder_id, reason, status, response_reason, responded_at, created_at, updated_at. Retrieve all related shopping_mall_refund_request_snapshots ordered by version ascending. Join with shopping_mall_order_items to verify order item ownership. Ensure customer_id matches caller (customer) or responder_id matches caller (seller) or caller has admin role. Return 404 if not found or unauthorized.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":requestId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("requestId")
    requestId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallRefundRequest> {
    try {
      return await getShoppingMallCustomerRefundRequestsRequestId({
        customer,
        requestId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
