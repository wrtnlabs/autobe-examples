import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallCustomerWishlists } from "../../../../providers/postShoppingMallCustomerWishlists";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { patchShoppingMallCustomerWishlists } from "../../../../providers/patchShoppingMallCustomerWishlists";
import { getShoppingMallCustomerWishlistsWishlistId } from "../../../../providers/getShoppingMallCustomerWishlistsWishlistId";
import { putShoppingMallCustomerWishlistsWishlistId } from "../../../../providers/putShoppingMallCustomerWishlistsWishlistId";
import { deleteShoppingMallCustomerWishlistsWishlistId } from "../../../../providers/deleteShoppingMallCustomerWishlistsWishlistId";

import { IShoppingMallWishlist } from "../../../../api/structures/IShoppingMallWishlist";
import { IPageIShoppingMallWishlist } from "../../../../api/structures/IPageIShoppingMallWishlist";

@Controller("/shoppingMall/customer/wishlists")
export class ShoppingmallCustomerWishlistsController {
  /**
   * Create a new wishlist for the authenticated customer.
   *
   * This operation allows a customer to create a personalized wishlist for
   * future product consideration. Each wishlist is associated with the
   * authenticated user's account and can be named descriptively for
   * organizational purposes (e.g., "Future Gifts", "Travel Essentials").
   *
   * The system validates that the wishlist name is unique within the customer's
   * account. Due to the composite unique constraint on
   * (shopping_mall_customer_id, name) in the shopping_mall_wishlists table,
   * each customer can have only one wishlist per name.
   *
   * The created wishlist will have automatic timestamps for creation and
   * update, and will be initially empty of items. It will be immediately
   * accessible through the customer's profile and can be modified by adding
   * product items.
   *
   * Security: Only authenticated customers can create wishlists. Related
   * operations: GET /wishlists (list customer's wishlists), PUT
   * /wishlists/{wishlistId} (rename or update wishlist), POST
   * /wishlists/{wishlistId}/items (add items to wishlist).
   *
   * @param connection
   * @param body Creation data for the new wishlist.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallWishlist.ICreate,
  ): Promise<IShoppingMallWishlist> {
    try {
      return await postShoppingMallCustomerWishlists({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a paginated list of all wishlists created by the authenticated
   * customer, ordered by most recently updated. This operation provides a
   * comprehensive view of all active wishlists associated with the current
   * user, allowing them to manage multiple collections of products they are
   * interested in for future purchase.
   *
   * The operation supports pagination with configurable page size and supports
   * sorting by creation date or update date. Customers can browse their entire
   * collection of wishlists to identify which lists contain products they're
   * considering for future purchase.
   *
   * There are no creation, update, or deletion of wishlists through this
   * operation - these are handled through separate endpoints. This endpoint is
   * read-only and specifically designed for listing and discovery of existing
   * wishlist collections.
   *
   * The data returned represents wishlist summaries rather than full details,
   * as the purpose is to provide an overview for selection. Detailed product
   * lists within each wishlist are accessible via the specific wishlist
   * endpoint.
   *
   * This operation corresponds to the shopping_mall_wishlists Prisma model,
   * retrieving records where deleted_at is null to show only active wishlists
   * that the customer has not removed. The operation automatically filters
   * results to only include wishlists belonging to the authenticated customer
   * based on the JWT token information.
   *
   * @param connection
   * @param body Pagination, sorting and filtering controls for wishlist list
   *   retrieval
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallWishlist.IRequest,
  ): Promise<IPageIShoppingMallWishlist.ISummary> {
    try {
      return await patchShoppingMallCustomerWishlists({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information of a specific wishlist identified by its
   * unique identifier. This operation returns comprehensive data for the
   * requested wishlist including its name, creation timestamp, update
   * timestamp, and the complete list of wishlist items with product variant
   * references.
   *
   * The operation verifies that the authenticated user owns the requested
   * wishlist before returning the data, ensuring privacy and access control.
   * The response includes a full list of items in this wishlist, each
   * containing the product variant ID, when the item was added to the wishlist,
   * and any optional notes the customer has added.
   *
   * This is a detail view operation providing all necessary information about a
   * single wishlist that a customer has selected for in-depth review. While the
   * wishlist listing endpoint returns summaries, this endpoint returns complete
   * details including the contained items.
   *
   * The data structure corresponds to the shopping_mall_wishlists Prisma model
   * for wishlist metadata and the shopping_mall_wishlist_items Prisma model for
   * the items within this wishlist. The operation performs a JOIN between these
   * tables to return the complete dataset relevant to this wishlist.
   *
   * The operation excludes any wishlist items that have been soft-deleted
   * (where deleted_at is non-null), ensuring only active products of interest
   * are displayed. The operation will return a 404 error if the wishlist_id
   * does not correspond to any active wishlist owned by the authenticated
   * customer.
   *
   * @param connection
   * @param wishlistId Unique identifier of the target wishlist to retrieve.
   *   This UUID corresponds to the shopping_mall_wishlists.id field in the
   *   database.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":wishlistId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("wishlistId")
    wishlistId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallWishlist> {
    try {
      return await getShoppingMallCustomerWishlistsWishlistId({
        customer,
        wishlistId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing wishlist's name or metadata.
   *
   * This operation allows a customer to modify an existing wishlist, such as
   * renaming it or updating its metadata. The wishlist must belong to the
   * authenticated customer.
   *
   * The system enforces the composite unique constraint on
   * (shopping_mall_customer_id, name) from the shopping_mall_wishlists table.
   * When updating the wishlist name, the system verifies the new name doesn't
   * already exist for the same customer to prevent duplicate names. If the name
   * is not changed, only the updated_at timestamp is modified.
   *
   * This operation does not allow modification of wishlist items - those are
   * managed through separate endpoint. The wishlist's creation timestamp remain
   * immutable.
   *
   * Security: Only the authenticated customer who owns the wishlist can perform
   * this operation. Related operations: GET /wishlists (list customer's
   * wishlists), DELETE /wishlists/{wishlistId} (soft delete wishlist), POST
   * /wishlists/{wishlistId}/items (add items to wishlist).
   *
   * @param connection
   * @param wishlistId Unique identifier of the target wishlist. This can be
   *   either the primary key UUID or a business code if present in schema;
   *   however, the shopping_mall_wishlists table uses UUID for id and has no
   *   separate code field, so the parameter must be the UUID formatted string.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":wishlistId")
  public async update(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("wishlistId")
    wishlistId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallWishlist> {
    try {
      return await putShoppingMallCustomerWishlistsWishlistId({
        customer,
        wishlistId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a user's wishlist and all its associated items. This
   * operation performs a hard delete of the wishlist record from the database,
   * removing it entirely and making it unrecoverable. The corresponding
   * wishlist items are automatically removed through database cascade deletion.
   * This action is irreversible and should be used with caution.
   *
   * This operation directly targets the shopping_mall_wishlists model and must
   * be performed by the owner of the wishlist. The operation first verifies
   * that the authenticated user is the owner of the wishlist by comparing the
   * user ID from the authentication token with the shopping_mall_customer_id
   * field in the wishlist record. If the user is not the owner, the operation
   * fails with access denied error.
   *
   * There is no soft delete functionality implemented for wishlists because
   * user-specific wishlist data is considered personal data that users have
   * full control over. The absence of a soft_delete_column in the
   * shopping_mall_wishlists schema confirms that hard deletion is the intended
   * behavior.
   *
   * Successful deletion returns no response body, as the resource is completely
   * removed from the system.
   *
   * Related operations: DELETE /wishlists/{wishlistId}/items (to remove
   * individual items without deleting the entire wishlist).
   *
   * @param connection
   * @param wishlistId Unique identifier of the wishlist to be deleted. This is
   *   the primary key of the shopping_mall_wishlists model.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":wishlistId")
  public async erase(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("wishlistId")
    wishlistId: string,
  ): Promise<void> {
    try {
      return await deleteShoppingMallCustomerWishlistsWishlistId({
        customer,
        wishlistId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
