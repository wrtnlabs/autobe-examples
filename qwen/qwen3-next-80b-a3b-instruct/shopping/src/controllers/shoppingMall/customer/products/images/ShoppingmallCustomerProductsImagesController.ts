import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallCustomerProductsProductIdImages } from "../../../../../providers/patchShoppingMallCustomerProductsProductIdImages";

import { IPageIShoppingMallProductImage } from "../../../../../api/structures/IPageIShoppingMallProductImage";
import { IShoppingMallProductImage } from "../../../../../api/structures/IShoppingMallProductImage";

@Controller("/shoppingMall/customer/products/:productId/images")
export class ShoppingmallCustomerProductsImagesController {
  /**
   * Retrieve a paginated and filtered list of product images associated with a
   * specific product. This endpoint provides a comprehensive view of all visual
   * assets linked to the product, enabling efficient browsing and management of
   * product media.
   *
   * The operation queries the shopping_mall_product_images table to return
   * images associated with the specified product_id. Results can be filtered by
   * primary status, sort order, or other criteria to facilitate efficient media
   * selection. The response includes a pagination structure to handle products
   * with large image collections.
   *
   * Images returned may include both primary and secondary images, ordered by
   * sort_order ascending, with primary images (is_primary=true) appearing first
   * by default. Only images related to the specified product (and not its
   * variants) are returned. The operation excludes deleted images (where
   * deleted_at is not null).
   *
   * This operation is commonly paired with GET /products/{productId} to present
   * a complete product view, and with POST /products/{productId}/images to
   * upload new images. The Shopify's media management approach inspired this
   * design for scalable image handling.
   *
   * Security enforcement ensures the requesting user has appropriate
   * permissions to view the product images via the authorizationActors. The
   * result set can be used by UI components to generate gallery views, carousel
   * sliders, or media selection interfaces.
   *
   * @param connection
   * @param productId Unique identifier of the product whose images are being
   *   retrieved. Must reference a valid shopping_mall_products.id. All returned
   *   images must be directly associated with this product, not its variants.
   * @param body Search, filter, and pagination parameters for product images
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallProductImage.IRequest,
  ): Promise<IPageIShoppingMallProductImage> {
    try {
      return await patchShoppingMallCustomerProductsProductIdImages({
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
