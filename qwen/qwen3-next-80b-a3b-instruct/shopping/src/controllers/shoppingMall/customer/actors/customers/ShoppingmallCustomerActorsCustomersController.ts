import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { putShoppingMallCustomerActorsCustomersCustomerId } from "../../../../../providers/putShoppingMallCustomerActorsCustomersCustomerId";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";

import { IShoppingMallCustomer } from "../../../../../api/structures/IShoppingMallCustomer";

@Controller("/shoppingMall/customer/actors/customers/:customerId")
export class ShoppingmallCustomerActorsCustomersController {
  /**
   * Update an existing customer's profile information on the shoppingMall
   * platform.
   *
   * This operation allows an authenticated customer to modify their personal
   * details such as name, email, or contact preferences. The customer must be
   * logged in and the operation validates that the requester matches the
   * customerId in the path parameter.
   *
   * The system ensures that email changes require verification, preventing
   * unauthorized email takeover attempts. When the email is updated, the system
   * marks the new email as pending verification and sends a verification email
   * to the new address. Until confirmed, the customer can still use the
   * platform with their original email.
   *
   * The update operation only allows modification of fields permitted to
   * customers: first_name, last_name, and notification preferences. Sensitive
   * fields like password_hash are not modifiable directly through this endpoint
   * - password changes must use the dedicated credential update workflow.
   *
   * The operation modifies the existing customer record in the
   * shopping_mall_customers table and updates the updated_at timestamp. The
   * original status (active, suspended, pending_verification) is maintained
   * unless explicitly changed through administrative processes.
   *
   * For security and compliance reasons, the response returns the updated
   * customer record in the same format as the create operation, excluding
   * password_hash and other sensitive fields.
   *
   * Related operations: POST /actors/customers to create new customer accounts,
   * GET /actors/customers/{customerId} to retrieve customer details, and DELETE
   * /actors/customers/{customerId} to suspend customer accounts.
   *
   * @param connection
   * @param customerId Unique identifier of the customer account to be updated.
   *   This must match the authenticated user's ID for security purposes.
   * @param body The fields and values to be updated for the customer profile.
   *   Only permitted fields (first_name, last_name) can be modified.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("customerId")
    customerId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallCustomer.IUpdate,
  ): Promise<IShoppingMallCustomer> {
    try {
      return await putShoppingMallCustomerActorsCustomersCustomerId({
        customer,
        customerId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
