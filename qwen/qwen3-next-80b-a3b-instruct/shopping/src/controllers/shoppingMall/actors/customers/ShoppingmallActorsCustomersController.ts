import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallActorsCustomers } from "../../../../providers/postShoppingMallActorsCustomers";
import { patchShoppingMallActorsCustomers } from "../../../../providers/patchShoppingMallActorsCustomers";
import { getShoppingMallActorsCustomersCustomerId } from "../../../../providers/getShoppingMallActorsCustomersCustomerId";

import { IShoppingMallCustomer } from "../../../../api/structures/IShoppingMallCustomer";
import { IPageIShoppingMallCustomer } from "../../../../api/structures/IPageIShoppingMallCustomer";

@Controller("/shoppingMall/actors/customers")
export class ShoppingmallActorsCustomersController {
  /**
   * Create a new customer account on the shoppingMall platform.
   *
   * This operation allows a new user to register as a customer by providing
   * their personal information and contact details. The system validates the
   * email address format, checks for duplicate email accounts, and initiates a
   * verification process to confirm ownership of the email address.
   *
   * The operation creates a new record in the shopping_mall_customers table
   * with initial status set to 'pending_verification'. The customer receives a
   * verification email with a link that must be clicked to activate the
   * account. Until verification is completed, the customer cannot access most
   * platform features.
   *
   * Security measures include password strength requirements, bcrypt password
   * hashing, and rate limiting to prevent brute force attacks. The operation
   * automatically generates a unique customer ID and timestamps for creation
   * and update.
   *
   * After successful creation, a JSON response returns the new customer record
   * with a subset of fields for security reasons, excluding sensitive
   * information like password_hash.
   *
   * Related operations: GET /actors/customers/{customerId} to retrieve the
   * verified customer details, PATCH /actors/customers to list all customers
   * with pagination, and PUT /actors/customers/{customerId} to update customer
   * information.
   *
   * @param connection
   * @param body Details required to create a new customer account on the
   *   shoppingMall platform.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @TypedBody()
    body: IShoppingMallCustomer.ICreate,
  ): Promise<IShoppingMallCustomer> {
    try {
      return await postShoppingMallActorsCustomers({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a filtered and paginated list of shopping mall customer accounts
   * from the system. This operation operates on the shopping_mall_customers
   * table and supports advanced search capabilities for finding customers based
   * on multiple criteria including partial name matching, email domain
   * filtering, registration date ranges, and account status.
   *
   * The operation supports comprehensive pagination with configurable page
   * sizes and sorting options. Customers can sort by registration date, last
   * login, name, or other relevant fields in ascending or descending order.
   *
   * Security considerations include rate limiting for search operations and
   * appropriate filtering of sensitive customer information based on the
   * requesting user's authorization level. Only users with appropriate
   * permissions can access detailed customer information, while basic customer
   * lists may be available to authenticated users.
   *
   * This operation integrates with the shopping_mall_customers table as defined
   * in the Prisma schema, incorporating all available customer fields and
   * relationships. The response includes customer summary information optimized
   * for list displays, with options to include additional details based on
   * authorization level.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for customer
   *   filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IShoppingMallCustomer.IRequest,
  ): Promise<IPageIShoppingMallCustomer.ISummary> {
    try {
      return await patchShoppingMallActorsCustomers({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific shopping mall customer
   * account by its unique identifier.
   *
   * This operation fetches the complete customer profile from the
   * shopping_mall_customers table, including personal information, account
   * status, and registration metadata. The customer record returned is the full
   * detail representation without summary reductions.
   *
   * The operation validates that the requested customer exists and is not
   * marked for deletion. If the customer is suspended, only limited public
   * metadata is returned, while active customers return full profile details
   * according to visibility rules.
   *
   * Customer IDs are expected as UUIDs and must match the primary key format
   * used in the shopping_mall_customers table. Endpoint access is public for
   * customer self-lookup or restricted to administrators based on authorization
   * settings.
   *
   * Security: Rate limiting applies to prevent brute force attacks on customer
   * identifiers. The response includes only information the requesting user has
   * permission to view, with sensitive fields like password_hash always
   * excluded.
   *
   * @param connection
   * @param customerId Unique identifier of the target customer account. This
   *   UUID corresponds to the id field in the shopping_mall_customers table and
   *   is used to locate the specific customer entity.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":customerId")
  public async at(
    @TypedParam("customerId")
    customerId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallCustomer> {
    try {
      return await getShoppingMallActorsCustomersCustomerId({
        customerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
