import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postShoppingMallActorsSellers } from "../../../../providers/postShoppingMallActorsSellers";

import { IShoppingMallSeller } from "../../../../api/structures/IShoppingMallSeller";

@Controller("/shoppingMall/actors/sellers")
export class ShoppingmallActorsSellersController {
  /**
   * Create a new seller account on the shoppingMall platform. This operation
   * registers a business entity as a seller capable of listing products for
   * sale. The seller account requires validation of business information before
   * becoming active.
   *
   * This operation accepts the core seller registration data including business
   * name, legal address, tax identification, and contact email. The password is
   * encrypted using BCrypt upon creation and stored securely. Upon successful
   * creation, the seller account enters a 'pending_verification' status and
   * requires document submission for final approval.
   *
   * The operation is only accessible via the seller registration interface and
   * cannot be performed by administrators or other actors.
   *
   * Related operations: GET /actors/sellers/{sellerId} retrieves the account
   * details after creation.
   *
   * Note regarding soft delete: This operation creates a permanent seller
   * account. The 'deleted_at' field remains null at creation and is only
   * populated if the account is later suspended or deactivated through
   * administrative action.
   *
   * @param connection
   * @param body Registration details for a new seller account
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @TypedBody()
    body: IShoppingMallSeller.ICreate,
  ): Promise<IShoppingMallSeller.IRegistrationResponse> {
    try {
      return await postShoppingMallActorsSellers({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve the detailed information of a specific seller account from the
   * shoppingMall platform. This operation returns comprehensive seller data for
   * view-only purposes.
   *
   * The operation returns all core seller information including business name,
   * contact email, tax identification, registration status, and timestamps.
   * Seller account exceptions include the password_hash field, which is never
   * returned to protect authentication security.
   *
   * The sellerId parameter must correspond to the unique UUID identifier of the
   * target seller. The operation supports both active and suspended accounts
   * but excludes accounts with deleted_at timestamp set.
   *
   * Access is permitted to the authenticated seller themselves, platform
   * administrators, and users with appropriate permissions. The operation does
   * not require authentication for public access to non-sensitive seller
   * information, but authentication is required to view the complete profile.
   *
   * Related operations: POST /actors/sellers creates a new seller account.
   * PATCH /actors/sellers searches and filters seller accounts by criteria.
   *
   * Note regarding soft delete: This operation filters out accounts with a
   * non-null deleted_at field, providing only active or pending seller
   * records.
   *
   * @param connection
   * @param sellerId Unique identifier of the target seller account
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sellerId")
  public async at(
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallSeller> {
    sellerId;
    return typia.random<IShoppingMallSeller>();
  }
}
