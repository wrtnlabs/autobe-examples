import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallProductsProductIdTags } from "../../../../providers/patchShoppingMallProductsProductIdTags";
import { getShoppingMallProductsProductIdTagsTagId } from "../../../../providers/getShoppingMallProductsProductIdTagsTagId";

import { IPageIShoppingMallProductTag } from "../../../../api/structures/IPageIShoppingMallProductTag";
import { IShoppingMallProductTag } from "../../../../api/structures/IShoppingMallProductTag";

@Controller("/shoppingMall/products/:productId/tags")
export class ShoppingmallProductsTagsController {
  /**
   * Retrieve all tags associated with a specific product in the shoppingMall
   * catalog. This operation operates on the shopping_mall_product_tags_products
   * junction table that establishes the many-to-many relationship between
   * products and tags. The endpoint returns a comprehensive list of all tags
   * applied to the specified product, including tag name, description, and
   * display order.
   *
   * This operation functions as a search/list endpoint with filtering
   * capabilities, sorted by the display_order field to ensure consistent UI
   * presentation. Each tag returned is an individual record from the
   * shopping_mall_product_tags table, linked through the
   * shopping_mall_product_tags_products junction table.
   *
   * Security: This is a public read operation. Any user, authenticated or not,
   * can retrieve product tags. The system does not restrict tag visibility
   * based on user roles or permissions since tags are public categorization
   * metadata.
   *
   * Implementation note: This operation performs a JOIN between
   * shopping_mall_products, shopping_mall_product_tags_products, and
   * shopping_mall_product_tags tables to return tag data. It selects ONLY the
   * tag properties (name, description, slug, display_order) from the
   * shopping_mall_product_tags entity, excluding product-related data to
   * maintain clean separation of concerns. The results are ordered by
   * display_order to ensure consistent presentation in UI components that rely
   * on tag ordering for navigation or filtering.
   *
   * @param connection
   * @param productId Unique identifier of the target product. This may be a
   *   UUID in the database or a product code if one is defined in the schema.
   *   In this system, the product identifier is a UUID.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
  ): Promise<IPageIShoppingMallProductTag> {
    try {
      return await patchShoppingMallProductsProductIdTags({
        productId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific tag associated with a product in the shoppingMall
   * catalog. This operation accesses the shopping_mall_product_tags_products
   * junction table to verify the relationship between a product and a specific
   * tag, then returns the complete tag details from the
   * shopping_mall_product_tags table.
   *
   * This is a detail retrieval operation (GET) that returns a single tag object
   * when the product-tag relationship exists. If the specified tag is not
   * associated with the product or does not exist, the system returns a 404 Not
   * Found error.
   *
   * Security: This is a public read operation. Any user, authenticated or not,
   * can retrieve specific product-tag associations. Tags are public
   * categorization metadata and are not subject to access controls based on
   * actor roles.
   *
   * Implementation note: This operation performs a JOIN between
   * shopping_mall_products, shopping_mall_product_tags_products, and
   * shopping_mall_product_tags tables to verify the existence of the
   * relationship and retrieve the tag's complete properties. Unlike the index
   * operation, this returns a single tag object with all its fields (name,
   * slug, description, display_order) instead of an array. The system does not
   * return product information in this response; it only returns tag
   * information as the response body type is ISshoppingMallProductTag, which
   * represents the tag entity itself.
   *
   * @param connection
   * @param productId Unique identifier of the target product. This may be a
   *   UUID in the database or a product code if one is defined in the schema.
   *   In this system, the product identifier is a UUID.
   * @param tagId Unique identifier of the target tag. This is the UUID of the
   *   specific tag in the shopping_mall_product_tags table. The system does not
   *   use human-readable codes for tags as there is no unique code field
   *   defined in the schema.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":tagId")
  public async at(
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedParam("tagId")
    tagId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallProductTag> {
    try {
      return await getShoppingMallProductsProductIdTagsTagId({
        productId,
        tagId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
