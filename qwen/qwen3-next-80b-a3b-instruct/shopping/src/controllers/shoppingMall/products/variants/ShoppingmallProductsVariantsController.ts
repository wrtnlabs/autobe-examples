import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchShoppingMallProductsProductIdVariants } from "../../../../providers/patchShoppingMallProductsProductIdVariants";
import { getShoppingMallProductsProductIdVariantsVariantId } from "../../../../providers/getShoppingMallProductsProductIdVariantsVariantId";

import { IPageIShoppingMallProductVariant } from "../../../../api/structures/IPageIShoppingMallProductVariant";
import { IShoppingMallProductVariant } from "../../../../api/structures/IShoppingMallProductVariant";

@Controller("/shoppingMall/products/:productId/variants")
export class ShoppingmallProductsVariantsController {
  /**
   * Retrieve a paginated list of product variants for a specific product. This
   * operation queries the shopping_mall_product_variants table and returns all
   * active variants associated with the given product ID. Variants are sorted
   * by creation date in descending order and support filtering by attributes,
   * price range, and inventory status.
   *
   * The operation supports comprehensive pagination with configurable page
   * sizes and sorting options. Variants can be filtered by attributes (color,
   * size, etc.) using JSON path expressions, price ranges, and minimum
   * inventory thresholds.
   *
   * Security considerations include rate limiting for search operations and
   * appropriate filtering of sensitive variant information based on the
   * requesting user's authorization level. Only users with appropriate
   * permissions can access detailed variant information, while basic variant
   * lists may be available to authenticated users.
   *
   * This operation integrates with the shopping_mall_product_variants table as
   * defined in the Prisma schema, incorporating all available variant fields
   * and relationships to the parent product. The response includes variant
   * summary information optimized for list displays, with options to include
   * additional details based on authorization level.
   *
   * @param connection
   * @param productId Unique identifier of the parent product whose variants are
   *   being queried. This is a UUID that links to the shopping_mall_products.id
   *   field.
   * @param body Search criteria and pagination parameters for variant filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallProductVariant.IRequest,
  ): Promise<IPageIShoppingMallProductVariant.ISummary> {
    try {
      return await patchShoppingMallProductsProductIdVariants({
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single product variant by its unique identifier. This operation
   * queries the shopping_mall_product_variants table and returns the complete
   * variant information for the specified variant ID, including its
   * relationship to the parent product.
   *
   * The operation returns detailed information about the variant including its
   * SKU, specific pricing, current inventory count, and attribute details. The
   * parent product information is included in the response to provide full
   * context without requiring additional API calls.
   *
   * Security considerations include validation that the requesting user has
   * access to the product (via the parent product's seller relationship) and
   * rate limiting to prevent abuse. Only users with appropriate permissions can
   * access detailed variant information.
   *
   * This operation integrates with the shopping_mall_product_variants table as
   * defined in the Prisma schema, incorporating all available variant fields
   * and the relationship to the parent product. The response includes detailed
   * variant information optimized for display in product detail pages.
   *
   * @param connection
   * @param productId Unique identifier of the parent product of the target
   *   variant. This is a UUID that links to the shopping_mall_products.id
   *   field.
   * @param variantId Unique identifier of the target product variant. This is a
   *   UUID that links to the shopping_mall_product_variants.id field.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":variantId")
  public async at(
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedParam("variantId")
    variantId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallProductVariant> {
    try {
      return await getShoppingMallProductsProductIdVariantsVariantId({
        productId,
        variantId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
