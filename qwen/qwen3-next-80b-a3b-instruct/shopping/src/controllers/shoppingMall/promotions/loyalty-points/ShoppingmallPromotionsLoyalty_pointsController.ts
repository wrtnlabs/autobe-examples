import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { patchShoppingMallPromotionsLoyaltyPoints } from "../../../../providers/patchShoppingMallPromotionsLoyaltyPoints";

import { IPageIShoppingMallLoyaltyPointTransaction } from "../../../../api/structures/IPageIShoppingMallLoyaltyPointTransaction";
import { IShoppingMallLoyaltyPointTransaction } from "../../../../api/structures/IShoppingMallLoyaltyPointTransaction";

@Controller("/shoppingMall/promotions/loyalty-points")
export class ShoppingmallPromotionsLoyalty_pointsController {
  /**
   * Retrieve paginated, filtered list of loyalty point transactions based on
   * search criteria and filters. This operation operates on the
   * shopping_mall_loyalty_point_transactions table from the Prisma schema and
   * provides comprehensive search and filtering capabilities for loyalty point
   * transactions.
   *
   * Users can filter transactions by customer, transaction type
   * (purchase_reward, sign_up_bonus, referral_bonus, point_redemption,
   * admin_adjustment), status (pending, completed, reversed), date ranges, and
   * search by description. The operation supports pagination with configurable
   * page sizes and sorting by points change amount, transaction date, or
   * status.
   *
   * This operation is designed for administrative oversight, customer service
   * investigations, and internal reconciliation purposes. Only authenticated
   * users with appropriate permissions can access transaction data. The results
   * include summary information with customer information, transaction type,
   * points change, and status.
   *
   * Note that loyalty point balances themselves are maintained in the
   * shopping_mall_loyalty_points table, but individual transactions are
   * recorded in this table for auditability. For querying current point
   * balances, use the shopping_mall_loyalty_points endpoint instead. This
   * endpoint focuses on the transaction history that leads to current
   * balances.
   *
   * Application Domain: This operation is essential for revenue analytics,
   * fraud detection by identifying unusual transaction patterns, customer
   * service investigations where customers question point activity, and
   * reconciliation between system balances and transaction records.
   *
   * @param connection
   * @param body Search parameters and filtering criteria for loyalty point
   *   transactions
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IShoppingMallLoyaltyPointTransaction.IRequest,
  ): Promise<IPageIShoppingMallLoyaltyPointTransaction.ISummary> {
    try {
      return await patchShoppingMallPromotionsLoyaltyPoints({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
