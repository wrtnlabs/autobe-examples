import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia from "typia";
import { patchShoppingMallPromotionsCoupons } from "../../../../providers/patchShoppingMallPromotionsCoupons";
import { getShoppingMallPromotionsCouponsCouponCode } from "../../../../providers/getShoppingMallPromotionsCouponsCouponCode";

import { IPageIShoppingMallCoupon } from "../../../../api/structures/IPageIShoppingMallCoupon";
import { IShoppingMallCoupon } from "../../../../api/structures/IShoppingMallCoupon";

@Controller("/shoppingMall/promotions/coupons")
export class ShoppingmallPromotionsCouponsController {
  /**
   * Retrieve a filtered and paginated list of all active promotional coupons
   * available on the shoppingMall platform. This operation queries the
   * shopping_mall_coupons table to return coupons that are currently active
   * (status = 'active') and have not exceeded their usage limits (usage_count <
   * max_usage_count). The response includes coupon codes, discount details,
   * validity periods, and eligibility restrictions to help customers identify
   * applicable promotions.
   *
   * This operation supports pagination through limit and offset parameters,
   * along with sorting options by discount amount, expiration date, or creation
   * date. Filtering is possible by discount type (fixed_amount or percentage),
   * minimum order value thresholds, and applicable categories or products. The
   * search functionality allows partial matching on coupon codes for quick
   * discovery.
   *
   * Security considerations include limiting coupon visibility to active,
   * non-expired records and preventing exposure of sensitive business metrics
   * like exact usage counts for internal audit purposes. Only customers and
   * anonymous users can access this list; administrators use separate
   * administrative interfaces for coupon management.
   *
   * This endpoint integrates directly with the shopping_mall_coupons Prisma
   * model, using all relevant fields including code, discount_amount,
   * discount_percentage, min_order_value, valid_from, valid_until, status, and
   * applicable_to_categories. The system automatically excludes expired or
   * exhausted coupons based on current timestamp and usage data.
   *
   * @param connection
   * @param body Search, filter, and pagination parameters for coupon discovery
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IShoppingMallCoupon.IRequest,
  ): Promise<IPageIShoppingMallCoupon.ISummary> {
    try {
      return await patchShoppingMallPromotionsCoupons({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific coupon using its unique
   * code.
   *
   * This operation looks up a single coupon record from the
   * shopping_mall_coupons table by its exact code value, returning
   * comprehensive details including discount type, validity period, usage
   * statistics, and eligibility rules. The code is treated as a
   * case-insensitive unique identifier for coupon lookup.
   *
   * The response includes all relevant coupon properties except for internal
   * audit fields like usage_count (which is omitted for security reasons), and
   * provides contextual information about whether the coupon is still valid for
   * current use based on expiration date and usage limits. This operation is
   * used by customers to validate coupon codes during checkout before applying
   * them to their order.
   *
   * This operation depends on the shopping_mall_coupons table where the code
   * field is uniquely indexed and serves as a public identifier for coupons.
   * The implementation ensures no sensitive information such as
   * created_by_admin_id or campaign_id is exposed in the response. The coupon
   * code must match exactly in a case-insensitive comparison, as defined by the
   * unique index on the code field in the shopping_mall_coupons model.
   *
   * This operation can have been preceded by the index operation to discover
   * available coupons by code, or used directly when a customer has received a
   * coupon code through marketing channels.
   *
   * @param connection
   * @param couponCode The exact alphanumeric code of the coupon to retrieve.
   *   Must be a valid, non-empty code. Case-insensitive matching is applied.
   *   This field is required for identifying the specific coupon.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":couponCode")
  public async at(
    @TypedParam("couponCode")
    couponCode: string,
  ): Promise<IShoppingMallCoupon> {
    try {
      return await getShoppingMallPromotionsCouponsCouponCode({
        couponCode,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
