export type IShoppingMallRegionSummary = {
  /**
   * Unique identifier code for the geographic region, such as 'NA-EAST',
   * 'EU-WEST', or 'ASIA-PACIFIC'.
   *
   * Used to uniquely identify and group shipping data by geographic region.
   * Matches region codes in the shopping_mall_regions table for consistency.
   *
   * This code serves as the primary key in the region summary object and
   * enables aggregation and comparison between regions.
   */
  region_code: string;

  /**
   * Total number of shipments delivered to this region during the reporting
   * period.
   *
   * Represents the aggregate count of all orders with shipping addresses in
   * this region.
   *
   * Computed by joining shopping_mall_order_shipments with
   * shopping_mall_order_addresses and filtering by region_code.
   */
  total_shipments: number & tags.Type<"int32"> & tags.Minimum<0>;

  /**
   * Percentage of shipments delivered on time to this region, calculated as
   * (on_time_shipments / total_shipments).
   *
   * A key performance indicator (KPI) for regional logistics efficiency.
   * 'On-time' is defined by carrier-specific SLA agreements consolidated in
   * the platform's shipping rules.
   *
   * Based on analysis of shopping_mall_delivery_events comparing planned
   * delivery windows with actual arrival timestamps.
   */
  on_time_rate: number & tags.Minimum<0> & tags.Maximum<1>;

  /**
   * Average number of days from order placement to final delivery for
   * shipments in this region.
   *
   * Measures distance-based and carrier efficiency characteristics.
   * Calculated by averaging the time difference between
   * shopping_mall_orders.created_at and
   * shopping_mall_delivery_events.event_time = 'delivered' for all deliveries
   * in this region.
   *
   * Used to identify regions with logistical challenges such as remoteness or
   * delivery congestion.
   */
  average_delivery_duration_days: number & tags.Minimum<0>;

  /**
   * Number of shipments to this region that failed to be delivered
   * successfully.
   *
   * Includes shipments with status: abandoned, lost, returned, or cancelled
   * after shipment was initiated.
   *
   * Identifies regional problems related to infrastructure, carrier
   * reliability, or address validation issues.
   *
   * Determined by querying shopping_mall_delivery_events for failure-related
   * event types and cross-referencing with shipping addresses in
   * shopping_mall_order_addresses.
   */
  failed_shipments: number & tags.Type<"int32"> & tags.Minimum<0>;

  /**
   * Total shipping revenue generated from orders delivered to this region.
   *
   * Sum of all shipping costs applied to orders shipped to this region.
   *
   * Calculated from the shipping_cost field in shopping_mall_order_shipments
   * joined with shopping_mall_order_addresses by region_code.
   */
  total_revenue: number & tags.Minimum<0>;

  /**
   * Average shipping fee per order delivered to this region.
   *
   * Calculated as total_revenue / total_shipments.
   *
   * Helps assess if regional shipping fees are appropriately aligned with
   * delivery costs and order value.
   *
   * Identifies regions where shipping may be over/under-priced relative to
   * operational expense.
   */
  average_revenue_per_order: number & tags.Minimum<0>;

  /**
   * Statistical variance of delivery durations across all shipments to this
   * region.
   *
   * Measures the spread of delivery times around the mean. High variance
   * indicates inconsistent delivery performance.
   *
   * Calculated using standard statistical variance formula on the time
   * difference between shopping_mall_orders.created_at and
   * shopping_mall_delivery_events.event_time for all shipments in the
   * region.
   */
  delivery_time_variance: number & tags.Minimum<0>;

  /**
   * Composite performance score for this region, combining on-time rate,
   * failure rate, and delivery duration into a single metric.
   *
   * Calculated as: (on_time_rate * 50) + ((1 -
   * failed_shipments/total_shipments) * 30) + ((1 -
   * average_delivery_duration_days/max_expected_days) * 20)
   *
   * Used for quick benchmarking and ranking regions by overall logistical
   * health.
   */
  delivery_performance_score: number & tags.Minimum<0> & tags.Maximum<100>;

  /**
   * Average customer satisfaction rating for orders delivered to this region.
   *
   * Based on product review ratings associated with orders shipped to this
   * region.
   *
   * Calculated by joining shopping_mall_order_addresses (region_code) ->
   * shopping_mall_orders -> shopping_mall_order_items ->
   * shopping_mall_product_reviews and averaging the rating fields.
   */
  customer_satisfaction_score: number & tags.Minimum<0> & tags.Maximum<5>;

  /**
   * The carrier with the highest performance metrics in this region.
   *
   * Determined by ranking carriers in the region by total_shipments and
   * on_time_rate.
   *
   * Provides insight into regional carrier preferences and actionability for
   * carrier management.
   */
  top_carrier: string;

  /**
   * Cost efficiency ratio for shipping in this region, calculated as
   * (total_revenue / total_shipping_cost_expense).
   *
   * Indicates profitability of regional shipping operations. Values >1
   * indicate profitable operations.
   *
   * Calculated from financial records in shopping_mall_shipping_cost_logs and
   * shopping_mall_order_shipments.
   */
  shipping_cost_efficiency: number & tags.Minimum<0>;

  /**
   * Proportion of deliveries to this region that resulted in returns.
   *
   * Calculated as (total_returns / total_shipments).
   *
   * High return rates suggest issues with product relevance, sizing accuracy,
   * or regional customer expectations.
   *
   * Derived from shopping_mall_order_returns joined with
   * shopping_mall_order_addresses by region_code.
   */
  return_rate: number & tags.Minimum<0> & tags.Maximum<1>;

  /**
   * Average time to delivery in hours, calculated from order placement to
   * final delivery.
   *
   * Provides higher-granularity insight than days-based metric, useful for
   * same-day or express delivery optimization.
   *
   * Calculated by averaging (delivery_time - order_time) in hours from
   * shopping_mall_orders and shopping_mall_delivery_events tables.
   */
  average_delivery_time_in_hours: number & tags.Minimum<0>;
};
