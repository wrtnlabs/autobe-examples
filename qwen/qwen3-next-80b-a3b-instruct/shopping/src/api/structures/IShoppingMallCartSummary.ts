import { tags } from "typia";

/**
 * Summary data for the authenticated customer's shopping cart including
 * aggregated statistics and state information.
 *
 * This DTO provides a lightweight overview of the cart without exposing
 * detailed line items or product information. It includes essential metrics for
 * cart display on mobile apps and web interfaces to improve performance and
 * reduce data transfer.
 *
 * The summary is computed from the shopping_mall_carts and
 * shopping_mall_cart_items tables in the database, with additional state logic
 * determined by order associations and activity timestamps.
 *
 * This type is used exclusively in the response body of the GET
 * /shoppingMall/customer/carts/summary operation, which is restricted to
 * authenticated customers.
 *
 * The cartId is included to ensure client-side cart tracking, though it is
 * derived from the authentication context. The totalValue is calculated using
 * the most current variant pricing from shopping_mall_product_variant_pricing
 * to ensure financial accuracy.
 *
 * The 'isGuestCart' field determines the session source (cart_session vs
 * customer), 'hasSavedPayments' indicates availability of
 * payment.tokenizations, and 'hasSavedAddresses' reflects presence in
 * order_addresses. These are mandatory for UI state management and checkout
 * workflow decisions.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type IShoppingMallCartSummary = {
  /**
   * Unique identifier for the shopping cart session. This maps to the
   * shopping_mall_carts table in the database and identifies the customer's
   * active cart.
   */
  cartId: string & tags.Format<"uuid">;

  /**
   * Total number of unique product variants in the cart. This is calculated
   * by counting the distinct shopping_mall_cart_items entries associated with
   * this cart.
   */
  itemCount: number & tags.Type<"int32"> & tags.Minimum<0>;

  /**
   * Combined monetary value of all items in the cart, calculated using
   * current variant pricing from shopping_mall_product_variant_pricing. Value
   * is in the base currency of the platform (USD).
   */
  totalValue: number & tags.Minimum<0>;

  /**
   * Current state of the cart determined by business rules:
   *
   * - Active: Cart has been recently updated and no associated order exists
   * - Abandoned: Cart has not been active for more than 30 days and has no
   *   associated order
   * - Pending_checkout: Cart is associated with an order that has been created
   *   but not yet completed
   *
   * This state is computed from the cart's last activity timestamp and any
   * associated order records in shopping_mall_orders.
   */
  state: "active" | "abandoned" | "pending_checkout";

  /**
   * Timestamp of the last modification to this cart, based on the updatedAt
   * field in shopping_mall_carts table. This reflects when items were added,
   * removed, or quantities changed.
   */
  lastUpdated: string & tags.Format<"date-time">;
};
