import { tags } from "typia";

/**
 * Product pricing details including base price, active discounts, currency
 * context, and variant-specific pricing information.
 *
 * This schema represents the complete pricing structure for a product in the
 * shopping mall platform.
 *
 * The pricing model supports multiple pricing strategies including:
 *
 * - A base price for the product
 * - Global discounts applicable to all variants
 * - Variant-specific pricing where different attribute combinations have
 *   different costs
 * - Promotional discounts on specific variants
 * - Dynamic stock status indicators
 *
 * The base price is the foundational price set by the seller, while variant
 * pricing allows for price differentiation based on product attributes (e.g.,
 * size, color, material). Discounted pricing reflects any active promotions
 * that reduce the base or variant prices.
 *
 * All prices are expressed in a specified currency using ISO 4217 codes,
 * enabling international commerce and currency conversion.
 *
 * The schema includes stock status for each variant to help customers
 * understand purchase availability.
 *
 * Each pricing record in the variantPricing array is linked to its
 * corresponding product variant through the variant_id field in the
 * shopping_mall_product_variant_pricing table, ensuring accurate mapping
 * between products and their pricing configurations.
 *
 * This pricing data is used in product listings, shopping carts, checkout
 * processes, and analytics systems to ensure accurate financial transactions.
 *
 * Derived from the shopping_mall_product_variant_pricing table in the database,
 * with additional context from the shopping_mall_product_variants table for
 * variant.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type IShoppingMallProductPricing = {
  /**
   * The base listed price of the product in the primary currency before any
   * discounts or variants are applied.
   *
   * This is the foundational price set by the seller for the product,
   * independent of any variants, promotions, or regional pricing adjustments.
   * It serves as the reference point for calculating variant pricing,
   * discounts, and promotional offers.
   *
   * In the database schema, this value is stored in the
   * shopping_mall_product_variant_pricing table as the default price for
   * products with no variant-specific pricing overrides. The price is linked
   * to a specific product variant through the variant_id field.
   *
   * The price value must be non-negative and typically reflects market value,
   * cost of goods, and margin expectations.
   *
   * This field is essential for customer transparency and for backend systems
   * to calculate accurate final pricing with applied discounts.
   *
   * This value will be used in product listings, shopping carts, and checkout
   * processes to determine the starting price before additional
   * calculations.
   */
  basePrice: number & tags.Minimum<0>;

  /**
   * The ISO 4217 currency code that represents the primary currency of this
   * pricing information.
   *
   * This field specifies the currency context for the basePrice and all
   * related pricing fields.
   *
   * Common values include USD (US Dollar), EUR (Euro), GBP (British Pound),
   * JPY (Japanese Yen), etc.
   *
   * The currency code is validated against the ISO 4217 standard using a
   * 3-letter uppercase format.
   *
   * All monetary values in this pricing object are expressed in this
   * currency. For international customers, the platform may display converted
   * prices in their local currency, but this field indicates the original
   * pricing currency.
   *
   * This field is critical for accurate financial calculations, tax
   * computations, and currency conversion in payment processing.
   */
  currency: string & tags.Pattern<"^[A-Z]{3}$">;

  /**
   * The final effective price after applying any active discounts or
   * promotional offers to the base price.
   *
   * If no discounts are currently active for this product, this value will
   * equal the basePrice.
   *
   * When discount promotions are active, this field represents the reduced
   * price customers will pay. The discount amount is calculated as (basePrice
   * - discountedPrice).
   *
   * This field is used in product listings and shopping carts to show
   * customers the actual price they will pay.
   *
   * The discountPrice must be less than or equal to the basePrice to ensure
   * logical pricing.
   *
   * This field may be zero for free promotional items, but typically
   * represents a reduced price with a positive value.
   */
  discountedPrice?: (number & tags.Minimum<0>) | undefined;

  /**
   * The percentage discount applied to the base price, expressed as a decimal
   * between 0 and 100.
   *
   * This field indicates what percentage reduction has been applied to
   * convert the basePrice to the discountedPrice.
   *
   * When no active discount exists, this value should be 0.
   *
   * For example:
   *
   * - BasePrice: 100.00, discountedPrice: 80.00 → discountPercentage: 20
   * - BasePrice: 150.00, discountedPrice: 150.00 → discountPercentage: 0
   *
   * This representation allows for quick understanding of discount magnitude
   * without requiring manual calculation by client applications.
   *
   * The percentage must be between 0 and 100 to ensure it represents a valid
   * discount range (no negative discounts or discounts exceeding 100% of base
   * price).
   */
  discountPercentage?:
    | (number & tags.Minimum<0> & tags.Maximum<100>)
    | undefined;

  /**
   * Unique identifier of the product variant to which this pricing record is
   * associated.
   *
   * This field serves as the foreign key linking the pricing information in
   * the shopping_mall_product_variant_pricing table to the specific product
   * variant in the shopping_mall_product_variants table.
   *
   * Each pricing record corresponds to exactly one product variant,
   * identified by this variant_id. This relationship allows the system to
   * maintain variant-specific pricing while keeping the base product price
   * separate.
   *
   * When retrieving pricing information for a product, this field ensures
   * pricing is correctly mapped to the specific variant selected by the
   * customer.
   *
   * In the database, this field is indexed and used for efficient lookup of
   * variant-specific pricing during checkout and product display operations
   */
  variant_id?: (string & tags.Format<"uuid">) | undefined;
};
