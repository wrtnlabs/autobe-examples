import { tags } from "typia";

export namespace IShoppingMallSellerSalesAnalytics {
  /**
   * Summary view of seller sales analytics for the shopping mall platform.
   * This DTO represents aggregated performance metrics for sellers, providing
   * a comprehensive overview of their commercial activities on the platform.
   *
   * This schema serves as the response model for the GET
   * /shoppingMall/admin/analytics/sellers/sales endpoint, delivering key
   * performance indicators that help platform administrators monitor seller
   * health, performance trends, and revenue contribution.
   *
   * The analytics combine data from multiple system tables including
   * shopping_mall_orders, shopping_mall_order_items, shopping_mall_products,
   * and shopping_mall_product_reviews to provide a holistic view of each
   * seller's marketplace performance.
   *
   * Key business metrics include revenue, transaction volume, customer
   * engagement, product diversity, and customer satisfaction - all critical
   * for strategic decision-making in seller management and platform growth.
   */
  export type ISummary = {
    /**
     * Unique identifier of the seller whose sales analytics are being
     * reported.
     *
     * This field links the analytics record to the specific seller account
     * in the shopping_mall_sellers table. It is a UUID generated by the
     * system that uniquely identifies each seller across the platform.
     *
     * Used as the primary key for seller-specific analytics, enabling
     * precise aggregation of sales data and performance metrics for
     * individual sellers.
     *
     * This identifier is essential for seller-specific reporting, payment
     * reconciliation, and platform support activities where seller
     * identification is required.
     */
    seller_id: string & tags.Format<"uuid">;

    /**
     * Total revenue generated by the seller from all completed orders.
     *
     * Calculated by summing the product of quantity and price for all order
     * items across all completed orders associated with this seller.
     *
     * This metric represents the seller's total sales performance before
     * any deductions such as refunds or platform fees.
     *
     * Used for performance evaluation, revenue sharing calculations, and
     * financial reporting to sellers.
     *
     * This value is derived from the shopping_mall_order_items table,
     * aggregated by seller_id.
     *
     * Note: Only orders with status 'completed' are included in this
     * calculation to ensure financial accuracy.
     */
    total_sales_revenue: number & tags.Minimum<0>;

    /**
     * Number of completed orders placed by customers that include products
     * from this seller.
     *
     * Counts each order transaction where at least one product from this
     * seller was purchased and the order status has been marked as
     * 'completed'.
     *
     * This metric indicates the seller's transaction volume and customer
     * engagement level.
     *
     * Used to calculate average order value and assess seller's sales
     * frequency.
     *
     * Based on data from the shopping_mall_orders table, filtering for
     * completed orders and grouping by seller_id.
     */
    total_completed_orders: number & tags.Type<"int32"> & tags.Minimum<0>;

    /**
     * Average monetary value of each completed order containing this
     * seller's products.
     *
     * Calculated as total_sales_revenue divided by total_completed_orders.
     *
     * This metric helps assess the typical purchase size from customers who
     * buy from this seller, indicating customer spending behavior.
     *
     * A higher average order value may indicate effective product bundling,
     * premium product offerings, or strong customer loyalty.
     *
     * Used for seller performance benchmarking and identifying
     * opportunities to increase basket size.
     */
    average_order_value: number & tags.Minimum<0>;

    /**
     * Total quantity of all products sold by this seller across all
     * completed orders.
     *
     * Sum of the quantity field from all order items in the
     * shopping_mall_order_items table that are associated with this
     * seller's products.
     *
     * This metric measures the seller's output volume regardless of product
     * price or order structure.
     *
     * Used to assess sales volume, inventory needs, and fulfillment
     * capacity.
     *
     * Distinguishes between number of transactions (total_completed_orders)
     * and volume of goods moved (total_units_sold).
     */
    total_units_sold: number & tags.Type<"int32"> & tags.Minimum<0>;

    /**
     * Number of distinct products listed by this seller in the marketplace
     * catalog.
     *
     * Counts unique products from the shopping_mall_products table that are
     * linked to this seller.
     *
     * This metric reflects the seller's product offering breadth and
     * diversity within the platform.
     *
     * A large product count may indicate a comprehensive inventory
     * strategy, while a smaller count may suggest a focused niche
     * strategy.
     *
     * Used to evaluate product assortment and catalog completeness for
     * seller onboarding and category management.
     */
    product_count: number & tags.Type<"int32"> & tags.Minimum<0>;

    /**
     * Current average customer rating for products sold by this seller.
     *
     * Calculated as the mean of all product review ratings (1-5 scale) for
     * products from this seller.
     *
     * Based on data from the shopping_mall_product_reviews table, joined
     * with product-to-seller relationships.
     *
     * This metric represents the overall customer satisfaction with the
     * seller's product quality and consistency.
     *
     * Used for seller reputation building, customer trust indicators, and
     * platform ranking algorithms.
     */
    rating_average: number & tags.Minimum<0> & tags.Maximum<5>;

    /**
     * Total number of product reviews submitted by customers for this
     * seller's products.
     *
     * Counts all reviews from the shopping_mall_product_reviews table that
     * are associated with products belonging to this seller.
     *
     * This metric indicates the level of customer engagement and
     * participation in the seller's product ecosystem.
     *
     * A higher review count generally suggests higher product volume and
     * customer interaction.
     *
     * Used alongside rating_average to assess overall product reputation
     * and market reception.
     */
    review_count: number & tags.Type<"int32"> & tags.Minimum<0>;

    /**
     * Number of unique customers who have placed orders for products from
     * this seller.
     *
     * Counts distinct customer_id values from the shopping_mall_orders
     * table associated with this seller's products.
     *
     * This metric represents the seller's customer base size and reach
     * across the marketplace.
     *
     * Used to assess customer loyalty, market penetration, and potential
     * for repeat purchases.
     *
     * Distinguishes between transaction volume and customer acquisition.
     */
    customer_count: number & tags.Type<"int32"> & tags.Minimum<0>;

    /**
     * Date and time of the seller's first completed sale on the platform.
     *
     * Determines the initial transaction date when the seller's first order
     * status changed to 'completed'.
     *
     * This timestamp is used to calculate seller tenure and historical
     * performance trends.
     *
     * Used for onboarding anniversary celebrations, loyalty programs, and
     * tenure-based platform benefits.
     */
    first_sale_date: string & tags.Format<"date-time">;

    /**
     * Date and time of the seller's most recent completed sale on the
     * platform.
     *
     * The timestamp of the most recent order where at least one product
     * from this seller was purchased and the order status became
     * 'completed'.
     *
     * This metric indicates the seller's current activity level and
     * engagement on the platform.
     *
     * Used to identify inactive sellers requiring re-engagement campaigns
     * and to assess seller consistency.
     */
    last_sale_date: string & tags.Format<"date-time">;

    /**
     * Number of days between the seller's first sale and last sale on the
     * platform, expressed as a whole number of days.
     *
     * Calculated as (last_sale_date - first_sale_date) in days.
     *
     * This metric represents the seller's active engagement period on the
     * platform.
     *
     * Important for assessing seller retention, platform stickiness, and
     * long-term business viability.
     *
     * Used to identify sellers with consistent activity patterns versus
     * those with intermittent engagement.
     */
    active_duration_days: number & tags.Type<"int32"> & tags.Minimum<0>;
  };
}
