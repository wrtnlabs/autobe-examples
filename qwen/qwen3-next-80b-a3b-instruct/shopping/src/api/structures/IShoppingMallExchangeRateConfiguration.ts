/**
 * Configuration settings for currency exchange rates applied to transactions
 * within this payment region.
 *
 * This object defines how exchange rates are determined and applied for
 * multi-currency transactions in this region, including the pricing strategy,
 * rate update frequency, and rounding behavior.
 *
 * The exchange_rate_configuration determines how transactions in one currency
 * are converted to the target currency for settlement purposes. This affects
 * both customer pricing and merchant payout amounts.
 *
 * The configuration includes the source of exchange rates (live from an
 * external provider, fixed at a specific rate, or auto-calculated based on
 * historical averages), update frequency (real-time, daily, weekly), and
 * rounding rules for transaction amounts.
 *
 * This setting must be aligned with the regulatory environment of the region to
 * avoid price manipulation concerns or anti-trust issues. Some jurisdictions
 * have strict rules about how currency conversions can be presented to
 * customers.
 *
 * This configuration is critical for financial accuracy and can have
 * significant impact on revenue projections, tax liabilities, and accounting
 * entries. Changes to exchange rate configuration require approval from finance
 * and compliance teams.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type IShoppingMallExchangeRateConfiguration = {
  /**
   * Source of exchange rate data for transactions in this region.
   *
   * - "live": Uses real-time exchange rates from external financial data
   *   providers (e.g., ECB, Fixer.io)
   * - "fixed": Uses a static, administrator-defined exchange rate that remains
   *   constant
   * - "historical": Uses average exchange rates from historical transaction
   *   data over a specific period
   *
   * The source choice impacts transaction pricing accuracy, compliance
   * requirements, and system performance. Live sources provide maximum
   * accuracy but require external API connectivity. Fixed sources provide
   * consistency but may become outdated. Historical sources offer a balance
   * between accuracy and system resilience.
   *
   * This field is mandatory for all payment regions and must be explicitly
   * configured to avoid ambiguity in financial calculations.
   */
  source: "live" | "fixed" | "historical";

  /**
   * How often exchange rate values are refreshed in the system for this
   * payment region.
   *
   * - "realtime": Exchange rates are updated immediately when external data
   *   sources change
   * - "daily": Rates are refreshed once per day at a scheduled time (UTC)
   * - "weekly": Rates are refreshed once per week on a specific day
   * - "monthly": Rates are refreshed once per month on a specific date
   *
   * The update frequency must balance financial accuracy with system
   * performance and external API usage limits. Realtime updates provide the
   * most accurate pricing but have higher operational costs and dependency on
   * external services. Daily updates are sufficient for most regions and
   * provide a good balance between accuracy and cost. Weekly and monthly
   * updates are suitable for regions with stable currency relationships and
   * low transaction volumes.
   *
   * The update frequency determines when the system queries external data
   * sources and triggers cache invalidation for cached exchange rates.
   */
  update_frequency: "realtime" | "daily" | "weekly" | "monthly";

  /**
   * Mathematical method used to round currency amounts during exchange rate
   * conversions.
   *
   * - "round_half_up": Rounds to the nearest value, with .5 always rounding up
   *   (e.g., 2.5 → 3, 1.5 → 2)
   * - "floor": Always rounds down to the nearest value (e.g., 2.9 → 2, 1.1 → 1)
   * - "ceil": Always rounds up to the nearest value (e.g., 2.1 → 3, 1.9 → 2)
   * - "round_half_even": Rounds to the nearest even value when at the midpoint
   *   (also known as banker's rounding)
   *
   * The rounding method affects the financial outcome of transactions and
   * must be selected based on regulatory requirements and business policy.
   * "round_half_up" is the most common method and follows standard accounting
   * principles. "round_half_even" reduces cumulative rounding bias over many
   * transactions and is preferred in financial institutions.
   *
   * This setting applies to all currency conversions within the region and
   * impacts final prices displayed to customers and settlement amounts
   * received by merchants.
   */
  rounding_method: "round_half_up" | "floor" | "ceil" | "round_half_even";

  /**
   * The primary currency against which all other currencies are converted in
   * this payment region.
   *
   * This field must contain a valid ISO 4217 currency code (e.g., 'USD',
   * 'EUR', 'JPY', 'GBP'). All exchange rates are calculated relative to this
   * base currency.
   *
   * The base currency should typically be the currency of the primary market
   * or the most commonly used currency in transactions within the region. If
   * this region handles transactions for multiple markets, the base currency
   * should be one that has the highest transaction volume or is required by
   * regulatory authorities.
   *
   * This field cannot be changed after region creation and must be chosen
   * carefully during initial configuration. Changing the base currency would
   * require reprocessing all historical transactions and recalculating all
   * pricing.
   *
   * The system validates this field against the official ISO 4217 currency
   * list to ensure correctness.
   */
  base_currency: string;

  /**
   * The number of seconds the system waits before fetching new exchange rates
   * from the source, even when the update_frequency is set to 'realtime'.
   *
   * This field provides a rate-limiting mechanism for real-time exchange rate
   * updates and prevents excessive API calls to external data providers.
   *
   * - Minimum value: 1 second (most frequent updates)
   * - Maximum value: 3600 seconds (1 hour - maximum allowed)
   *
   * For "realtime" update_frequency, this value determines how quickly the
   * system can respond to market changes while avoiding rate limits. For
   * lower update frequencies (daily, weekly, monthly), this value is ignored
   * since rates are updated only at scheduled intervals.
   *
   * Smaller values provide more up-to-date pricing but increase API usage and
   * operational costs. Larger values reduce costs but may result in less
   * accurate pricing during volatile market conditions. The recommended value
   * is 300 seconds (5 minutes) for most regions.
   */
  rate_update_window: number &
    tags.Type<"int32"> &
    tags.Minimum<1> &
    tags.Maximum<3600>;

  /**
   * The maximum percentage difference allowed between the cached exchange
   * rate and the new rate from the source before the system considers it
   * significant enough to update.
   *
   * This field helps prevent minor fluctuations in exchange rates from being
   * applied as changes that could affect transaction outcomes unnecessarily.
   *
   * - Minimum value: 0.01% (very sensitive to change)
   * - Maximum value: 5.0% (only significant changes trigger updates)
   *
   * Rates are updated when the absolute difference between the new rate and
   * cached rate exceeds this threshold (as a percentage of the cached rate).
   * For example, if the threshold is 0.1% and a cached rate is 1.1500, a new
   * rate of 1.1490 or 1.1510 would not trigger an update, but a rate of
   * 1.1400 (0.87% difference) would trigger an update.
   *
   * This setting prevents transaction fluctuations due to market noise and
   * ensures stability in pricing for customers and merchants. The default
   * value should be adjusted based on currency volatility — more volatile
   * currencies require higher thresholds.
   */
  rate_accuracy_threshold: number & tags.Minimum<0.01> & tags.Maximum<5>;

  /**
   * Determines whether currency conversion is active and allowed in this
   * payment region.
   *
   * When false, all transactions must be conducted in the base currency
   * specified in base_currency. No conversions to other currencies will be
   * permitted, and the system will reject any attempts to transact in foreign
   * currencies.
   *
   * When true, the region supports multi-currency transactions according to
   * the configured exchange rate settings.
   *
   * This field provides a regulatory compliance control mechanism. Some
   * jurisdictions prohibit or restrict currency conversion entirely,
   * requiring all transactions to be settled in the local currency. This
   * setting allows administrators to disable conversion in such regions
   * without changing other configuration parameters.
   *
   * When disabled, the system redirects all transaction requests to use the
   * base currency automatically, providing a seamless experience for
   * customers while maintaining compliance.
   */
  conversion_enabled: boolean;

  /**
   * The fallback exchange rate value to be used when the configured exchange
   * rate source is unavailable, returns an error, or fails to provide data
   * within timeout limits.
   *
   * This field provides a fail-safe mechanism to ensure transactions can
   * continue during temporary service outages of external data providers.
   *
   * Must be a positive number between 0.0001 and 9999.9999 to ensure
   * reasonable exchange rate values.
   *
   * The fallback rate should be a conservative estimate based on recent
   * historical rates from a stable period. It should represent a rate that is
   * slightly less favorable than the long-term average to account for the
   * risk that the last known rate may have been favorable.
   *
   * This value is only used when the primary source is unreachable or
   * malfunctioning, and the system will automatically attempt to reconnect to
   * the primary source after a configured interval. Once the primary source
   * becomes available again, the system will resume using live rates.
   */
  fallback_rate: number & tags.Minimum<0.0001> & tags.Maximum<9999.9999>;

  /**
   * The minimum allowable exchange rate value for any currency conversion in
   * this region.
   *
   * This field acts as a safety mechanism to prevent extreme market
   * conditions and potential fraud from affecting financial outcomes.
   *
   * Any calculated exchange rate below this threshold will be replaced by
   * this minimum value before being applied to transactions.
   *
   * The value should be set conservatively based on historical minimums for
   * currencies in the region. For example, if normal ranges are between 0.05
   * and 1.50, the minimum might be set to 0.01 to allow for exceptional
   * market volatility but prevent catastrophic errors.
   *
   * This value provides a hard boundary that protects against negative
   * financial impact during extreme market conditions. If the system detects
   * rate drops below this value, it logs a security alert for review by the
   * risk team.
   */
  min_rate: number & tags.Minimum<0.0001> & tags.Maximum<9999.9999>;

  /**
   * The maximum allowable exchange rate value for any currency conversion in
   * this region.
   *
   * This field acts as a safety mechanism to prevent extreme market
   * conditions and potential fraud from affecting financial outcomes.
   *
   * Any calculated exchange rate above this threshold will be replaced by
   * this maximum value before being applied to transactions.
   *
   * The value should be set conservatively based on historical maximums for
   * currencies in the region. For example, if normal ranges are between 0.05
   * and 1.50, the maximum might be set to 3.00 to allow for exceptional
   * market volatility but prevent catastrophic errors.
   *
   * This value provides a hard boundary that protects against negative
   * financial impact during extreme market conditions. If the system detects
   * rate spikes above this value, it logs a security alert for review by the
   * risk team.
   */
  max_rate: number & tags.Minimum<0.0001> & tags.Maximum<9999.9999>;
};
