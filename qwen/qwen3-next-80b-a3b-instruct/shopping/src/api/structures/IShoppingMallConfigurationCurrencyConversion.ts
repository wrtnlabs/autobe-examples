import { tags } from "typia";

/**
 * Currency configuration settings that control international pricing and
 * transaction processing. These settings determine pricing display, settlement
 * currency, and supported payment currencies for global customers.
 *
 * This schema defines the currency conversion configuration for the
 * shoppingMall platform, controlling how prices are displayed, converted, and
 * settled across different currencies in international transactions.
 *
 * The currency conversion settings determine:
 *
 * - Which currencies are supported for display and transactions
 * - Default base currency for pricing calculations
 * - Exchange rate update frequency and source
 * - Currency formatting rules for different regions
 * - Whether dynamic exchange rates are enabled or fixed rates are used
 *
 * The configuration enables seamless international commerce by automatically
 * adapting pricing to the customer's regional currency while maintaining
 * consistent accounting in the platform's base currency. This is critical for
 * global e-commerce compliance, revenue reporting, and customer trust.
 *
 * Exchange rate sources can include: financial API providers (like Fixer.io or
 * Alpha Vantage), bank networks, or manual rate uploads by administrators. The
 * system allows for fallback mechanisms when rates are unavailable.
 *
 * This configuration is tightly linked to payment processing, as pricing must
 * be accurately converted at the time of transaction to ensure correct
 * settlement amounts. All currency conversion activity is logged for audit and
 * reconciliation purposes.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type IShoppingMallConfigurationCurrencyConversion = {
  /**
   * The primary currency used for accounting and backend financial reporting.
   *
   * This is the platform's base currency for internal financial calculations,
   * data aggregation, and reporting purposes. All transaction amounts are
   * ultimately converted to and stored in this currency.
   *
   * Common values: "USD", "EUR", "GBP", "JPY",
   *
   * The base currency determines the default pricing in administrative
   * interfaces and is used as the denomination for exchange rate
   * calculations. All other currencies are referenced as conversions from
   * this base currency.
   *
   * The value must be a valid 3-letter ISO 4217 currency code.
   */
  baseCurrency?: string | undefined;

  /**
   * List of currencies in which products can be displayed to customers and
   * transactions processed.
   *
   * This array defines all currencies that the platform supports for
   * customer-facing operations, including price display, checkout, and
   * payment processing.
   *
   * The platform will advertise prices in all currencies listed here, and the
   * payment system will accept payments in these currencies.
   *
   * Each value must be a valid 3-letter ISO 4217 currency code.
   *
   * Example: ["USD", "EUR", "GBP", "JPY", "CAD", "AUD", "CNY"]
   *
   * Only currencies in this list can be used for customer transactions, even
   * if exchange rates exist for other currencies.
   *
   * Empty array means only the base currency is supported in customer
   * interfaces.
   */
  supportedCurrencies?: (string[] & tags.UniqueItems) | undefined;

  /**
   * The external service or mechanism used to obtain real-time currency
   * exchange rates.
   *
   * This setting determines how the platform obtains current exchange rates
   * for currency conversions.
   *
   * Valid values: "fixer" (Fixer.io API), "openexchangerates", "centralbank",
   * "manual" (admin-uploaded rates), "none" (fixed rates only)
   *
   * - "fixer": Use Fixer.io API for up-to-date exchange rates
   * - "openexchangerates": Use Open Exchange Rates API
   * - "centralbank": Use official central bank rates
   * - "manual": Use administratively uploaded rates
   * - "none": Use static fixed rates configured manually in the system
   *
   * Default: "fixer"
   *
   * Selection impacts accuracy, cost, and reliability of exchange rates used
   * in customer transactions.
   */
  exchangeRateSource?:
    | "fixer"
    | "openexchangerates"
    | "centralbank"
    | "manual"
    | "none"
    | undefined;

  /**
   * Determines whether exchange rates are updated automatically or kept
   * fixed.
   *
   * When true: The platform continuously fetches live exchange rates from the
   * configured source (exchangeRateSource) to ensure accurate pricing and
   * settlement.
   *
   * When false: The platform uses fixed exchange rates that must be manually
   * updated by administrators. This provides predictable pricing and avoids
   * unexpected fluctuations that might affect customer trust.
   *
   * This setting cannot be true when exchangeRateSource is "none".
   *
   * Default: true
   *
   * Real-time rate updating provides more accurate pricing but requires API
   * access and may have associated costs. Fixed rates are more predictable
   * and cost-effective but require manual maintenance.
   */
  enableDynamicRates?: boolean | undefined;

  /**
   * How often (in minutes) the platform refreshes currency exchange rates
   * from its source.
   *
   * The platform will automatically fetch updated exchange rates from the
   * configured source (exchangeRateSource) at this interval.
   *
   * Acceptable values: 15-1440 minutes (15 minutes to 24 hours)
   *
   * Recommendations:
   *
   * - 15-60 minutes: High-frequency trading, volatile currencies
   * - 60-360 minutes: Standard e-commerce operations
   * - 720-1440 minutes: Stable currency pairs, lower update costs
   *
   * Minimum: 15 minutes (to prevent API rate limiting) Maximum: 1440 minutes
   * (24 hours) to ensure reasonable freshness
   *
   * When enableDynamicRates is false, this setting has no effect.
   */
  rateUpdateFrequency?:
    | (number &
        tags.Type<"int32"> &
        tags.Default<180> &
        tags.Minimum<15> &
        tags.Maximum<1440>)
    | undefined;

  /**
   * The default currency to display to customers who have not selected a
   * preferred currency or whose location cannot be geolocated.
   *
   * This currency will be used to display prices to customers who arrive at
   * the platform without a selected currency preference or whose location
   * cannot be determined automatically.
   *
   * Must be one of the currencies listed in supportedCurrencies.
   *
   * Default: "USD"
   *
   * Example: If a customer from Germany visits the site and their locale
   * cannot be detected, prices will be shown in EUR if defaultDisplayCurrency
   * is set to "EUR".
   *
   * The value must be a valid 3-letter ISO 4217 currency code.
   */
  defaultDisplayCurrency?: (string & tags.Default<"USD">) | undefined;

  /**
   * The default format for displaying currency values to customers.
   *
   * This controls how values are visually presented to users, handling
   * currency symbol placement, decimal separators, digit grouping, and sign
   * positioning.
   *
   * Valid values:
   *
   * - "symbol_prefix": Currency symbol before amount (e.g., $100)
   * - "symbol_suffix": Currency symbol after amount (e.g., 100€)
   * - "code_prefix": Currency code before amount (e.g., USD 100)
   * - "code_suffix": Currency code after amount (e.g., 100 USD)
   *
   * Note: This determines display format only; data storage remains in
   * numeric format.
   *
   * Default: "symbol_prefix"
   *
   * This setting can be overriden by locale preferences when supported.
   */
  currencyDisplayFormat?:
    | "symbol_prefix"
    | "symbol_suffix"
    | "code_prefix"
    | "code_suffix"
    | undefined;

  /**
   * Enables automatic rounding of prices to standard currency denominations.
   *
   * When true: Final prices after conversion are rounded to the smallest
   * currency denomination (subunit) for the target currency.
   *
   * For example:
   *
   * - USD: Round to nearest cent (0.01)
   * - JPY: Round to nearest yen (1)
   * - EUR: Round to nearest cent (0.01)
   *
   * When false: Exact conversion results are preserved (e.g., $10.12345)
   *
   * Rounding is a practice requirement for most financial systems to avoid
   * fractions of currency units.
   *
   * Default: true
   */
  enableRounding?: boolean | undefined;

  /**
   * Number of days to retain historical exchange rate data for audit and
   * reconciliation purposes.
   *
   * The platform will store historical exchange rate values for this many
   * days to allow for:
   *
   * - Financial reconciliation of past transactions
   * - Audit trail for compliance
   * - Price history analysis
   * - Dispute resolution
   *
   * Minimum: 7 days (required for basic audit requirements) Maximum: 365 days
   * (yearly retention for compliance)
   *
   * Default: 90 days
   *
   * This setting affects data storage requirements and should be balanced
   * between compliance needs and storage costs.
   */
  exchangeRateHistoryDays?:
    | (number &
        tags.Type<"int32"> &
        tags.Default<90> &
        tags.Minimum<7> &
        tags.Maximum<365>)
    | undefined;
};
