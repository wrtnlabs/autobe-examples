import { tags } from "typia";

import { IAuthorizationToken } from "./IAuthorizationToken";

export namespace IShoppingMallAdmin {
  /**
   * Authentication response containing access and refresh JWT tokens and the authenticated admin's ID. Used to maintain session state across subsequent API requests. The access token is sent in the Authorization header for protected endpoints. The refresh token is used to obtain new access tokens without requiring re-login.
   */
  export type IAuthorized = {
    /**
     * Short-lived access token used for authenticating subsequent API requests. Must be included in the Authorization header as 'Bearer {access_token}'.
     *
     * @x-autobe-specification Generated by JWT signing service upon successful authentication. Expires after 30 minutes.
     */
    access_token: string;

    /**
     * Long-lived refresh token used to obtain new access tokens without requiring re-authentication. Must be securely stored and only transmitted to the /refresh endpoint.
     *
     * @x-autobe-specification Generated upon authentication and stored in shopping_mall_admin_sessions table. Expires after 30 days.
     */
    refresh_token: string;

    /**
     * Unique identifier of the authenticated administrator. Used to authorize administrative operations and associate session activity with the correct user.
     *
     * @x-autobe-specification Derived from the id field of the authenticated shopping_mall_admins record during token generation.
     */
    admin_id: string & tags.Format<"uuid">;

    /**
     * Authorization token.
     *
     * @x-autobe-specification Authorization token comes from the session table.
     */
    token: IAuthorizationToken;
  };

  /**
   * Request payload for authenticating a system administrator. Contains the email address and plaintext password used to verify identity against the admin account in the database.
   */
  export type ILogin = {
    /**
     * The registered email address of the administrator account to authenticate.
     *
     * @x-autobe-database-schema-property email
     * @x-autobe-specification Direct mapping from shopping_mall_admins.email. Must be a valid email address registered in the system.
     */
    email: string;

    /**
     * The plaintext password of the administrator account. Sent over HTTPS and hashed server-side for authentication.
     *
     * @x-autobe-database-schema-property password_hash
     * @x-autobe-specification Direct mapping to shopping_mall_admins.password_hash. Client sends plaintext password over HTTPS; server performs bcrypt comparison.
     */
    password: string;
  };

  /**
   * Request payload for registering a new system administrator. Must include a valid email address and a secure password meeting minimum length requirements. Used exclusively for initial account creation and not for subsequent authentication.
   */
  export type IJoin = {
    /**
     * Email address used to identify and register the administrator account.
     *
     * @x-autobe-specification Raw email input from client. Must be valid RFC 5322 email format. Will be checked for uniqueness against shopping_mall_admins.email.
     */
    email: string & tags.Format<"email">;

    /**
     * Secure password for administrator authentication. Minimum 8 characters required. Never stored in plaintext — hashed immediately after receipt.
     *
     * @x-autobe-specification Plain-text password provided by user. Must be at least 8 characters long. Will be hashed using bcrypt before storage in shopping_mall_admins.password_hash.
     */
    password: string & tags.MinLength<8>;
  };

  /**
   * Request body containing only the refresh token used to obtain a new access token from the server. Must be a valid, unexpired token previously issued by the system.
   */
  export type IRefresh = {
    /**
     * The refresh token issued during login, used to securely renew the access token without requiring re-authentication.
     *
     * @x-autobe-specification The refresh_token provided by the client is matched against the refresh_token field in the shopping_mall_admin_sessions table for validation. It is used to identify the admin_id and validate the session. Must not be a revoked or expired token.
     */
    refresh_token: string;
  };

  /**
   * Platform-wide statistical summary for administrators. Contains total counts of customers, sellers, products, orders, pending seller approvals, pending cancellation requests, and pending refund requests. This dashboard provides a real-time snapshot of platform health without exposing sensitive user data or historical details.
   */
  export type ISummary = {
    /**
     * Total number of active customer accounts registered on the platform.
     *
     * @x-autobe-specification COUNT of entries in shopping_mall_customers WHERE deleted_at IS NULL.
     */
    total_customers: number & tags.Type<"int32">;

    /**
     * Total number of seller accounts that have been approved and are active on the platform.
     *
     * @x-autobe-specification COUNT of entries in shopping_mall_sellers WHERE status = 'approved' AND deleted_at IS NULL.
     */
    total_sellers: number & tags.Type<"int32">;

    /**
     * Total number of products currently listed and active on the platform.
     *
     * @x-autobe-specification COUNT of entries in shopping_mall_products WHERE is_active = true AND deleted_at IS NULL.
     */
    total_products: number & tags.Type<"int32">;

    /**
     * Total number of orders created across all customers on the platform.
     *
     * @x-autobe-specification COUNT of entries in shopping_mall_orders WHERE deleted_at IS NULL.
     */
    total_orders: number & tags.Type<"int32">;

    /**
     * Number of seller registration requests awaiting administrator approval.
     *
     * @x-autobe-specification COUNT of entries in shopping_mall_sellers WHERE status = 'pending'.
     */
    pending_seller_approvals: number & tags.Type<"int32">;

    /**
     * Total number of cancellation requests initiated by customers that are still pending seller or admin response.
     *
     * @x-autobe-specification COUNT of entries in shopping_mall_cancellation_requests WHERE status = 'pending'.
     */
    pending_cancellation_requests: number & tags.Type<"int32">;

    /**
     * Total number of refund requests initiated by customers that are still pending seller or admin response.
     *
     * @x-autobe-specification COUNT of entries in shopping_mall_refund_requests WHERE status = 'pending'.
     */
    pending_refund_requests: number & tags.Type<"int32">;
  };
}
