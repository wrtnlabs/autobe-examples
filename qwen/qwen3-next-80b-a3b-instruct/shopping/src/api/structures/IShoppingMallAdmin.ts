import { tags } from "typia";

import { IAuthorizationToken } from "./IAuthorizationToken";

export namespace IShoppingMallAdmin {
  /**
   * Request payload for creating a new admin account with email and
   * password_hash fields.
   */
  export type ICreate = {
    /**
     * Admin's unique email address used for authentication and
     * communication. Must be unique across all admins.
     */
    email: string & tags.Format<"email">;

    /**
     * Admin's password (plain text). This value is hashed server-side and
     * compared against the stored password_hash field in the
     * shopping_mall_admins table for authentication. Clients must never
     * send pre-hashed passwords - hashing is performed by the backend.
     */
    password: string;
  };

  /**
   * Response type for successful admin authentication operations (login and
   * refresh). Contains the authenticated admin's unique ID and an
   * authentication token that enables access to protected resources. This
   * schema includes only minimal identifying information and the token,
   * excluding sensitive fields like passwords, session IDs, or administrative
   * permissions detail. The id corresponds to the admin's primary key in the
   * shopping_mall_admins table, but this schema represents the token-based
   * authentication response, not a direct replication of the admin table.
   */
  export type IAuthorized = {
    /**
     * Unique identifier of the authenticated admin user. This value is
     * obtained from the admin record in the shopping_mall_admins table and
     * is derived from the authentication context (JWT token). This
     * corresponds to the admin.id primary key in the shopping_mall_admins
     * table, though this schema does not contain fields from that table
     * directly.
     */
    id: string & tags.Format<"uuid">;

    /** JWT token information for authentication */
    token: IAuthorizationToken;
  };

  /**
   * Request payload for authenticating a shopping mall admin via email and
   * password. This type is used in the POST /auth/admin/login operation. The
   * password field represents the plain text password provided by the client,
   * which the backend will hash and verify against the password_hash field in
   * the shopping_mall_admins table. This schema excludes the admin ID and
   * session identifiers, as these are derived from the authentication
   * context. The email must be a valid email format per RFC 5322.
   */
  export type ILogin = {
    /**
     * Admin's unique email address used for authentication and
     * communication. Must be unique across all admins.
     */
    email: string & tags.Format<"email">;

    /**
     * Admin's password (plain text). This value is hashed server-side and
     * compared against the stored password_hash field in the
     * shopping_mall_admins table for authentication. Clients must never
     * send pre-hashed passwords - hashing is performed by the backend.
     */
    password: string;
  };

  /**
   * Request payload for refreshing an admin's access token. This type is used
   * in the POST /auth/admin/refresh operation. The refresh token must have
   * been previously issued and must still be valid (not expired or revoked).
   * The refresh token is tied to an admin account and is validated against
   * server-stored session records, not directly against the
   * shopping_mall_admins table. This schema does not include any fields from
   * the shopping_mall_admins table as the operation relies on token
   * validation, not credential verification. The token value must be a
   * UUID-format string as generated by the authentication system.
   */
  export type IRefresh = {
    /**
     * A valid refresh token issued during the original admin login or a
     * subsequent refresh operation. This token is used to obtain a new
     * access token without requiring re-authentication with the admin's
     * email and password. This token is validated against server-stored
     * session records and must be in UUID format as generated by the
     * authentication system.
     */
    refreshToken: string & tags.Format<"uuid">;
  };
}
