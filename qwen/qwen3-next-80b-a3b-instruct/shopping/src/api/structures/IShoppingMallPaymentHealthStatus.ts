  /**
   * Status of payment reconciliation between system records and gateway
   * settlements.
   *
   * Compares internal payment records with settlement reports received from
   * payment processors via shopping_mall_payment_reconciliation. This ensures
   * accurate financial accounting.
   *
   * - Balanced: All payment records match with gateway settlements with zero
   *   discrepancies.
   * - Minor-discrepancy: Small discrepancies exist (typically 0.1-2% of
   *   transaction volume) that may be due to processing delays or fee
   *   differences.
   * - Major-discrepancy: Significant discrepancies exist (>2% of transaction
   *   volume) indicating potential system errors or fraudulent activity
   *   requiring immediate investigation.
   */
