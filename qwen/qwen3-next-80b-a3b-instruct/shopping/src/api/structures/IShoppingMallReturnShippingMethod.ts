/**
 * Shipping method configuration for return delivery in the shopping mall
 * system. Defines the carrier service, delivery options, and handling
 * requirements for returning purchased items. This schema ensures consistent
 * return shipping configuration across customer, seller, and admin interfaces,
 * enabling automated return logistics processing and accurate delivery
 * tracking.
 *
 * The return shipping method is selected during return initiation and
 * determines the carrier, service level, return shipping cost responsibility,
 * and tracking protocol. It maps to the system's predefined return shipping
 * options configured in the shopping_mall_shipping_methods table.
 *
 * Key business rules:
 *
 * - Each option corresponds to a specific shipping carrier and service level
 * - Determines who pays for return shipping: customer or platform
 * - Affects return processing time and delivery expectations
 * - Required for all return requests to enable automatic shipping label
 *   generation
 *
 * Used in:
 *
 * - IShoppingMallOrderReturn (as returnShippingMethod property)
 * - POST /orders/{orderCode}/returns (request)
 * - GET /orders/{orderCode}/returns/{returnCode} (response)
 * - PUT /orders/{orderCode}/returns/{returnCode} (response)
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type IShoppingMallReturnShippingMethod = {
  /**
   * The carrier or logistics company handling the return shipment. This
   * corresponds to one of the predefined carriers configured in the
   * shopping_mall_carriers table. The value must exactly match one of the
   * registered carrier names in the system (e.g., "FedEx", "UPS", "DHL",
   * "USPS", "Postal Service").
   */
  carrier: "FedEx" | "UPS" | "DHL" | "USPS" | "Postal Service";

  /**
   * The specific service level option for the return shipping, defining
   * speed, cost, and handling characteristics. This corresponds to defined
   * service levels in the shopping_mall_shipping_methods table. Must be one
   * of the valid service level values configured for the selected carrier.
   * Common values include: "standard" (3-7 business days), "expedited" (2-3
   * business days), or "overnight" (1 business day). Only service levels
   * explicitly configured for return shipments are permitted.
   */
  service_level: "standard" | "expedited" | "overnight";

  /**
   * Determines which party is responsible for paying the return shipping
   * costs. This is a business rule that depends on the return reason and
   * platform policy. If customer is selected, the customer pays. If platform
   * is selected, the platform provides a prepaid return label.
   */
  cost_coverage: "customer" | "platform";

  /**
   * Indicates whether a physical return shipping label is required for this
   * return method. When true, the system will generate and provide a
   * printable return label for the customer to attach to the return package.
   * When false, the customer may only need to use a different return method
   * (e.g., drop off at a retailer location). By default, this should be true
   * for most carrier-based return shipping methods.
   */
  return_label_required: boolean;

  /**
   * The number of days from the original order delivery date within which
   * this return shipping method remains valid. This enforces return policy
   * compliance and ensures returns fall within the approved return window.
   * Valid values range from 1 to 90 days. This value should match the return
   * window configured in the system's return accounting policy (typically 30
   * days).
   */
  return_window_days: number &
    tags.Type<"int32"> &
    tags.Minimum<1> &
    tags.Maximum<90>;

  /**
   * Specifies whether tracking information will be provided and integrated
   * into the platform's order tracking system. When true, the system will
   * automatically import tracking updates from the carrier and update the
   * return status. When false, the customer will need to manually provide
   * tracking updates. All carrier-based methods should have tracking
   * enabled.
   */
  tracking_enabled: boolean;

  /**
   * The preferred format for generating the return shipping label. This
   * defines the preferred output format for the printable label that will be
   * provided to the customer. Must be one of the supported label formats
   * configured in the system, typically "PDF" for printable labels or "ZPL"
   * for thermal printer labels. PDF is standard for customer-facing labels
   * that can be printed on standard paper.
   */
  label_format: "PDF" | "ZPL";
};
