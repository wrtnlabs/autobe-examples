import { tags } from "typia";

/**
 * Comprehensive product performance summary containing aggregated sales and
 * view statistics across the product catalog.
 *
 * This schema represents the response structure for the administrative
 * dashboard product overview endpoint, providing administrators with a holistic
 * view of product performance across the entire e-commerce platform.
 *
 * The data combines metrics from shopping_mall_product_sales_stats (sales
 * performance), shopping_mall_product_view_stats (customer engagement),
 * shopping_mall_product_reviews (customer feedback),
 * shopping_mall_order_returns (return behavior), and
 * shopping_mall_cart_sessions (checkout behavior) to create a unified
 * performance dashboard.
 *
 * All metrics are calculated from recent aggregated statistics to ensure timely
 * insights for decision-making. The data refreshes continuously as new sales,
 * views, and customer interactions occur.
 *
 * Key considerations:
 *
 * - All monetary values are in the platform's primary currency (USD in this
 *   implementation)
 * - Conversion rates and percentages are expressed as decimal fractions between 0
 *   and 1
 * - Timestamp-based metrics use the current reporting period as defined by the
 *   system's analytics engine
 * - Product identifiers use UUID format for universal uniqueness across
 *   distributed systems
 * - Inventory thresholds may vary by product category based on seasonal factors
 *   and lead times
 *
 * This comprehensive overview enables administrators to identify top-performing
 * products, detect underperforming categories, optimize inventory levels,
 * evaluate marketing effectiveness, and make data-driven decisions to maximize
 * marketplace profitability.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type IShoppingMallProductOverview = {
  /**
   * Total revenue generated from all product sales.
   *
   * Represents the sum of all completed order payments for products in USD,
   * calculated during the current reporting period. This metric reflects the
   * overall financial performance of the product catalog.
   *
   * Calculated by aggregating the total_amount from all completed
   * shopping_mall_order_payments records associated with products.
   *
   * This total includes all sales across all channels and seller accounts,
   * providing a comprehensive view of overall marketplace revenue.
   */
  total_sales: number & tags.Minimum<0>;

  /**
   * Average conversion rate across all products, expressed as a decimal
   * fraction (0-1).
   *
   * Calculated as the ratio of total sales to total views across all
   * products: (total_sales / total_views).
   *
   * This metric represents the average effectiveness of product listings in
   * converting visitors into buyers. A higher conversion rate indicates more
   * effective product presentation, pricing, and description quality.
   *
   * Values are calculated using aggregated statistics from both
   * shopping_mall_product_sales_stats and shopping_mall_product_view_stats
   * tables to ensure accurate correlation between product views and sales
   * outcomes.
   */
  average_conversion_rate: number & tags.Minimum<0> & tags.Maximum<1>;

  /**
   * Unique identifier of the product with the highest sales volume.
   *
   * Identifies the single product that has generated the most revenue in the
   * current reporting period.
   *
   * This field is populated by querying the shopping_mall_product_sales_stats
   * table and ordering by total_sales_amount in descending order, then taking
   * the top result.
   *
   * Used by administrators to identify top-performing products for promotion
   * and inventory prioritization.
   */
  top_selling_product_id: string & tags.Format<"uuid">;

  /**
   * Total sales revenue generated by the top-selling product.
   *
   * Represents the total revenue generated by the single product with the
   * highest sales volume in the current reporting period, in USD.
   *
   * This value corresponds to the total_sales_amount field in the
   * shopping_mall_product_sales_stats table for the product identified in
   * top_selling_product_id.
   *
   * This metric highlights product-level performance and helps administrators
   * identify breakout products that may benefit from increased marketing
   * investment.
   */
  top_selling_product_sales: number & tags.Minimum<0>;
};
