/**
 * Shopping cart session entity representing a customer's active collection of
 * products for purchase. This session tracks the state of products a user
 * intends to buy, including quantities, pricing at time of addition, and
 * timestamps. The cart session serves as the primary container for cart items,
 * which are stored separately in shopping_mall_cart_items table linked via
 * cart_session_id.
 *
 * The cart session is created when a user begins shopping (either as
 * authenticated customer or guest) and persists until explicitly cleared,
 * expired by inactivity (30 days), or merged with an authenticated account upon
 * login.
 *
 * This schema represents the complete cart session state returned in responses
 * to GET /cart-sessions/{sessionId} and PATCH /cart-sessions, and is created in
 * responses to POST /cart-sessions. It includes all relevant metadata and
 * aggregated summary information necessary for the shopping experience.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type IShoppingMallCartSession = {
  /**
   * Unique identifier for the shopping cart session, corresponding to the
   * cart_session_id field in the shopping_mall_cart_sessions database table.
   */
  id: string & tags.Format<"uuid">;

  /**
   * Identifier of the customer associated with this cart session, linking to
   * the customer_id in the shopping_mall_customers table. This field is null
   * for guest users who have not yet logged in.
   */
  customer_id?: (string & tags.Format<"uuid">) | undefined;

  /**
   * Timestamp indicating when the cart session was initially created,
   * matching the created_at field in the shopping_mall_cart_sessions database
   * table.
   */
  created_at: string & tags.Format<"date-time">;

  /**
   * Total number of cart items contained in this session, calculated from the
   * shopping_mall_cart_items table entries linked by this cart_session_id.
   */
  item_count: number & tags.Type<"int32"> & tags.Minimum<0>;

  /**
   * Sum of all cart item prices (quantity * unit price) in the cart session,
   * calculated from shopping_mall_cart_items with pricing captured at time of
   * addition.
   */
  total_price: number & tags.Minimum<0>;

  /**
   * Indicates whether this cart session belongs to an unauthenticated guest
   * user (true) or an authenticated customer (false). Used to determine
   * session eligibility for merge and persistence rules.
   */
  guest_session: boolean;

  /**
   * Timestamp when this cart session will expire by inactivity (30-day
   * default). If null, the session has been merged with an authenticated
   * account or has been manually cleared.
   */
  expires_at: string & tags.Format<"date-time">;

  /**
   * Current state of the cart session. 'active' indicates session is in
   * normal use, 'expired' means inactivity threshold reached, 'merged'
   * indicates authentication caused session merge, 'cleared' means user
   * explicitly emptied cart.
   */
  session_status: "active" | "expired" | "merged" | "cleared";
};
