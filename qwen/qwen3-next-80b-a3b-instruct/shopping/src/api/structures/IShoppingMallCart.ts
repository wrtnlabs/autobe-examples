/**
 * Complete shopping cart entity representing a customer's collection of
 * products for purchase. This schema defines the full cart structure returned
 * in GET /shoppingMall/customer/carts/{cartId} and used in merge operations.
 * The cart contains metadata about the session, references to the customer, and
 * a complete list of cart items with their product variant details.
 *
 * This object represents the complete state of a shopping cart at a given
 * moment, capturing all items a customer has selected for potential purchase.
 * The cart serves as a temporary holding area before order placement and
 * supports persistence across sessions for both authenticated and guest users.
 *
 * The cart's data is directly derived from the shopping_mall_carts and
 * shopping_mall_cart_items tables in the database. This response DTO transforms
 * foreign key relationships into full detail objects following the relation
 * strategy: customer_id becomes customer (ISummary), and cart_items becomes an
 * array of IShoppingMallCartItem objects.
 *
 * Performance considerations: This schema enables single API call retrieval of
 * complete cart context, eliminating N+1 query problems. Related entities like
 * product variants and customer details are embedded to provide a
 * self-contained representation for the frontend interface.
 *
 * Security: The cart is always associated with the authenticated customer via
 * JWT token. Customer identity fields (customer_id) are transformed to customer
 * object and not exposed as raw IDs. No actor identity fields appear in the
 * request body as they're handled by the authentication system.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type IShoppingMallCart = {
  /**
   * Unique identifier for the shopping cart. Generated as a UUID by the
   * system and stored in the shopping_mall_carts table. This is the primary
   * key for cart lookup and reference in related tables like
   * shopping_mall_cart_items.
   */
  id: string & tags.Format<"uuid">;

  /**
   * Timestamp when the cart was initially created. This represents the moment
   * when the cart was first initialized in the shopping_mall_carts table. The
   * field is auto-populated by the database when a new cart record is
   * inserted.
   */
  createdAt: string & tags.Format<"date-time">;

  /**
   * Timestamp when the cart was last modified. This field is automatically
   * updated by the system whenever cart items are added, removed, or
   * quantities are changed in the shopping_mall_cart_items table.
   */
  updatedAt: string & tags.Format<"date-time">;

  /**
   * Current state of the cart. Can be 'active' (normal state), 'pending' (if
   * created during guest session and customer not yet registered), 'expired'
   * (after 30 days of inactivity), or 'merged' (if its items were combined
   * with another cart). This corresponds to the status column in the
   * shopping_mall_carts table.
   */
  status: "active" | "pending" | "expired" | "merged";

  /**
   * Collection of all product items currently in the shopping cart. Each item
   * represents a specific product variant with its quantity, price, and other
   * details as they were recorded at the time of addition to the cart.
   *
   * This is a composition relation following the database's one-to-many
   * relationship between shopping_mall_carts and shopping_mall_cart_items.
   *
   * To prevent circular references, cart item objects in this array are
   * represented using their base type (IShoppingMallCartItem) rather than a
   * summary type, as they are integral components of the cart context and
   * should have full detail visibility.
   *
   * Use of $ref ensures type reusability and prevents inline object
   * definitions, adhering to API design principles for maintainability.
   */
  items: IShoppingMallCartItem[];

  /**
   * Total number of distinct product items in this cart. This is the count of
   * cart item entries, not the sum of quantities. For example, if a cart
   * contains two units of the same product variant, it counts as 1 item here,
   * but contributes 2 to the totalQuantity field.
   *
   * This field provides a quick metric for UI display of cart item count
   * without requiring clients to iterate through the items array.
   */
  totalItems: number & tags.Type<"int32">;

  /**
   * Total number of product units across all cart items. This is the sum of
   * quantity values for each IShoppingMallCartItem in the items array.
   *
   * For example, if the cart contains 2 units of Product A and 3 units of
   * Product B, totalQuantity will be 5. This field enables cart summary
   * display showing "5 items" for the customer.
   */
  totalQuantity: number & tags.Type<"int32">;

  /**
   * Total monetary value of all items in the cart, calculated as the sum of
   * (unit_price * quantity) for each IShoppingMallCartItem in the items
   * array.
   *
   * This value reflects the current pricing at the time of cart retrieval,
   * with currency stored in USD. Prices reflect any promotions or discounts
   * that were active when the items were added to the cart, ensuring price
   * stability for the customer.
   *
   * The total is calculated server-side to ensure accuracy and prevent
   * manipulation by clients.
   */
  totalPrice: number & tags.Minimum<0>;

  /**
   * Summary information about the customer who owns this cart.
   *
   * This is an association relation where customer_id in the database is
   * transformed to a full customer summary object to provide context.
   *
   * Used to display customer name and account details to the user. The
   * reference prevents circular references by using ISummary. Since this is a
   * BELONGS-TO relationship (the cart belongs to the customer), the .ISummary
   * type is used to limit depth and avoid infinite recursion when cart is
   * included in other contexts.
   *
   * The customer summary includes essential information: id, name, email, and
   * avatar_url for display purposes. Full customer details are not included
   * to minimize payload size and maintain separation of concerns.
   *
   * This is a one-to-one relationship: each cart belongs to exactly one
   * customer, and each customer has at most one active cart.
   */
  customer: IShoppingMallCustomer.ISummary;
};
