import { tags } from "typia";

import { IShoppingMallProductVariantAvailability } from "./IShoppingMallProductVariantAvailability";

/**
 * Product availability status information returned by the PATCH
 * /shoppingMall/products/{productId}/availabilities endpoint.
 *
 * This schema represents the real-time inventory situation for a product,
 * combining overall product-level availability with detailed per-variant
 * availability data. The response is designed to provide customers with
 * accurate, granular stock information right before purchase decisions are
 * made.
 *
 * The availability data is computed in real-time from the
 * shopping_mall_variant_availability table, which is continuously updated by
 * inventory management processes triggered by order fulfillment, returns, and
 * restocking activities. No caching layers are involved that could cause
 * display discrepancies.
 *
 * This schema follows the compound object pattern where the primary object
 * represents the product-level summary status and the nested array provides
 * detailed variant-level information. This allows the client to display summary
 * information efficiently while providing detailed choice options when needed.
 *
 * All status values are constrained to predefined enum values to ensure
 * contract consistency across client implementations and prevent data integrity
 * issues. The schema is designed to be consumed directly by product detail
 * pages, shopping cart logic, and checkout workflows.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type IShoppingMallProductAvailability = {
  /**
   * Unique identifier of the product for which availability status is being
   * queried. This identifier corresponds to the primary key in the
   * shopping_mall_products table.
   */
  productId: string & tags.Format<"uuid">;

  /**
   * Overall availability status of the product across all variants. Reflects
   * the aggregated inventory status based on real-time stock levels and
   * fulfillment capacity.
   *
   * - Available: Sufficient stock is available for immediate fulfillment
   * - Low_stock: Inventory is below threshold but still available for purchase
   * - Out_of_stock: No inventory available and not accepting pre-orders
   * - Backorder: Currently out of stock but accepting new orders for future
   *   fulfillment
   * - Pre_order: Available only as pre-order with future delivery date
   *
   * This status is computed from variant-level inventory data and updated
   * continuously through inventory management processes.
   */
  status:
    | "available"
    | "low_stock"
    | "out_of_stock"
    | "backorder"
    | "pre_order";

  /**
   * Total available quantity for immediate purchase across all variants.
   * Represents the sum of stock levels that are genuinely available for
   * purchase (excludes reserved, pre-ordered, or backordered quantities).
   *
   * This value is updated in real-time as orders are placed and inventory is
   * restocked. It reflects only the physical inventory available in
   * warehouses, excluding any allocated or reserved stock.
   */
  availableQuantity: number & tags.Type<"int32"> & tags.Minimum<0>;

  /**
   * Detailed availability information for each individual product variant.
   * Each variant represents a unique combination of product attributes such
   * as color, size, material, or configuration.
   *
   * Variant-level availability is critical for ensuring customers can
   * accurately select their desired product configuration and understand
   * real-time inventory status. All variants of the same product may have
   * different availability statuses based on their specific inventory
   * levels.
   *
   * Only basic variant information is included here - any additional
   * variant-specific details are referenced through the standard product
   * variant lookup system. This prevents bloating the response with
   * unnecessary data while maintaining sufficient detail for
   */
  variantAvailabilities?: IShoppingMallProductVariantAvailability[] | undefined;
};
