/**
 * Configuration for how the system handles failed webhook delivery attempts.
 *
 * This schema defines the retry behavior for incoming webhook delivery
 * failures. When the target endpoint returns 5xx errors, network timeouts, or
 * fails to respond within the designated timeout period, the system uses this
 * configuration to decide whether and how to retry the delivery.
 *
 * This structure is referenced in response and update DTOs for the payment
 * webhook system. It is stored in the 'retry_policy' column of the
 * shopping_mall_payment_webhooks table as a JSON object.
 *
 * Key properties:
 *
 * - MaxRetries: Number of retry attempts allowed after initial failure
 * - BackoffMultiplier: Exponential multiplier controlling growth of delays
 *   between retries
 * - TimeoutSeconds: Maximum wait time per delivery attempt
 *
 * The retry policy balances delivery reliability against system resource usage.
 * Too many retries overwhelm endpoints; too few result in lost events. The
 * exponential backoff prevents flooding the endpoint with rapid repeated
 * requests, giving it time to recover.
 *
 * Example: Small merchant with minimal webhook integration might use
 * {"maxRetries": 3, "backoffMultiplier": 2, "timeoutSeconds": 10} to ensure
 * delivery without overburdening their server. Large enterprise platform might
 * use {"maxRetries": 8, "backoffMultiplier": 3, "timeoutSeconds": 20} to
 * accommodate longer downstream processing times across multiple distributed
 * systems.
 *
 * Error handling: The system will stop retrying after maxRetries attempts and
 * mark the webhook as failed with a suitable reason in lastFailureReason. This
 * allows system administrators to review and manually repair persistent
 * delivery failures.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type IShoppingMallPaymentWebhookRetryPolicy = {
  /**
   * Maximum number of times the system will retry delivery of an event to
   * this webhook endpoint when failures occur. This controls the resilience
   * of the webhook integration against temporary network issues or endpoint
   * downtime.
   *
   * This field maps to the 'max_retries' column in the
   * shopping_mall_payment_webhooks table. The system uses exponential backoff
   * to determine retry intervals, with the number of attempts governed by
   * this setting.
   *
   * Values:
   *
   * - 0 = No retries (event will be delivered once, then permanently failed if
   *   first attempt fails)
   * - 1-10 = Number of retry attempts after the initial delivery (1 = 2 total
   *   attempts total, 10 = 11 total attempts)
   *
   * Business impact:
   *
   * - Lower values (0-3): Suitable for critical webhooks where immediate
   *   failure triggers manual intervention or where duplicate events are
   *   unacceptable
   * - Higher values (5-10): Suitable for less sensitive integrations where
   *   eventual consistency is acceptable and temporary outages are common,
   *   reducing the chance of permanent failure due to transient network
   *   issues
   *
   * System behavior:
   *
   * - If maxRetries is not provided during create/update, the system uses a
   *   default value of 5
   * - This value is counted per failed delivery attempt, not per event
   * - Each retry counts as a separate attempt toward the limit, even if the
   *   same event is retried multiple times
   * - If the limit is reached, the system stops retrying and marks the webhook
   *   as failed, setting lastFailureReason to 'MAX_RETRIES_EXCEEDED'
   * - This limit prevents infinite retry loops that could overwhelm webhook
   *   endpoints or consume excessive system resources
   */
  maxRetries: number & tags.Type<"int32"> & tags.Minimum<0> & tags.Maximum<10>;

  /**
   * The multiplier used to exponentially increase the time between retry
   * attempts.
   *
   * This field maps to the 'backoff_multiplier' column in the
   * shopping_mall_payment_webhooks table. It determines how quickly retry
   * intervals grow after each failed attempt.
   *
   * The retry interval is calculated as:
   *
   * InitialDelay * (backoffMultiplier ^ attemptNumber)
   *
   * Where:
   *
   * - InitialDelay is fixed at 1 second by the system
   * - AttemptNumber begins at 0 for the first retry
   *
   * Values:
   *
   * - 1 = Linear retry intervals (1s, 1s, 1s, 1s...)
   * - 2 = Exponential doubling (1s, 2s, 4s, 8s, 16s...)
   * - 3 = Exponential tripling (1s, 3s, 9s, 27s, 81s...)
   * - 5 = Maximum exponential growth (1s, 5s, 25s, 125s, 625s...)
   *
   * Business impact:
   *
   * - Lower values (1-2): Better for integrations that experience transient but
   *   fast-resolving failures (e.g., temporary network blips)
   * - Higher values (3-5): Better for integrations that experience prolonged
   *   downtime (e.g., vendor maintenance windows), allowing longer time
   *   between retries to prevent overwhelming the server
   *
   * System behavior:
   *
   * - When backoffMultiplier is not provided during create/update, the system
   *   uses a default value of 2
   * - This value is applied uniformly across all webhook retries
   * - The multiplier only affects retry intervals, not the number of retries
   *   (controlled by maxRetries)
   * - Individual retry intervals are capped at 300 seconds (5 minutes) by
   *   system limits
   *
   * Example progression with backoffMultiplier=2 and maxRetries=5:
   *
   * - Retries 1-5: 2s, 4s, 8s, 16s, 32s (total 62 seconds waiting)
   * - Failure at attempt 6: maxRetries exceeded
   *
   * Example progression with backoffMultiplier=5 and maxRetries=10:
   *
   * - Retries 1-10: 5s, 25s, 125s, 625s, 3125s, ... (capped at 300s from 4th
   *   retry)
   * - Failure at attempt 11: maxRetries exceeded
   */
  backoffMultiplier: number &
    tags.Default<2> &
    tags.Minimum<1> &
    tags.Maximum<5>;

  /**
   * The maximum time in seconds the system will wait for a response from the
   * webhook endpoint before considering the delivery attempt a failure and
   * triggering a retry.
   *
   * This field maps to the 'timeout_seconds' column in the
   * shopping_mall_payment_webhooks table. It governs the HTTP request timeout
   * for each individual delivery attempt.
   *
   * Values:
   *
   * - 5-30 seconds range allows balancing between responsiveness and tolerance
   *   for slow network conditions or heavy endpoint processing
   * - Values under 5 seconds are not permitted as they are too aggressive for
   *   reliable delivery
   * - Values over 30 seconds are not permitted as they risk hanging system
   *   resources and delaying other deliveries
   *
   * Business impact:
   *
   * - Lower values (5-8): Better for high-throughput systems or where immediate
   *   feedback is required—more aggressive timeout reduces waiting time on
   *   dead endpoints
   * - Higher values (10-30): Better for expensive processing hooks (e.g.,
   *   complex data transformation or external service calls)—gauges tolerance
   *   for slow but valid endpoint responses
   *
   * System behavior:
   *
   * - When timeoutSeconds is not provided during create/update, the system uses
   *   a default value of 10
   * - The timeout applies to each individual POST request to the endpoint, not
   *   the entire retry sequence
   * - If the server responds with a status code (even 5xx), the timeout is
   *   considered successful
   * - Timeout only applies if no response is received within the specified
   *   seconds (connection timeout or read timeout)
   * - The system uses the HTTP client's default keep-alive and connection
   *   pooling settings within this timeout limit
   *
   * Example use cases:
   *
   * - Endpoint performs minimal validation → timeoutSeconds=5
   * - Endpoint runs database-intensive report → timeoutSeconds=20-30
   */
  timeoutSeconds: number &
    tags.Type<"int32"> &
    tags.Default<10> &
    tags.Minimum<5> &
    tags.Maximum<30>;
};
