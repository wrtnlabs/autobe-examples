import { tags } from "typia";

/**
 * Payment surcharge rule configuration that applies additional fees to specific
 * payment methods under defined conditions.
 *
 * This schema defines a single surcharge rule with configurable parameters that
 * determine when and how an additional fee is applied to transactions.
 *
 * Rules are evaluated in order and applied cumulatively. All rules must comply
 * with regional regulations regarding surcharges and must not exceed legal
 * limits in any jurisdiction.
 *
 * Examples: +$0.50 fee for cryptocurrency transactions, +3% fee for credit card
 * transactions over $1000.
 *
 * This configuration is referenced by the main payment settings and programmed
 * into the payment processing engine.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type IShoppingMallPaymentSettingsSurchargeRule = {
  /**
   * Specifies which payment method this surcharge rule applies to.
   *
   * Must be one of the allowed payment method types: "credit_card",
   * "digital_wallet", "cryptocurrency", or "bank_transfer".
   *
   * This determines which payment methods will trigger this surcharge when
   * selected by customers during checkout.
   *
   * Multiple surcharge rules can be defined for the same payment method with
   * different conditions to apply different fees under different
   * circumstances.
   */
  payment_method:
    | "credit_card"
    | "digital_wallet"
    | "cryptocurrency"
    | "bank_transfer";

  /**
   * Determines the type of surcharge being applied: either a fixed monetary
   * amount or a percentage of the transaction value.
   *
   * - "fixed": Applies a constant fee amount regardless of transaction size
   *   (e.g., $0.50)
   * - "percentage": Applies a proportional fee based on the transaction amount
   *   (e.g., 3%)
   *
   * This distinguishes between flat-rate surcharges and percentage-based
   * surcharges for different payment methods and business needs.
   */
  type: "fixed" | "percentage";

  /**
   * The absolute value of the surcharge to be applied, measured in the base
   * currency (USD).
   *
   * - For "fixed" type: This is the exact dollar amount added to transaction
   *   (e.g., 0.50 for $0.50 fee)
   * - For "percentage" type: This represents the percentage rate as a decimal
   *   (e.g., 0.03 for 3% fee)
   *
   * Must be non-negative (≥ 0). Cannot be negative or zero unless explicitly
   * allowed by regulations.
   *
   * The amount is rounded according to system rounding rules before being
   * applied to the transaction total.
   */
  amount: number & tags.Minimum<0>;

  /**
   * Optional minimum transaction amount threshold for this surcharge rule to
   * apply.
   *
   * If specified, the surcharge is only applied when the transaction amount
   * equals or exceeds this threshold.
   *
   * For example, if amount=0.50 and min_transaction_amount=100, a $0.50
   * surcharge would only apply to transactions of $100 or more.
   *
   * Useful for ensuring that small transactions aren't disproportionately
   * affected by fixed surcharges.
   *
   * If not specified (null), the surcharge applies to all transaction amounts
   * without minimum threshold.
   */
  min_transaction_amount?: (number & tags.Minimum<0>) | undefined;

  /**
   * Optional maximum transaction amount threshold for this surcharge rule to
   * apply.
   *
   * If specified, the surcharge is only applied when the transaction amount
   * is less than or equal to this threshold.
   *
   * For example, if amount=0.03 and max_transaction_amount=500, a 3%
   * surcharge would only apply to transactions of $500 or less.
   *
   * Useful for capping surcharges on large transactions to comply with
   * regulatory limits or business policies.
   *
   * If not specified (null), the surcharge applies to all transaction amounts
   * without maximum threshold.
   */
  max_transaction_amount?: (number & tags.Minimum<0>) | undefined;
};
