import { tags } from "typia";

/**
 * Statistical percentiles for response time distribution.
 *
 * This schema defines the structure for capturing key performance indicators of
 * response time variability.
 *
 * - P50: Median response time
 * - P75: 75th percentile response time
 * - P90: 90th percentile response time
 * - P95: 95th percentile response time
 *
 * These percentiles provide insight into typical and worst-case performance.
 * For example, a p95 value of 48 hours indicates that 5% of responses take 2
 * full days or more. High p90/p95 values relative to p50 indicate inconsistent
 * server performance or seller behavior.
 *
 * Used for SLA reporting and identifying outliers in seller behavior.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type ICommunicationLatencyPercentile = {
  /**
   * Median response time in hours.
   *
   * The 50th percentile response time represents the median value, where half
   * of all responses are faster than this time and half are slower.
   *
   * This metric indicates the typical response speed sellers exhibit. A low
   * p50 value (e.g., <4 hours) indicates sellers generally respond quickly,
   * while a high value indicates systemic delays in responsiveness.
   *
   * Used as a baseline for comparing seller performance against platform
   * benchmarks. Values are calculated from response timestamp minus message
   * timestamp for all resolved communications.
   */
  p50: number & tags.Minimum<0>;

  /**
   * 75th percentile response time in hours.
   *
   * This metric represents the response time below which 75% of all responses
   * fall. It is more sensitive to delays than the median, as it captures the
   * majority of cases while excluding only the slowest 25%.
   *
   * Values above 24 hours indicate that 25% of responses are taking a full
   * day or more, signaling potential issues with seller responsiveness or
   * system workflow. Used to identify performance bottlenecks that affect
   * most sellers.
   *
   * Found to be particularly valuable in signaling when support interventions
   * are needed for seller cohorts.
   */
  p75: number & tags.Minimum<0>;

  /**
   * 90th percentile response time in hours.
   *
   * This metric captures the response time below which 90% of all responses
   * occur, representing the upper limit of typical performance.
   *
   * Values high enough to trigger alerts (e.g., >48 hours) indicate that 10%
   * of responses are taking 2 full days or more, which is well beyond
   * acceptable customer service standards.
   *
   * This percentile is critical for identifying outliers and systemic issues,
   * as even a small percentage of extremely slow responses can indicate
   * serious customer satisfaction problems.
   */
  p90: number & tags.Minimum<0>;

  /**
   * 95th percentile response time in hours.
   *
   * This metric represents the response time below which 95% of all responses
   * occur, capturing the extreme tail of the distribution.
   *
   * Values above 72 hours (3 days) indicate that 5% of responses are taking a
   * full working week or more to be responded to, which is unacceptable for a
   * commercial platform.
   *
   * This metric is used for SLA compliance reporting and identifying the most
   * severe performance failures. Persistent high p95 values require direct
   * seller intervention and potential platform-level process changes.
   */
  p95: number & tags.Minimum<0>;
};
