import { tags } from "typia";

/**
 * Payment surcharge rule configuration that applies additional fees to specific
 * payment methods under defined conditions.
 *
 * This schema defines the structure for surcharge rules that can be applied to
 * payment methods based on transaction amount ranges, geographic regions, or
 * other criteria. Each rule specifies a fee structure (percentage and/or fixed
 * fee) that will be applied to transactions meeting the defined conditions.
 *
 * The surcharge rules are evaluated in order of priority, and only the first
 * matching rule is applied to any given transaction. This allows for tiered
 * pricing models where larger transactions have lower surcharges, or where
 * different fees apply to different regions or transaction types.
 *
 * This type is referenced in the payment method configuration as an array of
 * rules, enabling flexible and granular control over fee structures across the
 * platform.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type IShoppingMallPaymentMethodSurchargeRule = {
  /**
   * Identifier for the payment method to which this surcharge rule applies.
   * This must correspond to an existing payment method in the
   * shopping_mall_payment_methods table. The rule will be applied only to
   * transactions using this specific payment method.
   */
  payment_method_id: string & tags.Format<"uuid">;

  /**
   * Priority ranking of this surcharge rule for evaluation order. Higher
   * values are evaluated first. When multiple rules match the transaction
   * criteria, the highest priority rule is applied. Valid range is 1 to 100,
   * with 100 being the highest priority.
   */
  priority: number & tags.Type<"int32"> & tags.Minimum<1> & tags.Maximum<100>;

  /**
   * Minimum transaction amount (in primary currency) for this rule to apply.
   * Transactions with an amount equal to or greater than this value are
   * eligible for this rule. Must be greater than or equal to 0. If null,
   * there is no lower bound on transaction amount.
   */
  amount_min?: (number & tags.Minimum<0>) | undefined;

  /**
   * Maximum transaction amount (in primary currency) for this rule to apply.
   * Transactions with an amount less than this value are eligible for this
   * rule. Must be greater than or equal to amount_min if amount_min is
   * specified. If null, there is no upper bound on transaction amount.
   */
  amount_max?: (number & tags.Minimum<0>) | undefined;

  /**
   * Geographic region where this surcharge rule is applicable. Must match ISO
   * 3166-1 alpha-2 country code (e.g., "US", "JP", "KR") or "global" for
   * worldwide application. The rule applies only to transactions originating
   * from the specified region or everywhere if "global" is specified.
   */
  region?: (string & tags.Pattern<"^[A-Z]{2}$|^global$">) | undefined;

  /**
   * Type of fee structure this rule implements. Determines how the surcharge
   * amount is calculated:
   *
   * - "percentage": Fee is calculated as transaction_amount * percentage_value
   * - "fixed": Fee is fixed amount applied to all qualifying transactions
   * - "comb": Combined structure applying both percentage and fixed fees
   *
   * The type field determines which additional fee fields must be provided
   * and how the final surcharge amount is computed.
   */
  fee_type: "percentage" | "fixed" | "comb";

  /**
   * Percentage of transaction amount to be charged as fee (0.0 to 100.0). For
   * transactions that match this rule, this percentage is applied to the
   * transaction amount to calculate the surcharge. Allowed range is 0.0 (no
   * fee) to 100.0 (100% fee). For fee_type = "fixed" or "comb", this value
   * must be provided and must be between 0 and 100.
   */
  percentage_fee?: (number & tags.Minimum<0> & tags.Maximum<100>) | undefined;

  /**
   * Fixed fee amount charged per qualifying transaction in primary currency.
   * For transactions that match this rule, this fixed amount is added to the
   * surcharge regardless of the transaction amount. Must be greater than or
   * equal to 0. Must be provided when fee_type is "fixed" or "comb".
   */
  fixed_fee?: (number & tags.Minimum<0>) | undefined;

  /**
   * ISO 4217 three-letter currency code for which this surcharge rule
   * applies. The rule is only applied to transactions in this specific
   * currency. This field ensures consistent fee structures across different
   * currency denominations. Examples: "USD", "EUR", "JPY", "KRW". Must be an
   * active currency supported by the platform.
   */
  currency?: (string & tags.Pattern<"^[A-Z]{3}$">) | undefined;

  /**
   * Flag indicating whether this surcharge rule is currently active and
   * applied to transactions. When false, the rule is ignored and not applied
   * to any transactions, even if they match all other criteria. This allows
   * administrators to temporarily disable rules without deleting them, for
   * example during testing, rule reviews, or payment provider outages.
   */
  is_enabled: boolean;

  /**
   * Human-readable description of this surcharge rule. This field provides
   * context about the business purpose of the rule, including when and why it
   * should be applied. For example: "2% fee on card payments above $1000" or
   * "$5 flat fee for cryptocurrency transactions in Germany". This
   * description is used in administrative interfaces to help staff understand
   * the rule's intent and impact.
   */
  description: string & tags.MaxLength<500>;
};
