import { tags } from "typia";

/**
 * Detailed behavioral analytics profile for each customer, including purchase
 * patterns, engagement metrics, and conversion rates.
 *
 * This schema represents the result of a complex multi-table analytics query
 * that combines data from shopping_mall_customers, shopping_mall_orders,
 * shopping_mall_order_items, shopping_mall_product_variants,
 * shopping_mall_product_view_stats, and shopping_mall_wishlist_items to derive
 * meaningful behavioral insights.
 *
 * The schema contains aggregated metrics calculated at the customer level using
 * GROUP BY customer_id, with metrics including purchase frequency, average
 * order value, category preference distribution, view-to-purchase conversion
 * rates, and wishlist-to-purchase completion rates.
 *
 * This analytical data serves the business need for customer segmentation,
 * personalized marketing campaigns, and churn prediction. The system does NOT
 * store these metrics as physical records - they are computed on-demand to
 * ensure real-time accuracy.
 *
 * Security note: This schema is only accessible to admin actors due to the
 * sensitive nature of behavioral patterns revealed by these metrics. It does
 * not expose personally identifiable information beyond the customer_id
 * reference.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type IShoppingMallCustomerBehaviorAnalytics = {
  /**
   * Unique identifier for the customer.
   *
   * This UUID references the shopping_mall_customers table and serves as the
   * primary key for aggregating all behavioral data across multiple tables.
   *
   * Used as the GROUP BY key in the analytics query to produce one record per
   * customer.
   */
  customer_id: string & tags.Format<"uuid">;

  /**
   * Total number of orders placed by this customer.
   *
   * Calculated as the COUNT of shopping_mall_orders records grouped by
   * customer_id.
   *
   * Represents the customer's overall engagement level with the platform.
   *
   * A higher value indicates a more active and loyal customer.
   */
  purchase_frequency: number & tags.Type<"int32"> & tags.Minimum<0>;

  /**
   * Average monetary value of all orders placed by this customer.
   *
   * Calculated as AVG of order_total_amount from shopping_mall_orders records
   * grouped by customer_id.
   *
   * Represents the customer's typical spending behavior.
   *
   * Used for customer segmentation and identifying high-value customers.
   */
  average_order_value: number & tags.Minimum<0>;

  /**
   * The most frequently purchased product category for this customer.
   *
   * Determined by joining shopping_mall_orders → shopping_mall_order_items →
   * shopping_mall_product_variants → shopping_mall_products →
   * shopping_mall_categories and counting occurrences per category.
   *
   * Represents the customer's primary product interest area.
   *
   * Useful for personalized product recommendations and targeted marketing
   * campaigns.
   */
  category_preference: string;

  /**
   * Percentage of product views that result in a purchase.
   *
   * Calculated as (COUNT of shopping_mall_product_view_stats entries) /
   * (COUNT of shopping_mall_order_items) for the customer.
   *
   * Measures product interest conversion efficiency.
   *
   * A high ratio indicates effective product discovery and purchasing intent.
   *
   * A low ratio may indicate price sensitivity or product information gaps.
   */
  view_to_purchase_ratio: number & tags.Minimum<0>;

  /**
   * Percentage of wishlist items that have been purchased.
   *
   * Calculated as (COUNT of wishlist_items that have matching order_items) /
   * (Total wishlist_items) for the customer.
   *
   * Measures the effectiveness of the wishlist feature in driving sales.
   *
   * A high rate indicates strong intent and product consideration leading to
   * purchase.
   */
  wishlist_conversion_rate: number & tags.Minimum<0> & tags.Maximum<1>;

  /**
   * Number of days since this customer's last order.
   *
   * Calculated as (current date) - (MAX(order_date) from shopping_mall_orders
   * for the customer).
   *
   * Key indicator of customer churn risk.
   *
   * A high value indicates potential disengagement.
   *
   * Used to trigger re-engagement campaigns and loyalty incentives.
   */
  days_since_last_purchase: number & tags.Type<"int32"> & tags.Minimum<0>;

  /**
   * Total number of product variants currently in this customer's wishlist.
   *
   * Count of records in shopping_mall_wishlist_items table grouped by
   * customer_id.
   *
   * Indicates ongoing product interest and future purchase potential.
   *
   * Customers with many wishlist items are prime candidates for remarketing.
   */
  total_wishlist_items: number & tags.Type<"int32"> & tags.Minimum<0>;

  /**
   * Total number of product page views by this customer.
   *
   * Count of records in shopping_mall_product_view_stats table grouped by
   * customer_id.
   *
   * Measures overall engagement level and product exploration behavior.
   *
   * High view counts with low purchase frequency may indicate price
   * sensitivity or browsing behavior.
   */
  total_product_views: number & tags.Type<"int32"> & tags.Minimum<0>;

  /**
   * Composite score representing overall customer loyalty.
   *
   * Calculated using a weighted formula combining: purchase_frequency,
   * average_order_value, wishlist_conversion_rate, and
   * days_since_last_purchase.
   *
   * Each factor is normalized and weighted based on business priorities.
   *
   * Ranks customers from 0 (low loyalty) to 10 (high loyalty).
   *
   * Used for tiered reward programs and personalized customer service.
   */
  loyalty_score: number & tags.Minimum<0> & tags.Maximum<10>;

  /**
   * Classification of the customer into a behavioral segment.
   *
   * Determined algorithmically based on the combination of all other metrics.
   *
   * Common segments include:
   *
   * - High-Value Frequent Buyer
   * - Casual Browser
   * - Lapsed Customer
   * - Discount-Seeking Shopper
   * - Wishlist-Driven Buyer
   *
   * Used to tailor marketing strategies and customer experience.
   */
  customer_segment: string;

  /**
   * Flag indicating whether the customer should receive priority in
   * conversion optimization campaigns.
   *
   * Derived from analyzing high view-to-purchase ratio, low
   * days_since_last_purchase, and high loyalty_score.
   *
   * Indicates a high probability of conversion with targeted interventions.
   *
   * Used by marketing automation systems to prioritize customer
   * communications.
   */
  conversion_engine_boost: boolean;

  /**
   * Proportion of orders that have been refunded for this customer.
   *
   * Calculated as (COUNT of shopping_mall_order_refunds) / (COUNT of
   * shopping_mall_orders) for the customer.
   *
   * High refund rates may indicate product quality issues, sizing problems,
   * or mismatched expectations.
   *
   * Used to identify potential quality control issues or problematic
   * products.
   */
  refund_rate: number & tags.Minimum<0> & tags.Maximum<1>;

  /**
   * Total number of refund transactions processed for this customer.
   *
   * Count of shopping_mall_order_refunds records associated with the
   * customer's orders.
   *
   * A direct indicator of customer satisfaction with purchases.
   *
   * High values warrant investigation and potential customer service
   * intervention.
   */
  total_refunds: number & tags.Type<"int32"> & tags.Minimum<0>;
};
