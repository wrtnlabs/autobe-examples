import { tags } from "typia";

/**
 * Progress tracking object for the seller onboarding journey on the
 * shoppingMall platform.
 *
 * This schema defines the complete state of a seller's onboarding progress
 * through the registration and verification process. It tracks the current
 * stage of onboarding, the list of completed steps, whether all requirements
 * have been met, and when this information was last updated.
 *
 * The onboarding process consists of five mandatory phases:
 *
 * 1. Account creation (email/password registration)
 * 2. Identity verification (government-issued ID submission)
 * 3. Business information submission (legal name, address, contact details)
 * 4. Bank account linkage for payouts
 * 5. Terms of service acceptance
 *
 * The stage field indicates the current phase the seller is actively
 * completing, while completedSteps tracks a history of all successfully
 * completed phases. The isComplete flag is automatically calculated and
 * represents the final state where the seller can fully operate on the
 * platform.
 *
 * This progress object is referenced in seller authentication responses to
 * determine access level, and is updated throughout the onboarding workflow as
 * the seller completes each step. It provides a comprehensive view of the
 * seller's readiness to conduct business on the platform.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type IShoppingMallSellerOnboardingProgress = {
  /**
   * The current stage of the seller's onboarding journey. Must be one of:
   * 'accountCreation', 'identityVerification', 'businessInformation',
   * 'bankAccountLinkage', 'termsAcceptance'.
   */
  stage: string;

  /**
   * List of all onboarding steps that have been successfully completed by the
   * seller. Each item must be one of the valid onboarding stage identifiers.
   */
  completedSteps?:
    | ((
        | "accountCreation"
        | "identityVerification"
        | "businessInformation"
        | "bankAccountLinkage"
        | "termsAcceptance"
      )[] &
        tags.UniqueItems)
    | undefined;

  /**
   * Indicates whether the seller has completed all mandatory onboarding steps
   * and can fully operate on the platform. This is a derived field that is
   * automatically calculated as true when all five required steps are present
   * in the completedSteps array.
   */
  isComplete: boolean;
};
