/**
 * Distribution of shipment statuses across the entire reporting period.
 *
 * This object provides a detailed breakdown of all shipment states at the time
 * of the report. It's not just a count distribution but a comprehensive view of
 * the entire logistics pipeline, from order creation to final delivery or
 * failure.
 *
 * Each property represents a distinct phase in the shipping lifecycle:
 *
 * - Pending: Order has been placed but not yet processed
 * - Shipped: Warehouse has dispatched item to carrier
 * - In_transit: Item is moving through the carrier network
 * - Out_for_delivery: Item has reached local delivery hub
 * - Delivered: Successful delivery to customer
 * - Failed: Delivery attempt failed for various reasons
 * - Returned: Item is on way back to merchant
 * - Cancelled: Order was cancelled before shipment
 * - Other: Items in undefined or unexpected states
 *
 * These relationships reflect the business workflow and are essential for
 * monitoring operational health and identifying bottlenecks. The distribution
 * helps decision-makers understand where delays occur and what percentage of
 * shipments are performing successfully.
 *
 * The data is acquired by aggregating event logs from
 * shopping_mall_delivery_events and joining with shopping_mall_order_shipments
 * and shopping_mall_orders. The schema captures the precise status of every
 * shipment in the system at the time of report generation.
 *
 * This comprehensive view is critical for logistics optimization, carrier
 * performance evaluations, customer service analytics, and capacity planning.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type IShippingStatusDistribution = {
  /**
   * Number of shipments currently in pending status, awaiting processing or
   * dispatch.
   *
   * Represents orders that have been placed but not yet assigned to a carrier
   * or prepared for shipping. These are typically in an 'order_created' or
   * 'preparing_for_shipment' state in the shopping_mall_order_shipments
   * table.
   *
   * High pending counts may indicate fulfillment bottlenecks or resource
   * constraints in the warehouse operations.
   */
  pending: number & tags.Type<"int32"> & tags.Minimum<0>;

  /**
   * Number of shipments that have been dispatched from the warehouse and are
   * in transit.
   *
   * These shipments have been assigned to a carrier and have a shipping
   * tracking number assigned in shopping_mall_order_shipments. They are in
   * the 'shipped' status according to the shipping flow.
   *
   * This metric reflects current logistics activity and helps track inventory
   * movement.
   *
   * Derived from shopping_mall_delivery_events where the earliest event type
   * is 'shipped'.
   */
  shipped: number & tags.Type<"int32"> & tags.Minimum<0>;

  /**
   * Number of shipments actively moving through the carrier network towards
   * delivery.
   *
   * This is a subset of 'shipped' status, excluding those that have reached
   * final delivery or failed. Represents shipments that have been picked up
   * by carriers but not yet delivered.
   *
   * Tracked via shopping_mall_delivery_events where event_type = 'in_transit'
   * or equivalent status updates from carrier systems.
   *
   * Critical for estimating delivery timelines and managing customer
   * expectations.
   */
  in_transit: number & tags.Type<"int32"> & tags.Minimum<0>;

  /**
   * Number of shipments that have reached the local delivery hub and are
   * scheduled for same-day delivery.
   *
   * Represents the final stage of logistics before delivery. These shipments
   * are typically with local postal workers or couriers.
   *
   * Determined by shopping_mall_delivery_events with event_type =
   * 'out_for_delivery'.
   *
   * High out_for_delivery counts indicate imminent deliveries and require
   * coordination with delivery partners.
   */
  out_for_delivery: number & tags.Type<"int32"> & tags.Minimum<0>;

  /**
   * Number of shipments successfully completed with final delivery to the
   * customer.
   *
   * The primary goal of the shipping process. This status is recorded when
   * the final delivery event (shopping_mall_delivery_events.event_type =
   * 'delivered') is confirmed.
   *
   * Used to calculate on-time delivery rates and overall fulfillment success
   * percentages.
   */
  delivered: number & tags.Type<"int32"> & tags.Minimum<0>;

  /**
   * Number of shipments that could not be delivered successfully.
   *
   * Includes statuses such as 'lost', 'returned_to_sender',
   * 'delivery_failed', and 'abandoned'. These represent operational failures
   * and customer service issues.
   *
   * Identified through shopping_mall_delivery_events with failure-type event
   * statuses and post-failure actions in shopping_mall_order_returns.
   *
   * A high failure rate indicates carrier or logistical problems that require
   * immediate attention.
   */
  failed: number & tags.Type<"int32"> & tags.Minimum<0>;

  /**
   * Number of shipments that have been returned to the sender (merchant)
   * after attempted delivery.
   *
   * An industry-specific subset of failed shipments, often due to customer
   * refusal, incorrect address, or product issues.
   *
   * Based on integration with shopping_mall_order_returns table and inventory
   * reconciliation processes.
   *
   * High return rates may indicate product quality issues or inaccurate
   * product descriptions.
   */
  returned: number & tags.Type<"int32"> & tags.Minimum<0>;

  /**
   * Number of shipments that were cancelled by the customer or merchant after
   * order creation but before shipment dispatch.
   *
   * Represents lost sales opportunities and customer service issues. These
   * shipments never entered the logistics chain.
   *
   * Tracking cancellation reasons (shopping_mall_order_cancellation_reasons)
   * helps identify operational pain points.
   *
   * Includes only orders that were cancelled prior to 'shipped' status.
   */
  cancelled: number & tags.Type<"int32"> & tags.Minimum<0>;

  /**
   * Number of shipments in other or undefined status categories that don't
   * fit the standard flow.
   *
   * Catches edge cases, transient states, or custom statuses introduced by
   * carrier systems that don't map cleanly to the standard flow.
   *
   * Used as a catch-all for any unexpected status values in
   * shipping_mall_delivery_events.
   *
   * Should be minimal in a well-designed system and monitored for patterns
   * that indicate integration issues.
   */
  other: number & tags.Type<"int32"> & tags.Minimum<0>;
};
