import { tags } from "typia";

/**
 * Card-specific details from payment provider webhooks.
 *
 * Represents structured information returned by payment gateways about the card
 * used in a transaction. This schema captures key attributes that are commonly
 * included in webhook payloads from providers like Stripe, PayPal, Adyen, etc.
 *
 * This type is not intended to represent the full card data - it contains only
 * the minimal, PCI-DSS compliant subset of information that can be safely
 * transmitted and stored.
 *
 * The structure includes:
 *
 * - Brand: The payment network (Visa, Mastercard, etc.)
 * - Last4: The last four digits of the card number
 * - Funding: The card type (credit, debit, prepaid)
 * - Country: The issuing country of the card
 *
 * This represents the standard format used by major payment processors to
 * report card data in webhook events while maintaining security compliance.
 *
 * All fields are required to ensure consistent processing of transaction data
 * across different payment gateways.
 *
 * The schema enforces strict validation:
 *
 * - Country as two-letter uppercase ISO code (prevents typos)
 * - Last4 as exactly 4 numeric digits (ensures valid format)
 * - Funding from known types (prevents arbitrary values)
 * - Brand from standard network names (maintains consistency)
 *
 * This definition aligns with the end-to-end payment processing workflow where
 * webhook events are processed, validated, and mapped to internal financial
 * records.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type IShoppingMallPaymentWebhookCardPayload = {
  /**
   * The card brand or network, such as Visa, Mastercard, American Express,
   * Discover, etc.
   *
   * This identifies the payment network associated with the card. Common
   * values include:
   *
   * - 'visa'
   * - 'mastercard'
   * - 'amex'
   * - 'discover'
   * - 'diners_club'
   * - 'jcb'
   *
   * Used for routing transactions, fraud analysis, and displaying card type
   * to customers.
   */
  brand: string;

  /**
   * The last four digits of the card number.
   *
   * This provides a customer-visible identifier for the card without exposing
   * the full PAN (Primary Account Number).
   *
   * Must be exactly 4 numeric characters.
   *
   * Used for:
   *
   * - Customer identification and reference
   * - Receipt display
   * - Support inquiries
   * - Transaction matching
   *
   * Example: '4242' (for a card ending in ...4242)
   */
  last4: string & tags.Pattern<"^[0-9]{4}$">;

  /**
   * The funding source type of the card transaction.
   *
   * Indicates whether the card is a credit, debit, or prepaid card.
   *
   * Common values:
   *
   * - 'credit'
   * - 'debit'
   * - 'prepaid'
   *
   * Used for financial reconciliation, fraud detection, and understanding
   * customer spending behavior.
   */
  funding: string;

  /**
   * The two-letter ISO 3166-1 alpha-2 country code of the card issuer.
   *
   * Represents the country where the card was issued by the bank.
   *
   * Examples: 'US', 'GB', 'JP', 'CA', 'DE', 'AU'
   *
   * Used for:
   *
   * - Geolocation-based fraud detection
   * - KYC/AML compliance
   * - Transaction routing decisions
   * - Tax and regulatory compliance
   * - Currency conversion appropriate to the issuing region
   */
  country: string &
    tags.MinLength<2> &
    tags.MaxLength<2> &
    tags.Pattern<"^[A-Z]{2}$">;
};
