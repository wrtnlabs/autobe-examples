/**
 * Retrieve paginated list of payment gateway failover configurations for system
 * health monitoring and failover strategy analysis.
 *
 * This operation operates on the shopping_mall_payment_gateway_failovers table
 * and provides comprehensive inspection of all configured gateway failover
 * rules across the system. The failover configurations represent system-level
 * fallback strategies that activate when primary payment gateways encounter
 * failures or timeouts.
 *
 * The operation supports advanced filtering by gateway name, region, priority
 * level, and active status. Results are paginated with configurable page sizes
 * and support sorting by creation timestamp, priority weight, or last tested
 * status. Each configuration includes details of both primary and backup
 * gateway identifiers, activation thresholds, retry intervals, and status
 * monitoring history.
 *
 * Security considerations include that this operation is publicly accessible
 * since failover configurations are not sensitive business data but rather
 * operational system configurations analogous to network routing tables. Rate
 * limiting applies to prevent abuse of this diagnostic endpoint. This operation
 * serves critical infrastructure monitoring needs and is essential for
 * proactive system maintenance and incident response planning.
 *
 * Related operations include: PATCH /payments/payment-gateway-status (for
 * real-time gateway status), and GET /payments/settings (for viewing current
 * payment configuration).
 *
 * @param props.connection
 * @param props.body Search parameters for filtering and paginating payment
 *   gateway failover configurations
 * @path /shoppingMall/payment-gateway-failovers
 * @accessor api.functional.shoppingMall.payment_gateway_failovers.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
