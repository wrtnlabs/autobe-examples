import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IPageIShoppingMallReviewReply } from "../../../../structures/IPageIShoppingMallReviewReply";

/**
 * Retrieve all reply messages to a specific product review. This operation
 * queries the shopping_mall_review_replies table to fetch all reply entries
 * associated with a given review ID. Each reply contains the reply content,
 * timestamp, and reference to the originating review. Display order is
 * maintained based on creation timestamp with most recent replies appearing
 * first.
 *
 * This endpoint supports pagination and sorting of reply sequences to handle
 * high-volume review threads. Clients must provide the reviewId as a path
 * parameter to identify the target review. The reply content must be sanitized
 * before display to prevent XSS vulnerabilities, which is handled automatically
 * by the system.
 *
 * Security Considerations: The reply retrieval is publicly accessible - no
 * authentication is required. Each reply includes an author identifier that may
 * be linked to a customer or seller account, but personal data like email or
 * contact details is obfuscated.
 *
 * Implementational Note: The query joins with the shopping_mall_review_replies
 * and shopping_mall_reviews tables. The response includes the reply.id,
 * reply.reply_content, reply.created_at, and reply.author_id. The reviewId path
 * parameter must correspond to an existing review in the shopping_mall_reviews
 * table. If the reviewId does not exist, the system returns an empty array
 * response. Direct database deletions are not reflected in this API endpoint.
 *
 * Related Operations: For creating a new reply to a review, see POST
 * /reviews/{reviewId}/replies. For complete review information including the
 * original review and replies, see GET /reviews/{reviewId}.
 *
 * @param props.connection
 * @param props.reviewId Unique identifier of the target review to retrieve
 *   replies for
 * @path /shoppingMall/reviews/:reviewId/replies
 * @accessor api.functional.shoppingMall.reviews.replies.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
      );
}
export namespace index {
  export type Props = {
    /** Unique identifier of the target review to retrieve replies for */
    reviewId: string;
  };
  export type Response = IPageIShoppingMallReviewReply;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/reviews/:reviewId/replies",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/reviews/${encodeURIComponent(props.reviewId ?? "null")}/replies`;
  export const random = (): IPageIShoppingMallReviewReply =>
    typia.random<IPageIShoppingMallReviewReply>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("reviewId")(() => typia.assert(props.reviewId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
