/**
 * Retrieve the vote statistics for a specific product review. This operation
 * calculates the total number of helpful and unhelpful votes associated with a
 * review in the shopping_mall_review_votes table. It provides aggregated vote
 * counts to help users identify the most valuable feedback among multiple
 * reviews.
 *
 * The operation returns the total count of helpful votes (positive feedback)
 * and unhelpful votes (negative feedback) for the specified review. Votes are
 * stored in the shopping_mall_review_votes table with corresponding review_id
 * and vote_type values ("helpful" or "unhelpful"). This data is used by the
 * product review system to surface the most useful customer feedback at the top
 * of review lists.
 *
 * Security: The operation is public and requires no authentication since vote
 * counts are considered non-sensitive aggregate data that does not reveal
 * individual voter identities. However, the review ID must exist in the
 * shopping_mall_product_reviews table, otherwise a 404 error will be returned.
 *
 * Implementation Note: This endpoint does not return individual vote records
 * but rather computes and returns the aggregated counts. This approach prevents
 * data overload and protects user privacy by avoiding exposure of individual
 * voter information. The service layer aggregates the votes using a simple
 * COUNT aggregation grouped by vote_type against the review_id in the
 * database.
 *
 * Related operations: GET /reviews/{reviewId} to view the review content, PATCH
 * /reviews to list reviews with aggregated vote counts in summary views.
 *
 * @param props.connection
 * @param props.reviewId Unique identifier of the target product review. Must
 *   reference an existing record in the shopping_mall_product_reviews table.
 * @path /shoppingMall/reviews/:reviewId/votes
 * @accessor api.functional.shoppingMall.reviews.votes.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
