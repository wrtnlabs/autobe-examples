import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IPageIShoppingMallReviewReaction } from "../../../../structures/IPageIShoppingMallReviewReaction";

/**
 * Retrieve a paginated list of all reactions to a specific product review,
 * supporting filtering by reaction type, sorting by creation date, and
 * pagination controls. This operation queries the
 * shopping_mall_review_reactions table to aggregate and display all user
 * reactions to a specific review identified by its unique ID. The results are
 * optimized for display in review detail interfaces and support
 * community-driven insight into review helpfulness. Reactions are returned as
 * summary objects that include the reaction type and simple user
 * identification, without exposing sensitive user information. This operation
 * depends on the existence of a valid shopping_mall_review_id and cannot be
 * performed without it. The result is returned as a paginated list using a
 * specialized IPageIShoppingMallReviewReaction schema designed specifically for
 * this display context.
 *
 * Security: Only authenticated users can view reactions. Reactions are visible
 * to everyone regardless of user role, as they represent community sentiment.
 *
 * Implementation note: Retrieves reactions from the
 * shopping_mall_review_reactions table and joins with the
 * shopping_mall_customers table to get display names while excluding sensitive
 * user data. Uses common PostgreSQL query patterns optimized for read-heavy
 * usage. Utilizes indexes on shopping_mall_review_id and created_at for
 * performance.
 *
 * Related operations: POST /reviews/{reviewId}/reactions (to create a new
 * reaction), GET /reviews/{reviewId} (to view the review itself).
 *
 * @param props.connection
 * @param props.reviewId Unique identifier of the target review. This UUID
 *   refers to the shopping_mall_review_id in the shopping_mall_reviews table.
 * @path /shoppingMall/reviews/:reviewId/reactions
 * @accessor api.functional.shoppingMall.reviews.reactions.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
      );
}
export namespace index {
  export type Props = {
    /**
     * Unique identifier of the target review. This UUID refers to the
     * shopping_mall_review_id in the shopping_mall_reviews table.
     */
    reviewId: string;
  };
  export type Response = IPageIShoppingMallReviewReaction;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/reviews/:reviewId/reactions",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/reviews/${encodeURIComponent(props.reviewId ?? "null")}/reactions`;
  export const random = (): IPageIShoppingMallReviewReaction =>
    typia.random<IPageIShoppingMallReviewReaction>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("reviewId")(() => typia.assert(props.reviewId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
