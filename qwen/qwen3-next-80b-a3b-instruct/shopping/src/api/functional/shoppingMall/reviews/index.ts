/**
 * Retrieve a specific product review from the shoppingMall platform. This
 * operation operates on the shopping_mall_reviews table and returns the
 * complete review details including title, body, rating, and status.
 *
 * The review is identified by its unique reviewId and can be accessed by any
 * authenticated user. The operation returns the review as-is regardless of its
 * status (published, pending, rejected, or hidden). This ensures that users who
 * have previously seen a review can still access it, even if it has since been
 * moderated. The operation retrieves all fields from the shopping_mall_reviews
 * table as defined in the Prisma schema, including metadata like created_at,
 * updated_at, and deleted_at timestamps.
 *
 * Security: This is a public endpoint with no authentication required. However,
 * the response may contain a soft-deleted review if deleted_at is not null,
 * which should be handled appropriately by consuming applications.
 *
 * Related operations: This operation should be used in conjunction with PATCH
 * /reviews to retrieve the list of reviews for a product, and with POST
 * /reviews to create new reviews. Any client displaying a review should handle
 * soft-deleted records by hiding them from view while still allowing access to
 * the original data for auditing purposes.
 *
 * @param props.connection
 * @param props.reviewId Unique identifier of the target review. UUID format as
 *   defined in the Prisma schema.
 * @path /shoppingMall/reviews/:reviewId
 * @accessor api.functional.shoppingMall.reviews.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
