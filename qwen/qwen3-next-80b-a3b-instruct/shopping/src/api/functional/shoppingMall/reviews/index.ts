/**
 * Retrieve a specific product review from the shopping mall platform. This
 * operation accesses the shopping_mall_reviews database table to fetch detailed
 * customer feedback associated with a particular product.
 *
 * The review details include the customer's rating, written comments, review
 * date, and associated metadata such as review status and verification status.
 * This endpoint returns full review information optimized for display in
 * product detail pages and customer review sections.
 *
 * Security and authorization: This is a publicly viewable endpoint where all
 * visitors can see reviews, but authenticated users see additional metadata
 * about their own reviews such as reply status. Admins can view all reviews
 * including flagged or unapproved content.
 *
 * Implementation note: The review ID is a unique identifier from the
 * shopping_mall_reviews table. The system does not use UUID for review
 * identification; instead it uses a sequential integer primary key as verified
 * in the database schema. The response includes all review fields as defined in
 * the schema, including the product ID for context, customer information,
 * rating, and status flags.
 *
 * @param props.connection
 * @param props.reviewId Unique sequential identifier of the target review in
 *   the shopping_mall_reviews table (not a UUID). Represents the primary key of
 *   the review record in the database.
 * @path /shoppingMall/reviews/:reviewId
 * @accessor api.functional.shoppingMall.reviews.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique sequential identifier of the target review in the
     * shopping_mall_reviews table (not a UUID). Represents the primary key
     * of the review record in the database.
     */
    reviewId: number & tags.Type<"int32"> & tags.Minimum<1>;
  };
  export type Response = IShoppingMallProductReview;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/reviews/:reviewId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/reviews/${encodeURIComponent(props.reviewId ?? "null")}`;
  export const random = (): IShoppingMallProductReview =>
    typia.random<IShoppingMallProductReview>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("reviewId")(() => typia.assert(props.reviewId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

