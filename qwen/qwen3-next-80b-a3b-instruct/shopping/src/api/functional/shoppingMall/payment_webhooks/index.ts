/**
 * Receive payment webhook notifications from external payment providers. This
 * operation handles asynchronous notifications from payment gateways (such as
 * Stripe, PayPal, or other financial services) regarding payment events
 * including successful charges, failed payments, refunds, and disputes. The
 * system uses this endpoint to update order payment statuses, trigger
 * reconciliation processes, and maintain accurate financial records.
 *
 * The webhook endpoint receives JSON payloads containing payment event data as
 * defined by external providers. Each payload includes a unique identifier for
 * the payment, event type, timestamp, and relevant financial details. The
 * system validates the authenticity of the webhook by verifying
 * provider-specific signatures and ensuring the source IP address is from an
 * authorized payment gateway.
 *
 * Security considerations include strict validation of incoming webhook
 * signatures, rate limiting to prevent abuse, logging of all received webhooks
 * for audit purposes, and idempotency handling to prevent duplicate processing
 * of the same event. Each webhook is processed once and only once, even if the
 * same payload is received multiple times due to network issues or provider
 * retry attempts.
 *
 * This operation integrates with the shopping_mall_payment_webhooks database
 * table, which stores the raw webhook payload, event type, processing status,
 * processing timestamp, and error information (if any). The webhook data is
 * matched to corresponding payment records in the shopping_mall_payments table
 * to update payment statuses accordingly.
 *
 * Related operations: GET /payments/{paymentId} (to retrieve payment details),
 * PATCH /payments (to search for payments by various criteria).
 *
 * @param props.connection
 * @param props.body JSON payload containing payment event data from the
 *   external payment provider
 * @path /shoppingMall/payment-webhooks
 * @accessor api.functional.shoppingMall.payment_webhooks.post
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
