/**
 * Retrieve the detailed return information for a specific order return using
 * the order and return code identifiers.
 *
 * This operation retrieves a complete order return record from the
 * shopping_mall_order_returns database table. The return is uniquely identified
 * by the combination of an order code and a return code, which together form a
 * composite unique constraint. Each return represents a customer-initiated
 * return of items from a previously placed order.
 *
 * The system tracks return requests from initiation through processing and
 * final resolution. This endpoint returns detailed return information including
 * the return status, requested items, return reason, refund amount, return
 * shipping details, and any associated notes. Return information is retained as
 * part of the system's audit trail for financial reconciliation, customer
 * service, and fraud prevention purposes.
 *
 * Security considerations: Authorized customers can access their own returns,
 * while administrators can view all returns for customer service and fraud
 * investigation purposes. The operation ensures data integrity by verifying
 * that the return code is associated with the specified order code. Only the
 * customer who created the return or an administrator with appropriate
 * permissions can access this information.
 *
 * Related operations: The PATCH /orders/{orderCode}/returns endpoint can be
 * used to initiate new return requests, and the PUT
 * /orders/{orderCode}/returns/{returnCode} endpoint can be used to update
 * return details when additional information needs to be provided by the
 * customer or seller.
 *
 * @param props.connection
 * @param props.orderCode Unique business identifier code of the target order
 *   (global scope)
 * @param props.returnCode Unique business identifier code of the target return
 *   within the order (scoped to order)
 * @path /shoppingMall/admin/orders/:orderCode/returns/:returnCode
 * @accessor api.functional.shoppingMall.admin.orders.returns.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
