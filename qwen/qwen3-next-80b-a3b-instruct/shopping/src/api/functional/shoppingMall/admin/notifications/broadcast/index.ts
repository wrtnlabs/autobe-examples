/**
 * Create and dispatch a system-wide broadcast notification to all active users.
 * This operation allows admins to send critical system-wide announcements,
 * maintenance alerts, or urgent communications that must reach every active
 * user immediately. The notification content is predefined in the system
 * administration interface and submitted through this endpoint.
 *
 * The broadcast notification system is designed for emergency and high-priority
 * communications. All notifications created through this endpoint are stored in
 * the shopping_mall_notifications table and pushed to all currently active user
 * sessions via real-time messaging channels. Notifications are automatically
 * archived after 30 days but remain accessible for administrative review.
 *
 * Security: Only users with admin privileges can invoke this operation. The
 * system validates that the caller has appropriate permissions through the JWT
 * token. The notification text content is limited to 500 characters to ensure
 * readability and prevent abuse.
 *
 * This operation does not require any request parameters beyond the
 * authentication context as the actual notification content is pre-defined by
 * admins through the administrative dashboard. All broadcast notifications
 * originate from validated admin accounts and are subject to audit logging in
 * the shopping_mall_audit_logs table.
 *
 * @param props.connection
 * @param props.body Request body for creating a broadcast notification. This
 *   operation uses a predefined notification content from admin interface, so
 *   the request body expects a zero-content object to confirm the intent to
 *   broadcast.
 * @path /shoppingMall/admin/notifications/broadcast
 * @accessor api.functional.shoppingMall.admin.notifications.broadcast.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function create(
  connection: IConnection,
  props: create.Props,
): Promise<create.Response> {
  return true === connection.simulate
    ? create.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...create.METADATA,
          path: create.path(),
          status: null,
        },
        props.body,
      );
}
