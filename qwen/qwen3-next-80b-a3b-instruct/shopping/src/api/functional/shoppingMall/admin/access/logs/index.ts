import { IConnection } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";

import { IPageIShoppingMallAccessLog } from "../../../../../structures/IPageIShoppingMallAccessLog";

/**
 * Retrieve a paginated list of all access logs from the shoppingMall system.
 * This operation queries the shopping_mall_access_logs table to provide a
 * comprehensive security audit trail of all authentication events.
 *
 * The operation supports advanced filtering by actor type ('customer',
 * 'seller', 'admin'), action type ('login', 'logout', 'session_refresh',
 * 'token_regeneration'), application ('web_portal', 'mobile_app',
 * 'admin_dashboard'), and time range. Results are sorted chronologically with
 * support for pagination.
 *
 * Security implications: This operation requires administrative authorization
 * to prevent unauthorized access to security audit data. The logs contain
 * sensitive information about user authentication patterns and system access,
 * making this a critical compliance feature for SOC 2, ISO 27001, and financial
 * regulations.
 *
 * All access logs are immutable and append-only. This operation retrieves
 * historical records for forensic analysis, security investigations, and
 * compliance reporting purposes.
 *
 * Related operations: This complements the data-change-logs operation which
 * tracks modifications to business data, while this operation tracks system
 * access patterns.
 *
 * @param props.connection
 * @path /shoppingMall/admin/access/logs
 * @accessor api.functional.shoppingMall.admin.access.logs.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(connection: IConnection): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
      );
}
export namespace index {
  export type Response = IPageIShoppingMallAccessLog;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/admin/access/logs",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/shoppingMall/admin/access/logs";
  export const random = (): IPageIShoppingMallAccessLog =>
    typia.random<IPageIShoppingMallAccessLog>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}
