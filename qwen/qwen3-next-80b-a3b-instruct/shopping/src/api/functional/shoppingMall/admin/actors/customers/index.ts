import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

/**
 * Permanently remove a customer account from the shoppingMall platform.
 *
 * This operation deletes the customer record from the shopping_mall_customers
 * table. The deletion is permanent and cannot be undone. All associated data
 * including cart items, wishlists, order history, reviews, and loyalty points
 * will be persistently removed from the database.
 *
 * Security: Only authenticated administrators with 'admin' privileges can
 * perform this operation.
 *
 * Compliance: This hard delete operation is permitted only when required by
 * legal or regulatory obligations, or when requested by the customer for data
 * erasure under privacy regulations (e.g., GDPR Right to Erasure). The
 * operation will trigger audit logging of the deletion event.
 *
 * Relationships: This affects the following related entities that will also be
 * permanently removed:
 *
 * - Shopping_mall_customer_sessions (all sessions)
 * - Shopping_mall_carts (all active carts)
 * - Shopping_mall_cart_items (all cart items)
 * - Shopping_mall_wishlists (all wishlists)
 * - Shopping_mall_wishlist_items (all wishlist items)
 * - Shopping_mall_orders (all orders)
 * - Shopping_mall_order_items (all order items)
 * - Shopping_mall_order_payments (all payments)
 * - Shopping_mall_order_shipping (all shipping information)
 * - Shopping_mall_order_returns (all return requests)
 * - Shopping_mall_reviews (all reviews)
 * - Shopping_mall_review_images (all review images)
 * - Shopping_mall_review_reactions (all reactions)
 * - Shopping_mall_loyalty_points (all loyalty points balance)
 * - Shopping_mall_loyalty_point_transactions (all transaction history)
 * - Shopping_mall_notification_preferences (all notification preferences)
 * - Shopping_mall_alerter_preferences (all alert preferences)
 *
 * All DELETE operations on the shopping_mall_customers table are hard deletes
 * with no soft-delete flag. The previous soft-delete mechanism has been removed
 * for compliance with data minimization requirements in the platform's privacy
 * policy.
 *
 * @param props.connection
 * @param props.customerId Unique identifier of the target customer to be
 *   permanently deleted. This UUID references the id field in the
 *   shopping_mall_customers table.
 * @path /shoppingMall/admin/actors/customers/:customerId
 * @accessor api.functional.shoppingMall.admin.actors.customers.erase
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function erase(
  connection: IConnection,
  props: erase.Props,
): Promise<void> {
  return true === connection.simulate
    ? erase.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...erase.METADATA,
          path: erase.path(props),
          status: null,
        },
      );
}
export namespace erase {
  export type Props = {
    /**
     * Unique identifier of the target customer to be permanently deleted.
     * This UUID references the id field in the shopping_mall_customers
     * table.
     */
    customerId: string & tags.Format<"uuid">;
  };

  export const METADATA = {
    method: "DELETE",
    path: "/shoppingMall/admin/actors/customers/:customerId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/admin/actors/customers/${encodeURIComponent(props.customerId ?? "null")}`;
  export const random = (): void => typia.random<void>();
  export const simulate = (
    connection: IConnection,
    props: erase.Props,
  ): void => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: erase.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("customerId")(() => typia.assert(props.customerId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
