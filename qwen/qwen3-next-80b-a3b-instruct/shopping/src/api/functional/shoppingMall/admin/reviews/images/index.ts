import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallReviewImageSet } from "../../../../../structures/IShoppingMallReviewImageSet";

/**
 * Update the associated images for a specific product review on the
 * shoppingMall platform.
 *
 * This operation allows the review creator or an admin moderator to modify the
 * visual evidence associated with a product review. The operation replaces the
 * entire set of review images with the new set provided in the request.
 *
 * All existing review images linked to the review through the
 * shopping_mall_review_images table are deleted and replaced with the new
 * images provided in the request body. This ensures the review maintains a
 * clean, up-to-date set of visual documentation.
 *
 * The images provided must be URLs to images already uploaded to the content
 * delivery network, as the shoppingMall platform doesn't handle direct binary
 * file uploads in API calls. Each image URL must be a valid, permanent URI that
 * remains accessible after the operation completes.
 *
 * The review images are a subsidiary entity (shopping_mall_review_images) that
 * cannot exist independently from their parent review (shopping_mall_reviews).
 * The relationship is strictly one-to-many, where each image belongs to exactly
 * one review.
 *
 * This operation does not support partial updates - the entire set of images
 * for the review must be provided in each request, as this approach ensures
 * consistent visual representation and prevents orphaned or conflicting images
 * in the system.
 *
 * Security: This operation is restricted to the review's original creator
 * (matching shopping_mall_customer_id) or users with admin privileges.
 *
 * @param props.connection
 * @param props.reviewId Unique identifier of the target review whose images are
 *   being updated. This UUID must correspond to an existing review in the
 *   shopping_mall_reviews table.
 * @param props.body Request containing the new set of image URLs to associate
 *   with the review. The existing images for this review will be completely
 *   replaced with this new set.
 * @path /shoppingMall/admin/reviews/:reviewId/images
 * @accessor api.functional.shoppingMall.admin.reviews.images.update
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function update(
  connection: IConnection,
  props: update.Props,
): Promise<update.Response> {
  return true === connection.simulate
    ? update.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...update.METADATA,
          path: update.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace update {
  export type Props = {
    /**
     * Unique identifier of the target review whose images are being
     * updated. This UUID must correspond to an existing review in the
     * shopping_mall_reviews table.
     */
    reviewId: string & tags.Format<"uuid">;

    /**
     * Request containing the new set of image URLs to associate with the
     * review. The existing images for this review will be completely
     * replaced with this new set.
     */
    body: IShoppingMallReviewImageSet.IUpdate;
  };
  export type Body = IShoppingMallReviewImageSet.IUpdate;
  export type Response = IShoppingMallReviewImageSet;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/admin/reviews/:reviewId/images",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/shoppingMall/admin/reviews/${encodeURIComponent(props.reviewId ?? "null")}/images`;
  export const random = (): IShoppingMallReviewImageSet =>
    typia.random<IShoppingMallReviewImageSet>();
  export const simulate = (
    connection: IConnection,
    props: update.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: update.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("reviewId")(() => typia.assert(props.reviewId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
