import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallPaymentAnalytics } from "../../../../../structures/IShoppingMallPaymentAnalytics";
export * as reconciliation from "./reconciliation/index";

/**
 * Retrieve aggregated payment analytics and financial insights for the
 * platform.
 *
 * This operation provides summarized financial data across all payment
 * transactions recorded in the shopping_mall_payments and
 * shopping_mall_order_payments tables, enabling strategic business decisions
 * through real-time analytics. The system computes key performance indicators
 * including total revenue, transaction volume, average transaction value,
 * payment method distribution, regional payment patterns, and success/failure
 * rates.
 *
 * The analytics are computed dynamically by joining payment records with order
 * data, filtering for completed transactions, and grouping by time period,
 * payment method, and geographic region. This operation does not map to a
 * single database table but is a computed view derived from multiple payment
 * and order-related entities.
 *
 * Security and access: This endpoint is restricted to platform administrators
 * only, as it exposes sensitive financial metrics. All data is aggregated and
 * anonymized to prevent exposure of individual customer payment information.
 * The response contains no personally identifiable information and complies
 * with financial data privacy regulations.
 *
 * Implementation note: The operation executes a complex SQL query that joins
 * shopping_mall_payments and shopping_mall_order_payments tables, applies
 * time-based filters, and performs aggregations including SUM(total_amount),
 * COUNT(transaction_id), AVG(amount), and GROUP BY clauses for payment_method,
 * region, and date periods. This computed data serves as the foundation for
 * financial dashboards, revenue forecasting, and payment processing
 * optimization decisions.
 *
 * @param props.connection
 * @param props.body Query parameters for filtering payment analytics data by
 *   time range, payment method, and region.
 * @path /shoppingMall/admin/analytics/payments
 * @accessor api.functional.shoppingMall.admin.analytics.payments.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Query parameters for filtering payment analytics data by time range,
     * payment method, and region.
     */
    body: IShoppingMallPaymentAnalytics.IRequest;
  };
  export type Body = IShoppingMallPaymentAnalytics.IRequest;
  export type Response = IShoppingMallPaymentAnalytics;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/admin/analytics/payments",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/shoppingMall/admin/analytics/payments";
  export const random = (): IShoppingMallPaymentAnalytics =>
    typia.random<IShoppingMallPaymentAnalytics>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
