import { IShoppingMallFinancialReport } from "../../../../../structures/IShoppingMallFinancialReport";

/**
 * Generate a comprehensive financial report for the shoppingMall platform by
 * aggregating payment and order data across all transactions.
 *
 * This operation consolidates financial data from the shopping_mall_payments,
 * shopping_mall_orders, shopping_mall_order_payments,
 * shopping_mall_order_refunds, shopping_mall_payment_refunds,
 * shopping_mall_payment_audit_logs, and shopping_mall_payment_reconciliation
 * tables to provide a complete financial overview. It calculates total revenue,
 * net profit, refunds, transaction fees, and reconciliation discrepancies to
 * deliver actionable financial insights for platform administrators.
 *
 * The financial report is computed by joining payment records with their
 * corresponding orders and applying appropriate business rules for revenue
 * recognition and cost allocation. Payment processing fees are applied based on
 * the configured fee structure, and refunds are subtracted from gross revenue
 * to determine net revenue. The reconciliation process compares payment gateway
 * settlement reports with internal platform records to identify any
 * discrepancies that require investigation.
 *
 * The report data is computed in real-time through SQL aggregations on the
 * underlying tables, with all currency conversions applied using the locked
 * exchange rates from the shopping_mall_payment_exchange_rates table. The
 * results reflect completed transactions only, excluding pending or failed
 * payment attempts. This operation provides administrators with the critical
 * financial metrics needed for platform management, budget planning, and
 * financial compliance.
 *
 * Related operations: The data in this report can be filtered by date range,
 * payment method, or seller to generate more specific financial analyses. This
 * operation is read-only and serves as the authoritative financial report for
 * the platform.
 *
 * @param props.connection
 * @path /shoppingMall/admin/reports/financial
 * @accessor api.functional.shoppingMall.admin.reports.financial.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(connection: IConnection): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
      );
}
export namespace index {
  export type Response = IShoppingMallFinancialReport;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/admin/reports/financial",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/shoppingMall/admin/reports/financial";
  export const random = (): IShoppingMallFinancialReport =>
    typia.random<IShoppingMallFinancialReport>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}
