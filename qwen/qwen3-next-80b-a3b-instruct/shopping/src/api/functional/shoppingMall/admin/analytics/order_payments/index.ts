/**
 * Retrieve aggregated analytics on order payments across the shopping mall
 * platform.
 *
 * This operation provides comprehensive financial insights by querying the
 * shopping_mall_order_payments table and joining with shopping_mall_orders and
 * shopping_mall_payments to calculate total revenue, payment method
 * distribution, and transaction success rates over customizable time periods.
 * The analysis supports business intelligence needs such as identifying payment
 * trends, detecting anomalies in processing, and evaluating payment gateway
 * performance.
 *
 * The system aggregates data across multiple dimensions including date range,
 * payment method type, transaction status, and currency. This operation returns
 * statistical summaries rather than individual transaction records, ensuring
 * performance optimization for large datasets. The underlying implementation
 * combines SQL GROUP BY clauses with window functions to compute metrics like
 * daily revenue totals, average transaction amounts, and conversion rates.
 *
 * Security policy restricts access to administrators only, as this data
 * includes sensitive financial metrics. The operation enforces escrow period
 * policies to prevent financial reporting on incomplete settlement cycles.
 * Related operations include GET /payments for transaction-level detail and GET
 * /orders for order-level analytics.
 *
 * Resource constraints ensure this operation returns paginated results with a
 * maximum of 500 records per page to prevent system overload during high-demand
 * periods.
 *
 * @param props.connection
 * @param props.body Filtering and aggregation parameters for payment analytics
 *   calculation with date range, payment method filters, and currency
 *   selectors.
 * @path /shoppingMall/admin/analytics/order-payments
 * @accessor api.functional.shoppingMall.admin.analytics.order_payments.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Filtering and aggregation parameters for payment analytics
     * calculation with date range, payment method filters, and currency
     * selectors.
     */
    body: IShoppingMallOrderPayment.IRequest;
  };
  export type Body = IShoppingMallOrderPayment.IRequest;
  export type Response = IPageIShoppingMallOrderPayment.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/admin/analytics/order-payments",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/shoppingMall/admin/analytics/order-payments";
  export const random = (): IPageIShoppingMallOrderPayment.ISummary =>
    typia.random<IPageIShoppingMallOrderPayment.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
