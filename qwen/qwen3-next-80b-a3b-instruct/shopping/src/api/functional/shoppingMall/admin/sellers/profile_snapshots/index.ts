import { HttpError, IConnection } from "@nestia/fetcher";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";

import { IShoppingMallSellerProfileSnapshot } from "../../../../../structures/IShoppingMallSellerProfileSnapshot";

/**
 * Retrieve the complete immutable history of a seller's profile changes.
 *
 * This endpoint returns a chronological list of all snapshot records of a seller's shop name, description, and logo as they appeared at the time of each change. This history is critical for platform administrators to audit changes and for dispute resolution. Each snapshot captures the exact state of the seller's profile at the moment it was edited, ensuring that historical representations of the seller are permanently preserved.
 *
 * According to the platform's mandatory snapshot principle (12-snapshot-principle.md), all profile modifications are recorded as immutable snapshots in the shopping_mall_seller_profile_snapshots table. These records are never deleted, modified, or overwritten.
 *
 * This operation is accessible only to administrators, as indicated by the /admin/ path segment. The returned snapshots are ordered from most recent (newest) to oldest. Each snapshot contains only the data as it existed at that point in time — not the current state. Even if a seller updates their name or logo today, all previous snapshots remain unchanged and accurately reflect how the seller appeared during past transactions.
 *
 * This endpoint does not return the current profile (which is not stored in shopping_mall_seller_profiles due to violation of the snapshot principle) — only historical snapshots.
 *
 * @param props.connection
 * @param props.sellerId The unique identifier of the seller whose profile snapshot history is being requested.
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor admin
 * @x-autobe-specification Query shopping_mall_seller_profile_snapshots table filtered by seller_id = {sellerId}.
 * Order results by created_at DESC to show most recent snapshot first.
 * Return all columns for each snapshot: id, seller_id, name, description, logo_url, created_at.
 * Do not join with other tables; snapshots are self-contained.
 * Return list of up to 50 snapshots (primarily, very few projects have >10).
 * No pagination or search parameters required; entire history is small and primary use case is full display.
 * @path /shoppingMall/admin/sellers/:sellerId/profile-snapshots
 * @accessor api.functional.shoppingMall.admin.sellers.profile_snapshots.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
      );
}
export namespace index {
  export type Props = {
    /**
     * The unique identifier of the seller whose profile snapshot history is being requested.
     */
    sellerId: string;
  };
  export type Response = IShoppingMallSellerProfileSnapshot;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/admin/sellers/:sellerId/profile-snapshots",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/admin/sellers/${encodeURIComponent(props.sellerId ?? "null")}/profile-snapshots`;
  export const random = (): IShoppingMallSellerProfileSnapshot =>
    typia.random<IShoppingMallSellerProfileSnapshot>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("sellerId")(() => typia.assert(props.sellerId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
