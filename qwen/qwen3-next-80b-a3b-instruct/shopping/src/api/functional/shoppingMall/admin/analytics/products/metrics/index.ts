import { IConnection } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";

import { IShoppingMallProductAnalyticsMetrics } from "../../../../../../structures/IShoppingMallProductAnalyticsMetrics";

/**
 * Retrieve comprehensive product analytics metrics for the shoppingMall
 * platform, aggregating sales performance and customer viewing behavior across
 * all products.
 *
 * This operation computes aggregated statistics from the
 * shopping_mall_product_sales_stats and shopping_mall_product_view_stats
 * database tables to provide administrators with insights into product
 * popularity, conversion rates, and market performance. The system combines
 * sales data (total units sold, revenue generated) with view data (total views,
 * unique viewers) to calculate key performance indicators such as conversion
 * rate and sales per view.
 *
 * Security considerations: This analytics endpoint is restricted to admin
 * actors only because it exposes sensitive business intelligence that could
 * inform competitive strategies or internal pricing decisions. All data is
 * aggregated and does not reveal personally identifiable customer information.
 * The operation is designed to be read-only and does not modify any underlying
 * data.
 *
 * Implementation notes: This endpoint does NOT map to a single database table.
 * Instead, it executes two parallel aggregate queries:
 *
 * 1. SELECT SUM(units_sold) AS total_sales, SUM(revenue) AS total_revenue,
 *    COUNT(*) AS total_products_analyzed FROM
 *    shopping_mall_product_sales_stats
 * 2. SELECT SUM(total_views) AS total_views, SUM(unique_viewers) AS
 *    unique_viewers, AVG(view_duration_seconds) AS avg_view_duration FROM
 *    shopping_mall_product_view_stats
 *
 * The results are then combined into a single JSON response structure optimized
 * for dashboard visualization.
 *
 * Related operations: GET /analytics/products/top-sellers (returns ranked
 * list), PATCH /analytics/products/trends (returns time-series data with date
 * filtering), GET /products/{productId}/details (detailed view of single
 * product).
 *
 * @param props.connection
 * @path /shoppingMall/admin/analytics/products/metrics
 * @accessor api.functional.shoppingMall.admin.analytics.products.metrics.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(connection: IConnection): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
      );
}
export namespace index {
  export type Response = IShoppingMallProductAnalyticsMetrics;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/admin/analytics/products/metrics",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/shoppingMall/admin/analytics/products/metrics";
  export const random = (): IShoppingMallProductAnalyticsMetrics =>
    typia.random<IShoppingMallProductAnalyticsMetrics>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}
