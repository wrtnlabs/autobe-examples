/**
 * Retrieve a specific customer question and its associated answer for a product
 * in the shopping mall platform. This operation operates on the
 * shopping_mall_product_questions database table which stores questions
 * submitted by customers about products and the corresponding responses from
 * sellers.
 *
 * The operation accepts two path parameters: the unique product identifier and
 * the specific question identifier, enabling precise retrieval of individual
 * Q&A entries. This endpoint serves the business need for customers to view
 * detailed product-related discussions, helping them make informed purchase
 * decisions based on peer experiences.
 *
 * Security is enforced through user authentication context, where customers can
 * view only questions they submitted or answers provided by sellers for
 * products they've purchased. System administrators have elevated access to
 * view all questions for moderation purposes.
 *
 * The response includes the full question text, submission timestamp, answer
 * text (if available), answer timestamp, and the seller's identifier -
 * providing complete context for the product inquiry without exposing sensitive
 * user information. This operation is read-only and does not modify any data.
 *
 * The product and question identifiers are referenced using composite unique
 * constraints in the database schema, ensuring each question is uniquely
 * identifiable within its associated product context.
 *
 * Related operations:
 *
 * - POST /products/{productId}/questions creates new product questions
 * - PATCH /products/{productId}/questions retrieves all questions for a product
 * - PUT /products/{productId}/questions/{questionId} updates a question
 * - DELETE /products/{productId}/questions/{questionId} removes a question
 *
 * @param props.connection
 * @param props.productId Unique identifier of the target product (global scope)
 * @param props.questionId Unique identifier of the target product question
 *   (scoped to product)
 * @path /shoppingMall/admin/products/:productId/questions/:questionId
 * @accessor api.functional.shoppingMall.admin.products.questions.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
