/**
 * This operation computes customer behavioral analytics by aggregating data
 * from multiple tables to identify purchasing patterns, engagement frequency,
 * and product interest trends.
 *
 * Implementation note: This does NOT map to a single database table - instead
 * it executes a complex multi-table query that combines data from
 * shopping_mall_customers, shopping_mall_orders, shopping_mall_order_items,
 * shopping_mall_product_variants, shopping_mall_product_view_stats, and
 * shopping_mall_wishlist_items to derive meaningful behavioral insights. The
 * operation calculates customer purchase frequency, average order value,
 * category preference distribution, time between purchases, product
 * view-to-purchase conversion rates, and wishlist-to-purchase completion
 * rates.
 *
 * The data is aggregated at the customer level using GROUP BY customer_id, with
 * metrics calculated as:
 *
 * - Purchase frequency: COUNT of orders grouped by customer_id
 * - Average order value: AVG of order total amounts
 * - Category preference: Most frequently purchased category per customer (using
 *   LEFT JOIN with shopping_mall_product_variants → shopping_mall_products →
 *   shopping_mall_categories)
 * - View-to-purchase ratio: COUNT of product_view_stats entries divided by COUNT
 *   of order_items for same customer
 * - Wishlist conversion: COUNT of wishlist_items that have corresponding
 *   order_items divided by total wishlist_items
 * - Days since last purchase: MAX(order_date) for each customer calculated
 *   against current date
 *
 * The result set returns a summary profile for each customer that reflects
 * their behavioral characteristics without exposing personally identifiable
 * information beyond the customer_id reference. This aggregated analytical data
 * serves the business need for customer segmentation, personalized marketing
 * campaigns, and churn prediction. The system does NOT store these metrics as
 * physical records - they are computed on-demand to ensure real-time accuracy.
 *
 * Security note: This operation is restricted to admin actors only as it
 * exposes sensitive behavioral patterns that could be misused if accessible to
 * regular users.
 *
 * @param props.connection
 * @path /shoppingMall/admin/analytics/customers/behavior
 * @accessor api.functional.shoppingMall.admin.analytics.customers.behavior.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(connection: IConnection): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
      );
}
export namespace index {
  export type Response = IShoppingMallCustomerBehaviorAnalytics;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/admin/analytics/customers/behavior",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/shoppingMall/admin/analytics/customers/behavior";
  export const random = (): IShoppingMallCustomerBehaviorAnalytics =>
    typia.random<IShoppingMallCustomerBehaviorAnalytics>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}
