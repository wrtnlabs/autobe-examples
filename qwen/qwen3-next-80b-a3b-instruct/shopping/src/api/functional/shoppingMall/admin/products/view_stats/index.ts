/**
 * Retrieve detailed view statistics for a specific product in the shopping mall
 * platform. This operation operates on the shopping_mall_product_view_stats
 * table to provide comprehensive analytics about product engagement metrics,
 * including total views, unique visitors, view duration metrics, and regional
 * distribution data.
 *
 * The system collects product view data automatically through client-side
 * tracking when customers browse product pages, recording each view in the
 * shopping_mall_product_view_stats table. This data is aggregated and persisted
 * with records updated in real-time as viewing activity occurs. The operation
 * provides insights into product popularity, customer interest trends, and
 * content effectiveness for both sellers and administrators.
 *
 * Security and access control: Only authenticated users with appropriate
 * permissions can access detailed view statistics. The operation performs
 * ownership verification to ensure users can only access statistics for
 * products they have appropriate access rights to, either through direct
 * product ownership (sellers) or administrative privileges. No sensitive
 * personal data is exposed in the statistics.
 *
 * The response includes calculated metrics such as percentage change over time
 * periods, conversion rates from views to add-to-cart actions, and demographic
 * distribution of viewers. These metrics are computed on demand from the
 * aggregated view data in the database, rather than being stored directly, to
 * ensure the statistics always reflect the most current data.
 *
 * Related operations: GET /products/{productId} retrieves product details;
 * PATCH /products searches products by criteria; POST /products creates new
 * product listings; DELETE /products/{productId} removes product listings from
 * the catalog.
 *
 * @param props.connection
 * @param props.productId Unique identifier of the target product. This
 *   identifier corresponds to the product_id field in the
 *   shopping_mall_products table and is used to retrieve the corresponding view
 *   statistics from the shopping_mall_product_view_stats table.
 * @path /shoppingMall/admin/products/:productId/view-stats
 * @accessor api.functional.shoppingMall.admin.products.view_stats.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
