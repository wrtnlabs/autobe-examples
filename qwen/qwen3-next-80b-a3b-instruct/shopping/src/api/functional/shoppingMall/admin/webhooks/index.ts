/**
 * Retrieve a specific payment webhook event record from the system's
 * transaction notification logs. This operation queries the
 * shopping_mall_payment_webhooks database table, which captures all webhook
 * delivery attempts, including request payloads, response statuses, retry
 * counts, and delivery timestamps.
 *
 * The webhook event contains critical integration metadata for system-to-system
 * communication between the shoppingMall platform and external payment
 * processors, ERP systems, and fulfillment services. Each webhook represents a
 * single delivery attempt of an event notification (e.g., payment_completed,
 * order_shipped) to a registered endpoint URL.
 *
 * System security requires that only administrative users can view webhook
 * records, as these contain potentially sensitive system integration details.
 * The operation returns the complete webhook record including payload, response
 * headers, and delivery status for troubleshooting and debugging purposes.
 * Admins can use this endpoint to verify that webhook deliveries have been
 * successfully processed by external systems and diagnose integration
 * failures.
 *
 * When requesting a webhook by its ID, the system validates the existence of
 * the specific webhook record in the database and returns it with all
 * attributes. No pagination or filtering is supported for this single-record
 * retrieval endpoint. The webhook ID is a UUID string that uniquely identifies
 * the webhook record after creation by the system during event delivery
 * attempts.
 *
 * Related operations:
 *
 * - PATCH /webhooks - List all webhook delivery attempts with search and
 *   pagination
 * - DEL /webhooks/{id} - Delete a webhook record by ID (administrative
 *   maintenance)
 * - GET /webhooks/{id}/resend - Resend a specific webhook delivery
 *
 * @param props.connection
 * @param props.id Unique identifier of the webhook event record. This is the
 *   primary key UUID of the shopping_mall_payment_webhooks table in the
 *   database. Note that webhook IDs are system-generated at the time of webhook
 *   creation and cannot be created or modified by users.
 * @path /shoppingMall/admin/webhooks/:id
 * @accessor api.functional.shoppingMall.admin.webhooks.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
