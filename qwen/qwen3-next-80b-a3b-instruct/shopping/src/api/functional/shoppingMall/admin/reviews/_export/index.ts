import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallProductReview } from "../../../../../structures/IShoppingMallProductReview";
import { IExportIShoppingMallReview } from "../../../../../structures/IExportIShoppingMallReview";

/**
 * This export operation retrieves all product review records from the
 * shopping_mall_reviews table for comprehensive analytics, compliance
 * reporting, and data migration purposes. This endpoint serves administrative
 * and analytical needs, providing a complete dataset of customer feedback.
 *
 * Review data comes from the shopping_mall_reviews table, which contains
 * review_id, customer_id, product_id, rating, title, content, status,
 * created_at, and updated_at fields. The export supports filtering via request
 * parameters to subset results by date range, product category, review status,
 * or customer segment.
 *
 * Security: This export operation is restricted to admin actors only, as it
 * exposes sensitive customer data, including potentially personally
 * identifiable information. Audit logging is automatically generated for all
 * export requests, recording the admin user identity, timestamp, IP address,
 * and requested parameters.
 *
 * Implementation Note: The response contains a pre-processed CSV or JSON file
 * with all review data, including nested structures for reviewer and product
 * information. This export avoids circular references by using ISummary
 * variants for associated entities. Dates are formatted in ISO 8601, and all
 * text fields are properly HTML-escaped to prevent injection vulnerabilities.
 *
 * Related Operations: GET /reviews (list reviews), PATCH /reviews (search
 * reviews). This export operation should be used after filtering via PATCH
 * /reviews when specific subsets are required.
 *
 * @param props.connection
 * @param props.body Filtering, sorting, and export format parameters for
 *   reviews data export
 * @path /shoppingMall/admin/reviews/export
 * @accessor api.functional.shoppingMall.admin.reviews._export.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Filtering, sorting, and export format parameters for reviews data
     * export
     */
    body: IShoppingMallProductReview.IRequest;
  };
  export type Body = IShoppingMallProductReview.IRequest;
  export type Response = IExportIShoppingMallReview;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/admin/reviews/export",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/shoppingMall/admin/reviews/export";
  export const random = (): IExportIShoppingMallReview =>
    typia.random<IExportIShoppingMallReview>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
