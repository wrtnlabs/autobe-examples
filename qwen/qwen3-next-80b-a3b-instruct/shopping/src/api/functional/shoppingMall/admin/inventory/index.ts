/**
 * Manually adjust the inventory quantity for a specific product variant.
 *
 * This operation allows a seller to record inventory adjustments for non-purchase or non-cancellation reasons, such as damaged goods, theft, spoilage, or internal corrections. It creates a permanent inventory history record that changes the current stock level while preserving full audit trail.
 *
 * The adjustment can be either positive (increasing stock) or negative (decreasing stock). For positive adjustments, the reason should describe how the inventory was replenished. For negative adjustments, the reason must document the cause of loss (e.g., "damage", "theft", or "miscount"). Every adjustment triggers an immutable inventory log entry that records the change quantity, reason, timestamp, and actor identity.
 *
 * This operation is strictly for seller-initiated inventory corrections. System-generated inventory changes (such as order purchases, cancellations, or refunds) are handled automatically by the system and do not require this API endpoint. The operation requires an explanation to maintain accountability and traceability of all inventory movements.
 *
 * The variant must be owned by the authenticated seller. The seller cannot adjust inventory for products they do not own. This ensures that inventory adjustments are confined to each seller's own products and prevents unauthorized modifications. The adjustment quantity can be any integer value (positive or negative), with no enforced bounds other than database limits.
 *
 * This API operation is essential for maintaining accurate physical inventory records that match real-world conditions, especially in environments where products may be damaged, lost, or incorrectly counted.
 *
 * The corresponding database action is documented in 05-inventory-handling.md: "WHEN a seller needs to adjust inventory (loss, damage, etc.), THE system SHALL: [create inventory record]".
 *
 * @param props.connection
 * @param props.variantId Unique identifier of the product variant to adjust inventory
 * @param props.body Inventory adjustment details including quantity change and reason
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor admin
 * @x-autobe-specification Validate that variant belongs to authenticated seller.
 * Construct inventory log record with:
 * - variant_id: from path parameter
 * - quantity_change: from requestBody.quantity
 * - reason: from requestBody.reason
 * - operator_id: from authenticated user context
 * - timestamp: current UTC time
 * - record_type: 'adjustment'
 *
 * Update product variant's stock_quantity by adding quantity_change.
 *
 * Use atomic transaction to ensure stock_quantity is updated only after inventory log is successfully written.
 *
 * If stock_quantity would become negative due to adjustment, allow it (inventory can be negative during adjustment process; system will handle negative inventory as stock deficiency).
 *
 * Return success status without returning updated stock quantity to prevent race conditions.
 *
 * Log audit event with actor, variant, change, and action type.
 * @path /shoppingMall/admin/inventory/:variantId/adjust
 * @accessor api.functional.shoppingMall.admin.inventory.adjust
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function adjust(
  connection: IConnection,
  props: adjust.Props,
): Promise<void> {
  return true === connection.simulate
    ? adjust.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...adjust.METADATA,
          path: adjust.path(props),
          status: null,
        },
        props.body,
      );
}
