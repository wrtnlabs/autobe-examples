import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IPageIShoppingMallCartItem } from "../../../../../structures/IPageIShoppingMallCartItem";

/**
 * Retrieve a paginated list of cart items associated with a specific shopping
 * cart in the shoppingMall system. This operation operates on the
 * shopping_mall_cart_items table and allows authorized users to fetch all
 * products contained within a particular cart session.
 *
 * The cart items are sorted by creation timestamp in descending order, with
 * default pagination of 20 items per page. Each cart item includes detailed
 * product variant information, quantity, pricing, and seller reference as
 * captured at the time the item was added to the cart. This ensures consistency
 * even if product prices or inventory levels change after the item was added to
 * the cart.
 *
 * Authorization requires active user authentication: only the cart owner
 * (customer) or an administrator can access this data. For customer access, the
 * system verifies that the requesting user's authenticated session matches the
 * owner of the cart. Admins can view any cart's items for support and auditing
 * purposes.
 *
 * This operation is primarily used by customers during the checkout process to
 * review their selected items, and by platform administrators when assisting
 * customers with order inquiries or troubleshooting cart-related issues. It
 * integrates with the shopping_mall_carts and shopping_mall_product_variants
 * tables to provide comprehensive cart context.
 *
 * Related operations: Create cart item (POST /carts/{cartId}/items), Remove
 * cart item (DELETE /carts/{cartId}/items/{itemId}), Update cart item quantity
 * (PUT /carts/{cartId}/items/{itemId}).
 *
 * @param props.connection
 * @param props.cartId Unique identifier of the target shopping cart in the
 *   database. The cart_id is a UUID that uniquely identifies the
 *   shopping_mall_carts record. This parameter is required to scope the cart
 *   items to a specific cart session.
 * @path /shoppingMall/admin/carts/:cartId/items
 * @accessor api.functional.shoppingMall.admin.carts.items.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
      );
}
export namespace index {
  export type Props = {
    /**
     * Unique identifier of the target shopping cart in the database. The
     * cart_id is a UUID that uniquely identifies the shopping_mall_carts
     * record. This parameter is required to scope the cart items to a
     * specific cart session.
     */
    cartId: string & tags.Format<"uuid">;
  };
  export type Response = IPageIShoppingMallCartItem.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/admin/carts/:cartId/items",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/admin/carts/${encodeURIComponent(props.cartId ?? "null")}/items`;
  export const random = (): IPageIShoppingMallCartItem.ISummary =>
    typia.random<IPageIShoppingMallCartItem.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("cartId")(() => typia.assert(props.cartId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
