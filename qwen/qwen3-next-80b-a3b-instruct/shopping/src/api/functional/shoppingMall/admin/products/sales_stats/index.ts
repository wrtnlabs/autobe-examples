import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallProductSalesStat } from "../../../../../structures/IShoppingMallProductSalesStat";

/**
 * Retrieve sales statistics for a specific product from the
 * shopping_mall_product_sales_stats table. This operation provides
 * comprehensive sales analytics for the specified product, including total
 * units sold, revenue generated, average sale price, sales volume trends over
 * time, and customer purchase patterns.
 *
 * The system aggregates sales data from the shopping_mall_order_items and
 * shopping_mall_products tables to compute these statistics. The operation
 * filters results by the specified productId and returns aggregated metrics
 * across all completed orders.
 *
 * The response includes both summary statistics and historical trends, enabling
 * users to identify patterns such as seasonal buying behavior, product
 * popularity shifts, and pricing effectiveness. The implementation leverages
 * computed aggregations from the underlying sales data rather than reading from
 * a precomputed statistics table, ensuring data accuracy and real-time
 * relevance.
 *
 * @param props.connection
 * @param props.productId Unique identifier of the target product whose sales
 *   statistics are being retrieved
 * @path /shoppingMall/admin/products/:productId/sales-stats
 * @accessor api.functional.shoppingMall.admin.products.sales_stats.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
      );
}
export namespace index {
  export type Props = {
    /**
     * Unique identifier of the target product whose sales statistics are
     * being retrieved
     */
    productId: string & tags.Format<"uuid">;
  };
  export type Response = IShoppingMallProductSalesStat;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/admin/products/:productId/sales-stats",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/admin/products/${encodeURIComponent(props.productId ?? "null")}/sales-stats`;
  export const random = (): IShoppingMallProductSalesStat =>
    typia.random<IShoppingMallProductSalesStat>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("productId")(() => typia.assert(props.productId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
