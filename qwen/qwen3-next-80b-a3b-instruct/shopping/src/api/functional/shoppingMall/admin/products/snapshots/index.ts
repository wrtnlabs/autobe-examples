/**
 * Retrieve product snapshot history for the specified product. This operation
 * queries the shopping_mall_product_snapshots table to return historical
 * versions of product metadata including pricing, inventory, name, description,
 * and category changes. Each snapshot represents a point-in-time record of the
 * product's state when a significant change occurred, such as price
 * adjustments, inventory updates, or attribute modifications.
 *
 * The operation provides a pagination-compliant interface with comprehensive
 * filtering, enabling users to analyze product evolution over time. Snapshot
 * data is optimized for performance and includes timestamps, actor information,
 * and change descriptions to support advanced analytics and audit requirements.
 * This endpoint serves critical business needs for product history review,
 * compliance auditing, and change impact analysis.
 *
 * Security: Access to product snapshots requires the user to be an admin or to
 * have explicit permission to view product details. Non-admin users can only
 * access snapshots for products they own or manage. The request may specify
 * start and end dates to limit the date range of snapshot records returned.
 *
 * Implementation note: This operation does not map to any single entity's
 * primary data; it serves as a read-only audit trail derived from real-time
 * changes to the shopping_mall_products table. The system automatically creates
 * snapshot records whenever product fields are modified via the
 * IShoppingMallProduct.IUpdate request.
 *
 * Related operations: GET /products/{productId} (current product details), PUT
 * /products/{productId} (update product and trigger new snapshot).
 *
 * @param props.connection
 * @param props.productId Unique identifier of the target product. This must be
 *   a UUID format string representing a valid product in the
 *   shopping_mall_products table.
 * @param props.body Search and filtering criteria for product snapshot records
 *   including date ranges, change types, and pagination parameters.
 * @path /shoppingMall/admin/products/:productId/snapshots
 * @accessor api.functional.shoppingMall.admin.products.snapshots.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Unique identifier of the target product. This must be a UUID format
     * string representing a valid product in the shopping_mall_products
     * table.
     */
    productId: string & tags.Format<"uuid">;

    /**
     * Search and filtering criteria for product snapshot records including
     * date ranges, change types, and pagination parameters.
     */
    body: IShoppingMallProductSnapshot.IRequest;
  };
  export type Body = IShoppingMallProductSnapshot.IRequest;
  export type Response = IPageIShoppingMallProductSnapshot;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/admin/products/:productId/snapshots",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/shoppingMall/admin/products/${encodeURIComponent(props.productId ?? "null")}/snapshots`;
  export const random = (): IPageIShoppingMallProductSnapshot =>
    typia.random<IPageIShoppingMallProductSnapshot>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("productId")(() => typia.assert(props.productId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
