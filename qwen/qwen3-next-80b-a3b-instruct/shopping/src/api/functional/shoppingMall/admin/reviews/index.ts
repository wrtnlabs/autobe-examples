import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";
export * as images from "./images/index";

/**
 * Permanently delete a product review from the shoppingMall platform.
 *
 * This operation performs a hard delete of a review record from the
 * shopping_mall_reviews table. Unlike soft deletion which marks records as
 * deleted with a timestamp, this operation completely removes the review from
 * the database with no possibility of recovery.
 *
 * This deletion is permanent and irreversible. All associated review images in
 * the shopping_mall_review_images table are also automatically deleted through
 * database foreign key cascading when a parent review is deleted.
 *
 * Security: Only the original review creator or an admin moderator can delete a
 * review. The operation verifies the requesting user's identity against the
 * review's shopping_mall_customer_id field or checks for admin privileges.
 *
 * This operation is designed for extreme cases such as user account
 * termination, extensive moderation violations, or legal compliance
 * requirements where complete data erasure is mandated.
 *
 * @param props.connection
 * @param props.reviewId Unique identifier of the target review to be deleted.
 *   This is a UUID that corresponds to the primary key in the
 *   shopping_mall_reviews table.
 * @path /shoppingMall/admin/reviews/:reviewId
 * @accessor api.functional.shoppingMall.admin.reviews.erase
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function erase(
  connection: IConnection,
  props: erase.Props,
): Promise<void> {
  return true === connection.simulate
    ? erase.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...erase.METADATA,
          path: erase.path(props),
          status: null,
        },
      );
}
export namespace erase {
  export type Props = {
    /**
     * Unique identifier of the target review to be deleted. This is a UUID
     * that corresponds to the primary key in the shopping_mall_reviews
     * table.
     */
    reviewId: string & tags.Format<"uuid">;
  };

  export const METADATA = {
    method: "DELETE",
    path: "/shoppingMall/admin/reviews/:reviewId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/admin/reviews/${encodeURIComponent(props.reviewId ?? "null")}`;
  export const random = (): void => typia.random<void>();
  export const simulate = (
    connection: IConnection,
    props: erase.Props,
  ): void => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: erase.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("reviewId")(() => typia.assert(props.reviewId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
