/**
 * Retrieve compliance data exports for audit and regulatory purposes. This
 * operation queries the shopping_mall_compliance_records and
 * shopping_mall_data_exports tables to generate comprehensive compliance
 * reports with timestamps, user actions, and export metadata. The results are
 * filtered by compliance status, export type, and date range.
 *
 * Security considerations mandate that this endpoint is accessible only to
 * admin actors due to the sensitive nature of compliance data, which includes
 * personally identifiable information, regulatory documentation, and audit
 * trails. The operation enforces strict access controls at both the API layer
 * and the database query level.
 *
 * Implementation requires pagination to handle large datasets that may span
 * months or years of compliance records. Sorting is available by export date,
 * compliance status, and export type. Search functionality enables full-text
 * search across export descriptions and user identifiers.
 *
 * The response includes a standardized summary representation of each
 * compliance export record, containing essential metadata for audit review
 * without exposing full detailed records (which require individual retrieval).
 * This follows security best practices for list endpoints.
 *
 * Related operations: GET /compliance/data-exports/{exportId} to retrieve full
 * detailed records of specific exports.
 *
 * @param props.connection
 * @param props.body Search, filter, and pagination parameters for compliance
 *   data export retrieval
 * @path /shoppingMall/admin/compliance/data-exports
 * @accessor api.functional.shoppingMall.admin.compliance.data_exports.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Search, filter, and pagination parameters for compliance data export
     * retrieval
     */
    body: IShoppingMallDataExports.IRequest;
  };
  export type Body = IShoppingMallDataExports.IRequest;
  export type Response = IPageIShoppingMallDataExports.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/admin/compliance/data-exports",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/shoppingMall/admin/compliance/data-exports";
  export const random = (): IPageIShoppingMallDataExports.ISummary =>
    typia.random<IPageIShoppingMallDataExports.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
