/**
 * Retrieve the payment details for a specific order using its unique order
 * number.
 *
 * This operation fetches the complete payment information associated with an
 * order, including payment status, amount, currency, transaction ID, and
 * processing timestamp. The payment record is maintained in a 1:1 relationship
 * with the order entity in the database, and this endpoint provides read-only
 * access to this financial data.
 *
 * Security: This operation requires authentication as the order owner or an
 * administrator. The order number serves as a human-readable identifier that
 * maps to the internal UUID-based order ID. The payment details are returned in
 * the order's currency and include all financial metadata recorded at the time
 * of payment processing.
 *
 * Implementation: The system joins the shopping_mall_orders table with the
 * shopping_mall_order_payments table using the order_number as a lookup key and
 * returns a structured payment record with all relevant financial fields.
 *
 * Related operations: PUT /orders/{orderNumber}/payment (update payment status
 * for pre-authorized transactions), GET /orders/{orderNumber} (retrieve order
 * summary including payment status).
 *
 * @param props.connection
 * @param props.orderNumber Unique human-readable identifier for the order in
 *   format ORD-YYYYMMDD-NNNNN. Must exactly match the order_number field in the
 *   shopping_mall_orders table.
 * @path /shoppingMall/admin/orders/:orderNumber/payment
 * @accessor api.functional.shoppingMall.admin.orders.payment.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
