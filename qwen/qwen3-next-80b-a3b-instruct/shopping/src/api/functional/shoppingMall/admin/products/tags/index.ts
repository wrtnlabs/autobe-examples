import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

/**
 * Remove a specific tag from a product. This operation permanently deletes the
 * association between a product and a tag in the shopping_mall_product_tags
 * table. The tag is not deleted from the system, only the relationship between
 * the product and tag is removed. This allows tags to be reused across multiple
 * products while maintaining independent associations for each product.
 *
 * This operation requires successful authentication and appropriate
 * permissions. Customer users can only remove tags from products they have
 * purchased. Seller users can remove tags from products they own in their
 * catalog. Admin users can remove tags from any product in the system. The
 * operation does not affect the underlying product or tag records in the
 * shopping_mall_products or shopping_mall_product_tags tables.
 *
 * The path parameters productId and tagId must correspond to valid, existing
 * records that have an established relationship. If the specified product and
 * tag are not associated, the operation will return a 404 error. This operation
 * does not support batch removal or wildcard deletion.
 *
 * @param props.connection
 * @param props.productId Unique identifier of the target product. This
 *   identifier must match a valid product in the shopping_mall_products table
 *   and must correspond to the product that has the tag association to be
 *   removed.
 * @param props.tagId Unique identifier of the target tag. This identifier must
 *   match a valid tag in the shopping_mall_product_tags table and must
 *   correspond to the tag associated with the product being removed.
 * @path /shoppingMall/admin/products/:productId/tags/:tagId
 * @accessor api.functional.shoppingMall.admin.products.tags.erase
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function erase(
  connection: IConnection,
  props: erase.Props,
): Promise<void> {
  return true === connection.simulate
    ? erase.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...erase.METADATA,
          path: erase.path(props),
          status: null,
        },
      );
}
export namespace erase {
  export type Props = {
    /**
     * Unique identifier of the target product. This identifier must match a
     * valid product in the shopping_mall_products table and must correspond
     * to the product that has the tag association to be removed.
     */
    productId: string & tags.Format<"uuid">;

    /**
     * Unique identifier of the target tag. This identifier must match a
     * valid tag in the shopping_mall_product_tags table and must correspond
     * to the tag associated with the product being removed.
     */
    tagId: string & tags.Format<"uuid">;
  };

  export const METADATA = {
    method: "DELETE",
    path: "/shoppingMall/admin/products/:productId/tags/:tagId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/admin/products/${encodeURIComponent(props.productId ?? "null")}/tags/${encodeURIComponent(props.tagId ?? "null")}`;
  export const random = (): void => typia.random<void>();
  export const simulate = (
    connection: IConnection,
    props: erase.Props,
  ): void => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: erase.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("productId")(() => typia.assert(props.productId));
      assert.param("tagId")(() => typia.assert(props.tagId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
