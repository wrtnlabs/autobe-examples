import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallProductReview } from "../../../../../structures/IShoppingMallProductReview";
import { IPageIShoppingMallProductReview } from "../../../../../structures/IPageIShoppingMallProductReview";

/**
 * Retrieve comprehensive analytics on product reviews across the shoppingMall
 * platform. This operation aggregates data from the
 * shopping_mall_product_reviews, shopping_mall_product_review_votes, and
 * shopping_mall_review_moderation_logs tables to generate detailed review
 * analytics for administrative monitoring.
 *
 * The operation returns time-series data on review volume, sentiment trends,
 * moderation actions, and user engagement across all products. It accepts
 * complex filtering and sorting parameters, including date ranges, product
 * categories, seller IDs, review ratings, and moderation statuses.
 *
 * Data sources:
 *
 * - Shipping_mall_product_reviews: Main review records with ratings, content,
 *   timestamps, and product associations
 * - Shipping_mall_product_review_votes: User voting data that indicates
 *   helpfulness of reviews
 * - Shipping_mall_review_moderation_logs: Records of moderation actions including
 *   flags, removals, and notifications
 *
 * Security considerations: This endpoint is restricted to admin users only, as
 * it exposes sensitive analytics including seller performance metrics, user
 * review patterns, and moderation histories that could be exploited if
 * accessible to regular users or sellers.
 *
 * Implementation uses a series of SQL aggregations and joins:
 *
 * - Daily review count by product and seller
 * - Average rating trends over time
 * - Flag-to-removal conversion rate
 * - Moderator efficiency metrics
 * - Review helpfulness scores
 * - Review-to-purchase conversion correlation
 *
 * Related operations: GET /products/{productId}/reviews (list for customers),
 * PATCH /users/{userId}/reviews (user's own reviews).
 *
 * @param props.connection
 * @param props.body Search, filter, and sort parameters for retrieving product
 *   review analytics data.
 * @path /shoppingMall/admin/analytics/product-reviews
 * @accessor api.functional.shoppingMall.admin.analytics.product_reviews.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Search, filter, and sort parameters for retrieving product review
     * analytics data.
     */
    body: IShoppingMallProductReview.IRequest;
  };
  export type Body = IShoppingMallProductReview.IRequest;
  export type Response = IPageIShoppingMallProductReview;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/admin/analytics/product-reviews",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/shoppingMall/admin/analytics/product-reviews";
  export const random = (): IPageIShoppingMallProductReview =>
    typia.random<IPageIShoppingMallProductReview>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
