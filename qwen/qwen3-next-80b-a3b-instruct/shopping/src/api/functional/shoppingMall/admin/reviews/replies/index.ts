/**
 * Update an existing reply to a product review in the shopping mall platform.
 * This operation specifically targets the shopping_mall_review_replies database
 * table and allows authenticated users to modify their own reply content or
 * allow administrators to moderate replies.
 *
 * The operation requires the reviewer's reply identifier in the path to locate
 * the specific reply record. Only the reply author or an administrator can
 * update the reply content, which is validated against existing review
 * integrity rules. The update will be recorded in the system with audit trail
 * metadata but does not modify the associated review or affect the original
 * review rating.
 *
 * This is a write operation that modifies the content field of an existing
 * reply entity. The system enforces ownership verification before allowing
 * updates, so even if the replyId is valid, the operation will fail if the
 * requesting user is not the original author or does not have admin privileges.
 * This ensures review integrity and prevents malicious content modification by
 * unauthorized users.
 *
 * The operation returns the updated reply object with all its fields including
 * the modified content, updated_at timestamp, and verification status.
 *
 * Related operations:
 *
 * - POST /reviews/{reviewId}/replies - Create a new reply
 * - DELETE /reviews/{reviewId}/replies/{replyId} - Delete a reply
 * - GET /reviews/{reviewId}/replies - List all replies for a review
 *
 * @param props.connection
 * @param props.reviewId Unique identifier of the review that the reply belongs
 *   to (global scope)
 * @param props.replyId Unique identifier of the specific reply being updated
 *   (global scope)
 * @param props.body Updated content and metadata for the reply
 * @path /shoppingMall/admin/reviews/:reviewId/replies/:replyId
 * @accessor api.functional.shoppingMall.admin.reviews.replies.update
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function update(
  connection: IConnection,
  props: update.Props,
): Promise<update.Response> {
  return true === connection.simulate
    ? update.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...update.METADATA,
          path: update.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace update {
  export type Props = {
    /**
     * Unique identifier of the review that the reply belongs to (global
     * scope)
     */
    reviewId: string;

    /** Unique identifier of the specific reply being updated (global scope) */
    replyId: string;

    /** Updated content and metadata for the reply */
    body: IShoppingMallReviewReply.IUpdate;
  };
  export type Body = IShoppingMallReviewReply.IUpdate;
  export type Response = IShoppingMallReviewReply;

  export const METADATA = {
    method: "PUT",
    path: "/shoppingMall/admin/reviews/:reviewId/replies/:replyId",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/shoppingMall/admin/reviews/${encodeURIComponent(props.reviewId ?? "null")}/replies/${encodeURIComponent(props.replyId ?? "null")}`;
  export const random = (): IShoppingMallReviewReply =>
    typia.random<IShoppingMallReviewReply>();
  export const simulate = (
    connection: IConnection,
    props: update.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: update.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("reviewId")(() => typia.assert(props.reviewId));
      assert.param("replyId")(() => typia.assert(props.replyId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

