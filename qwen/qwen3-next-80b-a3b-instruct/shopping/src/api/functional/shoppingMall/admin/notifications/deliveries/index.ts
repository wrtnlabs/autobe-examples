import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallNotificationDelivery } from "../../../../../structures/IShoppingMallNotificationDelivery";
import { IPageIShoppingMallNotificationDelivery } from "../../../../../structures/IPageIShoppingMallNotificationDelivery";

/**
 * Retrieve a paginated list of notification delivery attempts and outcomes.
 *
 * This operation provides access to the shopping_mall_notification_deliveries
 * audit trail, which records every delivery attempt for every notification sent
 * through the platform. Unlike the queuing system that represents pending
 * notifications, this endpoint returns historical records of what actually
 * happened during delivery attempts.
 *
 * The deliveries collection serves as a permanent audit log for compliance and
 * debugging. Each record captures:
 *
 * - Which specific queue entry triggered the delivery (via queue_id)
 * - The delivery channel used (email, in_app, push)
 * - The outcome status (success, failed, skipped)
 * - The response from the delivery service gateway
 * - The timestamp of delivery completion
 *
 * This endpoint supports advanced filtering through search parameters,
 * pagination, and sorting to enable comprehensive analysis of notification
 * delivery performance.
 *
 * Use cases:
 *
 * - Validate delivery success rates for specific notification types
 * - Investigate patterns in delivery failures by actor or channel
 * - Identify system issues affecting specific notification providers
 * - Produce reports on notification delivery effectiveness
 *
 * Note: This endpoint uses PATCH semantics for complex filtering - a GET
 * request would be insufficient for the required search parameters like date
 * ranges, delivery status filters, and actor type criteria. The request body
 * contains the complete search criteria.
 *
 * Related operations:
 *
 * - GET /notifications/queue/{queueId} - View a specific pending notification
 * - GET /notifications/templates - List available notification templates
 *
 * The delivery records are immutable - they are never updated after creation.
 * New records are appended on retry attempts, creating a complete history of
 * delivery attempts for each notification.
 *
 * @param props.connection
 * @param props.body Search parameters for filtering notification delivery
 *   records. Includes date ranges, delivery status filters, and actor type
 *   criteria.
 * @path /shoppingMall/admin/notifications/deliveries
 * @accessor api.functional.shoppingMall.admin.notifications.deliveries.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Search parameters for filtering notification delivery records.
     * Includes date ranges, delivery status filters, and actor type
     * criteria.
     */
    body: IShoppingMallNotificationDelivery.IRequest;
  };
  export type Body = IShoppingMallNotificationDelivery.IRequest;
  export type Response = IPageIShoppingMallNotificationDelivery;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/admin/notifications/deliveries",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/shoppingMall/admin/notifications/deliveries";
  export const random = (): IPageIShoppingMallNotificationDelivery =>
    typia.random<IPageIShoppingMallNotificationDelivery>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
