import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallDataExport } from "../../../../../../structures/IShoppingMallDataExport";

/**
 * Initiate a bulk data export process for the shopping mall platform. This
 * operation triggers the generation of a comprehensive data dump containing
 * customer information, order histories, product catalogs, and sales analytics
 * based on configurable export parameters.
 *
 * The bulk export system is designed for compliance, analytics, and data
 * migration purposes, allowing authorized administrators to extract structured
 * datasets for external processing. The operation validates all requested
 * export parameters against the system's data retention policies and user
 * consent settings before initiating the background export job.
 *
 * Security considerations include role-based access control, audit log
 * generation for every export request, and automatic generation of encryption
 * keys for the exported archive. The system ensures all exported data complies
 * with GDPR/CCPA requirements by automatically redacting personal identifiers
 * unless explicit user consent is present in the dataset.
 *
 * The export job runs asynchronously in the background and generates a
 * downloadable archive file with the format:
 * 'ShoppingMall_Export_{YYYYMMDD}_{uniqueID}.zip'. Notification emails are sent
 * to the requesting admin upon completion with secure download links.
 *
 * Related operations: GET /data/exports to list pending/complete exports, GET
 * /data/exports/{exportId}/status to check individual export job status.
 *
 * @param props.connection
 * @param props.body Configuration parameters for the bulk data export job
 * @path /shoppingMall/admin/data/exports/bulk
 * @accessor api.functional.shoppingMall.admin.data.exports.bulk.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function create(
  connection: IConnection,
  props: create.Props,
): Promise<create.Response> {
  return true === connection.simulate
    ? create.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...create.METADATA,
          path: create.path(),
          status: null,
        },
        props.body,
      );
}
export namespace create {
  export type Props = {
    /** Configuration parameters for the bulk data export job */
    body: IShoppingMallDataExport.IRequest;
  };
  export type Body = IShoppingMallDataExport.IRequest;
  export type Response = IShoppingMallDataExport;

  export const METADATA = {
    method: "POST",
    path: "/shoppingMall/admin/data/exports/bulk",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/shoppingMall/admin/data/exports/bulk";
  export const random = (): IShoppingMallDataExport =>
    typia.random<IShoppingMallDataExport>();
  export const simulate = (
    connection: IConnection,
    props: create.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: create.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
