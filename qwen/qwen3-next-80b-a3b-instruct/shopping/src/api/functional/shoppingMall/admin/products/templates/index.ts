/**
 * Create a new product template configuration for a specific product in the
 * shopping mall system. This operation operates on the
 * shopping_mall_variant_templates table and allows administrators to define
 * standardized product variant configurations that can be applied to multiple
 * products, ensuring consistency across product catalogs.
 *
 * A product template defines a set of mandatory and optional variant attributes
 * (such as size, color, material, etc.) that can be applied to products. When a
 * new product is created, sellers can select an existing template to
 * automatically populate the variant configuration, reducing manual input and
 * minimizing errors. The template specifies which attributes are required,
 * which are optional, default values for each attribute, and any compatibility
 * rules between attributes.
 *
 * Security: Only users with administrative privileges can create product
 * templates. The operation validates that the referenced product exists and
 * that the template configuration does not create incompatible attribute
 * combinations. Template names must be unique across the system to prevent
 * conflicts.
 *
 * Implementation Note: This operation does NOT create product variants
 * directly. Instead, it defines a template that can be referenced when creating
 * or updating products. When a seller applies this template to a product, the
 * system generates unique SKUs for each valid combination of attributes defined
 * in the template, and creates corresponding inventory tracking records for
 * each variant.
 *
 * Related operations: GET /products/{productId}/templates (list templates for a
 * product), PATCH /products/{productId}/templates (search templates by
 * criteria), PUT /products/{productId}/templates/{templateId} (update
 * template), DELETE /products/{productId}/templates/{templateId} (erase
 * template).
 *
 * @param props.connection
 * @param props.productId Unique identifier of the target product for which the
 *   template is being created. This must reference an existing product in the
 *   shopping_mall_products table.
 * @param props.body Configuration details for the new product variant template
 *   including attribute definitions, defaults, and compatibility rules.
 * @path /shoppingMall/admin/products/:productId/templates
 * @accessor api.functional.shoppingMall.admin.products.templates.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
