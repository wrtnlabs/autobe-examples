import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallPaymentWebhook } from "../../../../structures/IShoppingMallPaymentWebhook";

/**
 * Retrieve a specific payment webhook configuration by its unique identifier
 * from the payment webhook system.
 *
 * This operation accesses the shopping_mall_payment_webhooks table, which
 * stores webhook configurations used for notifying external systems about
 * payment events. Each webhook defines a URL endpoint to which payment system
 * events (such as payment succeeded, payment failed, refund processed, etc.)
 * will be sent, along with the active status, secret key for signature
 * verification, and event types to trigger.
 *
 * The webhook ID is used to uniquely identify which webhook configuration to
 * retrieve. This endpoint is primarily used by system administrators and
 * payment integration teams to audit webhook settings, verify delivery targets,
 * or troubleshoot notification failures. It does not trigger event delivery but
 * only reads the stored configuration data.
 *
 * The operation requires administrative authorization because webhook
 * configurations contain sensitive information including endpoint URLs and
 * secret keys used for payload signature verification. Standard users or
 * sellers cannot view webhook configurations.
 *
 * This operation does not modify any data and has no associated request body.
 * The response contains a complete definition of the webhook including all
 * configuration details.
 *
 * @param props.connection
 * @param props.webhookId Unique identifier of the payment webhook configuration
 *   to retrieve. This is a system-generated identifier that is permanently
 *   assigned when the webhook is created and never reused.
 * @path /shoppingMall/admin/payment-webhooks/:webhookId
 * @accessor api.functional.shoppingMall.admin.payment_webhooks.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique identifier of the payment webhook configuration to retrieve.
     * This is a system-generated identifier that is permanently assigned
     * when the webhook is created and never reused.
     */
    webhookId: string & tags.Format<"uuid">;
  };
  export type Response = IShoppingMallPaymentWebhook;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/admin/payment-webhooks/:webhookId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/admin/payment-webhooks/${encodeURIComponent(props.webhookId ?? "null")}`;
  export const random = (): IShoppingMallPaymentWebhook =>
    typia.random<IShoppingMallPaymentWebhook>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("webhookId")(() => typia.assert(props.webhookId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
