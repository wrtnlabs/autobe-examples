/**
 * Permanently removes an order record from the system, marking it as
 * irreversibly deleted.
 *
 * This operation executes a hard delete on the shopping_mall_orders table,
 * removing all associated order data permanently from the database. Unlike soft
 * deletion (which only sets a deleted_at timestamp), this operation erases the
 * order and all its related records in a single atomic transaction.
 *
 * Due to the critical nature of order data in financial and audit systems, this
 * operation is restricted to administrators only. Once executed, the order
 * cannot be recovered, and all related entities (order items, payments,
 * shipping records, etc.) are also permanently removed.
 *
 * This endpoint exists only for regulatory compliance scenarios where data must
 * be completely eradicated under legal requirements.
 *
 * Security: This operation triggers comprehensive audit logging and requires
 * explicit admin authorization.
 *
 * Related operations: DELETE /orders/{orderNumber} (soft delete), PATCH
 * /orders/{orderNumber} (update status).
 *
 * @param props.connection
 * @param props.orderNumber Unique order identifier in format ORD-YYYYMMDD-NNNNN
 *   (global scope).
 * @path /shoppingMall/admin/orders/:orderNumber
 * @accessor api.functional.shoppingMall.admin.orders.erase
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function erase(
  connection: IConnection,
  props: erase.Props,
): Promise<void> {
  return true === connection.simulate
    ? erase.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...erase.METADATA,
          path: erase.path(props),
          status: null,
        },
      );
}
export namespace erase {
  export type Props = {
    /** Unique order identifier in format ORD-YYYYMMDD-NNNNN (global scope). */
    orderNumber: string;
  };

  export const METADATA = {
    method: "DELETE",
    path: "/shoppingMall/admin/orders/:orderNumber",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/admin/orders/${encodeURIComponent(props.orderNumber ?? "null")}`;
  export const random = (): void => typia.random<void>();
  export const simulate = (
    connection: IConnection,
    props: erase.Props,
  ): void => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: erase.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("orderNumber")(() => typia.assert(props.orderNumber));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
