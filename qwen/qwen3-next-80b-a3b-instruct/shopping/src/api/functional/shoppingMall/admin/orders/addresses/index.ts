import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

/**
 * Permanently remove a specific shipping or billing address associated with an
 * order.
 *
 * This operation deletes an address record that was captured at the time of
 * order placement and linked to the order via its unique address code. The
 * address is stored as historical data to preserve the exact shipping/billing
 * details at the time of purchase, ensuring financial and logistical accuracy
 * even if the customer later modifies their profile.
 *
 * This is a hard delete operation — the address record is permanently removed
 * from the database and cannot be recovered. This is appropriate because the
 * address is a historical snapshot associated with a specific order, and
 * removing it does not affect current customer profiles or other orders.
 *
 * Access is restricted to administrative actors only. Regular customers cannot
 * delete addresses associated with their own orders through this endpoint. The
 * system enforces that order addresses are immutable historical records, except
 * when administrative intervention is required for compliance, legal disputes,
 * or data correction purposes.
 *
 * This operation must be used with extreme caution. Any deleted address cannot
 * be restored, and its removal may impact audit trails, tax documentation, and
 * dispute resolution capabilities. Administrators are strongly advised to
 * verify the necessity of deletion before execution and ensure appropriate
 * backup or archival procedures are followed if the record has regulatory
 * value.
 *
 * This operation corresponds directly to the shopping_mall_order_addresses
 * table in the database schema, which stores address records linked to orders
 * by orderCode and addressCode. The operation does not affect the customer's
 * primary profile addresses or other orders.
 *
 * @param props.connection
 * @param props.orderCode Unique business identifier code of the target order
 *   (global scope)
 * @param props.addressCode Unique business identifier code of the target
 *   address within the order (scoped to order)
 * @path /shoppingMall/admin/orders/:orderCode/addresses/:addressCode
 * @accessor api.functional.shoppingMall.admin.orders.addresses.erase
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function erase(
  connection: IConnection,
  props: erase.Props,
): Promise<void> {
  return true === connection.simulate
    ? erase.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...erase.METADATA,
          path: erase.path(props),
          status: null,
        },
      );
}
export namespace erase {
  export type Props = {
    /** Unique business identifier code of the target order (global scope) */
    orderCode: string;

    /**
     * Unique business identifier code of the target address within the
     * order (scoped to order)
     */
    addressCode: string;
  };

  export const METADATA = {
    method: "DELETE",
    path: "/shoppingMall/admin/orders/:orderCode/addresses/:addressCode",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/admin/orders/${encodeURIComponent(props.orderCode ?? "null")}/addresses/${encodeURIComponent(props.addressCode ?? "null")}`;
  export const random = (): void => typia.random<void>();
  export const simulate = (
    connection: IConnection,
    props: erase.Props,
  ): void => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: erase.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("orderCode")(() => typia.assert(props.orderCode));
      assert.param("addressCode")(() => typia.assert(props.addressCode));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
