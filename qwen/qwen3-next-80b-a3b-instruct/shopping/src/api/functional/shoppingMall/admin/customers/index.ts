import { HttpError, IConnection } from "@nestia/fetcher";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";

import { IShoppingMallCategory } from "../../../../structures/IShoppingMallCategory";

/**
 * Retrieve detailed profile information for a specific customer account.
 *
 * This endpoint returns immutable customer profile data including display name, phone number, and account creation/update timestamps. The response provides sufficient information for customer-facing UI components while preserving privacy by excluding sensitive data like email and password_hash.
 *
 * Authorized only for administrators as defined in 02-user-actors.md under "View all users" permission. Customers may NOT access other customers' profiles using this endpoint. This is an admin-only operation for support and oversight purposes.
 *
 * Profile data is not subject to modification via this endpoint. To update customer information, use the PUT /customers/me endpoint instead.
 *
 * @param props.connection
 * @param props.customerId The UUID identifier of the target customer account. Must match the customer's stored id field in shopping_mall_customers table.
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor admin
 * @x-autobe-specification Query shopping_mall_customers table by id field. Use UUID comparison for exact match. Fetch display_name, phone_number, created_at, updated_at, and deleted_at fields. Return 404 if customer not found or if deleted_at is not null. Return 403 if requester is not the same customer and not an admin.
 * @path /shoppingMall/admin/customers/:customerId
 * @accessor api.functional.shoppingMall.admin.customers.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * The UUID identifier of the target customer account. Must match the customer's stored id field in shopping_mall_customers table.
     */
    customerId: string;
  };
  export type Response = IShoppingMallCategory;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/admin/customers/:customerId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/admin/customers/${encodeURIComponent(props.customerId ?? "null")}`;
  export const random = (): IShoppingMallCategory =>
    typia.random<IShoppingMallCategory>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("customerId")(() => typia.assert(props.customerId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
