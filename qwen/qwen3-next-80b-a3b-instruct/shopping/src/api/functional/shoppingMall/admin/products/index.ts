/**
 * Update an existing product in the shopping mall catalog. This operation
 * modifies specific fields of the product entity based on the
 * shopping_mall_products database table. The product must be identified by its
 * unique code field, not the UUID ID.
 *
 * This operation supports partial updates; only provided fields will be
 * modified while other fields retain their existing values. Modifiable fields
 * include name, description, category_id, price, and inventory_count as defined
 * in the shopping_mall_products schema. The operation requires authentication
 * and checks ownership: sellers can only update their own products, while
 * administrators can update any product.
 *
 * The update is performed atomically with immediate reflection in search
 * results and inventory displays. All field modifications must conform to the
 * product schema's field constraints (string lengths, numeric ranges, etc.).
 * Field validation is performed before application of changes.
 *
 * Related operations: GET /shoppingMall/admin/products/{productCode} for
 * viewing product details before update, DELETE
 * /shoppingMall/admin/products/{productCode} for permanent deletion, and PATCH
 * /shoppingMall/admin/products for bulk search and filtering operations.
 *
 * @param props.connection
 * @param props.productId Unique identifier of the target product. This field
 *   corresponds to the id field in the shopping_mall_products table.
 * @param props.body Product fields to be updated. Only fields provided in this
 *   object will be modified; all other fields retain their current values.
 * @path /shoppingMall/admin/products/:productId
 * @accessor api.functional.shoppingMall.admin.products.update
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function update(
  connection: IConnection,
  props: update.Props,
): Promise<update.Response> {
  return true === connection.simulate
    ? update.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...update.METADATA,
          path: update.path(props),
          status: null,
        },
        props.body,
      );
}
