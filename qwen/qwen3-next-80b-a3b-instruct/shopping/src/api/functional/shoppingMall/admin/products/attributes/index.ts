/**
 * Update a specific product attribute configuration in the shopping mall
 * system. This operation modifies the properties of a defined product attribute
 * associated with a given product, allowing administrators or sellers to adjust
 * attribute settings such as display order, validation rules, or required
 * status. The operation operates on the shopping_mall_product_attributes
 * database table and requires precise identification of both the product and
 * the attribute via their respective identifiers.
 *
 * Security context: Only authenticated sellers managing the product or system
 * administrators can modify attribute configurations. The system enforces
 * ownership verification by matching the authenticated actor's seller ID with
 * the product's seller association. Any attempt to modify an attribute
 * belonging to a product not owned by the requesting actor will result in a 403
 * Forbidden response.
 *
 * Business logic: Attribute updates are allowed only if the attribute is not
 * currently referenced by any product variants with inventory. If the attribute
 * is assigned to any product variants that have stock greater than zero, the
 * request will be rejected with a 409 Conflict error to prevent inventory
 * inconsistencies. This constraint prevents situations where customers would
 * see attribute options that no longer match their associated inventory levels.
 * The attribute update is atomic and triggers immediate cache invalidation for
 * product pages referencing this attribute to ensure display consistency.
 *
 * Implementation note: The product identifier must reference a valid product
 * from the shopping_mall_products table, and the attribute identifier must
 * reference a valid attribute from the shopping_mall_product_attributes table.
 * Both identifiers must be in UUID format as defined in the database schema.
 * The request body must contain the complete updated attribute configuration
 * object with all fields that require modification, and all required fields
 * must be present in the update payload. This operation does not perform
 * partial updates; the update payload must contain the complete revised
 * attribute definition.
 *
 * Related operations: To create new product attributes, use POST
 * /products/{productId}/attributes. To retrieve a list of all attributes for a
 * product, use GET /products/{productId}/attributes. To remove a product
 * attribute, use DELETE /products/{productId}/attributes/{attributeId}.
 *
 * Cache impact: Updating an attribute triggers cache invalidation for all
 * products containing this attribute across all shops and channels, ensuring
 * instant consistency in product display settings.
 *
 * @param props.connection
 * @param props.productId Unique identifier of the target product in the
 *   shopping mall system (global scope)
 * @param props.attributeId Unique identifier of the target product attribute
 *   (global scope)
 * @param props.body Complete updated configuration of the product attribute
 *   including all fields for replacement
 * @path /shoppingMall/admin/products/:productId/attributes/:attributeId
 * @accessor api.functional.shoppingMall.admin.products.attributes.update
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
