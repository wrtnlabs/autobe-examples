/**
 * Create a new seller account on the shoppingMall platform. This operation
 * registers a business entity as a seller capable of listing products for sale.
 * The seller account requires validation of business information before
 * becoming active.
 *
 * This operation accepts the core seller registration data including business
 * name, legal address, tax identification, and contact email. The password is
 * encrypted using BCrypt upon creation and stored securely. Upon successful
 * creation, the seller account enters a 'pending_verification' status and
 * requires document submission for final approval.
 *
 * The operation is only accessible via the seller registration interface and
 * cannot be performed by administrators or other actors.
 *
 * Related operations: GET /actors/sellers/{sellerId} retrieves the account
 * details after creation.
 *
 * Note regarding soft delete: This operation creates a permanent seller
 * account. The 'deleted_at' field remains null at creation and is only
 * populated if the account is later suspended or deactivated through
 * administrative action.
 *
 * @param props.connection
 * @param props.body Registration details for a new seller account
 * @path /shoppingMall/actors/sellers
 * @accessor api.functional.shoppingMall.actors.sellers.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function create(
  connection: IConnection,
  props: create.Props,
): Promise<create.Response> {
  return true === connection.simulate
    ? create.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...create.METADATA,
          path: create.path(),
          status: null,
        },
        props.body,
      );
}
