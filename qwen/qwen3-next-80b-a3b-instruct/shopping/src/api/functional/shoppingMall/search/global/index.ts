import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallSearch } from "../../../../structures/IShoppingMallSearch";
import { IPageIShoppingMallSearch } from "../../../../structures/IPageIShoppingMallSearch";

/**
 * Perform a unified global search across all products, product reviews, and
 * categories on the shoppingMall platform. This operation aggregates search
 * results from multiple data sources and returns a combined, paginated response
 * optimized for consumer discovery.
 *
 * This endpoint supports searching across product titles, descriptions, tags,
 * brand names, category names, and product review contents. The search
 * leverages full-text indexing on product catalog data and review text for
 * performance. Search results are ranked by relevance, with product title
 * matches weighted highest, followed by description matches, and category
 * matches.
 *
 * Security: This is a public endpoint with no authentication required. All
 * results are filtered to show only approved products with available inventory
 * and approved reviews. Seller-specific or personally identifiable information
 * is never exposed in search results.
 *
 * Implementation note: This operation does not map to a single database table.
 * Instead, it performs a UNION query over three source tables:
 *
 * 1. Shopping_mall_products (for product metadata, including title, description,
 *    brand, category)
 * 2. Shopping_mall_product_reviews (for review content, product association)
 * 3. Shopping_mall_categories (for category names and descriptions)
 *
 * The results are combined into a unified format with a type discriminator to
 * indicate the source of each result. Product results include product ID,
 * title, brand, primary category, price range, and average rating. Review
 * results include the review content, rating, and associated product ID.
 * Category results include category name and description. This guarantees
 * return of relevant data from all searchable entities.
 *
 * The operation supports pagination with configurable page size, sorting by
 * relevance (default), newest, or highest rated, and automatic highlighting of
 * search terms in result snippets.
 *
 * Related operations: GET /products/{productId} for retrieving detailed product
 * information, PATCH /products for category-specific product search, and GET
 * /reviews/{reviewId} for reviewing individual feedback.
 *
 * @param props.connection
 * @param props.body Search query parameters including the search term, filters,
 *   pagination, and sorting options.
 * @path /shoppingMall/search/global
 * @accessor api.functional.shoppingMall.search.global.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Search query parameters including the search term, filters,
     * pagination, and sorting options.
     */
    body: IShoppingMallSearch.IRequest;
  };
  export type Body = IShoppingMallSearch.IRequest;
  export type Response = IPageIShoppingMallSearch.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/search/global",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/shoppingMall/search/global";
  export const random = (): IPageIShoppingMallSearch.ISummary =>
    typia.random<IPageIShoppingMallSearch.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
