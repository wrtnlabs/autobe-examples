/**
 * Perform a comprehensive search across all products in the shopping mall
 * catalog using advanced filtering, sorting, and pagination. This operation
 * queries the shopping_mall_products table and its associated entities
 * including shopping_mall_categories, shopping_mall_product_attributes,
 * shopping_mall_product_variant_attributes,
 * shopping_mall_product_variant_pricing, shopping_mall_product_images,
 * shopping_mall_product_tags, shopping_mall_product_sales_stats, and
 * shopping_mall_product_view_stats to deliver relevant product results.
 *
 * The search is designed to handle complex user queries with multiple filter
 * criteria including category hierarchy navigation, attribute value matching,
 * price range constraints, stock availability status, and keyword-based text
 * matching across product names, descriptions, and tags. The operation supports
 * sophisticated sorting by relevance, price, rating, sales volume, or newest
 * first.
 *
 * For pagination, the service implements cursor-based paging with configurable
 * page sizes up to 100 items per page. Results are returned as a paginated
 * summary view to optimize performance and reduce bandwidth usage. The
 * operation returns only essential product information intended for display in
 * search result lists.
 *
 * Security considerations ensure that only products marked as active and
 * visible to the requesting user are returned, applying appropriate permissions
 * based on user role. The system implements query rate limiting to prevent
 * abuse and optimize performance. Order of operations follows parent-to-child
 * relationship logic: categories first, then products, then variants, then
 * pricing and inventory. This operation integrates with the
 * shopping_mall_product_sales_stats table to incorporate real-time sales data
 * and the shopping_mall_product_view_stats table for popularity-based ranking.
 *
 * Related operations include: GET /products/{productId} to retrieve full
 * product details after selecting from this search, and PATCH
 * /products/{productId}/inventory to check real-time availability.
 *
 * @param props.connection
 * @param props.body Search query parameters for product filtering, sorting, and
 *   pagination.
 * @path /shoppingMall/search/products
 * @accessor api.functional.shoppingMall.search.products.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Search query parameters for product filtering, sorting, and
     * pagination.
     */
    body: IShoppingMallProduct.IRequest;
  };
  export type Body = IShoppingMallProduct.IRequest;
  export type Response = IPageIShoppingMallProduct.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/search/products",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/shoppingMall/search/products";
  export const random = (): IPageIShoppingMallProduct.ISummary =>
    typia.random<IPageIShoppingMallProduct.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
