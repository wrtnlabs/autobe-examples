import { IShoppingMallOrderItem } from "../../../../structures/IShoppingMallOrderItem";

/**
 * Retrieve a specific order item by its ID within the context of an order
 * identified by its unique order number.
 *
 * This operation fetches an individual product item from an order using the
 * order's globally unique order_number (not UUID ID) and the item's internal
 * ID. The operation ensures data integrity by validating that the requested
 * item belongs to the specified order before returning results. This prevents
 * unauthorized access to items from other orders.
 *
 * The response includes the complete item details as they existed at the time
 * of purchase, including the unit price, quantity, total amount, and any
 * special customer notes. This provides an immutable historical record of the
 * purchase.
 *
 * Security: Public access since order items are accessible to anyone who knows
 * the order_number and item ID, as order items are not considered sensitive
 * private information beyond the order context.
 *
 * This operation is used during order tracking, customer service inquiries, and
 * invoice generation where specific line items need to be referenced.
 *
 * Relationships: This endpoint depends on both the shopping_mall_orders and
 * shopping_mall_order_items models. The order_number is a unique field in
 * shopping_mall_orders, and the item ID is a primary key in
 * shopping_mall_order_items with a foreign key relationship to
 * shopping_mall_orders.
 *
 * @param props.connection
 * @param props.orderNumber Unique order identifier in format ORD-YYYYMMDD-NNNNN
 *   (global scope). Must match exactly with an existing order.
 * @param props.id Unique identifier of the specific order item within the
 *   order.
 * @path /shoppingMall/orders/:orderNumber/items/:id
 * @accessor api.functional.shoppingMall.orders.items.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique order identifier in format ORD-YYYYMMDD-NNNNN (global scope).
     * Must match exactly with an existing order.
     */
    orderNumber: string;

    /** Unique identifier of the specific order item within the order. */
    id: string;
  };
  export type Response = IShoppingMallOrderItem;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/orders/:orderNumber/items/:id",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/orders/${encodeURIComponent(props.orderNumber ?? "null")}/items/${encodeURIComponent(props.id ?? "null")}`;
  export const random = (): IShoppingMallOrderItem =>
    typia.random<IShoppingMallOrderItem>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("orderNumber")(() => typia.assert(props.orderNumber));
      assert.param("id")(() => typia.assert(props.id));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

/**
 * Add a new product item to an existing order based on the order's unique order
 * number.
 *
 * This operation creates a new order line item within an existing order
 * context, identified by the order's unique order_number (not UUID ID). The
 * operation validates that the specified order exists and is in a modifiable
 * state (draft or pending_payment) before adding the item.
 *
 * The request body specifies the product variant and quantity to be added. The
 * system automatically calculates and populates the unit_price based on the
 * product variant's current market price at the time of addition, ensuring
 * historical pricing accuracy. The item_total is calculated as quantity ×
 * unit_price.
 *
 * This operation supports product selection during the checkout process before
 * payment completion. Once an order reaches paid or confirmed status, no
 * further items can be added.
 *
 * Security: Public access since adding items to an order doesn't require user
 * authentication, as the order is identified by its public order_number.
 * Authorization is enforced at the business logic level to ensure that items
 * can only be added to orders in modifiable states.
 *
 * This operation is crucial for the shopping cart workflow where customers can
 * iteratively add multiple products to an order before finalizing checkout.
 *
 * Relationships: This endpoint depends on both the shopping_mall_orders model
 * (for order validation and context) and the shopping_mall_product_variants
 * model (for product pricing and inventory information). The item is then
 * persisted in the shopping_mall_order_items table with a foreign key
 * relationship to the order.
 *
 * @param props.connection
 * @param props.orderNumber Unique order identifier in format ORD-YYYYMMDD-NNNNN
 *   (global scope). Must match exactly with an existing order.
 * @param props.body Details for adding a new product item to the order,
 *   including the product variant and quantity.
 * @path /shoppingMall/orders/:orderNumber/items
 * @accessor api.functional.shoppingMall.orders.items.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
