/**
 * Retrieve detailed delivery tracking information for a specific order by its
 * unique order code. This operation operates on the
 * shopping_mall_delivery_trackings and shopping_mall_order_shipments tables to
 * provide a comprehensive view of delivery status, carrier information, and
 * estimated delivery timelines based on real-time carrier API updates.
 *
 * The system aggregates delivery events from external carriers (FedEx, UPS,
 * DHL, USPS, and regional providers) linked to the order through the shipping
 * tracking number. Each tracking event is timestamped and automatically
 * triggers the appropriate order status transition: 'Shipped' → 'In Transit' →
 * 'Out for Delivery' → 'Delivered'. The delivery information is updated
 * continuously every 6 hours through carrier API polls.
 *
 * The response includes all delivery events in chronological order, the current
 * delivery status, the carrier name and logo, tracking number, estimated
 * delivery date calculated from processing time and transit time, and a
 * persistent tracking URL. This endpoint is used by customers to monitor their
 * order progress in real time and is accessed through the order tracking page.
 *
 * Security: This endpoint is publicly accessible without authentication because
 * delivery tracking information is considered non-sensitive and essential for
 * customer experience. However, it only exposes data related to the specific
 * order code provided in the path. No customer personal information beyond
 * delivery status is included in the response.
 *
 * This operation directly supports the Order Tracking System described in
 * 08-order-tracking.md, implementing the delivery tracking link generation,
 * status update logic, and carrier integration requirements. It fulfills the
 * business need for transparency and customer reassurance throughout the
 * delivery journey.
 *
 * Related operations: GET /orders/{orderCode} (retrieves general order
 * summary), PATCH /orders (searches orders by criteria).
 *
 * @param props.connection
 * @param props.orderCode Unique business identifier code of the target order.
 *   This must match the orderCode field in the shopping_mall_orders table.
 * @path /shoppingMall/orders/:orderCode/deliveries
 * @accessor api.functional.shoppingMall.orders.deliveries.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
