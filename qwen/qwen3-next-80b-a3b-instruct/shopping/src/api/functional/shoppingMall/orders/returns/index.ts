/**
 * Retrieve a paginated list of return requests for a specific order. This
 * operation operates on the shopping_mall_order_returns table which tracks
 * product returns initiated by customers for completed orders. Each return
 * request includes details about the returned items, return reason, status,
 * estimated refund amount, and supporting documentation.
 *
 * The operation supports comprehensive pagination with configurable page sizes
 * and sorting options. Return requests can be sorted by creation date, status,
 * or return amount in ascending or descending order. Search functionality
 * allows filtering returns by status, return reason, and item SKU.
 *
 * Security considerations include ensuring that only the original order
 * customer or authorized administrative personnel can view return requests. The
 * operation enforces ownership validation by verifying that the requesting user
 * is the customer who placed the original order, as determined by JWT
 * authentication context.
 *
 * This operation integrates with the Order and Return entities as defined in
 * the database schema, incorporating all available return request fields and
 * relationships. The response includes return summary information optimized for
 * list displays, with options to include additional details based on
 * authorization level. Related operations include GET /orders/{orderCode} to
 * view the original order details and PATCH
 * /orders/{orderCode}/returns/{returnCode} to retrieve a specific return
 * request.
 *
 * @param props.connection
 * @param props.orderCode Unique business identifier code of the target order
 *   (global scope)
 * @param props.body Search criteria and pagination parameters for return
 *   request filtering
 * @path /shoppingMall/orders/:orderCode/returns
 * @accessor api.functional.shoppingMall.orders.returns.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /** Unique business identifier code of the target order (global scope) */
    orderCode: string;

    /**
     * Search criteria and pagination parameters for return request
     * filtering
     */
    body: IShoppingMallOrderReturn.IRequest;
  };
  export type Body = IShoppingMallOrderReturn.IRequest;
  export type Response = IPageIShoppingMallOrderReturn.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/orders/:orderCode/returns",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/shoppingMall/orders/${encodeURIComponent(props.orderCode ?? "null")}/returns`;
  export const random = (): IPageIShoppingMallOrderReturn.ISummary =>
    typia.random<IPageIShoppingMallOrderReturn.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("orderCode")(() => typia.assert(props.orderCode));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

