/**
 * Retrieve return records associated with a specific order using its order
 * number.
 *
 * This operation performs a search across all return requests linked to the
 * order identified by the provided orderNumber. It returns a paginated list of
 * return records with comprehensive details about return status, requested
 * products, refund amounts, and processing history.
 *
 * The system uses the orderNumber to locate the internal UUID-based order
 * record, then retrieves all return records associated with that order through
 * the shopping_mall_order_returns table's foreign key relationship. The
 * operation supports filtering by return status and sorting by return date.
 *
 * This is a read-only operation that does not modify any return records. The
 * response includes summary information for each return, with links to detailed
 * return records if needed.
 *
 * Authorization: Any authenticated user can search for returns on their own
 * orders. Admin users can search for returns across all orders.
 *
 * Related operations: POST /orders/{orderNumber}/returns (to create a new
 * return request) and GET /returns/{returnId} (to retrieve a specific return
 * record details).
 *
 * @param props.connection
 * @param props.orderNumber Unique order identifier in format
 *   ORD-YYYYMMDD-NNNNN. Must be globally unique and exactly match the
 *   orderNumber field in the shopping_mall_orders table.
 * @path /shoppingMall/orders/:orderNumber/returns
 * @accessor api.functional.shoppingMall.orders.returns.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
      );
}
