import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IPageIShoppingMallOrderStatusHistory } from "../../../../structures/IPageIShoppingMallOrderStatusHistory";

/**
 * Retrieve the complete audit trail of status changes for a specific order.
 *
 * This operation returns a chronological list of all status transitions that an
 * order has undergone, providing a complete historical record of changes from
 * creation to completion or cancellation. Each status change is associated with
 * the timestamp, the actor who initiated the change (admin or customer), the
 * previous status, the new status, and any additional notes.
 *
 * The endpoint uses the primary key from the path parameter (orderNumber)
 * identity for the order, and returns all status history records associated
 * with that order. The results are ordered chronologically by created_at
 * timestamp, providing a complete view of the order lifecycle.
 *
 * This operation is critical for dispute resolution, customer service
 * inquiries, and compliance auditing. It allows users and customer support to
 * understand the exact sequence of events that led to the current order
 * status.
 *
 * The data returned is sourced from the shopping_mall_order_status_history
 * model, which is designed as an append-only snapshot table to preserve an
 * immutable audit trail. This table records every state transition with
 * fidelity, even if the current order status changes again.
 *
 * Since this endpoint returns potentially multiple records that are best
 * presented in a paged format, it uses a paginated response structure. This
 * ensures efficient data retrieval for orders with extensive status histories,
 * preventing performance issues through large result sets.
 *
 * Related operations: GET /orders/{orderNumber} to view current order state,
 * PATCH /orders/{orderNumber} to update order status.
 *
 * @param props.connection
 * @param props.orderNumber Unique order identifier in format
 *   ORD-YYYYMMDD-NNNNN. Identifies the specific order whose status history is
 *   being requested.
 * @path /shoppingMall/orders/:orderNumber/status-history
 * @accessor api.functional.shoppingMall.orders.status_history.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
      );
}
export namespace index {
  export type Props = {
    /**
     * Unique order identifier in format ORD-YYYYMMDD-NNNNN. Identifies the
     * specific order whose status history is being requested.
     */
    orderNumber: string;
  };
  export type Response = IPageIShoppingMallOrderStatusHistory;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/orders/:orderNumber/status-history",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/orders/${encodeURIComponent(props.orderNumber ?? "null")}/status-history`;
  export const random = (): IPageIShoppingMallOrderStatusHistory =>
    typia.random<IPageIShoppingMallOrderStatusHistory>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("orderNumber")(() => typia.assert(props.orderNumber));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
