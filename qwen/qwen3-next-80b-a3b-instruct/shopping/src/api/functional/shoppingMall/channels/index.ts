/**
 * Retrieve a filtered and paginated list of shopping mall channels from the
 * system. This operation operates on the IShoppingMallChannel entity from the
 * database schema and provides advanced search capabilities for finding
 * channels based on multiple criteria including partial name matching, channel
 * status filtering, creation date ranges, and parent channel hierarchy.
 *
 * The operation supports comprehensive pagination with configurable page sizes
 * and sorting options. Channels can sort by name, creation date, or status in
 * ascending or descending order.
 *
 * Security considerations include rate limiting for search operations and
 * appropriate filtering of sensitive channel information based on the
 * requesting user's authorization level. This operation is restricted to admin
 * users only, as channels are system configuration entities managed exclusively
 * by administrators.
 *
 * This operation integrates with the IShoppingMallChannel entity as defined in
 * the database schema, incorporating all available channel fields and
 * relationships. The response includes channel summary information optimized
 * for list displays, with options to include additional details based on
 * authorization level.
 *
 * @param props.connection
 * @param props.body Search criteria and pagination parameters for channel
 *   filtering
 * @path /shoppingMall/channels
 * @accessor api.functional.shoppingMall.channels.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
