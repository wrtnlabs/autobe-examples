/**
 * Retrieve real-time currency exchange rate analytics for payment processing
 * across international transactions. This operation queries the
 * shopping_mall_payment_exchange_rates table in the database schema to return
 * structured analytics on currency conversion rates used in payment
 * transactions.
 *
 * The operation provides aggregated insights into currency conversion trends
 * and historical rate data used by the shoppingMall payment system. It returns
 * the latest exchange rates between supported currencies, calculated from the
 * most recently processed transactions, enabling financial analytics and
 * reporting.
 *
 * Security considerations include that no authentication is required as this
 * data is considered public analytics information. The endpoint is rate-limited
 * to prevent abuse. Response data is cached for performance optimization and
 * only updates when new payment transactions are processed with different
 * currency pairings.
 *
 * This operation has no prerequisites. It provides standalone financial
 * analytics data that does not depend on any other API endpoint. The response
 * data is used primarily by backend reporting systems and financial
 * reconciliation services to monitor currency fluctuations and payment
 * processing efficiencies.
 *
 * Related operations: None - this is a bottom-up analytics endpoint that does
 * not depend on any other operations to function properly.
 *
 * @param props.connection
 * @path /shoppingMall/analytics/payment-exchange-rates
 * @accessor api.functional.shoppingMall.analytics.payment_exchange_rates.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(connection: IConnection): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
      );
}
export namespace index {
  export type Response = IPageIShoppingMallPaymentExchangeRate;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/analytics/payment-exchange-rates",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/shoppingMall/analytics/payment-exchange-rates";
  export const random = (): IPageIShoppingMallPaymentExchangeRate =>
    typia.random<IPageIShoppingMallPaymentExchangeRate>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}
