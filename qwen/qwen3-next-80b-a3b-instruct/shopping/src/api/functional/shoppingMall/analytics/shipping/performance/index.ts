import { IConnection } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";

import { IShoppingMallShippingPerformance } from "../../../../../structures/IShoppingMallShippingPerformance";

/**
 * Retrieve comprehensive shipping performance analytics across the entire
 * shopping mall platform. This operation integrates data from multiple sources
 * including shipping carriers, order fulfillment systems, and delivery tracking
 * to provide actionable insights into delivery efficiency, carrier performance,
 * transportation costs, and fulfillment timelines. The endpoint analyzes all
 * delivered orders to calculate key performance indicators including average
 * delivery time by carrier, on-time delivery rate, delivery failure rate, cost
 * per shipment, and regional fulfillment efficiency.
 *
 * @param props.connection
 * @path /shoppingMall/analytics/shipping/performance
 * @accessor api.functional.shoppingMall.analytics.shipping.performance.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(connection: IConnection): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
      );
}
export namespace index {
  export type Response = IShoppingMallShippingPerformance.ISummary;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/analytics/shipping/performance",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/shoppingMall/analytics/shipping/performance";
  export const random = (): IShoppingMallShippingPerformance.ISummary =>
    typia.random<IShoppingMallShippingPerformance.ISummary>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}
