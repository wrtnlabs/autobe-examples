import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallPaymentCryptocurrencyConversion } from "../../../structures/IShoppingMallPaymentCryptocurrencyConversion";
import { IPageIShoppingMallPaymentCryptocurrencyConversion } from "../../../structures/IPageIShoppingMallPaymentCryptocurrencyConversion";

/**
 * Retrieve cryptocurrency to fiat currency conversion rates used in payment
 * processing for the shoppingMall platform. This operation queries the
 * shopping_mall_payment_cryptocurrency_conversions table, which stores
 * historical and current exchange rates between various cryptocurrencies
 * (Bitcoin, Ethereum, etc.) and fiat currencies (USD, EUR, KRW, etc.) used for
 * payments in the system.
 *
 * The operation supports complex filtering and pagination, allowing users to
 * query conversion rates by cryptocurrency type, fiat currency, and date range.
 * It returns a paginated list of conversion rate records with source and target
 * currencies, rate value, timestamp, and source confidence level. This data is
 * used for financial reconciliation, pricing display to users, and asynchronous
 * payment settlement processing.
 *
 * The shopping_mall_payment_cryptocurrency_conversions table is indexed by
 * from_currency, to_currency, and created_at for efficient querying. Conversion
 * rates are immutable records that are never modified after creation. When new
 * exchange rates become available, background services create new records with
 * updated values and timestamps - existing records are preserved as historical
 * snapshots for audit and reconciliation purposes.
 *
 * CRITICAL SYSTEM NOTE: This endpoint does not perform real-time rate updates.
 * Rate polling is handled by background services that update the database when
 * new rates are available from external cryptocurrency APIs. This endpoint only
 * serves as a read-only view of historical and current recorded rates for
 * auditing and business operations.
 *
 * Related operations: This operation is consumed by the payment processing
 * service during transaction settlement and by the admin dashboard for
 * financial review. The creation of new conversion rate records is handled by
 * background services and does not expose a public API endpoint.
 *
 * @param props.connection
 * @param props.body Search and pagination parameters for filtering
 *   cryptocurrency conversion rate records
 * @path /shoppingMall/payment-cryptocurrency-conversions
 * @accessor api.functional.shoppingMall.payment_cryptocurrency_conversions.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Search and pagination parameters for filtering cryptocurrency
     * conversion rate records
     */
    body: IShoppingMallPaymentCryptocurrencyConversion.IRequest;
  };
  export type Body = IShoppingMallPaymentCryptocurrencyConversion.IRequest;
  export type Response = IPageIShoppingMallPaymentCryptocurrencyConversion;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/payment-cryptocurrency-conversions",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/shoppingMall/payment-cryptocurrency-conversions";
  export const random = (): IPageIShoppingMallPaymentCryptocurrencyConversion =>
    typia.random<IPageIShoppingMallPaymentCryptocurrencyConversion>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
