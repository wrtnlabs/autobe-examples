import { HttpError, IConnection } from "@nestia/fetcher";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";

import { IShoppingMallAdmin } from "../../../../../structures/IShoppingMallAdmin";

/**
 * This operation authenticates an administrator using email and password credentials, granting them a JWT access token and refresh token for subsequent authenticated requests.
 *
 * Key schema fields referenced: admin_email, admin_password_hash, admin_is_active, admin_is_suspended. The system checks authentication success by comparing the hashed password against the stored value in shopping_mall_admins. If the admin is suspended (admin_is_suspended=true), authentication is denied with 403 status.
 *
 * This operation is public — no authentication required to access the endpoint. Upon successful login, the system creates an entry in the shopping_mall_admin_sessions table with the issued access token, refresh token, and expiration time.
 *
 * The admin profile returned includes admin_id, admin_email, admin_role, admin_is_active, and admin_created_at. The access token is valid for 15 minutes; the refresh token is valid for 7 days.
 *
 * This operation is distinct from user/customer login, which uses different tables, schemas, and token rules.
 *
 * This operation is permanently available for admin authentication. No prerequisites are required. Access is strictly controlled via the authorizationType: "login".
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Login credentials to authenticate the admin.
 * @x-autobe-specification Service layer validates credentials against admin_email and admin_password_hash stored in shopping_mall_admins. If valid and admin_is_active=true, generates JWT access and refresh tokens. Creates entry in shopping_mall_admin_sessions. Returns 200 with tokens and admin profile. Returns 401 for invalid credentials or suspended account.
 * @path /shoppingMall/auth/admin/login
 * @accessor api.functional.shoppingMall.auth.admin.login.signIn
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function signIn(
  connection: IConnection,
  props: signIn.Props,
): Promise<signIn.Response> {
  const output: signIn.Response =
    true === connection.simulate
      ? signIn.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...signIn.METADATA,
            path: signIn.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
export namespace signIn {
  export type Props = {
    /**
     * Login credentials to authenticate the admin.
     */
    body: IShoppingMallAdmin.ILogin;
  };
  export type Body = IShoppingMallAdmin.ILogin;
  export type Response = IShoppingMallAdmin.IAuthorized;

  export const METADATA = {
    method: "POST",
    path: "/shoppingMall/auth/admin/login",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/shoppingMall/auth/admin/login";
  export const random = (): IShoppingMallAdmin.IAuthorized =>
    typia.random<IShoppingMallAdmin.IAuthorized>();
  export const simulate = (
    connection: IConnection,
    props: signIn.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: signIn.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
