import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallCartSession } from "../../../structures/IShoppingMallCartSession";

/**
 * Create a new shopping cart session for a customer to begin accumulating
 * products for purchase. This operation initializes a cart record in the
 * shopping_mall_cart_sessions table, which serves as the container for all
 * items a user intends to purchase.
 *
 * Authenticated customers (users with an active login session) will have their
 * new cart recorded with their customer_id linked to the
 * shopping_mall_customers table. Any previous guest cart will automatically be
 * merged into this new authenticated cart if one exists. The system will
 * preserve the cart state even if the user logs out, allowing for continuation
 * of shopping in a future session.
 *
 * Guest users (unauthenticated visitors) are assigned a temporary cart session
 * with a unique anonymous cart identifier stored in browser localStorage. This
 * cart persists across page refreshes and browser sessions until the user
 * either logs in (triggering merge with authenticated cart) or exceeds the
 * 30-day inactivity period, at which point the session expires and the cart is
 * deleted.
 *
 * The cart session does not store individual cart items — these are managed by
 * the shopping_mall_cart_items table and referenced via cart_session_id. This
 * operation only creates the cart container. Items must be added via POST
 * /cart-items endpoint.
 *
 * The cart session is considered active until explicitly cleared by the user,
 * expired by inactivity (30 days), or merged with an authenticated user account
 * upon login. This ensures uninterrupted shopping experience across devices and
 * sessions, aligning with business requirement: "THE system SHALL persist cart
 * data to database with customer identifier."
 *
 * @param props.connection
 * @param props.body Initial configuration and metadata for creating a new
 *   shopping cart session.
 * @path /shoppingMall/cart-sessions
 * @accessor api.functional.shoppingMall.cart_sessions.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function create(
  connection: IConnection,
  props: create.Props,
): Promise<create.Response> {
  return true === connection.simulate
    ? create.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...create.METADATA,
          path: create.path(),
          status: null,
        },
        props.body,
      );
}
export namespace create {
  export type Props = {
    /**
     * Initial configuration and metadata for creating a new shopping cart
     * session.
     */
    body: IShoppingMallCartSession.ICreate;
  };
  export type Body = IShoppingMallCartSession.ICreate;
  export type Response = IShoppingMallCartSession;

  export const METADATA = {
    method: "POST",
    path: "/shoppingMall/cart-sessions",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/shoppingMall/cart-sessions";
  export const random = (): IShoppingMallCartSession =>
    typia.random<IShoppingMallCartSession>();
  export const simulate = (
    connection: IConnection,
    props: create.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: create.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
