import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallPaymentRegion } from "../../../structures/IShoppingMallPaymentRegion";

/**
 * Retrieve detailed information about a specific payment region configuration
 * from the system. This operation queries the shopping_mall_payment_regions
 * table in the database schema to extract the region's payment acceptance
 * rules, supported currencies, regional tax regulations, and payment gateway
 * configurations. The region is identified by its unique code.
 *
 * This operation is primarily used by customer-facing applications to
 * dynamically display available payment methods during checkout based on the
 * customer's location. It allows the system to enforce regional compliance with
 * financial regulations and currency requirements without hardcoding payment
 * rules.
 *
 * The response includes all relevant configuration data for the specified
 * region, including which payment methods are approved (credit cards, digital
 * wallets, bank transfers), time zone offsets for payment processing, currency
 * conversion settings, and any specific regional tax rules that must be
 * applied. This eliminates the need for clients to maintain separate payment
 * rule databases for each supported region.
 *
 * This operation is read-only and does not modify any data in the system. It
 * always returns the most current configuration for the requested region.
 *
 * Security considerations: No authentication required since payment region data
 * is public information needed for customer checkout processes. This operation
 * has no relationship with user authentication or session management systems
 * and can be called by anonymous users.
 *
 * Related operations: This data is consumed by PATCH /payments/payment-methods
 * which lists available payment options, and during POST /orders to validate
 * payment region compliance at order placement.
 *
 * @param props.connection
 * @param props.regionId Unique business identifier code of the target payment
 *   region (global scope)
 * @path /shoppingMall/payment-regions/:regionId
 * @accessor api.functional.shoppingMall.payment_regions.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique business identifier code of the target payment region (global
     * scope)
     */
    regionId: string;
  };
  export type Response = IShoppingMallPaymentRegion;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/payment-regions/:regionId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/payment-regions/${encodeURIComponent(props.regionId ?? "null")}`;
  export const random = (): IShoppingMallPaymentRegion =>
    typia.random<IShoppingMallPaymentRegion>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("regionId")(() => typia.assert(props.regionId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
