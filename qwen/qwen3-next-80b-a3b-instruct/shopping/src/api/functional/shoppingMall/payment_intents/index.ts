import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallPaymentIntent } from "../../../structures/IShoppingMallPaymentIntent";

/**
 * Retrieve a specific payment intent from the shopping mall system. This
 * operation queries the shopping_mall_payment_intents table to return detailed
 * information about a payment intent identified by its unique identifier. The
 * payment intent represents a request to initiate a payment transaction with an
 * external payment gateway and contains all metadata necessary for processing
 * the payment.
 *
 * The operation returns comprehensive details including the payment amount,
 * currency, status, payment method, and associated payment gateway transaction
 * ID. This allows clients to check the status of pending payments and retrieve
 * payment details after initiation.
 *
 * The payment intent is keyed by the paymentIntentId path parameter, which
 * references the unique ID in the shopping_mall_payment_intents table.
 * Operation is available to any authenticated user who has access to the
 * payment intent (typically the origination user or admin).
 *
 * The response includes all financial details associated with the payment
 * intent but excludes sensitive data such as credit card numbers or bank
 * account information, which are stored securely with the payment processor.
 * This ensures compliance with PCI-DSS standards. The payment status field
 * indicates the current state (created, processing, expired, succeeded, failed)
 * and can be used to determine next actions such as retrying payment or
 * applying refunds.
 *
 * Payment intents are immutable audit records and cannot be deleted.
 * Cancellation of unprocessed payments is handled by transitioning the status
 * field to 'failed', not by DELETE operations.
 *
 * @param props.connection
 * @param props.paymentIntentId Unique identifier of the payment intent to
 *   retrieve. This ID is a UUID generated by the system when the payment intent
 *   is created and references the primary key field in the
 *   shopping_mall_payment_intents table.
 * @path /shoppingMall/payment-intents/:paymentIntentId
 * @accessor api.functional.shoppingMall.payment_intents.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique identifier of the payment intent to retrieve. This ID is a
     * UUID generated by the system when the payment intent is created and
     * references the primary key field in the shopping_mall_payment_intents
     * table.
     */
    paymentIntentId: string;
  };
  export type Response = IShoppingMallPaymentIntent;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/payment-intents/:paymentIntentId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/payment-intents/${encodeURIComponent(props.paymentIntentId ?? "null")}`;
  export const random = (): IShoppingMallPaymentIntent =>
    typia.random<IShoppingMallPaymentIntent>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("paymentIntentId")(() =>
        typia.assert(props.paymentIntentId),
      );
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
