import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallPromotionalCampaign } from "../../../../structures/IShoppingMallPromotionalCampaign";

/**
 * Retrieve a specific promotional campaign by its unique identifier. This
 * operation fetches the complete details of a promotional campaign from the
 * shopping_mall_promotional_campaigns table, including its name, description,
 * start and end dates, budget allocation, current usage, target customer
 * segment, status, and metadata timestamps.
 *
 * The operation validates that the campaign exists and is not logically deleted
 * (deleted_at is null). If the campaign was deleted, a 404 response is
 * returned. The campaign's status field controls visibility - active, paused,
 * or completed campaigns are visible, while draft or expired campaigns are
 * restricted to administrators with explicit permissions.
 *
 * This operation serves as the primary method for accessing detailed campaign
 * information in the system. Related operations include listing all campaigns
 * (GET /promotions/promotional-campaigns) and retrieving coupon data associated
 * with this campaign (GET /promotions/coupons?campaignId={campaignId}).
 *
 * @param props.connection
 * @param props.campaignId The unique identifier of the promotional campaign to
 *   retrieve. This is typically a UUID assigned by the system when the campaign
 *   is created, and it refers to the shopping_mall_promotional_campaigns.id
 *   field.
 * @path /shoppingMall/promotions/promotional-campaigns/:campaignId
 * @accessor api.functional.shoppingMall.promotions.promotional_campaigns.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * The unique identifier of the promotional campaign to retrieve. This
     * is typically a UUID assigned by the system when the campaign is
     * created, and it refers to the shopping_mall_promotional_campaigns.id
     * field.
     */
    campaignId: string & tags.Format<"uuid">;
  };
  export type Response = IShoppingMallPromotionalCampaign;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/promotions/promotional-campaigns/:campaignId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/promotions/promotional-campaigns/${encodeURIComponent(props.campaignId ?? "null")}`;
  export const random = (): IShoppingMallPromotionalCampaign =>
    typia.random<IShoppingMallPromotionalCampaign>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("campaignId")(() => typia.assert(props.campaignId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
