import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallCouponRedemption } from "../../../../structures/IShoppingMallCouponRedemption";

/**
 * Retrieve detailed information about a specific coupon redemption event from
 * the shoppingMall system. This operation accesses the
 * shopping_mall_coupon_redemptions table to provide full context about a single
 * coupon redemption transaction. The redemption record includes complete
 * details about the customer, coupon, order, discount applied, and timestamp.
 *
 * The operation returns a comprehensive view of the redemption event that
 * occurred at checkout. This data is essential for customer support inquiries,
 * financial reconciliation, abuse detection, and understanding coupon usage
 * patterns.
 *
 * Security: Only authenticated users can access their own redemption records.
 * Administrators can access any redemption record for auditing and support
 * purposes.
 *
 * This operation does not modify any data - it is read-only and provides a
 * snapshot of the redemption as it occurred at the moment of checkout.
 *
 * Linked operations: This operation complements the GET
 * /promotions/coupons/{couponId} operation, which provides metadata about the
 * coupon itself, while this operation provides the actual redemption event
 * data.
 *
 * @param props.connection
 * @param props.redemptionId Unique identifier of the coupon redemption record
 *   to retrieve. This ID corresponds to the primary key of the
 *   shopping_mall_coupon_redemptions table.
 * @path /shoppingMall/promotions/coupon-redemptions/:redemptionId
 * @accessor api.functional.shoppingMall.promotions.coupon_redemptions.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique identifier of the coupon redemption record to retrieve. This
     * ID corresponds to the primary key of the
     * shopping_mall_coupon_redemptions table.
     */
    redemptionId: string & tags.Format<"uuid">;
  };
  export type Response = IShoppingMallCouponRedemption;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/promotions/coupon-redemptions/:redemptionId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/promotions/coupon-redemptions/${encodeURIComponent(props.redemptionId ?? "null")}`;
  export const random = (): IShoppingMallCouponRedemption =>
    typia.random<IShoppingMallCouponRedemption>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("redemptionId")(() => typia.assert(props.redemptionId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
