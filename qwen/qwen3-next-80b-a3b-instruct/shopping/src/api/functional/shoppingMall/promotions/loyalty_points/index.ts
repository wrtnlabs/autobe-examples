import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallLoyaltyPointTransaction } from "../../../../structures/IShoppingMallLoyaltyPointTransaction";
import { IPageIShoppingMallLoyaltyPointTransaction } from "../../../../structures/IPageIShoppingMallLoyaltyPointTransaction";

/**
 * Retrieve paginated, filtered list of loyalty point transactions based on
 * search criteria and filters. This operation operates on the
 * shopping_mall_loyalty_point_transactions table from the Prisma schema and
 * provides comprehensive search and filtering capabilities for loyalty point
 * transactions.
 *
 * Users can filter transactions by customer, transaction type (purchase_reward,
 * sign_up_bonus, referral_bonus, point_redemption, admin_adjustment), status
 * (pending, completed, reversed), date ranges, and search by description. The
 * operation supports pagination with configurable page sizes and sorting by
 * points change amount, transaction date, or status.
 *
 * This operation is designed for administrative oversight, customer service
 * investigations, and internal reconciliation purposes. Only authenticated
 * users with appropriate permissions can access transaction data. The results
 * include summary information with customer information, transaction type,
 * points change, and status.
 *
 * Note that loyalty point balances themselves are maintained in the
 * shopping_mall_loyalty_points table, but individual transactions are recorded
 * in this table for auditability. For querying current point balances, use the
 * shopping_mall_loyalty_points endpoint instead. This endpoint focuses on the
 * transaction history that leads to current balances.
 *
 * Application Domain: This operation is essential for revenue analytics, fraud
 * detection by identifying unusual transaction patterns, customer service
 * investigations where customers question point activity, and reconciliation
 * between system balances and transaction records.
 *
 * @param props.connection
 * @param props.body Search parameters and filtering criteria for loyalty point
 *   transactions
 * @path /shoppingMall/promotions/loyalty-points
 * @accessor api.functional.shoppingMall.promotions.loyalty_points.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Search parameters and filtering criteria for loyalty point
     * transactions
     */
    body: IShoppingMallLoyaltyPointTransaction.IRequest;
  };
  export type Body = IShoppingMallLoyaltyPointTransaction.IRequest;
  export type Response = IPageIShoppingMallLoyaltyPointTransaction.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/promotions/loyalty-points",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/shoppingMall/promotions/loyalty-points";
  export const random =
    (): IPageIShoppingMallLoyaltyPointTransaction.ISummary =>
      typia.random<IPageIShoppingMallLoyaltyPointTransaction.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
