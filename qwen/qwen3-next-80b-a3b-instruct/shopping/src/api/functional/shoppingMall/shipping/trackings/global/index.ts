/**
 * Retrieve global shipping tracking information for all orders across the
 * platform. This operation queries the delivery_trackings and order_shipments
 * tables to provide comprehensive shipping status data. It supports advanced
 * filtering by status, carrier, date range, and shipment method. The response
 * includes all tracking details such as tracking number, carrier name, current
 * status, location, estimated delivery date, and shipment date.
 *
 * This operation is designed to support administrative monitoring and customer
 * service functions by providing a comprehensive view of shipment statuses
 * across the entire platform. It returns data from multiple related tables
 * including shipping_mall_delivery_trackings for tracking events and
 * shipping_mall_order_shipments for shipment details.
 *
 * The system combines data from the delivery_trackings table (which records
 * individual logistics events) with the order_shipments table (which stores
 * shipment configuration details including carrier and method). This allows for
 * a comprehensive view of shipments from order placement through delivery
 * completion.
 *
 * Security: This operation is publicly accessible to allow customers and
 * support staff to track shipments. Rate limiting applies to prevent abuse by
 * automated scrapers. The operation does not expose sensitive customer
 * information beyond what's necessary for tracking purposes.
 *
 * Implementation note: This does not map to a single database table - it
 * performs a JOIN between shipping_mall_delivery_trackings and
 * shipping_mall_order_shipments:
 *
 * SELECT ost.tracking_number, ost.carrier, ost.shipping_method, ost.created_at
 * as shipment_date, dt.status, dt.location, dt.event_time as last_updated,
 * dt.estimated_delivery_date, dt.actual_delivery_date, ost.order_id FROM
 * shipping_mall_order_shipments ost JOIN shipping_mall_delivery_trackings dt ON
 * ost.tracking_number = dt.tracking_number ORDER BY dt.event_time DESC
 *
 * This composite query serves the business need for real-time, comprehensive
 * shipping visibility across the entire platform and integrates data from two
 * separate system components.
 *
 * @param props.connection
 * @param props.body Filtering and pagination parameters for global shipping
 *   tracking search
 * @path /shoppingMall/shipping/trackings/global
 * @accessor api.functional.shoppingMall.shipping.trackings.global.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Filtering and pagination parameters for global shipping tracking
     * search
     */
    body: IShoppingMallShippingTracking.IRequest;
  };
  export type Body = IShoppingMallShippingTracking.IRequest;
  export type Response = IPageIShoppingMallShippingTracking;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/shipping/trackings/global",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/shoppingMall/shipping/trackings/global";
  export const random = (): IPageIShoppingMallShippingTracking =>
    typia.random<IPageIShoppingMallShippingTracking>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
