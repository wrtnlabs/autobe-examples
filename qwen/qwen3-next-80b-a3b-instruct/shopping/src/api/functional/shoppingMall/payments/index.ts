  export type Props = {
    /**
     * Unique identifier of the payment record to retrieve. This is a
     * system-generated UUID that uniquely identifies the payment
     * transaction within the shopping_mall_payments table.
     */
    paymentId: string;
  };
  export type Response = IShoppingMallPayment;

