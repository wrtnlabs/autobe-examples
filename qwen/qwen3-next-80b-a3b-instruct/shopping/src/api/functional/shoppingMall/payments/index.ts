/**
 * Retrieve detailed payment information by payment identifier from the
 * shopping_mall_payments table. This operation returns a complete payment
 * record with all associated metadata including amount, currency, payment
 * method, gateway transaction ID, status, and timestamps. The payment_id is
 * used as a direct lookup key in the database, ensuring fast retrieval of
 * payment records for customer account displays, reconciliation reports, and
 * support inquiries.
 *
 * Security: This endpoint is publicly accessible as payment records are
 * considered non-sensitive metadata that do not contain financial tokens, card
 * numbers, or personal authentication data. No authentication is required since
 * the payment_id is a random, cryptographically generated identifier that
 * cannot be feasibly guessed, and all payment data returned is already exposed
 * in order confirmation emails and customer account portals.
 *
 * Business logic: The operation returns the exact payment record as stored in
 * the database with no filtering, transformation, or aggregation. This ensures
 * data accuracy for reconciliation purposes. Payment status reflects the live
 * state in the payment gateway (e.g., pending, completed, failed, refunded).
 * Date fields are returned in ISO 8601 format with timezone. Any failed payment
 * attempts are included in the results for audit trail completeness.
 *
 * Related operations: POST /payments creates new payment intents. PATCH
 * /payments/{paymentId}/refunds initiates refund processes. The payment
 * information returned here is used as the authoritative source when displaying
 * payment status to customers and during financial reconciliation between the
 * platform and payment processors.
 *
 * Implementation note: This operation is a simple key-value lookup on the
 * shopping_mall_payments table with payment_id as the primary identifier. No
 * joins or complex queries are required. The operation returns the raw payment
 * record stored in the database with all fields preserved as-is.
 *
 * @param props.connection
 * @param props.paymentId Unique identifier of the payment record to retrieve.
 *   This is a system-generated UUID that uniquely identifies the payment
 *   transaction within the shopping_mall_payments table.
 * @path /shoppingMall/payments/:paymentId
 * @accessor api.functional.shoppingMall.payments.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
