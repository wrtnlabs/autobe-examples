/**
 * Delete a product brand record from the shopping mall system. This operation
 * permanently removes the brand entity from the database and affects all
 * associated products, which will have their brand references cleared. The
 * brand identification is based on the brandId path parameter, which
 * corresponds to the brandId field in the shopping_mall_product_brands table.
 * This is a hard delete operation that cannot be undone, with no soft-delete
 * column configured in the schema. The operation requires admin-level
 * authorization to prevent unauthorized deletion of brand entities that could
 * impact product catalogs and customer purchasing decisions.
 *
 * Product brands serve as critical identifiers for product categorization,
 * customer trust, and marketing campaigns within the shopping mall ecosystem.
 * Deleting a brand affects all products associated with it, causing those
 * products to become unbranded and potentially impacting search, filtering, and
 * customer expectations.
 *
 * Given the business context of a shopping mall system, brand deletion should
 * be strictly limited to administrators with full system control. This prevents
 * accidental loss of valuable brand identities that may be associated with
 * significant inventory, customer loyalty, and marketing investments. All
 * brand-related products continue to exist in the system but have their brand
 * field cleared to NULL, preserving historical data integrity while removing
 * the brand identity.
 *
 * The deletion operation is accompanied by the system automatically clearing
 * the brandId reference in all related products to maintain referential
 * integrity. This ensures no orphaned references remain in the product catalog.
 * The system does not maintain audit logs of brand deletions through this
 * endpoint since brand deletion is considered a rare administrative action,
 * with broader administrative audit logs handling system-wide change tracking.
 *
 * @param props.connection
 * @param props.brandId Unique identifier of the brand to be deleted. This
 *   corresponds to the brandId field in the shopping_mall_product_brands table
 *   and is used to locate the specific brand for deletion.
 * @path /shoppingMall/brands/:brandId
 * @accessor api.functional.shoppingMall.brands.erase
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function erase(
  connection: IConnection,
  props: erase.Props,
): Promise<void> {
  return true === connection.simulate
    ? erase.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...erase.METADATA,
          path: erase.path(props),
          status: null,
        },
      );
}
export namespace erase {
  export type Props = {
    /**
     * Unique identifier of the brand to be deleted. This corresponds to the
     * brandId field in the shopping_mall_product_brands table and is used
     * to locate the specific brand for deletion.
     */
    brandId: string;
  };

  export const METADATA = {
    method: "DELETE",
    path: "/shoppingMall/brands/:brandId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/brands/${encodeURIComponent(props.brandId ?? "null")}`;
  export const random = (): void => typia.random<void>();
  export const simulate = (
    connection: IConnection,
    props: erase.Props,
  ): void => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: erase.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("brandId")(() => typia.assert(props.brandId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

