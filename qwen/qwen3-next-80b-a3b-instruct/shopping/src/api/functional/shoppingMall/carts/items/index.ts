import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallCartItem } from "../../../../structures/IShoppingMallCartItem";

/**
 * Update a specific item within a customer's shopping cart.
 *
 * This operation modifies the quantity or status of an individual cart item
 * identified by its unique cart and item IDs. When a customer adjusts their
 * cart (increasing/decreasing item quantity or removing an item from purchase
 * intent), this endpoint handles the modification with atomic validation.
 *
 * The operation validates that the cart exists and is still active (not expired
 * or checked out), that the cart item belongs to the specified cart (enforced
 * by foreign key constraint), and that the new quantity does not exceed the
 * current inventory of the product variant. The price is not modified as it was
 * captured at the time of cart addition to ensure purchase consistency.
 *
 * Security: Only the cart owner (authenticated customer) can modify cart items.
 * The cart's customer_id is verified against the authenticated user's
 * identity.
 *
 * State transitions:
 *
 * - If quantity becomes 0, item.status transitions to 'removed'
 * - If inventory becomes insufficient after quantity adjustment, item.status
 *   transitions to 'out_of_stock'
 * - If quantity increases and inventory becomes available, item.status
 *   transitions back to 'active'
 *
 * This operation directly modifies the shopping_mall_cart_items table and is
 * atomic - either all changes succeed or none do.
 *
 * Related Operations:
 *
 * - GET /carts/{cartId}/items - View all items in a cart
 * - DELETE /carts/{cartId}/items/{itemId} - Remove the item from cart
 * - POST /carts/{cartId}/items - Add a new item to cart
 * - PATCH /carts/{cartId} - Check out the entire cart
 *
 * @param props.connection
 * @param props.cartId Unique identifier of the shopping cart containing the
 *   item. Must match the cart_id in shopping_mall_carts table. This property
 *   provides the context for the cart item update.
 * @param props.itemId Unique identifier of the cart item to be updated. Must
 *   match the id in shopping_mall_cart_items table. This identifies the
 *   specific item within the cart to be modified.
 * @param props.body Updated quantity and status information for the cart item.
 * @path /shoppingMall/carts/:cartId/items/:itemId
 * @accessor api.functional.shoppingMall.carts.items.update
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function update(
  connection: IConnection,
  props: update.Props,
): Promise<update.Response> {
  return true === connection.simulate
    ? update.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...update.METADATA,
          path: update.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace update {
  export type Props = {
    /**
     * Unique identifier of the shopping cart containing the item. Must
     * match the cart_id in shopping_mall_carts table. This property
     * provides the context for the cart item update.
     */
    cartId: string & tags.Format<"uuid">;

    /**
     * Unique identifier of the cart item to be updated. Must match the id
     * in shopping_mall_cart_items table. This identifies the specific item
     * within the cart to be modified.
     */
    itemId: string & tags.Format<"uuid">;

    /** Updated quantity and status information for the cart item. */
    body: IShoppingMallCartItem.IUpdate;
  };
  export type Body = IShoppingMallCartItem.IUpdate;
  export type Response = IShoppingMallCartItem;

  export const METADATA = {
    method: "PUT",
    path: "/shoppingMall/carts/:cartId/items/:itemId",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/shoppingMall/carts/${encodeURIComponent(props.cartId ?? "null")}/items/${encodeURIComponent(props.itemId ?? "null")}`;
  export const random = (): IShoppingMallCartItem =>
    typia.random<IShoppingMallCartItem>();
  export const simulate = (
    connection: IConnection,
    props: update.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: update.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("cartId")(() => typia.assert(props.cartId));
      assert.param("itemId")(() => typia.assert(props.itemId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

/**
 * Remove a specific item from a customer's shopping cart.
 *
 * This operation permanently removes an individual cart item from the cart,
 * reducing the cart's total item count and value. Unlike marking an item as
 * 'removed' in status, this operation deletes the cart item record entirely
 * from the database.
 *
 * The operation validates that the cart exists and is still active (not expired
 * or checked out), that the cart item belongs to the specified cart (enforced
 * by foreign key constraint), and that no other system processes are currently
 * modifying this item. This prevents race conditions during cart
 * modifications.
 *
 * Security: Only the cart owner (authenticated customer) can remove items from
 * their cart. The cart's customer_id is verified against the authenticated
 * user's identity.
 *
 * After removal, the system does not track this specific cart item any longer.
 * For audit purposes, the removal event may be logged separately in
 * shopping_mall_audit_logs table.
 *
 * This is a hard delete operation that permanently removes the record. The cart
 * item record is not subject to soft deletion.
 *
 * Related Operations:
 *
 * - PUT /carts/{cartId}/items/{itemId} - Update cart item details
 * - GET /carts/{cartId}/items - View all items in a cart
 * - POST /carts/{cartId}/items - Add a new item to cart
 *
 * @param props.connection
 * @param props.cartId Unique identifier of the shopping cart from which to
 *   remove the item. Must match the cart_id in shopping_mall_carts table.
 * @param props.itemId Unique identifier of the cart item to be permanently
 *   removed. Must match the id in shopping_mall_cart_items table.
 * @path /shoppingMall/carts/:cartId/items/:itemId
 * @accessor api.functional.shoppingMall.carts.items.erase
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
