/**
 * Add a product variant to a customer's shopping cart.
 *
 * This operation allows authenticated customers to add a specific product
 * variant to their active cart. The cart must be associated with the requesting
 * customer, either through direct ownership for authenticated users or session
 * linkage for guest users. When an item is added, the system verifies the
 * variant's current availability (inventory > 0) and price, ensuring the
 * customer receives accurate inventory and pricing information.
 *
 * The operation creates a cart item record linking the cart to the chosen
 * product variant with quantity 1 by default, capturing the variant's current
 * price at the time of addition to ensure price consistency even if the
 * product's price changes afterward. The system does not allow duplicate
 * entries for the same variant in a cart; instead, it increments the quantity
 * of the existing item.
 *
 * Security: Only authenticated customers can add items to their own cart. The
 * cart identifier in the path must correspond to a cart owned by the
 * authenticating user. The system validates that the referenced product variant
 * exists and is active before creating the cart item attachment.
 *
 * Business Logic: If the requested product variant is out of stock, the system
 * returns a 400 error with the message "Product variant is out of stock." If
 * the variant's price has changed since it was last viewed, the system uses the
 * current price for the new cart entry and may notify the customer of price
 * changes.
 *
 * Related Operations: GET /carts/{cartId} to view cart contents, PATCH
 * /carts/{cartId}/items to update item quantity, DELETE
 * /carts/{cartId}/items/{cartItemId} to remove items from cart.
 *
 * @param props.connection
 * @param props.cartId Unique identifier of the target shopping cart. This must
 *   be a cart belonging to the authenticated customer or an active guest cart
 *   associated with the current session.
 * @param props.body Details of the product variant to add to the cart.
 * @path /shoppingMall/customer/carts/:cartId/items
 * @accessor api.functional.shoppingMall.customer.carts.items.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
