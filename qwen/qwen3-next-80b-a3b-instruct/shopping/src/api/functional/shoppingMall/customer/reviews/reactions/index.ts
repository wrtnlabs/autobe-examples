/**
 * Create a new reaction (upvote or downvote) to a specific product review. This
 * operation adds an entry to the shopping_mall_review_reactions table,
 * recording a customer's feedback on the helpfulness of a review. Each customer
 * can create only one reaction per review, and the system enforces this
 * uniqueness constraint. The operation validates that the review exists, the
 * user is authenticated, and they have not already voted on this particular
 * review. This creates a record that helps surface the most helpful reviews
 * through community-based quality assessment.
 *
 * Security: Only authenticated customers can create reactions. Users cannot
 * react to reviews they created themselves. This prevents self-promotion and
 * manipulation of review quality metrics.
 *
 * Implementation note: Inserts a new row into shopping_mall_review_reactions
 * with operation_id from JWT token and validation against unique constraint on
 * (shopping_mall_review_id, shopping_mall_customer_id). If a duplicate is
 * attempted, the server returns a 409 Conflict error. Reactions are not subject
 * to moderation and become immediately visible.
 *
 * Related operations: PATCH /reviews/{reviewId}/reactions (to view existing
 * reactions), GET /reviews/{reviewId} (to view the review).
 *
 * @param props.connection
 * @param props.reviewId Unique identifier of the target review. This UUID
 *   refers to the shopping_mall_review_id in the shopping_mall_reviews table.
 * @param props.body The reaction data including type ('upvote' or 'downvote')
 *   to record for this review.
 * @path /shoppingMall/customer/reviews/:reviewId/reactions
 * @accessor api.functional.shoppingMall.customer.reviews.reactions.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function create(
  connection: IConnection,
  props: create.Props,
): Promise<create.Response> {
  return true === connection.simulate
    ? create.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...create.METADATA,
          path: create.path(props),
          status: null,
        },
        props.body,
      );
}
