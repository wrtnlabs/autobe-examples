import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallProductBrand } from "../../../../structures/IShoppingMallProductBrand";

/**
 * Retrieve detailed information about a specific product brand from the
 * shopping_mall_product_brands table.
 *
 * This operation fetches comprehensive brand details including the brand name,
 * logo URL, description, creation and update timestamps, and verification
 * status. The brand data is used to display product brand information on
 * catalog pages, product detail pages, and search results.
 *
 * Security considerations ensure that only authenticated users can access brand
 * information, as brand data may contain proprietary information and
 * trademarks. The endpoint supports filtering based on verified status,
 * allowing the system to surface only officially verified brands to customers
 * while still providing access to unverified brands for administrative
 * purposes.
 *
 * The brand verification status is used to indicate whether a brand has been
 * formally reviewed and approved by platform administrators. Verified brands
 * receive enhanced visibility in search results and catalog listings. This
 * operation also includes the banner image URL if available, providing visual
 * branding context for integrated marketing campaigns.
 *
 * Related operations include GET /brands to search multiple brands and PATCH
 * /brands to retrieve paginated brand lists with advanced filtering options.
 *
 * @param props.connection
 * @param props.brandId Unique identifier of the target brand record in the
 *   shopping_mall_product_brands table
 * @path /shoppingMall/customer/brands/:brandId
 * @accessor api.functional.shoppingMall.customer.brands.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique identifier of the target brand record in the
     * shopping_mall_product_brands table
     */
    brandId: string;
  };
  export type Response = IShoppingMallProductBrand;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/customer/brands/:brandId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/customer/brands/${encodeURIComponent(props.brandId ?? "null")}`;
  export const random = (): IShoppingMallProductBrand =>
    typia.random<IShoppingMallProductBrand>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("brandId")(() => typia.assert(props.brandId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
