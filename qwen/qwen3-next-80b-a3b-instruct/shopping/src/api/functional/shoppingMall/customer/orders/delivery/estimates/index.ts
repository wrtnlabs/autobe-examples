/**
 * Retrieve estimated delivery timeframes for a specific order. This operation
 * queries the shopping_mall_order_shipments and
 * shopping_mall_delivery_trackings tables to compute realistic delivery
 * timelines based on the order's shipping method and current transit status.
 *
 * The system calculates delivery estimates by combining the historical
 * performance data of the assigned carrier with real-time tracking updates from
 * logistics providers. When an order is shipped, the system automatically
 * creates a shipment record with the carrier's estimated delivery window, which
 * is then refined as tracking data becomes available through carrier APIs.
 *
 * Delivery estimates are presented in a human-readable format (e.g., "3-5
 * business days") and include a specific date range based on the shipment's
 * processing status. The estimate updates dynamically as tracking information
 * is received. For example, if a package is confirmed to be at a sorting
 * facility, the estimate may update to "Delivered by next business day".
 *
 * The system ensures delivery estimates comply with carrier SLAs, and provides
 * different estimates based on shipping tier (standard, expedited, overnight).
 * All estimates are calculated with business days only, excluding weekends and
 * public holidays according to the customer's shipping region.
 *
 * This operation returns comprehensive delivery timelines that help customers
 * plan for receipt of their order, and also supports customer service
 * operations by providing accurate information to address inquiries about
 * delivery status. The estimates are not guaranteed delivery dates but are
 * probabilistic projections based on historical carrier performance and current
 * transit status.
 *
 * The operation is read-only and does not modify any data in the database. The
 * delivery estimates are computed from the existing shipment records and
 * tracking events in the system.
 *
 * Note: If no shipment has been created for this order yet, the delivery
 * estimate will be "Processing - Shipping details pending.".
 *
 * @param props.connection
 * @param props.orderId Unique identifier of the target order. This parameter is
 *   used to look up the related shopping_mall_orders record in the database.
 *   The system verifies that the order exists and that the requesting user has
 *   appropriate permissions to view its details.
 * @path /shoppingMall/customer/orders/:orderId/delivery/estimates
 * @accessor api.functional.shoppingMall.customer.orders.delivery.estimates.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique identifier of the target order. This parameter is used to look
     * up the related shopping_mall_orders record in the database. The
     * system verifies that the order exists and that the requesting user
     * has appropriate permissions to view its details.
     */
    orderId: string & tags.Format<"uuid">;
  };
  export type Response = IShoppingMallOrderDeliveryEstimate;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/customer/orders/:orderId/delivery/estimates",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/customer/orders/${encodeURIComponent(props.orderId ?? "null")}/delivery/estimates`;
  export const random = (): IShoppingMallOrderDeliveryEstimate =>
    typia.random<IShoppingMallOrderDeliveryEstimate>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("orderId")(() => typia.assert(props.orderId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
