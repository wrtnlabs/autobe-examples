/**
 * Update vote status on a product review. This operation allows authenticated
 * users to cast or modify their vote on a specific product review, indicating
 * whether they found the review helpful or unhelpful.
 *
 * This operation operates on the shopping_mall_review_votes table, which tracks
 * individual user votes on product reviews. Each vote record links a customer
 * (user) to a specific review and records their voting decision as either
 * helpful or unhelpful. The system allows a user to change their vote at any
 * time but only permits one vote per user-review pair.
 *
 * Security: Only authenticated users can vote on reviews. The user ID is
 * extracted from the JWT token and used to validate ownership of the vote.
 * Admins can update votes for moderation purposes. The operation validates that
 * the target review exists and belongs to the system.
 *
 * Implementation: When a user votes, the system checks for an existing vote
 * record. If one exists, it updates the vote value (helpful/unhelpful). If none
 * exists, it creates a new record. To prevent duplicate votes from the same
 * user on the same review, the database enforces a unique constraint on
 * (review_id, user_id).
 *
 * Related operations: GET /reviews/{reviewId} returns review with vote totals;
 * PATCH /reviews/{reviewId}/votes returns the user's current vote status;
 * DELETE /reviews/{reviewId}/votes removes a vote.
 *
 * @param props.connection
 * @param props.reviewId Unique identifier of the target product review to be
 *   voted on (global scope)
 * @param props.body Vote update request body containing the new vote status
 *   (helpful or unhelpful)
 * @path /shoppingMall/customer/reviews/:reviewId/votes
 * @accessor api.functional.shoppingMall.customer.reviews.votes.update
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
