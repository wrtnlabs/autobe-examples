import { IConnection } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";

import { IShoppingMallWishlistSummary } from "../../../../structures/IShoppingMallWishlistSummary";
export * as items from "./items/index";

/**
 * Retrieve a comprehensive summary of all wishlists associated with the
 * authenticated customer. This operation analyzes data from the
 * shopping_mall_wishlists and shopping_mall_wishlist_items tables to generate a
 * high-level overview of the customer's wishlist activity without exposing
 * individual item details.
 *
 * The summary provides key metrics including the total number of wishlists,
 * total items across all wishlists, and the count of wishlists containing
 * out-of-stock items. This information enables the customer to quickly
 * understand their overall wishlist engagement without navigating to individual
 * wishlist pages.
 *
 * Security considerations include ensuring the operation only returns data for
 * the authenticated customer by matching the JWT token's user ID with the
 * wishlist owner reference. Rate limiting applies to prevent abuse through
 * rapid summation requests. The operation does not expose any private item
 * details or pricing information to maintain customer privacy.
 *
 * This summary operation complements the detailed wishlist retrieval APIs
 * (/wishlists/{wishlistId}) by providing a low-overhead overview. The summary
 * data is compiled each time the endpoint is accessed, ensuring real-time
 * accuracy without requiring separate caching mechanisms.
 *
 * @param props.connection
 * @path /shoppingMall/customer/wishlists/summary
 * @accessor api.functional.shoppingMall.customer.wishlists.summary
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function summary(
  connection: IConnection,
): Promise<summary.Response> {
  return true === connection.simulate
    ? summary.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...summary.METADATA,
          path: summary.path(),
          status: null,
        },
      );
}
export namespace summary {
  export type Response = IShoppingMallWishlistSummary;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/customer/wishlists/summary",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/shoppingMall/customer/wishlists/summary";
  export const random = (): IShoppingMallWishlistSummary =>
    typia.random<IShoppingMallWishlistSummary>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}
