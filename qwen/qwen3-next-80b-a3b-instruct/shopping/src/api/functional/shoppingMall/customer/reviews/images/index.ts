/**
 * Upload an image to accompany a product review.
 *
 * This operation allows authenticated customers to attach visual evidence to
 * their product reviews. Each review can have multiple images that provide
 * additional context about the product experience, including photos of product
 * quality, usage scenarios, or issues encountered. Images are strictly
 * associated with their parent review and cannot exist independently.
 *
 * Images are uploaded as URIs referencing stored files in a content delivery
 * network. The system generates secure, permanent URLs upon successful upload.
 * Each review image is moderated separately from the review text and may be
 * removed if it violates content policies.
 *
 * After upload, images become visible only after the parent review has been
 * published. If the review is rejected, all associated images are automatically
 * hidden. Admins can view all uploaded images for moderation purposes with full
 * audit trails.
 *
 * Related operations: DELETE /reviews/{reviewId}/images/{imageId} (removes
 * specific image)
 *
 * Implementation note: Image URLs are generated by a secure file upload service
 * and cannot be directly manipulated by clients.
 *
 * @param props.connection
 * @param props.reviewId Unique identifier of the parent product review. This is
 *   the review to which the image will be attached. Every image must belong to
 *   exactly one review.
 *
 *                 This references {@link shopping_mall_reviews.id} in the Prisma schema.
 * @param props.body Image data for upload with secure URI reference.
 * @path /shoppingMall/customer/reviews/:reviewId/images
 * @accessor api.functional.shoppingMall.customer.reviews.images.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
