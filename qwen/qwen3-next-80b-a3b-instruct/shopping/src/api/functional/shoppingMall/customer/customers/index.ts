import { IShoppingMallCustomer } from "../../../../structures/IShoppingMallCustomer";

/**
 * Retrieve detailed information about a specific customer account from the
 * shopping mall platform. This operation queries the shopping_mall_customers
 * table to return comprehensive customer data including personal information,
 * registration details, authentication status, and customer-specific
 * preferences.
 *
 * The operation returns the complete customer profile as defined in the
 * shopping_mall_customers database schema, including fields such as name,
 * email, phone, address information, registration timestamp, and account
 * status. Only verified and active customer accounts can be accessed through
 * this endpoint.
 *
 * Security is enforced at the business logic level where the system verifies
 * that the requesting user either matches the requested customer ID or is an
 * administrator with proper privileges. For regular users, this endpoint
 * enforces strict ownership verification to prevent unauthorized access to
 * other customers' profiles.
 *
 * This operation supports the customer profile view in the shopping mall
 * application and is essential for user profile management, order history
 * access, and personalized recommendations. The response data structure follows
 * the IShoppingMallCustomer type as defined in the database schema, ensuring
 * type safety and consistency across the system.
 *
 * @param props.connection
 * @param props.customerId Unique identifier of the target customer account.
 *   This field is derived directly from the shopping_mall_customers table
 *   primary key, ensuring precise customer identification. For security and
 *   performance reasons, this field is defined as a UUID, which is the database
 *   schema's designated identifier for customer records.
 * @path /shoppingMall/customer/customers/:customerId
 * @accessor api.functional.shoppingMall.customer.customers.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique identifier of the target customer account. This field is
     * derived directly from the shopping_mall_customers table primary key,
     * ensuring precise customer identification. For security and
     * performance reasons, this field is defined as a UUID, which is the
     * database schema's designated identifier for customer records.
     */
    customerId: string & tags.Format<"uuid">;
  };
  export type Response = IShoppingMallCustomer;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/customer/customers/:customerId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/customer/customers/${encodeURIComponent(props.customerId ?? "null")}`;
  export const random = (): IShoppingMallCustomer =>
    typia.random<IShoppingMallCustomer>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("customerId")(() => typia.assert(props.customerId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

