/**
 * Retrieve a specific attribute of a product by its unique identifier.
 *
 * This operation allows customers and authorized users to fetch detailed
 * attribute information associated with a specific product. The attribute is
 * linked to the product via its primary identifier in the database, ensuring
 * accurate retrieval of the correct attribute data.
 *
 * The operation is designed for product detail pages, comparison tools, and
 * filtering systems where users need to view specific product characteristics
 * such as size, color, material, or technical specifications. The data
 * retrieved comes directly from the product_attributes table in the database
 * schema and is presented in its raw format without transformation.
 *
 * Access to this endpoint is restricted to authenticated users only, regardless
 * of role, as attribute information is considered part of the product's core
 * presentation. The system does not differentiate permission levels between
 * user roles for this read operation since product attributes are public-facing
 * information.
 *
 * This operation does not support pagination or filtering as it retrieves a
 * single attribute by direct identifier reference. It is complementary to other
 * product-related operations such as GET /products/{productId} and PATCH
 * /products.
 *
 * No special permissions or administrative rights are required to access this
 * endpoint since product attributes are considered public product metadata.
 * However, the endpoint requires user authentication to maintain consistent
 * user session tracking and access logging.
 *
 * @param props.connection
 * @param props.productId Unique identifier of the target product in the system
 *   (global scope)
 * @param props.attributeId Unique identifier of the target product attribute
 *   within the product (global scope)
 * @path /shoppingMall/customer/products/:productId/attributes/:attributeId
 * @accessor api.functional.shoppingMall.customer.products.attributes.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique identifier of the target product in the system (global scope) */
    productId: string;

    /**
     * Unique identifier of the target product attribute within the product
     * (global scope)
     */
    attributeId: string;
  };
  export type Response = IShoppingMallProductAttribute;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/customer/products/:productId/attributes/:attributeId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/customer/products/${encodeURIComponent(props.productId ?? "null")}/attributes/${encodeURIComponent(props.attributeId ?? "null")}`;
  export const random = (): IShoppingMallProductAttribute =>
    typia.random<IShoppingMallProductAttribute>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("productId")(() => typia.assert(props.productId));
      assert.param("attributeId")(() => typia.assert(props.attributeId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
