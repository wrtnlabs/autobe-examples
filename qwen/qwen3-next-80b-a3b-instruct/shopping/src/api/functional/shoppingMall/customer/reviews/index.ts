/**
 * Create a new product review on the shoppingMall platform.
 *
 * This operation enables authenticated customers to submit written feedback
 * about a specific product after purchase. Each review includes a title, body
 * text, and a 1-5 star rating that quantifies the customer's satisfaction. The
 * review is initially created in 'pending' status and requires moderation by an
 * admin before becoming publicly visible.
 *
 * The operation validates that the requesting user is an authenticated customer
 * who has purchased the product being reviewed. The relationship between the
 * customer and product is checked against order history in the
 * shopping_mall_orders and shopping_mall_order_items tables. The review body
 * must be at least 10 characters to ensure meaningful feedback.
 *
 * Upon successful creation, the review is stamped with the current timestamp
 * and assigned a unique identifier. The operation returns the complete review
 * record including all metadata, but the status will remain 'pending' until
 * moderated. This design separates the submission process from the visibility
 * control, allowing for quality control and moderation workflows.
 *
 * This endpoint directly corresponds to the shopping_mall_reviews Prisma table
 * and uses all required fields: shopping_mall_product_id,
 * shopping_mall_customer_id, title, body, rating, status, created_at,
 * updated_at.
 *
 * Related operations: GET /reviews/{reviewId} (retrieve individual review), PUT
 * /reviews/{reviewId} (update review), PATCH /reviews (search and filter
 * reviews).
 *
 * @param props.connection
 * @param props.body Data required to create a new product review.
 * @path /shoppingMall/customer/reviews
 * @accessor api.functional.shoppingMall.customer.reviews.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
