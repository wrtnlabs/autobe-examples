import { IConnection } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";

import { IShoppingMallCartSummary } from "../../../../../structures/IShoppingMallCartSummary";

/**
 * Retrieve a summarized view of the customer's shopping cart containing total
 * item count, total value, and cart state details. This operation operates on
 * the shopping_mall_carts and shopping_mall_cart_items tables from the database
 * schema, aggregating cart data for the currently authenticated customer to
 * provide a quick overview without retrieving individual line items.
 *
 * The summary includes the total number of unique product variants in the cart,
 * the combined monetary value of all items calculated at current variant
 * pricing, and the cart's current state (active, abandoned, or pending
 * checkout). The cart state is determined by the presence or absence of active
 * order associations and the last activity timestamp.
 *
 * To ensure performance and reduce data transfer, this operation does not
 * return detailed line items or product information - it provides only
 * aggregated metrics. For detailed cart contents, customers should use the GET
 * /carts/{cartId}/items endpoint.
 *
 * Security: This operation is restricted to authenticated customers only. The
 * system automatically retrieves the cart identifier from the customer's
 * authenticated session, ensuring that each user sees only their own cart
 * summary. No cart ID parameters are exposed in the API since the cart is
 * implicitly tied to the authenticated user's session.
 *
 * Related operations: GET /carts/{cartId}/items (for detailed cart contents),
 * POST /carts/checkout (to initiate purchase from this summary state).
 *
 * @param props.connection
 * @path /shoppingMall/customer/carts/summary
 * @accessor api.functional.shoppingMall.customer.carts.summary.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(connection: IConnection): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(),
          status: null,
        },
      );
}
export namespace at {
  export type Response = IShoppingMallCartSummary;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/customer/carts/summary",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/shoppingMall/customer/carts/summary";
  export const random = (): IShoppingMallCartSummary =>
    typia.random<IShoppingMallCartSummary>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}
