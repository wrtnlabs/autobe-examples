import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallConfiguration } from "../../../../structures/IShoppingMallConfiguration";

/**
 * Retrieve the specific shopping mall configuration using its unique business
 * identifier code. This operation accesses the shopping_mall_configurations
 * table and returns the configuration data that controls platform-wide settings
 * such as payment gateway preferences, shipping method availability, currency
 * options, and other customizable business parameters. The configuration is
 * identified by its code field which contains human-readable identifiers like
 * "payment-gateway-production" or "shipping-allowed-countries", ensuring URLs
 * are user-friendly.
 *
 * The configuration code must be a valid key from the
 * shopping_mall_configurations table which contains predefined configuration
 * entries. The endpoint ensures that only publicly readable configurations are
 * returned and does not expose sensitive system secrets or admin-only
 * configuration values. Security is maintained by ensuring that configuration
 * access does not require authentication and is accessible to everyone,
 * including guests, as these are public platform settings.
 *
 * This operation is critical for frontend applications to dynamically configure
 * interface elements based on platform-wide business rules, such as displaying
 * accepted payment methods, enabled countries for shipping, or the appropriate
 * currency symbol. It provides essential metadata to client applications
 * without requiring authentication, enabling seamless user experiences across
 * all user types.
 *
 * Related operations: None require pre-execution, as this is a simple retrieval
 * of static platform configuration data. This operation does not influence any
 * other system functionality and is purely read-only.
 *
 * @param props.connection
 * @param props.configCode Unique business identifier code of the target
 *   configuration (global scope)
 * @path /shoppingMall/customer/configurations/:configCode
 * @accessor api.functional.shoppingMall.customer.configurations.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique business identifier code of the target configuration (global
     * scope)
     */
    configCode: string;
  };
  export type Response = IShoppingMallConfiguration;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/customer/configurations/:configCode",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/customer/configurations/${encodeURIComponent(props.configCode ?? "null")}`;
  export const random = (): IShoppingMallConfiguration =>
    typia.random<IShoppingMallConfiguration>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("configCode")(() => typia.assert(props.configCode));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
