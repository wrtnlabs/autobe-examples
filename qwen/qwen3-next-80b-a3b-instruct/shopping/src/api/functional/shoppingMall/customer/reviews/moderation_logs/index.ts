import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IPageIShoppingMallReviewModerationLog } from "../../../../../structures/IPageIShoppingMallReviewModerationLog";

/**
 * Retrieve the complete audit history of moderation actions taken on a specific
 * product review. This operation returns an ordered list of all moderation
 * events associated with the specified review, including status changes,
 * moderator actions, and reason codes. The data comes from the
 * shopping_mall_review_moderation_logs table and provides a forensic-level
 * audit trail of all administrative interventions.
 *
 * The results are ordered chronologically from oldest to newest, showing the
 * complete evolution of a review's moderation status from creation through any
 * number of moderation actions. Each log entry includes the status before and
 * after the action, the admin who performed the action, and any explanation
 * provided by the moderator.
 *
 * This operation supports filtering based on the status of the review at the
 * time of each log entry or the ID of the moderator who performed the action.
 * While there is no search filter in the request, users can paginate through
 * the results for reviews with extensive moderation histories.
 *
 * Security: Any authenticated user can view the moderation log for any review.
 * This transparency is intentional to build trust in the moderation system -
 * all moderation decisions are public by design to prevent abuse of moderation
 * power.
 *
 * Implementation note: This operation executes a query on
 * shopping_mall_review_moderation_logs table filtered by
 * shopping_mall_review_id, projecting all fields including previous_status,
 * new_status, action_reason, created_at, and admin details. No pagination
 * parameters are supported in the request body as this is a complete audit
 * history of a single review.
 *
 * Related operations: PATCH /reviews/{reviewId} to change review status (which
 * creates a new moderation log entry), GET /reviews/{reviewId} to view current
 * review status.
 *
 * @param props.connection
 * @param props.reviewId Unique identifier of the review whose moderation log is
 *   being requested. Must be a valid UUID format.
 * @path /shoppingMall/customer/reviews/:reviewId/moderation-logs
 * @accessor api.functional.shoppingMall.customer.reviews.moderation_logs.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
      );
}
export namespace index {
  export type Props = {
    /**
     * Unique identifier of the review whose moderation log is being
     * requested. Must be a valid UUID format.
     */
    reviewId: string;
  };
  export type Response = IPageIShoppingMallReviewModerationLog;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/customer/reviews/:reviewId/moderation-logs",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/customer/reviews/${encodeURIComponent(props.reviewId ?? "null")}/moderation-logs`;
  export const random = (): IPageIShoppingMallReviewModerationLog =>
    typia.random<IPageIShoppingMallReviewModerationLog>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("reviewId")(() => typia.assert(props.reviewId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
