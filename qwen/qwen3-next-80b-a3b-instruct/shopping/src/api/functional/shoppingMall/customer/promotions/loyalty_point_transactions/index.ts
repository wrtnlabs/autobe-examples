/**
 * Retrieve detailed information about a specific loyalty point transaction by
 * its unique transaction ID.
 *
 * This operation fetches a single loyalty point transaction record from the
 * shopping_mall_loyalty_point_transactions table. The transaction ID must be a
 * valid UUID that corresponds to an existing record in the database. Only
 * completed transactions (status = 'completed') are returned. Pending and
 * reversed transactions are not accessible through this endpoint.
 *
 * The response includes comprehensive details about the transaction: the exact
 * point change amount, transaction type classification, status, description,
 * timestamps, and related entities (customer, order, or promotion that
 * triggered the transaction). This endpoint provides the complete audit trail
 * for individual transactions.
 *
 * Security: Access is strictly controlled based on the authenticated user's
 * permissions. Customers can only view their own transactions. Admin users can
 * view any transaction. The system validates ownership by comparing the
 * authenticated user ID with the transaction's customer_id field. Unauthorized
 * access attempts return a 403 Forbidden response.
 *
 * This operation is critical for customer service inquiries, dispute
 * resolution, and detailed transaction verification.
 *
 * @param props.connection
 * @param props.transactionId Unique identifier of the loyalty point
 *   transaction. This is a UUID that references
 *   shopping_mall_loyalty_point_transactions.id.
 * @path /shoppingMall/customer/promotions/loyalty-point-transactions/:transactionId
 * @accessor api.functional.shoppingMall.customer.promotions.loyalty_point_transactions.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique identifier of the loyalty point transaction. This is a UUID
     * that references shopping_mall_loyalty_point_transactions.id.
     */
    transactionId: string & tags.Format<"uuid">;
  };
  export type Response = IShoppingMallLoyaltyPointTransaction;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/customer/promotions/loyalty-point-transactions/:transactionId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/customer/promotions/loyalty-point-transactions/${encodeURIComponent(props.transactionId ?? "null")}`;
  export const random = (): IShoppingMallLoyaltyPointTransaction =>
    typia.random<IShoppingMallLoyaltyPointTransaction>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("transactionId")(() => typia.assert(props.transactionId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
