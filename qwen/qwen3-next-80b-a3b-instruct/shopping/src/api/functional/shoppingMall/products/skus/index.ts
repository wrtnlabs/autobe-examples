import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallVariantSkus } from "../../../../structures/IShoppingMallVariantSkus";

/**
 * Retrieve detailed information about a specific product variant by its unique
 * SKU identifier. This operation queries the shopping_mall_variant_skus table
 * and returns comprehensive product variant data including pricing, inventory
 * status, and associated attribute values. The SKU serves as the primary
 * identifier for product variants in the system, allowing precise access to
 * specific product configurations.
 *
 * The operation validates the SKU format and checks for existence in the
 * system. If the SKU is valid and corresponds to an active product variant, the
 * detailed variant information is returned. This includes the base product
 * information, specific variant attributes (such as size, color, etc.), current
 * inventory levels, and pricing details. The system ensures that only active
 * and available variants are returned, excluding those that are discontinued or
 * have zero inventory.
 *
 * Security considerations include ensuring that SKU access does not leak
 * information about products the requesting user might not be authorized to
 * view. The system enforces product visibility rules based on category
 * permissions and seller relationships. Unauthorized attempts to access SKUs
 * will return a 404 Not Found response to prevent enumeration attacks on the
 * product catalog.
 *
 * @param props.connection
 * @param props.skuId Unique product variant identifier (SKU). This is a
 *   system-generated alphanumeric code that uniquely identifies a specific
 *   product configuration. The SKU follows the format PRDSKU-XXXXXXXX, where
 *   XXXXXXXX is a unique alphanumeric identifier. This fixed-length format
 *   ensures reliable pattern matching and indexing in the database.
 * @path /shoppingMall/products/skus/:skuId
 * @accessor api.functional.shoppingMall.products.skus.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique product variant identifier (SKU). This is a system-generated
     * alphanumeric code that uniquely identifies a specific product
     * configuration. The SKU follows the format PRDSKU-XXXXXXXX, where
     * XXXXXXXX is a unique alphanumeric identifier. This fixed-length
     * format ensures reliable pattern matching and indexing in the
     * database.
     */
    skuId: string;
  };
  export type Response = IShoppingMallVariantSkus;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/products/skus/:skuId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/products/skus/${encodeURIComponent(props.skuId ?? "null")}`;
  export const random = (): IShoppingMallVariantSkus =>
    typia.random<IShoppingMallVariantSkus>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("skuId")(() => typia.assert(props.skuId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
