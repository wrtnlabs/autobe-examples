import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallProductVariant } from "../../../../structures/IShoppingMallProductVariant";
export * as attributes from "./attributes/index";

/**
 * Retrieve a specific product variant from the system using its unique product
 * and variant identifiers. This operation provides detailed information about
 * the selected variant, including its price, availability status, and
 * associated attribute values such as size, color, and material.
 *
 * The response includes the variant's pricing information from the
 * shopping_mall_product_variant_pricing table, current inventory status from
 * the shopping_mall_product_variant_inventory table, and all assigned
 * attributes from the shopping_mall_product_variant_attributes table that
 * distinguish this variant from others in the product line.
 *
 * Related operations: GET /products/{productId} (product overview), PATCH
 * /products/{productId}/variants (list all variants).
 *
 * @param props.connection
 * @param props.productId Unique business identifier code of the target product
 *   (global scope)
 * @param props.variantId Unique business identifier code of the target product
 *   variant (scoped to product)
 * @path /shoppingMall/products/:productId/variants/:variantId
 * @accessor api.functional.shoppingMall.products.variants.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique business identifier code of the target product (global scope) */
    productId: string;

    /**
     * Unique business identifier code of the target product variant (scoped
     * to product)
     */
    variantId: string;
  };
  export type Response = IShoppingMallProductVariant;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/products/:productId/variants/:variantId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/products/${encodeURIComponent(props.productId ?? "null")}/variants/${encodeURIComponent(props.variantId ?? "null")}`;
  export const random = (): IShoppingMallProductVariant =>
    typia.random<IShoppingMallProductVariant>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("productId")(() => typia.assert(props.productId));
      assert.param("variantId")(() => typia.assert(props.variantId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
