import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallProductImage } from "../../../../structures/IShoppingMallProductImage";

/**
 * Retrieve a specific product image by its unique identifier.
 *
 * This operation fetches the metadata and public URL of a single product image
 * associated with a product. The image is identified by both the product ID and
 * the image ID, ensuring that images are accessed only in the context of their
 * parent product.
 *
 * The image metadata includes the image URL, alternative text, sort order, and
 * whether it is designated as the primary image for the product. This operation
 * returns the complete image record, including timestamps for creation and
 * update. Images are soft-deleted and only active (deleted_at null) records are
 * returned.
 *
 * This operation is used in product detail pages to display individual images.
 * The returned image URL is used directly in frontend image elements. The
 * alternative text is used for accessibility and SEO purposes. The sort_order
 * ensures consistent display order, and is_primary indicates the main product
 * image.
 *
 * The operation requires no authentication since product images are
 * public-facing content. This is consistent with the platform's design that
 * product visuals are intended for public discovery and accessibility.
 *
 * Security: Access is restricted by URL namespace - an image must belong to a
 * valid product. Attempting to access an image with a non-existent product ID
 * returns 404. Attempting to access an image with a valid image ID that does
 * not belong to the specified product returns 404.
 *
 * Related operations: GET /products/{productId}/images (lists all images for a
 * product).
 *
 * @param props.connection
 * @param props.productId Unique identifier of the parent product. Must be a
 *   valid product ID from the shopping_mall_products table.
 * @param props.imageId Unique identifier of the specific product image. Must be
 *   a valid image ID from the shopping_mall_product_images table.
 * @path /shoppingMall/products/:productId/images/:imageId
 * @accessor api.functional.shoppingMall.products.images.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique identifier of the parent product. Must be a valid product ID
     * from the shopping_mall_products table.
     */
    productId: string & tags.Format<"uuid">;

    /**
     * Unique identifier of the specific product image. Must be a valid
     * image ID from the shopping_mall_product_images table.
     */
    imageId: string & tags.Format<"uuid">;
  };
  export type Response = IShoppingMallProductImage;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/products/:productId/images/:imageId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/products/${encodeURIComponent(props.productId ?? "null")}/images/${encodeURIComponent(props.imageId ?? "null")}`;
  export const random = (): IShoppingMallProductImage =>
    typia.random<IShoppingMallProductImage>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("productId")(() => typia.assert(props.productId));
      assert.param("imageId")(() => typia.assert(props.imageId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
