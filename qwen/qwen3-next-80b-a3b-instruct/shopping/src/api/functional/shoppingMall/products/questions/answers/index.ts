import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallProductAnswer } from "../../../../../structures/IShoppingMallProductAnswer";

/**
 * Retrieve a specific answer to a product-related question.
 *
 * This operation retrieves a single answer from the
 * shopping_mall_product_answers table, identified by its unique answerId. The
 * answer is linked to a specific product question (identified by questionId)
 * which in turn is associated with a specific product (identified by
 * productId). This endpoint serves customers who want to view detailed
 * responses to questions they or other users have asked about a product.
 *
 * The operation leverages the hierarchical relationship structure between
 * products, questions, and answers in the database schema, ensuring the answer
 * being retrieved is fully contextualized within its product and question
 * hierarchy.
 *
 * Security: This endpoint is publicly accessible since product questions and
 * answers are customer-facing content. No authentication is required to view
 * public product Q&A content. However, only publicly visible answers
 * (non-flagged, non-hidden) will be returned.
 *
 * Relationship with other operations:
 *
 * - GET /products/{productId}/questions should be used to retrieve the list of
 *   questions for a product
 * - GET /products/{productId}/questions/{questionId} should be used to retrieve
 *   the specific question details
 * - POST /products/{productId}/questions should be used to create a new question
 * - POST /products/{productId}/questions/{questionId}/answers should be used to
 *   submit a new answer to a question
 *
 * Implementation Note: The system validates that the answerId exists and that
 * it is properly nested under the questionId and productId in the database
 * hierarchy. If the answer has been flagged for moderation and marked as
 * non-visible, it will not be returned even if the answerId exists in the
 * database.
 *
 * @param props.connection
 * @param props.productId Unique identifier of the product for which the
 *   question and answer were submitted. This links the answer to its parent
 *   product entity.
 * @param props.questionId Unique identifier of the specific question to which
 *   this answer belongs. This links the answer to its parent question entity.
 * @param props.answerId Unique identifier of the specific answer being
 *   retrieved. This is the primary identifier for this operation and must
 *   correspond to a valid answer in the shopping_mall_product_answers table.
 * @path /shoppingMall/products/:productId/questions/:questionId/answers/:answerId
 * @accessor api.functional.shoppingMall.products.questions.answers.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique identifier of the product for which the question and answer
     * were submitted. This links the answer to its parent product entity.
     */
    productId: string;

    /**
     * Unique identifier of the specific question to which this answer
     * belongs. This links the answer to its parent question entity.
     */
    questionId: string;

    /**
     * Unique identifier of the specific answer being retrieved. This is the
     * primary identifier for this operation and must correspond to a valid
     * answer in the shopping_mall_product_answers table.
     */
    answerId: string;
  };
  export type Response = IShoppingMallProductAnswer;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/products/:productId/questions/:questionId/answers/:answerId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/products/${encodeURIComponent(props.productId ?? "null")}/questions/${encodeURIComponent(props.questionId ?? "null")}/answers/${encodeURIComponent(props.answerId ?? "null")}`;
  export const random = (): IShoppingMallProductAnswer =>
    typia.random<IShoppingMallProductAnswer>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("productId")(() => typia.assert(props.productId));
      assert.param("questionId")(() => typia.assert(props.questionId));
      assert.param("answerId")(() => typia.assert(props.answerId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
