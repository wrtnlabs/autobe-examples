import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallProductSnapshot } from "../../../../structures/IShoppingMallProductSnapshot";

/**
 * Retrieve a detailed historical snapshot of a product at a specific point in
 * time. This operation accesses the shopping_mall_product_snapshots table to
 * return a complete snapshot of product details, including pricing, inventory,
 * attributes, and metadata as they existed at the time the snapshot was
 * created.
 *
 * The snapshot provides an immutable historical record that captures the exact
 * state of the product when it was saved, which is critical for compliance,
 * audit trails, and customer transparency in cases of price changes, inventory
 * adjustments, or product specification updates. The operation ensures data
 * integrity by returning data exactly as stored in the snapshot table, without
 * modifying or interpolating any values from the current product state.
 *
 * Examples of use cases include: displaying to customers the product details at
 * time of purchase, generating compliance reports showing historical product
 * configurations, and supporting dispute resolution with historical product
 * specifications. The snapshot includes all product information available at
 * creation time, such as the base product name, vendor, category, pricing, and
 * all attribute values.
 *
 * This operation does not return the current product information but instead
 * returns the frozen state from when the snapshot was created. The returned
 * data is completely independent of any subsequent changes to the product model
 * or product_variants. The snapshot must be accessed via its unique snapshotId,
 * which is the primary identifier for the historical record.
 *
 * This operation exclusively reads from the shopping_mall_product_snapshots
 * table and requires no write access. No operations modify snapshot data after
 * creation - snapshots are immutable records. related operations: GET
 * /products/{productId} (retrieves current product state), PATCH /products
 * (updates current product state).
 *
 * @param props.connection
 * @param props.productId Unique identifier of the product for which a
 *   historical snapshot is requested (global scope)
 * @param props.snapshotId Unique identifier of the historical product snapshot
 *   (global scope)
 * @path /shoppingMall/products/:productId/snapshots/:snapshotId
 * @accessor api.functional.shoppingMall.products.snapshots.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique identifier of the product for which a historical snapshot is
     * requested (global scope)
     */
    productId: string;

    /** Unique identifier of the historical product snapshot (global scope) */
    snapshotId: string & tags.Format<"uuid">;
  };
  export type Response = IShoppingMallProductSnapshot;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/products/:productId/snapshots/:snapshotId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/products/${encodeURIComponent(props.productId ?? "null")}/snapshots/${encodeURIComponent(props.snapshotId ?? "null")}`;
  export const random = (): IShoppingMallProductSnapshot =>
    typia.random<IShoppingMallProductSnapshot>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("productId")(() => typia.assert(props.productId));
      assert.param("snapshotId")(() => typia.assert(props.snapshotId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
