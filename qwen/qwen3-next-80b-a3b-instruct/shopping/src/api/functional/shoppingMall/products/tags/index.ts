import { IPageIShoppingMallProductTag } from "../../../../structures/IPageIShoppingMallProductTag";
import { IShoppingMallProductTag } from "../../../../structures/IShoppingMallProductTag";

/**
 * Retrieve all tags associated with a specific product in the shoppingMall
 * catalog. This operation operates on the shopping_mall_product_tags_products
 * junction table that establishes the many-to-many relationship between
 * products and tags. The endpoint returns a comprehensive list of all tags
 * applied to the specified product, including tag name, description, and
 * display order.
 *
 * This operation functions as a search/list endpoint with filtering
 * capabilities, sorted by the display_order field to ensure consistent UI
 * presentation. Each tag returned is an individual record from the
 * shopping_mall_product_tags table, linked through the
 * shopping_mall_product_tags_products junction table.
 *
 * Security: This is a public read operation. Any user, authenticated or not,
 * can retrieve product tags. The system does not restrict tag visibility based
 * on user roles or permissions since tags are public categorization metadata.
 *
 * Implementation note: This operation performs a JOIN between
 * shopping_mall_products, shopping_mall_product_tags_products, and
 * shopping_mall_product_tags tables to return tag data. It selects ONLY the tag
 * properties (name, description, slug, display_order) from the
 * shopping_mall_product_tags entity, excluding product-related data to maintain
 * clean separation of concerns. The results are ordered by display_order to
 * ensure consistent presentation in UI components that rely on tag ordering for
 * navigation or filtering.
 *
 * @param props.connection
 * @param props.productId Unique identifier of the target product. This may be a
 *   UUID in the database or a product code if one is defined in the schema. In
 *   this system, the product identifier is a UUID.
 * @path /shoppingMall/products/:productId/tags
 * @accessor api.functional.shoppingMall.products.tags.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
      );
}
export namespace index {
  export type Props = {
    /**
     * Unique identifier of the target product. This may be a UUID in the
     * database or a product code if one is defined in the schema. In this
     * system, the product identifier is a UUID.
     */
    productId: string & tags.Format<"uuid">;
  };
  export type Response = IPageIShoppingMallProductTag;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/products/:productId/tags",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/products/${encodeURIComponent(props.productId ?? "null")}/tags`;
  export const random = (): IPageIShoppingMallProductTag =>
    typia.random<IPageIShoppingMallProductTag>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("productId")(() => typia.assert(props.productId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

/**
 * Retrieve a specific tag associated with a product in the shoppingMall
 * catalog. This operation accesses the shopping_mall_product_tags_products
 * junction table to verify the relationship between a product and a specific
 * tag, then returns the complete tag details from the
 * shopping_mall_product_tags table.
 *
 * This is a detail retrieval operation (GET) that returns a single tag object
 * when the product-tag relationship exists. If the specified tag is not
 * associated with the product or does not exist, the system returns a 404 Not
 * Found error.
 *
 * Security: This is a public read operation. Any user, authenticated or not,
 * can retrieve specific product-tag associations. Tags are public
 * categorization metadata and are not subject to access controls based on actor
 * roles.
 *
 * Implementation note: This operation performs a JOIN between
 * shopping_mall_products, shopping_mall_product_tags_products, and
 * shopping_mall_product_tags tables to verify the existence of the relationship
 * and retrieve the tag's complete properties. Unlike the index operation, this
 * returns a single tag object with all its fields (name, slug, description,
 * display_order) instead of an array. The system does not return product
 * information in this response; it only returns tag information as the response
 * body type is ISshoppingMallProductTag, which represents the tag entity
 * itself.
 *
 * @param props.connection
 * @param props.productId Unique identifier of the target product. This may be a
 *   UUID in the database or a product code if one is defined in the schema. In
 *   this system, the product identifier is a UUID.
 * @param props.tagId Unique identifier of the target tag. This is the UUID of
 *   the specific tag in the shopping_mall_product_tags table. The system does
 *   not use human-readable codes for tags as there is no unique code field
 *   defined in the schema.
 * @path /shoppingMall/products/:productId/tags/:tagId
 * @accessor api.functional.shoppingMall.products.tags.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
