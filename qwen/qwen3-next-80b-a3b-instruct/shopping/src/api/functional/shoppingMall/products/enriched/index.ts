import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallProductEnriched } from "../../../../structures/IShoppingMallProductEnriched";

/**
 * Retrieve a denormalized product with complete attribute, variant, pricing,
 * inventory, and image data in a single optimized response.
 *
 * This operation provides a comprehensive product overview by combining data
 * from multiple related tables including product details, variants, pricing,
 * inventory status, images, and attribute definitions. Unlike standard product
 * retrieval which only returns base product information, this endpoint delivers
 * a fully enriched product object optimized for client-side product display and
 * comparison.
 *
 * The implementation joins the shopping_mall_products table with its related
 * entities: shopping_mall_product_variants for variant configurations,
 * shopping_mall_product_variant_pricing for variant-specific pricing,
 * shopping_mall_product_variant_inventory for real-time stock levels,
 * shopping_mall_product_images for product media, and
 * shopping_mall_product_attributes with shopping_mall_product_attribute_values
 * to reconstruct configurable product options. This denormalized view
 * eliminates the need for multiple round-trips to fetch related data.
 *
 * Security and performance considerations include caching at the CDN level for
 * frequently accessed products and rate limiting to prevent abuse of this
 * resource-intensive operation. The response structure is optimized for
 * front-end rendering with all necessary display data included, and no
 * additional API calls are required to render the full product page. The
 * operation reads from the database without writing, making it safe for
 * high-volume read operations. Related operations: GET /products/{productId}
 * (basic product info), GET /products (search/index).
 *
 * @param props.connection
 * @param props.productId Unique identifier of the target product, using the
 *   product's code field (global scope) which uniquely identifies each product
 *   across the entire catalog
 * @path /shoppingMall/products/:productId/enriched
 * @accessor api.functional.shoppingMall.products.enriched.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique identifier of the target product, using the product's code
     * field (global scope) which uniquely identifies each product across
     * the entire catalog
     */
    productId: string;
  };
  export type Response = IShoppingMallProductEnriched;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/products/:productId/enriched",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/products/${encodeURIComponent(props.productId ?? "null")}/enriched`;
  export const random = (): IShoppingMallProductEnriched =>
    typia.random<IShoppingMallProductEnriched>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("productId")(() => typia.assert(props.productId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
