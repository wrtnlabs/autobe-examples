/**
 * Update an existing inventory reservation by its unique identifier. This
 * operation allows modification of the reservation quantity or expiration time
 * for pending orders. The reservation must still be active (expires_at in the
 * future) for updates to be permitted. The system will validate that the
 * updated quantity does not exceed available inventory for the referenced
 * inventory unit, and that the new expiration time falls within allowable
 * limits (minimum 5 minutes, maximum 30 minutes from now).
 *
 * This operation works with the shopping_mall_inventory_reservations model in
 * the Prisma schema, which tracks temporary inventory locks for orders in the
 * checkout process. When a reservation is updated, the system recalculates the
 * available inventory for the associated inventory_unit_id and may trigger
 * inventory alerts if thresholds are approached.
 *
 * Security: Only authenticated users can update reservations. Customers can
 * only update reservations they created (verified by ownership of the
 * order_item_id). Administrative users can update any reservation regardless of
 * ownership.
 *
 * Related operations: DELETE /inventory/reservations/{reservationId} (cancels
 * reservation), GET /inventory/reservations/{reservationId} (retrieves
 * reservation details).
 *
 * @param props.connection
 * @param props.reservationId Unique identifier of the inventory reservation to
 *   update. This corresponds to the id field in the
 *   shopping_mall_inventory_reservations table.
 * @param props.body Updated properties for the inventory reservation.
 * @path /shoppingMall/inventory/reservations/:reservationId
 * @accessor api.functional.shoppingMall.inventory.reservations.update
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function update(
  connection: IConnection,
  props: update.Props,
): Promise<update.Response> {
  return true === connection.simulate
    ? update.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...update.METADATA,
          path: update.path(props),
          status: null,
        },
        props.body,
      );
}
