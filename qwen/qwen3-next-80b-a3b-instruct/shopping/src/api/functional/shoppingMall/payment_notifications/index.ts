import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallPaymentNotification } from "../../../structures/IShoppingMallPaymentNotification";

/**
 * Receive and process payment notification events from external payment
 * gateways.
 *
 * This operation accepts webhook notifications from payment providers such as
 * Stripe, PayPal, and other financial gateways, delivering real-time payment
 * status updates to the system. The request body contains encrypted payment
 * event data including transaction ID, status, amount, currency, and payment
 * method details, which the system validates against its internal payment
 * records.
 *
 * Security: Only requests from trusted webhooks with valid signatures from
 * registered payment providers are accepted. The system verifies the webhook
 * signature using registered provider secrets and cross-references the
 * payment_id with the shopping_mall_payments table. Invalid signatures or
 * mismatched payment IDs result in 401 Unauthorized responses.
 *
 * Processing: Upon successful verification, the system updates the
 * corresponding payment record in the payments table, logs the event in the
 * payment_audit_logs table, and triggers downstream workflows such as order
 * fulfillment, email notifications to customers, and seller payout processing.
 * The operation is idempotent: repeated notifications with the same payment_id
 * are accepted but have no further effect on the payment status.
 *
 * This operation is essential for the payment processing workflow, as it closes
 * the loop between external payment providers and the internal payment system.
 * Related operations: POST /payments (initiates payment), GET
 * /payments/{paymentId} (retrieves payment status).
 *
 * @param props.connection
 * @param props.body JSON payload containing payment gateway notification
 *   details including event information and payment identifiers.
 * @path /shoppingMall/payment-notifications
 * @accessor api.functional.shoppingMall.payment_notifications.receive
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function receive(
  connection: IConnection,
  props: receive.Props,
): Promise<receive.Response> {
  return true === connection.simulate
    ? receive.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...receive.METADATA,
          path: receive.path(),
          status: null,
        },
        props.body,
      );
}
export namespace receive {
  export type Props = {
    /**
     * JSON payload containing payment gateway notification details
     * including event information and payment identifiers.
     */
    body: IShoppingMallPaymentNotification.IRequest;
  };
  export type Body = IShoppingMallPaymentNotification.IRequest;
  export type Response = IShoppingMallPaymentNotification.IResponse;

  export const METADATA = {
    method: "POST",
    path: "/shoppingMall/payment-notifications",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/shoppingMall/payment-notifications";
  export const random = (): IShoppingMallPaymentNotification.IResponse =>
    typia.random<IShoppingMallPaymentNotification.IResponse>();
  export const simulate = (
    connection: IConnection,
    props: receive.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: receive.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
