/**
 * Retrieve a filtered and paginated list of shopping mall sections from the
 * system. This operation operates on the shopping_mall_sections table from the
 * database schema and provides advanced search capabilities for finding
 * sections based on multiple criteria including title partial matches,
 * description keywords, display order ranges, and active status flags.
 *
 * The operation supports comprehensive pagination with configurable page sizes
 * and sorting options. Sections can be sorted by display order
 * (ascending/descending), creation date, last update, or title in alphabetical
 * order.
 *
 * Security considerations include rate limiting for search operations and
 * appropriate filtering of sensitive section information based on the
 * requesting user's authorization level. All sections are publicly accessible
 * as they represent structural elements of the shopping mall interface.
 *
 * This operation integrates with the shopping_mall_sections table as defined in
 * the database schema, incorporating all available section fields and
 * relationships. The response includes section summary information optimized
 * for list displays, with options to include additional details based on
 * authorization level.
 *
 * @param props.connection
 * @param props.body Search criteria and pagination parameters for section
 *   filtering
 * @path /shoppingMall/sections
 * @accessor api.functional.shoppingMall.sections.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /** Search criteria and pagination parameters for section filtering */
    body: IShoppingMallSection.IRequest;
  };
  export type Body = IShoppingMallSection.IRequest;
  export type Response = IPageIShoppingMallSection.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/sections",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/shoppingMall/sections";
  export const random = (): IPageIShoppingMallSection.ISummary =>
    typia.random<IPageIShoppingMallSection.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

