/**
 * Trigger alert notifications for wishlist items based on price reductions or
 * stock availability changes.
 *
 * This operation identifies wishlist items belonging to the authenticated user
 * and checks their current pricing and inventory status. Notifications are sent
 * when significant changes occur, such as price drops or items transitioning
 * from out-of-stock to available status.
 *
 * Security: Only authenticated users can trigger this operation. The system
 * verifies the JWT authentication token to identify the user and retrieve their
 * associated wishlist items.
 *
 * Rate limiting applies to prevent spam notifications, with a maximum of 3
 * alerts per item per 24-hour period.
 *
 * Related operations: GET /wishlists (retrieve user wishlists), PATCH
 * /wishlists (update wishlist items), DELETE /wishlists/{wishlistId} (erase
 * wishlist).
 *
 * @param props.connection
 * @path /shoppingMall/wishlists/alerts
 * @accessor api.functional.shoppingMall.wishlists.alerts.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function create(
  connection: IConnection,
): Promise<create.Response> {
  return true === connection.simulate
    ? create.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...create.METADATA,
          path: create.path(),
          status: null,
        },
      );
}
export namespace create {
  export type Response = IShoppingMallWishlistAlert.IConfirm;

  export const METADATA = {
    method: "POST",
    path: "/shoppingMall/wishlists/alerts",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/shoppingMall/wishlists/alerts";
  export const random = (): IShoppingMallWishlistAlert.IConfirm =>
    typia.random<IShoppingMallWishlistAlert.IConfirm>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}
