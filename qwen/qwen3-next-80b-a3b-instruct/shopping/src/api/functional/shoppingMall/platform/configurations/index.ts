/**
 * Retrieve a specific platform configuration value by its unique key from the
 * shoppingMall platform configurations system. This operation queries the
 * shopping_mall_platform_configurations table in the database and returns the
 * configuration's value, type, description, and metadata. The configuration key
 * serves as the primary identifier and must be exactly matched to retrieve the
 * configuration. Each configuration entry contains a unique, case-sensitive key
 * string, a value of any type stored as JSON, a description field explaining
 * its purpose, and metadata including creation and modification timestamps.
 *
 * Platform configurations are used to manage global and dynamic system settings
 * without requiring code deployments, allowing administrators to modify
 * behavior such as feature flags, payment processing limits, shipping
 * thresholds, or UI display rules. This endpoint enables administrators and
 * services to fetch configuration values at runtime where the key is known.
 *
 * The operation returns only the first matching record for the specified
 * configKey. If the key does not exist in the database, a 404 Not Found
 * response will be returned. Configuration values are not cached at the
 * database level but may be cached at the service level for performance. The
 * configuration value is returned in its original JSON structure to maintain
 * type fidelity, including nested objects and arrays.
 *
 * This operation does not require authentication for public configurations, but
 * private or sensitive configuration values (such as API secrets or internal
 * service credentials) require admin authorization to prevent exposure. The
 * system implements a role-based access control system where each configuration
 * entry has an associated visibility level. Public configurations are
 * accessible by any client, while protected configurations require admin role
 * verification.
 *
 * The platform uses these configurations for runtime control of features such
 * as:
 *
 * - Enabling/disabling marketing promotions
 * - Adjusting rate limits for API endpoints
 * - Configuring tax calculation rules by region
 * - Setting default shipping thresholds
 * - Controlling product availability flags
 * - Managing maintenance mode status
 *
 * This operation should be called only when dynamic configuration values need
 * to be retrieved at runtime, not for static application settings which should
 * be managed through environment variables and deployed configurations.
 *
 * @param props.connection
 * @param props.configKey Unique case-sensitive key identifier of the platform
 *   configuration to retrieve. Must exactly match the config_key field in the
 *   shopping_mall_platform_configurations table. Used as a primary lookup key.
 *
 *                  Examples:
 *            - "feature_flag.new_checkout_ui"
 *            - "shipping.max_weight_limit"
 *            - "payment.currencies.enabled"
 *            - "system.maintenance_mode"
 *
 *            The key string may contain alphanumeric characters, dots, underscores, and hyphens. No spaces or special characters are allowed. Keys are not case-insensitive, so 'FeatureFlag' and 'featureflag' are treated as different keys.
 * @path /shoppingMall/platform/configurations/:configKey
 * @accessor api.functional.shoppingMall.platform.configurations.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique case-sensitive key identifier of the platform configuration to
     * retrieve. Must exactly match the config_key field in the
     * shopping_mall_platform_configurations table. Used as a primary lookup
     * key.
     *
     * Examples:
     *
     * - "feature_flag.new_checkout_ui"
     * - "shipping.max_weight_limit"
     * - "payment.currencies.enabled"
     * - "system.maintenance_mode"
     *
     * The key string may contain alphanumeric characters, dots,
     * underscores, and hyphens. No spaces or special characters are
     * allowed. Keys are not case-insensitive, so 'FeatureFlag' and
     * 'featureflag' are treated as different keys.
     */
    configKey: string;
  };
  export type Response = IShoppingMallPlatformConfiguration;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/platform/configurations/:configKey",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/platform/configurations/${encodeURIComponent(props.configKey ?? "null")}`;
  export const random = (): IShoppingMallPlatformConfiguration =>
    typia.random<IShoppingMallPlatformConfiguration>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("configKey")(() => typia.assert(props.configKey));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
