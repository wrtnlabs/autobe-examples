import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IArrayIShoppingMallReviewImage } from "../../../../../structures/IArrayIShoppingMallReviewImage";

/**
 * Retrieve all images associated with a specific product review. This operation
 * fetches the complete set of image attachments linked to a review entity in
 * the shopping mall platform, allowing customers and administrators to view
 * visual evidence submitted with product feedback.
 *
 * The operation operates on the shopping_mall_review_images table which
 * contains image metadata linked to review identifiers. Each image record
 * stores a unique identifier, reference to the parent review, image file URL or
 * path, upload timestamp, and optional display order.
 *
 * Security considerations include authentication requirements where only
 * authenticated users (customers or sellers) can access images for reviews they
 * created or own. Administrators have unrestricted access to all review images
 * for moderation and compliance purposes. The system does not expose file
 * system paths, only abstracted file URLs accessible through the platform's
 * content delivery network.
 *
 * This operation integrates with the shopping_mall_reviews table as defined in
 * the database schema, ensuring referential integrity. When a review is
 * deleted, all associated images are automatically removed as part of the
 * cascade delete relationship. Images are only accessible through this endpoint
 * and not via direct file system access.
 *
 * Related operations: GET /reviews/{reviewId} to retrieve review metadata
 * (including count of associated images), PATCH /reviews/{reviewId}/images to
 * upload new images, DELETE /reviews/{reviewId}/images/{imageId} to remove
 * specific review images.
 *
 * @param props.connection
 * @param props.reviewId Unique identifier of the target review whose images are
 *   being requested. This identifier corresponds to the primary key of the
 *   shopping_mall_reviews table.
 * @path /shoppingMall/seller/reviews/:reviewId/images
 * @accessor api.functional.shoppingMall.seller.reviews.images.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
      );
}
export namespace index {
  export type Props = {
    /**
     * Unique identifier of the target review whose images are being
     * requested. This identifier corresponds to the primary key of the
     * shopping_mall_reviews table.
     */
    reviewId: string & tags.Format<"uuid">;
  };
  export type Response = IArrayIShoppingMallReviewImage;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/seller/reviews/:reviewId/images",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/seller/reviews/${encodeURIComponent(props.reviewId ?? "null")}/images`;
  export const random = (): IArrayIShoppingMallReviewImage =>
    typia.random<IArrayIShoppingMallReviewImage>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("reviewId")(() => typia.assert(props.reviewId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
