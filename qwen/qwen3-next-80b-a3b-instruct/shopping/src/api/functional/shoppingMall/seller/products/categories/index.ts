/**
 * Retrieve a specific category assignment for a product.
 *
 * This operation fetches the relationship between a specific product and its
 * assigned category. It verifies that the product is indeed linked to the
 * requested category in the shopping_mall_product_categories junction table.
 * The product's status and category's active status are checked to ensure both
 * entities are in valid states.
 *
 * This operation is primarily used in product management interfaces and
 * category exploration features where users need to confirm the hierarchical
 * relationship between products and categories.
 *
 * The data returned corresponds to the shopping_mall_product_categories table,
 * with additional context from shopping_mall_products and
 * shopping_mall_categories to validate that both entities are active and
 * properly configured.
 *
 * Related operations:
 *
 * - DELETE /products/{productId}/categories/{categoryId}: Removes this
 *   product-category association
 * - PATCH /products/{productId}/categories: Lists all categories assigned to a
 *   product
 * - GET /categories/{categoryId}/products: Lists all products assigned to a
 *   category
 *
 * @param props.connection
 * @param props.productId Unique identifier of the target product. This
 *   references the shopping_mall_products.id field. The product must exist and
 *   be in 'published' or 'draft' status to be accessible.
 * @param props.categoryId Unique identifier of the target product category.
 *   This references the shopping_mall_categories.id field. The category must
 *   exist and have is_active set to true to be accessible.
 * @path /shoppingMall/seller/products/:productId/categories/:categoryId
 * @accessor api.functional.shoppingMall.seller.products.categories.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
