import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallOrderItem } from "../../../../../structures/IShoppingMallOrderItem";
import { IPageIShoppingMallOrderItem } from "../../../../../structures/IPageIShoppingMallOrderItem";

/**
 * Retrieves all items within a specific order, providing comprehensive product
 * details and pricing information at time of purchase.
 *
 * This operation queries the shopping_mall_order_items table and returns a list
 * of all items associated with the specified order. The response includes each
 * item's quantity, unit price (as it was at purchase time), item total, and
 * product variant details, enabling full historical order auditing.
 *
 * The operation supports pagination and sorting of order items by product name,
 * quantity, or unit price. It does not support filtering by product category or
 * other criteria as order items are always retrieved in context of their parent
 * order.
 *
 * This endpoint serves customer service, accounting, and dispute resolution
 * workflows where complete item-level order history must be verified.
 *
 * Security: Read access is permitted to the order's customer, the associated
 * seller, and platform administrators.
 *
 * Related operations: GET /orders/{orderNumber} (retrieve order summary), PATCH
 * /orders/{orderNumber} (search orders).
 *
 * @param props.connection
 * @param props.orderNumber Unique order identifier in format ORD-YYYYMMDD-NNNNN
 *   (global scope).
 * @param props.body Search parameters for filtering and sorting order items.
 * @path /shoppingMall/seller/orders/:orderNumber/items
 * @accessor api.functional.shoppingMall.seller.orders.items.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /** Unique order identifier in format ORD-YYYYMMDD-NNNNN (global scope). */
    orderNumber: string;

    /** Search parameters for filtering and sorting order items. */
    body: IShoppingMallOrderItem.IRequest;
  };
  export type Body = IShoppingMallOrderItem.IRequest;
  export type Response = IPageIShoppingMallOrderItem.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/seller/orders/:orderNumber/items",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/shoppingMall/seller/orders/${encodeURIComponent(props.orderNumber ?? "null")}/items`;
  export const random = (): IPageIShoppingMallOrderItem.ISummary =>
    typia.random<IPageIShoppingMallOrderItem.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("orderNumber")(() => typia.assert(props.orderNumber));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
