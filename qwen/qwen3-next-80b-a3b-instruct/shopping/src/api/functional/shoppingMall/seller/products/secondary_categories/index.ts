/**
 * Associate a product with one or more secondary categories in the shopping
 * mall catalog system.
 *
 * This operation allows sellers or administrators to assign additional
 * secondary categories to a product. Secondary categories serve as supplemental
 * classification dimensions beyond the primary category, enabling more granular
 * product discoverability and filtering. Each product can be linked to multiple
 * secondary categories to increase visibility across different browsing
 * contexts.
 *
 * The operation validates that the specified productId exists in the
 * shopping_mall_products table and that all requested secondary category IDs
 * correspond to valid entries in the shopping_mall_product_secondary_categories
 * table. The relationship is stored in a junction table that maintains
 * referential integrity between products and their secondary categories.
 *
 * Security restrictions ensure only authenticated sellers (who own the product)
 * or administrators can perform this operation. The system prevents circular
 * references or duplicate assignments. Upon successful association, the
 * product's category hierarchy is updated in real-time, affecting search
 * indexing and category-based navigation throughout the platform.
 *
 * Implementation note: This operation does not modify the product's primary
 * category, nor does it delete existing secondary category relationships. To
 * remove a category association, a separate disassociation operation would be
 * required. This design maintains historical category relationships while
 * allowing dynamic enrichment for improved product discoverability.
 *
 * Related operations: GET /products/{productId}/secondary-categories (to view
 * current associations), DELETE
 * /products/{productId}/secondary-categories/{secondaryCategoryId} (to remove a
 * specific association).
 *
 * @param props.connection
 * @param props.productId Unique identifier of the target product in the
 *   shopping_mall_products table. This identifier must reference an existing
 *   product created by an authenticated seller.
 * @param props.body Request body containing the list of secondary category IDs
 *   to associate with the product.
 * @path /shoppingMall/seller/products/:productId/secondary-categories
 * @accessor api.functional.shoppingMall.seller.products.secondary_categories.associate
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function associate(
  connection: IConnection,
  props: associate.Props,
): Promise<associate.Response> {
  return true === connection.simulate
    ? associate.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...associate.METADATA,
          path: associate.path(props),
          status: null,
        },
        props.body,
      );
}
