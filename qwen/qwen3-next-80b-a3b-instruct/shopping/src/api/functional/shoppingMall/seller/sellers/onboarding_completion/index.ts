/**
 * Complete the seller onboarding process by marking the onboarding status as
 * finalized in the system. This operation permanently updates the seller's
 * onboarding completion status from pending to completed, unlocking full access
 * to all seller features including product listing, order management, and
 * payout configuration.
 *
 * The operation requires a valid sellerId path parameter that references an
 * existing seller who has completed all prerequisite verification steps
 * (business documentation submission, bank account linkage, and identity
 * confirmation). Upon success, the system automatically enables seller-specific
 * features, triggers onboarding welcome notifications, and updates the seller's
 * dashboard display.
 *
 * Security considerations include ensuring that only the authenticated seller
 * (matching the sellerId) or an admin with appropriate permissions can trigger
 * this operation. The operation is idempotent - multiple successful calls will
 * have no additional effect beyond the first successful completion.
 *
 * This operation directly modifies the
 * shopping_mall_seller_onboarding_completion table, setting the completion
 * status to true and recording the completion timestamp. No request body is
 * required as all validation occurs during the prerequisite stages of
 * onboarding.
 *
 * Related operations: GET /sellers/{sellerId}/onboarding-status (to check
 * current status), GET /sellers/{sellerId} (to verify seller details).
 *
 * @param props.connection
 * @param props.sellerId Unique identifier of the target seller account whose
 *   onboarding process is being completed.
 * @path /shoppingMall/seller/sellers/:sellerId/onboarding-completion
 * @accessor api.functional.shoppingMall.seller.sellers.onboarding_completion.update
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function update(
  connection: IConnection,
  props: update.Props,
): Promise<update.Response> {
  return true === connection.simulate
    ? update.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...update.METADATA,
          path: update.path(props),
          status: null,
        },
      );
}
