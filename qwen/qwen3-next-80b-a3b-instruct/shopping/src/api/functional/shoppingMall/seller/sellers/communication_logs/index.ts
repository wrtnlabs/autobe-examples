/**
 * Create a new communication log entry between a seller and the platform
 * regarding order fulfillment issues, policy violations, or account status
 * inquiries.
 *
 * This operation allows authorized sellers to create audit-ready communication
 * records with platform administrators. Each communication log captures a
 * message from the seller with context about the reason for communication,
 * including order reference, product issue, or policy inquiry. The system
 * automatically associates the communication with the authenticated seller and
 * timestamps the entry.
 *
 * Security: The seller is authenticated through JWT token validation and is
 * only permitted to create communication logs for their own seller account. The
 * operation validates that the referenced sellerId in the path matches the
 * authenticated seller's ID to prevent impersonation.
 *
 * This operation creates records in the shopping_mall_seller_communication_logs
 * table.
 *
 * Related operations: GET /shopping-mall/sellers/{sellerId}/communication-logs
 * to retrieve log history.
 *
 * @param props.connection
 * @param props.sellerId Unique identifier of the seller who is creating the
 *   communication log (must match authenticated seller)
 * @param props.body The content and context of the communication message from
 *   the seller
 * @path /shoppingMall/seller/sellers/:sellerId/communication-logs
 * @accessor api.functional.shoppingMall.seller.sellers.communication_logs.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function create(
  connection: IConnection,
  props: create.Props,
): Promise<create.Response> {
  return true === connection.simulate
    ? create.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...create.METADATA,
          path: create.path(props),
          status: null,
        },
        props.body,
      );
}
