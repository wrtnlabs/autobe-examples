/**
 * Update seller account information in the shoppingMall platform. This
 * operation modifies the shopping_mall_sellers table and allows registered
 * sellers to update their business profile details, including contact
 * information, business name, and supporting documentation.
 *
 * Security and authorization: Only authenticated sellers can update their own
 * account information. The seller ID in the path parameter must match the
 * seller ID associated with the authenticated JWT token. This prevents
 * unauthorized modification of other seller accounts.
 *
 * The operation validates that updated fields comply with platform
 * requirements. For example: business name must be between 2 and 100
 * characters, contact email must be in valid email format, and uploaded
 * documentation must reference existing files from the platform's document
 * storage system.
 *
 * This operation updates the seller's metadata without affecting their product
 * catalog, orders, or financial information, which are managed through separate
 * API endpoints. Changes to seller status (active/inactive) or permissions
 * require administrative intervention through separate endpoints.
 *
 * Relationships: This operation interacts with the shopping_mall_sellers table
 * exclusively. It does not modify related entities such as
 * shopping_mall_products or shopping_mall_orders, which are maintained
 * independently.
 *
 * Error scenarios: The operation returns 403 Forbidden if the authenticated
 * seller does not match the seller ID in the path, 404 Not Found if the seller
 * ID does not exist, and 422 Unprocessable Entity if validation rules for
 * updated fields are violated.
 *
 * @param props.connection
 * @param props.sellerId Unique identifier of the seller account to be updated.
 *   This must be a globally unique seller code assigned during onboarding, not
 *   a UUID ID.
 * @param props.body Seller account update data containing fields to be
 *   modified.
 * @path /shoppingMall/seller/sellers/:sellerId
 * @accessor api.functional.shoppingMall.seller.sellers.update
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function update(
  connection: IConnection,
  props: update.Props,
): Promise<update.Response> {
  return true === connection.simulate
    ? update.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...update.METADATA,
          path: update.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace update {
  export type Props = {
    /**
     * Unique identifier of the seller account to be updated. This must be a
     * globally unique seller code assigned during onboarding, not a UUID
     * ID.
     */
    sellerId: string;

    /** Seller account update data containing fields to be modified. */
    body: IShoppingMallSeller.IUpdate;
  };
  export type Body = IShoppingMallSeller.IUpdate;
  export type Response = IShoppingMallSeller;

  export const METADATA = {
    method: "PUT",
    path: "/shoppingMall/seller/sellers/:sellerId",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/shoppingMall/seller/sellers/${encodeURIComponent(props.sellerId ?? "null")}`;
  export const random = (): IShoppingMallSeller =>
    typia.random<IShoppingMallSeller>();
  export const simulate = (
    connection: IConnection,
    props: update.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: update.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("sellerId")(() => typia.assert(props.sellerId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

