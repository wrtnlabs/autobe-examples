import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallAdmin } from "../../../../../structures/IShoppingMallAdmin";

/**
 * Deactivates a specific administrator account to suspend access without
 * permanently removing the record. This operation requires admin-level
 * authorization. The system updates the 'is_active' field in the
 * shopping_mall_admin table from true to false based on the admin's ID
 * contained in the path. All active sessions for the target account are
 * immediately invalidated. This is the only authorized null-type operation
 * affecting account status.
 *
 * Implementation uses the 'id' field from the shopping_mall_admin table to
 * identify the account. Security considerations include requiring admin-level
 * authorization, audit logging, and preventing unauthorized deactivation. An ID
 * must be provided via the path.
 *
 * Related operations: GET /auth/admin/account/{id} (to inspect status) and POST
 * /auth/admin/account/reactivate/{id} (to reverse deactivation, if supported).
 *
 * @param props.connection
 * @param props.id Unique identifier of the administrator account to deactivate.
 *   Must appear in path.
 * @param props.body Optional reason for deactivation. Used for audit purposes.
 * @path /auth/admin/account/deactivate/:id
 * @accessor api.functional.auth.admin.account.deactivate.deactivateAccount
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function deactivateAccount(
  connection: IConnection,
  props: deactivateAccount.Props,
): Promise<deactivateAccount.Response> {
  return true === connection.simulate
    ? deactivateAccount.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...deactivateAccount.METADATA,
          path: deactivateAccount.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace deactivateAccount {
  export type Props = {
    /**
     * Unique identifier of the administrator account to deactivate. Must
     * appear in path.
     */
    id: string;

    /** Optional reason for deactivation. Used for audit purposes. */
    body: IShoppingMallAdmin.IDeactivateAccount;
  };
  export type Body = IShoppingMallAdmin.IDeactivateAccount;
  export type Response = IShoppingMallAdmin.IAccountStatusUpdate;

  export const METADATA = {
    method: "PATCH",
    path: "/auth/admin/account/deactivate/:id",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/auth/admin/account/deactivate/${encodeURIComponent(props.id ?? "null")}`;
  export const random = (): IShoppingMallAdmin.IAccountStatusUpdate =>
    typia.random<IShoppingMallAdmin.IAccountStatusUpdate>();
  export const simulate = (
    connection: IConnection,
    props: deactivateAccount.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: deactivateAccount.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("id")(() => typia.assert(props.id));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
