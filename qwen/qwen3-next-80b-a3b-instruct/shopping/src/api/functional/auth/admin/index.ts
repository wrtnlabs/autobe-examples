/**
 * Register a new admin account in the Shopping Mall system using email and
 * password_hash.
 *
 * This API endpoint enables the creation of new admin accounts for system
 * administrators within the Shopping Mall platform.
 *
 * The operation accepts a request body with the admin's email address and
 * hashed password, both of which are mandatory fields defined in the
 * shopping_mall_admins Prisma schema. The email must be unique across all
 * admins, which is enforced by the unique index on the email field. The
 * password_hash is stored securely using a cryptographically secure algorithm,
 * as required by security best practices.
 *
 * The admin account is created with an initial status of 'active', allowing
 * immediate login after registration. The created_at field is automatically
 * populated with the server timestamp (Asia/Seoul timezone), and updated_at is
 * initialized to the same value. The deleted_at field is set to null,
 * indicating the account is not soft-deleted.
 *
 * This operation is strictly for self-registration of administrators and should
 * not be exposed to end-users. Successive calls with the same email will fail
 * due to the unique constraint on the email field. The operation requires a
 * successful completion of the email verification process before the admin can
 * use the assigned credentials, though no email verification field exists in
 * the schema so this is handled externally.
 *
 * It is recommended to follow this operation with an immediate login call using
 * the same credentials to establish a session. This operation is independent of
 * customer or seller creation workflows and only deals with platform
 * administrative accounts.
 *
 * Security Note: This endpoint must be protected against brute force attacks,
 * as it allows account creation with chosen credentials.
 *
 * @param props.connection
 * @param props.body Request payload for creating a new admin account with email
 *   and password_hash fields.
 * @setHeader token.access Authorization
 *
 * @path /auth/admin/join
 * @accessor api.functional.auth.admin.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
