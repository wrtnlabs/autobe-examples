import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallCustomer } from "../../../structures/IShoppingMallCustomer";

/**
 * Extends the validity of the customer's access token by exchanging a valid
 * refresh token for new access and refresh tokens. This operation is used when
 * the current access token has expired but the refresh token is still valid.
 *
 * The refresh token must be present and valid in the customer_session record
 * associated with the customer's account. The system validates the refresh
 * token against the stored token in the customer_session table and checks that
 * the corresponding customer account has 'active' status. If the customer is
 * suspended or deleted, the refresh will be denied.
 *
 * This process updates the refresh_token field in the customer_session record
 * and resets the expiration timestamp for both the access and refresh tokens.
 * The operation does not change the customer's authentication status or verify
 * credentials again.
 *
 * This operation is essential for maintaining a seamless user experience
 * without requiring re-authentication for every API call. The access token
 * typically expires after 15 minutes while the refresh token remains valid for
 * up to 7 days.
 *
 * Related operations: POST /auth/customer/join, POST /auth/customer/login, and
 * GET /auth/customer/logout. Exchange is used after login or previous refresh
 * operation, and must be called before the access token expires to maintain
 * continuous session.
 *
 * @param props.connection
 * @param props.body Request body for token refresh using a valid refresh token.
 * @setHeader token.access Authorization
 *
 * @path /auth/customer/refresh
 * @accessor api.functional.auth.customer.refresh
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function refresh(
  connection: IConnection,
  props: refresh.Props,
): Promise<refresh.Response> {
  const output: refresh.Response =
    true === connection.simulate
      ? refresh.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...refresh.METADATA,
            path: refresh.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
export namespace refresh {
  export type Props = {
    /** Request body for token refresh using a valid refresh token. */
    body: IShoppingMallCustomer.IRequest;
  };
  export type Body = IShoppingMallCustomer.IRequest;
  export type Response = IShoppingMallCustomer.IAuthorized;

  export const METADATA = {
    method: "POST",
    path: "/auth/customer/refresh",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/customer/refresh";
  export const random = (): IShoppingMallCustomer.IAuthorized =>
    typia.random<IShoppingMallCustomer.IAuthorized>();
  export const simulate = (
    connection: IConnection,
    props: refresh.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: refresh.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
