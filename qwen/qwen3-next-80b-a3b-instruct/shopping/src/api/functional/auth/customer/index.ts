/**
 * Register a new customer account using email and password, with validation
 * against shopping_mall_customers schema fields.
 *
 * This endpoint allows registration of new customers on the shoppingMall
 * platform. The operation consumes the customer's email and password, stores
 * them securely in the shopping_mall_customers table using the email and
 * password_hash fields, and creates an initial authentication session in the
 * shopping_mall_customer_sessions table. The account status is set to 'active'
 * immediately upon registration, enabling immediate platform access.
 *
 * The email field must be unique and provided as part of the request, and the
 * password_hash field is populated using a secure cryptographic hash algorithm,
 * never storing plain-text passwords. The operation creates a new customer
 * record with default status 'active' and initial timestamps for created_at and
 * updated_at.
 *
 * After successful registration, the system generates a JWT access token and
 * refresh token, packaged in the response following
 * IShoppingMallCustomer.IAuthorized schema. The refresh token is stored
 * securely in the shopping_mall_customer_sessions table with an expiration time
 * and the originating IP address.
 *
 * This service is available unauthenticated, allowing public user registration,
 * but API consumers must ensure valid email format and password strength via
 * client-side validation. Security considerations include rate-limiting
 * registration attempts and validating email domain patterns to prevent abuse.
 *
 * Related operations include POST /auth/customer/login for subsequent
 * authentications and POST /auth/customer/refresh for token renewal.
 * Post-registration behavior expects the client to store the access token for
 * future API requests requiring authentication.
 *
 * @param props.connection
 * @param props.body Registration data for a new customer account.
 * @setHeader token.access Authorization
 *
 * @path /auth/customer/join
 * @accessor api.functional.auth.customer.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
