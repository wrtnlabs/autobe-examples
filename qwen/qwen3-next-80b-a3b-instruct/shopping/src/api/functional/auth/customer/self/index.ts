import { IConnection } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";

import { IShoppingMallCustomer } from "../../../../structures/IShoppingMallCustomer";

/**
 * Handles all non-authentication operations for the customer role including
 * password reset, email verification, and two-factor authentication management.
 * Only one null-type operation is permitted to comply with authorization rules.
 * This single operation consolidates all customer self-service actions:
 * resetting password via token (POST /auth/customer/password/reset/{token}),
 * verifying email via token (POST /auth/customer/email/verify/{token}),
 * enabling two-factor authentication (POST /auth/customer/two-factor/enable),
 * disabling two-factor authentication (POST /auth/customer/two-factor/disable),
 * and changing password (POST /auth/customer/password/change). Each sub-action
 * is distinguished by the path and request body. The customer must be
 * authenticated to perform changing password, enrolling or disabling two-factor
 * auth. Password reset and email verification are public. This comprehensive
 * single endpoint approach eliminates ambiguity in authorization type and
 * abides by AutoBE's strict authorizationType = null uniqueness rule.
 *
 * @param props.connection
 * @path /auth/customer/self
 * @accessor api.functional.auth.customer.self.selfService
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function selfService(
  connection: IConnection,
): Promise<selfService.Response> {
  return true === connection.simulate
    ? selfService.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...selfService.METADATA,
          path: selfService.path(),
          status: null,
        },
      );
}
export namespace selfService {
  export type Response = IShoppingMallCustomer.IActionResult;

  export const METADATA = {
    method: "POST",
    path: "/auth/customer/self",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/customer/self";
  export const random = (): IShoppingMallCustomer.IActionResult =>
    typia.random<IShoppingMallCustomer.IActionResult>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}
