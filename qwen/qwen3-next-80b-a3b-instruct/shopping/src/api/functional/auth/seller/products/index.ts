import { IConnection } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";

import { IPageIShoppingMallProduct } from "../../../../structures/IPageIShoppingMallProduct";

/**
 * This null-authorization operation enables seller actors to browse available
 * products and product categories on the shoppingMall platform.
 *
 * Based on the shopping_mall_products and shopping_mall_categories tables, this
 * operation provides read-only access to product listings without requiring
 * authentication. The product catalog is structured with primary categories and
 * optional secondary category associations, enabling efficient product
 * discovery.
 *
 * This operation supports the critical business requirement for sellers to
 * evaluate product offerings, understand market positioning, and identify
 * potential inventory opportunities without needing to be authenticated. The
 * product information accessed (name, description, category, images) is all
 * publicly available data stored in the shopping_mall_products table.
 *
 * As a member actor (seller), this operation is essential for their business
 * workflow, allowing them to research market trends and competitor offerings
 * before making inventory decisions. The operation follows a standard REST
 * pattern for resource listing (PATCH method) to support potential filtering,
 * sorting, and pagination requirements.
 *
 * This authorizationType=null operation balances platform openness with
 * security by only exposing non-sensitive product information while maintaining
 * strict access control on all authenticated operations. It complements the
 * join/login/refresh authentication operations by enabling initial platform
 * exploration before account creation.
 *
 * The operation adheres to the platform's information architecture where
 * product catalog browsing is designated as a public-facing, non-authenticated
 * activity that serves both potential sellers and customers alike.
 *
 * @param props.connection
 * @path /auth/seller/products
 * @accessor api.functional.auth.seller.products.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(connection: IConnection): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
      );
}
export namespace index {
  export type Response = IPageIShoppingMallProduct;

  export const METADATA = {
    method: "PATCH",
    path: "/auth/seller/products",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/seller/products";
  export const random = (): IPageIShoppingMallProduct =>
    typia.random<IPageIShoppingMallProduct>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}
