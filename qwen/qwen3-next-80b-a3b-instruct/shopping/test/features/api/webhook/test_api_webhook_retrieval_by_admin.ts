export async function test_api_webhook_retrieval_by_admin(
  connection: api.IConnection,
): Promise<void> {
  // Step 1: Create a new connection and authenticate as admin
  const adminConnection: api.IConnection = { host: connection.host };
  const admin: IShoppingMallAdmin.IAuthorized = await authorize_admin_join(
    adminConnection,
    {
      body: {
        email: typia.random<string & tags.Format<"email">>(),
        password: RandomGenerator.alphaNumeric(16),
        href: "https://example.com/admin/join",
        referrer: "https://example.com/admin/signup",
      } satisfies IShoppingMallAdmin.IJoin,
    },
  );
  typia.assert(admin);
  // Step 2: Try to retrieve a non-existent webhook using a random UUID
  // Since no create endpoint exists, we must test the 404 case
  await TestValidator.error(
    "should return 404 for non-existent webhook",
    async () => {
      await api.functional.shoppingMall.admin.webhooks.at(adminConnection, {
        id: typia.random<string & tags.Format<"uuid">>(),
      });
    },
  );
}
