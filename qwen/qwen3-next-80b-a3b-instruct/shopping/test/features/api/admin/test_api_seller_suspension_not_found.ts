export async function test_api_seller_suspension_not_found(
  connection: api.IConnection,
): Promise<void> {
  // Step 1: Create admin connection and authenticate
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: "https://example.com/join",
      referrer: "https://example.com",
      ip: "192.168.1.1",
    } satisfies IShoppingMallAdmin.IJoin,
  });
  // Step 2: Generate a valid UUID that is guaranteed to be properly formatted but does not exist in the database
  const nonExistentSellerId: string & tags.Format<"uuid"> = typia.random<
    string & tags.Format<"uuid">
  >();
  // Step 3: Attempt to suspend non-existent seller and expect 404 error
  await TestValidator.error(
    "suspension should fail for non-existent seller",
    async () => {
      await api.functional.shoppingMall.admin.sellers.suspend(adminConnection, {
        sellerId: nonExistentSellerId,
      });
    },
  );
}
