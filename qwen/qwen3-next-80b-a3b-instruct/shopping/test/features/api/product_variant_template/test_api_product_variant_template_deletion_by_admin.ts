import type { IShoppingMallAdmin } from "@ORGANIZATION/PROJECT-api/lib/structures/IShoppingMallAdmin";
import { authorize_admin_join } from "../../../authorize/authorize_admin_join";
import { authorize_admin_login } from "../../../authorize/authorize_admin_login";
import { authorize_admin_refresh } from "../../../authorize/authorize_admin_refresh";
export async function test_api_product_variant_template_deletion_by_admin(
  connection: api.IConnection,
): Promise<void> {
  // Create admin connection and authenticate
  const adminConnection: api.IConnection = { host: connection.host };
  const admin = await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IShoppingMallAdmin.IJoin,
  });
  typia.assert(admin);
  // Generate random product and template IDs
  const productId = typia.random<string & tags.Format<"uuid">>();
  const templateId = typia.random<string & tags.Format<"uuid">>();
  // Perform template deletion as admin
  await api.functional.shoppingMall.admin.products.templates.erase(
    adminConnection,
    {
      productId,
      templateId,
    },
  );
  // No need for typia.assert since erase returns void
  // Verify that the deletion was successful (no error thrown)
  // TestValidator.error not used since we expect success, not failure
}
