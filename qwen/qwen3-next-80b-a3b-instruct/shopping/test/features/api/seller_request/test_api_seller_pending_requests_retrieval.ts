export async function test_api_seller_pending_requests_retrieval(
  connection: api.IConnection,
): Promise<void> {
  // 1. Seller joins and authenticates
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {
    body: {} satisfies IShoppingMallSeller.IJoin,
  });
  // 2. Retrieve pending requests using SDK function since no utility exists for this endpoint
  const pendingRequests =
    await api.functional.shoppingMall.seller.seller.requests.pending.index(
      sellerConnection,
    );
  typia.assert(pendingRequests);
  // 3. Validate response is not null/undefined
  TestValidator.predicate(
    "pending requests response exists",
    pendingRequests !== null,
  );
}
