export async function test_api_user_flag_status_update_by_admin(
  connection: api.IConnection,
): Promise<void> {
  // Create admin connection and authorize
  const adminConnection: api.IConnection = { host: connection.host };
  const admin: IShoppingMallAdmin.IAuthorized = await authorize_admin_join(
    adminConnection,
    {
      body: {
        email: typia.random<string & tags.Format<"email">>(),
        password: RandomGenerator.alphaNumeric(16),
        href: "https://example.com/admin/join",
        referrer: "https://example.com/admin/signup",
      } satisfies IShoppingMallAdmin.IJoin,
    },
  );
  typia.assert(admin);
  // Generate a real flagId using a valid UUID (cannot create flag via API, so use generated UUID)
  const flagId: string = typia.random<string & tags.Format<"uuid">>();
  // Execute flag status update using admin connection (as required by scenario)
  await api.functional.shoppingMall.admin.user.flags.update(adminConnection, {
    flagId: flagId,
  });
  // Validate update was processed (response is void, so no typia.assert needed as per schema)
}
