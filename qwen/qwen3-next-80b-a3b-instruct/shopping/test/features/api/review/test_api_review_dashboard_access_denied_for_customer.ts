export async function test_api_review_dashboard_access_denied_for_customer(
  connection: api.IConnection,
): Promise<void> {
  // Step 1: Create admin-specific connection and authenticate as admin
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: "https://example.com/join",
      referrer: "https://example.com",
      ip: null,
    } satisfies IShoppingMallAdmin.IJoin,
  });
  // Step 2: Create customer-specific connection and authenticate as customer
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: "https://example.com/join",
      referrer: "https://example.com",
      ip: null,
    } satisfies IShoppingMallCustomer.IJoin,
  });
  // Step 3: Execute the test - customer attempts to access admin-only dashboard
  // This should fail with 403 Forbidden since customers are not authorized for admin endpoints
  await TestValidator.error(
    "customer should be denied access to admin review dashboard",
    async () => {
      await api.functional.shoppingMall.admin.reviews.dashboard.index(
        customerConnection,
      );
    },
  );
}
