export async function test_api_admin_reviews_export_all(
  connection: api.IConnection,
): Promise<void> {
  // Step 1: Create new admin account to authenticate for export operation
  const adminConnection: api.IConnection = { host: connection.host };
  const admin = await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: "https://example.com/admin/join",
      referrer: "https://example.com/admin/signup",
    } satisfies IShoppingMallAdmin.IJoin,
  });
  typia.assert(admin);
  // Step 2: Use admin connection to request export of all reviews without filters
  // The IRequest schema allows empty filters to export all reviews
  const exportResult =
    await api.functional.shoppingMall.admin.reviews._export.index(
      adminConnection,
      {
        body: {} satisfies IShoppingMallProductReview.IRequest,
      },
    );
  typia.assert(exportResult);
}
