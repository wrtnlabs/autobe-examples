export async function test_api_order_item_admin_full_access(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin setup: Create and authenticate admin account
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {} satisfies IShoppingMallAdmin.IJoin,
  });
  // 2. Generate valid UUIDs for order and order item to access
  const orderId = typia.random<string & tags.Format<"uuid">>();
  const orderItemId = typia.random<string & tags.Format<"uuid">>();
  // 3. Admin retrieves any order item using generated UUIDs
  // This tests the core functionality: admin access regardless of ownership
  const item = await api.functional.shoppingMall.customer.orders.items.at(
    adminConnection,
    {
      orderId,
      orderItemId,
    },
  );
  typia.assert(item);
  // 4. Validate the admin access - the item is accessible and valid
  // typia.assert already validates the type and structure
}
