export async function test_api_product_engagement_analytics_unauthorized_access(
  connection: api.IConnection,
): Promise<void> {
  // Create admin connection and authenticate
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IShoppingMallAdmin.IJoin,
  });
  // Create customer connection and authenticate
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IShoppingMallCustomer.IJoin,
  });
  // Create seller connection and authenticate
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IShoppingMallSeller.IJoin,
  });
  // Test customer access (should fail with 403)
  await TestValidator.httpError(
    "customer should receive 403 Forbidden for product engagement analytics",
    403,
    async () => {
      await api.functional.shoppingMall.admin.analytics.products.engagement.index(
        customerConnection,
      );
    },
  );
  // Test seller access (should fail with 403)
  await TestValidator.httpError(
    "seller should receive 403 Forbidden for product engagement analytics",
    403,
    async () => {
      await api.functional.shoppingMall.admin.analytics.products.engagement.index(
        sellerConnection,
      );
    },
  );
}