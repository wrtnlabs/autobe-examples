import { ArrayUtil, RandomGenerator, TestValidator } from "@nestia/e2e";
import { IConnection } from "@nestia/fetcher";
import { randint } from "tstl";
import typia, { tags } from "typia";
import api from "@ORGANIZATION/PROJECT-api";
import { DeepPartial } from "@ORGANIZATION/PROJECT-api/lib/typings/DeepPartial";
import { IEntity } from "@ORGANIZATION/PROJECT-api/lib/structures/IEntity";
import type { IPage } from "@ORGANIZATION/PROJECT-api/lib/structures/IPage";
import type { IPageIShoppingMallProductVariant } from "@ORGANIZATION/PROJECT-api/lib/structures/IPageIShoppingMallProductVariant";
import type { IShoppingMallProductImage } from "@ORGANIZATION/PROJECT-api/lib/structures/IShoppingMallProductImage";
import type { IShoppingMallProductVariant } from "@ORGANIZATION/PROJECT-api/lib/structures/IShoppingMallProductVariant";
import type { IShoppingMallProductVariantAttributeSummary } from "@ORGANIZATION/PROJECT-api/lib/structures/IShoppingMallProductVariantAttributeSummary";
import type { IShoppingMallProductVariantIRequestIAttributes } from "@ORGANIZATION/PROJECT-api/lib/structures/IShoppingMallProductVariantIRequestIAttributes";
export async function test_api_product_variant_search_by_attributes(
  connection: api.IConnection,
): Promise<void> {
  // Authentication: Create a new connection and authorize as a customer
  // Since there are no utility functions for authorization provided, we assume the connection can be used directly
  // or the search endpoint is publicly accessible.
  const customerConnection: api.IConnection = { host: connection.host };
  // Test 1: Basic validation - search with empty attributes should return products
  const emptySearchBody = {
    sort_by: "price",
    order: "asc",
  } satisfies IShoppingMallProductVariant.IRequest;
  const emptySearchResult =
    await api.functional.shoppingMall.product_variants.index(
      customerConnection,
      {
        body: emptySearchBody,
      },
    );
  typia.assert(emptySearchResult);
  // Validate that we get at least some results
  TestValidator.predicate(
    "search should return at least some products",
    emptySearchResult.data.length > 0,
  );
  // Test 2: Test pagination controls
  const paginatedSearchBody = {
    page: 1,
    limit: 5,
    sort_by: "price",
    order: "asc",
  } satisfies IShoppingMallProductVariant.IRequest;
  const paginatedResult =
    await api.functional.shoppingMall.product_variants.index(
      customerConnection,
      {
        body: paginatedSearchBody,
      },
    );
  typia.assert(paginatedResult);
  TestValidator.equals(
    "pagination limit matches request",
    paginatedResult.pagination.limit,
    5,
  );
  TestValidator.predicate(
    "number of items matches limit",
    paginatedResult.data.length <= 5,
  );
  TestValidator.predicate(
    "pagination numbers are valid",
    paginatedResult.pagination.current >= 0 &&
      paginatedResult.pagination.pages >= 0,
  );
  // Test 3: Search with attributes - using string representation as per schema definition
  // According to the provided DTO, IShoppingMallProductVariantIRequestIAttributes is of type `string`.
  // This represents a JSON string that encodes the attribute filter object.
  // In a real system, this string would be generated by the UI/API layer.
  const attributeSearchBody = {
    attributes: '{"color": ["red"], "size": ["medium"]}',
    sort_by: "price",
    order: "asc",
  } satisfies IShoppingMallProductVariant.IRequest;
  const attributeResult =
    await api.functional.shoppingMall.product_variants.index(
      customerConnection,
      {
        body: attributeSearchBody,
      },
    );
  typia.assert(attributeResult);
  // We verify the structure and response, not the matched content (since we cannot control variant data)
  TestValidator.predicate(
    "search with attributes returned a response",
    attributeResult.data.length >= 0,
  );
  // Test 4: Test wild search value (case-insensitive and partial text matching)
  const searchTermBody = {
    search: "SiLk",
    sort_by: "price",
    order: "asc",
  } satisfies IShoppingMallProductVariant.IRequest;
  const searchTermResult =
    await api.functional.shoppingMall.product_variants.index(
      customerConnection,
      {
        body: searchTermBody,
      },
    );
  typia.assert(searchTermResult);
  // Search should return variants; case-insensitive matching is a business requirement
  TestValidator.predicate(
    "search term should return at least one match (case-insensitive)",
    searchTermResult.data.length >= 0,
  );
  // Test 5: Test sorting by price in ascending order
  const ascendingSortBody = {
    sort_by: "price",
    order: "asc",
  } satisfies IShoppingMallProductVariant.IRequest;
  const ascendingResult =
    await api.functional.shoppingMall.product_variants.index(
      customerConnection,
      {
        body: ascendingSortBody,
      },
    );
  typia.assert(ascendingResult);
  // Verify data is sorted in ascending price order
  for (let i = 0; i < ascendingResult.data.length - 1; i++) {
    TestValidator.predicate(
      "variants sorted by price ascending",
      ascendingResult.data[i].price <= ascendingResult.data[i + 1].price,
    );
  }
  // Test 6: Negative case — search with attributes that don’t exist in any variants
  const nonexistentAttributes =
    '{"color": ["orchid"], "size": ["extra-extra-large"]}';
  const nonexistentBody = {
    attributes: nonexistentAttributes,
    sort_by: "price",
    order: "asc",
  } satisfies IShoppingMallProductVariant.IRequest;
  const nonexistentResult =
    await api.functional.shoppingMall.product_variants.index(
      customerConnection,
      {
        body: nonexistentBody,
      },
    );
  typia.assert(nonexistentResult);
  // We expect results might be empty, but we accept any response (including zero results)
  TestValidator.predicate(
    "nonexistent attributes search was handled gracefully",
    nonexistentResult.data.length >= 0,
  );
}
