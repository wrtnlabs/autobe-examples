export async function test_api_seller_snapshots_cross_seller_access_denied(
  connection: api.IConnection,
): Promise<void> {
  // Create first seller and authenticate
  const seller1Connection: api.IConnection = { host: connection.host };
  const seller1Auth = await authorize_seller_join(seller1Connection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IShoppingMallSeller.IJoin,
  });
  typia.assert(seller1Auth);
  // Create second seller and authenticate
  const seller2Connection: api.IConnection = { host: connection.host };
  const seller2Auth = await authorize_seller_join(seller2Connection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IShoppingMallSeller.IJoin,
  });
  typia.assert(seller2Auth);
  // Use seller1's connection to attempt access to seller2's snapshots
  // This should fail with 403 Forbidden as seller1 is not authorized to access seller2's data
  await TestValidator.httpError(
    "seller cannot access another seller's snapshots",
    403,
    async () => {
      await api.functional.shoppingMall.seller.snapshots.index(
        seller1Connection,
        {
          body: {
            entity_type: "product",
            changed_by: "seller",
          } satisfies IShoppingMallProductSnapshot.IRequest,
        },
      );
    },
  );
}
