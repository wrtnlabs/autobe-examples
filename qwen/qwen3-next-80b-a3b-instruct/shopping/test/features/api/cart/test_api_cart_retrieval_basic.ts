export async function test_api_cart_retrieval_basic(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create customer account
  const customerConnection: api.IConnection = { host: connection.host };
  const customer = await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IShoppingMallCustomer.IJoin,
  });
  typia.assert(customer);
  // 2. Retrieve cart (default settings: in_stock_only=false)
  const cartResponse = await api.functional.shoppingMall.customer.carts.index(
    customerConnection,
    {
      body: {
        in_stock_only: false,
      } satisfies IShoppingMallCart.IRequest,
    },
  );
  typia.assert(cartResponse);
}
