export async function test_api_inventory_health_retrieval_by_admin(
  connection: api.IConnection,
): Promise<void> {
  // Step 1: Create a new connection and authenticate as admin
  const adminConnection: api.IConnection = { host: connection.host };
  const admin: IShoppingMallAdmin.IAuthorized = await authorize_admin_join(
    adminConnection,
    {
      body: {
        email: typia.random<string & tags.Format<"email">>(),
        password: RandomGenerator.alphaNumeric(16),
        href: "https://example.com/join",
        referrer: "https://example.com",
      } satisfies IShoppingMallAdmin.IJoin,
    },
  );
  typia.assert(admin);
  // Step 2: Call the inventory health retrieval endpoint using admin-specific connection
  const healthData: IShoppingMallInventoryHealth =
    await api.functional.shoppingMall.admin.inventory.metrics.health.index(
      adminConnection,
    );
  typia.assert(healthData);
}
