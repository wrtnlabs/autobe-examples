export async function test_api_payment_rate_limits_admin_view(
  connection: api.IConnection,
): Promise<void> {
  // Step 1: Create admin connection and authenticate
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: "https://example.com/admin/join",
      referrer: "https://example.com/admin/signup",
    } satisfies IShoppingMallAdmin.IJoin,
  });
  // Step 2: Call payment rate limits endpoint with admin connection
  const response: IPageIShoppingMallPaymentRateLimit =
    await api.functional.shoppingMall.admin.analytics.payment_rate_limits.index(
      adminConnection,
    );
  typia.assert(response);
}
