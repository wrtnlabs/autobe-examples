export async function test_api_user_profile_retrieval_success(
  connection: api.IConnection,
): Promise<void> {
  // Authenticate user with valid credentials to obtain JWT token
  const userConnection: api.IConnection = { host: connection.host };
  const authorized = await authorize_user_join(userConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies ITodoAppUser.IJoin,
  });
  typia.assert(authorized);
  // Retrieve user profile using authenticated connection
  const profile = await api.functional.todoApp.user.profile.at(userConnection);
  typia.assert(profile);
}
