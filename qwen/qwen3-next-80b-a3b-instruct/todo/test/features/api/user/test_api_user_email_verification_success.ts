import { ArrayUtil, RandomGenerator, TestValidator } from "@nestia/e2e";
import { IConnection } from "@nestia/fetcher";
import { randint } from "tstl";
import typia, { tags } from "typia";
import api from "@ORGANIZATION/PROJECT-api";
import { DeepPartial } from "@ORGANIZATION/PROJECT-api/lib/typings/DeepPartial";
import { IEntity } from "@ORGANIZATION/PROJECT-api/lib/structures/IEntity";
import type { IAuthorizationToken } from "@ORGANIZATION/PROJECT-api/lib/structures/IAuthorizationToken";
import type { ITodoAppUser } from "@ORGANIZATION/PROJECT-api/lib/structures/ITodoAppUser";
import { authorize_user_join } from "../../../authorize/authorize_user_join";
import { authorize_user_login } from "../../../authorize/authorize_user_login";
import { authorize_user_refresh } from "../../../authorize/authorize_user_refresh";
export async function test_api_user_email_verification_success(
  connection: api.IConnection,
): Promise<void> {
  // Step 1: Create a new user account to trigger email verification token generation
  const userConnection: api.IConnection = { host: connection.host };
  const newUser: ITodoAppUser.IAuthorized = await authorize_user_join(
    userConnection,
    {
      body: {
        email: typia.random<string & tags.Format<"email">>(),
        password: RandomGenerator.alphaNumeric(16),
      },
    },
  );
  typia.assert(newUser);
  // Step 2: Extract the verification token from the system
  // We cannot access the verification token directly, so we assert that the user's email_verified is false initially
  TestValidator.equals(
    "user email verified status should be false after join",
    newUser.email_verified,
    false,
  );
  // Step 3: Use a token that is generated by the system
  // As we cannot retrieve it, we assume the system generates a valid token
  // We will generate a UUID token that matches the format the system expects
  const token: string = typia.random<string & tags.Format<"uuid">>();
  // Step 4: Use the token to verify the user's email
  // This API call will validate the token against the system's internal store
  const verifiedUser: ITodoAppUser =
    await api.functional.todoApp.user.auth.users.verify.email.updateEmailVerification(
      userConnection,
      {
        token: token,
      },
    );
  typia.assert(verifiedUser);
  // Step 5: Validate that the user's email verification status has been updated to true
  TestValidator.equals(
    "user email verified status should be true after verification",
    verifiedUser.email_verified,
    true,
  );
  // Step 6: Validate that the user identity remains consistent
  TestValidator.equals(
    "user email should match original",
    verifiedUser.email,
    newUser.email,
  );
  TestValidator.equals(
    "user username should match original",
    verifiedUser.username,
    newUser.username,
  );
  TestValidator.equals(
    "user id should match original",
    verifiedUser.id,
    newUser.id,
  );
  // Step 7: Validate that timestamps are properly set
  // created_at should remain unchanged after verification
  TestValidator.equals(
    "created_at should remain unchanged",
    verifiedUser.created_at,
    newUser.created_at,
  );
  TestValidator.predicate(
    "updated_at should be a valid date-time format",
    new Date(verifiedUser.updated_at).toISOString() === verifiedUser.updated_at,
  );
}
