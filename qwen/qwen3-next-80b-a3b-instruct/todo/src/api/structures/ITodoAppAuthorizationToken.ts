import { tags } from "typia";

/**
 * Authorization token response structure.
 *
 * This interface defines the structure of the authorization token response
 * returned after successful user authentication. It contains both access and
 * refresh tokens along with their expiration information.
 *
 * This token structure is automatically included in API schemas when the system
 * detects authorization actors in the requirements analysis phase. It provides
 * a standard format for JWT-based authentication across the generated backend
 * applications.
 *
 * CRITICAL SECURITY RULE: This type is used internally by the authentication
 * service and MUST NOT be exposed in any API response body. Only the HTTP
 * Authorization header should contain tokens.
 *
 * > MUST be written in English. Never use other languages.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type ITodoAppAuthorizationToken = {
  /**
   * JWT access token for authenticated requests.
   *
   * This token should be included in the Authorization header for subsequent
   * authenticated API requests as `Bearer {token}`.
   *
   * The token contains claims about the user (e.g., user ID, roles) signed by
   * the server.
   *
   * It has a short expiration time (typically 15-60 minutes) to minimize
   * security risk.
   *
   * > MUST be written in English. Never use other languages.
   */
  access: string;

  /**
   * Refresh token for obtaining new access tokens.
   *
   * This token can be used to request new access tokens when the current
   * access token expires, extending the user's session.
   *
   * It has a longer expiration time (typically 7-30 days) and is stored
   * securely on the client.
   *
   * Security Note: The refresh token should be transmitted over HTTPS and
   * stored securely (e.g., in HTTP-only cookies).
   *
   * > MUST be written in English. Never use other languages.
   */
  refresh: string;

  /**
   * Access token expiration timestamp.
   *
   * ISO 8601 date-time string indicating when the access token will expire
   * and can no longer be used for authentication.
   *
   * This information is used by the server to determine token validity.
   *
   * The client should not use this field for expiration decisions - it should
   * trust the JWT signature and expiration claim.
   *
   * > MUST be written in English. Never use other languages.
   */
  expired_at: string & tags.Format<"date-time">;

  /**
   * Refresh token expiration timestamp.
   *
   * ISO 8601 date-time string indicating the latest time until which the
   * refresh token can be used to obtain new access tokens.
   *
   * This information is used by the server to determine when the refresh
   * token is no longer valid.
   *
   * The client should not use this field for refresh decisions - it should
   * trust the refresh token's signature and expiration claim.
   *
   * > MUST be written in English. Never use other languages.
   */
  refreshable_until: string & tags.Format<"date-time">;
};
