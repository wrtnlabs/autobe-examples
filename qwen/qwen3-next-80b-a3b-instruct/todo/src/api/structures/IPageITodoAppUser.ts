import { tags } from "typia";

export namespace IPageITodoAppUser {
  /**
   * Summary representation of a user entity for list views in paginated
   * responses.
   *
   * This schema provides a minimal, secure view of user information suitable
   * for display in lists, dropdowns, and other UI elements within the context
   * of a paginated user list.
   *
   * Fields:
   *
   * - Id: UUID identifier
   *
   * No additional fields are included in this summary type to ensure security
   * and optimal performance for list view scenarios.
   */
  export type ISummary = {
    /**
     * Primary Key identifier of the user.
     *
     * This field corresponds to the 'id' column in the todo_app_users
     * Prisma model, which is stored as a UUID.
     *
     * This field is generated by the database on user creation and should
     * not be requested or modified by clients.
     *
     * The value is a standard UUIDv4 format.
     */
    id: string & tags.Format<"uuid">;
  };
}
