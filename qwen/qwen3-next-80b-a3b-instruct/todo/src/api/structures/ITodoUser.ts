import { tags } from "typia";

import { IAuthorizationToken } from "./IAuthorizationToken";

export namespace ITodoUser {
  /**
   * Authentication response containing access and refresh tokens upon
   * successful registration or login.
   */
  export type IAuthorized = {
    /** Unique identifier of the authenticated user */
    id: string & tags.Format<"uuid">;

    /**
     * Unique email address used for user authentication. Must be unique
     * across the system.
     *
     * This field serves as the primary identifier for user login and
     * registration. It must be unique to ensure single user per email.
     *
     * Security Rule: Unlike password_hash, email is safe to expose in
     * responses as it doesn't contain secret information.
     *
     * Validation Rule: The system requires all users to register with a
     * valid, unique email address.
     *
     * Note: This field is also used for account recovery and communication,
     * but client-facing APIs for todo item operations do not typically
     * expose user details.
     */
    email: string & tags.Format<"email">;

    /**
     * Timestamp when the user account was created. Used for audit and
     * sorting purposes.
     *
     * This field records the moment the user first registered with the
     * system.
     *
     * Business Rule: Useful for audit trails and user analytics. May be
     * used to order users chronologically.
     *
     * Security Rule: This field is auto-generated by the system and MUST
     * NOT be included in any request bodies (e.g., ITodoUser.ICreate) as it
     * is managed automatically.
     *
     * The value is stored in ISO 8601 UTC format.
     */
    created_at: string & tags.Format<"date-time">;

    /**
     * Timestamp when the user account was last updated. Automatically
     * updated on changes to user profile.
     *
     * This field is automatically maintained by the system and updated
     * whenever a user modifies their profile information.
     *
     * Security Rule: This field is system-managed and MUST NOT be included
     * in any request bodies as it reflects internal system activity, not
     * user input.
     *
     * Note: Unlike todo_items, this field is only relevant for user profile
     * updates (e.g., changing email or password), not for todo item
     * operations. Since todo operations don't require user profile changes,
     * this field remains largely passive in the todo workflow.
     */
    updated_at: string & tags.Format<"date-time">;

    /**
     * Soft delete timestamp. When null, user account is active. When set,
     * account is marked for deletion.
     *
     * This field implements soft deletion for user accounts, allowing for
     * account recovery while maintaining data consistency.
     *
     * Business Rule: When deleted_at is set:
     *
     * - User cannot log in (authentication rejected)
     * - All associated todo_items are logically hidden (deleted_at set for
     *   all)
     * - Account data is retained for compliance and recovery
     *
     * Security Rule: This field is system-managed and MUST NOT be included
     * in any request bodies. User deletion is handled through dedicated
     * endpoint.
     *
     * API Behavior: If a user attempts to access their todo items and their
     * account has a non-null deleted_at, the system returns
     * 'AUTH_INVALID_TOKEN' or a 'USER_DELETED' error to prevent access.
     */
    deleted_at: string & tags.Format<"date-time">;

    /** JWT token information for authentication */
    token: IAuthorizationToken;
  };

  /** The request payload for user registration containing email and password. */
  export type IJoin = {
    /**
     * The unique email address the user will use to authenticate. This must
     * be unique across the system and will be stored in the email field of
     * the todo_users table.
     */
    email: string & tags.Format<"email">;

    /**
     * The plaintext password provided by the user during registration. This
     * will be securely hashed and stored in the password_hash field of the
     * todo_users table.
     */
    password: string & tags.MinLength<8> & tags.MaxLength<128>;
  };

  /**
   * The request payload for user authentication containing email and
   * password.
   */
  export type ILogin = {
    /**
     * The email address of the registered user attempting to authenticate.
     * This field corresponds to the email column in the todo_users table.
     */
    email: string & tags.Format<"email">;

    /**
     * The plaintext password provided by the user for authentication. This
     * will be hashed and compared against the password_hash field in the
     * todo_users table.
     */
    password: string & tags.MinLength<8> & tags.MaxLength<128>;

    /**
     * The IP address from which the session was created. Records the public
     * IP address of the device used to authenticate. Use Case: Security
     * monitoring for unusual location access, fraud detection. Note: This
     * field is optional because the server can derive this from the HTTP
     * request headers, but clients may include it explicitly in request
     * bodies for the IAuthLogin operation when ip is known from client
     * context (e.g., SSR applications). Security Rule: This field can be
     * modified by system or middleware, and the client-provided value
     * serves as a hint, not authority. Format is IPv4 or IPv6 string (e.g.,
     * "192.168.1.1" or "2001:0db8:85a3::8a2e:0370:7334").
     */
    ip?: string | undefined;

    /**
     * The URL of the connection that created this session. This field
     * captures the full URL (e.g., https://app.example.com/todo) of the
     * page where the user initiated the login or session creation. Security
     * Rule: This field is MANDATORY in all authentication request bodies
     * (e.g., ITodoUser.ILogin, ITodoUser.IJoin) because it provides crucial
     * context for session integrity and is directly used for audit trails.
     * It is NOT inferred by the server; it MUST be provided by the client.
     * Integrity Meaning: If this matches the current URL, the login was
     * initiated within the application context. Example:
     * "https://app.example.com/login" or
     * "https://app.example.com/dashboard".
     */
    href: string & tags.Format<"uri">;

    /**
     * The referrer URL that led to this session. This field captures the
     * previous page URL from which the user navigated to initiate login.
     * Security Rule: This field is MANDATORY in all authentication request
     * bodies (e.g., ITodoUser.ILogin, ITodoUser.IJoin). It helps in
     * detecting phishing attempts, tracking marketing channels, and
     * security analytics. It is NOT inferred by the server; it MUST be
     * provided by the client. Example: "https://google.com" (if user came
     * from a search engine) or "https://app.example.com/login" (if user
     * returned from different page). May be empty string when user directly
     * entered the URL or used a bookmark.
     */
    referrer: string & tags.Format<"uri">;
  };

  /** The request payload containing the refresh token for token renewal. */
  export type IRefresh = {
    /**
     * The refresh token received during the initial login or join
     * operation. This token is validated against the todo_user_sessions
     * table, confirming its validity and active status.
     */
    refreshToken: string & tags.MinLength<32>;
  };
}
