/**
 * A todo task item belonging exclusively to a registered user.
 *
 * Represents a single actionable item in the user's personal todo list. Each
 * todo item is owned by one user and contains a title (required, unique per
 * user), an optional description, a status flag indicating completion, and
 * related timestamps for creation, updates, and completion.
 *
 * All relationships, business rules, constraints, and validation requirements
 * as described in the todo_todos Prisma schema are enforced. Ownership is
 * managed via a foreign key to the user. Titles are unique for each user,
 * ensuring no accidental duplicate entries.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type ITodoTodo = {
  /** Primary Key. Unique identifier for each todo item. */
  id: string & tags.Format<"uuid">;

  /**
   * Short, descriptive title for the todo item. Must be unique per user, not
   * blank, maximum 255 characters. Cannot contain only whitespace. Required
   * on creation. Business rules prevent empty or duplicate values.
   */
  title: string;

  /**
   * Detailed notes or additional context for the todo item. Optional; may be
   * null. Maximum length 1000 characters. Not shown in list displays by
   * default.
   */
  description?: string | null | undefined;

  /**
   * Boolean flag indicating whether the task is complete. Defaults to false.
   * Can be toggled by user at any time.
   */
  completed: boolean;

  /**
   * Timestamp indicating when the todo was created. Set automatically,
   * immutable after insertion.
   */
  created_at: string & tags.Format<"date-time">;

  /**
   * Timestamp of last update to this todo, modified on every edit or status
   * change.
   */
  updated_at: string & tags.Format<"date-time">;

  /**
   * Timestamp when the todo was marked completed. Set when task is complete,
   * cleared when reverted to incomplete. Null if not completed.
   */
  completed_at?: (string & tags.Format<"date-time">) | null | undefined;

  /**
   * Reference to the owning user (summary only). Enforces strict single-user
   * data partition and access. Corresponds to todo_user_id property linking
   * this todo to its owner.
   */
  user: ITodoUser.ISummary;
};
