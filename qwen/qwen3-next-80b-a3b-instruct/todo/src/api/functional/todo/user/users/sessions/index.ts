/**
 * Search and paginate your own authentication sessions (todo_user_sessions
 * table).
 *
 * Retrieve a paginated and filtered list of your own authentication sessions by
 * userId in the path. This is designed for ordinary users ("user" role) to view
 * their own session history for cross-device management, logout, or security
 * monitoring.
 *
 * The response provides comprehensive session activity records, including
 * connection context, IP address, and login/referrer URLs, so that users can
 * review past account access and notice suspicious activity. Search and
 * filtering is performed via criteria in the request body, allowing filtering
 * by creation date, active/expired status, or device/session attributes.
 * Pagination and sorting are also supported for efficiency.
 *
 * Security ensures a user may only view their own sessions (the userId must
 * match the authenticated user's id). All results are filtered accordingly, and
 * there is never visibility into other users' sessions.
 *
 * @param props.connection
 * @param props.userId Unique identifier of the user account (must be the
 *   currently authenticated user).
 * @param props.body Search, filtering, and pagination criteria for
 *   todo_user_sessions records of the user.
 * @path /todo/user/users/:userId/sessions
 * @accessor api.functional.todo.user.users.sessions.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Unique identifier of the user account (must be the currently
     * authenticated user).
     */
    userId: string & tags.Format<"uuid">;

    /**
     * Search, filtering, and pagination criteria for todo_user_sessions
     * records of the user.
     */
    body: ITodoUserSession.IRequest;
  };
  export type Body = ITodoUserSession.IRequest;
  export type Response = IPageITodoUserSession.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/todo/user/users/:userId/sessions",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/todo/user/users/${encodeURIComponent(props.userId ?? "null")}/sessions`;
  export const random = (): IPageITodoUserSession.ISummary =>
    typia.random<IPageITodoUserSession.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("userId")(() => typia.assert(props.userId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

