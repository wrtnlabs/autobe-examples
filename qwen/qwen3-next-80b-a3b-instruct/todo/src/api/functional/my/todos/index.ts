import { IConnection } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";

import { IPageITodoListTodo } from "../../../structures/IPageITodoListTodo";

/**
 * Retrieves a member's own todo items for display in the user interface. This
 * operation queries the todo_list_todos table to return all active todo items
 * associated with the authenticated member's account. The system filters
 * results strictly by the authenticated user's context, ensuring no access to
 * other members' data.
 *
 * No parameters are required for this endpoint as it automatically uses the
 * actor's identity from the authentication context. The operation returns a
 * paginated list of todo items ordered by creation date, with summary
 * information including title, completion status, and creation timestamp.
 *
 * This is the primary interface for members to interact with their personal
 * task list. It requires successful authentication through one of the
 * join/login/refresh mechanisms before this operation can be performed.
 *
 * There are no direct prerequisite operations for this endpoint, but successful
 * authentication via join/login/refresh is implicitly required through the
 * authorization system's middleware protection.
 *
 * @param props.connection
 * @path /my/todos
 * @accessor api.functional.my.todos.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(connection: IConnection): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
      );
}
export namespace index {
  export type Response = IPageITodoListTodo;

  export const METADATA = {
    method: "GET",
    path: "/my/todos",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/my/todos";
  export const random = (): IPageITodoListTodo =>
    typia.random<IPageITodoListTodo>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}
