import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ITodoListAdmin } from "../../../structures/ITodoListAdmin";

/**
 * Retrieve the complete details of a specific administrator account from the
 * todo_list_admin table.
 *
 * This operation fetches a single admin user record based on the email address
 * provided in the path parameter. The email field in the todo_list_admin table
 * is defined with a unique constraint, ensuring each administrator has a
 * distinct email for identification. The response includes all available
 * fields: id, email, name, created_at, updated_at, and status to provide a
 * comprehensive view of the administrator account.
 *
 * The operation requires no request body as it's a simple retrieval operation.
 * Only authenticated admin users with proper authorization can access this
 * endpoint. User authentication is required via the system's JWT authentication
 * protocol to validate the requesting user's admin privileges.
 *
 * This operation complements other admin-related endpoints like PATCH /admins
 * for listing administrators and DELETE /admins/{adminId} for deactivating
 * accounts. The returned email field can be used as a unique identifier for
 * related system operations.
 *
 * @param props.connection
 * @param props.email Unique email address of the target administrator (global
 *   scope)
 * @path /todoList/admins/:email
 * @accessor api.functional.todoList.admins.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique email address of the target administrator (global scope) */
    email: string;
  };
  export type Response = ITodoListAdmin;

  export const METADATA = {
    method: "GET",
    path: "/todoList/admins/:email",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/todoList/admins/${encodeURIComponent(props.email ?? "null")}`;
  export const random = (): ITodoListAdmin => typia.random<ITodoListAdmin>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("email")(() => typia.assert(props.email));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
