import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

/**
 * Permanently delete a user session by combining the user identifier and
 * session identifier. This operation removes the session record from the
 * database and immediately invalidates the associated authentication token.
 *
 * This is an irreversible action that terminates the user's authentication
 * session across all devices. After this operation completes, any remaining
 * tokens associated with the session will no longer be valid for API
 * authentication. The system will log this deletion event for audit purposes.
 *
 * Security: A user can only delete their own session, not sessions belonging to
 * other users. The JWT token in the request header is used to verify the user's
 * identity and match it with the provided userId parameter. The userId
 * parameter in the path must match the authenticated user ID from the token.
 *
 * Relationships: This operation affects the todo_list_user_sessions model of
 * the Prisma schema, where each session record is uniquely identified by the
 * combination of user_id and session_id. The user_id field is a foreign key to
 * todo_list_user and ensures session isolation between users. The session_id is
 * a UUID that uniquely identifies the session record.
 *
 * This operation is particularly useful when a user wishes to terminate a
 * session on a lost or stolen device, or after detecting suspicious activity
 * across devices. It complements the logout operations on the authentication
 * microservice by providing a manual session cleanup capability.
 *
 * @param props.connection
 * @param props.userId Unique identifier of the user whose session is to be
 *   deleted. This must match the authenticated user ID from the JWT token.
 * @param props.sessionId Unique UUID identifier of the session to be
 *   terminated. Must correspond to an active session record for the specified
 *   user.
 * @path /todoList/user/actors/:userId/sessions/:sessionId
 * @accessor api.functional.todoList.user.actors.sessions.erase
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function erase(
  connection: IConnection,
  props: erase.Props,
): Promise<void> {
  return true === connection.simulate
    ? erase.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...erase.METADATA,
          path: erase.path(props),
          status: null,
        },
      );
}
export namespace erase {
  export type Props = {
    /**
     * Unique identifier of the user whose session is to be deleted. This
     * must match the authenticated user ID from the JWT token.
     */
    userId: string & tags.Format<"uuid">;

    /**
     * Unique UUID identifier of the session to be terminated. Must
     * correspond to an active session record for the specified user.
     */
    sessionId: string & tags.Format<"uuid">;
  };

  export const METADATA = {
    method: "DELETE",
    path: "/todoList/user/actors/:userId/sessions/:sessionId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/todoList/user/actors/${encodeURIComponent(props.userId ?? "null")}/sessions/${encodeURIComponent(props.sessionId ?? "null")}`;
  export const random = (): void => typia.random<void>();
  export const simulate = (
    connection: IConnection,
    props: erase.Props,
  ): void => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: erase.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("userId")(() => typia.assert(props.userId));
      assert.param("sessionId")(() => typia.assert(props.sessionId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
