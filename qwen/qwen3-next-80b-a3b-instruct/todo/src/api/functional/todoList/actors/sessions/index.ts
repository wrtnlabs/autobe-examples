/**
 * Retrieve a paginated list of active user sessions for a specific actor (user)
 * from the todo_list_user_sessions table. This operation provides advanced
 * filtering capabilities for user sessions based on status, creation date
 * range, and last activity timestamp.
 *
 * The operation supports comprehensive pagination with configurable page sizes
 * and sorting options. Sessions can be sorted by creation_date, last_active_at,
 * or device_info in ascending or descending order. Filter parameters allow
 * finding sessions for specific devices, IP addresses, or geographic
 * locations.
 *
 * Security considerations include rate limiting for search operations and
 * ensuring that users can only access their own session data. This is enforced
 * at the business logic layer by validating that the requested userId matches
 * the authenticated user's identity in the JWT token.
 *
 * The system follows a 'user-managed' data pattern where sessions are
 * automatically created when users authenticate and are automatically cleaned
 * up after inactivity timeouts. Users can view their own active sessions for
 * security monitoring but cannot create, update, or delete sessions directly -
 * these are managed by the authentication system.
 *
 * This operation is critical for user security awareness, allowing users to
 * view and understand where their account is currently logged in, helping them
 * identify unauthorized access.
 *
 * @param props.connection
 * @param props.userId Unique identifier of the target user (actor) whose
 *   sessions are being retrieved (global scope)
 * @param props.body Search criteria and pagination parameters for filtering
 *   sessions
 * @path /todoList/actors/:userId/sessions
 * @accessor api.functional.todoList.actors.sessions.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
