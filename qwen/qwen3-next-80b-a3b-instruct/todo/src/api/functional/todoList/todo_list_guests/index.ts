/**
 * Create a new guest registration record for a user attempting to join the
 * application.
 *
 * This operation initiates the user registration process by creating a record
 * in the todo_list_guest table with the provided email address. The system
 * validates that the email address is properly formatted and hasn't been used
 * in a previous registration attempt (either active or deleted). Upon
 * successful creation, the system sends a verification email to the provided
 * address.
 *
 * The registration record includes the email address and creation timestamp.
 * The guest record remains active until the user completes registration
 * (creates a todo_list_users record) or the registration expires. If the email
 * has been used before, the system will return a 409 Conflict error.
 *
 * This operation represents the first step in the user onboarding journey and
 * is a prerequisite for creating a full user account.
 *
 * Security: This is a public endpoint accessible to unauthenticated users to
 * enable new user registration.
 *
 * Related operations: GET /todo-list-guests/{guestId} (retrieve registration
 * details)
 *
 * @param props.connection
 * @param props.body Email address for the new guest registration
 * @path /todoList/todo-list-guests
 * @accessor api.functional.todoList.todo_list_guests.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
