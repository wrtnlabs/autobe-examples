import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ITodoListGuest } from "../../../structures/ITodoListGuest";

/**
 * Creates a temporary guest account for anonymous access to the public landing
 * page.
 *
 * This operation initializes a new guest session in the
 * todo_list_guest_sessions table. The guest account is not associated with any
 * persistent user data and exists only for the duration of the session. The
 * system uses the todo_list_guest table to track the existence of guest
 * entities, but no personal identifying information is stored.
 *
 * Guest accounts are designed for visitors to view the landing page without
 * requiring login credentials or personal registration. The account is
 * ephemeral and gets destroyed upon session termination.
 *
 * No schema fields such as email, password_hash, or security tokens are used
 * because guest users have no persistent identity in the system.
 *
 * This operation is the only way a guest can become associated with a session
 * state in the system, as they are otherwise completely anonymous.
 *
 * @param props.connection
 * @setHeader token.access Authorization
 *
 * @path /auth/guest/join
 * @accessor api.functional.auth.guest.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
export namespace join {
  export type Props = {
    body: ITodoListGuest.IJoin;
  };
  export type Body = ITodoListGuest.IJoin;
  export type Response = ITodoListGuest.IAuthorized;

  export const METADATA = {
    method: "POST",
    path: "/auth/guest/join",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/guest/join";
  export const random = (): ITodoListGuest.IAuthorized =>
    typia.random<ITodoListGuest.IAuthorized>();
  export const simulate = (
    connection: IConnection,
    props: join.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: join.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

