import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ITodoListUser } from "../../../../../structures/ITodoListUser";

/**
 * Initiates password reset flow for a registered user. Sends a password reset
 * token to the user's email address in todo_list_user table. The system
 * generates a cryptographically random token, stores it in the
 * password_reset_token field, and sets password_reset_expires_at to 2 hours
 * from now. An email with reset link containing the token is sent via
 * configured email service. This operation does not require authentication and
 * accepts any valid email registered in the system. After the token is used,
 * the token and expiry fields are cleared. This operation does not change the
 * password; it only triggers the email reset sequence. Related operation is
 * updatePassword to complete the reset with new credentials.
 *
 * @param props.connection
 * @param props.body Email address to send password reset instructions to.
 * @path /auth/user/password/reset
 * @accessor api.functional.auth.user.password.reset.resetPassword
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function resetPassword(
  connection: IConnection,
  props: resetPassword.Props,
): Promise<resetPassword.Response> {
  return true === connection.simulate
    ? resetPassword.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...resetPassword.METADATA,
          path: resetPassword.path(),
          status: null,
        },
        props.body,
      );
}
export namespace resetPassword {
  export type Props = {
    /** Email address to send password reset instructions to. */
    body: ITodoListUser.IPasswordResetRequest;
  };
  export type Body = ITodoListUser.IPasswordResetRequest;
  export type Response = ITodoListUser.IPasswordResetInitiated;

  export const METADATA = {
    method: "POST",
    path: "/auth/user/password/reset",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/user/password/reset";
  export const random = (): ITodoListUser.IPasswordResetInitiated =>
    typia.random<ITodoListUser.IPasswordResetInitiated>();
  export const simulate = (
    connection: IConnection,
    props: resetPassword.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: resetPassword.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
