/**
 * This operation registers a new user by creating a record in the
 * todo_list_user table. The email field is required and must be unique as
 * defined by the unique index on the todo_list_user table. The password_hash
 * field is populated with a BCrypt-hashed value derived from the user's input
 * password, never storing plain-text credentials. The created_at and updated_at
 * fields are automatically set to the current timestamp with no user-provided
 * values allowed. This operation enables users to establish their identity in
 * the TodoList application and will be used to generate the initial JWT tokens
 * for subsequent authentication.
 *
 * The implementation strictly follows the todo_list_user schema where email
 * must be a valid, unique string and password_hash is a non-nullable string
 * field. There are no other authentication fields available in the schema, so
 * extensions like email verification or two-factor authentication cannot be
 * implemented. This operation is public and requires no prior authentication.
 *
 * The user identity established here is the sole basis for all subsequent
 * operations in the TodoList application. Each task created, viewed, updated,
 * or deleted will be bound to this user record through the id field. No other
 * actor types exist in this application.
 *
 * Security considerations are addressed through BCrypt hashing and the
 * exclusion of any sensitive fields beyond email and password_hash in the
 * request body. The system does not implement password recovery, reset, or
 * change functions as these fields are not present in the todo_list_user
 * schema. The created_at field provides auditability of account creation time.
 *
 * This join operation must be executed before any login or refresh operations.
 * It is the foundational authentication step. The generated response body will
 * contain the JWT tokens necessary for subsequent API calls.
 *
 * @param props.connection
 * @param props.body Contains the email and password for a new user account.
 * @setHeader token.access Authorization
 *
 * @path /auth/user/join
 * @accessor api.functional.auth.user.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
