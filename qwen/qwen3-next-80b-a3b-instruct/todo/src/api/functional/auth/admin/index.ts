/**
 * Register a new system administrator account.
 *
 * This API endpoint registers a new system administrator account in the
 * todo_app_admins table. When a new admin account is created, the system
 * generates a unique admin ID and stores essential authentication parameters
 * including the hashed password and email address. The operation also
 * associates the new admin with a newly created session record in the
 * todo_app_admin_sessions table, which stores the initial refresh token and
 * session metadata. The system uses encryption to ensure the password is stored
 * securely with appropriate hashing algorithms. This operation is the
 * foundational step for any admin user to gain access to the administrative
 * system. The email field must contain a valid email address format as
 * specified in the DB schema, and timezone information is stored to support
 * locale-specific behavior.
 *
 * The implementation strictly relies on fields defined in the todo_app_admins
 * table: email, password_hash, created_at, last_login, last_password_change,
 * recovery_email, timezone, password_reset_token, password_reset_expires, and
 * is_active. All other fields not defined in the schema are intentionally
 * omitted. The operation does not handle two-factor authentication since the
 * schema does not define any TFA-related fields such as totp_secret or
 * recovery_codes.
 *
 * The registration process is designed with security in mind, ensuring the
 * password is never stored in plain text and all operations comply with
 * industry security standards for credential storage. The firstname, lastname,
 * and phone fields are not included in the request body because the schema does
 * not include these fields, even though they may be common in other systems.
 * The password_reset_token and password_reset_expires fields are included to
 * support password reset functionality, which is supported by the schema.
 *
 * The operation is not subject to rate limiting or IP whitelisting constraints
 * that might be enforced externally, as those mechanisms are not part of the
 * database schema and are handled by separate infrastructure components. The
 * admin account begins in an active state (is_active: true) unless the system
 * has specific configuration requiring manual approval, which is not supported
 * by this schema.
 *
 * This registration process is the only way new admin accounts can be created
 * within the system according to the defined schema, and it is only accessible
 * to the service's provisioning mechanisms, not to end-users.
 *
 * @param props.connection
 * @param props.body Request payload for creating a new admin account. Contains
 *   only fields that exist in the todo_app_admins schema. The email field is
 *   required and must be a valid email format. The password_hash field must
 *   contain a cryptographically secure hashed password generated by the system.
 *   The timezone field accepts valid IANA timezone identifiers and defaults to
 *   UTC if not provided. All other fields are optional according to the schema
 *   definition.
 * @setHeader token.access Authorization
 *
 * @path /auth/admin/join
 * @accessor api.functional.auth.admin.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
