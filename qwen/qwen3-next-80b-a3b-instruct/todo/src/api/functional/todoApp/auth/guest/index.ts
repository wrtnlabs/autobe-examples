/**
 * This operation creates a temporary guest account for unauthenticated users
 * accessing the Todo App. The guest is identified by email and password, which
 * are stored in the todo_app_guests table with the password_hash field. Upon
 * successful registration, a session token is created in
 * todo_app_guest_sessions with 60-minute expiration, allowing temporary access
 * to the application. A JWT access token with 15-minute expiration and refresh
 * token with 7-day expiration are issued. The operation validates that email is
 * not already used by checking the todo_app_guests table, ensuring data
 * integrity. This operation is public and accessible to any unauthenticated
 * user.
 *
 * This operation is required before any guest interaction with the system. It
 * enables users to use guest features without a permanent account. The
 * generated session and tokens expire according to system policy.
 *
 * This operation triggers the registration workflow that sets up the guest's
 * account state in the database and issues credentials for temporary access. It
 * is the primary means of onboarding unauthenticated users.
 *
 * For security, the password_hash field is always hashed before storage and
 * never stored in plaintext. This ensures compliance with data protection
 * standards.
 *
 * This API is part of the guest authentication system, which provides limited
 * access without requiring full registration or persistent identity.
 *
 * @param props.connection
 * @param props.body Data required to create a new guest account.
 * @setHeader token.access Authorization
 *
 * @x-autobe-specification Creates a new guest account by validating email format, generating a unique session ID, hashing password with bcrypt, and storing in todo_app_guests table. Associates the guest with a temporary session in todo_app_guest_sessions with 60-minute expiration. Returns JWT access token valid for 15 minutes and refresh token valid for 7 days.
 * @path /todoApp/auth/guest/join
 * @accessor api.functional.todoApp.auth.guest.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
