/**
 * Registers a new user account using email and password. The system requires a unique email and cryptographically hashed password stored in the todo_app_users table. Upon successful registration, the system issues an access token and refresh token. The email field must be validated for format compliance but is not verified via email confirmation since no email_verified field exists in the schema — confirmation is not required. The password_hash field is populated via bcrypt hashing on the server. No display name is collected during join — profile creation (including display_name) occurs after account activation and is managed separately via profile edit operations. This operation directly writes to the todo_app_users table with created_at and updated_at timestamps initialized. No other user-facing fields are involved in join. No session creation occurs — authentication state is managed via tokens. This operation is independent of any todo or profile data creation — those are separate workflows triggered after successful authentication. This operation does not involve password_reset tokens or user_deletion_requests — those are separate system workflows for later stages.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Request body for user account registration. Contains email and raw password to be hashed server-side. No other fields are accepted or expected. The password is never stored as plaintext — it is immediately hashed using bcrypt upon receipt and stored in the todo_app_users.password_hash field.
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor user
 * @x-autobe-specification Service creates a new record in todo_app_users table with email (verified for format), password_hash (hashed with bcrypt), created_at, updated_at. Returns 201 on success with JWT tokens. Returns 409 if email exists. Returns 400 if email invalid or password too short (7+ chars). Uses Prisma create, no transaction needed. Token generation uses secret key from env and JWT library. No database lookups before write — only validation. No events or hooks triggered.
 * @path /todoApp/auth/user/join
 * @accessor api.functional.todoApp.auth.user.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
