/**
 * Registers a new user account by creating a record in the todo_app_users table
 * with provided email and hashed password.
 *
 * This operation creates a new user account when a member user completes the
 * registration workflow. The email field is captured from the request and
 * stored as the primary identifier, while the password_hash field is populated
 * with a bcrypt-hashed value generated from the submitted password. The
 * operation succeeds only if the email is unique in the system and meets
 * character length requirements.
 *
 * The implementation directly references the todo_app_users table schema, using
 * its email and password_hash fields as defined in the database model. No other
 * fields are manipulated during registration.
 *
 * After successful creation, the system generates a new JWT access token and
 * refresh token pair. The access token is valid for 15 minutes and embedded in
 * the response, while the refresh token is stored securely and used for
 * subsequent token refresh operations.
 *
 * This operation provides the foundational authentication flow for member users
 * to gain access to their personal todo lists, which are protected by the
 * user's credential system.
 *
 * Related operations: /auth/user/login for re-authentication,
 * /auth/user/refresh for token renewal.
 *
 * @param props.connection
 * @param props.body Registration information for creating a new user account.
 * @setHeader token.access Authorization
 *
 * @x-autobe-specification Service layer validates email format and uniqueness against todo_app_users table. Hashes password using bcrypt with cost factor 12. Creates new record with email, password_hash, and empty password_reset_token. Generates JWT access token with 15-minute expiration and refresh token with 7-day expiration. Stores refresh token in secure session store. Returns access token in response header and refresh token in httpOnly cookie.
 * @path /todoApp/auth/user/join
 * @accessor api.functional.todoApp.auth.user.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
