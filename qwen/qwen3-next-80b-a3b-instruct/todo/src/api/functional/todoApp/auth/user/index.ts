/**
 * This endpoint allows a user to create a new account by providing their email address and password. The system validates the email format and password strength (minimum 8 characters). Upon confirmation, the user record is created in the todo_app_users table with is_active set to false and password_hash generated via bcrypt. Correspondingly, an email verification token is created in the todo_app_user_email_verifications table with a 24-hour expiration timestamp. The system returns a JWT access token and refresh token as part of the ITodoAppUser.IAuthorized response body, even though the account is not yet activated. This ensures immediate token issuance while awaiting email confirmation, aligning with the system's principle of non-disclosure about account existence. This operation must be called prior to email verification, and the verification token returned in this response is required for the subsequent email verification endpoint to complete the account activation workflow.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body The credentials required to create a new user account.
 * @x-autobe-specification Validate user credentials and create new account. Hash password using bcrypt, generate email verification token, store in todo_app_user_email_verifications table with 24-hour expiration, store user in todo_app_users table with is_active=false, return JWT token pair in response.
 * @path /todoApp/auth/user/join
 * @accessor api.functional.todoApp.auth.user.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
