import { HttpError, IConnection } from "@nestia/fetcher";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";

import { ITodoAppTodoHistory } from "../../../../../structures/ITodoAppTodoHistory";

/**
 * Retrieve the complete edit history for a specific todo item.
 *
 * This endpoint returns a chronological log of all field-level changes made to the todo, including the before and after values of any modified fields (title, description, start date, due date). History entries are ordered from most recent to oldest by timestamp.
 *
 * Only the owner of the todo can access its edit history. Attempts to access history for a todo belonging to another user will return HTTP 404 Not Found. If no edits have been made, an empty array will be returned.
 *
 * The history data is persisted independently from the todo itself and is automatically removed when the todo is permanently deleted.
 *
 * @param props.connection
 * @param props.id The ID of the todo whose edit history is being requested
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor user
 * @x-autobe-specification Query the todo_app_todo_histories table for all records where todo_app_todo_id = {id} AND the associated todo owner matches the authenticated user ID. Sort results by edited_at in descending order. Return array of history records with fields: id, todo_app_todo_id, edited_at, before_title, after_title, before_description, after_description, before_startdate, after_startdate, before_duedate, after_duedate. If no records exist, return empty array. Apply ownership verification by joining with todo_app_todos table and comparing userID from JWT.
 * @path /todoApp/user/todos/:id/history
 * @accessor api.functional.todoApp.user.todos.history.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * The ID of the todo whose edit history is being requested
     */
    id: string;
  };
  export type Response = ITodoAppTodoHistory;

  export const METADATA = {
    method: "GET",
    path: "/todoApp/user/todos/:id/history",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/todoApp/user/todos/${encodeURIComponent(props.id ?? "null")}/history`;
  export const random = (): ITodoAppTodoHistory =>
    typia.random<ITodoAppTodoHistory>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("id")(() => typia.assert(props.id));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
