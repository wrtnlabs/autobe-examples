import { ITodoAppUser } from "../../../../structures/ITodoAppUser";

/**
 * Retrieve detailed information of a specific user.
 *
 * Retrieve the complete profile details of a specific todo_app_user identified
 * by their unique UUID. This endpoint provides detailed information about a
 * single user, including name, email, role, authentication status, creation
 * date, and last login timestamp.
 *
 * This operation directly maps to the todo_app_users table in the Prisma
 * schema, returning all available fields except those marked as sensitive or
 * internal (such as password hashes or authentication tokens). The path
 * parameter userId must correspond to a valid, existing user ID in the
 * database.
 *
 * Security considerations include proper authentication validation and
 * role-based access control. Even authenticated users can only access their own
 * profile unless they have admin privileges. Authorization checks are performed
 * before execution to ensure the requesting user has permission to view the
 * target profile.
 *
 * This operation complements the user search operation and should be used when
 * precise profile details are needed, such as displaying a user's dashboard or
 * personalized settings.
 *
 * @param props.connection
 * @param props.userId Unique identifier of the target user
 * @path /todoApp/user/users/:userId
 * @accessor api.functional.todoApp.user.users.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique identifier of the target user */
    userId: string;
  };
  export type Response = ITodoAppUser;

  export const METADATA = {
    method: "GET",
    path: "/todoApp/user/users/:userId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/todoApp/user/users/${encodeURIComponent(props.userId ?? "null")}`;
  export const random = (): ITodoAppUser => typia.random<ITodoAppUser>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("userId")(() => typia.assert(props.userId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

