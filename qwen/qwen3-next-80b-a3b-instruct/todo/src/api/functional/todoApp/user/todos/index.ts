/**
 * Retrieve a specific todo item by ID.
 *
 * This endpoint retrieves a single todo item from the system based on its
 * unique identifier. It performs a direct lookup in the todo_app_todos table to
 * fetch the complete state of the requested todo item, including its title,
 * completion status, and creation timestamp.
 *
 * Security considerations ensure that users can only retrieve their own todo
 * items. The system authenticates the requesting user and validates ownership
 * before returning the data. Unauthorized access attempts result in a 404
 * response to prevent information leakage about the existence of todo items
 * belonging to other users.
 *
 * This operation integrates directly with the todo_app_todos Prisma model,
 * referencing its fields including id, title, completed, and created_at. The
 * response includes the full data structure as defined in the model schema. No
 * other models are involved in this specific retrieval operation.
 *
 * @param props.connection
 * @param props.todoId Unique identifier of the target todo item (UUID format)
 * @path /todoApp/user/todos/:todoId
 * @accessor api.functional.todoApp.user.todos.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique identifier of the target todo item (UUID format) */
    todoId: string & tags.Format<"uuid">;
  };
  export type Response = ITodoAppTodo;

  export const METADATA = {
    method: "GET",
    path: "/todoApp/user/todos/:todoId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/todoApp/user/todos/${encodeURIComponent(props.todoId ?? "null")}`;
  export const random = (): ITodoAppTodo => typia.random<ITodoAppTodo>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("todoId")(() => typia.assert(props.todoId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

