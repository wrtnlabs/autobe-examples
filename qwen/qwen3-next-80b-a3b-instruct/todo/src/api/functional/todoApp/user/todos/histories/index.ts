/**
 * Record a new edit history entry when a todo's title, description, startDate, or dueDate is modified.
 *
 * When a user edits any of the allowed fields on a todo, the system creates a dedicated history entry documenting the before and after values. This ensures full auditability of intentional changes to todo metadata while preserving the immutability of the todo's completion status and creation timestamp.
 *
 * The operation is designed with strict validation: only title, description, startDate, and dueDate fields may be submitted. Attempts to modify other fields (like completion status or ID) will result in an error. The edit history is automatically linked to the authenticated user and the specific todo item.
 *
 * This history is separate from toggle event logging. Toggle events (changing completion status) are recorded in a different audit trail and do not appear in this history.
 *
 * The returned response includes the full history entry with its timestamp, providing immediate feedback about the successful edit recording. This enables clients to update their local state or display the new history entry without needing a separate request.
 *
 * @param props.connection
 * @param props.todoId The unique identifier of the todo to edit.
 * @param props.body Fields to edit on the todo, with new values. Only title, description, startDate, and dueDate are permitted.
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor user
 * @x-autobe-specification Validate that requested todo exists and belongs to authenticated user. Verify that request body contains only allowed editable fields: title, description, startDate, dueDate. For each field provided, compare current database value to proposed value. If any value has changed, record old value as before_* and new value as after_* in a new todo_app_todo_histories record. Include current timestamp as edited_at. Do NOT record empty changes. Return created history record with ID and timestamps. Handle any database constraint violations or integrity failures with appropriate error responses.
 * @path /todoApp/user/todos/:todoId/histories
 * @accessor api.functional.todoApp.user.todos.histories.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function create(
  connection: IConnection,
  props: create.Props,
): Promise<create.Response> {
  return true === connection.simulate
    ? create.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...create.METADATA,
          path: create.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace create {
  export type Props = {
    /**
     * The unique identifier of the todo to edit.
     */
    todoId: string;

    /**
     * Fields to edit on the todo, with new values. Only title, description, startDate, and dueDate are permitted.
     */
    body: ITodoAppTodo.IRequest;
  };
  export type Body = ITodoAppTodo.IRequest;
  export type Response = ITodoAppTodoHistory;

  export const METADATA = {
    method: "PATCH",
    path: "/todoApp/user/todos/:todoId/histories",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/todoApp/user/todos/${encodeURIComponent(props.todoId ?? "null")}/histories`;
  export const random = (): ITodoAppTodoHistory =>
    typia.random<ITodoAppTodoHistory>();
  export const simulate = (
    connection: IConnection,
    props: create.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: create.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("todoId")(() => typia.assert(props.todoId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
