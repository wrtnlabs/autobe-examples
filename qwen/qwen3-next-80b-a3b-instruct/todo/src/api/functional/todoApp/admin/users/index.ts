import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

/**
 * Permanently delete a user account.
 *
 * This operation performs a hard delete of a user account from the system. When
 * executed, the entire user record is permanently removed from the
 * todo_app_users table in the database with no possibility of recovery.
 *
 * This is an administrative operation intended for system administrators to
 * remove unwanted or problematic user accounts. It should not be used for users
 * deleting their own accounts, as that functionality is intentionally not
 * provided to preserve data integrity and compliance with data retention
 * policies.
 *
 * The user account record contains personal information, authentication data,
 * and associated permissions that are completely purged from the system when
 * this operation is executed. This includes all linked data and references
 * within the system.
 *
 * Security considerations require that this operation can only be executed by
 * authorized administrators and is subject to strict access controls. Log
 * entries must be created the authentication or audit log system to track this
 * destructive action.
 *
 * This operation has no request body and does not return a response body as per
 * system design, indicating successful deletion through HTTP status code
 * alone.
 *
 * @param props.connection
 * @param props.userId Unique identifier of the target user account to be
 *   permanently deleted from the system
 * @path /todoApp/admin/users/:userId
 * @accessor api.functional.todoApp.admin.users.erase
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function erase(
  connection: IConnection,
  props: erase.Props,
): Promise<void> {
  return true === connection.simulate
    ? erase.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...erase.METADATA,
          path: erase.path(props),
          status: null,
        },
      );
}
export namespace erase {
  export type Props = {
    /**
     * Unique identifier of the target user account to be permanently
     * deleted from the system
     */
    userId: string & tags.Format<"uuid">;
  };

  export const METADATA = {
    method: "DELETE",
    path: "/todoApp/admin/users/:userId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/todoApp/admin/users/${encodeURIComponent(props.userId ?? "null")}`;
  export const random = (): void => typia.random<void>();
  export const simulate = (
    connection: IConnection,
    props: erase.Props,
  ): void => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: erase.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("userId")(() => typia.assert(props.userId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
