import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

/**
 * Permanently delete a specific todo item.
 *
 * This operation permanently removes a specific todo item from the system
 * database. This is a hard delete operation that completely removes the record
 * from the todo_app_todos table without any possibility of recovery.
 *
 * The operation requires authentication and checks user ownership or
 * administrative privileges before execution. A user can only delete their own
 * todo items unless they have admin privileges. Admin users can delete any todo
 * item in the system.
 *
 * The todo item is identified by its unique todoId, which must match the id
 * field in the todo_app_todos table. The operation does not accept a request
 * body as the todo identifier is provided in the URL path.
 *
 * After successful deletion, the system returns a 204 No Content response with
 * no body. If the todo item does not exist, returns a 404 Not Found response.
 * Attempts to delete without proper authorization return 403 Forbidden.
 *
 * This operation does not trigger any audit log creation itself; audit logs for
 * deletion are created automatically by the system as a side effect of the
 * operation in the todo_app_audit_logs table.
 *
 * @param props.connection
 * @param props.todoId Unique identifier of the target todo item (UUID format)
 *   in the todo_app_todos table
 * @path /todoApp/admin/todos/:todoId
 * @accessor api.functional.todoApp.admin.todos.erase
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function erase(
  connection: IConnection,
  props: erase.Props,
): Promise<void> {
  return true === connection.simulate
    ? erase.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...erase.METADATA,
          path: erase.path(props),
          status: null,
        },
      );
}
export namespace erase {
  export type Props = {
    /**
     * Unique identifier of the target todo item (UUID format) in the
     * todo_app_todos table
     */
    todoId: string;
  };

  export const METADATA = {
    method: "DELETE",
    path: "/todoApp/admin/todos/:todoId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/todoApp/admin/todos/${encodeURIComponent(props.todoId ?? "null")}`;
  export const random = (): void => typia.random<void>();
  export const simulate = (
    connection: IConnection,
    props: erase.Props,
  ): void => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: erase.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("todoId")(() => typia.assert(props.todoId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
