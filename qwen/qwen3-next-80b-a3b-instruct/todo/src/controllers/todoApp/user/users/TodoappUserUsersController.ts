import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { getTodoAppUserUsersUserId } from "../../../../providers/getTodoAppUserUsersUserId";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { putTodoAppUserUsersUserId } from "../../../../providers/putTodoAppUserUsersUserId";
import { putTodoAppUserUsersUserCode } from "../../../../providers/putTodoAppUserUsersUserCode";

import { ITodoAppUser } from "../../../../api/structures/ITodoAppUser";

@Controller("/todoApp/user/users")
export class TodoappUserUsersController {
  /**
   * Retrieve detailed information of a specific user.
   *
   * Retrieve the complete profile details of a specific todo_app_user
   * identified by their unique UUID. This endpoint provides detailed
   * information about a single user, including name, email, role,
   * authentication status, creation date, and last login timestamp.
   *
   * This operation directly maps to the todo_app_users table in the Prisma
   * schema, returning all available fields except those marked as sensitive or
   * internal (such as password hashes or authentication tokens). The path
   * parameter userId must correspond to a valid, existing user ID in the
   * database.
   *
   * Security considerations include proper authentication validation and
   * role-based access control. Even authenticated users can only access their
   * own profile unless they have admin privileges. Authorization checks are
   * performed before execution to ensure the requesting user has permission to
   * view the target profile.
   *
   * This operation complements the user search operation and should be used
   * when precise profile details are needed, such as displaying a user's
   * dashboard or personalized settings.
   *
   * @param connection
   * @param userId Unique identifier of the target user
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":userId")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string,
  ): Promise<ITodoAppUser> {
    try {
      return await getTodoAppUserUsersUserId({
        user,
        userId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update user account information.
   *
   * This endpoint allows users to modify their account information in the
   * todoApp system. The operation updates specific fields in the todo_app_users
   * table based on the provided parameters. The system validates that the user
   * ID in the path matches the authenticated user, ensuring that users can only
   * update their own accounts.
   *
   * Security considerations include protection against unauthorized data
   * modification through ownership validation, validation of email format and
   * uniqueness, and confirmation of password changes with appropriate security
   * requirements. The system maintains audit trails of account modifications
   * while preventing modification of sensitive system fields.
   *
   * This operation is critical for users to maintain accurate personal
   * information. It enables users to update their contact details, preferred
   * names, or other non-sensitive profile data. Changes made here directly
   * affect how users are identified in the system and how communications are
   * delivered.
   *
   * @param connection
   * @param userId Unique identifier of the target user account
   * @param body Updated user account information
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":userId")
  public async putByUserid(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoAppUser.IUpdate,
  ): Promise<ITodoAppUser> {
    try {
      return await putTodoAppUserUsersUserId({
        user,
        userId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update user account information.
   *
   * This endpoint allows users to modify their account information in the
   * todoApp system. The operation updates specific fields in the todo_app_users
   * table based on the provided parameters. The system validates that the user
   * ID in the path matches the authenticated user, ensuring that users can only
   * update their own accounts.
   *
   * Security considerations include protection against unauthorized data
   * modification through ownership validation, validation of email format and
   * uniqueness, and confirmation of password changes with appropriate security
   * requirements. The system maintains audit trails of account modifications
   * while preventing modification of sensitive system fields.
   *
   * This operation is critical for users to maintain accurate personal
   * information. It enables users to update their contact details, preferred
   * names, or other non-sensitive profile data. Changes made here directly
   * affect how users are identified in the system and how communications are
   * delivered.
   *
   * @param connection
   * @param userCode Unique business identifier code of the target user (global
   *   scope)
   * @param body Updated user account information
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":userCode")
  public async putByUsercode(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userCode")
    userCode: string,
    @TypedBody()
    body: ITodoAppUser.IUpdate,
  ): Promise<ITodoAppUser> {
    try {
      return await putTodoAppUserUsersUserCode({
        user,
        userCode,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
