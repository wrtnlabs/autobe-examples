import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { getTodoAppUserUsersUserId } from "../../../../providers/getTodoAppUserUsersUserId";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { putTodoAppUserUsersUserId } from "../../../../providers/putTodoAppUserUsersUserId";
import { deleteTodoAppUserUsersUserId } from "../../../../providers/deleteTodoAppUserUsersUserId";

import { ITodoAppUser } from "../../../../api/structures/ITodoAppUser";

@Controller("/todoApp/user/users/:userId")
export class TodoappUserUsersController {
  /**
   * Retrieve the complete profile information of a specific user by their
   * unique identifier.
   *
   * This operation fetches the full user record from the todo_app_users table
   * using the specified userId path parameter. The returned data includes all
   * available user details such as email, encrypted password hash, and
   * timestamps for creation and last update. The userId parameter is validated
   * against the database schema to ensure it corresponds to an actual user
   * record.
   *
   * Security is enforced by ensuring only authenticated users can access their
   * own data or authorized personnel (e.g., admins) can access other users'
   * data. The operation is read-only and does not modify any state.
   *
   * Implementation note: This operation does not return any sensitive
   * information beyond what's necessary for user profile display. Any
   * additional authentication or session validation occurs at the API gateway
   * or middleware layer before reaching this endpoint. Related operations: List
   * users (GET /users).
   *
   * @param connection
   * @param userId Unique identifier of the target user
   * @x-autobe-specification Query todo_app_users table by id field. Use parameterized query to prevent SQL injection. Return full user record with all fields. If user not found, return 404. Cache response for 5 minutes using userId as cache key.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppUser> {
    try {
      return await getTodoAppUserUsersUserId({
        user,
        userId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update a specific user's profile information. This operation allows an
   * authenticated user to modify their own profile details including email
   * address and username. The operation is performed on the todo_app_users
   * table in the database.
   *
   * The user must be authenticated to perform this update, and the userId in
   * the path must match the authenticated user's ID. Only the email and
   * username fields can be updated through this endpoint; password changes
   * require a dedicated password update endpoint.
   *
   * Email addresses must be validated for proper format and uniqueness across
   * the system (excluding the current user's existing email). Usernames must
   * also be unique and adhere to system requirements.
   *
   * This operation updates the updated_at timestamp automatically to reflect
   * when the change was made. If the email or username conflicts with another
   * user's information, a 409 Conflict response will be returned. If the user
   * does not exist, a 404 Not Found response will be returned.
   *
   * Related operations: Retrieve user profile (GET /users/{userId}), delete
   * user account (DELETE /users/{userId}), and update password (PUT
   * /users/{userId}/password).
   *
   * @param connection
   * @param userId Unique identifier of the target user account
   * @param body Fields to update for the user profile
   * @x-autobe-specification Update user record in todo_app_users table using provided userId path parameter. Accepts JSON body with optional email and username fields. Validate email format and username uniqueness (excluding current user). Update updated_at timestamp to current time. Return 404 if user not found. Return 400 if email or username is invalid. Return 409 if username or email conflicts with existing user. Return 200 with updated user object on success. Use Prisma update with where: { id: userId } and data: { email, username, updated_at: new Date() }. Do not update password_hash field in this endpoint.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoAppUser.IUpdate,
  ): Promise<ITodoAppUser> {
    try {
      return await putTodoAppUserUsersUserId({
        user,
        userId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently remove a user account from the todo_app system. This is a hard
   * delete operation that completely removes the user record and all associated
   * data from the database, including email verifications, password resets,
   * sessions, and personal todo items. The account and its data are
   * irreversibly purged from the system, which differs from soft delete
   * operations.
   *
   * This operation is available only to administrative actors with proper
   * authorization. Normal users cannot delete their own accounts through this
   * endpoint. Any attempt to delete an account that does not exist will return
   * a 404 error.
   *
   * The system does not maintain any historical records of deleted users for
   * compliance or auditing purposes. All user data is purged permanently upon
   * deletion. Related data such as todo items created by this user are also
   * completely removed, as they cannot exist without a parent user account.
   *
   * @param connection
   * @param userId Unique identifier of the target user account to be
   *   permanently deleted. This UUID corresponds to the id field in the
   *   todo_app_users database table.
   * @x-autobe-specification Perform hard delete of user from todo_app_users table using Prisma. Cascade-delete all related subsidiary entities including todo_app_user_email_verifications, todo_app_user_password_resets, todo_app_user_sessions, and todo_app_todo_items. Do not mark as deleted - completely remove records from database. Return the deleted user object before removal. No caching or audit logging required as system does not track user deletions.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppUser> {
    try {
      return await deleteTodoAppUserUsersUserId({
        user,
        userId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
