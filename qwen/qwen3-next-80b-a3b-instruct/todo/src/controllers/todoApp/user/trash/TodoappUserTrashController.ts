import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IPageITodoAppTodo } from "../../../../api/structures/IPageITodoAppTodo";
import { ITodoAppTodo } from "../../../../api/structures/ITodoAppTodo";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { patchTodoAppUserTrash } from "../../../../providers/patchTodoAppUserTrash";

@Controller("/todoApp/user/trash")
export class TodoappUserTrashController {
  /**
   * Retrieve a paginated list of todos that have been soft-deleted by the authenticated user.
   *
   * This operation provides access to the user's personal trash, containing all todos marked for deletion but not yet permanently purged. Users can filter by the timestamp range when the todo was deleted and sort the results by either the original creation timestamp or the deletion timestamp.
   *
   * The response includes only minimal summary information (title, completion status, creation date, deletion date) to optimize for list display performance. Full details and edit history can be retrieved via individual todo restoration or history endpoints.
   *
   * All data returned is exclusively owned by the authenticated user. No other user’s deleted todos are visible or accessible. System-enforced ownership validation ensures data isolation at the database query level.
   *
   * This endpoint is intended for users reviewing, restoring, or permanently deleting items from their trash. The operation requires no request parameters by default but supports complex search criteria through the request body for advanced filtering.
   *
   * @param connection
   * @param body Search and filter criteria for trash items.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Query todo_app_todos table where deleted_at is not null and todo_app_user_id = authenticatedUserId. Support filtering by deletion time range (deleted_atgte, deleted_atlte). Support sorting by created_at or deleted_at in ascending/descending order. Return cursor-based pagination with page and perPage parameters. Exclude any todos with deleted_at = null. Do not join with todo_app_todo_histories unless requested via expanded flag (not required per spec).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoAppTodo.IRequest,
  ): Promise<IPageITodoAppTodo.ISummary> {
    try {
      return await patchTodoAppUserTrash({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
