import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IPageITodoAppTodo } from "../../../../api/structures/IPageITodoAppTodo";
import { ITodoAppTodo } from "../../../../api/structures/ITodoAppTodo";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { deleteTodoAppUserTrashTodoId } from "../../../../providers/deleteTodoAppUserTrashTodoId";
import { patchTodoAppUserTrash } from "../../../../providers/patchTodoAppUserTrash";

@Controller("/todoApp/user/trash")
export class TodoappUserTrashController {
  /**
   * Retrieve a paginated list of your soft-deleted todos (trash).
   *
   * This endpoint returns all todos that have been soft-deleted and are currently in your personal trash. Only todos owned by the authenticated user are returned, ensuring strict data privacy. The list supports filtering by completion status (all, complete, incomplete) and can be sorted by creation date, start date, or due date.
   *
   * Todos without a start date or due date are sorted to appear at the end of the list when sorting by those respective fields. Each todo in the result includes essential summary information: title, completion status, start date (if set), due date (if set), and creation timestamp.
   *
   * @param connection
   * @param body Search criteria and filtering parameters for the trash list
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Query todo_app_todos table with deleted_at IS NOT NULL condition to identify soft-deleted todos. Apply pagination using offset and limit parameters. Apply active filters: completed (true/false/null) to filter by completion status. Sort results by: created_at, start_date, or due_date with direction (asc/desc). Todos without start_date appear last when sorting by start_date. Todos without due_date appear last when sorting by due_date. Include only those todos where todo_app_user_id matches the authenticated user's ID. Return count and page metadata for pagination along with an array of todo summaries.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoAppTodo.IRequest,
  ): Promise<IPageITodoAppTodo.ISummary> {
    try {
      return await patchTodoAppUserTrash({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently removes a todo from the system, purging all associated data including its edit history.
   *
   * This operation permanently deletes a todo item that is currently in trash. Unlike restoration, this is irreversible - the todo and related metadata are completely purged from the database.
   *
   * The operation requires authentication and enforces strict data isolation: users can only permanently delete their own todos. The todo must have been previously soft-deleted (moved to trash) with a non-null deleted_at timestamp.
   *
   * After successful deletion, the todo's ID is invalidated and cannot be restored or referenced.
   *
   * This operation is designed for users who want to ensure complete data removal, such as for compliance with data privacy laws or when confirming they no longer need any record of the task.
   *
   * This endpoint is not used for restoring items from trash. For restoration, use PATCH /trash/{todoId} with {deleted_at: null}.
   *
   * This endpoint is complementary to the restore operation on trash, which sets deleted_at to null to return the todo to the main list.
   *
   * @param connection
   * @param todoId Unique identifier of the todo to be permanently deleted. Must belong to authenticated user.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Execute a hard delete operation on todo_app_todos record where id = {todoId} and todo_app_user_id = authenticatedUserId.
   * Perform cascade deletion of all corresponding entries in todo_app_todo_histories table with matching todo_id.
   * Use direct database DELETE statement with WHERE clause on both id and user_id to enforce ownership.
   * Return 204 No Content on success.
   * Return 404 Not Found if todo does not exist or belongs to another user.
   * Return 400 Bad Request if todo is not in trash (deleted_at is null).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":todoId")
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoId")
    todoId: string,
  ): Promise<void> {
    try {
      return await deleteTodoAppUserTrashTodoId({
        user,
        todoId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
