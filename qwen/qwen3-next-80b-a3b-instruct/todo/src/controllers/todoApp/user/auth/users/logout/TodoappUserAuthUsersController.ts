import { Controller } from "@nestjs/common";
import { TypedRoute } from "@nestia/core";
import typia from "typia";
import { postTodoAppUserAuthUsersLogout } from "../../../../../../providers/postTodoAppUserAuthUsersLogout";
import { UserAuth } from "../../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../../decorators/payload/UserPayload";

@Controller("/todoApp/user/auth/users/logout")
export class TodoappUserAuthUsersController {
  /**
   * This endpoint handles user logout and session termination. According to
   * AutoBE architecture guidelines, authentication and session management
   * operations are strictly handled by specialized authentication services and
   * MUST NOT be generated by the API Operation Generator. This operation is
   * prohibited for implementation by this agent as it violates the separation
   * of concerns principle between business domain operations and cross-cutting
   * authentication concerns.
   *
   * @param connection
   * @x-autobe-specification No implementation provided. This is an authentication session management operation that must be handled exclusively by the authentication agent/service.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async logout(
    @UserAuth()
    user: UserPayload,
  ): Promise<void> {
    try {
      return await postTodoAppUserAuthUsersLogout({
        user,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
