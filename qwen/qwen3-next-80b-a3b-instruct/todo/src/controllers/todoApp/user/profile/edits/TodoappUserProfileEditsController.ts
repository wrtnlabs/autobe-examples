import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IPageITodoAppProfileEdit } from "../../../../../api/structures/IPageITodoAppProfileEdit";
import { ITodoAppProfileEdit } from "../../../../../api/structures/ITodoAppProfileEdit";
import { UserAuth } from "../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../decorators/payload/UserPayload";
import { getTodoAppUserProfileEdits } from "../../../../../providers/getTodoAppUserProfileEdits";
import { patchTodoAppUserProfileEdits } from "../../../../../providers/patchTodoAppUserProfileEdits";

@Controller("/todoApp/user/profile/edits")
export class TodoappUserProfileEditsController {
  /**
   * Retrieve the complete history of all display name changes made by the authenticated user.
   *
   * This endpoint provides a chronological log of every profile edit operation performed by the user, documenting each change in display name with timestamp, prior value, and new value. It serves as an audit trail for personal profile modifications and supports compliance and accountability requirements.
   *
   * History entries are ordered from most recent to oldest. Each entry includes the exact display name before and after the change, and the exact timestamp the change occurred. No user identifiers or internal record IDs are exposed in the response.
   *
   * This operation is implicitly filtered by authentication context — users can only view their own edit history and cannot access or infer the history of other users. The system enforces data isolation at the database layer: every query automatically appends WHERE todo_app_user_id = authenticated_user_id.
   *
   * This endpoint is designed to be used in the user profile settings screen to show a transparent history of changes they have made to their own display name. It supports pagination with standard page size of 20 entries per page.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Query todo_app_profile_edits table filtered by the authenticated user's ID (from JWT). Order results by created_at DESC to show most recent edits first. Return paginated results with default page size of 20. Include total count for pagination UI. Ensure no data from other users is accessible — query must use where todo_app_user_id = authenticatedUserId.
   *
   * Do not return any user identifiers in response (e.g., todo_app_user_id) — only expose original_display_name, new_display_name, and created_at. This aligns with privacy constraints where no user data should be exposed beyond their own history.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async get(
    @UserAuth()
    user: UserPayload,
  ): Promise<IPageITodoAppProfileEdit> {
    try {
      return await getTodoAppUserProfileEdits({
        user,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a paginated list of all historical display name changes for your account.
   *
   * This endpoint provides a complete audit trail of every time you changed your display name in TodoApp. Each entry records the original display name, the new display name, and the exact timestamp when the change occurred. This feature supports compliance, accountability, and personal record-keeping.
   *
   * All data is private to your account. No other user can access this history, even through indirect means. The system enforces strict data isolation at the database and service layer, ensuring your display name history is never exposed to other users.
   *
   * Results are paginated and can be filtered by original or new display name using partial text matching. You can sort entries chronologically (oldest or newest first). The default sort order is newest changes first.
   *
   * Display name changes are immutable - this data is a historical audit trail that cannot be altered after creation. Every edit triggers exactly one new entry. The system does not purge old entries under any circumstance.
   *
   * This operation is read-only and does not modify data. Use it to review your profile's evolution over time. Do not assume any pattern in display name changes - changes may occur infrequently or be frequent during account setup.
   *
   * @param connection
   * @param body Filter and sort parameters for display name edit history.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Query todo_app_profile_edits table with pagination, filtering by original_display_name (partial match), new_display_name (partial match), and date range (created_at). Sort by created_at (default: newest first). Return cursor-based pagination with configurable limit/offset. User context is authenticated via JWT - no user_id parameter needed as it is enforced server-side. Only return entries belonging to the authenticated user. No joins required. History entries are immutable and append-only.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async patch(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoAppProfileEdit.IRequest,
  ): Promise<IPageITodoAppProfileEdit.ISummary> {
    try {
      return await patchTodoAppUserProfileEdits({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
