import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { ITodoAppProfile } from "../../../../api/structures/ITodoAppProfile";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { getTodoAppUserProfile } from "../../../../providers/getTodoAppUserProfile";
import { putTodoAppUserProfile } from "../../../../providers/putTodoAppUserProfile";

@Controller("/todoApp/user/profile")
export class TodoappUserProfileController {
  /**
   * Retrieve the authenticated user's private profile information including display name, account creation date, and last update timestamp.
   *
   * This operation returns exactly one resource: the profile entity associated with the authenticated user whose JWT token is provided in the request header. The response contains no information about any other user, and attempting to access another user's profile will result in HTTP 404 Not Found.
   *
   * Profile data is completely private and isolated. Even when viewing a list of todos, no profile information (display name, email, or user ID) from any other user is ever included in responses. The system enforces data isolation at the database query layer — every query includes a WHERE clause matching the authenticated user ID, ensuring no SQL injection or data leakage can occur.
   *
   * No other API endpoint returns profile data. When a user edits their profile, the old value is preserved in audit logs, but those logs are never exposed through the API. Recovery of delete accounts from backups is handled at the infrastructure level and never accessible via API endpoints.
   *
   * Related operation: PUT /todo_app_profiles updates the display name; this operation is the read counterpart.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Query todo_app_profiles table by userId matching the authenticated user ID extracted from JWT token. Return only displayName, createdAt, and updatedAt fields. Ensure no joins or subqueries include any data from other tables or users. Use secondary index on userId for performance. If user ID is not found in profiles table, return 404 (should never occur if user has valid JWT and registered).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @UserAuth()
    user: UserPayload,
  ): Promise<ITodoAppProfile> {
    try {
      return await getTodoAppUserProfile({
        user,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update the authenticated user's display name.
   *
   * This operation allows a user to change their visible name within the application. The display name is the only user-editable attribute in the profile. All other profile data—including user ID, account creation timestamp, and last update timestamp—are immutable system-managed fields that are never editable via API.
   *
   * The display name must satisfy strict validation rules: between 1 and 100 characters, excluding HTML tags, special control characters, and leading/trailing whitespace. The system does not allow display names that contain forbidden characters: <, >, &, ", ', \, /, *, ?, |, :,
   *
   * Access to this endpoint is restricted exclusively to the authenticated user. Any attempt to update a profile belonging to another user results in HTTP 403 Forbidden with error code PROFILE_ACCESS_DENIED.
   *
   * This operation does not affect any todo data, history, or trash entries. Profile updates are purely cosmetic and do not trigger audit logs beyond the updatedAt timestamp update.
   *
   * @param connection
   * @param body Contains the new display name for the authenticated user's profile
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor user
   * @x-autobe-specification Extract display name from request body. Validate against length (1–100 chars) and character set restrictions (no forbidden characters). Look up authenticated user via JWT token. Update the todo_app_profiles table SET displayName = ?, updatedAt = NOW() WHERE userId = ? (verified from JWT). If update fails due to constraint violation, throw 400 with error PROFILE_DISPLAY_NAME_INVALID. Return updated profile with: userId, displayName, createdAt, updatedAt. Do not return email, password, or session tokens.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoAppProfile.IUpdate,
  ): Promise<ITodoAppProfile> {
    try {
      return await putTodoAppUserProfile({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
