import { Controller, Ip } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postTodoAppAuthUserJoin } from "../../../../providers/postTodoAppAuthUserJoin";
import { postTodoAppAuthUserLogin } from "../../../../providers/postTodoAppAuthUserLogin";
import { postTodoAppAuthUserRefresh } from "../../../../providers/postTodoAppAuthUserRefresh";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";

import { ITodoAppUser } from "../../../../api/structures/ITodoAppUser";

@Controller("/todoApp/auth/user")
export class TodoappAuthUserController {
  /**
   * Registers a new user account by creating a record in the todo_app_users
   * table with provided email and hashed password.
   *
   * This operation creates a new user account when a member user completes the
   * registration workflow. The email field is captured from the request and
   * stored as the primary identifier, while the password_hash field is
   * populated with a bcrypt-hashed value generated from the submitted password.
   * The operation succeeds only if the email is unique in the system and meets
   * character length requirements.
   *
   * The implementation directly references the todo_app_users table schema,
   * using its email and password_hash fields as defined in the database model.
   * No other fields are manipulated during registration.
   *
   * After successful creation, the system generates a new JWT access token and
   * refresh token pair. The access token is valid for 15 minutes and embedded
   * in the response, while the refresh token is stored securely and used for
   * subsequent token refresh operations.
   *
   * This operation provides the foundational authentication flow for member
   * users to gain access to their personal todo lists, which are protected by
   * the user's credential system.
   *
   * Related operations: /auth/user/login for re-authentication,
   * /auth/user/refresh for token renewal.
   *
   * @param connection
   * @param body Registration information for creating a new user account.
   * @setHeader token.access Authorization
   *
   * @x-autobe-specification Service layer validates email format and uniqueness against todo_app_users table. Hashes password using bcrypt with cost factor 12. Creates new record with email, password_hash, and empty password_reset_token. Generates JWT access token with 15-minute expiration and refresh token with 7-day expiration. Stores refresh token in secure session store. Returns access token in response header and refresh token in httpOnly cookie.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoAppUser.IJoin,
  ): Promise<ITodoAppUser.IAuthorized> {
    try {
      return await postTodoAppAuthUserJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticates an existing user by validating email and password_hash
   * against the todo_app_users table.
   *
   * This endpoint accepts user credentials and verifies them against the stored
   * email and password_hash values in the todo_app_users table. The system
   * checks if a user with the provided email exists and if the submitted
   * password matches the stored password_hash value generated by bcrypt during
   * registration.
   *
   * The operation references the password_hash field directly from the schema
   * and implements the bcrypt verification algorithm to compare hashes without
   * storing passwords in plaintext. No other schema fields are involved in the
   * authentication process.
   *
   * On successful authentication, the system generates a new JWT access token
   * (valid for 15 minutes) and refresh token (valid for 7 days). The access
   * token is returned in the response header, and the refresh token is stored
   * securely in an httpOnly cookie.
   *
   * This operation is the primary authentication mechanism for member users to
   * access their personal todo lists. The user is identified by email address,
   * which serves as their unique identifier in the system.
   *
   * Related operations: /auth/user/join for registration, /auth/user/refresh
   * for token renewal.
   *
   * @param connection
   * @param body Login credentials for authenticating a user account.
   * @setHeader token.access Authorization
   *
   * @x-autobe-specification Service layer queries todo_app_users table for matching email. Uses bcrypt.compare to verify password_hash against submitted password. If validation passes, generates new JWT token pair with 15-minute access token and 7-day refresh token. Stores refresh token in secure persistent store. Returns access token in response header and refresh token in httpOnly cookie. Returns 401 if email not found or password invalid.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoAppUser.ILogin,
  ): Promise<ITodoAppUser.IAuthorized> {
    try {
      return await postTodoAppAuthUserLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Renews access tokens by validating and exchanging a valid refresh token for
   * new access and refresh token pairs.
   *
   * This operation accepts an existing refresh token (received during login or
   * previous refresh) and validates its authenticity against the refresh token
   * store. If valid, it generates a new JWT access token (valid for 15 minutes)
   * and a new refresh token (valid for 7 days), invalidating the original
   * refresh token in the process.
   *
   * The implementation does not access the todo_app_users table directly but
   * relies on the secure refresh token store. No user schema fields (email,
   * password_hash, etc.) are involved in this refresh workflow.
   *
   * The system maintains a refresh token blacklist for revoked tokens and
   * enforces token expiration policies. This provides a secure way for users to
   * maintain persistent sessions without requiring re-authentication with
   * password credentials.
   *
   * This operation is essential for maintaining user sessions without frequent
   * re-authentication, providing both security and usability benefits.
   *
   * Related operations: /auth/user/join for initial registration,
   * /auth/user/login for initial authentication.
   *
   * @param connection
   * @param body Refresh token for obtaining new access tokens.
   * @setHeader token.access Authorization
   *
   * @x-autobe-specification Service layer verifies refresh token against secure token store. Checks token expiration and revocation status. On validation, generates new JWT access token (15-min) and refresh token (7-day). Invalidates original refresh token by adding to blacklist. Stores new refresh token in secure store. Returns access token in response header and new refresh token in httpOnly cookie.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoAppUser.IRefresh,
  ): Promise<ITodoAppUser.IAuthorized> {
    try {
      return await postTodoAppAuthUserRefresh({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
