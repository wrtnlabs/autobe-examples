import { Controller, Ip } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postTodoAppAuthGuestJoin } from "../../../../providers/postTodoAppAuthGuestJoin";
import { postTodoAppAuthGuestRefresh } from "../../../../providers/postTodoAppAuthGuestRefresh";
import { GuestAuth } from "../../../../decorators/GuestAuth";
import { GuestPayload } from "../../../../decorators/payload/GuestPayload";

import { ITodoAppGuest } from "../../../../api/structures/ITodoAppGuest";

@Controller("/todoApp/auth/guest")
export class TodoappAuthGuestController {
  /**
   * This operation creates a temporary guest account for unauthenticated users
   * accessing the Todo App. The guest is identified by email and password,
   * which are stored in the todo_app_guests table with the password_hash field.
   * Upon successful registration, a session token is created in
   * todo_app_guest_sessions with 60-minute expiration, allowing temporary
   * access to the application. A JWT access token with 15-minute expiration and
   * refresh token with 7-day expiration are issued. The operation validates
   * that email is not already used by checking the todo_app_guests table,
   * ensuring data integrity. This operation is public and accessible to any
   * unauthenticated user.
   *
   * This operation is required before any guest interaction with the system. It
   * enables users to use guest features without a permanent account. The
   * generated session and tokens expire according to system policy.
   *
   * This operation triggers the registration workflow that sets up the guest's
   * account state in the database and issues credentials for temporary access.
   * It is the primary means of onboarding unauthenticated users.
   *
   * For security, the password_hash field is always hashed before storage and
   * never stored in plaintext. This ensures compliance with data protection
   * standards.
   *
   * This API is part of the guest authentication system, which provides limited
   * access without requiring full registration or persistent identity.
   *
   * @param connection
   * @param body Data required to create a new guest account.
   * @setHeader token.access Authorization
   *
   * @x-autobe-specification Creates a new guest account by validating email format, generating a unique session ID, hashing password with bcrypt, and storing in todo_app_guests table. Associates the guest with a temporary session in todo_app_guest_sessions with 60-minute expiration. Returns JWT access token valid for 15 minutes and refresh token valid for 7 days.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoAppGuest.IJoin,
  ): Promise<ITodoAppGuest.IAuthorized> {
    try {
      return await postTodoAppAuthGuestJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This operation refreshes the guest's session by validating the provided
   * refresh token against the todo_app_guest_sessions table. When a valid
   * refresh token is presented, a new JWT access token with 15-minute
   * expiration is issued. The operation checks if the existing session is
   * within 20% of its 60-minute expiration window and extends the session
   * expiration if appropriate. Session records are updated in the
   * todo_app_guest_sessions table with the new expiration timestamp. This
   * operation fails if the refresh token has expired, is invalid, or does not
   * correspond to an active guest session. Only temporary guest accounts can
   * use this endpoint.
   *
   * This endpoint supports temporary session maintenance for unauthenticated
   * guest users. It provides a mechanism to remain active within the system
   * without re-authenticating with credentials. This is essential for guest
   * users who want to maintain session persistence within their limited access
   * window.
   *
   * The refresh operation is designed to minimize frequent re-authentication
   * while maintaining security through short-lived access tokens and token
   * rotation.
   *
   * This operation is crucial for providing a seamless user experience for
   * temporary guests who need to maintain access without full authentication.
   *
   * All refresh tokens are stored securely and validated against the
   * todo_app_guest_sessions table to prevent token reuse or hijacking.
   *
   * @param connection
   * @param body The refresh token used to obtain a new access token.
   * @setHeader token.access Authorization
   *
   * @x-autobe-specification Validates refresh token against todo_app_guest_sessions table, generates new access token with 15-minute expiration, and optionally extends session expiration if token is within 20% of expiration. Updates the session record in todo_app_guest_sessions with new expiration timestamp.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @GuestAuth()
    guest: GuestPayload,
    @TypedBody()
    body: ITodoAppGuest.IRefresh,
  ): Promise<ITodoAppGuest.IAuthorized> {
    try {
      return await postTodoAppAuthGuestRefresh({
        guest,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
