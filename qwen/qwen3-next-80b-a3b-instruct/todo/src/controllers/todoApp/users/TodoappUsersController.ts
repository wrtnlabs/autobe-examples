import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia from "typia";
import { postTodoAppUsers } from "../../../providers/postTodoAppUsers";
import { patchTodoAppUsers } from "../../../providers/patchTodoAppUsers";
import { getTodoAppUsersUserId } from "../../../providers/getTodoAppUsersUserId";
import { UserAuth } from "../../../decorators/UserAuth";
import { UserPayload } from "../../../decorators/payload/UserPayload";

import { ITodoAppUser } from "../../../api/structures/ITodoAppUser";
import { IPageITodoAppUser } from "../../../api/structures/IPageITodoAppUser";

@Controller("/todoApp/users")
export class TodoappUsersController {
  /**
   * Create a new user account.
   *
   * This endpoint allows new users to register and create an account in the
   * todoApp system. The operation creates a record in the todo_app_users table
   * with all required user information. The system validates the input data
   * before creating the account, ensuring that all mandatory fields are
   * provided and formatted correctly.
   *
   * Security considerations include password hashing using a strong algorithm
   * before storage, email uniqueness validation to prevent duplicate accounts,
   * and proper input sanitization to prevent injection attacks. The system
   * generates a unique user ID and records the registration timestamp.
   *
   * This operation is the foundation of user authentication in the system.
   * Without successful registration, users cannot access their personal todo
   * lists or other protected features. The user account created here links
   * directly to their todo items in the todo_app_todos table, establishing the
   * user-todo relationship that enables personalized task management.
   *
   * @param connection
   * @param body User registration information for creating a new account
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @TypedBody()
    body: ITodoAppUser.ICreate,
  ): Promise<ITodoAppUser> {
    try {
      return await postTodoAppUsers({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve a filtered, paginated list of users.
   *
   * Retrieve a filtered and paginated list of todo_app_users with comprehensive
   * search and sorting capabilities. This operation enables users to find
   * specific accounts by partial name or email matches, filter by role status,
   * and sort results chronologically or alphabetically. The system supports
   * pagination with configurable page sizes from 10 to 100 items, with a
   * default of 25 items per page.
   *
   * This API operation specifically targets the todo_app_users table from the
   * Prisma schema, incorporating all defined fields including id, name, email,
   * role, created_at, and last_login. It does not expose password fields or
   * other sensitive authentication data. Security considerations include rate
   * limiting to prevent abuse of search functionality and authorization that
   * restricts access based on user role. Admin users may access full user lists
   * while standard users may only see users with shared context.
   *
   * This operation integrates with the applicable Prisma model and returns
   * summary information optimized for display in user interfaces. The response
   * includes only essential user data to minimize payload size, with full user
   * details available through the specific user retrieval endpoint.
   *
   * @param connection
   * @param body Search criteria, sorting options, and pagination parameters for
   *   user filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async search(
    @TypedBody()
    body: ITodoAppUser.IRequest,
  ): Promise<IPageITodoAppUser.ISummary> {
    try {
      return await patchTodoAppUsers({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information of a specific user.
   *
   * Retrieve the complete profile details of a specific todo_app_user
   * identified by their unique UUID. This endpoint provides detailed
   * information about a single user, including name, email, role,
   * authentication status, creation date, and last login timestamp.
   *
   * This operation directly maps to the todo_app_users table in the Prisma
   * schema, returning all available fields except those marked as sensitive or
   * internal (such as password hashes or authentication tokens). The path
   * parameter userId must correspond to a valid, existing user ID in the
   * database.
   *
   * Security considerations include proper authentication validation and
   * role-based access control. Even authenticated users can only access their
   * own profile unless they have admin privileges. Authorization checks are
   * performed before execution to ensure the requesting user has permission to
   * view the target profile.
   *
   * This operation complements the user search operation and should be used
   * when precise profile details are needed, such as displaying a user's
   * dashboard or personalized settings.
   *
   * @param connection
   * @param userId Unique identifier of the target user
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":userId")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string,
  ): Promise<ITodoAppUser> {
    try {
      return await getTodoAppUsersUserId({
        user,
        userId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
