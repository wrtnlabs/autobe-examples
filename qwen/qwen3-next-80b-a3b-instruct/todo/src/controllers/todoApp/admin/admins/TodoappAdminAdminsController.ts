import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postTodoAppAdminAdmins } from "../../../../providers/postTodoAppAdminAdmins";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { patchTodoAppAdminAdmins } from "../../../../providers/patchTodoAppAdminAdmins";
import { getTodoAppAdminAdminsAdminId } from "../../../../providers/getTodoAppAdminAdminsAdminId";
import { putTodoAppAdminAdminsAdminId } from "../../../../providers/putTodoAppAdminAdminsAdminId";
import { deleteTodoAppAdminAdminsAdminId } from "../../../../providers/deleteTodoAppAdminAdminsAdminId";

import { ITodoAppAdmin } from "../../../../api/structures/ITodoAppAdmin";
import { IPageITodoAppAdmin } from "../../../../api/structures/IPageITodoAppAdmin";

@Controller("/todoApp/admin/admins")
export class TodoappAdminAdminsController {
  /**
   * Create a new admin account.
   *
   * This endpoint allows authorized personnel to create new administrative
   * accounts within the TodoApp system. Administrative accounts have elevated
   * privileges to manage all user accounts, view system logs, and configure
   * system settings.
   *
   * The request body must contain complete administrative credential
   * information including a unique username, valid email address, and properly
   * hashed password using PBKDF2 algorithm. The system validates all inputs
   * against security policies before creation, including email uniqueness and
   * password complexity requirements.
   *
   * Upon successful creation, the system generates a unique admin ID, records
   * the creation timestamp in the admin log, and returns the newly created
   * admin entity with minimal identifying information. System will
   * automatically trigger an email notification to the provided email address
   * with login credentials and security instructions.
   *
   * Security considerations include rate limiting on admin creation endpoints,
   * audit logging of all creation events, and mandatory two-factor
   * authentication setup upon first login. This operation is restricted to
   * existing administrators only and cannot be accessed by regular users,
   * preventing unauthorized privilege escalation.
   *
   * @param connection
   * @param body Credentials and configuration data for creating a new admin
   *   user account
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: ITodoAppAdmin.ICreate,
  ): Promise<ITodoAppAdmin> {
    try {
      return await postTodoAppAdminAdmins({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve a filtered, paginated list of admin accounts.
   *
   * Retrieve a filtered and paginated list of admin accounts from the system.
   * This operation provides advanced search capabilities for finding
   * administrators based on multiple criteria including partial name matching,
   * email domain filtering, registration date ranges, and account status.
   *
   * The operation supports comprehensive pagination with configurable page
   * sizes and sorting options. Administrators can sort by registration date,
   * last login, username, or other relevant fields in ascending or descending
   * order.
   *
   * Security considerations include rate limiting for search operations and
   * appropriate filtering of sensitive admin information based on the
   * requesting user's authorization level. Only users with appropriate
   * permissions can access detailed admin information, while basic admin lists
   * may be available to authenticated users.
   *
   * This operation integrates with the todo_app_admins table as defined in the
   * Prisma schema, incorporating all available admin fields and relationships.
   * The response includes admin summary information optimized for list
   * displays, with options to include additional details based on authorization
   * level.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for admin filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: ITodoAppAdmin.IRequest,
  ): Promise<IPageITodoAppAdmin.ISummary> {
    try {
      return await patchTodoAppAdminAdmins({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve details of a specific admin account.
   *
   * This endpoint returns detailed information about a specific admin account
   * identified by its unique adminId. The operation retrieves the complete
   * record from the todo_app_admins table and includes all non-sensitive
   * administrative details.
   *
   * The adminId parameter corresponds to the unique identifier field in the
   * todo_app_admins Prisma model. The operation validates that the requesting
   * user has sufficient privileges to access this administrative record,
   * requiring that the requester is an authenticated admin user.
   *
   * Response includes the admin's username, email address, account creation
   * timestamp, last login timestamp, and status flags. The operation does not
   * return any sensitive security data including password hashes,
   * authentication tokens, or session information.
   *
   * This endpoint supports auditing and accountability by providing complete
   * context about the admin account's lifecycle. Error responses occur if the
   * adminId does not correspond to an existing account or if the requester
   * lacks sufficient permissions.
   *
   * Note that this operation is specifically designed for administrative user
   * management and is inaccessible to regular users, maintaining strict
   * separation of privileges between regular users and system administrators.
   *
   * @param connection
   * @param adminId Unique identifier of the target admin account (global scope)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":adminId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppAdmin> {
    try {
      return await getTodoAppAdminAdminsAdminId({
        admin,
        adminId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an admin account by ID.
   *
   * This endpoint allows for updating the details of an existing admin account.
   * It provides the capability to modify administrative attributes such as
   * display name, contact information, permission levels, and other
   * account-related properties that are not related to authentication
   * credentials.
   *
   * The operation requires the adminId path parameter, which uniquely
   * identifies the admin account to be modified. Only accounts with
   * super-administrative privileges should be allowed to invoke this endpoint.
   *
   * Security considerations include strict authorization checks to ensure only
   * authorized administrators can modify other admin accounts, and audit
   * logging of all changes made to admin accounts. The system must prevent
   * modification of the admin's authentication credentials through this
   * endpoint; password or authentication changes should use separate, more
   * secure endpoints designed for credential updates.
   *
   * This operation directly interacts with the todo_app_admins table in the
   * Prisma schema, which contains the core administrative user data. Any
   * changes to the admin account's properties will be recorded in the system's
   * audit logs.
   *
   * @param connection
   * @param adminId Unique identifier of the target admin account
   * @param body Update payload containing admin properties to be modified
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":adminId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoAppAdmin.IUpdate,
  ): Promise<ITodoAppAdmin> {
    try {
      return await putTodoAppAdminAdminsAdminId({
        admin,
        adminId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete an admin account by ID.
   *
   * This endpoint permanently removes an admin account from the system. Upon
   * execution, all administrative privileges, access rights, and associated
   * data related to the specified admin account are irrevocably deleted.
   *
   * The operation requires the adminId path parameter, which uniquely
   * identifies the admin account to be deleted. This endpoint can only be
   * invoked by users with super-administrative privileges, and in most
   * production environments, requires additional confirmation mechanisms (like
   * two-factor authentication or multi-person approvals) before execution.
   *
   * Security considerations are critical for this operation as deletion of
   * admin accounts could severely impact system administration capabilities.
   * The system must enforce strict authorization checks to prevent unauthorized
   * deletion. All delete operations are logged to the todo_app_audit_logs table
   * for compliance and forensic analysis.
   *
   * This operation directly interacts with the todo_app_admins table in the
   * Prisma schema, removing the record entirely. There is no soft delete
   * mechanism for admin accounts, as administrative access must be completely
   * and permanently revoked upon deletion.
   *
   * After deletion, the admin's sessions are terminated, all related
   * authentication records are cleared, and any pending administrative tasks
   * are reassigned or canceled according to system policy.
   *
   * @param connection
   * @param adminId Unique identifier of the target admin account
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":adminId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoAppAdminAdminsAdminId({
        admin,
        adminId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
