import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { getTodoAppAdminAuditAuthLogs } from "../../../../../providers/getTodoAppAdminAuditAuthLogs";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { patchTodoAppAdminAuditAuthLogs } from "../../../../../providers/patchTodoAppAdminAuditAuthLogs";

import { IPageITodoAppAuthLog } from "../../../../../api/structures/IPageITodoAppAuthLog";
import { ITodoAppAuthLog } from "../../../../../api/structures/ITodoAppAuthLog";

@Controller("/todoApp/admin/audit/authLogs")
export class TodoappAdminAuditAuthlogsController {
  /**
   * Retrieve authentication audit logs.
   *
   * This operation fetches a list of authentication audit logs from the
   * todo_app_auth_logs table. The audit logs capture all authentication
   * attempts (successful and failed) in the system, providing a security record
   * of who tried to access the system and when.
   *
   * The requested data includes timestamp, client IP address, user agent,
   * authentication result (success/failure), username/email, and session
   * duration where applicable. Logs are sorted chronologically with the most
   * recent entries appearing first.
   *
   * This endpoint supports query parameters for filtering by date range,
   * authentication outcome, user, or IP address. For example, an admin might
   * query for failed login attempts over the last 24 hours to detect potential
   * brute force attacks.
   *
   * The operation is restricted to admin users only, as authentication logs
   * contain sensitive security information that should not be accessible to
   * regular users. Authorized administrators can use these logs for security
   * analysis, incident investigation, and system monitoring.
   *
   * The response format includes a paginated structure (IPageITodoAppAuthLog)
   * with pagination metadata and an array of log entries, each representing a
   * single authentication attempt from the todo_app_auth_logs table.
   *
   * @param connection
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async get(
    @AdminAuth()
    admin: AdminPayload,
  ): Promise<IPageITodoAppAuthLog> {
    try {
      return await getTodoAppAdminAuditAuthLogs({
        admin,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve paginated authentication logs.
   *
   * Retrieve a filtered and paginated list of authentication logs from the
   * todo_app_auth_logs table. This operation allows administrators to analyze
   * authentication patterns, identify suspicious login attempts, and monitor
   * system access.
   *
   * The operation supports comprehensive filtering by user identification (user
   * ID or email), date range (from/to), success status (success/failure), and
   * IP address. Results can be sorted by timestamp in ascending or descending
   * order with configurable page sizes.
   *
   * Security considerations include rate limiting to prevent enumeration
   * attacks and implicit authorization checks that ensure only users with
   * appropriate administrative privileges can access these logs. Sensitive
   * information such as password hashes are never included in responses.
   *
   * This operation integrates with the todo_app_auth_logs model as defined in
   * the Prisma schema, incorporating all available fields including user_id,
   * ip_address, success, created_at, and user_agent. The response includes only
   * necessary audit information optimized for monitoring and forensic
   * analysis.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for authentication
   *   log filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async patch(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: ITodoAppAuthLog.IRequest,
  ): Promise<IPageITodoAppAuthLog> {
    try {
      return await patchTodoAppAdminAuditAuthLogs({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
