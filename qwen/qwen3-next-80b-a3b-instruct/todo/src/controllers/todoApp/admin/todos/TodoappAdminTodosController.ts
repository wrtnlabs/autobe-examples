import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia from "typia";
import { deleteTodoAppAdminTodosTodoId } from "../../../../providers/deleteTodoAppAdminTodosTodoId";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";

@Controller("/todoApp/admin/todos/:todoId")
export class TodoappAdminTodosController {
  /**
   * Permanently delete a specific todo item.
   *
   * This operation permanently removes a specific todo item from the system
   * database. This is a hard delete operation that completely removes the
   * record from the todo_app_todos table without any possibility of recovery.
   *
   * The operation requires authentication and checks user ownership or
   * administrative privileges before execution. A user can only delete their
   * own todo items unless they have admin privileges. Admin users can delete
   * any todo item in the system.
   *
   * The todo item is identified by its unique todoId, which must match the id
   * field in the todo_app_todos table. The operation does not accept a request
   * body as the todo identifier is provided in the URL path.
   *
   * After successful deletion, the system returns a 204 No Content response
   * with no body. If the todo item does not exist, returns a 404 Not Found
   * response. Attempts to delete without proper authorization return 403
   * Forbidden.
   *
   * This operation does not trigger any audit log creation itself; audit logs
   * for deletion are created automatically by the system as a side effect of
   * the operation in the todo_app_audit_logs table.
   *
   * @param connection
   * @param todoId Unique identifier of the target todo item (UUID format) in
   *   the todo_app_todos table
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("todoId")
    todoId: string,
  ): Promise<void> {
    try {
      return await deleteTodoAppAdminTodosTodoId({
        admin,
        todoId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
