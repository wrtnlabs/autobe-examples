import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchTodoUserUsers } from "../../../../providers/patchTodoUserUsers";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { getTodoUserUsersUserId } from "../../../../providers/getTodoUserUsersUserId";
import { putTodoUserUsersUserId } from "../../../../providers/putTodoUserUsersUserId";
import { deleteTodoUserUsersUserId } from "../../../../providers/deleteTodoUserUsersUserId";

import { IPageITodoUser } from "../../../../api/structures/IPageITodoUser";
import { ITodoUser } from "../../../../api/structures/ITodoUser";

@Controller("/todo/user/users")
export class TodoUserUsersController {
  /**
   * Paginated search for todo_user accounts with advanced filters and privacy
   * compliance.
   *
   * Search and retrieve a paginated list of user accounts within the Todo List
   * Application.
   *
   * This endpoint allows administrators to perform advanced queries for users
   * based on unique email, soft deletion status, and various timestamp fields
   * such as account creation and update times. All filtering logic closely
   * follows the field definitions in the todo_user schema, ensuring operations
   * remain consistent with data privacy and security requirements.
   *
   * A key aspect of this operation is respect for user isolation and
   * right-to-be-forgotten compliance. Administrators can filter for accounts
   * flagged as soft-deleted via the deleted_at field. When reviewing results,
   * sensitive password hashes and internal identifiers are not exposed in the
   * default summary view. Related business rules and roles are enforced
   * strictly at the query and result-response level for maximum data security.
   *
   * Pagination is provided to efficiently support large user bases and
   * performance best practices. The operation is only available to users with
   * user-level access; no higher-privileged roles are defined in schema.
   *
   * @param connection
   * @param body Request body containing email filters, timestamp ranges, sort
   *   options, soft deletion filter, and pagination parameters for user
   *   search.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoUser.IRequest,
  ): Promise<IPageITodoUser.ISummary> {
    try {
      return await patchTodoUserUsers({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed attributes of a single todo_user account for user review.
   *
   * Fetch detailed information for a single user account in the Todo List
   * Application using the unique user identifier (UUID).
   *
   * The endpoint returns all critical account information including unique
   * email, account creation time, last update time, and soft deletion timestamp
   * (if applicable – for right-to-be-forgotten support). Access is strictly
   * scoped to users with 'user' role; no admin-level access is available per
   * schema. Password hash data is never exposed in responses.
   *
   * This operation helps users audit their individual account, review
   * historical modifications, and enforce system-wide privacy and security
   * policies. Only fields explicitly defined in the schema are presented, and
   * ownership/permissions are strongly enforced according to application rules.
   * Querying a user who is soft-deleted returns their record including the
   * deleted_at value; permanently erased users are not returned, resulting in a
   * not found error.
   *
   * @param connection
   * @param userId Primary key UUID of the user to retrieve. Must match the id
   *   field in the todo_user schema.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":userId")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
  ): Promise<ITodoUser> {
    try {
      return await getTodoUserUsersUserId({
        user,
        userId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update a user's account information (todo_user table).
   *
   * Update an existing user account's information, such as their email address
   * or password hash.
   *
   * This operation allows the modifying of the account's core details: the
   * unique email and password_hash. Email changes are validated for format and
   * uniqueness, ensuring there are no duplicates across all user accounts.
   * Password hashes must use secure cryptographic practices according to
   * policy, and raw passwords are never accepted. The updated_at field is
   * automatically set to the current timestamp on each modification.
   *
   * The operation references the todo_user table, leveraging the field-level
   * constraints as documented in the schema. The operation only permits
   * authenticated users or administrators to modify user data, ensuring account
   * isolation and privacy compliance. Invalid email formats, duplicated emails,
   * or insecure passwords will result in validation errors, and no changes will
   * be made unless all rules are satisfied.
   *
   * Security: Proper authorization is required—either the user updating their
   * own account or an administrator with appropriate privileges. Attempts to
   * update non-existent or soft-deleted accounts are rejected with a clear
   * error response. Related operations include account deletion (DELETE
   * /users/{userId}).
   *
   * @param connection
   * @param userId Unique identifier of the user account to be updated (primary
   *   key of todo_user).
   * @param body Fields to update for the user account (email, password_hash);
   *   must comply with uniqueness and security constraints.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":userId")
  public async update(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoUser.IUpdate,
  ): Promise<ITodoUser> {
    try {
      return await putTodoUserUsersUserId({
        user,
        userId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Soft-delete (flag as deleted) a user account (todo_user table).
   *
   * Mark a user account as deleted by updating the deleted_at timestamp (soft
   * delete), following data retention and privacy compliance requirements.
   *
   * This operation flags the target user account as deleted without actually
   * removing the record from the database, following GDPR and
   * right-to-be-forgotten standards where applicable. The deleted_at field is
   * set to the current timestamp, and the user will no longer be able to log in
   * or access any system functionality.
   *
   * Affected records remain in the database for audit and compliance,
   * supporting retention policies. Accessing or operating on soft-deleted
   * accounts results in rejection and clear error messaging. Related operations
   * include user update (PUT /users/{userId}). Only the user themselves or
   * administrators acting in compliance with security protocols can perform
   * this operation. Irreversible deletion (physical removal) must be handled by
   * a separate, privileged process if needed.
   *
   * @param connection
   * @param userId Unique identifier of the user account to be deleted (primary
   *   key of todo_user).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":userId")
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
  ): Promise<ITodoUser> {
    try {
      return await deleteTodoUserUsersUserId({
        user,
        userId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
