import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchTodoUserUsersUserIdSessions } from "../../../../../providers/patchTodoUserUsersUserIdSessions";
import { UserAuth } from "../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../decorators/payload/UserPayload";
import { getTodoUserUsersUserIdSessionsSessionId } from "../../../../../providers/getTodoUserUsersUserIdSessionsSessionId";

import { IPageITodoUserSession } from "../../../../../api/structures/IPageITodoUserSession";
import { ITodoUserSession } from "../../../../../api/structures/ITodoUserSession";

@Controller("/todo/user/users/:userId/sessions")
export class TodoUserUsersSessionsController {
  /**
   * Search and paginate your own authentication sessions (todo_user_sessions
   * table).
   *
   * Retrieve a paginated and filtered list of your own authentication sessions
   * by userId in the path. This is designed for ordinary users ("user" role) to
   * view their own session history for cross-device management, logout, or
   * security monitoring.
   *
   * The response provides comprehensive session activity records, including
   * connection context, IP address, and login/referrer URLs, so that users can
   * review past account access and notice suspicious activity. Search and
   * filtering is performed via criteria in the request body, allowing filtering
   * by creation date, active/expired status, or device/session attributes.
   * Pagination and sorting are also supported for efficiency.
   *
   * Security ensures a user may only view their own sessions (the userId must
   * match the authenticated user's id). All results are filtered accordingly,
   * and there is never visibility into other users' sessions.
   *
   * @param connection
   * @param userId Unique identifier of the user account (must be the currently
   *   authenticated user).
   * @param body Search, filtering, and pagination criteria for
   *   todo_user_sessions records of the user.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoUserSession.IRequest,
  ): Promise<IPageITodoUserSession.ISummary> {
    try {
      return await patchTodoUserUsersUserIdSessions({
        user,
        userId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about your own authentication session
   * (todo_user_sessions table).
   *
   * Retrieve full details of a specific authentication session belonging to the
   * requesting user, using both the userId and sessionId passed as path
   * parameters.
   *
   * The response contains all available session metadata, including time of
   * login, connection origin, referrer, and expiration. This operation allows
   * users to audit their own account usage and spot unauthorized logins or
   * forgotten sessions on other devices.
   *
   * Security is provided by restricting this endpoint to authenticated users,
   * and all responses are filtered so that only the owner's session details can
   * be accessed. UserId must match the authenticated identity.
   *
   * @param connection
   * @param userId Unique identifier of the user account (must be the currently
   *   authenticated user).
   * @param sessionId Unique identifier (UUID) of the target authentication
   *   session for the user.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<ITodoUserSession> {
    try {
      return await getTodoUserUsersUserIdSessionsSessionId({
        user,
        userId,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
