import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postTodoUserTodos } from "../../../../providers/postTodoUserTodos";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { patchTodoUserTodos } from "../../../../providers/patchTodoUserTodos";
import { getTodoUserTodosTodoId } from "../../../../providers/getTodoUserTodosTodoId";
import { putTodoUserTodosTodoId } from "../../../../providers/putTodoUserTodosTodoId";
import { deleteTodoUserTodosTodoId } from "../../../../providers/deleteTodoUserTodosTodoId";

import { ITodoTodo } from "../../../../api/structures/ITodoTodo";
import { IPageITodoTodo } from "../../../../api/structures/IPageITodoTodo";

@Controller("/todo/user/todos")
export class TodoUserTodosController {
  /**
   * Create a new todo item (todo_todos table) for the current user.
   *
   * Create a new todo task for the authenticated user in the personal todo
   * list.
   *
   * This operation allows the currently logged-in user to add a new todo item,
   * specifying a required title and an optional description. The system
   * enforces input validation for field presence (title), maximum allowed
   * lengths (255 for title, 1000 for description), and ensures the title is not
   * empty or whitespace-only. Titles are unique for each user, preventing
   * duplicate creation within one account. The completed status is set to false
   * by default; timestamps are managed automatically.
   *
   * Security is strictly enforced—the user must be authenticated, and the todo
   * is always assigned to the user's own account. Unauthorized or
   * unauthenticated creation attempts are denied. There is no possibility for
   * sharing or collaborative creation; all todos are strictly single-user and
   * private.
   *
   * If required fields are missing, validation fails, or constraints are
   * violated (such as title non-uniqueness per user), the operation returns
   * clear, actionable error messages. Only fields specified by requirements and
   * schema are accepted; extraneous input is rejected. No extra metadata is
   * stored or allowed.
   *
   * @param connection
   * @param body Details for the todo to create, including title (required, max
   *   255) and optional description (max 1000). Must not be empty or
   *   whitespace-only.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoTodo.ICreate,
  ): Promise<ITodoTodo> {
    try {
      return await postTodoUserTodos({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve a paginated, user-scoped list of todos from todo_todos.
   *
   * Retrieve a paginated list of todo tasks belonging to the authenticated
   * user.
   *
   * This operation allows a user to search and filter their personal todo items
   * using a set of advanced query parameters, such as keyword matching on the
   * todo title and filtering by completion status or creation date range. The
   * endpoint enforces that only the owning user's data is accessible, ensuring
   * privacy and data isolation as required by the underlying Prisma schema and
   * business requirements.
   *
   * Supports pagination and sorting by relevant fields (title, created_at,
   * completed) to optimize list display in client applications. Underlying
   * security design guarantees that all filters are scoped to the authenticated
   * user's record set. Related endpoints include creation (POST /todos), detail
   * retrieval (GET /todos/{todoId}), updating (PUT /todos/{todoId}), completion
   * toggling, and permanent erasure (DELETE /todos/{todoId}). Soft deletion is
   * not supported—deletions are always permanent per the schema.
   *
   * @param connection
   * @param body Filter and pagination parameters for searching the todos list.
   *   Only fields relevant to the authenticated user's own todos are
   *   supported.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoTodo.IRequest,
  ): Promise<IPageITodoTodo.ISummary> {
    try {
      return await patchTodoUserTodos({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detail of a specific todo by todo_todos primary key.
   *
   * Retrieve all details of a specific todo task, owned by the authenticated
   * user.
   *
   * This operation lets a user access complete information for a single todo
   * item using its UUID. It returns the full detail as per the todo_todos
   * schema including title, description, completion state, and
   * creation/update/completion timestamps. Business rules ensure that only the
   * owning user is allowed access, preventing data leaks or cross-user data
   * exposure.
   *
   * Appropriate errors are returned if the todo does not exist or if the user
   * lacks access. Related operations include list retrieval (PATCH /todos),
   * creation, modification, and permanent deletion. There is no soft-delete
   * mechanism—deleted todos are removed entirely per privacy policy.
   *
   * @param connection
   * @param todoId Unique identifier (UUID) for the todo_todos record to
   *   retrieve. Must belong to the requesting user.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":todoId")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
  ): Promise<ITodoTodo> {
    try {
      return await getTodoUserTodosTodoId({
        user,
        todoId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing todo item (todo_todos table) belonging to the current
   * user.
   *
   * Update a todo item that belongs exclusively to the authenticated user.
   *
   * This operation permits the user to change the title, description, or
   * completion status of an existing todo item, provided they are the sole
   * owner. The title must remain not empty, unique, and within length limits;
   * description changes are optional and may be set, cleared, or shortened as
   * needed (subject to constraints). Completion may be toggled freely—setting
   * or unsetting also manages the completed_at timestamp. Attempted
   * modifications by unauthorized users or to non-existent or non-owned todos
   * always result in forbidden or not found errors.
   *
   * Input is fully validated: title (required, non-empty, max 255, unique per
   * user), description (optional, max 1000), completed (boolean). The creation
   * timestamp remains fixed, while updated_at and completed_at are
   * system-managed. This operation strictly adheres to business rules for
   * privacy, ownership, and data integrity.
   *
   * Success returns the new state of the todo; all errors are precise and
   * actionable. No extra features, sharing, or collaborative edits are
   * permitted—operation is minimalist by design and schema.
   *
   * @param connection
   * @param todoId Unique identifier of the target todo item (owned by the
   *   authenticated user).
   * @param body Fields to update for the todo. Includes required title (max
   *   255), optional description (max 1000), and completed status (boolean).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":todoId")
  public async update(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoTodo.IUpdate,
  ): Promise<ITodoTodo> {
    try {
      return await putTodoUserTodosTodoId({
        user,
        todoId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a todo item from the todo_todos table.
   *
   * Delete a specific todo item associated with the currently authenticated
   * user. The operation requires the unique identifier of the target todo task
   * as a path parameter. Once invoked, the operation removes the todo task from
   * persistent storage permanently.
   *
   * Security enforcement ensures that only the owner of the todo (identified by
   * 'todo_user_id') or an authorized administrative actor can delete the
   * resource. No soft delete or archiving is performed; deletion is permanent,
   * as required by strict privacy rules and business policy in the Prisma
   * schema. All associated timestamps and metadata are lost upon deletion.
   *
   * Error scenarios include: trying to delete a non-existent or already-deleted
   * task (results in 404), attempting to delete a todo that does not belong to
   * the current user (results in 403), or providing an invalid or non-UUID ID
   * (results in 400). Related operations include creation, listing, updating,
   * and toggling the completion state of todos. This endpoint plays a critical
   * role in upholding user control over their own data lifecycle, in compliance
   * with privacy regulations.
   *
   * @param connection
   * @param todoId Unique identifier (UUID) of the todo item to be deleted.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":todoId")
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoUserTodosTodoId({
        user,
        todoId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
