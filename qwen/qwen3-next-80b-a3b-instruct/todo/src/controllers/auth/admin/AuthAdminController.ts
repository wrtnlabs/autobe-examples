import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthAdminJoin } from "../../../providers/postAuthAdminJoin";
import { AdminAuth } from "../../../decorators/AdminAuth";
import { AdminPayload } from "../../../decorators/payload/AdminPayload";
import { postAuthAdminLogin } from "../../../providers/postAuthAdminLogin";
import { postAuthAdminRefresh } from "../../../providers/postAuthAdminRefresh";
import { getAuthAdminProfile } from "../../../providers/getAuthAdminProfile";

import { ITodoListAdmin } from "../../../api/structures/ITodoListAdmin";

@Controller("/auth/admin")
export class AuthAdminController {
  /**
   * Registers a new administrative account using email and password. The
   * operation creates a todo_list_admin record with the provided email and
   * hashed password, sets email_verified_at to null (indicating unverified),
   * and initializes last_login_at to null. This endpoint is publicly accessible
   * to allow system administration setup. This operation requires no prior
   * authentication and is the only method to create a new admin account.
   *
   * Security considerations include requiring a strong password policy and
   * verifying that the email is not already registered. The system will not
   * send email verification in this implementation as there is no email
   * verification workflow defined in the schema.
   *
   * This operation directly relates to the todo_list_admin table and uses the
   * email and password_hash columns to store the new account data. The
   * resulting JWT token issued contains the admin's unique identifier and is
   * signed with the service's secret key.
   *
   * Related operations: login (follows join for first login), refresh
   * (maintains session after initial authentication).
   *
   * @param connection
   * @param body Payload containing registration information to create a new
   *   admin account.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: ITodoListAdmin.IJoin,
  ): Promise<ITodoListAdmin.IAuthorized> {
    try {
      return await postAuthAdminJoin({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticates an existing administrative user using email and password
   * credentials. Validates the email against the todo_list_admin table and
   * checks the password_hash field for a match using a secure hashing
   * algorithm.
   *
   * Upon successful validation, generates a new access token and refresh token.
   * Updates the last_login_at field in the todo_list_admin table to the current
   * timestamp for audit tracking.
   *
   * This endpoint is publicly accessible and is the standard method for
   * administrative users to initiate a session. If the email does not exist or
   * the password is incorrect, a 401 Unauthorized response is returned.
   *
   * Security practice includes rate limiting, input sanitization, and
   * protection against brute-force attacks. The system does not enforce email
   * verification on login as email_verified_at is optional in the schema.
   *
   * Related operations: join (creates account before login), refresh (renews
   * tokens after login).
   *
   * @param connection
   * @param body Payload containing login credentials (email and password) for
   *   authentication.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: ITodoListAdmin.ILogin,
  ): Promise<ITodoListAdmin.IAuthorized> {
    try {
      return await postAuthAdminLogin({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Exchanges a valid refresh token for a new access token and refresh token,
   * extending the user's session without requiring re-authentication.
   *
   * The operation validates the refresh token against the todo_list_tokens
   * table, ensuring it is unrevoked, unexpired, and belongs to an active admin
   * user. Upon validation, a new pair of tokens is issued and the old refresh
   * token is revoked.
   *
   * Updates to the todo_list_admin table (specifically last_login_at) are not
   * performed on refresh, as this endpoint is designed for session maintenance,
   * not re-authentication.
   *
   * This operation requires a valid refresh token in the request body and is a
   * critical part of the JWT-based authentication flow for administrative
   * users.
   *
   * Related operations: login (obtains initial refresh token), join (creates
   * account that can later be logged into).
   *
   * @param connection
   * @param body Payload containing the refresh token to be exchanged for new
   *   access and refresh tokens.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: ITodoListAdmin.IRefresh,
  ): Promise<ITodoListAdmin.IAuthorized> {
    try {
      return await postAuthAdminRefresh({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves the current authenticated admin's profile information. Returns
   * only publicly visible fields: email and last_login_at from the
   * todo_list_admin table. This endpoint is protected by the admin
   * authorizationActor, ensuring only authenticated admin users can access
   * their own data.
   *
   * This operation supports admin UIs and client applications that need to
   * display the current user's identity and last login time. The response does
   * not include sensitive fields like password_hash or email_verified_at to
   * maintain security.
   *
   * The email field is returned without modification as it is the primary
   * identifier.
   *
   * The last_login_at field provides a timestamp of the user's most recent
   * successful authentication, useful for security auditing.
   *
   * Related operations: login (authenticates to obtain access token), logout
   * (terminates session), updatePassword (can follow this profile retrieval if
   * password change is needed).
   *
   * @param connection
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get("profile")
  public async profile(
    @AdminAuth()
    admin: AdminPayload,
  ): Promise<ITodoListAdmin.ISummary> {
    try {
      return await getAuthAdminProfile({
        admin,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
