import { Controller, Ip } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthUserJoin } from "../../../providers/postAuthUserJoin";
import { postAuthUserLogin } from "../../../providers/postAuthUserLogin";
import { postAuthUserRefresh } from "../../../providers/postAuthUserRefresh";

import { ITodoAppUser } from "../../../api/structures/ITodoAppUser";

@Controller("/auth/user")
export class AuthUserController {
  /**
   * Register a new user account using email and password.
   *
   * This endpoint registers a new user account for the member actor. The
   * operation creates a record in the todo_app_users table using the provided
   * email and password. The schema confirms the existence of email (unique
   * string), hashed_password (string), and is_active (boolean) fields. Since no
   * other fields like name, phone_number, or created_at exist in the schema,
   * these cannot be included in the request. The user is initialized with
   * is_active: true, reflecting the business rule that all registered members
   * are active by default. No email verification or account confirmation flow
   * is supported, as no verification_token or email_verified_at fields exist in
   * the schema. This operation cannot be used for guest users, as the actor
   * kind is member and the schema has no guest-specific fields.
   *
   * @param connection
   * @param body Request body for user registration containing email and
   *   password.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoAppUser.ICreate,
  ): Promise<ITodoAppUser.IAuthorized> {
    try {
      return await postAuthUserJoin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate a user and issue access tokens.
   *
   * This endpoint authenticates a user by validating their email and password
   * against the todo_app_users table. The system checks for a matching record
   * with the provided email and confirms the hashed_password matches the input.
   * The schema contains email, hashed_password, and is_active fields; login
   * will fail if the email is not found, the password does not match, or if
   * is_active is false. No password reset, failed login tracking, or MFA fields
   * exist in the schema (e.g., no mfa_enabled, mfa_secret, or auth_attempts),
   * so these features are not supported. This operation produces a session
   * token that enables all subsequent authenticated requests. The operation is
   * designed to support only password-based authentication as specified by the
   * available schema structure.
   *
   * @param connection
   * @param body Request body containing email and password for authentication.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoAppUser.ILogin,
  ): Promise<ITodoAppUser.IAuthorized> {
    try {
      return await postAuthUserLogin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Renew access token using a valid refresh token.
   *
   * This endpoint refreshes an expired access token using a refresh token
   * issued during login or registration. While the todo_app_users table does
   * not contain refresh_token, refresh_expires_at, or similar fields, the
   * refresh mechanism is implemented using stateless JWT signature validation.
   * The server validates the freshness and validity of the refresh token’s
   * signature and claims (such as exp and sub). If valid, a new access token is
   * issued without re-authenticating credentials. This operation reflects a
   * standard JWT session renewal flow, compatible with the absence of
   * server-side refresh token storage in the schema. The system does not
   * implement token blacklist, rotation history, or revocation tracking because
   * the schema lacks support for these fields, and thus refresh token reuse or
   * compromise cannot be detected server-side.
   *
   * @param connection
   * @param body Request body containing the refresh token for token renewal.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: ITodoAppUser.IRefresh,
  ): Promise<ITodoAppUser.IAuthorized> {
    try {
      return await postAuthUserRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
