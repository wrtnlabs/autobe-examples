import { Controller, Ip } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthUserJoin } from "../../../providers/postAuthUserJoin";
import { postAuthUserLogin } from "../../../providers/postAuthUserLogin";
import { postAuthUserRefresh } from "../../../providers/postAuthUserRefresh";

import { ITodoUser } from "../../../api/structures/ITodoUser";

@Controller("/auth/user")
export class AuthUserController {
  /**
   * Register a new user in todo_user table, enforcing email uniqueness and
   * strong password policies.
   *
   * This endpoint supports account registration for new users in the Todo List
   * Application by creating a new row in the todo_user table.
   *
   * Requests must provide a valid, unique email address (see the 'email' field
   * in the schema: 'Unique email address for authentication and account
   * recovery. Must be unique across all users and adhere to standard email
   * formatting.') and a raw password for hashing and storage in the
   * 'password_hash' field ('Secure hash of the user's password. Stored using
   * strong cryptographic practices. Never stores raw passwords.').
   *
   * On successful registration, the new user's record is created with
   * associated timestamps: 'created_at' as the instant of creation,
   * 'updated_at' matching 'created_at', and a null 'deleted_at' field
   * indicating it is active. All session management, business rule enforcement,
   * and unique account creation logic are enforced here as described in the
   * requirements document.
   *
   * The endpoint does not integrate social login, phone verification, or
   * additional roles/profiles. Only direct, per-user sign-up is supported.
   *
   * If an email already exists, the endpoint returns a business-level
   * registration error (no technical leakage of user existence), enforcing the
   * uniqueness constraint described in the Prisma schema.
   *
   * This endpoint is the initial step for account creation; users must
   * subsequently authenticate via login with issued credentials and may request
   * token refresh when needed.
   *
   * @param connection
   * @param body Registration data with user email and password.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoUser.IJoin,
  ): Promise<ITodoUser.IAuthorized> {
    try {
      return await postAuthUserJoin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate a user from todo_user table and issue a JWT token if
   * credentials are valid.
   *
   * This endpoint enables registered users to authenticate by submitting their
   * email ('email' field, unique, mandatory in todo_user schema) and raw
   * password (checked against the 'password_hash' field using secure
   * verification).
   *
   * Upon successful verification, the system issues a JWT token as described in
   * the requirements, including userId claims and session timing based on
   * 'created_at'/'updated_at' timestamps. Only users with active, non-deleted
   * accounts ('deleted_at' must be null) may successfully log in.
   *
   * Failed login attempts for invalid credentials never disclose account
   * existence or technical errors. Errors are presented as uniform
   * authentication failures matching security guidelines.
   *
   * On successful authentication, the session follows strict rules: session
   * expiration after 30 days, log out/invalidation support, and user data
   * isolation as required by the business processes and permission matrix
   * documented.
   *
   * No role elevation, admin, or additional attributes are ever exposed via
   * this endpoint. All logic references the todo_user schema for registration,
   * credential checking, and session management.
   *
   * @param connection
   * @param body User login credentials: email and password.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoUser.ILogin,
  ): Promise<ITodoUser.IAuthorized> {
    try {
      return await postAuthUserLogin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh JWT authorization token for an authenticated todo_user session.
   *
   * This endpoint refreshes the JWT authorization token for an authenticated
   * user whose current session remains valid. It checks the refresh token's
   * association in the session system (either via sessions table or token
   * content referencing the todo_user primary key).
   *
   * The system validates session timing constraints (inactivity window, as
   * enforced by the 'created_at' and 'updated_at' fields of the todo_user
   * schema and session lifetime rules from requirements). On success, a new JWT
   * and refresh token are issued, not exposing underlying credential or user
   * details.
   *
   * This endpoint does not permit re-activation of deleted ('deleted_at' not
   * null) or invalid/expired user accounts. Uniform error responses are given
   * for expired or invalid tokens.
   *
   * Token refresh operations must precede any attempts to access Todo data if
   * the original session is expired.
   *
   * No account creation, update, or role adjustment occurs here. Solely
   * refreshes authorization on existing valid sessions per business and schema
   * rules.
   *
   * @param connection
   * @param body Refresh token submission for session renewal.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: ITodoUser.IRefresh,
  ): Promise<ITodoUser.IAuthorized> {
    try {
      return await postAuthUserRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
