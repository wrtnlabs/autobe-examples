import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthUserJoin } from "../../../providers/postAuthUserJoin";
import { UserAuth } from "../../../decorators/UserAuth";
import { UserPayload } from "../../../decorators/payload/UserPayload";
import { postAuthUserLogin } from "../../../providers/postAuthUserLogin";
import { postAuthUserRefresh } from "../../../providers/postAuthUserRefresh";

import { ITodoListUser } from "../../../api/structures/ITodoListUser";

@Controller("/auth/user")
export class AuthUserController {
  /**
   * Register a new user account with email and password.
   *
   * This registration endpoint creates a new user account in the todoList
   * system by storing user credentials in the todo_list_users table. The
   * operation uses the 'email' field for unique identification and the
   * 'password' field for authentication. Since the todo_list_users model
   * includes these required fields, the system can perform account creation.
   * The user actor is of type 'member', meaning they will have full CRUD access
   * to their own todo items after successful registration. The password will be
   * securely hashed before storage as per industry best practices for password
   * security. No additional fields are needed for basic registration since the
   * model only requires email and password for initial account creation.
   * Authentication will be handled via JWT tokens following the system's
   * security policy.
   *
   * @param connection
   * @param body Payload containing user registration details required to create
   *   a new account.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoListUser.ICreate,
  ): Promise<ITodoListUser.IAuthorized> {
    try {
      return await postAuthUserJoin({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate a user and obtain access and refresh tokens.
   *
   * This login endpoint authenticates a user by comparing the provided email
   * and password against the corresponding fields in the todo_list_users table.
   * The user actor is a 'member' with full access to their own todo items, and
   * authentication is mandatory to use the system. The 'email' field serves as
   * the unique identifier, while the 'password' field is cryptographically
   * verified. Since both fields exist in the Prisma schema, the system can
   * perform secure credential validation. Session management is handled via JWT
   * tokens, with refresh tokens enabling uninterrupted access without requiring
   * re-authentication. Passwords are stored using Bcrypt hashing for security.
   * The operation returns an authorized token payload that identifies the
   * authenticated user and enables access to protected resources.
   *
   * @param connection
   * @param body Payload containing user credentials for authentication.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoListUser.ILogin,
  ): Promise<ITodoListUser.IAuthorized> {
    try {
      return await postAuthUserLogin({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh access token using a valid refresh token.
   *
   * This refresh endpoint allows users to obtain a new access token using a
   * valid refresh token, extending their session without requiring
   * re-authentication with email and password. The operation verifies the
   * refresh token against the stored token in the todo_list_users table, which
   * has a corresponding refresh_token field defined in the schema. Since the
   * todo_list_users model includes the refresh_token field, this refresh
   * functionality can be implemented securely. The refresh token is bound to
   * the specific user account and has a longer expiration time than the access
   * token. After successful validation, a new access token is issued while the
   * refresh token remains valid until its expiration or revocation. This
   * approach follows standard JWT security patterns for maintaining user
   * sessions.
   *
   * @param connection
   * @param body Payload containing the refresh token to obtain a new access
   *   token.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoListUser.IRefresh,
  ): Promise<ITodoListUser.IAuthorized> {
    try {
      return await postAuthUserRefresh({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
