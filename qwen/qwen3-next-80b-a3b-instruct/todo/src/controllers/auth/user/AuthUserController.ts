import { Controller, Ip } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthUserJoin } from "../../../providers/postAuthUserJoin";
import { postAuthUserLogin } from "../../../providers/postAuthUserLogin";
import { postAuthUserRefresh } from "../../../providers/postAuthUserRefresh";

import { ITodoListUser } from "../../../api/structures/ITodoListUser";

@Controller("/auth/user")
export class AuthUserController {
  /**
   * Create a new member user account.
   *
   * This operation handles user registration by creating a new record in the
   * todo_list_users table. The incoming request includes email and plain-text
   * password, which are transformed server-side: the password is hashed using
   * bcrypt before storage, and a unique UUID is generated for the id field. The
   * createdAt timestamp is automatically set to the current date and time in
   * the Asia/Seoul timezone. The email field is validated for unique existence
   * before insertion (as defined by the unique index on todo_list_users.email).
   * The isActive flag is explicitly set to true during creation, as all new
   * users are active by default. The role field defaults to 'member', as
   * defined in the Prisma schema. No additional fields are included in the
   * request body because the todo_list_users schema does not have any other
   * required or nullable fields for registration beyond email and password.
   *
   * This operation is publicly accessible and does not require authentication
   * since it's for new user account creation. It is the first step in the
   * authentication workflow for member users.
   *
   * Associated Prisma schema field: todo_list_users.email (String, unique),
   * todo_list_users.hashedPassword (String), todo_list_users.createdAt
   * (DateTime), todo_list_users.isActive (Boolean), todo_list_users.role
   * (String, enum).
   *
   * @param connection
   * @param body Request payload for user registration
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoListUser.ICreate,
  ): Promise<ITodoListUser.IAuthorized> {
    try {
      return await postAuthUserJoin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate a member user and issue access & refresh tokens.
   *
   * This operation authenticates an existing member user by validating their
   * email and plain-text password against the records stored in the
   * todo_list_users table. The server looks up the user by email (which is
   * indexed and unique) and compares the provided password against the stored
   * bcrypt hash using a cryptographic comparison function.
   *
   * If authentication succeeds, the system generates two tokens: a short-lived
   * access token (valid for 15 minutes) and a long-lived refresh token (valid
   * for 7 days). The access token contains the user's id, email, and role in
   * the payload. The refresh token is stored as a hashed value in the
   * todo_list_users.refreshTokenHash field (and expiresAt timestamp is updated)
   * during this operation, as these fields are part of the user model and
   * explicitly designed for token management.
   *
   * The operation responds with a success status and the token payload if
   * authentication passes. If the email doesn't exist or the password hash
   * doesn't match, it returns a 401 Unauthorized error.
   *
   * This is the core authentication operation for member users, following the
   * principle of stateless authentication with JWT. It is publicly accessible
   * and does not require prior authentication.
   *
   * Associated Prisma schema field: todo_list_users.email (String, unique),
   * todo_list_users.hashedPassword (String), todo_list_users.refreshTokenHash
   * (String, nullable), todo_list_users.refreshTokenExpiresAt (DateTime,
   * nullable).
   *
   * @param connection
   * @param body Login credentials for user authentication
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoListUser.ILogin,
  ): Promise<ITodoListUser.IAuthorized> {
    try {
      return await postAuthUserLogin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh access token using a valid refresh token.
   *
   * This operation allows a client to obtain a new access token after the
   * current one expires, using a previously issued refresh token. The client
   * submits the refresh token (which is stored as a hashed value in the
   * todo_list_users.refreshTokenHash field) to this endpoint.
   *
   * The server verifies the refresh token by hashing the submitted value and
   * comparing it to the stored refreshTokenHash in the todo_list_users table.
   * It also checks that the corresponding refreshTokenExpiresAt timestamp has
   * not yet passed.
   *
   * If valid, a new access token is generated (valid for 15 minutes), and a new
   * refresh token is created, with its hash stored back to
   * todo_list_users.refreshTokenHash and its expiration time set in
   * todo_list_users.refreshTokenExpiresAt. The old refresh token is effectively
   * invalidated by replacing it.
   *
   * This operation is crucial for maintaining a persistent authentication
   * session without requiring the user to re-enter credentials. The client must
   * securely store and submit the refresh token with each refresh request.
   *
   * This endpoint remains accessible to authenticated users as long as they
   * possess a valid refresh token. It is a stateful operation because it
   * updates the user's record in the database.
   *
   * Associated Prisma schema field: todo_list_users.refreshTokenHash (String,
   * nullable), todo_list_users.refreshTokenExpiresAt (DateTime, nullable).
   *
   * @param connection
   * @param body Refresh token to extend the authenticated session
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: ITodoListUser.IRefresh,
  ): Promise<ITodoListUser.IAuthorized> {
    try {
      return await postAuthUserRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
