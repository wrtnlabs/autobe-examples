import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";

import { ITodoListUser } from "../../../../../api/structures/ITodoListUser";

@Controller("/auth/user/password/reset")
export class AuthUserPasswordResetController {
  /**
   * Initiates password reset flow for a registered user. Sends a password reset
   * token to the user's email address in todo_list_user table. The system
   * generates a cryptographically random token, stores it in the
   * password_reset_token field, and sets password_reset_expires_at to 2 hours
   * from now. An email with reset link containing the token is sent via
   * configured email service. This operation does not require authentication
   * and accepts any valid email registered in the system. After the token is
   * used, the token and expiry fields are cleared. This operation does not
   * change the password; it only triggers the email reset sequence. Related
   * operation is updatePassword to complete the reset with new credentials.
   *
   * @param connection
   * @param body Email address to send password reset instructions to.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async resetPassword(
    @TypedBody()
    body: ITodoListUser.IPasswordResetRequest,
  ): Promise<ITodoListUser.IPasswordResetInitiated> {
    body;
    return typia.random<ITodoListUser.IPasswordResetInitiated>();
  }
}
