import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthGuestJoin } from "../../../providers/postAuthGuestJoin";
import { GuestAuth } from "../../../decorators/GuestAuth";
import { GuestPayload } from "../../../decorators/payload/GuestPayload";
import { postAuthGuestRefresh } from "../../../providers/postAuthGuestRefresh";

import { ITodoListGuest } from "../../../api/structures/ITodoListGuest";

@Controller("/auth/guest")
export class AuthGuestController {
  /**
   * Enables guest users to register and become authenticated members via the
   * todo_list_guest schema.
   *
   * This API endpoint enables unauthenticated guest users to register and
   * become authenticated members of the todo list system.
   *
   * The operation creates a new user record based on the todo_list_guest Prisma
   * model. Once registered, the guest transitions from a temporary anonymous
   * state to a permanent authenticated member with full todo item management
   * capabilities. The system does not require initial password input as
   * credentials are generated internally and communicated via secure channels.
   *
   * The model is designed to support guest-to-member transition without
   * requiring prior knowledge or complex onboarding. Since the todo_list_guest
   * table exists, this registration flow is explicitly supported by the
   * database schema. No additional fields are needed beyond the base schema for
   * this operation.
   *
   * This is a critical first-step operation in the user lifecycle and must be
   * completed before any other account actions (like viewing or creating todo
   * items).
   *
   * The generated tokens adhere to JWT standards and are bound to the newly
   * created guest identity, allowing subsequent authentication via the login
   * and refresh endpoints.
   *
   * @param connection
   * @param body Registration data for creating a new guest account.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @GuestAuth()
    guest: GuestPayload,
    @TypedBody()
    body: ITodoListGuest.IJoin,
  ): Promise<ITodoListGuest.IAuthorized> {
    try {
      return await postAuthGuestJoin({
        guest,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Allows registered guest users to refresh their access tokens for ongoing
   * authentication.
   *
   * This API endpoint enables previously registered guest users to refresh
   * their access tokens, maintaining an active authentication session without
   * requiring re-entry of credentials.
   *
   * This operation is only available to users who have successfully completed
   * the join operation and hold a valid refresh token. The refresh token is
   * issued during the join process and stored securely in a cookie or secure
   * storage.
   *
   * The todo_list_guest table provides the necessary structure to validate
   * refresh tokens against legitimate registered users. When a refresh request
   * is received, the system validates the refresh token against the guest's
   * stored session information. This ensures that only legitimate users can
   * extend their session, preventing token reuse attacks.
   *
   * Since no passwords or additional authentication factors are required for
   * guest users after registration, the refresh operation is the only means to
   * maintain long-term authenticated access beyond the short-lived access
   * token. This design follows industry-standard token rotation practices.
   *
   * This operation is essential for user experience, allowing guests to
   * continue using the service without being logged out frequently after
   * initial registration.
   *
   * @param connection
   * @param body Refresh token submitted to renew access credentials.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @GuestAuth()
    guest: GuestPayload,
    @TypedBody()
    body: ITodoListGuest.IRefresh,
  ): Promise<ITodoListGuest.IAuthorized> {
    try {
      return await postAuthGuestRefresh({
        guest,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
