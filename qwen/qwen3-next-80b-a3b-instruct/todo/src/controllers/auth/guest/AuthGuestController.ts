import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthGuestJoin } from "../../../providers/postAuthGuestJoin";
import { GuestAuth } from "../../../decorators/GuestAuth";
import { GuestPayload } from "../../../decorators/payload/GuestPayload";
import { postAuthGuestRefresh } from "../../../providers/postAuthGuestRefresh";
import { getAuthGuest } from "../../../providers/getAuthGuest";

import { ITodoListGuest } from "../../../api/structures/ITodoListGuest";

@Controller("/auth/guest")
export class AuthGuestController {
  /**
   * Creates a temporary guest account for anonymous access to the public
   * landing page.
   *
   * This operation initializes a new guest session in the
   * todo_list_guest_sessions table. The guest account is not associated with
   * any persistent user data and exists only for the duration of the session.
   * The system uses the todo_list_guest table to track the existence of guest
   * entities, but no personal identifying information is stored.
   *
   * Guest accounts are designed for visitors to view the landing page without
   * requiring login credentials or personal registration. The account is
   * ephemeral and gets destroyed upon session termination.
   *
   * No schema fields such as email, password_hash, or security tokens are used
   * because guest users have no persistent identity in the system.
   *
   * This operation is the only way a guest can become associated with a session
   * state in the system, as they are otherwise completely anonymous.
   *
   * @param connection
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @GuestAuth()
    guest: GuestPayload,
    @TypedBody()
    body: ITodoListGuest.IJoin,
  ): Promise<ITodoListGuest.IAuthorized> {
    try {
      return await postAuthGuestJoin({
        guest,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refreshes the temporary guest session token to extend anonymous access
   * validity.
   *
   * This operation updates the todo_list_guest_sessions table with a new access
   * token and extends the session expiration time. The guest entity remains
   * linked to the session without requiring authentication credentials.
   *
   * The session is maintained through the todo_list_guest_sessions table which
   * tracks active guest sessions. No database fields associated with persistent
   * user identity (email, password, tokens) are involved.
   *
   * Refresh is necessary because guest sessions have limited lifespans; this
   * operation allows continued access to the public landing page without
   * re-registration.
   *
   * This operation only works with valid existing guest session tokens and
   * cannot create new identity. The guest user never authenticates with
   * passwords or personal information - the session is purely stateful and
   * temporary.
   *
   * @param connection
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @GuestAuth()
    guest: GuestPayload,
    @TypedBody()
    body: ITodoListGuest.IRefresh,
  ): Promise<ITodoListGuest.IAuthorized> {
    try {
      return await postAuthGuestRefresh({
        guest,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Provides public information accessible to anonymous guests without
   * authentication.
   *
   * This endpoint returns the public landing page data that guests can view
   * prior to any authentication. Since guest users have no persistent identity,
   * their authorization is null by nature.
   *
   * This operation reflects the system's state for unauthenticated visitors
   * based on the todo_list_guest table structure which only tracks session
   * existence without any data fields. No authentication fields are required or
   * allowed for this public access.
   *
   * It aligns with the business rule: guests can only access public information
   * without any form of credential validation.
   *
   * @param connection
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async index(
    @GuestAuth()
    guest: GuestPayload,
  ): Promise<ITodoListGuest.IPublic> {
    try {
      return await getAuthGuest({
        guest,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
