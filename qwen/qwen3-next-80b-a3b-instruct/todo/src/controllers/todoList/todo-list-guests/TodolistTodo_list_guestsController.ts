import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postTodoListTodoListGuests } from "../../../providers/postTodoListTodoListGuests";
import { putTodoListTodoListGuestsGuestId } from "../../../providers/putTodoListTodoListGuestsGuestId";
import { UserAuth } from "../../../decorators/UserAuth";
import { UserPayload } from "../../../decorators/payload/UserPayload";
import { deleteTodoListTodoListGuestsGuestId } from "../../../providers/deleteTodoListTodoListGuestsGuestId";

import { ITodoListGuest } from "../../../api/structures/ITodoListGuest";

@Controller("/todoList/todo-list-guests")
export class TodolistTodo_list_guestsController {
  /**
   * Create a new guest registration record for a user attempting to join the
   * application.
   *
   * This operation initiates the user registration process by creating a record
   * in the todo_list_guest table with the provided email address. The system
   * validates that the email address is properly formatted and hasn't been used
   * in a previous registration attempt (either active or deleted). Upon
   * successful creation, the system sends a verification email to the provided
   * address.
   *
   * The registration record includes the email address and creation timestamp.
   * The guest record remains active until the user completes registration
   * (creates a todo_list_users record) or the registration expires. If the
   * email has been used before, the system will return a 409 Conflict error.
   *
   * This operation represents the first step in the user onboarding journey and
   * is a prerequisite for creating a full user account.
   *
   * Security: This is a public endpoint accessible to unauthenticated users to
   * enable new user registration.
   *
   * Related operations: GET /todo-list-guests/{guestId} (retrieve registration
   * details)
   *
   * @param connection
   * @param body Email address for the new guest registration
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @TypedBody()
    body: ITodoListGuest.ICreate,
  ): Promise<ITodoListGuest> {
    try {
      return await postTodoListTodoListGuests({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update guest registration information.
   *
   * Update an existing guest registration record in the system.
   *
   * This operation allows modification of guest registration data before the
   * account is activated and converted to a full user account. Only pending
   * guest records (where deleted_at is null) can be updated. This includes
   * updating the email address, correcting registration information, or
   * resending verification emails.
   *
   * Security: Only the guest can update their own registration record using the
   * generated verification token. This is enforced by the business logic layer
   * using the guestId from the path parameter and the authentication token.
   *
   * This operation directly modifies the todo_list_guest table in the database.
   * The updated_at field is automatically set to the current timestamp upon
   * successful update.
   *
   * Note: This operation cannot convert a guest to a user. User conversion
   * happens via email verification, not through this endpoint.
   *
   * Related operations: DELETE /todo-list-guests/{guestId} to cancel
   * registration.
   *
   * Referenced Model: todo_list_guest
   *
   * @param connection
   * @param guestId Unique identifier of the guest registration record to
   *   update. This is a UUID that references a record in the todo_list_guests
   *   table.
   * @param body The updated information for the guest registration.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":guestId")
  public async update(
    @UserAuth()
    user: UserPayload,
    @TypedParam("guestId")
    guestId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoListGuest.IUpdate,
  ): Promise<ITodoListGuest> {
    try {
      return await putTodoListTodoListGuestsGuestId({
        user,
        guestId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete guest registration.
   *
   * Permanently delete a guest registration record from the system.
   *
   * This operation completely removes a guest's registration data from the
   * database using a hard delete. Unlike soft deletion that marks records as
   * deleted, this operation permanently erases the guest registration
   * information. This is used when a guest requests complete data removal from
   * the system.
   *
   * Security: Only the guest can delete their own registration record using the
   * generated verification token. This is enforced by the business logic layer
   * using the guestId from the path parameter and the authentication token.
   *
   * This operation directly removes a record from the todo_list_guest table in
   * the database. There is no recovery mechanism once this operation is
   * performed.
   *
   * Note: This operation is different from marking a guest record as inactive
   * (setting deleted_at). That is handled by the system for expired
   * registrations, not through this endpoint.
   *
   * Related operations: PUT /todo-list-guests/{guestId} to update guest
   * information before deletion.
   *
   * Referenced Model: todo_list_guest
   *
   * @param connection
   * @param guestId Unique identifier of the guest registration record to
   *   delete. This is a UUID that references a record in the todo_list_guests
   *   table.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":guestId")
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("guestId")
    guestId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoListTodoListGuestsGuestId({
        user,
        guestId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
