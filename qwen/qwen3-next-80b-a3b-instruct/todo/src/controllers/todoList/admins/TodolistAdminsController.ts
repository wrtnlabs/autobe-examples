import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia from "typia";
import { getTodoListAdminsEmail } from "../../../providers/getTodoListAdminsEmail";

import { ITodoListAdmin } from "../../../api/structures/ITodoListAdmin";

@Controller("/todoList/admins/:email")
export class TodolistAdminsController {
  /**
   * Retrieve the complete details of a specific administrator account from the
   * todo_list_admin table.
   *
   * This operation fetches a single admin user record based on the email
   * address provided in the path parameter. The email field in the
   * todo_list_admin table is defined with a unique constraint, ensuring each
   * administrator has a distinct email for identification. The response
   * includes all available fields: id, email, name, created_at, updated_at, and
   * status to provide a comprehensive view of the administrator account.
   *
   * The operation requires no request body as it's a simple retrieval
   * operation. Only authenticated admin users with proper authorization can
   * access this endpoint. User authentication is required via the system's JWT
   * authentication protocol to validate the requesting user's admin
   * privileges.
   *
   * This operation complements other admin-related endpoints like PATCH /admins
   * for listing administrators and DELETE /admins/{adminId} for deactivating
   * accounts. The returned email field can be used as a unique identifier for
   * related system operations.
   *
   * @param connection
   * @param email Unique email address of the target administrator (global
   *   scope)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @TypedParam("email")
    email: string,
  ): Promise<ITodoListAdmin> {
    try {
      return await getTodoListAdminsEmail({
        email,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
