import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia from "typia";
import { getTodoListUserActorsUserId } from "../../../../providers/getTodoListUserActorsUserId";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { patchTodoListUserActors } from "../../../../providers/patchTodoListUserActors";

import { ITodoListUser } from "../../../../api/structures/ITodoListUser";
import { IPageITodoListUser } from "../../../../api/structures/IPageITodoListUser";

@Controller("/todoList/user/actors")
export class TodolistUserActorsController {
  /**
   * Retrieve a specific user account by userId.
   *
   * Retrieve detailed information for a specific user account identified by
   * userId.
   *
   * This operation allows administrative users to view the complete profile
   * information of a specific user in the Todo List application. It returns
   * core user attributes including email, creation timestamp, and update
   * timestamp. This functionality supports user support requests, account
   * investigations, and system auditing.
   *
   * Security considerations: This endpoint is restricted to administrative
   * actors only. Regular users cannot access this endpoint, ensuring privacy
   * and data protection. The password_hash field is deliberately excluded from
   * the response to prevent exposure of authentication credentials, even to
   * administrators.
   *
   * The operation retrieves data directly from the todo_list_user table as
   * defined in the Prisma schema. The userId parameter corresponds to the
   * primary key field id in the todo_list_user table. This ensures data
   * integrity and precise record identification.
   *
   * Related operations: Search all users (PATCH /actors) provides bulk access
   * to multiple user records with filtering capabilities.
   *
   * @param connection
   * @param userId Unique identifier of the target user (primary key in
   *   todo_list_user table).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":userId")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string,
  ): Promise<ITodoListUser> {
    try {
      return await getTodoListUserActorsUserId({
        user,
        userId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve paginated list of user accounts.
   *
   * Perform comprehensive search, filtering, sorting, and pagination of user
   * accounts.
   *
   * This operation enables administrative users to discover and evaluate user
   * accounts in bulk using sophisticated query parameters. It supports advanced
   * filtering by email patterns, date ranges for account creation or
   * modification, and sorting by creation time, update time, or email
   * alphabetically. Results are paginated to ensure optimal performance when
   * dealing with large user bases.
   *
   * The operation queries the todo_list_user table directly, leveraging the
   * index on created_at and the unique constraint on email for optimized query
   * performance. This endpoint is designed for administrative workflows like
   * user management, compliance audits, and bulk operations.
   *
   * Security: Access is restricted to administrative actors only. Regular users
   * cannot perform searches across user accounts, protecting user privacy. The
   * operation returns the same set of non-sensitive fields as the individual
   * user lookup (at operation), ensuring consistent data exposure policies.
   *
   * This operation complements the individual user lookup (GET
   * /actors/{userId}) by providing a scalable way to discover user records in
   * bulk, making it ideal for user management dashboards and reporting tools.
   *
   * @param connection
   * @param body Search criteria including filters, pagination, and sorting
   *   parameters for user account discovery.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async search(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoListUser.IRequest,
  ): Promise<IPageITodoListUser> {
    try {
      return await patchTodoListUserActors({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
